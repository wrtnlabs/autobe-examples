import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postTodoListUserTasks } from "../../../../providers/postTodoListUserTasks";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoListUserTasks } from "../../../../providers/patchTodoListUserTasks";
import { getTodoListUserTasksTaskId } from "../../../../providers/getTodoListUserTasksTaskId";
import { putTodoListUserTasksTaskId } from "../../../../providers/putTodoListUserTasksTaskId";
import { deleteTodoListUserTasksTaskId } from "../../../../providers/deleteTodoListUserTasksTaskId";

import { ITodoListTask } from "../../../../api/structures/ITodoListTask";
import { IPageITodoListTask } from "../../../../api/structures/IPageITodoListTask";

@Controller("/todoList/user/tasks")
export class TodolistUserTasksController {
  /**
   * Create a new todo task by inserting a record into the todo_list_task table.
   * This operation allows an authenticated user to add a new task to their
   * to-do list by providing a text description of the task.
   *
   * When a task is created, the system automatically: 1) Associates the task
   * with the authenticated user via the JWT token, 2) Sets the created_at
   * timestamp to the current time, and 3) Sets the completed flag to false by
   * default. The description field is required and must contain non-empty
   * content.
   *
   * Security is enforced by requiring user authentication - only authenticated
   * users can create tasks, and the system automatically assigns the task to
   * the authenticated user's account. Input validation ensures the description
   * is not empty and does not exceed the maximum character limit defined in the
   * todo_list_task schema.
   *
   * After successful creation, the operation returns the complete task object
   * with its generated unique identifier. This operation supports the core user
   * workflow of adding new tasks to their to-do list, with immediate visibility
   * of the new task in their task list. Related operations: Get task (GET
   * /tasks/{taskId}) to view details of the created task, and delete task
   * (DELETE /tasks/{taskId}) to remove it if needed.
   *
   * @param connection
   * @param body Task description for the new todo item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTask.ICreate,
  ): Promise<ITodoListTask> {
    try {
      return await postTodoListUserTasks({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of user tasks with advanced filtering, searching,
   * and sorting capabilities.
   *
   * This operation allows users to search for tasks based on partial
   * description matches, filter by completion status, and sort results by
   * various criteria including creation date, update date, and task priority.
   * The operation supports pagination with configurable page size and
   * cursor-based navigation for optimal performance.
   *
   * The server enforces strict data isolation: users can only access tasks that
   * belong to their authenticated account. The user identification is derived
   * from the authentication token in the request header, not from any request
   * parameters, ensuring data privacy and security.
   *
   * The operation returns a paginated response with task summary information
   * optimized for performance, reducing payload size while including essential
   * fields like completion status, creation timestamp, and task description.
   * This is particularly beneficial for mobile clients with limited bandwidth.
   *
   * This operation references the todo_list_task model from the Prisma schema,
   * leveraging the user_id foreign key to ensure data isolation. It utilizes
   * the gin index on the description field for efficient full-text search
   * performance and the index on user_id and created_at for optimal sorting
   * performance.
   *
   * The request body accepts IToDoListTask.IRequest which includes fields for
   * search term, completion filter, and sorting direction. This design follows
   * RESTful patterns where complex queries are handled via request body rather
   * than query parameters for better maintainability and readability.
   *
   * @param connection
   * @param body Search, filter, and pagination parameters for retrieving user
   *   tasks.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTask.IRequest,
  ): Promise<IPageITodoListTask.ISummary> {
    try {
      return await patchTodoListUserTasks({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific todo task by its unique identifier from the
   * todo_list_task table. This operation allows an authenticated user to view
   * detailed information about a single task that they own. The task is
   * identified by its taskId parameter, which must correspond to an existing
   * task in the database.
   *
   * The operation returns the complete task object including the description,
   * completion status, and creation timestamp. The system validates that the
   * requesting user has ownership of the specified task before returning the
   * data. If the task does not exist or does not belong to the requesting user,
   * a 404 error is returned.
   *
   * This operation supports the user workflow of reviewing individual tasks in
   * detail, particularly when users need to reference specific task information
   * before making modifications or completing the task. The response includes
   * all fields defined in the todo_list_task model to provide comprehensive
   * information.
   *
   * Related operations: Create new task (POST /tasks) to create new tasks, and
   * delete task (DELETE /tasks/{taskId}) to remove tasks permanently.
   *
   * @param connection
   * @param taskId Unique identifier of the target todo task
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":taskId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("taskId")
    taskId: string,
  ): Promise<ITodoListTask> {
    try {
      return await getTodoListUserTasksTaskId({
        user,
        taskId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo list task identified by its unique taskId. This
   * operation allows users to modify the description or completion status of
   * their personal tasks. The task must exist and be owned by the authenticated
   * user.
   *
   * The request body contains an optional description field that will replace
   * the current task description if provided, and an optional completed field
   * that will toggle the task's completion status. When completed is set to
   * true, the system automatically sets completed_at to the current timestamp.
   * When completed is set to false, the system sets completed_at to null.
   *
   * Security: The system verifies that the authenticated user is the owner of
   * the task by comparing the user_id in the JWT token with the task's user_id
   * field in the database. Only the task owner can update the task. Rate
   * limiting applies to prevent abusive updates.
   *
   * The system validates the description field to ensure it is not empty after
   * trimming whitespace. If description is provided and is empty, the operation
   * fails with appropriate validation error. The completed field must be a
   * boolean value. All other fields in the request body are ignored.
   *
   * Upon successful update, the system updates the task's updated_at timestamp
   * to the current time. All other fields remain unchanged. The operation
   * returns the complete updated task object.
   *
   * Related operations: GET /tasks/{taskId} for retrieving task details, DELETE
   * /tasks/{taskId} for permanent removal.
   *
   * @param connection
   * @param taskId Unique identifier of the task to be updated. Must correspond
   *   to an existing task owned by the authenticated user.
   * @param body Update parameters for the todo list task. Contains optional
   *   fields to modify the task description and completion status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":taskId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("taskId")
    taskId: string,
    @TypedBody()
    body: ITodoListTask.IUpdate,
  ): Promise<ITodoListTask> {
    try {
      return await putTodoListUserTasksTaskId({
        user,
        taskId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a todo list task identified by its unique taskId. This
   * operation permanently removes the task from the system's dataset.
   *
   * This is not a soft delete operation (which would preserve data with a
   * deleted_at timestamp marked as non-null). This operation performs a true
   * hard delete, immediately and permanently removing all data associated with
   * the task. Once deleted, the task data cannot be recovered.
   *
   * Security: The system verifies that the authenticated user is the owner of
   * the task by comparing the user_id in the JWT token with the task's user_id
   * field in the database. Only the task owner can delete the task.
   *
   * Upon successful deletion, the system immediately removes the task from the
   * database. There is no confirmation step or recovery mechanism. The
   * operation returns no response body to indicate success.
   *
   * This deletion is irreversible. All related data (such as audit trails) are
   * preserved as necessary for system integrity, but the task record itself is
   * permanently removed from the primary data store.
   *
   * Related operations: PUT /tasks/{taskId} for updating tasks, GET
   * /tasks/{taskId} for retrieving task details.
   *
   * @param connection
   * @param taskId Unique identifier of the task to be permanently deleted. Must
   *   correspond to an existing task owned by the authenticated user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":taskId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("taskId")
    taskId: string,
  ): Promise<void> {
    try {
      return await deleteTodoListUserTasksTaskId({
        user,
        taskId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
