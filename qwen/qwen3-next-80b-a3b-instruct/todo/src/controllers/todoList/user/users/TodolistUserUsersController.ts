import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putTodoListUserUsersUserId } from "../../../../providers/putTodoListUserUsersUserId";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { deleteTodoListUserUsersUserId } from "../../../../providers/deleteTodoListUserUsersUserId";

import { ITodoListUser } from "../../../../api/structures/ITodoListUser";

@Controller("/todoList/user/users/:userId")
export class TodolistUserUsersController {
  /**
   * Update an existing user account with new profile information.
   *
   * This operation allows authenticated users to modify their own user account
   * details including email address and username. The operation validates that
   * the provided email and username are not already taken by another user, and
   * that the email follows a valid format. All modifications are tracked in the
   * system's audit logs with the user's ID and timestamp.
   *
   * The id field cannot be modified as it is the system-generated unique
   * identifier. The created_at field is set during user registration and cannot
   * be updated. The updated_at field is automatically updated by the system
   * when any modifications occur.
   *
   * Security considerations include ensuring that users can only modify their
   * own account by validating the JWT validation context against the user ID in
   * the path.
   *
   * Related operations: GET /users/{userId} for retrieving user information,
   * PATCH /users for search and filtering.
   *
   * @param connection
   * @param userId Unique identifier of the target user account to be updated
   *   (global scope)
   * @param body Fields to update for the user account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUser.IUpdate,
  ): Promise<ITodoListUser> {
    try {
      return await putTodoListUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes a user account from the todo_list system.
   *
   * This operation performs a hard delete of the specified user account,
   * completely removing all associated data from the database. The user record
   * and all associated todo items are permanently deleted and cannot be
   * recovered.
   *
   * The operation is initiated by providing the user's unique identifier in the
   * path parameter. This identifier corresponds to the UUID-based primary key
   * in the todo_list_user database model.
   *
   * Security: The operation requires authentication via JWT token, which is
   * used to identify the requester. Note: The system does not validate that the
   * requester owns the account being deleted - this is enforced in the service
   * layer.
   *
   * Data Integrity: All associated data owned by this user, such as todo items,
   * is deleted in cascade. The system ensures referential integrity by removing
   * all dependent records when the user account is deleted.
   *
   * This deletion operation is used for account termination and data removal
   * requests. There is no equivalent restore function available, as this system
   * design prioritizes data privacy and compliance with user data removal
   * requests.
   *
   * @param connection
   * @param userId Unique identifier of the target user account in UUID format.
   *   This corresponds to the primary key in the todo_list_user database
   *   model.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
