import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoListUserTodoItemsTodoId } from "../../../../providers/getTodoListUserTodoItemsTodoId";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { putTodoListUserTodoItemsTodoId } from "../../../../providers/putTodoListUserTodoItemsTodoId";
import { deleteTodoListUserTodoItemsTodoId } from "../../../../providers/deleteTodoListUserTodoItemsTodoId";
import { postTodoListUserTodoItems } from "../../../../providers/postTodoListUserTodoItems";
import { patchTodoListUserTodoItems } from "../../../../providers/patchTodoListUserTodoItems";

import { ITodoListTodo } from "../../../../api/structures/ITodoListTodo";
import { IPageITodoListTodo } from "../../../../api/structures/IPageITodoListTodo";

@Controller("/todoList/user/todoItems")
export class TodolistUserTodoitemsController {
  /**
   * Retrieve a specific todo item by its unique ID.
   *
   * Retrieve a specific todo item by its unique identifier for the
   * authenticated user.
   *
   * This operation fetches the complete details of a single todo item from the
   * todo_list_todos table based on the provided todoId path parameter. The
   * system enforces strict data ownership: only the user who created the todo
   * item can access it. If the requested todo item does not exist or belongs to
   * another user, the system returns a 404 Not Found response.
   *
   * The response includes all fields defined in the todo_list_todos model: id,
   * title, completed status, created_at, and updated_at timestamps. This
   * provides the user with the complete state of their todo item at the time of
   * retrieval.
   *
   * This operation supports use cases such as displaying individual todo
   * details in a UI, syncing data across devices, or preparing items for
   * editing. It complements the search operation that retrieves multiple todo
   * items with filtering capabilities.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item. This is a
   *   system-generated UUID that identifies the specific todo item across all
   *   users.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodo> {
    try {
      return await getTodoListUserTodoItemsTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo item by ID.
   *
   * Update an existing todo item by its unique identifier. This operation
   * allows authenticated users to modify the title or completion status of
   * their own todo items.
   *
   * The todo item must be owned by the authenticated user as enforced by the
   * todo_list_users_id foreign key relationship in the todo_list_todos table.
   * Only the title and completed fields can be modified - the creation
   * timestamp, update timestamp, and ID are not modifiable.
   *
   * The title must still adhere to the validation rules: at least one
   * non-whitespace character and no more than 200 characters. If the title is
   * omitted from the request, it remains unchanged. If the completed field is
   * omitted, its current value persists.
   *
   * The update timestamp is automatically updated to the current server time.
   * The operation will fail if the todo item does not exist, or if the user
   * attempting to update the item is not its owner.
   *
   * Related operations: Create todo item (POST /todoItems), List todo items
   * (GET /todoItems).
   *
   * @param connection
   * @param todoId Unique identifier of the todo item to update. This is the
   *   primary key from the todo_list_todos table.
   * @param body The fields to be updated in the todo item, including optional
   *   title and completion status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListTodo.IUpdate,
  ): Promise<ITodoListTodo> {
    try {
      return await putTodoListUserTodoItemsTodoId({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a specific todo item.
   *
   * This operation removes a todo item from the system permanently. Once
   * deleted, the todo item cannot be recovered and all associated data is
   * removed from the database.
   *
   * The operation requires a valid todo item identifier in the path parameter.
   * The user sending this request must be the owner of this todo item, as
   * verification is performed by the service layer based on the authenticated
   * user context.
   *
   * This is not a soft-delete operation - the record is completely removed from
   * the database. There is no archive, restore, or recovery mechanism available
   * for deleted todo items.
   *
   * The todo item owner is determined by the authenticated session. Only the
   * user who created the todo item can delete it, and deletion cannot be
   * performed by administrators or other users even if they have access to the
   * item ID.
   *
   * This operation is irreversible and will not return any response body. The
   * server will respond with HTTP 204 No Content on successful deletion or
   * appropriate error codes if the todo item does not exist or the user lacks
   * authorization.
   *
   * @param connection
   * @param todoId Unique identifier of the todo item to be deleted. This must
   *   be a valid, existing todo item ID belonging to the authenticated user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListUserTodoItemsTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new todo item for the authenticated user. This operation allows
   * users to create personal tasks that will be stored in their private todo
   * list. Each todo item must have a title describing the task, which must
   * contain at least one non-whitespace character and cannot exceed 200
   * characters.
   *
   * The created item is associated with the authenticated user via the userId
   * relationship in the todo_list_todos table. The completed field is
   * automatically set to false by default, and timestamps for creation and
   * update are populated with the current server time.
   *
   * The operation validates that the title is not empty and adheres to the
   * character length constraint. The authenticated user cannot create todo
   * items on behalf of other users due to the strict ownership model enforced
   * in the database.
   *
   * Related operations: Update todo item (PUT /todoItems/{todoId}), List todo
   * items (GET /todoItems).
   *
   * @param connection
   * @param body The data needed to create a new todo item, including the task
   *   title and completion status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.ICreate,
  ): Promise<ITodoListTodo> {
    try {
      return await postTodoListUserTodoItems({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated list of todo items with filtering and
   * sorting.
   *
   * Search and retrieve a filtered, paginated list of todo items for the
   * authenticated user.
   *
   * This operation enables users to query their todo items with advanced
   * filtering and sorting capabilities. Unlike a simple list retrieval, this
   * patch operation accepts a request body with search parameters including
   * pagination controls, sorting options, and filter criteria for completion
   * status.
   *
   * The search supports filtering by the 'completed' boolean field to retrieve
   * only pending or only completed items. Results can be sorted by created_at
   * timestamp in ascending or descending order. Pagination is fully
   * configurable with page size limitations (typically 10-100 items per page)
   * and cursor-based or offset-based pagination.
   *
   * The response returns a paginated result set containing metadata about the
   * total count, current page, and total pages, along with a subset of todo
   * item summary data. This operation is optimized for performance on large
   * datasets and supports client-side caching and incremental loading.
   *
   * This search functionality is crucial for users with many todo items,
   * allowing them to efficiently navigate their task list by status, with a
   * responsive user experience. It complements the detailed retrieval operation
   * that fetches a single item by its ID.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering todo
   *   items.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.IRequest,
  ): Promise<IPageITodoListTodo.ISummary> {
    try {
      return await patchTodoListUserTodoItems({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
