import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListUserSessions } from "../../../../providers/patchTodoListUserSessions";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoListUserSessionsSessionId } from "../../../../providers/getTodoListUserSessionsSessionId";
import { deleteTodoListUserSessionsSessionId } from "../../../../providers/deleteTodoListUserSessionsSessionId";

import { IPageITodoListUserSession } from "../../../../api/structures/IPageITodoListUserSession";
import { ITodoListUserSession } from "../../../../api/structures/ITodoListUserSession";

@Controller("/todoList/user/sessions")
export class TodolistUserSessionsController {
  /**
   * Retrieve a filtered and paginated list of user session records from the
   * todo_list_user_sessions table. This operation provides advanced search
   * capabilities for finding active, expired, or suspended authentication
   * sessions based on user ID, session status, creation date ranges, and token
   * metadata.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes, sorting by session creation time, last activity, or token
   * expiration, and filtering by session state (active, expired, revoked).
   * Results are optimized for administrative monitoring and security auditing
   * purposes.
   *
   * Security considerations include rate limiting for search operations on
   * session data and restricted access to sensitive authentication metadata.
   * Only authenticated administrators can perform this search to prevent abuse
   * and protect user privacy. The operation retrieves only non-sensitive
   * session identifiers and metadata without exposing JWT tokens or
   * authentication secrets.
   *
   * This operation interfaces directly with the todo_list_user_sessions
   * database table, incorporating all available session fields including
   * user_id, token, created_at, expires_at, last_activity, and status. The
   * response provides session summary information optimized for list displays,
   * with options to include detailed metadata for administrative investigation
   * purposes based on authorization level.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering user
   *   sessions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUserSession.IRequest,
  ): Promise<IPageITodoListUserSession.ISummary> {
    try {
      return await patchTodoListUserSessions({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed session information for an authenticated user's active
   * session.
   *
   * This operation retrieves a specific user session from the
   * todo_list_user_sessions database table, which stores authentication session
   * metadata for users. It is designed for use by authenticated users to verify
   * their current session state and potentially manage session activity.
   *
   * The session data includes metadata such as the session creation timestamp,
   * last activity time, and device information, allowing users to identify
   * suspicious activity or validate their authentication state. This operation
   * does not modify session data but provides readonly access to the session
   * record based on the session ID provided in the path parameter.
   *
   * Security considerations: Only the user associated with the session can
   * access it through JWT authentication. The system enforces that users cannot
   * access other users' sessions, even if they have the session ID. Session
   * records are automatically purged after a configurable expiration period for
   * security compliance.
   *
   * This operation works in conjunction with other authentication endpoints
   * such as login, logout, and token refresh. It is used primarily for session
   * management UI elements, allowing users to view and terminate their own
   * active sessions if needed. The operation returns detailed session
   * information to provide transparency to users about their authentication
   * state.
   *
   * Related operations: DELETE /sessions/{sessionId} (to terminate session),
   * POST /auth/login (to create session).
   *
   * @param connection
   * @param sessionId Unique identifier of the target user session (UUID
   *   format). This session ID was provided during authentication and is stored
   *   in the todo_list_user_sessions table as a primary key.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("sessionId")
    sessionId: string,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListUserSessionsSessionId({
        user,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently terminate and remove an authenticated user session from the
   * system.
   *
   * This operation deletes the session record from the todo_list_user_sessions
   * database table. Once a session is deleted, the associated JWT token becomes
   * instantly invalid, requiring the user to log in again to obtain a new
   * session.
   *
   * The session deletion is immediate and permanent, with no recovery possible.
   * This operation is used when users explicitly log out or when administrators
   * terminate sessions for security reasons.
   *
   * The sessionId parameter must exactly match a valid session record in the
   * database. Attempts to delete non-existent sessions will result in a 404
   * error.
   *
   * Security Note: Only the owner of the session (authenticated user) can
   * delete a session. Authentication and authorization checks are enforced at
   * the controller level before execution.
   *
   * @param connection
   * @param sessionId Unique identifier of the user session to be terminated.
   *   This must correspond to an existing session record in the
   *   todo_list_user_sessions table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await deleteTodoListUserSessionsSessionId({
        user,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
