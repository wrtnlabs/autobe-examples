import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListAdminAdmins } from "../../../../providers/patchTodoListAdminAdmins";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putTodoListAdminAdminsAdminId } from "../../../../providers/putTodoListAdminAdminsAdminId";
import { deleteTodoListAdminAdminsAdminId } from "../../../../providers/deleteTodoListAdminAdminsAdminId";

import { IPageITodoListAdmin } from "../../../../api/structures/IPageITodoListAdmin";
import { ITodoListAdmin } from "../../../../api/structures/ITodoListAdmin";

@Controller("/todoList/admin/admins")
export class TodolistAdminAdminsController {
  /**
   * Retrieve a filtered and paginated list of administrator accounts from the
   * system. This operation operates on the todo_list_admin table and provides
   * advanced search capabilities for finding administrator accounts based on
   * multiple criteria including partial username matching, email domain
   * filtering, registration date ranges, and account status.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Administrators can sort by creation date,
   * username, email, or other relevant fields in ascending or descending
   * order.
   *
   * Security considerations include rate limiting for search operations and
   * appropriate filtering of sensitive administrator information. Only
   * administrators with appropriate permissions can access detailed
   * administrator information, while basic administrator lists may be available
   * to authenticated users.
   *
   * This operation integrates with the todo_list_admin table as defined in the
   * database schema, incorporating all available administrator fields and
   * relationships. The response includes administrator summary information
   * optimized for list displays, with options to include additional details
   * based on authorization level.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for administrator
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.IRequest,
  ): Promise<IPageITodoListAdmin.ISummary> {
    try {
      return await patchTodoListAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing administrator account in the todo_list_admin table. This
   * operation requires the adminId path parameter to identify the specific
   * administrator record to be modified. The operation replaces all editable
   * fields of the administrator account including email and name. This is a
   * complete replacement operation (PUT semantics), requiring all editable
   * fields to be provided in the request body. The updated_at timestamp is
   * automatically set by the system.
   *
   * This endpoint is protected by admin-only authorization, preventing regular
   * users from modifying administrator accounts. Only users with the 'admin'
   * actor role can execute this update operation.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator account (UUID
   *   format). This must match the exact ID of an existing administrator record
   *   in the todo_list_admin table.
   * @param body Complete set of update fields for the administrator account.
   *   This includes all fields that can be modified: email and name. The
   *   request body must contain all required fields. The system performs
   *   complete replacement, not partial update.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListAdmin.IUpdate,
  ): Promise<ITodoListAdmin> {
    try {
      return await putTodoListAdminAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove an administrative account from the todo list system.
   *
   * This operation deletes a specific admin account from the todo_list_admin
   * database table. Administrative accounts have elevated system privileges and
   * are used for system management tasks. This deletion is permanent and cannot
   * be undone. The system will not recover the account or its associated data
   * upon deletion.
   *
   * Only other administrators have permission to perform this action. Once
   * deleted, the admin's access tokens are revoked and their account is
   * completely removed from the system. This operation is critical for security
   * and access control management and should be used with caution. Related
   * operations: View admin details (GET /admins/{adminId}), list all
   * administrators (GET /admins).
   *
   * @param connection
   * @param adminId Unique business identifier code of the target administrative
   *   account (global scope). This identifier is used to precisely locate and
   *   delete the specific admin account in the todo_list_admin table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string,
  ): Promise<ITodoListAdmin> {
    try {
      return await deleteTodoListAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
