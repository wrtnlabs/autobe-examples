import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchTodoListActorsUserIdSessions } from "../../../../providers/patchTodoListActorsUserIdSessions";
import { getTodoListActorsUserIdSessionsSessionId } from "../../../../providers/getTodoListActorsUserIdSessionsSessionId";

import { IPageITodoListUserSession } from "../../../../api/structures/IPageITodoListUserSession";
import { ITodoListUserSession } from "../../../../api/structures/ITodoListUserSession";

@Controller("/todoList/actors/:userId/sessions")
export class TodolistActorsSessionsController {
  /**
   * Retrieve a paginated list of active user sessions for a specific actor
   * (user) from the todo_list_user_sessions table. This operation provides
   * advanced filtering capabilities for user sessions based on status, creation
   * date range, and last activity timestamp.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Sessions can be sorted by creation_date,
   * last_active_at, or device_info in ascending or descending order. Filter
   * parameters allow finding sessions for specific devices, IP addresses, or
   * geographic locations.
   *
   * Security considerations include rate limiting for search operations and
   * ensuring that users can only access their own session data. This is
   * enforced at the business logic layer by validating that the requested
   * userId matches the authenticated user's identity in the JWT token.
   *
   * The system follows a 'user-managed' data pattern where sessions are
   * automatically created when users authenticate and are automatically cleaned
   * up after inactivity timeouts. Users can view their own active sessions for
   * security monitoring but cannot create, update, or delete sessions directly
   * - these are managed by the authentication system.
   *
   * This operation is critical for user security awareness, allowing users to
   * view and understand where their account is currently logged in, helping
   * them identify unauthorized access.
   *
   * @param connection
   * @param userId Unique identifier of the target user (actor) whose sessions
   *   are being retrieved (global scope)
   * @param body Search criteria and pagination parameters for filtering
   *   sessions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("userId")
    userId: string,
    @TypedBody()
    body: ITodoListUserSession.IRequest,
  ): Promise<IPageITodoListUserSession.ISummary> {
    try {
      return await patchTodoListActorsUserIdSessions({
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete details of a specific user session identified by its
   * unique session ID for the authenticated user. This operation provides
   * detailed information about a single session including device, location, and
   * authentication context.
   *
   * The session ID is a unique system-generated identifier for each
   * authentication session. Users can view their own session details to monitor
   * account activity and identify potential security issues. The system
   * validates that the requested session belongs to the authenticated user
   * before returning any data.
   *
   * This operation supports the security principle of user awareness, allowing
   * users to see the exact device information, IP address, and timestamp for
   * each active session. For security reasons, this endpoint does not support
   * batch retrieval or multiple session queries - each request is limited to a
   * single session identified by its unique ID.
   *
   * Session details are automatically cleared after inactivity timeouts or
   * user-initiated logout. Users cannot create, modify, or delete sessions
   * programmatically - these operations are handled automatically by the
   * authentication subsystem.
   *
   * Related operations: Search sessions (PATCH /actors/{userId}/sessions) to
   * get an overview of all sessions and this operation to view detailed
   * information for a specific session.
   *
   * @param connection
   * @param userId Unique identifier of the target user (actor) whose session is
   *   being retrieved (global scope)
   * @param sessionId Unique identifier of the target user session (global
   *   scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @TypedParam("userId")
    userId: string,
    @TypedParam("sessionId")
    sessionId: string,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListActorsUserIdSessionsSessionId({
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
