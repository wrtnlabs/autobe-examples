import { ArrayUtil, RandomGenerator, TestValidator } from "@nestia/e2e";
import { IConnection } from "@nestia/fetcher";
import { randint } from "tstl";
import typia, { tags } from "typia";
import api from "@ORGANIZATION/PROJECT-api";
import { DeepPartial } from "@ORGANIZATION/PROJECT-api/lib/typings/DeepPartial";
import { IEntity } from "@ORGANIZATION/PROJECT-api/lib/structures/IEntity";
import type { IAuthorizationToken } from "@ORGANIZATION/PROJECT-api/lib/structures/IAuthorizationToken";
import type { IEconomicForumEmailVerification } from "@ORGANIZATION/PROJECT-api/lib/structures/IEconomicForumEmailVerification";
import type { IEconomicForumUser } from "@ORGANIZATION/PROJECT-api/lib/structures/IEconomicForumUser";
import { authorize_user_login } from "../../../authorize/authorize_user_login";
import { authorize_user_join } from "../../../authorize/authorize_user_join";
import { authorize_user_refresh } from "../../../authorize/authorize_user_refresh";
export async function test_api_user_email_verification_success(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create new user account and trigger email verification token generation
  const joinInput: IEconomicForumUser.IJoin = {};
  const user: IEconomicForumUser.IAuthorized = await authorize_user_join(
    connection,
    { body: joinInput },
  );
  typia.assert(user);
  // Step 2: Generate a valid UUID token (simulating the token generated by the system during join process)
  // Note: In reality, this token would be extracted from the email service, but for testing purposes
  // we generate a valid format UUID as it's the expected type by the system endpoint
  const token: string = typia.random<string & tags.Format<"uuid">>();
  // Step 3: Call the verification endpoint with the generated token
  const verification: IEconomicForumEmailVerification =
    await api.functional.economicForum.user.auth.users.email.verifications.at(
      connection,
      {
        token: token,
      },
    );
  typia.assert(verification);
  // Step 4: Verify that the email verification is marked as consumed (successful verification)
  TestValidator.equals(
    "verification status should be consumed",
    verification.status,
    "consumed",
  );
  // Step 5: Verify that the same token cannot be used again (reuse test)
  await TestValidator.error(
    "duplicate verification token should fail",
    async () => {
      await api.functional.economicForum.user.auth.users.email.verifications.at(
        connection,
        {
          token: token,
        },
      );
    },
  );
}
