export async function test_api_article_retrieval_by_citizen_denied(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate citizen user
  const citizenConnection: api.IConnection = { host: connection.host };
  await authorize_citizen_join(citizenConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IEconomicBoardCitizen.IJoin,
  });
  // 2. Generate a random article ID - we don't need to create it, the access control
  // should deny before checking existence
  const articleId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  // 3. Attempt to retrieve article as citizen - should be denied with 403 Forbidden
  await TestValidator.httpError(
    "citizen denied access to administrator article endpoint",
    403,
    async () => {
      await api.functional.economicBoard.administrator.articles.at(
        citizenConnection,
        {
          articleId,
        },
      );
    },
  );
}
