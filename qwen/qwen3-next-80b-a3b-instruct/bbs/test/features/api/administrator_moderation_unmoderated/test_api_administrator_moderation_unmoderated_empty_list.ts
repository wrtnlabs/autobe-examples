export async function test_api_administrator_moderation_unmoderated_empty_list(
  connection: api.IConnection,
): Promise<void> {
  // Create administrator connection
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: typia.random<IEconomicBoardAdministrator.IJoin>(),
  });
  // Call the unmoderated endpoint
  const result =
    await api.functional.economicBoard.administrator.moderation.unmoderated.index(
      adminConnection,
    );
  typia.assert(result);
  // Validate that the list is empty
  TestValidator.equals("no flagged articles", result.data.length, 0);
}
