export async function test_api_admin_email_verification_success(
  connection: api.IConnection,
): Promise<void> {
  // Test a successful email verification endpoint with a known valid token
  // This is a contract test of the endpoint's success path response
  // In a real test environment, a pre-generated valid token exists for testing
  // We assume one such token is seeded and known to be valid: 'a1b2c3d4-e5f6-7890-1234-567890abcdef'
  // We are not testing the workflow of email generation, because it's not programmatically accessible
  // We are testing that the endpoint responds as specified when given a valid token
  // Define a known valid verification token
  // This token is assumed to exist in the test database
  // It represents a token that was successfully generated by a join operation
  // on a test admin account
  const validToken: string = "a1b2c3d4-e5f6-7890-1234-567890abcdef";
  // Call the email verification endpoint with the valid token
  // The endpoint returns IEconomicForumAdminEmailVerification, which is an empty object {}
  const result: IEconomicForumAdminEmailVerification =
    await api.functional.economicForum.admin.auth.admins.email.verifications.at(
      connection,
      { token: validToken },
    );
  // Verify the response type is IEconomicForumAdminEmailVerification (empty object)
  typia.assert(result);
  // Verify the response is indeed an empty object (as per design)
  TestValidator.equals(
    "verification response should be empty object",
    result,
    {},
  );
}
