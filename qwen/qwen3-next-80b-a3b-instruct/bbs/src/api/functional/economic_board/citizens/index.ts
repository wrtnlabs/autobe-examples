/**
 * Retrieve a citizen's profile by their unique code.
 *
 * This endpoint retrieves detailed profile information for a specific citizen
 * identified by their unique code. The operation queries the
 * economic_board_citizens table to find the citizen record matching the
 * provided code. The citizen code serves as a human-readable identifier that
 * replaces the internal UUID in URLs for better usability and
 * SEO-friendliness.
 *
 * The response includes the citizen's email address (for identification
 * purposes), status (active/suspended/banned), and creation/update timestamps.
 * This information allows other users to verify a citizen's identity and
 * account status before engaging with their content. The email is included as a
 * public identifier but is not used for communication purposes through this
 * endpoint.
 *
 * Security considerations: Public read access is permitted since this
 * information is not sensitive personally identifiable information. However, if
 * a citizen account is marked as deleted (deleted_at is not null), the
 * operation returns a 404 Not Found response to prevent access to anonymized
 * records. This ensures compliance with privacy regulations and content
 * governance policies.
 *
 * The operation is designed to be consumed by other citizens, moderators, and
 * external systems that need to reference citizens in a user-friendly way, such
 * as in post attribution, comment threads, or moderation reports. The citizen
 * code format is designed to be memorable and pronounceable, enhancing the
 * social nature of the economic board platform.
 *
 * @param props.connection
 * @param props.citizenCode Unique business identifier code of the target
 *   citizen (global scope). This code uniquely identifies a citizen across the
 *   entire economic board platform and is used as a human-readable alternative
 *   to UUID identifiers.
 * @path /economic-board/citizens/:citizenCode
 * @accessor api.functional.economic_board.citizens.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique business identifier code of the target citizen (global scope).
     * This code uniquely identifies a citizen across the entire economic
     * board platform and is used as a human-readable alternative to UUID
     * identifiers.
     */
    citizenCode: string;
  };
  export type Response = IEconomicBoardCitizen;

  export const METADATA = {
    method: "GET",
    path: "/economic-board/citizens/:citizenCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economic-board/citizens/${encodeURIComponent(props.citizenCode ?? "null")}`;
  export const random = (): IEconomicBoardCitizen =>
    typia.random<IEconomicBoardCitizen>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("citizenCode")(() => typia.assert(props.citizenCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Update a citizen's account information.
 *
 * This endpoint allows a citizen to update their account information identified
 * by their unique code. The operation updates records in the
 * economic_board_citizens table with the provided information. Only specific
 * fields can be updated through this operation: the citizen's display
 * preferences and profile metadata, but NOT the email address (which requires
 * separate verification) or password (which requires a dedicated password
 * change endpoint).
 *
 * Authentication is required for this operation through a JWT token that must
 * be associated with the citizenCode being updated. The system verifies that
 * the authenticated citizen matches the citizenCode in the path parameter to
 * prevent unauthorized modifications. This ensures that citizens can only
 * modify their own account information and cannot hijack other citizens'
 * accounts.
 *
 * When successful, the operation updates the updated_at timestamp to reflect
 * the modification. Security considerations include rate limiting to prevent
 * abuse and confirmation of email changes through a verification process. This
 * operation does not support changing the citizen's primary authorization
 * credentials (email and password hash), which are handled by separate
 * dedicated endpoints for security reasons.
 *
 * This operation serves the business need for citizens to maintain their
 * profile information and preferences on the economic board platform, while
 * maintaining strict security boundaries around sensitive authentication data.
 * The write operation is intentionally restricted to prevent credential
 * compromise and ensure account integrity.
 *
 * @param props.connection
 * @param props.citizenCode Unique business identifier code of the target
 *   citizen (global scope). This code uniquely identifies a citizen across the
 *   entire economic board platform and is used as a human-readable alternative
 *   to UUID identifiers.
 * @param props.body Update data for the citizen account including only
 *   permitted fields such as display preferences and metadata.
 * @path /economic-board/citizens/:citizenCode
 * @accessor api.functional.economic_board.citizens.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
