/**
 * Registers a new admin account in the discussion board system. This operation
 * creates a new admin entity in the discussion_board_moderator table with
 * initial authentication credentials.
 *
 * The operation requires a valid email address to be provided in the request
 * body, which will be verified against the discussion_board_users table to
 * ensure uniqueness. The password field will be hashed using bcrypt before
 * storage in the discussion_board_moderator table. The admin's account will be
 * initialized with default permissions for content moderation and user
 * reporting.
 *
 * This operation is distinct from user registration (join for citizen actors)
 * and is specifically designed for system administrators who require elevated
 * privileges to manage content, review reports, and suspend users. The admin
 * account creation process includes additional background verification steps
 * that are not available to regular citizens.
 *
 * All admin accounts created through this endpoint will have immediate access
 * to moderation tools within the system. The registration process enforces
 * strong password policies and requires email verification before the account
 * can be fully activated.
 *
 * @param props.connection
 * @param props.body Request body containing admin registration information.
 *   Defines the required fields for creating a new admin account, including
 *   email address and password. The email field references the
 *   discussion_board_users table for unique verification, and the password
 *   field must meet the system's strength requirements.
 * @setHeader token.access Authorization
 *
 * @path /auth/admin/join
 * @accessor api.functional.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
