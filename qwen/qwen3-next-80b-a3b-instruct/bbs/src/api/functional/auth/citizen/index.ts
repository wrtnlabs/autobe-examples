/**
 * Register a new citizen user and issue initial authentication tokens.
 *
 * This endpoint registers a new citizen user in the political discussion forum
 * by creating an entry in the political_forum_citizens table. The process
 * verifies that the provided email is not already registered and ensures the
 * password meets complexity requirements. Upon successful registration, the
 * system generates both access and refresh JWT tokens as specified by the
 * authentication strategy.
 *
 * The implementation references the following fields from the
 * political_forum_citizens schema: email (required, unique), password_hash
 * (required, stored as hashed value), display_name (optional, defaulted to
 * email username if not provided), created_at (automatically set by database),
 * and last_login_at (initialized to null). Additional fields like
 * email_verified and two_factor_enabled are set to false by default, requiring
 * subsequent verification steps.
 *
 * The registration process includes a built-in validation that prevents
 * duplicate emails and enforces password security policies. After creating the
 * user record, the system immediately generates a session entry in
 * political_forum_citizen_sessions with the initial refresh token, which is
 * returned to the client with the access token.
 *
 * The security model ensures that newly registered users have their permissions
 * correctly scoped to citizen capabilities only, with no administrative or
 * moderation privileges. This registration endpoint is publicly accessible to
 * allow new users to join the platform without requiring prior authentication.
 *
 * Related operations include POST /auth/citizen/login for subsequent
 * authentication and POST /auth/citizen/refresh for token renewal after the
 * access token expires.
 *
 * @param props.connection
 * @param props.body Registration data for creating a new citizen user account
 * @setHeader token.access Authorization
 *
 * @path /auth/citizen/join
 * @accessor api.functional.auth.citizen.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
