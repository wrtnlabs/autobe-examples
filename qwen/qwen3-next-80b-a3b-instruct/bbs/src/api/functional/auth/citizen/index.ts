/**
 * Registers a new citizen account in the economic board system.
 *
 * This endpoint allows a new citizen to register an account on the economic
 * board platform using their email and password. The registration process
 * creates a new record in the economic_board_citizens table with the provided
 * email, password, and optional display_name. The email field is required and
 * must be unique across all records as enforced by the unique constraint in the
 * database schema. Password is stored in hashed format. display_name is
 * optional, and if not provided, will be null. Upon successful registration,
 * the system generates both access and refresh tokens for subsequent
 * authentication. The created_at timestamp is automatically set to the current
 * server time. This operation does not require prior authentication since it's
 * for new account creation. The refresh token is issued with a longer lifespan
 * to allow token renewal. This operation directly corresponds to the creation
 * of records in the economic_board_citizens table and must be used before any
 * other authenticated operations.
 *
 * @param props.connection
 * @param props.body Request payload for citizen account registration. Contains
 *   email (required), password (required), and display_name (optional). Email
 *   field maps to the email column in economic_board_citizens table, password
 *   maps to the password column, and display_name maps to the display_name
 *   column. Email must be unique as constrained by unique index in the
 *   database.
 * @setHeader token.access Authorization
 *
 * @path /auth/citizen/join
 * @accessor api.functional.auth.citizen.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
