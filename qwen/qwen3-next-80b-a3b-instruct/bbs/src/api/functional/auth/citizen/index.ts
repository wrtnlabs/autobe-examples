/**
 * Register a new citizen user for the discussion board system.
 *
 * This API endpoint handles the registration of new citizen users for the
 * discussion board system. When a user submits their email and password, the
 * system creates a new record in the discussion_board_citizens table with the
 * provided email and password_hash values. The email_verified flag is set to
 * false by default, requiring the user to verify their email before they can
 * create posts or comments. The operation strictly follows the schema of the
 * discussion_board_citizens table which contains the necessary fields: email
 * (unique), password_hash, and email_verified. The email must be unique and
 * follow standard email format, while the password_hash is stored as a hashed
 * value created from the provided password. This registration process ensures
 * that only users with verified email addresses can participate in discussions,
 * maintaining system integrity and accountability. The operation is designed to
 * be public and accessible without authentication, allowing any user to
 * initiate account creation.
 *
 * Implementation is based directly on the discussion_board_citizens schema
 * fields: email (mandatory, unique), password_hash (mandatory), and
 * email_verified (boolean, default false). No other fields from the table are
 * used as they are not relevant to the registration process. The system will
 * validate that the email format is correct and that the password meets minimum
 * security requirements before creating the record.
 *
 * This registration flow is specifically for citizen users as defined in the
 * business requirements, and it aligns with the citizen actor's characteristics
 * which require email verification before posting or commenting. The operation
 * is named 'join' as per the standard naming convention for user registration
 * in authentication systems. The response will include a JWT token with the
 * user's ID and role (citizen) upon successful registration, even though the
 * account is not yet verified, allowing the user to proceed to verification.
 *
 * Security considerations include ensuring password hashing is performed
 * properly before storage, validating email format against RFC standards, and
 * ensuring the email field is unique before creation to prevent duplicate
 * accounts. The operation does not use soft delete functionality as account
 * deletion is handled separately.
 *
 * Related operations include the login endpoint which authenticates registered
 * users with their credentials, and the refresh endpoint which allows token
 * renewal. The verify email endpoint (not created here as it's handled by email
 * system) would be the next step in this workflow to enable posting
 * capabilities.
 *
 * @param props.connection
 * @param props.body Request body containing registration data for a new citizen
 *   user. Includes the email address and password required to create a citizen
 *   account in the discussion_board_citizens table. The email field stores the
 *   user's email address which must be unique, and the password field contains
 *   the plain text password that will be hashed and stored as password_hash in
 *   the database.
 * @setHeader token.access Authorization
 *
 * @path /auth/citizen/join
 * @accessor api.functional.auth.citizen.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
