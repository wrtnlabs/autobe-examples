import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconomicBoardModerator } from "../../../structures/IEconomicBoardModerator";

/**
 * Renew the moderator's access token using a valid refresh token.
 *
 * This API operation enables the moderator to obtain a new access token using a
 * previously issued refresh token, without requiring re-authentication via
 * email and password. The operation validates that the refresh token matches a
 * valid, unexpired, and non-blacklisted token in the system's secure token
 * storage. This implementation is consistent with the
 * economic_board_moderator_sessions table, which tracks active sessions, but
 * this operation does not directly query or update the sessions table.
 *
 * The refresh mechanism is designed as a stateless, token-based authentication
 * extension. The system maintains a list of valid refresh tokens in its secure
 * token store, and this endpoint validates the presented refresh token against
 * that list. Upon validation, a new access token is issued with the same
 * moderator identity claims (including the role and id) and a short expiration
 * (typically 15-30 minutes). The refresh token itself is not renewed unless the
 * client explicitly requests a rotation (which would require a separate
 * endpoint).
 *
 * Security considerations include token rotation policies, mandatory refresh
 * token expiration (e.g., 7 days), and token blacklisting on password changes
 * or account deactivation. This endpoint must be protected against brute force
 * attacks through rate limiting and should respond with generic errors (e.g.,
 * "invalid refresh token") to prevent enumeration attacks. The client must
 * present the exact refresh token issued during login, and any alteration of
 * the token will result in immediate rejection.
 *
 * Related operations: /auth/moderator/login (source of refresh token),
 * /auth/moderator/join (account creation, prerequisite for token issuance), and
 * /moderator/logout (explicit refresh token revocation).
 *
 * @param props.connection
 * @param props.body Request payload containing a valid refresh token issued
 *   during login.
 * @setHeader token.access Authorization
 *
 * @path /auth/moderator/refresh
 * @accessor api.functional.auth.moderator.refresh
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function refresh(
  connection: IConnection,
  props: refresh.Props,
): Promise<refresh.Response> {
  const output: refresh.Response =
    true === connection.simulate
      ? refresh.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...refresh.METADATA,
            path: refresh.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace refresh {
  export type Props = {
    /** Request payload containing a valid refresh token issued during login. */
    body: IEconomicBoardModerator.IRefresh;
  };
  export type Body = IEconomicBoardModerator.IRefresh;
  export type Response = IEconomicBoardModerator.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/moderator/refresh",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/moderator/refresh";
  export const random = (): IEconomicBoardModerator.IAuthorized =>
    typia.random<IEconomicBoardModerator.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: refresh.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: refresh.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
