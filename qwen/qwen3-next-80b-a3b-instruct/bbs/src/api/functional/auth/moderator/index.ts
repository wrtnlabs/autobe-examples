/**
 * Creates a new moderator account in the system. This operation is initiated by
 * administrators during moderator onboarding and sets up the core identity for
 * a new moderator. The email field is required and must be unique in the
 * economic_board_moderators table. The password_hash field is stored using
 * bcrypt and never exposed in responses.
 *
 * This operation leverages the design characteristics of the
 * economic_board_moderators table, specifically the email and password_hash
 * fields which are marked as required and populated during account creation.
 * The account is initially created with status 'active' and deleted_at set to
 * null.
 *
 * This operation follows the same security model as user registration, but is
 * restricted to administrative onboarding workflows rather than public
 * self-signup.
 *
 * No other authentication-related operations are required for the moderator
 * actor, as the Prisma schema does not include fields for password reset, email
 * verification, or two-factor authentication.
 *
 * This operation has no prerequisites as it is the primary entry point for
 * moderator account creation.
 *
 * @param props.connection
 * @param props.body Required information for creating a new moderator account,
 *   including a unique email address and a securely hashed password.
 * @setHeader token.access Authorization
 *
 * @path /auth/moderator/join
 * @accessor api.functional.auth.moderator.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
