/**
 * Permanently remove a discussion post from the forum. This operation deletes
 * the post record from the economic_forum_posts table and all associated child
 * records including post attachments and post reports.
 *
 * This is a hard delete operation, not a soft delete. The record is permanently
 * removed from the database and cannot be recovered. This functionality is
 * exclusively available to system administrators as defined by the user actor
 * model with admin permissions.
 *
 * The operation requires proper authorization - only users with admin
 * privileges can execute this action. The system will automatically log this
 * administrative action in the economic_forum_system_audits table for
 * compliance and tracking purposes.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the target post to be deleted. This
 *   is the UUID primary key from the economic_forum_posts table.
 * @x-autobe-specification Delete the post record from economic_forum_posts table using the provided postId identifier. Validate that the authenticated user has admin privileges before deletion. Return the deleted post object with all fields populated as confirmation. Do not perform soft delete; remove the record permanently from the database. Log this deletion event in economic_forum_system_audits table with actor context and timestamp.
 * @path /economicForum/admin/posts/:postId
 * @accessor api.functional.economicForum.admin.posts.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<erase.Response> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the target post to be deleted. This is the UUID
     * primary key from the economic_forum_posts table.
     */
    postId: string & tags.Format<"uuid">;
  };
  export type Response = IEconomicForumPost;

  export const METADATA = {
    method: "DELETE",
    path: "/economicForum/admin/posts/:postId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicForum/admin/posts/${encodeURIComponent(props.postId ?? "null")}`;
  export const random = (): IEconomicForumPost =>
    typia.random<IEconomicForumPost>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
