export async function verify(
  connection: IConnection,
  props: verify.Props,
): Promise<void> {
  return true === connection.simulate
    ? verify.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verify.METADATA,
          path: verify.path(props),
          status: null,
        },
      );
}
