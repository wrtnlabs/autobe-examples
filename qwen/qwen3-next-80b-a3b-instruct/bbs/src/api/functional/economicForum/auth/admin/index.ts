/**
 * Register a new system administrator account. This operation creates an admin
 * record in the economic_forum_admins table with initial fields: email,
 * password_hash, and created_at. The email_verified_at field is set to null
 * initially, requiring email verification before full access. The
 * password_reset_token field is initialized as null. The operation requires a
 * request body with email and password fields as defined in IAdmin.IJoin
 * schema.
 *
 * Upon success, returns a token with access and refresh tokens in
 * IAdmin.IAuthorized format, establishing initial admin authentication session.
 * The last_login_at field remains null until first successful login.
 *
 * This operation is publicly accessible but requires valid email format and
 * password strength as enforced by application logic. The database triggers
 * ensure email uniqueness and password hashing.
 *
 * This operation is mandatory for all new admin accounts and must be called
 * before any other admin operations except login and refresh.
 *
 * Followed by: After successful join, the admin must verify their email by
 * calling /auth/admin/email/verify before accessing sensitive administrative
 * functions.
 *
 * @param props.connection
 * @param props.body Data required to register a new admin account.
 * @setHeader token.access Authorization
 *
 * @x-autobe-specification Creates a new admin record with email and encrypted password. Sends email verification token to provided email. Hashes password using bcrypt. Sets created_at to current timestamp. Initializes email_verified_at and last_login_at as null. password_reset_token remains null. Returns access and refresh tokens. Validates email format and password strength before creation.
 * @path /economicForum/auth/admin/join
 * @accessor api.functional.economicForum.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
