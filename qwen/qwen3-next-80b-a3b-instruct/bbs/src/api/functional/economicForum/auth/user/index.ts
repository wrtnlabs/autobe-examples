/**
 * The refresh operation allows a user to obtain a new short-lived access token
 * using a valid, unexpired refresh token present in their HTTP-only cookie
 * storage. This operation extends user sessions without requiring
 * re-authentication.
 *
 * The refresh token must be provided either in a header (Authorization: Bearer)
 * or a secure HTTP-only cookie. This token is validated against entries in the
 * economic_forum_user_sessions table, checking its existence, expiration, and
 * revocation status. If the refresh token has been revoked, used multiple
 * times, expired, or is invalid, the system responds with a 401 Unauthorized
 * and mandates re-login.
 *
 * Upon successful validation, a new access token and refresh token are
 * generated; the old refresh token is marked as revoked in the database to
 * prevent replay attacks. The new tokens are returned in the response body and
 * concurrently stored in new HTTP-only cookies. This pattern enforces rolling
 * refresh tokens for enhanced security.
 *
 * This operation is crucial for maintaining seamless user experience during
 * extended usage of the application. It is protected against CSRF and
 * stolen-token attacks through the secured cookie mechanism. This operation is
 * accessed only after successful login or join, and must not depend on any
 * prerequisite for authentication state.
 *
 * Related operations: login (initial authentication), join (first-time
 * registration), and logout (explicit session termination).
 *
 * @param props.connection
 * @param props.body Refresh token for renewing the access token.
 * @setHeader token.access Authorization
 *
 * @x-autobe-specification Validate refresh token from request header. Check if refresh token exists in economic_forum_user_sessions and is not expired. Generate new access token and refresh token. Update session record with new tokens and expiration time. Return updated tokens. Revoke compromised refresh tokens on failure.
 * @path /economicForum/auth/user/refresh
 * @accessor api.functional.economicForum.auth.user.refresh
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
