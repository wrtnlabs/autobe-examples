/**
 * Upload a file attachment to a forum post.
 *
 * This operation allows authenticated users to upload files (images, documents,
 * etc.) as attachments to forum posts. The system enforces file type and size
 * restrictions based on the configured limits in the
 * economic_forum_upload_limits table. File metadata is stored in the
 * economic_forum_attachment_files table, which contains fields: file_name,
 * file_path, file_size, mime_type, uploaded_by, uploaded_at, and post_id.
 *
 * The user's identity is automatically extracted from the JWT authentication
 * token, and the uploaded_by field is populated with the authenticated user's
 * ID. The file_name and file_path fields are generated by the system using a
 * secure naming scheme. The file_size and mime_type fields are automatically
 * extracted from the uploaded file data.
 *
 * All file uploads are validated against allowed file extensions and maximum
 * file size. Files are uploaded with exclusive access to prevent conflicts and
 * are permanently stored with immutable paths.
 *
 * Related operations: GET /economic_forum/user/attachmentFiles (list
 * attachments for a post), DELETE /economic_forum/user/attachmentFiles/{fileId}
 * (remove an attachment).
 *
 * @param props.connection
 * @param props.body File upload information including the file data as a
 *   base64-encoded string and associated post ID.
 * @x-autobe-specification Receive file upload as base64-encoded string in request body. Validate file extension against allowed types in upload_limits. Verify user has appropriate permissions to upload to target post. Generate secure UUID-based file name. Create physical file in secure storage path. Extract file metadata (size, mime type). Insert record into economic_forum_attachment_files table with: file_name, file_path, file_size, mime_type, uploaded_by (from JWT), uploaded_at (current timestamp), and post_id from request. Return newly created attachment file metadata with full path and file details.
 * @path /economicForum/user/attachmentFiles
 * @accessor api.functional.economicForum.user.attachmentFiles.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
