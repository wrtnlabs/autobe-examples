import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPageIEconomicForumPostAttachment } from "../../../../structures/IPageIEconomicForumPostAttachment";

/**
 * Retrieve a list of all attachments associated with a specific forum post.
 *
 * This operation fetches all file attachments linked to a particular post
 * through the economic_forum_post_attachments join table. The attachments are
 * stored in the economic_forum_attachment_files table and linked to posts via
 * the economic_forum_post_attachments table which contains foreign keys to both
 * the post and file records. This API endpoint returns summary information
 * about each attachment including the file name, size, upload timestamp, and
 * file URL for download.
 *
 * Security considerations require that only authenticated users can access
 * attachments for posts they have authorization to view. The operation checks
 * the user's permissions against the post's access controls before returning
 * any attachment data. Rate limiting applies to prevent abuse of this endpoint
 * for excessive file enumeration.
 *
 * This operation integrates directly with the economic_forum_posts,
 * economic_forum_post_attachments, and economic_forum_attachment_files database
 * tables. The query joins these tables to retrieve attachment metadata while
 * filtering by the provided postId path parameter. Any attachments associated
 * with the specified post are returned, regardless of whether the post has been
 * deleted or archived.
 *
 * Related operations: GET /posts/{postId} (retrieves post content), GET
 * /attachment-files/{fileId} (retrieves individual attachment details), and
 * PATCH /posts/{postId}/attachments (uploads new attachments).
 *
 * @param props.connection
 * @param props.postId Unique identifier of the target forum post whose
 *   attachments are being retrieved.
 * @x-autobe-specification Query economic_forum_post_attachments table joined with economic_forum_attachment_files to retrieve attachment metadata.
 * Filter by economic_forum_post_attachments.post_id = postId path parameter.
 * Return paginated results with attachment_id, file_name, file_size, created_at, and file_url properties.
 * Apply permission checks based on post access controls from economic_forum_posts table.
 * Implement cursor-based pagination for large attachment lists.
 * Cache results for 5 minutes with postId cache key.
 * Include proper content-disposition headers for file download.
 * @path /economicForum/posts/:postId/attachments
 * @accessor api.functional.economicForum.posts.attachments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target forum post whose attachments are
     * being retrieved.
     */
    postId: string;
  };
  export type Response = IPageIEconomicForumPostAttachment.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/economicForum/posts/:postId/attachments",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicForum/posts/${encodeURIComponent(props.postId ?? "null")}/attachments`;
  export const random = (): IPageIEconomicForumPostAttachment.ISummary =>
    typia.random<IPageIEconomicForumPostAttachment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
