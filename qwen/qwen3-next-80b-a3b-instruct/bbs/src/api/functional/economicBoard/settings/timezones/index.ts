/**
 * Retrieve a comprehensive list of all supported timezone settings that the
 * economic board platform uses for user-facing timestamp display.
 *
 * The system stores all timestamps internally in UTC but presents them in the
 * user's local timezone. This endpoint provides access to the
 * economic_board_timezone_settings table which contains the complete set of
 * valid timezone identifiers from the IANA timezone database that users can
 * select for display purposes. Only timezones listed here can be selected by
 * users, ensuring consistency across the platform.
 *
 * The response includes each timezone's full name, short code, UTC offset, and
 * whether it's the system default. This information allows clients to construct
 * proper timezone selection UIs and convert timestamps correctly. The system
 * default timezone ("Asia/Seoul") is identified by is_default=true and must be
 * displayed prominently.
 *
 * This operation supports pagination and filtering for large deployments,
 * though in standard configurations the list of valid timezones is relatively
 * small and typically returned in a single page.
 *
 * @param props.connection
 * @path /economicBoard/settings/timezones
 * @accessor api.functional.economicBoard.settings.timezones.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPageIEconomicBoardTimezoneSetting;

  export const METADATA = {
    method: "GET",
    path: "/economicBoard/settings/timezones",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/economicBoard/settings/timezones";
  export const random = (): IPageIEconomicBoardTimezoneSetting =>
    typia.random<IPageIEconomicBoardTimezoneSetting>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Retrieve detailed information about a specific timezone setting using its
 * short platform identifier code (e.g., "KST", "EST").
 *
 * This operation looks up the timezone_setting record by its unique code field
 * from the economic_board_timezone_settings table. The timezoneCode parameter
 * must exactly match the code stored in the database (case-sensitive), and only
 * codes defined in the timezone_settings table are valid.
 *
 * The response returns the complete timezone details: the full IANA timezone
 * name (e.g., "Asia/Seoul"), the short code, UTC offset, and whether it's the
 * system default. This information is essential for applications that need to
 * display timezone information to users with contextual details instead of just
 * the code.
 *
 * This endpoint is typically used after a user selects a timezone from the list
 * returned by GET /settings/timezones, or when restoring a saved timezone
 * preference for a user account. The system validates that the requested code
 * exists in the timezone_settings table before returning the result.
 *
 * @param props.connection
 * @param props.timezoneCode Short identifier code of the target timezone
 *   setting (e.g., "KST", "EST"). Must exactly match a code defined in the
 *   economic_board_timezone_settings table.
 * @path /economicBoard/settings/timezones/:timezoneCode
 * @accessor api.functional.economicBoard.settings.timezones.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Short identifier code of the target timezone setting (e.g., "KST",
     * "EST"). Must exactly match a code defined in the
     * economic_board_timezone_settings table.
     */
    timezoneCode: string;
  };
  export type Response = IEconomicBoardTimezoneSetting;

  export const METADATA = {
    method: "GET",
    path: "/economicBoard/settings/timezones/:timezoneCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicBoard/settings/timezones/${encodeURIComponent(props.timezoneCode ?? "null")}`;
  export const random = (): IEconomicBoardTimezoneSetting =>
    typia.random<IEconomicBoardTimezoneSetting>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("timezoneCode")(() => typia.assert(props.timezoneCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
