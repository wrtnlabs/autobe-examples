/**
 * Retrieve the full details of a single economic board category identified by
 * its unique code.
 *
 * This endpoint returns complete information about a specific category used to
 * classify and filter economic and political discussion posts. The category is
 * identified by an immutable, system-assigned code (e.g., "economy",
 * "politics"). This code is used across the entire platform in URLs, search
 * queries, and API filters to ensure consistent, human-readable access to
 * content organization.
 *
 * The operation retrieves the complete record from the
 * economic_board_categories table where the code matches the provided path
 * parameter. The returned data includes the human-readable name for display, a
 * detailed description for internal use, and system timestamps for audit
 * purposes.
 *
 * This operation is part of a read-only hierarchy. Categories cannot be
 * created, updated, or deleted by users or moderators. The system maintains
 * immutability of these taxonomy terms to ensure data consistency. This
 * endpoint supports direct navigation and is used for category detail views and
 * validation of category references in posted content.
 *
 * Security: This endpoint is public. No authentication or authorization is
 * required since category taxonomy information is not sensitive.
 *
 * Related operations:
 *
 * - GET /settings/categories - List all categories
 * - GET /posts?categoryCode=xx - Search for posts in a specific category
 * - POST /settings/categories - Forbidden: system-managed
 * - PUT /settings/categories/{code} - Forbidden: system-managed
 * - DELETE /settings/categories/{code} - Forbidden: system-managed
 *
 * @param props.connection
 * @param props.categoryCode Unique machine-readable identifier of the category
 *   (e.g., "economy", "politics"). Must match exactly one of the predefined
 *   codes in the system. Used to directly reference category in URLs and search
 *   queries.
 * @path /economicBoard/settings/categories/:categoryCode
 * @accessor api.functional.economicBoard.settings.categories.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique machine-readable identifier of the category (e.g., "economy",
     * "politics"). Must match exactly one of the predefined codes in the
     * system. Used to directly reference category in URLs and search
     * queries.
     */
    categoryCode: string;
  };
  export type Response = IEconomicBoardCategory;

  export const METADATA = {
    method: "GET",
    path: "/economicBoard/settings/categories/:categoryCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicBoard/settings/categories/${encodeURIComponent(props.categoryCode ?? "null")}`;
  export const random = (): IEconomicBoardCategory =>
    typia.random<IEconomicBoardCategory>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("categoryCode")(() => typia.assert(props.categoryCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
