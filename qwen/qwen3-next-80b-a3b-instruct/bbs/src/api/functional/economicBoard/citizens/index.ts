/**
 * Search and retrieve a filtered, paginated list of citizens.
 *
 * This endpoint retrieves a filtered and paginated list of citizens who
 * participate in the economic and political discussion board.
 *
 * The operation supports comprehensive search and filtering functionality,
 * allowing administrators to identify citizens based on email address patterns,
 * account status (active, suspended, banned), and registration date ranges.
 * This enables efficient oversight of the citizen base, identification of
 * problematic accounts, and compliance monitoring.
 *
 * All citizens are currently in the 'active' state, with no suspended or banned
 * accounts detected. The system maintains an audit trail with deleted_at
 * timestamps to track account deletions while preserving historical integrity.
 * This approach ensures data compliance while maintaining privacy.
 *
 * The response returns citizen summary information including email, status, and
 * account creation/update timestamps, but excludes sensitive authentication
 * data like password_hash. This design follows the principle of least
 * privilege, exposing only necessary information for administrative oversight.
 *
 * This operation supports pagination with configurable page sizes and multiple
 * sorting options, allowing administrators to efficiently navigate large
 * citizen bases. Rate limiting is applied to prevent abuse of this
 * administrative search functionality. The operation is available only to admin
 * users to protect citizen privacy and prevent unauthorized enumeration of user
 * accounts.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for citizen
 *   filtering
 * @path /economicBoard/citizens
 * @accessor api.functional.economicBoard.citizens.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
