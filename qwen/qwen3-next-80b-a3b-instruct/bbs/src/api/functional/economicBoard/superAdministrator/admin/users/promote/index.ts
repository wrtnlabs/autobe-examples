export async function promoteToAdmin(
  connection: IConnection,
  props: promoteToAdmin.Props,
): Promise<promoteToAdmin.Response> {
  return true === connection.simulate
    ? promoteToAdmin.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...promoteToAdmin.METADATA,
          path: promoteToAdmin.path(props),
          status: null,
        },
      );
}
