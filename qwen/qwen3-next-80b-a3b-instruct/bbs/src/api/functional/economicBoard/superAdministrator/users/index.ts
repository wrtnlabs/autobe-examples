import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IEconomicBoardCitizen } from "../../../../structures/IEconomicBoardCitizen";

/**
 * Demote a super administrator to administrator status.
 *
 * This operation is only available to users with super administrator privileges. It permanently reduces the rank of another super administrator to a standard administrator, stripping their promotion and demotion permissions. This action is irreversible and logged for audit trails.
 *
 * The system refuses to demote the requesting super administrator (CANNOT_DEMOTE_SELF flag). The demoted user will receive a system notification. Their session remains valid until logout, but their permissions will be refreshed on the next authentication.
 *
 * @param props.connection
 * @param props.id The UUID of the super administrator to be demoted.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor superAdministrator
 * @x-autobe-specification Fetch the target user from economic_board_super_administrators by id.
 * Verify the authenticated user is a super administrator by checking economic_board_super_administrators.
 * If target user id equals current user id, return error CANNOT_DEMOTE_SELF.
 * Delete the target user's record from economic_board_super_administrators.
 * Update the target user's record in economic_board_administrators to ensure they exist and are marked as administrator (update role flag if needed).
 * Log the demotion event in economic_board_administrator_audit_logs with demoting_admin_id, target_user_id, and timestamp.
 * Set the updated_at field on the target user (economic_board_administrators table).
 * Return the updated user record with is_super_admin: false.
 * @path /economicBoard/superAdministrator/users/:id/demote
 * @accessor api.functional.economicBoard.superAdministrator.users.demote
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function demote(
  connection: IConnection,
  props: demote.Props,
): Promise<demote.Response> {
  return true === connection.simulate
    ? demote.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...demote.METADATA,
          path: demote.path(props),
          status: null,
        },
      );
}
export namespace demote {
  export type Props = {
    /**
     * The UUID of the super administrator to be demoted.
     */
    id: string;
  };
  export type Response = IEconomicBoardCitizen;

  export const METADATA = {
    method: "POST",
    path: "/economicBoard/superAdministrator/users/:id/demote",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicBoard/superAdministrator/users/${encodeURIComponent(props.id ?? "null")}/demote`;
  export const random = (): IEconomicBoardCitizen =>
    typia.random<IEconomicBoardCitizen>();
  export const simulate = (
    connection: IConnection,
    props: demote.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: demote.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("id")(() => typia.assert(props.id));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
