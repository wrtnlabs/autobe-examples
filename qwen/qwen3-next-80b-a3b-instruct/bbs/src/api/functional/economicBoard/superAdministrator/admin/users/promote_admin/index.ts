/**
 * Promote a citizen user to administrator status by submitting a promotion request.
 *
 * This endpoint allows a super administrator to initiate the promotion of a regular citizen to an administrator role. The citizen must have previously submitted a promotion request with a reason, and this endpoint executes the final administrative action to convert the citizen into an administrator. The system will maintain the original citizen record unchanged and create a new, separate administrator account record with all associated data migrated.
 *
 * The administrator status grants expanded privileges including moderating content, banning users, and approving other promotion requests. This endpoint does not immediately grant full administrator power but places the user into a pending promotion state, requiring approval from a super administrator if additional verification is needed. The promotion message is handled through the administrator's internal system and does not notify the user immediately.
 *
 * This operation is part of the admin promotion workflow defined in the requirements and works in tandem with POST /admin/requests and PATCH /admin/admin-requests/{requestId}/approve routes to create a complete promotion lifecycle.
 *
 * @param props.connection
 * @param props.userId UUID of the citizen user to promote. Must be a valid ID from the economic_board_citizens table.
 * @param props.body The reason for promoting the citizen to administrator role. Must be at least 10 characters and provided by the citizen in their promotion request.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor superAdministrator
 * @x-autobe-specification Validate that the target user exists in economic_board_citizens table and is not banned. Check that user does not already have administrator or super administrator status. Create a new record in economic_board_administrators with all fields copied from economic_board_citizens except admin_request_status is set to 'pending'. Set admin_request_reason from request body. Mark the citizen's is_banned flag as false if true. Log the promotion event with actor ID and timestamp. Do not delete or modify the original citizen record (as per actor separation principle).
 * @path /economicBoard/superAdministrator/admin/users/:userId/promote-admin
 * @accessor api.functional.economicBoard.superAdministrator.admin.users.promote_admin.promoteAdmin
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function promoteAdmin(
  connection: IConnection,
  props: promoteAdmin.Props,
): Promise<promoteAdmin.Response> {
  return true === connection.simulate
    ? promoteAdmin.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...promoteAdmin.METADATA,
          path: promoteAdmin.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace promoteAdmin {
  export type Props = {
    /**
     * UUID of the citizen user to promote. Must be a valid ID from the economic_board_citizens table.
     */
    userId: string & tags.Format<"uuid">;

    /**
     * The reason for promoting the citizen to administrator role. Must be at least 10 characters and provided by the citizen in their promotion request.
     */
    body: IEconomicBoardAdministratorAuditLog;
  };
  export type Body = IEconomicBoardAdministratorAuditLog;
  export type Response = IEconomicBoardCitizen;

  export const METADATA = {
    method: "PATCH",
    path: "/economicBoard/superAdministrator/admin/users/:userId/promote-admin",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/economicBoard/superAdministrator/admin/users/${encodeURIComponent(props.userId ?? "null")}/promote-admin`;
  export const random = (): IEconomicBoardCitizen =>
    typia.random<IEconomicBoardCitizen>();
  export const simulate = (
    connection: IConnection,
    props: promoteAdmin.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: promoteAdmin.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
