export async function updateAttachments(
  connection: IConnection,
  props: updateAttachments.Props,
): Promise<updateAttachments.Response> {
  return true === connection.simulate
    ? updateAttachments.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...updateAttachments.METADATA,
          path: updateAttachments.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace updateAttachments {
  export type Props = {
    /**
     * UUID of the article to update attachments for.
     */
    articleId: string & tags.Format<"uuid">;

    /**
     * Pagination and filtering criteria for attachment list retrieval.
     */
    body: IEconomicBoardArticle.IRequest;
  };
  export type Body = IEconomicBoardArticle.IRequest;
  export type Response = IPageIEconomicBoardArticleAttachment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/economicBoard/articles/:articleId/attachments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/economicBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/attachments`;
  export const random = (): IPageIEconomicBoardArticleAttachment.ISummary =>
    typia.random<IPageIEconomicBoardArticleAttachment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: updateAttachments.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: updateAttachments.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
