import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";

import { IPageIEconomicBoardArticleImage } from "../../../../structures/IPageIEconomicBoardArticleImage";

/**
 * Retrieve a paginated list of all image attachments associated with a specific article.
 *
 * This operation returns the metadata for every image attached to the article identified by {articleId}. Each image entry includes the original filename, dimensions (width and height), upload timestamp, and paths to optimized thumbnail and medium-sized versions for efficient display within the article UI.
 *
 * The images are displayed inline within the article’s content view, and this endpoint provides the necessary data for rendering each image with appropriate sizing and lazy-loading behavior. The response includes only the data necessary for client-side rendering, excluding full-resolution paths to minimize exposure.
 *
 * Image attachments are subsidiary entities managed entirely through their parent article; users cannot access images directly without viewing the associated article. This ensures that image access follows the same permission rules as the article itself.
 *
 * The list is sorted chronologically (oldest first) to preserve the sequence in which images were uploaded by the author.
 *
 * This operation is always called after viewing a specific article and is dependent on successful article retrieval. If the article does not exist or the provided articleId is invalid, the response will be an empty array — no error is returned to avoid leaking information about article existence.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article whose images are being retrieved. Must be a valid UUID.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query economic_board_article_images table filtered by economic_board_article_id = {articleId}.
 *
 * Apply pagination with 30 items per page using cursor-based or offset-based pagination (prefer cursor-based).
 *
 * Return only: original_filename, width, height, uploaded_at, thumbnail_path, medium_path.
 *
 * Sort by uploaded_at ASC (oldest first), as images are typically displayed in chronological order.
 *
 * Do not include original_path unless explicitly requested by the image viewer component.
 *
 * Do not join with economic_board_articles to verify existence — the path parameter context is sufficient and article existence is validated in the service layer.
 *
 * Handle case where articleId is invalid or article is deleted by returning empty array (not 404).
 * @path /economicBoard/articles/:articleId/images
 * @accessor api.functional.economicBoard.articles.images.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the article whose images are being retrieved. Must be a valid UUID.
     */
    articleId: string & tags.Format<"uuid">;
  };
  export type Response = IPageIEconomicBoardArticleImage.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/economicBoard/articles/:articleId/images",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/images`;
  export const random = (): IPageIEconomicBoardArticleImage.ISummary =>
    typia.random<IPageIEconomicBoardArticleImage.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
