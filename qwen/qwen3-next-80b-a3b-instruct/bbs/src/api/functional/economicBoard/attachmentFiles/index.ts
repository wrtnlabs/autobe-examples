import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconomicBoardAttachment } from "../../../structures/IEconomicBoardAttachment";

/**
 * Retrieve metadata and storage URI of an attachment by its sanitized code.
 *
 * This operation retrieves the full metadata record for a specific attachment
 * identified by its sanitized_name field, which acts as a human-readable code
 * rather than the system-generated UUID.
 *
 * The attachment code (attachmentCode) corresponds to the sanitized_name field
 * in the economic_board_attachments table. This field contains only
 * alphanumeric characters, hyphens, underscores, and periods, making it
 * suitable for use in URLs. The system enforces uniqueness through a composite
 * index with economic_board_post_id to ensure no two attachments within the
 * same post share the same sanitized name.
 *
 * Access to this endpoint is restricted to attachments that have successfully
 * completed processing (status = 'processed') and are still active (deleted_at
 * is null). Attachments in 'uploaded' (incomplete) or 'quarantined' (pending
 * review) status are not accessible through this endpoint. This ensures that
 * only validated, secure files are made available for download.
 *
 * The returned data includes the original filename, file size, MIME type, and a
 * signed storage_path URI that provides time-limited access to the actual file
 * in object storage. The storage_path is never a direct filesystem path,
 * ensuring security and access control. This operation does not serve the file
 * content directly but provides the secure URI for client-side retrieval,
 * preventing direct server-side file streaming.
 *
 * Security policy requires that only attachments related to publicly accessible
 * posts can be retrieved, or if requested by a moderator with appropriate
 * permissions. The system automatically enforces this through business logic
 * layer checks after this endpoint is called.
 *
 * Related operations: PATCH /attachmentFiles/{attachmentCode} - updates
 * attachment metadata.
 *
 * @param props.connection
 * @param props.attachmentCode The sanitized unique code for the attachment,
 *   corresponding to the sanitized_name field in the economic_board_attachments
 *   table. This code is uniquely generated during upload by sanitizing the
 *   original filename (removing special characters) and ensuring it is unique
 *   within the same post. The code must be alphanumeric, containing only
 *   letters, numbers, hyphens, and underscores. This is NOT the
 *   system-generated UUID id.
 * @path /economicBoard/attachmentFiles/:attachmentCode
 * @accessor api.functional.economicBoard.attachmentFiles.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * The sanitized unique code for the attachment, corresponding to the
     * sanitized_name field in the economic_board_attachments table. This
     * code is uniquely generated during upload by sanitizing the original
     * filename (removing special characters) and ensuring it is unique
     * within the same post. The code must be alphanumeric, containing only
     * letters, numbers, hyphens, and underscores. This is NOT the
     * system-generated UUID id.
     */
    attachmentCode: string;
  };
  export type Response = IEconomicBoardAttachment;

  export const METADATA = {
    method: "GET",
    path: "/economicBoard/attachmentFiles/:attachmentCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicBoard/attachmentFiles/${encodeURIComponent(props.attachmentCode ?? "null")}`;
  export const random = (): IEconomicBoardAttachment =>
    typia.random<IEconomicBoardAttachment>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("attachmentCode")(() => typia.assert(props.attachmentCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
