/**
 * Retrieve a complete, immutable historical snapshot of an article.
 *
 * This endpoint returns a point-in-time capture of an article's state, including its title (via linked article_id), content state, and context at the moment of snapshot creation. Snapshots are automatically generated during article edits, deletions, or administrative actions to support audit trails, compliance, and version history.
 *
 * This endpoint is accessible to all authenticated users. It does not expose the current state of the article, only its state at the time of recording. The snapshot_reason field indicates why this version was captured: "initial" (first version), "edit" (after user edit), "deletion" (when article was deleted), or "admin_delete" (when deleted by administrator).
 *
 * This operation does not include tags, attachments, or comments — those are tracked in separate subsidiary tables (economic_board_article_snapshot_tags and economic_board_article_snapshot_attachments) and must be queried separately using the article_id and snapshot_id if historical tag/attachment state is needed.
 *
 * @param props.connection
 * @param props.snapshotId The unique identifier (UUID) of the article snapshot to retrieve. This is not the original article ID, but the snapshot record ID itself.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query economic_board_article_snapshots table by id. Return record with id, article_id, created_at, snapshot_reason. Do not join with articles, tags, or attachments — this is a standalone audit record. Validate that the snapshot exists. Return 404 if not found. No authorization beyond JWT token — any authenticated user may view snapshots for transparency and audit compliance. No soft delete behavior — snapshots are never deleted.
 * @path /economicBoard/article-snapshots/:snapshotId
 * @accessor api.functional.economicBoard.article_snapshots.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * The unique identifier (UUID) of the article snapshot to retrieve. This is not the original article ID, but the snapshot record ID itself.
     */
    snapshotId: string & tags.Format<"uuid">;
  };
  export type Response = IEconomicBoardArticleSnapshot;

  export const METADATA = {
    method: "GET",
    path: "/economicBoard/article-snapshots/:snapshotId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicBoard/article-snapshots/${encodeURIComponent(props.snapshotId ?? "null")}`;
  export const random = (): IEconomicBoardArticleSnapshot =>
    typia.random<IEconomicBoardArticleSnapshot>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("snapshotId")(() => typia.assert(props.snapshotId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
