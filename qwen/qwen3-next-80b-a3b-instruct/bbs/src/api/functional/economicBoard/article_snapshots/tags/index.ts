/**
 * Retrieve all tags associated with a specific article snapshot.
 *
 * This operation returns the complete set of tags that were attached to the article at the exact moment the snapshot was created. It is used to display historical tagging context for auditing, revision comparison, or analytics.
 *
 * The associated tags are stored in the subsidiary economic_board_article_snapshot_tags table and linked to their normalized string representations in economic_board_tags. Each returned tag is represented as a normalized lowercase string, preserving the state at snapshot time. Tags are ordered by creation time (most recent first).
 *
 * This operation does not modify or create any data — it is strictly read-only. The snapshotId must refer to an existing article snapshot; otherwise, a 404 error is returned.
 *
 * Clients may filter the list by specifying one or more tag names in the request body to return only tags matching those exact strings, or use pagination to load results incrementally.
 *
 * This endpoint should be called after retrieving the snapshot itself to explore its historical tag context.
 *
 * Note: This operation is unrelated to live article tagging. Tags on live articles are managed through separate endpoints that modify economic_board_article_tags, not this snapshot table.
 *
 * @param props.connection
 * @param props.snapshotId The unique identifier of the article snapshot whose tag associations are being retrieved. This must match an existing id in the economic_board_article_snapshots table.
 * @param props.body Search, filter, and pagination parameters for the tag listing.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query economic_board_article_snapshot_tags joined with economic_board_tags to retrieve tag associations for the specified article snapshot. Filter by snapshotId. Apply pagination (page, limit) and optional tag name filter via request body. Sort by created_at DESC by default. Return only non-deleted tags. Exclude any tag that has been soft-deleted in economic_board_tags. Use cursor-based pagination if result set exceeds 100 tags.
 * @path /economicBoard/article-snapshots/:snapshotId/tags
 * @accessor api.functional.economicBoard.article_snapshots.tags.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
