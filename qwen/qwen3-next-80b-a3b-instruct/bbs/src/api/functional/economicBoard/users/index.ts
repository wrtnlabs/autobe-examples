import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IEconomicBoardCitizen } from "../../../structures/IEconomicBoardCitizen";

/**
 * Retrieve detailed information about a specific user's profile.
 *
 * This endpoint provides comprehensive profile data for a user identified by their unique UUID. The response includes public information such as display name and bio, account status indicators including ban state, administrative privileges, and system timestamps.
 *
 * Additionally, the system calculates and returns the total count of published articles and active comments authored by this user, providing insight into their content contributions. This data is essential for profile pages, author bios, and community engagement metrics.
 *
 * Authentication is required for this endpoint. If the user is banned, the system will return the user record but omit sensitive information and indicate ban status. System administrators can view profiles of banned users for moderation purposes.
 *
 * The profile information is derived exclusively from the economic_board_citizens database table, with article and comment counts aggregated from economic_board_articles and economic_board_comments tables respectively. This ensures data integrity and consistency between the API and the underlying database.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the user whose profile is being retrieved. This must be a valid UUID corresponding to a record in the economic_board_citizens table.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query economic_board_citizens table by UUID id. Join with economic_board_articles to count published articles (WHERE status = 'published'). Join with economic_board_comments to count published comments (WHERE status = 'active'). Return all citizen fields along with computed article_count and comment_count. Return 404 if user not found. Never return email if user is banned.
 * @path /economicBoard/users/:userId
 * @accessor api.functional.economicBoard.users.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the user whose profile is being retrieved. This must be a valid UUID corresponding to a record in the economic_board_citizens table.
     */
    userId: string;
  };
  export type Response = IEconomicBoardCitizen;

  export const METADATA = {
    method: "GET",
    path: "/economicBoard/users/:userId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicBoard/users/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): IEconomicBoardCitizen =>
    typia.random<IEconomicBoardCitizen>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
