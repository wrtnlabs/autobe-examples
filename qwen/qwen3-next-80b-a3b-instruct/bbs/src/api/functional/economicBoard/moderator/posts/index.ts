import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
export * as attachments from "./attachments/index";
export * as comments from "./comments/index";

/**
 * Permanently delete a discussion post (hard delete).
 *
 * Permanently removes a discussion post from the economic board system. This
 * operation is exclusively available to moderators and results in the complete
 * and irreversible deletion of the post record from the database.
 *
 * Unlike typical system behavior where soft deletes (setting deleted_at) are
 * preferred for audit compliance, this operation performs a hard delete per
 * explicit business rule: moderation authority permits immediate and permanent
 * removal of content. All associated child records, including attachments and
 * revisions, are also immediately purged from the system. No audit log is
 * created for this deletion in this table — audit trails are captured in the
 * moderation_actions table separately.
 *
 * Security considerations require that only authenticated moderators can invoke
 * this endpoint. The system enforces authorization by validating the JWT
 * token's role field and ensuring the user has moderator privileges. For
 * compliance, all deletion events must be logged in the
 * economic_board_moderation_actions table via the backend service layer.
 *
 * This is the only operation in the system that performs hard deletion. All
 * other entities (e.g., attachments, comments) use soft delete. This operation
 * is reserved for extreme cases where the post contains illegal content,
 * threats, or severe policy violations that require immediate eradication from
 * the system.
 *
 * Related operations: GET /posts/{postId} (retrieve a post before deletion),
 * DELETE /posts/{postId}/attachments (remove individual attachments).
 *
 * @param props.connection
 * @param props.postId Unique identifier of the post to be permanently deleted.
 *   Must be a valid UUID of an existing post.
 * @path /economicBoard/moderator/posts/:postId
 * @accessor api.functional.economicBoard.moderator.posts.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the post to be permanently deleted. Must be a
     * valid UUID of an existing post.
     */
    postId: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/economicBoard/moderator/posts/:postId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicBoard/moderator/posts/${encodeURIComponent(props.postId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
