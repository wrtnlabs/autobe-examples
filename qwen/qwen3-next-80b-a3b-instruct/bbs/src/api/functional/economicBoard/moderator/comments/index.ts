import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Permanently remove a specific comment from the system. This operation
 * performs a hard delete of a comment identified by its unique commentId,
 * removing the record entirely from the database with no possibility of
 * recovery.
 *
 * Security considerations are critical: this operation requires the user to
 * have moderator privileges, as only authorized moderators can permanently
 * delete comments. The operation does not change the comment's status flag but
 * directly deletes the record from the database, which is consistent with the
 * platform's policy for severe violations where audit trails must be maintained
 * but content must be completely erased.
 *
 * The comment's deletion is recorded in the economic_board_moderation_actions
 * system as a deletion action, where the moderator and targeted citizen are
 * logged for audit purposes. This operation complements the moderation action
 * logging system by providing the actual data removal function.
 *
 * This deletion operation is irreversible and should be used with extreme
 * caution. It is not a soft delete - the comment cannot be restored once
 * deleted. System logs preserve the timing and actor of deletion for compliance
 * and forensic purposes. Related comments in reply threads are left intact as
 * children of the deleted post remains visible with removed indicator.
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the comment to be permanently
 *   deleted
 * @path /economicBoard/moderator/comments/:commentId
 * @accessor api.functional.economicBoard.moderator.comments.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the comment to be permanently deleted */
    commentId: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/economicBoard/moderator/comments/:commentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicBoard/moderator/comments/${encodeURIComponent(props.commentId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
