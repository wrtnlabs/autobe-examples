/**
 * Retrieve detailed information about a specific active moderator.
 *
 * Retrieve the complete profile details of a specific active moderator account
 * from the economic_board_moderators table.
 *
 * This operation returns detailed information about a single moderator
 * identified by their unique ID. It returns all non-sensitive fields including
 * email, creation date, update date, and current status information. Password
 * hash and other sensitive authentication details are explicitly excluded from
 * the response for security reasons.
 *
 * Security considerations require that only authenticated administrators may
 * access this endpoint. The operation validates that the requested moderator
 * account exists and is active (not deactivated). Requests for non-existent or
 * deactivated moderator accounts return a 404 error.
 *
 * This operation is intended for administrative use to review individual
 * moderator profiles, audit activity history, or provide support for moderator
 * account inquiries. It complements the GET /moderators operation by providing
 * detailed information about an individual moderator.
 *
 * Related operations: PATCH /moderators (lists multiple moderators with summary
 * information).
 *
 * @param props.connection
 * @param props.moderatorId Unique identifier of the target moderator account
 * @path /economicBoard/moderator/moderators/:moderatorId
 * @accessor api.functional.economicBoard.moderator.moderators.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target moderator account */
    moderatorId: string;
  };
  export type Response = IEconomicBoardModerator;

  export const METADATA = {
    method: "GET",
    path: "/economicBoard/moderator/moderators/:moderatorId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicBoard/moderator/moderators/${encodeURIComponent(props.moderatorId ?? "null")}`;
  export const random = (): IEconomicBoardModerator =>
    typia.random<IEconomicBoardModerator>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("moderatorId")(() => typia.assert(props.moderatorId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

