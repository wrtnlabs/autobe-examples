import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Permanently delete a comment from a post.
 *
 * Permanently delete a specific comment from a discussion post within the
 * economic board system. This operation performs a hard delete, removing the
 * comment record entirely from the database without any possibility of
 * recovery.
 *
 * This action requires both the postCode and commentCode to uniquely identify
 * the target comment due to the composite unique constraint
 * @@unique([economic_board_post_id, code]) defined in the
 * economic_board_comments table. The postCode identifies the parent discussion
 * post, and the commentCode identifies the specific comment within that post.
 *
 * Security considerations: This operation is restricted to moderator-level
 * actors only, ensuring that only authorized users can permanently delete
 * content. Complete deletion of comments may be necessary for compliance with
 * content moderation policies, removing hate speech, threats, or other
 * violations of community guidelines.
 *
 * This deletion will immediately remove the comment from all views, including
 * search results and parent post comment threads. Any subsequent attempts to
 * retrieve this comment will return a 404 error. The operation does not affect
 * the parent post, only the specified comment record in the database.
 *
 * This operation is distinct from moderation flags or locks, as it represents
 * complete removal rather than content restriction.
 *
 * @param props.connection
 * @param props.postCode Unique business identifier code of the target post
 *   (global scope)
 * @param props.commentCode Unique business identifier code of the target
 *   comment within the post (scoped to post)
 * @path /economicBoard/moderator/posts/:postCode/comments/:commentCode
 * @accessor api.functional.economicBoard.moderator.posts.comments.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique business identifier code of the target post (global scope) */
    postCode: string;

    /**
     * Unique business identifier code of the target comment within the post
     * (scoped to post)
     */
    commentCode: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/economicBoard/moderator/posts/:postCode/comments/:commentCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicBoard/moderator/posts/${encodeURIComponent(props.postCode ?? "null")}/comments/${encodeURIComponent(props.commentCode ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postCode")(() => typia.assert(props.postCode));
      assert.param("commentCode")(() => typia.assert(props.commentCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
