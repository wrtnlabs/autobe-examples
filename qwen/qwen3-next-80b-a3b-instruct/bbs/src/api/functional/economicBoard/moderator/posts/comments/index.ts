import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Permanently deletes a specific comment from a discussion post. This operation
 * is irreversible and immediately hides the comment from public view by setting
 * the deleted_at timestamp in the economic_board_comments table.
 *
 * Security and permissions: Only the citizen who created the comment or a
 * moderator can delete it. The system verifies ownership using the JWT
 * authentication token to match the comment's citizen_id field. Moderators may
 * delete any comment regardless of ownership, subject to audit logging.
 *
 * The deletion is soft (tombstone) using the deleted_at field as defined in the
 * Prisma schema. The comment record remains in the database for audit
 * compliance but is filtered out from all public queries. The comment's parent
 * post_id reference is preserved to maintain thread integrity and historical
 * context.
 *
 * This operation does not affect other comments or the parent post. Only the
 * comment marked by comment_id is deleted.
 *
 * Related operations:
 *
 * - GET /comments: To retrieve remaining comments on the same post after deletion
 * - PATCH /posts/{postId}/comments: To retrieve a paginated list of the post's
 *   comments
 *
 * Error handling: Returns 404 if the comment_id does not exist, or if the
 * comment is already deleted.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the published post containing this
 *   comment. Must reference a record in economic_board_posts with status
 *   'published'.
 * @param props.commentId Unique identifier of the comment to be deleted. Must
 *   be a valid UUID and exist in economic_board_comments.
 * @path /economicBoard/moderator/posts/:postId/comments/:commentId
 * @accessor api.functional.economicBoard.moderator.posts.comments.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the published post containing this comment. Must
     * reference a record in economic_board_posts with status 'published'.
     */
    postId: string;

    /**
     * Unique identifier of the comment to be deleted. Must be a valid UUID
     * and exist in economic_board_comments.
     */
    commentId: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/economicBoard/moderator/posts/:postId/comments/:commentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicBoard/moderator/posts/${encodeURIComponent(props.postId ?? "null")}/comments/${encodeURIComponent(props.commentId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
      assert.param("commentId")(() => typia.assert(props.commentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
