import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Permanently delete a citizen account using their unique code.
 *
 * Permanently delete a citizen account from the economic board system. This
 * operation removes the citizen record entirely from the database with no
 * possibility of recovery. This is a hard delete action that does not mark the
 * record as deleted or move it to an archive; the citizen's data is completely
 * and irreversibly removed from the system.
 *
 * Security considerations: This operation can only be performed by moderators
 * with appropriate access rights. The system verifies that the requesting
 * moderator has the necessary permissions to delete citizen accounts before
 * executing the operation. This ensures that only authorized personnel can
 * remove citizen records from the database.
 *
 * The citizenCode parameter identifies the target citizen using the unique
 * business identifier code defined in the Prisma schema. This uses the code
 * field from the economic_board_citizens model instead of the system-generated
 * UUID id, ensuring the use of human-readable identifiers for operation
 * access.
 *
 * After deletion, the citizen's posts, comments, and other associated data are
 * also purged from the system as part of the cascading delete behavior defined
 * in the database schema. This ensures data integrity and prevents orphaned
 * records from remaining in the system.
 *
 * There is no confirmation step for this operation, and it cannot be undone.
 * Moderators must exercise extreme caution when using this capability, as it
 * results in permanent data loss.
 *
 * Related operations: PATCH /moderators (search for moderators), GET
 * /citizens/{citizenCode} (retrieve citizen information before deletion).
 *
 * @param props.connection
 * @param props.citizenCode Unique business identifier code of the citizen to be
 *   permanently deleted (global scope)
 * @path /economicBoard/moderator/citizens/:citizenCode
 * @accessor api.functional.economicBoard.moderator.citizens.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique business identifier code of the citizen to be permanently
     * deleted (global scope)
     */
    citizenCode: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/economicBoard/moderator/citizens/:citizenCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicBoard/moderator/citizens/${encodeURIComponent(props.citizenCode ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("citizenCode")(() => typia.assert(props.citizenCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
