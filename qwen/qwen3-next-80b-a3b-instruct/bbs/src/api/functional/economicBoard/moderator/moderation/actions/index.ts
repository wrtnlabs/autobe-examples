/**
 * Search and retrieve a filtered, paginated list of economic board moderation
 * actions.
 *
 * This operation provides comprehensive access to the audit trail of all
 * moderation actions performed on the economic board. It queries the
 * economic_board_moderation_actions table to retrieve records of moderation
 * activities including warnings, deletions, and locks, along with their
 * associated metadata.
 *
 * Moderators and administrators can filter actions by multiple criteria: target
 * citizen (citizen_id), acting moderator (moderator_id), creation date range,
 * and action status (active vs. deleted). The operation supports pagination to
 * handle large volumes of audit records efficiently. The response provides
 * complete metadata for each action including timestamps, references to the
 * affected user and moderator, and the deletion status.
 *
 * The operation does not include details of the specific action type (warning,
 * deletion, lock) in the base response. These details are stored in subordinate
 * tables (economic_board_moderation_warnings,
 * economic_board_moderation_deletions, economic_board_moderation_locks) and
 * must be retrieved separately using the moderation_action_id as a reference.
 * This design ensures database integrity and allows for extensible action types
 * while maintaining a single audit trail.
 *
 * The system permanently retains all moderation actions in the database. Even
 * when actions are marked as deleted (via deleted_at field), they remain
 * available for audit and compliance purposes. Only the deleted_at field is
 * modified to reflect logical deletion, ensuring complete audit history.
 *
 * This operation is critical for the moderator dashboard, enabling oversight of
 * moderation patterns, identification of potential moderator abuse, and
 * generation of compliance reports. It is restricted to moderator roles since
 * moderation logs contain sensitive information about citizen interactions and
 * system enforcement actions.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for retrieving
 *   moderation actions. Includes filters for citizen_id, moderator_id,
 *   created_at date range, and search by deletion status.
 * @path /economicBoard/moderator/moderation/actions
 * @accessor api.functional.economicBoard.moderator.moderation.actions.search
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function search(
  connection: IConnection,
  props: search.Props,
): Promise<search.Response> {
  return true === connection.simulate
    ? search.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...search.METADATA,
          path: search.path(),
          status: null,
        },
        props.body,
      );
}
