/**
 * Create a new comment on a published post.
 *
 * This operation allows authenticated citizens to create comments on published
 * discussion posts. When a comment is submitted, it is immediately published
 * and visible to all users on the platform. The system automatically links the
 * comment to the post identified by the postId path parameter and associates it
 * with the currently authenticated citizen.
 *
 * Security requires that only published posts can receive comments. If the post
 * referenced by postId has a status of 'pending' or 'rejected', the system will
 * return a 404 error. The comment body is limited to 500 characters as defined
 * in the economic_board_comments schema, and this constraint is enforced at the
 * application layer.
 *
 * Comments can be edited by the author within 24 hours of creation, and can be
 * permanently deleted by moderators, which sets the deleted_at field. The
 * comment's parent_comment_id can reference another comment to create threaded
 * discussions, but this is optional.
 *
 * Related operations: GET /posts/{postId}/comments to retrieve all comments on
 * a post, PUT /posts/{postId}/comments/{commentId} to edit a comment.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the published post to which this
 *   comment is attached. Must reference a post with status 'published' in the
 *   economic_board_posts table. Using a UUID format.
 * @param props.body The content of the new comment to be created. Must be 500
 *   characters or less as defined in the economic_board_comments schema.
 *   Includes text content and optional parent comment reference.
 * @path /economicBoard/citizen/posts/:postId/comments
 * @accessor api.functional.economicBoard.citizen.posts.comments.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
