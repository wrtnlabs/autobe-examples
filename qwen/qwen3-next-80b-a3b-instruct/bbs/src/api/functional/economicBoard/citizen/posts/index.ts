/**
 * Create a new economic board post.
 *
 * This endpoint creates a new economic board post submitted by an authenticated
 * citizen. The post is initially created with a status of 'pending' and will
 * only become visible to the public after moderation review.
 *
 * The operation validates that the user is a valid citizen with an active
 * session and fails if the authentication token is invalid, expired, or the
 * session has been invalidated. The citizen's ID is extracted from the JWT
 * authentication token and automatically associated with the post - the client
 * cannot specify the creator ID.
 *
 * The post must include both a title and body field, each constrained to 10,000
 * characters maximum. Empty or whitespace-only content is rejected with a
 * validation error. The system automatically sets the created_at timestamp in
 * UTC and assigns a unique post code that serves as the human-readable
 * identifier for this post.
 *
 * The operation does not accept attachments during creation. Attachments must
 * be uploaded separately after the post has been assigned a valid ID, as
 * attachments require the post to be created first before linking.
 *
 * Success returns the complete post object with generated ID and code. The post
 * code is the human-readable identifier and is included in the response for use
 * in subsequent API calls such as GET /posts/{postCode}.
 *
 * This operation follows a queuing model where citizen-submitted content enters
 * a moderation queue, ensuring compliance with content governance policies
 * before public visibility.
 *
 * @param props.connection
 * @param props.body Creation data for a new economic board post including title
 *   and body content
 * @path /economicBoard/citizen/posts
 * @accessor api.functional.economicBoard.citizen.posts.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
