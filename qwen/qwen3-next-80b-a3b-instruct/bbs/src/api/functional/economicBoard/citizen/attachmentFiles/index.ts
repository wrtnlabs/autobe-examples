import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconomicBoardAttachment } from "../../../../structures/IEconomicBoardAttachment";

/**
 * Upload a file attachment related to a discussion post on the economic board
 * platform. This operation creates a new attachment record in the
 * economic_board_attachments table and associates it with a designated post.
 *
 * The actual file content is stored in an external object storage system (such
 * as S3 or similar), while this API endpoint handles the metadata registration
 * in the database. The attachment record stores the original filename, MIME
 * type, file size, and a unique identifier that references the physical
 * location of the file.
 *
 * The file upload capability is designed to support various media types
 * including images, PDFs, documents, and other formats relevant to economic and
 * political discourse. This functionality enables users to share supporting
 * materials, charts, graphs, or reference documents to enhance discussion
 * threads.
 *
 * Uploads must adhere to system-imposed constraints on file size, type, and
 * upload volume. These restrictions appear in business rules which limit size
 * and restrict dangerous file types. The attachment record created here will be
 * accessible through the post's attachment collection, but the actual file is
 * served through a secure token-based URI system.
 *
 * As attachments are explicit user-generated content, we do not analyze or
 * extract content from files programmatically, but metadata is captured for
 * organizational, moderation, and compliance purposes.
 *
 * This functionality integrates with the economic_board_attachments model,
 * which is linked to economic_board_posts via foreign key relationship.
 *
 * @param props.connection
 * @param props.body Metadata and content for the new file attachment
 * @path /economicBoard/citizen/attachmentFiles
 * @accessor api.functional.economicBoard.citizen.attachmentFiles.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** Metadata and content for the new file attachment */
    body: IEconomicBoardAttachment.ICreate;
  };
  export type Body = IEconomicBoardAttachment.ICreate;
  export type Response = IEconomicBoardAttachment;

  export const METADATA = {
    method: "POST",
    path: "/economicBoard/citizen/attachmentFiles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/economicBoard/citizen/attachmentFiles";
  export const random = (): IEconomicBoardAttachment =>
    typia.random<IEconomicBoardAttachment>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
