/**
 * Perform a unified search across all articles in the economic board.
 *
 * This endpoint enables users to search article titles and content using full-text search criteria, filter results by one or more tags using AND logic, and retrieve paginated results sorted by publication date. Search queries must be at least 3 characters and no more than 100 characters.
 *
 * Results are sorted by newest first by default, with an option to sort by oldest. When tag filters are applied, only articles that contain ALL specified tags are returned. The system supports up to 10 simultaneous tag filters. Partial word matching is enabled using PostgreSQL trigram operators for improved recall.
 *
 * The search respects hard deletion: articles marked as deleted (is_deleted = true) do not exist in the database and are never included in results. If no articles match the search or tag filters, an empty array is returned with totalCount: 0.
 *
 * This endpoint replaces fragmented search functionality and is consumed by the main search bar, section-specific searches, and tag filter UI components.
 *
 * @param props.connection
 * @param props.body Search query, tag filters, and pagination controls
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor citizen
 * @x-autobe-specification Query economic_board_articles table with full-text search on title and content fields. Join with economic_board_article_tags to filter by exact tag matches (AND logic for multiple tags). Apply pagination with 20 items per page. Sort results by created_at DESC (newest first) by default. Support sort parameter for oldest first. Return article id, title, section_id, author_id, created_at, updated_at, comment_count, and an array of tag strings. Exclude soft-deleted articles (is_deleted = false).
 * @path /economicBoard/citizen/searches
 * @accessor api.functional.economicBoard.citizen.searches.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search query, tag filters, and pagination controls
     */
    body: IEconomicBoardArticle.IRequest;
  };
  export type Body = IEconomicBoardArticle.IRequest;
  export type Response = IPageIEconomicBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/economicBoard/citizen/searches",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/economicBoard/citizen/searches";
  export const random = (): IPageIEconomicBoardArticle.ISummary =>
    typia.random<IPageIEconomicBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
