/**
 * Search for posts using full-text search with topic filtering.
 *
 * Perform a full-text search across economic board posts with advanced
 * filtering capabilities.
 *
 * This operation enables users to discover relevant discussions by querying
 * multiple indexed data sources simultaneously: economic_board_search_index for
 * full-text token matching, economic_board_search_metadata for filtering by
 * post status and creation date, and economic_board_search_tags for
 * category-based topic filtering.
 *
 * The search supports complex and flexible querying, allowing users to combine
 * keyword matches with filters for status (published, pending, rejected),
 * publication time range, and specific economic topics. No separate endpoint
 * for simple keyword searches is needed as this single endpoint handles all
 * search scenarios, from basic text matching to sophisticated combinations with
 * filters.
 *
 * Results are returned in a paginated format optimized for display, with
 * summary information including post titles, statuses, and topic tags. The
 * operation avoids returning complete post content to maintain performance and
 * reduce bandwidth usage. Full content can be retrieved individually using the
 * GET /posts/{postId} endpoint.
 *
 * The search functionality is crucial for platform usability, allowing citizens
 * to find relevant economic discussions among thousands of posts. Performance
 * is prioritized through denormalized search structures, ensuring results are
 * returned under 2 seconds even with complex queries.
 *
 * This operation does not allow direct access to moderation records or
 * user-specific data, maintaining privacy and appropriate access boundaries.
 *
 * Related operations include retrieving a specific post (GET /posts/{postId})
 * or retrieving all posts by a citizen (GET /citizens/{citizenId}/posts).
 *
 * @param props.connection
 * @param props.body Search parameters including keyword query, status filters,
 *   and topic tags for refining search results.
 * @path /economicBoard/search
 * @accessor api.functional.economicBoard.search
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function search(
  connection: IConnection,
  props: search.Props,
): Promise<search.Response> {
  return true === connection.simulate
    ? search.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...search.METADATA,
          path: search.path(),
          status: null,
        },
        props.body,
      );
}
export namespace search {
  export type Props = {
    /**
     * Search parameters including keyword query, status filters, and topic
     * tags for refining search results.
     */
    body: IEconomicBoardSearchMetadata.IRequest;
  };
  export type Body = IEconomicBoardSearchMetadata.IRequest;
  export type Response = IPageIEconomicBoardPost.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/economicBoard/search",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/economicBoard/search";
  export const random = (): IPageIEconomicBoardPost.ISummary =>
    typia.random<IPageIEconomicBoardPost.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: search.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: search.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
