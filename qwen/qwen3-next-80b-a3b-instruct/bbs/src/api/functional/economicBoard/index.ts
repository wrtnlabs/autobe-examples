/**
 * Search economic board posts with filters and pagination.
 *
 * Search across all economic board posts using keywords, filters, and sorting.
 *
 * This operation enables users and moderators to discover relevant discussion
 * posts using free-text queries and advanced filtering. The search engine
 * indexes the title and body content of all published posts via the
 * economic_board_search_metadata table, allowing for fast response times
 * without impacting the performance of content creation operations.
 *
 * Search results can be filtered by post status (published, pending, rejected),
 * date range (created_at), and category (using economic_board_search_tags to
 * join with economic_board_categories). The system evaluates relevance based on
 * keyword frequency, title matching priority, and post recency, returning the
 * most relevant results first.
 *
 * Results are paginated with configurable page size and offset parameters to
 * handle large datasets efficiently. Sorting can be applied by relevance
 * (default), date (newest first, oldest first), and title alphabetically.
 *
 * Security: The search respects content moderation status—only published posts
 * are returnable. Users see only what they are authorized to see based on
 * platform permissions, while moderators receive full visibility with all
 * statuses visible.
 *
 * This operation is critical to the platform's accessibility, enabling users to
 * find topics of interest and moderators to locate problematic content for
 * review. It performs no updates or deletions, ensuring data integrity during
 * query operations.
 *
 * Related operations: GET /moderation/actions/{actionCode} to investigate
 * specific moderation decisions triggered by search findings.
 *
 * @param props.connection
 * @param props.body Search criteria including query terms, filters, sorting
 *   options, and pagination parameters.
 * @path /economicBoard/search
 * @accessor api.functional.economicBoard.search
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function search(
  connection: IConnection,
  props: search.Props,
): Promise<search.Response> {
  return true === connection.simulate
    ? search.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...search.METADATA,
          path: search.path(),
          status: null,
        },
        props.body,
      );
}
export namespace search {
  export type Props = {
    /**
     * Search criteria including query terms, filters, sorting options, and
     * pagination parameters.
     */
    body: IEconomicBoardSearchMetadata.IRequest;
  };
  export type Body = IEconomicBoardSearchMetadata.IRequest;
  export type Response = IPageIEconomicBoardPost.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/economicBoard/search",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/economicBoard/search";
  export const random = (): IPageIEconomicBoardPost.ISummary =>
    typia.random<IPageIEconomicBoardPost.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: search.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: search.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
