/**
 * Permanently ban a user from the Economic/Political Discussion Board.
 *
 * This operation immediately revokes the target user's access to the platform by marking their account as banned. The user will be unable to log in, post articles or comments, or access any functionality until explicitly unbanned by an administrator.
 *
 * All content created by the banned user—including articles, comments, and file attachments—remains publicly visible to preserve transparency and maintain the integrity of historical discourse. No data is deleted or hidden.
 *
 * Administrators must provide a minimum 10-character ban reason that will be recorded permanently as an audit trail. The reason will be visible to all other administrators via the audit log.
 *
 * The system automatically invalidates all active sessions for the banned user, forcing immediate logout across all devices. A comprehensive audit log entry is created in economic_board_administrator_audit_logs, recording the target user ID, banning administrator ID, ban reason, IP address, and timestamp.
 *
 * This operation requires administrator privileges and cannot be performed by regular citizens. This endpoint is the only mechanism to initiate a ban.
 *
 * Related operations:
 * - POST /economicBoard/administrator/admin/users/{userId}/unban: Reverses a ban and restores user access.
 *
 * @param props.connection
 * @param props.userId The unique identifier of the user to be banned. Must be a valid UUID from either economic_board_citizens or economic_board_administrators table.
 * @param props.body The reason for banning the user. Must be at least 10 characters and not exceed 500 characters. The reason will be recorded permanently as an audit trail.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor administrator
 * @x-autobe-specification Update the target user's is_banned field to true in economic_board_citizens or economic_board_administrators table. Set ban_reason to the provided reason text (10-500 chars). Set banned_at timestamp to current server time (Asia/Seoul). Set banned_by field to the authenticated administrator's UUID. Do not modify any article, comment, or file records. Clear all active sessions in economic_board_citizen_sessions or economic_board_administrator_sessions for this user. Log the ban event in economic_board_administrator_audit_logs with user_id, action: 'ban', reason, and operator_id. Validate that the authenticated user has administrator role. Validate that the target user is not the same as the authenticating administrator. Validate that ban_reason is non-empty and between 10 and 500 characters. Return HTTP 204 No Content on success, 400 if reason is invalid, 403 if permission fails, 404 if user not found.
 * @path /economicBoard/administrator/admin/users/:userId/ban
 * @accessor api.functional.economicBoard.administrator.admin.users.ban
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function ban(
  connection: IConnection,
  props: ban.Props,
): Promise<void> {
  return true === connection.simulate
    ? ban.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...ban.METADATA,
          path: ban.path(props),
          status: null,
        },
        props.body,
      );
}
