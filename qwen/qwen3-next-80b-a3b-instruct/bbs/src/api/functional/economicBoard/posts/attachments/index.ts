import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconomicBoardAttachment } from "../../../../structures/IEconomicBoardAttachment";

/**
 * Retrieve metadata for a specific attachment linked to a published post.
 *
 * Retrieve metadata for a specific file attachment associated with a discussion
 * post.
 *
 * This operation returns comprehensive metadata about an attachment linked to a
 * specific post. All attachments are stored in object storage and accessed via
 * signed URIs. The operation returns the original filename, sanitized filename,
 * file size in bytes, MIME type, secure storage URI, and current status
 * (uploaded, processed, or quarantined).
 *
 * The attachment's visibility is governed by the status of its parent post.
 * Only attachments linked to published posts can be accessed. If the parent
 * post is pending, rejected, or deleted, this operation will return a 404 error
 * even if the attachment record exists. This ensures content security and
 * prevents access to attachments associated with non-public posts.
 *
 * Attachments are never permanently deleted. The deleted_at field is used for
 * audit trails only and does not affect accessibility—access is controlled
 * solely by the parent post's status. The storage_path is a signed,
 * time-limited URI that expires after 1 hour for security.
 *
 * The attachment must be verified as accessible before returning any metadata.
 * No authentication is required for this operation since any attached file is
 * visible only if the parent post is published, but post visibility is
 * validated internally.
 *
 * Related operations: GET /posts/{postId} to validate post status before
 * accessing attachments, PATCH /posts/{postId}/attachments to list attachments
 * for a post.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the parent discussion post, used to
 *   validate post status before returning attachment metadata. Must reference
 *   an existing economic_board_posts.id.
 * @param props.attachmentId Unique identifier of the attachment record to
 *   retrieve, referencing economic_board_attachments.id.
 * @path /economicBoard/posts/:postId/attachments/:attachmentId
 * @accessor api.functional.economicBoard.posts.attachments.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the parent discussion post, used to validate
     * post status before returning attachment metadata. Must reference an
     * existing economic_board_posts.id.
     */
    postId: string;

    /**
     * Unique identifier of the attachment record to retrieve, referencing
     * economic_board_attachments.id.
     */
    attachmentId: string;
  };
  export type Response = IEconomicBoardAttachment;

  export const METADATA = {
    method: "GET",
    path: "/economicBoard/posts/:postId/attachments/:attachmentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicBoard/posts/${encodeURIComponent(props.postId ?? "null")}/attachments/${encodeURIComponent(props.attachmentId ?? "null")}`;
  export const random = (): IEconomicBoardAttachment =>
    typia.random<IEconomicBoardAttachment>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
      assert.param("attachmentId")(() => typia.assert(props.attachmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
