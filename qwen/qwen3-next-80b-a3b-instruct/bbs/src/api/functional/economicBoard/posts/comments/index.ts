/**
 * Retrieve a paginated list of published comments associated with the specified
 * post. Returns only comments with status 'published' that belong to a post
 * with status 'published'. Uses index on (post_id, created_at) for
 * performance.
 *
 * This operation supports navigation through large comment threads using
 * pagination. Clients specify page number and page size with query parameters
 * (or path parameters). The default page size is 20, with a hard limit of 100
 * to prevent system overload.
 *
 * Only comments attached to published posts are returned. Comments on pending
 * or rejected posts are excluded from results.
 *
 * The response includes the comment body, creation timestamp, and the citizen's
 * handle (username) from the economic_board_citizens table, to provide a clean
 * user experience without exposing internal UUIDs.
 *
 * Related operations:
 *
 * - DELETE /economicBoard/comments/{commentId}: To delete a specific comment
 * - POST /economicBoard/posts/{postId}/comments: To add a new comment
 *
 * Error handling: Returns 404 if the post_id does not reference a valid
 * published post.
 *
 * Performance: The database index on (post_id, created_at) ensures efficient
 * retrieval of comments for a specific post in reverse chronological order.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the published post whose comments
 *   are being retrieved. Must reference a record in economic_board_posts with
 *   status 'published'.
 * @path /economicBoard/posts/:postId/comments
 * @accessor api.functional.economicBoard.posts.comments.getByPostid
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
