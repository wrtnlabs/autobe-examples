import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconomicBoardPost } from "../../../structures/IEconomicBoardPost";
export * as comments from "./comments/index";

/**
 * Retrieve a specific economic board post by its code.
 *
 * This endpoint retrieves a specific economic board post by its unique post
 * code identifier. The post code serves as a human-readable business identifier
 * for the post, replacing the need for UUIDs in URLs for better usability.
 *
 * The post must have a status of 'published' to be accessible through this
 * endpoint. Posts with 'pending' or 'rejected' status will return a 404
 * response to maintain content moderation policies. The system does not expose
 * the internal UUID identifier in any public API response.
 *
 * The response includes the post's title, body content, status, creation
 * timestamp, and the username of the citizen who created it. Moderation details
 * such as which moderator approved or rejected the post are excluded from this
 * summary response for privacy and security reasons. To obtain moderated
 * details, administrators must use administrative endpoints with appropriate
 * permissions.
 *
 * This operation is restricted to read-only access following the principle that
 * public content should be accessible without authentication, while sensitive
 * moderation data requires higher privileges.
 *
 * @param props.connection
 * @param props.postCode Unique business identifier code of the target economic
 *   board post (global scope). This human-readable code replaces UUID
 *   identifiers in URLs for improved usability and is guaranteed to be unique
 *   across the entire system.
 * @path /economicBoard/posts/:postCode
 * @accessor api.functional.economicBoard.posts.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique business identifier code of the target economic board post
     * (global scope). This human-readable code replaces UUID identifiers in
     * URLs for improved usability and is guaranteed to be unique across the
     * entire system.
     */
    postCode: string;
  };
  export type Response = IEconomicBoardPost;

  export const METADATA = {
    method: "GET",
    path: "/economicBoard/posts/:postCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicBoard/posts/${encodeURIComponent(props.postCode ?? "null")}`;
  export const random = (): IEconomicBoardPost =>
    typia.random<IEconomicBoardPost>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postCode")(() => typia.assert(props.postCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
