/**
 * Retrieve a specific section by its unique section identifier. This operation returns the full details of the specified section including its name and description. Section information is publicly accessible and may be viewed by all authenticated users, including both citizens and administrators.
 *
 * The section name and description are stored in the database according to the economic_discussion_sections model. The section name is a required field with a length between 3 and 50 characters, while the description is required and must be between 50 and 500 characters. Section information determines the structure for article categorization and user navigation across the platform.
 *
 * This operation complements the section listing endpoint (/sections) which returns a paginated list of all sections. Unlike the list operation that returns summary information, this endpoint provides complete details of a specific section. Section visibility is not restricted by user role, allowing any authenticated user to access section details.
 *
 * The section reference is required when creating articles and is used for filtering article lists. This operation is used when users click on a section from the sidebar navigation or when administrators need to view the complete section details for editing purposes.
 *
 * @param props.connection
 * @param props.sectionId Unique identifier of the target section
 * @x-autobe-specification Query economic_discussion_sections table for the section with matching id. Return the section's name and description fields. Return HTTP 404 if section is not found. No caching necessary as section data changes infrequently. Log access for security auditing purposes.
 * @path /economicDiscussion/sections/:sectionId
 * @accessor api.functional.economicDiscussion.sections.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target section
     */
    sectionId: string;
  };
  export type Response = IEconomicDiscussionSection;

  export const METADATA = {
    method: "GET",
    path: "/economicDiscussion/sections/:sectionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicDiscussion/sections/${encodeURIComponent(props.sectionId ?? "null")}`;
  export const random = (): IEconomicDiscussionSection =>
    typia.random<IEconomicDiscussionSection>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sectionId")(() => typia.assert(props.sectionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
