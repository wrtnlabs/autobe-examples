/**
 * This join operation creates a new citizen account by registering a user with their email and password. The system validates the email format according to RFC 5322 standards before proceeding. The password is hashed using bcrypt with 12-round salt before storage in the citizens table. The registration creates a new record with email, password_hash, and timestamp fields. The operation does not require prior authentication since it's for new account creation. The citizen table contains email as unique identifier and password_hash as the encrypted credential, which are the only required fields for registration. This operation is the first step in the authentication workflow for citizen users.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Contains user's email and password for account registration.
 * @x-autobe-specification Validate email and password credentials against citizen table. Hash password using bcrypt algorithm with 12-round salt. Query citizens table with WHERE email = provided_email AND password_hash = hashed_password. Return matching citizen record if found, null otherwise.
 * @path /economicDiscussion/auth/citizen/join
 * @accessor api.functional.economicDiscussion.auth.citizen.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
