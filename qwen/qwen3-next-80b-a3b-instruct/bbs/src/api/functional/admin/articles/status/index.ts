import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IAdmin } from "../../../../structures/IAdmin";
import { IArticleStatusUpdateResult } from "../../../../structures/IArticleStatusUpdateResult";

/**
 * Allows an authenticated admin to modify the status of an article in the
 * discussion_board_articles table. Admins can set articles to 'published',
 * 'hidden' or 'deleted' status, bypassing regular publication workflows. The
 * operation reads the article's current status from
 * discussion_board_article_status_logs and updates it within the
 * discussion_board_articles table using the admin's authorized identity. All
 * actions are logged in discussion_board_moderation_actions for audit
 * purposes.
 *
 * This admin privilege is essential for content moderation - allowing quick
 * removal of inappropriate content or immediate publication of time-sensitive
 * material. The request includes the article UUID and target state, ensuring
 * precise control. The operation is only available to users authenticated as
 * admin.
 *
 * @param props.connection
 * @param props.articleId UUID identifier of the article to modify status for as
 *   referenced in discussion_board_articles table.
 * @param props.body Request body containing the target status value for the
 *   article. Must be one of: 'published', 'hidden', or 'deleted' per
 *   discussion_board_article_statuses enumeration.
 * @path /admin/articles/:articleId/status
 * @accessor api.functional.admin.articles.status.updateArticleStatus
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function updateArticleStatus(
  connection: IConnection,
  props: updateArticleStatus.Props,
): Promise<updateArticleStatus.Response> {
  return true === connection.simulate
    ? updateArticleStatus.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...updateArticleStatus.METADATA,
          path: updateArticleStatus.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace updateArticleStatus {
  export type Props = {
    /**
     * UUID identifier of the article to modify status for as referenced in
     * discussion_board_articles table.
     */
    articleId: string;

    /**
     * Request body containing the target status value for the article. Must
     * be one of: 'published', 'hidden', or 'deleted' per
     * discussion_board_article_statuses enumeration.
     */
    body: IAdmin.IUpdateArticleStatus;
  };
  export type Body = IAdmin.IUpdateArticleStatus;
  export type Response = IArticleStatusUpdateResult;

  export const METADATA = {
    method: "PUT",
    path: "/admin/articles/:articleId/status",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/admin/articles/${encodeURIComponent(props.articleId ?? "null")}/status`;
  export const random = (): IArticleStatusUpdateResult =>
    typia.random<IArticleStatusUpdateResult>();
  export const simulate = (
    connection: IConnection,
    props: updateArticleStatus.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: updateArticleStatus.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
