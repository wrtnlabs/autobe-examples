import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPoliticalForumPostAttachment } from "../../../../structures/IPoliticalForumPostAttachment";

/**
 * Retrieve a specific attachment file by ID for a given post.
 *
 * Retrieve a specific attachment file associated with a political forum post.
 * This operation allows users to download or view metadata for a file uploaded
 * as part of a political discussion post. The attachment is identified by a
 * unique combination of post and attachment identifiers.
 *
 * This operation is specifically implemented for the
 * political_forum_post_attachments table, which stores metadata about files
 * uploaded to posts. It does not return the actual binary file content but
 * provides the necessary information to access the file in cloud storage. The
 * response includes critical metadata fields such as filename, file type, size,
 * and upload timestamp.
 *
 * Security considerations include ensuring that the requesting user has
 * appropriate permissions to view the post to which the attachment belongs.
 * Only users who can access the parent post can retrieve its attachments. This
 * prevents unauthorized access to sensitive files through direct URL access.
 *
 * The attachment files are stored externally (e.g., in cloud storage), and this
 * API endpoint provides the reference to the file location rather than the file
 * content itself. This follows the best practice of separating metadata from
 * large binary objects to improve performance and scalability.
 *
 * Error scenarios include: attempting to access a non-existent attachment,
 * accessing an attachment belonging to a post that doesn't exist or is not
 * accessible, or when the cloud storage system is unavailable.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the political forum post that
 *   contains this attachment (global scope)
 * @param props.attachmentId Unique identifier of the attachment file within the
 *   context of the post (global scope)
 * @path /politicalForum/posts/:postId/attachmentFiles/:attachmentId
 * @accessor api.functional.politicalForum.posts.attachmentFiles.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the political forum post that contains this
     * attachment (global scope)
     */
    postId: string;

    /**
     * Unique identifier of the attachment file within the context of the
     * post (global scope)
     */
    attachmentId: string;
  };
  export type Response = IPoliticalForumPostAttachment;

  export const METADATA = {
    method: "GET",
    path: "/politicalForum/posts/:postId/attachmentFiles/:attachmentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/politicalForum/posts/${encodeURIComponent(props.postId ?? "null")}/attachmentFiles/${encodeURIComponent(props.attachmentId ?? "null")}`;
  export const random = (): IPoliticalForumPostAttachment =>
    typia.random<IPoliticalForumPostAttachment>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
      assert.param("attachmentId")(() => typia.assert(props.attachmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
