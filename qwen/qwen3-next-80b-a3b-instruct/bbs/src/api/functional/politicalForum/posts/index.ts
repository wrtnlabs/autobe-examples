/**
 * Search and retrieve a filtered, paginated list of political forum posts.
 *
 * Retrieve a filtered and paginated list of political forum posts from the
 * system. This operation provides advanced search capabilities for finding
 * posts based on multiple criteria including partial title matching, content
 * keywords, author citizenship status, post state (draft/published/archived),
 * moderation status (approved/rejected/pending), and creation date ranges.
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * and sorting options. Posts can be sorted by creation date, last activity,
 * number of comments, or other relevant fields in ascending or descending
 * order.
 *
 * Security considerations include rate limiting for search operations and
 * appropriate filtering of posts based on the requesting user's authorization
 * level. Only users with appropriate permissions can access detailed post
 * information or perform complex searches across sensitive data. Publicly
 * accessible posts are returned by default, while access to draft or unapproved
 * posts requires specific privileges.
 *
 * This operation integrates with the political_forum_posts table as defined in
 * the Prisma schema, incorporating all available post fields and relationships.
 * The response includes post summary information optimized for list displays,
 * with options to include additional details based on authorization level.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for post
 *   filtering
 * @path /politicalForum/posts
 * @accessor api.functional.politicalForum.posts.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for post filtering */
    body: IPoliticalForumPost.IRequest;
  };
  export type Body = IPoliticalForumPost.IRequest;
  export type Response = IPageIPoliticalForumPost.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/politicalForum/posts",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/politicalForum/posts";
  export const random = (): IPageIPoliticalForumPost.ISummary =>
    typia.random<IPageIPoliticalForumPost.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

