/**
 * Retrieve detailed information for a specific political forum post.
 *
 * This operation retrieves the complete details of a single political forum
 * post identified by its UUID. The response includes the post's title, content,
 * author, status (as defined in political_forum_post_states), moderation status
 * (as defined in political_forum_moderation_status), creation and update
 * timestamps, any associated attachments from political_forum_post_attachments,
 * and audit metadata.
 *
 * Although the political_forum_posts table supports multiple states and the
 * political_forum_post_modifications table tracks historical changes, this
 * endpoint returns only the current state of the post. The system automatically
 * applies any legal moderation actions (e.g., deletion, locking, verification)
 * and updates the status accordingly, making this endpoint always return the
 * live, visible state of the content.
 *
 * This is a PATCH method because, although it’s a retrieval operation, it
 * allows for advanced filtering and inclusion options (e.g., include
 * attachments, include comments) via the request body. Request body parameters
 * are optional and determine the level of detail returned. This approach avoids
 * complex query strings and aligns with our API design standard for rich
 * retrieval operations.
 *
 * The operation is accessible to all authenticated users. Moderators can view
 * posts with any status, while regular citizens can only view public,
 * non-deleted posts. The system enforces these restrictions at the business
 * logic layer, not through separate endpoint variants. Author information is
 * exposed as required by user need, but sensitive user data like contact
 * details is omitted.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the political forum post to
 *   retrieve. This refers to a record in the political_forum_posts table. The
 *   post may be public, locked, or archived, but this endpoint returns its
 *   current state regardless of moderation history.
 * @param props.body Optional parameters to control the level of detail in the
 *   response, such as whether to include attachments and comments.
 * @path /politicalForum/citizen/posts/:postId
 * @accessor api.functional.politicalForum.citizen.posts.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
