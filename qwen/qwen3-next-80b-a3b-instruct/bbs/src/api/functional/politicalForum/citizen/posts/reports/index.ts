import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPoliticalForumPostReport } from "../../../../../structures/IPoliticalForumPostReport";

/**
 * Submit a report against a specific political forum post.
 *
 * Citizens can report posts that violate community guidelines by submitting
 * detailed reports through this endpoint. The system automatically prevents
 * duplicate reports from the same citizen on the same post to avoid abusive
 * reporting patterns. When a report is submitted, it's immediately recorded in
 * the political_forum_post_reports table and triggers a moderation review
 * workflow.
 *
 * The operation requires the postId path parameter to identify the target post
 * and includes a request body with optional reason text and user context. The
 * system validates the citizen's authentication status before processing and
 * ensures the reported post exists in the political_forum_posts table.
 *
 * This operation does not modify the target post but creates a new record in
 * political_forum_post_reports, linking to the reporting citizen (from
 * political_forum_citizens) and the target post. The system logs these reports
 * for moderation team review and may trigger automated actions based on report
 * volume patterns.
 *
 * All reports submitted via this endpoint are immutable and cannot be edited or
 * deleted after submission. Moderators can view these reports in their
 * dashboard and take appropriate actions including post removal, warning
 * issuance, or account suspension.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the target political forum post
 *   being reported. This must reference an existing post in the
 *   political_forum_posts table.
 * @param props.body Details of the report being submitted, including optional
 *   reason text and reporting context.
 * @path /politicalForum/citizen/posts/:postId/reports
 * @accessor api.functional.politicalForum.citizen.posts.reports.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Unique identifier of the target political forum post being reported.
     * This must reference an existing post in the political_forum_posts
     * table.
     */
    postId: string & tags.Format<"uuid">;

    /**
     * Details of the report being submitted, including optional reason text
     * and reporting context.
     */
    body: IPoliticalForumPostReport.ICreate;
  };
  export type Body = IPoliticalForumPostReport.ICreate;
  export type Response = IPoliticalForumPostReport;

  export const METADATA = {
    method: "POST",
    path: "/politicalForum/citizen/posts/:postId/reports",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/politicalForum/citizen/posts/${encodeURIComponent(props.postId ?? "null")}/reports`;
  export const random = (): IPoliticalForumPostReport =>
    typia.random<IPoliticalForumPostReport>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
