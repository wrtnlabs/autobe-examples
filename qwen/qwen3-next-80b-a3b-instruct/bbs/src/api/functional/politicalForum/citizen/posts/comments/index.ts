/**
 * Create a new comment on a political forum post in response to a specific
 * discussion thread. This operation allows authenticated citizens to contribute
 * to ongoing political discussions by posting new comments beneath existing
 * posts. Each created comment inherits its context from the parent post and
 * becomes part of the threaded conversation history.
 *
 * The comment creation workflow requires the user to be authenticated as a
 * citizen, as only registered and authenticated users are permitted to post
 * comments on the forum. The system verifies the user's authentication token
 * and associates the comment with the appropriate citizen identity via the
 * comment's userId field. Post IDs are validated to ensure the target post
 * exists and is not archived, preventing comments on non-existent or retired
 * discussion threads.
 *
 * The comment content is subject to validation rules defined in the business
 * requirements: text content must not exceed 2000 characters, and inappropriate
 * content will trigger moderation flags for review. The system automatically
 * assigns timestamps for creation and records the creator's identity. No
 * attachments can be included with comments through this endpoint; if
 * attachments are needed, they must be uploaded separately with a dedicated
 * attachment endpoint.
 *
 * After successful creation, the new comment is immediately visible on the
 * post's comment thread, and relevant subscribers may receive notification
 * alerts based on their preference settings. The system maintains referential
 * integrity by requiring the existence of the parent post ID before allowing
 * comment creation, ensuring a valid hierarchical structure.
 *
 * Error handling includes rejecting requests with invalid post IDs, missing or
 * empty comment content, unauthorized users, or comments exceeding character
 * limits. This operation does not allow duplicate comment submission attempts
 * within a short time window to prevent spam.
 *
 * This endpoint complements the GET /posts/{postId}/comments/{commentId}
 * operation by enabling the creation of new comments in the same hierarchical
 * context.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the parent political forum post
 *   where the comment will be posted
 * @param props.body The content and metadata required to create a new political
 *   forum comment
 * @path /politicalForum/citizen/posts/:postId/comments
 * @accessor api.functional.politicalForum.citizen.posts.comments.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
