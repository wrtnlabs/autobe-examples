import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPoliticalForumCommentReport } from "../../../../../structures/IPoliticalForumCommentReport";

/**
 * Submit a report against a specific political forum comment.
 *
 * Citizens can report comments that violate community guidelines by submitting
 * detailed reports through this endpoint. The system automatically prevents
 * duplicate reports from the same citizen on the same comment to avoid abusive
 * reporting patterns. When a report is submitted, it's immediately recorded in
 * the political_forum_comment_reports table and triggers a moderation review
 * workflow.
 *
 * The operation requires the commentId path parameter to identify the target
 * comment and includes a request body with optional reason text and user
 * context. The system validates the citizen's authentication status before
 * processing and ensures the reported comment exists in the
 * political_forum_comments table.
 *
 * This operation does not modify the target comment but creates a new record in
 * political_forum_comment_reports, linking to the reporting citizen (from
 * political_forum_citizens) and the target comment. The system logs these
 * reports for moderation team review and may trigger automated actions based on
 * report volume patterns.
 *
 * All reports submitted via this endpoint are immutable and cannot be edited or
 * deleted after submission. Moderators can view these reports in their
 * dashboard and take appropriate actions including comment removal, warning
 * issuance, or account suspension.
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the target political forum
 *   comment being reported. This must reference an existing comment in the
 *   political_forum_comments table.
 * @param props.body Details of the report being submitted, including optional
 *   reason text and reporting context.
 * @path /politicalForum/citizen/comments/:commentId/reports
 * @accessor api.functional.politicalForum.citizen.comments.reports.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Unique identifier of the target political forum comment being
     * reported. This must reference an existing comment in the
     * political_forum_comments table.
     */
    commentId: string & tags.Format<"uuid">;

    /**
     * Details of the report being submitted, including optional reason text
     * and reporting context.
     */
    body: IPoliticalForumCommentReport.ICreate;
  };
  export type Body = IPoliticalForumCommentReport.ICreate;
  export type Response = IPoliticalForumCommentReport;

  export const METADATA = {
    method: "POST",
    path: "/politicalForum/citizen/comments/:commentId/reports",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/politicalForum/citizen/comments/${encodeURIComponent(props.commentId ?? "null")}/reports`;
  export const random = (): IPoliticalForumCommentReport =>
    typia.random<IPoliticalForumCommentReport>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
