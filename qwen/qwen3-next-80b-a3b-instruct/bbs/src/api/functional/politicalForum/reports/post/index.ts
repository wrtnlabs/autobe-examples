import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPoliticalForumPostReport } from "../../../../structures/IPoliticalForumPostReport";

/**
 * Retrieve a specific post report by its unique identifier.
 *
 * This operation fetches a single post report entity from the
 * political_forum_post_reports table based on the provided reportId. Reports
 * are created when users flag posts as inappropriate or violating community
 * guidelines.
 *
 * A successful response returns the complete post report details including the
 * reported post identifier, the reporter user ID, a description of the
 * violation, timestamps, and current status.
 *
 * Security considerations require this operation to be restricted to
 * authenticated users and moderators, as reports may contain sensitive
 * moderation metadata and private user information. The system ensures that
 * users can only access reports they created or have been granted permission to
 * view. The report ID must be validated against the database to prevent
 * unauthorized access attempts.
 *
 * This operation is typically used in moderation workflows where team members
 * need to review reported content. It supports the company's commitment to
 * responsible content moderation and user safety by providing detailed context
 * for each reported item. The response includes all available information about
 * the report to enable informed moderation decisions.
 *
 * @param props.connection
 * @param props.reportId Unique identifier of the post report to retrieve. This
 *   identifier references a post report entry from the
 *   political_forum_post_reports table.
 * @path /politicalForum/reports/post/:reportId
 * @accessor api.functional.politicalForum.reports.post.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the post report to retrieve. This identifier
     * references a post report entry from the political_forum_post_reports
     * table.
     */
    reportId: string & tags.Format<"uuid">;
  };
  export type Response = IPoliticalForumPostReport;

  export const METADATA = {
    method: "GET",
    path: "/politicalForum/reports/post/:reportId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/politicalForum/reports/post/${encodeURIComponent(props.reportId ?? "null")}`;
  export const random = (): IPoliticalForumPostReport =>
    typia.random<IPoliticalForumPostReport>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reportId")(() => typia.assert(props.reportId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
