/**
 * Retrieve moderation efficiency metrics for the past 30 days.
 *
 * This endpoint provides comprehensive moderation efficiency metrics to help
 * administrators assess the effectiveness of the content moderation team. The
 * system calculates key performance indicators by analyzing reported content
 * and resolution patterns from the political_forum_post_reports and
 * political_forum_comment_reports tables.
 *
 * The operation computes the total number of reported posts and comments, the
 * quantity resolved within 24 hours, and the average time-to-resolution across
 * all reports over the past 30 days. It also calculates the percentage of
 * reports that remain pending versus those that have been reviewed, dismissed,
 * or escalated. This multi-dimensional analysis provides a holistic view of
 * moderation team responsiveness and workload balance.
 *
 * The metrics are derived from the status and created_at/updated_at fields in
 * the political_forum_post_reports and political_forum_comment_reports tables,
 * with date range filters applied to the last 30 days. The system aggregates
 * these reports by status type and calculates resolution rates based on the
 * logic: (resolved_reports / total_reports) * 100.
 *
 * This endpoint has no security restrictions as it exposes aggregated,
 * non-sensitive metrics. Any authenticated user with moderator privileges can
 * access it, but it does not expose individual report details or personal
 * information. It is designed for dashboard consumption by platform
 * administrators.
 *
 * This operation is independent of user_session and citizen tables, as it only
 * aggregates reporting data without linking to specific users. The operation
 * does not modify any data and is purely read-only. Similar dashboard
 * operations exist for user engagement and content growth analytics, which can
 * be called in sequence to provide comprehensive platform health insights.
 *
 * @param props.connection
 * @path /politicalForum/moderator/dashboards/moderation-efficiency
 * @accessor api.functional.politicalForum.moderator.dashboards.moderation_efficiency.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
