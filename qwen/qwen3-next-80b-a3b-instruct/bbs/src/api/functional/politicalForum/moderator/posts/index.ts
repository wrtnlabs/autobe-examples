import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
export * as comments from "./comments/index";

/**
 * Permanently delete a political forum post.
 *
 * This endpoint allows authorized moderators to permanently delete a political
 * forum post. The deletion is immediate and irreversible, meaning the post
 * record is removed entirely from the political_forum_posts table with no
 * possibility of recovery.
 *
 * This operation does not implement soft deletion, as the political_forum_posts
 * table has no soft_delete_column field defined in the Prisma schema.
 * Therefore, the deletion is a hard delete that removes the row entirely from
 * the database. This aligns with the moderation workflow where posts violating
 * community guidelines are removed completely and permanently.
 *
 * The delete operation is restricted to moderators only, as regular citizens
 * cannot delete posts they did not create. Moderators must have appropriate
 * privileges to perform this action, as it constitutes a high-impact system
 * change that affects content availability and user trust.
 *
 * The operation triggers a related moderation action to be recorded in the
 * political_forum_moderation_actions table, which logs the deletion event with
 * the moderator’s ID, the post’s ID, and the reason for deletion (if provided).
 * This audit trail is critical for transparency and compliance.
 *
 * No response body is returned upon successful deletion, following REST
 * conventions for delete operations. A 204 No Content status code is expected
 * from the server. On failure (e.g., unauthorized access or non-existent post),
 * appropriate HTTP 4xx status codes are returned.
 *
 * This operation is tightly coupled with the moderation system: it must be
 * called only after an audit trail has been initiated and it aligns with the
 * political_forum_moderation_status model’s defined moderation states.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the target political forum post to
 *   be deleted
 * @path /politicalForum/moderator/posts/:postId
 * @accessor api.functional.politicalForum.moderator.posts.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the target political forum post to be deleted */
    postId: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/politicalForum/moderator/posts/:postId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/politicalForum/moderator/posts/${encodeURIComponent(props.postId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
