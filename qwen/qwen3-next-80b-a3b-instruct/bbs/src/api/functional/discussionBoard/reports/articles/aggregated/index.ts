import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardArticleAggregatedReport } from "../../../../../structures/IDiscussionBoardArticleAggregatedReport";

/**
 * Retrieve aggregated report statistics for discussion board articles. This
 * operation combines data from the discussion_board_article_reports,
 * discussion_board_article_status_logs, and discussion_board_articles tables to
 * provide comprehensive analytics on article reports, statuses, and overall
 * article metrics.
 *
 * The operation calculates and returns aggregated statistics including total
 * number of articles, count of reported articles, average report count per
 * article, distribution of article statuses, and temporal trends in reporting
 * activity. These aggregated metrics provide system administrators and
 * moderators with actionable insights into content health and moderation
 * effectiveness.
 *
 * Security is maintained by ensuring this operation is publicly accessible
 * since report aggregates do not expose personally identifying information. The
 * operation does not return individual article details or reporter identities,
 * only summarized statistics. This aligns with privacy principles while still
 * delivering valuable operational intelligence.
 *
 * The data is derived from a combination of JOINs between the main article
 * records and their associated reports and status logs. Database constraints
 * ensure data integrity, including foreign key relationships and unique key
 * validations that guarantee accurate aggregation.
 *
 * This operation supports system monitoring requirements and enables moderation
 * teams to identify trending issues, prioritize interventions, and evaluate the
 * effectiveness of community guidelines.
 *
 * Related operations: Discuss article reports (GET /reports/articles), Retrieve
 * individual article (GET /articles/{articleId}).
 *
 * @param props.connection
 * @path /discussionBoard/reports/articles/aggregated
 * @accessor api.functional.discussionBoard.reports.articles.aggregated.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IDiscussionBoardArticleAggregatedReport;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/reports/articles/aggregated",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/reports/articles/aggregated";
  export const random = (): IDiscussionBoardArticleAggregatedReport =>
    typia.random<IDiscussionBoardArticleAggregatedReport>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
