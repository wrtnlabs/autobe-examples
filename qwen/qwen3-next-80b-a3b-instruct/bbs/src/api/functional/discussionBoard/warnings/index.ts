import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardWarning } from "../../../structures/IDiscussionBoardWarning";
import { IPageIDiscussionBoardWarning } from "../../../structures/IPageIDiscussionBoardWarning";

/**
 * Retrieve a filtered list of system-generated warning records from the
 * discussion board platform. This operation operates on the
 * discussion_board_warnings table, which tracks all system-generated warning
 * events related to user behavior, content moderation, and platform policy
 * violations. The operation supports advanced filtering across multiple
 * dimensions including warning severity, affected entity type, warning
 * category, and timestamp range. Results are paginated to handle large datasets
 * efficiently.
 *
 * The warning records represent system-enforced actions or alerts triggered by
 * automated policy enforcement systems rather than user-initiated reports.
 * These warnings are automatically generated based on behavioral analysis,
 * content pattern detection, and compliance monitoring systems.
 *
 * Security considerations include role-based access control where moderators
 * and administrators can view all warnings, while regular citizens can only
 * view warnings affecting their own content or account. The response structure
 * includes full warning metadata including origin system, severity level,
 * affected entity identifiers, and timestamps for audit trail completeness.
 *
 * This operation is critical for platform monitoring and compliance reporting,
 * providing insight into automated enforcement patterns and system health
 * metrics. Related operations include GET /warnings/{warningId} to retrieve
 * individual warning details and PATCH /notifications to manage user
 * notification preferences for warning types.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for filtering
 *   warning records
 * @path /discussionBoard/warnings
 * @accessor api.functional.discussionBoard.warnings.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and pagination parameters for filtering warning
     * records
     */
    body: IDiscussionBoardWarning.IRequest;
  };
  export type Body = IDiscussionBoardWarning.IRequest;
  export type Response = IPageIDiscussionBoardWarning;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/warnings",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/warnings";
  export const random = (): IPageIDiscussionBoardWarning =>
    typia.random<IPageIDiscussionBoardWarning>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
