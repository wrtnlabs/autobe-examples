/**
 * Retrieve a specific system configuration setting from the discussion board's
 * configuration system. This operation fetches the current value of a named
 * configuration parameter based on its unique key identifier.
 *
 * The configuration values are stored in the discussion_board_configurations
 * database table and represent system-wide settings that may be modified
 * without code deployment. Each configuration key acts as a unique identifier
 * for a specific setting, enabling dynamic configuration management across the
 * platform.
 *
 * This API operation serves as the primary interface for retrieving
 * configuration values used by various components of the system, including
 * content moderation rules, user experience preferences, and platform behavior
 * controls. The configuration system allows administrators to adjust platform
 * parameters through administrative interfaces without requiring code
 * deployments or system restarts.
 *
 * The retrieved configuration value is returned in a format compatible with its
 * expected usage context, which may include boolean flags, numeric thresholds,
 * string values, or JSON-encoded configuration objects. Requesting a
 * configuration key that does not exist will return a 404 Not Found response.
 *
 * Changes to configuration values are direct and immediate updates to the
 * record in the database. There is no soft delete behavior or historical
 * versioning. The current value is always the latest value stored in the
 * database.
 *
 * This operation is often used in conjunction with PATCH
 * /configurations/{configKey} for configuration updates and in support of
 * system components that need to dynamically adapt their behavior based on
 * current platform settings. Related operations: Update configuration (PATCH
 * /configurations/{configKey}).
 *
 * @param props.connection
 * @param props.configKey Unique system identifier for the configuration setting
 *   to retrieve. This corresponds to the 'key' field in the
 *   discussion_board_configurations database table and is used to look up the
 *   specific configuration value. The configuration key is a case-sensitive
 *   string that uniquely identifies the setting within the system.
 * @path /discussionBoard/configurations/:configKey
 * @accessor api.functional.discussionBoard.configurations.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
