import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardAttachment } from "../../../structures/IDiscussionBoardAttachment";
import { IPageIDiscussionBoardAttachment } from "../../../structures/IPageIDiscussionBoardAttachment";

/**
 * Retrieve a filtered and paginated list of attachment records from the
 * discussion board system. This operation operates on the
 * discussion_board_attachments table and provides advanced search capabilities
 * for finding attachments based on file type, size range, upload date
 * intervals, associated content ID, and ownership context (article, comment, or
 * user).
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * and sorting options. Attachments can be sorted by creation date, file size,
 * or filename in ascending or descending order. The search functionality
 * enables filtering by exact file extension (e.g., .jpg, .pdf), size range
 * (min/max bytes), and date ranges (created_after, created_before).
 * Additionally, users can filter by the parent content type (article, comment,
 * post) and specific parent IDs to retrieve attachments linked to particular
 * content.
 *
 * Security considerations include rate limiting for search operations and
 * appropriate filtering of sensitive attachment information based on the
 * requesting user's authorization level. Only users with appropriate
 * permissions can access detailed attachment information or retrieve
 * attachments for private content. The operation respects content visibility
 * rules - attachments linked to published content are accessible to users with
 * appropriate view permissions, while attachments linked to unpublished or
 * hidden content are restricted accordingly.
 *
 * This operation integrates with the discussion_board_attachments table as
 * defined in the database schema, incorporating all available fields and
 * relationships to discussion_board_attachment_images and
 * discussion_board_attachment_files. The response includes attachment summary
 * information optimized for list displays, with options to include additional
 * metadata based on authorization level.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for attachment
 *   filtering
 * @path /discussionBoard/attachments
 * @accessor api.functional.discussionBoard.attachments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for attachment filtering */
    body: IDiscussionBoardAttachment.IRequest;
  };
  export type Body = IDiscussionBoardAttachment.IRequest;
  export type Response = IPageIDiscussionBoardAttachment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/attachments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/attachments";
  export const random = (): IPageIDiscussionBoardAttachment.ISummary =>
    typia.random<IPageIDiscussionBoardAttachment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
