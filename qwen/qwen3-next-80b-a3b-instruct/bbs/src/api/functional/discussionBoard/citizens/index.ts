/**
 * Retrieve a filtered and paginated list of discussion board citizens from the
 * system. This operation operates on the discussion_board_citizen table and
 * provides advanced search capabilities for finding citizens based on multiple
 * criteria including partial username matching, registration date ranges, trust
 * score thresholds, and account status.
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * and sorting options. Citizens can be sorted by registration date, trust
 * score, username, or active status in ascending or descending order. Search
 * parameters include partial username matching, account status filters (active,
 * suspended, banned), and minimum trust score thresholds.
 *
 * Security considerations include rate limiting for search operations and
 * appropriate filtering of sensitive citizen information based on the
 * requesting actor's authorization level. Only citizens with appropriate
 * permissions can access detailed account information, while basic citizen
 * lists may be available to authenticated users.
 *
 * This operation integrates with the discussion_board_citizen table as defined
 * in the database schema, incorporating all available citizen fields including
 * username, email, registration timestamp, trust_score, and account_status
 * fields. The response includes only essential citizen summary information
 * optimized for list displays, with options to include additional details based
 * on authorization level. Related operations: Create citizen (POST
 * /discussion_board/citizens), Retrieve citizen by ID (GET
 * /discussion_board/citizens/{citizenId}).
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for citizen
 *   filtering
 * @path /discussionBoard/citizens
 * @accessor api.functional.discussionBoard.citizens.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for citizen filtering */
    body: IDiscussionBoardCitizen.IRequest;
  };
  export type Body = IDiscussionBoardCitizen.IRequest;
  export type Response = IPageIDiscussionBoardCitizen.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/citizens",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/citizens";
  export const random = (): IPageIDiscussionBoardCitizen.ISummary =>
    typia.random<IPageIDiscussionBoardCitizen.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
