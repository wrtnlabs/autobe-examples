import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardAuthenticationLog } from "../../../../structures/IDiscussionBoardAuthenticationLog";

/**
 * Retrieve the login history for a specific citizen. This operation fetches all
 * authentication events associated with the specified citizen from the
 * discussion_board_authentication_logs table, ordered by timestamp in
 * descending order to show the most recent logins first. The system tracks
 * login attempts, successful authentications, and failed attempts as separate
 * audit events.
 *
 * The operation retrieves the citizen_id path parameter matching the citizen
 * record in the discussion_board_citizen table. The citizen_id used in the path
 * parameter corresponds to the unique identifier of the citizen, which is
 * stored as the primary key in the discussion_board_citizen table with the
 * field name "id". This operation does not return any personally identifiable
 * information beyond authentication events.
 *
 * Security: This endpoint is publicly accessible without authentication for
 * verified citizen IDs to allow citizens to review their own login history.
 * However, the citizen_id parameter must exactly match an existing record in
 * the discussion_board_citizen table. Unauthorized users cannot access other
 * citizens' login history.
 *
 * This design follows the principle of minimal permission escalation - exposing
 * login history allows users to detect unauthorized access without requiring
 * elevated privileges. The operation returns only timestamped events which are
 * immutable records of system activity. Update or deletion of login history is
 * not permitted under any circumstances.
 *
 * Related operations: Authentication events can be correlated with user
 * activity patterns to detect anomalous behavior. This endpoint can be used in
 * conjunction with the /citizens/{citizenId} endpoint to verify account
 * ownership before displaying authentication events.
 *
 * @param props.connection
 * @param props.citizenId Unique identifier of the target citizen whose login
 *   history is being requested. This ID must match exactly with the id field in
 *   the discussion_board_citizen table and is stored as a UUID.
 * @path /discussionBoard/citizens/:citizenId/login-history
 * @accessor api.functional.discussionBoard.citizens.login_history.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target citizen whose login history is being
     * requested. This ID must match exactly with the id field in the
     * discussion_board_citizen table and is stored as a UUID.
     */
    citizenId: string;
  };
  export type Response = IDiscussionBoardAuthenticationLog;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/citizens/:citizenId/login-history",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/citizens/${encodeURIComponent(props.citizenId ?? "null")}/login-history`;
  export const random = (): IDiscussionBoardAuthenticationLog =>
    typia.random<IDiscussionBoardAuthenticationLog>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("citizenId")(() => typia.assert(props.citizenId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
