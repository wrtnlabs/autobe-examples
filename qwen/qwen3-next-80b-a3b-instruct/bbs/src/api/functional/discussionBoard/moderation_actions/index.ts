/**
 * Retrieve a specific moderation action record from the discussion board
 * system. This operation accesses the discussion_board_moderation_actions table
 * and returns detailed information about a particular moderation event,
 * including the type of action taken, the target content, the moderator
 * responsible, the timestamp, and any associated reason or metadata. This
 * endpoint provides essential audit trail information for compliance, dispute
 * resolution, and moderation transparency.
 *
 * The operation retrieves a single moderator action record identified by its
 * unique actionId. Each record contains the full context of the moderation
 * decision, including the actor (moderator), the target article or comment, the
 * action type (e.g., approval, rejection, deletion), and any comments or
 * justification provided during the moderation process. This information is
 * critical for users who wish to understand why specific content was modified
 * or removed, and for moderators who need to review their own actions.
 *
 * Security is enforced through authorization rules that restrict access to
 * moderator actions based on user role. Regular citizens may only view actions
 * taken on their own content, while moderators and administrators have broader
 * access privileges to review actions across the platform. The operation
 * integrates with the discussion_board_moderation_actions table as defined in
 * the database schema, using the actionId field as the primary identifier. The
 * returned data includes all fields necessary for accountability, including the
 * timestamp of the action and the moderator's user identifier. This endpoint
 * supports platform transparency and user trust by making moderation decisions
 * visible and verifiable to those with appropriate permissions.
 *
 * @param props.connection
 * @param props.actionId Unique identifier of the moderation action to retrieve.
 *   This UUID references the primary key of the
 *   discussion_board_moderation_actions table.
 * @path /discussionBoard/moderation-actions/:actionId
 * @accessor api.functional.discussionBoard.moderation_actions.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the moderation action to retrieve. This UUID
     * references the primary key of the discussion_board_moderation_actions
     * table.
     */
    actionId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardModerationAction;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/moderation-actions/:actionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderation-actions/${encodeURIComponent(props.actionId ?? "null")}`;
  export const random = (): IDiscussionBoardModerationAction =>
    typia.random<IDiscussionBoardModerationAction>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("actionId")(() => typia.assert(props.actionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
