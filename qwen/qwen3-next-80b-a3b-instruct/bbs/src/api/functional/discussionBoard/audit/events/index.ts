import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardAuditEvent } from "../../../../structures/IDiscussionBoardAuditEvent";

/**
 * Retrieve a specific audit event record from the system. This operation
 * accesses the discussion_board_audit_events table, which stores immutable
 * records of system actions and security events for compliance and monitoring
 * purposes. Each audit event represents a system-generated record captured at
 * the time of user or system activity, including timestamps, actor identifiers,
 * event types, and context details.
 *
 * Security considerations ensure these records are read-only and cannot be
 * modified after creation, preserving data integrity for audit trails. The
 * operation returns the complete audit event details including event type,
 * actor ID, timestamp, and associated context. Audit logs are critical for
 * forensic investigations, regulatory compliance, and security monitoring.
 *
 * No user input modifies these records - they are created automatically by the
 * system during any action that triggers an audit event (login attempts,
 * content modifications, administrative actions, etc.). This operation supports
 * system monitoring and incident response by providing access to the historical
 * audit trail.
 *
 * Related operations: None - audit events are designed as append-only immutable
 * records. Creating or updating these records should never be exposed via API
 * as they violate the core audit principle of immutability.
 *
 * @param props.connection
 * @param props.eventId Unique identifier of the audit event record to retrieve
 * @path /discussionBoard/audit/events/:eventId
 * @accessor api.functional.discussionBoard.audit.events.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the audit event record to retrieve */
    eventId: string;
  };
  export type Response = IDiscussionBoardAuditEvent;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/audit/events/:eventId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/audit/events/${encodeURIComponent(props.eventId ?? "null")}`;
  export const random = (): IDiscussionBoardAuditEvent =>
    typia.random<IDiscussionBoardAuditEvent>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("eventId")(() => typia.assert(props.eventId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
