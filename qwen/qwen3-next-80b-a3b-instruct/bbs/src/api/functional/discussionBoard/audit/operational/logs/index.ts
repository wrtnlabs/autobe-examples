export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPageIDiscussionBoardOperationalLog;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/audit/operational/logs",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/audit/operational/logs";
  export const random = (): IPageIDiscussionBoardOperationalLog =>
    typia.random<IPageIDiscussionBoardOperationalLog>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
