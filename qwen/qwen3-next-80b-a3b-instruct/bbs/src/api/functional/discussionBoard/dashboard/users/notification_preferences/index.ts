import { IDiscussionBoardNotificationPreferences } from "../../../../../structures/IDiscussionBoardNotificationPreferences";

/**
 * Retrieve the notification preferences for a specific user on the discussion
 * board platform. This operation accesses the
 * discussion_board_notification_preferences table from the database schema,
 * which stores user-specific notification configuration settings including
 * email, in-app, and push notification toggles for various event types such as
 * replies, mentions, and moderation actions.
 *
 * The operation requires the userId path parameter to identify the target user,
 * which must correspond to a valid citizen entry in the
 * discussion_board_citizen table. The returned preferences reflect the user's
 * personal configuration stored in the notification_preferences table and are
 * private to that individual.
 *
 * Security: This endpoint is accessible to the user themselves or
 * administrators due to the sensitive nature of notification preferences. User
 * privacy is preserved - notification preferences contain no personally
 * identifiable information beyond the user ID reference, and are not exposed to
 * other users. The operation returns only the preferences for the authenticated
 * user.
 *
 * Business logic: Preferences are persisted as boolean flags for different
 * notification types. System defaults are applied when preferences are not
 * explicitly set by the user. This endpoint does not modify preferences - it is
 * a read-only operation that returns the current configuration.
 *
 * Related operations: To update preferences, use PATCH
 * /dashboard/users/{userId}/notification-preferences. To view all notifications
 * received by a user, use GET /dashboard/users/{userId}/notifications.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the target citizen user whose
 *   notification preferences are being retrieved
 * @path /discussionBoard/dashboard/users/:userId/notification-preferences
 * @accessor api.functional.discussionBoard.dashboard.users.notification_preferences.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target citizen user whose notification
     * preferences are being retrieved
     */
    userId: string;
  };
  export type Response = IDiscussionBoardNotificationPreferences;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/dashboard/users/:userId/notification-preferences",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/dashboard/users/${encodeURIComponent(props.userId ?? "null")}/notification-preferences`;
  export const random = (): IDiscussionBoardNotificationPreferences =>
    typia.random<IDiscussionBoardNotificationPreferences>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
