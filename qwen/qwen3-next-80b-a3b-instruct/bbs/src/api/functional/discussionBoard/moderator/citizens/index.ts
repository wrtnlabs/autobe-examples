/**
 * Retrieve detailed information about a specific citizen account from the
 * discussion board system. This operation accesses the discussion_board_citizen
 * model in the database schema and returns comprehensive profile data including
 * identification, registration details, and account status.
 *
 * The operation is designed for authenticated users and administrators who need
 * to view individual citizen profiles. It returns all publicly accessible
 * information about the citizen while respecting privacy restrictions. The
 * response includes the citizen's unique identifier, registration timestamp,
 * trust score, violation history, and suspension status.
 *
 * This operation is used for citizen profile viewing, administrative
 * investigations, and customer support scenarios where specific user details
 * are required. It complements the search operation on /citizens which provides
 * listing functionality.
 *
 * Key related operations:
 *
 * - POST /citizens for creating new citizen accounts
 * - PATCH /citizens when searching or filtering citizen records
 * - PUT /citizens/{citizenCode} for updating citizen profile information
 * - DELETE /citizens/{citizenCode} for removing citizen accounts (with
 *   appropriate moderation)
 *
 * All data returned is governed by the discussion_board_citizen table structure
 * and should not assume the presence of fields that are not explicitly defined
 * in the schema.
 *
 * @param props.connection
 * @param props.citizenId Unique identifier of the target citizen account in
 *   UUIDv4 format, referencing the primary key of the discussion_board_citizen
 *   table in the database schema.
 * @path /discussionBoard/moderator/citizens/:citizenId
 * @accessor api.functional.discussionBoard.moderator.citizens.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target citizen account in UUIDv4 format,
     * referencing the primary key of the discussion_board_citizen table in
     * the database schema.
     */
    citizenId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardCitizen.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/moderator/citizens/:citizenId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/citizens/${encodeURIComponent(props.citizenId ?? "null")}`;
  export const random = (): IDiscussionBoardCitizen.ISummary =>
    typia.random<IDiscussionBoardCitizen.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("citizenId")(() => typia.assert(props.citizenId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
