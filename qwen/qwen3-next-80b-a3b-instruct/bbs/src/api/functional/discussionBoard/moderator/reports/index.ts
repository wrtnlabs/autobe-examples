/**
 * Retrieve a specific report by its ID.
 *
 * Fetch detailed information about a specific content report by its unique
 * identifier. This operation retrieves the complete report record from the
 * discussion_board_reports table, including the type of content reported
 * (either a post or comment), the actor type who submitted the report, the
 * complaint reason provided, and the current status of the report.
 *
 * The application must determine whether the report pertains to a post or
 * comment by examining the reported_post_id and reported_comment_id fields.
 * When reported_post_id is populated, the system must join with the
 * discussion_board_posts table to retrieve post details. When
 * reported_comment_id is populated, the system must join with the
 * discussion_board_comments table to retrieve comment details. The actor_type
 * field indicates whether the report was initiated by a citizen or moderator,
 * which determines which lookup table to use
 * (discussion_board_report_of_citizens or
 * discussion_board_report_of_moderators).
 *
 * This operation supports the moderation workflow by providing comprehensive
 * context for reported content. Moderators rely on this endpoint to review the
 * nature of the complaint, assess its validity, and determine appropriate
 * actions such as dismissing the report, editing the content, or deleting it
 * according to community guidelines.
 *
 * Access to this information is restricted to authenticated moderators.
 * Citizens cannot use this endpoint to view report details.
 *
 * Any user attempting to access this endpoint without being authenticated as a
 * moderator will receive a 403 Forbidden response. The system must validate the
 * requesting user's role before returning any report data.
 *
 * @param props.connection
 * @param props.reportId Unique identifier of the report to retrieve (UUID
 *   format)
 * @path /discussionBoard/moderator/reports/:reportId
 * @accessor api.functional.discussionBoard.moderator.reports.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the report to retrieve (UUID format) */
    reportId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardReport;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/moderator/reports/:reportId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/reports/${encodeURIComponent(props.reportId ?? "null")}`;
  export const random = (): IDiscussionBoardReport =>
    typia.random<IDiscussionBoardReport>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reportId")(() => typia.assert(props.reportId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

