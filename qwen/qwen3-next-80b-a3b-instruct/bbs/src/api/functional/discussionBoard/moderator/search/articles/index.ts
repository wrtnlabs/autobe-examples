/**
 * Search for published discussion board articles across multiple criteria
 * including title, content, author, and attached files.
 *
 * This operation enables citizens and moderators to find articles through
 * comprehensive text-based search across all published articles in the system.
 * The search functionality matches against article titles, article content,
 * citizen username, and attached file names, providing a unified search
 * experience for users.
 *
 * The operation supports pagination with configurable page sizes and sorting
 * options. Search results are returned in descending chronological order by
 * publication time, with matching keywords highlighted in the results for
 * improved usability. The search is case-insensitive and uses partial matching
 * for flexible query patterns.
 *
 * Security and authorization: This search operation is available to both
 * authenticated citizens and moderators, with no additional permissions
 * required beyond basic system access. The search respects content visibility
 * rules, returning only articles that are in published state and have not been
 * hidden by moderators.
 *
 * This operation integrates with the discussion_board_articles table as defined
 * in the database schema, incorporating all available article fields and
 * relationships. When article titles or content contain matching search terms,
 * those articles appear in the results. If search terms match an attached
 * filename (image or document), the article containing that attachment is also
 * included. The operation does not return draft articles, hidden articles, or
 * articles with pending publication status.
 *
 * Related operations: GET /articles/{articleId} (to view detailed article),
 * PATCH /articles (to list articles with filters).
 *
 * @param props.connection
 * @param props.body Search parameters and pagination controls for article
 *   filtering and retrieval
 * @path /discussionBoard/moderator/search/articles
 * @accessor api.functional.discussionBoard.moderator.search.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search parameters and pagination controls for article filtering and
     * retrieval
     */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/search/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/moderator/search/articles";
  export const random = (): IPageIDiscussionBoardArticle.ISummary =>
    typia.random<IPageIDiscussionBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
