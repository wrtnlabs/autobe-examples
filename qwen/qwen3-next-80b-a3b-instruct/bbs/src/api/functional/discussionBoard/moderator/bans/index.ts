/**
 * Retrieve a specific ban record from the system. This operation fetches a
 * single ban record by its unique identifier from the discussion_board_bans
 * table, which logs all user bans imposed by moderators.
 *
 * The ban record includes the banned citizen's identifier, the moderator who
 * imposed the ban, the reason for the ban, the start date of the ban, and
 * whether the ban is permanent. Temporary bans may include an end date, but
 * permanent bans have no expiration. This endpoint provides detailed audit
 * information about moderation actions taken on the platform.
 *
 * Security: Only authorized moderators can access this information, and the
 * operation is designed to be accessed only for audit and administrative
 * purposes. The permanent flag in the ban record determines whether the ban is
 * temporary or permanent, and this field is essential for understanding the
 * duration and scope of the moderation action.
 *
 * Relationships: This operation is tightly coupled with the
 * discussion_board_bans table and the discussion_board_citizen and
 * discussion_board_moderator tables, as it references the user who was banned
 * and the moderator who issued the ban. This endpoint supports the moderation
 * review and appeal workflows described in the requirements document.
 *
 * Note: This endpoint should be used for administrative oversight, internal
 * investigations, and compliance reporting, not for general user-facing
 * functionality.
 *
 * @param props.connection
 * @param props.banId Unique identifier of the ban record to retrieve
 *   (system-generated UUID)
 * @path /discussionBoard/moderator/bans/:banId
 * @accessor api.functional.discussionBoard.moderator.bans.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
