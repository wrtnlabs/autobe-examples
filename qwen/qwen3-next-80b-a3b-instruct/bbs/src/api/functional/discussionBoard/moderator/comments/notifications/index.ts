import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPageIDiscussionBoardNotificationRecord } from "../../../../../structures/IPageIDiscussionBoardNotificationRecord";

/**
 * Retrieve notification records associated with a specific discussion board
 * comment. This operation operates on the discussion_board_notification_records
 * table and retrieves all system-generated notifications linked to a target
 * comment ID.
 *
 * The operation supports filtering and pagination of notification records for a
 * specific comment, returning comprehensive metadata about each notification
 * including type, target actor, delivery status, and creation timestamp.
 *
 * Security: Only authenticated citizens and moderators can access notifications
 * for comments they are associated with. The system automatically enforces
 * ownership validation by cross-referencing the comment's author or recipient
 * with the authenticated user.
 *
 * Implementation detail: This operation performs a JOIN between
 * discussion_board_comments and discussion_board_notification_records tables,
 * filtering by the comment's UUID identifier. The notification records are
 * ordered by creation timestamp descending to present the most recent
 * notifications first.
 *
 * Related operations: To view all notifications for a user, use PATCH
 * /notifications. To mark a notification as read, use PATCH
 * /notifications/{notificationId}/read.
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the target comment. This field
 *   references the discussion_board_comments table's id field and must be a
 *   valid UUID.
 * @path /discussionBoard/moderator/comments/:commentId/notifications
 * @accessor api.functional.discussionBoard.moderator.comments.notifications.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target comment. This field references the
     * discussion_board_comments table's id field and must be a valid UUID.
     */
    commentId: string & tags.Format<"uuid">;
  };
  export type Response = IPageIDiscussionBoardNotificationRecord;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/comments/:commentId/notifications",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/comments/${encodeURIComponent(props.commentId ?? "null")}/notifications`;
  export const random = (): IPageIDiscussionBoardNotificationRecord =>
    typia.random<IPageIDiscussionBoardNotificationRecord>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
