import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardBan } from "../../../../../structures/IDiscussionBoardBan";

/**
 * Create a new moderation ban record on the discussion board system. This
 * operation interacts with the discussion_board_bans table in the database
 * schema and allows privileged moderators to issue temporary or permanent bans
 * against citizen accounts for policy violations. The ban record is permanently
 * stored in the database as an immutable audit record, regardless of whether it
 * is temporary or permanent.
 *
 * The operation creates a permanent record that includes the banned citizen's
 * ID, the moderator's ID, the reason for the ban, the start date and optional
 * end date for temporary bans, and any additional notes. All ban records are
 * preserved indefinitely in the database for compliance and audit purposes
 * through the system's moderation audit trails.
 *
 * Security considerations require this operation to be restricted to
 * moderator-level actors only. The moderation system enforces role-based access
 * control, and this endpoint is intentionally not available to regular citizens
 * or any other user type.
 *
 * This operation does not update, delete, or modify existing bans - it only
 * creates new ones. The ban records are hard records in the database with no
 * soft-delete mechanism; deletion is not possible and records remain
 * permanently in the database.
 *
 * This operation is complementary to other moderation endpoints: users may
 * appeal a ban via POST /moderation/appeals, and moderators can view existing
 * bans through GET /moderation/bans with search parameters. All banned citizens
 * are automatically restricted from posting, commenting, and other interactive
 * features upon successful creation of this ban record.
 *
 * @param props.connection
 * @param props.body Data required to create a moderation ban record on the
 *   discussion board system
 * @path /discussionBoard/moderator/moderation/bans
 * @accessor api.functional.discussionBoard.moderator.moderation.bans.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Data required to create a moderation ban record on the discussion
     * board system
     */
    body: IDiscussionBoardBan.ICreate;
  };
  export type Body = IDiscussionBoardBan.ICreate;
  export type Response = IDiscussionBoardBan;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/moderator/moderation/bans",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/moderator/moderation/bans";
  export const random = (): IDiscussionBoardBan =>
    typia.random<IDiscussionBoardBan>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
