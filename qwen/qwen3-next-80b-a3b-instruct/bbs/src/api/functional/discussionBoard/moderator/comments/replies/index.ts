import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Permanently removes a specific reply from the discussion board. This
 * operation directly targets the discussion_board_comment_replies table in the
 * database, eliminating the reply record and its association with the parent
 * comment. The reply is irreversibly deleted from the system with no
 * possibility of recovery.
 *
 * Security and authorization: Only the original author of the reply or a
 * moderator can delete a reply. The system verifies the JWT authentication
 * token against the reply's author_id field in the database. If the
 * authenticated user is not the author, the system checks if they have
 * moderator privileges. Unauthorized deletion attempts result in a 403
 * Forbidden response.
 *
 * This operation is irreversible. Once a reply is deleted, it cannot be
 * restored, and any references to it become invalid. All related notifications,
 * votes, and report records associated with the reply are also automatically
 * purged to maintain data integrity.
 *
 * Note: This is a hard delete operation. Although some systems use soft
 * deletes, this implementation implements permanent deletion as specified by
 * the database schema and business requirements.
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the parent comment to which this
 *   reply belongs. This parameter must match the comment_id field in the
 *   database schema.
 * @param props.replyId Unique identifier of the reply to be deleted. This
 *   parameter must match the id field in the discussion_board_comment_replies
 *   table.
 * @path /discussionBoard/moderator/comments/:commentId/replies/:replyId
 * @accessor api.functional.discussionBoard.moderator.comments.replies.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the parent comment to which this reply belongs.
     * This parameter must match the comment_id field in the database
     * schema.
     */
    commentId: string;

    /**
     * Unique identifier of the reply to be deleted. This parameter must
     * match the id field in the discussion_board_comment_replies table.
     */
    replyId: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/moderator/comments/:commentId/replies/:replyId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/comments/${encodeURIComponent(props.commentId ?? "null")}/replies/${encodeURIComponent(props.replyId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
      assert.param("replyId")(() => typia.assert(props.replyId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
