/**
 * Update an existing attachment in the discussion board system. This operation
 * modifies the attachment metadata including file location (file_url), file
 * type (content_type), file size (file_size), and description. The operation
 * operates on the discussion_board_attachments table and is accessible to both
 * citizens (regular users who created the attachment) and moderators (who can
 * manage any attachment).
 *
 * The attachment entity supports file uploads and image uploads through
 * attachments. When an attachment is updated, the system validates that the
 * user has permission to modify the attachment (ownership check for citizens,
 * elevated permissions for moderators). The object_id field in the attachment
 * must reference a valid entity in the system, such as an article or comment.
 * The updated_at timestamp is automatically set to the current time. Related
 * operations: GET /attachments/{attachmentId} to retrieve attachment details,
 * DELETE /attachments/{attachmentId} to remove the attachment from the system.
 *
 * This operation is critical for user experience as it allows users to maintain
 * the accuracy of their content submissions and allows moderators to correct
 * unauthorized or inaccurate metadata. The system ensures that updates do not
 * disrupt existing references to the attachment by maintaining the attachment's
 * unique ID across updates.
 *
 * @param props.connection
 * @param props.attachmentId Unique identifier of the target attachment
 * @param props.body Update parameters for the attachment including description,
 *   file_url, content_type, file_size, and object_id
 * @path /discussionBoard/moderator/attachments/:attachmentId
 * @accessor api.functional.discussionBoard.moderator.attachments.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
