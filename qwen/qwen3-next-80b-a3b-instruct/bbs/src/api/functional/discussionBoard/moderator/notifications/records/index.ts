/**
 * Retrieve a specific notification record from the system's audit trail. This
 * operation accesses the discussion_board_notification_records table, which
 * stores system-generated notifications with metadata including recipient,
 * type, content, and delivery status. Each notification record represents a
 * discrete system notification delivered to a citizen, moderator, or system
 * process.
 *
 * The operation retrieves a single notification record by its unique identifier
 * (recordId), returning the complete notification payload, delivery metadata,
 * and audit context. Notification records are immutable system-generated events
 * that are never modified or deleted, and exist solely for audit, compliance,
 * and user notification tracking purposes.
 *
 * Security: Access to notification records is restricted to the recipient user
 * only. The system validates that the authenticated user's ID matches the
 * recipient_id field in the notification record. Administrators can access all
 * notification records for auditing purposes.
 *
 * Implementation note: This operation returns only the notification record
 * itself - no additional user or content context is included in the response.
 * Related entities (like the triggering article or comment) must be retrieved
 * through separate operations when needed. This ensures optimal performance and
 * prevents unintended data exposure.
 *
 * Related operations:
 *
 * - GET /notifications/preferences - View notification preferences
 * - GET /notifications/records - List notification records
 * - PATCH /notifications/read-status - Mark notifications as read
 *
 * @param props.connection
 * @param props.recordId Unique identifier of the target notification record
 * @path /discussionBoard/moderator/notifications/records/:recordId
 * @accessor api.functional.discussionBoard.moderator.notifications.records.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target notification record */
    recordId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardNotificationRecord;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/moderator/notifications/records/:recordId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/notifications/records/${encodeURIComponent(props.recordId ?? "null")}`;
  export const random = (): IDiscussionBoardNotificationRecord =>
    typia.random<IDiscussionBoardNotificationRecord>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("recordId")(() => typia.assert(props.recordId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

