/**
 * Create a new moderation warning for a citizen in the discussion board system.
 * This operation allows moderators to issue explicit warnings to citizens for
 * policy violations, documenting the violation reason and directing the citizen
 * to review community guidelines. The warning is stored in the
 * discussion_board_warnings table and creates an audit trail of moderator
 * actions for accountability.
 *
 * Warnings are permanent audit records with no expiration. Each warning
 * contributes to a citizen's violation count, which is used in reputation
 * scoring to determine suspension eligibility. Warnings cannot be removed or
 * modified after creation.
 *
 * Security: Only users with moderator privileges can issue warnings. The system
 * validates that the target citizen exists and is not already permanently
 * banned. A warning does not immediately affect a user's account status but
 * accumulates as part of a reputation system.
 *
 * The operation supports complex editor features, including formatting options
 * and file attachments for evidence, which are stored in the
 * discussion_board_attachment_files and discussion_board_attachment_images
 * tables.
 *
 * Related operations: View warnings (GET /moderation/warnings), List warnings
 * by citizen (PATCH /moderation/warnings/citizen/{citizenId}), and Delete
 * warning (DELETE /moderation/warnings/{warningId}).
 *
 * @param props.connection
 * @param props.body Creation data for a new moderation warning including target
 *   citizen, violation description, and severity level.
 * @path /discussionBoard/moderator/moderation/warnings
 * @accessor api.functional.discussionBoard.moderator.moderation.warnings.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
