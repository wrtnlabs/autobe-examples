import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Permanently delete a specific notification template from the system.
 *
 * This operation removes a notification template from the
 * discussion_board_notification_templates table in the database. The template
 * can be deleted by any authenticated citizen user if they are the original
 * creator of the template, or by a moderator with elevated privileges. This is
 * a hard delete operation that permanently removes the record and cannot be
 * undone.
 *
 * The operation validates that the template ID provided in the path parameter
 * corresponds to an existing notification template. If the requesting user is a
 * citizen, the system checks that the template was created by the same user
 * before allowing deletion. Moderator users can delete any template regardless
 * of ownership.
 *
 * Security considerations include preventing unauthorized deletion of system
 * templates and enforcing proper ownership verification. The system maintains
 * an audit trail of all template deletions through the
 * discussion_board_moderation_logs table for compliance purposes.
 *
 * This operation is associated with the discussion_board_notification_templates
 * table and does not cascade to other tables since notification templates are
 * standalone definitional records.
 *
 * Related operations: GET /notifications/templates for listing templates, PUT
 * /notifications/templates/{templateId} for updating templates, POST
 * /notifications/templates for creating new templates.
 *
 * @param props.connection
 * @param props.templateId Unique identifier of the notification template to be
 *   deleted
 * @path /discussionBoard/moderator/notifications/templates/:templateId
 * @accessor api.functional.discussionBoard.moderator.notifications.templates.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the notification template to be deleted */
    templateId: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/moderator/notifications/templates/:templateId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/notifications/templates/${encodeURIComponent(props.templateId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("templateId")(() => typia.assert(props.templateId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
