/**
 * Retrieve a detailed, paginated list of all comment report aggregations and
 * associated moderation details on the discussion board platform. This
 * operation combines data from multiple core entities including
 * discussion_board_comment_reports, discussion_board_comments,
 * discussion_board_reports, and discussion_board_article_reports to provide
 * comprehensive insight into community moderation activity.
 *
 * The endpoint returns a unified view of all comment report instances across
 * the platform, including the original comment content, reporter information,
 * moderation actions taken, and the current status of each report. Data is
 * aggregated and structured for operational review, enabling moderators to
 * efficiently assess patterns of abuse, identify repeat offenders, and validate
 * moderation decisions. The operation supports pagination and filtering for
 * large-scale moderation workflows.
 *
 * Each record in the response contains full context: the reported comment's
 * text and metadata, the reporter's identity and trust score, the reason for
 * the report, the timeline of moderation review, and any actions taken
 * (dismiss, warn, remove, ban). This integration avoids the need for multiple
 * API calls to gather moderation context and ensures moderators have complete
 * visibility into comment moderation issues.
 *
 * Security and authorization: This operation is restricted to moderator actors
 * only. Regular users cannot access this endpoint. The operation does not
 * return sensitive user data unrelated to moderation actions and strictly
 * follows the platform's privacy policies and data retention guidelines.
 *
 * @param props.connection
 * @path /discussionBoard/moderator/reports/comments/full
 * @accessor api.functional.discussionBoard.moderator.reports.comments.full.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPageIDiscussionBoardCommentReportSummary;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/moderator/reports/comments/full",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/moderator/reports/comments/full";
  export const random = (): IPageIDiscussionBoardCommentReportSummary =>
    typia.random<IPageIDiscussionBoardCommentReportSummary>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
