import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardModerator } from "../../../../../structures/IDiscussionBoardModerator";

/**
 * Retrieve the current status of a specific moderator account. This operation
 * fetches the moderation status from the discussion_board_moderator table,
 * which tracks moderator permissions and activity level for the discussion
 * board platform.
 *
 * The returned status indicates whether the moderator account is active,
 * suspended, or has restricted privileges based on compliance with community
 * guidelines. Status overrides may be applied based on the moderator's history
 * of moderation actions such as report compliance, post removal consistency,
 * and appeal resolution.
 *
 * Security considerations include enforcing that only administrators can view
 * or modify moderator statuses, while other moderators may only view their own
 * status. Access is restricted to authenticated moderator users whose own
 * account has been confirmed and activated in the system.
 *
 * This operation is designed to be low-latency since moderator status checks
 * may occur during content review workflows. The status field is cached for
 * performance, but refreshed whenever moderator permissions are modified in the
 * system.
 *
 * Related operations include: POST /moderators/{moderatorId}/status (to update
 * status), PATCH /moderators (to search for moderators by status), and GET
 * /moderators/{moderatorId} (for full moderator profile details).
 *
 * @param props.connection
 * @param props.moderatorId Unique identifier of the target moderator account
 *   whose status is being retrieved
 * @path /discussionBoard/moderator/moderators/:moderatorId/status
 * @accessor api.functional.discussionBoard.moderator.moderators.status.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target moderator account whose status is
     * being retrieved
     */
    moderatorId: string;
  };
  export type Response = IDiscussionBoardModerator;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/moderator/moderators/:moderatorId/status",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/moderators/${encodeURIComponent(props.moderatorId ?? "null")}/status`;
  export const random = (): IDiscussionBoardModerator =>
    typia.random<IDiscussionBoardModerator>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("moderatorId")(() => typia.assert(props.moderatorId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
