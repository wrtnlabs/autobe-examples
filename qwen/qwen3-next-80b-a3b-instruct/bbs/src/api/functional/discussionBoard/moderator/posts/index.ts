/**
 * Update an existing post on the discussion board. This operation modifies the
 * content, title, or other editable fields of a post identified by its postId.
 * The operation requires the user to be authenticated with the appropriate
 * permissions, as only the original author or a moderator can update a post.
 *
 * The update is applied to the discussion_board_articles table in the database.
 * All fields in the request body must correspond to columns defined in this
 * schema, including title, content, and visibility settings. The operation
 * validates that the post exists and the requesting user has ownership or
 * administrative rights before applying changes. The database enforces
 * referential integrity and ensures the update does not violate any constraints
 * defined in the schema.
 *
 * Security considerations include role-based access control: ordinary citizens
 * can only modify their own posts, while moderators can update any post. The
 * operation logs the modification in the discussion_board_article_status_logs
 * table to maintain an audit trail for compliance purposes. Rate limiting
 * applies to prevent abuse of this endpoint. This operation may trigger
 * system-level notifications to subscribers if the post content changes
 * significantly.
 *
 * Related operations: GET /posts/{postId} to retrieve post details, PATCH
 * /posts to search for posts, DELETE /posts/{postId} to permanently remove a
 * post.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the target post to update (global
 *   scope)
 * @param props.body Updated content and metadata for the post being modified
 * @path /discussionBoard/moderator/posts/:postId
 * @accessor api.functional.discussionBoard.moderator.posts.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /** Unique identifier of the target post to update (global scope) */
    postId: string & tags.Format<"uuid">;

    /** Updated content and metadata for the post being modified */
    body: IDiscussionBoardArticle.IUpdate;
  };
  export type Body = IDiscussionBoardArticle.IUpdate;
  export type Response = IDiscussionBoardArticle;

  export const METADATA = {
    method: "PUT",
    path: "/discussionBoard/moderator/posts/:postId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/posts/${encodeURIComponent(props.postId ?? "null")}`;
  export const random = (): IDiscussionBoardArticle =>
    typia.random<IDiscussionBoardArticle>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

