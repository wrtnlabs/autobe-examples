/**
 * Update an existing article on the discussion board. This operation allows
 * authorized users to modify the title, content, or other editable fields of an
 * article that has been previously published.
 *
 * The article entity is linked to the discussion_board_articles database table,
 * which stores all article metadata including the author ID, publication
 * timestamp, and current status (draft, published, pending, etc.). Only the
 * author of the article (citizen actor) or a moderator with appropriate
 * privileges can perform this update. The operation validates that the article
 * exists and is not in a locked state (such as archived or deleted).
 *
 * When an article is updated, the system automatically tracks this change in
 * the discussion_board_article_status_logs table through an audit trail,
 * recording the timestamp, actor, and changes made. This audit mechanism
 * ensures accountability and enables moderation review if the updated content
 * violates community guidelines. The update operation does not affect the
 * article's creation date or original author information, preserving the
 * article's provenance.
 *
 * This operation is part of the article lifecycle managed by the
 * discussion_board_articles table and its related metadata tables. It is paired
 * with the GET /articles/{articleId} operation for retrieving article details
 * and DELETE /articles/{articleId} for removing articles entirely. The update
 * operation respects the article's current status: articles in 'draft' status
 * can be freely edited, while articles in 'published' status remain accessible
 * to the public while being modifiable only by their owner or administrators.
 *
 * Note: This operation does not handle media attachments directly; those are
 * managed through separate PUT operations on the related media tables
 * (discussion_board_article_images, discussion_board_article_files, etc.).
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article. The articleId
 *   is a UUID that corresponds to the primary key of the
 *   discussion_board_articles table.
 * @param props.body Update data for the article with new values for editable
 *   fields.
 * @path /discussionBoard/moderator/articles/:articleId
 * @accessor api.functional.discussionBoard.moderator.articles.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
