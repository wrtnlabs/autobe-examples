import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPageIDiscussionBoardAuthenticationLog } from "../../../../../structures/IPageIDiscussionBoardAuthenticationLog";

/**
 * Retrieve the login history for a specific moderator from the discussion board
 * moderation system. This operation queries the
 * discussion_board_authentication_logs and discussion_board_moderator_sessions
 * tables to compile a comprehensive audit trail of all authentication events
 * associated with the specified moderator ID.
 *
 * The operation returns detailed session information including timestamps,
 * authentication methods, connection origins (IP addresses), and duration
 * metrics. This data is critical for security audits, compliance verification,
 * and accountability tracking of moderation activities.
 *
 * The endpoint requires moderator-level authorization since login histories
 * contain sensitive authentication data. This operation only returns entries
 * directly associated with the specified moderatorId path parameter. Entries
 * from other moderators are excluded by the implementation logic.
 *
 * The authentication logs are maintained as an immutable audit trail,
 * preserving records of every login attempt (successful or failed) and
 * subsequent session activity. The response format consolidates these
 * individual log events into a structured timeline for easy human analysis.
 *
 * Related operations: GET /moderators/{moderatorId}/account-status, GET
 * /moderators/{moderatorId}/moderation-activity-log, POST
 * /moderators/{moderatorId}/deactivate
 *
 * @param props.connection
 * @param props.moderatorId Unique identifier of the moderator whose login
 *   history is being requested
 * @path /discussionBoard/moderator/moderators/:moderatorId/login-history
 * @accessor api.functional.discussionBoard.moderator.moderators.login_history.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the moderator whose login history is being
     * requested
     */
    moderatorId: string;
  };
  export type Response = IPageIDiscussionBoardAuthenticationLog;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/moderator/moderators/:moderatorId/login-history",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/moderators/${encodeURIComponent(props.moderatorId ?? "null")}/login-history`;
  export const random = (): IPageIDiscussionBoardAuthenticationLog =>
    typia.random<IPageIDiscussionBoardAuthenticationLog>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("moderatorId")(() => typia.assert(props.moderatorId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
