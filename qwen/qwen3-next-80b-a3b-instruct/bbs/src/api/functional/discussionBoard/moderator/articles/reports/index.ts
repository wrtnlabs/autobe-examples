/**
 * Retrieve a paginated list of all reports submitted against a specific
 * discussion board article. This operation operates on the
 * discussion_board_reports table and allows moderators and citizens to view all
 * reports associated with a given article, including the reporter's anonymous
 * ID, report reason, timestamp, and current moderation status.
 *
 * The system supports advanced filtering and pagination to handle large volumes
 * of reports. Users can sort reports by creation date (newest first) and filter
 * by report status (pending, reviewed, dismissed, etc.). The operation returns
 * a summary of each report with minimal identifying information to protect
 * reporter anonymity while providing context for decision-making.
 *
 * This endpoint is designed for moderation teams to efficiently review and
 * manage reported content. Each report is linked to a specific article via the
 * articleId path parameter, ensuring reports are always scoped to the correct
 * context. The operation does not return sensitive information about reporters
 * beyond their anonymous ID, in compliance with privacy requirements.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article for which
 *   reports are being retrieved. This is the primary key from the
 *   discussion_board_articles table.
 * @path /discussionBoard/moderator/articles/:articleId/reports
 * @accessor api.functional.discussionBoard.moderator.articles.reports.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target article for which reports are being
     * retrieved. This is the primary key from the discussion_board_articles
     * table.
     */
    articleId: string;
  };
  export type Response = IPageIDiscussionBoardReport.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/articles/:articleId/reports",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/articles/${encodeURIComponent(props.articleId ?? "null")}/reports`;
  export const random = (): IPageIDiscussionBoardReport.ISummary =>
    typia.random<IPageIDiscussionBoardReport.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Update the reason and status of a report on a discussion board article. This
 * operation allows moderators to update the status and rationale for handling a
 * report on a specific article. Reports are submitted by citizens when they
 * observe content that may violate platform guidelines, and moderators are
 * responsible for evaluating and taking appropriate action. Each report is
 * linked to both the article and the reporter, creating a traceable moderation
 * history.
 *
 * The operation validates that the reporter and article combination exists, and
 * that the moderator initiating the update has appropriate permissions. The
 * report status can be updated to resolved, dismissed, or escalated, with each
 * status change triggering appropriate system actions such as notification to
 * the reporter or escalation to a senior moderator team.
 *
 * The update does not modify the article itself, only the status of the report
 * on that article. This allows multiple reports on the same article to be
 * handled independently. The new reason provided in the update replaces any
 * previous explanation, creating a clear audit trail.
 *
 * This operation is linked to the discussion_board_article_reports table, which
 * tracks all citizen-initiated reports on articles. The reportId path parameter
 * maps directly to the report's unique identifier in this table, while the
 * articleId path parameter ensures the report being updated is associated with
 * the correct article, preventing accidental updates to unrelated reports.
 *
 * This operation maintains the integrity of moderation decisions by requiring
 * authorization from the moderator role. It is not accessible to regular
 * citizens, ensuring that report handling decisions remain under the control of
 * trained moderators.
 *
 * Related operations include: POST /articles/{articleId}/reports (to submit a
 * new report) and GET /articles/{articleId}/reports (to retrieve existing
 * reports on an article).
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article that was reported for
 *   review
 * @param props.reportId Unique identifier of the report on the article to be
 *   updated
 * @param props.body Updated information for the article report including status
 *   and reason
 * @path /discussionBoard/moderator/articles/:articleId/reports/:reportId
 * @accessor api.functional.discussionBoard.moderator.articles.reports.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
