import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IPageIDiscussionBoardReportSummary } from "../../../../../../structures/IPageIDiscussionBoardReportSummary";

/**
 * Retrieve all unresolved reports from the discussion board system for
 * moderator review. This operation aggregates data from the
 * discussion_board_reports and discussion_board_article_reports tables to
 * provide a comprehensive view of unaddressed user reports.
 *
 * The endpoint returns reports that have not been processed by moderators,
 * including both standalone reports on user behavior and reports on specific
 * article content. Each report contains metadata about the reporter, the
 * reported entity, the reason for the report, and timestamp of submission.
 *
 * Security: Only moderators can access this endpoint. The operation filters
 * reports that have no associated moderation action record in the
 * discussion_board_moderation_actions table. Reports are returned in
 * chronological order with the oldest first to prioritize timely review.
 *
 * System Design Note: This operation does not require pagination as the volume
 * of unresolved reports in a healthy system should remain manageable (typically
 * under 100 at any time). For systems experiencing high report volumes,
 * automated moderation queues or automated classification systems are
 * recommended.
 *
 * Related Operations: GET /dashboards/reports/resolved to view processed
 * reports and POST /moderation/actions to take action on reported content.
 *
 * @param props.connection
 * @path /discussionBoard/moderator/dashboards/reports/unresolved
 * @accessor api.functional.discussionBoard.moderator.dashboards.reports.unresolved.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPageIDiscussionBoardReportSummary;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/moderator/dashboards/reports/unresolved",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/discussionBoard/moderator/dashboards/reports/unresolved";
  export const random = (): IPageIDiscussionBoardReportSummary =>
    typia.random<IPageIDiscussionBoardReportSummary>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
