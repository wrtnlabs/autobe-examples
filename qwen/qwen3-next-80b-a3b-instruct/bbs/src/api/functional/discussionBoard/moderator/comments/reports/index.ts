import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardCommentReport } from "../../../../../structures/IDiscussionBoardCommentReport";

/**
 * Retrieve a specific report on a comment in the discussion board system. This
 * operation operates on the discussion_board_comment_reports table and returns
 * detailed information about a user report submitted against a comment.
 *
 * This endpoint allows authorized users to view the details of a specific
 * comment report, including the reason for reporting, timestamp, and reporting
 * user information. Both regular citizens and moderators can access this
 * information to review reported content.
 *
 * Security: Only authenticated users can access report details. The system
 * ensures that sensitive user information is hidden from non-moderators to
 * protect reporter privacy. The report must be associated with an existing
 * comment and must have been submitted by a registered user.
 *
 * This operation is typically used by moderators to review reported content for
 * action and by citizens to inspect reports they have submitted. The report
 * information is not available to guests or unauthenticated users.
 *
 * Related operations: GET /comments/{commentId}/reports (list all reports for a
 * comment), DELETE /comments/{commentId}/reports/{reportId} (erase report).
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the target comment that was
 *   reported
 * @param props.reportId Unique identifier of the specific report being
 *   retrieved
 * @path /discussionBoard/moderator/comments/:commentId/reports/:reportId
 * @accessor api.functional.discussionBoard.moderator.comments.reports.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target comment that was reported */
    commentId: string;

    /** Unique identifier of the specific report being retrieved */
    reportId: string;
  };
  export type Response = IDiscussionBoardCommentReport;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/moderator/comments/:commentId/reports/:reportId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/comments/${encodeURIComponent(props.commentId ?? "null")}/reports/${encodeURIComponent(props.reportId ?? "null")}`;
  export const random = (): IDiscussionBoardCommentReport =>
    typia.random<IDiscussionBoardCommentReport>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
      assert.param("reportId")(() => typia.assert(props.reportId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
