/**
 * Create a new temporary suspension for a citizen account on the discussion
 * board platform. This operation is used by moderators to enforce community
 * guidelines by temporarily restricting a citizen's access to posting and
 * commenting functions. The suspension is recorded in the
 * DiscussionBoardCitizenSuspension entity with a reference to the citizen being
 * suspended and the moderator who enacted the suspension. This creates a
 * comprehensive audit trail for all moderation actions.
 *
 * The suspension includes a start date and optional end date, during which the
 * citizen cannot post or comment on the platform. The system automatically
 * invalidates the citizen's active session, preventing further interactions
 * until the suspension period expires. The suspension does not delete or hide
 * any of the citizen's previously created content.
 *
 * Authorization: Only moderators can initiate suspensions. Suspended citizens
 * cannot access the platform during their suspension period and cannot appeal
 * the suspension until it has expired. The suspension duration is enforced
 * system-wide and cannot be circumvented by creating new accounts.
 *
 * Related operations: List suspensions (PATCH /moderation/suspensions), View
 * suspension details (GET /moderation/suspensions/{suspensionId}), Resume
 * suspension (PUT /moderation/suspensions/{suspensionId}), Appeal suspension
 * (POST /moderation/appeals).
 *
 * @param props.connection
 * @param props.body Details for initiating a new citizen suspension on the
 *   discussion board platform.
 * @path /discussionBoard/moderator/moderation/suspensions
 * @accessor api.functional.discussionBoard.moderator.moderation.suspensions.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
