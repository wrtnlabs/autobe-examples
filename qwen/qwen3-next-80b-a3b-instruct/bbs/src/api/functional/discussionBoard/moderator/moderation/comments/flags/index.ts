import { IPageIDiscussionBoardCommentReport } from "../../../../../../structures/IPageIDiscussionBoardCommentReport";

/**
 * Retrieve all flagged comment reports for moderator review. This operation
 * accesses the discussion_board_comment_reports table to fetch all submitted
 * reports on comments, including the report identifier, reporter identifier,
 * reason for report, and creation timestamp. This allows moderators to
 * prioritize and review reported content efficiently.
 *
 * This endpoint provides a comprehensive list of comment reports that require
 * human moderation. Each report includes the comment_id to identify the flagged
 * comment, reporter_id to understand the reporter's identity, reason for the
 * report, and creation timestamp. Moderators can use this list to identify
 * patterns of abuse, respond to user complaints, and make decisions on content
 * removal.
 *
 * Authorization: Only users with moderator role can access this data to prevent
 * abuse of reporting system.
 *
 * Relationship to other operations: This operation is complementary to DELETE
 * /moderation/comments/{commentId}/remove, which performs the actual content
 * removal after review.
 *
 * Note: The specific fields in the response correspond exactly to the
 * discussion_board_comment_reports database table schema. The returned fields
 * are: id, comment_id, reporter_id, reason, created_at, status.
 *
 * @param props.connection
 * @path /discussionBoard/moderator/moderation/comments/flags
 * @accessor api.functional.discussionBoard.moderator.moderation.comments.flags.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPageIDiscussionBoardCommentReport;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/moderator/moderation/comments/flags",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/discussionBoard/moderator/moderation/comments/flags";
  export const random = (): IPageIDiscussionBoardCommentReport =>
    typia.random<IPageIDiscussionBoardCommentReport>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
