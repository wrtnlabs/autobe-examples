import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Permanently removes a user account from the discussion board system. This
 * operation directly affects the discussion_board_users table and is
 * irreversible. Once a user is deleted, associated data (posts, comments,
 * notifications) are archived by system processes for compliance purposes. The
 * deletion is performed as a hard delete, meaning the user record is completely
 * removed from the active database with no possibility of recovery.
 *
 * This operation is restricted to users who have been granted administrative
 * authority to manage user accounts. The system automatically logs this
 * deletion event in the discussion_board_audit_events table to maintain an
 * immutable audit trail for compliance and security monitoring.
 *
 * Due to the sensitivity of this operation, it can only be performed by users
 * with explicit administrative permissions. The action will also trigger a
 * series of background processes to archive related content in
 * discussion_board_archives and update compliance records in
 * discussion_board_compliance_records to meet legal retention requirements.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the target user to be removed from
 *   the system
 * @path /discussionBoard/moderator/users/:userId
 * @accessor api.functional.discussionBoard.moderator.users.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the target user to be removed from the system */
    userId: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/moderator/users/:userId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/users/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
