/**
 * Refreshes moderator authentication session using a refresh token.
 *
 * Refreshes the moderator's authentication token to extend their session
 * without requiring a full login. When a moderator's current access token
 * expires or is near expiration, the client presents a valid refresh token to
 * this endpoint. The system validates the refresh token's signature,
 * expiration, and binding to an active moderator session. If valid, a new
 * access token is generated with a 30-minute lifetime and returned in the
 * response. The original refresh token remains unchanged and retains its 7-day
 * validity.
 *
 * Security considerations require that refresh tokens are transmitted over
 * HTTPS and stored securely on the client (e.g., in localStorage or secure
 * cookie). Refresh tokens must not be reused across different devices or IP
 * addresses to prevent token hijacking. Repeated invalid refresh token attempts
 * trigger rate-limiting to prevent brute-force attacks.
 *
 * This operation does not interact with the database or modify any moderator
 * state. It only verifies the cryptographic validity of the submitted refresh
 * token. The operation is stateless and relies entirely on JWT token structure
 * and signature verification. Moderators who have been disabled or deleted will
 * have their refresh tokens rejected upon validation.
 *
 * This operation should be invoked when the client receives a 401 Unauthorized
 * error on protected endpoints, indicating token expiration.
 *
 * @param props.connection
 * @param props.body Contains the refresh token to be validated and exchanged
 *   for a new access token.
 * @path /discussionBoard/moderator/auth/moderator/refresh
 * @accessor api.functional.discussionBoard.moderator.auth.moderator.refresh
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function refresh(
  connection: IConnection,
  props: refresh.Props,
): Promise<refresh.Response> {
  return true === connection.simulate
    ? refresh.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...refresh.METADATA,
          path: refresh.path(),
          status: null,
        },
        props.body,
      );
}
export namespace refresh {
  export type Props = {
    /**
     * Contains the refresh token to be validated and exchanged for a new
     * access token.
     */
    body: IDiscussionBoardAuthRefreshRequest;
  };
  export type Body = IDiscussionBoardAuthRefreshRequest;
  export type Response = IDiscussionBoardAuthRefreshResponse;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/moderator/auth/moderator/refresh",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/moderator/auth/moderator/refresh";
  export const random = (): IDiscussionBoardAuthRefreshResponse =>
    typia.random<IDiscussionBoardAuthRefreshResponse>();
  export const simulate = (
    connection: IConnection,
    props: refresh.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: refresh.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
