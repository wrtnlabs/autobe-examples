import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Permanently removes an image attachment from the system. This operation
 * targets the discussion_board_attachment_images table and executes a hard
 * delete, removing both the image record and its associated metadata. The image
 * file itself is also permanently deleted from the storage system.
 *
 * This operation cannot be undone. Once executed, the image will be completely
 * removed from all displays and references within the system. There is no
 * recovery mechanism. No soft-delete flag is applied, as the system maintains
 * an audit trail of deletions in the discussion_board_moderation_logs table for
 * compliance purposes.
 *
 * The system enforces authorization through the authentication token attached
 * to the request. The operation verifies that the authenticated user is the
 * original uploader of the image or holds moderator privileges. User uploads
 * are tracked through the discussion_board_attachment_images table's
 * uploader_id field, which is compared against the authenticated user's ID from
 * the JWT token.
 *
 * This deletion operation is irreversible and is only available for users with
 * appropriate permissions. For security and audit compliance, each deletion is
 * automatically logged in the discussion_board_moderation_logs table with the
 * actor's ID, target entity, and timestamp.
 *
 * Related operations: GET /images/{imageId} (retrieves image metadata) and
 * PATCH /images (searches for image attachments).
 *
 * @param props.connection
 * @param props.imageId Unique identifier of the target image attachment in the
 *   discussion_board_attachment_images table
 * @path /discussionBoard/moderator/images/:imageId
 * @accessor api.functional.discussionBoard.moderator.images.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the target image attachment in the
     * discussion_board_attachment_images table
     */
    imageId: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/moderator/images/:imageId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/images/${encodeURIComponent(props.imageId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("imageId")(() => typia.assert(props.imageId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
