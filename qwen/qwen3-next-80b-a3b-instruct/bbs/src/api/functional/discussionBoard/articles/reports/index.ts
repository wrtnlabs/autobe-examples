import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardArticleReport } from "../../../../structures/IDiscussionBoardArticleReport";

/**
 * Retrieve a specific article report by its unique identifier. This operation
 * fetches a report entry from the discussion_board_article_reports table, which
 * logs user reports on articles. The report includes the reporter's identifier,
 * reason for reporting, timestamp of reporting, and any additional context
 * provided.
 *
 * The operation requires both the article ID and report ID as path parameters
 * to uniquely identify the report within the specific article context. This
 * ensures reports are scoped to the article they pertain to, preventing
 * ambiguity when multiple articles have reports with similar or identical
 * identifiers.
 *
 * Security considerations include ensuring that reports are accessible to the
 * system for moderation purposes, while maintaining reporter anonymity unless
 * explicitly handled by moderation. The operation is available to system
 * administrators and moderation systems for auditing and review. No
 * authentication is required for this read-only operation as reports are
 * considered system metadata.
 *
 * The result includes all fields from the report record including the report
 * reason, creation timestamp, associated article ID, and any custom context
 * provided by the reporter. This report data is typically displayed in
 * moderation dashboards and are used for compliance and integrity
 * verification.
 *
 * Related operations: PATCH /articles/{articleId}/reports (list all reports for
 * an article), DELETE /articles/{articleId}/reports/{reportId} (remove a
 * report).
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article in the
 *   discussion_board_articles table that the report refers to (global scope)
 * @param props.reportId Unique identifier of the specific report entry in the
 *   discussion_board_article_reports table that is being requested (global
 *   scope)
 * @path /discussionBoard/articles/:articleId/reports/:reportId
 * @accessor api.functional.discussionBoard.articles.reports.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target article in the
     * discussion_board_articles table that the report refers to (global
     * scope)
     */
    articleId: string;

    /**
     * Unique identifier of the specific report entry in the
     * discussion_board_article_reports table that is being requested
     * (global scope)
     */
    reportId: string;
  };
  export type Response = IDiscussionBoardArticleReport;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/articles/:articleId/reports/:reportId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/reports/${encodeURIComponent(props.reportId ?? "null")}`;
  export const random = (): IDiscussionBoardArticleReport =>
    typia.random<IDiscussionBoardArticleReport>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.param("reportId")(() => typia.assert(props.reportId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
