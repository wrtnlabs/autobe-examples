/**
 * Retrieve a filtered, paginated, and sorted list of discussion board articles.
 * This operation queries the discussion_board_articles table and supports
 * advanced search capabilities including text search across title and content
 * fields, filtering by publication status, date range, author UID, and category
 * association. Results are returned in paginated format with configurable page
 * size, sorting by creation date, update date, or relevance score, and complete
 * pagination metadata.
 *
 * The operation leverages full-text search capabilities on the article's title
 * and content fields to provide accurate keyword matching. Users can filter
 * articles by their current status (draft, pending, published, hidden) and
 * specify date ranges for creation or modification. Category filtering allows
 * users to retrieve articles belonging to specific discussion channels.
 *
 * Security considerations include rate limiting for search operations and
 * filtering of sensitive article data based on the requesting user's
 * authorization level. Only published articles are accessible to
 * non-administrative users, while administrators can view articles in all
 * supported states (draft, pending, published, hidden). The operation does not
 * expose private metadata such as internal IDs or audit logs.
 *
 * This operation integrates with the discussion_board_articles,
 * discussion_board_article_statuses, discussion_board_channels, and
 * discussion_board_citizen models as defined in the database schema. The
 * response format is optimized for frontend consumption, returning only
 * essential summary information for article listings.
 *
 * @param props.connection
 * @param props.body Search, filter, sort, and pagination parameters for article
 *   retrieval
 * @path /discussionBoard/articles
 * @accessor api.functional.discussionBoard.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search, filter, sort, and pagination parameters for article retrieval */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/articles";
  export const random = (): IPageIDiscussionBoardArticle.ISummary =>
    typia.random<IPageIDiscussionBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
