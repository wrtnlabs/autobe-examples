import { IDiscussionBoardArticleStatusLog } from "../../../../structures/IDiscussionBoardArticleStatusLog";

/**
 * Retrieve a specific status log record for an article. This operation accesses
 * the discussion_board_article_status_logs table, which tracks all publication
 * status transitions for articles with detailed audit context including
 * timestamp, status, and associated actor.
 *
 * The status log contains immutable historical records of every status change
 * an article has undergone, providing a complete audit trail for compliance and
 * troubleshooting. Each log entry includes the article ID, the status value
 * (draft, pending, published, hidden, deleted), the timestamp of the change,
 * and the actor ID responsible for the transition.
 *
 * Security considerations involve ensuring that only users with appropriate
 * permissions can access detailed status logs. While status changes are
 * typically AUDIT records, the API operation returns the complete log entry
 * with no masking of sensitive information, as the audit trail is considered
 * publicly accessible for transparency purposes.
 *
 * This operation is exclusively read-only. Status changes are automatically
 * generated by the system as side effects of other operations (POST, PUT,
 * DELETE) to articles and cannot be manually created, edited, or deleted
 * through this API endpoint.
 *
 * Related operations: GET /articles/{articleId} retrieves the current status of
 * an article, while PATCH /articles/{articleId} performs status transitions
 * which automatically create new log entries.
 *
 * The log ID is a globally unique identifier for each individual status
 * transition event, including both user-triggered and system-generated status
 * changes. The log entry represents a single state transition and cannot be
 * modified after creation.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article
 * @param props.logId Unique identifier of the status log entry
 * @path /discussionBoard/articles/:articleId/status-logs/:logId
 * @accessor api.functional.discussionBoard.articles.status_logs.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target article */
    articleId: string;

    /** Unique identifier of the status log entry */
    logId: string;
  };
  export type Response = IDiscussionBoardArticleStatusLog;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/articles/:articleId/status-logs/:logId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/status-logs/${encodeURIComponent(props.logId ?? "null")}`;
  export const random = (): IDiscussionBoardArticleStatusLog =>
    typia.random<IDiscussionBoardArticleStatusLog>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.param("logId")(() => typia.assert(props.logId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
