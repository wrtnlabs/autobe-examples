import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardAttachmentImage } from "../../../structures/IDiscussionBoardAttachmentImage";

/**
 * Retrieve a specific image attachment associated with an article on the
 * discussion board.
 *
 * This operation retrieves metadata for a single image file by its unique
 * identifier from the discussion_board_attachment_images table. Each image is
 * stored as a binary file with associated metadata including file name, MIME
 * type, size, and upload timestamp. The image is linked to a parent article
 * through the article_id field in the database.
 *
 * The system maintains image files as immutable assets after upload, and this
 * operation provides access to the image's metadata for display in the frontend
 * application. Security validation ensures the requesting user has permission
 * to view the parent article before returning the image metadata.
 *
 * The actual image file is served via a secure, pre-signed URI stored in the
 * response, which enables dynamic loading of attached images without exposing
 * full article details. No binary content is returned in this API response to
 * maintain type-safety and JSON compatibility. Image retrieval is handled
 * through a separate file-serving system using the provided URI.
 *
 * Related operations: List article images (PATCH /articles/{articleId}/images),
 * Upload new image (POST /articles/{articleId}/images).
 *
 * @param props.connection
 * @param props.imageId Unique identifier of the target image record in the
 *   discussion_board_attachment_images table.
 * @path /discussionBoard/images/:imageId
 * @accessor api.functional.discussionBoard.images.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target image record in the
     * discussion_board_attachment_images table.
     */
    imageId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardAttachmentImage;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/images/:imageId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/images/${encodeURIComponent(props.imageId ?? "null")}`;
  export const random = (): IDiscussionBoardAttachmentImage =>
    typia.random<IDiscussionBoardAttachmentImage>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("imageId")(() => typia.assert(props.imageId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
