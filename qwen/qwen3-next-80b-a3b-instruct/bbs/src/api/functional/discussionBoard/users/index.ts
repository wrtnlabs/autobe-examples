import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardUser } from "../../../structures/IDiscussionBoardUser";

/**
 * Create a new citizen account for the discussion board platform. This
 * operation allows new users to register with a unique username and email
 * address, establishing their identity as a citizen on the platform.
 *
 * The system creates a new citizen record in the discussion_board_users
 * database table with a unique user identifier. Upon successful registration, a
 * dedicated session is initiated and stored in the
 * discussion_board_citizen_sessions table, with the session token serving as
 * the authentication credential for subsequent interactions.
 *
 * All registration attempts are logged for audit purposes in the
 * discussion_board_authentication_logs table, ensuring compliance with security
 * and regulatory standards. This enables tracking of registration attempts, IP
 * addresses, and timestamps for security monitoring and abuse prevention.
 *
 * Security considerations include rate limiting to prevent automated
 * registration abuse and mandatory validation of email format. Only one account
 * per unique email address is permitted, preventing duplicate registrations.
 * New users begin with a default trust score of zero, which increases as they
 * contribute positive content and interactions that are approved by the
 * moderation system.
 *
 * Subsequent operations rely on a successful registration, as authentication
 * tokens generated during this operation are required for accessing protected
 * resources such as posting articles, commenting, and uploading files. This
 * makes user registration the foundational operation for all citizen activity
 * on the platform.
 *
 * @param props.connection
 * @param props.body Registration credentials and profile information required
 *   to create a new citizen account.
 * @path /discussionBoard/users
 * @accessor api.functional.discussionBoard.users.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Registration credentials and profile information required to create a
     * new citizen account.
     */
    body: IDiscussionBoardUser.ICreate;
  };
  export type Body = IDiscussionBoardUser.ICreate;
  export type Response = IDiscussionBoardUser;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/users",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/users";
  export const random = (): IDiscussionBoardUser =>
    typia.random<IDiscussionBoardUser>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
