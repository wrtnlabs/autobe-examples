import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardCitizenSuspension } from "../../../../structures/IDiscussionBoardCitizenSuspension";

/**
 * Retrieve the suspension details for a specific citizen on the discussion
 * board.
 *
 * This operation retrieves information about temporary account suspensions
 * imposed on citizens due to policy violations. Suspensions are managed through
 * the discussion_board_citizen_suspensions database table and store the
 * suspension start date, end date, reason for suspension, and the moderator who
 * initiated the action.
 *
 * When a citizen receives multiple content removals within a 6-month period,
 * the system automatically triggers a temporary suspension according to the
 * moderation policy. Citizens who are suspended cannot post, comment, or edit
 * content during the suspension period. The suspension duration can be 1 day, 7
 * days, 30 days, or permanent (with permanent bans handled through the
 * discussion_board_bans table).
 *
 * Suspension details are accessible only to the suspended citizen themselves
 * and moderators. Regular citizens cannot view other citizens' suspension
 * records. The suspension status appears in the user interface and is
 * communicated through system notifications.
 *
 * This operation supports administrators and moderators in auditing suspension
 * cases and citizens in checking their own suspension status. The operation
 * returns the suspension details including duration, reason, and the moderator
 * responsible, enabling transparency and compliance with community standards.
 *
 * Note: The system preserves all suspension records for audit and compliance
 * purposes even after the suspension period ends.
 *
 * @param props.connection
 * @param props.suspensionId Unique identifier of the target suspension record.
 *   This is the system-generated ID assigned when the suspension was created in
 *   the discussion_board_citizen_suspensions table.
 * @path /discussionBoard/citizen/citizen-suspensions/:suspensionId
 * @accessor api.functional.discussionBoard.citizen.citizen_suspensions.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target suspension record. This is the
     * system-generated ID assigned when the suspension was created in the
     * discussion_board_citizen_suspensions table.
     */
    suspensionId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardCitizenSuspension;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/citizen/citizen-suspensions/:suspensionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/citizen/citizen-suspensions/${encodeURIComponent(props.suspensionId ?? "null")}`;
  export const random = (): IDiscussionBoardCitizenSuspension =>
    typia.random<IDiscussionBoardCitizenSuspension>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("suspensionId")(() => typia.assert(props.suspensionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
