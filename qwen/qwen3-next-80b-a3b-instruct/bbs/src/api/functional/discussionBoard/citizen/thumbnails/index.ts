/**
 * Create a new thumbnail representation for a discussion board article. This
 * operation creates a thumbnail image based on the content of the associated
 * article, generating a visually representative preview that can be displayed
 * in article listings, feed summaries, and search results.
 *
 * The thumbnail is automatically generated from the article's primary image or
 * first available image attachment. If no image is available in the article, a
 * default system-generated thumbnail is created based on the article's category
 * and title. This automated process eliminates manual upload requirements while
 * ensuring consistent visual presentation across the platform.
 *
 * Security considerations: Only authenticated citizens can create thumbnails
 * for their own articles. Moderators can create thumbnails for any article they
 * have access to. The operation validates that the referenced article exists
 * and that the user has appropriate permissions to create a thumbnail for it.
 *
 * The generated thumbnail is stored in the system as a new thumbnail record,
 * with metadata linking it back to the original article. The thumbnail file is
 * saved in optimized web formats with appropriate resolution scaling, and its
 * size is constrained to ensure fast rendering. The operation also triggers
 * metadata indexing for content-based search and visual similarity detection.
 *
 * Related operations: Get article thumbnails (GET /thumbnails/{thumbnailId}),
 * Delete thumbnail (DELETE /thumbnails/{thumbnailId}).
 *
 * @param props.connection
 * @param props.body Request payload for creating a new thumbnail where the
 *   articleId identifies the target article for which thumbnail should be
 *   generated.
 * @path /discussionBoard/citizen/thumbnails
 * @accessor api.functional.discussionBoard.citizen.thumbnails.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
