/**
 * Search, filter, and retrieve images attached to articles based on query
 * parameters. This operation accesses the discussion_board_attachment_images
 * and discussion_board_article_images tables to return a paginated list of
 * image records matching search criteria.
 *
 * The operation supports filtering by article ID, status (active/inactive),
 * upload date range, and file type. Results are sorted by upload timestamp
 * descending by default. Pagination is controlled via limit and offset
 * parameters. Results include metadata such as filename, size, upload
 * timestamp, and associated article ID.
 *
 * The request body is required because complex filtering capabilities (search
 * terms, date ranges, file type filters) cannot be adequately expressed through
 * URL query parameters alone. This follows the API design principle that PATCH
 * should be used for highly parameterized list operations where body content
 * provides advanced filtering and sorting controls.
 *
 * The response returns a paginated result set with total count and metadata,
 * optimized for UI display in client applications that need to render image
 * galleries or thumbnails on user posts.
 *
 * Security: Only authenticated citizens may query their own attached images.
 * Arbitrary viewing of all images in the system is not permitted. This prevents
 * unauthorized access or scraping of media content.
 *
 * Implementation note: This endpoint does not serve network streams of the
 * image data itself - it returns metadata and file paths. The actual image
 * files are accessed via separate static file endpoints using the returned
 * URI.
 *
 * Related operations: POST /articles/{articleId}/images to upload new images,
 * DELETE /images/{imageId} to remove specific images.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for filtering
 *   images by article, status, or upload date.
 * @path /discussionBoard/citizen/images
 * @accessor api.functional.discussionBoard.citizen.images.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
