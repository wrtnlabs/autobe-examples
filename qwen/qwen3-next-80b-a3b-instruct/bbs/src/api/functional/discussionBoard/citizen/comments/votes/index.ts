import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardCommentVote } from "../../../../../structures/IDiscussionBoardCommentVote";

/**
 * Retrieve a specific vote on a comment within the discussion board system.
 * This operation accesses the discussion_board_comment_votes table and returns
 * the detailed vote information associated with a given comment and vote.
 *
 * The endpoint allows authenticated citizens to view the details of a specific
 * vote record linked to their comment. Each vote represents a user's positive
 * or negative feedback on a comment, stored with its associated timestamp and
 * the voter's identity.
 *
 * This operation is used to display the voting status to users in real-time,
 * allowing them to see how their comments are being received by others. The
 * vote record contains the vote value (e.g., +1 or -1) and the identity of the
 * user who cast the vote, ensuring transparency in community feedback.
 *
 * The application ensures that only users with appropriate permissions can view
 * vote details. The vote is linked to its parent comment and stored as an
 * individual entity with creation timestamp and user association in the
 * database.
 *
 * The comment identification is provided by the {commentId} path parameter, and
 * the specific vote is targeted using the {voteId} path parameter, which
 * uniquely identifies the vote record within the comment's vote set.
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the target comment
 * @param props.voteId Unique identifier of the target vote record
 * @path /discussionBoard/citizen/comments/:commentId/votes/:voteId
 * @accessor api.functional.discussionBoard.citizen.comments.votes.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target comment */
    commentId: string;

    /** Unique identifier of the target vote record */
    voteId: string;
  };
  export type Response = IDiscussionBoardCommentVote;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/citizen/comments/:commentId/votes/:voteId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/citizen/comments/${encodeURIComponent(props.commentId ?? "null")}/votes/${encodeURIComponent(props.voteId ?? "null")}`;
  export const random = (): IDiscussionBoardCommentVote =>
    typia.random<IDiscussionBoardCommentVote>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
      assert.param("voteId")(() => typia.assert(props.voteId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
