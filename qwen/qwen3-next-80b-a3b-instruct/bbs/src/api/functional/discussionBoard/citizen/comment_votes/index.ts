import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardCommentVote } from "../../../../structures/IDiscussionBoardCommentVote";

/**
 * This operation allows authenticated citizens to upvote or downvote a comment
 * on an article. This functionality enables community feedback and engagement
 * with content. The operation modifies the discussion_board_comment_votes table
 * by creating, updating, or removing a vote record based on the provided vote
 * value. Each citizen can have only one vote per comment to prevent
 * manipulation, and the vote value must be either +1 or -1. The vote value is
 * used to update the comment's overall rating, which affects comment ordering
 * in displays.
 *
 * When a citizen submits a vote, the system checks if they already have a vote
 * on that comment. If they do, the existing vote is updated with the new value.
 * If they don't, a new vote record is created. If the vote value is 0, the
 * system removes the existing vote (equivalent to removing their feedback). The
 * operation requires the comment identifier (commentId) to be provided, and the
 * vote value must be validated against allowed values.
 *
 * Security considerations include ensuring that only authenticated citizens can
 * vote, preventing vote fraud through rate limiting, and verifying that the
 * comment exists before allowing a vote. The operation does not require
 * administrative authorization since comment voting is a community-driven
 * feature intended for all registered users.
 *
 * Related operations: This operation works in conjunction with the comment
 * retrieval operations (GET /comments/{commentId}) where the total vote count
 * is displayed, and the comment moderation operations that may hide or delete
 * comments with negative scores.
 *
 * Implementation note: The operation maps directly to the
 * discussion_board_comment_votes entity which has the composite unique
 * constraint @@unique([citizenId, commentId]) to ensure one vote per citizen
 * per comment. The vote is stored as an integer field, and the total score for
 * each comment is calculated by summing the vote values in this table.
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the target comment for which the
 *   vote is being cast (scoped to comment)
 * @param props.body Vote submission details including the vote value (+1 for
 *   upvote, -1 for downvote) and option to remove a vote with value 0
 * @path /discussionBoard/citizen/comment-votes/:commentId
 * @accessor api.functional.discussionBoard.citizen.comment_votes.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target comment for which the vote is being
     * cast (scoped to comment)
     */
    commentId: string;

    /**
     * Vote submission details including the vote value (+1 for upvote, -1
     * for downvote) and option to remove a vote with value 0
     */
    body: IDiscussionBoardCommentVote.IRequest;
  };
  export type Body = IDiscussionBoardCommentVote.IRequest;
  export type Response = IDiscussionBoardCommentVote;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/citizen/comment-votes/:commentId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/citizen/comment-votes/${encodeURIComponent(props.commentId ?? "null")}`;
  export const random = (): IDiscussionBoardCommentVote =>
    typia.random<IDiscussionBoardCommentVote>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
