/**
 * Create a new article in the discussion board system. This operation allows
 * authenticated citizens to create new articles with title, content, and
 * optional attachments. The article is initially saved in 'draft' status and
 * requires a publication step before becoming publicly visible. This operation
 * directly interacts with the discussion_board_articles database table, which
 * stores the primary article metadata including author, title, content, status,
 * and timestamps.
 *
 * Security and authorization: Only authenticated citizens (regular users) can
 * create articles. The system automatically populates the author_id field from
 * the JWT authentication token. No other actors (like moderators) are permitted
 * to create articles through this endpoint.
 *
 * Validation rules: The article title must be non-empty and under 500
 * characters. The content field must not be empty. The status field is
 * automatically set to 'draft' and cannot be overridden by the client. The
 * created_at and updated_at fields are managed by the system and populated
 * automatically. The published_at field remains null until the article is
 * published.
 *
 * Relationships: This operation creates a record in discussion_board_articles,
 * which can later be associated with comments
 * (discussion_board_article_comments), tags
 * (discussion_board_article_categories), and files
 * (discussion_board_article_files, discussion_board_article_images) through
 * separate operations. This article creation operation does not create or
 * associate any attachments - those require separate POST operations on the
 * appropriate attachments endpoints.
 *
 * Important: This operation does not publish the article immediately. As per
 * system requirements, articles must be published via a separate operation to
 * maintain editorial control. This follows the business workflow where articles
 * are reviewed before public display. Related operations: PATCH /articles
 * (list/search articles), PUT /articles/{articleId} (update article), DELETE
 * /articles/{articleId} (erase article), POST /articles/{articleId}/publish
 * (publish article).
 *
 * @param props.connection
 * @param props.body Creation data for a new discussion board article.
 * @path /discussionBoard/citizen/articles
 * @accessor api.functional.discussionBoard.citizen.articles.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
