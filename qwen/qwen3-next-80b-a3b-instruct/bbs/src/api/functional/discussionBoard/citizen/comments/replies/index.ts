/**
 * Create a new reply to an existing discussion board comment. This operation
 * allows citizens to respond to existing comments in the discussion board
 * system, enabling threaded conversations and community engagement.
 *
 * The reply is associated with the target comment identified by the commentId
 * path parameter. The reply content must be provided in the request body and
 * adheres to the platform's content policies and restrictions. Replies inherit
 * the visibility status of their parent comment and are subject to the same
 * moderation rules.
 *
 * Security: Only authenticated citizens can create replies. The system
 * automatically associates the reply with the authenticated user's citizen
 * identity. Rate limiting prevents spam and abuse.
 *
 * Relationships: Each reply is linked to its parent comment through the
 * commentId reference. The reply's author is the currently authenticated
 * citizen. The system creates audit events to track reply creation for
 * compliance and moderation purposes.
 *
 * Validations: Reply content must be non-empty and within the configured
 * maximum length limits. The operation rejects attempts to create replies on
 * non-existent or already-deleted comments. The system prevents reply creation
 * on posts that have been locked for commenting.
 *
 * Related operations:
 *
 * - PATCH /comments/{commentId}/replies: Retrieve paginated replies for a comment
 * - PUT /comments/{commentId}/replies/{replyId}: Update an existing reply
 * - DELETE /comments/{commentId}/replies/{replyId}: Delete a reply
 * - POST /comments/{commentId}: Create a top-level comment (parent of replies)
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the target comment to which the
 *   reply is being created. Must reference an existing comment in the
 *   discussion_board_comments table.
 * @param props.body Data required to create a new comment reply on the
 *   discussion board system.
 * @path /discussionBoard/citizen/comments/:commentId/replies
 * @accessor api.functional.discussionBoard.citizen.comments.replies.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
