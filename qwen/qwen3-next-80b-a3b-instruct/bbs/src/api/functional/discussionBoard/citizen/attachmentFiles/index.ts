import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardAttachment } from "../../../../structures/IDiscussionBoardAttachment";
import { IPageIDiscussionBoardAttachment } from "../../../../structures/IPageIDiscussionBoardAttachment";

/**
 * Search and retrieve paginated attachments with filtering options.
 *
 * This operation enables the retrieval of a comprehensive list of file
 * attachments from the discussion_board_attachments table with advanced
 * filtering and pagination capabilities. Unlike simple GET operations, this
 * uses PATCH to accommodate complex search criteria that cannot be passed
 * effectively through URL parameters alone.
 *
 * The system supports filtering by:
 *
 * - File status (active, removed)
 * - File type (jpeg, png, gif, pdf, txt, docx)
 * - Date ranges (created after/before)
 * - File size ranges
 * - Search terms in filename
 *
 * The operation returns paginated results with configurable page sizes,
 * defaulting to 20 attachments per page. The response includes metadata about
 * the total count of matching attachments and the current page information.
 *
 * This operation is publicly accessible to authenticated users (both citizens
 * and moderators) to allow discovery of attached resources. However, only
 * moderators can view attachments with status 'removed' since these represent
 * deleted content retained for audit purposes.
 *
 * The search respects the business rule of not exposing deleted attachments to
 * citizens unless they were the original uploader of the post containing the
 * attachment. This operation facilitates content governance and audit by
 * providing moderators with a complete overview of all attachments, including
 * those marked for removal.
 *
 * Downloads of attachments are handled through separate public endpoints that
 * serve the storage_path directly, so this operation only returns metadata and
 * links, not binary file data.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for finding
 *   attachments
 * @path /discussionBoard/citizen/attachmentFiles
 * @accessor api.functional.discussionBoard.citizen.attachmentFiles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for finding attachments */
    body: IDiscussionBoardAttachment.IRequest;
  };
  export type Body = IDiscussionBoardAttachment.IRequest;
  export type Response = IPageIDiscussionBoardAttachment;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/citizen/attachmentFiles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/citizen/attachmentFiles";
  export const random = (): IPageIDiscussionBoardAttachment =>
    typia.random<IPageIDiscussionBoardAttachment>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
