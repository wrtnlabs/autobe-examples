import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardBan } from "../../../../structures/IDiscussionBoardBan";

/**
 * Retrieve a specific ban record from the system. This operation fetches a
 * single ban record by its unique identifier from the discussion_board_bans
 * table, which logs all user bans imposed by moderators.
 *
 * The ban record includes the banned citizen's identifier, the moderator who
 * imposed the ban, the reason for the ban, the start and end dates of the ban
 * period, and whether the ban is permanent. This endpoint provides detailed
 * audit information about moderation actions taken on the platform.
 *
 * Security: Only authorized actors can access this information, and the
 * operation is designed to be accessed only for audit and administrative
 * purposes. Sentry data is protected and not exposed to regular citizens. This
 * operation does not allow filtering or searching - it retrieves exactly one
 * record by its primary key.
 *
 * Relationships: This operation is tightly coupled with the
 * discussion_board_bans table and the discussion_board_citizen and
 * discussion_board_moderator tables, as it references the user who was banned
 * and the moderator who issued the ban. This endpoint supports the moderation
 * review and appeal workflows described in the requirements document.
 *
 * Note: This endpoint should be used for administrative oversight, internal
 * investigations, and compliance reporting, not for general user-facing
 * functionality.
 *
 * @param props.connection
 * @param props.banId Unique identifier of the ban record to retrieve
 *   (system-generated UUID)
 * @path /discussionBoard/citizen/bans/:banId
 * @accessor api.functional.discussionBoard.citizen.bans.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the ban record to retrieve (system-generated
     * UUID)
     */
    banId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardBan;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/citizen/bans/:banId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/citizen/bans/${encodeURIComponent(props.banId ?? "null")}`;
  export const random = (): IDiscussionBoardBan =>
    typia.random<IDiscussionBoardBan>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("banId")(() => typia.assert(props.banId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
