import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardAppeal } from "../../../../structures/IDiscussionBoardAppeal";

/**
 * Retrieve a specific appeal record from the system's dispute management
 * system. This operation accesses the discussion_board_appeals database table
 * to fetch detailed information about a user-initiated appeal against a
 * moderation decision.
 *
 * The appeal object contains the original moderation action being challenged,
 * the citizen's reasoning for the appeal, any supporting documentation
 * submitted, the status of the appeal (pending, approved, rejected), the
 * timestamp of submission, and the moderator's decision if already processed.
 * This endpoint is critical for users seeking to contest content removals,
 * account suspensions, or other moderation actions.
 *
 * Security is enforced by verifying that the authenticated user has ownership
 * of the appeal record. Only the citizen who originally submitted the appeal
 * can view its details. This prevents unauthorized access to other users'
 * appeals. The system does not support batch retrieval or searching appeals
 * through this endpoint—each appeal must be accessed individually using its
 * unique identifier. This design ensures data privacy and adheres to the
 * principle of least privilege.
 *
 * Relationships: This operation depends on the discussion_board_appeals table
 * which has foreign key relationships to the citizen, moderator, and
 * moderation_actions tables. The appeal record stores the ID of the original
 * moderation action being challenged and links to the citizen who filed it. The
 * appeal status reflects the current state of the review process and is updated
 * when moderation teams make a decision on the appeal.
 *
 * Related operations: When an appeal is submitted, it triggers a notification
 * to the moderation team
 * ({@link IAutoBeInterfaceOperationApplication.IOperation: POST /appeals}). When
 * an appeal's status changes, a corresponding notification is sent to the
 * citizen ({@link IAutoBeInterfaceOperationApplication.IOperation: PATCH
 * /appeals/{appealId}/notifications}).
 *
 * @param props.connection
 * @param props.appealId Unique identifier of the appeal record to be retrieved.
 *   This corresponds to the primary key of the discussion_board_appeals table.
 * @path /discussionBoard/citizen/appeals/:appealId
 * @accessor api.functional.discussionBoard.citizen.appeals.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the appeal record to be retrieved. This
     * corresponds to the primary key of the discussion_board_appeals
     * table.
     */
    appealId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardAppeal;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/citizen/appeals/:appealId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/citizen/appeals/${encodeURIComponent(props.appealId ?? "null")}`;
  export const random = (): IDiscussionBoardAppeal =>
    typia.random<IDiscussionBoardAppeal>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("appealId")(() => typia.assert(props.appealId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
