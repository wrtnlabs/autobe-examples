import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardArchive } from "../../../../structures/IDiscussionBoardArchive";

/**
 * Retrieve a specific archived discussion board article by its unique archive
 * ID. This operation provides access to archived content that is no longer
 * visible in active discussion streams but preserved for historical,
 * compliance, or moderation review purposes.
 *
 * This endpoint is designed to retrieve archived articles from the
 * discussion_board_archives table, which serves as a persistent storage for
 * content removed from active channels due to moderation decisions, user
 * requests, or system archives. The operation returns the complete archived
 * article including all metadata, publication history, and associated audit
 * trail information.
 *
 * Safety and Permissions: Only authenticated citizens can access their own
 * archived articles. This restriction ensures privacy and prevents unauthorized
 * access to other users' archived content. The operation does not return
 * archived articles belonging to other users, even for administrator accounts,
 * unless explicitly permitted for moderation review in separate endpoints.
 *
 * Data Format: The response includes the full content of the archived article
 * as it existed at the time of archiving, including title, body text, original
 * author, creation timestamp, publication status history, and any associated
 * files or images from the original post. The article is returned in its final
 * archived state without any subsequent modifications.
 *
 * Related Objects: The response references the original
 * discussion_board_articles table record via the article_id foreign key, which
 * links to the archived version. The author information is retrieved from the
 * discussion_board_citizen table to maintain author attribution.
 *
 * Archived content is designated as read-only; no update or deletion operations
 * are allowed on archived articles. This operation is part of the platform's
 * legal compliance system to maintain immutable records of user-generated
 * content for regulatory and dispute resolution purposes.
 *
 * @param props.connection
 * @param props.archiveId Unique identifier of the archived article record in
 *   the discussion_board_archives table
 * @path /discussionBoard/citizen/archives/:archiveId
 * @accessor api.functional.discussionBoard.citizen.archives.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the archived article record in the
     * discussion_board_archives table
     */
    archiveId: string;
  };
  export type Response = IDiscussionBoardArchive;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/citizen/archives/:archiveId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/citizen/archives/${encodeURIComponent(props.archiveId ?? "null")}`;
  export const random = (): IDiscussionBoardArchive =>
    typia.random<IDiscussionBoardArchive>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("archiveId")(() => typia.assert(props.archiveId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
