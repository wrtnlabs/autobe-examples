/**
 * Retrieve all unread notification records for the authenticated citizen user.
 *
 * This operation retrieves notifications from the
 * discussion_board_notification_records table where the read_status is marked
 * as unread. The system tracks notification states using
 * discussion_board_notification_read_status records that link to both the
 * citizen and the notification record.
 *
 * The operation filters notifications by the citizen's ID, which is derived
 * from the authentication token. Only notifications that have a corresponding
 * discussion_board_notification_read_status record with read_flag = false are
 * returned. The notifications are ordered by creation timestamp with the most
 * recent first.
 *
 * The response contains full notification details including type, title,
 * message content, target object ID, and creation timestamp. This ensures
 * citizens can understand the context of each unread notification and act
 * appropriately.
 *
 * For performance optimization, the operation uses an efficient database join
 * between discussion_board_notification_records and
 * discussion_board_notification_read_status tables. The system employs
 * appropriate indexing on citizen_id and read_flag columns. The operation has
 * been designed to handle high-volume notification systems with thousands of
 * notifications per user.
 *
 * Related operations: Mark notification as read (PUT
 * /notifications/{notificationId}/read), Clear all unread notifications (DELETE
 * /notifications/user/unread).
 *
 * @param props.connection
 * @path /discussionBoard/citizen/notifications/user/unread
 * @accessor api.functional.discussionBoard.citizen.notifications.user.unread.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPageIDiscussionBoardNotificationRecord;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/citizen/notifications/user/unread",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/discussionBoard/citizen/notifications/user/unread";
  export const random = (): IPageIDiscussionBoardNotificationRecord =>
    typia.random<IPageIDiscussionBoardNotificationRecord>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
