import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardArticleStatusLog } from "../../../../../structures/IDiscussionBoardArticleStatusLog";
import { IPageIDiscussionBoardArticleStatusLog } from "../../../../../structures/IPageIDiscussionBoardArticleStatusLog";

/**
 * Retrieve the complete audit history of publication status changes for a
 * specific article on the discussion board. This operation queries the
 * discussion_board_article_status_logs table to return all logged transitions
 * of an article's publication state, including draft, pending review,
 * published, hidden, and unpublished status changes. Each log entry captures
 * the transition timestamp, the actor who initiated the change (system or
 * moderator), the reason for the status change if provided, and the article's
 * state immediately after the transition. The operation is designed for
 * compliance auditing and content moderation review, providing full
 * traceability of how an article's visibility state evolved over time.
 *
 * This is a read-only operation that does not modify any data. It supports
 * complex filtering and sorting through request parameters, with pagination
 * support to handle large audit trails. The response includes a summary view of
 * each status transition in a structured format optimized for display in
 * moderation interfaces and compliance dashboards.
 *
 * Security is enforced through user authorization: only the article's author
 * and system moderators can access its status history. Regular citizens cannot
 * view status logs of articles they did not author, ensuring privacy and
 * preventing unauthorized audit trail access. The system automatically verifies
 * article ownership against the authenticated user's identity during access.
 *
 * Implementation note: This operation does not map to a single database table
 * for data retrieval - instead it combines data from the
 * discussion_board_article_statuses table (current status) and
 * discussion_board_article_status_logs table (historical transitions) using
 * JOIN operations. This design ensures maximum efficiency and allows for
 * retrieval of both current state and full history in one API call. The status
 * transition sequence is ordered chronologically through the timestamp field to
 * recreate the complete editorial timeline for each article.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article whose status
 *   log history is being retrieved. This UUID must correspond to an existing
 *   article in the discussion_board_articles table.
 * @param props.body Filtering criteria and pagination parameters for status log
 *   retrieval
 * @path /discussionBoard/citizen/articles/:articleId/status-logs
 * @accessor api.functional.discussionBoard.citizen.articles.status_logs.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target article whose status log history is
     * being retrieved. This UUID must correspond to an existing article in
     * the discussion_board_articles table.
     */
    articleId: string;

    /** Filtering criteria and pagination parameters for status log retrieval */
    body: IDiscussionBoardArticleStatusLog.IRequest;
  };
  export type Body = IDiscussionBoardArticleStatusLog.IRequest;
  export type Response = IPageIDiscussionBoardArticleStatusLog.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/citizen/articles/:articleId/status-logs",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/citizen/articles/${encodeURIComponent(props.articleId ?? "null")}/status-logs`;
  export const random = (): IPageIDiscussionBoardArticleStatusLog.ISummary =>
    typia.random<IPageIDiscussionBoardArticleStatusLog.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
