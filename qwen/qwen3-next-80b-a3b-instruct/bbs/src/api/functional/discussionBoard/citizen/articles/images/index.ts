/**
 * Upload new image attachments to a specific discussion board article. This
 * operation allows citizens to add image files to an article for visual
 * enrichment, enhancing content presentation and user engagement.
 *
 * The operation requires an authenticated citizen user with write access to the
 * article. The article must exist and be in a publishable state (draft,
 * pending, or published). Each uploaded image must be a valid image file (PNG,
 * JPG, JPEG, GIF, WebP, SVG) with a maximum size of 5MB as specified in the
 * system configuration. The operation creates a new entry in the
 * discussion_board_article_images table, establishing a many-to-one
 * relationship with the target article.
 *
 * The system automatically generates thumbnail metadata for each uploaded image
 * and links it to the discussion_board_attachments and
 * discussion_board_thumbnails tables for efficient display. The original image
 * is stored in secure object storage. The operation returns the complete image
 * record with auto-generated fields including upload timestamp, file metadata,
 * and the generated thumbnail URI.
 *
 * Security: Only authenticated citizens can upload images to articles they have
 * permission to modify. Rate limiting enforces a maximum of 10 images per
 * request and 50 images per article. The upload endpoint is protected against
 * malicious file injection by validating file content type against the actual
 * image binary signature, not just the file extension.
 *
 * Related operations: GET /articles/{articleId}/images (list article images),
 * DELETE /articles/{articleId}/images/{imageId} (remove an image).
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article. This
 *   corresponds to the article's primary key in the discussion_board_articles
 *   table.
 * @param props.body Contains the image file data to be uploaded and associated
 *   with the article.
 * @path /discussionBoard/citizen/articles/:articleId/images
 * @accessor api.functional.discussionBoard.citizen.articles.images.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
