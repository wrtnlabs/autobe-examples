/**
 * Retrieve the publication history log for a specific article. This operation
 * operates on the discussion_board_article_publication_log table and provides a
 * chronological record of all status changes and publication events associated
 * with the target article.
 *
 * Each log entry captures the transition between article statuses, including
 * the timestamp, the actor responsible for the status change (if applicable),
 * and the context of the change (e.g., initial publication, moderation action,
 * user retraction). This enables users and moderators to audit when and why an
 * article became visible or hidden over time.
 *
 * The publication log does not include the article's content, metadata, or
 * comments - only the state transitions concerning its publication status. The
 * system automatically generates these logs whenever an article's status
 * changes via the discussion_board_article_statuses table, ensuring a complete
 * and immutable audit trail. This operation aggregates these automatic events
 * for a single article, ordered chronologically from oldest to newest.
 *
 * For performance and clarity, this endpoint supports pagination and filtering
 * of log entries by status type or date range. Security: Only authenticated
 * users (citizen or moderator) with access to the article can view its
 * publication log. This prevents unauthorized actors from tracking unpublished
 * content history. The system ensures that logs for hidden or deleted articles
 * are only accessible to moderators with appropriate permissions. Related
 * operations: GET /articles/{articleId} (retrieve article details), PATCH
 * /articles (search articles by status).
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article. This UUID
 *   references the discussion_board_articles table and identifies the specific
 *   article whose publication history is being requested.
 * @param props.body Filtering and pagination parameters for publication log
 *   retrieval.
 * @path /discussionBoard/citizen/articles/:articleId/publication-logs
 * @accessor api.functional.discussionBoard.citizen.articles.publication_logs.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
