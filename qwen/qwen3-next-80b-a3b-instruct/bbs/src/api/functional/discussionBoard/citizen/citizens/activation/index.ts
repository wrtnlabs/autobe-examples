import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardCitizenActivationStatus } from "../../../../../structures/IDiscussionBoardCitizenActivationStatus";

/**
 * Retrieve the activation status of a citizen account from the discussion board
 * system. This operation queries the discussion_board_citizen table to
 * determine if the specified citizen's account is currently active or
 * deactivated. The activation status reflects whether the citizen has completed
 * account verification and is permitted to participate in discussions and post
 * content on the platform.
 *
 * Account activation is a critical security and compliance feature that
 * prevents unauthorized or unverified users from engaging with the platform.
 * The system enforces mandatory account verification to ensure accountability
 * and reduce spam or malicious activity. This operation supports platform
 * security policies by providing a standardized means to check account
 * eligibility for interaction.
 *
 * When a citizen registers, their account is initially inactive. Activation
 * occurs either through manual verification by a moderator or automatic
 * verification upon meeting eligibility criteria (e.g., email confirmation).
 * This endpoint allows administrators, moderators, or specific system services
 * to programmatically verify account status before granting access to content
 * creation features.
 *
 * The operation returns a structured response containing the citizen's
 * activation status, with a success response indicating the current state. No
 * request body is required as the citizen identifier is provided via the path
 * parameter.
 *
 * @param props.connection
 * @param props.citizenId Unique identifier of the target citizen account. This
 *   identifier maps to the primary key of the discussion_board_citizen table in
 *   the database and must be a valid UUID format.
 * @path /discussionBoard/citizen/citizens/:citizenId/activation
 * @accessor api.functional.discussionBoard.citizen.citizens.activation.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target citizen account. This identifier maps
     * to the primary key of the discussion_board_citizen table in the
     * database and must be a valid UUID format.
     */
    citizenId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardCitizenActivationStatus;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/citizen/citizens/:citizenId/activation",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/citizen/citizens/${encodeURIComponent(props.citizenId ?? "null")}/activation`;
  export const random = (): IDiscussionBoardCitizenActivationStatus =>
    typia.random<IDiscussionBoardCitizenActivationStatus>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("citizenId")(() => typia.assert(props.citizenId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
