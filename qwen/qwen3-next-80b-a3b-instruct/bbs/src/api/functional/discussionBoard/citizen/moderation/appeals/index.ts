import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardAppeal } from "../../../../../structures/IDiscussionBoardAppeal";

/**
 * Submit a formal appeal against a moderation decision on the discussion board
 * platform.
 *
 * This operation allows citizens to formally appeal moderation actions such as
 * content removal, account suspension, or warnings. The appeal is linked to a
 * specific moderation action via the moderation_action_id field, and includes a
 * free-form justification provided by the citizen.
 *
 * The system records the appeal as a new entry in the discussion_board_appeals
 * table, with status set to "pending" by default. Appeals are then reviewed by
 * moderators who can either uphold the original decision or rescind it. The
 * platform enforces a limit of 3 active appeals per citizen at any time to
 * prevent abuse.
 *
 * This operation does not modify the underlying moderation action or its
 * outcome; it simply creates a review request that triggers the appeal
 * workflow. The created_at timestamp is automatically set to the current time
 * when the appeal is submitted, and the status field is set to "pending" by
 * default. Related operations include GET /moderation/appeals for viewing
 * pending appeals and PATCH /moderation/appeals/{appealId}/status for moderator
 * response.
 *
 * Security: Only authenticated citizens can submit appeals. The citizen_id
 * field is automatically derived from the authenticated user's JWT token and
 * cannot be overridden in the request body. Attempting to submit an appeal for
 * a moderation action that doesn't exist or has already been resolved will
 * return a 404 error.
 *
 * @param props.connection
 * @param props.body Information required to submit an appeal against a
 *   moderation decision.
 * @path /discussionBoard/citizen/moderation/appeals
 * @accessor api.functional.discussionBoard.citizen.moderation.appeals.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Information required to submit an appeal against a moderation
     * decision.
     */
    body: IDiscussionBoardAppeal.ICreate;
  };
  export type Body = IDiscussionBoardAppeal.ICreate;
  export type Response = IDiscussionBoardAppeal;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/citizen/moderation/appeals",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/citizen/moderation/appeals";
  export const random = (): IDiscussionBoardAppeal =>
    typia.random<IDiscussionBoardAppeal>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
