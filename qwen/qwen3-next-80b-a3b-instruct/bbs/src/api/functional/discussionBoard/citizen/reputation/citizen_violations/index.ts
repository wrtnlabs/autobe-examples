import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardCitizenViolation } from "../../../../../structures/IDiscussionBoardCitizenViolation";

/**
 * Retrieve a specific citizen violation record from the system. This operation
 * fetches the violation data from the discussion_board_citizen_violations table
 * in the database schema, which records when citizens have violated community
 * policy.
 *
 * This endpoint is used to view detailed information about a single violation
 * incident, including the violation reason, date and time, the citizen who was
 * violated, and the moderator or system that reported the violation. The
 * violation details are critical for citizens to understand why their actions
 * were flagged and for moderators to audit their decisions.
 *
 * The violation data includes metadata about the context of the violation, such
 * as associated content IDs, and may contain policy violation codes. Access to
 * this endpoint ensures transparency in the moderation process. This operation
 * requires authentication and authorization as a citizen to view their own
 * violations. The system ensures that users can only access their own violation
 * records unless explicitly granted broader access.
 *
 * The operation returns a full violation object with all details, including
 * timestamps, violation type codes, and the moderation decision explanation
 * text. This ensures citizens are informed about the specific nature of their
 * violation and the rules that were broken. Related operations: List citizen
 * violations (PATCH /reputation/citizen-violations) to view all violations.
 * This is a read-only operation and does not modify the violation record.
 *
 * @param props.connection
 * @param props.violationId Unique identifier of the target violation record
 *   (scoped to citizen)
 * @path /discussionBoard/citizen/reputation/citizen-violations/:violationId
 * @accessor api.functional.discussionBoard.citizen.reputation.citizen_violations.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target violation record (scoped to citizen) */
    violationId: string;
  };
  export type Response = IDiscussionBoardCitizenViolation;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/citizen/reputation/citizen-violations/:violationId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/citizen/reputation/citizen-violations/${encodeURIComponent(props.violationId ?? "null")}`;
  export const random = (): IDiscussionBoardCitizenViolation =>
    typia.random<IDiscussionBoardCitizenViolation>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("violationId")(() => typia.assert(props.violationId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
