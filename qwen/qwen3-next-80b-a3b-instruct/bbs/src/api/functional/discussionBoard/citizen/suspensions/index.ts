import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardSuspension } from "../../../../structures/IDiscussionBoardSuspension";

/**
 * Retrieve detailed information about a specific user suspension from the
 * discussion board system. This operation retrieves data from the
 * discussion_board_suspensions table, which records all suspension events
 * imposed on citizens for policy violations. The suspension record includes the
 * start and end dates of the suspension, the reason provided by the moderator,
 * the moderator's identifier, and the affected citizen's account information.
 *
 * This endpoint is designed for administrative review and user appeal purposes.
 * Moderators can use this to verify suspension details before making final
 * decisions, and suspended users can retrieve information about their
 * suspension for appeal purposes. The endpoint returns comprehensive suspension
 * records that include the full context of the restriction period, the
 * violation justification, and the administrative process details.
 *
 * Security considerations include ensuring that only authorized users can
 * access suspension details. Suspended citizens can view their own suspension
 * records, but cannot view other users' records. Moderators and administrators
 * can view all suspension records for auditing and review purposes. The system
 * enforces strict ownership verification to prevent unauthorized disclosure of
 * sensitive suspension information.
 *
 * Note: Suspension records are permanent and immutable. Once a suspension is
 * recorded, it cannot be undone or modified through this API system, as it
 * serves as an audit trail of disciplinary actions.
 *
 * @param props.connection
 * @param props.suspensionId Unique identifier of the specific suspension record
 *   to retrieve (global scope)
 * @path /discussionBoard/citizen/suspensions/:suspensionId
 * @accessor api.functional.discussionBoard.citizen.suspensions.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the specific suspension record to retrieve
     * (global scope)
     */
    suspensionId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardSuspension;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/citizen/suspensions/:suspensionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/citizen/suspensions/${encodeURIComponent(props.suspensionId ?? "null")}`;
  export const random = (): IDiscussionBoardSuspension =>
    typia.random<IDiscussionBoardSuspension>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("suspensionId")(() => typia.assert(props.suspensionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
