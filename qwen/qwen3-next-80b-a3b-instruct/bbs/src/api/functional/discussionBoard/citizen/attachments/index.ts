/**
 * Retrieve a specific attachment by its unique identifier from the discussion
 * board system. This operation operates on the discussion_board_attachments
 * table and returns detailed metadata about the requested attachment, including
 * its file name, size, MIME type, upload timestamp, and associated content
 * reference.
 *
 * The attachmentId parameter must match the unique identifier of an existing
 * attachment record in the database. This endpoint is designed for file
 * retrieval and serves as a gateway to the stored attachment content. The file
 * data itself is not returned directly in the response body but is accessible
 * via a secure, time-limited URI as specified in the response schema.
 *
 * Security: This endpoint implements an authorship validation check where the
 * requesting user's authentication token is matched against the attachment's
 * original uploader. Only authenticated users who have permission to view the
 * associated content can access the attachment. Public attachments may be made
 * available for anonymous access based on the content's publication status and
 * visibility rules.
 *
 * Error handling: Returns 404 Not Found if the attachmentId does not exist, 403
 * Forbidden if the user lacks permissions to access the attachment, or 500
 * Internal Server Error if there is a system issue retrieving the file. The
 * attachment remains accessible through this endpoint for its lifetime or until
 * explicitly removed by moderation unless it's part of archived or deleted
 * content.
 *
 * @param props.connection
 * @param props.attachmentId Unique identifier of the target attachment (global
 *   scope)
 * @path /discussionBoard/citizen/attachments/:attachmentId
 * @accessor api.functional.discussionBoard.citizen.attachments.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target attachment (global scope) */
    attachmentId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardAttachment;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/citizen/attachments/:attachmentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/citizen/attachments/${encodeURIComponent(props.attachmentId ?? "null")}`;
  export const random = (): IDiscussionBoardAttachment =>
    typia.random<IDiscussionBoardAttachment>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("attachmentId")(() => typia.assert(props.attachmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

