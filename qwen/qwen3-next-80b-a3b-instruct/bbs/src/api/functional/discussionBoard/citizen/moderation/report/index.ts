import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardReport } from "../../../../../structures/IDiscussionBoardReport";

/**
 * Submit a formal report against content on the discussion board platform to
 * initiate moderation review. This operation targets the
 * discussion_board_reports table in the database and allows citizens to
 * formally report violations by providing detailed context about the
 * problematic content, including the report type and supporting text.
 *
 * The operation accepts a report payload that references a specific target
 * content item (either an article or comment), categorizes the violation using
 * predefined report types, and provides an optional free-text description to
 * help moderators understand the nature of the violation. All reports are
 * logged as audit events and trigger automated moderation workflows.
 *
 * Security: Only authenticated citizens can submit reports. Each user is
 * limited to a reasonable number of reports per day to prevent abuse. The
 * system automatically flags frequent or low-quality reports, potentially
 * leading to temporary suspension of reporting privileges.
 *
 * The report is not immediately actionable; it enters a moderation queue where
 * moderators review the submission, validate the concern, and determine
 * appropriate action such as content removal, user warning, or account
 * suspension. The reporting process is confidential - the target user's
 * identity is protected from the reporter while the reporter's identity is
 * protected from the target.
 *
 * Related operations: GET /moderation/report/{reportId} (view report status),
 * GET /moderation/reports/me (list user's reports), GET /moderation/reports
 * (admin view of all reports, requires admin role).
 *
 * @param props.connection
 * @param props.body Payload with details of the violation report to be
 *   submitted.
 * @path /discussionBoard/citizen/moderation/report
 * @accessor api.functional.discussionBoard.citizen.moderation.report.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** Payload with details of the violation report to be submitted. */
    body: IDiscussionBoardReport.ICreate;
  };
  export type Body = IDiscussionBoardReport.ICreate;
  export type Response = IDiscussionBoardReport;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/citizen/moderation/report",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/citizen/moderation/report";
  export const random = (): IDiscussionBoardReport =>
    typia.random<IDiscussionBoardReport>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
