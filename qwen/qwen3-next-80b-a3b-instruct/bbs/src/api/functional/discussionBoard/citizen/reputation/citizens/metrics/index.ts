import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardCitizenMetrics } from "../../../../../../structures/IDiscussionBoardCitizenMetrics";

/**
 * Retrieve comprehensive reputation metrics for citizens on the discussion
 * board platform.
 *
 * This operation calculates and presents a comprehensive reputation profile for
 * each citizen based on their activity, trustworthiness, and moderation
 * history. It integrates data from the discussion_board_citizen_trust_scores,
 * discussion_board_citizen_suspensions, discussion_board_citizen_violations,
 * and discussion_board_report_aggregations tables to provide a holistic view of
 * citizen reputation.
 *
 * The reputation score represents the citizen's standing within the community,
 * calculated by combining positive contributions (trust scores) with negative
 * actions (suspensions and violations). Higher scores indicate more trusted
 * community members, while lower scores indicate potential reliability
 * concerns.
 *
 * The endpoint returns metrics including total trust score, suspension history,
 * violation counts, and report aggregations relevant to the citizen's behavior.
 * This information helps users understand community standing and assists
 * moderators in identifying patterns of behavior.
 *
 * The operation is designed for use by citizens to view their own standing and
 * by moderators to assess community members' reputations.
 *
 * Note: This is a read-only operation that aggregates historical behavioral
 * data.
 *
 * Related operations: PATCH /reputation/citizens/{citizenId} (to view
 * individual citizen metrics), GET /reputation/metrics (to view aggregate
 * community metrics).
 *
 * @param props.connection
 * @path /discussionBoard/citizen/reputation/citizens/metrics
 * @accessor api.functional.discussionBoard.citizen.reputation.citizens.metrics.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = IDiscussionBoardCitizenMetrics;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/citizen/reputation/citizens/metrics",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/discussionBoard/citizen/reputation/citizens/metrics";
  export const random = (): IDiscussionBoardCitizenMetrics =>
    typia.random<IDiscussionBoardCitizenMetrics>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
