import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardChannel } from "../../../../structures/IDiscussionBoardChannel";

/**
 * Retrieve a specific discussion board channel by its unique identifier.
 *
 * This operation fetches detailed information about a single channel from the
 * discussion_board_channels table, including its name, description, creation
 * timestamp, and moderation status. The channel identifier is provided in the
 * path parameter as channelId.
 *
 * The channel data returned includes essential metadata for displaying the
 * channel to users and for selecting appropriate content filters. Community
 * channels with a published status can be accessed by registered citizens.
 * Pending or hidden channels are not visible to regular users.
 *
 * Security: Only authenticated citizens can retrieve channel details. The
 * system checks the user's authentication token against the channel's access
 * control policy. Rate limiting is applied to prevent automated enumeration of
 * channel identifiers.
 *
 * This operation is used by the frontend application to load channel
 * information when navigating to a specific channel page. The operation is
 * paired with POST /channels for creating new channels and DELETE
 * /channels/{channelId} for removing channels.
 *
 * Related operations: POST /channels (create new channel), PATCH /channels
 * (list/search channels), DELETE /channels/{channelId} (delete channel).
 *
 * @param props.connection
 * @param props.channelId Unique identifier of the target channel
 *   (system-generated UUID)
 * @path /discussionBoard/citizen/channels/:channelId
 * @accessor api.functional.discussionBoard.citizen.channels.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target channel (system-generated UUID) */
    channelId: string;
  };
  export type Response = IDiscussionBoardChannel;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/citizen/channels/:channelId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/citizen/channels/${encodeURIComponent(props.channelId ?? "null")}`;
  export const random = (): IDiscussionBoardChannel =>
    typia.random<IDiscussionBoardChannel>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("channelId")(() => typia.assert(props.channelId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
