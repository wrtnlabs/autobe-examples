import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardWarning } from "../../../../structures/IDiscussionBoardWarning";

/**
 * Update a warning issued to a citizen on the discussion board system. This
 * operation modifies an existing warning record in the
 * discussion_board_warnings table, which tracks violations of community
 * guidelines and moderation actions. The warning is identified by its unique
 * warningId path parameter.
 *
 * The operation requires the citizen or moderator to provide updated details
 * about the warning, including the new warning level, updated reason, and any
 * additional context about the violation. The warning system supports three
 * levels: none, moderate, and severe, and the update must preserve the warning
 * creation timestamp and original reporter information for audit trail
 * purposes.
 *
 * Security and Authorization: Both citizens and moderators can update warnings
 * they've issued. Moderators can update any warning on the platform. The system
 * enforces that only the original issuer or a moderator can modify a warning.
 * Unauthorized attempts to update a warning will return a 403 Forbidden error.
 * For integrity purposes, the actual modification timestamp is automatically
 * recorded by the system and cannot be overridden by the client.
 *
 * Implementation note: This update operation does not modify the created_at
 * timestamp of the warning, which is preserved for audit purposes. Only the
 * reason, level, and additional context fields are modifiable. The system
 * automatically logs this moderation action in the
 * discussion_board_moderation_logs table with appropriate context about the
 * update. Related operations: GET /warnings/{warningId} to retrieve warning
 * details, DELETE /warnings/{warningId} to remove a warning (soft delete).
 *
 * @param props.connection
 * @param props.warningId Unique identifier of the warning to update
 * @param props.body Updated details for the warning record
 * @path /discussionBoard/citizen/warnings/:warningId
 * @accessor api.functional.discussionBoard.citizen.warnings.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the warning to update */
    warningId: string;

    /** Updated details for the warning record */
    body: IDiscussionBoardWarning.IUpdate;
  };
  export type Body = IDiscussionBoardWarning.IUpdate;
  export type Response = IDiscussionBoardWarning;

  export const METADATA = {
    method: "PUT",
    path: "/discussionBoard/citizen/warnings/:warningId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/citizen/warnings/${encodeURIComponent(props.warningId ?? "null")}`;
  export const random = (): IDiscussionBoardWarning =>
    typia.random<IDiscussionBoardWarning>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("warningId")(() => typia.assert(props.warningId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
