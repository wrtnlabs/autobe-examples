/**
 * Create a new active discussion board post with title and content by an
 * authenticated citizen.
 *
 * Create a new discussion board post by submitting a title and body content
 * from an authenticated citizen user. This operation initiates a new
 * conversation thread on the platform and must adhere to strict business rules
 * for input validation.
 *
 * The system requires the title to be at least 5 characters and the body to be
 * at least 10 characters. Attempts to submit a post with an empty or undersized
 * title or content are rejected with a 400 error, accompanied by a
 * human-readable message that identifies the specific field that requires
 * correction.
 *
 * Authentication and authorization are enforced before processing: only
 * authenticated users who have verified their email address (email_verified =
 * true) can create posts. Users with unverified email addresses receive an HTTP
 * 403 response with the message "You must verify your email address before
 * posting." The system identifies the creating citizen by the JWT token in the
 * request header, retrieving the system's internal citizen_id reference for the
 * request.
 *
 * The created post is always set to status 'active', meaning it will be
 * immediately visible in public feed and search results. Timestamps are
 * automatically generated by the system: created_at is set to the instant of
 * submission, and updated_at is initialized to the same value. The moderator_id
 * is left null, as no moderator action is involved in creation. The deleted_at
 * field is always null at creation as the post is not deleted.
 *
 * The operation does not support direct attachment of files during this
 * request. Attachment uploads must occur through a separate endpoint
 * (/posts/{postId}/attachments). This separation of concerns improves system
 * reliability and allows for optimized file handling outside the primary POST
 * request lifecycle.
 *
 * When the post is successfully created, the system returns the full post
 * object with all fields set, including the newly generated UUID id. This
 * allows the client to immediately access the post's unique identifier for
 * subsequent operations such as adding comments, attaching files, or retrieving
 * the post on a detail page.
 *
 * @param props.connection
 * @param props.body The data structure containing the title and body of the new
 *   post to be created. Title must be 5+ characters, body must be 10+
 *   characters.
 * @path /discussionBoard/citizen/posts
 * @accessor api.functional.discussionBoard.citizen.posts.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
