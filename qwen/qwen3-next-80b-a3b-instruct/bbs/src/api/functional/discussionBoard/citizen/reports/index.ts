import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardReport } from "../../../../structures/IDiscussionBoardReport";
export * as notifications from "./notifications/index";

/**
 * Retrieve detailed report information by unique identifier. This operation
 * accesses the discussion_board_reports table to return comprehensive data
 * about a specific report submission, including the target content type,
 * reporter information, violation reason, status, and timestamp.
 *
 * The report is identified by its unique identifier (reportId) in the database.
 * This endpoint is designed for internal moderation systems and user-facing
 * report status checks. Both citizens (reporters) and moderators can access
 * report details for transparency and accountability.
 *
 * Security: Citizens can view reports they created, while moderators can view
 * all reports. The system enforces data isolation: reporting citizen can only
 * access their own reports unless they are a moderator.
 *
 * Operation flow: When a report is submitted, the system creates a record with
 * reporter ID, target content reference, violation reason, status, and creation
 * timestamp. This endpoint returns all these details along with
 * system-generated metadata.
 *
 * Related operations: GET /reports (list reports), PATCH /reports/{reportId}
 * (update report status).
 *
 * Database Schema Reference:
 *
 * - Discussion_board_reports table contains: id, reporter_id, target_type,
 *   target_id, reason, status, created_at, updated_at, resolved_by
 * - The id field serves as the primary key and is used as the path parameter
 *   reportId
 * - The reporter_id is a foreign key to discussion_board_citizen
 * - The target_type indicates the type of reported content (e.g., article,
 *   comment)
 * - The target_id links to the specific reported content
 * - Status can be: pending, reviewed, dismissed, confirmed, resolved
 * - Resolved_by references moderator_id when a moderator takes action
 *
 * @param props.connection
 * @param props.reportId Unique identifier of the target report record
 * @path /discussionBoard/citizen/reports/:reportId
 * @accessor api.functional.discussionBoard.citizen.reports.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target report record */
    reportId: string;
  };
  export type Response = IDiscussionBoardReport;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/citizen/reports/:reportId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/citizen/reports/${encodeURIComponent(props.reportId ?? "null")}`;
  export const random = (): IDiscussionBoardReport =>
    typia.random<IDiscussionBoardReport>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reportId")(() => typia.assert(props.reportId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
