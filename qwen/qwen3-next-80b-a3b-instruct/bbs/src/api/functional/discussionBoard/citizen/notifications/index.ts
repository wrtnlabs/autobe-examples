/**
 * Trigger a notification for a specific user or set of users based on system
 * events or user actions. This operation sends notifications according to
 * pre-configured templates and user preferences. It interacts with the
 * notification_records table to log the notification attempt, the
 * notification_templates table to retrieve the template content, and the
 * notification_preferences table to verify user opt-in settings.
 *
 * The trigger operation does not require user input parameters like email or
 * user ID as these are determined by the system context (e.g., post creation,
 * comment reply, report submission). Instead, it receives a trigger type
 * identifier (e.g., "POST_PUBLISHED", "COMMENT_REPLY", "REPORT_SUBMITTED") and
 * an optional context object with structured data such as article ID, comment
 * ID, or user ID being referenced. Security measures include validation that
 * the triggering action aligns with a permitted event type and checks user
 * notification preferences before sending.
 *
 * If a user has disabled notifications in their preferences, the system logs
 * the attempt but does not send the notification. Only users with active
 * notification preferences for the specific event type are targeted. The
 * operation will automatically append an attachment URI if the notification
 * template contains a file attachment reference.
 *
 * This operation is designed as a system-triggered event and must NOT be
 * interacted with directly by end users for spam protection. Access is
 * restricted to system services and moderator actions only. Related operations
 * include GET /notifications/preferences (to update user preferences) and GET
 * /notifications/templates (to view templates).
 *
 * @param props.connection
 * @param props.body Trigger type and contextual data that defines which
 *   notification template to send and to whom.
 * @path /discussionBoard/citizen/notifications/trigger
 * @accessor api.functional.discussionBoard.citizen.notifications.trigger
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function trigger(
  connection: IConnection,
  props: trigger.Props,
): Promise<trigger.Response> {
  return true === connection.simulate
    ? trigger.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...trigger.METADATA,
          path: trigger.path(),
          status: null,
        },
        props.body,
      );
}
