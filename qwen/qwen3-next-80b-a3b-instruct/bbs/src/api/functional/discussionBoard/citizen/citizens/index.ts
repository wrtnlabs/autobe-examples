/**
 * Retrieve a limited set of information about a citizen for administrative
 * investigation purposes. This operation is accessible only to moderators when
 * investigating reports. Returns only the citizen's code, email, registration
 * timestamp, and suspension status. Personal data such as IP addresses, trust
 * scores, and violation history are accessible through separate audit tables
 * and not exposed through this endpoint. This follows the privacy policy
 * requirement to minimize citizen data exposure.
 *
 * The operation accesses the discussion_board_citizen table in the database
 * schema. The citizenCode parameter must reference a valid citizen's unique
 * business identifier code. The system validates code existence and returns a
 * 404 error if not found.
 *
 * Only moderators can access this endpoint. The returned data excludes all
 * personal identifiers beyond code and email to comply with privacy policy. For
 * a citizen's own profile information, use the session-based user information
 * endpoint.
 *
 * Related operations: PATCH /citizens (search), GET /moderation/actions (audit
 * logs).
 *
 * @param props.connection
 * @param props.citizenId Unique identifier of the target citizen account in
 *   UUIDv4 format, referencing the primary key of the discussion_board_citizen
 *   table in the database schema.
 * @path /discussionBoard/citizen/citizens/:citizenId
 * @accessor api.functional.discussionBoard.citizen.citizens.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
