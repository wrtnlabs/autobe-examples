import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardActivityLog } from "../../../../structures/IDiscussionBoardActivityLog";

/**
 * Retrieve a specific activity log entry from the discussion board system. This
 * operation accesses the discussion_board_activity_logs table and returns
 * comprehensive details about a single logged event, including the actor,
 * action performed, target resource, timestamp, and contextual metadata.
 *
 * This endpoint is designed to support both citizen users and moderators who
 * require visibility into platform activities for auditing, troubleshooting, or
 * user support purposes. The activity log contains records of all
 * user-initiated actions and system events that impact content or user behavior
 * on the platform. Each log entry is uniquely identified by a logId and
 * contains immutable historical data.
 *
 * The activity log includes comprehensive metadata such as the IP address from
 * which the action originated, the user agent string for device identification,
 * and the specific target resource identifier (e.g., article ID, comment ID,
 * user ID) that was affected by the action. This granular detail enables
 * precise forensic analysis of platform events.
 *
 * Security considerations include token-based authentication validation prior
 * to access and auditing of all retrieval attempts. The data returned by this
 * endpoint is essential for maintaining platform integrity, investigating
 * suspicious activity, and ensuring compliance with content moderation
 * policies. This operation returns complete and unaltered historical records -
 * activity logs serve as the definitive source for tracking user actions.
 *
 * Related operations: The PATCH /activity-logs endpoint can be used to search a
 * range of activity logs using filtering and pagination criteria. This GET
 * /activity-logs/{logId} operation is the direct accessor for retrieving
 * individual log entries identified by their unique identifier.
 *
 * @param props.connection
 * @param props.logId Unique identifier of the specific activity log entry to
 *   retrieve
 * @path /discussionBoard/citizen/activity-logs/:logId
 * @accessor api.functional.discussionBoard.citizen.activity_logs.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the specific activity log entry to retrieve */
    logId: string;
  };
  export type Response = IDiscussionBoardActivityLog;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/citizen/activity-logs/:logId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/citizen/activity-logs/${encodeURIComponent(props.logId ?? "null")}`;
  export const random = (): IDiscussionBoardActivityLog =>
    typia.random<IDiscussionBoardActivityLog>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("logId")(() => typia.assert(props.logId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
