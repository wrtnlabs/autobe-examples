/**
 * Create a new vote on a comment in the discussion board.
 *
 * This operation allows authenticated citizens to submit a vote (upvote or
 * downvote) on a specific comment to signal approval or disapproval. Each
 * comment's vote count is maintained as a running total that influences content
 * visibility and reputation scoring.
 *
 * The operation accepts a vote value as a positive or negative integer (1 for
 * upvote, -1 for downvote) and associates it with the authenticated user's
 * account. Multiple votes from the same user on the same comment are not
 * permitted - existing votes will be overwritten.
 *
 * Security: Only authenticated citizens can vote on comments. The system checks
 * for valid authentication via JWT token and verifies the user has not been
 * banned or suspended. The vote value is constrained between -1 and 1 to
 * prevent manipulation.
 *
 * The operation updates the comment's overall vote count, which is used in the
 * comment ranking algorithm for sorting and display. It also updates the
 * citizen's trust score based on whether the vote was on content that was later
 * approved or flagged by moderators.
 *
 * Related operations: GET /comments/{commentId} (to retrieve comment and vote
 * count), GET /comments/{commentId}/votes (to review user's own votes).
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the target comment to vote on
 * @param props.body Vote data for submission on the target comment
 * @path /discussionBoard/comments/:commentId/votes
 * @accessor api.functional.discussionBoard.comments.votes.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** Unique identifier of the target comment to vote on */
    commentId: string;

    /** Vote data for submission on the target comment */
    body: IDiscussionBoardCommentVote.ICreate;
  };
  export type Body = IDiscussionBoardCommentVote.ICreate;
  export type Response = IDiscussionBoardCommentVote;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/comments/:commentId/votes",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/comments/${encodeURIComponent(props.commentId ?? "null")}/votes`;
  export const random = (): IDiscussionBoardCommentVote =>
    typia.random<IDiscussionBoardCommentVote>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

