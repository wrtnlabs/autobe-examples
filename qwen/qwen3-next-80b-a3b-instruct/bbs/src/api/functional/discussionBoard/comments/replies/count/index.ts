import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardNumberValue } from "../../../../../structures/IDiscussionBoardNumberValue";

/**
 * Retrieve the total count of reply comments linked to a specific parent
 * comment in the discussion board system. This operation operates on the
 * discussion_board_comment_replies database table and provides a lightweight
 * counter that returns only the numerical total of reply comments, optimized
 * for performance in high-volume scenarios.
 *
 * The operation serves a critical performance optimization need for the
 * discussion board interface, allowing the UI to display the total number of
 * replies without loading full reply data. Applications use this endpoint to
 * show reply counts in comment summaries, thread indicators, and UI badges
 * efficiently. Since the system handles millions of comments, this lightweight
 * counter avoids expensive JOIN operations or full data retrieval.
 *
 * The operation is designed to be called frequently by clients viewing comment
 * threads, with server-side caching implemented to minimize database load. It
 * leverages the database's COUNT aggregation function with direct index access
 * on the parent_comment_id field, ensuring sub-millisecond response times even
 * under high concurrency. The endpoint does not require user authentication
 * because reply counts are public metadata accessible to any viewer of the
 * discussion board, similar to how public post view counts are displayed.
 *
 * This endpoint is part of a performance-optimized API tier designed for
 * high-frequency, low-latency operations. It complements the full reply
 * retrieval API which may be called when users expand a comment thread and need
 * to view the actual reply content. For this endpoint, no request body is
 * needed as the comment identifier is provided via the path parameter.
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the parent comment whose reply
 *   count is being queried (UUID format)
 * @path /discussionBoard/comments/:commentId/replies/count
 * @accessor api.functional.discussionBoard.comments.replies.count.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the parent comment whose reply count is being
     * queried (UUID format)
     */
    commentId: string;
  };
  export type Response = IDiscussionBoardNumberValue;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/comments/:commentId/replies/count",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/comments/${encodeURIComponent(props.commentId ?? "null")}/replies/count`;
  export const random = (): IDiscussionBoardNumberValue =>
    typia.random<IDiscussionBoardNumberValue>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
