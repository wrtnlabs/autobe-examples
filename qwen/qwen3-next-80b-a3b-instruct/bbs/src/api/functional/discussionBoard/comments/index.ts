/**
 * Retrieve a single discussion board comment by ID.
 *
 * This operation retrieves a single comment from the discussion board system by
 * its unique identifier. The comment is linked to a specific post and contains
 * the complete content, author information, and status. The response includes
 * the comment's text content, creation and update timestamps, and current
 * status (active, deleted_by_moderator, or deleted_by_author).
 *
 * Security considerations ensure that only active comments are returned to
 * users. Deleted or removed comments will not be accessible through this
 * endpoint. The operation exclusively retrieves public-facing content that is
 * still visible to users, filtering out any content with status
 * 'deleted_by_moderator' or 'deleted_by_author' from the query results.
 *
 * This operation relates directly to the discussion_board_comments table in the
 * Prisma schema, utilizing its id, content, author_id, author_type, status,
 * created_at, and updated_at fields. The polymorphic author_type field (citizen
 * or moderator) indicates which user actor created the comment, and the status
 * field controls visibility. This operation does not return any editor or
 * moderator metadata unless explicitly requested in a separate moderation audit
 * endpoint.
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the target comment. This
 *   corresponds to the id field in the discussion_board_comments table and must
 *   be a valid UUID.
 * @path /discussionBoard/comments/:commentId
 * @accessor api.functional.discussionBoard.comments.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target comment. This corresponds to the id
     * field in the discussion_board_comments table and must be a valid
     * UUID.
     */
    commentId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardComment;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/comments/:commentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/comments/${encodeURIComponent(props.commentId ?? "null")}`;
  export const random = (): IDiscussionBoardComment =>
    typia.random<IDiscussionBoardComment>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

