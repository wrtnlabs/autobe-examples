import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardCommentVote } from "../../../structures/IDiscussionBoardCommentVote";

/**
 * Retrieve a specific comment vote record from the discussion board system.
 * This operation accesses the discussion_board_comment_votes table to return
 * detailed information about a single citizen's vote on a comment, including
 * the vote value, timestamp, and associated citizen and comment identifiers.
 *
 * The vote record contains a numeric value indicating the type of vote
 * (typically +1 for upvote, -1 for downvote) and is linked to both the comment
 * being voted on and the citizen who cast the vote. This data is crucial for
 * calculating comment reputation scores and identifying voting patterns.
 *
 * Security implementation follows strict read-only access policies: citizens
 * can only view their own vote records, while moderators may view any vote
 * record for moderation and audit purposes. The system ensures data privacy by
 * never exposing personal information about voters beyond their citizen
 * identifier.
 *
 * This operation supports direct access to individual vote records using the
 * unique vote identifier and is often used in conjunction with comment
 * retrieval operations to provide context for comment reputation.
 *
 * @param props.connection
 * @param props.voteId Unique identifier of the comment vote record to retrieve
 * @path /discussionBoard/comment-votes/:voteId
 * @accessor api.functional.discussionBoard.comment_votes.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the comment vote record to retrieve */
    voteId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardCommentVote;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/comment-votes/:voteId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/comment-votes/${encodeURIComponent(props.voteId ?? "null")}`;
  export const random = (): IDiscussionBoardCommentVote =>
    typia.random<IDiscussionBoardCommentVote>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("voteId")(() => typia.assert(props.voteId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
