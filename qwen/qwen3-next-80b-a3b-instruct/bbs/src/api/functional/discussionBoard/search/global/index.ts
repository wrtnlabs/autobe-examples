import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardSearch } from "../../../../structures/IDiscussionBoardSearch";
import { IPageIDiscussionBoardSearch } from "../../../../structures/IPageIDiscussionBoardSearch";

/**
 * Perform a unified global search across all public content types on the
 * discussion board, including articles, comments, posts, and file attachments.
 * This operation aggregates results from multiple database entities into a
 * single search response, enabling users to find relevant content regardless of
 * where it was originally posted.
 *
 * The implementation executes composite SQL queries that UNION results from the
 * discussion_board_articles, discussion_board_comments, discussion_board_posts,
 * discussion_board_attachment_images, and discussion_board_attachment_files
 * tables. Each result is tagged with its content type and includes only
 * publicly accessible data (published status confirmed) with minimal metadata
 * for quick display.
 *
 * Security: Only returns content that has been published and is not subject to
 * moderation restrictions. Private or draft content is excluded from results.
 * Rate limiting applies to prevent abuse of this high-resource operation.
 *
 * Implementation note: This does NOT map to a single database table - instead
 * it executes:
 *
 * SELECT 'article' as type, id, title as display_text, content as preview,
 * created_at, author_id FROM discussion_board_articles WHERE status =
 * 'published'
 *
 * UNION ALL
 *
 * SELECT 'comment' as type, id, content as display_text, content as preview,
 * created_at, author_id FROM discussion_board_comments WHERE status =
 * 'published'
 *
 * UNION ALL
 *
 * SELECT 'post' as type, id, title as display_text, content as preview,
 * created_at, author_id FROM discussion_board_posts WHERE status = 'published'
 *
 * UNION ALL
 *
 * SELECT 'image' as type, id, file_name as display_text, description as
 * preview, uploaded_at as created_at, uploaded_by as author_id FROM
 * discussion_board_attachment_images WHERE status = 'published'
 *
 * UNION ALL
 *
 * SELECT 'file' as type, id, file_name as display_text, description as preview,
 * uploaded_at as created_at, uploaded_by as author_id FROM
 * discussion_board_attachment_files WHERE status = 'published'
 *
 * ORDER BY created_at DESC LIMIT 50;
 *
 * This unified search serves the business requirement for users to find
 * relevant content across all content types within a single interface. Related
 * operations: GET /articles (search within articles only), PATCH /comments
 * (search within comments only).
 *
 * @param props.connection
 * @param props.body Search query parameters for global search including
 *   keywords, filters, and pagination controls.
 * @path /discussionBoard/search/global
 * @accessor api.functional.discussionBoard.search.global.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search query parameters for global search including keywords,
     * filters, and pagination controls.
     */
    body: IDiscussionBoardSearch.IRequest;
  };
  export type Body = IDiscussionBoardSearch.IRequest;
  export type Response = IPageIDiscussionBoardSearch.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/search/global",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/search/global";
  export const random = (): IPageIDiscussionBoardSearch.ISummary =>
    typia.random<IPageIDiscussionBoardSearch.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
