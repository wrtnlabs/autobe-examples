import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardPost } from "../../../../structures/IDiscussionBoardPost";
import { IPageIDiscussionBoardPost } from "../../../../structures/IPageIDiscussionBoardPost";

/**
 * Search and retrieve a filtered, paginated list of discussion board posts.
 *
 * This operation allows citizens to search for discussion board posts using
 * keyword matching across both post titles and content bodies. The search
 * functionality returns results ordered by creation date in descending order
 * (newest first) to ensure users see the most recent content first. This
 * feature is critical for content discovery and aligns with the business
 * requirement for citizens to find relevant discussions based on keywords.
 *
 * The operation implements comprehensive search capabilities with full-text
 * search optimization using PostgreSQL's trigram indexes on both title and body
 * fields. This enables partial matches and spelling tolerance in search
 * queries. The result set is paginated with a default limit of 20 posts per
 * page, as specified in the requirements. The pagination parameters can be
 * extended to support custom page sizes and offsets.
 *
 * A key business requirement is to explicitly exclude deleted or reported posts
 * from search results. The operation automatically filters out any posts where
 * status is not 'active', ensuring users only see content that is publicly
 * available. This filtering is consistent with the operational requirement that
 * defines the visibility of posts in search results.
 *
 * The search operation is implemented as a PATCH request because it carries
 * complex search parameters in the request body, rather than as URL query
 * parameters. This approach allows for more sophisticated search criteria while
 * maintaining RESTful design principles. The operation supports attributes such
 * as keyword search terms, page number, and page size, though these are modeled
 * within the request schema rather than as path or query parameters.
 *
 * @param props.connection
 * @param props.body Search parameters for filtering and paginating discussion
 *   board posts including keywords, page number, and page size
 * @path /discussionBoard/search/posts
 * @accessor api.functional.discussionBoard.search.posts.search
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function search(
  connection: IConnection,
  props: search.Props,
): Promise<search.Response> {
  return true === connection.simulate
    ? search.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...search.METADATA,
          path: search.path(),
          status: null,
        },
        props.body,
      );
}
export namespace search {
  export type Props = {
    /**
     * Search parameters for filtering and paginating discussion board posts
     * including keywords, page number, and page size
     */
    body: IDiscussionBoardPost.IRequest;
  };
  export type Body = IDiscussionBoardPost.IRequest;
  export type Response = IPageIDiscussionBoardPost.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/search/posts",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/search/posts";
  export const random = (): IPageIDiscussionBoardPost.ISummary =>
    typia.random<IPageIDiscussionBoardPost.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: search.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: search.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
