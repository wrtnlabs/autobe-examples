/**
 * Retrieve details of a specific attachment by ID.
 *
 * Fetch the metadata of a single attachment file from the system using its
 * unique identifier.
 *
 * The operation retrieves data from the discussion_board_attachments table,
 * returning the original filename, file type, file size, storage path, and
 * current status of the attachment. This endpoint is used by both citizens and
 * moderators to access file metadata for display and download purposes.
 * Security is enforced at the application level, ensuring that only active
 * attachments that are associated with visible posts can be retrieved.
 *
 * The attachment status field determines visibility: 'active' attachments are
 * accessible, while 'removed' attachments return a 404 error. This design
 * supports the business requirement that moderators can remove attachments,
 * replacing their links with '[Attachment removed by moderator]' without
 * permanently deleting the record from the database, preserving audit trails.
 * The retrieval is limited to a single attachment by ID, consistent with the
 * request for direct file access via unique identifier.
 *
 * @param props.connection
 * @param props.attachmentId Unique identifier of the target attachment. This
 *   UUID corresponds to the 'id' field in the discussion_board_attachments
 *   table, which is the primary key for attachment records (global scope).
 * @path /discussionBoard/attachmentFiles/:attachmentId
 * @accessor api.functional.discussionBoard.attachmentFiles.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
