import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardAppeal } from "../../../structures/IDiscussionBoardAppeal";
import { IPageIDiscussionBoardAppeal } from "../../../structures/IPageIDiscussionBoardAppeal";

/**
 * Retrieve a filtered, paginated list of appeals submitted by citizens for
 * content moderation decisions. This operation operates on the
 * discussion_board_appeals table from the database schema and provides advanced
 * search capabilities for identifying appeals based on multiple criteria
 * including appeal status, reporter type, appeal date ranges, and associated
 * content identifiers.
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * and sorting options. Appeals can sort by submission date, resolution date,
 * appeal priority, or status in ascending or descending order. This includes
 * filtering by appeal type (content removal, user suspension, account ban) and
 * associated content identifier.
 *
 * Security considerations include rate limiting for search operations and
 * appropriate filtering of sensitive appeal information based on the requesting
 * user's authorization level. Only administrators and moderators can access
 * detailed appeal information, while basic appeal summary may be available to
 * authenticated citizens.
 *
 * This operation integrates with the discussion_board_appeals table as defined
 * in the database schema, incorporating all available appeal fields and
 * relationships. The response includes appeal summary information optimized for
 * list displays, with options to include additional details based on
 * authorization level and appeal relevance.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for appeal
 *   filtering
 * @path /discussionBoard/appeals
 * @accessor api.functional.discussionBoard.appeals.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for appeal filtering */
    body: IDiscussionBoardAppeal.IRequest;
  };
  export type Body = IDiscussionBoardAppeal.IRequest;
  export type Response = IPageIDiscussionBoardAppeal.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/appeals",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/appeals";
  export const random = (): IPageIDiscussionBoardAppeal.ISummary =>
    typia.random<IPageIDiscussionBoardAppeal.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
