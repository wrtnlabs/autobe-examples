/**
 * Retrieve a filtered and paginated list of discussion board channels. This
 * operation operates on the discussion_board_channels table from the database
 * schema and provides advanced search capabilities for finding channels based
 * on multiple criteria including name, description, category, and active
 * status.
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * and sorting options. Channels can be sorted by name, creation date, or member
 * count in ascending or descending order. Search filters allow matching partial
 * names, descriptions, and category identifiers.
 *
 * Security considerations include rate limiting for search operations and
 * appropriate filtering of private channels based on user authentication.
 * Public channels are accessible to all users, while private channels require
 * appropriate permissions.
 *
 * This operation integrates with the discussion_board_channels table as defined
 * in the database schema, incorporating all available channel fields and
 * relationships. The response includes channel summary information optimized
 * for list displays, with options to include additional details based on
 * authorization level.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for channel
 *   filtering
 * @path /discussionBoard/channels
 * @accessor api.functional.discussionBoard.channels.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for channel filtering */
    body: IDiscussionBoardChannel.IRequest;
  };
  export type Body = IDiscussionBoardChannel.IRequest;
  export type Response = IPageIDiscussionBoardChannel.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/channels",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/channels";
  export const random = (): IPageIDiscussionBoardChannel.ISummary =>
    typia.random<IPageIDiscussionBoardChannel.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
