import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardCitizen } from "../../../../../structures/IDiscussionBoardCitizen";

/**
 * Register a new citizen account with email and password.
 *
 * This operation enables new users to create a citizen account on the
 * discussion board platform. The citizen is required to provide a
 * validation-ready email address and a secure password (minimum 8 characters).
 *
 * The email provided must be unique within the discussion_board_citizens table
 * - attempting to register with an existing email will return a 409 Conflict
 * error. The system performs format validation to ensure the email conforms to
 * standard email format patterns. The password is immediately hashed using a
 * secure algorithm and never stored in plain text.
 *
 * Upon successful registration, the system creates an entry in the
 * discussion_board_citizens table with email_verified set to false. The system
 * then generates and sends a verification email to the provided address. Until
 * email verification is completed, the citizen cannot perform any posting or
 * commenting actions.
 *
 * This operation does not create a session automatically. The citizen must log
 * in via the authentication endpoint after email verification to obtain a
 * session token. This two-step process enhances security by ensuring users have
 * access to their email before gaining full platform privileges.
 *
 * The operation is designed to comply with privacy regulations by storing only
 * necessary authentication data. No additional profile information is captured
 * at registration time, keeping the citizen account creation process simple and
 * focused.
 *
 * @param props.connection
 * @param props.body The registration payload containing the citizen's email
 *   address and password. The email must be unique and properly formatted. The
 *   password must be at least 8 characters long.
 * @path /discussionBoard/auth/citizen/join
 * @accessor api.functional.discussionBoard.auth.citizen.join.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * The registration payload containing the citizen's email address and
     * password. The email must be unique and properly formatted. The
     * password must be at least 8 characters long.
     */
    body: IDiscussionBoardCitizen.ICreate;
  };
  export type Body = IDiscussionBoardCitizen.ICreate;
  export type Response = IDiscussionBoardCitizen.IRegisterResponse;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/auth/citizen/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/auth/citizen/join";
  export const random = (): IDiscussionBoardCitizen.IRegisterResponse =>
    typia.random<IDiscussionBoardCitizen.IRegisterResponse>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
