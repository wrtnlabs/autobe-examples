import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardCitizenRefreshRequest } from "../../../../../structures/IDiscussionBoardCitizenRefreshRequest";
import { IDiscussionBoardCitizenRefreshResponse } from "../../../../../structures/IDiscussionBoardCitizenRefreshResponse";

/**
 * Refresh expired access token for citizen users.
 *
 * Refreshes an expired access token for a citizen user by validating a refresh
 * token stored securely on the client. When the access token expires (after 30
 * minutes), the client can submit a request to this endpoint containing the
 * refresh token in a secure cookie. The server retrieves the citizen ID
 * associated with this refresh token from the discussion_board_citizen_sessions
 * table, verifies the token's integrity, and ensures it has not been revoked or
 * expired.
 *
 * Upon successful validation, the system issues a new access token with a
 * freshly minted 30-minute expiration, and the same refresh token is returned
 * unchanged, preserving the original 7-day lifetime. This design prevents
 * unlimited token renewal cycles while maintaining a seamless user experience.
 *
 * The session record is not updated during refresh — the refresh token's
 * original created_at timestamp remains unchanged to allow suspension of
 * sessions after 7 days regardless of activity. If the refresh token is
 * missing, invalid, or expired, the system responds with HTTP 401 and directs
 * the user to log in again.
 *
 * This operation maintains stateless authentication by using cryptographically
 * signed tokens. It does not alter any database record except for potential
 * logging of refresh events, but no join or update to citizen sessions is
 * required. The endpoint supports only citizen users due to the actor-specific
 * session tables.
 *
 * This endpoint is designed exclusively for refresh operations, and the
 * countermeasures against token theft include token binding, IP address
 * verification, and usage tracking for suspicious activity.
 *
 * @param props.connection
 * @param props.body No request body required — refresh token conveyed via
 *   secure cookie
 * @path /discussionBoard/auth/citizen/refresh
 * @accessor api.functional.discussionBoard.auth.citizen.refresh.refreshToken
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function refreshToken(
  connection: IConnection,
  props: refreshToken.Props,
): Promise<refreshToken.Response> {
  return true === connection.simulate
    ? refreshToken.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...refreshToken.METADATA,
          path: refreshToken.path(),
          status: null,
        },
        props.body,
      );
}
export namespace refreshToken {
  export type Props = {
    /** No request body required — refresh token conveyed via secure cookie */
    body: IDiscussionBoardCitizenRefreshRequest;
  };
  export type Body = IDiscussionBoardCitizenRefreshRequest;
  export type Response = IDiscussionBoardCitizenRefreshResponse;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/auth/citizen/refresh",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/auth/citizen/refresh";
  export const random = (): IDiscussionBoardCitizenRefreshResponse =>
    typia.random<IDiscussionBoardCitizenRefreshResponse>();
  export const simulate = (
    connection: IConnection,
    props: refreshToken.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: refreshToken.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
