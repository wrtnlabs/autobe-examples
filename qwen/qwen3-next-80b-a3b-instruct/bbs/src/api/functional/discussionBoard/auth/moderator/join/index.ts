/**
 * Register a new moderator account.
 *
 * This endpoint enables moderator account registration through email and
 * password authentication. When a user submits registration data, the system
 * validates the email format and ensures the password meets security
 * requirements (at least 8 characters).
 *
 * The system creates a new record in the discussion_board_moderators table with
 * email_verified set to false, which prevents any moderation actions until the
 * user confirms their email address. This security measure ensures that
 * moderation privileges are only granted to verified individuals.
 *
 * The operation does NOT create a session immediately - session creation occurs
 * only after successful login with a verified account. The registration process
 * is designed for human users via web interface, not for automated systems or
 * client applications.
 *
 * The discussion_board_moderators table stores the moderator's email (uniquely
 * constrained) and password_hash, with no direct access to plain text
 * passwords. The creation_at and updated_at timestamps are automatically
 * populated, and deleted_at remains null unless the moderator account is later
 * soft-deleted.
 *
 * @param props.connection
 * @param props.body Registration data for creating a new moderator account
 *   including email and password
 * @path /discussionBoard/auth/moderator/join
 * @accessor api.functional.discussionBoard.auth.moderator.join.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
