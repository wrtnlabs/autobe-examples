import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardCitizenLoginRequest } from "../../../../../structures/IDiscussionBoardCitizenLoginRequest";
import { IDiscussionBoardCitizenLoginResponse } from "../../../../../structures/IDiscussionBoardCitizenLoginResponse";

/**
 * Authenticate citizen user and issue JWT access and refresh tokens.
 *
 * Authenticates a citizen user by validating their email and password. When a
 * citizen submits valid credentials, the system verifies the existence of the
 * email in the discussion_board_citizens table and checks that the
 * password_hash matches the provided password. If verification succeeds, the
 * system generates a JSON Web Token (JWT) containing the citizen's unique ID,
 * role as "citizen" (as per authorization actor requirements), and issue
 * timestamp (iat). The JWT is valid for 30 minutes. Additionally, a refresh
 * token is generated with a 7-day expiration, stored as a secure HTTP-only
 * cookie or client-side storage. The refresh token is used to obtain new access
 * tokens without requiring re-entry of credentials.
 *
 * Security considerations require that passwords are stored as bcrypt hashes
 * and that the system enforces rate limiting to prevent brute force attacks.
 * The endpoint must reject empty email or password fields, returning a
 * user-facing error message. Users with unverified email addresses
 * (email_verified = false) must be denied access with a message indicating
 * verification is required.
 *
 * This operation is the entry point for citizen users to gain access to
 * protected endpoints. The access token must be included in the Authorization
 * header as a Bearer token for subsequent requests. The refresh token mechanism
 * follows RFC 6749 standards for OAuth 2.0 refresh token grants.
 *
 * This operation does not create or modify any data in the database; it
 * performs only a read query on the discussion_board_citizens table to validate
 * credentials. Session state is managed entirely through tokens, not
 * server-side storage.
 *
 * @param props.connection
 * @param props.body Authentication credentials for citizen login
 * @path /discussionBoard/auth/citizen/login
 * @accessor api.functional.discussionBoard.auth.citizen.login.signIn
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function signIn(
  connection: IConnection,
  props: signIn.Props,
): Promise<signIn.Response> {
  return true === connection.simulate
    ? signIn.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...signIn.METADATA,
          path: signIn.path(),
          status: null,
        },
        props.body,
      );
}
export namespace signIn {
  export type Props = {
    /** Authentication credentials for citizen login */
    body: IDiscussionBoardCitizenLoginRequest;
  };
  export type Body = IDiscussionBoardCitizenLoginRequest;
  export type Response = IDiscussionBoardCitizenLoginResponse;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/auth/citizen/login",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/auth/citizen/login";
  export const random = (): IDiscussionBoardCitizenLoginResponse =>
    typia.random<IDiscussionBoardCitizenLoginResponse>();
  export const simulate = (
    connection: IConnection,
    props: signIn.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: signIn.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
