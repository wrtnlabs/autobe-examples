import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardModerator } from "../../../../../structures/IDiscussionBoardModerator";
import { IDiscussionBoardModeratorSession } from "../../../../../structures/IDiscussionBoardModeratorSession";

/**
 * Authenticate moderator and generate session token.
 *
 * This endpoint authenticates moderator users by validating their email and
 * password against the discussion_board_moderators table.
 *
 * The system first verifies that the provided email exists and is not
 * soft-deleted. It then checks if email_verified is true, as unverified
 * accounts cannot authenticate for security reasons. The password_hash is
 * verified using a cryptographic function to ensure authentication security.
 *
 * Upon successful authentication, the system generates a JWT access token
 * containing the moderator's ID and role ("moderator") with a 30-minute
 * expiration, and a refresh token with 7-day expiration stored securely on the
 * client. The session is recorded in the discussion_board_moderator_sessions
 * table with details including IP address, referrer, and href.
 *
 * If authentication fails due to incorrect credentials, the system returns an
 * error without disclosing whether the email or password was incorrect to
 * prevent account enumeration attacks. If the email is unverified, the system
 * returns a specific error requesting email verification.
 *
 * This endpoint does not create a moderator account - that requires the
 * /auth/moderator/join endpoint. This endpoint only authenticates existing,
 * verified moderator accounts for API session establishment.
 *
 * @param props.connection
 * @param props.body Login credentials containing email and password for
 *   moderator authentication
 * @path /discussionBoard/auth/moderator/login
 * @accessor api.functional.discussionBoard.auth.moderator.login.signIn
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function signIn(
  connection: IConnection,
  props: signIn.Props,
): Promise<signIn.Response> {
  return true === connection.simulate
    ? signIn.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...signIn.METADATA,
          path: signIn.path(),
          status: null,
        },
        props.body,
      );
}
export namespace signIn {
  export type Props = {
    /**
     * Login credentials containing email and password for moderator
     * authentication
     */
    body: IDiscussionBoardModerator.IRequest;
  };
  export type Body = IDiscussionBoardModerator.IRequest;
  export type Response = IDiscussionBoardModeratorSession;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/auth/moderator/login",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/auth/moderator/login";
  export const random = (): IDiscussionBoardModeratorSession =>
    typia.random<IDiscussionBoardModeratorSession>();
  export const simulate = (
    connection: IConnection,
    props: signIn.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: signIn.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
