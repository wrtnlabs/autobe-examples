/**
 * Retrieve statistical analytics for articles organized by discussion board
 * channels. This operation aggregates article counts, publishing trends, and
 * engagement metrics across all channels to provide administrators with
 * insights into content distribution and channel performance.
 *
 * The data is derived from the discussion_board_articles and
 * discussion_board_channels tables, joining on channel_id to group articles by
 * their respective channels. This operation does not return individual article
 * records but instead computes aggregated metrics such as total articles per
 * channel, average publication frequency, and recent activity trends.
 *
 * The analytics are updated dynamically based on real-time data and include
 * filters for publication status (published, pending, hidden) to give a
 * comprehensive view of content pipeline health. This endpoint serves as a
 * foundational dashboard metric for moderation teams and platform strategists.
 *
 * Implementation note: This operation does not map to a single database table.
 * Instead, it executes an SQL query performing a JOIN between
 * discussion_board_articles and discussion_board_channels, then grouping by
 * channel_id to compute aggregations:
 *
 * SELECT c.name as channel_name, COUNT(a.id) as article_count,
 * AVG(DATEDIFF(NOW(), a.created_at)) as avg_age_days, SUM(CASE WHEN a.status =
 * 'published' THEN 1 ELSE 0 END) as published_count, SUM(CASE WHEN a.status =
 * 'pending' THEN 1 ELSE 0 END) as pending_count FROM discussion_board_channels
 * c LEFT JOIN discussion_board_articles a ON c.id = a.channel_id GROUP BY c.id,
 * c.name ORDER BY article_count DESC
 *
 * This statistical aggregation serves the business need for channel performance
 * analytics.
 *
 * Related operations: GET /analytics/articles/summary (overall article
 * metrics), GET /analytics/users/engagement (user-level activity analytics).
 *
 * @param props.connection
 * @path /discussionBoard/analytics/articles/channels
 * @accessor api.functional.discussionBoard.analytics.articles.channels.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPageIDiscussionBoardChannelAnalytics;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/analytics/articles/channels",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/analytics/articles/channels";
  export const random = (): IPageIDiscussionBoardChannelAnalytics =>
    typia.random<IPageIDiscussionBoardChannelAnalytics>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
