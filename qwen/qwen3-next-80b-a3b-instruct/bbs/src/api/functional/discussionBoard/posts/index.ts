/**
 * Retrieve a specific article from the discussion board by its unique
 * identifier. This operation accesses the discussion_board_articles table and
 * returns the complete article content along with its metadata including title,
 * content, creation timestamp, and author information.
 *
 * The operation accepts a postId parameter that corresponds to the article's
 * unique identifier in the database. This endpoint serves as the primary
 * mechanism for users to view individual article content after discovering it
 * through search or category browsing.
 *
 * Security considerations include rate limiting to prevent abuse and ensuring
 * that only articles with active statuses (as defined in
 * discussion_board_article_statuses) are returned. The system filters out
 * articles with hidden, pending, or inactive status values that are managed
 * through the article_statuses table.
 *
 * The article returned includes all non-sensitive fields from the article, but
 * excludes any related data such as comments or attachments as those are
 * accessed through separate endpoints (GET /posts/{postId}/comments and GET
 * /posts/{postId}/files). This ensures optimal performance and prevents
 * unnecessary data transfer. Related operations include searching articles
 * (PATCH /posts) and retrieving article comments (GET
 * /posts/{postId}/comments).
 *
 * @param props.connection
 * @param props.postId Unique identifier of the target article from the
 *   discussion_board_articles table (global scope)
 * @path /discussionBoard/posts/:postId
 * @accessor api.functional.discussionBoard.posts.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target article from the
     * discussion_board_articles table (global scope)
     */
    postId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardArticle;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/posts/:postId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/posts/${encodeURIComponent(props.postId ?? "null")}`;
  export const random = (): IDiscussionBoardArticle =>
    typia.random<IDiscussionBoardArticle>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

