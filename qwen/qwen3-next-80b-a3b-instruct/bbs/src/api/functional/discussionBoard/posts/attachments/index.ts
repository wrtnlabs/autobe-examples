/**
 * Create a new attachment for a post.
 *
 * Allows authenticated users to upload one or more files as attachments to an
 * existing post. This operation creates a record in the
 * discussion_board_attachments table with metadata including filename,
 * filetype, filesize, and storage_path. The system validates that the file type
 * is among the allowed formats (jpeg, png, gif, pdf, txt, docx) and that
 * individual file size does not exceed 5 MB and total attachments per post do
 * not exceed 10 MB.
 *
 * The endpoint must be called with multipart/form-data format to handle file
 * uploads. Only the citizen who created the post can upload attachments
 * (verified through session and actor association). The storage_path is
 * generated automatically by the system upon successful upload and does not
 * include sensitive information or path traversal sequences.
 *
 * This operation does not support multiple file uploads in a single request;
 * clients must make separate requests for each file. Validation errors are
 * handled by providing clear user-facing messages about file type or size
 * violations. Successful creation returns the attachment metadata with its new
 * ID, stored filename, and server path.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the post to which the attachment is
 *   being added (from discussion_board_posts.id)
 * @param props.body File metadata and upload data for a new attachment.
 *   Content-type: multipart/form-data. Includes file data and fields: filename,
 *   filetype, filesize.
 * @path /discussionBoard/posts/:postId/attachments
 * @accessor api.functional.discussionBoard.posts.attachments.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Unique identifier of the post to which the attachment is being added
     * (from discussion_board_posts.id)
     */
    postId: string;

    /**
     * File metadata and upload data for a new attachment. Content-type:
     * multipart/form-data. Includes file data and fields: filename,
     * filetype, filesize.
     */
    body: IDiscussionBoardAttachment.ICreate;
  };
  export type Body = IDiscussionBoardAttachment.ICreate;
  export type Response = IDiscussionBoardAttachment;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/posts/:postId/attachments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/posts/${encodeURIComponent(props.postId ?? "null")}/attachments`;
  export const random = (): IDiscussionBoardAttachment =>
    typia.random<IDiscussionBoardAttachment>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

