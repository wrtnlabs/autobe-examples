/**
 * Create a new comment on a specific discussion board post. This operation
 * allows an authenticated user to add their input to an existing post by
 * providing textual content. The comment is associated with the post identified
 * by the postId path parameter and is attributed to the authenticated user's
 * session.
 *
 * The comment's content must be between 1 and 1,000 characters, as mandated by
 * business requirements. If the content is empty or exceeds 1,000 characters,
 * the system will reject the request and return an appropriate error message.
 * The system automatically sets the created_at and updated_at timestamps to the
 * current time and assigns the status as 'active'.
 *
 * Security considerations include ensuring the authenticated user has
 * permission to comment on the post. Only citizens with verified email
 * addresses and active accounts can create comments. The author_id and
 * author_type are derived from the authentication token, and the
 * discussion_board_post_id is validated against the postId path parameter to
 * ensure referential integrity with the discussion_board_posts table.
 *
 * This operation is part of the Comments domain and directly populates the
 * discussion_board_comments table. The related discussion_board_reports and
 * discussion_board_moderation_action_of_comments tables are populated only if
 * the comment is later reported or moderated.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the target discussion board post on
 *   which the comment will be created. This references the id field in the
 *   discussion_board_posts table and must be a valid UUID.
 * @param props.body The content of the new comment being created. Must be a
 *   string between 1 and 1,000 characters as required by business rules.
 * @path /discussionBoard/posts/:postId/comments
 * @accessor api.functional.discussionBoard.posts.comments.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
