import { tags } from "typia";

/**
 * Response DTO for updating an article's status. This object contains the
 * complete details of the status change operation performed by an admin
 * moderator.
 *
 * Used as the response body for the PUT /admin/articles/{articleId}/status
 * endpoint.
 *
 * The object provides comprehensive information about the status update,
 * including:
 *
 * - The unique ID of the status log entry
 * - The article affected by the change
 * - The new status assigned (published, hidden, or deleted)
 * - The exact time the change was applied
 * - The moderator responsible for the change
 *
 * This ensures complete auditability of all content moderation actions and
 * provides clients with immediate confirmation of the update's success.
 *
 * Note: All fields are required because every status update creates an
 * immutable audit log entry. None of these fields are optional as they form a
 * complete, self-contained record of the moderation action.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IArticleStatusUpdateResult = {
  /**
   * Unique identifier for the status update record.
   *
   * This UUID corresponds to the primary key in the
   * discussion_board_article_status_logs table, ensuring each status change
   * has a distinct, auditable record.
   *
   * Used to track the entire history of an article's status changes and
   * provides a reference for moderation audit trails.
   */
  id: string & tags.Format<"uuid">;

  /**
   * The unique identifier of the article whose status was updated.
   *
   * This UUID references the discussion_board_articles table and links this
   * status update to the specific article modified.
   *
   * This field is critical for associating moderation actions with content
   * and enables reporting and analytics on article status changes by
   * article.
   */
  articleId: string & tags.Format<"uuid">;

  /**
   * The article's new publication status after the update.
   *
   * This represents one of three allowed states from
   * discussion_board_article_statuses - published, hidden, or deleted.
   *
   * This change bypasses normal publication workflows and is an admin-only
   * privileged operation recorded in discussion_board_moderation_actions.
   */
  status: "published" | "hidden" | "deleted";

  /**
   * The precise timestamp when the status change was applied.
   *
   * This field records the exact time (ISO 8601 UTC format) when the admin's
   * update request was processed and the article's status was modified in the
   * database.
   *
   * Used for auditing purposes and to determine the sequence of status
   * changes for an article.
   *
   * This timestamp is automatically generated by the system server and
   * reflects UTC time, not client time.
   */
  changedAt: string & tags.Format<"date-time">;

  /**
   * The unique identifier of the moderator who initiated the status change.
   *
   * This UUID references the discussion_board_moderator table and identifies
   * which admin performed this moderation action.
   *
   * This field enables accountability and attribution, allowing audit trails
   * to link each status change to the specific moderator responsible.
   *
   * The value is extracted from the authenticated moderator's JWT token
   * during request processing, not provided by the client.
   */
  changedBy: string & tags.Format<"uuid">;
};
