import { tags } from "typia";

/**
 * Represents reaction metrics for a discussion board comment in the context of
 * a summarized view. Captures user engagement beyond basic upvotes/downvotes
 * using standardized emoji-type reactions.
 *
 * This schema defines a dictionary-like structure where each key represents a
 * specific reaction type (e.g., "like", "laugh", "support") and the value
 * represents the count of users who have applied that reaction to the comment.
 *
 * The reaction types are predefined by the system and should be consistent
 * across all comments. This enables consistent data analysis and UI rendering.
 * Reactions provide users with more nuanced ways to respond to content beyond a
 * simple binary upvote/downvote.
 *
 * Used in the IDiscussionBoardComment.ISummary to provide richer engagement
 * metrics without requiring additional API calls to fetch reaction details.
 *
 * Follows the pattern of a Record<string, number> where keys are reaction type
 * identifiers and values are integer counts.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ICommentReactions = {
  /**
   * Number of users who gave a 'like' reaction to this comment. This is the
   * most common reaction and represents general approval or appreciation.
   */
  like?: (number & tags.Type<"int32"> & tags.Minimum<0>) | undefined;

  /**
   * Number of users who gave a 'laugh' reaction to this comment. Used to
   * indicate humorous or ironic content that users found amusing.
   */
  laugh?: (number & tags.Type<"int32"> & tags.Minimum<0>) | undefined;

  /**
   * Number of users who gave a 'support' reaction to this comment. Indicates
   * agreement or encouragement, often used for comments expressing
   * perspective or advocacy.
   */
  support?: (number & tags.Type<"int32"> & tags.Minimum<0>) | undefined;

  /**
   * Number of users who gave a 'surprised' reaction to this comment.
   * Indicates unexpected, shocking, or noteworthy content that stood out to
   * users.
   */
  surprised?: (number & tags.Type<"int32"> & tags.Minimum<0>) | undefined;

  /**
   * Number of users who gave a 'care' reaction to this comment. Serves as an
   * emotional response indicating empathy, concern, or personal connection
   * with the comment's content.
   */
  care?: (number & tags.Type<"int32"> & tags.Minimum<0>) | undefined;
};
