import { tags } from "typia";

/**
 * Comprehensive moderation analytics dashboard with aggregated metrics and
 * trend indicators.
 *
 * This schema represents the data returned by the PATCH
 * /discussionBoard/moderator/moderation/analytics endpoint.
 *
 * The model combines information from the discussion_board_report_aggregations
 * and discussion_board_moderation_logs tables to provide a holistic view of
 * platform moderation performance.
 *
 * This dashboard serves administrators and platform managers, enabling
 * data-driven decisions about moderator scheduling, policy updates, and
 * community management strategies.
 *
 * All data is aggregated and anonymized to protect individual user identities
 * while providing actionable insights into platform health.
 *
 * Key components include:
 *
 * - Overall reporting volume and resolution rates
 * - Channel-specific report distributions
 * - Moderator activity patterns and performance metrics
 * - Historical trends for forecasting and planning
 * - Composite effectiveness scores for performance tracking
 *
 * The data is updated every 60 minutes and includes historical trends dating
 * back 90 days to support comprehensive analysis.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardModerationAnalytics = {
  /**
   * Total number of user reports submitted across all platform channels.
   *
   * Counts all reports including articles, comments, and other content types.
   *
   * Reports are filtered to exclude duplicates and resolved conflicts before
   * aggregation.
   *
   * This metric provides overall platform engagement with moderation systems.
   */
  totalReports: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Number of reported items that have been resolved by moderators.
   *
   * A report is considered resolved when a moderator has taken action
   * (dismiss, remove, warn, suspend, ban).
   *
   * The resolution rate (resolvedReports/totalReports) reflects moderator
   * effectiveness and system efficiency.
   *
   * Includes all resolved reports regardless of the action type taken.
   */
  resolvedReports: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Average time in hours between report submission and moderator action.
   *
   * Calculated as the mean of resolution times for all resolved reports over
   * the reporting period.
   *
   * Values exclude reports that are still pending resolution.
   *
   * Slow resolution times (above 24 hours) indicate potential moderator
   * overload or process bottlenecks.
   *
   * Time is measured from report creation timestamp to moderator action
   * timestamp.
   */
  averageResolutionTimeHours: number & tags.Minimum<0>;

  /**
   * Number of unique citizens who have submitted reports that resulted in
   * violations being confirmed.
   *
   * Counts users who have been reported repeatedly and whose content was
   * found to violate platform policies.
   *
   * Indicates the presence of habitual offenders who may require special
   * monitoring.
   *
   * Excludes users who submitted reports that were later determined to be
   * false or malicious.
   */
  recurrentViolatorsCount: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Percentage of reports that are currently in suspense (pending moderator
   * review).
   *
   * Calculated as: (pendingReports / totalReports) * 100
   *
   * Suspense rate reflects current moderator workload and response capacity.
   *
   * A high suspense rate (above 20%) indicates that the moderation queue is
   * growing faster than it can be processed.
   *
   * Target: maintain suspense rate below 10% for optimal platform management.
   */
  suspenseRate: number & tags.Minimum<0> & tags.Maximum<1>;

  /**
   * Percentage of reports that were determined to be false or without merit.
   *
   * Calculated as: (falseReports / totalReports) * 100
   *
   * A rising false report rate suggests potential abuse of the reporting
   * system or confusion about community guidelines.
   *
   * Target: maintain false report rate below 5% indicates healthy community
   * self-policing.
   *
   * High rates may indicate malicious reporting campaigns or a need for
   * better reporting guidance.
   */
  falseReportRate: number & tags.Minimum<0> & tags.Maximum<1>;

  /**
   * Composite score representing overall moderation effectiveness based on
   * multiple metrics.
   *
   * Calculated using a weighted formula: (resolvedReports / totalReports) *
   * 40 + (1 - falseReportRate) * 30 + (1 - suspenseRate) * 20 +
   * (recurrentViolatorsCount / totalReports) * 10
   *
   * Range: 0-100, where higher scores indicate more effective moderation.
   *
   * Provides a single metric for tracking moderation performance trends over
   * time.
   *
   * Scores below 60 indicate significant moderation challenges requiring
   * intervention.
   */
  resolutionEffectivenessScore: number & tags.Minimum<0> & tags.Maximum<100>;
};
