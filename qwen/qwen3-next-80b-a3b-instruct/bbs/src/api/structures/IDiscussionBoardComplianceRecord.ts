/**
 * Schema for a single compliance record generated when platform policies are
 * violated.
 *
 * Represents a comprehensive audit trail of violations and responses on the
 * discussion board platform. A compliance record is generated in response to
 * various triggers: user reports, moderator actions, automated system
 * detections, or user appeals.
 *
 * This schema integrates with multiple other systems:
 *
 * - Links to moderation actions via action_id
 * - References reported content through reported_content_id
 * - Connects to users via reporter_id and moderator_id
 * - Correlates with policy violations and trust score adjustments
 *
 * The record provides a complete history of the incident from detection through
 * resolution, ensuring accountability, transparency, and compliance with
 * regulatory requirements.
 *
 * Each compliance record is immutable - once created, its data cannot be
 * altered, ensuring its integrity as an audit trail.
 *
 * All compliance records are retained permanently for legal and regulatory
 * compliance purposes, even when the underlying content is removed.
 *
 * This schema is used in both request (IRequest) and response contexts, though
 * the IRequest variant only accepts properties relevant for filtering criteria,
 * while this object includes all properties for full audit visibility in
 * responses.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardComplianceRecord = {
  /**
   * Unique identifier for the compliance record in the database.
   *
   * This UUID is automatically generated by the system when a compliance
   * record is created. It serves as the primary key for identifying and
   * referencing compliance events across the platform's audit systems.
   *
   * This identifier is immutable and persists throughout the entire lifecycle
   * of the compliance record.
   *
   * Used in API endpoints like GET
   * /discussionBoard/moderator/audit/compliance-records/{recordId} to access
   * specific compliance records.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Categorizes the compliance record based on its origin.
   *
   * This discriminator determines how the record was created:
   *
   * - USER_REPORT: Generated when a citizen submits a report against content or
   *   another user
   * - MODERATOR_ACTION: Created when a moderator takes action (removal,
   *   warning, ban, etc.)
   * - SYSTEM_TRIGGER: Automated record generated by system rules (e.g., spam
   *   detection, rate limiting)
   * - APPEAL: Generated when a user appeals a moderation decision
   *
   * The record_type directly influences which related entities are linked to
   * this compliance record and determines the visibility and processing
   * workflow for the record.
   */
  record_type: IComplianceRecordType;

  /**
   * Reference to the moderation action that generated this compliance record.
   *
   * When the record_type is MODERATOR_ACTION, this field links to the
   * discussion_board_moderation_actions table entry that contains details
   * about the specific moderation action taken.
   *
   * For records created through other means (USER_REPORT, SYSTEM_TRIGGER,
   * APPEAL), this field may be null since no direct moderation action
   * generated the record.
   *
   * This linkage allows for comprehensive audit trails, enabling moderators
   * and administrators to trace compliance records back to the specific
   * actions taken by human moderators.
   */
  action_id?: (string & tags.Format<"uuid">) | undefined;

  /**
   * ID of the content that triggered the compliance record.
   *
   * This references the original entity that violated policy:
   *
   * - For articles: links to discussion_board_articles table
   * - For comments: links to discussion_board_comments table
   * - For reports: links to discussion_board_reports table
   * - For user accounts: links to discussion_board_citizen table
   *
   * The system uses this to identify the affected content, apply appropriate
   * moderation workflows, and potentially trigger content archival or removal
   * processes.
   *
   * This field is required for all compliance records except those created
   * solely as audit logs without specific target content.
   */
  reported_content_id?: (string & tags.Format<"uuid">) | undefined;

  /**
   * Identifier of the citizen who reported the violation or triggered this
   * record.
   *
   * This field references the discussion_board_citizen table and identifies
   * the user who submitted a report, triggered a system alert, or initiated
   * an appeal.
   *
   * For SYSTEM_TRIGGER records created automatically by the platform's
   * monitoring systems, this field is null.
   *
   * For MODERATOR_ACTION records, this field typically contains the
   * moderator's ID.
   *
   * This field enables analysis of reporting patterns, identification of
   * repeat reporters, and assessment of reported content's nature across the
   * platform.
   */
  reporter_id?: (string & tags.Format<"uuid">) | undefined;

  /**
   * Identifier of the moderator who performed the action related to this
   * compliance record.
   *
   * This field references the discussion_board_moderator table and identifies
   * the human moderator responsible for taking action on the reported
   * content.
   *
   * For USER_REPORT and SYSTEM_TRIGGER records, this field is null since no
   * moderator action has been taken yet.
   *
   * For APPEAL records, this field contains the moderator who reviewed and
   * resolved the appeal.
   *
   * This field supports accountability, performance metrics for moderators,
   * and analysis of moderation patterns across different moderators.
   */
  moderator_id?: (string & tags.Format<"uuid">) | undefined;

  /**
   * Current status of the compliance record in its lifecycle.
   *
   * Determines the stage of processing:
   *
   * - PENDING_REVIEW: New record awaiting moderator investigation
   * - RESOLVED: Moderation action completed and decision final
   * - APPEAL_PENDED: User has appealed the decision and it's under review
   * - APPEAL_REJECTED: Appeal was reviewed but the original decision was upheld
   * - APPEAL_GRANTED: Appeal was successful and the original decision was
   *   overturned
   *
   * The status determines the record's visibility and accessibility, with
   * only RESOLVED and APPEAL_REJECTED records being considered final.
   *
   * Status transitions are governed by the platform's moderation policy
   * workflow.
   */
  status?: IComplianceRecordStatus | undefined;

  /**
   * Categorization of the policy violation that triggered the compliance
   * record.
   *
   * This field references predefined violation categories in the system's
   * moderation policy:
   *
   * - HARASSMENT: Threats, hate speech, targeted abuse
   * - SPAM: Unwanted advertising, repetitive content
   * - INAPPROPRIATE_CONTENT: Nude, sexual, or violent material
   * - FALSE_INFORMATION: Misinformation, disinformation
   * - COPYRIGHT_INFRINGEMENT: Unauthorized use of protected material
   * - SECURITY_VIOLATION: Attempted system exploitation
   * - PRIVACY_VIOLATION: Doxxing, unauthorized personal data disclosure
   *
   * The category determines the severity level, appropriate moderation
   * response, and analytics categorization for the compliance record.
   */
  violation_category?: string | undefined;

  /**
   * More specific classification within the violation category.
   *
   * Provides granular detail about the nature of the violation:
   *
   * - For HARASSMENT: "threatening language", "targeted bullying",
   *   "identity-based abuse"
   * - For SPAM: "commercial advertising", "link spam", "copy-paste bot content"
   * - For FALSE_INFORMATION: "medical misinformation", "political
   *   disinformation", "financial fraud"
   * - For INAPPROPRIATE_CONTENT: "nudity", "violence", "bestiality"
   *
   * This subcategory allows for more precise reporting, statistical analysis,
   * and targeted policy updates based on exact violation patterns in the
   * community.
   */
  violation_subcategory?: string | undefined;

  /**
   * A numeric severity rating from 1 (lowest) to 5 (highest) indicating the
   * seriousness of the violation.
   *
   * This assessment is based on:
   *
   * - Content of the violation
   * - History of the reporting user
   * - History of the reported user
   * - Scale of impact (number of affected users)
   * - Platform policy thresholds
   *
   * Severity levels determine:
   *
   * - Response time requirements
   * - Escalation paths
   * - Final action consequences
   * - Analytics aggregation
   *
   * Level 1: Minor policy missteps with low potential harm Level 3: Clear
   * policy violations with moderate community impact Level 5: Severe
   * violations posing significant harm to individuals or platform integrity
   */
  severity_level?:
    | (number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>)
    | undefined;

  /**
   * The specific moderation action taken in response to this compliance
   * record.
   *
   * Determines the operational outcome of the moderation process:
   *
   * - NONE: No action taken after review
   * - WARNING: Issued a formal warning notice to the user
   * - CONTENT_REMOVAL: Deleted or hid the violating content
   * - ACCOUNT_SUSPENSION: Temporarily suspended the user's account
   * - ACCOUNT_BAN: Permanently banned the user from the platform
   * - TRUST_SCORE_ADJUSTMENT: Modified the user's platform trust score
   *
   * This field reflects the outcome of the moderation process and is critical
   * for user accountability, transparency, and analytics.
   */
  action_taken?: IComplianceRecordActionTaken | undefined;

  /**
   * Additional context and reasoning behind the moderation action taken.
   *
   * This field provides detailed documentation of:
   *
   * - Specific policy provisions violated
   * - Evidence reviewed
   * - Precedents considered
   * - Reasoning for severity level determination
   * - Mitigating circumstances considered
   *
   * This documentation supports transparency, appeal reviews, regulatory
   * compliance, and moderator training by capturing the rationale behind
   * every moderation decision.
   *
   * The field is mandatory for ACTION_TAKEN types that have consequences
   * (WARNING, CONTENT_REMOVAL, ACCOUNT_SUSPENSION, ACCOUNT_BAN).
   */
  action_details?: string | undefined;

  /**
   * Timestamp when the compliance record was created in the database.
   *
   * Records the exact moment the system generated this compliance event,
   * following ISO 8601 date-time format.
   *
   * This timestamp is critical for:
   *
   * - Establishing chronological order of events
   * - Time-based analytics and trend analysis
   * - Legal compliance and audit trail requirements
   * - Triggering automatic escalation workflows
   *
   * The timestamp is immutable and represents the system's authoritative
   * record of when the compliance event was logged.
   */
  timestamp: string & tags.Format<"date-time">;

  /**
   * The number of appeals filed against this compliance record.
   *
   * Counts all user-initiated appeals against the moderation decision
   * associated with this compliance record.
   *
   * This metric indicates:
   *
   * - Community disagreement with moderator decisions
   * - Potential for systemic issues in moderation policy
   * - Areas where policy clarification is needed
   *
   * The system allows a maximum of 10 appeals per record to prevent abuse and
   * maintain efficiency in the review process.
   */
  appeal_count?:
    | (number & tags.Type<"int32"> & tags.Minimum<0> & tags.Maximum<10>)
    | undefined;

  /**
   * Array of IDs of related reports that contributed to this compliance
   * record when aggregated.
   *
   * When this record was generated from the aggregation of multiple
   * individual reports:
   *
   * - Each report submitted independently
   * - System aggregated them based on similarity, context, and target
   * - This field contains the unique IDs of all contributing reports
   *
   * Used to:
   *
   * - Support transparency in decision-making
   * - Allow for investigation of report patterns
   * - Enable appeals that may relate to specific contributing reports
   *
   * The array may be empty if the record was generated by a single report or
   * system trigger.
   */
  related_report_ids?: (string & tags.Format<"uuid">)[] | undefined;

  /**
   * URL links to stored evidence supporting the compliance record.
   *
   * Contains direct links to:
   *
   * - Archived copies of the violating content
   * - Screenshots or text captures used in moderation decisions
   * - Server logs or system data that triggered automated reports
   * - User communication logs (if applicable and permitted)
   *
   * These links provide transparency and allow for independent verification
   * of moderation decisions. All evidence is stored in the system's secure,
   * immutable archive.
   */
  evidence_links?: (string & tags.Format<"uri">)[] | undefined;

  /**
   * The specific platform policy section that was violated.
   *
   * Identifies the exact clause in the community guidelines and moderation
   * policy that was breached:
   *
   * - Section 3.2: Prohibition of hate speech
   * - Section 5.1: Copyright infringement
   * - Section 7.4: Harassment of moderators
   * - Section 9.3: Privacy violations
   *
   * This provides clarity to users about why their actions were deemed
   * inappropriate and helps moderators apply consistent enforcement standards
   * across the platform.
   */
  policy_violated?: string | undefined;

  /**
   * Additional details about how this compliance record was resolved.
   *
   * Contains narrative notes from moderators about:
   *
   * - The final determination
   * - Consideration of context or mitigating factors
   * - Communication with the user
   * - Any special circumstances
   * - Follow-up actions beyond the immediate moderation
   *
   * These notes capture the human judgment elements of moderation that go
   * beyond automated decisions and provide rich context for appeals reviews
   * and policy refinement.
   */
  resolution_notes?: string | undefined;
};
