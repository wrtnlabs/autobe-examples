import { tags } from "typia";

import { IDiscussionBoardModerationLogDetails } from "./IDiscussionBoardModerationLogDetails";

/**
 * Moderation log entry representing a single action taken by a moderator on
 * content, users, or reports.
 *
 * An immutable audit record of moderation actions taken by moderators on
 * articles, comments, citizen accounts, reports, and system configurations.
 *
 * Each entry captures the complete context of the action including who
 * performed it, what was targeted, why it was done, and the technical
 * environment in which it occurred.
 *
 * These logs are automatically generated by the system as side effects of
 * moderator actions and cannot be created, modified, or deleted through any
 * API. They serve as the authoritative source of truth for all moderation
 * activities.
 *
 * Used to: Track moderator activity, investigate misconduct, handle user
 * appeals, comply with legal requirements, and provide transparency in content
 * governance.
 *
 * This schema represents the full details of a single moderation log entry in
 * the discussion board's compliance system. It must be treated as immutable
 * evidence in all contexts.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardModerationLogs = {
  /**
   * Unique identifier for the moderation log entry. Generated as a UUID v4
   * and serves as the primary key for the moderation log table in the
   * database.
   */
  id: string & tags.Format<"uuid">;

  /**
   * ID of the moderator who performed the action. References the
   * discussion_board_moderator table to identify the specific moderator
   * responsible for the action.
   */
  moderator_id: string & tags.Format<"uuid">;

  /**
   * Type of moderation action taken.
   *
   * Dismiss: The moderator concluded a report without taking corrective
   * action remove: The moderator removed content or suspended a user account
   * warn: The moderator issued a warning to a user for a policy violation
   *
   * These action types correspond directly to moderation decisions in the
   * system and are immutable once logged. They are case-sensitive and must
   * match exactly.
   */
  action_type: "dismiss" | "remove" | "warn";

  /**
   * ID of the content or user that was targeted by the moderation action.
   *
   * This field references the specific article, comment, citizen account, or
   * report that was acted upon. For content removals, this is the article or
   * comment ID. For user actions, this is the citizen's user ID.
   *
   * This field is nullable because certain moderation actions may be
   * system-wide configuration changes that don't target specific content or
   * users. When null, action_type indicates a system-level change.
   */
  target_content_id?: (string & tags.Format<"uuid">) | undefined;

  /**
   * Type of entity that was targeted by the moderation action.
   *
   * Article: Moderation action on an article comment: Moderation action on a
   * comment citizen: Moderation action on a user account report: Moderation
   * action on a user report configuration: Moderation action on system
   * configuration
   *
   * This field enables targeted queries and reporting by entity type and must
   * match the target_content_id reference. When target_content_id is null,
   * this field must also be null.
   */
  target_content_type?:
    | "article"
    | "comment"
    | "citizen"
    | "report"
    | "configuration"
    | undefined;

  /**
   * Detailed reason provided by the moderator for the moderation action.
   *
   * This field contains the moderator's written explanation for their
   * decision. It must be sufficiently detailed to justify the action taken
   * and serve as documentation for audits or appeals.
   *
   * The description should include specific policy violations observed,
   * contextual details about the content or behavior, and any relevant
   * history of activity for the targeted user or content. A minimum of 10
   * characters is recommended for meaningful context.
   */
  reason?: string | undefined;

  /**
   * Timestamp when the moderation action was performed and logged.
   *
   * This field records the exact time the moderation decision was executed
   * and recorded in the system. It is automatically set by the server at the
   * moment the action is processed and cannot be modified.
   *
   * All logs are stored in chronological order with the most recent entries
   * first for audit trail purposes. The timestamp must follow ISO 8601 format
   * with timezone information to ensure global consistency across regional
   * systems.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * IP address of the moderator when performing the action.
   *
   * This field captures the network location from which the moderator
   * initiated the action for security and forensic purposes.
   *
   * The IP address helps identify potential account compromise, geographic
   * patterns in moderation behavior, or connection anomalies. This value may
   * be null if the moderator acted through a proxy service or anonymized
   * network connection.
   */
  ip_address?: string | undefined;

  /**
   * User agent string from the moderator's client when performing the action.
   *
   * This field records information about the browser, device, and operating
   * system used by the moderator during the action.
   *
   * It provides additional context for investigations and helps detect
   * automated tools or unauthorized access patterns. This value may be null
   * if the moderator used a non-browser interface or the user agent was not
   * captured.
   */
  user_agent?: string | undefined;

  /**
   * Additional metadata about the moderation action.
   *
   * This object contains supplementary information that provides
   * comprehensive context for the action taken, including before/after states
   * of the target content and the original material that was acted upon.
   *
   * Phases of moderation decisions are fully documented here to ensure
   * complete audit capability. This includes the full text of moderated
   * content, prior version identifiers, and system state at time of action.
   */
  details?: IDiscussionBoardModerationLogDetails | undefined;
};
