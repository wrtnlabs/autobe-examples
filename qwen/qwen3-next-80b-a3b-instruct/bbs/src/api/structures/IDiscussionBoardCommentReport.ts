/**
 * Represents a user report on a comment in the discussion board system. This
 * entity captures the reason for reporting inappropriate content, the timestamp
 * of submission, and the status of moderation review. Used by both citizens to
 * report violations and moderators to review reported content.
 *
 * The report is a separate entity from the original comment to preserve comment
 * integrity and enable independent moderation workflows. Reports do not alter
 * the target comment directly but trigger automated and manual review
 * processes.
 *
 * Each report contains exactly one reason from a predefined list: "spam",
 * "hate_speech", "harassment", "inaccurate", or "other". Reports are anonymous
 * from the perspective of other users - the reporter's identity is stored for
 * moderation purposes but not exposed in response to non-moderator users.
 *
 * This schema is used for both creating new reports (with creation request) and
 * retrieving existing reports (in response). When used as response, all fields
 * are exposed. When used as request, only reason field is accepted from user
 * input; system generates id, comment_id, reporter_id, and created_at fields
 * automatically.
 *
 * Related operations: POST
 * /discussionBoard/citizen/comments/{commentId}/reports (create), GET
 * /discussionBoard/citizen/comments/{commentId}/reports/{reportId} (retrieve),
 * GET /discussionBoard/moderator/moderation/comments/flags (list all).
 *
 * X-autobe-database-schema": "discussion_board_comment_reports
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardCommentReport = {
  /**
   * Unique identifier for the report record. Generated by system upon
   * creation to ensure uniqueness and traceability.
   */
  id: string & tags.Format<"uuid">;

  /**
   * The unique identifier of the comment that was reported. This field links
   * the report to its target comment in the discussion_board_comments table.
   */
  commentId: string & tags.Format<"uuid">;

  /**
   * The unique identifier of the user who submitted this report. This is
   * automatically populated from the authenticated citizen's JWT token and is
   * not provided by the client. Used internally by moderators to assess
   * reporting patterns and prevent abuse.
   */
  reporterId: string & tags.Format<"uuid">;

  /**
   * The reason for the report, selected from predefined categories. Required
   * field that must be one of: "spam", "hate_speech", "harassment",
   * "inaccurate", or "other". This provides moderation context for evaluating
   * the report.
   */
  reason: "spam" | "hate_speech" | "harassment" | "inaccurate" | "other";

  /**
   * Timestamp when the report was submitted. Automatically populated by the
   * system when the report is created. Follows ISO 8601 format.
   */
  createdAt: string & tags.Format<"date-time">;

  /**
   * Current moderation status of the report. Default value is "pending" upon
   * creation. Possible values: "pending" (initial state), "reviewed"
   * (moderator has taken action), "dismissed" (reported content was
   * determined to be appropriate), "action_taken" (moderator removed content
   * or punished reporter). Used to track the progress of moderation
   * workflows.
   */
  status: "pending" | "reviewed" | "dismissed" | "action_taken";
};
