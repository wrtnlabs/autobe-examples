import { tags } from "typia";

/**
 * Session tracking table for moderator users. Each record represents one active
 * or expired authentication session for a moderator. Follows exact mandatory
 * schema for actor session tables with no additional fields. Managed
 * exclusively through the authentication system, not directly by users.
 *
 * @author AutoBE - https://github.com/wrtnlabs/autobe
 *
 *   This schema represents the session tracking record for authenticated
 *   moderators. The system creates a new session record when a moderator
 *   successfully authenticates via the /discussionBoard/auth/moderator/login
 *   endpoint, capturing essential connection metadata (IP address, referrer,
 *   href) and linking it to the assigned moderator through
 *   discussion_board_moderator_id.
 *
 *   The created_at field records the moment authentication was granted, while the
 *   expired_at field indicates when the session token expired (typically 30
 *   minutes after creation). When a moderator explicitly logs out or the system
 *   invalidates the session (for security reasons), the expired_at field is
 *   populated.
 *
 *   The updated_at field is automatically updated by the system whenever the
 *   session record is modified, such as during explicit logout, session
 *   restart, or administrative session termination. This provides a complete
 *   audit trail of changes to the session record.
 *
 *   The deleted_at field implements soft delete behavior for sessions that have
 *   been logically removed from the system (e.g., when a moderator account is
 *   disabled). This ensures audit compliance while preventing the session from
 *   being used for authentication.
 *
 *   This session data is crucial for security auditing, detecting suspicious
 *   activity patterns, and session-based rate limiting. The system logs and
 *   analyzes this data to identify potential security breaches, such as
 *   multiple sessions from different locations or sessions with suspicious
 *   header information.
 * @namespace Actors
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardModeratorSession = {
  /**
   * Primary Key.
   *
   * Unique identifier for the moderator session record.
   */
  id: string & tags.Format<"uuid">;

  /**
   * References the moderator user who owns this session.
   * {@link discussion_board_moderators.id}.
   */
  discussion_board_moderator_id: string & tags.Format<"uuid">;

  /** IP address from which the session was initiated. */
  ip: string;

  /** URL where the user accessed the system during this session. */
  href: string & tags.Format<"uri">;

  /**
   * Referrer URL indicating the source of this session (e.g., which page
   * linked to the login).
   */
  referrer: string & tags.Format<"uri">;

  /** Timestamp when this session was created. */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp when this session expired or was invalidated. Nullable since
   * active sessions have no expiration.
   */
  expired_at?: (string & tags.Format<"date-time">) | undefined;
};
