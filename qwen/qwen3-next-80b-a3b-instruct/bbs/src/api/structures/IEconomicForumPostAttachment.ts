import { tags } from "typia";

export namespace IEconomicForumPostAttachment {
  /**
   * Summary information for forum post attachments, providing essential
   * metadata for displaying attachment listings without full file details.
   * Each entry represents a single file attachment linked to a forum post,
   * containing the file name, size, upload timestamp, and downloadable URL.
   * Designed for use in paginated responses to reduce payload size while
   * providing sufficient information for users to identify and access files.
   */
  export type ISummary = {
    /**
     * Unique identifier for the attachment file.
     *
     * @x-autobe-database-schema-property id
     * @x-autobe-specification Direct mapping from economic_forum_attachment_files.id column. UUID primary key uniquely identifying each attachment.
     */
    id: string & tags.Format<"uuid">;

    /**
     * The original name of the uploaded file as provided by the user.
     *
     * @x-autobe-specification Computed from external file storage metadata service. The original filename is retrieved from the file storage system using the attachment's id as the key, then sanitized to remove path components and special characters before display.
     */
    file_name: string;

    /**
     * Size of the attachment file in bytes.
     *
     * @x-autobe-specification Computed from file storage system metadata. The file size in bytes is retrieved directly from the object store using the attachment's id as the key. This value is cached upon upload and updated upon any file modification.
     */
    file_size: number & tags.Type<"int32">;

    /**
     * Date and time when the file was uploaded to the system, in ISO 8601
     * format.
     *
     * @x-autobe-specification Computed from system audit events. The creation timestamp is retrieved from the system audit logs where 'operation' = 'file_upload' and 'entity_id' matches the attachment's id. Falls back to system time if audit log not found.
     */
    created_at: string & tags.Format<"date-time">;

    /**
     * Complete URL path to access and download the attachment file.
     *
     * @x-autobe-specification Computed from cloud storage service. The absolute URL for downloading the file is generated by the cloud storage service using the attachment's id and the configured storage bucket. The URL includes authentication tokens for secure access, created in real-time based on user permissions.
     */
    file_url: string & tags.Format<"uri">;
  };
}
