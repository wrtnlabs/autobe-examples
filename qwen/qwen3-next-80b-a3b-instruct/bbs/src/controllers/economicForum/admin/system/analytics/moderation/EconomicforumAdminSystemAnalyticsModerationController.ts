import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchEconomicForumAdminSystemAnalyticsModeration } from "../../../../../../providers/patchEconomicForumAdminSystemAnalyticsModeration";
