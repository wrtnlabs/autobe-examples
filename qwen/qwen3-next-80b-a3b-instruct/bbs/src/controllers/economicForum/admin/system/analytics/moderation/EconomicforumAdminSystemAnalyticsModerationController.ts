@Controller("/economicForum/admin/system/analytics/moderation")
export class EconomicforumAdminSystemAnalyticsModerationController {
  /**
   * Retrieve aggregated moderation analytics data for system administrators to
   * monitor content moderation effectiveness and workload distribution.
   *
   * This operation queries the economic_forum_post_reports and
   * economic_forum_moderation_flags tables to provide a comprehensive summary
   * of all moderation activities. It returns counts of reported posts, approved
   * posts, deleted posts, and the top reasons for moderation reports. This
   * endpoint serves the administrative need to review moderation patterns and
   * identify potential issues or trends in user behavior.
   *
   * The data is derived from the economic_forum_post_reports table, which
   * records each user report on a post with a reason and timestamp, and the
   * economic_forum_moderation_flags table, which logs all administrative
   * actions taken on reported posts, including the action type
   * (approve/delete), the admin who took action, and timestamp.
   *
   * Security: This operation is only accessible to users with admin privileges.
   * Non-administrative users attempting to access this endpoint will receive a
   * 403 Forbidden response. The operation does not return any personally
   * identifiable information or sensitive user data. Only aggregated statistics
   * are provided to protect user privacy.
   *
   * This operation should be called regularly by administrative dashboards to
   * display current moderation metrics. It may be combined with other analytics
   * endpoints for a complete system overview. Change requests to moderation
   * workflow should be reviewed against these analytics to ensure policy
   * effectiveness.
   *
   * @param connection
   * @param body Filtering parameters for moderation analytics data retrieval
   * @x-autobe-specification Join economic_forum_post_reports with economic_forum_moderation_flags on report_id to correlate reports with actions. Aggregate counts by action_type (approve, delete) and report_reason. Group by 24-hour time buckets if date_range provided. Calculate total reports, total approved, total deleted, and top 5 most common report reasons with count. Apply pagination and sorting parameters from request body. Cache results for 15 minutes based on request parameters to reduce database load. Return response with pagination metadata and data array.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEconomicForumModerationFlag,
  ): Promise<IEconomicForumSystemAudit> {
    try {
      return await patchEconomicForumAdminSystemAnalyticsModeration({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
