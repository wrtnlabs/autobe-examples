import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getEconomicForumAdminAuthAdminsEmailVerificationsToken } from "../../../../../../../providers/getEconomicForumAdminAuthAdminsEmailVerificationsToken";
import { AdminAuth } from "../../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../../decorators/payload/AdminPayload";
import { deleteEconomicForumAdminAuthAdminsEmailVerificationsToken } from "../../../../../../../providers/deleteEconomicForumAdminAuthAdminsEmailVerificationsToken";
import { postEconomicForumAdminAuthAdminsEmailVerifications } from "../../../../../../../providers/postEconomicForumAdminAuthAdminsEmailVerifications";

