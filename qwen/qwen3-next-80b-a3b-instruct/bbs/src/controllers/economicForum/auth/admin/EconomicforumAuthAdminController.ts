import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postEconomicForumAuthAdminJoin } from "../../../../providers/postEconomicForumAuthAdminJoin";
import { postEconomicForumAuthAdminLogin } from "../../../../providers/postEconomicForumAuthAdminLogin";
import { postEconomicForumAuthAdminRefresh } from "../../../../providers/postEconomicForumAuthAdminRefresh";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

import { IEconomicForumAdmin } from "../../../../api/structures/IEconomicForumAdmin";

@Controller("/economicForum/auth/admin")
export class EconomicforumAuthAdminController {
  /**
   * Register a new system administrator account. This operation creates an
   * admin record in the economic_forum_admins table with initial fields: email,
   * password_hash, and created_at. The email_verified_at field is set to null
   * initially, requiring email verification before full access. The
   * password_reset_token field is initialized as null. The operation requires a
   * request body with email and password fields as defined in IAdmin.IJoin
   * schema.
   *
   * Upon success, returns a token with access and refresh tokens in
   * IAdmin.IAuthorized format, establishing initial admin authentication
   * session. The last_login_at field remains null until first successful
   * login.
   *
   * This operation is publicly accessible but requires valid email format and
   * password strength as enforced by application logic. The database triggers
   * ensure email uniqueness and password hashing.
   *
   * This operation is mandatory for all new admin accounts and must be called
   * before any other admin operations except login and refresh.
   *
   * Followed by: After successful join, the admin must verify their email by
   * calling /auth/admin/email/verify before accessing sensitive administrative
   * functions.
   *
   * @param connection
   * @param body Data required to register a new admin account.
   * @setHeader token.access Authorization
   *
   * @x-autobe-specification Creates a new admin record with email and encrypted password. Sends email verification token to provided email. Hashes password using bcrypt. Sets created_at to current timestamp. Initializes email_verified_at and last_login_at as null. password_reset_token remains null. Returns access and refresh tokens. Validates email format and password strength before creation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEconomicForumAdmin.IJoin,
  ): Promise<IEconomicForumAdmin.IAuthorized> {
    try {
      return await postEconomicForumAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing admin user with email and password. This operation
   * validates credentials against the economic_forum_admins table, checking
   * email existence and password_hash match. The email_verified_at field must
   * not be null for successful login - the admin must have completed email
   * verification.
   *
   * Upon successful authentication, generates a new session with access and
   * refresh tokens stored in economic_forum_admin_sessions table, and updates
   * last_login_at to the current timestamp. Returns the access token, refresh
   * token, and admin profile in IAdmin.IAuthorized format.
   *
   * The operation fails if: email doesn't exist, password is incorrect,
   * email_verified_at is null, or admin account is inactive. Password reset
   * tokens are ignored during login.
   *
   * This operation is essential for re-authentication after token expiration
   * and must be performed after join or refresh operations.
   *
   * Followed by: After login, the admin can perform restricted administrative
   * actions. The token must be refreshed periodically using
   * /auth/admin/refresh.
   *
   * @param connection
   * @param body Credentials for authenticating an admin user.
   * @setHeader token.access Authorization
   *
   * @x-autobe-specification Verifies email existence, checks password_hash against provided password, validates email_verified_at is not null, creates new session record in economic_forum_admin_sessions with 24-hour expiration, updates last_login_at, and returns authenticated token payload. Uses bcrypt for password verification.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEconomicForumAdmin.ILogin,
  ): Promise<IEconomicForumAdmin.IAuthorized> {
    try {
      return await postEconomicForumAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Extend access to the admin system by refreshing the access token using a
   * valid refresh token. This operation validates the refresh token against the
   * economic_forum_admin_sessions table, checks expiration, and ensures the
   * associated admin account is still active.
   *
   * Upon successful validation, generates a new access token (with 24-hour
   * expiration) while retaining the same refresh token (which renews every
   * 24-hour session). Returns updated access token and refresh token in
   * IAdmin.IAuthorized format.
   *
   * Refresh token can be reused until expiration (24 hours). After expiration,
   * the admin must log in again with credentials. The operation fails if
   * refresh token is invalid, expired, revoked, or associated admin is
   * inactive.
   *
   * This operation enables uninterrupted access without requiring re-entry of
   * login credentials and improves security by keeping access tokens
   * short-lived.
   *
   * Followed by: After refresh, the new access token must be used for
   * subsequent administrative API calls. The refresh token's expiration remains
   * unchanged.
   *
   * @param connection
   * @param body Refresh token to extend admin session.
   * @setHeader token.access Authorization
   *
   * @x-autobe-specification Validates refresh token against economic_forum_admin_sessions table, checks expiration (max 24h), retrieves associated admin ID, creates new access token, returns new access token with same refresh token, updates session's refreshed_at timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEconomicForumAdmin.IRefresh,
  ): Promise<IEconomicForumAdmin.IAuthorized> {
    try {
      return await postEconomicForumAuthAdminRefresh({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
