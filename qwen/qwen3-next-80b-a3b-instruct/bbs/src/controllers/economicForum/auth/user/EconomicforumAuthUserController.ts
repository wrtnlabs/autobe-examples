import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postEconomicForumAuthUserLogin } from "../../../../providers/postEconomicForumAuthUserLogin";
import { postEconomicForumAuthUserJoin } from "../../../../providers/postEconomicForumAuthUserJoin";
import { postEconomicForumAuthUserRefresh } from "../../../../providers/postEconomicForumAuthUserRefresh";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";

import { IEconomicForumUser } from "../../../../api/structures/IEconomicForumUser";

@Controller("/economicForum/auth/user")
export class EconomicforumAuthUserController {
  /**
   * The login operation authenticates a registered user by verifying their
   * email and password_hash against stored credentials in the
   * economic_forum_users table. This operation is公开 (public) and available for
   * all users, regardless of email verification status, as per the system
   * design.
   *
   * Authentication uses the password_hash field for secure storage and
   * comparison with bcrypt or similar hashing algorithm. A new session record
   * is created in economic_forum_user_sessions, populated with a freshly
   * generated JWT access token and refresh token, both set to expire in
   * accordance with system-wide configuration. The access token is short-lived
   * (e.g., 15 minutes) and the refresh token longer-lived (e.g., 7 days).
   *
   * The email_verified_at field is not used to block login, permitting users to
   * log in even before email verification. Verification status may affect
   * feature access (e.g., file uploads) but not authentication itself.
   *
   * This operation is the primary entry point for authenticated user sessions.
   * It must be called before any other protected endpoint. Security
   * considerations include rate limiting to prevent brute-force attacks and
   * secure storage of refresh tokens in HTTP-only cookies.
   *
   * This operation should be preceded by a display of login UI asking for email
   * and password. It is followed by user session management during application
   * use. Related operations: join (registration), refresh (token renewal), and
   * password_reset (account recovery).
   *
   * @param connection
   * @param body Credentials for authenticating a user account.
   * @setHeader token.access Authorization
   *
   * @x-autobe-specification Validate email and password credentials from request body. Grant access token and refresh token upon successful authentication. Set session record in economic_forum_user_sessions table with access_token, refresh_token, and expiration. Log authentication attempt in economic_forum_system_audits if enabled.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEconomicForumUser.ILogin,
  ): Promise<IEconomicForumUser.IAuthorized> {
    try {
      return await postEconomicForumAuthUserLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * The join operation registers a new user by collecting a valid email address
   * and password via the frontend UI. After validation, the password is
   * securely hashed using bcrypt with a cost factor of 12, and the resulting
   * password_hash is stored in the economic_forum_users table.
   *
   * A unique email verification token is generated (UUIDv4) and inserted into
   * the economic_forum_user_email_verifications table with an expiration of 24
   * hours from creation. The user's email_verified_at field remains null until
   * the verification process completes. The user is immediately granted a
   * temporary guest session until verification.
   *
   * Email verification has been configured as a mandatory step for enabling
   * additional features like file uploads, but the user can still log in before
   * verification. This balances security with usability.
   *
   * This is the first step in the user lifecycle and is publicly accessible.
   * After successful registration, the system sends an automated email with a
   * link containing the verification token. If no email is received, the user
   * may request a new verification via a separate endpoint.
   *
   * Related operations: login (after verification), email_verification (to
   * confirm identity), and password_reset (for recovery).
   *
   * @param connection
   * @param body New user registration details required to create an account.
   * @setHeader token.access Authorization
   *
   * @x-autobe-specification Create new user account with provided email and password. Hash password using bcrypt or similar. Emit email verification token and insert into economic_forum_user_email_verifications with 24-hour expiration. Store user record in economic_forum_users with email_verified_at set to null. Send email verification email via configured SMTP provider or third-party service.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEconomicForumUser.IJoin,
  ): Promise<IEconomicForumUser.IAuthorized> {
    try {
      return await postEconomicForumAuthUserJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * The refresh operation allows a user to obtain a new short-lived access
   * token using a valid, unexpired refresh token present in their HTTP-only
   * cookie storage. This operation extends user sessions without requiring
   * re-authentication.
   *
   * The refresh token must be provided either in a header (Authorization:
   * Bearer) or a secure HTTP-only cookie. This token is validated against
   * entries in the economic_forum_user_sessions table, checking its existence,
   * expiration, and revocation status. If the refresh token has been revoked,
   * used multiple times, expired, or is invalid, the system responds with a 401
   * Unauthorized and mandates re-login.
   *
   * Upon successful validation, a new access token and refresh token are
   * generated; the old refresh token is marked as revoked in the database to
   * prevent replay attacks. The new tokens are returned in the response body
   * and concurrently stored in new HTTP-only cookies. This pattern enforces
   * rolling refresh tokens for enhanced security.
   *
   * This operation is crucial for maintaining seamless user experience during
   * extended usage of the application. It is protected against CSRF and
   * stolen-token attacks through the secured cookie mechanism. This operation
   * is accessed only after successful login or join, and must not depend on any
   * prerequisite for authentication state.
   *
   * Related operations: login (initial authentication), join (first-time
   * registration), and logout (explicit session termination).
   *
   * @param connection
   * @param body Refresh token for renewing the access token.
   * @setHeader token.access Authorization
   *
   * @x-autobe-specification Validate refresh token from request header. Check if refresh token exists in economic_forum_user_sessions and is not expired. Generate new access token and refresh token. Update session record with new tokens and expiration time. Return updated tokens. Revoke compromised refresh tokens on failure.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IEconomicForumUser.IRefresh,
  ): Promise<IEconomicForumUser.IAuthorized> {
    try {
      return await postEconomicForumAuthUserRefresh({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
