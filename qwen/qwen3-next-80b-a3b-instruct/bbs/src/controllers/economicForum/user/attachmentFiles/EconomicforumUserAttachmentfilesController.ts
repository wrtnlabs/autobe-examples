import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postEconomicForumUserAttachmentFiles } from "../../../../providers/postEconomicForumUserAttachmentFiles";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { deleteEconomicForumUserAttachmentFilesAttachmentFileId } from "../../../../providers/deleteEconomicForumUserAttachmentFilesAttachmentFileId";

import { IEconomicForumAttachmentFile } from "../../../../api/structures/IEconomicForumAttachmentFile";

@Controller("/economicForum/user/attachmentFiles")
export class EconomicforumUserAttachmentfilesController {
  /**
   * Upload a file attachment to a forum post.
   *
   * This operation allows authenticated users to upload files (images,
   * documents, etc.) as attachments to forum posts. The system enforces file
   * type and size restrictions based on the configured limits in the
   * economic_forum_upload_limits table. File metadata is stored in the
   * economic_forum_attachment_files table, which contains fields: file_name,
   * file_path, file_size, mime_type, uploaded_by, uploaded_at, and post_id.
   *
   * The user's identity is automatically extracted from the JWT authentication
   * token, and the uploaded_by field is populated with the authenticated user's
   * ID. The file_name and file_path fields are generated by the system using a
   * secure naming scheme. The file_size and mime_type fields are automatically
   * extracted from the uploaded file data.
   *
   * All file uploads are validated against allowed file extensions and maximum
   * file size. Files are uploaded with exclusive access to prevent conflicts
   * and are permanently stored with immutable paths.
   *
   * Related operations: GET /economic_forum/user/attachmentFiles (list
   * attachments for a post), DELETE
   * /economic_forum/user/attachmentFiles/{fileId} (remove an attachment).
   *
   * @param connection
   * @param body File upload information including the file data as a
   *   base64-encoded string and associated post ID.
   * @x-autobe-specification Receive file upload as base64-encoded string in request body. Validate file extension against allowed types in upload_limits. Verify user has appropriate permissions to upload to target post. Generate secure UUID-based file name. Create physical file in secure storage path. Extract file metadata (size, mime type). Insert record into economic_forum_attachment_files table with: file_name, file_path, file_size, mime_type, uploaded_by (from JWT), uploaded_at (current timestamp), and post_id from request. Return newly created attachment file metadata with full path and file details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IEconomicForumAttachmentFile.ICreate,
  ): Promise<IEconomicForumAttachmentFile> {
    try {
      return await postEconomicForumUserAttachmentFiles({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanent deletion of a specific attachment file from the system.
   *
   * This operation removes an attachment file record from the
   * economic_forum_attachment_files table. When called, the system performs a
   * hard delete that completely removes both the database record and the
   * associated physical file from the storage system.
   *
   * Security: Only the owner of the file or an admin user can perform this
   * deletion. The system validates that the requesting user has appropriate
   * permissions by checking that the user_id field in the attachment record
   * matches the authenticated user's ID, or that the requester has admin
   * privileges. Attachments associated with posts are protected from deletion
   * by regular users if they are not the original uploader as specified by the
   * user_id relationship in the database schema.
   *
   * Implementation: The operation triggers a cascade delete process. First, the
   * physical file is removed from the storage system (file system or object
   * storage), then the corresponding database record is deleted from the
   * economic_forum_attachment_files table. This entire process occurs within a
   * single transaction to ensure data consistency and prevent orphaned files.
   *
   * This operation does not support soft deletion - once deleted, the file
   * cannot be recovered. There is no 'deleted_at' column in the table
   * structure, confirming this is a hard delete operation. Users are warned
   * before deletion since this action is irreversible.
   *
   * Related operations: Users can view attachments via GET
   * /posts/{postId}/attachments and upload new files via POST
   * /posts/{postId}/attachments.
   *
   * @param connection
   * @param attachmentFileId Unique identifier of the attachment file to delete.
   * @x-autobe-specification Perform hard delete of attachment file from storage and database in a transaction. First, retrieve the file record by attachmentFileId. Then, delete the physical file from storage using the stored file path. Finally, delete the database record from economic_forum_attachment_files table. The entire operation must be wrapped in a database transaction to ensure consistency. If either step fails, the entire transaction is rolled back to prevent orphaned files or inconsistent state.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":attachmentFileId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("attachmentFileId")
    attachmentFileId: string,
  ): Promise<void> {
    try {
      return await deleteEconomicForumUserAttachmentFilesAttachmentFileId({
        user,
        attachmentFileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
