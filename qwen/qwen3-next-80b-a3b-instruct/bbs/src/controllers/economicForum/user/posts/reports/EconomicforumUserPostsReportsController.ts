import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postEconomicForumUserPostsPostIdReports } from "../../../../../providers/postEconomicForumUserPostsPostIdReports";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { IEconomicForumPostReport } from "../../../../../api/structures/IEconomicForumPostReport";

@Controller("/economicForum/user/posts/:postId/reports")
export class EconomicforumUserPostsReportsController {
  /**
   * Create a report on a specific post to initiate the content moderation
   * workflow.
   *
   * This operation allows authenticated users to report posts that violate
   * community guidelines, contain spam, or are otherwise inappropriate. Each
   * report is tied to a specific post identified by postId in the URL path and
   * includes a reason for reporting chosen from predefined categories. Users
   * may optionally add a comment providing additional context for moderators.
   *
   * The report is stored in the economic_forum_post_reports table, with the
   * reporter's identity automatically derived from the authenticated user's JWT
   * token. This ensures accountability and prevents anonymous reporting abuse.
   * Upon report creation, the post's moderation status may be elevated for
   * review depending on system thresholds.
   *
   * This is a user-initiated action, not automated system behavior. Reports
   * trigger moderation workflows and may lead to post removal, user warnings,
   * or account suspension based on accumulated reports. This functionality is
   * essential for maintaining community standards on the economic forum.
   * Related operations include GET /posts/{postId} for viewing the reported
   * post and PATCH /posts/reports for moderators to view and manage reports.
   *
   * @param connection
   * @param postId Unique identifier of the post being reported
   * @param body Details of the report being created, including reason for
   *   reporting and optional additional comment.
   * @x-autobe-specification Create a new post report by inserting into economic_forum_post_reports table. Extract reporterId from JWT authentication token. Map provided reason and optional comment from request body to fields. Validate that reported postId exists in economic_forum_posts table. Set created_at to current timestamp. Return created report object with all fields including auto-generated id.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicForumPostReport.ICreate,
  ): Promise<IEconomicForumPostReport> {
    try {
      return await postEconomicForumUserPostsPostIdReports({
        user,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
