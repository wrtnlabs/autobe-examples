import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postEconomicForumUserPosts } from "../../../../providers/postEconomicForumUserPosts";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { putEconomicForumUserPostsPostId } from "../../../../providers/putEconomicForumUserPostsPostId";
import { deleteEconomicForumUserPostsPostId } from "../../../../providers/deleteEconomicForumUserPostsPostId";

import { IEconomicForumPost } from "../../../../api/structures/IEconomicForumPost";

@Controller("/economicForum/user/posts")
export class EconomicforumUserPostsController {
  /**
   * Create a new discussion post in the economic forum.
   *
   * This operation allows authenticated users to submit new discussion topics
   * by providing a title and detailed content. The post is immediately
   * published and visible to all forum members. Each post must have a
   * meaningful title and substantive content that contributes to the community
   * discussion. Attachments such as images, documents, or files can be included
   * by referencing their file IDs from uploaded attachments.
   *
   * Security: Only authenticated users can create posts. The user_id is
   * automatically populated from the JWT authentication token. The system
   * validates that attachment IDs referenced in the request actually exist and
   * belong to the requesting user.
   *
   * The created post will appear in the primary feed and can be discovered
   * through search functionality. The post status is automatically set to
   * 'active' upon creation. Related operations: GET /posts for list retrieval,
   * GET /posts/{postId} for detailed view, PATCH /posts/{postId} for updates,
   * DELETE /posts/{postId} for post removal.
   *
   * @param connection
   * @param body Creation data for a new economic forum post including title,
   *   content, and optional file attachments.
   * @x-autobe-specification Insert new record into economic_forum_posts table with title, content, and status='active'. Generate and assign unique UUID id. Set created_at and updated_at to current timestamp. For each attachment in the attachments array, create corresponding entries in economic_forum_post_attachments junction table with the post_id reference. Return the complete created post object with all fields including generated id, created_at, updated_at, and attachments.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IEconomicForumPost.ICreate,
  ): Promise<IEconomicForumPost> {
    try {
      return await postEconomicForumUserPosts({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing forum post with new content, title, status, or category
   * information.
   *
   * This operation allows users to modify their own forum posts or
   * administrators to edit any post in the system. The update requires a
   * complete replacement of the post data - all fields must be provided in the
   * request body. The operation updates the title, content, status, and
   * category fields, and automatically sets the updated_at timestamp to the
   * current time.
   *
   * Security and authorization are enforced at the service layer: regular users
   * can only update posts they created (matching their user_id with the post's
   * user_id), while admin users can update any post regardless of ownership.
   * The status field must be one of the allowed values: 'draft', 'published',
   * or 'archived'. If a category_id is provided, the system validates that
   * category exists in the categories table before applying the update.
   *
   * This operation performs a hard update, replacing the entire post resource.
   * System-generated fields such as id, user_id, created_at, and view_count are
   * preserved unchanged and cannot be modified via this endpoint.
   *
   * Related operations: Retrieve post details (GET /posts/{postId}), List posts
   * (GET /posts), and Delete post (DELETE /posts/{postId}).
   *
   * @param connection
   * @param postId Unique identifier of the target post to be updated (UUID
   *   format). This parameter corresponds to the id field in the
   *   economic_forum_posts database table.
   * @param body Complete update object containing all fields for post
   *   modification. This operation follows PUT semantics requiring full
   *   replacement of the resource state.
   * @x-autobe-specification Update an existing forum post. Query economic_forum_posts table by postId (id field). Validate that either: 1) The requesting user is the post's user_id (for non-admins), OR 2) The requesting user has admin privileges (for any post). Update fields: title, content, status, category_id. Set updated_at to current timestamp. Return the updated post object. Validate that status is one of allowed enum values ('draft', 'published', 'archived'). If category_id provided, verify it exists in economic_forum_categories table. Use transaction to ensure consistency. Return updated post object with all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":postId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicForumPost.IUpdate,
  ): Promise<IEconomicForumPost> {
    try {
      return await putEconomicForumUserPostsPostId({
        user,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a discussion post from the forum. This operation deletes
   * the post record from the EconomicForum database and all associated child
   * records including post attachments and post reports.
   *
   * This is a hard delete operation, not a soft delete. The record is
   * permanently removed from the database and cannot be recovered. This
   * functionality is exclusively available to system administrators as defined
   * by the user actor model with admin permissions.
   *
   * The operation requires proper authorization - only users with admin
   * privileges can execute this action. The system will automatically log this
   * administrative action in the EconomicForum system audit table for
   * compliance and tracking purposes.
   *
   * @param connection
   * @param postId Unique identifier of the target post to be deleted. This is
   *   the UUID primary key from the economic_forum_posts table.
   * @x-autobe-specification Delete the post record from economic_forum_posts table using the provided postId identifier. Validate that the authenticated user has admin privileges before deletion. Return the deleted post object with all fields populated as confirmation. Do not perform soft delete; remove the record permanently from the database. Log this deletion event in economic_forum_system_audits table with actor context and timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":postId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
  ): Promise<IEconomicForumPost> {
    try {
      return await deleteEconomicForumUserPostsPostId({
        user,
        postId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
