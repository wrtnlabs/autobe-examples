import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthCitizenJoin } from "../../../providers/postAuthCitizenJoin";
import { postAuthCitizenLogin } from "../../../providers/postAuthCitizenLogin";
import { postAuthCitizenRefresh } from "../../../providers/postAuthCitizenRefresh";

import { IEconomicBoardCitizen } from "../../../api/structures/IEconomicBoardCitizen";

@Controller("/auth/citizen")
export class AuthCitizenController {
  /**
   * This endpoint allows new users to register as citizens by providing their
   * email and password. Upon successful registration, a new record is created
   * in the economic_board_citizens table with the provided email and a hashed
   * password in the password_hash field. The created_at and updated_at fields
   * are automatically set to the current UTC timestamp, and the status is
   * initialized to 'active'. The deleted_at field remains null, indicating an
   * active account.
   *
   * The implementation follows strict security practices: passwords are never
   * stored in plain text but are hashed using bcrypt before storage. The email
   * field must be unique, as enforced by the GIN index on the
   * economic_board_citizens table.
   *
   * This registration flow enables citizens to participate in economic and
   * political discussions by creating their persistent identity, linking future
   * posts, comments, and attachments to this account. Success triggers issuance
   * of a JWT access token and refresh token for subsequent authenticated
   * requests.
   *
   * This operation should be called before any other citizen-related
   * operations, as it establishes the user's identity in the system. It is
   * publicly accessible and does not require prior authentication.
   *
   * @param connection
   * @param body Registration data for creating a new citizen account.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEconomicBoardCitizen.ICreate,
  ): Promise<IEconomicBoardCitizen.IAuthorized> {
    try {
      return await postAuthCitizenJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint authenticates existing citizens by verifying their email and
   * password against the records in the economic_board_citizens table. The
   * system checks that the provided email exists and that the password_hash
   * matches the bcrypt-hashed value provided.
   *
   * When authentication succeeds, a new access token is generated and issued,
   * along with a refresh token to enable token renewal. The updated_at field in
   * the economic_board_citizens table is automatically updated to reflect the
   * latest login timestamp, providing a security audit trail.
   *
   * Login attempts for accounts with non-null deleted_at timestamps are
   * rejected to prevent access to deleted accounts. Similarly, accounts with
   * status of 'suspended' or 'banned' are denied access, enforcing the account
   * status enforcement policy.
   *
   * The system supports secure token refresh mechanisms and multiple concurrent
   * sessions per citizen. This operation is essential for establishing a secure
   * authenticated session and must be performed before accessing protected
   * citizen resources.
   *
   * This endpoint is public and does not require authentication prior to
   * invocation as it is the entry point to the authentication system.
   *
   * @param connection
   * @param body Login credentials for authenticating a citizen.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEconomicBoardCitizen.ILogin,
  ): Promise<IEconomicBoardCitizen.IAuthorized> {
    try {
      return await postAuthCitizenLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint enables citizens to obtain new access tokens using a
   * previously issued refresh token, extending their authenticated session
   * without requiring password re-entry.
   *
   * The system validates that the provided refresh token is active, unexpired,
   * and correctly issued to the citizen identified in the token payload. This
   * validation checks against stored refresh tokens associated with the citizen
   * in the economic_board_citizens table's session management system.
   *
   * Upon successful validation, a new access token is issued, and a new refresh
   * token is rotated (replaced) to prevent replay attacks and enhance security.
   * The refresh token is not stored directly in the economic_board_citizens
   * table's plain fields but is managed securely in the backend token store
   * linked by citizen_id.
   *
   * This operation supports seamless user experience by maintaining
   * authentication across application sessions or browser tabs, while
   * maintaining high security through temporary access tokens and rotating
   * refresh tokens.
   *
   * This endpoint is public but requires a valid refresh token for access, not
   * the citizen's password, ensuring that the authentication system remains
   * secure even if access tokens are compromised.
   *
   * @param connection
   * @param body Refresh token to be validated for generating new access tokens.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEconomicBoardCitizen.IRefresh,
  ): Promise<IEconomicBoardCitizen.IAuthorized> {
    try {
      return await postAuthCitizenRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
