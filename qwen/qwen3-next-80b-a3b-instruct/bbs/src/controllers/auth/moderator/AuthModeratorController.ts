import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthModeratorJoin } from "../../../providers/postAuthModeratorJoin";
import { postAuthModeratorLogin } from "../../../providers/postAuthModeratorLogin";
import { postAuthModeratorRefresh } from "../../../providers/postAuthModeratorRefresh";

import { IEconomicBoardModerator } from "../../../api/structures/IEconomicBoardModerator";

@Controller("/auth/moderator")
export class AuthModeratorController {
  /**
   * Create a new moderator account with email and password_hash.
   *
   * Creates a new moderator account in the system. This operation is initiated
   * by administrators during moderator onboarding and sets up the core identity
   * for a new moderator. The email field is required and must be unique in the
   * economic_board_moderators table. The password_hash field is stored using
   * bcrypt and never exposed in responses.
   *
   * This operation leverages the design characteristics of the
   * economic_board_moderators table, specifically the email and password_hash
   * fields which are marked as required and populated during account creation.
   * The account is initially created with status 'active' and deleted_at set to
   * null.
   *
   * This operation follows the same security model as user registration, but is
   * restricted to administrative onboarding workflows rather than public
   * self-signup.
   *
   * No other authentication-related operations are required for the moderator
   * actor, as the Prisma schema does not include fields for password reset,
   * email verification, or two-factor authentication.
   *
   * This operation has no prerequisites as it is the primary entry point for
   * moderator account creation.
   *
   * @param connection
   * @param body Required information for creating a new moderator account,
   *   including a unique email address and a securely hashed password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEconomicBoardModerator.ICreate,
  ): Promise<IEconomicBoardModerator.IAuthorized> {
    try {
      return await postAuthModeratorJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a moderator using email and password to obtain JWT tokens.
   *
   * Authenticates a moderator by validating email and password credentials
   * against the economic_board_moderators table. The operation checks for an
   * active account with deleted_at = null. If the account exists, the
   * password_hash is verified using bcrypt, and upon success, new access and
   * refresh tokens are generated.
   *
   * This operation relies entirely on the email and password_hash fields
   * defined in the economic_board_moderators table. No other authentication
   * fields (e.g., two-factor secrets, verification tokens) are present, so
   * multi-factor authentication is not supported.
   *
   * Security is enforced through the bcrypt-hashed password storage and the
   * status field validation to prevent login attempts on deactivated accounts.
   *
   * This operation is required for all moderator access and is not subject to
   * prior authentication since it is the entry point for authenticated
   * sessions.
   *
   * This operation has no prerequisites as it is the primary authentication
   * endpoint for moderator access.
   *
   * @param connection
   * @param body Required credentials for authenticating a moderator, including
   *   email and plain text password (encrypted server-side).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEconomicBoardModerator.IRequest,
  ): Promise<IEconomicBoardModerator.IAuthorized> {
    try {
      return await postAuthModeratorLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh the moderator's JWT access token using a valid refresh token.
   *
   * Extends the moderator's session by exchanging a valid refresh token for a
   * new access token. This operation validates the refresh token against the
   * economic_board_moderator_sessions table using the associated
   * economic_board_moderator_id, ensures the session has not expired
   * (expired_at is null), and generates a new access token.
   *
   * This operation depends on the session management design implied by the
   * economic_board_moderator_sessions table, which stores session-specific
   * metadata. While the refresh token itself is not stored in the database, the
   * associated session state is validated using the sleeper pattern based on
   * the existence of a valid session record with matching moderator_id.
   *
   * This operation is critical for maintaining user experience by avoiding
   * frequent login prompts while ensuring security through token expiration and
   * invalidation mechanisms.
   *
   * No additional fields from the moderator schema are involved beyond the
   * session linkage established by the economic_board_moderator_id in the
   * sessions table.
   *
   * This operation has no prerequisites as it is a standalone token refresh
   * mechanism.
   *
   * @param connection
   * @param body Requires a valid refresh token issued during login or a
   *   previous refresh.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEconomicBoardModerator.IRefresh,
  ): Promise<IEconomicBoardModerator.IAuthorized> {
    try {
      return await postAuthModeratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
