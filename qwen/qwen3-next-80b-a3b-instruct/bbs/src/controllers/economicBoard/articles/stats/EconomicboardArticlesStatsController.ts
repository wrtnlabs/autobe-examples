import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicBoardArticleViewStat } from "../../../../api/structures/IEconomicBoardArticleViewStat";
import { getEconomicBoardArticlesArticleIdStats } from "../../../../providers/getEconomicBoardArticlesArticleIdStats";

@Controller("/economicBoard/articles/:articleId/stats")
export class EconomicboardArticlesStatsController {
  /**
   * Retrieve the view statistics for a specific article.
   *
   * This endpoint returns aggregate analytics data for an article, showing how many times it has been viewed in total and how many unique users have viewed it. These statistics are automatically collected by the system whenever an article is accessed and are intended to help users understand the reach and engagement of their content.
   *
   * The data is generated automatically by the system based on article viewing activity and is not editable by users. The total_views count includes all views, even multiple views by the same user. The unique_viewers count represents the number of distinct users who have viewed the article at least once.
   *
   * This endpoint requires the article ID to be provided in the URL path. The endpoint will return 404 Not Found if the article does not exist or if no view statistics are available for it.
   *
   * This operation is read-only and cannot be used to modify statistics. Attempts to use POST, PUT, or DELETE methods will be rejected. This is consistent with the system design where automatically generated metrics do not allow manual manipulation.
   *
   * @param connection
   * @param articleId Unique identifier of the article for which to retrieve view statistics.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query economic_board_article_view_stats table using economic_board_article_id to find the view statistics record. Return total_views and unique_viewers as a JSON object. Return 404 if no statistics record exists (article does not exist or has no views).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IEconomicBoardArticleViewStat> {
    try {
      return await getEconomicBoardArticlesArticleIdStats({
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
