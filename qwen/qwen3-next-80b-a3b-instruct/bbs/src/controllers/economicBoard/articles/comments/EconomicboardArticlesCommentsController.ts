import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicBoardComment } from "../../../../api/structures/IEconomicBoardComment";
import { patchEconomicBoardArticlesArticleIdComments } from "../../../../providers/patchEconomicBoardArticlesArticleIdComments";

@Controller("/economicBoard/articles/:articleId/comments")
export class EconomicboardArticlesCommentsController {
  /**
   * Update an existing comment on a specific article.
   *
   * This operation allows a citizen to modify their own comment within a 60-minute window after posting, or an administrator to edit any comment for moderation purposes. Only the content field may be updated; metadata such as author, article association, and timestamps are automatically managed by the system.
   *
   * When a citizen attempts to edit beyond the 60-minute window, the system returns a 403 Forbidden response, enforcing the policy that comments become immutable after a short grace period to preserve context integrity. Administrators may override this limit. No other fields (such as article_id or author_id) are permitted in the request body—these are bound by the path parameter and authentication context.
   *
   * The response includes the full updated comment object with the author's display name to ensure UI consistency with comment listing views. This operation is protected by JWT authentication and strictly enforces ownership and role permissions.
   *
   * Related operations:
   * - POST /articles/{articleId}/comments for creating new comments
   * - DELETE /comments/{commentId} for removing comments
   * - GET /articles/{articleId}/comments for viewing the list of comments on an article
   *
   * @param connection
   * @param articleId The UUID of the article to which the comment belongs.
   * @param body The updated content of the comment. Must not be empty and must not exceed 1,000 characters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Update an existing comment by commentId. Query economic_board_comments table for comment where id = commentId AND article_id = articleId AND deleted_at IS NULL. Validate user is authenticated and is either comment author or administrator. If comment was created more than 60 minutes ago, return 403 forbidden. Update content and set updated_at to current timestamp. Return updated comment with nested author: {id, display_name}.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicBoardComment.IUpdate,
  ): Promise<IEconomicBoardComment> {
    try {
      return await patchEconomicBoardArticlesArticleIdComments({
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
