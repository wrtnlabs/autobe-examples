import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicBoardArticle } from "../../../api/structures/IEconomicBoardArticle";
import { IEconomicBoardSection } from "../../../api/structures/IEconomicBoardSection";
import { IPageIEconomicBoardArticle } from "../../../api/structures/IPageIEconomicBoardArticle";
import { getEconomicBoardArticlesArticleId } from "../../../providers/getEconomicBoardArticlesArticleId";
import { patchEconomicBoardArticles } from "../../../providers/patchEconomicBoardArticles";

@Controller("/economicBoard/articles")
export class EconomicboardArticlesController {
  /**
   * Retrieve a paginated list of economic board articles with advanced filtering and sorting capabilities.
   *
   * This operation allows authenticated users to search and filter articles across the entire economic discussion board. Supported filters include section (to limit results to a specific category), tag (to find articles with specific keywords), search term (to match against article title or content), and sort order (newest or oldest first). Results are always limited to published (non-deleted) articles.
   *
   * This endpoint is available to all registered users (citizens and administrators). Anonymous access is not permitted. The search functionality performs case-insensitive substring matching on both article title and content fields, enabling flexible discovery of relevant content. Filtering by tag supports free-form user-generated keywords, allowing rich categorization beyond predefined taxonomies. Section filtering ensures content relevance within specific topic areas.
   *
   * Pagination supports configurable page sizes, making it suitable for mobile and desktop clients alike. The summary format provides essential information without the overhead of loading full article content, ensuring fast load times even with large datasets.
   *
   * Related endpoint: GET /economicBoard/articles/{articleId} for detailed article viewing.
   *
   * @param connection
   * @param body Search, filter, and pagination parameters for article list query
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query economic_board_articles table with join to economic_board_sections and economic_board_article_tags.
   * Apply filters: section_id (optional), tag (optional), search (case-insensitive title/content match), is_deleted = false
   * Sort by created_at descending (newest) or ascending (oldest)
   * Apply pagination with offset/limit
   * Return filtered article summaries including article.id, title, section.id/name, author.display_name, tags array, comment_count, created_at, updated_at
   * Join with economic_board_article_views to count total views per article if needed for future ranking
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEconomicBoardArticle.IRequest,
  ): Promise<IPageIEconomicBoardArticle.ISummary> {
    try {
      return await patchEconomicBoardArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single article with complete details including its full content, section, author information, tags, and file attachments.
   *
   * This endpoint provides the complete view of a published article when a user navigates to its detail page. It returns the full title, content, and metadata, including associated tags and any uploaded files (PDFs, images, etc.). The article's section and author are embedded as nested objects for immediate UI display.
   *
   * All returned data is immutable and represents the article's state at the time of retrieval. Deleted articles are excluded from results with a 404 response. Users with no permissions can still access the article if it is public and published.
   *
   * This operation is the canonical source for article content and must be fast and reliable, as it is frequently accessed by readers. It does not support updates or modifications — it is strictly a read-only view.
   *
   * Related endpoints:
   * - GET /articles: Lists articles with summary data (limited fields)
   * - PATCH /articles/{articleId}: Updates an article (requires authentication and ownership)
   * - POST /articles/{articleId}/comments: Adds a new comment on this article
   *
   * @param connection
   * @param articleId Unique UUID identifier of the article to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query economic_board_articles table by id where is_deleted = false. Join with economic_board_sections to get section name. Join with economic_board_citizens to get author display_name. Left join with economic_board_article_tags to collect all tags as array. Left join with economic_board_article_attachments to collect all attachments. Return full article object with nested section, author, tags, and attachments. Return 404 if article is deleted or not found. Do not include soft delete logic in this operation; deleted articles are filtered out by the is_deleted condition. Never include article content in summary endpoints — only this 'at' endpoint returns full content.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IEconomicBoardSection> {
    try {
      return await getEconomicBoardArticlesArticleId({
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
