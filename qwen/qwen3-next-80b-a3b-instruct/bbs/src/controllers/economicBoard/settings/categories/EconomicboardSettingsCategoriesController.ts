import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getEconomicBoardSettingsCategories } from "../../../../providers/getEconomicBoardSettingsCategories";
import { getEconomicBoardSettingsCategoriesCategoryCode } from "../../../../providers/getEconomicBoardSettingsCategoriesCategoryCode";

import { IPageIEconomicBoardCategory } from "../../../../api/structures/IPageIEconomicBoardCategory";
import { IEconomicBoardCategory } from "../../../../api/structures/IEconomicBoardCategory";

@Controller("/economicBoard/settings/categories")
export class EconomicboardSettingsCategoriesController {
  /**
   * Retrieve a list of all system-defined economic board categories.
   *
   * Retrieve a paginated list of all system-defined economic board categories
   * that are used to classify and filter discussion posts.
   *
   * This endpoint provides administrators and users with complete visibility
   * into the platform's taxonomy structure. The returned categories are
   * system-managed immutable values that define the core content organization
   * framework of the economic discussion board. Each category has a unique code
   * used in search and filtering APIs and a human-readable name displayed in
   * user interfaces.
   *
   * The service retrieves all categories from the economic_board_categories
   * table. The operation does not include pagination parameters since the
   * number of categories is expected to be small (typically under 50) and
   * stable. All categories are active and cannot be deleted by users or
   * moderators. The response provides minimal metadata fields to optimize data
   * transfer while ensuring all necessary information for filtering and display
   * is included.
   *
   * This is a read-only operation. The categories are set up during system
   * deployment and cannot be modified by end-users. Any changes to the category
   * list require a code deployment. The operation returns all categories
   * without filtering. For APIs that need to search or filter by category, the
   * client should use the category code in URL paths like
   * /settings/categories/{categoryCode}.
   *
   * Security: This endpoint is public. No authentication or authorization is
   * required to view the category taxonomy.
   *
   * Related operations:
   *
   * - GET /settings/categories/{categoryCode} - Retrieve detailed view of a
   *   single category
   * - POST /settings/categories - Forbidden (categories are system-managed)
   * - PATCH /settings/categories - Forbidden (categories are system-managed)
   * - DELETE /settings/categories - Forbidden (categories are system-managed)
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(): Promise<IPageIEconomicBoardCategory.ISummary> {
    try {
      return await getEconomicBoardSettingsCategories();
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific economic board category by its code.
   *
   * Retrieve the full details of a single economic board category identified by
   * its unique code.
   *
   * This endpoint returns complete information about a specific category used
   * to classify and filter economic and political discussion posts. The
   * category is identified by an immutable, system-assigned code (e.g.,
   * "economy", "politics"). This code is used across the entire platform in
   * URLs, search queries, and API filters to ensure consistent, human-readable
   * access to content organization.
   *
   * The operation retrieves the complete record from the
   * economic_board_categories table where the code matches the provided path
   * parameter. The returned data includes the human-readable name for display,
   * a detailed description for internal use, and system timestamps for audit
   * purposes.
   *
   * This operation is part of a read-only hierarchy. Categories cannot be
   * created, updated, or deleted by users or moderators. The system maintains
   * immutability of these taxonomy terms to ensure data consistency. This
   * endpoint supports direct navigation and is used for category detail views
   * and validation of category references in posted content.
   *
   * Security: This endpoint is public. No authentication or authorization is
   * required since category taxonomy information is not sensitive.
   *
   * Related operations:
   *
   * - GET /settings/categories - List all categories
   * - GET /posts?categoryCode=xx - Search for posts in a specific category
   * - POST /settings/categories - Forbidden: system-managed
   * - PUT /settings/categories/{code} - Forbidden: system-managed
   * - DELETE /settings/categories/{code} - Forbidden: system-managed
   *
   * @param connection
   * @param categoryCode Unique machine-readable identifier of the category
   *   (e.g., "economy", "politics"). Must match exactly one of the predefined
   *   codes in the system. Used to directly reference category in URLs and
   *   search queries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryCode")
  public async at(
    @TypedParam("categoryCode")
    categoryCode: string,
  ): Promise<IEconomicBoardCategory> {
    try {
      return await getEconomicBoardSettingsCategoriesCategoryCode({
        categoryCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
