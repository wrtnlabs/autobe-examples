import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getEconomicBoardSettingsTimezones } from "../../../../providers/getEconomicBoardSettingsTimezones";
import { getEconomicBoardSettingsTimezonesTimezoneCode } from "../../../../providers/getEconomicBoardSettingsTimezonesTimezoneCode";

import { IPageIEconomicBoardTimezoneSetting } from "../../../../api/structures/IPageIEconomicBoardTimezoneSetting";
import { IEconomicBoardTimezoneSetting } from "../../../../api/structures/IEconomicBoardTimezoneSetting";

@Controller("/economicBoard/settings/timezones")
export class EconomicboardSettingsTimezonesController {
  /**
   * Retrieve a comprehensive list of all supported timezone settings that the
   * economic board platform uses for user-facing timestamp display.
   *
   * The system stores all timestamps internally in UTC but presents them in the
   * user's local timezone. This endpoint provides access to the
   * economic_board_timezone_settings table which contains the complete set of
   * valid timezone identifiers from the IANA timezone database that users can
   * select for display purposes. Only timezones listed here can be selected by
   * users, ensuring consistency across the platform.
   *
   * The response includes each timezone's full name, short code, UTC offset,
   * and whether it's the system default. This information allows clients to
   * construct proper timezone selection UIs and convert timestamps correctly.
   * The system default timezone ("Asia/Seoul") is identified by is_default=true
   * and must be displayed prominently.
   *
   * This operation supports pagination and filtering for large deployments,
   * though in standard configurations the list of valid timezones is relatively
   * small and typically returned in a single page.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(): Promise<IPageIEconomicBoardTimezoneSetting> {
    try {
      return await getEconomicBoardSettingsTimezones();
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific timezone setting using its
   * short platform identifier code (e.g., "KST", "EST").
   *
   * This operation looks up the timezone_setting record by its unique code
   * field from the economic_board_timezone_settings table. The timezoneCode
   * parameter must exactly match the code stored in the database
   * (case-sensitive), and only codes defined in the timezone_settings table are
   * valid.
   *
   * The response returns the complete timezone details: the full IANA timezone
   * name (e.g., "Asia/Seoul"), the short code, UTC offset, and whether it's the
   * system default. This information is essential for applications that need to
   * display timezone information to users with contextual details instead of
   * just the code.
   *
   * This endpoint is typically used after a user selects a timezone from the
   * list returned by GET /settings/timezones, or when restoring a saved
   * timezone preference for a user account. The system validates that the
   * requested code exists in the timezone_settings table before returning the
   * result.
   *
   * @param connection
   * @param timezoneCode Short identifier code of the target timezone setting
   *   (e.g., "KST", "EST"). Must exactly match a code defined in the
   *   economic_board_timezone_settings table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":timezoneCode")
  public async at(
    @TypedParam("timezoneCode")
    timezoneCode: string,
  ): Promise<IEconomicBoardTimezoneSetting> {
    try {
      return await getEconomicBoardSettingsTimezonesTimezoneCode({
        timezoneCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
