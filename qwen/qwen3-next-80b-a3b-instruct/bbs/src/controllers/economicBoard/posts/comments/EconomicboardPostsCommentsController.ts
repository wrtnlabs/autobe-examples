import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getEconomicBoardPostsPostIdComments } from "../../../../providers/getEconomicBoardPostsPostIdComments";
import { patchEconomicBoardPostsPostIdComments } from "../../../../providers/patchEconomicBoardPostsPostIdComments";
import { getEconomicBoardPostsPostIdCommentsCommentId } from "../../../../providers/getEconomicBoardPostsPostIdCommentsCommentId";

import { IPageIEconomicBoardComment } from "../../../../api/structures/IPageIEconomicBoardComment";
import { IEconomicBoardComment } from "../../../../api/structures/IEconomicBoardComment";

@Controller("/economicBoard/posts/:postId/comments")
export class EconomicboardPostsCommentsController {
  /**
   * Retrieve paginated comments for a specific discussion post.
   *
   * Retrieve a paginated list of published comments associated with the
   * specified post. Returns only comments with status 'published' that belong
   * to a post with status 'published'. Uses index on (post_id, created_at) for
   * performance.
   *
   * This operation supports navigation through large comment threads using
   * pagination. Clients specify page number and page size with query parameters
   * (or path parameters). The default page size is 20, with a hard limit of 100
   * to prevent system overload.
   *
   * Only comments attached to published posts are returned. Comments on pending
   * or rejected posts are excluded from results.
   *
   * The response includes the comment body, creation timestamp, and the
   * citizen's handle (username) from the economic_board_citizens table, to
   * provide a clean user experience without exposing internal UUIDs.
   *
   * Related operations:
   *
   * - DELETE /economicBoard/comments/{commentId}: To delete a specific comment
   * - POST /economicBoard/posts/{postId}/comments: To add a new comment
   *
   * Error handling: Returns 404 if the post_id does not reference a valid
   * published post.
   *
   * Performance: The database index on (post_id, created_at) ensures efficient
   * retrieval of comments for a specific post in reverse chronological order.
   *
   * @param connection
   * @param postId Unique identifier of the published post whose comments are
   *   being retrieved. Must reference a record in economic_board_posts with
   *   status 'published'.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async getByPostid(
    @TypedParam("postId")
    postId: string,
  ): Promise<IPageIEconomicBoardComment> {
    try {
      return await getEconomicBoardPostsPostIdComments({
        postId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get list of comments for a specific post.
   *
   * Retrieve a paginated list of comments for a specific economic board post.
   *
   * This operation fetches all comments associated with a given post ID,
   * returning only those that are in 'published' status (status = 'published').
   * According to the business rules defined in the economic_board_comments
   * model, comments can only exist on published posts, so the operation
   * implicitly validates that the target post is published by its existence in
   * the system.
   *
   * Comments returned are ordered by created_at in descending order (newest
   * first) by default. The operation supports pagination through limit and
   * offset parameters, and allows clients to sort by created_at in ascending or
   * descending order.
   *
   * Deleted comments (where deleted_at is not null) are excluded from results
   * by default, as they are archived for audit purposes but not displayed to
   * users. The comment status field is an enum with 'published' or 'deleted'
   * values, so the query uses a WHERE status = 'published' clause.
   *
   * This operation is directly tied to the economic_board_comments table and
   * uses the post_id foreign key to filter results, ensuring referential
   * integrity. The operation never returns comments on pending or rejected
   * posts, as those posts are not commentable according to the system's
   * business logic.
   *
   * @param connection
   * @param postId The unique identifier of the target post for which to
   *   retrieve comments. Must reference a post in economic_board_posts table.
   * @param body Search and pagination parameters for comment filtering and
   *   ordering.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async patchByPostid(
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicBoardComment.IRequest,
  ): Promise<IPageIEconomicBoardComment.ISummary> {
    try {
      return await patchEconomicBoardPostsPostIdComments({
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get a specific comment by ID.
   *
   * Retrieve detailed information about a specific comment by its unique
   * identifier.
   *
   * This operation fetches a single comment from the economic_board_comments
   * table using its UUID identifier. The operation validates that the comment
   * exists, is published (status = 'published'), and has not been deleted
   * (deleted_at = null). If the comment doesn't exist, is not published, or has
   * been deleted, a 404 error is returned.
   *
   * The response includes the complete comment content (body), timestamps
   * (created_at, updated_at), reply structure (parent_comment_id), and
   * references to the citizen who made the comment. The post_id field is
   * included to maintain context of the parent post, but the parent post's
   * content itself is not returned as this would be excessive for a single
   * comment lookup.
   *
   * Security is enforced through the comment's status field: only comments with
   * status 'published' are returned. Comments with status 'deleted' or those
   * associated with unpublished posts are never accessible via this endpoint,
   * regardless of whether the caller knows the comment's UUID.
   *
   * The primary source of truth is the economic_board_comments table model,
   * which defines the mandatory fields and constraints that must be respected
   * in this operation.
   *
   * @param connection
   * @param postId The unique identifier of the target post for which to
   *   retrieve comments. Must reference a post in economic_board_posts table.
   * @param commentId The unique identifier of the target comment to retrieve.
   *   Must reference a record in the economic_board_comments table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":commentId")
  public async at(
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IEconomicBoardComment> {
    try {
      return await getEconomicBoardPostsPostIdCommentsCommentId({
        postId,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
