import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchEconomicBoardPosts } from "../../../providers/patchEconomicBoardPosts";
import { getEconomicBoardPostsPostId } from "../../../providers/getEconomicBoardPostsPostId";

import { IPageIEconomicBoardPost } from "../../../api/structures/IPageIEconomicBoardPost";
import { IEconomicBoardPost } from "../../../api/structures/IEconomicBoardPost";

@Controller("/economicBoard/posts")
export class EconomicboardPostsController {
  /**
   * Retrieve a filtered and paginated list of economic board discussion posts
   * based on configurable search and filtering parameters.
   *
   * This operation enables citizens to discover content through categories,
   * authors, and status filters, while allowing moderators to efficiently
   * review pending or rejected posts. The query supports filtering by status
   * (pending, published, rejected), category, citizen author, and post creation
   * date ranges. Only non-deleted posts are returned, and their visibility is
   * further restricted by the requesting actor's permissions.
   *
   * Security: All actors can view published posts, while only moderators can
   * view pending and rejected posts. The operation supports pagination with
   * configurable limit and offset, and results are sortable by created_at
   * (default), updated_at, or title. Search terms are applied as full-text
   * queries against the title and body fields.
   *
   * This operation is part of the citizen discovery workflow and the moderator
   * review pipeline. Related operations: GET /posts/{postId} (to retrieve a
   * single post's details), POST /posts (for creating a new pending post), and
   * PATCH /posts/{postId} (for updating post metadata).
   *
   * The response returns a paginated summary view
   * (IPageIEconomicBoardPost.ISummary) to reduce payload size for list
   * displays, avoiding the full post body unless absolutely necessary.
   *
   * @param connection
   * @param body Search criteria, pagination settings, and sorting preferences
   *   for post filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @TypedBody()
    body: IEconomicBoardPost.IRequest,
  ): Promise<IPageIEconomicBoardPost.ISummary> {
    try {
      return await patchEconomicBoardPosts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the detailed information of a single economic board discussion
   * post by its unique identifier.
   *
   * This operation is used by citizens to view published posts in detail, and
   * by moderators to inspect pending, rejected, or deleted posts for review
   * purposes. The post must be identified by its numeric ID (post_id) and is
   * returned with full content (title, body), metadata (status, created_at,
   * updated_at), and reference identifiers for the citizen author and moderator
   * decisions (approved/rejected/deleted).
   *
   * Security: The operation checks both the post's status and the requesting
   * actor's permissions. Citizens may only view published posts (status:
   * 'published'). Moderators can view all posts including pending ('pending'),
   * rejected ('rejected'), and deleted ('deleted_at' not null). The operation
   * returns a 404 Not Found if the post does not exist or if the actor lacks
   * sufficient permissions to view it.
   *
   * This operation returns the full entity (IEconomicBoardPost) for detailed
   * display contexts, contrasting with the summary view used in list queries.
   * Related operations: PATCH /posts (to search and filter published posts),
   * PATCH /posts/{postId} (to handle UPDATE operations on post metadata).
   *
   * The ID parameter is taken from the economic_board_posts.id field, which is
   * a universally unique identifier. No human-readable code field exists for
   * posts, so the UUID identifier is used.
   *
   * @param connection
   * @param postId The universally unique identifier of the target post to
   *   retrieve. Must match the id field in the economic_board_posts table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":postId")
  public async at(
    @TypedParam("postId")
    postId: string,
  ): Promise<IEconomicBoardPost> {
    try {
      return await getEconomicBoardPostsPostId({
        postId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
