import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getEconomicBoardPostsPostIdAttachmentsAttachmentId } from "../../../../providers/getEconomicBoardPostsPostIdAttachmentsAttachmentId";

import { IEconomicBoardAttachment } from "../../../../api/structures/IEconomicBoardAttachment";

@Controller("/economicBoard/posts/:postId/attachments/:attachmentId")
export class EconomicboardPostsAttachmentsController {
  /**
   * Retrieve metadata for a specific file attachment associated with a
   * discussion post.
   *
   * This operation returns comprehensive metadata about an attachment linked to
   * a specific post. All attachments are stored in object storage and accessed
   * via signed URIs. The operation returns the original filename, sanitized
   * filename, file size in bytes, MIME type, secure storage URI, and current
   * status (uploaded, processed, or quarantined).
   *
   * The attachment's visibility is governed by the status of its parent post.
   * Only attachments linked to published posts can be accessed. If the parent
   * post is pending, rejected, or deleted, this operation will return a 404
   * error even if the attachment record exists. This ensures content security
   * and prevents access to attachments associated with non-public posts.
   *
   * Attachments are never permanently deleted. The deleted_at field is used for
   * audit trails only and does not affect accessibility—access is controlled
   * solely by the parent post's status. The storage_path is a signed,
   * time-limited URI that expires after 1 hour for security.
   *
   * The attachment must be verified as accessible before returning any
   * metadata. No authentication is required for this operation since any
   * attached file is visible only if the parent post is published, but post
   * visibility is validated internally.
   *
   * Related operations: GET /posts/{postId} to validate post status before
   * accessing attachments, PATCH /posts/{postId}/attachments to list
   * attachments for a post.
   *
   * @param connection
   * @param postId Unique identifier of the parent discussion post, used to
   *   validate post status before returning attachment metadata. Must reference
   *   an existing economic_board_posts.id.
   * @param attachmentId Unique identifier of the attachment record to retrieve,
   *   referencing economic_board_attachments.id.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("postId")
    postId: string,
    @TypedParam("attachmentId")
    attachmentId: string,
  ): Promise<IEconomicBoardAttachment> {
    try {
      return await getEconomicBoardPostsPostIdAttachmentsAttachmentId({
        postId,
        attachmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
