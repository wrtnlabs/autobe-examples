import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getEconomicBoardCommentsCommentId } from "../../../providers/getEconomicBoardCommentsCommentId";
import { deleteEconomicBoardCommentsCommentId } from "../../../providers/deleteEconomicBoardCommentsCommentId";

import { IEconomicBoardComment } from "../../../api/structures/IEconomicBoardComment";

@Controller("/economicBoard/comments/:commentId")
export class EconomicboardCommentsController {
  /**
   * Retrieve a single economic board comment by its unique UUID identifier.
   * This operation provides comprehensive details of a comment attached to a
   * published discussion post, including its content, authorship, and
   * moderation status.
   *
   * The comment object contains the full text content, creation and update
   * timestamps, and status field indicating whether the comment is still
   * published or has been deleted by a moderator. The citizen_id field
   * identifies the original author, and the post_id field references the
   * published post this comment responds to. If the comment is part of a
   * threaded conversation, the parent_comment_id field links to its parent
   * comment.
   *
   * Security: Any authenticated user may retrieve a comment by its ID.
   * Moderators will receive escalated metadata fields including
   * moderator_deleted_id. The operation respects comment deletion status: even
   * deleted comments remain retrievable for audit and moderation purposes, but
   * their status field will indicate 'deleted'. The comment body is always
   * visible, regardless of status, to preserve context in moderation chains.
   *
   * This operation directly maps to the economic_board_comments Prisma table.
   * It returns all fields including status, which is critical for thread
   * integrity and moderator audit trails. The comment must exist in the
   * database to be retrievable; non-existent IDs return 404.
   *
   * Related operations: Updates to a comment (PUT /comments/{commentId}) can
   * modify the body and updated_at fields within 24 hours. Moderators can
   * perform permanent deletion through a separate operation that sets status to
   * 'deleted'.
   *
   * @param connection
   * @param commentId Unique identifier of the comment to retrieve. Matches the
   *   UUID primary key in the economic_board_comments table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("commentId")
    commentId: string,
  ): Promise<IEconomicBoardComment> {
    try {
      return await getEconomicBoardCommentsCommentId({
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently deletes a specific comment by its globally unique ID. The
   * record is soft-deleted using the deleted_at field. Only the comment owner
   * or a moderator can delete the comment.
   *
   * This operation removes the comment from public view by updating the
   * deleted_at timestamp to the current time. The comment record remains in the
   * database for audit compliance, but it is filtered out from all public
   * queries and APIs.
   *
   * The system verifies either that the JWT token's user_id matches the
   * comment's citizen_id field (for citizen) OR that the JWT token contains the
   * 'moderator' actor role (for moderator).
   *
   * Related operations:
   *
   * - GET /economicBoard/posts/{postId}/comments: To retrieve remaining comments
   *   on the same post
   *
   * Security: The server checks role/ownership matching upon request. Access
   * denied if neither condition is met.
   *
   * Error handling: Returns 404 if the comment_id does not exist or if access
   * is denied (user is not owner or moderator).
   *
   * @param connection
   * @param commentId The globally unique identifier (UUID) of the comment to be
   *   deleted. Must exist in the economic_board_comments table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @TypedParam("commentId")
    commentId: string,
  ): Promise<void> {
    try {
      return await deleteEconomicBoardCommentsCommentId({
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
