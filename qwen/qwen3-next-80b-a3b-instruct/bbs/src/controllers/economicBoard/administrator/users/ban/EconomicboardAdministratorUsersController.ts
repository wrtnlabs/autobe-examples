import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEconomicBoardCitizen } from "../../../../../api/structures/IEconomicBoardCitizen";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { postEconomicBoardAdministratorUsersUserIdBan } from "../../../../../providers/postEconomicBoardAdministratorUsersUserIdBan";

@Controller("/economicBoard/administrator/users/:userId/ban")
export class EconomicboardAdministratorUsersController {
  /**
   * Permanently ban a citizen account, preventing all future authentication and interactions with the system.
   *
   * This operation sets the is_banned flag to true and records a mandatory ban reason provided by an administrator or super administrator. Once banned, the user can no longer log in, and their sessions are immediately invalidated. All of their existing articles and comments remain publicly visible to preserve content integrity and accountability — the ban enforces access restriction, not content removal.
   *
   * The reason must be at least 10 characters long and provides official documentation for the enforcement action. This behavior is designed as a hard policy: bans can be reversed by setting is_banned back to false via the same endpoint.
   *
   * This endpoint can only be invoked by users holding administrator or super administrator roles. Regular citizens cannot initiate bans. Ban actions are logged in the administrator_audit_logs table for audit compliance.
   *
   * @param connection
   * @param userId Unique identifier of the citizen account to be banned.
   * @param body Fields for updating citizen account to banned state.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Update economic_board_citizens record by setting is_banned = true, ban_reason = provided reason, and banned_at = current timestamp. Invalidate all citizen_sessions records for this user_id using DELETE WHERE citizen_id = userId. Ensure only users with 'administrator' or 'superAdministrator' role can execute this operation. Validate that reason length is between 10 and 500 characters. Log the action to economic_board_administrator_audit_logs with actor_id, target_id, action='ban', and reason. Return updated economic_board_citizens record with all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async ban(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("userId")
    userId: string,
    @TypedBody()
    body: IEconomicBoardCitizen,
  ): Promise<IEconomicBoardCitizen> {
    try {
      return await postEconomicBoardAdministratorUsersUserIdBan({
        administrator,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
