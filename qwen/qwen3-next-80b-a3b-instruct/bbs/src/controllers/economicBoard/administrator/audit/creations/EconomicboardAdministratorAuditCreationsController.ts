import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIEconomicBoardSectionCreation } from "../../../../../api/structures/IPageIEconomicBoardSectionCreation";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getEconomicBoardAdministratorAuditCreations } from "../../../../../providers/getEconomicBoardAdministratorAuditCreations";

@Controller("/economicBoard/administrator/audit/creations")
export class EconomicboardAdministratorAuditCreationsController {
  /**
   * Retrieve a paginated audit log of section creation events on the Economic/Political Discussion Board.
   *
   * This endpoint provides a historical record of all section creations, showing which administrator created each section and when. The audit trail is essential for accountability, compliance, and debugging, allowing super administrators to track the evolution of the platform's structure over time.
   *
   * Each record in the response includes the section name, the administrator's display name who created it, and the exact timestamp of creation. This information is presented in a summarized format optimized for listing interfaces, with full details available through associated links.
   *
   * Access to this endpoint is restricted to super administrators due to the sensitive nature of administrative audit trails. This prevents misuse of administrative power by ensuring only the highest-level users can monitor other administrators' actions.
   *
   * This operation complements the section management workflow, where section creation is an auditable administrative action. Users can verify that all sections were created by authorized personnel, and super administrators can identify patterns of activity or potential abuse.
   *
   * Important: Section creation records are preserved in the audit log even if the corresponding section is later soft-deleted (marked with deleted_at). This ensures complete audit history regardless of the current status of the section. Hard deletion of section creation records never occurs, as the audit trail must remain immutable for compliance.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the economic_board_section_creations table, joining with economic_board_administrators to get display_name and economic_board_sections to get section name. Return results ordered by created_at descending. Implement cursor-based pagination with limit and offset parameters. Include only active sections (deleted_at IS NULL). Do not include any section creation records where the associated section or administrator has been deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
  ): Promise<IPageIEconomicBoardSectionCreation.ISummary> {
    try {
      return await getEconomicBoardAdministratorAuditCreations({
        administrator,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
