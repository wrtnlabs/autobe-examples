import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicBoardSectionSnapshot } from "../../../../../api/structures/IEconomicBoardSectionSnapshot";
import { IPageIEconomicBoardSectionSnapshot } from "../../../../../api/structures/IPageIEconomicBoardSectionSnapshot";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { patchEconomicBoardAdministratorSectionsSectionIdSnapshots } from "../../../../../providers/patchEconomicBoardAdministratorSectionsSectionIdSnapshots";

@Controller("/economicBoard/administrator/sections/:sectionId/snapshots")
export class EconomicboardAdministratorSectionsSnapshotsController {
  /**
   * Retrieve a paginated list of historical snapshots for a specific section.
   *
   * This endpoint provides an audit trail of all name and description changes made to a section over time. Each snapshot records the exact state of the section at the moment it was modified, including the administrator who made the change and the reason for the modification.
   *
   * This is not a listing of active sections, but a chronological history of modifications—essential for accountability, compliance, and debugging administrative actions. The list is ordered newest first, and supports pagination to handle sections with extensive modification histories.
   *
   * Snapshots are immutable records; no updates or deletions are allowed once created. This endpoint does not return the current state of the section—only prior historical states.
   *
   * @param connection
   * @param sectionId The unique identifier of the section whose historical snapshots are being retrieved. This must correspond to a valid economic_board_section.id.
   * @param body Pagination and ordering parameters for the snapshot list.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query economic_board_section_snapshots table filtered by economic_board_section_id. Support pagination with cursor-based or offset-based (page, limit) parameters received in request body. Sort by created_at descending (newest first). Return only id, section_name, section_description, created_at, snapshot_reason, and administrator_id (with null handling). Ensure that section_id path parameter is used to filter records strictly.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicBoardSectionSnapshot.IRequest,
  ): Promise<IPageIEconomicBoardSectionSnapshot.ISummary> {
    try {
      return await patchEconomicBoardAdministratorSectionsSectionIdSnapshots({
        administrator,
        sectionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
