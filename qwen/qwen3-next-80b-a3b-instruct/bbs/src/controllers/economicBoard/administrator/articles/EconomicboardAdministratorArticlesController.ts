import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicBoardArticle } from "../../../../api/structures/IEconomicBoardArticle";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { deleteEconomicBoardAdministratorArticlesArticleId } from "../../../../providers/deleteEconomicBoardAdministratorArticlesArticleId";
import { getEconomicBoardAdministratorArticlesArticleId } from "../../../../providers/getEconomicBoardAdministratorArticlesArticleId";

@Controller("/economicBoard/administrator/articles/:articleId")
export class EconomicboardAdministratorArticlesController {
  /**
   * Retrieve the full details of a specific article by its unique identifier.
   *
   * This endpoint returns comprehensive information about a single article, including its title, content, associated section, author display name, list of tags, attached files or images, and comment count. The article must not be deleted (is_deleted = false).
   *
   * All timestamp fields (created_at, updated_at) are returned in ISO 8601 format. Attachment URLs point to externally hosted files. Tags are returned as an array of string labels. Author information is anonymized to display name only, without email or ID exposure.
   *
   * This operation is available to all authenticated users and administrators. If the article does not exist or has been deleted, a 404 response is returned.
   *
   * @param connection
   * @param articleId Unique identifier of the article to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query economic_board_articles table by id where is_deleted = false. Join with economic_board_sections to get section name. Join with economic_board_citizens to get author display_name. Join with economic_board_article_tags and economic_board_tags to compile list of tag names. Join with economic_board_article_attachments to retrieve attachment metadata (file_url, file_name, file_type, file_size). Count related economic_board_comments for comment_count. Return all fields as specified in requirements with ISO 8601 timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IEconomicBoardArticle> {
    try {
      return await getEconomicBoardAdministratorArticlesArticleId({
        administrator,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an article from public view while preserving its record in the database for audit purposes.
   *
   * This endpoint allows the author of an article to permanently remove their content from public visibility. The article is hidden from all listings, search results, and feeds, but its record remains in the database with metadata for legal and operational audit trails.
   *
   * This operation does NOT remove the article from the database or delete associated comments. Comments remain intact and are preserved as orphaned records. File attachments are not deleted from storage but are marked as unused. The system enforces strict ownership checks: only the author of the article or an administrator can delete it.
   *
   * If the article has already been deleted, subsequent delete requests return "ECONOMICBOARD_ARTICLE_NOT_FOUND". When an administrator deletes an article, the system internally logs the action for accountability.
   *
   * The deletion is permanent and irreversible. This design ensures content accountability while respecting user privacy and regulatory requirements.
   *
   * This operation must be called after retrieving the target article (GET /economic_board_articles/{articleId}) to confirm ownership prior to deletion.
   *
   * @param connection
   * @param articleId The unique identifier of the article to be deleted. Must be a valid UUID of an existing article.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Update economic_board_articles record by setting status = 'deleted', deleted_at = CURRENT_TIMESTAMP, and deleted_by = (if admin, admin_id; else user_id). Do not delete record from database. Update article_views cache to mark visibility as false. Preserve comments in economic_board_comments (no action needed on comments). Do not delete attachment files — just mark economic_board_article_attachments as unused. Log deletion event to economic_board_administrator_audit_logs if performed by admin. Return 404 if article already deleted or not found. Return 403 if user is not author or admin.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("articleId")
    articleId: string,
  ): Promise<void> {
    try {
      return await deleteEconomicBoardAdministratorArticlesArticleId({
        administrator,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
