import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicBoardComment } from "../../../../../api/structures/IEconomicBoardComment";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { deleteEconomicBoardAdministratorArticlesArticleIdCommentsCommentId } from "../../../../../providers/deleteEconomicBoardAdministratorArticlesArticleIdCommentsCommentId";
import { putEconomicBoardAdministratorArticlesArticleIdCommentsCommentId } from "../../../../../providers/putEconomicBoardAdministratorArticlesArticleIdCommentsCommentId";

@Controller(
  "/economicBoard/administrator/articles/:articleId/comments/:commentId",
)
export class EconomicboardAdministratorArticlesCommentsController {
  /**
   * Edit an existing comment on an article.
   *
   * This operation allows the original author or an administrator to modify the content of a comment within 60 minutes of its creation. After the edit window closes, comments become immutable as a policy to preserve discussion integrity.
   *
   * The comment must belong to a valid article and the user must hold appropriate permissions — either the author of the comment or an administrator. If the comment has been soft-deleted (marked by deleted_at), it cannot be edited.
   *
   * Content must be trimmed and validated to be non-empty and not exceed 1,000 characters. Successful edits update the updated_at timestamp and return the full comment object with an edited timestamp. An 'edited' badge will be displayed in the frontend.
   *
   * This operation is not used for mass updates, deletions, or bulk operations — those are handled by separate endpoints. It is strictly a single-comment field update.
   *
   * Related operations: POST /articles/{articleId}/comments (create), DELETE /comments/{commentId} (soft-delete).
   *
   * @param connection
   * @param articleId The unique identifier of the article to which the comment belongs. Must be a valid UUID.
   * @param commentId The unique identifier of the comment to be updated. Must be a valid UUID.
   * @param body The new content for the comment. Must be non-empty and ≤1000 characters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Update an existing comment by its ID. Perform ownership validation: user must be either the comment's author or an administrator. Verify comment is not soft-deleted (deleted_at is null). Enforce edit window: only allow edit if updated_at is within 60 minutes of created_at. Validate content length (≤ 1000 characters after trimming). Update only the 'content' and 'updated_at' fields in database. Do not modify article_id, author_id, or created_at. Return updated comment object including all fields: id, article_id, author_id, content, created_at, updated_at, deleted_at. Do not update article comment_count on edit — only on create/delete.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("articleId")
    articleId: string,
    @TypedParam("commentId")
    commentId: string,
    @TypedBody()
    body: IEconomicBoardComment.IUpdate,
  ): Promise<IEconomicBoardComment> {
    try {
      return await putEconomicBoardAdministratorArticlesArticleIdCommentsCommentId(
        {
          administrator,
          articleId,
          commentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a comment from public view while preserving it for audit purposes.
   *
   * This operation allows either the comment's original author or an administrator to delete a comment. When executed, the system marks the comment as deleted by setting the deleted_at timestamp, removes it from article comment threads, and decrements the associated article's comment count. The original comment content and metadata are preserved in the database for compliance and moderation auditing.
   *
   * Only users with ownership of the comment or administrator privileges can perform this action. If a citizen attempts to delete a comment they did not create, the system responds with HTTP 403 Forbidden. Administrators must provide a deletion reason that is logged with the event.
   *
   * This operation supports compliance with content moderation policies and user rights to manage their own content, consistent with the system's privacy and audit requirements.
   *
   * This operation is logically followed by GET /articles/{articleId}/comments to refresh the displayed comment list after deletion.
   *
   * @param connection
   * @param articleId The unique identifier of the article containing the comment.
   * @param commentId The unique identifier of the comment to be deleted.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Soft-delete the comment by setting deleted_at to current timestamp. Decrement the associated article's comment_count by 1. Log deletion event with administrator ID (if admin) or user ID (if owner), comment ID, article ID, and timestamp. Do NOT delete the comment record physically. Validate that user is either the comment author or an administrator before executing. Ensure article exists and is not itself deleted. Return 403 Forbidden if user lacks permission. Return 404 if comment or article does not exist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEconomicBoardAdministratorArticlesArticleIdCommentsCommentId(
        {
          administrator,
          articleId,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
