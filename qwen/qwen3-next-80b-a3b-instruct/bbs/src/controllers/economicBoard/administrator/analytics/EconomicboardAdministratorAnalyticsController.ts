import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIEconomicBoardArticleView } from "../../../../api/structures/IPageIEconomicBoardArticleView";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { patchEconomicBoardAdministratorAnalytics } from "../../../../providers/patchEconomicBoardAdministratorAnalytics";

@Controller("/economicBoard/administrator/analytics")
export class EconomicboardAdministratorAnalyticsController {
  /**
   * Retrieve aggregated analytics data for super administrators showing user activity and content performance trends.
   *
   * This endpoint returns key performance indicators for the economic board platform, including Daily Active Users (DAU), Weekly Active Users (WAU), and Monthly Active Users (MAU) over the past 30 days. It also provides trend data showing daily patterns of article postings, comment activity, and user logins.
   *
   * Additionally, the endpoint categorizes users based on engagement patterns: users who have posted more than 10 articles are marked as 'super contributors', those who have commented on articles across 5+ different sections are identified as 'cross-topic participants', and users who have received replies on their comments across 15+ unique articles are counted as 'engaged participants'.
   *
   * This data is system-generated and updated automatically through background processes. There are no user inputs or writes to this endpoint. The analytics are computed from existing data in economic_board_citizens, economic_board_articles, and economic_board_comments tables.
   *
   * Only super administrators can access this endpoint. The results are paginated to support efficient loading of large datasets with configurable page sizes and sorting by metric type or date range.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query economic_board_citizens, economic_board_articles, and economic_board_comments to calculate daily/weekly/monthly active users (DAU/WAU/MAU) and trend lines. Aggregate article post counts, comment counts, and login events over the past 30 days. Categorize users as 'super contributor' (10+ articles), 'cross-topic participant' (5+ section comments), and 'engaged participant' (15+ reply interactions). Return paginated results filtered by date range if specified.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
  ): Promise<IPageIEconomicBoardArticleView.ISummary> {
    try {
      return await patchEconomicBoardAdministratorAnalytics({
        administrator,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
