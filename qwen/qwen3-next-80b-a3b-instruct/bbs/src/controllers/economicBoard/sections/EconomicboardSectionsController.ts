import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEconomicBoardSection } from "../../../api/structures/IEconomicBoardSection";
import { IPageIEconomicBoardSection } from "../../../api/structures/IPageIEconomicBoardSection";
import { getEconomicBoardSectionsSectionId } from "../../../providers/getEconomicBoardSectionsSectionId";
import { patchEconomicBoardSections } from "../../../providers/patchEconomicBoardSections";

@Controller("/economicBoard/sections")
export class EconomicboardSectionsController {
  /**
   * Retrieve a paginated list of all active sections on the economic discussion board.
   *
   * This endpoint returns a comprehensive listing of sections that are currently available for article categorization. The system does not support soft deletion; sections are either created and active, or they are deleted and removed from the system entirely. Only sections that exist in the database are returned.
   *
   * Each section includes its unique identifier, name, description, creation timestamp, and update timestamp. This supports section discovery, selection for article creation, and administration overview.
   *
   * The response is paginated to ensure performance with large datasets, supporting configurable page sizes and sorting by name or creation date. For system performance, only section-level metadata is returned — no nested article or comment data is included.
   *
   * To retrieve articles within a specific section, use GET /economicBoard/articles?section_id={sectionId} after obtaining section identifiers from this endpoint.
   *
   * @param connection
   * @param body Pagination, sorting, and filtering parameters for section list retrieval
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query economic_board_sections table with pagination and optional filtering.
   * 1. Filter by status: WHERE deleted_at IS NULL (active sections only)
   * 2. Support sorting by name (ASC/DESC) or created_at (ASC/DESC)
   * 3. Implement cursor-based pagination with limit parameter (default 10, max 50)
   * 4. Return total count and totalPages for pagination UI
   * 5. Do not include section's associated articles or comments (as per schema)
   * 6. Never return soft-deleted sections (deleted_at IS NOT NULL)
   * 7. Ensure case-insensitive name search if search term provided
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEconomicBoardSection.IRequest,
  ): Promise<IPageIEconomicBoardSection.ISummary> {
    try {
      return await patchEconomicBoardSections({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific section by its unique ID. This endpoint returns the section's name, description, and timestamps for users browsing available content categories. Only active sections (where deleted_at is null) are returned. Attempts to access deleted sections will result in 404 Not Found.
   *
   * This operation is publicly accessible. Authenticated users receive the same response as unauthenticated users since section metadata is non-sensitive. This endpoint supports the homepage section list and linking to articles within a section.
   *
   * The operation does not return any article counts or associated content — those are available via separate endpoints: GET /articles?section_id={sectionId} for articles and GET /sections for bulk listing.
   *
   * If the requested section does not exist or has been deleted, a 404 Not Found error is returned without revealing the reason to prevent enumeration attacks.
   *
   * @param connection
   * @param sectionId Unique identifier of the section to retrieve. Must be a valid UUID.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query economic_board_sections table with WHERE id = sectionId AND deleted_at IS NULL. Return only name, description, created_at, and updated_at fields. Use Prisma's unique index on id for fast lookup. Return 404 if no record found (even if record exists with deleted_at set). Ensure all date fields are returned as ISO 8601 strings. Apply query-level caching for high-traffic section reads.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sectionId")
  public async at(
    @TypedParam("sectionId")
    sectionId: string,
  ): Promise<IEconomicBoardSection> {
    try {
      return await getEconomicBoardSectionsSectionId({
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
