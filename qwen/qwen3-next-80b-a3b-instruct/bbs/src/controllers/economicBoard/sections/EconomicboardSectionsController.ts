import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicBoardSection } from "../../../api/structures/IEconomicBoardSection";
import { IPageIEconomicBoardSection } from "../../../api/structures/IPageIEconomicBoardSection";
import { getEconomicBoardSectionsSectionId } from "../../../providers/getEconomicBoardSectionsSectionId";
import { patchEconomicBoardSections } from "../../../providers/patchEconomicBoardSections";

@Controller("/economicBoard/sections")
export class EconomicboardSectionsController {
  /**
   * Retrieve a paginated list of active economic board sections.
   *
   * This endpoint returns a list of all active sections on the platform, including their key identifying information such as section name, description, and creation timestamp. Users may apply filtering and sorting criteria to navigate sections efficiently. Only sections with status 'active' are returned; sections with status 'deleted' are excluded from results, regardless of audit trail entries.
   *
   * The result set is paginated with configurable page size, and results can be sorted by creation timestamp (most recent first or oldest first). The section list serves as the primary navigation mechanism for users to access articles organized by thematic categories (e.g., Politics, Economy, Current Affairs). This operation does not return full article counts per section to optimize performance — section-specific article counts may be queried separately using other endpoints.
   *
   * This endpoint interacts with the economic_board_sections table and depends on its status field to enforce active section visibility. Deleted sections are governed by the economic_board_section_deletions audit table, but deleted sections are excluded from this endpoint's results based on their status field value.
   *
   * No dependency on other API endpoints is required for this operation — it functions as a standalone list retrieval.
   *
   * @param connection
   * @param body Pagination and sort criteria for section list.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query economic_board_sections where status = 'active' and deleted_at IS NULL.
   * Apply pagination with limit and offset.
   * Sort results by created_at DESC for 'newest' or ASC for 'oldest'.
   * Return only fields: id, name, description, created_at.
   * Exclude all deleted sections (even if in deletion audit log).
   * Return cursor-based pagination metadata including total count, current page, and page size.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEconomicBoardSection.IRequest,
  ): Promise<IPageIEconomicBoardSection.ISummary> {
    try {
      return await patchEconomicBoardSections({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific section on the economic discussion board.
   *
   * This operation returns complete metadata for a single section identified by its unique identifier. The section information includes its name, description, creation and update timestamps, deletion status, and current active status. This endpoint is essential for users who need to understand the context of articles within a specific section or verify section details before interacting with its content.
   *
   * The response includes only publicly accessible section information. No sensitive data, internal identifiers, or private metadata are exposed. This operation does not return articles within the section—the article list is available through a separate endpoint. The section information returned is independent of user authentication status, meaning both authenticated users and anonymous visitors can read section details.
   *
   * If the requested section has been logically deleted (marked with a deleted_at timestamp), this endpoint will return HTTP 404 Not Found to prevent access to deleted content while preserving audit trails.
   *
   * @param connection
   * @param sectionId The unique identifier of the section to retrieve. This is the primary key in the economic_board_sections table.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the economic_board_sections table by id parameter. Return section record with id, name, description, created_at, updated_at, deleted_at, and status fields. Ensure soft-deleted sections (deleted_at not null) return HTTP 404. Validate sectionId is a valid UUID format before database query.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sectionId")
  public async at(
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
  ): Promise<IEconomicBoardSection> {
    try {
      return await getEconomicBoardSectionsSectionId({
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
