import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchEconomicBoardSearch } from "../../../providers/patchEconomicBoardSearch";

import { IPageIEconomicBoardPost } from "../../../api/structures/IPageIEconomicBoardPost";
import { IEconomicBoardSearchMetadata } from "../../../api/structures/IEconomicBoardSearchMetadata";

@Controller("/economicBoard/search")
export class EconomicboardController {
  /**
   * Perform a full-text search across economic board posts with advanced
   * filtering capabilities.
   *
   * This operation enables users to discover relevant discussions by querying
   * multiple indexed data sources simultaneously: economic_board_search_index
   * for full-text token matching, economic_board_search_metadata for filtering
   * by post status and creation date, and economic_board_search_tags for
   * category-based topic filtering.
   *
   * The search supports complex and flexible querying, allowing users to
   * combine keyword matches with filters for status (published, pending,
   * rejected), publication time range, and specific economic topics. No
   * separate endpoint for simple keyword searches is needed as this single
   * endpoint handles all search scenarios, from basic text matching to
   * sophisticated combinations with filters.
   *
   * Results are returned in a paginated format optimized for display, with
   * summary information including post titles, statuses, and topic tags. The
   * operation avoids returning complete post content to maintain performance
   * and reduce bandwidth usage. Full content can be retrieved individually
   * using the GET /posts/{postId} endpoint.
   *
   * The search functionality is crucial for platform usability, allowing
   * citizens to find relevant economic discussions among thousands of posts.
   * Performance is prioritized through denormalized search structures, ensuring
   * results are returned under 2 seconds even with complex queries.
   *
   * This operation does not allow direct access to moderation records or
   * user-specific data, maintaining privacy and appropriate access boundaries.
   *
   * Related operations include retrieving a specific post (GET /posts/{postId})
   * or retrieving all posts by a citizen (GET /citizens/{citizenId}/posts).
   *
   * @param connection
   * @param body Search parameters including keyword query, status filters, and
   *   topic tags for refining search results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @TypedBody()
    body: IEconomicBoardSearchMetadata.IRequest,
  ): Promise<IPageIEconomicBoardPost.ISummary> {
    try {
      return await patchEconomicBoardSearch({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
