import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { deleteEconomicBoardModeratorPostsPostId } from "../../../../providers/deleteEconomicBoardModeratorPostsPostId";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";

@Controller("/economicBoard/moderator/posts/:postId")
export class EconomicboardModeratorPostsController {
  /**
   * Permanently delete a discussion post (hard delete).
   *
   * Permanently removes a discussion post from the economic board system. This
   * operation is exclusively available to moderators and results in the
   * complete and irreversible deletion of the post record from the database.
   *
   * Unlike typical system behavior where soft deletes (setting deleted_at) are
   * preferred for audit compliance, this operation performs a hard delete per
   * explicit business rule: moderation authority permits immediate and
   * permanent removal of content. All associated child records, including
   * attachments and revisions, are also immediately purged from the system. No
   * audit log is created for this deletion in this table — audit trails are
   * captured in the moderation_actions table separately.
   *
   * Security considerations require that only authenticated moderators can
   * invoke this endpoint. The system enforces authorization by validating the
   * JWT token's role field and ensuring the user has moderator privileges. For
   * compliance, all deletion events must be logged in the
   * economic_board_moderation_actions table via the backend service layer.
   *
   * This is the only operation in the system that performs hard deletion. All
   * other entities (e.g., attachments, comments) use soft delete. This
   * operation is reserved for extreme cases where the post contains illegal
   * content, threats, or severe policy violations that require immediate
   * eradication from the system.
   *
   * Related operations: GET /posts/{postId} (retrieve a post before deletion),
   * DELETE /posts/{postId}/attachments (remove individual attachments).
   *
   * @param connection
   * @param postId Unique identifier of the post to be permanently deleted. Must
   *   be a valid UUID of an existing post.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("postId")
    postId: string,
  ): Promise<void> {
    try {
      return await deleteEconomicBoardModeratorPostsPostId({
        moderator,
        postId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
