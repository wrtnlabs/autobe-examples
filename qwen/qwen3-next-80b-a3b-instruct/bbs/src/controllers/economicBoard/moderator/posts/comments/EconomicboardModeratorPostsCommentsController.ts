@Controller("/economicBoard/moderator/posts/:postId/comments/:commentId")
export class EconomicboardModeratorPostsCommentsController {
  /**
   * Delete a specific comment from a discussion post.
   *
   * Permanently deletes a specific comment from a discussion post. This
   * operation is irreversible and immediately hides the comment from public
   * view by setting the deleted_at timestamp in the economic_board_comments
   * table.
   *
   * Security and permissions: Only the citizen who created the comment or a
   * moderator can delete it. The system verifies ownership using the JWT
   * authentication token to match the comment's citizen_id field. Moderators
   * may delete any comment regardless of ownership, subject to audit logging.
   *
   * The deletion is soft (tombstone) using the deleted_at field as defined in
   * the Prisma schema. The comment record remains in the database for audit
   * compliance but is filtered out from all public queries. The comment's
   * parent post_id reference is preserved to maintain thread integrity and
   * historical context.
   *
   * This operation does not affect other comments or the parent post. Only the
   * comment marked by comment_id is deleted.
   *
   * Related operations:
   *
   * - GET /comments: To retrieve remaining comments on the same post after
   *   deletion
   * - PATCH /posts/{postId}/comments: To retrieve a paginated list of the post's
   *   comments
   *
   * Error handling: Returns 404 if the comment_id does not exist, or if the
   * comment is already deleted.
   *
   * @param connection
   * @param postId Unique identifier of the published post containing this
   *   comment. Must reference a record in economic_board_posts with status
   *   'published'.
   * @param commentId Unique identifier of the comment to be deleted. Must be a
   *   valid UUID and exist in economic_board_comments.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("postId")
    postId: string,
    @TypedParam("commentId")
    commentId: string,
  ): Promise<void> {
    try {
      return await deleteEconomicBoardModeratorPostsPostIdCommentsCommentId({
        moderator,
        postId,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
