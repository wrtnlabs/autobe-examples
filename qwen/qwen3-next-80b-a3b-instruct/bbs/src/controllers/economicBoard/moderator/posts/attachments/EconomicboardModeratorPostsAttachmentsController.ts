import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { postEconomicBoardModeratorPostsPostIdAttachments } from "../../../../../providers/postEconomicBoardModeratorPostsPostIdAttachments";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { deleteEconomicBoardModeratorPostsPostIdAttachmentsAttachmentId } from "../../../../../providers/deleteEconomicBoardModeratorPostsPostIdAttachmentsAttachmentId";

import { IEconomicBoardAttachment } from "../../../../../api/structures/IEconomicBoardAttachment";

@Controller("/economicBoard/moderator/posts/:postId/attachments")
export class EconomicboardModeratorPostsAttachmentsController {
  /**
   * Upload a file attachment to a discussion post.
   *
   * Uploads a file attachment to a specified discussion post. This operation
   * accepts multipart-form upload data containing the file and allows the
   * client to associate metadata with the uploaded file.
   *
   * The attachment record is created in the economic_board_attachments table
   * immediately upon receipt. The system validates the file's MIME type, size,
   * format, and sanitizes the filename before storage. Only approved formats
   * (image/jpeg, image/png, image/gif, image/webp, application/pdf, text/plain,
   * application/vnd.openxmlformats-officedocument.wordprocessingml.document,
   * application/vnd.openxmlformats-officedocument.spreadsheetml.sheet) are
   * permitted, and files larger than 10MB (10485760 bytes) are rejected.
   *
   * Attachments persist independently of their parent post — even if the post
   * is deleted permanently (hard delete), the attachment metadata remains to
   * satisfy audit and legal compliance requirements.
   *
   * This operation is available to both citizens and moderators, as any user
   * who can create a post may attach supporting content. Owner authorization is
   * enforced via the JWT token — the user must be authenticated and the post
   * must exist and belong to the same citizen or be visible to the moderator.
   *
   * The system returns a reference to the new attachment record with its
   * sanitized file name and secure storage URI. The file is not immediately
   * available for download until processing is complete and its status
   * transitions from 'uploaded' to 'processed'.
   *
   * Related operations: GET /posts/{postId}/attachments (retrieve all
   * attachments for a post), DELETE /posts/{postId}/attachments/{attachmentId}
   * (remove specific attachment).
   *
   * @param connection
   * @param postId Unique identifier of the post to which the attachment will be
   *   linked. Must be a valid UUID of an existing post.
   * @param body Form data containing the uploaded file and metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("postId")
    postId: string,
    @TypedBody()
    body: IEconomicBoardAttachment.ICreate,
  ): Promise<IEconomicBoardAttachment> {
    try {
      return await postEconomicBoardModeratorPostsPostIdAttachments({
        moderator,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove an attachment from visibility (soft delete) by a
   * moderator.
   *
   * Permanently remove an attachment from visibility by marking it as deleted.
   *
   * This operation performs a soft delete on a specific attachment record,
   * setting the deleted_at timestamp to the current UTC time. The attachment
   * metadata is retained in the database for audit, compliance, and historical
   * reference purposes. The file itself is not removed from object storage, and
   * the storage_path URI remains valid for system-level archival purposes.
   *
   * Access to this operation is restricted to authenticated moderator accounts.
   * The requester must have moderator privileges verified via JWT token. This
   * protection prevents citizens from deleting attachments they uploaded,
   * enforcing moderation authority.
   *
   * The operation fails if the attachment's parent post has already been
   * deleted (deleted_at is not null). This is because attachments cannot be
   * selectively deleted when their parent post has been removed—moderation
   * actions must apply to the entire post context, not individual attachments.
   *
   * After deletion, the attachment no longer appears in public attachment lists
   * or attachment previews. However, it remains discoverable in moderator audit
   * logs. The attachment status transitions from 'uploaded', 'processed', or
   * 'quarantined' to 'deleted'.
   *
   * Description excerpt from economic_board_attachments: 'Attachment data is
   * persistent even if the parent post is deleted, as required for compliance.'
   * This operation enforces that compliance by preserving records while
   * restricting public visibility.
   *
   * Related operations: GET /posts/{postId}/attachments/{attachmentId} to check
   * attachment status before deletion, DELETE /posts/{postId} to delete entire
   * post (which affects all attached files).
   *
   * @param connection
   * @param postId Unique identifier of the parent discussion post, used to
   *   validate post status before processing soft deletion. Must reference an
   *   existing economic_board_posts.id.
   * @param attachmentId Unique identifier of the attachment record to
   *   soft-delete, referencing economic_board_attachments.id.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":attachmentId")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("postId")
    postId: string,
    @TypedParam("attachmentId")
    attachmentId: string,
  ): Promise<void> {
    try {
      return await deleteEconomicBoardModeratorPostsPostIdAttachmentsAttachmentId(
        {
          moderator,
          postId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
