import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchEconomicBoardModeratorCitizens } from "../../../../providers/patchEconomicBoardModeratorCitizens";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { getEconomicBoardModeratorCitizensCitizenId } from "../../../../providers/getEconomicBoardModeratorCitizensCitizenId";

import { IPageIEconomicBoardCitizen } from "../../../../api/structures/IPageIEconomicBoardCitizen";
import { IEconomicBoardCitizen } from "../../../../api/structures/IEconomicBoardCitizen";

@Controller("/economicBoard/moderator/citizens")
export class EconomicboardModeratorCitizensController {
  /**
   * Retrieve a filtered and paginated list of economic board citizens from the
   * system. This operation provides advanced search capabilities for finding
   * citizens based on multiple criteria including partial email matching,
   * account status filtering, and registration date ranges.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Citizens can sort by registration date, last
   * update, or email address in ascending or descending order.
   *
   * Security considerations include rate limiting for search operations and
   * appropriate filtering of sensitive citizen information based on the
   * requesting user's authorization level. Only users with appropriate
   * permissions can access detailed citizen information, while basic citizen
   * lists may be available to authenticated users.
   *
   * This operation integrates with the economic_board_citizens table as defined
   * in the Prisma schema, incorporating all available citizen fields and
   * relationships. The response includes citizen summary information optimized
   * for list displays, with options to include additional details based on
   * authorization level.
   *
   * This operation is essential for administrative oversight, user management,
   * and support operations where moderators need to locate specific citizen
   * accounts across the platform.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for citizen filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IEconomicBoardCitizen.IRequest,
  ): Promise<IPageIEconomicBoardCitizen.ISummary> {
    try {
      return await patchEconomicBoardModeratorCitizens({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific economic board citizen by
   * their unique identifier.
   *
   * This operation fetches the complete citizen record from the
   * economic_board_citizens table, including all associated metadata such as
   * email address, account status, creation and update timestamps, and deletion
   * status. The citizen's identity and account status are crucial for
   * comprehensive administrative review, account management, and support
   * investigations.
   *
   * Security considerations are paramount - this operation requires
   * moderator-level authorization as it returns sensitive account details that
   * could be misused if accessed by unauthorized users. The operation strictly
   * enforces authentication and authorization checks before returning any
   * data.
   *
   * The response includes comprehensive data from the citizen table that is not
   * suitable for general display, making this endpoint reserved exclusively for
   * administrative personnel with appropriate privileges.
   *
   * This operation complements the search functionality provided by the
   * /citizens endpoint by providing a direct, high-detail view of individual
   * citizen records when their unique identifier is known.
   *
   * @param connection
   * @param citizenId Unique identifier of the target citizen account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":citizenId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("citizenId")
    citizenId: string,
  ): Promise<IEconomicBoardCitizen> {
    try {
      return await getEconomicBoardModeratorCitizensCitizenId({
        moderator,
        citizenId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
