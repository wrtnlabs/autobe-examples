import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getEconomicBoardModeratorSettingsConfig } from "../../../../../providers/getEconomicBoardModeratorSettingsConfig";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { getEconomicBoardModeratorSettingsConfigConfigKey } from "../../../../../providers/getEconomicBoardModeratorSettingsConfigConfigKey";

import { IEconomicBoardSystemConfig } from "../../../../../api/structures/IEconomicBoardSystemConfig";

@Controller("/economicBoard/moderator/settings/config")
export class EconomicboardModeratorSettingsConfigController {
  /**
   * Retrieve all system configuration settings from the
   * economic_board_system_config table.
   *
   * This operation returns a comprehensive set of key-value pairs that define
   * the behavior of the economic board platform. Configuration settings include
   * parameters like maximum comment length, edit window duration, rate limiting
   * thresholds, and feature toggles that control the platform's functionality.
   *
   * The configuration data is stored in a single table with a unique key
   * constraint on the key field, ensuring each configuration parameter is
   * defined exactly once. Settings are implemented as JSON-serialized strings
   * to accommodate various data types including strings, numbers, booleans, and
   * complex JSON objects.
   *
   * Security: This endpoint is restricted to moderator actors only, as system
   * configuration changes can significantly impact platform functionality and
   * user experiences. Unauthorized access could lead to denial-of-service or
   * unintended feature changes.
   *
   * The configuration system follows a master-slave pattern where the
   * economic_board_system_config table serves as the single source of truth.
   * Changes to configuration are applied through administrative interfaces, and
   * the application reads these settings on startup and periodically refreshes
   * its cache.
   *
   * Related operations: get system configuration by key (GET
   * /settings/config/{configKey}) allows retrieval of individual configuration
   * parameters.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
  ): Promise<IEconomicBoardSystemConfig> {
    try {
      return await getEconomicBoardModeratorSettingsConfig({
        moderator,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific system configuration setting by its unique key from the
   * economic_board_system_config table.
   *
   * This operation allows moderators to view individual configuration
   * parameters that control the platform's behavior. Valid configuration keys
   * include "comment_max_length", "edit_window_hours", "rate_limit_per_minute",
   * and other system-specific parameters defined in the
   * economic_board_system_config table.
   *
   * The operation performs a direct lookup on the unique key field in the
   * economic_board_system_config table, which is constrained to be unique. If
   * the requested configuration key does not exist, the system returns a 404
   * Not Found error.
   *
   * The returned value is a JSON-serialized string that contains the actual
   * configuration value, which may be a simple string, number, boolean, or a
   * complex JSON object depending on the configuration parameter.
   *
   * Security: This endpoint requires moderator authorization due to the
   * sensitive nature of system configuration data. Exposing configuration
   * details could provide attackers with insights into platform limitations and
   * potential attack vectors.
   *
   * This operation complements the full configuration retrieval (GET
   * /settings/config) by allowing targeted access to specific parameters, which
   * is useful for debugging, verification, and monitoring specific
   * configuration values without transferring unnecessary data.
   *
   * @param connection
   * @param configKey Unique configuration key name (e.g., "comment_max_length",
   *   "edit_window_hours") that identifies the specific setting to retrieve
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":configKey")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("configKey")
    configKey: string,
  ): Promise<IEconomicBoardSystemConfig> {
    try {
      return await getEconomicBoardModeratorSettingsConfigConfigKey({
        moderator,
        configKey,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
