import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getEconomicBoardModeratorSettingsContentFlags } from "../../../../../providers/getEconomicBoardModeratorSettingsContentFlags";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { getEconomicBoardModeratorSettingsContentFlagsFlagCode } from "../../../../../providers/getEconomicBoardModeratorSettingsContentFlagsFlagCode";

import { IPageIEconomicBoardContentFlag } from "../../../../../api/structures/IPageIEconomicBoardContentFlag";
import { IEconomicBoardContentFlag } from "../../../../../api/structures/IEconomicBoardContentFlag";

@Controller("/economicBoard/moderator/settings/contentFlags")
export class EconomicboardModeratorSettingsContentflagsController {
  /**
   * Retrieve all content flag configuration categories.
   *
   * Retrieve a comprehensive list of all content flag categories defined in the
   * economic_board_content_flags table.
   *
   * This endpoint returns a paginated, sorted list of all configured flag types
   * that can be applied to posts by automated systems or manual moderation.
   * Each flag contains a human-readable name, machine-readable code, severity
   * level, and configuration flags for automated actions.
   *
   * The response includes the complete set of flag definitions, allowing system
   * administrators to audit moderation criteria, configure detection rules, and
   * verify flag settings. The list is sorted by flag code for consistent
   * display and is paginated to support large-scale deployments.
   *
   * This operation is critical for content moderation system configuration and
   * must be accessible to authorized users. The flags are read-only
   * configuration data protected from modification via this API. Any changes to
   * flags must be made through administrative UIs or direct database updates.
   *
   * This endpoint directly references the economic_board_content_flags table's
   * fields: name, code, severity, description, auto_flag_enabled, and
   * auto_reject_enabled. No additional fields are included beyond those defined
   * in the schema.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
  ): Promise<IPageIEconomicBoardContentFlag> {
    try {
      return await getEconomicBoardModeratorSettingsContentFlags({
        moderator,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific content flag by its code identifier.
   *
   * Retrieve a specific content flag category by its machine-readable code
   * identifier from the economic_board_content_flags table.
   *
   * This operation allows system administrators or integrated moderation
   * systems to retrieve detailed configuration information for a single flag
   * category by its unique code (e.g., "hate_speech", "doxxing"). The response
   * includes all fields defined in the economic_board_content_flags table:
   * name, code, severity, description, auto_flag_enabled, and
   * auto_reject_enabled.
   *
   * The flagCode parameter is a unique machine-readable identifier that matches
   * the code field in the economic_board_content_flags table. This design
   * ensures integration systems can reliably reference flags without relying on
   * display names that may change. The path parameter uses the camelCase
   * identifier flagCode to match the Prisma schema field name.
   *
   * This endpoint is optimized for integration with automated moderation
   * systems that need precise, code-based flag references rather than
   * human-readable names. It is restricted to access by moderators to enable
   * administrative oversight while preventing user exposure to system
   * configuration. No external dependencies or other API operations are
   * required to use this endpoint.
   *
   * @param connection
   * @param flagCode Unique machine-readable code identifier for the target
   *   content flag (e.g., "hate_speech", "doxxing"). Matches the code field in
   *   economic_board_content_flags. Must be exact match.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":flagCode")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("flagCode")
    flagCode: string,
  ): Promise<IEconomicBoardContentFlag> {
    try {
      return await getEconomicBoardModeratorSettingsContentFlagsFlagCode({
        moderator,
        flagCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
