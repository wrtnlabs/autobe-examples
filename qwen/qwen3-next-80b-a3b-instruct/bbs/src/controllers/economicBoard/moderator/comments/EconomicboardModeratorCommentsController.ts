import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { deleteEconomicBoardModeratorCommentsCommentId } from "../../../../providers/deleteEconomicBoardModeratorCommentsCommentId";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";

@Controller("/economicBoard/moderator/comments/:commentId")
export class EconomicboardModeratorCommentsController {
  /**
   * Permanently delete a comment from the system.
   *
   * Permanently remove a specific comment from the system. This operation
   * performs a hard delete of a comment identified by its unique commentId,
   * removing the record entirely from the database with no possibility of
   * recovery.
   *
   * Security considerations are critical: this operation requires the user to
   * have moderator privileges, as only authorized moderators can permanently
   * delete comments. The operation does not change the comment's status flag
   * but directly deletes the record from the database, which is consistent with
   * the platform's policy for severe violations where audit trails must be
   * maintained but content must be completely erased.
   *
   * The comment's deletion is recorded in the economic_board_moderation_actions
   * system as a deletion action, where the moderator and targeted citizen are
   * logged for audit purposes. This operation complements the moderation action
   * logging system by providing the actual data removal function.
   *
   * This deletion operation is irreversible and should be used with extreme
   * caution. It is not a soft delete - the comment cannot be restored once
   * deleted. System logs preserve the timing and actor of deletion for
   * compliance and forensic purposes. Related comments in reply threads are
   * left intact as children of the deleted post remains visible with removed
   * indicator.
   *
   * @param connection
   * @param commentId Unique identifier of the comment to be permanently deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("commentId")
    commentId: string,
  ): Promise<void> {
    try {
      return await deleteEconomicBoardModeratorCommentsCommentId({
        moderator,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
