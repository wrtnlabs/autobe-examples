import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { getEconomicBoardModeratorModeratorsModeratorId } from "../../../../providers/getEconomicBoardModeratorModeratorsModeratorId";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { patchEconomicBoardModeratorModerators } from "../../../../providers/patchEconomicBoardModeratorModerators";

import { IEconomicBoardModerator } from "../../../../api/structures/IEconomicBoardModerator";
import { IPageIEconomicBoardModerator } from "../../../../api/structures/IPageIEconomicBoardModerator";

@Controller("/economicBoard/moderator/moderators")
export class EconomicboardModeratorModeratorsController {
  /**
   * Retrieve detailed information about a specific active moderator.
   *
   * Retrieve the complete profile details of a specific active moderator
   * account from the economic_board_moderators table.
   *
   * This operation returns detailed information about a single moderator
   * identified by their unique ID. It returns all non-sensitive fields
   * including email, creation date, update date, and current status
   * information. Password hash and other sensitive authentication details are
   * explicitly excluded from the response for security reasons.
   *
   * Security considerations require that only authenticated administrators may
   * access this endpoint. The operation validates that the requested moderator
   * account exists and is active (not deactivated). Requests for non-existent
   * or deactivated moderator accounts return a 404 error.
   *
   * This operation is intended for administrative use to review individual
   * moderator profiles, audit activity history, or provide support for
   * moderator account inquiries. It complements the GET /moderators operation
   * by providing detailed information about an individual moderator.
   *
   * Related operations: PATCH /moderators (lists multiple moderators with
   * summary information).
   *
   * @param connection
   * @param moderatorId Unique identifier of the target moderator account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":moderatorId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("moderatorId")
    moderatorId: string,
  ): Promise<IEconomicBoardModerator> {
    try {
      return await getEconomicBoardModeratorModeratorsModeratorId({
        moderator,
        moderatorId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of active moderators.
   *
   * Retrieve a filtered and paginated list of active moderator accounts from
   * the economic_board_moderators table.
   *
   * This operation allows administrators to browse and manage the community of
   * moderators who oversee economic and political discussion content. It
   * returns a list of moderator accounts with active status, excluding those
   * that have been deactivated.
   *
   * The operation supports advanced filtering by email address through partial
   * matching, and allows sorting by created_at or updated_at timestamps in
   * ascending or descending order. Pagination is implemented with configurable
   * page size and cursor-based navigation to efficiently handle large
   * datasets.
   *
   * Security considerations include that only authenticated administrators may
   * access this endpoint. The operation does not return sensitive information
   * such as password_hash, ensuring compliance with data protection
   * principles.
   *
   * Modifying moderator status through this endpoint is not permitted - status
   * changes must be made through dedicated administrative controls. This
   * operation is read-only and used exclusively for managerial oversight.
   *
   * Related operations: GET /moderators/{moderatorId} (retrieves single
   * moderator details).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for moderator listing
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IEconomicBoardModerator.IRequest,
  ): Promise<IPageIEconomicBoardModerator.ISummary> {
    try {
      return await patchEconomicBoardModeratorModerators({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
