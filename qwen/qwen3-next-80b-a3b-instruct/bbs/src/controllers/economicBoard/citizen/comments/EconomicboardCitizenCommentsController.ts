import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { putEconomicBoardCitizenCommentsCommentId } from "../../../../providers/putEconomicBoardCitizenCommentsCommentId";
import { CitizenAuth } from "../../../../decorators/CitizenAuth";
import { CitizenPayload } from "../../../../decorators/payload/CitizenPayload";
import { deleteEconomicBoardCitizenCommentsCommentId } from "../../../../providers/deleteEconomicBoardCitizenCommentsCommentId";

import { IEconomicBoardComment } from "../../../../api/structures/IEconomicBoardComment";

@Controller("/economicBoard/citizen/comments/:commentId")
export class EconomicboardCitizenCommentsController {
  /**
   * Update the content of a comment within its 24-hour editing window.
   *
   * Update the content of an economic board comment within the 24-hour editing
   * window. This operation allows the original author to correct typographical
   * errors, enhance clarity, or correct factual inaccuracies in their comment.
   *
   * The update is permitted only if the comment was created less than 24 hours
   * ago and has not been deleted. Only the citizen who originally created the
   * comment may perform this update, verified through JWT authentication and
   * citizen_id matching. The editor cannot change the related post_id,
   * parent_comment_id, or citizen_id.
   *
   * Only the body field may be modified. Other fields such as created_at,
   * updated_at, status, and moderator_deleted_id are system-managed and will
   * not be accepted in the request body. For comment updates, only a plain text
   * string with maximum 500 characters is permitted, matching the constraint in
   * the schema.
   *
   * If the comment is published, the edit is immediately visible to all users.
   * If the comment is deleted, updating it in the 24-hour window will not
   * restore visibility, but will update the content field for moderator review
   * and audit trail purposes. The updated_at field is automatically set to the
   * current UTC timestamp with no user control.
   *
   * This operation directly maps to the economic_board_comments Prisma table
   * and respects its constraints, particularly the 500-character limit on the
   * body field and the requirement that citizen_id must match the authenticated
   * user. After 24 hours, the comment becomes immutable and this operation
   * returns 403 Forbidden.
   *
   * Related operations: Individual comments may be retired through moderator
   * deletion (DELETE), but this endpoint only supports content edits, not
   * moderation actions. Retrieval of the updated comment uses GET
   * /comments/{commentId}.
   *
   * @param connection
   * @param commentId Unique identifier of the comment to update. Matches the
   *   UUID primary key in the economic_board_comments table.
   * @param body The new body content for the comment. Maximum 500 characters.
   *   Must be a string with no HTML or formatting. Only the 'body' property is
   *   accepted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("commentId")
    commentId: string,
    @TypedBody()
    body: IEconomicBoardComment.IUpdate,
  ): Promise<IEconomicBoardComment> {
    try {
      return await putEconomicBoardCitizenCommentsCommentId({
        citizen,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a comment from the economic board.
   *
   * This operation removes a user's comment from public view by setting its
   * deleted_at timestamp. Once deleted, the comment is no longer visible in
   * comment threads or search results. The deleted comment is not physically
   * removed from the database, preserving audit integrity as required by
   * platform policy.
   *
   * Security: Users can delete their own comments at any time without
   * restriction. Moderators can delete any comment based on content policy
   * violations. The operation verifies that the requesting user is either the
   * author of the comment or a moderator with appropriate permissions.
   *
   * The comment must exist and have status 'published'. Attempting to delete a
   * comment that is already deleted or never published will return a 404 error.
   * When a comment is deleted, it is replaced in the UI with a placeholder
   * indicating "[Comment deleted]" and the original content is no longer
   * accessible.
   *
   * Related operations: GET /comments/{commentId} to retrieve a comment before
   * deletion, POST /comments to create new comments.
   *
   * Note: Unlike post deletion, comments do not trigger cascading deletions of
   * replies. Child replies remain visible with their content intact but are
   * marked as orphaned.
   *
   * This deletion is permanent from a user perspective and cannot be undone by
   * the user or moderator.
   *
   * @param connection
   * @param commentId Unique identifier of the comment to delete, referenced
   *   from economic_board_comments.id
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("commentId")
    commentId: string,
  ): Promise<void> {
    try {
      return await deleteEconomicBoardCitizenCommentsCommentId({
        citizen,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
