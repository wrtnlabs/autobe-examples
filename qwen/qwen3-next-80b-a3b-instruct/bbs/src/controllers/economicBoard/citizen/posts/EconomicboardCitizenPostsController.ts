import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postEconomicBoardCitizenPosts } from "../../../../providers/postEconomicBoardCitizenPosts";
import { CitizenAuth } from "../../../../decorators/CitizenAuth";
import { CitizenPayload } from "../../../../decorators/payload/CitizenPayload";
import { putEconomicBoardCitizenPostsPostId } from "../../../../providers/putEconomicBoardCitizenPostsPostId";

import { IEconomicBoardPost } from "../../../../api/structures/IEconomicBoardPost";

@Controller("/economicBoard/citizen/posts")
export class EconomicboardCitizenPostsController {
  /**
   * Submit a new discussion post for moderator review.
   *
   * Allows authenticated citizens to submit a new discussion post to the
   * economic board with title and content. Upon submission, the post is
   * immediately placed in a 'pending' state and is never visible to other
   * citizens until a moderator approves it.
   *
   * The post must have a title (up to 10,000 characters) and body (up to 10,000
   * characters), both of which are required. The system validates that the
   * content does not contain prohibited material such as hate speech, threats,
   * or personal information, as defined in the business rules.
   *
   * The citizen's identity is automatically captured from the JWT token and
   * stored as the citizen_id in the economic_board_posts table. The post is
   * flagged as 'pending' status with created_at timestamp set to the current
   * UTC time.
   *
   * File attachments (up to five, each ≤10MB) are uploaded via separate
   * endpoints and recorded in economic_board_attachment_logs that reference
   * this post's ID. The system accepts only permitted formats: JPG, PNG, GIF,
   * WEBP for images; and PDF, TXT, DOCX, XLSX for documents. Executable files
   * are rejected.
   *
   * This operation does not make the post visible; it only queues it for
   * review. The post will not appear in search results, category filters, or
   * public feeds until explicitly approved by a moderator.
   *
   * Related operations: POST /attachments (for file uploads), PATCH /posts (for
   * search, which will return only published posts), PUT /posts/{postId} (for
   * editing within 24 hours). The moderation workflow requires accessing the
   * pending queue via moderator-specific endpoints.
   *
   * Security: Only authenticated citizens can create posts. Moderators can
   * create posts if they have citizen privileges. Guest users are rejected with
   * 401 status.
   *
   * @param connection
   * @param body Structured data for creating a discussion post with title and
   *   content
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedBody()
    body: IEconomicBoardPost.ICreate,
  ): Promise<IEconomicBoardPost> {
    try {
      return await postEconomicBoardCitizenPosts({
        citizen,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Edit your own post within 24 hours of creation.
   *
   * Permits a citizen to update the title or body of their own post, but only
   * if the edit occurs within 24 hours of the original post submission. This
   * operation does not modify the main economic_board_posts record; instead, it
   * creates a new immutable revision in the economic_board_post_revisions table
   * to preserve the original content and establish a clear edit history.
   *
   * The citizen must be the same user who created the post (verified via JWT).
   * The revised title and body must not exceed 10,000 characters each. The
   * system rejects the request if the 24-hour window has expired, even by one
   * second.
   *
   * The association between the revision and the original post is preserved via
   * the post_id foreign key. The edited_at timestamp is automatically set to
   * the current system time (UTC). All edits are logged and later displayed in
   * the UI as "Edited [timestamp]" beneath the post.
   *
   * This operation cannot change the post's status
   * (pending/published/rejected), cannot assign or remove categories, and
   * cannot affect the visibility of the post. The post's visibility state
   * depends entirely on moderator approval or deletion.
   *
   * After the 24-hour deadline, the endpoint returns a 403 Forbidden status,
   * preventing any further edits from the citizen or from any other user,
   * including moderators.
   *
   * This operation respects the core business rule that ensures content
   * integrity by freezing the original post and storing edits separately. This
   * design prevents post-history tampering and supports moderation
   * transparency.
   *
   * Related operations: POST /posts (creation), GET /posts/{postId} (retrieve),
   * PATCH /posts (search). Revisions are not directly accessible via client
   * API; only the final view with "edited" label is exposed.
   *
   * @param connection
   * @param postId Unique identifier of the post to be edited. The post must
   *   exist and be owned by the authenticated citizen.
   * @param body Fields to update in the citizen's post, including title and
   *   body
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":postId")
  public async update(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("postId")
    postId: string,
    @TypedBody()
    body: IEconomicBoardPost.IUpdate,
  ): Promise<IEconomicBoardPost> {
    try {
      return await putEconomicBoardCitizenPostsPostId({
        citizen,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
