import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postEconomicBoardCitizenPostsPostIdComments } from "../../../../../providers/postEconomicBoardCitizenPostsPostIdComments";
import { CitizenAuth } from "../../../../../decorators/CitizenAuth";
import { CitizenPayload } from "../../../../../decorators/payload/CitizenPayload";
import { putEconomicBoardCitizenPostsPostIdCommentsCommentId } from "../../../../../providers/putEconomicBoardCitizenPostsPostIdCommentsCommentId";
import { deleteEconomicBoardCitizenPostsPostIdCommentsCommentId } from "../../../../../providers/deleteEconomicBoardCitizenPostsPostIdCommentsCommentId";

import { IEconomicBoardComment } from "../../../../../api/structures/IEconomicBoardComment";

@Controller("/economicBoard/citizen/posts/:postId/comments")
export class EconomicboardCitizenPostsCommentsController {
  /**
   * This operation allows authenticated citizens to create comments on
   * published discussion posts. When a comment is submitted, it is immediately
   * published and visible to all users on the platform. The system
   * automatically links the comment to the post identified by the postId path
   * parameter and associates it with the currently authenticated citizen.
   *
   * Security requires that only published posts can receive comments. If the
   * post referenced by postId has a status of 'pending' or 'rejected', the
   * system will return a 404 error. The comment body is limited to 500
   * characters as defined in the economic_board_comments schema, and this
   * constraint is enforced at the application layer.
   *
   * Comments can be edited by the author within 24 hours of creation, and can
   * be permanently deleted by moderators, which sets the deleted_at field. The
   * comment's parent_comment_id can reference another comment to create
   * threaded discussions, but this is optional.
   *
   * Related operations: GET /posts/{postId}/comments to retrieve all comments
   * on a post, PUT /posts/{postId}/comments/{commentId} to edit a comment.
   *
   * @param connection
   * @param postId Unique identifier of the published post to which this comment
   *   is attached. Must reference a post with status 'published' in the
   *   economic_board_posts table. Using a UUID format.
   * @param body The content of the new comment to be created. Must be 500
   *   characters or less as defined in the economic_board_comments schema.
   *   Includes text content and optional parent comment reference.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicBoardComment.ICreate,
  ): Promise<IEconomicBoardComment> {
    try {
      return await postEconomicBoardCitizenPostsPostIdComments({
        citizen,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation allows authenticated citizens to edit their own comments
   * within a 24-hour window after creation. This is enforced by the system
   * using the created_at and updated_at fields from the economic_board_comments
   * schema. After 24 hours, further edits are prohibited and shall result in a
   * 403 Forbidden response.
   *
   * The comment being updated must belong to the currently authenticated user,
   * as determined by the authentication token. If a user attempts to edit
   * another user's comment, the system returns a 403 error. The target comment
   * must be associated with a published post (status = 'published') as defined
   * in the economic_board_posts schema.
   *
   * The request body must contain the new comment text content, which will
   * replace the original content entirely. The system updates the updated_at
   * timestamp automatically, preserving the original created_at timestamp and
   * maintaining the comment's existence status (never deleted).
   *
   * Related operations: POST /posts/{postId}/comments to create new comments,
   * DELETE /posts/{postId}/comments/{commentId} to remove (but not permanently
   * delete) a comment, GET /posts/{postId}/comments/{commentId} to retrieve a
   * specific comment.
   *
   * @param connection
   * @param postId Unique identifier of the published post containing the
   *   comment. Must reference a post with status 'published' in the
   *   economic_board_posts table. Using a UUID format.
   * @param commentId Unique identifier of the comment to be updated. Must be
   *   owned by the authenticated user and created within the last 24 hours as
   *   recorded in economic_board_comments table. Using a UUID format.
   * @param body The updated content of the comment, replacing the existing
   *   value. Must be 500 characters or less as defined in the
   *   economic_board_comments schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicBoardComment.IUpdate,
  ): Promise<IEconomicBoardComment> {
    try {
      return await putEconomicBoardCitizenPostsPostIdCommentsCommentId({
        citizen,
        postId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently deletes a specific comment from a discussion post. This
   * operation is irreversible and immediately hides the comment from public
   * view by setting the deleted_at timestamp in the economic_board_comments
   * table.
   *
   * Security and permissions: Only the citizen who created the comment or a
   * moderator can delete it. The system verifies ownership using the JWT
   * authentication token to match the comment's citizen_id field. Moderators
   * may delete any comment regardless of ownership, subject to audit logging.
   *
   * The deletion is soft (tombstone) using the deleted_at field as defined in
   * the Prisma schema. The comment record remains in the database for audit
   * compliance but is filtered out from all public queries. The comment's
   * parent post_id reference is preserved to maintain thread integrity and
   * historical context.
   *
   * This operation does not affect other comments or the parent post. Only the
   * comment marked by comment_id is deleted.
   *
   * Related operations:
   *
   * - GET /comments: To retrieve remaining comments on the same post after
   *   deletion
   * - PATCH /posts/{postId}/comments: To retrieve a paginated list of the post's
   *   comments
   *
   * Error handling: Returns 404 if the comment_id does not exist, or if the
   * comment is already deleted.
   *
   * @param connection
   * @param postId Unique identifier of the published post containing this
   *   comment. Must reference a record in economic_board_posts with status
   *   'published'.
   * @param commentId Unique identifier of the comment to be deleted. Must be a
   *   valid UUID and exist in economic_board_comments.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("postId")
    postId: string,
    @TypedParam("commentId")
    commentId: string,
  ): Promise<void> {
    try {
      return await deleteEconomicBoardCitizenPostsPostIdCommentsCommentId({
        citizen,
        postId,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
