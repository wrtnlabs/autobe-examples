import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { postEconomicBoardCitizenPostsPostIdAttachments } from "../../../../../providers/postEconomicBoardCitizenPostsPostIdAttachments";
import { CitizenAuth } from "../../../../../decorators/CitizenAuth";
import { CitizenPayload } from "../../../../../decorators/payload/CitizenPayload";

import { IEconomicBoardAttachment } from "../../../../../api/structures/IEconomicBoardAttachment";

@Controller("/economicBoard/citizen/posts/:postId/attachments")
export class EconomicboardCitizenPostsAttachmentsController {
  /**
   * Uploads a file attachment to a specified discussion post. This operation
   * accepts multipart-form upload data containing the file and allows the
   * client to associate metadata with the uploaded file.
   *
   * The attachment record is created in the economic_board_attachments table
   * immediately upon receipt. The system validates the file's MIME type, size,
   * format, and sanitizes the filename before storage. Only approved formats
   * (image/jpeg, image/png, image/gif, image/webp, application/pdf, text/plain,
   * application/vnd.openxmlformats-officedocument.wordprocessingml.document,
   * application/vnd.openxmlformats-officedocument.spreadsheetml.sheet) are
   * permitted, and files larger than 10MB (10485760 bytes) are rejected.
   *
   * Attachments persist independently of their parent post — even if the post
   * is deleted permanently (hard delete), the attachment metadata remains to
   * satisfy audit and legal compliance requirements.
   *
   * This operation is available to both citizens and moderators, as any user
   * who can create a post may attach supporting content. Owner authorization is
   * enforced via the JWT token — the user must be authenticated and the post
   * must exist and belong to the same citizen or be visible to the moderator.
   *
   * The system returns a reference to the new attachment record with its
   * sanitized file name and secure storage URI. The file is not immediately
   * available for download until processing is complete and its status
   * transitions from 'uploaded' to 'processed'.
   *
   * Related operations: GET /posts/{postId}/attachments (retrieve all
   * attachments for a post), DELETE /posts/{postId}/attachments/{attachmentId}
   * (remove specific attachment).
   *
   * @param connection
   * @param postId Unique identifier of the post to which the attachment will be
   *   linked. Must be a valid UUID of an existing post.
   * @param body Form data containing the uploaded file and metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("postId")
    postId: string,
    @TypedBody()
    body: IEconomicBoardAttachment.ICreate,
  ): Promise<IEconomicBoardAttachment> {
    try {
      return await postEconomicBoardCitizenPostsPostIdAttachments({
        citizen,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
