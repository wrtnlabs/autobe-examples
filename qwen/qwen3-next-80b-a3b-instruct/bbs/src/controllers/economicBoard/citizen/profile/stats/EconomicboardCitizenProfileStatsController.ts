import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEconomicBoardProfile } from "../../../../../api/structures/IEconomicBoardProfile";
import { CitizenAuth } from "../../../../../decorators/CitizenAuth";
import { CitizenPayload } from "../../../../../decorators/payload/CitizenPayload";
import { getEconomicBoardCitizenProfileStats } from "../../../../../providers/getEconomicBoardCitizenProfileStats";

@Controller("/economicBoard/citizen/profile/stats")
export class EconomicboardCitizenProfileStatsController {
  /**
   * Retrieve a comprehensive overview of your profile activity on the Economic/Political Discussion Board.
   *
   * This endpoint provides a statistical summary of your contributions to the platform, including the total number of articles you've published and comments you've made. It serves as an analytical dashboard for your participation, helping you understand the scope of your engagement within the community.
   *
   * The statistics are computed dynamically based on your authenticated identity and reflect only active content: articles and comments that have not been deleted. This ensures the data presented represents your current and meaningful contributions.
   *
   * As a user-centric metric, this endpoint aggregates data from your authorship across multiple tables (economic_board_articles and economic_board_comments) without exposing individual data points. The information is presented in a concise summary format optimized for quick insight rather than raw data retrieval. This approach protects privacy while providing valuable feedback on your participation.
   *
   * This operation does not return any sensitive information such as specific article titles, comment content, or personal identifiers. It provides only aggregated count metrics that are safe for public display on your profile page. This aligns with the platform's commitment to secure, privacy-preserving analytics.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor citizen
   * @x-autobe-specification Query economic_board_articles to count total articles by the authenticated user where deleted_at IS NULL. Query economic_board_comments to count total comments by the authenticated user where deleted_at IS NULL. Calculate total engagement as sum of article views and comment replies if data available. Return object with articleCount, commentCount, and engagementScore.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @CitizenAuth()
    citizen: CitizenPayload,
  ): Promise<IEconomicBoardProfile> {
    try {
      return await getEconomicBoardCitizenProfileStats({
        citizen,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
