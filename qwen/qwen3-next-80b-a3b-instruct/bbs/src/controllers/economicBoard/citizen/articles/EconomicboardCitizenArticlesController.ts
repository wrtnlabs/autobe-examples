import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicBoardArticle } from "../../../../api/structures/IEconomicBoardArticle";
import { CitizenAuth } from "../../../../decorators/CitizenAuth";
import { CitizenPayload } from "../../../../decorators/payload/CitizenPayload";
import { deleteEconomicBoardCitizenArticlesArticleId } from "../../../../providers/deleteEconomicBoardCitizenArticlesArticleId";
import { getEconomicBoardCitizenArticlesArticleId } from "../../../../providers/getEconomicBoardCitizenArticlesArticleId";
import { postEconomicBoardCitizenArticles } from "../../../../providers/postEconomicBoardCitizenArticles";

@Controller("/economicBoard/citizen/articles")
export class EconomicboardCitizenArticlesController {
  /**
   * Create a new article in the economic discussion board.
   *
   * This endpoint allows registered citizens to submit original content to any active section of the board. The article must include a title and content, both subjected to length validation (title: 5–200 chars, content: 10–50,000 chars). Section validity is enforced server-side — attempts to post to non-existent or inactive sections will fail.
   *
   * Authors may optionally associate up to 10 free-form tags with their article for improved discoverability. These tags are stored as raw strings without pre-validation, enabling flexible categorization. Attachment files (images, documents) must be uploaded previously; their IDs are referenced in the request to associate them with the new article. All timestamps are recorded in Asia/Seoul timezone.
   *
   * Article metadata includes author, section, and tagging information. The article’s created_at timestamp is immutable. Authors retain ownership and can edit their articles within a 30-minute window (as defined in 04-business-rules.md), but deletion is permanent and irreversible — no soft delete mechanism exists in the system because the economic_board_articles table has no deleted_at column.
   *
   * This operation is available to authenticated citizens only. Banned users receive a 403 Forbidden response.
   *
   * @param connection
   * @param body Details needed to create a new article, including title, content, section reference, and optional tags and attachments.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor citizen
   * @x-autobe-specification Create a new article record in economic_board_articles table. Validate that section_id exists and is not marked as inactive. Associate provided tag strings with economic_board_article_tags via junction table. Link attachment_ids to economic_board_article_attachments via article_id. Set created_at and updated_at to current timestamp in Asia/Seoul timezone. Return full article object with embedded section and author details. Do not create attachment records here — assume attachment_ids reference pre-uploaded files.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedBody()
    body: IEconomicBoardArticle.ICreate,
  ): Promise<IEconomicBoardArticle> {
    try {
      return await postEconomicBoardCitizenArticles({
        citizen,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the full details of a specific article by its unique identifier.
   *
   * This endpoint returns comprehensive information about a single article, including its title, content, associated section, author display name, list of tags, attached files or images, and comment count. The article must not be deleted (is_deleted = false).
   *
   * All timestamp fields (created_at, updated_at) are returned in ISO 8601 format. Attachment URLs point to externally hosted files. Tags are returned as an array of string labels. Author information is anonymized to display name only, without email or ID exposure.
   *
   * This operation is available to all authenticated users and administrators. If the article does not exist or has been deleted, a 404 response is returned.
   *
   * @param connection
   * @param articleId Unique identifier of the article to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor citizen
   * @x-autobe-specification Query economic_board_articles table by id where is_deleted = false. Join with economic_board_sections to get section name. Join with economic_board_citizens to get author display_name. Join with economic_board_article_tags and economic_board_tags to compile list of tag names. Join with economic_board_article_attachments to retrieve attachment metadata (file_url, file_name, file_type, file_size). Count related economic_board_comments for comment_count. Return all fields as specified in requirements with ISO 8601 timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IEconomicBoardArticle> {
    try {
      return await getEconomicBoardCitizenArticlesArticleId({
        citizen,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove an article from public view while preserving its record in the database for audit purposes.
   *
   * This operation implements a soft-delete mechanism. When a user deletes their own article, the article is marked with is_deleted=true, hidden from all public listings, search results, and feeds, and remains in the database with its original content and metadata intact. All associated comments and attachments are preserved and flagged as orphaned if the article is queried directly. This behavior applies to both citizen authors and administrators.
   *
   * For citizen authors: The system validates that the requesting user is the article's author (author_id matches the authenticated user's ID). Only owners may delete their articles. If an unauthorized user attempts deletion, the system returns status 403 Forbidden with a message indicating permission denial.
   *
   * For administrators: Administrators may delete any article regardless of ownership. The system records the administrator's ID in the audit trail, noting the deletion was performed by an admin with elevated privileges. This supports accountability for content moderation.
   *
   * Associated comment records are not deleted, even under administrator action. The article's section association, author reference, and timestamps remain unchanged. The deletion operation does not purge file attachments from storage — they are marked unused but not physically removed.
   *
   * Attempting to delete an already-deleted article returns status 404 Article Not Found. This prevents users from needing to track the deletion state, and reinforces the single authoritative state of the article record.
   *
   * This operation is dependent on valid JWT authentication. No request body is required; deletion is determined solely by the path parameter articleId and the authenticated user's permissions.
   *
   * Related operations: GET /articles/{articleId} will return 404 after deletion. PATCH /articles/{articleId} will return 404 after deletion. GET /users/{userId}/articles will filter out deleted articles.
   *
   * @param connection
   * @param articleId Unique identifier for the article to be deleted. Must be a valid UUID.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor citizen
   * @x-autobe-specification Query economic_board_articles by id with WHERE is_deleted = false. If article not found or is_deleted = true, return 404. Validate user permission: author_id must equal authenticated user.id OR authenticated user is administrator. If permission denied, return 403. Set is_deleted = true and updated_at = current timestamp. Do not alter section_id, author_id, title, content, created_at. Do not delete or modify any child records (comments or attachments). Log deletion event to audit log table with admin_id if applicable. Return 204 No Content.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":articleId")
  public async erase(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("articleId")
    articleId: string,
  ): Promise<void> {
    try {
      return await deleteEconomicBoardCitizenArticlesArticleId({
        citizen,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
