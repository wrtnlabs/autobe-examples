import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEconomicBoardCitizen } from "../../../../api/structures/IEconomicBoardCitizen";
import { postEconomicBoardAuthCitizenJoin } from "../../../../providers/postEconomicBoardAuthCitizenJoin";
import { postEconomicBoardAuthCitizenLogin } from "../../../../providers/postEconomicBoardAuthCitizenLogin";
import { postEconomicBoardAuthCitizenRefresh } from "../../../../providers/postEconomicBoardAuthCitizenRefresh";

@Controller("/economicBoard/auth/citizen")
export class EconomicboardAuthCitizenController {
  /**
   * Registers a new citizen user by validating email uniqueness and password strength. The endpoint accepts email and password as plain text fields, which are immediately hashed using bcrypt before storage. Upon success, the system creates a citizen record in economic_board_citizens table with status active (is_banned = false), generates a JWT access token (20-minute expiration) with claims { userId, role: "citizen" }, and issues a refresh token stored securely in an httpOnly, Secure, SameSite=Strict cookie. The refresh token is linked to the citizen_id in economic_board_citizen_sessions. Any attempt to register with an existing email returns HTTP 409 Conflict. The display_name and bio fields are optional and default to null. No email verification is enforced by this endpoint; verification is handled through a separate flow via economic_board_citizen_email_verifications. This endpoint implements the "join" authorization type as specified in the Authorization Operations Table.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body for citizen registration, containing email and password to create a new account. The email must be unique and validated against existing records. password_hash is generated server-side using bcrypt.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor citizen
   * @x-autobe-specification Service layer receives email and password, validates email format (RFC 5322), checks economic_board_citizens for existing email (unique constraint), generates bcrypt hash with cost 12, inserts into economic_board_citizens with created_at and updated_at timestamps. Generates JWT with secret key (256-bit), payload { userId, role: "citizen" }, expiration 20m. Stores refresh token as hash in economic_board_citizen_sessions with device_fingerprint, ip, and expires_at (14d). Returns access token in response body, refresh token in httpOnly cookie.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEconomicBoardCitizen.IJoin,
  ): Promise<IEconomicBoardCitizen.IAuthorized> {
    try {
      return await postEconomicBoardAuthCitizenJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates a citizen user by validating email existence and password match against bcrypt hash. Upon success, the system generates a new JWT access token (20-minute expiration) with claims { userId, role: "citizen" }, and issues a new refresh token stored as a hash in economic_board_citizen_sessions with device fingerprint and timestamp. All existing sessions for this citizen are invalidated. If email does not exist or password is invalid, returns HTTP 401 Unauthorized. The endpoint does not distinguish between invalid email and wrong password for security reasons. This endpoint implements the "login" authorization type as specified in the Authorization Operations Table.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body for citizen login, containing email and password to authenticate and obtain JWT tokens. Email must exist in economic_board_citizens and password must match the stored bcrypt hash.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor citizen
   * @x-autobe-specification Service layer queries economic_board_citizens by email. Verifies account is not banned (is_banned = false). Compares input password with password_hash using bcrypt.compare(). On success, generates new JWT access token (exp: 20m), generates random refresh token, hashes it, and inserts into economic_board_citizen_sessions with device_fingerprint, ip, and expires_at (14d). Invalidates all previous sessions for this user (sets expired_at in economic_board_citizen_sessions). Returns access token in response body, refresh token in httpOnly cookie.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEconomicBoardCitizen.ILogin,
  ): Promise<IEconomicBoardCitizen.IAuthorized> {
    try {
      return await postEconomicBoardAuthCitizenLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Reissues a fresh access token and refresh token using the existing refresh token stored in the httpOnly, Secure, SameSite=Strict cookie. The server verifies the refresh token’s integrity and confirms its association with a valid, active citizen session in economic_board_citizen_sessions. If valid, a new access token (20-minute expiration) is generated with updated claims, and new refresh token is issued, replacing the old one in the cookie. The previous refresh token is immediately invalidated by expiring its record in economic_board_citizen_sessions. If token is expired, tampered, or not found, returns HTTP 401 Unauthorized. This operation is only available to authenticated citizens and implements the "refresh" authorization type as defined in the Authorization Operations Table.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body for token refresh, containing no explicit fields. Authentication is performed via the httpOnly refresh token cookie sent with the request.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor citizen
   * @x-autobe-specification Middleware extracts refresh token from httpOnly cookie. Attempts to retrieve matching session from economic_board_citizen_sessions where refresh_token_hash matches and expires_at > now. If session found and active, generates new JWT access token (exp: 20m), generates new refresh token, hashes it, updates economic_board_citizen_sessions with new refresh_token_hash and expires_at (extend to 14d from now). Invalidates old refresh token by updating is_expired = true. Returns new access token in body, new refresh token in cookie.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEconomicBoardCitizen.IRefresh,
  ): Promise<IEconomicBoardCitizen.IAuthorized> {
    try {
      return await postEconomicBoardAuthCitizenRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
