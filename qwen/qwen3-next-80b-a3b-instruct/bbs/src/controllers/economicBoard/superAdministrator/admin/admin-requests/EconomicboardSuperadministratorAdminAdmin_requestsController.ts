  /**
   * Reject a pending administrator promotion request.
   *
   * This operation allows super administrators to deny a citizen's request to become an administrator. When a request is rejected, the user's admin_request_status is updated to 'rejected' and an audit log entry is created to record the action.
   *
   * The rejection is permanent; the user may submit a new request after a cooldown period of 30 days, as enforced by application logic. The request rejection does not modify the user's ban status, email, or account permissions. Rejection notifications are sent via email, as specified in the business workflow.
   *
   * This operation is part of the administrator governance framework and is only accessible to super administrators, as specified in the permission matrix. Super administrators must be authenticated with a valid JWT token to perform this action. The system does not allow self-rejection — a super administrator cannot reject their own request if they previously submitted one.
   *
   * All rejections are logged in economic_board_administrator_audit_logs for forensic accountability and regulatory compliance. This is a status transition in the admin request workflow, not a soft delete operation.
   *
   * @param connection
   * @param requestId Unique identifier of the pending administrator request to reject. This UUID references the economic_board_administrators.id field where admin_request_status = 'pending'.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Update admin request status from 'pending' to 'rejected' in economic_board_administrators table where id = requestId. Create an audit log entry with action_type = 'reject_admin_request', actor_id from authenticated super admin, target_id = requested user id, and reason = 'Request rejected by super administrator'. Must validate: request is in 'pending' status, actor is super administrator, and requestId references a valid admin request record. Log rejection event to economic_board_administrator_audit_logs. Do not modify admin_request_reason field — only status changes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":requestId/reject")
  public async reject(
    @SuperadministratorAuth()
    superAdministrator: SuperadministratorPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IEconomicBoardSystemOverview> {
    try {
      return await patchEconomicBoardSuperAdministratorAdminAdminRequestsRequestIdReject(
        {
          superAdministrator,
          requestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
