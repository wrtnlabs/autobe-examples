import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEconomicBoardCitizen } from "../../../../../../api/structures/IEconomicBoardCitizen";
import { SuperadministratorAuth } from "../../../../../../decorators/SuperadministratorAuth";
import { SuperadministratorPayload } from "../../../../../../decorators/payload/SuperadministratorPayload";
import { postEconomicBoardSuperAdministratorAdminUsersUserIdPromote } from "../../../../../../providers/postEconomicBoardSuperAdministratorAdminUsersUserIdPromote";

@Controller("/economicBoard/superAdministrator/admin/users/:userId/promote")
export class EconomicboardSuperadministratorAdminUsersPromoteController {
  /**
   * Promote a citizen user to administrator status.
   *
   * This operation elevates a regular citizen to an administrator role, granting them permissions to manage content, approve user requests, and ban other users. The target user must be a citizen (not already an administrator or super-administrator). Promotion is only permitted by a super administrator.
   *
   * Upon successful promotion, the target user's account is updated to have the role of "administrator", their admin_request_status is set to "approved", and a promotion audit event is logged. The user's email, display name, and bio remain unchanged. The target user receives a notification of promotion.
   *
   * This operation cannot be performed if the target is already an administrator or super-administrator; in such cases, an error code "USER_ALREADY_ADMIN" is returned. Only super administrators can invoke this endpoint. Regular administrators have no authority to promote users.
   *
   * This operation does not affect the target's session tokens — the user remains logged in and gains new permissions immediately. The promotion is final and cannot be reversed without demotion via the demote-admin endpoint.
   *
   * @param connection
   * @param userId The UUID of the citizen user to promote to administrator.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Query the economic_board_citizens table to verify that the target user exists and has not been promoted before.
   *
   * Join with economic_board_administrators to confirm the target is not already an administrator.
   *
   * Ensure the requesting user (from JWT) is a superAdministrator by checking against economic_board_super_administrators.
   *
   * If both validations pass, insert a new record into economic_board_administrators with the target's data (id, email, password_hash, display_name, bio) and set is_banned: false and admin_request_status: "approved".
   *
   * Delete the original record from economic_board_citizens.
   *
   * Log the promotion event in economic_board_administrator_audit_logs with actor_id (super admin), target_user_id, action: "promote_to_admin", and timestamp.
   *
   * Return the updated User object with is_admin: true and is_super_admin: false.
   *
   * If the target is already an administrator, return 400 with error code "USER_ALREADY_ADMIN".
   *
   * If the requester is not a super-administrator, return 403 with error code "INSUFFICIENT_PERMISSIONS".
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async promoteToAdmin(
    @SuperadministratorAuth()
    superAdministrator: SuperadministratorPayload,
    @TypedParam("userId")
    userId: string,
  ): Promise<IEconomicBoardCitizen> {
    try {
      return await postEconomicBoardSuperAdministratorAdminUsersUserIdPromote({
        superAdministrator,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
