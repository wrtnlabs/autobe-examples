import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicBoardAdministrator } from "../../../../api/structures/IEconomicBoardAdministrator";
import { IEconomicBoardAdministratorAuditLog } from "../../../../api/structures/IEconomicBoardAdministratorAuditLog";
import { SuperadministratorAuth } from "../../../../decorators/SuperadministratorAuth";
import { SuperadministratorPayload } from "../../../../decorators/payload/SuperadministratorPayload";
import { patchEconomicBoardSuperAdministratorRequests } from "../../../../providers/patchEconomicBoardSuperAdministratorRequests";
import { patchEconomicBoardSuperAdministratorRequestsRequestIdReject } from "../../../../providers/patchEconomicBoardSuperAdministratorRequestsRequestIdReject";

@Controller("/economicBoard/superAdministrator/requests")
export class EconomicboardSuperadministratorRequestsController {
  /**
   * Reject a pending administrator promotion request.
   *
   * This operation allows a super administrator to officially reject a citizen's request to become an administrator. The action is irreversible and updates the request status to 'rejected' in the system.
   *
   * Super administrators are the only actors permitted to perform this action. Regular administrators cannot access this endpoint. The system validates the actor role against the JWT payload before execution.
   *
   * When executed, the economic_board_administrators record corresponding to the request ID is updated with admin_request_status set to 'rejected'. The original reason provided by the citizen remains stored in admin_request_reason for audit purposes.
   *
   * This operation is not available to citizens or regular administrators. It is exclusively reserved for super administrators managing the administrative promotion pipeline.
   *
   * Rejection triggers an automated email to the requesting citizen informing them that their request has been denied. The original reason may optionally be included in the email based on system configuration.
   *
   * This operation must be called with a valid UUID for the request ID in the path. Any request not in 'pending' status will result in a 404 response, ensuring the workflow state is enforced.
   *
   * @param connection
   * @param requestId The unique identifier of the administrator request to reject. This is the UUID of the economic_board_administrators record containing the pending request.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Update the admin_request_status of the target economic_board_administrators record to 'rejected'. The request ID is extracted from the path parameter. The system MUST verify that the authenticated user is a super administrator. If not, return 403 Forbidden. If the request does not exist or is not in 'pending' status, return 404 Not Found. No request body is processed. Log the rejection event. Respond with the updated economic_board_administrators record including id, email, display_name, admin_request_status, and admin_request_reason.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":requestId/reject")
  public async reject(
    @SuperadministratorAuth()
    superAdministrator: SuperadministratorPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IEconomicBoardAdministrator> {
    try {
      return await patchEconomicBoardSuperAdministratorRequestsRequestIdReject({
        superAdministrator,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Submit a request to be promoted from citizen to administrator.
   *
   * Citizen users may submit an administrative promotion request by providing a brief reason explaining why they believe they should be granted administrator privileges. This request is placed in a queue for review by super administrators.
   *
   * Only users with the citizen role and no existing pending, approved, or rejected requests may submit. Upon submission, the user's record is updated with admin_request_status = 'pending' and the provided reason is stored. No immediate role change occurs.
   *
   * The request is not visible to regular administrators—only super administrators can view and act on pending requests via the /admin/admin-requests endpoint. This endpoint is deliberately not paginated as it is a submission mechanism, and the response is minimal to enforce a stateless, audit-only workflow.
   *
   * This system ensures that promotion requests are properly logged, audited, and separated from direct administrative actions, maintaining strict role segregation and preventing misuse of privileges.
   *
   * @param connection
   * @param body The reason provided by the citizen for requesting administrator privileges. Limited to 500 characters by application logic.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Create a new pending administrator request in the economic_board_administrators table based on the authenticated citizen's ID. The user must be a citizen with is_admin = false and admin_request_status = 'none'. Insert a new record with admin_request_status = 'pending', admin_request_reason = provided reason, and updated_at = current timestamp. Reject if user already has pending, approved, or rejected request. Log audit entry with actor_id = user.id, action_type = 'approve_admin_request', target_id = user.id, and ip_address = request headers. Do not change user role, only set pending state.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async create(
    @SuperadministratorAuth()
    superAdministrator: SuperadministratorPayload,
    @TypedBody()
    body: IEconomicBoardAdministratorAuditLog,
  ): Promise<void> {
    try {
      return await patchEconomicBoardSuperAdministratorRequests({
        superAdministrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
