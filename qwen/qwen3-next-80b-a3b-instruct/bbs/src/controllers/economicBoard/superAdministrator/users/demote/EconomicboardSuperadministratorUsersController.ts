import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEconomicBoardCitizen } from "../../../../../api/structures/IEconomicBoardCitizen";
import { SuperadministratorAuth } from "../../../../../decorators/SuperadministratorAuth";
import { SuperadministratorPayload } from "../../../../../decorators/payload/SuperadministratorPayload";
import { postEconomicBoardSuperAdministratorUsersIdDemote } from "../../../../../providers/postEconomicBoardSuperAdministratorUsersIdDemote";

@Controller("/economicBoard/superAdministrator/users/:id/demote")
export class EconomicboardSuperadministratorUsersController {
  /**
   * Demote a super administrator to administrator status.
   *
   * This operation is only available to users with super administrator privileges. It permanently reduces the rank of another super administrator to a standard administrator, stripping their promotion and demotion permissions. This action is irreversible and logged for audit trails.
   *
   * The system refuses to demote the requesting super administrator (CANNOT_DEMOTE_SELF flag). The demoted user will receive a system notification. Their session remains valid until logout, but their permissions will be refreshed on the next authentication.
   *
   * @param connection
   * @param id The UUID of the super administrator to be demoted.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Fetch the target user from economic_board_super_administrators by id.
   * Verify the authenticated user is a super administrator by checking economic_board_super_administrators.
   * If target user id equals current user id, return error CANNOT_DEMOTE_SELF.
   * Delete the target user's record from economic_board_super_administrators.
   * Update the target user's record in economic_board_administrators to ensure they exist and are marked as administrator (update role flag if needed).
   * Log the demotion event in economic_board_administrator_audit_logs with demoting_admin_id, target_user_id, and timestamp.
   * Set the updated_at field on the target user (economic_board_administrators table).
   * Return the updated user record with is_super_admin: false.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async demote(
    @SuperadministratorAuth()
    superAdministrator: SuperadministratorPayload,
    @TypedParam("id")
    id: string,
  ): Promise<IEconomicBoardCitizen> {
    try {
      return await postEconomicBoardSuperAdministratorUsersIdDemote({
        superAdministrator,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
