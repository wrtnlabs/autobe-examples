import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicDiscussionComment } from "../../../../../api/structures/IEconomicDiscussionComment";
import { IPageIEconomicDiscussionComment } from "../../../../../api/structures/IPageIEconomicDiscussionComment";
import { CitizenAuth } from "../../../../../decorators/CitizenAuth";
import { CitizenPayload } from "../../../../../decorators/payload/CitizenPayload";
import { getEconomicDiscussionCitizenArticlesArticleIdComments } from "../../../../../providers/getEconomicDiscussionCitizenArticlesArticleIdComments";
import { patchEconomicDiscussionCitizenArticlesArticleIdComments } from "../../../../../providers/patchEconomicDiscussionCitizenArticlesArticleIdComments";
import { postEconomicDiscussionCitizenArticlesArticleIdComments } from "../../../../../providers/postEconomicDiscussionCitizenArticlesArticleIdComments";

@Controller("/economicDiscussion/citizen/articles/:articleId/comments")
export class EconomicdiscussionCitizenArticlesCommentsController {
  /**
   * Retrieve a chronological list of all comments associated with a specific article on the Economic/Political Discussion Board.
   *
   * This operation returns all comments made on a particular article, sorted from oldest to newest, providing a complete historical record of user discussions on that article. The API responds with a comprehensive set of comment data including the comment text, author's display name, creation timestamp, and edit timestamp, enabling users to follow the conversation thread in natural order.
   *
   * The system ensures that only comments for valid, existing articles are returned. Comments are linked through the article_id foreign key relationship with the economic_discussion_articles table, and only comments from citizen accounts are included. The comment content is limited to 1,000 characters as defined in the requirements, and is fully preserved in the response without truncation.
   *
   * Comments are displayed in a single-level thread with no nesting, as specified in the requirements. The operation returns all comments for an article at once without pagination, as comment volumes are expected to be low based on system design. Client applications must handle comment display efficiently for potentially large threads by implementing UI optimizations. This endpoint is essential for the core user interaction of reviewing discussion threads on articles.
   *
   * Related operations: Create comment (POST /articles/{articleId}/comments), Edit comment (PUT /comments/{commentId}), and Delete comment (DELETE /comments/{commentId}).
   *
   * @param connection
   * @param articleId Unique identifier of the article for which to retrieve comments (scoped to article)
   * @x-autobe-specification Query economic_discussion_comments table, join with economic_discussion_articles to verify article exists and is visible (not deleted).
   * Filter by article_id path parameter.
   * Sort results by created_at ascending (oldest first).
   * Limit results to 1000 comments for performance safety.
   * Include citizen display name in result by joining with economic_discussion_citizens table.
   * No pagination as comment volumes are expected to be low, but include total count for UI feedback.
   * Cache results with TTL of 60 seconds based on article_id.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async getByArticleid(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IPageIEconomicDiscussionComment.ISummary> {
    try {
      return await getEconomicDiscussionCitizenArticlesArticleIdComments({
        citizen,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new comment on a specified article in the economic/political discussion board. This operation allows authenticated users to submit textual comments that are associated with a specific article identified by the articleId path parameter. The comment content must be between 1 and 5,000 characters and cannot be empty.
   *
   * The comment is linked to the authenticated user who is making the request. The system enforces that the user must be authenticated and not banned to submit a comment. The comment creation triggers an automatic update to the article's comment count, which is maintained as a denormalized field for performance optimization.
   *
   * When a comment is created, the system records the current timestamp in Asia/Seoul timezone and stores the comment in the economic_discussion_comments table. The comment is permanently inserted and cannot be reverted — deletion performs a hard delete, removing the record entirely from the database.
   *
   * This operation supports the core discussion functionality of the platform, allowing users to engage with content through direct textual responses. The operation ensures data integrity by validating content length requirements and authenticating all requestors.
   *
   * Related operations: GET /economicDiscussion/citizen/articles/{articleId}/comments (retrieve comments), PUT /economicDiscussion/citizen/comments/{commentId} (edit comment), DELETE /economicDiscussion/citizen/comments/{commentId} (delete comment).
   *
   * @param connection
   * @param articleId Unique identifier of the article to which the comment should be added.
   * @param body The content of the new comment. Must contain at least 1 character and no more than 5,000 characters.
   * @x-autobe-specification Validate that user is authenticated and not banned. Extract authenticated user ID from JWT. Verify article exists and is active. Validate comment content length between 1-5000 characters. Reject if empty or exceeds limit. Generate new unique comment ID. Insert comment with article_id from path, author_id from JWT, content from request body, created_at and updated_at set to current Asia/Seoul time, and status='active'. Increment article's comment_count field by 1. Return created comment object with all fields including generated ID, timestamps, and status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("articleId")
    articleId: string,
    @TypedBody()
    body: IEconomicDiscussionComment.ICreate,
  ): Promise<IEconomicDiscussionComment> {
    try {
      return await postEconomicDiscussionCitizenArticlesArticleIdComments({
        citizen,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of comments associated with a specific article.
   *
   * This operation returns all comments made on a particular article, sorted from oldest to newest to maintain chronological conversation flow. Comments are displayed with their content, creation timestamp, and author identification, enabling users to follow the discussion thread in sequence.
   *
   * The system retrieves only comments that are actively visible, with no soft-delete mechanism in place as specified in the requirements. The results are limited to 20 comments per page to ensure optimal performance, particularly when an article receives high volumes of comments. Users can navigate through pages to view the complete comment history.
   *
   * Comment visibility is restricted to comments linked to the requested article; no cross-article comment filtering occurs. This endpoint is accessible to all authenticated users (citizens and administrators). The article's existence is enforced by the path parameter, and any attempt to access comments for a non-existent article returns a 404 error.
   *
   * For performance, the system serves this content from cache when possible, significantly reducing database load for popular articles. The implementation follows the business requirements that comments should be displayed in chronological order without nested replies and with full visibility of all posted comments. This endpoint is read-only; comments can be created or modified via separate POST and PUT operations.
   *
   * @param connection
   * @param articleId Unique identifier of the target article whose comments are being retrieved (UUID format)
   * @x-autobe-specification Query economic_discussion_comments table filtered by article_id field, ordered by created_at in ascending order (oldest first). Apply pagination with 20 comments per page using cursor-based pagination for efficiency. Include only comment content, author_id, and created_at fields in result. Exclude any deleted comments (if soft-delete flag exists, filter by it; but schema shows no such field). Cache results for 1 minute using caching key built from articleId and pagination cursor.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async patchByArticleid(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IPageIEconomicDiscussionComment.ISummary> {
    try {
      return await patchEconomicDiscussionCitizenArticlesArticleIdComments({
        citizen,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
