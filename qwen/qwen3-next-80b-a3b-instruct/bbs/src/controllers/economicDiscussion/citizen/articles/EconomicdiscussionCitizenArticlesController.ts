  public async index(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedBody()
    body: IEconomicDiscussionArticle.IRequest,
  ): Promise<IPageIEconomicDiscussionArticle.ISummary> {
    try {
      return await patchEconomicDiscussionCitizenArticles({
        citizen,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single article with complete details including author, attachments, and tags. This operation queries the economic_discussion_articles table and joins with economic_discussion_citizens, economic_discussion_article_files, and economic_discussion_article_tags to provide a comprehensive view of the article.
   *
   * The article is identified by its unique UUID identifier in the path parameter {articleId}. The response includes the article title, full content, timestamps (created_at and updated_at), and the author's display name. All attached files (PDFs, images, documents) are included with their metadata: filename, path, type, MIME type, size, and upload timestamp. All tags assigned to the article are listed as a flat array of strings.
   *
   * This operation does not limit the number of files or tags returned - all associated data is included. The implementation performs a single SQL query with multiple JOIN operations to efficiently retrieve all required data, avoiding N+1 query problems. The result is cached for 5 minutes for performance optimization, and the cache is invalidated when the article is updated.
   *
   * Note: While the HTTP method is PATCH (per explicit API instruction), this is functionally a read-only operation that returns data rather than modifying it. No user authentication is required to view public articles, in accordance with the system's public discussion model.
   *
   * @param connection
   * @param articleId Unique identifier of the target article in UUID format
   * @x-autobe-specification Query economic_discussion_articles table by the uuid articleId.
   * Join with economic_discussion_citizens to get author display_name.
   * Join with economic_discussion_article_files to get all attached files (file_path, file_name, file_type, mime_type, created_at, size).
   * Join with economic_discussion_article_tags to get all tag names associated with the article.
   * Return the article's title, content, created_at, updated_at, author's display_name, and aggregated files and tags.
   * Cache the result using a cache key that includes articleId, with 5-minute TTL to improve performance for repeated views.
   * Validate that the articleId is a valid UUID format before querying the database.
   * If article is not found, return HTTP 404 with error code ARTICLE_NOT_FOUND.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
