  public async create(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedBody()
    body: IEconomicDiscussionArticle.ICreate,
  ): Promise<IEconomicDiscussionArticle> {
    try {
      return await postEconomicDiscussionCitizenArticles({
        citizen,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of articles from the Economic Discussion platform, filtered by section and searchable by title or content.
   *
   * This operation provides users with an organized, browsable view of articles across the platform, enabling them to discover content based on their interests. The endpoint supports filtering by specific sections, full-text search across article titles and content, and filtering by multiple tags using AND logic. Each article in the result set displays summary information including the title, author's display name, associated tags, comment count, and posting timestamp, without revealing the full article content for performance optimization.
   *
   * Users can sort articles by newest first (default) or oldest first to better organize their browsing experience. The operation returns exactly 20 articles per page, with cursor-based pagination allowing efficient navigation through large result sets. For searches, fuzzy matching is applied to both title and content fields to support partial matches and misspellings, enhancing the user experience.
   *
   * This endpoint integrates with the economic_discussion_articles table as defined in the database schema, and combines data from related tables including economic_discussion_article_tags (for tags), economic_discussion_citizens (for author display names), and economic_discussion_comments (for comment counts). No full article content is returned by this operation to ensure fast response times and efficient data transfer, with full content available only through the individual article view endpoint.
   *
   * To optimize performance, results are cached for 5 minutes using a composite cache key based on the applied filters. This ensures high performance for common search and filter combinations while maintaining reasonable data freshness. Related operations: GET /articles/{articleId} for detailed article viewing, PATCH /search/articles for search-specific capabilities, and PATCH /sections for section management.
   *
   * @param connection
   * @param body Search and filter parameters for retrieving a paginated list of articles.
   * @x-autobe-specification Query economic_discussion_articles table with pagination, filtering by section_id if provided, and full-text search on title and content fields. Join with economic_discussion_article_tags to get article tag list. Join with economic_discussion_citizens to get author display_name. Count related economic_discussion_comments for comment_count. Return results sorted by created_at descending (newest first) by default or ascending if requested. Implement fuzzy text search using ILIKE with %% wildcards on title and content. Return 20 results per page with cursor-based pagination. Cache results for 5 minutes using a composite cache key based on section_id, search_term, tag_filters, and sort_order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
