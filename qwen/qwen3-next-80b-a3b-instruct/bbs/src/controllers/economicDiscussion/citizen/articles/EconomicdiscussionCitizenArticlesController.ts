  /**
   * Create a new article in a specified section with title, content, optional attachments, and tags.
   *
   * This operation allows authenticated citizens to create new discussion articles in predefined sections. Each article must reference exactly one section and include a title between 6 and 200 characters and content between 100 and 10,000 characters. The system validates that the section exists and the user has permission to post in it. All files and images are uploaded separately and referenced by URI in the request body, following the platform's spec that all media is handled via URI strings instead of multipart/form-data.
   *
   * Security: Only authenticated citizens can create articles. The creator_id field is automatically populated from the JWT authentication token. Article titles must be unique within the section to prevent duplicate content. Content is trimmed and sanitized to prevent XSS attacks. The creation timestamp is automatically recorded in UTC.
   *
   * Tags are applied as free-text keywords with a maximum of 10 tags per article. All tags are stored in lowercase and trimmed of whitespace. Files attached must be less than 50MB each and of acceptable types: PDF, DOCX, XLSX, PNG, JPG, JPEG, GIF. If any file exceeds size limits or has an invalid type, the request fails.
   *
   * This operation triggers an immediate lookup of the target section and validates existence. After successful creation, the article becomes immediately visible in section listings and search results. The assigned section cannot be changed after article creation - it is immutable. Related operations: GET /articles/{id} to view article detail, PATCH /articles to search/list articles, DELETE /articles/{id} to erase own article.
   *
   * @param connection
   * @param body Data required to create a new article including title, content, section identifier, optional file attachments as URIs, and tags.
   * @x-autobe-specification Insert new record into economic_discussion_articles table with title, content, section_id (resolved from provided section name), creator_id (from JWT), and timestamps. Create equivalent entries in economic_discussion_article_tags for each tag provided. For each file URI in request, create record in economic_discussion_article_files with metadata (original_name, size, content_type, storage_path). All operations executed in a single transaction. Validate title length (6-200), content length (100-10000), tag count ≤ 10, tag length 2-50, and file count ≤ 5. Reject if section does not exist. Create article only if user is authenticated as citizen. Update article count for the section in memory cache for performance. Return created article with generated id, createdAt, and full file metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
