import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicDiscussionBan } from "../../../../api/structures/IEconomicDiscussionBan";
import { IPageIEconomicDiscussionBan } from "../../../../api/structures/IPageIEconomicDiscussionBan";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getEconomicDiscussionAdministratorBans } from "../../../../providers/getEconomicDiscussionAdministratorBans";
import { getEconomicDiscussionAdministratorBansBanId } from "../../../../providers/getEconomicDiscussionAdministratorBansBanId";
import { patchEconomicDiscussionAdministratorBans } from "../../../../providers/patchEconomicDiscussionAdministratorBans";
import { postEconomicDiscussionAdministratorBansUserId } from "../../../../providers/postEconomicDiscussionAdministratorBansUserId";

@Controller("/economicDiscussion/administrator/bans")
export class EconomicdiscussionAdministratorBansController {
  /**
   * Ban a user from the Economic/Political Discussion Board platform. This operation creates a permanent ban record associated with a specific target user, as defined by the user ID in the path.
   *
   * Administrators must provide a reason for the ban, which must be between 10 and 500 characters, documenting the rationale for restricting the account. Once a user is banned, their access to the system is immediately revoked upon future login attempts. Importantly, their existing articles and comments remain visible on the platform to preserve content integrity. This is distinct from deletion, which permanently removes content.
   *
   * The ban process is auditable: the reason provided, the administrator who imposed the ban, and the timestamp of the ban are permanently recorded in the database. These records are stored in the economic_discussion_bans table, which links the banned user ID to the administrator who issued the ban. The system does not send notification emails to banned users.
   *
   * This operation complements the unban functionality (DELETE /bans/{userId}), which may be used if a ban is determined to be in error. The banning system is designed to enforce community guidelines while preserving valuable user-generated content for transparency.
   *
   * @param connection
   * @param userId Unique identifier of the target user to be banned (non-administrators)
   * @param body The reason for banning the user, explaining why this action is being taken.
   * @x-autobe-specification Create a new ban record in economic_discussion_bans table by linking the authenticated administrator's ID with the target user ID provided in the path parameter. Validate the ban reason from request body is between 10 and 500 characters. Store the ban reason, timestamp, administrator ID, and target user ID in the bans table. Do NOT change user status during this operation - the system will handle login denial during authentication based on bans presence. Return HTTP 204 No Content on successful creation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":userId")
  public async create(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicDiscussionBan.ICreate,
  ): Promise<void> {
    try {
      return await postEconomicDiscussionAdministratorBansUserId({
        administrator,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of all banned users in the economic/political discussion board system as part of an audit trail. This operation provides administrators with a read-only view of users who have been banned from the platform, including their ban reason and the administrator who imposed the ban. The banned users list is a critical system-generated audit tool that enables administrators to monitor and review platform conduct for compliance, ensuring the maintenance of civil discourse.
   *
   * The operation returns a paginated list containing the user ID of the banned account, the ID of the administrator who imposed the ban, the mandatory reason provided for the ban, the timestamp when the ban was imposed, and when the ban record was created in the system. These records are automatically generated by the system when administrators perform a ban action and are NOT accessible for creation, update, or deletion through external APIs. This system-generated audit trail is intended for complete transparency and traceability of moderation decisions.
   *
   * Administrators can use this list to review ban decisions, understand patterns of user misconduct, and make informed decisions about potential unban requests. The ban reason field is a required field that must be provided by the administrator who imposed the ban, and this text is displayed in this interface to provide context for each ban decision. The system does not support automatic ban expirations; all bans are permanent unless manually unban by a super administrator.
   *
   * This operation requires administrator privileges to access. Unauthorized users attempting to access this endpoint will receive a 403 Forbidden response. The endpoint is designed to be searchable and should return results efficiently even with large numbers of banned users, adhering to the performance target of under 1 second response time for pagination requests.
   *
   * @param connection
   * @x-autobe-specification Query economic_discussion_bans table with cursor-based pagination. Include banned_user_id, banned_by_admin_id, reason, banned_at, and created_at fields in results. Return data ordered by banned_at descending (most recent bans first). Apply rate limiting of 10 requests per minute per admin. Cache results for 2 minutes using admin ID as cache key.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async get(
    @AdministratorAuth()
    administrator: AdministratorPayload,
  ): Promise<IPageIEconomicDiscussionBan.ISummary> {
    try {
      return await getEconomicDiscussionAdministratorBans({
        administrator,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of banned users with filtering and search capabilities. This operation queries the economic_discussion_bans table to return records of users who have been banned from the platform. The operation supports advanced filtering by username, ban reason, and ban date range to assist administrators in managing banned users.
   *
   * Security considerations require that only authenticated administrators may access this endpoint. The ban reason field is only visible to administrators and is hidden from regular users. The operation returns only the minimum necessary information for ban management: user ID, username, ban reason, ban date, and the administrator who issued the ban.
   *
   * This operation integrates with the economic_discussion_bans table as defined in the database schema and supports cursor-based pagination for optimal performance with large datasets. The request parameters allow administrators to focus their review on specific categories of banned users (e.g., recent bans, specific reasons like hate speech). Related operations include the ban processing endpoint (POST /bans) and the unban endpoint (DELETE /bans/{banId}).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering banned users
   * @x-autobe-specification Query economic_discussion_bans table with cursor-based pagination for efficiency. Join with economic_discussion_citizens to retrieve username for display. Filter by username (partial match), reason (partial match), and ban date range when provided. Apply sorting by ban date descending (newest first). Return pagination cursor with next link. Cache results for 1 minute with cache key based on pagination and filter parameters. Validate that user has administrator role before executing query.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async patch(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IEconomicDiscussionBan.IRequest,
  ): Promise<IPageIEconomicDiscussionBan.ISummary> {
    try {
      return await patchEconomicDiscussionAdministratorBans({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific ban record from the economic_discussion_bans table. This operation allows administrators to view detailed information about a specific user ban, including the reason for the ban, the timestamp when the ban was issued, and the identifier of the affected user.
   *
   * The ban record contains all necessary details for administrative review and audit purposes. This endpoint is used by administrators to investigate specific banning incidents, review the justification for bans, and ensure compliance with moderation policies.
   *
   * Security considerations include ensuring that only authenticated administrators can access this information, as ban details are sensitive moderation data. The endpoint returns HTTP 404 (Not Found) if the specified banId does not exist in the database. Access is restricted to administrators and super administrators based on role-based access control.
   *
   * This operation does not modify any data and is strictly read-only.
   *
   * @param connection
   * @param banId Unique identifier of the specific ban record to retrieve
   * @x-autobe-specification Query economic_discussion_bans table by banId. Return the ban record with all fields including ban reason, timestamp, affected user ID, and admin who issued the ban. Implement strict authorization to ensure only administrators can access this endpoint. Return HTTP 404 if ban record not found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":banId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("banId")
    banId: string & tags.Format<"uuid">,
  ): Promise<IEconomicDiscussionBan> {
    try {
      return await getEconomicDiscussionAdministratorBansBanId({
        administrator,
        banId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
