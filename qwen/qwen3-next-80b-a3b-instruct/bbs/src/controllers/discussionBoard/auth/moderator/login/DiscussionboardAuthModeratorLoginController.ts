import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";

import { IDiscussionBoardModeratorSession } from "../../../../../api/structures/IDiscussionBoardModeratorSession";
import { IDiscussionBoardModerator } from "../../../../../api/structures/IDiscussionBoardModerator";

@Controller("/discussionBoard/auth/moderator/login")
export class DiscussionboardAuthModeratorLoginController {
  /**
   * Authenticate moderator and generate session token.
   *
   * This endpoint authenticates moderator users by validating their email and
   * password against the discussion_board_moderators table.
   *
   * The system first verifies that the provided email exists and is not
   * soft-deleted. It then checks if email_verified is true, as unverified
   * accounts cannot authenticate for security reasons. The password_hash is
   * verified using a cryptographic function to ensure authentication
   * security.
   *
   * Upon successful authentication, the system generates a JWT access token
   * containing the moderator's ID and role ("moderator") with a 30-minute
   * expiration, and a refresh token with 7-day expiration stored securely on
   * the client. The session is recorded in the
   * discussion_board_moderator_sessions table with details including IP
   * address, referrer, and href.
   *
   * If authentication fails due to incorrect credentials, the system returns
   * an error without disclosing whether the email or password was incorrect
   * to prevent account enumeration attacks. If the email is unverified, the
   * system returns a specific error requesting email verification.
   *
   * This endpoint does not create a moderator account - that requires the
   * /auth/moderator/join endpoint. This endpoint only authenticates existing,
   * verified moderator accounts for API session establishment.
   *
   * @param connection
   * @param body Login credentials containing email and password for moderator
   *   authentication
   * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
   */
  @TypedRoute.Post()
  public async signIn(
    @TypedBody()
    body: IDiscussionBoardModerator.IRequest,
  ): Promise<IDiscussionBoardModeratorSession> {
    body;
    return typia.random<IDiscussionBoardModeratorSession>();
  }
}
