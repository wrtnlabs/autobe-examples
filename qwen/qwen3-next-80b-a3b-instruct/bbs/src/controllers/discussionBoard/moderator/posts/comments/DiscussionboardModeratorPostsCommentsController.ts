  /**
   * Permanently delete a specific comment.
   *
   * This operation permanently removes a specific comment from the system,
   * identified by both the postId and commentId path parameters. Unlike soft
   * delete operations, this performs a hard deletion, completely removing the
   * comment record from the database. This behavior is consistent with the
   * business requirement for moderator actions, where moderators can delete
   * any comment at any time regardless of ownership.
   *
   * The deletion mechanism is designed to remove the comment entirely from
   * the database rather than marking it with a deleted_at flag, as the
   * discussion_board_comments table does not contain a deleted_at column to
   * support soft deletion. The system preserves audit information by
   * replacing the comment content with '[Deleted by moderator]' in the UI
   * while the record is permanently removed from storage.
   *
   * This operation requires the user to be authenticated as a moderator, as
   * only moderators have the permission to delete comments. Regular citizens
   * cannot delete comments belonging to others. The deletion triggers a
   * system notification to the comment's original author if applicable,
   * informing them that their comment was removed by a moderator.
   *
   * This operation is irreversible, and the comment content cannot be
   * recovered after deletion. The deletion is logged in the moderation action
   * audit trail with details of the moderator who performed the action and
   * the timestamp of the deletion.
   *
   * @param connection
   * @param postId Unique identifier of the post containing the comment to be
   *   deleted. Must be a valid UUID that corresponds to an existing post in
   *   the discussion_board_posts table
   * @param commentId Unique identifier of the comment to be deleted. Must be
   *   a valid UUID that corresponds to an existing comment in the
   *   discussion_board_comments table
   * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
   */
