  /**
   * Retrieve detailed information for a specific comment.
   *
   * Retrieve a single comment by its unique identifier for display in the
   * context of its parent post. This operation is triggered when a user
   * clicks on a specific comment to view it in isolation or when navigation
   * requires direct access to a comment's details.
   *
   * Security considerations require that the comment must be associated with
   * an active post (status: active) for the comment to be accessible. If the
   * parent post is deleted or removed, the comment is considered orphaned and
   * will return HTTP 404. The comment's own status (active,
   * deleted_by_author, deleted_by_moderator) is reflected in the response for
   * transparency.
   *
   * This operation integrates directly with the discussion_board_comments
   * table and performs joins with discussion_board_citizens and
   * discussion_board_moderators to populate the complete author object based
   * on the author_type field. The response includes the full comment content,
   * creation and update timestamps, deletion timestamp if applicable, and a
   * resolved author object with appropriate username.
   *
   * The operation is read-only and optimized for singular document retrieval
   * using the primary key index on id. It does not support pagination as it
   * returns a single result. This operation complies with the requirement to
   * display comment author names and timestamps for all existing comments.
   *
   * @param connection
   * @param postId Unique identifier of the target post that contains the
   *   comment. This must be a valid UUID from the discussion_board_posts
   *   table.
   * @param commentId Unique identifier of the target comment. This must be a
   *   valid UUID from the discussion_board_comments table.
   * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
   */
