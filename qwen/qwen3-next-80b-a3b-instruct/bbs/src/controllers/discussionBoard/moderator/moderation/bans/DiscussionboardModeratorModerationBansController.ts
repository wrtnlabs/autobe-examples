import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";

import { IDiscussionBoardBan } from "../../../../../api/structures/IDiscussionBoardBan";

@Controller("/discussionBoard/moderator/moderation/bans")
export class DiscussionboardModeratorModerationBansController {
  /**
   * Create a new moderation ban record on the discussion board system. This
   * operation interacts with the discussion_board_bans table in the database
   * schema and allows privileged moderators to issue temporary or permanent
   * bans against citizen accounts for policy violations. The ban record is
   * permanently stored in the database as an immutable audit record, regardless
   * of whether it is temporary or permanent.
   *
   * The operation creates a permanent record that includes the banned citizen's
   * ID, the moderator's ID, the reason for the ban, the start date and optional
   * end date for temporary bans, and any additional notes. All ban records are
   * preserved indefinitely in the database for compliance and audit purposes
   * through the system's moderation audit trails.
   *
   * Security considerations require this operation to be restricted to
   * moderator-level actors only. The moderation system enforces role-based
   * access control, and this endpoint is intentionally not available to regular
   * citizens or any other user type.
   *
   * This operation does not update, delete, or modify existing bans - it only
   * creates new ones. The ban records are hard records in the database with no
   * soft-delete mechanism; deletion is not possible and records remain
   * permanently in the database.
   *
   * This operation is complementary to other moderation endpoints: users may
   * appeal a ban via POST /moderation/appeals, and moderators can view existing
   * bans through GET /moderation/bans with search parameters. All banned
   * citizens are automatically restricted from posting, commenting, and other
   * interactive features upon successful creation of this ban record.
   *
   * @param connection
   * @param body Data required to create a moderation ban record on the
   *   discussion board system
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: IDiscussionBoardBan.ICreate,
  ): Promise<IDiscussionBoardBan> {
    body;
    return typia.random<IDiscussionBoardBan>();
  }
}
