import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchPoliticalForumModeratorUsers } from "../../../../providers/patchPoliticalForumModeratorUsers";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { deletePoliticalForumModeratorUsersUserId } from "../../../../providers/deletePoliticalForumModeratorUsersUserId";

import { IPageIPoliticalForumCitizen } from "../../../../api/structures/IPageIPoliticalForumCitizen";
import { IPoliticalForumCitizen } from "../../../../api/structures/IPoliticalForumCitizen";

@Controller("/politicalForum/moderator/users")
export class PoliticalforumModeratorUsersController {
  /**
   * Search and retrieve a filtered, paginated list of citizens.
   *
   * Retrieve a filtered and paginated list of political forum citizens with
   * advanced search capabilities. This operation allows administrative actors
   * to find users based on multiple criteria including partial display name
   * matching, email domain filtering, account activity status, and creation
   * date ranges.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Citizens can sort by creation date, last login,
   * display name, or other relevant fields in ascending or descending order.
   *
   * Security considerations include rate limiting for search operations and
   * appropriate filtering of sensitive citizen information based on the
   * requesting user's authorization level. Only users with administrative
   * privileges can access detailed citizen information including email
   * addresses. Regular users cannot access this endpoint.
   *
   * This operation integrates with the political_forum_citizens table as
   * defined in the Prisma schema, incorporating all available citizen fields
   * and relationships. The response includes citizen summary information
   * optimized for list displays, with options to include additional details
   * based on authorization level.
   *
   * This operation relates to other endpoints such as GET /users/{userId} (at)
   * and POST /users (create). It is used exclusively by administrators for user
   * management tasks such as investigating reports, reviewing user activity, or
   * performing bulk operations.
   *
   * Error handling: If search parameters are invalid (e.g., malformed date
   * format), the server returns a 400 Bad Request. If pagination parameters
   * exceed allowed limits (e.g., page size > 100), the server returns a 400 Bad
   * Request.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for citizen filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IPoliticalForumCitizen.IRequest,
  ): Promise<IPageIPoliticalForumCitizen.ISummary> {
    try {
      return await patchPoliticalForumModeratorUsers({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a citizen user account.
   *
   * This operation permanently deletes a citizen user account from the
   * political forum database. Unlike soft deletion, this removes the record
   * entirely from the political_forum_citizens table, making it unrecoverable.
   *
   * The operation requires authentication as a moderator with appropriate
   * permissions. Upon success, the system will also delete all associated
   * citizen sessions and purge any audit log entries specifically related to
   * this user's actions. Any posts or comments created by this user will remain
   * in the system but will be marked as 'author deleted' with the user's
   * information redacted for privacy and legal compliance.
   *
   * This hard delete operation has significant implications for data integrity
   * and compliance. It cannot be reversed, and any data associated with the
   * user will be permanently lost. This is designed for cases of severe policy
   * violations where complete removal is necessary.
   *
   * During deletion, the system will trigger the political_forum_audit_logs
   * system to record this administrative action along with the operator
   * identifier and timestamp for accountability purposes.
   *
   * @param connection
   * @param userId Unique identifier of the citizen user to be permanently
   *   deleted from the system. This ID must match an existing record in the
   *   political_forum_citizens table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userId")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deletePoliticalForumModeratorUsersUserId({
        moderator,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
