import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putPoliticalForumModeratorPostsPostIdCommentsCommentId } from "../../../../../providers/putPoliticalForumModeratorPostsPostIdCommentsCommentId";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { deletePoliticalForumModeratorPostsPostIdCommentsCommentId } from "../../../../../providers/deletePoliticalForumModeratorPostsPostIdCommentsCommentId";

import { IPoliticalForumComment } from "../../../../../api/structures/IPoliticalForumComment";

@Controller("/politicalForum/moderator/posts/:postId/comments/:commentId")
export class PoliticalforumModeratorPostsCommentsController {
  /**
   * Update a specific comment on a political forum post.
   *
   * This operation allows authorized users to modify the content of an existing
   * comment on a political forum post. The comment is uniquely identified by
   * its postId and commentId parameters. Only the original author of the
   * comment or a moderator can update the comment content.
   *
   * The update operation replaces the entire comment content with the new data
   * provided in the request body. Partial updates are not supported - the
   * entire comment object must be provided with all fields filled out. The
   * system will update the modified_at timestamp automatically during this
   * operation.
   *
   * Security considerations include verifying the user's ownership of the
   * comment or moderator privileges before allowing the update. Rate limiting
   * is applied to prevent abuse of this endpoint. The operation will not allow
   * updates to comments that have been archived or deleted.
   *
   * @param connection
   * @param postId Unique identifier of the target political forum post (UUID
   *   format)
   * @param commentId Unique identifier of the target comment on the post (UUID
   *   format)
   * @param body Updated content and metadata for the political forum comment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IPoliticalForumComment.IUpdate,
  ): Promise<IPoliticalForumComment> {
    try {
      return await putPoliticalForumModeratorPostsPostIdCommentsCommentId({
        moderator,
        postId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific comment on a political forum post.
   *
   * This operation permanently removes a specific comment on a political forum
   * post from the system. The comment is uniquely identified by its postId and
   * commentId parameters. Only the original author of the comment or a
   * moderator can delete the comment.
   *
   * This is a hard delete operation that removes all data associated with the
   * comment permanently. Unlike moderation actions that mark comments as
   * hidden, this operation completely deletes the record from the database.
   * After deletion, the comment cannot be recovered.
   *
   * Security considerations include verifying the user's ownership of the
   * comment or moderator privileges before allowing deletion. Audit logs are
   * automatically generated to record this deletion action for compliance
   * purposes. The system will ensure that deletions cannot be performed on
   * comments that have already been archived or removed.
   *
   * @param connection
   * @param postId Unique identifier of the target political forum post (UUID
   *   format)
   * @param commentId Unique identifier of the target comment on the post (UUID
   *   format)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IPoliticalForumComment> {
    try {
      return await deletePoliticalForumModeratorPostsPostIdCommentsCommentId({
        moderator,
        postId,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
