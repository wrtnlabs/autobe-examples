import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { deletePoliticalForumModeratorPostsPostId } from "../../../../providers/deletePoliticalForumModeratorPostsPostId";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";

@Controller("/politicalForum/moderator/posts/:postId")
export class PoliticalforumModeratorPostsController {
  /**
   * Permanently delete a political forum post.
   *
   * This endpoint allows authorized moderators to permanently delete a
   * political forum post. The deletion is immediate and irreversible, meaning
   * the post record is removed entirely from the political_forum_posts table
   * with no possibility of recovery.
   *
   * This operation does not implement soft deletion, as the
   * political_forum_posts table has no soft_delete_column field defined in the
   * Prisma schema. Therefore, the deletion is a hard delete that removes the
   * row entirely from the database. This aligns with the moderation workflow
   * where posts violating community guidelines are removed completely and
   * permanently.
   *
   * The delete operation is restricted to moderators only, as regular citizens
   * cannot delete posts they did not create. Moderators must have appropriate
   * privileges to perform this action, as it constitutes a high-impact system
   * change that affects content availability and user trust.
   *
   * The operation triggers a related moderation action to be recorded in the
   * political_forum_moderation_actions table, which logs the deletion event
   * with the moderator’s ID, the post’s ID, and the reason for deletion (if
   * provided). This audit trail is critical for transparency and compliance.
   *
   * No response body is returned upon successful deletion, following REST
   * conventions for delete operations. A 204 No Content status code is expected
   * from the server. On failure (e.g., unauthorized access or non-existent
   * post), appropriate HTTP 4xx status codes are returned.
   *
   * This operation is tightly coupled with the moderation system: it must be
   * called only after an audit trail has been initiated and it aligns with the
   * political_forum_moderation_status model’s defined moderation states.
   *
   * @param connection
   * @param postId Unique identifier of the target political forum post to be
   *   deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("postId")
    postId: string,
  ): Promise<void> {
    try {
      return await deletePoliticalForumModeratorPostsPostId({
        moderator,
        postId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
