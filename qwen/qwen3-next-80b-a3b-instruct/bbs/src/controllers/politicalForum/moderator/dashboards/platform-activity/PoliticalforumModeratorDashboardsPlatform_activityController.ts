import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getPoliticalForumModeratorDashboardsPlatformActivity } from "../../../../../providers/getPoliticalForumModeratorDashboardsPlatformActivity";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IPoliticalForumPlatformActivityDashboard } from "../../../../../api/structures/IPoliticalForumPlatformActivityDashboard";

@Controller("/politicalForum/moderator/dashboards/platform-activity")
export class PoliticalforumModeratorDashboardsPlatform_activityController {
  /**
   * Retrieve platform activity dashboard metrics.
   *
   * This operation retrieves a real-time dashboard of platform activity metrics
   * that provides moderation teams with key insights into the health and
   * engagement of the political forum.
   *
   * The dashboard aggregates data from multiple core entities: the number of
   * active posts, the count of recent comments, the volume of user reports, and
   * the status of pending moderation actions. This information is computed
   * on-demand through SQL joins and aggregations across the
   * political_forum_posts, political_forum_comments,
   * political_forum_post_reports, and political_forum_moderation_actions
   * tables.
   *
   * The returned data includes statistics such as total posts from the past 24
   * hours, active conversations, reports requiring attention, IDs of the most
   * recently moderated items, and the current status of platform-wide settings
   * that affect content visibility. It does not return individual records but
   * instead provides aggregated numerical values and counts that enable
   * moderators to monitor platform activity at a glance.
   *
   * This operation is optimized for performance with database-level
   * aggregations, and uses the political_forum_system_settings table to
   * determine the time window for activity calculations, ensuring that metrics
   * always reflect the system's current configuration.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
  ): Promise<IPoliticalForumPlatformActivityDashboard> {
    try {
      return await getPoliticalForumModeratorDashboardsPlatformActivity({
        moderator,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
