import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getPoliticalForumModeratorDashboardsModerationEfficiency } from "../../../../../providers/getPoliticalForumModeratorDashboardsModerationEfficiency";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IPoliticalForumModerationEfficiencyMetrics } from "../../../../../api/structures/IPoliticalForumModerationEfficiencyMetrics";

@Controller("/politicalForum/moderator/dashboards/moderation-efficiency")
export class PoliticalforumModeratorDashboardsModeration_efficiencyController {
  /**
   * Retrieve moderation efficiency metrics for the past 30 days.
   *
   * This endpoint provides comprehensive moderation efficiency metrics to help
   * administrators assess the effectiveness of the content moderation team. The
   * system calculates key performance indicators by analyzing reported content
   * and resolution patterns from the political_forum_post_reports and
   * political_forum_comment_reports tables.
   *
   * The operation computes the total number of reported posts and comments, the
   * quantity resolved within 24 hours, and the average time-to-resolution
   * across all reports over the past 30 days. It also calculates the percentage
   * of reports that remain pending versus those that have been reviewed,
   * dismissed, or escalated. This multi-dimensional analysis provides a
   * holistic view of moderation team responsiveness and workload balance.
   *
   * The metrics are derived from the status and created_at/updated_at fields in
   * the political_forum_post_reports and political_forum_comment_reports
   * tables, with date range filters applied to the last 30 days. The system
   * aggregates these reports by status type and calculates resolution rates
   * based on the logic: (resolved_reports / total_reports) * 100.
   *
   * This endpoint has no security restrictions as it exposes aggregated,
   * non-sensitive metrics. Any authenticated user with moderator privileges can
   * access it, but it does not expose individual report details or personal
   * information. It is designed for dashboard consumption by platform
   * administrators.
   *
   * This operation is independent of user_session and citizen tables, as it
   * only aggregates reporting data without linking to specific users. The
   * operation does not modify any data and is purely read-only. Similar
   * dashboard operations exist for user engagement and content growth
   * analytics, which can be called in sequence to provide comprehensive
   * platform health insights.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
  ): Promise<IPoliticalForumModerationEfficiencyMetrics> {
    try {
      return await getPoliticalForumModeratorDashboardsModerationEfficiency({
        moderator,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
