import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchPoliticalForumModeratorReportsWeeklyActivity } from "../../../../../providers/patchPoliticalForumModeratorReportsWeeklyActivity";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IPoliticalForumWeeklyActivityMetrics } from "../../../../../api/structures/IPoliticalForumWeeklyActivityMetrics";
import { IPoliticalForumWeeklyActivityRequest } from "../../../../../api/structures/IPoliticalForumWeeklyActivityRequest";

@Controller("/politicalForum/moderator/reports/weekly-activity")
export class PoliticalforumModeratorReportsWeekly_activityController {
  /**
   * Fetch aggregated weekly activity metrics for forum engagement.
   *
   * This operation provides weekly activity analytics for the political forum
   * platform by aggregating engagement data from the primary content and
   * reporting tables. The system calculates daily and weekly totals for posts
   * created, comments added, post reports submitted, and comment reports
   * submitted over the past seven days.
   *
   * The operation processes data from political_forum_posts (created_at),
   * political_forum_comments (created_at), political_forum_post_reports
   * (created_at), and political_forum_comment_reports (created_at), using date
   * aggregation to group records by day of week. It calculates trends by
   * comparing weekly totals against previous periods and detects anomalies
   * through rate-of-change thresholds.
   *
   * The calculation logic includes: cumulative post count, daily
   * comment-to-post ratio, report-to-content ratio, and peak activity timing.
   * The endpoint returns weekly trends and helps identify unusual patterns in
   * user engagement or moderation burden. This is a read-only operation that
   * does not modify any system data.
   *
   * The returned metrics are calculated from raw data without joining to user
   * tables, preserving privacy. The operation is designed for consumption by
   * platform analysts who require insight into weekly behavioral patterns. This
   * endpoint can be called concurrently with the
   * /dashboards/moderation-efficiency endpoint to provide a complete picture of
   * platform health.
   *
   * The operation supports pagination and filtering through request parameters
   * that allow analysts to specify custom date ranges or include/exclude
   * certain content types. Documentation for the request body structure is
   * provided in the IWeeklyForumActivityRequest definition.
   *
   * @param connection
   * @param body Optional parameters for filtering weekly activity data
   *   including date range, content types to include, and aggregation level
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IPoliticalForumWeeklyActivityRequest,
  ): Promise<IPoliticalForumWeeklyActivityMetrics> {
    try {
      return await patchPoliticalForumModeratorReportsWeeklyActivity({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
