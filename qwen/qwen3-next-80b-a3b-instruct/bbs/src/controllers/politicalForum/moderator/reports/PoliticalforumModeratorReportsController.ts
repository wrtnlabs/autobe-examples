import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getPoliticalForumModeratorReportsReportId } from "../../../../providers/getPoliticalForumModeratorReportsReportId";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { patchPoliticalForumModeratorReports } from "../../../../providers/patchPoliticalForumModeratorReports";

import { IPoliticalForumPostReport } from "../../../../api/structures/IPoliticalForumPostReport";
import { IPageIPoliticalForumPostReport } from "../../../../api/structures/IPageIPoliticalForumPostReport";

@Controller("/politicalForum/moderator/reports")
export class PoliticalforumModeratorReportsController {
  /**
   * Retrieve a specific report by its unique identifier.
   *
   * This operation fetches a single report entity from the
   * political_forum_post_reports or political_forum_comment_reports table based
   * on the provided reportId. Reports are created when users flag content as
   * inappropriate or violating community guidelines.
   *
   * The system distinguishes between post reports and comment reports based on
   * the reportId format and corresponding table structure. A successful
   * response returns the complete report details including the reported content
   * identifier, the reporter user ID, a description of the violation,
   * timestamps, and current status.
   *
   * Security considerations require this operation to be restricted to
   * authenticated users and moderators, as reports may contain sensitive
   * moderation metadata and private user information. The system ensures that
   * users can only access reports they created or have been granted permission
   * to view. The report ID must be validated against the database to prevent
   * unauthorized access attempts.
   *
   * This operation is typically used in moderation workflows where team members
   * need to review reported content. It supports the company's commitment to
   * responsible content moderation and user safety by providing detailed
   * context for each reported item. The response includes all available
   * information about the report to enable informed moderation decisions.
   *
   * @param connection
   * @param reportId Unique identifier of the report to retrieve. This
   *   identifier references either a post report or comment report entry from
   *   the database, assuming a single unique identifier space for both report
   *   types.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reportId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<IPoliticalForumPostReport> {
    try {
      return await getPoliticalForumModeratorReportsReportId({
        moderator,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated list of reports with advanced filtering.
   *
   * This operation performs a comprehensive search across both
   * political_forum_post_reports and political_forum_comment_reports tables to
   * return a filtered, paginated list of reports. It enables moderators and
   * system administrators to efficiently manage the report queue by applying
   * multiple filters such as reporter ID, content type (post or comment -
   * filtered by report_type), report status (pending, reviewed, dismissed,
   * actioned), creation date range, and keyword searches in report reason
   * descriptions.
   *
   * The results are presented in a paginated format with configurable page size
   * and sorting options to accommodate different workloads. Users can sort by
   * creation date, status, or other relevant fields in ascending or descending
   * order. The search functionality supports partial matching on report reasons
   * and detected rule violations.
   *
   * Security considerations require this operation to be restricted to
   * authenticated users and moderators, as reports contain sensitive moderation
   * information. This is a read-only operation that provides visibility into
   * the content moderation system without allowing modification of report
   * data.
   *
   * This operation is critical for the system's content moderation
   * capabilities, ensuring that moderation teams can efficiently triage and
   * process reported content in a scalable manner. It provides the necessary
   * tooling to prioritize reports based on urgency and visibility with rich
   * filtering abilities.
   *
   * @param connection
   * @param body Search criteria, sorting options, pagination parameters, and
   *   report_type filter for filtering reports
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IPoliticalForumPostReport.IRequest,
  ): Promise<IPageIPoliticalForumPostReport.ISummary> {
    try {
      return await patchPoliticalForumModeratorReports({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
