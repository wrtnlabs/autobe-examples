import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getPoliticalForumReportsPostReportId } from "../../../../providers/getPoliticalForumReportsPostReportId";
import { CitizenAuth } from "../../../../decorators/CitizenAuth";
import { CitizenPayload } from "../../../../decorators/payload/CitizenPayload";

import { IPoliticalForumPostReport } from "../../../../api/structures/IPoliticalForumPostReport";

@Controller("/politicalForum/reports/post/:reportId")
export class PoliticalforumReportsPostController {
  /**
   * Retrieve a specific post report by its unique identifier.
   *
   * This operation fetches a single post report entity from the
   * political_forum_post_reports table based on the provided reportId. Reports
   * are created when users flag posts as inappropriate or violating community
   * guidelines.
   *
   * A successful response returns the complete post report details including
   * the reported post identifier, the reporter user ID, a description of the
   * violation, timestamps, and current status.
   *
   * Security considerations require this operation to be restricted to
   * authenticated users and moderators, as reports may contain sensitive
   * moderation metadata and private user information. The system ensures that
   * users can only access reports they created or have been granted permission
   * to view. The report ID must be validated against the database to prevent
   * unauthorized access attempts.
   *
   * This operation is typically used in moderation workflows where team members
   * need to review reported content. It supports the company's commitment to
   * responsible content moderation and user safety by providing detailed
   * context for each reported item. The response includes all available
   * information about the report to enable informed moderation decisions.
   *
   * @param connection
   * @param reportId Unique identifier of the post report to retrieve. This
   *   identifier references a post report entry from the
   *   political_forum_post_reports table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<IPoliticalForumPostReport> {
    try {
      return await getPoliticalForumReportsPostReportId({
        citizen,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
