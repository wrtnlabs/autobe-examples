import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postPoliticalForumCitizenCommentsCommentIdReports } from "../../../../../providers/postPoliticalForumCitizenCommentsCommentIdReports";
import { CitizenAuth } from "../../../../../decorators/CitizenAuth";
import { CitizenPayload } from "../../../../../decorators/payload/CitizenPayload";

import { IPoliticalForumCommentReport } from "../../../../../api/structures/IPoliticalForumCommentReport";

@Controller("/politicalForum/citizen/comments/:commentId/reports")
export class PoliticalforumCitizenCommentsReportsController {
  /**
   * Submit a report against a specific political forum comment.
   *
   * Citizens can report comments that violate community guidelines by
   * submitting detailed reports through this endpoint. The system automatically
   * prevents duplicate reports from the same citizen on the same comment to
   * avoid abusive reporting patterns. When a report is submitted, it's
   * immediately recorded in the political_forum_comment_reports table and
   * triggers a moderation review workflow.
   *
   * The operation requires the commentId path parameter to identify the target
   * comment and includes a request body with optional reason text and user
   * context. The system validates the citizen's authentication status before
   * processing and ensures the reported comment exists in the
   * political_forum_comments table.
   *
   * This operation does not modify the target comment but creates a new record
   * in political_forum_comment_reports, linking to the reporting citizen (from
   * political_forum_citizens) and the target comment. The system logs these
   * reports for moderation team review and may trigger automated actions based
   * on report volume patterns.
   *
   * All reports submitted via this endpoint are immutable and cannot be edited
   * or deleted after submission. Moderators can view these reports in their
   * dashboard and take appropriate actions including comment removal, warning
   * issuance, or account suspension.
   *
   * @param connection
   * @param commentId Unique identifier of the target political forum comment
   *   being reported. This must reference an existing comment in the
   *   political_forum_comments table.
   * @param body Details of the report being submitted, including optional
   *   reason text and reporting context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IPoliticalForumCommentReport.ICreate,
  ): Promise<IPoliticalForumCommentReport> {
    try {
      return await postPoliticalForumCitizenCommentsCommentIdReports({
        citizen,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
