import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postPoliticalForumCitizenPostsPostIdReports } from "../../../../../providers/postPoliticalForumCitizenPostsPostIdReports";
import { CitizenAuth } from "../../../../../decorators/CitizenAuth";
import { CitizenPayload } from "../../../../../decorators/payload/CitizenPayload";

import { IPoliticalForumPostReport } from "../../../../../api/structures/IPoliticalForumPostReport";

@Controller("/politicalForum/citizen/posts/:postId/reports")
export class PoliticalforumCitizenPostsReportsController {
  /**
   * Submit a report against a specific political forum post.
   *
   * Citizens can report posts that violate community guidelines by submitting
   * detailed reports through this endpoint. The system automatically prevents
   * duplicate reports from the same citizen on the same post to avoid abusive
   * reporting patterns. When a report is submitted, it's immediately recorded
   * in the political_forum_post_reports table and triggers a moderation review
   * workflow.
   *
   * The operation requires the postId path parameter to identify the target
   * post and includes a request body with optional reason text and user
   * context. The system validates the citizen's authentication status before
   * processing and ensures the reported post exists in the
   * political_forum_posts table.
   *
   * This operation does not modify the target post but creates a new record in
   * political_forum_post_reports, linking to the reporting citizen (from
   * political_forum_citizens) and the target post. The system logs these
   * reports for moderation team review and may trigger automated actions based
   * on report volume patterns.
   *
   * All reports submitted via this endpoint are immutable and cannot be edited
   * or deleted after submission. Moderators can view these reports in their
   * dashboard and take appropriate actions including post removal, warning
   * issuance, or account suspension.
   *
   * @param connection
   * @param postId Unique identifier of the target political forum post being
   *   reported. This must reference an existing post in the
   *   political_forum_posts table.
   * @param body Details of the report being submitted, including optional
   *   reason text and reporting context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IPoliticalForumPostReport.ICreate,
  ): Promise<IPoliticalForumPostReport> {
    try {
      return await postPoliticalForumCitizenPostsPostIdReports({
        citizen,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
