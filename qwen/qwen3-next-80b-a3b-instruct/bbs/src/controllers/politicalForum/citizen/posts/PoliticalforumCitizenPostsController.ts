import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postPoliticalForumCitizenPosts } from "../../../../providers/postPoliticalForumCitizenPosts";
import { CitizenAuth } from "../../../../decorators/CitizenAuth";
import { CitizenPayload } from "../../../../decorators/payload/CitizenPayload";
import { putPoliticalForumCitizenPostsPostId } from "../../../../providers/putPoliticalForumCitizenPostsPostId";
import { patchPoliticalForumCitizenPostsPostId } from "../../../../providers/patchPoliticalForumCitizenPostsPostId";

import { IPoliticalForumPost } from "../../../../api/structures/IPoliticalForumPost";

@Controller("/politicalForum/citizen/posts")
export class PoliticalforumCitizenPostsController {
  /**
   * Create a new political forum post.
   *
   * This operation allows authenticated citizens to create a new political
   * forum post. The post will be stored in the political_forum_posts table with
   * its title and body content as specified in business requirements (3-150
   * characters for title, 10-5000 characters for body). The system
   * automatically assigns the authenticated citizen as the author using their
   * citizen_id from the authentication token, and sets the post_state_id to the
   * default 'published' state.
   *
   * Security considerations include ensuring the authenticated user has a valid
   * citizen account (as defined in political_forum_citizens) and that the post
   * content complies with character length requirements. Rate limiting is
   * applied to prevent spam submissions. The system logs this creation event in
   * the political_forum_audit_logs table with actor_type of 'citizen'.
   *
   * This operation is available to any authenticated citizen and does not
   * require special permissions beyond basic authentication. Moderators cannot
   * use this operation to create posts on behalf of citizens - all posts must
   * be submitted through citizen accounts. The submitted content is subject to
   * review and may be later moderated according to the
   * political_forum_moderation_actions workflow.
   *
   * @param connection
   * @param body Creation data for a new political forum post including the
   *   title and body content.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedBody()
    body: IPoliticalForumPost.ICreate,
  ): Promise<IPoliticalForumPost> {
    try {
      return await postPoliticalForumCitizenPosts({
        citizen,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing political forum post.
   *
   * This operation allows the original author of a political forum post to edit
   * its content, subject to the 24-hour editing window defined in
   * political_forum_system_parameters (edit_window_hours = 24). After 24 hours,
   * the post becomes immutable and cannot be modified by the author.
   *
   * The operation validates that the authenticated user is the owner of the
   * post by verifying the citizen_id against the post's citizen_id in the
   * political_forum_posts table. If the user is not the author, the request is
   * rejected with appropriate authorization response.
   *
   * When a post is successfully updated, the system increases the edit_count
   * field by one and updates the updated_at timestamp. This change is logged in
   * the political_forum_audit_logs table with actor_type of 'citizen' and
   * target_type of 'post'. The previous state is stored in new_state and
   * old_state JSON fields for audit and transparency purposes.
   *
   * Only the title and body fields can be modified through this endpoint.
   * Fields like post_state_id, deleted_at, and created_at are protected and
   * cannot be changed via this API operation. This ensures system integrity and
   * prevents manipulation of post state outside the moderation workflow.
   *
   * @param connection
   * @param postId Unique identifier of the target political forum post that
   *   needs to be updated. This must match the id field in the
   *   political_forum_posts table.
   * @param body Update data for the political forum post containing the new
   *   title and body content.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":postId")
  public async update(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IPoliticalForumPost.IUpdate,
  ): Promise<IPoliticalForumPost> {
    try {
      return await putPoliticalForumCitizenPostsPostId({
        citizen,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific political forum post.
   *
   * This operation retrieves the complete details of a single political forum
   * post identified by its UUID. The response includes the post's title,
   * content, author, status (as defined in political_forum_post_states),
   * moderation status (as defined in political_forum_moderation_status),
   * creation and update timestamps, any associated attachments from
   * political_forum_post_attachments, and audit metadata.
   *
   * Although the political_forum_posts table supports multiple states and the
   * political_forum_post_modifications table tracks historical changes, this
   * endpoint returns only the current state of the post. The system
   * automatically applies any legal moderation actions (e.g., deletion,
   * locking, verification) and updates the status accordingly, making this
   * endpoint always return the live, visible state of the content.
   *
   * This is a PATCH method because, although it’s a retrieval operation, it
   * allows for advanced filtering and inclusion options (e.g., include
   * attachments, include comments) via the request body. Request body
   * parameters are optional and determine the level of detail returned. This
   * approach avoids complex query strings and aligns with our API design
   * standard for rich retrieval operations.
   *
   * The operation is accessible to all authenticated users. Moderators can view
   * posts with any status, while regular citizens can only view public,
   * non-deleted posts. The system enforces these restrictions at the business
   * logic layer, not through separate endpoint variants. Author information is
   * exposed as required by user need, but sensitive user data like contact
   * details is omitted.
   *
   * @param connection
   * @param postId Unique identifier of the political forum post to retrieve.
   *   This refers to a record in the political_forum_posts table. The post may
   *   be public, locked, or archived, but this endpoint returns its current
   *   state regardless of moderation history.
   * @param body Optional parameters to control the level of detail in the
   *   response, such as whether to include attachments and comments.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":postId")
  public async at(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("postId")
    postId: string,
    @TypedBody()
    body: IPoliticalForumPost.IRequest,
  ): Promise<IPoliticalForumPost> {
    try {
      return await patchPoliticalForumCitizenPostsPostId({
        citizen,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
