import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postPoliticalForumCitizenPostsPostIdComments } from "../../../../../providers/postPoliticalForumCitizenPostsPostIdComments";
import { CitizenAuth } from "../../../../../decorators/CitizenAuth";
import { CitizenPayload } from "../../../../../decorators/payload/CitizenPayload";
import { putPoliticalForumCitizenPostsPostIdCommentsCommentId } from "../../../../../providers/putPoliticalForumCitizenPostsPostIdCommentsCommentId";
import { deletePoliticalForumCitizenPostsPostIdCommentsCommentId } from "../../../../../providers/deletePoliticalForumCitizenPostsPostIdCommentsCommentId";

import { IPoliticalForumComment } from "../../../../../api/structures/IPoliticalForumComment";

@Controller("/politicalForum/citizen/posts/:postId/comments")
export class PoliticalforumCitizenPostsCommentsController {
  /**
   * Create a new comment on a political forum post in response to a specific
   * discussion thread. This operation allows authenticated citizens to
   * contribute to ongoing political discussions by posting new comments beneath
   * existing posts. Each created comment inherits its context from the parent
   * post and becomes part of the threaded conversation history.
   *
   * The comment creation workflow requires the user to be authenticated as a
   * citizen, as only registered and authenticated users are permitted to post
   * comments on the forum. The system verifies the user's authentication token
   * and associates the comment with the appropriate citizen identity via the
   * comment's userId field. Post IDs are validated to ensure the target post
   * exists and is not archived, preventing comments on non-existent or retired
   * discussion threads.
   *
   * The comment content is subject to validation rules defined in the business
   * requirements: text content must not exceed 2000 characters, and
   * inappropriate content will trigger moderation flags for review. The system
   * automatically assigns timestamps for creation and records the creator's
   * identity. No attachments can be included with comments through this
   * endpoint; if attachments are needed, they must be uploaded separately with
   * a dedicated attachment endpoint.
   *
   * After successful creation, the new comment is immediately visible on the
   * post's comment thread, and relevant subscribers may receive notification
   * alerts based on their preference settings. The system maintains referential
   * integrity by requiring the existence of the parent post ID before allowing
   * comment creation, ensuring a valid hierarchical structure.
   *
   * Error handling includes rejecting requests with invalid post IDs, missing
   * or empty comment content, unauthorized users, or comments exceeding
   * character limits. This operation does not allow duplicate comment
   * submission attempts within a short time window to prevent spam.
   *
   * This endpoint complements the GET /posts/{postId}/comments/{commentId}
   * operation by enabling the creation of new comments in the same hierarchical
   * context.
   *
   * @param connection
   * @param postId Unique identifier of the parent political forum post where
   *   the comment will be posted
   * @param body The content and metadata required to create a new political
   *   forum comment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("postId")
    postId: string,
    @TypedBody()
    body: IPoliticalForumComment.ICreate,
  ): Promise<IPoliticalForumComment> {
    try {
      return await postPoliticalForumCitizenPostsPostIdComments({
        citizen,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific comment on a political forum post.
   *
   * This operation allows authorized users to modify the content of an existing
   * comment on a political forum post. The comment is uniquely identified by
   * its postId and commentId parameters. Only the original author of the
   * comment or a moderator can update the comment content.
   *
   * The update operation replaces the entire comment content with the new data
   * provided in the request body. Partial updates are not supported - the
   * entire comment object must be provided with all fields filled out. The
   * system will update the modified_at timestamp automatically during this
   * operation.
   *
   * Security considerations include verifying the user's ownership of the
   * comment or moderator privileges before allowing the update. Rate limiting
   * is applied to prevent abuse of this endpoint. The operation will not allow
   * updates to comments that have been archived or deleted.
   *
   * @param connection
   * @param postId Unique identifier of the target political forum post (UUID
   *   format)
   * @param commentId Unique identifier of the target comment on the post (UUID
   *   format)
   * @param body Updated content and metadata for the political forum comment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IPoliticalForumComment.IUpdate,
  ): Promise<IPoliticalForumComment> {
    try {
      return await putPoliticalForumCitizenPostsPostIdCommentsCommentId({
        citizen,
        postId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific comment on a political forum post.
   *
   * This operation permanently removes a specific comment on a political forum
   * post from the system. The comment is uniquely identified by its postId and
   * commentId parameters. Only the original author of the comment or a
   * moderator can delete the comment.
   *
   * This is a hard delete operation that removes all data associated with the
   * comment permanently. Unlike moderation actions that mark comments as
   * hidden, this operation completely deletes the record from the database.
   * After deletion, the comment cannot be recovered.
   *
   * Security considerations include verifying the user's ownership of the
   * comment or moderator privileges before allowing deletion. Audit logs are
   * automatically generated to record this deletion action for compliance
   * purposes. The system will ensure that deletions cannot be performed on
   * comments that have already been archived or removed.
   *
   * @param connection
   * @param postId Unique identifier of the target political forum post (UUID
   *   format)
   * @param commentId Unique identifier of the target comment on the post (UUID
   *   format)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IPoliticalForumComment> {
    try {
      return await deletePoliticalForumCitizenPostsPostIdCommentsCommentId({
        citizen,
        postId,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
