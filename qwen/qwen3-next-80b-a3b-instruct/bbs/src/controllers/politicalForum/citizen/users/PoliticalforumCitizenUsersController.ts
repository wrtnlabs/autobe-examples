import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getPoliticalForumCitizenUsersUserId } from "../../../../providers/getPoliticalForumCitizenUsersUserId";
import { CitizenAuth } from "../../../../decorators/CitizenAuth";
import { CitizenPayload } from "../../../../decorators/payload/CitizenPayload";
import { putPoliticalForumCitizenUsersUserId } from "../../../../providers/putPoliticalForumCitizenUsersUserId";
import { patchPoliticalForumCitizenUsersUserId } from "../../../../providers/patchPoliticalForumCitizenUsersUserId";

import { IPoliticalForumCitizen } from "../../../../api/structures/IPoliticalForumCitizen";

@Controller("/politicalForum/citizen/users/:userId")
export class PoliticalforumCitizenUsersController {
  /**
   * Retrieve a citizen's profile information by user ID.
   *
   * This endpoint retrieves the complete profile information for a specific
   * citizen in the political forum system. The operation accesses the
   * political_forum_citizens table to fetch details about the citizen's account
   * including username, registration date, profile status, and other
   * identifying information.
   *
   * This operation returns sensitive user data and therefore requires
   * appropriate authentication. The system verifies the requesting user has
   * permission to view the target citizen's profile based on the application's
   * authorization framework. For privacy reasons, certain sensitive fields may
   * be redacted based on the requesting actor's permissions.
   *
   * The response uses IPoliticalForumCitizen.IPublic type for non-admin actors,
   * which excludes deleted_at, created_at, updated_at for security and
   * compliance. Admin actors receive the full IPoliticalForumCitizen entity
   * with system fields exposed. This ensures the system's audit trail remains
   * secure while still enabling administrative oversight.
   *
   * The operation is designed for use by other actors within the system to view
   * citizen profiles, such as when moderators need to investigate reports
   * submitted against users or when citizens view each other's profiles in
   * public forums.
   *
   * @param connection
   * @param userId The unique identifier of the target citizen in the political
   *   forum system (global scope). This is a system-generated UUID that
   *   uniquely identifies each citizen account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<IPoliticalForumCitizen.IPublic> {
    try {
      return await getPoliticalForumCitizenUsersUserId({
        citizen,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a citizen's profile information.
   *
   * This endpoint allows an authenticated citizen to update their profile
   * information in the political forum system. The operation performs a full
   * update of the political_forum_citizens record identified by the userId path
   * parameter.
   *
   * Only the citizen who owns the profile (matching the authenticated user's
   * ID) has permission to make these changes. The endpoint validates that the
   * requesting user matches the target user ID and rejects attempts to modify
   * other users' profiles.
   *
   * The update operation requires the complete profile data to be submitted in
   * the request body. All fields must be provided in the request, even if they
   * remain unchanged, as this is a full update (PUT) operation. Fields can be
   * updated to empty/null values to clear them from the profile, according to
   * the business rules defined in the political_forum_citizens table.
   *
   * The operation includes validation logic that checks the format of fields
   * like email addresses and ensures uniqueness constraints for fields like
   * username and email are maintained.
   *
   * After successfully updating the profile, the operation returns the complete
   * updated citizen record in the response, reflecting all changes made to the
   * profile.
   *
   * @param connection
   * @param userId The unique identifier of the citizen whose profile is being
   *   updated (global scope). This is a system-generated UUID that uniquely
   *   identifies each citizen account. The requesting user must have matching
   *   credentials.
   * @param body Complete updated profile information for the citizen. All
   *   fields from the political_forum_citizens table must be provided as this
   *   is a full update (PUT) operation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async putByUserid(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IPoliticalForumCitizen.IUpdate,
  ): Promise<IPoliticalForumCitizen> {
    try {
      return await putPoliticalForumCitizenUsersUserId({
        citizen,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a citizen's profile information.
   *
   * This endpoint allows an authenticated citizen to update their profile
   * information in the political forum system. The operation performs a partial
   * update of the political_forum_citizens record identified by the userId path
   * parameter.
   *
   * Only the citizen who owns the profile (matching the authenticated user's
   * ID) has permission to make these changes. The endpoint validates that the
   * requesting user matches the target user ID and rejects attempts to modify
   * other users' profiles.
   *
   * The update operation requires only the specific fields to be changed to be
   * provided in the request body. Fields not included in the request body
   * remain unchanged. System-managed fields such as created_at, updated_at, and
   * deleted_at are automatically managed by the database and must not be
   * included in the request.
   *
   * The operation includes validation logic that checks the format of fields
   * like email addresses and ensures uniqueness constraints for fields like
   * username and email are maintained.
   *
   * After successfully updating the profile, the operation returns the complete
   * updated citizen record in the response, reflecting all changes made to the
   * profile.
   *
   * @param connection
   * @param userId The unique identifier of the citizen whose profile is being
   *   updated (global scope). This is a system-generated UUID that uniquely
   *   identifies each citizen account. The requesting user must have matching
   *   credentials.
   * @param body Partial profile updates for the citizen. Include only the
   *   fields to be changed: username, email, avatar_url, bio, and
   *   opt_in_newsletter. System-managed fields (created_at, updated_at,
   *   deleted_at) must not be included.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async patchByUserid(
    @CitizenAuth()
    citizen: CitizenPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IPoliticalForumCitizen.IUpdate,
  ): Promise<IPoliticalForumCitizen> {
    try {
      return await patchPoliticalForumCitizenUsersUserId({
        citizen,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
