import { Prisma } from "@prisma/sdk";
import { ArrayUtil } from "@nestia/e2e";
import typia, { tags } from "typia";

import { IDiscussionBoardAttachmentFile } from "@ORGANIZATION/PROJECT-api/lib/structures/IDiscussionBoardAttachmentFile";

import { toISOStringSafe } from "../utils/toISOStringSafe";

export namespace DiscussionBoardAttachmentFileTransformer {
  export type Payload = Prisma.discussion_board_attachment_filesGetPayload<
    ReturnType<typeof select>
  >;
  export function select() {
    return {
      select: {
        id: true,
        filename: true,
        size_bytes: true,
        mime_type: true,
        sha256_hash: true,
        storage_path: true,
        created_at: true,
        updated_at: true,
        deleted_at: true,
        post: {
          select: {
            id: true,
          },
        },
        uploader: {
          select: {
            id: true,
          },
        },
        discussion_board_archives: {
          select: {
            id: true,
          },
        },
        discussion_board_audit_events: {
          select: {
            id: true,
          },
        },
      },
    } satisfies Prisma.discussion_board_attachment_filesFindManyArgs;
  }
  export async function transform(
    input: Payload,
  ): Promise<IDiscussionBoardAttachmentFile> {
    const extension = input.filename.split(".").pop() || "";
    const url = `https://cdn.example.com/files/${input.id}.${extension}`;
    const fileStatus = input.deleted_at ? "deleted" : "active";
    return {
      name: input.filename,
      mimetype: input.mime_type,
      extension,
      url,
      fileSize: input.size_bytes,
      uploadPath: input.storage_path,
      contentMd5: "", // Field doesn't exist in schema, use empty string
      contentSha256: input.sha256_hash,
      uploadAt: input.created_at.toISOString(),
      updatedAt: input.updated_at.toISOString(),
      updatedBy: input.uploader.id,
      createdBy: input.uploader.id,
      createdAt: input.created_at.toISOString(),
      isAutoGenerated: false,
      fileStatus,
      description: null, // Field doesn't exist in schema, use null
      is_primary: false, // Field doesn't exist in schema, use false
    };
  }
}
