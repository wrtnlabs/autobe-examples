export async function test_api_admin_request_review_by_regular_admin_denied(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create regular admin account
  const regularAdminConnection: api.IConnection = { host: connection.host };
  const regularAdmin = await authorize_admin_join(regularAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      grade: "regular",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(regularAdmin);
  // 2. Create member account
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(member);
  // 3. Member submits admin privilege request
  const adminRequest =
    await generate_random_discussion_board_member_admin_requests_create(
      memberConnection,
      {
        body: {
          reason: RandomGenerator.paragraph({ sentences: 3 }),
        } satisfies IDiscussionBoardAdminRequest.ICreate,
      },
    );
  typia.assert(adminRequest);
  // Verify initial state
  TestValidator.equals(
    "initial status is pending",
    adminRequest.status,
    "pending",
  );
  TestValidator.equals(
    "initial reviewed_at is null",
    adminRequest.reviewed_at,
    null,
  );
  TestValidator.equals("initial reviewer is null", adminRequest.reviewer, null);
  // 4. Regular admin attempts to review the request (should fail with 403)
  await TestValidator.httpError(
    "regular admin cannot review admin requests",
    403,
    async () => {
      await api.functional.discussionBoard.admin.admin_requests.review(
        regularAdminConnection,
        {
          adminRequestId: adminRequest.id,
          body: {
            status: "approved",
          } satisfies IDiscussionBoardAdminRequest.IReview,
        },
      );
    },
  );
  // 5. Request state remains unchanged - validated by the httpError above
  // The 403 error confirms the authorization check prevented the operation
}
