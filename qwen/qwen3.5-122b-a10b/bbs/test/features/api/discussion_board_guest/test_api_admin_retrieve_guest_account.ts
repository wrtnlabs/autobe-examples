export async function test_api_admin_retrieve_guest_account(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate admin
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(adminAuth);
  // 2. Generate random guest UUID for retrieval
  const guestId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  // 3. Retrieve guest account using admin connection
  const guest: IDiscussionBoardGuest =
    await api.functional.discussionBoard.admin.guests.at(adminConnection, {
      guestId,
    });
  typia.assert(guest);
  // 4. Validate business logic - guest ID should match requested ID
  TestValidator.equals("retrieved guest ID matches request", guest.id, guestId);
}
