/**
 * Test that non-administrator users cannot delete tags.
 *
 * This test validates proper authorization enforcement for tag deletion operations:
 * 1. Authenticate as admin and create a tag
 * 2. Authenticate as a regular member
 * 3. Attempt to delete the tag using member's authentication
 * 4. Verify the system returns a 403 Forbidden error
 */
export async function test_api_tag_deletion_non_admin_rejected(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates a tag
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(adminAuth);
  const tag = await generate_random_discussion_board_admin_tags_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 2 }),
      },
    },
  );
  typia.assert(tag);
  // 2. Authenticate as member
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(memberAuth);
  // 3. Attempt to delete tag as member (should fail)
  await TestValidator.httpError("member cannot delete tag", 403, async () => {
    await api.functional.discussionBoard.admin.tags.erase(memberConnection, {
      tagId: tag.id,
    });
  });
}
