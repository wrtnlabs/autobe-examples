export async function test_api_audit_log_access_denied_for_member(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate as member
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(1),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(memberAuth);
  // 2. Attempt to access audit log as member (should fail with 403)
  const auditLogId = typia.random<string & tags.Format<"uuid">>();
  // 3. Verify 403 Forbidden response for unauthorized access
  await TestValidator.httpError(
    "member should not access audit logs",
    403,
    async () => {
      await api.functional.discussionBoard.admin.audit_logs.at(
        memberConnection,
        {
          auditLogId,
        },
      );
    },
  );
}
