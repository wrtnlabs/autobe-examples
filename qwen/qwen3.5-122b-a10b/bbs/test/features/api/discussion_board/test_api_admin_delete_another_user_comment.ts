/**
 * Test that an administrator can delete a comment authored by another user for content moderation purposes.
 * The workflow should: (1) authenticate as admin via join, (2) create a discussion board section,
 * (3) authenticate as a regular member via join, (4) create an article in that section as the member,
 * (5) create a comment on the article as the member, (6) delete the member's comment using the admin endpoint.
 * This validates the content moderation capability where administrators can remove inappropriate content
 * regardless of ownership, as specified in the business rules for admin comment management.
 */
export async function test_api_admin_delete_another_user_comment(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(adminAuth);
  // 2. Create a discussion board section as admin
  const section = await generate_random_discussion_board_admin_sections_create(
    adminConnection,
    {},
  );
  typia.assert(section);
  // 3. Member setup - authenticate as regular member
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(memberAuth);
  // 4. Create an article in the section as the member
  const article = await generate_random_discussion_board_member_articles_create(
    memberConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 3 }),
        body: RandomGenerator.content({ paragraphs: 2 }),
        discussion_board_section_id: section.id,
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // 5. Create a comment on the article as the member
  const comment =
    await generate_random_discussion_board_member_articles_comments_create(
      memberConnection,
      {
        params: {
          articleId: article.id,
        },
      },
    );
  typia.assert(comment);
  // Validate comment was created by the member
  TestValidator.equals(
    "comment author matches member",
    comment.member.id,
    memberAuth.id,
  );
  // 6. Admin deletes the member's comment using admin endpoint
  await api.functional.discussionBoard.admin.articles.comments.erase(
    adminConnection,
    {
      articleId: article.id,
      commentId: comment.id,
    },
  );
}
