export async function test_api_comment_creation_article_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as member
  const memberConnection: api.IConnection = { host: connection.host };
  const auth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(auth);
  // 2. Attempt to create comment on non-existent article
  const invalidArticleId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError("article not found", 404, async () => {
    await api.functional.discussionBoard.member.articles.comments.create(
      memberConnection,
      {
        articleId: invalidArticleId,
        body: {
          content: RandomGenerator.paragraph({ sentences: 2 }),
        } satisfies IDiscussionBoardComment.ICreate,
      },
    );
  });
}
