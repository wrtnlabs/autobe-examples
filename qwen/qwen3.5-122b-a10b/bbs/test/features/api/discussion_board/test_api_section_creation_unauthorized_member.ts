export async function test_api_section_creation_unauthorized_member(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate a regular member
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 3 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(memberAuth);
  // 2. Attempt to create a section as a member (should fail with 403 Forbidden)
  await TestValidator.httpError(
    "member cannot create section - should return 403 Forbidden",
    403,
    async () => {
      await api.functional.discussionBoard.admin.sections.create(
        memberConnection,
        {
          body: {
            name: RandomGenerator.name(),
            description: RandomGenerator.paragraph({ sentences: 2 }),
          } satisfies IDiscussionBoardSection.ICreate,
        },
      );
    },
  );
}
