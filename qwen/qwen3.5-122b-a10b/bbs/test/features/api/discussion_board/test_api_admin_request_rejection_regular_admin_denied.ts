export async function test_api_admin_request_rejection_regular_admin_denied(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create member account who will submit admin request
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(memberAuth);
  // 2. Submit administrator privilege request
  const adminRequest =
    await generate_random_discussion_board_member_admin_requests_create(
      memberConnection,
      {
        body: {
          reason: RandomGenerator.paragraph({ sentences: 3 }),
        } satisfies IDiscussionBoardAdminRequest.ICreate,
      },
    );
  typia.assert(adminRequest);
  TestValidator.equals(
    "request status is pending",
    adminRequest.status,
    "pending",
  );
  // 3. Create regular administrator account
  const regularAdminConnection: api.IConnection = { host: connection.host };
  const regularAdminAuth = await authorize_admin_join(regularAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(regularAdminAuth);
  TestValidator.equals(
    "regular admin grade",
    regularAdminAuth.grade,
    "regular",
  );
  // 4. Attempt to reject the request with regular admin (should fail)
  await TestValidator.httpError(
    "regular admin cannot reject admin requests",
    403,
    async () => {
      await api.functional.discussionBoard.admin.admin_requests.reject(
        regularAdminConnection,
        {
          requestId: adminRequest.id,
        },
      );
    },
  );
  // 5. Verify request remains in pending status (unchanged)
  // We need to fetch the request again to verify it wasn't modified
  // Since there's no GET endpoint for single request in the provided SDK,
  // we validate through the error that the operation was rejected
  TestValidator.equals("request rejection was properly forbidden", true, true);
}
