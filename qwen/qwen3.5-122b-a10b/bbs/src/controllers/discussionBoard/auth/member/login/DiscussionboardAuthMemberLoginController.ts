import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardMember } from "../../../../../api/structures/IDiscussionBoardMember";
import { postDiscussionBoardAuthMemberLogin } from "../../../../../providers/postDiscussionBoardAuthMemberLogin";

@Controller("/discussionBoard/auth/member/login")
export class DiscussionboardAuthMemberLoginController {
  /**
   * Authenticate a registered member with email and password credentials to obtain JWT access and refresh tokens.
   *
   * This endpoint validates the provided email address and password against the stored credentials in the discussion_board_members table. The system first checks if a member account exists with the matching email address, then verifies the password using BCrypt comparison against the stored password_hash. Successful authentication results in the generation of both access and refresh tokens for session management.
   *
   * The endpoint enforces account status validation by checking the ban_status field before allowing login. Members with ban_status='banned' are denied access and receive a 403 Forbidden response including the ban_reason from the database. This ensures that administratively suspended accounts cannot authenticate even with valid credentials.
   *
   * Upon successful authentication, the system creates a session record in discussion_board_member_sessions with client context information (IP address, page href, referrer) for security auditing and connection tracking. The session includes a mandatory expired_at timestamp that enforces session timeout policies and prevents indefinite access.
   *
   * Security features include BCrypt password verification, ban status enforcement, session tracking with client context, and JWT token generation with appropriate expiration times. The access token expires after 1 hour while the refresh token remains valid for 30 days, enabling secure token renewal without requiring re-authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials including email address and password for member authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate email format and find matching discussion_board_members record by email
   * 2. Check if member exists and ban_status is 'active' (not banned)
   * 3. Verify password_hash matches provided password using BCrypt compare function
   * 4. If credentials invalid, return 401 Unauthorized with error message
   * 5. If member banned, return 403 Forbidden with ban_reason from discussion_board_members.ban_reason
   * 6. Generate access token (JWT) with payload: { member_id, email, display_name, ban_status, role='member', iat, exp=now()+1hour }
   * 7. Generate refresh token (JWT) with payload: { member_id, type='refresh', iat, exp=now()+30days }
   * 8. Create discussion_board_member_sessions record with: discussion_board_member_id, ip, href, referrer, created_at=now(), updated_at=now(), expired_at=now()+30days
   * 9. Update discussion_board_members.updated_at to current timestamp
   * 10. Return IDiscussionBoardMember.IAuthorized response with member_id, email, display_name, access_token, refresh_token, token_type='Bearer', expires_in=3600
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async signIn(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardMember.ILogin,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postDiscussionBoardAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
