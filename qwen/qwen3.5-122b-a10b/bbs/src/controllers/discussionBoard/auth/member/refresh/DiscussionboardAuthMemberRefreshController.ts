import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardMember } from "../../../../../api/structures/IDiscussionBoardMember";
import { postDiscussionBoardAuthMemberRefresh } from "../../../../../providers/postDiscussionBoardAuthMemberRefresh";

@Controller("/discussionBoard/auth/member/refresh")
export class DiscussionboardAuthMemberRefreshController {
  /**
   * Renew JWT access token using a valid refresh token without requiring member re-authentication.
   *
   * This endpoint enables members to obtain a new access token by presenting a valid refresh token, extending their session without requiring password re-entry. The system validates the refresh token's JWT signature and expiration, then verifies the associated member account exists and remains active (not banned). A valid session record must exist in discussion_board_member_sessions with an expired_at timestamp in the future.
   *
   * The refresh token validation process includes checking the member's ban_status to ensure administratively suspended accounts cannot renew their sessions. If the member has been banned since their last login, the refresh operation fails with a 403 Forbidden response including the ban_reason from the database.
   *
   * Upon successful validation, the endpoint generates both a new access token (1-hour expiration) and a new refresh token (30-day expiration), implementing token rotation for enhanced security. The session record in discussion_board_member_sessions is updated with the current timestamp to track refresh activity.
   *
   * Security considerations include refresh token rotation (new refresh token issued with each refresh), session validation against discussion_board_member_sessions table, ban status enforcement, and JWT signature verification. This pattern prevents unauthorized token reuse and enables immediate session invalidation when members are banned or sessions are terminated.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for JWT token renewal without re-authentication.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate refresh token JWT signature and expiration
   * 2. Extract member_id from refresh token payload
   * 3. Verify member_id exists in discussion_board_members table
   * 4. Check member ban_status is 'active' (not banned)
   * 5. Find valid session in discussion_board_member_sessions matching member_id where expired_at > now()
   * 6. If session invalid or expired, return 401 Unauthorized
   * 7. If member banned, return 403 Forbidden with ban_reason
   * 8. Generate new access token (JWT) with payload: { member_id, email, display_name, ban_status, role='member', iat, exp=now()+1hour }
   * 9. Generate new refresh token (JWT) with payload: { member_id, type='refresh', iat, exp=now()+30days }
   * 10. Update discussion_board_member_sessions.updated_at to current timestamp
   * 11. Return IDiscussionBoardMember.IAuthorized response with member_id, email, display_name, access_token, refresh_token, token_type='Bearer', expires_in=3600
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async refreshToken(
    @TypedBody()
    body: IDiscussionBoardMember.IRefresh,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postDiscussionBoardAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
