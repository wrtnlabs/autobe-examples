import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardMember } from "../../../../../api/structures/IDiscussionBoardMember";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { postDiscussionBoardAdminMembersMemberIdBan } from "../../../../../providers/postDiscussionBoardAdminMembersMemberIdBan";

@Controller("/discussionBoard/admin/members/:memberId/ban")
export class DiscussionboardAdminMembersController {
  /**
   * Ban a registered member account by creating a ban record and updating the member's access status.
   *
   * This operation is restricted to administrators only. When executed, it creates a new ban record in the ban_records table and updates the target member's ban_status to 'banned' with the provided ban reason. The ban record includes the administrator who performed the action, the reason for banning, and the timestamp.
   *
   * Banned users are prevented from logging in and accessing member-only features. Their existing articles and comments remain visible but they cannot create new content or modify existing content. The ban record persists in the system for audit trail purposes even after unbanning.
   *
   * Related operations: `GET /members/{memberId}` to view member details, `POST /members/{memberId}/unban` to restore access, `PATCH /ban-records` to view all banned users (admin only).
   *
   * Security considerations: Only administrators with appropriate privileges can execute this operation. The ban reason is required and will be visible to administrators reviewing ban records. All ban actions are logged in the audit trail.
   *
   * @param connection
   * @param memberId Target member's unique identifier (UUID)
   * @param body Ban action details including the reason for banning
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate the requesting user is an authenticated administrator with ban permissions
   * 2. Verify the target member exists by querying discussion_board_members.id = {memberId}
   * 3. Check if the member is already banned (ban_status = 'banned') - return conflict error if so
   * 4. Create a new ban record in discussion_board_ban_records with:
   *    - discussion_board_member_id = {memberId}
   *    - discussion_board_admin_id = current admin's ID
   *    - reason = request body reason
   *    - banned_at = current timestamp
   *    - unbanned_at = null
   * 5. Update the member record:
   *    - Set ban_status = 'banned'
   *    - Set ban_reason = request body reason
   * 6. Terminate any active sessions for the banned member from discussion_board_member_sessions
   * 7. Create an audit log entry in discussion_board_audit_logs
   * 8. Return the updated member information
   *
   * Error handling:
   * - 404 if member not found
   * - 409 if member already banned
   * - 403 if requester is not an admin
   * - 400 if reason is missing or empty
   * - 500 on database errors with transaction rollback
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async ban(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardMember.IBan,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await postDiscussionBoardAdminMembersMemberIdBan({
        admin,
        memberId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
