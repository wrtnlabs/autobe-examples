import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardAdmin } from "../../../../api/structures/IDiscussionBoardAdmin";
import { IPageIDiscussionBoardAdmin } from "../../../../api/structures/IPageIDiscussionBoardAdmin";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminAdminsAdminId } from "../../../../providers/getDiscussionBoardAdminAdminsAdminId";
import { patchDiscussionBoardAdminAdmins } from "../../../../providers/patchDiscussionBoardAdminAdmins";

@Controller("/discussionBoard/admin/admins")
export class DiscussionboardAdminAdminsController {
  /**
   * Retrieve a filtered and paginated list of administrator accounts on the discussion board platform.
   *
   * This operation provides administrative oversight capabilities, allowing authorized administrators to view all administrator accounts with search and filtering options. The endpoint supports filtering by administrator grade level (regular or super), partial matching on display names and email addresses, and date range filtering based on account creation timestamps.
   *
   * Pagination is supported with configurable page sizes and cursor-based navigation for efficient traversal of large result sets. Results can be sorted by creation date, display name, or grade level in ascending or descending order.
   *
   * Access is restricted to authenticated administrators only. Regular administrators can view the list but with reduced visibility on certain sensitive fields. Super administrators have full visibility across all administrator account information.
   *
   * The operation excludes soft-deleted administrator accounts from results unless explicitly requested with an admin-only flag. All access to this endpoint is logged in the audit trail for security compliance.
   *
   * @param connection
   * @param body Search criteria, filtering options, and pagination parameters for administrator list retrieval
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_admins table with soft-delete filtering (exclude deleted_at IS NOT NULL). Apply search filters from request body: grade (regular/super), display_name partial match, email partial match, date range for created_at. Implement pagination with cursor or offset-based approach. Sort by created_at, display_name, or grade. Return paginated results with summary fields (id, email, display_name, grade, created_at). Validate user is authenticated as admin. Super admins see all admins; regular admins see all admins but with limited visibility on sensitive fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAdmin.IRequest,
  ): Promise<IPageIDiscussionBoardAdmin.ISummary> {
    try {
      return await patchDiscussionBoardAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific administrator's profile information by their unique identifier.
   *
   * This operation returns detailed information about an administrator account including their display name, bio, grade level, and account timestamps. The password hash is excluded from the response for security reasons.
   *
   * The endpoint enforces soft delete validation, ensuring that deleted administrator accounts are not returned. Administrators with deleted_at timestamps set are considered inactive and will not be retrievable through this endpoint.
   *
   * This operation is typically used by administrators to view their own profile or by super administrators to review other administrator accounts during management workflows.
   *
   * @param connection
   * @param adminId Target administrator's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_admins table by id UUID. Validate admin exists and is not soft-deleted (deleted_at IS NULL). Return administrator profile information excluding password_hash. Apply soft delete check to prevent returning deleted accounts. No authorization scope check at service layer - authorization handled at middleware level.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAdmin> {
    try {
      return await getDiscussionBoardAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
