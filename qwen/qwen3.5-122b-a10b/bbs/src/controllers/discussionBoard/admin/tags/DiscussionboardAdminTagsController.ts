import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardTag } from "../../../../api/structures/IDiscussionBoardTag";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteDiscussionBoardAdminTagsTagId } from "../../../../providers/deleteDiscussionBoardAdminTagsTagId";
import { postDiscussionBoardAdminTags } from "../../../../providers/postDiscussionBoardAdminTags";
import { putDiscussionBoardAdminTagsTagId } from "../../../../providers/putDiscussionBoardAdminTagsTagId";

@Controller("/discussionBoard/admin/tags")
export class DiscussionboardAdminTagsController {
  /**
   * Create a new tag definition for article categorization and search filtering in the discussion board system.
   *
   * This operation is available to administrators only and manages the global tag vocabulary. Tags are reusable labels stored in the discussion_board_tags table that enable multi-dimensional categorization of articles beyond the single section assignment. Each tag can be associated with multiple articles through the discussion_board_article_tags junction table, and each article can have multiple tags.
   *
   * The tag entity includes the following fields from the discussion_board_tags schema:
   * - **id**: Auto-generated UUID primary key for tag identification
   * - **name**: Unique tag name (case-sensitive) used for article categorization and search filtering
   * - **description**: Optional text providing context about the tag's purpose and usage
   * - **created_at**: Timestamp when the tag was created (timestamptz)
   * - **updated_at**: Timestamp when the tag was last modified (timestamptz)
   * - **deleted_at**: Soft delete timestamp for archival purposes (NULL for active tags)
   *
   * Once created, tags become available for selection when members create or edit articles, enabling flexible content organization and discovery through tag-based filtering and search. The system enforces case-sensitive uniqueness on the name field to prevent duplicate tag entries.
   *
   * The system automatically trims leading and trailing whitespace from tag names before validation and storage. Empty tag names or names containing only whitespace characters are rejected with 400 Bad Request error.
   *
   * @param connection
   * @param body Tag creation information including unique name and optional description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new tag record in the discussion_board_tags table. Validate that tag name is non-empty string with at least one non-whitespace character. Check for existing tag with same name (case-sensitive uniqueness constraint). Trim leading/trailing whitespace from tag name before saving. Insert new tag record with generated UUID, current timestamps for created_at and updated_at, and null deleted_at. Return the created tag object with all fields. If tag name already exists, return 409 Conflict error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardTag.ICreate,
  ): Promise<IDiscussionBoardTag> {
    try {
      return await postDiscussionBoardAdminTags({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing discussion board tag's name and/or description. This operation modifies tag metadata that is shared across all articles using this tag for categorization.
   *
   * Tags serve as flexible categorization labels that articles can reference through a many-to-many relationship. When a tag is updated, all articles associated with that tag will reflect the updated tag information immediately. This makes tag updates a sensitive operation requiring administrator privileges to prevent unauthorized changes to the categorization system.
   *
   * The tag name must remain unique across all active (non-deleted) tags. Name comparison is case-sensitive, meaning "Technology" and "technology" would be treated as distinct tags. Attempting to update a tag's name to match an existing tag's name will result in a conflict error.
   *
   * This operation requires administrator authentication. Only users with admin or super admin privileges can modify tags, as changes affect the entire discussion board's content organization structure.
   *
   * Related operations:
   * - `GET /tags` - List all available tags for article categorization
   * - `GET /tags/{tagId}` - Retrieve detailed information about a specific tag
   * - `PATCH /articles` - Create or update articles with tag associations
   *
   * @param connection
   * @param tagId Target tag's unique identifier (UUID format)
   * @param body Tag update information containing name and/or description fields. At least one field must be provided.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_tags table by tagId. Verify tag exists and is not soft-deleted. Validate new name uniqueness against all non-deleted tags (case-sensitive comparison). Check user has admin authorization. Update name and/or description fields. Update updated_at timestamp. Return updated tag object. If name conflicts with existing tag, return 409 Conflict error. If tag not found, return 404 Not Found. If user lacks admin privileges, return 403 Forbidden.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":tagId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("tagId")
    tagId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardTag.IUpdate,
  ): Promise<IDiscussionBoardTag> {
    try {
      return await putDiscussionBoardAdminTagsTagId({
        admin,
        tagId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete a tag from the discussion board system by marking it as deleted.
   *
   * This operation removes a tag from active view and severs all associated article-tag relationships. When a tag is soft-deleted, the system sets the `deleted_at` timestamp on the tag record, making it invisible in normal tag listings while preserving the record for audit purposes.
   *
   * **Authorization Requirements**
   *
   * Only administrators have permission to delete tags. Regular members and guests cannot perform this operation. The system validates admin privileges before executing the deletion.
   *
   * **Deletion Behavior**
   *
   * The tag is soft-deleted by setting the `deleted_at` timestamp field. The record remains in the database for audit trail purposes but is excluded from normal query results. All article-tag associations in the discussion_board_article_tags junction table are automatically cleaned up through database cascade constraints when the tag is marked as deleted.
   *
   * **Related Operations**
   *
   * - `PATCH /tags` - List/search available tags (excludes soft-deleted tags)
   * - `GET /tags/{tagId}` - View tag details
   * - `POST /tags` - Create a new tag
   * - `PUT /tags/{tagId}` - Update tag information
   *
   * @param connection
   * @param tagId Target tag's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_tags table by tagId UUID. Verify user has admin authorization before proceeding. Perform permanent deletion by removing the tag record (bypass soft delete). Database cascade will automatically remove associated discussion_board_article_tags junction records. Return the deleted tag object for confirmation. If tag does not exist, return 404 Not Found. If user lacks admin privileges, return 403 Forbidden.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":tagId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("tagId")
    tagId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminTagsTagId({
        admin,
        tagId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
