  /**
   * Update a system-wide configuration setting by its unique key identifier.
   *
   * This operation allows administrators to modify platform-wide settings that control system behavior, feature flags, operational thresholds, and configuration parameters accessible across all domains. The setting is identified by its unique key, which must already exist in the system settings registry.
   *
   * **Security Considerations**:
   *
   * Only administrators with appropriate privileges can modify system settings. This operation requires admin authentication and authorization verification. Changes to system settings affect all platform users and operations, so access is strictly controlled to prevent unauthorized configuration modifications.
   *
   * **Business Logic**:
   *
   * The system validates that the setting key exists before applying updates. Only the `value` and `description` fields can be modified through this operation. The `id`, `created_at`, and `updated_at` fields are managed automatically by the system. The `deleted_at` field indicates whether the setting has been soft-deleted; attempting to update a soft-deleted setting will return a 400 Bad Request error. To modify a deleted setting, it must first be restored or a new setting with a different key must be created.
   *
   * **Validation Rules**:
   *
   * - The setting key must exist in the system settings table
   * - The setting must not be soft-deleted (deleted_at must be null)
   * - The value field accepts string representations of various data types (boolean, number, string, JSON)
   * - The description field is optional and can be null or empty
   * - All updates are logged in the audit trail for administrative accountability
   * - Concurrent modifications are detected via optimistic locking on updated_at timestamp
   *
   * **Related Operations**:
   *
   * - `GET /discussionBoard/admin/system/settings` - Retrieve list of all system settings
   * - `GET /discussionBoard/admin/system/settings/{settingKey}` - Retrieve a specific setting by key
   * - `POST /discussionBoard/admin/system/settings` - Create a new system setting (admin only)
   * - `DELETE /discussionBoard/admin/system/settings/{settingKey}` - Soft-delete a system setting (admin only)
   *
   * @param connection
   * @param settingKey Unique identifier key of the system setting to update (global scope)
   * @param body Update data for the system setting including value and optional description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implement PUT operation for updating discussion_board_system_settings table records.
   *
   * **Service Layer Logic**:
   *
   * 1. Validate authentication - verify user has admin role
   * 2. Query discussion_board_system_settings table by key = settingKey
   * 3. Check if setting exists - return 404 if not found
   * 4. Check if setting is soft-deleted (deleted_at IS NOT NULL) - return 400 if deleted
   * 5. Validate request body - value is required string, description is optional string
   * 6. Begin database transaction
   * 7. Update value and description fields
   * 8. Set updated_at to current timestamp
   * 9. Commit transaction
   * 10. Return updated setting entity
   *
   * **Database Query**:
   *
   * ```sql
   * UPDATE discussion_board_system_settings
   * SET value = $1, description = $2, updated_at = NOW()
   * WHERE key = $3 AND deleted_at IS NULL
   * RETURNING id, key, value, description, created_at, updated_at, deleted_at
   * ```
   *
   * **Error Handling**:
   *
   * - 401 Unauthorized - user not authenticated
   * - 403 Forbidden - user lacks admin privileges
   * - 404 Not Found - setting key does not exist
   * - 400 Bad Request - setting is soft-deleted or invalid request body
   * - 500 Internal Server Error - database transaction failure
   *
   * **Concurrency Control**:
   *
   * Use optimistic locking via updated_at timestamp. If concurrent updates occur, the second update will fail and should return a conflict error (409).
   *
   * **Audit Trail**:
   *
   * Log all system setting modifications in discussion_board_audit_logs table with administrator ID, setting key, old value, new value, and timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
