import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSecurityMonitoring } from "../../../../../api/structures/IDiscussionBoardSecurityMonitoring";
import { IPageIDiscussionBoardSecurityMonitoring } from "../../../../../api/structures/IPageIDiscussionBoardSecurityMonitoring";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchDiscussionBoardAdminMonitoringSecurity } from "../../../../../providers/patchDiscussionBoardAdminMonitoringSecurity";

@Controller("/discussionBoard/admin/monitoring/security")
export class DiscussionboardAdminMonitoringSecurityController {
  /**
   * Retrieve comprehensive security monitoring data for the discussion board platform.
   *
   * This endpoint provides administrators with a centralized view of security-related metrics, alerts, and audit events across the platform. It aggregates data from the discussion_board_audit_logs table, which serves as a centralized compliance and accountability mechanism tracking every significant action performed across the platform including article/comment CRUD operations, user bans/unbans, section management, and admin request approvals.
   *
   * The response includes:
   * - Failed login attempt statistics (total count, by IP address, time-based trends)
   * - Active ban records count from discussion_board_ban_records and recent ban activities
   * - Suspicious activity alerts based on anomaly detection patterns
   * - Recent security events including user bans, content deletions, and administrative actions
   * - Authentication security metrics for threat detection
   *
   * Access to this endpoint is restricted to administrator accounts (both regular and super administrators) to ensure sensitive security information remains protected. The endpoint supports optional date range filtering and pagination for large result sets through the request body parameters.
   *
   * Related operations:
   * - GET /monitoring/performance - For performance metrics and system health data
   * - GET /admin/bans - For detailed banned user list management
   * - GET /audit-logs - For comprehensive audit trail access
   *
   * @param connection
   * @param body Security monitoring query parameters including date range filtering and pagination
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query security monitoring data from multiple sources:
   * 1. Count failed login attempts from discussion_board_audit_logs (action_type containing 'login' failures) within specified date range
   * 2. Count active bans from discussion_board_ban_records (unbanned_at IS NULL)
   * 3. Retrieve recent security events from discussion_board_audit_logs (action_type in 'user.ban', 'user.unban', 'article.delete', 'comment.delete') ordered by created_at DESC
   * 4. Aggregate authentication failures by IP address for anomaly detection
   * 5. Apply pagination for security events list using page and limit parameters
   * 6. Filter by date range from startDate and endDate in request body
   * 7. Return aggregated metrics and paginated security event list
   * 8. Authorization: Require admin actor with appropriate permissions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardSecurityMonitoring.IRequest,
  ): Promise<IPageIDiscussionBoardSecurityMonitoring> {
    try {
      return await patchDiscussionBoardAdminMonitoringSecurity({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
