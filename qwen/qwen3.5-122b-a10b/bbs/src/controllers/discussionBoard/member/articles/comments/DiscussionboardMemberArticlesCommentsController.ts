import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardComment } from "../../../../../api/structures/IDiscussionBoardComment";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId";
import { postDiscussionBoardMemberArticlesArticleIdComments } from "../../../../../providers/postDiscussionBoardMemberArticlesArticleIdComments";
import { putDiscussionBoardMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/putDiscussionBoardMemberArticlesArticleIdCommentsCommentId";

@Controller("/discussionBoard/member/articles/:articleId/comments")
export class DiscussionboardMemberArticlesCommentsController {
  /**
   * Create a new comment on a specific article in the discussion board.
   *
   * This operation allows authenticated members to post comments on articles, contributing to the article's discussion thread. Comments are stored in a single-level structure without nested replies, displayed chronologically from oldest to newest based on the created_at timestamp.
   *
   * **Security and Validation**:
   *
   * - The requesting user must be authenticated with a valid JWT token from discussion_board_member_sessions
   * - The user must not have a banned status (ban_status must be 'active' in discussion_board_members table)
   * - The target article must exist and must not be soft-deleted (deleted_at must be NULL in discussion_board_articles)
   * - The comment content must be a non-empty string as required by the content column constraint
   *
   * **Data Relationships**:
   *
   * - The comment is associated with the article via discussion_board_article_id foreign key referencing discussion_board_articles.id
   * - The comment author is automatically set to the authenticated member via discussion_board_member_id foreign key referencing discussion_board_members.id
   * - Timestamps created_at and updated_at are automatically generated by the system as DB.Timestamptz values
   * - The deleted_at field is initialized to NULL, allowing future soft deletion while preserving the comment for audit purposes
   *
   * **Database Schema References**:
   *
   * - discussion_board_comments.content: "Comment text content. The actual message or response written by the member."
   * - discussion_board_comments.created_at: "Timestamp when the comment was initially created. Used for chronological ordering."
   * - discussion_board_comments.updated_at: "Timestamp when the comment was last modified. Updated on each edit operation."
   * - discussion_board_comments.deleted_at: "Timestamp when the comment was soft-deleted. Null if comment is active. Preserves audit trail while hiding from normal queries."
   *
   * **Related Operations**:
   *
   * - `PATCH /discussionBoard/member/articles/{articleId}/comments` - Retrieve all comments on an article with pagination
   * - `PUT /discussionBoard/member/comments/{commentId}` - Edit an existing comment (owner only)
   * - `DELETE /discussionBoard/member/comments/{commentId}` - Delete a comment (owner or administrator)
   *
   * @param connection
   * @param articleId Target article's unique identifier (global scope)
   * @param body Comment creation information including content text
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new comment on the specified article. Implementation steps: 1) Verify article exists and is not deleted by checking discussion_board_articles.deleted_at is null. 2) Verify authenticated member exists and is not banned (ban_status != 'banned'). 3) Validate comment content is non-empty string with length between 1 and maximum allowed characters. 4) Insert new record into discussion_board_comments with discussion_board_article_id from path, discussion_board_member_id from authentication context, content from request body, and timestamps set to current time. 5) Return the created comment with all fields. Error cases: article not found (404), article deleted (400), user banned (403), user not authenticated (401), empty content (400).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.ICreate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await postDiscussionBoardMemberArticlesArticleIdComments({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing comment's content on a specific article within the discussion board.
   *
   * This operation allows the authenticated comment author to modify their previously posted comment text. The system performs comprehensive ownership validation to ensure only the original comment creator can update their content, preserving the integrity of article discussions and author attribution.
   *
   * **Database Schema Reference**:
   *
   * The operation updates the `content` field of the `discussion_board_comments` table while automatically refreshing the `updated_at` timestamp. The `created_at` timestamp remains unchanged to preserve the original posting time for chronological display. The `deleted_at` field is checked to ensure the comment has not been soft-deleted.
   *
   * **Ownership and Authorization**:
   *
   * Only the member whose ID matches `discussion_board_member_id` on the comment record can perform updates. This ownership check occurs within a database transaction to prevent race conditions. Administrators do not have update privileges on other users' comments—they must use the delete endpoint for content moderation.
   *
   * **Validation Rules**:
   *
   * - Comment content must be a non-empty string between 1 and 10,000 characters
   * - Both the parent article and comment must exist and not be soft-deleted (`deleted_at IS NULL`)
   * - The comment must belong to the specified article (`discussion_board_article_id` matches `articleId`)
   * - The authenticated user must own the comment (`discussion_board_member_id` matches user ID)
   *
   * **Audit Trail**:
   *
   * The `updated_at` timestamp is automatically set to the current time on each modification, enabling users to identify recently edited comments. The original `created_at` timestamp is preserved throughout the comment's lifecycle.
   *
   * **Related Operations**:
   *
   * - `GET /discussionBoard/articles/{articleId}/comments` - Retrieve all comments on an article (sorted by `created_at` ascending)
   * - `DELETE /discussionBoard/articles/{articleId}/comments/{commentId}` - Permanently remove a comment (owner or administrator)
   * - `GET /discussionBoard/articles/{articleId}` - View the parent article with comment count
   * - `PUT /discussionBoard/member/profile` - Update own display name (propagates to all comments)
   *
   * @param connection
   * @param articleId UUID of the article containing the comment (global scope)
   * @param commentId UUID of the comment to update (global scope)
   * @param body Updated comment content text for the comment identified by the path parameter. The content must be a non-empty string between 1 and 10,000 characters after trimming whitespace.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update an existing comment on an article. Implementation steps:
   *
   * 1. Validate articleId and commentId are valid UUIDs
   * 2. Query discussion_board_comments table for comment with matching id
   * 3. Verify comment exists and is not soft-deleted (deleted_at IS NULL)
   * 4. Verify comment belongs to the specified article (discussion_board_article_id matches articleId)
   * 5. Query discussion_board_articles to verify article exists and is not soft-deleted
   * 6. Get current authenticated user from JWT token
   * 7. Verify user owns the comment (discussion_board_member_id matches user ID)
   * 8. Validate request body content: non-empty string, 1-10000 characters
   * 9. Update comment.content and comment.updated_at to current timestamp
   * 10. Return updated comment object with all fields
   *
   * Error cases:
   * - 404: Article not found or soft-deleted
   * - 404: Comment not found or soft-deleted
   * - 400: Comment belongs to different article than specified
   * - 403: User does not own the comment
   * - 400: Content validation fails (empty, too long)
   *
   * Admin override: Administrators cannot update other users' comments, only delete them.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardMemberArticlesArticleIdCommentsCommentId({
        member,
        articleId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a comment from an article through soft deletion.
   *
   * This operation deletes a specific comment by marking it as deleted via the deleted_at timestamp field. The comment content and author information are preserved in the database for audit purposes but hidden from normal queries and article comment listings.
   *
   * **Authorization Rules**:
   *
   * - **Comment Author**: Members can delete their own comments at any time
   * - **Administrators**: Admin users can delete any comment on any article for content moderation purposes, regardless of ownership
   * - **Banned Users**: Banned members cannot perform any comment operations including deletion
   *
   * **Deletion Behavior**:
   *
   * When a comment is deleted:
   * 1. The comment is soft-deleted via the deleted_at timestamp field on the discussion_board_comments table
   * 2. The comment is removed from the article's comment listing automatically
   * 3. The comment remains in the database for audit trail purposes
   * 4. Article comment count is automatically updated (computed dynamically from active comments)
   * 5. When the parent article is deleted, all associated comments are cascade deleted via database foreign key constraint
   *
   * **Related Operations**:
   *
   * - `GET /discussionBoard/articles/{articleId}/comments` - Retrieve all comments for an article
   * - `PUT /discussionBoard/comments/{commentId}` - Edit an existing comment
   * - `POST /discussionBoard/articles/{articleId}/comments` - Create a new comment on an article
   *
   * @param connection
   * @param articleId Target article's unique identifier (global scope)
   * @param commentId Target comment's unique identifier (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Delete a comment from an article. Implementation steps:
   *
   * 1. Validate articleId and commentId are valid UUIDs
   * 2. Fetch the comment by commentId from discussion_board_comments table
   * 3. Verify comment exists; return 404 if not found
   * 4. Verify comment is not already deleted (deleted_at is null); return 409 if already deleted
   * 5. Fetch the article by articleId to verify it exists
   * 6. Verify articleId matches comment's discussion_board_article_id; return 400 if mismatch
   * 7. Check authorization:
   *    - If current user is the comment author (discussion_board_member_id matches), allow deletion
   *    - If current user is an administrator, allow deletion
   *    - Otherwise return 403 Forbidden
   * 8. Check if current user is banned; return 403 if banned
   * 9. Set deleted_at to current timestamp (soft deletion)
   * 10. Update the discussion_board_comments record
   * 11. Return 204 No Content on success
   *
   * Edge cases:
   * - Comment not found: 404 Not Found
   * - Article not found: 404 Not Found
   * - Comment already deleted: 409 Conflict
   * - Unauthorized: 403 Forbidden
   * - Banned user: 403 Forbidden
   * - Article-comment ID mismatch: 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId(
        {
          member,
          articleId,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
