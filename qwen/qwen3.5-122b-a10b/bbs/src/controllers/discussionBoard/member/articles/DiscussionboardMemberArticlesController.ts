import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../api/structures/IPageIDiscussionBoardArticle";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberArticlesArticleId } from "../../../../providers/deleteDiscussionBoardMemberArticlesArticleId";
import { patchDiscussionBoardMemberArticlesSearch } from "../../../../providers/patchDiscussionBoardMemberArticlesSearch";
import { postDiscussionBoardMemberArticles } from "../../../../providers/postDiscussionBoardMemberArticles";
import { putDiscussionBoardMemberArticlesArticleId } from "../../../../providers/putDiscussionBoardMemberArticlesArticleId";

@Controller("/discussionBoard/member/articles")
export class DiscussionboardMemberArticlesController {
  /**
   * Create a new article in the discussion board with title, content, section assignment, and optional tags.
   *
   * This operation allows authenticated members to publish articles within a specific section. The article title and body are required fields that will be indexed for full-text search capabilities. Tags can be assigned for flexible categorization and search filtering.
   *
   * Security considerations:
   * - Only authenticated members can create articles
   * - Banned users are blocked from article creation
   * - Section must exist and be accessible
   * - Tags must exist in the system or will be validated
   *
   * The article is immediately visible in section lists upon successful creation. Article attachments (files and images) must be uploaded separately through dedicated attachment endpoints after article creation.
   *
   * Related operations:
   * - GET /articles - List articles with pagination and filtering
   * - GET /articles/{id} - View single article with full content
   * - PUT /articles/{id} - Edit existing article (owner only)
   * - DELETE /articles/{id} - Delete article (owner or admin)
   *
   * @param connection
   * @param body Article creation information including title, body content, section assignment, and optional tags
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Service layer implementation for article creation:
   *
   * 1. Authentication: Verify JWT token and extract member ID from session
   * 2. Ban check: Query discussion_board_members table to verify ban_status is 'active'
   * 3. Section validation: Query discussion_board_sections table to verify section exists and is not deleted
   * 4. Tag validation: For each tag in request, verify existence in discussion_board_tags table
   * 5. Create article: Insert into discussion_board_articles with title, body, section_id, member_id, timestamps
   * 6. Tag associations: For each validated tag, insert into discussion_board_article_tags junction table
   * 7. Transaction: All operations must be atomic - rollback on any failure
   * 8. Response: Return created article with generated UUID and computed fields
   *
   * Edge cases:
   * - Duplicate tag names in request: Deduplicate before validation
   * - Non-existent tags: Return validation error with missing tag names
   * - Section not found: Return 404 with section ID
   * - Banned user: Return 403 with ban status
   * - Title/body length validation: Enforce maximum character limits
   * - Concurrency: Use optimistic locking if section has concurrent modifications
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.ICreate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await postDiscussionBoardMemberArticles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing article's title, content, and associated tags.
   *
   * This operation allows the article owner to modify their article's title, body content, and tag assignments. Only the member who originally created the article can perform this update, unless an administrator with appropriate privileges is performing moderation actions.
   *
   * The update operation is atomic - all changes to title, body, and tags are applied together or rolled back if any part fails. This ensures data consistency and prevents partial updates that could leave the article in an inconsistent state.
   *
   * Tags are managed as part of the update request. The system will replace existing tag associations with the new set of tags provided in the request. If a tag does not exist, it will be created automatically. Duplicate tags in the request are deduplicated.
   *
   * Administrators can update any article for moderation purposes. However, regular members are strictly limited to updating only their own articles. Attempting to update another member's article will result in an authorization error.
   *
   * The article's updated_at timestamp is automatically refreshed to reflect when the modification occurred. The created_at timestamp remains unchanged to preserve the original publication date.
   *
   * @param connection
   * @param articleId Target article's unique identifier (UUID scope)
   * @param body Article update information including title, body content, and tag assignments
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implement article update with the following logic:
   *
   * 1. Validate authentication - extract JWT token from Authorization header, verify member session is valid and not expired
   * 2. Check ban status - reject if the authenticated member is banned
   * 3. Retrieve article by {articleId} UUID parameter - return 404 if not found
   * 4. Validate ownership - compare discussion_board_member_id with authenticated member's ID
   *    - If owner: proceed with update
   *    - If admin: check admin privileges and proceed
   *    - If neither: return 403 Forbidden
   * 5. Validate request body:
   *    - title: required, string, 1-200 characters
   *    - body: required, string, 10-10000 characters
   *    - tags: optional array of strings, max 10 tags, each tag 1-50 characters
   * 6. Begin database transaction:
   *    - Update article title and body in discussion_board_articles
   *    - Update updated_at timestamp to current time
   *    - Delete existing article-tag associations from discussion_board_article_tags
   *    - For each tag in request:
   *      - Find or create tag in discussion_board_tags
   *      - Create new article-tag association in discussion_board_article_tags
   *    - Commit transaction
   * 7. If any step fails, rollback transaction and return appropriate error
   * 8. Return updated article with all associations (tags, section, author)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":articleId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticle.IUpdate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await putDiscussionBoardMemberArticlesArticleId({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove an article from the discussion board platform with role-based deletion behavior.
   *
   * This operation deletes articles based on the requesting actor's authorization level. Members can only delete their own articles using soft deletion, while administrators can delete any article with permanent removal.
   *
   * **Member Deletion (Owner Only):**
   *
   * When a registered member deletes an article they own, the system marks the article as deleted by setting the `deleted_at` timestamp. The article becomes hidden from public views and listings but remains in the database for audit purposes. All associated comments and tag associations are also soft-deleted.
   *
   * **Administrator Deletion (Any Article):**
   *
   * When an administrator deletes an article (regardless of ownership), the system performs permanent deletion from the database. This completely removes:
   * - The article record
   * - All comments on the article
   * - All tag associations
   *
   * This operation is irreversible and intended for content moderation.
   *
   * **Authorization Requirements:**
   *
   * - Members can only delete articles they own (discussion_board_member_id matches current user)
   * - Administrators can delete any article regardless of ownership
   * - Banned users cannot perform this operation
   * - Guest users cannot perform this operation
   *
   * **Related Operations:**
   *
   * - `GET /discussionBoard/articles/{articleId}` - View article details before deletion
   * - `PATCH /discussionBoard/articles` - List articles with filtering
   *
   * @param connection
   * @param articleId Target article's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implement article deletion with role-based authorization:
   *
   * 1. **Authentication Check:**
   *    - Verify user is authenticated (JWT token valid)
   *    - Reject if user is banned (check discussion_board_members.ban_status)
   *    - Reject if user is guest (not a registered member)
   *
   * 2. **Article Existence Check:**
   *    - Query discussion_board_articles by id
   *    - Return 404 if article not found
   *    - Check if already deleted (deleted_at IS NOT NULL) - return 400
   *
   * 3. **Authorization Logic:**
   *    - If user is regular member:
   *      - Verify discussion_board_member_id matches current user
   *      - Return 403 if not owner
   *      - Perform SOFT DELETE: SET deleted_at = NOW()
   *      - Cascade soft delete to comments (SET deleted_at)
   *      - Cascade soft delete to article_tags (SET deleted_at)
   *    - If user is administrator:
   *      - Perform HARD DELETE: DELETE FROM discussion_board_articles WHERE id = {articleId}
   *      - CASCADE will automatically delete related comments, article_tags
   *      - File/image attachments handled by cascade or separate cleanup
   *
   * 4. **Database Operations:**
   *    - Member deletion: UPDATE discussion_board_articles SET deleted_at = NOW(), updated_at = NOW() WHERE id = {articleId}
   *    - Admin deletion: DELETE FROM discussion_board_articles WHERE id = {articleId}
   *    - Use transaction to ensure atomicity
   *
   * 5. **Response:**
   *    - Return 200 with deleted article summary
   *    - Include article id, title, deletion timestamp
   *
   * 6. **Error Handling:**
   *    - 401: Unauthorized (invalid/missing token)
   *    - 403: Forbidden (not owner or not admin)
   *    - 404: Not Found (article doesn't exist)
   *    - 400: Bad Request (already deleted)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":articleId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberArticlesArticleId({
        member,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of articles owned by the current authenticated member based on keyword queries and tag filters.
   *
   * This operation provides comprehensive search capabilities across the member's own article titles and content using PostgreSQL trigram indexing on the `discussion_board_articles.title` and `discussion_board_articles.body` columns for efficient full-text matching. Only articles where `discussion_board_member_id` matches the authenticated user's ID are returned.
   *
   * Tag filtering supports multiple tag selection with AND logic - an article must be associated with ALL specified tags to appear in results. Tag matching is case-insensitive for user convenience. If no tags are specified, tag filtering is not applied.
   *
   * Results are paginated with configurable page sizes and support sorting by publication date (newest or oldest first). The response includes article summaries optimized for list displays, with full article details available through the detail retrieval endpoint.
   *
   * Only authenticated members can perform this search operation. Soft-deleted articles (where `deleted_at` is not null) are automatically excluded from search results. The system preserves search queries in the response to allow users to modify their search terms when no results are found.
   *
   * @param connection
   * @param body Search criteria including keyword query, tag filters, pagination, and sorting parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query discussion_board_articles table with full-text search on title and body columns using gin_trgm_ops indexes. Join with discussion_board_article_tags and discussion_board_tags for tag filtering. Apply AND logic for multiple tags - article must have ALL specified tags. Filter out soft-deleted articles (deleted_at IS NULL). Implement cursor-based pagination with configurable page size (default 20). Sort by created_at descending (newest first) as default, support ascending order. Validate search query length (max 255 characters). Handle empty query by returning all articles. Validate tag names case-insensitively. Return empty array if no matches. Include pagination metadata (page, limit, total, totalPages).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("search")
  public async search(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardMemberArticlesSearch({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
