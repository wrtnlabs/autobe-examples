import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardMember } from "../../../../api/structures/IDiscussionBoardMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putDiscussionBoardMemberProfile } from "../../../../providers/putDiscussionBoardMemberProfile";

@Controller("/discussionBoard/member/profile")
export class DiscussionboardMemberProfileController {
  /**
   * Update the authenticated member's profile information including display name and bio text.
   *
   * This operation allows logged-in members to customize their public profile by updating their display name and optional bio description. The display name is required and must contain at least one non-whitespace character. When the display name changes, the system automatically reflects the new name across all existing articles and comments written by this user through the foreign key relationship.
   *
   * The bio field is optional and can be any text describing the member to other users. Bio text length is validated against maximum character limits defined in the business rules.
   *
   * Profile changes are persisted immediately and visible to all users who view this member's profile. The updated_at timestamp is refreshed on every profile modification.
   *
   * This operation requires valid member authentication via JWT token in the Authorization header. Banned users cannot access this endpoint. Users can only update their own profile, not other members' profiles.
   *
   * @param connection
   * @param body Profile update information including display name and bio
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update authenticated user's profile in discussion_board_members table. Extract user ID from JWT authentication token. Validate display_name is not empty and within length limits. Bio is optional and can be empty string or null. Update display_name and bio fields, set updated_at to current timestamp. Persist changes immediately. Reflect display_name change across all user's articles and comments (update author_name fields in discussion_board_articles and discussion_board_comments tables). Return updated user profile with all fields including ban_status, created_at, updated_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardMember.IUpdate,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await putDiscussionBoardMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
