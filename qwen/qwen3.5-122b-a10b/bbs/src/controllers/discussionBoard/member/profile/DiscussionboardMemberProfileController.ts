import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardMember } from "../../../../api/structures/IDiscussionBoardMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getDiscussionBoardMemberProfile } from "../../../../providers/getDiscussionBoardMemberProfile";
import { putDiscussionBoardMemberProfile } from "../../../../providers/putDiscussionBoardMemberProfile";

@Controller("/discussionBoard/member/profile")
export class DiscussionboardMemberProfileController {
  /**
   * Retrieve the complete profile information for the currently authenticated member account.
   *
   * This operation returns the member's public identity data including their display name which appears on all articles and comments, optional bio text providing additional context about themselves, and current ban status which determines access permissions. The profile serves as the member's public identity within the discussion board community.
   *
   * The response includes the display_name field used to identify the member in the discussion board, the optional bio field providing additional context about the member to other users, and the ban_status field controlling login and content access permissions. All timestamps (created_at, updated_at) are included for audit purposes.
   *
   * Authentication is required for this operation - only the member themselves can access their profile through this endpoint. Other users viewing a member's profile should use the member-specific endpoint with the member ID parameter. The profile information is updated whenever the member modifies their display name or bio through the profile editing operation.
   *
   * Related operations include profile editing (PUT /discussionBoard/member/profile) for updating display name and bio, password change (PUT /discussionBoard/member/password) for credential updates, and member profile viewing (GET /discussionBoard/members/{memberId}) for viewing other members' public profiles.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query discussion_board_members table for the authenticated member's record using session token. Extract id, display_name, bio, ban_status, ban_reason, created_at, updated_at fields. Join with discussion_board_articles and discussion_board_comments tables to retrieve article and comment counts or summaries for the member. Apply soft delete check (deleted_at IS NULL) to ensure account is active. Return member profile data with related content lists. Validate that the authenticated member ID matches the session token. Handle ban status - banned members can still view their profile but with restricted access indicators.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await getDiscussionBoardMemberProfile({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated member's profile information including display name and bio text.
   *
   * This operation allows a logged-in member to modify their public profile information stored in the discussion_board_members table. The display name is a required field that will be shown on all the member's articles and comments throughout the discussion board. The bio text is optional and provides additional context about the member to other users viewing their profile.
   *
   * **Security Considerations**
   *
   * Only the authenticated member can update their own profile record. The member identity is derived from the JWT authentication token in the request header, not from path parameters. The system validates that the authenticated member ID matches the profile being updated. Any attempt to modify another member's profile will be rejected with a 403 Forbidden response.
   *
   * **Data Validation**
   *
   * - Display name must be provided and cannot be null, empty, or whitespace-only after trimming
   * - Display name length must not exceed 100 characters
   * - Bio text is optional and can be null, empty string, or up to 500 characters
   * - All changes are persisted immediately to the discussion_board_members table and the updated_at timestamp is refreshed
   *
   * **Soft Delete Handling**
   *
   * This operation respects the soft delete mechanism. If the member account has been soft-deleted (deleted_at is not null), the update will fail with a 404 Not Found response. The soft-deleted account cannot be modified until it is restored.
   *
   * **Related Operations**
   *
   * - `GET /discussionBoard/member/profile` - Retrieve the current authenticated member's profile information
   * - `GET /discussionBoard/members/{memberId}` - View another member's public profile by member ID
   * - `PATCH /discussionBoard/members` - List and search members with pagination and filters
   *
   * @param connection
   * @param body Profile update payload containing display name (required) and bio text (optional). Display name must be non-empty after trimming and cannot exceed 100 characters. Bio text can be null, empty, or up to 500 characters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Service layer implementation for member profile update:
   *
   * 1. Extract authenticated member ID from JWT token/session
   * 2. Query discussion_board_members table by id
   * 3. Validate member exists and is not deleted (deleted_at is null)
   * 4. Validate request body:
   *    - display_name: required, non-empty string, max length (check validation rules)
   *    - bio: optional string, max length (check validation rules)
   * 5. Update display_name and bio fields
   * 6. Update updated_at timestamp to current time
   * 7. Persist changes to database
   * 8. Return updated member record with full profile information
   *
   * Edge cases:
   * - Member not found: return 404
   * - Member deleted: return 404
   * - Invalid display_name (empty): return 400 with validation error
   * - Bio exceeds max length: return 400 with validation error
   * - Concurrent modification: handle via updated_at check or optimistic locking
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardMember.IUpdate,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await putDiscussionBoardMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
