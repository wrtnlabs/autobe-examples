import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardMember } from "../../../api/structures/IDiscussionBoardMember";
import { IPageIDiscussionBoardMember } from "../../../api/structures/IPageIDiscussionBoardMember";
import { getDiscussionBoardMembersMemberId } from "../../../providers/getDiscussionBoardMembersMemberId";
import { patchDiscussionBoardMembers } from "../../../providers/patchDiscussionBoardMembers";

@Controller("/discussionBoard/members")
export class DiscussionboardMembersController {
  /**
   * Retrieve a filtered and paginated list of discussion board member accounts.
   *
   * This operation provides search capabilities for browsing member accounts with filtering by display name, email, ban status, and registration date range. The endpoint supports various use cases including community browsing, user management, and administrative oversight.
   *
   * Supports comprehensive pagination with configurable page sizes and multiple sorting options. Response includes member summary information optimized for list displays, with optional article and comment counts for activity metrics when requested in the search criteria.
   *
   * Access permissions vary by actor role: guests can browse basic member information, members have standard access, and administrators can utilize additional filtering options including ban status management.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for member listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_members table with pagination and filtering. Apply search filters on display_name (partial match), email (partial match), ban_status (exact match). Support sorting by created_at (ascending/descending) and display_name (ascending/descending). Implement cursor-based or offset-based pagination with configurable page size (default 20, max 100). Exclude deleted_at records unless explicitly requested by admin. Join with discussion_board_articles and discussion_board_comments for article/comment counts if requested. Validate pagination parameters (page >= 1, limit between 1-100). Return paginated member summaries with essential fields: id, display_name, bio, ban_status, created_at, article_count, comment_count.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardMember.IRequest,
  ): Promise<IPageIDiscussionBoardMember.ISummary> {
    try {
      return await patchDiscussionBoardMembers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a public member profile from the discussion board.
   *
   * This operation allows any user (guests and authenticated members) to view another member's public profile information. The profile displays the member's display name, bio text, and counts of their articles and comments.
   *
   * Sensitive information including email address, password hash, ban status, and ban reason are explicitly excluded from the response to protect user privacy. Soft-deleted members (deleted_at is set) return a 404 Not Found error.
   *
   * The operation queries the discussion_board_members table by member ID and joins with discussion_board_articles and discussion_board_comments tables to calculate article and comment counts. Banned users' profiles remain publicly viewable as their content stays visible per the platform's content retention policy.
   *
   * Related operations:
   * - GET /members/{memberId}/articles - List articles written by this member
   * - GET /members/{memberId}/comments - List comments written by this member
   *
   * @param connection
   * @param memberId Target member's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_members table by id (UUID). Return public profile information excluding sensitive fields (email, password_hash, ban_status, ban_reason). Check if member is soft-deleted (deleted_at IS NOT NULL) and return 404 if so. Join with discussion_board_articles and discussion_board_comments to count articles and comments written by the member. Apply row-level security to ensure banned users' profiles are still viewable (content remains visible per requirements). Return 404 if member not found. Response includes: id, displayName, bio, articleCount, commentCount, createdAt, updatedAt.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":memberId")
  public async at(
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardMember.ISummary> {
    try {
      return await getDiscussionBoardMembersMemberId({
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
