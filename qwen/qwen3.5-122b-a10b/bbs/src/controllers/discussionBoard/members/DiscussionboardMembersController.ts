import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardMember } from "../../../api/structures/IDiscussionBoardMember";
import { IPageIDiscussionBoardMember } from "../../../api/structures/IPageIDiscussionBoardMember";
import { getDiscussionBoardMembersMemberId } from "../../../providers/getDiscussionBoardMembersMemberId";
import { patchDiscussionBoardMembers } from "../../../providers/patchDiscussionBoardMembers";

@Controller("/discussionBoard/members")
export class DiscussionboardMembersController {
  /**
   * Retrieve a filtered and paginated list of registered discussion board member accounts.
   *
   * This operation provides comprehensive search capabilities for browsing member accounts with filtering by display name, email address, ban status, and registration date range. It supports cursor-based pagination for efficient navigation through large result sets.
   *
   * The endpoint is primarily designed for administrators who need to manage member accounts, review user registrations, and monitor ban status. Members may also use this endpoint to browse the community with appropriate access restrictions.
   *
   * Search filters include partial matching for display_name and email fields, exact matching for ban_status, and range queries for registration dates. Results are sorted by registration date (newest first) by default, with configurable sorting options.
   *
   * Soft-deleted accounts (where deleted_at is set) are excluded from search results to ensure only active and logically existing accounts are returned. Ban status filtering allows administrators to quickly identify banned or active members.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for member account listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_members table with cursor-based pagination and filtering capabilities. Apply search filters on display_name (partial match), email (partial match), ban_status (exact match: 'active' or 'banned'), and created_at date range. Sort by created_at descending by default, with configurable sort order. Exclude soft-deleted records (deleted_at IS NOT NULL). Return paginated results with cursor for next page navigation. Implement proper indexing on ban_status and created_at for query performance.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardMember.IRequest,
  ): Promise<IPageIDiscussionBoardMember.ISummary> {
    try {
      return await patchDiscussionBoardMembers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a member's public profile information from the discussion board by querying the discussion_board_members table.
   *
   * This operation provides access to a member's identity information including their display_name, bio, and ban_status fields from the discussion_board_members table. The endpoint is accessible to both guests and authenticated members, enabling profile discovery and content attribution without requiring authentication.
   *
   * The response includes computed article_count and comment_count values calculated by querying the discussion_board_articles and discussion_board_comments tables respectively. These counts reflect only non-deleted content (where deleted_at IS NULL) to ensure accuracy. Sensitive information such as email, password_hash, and ban_reason are never exposed through this endpoint as they are excluded from the response schema.
   *
   * Related operations include:
   * - PATCH /discussionBoard/members (list all members with pagination and filtering via discussion_board_members table)
   * - GET /discussionBoard/members/{memberId}/articles (retrieve member's articles from discussion_board_articles table)
   * - GET /discussionBoard/members/{memberId}/comments (retrieve member's comments from discussion_board_comments table)
   *
   * @param connection
   * @param memberId Target member's unique identifier (UUID scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_members table by id UUID primary key. Verify the member record exists and is not soft-deleted (deleted_at IS NULL). Return public profile fields: id, display_name, bio, ban_status, created_at, updated_at. Calculate article_count and comment_count by querying discussion_board_articles and discussion_board_comments tables with member_id foreign key. Exclude sensitive fields: email, password_hash, ban_reason. Handle NOT_FOUND error when member id does not exist or is soft-deleted. Apply row-level security to prevent access to deleted members.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":memberId")
  public async at(
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await getDiscussionBoardMembersMemberId({
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
