import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardTag } from "../../../api/structures/IDiscussionBoardTag";
import { IPageIDiscussionBoardTag } from "../../../api/structures/IPageIDiscussionBoardTag";
import { getDiscussionBoardTagsTagId } from "../../../providers/getDiscussionBoardTagsTagId";
import { patchDiscussionBoardTags } from "../../../providers/patchDiscussionBoardTags";

@Controller("/discussionBoard/tags")
export class DiscussionboardTagsController {
  /**
   * Retrieve a filtered and paginated list of discussion board tags available for article categorization.
   *
   * This operation provides tag discovery capabilities allowing users to search for existing tags by name pattern, view tag creation dates, and optionally see how many articles are using each tag. Tags are reusable categorization labels that can be attached to multiple articles, enabling flexible content organization beyond single-section assignment.
   *
   * The endpoint supports comprehensive search filters including partial name matching (case-insensitive), creation date ranges, and sorting options. Results are paginated to handle large tag collections efficiently. This operation is accessible to guest users without authentication.
   *
   * Tags displayed through this endpoint can be referenced when creating or editing articles to categorize content. Each tag may be associated with zero or more articles through the discussion_board_article_tags junction table. Soft-deleted tags (those with deleted_at set) are automatically excluded from results by default.
   *
   * @param connection
   * @param body Tag search criteria, pagination parameters, and sorting options
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_tags table with pagination and filtering. Apply search filters on tag name using case-insensitive partial matching. Support date range filtering on created_at. Return cursor-based or offset-based pagination results. Sort by name alphabetically, creation date (newest/oldest), or usage count (number of articles using the tag). Implement soft delete filtering to exclude tags with deleted_at set. For usage count, join with discussion_board_article_tags table and count distinct article references. Validate pagination parameters: page >= 1, limit between 1 and 100. Apply database indexes on name and created_at for query performance.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardTag.IRequest,
  ): Promise<IPageIDiscussionBoardTag.ISummary> {
    try {
      return await patchDiscussionBoardTags({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific discussion board tag by its unique identifier.
   *
   * This operation returns comprehensive tag details including the tag name, optional description, and timestamps for creation and last modification. Tags are used for article categorization and search filtering across the discussion board system.
   *
   * The tag must exist and not be soft-deleted. If the tag has been deleted (deleted_at is not null), the system returns a 404 Not Found response. This endpoint supports both authenticated members and unauthenticated guests for viewing tag information.
   *
   * Tags enable multi-dimensional article categorization beyond section assignments. An article can belong to only one section but can have multiple tags for flexible discovery and organization.
   *
   * @param connection
   * @param tagId The unique identifier of the tag to retrieve (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_tags table by primary key id field. Apply soft delete filtering to exclude tags where deleted_at is not null. Return tag details including id, name, description, created_at, and updated_at. Join with discussion_board_article_tags to optionally include article count or associated article IDs if requested. Validate tagId is valid UUID format before database query. Return 404 Not Found if tag does not exist or is soft-deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":tagId")
  public async at(
    @TypedParam("tagId")
    tagId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardTag> {
    try {
      return await getDiscussionBoardTagsTagId({
        tagId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
