/**
 * Retrieve all tags associated with a specific discussion board article.
 *
 * This endpoint returns the complete list of tags that have been assigned to the specified article. Tags enable multi-dimensional categorization beyond the single section assignment, allowing articles to be discovered through multiple keyword-based filters.
 *
 * The operation queries the discussion_board_article_tags junction table to find all active tag associations for the article, then joins with discussion_board_tags to retrieve the tag metadata including name and optional description. Soft-deleted tags and articles are automatically filtered out from the results.
 *
 * This read-only operation is accessible to all actors (guest, member, admin) without authentication requirements, as tags are public metadata used for article discovery and search functionality.
 *
 * @param props.connection
 * @param props.articleId Target article's unique identifier (UUID format)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query discussion_board_article_tags junction table for all active (deleted_at IS NULL) tag associations with the specified article. Join with discussion_board_tags to retrieve tag name and description. Filter out soft-deleted tags and articles. Validate articleId is valid UUID format. Return array of tag summaries containing id, name, and description. Handle 404 if article not found or deleted. No authorization check needed as tags are publicly visible.
 * @path /discussionBoard/articles/:articleId/tags
 * @accessor api.functional.discussionBoard.articles.tags.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Target article's unique identifier (UUID format)
     */
    articleId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardTag.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/articles/:articleId/tags",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/tags`;
  export const random = (): IDiscussionBoardTag.ISummary =>
    typia.random<IDiscussionBoardTag.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
