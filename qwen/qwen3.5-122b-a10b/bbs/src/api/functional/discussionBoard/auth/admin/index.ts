/**
 * Register a new administrator account for the discussion board platform.
 *
 * This endpoint creates a new administrator account with email/password authentication credentials. The registration process validates email format, password security requirements, display name uniqueness, and ensures the email address is not already registered in the system.
 *
 * The newly created administrator account will have a 'regular' grade by default and must be approved through the administrator request workflow (submitted via /admin/requests endpoint) before gaining full administrative privileges. Until approved, the account has limited access to administrative features.
 *
 * Security considerations include bcrypt password hashing, email format validation, display name uniqueness checking, and prevention of duplicate email registrations. The system enforces minimum password complexity requirements and validates that the display name is not empty or whitespace-only.
 *
 * Related operations include /auth/admin/login for authentication after registration, and /admin/requests for submitting administrator privilege approval requests.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Administrator registration information including email, password, display name, and optional bio.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification 1. Validate request body: email format (regex), password strength (min length, complexity), display name (non-empty), optional bio (max length)
 * 2. Check email uniqueness in discussion_board_admins table
 * 3. Check display name uniqueness in discussion_board_admins table
 * 4. Hash password using bcrypt with appropriate cost factor
 * 5. Create new discussion_board_admins record with grade='regular', deleted_at=null
 * 6. Return IDiscussionBoardAdmin.IAuthorized response (note: new admin must still submit approval request)
 * 7. Error responses: 400 for validation failures, 409 for duplicate email/display name
 * @path /discussionBoard/auth/admin/join
 * @accessor api.functional.discussionBoard.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
