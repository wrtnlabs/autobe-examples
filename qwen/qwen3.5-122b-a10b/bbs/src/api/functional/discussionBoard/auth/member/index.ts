/**
 * Register a new member account with email/password authentication credentials and initiate email verification workflow.
 *
 * This endpoint creates a new member account in the discussion_board_members table with the provided email address, password, and display name. The system validates the email format and ensures uniqueness across all existing member accounts. The password is securely hashed using BCrypt with a cost factor of 12 before storage, ensuring that plaintext passwords are never persisted in the database.
 *
 * Upon successful registration, the system automatically generates an email verification token and creates a record in the discussion_board_member_email_verifications table. This token is sent to the provided email address and must be verified before the account becomes fully active. The verification token expires after 24 hours and can only be used once.
 *
 * The member account is created with ban_status set to 'active' by default, allowing immediate access to authenticated features after email verification. Optional bio information can be provided during registration to personalize the member profile. The display_name field is required and will be shown on all articles and comments authored by this member.
 *
 * Security considerations include email uniqueness validation, password strength requirements, and secure token generation for email verification. The system prevents duplicate account creation by enforcing the unique constraint on the email field at the database level.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Member registration information including email, password, display name, and optional bio for account creation.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification 1. Validate email format (RFC 5322) and check uniqueness against discussion_board_members.email (unique constraint)
 * 2. Validate password meets security requirements (min length, complexity)
 * 3. Validate display_name is not empty and within length limits
 * 4. Generate BCrypt hash of password using cost factor 12
 * 5. Create discussion_board_members record with: email, password_hash, display_name, bio (nullable), ban_status='active', created_at=now(), updated_at=now()
 * 6. Generate email verification token (cryptographically secure random string)
 * 7. Create discussion_board_member_email_verifications record with: discussion_board_member_id, token, expires_at=now()+24hours, verified_at=null
 * 8. Send verification email to provided email address with token
 * 9. Return IDiscussionBoardMember.IAuthorized response with member_id, email, display_name, access_token (JWT), refresh_token (JWT), token_type='Bearer', expires_in=3600
 * 10. JWT payload: { member_id, email, display_name, ban_status, role='member', iat, exp }
 * 11. Store refresh token in discussion_board_member_sessions with IP, href, referrer from request context
 * @path /discussionBoard/auth/member/join
 * @accessor api.functional.discussionBoard.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /**
     * Member registration information including email, password, display name, and optional bio for account creation.
     */
    body: IDiscussionBoardMember.IJoin;
  };
  export type Body = IDiscussionBoardMember.IJoin;
  export type Response = IDiscussionBoardMember.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/auth/member/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/auth/member/join";
  export const random = (): IDiscussionBoardMember.IAuthorized =>
    typia.random<IDiscussionBoardMember.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
