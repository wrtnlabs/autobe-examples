import { tags } from "typia";

import { IAuthorizationToken } from "./IAuthorizationToken";

export namespace IDiscussionBoardGuest {
  /**
   * Request body for refreshing guest JWT tokens. Contains the current refresh_token that will be validated and used to generate new access and refresh token pairs for continued guest session access.
   */
  export type IRefresh = {
    /**
     * Current refresh token for session renewal. This long-lived token allows obtaining new access tokens without requiring the guest to re-register.
     *
     * @x-autobe-specification JWT refresh token validated against discussion_board_guest_sessions table. Used to obtain new access and refresh token pairs without re-authentication. Must match stored refresh_token in session record and not be expired.
     */
    refresh_token: string;
  };

  /**
   * Request body for guest account registration. Creates a new guest identity identified by device fingerprint for unauthenticated browsing of sections, articles, and comments. The device fingerprint uniquely identifies the guest's device/browser combination. An optional display name can be provided to personalize the guest experience.
   */
  export type IJoin = {
    /**
     * Unique device fingerprint identifying the guest user across sessions. Generated from device characteristics for anonymous identification.
     *
     * @x-autobe-database-schema-property device_fingerprint
     * @x-autobe-specification Direct mapping from discussion_board_guests.device_fingerprint. Unique constraint enforced at database level via @@unique index.
     */
    deviceFingerprint: string & tags.MinLength<1>;
  };

  /**
   * Authorized guest response containing guest identifier and JWT tokens for session management. Returned after successful guest registration (join) or token refresh operations. Enables authenticated browsing of sections, articles, and comments without requiring email/password credentials.
   */
  export type IAuthorized = {
    /**
     * Unique identifier for the guest account.
     *
     * @x-autobe-database-schema-property id
     * @x-autobe-specification Direct mapping from discussion_board_guests.id. UUID primary key generated on guest registration.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Optional display name for personalizing the guest experience.
     *
     * @x-autobe-specification Optional display name from guest join request body. May not be persisted to database if not provided during registration.
     */
    displayName?: string | undefined;

    /**
     * Authorization token.
     *
     * @x-autobe-specification Authorization token comes from the session table.
     */
    token: IAuthorizationToken;
  };

  /**
   * Lightweight guest account summary for list views and references. Contains the device fingerprint that uniquely identifies the anonymous guest across sessions. Used for displaying guest identity in session listings and other contexts where full guest details are not required.
   */
  export type ISummary = {
    /**
     * Unique identifier for the guest account.
     *
     * @x-autobe-database-schema-property id
     * @x-autobe-specification Direct mapping from discussion_board_guests.id. UUID primary key generated by database.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Unique device fingerprint identifying the guest user across sessions.
     *
     * @x-autobe-database-schema-property device_fingerprint
     * @x-autobe-specification Direct mapping from discussion_board_guests.device_fingerprint. Unique device identifier generated from device characteristics for anonymous guest identification.
     */
    device_fingerprint: string;

    /**
     * Timestamp when the guest account was created.
     *
     * @x-autobe-database-schema-property created_at
     * @x-autobe-specification Direct mapping from discussion_board_guests.created_at. Timestamp when the guest account was created.
     */
    created_at: string & tags.Format<"date-time">;

    /**
     * Timestamp when the guest account was soft deleted, null if active.
     *
     * @x-autobe-database-schema-property deleted_at
     * @x-autobe-specification Direct mapping from discussion_board_guests.deleted_at. Nullable timestamp when the guest account was soft deleted. Null indicates active account.
     */
    deleted_at: (string & tags.Format<"date-time">) | null;
  };
}
