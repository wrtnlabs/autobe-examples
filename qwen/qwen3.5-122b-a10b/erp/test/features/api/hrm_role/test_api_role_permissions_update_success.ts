/**
 * Test updating permissions on a custom role within an organization.
 *
 * Validates the role permissions update workflow including member authentication, custom role creation, and permission modification. Ensures that the permission update operation correctly replaces all existing permissions with the provided list and returns the updated role with complete permission details.
 *
 * Special attention is given to verifying that the permission replacement is complete (no orphaned permissions remain) and that the role's other properties (name, organization, timestamps) remain unchanged during the permission update operation.
 *
 * 1. Member joins the system with email and password credentials.
 * 2. Member creates a custom role within an organization.
 * 3. Member updates the role's permissions with a new permission ID list.
 * 4. Validates the updated role contains exactly the new permissions.
 * 5. Verifies role metadata remains intact after permission update.
 */
export async function test_api_role_permissions_update_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Member joins the system
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IHrmMember.IJoin,
  });
  typia.assert(memberAuth);
  // 2. Create custom role (organization ID will be generated by system)
  const role = await generate_random_hrm_member_organizations_roles_create(
    memberConnection,
    {
      body: {
        name: RandomGenerator.name(2),
        description: RandomGenerator.paragraph({ sentences: 2 }),
      } satisfies IHrmRole.ICreate,
    },
  );
  typia.assert(role);
  // 3. Prepare new permission IDs from available permissions
  // Extract existing permission IDs and create a new subset (at least 1 permission)
  const existingPermissionIds = role.permissions.map((p) => p.id);
  const halfCount = Math.floor(existingPermissionIds.length / 2);
  const newPermissionIds: (string & tags.Format<"uuid">)[] =
    existingPermissionIds.length > 1
      ? existingPermissionIds.slice(0, Math.max(1, halfCount))
      : existingPermissionIds;
  // 4. Update role permissions
  const updatedRole = await api.functional.hrm.member.roles.permissions.update(
    memberConnection,
    {
      roleId: role.id,
      body: {
        permission_ids: newPermissionIds satisfies (string &
          tags.Format<"uuid">)[],
      } satisfies IHrmRole.IUpdatePermission,
    },
  );
  typia.assert(updatedRole);
  // 5. Validate updated role has exactly the new permissions
  TestValidator.equals("role id unchanged", updatedRole.id, role.id);
  TestValidator.equals("role name unchanged", updatedRole.name, role.name);
  TestValidator.equals(
    "organization unchanged",
    updatedRole.organization.id,
    role.organization.id,
  );
  TestValidator.equals(
    "permission count matches",
    updatedRole.permissions.length,
    newPermissionIds.length,
  );
  // 6. Validate all permissions in updated role are from the new set
  const updatedPermissionIds = updatedRole.permissions.map((p) => p.id);
  TestValidator.predicate(
    "all permissions are from new set",
    updatedPermissionIds.every((id) => newPermissionIds.includes(id)),
  );
  // 7. Validate no extra permissions remain (complete replacement)
  TestValidator.predicate(
    "no extra permissions remain",
    newPermissionIds.every((id) => updatedPermissionIds.includes(id)),
  );
}
