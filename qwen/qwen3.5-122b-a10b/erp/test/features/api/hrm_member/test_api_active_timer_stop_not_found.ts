export async function test_api_active_timer_stop_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as member
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmMember.IJoin,
  });
  // 2. Generate non-existent timer ID
  const nonExistentTimerId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  // 3. Attempt to stop non-existent timer - expect 404 error
  await TestValidator.httpError("timer not found", 404, async () => {
    await api.functional.hrm.member.active_timers.erase(memberConnection, {
      timerId: nonExistentTimerId,
    });
  });
}
