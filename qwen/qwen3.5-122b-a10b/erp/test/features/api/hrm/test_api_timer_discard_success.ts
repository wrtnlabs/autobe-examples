export async function test_api_timer_discard_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as member
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth: IHrmMember.IAuthorized = await authorize_member_join(
    memberConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
      } satisfies IHrmMember.IJoin,
    },
  );
  typia.assert(memberAuth);
  // 2. Create an active timer session (requires project)
  const timer: IHrmActiveTimer =
    await generate_random_hrm_member_active_timers_create(memberConnection, {
      body: {
        projectId: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IHrmActiveTimer.ICreate,
    });
  typia.assert(timer);
  // 3. Discard the active timer - returns void (204 No Content)
  await api.functional.hrm.member.active_timers.discard(memberConnection, {
    timerId: timer.id,
  });
}
