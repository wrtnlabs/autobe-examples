/**
 * Test updating a draft timesheet's week period dates.
 *
 * Validates the timesheet metadata update workflow by modifying the week_start_date of a draft timesheet. The test ensures that:
 * - The timesheet can be updated while in draft status
 * - The new week date forms a valid Monday-to-Sunday period (week_end_date calculated automatically)
 * - The total_hours is recalculated based on timelogs within the new week period
 * - The timesheet maintains its draft status after update
 *
 * The test follows this workflow:
 * 1. Register a new member and authenticate
 * 2. Create a draft timesheet for week 1 (Monday to Sunday)
 * 3. Update the timesheet to a different week period
 * 4. Validate the update succeeded with correct week dates
 * 5. Verify total_hours exists and is properly calculated
 *
 * Special attention is given to ensuring the week dates are valid (Monday start, Sunday end) and that the timesheet remains modifiable only in draft status.
 */
export async function test_api_timesheet_update_week_dates(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate member
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberAuth);
  // 2. Create draft timesheet for week 1 (Monday 2024-01-15 to Sunday 2024-01-21)
  // Note: organizationId and employeeId will be generated by the system
  const week1Start = new Date("2024-01-15T00:00:00Z");
  const timesheet1: IHrmTimesheetTimelog =
    await generate_random_hrm_member_organizations_timesheets_create(
      memberConnection,
      {
        body: {
          week_start_date: week1Start.toISOString(),
        },
      },
    );
  typia.assert(timesheet1);
  // 3. Validate initial timesheet state
  TestValidator.equals("initial status is draft", timesheet1.status, "draft");
  TestValidator.equals(
    "initial week_start_date matches week 1",
    new Date(timesheet1.week_start_date).toDateString(),
    week1Start.toDateString(),
  );
  // 4. Update timesheet to week 2 (Monday 2024-01-22 to Sunday 2024-01-28)
  // Only provide week_start_date - week_end_date is calculated automatically
  const week2Start = new Date("2024-01-22T00:00:00Z");
  const updatedTimesheet: IHrmTimesheetTimelog =
    await api.functional.hrm.member.organizations.timesheets.update(
      memberConnection,
      {
        organizationId: timesheet1.employee.organization.id,
        timesheetId: timesheet1.id,
        body: {
          week_start_date: week2Start.toISOString(),
        } satisfies IHrmTimesheetTimelog.IUpdate,
      },
    );
  typia.assert(updatedTimesheet);
  // 5. Validate update succeeded
  TestValidator.equals(
    "updated status remains draft",
    updatedTimesheet.status,
    "draft",
  );
  TestValidator.equals(
    "updated week_start_date matches week 2",
    new Date(updatedTimesheet.week_start_date).toDateString(),
    week2Start.toDateString(),
  );
  // 6. Verify week_end_date is calculated correctly (week_start_date + 6 days = Sunday)
  const expectedWeek2End = new Date(week2Start);
  expectedWeek2End.setDate(expectedWeek2End.getDate() + 6);
  TestValidator.equals(
    "week_end_date is week_start_date + 6 days",
    new Date(updatedTimesheet.week_end_date).toDateString(),
    expectedWeek2End.toDateString(),
  );
  // 7. Verify week dates are valid (Monday to Sunday)
  const startDay = new Date(updatedTimesheet.week_start_date).getDay();
  const endDay = new Date(updatedTimesheet.week_end_date).getDay();
  TestValidator.predicate("week starts on Monday", startDay === 1);
  TestValidator.predicate("week ends on Sunday", endDay === 0);
  // 8. Verify total_hours exists and is a number
  TestValidator.predicate(
    "total_hours is a number",
    typeof updatedTimesheet.total_hours === "number",
  );
  TestValidator.predicate(
    "total_hours is non-negative",
    updatedTimesheet.total_hours >= 0,
  );
}
