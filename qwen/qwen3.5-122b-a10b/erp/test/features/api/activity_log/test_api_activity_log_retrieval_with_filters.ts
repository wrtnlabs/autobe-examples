/**
 * Test retrieving paginated activity logs for an organization with various filtering options.
 *
 * Validates the activity log retrieval endpoint's ability to filter and paginate organization audit trails. Ensures that logs are returned in descending timestamp order by default, and that filters correctly narrow results.
 *
 * The test verifies pagination metadata accuracy including current page, limit, total records, and total pages. Each log entry should include performer information (member summary) and target entity details when applicable.
 *
 * 1. Create member account and authenticate.
 * 2. Retrieve activity logs with default parameters (no filters).
 * 3. Validate response structure and pagination metadata.
 * 4. Test filtering by action_type.
 * 5. Test filtering by performer_id.
 * 6. Test filtering by timestamp range.
 * 7. Validate descending timestamp order.
 * 8. Test pagination with different page sizes.
 */
export async function test_api_activity_log_retrieval_with_filters(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create member account and authenticate
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmMember.IJoin,
  });
  typia.assert(memberAuth);
  // Note: Activity logs are automatically generated by the system when actions occur.
  // Since we don't have functions to create activities directly, we test the retrieval
  // endpoint with the logs that exist in the system (may be empty or populated).
  // 2. Create organization code for testing
  const organizationCode = RandomGenerator.alphabets(8);
  // 3. Retrieve activity logs with default parameters (no filters)
  const defaultLogs =
    await api.functional.hrm.member.organizations.activity_logs.patchByOrganizationcode(
      memberConnection,
      {
        organizationCode,
        body: {
          page: 1,
          pageSize: 10,
        } satisfies IHrmActivityLog.IRequest,
      },
    );
  typia.assert(defaultLogs);
  // 4. Validate response structure and pagination metadata
  TestValidator.equals(
    "pagination exists",
    defaultLogs.pagination !== undefined,
    true,
  );
  TestValidator.predicate(
    "pagination current is positive",
    defaultLogs.pagination.current >= 1,
  );
  TestValidator.predicate(
    "pagination limit is positive",
    defaultLogs.pagination.limit > 0,
  );
  TestValidator.predicate(
    "pagination records is non-negative",
    defaultLogs.pagination.records >= 0,
  );
  TestValidator.predicate(
    "pagination pages is non-negative",
    defaultLogs.pagination.pages >= 0,
  );
  TestValidator.predicate("data is array", Array.isArray(defaultLogs.data));
  // 5. Test filtering by action_type
  const actionTypeFilter = "employee_invited";
  const filteredByActionType =
    await api.functional.hrm.member.organizations.activity_logs.patchByOrganizationcode(
      memberConnection,
      {
        organizationCode,
        body: {
          action_type: actionTypeFilter,
          page: 1,
          pageSize: 10,
        } satisfies IHrmActivityLog.IRequest,
      },
    );
  typia.assert(filteredByActionType);
  // All returned logs should match the action_type filter (only if data exists)
  if (filteredByActionType.data.length > 0) {
    const allMatchActionType = filteredByActionType.data.every(
      (log) => log.action_type === actionTypeFilter,
    );
    TestValidator.predicate(
      "all logs match action_type filter",
      allMatchActionType,
    );
  }
  // 6. Test filtering by performer_id
  if (defaultLogs.data.length > 0) {
    const performerId = defaultLogs.data[0].performer.id;
    const filteredByPerformer =
      await api.functional.hrm.member.organizations.activity_logs.patchByOrganizationcode(
        memberConnection,
        {
          organizationCode,
          body: {
            performer_id: performerId,
            page: 1,
            pageSize: 10,
          } satisfies IHrmActivityLog.IRequest,
        },
      );
    typia.assert(filteredByPerformer);
    // All returned logs should match the performer_id filter
    const allMatchPerformer = filteredByPerformer.data.every(
      (log) => log.performer.id === performerId,
    );
    TestValidator.predicate(
      "all logs match performer_id filter",
      allMatchPerformer,
    );
  }
  // 7. Test filtering by timestamp range
  const now = new Date();
  const oneDayAgo = new Date(now.getTime() - 24 * 60 * 60 * 1000);
  const filteredByTimestamp =
    await api.functional.hrm.member.organizations.activity_logs.patchByOrganizationcode(
      memberConnection,
      {
        organizationCode,
        body: {
          timestamp: {
            gte: oneDayAgo.toISOString(),
            lte: now.toISOString(),
          },
          page: 1,
          pageSize: 10,
        } satisfies IHrmActivityLog.IRequest,
      },
    );
  typia.assert(filteredByTimestamp);
  // All returned logs should be within the timestamp range (only if data exists)
  if (filteredByTimestamp.data.length > 0) {
    const allWithinRange = filteredByTimestamp.data.every((log) => {
      const logTime = new Date(log.timestamp);
      return logTime >= oneDayAgo && logTime <= now;
    });
    TestValidator.predicate("all logs within timestamp range", allWithinRange);
  }
  // 8. Validate descending timestamp order (default)
  if (defaultLogs.data.length > 1) {
    const isDescending = defaultLogs.data.every((log, index) => {
      if (index === 0) return true;
      const prevTime = new Date(defaultLogs.data[index - 1].timestamp);
      const currTime = new Date(log.timestamp);
      return prevTime >= currTime;
    });
    TestValidator.predicate("logs are in descending order", isDescending);
  }
  // 9. Test pagination with different page sizes
  const smallPageSize =
    await api.functional.hrm.member.organizations.activity_logs.patchByOrganizationcode(
      memberConnection,
      {
        organizationCode,
        body: {
          page: 1,
          pageSize: 5,
        } satisfies IHrmActivityLog.IRequest,
      },
    );
  typia.assert(smallPageSize);
  TestValidator.equals(
    "small page size limit",
    smallPageSize.pagination.limit,
    5,
  );
  TestValidator.predicate(
    "small page size data count",
    smallPageSize.data.length <= 5,
  );
  const largePageSize =
    await api.functional.hrm.member.organizations.activity_logs.patchByOrganizationcode(
      memberConnection,
      {
        organizationCode,
        body: {
          page: 1,
          pageSize: 50,
        } satisfies IHrmActivityLog.IRequest,
      },
    );
  typia.assert(largePageSize);
  TestValidator.equals(
    "large page size limit",
    largePageSize.pagination.limit,
    50,
  );
  TestValidator.predicate(
    "large page size data count",
    largePageSize.data.length <= 50,
  );
  // 10. Validate log entry structure (only if data exists)
  if (defaultLogs.data.length > 0) {
    const firstLog = defaultLogs.data[0];
    TestValidator.predicate("log has id", firstLog.id !== undefined);
    TestValidator.predicate(
      "log has timestamp",
      firstLog.timestamp !== undefined,
    );
    TestValidator.predicate(
      "log has action_type",
      firstLog.action_type !== undefined,
    );
    TestValidator.predicate(
      "log has performer",
      firstLog.performer !== undefined,
    );
    TestValidator.predicate(
      "performer has id",
      firstLog.performer.id !== undefined,
    );
    TestValidator.predicate(
      "performer has email",
      firstLog.performer.email !== undefined,
    );
  }
}
