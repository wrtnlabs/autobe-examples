/**
 * Guest account entity representing temporary device-based access for unauthenticated users.
 *
 * A guest account is created automatically when an unauthenticated user accesses the system, identified by a unique device fingerprint. This enables device-based tracking and temporary session management without requiring email registration or password authentication. Each device should have a unique fingerprint generated from browser/device characteristics.
 *
 * **Identification**
 *
 * The {@link device_fingerprint} field serves as the primary identifier for guest accounts, generated from browser and device characteristics. This enables recognition of returning devices without requiring user registration.
 *
 * **Lifecycle**
 *
 * Guest accounts support soft delete via the {@link deleted_at} field, allowing temporary deactivation while preserving historical data. Active guests have a null deleted_at value. The {@link id} is a UUID primary key assigned at creation.
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
