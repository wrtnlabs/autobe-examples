/**
 * Renew guest session tokens using a valid refresh token.
 *
 * This operation extends the guest session by issuing new access and refresh tokens when the current access token expires. The refresh token is single-use and becomes invalid after successful renewal to prevent token replay attacks.
 *
 * **Business Logic**
 *
 * The service validates the provided refresh token against the hrm_guest_sessions table. If valid and unused, it generates new access and refresh tokens, marks the old refresh token as consumed, and updates the session record. The guest continues their session without re-registration. If the guest account itself has expired (hrm_guests.expiresAt), the refresh is rejected even with a valid token.
 *
 * **Schema Fields**
 *
 * - hrm_guest_sessions: sessionId, guestId, accessToken, refreshToken, expiresAt, isConsumed
 * - hrm_guests: guestId, expiresAt (account-level expiration)
 *
 * **Security Considerations**
 *
 * Refresh tokens are single-use to prevent replay attacks. Each successful refresh invalidates the previous refresh token. Access tokens have short expiration (15-30 minutes) while refresh tokens last longer (typically 7-30 days) but are still subject to guest account expiration. Client must handle 401 responses by re-registering via join if refresh fails.
 *
 * **Related Operations**
 *
 * - IHrmGuest.IJoin: Initial guest registration when session is lost or expired
 * - No logout operation (JWT is stateless, client discards tokens)
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest token refresh request containing valid refresh token
 * @x-autobe-authorization-type refresh
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Renew guest session tokens using a valid refresh
 *   token. The service must: 1) Accept refreshToken from request body, 2)
 *   Validate the token exists in hrm_guest_sessions and is not expired, 3)
 *   Verify the token has not been used before (single-use refresh), 4)
 *   Invalidate the old refresh token, 5) Generate new access and refresh
 *   tokens, 6) Update hrm_guest_sessions with new tokens, 7) Return the
 *   IAuthorized response. Edge cases: expired token (401), already-used token
 *   (401), invalid format (400), guest account expired (401). Error handling:
 *   401 for invalid/expired tokens, 400 for malformed requests, 500 for token
 *   generation failures.
 * @path /hrm/auth/guest/refresh
 * @accessor api.functional.hrm.auth.guest.refresh
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
