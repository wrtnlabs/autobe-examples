/**
 * Register a new member account with email and password credentials.
 *
 * This operation creates a new member user account in the system. The member will need to verify their email address before accessing organization-scoped features. Upon successful registration, JWT access and refresh tokens are issued, though full organization access requires email verification completion.
 *
 * The operation performs the following steps:
 * - Validates email format and password strength requirements
 * - Checks for email uniqueness across all member accounts
 * - Creates a new hrm_members record with hashed password
 * - Generates an email verification token stored in hrm_member_email_verifications
 * - Returns authentication tokens with verification status
 *
 * Email verification is required before the member can select an organization and access scoped features. The verification token expires after 24 hours and supports single-use validation through the email verification endpoint.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration credentials for new member account creation.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification 1. Validate request body: email format, password
 *   strength (min 8 chars, alphanumeric). 2. Check email uniqueness in
 *   hrm_members table. 3. Create member record with hashed password (bcrypt).
 *   4. Generate email verification token, store in
 *   hrm_member_email_verifications with expiration. 5. Return IAuthorized with
 *   tokens and verification required flag. 6. If email already exists, return
 *   409 conflict. 7. Log activity in hrm_activity_logs.
 * @path /hrm/auth/member/join
 * @accessor api.functional.hrm.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
