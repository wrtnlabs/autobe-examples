/**
 * Retrieve budget utilization report for a specific project within an organization.
 *
 * This endpoint returns the budget hours allocated to the project, actual hours logged through timelogs, and the percentage of budget consumed. Projects without budget hours are excluded from this report.
 *
 * **Budget Tracking**
 *
 * The report calculates actual hours by summing all timelogs associated with the project. The percentage consumed is computed as (actual hours / budget hours) × 100. This information supports budget monitoring and capacity planning.
 *
 * **Access Control**
 *
 * Users with report:view permission within the organization can access this endpoint. The organization context is enforced through the path parameter for multi-tenancy data isolation.
 *
 * @param props.connection
 * @param props.organizationId Unique identifier of the organization (global scope).
 * @param props.projectId Unique identifier of the project within the organization (global scope).
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query hrm_projects table by organizationId and
 *   projectId to retrieve project details including budget_hours. Sum all
 *   duration_minutes from hrm_timelogs where hrm_project_id matches the
 *   projectId and deleted_at is null to calculate actual hours. Compute
 *   percentage consumed as (actualHours / budgetHours) × 100. Return 404 if
 *   project not found or if project has no budget_hours defined. Verify
 *   organization context matches the provided organizationId for data
 *   isolation. Apply report:view permission check before returning results.
 * @path /hrm/member/organizations/:organizationId/projects/:projectId/budget-report
 * @accessor api.functional.hrm.member.organizations.projects.budget_report.budgetReport
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function budgetReport(
  connection: IConnection,
  props: budgetReport.Props,
): Promise<budgetReport.Response> {
  return true === connection.simulate
    ? budgetReport.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...budgetReport.METADATA,
          path: budgetReport.path(props),
          status: null,
        },
      );
}
export namespace budgetReport {
  export type Props = {
    /**
     * Unique identifier of the organization (global scope).
     */
    organizationId: string & tags.Format<"uuid">;

    /**
     * Unique identifier of the project within the organization (global scope).
     */
    projectId: string & tags.Format<"uuid">;
  };
  export type Response = IHrmProject.IBudgetReport;

  export const METADATA = {
    method: "GET",
    path: "/hrm/member/organizations/:organizationId/projects/:projectId/budget-report",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/hrm/member/organizations/${encodeURIComponent(props.organizationId ?? "null")}/projects/${encodeURIComponent(props.projectId ?? "null")}/budget-report`;
  export const random = (): IHrmProject.IBudgetReport =>
    typia.random<IHrmProject.IBudgetReport>();
  export const simulate = (
    connection: IConnection,
    props: budgetReport.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: budgetReport.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("organizationId")(() => typia.assert(props.organizationId));
      assert.param("projectId")(() => typia.assert(props.projectId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
