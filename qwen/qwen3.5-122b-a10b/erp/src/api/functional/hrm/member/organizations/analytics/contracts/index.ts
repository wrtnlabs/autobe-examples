import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IHrmContractAnalytic } from "../../../../../../structures/IHrmContractAnalytic";

/**
 * Retrieve contract analytics and statistics for an organization.
 *
 * This endpoint provides aggregated insights into employment contracts within the organization, including contract distribution by pay period, active versus historical contract counts, compensation statistics, and employment type breakdowns. The data is computed from all contracts associated with employees in the organization.
 *
 * **Analytics Metrics**
 *
 * The response includes total contract counts, active contract counts (contracts without end_date), historical contract counts (contracts with end_date), pay period distribution (hourly, daily, weekly, monthly), average pay rates grouped by pay period, average working hours per week, and employment type distribution across all contracts.
 *
 * **Access Control**
 *
 * Users must be authenticated members of the organization. Users with employee:view permission can access contract analytics. The organization_id parameter identifies the target organization for which analytics are computed.
 *
 * @param props.connection
 * @param props.organizationId UUID identifier of the organization for which contract analytics are requested (global scope).
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query hrm_contracts table with organization context through employee relationship. Join hrm_employees to filter contracts by organization_id. Calculate aggregated statistics including: total contract count, active vs historical contract distribution, pay period breakdown (hourly/daily/weekly/monthly), average pay rates by pay period, employment type distribution, and working hours statistics. Apply soft-delete filter (deleted_at IS NULL). Return analytics summary object with computed metrics.
 * @path /hrm/member/organizations/:organizationId/analytics/contracts
 * @accessor api.functional.hrm.member.organizations.analytics.contracts.analytics
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function analytics(
  connection: IConnection,
  props: analytics.Props,
): Promise<analytics.Response> {
  return true === connection.simulate
    ? analytics.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...analytics.METADATA,
          path: analytics.path(props),
          status: null,
        },
      );
}
export namespace analytics {
  export type Props = {
    /**
     * UUID identifier of the organization for which contract analytics are requested (global scope).
     */
    organizationId: string & tags.Format<"uuid">;
  };
  export type Response = IHrmContractAnalytic;

  export const METADATA = {
    method: "GET",
    path: "/hrm/member/organizations/:organizationId/analytics/contracts",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/hrm/member/organizations/${encodeURIComponent(props.organizationId ?? "null")}/analytics/contracts`;
  export const random = (): IHrmContractAnalytic =>
    typia.random<IHrmContractAnalytic>();
  export const simulate = (
    connection: IConnection,
    props: analytics.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: analytics.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("organizationId")(() => typia.assert(props.organizationId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
