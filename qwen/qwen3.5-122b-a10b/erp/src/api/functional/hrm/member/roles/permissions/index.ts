/**
 * Assign one or more permissions to an existing role within an organization.
 *
 * This operation adds the specified permissions to the role's permission set by creating entries in the role-permissions junction table (hrm_role_permissions). The role must exist and belong to the current organization context. Built-in roles (Owner, Manager, Employee) cannot have their permissions modified as they are system-defined and immutable per business rules.
 *
 * **Business Rules**
 * - Role must exist and be owned by the current organization
 * - Built-in roles (is_builtin = true) cannot have permissions modified
 * - Each permission must exist in the system permission catalog (hrm_permissions)
 * - Duplicate permission assignments are prevented by unique constraint on (hrm_role_id, hrm_permission_id)
 * - User must have org:manage permission to modify role permissions
 * - Custom roles must have at least one permission assigned (enforced at role creation, not during assignment)
 *
 * **Error Scenarios**
 * - Role not found: Returns 404 if roleId does not exist in the system
 * - Built-in role: Returns 403 if attempting to modify a built-in role's permissions
 * - Invalid permission: Returns 400 if any permission_id does not exist in hrm_permissions
 * - Insufficient permissions: Returns 403 if user lacks org:manage permission for the organization
 * - Organization mismatch: Returns 403 if role belongs to a different organization than the current context
 *
 * @param props.connection
 * @param props.roleId Unique identifier of the role to assign permissions to (scoped to organization). Must be a valid UUID.
 * @param props.body Array of permission IDs to assign to the role. Each permission must exist in the system permission catalog. The array must contain at least one valid permission ID.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification 1. Extract roleId from path parameter and validate
 *   UUID format 2. Verify user has org:manage permission for the current
 *   organization context (from session/organization context) 3. Query hrm_roles
 *   table by id to retrieve role record 4. Check if role exists; if not, return
 *   404 Not Found 5. Check if role.is_builtin = true; if so, return 403
 *   Forbidden (built-in roles cannot be modified per section 158) 6. Verify
 *   role.hrm_organization_id matches the current organization context 7.
 *   Extract permission_ids array from request body 8. Validate permission_ids
 *   is not empty and contains valid UUIDs 9. For each permission_id in the
 *   array: - Query hrm_permissions table to verify permission exists - If any
 *   permission_id not found, return 400 Bad Request with list of invalid
 *   permission IDs 10. Begin database transaction 11. Insert records into
 *   hrm_role_permissions table for each (hrm_role_id, hrm_permission_id) pair
 *   12. Handle unique constraint violations gracefully (duplicate permissions
 *   are silently ignored due to @@unique constraint) 13. Commit transaction 14.
 *   Query hrm_roles with joined hrm_role_permissions and hrm_permissions to
 *   return complete role with all permissions 15. Return 200 OK with updated
 *   role object including permission array
 * @path /hrm/member/roles/:roleId/permissions
 * @accessor api.functional.hrm.member.roles.permissions.assign
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
