/**
 * Retrieve aggregated metrics and statistics for all members assigned to a specific project.
 *
 * This endpoint returns summary statistics about project membership including total member count, role distribution (members vs project-leads), and time tracking metrics aggregated across all project members. The metrics are calculated from the hrm_project_members table joined with hrm_timelogs for time-based statistics.
 *
 * **Security and Access**
 *
 * Members must have project:view permission to access this endpoint. The organization context is validated from the organizationId path parameter to ensure data isolation across organizations.
 *
 * **Data Aggregation**
 *
 * Metrics are computed in real-time from active project member assignments. Soft-deleted members (deleted_at is not null) are excluded from all counts. Time-based metrics only include timelogs from active members within the specified project.
 *
 * @param props.connection
 * @param props.organizationId Unique identifier of the organization (global scope).
 * @param props.projectId Unique identifier of the project within the organization (scoped to organization).
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query hrm_project_members table filtered by project_id where deleted_at IS NULL. Join with hrm_employees to verify employee status is active. Join with hrm_timelogs to calculate time-based metrics.
 *
 * **Query Logic**
 *
 * 1. Count total project members (COUNT of hrm_project_members where deleted_at IS NULL)
 * 2. Count members by role (GROUP BY role: member vs project-lead)
 * 3. Calculate total hours logged by all members (SUM of hrm_timelogs.duration_minutes / 60)
 * 4. Calculate average hours per member (total hours / member count, handle division by zero)
 * 5. Count active timers across all members (hrm_active_timers if available)
 *
 * **Validation**
 *
 * - Verify organizationId matches the hrm_organization_id on the project record
 * - Verify projectId exists and is not soft-deleted (deleted_at IS NULL)
 * - Return 404 if project not found or belongs to different organization
 * - Return 403 if user lacks project:view permission
 *
 * **Edge Cases**
 *
 * - Empty project (no members): Return counts as 0, averages as null or 0
 * - No timelogs: Return null or 0 for time-based metrics
 * - Division by zero: Handle when calculating averages with 0 members
 * @path /hrm/member/organizations/:organizationId/projects/:projectId/members/metrics
 * @accessor api.functional.hrm.member.organizations.projects.members.metrics
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function metrics(
  connection: IConnection,
  props: metrics.Props,
): Promise<metrics.Response> {
  return true === connection.simulate
    ? metrics.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...metrics.METADATA,
          path: metrics.path(props),
          status: null,
        },
      );
}
export namespace metrics {
  export type Props = {
    /**
     * Unique identifier of the organization (global scope).
     */
    organizationId: string & tags.Format<"uuid">;

    /**
     * Unique identifier of the project within the organization (scoped to organization).
     */
    projectId: string & tags.Format<"uuid">;
  };
  export type Response = IHrmProjectMemberMetric;

  export const METADATA = {
    method: "GET",
    path: "/hrm/member/organizations/:organizationId/projects/:projectId/members/metrics",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/hrm/member/organizations/${encodeURIComponent(props.organizationId ?? "null")}/projects/${encodeURIComponent(props.projectId ?? "null")}/members/metrics`;
  export const random = (): IHrmProjectMemberMetric =>
    typia.random<IHrmProjectMemberMetric>();
  export const simulate = (
    connection: IConnection,
    props: metrics.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: metrics.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("organizationId")(() => typia.assert(props.organizationId));
      assert.param("projectId")(() => typia.assert(props.projectId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
