/**
 * Register a new member account with email and password credentials for the HRM platform. This endpoint creates a new user account in the hrm_platform_members table with the provided email address and securely hashed password using BCrypt algorithm.
 *
 * The registration process generates an email verification token stored in hrm_platform_member_email_verifications table, which is sent to the user's email address for account activation. The member account is created immediately but may require email verification before full access is granted depending on organizational policies.
 *
 * The response includes access and refresh tokens for immediate session establishment, allowing the new member to begin using the platform while completing email verification. The display_name field establishes the user's global profile identity that will be shared across all organization memberships.
 *
 * Security considerations include email uniqueness validation to prevent duplicate accounts, password strength requirements enforced during hashing, and token expiration management for verification links. The password is never stored in plain text and is hashed with BCrypt before database insertion.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration information for new member account including email, password, and display name.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification 1. Validate email format and uniqueness against hrm_platform_members table
 * 2. Hash password using BCrypt with appropriate cost factor
 * 3. Generate unique verification token and store in hrm_platform_member_email_verifications with expiration
 * 4. Create member record with email, password_hash, display_name, and timestamps
 * 5. Send verification email with token to user
 * 6. Return IAuthorized response with access/refresh tokens for immediate session
 * 7. Verification token expires after configured duration (e.g., 24 hours)
 * @path /hrmPlatform/auth/member/join
 * @accessor api.functional.hrmPlatform.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
