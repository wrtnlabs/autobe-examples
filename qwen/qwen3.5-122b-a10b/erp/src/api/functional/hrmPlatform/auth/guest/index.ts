/**
 * Register a new guest user account with email and password credentials for the HRM platform authentication system.
 *
 * This endpoint creates a new guest actor account in the hrm_platform_guests table, storing the provided email address and hashed password. The registration process validates the email format using standard email validation rules and checks for email uniqueness across all existing guest accounts to prevent duplicate registrations.
 *
 * Upon successful validation, the system generates a new guest session record in the hrm_platform_guest_sessions table containing JWT access and refresh tokens. The access token is used for subsequent authenticated API requests, while the refresh token enables token renewal without requiring re-authentication.
 *
 * Security considerations include password hashing using bcrypt with appropriate salt rounds, email uniqueness constraint enforcement at database level, and rate limiting on registration endpoints to prevent abuse. The guest actor created through this operation can then access the system with authenticated privileges based on their assigned permissions.
 *
 * This operation is the primary entry point for guest actors to transition from unauthenticated to authenticated state, enabling them to access organization-scoped features and perform member-level actions after login.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration credentials for creating a new guest account including email and password
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Register a new guest user account with email and password credentials. The service layer validates email uniqueness, password strength requirements, creates a new guest record in hrm_platform_guests table, generates a member session token in hrm_platform_guest_sessions, and returns authorized response with JWT tokens. Email validation checks format and uniqueness. Password must meet minimum complexity requirements. Transaction ensures guest creation and session token generation are atomic.
 * @path /hrmPlatform/auth/guest/join
 * @accessor api.functional.hrmPlatform.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
