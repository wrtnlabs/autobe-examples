import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformPermission } from "../../../../api/structures/IHrmPlatformPermission";
import { IPageIHrmPlatformPermission } from "../../../../api/structures/IPageIHrmPlatformPermission";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberPermissionsPermissionId } from "../../../../providers/getHrmPlatformMemberPermissionsPermissionId";
import { patchHrmPlatformMemberPermissions } from "../../../../providers/patchHrmPlatformMemberPermissions";

@Controller("/hrmPlatform/member/permissions")
export class HrmplatformMemberPermissionsController {
  /**
   * Retrieve a filtered and paginated list of available permissions in the organization.
   *
   * This operation provides access to the complete set of permissions that can be assigned to roles within the organization. Permissions represent atomic access rights that grant the holder the ability to perform specific actions or access specific data types.
   *
   * The platform defines nine permissions across five categories: Organization management (org:manage), Employee management (employee:manage, employee:view), Project management (project:manage, project:view), Time tracking (time:manage, time:approve, time:view_all), and Reporting (report:view). Each permission is scoped to a single organization and cannot be shared across organizations.
   *
   * Supports comprehensive pagination with configurable page sizes and cursor-based navigation for large result sets. Filtering by permission category allows clients to retrieve only relevant subsets of permissions. Response includes permission identifiers, names, categories, and descriptions suitable for role management interfaces.
   *
   * This operation is commonly used when creating or editing custom roles to display available permission options to organization owners.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering permissions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the predefined list of available permissions for the organization. Return all 9 permissions: org:manage, employee:manage, employee:view, project:manage, project:view, time:manage, time:approve, time:view_all, report:view. Apply pagination from request body (page, limit, cursor). Support filtering by permission category (organization, employee, project, time, report). Sort by permission name. Return permission summaries with name, category, and description.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformPermission.IRequest,
  ): Promise<IPageIHrmPlatformPermission.ISummary> {
    try {
      return await patchHrmPlatformMemberPermissions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific permission definition from the hrm_platform_permissions table by its unique identifier.
   *
   * This operation returns the complete permission record including the primary key `id` (UUID), unique permission `code` (e.g., 'org:manage', 'employee:view'), human-readable `name`, detailed `description` of the permission's capabilities, and optional `category` classification for organizational grouping. The response also includes audit timestamps `created_at` and `updated_at`.
   *
   * Permission definitions serve as the atomic building blocks of the access control system, representing individual access rights that can be assigned to roles within any organization. Each permission grants the holder the ability to perform a specific type of action or access a specific type of data. Common permissions include org:manage for organization settings management, employee:manage and employee:view for employee management operations, project:manage and project:view for project management, and time:manage, time:approve, time:view_all for time tracking and timesheet approval operations.
   *
   * The system validates that the permission exists in the hrm_platform_permissions table and that the `deleted_at` field is NULL, indicating the permission has not been soft-deleted. If the permission does not exist or has been soft-deleted, the operation returns a 404 Not Found response. Permission definitions are global reference data shared across all organizations, though access to view them may be restricted based on the user's organizational role and permissions.
   *
   * This operation is typically used when displaying permission options in role management interfaces, validating permission assignments during role configuration, or auditing access control configurations. It may be called after retrieving the list of available permissions via PATCH /hrmPlatform/member/permissions to obtain full details of a specific permission.
   *
   * @param connection
   * @param permissionId Unique identifier of the permission to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the hrm_platform_permissions table by primary key id (UUID). Validate that the permission exists and deleted_at is NULL (not soft-deleted). Return the complete permission record with all fields: id, code, name, description, category, created_at, and updated_at.
   *
   * Authorization: User must be authenticated (member actor). Organization context is extracted from the session. While permission definitions are global, verify the user has appropriate access to view permission definitions (typically requires org:manage or similar administrative permission).
   *
   * Error handling: Return 404 Not Found if permission does not exist or is soft-deleted. Return 401 Unauthorized if user is not authenticated. Return 403 Forbidden if user lacks permission to view permission definitions.
   *
   * Performance: Use primary key lookup for O(1) retrieval. No joins required since this is a single-table query.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":permissionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("permissionId")
    permissionId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformPermission> {
    try {
      return await getHrmPlatformMemberPermissionsPermissionId({
        member,
        permissionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
