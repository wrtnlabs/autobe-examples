import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformRole } from "../../../../../api/structures/IHrmPlatformRole";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchHrmPlatformMemberRolesRoleIdPermissions } from "../../../../../providers/patchHrmPlatformMemberRolesRoleIdPermissions";

@Controller("/hrmPlatform/member/roles/:roleId/permissions")
export class HrmplatformMemberRolesPermissionsController {
  /**
   * Update the set of permissions assigned to a specific role within an organization.
   *
   * This operation allows organization owners to modify the permissions associated with a custom role. The request body contains a list of permission IDs that will replace the current permission assignments for the role. All existing permissions are removed and the new set is assigned.
   *
   * Built-in roles (Owner, Manager, Employee) cannot have their permissions modified. This operation validates that all provided permission IDs exist in the system and are from the predefined list of available permissions. Permission assignments are applied immediately and affect all employees assigned to the role.
   *
   * The operation requires the caller to have organization management permissions (org:manage) and must be executed within the context of the organization that owns the role.
   *
   * @param connection
   * @param roleId Unique identifier of the role to update permissions for
   * @param body List of permission IDs to assign to the role, replacing all existing permissions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate the role exists and belongs to the requesting user's organization context
   * 2. Check if the role is a built-in role (is_builtin = true) - reject with error if so
   * 3. Validate all permission IDs in the request body exist in hrm_platform_permissions table
   * 4. Validate all permission IDs are from the active (non-deleted) permissions
   * 5. Begin transaction:
   *    - Delete all existing records in hrm_platform_role_permissions for this role
   *    - Insert new records for each permission ID in the request
   * 6. Commit transaction
   * 7. Fetch the updated role with its new permission assignments
   * 8. Return the role object with embedded permissions array
   *
   * Edge cases:
   * - Empty permission array is valid (role with no permissions)
   * - Duplicate permission IDs in request should be deduplicated
   * - Invalid permission IDs should return validation error before any changes
   * - Built-in role modification should return authorization error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updatePermissions(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformRole.IPermissionUpdate,
  ): Promise<IHrmPlatformRole> {
    try {
      return await patchHrmPlatformMemberRolesRoleIdPermissions({
        member,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
