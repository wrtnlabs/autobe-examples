@Controller("/hrmPlatform/member/roles")
export class HrmplatformMemberRolesController {
  /**
   * Create a custom role within the current organization with specified permissions.
   *
   * This operation allows organization owners to define custom roles beyond the three built-in roles (Owner, Manager, Employee). Custom roles enable granular access control tailored to organizational needs.
   *
   * **Authorization Requirements**:
   *
   * Only users with the `org:manage` permission can create custom roles. This ensures that role management remains under administrative control and prevents unauthorized privilege escalation.
   *
   * **Role Properties**:
   *
   * The new role must have a unique name within the organization. The name serves as the human-readable identifier displayed in the user interface. An optional description can provide additional context about the role's purpose and intended use.
   *
   * **Permission Assignment**:
   *
   * Permissions are assigned via their permission codes from the available permissions catalog. Each permission grants access to specific system capabilities such as organization management, employee management, project viewing, time approval, and report access. The system validates that all provided permission codes exist and are active (not soft-deleted).
   *
   * **Built-in Role Protection**:
   *
   * The system prevents creation of roles with names matching built-in roles (Owner, Manager, Employee) to maintain the integrity of the core role hierarchy.
   *
   * **Related Operations**:
   *
   * - `GET /roles` - Retrieve the list of roles in the organization
   * - `PUT /roles/{roleCode}` - Update an existing custom role
   * - `DELETE /roles/{roleCode}` - Delete a custom role (if no employees assigned)
   * - `GET /permissions` - List all available permissions for assignment
   *
   * @param connection
   * @param body Custom role creation information including name, description, and assigned permissions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a custom role in the current organization context. Implementation steps: 1) Extract organization ID from authenticated member's context. 2) Validate user has org:manage permission (organization owner). 3) Validate role name is unique within organization (check hrm_platform_roles where hrm_platform_organization_id = context org AND name = request name AND deleted_at IS NULL). 4) Validate all permission IDs exist in hrm_platform_permissions table and are not soft-deleted. 5) Generate unique role code (can be derived from name or auto-generated UUID). 6) Create role record in hrm_platform_roles with is_builtin = false. 7) Insert permission assignments into hrm_platform_role_permissions junction table for each permission ID. 8) Return created role with full details including assigned permissions. Error cases: 403 if user lacks org:manage permission, 400 if role name duplicates existing role, 400 if permission IDs are invalid, 400 if attempting to create built-in role.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformRole.ICreate,
  ): Promise<IHrmPlatformRole> {
    try {
      return await postHrmPlatformMemberRoles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of roles within the currently selected organization.
   *
   * This operation returns both built-in roles (Owner, Manager, Employee) and custom roles created by organization owners. Each role entry includes the role name, code, description, built-in status indicator, and associated permissions. Soft-deleted roles (where deleted_at is not null) are automatically excluded from results.
   *
   * The response supports pagination with configurable page sizes and cursor-based navigation for organizations with many roles. Search functionality allows filtering by role name, code, or built-in status.
   *
   * All authenticated members within an organization can access this endpoint to view available roles and their permission sets. The role list reflects the current state including any recent changes made by organization owners.
   *
   * Related operations include creating custom roles (POST /roles), updating custom roles (PUT /roles/{roleId}), and deleting custom roles (DELETE /roles/{roleId}) which require organization owner permissions.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for role listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_roles table filtered by hrm_platform_organization_id from authenticated user context.
   *
   * Apply search filters on name, code, and is_builtin fields. Support partial text matching on name and code.
   *
   * Implement cursor-based pagination using created_at or id as cursor field.
   *
   * Join with hrm_platform_role_permissions and hrm_platform_permissions tables to fetch associated permission codes for each role.
   *
   * Exclude soft-deleted roles (deleted_at IS NULL) from results.
   *
   * Sort results by is_builtin descending (built-in roles first), then by name ascending.
   *
   * Return summary projection with role id, code, name, description, is_builtin flag, and permission codes array.
   *
   * Validate user has member access to the organization from authentication context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformRole.IRequest,
  ): Promise<IPageIHrmPlatformRole.ISummary> {
    try {
      return await patchHrmPlatformMemberRoles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific role within the current organization context.
   *
   * This operation returns comprehensive role details including the role's identifying information (name, code, description), its built-in status, and all associated permissions. The role is identified by its UUID and must belong to the organization specified in the request context.
   *
   * Built-in roles (Owner, Manager, Employee) are automatically created when an organization is established and cannot be deleted or modified. Custom roles can be created by organization owners and may be deleted only when no employees are assigned to them. Soft-deleted roles are excluded from retrieval by default.
   *
   * The response includes the complete set of permissions assigned to this role, allowing API consumers to understand the full access rights granted by this role. Each permission includes its code, name, description, and category for display purposes. Soft-deleted permissions are excluded from the response.
   *
   * All authenticated members within the organization can access this endpoint to view role information. The organization context is derived from the authenticated session, ensuring proper data isolation between organizations. Users can only retrieve roles that belong to their currently selected organization.
   *
   * @param connection
   * @param roleId Target role's unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the hrm_platform_roles table by role ID within the current organization context. Verify the role exists and belongs to the authenticated user's organization. Join with hrm_platform_role_permissions to retrieve all assigned permissions, then join with hrm_platform_permissions to get permission details. Filter out soft-deleted permissions (deleted_at IS NULL). Return the role object with embedded permissions array. Apply organization-scoped authorization to ensure users can only access roles within their selected organization.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":roleId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformRole> {
    try {
      return await getHrmPlatformMemberRolesRoleId({
        member,
        roleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing role's name, description, and assigned permissions within the current organization.
   *
   * This operation allows organization owners to modify custom roles, including changing the role's display name, description, and the set of permissions assigned to it. The permissions are specified as an array of permission codes that will replace the existing permission assignments.
   *
   * **Authorization Requirements:**
   *
   * Only users with organization owner status can update roles. Organization managers and regular employees cannot modify role definitions, even if they have employee management permissions.
   *
   * **Built-in Role Protection:**
   *
   * Built-in roles (Owner, Manager, Employee) cannot be edited. The system will reject any update attempt on built-in roles with an appropriate error message. This protection ensures that the core permission structure of the organization remains intact.
   *
   * **Permission Assignment:**
   *
   * The request body includes an array of permission codes that will be assigned to the role. This array completely replaces any existing permission assignments. To remove all permissions from a role, provide an empty array. To add permissions, include their codes in the array.
   *
   * **Validation Rules:**
   *
   * - The role name must be unique within the organization
   * - Permission codes must exist in the system's permission definitions
   * - The role must belong to the current organization
   * - Built-in roles are protected from modification
   *
   * **Related Operations:**
   *
   * - `GET /roles/{roleId}` - Retrieve detailed information about a specific role
   * - `PATCH /roles` - List all roles in the organization with pagination
   * - `POST /roles` - Create a new custom role
   * - `DELETE /roles/{roleId}` - Delete a custom role (with validation for employee assignments)
   * - `GET /permissions` - Retrieve the list of available permissions that can be assigned to roles
   *
   * @param connection
   * @param roleId Unique identifier of the role to update (UUID format)
   * @param body Role update information including name, description, and permission assignments
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Service layer implementation for role update operation:
   *
   * 1. **Organization Context Validation:**
   *    - Extract organization ID from authentication context
   *    - Verify the authenticated user has organization owner status
   *    - Reject with 403 Forbidden if user lacks owner permissions
   *
   * 2. **Role Retrieval:**
   *    - Query hrm_platform_roles table by roleId and organization ID
   *    - Return 404 Not Found if role doesn't exist or doesn't belong to organization
   *
   * 3. **Built-in Role Check:**
   *    - Check role.is_builtin flag
   *    - Reject with 400 Bad Request if role is built-in (Owner, Manager, Employee)
   *    - Error message should indicate built-in roles cannot be modified
   *
   * 4. **Permission Validation:**
   *    - Validate each permission code in the request body against hrm_platform_permissions table
   *    - Ensure all permission codes exist and are not soft-deleted
   *    - Return 400 Bad Request with invalid permission codes listed
   *
   * 5. **Name Uniqueness Validation:**
   *    - If name is being changed, check for duplicate names within the organization
   *    - Query hrm_platform_roles for existing role with same name (excluding current role)
   *    - Return 409 Conflict if duplicate name found
   *
   * 6. **Database Transaction:**
   *    - Begin transaction
   *    - Update role record (name, description, updated_at)
   *    - Delete existing role_permissions records for this role (WHERE hrm_platform_role_id = roleId AND deleted_at IS NULL)
   *    - Insert new role_permissions records for each permission code in request
   *    - Commit transaction
   *
   * 7. **Response Construction:**
   *    - Fetch updated role with new permission assignments
   *    - Return 200 OK with complete role object including permissions array
   *
   * 8. **Error Handling:**
   *    - 400 Bad Request: Built-in role modification, invalid permission codes, duplicate name
   *    - 403 Forbidden: User lacks organization owner permissions
   *    - 404 Not Found: Role doesn't exist or doesn't belong to organization
   *    - 409 Conflict: Duplicate role name within organization
   *    - 500 Internal Server Error: Database transaction failures
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":roleId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformRole.IUpdate,
  ): Promise<IHrmPlatformRole> {
    try {
      return await putHrmPlatformMemberRolesRoleId({
        member,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a custom role from the organization.
   *
   * This operation permanently removes a custom role definition from the organization. Only organization owners have permission to delete roles.
   *
   * The system enforces two critical validation rules before allowing deletion. First, built-in roles (Owner, Manager, and Employee) are protected from deletion under all circumstances and cannot be removed. Second, custom roles can only be deleted if no employees are currently assigned to them. If any employees have the role assigned, the deletion request is rejected and the user must reassign those employees to a different role first.
   *
   * Upon successful deletion, the role is permanently removed from the organization and all associated role-permission mappings are cascaded deleted. Employees who previously had access through this role will lose those permissions immediately. The system does not support soft deletion for roles - this is a permanent removal operation.
   *
   * Related operations include PATCH /roles/{roleId} for updating role names and permissions, and PATCH /roles for listing all available roles in the organization.
   *
   * @param connection
   * @param roleId Unique identifier of the role to delete (scoped to organization)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implement role deletion with the following logic:
   *
   * 1. Authenticate request and verify organization context from JWT token
   * 2. Verify user has organization owner permission (org:manage)
   * 3. Fetch role by {roleId} UUID within the organization context
   * 4. Check if role is built-in (is_builtin = true) - if yes, return 403 Forbidden with error message "Built-in roles cannot be deleted"
   * 5. Query hrm_platform_employees table for any employees with hrm_platform_role_id = {roleId} and deleted_at IS NULL
   * 6. If employees found, return 409 Conflict with error message "Cannot delete role: {count} employee(s) are assigned to this role. Reassign them first."
   * 7. If validation passes, delete the role record (set deleted_at = current timestamp for audit trail, or hard delete)
   * 8. Cascade delete all hrm_platform_role_permissions records for this role
   * 9. Return 204 No Content on success
   * 10. Log activity event: role:deleted with role name and organization ID
   *
   * Edge cases:
   * - Role not found: 404 Not Found
   * - User lacks permission: 403 Forbidden
   * - Built-in role: 403 Forbidden with specific error
   * - Employees assigned: 409 Conflict with employee count
   * - Concurrent deletion: handle transaction isolation
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":roleId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberRolesRoleId({
        member,
        roleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
