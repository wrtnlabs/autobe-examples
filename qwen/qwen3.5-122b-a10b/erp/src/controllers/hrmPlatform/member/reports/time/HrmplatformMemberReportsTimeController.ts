import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformTimeReport } from "../../../../../api/structures/IHrmPlatformTimeReport";
import { IPageIHrmPlatformTimeReport } from "../../../../../api/structures/IPageIHrmPlatformTimeReport";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchHrmPlatformMemberReportsTime } from "../../../../../providers/patchHrmPlatformMemberReportsTime";

@Controller("/hrmPlatform/member/reports/time")
export class HrmplatformMemberReportsTimeController {
  /**
   * Retrieve a filtered and aggregated time tracking report with customizable grouping and comprehensive filtering options.
   *
   * This operation provides organization-wide time reporting capabilities, allowing users with report:view permission to analyze time logged across employees, projects, and tasks. The report aggregates timelog data within a specified date range and groups results by the chosen dimension (employee, project, or task).
   *
   * The report includes detailed hour breakdowns showing total hours logged, billable hours (chargeable to clients), and non-billable hours (internal work). This classification supports accurate client billing, capacity planning, and internal cost tracking as defined in the billable time classification requirements.
   *
   * Filtering capabilities include date range selection, optional employee filtering, optional project filtering, and billable status filtering. The response is paginated to handle large result sets efficiently, with cursor-based navigation for seamless data browsing.
   *
   * Related operations: GET /reports/budget for project budget utilization reports, GET /reports/weekly for weekly summary reports, PATCH /reports/activity for activity log access.
   *
   * @param connection
   * @param body Time report search criteria including date range, grouping dimension, filters, and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_timelogs table with date range filtering and aggregation logic.
   *
   * 1. Validate report:view permission for authenticated user
   * 2. Apply organization context from authentication token
   * 3. Filter timelogs by:
   *    - Date range (date >= startDate AND date <= endDate)
   *    - Employee ID (optional filter)
   *    - Project ID (optional filter)
   *    - Billable status (optional filter)
   * 4. Group results by specified dimension (employee/project/task)
   * 5. Calculate aggregated metrics per group:
   *    - Total hours (sum of duration_minutes / 60)
   *    - Billable hours (sum where billable = true)
   *    - Non-billable hours (sum where billable = false)
   * 6. Apply pagination (page, pageSize) with cursor-based navigation
   * 7. Join with hrm_platform_employees, hrm_platform_projects, hrm_platform_tasks for group metadata
   * 8. Return paginated response with pagination metadata and grouped time data
   *
   * Edge cases:
   * - Empty date range: reject with validation error
   * - Invalid groupBy value: reject with validation error
   * - No timelogs in range: return empty data array with zero pagination totals
   * - User lacks report:view permission: return 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformTimeReport.IRequest,
  ): Promise<IPageIHrmPlatformTimeReport.ISummary> {
    try {
      return await patchHrmPlatformMemberReportsTime({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
