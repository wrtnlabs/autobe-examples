import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformProjectSnapshot } from "../../../../../api/structures/IHrmPlatformProjectSnapshot";
import { IPageIHrmPlatformProjectSnapshot } from "../../../../../api/structures/IPageIHrmPlatformProjectSnapshot";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberProjectsProjectIdSnapshotsSnapshotId } from "../../../../../providers/getHrmPlatformMemberProjectsProjectIdSnapshotsSnapshotId";
import { patchHrmPlatformMemberProjectsProjectIdSnapshots } from "../../../../../providers/patchHrmPlatformMemberProjectsProjectIdSnapshots";

@Controller("/hrmPlatform/member/projects/:projectId/snapshots")
export class HrmplatformMemberProjectsSnapshotsController {
  /**
   * Retrieve a filtered and paginated list of project snapshot audit trail records for a specific project.
   *
   * This operation provides access to the historical state changes of a project through point-in-time snapshots. Each snapshot captures the complete project state including name, description, status, budget hours, and date ranges at the moment the snapshot was created.
   *
   * Snapshots are immutable audit trail records created automatically when projects undergo significant changes or at regular intervals for compliance tracking. They enable historical review, change tracking, and audit purposes without modifying the current project state.
   *
   * The operation supports filtering by date range to narrow results to specific time periods, and by snapshot status (active, archived, completed) to focus on particular project states. Pagination controls allow efficient browsing of large snapshot histories.
   *
   * Access to project snapshots requires appropriate project viewing permissions. Organization context is enforced on every request to ensure data isolation between organizations.
   *
   * @param connection
   * @param projectId Target project's unique identifier (UUID format)
   * @param body Search criteria and pagination parameters for filtering snapshots
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_project_snapshots table filtered by hrm_platform_project_id matching the path parameter projectId.
   *
   * Apply date range filters from request body: created_at >= fromDate and created_at <= toDate if provided.
   * Apply status filter if provided: status = request.status.
   * Apply pagination: limit and offset from request, or cursor-based pagination for large result sets.
   * Apply sorting: default order by created_at DESC (newest first), support custom sort by created_at, status.
   *
   * Return IHrmPlatformProjectSnapshot.ISummary for each snapshot, excluding sensitive fields.
   * Include pagination metadata: total count, page size, current page, hasMore flag.
   *
   * Validate projectId exists and is accessible to the authenticated user within their organization context.
   * Enforce organization isolation: verify the project belongs to the user's selected organization.
   * Check user has project:view permission before returning results.
   *
   * Edge cases:
   * - Empty snapshot list: return pagination with zero data
   * - Invalid projectId: return 404 Not Found
   * - Unauthorized access: return 403 Forbidden
   * - Invalid date range: return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformProjectSnapshot.IRequest,
  ): Promise<IPageIHrmPlatformProjectSnapshot.ISummary> {
    try {
      return await patchHrmPlatformMemberProjectsProjectIdSnapshots({
        member,
        projectId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific point-in-time snapshot of a project's state.
   *
   * This operation returns the complete historical record of a project as it existed at the moment the snapshot was created. Project snapshots are immutable audit trail records that capture the exact state of a project including its name, description, status, budget allocation, and timeline information.
   *
   * Snapshots are automatically created when projects undergo significant state changes such as archiving or completion, preserving the project's configuration for historical reference and compliance purposes. Each snapshot is append-only and cannot be modified after creation.
   *
   * The requesting user must have project:view permission on the parent project to access its snapshots. Multi-tenancy isolation is enforced to ensure users can only view snapshots from projects within their current organization context.
   *
   * This endpoint is typically used for audit reviews, historical analysis, and compliance reporting where the exact project configuration at a specific point in time needs to be verified.
   *
   * @param connection
   * @param projectId The unique identifier of the parent project (global scope)
   * @param snapshotId The unique identifier of the project snapshot record (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve a specific project snapshot record by ID. First validate the requesting user has project:view permission on the parent project identified by projectId. Query the hrm_platform_project_snapshots table for the snapshot with matching snapshotId and hrm_platform_project_id matching the projectId. Verify the snapshot belongs to the same organization as the requesting user's current organization context to enforce multi-tenancy isolation. Return the complete snapshot record including all captured project state fields (name, description, color_code, status, budget_hours, start_date, end_date) along with snapshot metadata (created_at, updated_at). If snapshot not found or user lacks permission, return 404 or 403 error respectively.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformProjectSnapshot> {
    try {
      return await getHrmPlatformMemberProjectsProjectIdSnapshotsSnapshotId({
        member,
        projectId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
