import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformTask } from "../../../../../../api/structures/IHrmPlatformTask";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { patchHrmPlatformMemberProjectsProjectIdTasksTaskIdStatus } from "../../../../../../providers/patchHrmPlatformMemberProjectsProjectIdTasksTaskIdStatus";

@Controller("/hrmPlatform/member/projects/:projectId/tasks/:taskId/status")
export class HrmplatformMemberProjectsTasksStatusController {
  /**
   * Update the status of a specific task within a project and record the status change in the task history audit trail.
   *
   * This operation changes a task's status among the allowed values (open, in-progress, completed, closed) and automatically creates a history entry documenting the transition. The history entry captures the previous status, new status, timestamp of change, and the member who initiated the change for compliance and audit purposes.
   *
   * Authorization Requirements:
   * - Project leads can update task status for any task within their assigned projects
   * - Users with project:manage permission can update task status for all tasks in the organization
   * - The requesting member must be a project member to access tasks in that project
   *
   * Business Rules:
   * - Task status can transition between any of the four states (open, in-progress, completed, closed)
   * - Every status change creates an immutable history entry in hrm_platform_task_histories
   * - The history entry includes the exact timestamp, old status, new status, and member identity
   * - Parent task status changes do not automatically propagate to subtasks
   * - Subtasks maintain independent status from their parent tasks
   *
   * Related Operations:
   * - `GET /projects/{projectId}/tasks/{taskId}` retrieves complete task details including current status
   * - `GET /projects/{projectId}/tasks/{taskId}/histories` retrieves the complete status change history for a task
   * - `PATCH /projects/{projectId}/tasks/{taskId}` updates other task properties (description, due date, assignment, etc.)
   *
   * Validation:
   * - The task must exist and belong to the specified project
   * - The new status must be one of: open, in-progress, completed, closed
   * - The requesting member must have appropriate permissions (project lead or project:manage)
   *
   * @param connection
   * @param projectId Unique identifier of the project containing the task (global scope)
   * @param taskId Unique identifier of the task to update status (scoped to project)
   * @param body New status value for the task
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate projectId and taskId path parameters are valid UUIDs
   * 2. Verify the task exists and belongs to the specified project (hrm_platform_tasks.hrm_platform_projects_id = projectId)
   * 3. Check authorization: verify requesting member is a project member with project lead role or project:manage permission
   * 4. Retrieve current task status from hrm_platform_tasks table
   * 5. Validate new status is one of: 'open', 'in-progress', 'completed', 'closed'
   * 6. Update hrm_platform_tasks.status with new status value
   * 7. Create history entry in hrm_platform_task_histories:
   *    - hrm_platform_task_id: taskId
   *    - hrm_platform_member_id: requesting member's ID
   *    - changed_at: current timestamp (timestamptz)
   *    - old_status: previous status value
   *    - new_status: new status value
   * 8. Return updated task object with new status
   * 9. Emit task status change event for real-time updates to project members
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async changeStatus(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformTask.IStatusChange,
  ): Promise<IHrmPlatformTask> {
    try {
      return await patchHrmPlatformMemberProjectsProjectIdTasksTaskIdStatus({
        member,
        projectId,
        taskId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
