import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformTaskHistory } from "../../../../../../api/structures/IHrmPlatformTaskHistory";
import { IPageIHrmPlatformTaskHistory } from "../../../../../../api/structures/IPageIHrmPlatformTaskHistory";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberProjectsProjectIdTasksTaskIdHistoriesHistoryId } from "../../../../../../providers/getHrmPlatformMemberProjectsProjectIdTasksTaskIdHistoriesHistoryId";
import { patchHrmPlatformMemberProjectsProjectIdTasksTaskIdHistories } from "../../../../../../providers/patchHrmPlatformMemberProjectsProjectIdTasksTaskIdHistories";

@Controller("/hrmPlatform/member/projects/:projectId/tasks/:taskId/histories")
export class HrmplatformMemberProjectsTasksHistoriesController {
  /**
   * Retrieve a filtered and paginated list of task status change history records for a specific task within a project.
   *
   * This operation provides access to the complete audit trail of status transitions for a task, including timestamps, previous and new status values, and the member who initiated each change. Task history records are immutable once created and support compliance tracking and workflow analysis.
   *
   * The endpoint enforces strict organization context isolation, ensuring users can only access task histories within projects they have membership in. Project leads can view the full status history for all tasks in their project, while regular members can view histories for tasks they have access to.
   *
   * Supports comprehensive filtering by date range and the member who made changes, along with flexible sorting options. Response includes paginated task history summaries optimized for list displays and audit trail reviews.
   *
   * Related operations:
   * - `PATCH /projects/{projectId}/tasks` - List all tasks in a project
   * - `GET /projects/{projectId}/tasks/{taskId}` - Retrieve detailed task information
   * - `PATCH /projects/{projectId}/tasks/{taskId}` - Update task properties including status
   *
   * @param connection
   * @param projectId Target project's unique identifier (global scope)
   * @param taskId Target task's unique identifier (scoped to project)
   * @param body Filter criteria and pagination parameters for task history retrieval
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_task_histories table filtered by hrm_platform_task_id from path parameter.
   *
   * Validate organization context:
   * - Load project from hrm_platform_projects using projectId
   * - Verify task exists and belongs to the specified project
   * - Check user has membership in the project (as member or project-lead)
   * - Enforce organization-scoped data isolation
   *
   * Apply filtering from request body:
   * - Filter by changed_at date range (from/to timestamps)
   * - Filter by hrm_platform_member_id (member who made changes)
   * - Apply soft delete filter (exclude records where deleted_at is not null)
   *
   * Apply sorting:
   * - Default sort by changed_at DESC (most recent first)
   * - Support ascending/descending order configuration
   *
   * Apply pagination:
   * - Use cursor-based pagination with page and limit parameters
   * - Return pagination metadata (current page, total count, hasMore)
   *
   * Return paginated response with IHrmPlatformTaskHistory.ISummary objects containing:
   * - id, hrm_platform_task_id, hrm_platform_member_id, changed_at, old_status, new_status, member (embedded summary with id, name, email)
   *
   * Error handling:
   * - 404 if project or task not found
   * - 403 if user lacks project membership
   * - 400 for invalid filter/sort parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformTaskHistory.IRequest,
  ): Promise<IPageIHrmPlatformTaskHistory.ISummary> {
    try {
      return await patchHrmPlatformMemberProjectsProjectIdTasksTaskIdHistories({
        member,
        projectId,
        taskId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific task status change history record from the hrm_platform_task_histories table.
   *
   * This operation fetches detailed information about a single task status transition event, including the exact timestamp when the change occurred (changed_at), the previous status value (old_status), the new status value (new_status), and the identity of the member who initiated the change (hrm_platform_member_id). Each history record is an immutable audit trail entry that captures the complete lifecycle of task status transitions.
   *
   * Task status history records track transitions between open, in-progress, completed, and closed states. The hrm_platform_task_histories table maintains these records with full accountability through member references, supporting audit compliance, workflow analysis, and accountability tracking requirements.
   *
   * Access to this endpoint requires membership in the project containing the task. Members can only view history records for tasks within their assigned projects. Project leads can view all task histories within their project. Users with project:manage permission can access task histories across all projects in the organization.
   *
   * The history record includes the exact date and time of the status change via the changed_at field, the status value before the transition via old_status, the status value after the transition via new_status, and the member who performed the change via hrm_platform_member_id. This information supports audit compliance, workflow analysis, and accountability tracking.
   *
   * Related operations include retrieving the parent task via GET /hrmPlatform/member/projects/{projectId}/tasks/{taskId} and listing all task histories via PATCH /hrmPlatform/member/projects/{projectId}/tasks/{taskId}/histories with pagination and filtering.
   *
   * @param connection
   * @param projectId Target project's unique identifier (global scope)
   * @param taskId Target task's unique identifier (scoped to project)
   * @param historyId Target history record's unique identifier (scoped to task)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_task_histories table by history ID with foreign key validation.
   *
   * 1. Validate projectId exists and is not soft-deleted
   * 2. Validate taskId exists, belongs to projectId, and is not soft-deleted
   * 3. Validate historyId exists, belongs to taskId, and is not soft-deleted
   * 4. Verify member has project access (project member or project:manage permission)
   * 5. Load history record with member details (hrm_platform_members)
   * 6. Return IHrmPlatformTaskHistory response with member information
   *
   * Error scenarios:
   * - 404 if projectId, taskId, or historyId not found or soft-deleted
   * - 403 if member lacks project access
   * - 400 if path parameters are invalid UUIDs
   *
   * Join hrm_platform_members to include member display information in response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":historyId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedParam("historyId")
    historyId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformTaskHistory> {
    try {
      return await getHrmPlatformMemberProjectsProjectIdTasksTaskIdHistoriesHistoryId(
        {
          member,
          projectId,
          taskId,
          historyId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
