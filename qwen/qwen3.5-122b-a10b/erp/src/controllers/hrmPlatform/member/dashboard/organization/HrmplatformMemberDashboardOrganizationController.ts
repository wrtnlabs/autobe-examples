import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IOrganizationDashboard } from "../../../../../api/structures/IOrganizationDashboard";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberDashboardOrganization } from "../../../../../providers/getHrmPlatformMemberDashboardOrganization";

@Controller("/hrmPlatform/member/dashboard/organization")
export class HrmplatformMemberDashboardOrganizationController {
  /**
   * Retrieve an aggregated organizational dashboard with key metrics and statistics for the current organization context.
   *
   * This operation provides a comprehensive overview of organizational activity including employee engagement, time tracking metrics, timesheet status, project budget utilization, and top performer rankings. The dashboard is designed for organization managers and administrators who need a quick snapshot of organizational health and activity.
   *
   * The response includes five key metric categories: active employee count, weekly time tracking totals, pending timesheet approvals, budget utilization alerts, and employee performance rankings. Each metric is calculated from the underlying employee, timelog, timesheet, and project data.
   *
   * Security considerations: Users must have either org:manage permission or time:view_all permission to access this dashboard. All data is strictly scoped to the organization context established by the authenticated user's session.
   *
   * Related operations: GET /dashboard/personal for individual employee dashboard, PATCH /timesheets for timesheet management, PATCH /employees for employee list retrieval.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_employees table to count active employees (status='active').
   *
   * Query hrm_platform_timelogs table to calculate total hours logged this week (date between Monday and Sunday of current week, group by employee, sum duration_minutes).
   *
   * Query hrm_platform_timesheets table to count pending timesheets (status='submitted' or status='draft').
   *
   * Query hrm_platform_projects table to identify projects with budget utilization over 80% (sum of timelog hours / budget_hours > 0.8 where budget_hours is not null).
   *
   * Query hrm_platform_timelogs joined with hrm_platform_employees to get top 5 employees by total hours this week, ordered by hours descending, limited to 5.
   *
   * All queries must be scoped to hrm_platform_organization_id from the authenticated user's organization context.
   *
   * Implement caching for performance if dashboard is accessed frequently.
   *
   * Handle edge cases: no employees, no timelogs, no projects with budgets - return zeros or empty arrays appropriately.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IOrganizationDashboard> {
    try {
      return await getHrmPlatformMemberDashboardOrganization({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
