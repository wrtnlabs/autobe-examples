import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformPersonalDashboard } from "../../../../../api/structures/IHrmPlatformPersonalDashboard";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberDashboardPersonal } from "../../../../../providers/getHrmPlatformMemberDashboardPersonal";

@Controller("/hrmPlatform/member/dashboard/personal")
export class HrmplatformMemberDashboardPersonalController {
  /**
   * Retrieve a comprehensive personal dashboard view for the authenticated employee, aggregating time tracking data, active timer status, pending timesheet information, and assigned tasks.
   *
   * This operation provides a unified view of the employee's current work activities and time tracking status. It calculates hours logged for today and the current week by summing duration from individual timelog entries. The active timer status shows if the employee has a running timer session, including the project and task being tracked along with elapsed duration.
   *
   * Recent timelogs are included to show the employee's recent work activity, typically displaying the last 7 days of time entries. Pending timesheet status indicates if there are any timesheets in draft or submitted state awaiting approval. Assigned tasks display all active tasks assigned to the employee that have not yet been completed or closed.
   *
   * All data is scoped to the authenticated employee's context and respects organization-level data isolation. The operation performs multiple database queries with appropriate joins to project and task information for complete context.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the personal dashboard for the authenticated employee. Implementation steps: 1) Resolve current employee from authentication context using hrm_platform_employees table. 2) Calculate hours logged today by summing duration_minutes from hrm_platform_timelogs where employee_id matches and date equals today. 3) Calculate hours logged this week by summing duration_minutes from hrm_platform_timelogs where employee_id matches and date falls within current week (Monday to Sunday). 4) Retrieve active timer from hrm_platform_timers where employee_id matches and stopped_at is null. 5) Get recent timelogs (last 7 days) from hrm_platform_timelogs ordered by date descending, limited to 10 entries. 6) Check for pending timesheets from hrm_platform_timesheets where employee_id matches and status is 'submitted' or 'draft'. 7) Retrieve assigned tasks from hrm_platform_tasks where hrm_platform_employees_id matches and status is not 'completed' or 'closed'. 8) Join project information for tasks and timers. 9) Return aggregated dashboard data as single response object.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmPlatformPersonalDashboard> {
    try {
      return await getHrmPlatformMemberDashboardPersonal({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
