import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmGuest } from "../../../api/structures/IHrmGuest";
import { IPageIHrmGuest } from "../../../api/structures/IPageIHrmGuest";
import { getHrmGuestsGuestId } from "../../../providers/getHrmGuestsGuestId";
import { patchHrmGuests } from "../../../providers/patchHrmGuests";

@Controller("/hrm/guests")
export class HrmGuestsController {
  /**
   * Search and list guest device records with pagination and filtering.
   *
   * This endpoint retrieves a paginated list of guest accounts identified by device fingerprints. Administrators can filter guests by creation date range, deletion status, and search by device fingerprint patterns. The results include summary information about each guest device and their session activity.
   *
   * Guest accounts represent temporary, unauthenticated users who access the system via device fingerprint tracking. These records enable device-based analytics and temporary session management without requiring user registration. Guests transition to member accounts upon successful registration or login.
   *
   * The endpoint supports filtering by soft delete status to identify active versus deleted guest records. Date range filtering allows analysis of guest acquisition trends over specific time periods.
   *
   * @param connection
   * @param body Search criteria for filtering guest records including date ranges, deletion status, device fingerprint patterns, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the hrm_guests table with pagination and
     *   filtering support.
   *
   * Implementation steps:
   * 1. Build base query selecting from hrm_guests table
   * 2. Apply soft delete filter: if deletedAt is null, filter active guests; if true, filter deleted guests; if not provided, include both
   * 3. Apply date range filters on created_at field (createdAfter, createdBefore)
   * 4. Apply device fingerprint search filter using ILIKE pattern matching if provided
   * 5. Order results by created_at descending (newest first)
   * 6. Apply cursor-based or offset pagination based on request parameters
   * 7. Join with hrm_guest_sessions to count active sessions per guest if session count is requested
   * 8. Return paginated results with IPageIHrmGuest.ISummary type
   *
   * Validation rules:
   * - pageSize must be between 1 and 100
   * - Page cursor or offset must be valid
   * - Date range must have createdBefore >= createdAfter if both provided
   * - Device fingerprint search pattern must not exceed 255 characters
   *
   * Error handling:
   * - Return 400 if pagination parameters are invalid
   * - Return 400 if date range is inconsistent
   * - Return 404 if cursor points to non-existent record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IHrmGuest.IRequest,
  ): Promise<IPageIHrmGuest.ISummary> {
    try {
      return await patchHrmGuests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a guest account record by its unique identifier.
   *
   * This endpoint returns the complete guest entity including device fingerprint and timestamps. The guest must exist and must not be soft-deleted (deleted_at must be null). This operation is typically used by administrators for guest account management and device tracking purposes.
   *
   * **Access Control**
   *
   * Requires admin-level authentication with appropriate permissions to view guest records. Regular members cannot access guest account information.
   *
   * **Soft Delete Behavior**
   *
   * Guests that have been soft-deleted (deleted_at is not null) will return a 404 Not Found error. Only active guests with null deleted_at values are retrievable.
   *
   * @param connection
   * @param guestId Unique identifier of the guest account (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the hrm_guests table by id UUID primary
     *   key. Validate the guest exists and deleted_at is null (not
     *   soft-deleted). Return the full guest entity including id,
     *   device_fingerprint, created_at, and updated_at fields. Return 404 Not
     *   Found if guest does not exist or has been soft-deleted. Implement with
     *   a simple SELECT query with WHERE id = $1 AND deleted_at IS NULL.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":guestId")
  public async at(
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<IHrmGuest> {
    try {
      return await getHrmGuestsGuestId({
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
