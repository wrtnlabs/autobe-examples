import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPermission } from "../../../../api/structures/IHrmPermission";
import { IPageIHrmPermission } from "../../../../api/structures/IPageIHrmPermission";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmMemberPermissionsPermissionId } from "../../../../providers/getHrmMemberPermissionsPermissionId";
import { patchHrmMemberPermissions } from "../../../../providers/patchHrmMemberPermissions";

@Controller("/hrm/member/permissions")
export class HrmMemberPermissionsController {
  /**
   * Retrieve a paginated list of available system permissions that can be assigned to roles within the HRM system.
   *
   * This endpoint returns the complete set of predefined permissions organized by category (organization, employee, project, time, reporting). Each permission represents a specific capability that can be granted to custom roles.
   *
   * **Permission Categories**
   *
   * - Organization: org:manage - Full organization configuration management
   * - Employee: employee:manage, employee:view - Employee record management and viewing
   * - Project: project:manage, project:view - Project and task management and viewing
   * - Time: time:manage, time:approve, time:view_all - Time tracking and timesheet approval
   * - Reporting: report:view - Access to organization-wide reports and analytics
   *
   * **Usage**
   *
   * Organization owners use this endpoint to view available permissions when creating or editing custom roles. The permission names follow a {domain}:{action} naming convention for clarity and consistency.
   *
   * @param connection
   * @param body Search criteria including permission name filter, description filter, permission category filter, pagination parameters (page, pageSize), and sorting options.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the hrm_permissions table to retrieve all available permission definitions.
   *
   * Implement cursor-based or offset-based pagination with configurable page size (default 20, max 100).
   *
   * Apply search filters on permission_name and description fields using case-insensitive partial matching.
   *
   * Support filtering by permission category by extracting the domain prefix (org, employee, project, time, report) from permission_name.
   *
   * Sort results by permission_name in ascending alphabetical order by default.
   *
   * Return paginated response with IPageIHrmPermission.ISummary type containing permission summaries (id, permission_name, description).
   *
   * No authentication-specific filtering needed as all authenticated members can view available permissions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPermission.IRequest,
  ): Promise<IPageIHrmPermission.ISummary> {
    try {
      return await patchHrmMemberPermissions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific permission definition by its unique identifier.
   *
   * This operation returns the complete details of a system-defined permission including its name, description, and timestamps. Permissions are predefined by the system and cannot be modified or deleted.
   *
   * The permission name follows the {domain}:{action} naming convention (e.g., org:manage, employee:view, project:manage). Each permission represents a specific capability that can be granted to roles within an organization.
   *
   * Permission Categories
   *
   * Organization permissions control access to organization configuration and lifecycle management. Employee permissions govern employee record access and management. Project permissions manage project and task visibility. Time permissions control time tracking and approval workflows. Reporting permissions provide access to organization-wide analytics.
   *
   * Authorization
   *
   * Access to permission definitions requires valid authentication. The requesting user must be a member of an organization to view permission details.
   *
   * @param connection
   * @param permissionId Unique identifier of the permission definition (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the hrm_permissions table by the permissionId UUID parameter. Return the full permission record including id, permission_name, description, created_at, and updated_at fields. If the permission does not exist, return HTTP 404 with an appropriate error response. The hrm_permissions table contains system-defined permission names that are immutable and cannot be modified through API operations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":permissionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("permissionId")
    permissionId: string & tags.Format<"uuid">,
  ): Promise<IHrmPermission> {
    try {
      return await getHrmMemberPermissionsPermissionId({
        member,
        permissionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
