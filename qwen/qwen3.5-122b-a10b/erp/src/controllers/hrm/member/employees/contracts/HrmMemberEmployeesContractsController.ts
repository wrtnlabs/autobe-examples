import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmContract } from "../../../../../api/structures/IHrmContract";
import { IPageIHrmContract } from "../../../../../api/structures/IPageIHrmContract";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteHrmMemberEmployeesEmployeeIdContractsContractId } from "../../../../../providers/deleteHrmMemberEmployeesEmployeeIdContractsContractId";
import { patchHrmMemberEmployeesEmployeeIdContracts } from "../../../../../providers/patchHrmMemberEmployeesEmployeeIdContracts";
import { postHrmMemberEmployeesEmployeeIdContracts } from "../../../../../providers/postHrmMemberEmployeesEmployeeIdContracts";
import { putHrmMemberEmployeesEmployeeIdContractsContractId } from "../../../../../providers/putHrmMemberEmployeesEmployeeIdContractsContractId";

@Controller("/hrm/member/employees/:employeeId/contracts")
export class HrmMemberEmployeesContractsController {
  /**
   * Create a new employment contract for an employee.
   *
   * This operation establishes a new employment agreement with specified compensation terms and working conditions. When a new contract is created, the system automatically terminates any previously active contract for the same employee by setting its end_date to one day before the new contract's start_date, ensuring continuous employment history without overlapping active contracts.
   *
   * **Authorization**
   *
   * Only users with employee:manage permission within the employee's organization can create contracts. Employees can view their own contracts but cannot create or modify them.
   *
   * **Business Rules**
   *
   * - Each employee can have multiple contracts over time, but only one active contract (NULL end_date) at any given time
   * - The new contract's start_date must not overlap with existing active contracts
   * - Once a contract has an end_date set, it becomes immutable and cannot be edited
   * - Contract creation requires valid pay_rate, pay_period, and start_date
   *
   * @param connection
   * @param employeeId Unique identifier of the employee to whom this contract belongs (UUID format).
   * @param body Contract creation details including compensation terms, working hours, and effective dates. The start_date is required and determines when the contract becomes active. Pay rate and pay period define the compensation structure.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate employee exists and belongs to the authenticated user's organization context
   * 2. Check user has employee:manage permission for the organization
   * 3. Query hrm_contracts table for any existing active contract (end_date IS NULL) for this employee
   * 4. If active contract exists, update its end_date to one day before the new contract's start_date
   * 5. Insert new contract record with provided fields (start_date, end_date, pay_rate, pay_period, working_hours_per_week, notes)
   * 6. Validate pay_period is one of: hourly, daily, weekly, monthly
   * 7. Validate start_date is not in the past and does not create gaps in employment history
   * 8. Return the newly created contract with full details
   * 9. Handle errors: 404 if employee not found, 403 if insufficient permissions, 400 if validation fails, 409 if contract date overlap detected
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmContract.ICreate,
  ): Promise<IHrmContract> {
    try {
      return await postHrmMemberEmployeesEmployeeIdContracts({
        member,
        employeeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of employment contracts for a specific employee within an organization.
   *
   * This endpoint returns all contracts associated with an employee, including both active contracts (no end_date) and historical contracts (with end_date set). The response supports pagination, filtering by contract status, and date range searches to help users find specific contract records.
   *
   * **Access Control**
   *
   * Employees can view their own contracts. Users with employee:view permission can view any employee's contracts within their organization. Permission is validated against the organization context of the employee record.
   *
   * **Contract Lifecycle**
   *
   * Contracts are returned with their lifecycle state indicated by the end_date field. Active contracts have NULL end_date, while historical contracts have an end_date set. Historical contracts are immutable and cannot be modified through this endpoint.
   *
   * **Filtering Options**
   *
   * Supports filtering by contract status (active or historical), pay period type, date ranges for start_date and end_date, and pagination parameters for large result sets.
   *
   * @param connection
   * @param employeeId Unique identifier of the employee whose contracts to retrieve (UUID format).
   * @param body Search criteria including pagination parameters, contract status filter, pay period filter, and date range constraints for filtering contract records.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_contracts table with hrm_employee_id filter.
   *
   * Implementation steps:
   * 1. Validate employeeId exists and belongs to current organization context
   * 2. Check authorization: user is either the employee themselves OR has employee:view permission for the organization
   * 3. Apply search filters from request body:
   *    - status filter: 'active' (end_date IS NULL) or 'historical' (end_date IS NOT NULL)
   *    - pay_period filter: match against pay_period column
   *    - date_range: filter by start_date and/or end_date ranges
   * 4. Apply pagination: limit/offset or cursor-based pagination
   * 5. Apply sorting: default by start_date DESC, support custom sort fields
   * 6. Return paginated response with IHrmContract.ISummary items
   *
   * Edge cases:
   * - Employee with no contracts: return empty array with pagination metadata
   * - Invalid employeeId: return 404 Not Found
   * - Authorization failure: return 403 Forbidden
   * - Employee deleted or deactivated: still return contracts (historical data preserved)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmContract.IRequest,
  ): Promise<IPageIHrmContract.ISummary> {
    try {
      return await patchHrmMemberEmployeesEmployeeIdContracts({
        member,
        employeeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an active employment contract's compensation terms and working conditions.
   *
   * This operation modifies the pay rate, pay period, working hours, and notes for an existing employment contract. Only contracts without an end date (active contracts) can be modified; historical contracts with an end date are immutable to preserve audit trail integrity.
   *
   * **Permission Requirements**
   *
   * Only users with employee:manage permission can update contracts. Employees can view their own contracts but cannot modify them. Users with employee:view permission can view any employee's contracts but cannot edit them.
   *
   * **Business Rules**
   *
   * - The contract must be active (end_date is NULL) to be editable
   * - Past contracts with an end_date are immutable and cannot be modified
   * - The employee_id in the path must match the contract's hrm_employee_id
   * - Changes to contract terms are recorded in the activity log for audit purposes
   * - Updated timestamp is automatically set to the current time
   *
   * @param connection
   * @param employeeId UUID of the employee whose contract is being updated (scoped to organization).
   * @param contractId UUID of the contract to update.
   * @param body Mutable fields for updating an active employment contract. Only fields included in the request will be modified; omitted fields retain their current values.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate user has employee:manage permission for the organization
   * 2. Retrieve the contract by contractId and verify hrm_employee_id matches the path parameter
   * 3. Check that the contract exists and belongs to the current organization (via employee's organization_id)
   * 4. Validate that end_date is NULL (contract is active); reject with error if contract has an end_date
   * 5. Update only the provided mutable fields: pay_rate, pay_period, working_hours_per_week, notes
   * 6. Set updated_at to current timestamp
   * 7. Log the contract modification to hrm_activity_logs with action type 'contract.updated'
   * 8. Return the updated contract object
   *
   * Error cases:
   * - 404: Contract not found or employee/contract mismatch
   * - 403: User lacks employee:manage permission
   * - 400: Contract is not active (has end_date)
   * - 400: Invalid pay_period value (must be hourly, daily, weekly, or monthly)
   * - 400: pay_rate must be positive number
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":contractId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedParam("contractId")
    contractId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmContract.IUpdate,
  ): Promise<IHrmContract> {
    try {
      return await putHrmMemberEmployeesEmployeeIdContractsContractId({
        member,
        employeeId,
        contractId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an inactive employment contract from the system.
   *
   * This operation removes a terminated employment contract record through soft deletion, setting the deleted_at timestamp while preserving the historical record for audit and compliance purposes. The contract must be inactive (have an end_date set) before deletion is allowed.
   *
   * **Business Rules**
   *
   * - Only inactive contracts (those with an end_date) can be deleted
   * - Active contracts (end_date is NULL) must be ended first before deletion
   * - The contract must belong to the specified employee
   * - Organization-level permissions are required to manage contracts
   *
   * **Deletion Behavior**
   *
   * This operation performs a soft delete, marking the contract as deleted without physically removing the record. The contract data remains in the database for historical tracking and audit purposes.
   *
   * **Authorization**
   *
   * The requesting user must have appropriate permissions within the employee's organization to manage employment contracts. This typically includes organization owners, managers, or users with contract management permissions.
   *
   * @param connection
   * @param employeeId UUID identifier of the employee whose contract is being deleted (scoped to organization context).
   * @param contractId UUID identifier of the contract to delete.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Verify the authenticated user has permission to manage contracts in the employee's organization.
   * 2. Retrieve the contract record by contractId and verify it belongs to the specified employeeId.
   * 3. Check if the contract is active (end_date is NULL). If active, reject with error: 'Cannot delete an active contract. End the contract first by setting an end_date.'
   * 4. Perform soft delete by setting deleted_at to current timestamp.
   * 5. Return 204 No Content on success.
   *
   * Edge cases:
   * - Contract not found: 404 Not Found
   * - Contract belongs to different employee: 404 Not Found
   * - Contract is active: 409 Conflict
   * - Insufficient permissions: 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":contractId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedParam("contractId")
    contractId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmMemberEmployeesEmployeeIdContractsContractId({
        member,
        employeeId,
        contractId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
