import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmContractSnapshot } from "../../../../../../api/structures/IHrmContractSnapshot";
import { IPageIHrmContractSnapshot } from "../../../../../../api/structures/IPageIHrmContractSnapshot";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { getHrmMemberEmployeesEmployeeIdContractsContractIdSnapshotsSnapshotId } from "../../../../../../providers/getHrmMemberEmployeesEmployeeIdContractsContractIdSnapshotsSnapshotId";
import { patchHrmMemberEmployeesEmployeeIdContractsContractIdSnapshots } from "../../../../../../providers/patchHrmMemberEmployeesEmployeeIdContractsContractIdSnapshots";

@Controller("/hrm/member/employees/:employeeId/contracts/:contractId/snapshots")
export class HrmMemberEmployeesContractsSnapshotsController {
  /**
   * Retrieve a paginated list of contract snapshots for a specific employment contract.
   *
   * Contract snapshots preserve the historical state of a contract at specific points in time, capturing compensation terms, employment dates, and working arrangements as they existed when each snapshot was created. Each snapshot is an immutable, append-only record that provides a complete audit trail of contract modifications.
   *
   * Snapshots are automatically created when contracts are modified, ensuring a complete history of changes throughout the contract lifecycle. This endpoint allows administrators and authorized users to browse the historical record of a contract's evolution over time.
   *
   * **Access Control**: Users with employee:view permission can view contract snapshots. Employees can view snapshots of their own contracts.
   *
   * **Snapshot Characteristics**: Snapshots are read-only records that cannot be modified or deleted. Each snapshot captures the complete contract state including pay_rate, pay_period, working_hours_per_week, start_date, end_date, and notes at the moment of creation.
   *
   * @param connection
   * @param employeeId Unique identifier of the employee whose contract is being queried (global scope).
   * @param contractId Unique identifier of the contract to retrieve snapshots for (global scope).
   * @param body Search criteria for filtering contract snapshots including date ranges, compensation filters, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_contract_snapshots table filtered by
     *   hrm_contract_id (from contractId path parameter). Apply search filters
     *   from request body: date range (created_at, start_date), pay_period,
     *   pay_rate range. Order by created_at descending for most recent
     *   snapshots first. Implement cursor-based or offset pagination. Validate
     *   that contractId belongs to employeeId before querying snapshots. Return
     *   paginated summary records with snapshot metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedParam("contractId")
    contractId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmContractSnapshot.IRequest,
  ): Promise<IPageIHrmContractSnapshot.ISummary> {
    try {
      return await patchHrmMemberEmployeesEmployeeIdContractsContractIdSnapshots(
        {
          member,
          employeeId,
          contractId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific contract snapshot by employee, contract, and snapshot identifiers.
   *
   * Contract snapshots preserve the complete state of an employment contract at the moment it was captured, creating an immutable historical record. Each snapshot contains the contract's compensation terms, employment dates, working hours, and notes as they existed at snapshot creation time.
   *
   * **Access Control**
   *
   * Employees can view snapshots of their own contracts. Users with employee:view permission can view snapshots of any employee's contracts within the organization. Permission validation occurs before snapshot retrieval.
   *
   * **Snapshot Immutability**
   *
   * Snapshots are append-only records that cannot be modified or deleted after creation. They serve as an audit trail for contract changes and historical analysis of employment terms over time.
   *
   * **Relationship Context**
   *
   * This endpoint accesses snapshots through the full relationship chain: employee → contract → snapshot. All three identifiers must be valid and properly linked for successful retrieval.
   *
   * @param connection
   * @param employeeId Employee identifier (scoped to organization). Must correspond to an active or deactivated employee record.
   * @param contractId Contract identifier (scoped to employee). Must correspond to a contract belonging to the specified employee.
   * @param snapshotId Snapshot identifier (global scope). Unique UUID identifying the specific contract snapshot record.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Implement GET operation for contract snapshot
     *   retrieval with the following logic:
   *
   * 1. **Parameter Validation**: Validate all three path parameters (employeeId, contractId, snapshotId) are valid UUIDs.
   *
   * 2. **Organization Context**: Extract organization ID from authenticated session context. All entities must belong to the same organization.
   *
   * 3. **Permission Check**: Verify user has either:
   *    - employee:view permission for the organization, OR
   *    - Is the employee themselves (employeeId matches current user's employee record)
   *    Return 403 Forbidden if permission check fails.
   *
   * 4. **Entity Validation**:
   *    - Verify employee exists and belongs to the organization
   *    - Verify contract exists, belongs to the employee, and is in the organization
   *    - Verify snapshot exists, belongs to the contract
   *    Return 404 Not Found if any entity is missing or mismatched.
   *
   * 5. **Snapshot Retrieval**: Query hrm_contract_snapshots table by snapshotId with joins to verify employee_id and hrm_contract_id relationships.
   *
   * 6. **Response Construction**: Return full snapshot entity including: id, hrm_contract_id, employee_id, start_date, end_date, pay_rate, pay_period, working_hours_per_week, notes, created_at.
   *
   * 7. **Error Handling**:
   *    - 400 Bad Request: Invalid UUID format in path parameters
   *    - 403 Forbidden: Insufficient permissions
   *    - 404 Not Found: Employee, contract, or snapshot not found, or relationship mismatch
   *    - 500 Internal Server Error: Database query failures
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedParam("contractId")
    contractId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IHrmContractSnapshot> {
    try {
      return await getHrmMemberEmployeesEmployeeIdContractsContractIdSnapshotsSnapshotId(
        {
          member,
          employeeId,
          contractId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
