import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmEmployeeAnalytic } from "../../../../../api/structures/IHrmEmployeeAnalytic";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchHrmMemberEmployeesAnalytics } from "../../../../../providers/patchHrmMemberEmployeesAnalytics";

@Controller("/hrm/member/employees/analytics")
export class HrmMemberEmployeesAnalyticsController {
  /**
   * Retrieve aggregated employee statistics and analytics data for the organization.
   *
   * This endpoint provides summary metrics about the employee workforce including counts by employment type, status distribution, department breakdown, and role assignments. The analytics support workforce planning, reporting, and organizational insights.
   *
   * **Filtering Capabilities**
   *
   * Filters can be applied to narrow the analytics scope:
   * - Date range filtering for historical snapshots
   * - Department filtering for department-specific analytics
   * - Employment type filtering for specific work arrangement analysis
   * - Status filtering to focus on active or deactivated employees
   *
   * **Data Aggregation**
   *
   * The response includes:
   * - Total employee count matching the filter criteria
   * - Breakdown by employment type (full-time, part-time, contractor, intern)
   * - Breakdown by status (active, deactivated)
   * - Breakdown by department with counts per department
   * - Breakdown by role with counts per role
   *
   * **Access Control**
   *
   * Requires `employee:view` permission to access employee analytics data across the organization.
   *
   * @param connection
   * @param body Filter criteria for employee analytics including date ranges, department, employment types, and status filters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_employees table with organization context from authenticated user's session.
   *
   * Apply filter criteria from request body:
   * - If date_range provided, filter employees by created_at within range
   * - If department_id provided, filter by department_id
   * - If employment_types provided, filter by employment_type IN list
   * - If statuses provided, filter by status IN list
   *
   * Perform aggregation queries:
   * - COUNT(*) for total employees matching filters
   * - GROUP BY employment_type for type distribution
   * - GROUP BY status for status distribution
   * - GROUP BY department_id for department breakdown (join hrm_departments for names)
   * - GROUP BY role_id for role breakdown (join hrm_roles for names)
   *
   * Return aggregated statistics in response body.
   *
   * Handle edge cases:
   * - Empty result set: return zero counts across all categories
   * - Department with null department_id: group as 'unassigned'
   * - Permission check: verify employee:view permission before executing query
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmEmployeeAnalytic.IRequest,
  ): Promise<IHrmEmployeeAnalytic> {
    try {
      return await patchHrmMemberEmployeesAnalytics({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
