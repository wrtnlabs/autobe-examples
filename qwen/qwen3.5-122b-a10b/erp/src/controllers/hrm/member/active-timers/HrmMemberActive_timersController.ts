import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmActiveTimer } from "../../../../api/structures/IHrmActiveTimer";
import { IPageIHrmActiveTimer } from "../../../../api/structures/IPageIHrmActiveTimer";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteHrmMemberActiveTimersTimerId } from "../../../../providers/deleteHrmMemberActiveTimersTimerId";
import { patchHrmMemberActiveTimers } from "../../../../providers/patchHrmMemberActiveTimers";
import { postHrmMemberActiveTimers } from "../../../../providers/postHrmMemberActiveTimers";
import { postHrmMemberActiveTimersTimerIdDiscard } from "../../../../providers/postHrmMemberActiveTimersTimerIdDiscard";
import { putHrmMemberActiveTimersTimerId } from "../../../../providers/putHrmMemberActiveTimersTimerId";

@Controller("/hrm/member/active-timers")
export class HrmMemberActive_timersController {
  /**
   * Start a new live timer session for real-time time tracking.
   *
   * This operation initiates an active timer for the authenticated employee, enabling real-time work duration tracking. The employee must select a project, and optionally select a task within that project and provide a description of the work activity.
   *
   * **Business Rules**
   *
   * - Each employee can have at most one active timer at a time. If a timer is already running, this request will fail with a validation error.
   * - Project selection is required. A timer cannot be started without associating it with a project.
   * - Task selection is optional. When provided, the task must belong to the selected project.
   * - The employee must be active (not deactivated) to start a timer.
   * - The timer start timestamp is recorded at the time of request creation.
   *
   * **Response**
   *
   * Returns the created active timer record with all fields including the automatically generated start_timestamp.
   *
   * @param connection
   * @param body Timer start request containing project selection, optional task, and optional work description.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate authenticated employee exists and has
     *   active status (section 30, 150). 2. Check if employee already has an
     *   active timer via hrm_active_timers table (section 302). If exists,
     *   return 409 Conflict. 3. Validate project_id exists and belongs to
     *   employee's organization via hrm_projects table. 4. If task_id provided,
     *   validate it exists, belongs to the selected project, and is not
     *   deleted. 5. Validate employee has permission to track time (member
     *   actor with active employee record). 6. Create hrm_active_timers record
     *   with: - employee_id: from authenticated session - project_id: from
     *   request body - task_id: from request body (nullable) - description:
     *   from request body (nullable) - start_timestamp: current timestamp -
     *   created_at: current timestamp - updated_at: current timestamp 7. Return
     *   the created timer record with full entity structure.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmActiveTimer.ICreate,
  ): Promise<IHrmActiveTimer> {
    try {
      return await postHrmMemberActiveTimers({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of active timer sessions across the organization with optional filtering by employee, project, or date range.
   *
   * This endpoint returns currently running timer sessions for time tracking purposes. Each timer represents an employee actively working on a project or task. The response includes timer details such as start time, duration elapsed, and associated project/task information.
   *
   * **Filtering Options**
   *
   * You can filter the results by employee ID, project ID, task ID, or date ranges. Multiple filters can be combined for precise queries. Pagination parameters control the result set size and cursor position.
   *
   * **Access Control**
   *
   * Members can view their own active timers. Managers and owners can view all active timers within their organization. Access is enforced through organization-scoped permissions.
   *
   * @param connection
   * @param body Search criteria including employee ID filter, project ID filter, task ID filter, date range for timer start time, and pagination parameters for cursor-based navigation.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_active_timers table with
     *   organization-scoped filtering. Apply search filters from request body:
     *   employee_id, project_id, task_id, and date range for start_timestamp.
     *   Join with hrm_employees for employee details, hrm_projects for project
     *   information, and hrm_tasks for task details when requested. Implement
     *   cursor-based pagination for large result sets. Calculate elapsed
     *   duration from start_timestamp to current time for each timer. Enforce
     *   organization context from authentication token to filter timers by
     *   organization_id through employee relationship. Return summary
     *   projections optimized for list display.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmActiveTimer.IRequest,
  ): Promise<IPageIHrmActiveTimer.ISummary> {
    try {
      return await patchHrmMemberActiveTimers({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an active timer's editable properties while preserving the original start time.
   *
   * This endpoint allows employees to modify their running timer's description, selected project, or assigned task before stopping it. The timer's start timestamp remains unchanged to ensure accurate duration calculation when the timer is eventually stopped.
   *
   * **Editable Fields**
   *
   * - `description`: Optional work activity description
   * - `project_id`: Required project reference (must belong to the same organization)
   * - `task_id`: Optional task reference within the selected project
   *
   * **Business Rules**
   *
   * - Only the employee who started the timer can update it
   * - The project must belong to the same organization as the employee
   * - The task (if provided) must belong to the selected project
   * - The timer must still be active (exists in hrm_active_timers table)
   * - Project is required - timers cannot exist without a project selection
   *
   * @param connection
   * @param timerId Unique identifier of the active timer session (global scope).
   * @param body Editable timer properties including optional description, required project reference, and optional task reference within the project.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate the authenticated employee owns this
     *   timer by checking employee_id matches current user's employee record 2.
     *   Verify timer exists in hrm_active_timers table 3. Validate project_id
     *   references a valid project in the same organization 4. If task_id is
     *   provided, validate it belongs to the specified project 5. Update only
     *   description, project_id, and task_id fields 6. Do NOT modify
     *   start_timestamp, created_at, or employee_id 7. Update updated_at to
     *   current timestamp 8. Return the updated timer object with all fields
   *
   * **Error Cases**
   *
   * - 404: Timer not found or does not belong to authenticated employee
   * - 400: Project is required but not provided
   * - 400: Task does not belong to specified project
   * - 403: Timer belongs to another employee
   * - 404: Project or task not found
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":timerId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmActiveTimer.IUpdate,
  ): Promise<IHrmActiveTimer> {
    try {
      return await putHrmMemberActiveTimersTimerId({
        member,
        timerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Stop an active timer session and create a corresponding timelog entry with calculated duration.
   *
   * This operation terminates the live timer tracking for an employee's current work session. When stopped, the system calculates the elapsed duration from the timer's start_timestamp to the current time, rounds it to the nearest minute, and creates a timelog entry in the hrm_timelogs table. The timer record is then deleted from hrm_active_timers.
   *
   * The created timelog includes the project, optional task, description, and calculated duration. This ensures accurate time tracking and billing records are maintained even after the live session ends.
   *
   * **Business Rules**
   *
   * - Only the employee who owns the timer can stop it
   * - The timer must exist and be currently active
   * - A timelog is automatically created with the calculated duration
   * - The operation validates the employee has permission to log time for the referenced project
   *
   * **Error Scenarios**
   *
   * - Timer not found: Returns 404 if no active timer exists with the given ID
   * - Permission denied: Returns 403 if the authenticated employee does not own the timer
   * - Invalid project: Returns 400 if the project does not belong to the employee's organization
   *
   * @param connection
   * @param timerId Unique identifier of the active timer session to stop (global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate the authenticated employee owns the
     *   timer by checking employee_id matches the current user's employee
     *   record 2. Retrieve the hrm_active_timers record by timerId 3. If timer
     *   not found, throw NotFoundError with 404 status 4. Calculate duration:
     *   current_time - start_timestamp, rounded to nearest minute 5. Create
     *   hrm_timelogs entry with: - employee_id: from timer - project_id: from
     *   timer - task_id: from timer (nullable) - description: from timer
     *   (nullable) - duration_minutes: calculated duration - billable: false
     *   (default, unless project has billable flag) - date: current date 6.
     *   Delete the hrm_active_timers record 7. Return the deleted timer object
     *   with calculated duration included in response 8. Wrap in transaction to
     *   ensure atomicity of timelog creation and timer deletion
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":timerId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmMemberActiveTimersTimerId({
        member,
        timerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Discard an active timer session without creating a time log entry.
   *
   * This operation removes the active timer record from the system without generating a corresponding timelog entry. The timer's elapsed duration is not recorded and no time tracking data is created.
   *
   * **Business Rules**
   *
   * - Only the employee who started the timer can discard it
   * - The timer must still be active (not already stopped or discarded)
   * - No timelog is created when discarding
   * - Returns 404 if timer not found or belongs to another employee
   * - Returns 409 if the employee has no active timer
   *
   * @param connection
   * @param timerId UUID of the active timer session to discard
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Extract timerId from path parameter 2. Verify
     *   authenticated employee matches timer.employee_id 3. Query
     *   hrm_active_timers table by id 4. If timer not found or employee_id
     *   mismatch → return 404 Not Found 5. Delete the timer record from
     *   hrm_active_timers table 6. Do NOT create any timelog entry 7. Return
     *   204 No Content on successful discard
   *
   * **Validation**
   * - Timer must exist and belong to current employee
   * - No additional business constraints beyond ownership verification
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":timerId/discard")
  public async discard(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await postHrmMemberActiveTimersTimerIdDiscard({
        member,
        timerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
