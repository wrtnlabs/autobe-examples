import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmTimesheetTimelog } from "../../../../../api/structures/IHrmTimesheetTimelog";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { putHrmMemberTimesheetsTimesheetIdTimelogs } from "../../../../../providers/putHrmMemberTimesheetsTimesheetIdTimelogs";

@Controller("/hrm/member/timesheets/:timesheetId/timelogs")
export class HrmMemberTimesheetsTimelogsController {
  /**
   * Update the timelog entries associated with a draft timesheet by adding or removing specific timelog IDs.
   *
   * This operation allows employees to customize which timelogs are included in their draft timesheet before submission. Only timesheets in draft status can be modified - submitted timesheets lock timelogs from changes, and approved timesheets permanently lock all included timelogs.
   *
   * The request body specifies which timelogs to add and which to remove. The operation validates that all referenced timelogs belong to the same employee as the timesheet and fall within the timesheet's week date range. Timelogs already in the timesheet are not duplicated when added.
   *
   * Business rules enforce that timelogs included in submitted or approved timesheets cannot be removed. The operation returns the updated timesheet with recalculated total hours and the current list of associated timelog IDs.
   *
   * @param connection
   * @param timesheetId UUID of the timesheet to update (scoped to employee)
   * @param body Timelog management request specifying which timelog IDs to add and remove from the draft timesheet.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate the timesheet exists and belongs to the authenticated employee
   * 2. Check timesheet status is 'draft' - reject with 409 Conflict if submitted, approved, or rejected
   * 3. Validate all timelog IDs in the request:
   *    - Each timelog must exist
   *    - Each timelog must belong to the same employee as the timesheet
   *    - Each timelog's date must fall within the timesheet's week_start_date to week_end_date range
   *    - Each timelog must not be part of any submitted or approved timesheet
   * 4. Process additions:
   *    - Insert new rows into hrm_timesheet_timelogs junction table
   *    - Skip duplicates (already associated)
   * 5. Process removals:
   *    - Soft delete rows from hrm_timesheet_timelogs where deleted_at is null
   *    - Validate timelog is not locked by submitted/approved timesheet
   * 6. Recalculate total_hours by summing duration_minutes of all remaining timelogs and dividing by 60
   * 7. Update updated_at timestamp on the timesheet
   * 8. Return the updated timesheet with associated timelog IDs
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmTimesheetTimelog.ITimelogUpdate,
  ): Promise<IHrmTimesheetTimelog> {
    try {
      return await putHrmMemberTimesheetsTimesheetIdTimelogs({
        member,
        timesheetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
