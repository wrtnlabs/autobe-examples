import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmContract } from "../../../../../../api/structures/IHrmContract";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { getHrmMemberOrganizationsOrganizationIdEmployeesEmployeeIdContractsContractId } from "../../../../../../providers/getHrmMemberOrganizationsOrganizationIdEmployeesEmployeeIdContractsContractId";

@Controller(
  "/hrm/member/organizations/:organizationId/employees/:employeeId/contracts/:contractId",
)
export class HrmMemberOrganizationsEmployeesContractsController {
  /**
   * Retrieves a specific employment contract by contract ID within an employee's contract history.
   *
   * This endpoint returns the complete contract record including compensation terms, working hours, and contract dates. Both active and historical contracts are accessible through this endpoint.
   *
   * **Access Control**
   *
   * - Employees can view their own contracts
   * - Users with employee:view permission can view any employee's contracts within the organization
   *
   * **Contract Information**
   *
   * The response includes start date, end date (null for active contracts), pay rate, pay period classification, working hours per week, and optional notes.
   *
   * @param connection
   * @param organizationId UUID of the organization containing the employee and contract.
   * @param employeeId UUID of the employee whose contract is being retrieved.
   * @param contractId UUID of the specific contract to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_contracts table by contract ID and
     *   validate the contract belongs to the specified employee within the
     *   organization. Verify the requesting user has permission to view this
     *   contract (either the contract belongs to the authenticated employee or
     *   the user has employee:view permission). Return full contract entity
     *   with all fields including id, hrm_employee_id, start_date, end_date,
     *   pay_rate, pay_period, working_hours_per_week, notes, created_at,
     *   updated_at, and deleted_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedParam("contractId")
    contractId: string & tags.Format<"uuid">,
  ): Promise<IHrmContract> {
    try {
      return await getHrmMemberOrganizationsOrganizationIdEmployeesEmployeeIdContractsContractId(
        {
          member,
          organizationId,
          employeeId,
          contractId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
