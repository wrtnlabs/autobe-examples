import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmContractAnalytic } from "../../../../../../api/structures/IHrmContractAnalytic";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { getHrmMemberOrganizationsOrganizationIdAnalyticsContracts } from "../../../../../../providers/getHrmMemberOrganizationsOrganizationIdAnalyticsContracts";

@Controller("/hrm/member/organizations/:organizationId/analytics/contracts")
export class HrmMemberOrganizationsAnalyticsContractsController {
  /**
   * Retrieve contract analytics and statistics for an organization.
   *
   * This endpoint provides aggregated insights into employment contracts within the organization, including contract distribution by pay period, active versus historical contract counts, compensation statistics, and employment type breakdowns. The data is computed from all contracts associated with employees in the organization.
   *
   * **Analytics Metrics**
   *
   * The response includes total contract counts, active contract counts (contracts without end_date), historical contract counts (contracts with end_date), pay period distribution (hourly, daily, weekly, monthly), average pay rates grouped by pay period, average working hours per week, and employment type distribution across all contracts.
   *
   * **Access Control**
   *
   * Users must be authenticated members of the organization. Users with employee:view permission can access contract analytics. The organization_id parameter identifies the target organization for which analytics are computed.
   *
   * @param connection
   * @param organizationId UUID identifier of the organization for which contract analytics are requested (global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_contracts table with organization
     *   context through employee relationship. Join hrm_employees to filter
     *   contracts by organization_id. Calculate aggregated statistics
     *   including: total contract count, active vs historical contract
     *   distribution, pay period breakdown (hourly/daily/weekly/monthly),
     *   average pay rates by pay period, employment type distribution, and
     *   working hours statistics. Apply soft-delete filter (deleted_at IS
     *   NULL). Return analytics summary object with computed metrics.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async analytics(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
  ): Promise<IHrmContractAnalytic> {
    try {
      return await getHrmMemberOrganizationsOrganizationIdAnalyticsContracts({
        member,
        organizationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
