import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmOrganizationOwner } from "../../../../../api/structures/IHrmOrganizationOwner";
import { IPageIHrmOrganizationOwner } from "../../../../../api/structures/IPageIHrmOrganizationOwner";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmMemberOrganizationsOrganizationIdOwnersOwnerId } from "../../../../../providers/getHrmMemberOrganizationsOrganizationIdOwnersOwnerId";
import { patchHrmMemberOrganizationsOrganizationIdOwners } from "../../../../../providers/patchHrmMemberOrganizationsOrganizationIdOwners";

@Controller("/hrm/member/organizations/:organizationId/owners")
export class HrmMemberOrganizationsOwnersController {
  /**
   * Retrieve ownership records for a specific organization with pagination and filtering.
   *
   * This endpoint returns a paginated list of organization ownership records, including current and historical owners. Each record contains ownership period information (start/end dates) and the associated user details.
   *
   * The operation supports filtering by ownership status (current vs. historical) and date ranges, enabling organizations to audit their ownership history or identify the current owner.
   *
   * **Access Control**: Requires authentication with organization context. Users can access ownership records for organizations they belong to.
   *
   * @param connection
   * @param organizationId UUID of the organization to retrieve ownership records for (global scope).
   * @param body Search criteria for filtering ownership records including pagination parameters, ownership status filter, and date range constraints.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_organization_owners table filtered by organization_id.
   *
   * 1. Validate organization exists and user has access permission
   * 2. Apply search filters from request body:
   *    - is_current: filter by current/historical ownership
   *    - date_range: filter by started_at/ended_at range
   *    - pagination: page, pageSize parameters
   * 3. Join with hrm_members to include user profile information (display_name, email)
   * 4. Order by started_at descending (most recent first)
   * 5. Return paginated results with total count
   *
   * Edge cases:
   * - Return empty array if no ownership records exist
   * - Handle invalid organization_id with 404 error
   * - Enforce permission checks before returning data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmOrganizationOwner.IRequest,
  ): Promise<IPageIHrmOrganizationOwner.ISummary> {
    try {
      return await patchHrmMemberOrganizationsOrganizationIdOwners({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific organization owner record with user details.
   *
   * This endpoint returns detailed information about an organization owner, including ownership metadata (start date, current status) and the associated user account information. The owner record tracks who currently or historically owns the organization, supporting ownership transfer workflows.
   *
   * **Access Control**
   *
   * Only authenticated members within the organization can access this endpoint. Organization owners have full access to all owner records. The requesting user must belong to the specified organization.
   *
   * **Response Data**
   *
   * The response includes the ownership record fields (organization_id, user_id, is_current, started_at, ended_at) along with the associated user's profile information (email, display name from global profile). Historical ownership records (ended_at not null) are also retrievable for audit purposes.
   *
   * **Error Handling**
   *
   * Returns 404 if the owner record does not exist for the specified organization. Returns 403 if the user lacks permission to access organization owner information. Returns 400 if organizationId or ownerId are invalid UUIDs.
   *
   * @param connection
   * @param organizationId UUID identifier of the organization (global scope).
   * @param ownerId UUID identifier of the owner record within the organization (global scope).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_organization_owners table by organization_id and id (ownerId). Verify the requesting user belongs to the organization via hrm_employees table. Join with hrm_members to retrieve user email and profile data. Check soft delete status on organization and owner record - return 404 if either is deleted. Return full owner entity with embedded user information. Enforce permission check: user must be organization member (any role) to view owner details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":ownerId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedParam("ownerId")
    ownerId: string & tags.Format<"uuid">,
  ): Promise<IHrmOrganizationOwner> {
    try {
      return await getHrmMemberOrganizationsOrganizationIdOwnersOwnerId({
        member,
        organizationId,
        ownerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
