  /**
   * Update department properties including name, description, and parent department assignment.
   *
   * This operation modifies an existing department within the specified organization. Users with organization management permission can update department name, description, and parent department reference to reorganize the department hierarchy.
   *
   * **Validation Rules**
   *
   * - The parent department (if specified) must exist within the same organization
   * - Self-reference is not allowed (department cannot be its own parent)
   * - One-level nesting constraint: the parent department cannot itself have a parent department
   * - The department must exist and not be soft-deleted
   *
   * **Permission Requirements**
   *
   * Only users with `org:manage` permission within the organization can perform this operation.
   *
   * **Response**
   *
   * Returns the complete updated department entity with all fields including timestamps.
   *
   * @param connection
   * @param organizationId Unique identifier of the organization containing the department (global scope)
   * @param departmentId Unique identifier of the department to update (scoped to organization)
   * @param body Department fields to update. At least one field must be provided. Name is required if included. Parent department validation applies if parent_department_id is specified.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Implement department update with validation:
   *
   * 1. **Authentication & Authorization**
   *    - Verify JWT token is valid and user is authenticated
   *    - Check user has `org:manage` permission for the specified organization
   *    - Validate organization_id matches the authenticated user's accessible organizations
   *
   * 2. **Resource Validation**
   *    - Fetch department by id and organization_id
   *    - Return 404 if department not found or soft-deleted (deleted_at IS NOT NULL)
   *    - Return 403 if user lacks permission
   *
   * 3. **Parent Department Validation** (if parent_department_id provided in request)
   *    - Verify parent_department_id exists in the same organization
   *    - Ensure parent_department_id is not the same as department_id (no self-reference)
   *    - Query parent department to verify parent_department.parent_department_id IS NULL (one-level nesting constraint)
   *    - Return 400 with validation error if any constraint violated
   *
   * 4. **Update Operation**
   *    - Update name, description, and parent_department_id fields
   *    - Set updated_at to current timestamp
   *    - Use database transaction to ensure atomicity
   *
   * 5. **Response**
   *    - Return 200 with complete department entity including all fields
   *    - Include organization context in response for client convenience
   *
   * **Edge Cases**
   * - Empty string for name should be rejected (name is required)
   * - Null parent_department_id is valid (converts to root-level department)
   * - Concurrent updates: use optimistic locking or handle update conflicts
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
