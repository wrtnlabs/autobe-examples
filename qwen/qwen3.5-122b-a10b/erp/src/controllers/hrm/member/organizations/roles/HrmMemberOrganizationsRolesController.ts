import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmRole } from "../../../../../api/structures/IHrmRole";
import { IPageIHrmRole } from "../../../../../api/structures/IPageIHrmRole";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteHrmMemberOrganizationsOrganizationIdRolesRoleId } from "../../../../../providers/deleteHrmMemberOrganizationsOrganizationIdRolesRoleId";
import { getHrmMemberOrganizationsOrganizationIdRolesRoleId } from "../../../../../providers/getHrmMemberOrganizationsOrganizationIdRolesRoleId";
import { patchHrmMemberOrganizationsOrganizationIdRoles } from "../../../../../providers/patchHrmMemberOrganizationsOrganizationIdRoles";
import { postHrmMemberOrganizationsOrganizationIdRoles } from "../../../../../providers/postHrmMemberOrganizationsOrganizationIdRoles";
import { putHrmMemberOrganizationsOrganizationIdRolesRoleId } from "../../../../../providers/putHrmMemberOrganizationsOrganizationIdRolesRoleId";

@Controller("/hrm/member/organizations/:organizationId/roles")
export class HrmMemberOrganizationsRolesController {
  /**
   * Create a custom role within an organization.
   *
   * This endpoint allows organization owners to define new custom roles with specific permission configurations. Custom roles are organization-scoped and cannot be shared across organizations.
   *
   * **Business Rules**
   * - Only organization owners can create custom roles
   * - Role names must be unique within the organization (built-in roles: Owner, Manager, Employee are reserved)
   * - Custom roles have `is_builtin = false` and can be deleted if no employees are assigned
   * - Permissions are assigned separately via the role permissions management endpoints
   *
   * **Validation**
   * - Role name cannot be empty or exceed maximum length
   * - Role name cannot conflict with built-in role names (Owner, Manager, Employee)
   * - Organization must exist and the caller must have owner permissions
   *
   * @param connection
   * @param organizationId Unique identifier of the organization where the role will be created (UUID format).
   * @param body Custom role creation request including name and optional description. The is_builtin field is automatically set to false for custom roles.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate organization exists and caller has owner permissions via organization context
   * 2. Validate role name is not empty and does not conflict with built-in role names (Owner, Manager, Employee)
   * 3. Check for duplicate role name within the organization using unique constraint on (hrm_organization_id, name)
   * 4. Insert new role record with is_builtin=false, generated UUID id, and current timestamps
   * 5. Return the created role object with all fields including id and timestamps
   * 6. Handle constraint violations: return 409 Conflict for duplicate name, 404 Not Found for invalid organization, 403 Forbidden for insufficient permissions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmRole.ICreate,
  ): Promise<IHrmRole> {
    try {
      return await postHrmMemberOrganizationsOrganizationIdRoles({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of roles within an organization.
   *
   * This endpoint returns all roles (both built-in and custom) associated with the specified organization. Built-in roles (Owner, Manager, Employee) are automatically included in every organization. Custom roles created by organization owners are also returned.
   *
   * The response supports filtering by role name, built-in status, and pagination parameters. Results are ordered by role name alphabetically.
   *
   * @param connection
   * @param organizationId Unique identifier of the organization (global scope).
   * @param body Search criteria for filtering roles including name pattern, built-in status filter, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the hrm_roles table filtering by hrm_organization_id matching the path parameter. Exclude soft-deleted roles (deleted_at IS NULL). Apply search filters from request body: name partial match, is_builtin filter. Implement cursor-based pagination with page and pageSize parameters. Order results by name ascending. Return summary projection excluding permission details (permissions retrieved via separate endpoint). Validate organization exists and caller has permission to view roles.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmRole.IRequest,
  ): Promise<IPageIHrmRole.ISummary> {
    try {
      return await patchHrmMemberOrganizationsOrganizationIdRoles({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific role within an organization along with its assigned permissions.
   *
   * This operation returns complete role information including the role's name, description, built-in status, and all permissions assigned to it through the role-permission junction table. The response is useful for displaying role configurations in administrative interfaces or for auditing purposes.
   *
   * **Organization Scope**: The role is scoped to the specified organization. Roles are not shared across organizations, and the organization context must be valid and accessible by the authenticated user.
   *
   * **Permission Details**: Each permission in the response includes the permission name (following {domain}:{action} convention) and its human-readable description. This allows consumers to understand what capabilities the role grants.
   *
   * **Built-in Role Protection**: Built-in roles (Owner, Manager, Employee) are marked with `is_builtin=true`. These roles cannot be deleted or modified, but their details can be retrieved.
   *
   * **Authorization**: The authenticated user must have sufficient permissions to view roles in the specified organization. Typically, this requires employee management or organization administration capabilities.
   *
   * @param connection
   * @param organizationId UUID of the organization containing the role (global scope)
   * @param roleId UUID of the role to retrieve (scoped to organization)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate organization_id exists and user has access to it.
   * 2. Query hrm_roles table where id = roleId AND hrm_organization_id = organizationId.
   * 3. Return 404 if role not found or belongs to different organization.
   * 4. Return 403 if user lacks permission to view roles in this organization.
   * 5. Join hrm_role_permissions on hrm_role_id = role.id.
   * 6. Join hrm_permissions on hrm_permission_id = role_permissions.hrm_permission_id.
   * 7. Construct response with role fields (id, name, is_builtin, description, created_at, updated_at) and nested permissions array.
   * 8. Permissions array should include permission_name and description from hrm_permissions table.
   * 9. Exclude deleted roles (check deleted_at is null) unless user has admin privileges to view soft-deleted resources.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":roleId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
  ): Promise<IHrmRole.IDetailed> {
    try {
      return await getHrmMemberOrganizationsOrganizationIdRolesRoleId({
        member,
        organizationId,
        roleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a custom role within an organization.
   *
   * This operation allows organization owners to modify the name and description of custom roles. Built-in roles (Owner, Manager, Employee) are immutable and cannot be updated through this endpoint.
   *
   * ## Business Rules
   *
   * - Only organization owners can update roles
   * - Built-in roles (is_builtin = true) cannot be modified
   * - Role name must remain unique within the organization
   * - Soft delete status is preserved (deleted roles cannot be updated)
   *
   * ## Relationships
   *
   * - Role belongs to a specific organization
   * - Role may be assigned to multiple employees
   * - Role has associated permissions through hrm_role_permissions
   *
   * ## Error Handling
   *
   * - Returns 404 if role or organization does not exist
   * - Returns 403 if user is not organization owner
   * - Returns 400 if attempting to update a built-in role
   * - Returns 409 if new role name conflicts with existing role in organization
   *
   * @param connection
   * @param organizationId Unique identifier of the organization containing the role (global scope).
   * @param roleId Unique identifier of the role to update (scoped to organization).
   * @param body Role update payload containing modifiable fields. Only name and description can be updated. Built-in roles cannot be modified.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implement role update with the following logic:
   *
   * 1. **Authorization Check**: Verify user is organization owner. Extract organization context from JWT token and compare with organizationId.
   *
   * 2. **Resource Validation**:
   *    - Query hrm_roles table by id (roleId) and hrm_organization_id (organizationId)
   *    - Return 404 if role not found or organization mismatch
   *    - Check deleted_at is null (role not soft-deleted)
   *
   * 3. **Built-in Role Protection**:
   *    - Check is_builtin flag on role record
   *    - Return 400 error if is_builtin = true (built-in roles cannot be modified)
   *
   * 4. **Name Uniqueness Validation**:
   *    - If name is being updated, query hrm_roles for existing role with same hrm_organization_id and name (excluding current role)
   *    - Return 409 conflict if duplicate name exists
   *
   * 5. **Update Operation**:
   *    - Update name and/or description fields from request body
   *    - Set updated_at to current timestamp
   *    - Do NOT allow updating is_builtin, hrm_organization_id, or id fields
   *
   * 6. **Response**: Return updated role object with all fields including updated_at timestamp.
   *
   * 7. **Edge Cases**:
   *    - Empty string validation for name (required field)
   *    - Description can be null or empty string
   *    - Transaction-safe update to prevent partial modifications
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":roleId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmRole.IUpdate,
  ): Promise<IHrmRole> {
    try {
      return await putHrmMemberOrganizationsOrganizationIdRolesRoleId({
        member,
        organizationId,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a custom role within an organization.
   *
   * This operation soft-deletes a role by setting its deleted_at timestamp. Built-in roles (Owner, Manager, Employee) cannot be deleted. Custom roles can only be deleted if no employees are currently assigned to them.
   *
   * ## Deletion Constraints
   *
   * **Built-in Role Protection**: The three built-in roles (Owner, Manager, Employee) are immutable and cannot be deleted. Attempting to delete a built-in role will result in a 403 Forbidden error.
   *
   * **Employee Assignment Check**: Custom roles can only be deleted if no employees are currently assigned to the role. If employees are assigned, they must be reassigned to a different role before deletion is allowed. Attempting to delete an assigned role will result in a 409 Conflict error.
   *
   * **Organization Scope**: The role must belong to the specified organization. Cross-organization role deletion is not permitted.
   *
   * ## Soft Delete Behavior
   *
   * The role is soft-deleted rather than permanently removed. This preserves historical employee assignments and audit trail integrity. The role will no longer appear in active role listings but historical data remains accessible.
   *
   * @param connection
   * @param organizationId Unique identifier of the organization in UUID format (global scope).
   * @param roleId Unique identifier of the role within the organization in UUID format (scoped to organization).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate organization exists and user has owner permission for the organization.
   * 2. Retrieve the role by roleId within the specified organization.
   * 3. Check if role is built-in (is_builtin = true). If yes, return 403 Forbidden error with message 'Built-in roles cannot be deleted'.
   * 4. Check if any employees are assigned to this role by querying hrm_employees table where hrm_role_id equals the roleId. If employees exist, return 409 Conflict error with list of affected employee IDs.
   * 5. Set deleted_at to current timestamp on the role record within a database transaction.
   * 6. Return the deleted role object with updated deleted_at timestamp.
   * 7. Ensure transaction atomicity - if any step fails, rollback the entire operation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":roleId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmMemberOrganizationsOrganizationIdRolesRoleId({
        member,
        organizationId,
        roleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
