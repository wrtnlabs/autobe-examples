import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIHrmTaskHistory } from "../../../../../../../api/structures/IPageIHrmTaskHistory";
import { MemberAuth } from "../../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../../decorators/payload/MemberPayload";
import { getHrmMemberOrganizationsOrganizationIdProjectsProjectIdTasksTaskIdHistory } from "../../../../../../../providers/getHrmMemberOrganizationsOrganizationIdProjectsProjectIdTasksTaskIdHistory";

@Controller(
  "/hrm/member/organizations/:organizationId/projects/:projectId/tasks/:taskId/history",
)
export class HrmMemberOrganizationsProjectsTasksHistoryController {
  /**
   * Retrieves the complete audit trail of status changes for a specific task within a project.
   *
   * This endpoint returns all recorded task status transitions, including the timestamp of each change, the previous status, the new status, and the member who initiated the change. Task history is automatically generated by the system whenever a task status changes and cannot be manually created, modified, or deleted.
   *
   * **Access Control**
   * Users must have project:view permission for the parent project to access task history. The requesting user must also have visibility into the specific task.
   *
   * **Response Format**
   * History records are returned in chronological order with the most recent changes first. Each record includes the complete transition details for audit and debugging purposes.
   *
   * **Use Cases**
   * - Track task workflow progression over time
   * - Audit who made specific status changes
   * - Debug task lifecycle issues
   * - Compliance and reporting requirements
   *
   * @param connection
   * @param organizationId Unique identifier of the organization (global scope)
   * @param projectId Unique identifier of the project within the organization (scoped to organization)
   * @param taskId Unique identifier of the task within the project (scoped to project)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_task_histories table filtered by
     *   hrm_task_id. Join with hrm_members to include member information who
     *   made each change. Order results by timestamp descending (most recent
     *   first). Implement pagination with cursor or offset-based approach.
     *   Verify user has project:view permission for the parent project. Return
     *   404 if task does not exist or user lacks access. History records are
     *   immutable and read-only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
  ): Promise<IPageIHrmTaskHistory.ISummary> {
    try {
      return await getHrmMemberOrganizationsOrganizationIdProjectsProjectIdTasksTaskIdHistory(
        {
          member,
          organizationId,
          projectId,
          taskId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
