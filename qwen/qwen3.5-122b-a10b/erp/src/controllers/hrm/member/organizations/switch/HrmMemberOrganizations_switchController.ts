import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmOrganization } from "../../../../../api/structures/IHrmOrganization";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { postHrmMemberOrganizationsOrganizationIdSwitch } from "../../../../../providers/postHrmMemberOrganizationsOrganizationIdSwitch";

@Controller("/hrm/member/organizations/:organizationId/switch")
export class HrmMemberOrganizations_switchController {
  /**
   * Switch the current user's organization context to a different organization they belong to.
   *
   * This operation updates the session's active organization context without requiring re-authentication. All subsequent API requests within this session will be scoped to the newly selected organization.
   *
   * The user must be a member of the target organization. Data isolation is enforced to ensure users can only access data within their selected organization context.
   *
   * ## Security and Authorization
   *
   * - Requires authenticated member session
   * - Target organization must be in user's membership list
   * - Previous organization context is replaced with the new one
   *
   * ## Response
   *
   * Returns the switched organization's summary information to confirm the new active context.
   *
   * @param connection
   * @param organizationId UUID of the organization to switch to. The user must be a member of this organization.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate the authenticated user's session exists and is not expired.
   * 2. Verify the organizationId path parameter is a valid UUID format.
   * 3. Query hrm_organizations table to confirm the organization exists and is not soft-deleted (deleted_at IS NULL).
   * 4. Verify the user is a member of this organization by checking hrm_employees table for a record with matching hrm_member_id and hrm_organization_id.
   * 5. If user is not a member, return 403 Forbidden with error code 'organization.not_member'.
   * 6. Update the session's organization context in hrm_member_sessions or session store.
   * 7. Return 200 OK with the organization summary (id, name, description, logo_image_url, currency, timezone).
   * 8. Log the organization switch action in hrm_activity_logs for audit trail.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async select(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
  ): Promise<IHrmOrganization.ISummary> {
    try {
      return await postHrmMemberOrganizationsOrganizationIdSwitch({
        member,
        organizationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
