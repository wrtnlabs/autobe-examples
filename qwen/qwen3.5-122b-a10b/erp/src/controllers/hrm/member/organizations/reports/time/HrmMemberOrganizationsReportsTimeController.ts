import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmTimelog } from "../../../../../../api/structures/IHrmTimelog";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { patchHrmMemberOrganizationsOrganizationIdReportsTime } from "../../../../../../providers/patchHrmMemberOrganizationsOrganizationIdReportsTime";

@Controller("/hrm/member/organizations/:organizationId/reports/time")
export class HrmMemberOrganizationsReportsTimeController {
  /**
   * Retrieve aggregated time tracking reports grouped by employee, project, and task with customizable filters for an organization.
   *
   * This endpoint provides comprehensive time analytics for organizational reporting. Users can filter by date range, billable status, and specific projects or employees. Results are aggregated to show total hours, billable vs non-billable breakdowns, and can be grouped by various dimensions for management dashboards and client billing reports.
   *
   * **Filtering and Grouping**
   *
   * Date range filtering supports custom periods from daily to yearly views. Billable status filtering allows separation of chargeable client work from internal administrative tasks. Grouping options include employee, project, task, or combinations thereof for hierarchical reporting.
   *
   * **Data Sources**
   *
   * Report data aggregates from timelog records in the hrm_timelogs table, joined with employee, project, and task information for contextual details. Approved timesheet timelogs and active timer sessions are both included in calculations.
   *
   * **Organization Context**
   *
   * Reports are scoped to the specified organization for multi-tenancy isolation. Users can only access reports for organizations where they have appropriate permissions (typically time:report permission).
   *
   * @param connection
   * @param organizationId Organization identifier for multi-tenancy scoping (global scope)
   * @param body Report filtering criteria including date range (start and end dates), billable status filter, optional employee/project/task IDs for narrowing scope, and grouping dimension preferences.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_timelogs table with date range
     *   filtering on the date column. Apply billable flag filter if specified.
     *   Join with hrm_employees for employee details, hrm_projects for project
     *   information, and hrm_tasks for task details.
   *
   * Apply organization scoping through employee.organization_id matching the organizationId path parameter to ensure multi-tenancy isolation. Filter out soft-deleted timelogs (deleted_at IS NULL).
   *
   * Group results by requested dimensions (employee, project, task) and calculate aggregated metrics: total duration_minutes summed and converted to hours, billable hours, non-billable hours, and entry count.
   *
   * Handle edge cases: empty date ranges return zero results, invalid groupings default to employee-level grouping, null task associations group under 'unassigned'.
   *
   * Return cursor-based pagination for large result sets with total_hours summary at the top level.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmTimelog.IRequest,
  ): Promise<IHrmTimelog.ISummary> {
    try {
      return await patchHrmMemberOrganizationsOrganizationIdReportsTime({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
