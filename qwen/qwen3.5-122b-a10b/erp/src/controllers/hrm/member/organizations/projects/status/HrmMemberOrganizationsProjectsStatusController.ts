import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmProject } from "../../../../../../api/structures/IHrmProject";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { putHrmMemberOrganizationsOrganizationIdProjectsProjectIdStatus } from "../../../../../../providers/putHrmMemberOrganizationsOrganizationIdProjectsProjectIdStatus";

@Controller(
  "/hrm/member/organizations/:organizationId/projects/:projectId/status",
)
export class HrmMemberOrganizationsProjectsStatusController {
  /**
   * Update the status of a project within an organization.
   *
   * Users with project management permission can transition a project between active, archived, and completed states. Active projects accept new timelogs and task assignments. Archived projects are paused but preserved for historical reference. Completed projects are finished and cannot receive new timelogs.
   *
   * **Status Transition Rules**
   *
   * Projects can transition from active to archived or completed. Archived projects can be reactivated to active status. Completed projects can be changed back to active status. When a project transitions to archived or completed, existing timelogs are preserved but no new timelogs can be added.
   *
   * **Permissions**
   *
   * Only users with project:manage permission can update project status. This typically includes organization owners and managers with project management roles.
   *
   * **Error Handling**
   *
   * Returns 404 if the project does not exist. Returns 403 if the user lacks permission. Returns 400 if the status value is invalid.
   *
   * @param connection
   * @param organizationId UUID of the organization that owns the project (global scope).
   * @param projectId UUID of the project to update (global scope).
   * @param body Project status update request containing the new status value.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_projects table by organizationId and
     *   projectId. Verify the project exists and belongs to the organization.
     *   Validate the user has project:manage permission. Check the new status
     *   value is one of: active, archived, completed. Validate status
     *   transition rules: archived and completed projects cannot receive new
     *   timelogs. Update the status field and updated_at timestamp. Return the
     *   updated project entity. If project not found, return 404. If permission
     *   denied, return 403. If invalid status value, return 400.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmProject.IStatusUpdate,
  ): Promise<IHrmProject> {
    try {
      return await putHrmMemberOrganizationsOrganizationIdProjectsProjectIdStatus(
        {
          member,
          organizationId,
          projectId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
