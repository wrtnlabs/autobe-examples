import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmEmployeeDashboard } from "../../../../../../api/structures/IHrmEmployeeDashboard";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { getHrmMemberOrganizationsOrganizationIdDashboardEmployee } from "../../../../../../providers/getHrmMemberOrganizationsOrganizationIdDashboardEmployee";

@Controller("/hrm/member/organizations/:organizationId/dashboard/employee")
export class HrmMemberOrganizationsDashboardEmployeeController {
  /**
   * Retrieve the current employee's personal dashboard with work metrics and activity summaries.
   *
   * This endpoint aggregates data from multiple sources including time tracking records, active timers, timesheets, and assigned tasks to provide a comprehensive overview of the employee's current work status within the organization.
   *
   * **Dashboard Components**
   *
   * The response includes hours worked today and this week, the currently active timer session if running, recent time log entries, the employee's pending timesheet status, and tasks assigned to them. All data is scoped to the organization context provided in the path parameter.
   *
   * **Security and Access**
   *
   * Only the authenticated employee can access their own dashboard. Organization-scoped access is enforced to ensure data isolation between organizations. The employee must have an active status in the organization to retrieve dashboard data.
   *
   * @param connection
   * @param organizationId UUID identifier of the organization containing the employee dashboard (organization scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Implement as a composite read operation
     *   aggregating data from multiple tables:
   *
   * 1. **Hours Calculation**: Query hrm_timelogs for the current employee_id, filter by date ranges (today: current date, this week: Monday to current date), sum duration_minutes and convert to hours.
   *
   * 2. **Active Timer**: Query hrm_active_timers where employee_id matches current user and record exists. Return timer details including project, task, description, and start_timestamp.
   *
   * 3. **Recent Timelogs**: Query hrm_timelogs for current employee_id, order by date DESC, limit to last 5 entries. Include project name and task title via joins.
   *
   * 4. **Pending Timesheet**: Query hrm_timesheets where hrm_employee_id matches and status is 'submitted'. Return the most recent pending timesheet with week dates and total_hours.
   *
   * 5. **Assigned Tasks**: Query hrm_tasks where assigned_employee_id matches, status is 'open' or 'in-progress'. Include project context and due_date.
   *
   * **Edge Cases**
   *
   * - No active timer: Return null for activeTimer field
   * - No pending timesheet: Return null for pendingTimesheet field
   * - No assigned tasks: Return empty array for assignedTasks
   * - Employee deactivated: Return 403 Forbidden
   * - Organization not found: Return 404 Not Found
   *
   * **Performance Considerations**
   *
   * Use database joins to minimize round trips. Index hrm_timelogs on (hrm_employee_id, date) and hrm_tasks on (assigned_employee_id, status) for efficient queries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
  ): Promise<IHrmEmployeeDashboard> {
    try {
      return await getHrmMemberOrganizationsOrganizationIdDashboardEmployee({
        member,
        organizationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
