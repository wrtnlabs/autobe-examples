import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmEmployee } from "../../../../api/structures/IHrmEmployee";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putHrmMemberProfile } from "../../../../providers/putHrmMemberProfile";

@Controller("/hrm/member/profile")
export class HrmMemberProfileController {
  /**
   * Update the authenticated member's global profile information.
   *
   * This endpoint allows members to update their global profile data including display name, avatar image URL, and phone number. The profile information is shared across all organizations the member belongs to and changes are immediately visible in all organization contexts.
   *
   * **Fields**:
   * - Display name: The user's display name shown throughout the platform
   * - Avatar image URL: URL to the user's profile avatar image
   * - Phone number: Contact phone number for the user
   *
   * **Authorization**:
   * - Requires authenticated member session
   * - Users can only update their own profile
   *
   * @param connection
   * @param body Profile update data containing display name, avatar image URL, and phone number fields. All fields are optional; only provided fields will be updated.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate the authenticated member from JWT
     *   token in Authorization header 2. Extract member ID from the session
     *   context 3. Validate request body fields: - display_name: optional
     *   string, max 100 characters - avatar_image_url: optional string, must be
     *   valid URL format if provided - phone_number: optional string, validate
     *   phone number format 4. Update the hrm_members table record with the
     *   provided fields 5. Return the updated profile object with all fields 6.
     *   Handle validation errors with appropriate error codes
     *   (INVALID_DISPLAY_NAME, INVALID_AVATAR_URL, INVALID_PHONE_NUMBER)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmEmployee.IUpdate,
  ): Promise<IHrmEmployee> {
    try {
      return await putHrmMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
