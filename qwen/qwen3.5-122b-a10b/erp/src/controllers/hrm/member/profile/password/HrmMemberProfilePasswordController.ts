import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmMember } from "../../../../../api/structures/IHrmMember";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { putHrmMemberProfilePassword } from "../../../../../providers/putHrmMemberProfilePassword";

@Controller("/hrm/member/profile/password")
export class HrmMemberProfilePasswordController {
  /**
   * Change the authenticated user's account password.
   *
   * This operation requires verification of the current password before accepting a new password. The new password must meet the system's security requirements and be different from the current password. Password changes apply globally to the user account and affect access to all organizations the user belongs to.
   *
   * After a successful password change, all existing sessions are invalidated. The user must log in again with the new password to continue accessing the system.
   *
   * **Security Requirements**:
   * - Current password must be validated against stored credentials
   * - New password must meet platform security policies (minimum length, complexity)
   * - New password must differ from the current password
   * - Password hash is stored using bcrypt or equivalent secure algorithm
   *
   * @param connection
   * @param body Password change request containing the current password for verification and the new password to set.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Authenticate the request using JWT token from
     *   Authorization header. 2. Extract member ID from the authenticated
     *   session. 3. Retrieve the hrm_members record by ID. 4. Validate the
     *   current_password by comparing against password_hash using
     *   bcrypt.compare(). 5. If current password is incorrect, return 401
     *   Unauthorized with error code 'INVALID_CURRENT_PASSWORD'. 6. Validate
     *   new_password meets security requirements (minimum 8 characters,
     *   uppercase, lowercase, number, special character). 7. Validate
     *   new_password is different from current_password. 8. Hash the
     *   new_password using bcrypt with appropriate salt rounds. 9. Update the
     *   password_hash field in hrm_members table. 10. Update the updated_at
     *   timestamp. 11. Invalidate all existing sessions for this member (delete
     *   from hrm_member_sessions). 12. Return the updated member summary
     *   (excluding password_hash).
   *
   * **Error Cases**:
   * - 401: Invalid current password
   * - 400: New password does not meet security requirements
   * - 400: New password is same as current password
   * - 404: Member not found
   * - 410: Member account is deleted (deleted_at is not null)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmMember.IPasswordUpdate,
  ): Promise<IHrmMember.ISummary> {
    try {
      return await putHrmMemberProfilePassword({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
