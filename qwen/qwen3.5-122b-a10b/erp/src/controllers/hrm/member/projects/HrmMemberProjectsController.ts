import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmProject } from "../../../../api/structures/IHrmProject";
import { IPageIHrmProject } from "../../../../api/structures/IPageIHrmProject";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { patchHrmMemberProjects } from "../../../../providers/patchHrmMemberProjects";

@Controller("/hrm/member/projects")
export class HrmMemberProjectsController {
  /**
   * Retrieve a paginated list of projects within the organization with optional filtering by status and name search.
   *
   * This endpoint supports browsing projects with flexible search criteria including status filtering (active, archived, completed), partial name matching, and date range filters. Results are paginated to support efficient navigation through large project collections.
   *
   * **Access Control**
   * Users with `project:view` permission can access this endpoint. The organization context is derived from the authenticated user's session.
   *
   * **Filtering Options**
   * - Status: Filter by project status (active, archived, completed)
   * - Name: Partial match search on project name using trigram indexing
   * - Date Range: Filter by start_date or end_date ranges
   * - Pagination: Page number and page size controls
   *
   * **Response Format**
   * Returns paginated project summaries optimized for list displays, including project id, name, status, color code, and timeline information.
   *
   * @param connection
   * @param body Search criteria for filtering projects including status, name pattern, date ranges, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implement PATCH /projects as a paginated project list endpoint with search capabilities.
   *
   * **Implementation Steps**
   * 1. Extract organization context from authenticated user session
   * 2. Validate user has `project:view` permission for the organization
   * 3. Build query on hrm_projects table with organization filter (hrm_organization_id)
   * 4. Apply search filters from request body:
   *    - status: exact match if provided (active/archived/completed)
   *    - name: trigram-based partial match using GIN index
   *    - start_date/end_date: range filters if provided
   * 5. Apply pagination: offset = (page - 1) * pageSize, limit = pageSize
   * 6. Join with hrm_organizations if organization details needed
   * 7. Return paginated response with IPageIHrmProject.ISummary type
   *
   * **Business Rules**
   * - All projects must belong to the user's current organization (multi-tenancy isolation)
   * - Status values must be one of: active, archived, completed
   * - Page number must be >= 1, pageSize must be between 1 and 100
   * - Soft-deleted projects (deleted_at IS NOT NULL) should be excluded from results
   *
   * **Error Handling**
   * - 403 Forbidden: User lacks project:view permission
   * - 400 Bad Request: Invalid status value, pagination parameters out of range
   * - 401 Unauthorized: Missing or invalid authentication token
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmProject.IRequest,
  ): Promise<IPageIHrmProject.ISummary> {
    try {
      return await patchHrmMemberProjects({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
