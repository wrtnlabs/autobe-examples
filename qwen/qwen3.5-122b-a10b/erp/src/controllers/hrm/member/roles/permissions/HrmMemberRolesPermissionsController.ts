import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmRole } from "../../../../../api/structures/IHrmRole";
import { IHrmRolePermission } from "../../../../../api/structures/IHrmRolePermission";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteHrmMemberRolesRoleIdPermissionsPermissionId } from "../../../../../providers/deleteHrmMemberRolesRoleIdPermissionsPermissionId";
import { patchHrmMemberRolesRoleIdPermissions } from "../../../../../providers/patchHrmMemberRolesRoleIdPermissions";
import { postHrmMemberRolesRoleIdPermissions } from "../../../../../providers/postHrmMemberRolesRoleIdPermissions";

@Controller("/hrm/member/roles/:roleId/permissions")
export class HrmMemberRolesPermissionsController {
  /**
   * Assign one or more permissions to an existing role within an organization.
   *
   * This operation adds the specified permissions to the role's permission set by creating entries in the role-permissions junction table (hrm_role_permissions). The role must exist and belong to the current organization context. Built-in roles (Owner, Manager, Employee) cannot have their permissions modified as they are system-defined and immutable per business rules.
   *
   * **Business Rules**
   * - Role must exist and be owned by the current organization
   * - Built-in roles (is_builtin = true) cannot have permissions modified
   * - Each permission must exist in the system permission catalog (hrm_permissions)
   * - Duplicate permission assignments are prevented by unique constraint on (hrm_role_id, hrm_permission_id)
   * - User must have org:manage permission to modify role permissions
   * - Custom roles must have at least one permission assigned (enforced at role creation, not during assignment)
   *
   * **Error Scenarios**
   * - Role not found: Returns 404 if roleId does not exist in the system
   * - Built-in role: Returns 403 if attempting to modify a built-in role's permissions
   * - Invalid permission: Returns 400 if any permission_id does not exist in hrm_permissions
   * - Insufficient permissions: Returns 403 if user lacks org:manage permission for the organization
   * - Organization mismatch: Returns 403 if role belongs to a different organization than the current context
   *
   * @param connection
   * @param roleId Unique identifier of the role to assign permissions to (scoped to organization). Must be a valid UUID.
   * @param body Array of permission IDs to assign to the role. Each permission must exist in the system permission catalog. The array must contain at least one valid permission ID.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Extract roleId from path parameter and
     *   validate UUID format 2. Verify user has org:manage permission for the
     *   current organization context (from session/organization context) 3.
     *   Query hrm_roles table by id to retrieve role record 4. Check if role
     *   exists; if not, return 404 Not Found 5. Check if role.is_builtin =
     *   true; if so, return 403 Forbidden (built-in roles cannot be modified
     *   per section 158) 6. Verify role.hrm_organization_id matches the current
     *   organization context 7. Extract permission_ids array from request body
     *   8. Validate permission_ids is not empty and contains valid UUIDs 9. For
     *   each permission_id in the array: - Query hrm_permissions table to
     *   verify permission exists - If any permission_id not found, return 400
     *   Bad Request with list of invalid permission IDs 10. Begin database
     *   transaction 11. Insert records into hrm_role_permissions table for each
     *   (hrm_role_id, hrm_permission_id) pair 12. Handle unique constraint
     *   violations gracefully (duplicate permissions are silently ignored due
     *   to @@unique constraint) 13. Commit transaction 14. Query hrm_roles with
     *   joined hrm_role_permissions and hrm_permissions to return complete role
     *   with all permissions 15. Return 200 OK with updated role object
     *   including permission array
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async assign(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmRolePermission.IAssign,
  ): Promise<IHrmRole> {
    try {
      return await postHrmMemberRolesRoleIdPermissions({
        member,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates the permissions assigned to a custom role within an organization.
   *
   * This operation replaces all existing permissions with the provided list. Built-in roles (Owner, Manager, Employee) cannot have their permissions modified as they are immutable system-defined roles.
   *
   * The request body must contain at least one valid permission ID. Each permission ID must reference an existing permission from the system permission set. Invalid or non-existent permission IDs will result in a validation error.
   *
   * Organization owners and users with appropriate role management permissions can perform this operation on custom roles. The updated permissions take effect immediately for all employees assigned to this role.
   *
   * @param connection
   * @param roleId Unique identifier of the role to update permissions for (UUID format)
   * @param body List of permission IDs to assign to the role. This replaces all existing permissions with the provided list. Must contain at least one valid permission ID.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate roleId parameter is valid UUID
     *   format. 2. Query hrm_roles table to verify role exists and is not a
     *   built-in role (is_builtin = false). 3. Load hrm_permissions table to
     *   validate all permission IDs in request body exist. 4. Begin database
     *   transaction. 5. Delete all existing hrm_role_permissions records for
     *   this role. 6. Insert new hrm_role_permissions records for each
     *   permission ID in the request. 7. Verify at least one permission was
     *   assigned (enforce minimum one permission constraint). 8. Commit
     *   transaction. 9. Query updated role with joined hrm_role_permissions and
     *   hrm_permissions tables. 10. Return updated role with permissions array.
   *
   * Error cases:
   * - 404: Role not found
   * - 403: Role is built-in (is_builtin = true)
   * - 400: Invalid permission ID in request body
   * - 400: No permissions provided (empty array)
   * - 400: Permission ID does not exist in hrm_permissions table
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmRole.IUpdatePermission,
  ): Promise<IHrmRole> {
    try {
      return await patchHrmMemberRolesRoleIdPermissions({
        member,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a permission assignment from a role within an organization.
   *
   * This operation deletes a specific role-permission relationship from the junction table, effectively revoking that permission from the role. The role must be a custom role (not a built-in role like Owner, Manager, or Employee), and must retain at least one permission after the deletion.
   *
   * Built-in roles cannot have their permissions modified. Custom roles can only be modified by organization owners or users with appropriate permissions. If the role would be left with zero permissions after this deletion, the operation will fail with a validation error.
   *
   * This operation does not affect employees currently assigned to the role; they will immediately lose this permission upon successful deletion.
   *
   * @param connection
   * @param roleId Unique identifier of the role from which to remove the permission (scoped to organization).
   * @param permissionId Unique identifier of the permission to remove from the role.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate the authenticated user has permission
     *   to modify roles in the organization (org:manage or role management
     *   permission). 2. Retrieve the role by roleId from hrm_roles table. 3.
     *   Verify the role is not a built-in role (is_builtin = false). Return 403
     *   if built-in. 4. Verify the role belongs to the current organization
     *   context. 5. Retrieve the permission by permissionId from
     *   hrm_permissions table. 6. Verify the role-permission assignment exists
     *   in hrm_role_permissions table. 7. Count remaining permissions for this
     *   role after deletion (excluding the one being deleted). 8. If remaining
     *   permission count would be 0, return 400 error: 'Role must have at least
     *   one permission'. 9. Delete the role-permission record from
     *   hrm_role_permissions table. 10. Log the permission removal in
     *   hrm_activity_logs table. 11. Return 204 No Content on success.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":permissionId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedParam("permissionId")
    permissionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmMemberRolesRoleIdPermissionsPermissionId({
        member,
        roleId,
        permissionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
