import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmEmployeeInvitation } from "../../../../api/structures/IHrmEmployeeInvitation";
import { IPageIHrmEmployeeInvitation } from "../../../../api/structures/IPageIHrmEmployeeInvitation";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmMemberInvitationsInvitationId } from "../../../../providers/getHrmMemberInvitationsInvitationId";
import { patchHrmMemberInvitations } from "../../../../providers/patchHrmMemberInvitations";
import { patchHrmMemberInvitationsInvitationIdAccept } from "../../../../providers/patchHrmMemberInvitationsInvitationIdAccept";
import { postHrmMemberInvitations } from "../../../../providers/postHrmMemberInvitations";

@Controller("/hrm/member/invitations")
export class HrmMemberInvitationsController {
  /**
   * Create a new employee invitation to join an organization.
   *
   * This operation sends an email invitation to a user, allowing them to join the organization as an employee. If the invited email already has a user account, that user is immediately added to the organization as an employee. If no account exists, a pending invitation is created that can be accepted when the user signs up with the invited email address.
   *
   * **Business Rules**
   *
   * - Only users with `employee:manage` permission can create invitations
   * - The invited role must exist within the target organization
   * - Built-in roles (Owner, Manager, Employee) and custom roles are both supported
   * - Only one pending invitation per email per organization is allowed
   * - Invitations expire based on the configured expiration date
   * - The invitation token is sent to the invited email address for secure acceptance
   *
   * **Response**
   *
   * Returns the created invitation record including the unique token, expiration date, and status. The token must be provided when accepting the invitation.
   *
   * @param connection
   * @param body Invitation creation request including the target email address and role to assign upon acceptance.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate the authenticated user has
     *   `employee:manage` permission in the organization context 2. Verify the
     *   role_id exists within the organization 3. Check for existing pending
     *   invitations with the same email and organization_id 4. Generate a
     *   unique token for invitation acceptance 5. Calculate expiration date
     *   (typically 7-30 days from creation based on organization settings) 6.
     *   Insert new hrm_employee_invitations record with status='pending' 7.
     *   Return the created invitation record with token and expiration
     *   information 8. Trigger email delivery with invitation link containing
     *   the token
   *
   * **Validation Rules**
   *
   * - email: valid email format, required
   * - role_id: must reference existing role in organization, required
   * - organization_id: derived from authenticated user's organization context
   *
   * **Error Cases**
   *
   * - 403: User lacks employee:manage permission
   * - 404: Role not found in organization
   * - 409: Pending invitation already exists for this email in organization
   * - 400: Invalid email format or missing required fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmEmployeeInvitation.ICreate,
  ): Promise<IHrmEmployeeInvitation> {
    try {
      return await postHrmMemberInvitations({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve employee invitations with filtering and pagination.
   *
   * This endpoint allows administrators to search through pending, accepted, expired, and cancelled invitations within their organization. Search criteria include email address, invitation status, date ranges, and pagination parameters. The results return invitation summaries optimized for list displays.
   *
   * **Filtering Capabilities**
   * - Filter by invitation status (pending, accepted, expired, cancelled)
   * - Search by email address (partial match)
   * - Filter by date ranges (created_at, expires_at)
   * - Sort by various fields (created_at, expires_at, email)
   * - Pagination with cursor or offset-based navigation
   *
   * **Authorization**
   * - Requires employee:manage permission to view invitations
   * - Results are scoped to the authenticated user's organization
   * - Only invitations within the organization context are returned
   *
   * **Related Operations**
   * - POST /invitations - Create a new invitation
   * - GET /invitations/{id} - Retrieve a specific invitation detail
   * - DELETE /invitations/{id} - Cancel an invitation
   *
   * @param connection
   * @param body Search criteria for filtering invitations including status, email, date ranges, sorting preferences, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_employee_invitations table with
     *   organization scoping from authentication context. Apply search filters
     *   from request body: status filter (enum validation), email partial match
     *   (ILIKE), date range filters (created_at, expires_at). Join with
     *   hrm_roles to include role name in summary. Join with hrm_members to
     *   include inviter display name. Implement pagination with cursor-based or
     *   offset-based navigation. Return IHrmEmployeeInvitation.ISummary array
     *   wrapped in IPageIHrmEmployeeInvitation. Validate user has
     *   employee:manage permission before executing query. Handle soft-deleted
     *   invitations by filtering where deleted_at IS NULL.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmEmployeeInvitation.IRequest,
  ): Promise<IPageIHrmEmployeeInvitation.ISummary> {
    try {
      return await patchHrmMemberInvitations({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single employee invitation by its unique identifier.
   *
   * This operation fetches the complete details of an employee invitation record, including the target organization, assigned role, invited email address, current status, and expiration information. The invitation must belong to the user's current organization context.
   *
   * The response includes all invitation fields such as the inviter information, acceptance status, and timestamps for audit purposes. Users can only view invitations they have created or invitations within their organization where they have appropriate read permissions.
   *
   * **Authorization**: Requires `employee:manage` permission or organization owner role to view invitation details.
   *
   * **Error Handling**: Returns 404 if invitation does not exist, 403 if user lacks permission, and 400 if invitation belongs to a different organization.
   *
   * @param connection
   * @param invitationId Unique identifier of the invitation to retrieve (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate invitationId is a valid UUID format.
     *   2. Verify the invitation exists in hrm_employee_invitations table. 3.
     *   Check that invitation.organization_id matches the user's current
     *   organization context. 4. Verify user has `employee:manage` permission
     *   or is organization owner. 5. Query hrm_employee_invitations with
     *   invitationId, joining hrm_organizations, hrm_roles, and hrm_members
     *   tables for related data. 6. Apply soft delete filter (deleted_at IS
     *   NULL). 7. Return full invitation entity with embedded role,
     *   organization, and inviter information. 8. If invitation not found or
     *   organization mismatch, return appropriate error (404 or 403).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":invitationId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("invitationId")
    invitationId: string & tags.Format<"uuid">,
  ): Promise<IHrmEmployeeInvitation> {
    try {
      return await getHrmMemberInvitationsInvitationId({
        member,
        invitationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Accepts a pending employee invitation and creates the employee record in the target organization.
   *
   * This operation allows users to accept invitations sent to their email address, joining the inviting organization as an employee with the specified role. When accepted, the invitation status changes to 'accepted' and the member_id is populated to link the invitation to the user's account.
   *
   * The system validates the invitation token for security, ensures the invitation is still pending and not expired, and verifies the invited email matches the authenticated user. Upon successful acceptance, an employee record is created linking the user to the organization with the assigned role.
   *
   * If the invitation has already been accepted, expired, or cancelled, the operation is rejected. The invitation is consumed upon acceptance and cannot be reused.
   *
   * @param connection
   * @param invitationId UUID identifier of the invitation to accept (global scope).
   * @param body Invitation acceptance request containing the verification token sent to the invited email address.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Extract invitationId from path parameter and
     *   validate UUID format. 2. Fetch invitation from hrm_employee_invitations
     *   table where id = invitationId AND deleted_at IS NULL. 3. Validate
     *   invitation exists; return 404 if not found. 4. Check invitation.status
     *   equals 'pending'; return 400 if status is 'accepted', 'expired', or
     *   'cancelled'. 5. Validate invitation.expires_at is not in the past;
     *   return 400 if expired. 6. Verify request body token matches
     *   invitation.token; return 401 if mismatch. 7. Get current authenticated
     *   member from session/JWT. 8. Verify member.email matches
     *   invitation.email; return 403 if mismatch. 9. Begin database
     *   transaction. 10. Update invitation: SET status = 'accepted', member_id
     *   = member.id, updated_at = NOW() WHERE id = invitationId. 11. Check if
     *   employee record already exists for this organization_id and user_id; if
     *   not, create employee record with role_id, department_id (null),
     *   position (null), employment_type (from role or default), status =
     *   'active'. 12. Commit transaction. 13. Return 200 with updated
     *   invitation object including populated member_id. 14. Handle unique
     *   constraint violations on [organization_id, email, status] with 409
     *   Conflict. 15. Log activity for invitation acceptance.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":invitationId/accept")
  public async accept(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("invitationId")
    invitationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmEmployeeInvitation.IAccept,
  ): Promise<IHrmEmployeeInvitation> {
    try {
      return await patchHrmMemberInvitationsInvitationIdAccept({
        member,
        invitationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
