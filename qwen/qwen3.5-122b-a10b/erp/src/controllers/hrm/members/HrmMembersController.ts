import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmMember } from "../../../api/structures/IHrmMember";
import { IPageIHrmMember } from "../../../api/structures/IPageIHrmMember";
import { getHrmMembersMemberId } from "../../../providers/getHrmMembersMemberId";
import { patchHrmMembers } from "../../../providers/patchHrmMembers";

@Controller("/hrm/members")
export class HrmMembersController {
  /**
   * Search and retrieve a paginated list of member accounts within the organization context.
   *
   * This endpoint provides administrative access to browse member user accounts with flexible filtering options including email search, creation date ranges, and account status. Results are returned with cursor-based pagination for efficient navigation through large result sets.
   *
   * **Access Control**: Requires authenticated member with appropriate permissions to view user data.
   *
   * **Filtering**: Supports partial email matching, date range filtering on account creation, and soft-deleted account visibility.
   *
   * **Pagination**: Returns paginated results with cursor-based navigation tokens for seamless browsing.
   *
   * @param connection
   * @param body Search criteria including email partial match, account creation date range, soft-deleted account visibility flag, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query hrm_members table with organization-scoped filtering and pagination.
   *
   * Implementation steps:
   * 1. Validate authenticated user has permission to view member data (employee:view or higher)
   * 2. Build query with optional filters:
   *    - email: partial match search (ILIKE with wildcards)
   *    - created_at_from, created_at_to: date range filtering
   *    - include_deleted: boolean to include soft-deleted accounts (default false)
   * 3. Apply cursor-based pagination using created_at and id as composite cursor
   * 4. Return paginated summary with next/previous cursor tokens
   * 5. Exclude password_hash from all responses
   * 6. Handle soft-deleted accounts based on include_deleted flag
   *
   * Edge cases:
   * - Empty result set: return pagination metadata with empty data array
   * - Invalid cursor: return 400 Bad Request with error message
   * - Permission denied: return 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IHrmMember.IRequest,
  ): Promise<IPageIHrmMember.ISummary> {
    try {
      return await patchHrmMembers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a member account's details by their unique identifier.
   *
   * This operation returns comprehensive information about a member account, including their authentication email, account timestamps, and soft delete status. The response excludes sensitive fields such as password hashes for security purposes.
   *
   * **Access Control**: This endpoint requires administrative privileges. Regular members cannot retrieve other members' account details. Only users with organization-level administrative permissions can access this endpoint.
   *
   * **Organization Context**: While member accounts are global and shared across organizations, this endpoint operates within the context of the authenticated user's selected organization. The organization context is validated but does not filter the member data since members are global entities.
   *
   * **Soft Delete Handling**: If the member account has been soft-deleted (deleted_at is not null), the response will still include the account information. The caller is responsible for handling soft-deleted accounts according to business requirements.
   *
   * @param connection
   * @param memberId Unique identifier of the member account (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the hrm_members table by primary key (id) using the memberId path parameter. Validate that the member exists and return the full member record excluding the password_hash field.
   *
   * **Implementation Steps**:
   * 1. Extract memberId from path parameters (UUID format)
   * 2. Validate memberId format against UUID pattern
   * 3. Query hrm_members table WHERE id = memberId
   * 4. If no record found, return 404 Not Found
   * 5. If member exists, construct response excluding password_hash field
   * 6. Apply organization context validation for authorization
   * 7. Return member details with id, email, created_at, updated_at, and deleted_at fields
   *
   * **Authorization**:
   * - Require valid JWT authentication token
   * - Verify caller has administrative permissions at organization level
   * - Reject with 403 Forbidden if unauthorized
   *
   * **Error Handling**:
   * - 404: Member not found (invalid memberId or deleted account)
   * - 403: Insufficient permissions (non-administrator caller)
   * - 400: Invalid UUID format in memberId parameter
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":memberId")
  public async at(
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<IHrmMember> {
    try {
      return await getHrmMembersMemberId({
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
