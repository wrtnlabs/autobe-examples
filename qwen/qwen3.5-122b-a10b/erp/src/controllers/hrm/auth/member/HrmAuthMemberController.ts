import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IHrmMember } from "../../../../api/structures/IHrmMember";
import { postHrmAuthMemberJoin } from "../../../../providers/postHrmAuthMemberJoin";
import { postHrmAuthMemberLogin } from "../../../../providers/postHrmAuthMemberLogin";
import { postHrmAuthMemberRefresh } from "../../../../providers/postHrmAuthMemberRefresh";

@Controller("/hrm/auth/member")
export class HrmAuthMemberController {
  /**
   * Register a new member account with email and password credentials.
   *
   * This operation creates a new member user account in the system. The member will need to verify their email address before accessing organization-scoped features. Upon successful registration, JWT access and refresh tokens are issued, though full organization access requires email verification completion.
   *
   * The operation performs the following steps:
   * - Validates email format and password strength requirements
   * - Checks for email uniqueness across all member accounts
   * - Creates a new hrm_members record with hashed password
   * - Generates an email verification token stored in hrm_member_email_verifications
   * - Returns authentication tokens with verification status
   *
   * Email verification is required before the member can select an organization and access scoped features. The verification token expires after 24 hours and supports single-use validation through the email verification endpoint.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials for new member account creation.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate request body: email format, password strength (min 8 chars, alphanumeric). 2. Check email uniqueness in hrm_members table. 3. Create member record with hashed password (bcrypt). 4. Generate email verification token, store in hrm_member_email_verifications with expiration. 5. Return IAuthorized with tokens and verification required flag. 6. If email already exists, return 409 conflict. 7. Log activity in hrm_activity_logs.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmMember.IJoin,
  ): Promise<IHrmMember.IAuthorized> {
    try {
      return await postHrmAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate member with email and password credentials.
   *
   * This operation validates member credentials and establishes an authenticated session. Upon successful authentication, the member receives JWT access and refresh tokens along with their profile information and list of organizations they belong to.
   *
   * The operation performs the following steps:
   * - Validates email format and password presence
   * - Retrieves member record from hrm_members by email
   * - Verifies password hash using bcrypt comparison
   * - Checks account is active and not suspended
   * - Generates JWT access token (short-lived, 15 minutes) and refresh token (long-lived, 7 days)
   * - Creates session record in hrm_member_sessions with token metadata
   * - Returns member profile, available organizations, and authentication tokens
   *
   * The member must select an organization context from the returned list before accessing organization-scoped endpoints. Organization context is provided via request header in subsequent API calls. Refresh tokens can be used to obtain new access tokens without re-authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials for member authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate request body: email format, password present. 2. Find member in hrm_members by email. 3. Verify password hash matches using bcrypt. 4. Check account status (not suspended/deleted). 5. Generate JWT access token (15 min expiry) and refresh token (7 day expiry). 6. Store session in hrm_member_sessions with token hashes. 7. Return IAuthorized with tokens, member profile, and available organizations. 8. Log successful login in hrm_activity_logs. 9. On failure (invalid credentials), return 401 with appropriate error code.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmMember.ILogin,
  ): Promise<IHrmMember.IAuthorized> {
    try {
      return await postHrmAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew authentication tokens using a valid refresh token.
   *
   * This operation extends the member's authenticated session by issuing new access and refresh tokens. The refresh token must be valid, unexpired, and associated with an active session in hrm_member_sessions.
   *
   * The operation performs the following steps:
   * - Validates refresh token format and presence
   * - Looks up session record in hrm_member_sessions using token hash
   * - Verifies session is active and refresh token not expired
   * - Confirms member account still exists and is active
   * - Implements token rotation: invalidates old refresh token, generates new pair
   * - Creates new JWT access token with standard expiry
   * - Updates session record with new token metadata
   * - Returns new access and refresh tokens in IAuthorized response
   *
   * Token rotation enhances security by limiting refresh token reuse. If a refresh token is compromised, the rotation mechanism limits the attack window. Members should store both tokens securely and use the access token for API requests, refreshing before expiration.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for session renewal and new token issuance.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate request body: refresh token present and valid format. 2. Lookup session in hrm_member_sessions by refresh token hash. 3. Verify token not expired and session active. 4. Verify member still exists and account active. 5. Rotate refresh token (invalidate old, generate new). 6. Generate new JWT access token. 7. Update hrm_member_sessions with new token hashes. 8. Return new IAuthorized with refreshed tokens. 9. On invalid/expired token, return 401 requiring re-login.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IHrmMember.IRefresh,
  ): Promise<IHrmMember.IAuthorized> {
    try {
      return await postHrmAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
