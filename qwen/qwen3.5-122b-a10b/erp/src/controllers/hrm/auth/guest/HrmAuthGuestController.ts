import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IHrmGuest } from "../../../../api/structures/IHrmGuest";
import { postHrmAuthGuestJoin } from "../../../../providers/postHrmAuthGuestJoin";
import { postHrmAuthGuestRefresh } from "../../../../providers/postHrmAuthGuestRefresh";

@Controller("/hrm/auth/guest")
export class HrmAuthGuestController {
  /**
   * Create a new guest account and session using device fingerprint identification.
   *
   * This operation registers an unauthenticated user as a guest by creating a temporary account identified by their device fingerprint. The guest receives JWT access and refresh tokens for authenticated API access within session limits.
   *
   * **Business Logic**
   *
   * The service accepts a device fingerprint string and generates a unique guest identifier. A new record is created in the hrm_guests table linking the fingerprint to the guest account. Simultaneously, a session record is created in hrm_guest_sessions containing the access token, refresh token, and expiration timestamps. The access token is short-lived (typically 15-30 minutes) while the refresh token allows token renewal without re-registration.
   *
   * **Schema Fields**
   *
   * - hrm_guests: guestId (primary key), deviceFingerprint (unique identifier), createdAt, expiresAt
   * - hrm_guest_sessions: sessionId, guestId (foreign key), accessToken, refreshToken, expiresAt
   *
   * **Security Considerations**
   *
   * Device fingerprints should be generated client-side using browser/device characteristics. The server validates fingerprint format but does not verify authenticity - this is a temporary access mechanism. Sessions have strict expiration times and single-use refresh tokens to limit unauthorized access window.
   *
   * **Related Operations**
   *
   * - IHrmGuest.IRefresh: Renew expired access tokens using valid refresh token
   * - No login operation exists for guests (they authenticate via join only)
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest registration request containing device fingerprint for identification
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Create a new guest account using device fingerprint identification. The service must: 1) Accept deviceFingerprint from request body, 2) Generate a unique guestId, 3) Create a hrm_guests record with the fingerprint, 4) Create a hrm_guest_sessions record with access and refresh tokens, 5) Return the IAuthorized response with tokens and guest information. Edge cases: duplicate fingerprint handling (return existing guest or reject based on policy), token generation failures. Error handling: 400 for invalid fingerprint format, 500 for token generation failures.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmGuest.IJoin,
  ): Promise<IHrmGuest.IAuthorized> {
    try {
      return await postHrmAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew guest session tokens using a valid refresh token.
   *
   * This operation extends the guest session by issuing new access and refresh tokens when the current access token expires. The refresh token is single-use and becomes invalid after successful renewal to prevent token replay attacks.
   *
   * **Business Logic**
   *
   * The service validates the provided refresh token against the hrm_guest_sessions table. If valid and unused, it generates new access and refresh tokens, marks the old refresh token as consumed, and updates the session record. The guest continues their session without re-registration. If the guest account itself has expired (hrm_guests.expiresAt), the refresh is rejected even with a valid token.
   *
   * **Schema Fields**
   *
   * - hrm_guest_sessions: sessionId, guestId, accessToken, refreshToken, expiresAt, isConsumed
   * - hrm_guests: guestId, expiresAt (account-level expiration)
   *
   * **Security Considerations**
   *
   * Refresh tokens are single-use to prevent replay attacks. Each successful refresh invalidates the previous refresh token. Access tokens have short expiration (15-30 minutes) while refresh tokens last longer (typically 7-30 days) but are still subject to guest account expiration. Client must handle 401 responses by re-registering via join if refresh fails.
   *
   * **Related Operations**
   *
   * - IHrmGuest.IJoin: Initial guest registration when session is lost or expired
   * - No logout operation (JWT is stateless, client discards tokens)
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest token refresh request containing valid refresh token
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Renew guest session tokens using a valid refresh token. The service must: 1) Accept refreshToken from request body, 2) Validate the token exists in hrm_guest_sessions and is not expired, 3) Verify the token has not been used before (single-use refresh), 4) Invalidate the old refresh token, 5) Generate new access and refresh tokens, 6) Update hrm_guest_sessions with new tokens, 7) Return the IAuthorized response. Edge cases: expired token (401), already-used token (401), invalid format (400), guest account expired (401). Error handling: 401 for invalid/expired tokens, 400 for malformed requests, 500 for token generation failures.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IHrmGuest.IRefresh,
  ): Promise<IHrmGuest.IAuthorized> {
    try {
      return await postHrmAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
