import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { ITodoAppMember } from "../../../../../structures/ITodoAppMember";

/**
 * Authenticate a registered member using email and password credentials. This endpoint validates the provided credentials against the todo_app_members table and establishes a new authenticated session.
 *
 * The login process begins with credential validation: email format verification and password non-empty check. The system queries the todo_app_members table using the provided email address with case-insensitive matching. If no matching record exists, or if the account has been soft-deleted (deleted_at is set), the request is rejected with a 401 unauthorized response.
 *
 * For valid accounts, the system performs password verification using bcrypt.compare() against the stored password_hash. This cryptographic comparison ensures secure credential validation without exposing the actual password. Failed password matching results in a 401 unauthorized response.
 *
 * Upon successful authentication, a new session record is created in the todo_app_member_sessions table. This session tracks the login event with metadata including the client IP address, login page URL (href), and referrer header. The session is assigned a 30-day expiration period (expired_at) and is linked to the authenticated member via foreign key.
 *
 * The response includes an IAuthorized object containing JWT access and refresh tokens. The access token is used for authenticating subsequent API requests, while the refresh token enables token renewal without requiring re-authentication. The response also includes the member's profile information (id, email, displayName) for immediate client-side use.
 *
 * Related operations: After login, users can access protected resources using the access token. The refresh operation (/auth/member/refresh) renews expired access tokens. Password change (/auth/member/password/change) and account deletion (/auth/member/account/erase) are available for authenticated members.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Login credentials including email and password for authentication.
 * @x-autobe-authorization-type login
 * @x-autobe-authorization-actor member
 * @x-autobe-specification 1. Validate request body: email format, password non-empty. 2. Query todo_app_members by email (case-insensitive). 3. If no record or deleted_at is set, return 401 unauthorized. 4. Verify password using bcrypt.compare() against stored password_hash. 5. If password mismatch, return 401 unauthorized. 6. Create new session record in todo_app_member_sessions with ip, href, referrer from request context, created_at=now, expired_at=now+30days. 7. Generate JWT access token and refresh token. 8. Return IAuthorized response with tokens and member profile.
 * @path /todoApp/auth/member/login
 * @accessor api.functional.todoApp.auth.member.login.signIn
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function signIn(
  connection: IConnection,
  props: signIn.Props,
): Promise<signIn.Response> {
  const output: signIn.Response =
    true === connection.simulate
      ? signIn.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...signIn.METADATA,
            path: signIn.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace signIn {
  export type Props = {
    /**
     * Login credentials including email and password for authentication.
     */
    body: ITodoAppMember.ILogin;
  };
  export type Body = ITodoAppMember.ILogin;
  export type Response = ITodoAppMember.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/auth/member/login",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/auth/member/login";
  export const random = (): ITodoAppMember.IAuthorized =>
    typia.random<ITodoAppMember.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: signIn.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: signIn.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
