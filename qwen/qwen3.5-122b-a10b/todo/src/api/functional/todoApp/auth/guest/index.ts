/**
 * Register a new guest user account identified by device fingerprint for anonymous access to the todo application.
 *
 * This endpoint creates a temporary guest account that allows unauthenticated users to access the system without email/password registration. The guest is uniquely identified by their device fingerprint, which serves as the primary identifier for session persistence and data ownership.
 *
 * The operation validates that the device fingerprint is unique - if a guest with the same fingerprint already exists, a 409 Conflict error is returned. This prevents duplicate guest accounts from the same device.
 *
 * Upon successful registration, the system creates both a guest account record and an initial session record. The session tracks connection metadata including IP address, current URL, and referrer for security auditing purposes. JWT tokens are generated and returned for subsequent authenticated requests.
 *
 * Guest accounts support soft deletion via the deleted_at timestamp, allowing for account cleanup while maintaining audit trails. The session records are append-only and expire based on the expired_at timestamp for security.
 *
 * Related operations include refresh (POST /auth/guest/refresh) for renewing expired tokens. No login operation exists for guests as they authenticate via device fingerprint through the join flow.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest registration information containing device fingerprint for unique identification
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Create new guest account with device fingerprint. 1) Validate device_fingerprint is provided and not empty. 2) Check if device_fingerprint already exists (return 409 Conflict if exists). 3) Create todo_app_guests record with device_fingerprint, set created_at and updated_at to current timestamp, deleted_at to null. 4) Create initial todo_app_guest_sessions record with the guest id, client IP from request, href and referrer from request headers. 5) Generate JWT access token and refresh token with guest actor claims. 6) Return authorized response with tokens and guest id.
 * @path /todoApp/auth/guest/join
 * @accessor api.functional.todoApp.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
