/**
 * Register a new member account with email and password credentials.
 *
 * This endpoint creates a new authenticated user account in the system. Upon successful registration, the member account is created with the provided email and password, and an email verification token is generated for account validation.
 *
 * **Registration Process**
 *
 * The service validates the email format and checks for uniqueness in the todo_app_members table. If the email is available, the password is securely hashed and the member record is created. An email verification token is generated in the todo_app_member_email_verifications table to validate ownership of the email address.
 *
 * **Schema Fields Used**
 *
 * - email: Unique identifier for authentication (todo_app_members.email)
 * - password: Securely stored as password_hash (todo_app_members.password_hash)
 * - display_name: Optional public name (todo_app_members.display_name, defaults to email prefix)
 *
 * **Error Handling**
 *
 * Returns 409 Conflict if the email is already registered, 400 Bad Request for invalid email format or weak password, and 500 Internal Server Error for database failures.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration credentials for new member account creation
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Register a new member account with email and password. The service must: 1) Validate email format and uniqueness against todo_app_members table, 2) Hash the password using bcrypt or Argon2, 3) Create a new member record with email, password_hash, and display_name (default to email prefix if not provided), 4) Create an email verification token in todo_app_member_email_verifications table, 5) Return 409 Conflict if email already exists, 400 Bad Request for validation failures. The email verification token should be returned in the response or sent via email separately.
 * @path /todoApp/auth/member/join
 * @accessor api.functional.todoApp.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
