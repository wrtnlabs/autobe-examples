/**
 * Retrieve a specific edit history entry for a todo item.
 *
 * This operation returns the complete details of a single history entry that was created when a todo was edited. Each history entry captures the state of the todo at the time of an edit, including the timestamp and the values of fields that were modified (title, description, start date, due date, and completion status).
 *
 * **Ownership Verification**
 *
 * Before returning the history entry, the system must verify:
 * 1. The history entry exists and belongs to the specified todo
 * 2. The todo is owned by the authenticated member
 * 3. The member has permission to view the history (only the todo owner can access history)
 *
 * If any ownership verification fails, the system returns a 404 Not Found error to prevent information leakage about the existence of todos or history entries owned by other members.
 *
 * **History Entry Details**
 *
 * The response includes the exact field values that were recorded at the time of the edit. Fields that were not changed in that particular edit will be null. The entry includes:
 * - Timestamp when the edit occurred (created_at)
 * - Title value at the time of edit (if title was changed)
 * - Description value at the time of edit (if description was changed)
 * - Start date value at the time of edit (if start date was changed)
 * - Due date value at the time of edit (if due date was changed)
 * - Completion status at the time of edit (if completion status was changed)
 *
 * **Related Operations**
 *
 * To view all history entries for a todo in chronological order, use `GET /todoApp/todos/{todoId}/histories` which returns a paginated list sorted from most recent to oldest. This operation is for retrieving a single specific history entry when the history ID is already known.
 *
 * **Soft Deletion Consideration**
 *
 * History entries are soft-deleted when the parent todo is soft-deleted (moved to trash). The history entry remains accessible through this endpoint even when the todo is in the trash, as long as the todo has not been permanently deleted. When a todo is permanently deleted from the trash, all associated history entries are permanently deleted as well and cannot be retrieved.
 *
 * @param props.connection
 * @param props.todoId The UUID of the parent todo that owns this history entry (global scope)
 * @param props.historyId The UUID of the specific history entry to retrieve (global scope)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification 1. Extract todoId and historyId from path parameters (both UUID format)
 * 2. Validate UUID format for both parameters
 * 3. Query todo_app_todo_histories table for the history entry with matching id
 * 4. Verify the history entry exists and its todo_app_todos_id matches the provided todoId
 * 5. If history not found or todoId mismatch, return 404 Not Found
 * 6. Join with todo_app_todos table to verify ownership
 * 7. Verify todo_app_todos.todo_app_member_id matches the authenticated member's ID
 * 8. If ownership verification fails, return 404 Not Found (do not reveal existence)
 * 9. Check if the history entry is soft-deleted (deleted_at is not null)
 * 10. If soft-deleted, return 404 Not Found
 * 11. Query the history entry with all field values (title, description, start_date, due_date, completed, created_at, updated_at)
 * 12. Return the complete history entry as ITodoAppTodoHistory response
 * 13. Ensure transaction isolation - read the current committed state
 * 14. Log access for audit trail if required by observability policies
 * @path /todoApp/member/todoApp/todos/:todoId/histories/:historyId
 * @accessor api.functional.todoApp.member.todoApp.todos.histories.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * The UUID of the parent todo that owns this history entry (global scope)
     */
    todoId: string & tags.Format<"uuid">;

    /**
     * The UUID of the specific history entry to retrieve (global scope)
     */
    historyId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppTodoHistory;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/member/todoApp/todos/:todoId/histories/:historyId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/member/todoApp/todos/${encodeURIComponent(props.todoId ?? "null")}/histories/${encodeURIComponent(props.historyId ?? "null")}`;
  export const random = (): ITodoAppTodoHistory =>
    typia.random<ITodoAppTodoHistory>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
      assert.param("historyId")(() => typia.assert(props.historyId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
