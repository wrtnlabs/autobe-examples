import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { ITodoAppTodo } from "../../../../../structures/ITodoAppTodo";

/**
 * Toggle the completion status of a todo task between complete and incomplete.
 *
 * This operation changes the completion status of an existing todo task. Users can mark tasks as complete when finished, or mark them as incomplete if they need to continue working on them. The completion status is a simple toggle between two states.
 *
 * **Access Control**
 *
 * Only the owner of the todo can toggle its completion status. The authenticated member must match the todo's owner. Deleted todos (in trash) cannot be toggled.
 *
 * **Edit History**
 *
 * Each toggle operation creates a snapshot record in the edit history, allowing users to view when the completion status was changed.
 *
 * @param props.connection
 * @param props.todoId Unique identifier of the todo task to toggle completion status (UUID format).
 * @param props.body Toggle request containing the target completion status value.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification 1. Validate authenticated member owns the todo by
 *   checking todo_app_member_id matches current user. 2. Verify todo exists and
 *   is not permanently deleted (deleted_at IS NULL). 3. Update is_completed
 *   field to the target value from request body. 4. Update updated_at timestamp
 *   to current time. 5. Create corresponding snapshot record in
 *   todo_app_snapshots table for edit history. 6. Return the updated todo
 *   entity.
 *
 * Error cases:
 * - 404 if todo not found or belongs to different user
 * - 400 if target status is not valid boolean
 * @path /todoApp/member/todos/:todoId/complete
 * @accessor api.functional.todoApp.member.todos.complete.toggle
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function toggle(
  connection: IConnection,
  props: toggle.Props,
): Promise<toggle.Response> {
  return true === connection.simulate
    ? toggle.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...toggle.METADATA,
          path: toggle.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace toggle {
  export type Props = {
    /**
     * Unique identifier of the todo task to toggle completion status (UUID format).
     */
    todoId: string & tags.Format<"uuid">;

    /**
     * Toggle request containing the target completion status value.
     */
    body: ITodoAppTodo.IToggle;
  };
  export type Body = ITodoAppTodo.IToggle;
  export type Response = ITodoAppTodo;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/member/todos/:todoId/complete",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todoApp/member/todos/${encodeURIComponent(props.todoId ?? "null")}/complete`;
  export const random = (): ITodoAppTodo => typia.random<ITodoAppTodo>();
  export const simulate = (
    connection: IConnection,
    props: toggle.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: toggle.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
