import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";

/**
 * Permanently delete a todo and all its associated edit history entries from the database.
 *
 * This operation performs irreversible hard deletion of a todo item, completely removing the record from the todo_app_todos table along with all its associated todo_app_todo_histories entries. Unlike soft deletion which sets the deleted_at timestamp to mark records as deleted while retaining them in the database, this operation physically removes all data, making recovery impossible.
 *
 * The endpoint is designed for use when removing todos from the trash view or when cascading deletion during account deletion. Before permanent deletion can occur, the todo must first be soft deleted (deleted_at timestamp set) and exist in the trash. The operation verifies the todo is in trash state before proceeding with permanent removal.
 *
 * **Security and Privacy**:
 *
 * Only the todo owner can permanently delete their todo. The system verifies that the authenticated member ID matches the todo_app_member_id foreign key before proceeding. This enforces data isolation and prevents cross-user access violations.
 *
 * **Cascade Deletion**:
 *
 * All associated edit history entries in todo_app_todo_histories are deleted within the same transaction to prevent orphaned records. This cascade deletion is atomic - either all history entries and the todo are removed, or none are.
 *
 * **Related Operations**:
 *
 * - `DELETE /todoApp/member/todos/{todoId}` - Soft delete (sets deleted_at, moves to trash)
 * - `PATCH /todoApp/member/todos/{todoId}/restore` - Restore from trash (clears deleted_at)
 * - `PATCH /todoApp/member/todos` - List todos with deleted_at filter for trash view
 * - `GET /todoApp/member/todos/{todoId}/history` - View edit history before permanent deletion
 *
 * @param props.connection
 * @param props.todoId Target todo's unique identifier (UUID scope)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification 1. Authenticate user and extract member ID from session token.
 * 2. Query todo_app_todos WHERE id = {todoId} AND todo_app_member_id = {authenticatedMemberId}.
 * 3. If todo not found or belongs to different user, return 404 Not Found.
 * 4. If todo.deleted_at is not null (already in trash), proceed with permanent deletion.
 * 5. Begin database transaction.
 * 6. Delete all todo_app_todo_histories WHERE todo_app_todos_id = {todoId}.
 * 7. Delete todo_app_todos WHERE id = {todoId}.
 * 8. Commit transaction atomically.
 * 9. Return 200 OK with deleted todo summary.
 *
 * Edge cases:
 * - Todo not found: 404
 * - Todo belongs to different user: 404 (privacy boundary)
 * - Database constraint violation: 500 with error details
 * @path /todoApp/member/todos/:todoId/permanent
 * @accessor api.functional.todoApp.member.todos.permanent.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Target todo's unique identifier (UUID scope)
     */
    todoId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/todoApp/member/todos/:todoId/permanent",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/member/todos/${encodeURIComponent(props.todoId ?? "null")}/permanent`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
