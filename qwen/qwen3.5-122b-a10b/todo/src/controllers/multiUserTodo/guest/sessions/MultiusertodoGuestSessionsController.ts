import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMultiUserTodoMemberSession } from "../../../../api/structures/IMultiUserTodoMemberSession";
import { IPageIMultiUserTodoMemberSession } from "../../../../api/structures/IPageIMultiUserTodoMemberSession";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { getMultiUserTodoGuestSessionsSessionId } from "../../../../providers/getMultiUserTodoGuestSessionsSessionId";
import { patchMultiUserTodoGuestSessions } from "../../../../providers/patchMultiUserTodoGuestSessions";

@Controller("/multiUserTodo/guest/sessions")
export class MultiusertodoGuestSessionsController {
  /**
   * Retrieve a filtered and paginated list of authenticated member sessions for security auditing and session management.
   *
   * This operation allows members to view their own active and terminated sessions, providing visibility into where and when their account has been accessed. Each session record contains connection metadata including client IP address, request URI, and temporal information for audit trails.
   *
   * Members can filter sessions by date ranges, expiration status, and soft-deletion state. The response includes session summaries optimized for list displays, with detailed session information available through individual session retrieval operations.
   *
   * This operation enforces strict privacy boundaries - members can only view their own sessions. Cross-user access is denied, and unauthorized access attempts are rejected with appropriate error responses.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering member sessions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query multi_user_todo_member_sessions table filtered by the authenticated member's ID from the session token.
   *
   * Apply search filters from request body:
   * - Date range filtering on created_at and expired_at
   * - Status filtering (active, expired, soft-deleted)
   * - Pagination with cursor or offset-based pagination
   * - Sorting by creation date or expiration date
   *
   * Implement member ownership validation - only return sessions where multi_user_todo_member_id matches the authenticated member's ID.
   *
   * Return paginated results with IPageIMultiUserTodoMemberSession.ISummary structure including pagination metadata and session summary data.
   *
   * Handle edge cases:
   * - No sessions found: return empty data array with pagination metadata
   * - Invalid filter parameters: return validation error
   * - Session expired during operation: still include in results with appropriate status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IMultiUserTodoMemberSession.IRequest,
  ): Promise<IPageIMultiUserTodoMemberSession.ISummary> {
    try {
      return await patchMultiUserTodoGuestSessions({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific member session by its unique identifier.
   *
   * This operation provides access to session metadata including connection details, temporal information, and session status for authenticated member accounts. The session must belong to the currently authenticated member, as the system enforces strict privacy boundaries preventing cross-user session access.
   *
   * The response includes connection metadata such as client IP address, request URI, and referrer information from when the session was established. Temporal fields track session creation, last update, and expiration timestamps. Soft deletion status is also reflected in the response.
   *
   * Session information is critical for security auditing, session management, and troubleshooting authentication issues. Members can view their active sessions to monitor account activity and identify unauthorized access attempts.
   *
   * Related operations include listing all sessions for the authenticated member and terminating specific sessions through the logout or session management endpoints.
   *
   * @param connection
   * @param sessionId Target session's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query multi_user_todo_member_sessions table by session UUID.
   *
   * Validate authenticated member identity from request token.
   * Verify session.multi_user_todo_member_id matches authenticated member ID.
   * Return 404 if session does not exist.
   * Return 403 if session belongs to different member.
   * Return 400 if session is expired (expired_at < current time).
   *
   * Include all session fields: id, multi_user_todo_member_id, ip, href, referrer, created_at, updated_at, deleted_at, expired_at.
   *
   * Apply soft delete check: if deleted_at is not null, treat as terminated session.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IMultiUserTodoMemberSession> {
    try {
      return await getMultiUserTodoGuestSessionsSessionId({
        guest,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
