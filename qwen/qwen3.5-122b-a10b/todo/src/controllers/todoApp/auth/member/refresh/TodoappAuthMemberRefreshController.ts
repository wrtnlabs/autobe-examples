import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoAppMember } from "../../../../../api/structures/ITodoAppMember";
import { postTodoAppAuthMemberRefresh } from "../../../../../providers/postTodoAppAuthMemberRefresh";

@Controller("/todoApp/auth/member/refresh")
export class TodoappAuthMemberRefreshController {
  /**
   * Renew expired access tokens using a valid refresh token. This endpoint enables members to maintain authenticated sessions without re-entering credentials, supporting seamless user experience across extended usage periods.
   *
   * The refresh process begins with refresh token validation. The system decodes the JWT refresh token and verifies its cryptographic signature to ensure authenticity. Token expiration is checked, and expired refresh tokens result in a 401 unauthorized response requiring re-authentication via the login endpoint.
   *
   * After signature verification, the system extracts the member identifier from the token payload and queries the todo_app_member_sessions table to validate the associated session. The session must exist and not be expired (expired_at > now). Invalid or expired sessions indicate compromised or stale tokens, resulting in authentication failure.
   *
   * Upon successful validation, the system generates a new pair of access and refresh tokens. The access token is short-lived (typically 15 minutes) and used for API authentication, while the refresh token is longer-lived (30 days) and used for subsequent renewals. The session's expired_at timestamp is updated to extend the session validity period.
   *
   * The response includes an IAuthorized object containing the new access and refresh tokens. The client should replace the old tokens with the new ones and continue using the access token for authenticated requests. The refresh token rotation mechanism ensures that compromised tokens have limited validity windows.
   *
   * Related operations: Access tokens are used for all protected API endpoints including todo operations (/auth/member/todos/*). When access tokens expire, this refresh operation renews them without requiring login. If refresh tokens also expire or become invalid, users must re-authenticate via the login endpoint.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for renewing expired access tokens.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate request body: refresh_token non-empty. 2. Decode and verify refresh token signature and expiration. 3. Extract member_id from token payload. 4. Query todo_app_member_sessions to verify session exists and is not expired. 5. If session invalid or expired, return 401 unauthorized. 6. Generate new access token and refresh token. 7. Update session expired_at timestamp. 8. Return IAuthorized response with new tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async refreshToken(
    @TypedBody()
    body: ITodoAppMember.IRefresh,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
