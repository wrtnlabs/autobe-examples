import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppGuest } from "../../../../api/structures/ITodoAppGuest";
import { postTodoAppAuthGuestJoin } from "../../../../providers/postTodoAppAuthGuestJoin";
import { postTodoAppAuthGuestRefresh } from "../../../../providers/postTodoAppAuthGuestRefresh";

@Controller("/todoApp/auth/guest")
export class TodoappAuthGuestController {
  /**
   * Register a new guest user or retrieve existing guest by device fingerprint.
   *
   * This endpoint creates a guest account when a new device accesses the system, or returns the existing guest identity if the device has registered before. Guest accounts are identified solely by device fingerprint, requiring no email or password credentials.
   *
   * **Business Logic**
   * - Accept device_fingerprint from request body
   * - Search for existing guest with matching fingerprint
   * - If found and not soft-deleted: return existing guest's session
   * - If not found or soft-deleted: create new guest record and session
   * - Generate JWT access token for the guest session
   *
   * **Schema Integration**
   * - Creates record in todo_app_guests with device_fingerprint
   * - Creates associated todo_app_guest_sessions record
   * - Sets created_at and updated_at timestamps
   * - Session expires_at set based on configured timeout
   *
   * **Error Handling**
   * - Return 400 if device_fingerprint is missing or empty
   * - Return 500 on database errors during guest or session creation
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Device fingerprint for guest identification
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Create a new guest account identified by device
     *   fingerprint. Validate device_fingerprint is provided and non-empty.
     *   Check if guest with this fingerprint already exists; if so, return
     *   existing guest's session. If not, create new guest record with current
     *   timestamp, create associated session with expiration (e.g., 30 days),
     *   and return authorized response with access token. Session expiration
     *   should be configurable. On soft-deleted guests (deleted_at not null),
     *   treat as new registration.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppGuest.IJoin,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh the session token for an existing guest user.
   *
   * This endpoint extends the session lifetime for authenticated guest users by generating a new access token. It validates the current session token and updates its expiration timestamp.
   *
   * **Business Logic**
   * - Accept current session token in request body
   * - Validate token signature and extract guest session ID
   * - Look up session in todo_app_guest_sessions table
   * - Verify session has not expired (expired_at > now)
   * - Generate new access token with extended expiration
   * - Update session's expired_at timestamp
   * - Return new authorized response with refreshed tokens
   *
   * **Schema Integration**
   * - Reads from todo_app_guest_sessions by session ID
   * - Updates expired_at timestamp on session record
   * - Links to todo_app_guests for guest identity verification
   *
   * **Security Considerations**
   * - Token validation prevents unauthorized refresh attempts
   * - Expired sessions are rejected with 401 response
   * - Session expiration configured per application policy
   *
   * **Error Handling**
   * - Return 401 if session token is invalid or expired
   * - Return 401 if associated guest account is soft-deleted
   * - Return 500 on database errors during session lookup or update
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Current session token for refresh
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Refresh an existing guest session token. Validate
     *   the provided session token is valid and not expired. Look up the guest
     *   session by token, verify expired_at is in the future, then generate a
     *   new access token with extended expiration. Update the session's
     *   expired_at timestamp in todo_app_guest_sessions table. Return new
     *   authorized response with refreshed tokens. Return 401 if session is
     *   expired or invalid.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppGuest.IRefresh,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
