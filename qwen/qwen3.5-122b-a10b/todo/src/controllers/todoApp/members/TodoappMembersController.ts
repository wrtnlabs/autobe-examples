import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { ITodoAppMember } from "../../../api/structures/ITodoAppMember";
import { getTodoAppMembersMemberId } from "../../../providers/getTodoAppMembersMemberId";
import { patchTodoAppMembers } from "../../../providers/patchTodoAppMembers";

@Controller("/todoApp/members")
export class TodoappMembersController {
  /**
   * Update the authenticated member's profile information.
   *
   * This operation allows a logged-in member to update their display name. The member's email and password cannot be changed through this endpoint. All updates are validated against business rules before being persisted to the database.
   *
   * **Updateable Fields**
   *
   * - `displayName`: The user's chosen public name shown in the application interface
   *
   * **Validation Rules**
   *
   * - Display name is required and must not be empty
   * - Display name length must be between 1 and 100 characters
   *
   * **Access Control**
   *
   * - Requires valid authentication (member token)
   * - Only updates the authenticated member's own profile
   * - Returns 401 Unauthorized if not authenticated
   * - Returns 403 Forbidden if authentication is invalid
   *
   * @param connection
   * @param body Profile update request containing display name to update.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Implement profile update for authenticated member.
   *
   * **Authentication**
   * - Extract member ID from JWT token in Authorization header
   * - Validate token is not expired
   * - Return 401 if token missing or invalid
   *
   * **Request Validation**
   * - Validate display_name is present if provided
   * - Validate display_name length (1-100 characters)
   * - Return 400 Bad Request with validation errors
   *
   * **Database Update**
   * - Query: UPDATE todo_app_members SET display_name = $1, updated_at = $2 WHERE id = $3 AND deleted_at IS NULL
   * - Use member ID from authenticated token
   * - Return updated member record
   *
   * **Error Handling**
   * - 401 Unauthorized: Missing or invalid authentication token
   * - 400 Bad Request: Validation errors on display_name
   * - 404 Not Found: Member not found or already deleted
   *
   * **Response**
   * - Return 200 OK with updated member object
   * - Include updated_at timestamp
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @TypedBody()
    body: ITodoAppMember.IUpdate,
  ): Promise<ITodoAppMember> {
    try {
      return await patchTodoAppMembers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a member's profile information by their unique identifier.
   *
   * This endpoint returns the complete profile details for a specific member account, including their display name and email address. The authenticated member must match the requested memberId to ensure data privacy and isolation.
   *
   * **Authorization**
   *
   * Only the member themselves can access their own profile. Members cannot view or access another user's profile information. This enforces the private todo app's strict data isolation policy.
   *
   * **Response Data**
   *
   * The response includes the member's display name, email address, and account timestamps (created_at, updated_at). The password_hash is never exposed in API responses.
   *
   * @param connection
   * @param memberId The unique identifier of the member account (UUID format, global scope).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query todo_app_members table by UUID id parameter. Verify the authenticated member's ID matches the requested memberId in the path to enforce data isolation. Return 404 if member not found or if the member has been soft-deleted (deleted_at is not null). Return 403 if the authenticated member does not match the requested memberId. Include display_name, email, created_at, and updated_at in the response. Never expose password_hash field.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":memberId")
  public async at(
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMember> {
    try {
      return await getTodoAppMembersMemberId({
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
