import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppMemberSession } from "../../../../api/structures/IPageITodoAppMemberSession";
import { ITodoAppMemberSession } from "../../../../api/structures/ITodoAppMemberSession";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { getTodoAppGuestSessionsSessionId } from "../../../../providers/getTodoAppGuestSessionsSessionId";
import { patchTodoAppGuestSessions } from "../../../../providers/patchTodoAppGuestSessions";

@Controller("/todoApp/guest/sessions")
export class TodoappGuestSessionsController {
  /**
   * Retrieve a paginated list of the authenticated member's active login sessions.
   *
   * This endpoint returns session information including device details, IP addresses, and session timestamps for security auditing and session management purposes. Members can view all their currently active sessions across different devices and browsers.
   *
   * **Security and Privacy**
   *
   * Only the authenticated member can view their own sessions. Session tokens (access_token, refresh_token) are excluded from the response for security. Each session record includes the originating IP address, page href, and referrer captured at login time for security auditing.
   *
   * **Pagination and Filtering**
   *
   * Supports cursor-based pagination for efficient browsing of session history. Filter by creation date range and sort by creation time or expiration time. Results are ordered newest-first by default.
   *
   * @param connection
   * @param body Search criteria for filtering and paginating session list, including date range filters, sorting options, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query todo_app_member_sessions table for the authenticated member (from session token). Apply search filters from request body including date range filtering on created_at, sorting by created_at or expired_at, and cursor-based pagination. Filter only sessions where deleted_at is null (active sessions). Order results by created_at descending (newest first). Return paginated session summaries excluding sensitive token data (access_token, refresh_token should not be exposed in list response). Implement access control to ensure member can only view their own sessions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: ITodoAppMemberSession.IRequest,
  ): Promise<IPageITodoAppMemberSession.ISummary> {
    try {
      return await patchTodoAppGuestSessions({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific session belonging to the authenticated member.
   *
   * This endpoint returns comprehensive session information including creation timestamp, expiration time, client IP address, and activity metadata. The session must belong to the currently authenticated member for access.
   *
   * **Security**
   * Only the session owner can access this endpoint. Sessions are filtered by the authenticated member's ID to ensure data isolation.
   *
   * **Expiration**
   * Expired sessions can still be retrieved but should be flagged as invalid for authentication purposes. The expired_at timestamp indicates when the session becomes invalid.
   *
   * **Sensitive Data**
   * JWT access and refresh tokens are excluded from the response to prevent credential exposure.
   *
   * @param connection
   * @param sessionId The unique identifier of the session to retrieve (UUID format, global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query todo_app_member_sessions table by session ID. Verify the session belongs to the authenticated member (todo_app_member_id matches current user). Return session metadata including id, IP address, href, referrer, created_at, updated_at, expired_at, and deleted_at status. Exclude access_token and refresh_token from response for security. Check session expiration status and mark as expired if expired_at < current time. Return 404 if session not found or does not belong to authenticated member. Return 403 if session belongs to another member.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMemberSession> {
    try {
      return await getTodoAppGuestSessionsSessionId({
        guest,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
