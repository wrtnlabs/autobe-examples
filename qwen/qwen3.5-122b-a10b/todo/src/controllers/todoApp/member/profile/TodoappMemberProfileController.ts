import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberProfile } from "../../../../providers/getTodoAppMemberProfile";
import { putTodoAppMemberProfile } from "../../../../providers/putTodoAppMemberProfile";

@Controller("/todoApp/member/profile")
export class TodoappMemberProfileController {
  /**
   * Retrieve the current user's profile information.
   *
   * This endpoint returns the authenticated user's profile data including their display name and account details. The user is identified from the authentication token or session, so no path parameters are required.
   *
   * **Access Control**
   *
   * Only the authenticated user can access their own profile. Users cannot view other users' profiles. Any attempt to access another user's data is rejected by the system.
   *
   * **Response Fields**
   *
   * The response includes the user's display name, email, and account timestamps (created_at, updated_at). The password_hash is never exposed in API responses.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve the current authenticated user's profile from todo_app_members table.
   *
   * 1. Extract user ID from authentication token/session
   * 2. Query todo_app_members table WHERE id = authenticated_user_id AND deleted_at IS NULL
   * 3. Return the member record excluding password_hash field
   * 4. If user not found or soft-deleted, return 404 Not Found
   * 5. Implement authorization middleware to ensure only authenticated users can access this endpoint
   * 6. The user context is derived from authentication, not path parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<ITodoAppMember> {
    try {
      return await getTodoAppMemberProfile({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the current authenticated user's profile display name.
   *
   * This operation allows members to modify their public display name that appears throughout the application. The display name is a user-defined identifier that represents them within the system.
   *
   * **Access Control**
   *
   * Only the authenticated user can update their own profile. Users cannot access or modify other users' profile information. The system enforces complete data isolation between users.
   *
   * **Validation**
   *
   * The display name must be provided and cannot be empty. The system validates the input before persisting changes to the database.
   *
   * @param connection
   * @param body Profile update request containing the new display name for the authenticated user.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Verify the request has a valid authentication token (member session)
   * 2. Extract the member_id from the authenticated session context
   * 3. Validate the request body contains a non-empty display_name string
   * 4. Query todo_app_members table: SELECT id, email, display_name, created_at, updated_at WHERE id = ? AND deleted_at IS NULL
   * 5. If member not found or soft-deleted, return 404 Not Found
   * 6. Update the record: UPDATE todo_app_members SET display_name = ?, updated_at = NOW() WHERE id = ?
   * 7. Return the updated member record with id, email, display_name, created_at, updated_at
   * 8. If authentication fails or session is invalid, return 401 Unauthorized
   * 9. If validation fails (empty display_name), return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMember.IUpdate,
  ): Promise<ITodoAppMember> {
    try {
      return await putTodoAppMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
