import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { ITodoAppMemberEmailVerification } from "../../../../api/structures/ITodoAppMemberEmailVerification";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberEmailVerificationsVerificationId } from "../../../../providers/getTodoAppMemberEmailVerificationsVerificationId";
import { patchTodoAppMemberEmailVerifications } from "../../../../providers/patchTodoAppMemberEmailVerifications";

@Controller("/todoApp/member/email-verifications")
export class TodoappMemberEmail_verificationsController {
  /**
   * Verify email ownership during member registration by submitting a verification token.
   *
   * This operation confirms that the email address provided during registration belongs to the registering user. The verification token is sent via email and must be submitted through this endpoint to activate the member account.
   *
   * Upon successful verification, the system marks the verification record as confirmed by setting the verified_at timestamp. The associated member account becomes active and the user can proceed with authentication.
   *
   * The token must be valid (not expired), not previously used, and correspond to an existing member account. Expired or already-used tokens will be rejected with appropriate error responses.
   *
   * Related operations:
   * - Registration creates the verification record and sends the token via email
   * - After verification, the user can log in using the registered email and password
   *
   * @param connection
   * @param body Email verification token submitted by the user
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query todo_app_member_email_verifications table by token. Validate token exists, not expired, and not already verified. Set verified_at timestamp on successful verification. Return member account information after verification. Check todo_app_member_id foreign key validity. Verify deleted_at is null for both verification record and member account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async verify(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMemberEmailVerification.IRequest,
  ): Promise<ITodoAppMemberEmailVerification> {
    try {
      return await patchTodoAppMemberEmailVerifications({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific email verification record for the authenticated member.
   *
   * This endpoint allows members to check the status of their email verification, including whether the email has been verified (verified_at is set), when the verification token expires, and when the verification record was created. The verification record is stored in the todo_app_member_email_verifications table and contains a cryptographically secure token that was sent to the member's email address during the registration workflow.
   *
   * **Security Considerations**
   *
   * Only the member who owns the verification record can access it. The system verifies that the authenticated member's ID matches the todo_app_member_id field of the verification record before returning any data. This ownership verification prevents members from accessing verification information belonging to other users and protects against information leakage about other members' registration status.
   *
   * **Soft Delete Behavior**
   *
   * If the verification record has been soft-deleted (deleted_at is not null), the endpoint returns a 404 Not Found response. Soft-deleted records are treated as non-existent to prevent access to expired or invalidated verification tokens.
   *
   * **Response Data**
   *
   * The response includes the verification record's ID, the expiration timestamp (expires_at), the verification completion timestamp (verified_at), and the creation timestamp (created_at). The token value itself is not exposed in the response to maintain security and prevent token replay attacks.
   *
   * **Related Operations**
   *
   * - Email verification records are created during member registration when a new account is created
   * - Email is verified by the member clicking the verification link sent to their email address, which sets the verified_at timestamp
   * - Members can request a new verification email if the token expires or before clicking the verification link
   * - Use GET /todoApp/members/{memberId} to retrieve the member's account information after verification
   *
   * @param connection
   * @param verificationId Unique identifier of the email verification record (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve email verification record by ID for authenticated member. 1) Authenticate the request and get the current member's ID. 2) Query todo_app_member_email_verifications table where id matches verificationId AND todo_app_member_id matches authenticated member's ID. 3) If record not found or belongs to different member, return 404 Not Found. 4) If record is soft-deleted (deleted_at is not null), return 404 Not Found. 5) Return verification record with id, token status, expires_at, verified_at, and created_at. 6) Ensure ownership verification happens before any data access to prevent information leakage about other members' verification records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":verificationId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("verificationId")
    verificationId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMemberEmailVerification> {
    try {
      return await getTodoAppMemberEmailVerificationsVerificationId({
        member,
        verificationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
