import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { ITodoAppTodo } from "../../../../../api/structures/ITodoAppTodo";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { putTodoAppMemberTrashTodoIdRestore } from "../../../../../providers/putTodoAppMemberTrashTodoIdRestore";

@Controller("/todoApp/member/trash/:todoId/restore")
export class TodoappMemberTrashController {
  /**
   * Restore a soft-deleted todo from trash back to the active todo list.
   *
   * This operation recovers a previously deleted todo by removing its deletion timestamp, returning it to normal visibility in the user's todo list with all attributes intact including completion status, dates, and description.
   *
   * **Access Control**
   *
   * Only the todo owner can restore their own deleted todos. The system validates that the authenticated member matches the todo's owner before allowing restoration. Attempting to restore another user's todo or a non-existent todo results in an authorization or not found error.
   *
   * **Business Behavior**
   *
   * When restored, the todo reappears in the normal todo list immediately. The completion status, start date, due date, and all other attributes remain exactly as they were when deleted. The updated_at timestamp is refreshed to reflect the restoration time.
   *
   * @param connection
   * @param todoId Unique identifier of the todo to restore (UUID format). The todo must be soft-deleted and belong to the authenticated user.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Extract todoId from path parameter (UUID format)
   * 2. Verify authentication - reject if no valid session
   * 3. Query todo_app_todos WHERE id = todoId AND todo_app_member_id = authenticated_member_id
   * 4. If not found, return 404 Not Found
   * 5. Check deleted_at is NOT null - if null, return 400 Bad Request (todo not deleted)
   * 6. Update deleted_at to NULL and updated_at to current timestamp
   * 7. Return the restored todo entity with all fields
   *
   * **Edge Cases**
   * - Todo does not exist: 404 Not Found
   * - Todo belongs to another user: 403 Forbidden
   * - Todo is not deleted (deleted_at is null): 400 Bad Request with message indicating todo is already active
   * - Database constraint violation: 500 Internal Server Error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async restore(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodo> {
    try {
      return await putTodoAppMemberTrashTodoIdRestore({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
