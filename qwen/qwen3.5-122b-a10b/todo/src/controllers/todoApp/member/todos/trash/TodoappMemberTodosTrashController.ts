import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppTodo } from "../../../../../api/structures/IPageITodoAppTodo";
import { ITodoAppTodo } from "../../../../../api/structures/ITodoAppTodo";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteTodoAppMemberTodosTodoIdTrash } from "../../../../../providers/deleteTodoAppMemberTodosTodoIdTrash";
import { patchTodoAppMemberTodosTrash } from "../../../../../providers/patchTodoAppMemberTodosTrash";

@Controller("/todoApp/member/todos")
export class TodoappMemberTodosTrashController {
  /**
   * Retrieve a paginated list of soft-deleted todos from the user's trash.
   *
   * This operation returns todos that have been deleted by the user but not yet permanently removed. Soft-deleted todos retain all their original attributes including title, description, dates, and completion status. Users can review deleted tasks and choose to restore them or permanently delete them.
   *
   * ## Access Control
   *
   * Only the authenticated user's own deleted todos are returned. Users cannot access another user's trash.
   *
   * ## Pagination
   *
   * Results are paginated to handle large numbers of deleted todos efficiently. Users can control the page number and page size through the request body parameters.
   *
   * ## Soft Delete Behavior
   *
   * Todos in the trash are soft-deleted, meaning they remain in the database with a deleted_at timestamp set. They do not appear in the normal todo list but are accessible through this trash endpoint.
   *
   * @param connection
   * @param body Pagination parameters including page number and limit to control the number of results returned per page.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query todo_app_todos table filtering by
     *   todo_app_member_id from authenticated user context and deleted_at IS
     *   NOT NULL. Apply pagination using page and limit parameters from request
     *   body. Sort results by deleted_at descending to show most recently
     *   deleted first. Return paginated response with items array containing
     *   ITodoAppTodo.ISummary objects and total count. Authorization middleware
     *   must validate that authenticated user owns all returned todos.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("trash")
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppTodo.IRequest,
  ): Promise<IPageITodoAppTodo.ISummary> {
    try {
      return await patchTodoAppMemberTodosTrash({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a todo from trash, removing it and all associated edit history from the system.
   *
   * This operation performs permanent deletion of a soft-deleted todo. Unlike soft deletion which moves todos to trash, this operation completely removes the todo record and all associated snapshots from the database. This action cannot be undone.
   *
   * **Access Control**
   *
   * Only the todo owner can permanently delete their own todos from trash. The authenticated user must match the todo's owner. The todo must exist and be in trash status (deleted_at is set).
   *
   * **Cascade Deletion**
   *
   * When a todo is permanently deleted, all associated edit history snapshots are also permanently removed from the database through cascade deletion.
   *
   * **Error Conditions**
   *
   * Returns 404 if the todo does not exist, is not in trash status, or belongs to another user.
   *
   * @param connection
   * @param todoId Unique identifier of the todo to permanently delete from trash (scoped to authenticated user)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate authenticated member identity from
     *   session token 2. Query todo_app_todos by id and todo_app_member_id
     *   (authenticated user) 3. Verify todo exists AND deleted_at is not null
     *   (in trash status) 4. If todo not found or not in trash or belongs to
     *   different user, return 404 5. Delete the todo record (this cascades to
     *   delete associated snapshots from todo_app_snapshots) 6. Return 204 No
     *   Content on success
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId/trash")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppMemberTodosTodoIdTrash({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
