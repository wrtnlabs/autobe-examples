import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { ITodoAppTodo } from "../../../../../api/structures/ITodoAppTodo";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchTodoAppMemberTodosTodoIdComplete } from "../../../../../providers/patchTodoAppMemberTodosTodoIdComplete";

@Controller("/todoApp/member/todos/:todoId/complete")
export class TodoappMemberTodosCompleteController {
  /**
   * Toggle the completion status of a todo task between complete and incomplete.
   *
   * This operation changes the completion status of an existing todo task. Users can mark tasks as complete when finished, or mark them as incomplete if they need to continue working on them. The completion status is a simple toggle between two states.
   *
   * **Access Control**
   *
   * Only the owner of the todo can toggle its completion status. The authenticated member must match the todo's owner. Deleted todos (in trash) cannot be toggled.
   *
   * **Edit History**
   *
   * Each toggle operation creates a snapshot record in the edit history, allowing users to view when the completion status was changed.
   *
   * @param connection
   * @param todoId Unique identifier of the todo task to toggle completion status (UUID format).
   * @param body Toggle request containing the target completion status value.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate authenticated member owns the todo by
     *   checking todo_app_member_id matches current user. 2. Verify todo exists
     *   and is not permanently deleted (deleted_at IS NULL). 3. Update
     *   is_completed field to the target value from request body. 4. Update
     *   updated_at timestamp to current time. 5. Create corresponding snapshot
     *   record in todo_app_snapshots table for edit history. 6. Return the
     *   updated todo entity.
   *
   * Error cases:
   * - 404 if todo not found or belongs to different user
   * - 400 if target status is not valid boolean
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async toggle(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppTodo.IToggle,
  ): Promise<ITodoAppTodo> {
    try {
      return await patchTodoAppMemberTodosTodoIdComplete({
        member,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
