export async function test_api_password_reset_token_expired_validation(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create a member account
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IMultiUserTodoMember.IJoin,
  });
  typia.assert(memberAuth);
  // 2. Generate a valid UUID for a non-existent password reset token
  const nonExistentResetId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  // 3. Attempt to retrieve the password reset token (should fail)
  await TestValidator.httpError(
    "expired/invalid token should return error",
    [400, 404],
    async () => {
      await api.functional.multiUserTodo.member.password_resets.at(
        memberConnection,
        {
          resetId: nonExistentResetId,
        },
      );
    },
  );
}
