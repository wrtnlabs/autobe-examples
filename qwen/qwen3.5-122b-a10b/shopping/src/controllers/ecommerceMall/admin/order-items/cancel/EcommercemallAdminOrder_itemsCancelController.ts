@Controller("/ecommerceMall/admin/order-items/:orderItemId/cancel")
export class EcommercemallAdminOrder_itemsCancelController {
  /**
   * Create a cancellation request for an order item that is currently in 'paid' status.
   *
   * This operation allows customers to request cancellation of order items before they are shipped. The customer must provide a reason explaining why they want to cancel the order item. The cancellation request is created with 'pending' status and awaits seller approval or rejection.
   *
   * **Eligibility Requirements**:
   * - The order item must have 'paid' status (not yet shipped)
   * - The order item must belong to the authenticated customer
   * - No existing cancellation request must exist for this order item
   * - The order item cannot be already cancelled, refunded, or shipped
   *
   * **Business Workflow**:
   * 1. Customer submits cancellation request with reason
   * 2. Request is created with 'pending' status
   * 3. Seller reviews and either approves or rejects the request
   * 4. If approved: order item status changes to 'cancelled', stock is restored via inventory record, refund is processed
   * 5. If rejected: order item continues processing normally, status remains 'paid'
   *
   * **Related Operations**:
   * - `GET /order-items/{orderItemId}`: Retrieve order item details to verify eligibility
   * - `PATCH /order-items/{orderItemId}/cancellation-requests/{requestId}`: Seller response to approve/reject (if implemented)
   * - `GET /order-items/{orderItemId}/cancellation-requests`: List cancellation requests for an order item
   *
   * @param connection
   * @param orderItemId Target order item's UUID for which cancellation is requested
   * @param body Cancellation request creation information including the reason for cancellation
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate orderItemId exists and belongs to authenticated customer
   * 2. Query ecommerce_mall_order_items table for the order item
   * 3. Verify order item status is 'paid' (not shipped, delivered, cancelled, or refunded)
   * 4. Check no existing pending/approved cancellation request exists for this order item
   * 5. Create new ecommerce_mall_order_item_cancellation_requests record with:
   *    - order_item_id: the order item ID
   *    - reason: customer-provided cancellation reason
   *    - status: 'pending'
   *    - requested_at: current timestamp
   *    - responded_at: null
   * 6. Create a snapshot of the cancellation request state
   * 7. Return the created cancellation request with 201 status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallOrderItemCancellationRequest.ICreate,
  ): Promise<IEcommerceMallOrderItemCancellationRequest> {
    try {
      return await postEcommerceMallAdminOrderItemsOrderItemIdCancel({
        admin,
        orderItemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
