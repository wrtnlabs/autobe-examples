import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallAdmin } from "../../../../api/structures/IEcommerceMallAdmin";
import { IPageIEcommerceMallAdmin } from "../../../../api/structures/IPageIEcommerceMallAdmin";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminAdminsAdminId } from "../../../../providers/getEcommerceMallAdminAdminsAdminId";
import { patchEcommerceMallAdminAdmins } from "../../../../providers/patchEcommerceMallAdminAdmins";

@Controller("/ecommerceMall/admin/admins")
export class EcommercemallAdminAdminsController {
  /**
   * Retrieve a filtered and paginated list of administrator accounts on the platform.
   *
   * This operation provides administrators with the ability to search, view, and manage administrator accounts across the platform. It supports comprehensive filtering by email, account status, and admin grade, along with flexible sorting and pagination options.
   *
   * Access Control:
   * - Only authenticated administrators (regular or super) can access this endpoint
   * - Regular administrators can view all admin accounts but cannot modify admin grades
   * - Super administrators have full visibility and can manage admin grade promotions/demotions
   * - The endpoint respects data isolation rules while providing platform-wide oversight capabilities
   *
   * Search Capabilities:
   * - Email partial matching for finding specific administrators
   * - Account status filtering (active, suspended, banned)
   * - Admin grade filtering (regular, super)
   * - Date range filtering by creation date
   * - Custom sorting by any admin field
   *
   * Pagination:
   * - Cursor-based pagination for efficient large dataset handling
   * - Configurable page size with maximum limit enforcement
   * - Includes pagination metadata for navigation
   * - Returns admin summary information optimized for list displays
   *
   * Related Operations:
   * - GET /admins/{adminId} - Retrieve detailed information for a specific administrator
   * - POST /admins - Submit a request to become an administrator (for non-admin users)
   * - PUT /admins/{adminId} - Update administrator profile information
   * - DELETE /admins/{adminId} - Soft delete an administrator account
   * - GET /admins/me - Retrieve the current administrator's own profile
   *
   * @param connection
   * @param body Search criteria and pagination parameters for administrator account listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_admins table with pagination, filtering, and sorting capabilities.
   *
   * Implementation steps:
   * 1. Validate caller is authenticated as an administrator (regular or super)
   * 2. Build query with optional filters: email partial match, account_status (active/suspended/banned), admin_grade (regular/super)
   * 3. Apply sorting with default: created_at DESC (newest first)
   * 4. Apply cursor-based pagination with configurable page size (default 20, max 100)
   * 5. Join with sessions table if session information is requested
   * 6. Exclude deleted_at records (soft-deleted admins)
   * 7. Return paginated results with admin summary information
   *
   * Business rules:
   * - Regular admins can view all admins but cannot manage admin grades
   * - Super admins can view all admins and manage admin grades
   * - All admins can view their own profile via GET /admins/me
   * - Account status and admin_grade must be validated against enum values
   * - Email search uses case-insensitive partial matching
   *
   * Edge cases:
   * - Empty result set returns pagination with zero data
   * - Invalid filter values return validation error
   * - Page size exceeding maximum returns error with allowed range
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallAdmin.IRequest,
  ): Promise<IPageIEcommerceMallAdmin.ISummary> {
    try {
      return await patchEcommerceMallAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific administrator account by their unique identifier.
   *
   * This operation provides administrators with the ability to view complete profile information for any administrator on the platform, including their privilege grade, account status, and registration timestamps. This is essential for administrative oversight and account management purposes.
   *
   * The response excludes sensitive authentication credentials such as the password hash to maintain security. Only authenticated administrators can access this endpoint - customers and sellers are denied access regardless of their intent.
   *
   * The operation validates that the target administrator account exists and has not been soft-deleted. If the account is deleted or does not exist, a 404 Not Found error is returned.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator account (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_admins table by id (UUID). Validate the requesting user is an authenticated administrator. Check that the target admin account is not soft-deleted (deleted_at is null). Return administrator details excluding password_hash. Include admin_grade (regular/super), account_status (active/suspended/banned), email, and timestamps. Apply row-level security to ensure only admins can access this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallAdmin> {
    try {
      return await getEcommerceMallAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
