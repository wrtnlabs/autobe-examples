import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCustomer } from "../../../../api/structures/IEcommerceMallCustomer";
import { IPageIEcommerceMallCustomer } from "../../../../api/structures/IPageIEcommerceMallCustomer";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminCustomersCustomerId } from "../../../../providers/getEcommerceMallAdminCustomersCustomerId";
import { patchEcommerceMallAdminCustomers } from "../../../../providers/patchEcommerceMallAdminCustomers";
import { postEcommerceMallAdminCustomersCustomerIdBan } from "../../../../providers/postEcommerceMallAdminCustomersCustomerIdBan";
import { postEcommerceMallAdminCustomersCustomerIdUnban } from "../../../../providers/postEcommerceMallAdminCustomersCustomerIdUnban";
import { putEcommerceMallAdminCustomersCustomerId } from "../../../../providers/putEcommerceMallAdminCustomersCustomerId";

@Controller("/ecommerceMall/admin/customers")
export class EcommercemallAdminCustomersController {
  /**
   * Retrieve a filtered and paginated list of customer accounts for administrator oversight and management.
   *
   * This operation provides comprehensive search capabilities for customer accounts including partial email matching, display name filtering, phone number search, and account status filtering (active, suspended, banned). Administrators can filter by registration date ranges to identify customers within specific time periods.
   *
   * Supports flexible pagination with configurable page sizes and multiple sorting options. The response includes customer summary information optimized for administrative list displays, excluding sensitive data like password hashes.
   *
   * Administrators can view all customers on the platform regardless of account status. Super administrators have additional capabilities to view soft-deleted customers when investigating account issues or compliance matters.
   *
   * Related operations include GET /customers/{customerId} for detailed customer information, PATCH /customers/{customerId} for profile updates, and DELETE /customers/{customerId} for account deletion.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for customer list retrieval
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_customers table with pagination and filtering for administrator customer management. Apply search filters on email, displayName, phoneNumber, and accountStatus. Support date range filtering on createdAt and updatedAt fields. Implement cursor-based or offset-based pagination with configurable page size (default 20, max 100). Sort by createdAt, updatedAt, or email with ascending/descending order. Exclude soft-deleted customers from results unless explicitly requested by super admin. Return customer summary information optimized for list displays including id, email, displayName, phoneNumber, accountStatus, createdAt, and updatedAt.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallCustomer.IRequest,
  ): Promise<IPageIEcommerceMallCustomer.ISummary> {
    try {
      return await patchEcommerceMallAdminCustomers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed profile information for a specific customer account.
   *
   * This operation returns comprehensive customer profile data including display name, phone number, account status, and account timestamps. The response excludes sensitive authentication credentials such as the password hash.
   *
   * Access control:
   * - Customers can view their own profile by specifying their customer ID
   * - Administrators can view any customer profile for oversight and support purposes
   * - Unauthorized access attempts result in a 403 Forbidden response
   * - Non-existent or deleted customer IDs result in a 404 Not Found response
   *
   * The customer profile includes the email address used for authentication, optional display name and phone number, current account status (active, suspended, or banned), and timestamps for account creation and last modification. This information is useful for profile management, account verification, and administrative oversight.
   *
   * Related operations:
   * - PATCH /customers (update own profile)
   * - GET /customers/{customerId}/addresses (list customer shipping addresses)
   * - GET /customers/{customerId}/orders (list customer orders)
   *
   * @param connection
   * @param customerId Target customer's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Retrieve detailed customer profile information by UUID identifier.
   *
   * Implementation steps:
   * 1. Validate customerId is a valid UUID format
   * 2. Query ecommerce_mall_customers table by id = customerId
   * 3. Check if customer exists (return 404 if not found)
   * 4. Check if customer is not soft-deleted (deleted_at is null) - return 404 if deleted
   * 5. Verify authorization: customer can only view their own profile, or user must have admin role
   * 6. Return customer object excluding sensitive fields (password_hash)
   * 7. Include all profile fields: email, display_name, phone_number, account_status, created_at, updated_at
   *
   * Authorization rules:
   * - If authenticated user is the customer themselves (customerId matches session), allow access
   * - If authenticated user has admin role, allow access to any customer
   * - Otherwise, return 403 Forbidden
   *
   * Database query:
   * SELECT id, email, display_name, phone_number, account_status, created_at, updated_at
   * FROM ecommerce_mall_customers
   * WHERE id = $1 AND deleted_at IS NULL
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCustomer> {
    try {
      return await getEcommerceMallAdminCustomersCustomerId({
        admin,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a customer's profile information including display name and phone number.
   *
   * This endpoint allows authenticated customers to modify their personal profile information. Only the display name and phone number fields can be updated through this operation. Email addresses and password credentials require separate dedicated endpoints for security reasons.
   *
   * Every profile update automatically creates a snapshot record in the system to maintain a complete audit trail of all changes. This enables administrators and customers to review historical profile modifications when needed.
   *
   * The authenticated customer must own the profile being updated. Attempting to modify another customer's profile will result in an authorization error. Additionally, customers with 'banned' account status cannot update their profiles.
   *
   * Related operations include GET /customers/{customerId} for viewing profile details and DELETE /customers/{customerId} for account deletion.
   *
   * @param connection
   * @param customerId Target customer's unique identifier (UUID format)
   * @param body Customer profile update information containing editable fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update customer profile information for the given customerId. Validate that the authenticated customer matches the customerId in the path (ownership check). Allow updates only to display_name and phone_number fields. Email and password_hash cannot be modified through this endpoint. Create a snapshot record before applying changes to preserve audit trail. Update the updated_at timestamp. Return the complete updated customer object. Validate: display_name max length 100 characters, phone_number must be valid format if provided. Check account_status is not 'banned' before allowing updates.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":customerId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallCustomer.IUpdate,
  ): Promise<IEcommerceMallCustomer> {
    try {
      return await putEcommerceMallAdminCustomersCustomerId({
        admin,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Ban a customer account for policy violations or other administrative reasons by changing the account status.
   *
   * This operation changes the customer's `account_status` to 'banned', blocking their login access to the platform while preserving all historical data including orders, order items, reviews, wishlists, and addresses for record-keeping and legal compliance purposes. Unlike account deletion (which sets `deleted_at` and removes profile information), this ban operation only modifies the status field and maintains full account data.
   *
   * **Authorization**: Only regular administrators and super administrators with user management privileges can execute this operation.
   *
   * **Effects**:
   * - Customer cannot login to the platform (enforced at authentication layer by checking `account_status`)
   * - Customer cannot create new orders or modify cart/wishlist items
   * - Customer can view order history for record purposes (if they had active sessions before ban)
   * - All existing orders, order items, reviews, wishlists, and addresses remain intact
   * - The `account_status` field is updated to 'banned' while `deleted_at` remains null
   * - Customer remains fully in the system for audit and historical purposes
   * - Ban can be reversed by administrators using the unban operation
   *
   * **Related Operations**:
   * - `POST /ecommerceMall/admin/customers/{customerId}/unban` - Restore customer login access by changing `account_status` back to 'active'
   * - `PATCH /ecommerceMall/admin/customers` - List all customers (admin view)
   * - `GET /ecommerceMall/admin/customers/{customerId}` - View customer details
   *
   * **Error Conditions**:
   * - Customer not found: Return 404
   * - Customer already banned (account_status is 'banned'): Return 409 Conflict
   * - Insufficient permissions: Return 403 Forbidden
   *
   * **Database Schema Reference**: This operation updates the `account_status` column in the `ecommerce_mall_customers` table. The `deleted_at` column remains null, distinguishing this from account deletion operations.
   *
   * @param connection
   * @param customerId Target customer's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Execute customer account ban operation:
   * 1. Verify caller is regular or super administrator with user management privileges
   * 2. Fetch customer by id from ecommerce_mall_customers table
   * 3. Validate customer exists and is not already banned
   * 4. Update account_status column to 'banned'
   * 5. Update updated_at timestamp to current time
   * 6. Return updated customer record
   * 7. Log audit trail of ban action with administrator id
   *
   * Business rules:
   * - Banned customers cannot login (enforced at authentication layer)
   * - All order history, reviews, wishlists preserved
   * - Account deletion still not permitted, only ban/unban
   * - Ban is permanent until administrator unbans the account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":customerId/ban")
  public async ban(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCustomer> {
    try {
      return await postEcommerceMallAdminCustomersCustomerIdBan({
        admin,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Restore login access for a banned customer account by an administrator.
   *
   * This operation reverses a previous account ban, allowing the customer to log in and access all platform features again. The administrator must have regular or super administrator privileges to perform this action.
   *
   * When a customer account is unbanned, the system restores their login capability while preserving all historical data including order history, reviews, wishlists, and other transactional records. The account status changes from 'banned' to 'active' in the database.
   *
   * This operation is part of the administrator user management capabilities defined in the platform requirements. Regular administrators can ban and unban customer accounts for policy enforcement, while super administrators have full grade management capabilities.
   *
   * The operation requires the customer ID as a path parameter and returns the updated customer record with the new account status and timestamp.
   *
   * @param connection
   * @param customerId Target customer account ID (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Verify caller has admin authorization (regular or super administrator)
   * 2. Retrieve customer by customerId from ecommerce_mall_customers table
   * 3. Validate customer exists and account_status is 'banned'
   * 4. Update account_status from 'banned' to 'active'
   * 5. Update updated_at timestamp to current time
   * 6. Return updated customer record
   * 7. Log audit trail of unban action with administrator ID
   * 8. Return 404 if customer not found
   * 9. Return 409 if customer is not in 'banned' status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":customerId/unban")
  public async unban(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCustomer> {
    try {
      return await postEcommerceMallAdminCustomersCustomerIdUnban({
        admin,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
