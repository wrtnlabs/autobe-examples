import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomer } from "../../../../api/structures/IEcommerceMallCustomer";
import { postEcommerceMallAuthCustomerJoin } from "../../../../providers/postEcommerceMallAuthCustomerJoin";
import { postEcommerceMallAuthCustomerRefresh } from "../../../../providers/postEcommerceMallAuthCustomerRefresh";

@Controller("/ecommerceMall/auth/customer")
export class EcommercemallAuthCustomerController {
  /**
   * This endpoint registers a new customer account in the e-commerce shopping mall platform. The operation accepts email and password as mandatory credentials, with optional displayName and phoneNumber for profile personalization.
   *
   * The email address must be unique across all customer accounts and follow valid email format standards. Upon successful registration, the system creates a new customer record with the provided information, storing the password as a bcrypt-hashed value for security. The account is initialized with 'active' status, enabling immediate access to customer features.
   *
   * Password requirements include minimum length of 8 characters with a mix of uppercase, lowercase, numbers, and special characters. The system enforces these requirements during registration to ensure account security. Invalid or weak passwords will be rejected with appropriate error messages.
   *
   * Upon successful registration, the endpoint returns authentication tokens (access token and refresh token) along with basic customer information. The access token is used for subsequent authenticated API calls, while the refresh token enables token renewal without requiring re-authentication. Customer accounts can later be managed through profile editing and password change operations.
   *
   * This operation is publicly accessible without authentication, as it serves new user registration. However, rate limiting applies to prevent abuse and automated account creation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration information for creating a new customer account, including email, password, and optional profile fields.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Validate email format (RFC 5322) and uniqueness in database. 2. Hash password using bcrypt with cost factor 12. 3. Insert new customer record with email, hashed password, displayName (if provided), phoneNumber (if provided), accountStatus='active'. 4. Generate JWT access token (15min expiry) and refresh token (7day expiry). 5. Create customer session record with tokens. 6. Return authorized response with tokens and customer info. Error cases: duplicate email (409), invalid email format (400), weak password (400).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallCustomer.IJoin,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint renews authentication tokens using a valid refresh token. When a customer's access token expires (after 15 minutes), they can use their refresh token to obtain a new access token without re-entering credentials.
   *
   * The operation validates the refresh token's signature and checks for expiration. It then locates the associated customer session and verifies that the customer account remains in 'active' status. If the account has been suspended or banned since the refresh token was issued, the request is rejected.
   *
   * For enhanced security, the system implements refresh token rotation: each successful refresh generates a new refresh token, invalidating the previous one. This prevents replay attacks where stolen refresh tokens could be reused. If a refresh token is used after it has already been rotated (indicating potential token theft), all tokens in that session are invalidated and the account may be flagged for review.
   *
   * Upon successful token renewal, the endpoint returns a new access token (valid for 15 minutes) and a new refresh token (valid for 7 days). The new refresh token must be stored and used for subsequent refresh operations. The old refresh token becomes invalid immediately.
   *
   * This operation requires a valid refresh token but does not require an access token. The refresh token is sent in the request body or Authorization header. Rate limiting applies to prevent abuse of the token refresh mechanism.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for renewing authentication without re-entering credentials.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Validate refresh token format and signature. 2. Find corresponding customer session by refresh token. 3. Verify session is not expired and customer account is still active. 4. Generate new JWT access token (15min expiry) and optionally new refresh token (rotation). 5. Update session record with new tokens. 6. Return authorized response. Error cases: invalid token (401), expired token (401), session not found (401), account suspended/banned (403). Implement refresh token rotation for security.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallCustomer.IRefresh,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
