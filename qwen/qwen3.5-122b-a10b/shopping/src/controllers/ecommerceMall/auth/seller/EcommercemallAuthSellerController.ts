import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSeller } from "../../../../api/structures/IEcommerceMallSeller";
import { postEcommerceMallAuthSellerJoin } from "../../../../providers/postEcommerceMallAuthSellerJoin";
import { postEcommerceMallAuthSellerRefresh } from "../../../../providers/postEcommerceMallAuthSellerRefresh";

@Controller("/ecommerceMall/auth/seller")
export class EcommercemallAuthSellerController {
  /**
   * Register a new seller account for the e-commerce mall platform. This operation creates a seller account with email/password authentication credentials and initial shop profile information including shop name and optional description.
   *
   * The seller account is created with approval_status set to 'pending', requiring administrator review before the seller can create products and process orders. The account_status is initialized to 'active', allowing the seller to login immediately after registration while awaiting approval.
   *
   * Email validation ensures uniqueness across all seller accounts in the ecommerce_mall_sellers table. Password is hashed using bcrypt with cost factor 10 for secure storage in the password_hash field. The shop_name field is required and must be unique, while shop_description is optional text describing the seller's business.
   *
   * Upon successful registration, the system creates an initial session record in ecommerce_mall_seller_sessions containing JWT access_token and refresh_token. The access_token is short-lived (15 minutes) for API authorization, while the refresh_token is long-lived (7 days) for session renewal. Session metadata includes client IP address, origin URL, and HTTP referrer for security auditing.
   *
   * Related operations: After registration, sellers should check their approval_status via profile endpoint. Once approved by administrator, sellers can create products and manage orders.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration information including email, password, and shop profile details.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Create new seller account with email/password credentials and shop profile. Service layer validates email uniqueness against ecommerce_mall_sellers table, hashes password using bcrypt with cost factor 10, sets approval_status to 'pending', account_status to 'active'. Transaction creates seller record and returns authorization tokens. Email verification optional based on business requirements. Password must meet security requirements: minimum 8 characters, uppercase, lowercase, number, special character. Shop name required, shop description optional. On success, create initial session in ecommerce_mall_seller_sessions with access_token and refresh_token.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSeller.IJoin,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew JWT access token using a valid refresh token. This operation extends the seller's authenticated session without requiring re-entry of credentials.
   *
   * The refresh process queries the ecommerce_mall_seller_sessions table by the provided refresh_token and validates that the session exists and has not expired (expired_at timestamp is in the future). The operation verifies that the associated seller account in ecommerce_mall_sellers exists, has account_status 'active', and has not been deleted (deleted_at is null).
   *
   * Upon successful validation, the system generates a new access_token and refresh_token pair. The session record is updated with the new tokens and the expired_at timestamp is extended based on the refresh token TTL policy (7 days). This implements refresh token rotation for enhanced security - the old tokens are immediately invalidated, preventing reuse if compromised.
   *
   * The response includes the new access_token and refresh_token. The client must replace both tokens in local storage. The new access_token should be included in the Authorization header for subsequent API requests.
   *
   * If the refresh token is invalid, expired, or the associated account is suspended/banned/deleted, the operation returns 401 Unauthorized, requiring the seller to re-authenticate via the login endpoint.
   *
   * Related operations: Use login endpoint to authenticate with credentials. Access token expiration triggers automatic refresh token usage by client SDKs.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for session renewal.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Renew JWT access token using valid refresh token. Service layer queries ecommerce_mall_seller_sessions by refresh_token, validates session exists and expired_at is in the future. Verifies associated seller account exists, account_status is 'active', and deleted_at is null. Generates new access_token and refresh_token pair, updates session record with new tokens and updated expired_at timestamp. Returns new tokens to client. Old tokens are immediately invalidated (refresh token rotation for security). On failure (invalid/expired refresh token, suspended/deleted account), returns 401 error requiring re-login.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallSeller.IRefresh,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
