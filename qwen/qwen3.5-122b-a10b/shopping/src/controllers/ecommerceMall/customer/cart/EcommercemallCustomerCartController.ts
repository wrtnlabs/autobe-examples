import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCartItem } from "../../../../api/structures/IEcommerceMallCartItem";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerCart } from "../../../../providers/getEcommerceMallCustomerCart";

@Controller("/ecommerceMall/customer/cart")
export class EcommercemallCustomerCartController {
  /**
   * Retrieve the shopping cart contents for the authenticated customer.
   *
   * This operation displays all items currently in the customer's shopping cart, including detailed product information, variant options, pricing, quantities, and calculated subtotals. The cart view provides a comprehensive summary of items selected for potential purchase.
   *
   * Each cart item includes the product name from the parent product record, variant option values (such as color, size, material) from the normalized variant options table, unit price (either variant-specific override or product base price), quantity, and line subtotal. The response also includes the overall cart total calculated as the sum of all item subtotals.
   *
   * Availability status is indicated for each item, showing whether the variant is still in stock and not deleted by the seller. Items marked as unavailable due to stock depletion or product deletion are displayed but cannot be included in checkout. The system automatically removes cart items when their associated variants are deleted by sellers.
   *
   * Cart items persist across customer sessions and are associated with the customer account rather than browser sessions. Items remain in the cart until removed by the customer or used in a successful order placement. The response includes timestamps indicating when each item was added and last updated.
   *
   * Related operations: PATCH /cart/items for adding items, PUT /cart/items/{itemId} for updating quantities, DELETE /cart/items/{itemId} for removing items.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Retrieve all cart items for the authenticated customer from ecommerce_mall_cart_items table. Join with ecommerce_mall_product_variants to get variant details including SKU code and price override. Join with ecommerce_mall_products to get product name and base price. Join with ecommerce_mall_product_variant_options to get option values (color, size, etc.). Filter by customer_id from authenticated session. Exclude soft-deleted cart items (deleted_at is null). Calculate line subtotal as quantity multiplied by unit price (variant price or product base price). Calculate cart total as sum of all line subtotals. Include is_available flag to indicate stock/deletion status. Return enriched cart items with product name, variant options, pricing information, and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IEcommerceMallCartItem> {
    try {
      return await getEcommerceMallCustomerCart({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
