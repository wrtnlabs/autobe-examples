import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCustomerSession } from "../../../../api/structures/IEcommerceMallCustomerSession";
import { IPageIEcommerceMallCustomerSession } from "../../../../api/structures/IPageIEcommerceMallCustomerSession";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerSessionsSessionId } from "../../../../providers/getEcommerceMallCustomerSessionsSessionId";
import { patchEcommerceMallCustomerSessions } from "../../../../providers/patchEcommerceMallCustomerSessions";

@Controller("/ecommerceMall/customer/sessions")
export class EcommercemallCustomerSessionsController {
  /**
   * Retrieve a filtered and paginated list of active authentication sessions for the authenticated user.
   *
   * This operation provides session management capabilities allowing users to view their current and recent authentication sessions across multiple devices. Each session record contains connection metadata including IP address, client URL, and referrer information for security auditing purposes.
   *
   * The operation supports comprehensive filtering by session status (active vs expired), date ranges, and connection metadata. Results are paginated to handle large numbers of concurrent sessions efficiently.
   *
   * Security: Users can only view their own sessions. The system enforces strict ownership validation based on the authenticated user's identity and type (customer, seller, or admin). Sensitive token information (access tokens, refresh tokens) is never exposed in the response.
   *
   * Related operations:
   * - DELETE /sessions/{sessionId}: Terminate an individual active session
   * - DELETE /sessions: Terminate all active sessions except the current one
   *
   * @param connection
   * @param body Search criteria and pagination parameters for session list retrieval
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query sessions table based on authenticated user type (customer/seller/admin). Apply pagination with cursor or offset-based pagination. Filter by session status (active/expired). Include connection metadata (ip, href, referrer) and timestamps. Return session summaries without exposing sensitive tokens (access_token, refresh_token). Implement security checks to ensure user can only view their own sessions. Support sorting by created_at (newest first).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCustomerSession.IRequest,
  ): Promise<IPageIEcommerceMallCustomerSession.ISummary> {
    try {
      return await patchEcommerceMallCustomerSessions({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific JWT authentication session.
   *
   * This endpoint provides comprehensive session details for the authenticated user, including connection metadata such as IP address, page href, and referrer URL. Sessions are created upon successful authentication and tracked for security auditing purposes.
   *
   * The operation validates that the requested session belongs to the currently authenticated user, ensuring data isolation and privacy. Users can only access their own session records and cannot view sessions belonging to other users.
   *
   * Session information includes creation timestamp, expiration timestamp for security compliance, and connection context metadata. Expired sessions or sessions that have been terminated (soft-deleted for admin sessions) will not be returned.
   *
   * Related operations:
   * - PATCH /sessions - List all active sessions for the authenticated user
   * - DELETE /sessions/{sessionId} - Terminate a specific session
   * - DELETE /sessions - Terminate all sessions except the current one
   *
   * @param connection
   * @param sessionId Unique identifier of the session to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the appropriate session table (customer_sessions, seller_sessions, or admin_sessions) based on the authenticated user's actor type. Validate that the session belongs to the authenticated user by checking the foreign key (ecommerce_mall_customer_id, ecommerce_mall_sellers_id, or ecommerce_mall_admin_id). Verify session has not expired (expired_at > current time) and is not soft-deleted (deleted_at IS NULL for admin sessions). Return session details including id, creation timestamp, expiration timestamp, IP address, href, and referrer. Return 404 if session not found, does not belong to user, or is expired/deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCustomerSession> {
    try {
      return await getEcommerceMallCustomerSessionsSessionId({
        customer,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
