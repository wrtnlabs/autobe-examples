import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIEcommerceMallReviewSnapshot } from "../../../../../../api/structures/IPageIEcommerceMallReviewSnapshot";
import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerReviewsMySnapshots } from "../../../../../../providers/getEcommerceMallCustomerReviewsMySnapshots";

@Controller("/ecommerceMall/customer/reviews/my/snapshots")
export class EcommercemallCustomerReviewsMySnapshotsController {
  /**
   * Retrieve all review snapshots for the authenticated customer's own reviews.
   *
   * This operation provides customers with complete visibility into their review editing history, showing every modification made to their reviews including rating changes, content edits, and deletion events. Each snapshot captures the complete state of a review before and after modification.
   *
   * Snapshots are immutable audit trail records created automatically whenever a customer edits their review. They include the previous rating and content, the new rating and content, the timestamp of the change, and confirmation that the customer made the modification.
   *
   * This endpoint returns snapshots in reverse chronological order (newest first) with cursor-based pagination for efficient loading of large review histories.
   *
   * **Security**: Only the customer who authored the review can view its snapshots. Administrators have separate endpoints for platform-wide snapshot access.
   *
   * **Related Operations**:
   * - `GET /reviews/my` - List the customer's own reviews
   * - `PATCH /reviews/{reviewId}` - Edit a review (automatically creates a snapshot)
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_review_snapshots table joining with ecommerce_mall_reviews to filter snapshots where changed_by_customer_id equals authenticated customer ID. Apply cursor-based pagination with configurable page size (default 20, max 100). Sort by created_at descending (newest first). Include review context (product_id, rating, content) from joined reviews table for each snapshot. Validate customer owns the review before returning each snapshot. Return IPageIEcommerceMallReviewSnapshot.ISummary with pagination metadata and snapshot summary data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IPageIEcommerceMallReviewSnapshot.ISummary> {
    try {
      return await getEcommerceMallCustomerReviewsMySnapshots({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
