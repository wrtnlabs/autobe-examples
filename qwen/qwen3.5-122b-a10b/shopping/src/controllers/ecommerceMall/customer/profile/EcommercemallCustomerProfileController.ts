import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomer } from "../../../../api/structures/IEcommerceMallCustomer";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerProfile } from "../../../../providers/getEcommerceMallCustomerProfile";
import { putEcommerceMallCustomerProfile } from "../../../../providers/putEcommerceMallCustomerProfile";

@Controller("/ecommerceMall/customer/profile")
export class EcommercemallCustomerProfileController {
  /**
   * Retrieve the authenticated customer's profile information from the ecommerce_mall_customers table.
   *
   * This operation provides customers with access to their own profile data including display name, phone number, account status, and account timestamps. The customer identity is determined through the authenticated session token, ensuring that each customer can only access their own profile information.
   *
   * The response includes optional fields (display_name, phone_number) that customers may have provided during profile setup or subsequent edits. The account_status field reflects the current account state (active, suspended, or banned) which controls platform access. Timestamps (created_at, updated_at) provide audit trail information for account lifecycle tracking.
   *
   * This operation respects the soft deletion policy defined in the ecommerce_mall_customers schema. Accounts marked as deleted (deleted_at is not null) are not accessible through this endpoint. For customers who need to update their profile information, the corresponding update operation should be used after retrieving current values.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Retrieve the authenticated customer's profile information from ecommerce_mall_customers table. Extract the customer ID from the authenticated session token, query the database for the customer record, and return display_name and phone_number fields. Verify the customer account is not deleted (deleted_at is null). Return 404 if customer not found or deleted. Include created_at and updated_at timestamps for reference.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IEcommerceMallCustomer> {
    try {
      return await getEcommerceMallCustomerProfile({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated customer's profile information including display name and phone number.
   *
   * This operation allows customers to modify their personal profile information that appears in reviews, order history, and other public-facing areas of the platform. The display name is used for public identification, while the phone number is used for order notifications and account verification.
   *
   * Each profile update automatically creates an immutable snapshot record that captures the previous state of the profile before the change. This audit trail is maintained for compliance and dispute resolution purposes. Snapshots cannot be modified or deleted once created.
   *
   * The operation requires the customer to be authenticated via a valid session token. Only the authenticated customer can update their own profile; customers cannot modify other users' profiles.
   *
   * Related operations include GET /profile for viewing current profile information and POST /profile/snapshots for viewing the audit history of profile changes.
   *
   * @param connection
   * @param body Profile update information for display name and phone number
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update customer profile fields (display_name, phone_number) for the authenticated customer. Implementation steps: 1) Extract customer ID from authentication token/session, 2) Validate request body fields against schema constraints, 3) Begin database transaction, 4) Create snapshot record capturing previous profile state (before values), 5) Update customer record with new values, 6) Record snapshot with current values after update, 7) Commit transaction, 8) Return updated customer entity. Validation: display_name can be null but if provided must be non-empty string, phone_number can be null but if provided must match phone format. Snapshot type is 'customer' with changedBy referencing the customer ID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCustomer.IUpdate,
  ): Promise<IEcommerceMallCustomer> {
    try {
      return await putEcommerceMallCustomerProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
