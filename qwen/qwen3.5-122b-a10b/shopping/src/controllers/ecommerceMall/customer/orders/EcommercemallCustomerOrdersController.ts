import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrder } from "../../../../api/structures/IEcommerceMallOrder";
import { IPageIEcommerceMallOrder } from "../../../../api/structures/IPageIEcommerceMallOrder";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerOrdersOrderId } from "../../../../providers/getEcommerceMallCustomerOrdersOrderId";
import { patchEcommerceMallCustomerOrders } from "../../../../providers/patchEcommerceMallCustomerOrders";
import { postEcommerceMallCustomerOrders } from "../../../../providers/postEcommerceMallCustomerOrders";

@Controller("/ecommerceMall/customer/orders")
export class EcommercemallCustomerOrdersController {
  /**
   * Create a new order from the customer's shopping cart items.
   *
   * This operation processes the customer's shopping cart, validates item availability, creates an order record with embedded shipping address information, and generates individual order items for each product variant in the cart. The operation automatically reduces stock quantities and creates inventory records for audit purposes.
   *
   * The shipping address is captured at order creation time and embedded directly in the order record. This ensures the address remains immutable even if the customer later modifies their saved addresses. All shipping address fields (recipient name, phone number, street address, city, state, postal code, country) are stored as part of the order.
   *
   * Upon successful order creation, the system generates a unique order number that can be used for tracking and reference. The order status is initially set to 'paid' and will be derived from the status of individual order items as they progress through the fulfillment workflow.
   *
   * After order placement, all cart items used in the order are automatically removed from the customer's shopping cart. The customer can view their order history and track order status through subsequent API operations.
   *
   * Stock quantities are reduced immediately upon order creation to prevent overselling. Inventory records are automatically created with negative quantity changes to maintain a complete audit trail of stock movements.
   *
   * This operation requires customer authentication. Only authenticated customers can place orders, and the order will be associated with their customer account.
   *
   * @param connection
   * @param body Order creation request including shipping address selection (by address ID or inline address data) and cart item processing instructions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Validate customer authentication and account status (must be active). 2. Retrieve customer's cart items from ecommerce_mall_cart_items where customer_id matches and deleted_at is null. 3. Validate all cart items have is_available=true and product variants exist with sufficient stock_quantity. 4. Validate customer has at least one saved address or shipping address is provided in request. 5. Calculate total_price from cart items (quantity * variant.price or product.base_price). 6. Begin database transaction. 7. Create ecommerce_mall_orders record with order_number (generate unique), shipping address fields from selected address, total_price, status='paid', customer_id. 8. For each cart item: create ecommerce_mall_order_items record with order_id, product_variant_id, quantity, unit_price, status='paid'. 9. For each order item: create ecommerce_mall_inventory_records with quantityChange=-quantity, reason='order_placed', currentStock=calculated. 10. Delete all cart items used in order from ecommerce_mall_cart_items. 11. Commit transaction. 12. Return created order with all order items. Edge cases: handle concurrent cart modifications with optimistic locking, handle payment gateway failures by rolling back inventory changes, handle stock depletion between cart add and checkout.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallOrder.ICreate,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await postEcommerceMallCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of shopping orders for the authenticated customer or all orders for administrators.
   *
   * This operation provides comprehensive order history viewing capabilities with advanced filtering options. Customers can view their own orders with filters for order status, date ranges, and order number search. Administrators can view all platform orders with the same filtering capabilities for oversight and dispute resolution.
   *
   * The response includes order summaries optimized for list displays, containing essential information such as order number, current status, total price, and creation timestamp. For detailed order information including all items and shipping address, use the GET /orders/{orderId} endpoint.
   *
   * Pagination is implemented using cursor-based navigation for efficient large dataset handling. The response includes pagination metadata with cursors for navigating to previous and next pages.
   *
   * Order status is derived from individual order item statuses and can be: paid, shipped, delivered, cancelled, refunded, or partiallyCompleted. Status filtering allows customers to quickly find orders in specific lifecycle stages.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for order list retrieval
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_orders table with authorization filtering. For customer actor: add WHERE ecommerce_mall_customer_id = authenticatedCustomerId clause. For admin actor: no customer filter, returns all orders. Apply search filters from request body: status (enum filter), orderNumber (partial match), date range (created_at between startDate and endDate). Implement cursor-based pagination using created_at and id as cursor keys. Join with ecommerce_mall_order_items for item count if requested. Return summary fields only (id, orderNumber, status, totalPrice, createdAt, itemCount). Sort by created_at DESC, id DESC for consistent ordering. Validate status values against allowed enum. Handle empty result sets gracefully.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallOrder.IRequest,
  ): Promise<IPageIEcommerceMallOrder.ISummary> {
    try {
      return await patchEcommerceMallCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete details of a specific order including all purchased items, embedded shipping address snapshot, and associated shipments.
   *
   * This operation provides comprehensive order information for customers to review their purchase details, track shipments, and verify order contents. Administrators can also access this endpoint for platform oversight and dispute resolution purposes.
   *
   * The response includes the order's unique order number, creation timestamp, total price, and overall status derived from individual order item statuses. The shipping address is captured as a snapshot at the time of order placement and remains immutable even if the customer later modifies their saved addresses.
   *
   * Each order item displays the purchased product variant, quantity, unit price at time of purchase, and current status (paid, shipped, delivered, cancelled, or refunded). Items from different sellers are grouped by their respective shipments, each with tracking information and delivery status.
   *
   * For orders containing multiple items, the overall order status is derived from the individual item statuses. An order is considered 'paid' when all items are paid, 'shipped' when all items are shipped, 'delivered' when all items are delivered, and 'partiallyCompleted' when items have mixed statuses.
   *
   * Related operations include `PATCH /orders` for retrieving paginated order history and `GET /orders/{orderId}/items` for retrieving order items separately.
   *
   * @param connection
   * @param orderId Target order's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_mall_orders table by orderId (UUID primary key). Verify authorization: customer must own the order (ecommerce_mall_customer_id matches authenticated customer) OR user must be admin. Include soft-deleted orders only for admin access.
   *
   * Join with ecommerce_mall_order_items table to retrieve all order items for this order. For each order item, join with ecommerce_mall_product_variants to get variant details including SKU code and option values, and join with ecommerce_mall_products to get product name and main image.
   *
   * Join with ecommerce_mall_shipments table to retrieve all shipments associated with this order. For each shipment, include tracking number, carrier name, shipped timestamp, and optional delivered timestamp. Map order items to their respective shipments.
   *
   * Calculate average product ratings by querying ecommerce_mall_reviews for each product in the order items. Return null if no reviews exist.
   *
   * Apply optimistic locking if concurrent modifications are possible. Return 404 if order not found or user lacks authorization. Return 403 if customer tries to access another customer's order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await getEcommerceMallCustomerOrdersOrderId({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
