import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrderItem } from "../../../../../api/structures/IEcommerceMallOrderItem";
import { IPageIEcommerceMallOrderItem } from "../../../../../api/structures/IPageIEcommerceMallOrderItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerOrdersOrderIdItemsItemId } from "../../../../../providers/getEcommerceMallCustomerOrdersOrderIdItemsItemId";
import { patchEcommerceMallCustomerOrdersOrderIdItems } from "../../../../../providers/patchEcommerceMallCustomerOrdersOrderIdItems";

@Controller("/ecommerceMall/customer/orders/:orderId/items")
export class EcommercemallCustomerOrdersItemsController {
  /**
   * Retrieve a filtered and paginated list of order items belonging to a specific order.
   *
   * This operation provides access to all purchased product variants within an order, including their quantities, unit prices at time of purchase, current status, and associated product information. Each order item represents an independent purchase with its own status lifecycle that can be cancelled or refunded separately from other items in the same order.
   *
   * Customers can view their own order items to track purchase details and current status. Administrators have oversight access to view any order's items for dispute resolution and policy enforcement. The response includes product names and variant option values to provide complete context without requiring additional API calls.
   *
   * Supports filtering by order item status (paid, shipped, delivered, cancelled, refunded) and pagination with configurable page sizes. Results are sorted by creation date descending (newest items first). The unit price is immutable and reflects the price at time of purchase, preserved in order item snapshots for audit purposes.
   *
   * @param connection
   * @param orderId Target order's unique identifier (UUID scope)
   * @param body Search criteria and pagination parameters for filtering order items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_order_items table filtering by ecommerce_mall_order_id. Apply pagination with cursor-based navigation. Support filtering by status field (paid, shipped, delivered, cancelled, refunded). Sort by created_at descending (newest first). Join with ecommerce_mall_products and ecommerce_mall_product_variants to include product name and variant options in response. Enforce ownership validation: customers can only access their own orders, administrators can access all orders. Return summary-level data optimized for list display including id, quantity, unit_price, status, product name, variant options, and created_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallOrderItem.IRequest,
  ): Promise<IPageIEcommerceMallOrderItem.ISummary> {
    try {
      return await patchEcommerceMallCustomerOrdersOrderIdItems({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order item within an order.
   *
   * This operation returns the complete details of a purchased product variant within a customer's order, including quantity, unit price at time of purchase, current status, and product variant reference. The order item represents an individual purchased item that can have independent status tracking for cancellation and refund workflows.
   *
   * **Access Control:**
   *
   * - **Customers**: Can only access order items belonging to their own orders
   * - **Sellers**: Can access order items for products they sell (across all orders)
   * - **Administrators**: Can access any order item for platform oversight and dispute resolution
   *
   * **Order Item Status:**
   *
   * The status field indicates the current lifecycle state of the order item:
   * - `paid`: Payment completed, awaiting shipment
   * - `shipped`: Seller has shipped the item
   * - `delivered`: Customer has received the item
   * - `cancelled`: Item was cancelled (by customer, seller, or administrator)
   * - `refunded`: Item was refunded after delivery
   *
   * **Related Operations:**
   *
   * - `GET /orders/{orderId}`: Retrieve the parent order details
   * - `PATCH /orders/{orderId}/items`: List all items within an order
   * - `POST /order-items/{itemId}/cancellation-requests`: Request cancellation for eligible items
   * - `POST /order-items/{itemId}/refund-requests`: Request refund for delivered items
   * - `GET /order-item-snapshots`: View historical snapshots of this order item
   *
   * **Data Preservation:**
   *
   * The unit price is immutable after order creation and represents the price at time of purchase. This value is preserved in order item snapshots for dispute resolution and audit purposes. The product variant reference allows retrieval of current product information, though the snapshot preserves the variant state at purchase time.
   *
   * @param connection
   * @param orderId Parent order's unique identifier (UUID format)
   * @param itemId Target order item's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_mall_order_items table by id and verify ownership/authorization.
   *
   * 1. Validate both orderId and itemId are valid UUIDs
   * 2. Query order_items table WHERE id = itemId AND ecommerce_mall_order_id = orderId
   * 3. If no record found, return 404 Not Found
   * 4. Verify authorization:
   *    - Get the order's ecommerce_mall_customer_id
   *    - If user is customer: verify user.id == order.ecommerce_mall_customer_id
   *    - If user is seller: verify product_variant.ecommerce_mall_product_id belongs to seller
   *    - If user is admin: allow access
   * 5. If unauthorized, return 403 Forbidden
   * 6. Return the order item with all fields: id, ecommerce_mall_order_id, ecommerce_mall_product_variant_id, quantity, unit_price, status, created_at, updated_at
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrderItem> {
    try {
      return await getEcommerceMallCustomerOrdersOrderIdItemsItemId({
        customer,
        orderId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
