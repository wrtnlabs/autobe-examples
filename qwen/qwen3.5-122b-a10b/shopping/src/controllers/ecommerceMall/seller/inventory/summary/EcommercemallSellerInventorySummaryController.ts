import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallInventoryRecord } from "../../../../../api/structures/IEcommerceMallInventoryRecord";
import { IPageIEcommerceMallInventoryRecord } from "../../../../../api/structures/IPageIEcommerceMallInventoryRecord";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerInventorySummary } from "../../../../../providers/patchEcommerceMallSellerInventorySummary";

@Controller("/ecommerceMall/seller/inventory/summary")
export class EcommercemallSellerInventorySummaryController {
  /**
   * Retrieve a paginated list of inventory record summaries for the authenticated seller's product variants.
   *
   * This operation provides sellers with visibility into all inventory movements for their products, including restocking operations, order deductions, cancellation/refund restorations, and manual adjustments. Each inventory record captures the quantity change amount, reason for the change, timestamp, and the current stock level after the change was applied.
   *
   * Inventory records are automatically created by the system for various operations:
   * - Seller-initiated restocking (positive quantity changes)
   * - Seller-initiated stock adjustments for loss or correction (negative quantity changes)
   * - Order placement (automatic negative changes)
   * - Order cancellation approvals (automatic positive changes to restore stock)
   * - Order refund approvals (automatic positive changes to restore stock)
   *
   * The response includes inventory record details along with associated variant information (SKU code) and product name for context. Records are ordered by timestamp in descending order (newest first) to show the most recent inventory movements.
   *
   * Sellers can only view inventory records for their own product variants. Administrators have access to all inventory records across the platform.
   *
   * Related operations:
   * - `GET /variants/{variantId}/inventory` - View detailed inventory history for a specific variant
   * - `PATCH /variants/{variantId}/inventory` - Add or adjust inventory for a variant
   *
   * @param connection
   * @param body Search criteria and pagination parameters for inventory records
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query inventory_records table joined with product_variants, products, and sellers to filter by authenticated seller ownership. Apply pagination with configurable page size and cursor/offset. Support optional filtering by product_id or variant_id. Order results by recorded_at DESC. Validate seller authentication and ownership of variants. Return inventory summary including record_id, variant_sku_code, product_name, quantity_change, reason, recorded_at, current_stock. Implement cursor-based pagination for large result sets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallInventoryRecord.IRequest,
  ): Promise<IPageIEcommerceMallInventoryRecord.ISummary> {
    try {
      return await patchEcommerceMallSellerInventorySummary({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
