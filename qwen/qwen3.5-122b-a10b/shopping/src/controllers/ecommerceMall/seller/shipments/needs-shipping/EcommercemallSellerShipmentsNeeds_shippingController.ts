import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallOrderItem } from "../../../../../api/structures/IEcommerceMallOrderItem";
import { IPageIEcommerceMallOrderItem } from "../../../../../api/structures/IPageIEcommerceMallOrderItem";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerShipmentsNeedsShipping } from "../../../../../providers/patchEcommerceMallSellerShipmentsNeedsShipping";

@Controller("/ecommerceMall/seller/shipments/needs-shipping")
export class EcommercemallSellerShipmentsNeeds_shippingController {
  /**
   * Retrieve a filtered and paginated list of order items that require shipping from the authenticated seller's products.
   *
   * This endpoint provides sellers with visibility into all order items with 'paid' status that belong to their products and need to be shipped. The operation supports filtering by order date range and includes comprehensive pagination support for managing large volumes of orders.
   *
   * Each order item in the response includes essential information for shipment processing: order number, product variant details, quantity, unit price at time of purchase, and order creation date. This enables sellers to efficiently batch shipments and track fulfillment progress.
   *
   * **Security Considerations**:
   *
   * Only authenticated sellers can access this endpoint. The system automatically filters results to show only order items for products owned by the authenticated seller, ensuring data isolation between different sellers on the platform.
   *
   * **Related Operations**:
   *
   * - `POST /shipments` - Create a shipment from selected order items
   * - `GET /orders/{orderId}` - View detailed order information including all items
   * - `PATCH /orders` - View customer order history with pagination
   *
   * **Expected Behavior**:
   *
   * The endpoint returns an empty list if the seller has no order items with 'paid' status. Order items are sorted by creation date in descending order (newest first) by default.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering order items needing shipping
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_order_items table joined with ecommerce_mall_orders and ecommerce_mall_products to filter order items by seller ownership and 'paid' status.
   *
   * 1. Extract seller_id from authenticated session context
   * 2. Join order_items with orders to get ecommerce_mall_order_id
   * 3. Join orders with products to verify seller ownership (ecommerce_mall_orders.ecommerce_mall_customer_id -> ecommerce_mall_products.seller_id)
   * 4. Filter where order_items.status = 'paid'
   * 5. Filter where products.seller_id = authenticated seller_id
   * 6. Apply optional date range filter on order_items.created_at
   * 7. Apply pagination with cursor or offset-based pagination
   * 8. Return paginated results with order item summaries including order number, product info, quantity, unit price, and order date
   *
   * Business rules:
   * - Only sellers can access this endpoint
   * - Sellers only see order items for products they own
   * - Order items must have status 'paid' (not shipped, delivered, cancelled, or refunded)
   * - Pagination defaults to 20 items per page, max 100
   * - Sort by created_at descending (newest orders first)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallOrderItem.IRequest,
  ): Promise<IPageIEcommerceMallOrderItem.ISummary> {
    try {
      return await patchEcommerceMallSellerShipmentsNeedsShipping({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
