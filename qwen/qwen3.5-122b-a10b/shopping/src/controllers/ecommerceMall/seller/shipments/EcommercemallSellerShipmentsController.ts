import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipment } from "../../../../api/structures/IEcommerceMallShipment";
import { IPageIEcommerceMallShipment } from "../../../../api/structures/IPageIEcommerceMallShipment";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerShipmentsShipmentId } from "../../../../providers/getEcommerceMallSellerShipmentsShipmentId";
import { patchEcommerceMallSellerShipments } from "../../../../providers/patchEcommerceMallSellerShipments";
import { postEcommerceMallSellerShipments } from "../../../../providers/postEcommerceMallSellerShipments";

@Controller("/ecommerceMall/seller/shipments")
export class EcommercemallSellerShipmentsController {
  /**
   * Create a new shipment package for order items belonging to the authenticated seller.
   *
   * This operation allows sellers to create shipping packages containing one or more order items from their products. When a shipment is created, all order items included in the shipment will have their status automatically updated to 'shipped', and the shipped timestamp will be recorded. The shipment record uses soft deletion for audit trail preservation.
   *
   * The seller must provide a unique tracking number assigned by the shipping carrier and the carrier name (e.g., FedEx, UPS, DHL). Multiple shipments can be created for the same order if the seller chooses to bundle items differently or ship them separately.
   *
   * **Business Rules**:
   *
   * - Only order items with 'paid' status can be included in a shipment
   * - All order items in the same shipment must belong to the same seller
   * - Order items from different sellers cannot be combined in one shipment
   * - The tracking number must be unique across all shipments on the platform
   * - At least one order item must be included in each shipment
   * - Items from cancelled or refunded orders cannot be shipped
   * - Automatic delivery confirmation occurs after 14 days from shipped_at if customer doesn't confirm manually
   *
   * **Authorization**:
   *
   * - Only authenticated sellers can create shipments
   * - The seller can only include order items from their own products
   * - Sellers cannot view or modify shipments created by other sellers
   *
   * **Related Operations**:
   *
   * - `GET /orders/{orderId}` - View order details including order items to select for shipment
   * - `PATCH /orders/seller/items` - List order items needing shipping for the seller
   * - `GET /shipments/{shipmentId}` - View shipment details after creation
   * - `PUT /shipments/{shipmentId}/delivery` - Confirm delivery for the shipment
   *
   * @param connection
   * @param body Shipment creation information including tracking details and order items to ship
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Authenticate seller and verify seller_id from session
   * 2. Validate request body:
   *    - tracking_number: required, unique string (check against existing shipments)
   *    - carrier_name: required, non-empty string
   *    - shipped_at: required, valid datetime (default to current timestamp if not provided)
   *    - orderItemIds: required, non-empty array of UUIDs
   * 3. For each order item in orderItemIds:
   *    - Fetch order item from database
   *    - Verify order item belongs to seller's products (join order_items -> product_variants -> products -> sellers)
   *    - Verify order item status is 'paid'
   *    - Verify order item is not already shipped, delivered, cancelled, or refunded
   * 4. Create shipment record with seller_id, tracking_number, carrier_name, shipped_at
   * 5. Update all order items in orderItemIds to status 'shipped'
   * 6. Create inventory records for shipped items if needed
   * 7. Return created shipment with full details including included order items
   * 8. Error handling:
   *    - 400 if tracking number already exists
   *    - 400 if no order items provided
   *    - 403 if order items belong to different sellers or not seller's items
   *    - 400 if any order item has invalid status
   *    - 404 if any order item not found
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallShipment.ICreate,
  ): Promise<IEcommerceMallShipment> {
    try {
      return await postEcommerceMallSellerShipments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of shipping shipments with tracking information.
   *
   * This operation provides comprehensive search capabilities for shipments across the platform. Customers can view shipments associated with their orders, sellers can view shipments they created for their products, and administrators have full visibility across all shipments.
   *
   * Search filters include tracking number partial matching, carrier name filtering, seller identification, shipping date ranges, and delivery status (delivered or pending delivery). The response includes shipment summaries with essential tracking details, carrier information, and delivery timestamps.
   *
   * Access control is enforced based on actor type: customers are restricted to shipments from their orders, sellers see only shipments they created, and administrators have platform-wide visibility. The operation supports cursor-based pagination for efficient handling of large result sets.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for shipment filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_shipments table with pagination and filtering support. Apply access control based on actor type: customers can only view shipments associated with their orders, sellers can view shipments they created, administrators can view all shipments. Implement filtering on tracking_number (partial match), carrier_name (exact match), seller_id (exact match), shipped_at date range, delivered_at date range (null for undelivered), and delivery status. Sort by shipped_at descending by default. Join with order_items and orders tables to verify customer access. Return paginated results with cursor-based pagination for large result sets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallShipment.IRequest,
  ): Promise<IPageIEcommerceMallShipment.ISummary> {
    try {
      return await patchEcommerceMallSellerShipments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shipment package.
   *
   * This endpoint provides comprehensive shipment details including tracking information, carrier details, shipping and delivery timestamps, and all order items included in the shipment. The shipment represents a physical package sent by a seller to a customer with complete tracking capabilities.
   *
   * **Authorization**:
   * - **Sellers**: Can view shipments they created (matching seller_id)
   * - **Customers**: Can view shipments containing their order items
   * - **Administrators**: Can view all shipments on the platform
   *
   * **Shipment Information**:
   * - Tracking number and carrier name for shipment tracking
   * - Shipping timestamp when items transitioned to 'shipped' status
   * - Delivery timestamp (manual confirmation or automatic after 14 days)
   * - All order items included in this shipment with their current statuses
   * - Order reference and customer information (for administrators)
   *
   * **Related Operations**:
   * - `GET /orders/{orderId}` - View order details including all associated shipments
   * - `PATCH /shipments` - List shipments with filtering (seller/admin only)
   * - `POST /orders/{orderId}/shipments` - Create new shipment (seller only)
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Retrieve detailed shipment information by shipment ID. Implementation steps:
   *
   * 1. Validate shipmentId format (UUID)
   * 2. Query ecommerce_mall_shipments table with shipmentId
   * 3. Apply authorization checks:
   *    - If user is seller: verify seller_id matches authenticated user
   *    - If user is customer: verify shipment contains order items belonging to user's orders
   *    - If user is admin: allow access
   * 4. Join with order_items table to include shipment items
   * 5. Join with orders table to include order reference
   * 6. Join with customers table for customer information (admin only)
   * 7. Return shipment with all related data
   * 8. Handle 404 if shipment not found
   * 9. Handle 403 if user lacks authorization
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShipment> {
    try {
      return await getEcommerceMallSellerShipmentsShipmentId({
        seller,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
