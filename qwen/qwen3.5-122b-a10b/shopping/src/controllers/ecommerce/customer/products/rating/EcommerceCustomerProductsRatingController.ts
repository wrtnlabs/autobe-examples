import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceProductRating } from "../../../../../api/structures/IEcommerceProductRating";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerProductsProductIdRating } from "../../../../../providers/getEcommerceCustomerProductsProductIdRating";

@Controller("/ecommerce/customer/products/:productId/rating")
export class EcommerceCustomerProductsRatingController {
  /**
   * Retrieve the average rating for a specific product.
   *
   * Returns the calculated average rating from all non-deleted customer reviews for this product. Reviews are excluded from the calculation if they have been soft-deleted by customers. If no non-deleted reviews exist for the product, the average rating will be null.
   *
   * **Rating Calculation**
   *
   * The average is computed as the arithmetic mean of all rating values (1-5 stars) from active reviews. Deleted reviews are completely excluded from both the sum and count used in the calculation.
   *
   * **Product Verification**
   *
   * The endpoint validates that the product exists before returning rating information. A 404 response is returned if the product ID does not correspond to any product in the system.
   *
   * @param connection
   * @param productId Product identifier (UUID scope)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query ecommerce_reviews table to calculate
     *   average rating for the given product. Filter reviews where deleted_at
     *   IS NULL. Calculate AVG(rating) from non-deleted reviews for the
     *   product_id. Return null if no non-deleted reviews exist. Join with
     *   ecommerce_products to verify product exists. Return 404 if product not
     *   found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceProductRating> {
    try {
      return await getEcommerceCustomerProductsProductIdRating({
        customer,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
