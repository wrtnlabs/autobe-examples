import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceDeletionValidationResult } from "../../../../api/structures/IEcommerceDeletionValidationResult";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerDeletionValidation } from "../../../../providers/getEcommerceCustomerDeletionValidation";

@Controller("/ecommerce/customer/deletion-validation")
export class EcommerceCustomerDeletion_validationController {
  /**
   * Validates whether the authenticated user's account can be deleted based on business rules and active resource constraints.
   *
   * This endpoint checks deletion eligibility for customer or seller accounts by examining active orders, pending cancellation requests, and pending refund requests. The validation prevents account deletion when resources would be orphaned or when dispute resolution processes are in progress.
   *
   * **Customer Account Validation**
   *
   * A customer account cannot be deleted if they have any active orders with items in paid, shipped, or delivered status. Order history must be preserved for seller records and legal compliance even after account deletion.
   *
   * **Seller Account Validation**
   *
   * A seller account cannot be deleted if they have:
   * - Any pending orders (items with paid or shipped status) that require fulfillment
   * - Any pending cancellation requests for their order items
   * - Any pending refund requests for their order items
   *
   * These restrictions ensure that ongoing transactions and dispute resolution processes are not disrupted by account deletion.
   *
   * **Response Structure**
   *
   * The response includes a boolean indicating whether deletion is allowed, along with an array of blocking reasons if deletion is not permitted. Each blocking reason specifies the resource type and the constraint preventing deletion.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Implement deletion validation for authenticated
     *   user account based on actor type.
   *
   * **Authorization**
   * - Require valid authentication token (customer or seller)
   * - Extract actor type and ID from authentication context
   *
   * **Validation Logic for Customers**
   * 1. Query ecommerce_orders joined with ecommerce_order_items for the customer
   * 2. Check if any order items exist with status IN ('paid', 'shipped', 'delivered')
   * 3. If active order items exist, deletion is blocked with reason about active orders
   *
   * **Validation Logic for Sellers**
   * 1. Query ecommerce_order_items for the seller with status IN ('paid', 'shipped')
   * 2. Query ecommerce_cancellation_requests joined with ecommerce_order_items for the seller with status = 'pending'
   * 3. Query ecommerce_refund_requests joined with ecommerce_order_items for the seller with status = 'pending'
   * 4. If any pending orders, cancellation requests, or refund requests exist, deletion is blocked
   *
   * **Response Construction**
   * - Return { isDeletable: true } if no blocking constraints found
   * - Return { isDeletable: false, blockingReasons: [...] } with detailed reasons
   * - Each blocking reason includes resourceType, resourceId, and reason text
   *
   * **Error Handling**
   * - 401 Unauthorized if not authenticated
   * - 400 Bad Request if actor type is unrecognized
   * - 500 Internal Server Error on database query failures
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IEcommerceDeletionValidationResult> {
    try {
      return await getEcommerceCustomerDeletionValidation({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
