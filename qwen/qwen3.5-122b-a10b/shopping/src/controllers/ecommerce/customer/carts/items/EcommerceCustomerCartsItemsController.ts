import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceCartItem } from "../../../../../api/structures/IEcommerceCartItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { deleteEcommerceCustomerCartsCartIdItemsItemId } from "../../../../../providers/deleteEcommerceCustomerCartsCartIdItemsItemId";
import { getEcommerceCustomerCartsCartIdItemsItemId } from "../../../../../providers/getEcommerceCustomerCartsCartIdItemsItemId";
import { patchEcommerceCustomerCartsCartIdItems } from "../../../../../providers/patchEcommerceCustomerCartsCartIdItems";
import { postEcommerceCustomerCartsCartIdItems } from "../../../../../providers/postEcommerceCustomerCartsCartIdItems";
import { putEcommerceCustomerCartsCartIdItemsItemId } from "../../../../../providers/putEcommerceCustomerCartsCartIdItemsItemId";

@Controller("/ecommerce/customer/carts/:cartId/items")
export class EcommerceCustomerCartsItemsController {
  /**
   * Add a product variant to the customer's shopping cart with specified quantity.
   *
   * This operation creates a new cart item entry or increments the quantity if the variant already exists in the cart. The system validates product availability, stock levels, and cart ownership before processing.
   *
   * ## Business Rules
   *
   * - Out of stock variants cannot be added to the cart
   * - Each product variant can appear only once per cart (quantity increments on duplicate adds)
   * - Cart must belong to the authenticated customer
   * - Quantity must be a positive integer (minimum 1)
   * - Deleted products or variants are rejected
   *
   * ## Error Handling
   *
   * Returns 404 if cart or product variant not found. Returns 400 if variant is out of stock or already soft-deleted. Returns 403 if cart does not belong to authenticated customer.
   *
   * @param connection
   * @param cartId Unique identifier of the shopping cart (UUID scope)
   * @param body Request body containing the product variant ID and quantity to add to the cart.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Create a new cart item in the specified
     *   customer's cart. Validate that the cart exists and belongs to the
     *   authenticated customer. Verify the product variant exists, is not
     *   deleted, and has available stock (stock quantity > 0). Check if the
     *   variant already exists in the cart - if yes, increment quantity instead
     *   of creating duplicate. If no, create new cart item. Enforce quantity
     *   must be positive integer. Return the created/updated cart item with
     *   current stock availability status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceCartItem.ICreate,
  ): Promise<IEcommerceCartItem> {
    try {
      return await postEcommerceCustomerCartsCartIdItems({
        customer,
        cartId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates quantities of items in a customer's shopping cart or removes items by setting quantity to zero.
   *
   * This operation allows customers to modify the quantities of product variants already in their cart. Each cart item update specifies a product variant ID and the desired quantity. If the quantity is set to zero or less, the item is removed from the cart via soft deletion.
   *
   * The operation validates that each product variant exists, is not out of stock, and belongs to an active product. If a variant becomes unavailable after being added to the cart, it is marked as unavailable but remains until explicitly removed or the quantity is changed to zero.
   *
   * Cart items are automatically removed when their referenced product is deleted by a seller. When a variant is deleted, the cart item is marked as unavailable but retained for customer review.
   *
   * @param connection
   * @param cartId The unique identifier of the shopping cart to update (UUID format).
   * @param body Array of cart item updates, each specifying a product variant ID and the desired quantity. Variants with zero or negative quantity will be removed from the cart.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the ecommerce_cart_items table for the
     *   specified cart ID. For each cart item update in the request body: 1)
     *   Validate the product variant exists and is not out of stock, 2)
     *   Validate the variant belongs to an active (not deleted) product, 3)
     *   Update the quantity field, 4) If quantity is zero or less, soft-delete
     *   the cart item by setting deleted_at timestamp, 5) Update the updated_at
     *   timestamp. Return the updated cart items with current stock
     *   availability status. Handle concurrent updates with optimistic locking
     *   if needed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async patchByCartid(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceCartItem.IUpdate,
  ): Promise<IEcommerceCartItem.ISummary> {
    try {
      return await patchEcommerceCustomerCartsCartIdItems({
        customer,
        cartId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific cart item within a customer's shopping cart.
   *
   * This endpoint returns detailed information about a single cart item, including the product variant details, quantity, and current availability status. The cart item is identified by both the parent cart ID and the item ID, ensuring proper scoping within the customer's cart.
   *
   * The response includes the associated product variant information such as name, price, and option values, allowing clients to display complete product details without additional API calls. Availability status is determined by checking the variant's current stock level against zero.
   *
   * Access is restricted to the cart owner (the customer who owns the cart). Attempting to access another customer's cart item will result in a 403 Forbidden response.
   *
   * @param connection
   * @param cartId Unique identifier of the shopping cart (global scope)
   * @param itemId Unique identifier of the cart item within the specified cart
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Retrieve cart item from ecommerce_cart_items
     *   table by id and validate cart ownership.
   *
   * Implementation steps:
   * 1. Validate cartId exists in ecommerce_carts table and is not soft-deleted
   * 2. Verify the authenticated customer owns the cart (ecommerce_carts.ecommerce_customer_id matches current customer)
   * 3. Query ecommerce_cart_items by id, ensuring ecommerce_cart_id matches the provided cartId
   * 4. Join with ecommerce_product_variants to retrieve variant details (name, price, options)
   * 5. Check variant stock availability by summing all inventory records for the variant
   * 6. Mark cart item as unavailable if variant stock is zero
   * 7. Return 404 if cart item not found or soft-deleted
   * 8. Return 403 if cart belongs to different customer
   *
   * Edge cases:
   * - Cart item soft-deleted: Return 404 Not Found
   * - Product or variant deleted: Return 404 (per requirements, deleted items are removed from cart)
   * - Variant out of stock: Return cart item with availability status marked as unavailable
   * - Cart soft-deleted: Return 404 Not Found
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceCartItem> {
    try {
      return await getEcommerceCustomerCartsCartIdItemsItemId({
        customer,
        cartId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the quantity of a specific cart item in a customer's shopping cart.
   *
   * This operation modifies the quantity of an existing cart item, allowing customers to adjust how many units of a product variant they wish to purchase. The system validates that the product variant is still available and in stock before applying the update.
   *
   * ## Business Rules
   *
   * - The cart item must exist and belong to the specified cart
   * - The quantity must be a positive integer (minimum 1)
   * - The product variant must still be available and in stock
   * - If the variant becomes out of stock after the cart item was added, the update may fail
   * - The cart item cannot be soft-deleted (deleted_at must be null)
   *
   * ## Security
   *
   * - Customers can only update cart items in their own cart
   * - Authentication is required to access this endpoint
   * - Authorization validates cart ownership before allowing modifications
   *
   * @param connection
   * @param cartId UUID identifier of the shopping cart (customer-scoped)
   * @param itemId UUID identifier of the cart item to update
   * @param body Update request containing the new quantity for the cart item. The quantity must be a positive integer.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Validate authentication and extract customer
     *   ID from session 2. Query ecommerce_carts table to verify cart exists
     *   and belongs to the authenticated customer 3. Query ecommerce_cart_items
     *   table to verify cart item exists, belongs to the cart, and is not
     *   soft-deleted (deleted_at IS NULL) 4. Validate product variant
     *   availability: - Join with ecommerce_product_variants table - Check
     *   variant stock quantity is greater than 0 - Verify product is not
     *   deleted (check product snapshot or variant existence) 5. Validate
     *   request body quantity is a positive integer (minimum 1) 6. Update the
     *   quantity field in ecommerce_cart_items table 7. Update the updated_at
     *   timestamp to current time 8. Return the updated cart item with all
     *   fields including variant details and stock availability status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":itemId")
  public async putByCartidAndItemid(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceCartItem.IUpdate,
  ): Promise<IEcommerceCartItem> {
    try {
      return await putEcommerceCustomerCartsCartIdItemsItemId({
        customer,
        cartId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Removes a cart item from the customer's shopping cart.
   *
   * This operation deletes a specific cart item by setting its deleted_at timestamp, effectively removing it from the active cart. The item is soft-deleted to enable recovery if needed.
   *
   * ## Business Rules
   *
   * - The cart item is immediately removed from the customer's active cart view
   * - Soft delete preserves the record for audit and recovery purposes
   * - When a seller deletes a product, all cart items referencing that product are automatically removed from all customers' carts
   * - When a order is successfully placed, all cart items from that order are automatically removed
   * - The operation validates that the cart belongs to the authenticated customer
   * - The operation validates that the item exists within the specified cart
   *
   * @param connection
   * @param cartId UUID of the shopping cart containing the item (scoped to customer)
   * @param itemId UUID of the cart item to remove
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Implement cart item deletion with the following
     *   logic:
   *
   * 1. **Authorization**: Verify the authenticated customer owns the cart (ecommerce_cart.ecommerce_customer_id matches current customer)
   * 2. **Validation**:
   *    - Verify cart exists and is not deleted
   *    - Verify cart item exists within the specified cart
   *    - Verify cart item is not already soft-deleted
   * 3. **Soft Delete**: Set deleted_at timestamp on the cart item record
   * 4. **Cascade Considerations**: No cascade actions needed - cart item deletion is independent
   * 5. **Edge Cases**:
   *    - Return 404 if cart or item not found
   *    - Return 403 if cart belongs to different customer
   *    - Return 400 if item already deleted
   * 6. **Automatic Removal Triggers**: Product deletion or order placement should automatically trigger cart item removal via separate service logic
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":itemId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceCustomerCartsCartIdItemsItemId({
        customer,
        cartId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
