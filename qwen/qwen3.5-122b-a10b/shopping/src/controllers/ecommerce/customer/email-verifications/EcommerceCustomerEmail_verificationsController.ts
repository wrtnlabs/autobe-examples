import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceCustomerEmailVerification } from "../../../../api/structures/IEcommerceCustomerEmailVerification";
import { IPageIEcommerceCustomerEmailVerification } from "../../../../api/structures/IPageIEcommerceCustomerEmailVerification";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerEmailVerificationsVerificationId } from "../../../../providers/getEcommerceCustomerEmailVerificationsVerificationId";
import { patchEcommerceCustomerEmailVerifications } from "../../../../providers/patchEcommerceCustomerEmailVerifications";

@Controller("/ecommerce/customer/email-verifications")
export class EcommerceCustomerEmail_verificationsController {
  /**
   * Search and retrieve email verification records for administrative oversight.
   *
   * This operation allows administrators to view email verification records across both customer and seller accounts. Administrators can filter by verification status, user type, email address, and date ranges to monitor registration verification workflows and troubleshoot verification issues.
   *
   * **Search Capabilities**
   *
   * Administrators can filter verification records by status (verified, pending, expired), user type (customer or seller), specific email addresses, creation date ranges, and expiration date ranges. Multiple filters can be combined for precise queries.
   *
   * **Pagination**
   *
   * Results are returned using cursor-based pagination for efficient handling of large result sets. Include limit and cursor parameters in the request to navigate through pages of verification records.
   *
   * **Access Control**
   *
   * This operation requires administrator authentication. Only administrators with appropriate privileges can access email verification records to maintain privacy and security of user registration data.
   *
   * @param connection
   * @param body Search criteria for filtering email verification records including user type, verification status, email patterns, date ranges, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query both ecommerce_customer_email_verifications and ecommerce_seller_email_verifications tables with unified search criteria. Apply filters on verification status (verified/pending/expired based on verified_at and expires_at), user type (customer/seller discriminator), email address from joined customer/seller tables, date ranges for created_at and expires_at. Perform LEFT JOIN with ecommerce_customers and ecommerce_sellers to retrieve user email addresses. Return cursor-based pagination with verification record summaries including id, user_type, email, status, created_at, expires_at, verified_at. Implement access control to restrict to administrator accounts only. Handle empty results gracefully with zero-count pagination response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceCustomerEmailVerification.IRequest,
  ): Promise<IPageIEcommerceCustomerEmailVerification.ISummary> {
    try {
      return await patchEcommerceCustomerEmailVerifications({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific email verification record by its unique identifier.
   *
   * This endpoint allows authenticated customers or sellers to check the status of their email verification request during the registration process. The system validates that the requesting user owns the verification record before returning details.
   *
   * **Verification Status**
   *
   * The response includes whether the email has been verified (verified_at is set), when the token expires, and the creation timestamp. Users can use this information to determine if they need to request a new verification email.
   *
   * **Security**
   *
   * Only the user who owns the verification record can access it. The system validates ownership by matching the authenticated user's ID with the verification record's customer_id or seller_id foreign key. Token values are not exposed in the response for security.
   *
   * @param connection
   * @param verificationId Unique identifier of the email verification record (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Extract verificationId from path parameter (UUID format)
   * 2. Authenticate the requesting user (customer or seller)
   * 3. Query email verification tables:
   *    - First check ecommerce_customer_email_verifications where id = verificationId
   *    - If not found, check ecommerce_seller_email_verifications where id = verificationId
   * 4. Validate ownership: verification record's customer_id/seller_id must match authenticated user's ID
   * 5. If no matching record or ownership mismatch, return 404 Not Found
   * 6. If record exists and owned by user, return verification details including:
   *    - id, expires_at, verified_at, created_at, updated_at
   *    - Do NOT expose the token value in the response
   * 7. Handle soft-deleted records: return 404 if deleted_at is set
   * 8. Return 401 if user is not authenticated
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":verificationId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("verificationId")
    verificationId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceCustomerEmailVerification> {
    try {
      return await getEcommerceCustomerEmailVerificationsVerificationId({
        customer,
        verificationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
