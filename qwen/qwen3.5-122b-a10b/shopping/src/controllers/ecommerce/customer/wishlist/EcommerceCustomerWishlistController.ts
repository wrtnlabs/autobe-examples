import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceWishlistItem } from "../../../../api/structures/IEcommerceWishlistItem";
import { IPageIEcommerceWishlistItem } from "../../../../api/structures/IPageIEcommerceWishlistItem";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchEcommerceCustomerWishlist } from "../../../../providers/patchEcommerceCustomerWishlist";

@Controller("/ecommerce/customer/wishlist")
export class EcommerceCustomerWishlistController {
  /**
   * Retrieve the authenticated customer's wishlist items with product information in paginated format.
   *
   * This operation returns all products saved by the customer for future purchase consideration, displaying current product details including name, main image, price, and availability status. The wishlist is automatically created when a customer registers and persists for the lifetime of their account.
   *
   * **Pagination**
   *
   * Wishlist items are paginated to facilitate browsing when the wishlist contains many products. Cursor-based pagination is recommended for consistent results during scrolling.
   *
   * **Product Information**
   *
   * Each wishlist item displays the product's current information, not the information at the time it was added. If product details change (price, name, images), the wishlist reflects the updated values. Availability status is checked in real-time to show whether products can still be purchased.
   *
   * **Access Control**
   *
   * Only the authenticated customer who owns the wishlist can access this endpoint. Administrators cannot view individual customer wishlists as this data is private.
   *
   * @param connection
   * @param body Pagination parameters and optional filters for browsing wishlist items.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_wishlist_items table for the authenticated customer's wishlist, filtering out soft-deleted items (deleted_at IS NULL). Join with ecommerce_products to fetch current product information including name, main image, price, and availability status.
   *
   * Implement cursor-based pagination using created_at timestamp and id for stable ordering. Support optional filtering by product availability status.
   *
   * Validate that the authenticated customer ID matches the ecommerce_wishlist_id's associated customer. Return 403 Forbidden if access denied.
   *
   * Handle edge cases: empty wishlist returns empty page, product deleted by seller should not appear in wishlist (cascade delete), out-of-stock products still appear but with unavailable status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceWishlistItem.IRequest,
  ): Promise<IPageIEcommerceWishlistItem.ISummary> {
    try {
      return await patchEcommerceCustomerWishlist({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
