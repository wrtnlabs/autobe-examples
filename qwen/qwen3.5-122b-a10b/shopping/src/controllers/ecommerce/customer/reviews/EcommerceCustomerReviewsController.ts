import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceReview } from "../../../../api/structures/IEcommerceReview";
import { IPageIEcommerceReview } from "../../../../api/structures/IPageIEcommerceReview";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteEcommerceCustomerReviewsReviewId } from "../../../../providers/deleteEcommerceCustomerReviewsReviewId";
import { getEcommerceCustomerReviewsReviewId } from "../../../../providers/getEcommerceCustomerReviewsReviewId";
import { patchEcommerceCustomerReviews } from "../../../../providers/patchEcommerceCustomerReviews";
import { postEcommerceCustomerReviews } from "../../../../providers/postEcommerceCustomerReviews";
import { putEcommerceCustomerReviewsReviewId } from "../../../../providers/putEcommerceCustomerReviewsReviewId";

@Controller("/ecommerce/customer/reviews")
export class EcommerceCustomerReviewsController {
  /**
   * Create a new product review for a delivered order item.
   *
   * This operation allows customers to submit feedback and ratings for products they have purchased and received. The review includes a mandatory star rating (1-5) and optional text content describing their experience.
   *
   * **Eligibility Requirements**
   *
   * Customers can only create reviews for order items with status "delivered". Each order item can have at most one review, enforced by a unique constraint. If a customer has purchased the same product in multiple orders, they can write a separate review for each order.
   *
   * **Review Content**
   *
   * The rating field is required and must be an integer between 1 and 5 stars. The content field is optional and can contain detailed feedback about the product. Reviews are displayed on the product detail page sorted by newest first and contribute to the product's average rating calculation.
   *
   * **Permissions and Ownership**
   *
   * Only authenticated customers can create reviews. The system automatically associates the review with the authenticated customer's ID. Customers can later edit or delete their own reviews through separate endpoints.
   *
   * @param connection
   * @param body Review creation data including the order item being reviewed, star rating (1-5), and optional text content. The customer_id is automatically derived from authentication context.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Validate authentication: Extract customer_id from JWT session token. Return 401 if not authenticated.
   *
   * 2. Validate order item existence: Query ecommerce_order_items by orderItemId. Return 404 if not found.
   *
   * 3. Verify purchase eligibility: Check that order item's status equals "delivered". Return 403 if not delivered (paid, shipped, cancelled, or refunded states are ineligible).
   *
   * 4. Verify review uniqueness: Check ecommerce_reviews table for existing review with this order_item_id. Return 409 Conflict if review already exists for this order item.
   *
   * 5. Validate rating: Ensure rating is an integer between 1 and 5 inclusive. Return 400 if out of range.
   *
   * 6. Derive product_id: Extract product_id from the order item's productVariant relationship (orderItem.productVariant.product_id).
   *
   * 7. Create review record: Insert into ecommerce_reviews with customer_id (from auth), order_item_id, product_id (derived), rating, content (nullable), and timestamps.
   *
   * 8. Return created review: Respond with 201 Created and the full IEcommerceReview object including generated id and timestamps.
   *
   * **Edge Cases**
   *
   * - Order item belongs to different customer: Return 403 Forbidden (customer cannot review another customer's order)
   * - Product has been deleted: Still allow review creation (product_id is denormalized and preserved)
   * - Content exceeds maximum length: Validate against schema maxLength constraint if defined
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceReview.ICreate,
  ): Promise<IEcommerceReview> {
    try {
      return await postEcommerceCustomerReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of product reviews with optional filtering and sorting.
   *
   * This endpoint returns reviews associated with products, supporting filters by product, customer, rating range, and date ranges. Reviews are sorted by creation date (newest first) by default. Soft-deleted reviews are excluded from results unless explicitly included via filter.
   *
   * **Filtering Options**
   *
   * - Filter by specific product to view all reviews for that product
   * - Filter by customer to view reviews written by a specific customer
   * - Filter by rating range (1-5 stars)
   * - Filter by date range (created_at, updated_at)
   * - Include/exclude soft-deleted reviews
   *
   * **Sorting**
   *
   * - Default: created_at DESC (newest first)
   * - Alternative: rating DESC, rating ASC, updated_at DESC
   *
   * **Pagination**
   *
   * - Cursor-based pagination for consistent paging through large result sets
   * - Page size limits apply (minimum 1, maximum 100)
   *
   * @param connection
   * @param body Search criteria for filtering and paginating reviews. Includes optional filters by product, customer, rating range, and date ranges. Pagination parameters control result set size and cursor-based navigation.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_reviews table with the following implementation logic:
   *
   * 1. **Base Query**: SELECT reviews with customer, product, and orderItem relationships
   * 2. **Soft Delete Filter**: By default, WHERE deleted_at IS NULL. Override if includeDeleted=true in request.
   * 3. **Product Filter**: If product_id provided, WHERE product_id = :product_id
   * 4. **Customer Filter**: If customer_id provided, WHERE customer_id = :customer_id
   * 5. **Rating Filter**: If ratingMin/ratingMax provided, WHERE rating BETWEEN :ratingMin AND :ratingMax
   * 6. **Date Range Filter**: If createdAtFrom/createdAtTo provided, WHERE created_at BETWEEN :createdAtFrom AND :createdAtTo
   * 7. **Sorting**: Default ORDER BY created_at DESC. Support rating ASC/DESC, updated_at DESC as alternatives.
   * 8. **Pagination**: Implement cursor-based pagination using created_at and id as cursor keys
   * 9. **Authorization**: No specific authorization required for public product reviews. Customer-filtered queries require customer authentication.
   * 10. **Response Construction**: Return IPageIEcommerceReview.ISummary with review summaries excluding deleted_at field in summaries
   *
   * **Edge Cases**
   *
   * - Empty result set: Return page with empty items array and null cursors
   * - Invalid rating values: Return 400 Bad Request
   * - Invalid cursor: Return 400 Bad Request with error message
   * - Product has no reviews: Return page with empty items array
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceReview.IRequest,
  ): Promise<IPageIEcommerceReview.ISummary> {
    try {
      return await patchEcommerceCustomerReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single review by its unique identifier.
   *
   * This operation fetches the complete details of a specific review, including the rating, content, and associated customer and product information. The review must exist and must not be soft-deleted to be retrieved.
   *
   * **Access Control**
   *
   * All authenticated customers can view any non-deleted review. This supports the use case of viewing product reviews on product detail pages.
   *
   * **Soft Delete Behavior**
   *
   * Reviews that have been deleted by their author (soft-deleted via deleted_at timestamp) will return a 404 Not Found response. This ensures deleted reviews are not accessible through the API.
   *
   * **Related Resources**
   *
   * - The review references a customer (customer_id)
   * - The review references an order item (order_item_id) for purchase verification
   * - The review references a product (product_id) for display purposes
   *
   * @param connection
   * @param reviewId The unique identifier of the review to retrieve (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_reviews table by primary key id (UUID).
   *
   * **Implementation Steps**
   *
   * 1. Validate the reviewId parameter is a valid UUID format
   * 2. Query ecommerce_reviews WHERE id = :reviewId AND deleted_at IS NULL
   * 3. If no record found, return 404 Not Found
   * 4. If found, return the full review entity with all fields
   *
   * **Business Rules**
   *
   * - Only non-deleted reviews (deleted_at IS NULL) should be returned
   * - The review must exist in the database
   * - No authorization check needed for reading reviews (all authenticated users can view any review)
   *
   * **Error Handling**
   *
   * - 404 Not Found: Review does not exist or has been soft-deleted
   * - 400 Bad Request: Invalid UUID format in reviewId parameter
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reviewId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceReview> {
    try {
      return await getEcommerceCustomerReviewsReviewId({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing customer review including rating and optional text content.
   *
   * This operation allows customers to modify their own review after submission. Every edit triggers the creation of a snapshot in the review_snapshots table, preserving the previous state for audit and dispute resolution purposes.
   *
   * **Authentication & Authorization**
   * - Customer must be authenticated
   * - Customer must own the review (customer_id matches authenticated user)
   * - Review must not be soft-deleted (deleted_at is null)
   *
   * **Updateable Fields**
   * - rating: Required, integer from 1 to 5 stars
   * - content: Optional, text content (can be null or empty string)
   *
   * **Business Rules**
   * - A snapshot is automatically created before updating, capturing the current rating and content
   * - The updated_at timestamp is set to the current time
   * - Deleted reviews cannot be updated (404 error returned)
   * - Rating must be within valid range (1-5)
   *
   * @param connection
   * @param reviewId Unique identifier of the review to update (UUID format)
   * @param body Updated review data including mandatory rating (1-5 stars) and optional text content.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Authenticate customer and extract customer_id from session
   * 2. Query ecommerce_reviews by id (reviewId path parameter)
   * 3. If review not found OR deleted_at is NOT null, return 404 Not Found
   * 4. Verify review.customer_id matches authenticated customer_id
   * 5. If mismatch, return 403 Forbidden
   * 6. Create snapshot record in ecommerce_review_snapshots:
   *    - ecommerce_review_id: review.id
   *    - rating: review.rating (current value)
   *    - content: review.content (current value, nullable)
   *    - created_at: current timestamp
   * 7. Update review record:
   *    - Set rating from request body (required, validate 1-5)
   *    - Set content from request body (optional, nullable)
   *    - Set updated_at to current timestamp
   * 8. Return updated review entity with 200 OK
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":reviewId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceReview.IUpdate,
  ): Promise<IEcommerceReview> {
    try {
      return await putEcommerceCustomerReviewsReviewId({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a customer's review for a product.
   *
   * This operation removes a review from public display by marking it as deleted. The review record is preserved in the database with a deleted_at timestamp, while snapshots remain intact for historical and dispute resolution purposes.
   *
   * **Deletion Behavior**
   *
   * The review is soft-deleted rather than physically removed. This means:
   * - The review is no longer visible on the product detail page
   * - The review is excluded from the product's average rating calculation
   * - All review snapshots are preserved for audit and historical purposes
   * - The review record remains in the database with a deleted_at timestamp
   *
   * **Authorization**
   *
   * Only the customer who owns the review can delete it. The system validates that the authenticated customer's ID matches the review's customer_id before allowing deletion.
   *
   * **Product Rating Recalculation**
   *
   * After deletion, the product's average rating is automatically recalculated to reflect only non-deleted reviews.
   *
   * @param connection
   * @param reviewId Unique identifier of the review to delete (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Validate the authenticated customer owns this review by checking customer_id matches the authenticated user.
   * 2. Verify the review exists and is not already deleted (deleted_at is null).
   * 3. Set deleted_at to current timestamp (soft delete).
   * 4. Do NOT delete review snapshots - they must be preserved per requirements.
   * 5. Recalculate the product's average rating excluding this deleted review.
   * 6. Return 200 OK on success, 404 if review not found, 403 if customer does not own the review.
   * 7. Use database transaction to ensure atomicity of soft delete and rating recalculation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reviewId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceCustomerReviewsReviewId({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
