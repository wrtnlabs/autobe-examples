import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceReview } from "../../../../../api/structures/IEcommerceReview";
import { IPageIEcommerceReview } from "../../../../../api/structures/IPageIEcommerceReview";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchEcommerceCustomerReviewsSummary } from "../../../../../providers/patchEcommerceCustomerReviewsSummary";

@Controller("/ecommerce/customer/reviews/summary")
export class EcommerceCustomerReviewsSummaryController {
  /**
   * Retrieve a paginated list of review summaries with filtering and sorting options.
   *
   * This endpoint returns review summaries for products, excluding deleted reviews. Each summary includes the rating, optional content preview, customer information, and timestamps. Reviews are sorted by newest first by default.
   *
   * The average product rating is calculated from non-deleted reviews only, ensuring rating integrity even when customers delete their reviews.
   *
   * **Filtering**
   *
   * Filter reviews by product ID or customer ID to retrieve specific review subsets.
   *
   * **Pagination**
   *
   * Use page and limit parameters in the request body to paginate through large review collections. The response includes total count and pagination metadata.
   *
   * **Sorting**
   *
   * Reviews are sorted by created_at descending (newest first) by default. This sorting order applies to all review displays on product detail pages.
   *
   * @param connection
   * @param body Search criteria including product ID filter, customer ID filter, pagination parameters (page, limit), and sorting options.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_reviews table with pagination and filtering.
   *
   * Filter by product_id or customer_id if provided in the request body.
   * Exclude reviews where deleted_at is not null (soft-deleted reviews).
   *
   * Join with ecommerce_customers to retrieve customer display name and profile information.
   * Join with ecommerce_products to validate product existence.
   *
   * Apply pagination: offset = (page - 1) * limit, limit defaults to 20, max 100.
   * Sort by created_at DESC (newest first) as the default ordering.
   *
   * Calculate and include total count of matching reviews for pagination metadata.
   *
   * Return review summaries with: id, product_id, customer display name, rating, content preview (truncated), created_at, updated_at.
   *
   * Do not include deleted reviews in the result set or in the total count.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceReview.IRequest,
  ): Promise<IPageIEcommerceReview.ISummary> {
    try {
      return await patchEcommerceCustomerReviewsSummary({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
