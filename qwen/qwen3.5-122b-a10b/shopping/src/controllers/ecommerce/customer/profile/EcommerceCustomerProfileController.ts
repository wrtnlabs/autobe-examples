import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceCustomer } from "../../../../api/structures/IEcommerceCustomer";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putEcommerceCustomerProfile } from "../../../../providers/putEcommerceCustomerProfile";

@Controller("/ecommerce/customer/profile")
export class EcommerceCustomerProfileController {
  /**
   * Update the authenticated customer's profile information including display name and phone number.
   *
   * This operation allows customers to modify their public-facing profile details. The display name is visible to other users in reviews and order histories. The phone number is used for shipping notifications and customer service contact.
   *
   * **Validation Rules**
   *
   * - Display name must be non-empty (at least one character)
   * - Phone number must be in a valid format if provided
   * - Both fields can be updated independently
   *
   * **Authorization**
   *
   * Only the authenticated customer can update their own profile. The system identifies the customer from the session token, not from request parameters.
   *
   * **Response**
   *
   * Returns the complete updated customer profile including all fields.
   *
   * @param connection
   * @param body Profile update request containing display name and phone number fields to modify.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Extract customer ID from authenticated session token
   * 2. Validate customer account is not soft-deleted (deleted_at IS NULL)
   * 3. Validate request body fields:
   *    - display_name: required, non-empty string (minLength: 1)
   *    - phone_number: optional string, validate format if provided
   * 4. Update ecommerce_customers table fields (display_name, phone_number, updated_at)
   * 5. Return updated customer record as response
   * 6. Error responses:
   *    - 401: Invalid or missing authentication token
   *    - 404: Customer not found or soft-deleted
   *    - 400: Validation error on request body fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceCustomer.IUpdate,
  ): Promise<IEcommerceCustomer> {
    try {
      return await putEcommerceCustomerProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
