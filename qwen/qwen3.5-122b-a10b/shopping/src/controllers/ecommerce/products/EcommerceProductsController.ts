import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceProduct } from "../../../api/structures/IEcommerceProduct";
import { IPageIEcommerceProduct } from "../../../api/structures/IPageIEcommerceProduct";
import { getEcommerceProductsProductId } from "../../../providers/getEcommerceProductsProductId";
import { patchEcommerceProducts } from "../../../providers/patchEcommerceProducts";

@Controller("/ecommerce/products")
export class EcommerceProductsController {
  /**
   * Search and list products with pagination, filtering, and sorting capabilities.
   *
   * This endpoint retrieves a paginated list of products from the ecommerce_products table. Customers can browse products by name, category, price range, and other criteria. Sellers can filter by their own products. The response includes product summaries optimized for list displays with essential information like name, base price, category, and variant availability status.
   *
   * **Search Capabilities**
   * - Text search on product name using trigram matching
   * - Category filtering by category ID (includes subcategories option)
   * - Price range filtering (minimum and maximum base price)
   * - Seller filtering (for seller dashboard views)
   * - Pagination with cursor-based navigation
   * - Sorting by created_at, updated_at, name, or base_price
   *
   * **Business Rules**
   * - Soft-deleted products are excluded from results unless explicitly requested
   * - Products without variants are marked as unavailable in summaries
   * - Category filtering can include or exclude subcategory products
   * - Stock availability is calculated from inventory records on-demand
   *
   * @param connection
   * @param body Search criteria for product listing including text filters, category filters, price ranges, pagination parameters, and sorting options.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Implement product search with the following
     *   logic:
   *
   * 1. **Query Construction**
   *    - Query ecommerce_products table with filters from request body
   *    - Join with ecommerce_categories for category name in summaries
   *    - Join with ecommerce_sellers for seller name in summaries (if requested)
   *    - LEFT JOIN with ecommerce_product_variants to check variant availability
   *    - Filter out soft-deleted products (deleted_at IS NULL) by default
   *
   * 2. **Filter Application**
   *    - Name search: Use PostgreSQL trigram matching (name ILIKE %keyword% or gin_trgm_ops index)
   *    - Category filter: Match category_id exactly, optionally include subcategories via recursive CTE
   *    - Price range: Apply >= min_price AND <= max_price on base_price
   *    - Seller filter: Match seller_id for seller-specific views
   *    - Availability filter: Check if product has at least one non-deleted variant with stock > 0
   *
   * 3. **Stock Availability Calculation**
   *    - For each product, calculate total stock by summing all ecommerce_inventory_records for its variants
   *    - Mark product as 'available' if any variant has stock > 0
   *    - Mark product as 'out_of_stock' if all variants have stock = 0
   *    - Mark product as 'unavailable' if no variants exist
   *
   * 4. **Pagination**
   *    - Implement cursor-based pagination using created_at or id as cursor
   *    - Support limit (default 20, max 100) and cursor parameters
   *    - Return has_more flag indicating if additional pages exist
   *
   * 5. **Sorting**
   *    - Support sort_by: 'created_at', 'updated_at', 'name', 'base_price'
   *    - Support sort_order: 'asc' or 'desc' (default 'desc' for created_at)
   *    - Apply sorting before pagination
   *
   * 6. **Error Handling**
   *    - Return 400 if invalid filter values (e.g., negative price)
   *    - Return 400 if invalid sort_by or sort_order values
   *    - Return 400 if cursor is malformed
   *
   * 7. **Performance Optimization**
   *    - Use existing indexes: name (gin_trgm_ops), category_id, seller_id, created_at
   *    - Add composite index on (category_id, deleted_at) for category filtering
   *    - Consider materialized view for stock calculations if performance issues arise
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommerceProduct.IRequest,
  ): Promise<IPageIEcommerceProduct.ISummary> {
    try {
      return await patchEcommerceProducts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific product including its seller, category, images, and variants.
   *
   * This endpoint returns the complete product entity with all associated data. The product must be active (not soft-deleted) to be accessible. Customers can browse products, sellers can view their own products, and administrators can view any product on the platform.
   *
   * **Product Information**
   *
   * The response includes the product's name, description, base price, and timestamps. The base price serves as the default price unless overridden by individual variants.
   *
   * **Related Entities**
   *
   * - **Seller**: The shop owner who created and manages this product
   * - **Category**: The category assignment for browsing and organization
   * - **Images**: All product images with display ordering (first image is thumbnail)
   * - **Variants**: All SKU variants with option values and optional price overrides
   *
   * **Access Control**
   *
   * - Customers: Can view any active product
   * - Sellers: Can view their own products (active or deleted)
   * - Administrators: Can view any product including deleted ones for oversight
   *
   * @param connection
   * @param productId Unique identifier of the product to retrieve (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the ecommerce_products table by UUID id
     *   parameter.
   *
   * Filter out soft-deleted products where deleted_at IS NOT NULL (unless requested by administrator with elevated privileges).
   *
   * Join with ecommerce_sellers to retrieve seller information including shop name.
   *
   * Join with ecommerce_categories to retrieve category hierarchy information.
   *
   * Include all active product images from ecommerce_product_images ordered by display_order.
   *
   * Include all variants from ecommerce_product_variants (including soft-deleted variants if parent product is active).
   *
   * Return full product entity with embedded relationships.
   *
   * Error handling:
   * - Return 404 if product not found or is soft-deleted (for regular users)
   * - Return 403 if user lacks permission to view this product
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceProduct> {
    try {
      return await getEcommerceProductsProductId({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
