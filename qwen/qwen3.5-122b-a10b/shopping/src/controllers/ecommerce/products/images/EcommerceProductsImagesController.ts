import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceProductImage } from "../../../../api/structures/IEcommerceProductImage";
import { getEcommerceProductsProductIdImagesImageId } from "../../../../providers/getEcommerceProductsProductIdImagesImageId";
import { patchEcommerceProductsProductIdImages } from "../../../../providers/patchEcommerceProductsProductIdImages";

@Controller("/ecommerce/products/:productId/images")
export class EcommerceProductsImagesController {
  /**
   * Reorder product images to change their display sequence and thumbnail selection.
   *
   * Sellers can reorder the images of their products by submitting the desired display order. The first image in the submitted order becomes the main thumbnail image displayed in search results, category listings, and product detail pages.
   *
   * **Thumbnail Selection**
   *
   * The image with display_order = 0 automatically serves as the thumbnail. When images are reordered, the system updates display_order values to reflect the new sequence. If the previous thumbnail is moved, the new first image becomes the thumbnail.
   *
   * **Snapshot Creation**
   *
   * When images are reordered, a product snapshot is created that captures the complete image state before and after the modification. This includes all image URLs and their sequence order for audit and dispute resolution purposes.
   *
   * **Authorization**
   *
   * Only the product owner (seller) can reorder images. Administrators can reorder images on any product for oversight purposes.
   *
   * @param connection
   * @param productId UUID of the product whose images are being reordered (global scope).
   * @param body Array of image IDs in the desired display order. The first ID becomes display_order=0 (thumbnail). All active images for the product must be included exactly once.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification 1. Validate productId exists and is not
     *   soft-deleted 2. Verify seller authorization (current user owns product
     *   OR is admin) 3. Validate request body contains array of image IDs
     *   belonging to this product 4. Validate all image IDs exist and are not
     *   soft-deleted 5. Validate no duplicate image IDs in request 6. Validate
     *   image count matches existing active images for product 7. Update
     *   display_order for each image based on array index (0, 1, 2, ...) 8.
     *   Wrap in transaction to ensure atomicity 9. Create product snapshot
     *   capturing image state before and after reorder 10. Return updated
     *   images in new order
   *
   * Edge cases:
   * - Product not found: 404
   * - Unauthorized: 403
   * - Image IDs not belonging to product: 400
   * - Duplicate image IDs: 400
   * - Missing images: 400
   * - Soft-deleted product: 404
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async reorder(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductImage.IReorder,
  ): Promise<IEcommerceProductImage.ISummary> {
    try {
      return await patchEcommerceProductsProductIdImages({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific product image by its ID within the context of a product.
   *
   * This endpoint returns the complete details of a product image including its URL, display order, and metadata. The image must belong to the specified product, ensuring proper access control and data consistency.
   *
   * **Access Control**
   *
   * - Customers can view product images for browsing purposes
   * - Sellers can view images of their own products
   * - Administrators can view any product image
   *
   * **Image Details**
   *
   * The response includes the image URL, display order position, and timestamps. The display order determines the image's position in the product gallery, with the first image (display_order = 0) serving as the thumbnail in listings and search results.
   *
   * @param connection
   * @param productId Unique identifier of the parent product (UUID format).
   * @param imageId Unique identifier of the product image (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the ecommerce_product_images table by
     *   imageId and verify the image belongs to the specified productId.
   *
   * 1. Validate both productId and imageId are valid UUIDs
   * 2. Query ecommerce_product_images WHERE id = imageId AND ecommerce_product_id = productId
   * 3. If no matching record found, return 404 Not Found
   * 4. Verify the parent product exists and is not soft-deleted (deleted_at IS NULL)
   * 5. Return the complete image entity including image_url, display_order, created_at, and updated_at
   * 6. Do not include system-generated fields (id, created_at, updated_at) in requestBody as this is a GET operation
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":imageId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceProductImage> {
    try {
      return await getEcommerceProductsProductIdImagesImageId({
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
