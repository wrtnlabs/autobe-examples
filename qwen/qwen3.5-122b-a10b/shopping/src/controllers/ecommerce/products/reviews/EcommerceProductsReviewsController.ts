import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceReview } from "../../../../api/structures/IEcommerceReview";
import { IPageIEcommerceReview } from "../../../../api/structures/IPageIEcommerceReview";
import { patchEcommerceProductsProductIdReviews } from "../../../../providers/patchEcommerceProductsProductIdReviews";

@Controller("/ecommerce/products/:productId/reviews")
export class EcommerceProductsReviewsController {
  /**
   * Retrieve paginated list of customer reviews for a specific product, sorted by newest first.
   *
   * This endpoint returns all non-deleted reviews associated with the specified product. Reviews are sorted by creation date in descending order, with the most recent reviews appearing first. The response includes review summaries with rating, content preview, customer information, and timestamps.
   *
   * **Filtering and Pagination**
   *
   * The request body supports optional filtering by rating range, customer identifier, and date ranges. Pagination is handled through cursor-based or offset-based mechanisms with configurable page size. Sorting can be customized beyond the default newest-first order.
   *
   * **Review Visibility**
   *
   * Only non-deleted reviews are included in the response. Deleted reviews (where deleted_at is not null) are excluded from both the list and the product's average rating calculation. Each review includes the star rating (1-5) and optional text content provided by the customer.
   *
   * @param connection
   * @param productId Unique identifier of the product to retrieve reviews for (UUID format).
   * @param body Search criteria including rating filters, customer filters, date ranges, and pagination parameters for reviewing product feedback.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query ecommerce_reviews table filtered by
     *   product_id. Apply pagination (cursor or offset-based), sorting
     *   (default: created_at DESC for newest first), and optional filters
     *   (rating range, customer_id). Exclude reviews where deleted_at is not
     *   null. Join with ecommerce_customers for customer display name if
     *   requested. Return paginated review summaries optimized for product
     *   detail page display. Validate that product exists before querying
     *   reviews.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceReview.IRequest,
  ): Promise<IPageIEcommerceReview.ISummary> {
    try {
      return await patchEcommerceProductsProductIdReviews({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
