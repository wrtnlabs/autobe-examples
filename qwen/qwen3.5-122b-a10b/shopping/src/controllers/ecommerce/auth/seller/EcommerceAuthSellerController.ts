import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceSeller } from "../../../../api/structures/IEcommerceSeller";
import { postEcommerceAuthSellerJoin } from "../../../../providers/postEcommerceAuthSellerJoin";
import { postEcommerceAuthSellerLogin } from "../../../../providers/postEcommerceAuthSellerLogin";
import { postEcommerceAuthSellerRefresh } from "../../../../providers/postEcommerceAuthSellerRefresh";

@Controller("/ecommerce/auth/seller")
export class EcommerceAuthSellerController {
  /**
   * Register a new seller account for the e-commerce platform.
   *
   * This operation creates a seller account with email and password credentials, initiates the email verification workflow, and creates a seller approval request that requires administrator review before the seller can begin selling products.
   *
   * **Registration Process**
   *
   * The system validates the email address format and uniqueness, enforces password strength requirements, and creates the seller account with pending approval status. An email verification token is generated and sent to the provided email address. The seller must verify their email before they can log in.
   *
   * **Approval Workflow**
   *
   * After registration, the seller account enters a pending approval state. An administrator must review and approve the registration before the seller gains full selling privileges. The approval status is tracked in the seller record and can be viewed by the seller during the waiting period.
   *
   * **Security Considerations**
   *
   * Passwords are hashed using bcrypt before storage. Email verification prevents account creation with invalid or owned email addresses. The approval workflow ensures platform quality control before allowing sellers to list products.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration credentials and initial account information.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Register a new seller account with email and password. Validate email uniqueness, password strength (minimum 8 characters), and create seller record with pending approval status. Generate email verification token and send verification email. Create seller profile with default shop name derived from email prefix. Create approval request record with pending status. Hash password using bcrypt before storage. Return authorized response with access and refresh tokens after email verification is complete.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceSeller.IJoin,
  ): Promise<IEcommerceSeller.IAuthorized> {
    try {
      return await postEcommerceAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a seller and establish an authenticated session.
   *
   * This operation validates seller credentials against stored email and password hash, checks account status constraints, and creates a JWT session with access and refresh tokens for subsequent authenticated API calls.
   *
   * **Authentication Flow**
   *
   * The system verifies the email exists, compares the provided password against the stored bcrypt hash, and validates account status constraints. Only sellers with approved status who are not suspended or banned can successfully authenticate.
   *
   * **Account Status Validation**
   *
   * Sellers must have approval_status of 'approved' to log in. Accounts with pending or rejected status cannot authenticate. Suspended accounts cannot log in but retain order processing capabilities. Banned accounts are completely blocked from platform access.
   *
   * **Session Management**
   *
   * Upon successful authentication, a session record is created with encrypted access and refresh tokens. The session tracks client metadata (IP address, href, referrer) for security monitoring. Access tokens expire after a short period while refresh tokens enable session renewal without re-authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login credentials for authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Authenticate seller with email and password credentials. Validate email format and existence, verify password hash using bcrypt comparison, check approval status (must be approved), verify account is not suspended or banned. If valid, create session record with access and refresh tokens, store session metadata (IP, href, referrer), set expiration timestamps. Return authorized response with tokens. Return 401 for invalid credentials, 403 for unapproved/suspended/banned accounts.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceSeller.ILogin,
  ): Promise<IEcommerceSeller.IAuthorized> {
    try {
      return await postEcommerceAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew an expired access token using a valid refresh token.
   *
   * This operation extends the seller's authenticated session without requiring re-authentication by validating the refresh token and issuing new access and refresh tokens.
   *
   * **Token Renewal Process**
   *
   * The system validates the refresh token against stored session records, verifies the session has not expired, and confirms the seller account remains in good standing. New tokens are generated with updated expiration timestamps.
   *
   * **Security Validation**
   *
   * Refresh tokens are single-use and tied to specific sessions. The system validates the seller account status to prevent token renewal for suspended or banned accounts. Expired sessions are rejected even with valid refresh tokens.
   *
   * **Session Continuity**
   *
   * Successful token renewal extends the session lifetime and updates the session record with new token values. This enables seamless API access without requiring the seller to re-enter credentials.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for session renewal.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Renew access token using valid refresh token. Validate refresh token existence and validity, check session is not expired or deleted, verify seller account still exists and is approved/not suspended/not banned. If valid, generate new access and refresh tokens, update session record with new tokens and extended expiration, return authorized response with new tokens. Return 401 for invalid/expired refresh tokens or invalid account status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceSeller.IRefresh,
  ): Promise<IEcommerceSeller.IAuthorized> {
    try {
      return await postEcommerceAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
