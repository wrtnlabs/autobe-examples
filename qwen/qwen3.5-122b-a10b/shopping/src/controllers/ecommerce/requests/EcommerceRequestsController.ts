import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceAdminRequest } from "../../../api/structures/IEcommerceAdminRequest";
import { postEcommerceRequests } from "../../../providers/postEcommerceRequests";

@Controller("/ecommerce/requests")
export class EcommerceRequestsController {
  /**
   * Submit a request to become a platform administrator.
   *
   * This operation allows registered customers or sellers to apply for administrator access by providing a reason for their request. The system validates that the user does not already have an active administrator request and is not already an administrator.
   *
   * Upon successful submission, the request is created with 'pending' status and queued for review by super administrators. The applicant will be notified when the request is approved or rejected.
   *
   * ## Validation Rules
   *
   * - A reason must be provided (non-empty string)
   * - User must not already have a pending administrator request
   * - User must not already be an administrator
   * - Requester must be authenticated as a customer or seller
   *
   * ## Requester Type
   *
   * The system automatically determines the requester type based on the authenticated user's role. Customers and sellers can both submit administrator requests through this endpoint.
   *
   * @param connection
   * @param body Administrator access request containing the applicant's reason for seeking administrator privileges.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification 1. Authenticate the requesting user and determine their type (customer or seller)
   * 2. Check if user is already an administrator by querying ecommerce_admins table - if yes, return 400 error
   * 3. Query ecommerce_admin_requests table for existing pending requests from this user (by requester_type and requester_customer_id or requester_seller_id)
   * 4. If a pending request exists, return 409 Conflict error with message about existing pending request
   * 5. Validate that reason field is provided and non-empty
   * 6. Create new ecommerce_admin_requests record with:
   *    - requester_type: 'customer' or 'seller'
   *    - requester_customer_id or requester_seller_id: based on user type
   *    - reason: from request body
   *    - status: 'pending'
   *    - created_at and updated_at: current timestamp
   * 7. Return the created admin request with 201 Created status
   * 8. All database operations should be within a transaction to ensure consistency
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: IEcommerceAdminRequest.ICreate,
  ): Promise<IEcommerceAdminRequest> {
    try {
      return await postEcommerceRequests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
