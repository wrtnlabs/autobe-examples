import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceSeller } from "../../../api/structures/IEcommerceSeller";
import { IPageIEcommerceSeller } from "../../../api/structures/IPageIEcommerceSeller";
import { getEcommerceSellersSellerId } from "../../../providers/getEcommerceSellersSellerId";
import { patchEcommerceSellers } from "../../../providers/patchEcommerceSellers";

@Controller("/ecommerce/sellers")
export class EcommerceSellersController {
  /**
   * Search and retrieve a paginated list of seller accounts with filtering options.
   *
   * This endpoint enables administrators and sellers to browse seller accounts based on various criteria including approval status, suspension status, ban status, and date ranges. The response includes summary information optimized for list displays.
   *
   * **Filtering Capabilities**
   *
   * You can filter sellers by their approval workflow status (pending, approved, rejected), account suspension state, ban state, and registration date ranges. Multiple filters can be combined for precise searches.
   *
   * **Pagination**
   *
   * Results are returned using cursor-based pagination for efficient handling of large result sets. Include page cursor and limit parameters in your request.
   *
   * **Data Access**
   *
   * Administrators can view all seller accounts. Sellers can view other seller profiles for transparency and marketplace exploration purposes.
   *
   * @param connection
   * @param body Search criteria for filtering seller accounts including approval status, suspension status, ban status, date ranges, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query ecommerce_sellers table with optional joins
     *   to ecommerce_seller_profiles for shop information.
   *
   * Apply search filters from request body:
   * - approval_status: filter by 'pending', 'approved', or 'rejected'
   * - is_suspended: filter by boolean value
   * - is_banned: filter by boolean value
   * - created_at_gte/created_at_lte: date range filtering
   * - shop_name: partial text search on profile shop_name
   *
   * Implement cursor-based pagination using created_at and id as composite cursor.
   *
   * Return IPageIEcommerceSeller.ISummary with seller summary records including:
   * - id, email, approval_status, is_suspended, is_banned
   * - shop_name, shop_description from joined profile
   * - created_at timestamp
   *
   * Ensure proper authorization checks: admin can view all, sellers can view all for marketplace transparency.
   *
   * Handle soft-deleted records by excluding them from results (deleted_at IS NULL).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommerceSeller.IRequest,
  ): Promise<IPageIEcommerceSeller.ISummary> {
    try {
      return await patchEcommerceSellers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a seller's public profile information including shop details, approval status, and account standing.
   *
   * This endpoint returns comprehensive seller information visible to customers browsing products and to administrators overseeing the platform. The response includes the seller's shop name, description, logo image URL, and current approval status (pending, approved, or rejected). If the seller's registration was rejected, the rejection reason is also included for transparency.
   *
   * **Access Control**
   *
   * - Sellers can view their own profile at any time
   * - Administrators can view any seller's profile for oversight purposes
   * - Customers can view seller profiles when browsing products or order details
   *
   * **Data Included**
   *
   * - Shop profile information (name, description, logo URL)
   * - Account approval status and rejection reason if applicable
   * - Suspension and ban status for administrative visibility
   * - Account creation and update timestamps
   *
   * **Excluded Data**
   *
   * - Sensitive authentication credentials (password hash)
   * - Internal system identifiers not relevant to public display
   *
   * @param connection
   * @param sellerId Unique identifier of the seller account (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the ecommerce_sellers table by UUID primary
     *   key (id). Join with ecommerce_seller_profiles table to retrieve shop
     *   profile information (shop_name, shop_description, logo_image_url).
   *
   * **Implementation Steps**
   *
   * 1. Validate the sellerId parameter is a valid UUID format
   * 2. Query ecommerce_sellers with WHERE id = :sellerId AND deleted_at IS NULL
   * 3. If no record found, return 404 Not Found
   * 4. Join with ecommerce_seller_profiles WHERE ecommerce_seller_id = seller.id
   * 5. Construct response object excluding sensitive fields (password_hash, email)
   * 6. Return 200 OK with seller profile data
   *
   * **Business Rules**
   *
   * - Only return sellers where deleted_at IS NULL (soft-deleted sellers not accessible)
   * - Include approval_status from ecommerce_sellers table
   * - Include rejection_reason only if approval_status is 'rejected' and value is not null
   * - Include is_suspended and is_banned flags for administrative visibility
   * - Join with profile is optional (profile may be null if not created yet)
   *
   * **Error Handling**
   *
   * - 404 Not Found: Seller ID does not exist or is soft-deleted
   * - 401 Unauthorized: User not authenticated (handled by middleware)
   * - 403 Forbidden: User lacks permission (not seller owner and not admin)
   *
   * **Authorization**
   *
   * - Owner access: Authenticated seller can view their own profile
   * - Admin access: Administrators can view any seller's profile
   * - Customer access: Any authenticated user can view seller profiles for browsing
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceSeller> {
    try {
      return await getEcommerceSellersSellerId({
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
