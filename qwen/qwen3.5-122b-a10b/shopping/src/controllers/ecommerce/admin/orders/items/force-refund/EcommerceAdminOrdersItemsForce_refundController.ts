@Controller("/ecommerce/admin/orders/:orderId/items/:itemId/force-refund")
export class EcommerceAdminOrdersItemsForce_refundController {
  /**
   * Force-refund an individual order item by administrator, bypassing seller approval.
   *
   * This operation allows administrators to immediately refund an order item regardless of its current status, bypassing the standard seller approval workflow. The customer receives a refund for that specific item only, and the stock quantity is automatically restored through an inventory record.
   *
   * **Business Logic**
   * - Only administrators can perform this operation
   * - The item's stock quantity is restored via an inventory record with reason "refund"
   * - A snapshot of the refund request is created for audit trail
   * - If the item is already in "refunded" status, the action is rejected
   * - Only this specific item is refunded; other items in the order remain unaffected
   * - If all items in the order become refunded, the order status updates to "refunded"
   *
   * **Security**
   * - Requires administrator authentication and authorization
   * - Administrators can force-refund items from any seller or customer
   *
   * **Error Handling**
   * - Returns 404 if order or item does not exist
   * - Returns 409 if item is already refunded
   * - Returns 403 if caller is not an administrator
   *
   * @param connection
   * @param orderId Unique identifier of the parent order (UUID format).
   * @param itemId Unique identifier of the order item to force-refund (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Authenticate and verify caller is an administrator
   * 2. Validate orderId and itemId are valid UUIDs
   * 3. Query ecommerce_orders table to verify order exists
   * 4. Query ecommerce_order_items table to verify item exists and belongs to the order
   * 5. Check item.status is not already "refunded" - if refunded, return 409 Conflict
   * 6. Begin database transaction
   * 7. Update item.status to "refunded", set updated_at to current timestamp
   * 8. Create inventory record for the product variant with:
   *    - quantity change: +item.quantity (restore stock)
   *    - reason: "refund"
   *    - reference to the order item
   * 9. Create refund_request_snapshot recording:
   *    - action: "force-refund"
   *    - performed_by: administrator ID
   *    - timestamp
   *    - item state at time of action
   * 10. Recalculate parent order status based on all item statuses
   * 11. Commit transaction
   * 12. Return updated order item with new status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async forceRefund(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceOrderItem> {
    try {
      return await postEcommerceAdminOrdersOrderIdItemsItemIdForceRefund({
        admin,
        orderId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
