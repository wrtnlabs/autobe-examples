import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { getEcommerceAdminOrdersOrderIdItemsItemIdCancellationRequestsRequestId } from "../../../../../../providers/getEcommerceAdminOrdersOrderIdItemsItemIdCancellationRequestsRequestId";
import { patchEcommerceAdminOrdersOrderIdItemsItemIdCancellationRequests } from "../../../../../../providers/patchEcommerceAdminOrdersOrderIdItemsItemIdCancellationRequests";

@Controller(
  "/ecommerce/admin/orders/:orderId/items/:itemId/cancellation-requests",
)
export class EcommerceAdminOrdersItemsCancellation_requestsController {
  /**
   * Search and retrieve cancellation requests for a specific order item within an order.
   *
   * Customers can view cancellation requests for their own order items. Sellers can view cancellation requests for order items they sell. Administrators can view all cancellation requests across the platform.
   *
   * Each order item can have at most one active cancellation request due to the unique constraint on ecommerce_order_item_id. The endpoint returns paginated results with optional status filtering.
   *
   * **Authorization**
   * - Customers: Can only view cancellation requests for their own orders
   * - Sellers: Can view cancellation requests for order items of products they sell
   * - Administrators: Can view all cancellation requests on the platform
   *
   * **Business Rules**
   * - Cancellation requests are only valid for order items with "paid" status
   * - Items with "shipped" or "delivered" status cannot have cancellation requests (use refund requests instead)
   * - Each order item can have at most one cancellation request at a time
   * - Cancellation request status: pending, approved, or rejected
   *
   * @param connection
   * @param orderId UUID of the parent order (global scope)
   * @param itemId UUID of the order item within the order (scoped to order)
   * @param body Search criteria including status filters and pagination parameters for retrieving cancellation requests.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_cancellation_requests table filtered by ecommerce_order_item_id. First verify the order item belongs to the specified order by joining ecommerce_order_items with ecommerce_orders. Check authorization: if customer, verify ecommerce_customer_id matches authenticated user; if seller, verify ecommerce_seller_id matches authenticated seller; if admin, allow all.
   *
   * Apply status filters from request body if provided (pending, approved, rejected). Apply pagination using cursor or offset-based pagination. Return IEcommerceCancellationRequest.ISummary for each result.
   *
   * Validate that the order item exists and has status "paid" for cancellation request eligibility. Return 404 if order or order item not found. Return 403 if user lacks authorization to view this cancellation request.
   *
   * Since each order item can have at most one cancellation request (unique constraint on ecommerce_order_item_id), the result set will contain 0 or 1 records typically.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceCancellationRequest.IRequest,
  ): Promise<IPageIEcommerceCancellationRequest.ISummary> {
    try {
      return await patchEcommerceAdminOrdersOrderIdItemsItemIdCancellationRequests(
        {
          admin,
          orderId,
          itemId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific cancellation request for an order item.
   *
   * This endpoint returns the complete details of a cancellation request including the customer's reason, current status, seller's response (if any), and timestamps. The cancellation request is accessed through its parent order and order item for contextual validation.
   *
   * **Access Control**
   * - Customers can view their own order item cancellation requests
   * - Sellers can view cancellation requests for their products
   * - Administrators can view all cancellation requests
   *
   * **Business Context**
   * - Cancellation requests are created when customers want to cancel order items with 'paid' status
   * - Status values: 'pending' (awaiting seller response), 'approved' (seller approved), 'rejected' (seller rejected)
   * - Only one cancellation request exists per order item (enforced by unique constraint)
   * - Approved requests trigger refund processing and stock restoration
   *
   * @param connection
   * @param orderId UUID of the parent order containing the order item (global scope).
   * @param itemId UUID of the order item with the cancellation request (scoped to order).
   * @param requestId UUID of the cancellation request to retrieve (scoped to order item).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_cancellation_requests table by requestId UUID.
   *
   * Validate the cancellation request belongs to the specified orderId and itemId:
   * 1. Load order item by itemId and verify its ecommerce_order_id matches orderId
   * 2. Verify the cancellation request's ecommerce_order_item_id matches itemId
   * 3. Return 404 if any resource not found or IDs don't match
   *
   * Authorization checks:
   * - If customer: verify ecommerce_order_id belongs to authenticated customer
   * - If seller: verify ecommerce_seller_id of order item belongs to authenticated seller
   * - If admin: allow access to all
   *
   * Return the cancellation request with embedded order item summary including product variant details and seller information for context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":requestId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceCancellationRequest> {
    try {
      return await getEcommerceAdminOrdersOrderIdItemsItemIdCancellationRequestsRequestId(
        {
          admin,
          orderId,
          itemId,
          requestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
