import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceOrderItemSnapshot } from "../../../../../../api/structures/IEcommerceOrderItemSnapshot";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { getEcommerceAdminOrdersOrderIdItemsItemIdSnapshot } from "../../../../../../providers/getEcommerceAdminOrdersOrderIdItemsItemIdSnapshot";

@Controller("/ecommerce/admin/orders/:orderId/items/:itemId/snapshot")
export class EcommerceAdminOrdersItemsSnapshotController {
  /**
   * Retrieves the point-in-time snapshot of a specific order item as it existed at the moment of purchase.
   *
   * This snapshot preserves the complete state of the purchased item including product name, description, base price, and seller profile information (shop name and logo) exactly as they appeared when the customer placed the order. These snapshots remain accessible even after the product is deleted, the variant is modified, or the seller's profile changes.
   *
   * **Access Control**
   *
   * - Order owners (customers who placed the order) can view snapshots of their own order items
   * - Administrators can view snapshots of any order item on the platform
   * - Unauthorized users receive an access denied error without revealing whether the snapshot exists
   *
   * **Use Cases**
   *
   * - Customers reviewing their purchase history to verify what they bought
   * - Dispute resolution when product details or seller information has changed since purchase
   * - Audit trail verification for compliance and quality assurance
   *
   * @param connection
   * @param orderId UUID of the parent order containing this item (global scope)
   * @param itemId UUID of the order item whose snapshot to retrieve (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_order_item_snapshots table by joining with ecommerce_order_items to validate ownership and authorization.
   *
   * **Implementation Steps**
   *
   * 1. Validate orderId and itemId are valid UUIDs
   * 2. Query ecommerce_order_items to verify the order item exists and belongs to the specified order
   * 3. Check authorization:
   *    - If authenticated as customer: verify ecommerce_order_items.ecommerce_customer_id matches the authenticated customer
   *    - If authenticated as admin: allow access regardless of ownership
   *    - If unauthorized: return 403 Forbidden without revealing if snapshot exists
   * 4. Join with ecommerce_order_item_snapshots using the 1:1 relationship
   * 5. Return the snapshot data with product_name, product_description, seller_shop_name, seller_logo_url, base_price, and created_at
   *
   * **Edge Cases**
   *
   * - Order item not found: return 404
   * - Snapshot not found (should not occur due to 1:1 constraint): return 404
   * - Unauthorized access: return 403 without revealing existence
   * - Invalid UUID format: return 400
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceOrderItemSnapshot> {
    try {
      return await getEcommerceAdminOrdersOrderIdItemsItemIdSnapshot({
        admin,
        orderId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
