import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceAdministratorGrade } from "../../../../api/structures/IEcommerceAdministratorGrade";
import { IPageIEcommerceAdministratorGrade } from "../../../../api/structures/IPageIEcommerceAdministratorGrade";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceAdminGradesAdminId } from "../../../../providers/getEcommerceAdminGradesAdminId";
import { patchEcommerceAdminGrades } from "../../../../providers/patchEcommerceAdminGrades";
import { postEcommerceAdminGrades } from "../../../../providers/postEcommerceAdminGrades";
import { putEcommerceAdminGradesAdminId } from "../../../../providers/putEcommerceAdminGradesAdminId";

@Controller("/ecommerce/admin/grades")
export class EcommerceAdminGradesController {
  /**
   * Create a new administrator grade assignment for promoting or assigning grade levels to administrators.
   *
   * This operation allows super administrators to assign grade levels (regular or super) to administrator accounts. Grade assignments determine the permission boundaries and capabilities of each administrator within the platform.
   *
   * ## Grade Levels
   *
   * - **regular** — Standard administrator with permissions to approve sellers, manage categories, oversee products and orders, and manage user accounts
   * - **super** — Super administrator with elevated privileges including the ability to promote and demote other administrators
   *
   * ## Authorization
   *
   * Only super administrators can create grade assignments. Regular administrators cannot modify administrator grades.
   *
   * ## Business Rules
   *
   * - Each administrator can have exactly one active grade assignment at any time
   * - Grade changes take effect immediately upon creation
   * - All grade assignments are recorded in the audit trail for compliance
   * - Self-demotion is not allowed (though this operation is for creation/promotion)
   *
   * @param connection
   * @param body Grade assignment creation request containing the target administrator ID and the grade level to assign.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Create administrator grade assignment with the
     *   following implementation logic:
   *
   * 1. **Authorization Check**: Verify the requesting administrator has super grade level. Return 403 Forbidden if regular administrator.
   *
   * 2. **Validate Request Body**:
   *    - ecommerce_admin_id must reference an existing, non-deleted administrator
   *    - grade must be either 'regular' or 'super'
   *    - Check that the target administrator does not already have an active grade assignment (no deleted_at on existing grade record)
   *
   * 3. **Create Grade Assignment**:
   *    - Insert new record into ecommerce_administrator_grades table
   *    - Set ecommerce_admin_id, grade, created_at, updated_at
   *    - deleted_at remains null for active assignment
   *
   * 4. **Audit Trail**:
   *    - Grade assignment creation is automatically tracked
   *    - For grade promotions/demotions, also create entry in ecommerce_admin_grade_transitions table
   *    - Include performing administrator ID, target administrator ID, previous grade (if exists), new grade, and timestamp
   *
   * 5. **Response**: Return the created grade assignment with full entity details
   *
   * 6. **Error Handling**:
   *    - 400 Bad Request: Invalid grade value or missing required fields
   *    - 403 Forbidden: Requesting administrator is not super grade
   *    - 404 Not Found: Target administrator does not exist or is deleted
   *    - 409 Conflict: Administrator already has an active grade assignment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceAdministratorGrade.ICreate,
  ): Promise<IEcommerceAdministratorGrade> {
    try {
      return await postEcommerceAdminGrades({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of administrator grade assignments with optional filtering.
   *
   * This endpoint allows administrators to browse current grade assignments across the platform. Each record shows which administrator holds which grade level (regular or super) and when the assignment was created or updated.
   *
   * **Grade Levels**
   *
   * - `regular` - Standard administrator with permissions to approve sellers, manage categories, oversee products/orders, and manage user accounts
   * - `super` - Super administrator with additional permissions to promote/demote other administrators
   *
   * **Filtering Capabilities**
   *
   * Administrators can filter by grade level, search by administrator email, and filter by creation/update date ranges. Pagination parameters control the number of results and cursor position.
   *
   * **Access Control**
   *
   * This operation requires administrator authentication. Both regular and super administrators can view grade assignments, but only super administrators can modify them through separate grade management endpoints.
   *
   * @param connection
   * @param body Search criteria for filtering administrator grade assignments including grade level, administrator email, date ranges, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query ecommerce_administrator_grades table with
     *   optional filtering and pagination.
   *
   * **Implementation Steps**
   *
   * 1. Validate requesting user is an authenticated administrator
   * 2. Build query on ecommerce_administrator_grades with joins to ecommerce_admins for email lookup
   * 3. Apply filters from request body:
   *    - grade: filter by grade level (regular/super)
   *    - adminEmail: search by administrator email (partial match)
   *    - createdAtFrom/createdAtTo: filter by creation date range
   *    - updatedAtFrom/updatedAtTo: filter by update date range
   * 4. Apply sorting (default: created_at DESC)
   * 5. Apply pagination using cursor-based or offset-based approach
   * 6. Return paginated summary with total count and navigation cursors
   *
   * **Edge Cases**
   *
   * - Empty result set: return empty items array with zero count
   * - Invalid grade filter value: return 400 Bad Request
   * - Administrator not authenticated: return 401 Unauthorized
   * - Administrator grade insufficient: return 403 Forbidden (though viewing is allowed for all admins)
   *
   * **Performance Considerations**
   *
   * - Use database indexes on ecommerce_admin_id, grade, created_at, updated_at
   * - Limit maximum page size to prevent excessive data retrieval
   * - Consider caching for frequently accessed grade lists
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceAdministratorGrade.IRequest,
  ): Promise<IPageIEcommerceAdministratorGrade.ISummary> {
    try {
      return await patchEcommerceAdminGrades({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the current grade assignment for a specific administrator.
   *
   * This endpoint returns the administrator's active grade level (regular or super) along with audit timestamps. The grade determines the administrator's permission boundaries and what actions they can perform on the platform.
   *
   * **Grade Levels**
   *
   * - `regular` — Standard administrator with permissions to approve sellers, manage categories, oversee products/orders, and manage user accounts
   * - `super` — Super administrator with additional permissions to promote/demote other administrators and manage the administrator system
   *
   * **Authorization**
   *
   * Only authenticated administrators can access this endpoint. The requesting administrator must have sufficient privileges to view grade information.
   *
   * **Related Operations**
   *
   * - Grade promotion/demotion: Requires super administrator privileges
   * - Grade transition history: Available through audit trail endpoints
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the ecommerce_administrator_grades table by
     *   ecommerce_admin_id to retrieve the current grade assignment.
   *
   * Implementation steps:
   * 1. Validate adminId parameter is a valid UUID format
   * 2. Query ecommerce_administrator_grades where ecommerce_admin_id = {adminId} and deleted_at IS NULL
   * 3. Join with ecommerce_admins to verify the administrator account exists and is not deleted
   * 4. Return the grade record with grade level, admin reference, and timestamps
   * 5. Return 404 if no active grade assignment exists for the given adminId
   *
   * Business rules:
   * - Only return non-deleted grade assignments (deleted_at IS NULL)
   * - Each administrator has exactly one active grade assignment due to unique constraint
   * - Grade values are restricted to 'regular' or 'super' only
   *
   * Error handling:
   * - 404 Not Found: No grade assignment exists for the given adminId
   * - 400 Bad Request: Invalid UUID format for adminId
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceAdministratorGrade> {
    try {
      return await getEcommerceAdminGradesAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an administrator's grade assignment between regular and super administrator levels.
   *
   * This operation allows super administrators to modify the grade level of other administrators, enabling promotions from regular to super administrator or demotions from super to regular administrator. Grade changes take effect immediately and are recorded in the audit trail for compliance purposes.
   *
   * **Authorization Requirements**
   *
   * Only super administrators can perform grade modifications. Regular administrators cannot change any administrator grades, including their own. A super administrator cannot demote themselves to prevent abuse of power and ensure accountability in the promotion/demotion process.
   *
   * **Grade Level Rules**
   *
   * - Regular administrators can be promoted to super administrator
   * - Super administrators can be demoted to regular administrator
   * - Self-demotion is prohibited for super administrators
   * - Grade changes are immediately effective upon successful update
   *
   * @param connection
   * @param adminId UUID identifier of the administrator whose grade is being updated (scoped to administrator account)
   * @param body New grade assignment for the administrator. Must be either 'regular' or 'super'. Super administrators can promote regular admins to super or demote other super admins to regular, but cannot demote themselves.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Implement grade update with the following logic:
   *
   * 1. **Authentication & Authorization**
   *    - Verify the requesting administrator is authenticated via session token
   *    - Check the administrator's current grade from ecommerce_administrator_grades table
   *    - Reject with 403 Forbidden if the administrator is not a super administrator
   *    - Reject with 400 Bad Request if the administrator attempts to demote themselves (current adminId equals target adminId and grade is being changed from super to regular)
   *
   * 2. **Record Retrieval**
   *    - Query ecommerce_administrator_grades table by adminId
   *    - Verify the grade record exists and is not soft-deleted
   *    - Return 404 Not Found if the administrator does not exist or grade record is missing
   *
   * 3. **Grade Validation**
   *    - Validate the new grade value is either 'regular' or 'super'
   *    - Reject with 400 Bad Request if grade value is invalid
   *
   * 4. **Update Operation**
   *    - Update the grade field in ecommerce_administrator_grades table
   *    - Update the updated_at timestamp to current time
   *    - Create a corresponding record in ecommerce_admin_grade_transitions table with:
   *      - Old grade value
   *      - New grade value
   *      - Administrator who performed the change
   *      - Timestamp of change
   *    - Use database transaction to ensure atomicity of grade update and transition record creation
   *
   * 5. **Response**
   *    - Return the updated grade record with all fields
   *    - Include the new grade value, updated_at timestamp, and related admin information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceAdministratorGrade.IUpdate,
  ): Promise<IEcommerceAdministratorGrade> {
    try {
      return await putEcommerceAdminGradesAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
