import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceReport } from "../../../../api/structures/IEcommerceReport";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { postEcommerceAdminReports } from "../../../../providers/postEcommerceAdminReports";

@Controller("/ecommerce/admin/reports")
export class EcommerceAdminReportsController {
  /**
   * Generate business reports with aggregated statistics across orders, products, customers, and sellers.
   *
   * This endpoint supports multiple report types including sales reports, inventory reports, customer analytics, and seller performance metrics. The request body specifies the report type, date range filters, grouping options, and aggregation parameters.
   *
   * **Report Types**
   *
   * - `sales`: Total sales revenue, order counts, average order value grouped by date, category, or seller
   * - `inventory`: Stock levels, inventory movements, out-of-stock alerts for product variants
   * - `customer`: Customer acquisition, order frequency, lifetime value metrics
   * - `seller`: Seller performance, product counts, order fulfillment metrics
   *
   * **Filtering and Grouping**
   *
   * Reports can be filtered by date ranges, specific sellers, categories, order statuses, and customer segments. Results can be grouped by various dimensions (date, category, seller, product) and sorted by different metrics.
   *
   * **Access Control**
   *
   * - Customers can only access their own order and product reports
   * - Sellers can access reports for their own products and orders
   * - Administrators can access platform-wide reports across all entities
   *
   * @param connection
   * @param body Report generation request with report type, date range filters, grouping options, and aggregation parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Implement multi-table aggregation query for
     *   report generation.
   *
   * **Service Logic**
   *
   * 1. Validate report type and filter parameters from request body
   * 2. Apply authorization checks based on actor type:
   *    - Customer: filter by ecommerce_customer_id
   *    - Seller: filter by seller_id through product relationships
   *    - Admin: no filtering (platform-wide)
   * 3. Execute aggregation queries across ecommerce_orders, ecommerce_order_items, ecommerce_products, ecommerce_customers, ecommerce_sellers, ecommerce_inventory_records
   * 4. Apply date range filters on created_at fields
   * 5. Group results by specified dimension (date, category, seller, product)
   * 6. Calculate aggregated metrics (sum, count, average)
   * 7. Apply pagination if requested
   * 8. Return formatted report data
   *
   * **Database Queries**
   *
   * - JOIN orders with order_items to get line item details
   * - JOIN with products to get category and product information
   * - JOIN with sellers for seller-specific metrics
   * - LEFT JOIN with inventory_records for stock analysis
   * - Use GROUP BY for aggregation dimensions
   * - Use SUM, COUNT, AVG for metric calculations
   *
   * **Business Rules**
   *
   * - Date range must be valid (start_date <= end_date)
   * - Maximum date range: 365 days for performance
   * - Report generation should timeout after 30 seconds
   * - Cache frequently requested reports for 5 minutes
   *
   * **Error Handling**
   *
   * - Invalid report type: 400 Bad Request
   * - Invalid date range: 400 Bad Request
   * - Unauthorized access: 403 Forbidden
   * - Report generation timeout: 504 Gateway Timeout
   * - No data for filters: 200 OK with empty results
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async generate(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceReport.IRequest,
  ): Promise<IEcommerceReport> {
    try {
      return await postEcommerceAdminReports({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
