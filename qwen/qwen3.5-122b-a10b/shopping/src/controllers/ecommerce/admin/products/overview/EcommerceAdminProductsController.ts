import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceProduct } from "../../../../../api/structures/IEcommerceProduct";
import { IPageIEcommerceProduct } from "../../../../../api/structures/IPageIEcommerceProduct";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchEcommerceAdminProductsOverview } from "../../../../../providers/patchEcommerceAdminProductsOverview";

@Controller("/ecommerce/admin/products/overview")
export class EcommerceAdminProductsController {
  /**
   * Retrieve a paginated list of product summaries for customer browsing and discovery with advanced filtering.
   *
   * This endpoint returns product listings with essential information including product name, base price, main image, seller shop name, and average rating. Products are filtered to show only active (non-deleted) products.
   *
   * **Features**
   * - Paginated product listings with configurable page size
   * - Filter by category for browsing products by category hierarchy
   * - Filter by price range (minimum and maximum)
   * - Filter by stock availability (in-stock only)
   * - Sort by newest first, price low to high, or price high to low
   * - Product listings display main thumbnail image, name, price, seller shop name, and average rating
   *
   * **Access**
   * - Available to all customers (member role)
   * - No authentication required for browsing
   * - Shows products from all sellers on the platform
   *
   * **Related Operations**
   * - Use GET /products/{productId} for detailed product information including all images, variants, and reviews
   * - Use GET /products/overview without filters for basic product listing
   *
   * @param connection
   * @param body Search criteria for filtering, sorting, and paginating product listings. Includes optional category filter, price range, stock availability, sort order, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_products table for active products (deleted_at IS NULL). Join with ecommerce_sellers for shop name and ecommerce_categories for category information. Join with ecommerce_reviews to calculate average rating (AVG of rating where deleted_at IS NULL). Join with ecommerce_product_images to get main thumbnail image (display_order = 0). Join with ecommerce_product_variants to check stock availability (sum of inventory records). Apply pagination with cursor or offset-based pagination. Apply filters from request body: categoryId, minPrice, maxPrice, inStockOnly. Apply sorting: created_at DESC (newest), base_price ASC, or base_price DESC. Return paginated summary with product id, name, base_price, main_image_url, seller_shop_name, average_rating, stock_status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async overview(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceProduct.IRequest,
  ): Promise<IPageIEcommerceProduct.ISummary> {
    try {
      return await patchEcommerceAdminProductsOverview({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
