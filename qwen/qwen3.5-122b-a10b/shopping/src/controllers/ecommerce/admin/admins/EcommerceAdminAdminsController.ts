import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceAdmin } from "../../../../api/structures/IEcommerceAdmin";
import { IPageIEcommerceAdmin } from "../../../../api/structures/IPageIEcommerceAdmin";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceAdminAdminsAdminId } from "../../../../providers/getEcommerceAdminAdminsAdminId";
import { patchEcommerceAdminAdmins } from "../../../../providers/patchEcommerceAdminAdmins";

@Controller("/ecommerce/admin/admins")
export class EcommerceAdminAdminsController {
  /**
   * Retrieve a paginated list of administrator accounts with optional filtering and sorting.
   *
   * This endpoint allows administrators to browse all platform administrator accounts for oversight and management purposes. The response includes administrator summaries with their current grade level (regular or super).
   *
   * **Filtering Capabilities**
   *
   * Administrators can filter by email partial match, grade level (regular or super), and account status (active or deleted). Date range filters are available for creation and update timestamps.
   *
   * **Sorting Options**
   *
   * Results can be sorted by email, created_at, or updated_at in ascending or descending order. Default sorting is by created_at descending (newest first).
   *
   * **Pagination**
   *
   * Cursor-based pagination is supported with configurable page size (default 20, maximum 100). The response includes pagination metadata for navigating through results.
   *
   * **Access Control**
   *
   * Only authenticated administrators can access this endpoint. Both regular and super administrators have equal access to view administrator accounts.
   *
   * @param connection
   * @param body Search criteria for filtering, sorting, and paginating administrator accounts. Includes optional email partial match, grade level filter, status filter, date range filters, sorting parameters, and pagination settings.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_admins table joined with ecommerce_administrator_grades to retrieve administrator accounts with their current grade levels.
   *
   * **Implementation Steps**
   *
   * 1. Validate authenticated administrator has admin actor permissions
   * 2. Build query with optional filters from request body:
   *    - email: partial match (ILIKE) on email column
   *    - grade: exact match on grade column in ecommerce_administrator_grades
   *    - status: filter by deleted_at IS NULL (active) or IS NOT NULL (deleted)
   *    - created_at_from, created_at_to: date range filters
   *    - updated_at_from, updated_at_to: date range filters
   * 3. Apply sorting based on sort_by and sort_order parameters
   * 4. Apply cursor-based pagination using created_at/id as cursor
   * 5. Join with ecommerce_administrator_grades to include grade information
   * 6. Exclude password_hash from all responses
   * 7. Return paginated summary with metadata
   *
   * **Business Rules**
   *
   * - Password hashes must NEVER be included in responses
   * - Soft-deleted administrators should be filterable but excluded by default
   * - Grade information comes from the active grade record (not soft-deleted)
   * - Pagination cursor should use composite key (created_at, id) for consistent ordering
   *
   * **Error Handling**
   *
   * - Return 401 if not authenticated as administrator
   * - Return 400 for invalid filter values or pagination parameters
   * - Return 400 if sort_by field is not allowed
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceAdmin.IRequest,
  ): Promise<IPageIEcommerceAdmin.ISummary> {
    try {
      return await patchEcommerceAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific administrator account including their current grade level.
   *
   * This endpoint provides comprehensive administrator profile data including email, grade level (regular or super), and account timestamps. The grade information is fetched from the administrator grades table and included in the response.
   *
   * **Access Control**
   *
   * Only authenticated administrators can access this endpoint. The requesting administrator must have valid authentication credentials. Both regular and super administrators can view any administrator's details.
   *
   * **Response Data**
   *
   * The response includes the administrator's email, current grade level, account creation and update timestamps, and deletion status. Password hashes are never exposed in API responses.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_admins table by UUID id parameter. Join with ecommerce_administrator_grades table on ecommerce_admin_id to retrieve the current grade level. Filter out soft-deleted administrators (deleted_at IS NOT NULL) and return 404 Not Found if the admin does not exist or has been deleted. Validate that the requesting user is an authenticated administrator. Return the admin entity with grade information merged into a single response object. Do not expose password_hash field in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceAdmin> {
    try {
      return await getEcommerceAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
