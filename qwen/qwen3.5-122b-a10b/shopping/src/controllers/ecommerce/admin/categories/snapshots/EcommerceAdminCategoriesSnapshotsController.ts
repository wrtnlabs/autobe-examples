import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceCategorySnapshot } from "../../../../../api/structures/IEcommerceCategorySnapshot";
import { IPageIEcommerceCategorySnapshot } from "../../../../../api/structures/IPageIEcommerceCategorySnapshot";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceAdminCategoriesCategoryIdSnapshotsSnapshotId } from "../../../../../providers/getEcommerceAdminCategoriesCategoryIdSnapshotsSnapshotId";
import { patchEcommerceAdminCategoriesCategoryIdSnapshots } from "../../../../../providers/patchEcommerceAdminCategoriesCategoryIdSnapshots";

@Controller("/ecommerce/admin/categories/:categoryId/snapshots")
export class EcommerceAdminCategoriesSnapshotsController {
  /**
   * Retrieve paginated snapshot history for a specific category, showing all historical states before modifications.
   *
   * This operation returns a chronological list of category snapshots, each capturing the category's state (name, description, parent category) before a modification occurred. Snapshots are immutable audit trail records created automatically whenever a category is edited.
   *
   * **Access Control**: Only administrators can access this endpoint. Regular customers and sellers cannot view category snapshots.
   *
   * **Pagination**: Results are returned in pages with cursor-based or offset-based pagination. Each snapshot includes the timestamp when it was created and the category state at that point in time.
   *
   * **Filtering**: Support filtering by date range to find snapshots within a specific time period.
   *
   * @param connection
   * @param categoryId Unique identifier of the category whose snapshot history to retrieve (UUID format).
   * @param body Search criteria for filtering category snapshots including date range filters, pagination parameters, and sort order preferences.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_category_snapshots table filtered by ecommerce_category_id matching the categoryId path parameter.
   *
   * Implement pagination with configurable page size (default 20, max 100). Support cursor-based or offset-based pagination.
   *
   * Apply date range filters on created_at field if provided in request body.
   *
   * Order results by created_at descending (newest snapshots first) by default, with support for ascending order.
   *
   * Verify category exists before returning snapshots. Return 404 if category not found.
   *
   * Enforce administrator-only access via authentication middleware.
   *
   * Include snapshot count and pagination metadata in response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceCategorySnapshot.IRequest,
  ): Promise<IPageIEcommerceCategorySnapshot.ISummary> {
    try {
      return await patchEcommerceAdminCategoriesCategoryIdSnapshots({
        admin,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific historical snapshot of a category for audit and dispute resolution purposes.
   *
   * This endpoint returns the state of a category at a specific point in time before a modification occurred. Each snapshot preserves the category name, description, and parent category reference as they existed before the change.
   *
   * **Use Cases**
   * - Administrators reviewing category modification history
   * - Dispute resolution requiring historical category state verification
   * - Compliance audits tracking category changes over time
   *
   * **Access Control**
   * This operation requires administrator authentication. Only administrators with appropriate privileges can access category snapshots.
   *
   * @param connection
   * @param categoryId Unique identifier of the parent category (UUID format)
   * @param snapshotId Unique identifier of the snapshot record to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_category_snapshots table by snapshotId. Verify the snapshot belongs to the specified categoryId by checking ecommerce_category_id foreign key. Return the snapshot record including name, description, parent_category_id, and created_at. If snapshot not found or does not belong to the category, return 404 Not Found. This operation is read-only and does not modify any data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceCategorySnapshot> {
    try {
      return await getEcommerceAdminCategoriesCategoryIdSnapshotsSnapshotId({
        admin,
        categoryId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
