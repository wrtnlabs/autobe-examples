import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceAdminRequest } from "../../../../api/structures/IEcommerceAdminRequest";
import { IPageIEcommerceAdminRequest } from "../../../../api/structures/IPageIEcommerceAdminRequest";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceAdminRequestsRequestId } from "../../../../providers/getEcommerceAdminRequestsRequestId";
import { patchEcommerceAdminRequests } from "../../../../providers/patchEcommerceAdminRequests";
import { putEcommerceAdminRequestsRequestId } from "../../../../providers/putEcommerceAdminRequestsRequestId";

@Controller("/ecommerce/admin/requests")
export class EcommerceAdminRequestsController {
  /**
   * Retrieve a paginated list of administrator access requests with filtering and sorting capabilities.
   *
   * This endpoint allows administrators to search and browse all administrator access requests submitted by customers or sellers. Requests can be filtered by status (pending, approved, rejected), requester type (customer or seller), and date ranges. The response includes request details along with applicant information and review status.
   *
   * **Access Control**
   *
   * Only authenticated administrators can access this endpoint. Super administrators can view all requests across all requester types. Regular administrators may have restricted access based on their grade level and assigned permissions.
   *
   * **Request Filtering**
   *
   * Supports filtering by request status, requester type, creation date range, review date range, and pagination parameters. Multiple filters can be combined to narrow down results.
   *
   * **Response Structure**
   *
   * Returns a paginated summary of admin requests with applicant details, current status, and review information. Full request details are available through the detail endpoint.
   *
   * @param connection
   * @param body Search criteria for filtering administrator requests including status, requester type, date ranges, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query ecommerce_admin_requests table with
     *   pagination and filtering. Apply search filters on status
     *   (pending/approved/rejected), requester_type (customer/seller), date
     *   ranges (created_at, reviewed_at). Join with ecommerce_customers or
     *   ecommerce_sellers based on requester_type to retrieve applicant
     *   information. Join with ecommerce_admins for reviewer information when
     *   reviewed_by_id is present. Return cursor-based pagination for large
     *   result sets. Only administrators with appropriate grade can access this
     *   endpoint. Super administrators can view all requests; regular
     *   administrators may have restricted access based on business rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceAdminRequest.IRequest,
  ): Promise<IPageIEcommerceAdminRequest.ISummary> {
    try {
      return await patchEcommerceAdminRequests({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single administrator request by its unique identifier.
   *
   * This operation returns the complete details of an administrator request including the applicant's information, reason for requesting access, current approval status, and any review details if the request has been processed by a super administrator.
   *
   * ## Requester Information
   *
   * The request includes details about who submitted the request (either a customer or seller), identified by the requester_type field and the corresponding customer_id or seller_id.
   *
   * ## Status Information
   *
   * The response includes the current status of the request (pending, approved, or rejected). If the request has been reviewed, it includes the reviewing administrator's information, review timestamp, and rejection reason if applicable.
   *
   * ## Authorization
   *
   * This operation requires administrator authentication. Only administrators can view administrator request details.
   *
   * @param connection
   * @param requestId The unique identifier of the administrator request to retrieve (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Retrieve a single admin request record from
     *   ecommerce_admin_requests table by id (UUID).
   *
   * Validate that the authenticated user is an administrator.
   * Return 404 if the request ID does not exist.
   * Return 403 if the user lacks permission to view admin requests.
   *
   * Include joined data for requester information (customer or seller based on requester_type).
   * Include joined data for reviewing administrator if reviewed_by_id is present.
   *
   * Response should include all fields: id, requester_customer_id, requester_seller_id, requester_type, reason, status, rejection_reason, reviewed_by_id, reviewed_at, created_at, updated_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":requestId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceAdminRequest> {
    try {
      return await getEcommerceAdminRequestsRequestId({
        admin,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an administrator request status by approving or rejecting it.
   *
   * This operation allows super administrators to review pending administrator requests and make approval decisions. When approving, the user is granted regular administrator grade access. When rejecting, a reason must be provided to inform the applicant.
   *
   * The requester can be either a customer or seller, identified by the requester_type field and the corresponding customer_id or seller_id foreign key.
   *
   * ## Approval Process
   *
   * When status is set to 'approved', the requesting user immediately becomes a regular administrator with access to administrator operations. The reviewed_by_id and reviewed_at fields are automatically populated.
   *
   * ## Rejection Process
   *
   * When status is set to 'rejected', the rejection_reason field becomes required. The user remains in their current role (customer or seller) and can submit a new request with a different reason after rejection.
   *
   * ## Validation Rules
   *
   * - Only super administrators can perform this operation
   * - The request must be in 'pending' status to be updated
   * - rejection_reason is required when status is 'rejected'
   * - A user cannot have multiple pending administrator requests simultaneously
   *
   * @param connection
   * @param requestId Unique identifier of the administrator request to update (UUID format).
   * @param body Update payload containing the new approval status and optional rejection reason for administrator review decisions.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Implement PUT /requests/{requestId} for
     *   administrator request approval workflow.
   *
   * ## Implementation Steps
   *
   * 1. **Authentication & Authorization**
   *    - Verify the caller is a super administrator (admin grade = 'super')
   *    - Reject with 403 Forbidden if not authorized
   *
   * 2. **Request Validation**
   *    - Validate requestId is a valid UUID format
   *    - Validate status is one of: 'pending', 'approved', 'rejected'
   *    - Validate rejection_reason is provided when status is 'rejected'
   *    - Validate status is currently 'pending' (cannot update already resolved requests)
   *
   * 3. **Database Query**
   *    - Fetch the admin request by id
   *    - Verify the request exists and is in 'pending' status
   *    - Check for duplicate pending requests by the same user (requester_type + requester_customer_id or requester_seller_id)
   *
   * 4. **Update Logic**
   *    - Set status to the new value ('approved' or 'rejected')
   *    - Set reviewed_by_id to the current administrator's id
   *    - Set reviewed_at to current timestamp
   *    - Set rejection_reason if status is 'rejected'
   *    - Set updated_at to current timestamp
   *
   * 5. **Post-Update Actions**
   *    - If approved: Update the requesting user's grade to 'regular' administrator
   *    - If rejected: No additional action needed
   *
   * 6. **Error Handling**
   *    - 404 Not Found: Request ID does not exist
   *    - 409 Conflict: Request is not in 'pending' status or duplicate pending request exists
   *    - 400 Bad Request: Invalid status value or missing rejection_reason
   *    - 403 Forbidden: Caller is not a super administrator
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":requestId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceAdminRequest.IUpdate,
  ): Promise<IEcommerceAdminRequest> {
    try {
      return await putEcommerceAdminRequestsRequestId({
        admin,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
