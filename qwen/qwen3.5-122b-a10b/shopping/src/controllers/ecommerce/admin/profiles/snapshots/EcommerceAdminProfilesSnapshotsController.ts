import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIEcommerceSellerSnapshot } from "../../../../../api/structures/IPageIEcommerceSellerSnapshot";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceAdminProfilesProfileIdSnapshots } from "../../../../../providers/getEcommerceAdminProfilesProfileIdSnapshots";

@Controller("/ecommerce/admin/profiles/:profileId/snapshots")
export class EcommerceAdminProfilesSnapshotsController {
  /**
   * Retrieve the complete history of seller profile snapshots for audit and dispute resolution.
   *
   * This endpoint returns all historical snapshots of a seller's shop profile, including shop name, description, and logo image URL at each point in time when changes were made. Snapshots are immutable records created automatically whenever the seller edits their profile.
   *
   * ## Access Control
   *
   * Only the seller who owns the profile or platform administrators can access snapshot history. Customers viewing seller profiles can see current information but cannot access historical snapshots. Unauthorized access attempts are denied with 403 status without revealing whether snapshots exist.
   *
   * ## Snapshot Contents
   *
   * Each snapshot contains the complete profile state at the time of modification: shop name, shop description (nullable), and logo image URL (nullable). Snapshots are ordered chronologically with the most recent first.
   *
   * ## Pagination
   *
   * Results support pagination via query parameters for efficient browsing of long snapshot histories. Include page size and cursor parameters in the query string to control result set.
   *
   * @param connection
   * @param profileId UUID of the seller profile whose snapshot history to retrieve. Must belong to an existing seller account.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query ecommerce_seller_snapshots table by seller
     *   profile ID with pagination support.
   *
   * Authorization checks:
   * - Verify authenticated user is either the profile owner (seller) or has admin privileges
   * - Deny access with 403 if unauthorized (per Section 364)
   * - Do not reveal whether snapshot exists if access denied
   *
   * Database queries:
   * - Join ecommerce_seller_profiles to verify profile existence
   * - Query ecommerce_seller_snapshots filtered by ecommerce_seller_id from profile
   * - Order by created_at DESC (most recent first)
   * - Apply pagination using query parameters (page, limit, cursor)
   *
   * Business rules:
   * - Snapshots are immutable - no filtering by deleted_at needed
   * - Include all snapshot fields: shop_name, shop_description, logo_url, created_at
   * - Return summary projection optimized for list display
   *
   * Error handling:
   * - 404 if profile does not exist
   * - 403 if unauthorized (seller or admin only)
   * - 400 if invalid pagination parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async list(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("profileId")
    profileId: string & tags.Format<"uuid">,
  ): Promise<IPageIEcommerceSellerSnapshot.ISummary> {
    try {
      return await getEcommerceAdminProfilesProfileIdSnapshots({
        admin,
        profileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
