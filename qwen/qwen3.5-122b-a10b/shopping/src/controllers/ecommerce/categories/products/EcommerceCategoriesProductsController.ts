import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceProduct } from "../../../../api/structures/IEcommerceProduct";
import { IPageIEcommerceProduct } from "../../../../api/structures/IPageIEcommerceProduct";
import { patchEcommerceCategoriesCategoryIdProducts } from "../../../../providers/patchEcommerceCategoriesCategoryIdProducts";

@Controller("/ecommerce/categories/:categoryId/products")
export class EcommerceCategoriesProductsController {
  /**
   * Retrieve a paginated list of products belonging to a specific category or its subcategories.
   *
   * This operation returns all active products assigned to the specified category, including products from any subcategories. Products are filtered to exclude soft-deleted items and are returned with pagination support for efficient browsing.
   *
   * **Features**
   * - Lists products within a category hierarchy (category + subcategories)
   * - Supports pagination with cursor-based navigation
   * - Includes seller information for each product
   * - Filters out soft-deleted products
   * - Supports sorting by name, creation date, and price
   *
   * **Security**
   * - No authentication required for browsing
   * - Public access for customer product discovery
   *
   * **Relationships**
   * - Products reference the category via category_id foreign key
   * - Each product includes owner seller information
   * - Subcategory products are included in results
   *
   * @param connection
   * @param categoryId Unique identifier of the category (UUID scope). Products from this category and its subcategories will be returned.
   * @param body Search criteria including pagination parameters, sorting options, and optional filters for product name and price range.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query ecommerce_products table filtered by
     *   category_id. Include products from subcategories by joining with parent
     *   category. Apply soft-delete filter (deleted_at IS NULL). Implement
     *   cursor-based pagination with limit/offset. Support sorting by
     *   created_at, name, base_price. Join with ecommerce_sellers for seller
     *   information. Validate category exists and is not soft-deleted. Return
     *   paginated product summaries with seller details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProduct.IRequest,
  ): Promise<IPageIEcommerceProduct.ISummary> {
    try {
      return await patchEcommerceCategoriesCategoryIdProducts({
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
