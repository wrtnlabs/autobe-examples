import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceCategory } from "../../../api/structures/IEcommerceCategory";
import { IPageIEcommerceCategory } from "../../../api/structures/IPageIEcommerceCategory";
import { getEcommerceCategoriesCategoryId } from "../../../providers/getEcommerceCategoriesCategoryId";
import { patchEcommerceCategories } from "../../../providers/patchEcommerceCategories";

@Controller("/ecommerce/categories")
export class EcommerceCategoriesController {
  /**
   * Retrieve a paginated list of product categories with optional filtering and sorting.
   *
   * This endpoint returns categories organized in a two-level hierarchy (root categories and subcategories). Each category includes its name, description, parent relationship, and timestamps. Administrators use this endpoint to browse and manage the category structure.
   *
   * **Key Features**
   * - Pagination support with cursor-based navigation
   * - Filter by name (partial match using trigram index)
   * - Filter by parent category to view subcategories
   * - Sort by name, created_at, or updated_at
   * - Includes both root categories and subcategories in results
   *
   * **Security**
   * - Requires administrator authentication
   * - Returns all categories visible to platform administrators
   *
   * **Relationships**
   * - Each category may have a parent category (null for root categories)
   * - Categories can have multiple subcategories (children)
   * - Products reference categories for browsing and filtering
   *
   * @param connection
   * @param body Search criteria including name filter (partial match), parent category filter, date range filters, pagination parameters (limit, cursor/offset), and sorting options (field and direction).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_categories table with soft delete filter (deleted_at IS NULL). Apply search filters from request body: name (trigram partial match using gin_trgm_ops index), parent_id (filter by parent category to get subcategories), date ranges on created_at/updated_at. Support pagination with cursor or offset-based navigation. Sort by name, created_at, or updated_at with ascending/descending order. Join not required for basic listing. For category details with product counts, optionally aggregate from ecommerce_products table. Enforce administrator authentication via middleware. Return IPageIEcommerceCategory.ISummary with category summaries optimized for list displays.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommerceCategory.IRequest,
  ): Promise<IPageIEcommerceCategory.ISummary> {
    try {
      return await patchEcommerceCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single category by its unique identifier.
   *
   * This operation returns the complete category entity including its name, description, parent category reference (if any), and nested subcategories. Categories form a two-level hierarchy where root categories have no parent and subcategories belong to exactly one parent category.
   *
   * **Access Control**
   * - Customers: Can view any category for product browsing
   * - Sellers: Can view any category for product categorization
   * - Administrators: Can view any category for management purposes
   *
   * **Related Resources**
   * - Products assigned to this category can be retrieved separately
   * - Parent category (if exists) is included in the response
   * - Subcategories are included as an array of category summaries
   *
   * @param connection
   * @param categoryId Unique identifier of the category to retrieve (UUID format, global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the ecommerce_categories table by id (UUID primary key). Include the parent category relationship (parent_id) with full parent category details. Include subcategories array with child category summaries. Apply soft-delete filter (deleted_at IS NULL) to exclude deleted categories. Return 404 if category not found or has been deleted. Join with parent category using LEFT JOIN on parent_id. Order subcategories by created_at ascending.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async at(
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceCategory> {
    try {
      return await getEcommerceCategoriesCategoryId({
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
