import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceProduct } from "../../../../api/structures/IEcommerceProduct";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteEcommerceSellerProductsProductId } from "../../../../providers/deleteEcommerceSellerProductsProductId";
import { postEcommerceSellerProducts } from "../../../../providers/postEcommerceSellerProducts";
import { putEcommerceSellerProductsProductId } from "../../../../providers/putEcommerceSellerProductsProductId";

@Controller("/ecommerce/seller/products")
export class EcommerceSellerProductsController {
  /**
   * Creates a new product listing for the authenticated seller's shop.
   *
   * This operation allows sellers to add new products to their inventory. The product becomes immediately active and visible in search results and category listings upon creation.
   *
   * **Required Fields**
   * - Product name: Required, displayed in search results and listings
   * - Description: Required, provides product details to customers
   * - Category ID: Required, must reference an existing category
   * - Base price: Required, the default selling price
   *
   * **Optional Fields**
   * - Variants: Array of SKU variants with option values and optional price overrides
   * - Images: Array of image URLs with display ordering
   *
   * **Business Rules**
   * - Product is immediately active upon creation
   * - Seller ID is derived from authentication context (not provided in request)
   * - Category must exist and be active
   * - Each variant must have unique SKU code within the product
   * - First image (display_order=0) becomes the product thumbnail
   *
   * @param connection
   * @param body Product creation data including name, description, category assignment, base price, and optional variants and images.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Authenticate seller from JWT session token
   * 2. Validate seller has approved status (not pending or rejected)
   * 3. Verify category_id references an existing, non-deleted category
   * 4. Validate required fields: name (non-empty), description (non-empty), base_price (positive number)
   * 5. Begin database transaction
   * 6. Insert product record with seller_id from authenticated session, category_id, name, description, base_price
   * 7. If variants provided: validate unique SKU codes within product, insert each variant with product_id
   * 8. If images provided: validate display_order uniqueness, insert each image with product_id
   * 9. Commit transaction
   * 10. Return created product with generated UUID and timestamps
   *
   * **Error Handling**
   * - 401: Missing or invalid authentication
   * - 403: Seller not approved or account suspended
   * - 400: Validation errors (missing required fields, invalid category, duplicate SKU)
   * - 404: Category not found
   * - 500: Database transaction failure
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceProduct.ICreate,
  ): Promise<IEcommerceProduct> {
    try {
      return await postEcommerceSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update product information for an existing product listing.
   *
   * This operation allows sellers to modify their own product details including the product name, description, category assignment, and base price. The system validates that the authenticated seller owns the product before applying changes.
   *
   * **Updateable Fields**
   *
   * - **name**: Product display name (required, must be non-empty)
   * - **description**: Detailed product description (required, must be non-empty)
   * - **category_id**: Category or subcategory reference for product organization
   * - **base_price**: Default selling price for the product
   *
   * **Business Rules**
   *
   * - Only the seller who created the product can update it
   * - Administrators can update any product for policy enforcement
   * - The product must exist and not be soft-deleted
   * - Category must exist and be active
   * - Base price must be a positive number
   * - A snapshot is automatically created to preserve the previous product state for audit purposes
   *
   * **Response**
   *
   * Returns the complete updated product entity including all relationships (category, seller, variants, images).
   *
   * @param connection
   * @param productId Unique identifier of the product to update (UUID format)
   * @param body Product fields to update. At least one field must be provided. All provided fields will be validated and updated atomically.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Validate authenticated seller owns the product (seller_id matches authenticated seller). 2. Load product from ecommerce_products table by productId. 3. Verify product is not soft-deleted (deleted_at IS NULL). 4. Validate request body fields: name (required, non-empty), description (required, non-empty), category_id (valid category reference), base_price (positive number). 5. Update allowed fields: name, description, category_id, base_price. 6. Set updated_at to current timestamp. 7. Create a product snapshot record (ecommerce_product_snapshots) preserving previous state. 8. Return updated product with all fields including relationships (category, seller). 9. Authorization: Only product owner (seller) or administrator can update. 10. Error handling: 404 if product not found, 403 if unauthorized, 400 for validation errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProduct.IUpdate,
  ): Promise<IEcommerceProduct> {
    try {
      return await putEcommerceSellerProductsProductId({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Deletes a product from the e-commerce platform.
   *
   * Sellers can delete their own products only when there are no pending order items with paid or shipped status for any variant of the product, and there are no pending cancellation or refund requests for any variant. When deleted, all variants and inventory records are also removed, and the product no longer appears in search or category listings.
   *
   * Administrators can delete any product regardless of ownership for policy violations, bypassing the order status restrictions.
   *
   * Product snapshots are preserved even after deletion to maintain historical audit trails for dispute resolution and compliance verification.
   *
   * @param connection
   * @param productId Unique identifier of the product to delete (UUID format, global scope).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Authenticate request and identify actor (seller or admin)
   * 2. Load product by productId from ecommerce_products table
   * 3. Validate product exists and is not already deleted
   * 4. Check authorization:
   *    - If seller: verify seller_id matches authenticated seller
   *    - If admin: allow any product deletion
   * 5. Validate deletion eligibility (for sellers only):
   *    - Query all variants of the product
   *    - Check ecommerce_order_items for any variant with status 'paid' or 'shipped'
   *    - Check ecommerce_cancellation_requests for any variant with status 'pending'
   *    - Check ecommerce_refund_requests for any variant with status 'pending'
   *    - If any restriction exists, return 409 Conflict with appropriate error message
   * 6. Perform cascade soft-delete:
   *    - Set deleted_at on all variants (ecommerce_product_variants)
   *    - Set deleted_at on all inventory records (ecommerce_inventory_records)
   *    - Set deleted_at on the product itself (ecommerce_products)
   * 7. Do NOT delete snapshots (ecommerce_product_snapshots, ecommerce_product_snapshot_variants) - preserve for audit
   * 8. Return 204 No Content on success
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
