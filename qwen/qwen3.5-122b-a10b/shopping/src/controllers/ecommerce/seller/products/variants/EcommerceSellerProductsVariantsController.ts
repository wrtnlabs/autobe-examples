import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceProductVariant } from "../../../../../api/structures/IEcommerceProductVariant";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { deleteEcommerceSellerProductsProductIdVariantsVariantId } from "../../../../../providers/deleteEcommerceSellerProductsProductIdVariantsVariantId";
import { postEcommerceSellerProductsProductIdVariants } from "../../../../../providers/postEcommerceSellerProductsProductIdVariants";
import { putEcommerceSellerProductsProductIdVariantsVariantId } from "../../../../../providers/putEcommerceSellerProductsProductIdVariantsVariantId";

@Controller("/ecommerce/seller/products/:productId/variants")
export class EcommerceSellerProductsVariantsController {
  /**
   * Create a new product variant (SKU) for the specified product.
   *
   * This operation allows sellers to add a specific variant combination to their product listing. Each variant represents a unique combination of options such as color, size, material, or other attributes.
   *
   * **Variant Identification**
   * Each variant is identified by a SKU code that must be unique within the product. The SKU code is used for inventory tracking and order fulfillment.
   *
   * **Option Values**
   * Option values are provided as a structured string in key=value format separated by semicolons (e.g., "color=Red;size=Large;material=Cotton"). This preserves the option structure while maintaining database normalization.
   *
   * **Price Override**
   * The variant can optionally override the product's base price. If the price field is not provided or is null, the product's base price will be used for this variant.
   *
   * **Business Rules**
   * - The product must exist and belong to the authenticated seller
   * - The SKU code must be unique within the product (composite unique constraint on product_id and sku_code)
   * - Option values are required and must be properly formatted
   * - The variant cannot be soft-deleted at creation time
   *
   * @param connection
   * @param productId Unique identifier of the parent product (UUID format).
   * @param body Variant creation data including SKU code, option values, and optional price override. The SKU code must be unique within the product.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification 1. Validate the authenticated user is a seller
     *   with approval status 'approved' 2. Query ecommerce_products table to
     *   verify the product exists and belongs to the seller (seller_id matches
     *   authenticated user) 3. Check if product is not soft-deleted (deleted_at
     *   is null) 4. Validate the SKU code is unique within the product (check
     *   existing variants where product_id = productId and sku_code =
     *   request.sku_code and deleted_at is null) 5. Validate option_values
     *   format (key=value pairs separated by semicolons) 6. Create new
     *   ecommerce_product_variants record with: - id: generate UUID -
     *   product_id: from path parameter - sku_code: from request body -
     *   option_values: from request body - price: from request body (nullable)
     *   - created_at: current timestamp - updated_at: current timestamp -
     *   deleted_at: null 7. Return the created variant with all fields
   *
   * **Error Handling**
   * - 404: Product not found or does not belong to seller
   * - 400: SKU code already exists for this product, invalid option_values format
   * - 403: User is not an approved seller
   * - 409: SKU code conflict (duplicate within product)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductVariant.ICreate,
  ): Promise<IEcommerceProductVariant> {
    try {
      return await postEcommerceSellerProductsProductIdVariants({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product variant within its parent product.
   *
   * This operation allows sellers to modify the SKU code, option values, and price of a specific variant. The variant must belong to a product owned by the authenticated seller. Updates are only permitted when the variant has no pending order items (paid or shipped status) and no pending cancellation or refund requests.
   *
   * **Business Rules**
   *
   * - The seller who owns the parent product must be the one updating the variant
   * - Variant cannot be updated if there are pending order items for that variant
   * - Variant cannot be updated if there are pending cancellation or refund requests
   * - SKU code must remain unique within the parent product
   * - At least one variant must always exist on a product (cannot delete the last variant)
   *
   * **Response Data**
   *
   * The response includes the complete updated variant object with calculated stock quantity derived from inventory history records.
   *
   * @param connection
   * @param productId UUID of the parent product that contains this variant (global scope)
   * @param variantId UUID of the variant to update (scoped to product)
   * @param body Variant update data including SKU code, option values, and optional price override.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Update a product variant owned by the
     *   authenticated seller. Verify that the variant belongs to the specified
     *   product and that the product is owned by the authenticated seller.
     *   Allow updates to sku_code, option_values, and price fields only. The
     *   variant cannot be modified if it has pending order items (paid or
     *   shipped status) or pending cancellation/refund requests. After
     *   successful update, create a product snapshot record to preserve
     *   historical state. Return the updated variant with all fields including
     *   calculated stock quantity from inventory history.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":variantId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductVariant.IUpdate,
  ): Promise<IEcommerceProductVariant> {
    try {
      return await putEcommerceSellerProductsProductIdVariantsVariantId({
        seller,
        productId,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a product variant by ID.
   *
   * This operation allows sellers to remove a specific variant (SKU) from their product listing. The variant is soft-deleted, meaning it is marked as deleted but preserved in the database for audit purposes.
   *
   * **Deletion Restrictions**
   *
   * The system enforces strict validation before allowing variant deletion:
   *
   * - The variant cannot have any order items with paid or shipped status
   * - The variant cannot have any pending cancellation requests
   * - The variant cannot have any pending refund requests
   * - The product must have at least one remaining active variant (cannot delete the last variant)
   *
   * **Business Impact**
   *
   * When a variant is deleted:
   * - All associated inventory history records are preserved for audit purposes
   * - The variant no longer appears in product listings or search results
   * - Existing orders referencing this variant remain unchanged
   * - Product snapshots preserve the variant state at the time of deletion
   *
   * **Authorization**
   *
   * Only the seller who owns the parent product can delete its variants. Administrators have oversight access to delete any variant on the platform.
   *
   * @param connection
   * @param productId UUID of the parent product containing the variant (global scope).
   * @param variantId UUID of the variant to delete (scoped to product).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Implement variant deletion with the following
     *   logic:
   *
   * 1. **Authorization Check**: Verify the authenticated seller owns the parent product (seller_id matches). Administrators bypass this check.
   *
   * 2. **Existence Validation**: Fetch the variant by productId and variantId. Return 404 if not found.
   *
   * 3. **Business Rule Validation**:
   *    - Query order_items table for any items with this variant_id and status IN ('paid', 'shipped'). If found, reject with 409 Conflict.
   *    - Query cancellation_requests table for any pending requests referencing this variant_id. If found, reject with 409 Conflict.
   *    - Query refund_requests table for any pending requests referencing this variant_id. If found, reject with 409 Conflict.
   *    - Count active (non-deleted) variants for this product. If count equals 1 (this is the last variant), reject with 409 Conflict per business rule.
   *
   * 4. **Soft Delete**: Set deleted_at = current timestamp on the variant record.
   *
   * 5. **Preserve Inventory**: Do NOT delete inventory records. Leave all ecommerce_inventory_records for this variant intact for audit trail.
   *
   * 6. **Response**: Return the deleted variant entity with updated deleted_at timestamp.
   *
   * **Error Codes**:
   * - 404: Variant not found
   * - 403: Unauthorized (seller does not own product)
   * - 409: Deletion blocked due to existing orders or requests, or last variant protection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":variantId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceSellerProductsProductIdVariantsVariantId({
        seller,
        productId,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
