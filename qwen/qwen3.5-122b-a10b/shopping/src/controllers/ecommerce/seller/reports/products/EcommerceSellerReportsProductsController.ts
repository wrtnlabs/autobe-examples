import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceProductSalesReport } from "../../../../../api/structures/IEcommerceProductSalesReport";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { postEcommerceSellerReportsProducts } from "../../../../../providers/postEcommerceSellerReportsProducts";

@Controller("/ecommerce/seller/reports/products")
export class EcommerceSellerReportsProductsController {
  /**
   * Generate a comprehensive sales report for products owned by the authenticated seller.
   *
   * This endpoint aggregates sales data across products, variants, and order items to provide insights into product performance. The report includes sales counts, revenue metrics, and inventory status filtered by optional criteria such as date range, specific products, categories, or order statuses.
   *
   * **Report Metrics**
   *
   * - Total number of products in the report scope
   * - Total sales count (number of order items)
   * - Total revenue (sum of quantity × unit_price)
   * - Average order value per product
   * - Inventory status summary (in-stock, out-of-stock, low-stock counts)
   *
   * **Filtering Options**
   *
   * - Date range: Filter by product creation date or order item creation date
   * - Product IDs: Include only specific products
   * - Category IDs: Filter products by category
   * - Order item status: Filter by paid, shipped, delivered, cancelled, or refunded status
   *
   * **Data Isolation**
   *
   * Only products owned by the authenticated seller are included in the report. Cross-seller data access is prohibited.
   *
   * @param connection
   * @param body Report generation criteria including optional date range filters, product ID list, category ID list, and order item status filters for customizing the report scope.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Generate product sales report for the
     *   authenticated seller. Query ecommerce_products joined with
     *   ecommerce_product_variants and ecommerce_order_items. Apply filters
     *   from request body: date range (created_at or order created_at), product
     *   IDs, category IDs, order item status. Calculate aggregated metrics:
     *   total sales count, total revenue (sum of quantity * unit_price),
     *   average order value, inventory status. Join with ecommerce_categories
     *   for category names. Filter by seller_id to ensure data isolation.
     *   Return report data with per-product breakdown and summary totals.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async generate(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceProductSalesReport.IRequest,
  ): Promise<IEcommerceProductSalesReport> {
    try {
      return await postEcommerceSellerReportsProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
