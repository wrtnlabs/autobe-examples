import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceInventoryRecord } from "../../../../../api/structures/IEcommerceInventoryRecord";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerVariantsVariantIdInventoryRecordId } from "../../../../../providers/getEcommerceSellerVariantsVariantIdInventoryRecordId";
import { patchEcommerceSellerVariantsVariantIdInventory } from "../../../../../providers/patchEcommerceSellerVariantsVariantIdInventory";
import { postEcommerceSellerVariantsVariantIdInventory } from "../../../../../providers/postEcommerceSellerVariantsVariantIdInventory";

@Controller("/ecommerce/seller/variants/:variantId/inventory")
export class EcommerceSellerVariantsInventoryController {
  /**
   * Create an inventory record for a product variant to add or subtract stock quantity.
   *
   * Sellers can manage inventory by creating inventory records with a quantity change value and a reason. Positive quantities add stock (restocking), while negative quantities subtract stock (adjustments or losses). The system automatically calculates the current stock quantity by summing all inventory records for the variant.
   *
   * **Business Rules**
   *
   * - Only sellers who own the parent product can create inventory records
   * - Quantity change must not be zero (no meaningful inventory movement)
   * - Reason is required to document the business context for the change
   * - Inventory records are immutable after creation
   * - When stock reaches zero, the variant is shown as out of stock
   *
   * **Automatic Inventory Updates**
   *
   * The system automatically creates inventory records for order-related events (order placement, cancellation, refund). This endpoint is for manual seller-initiated inventory changes only.
   *
   * @param connection
   * @param variantId Unique identifier of the product variant (UUID scope).
   * @param body Inventory change details including quantity change value and business reason.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Validate the authenticated user is a seller who owns the parent product of the variant
   * 2. Verify the variant exists and is not soft-deleted
   * 3. Validate quantity_change is not zero (must be positive or negative)
   * 4. Validate reason is provided and not empty
   * 5. Create a new ecommerce_inventory_records record with:
   *    - ecommerce_product_variant_id from the path parameter
   *    - quantity_change from the request body
   *    - reason from the request body
   *    - created_at and updated_at set to current timestamp
   * 6. Return the created inventory record with all fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceInventoryRecord.ICreate,
  ): Promise<IEcommerceInventoryRecord> {
    try {
      return await postEcommerceSellerVariantsVariantIdInventory({
        seller,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Add or subtract inventory for a product variant by creating an inventory record with quantity change and reason.
   *
   * This operation allows sellers to manually adjust stock levels through restocking (positive quantity) or inventory corrections (negative quantity). The system automatically calculates the current stock quantity by summing all inventory records for the variant.
   *
   * **Business Rules**
   *
   * - Sellers can only adjust inventory for variants they own
   * - Quantity change cannot be zero
   * - Restock operations use positive quantities
   * - Adjustment/loss operations use negative quantities
   * - Each change requires a reason for audit purposes
   * - Inventory records are immutable after creation
   *
   * @param connection
   * @param variantId Unique identifier of the product variant (UUID scope)
   * @param body Inventory adjustment request containing quantity change value and business reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Authenticate seller and verify ownership of the product variant (join ecommerce_product_variants with ecommerce_products to check seller_id matches authenticated seller)
   * 2. Validate quantity_change is not zero (business invariant)
   * 3. Create new inventory record with quantity_change, reason, and current timestamp
   * 4. Return the created inventory record
   * 5. Error responses: 403 Forbidden if seller doesn't own variant, 400 Bad Request if quantity is zero, 404 Not Found if variant not found or is deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async adjust(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceInventoryRecord.IAdjust,
  ): Promise<IEcommerceInventoryRecord> {
    try {
      return await patchEcommerceSellerVariantsVariantIdInventory({
        seller,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific inventory change record for a product variant.
   *
   * This endpoint returns the complete details of a single inventory history entry, including the quantity change value, business reason, and timestamp. Inventory records form an immutable audit trail of all stock movements for a variant.
   *
   * **Access Control**
   *
   * Sellers can only access inventory records for variants belonging to their products. Administrators can access all inventory records across the platform.
   *
   * **Record Contents**
   *
   * Each inventory record contains:
   * - Quantity change value (positive for additions, negative for deductions)
   * - Business reason for the change (e.g., restock, order, cancellation, adjustment)
   * - Timestamp when the change was recorded
   * - Reference to the parent product variant
   *
   * @param connection
   * @param variantId Unique identifier of the product variant (UUID format)
   * @param recordId Unique identifier of the inventory record (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Retrieve a single inventory record by ID with variant ownership validation.
   *
   * **Implementation Steps**
   *
   * 1. Validate both variantId and recordId are valid UUIDs
   * 2. Query ecommerce_inventory_records table for the record with id = recordId
   * 3. Verify the record's ecommerce_product_variant_id matches the provided variantId
   * 4. Validate ownership: seller can only access if they own the parent product (join through product → seller)
   * 5. For admin users, skip ownership validation
   * 6. Return the full inventory record entity
   *
   * **Error Handling**
   *
   * - 404: Record not found or variantId/recordId mismatch
   * - 403: User lacks permission to access this inventory record (not owner/admin)
   * - 400: Invalid UUID format in path parameters
   *
   * **Database Query**
   *
   * SELECT * FROM ecommerce_inventory_records WHERE id = :recordId AND ecommerce_product_variant_id = :variantId
   *
   * Include joins to ecommerce_product_variants and ecommerce_products for ownership validation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":recordId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedParam("recordId")
    recordId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceInventoryRecord> {
    try {
      return await getEcommerceSellerVariantsVariantIdInventoryRecordId({
        seller,
        variantId,
        recordId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
