import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceCustomer } from "../../../../api/structures/IEcommerceCustomer";
import { IEcommerceSellerProfile } from "../../../../api/structures/IEcommerceSellerProfile";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerProfilesProfileId } from "../../../../providers/getEcommerceSellerProfilesProfileId";
import { patchEcommerceSellerProfiles } from "../../../../providers/patchEcommerceSellerProfiles";
import { putEcommerceSellerProfilesProfileId } from "../../../../providers/putEcommerceSellerProfilesProfileId";

@Controller("/ecommerce/seller/profiles")
export class EcommerceSellerProfilesController {
  /**
   * Update the authenticated customer's profile information including display name and phone number.
   *
   * This operation allows customers to modify their public-facing profile details. The display name is shown to other users in reviews and order histories, while the phone number is used for shipping notifications and customer service contact.
   *
   * **Business Rules**
   *
   * - Only authenticated customers can update their own profile
   * - Display name is required and must be non-empty
   * - Phone number is optional and can be cleared
   * - Profile changes are recorded in the system but do not create snapshots (snapshots apply to seller profiles, products, and transactional data)
   * - The updated_at timestamp is automatically refreshed on each update
   *
   * **Error Handling**
   *
   * - Returns 401 if the customer is not authenticated
   * - Returns 400 if display_name is empty or invalid
   * - Returns 404 if the customer account does not exist or has been deleted
   *
   * @param connection
   * @param body Profile update request containing display name and optional phone number fields to modify.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Implement profile update for the authenticated
     *   customer:
   *
   * 1. **Authentication**: Extract customer ID from JWT session token. Reject with 401 if no valid session.
   *
   * 2. **Validation**:
   *    - Validate display_name is present and non-empty (min length 1, max length 100)
   *    - Validate phone_number format if provided (optional field)
   *    - Check customer account exists and is not soft-deleted (deleted_at IS NULL)
   *
   * 3. **Database Update**:
   *    - Update ecommerce_customers table: set display_name, phone_number (nullable), updated_at = now()
   *    - Use WHERE clause: id = {customerId} AND deleted_at IS NULL
   *    - Return updated customer record
   *
   * 4. **Response**: Return full customer object (IEcommerceCustomer) with updated fields
   *
   * 5. **Edge Cases**:
   *    - If customer not found or deleted: return 404
   *    - If validation fails: return 400 with specific field errors
   *    - Phone number can be set to NULL to clear the value
   *
   * No snapshot creation required for customer profile changes (per requirements - snapshots apply to seller profiles, products, reviews, etc.)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async patch(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceCustomer.IUpdate,
  ): Promise<IEcommerceCustomer> {
    try {
      return await patchEcommerceSellerProfiles({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a seller's shop profile by profile ID, including shop name, description, and logo image URL.
   *
   * This operation allows customers to view seller information when browsing products or viewing order details. Administrators can also access this endpoint for oversight and dispute resolution purposes. The profile displays current shop information as maintained by the seller.
   *
   * **Access Control**
   *
   * - Customers: Can view any seller's profile for transparency when browsing products
   * - Sellers: Can view their own profile
   * - Administrators: Can view all seller profiles for platform oversight
   *
   * **Data Preserved in Snapshots**
   *
   * Shop profile information at the time of purchase is preserved in order item snapshots, ensuring historical accuracy even if the seller updates their profile later.
   *
   * @param connection
   * @param profileId Unique identifier of the seller profile (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification 1. Extract profileId from path parameter (UUID
     *   format) 2. Validate profileId is a valid UUID format 3. Query
     *   ecommerce_seller_profiles table WHERE id = profileId AND deleted_at IS
     *   NULL 4. If profile not found, return 404 Not Found 5. Verify
     *   authorization: - If requester is customer: allow access (public seller
     *   profiles) - If requester is seller: verify ecommerce_seller_id matches
     *   requester's seller account - If requester is admin: allow access 6.
     *   Return the full seller profile entity including shop_name,
     *   shop_description, and logo_image_url 7. Join with ecommerce_sellers
     *   table to verify seller account is not banned (optional, for access
     *   control)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":profileId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("profileId")
    profileId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceSellerProfile> {
    try {
      return await getEcommerceSellerProfilesProfileId({
        seller,
        profileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a seller's shop profile information including shop name, description, and logo image.
   *
   * This operation allows authenticated sellers to modify their public-facing shop profile. The profile includes the shop name displayed on product listings, an optional description, and a logo image URL for branding.
   *
   * **Snapshot Creation**
   *
   * Every profile update creates an immutable snapshot in the seller_snapshots table, preserving the previous state with timestamp and field change details. This audit trail supports dispute resolution and compliance verification.
   *
   * **Access Control**
   *
   * Only the seller who owns this profile can update it. The system validates that the authenticated seller's account matches the profile's seller_id. Banned or suspended sellers cannot update their profiles.
   *
   * **Field Validation**
   *
   * Shop name is required and must be non-empty. Shop description and logo image URL are optional. Logo image URL must be a valid URI format if provided.
   *
   * @param connection
   * @param profileId Unique identifier of the seller profile to update (UUID format).
   * @param body Shop profile fields to update. At least one field must be provided.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Update seller shop profile by UUID. Validate
     *   seller owns this profile (authenticated seller's ecommerce_seller_id
     *   matches profile). Update shop_name, shop_description, and
     *   logo_image_url fields. Create immutable snapshot record in
     *   ecommerce_seller_snapshots before saving changes, capturing previous
     *   values. Return updated profile entity. Validate seller account is not
     *   banned. Soft delete check - reject if profile is deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":profileId")
  public async putByProfileid(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("profileId")
    profileId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceSellerProfile.IUpdate,
  ): Promise<IEcommerceSellerProfile> {
    try {
      return await putEcommerceSellerProfilesProfileId({
        seller,
        profileId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
