import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceSellerApproval } from "../../../../api/structures/IEcommerceSellerApproval";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerApprovalStatus } from "../../../../providers/getEcommerceSellerApprovalStatus";

@Controller("/ecommerce/seller/approval-status")
export class EcommerceSellerApproval_statusController {
  /**
   * Retrieve the current approval status of the authenticated seller's registration request.
   *
   * This endpoint returns the seller's approval workflow status, which indicates whether their registration is pending administrator review, has been approved, or was rejected. When rejected, the response includes the administrator-provided rejection reason.
   *
   * **Approval Status Values**
   *
   * - `pending`: Initial state when seller registers, awaiting administrator review
   * - `approved`: Administrator has approved the seller, who can now create products and process orders
   * - `rejected`: Administrator has rejected the seller registration, with a reason recorded
   *
   * **Access Control**
   *
   * Only authenticated sellers can access this endpoint. The system validates that the request comes from the seller whose approval status is being retrieved. Sellers can view their own approval status but cannot access other sellers' approval information.
   *
   * **Business Context**
   *
   * New sellers start with pending approval status. Administrators review and approve or reject registrations. Rejected sellers can view the rejection reason and submit new registration requests after addressing the issues.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_seller_approvals table to retrieve the current seller's approval status.
   *
   * Implementation steps:
   * 1. Extract seller identity from authentication token/session
   * 2. Query ecommerce_seller_approvals table where seller_id matches the authenticated seller
   * 3. Return the approval record with status, rejection_reason (if applicable), reviewed_at, and created_at
   * 4. If no approval record exists (edge case), return 404 Not Found
   * 5. Validate that the authenticated user has seller role before returning data
   *
   * Business rules:
   * - Only the seller themselves can view their approval status
   * - The rejection_reason is only populated when status is 'rejected'
   * - reviewed_at is only populated when status changed from 'pending'
   * - Soft-deleted approval records should not be returned (filter by deleted_at IS NULL)
   *
   * Error handling:
   * - 401 Unauthorized: No valid authentication token
   * - 403 Forbidden: User is not a seller or accessing another seller's status
   * - 404 Not Found: No approval record exists for this seller
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IEcommerceSellerApproval> {
    try {
      return await getEcommerceSellerApprovalStatus({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
