import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceShopDashboard } from "../../../../api/structures/IEcommerceShopDashboard";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerDashboard } from "../../../../providers/getEcommerceSellerDashboard";

@Controller("/ecommerce/seller/dashboard")
export class EcommerceSellerDashboardController {
  /**
   * Retrieve seller shop dashboard summary statistics.
   *
   * Returns aggregated counts of products, order items, pending cancellation requests, and pending refund requests for the authenticated seller's shop. This endpoint provides a quick overview of shop activity and pending actions requiring seller attention.
   *
   * **Business Context**
   *
   * Sellers use this dashboard to monitor their shop's health and identify pending tasks. The statistics are computed in real-time from the products, order items, cancellation requests, and refund requests tables.
   *
   * **Data Sources**
   *
   * - Product count: All products owned by the seller (excluding soft-deleted)
   * - Order item count: All order items for the seller's products
   * - Pending cancellation requests: Cancellation requests with status 'pending' for the seller's order items
   * - Pending refund requests: Refund requests with status 'pending' for the seller's order items
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Implement seller shop dashboard retrieval with
     *   the following logic:
   *
   * 1. **Authentication**: Validate seller authentication via session token. Extract seller_id from authenticated session.
   *
   * 2. **Product Count Query**: Query ecommerce_products table where seller_id matches authenticated seller AND deleted_at IS NULL. Return count.
   *
   * 3. **Order Item Count Query**: Query ecommerce_order_items table joined with ecommerce_products on ecommerce_product_variant_id. Filter where products.seller_id matches authenticated seller. Return count.
   *
   * 4. **Pending Cancellation Requests Count**: Query ecommerce_cancellation_requests joined with ecommerce_order_items and ecommerce_products. Filter where products.seller_id matches authenticated seller AND status = 'pending'. Return count.
   *
   * 5. **Pending Refund Requests Count**: Query ecommerce_refund_requests joined with ecommerce_order_items and ecommerce_products. Filter where products.seller_id matches authenticated seller AND status = 'pending'. Return count.
   *
   * 6. **Response Construction**: Return summary object with all four counts.
   *
   * **Edge Cases**
   *
   * - Seller with no products: Return zero counts for all fields
   * - Seller with pending approval status: Return 403 Forbidden (per section 370)
   * - High-volume shops: Ensure queries use indexed columns (seller_id, status)
   *
   * **Error Handling**
   *
   * - 401 Unauthorized: Missing or invalid authentication
   * - 403 Forbidden: Seller approval status is pending or rejected
   * - 500 Internal Server Error: Database query failure
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IEcommerceShopDashboard.ISummary> {
    try {
      return await getEcommerceSellerDashboard({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
