  /**
   * Update a cancellation request by approving or rejecting it.
   *
   * Customers can request cancellation for order items with "paid" status before they are shipped. Sellers of those items can approve or reject the cancellation request, providing a response reason.
   *
   * When a seller approves a cancellation request, the order item is cancelled, the customer receives a refund, and stock quantities are restored through inventory records. When a seller rejects the request, the order item continues processing through the normal shipping workflow.
   *
   * This operation is restricted to the seller who owns the product variant in the order item. Only cancellation requests with "pending" status can be updated.
   *
   * @param connection
   * @param orderId Unique identifier of the parent order (UUID format).
   * @param itemId Unique identifier of the order item within the order (UUID format).
   * @param requestId Unique identifier of the cancellation request to update (UUID format).
   * @param body Seller's response to the cancellation request including decision status and rationale.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Implement seller response to cancellation
     *   request:
   *
   * 1. Validate path parameters (orderId, itemId, requestId) are valid UUIDs
   * 2. Verify the order item belongs to the specified order
   * 3. Verify the cancellation request belongs to the specified order item
   * 4. Check that the cancellation request status is "pending" (not already approved/rejected)
   * 5. Verify the authenticated seller owns the product variant in the order item
   * 6. Validate request body contains valid status value ("approved" or "rejected")
   * 7. Validate seller_response is provided when status is not "pending"
   * 8. Update the cancellation request with new status and seller_response
   * 9. Create a cancellation request snapshot recording the state change
   * 10. If status is "approved":
   *    - Update order item status to "cancelled"
   *    - Create inventory record to restore stock quantity
   *    - Process refund for the customer
   * 11. If status is "rejected":
   *    - Order item continues normal processing
   * 12. Recalculate parent order status based on all order items
   * 13. Return updated cancellation request with snapshot reference
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
