import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceOrderItem } from "../../../../../api/structures/IEcommerceOrderItem";
import { IPageIEcommerceOrderItem } from "../../../../../api/structures/IPageIEcommerceOrderItem";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerOrdersOrderIdItemsItemId } from "../../../../../providers/getEcommerceSellerOrdersOrderIdItemsItemId";
import { patchEcommerceSellerOrdersOrderIdItems } from "../../../../../providers/patchEcommerceSellerOrdersOrderIdItems";

@Controller("/ecommerce/seller/orders/:orderId/items")
export class EcommerceSellerOrdersItemsController {
  /**
   * Retrieves a paginated list of order items belonging to a specific order.
   *
   * This endpoint allows administrators and order owners to view all line items within an order, with support for filtering by status, sorting, and pagination. Each order item represents a single product variant purchased, including the price and quantity at the time of purchase.
   *
   * **Access Control**
   * - Customers can view order items only for their own orders
   * - Sellers can view order items for products they own (filtered by seller_id)
   * - Administrators can view all order items across all orders
   *
   * **Available Filters**
   * - Status: Filter by item fulfillment status (paid, shipped, delivered, cancelled, refunded)
   * - Seller: Filter items by specific seller
   * - Date range: Filter by creation timestamp
   *
   * **Pagination**
   * Supports cursor-based pagination for large result sets with configurable page size.
   *
   * @param connection
   * @param orderId Unique identifier of the parent order (UUID format).
   * @param body Search criteria for filtering and paginating order items. Includes status filters, seller filters, date ranges, sorting options, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_order_items table with the following implementation requirements:
   *
   * 1. **Filter by Order ID**: Apply WHERE clause on ecommerce_order_id = {orderId} parameter
   *
   * 2. **Authorization Check**:
   *    - For customers: Verify ecommerce_customer_id matches authenticated user's customer ID via join with ecommerce_orders
   *    - For sellers: Filter items where ecommerce_seller_id matches authenticated seller's ID
   *    - For administrators: No additional filtering (full access)
   *
   * 3. **Apply Search Filters from Request Body**:
   *    - status: Filter by item status if provided (enum: paid, shipped, delivered, cancelled, refunded)
   *    - sellerId: Filter by seller ID if provided
   *    - dateFrom/dateTo: Filter by created_at timestamp range if provided
   *
   * 4. **Apply Sorting**:
   *    - Default: Sort by created_at DESC (newest first)
   *    - Allow sorting by: status, quantity, unit_price, created_at
   *    - Support ASC/DESC direction
   *
   * 5. **Apply Pagination**:
   *    - cursor: Use created_at and id as composite cursor for deterministic ordering
   *    - limit: Page size (default 20, max 100)
   *    - Return next cursor for pagination continuation
   *
   * 6. **Join Required Relations**:
   *    - Join with ecommerce_product_variants to include product information
   *    - Join with ecommerce_sellers to include seller information
   *    - Join with ecommerce_products for product name and thumbnail
   *
   * 7. **Return Summary Fields**:
   *    - id, ecommerce_order_id, ecommerce_product_variant_id, ecommerce_seller_id
   *    - quantity, unit_price, status
   *    - created_at, updated_at
   *    - Include product variant options and seller shop name in summary
   *
   * 8. **Edge Cases**:
   *    - Return empty array if order has no items
   *    - Return 404 if order does not exist
   *    - Return 403 if user lacks permission to view this order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceOrderItem.IRequest,
  ): Promise<IPageIEcommerceOrderItem.ISummary> {
    try {
      return await patchEcommerceSellerOrdersOrderIdItems({
        seller,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific order item within an order with full details including purchase-time snapshot data.
   *
   * This endpoint returns comprehensive information about a purchased item, including the product details and seller profile as they existed at the time of purchase. The snapshot data ensures historical accuracy even if the product or seller information has since changed.
   *
   * **Access Control**
   * - Customers can view order items only within their own orders
   * - Sellers can view order items for products they own
   * - Administrators can view all order items across the platform
   *
   * **Snapshot Data**
   * The response includes an embedded snapshot object containing the product name, description, seller shop name, seller logo URL, and base price at the time of purchase. This immutable audit trail enables dispute resolution and accurate order history.
   *
   * **Error Handling**
   * - Returns 404 if the order item does not exist or is not accessible to the requesting actor
   * - Returns 403 if the requesting actor lacks permission to view this order item
   *
   * @param connection
   * @param orderId UUID of the parent order containing this item (global scope)
   * @param itemId UUID of the order item to retrieve (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Retrieve a single order item by ID within a specific order. Query ecommerce_order_items table with orderId and itemId parameters. Join with ecommerce_order_item_snapshots to include historical product and seller data. Implement access control: customers can only access items in their own orders, sellers can only access items for their products, administrators have unrestricted access. Return 404 if order item not found or access denied. Include embedded snapshot object with product_name, product_description, seller_shop_name, seller_logo_url, base_price, and created_at fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceOrderItem> {
    try {
      return await getEcommerceSellerOrdersOrderIdItemsItemId({
        seller,
        orderId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
