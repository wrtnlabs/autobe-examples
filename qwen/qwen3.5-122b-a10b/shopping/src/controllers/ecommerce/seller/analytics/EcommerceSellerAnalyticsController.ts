import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceAnalytic } from "../../../../api/structures/IEcommerceAnalytic";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerAnalytics } from "../../../../providers/getEcommerceSellerAnalytics";

@Controller("/ecommerce/seller/analytics")
export class EcommerceSellerAnalyticsController {
  /**
   * Retrieve platform-wide analytics and statistics.
   *
   * This endpoint provides aggregated metrics across the e-commerce platform including total counts for products, orders, customers, sellers, and pending cancellation/refund requests. The data is computed on-demand from multiple tables to give administrators and authorized users a comprehensive system overview.
   *
   * **Analytics Metrics**
   *
   * The response includes:
   * - Total number of active products
   * - Total number of orders (with status breakdown)
   * - Total number of registered customers
   * - Total number of registered sellers (with approval status breakdown)
   * - Count of pending cancellation requests
   * - Count of pending refund requests
   * - Recent activity summaries
   *
   * **Access Control**
   *
   * This endpoint requires administrator authentication. Regular customers and sellers cannot access platform-wide analytics as this data may contain sensitive business information.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement GET /analytics as a read-only statistics endpoint.
   *
   * **Service Logic**
   *
   * 1. Verify administrator authentication and authorization
   * 2. Query each entity table for aggregated counts:
   *    - ecommerce_products: COUNT where deleted_at IS NULL
   *    - ecommerce_orders: COUNT with GROUP BY status
   *    - ecommerce_customers: COUNT where deleted_at IS NULL
   *    - ecommerce_sellers: COUNT with GROUP BY approval_status, is_suspended, is_banned
   *    - ecommerce_cancellation_requests: COUNT where status = 'pending'
   *    - ecommerce_refund_requests: COUNT where status = 'pending'
   * 3. Calculate derived metrics (e.g., active seller ratio, order completion rate)
   * 4. Return aggregated statistics as JSON response
   *
   * **Database Queries**
   *
   * Use efficient COUNT queries with appropriate WHERE clauses to filter soft-deleted records. Consider using database views or materialized tables for performance if analytics are queried frequently.
   *
   * **Edge Cases**
   *
   * - Handle empty tables (return 0 counts)
   * - Handle null/missing data gracefully
   * - Ensure consistent timestamp formatting for any time-based metrics
   *
   * **Error Handling**
   *
   * - 401: Unauthenticated request
   * - 403: Non-administrator access attempt
   * - 500: Database query failure
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IEcommerceAnalytic> {
    try {
      return await getEcommerceSellerAnalytics({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
