export async function getEcommerceAdminOrdersOrderId(props: {
  admin: AdminPayload;
  orderId: string & tags.Format<"uuid">;
}): Promise<IEcommerceOrder> {
  const record = await MyGlobal.prisma.ecommerce_orders.findFirstOrThrow({
    ...EcommerceOrderTransformer.select(),
    where: {
      id: props.orderId,
      deleted_at: null,
    },
  });
  return await EcommerceOrderTransformer.transform(record);
}
