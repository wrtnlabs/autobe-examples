export async function getEcommerceSellerOrdersOrderIdShipmentsShipmentId(props: {
  seller: SellerPayload;
  orderId: string & tags.Format<"uuid">;
  shipmentId: string & tags.Format<"uuid">;
}): Promise<IEcommerceShipment> {
  const record = await MyGlobal.prisma.ecommerce_shipments.findFirstOrThrow({
    ...EcommerceShipmentTransformer.select(),
    where: {
      id: props.shipmentId,
      order_id: props.orderId,
      seller_id: props.seller.id,
    },
  });
  return await EcommerceShipmentTransformer.transform(record);
}
