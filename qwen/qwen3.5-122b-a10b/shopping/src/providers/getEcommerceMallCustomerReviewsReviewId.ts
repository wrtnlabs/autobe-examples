export async function getEcommerceMallCustomerReviewsReviewId(props: {
  customer: CustomerPayload;
  reviewId: string & tags.Format<"uuid">;
}): Promise<IEcommerceMallReview> {
  // Fetch review using transformer select for proper relation loading
  const review = await MyGlobal.prisma.ecommerce_mall_reviews.findUniqueOrThrow(
    {
      where: { id: props.reviewId },
      ...EcommerceMallReviewTransformer.select(),
    } satisfies Prisma.ecommerce_mall_reviewsFindUniqueArgs,
  );
  // Transform database record to API response DTO
  return await EcommerceMallReviewTransformer.transform(review);
}
