/**
 * Confirm delivery for a specific shipment package.
 *
 * This operation allows customers to confirm that they have received their shipment. When delivery is confirmed, the system updates the shipment's delivery timestamp and marks all order items within that shipment as 'delivered'. This action triggers the ability for customers to write reviews for the delivered products.
 *
 * The operation validates that the authenticated customer owns the order containing the shipment, and that the shipment is currently in 'shipped' status (not already delivered). Delivery confirmation is performed per shipment, not per individual order item, meaning all items in the confirmed shipment are simultaneously marked as delivered.
 *
 * After successful delivery confirmation, the overall order status is automatically updated based on the statuses of all order items. If all items in an order are delivered, the order status becomes 'delivered'. If some items are delivered while others have different statuses, the order status becomes 'partiallyCompleted'.
 *
 * This operation is critical for enabling the review workflow, as customers can only create reviews for products after their order items have been marked as 'delivered' through shipment confirmation or automatic delivery (14 days after shipping).
 *
 * @param props.connection
 * @param props.shipmentId Unique identifier of the shipment to confirm delivery for (UUID format)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification 1. Validate shipment exists and is not soft-deleted. 2. Verify customer owns the order containing this shipment (check order customer_id matches authenticated customer). 3. Verify shipment status is 'shipped' (delivered_at is null). 4. If valid, begin transaction: a) Update shipment.delivered_at to current timestamp, b) Find all order items linked to this shipment via order_id, c) Update all order items with status='paid' to status='delivered', d) Update order status based on all order items' statuses (all delivered -> 'delivered', mixed -> 'partiallyCompleted'). 5. Create shipment snapshot recording the delivered_at change. 6. Commit transaction. 7. Return updated shipment object. Edge cases: shipment already delivered (409 Conflict), customer doesn't own order (403 Forbidden), shipment not in shipped status (400 Bad Request), shipment not found (404 Not Found).
 * @path /ecommerceMall/customer/shipments/:shipmentId/confirm-delivery
 * @accessor api.functional.ecommerceMall.customer.shipments.confirm_delivery.confirmDelivery
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function confirmDelivery(
  connection: IConnection,
  props: confirmDelivery.Props,
): Promise<confirmDelivery.Response> {
  return true === connection.simulate
    ? confirmDelivery.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...confirmDelivery.METADATA,
          path: confirmDelivery.path(props),
          status: null,
        },
      );
}
