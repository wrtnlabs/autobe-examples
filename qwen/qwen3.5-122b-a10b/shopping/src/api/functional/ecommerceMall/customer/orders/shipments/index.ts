/**
 * Confirm delivery for a specific shipment associated with an order.
 *
 * This operation allows a customer to manually confirm that they have received the physical package for a shipment. When delivery is confirmed, the system records the delivery timestamp and updates all order items included in this shipment to 'delivered' status.
 *
 * **Security and Access Control**
 *
 * Only the customer who placed the order can confirm delivery for shipments associated with that order. Sellers and administrators can view shipment information but cannot confirm delivery on behalf of customers. The system validates that the authenticated customer owns the order before allowing delivery confirmation.
 *
 * **Business Logic**
 *
 * When delivery is confirmed, the following operations occur:
 * 1. The shipment's delivered_at timestamp is set to the current server time
 * 2. All order items linked to this shipment are updated from 'shipped' to 'delivered' status
 * 3. If all items in the order are now delivered, the order status updates to 'delivered'
 * 4. If some items have different statuses, the order status updates to 'partiallyCompleted'
 * 5. A snapshot is created to record the delivery confirmation event
 *
 * **Delivery Window**
 *
 * Customers can confirm delivery at any time after the shipment status is 'shipped'. The system also supports automatic delivery confirmation after 14 days from the shipped_at timestamp, but manual confirmation takes precedence.
 *
 * **Related Operations**
 *
 * - `GET /orders/{orderId}/shipments/{shipmentId}` - Retrieve shipment details before confirming delivery
 * - `PATCH /orders/{orderId}/shipments` - List all shipments for an order
 * - `GET /orders/{orderId}` - View complete order details including all shipments
 * - `PUT /order-items/{orderItemId}/cancellation` - Request cancellation (only available before shipment)
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the order containing this shipment (UUID format)
 * @param props.shipmentId Unique identifier of the shipment to confirm delivery (UUID format)
 * @param props.body Delivery confirmation request with optional delivery timestamp
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification 1. Validate authentication - ensure request is from authenticated customer
 * 2. Verify order ownership - check ecommerce_mall_orders.ecommerce_mall_customer_id matches authenticated customer ID
 * 3. Verify shipment exists - query ecommerce_mall_shipments by shipmentId
 * 4. Verify shipment belongs to order - check shipment's order items reference the given orderId
 * 5. Validate shipment status - ensure delivered_at is null (not already delivered)
 * 6. Validate order item statuses - ensure all order items in shipment are 'shipped' status
 * 7. Begin database transaction
 * 8. Update ecommerce_mall_shipments.delivered_at to current timestamp
 * 9. Update all order items (ecommerce_mall_order_items) in this shipment to status 'delivered'
 * 10. Recalculate order status based on all order items in the order:
 *     - If all items are 'delivered' → order status = 'delivered'
 *     - If some items are 'delivered' and others have different statuses → order status = 'partiallyCompleted'
 * 11. Update order's updated_at timestamp
 * 12. Commit transaction
 * 13. Return updated shipment object with delivered_at timestamp
 * @path /ecommerceMall/customer/orders/:orderId/shipments/:shipmentId
 * @accessor api.functional.ecommerceMall.customer.orders.shipments.confirmDelivery
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
