/**
 * Bulk remove multiple shopping cart items in a single operation.
 *
 * This endpoint allows customers to remove multiple items from their shopping cart simultaneously by providing a list of cart item IDs. All items must belong to the authenticated customer, otherwise the entire operation is rejected.
 *
 * The operation validates ownership for each cart item ID before proceeding with deletion. If any item does not belong to the authenticated customer or does not exist, the entire bulk operation is rolled back and no items are removed.
 *
 * Upon successful deletion, the cart total price is recalculated to reflect the remaining items. All removed cart items are permanently deleted from the system.
 *
 * This operation is particularly useful when customers want to clear multiple items at once, such as removing out-of-stock items or clearing the entire cart before checkout.
 *
 * @param props.connection
 * @param props.body List of cart item IDs to remove
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query cart items by ID list with customer ownership validation. For each cart item ID in the request, verify the item belongs to the authenticated customer. If any item doesn't belong to the customer, reject the entire operation with an ownership error. Delete all validated cart items in a single transaction. Recalculate cart total price after deletion. Return list of successfully removed cart item IDs.
 * @path /ecommerceMall/customer/bulk-remove
 * @accessor api.functional.ecommerceMall.customer.bulk_remove.bulkRemove
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function bulkRemove(
  connection: IConnection,
  props: bulkRemove.Props,
): Promise<bulkRemove.Response> {
  return true === connection.simulate
    ? bulkRemove.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...bulkRemove.METADATA,
          path: bulkRemove.path(),
          status: null,
        },
        props.body,
      );
}
