/**
 * Retrieve aggregated review statistics for a specific product.
 *
 * This endpoint provides summary information about customer reviews for a product, including the average rating, total review count, and the distribution of ratings across the 1-5 star scale. The statistics are calculated from all non-deleted reviews associated with the product.
 *
 * **Average Rating Calculation**
 *
 * The average rating is computed by summing all ratings from non-deleted reviews and dividing by the count of non-deleted reviews, then rounding to one decimal place. If the product has no reviews or all reviews are deleted, the average rating will be null.
 *
 * **Review Count**
 *
 * The total review count reflects only non-deleted reviews. Deleted reviews (where is_deleted is true) are excluded from both the count and the average rating calculation.
 *
 * **Rating Distribution**
 *
 * The response includes a breakdown of review counts by rating level (1 star through 5 stars). This allows clients to display rating histograms or distribution charts on product detail pages.
 *
 * **Product Visibility**
 *
 * This operation returns review statistics regardless of the product's status (active, deleted, or suspended). Even deleted or suspended products retain their historical review data for reference.
 *
 * **Related Operations**
 *
 * - `GET /products/{productId}` - Retrieve complete product details including embedded review summary
 * - `PATCH /products/{productId}/reviews` - List individual reviews with pagination and filtering
 * - `POST /products/{productId}/reviews` - Create a new review (requires delivered order item)
 *
 * @param props.connection
 * @param props.productId Target product's unique identifier
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query the ecommerce_mall_reviews table for all reviews where product_id matches the path parameter and is_deleted is false.
 *
 * Calculate the following aggregations:
 * 1. Average rating: AVG(rating) rounded to 1 decimal place (NULL if no non-deleted reviews)
 * 2. Total count: COUNT of non-deleted reviews
 * 3. Rating distribution: GROUP BY rating, COUNT for each rating value (1-5)
 *
 * Performance considerations:
 * - Use the existing index on [product_id, created_at] for efficient filtering
 * - The is_deleted index can help optimize the WHERE clause
 * - Return early if product_id is invalid (404 Not Found)
 *
 * Edge cases:
 * - Product with no reviews: Return null average, zero counts
 * - Product with all deleted reviews: Same as no reviews
 * - Rating values outside 1-5 range should not occur due to database constraints
 *
 * No write operations or transactions required. This is a read-only query.
 * @path /ecommerceMall/products/:productId/reviews/summary
 * @accessor api.functional.ecommerceMall.products.reviews.summary.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
