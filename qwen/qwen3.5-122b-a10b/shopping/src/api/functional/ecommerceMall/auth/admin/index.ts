/**
 * Administrator registration endpoint that creates a new admin account in the system. This operation validates the provided email address for format correctness and uniqueness, ensuring no duplicate administrator accounts exist. The password undergoes security validation to enforce minimum length and complexity requirements before being hashed using bcrypt with an appropriate cost factor for secure storage.
 *
 * Upon successful validation, a new admin record is created in the ecommerce_mall_admins table with the email address, hashed password, default admin_grade set to 'regular', and account_status set to 'active'. The system generates a unique UUID identifier for the admin account and records creation timestamps. The admin_grade field determines privilege levels, where 'regular' administrators can manage sellers, categories, products, orders, and users, while 'super' administrators have additional privileges for admin promotion/demotion.
 *
 * The response includes JWT access and refresh tokens for immediate authentication, along with the admin profile information. Account status validation ensures only 'active' accounts can authenticate, while 'suspended' or 'banned' accounts are rejected. Registration events are logged for security auditing and compliance purposes.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Administrator registration credentials and profile information
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification 1. Validate email format and uniqueness against ecommerce_mall_admins table
 * 2. Validate password meets security requirements (minimum length, complexity)
 * 3. Hash password using bcrypt with appropriate cost factor
 * 4. Create new admin record with email, password_hash, admin_grade='regular', account_status='active'
 * 5. Generate unique admin ID and set created_at/updated_at timestamps
 * 6. Return IAuthorized response with JWT access token, refresh token, and admin profile
 * 7. Log registration event for audit trail
 * @path /ecommerceMall/auth/admin/join
 * @accessor api.functional.ecommerceMall.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
