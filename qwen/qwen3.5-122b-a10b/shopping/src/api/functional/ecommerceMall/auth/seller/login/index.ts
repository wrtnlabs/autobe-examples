import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IEcommerceMallSeller } from "../../../../../structures/IEcommerceMallSeller";

/**
 * Authenticate a seller account using email and password credentials. This operation validates the seller's identity and issues JWT tokens for subsequent API authorization.
 *
 * The authentication process queries the ecommerce_mall_sellers table by email address and compares the provided password against the stored password_hash using bcrypt verification. The operation validates that the account_status is 'active' (not suspended or banned) and that deleted_at is null (account not deleted).
 *
 * Sellers with approval_status 'pending' can successfully login but cannot create products or process orders until administrator approval. Sellers with approval_status 'rejected' can login to view rejection_reason and reapply. Only sellers with approval_status 'approved' have full selling privileges.
 *
 * Upon successful authentication, the system creates a new session record in ecommerce_mall_seller_sessions containing the generated JWT access_token and refresh_token. Session metadata captures client IP address, origin URL (href), and HTTP referrer for security auditing and anomaly detection. The session's expired_at timestamp is set based on the token TTL policy (access token: 15 minutes, refresh token: 7 days).
 *
 * The response includes the access_token and refresh_token for client-side storage, along with seller profile information including shop_name, approval_status, and account_status. The client must include the access_token in Authorization header (Bearer token) for all subsequent authenticated requests.
 *
 * Related operations: Use refresh endpoint to renew expired access tokens. Use password reset flow if credentials are forgotten. Check approval_status to determine selling privileges.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Login credentials including email and password.
 * @x-autobe-authorization-type login
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Authenticate seller with email/password credentials. Service layer queries ecommerce_mall_sellers table by email, validates password_hash against provided password using bcrypt comparison. Checks account_status is 'active' (not suspended/banned) and deleted_at is null. Verifies approval_status is 'approved' before allowing product/order operations (though login succeeds for pending sellers). On success, creates new session record in ecommerce_mall_seller_sessions with generated JWT access_token and refresh_token, stores IP, href, referrer from request, sets expired_at based on token TTL. Returns tokens and seller profile including approval_status. On failure (invalid credentials, suspended account, deleted account), returns 401 error.
 * @path /ecommerceMall/auth/seller/login
 * @accessor api.functional.ecommerceMall.auth.seller.login.signIn
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function signIn(
  connection: IConnection,
  props: signIn.Props,
): Promise<signIn.Response> {
  const output: signIn.Response =
    true === connection.simulate
      ? signIn.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...signIn.METADATA,
            path: signIn.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace signIn {
  export type Props = {
    /**
     * Login credentials including email and password.
     */
    body: IEcommerceMallSeller.ILogin;
  };
  export type Body = IEcommerceMallSeller.ILogin;
  export type Response = IEcommerceMallSeller.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/ecommerceMall/auth/seller/login",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerceMall/auth/seller/login";
  export const random = (): IEcommerceMallSeller.IAuthorized =>
    typia.random<IEcommerceMallSeller.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: signIn.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: signIn.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
