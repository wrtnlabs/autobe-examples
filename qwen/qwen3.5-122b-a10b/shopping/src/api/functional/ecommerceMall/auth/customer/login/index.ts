/**
 * This endpoint authenticates an existing customer account using email and password credentials. The operation validates the provided credentials against stored customer data and returns authentication tokens upon successful verification.
 *
 * The system first locates the customer record by email address, then verifies the password using bcrypt comparison. If the credentials match and the account status is 'active', the operation proceeds to generate authentication tokens. Accounts with 'suspended' or 'banned' status are rejected even with valid credentials, requiring administrator intervention for reactivation.
 *
 * Password verification uses constant-time comparison to prevent timing attacks. Multiple failed login attempts trigger rate limiting and temporary account lockout to protect against brute force attacks. The system tracks login attempts and enforces cooldown periods after repeated failures.
 *
 * Upon successful authentication, the endpoint returns a JWT access token (valid for 15 minutes) and a refresh token (valid for 7 days). The access token must be included in the Authorization header for subsequent API calls. When the access token expires, the refresh token can be used to obtain a new access token without requiring re-entry of credentials.
 *
 * This operation is publicly accessible without prior authentication, as it serves the login function. However, strict rate limiting and monitoring apply to prevent abuse and credential stuffing attacks.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Login credentials for authenticating an existing customer account, including email and password.
 * @x-autobe-authorization-type login
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification 1. Find customer by email in database. 2. Verify password using bcrypt comparison. 3. Check accountStatus - reject if 'suspended' or 'banned'. 4. Generate JWT access token (15min expiry) and refresh token (7day expiry). 5. Create customer session record with tokens. 6. Return authorized response. Error cases: invalid credentials (401), account suspended/banned (403), rate limit exceeded (429). Implement login attempt tracking for brute force protection.
 * @path /ecommerceMall/auth/customer/login
 * @accessor api.functional.ecommerceMall.auth.customer.login.signIn
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function signIn(
  connection: IConnection,
  props: signIn.Props,
): Promise<signIn.Response> {
  const output: signIn.Response =
    true === connection.simulate
      ? signIn.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...signIn.METADATA,
            path: signIn.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
