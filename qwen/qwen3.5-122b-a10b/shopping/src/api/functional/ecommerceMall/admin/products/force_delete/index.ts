/**
 * Force-delete a product from the platform due to policy violations. This administrator-only operation permanently removes a product from all customer-facing listings while preserving complete audit trails through snapshots.
 *
 * **Purpose and Overview**
 *
 * This endpoint allows system administrators to remove products that violate platform policies, regardless of the product's current order status or seller ownership. Unlike seller-initiated product deletion which requires validation checks (no pending orders, no cancellation/refund requests), administrator force-deletion bypasses these restrictions to enable immediate policy enforcement.
 *
 * **Security and Authorization**
 *
 * Only authenticated administrators (regular or super admin grades) can access this endpoint. The operation requires administrator credentials and logs the performing administrator's ID along with the violation reason for audit compliance.
 *
 * **Business Logic and Validation**
 *
 * The operation validates that the target product exists and is not already deleted. Upon successful execution, the product status changes to 'deleted' and the deleted_at timestamp is recorded. The product is immediately removed from search results, category listings, and all customer-facing interfaces.
 *
 * **Snapshot and Audit Preservation**
 *
 * All product snapshots are preserved even after deletion to maintain historical records for dispute resolution and legal compliance. A new snapshot is created capturing the deletion event with previous values (active product state) and current values (deleted state).
 *
 * **Wishlist Auto-Removal**
 *
 * The system automatically removes the deleted product from all customer wishlists by marking associated wishlist entries as inactive. This occurs as a background operation to ensure customer wishlists remain consistent with available products.
 *
 * **Related Operations**
 *
 * - `PATCH /products` - Search and list products (includes deleted products for administrators)
 * - `GET /products/{productId}` - Retrieve product details (deleted products visible to administrators)
 * - `GET /products/{productId}/snapshots` - View product snapshot history including deletion records
 * - `POST /products` - Create new products (deleted product names can be reused)
 *
 * @param props.connection
 * @param props.productId Unique identifier of the product to force-delete (UUID format)
 * @param props.body Violation reason and deletion metadata for audit purposes
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification 1. Authenticate request as administrator (regular or super admin)
 * 2. Validate productId exists in ecommerce_mall_products table
 * 3. Verify product is not already deleted (deleted_at is null)
 * 4. Begin database transaction:
 *    a. Update product status to 'deleted'
 *    b. Set deleted_at timestamp to current time
 *    c. Record administrator ID in system audit log with violation reason
 *    d. Trigger background job to remove product from all customer wishlists (mark wishlist items as inactive)
 *    e. Create product snapshot with previous and current values
 * 5. Commit transaction
 * 6. Return deleted product summary with deletion confirmation
 * @path /ecommerceMall/admin/products/:productId/force-delete
 * @accessor api.functional.ecommerceMall.admin.products.force_delete.forceDelete
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function forceDelete(
  connection: IConnection,
  props: forceDelete.Props,
): Promise<forceDelete.Response> {
  return true === connection.simulate
    ? forceDelete.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...forceDelete.METADATA,
          path: forceDelete.path(props),
          status: null,
        },
        props.body,
      );
}
