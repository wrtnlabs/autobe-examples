/**
 * Retrieve the seller dashboard summary with shop statistics and pending request counts.
 *
 * This operation provides sellers with a comprehensive overview of their shop's current state, including the total number of active products, order items across all orders, and the count of pending cancellation and refund requests requiring their attention.
 *
 * The dashboard aggregates data from multiple related entities: products owned by the seller, order items containing their products, and pending cancellation/refund requests associated with those order items. This consolidated view enables sellers to quickly assess their shop's operational status and prioritize pending actions.
 *
 * Access is restricted to authenticated sellers only. Each seller can only view their own dashboard statistics. The operation returns summary counts optimized for dashboard display without requiring additional detail retrieval calls.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Query ecommerce_mall_sellers table to get authenticated seller ID. Count products from ecommerce_mall_products where seller_id matches and status is active. Count order items from ecommerce_mall_order_items joined with products where seller_id matches. Count pending cancellation requests from ecommerce_mall_order_item_cancellation_requests joined with order items and products where seller_id matches and status is pending. Count pending refund requests from ecommerce_mall_order_item_refund_requests joined with order items and products where seller_id matches and status is pending. Return aggregated counts in single response object. Apply authorization check to ensure seller can only access their own dashboard data.
 * @path /ecommerceMall/seller/dashboard
 * @accessor api.functional.ecommerceMall.seller.dashboard
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function dashboard(
  connection: IConnection,
): Promise<dashboard.Response> {
  return true === connection.simulate
    ? dashboard.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...dashboard.METADATA,
          path: dashboard.path(),
          status: null,
        },
      );
}
export namespace dashboard {
  export type Response = IEcommerceMallDashboard;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/seller/dashboard",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerceMall/seller/dashboard";
  export const random = (): IEcommerceMallDashboard =>
    typia.random<IEcommerceMallDashboard>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
