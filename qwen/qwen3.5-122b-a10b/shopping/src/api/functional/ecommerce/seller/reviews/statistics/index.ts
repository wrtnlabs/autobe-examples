import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia from "typia";

import { IEcommerceReview } from "../../../../../structures/IEcommerceReview";
import { IEcommerceReviewStatistic } from "../../../../../structures/IEcommerceReviewStatistic";

/**
 * Retrieve review statistics including average rating and rating distribution.
 *
 * This endpoint returns aggregated statistics for reviews, including the average rating calculated from non-deleted reviews only. The statistics can be filtered by product ID to get product-specific review metrics. Deleted reviews are excluded from all calculations to ensure accurate rating representation.
 *
 * **Statistics Included**
 *
 * - Average rating (1-5 stars) from non-deleted reviews
 * - Total count of reviews
 * - Rating distribution showing count for each star level (1-5)
 *
 * **Filtering**
 *
 * - Filter by product_id to get statistics for a specific product
 * - If no product_id is provided, returns global statistics across all products
 *
 * @param props.connection
 * @param props.body Search criteria including optional product ID filter for product-specific statistics.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Query ecommerce_reviews table for statistics
 *   aggregation.
 *
 * Filter by product_id if provided in request body to get product-specific statistics.
 * Calculate average rating from non-deleted reviews only (WHERE deleted_at IS NULL).
 * Count total reviews and rating distribution (1-5 stars).
 * Join with ecommerce_products for product name if requested.
 * Return aggregated statistics without pagination since this is an aggregation endpoint.
 * @path /ecommerce/seller/reviews/statistics
 * @accessor api.functional.ecommerce.seller.reviews.statistics.search
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function search(
  connection: IConnection,
  props: search.Props,
): Promise<search.Response> {
  return true === connection.simulate
    ? search.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...search.METADATA,
          path: search.path(),
          status: null,
        },
        props.body,
      );
}
export namespace search {
  export type Props = {
    /**
     * Search criteria including optional product ID filter for product-specific statistics.
     */
    body: IEcommerceReview.IRequest;
  };
  export type Body = IEcommerceReview.IRequest;
  export type Response = IEcommerceReviewStatistic;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerce/seller/reviews/statistics",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerce/seller/reviews/statistics";
  export const random = (): IEcommerceReviewStatistic =>
    typia.random<IEcommerceReviewStatistic>();
  export const simulate = (
    connection: IConnection,
    props: search.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: search.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
