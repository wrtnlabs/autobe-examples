import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia from "typia";

import { IEcommerceProductSalesReport } from "../../../../../structures/IEcommerceProductSalesReport";

/**
 * Generate a comprehensive sales report for products owned by the authenticated seller.
 *
 * This endpoint aggregates sales data across products, variants, and order items to provide insights into product performance. The report includes sales counts, revenue metrics, and inventory status filtered by optional criteria such as date range, specific products, categories, or order statuses.
 *
 * **Report Metrics**
 *
 * - Total number of products in the report scope
 * - Total sales count (number of order items)
 * - Total revenue (sum of quantity × unit_price)
 * - Average order value per product
 * - Inventory status summary (in-stock, out-of-stock, low-stock counts)
 *
 * **Filtering Options**
 *
 * - Date range: Filter by product creation date or order item creation date
 * - Product IDs: Include only specific products
 * - Category IDs: Filter products by category
 * - Order item status: Filter by paid, shipped, delivered, cancelled, or refunded status
 *
 * **Data Isolation**
 *
 * Only products owned by the authenticated seller are included in the report. Cross-seller data access is prohibited.
 *
 * @param props.connection
 * @param props.body Report generation criteria including optional date range filters, product ID list, category ID list, and order item status filters for customizing the report scope.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Generate product sales report for the authenticated
 *   seller. Query ecommerce_products joined with ecommerce_product_variants and
 *   ecommerce_order_items. Apply filters from request body: date range
 *   (created_at or order created_at), product IDs, category IDs, order item
 *   status. Calculate aggregated metrics: total sales count, total revenue (sum
 *   of quantity * unit_price), average order value, inventory status. Join with
 *   ecommerce_categories for category names. Filter by seller_id to ensure data
 *   isolation. Return report data with per-product breakdown and summary
 *   totals.
 * @path /ecommerce/seller/reports/products
 * @accessor api.functional.ecommerce.seller.reports.products.generate
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function generate(
  connection: IConnection,
  props: generate.Props,
): Promise<generate.Response> {
  return true === connection.simulate
    ? generate.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...generate.METADATA,
          path: generate.path(),
          status: null,
        },
        props.body,
      );
}
export namespace generate {
  export type Props = {
    /**
     * Report generation criteria including optional date range filters, product ID list, category ID list, and order item status filters for customizing the report scope.
     */
    body: IEcommerceProductSalesReport.IRequest;
  };
  export type Body = IEcommerceProductSalesReport.IRequest;
  export type Response = IEcommerceProductSalesReport;

  export const METADATA = {
    method: "POST",
    path: "/ecommerce/seller/reports/products",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerce/seller/reports/products";
  export const random = (): IEcommerceProductSalesReport =>
    typia.random<IEcommerceProductSalesReport>();
  export const simulate = (
    connection: IConnection,
    props: generate.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: generate.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
