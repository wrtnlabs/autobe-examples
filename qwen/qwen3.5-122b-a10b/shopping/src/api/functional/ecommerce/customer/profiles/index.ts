import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IEcommerceSellerProfile } from "../../../../structures/IEcommerceSellerProfile";

/**
 * Retrieve a seller's shop profile by profile ID, including shop name, description, and logo image URL.
 *
 * This operation allows customers to view seller information when browsing products or viewing order details. Administrators can also access this endpoint for oversight and dispute resolution purposes. The profile displays current shop information as maintained by the seller.
 *
 * **Access Control**
 *
 * - Customers: Can view any seller's profile for transparency when browsing products
 * - Sellers: Can view their own profile
 * - Administrators: Can view all seller profiles for platform oversight
 *
 * **Data Preserved in Snapshots**
 *
 * Shop profile information at the time of purchase is preserved in order item snapshots, ensuring historical accuracy even if the seller updates their profile later.
 *
 * @param props.connection
 * @param props.profileId Unique identifier of the seller profile (UUID format).
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification 1. Extract profileId from path parameter (UUID format)
 * 2. Validate profileId is a valid UUID format
 * 3. Query ecommerce_seller_profiles table WHERE id = profileId AND deleted_at IS NULL
 * 4. If profile not found, return 404 Not Found
 * 5. Verify authorization:
 *    - If requester is customer: allow access (public seller profiles)
 *    - If requester is seller: verify ecommerce_seller_id matches requester's seller account
 *    - If requester is admin: allow access
 * 6. Return the full seller profile entity including shop_name, shop_description, and logo_image_url
 * 7. Join with ecommerce_sellers table to verify seller account is not banned (optional, for access control)
 * @path /ecommerce/customer/profiles/:profileId
 * @accessor api.functional.ecommerce.customer.profiles.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the seller profile (UUID format).
     */
    profileId: string & tags.Format<"uuid">;
  };
  export type Response = IEcommerceSellerProfile;

  export const METADATA = {
    method: "GET",
    path: "/ecommerce/customer/profiles/:profileId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerce/customer/profiles/${encodeURIComponent(props.profileId ?? "null")}`;
  export const random = (): IEcommerceSellerProfile =>
    typia.random<IEcommerceSellerProfile>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("profileId")(() => typia.assert(props.profileId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
