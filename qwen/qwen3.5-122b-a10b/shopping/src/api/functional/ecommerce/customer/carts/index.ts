/**
 * Retrieve a customer's shopping cart with all items and stock availability status.
 *
 * This operation returns the complete cart entity including all cart items with their current product variant details, quantities, and stock availability status. The system validates that each cart item's product variant is still in stock and marks unavailable items accordingly.
 *
 * ## Cart Item Availability
 *
 * When a product variant's stock quantity reaches zero, the corresponding cart item is automatically marked as unavailable. Customers cannot proceed to checkout with unavailable items in their cart. Deleted products are automatically removed from all customer carts.
 *
 * ## Authorization
 *
 * Only the cart owner (the customer who owns this cart) can access this endpoint. The system validates that the authenticated customer's ID matches the cart's owner before returning data.
 *
 * ## Stock Validation
 *
 * The response includes real-time stock availability for each cart item based on the current inventory records. Items may be marked as unavailable if the variant stock has been depleted since the item was added to the cart.
 *
 * @param props.connection
 * @param props.cartId Unique identifier of the shopping cart to retrieve (UUID format).
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification 1. Validate cartId is a valid UUID format
 * 2. Query ecommerce_carts table by id with soft delete check (deleted_at IS NULL)
 * 3. Verify cart ownership: authenticated customer ID must match ecommerce_customer_id
 * 4. If cart not found or unauthorized, return 404 Not Found
 * 5. Join with ecommerce_cart_items where deleted_at IS NULL
 * 6. For each cart item, join with ecommerce_product_variants to get variant details
 * 7. Calculate current stock quantity for each variant by summing all ecommerce_inventory_records
 * 8. Mark cart items as unavailable if variant stock quantity equals zero
 * 9. Return cart with embedded cart items array including availability status
 * 10. Handle edge cases: empty cart (return cart with empty items array), variant deleted (item removed from cart per requirements)
 * @path /ecommerce/customer/carts/:cartId
 * @accessor api.functional.ecommerce.customer.carts.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
