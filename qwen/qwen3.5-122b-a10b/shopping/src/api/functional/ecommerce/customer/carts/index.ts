/**
 * Retrieve the customer's shopping cart with all items and stock validation information.
 *
 * This operation returns the authenticated customer's shopping cart containing all added product variants with quantities, prices, and current stock availability. Each cart item includes the associated product and variant details for display purposes.
 *
 * **Stock Validation**
 *
 * The system validates stock availability for each cart item. Items with variants that are out of stock are marked as unavailable. Out of stock variants cannot be added to the cart, but existing cart items may become unavailable if stock is depleted by other orders.
 *
 * **Product Deletion Handling**
 *
 * When a seller deletes a product, all cart items referencing that product are automatically removed from all customers' carts. When a variant is deleted, cart items referencing that variant are marked as unavailable but retained for customer review.
 *
 * **Checkout Restrictions**
 *
 * Customers cannot proceed to checkout if any cart item is unavailable (out of stock or deleted variant). Cart validation checks stock availability before allowing checkout completion.
 *
 * @param props.connection
 * @param props.body Cart retrieval options including flags for including detailed product/variant information and validation preferences.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query the ecommerce_carts table for the authenticated customer's cart. Join with ecommerce_cart_items to retrieve all cart items. For each cart item, join with ecommerce_product_variants to get variant details (sku_code, option_values, price). Join with ecommerce_products to get product details (name, description, base_price).
 *
 * Stock quantity calculation: Sum all ecommerce_inventory_records for each variant to determine current stock. If stock equals zero, mark the variant as out of stock.
 *
 * Apply automatic cleanup: Remove cart items where the product is deleted (deleted_at is not null). Mark cart items as unavailable where the variant is deleted or out of stock.
 *
 * Return cart with items array containing: cart item id, quantity, variant details, product details, calculated price (variant.price or product.base_price), stock status (in_stock, out_of_stock, deleted), and availability flag.
 *
 * Calculate cart totals: sum of (quantity × price) for all available items. Include item count and unavailable item count in response.
 * @path /ecommerce/customer/carts
 * @accessor api.functional.ecommerce.customer.carts.search
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function search(
  connection: IConnection,
  props: search.Props,
): Promise<search.Response> {
  return true === connection.simulate
    ? search.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...search.METADATA,
          path: search.path(),
          status: null,
        },
        props.body,
      );
}
