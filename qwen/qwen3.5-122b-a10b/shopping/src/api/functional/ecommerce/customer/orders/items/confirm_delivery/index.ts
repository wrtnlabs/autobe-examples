/**
 * Confirm delivery for an individual order item.
 *
 * This operation allows customers to manually confirm that they have received a specific order item. When delivery is confirmed, the order item transitions from "shipped" to "delivered" status.
 *
 * **Important Note on Delivery Confirmation Scope**
 *
 * Per business requirements, delivery confirmation typically applies at the shipment level, not individual items. All items within the same shipment share the same tracking information and delivery status. When a customer confirms delivery for a shipment, all order items in that shipment are updated simultaneously.
 *
 * This endpoint provides item-level confirmation as an alternative interface, but the underlying implementation must ensure consistency with shipment-level status. If an item belongs to a shipment, confirming delivery for one item should update all items in that shipment.
 *
 * **Status Transition**
 *
 * Once an order item is marked as delivered (either manually or automatically), the delivery status cannot be reverted to shipped. This ensures data integrity and prevents status manipulation.
 *
 * **Automatic Delivery Confirmation**
 *
 * If a customer does not manually confirm delivery within 14 days from the shipping date, the system automatically marks all items in the shipment as delivered. This automatic trigger ensures orders are not left in pending status indefinitely.
 *
 * **Authorization**
 *
 * Only the customer who owns the order can confirm delivery for its items. Sellers and administrators cannot confirm delivery on behalf of customers.
 *
 * @param props.connection
 * @param props.orderId UUID of the parent order containing the item (global scope)
 * @param props.itemId UUID of the order item to confirm delivery for (scoped to order)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification 1. Validate path parameters: orderId (UUID), itemId
 *   (UUID) 2. Verify order item exists and belongs to the specified order
 *   (order_item.ecommerce_order_id = orderId) 3. Verify the authenticated
 *   customer owns the order (order.ecommerce_customer_id = current_customer_id)
 *   4. Verify order item status is "shipped" (not already "delivered",
 *   "cancelled", or "refunded") 5. Find the shipment containing this order item
 *   via ecommerce_shipment_items junction table 6. If item belongs to a
 *   shipment: - Update all order items in the same shipment: set status =
 *   "delivered" - Update shipment: set delivered_at = current_timestamp, status
 *   = "delivered" 7. If item does not belong to any shipment (edge case): -
 *   Update only this order item: set status = "delivered" 8. Recalculate parent
 *   order status based on all order items' statuses 9. Return the updated order
 *   item object with status "delivered"
 *
 * **Error Cases**:
 * - 404: Order item not found or does not belong to order
 * - 403: Customer does not own the order
 * - 409: Order item already delivered (status is not "shipped")
 * - 400: Order item status is not "shipped" (e.g., paid, cancelled, refunded)
 * @path /ecommerce/customer/orders/:orderId/items/:itemId/confirm-delivery
 * @accessor api.functional.ecommerce.customer.orders.items.confirm_delivery.confirmDelivery
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
