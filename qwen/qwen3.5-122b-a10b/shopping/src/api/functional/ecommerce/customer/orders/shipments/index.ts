/**
 * Retrieve a paginated list of shipments associated with a specific order, including tracking information and linked order items.
 *
 * This endpoint allows customers to view all shipments for their order, displaying carrier details, tracking numbers, and delivery status. For orders with multiple shipments from different sellers, each shipment shows its own tracking information independently.
 *
 * **Tracking Information**
 *
 * Each shipment includes the carrier name, tracking number, and optional tracking URL. Customers can use the tracking number with the carrier's website to track their package in real-time.
 *
 * **Shipment Contents**
 *
 * The response includes which order items are included in each shipment, allowing customers to see what products are in each package. All items in the same shipment share the same tracking information.
 *
 * **Delivery Status**
 *
 * Shipments progress through tracking states: pending, shipped, in_transit, delivered, or exception. When a shipment is created, all linked order items change to "shipped" status. When the customer confirms delivery (or after 14 days auto-delivery), all items change to "delivered" status.
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the order (UUID format).
 * @param props.body Search criteria and pagination parameters for filtering and paginating shipment results.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query the ecommerce_shipments table filtered by order_id foreign key. Join with ecommerce_shipment_items to retrieve included order items for each shipment.
 *
 * **Implementation Steps**:
 *
 * 1. Validate the order exists and the authenticated user has access (customer who owns the order, seller of items in the order, or admin)
 * 2. Query shipments where order_id matches the path parameter
 * 3. For each shipment, fetch associated shipment_items to include order item references
 * 4. Apply pagination from request body (offset, limit)
 * 5. Apply optional filters from request body (status, carrier_name)
 * 6. Return paginated response with shipment summaries including tracking information and order item IDs
 *
 * **Business Rules**:
 *
 * - Row-level security: Customers can only view shipments for their own orders
 * - Sellers can view shipments containing their products
 * - Admins can view all shipments
 * - Include order item IDs in each shipment to show which items are in each package
 * - shipped_at is required, delivered_at is nullable (auto-set after 14 days if not manually confirmed)
 *
 * **Error Handling**:
 *
 * - Return 404 if order does not exist
 * - Return 403 if user lacks permission to view this order's shipments
 * - Return 400 for invalid pagination parameters
 * @path /ecommerce/customer/orders/:orderId/shipments
 * @accessor api.functional.ecommerce.customer.orders.shipments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
