import { IConnection, PlainFetcher } from "@nestia/fetcher";
import typia from "typia";

import { IEcommerceCart } from "../../../../../structures/IEcommerceCart";

/**
 * Retrieve the customer's shopping cart summary with all items, prices, quantities, and total price calculation.
 *
 * This endpoint returns the current state of the authenticated customer's shopping cart, including all product variants they have added for potential purchase. Each cart item displays the product name, variant options, unit price, quantity, and calculated subtotal. The response also includes the total price of all items and stock availability warnings.
 *
 * The cart total is calculated by summing all cart item subtotals (unit price multiplied by quantity for each item). If any variant has insufficient stock or has been deleted by the seller, it is marked as unavailable in the response.
 *
 * **Security**: Only the cart owner (authenticated customer) can access their own cart summary.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query the ecommerce_carts table to retrieve the authenticated customer's cart by ecommerce_customer_id from session context.
 *
 * Join with ecommerce_cart_items table to fetch all cart items (exclude soft-deleted items where deleted_at IS NOT NULL).
 *
 * For each cart item, join with ecommerce_product_variants to get variant details (sku_code, option_values, price), then join with ecommerce_products to get product name and base_price.
 *
 * Calculate each item's subtotal as: (variant.price OR product.base_price) * cart_item.quantity.
 *
 * Calculate total price by summing all item subtotals.
 *
 * Check stock availability by querying ecommerce_inventory_records for each variant and comparing total stock quantity with cart quantity.
 *
 * Mark variants as unavailable if: deleted_at IS NOT NULL on variant, OR stock quantity < cart quantity.
 *
 * Return cart summary with items array and total price.
 * @path /ecommerce/customer/cart/summary
 * @accessor api.functional.ecommerce.customer.cart.summary.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = IEcommerceCart.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/ecommerce/customer/cart/summary",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerce/customer/cart/summary";
  export const random = (): IEcommerceCart.ISummary =>
    typia.random<IEcommerceCart.ISummary>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
