import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IEcommerceReview } from "../../../../structures/IEcommerceReview";
import { IPageIEcommerceReview } from "../../../../structures/IPageIEcommerceReview";

/**
 * Retrieve paginated list of customer reviews for a specific product, sorted by newest first.
 *
 * This endpoint returns all non-deleted reviews associated with the specified product. Reviews are sorted by creation date in descending order, with the most recent reviews appearing first. The response includes review summaries with rating, content preview, customer information, and timestamps.
 *
 * **Filtering and Pagination**
 *
 * The request body supports optional filtering by rating range, customer identifier, and date ranges. Pagination is handled through cursor-based or offset-based mechanisms with configurable page size. Sorting can be customized beyond the default newest-first order.
 *
 * **Review Visibility**
 *
 * Only non-deleted reviews are included in the response. Deleted reviews (where deleted_at is not null) are excluded from both the list and the product's average rating calculation. Each review includes the star rating (1-5) and optional text content provided by the customer.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the product to retrieve reviews for (UUID format).
 * @param props.body Search criteria including rating filters, customer filters, date ranges, and pagination parameters for reviewing product feedback.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query ecommerce_reviews table filtered by product_id. Apply pagination (cursor or offset-based), sorting (default: created_at DESC for newest first), and optional filters (rating range, customer_id). Exclude reviews where deleted_at is not null. Join with ecommerce_customers for customer display name if requested. Return paginated review summaries optimized for product detail page display. Validate that product exists before querying reviews.
 * @path /ecommerce/products/:productId/reviews
 * @accessor api.functional.ecommerce.products.reviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the product to retrieve reviews for (UUID format).
     */
    productId: string & tags.Format<"uuid">;

    /**
     * Search criteria including rating filters, customer filters, date ranges, and pagination parameters for reviewing product feedback.
     */
    body: IEcommerceReview.IRequest;
  };
  export type Body = IEcommerceReview.IRequest;
  export type Response = IPageIEcommerceReview.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerce/products/:productId/reviews",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/ecommerce/products/${encodeURIComponent(props.productId ?? "null")}/reviews`;
  export const random = (): IPageIEcommerceReview.ISummary =>
    typia.random<IPageIEcommerceReview.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
