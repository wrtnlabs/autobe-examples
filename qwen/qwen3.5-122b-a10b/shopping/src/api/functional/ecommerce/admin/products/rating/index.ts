import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IEcommerceProductRating } from "../../../../../structures/IEcommerceProductRating";

/**
 * Retrieve the average rating for a specific product.
 *
 * Returns the calculated average rating from all non-deleted customer reviews for this product. Reviews are excluded from the calculation if they have been soft-deleted by customers. If no non-deleted reviews exist for the product, the average rating will be null.
 *
 * **Rating Calculation**
 *
 * The average is computed as the arithmetic mean of all rating values (1-5 stars) from active reviews. Deleted reviews are completely excluded from both the sum and count used in the calculation.
 *
 * **Product Verification**
 *
 * The endpoint validates that the product exists before returning rating information. A 404 response is returned if the product ID does not correspond to any product in the system.
 *
 * @param props.connection
 * @param props.productId Product identifier (UUID scope)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query ecommerce_reviews table to calculate average rating for the given product. Filter reviews where deleted_at IS NULL. Calculate AVG(rating) from non-deleted reviews for the product_id. Return null if no non-deleted reviews exist. Join with ecommerce_products to verify product exists. Return 404 if product not found.
 * @path /ecommerce/admin/products/:productId/rating
 * @accessor api.functional.ecommerce.admin.products.rating.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Product identifier (UUID scope)
     */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IEcommerceProductRating;

  export const METADATA = {
    method: "GET",
    path: "/ecommerce/admin/products/:productId/rating",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerce/admin/products/${encodeURIComponent(props.productId ?? "null")}/rating`;
  export const random = (): IEcommerceProductRating =>
    typia.random<IEcommerceProductRating>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
