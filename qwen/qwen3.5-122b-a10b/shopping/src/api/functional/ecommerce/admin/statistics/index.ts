import { IConnection, PlainFetcher } from "@nestia/fetcher";
import typia from "typia";

import { IEcommerceStatistic } from "../../../../structures/IEcommerceStatistic";

/**
 * Retrieve aggregated e-commerce platform statistics for dashboard display.
 *
 * This endpoint returns summary metrics including order counts by status, product counts, and pending request counts for cancellation and refund requests. The statistics are calculated on-demand from the current state of orders, products, and request records.
 *
 * **Statistics Included**
 *
 * - Total order counts broken down by status (paid, shipped, delivered, cancelled, refunded, partially_completed)
 * - Total product counts for seller's products or platform-wide
 * - Pending cancellation request count
 * - Pending refund request count
 *
 * **Access Control**
 *
 * - Sellers: View statistics for their own shop (products they own, order items for their products)
 * - Administrators: View platform-wide statistics across all sellers and orders
 *
 * **Response Format**
 *
 * The response contains aggregated counts optimized for dashboard display without requiring the client to perform calculations.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query aggregated statistics from ecommerce_orders,
 *   ecommerce_products, ecommerce_cancellation_requests, and
 *   ecommerce_refund_requests tables.
 *
 * **Implementation Steps**
 *
 * 1. Authenticate user and determine role (seller or admin)
 * 2. For sellers: filter statistics by seller_id in products and order_items tables
 * 3. For admins: return platform-wide statistics without filtering
 * 4. Calculate order counts grouped by status field
 * 5. Count total products (excluding soft-deleted)
 * 6. Count pending cancellation requests (status = 'pending')
 * 7. Count pending refund requests (status = 'pending')
 * 8. Return aggregated statistics object
 *
 * **Business Rules**
 *
 * - Only count non-soft-deleted records (deleted_at IS NULL)
 * - Order status derivation from order items should be respected
 * - Sellers only see statistics for their own products and related order items
 * - Administrators see all platform statistics
 *
 * **Edge Cases**
 *
 * - No orders: return zero counts for all order statuses
 * - No products: return zero product count
 * - No pending requests: return zero for pending cancellation/refund counts
 *
 * **Performance Considerations**
 *
 * - Use COUNT with GROUP BY for order status aggregation
 * - Add indexes on status fields for efficient filtering
 * - Consider caching statistics for frequently accessed dashboards
 * @path /ecommerce/admin/statistics
 * @accessor api.functional.ecommerce.admin.statistics.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = IEcommerceStatistic;

  export const METADATA = {
    method: "GET",
    path: "/ecommerce/admin/statistics",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerce/admin/statistics";
  export const random = (): IEcommerceStatistic =>
    typia.random<IEcommerceStatistic>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
