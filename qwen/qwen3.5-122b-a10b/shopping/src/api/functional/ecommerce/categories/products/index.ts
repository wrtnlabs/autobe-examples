import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IEcommerceProduct } from "../../../../structures/IEcommerceProduct";
import { IPageIEcommerceProduct } from "../../../../structures/IPageIEcommerceProduct";

/**
 * Retrieve a paginated list of products belonging to a specific category or its subcategories.
 *
 * This operation returns all active products assigned to the specified category, including products from any subcategories. Products are filtered to exclude soft-deleted items and are returned with pagination support for efficient browsing.
 *
 * **Features**
 * - Lists products within a category hierarchy (category + subcategories)
 * - Supports pagination with cursor-based navigation
 * - Includes seller information for each product
 * - Filters out soft-deleted products
 * - Supports sorting by name, creation date, and price
 *
 * **Security**
 * - No authentication required for browsing
 * - Public access for customer product discovery
 *
 * **Relationships**
 * - Products reference the category via category_id foreign key
 * - Each product includes owner seller information
 * - Subcategory products are included in results
 *
 * @param props.connection
 * @param props.categoryId Unique identifier of the category (UUID scope). Products from this category and its subcategories will be returned.
 * @param props.body Search criteria including pagination parameters, sorting options, and optional filters for product name and price range.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query ecommerce_products table filtered by
 *   category_id. Include products from subcategories by joining with parent
 *   category. Apply soft-delete filter (deleted_at IS NULL). Implement
 *   cursor-based pagination with limit/offset. Support sorting by created_at,
 *   name, base_price. Join with ecommerce_sellers for seller information.
 *   Validate category exists and is not soft-deleted. Return paginated product
 *   summaries with seller details.
 * @path /ecommerce/categories/:categoryId/products
 * @accessor api.functional.ecommerce.categories.products.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the category (UUID scope). Products from this category and its subcategories will be returned.
     */
    categoryId: string & tags.Format<"uuid">;

    /**
     * Search criteria including pagination parameters, sorting options, and optional filters for product name and price range.
     */
    body: IEcommerceProduct.IRequest;
  };
  export type Body = IEcommerceProduct.IRequest;
  export type Response = IPageIEcommerceProduct.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerce/categories/:categoryId/products",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/ecommerce/categories/${encodeURIComponent(props.categoryId ?? "null")}/products`;
  export const random = (): IPageIEcommerceProduct.ISummary =>
    typia.random<IPageIEcommerceProduct.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("categoryId")(() => typia.assert(props.categoryId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
