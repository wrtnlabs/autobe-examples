/**
 * Submit administrator registration request with email, password, and reason for approval.
 *
 * This endpoint allows users to request administrator access by providing their email address, password, and justification. The system validates the credentials against security requirements and creates a pending administrator request that requires super admin approval before full access is granted.
 *
 * **Request Validation**
 * - Email must be unique across all admin accounts
 * - Password must meet minimum strength requirements (8+ characters, mixed case, numbers)
 * - Reason field is required and must be non-empty
 *
 * **Response**
 * Returns IAuthorized with temporary access and refresh tokens. The admin account remains in pending approval status until a super admin reviews and approves the request via the admin_requests approval endpoint.
 *
 * **Related Operations**
 * - login: After approval, use login endpoint with same credentials
 * - refresh: Renew expired tokens using refresh token
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Administrator registration request with email, password, and approval reason.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Administrator registration endpoint. Validates email
 *   uniqueness and password strength, creates administrator request record in
 *   ecommerce_admin_requests table, sends email verification token to
 *   ecommerce_admin_email_verifications table. Requires email format validation
 *   (RFC 5322), password minimum 8 characters with uppercase, lowercase,
 *   number. On success, returns IAuthorized with temporary tokens pending
 *   approval. Implementation: 1) Validate request body against schema, 2) Check
 *   email not already registered in ecommerce_admins, 3) Create admin request
 *   record with reason, 4) Generate and store email verification token with
 *   expiration, 5) Return IAuthorized with limited-scope tokens.
 * @path /ecommerce/auth/admin/join
 * @accessor api.functional.ecommerce.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
