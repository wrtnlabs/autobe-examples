import { tags } from "typia";

export namespace IEcommerceMallSalesAnalytic {
  /**
   * Sales analytics summary record containing aggregated metrics for a specific time period in the e-commerce mall platform. This DTO represents a single row of sales analytics data, including total revenue, order count, average order value, and item count for the specified period. Optional fields (sellerId, sellerName, categoryId, categoryName, status) provide context when the analytics are filtered by seller, product category, or order status. Metrics are calculated in real-time from orders and order items tables, optimized for dashboard displays and reporting interfaces. Each record is uniquely identified by an id and covers a specific date period. When no filters are applied, records represent overall platform sales. When filters are applied, records are segmented by the filter dimensions.
   */
  export type ISummary = {
    /**
     * Unique identifier for this sales analytics record.
     *
     * @x-autobe-specification Unique identifier for this analytics record. Generated by the analytics query system to distinguish individual aggregated records. Not mapped to any database column.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Time period covered by this analytics record, formatted as date-time.
     *
     * @x-autobe-specification Time period this analytics record covers (day or hour granularity). Derived from GROUP BY date truncation of order timestamps. Not mapped to any database column.
     */
    date: string & tags.Format<"date-time">;

    /**
     * Total revenue generated from all orders in this time period.
     *
     * @x-autobe-specification Computed as SUM(orders.total_price) for all orders in the time period. Minimum value is 0. Aggregation from ecommerce_mall_orders table.
     */
    totalRevenue: number & tags.Minimum<0>;

    /**
     * Number of distinct orders placed in this time period.
     *
     * @x-autobe-specification Computed as COUNT(DISTINCT orders.id) for all orders in the time period. Minimum value is 0. Aggregation from ecommerce_mall_orders table.
     */
    orderCount: number & tags.Type<"int32"> & tags.Minimum<0>;

    /**
     * Average value per order in this time period, calculated as total revenue divided by order count.
     *
     * @x-autobe-specification Computed as totalRevenue / orderCount. Minimum value is 0. Derived from aggregating ecommerce_mall_orders table.
     */
    averageOrderValue: number & tags.Minimum<0>;

    /**
     * Total number of items (sum of quantities) across all orders in this time period.
     *
     * @x-autobe-specification Computed as SUM(order_items.quantity) for all order items in orders within the time period. Minimum value is 0. Aggregation from ecommerce_mall_order_items table.
     */
    itemCount: number & tags.Type<"int32"> & tags.Minimum<0>;

    /**
     * Seller identifier when analytics are filtered by seller. Null if no seller filter applied.
     *
     * @x-autobe-specification Optional filter dimension: seller ID when analytics are filtered by specific seller. Null when no seller filter applied. JOIN with ecommerce_mall_sellers table for sellerName. Not mapped to any database column.
     */
    sellerId?: (string & tags.Format<"uuid">) | null | undefined;

    /**
     * Seller shop name when analytics are filtered by seller. Null if no seller filter applied.
     *
     * @x-autobe-specification Optional filter dimension: seller name when analytics are filtered by specific seller. Null when no seller filter applied. Derived from JOIN with ecommerce_mall_sellers table. Not mapped to any database column.
     */
    sellerName?: string | null | undefined;

    /**
     * Category identifier when analytics are filtered by product category. Null if no category filter applied.
     *
     * @x-autobe-specification Optional filter dimension: category ID when analytics are filtered by specific product category. Null when no category filter applied. JOIN with ecommerce_mall_products and ecommerce_mall_categories tables for categoryName. Not mapped to any database column.
     */
    categoryId?: (string & tags.Format<"uuid">) | null | undefined;

    /**
     * Category name when analytics are filtered by product category. Null if no category filter applied.
     *
     * @x-autobe-specification Optional filter dimension: category name when analytics are filtered by specific product category. Null when no category filter applied. Derived from JOIN with ecommerce_mall_products and ecommerce_mall_categories tables. Not mapped to any database column.
     */
    categoryName?: string | null | undefined;

    /**
     * Order status filter when analytics are filtered by order status. Null if no status filter applied.
     *
     * @x-autobe-specification Optional filter dimension: order status when analytics are filtered by specific order status (paid, shipped, delivered, cancelled, refunded, partiallyCompleted). Null when no status filter applied. Not mapped to any database column.
     */
    status?: string | null | undefined;
  };

  /**
   * Request body for querying sales analytics data with comprehensive filtering and pagination capabilities.
   *
   * This request enables sellers and administrators to retrieve aggregated sales statistics across various dimensions including date ranges, order statuses, sellers, and product categories. The operation calculates key metrics such as total revenue, order counts, and average order values from the order and order item tables.
   *
   * Date range filtering is enforced with a maximum 90-day window to maintain query performance. All filter parameters are optional, allowing flexible querying from broad overviews to highly specific analyses. Pagination supports offset-based navigation for large result sets.
   *
   * Sorting can be applied on creation date, total price, or status fields with ascending or descending order. The response includes aggregated sales summaries optimized for dashboard displays and reporting interfaces.
   */
  export type IRequest = {
    /**
     * Start date for the analytics query range. Orders created on or after this date will be included. Maximum 90 days before date_to.
     *
     * @x-autobe-specification Query parameter for filtering orders by creation date. Used in WHERE clause: orders.created_at >= date_from. Enforced to be within 90 days of date_to at service layer. Format: ISO 8601 date-time string.
     */
    date_from?: (string & tags.Format<"date-time">) | undefined;

    /**
     * End date for the analytics query range. Orders created before this date will be included. Defaults to current time if not specified.
     *
     * @x-autobe-specification Query parameter for filtering orders by creation date. Used in WHERE clause: orders.created_at < date_to. Defaults to current timestamp if not provided. Format: ISO 8601 date-time string.
     */
    date_to?: (string & tags.Format<"date-time">) | undefined;

    /**
     * Filter orders by status. Valid values: paid, shipped, delivered, cancelled, refunded, partiallyCompleted. If not specified, includes all statuses.
     *
     * @x-autobe-specification Query parameter for filtering orders by status. Used in WHERE clause: orders.status = status. Valid values: paid, shipped, delivered, cancelled, refunded, partiallyCompleted. If omitted, all statuses are included.
     */
    status?: string | undefined;

    /**
     * Filter analytics by specific seller. If not specified, includes all sellers accessible to the authenticated user.
     *
     * @x-autobe-specification Query parameter for filtering analytics by seller. Used in WHERE clause: orders.seller_id = seller_id (via JOIN on order_items). UUID format. If omitted, includes all sellers accessible to the authenticated user.
     */
    seller_id?: (string & tags.Format<"uuid">) | undefined;

    /**
     * Filter analytics by product category. If not specified, includes all categories.
     *
     * @x-autobe-specification Query parameter for filtering analytics by product category. Used in WHERE clause via JOIN: products.category_id = category_id. UUID format. If omitted, includes all categories.
     */
    category_id?: (string & tags.Format<"uuid">) | undefined;

    /**
     * Search term for filtering orders by order number or related product names.
     *
     * @x-autobe-specification Query parameter for text search filtering. Used in WHERE clause with LIKE operator: order_number LIKE %search% OR product_name LIKE %search%. Case-insensitive matching. If omitted, no text filtering applied.
     */
    search?: string | undefined;

    /**
     * Page number for offset-based pagination. Starts from 1.
     *
     * @x-autobe-specification Pagination parameter for offset-based paging. Used to calculate OFFSET: (page - 1) * limit. Minimum value: 1. Defaults to 1 if not provided.
     */
    page?: (number & tags.Type<"int32"> & tags.Minimum<1>) | undefined;

    /**
     * Number of results per page. Maximum 100 results per request.
     *
     * @x-autobe-specification Pagination parameter for result set size. Used as LIMIT in SQL query. Minimum: 1, Maximum: 100. Defaults to a reasonable page size if not provided.
     */
    limit?:
      | (number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<100>)
      | undefined;

    /**
     * Field to sort results by. Default: created_at.
     *
     * @x-autobe-specification Sorting parameter for result ordering. Used in ORDER BY clause. Valid values: created_at, total_price, status, order_number. Defaults to created_at if not specified.
     */
    sort_by?:
      | "created_at"
      | "total_price"
      | "status"
      | "order_number"
      | undefined;

    /**
     * Sort order direction. Default: desc (newest first).
     *
     * @x-autobe-specification Sorting direction parameter. Used in ORDER BY clause as ASC or DESC. Valid values: asc, desc. Defaults to desc (newest/highest first) if not specified.
     */
    sort_order?: "asc" | "desc" | undefined;
  };
}
