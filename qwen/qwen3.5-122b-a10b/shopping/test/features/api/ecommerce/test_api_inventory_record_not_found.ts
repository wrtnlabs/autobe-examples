export async function test_api_inventory_record_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceSeller.IJoin,
  });
  typia.assert(seller);
  // 2. Create a product
  const product = await generate_random_ecommerce_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(3),
        description: RandomGenerator.paragraph({ sentences: 5 }),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      },
    },
  );
  typia.assert(product);
  // 3. Create a variant for the product
  const variant =
    await generate_random_ecommerce_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
        body: {
          sku_code: RandomGenerator.alphaNumeric(10),
          option_values: `color=${RandomGenerator.name(1)};size=${RandomGenerator.name(1)}`,
        },
      },
    );
  typia.assert(variant);
  // 4. Attempt to retrieve a non-existent inventory record
  // Use a random UUID that doesn't exist in the database
  const nonExistentRecordId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "inventory record not found should return 404",
    404,
    async () => {
      await api.functional.ecommerce.seller.variants.inventory.at(
        sellerConnection,
        {
          variantId: variant.id,
          recordId: nonExistentRecordId,
        },
      );
    },
  );
}
