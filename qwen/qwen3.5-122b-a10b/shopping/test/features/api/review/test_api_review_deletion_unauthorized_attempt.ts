/**
 * Test customer attempts to delete another customer's review and receives authorization error.
 *
 * This test validates ownership enforcement for review deletion:
 * 1. Two customers register and authenticate
 * 2. Admin creates category for product classification
 * 3. Seller creates product with variants
 * 4. First customer places order and submits review
 * 5. Second customer attempts to delete the first customer's review using the review ID
 * 6. System must reject unauthorized deletion with 403 Forbidden response
 * 7. Original review's content, rating, and visibility must be preserved
 *
 * This validates that review deletion is strictly limited to the review owner and prevents malicious deletion of other customers' feedback.
 */
export async function test_api_review_deletion_unauthorized_attempt(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register two customers
  const customer1Connection: api.IConnection = { host: connection.host };
  const customer1 = await authorize_customer_join(customer1Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customer1);
  const customer2Connection: api.IConnection = { host: connection.host };
  const customer2 = await authorize_customer_join(customer2Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customer2);
  // 2. Register and login admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email"> & tags.MinLength<1> & tags.MaxLength<255>>(),
      password: typia.random<string & tags.MinLength<8> & tags.MaxLength<128>>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  // 3. Register and login seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(seller);
  // 4. Admin creates category
  const category = await api.functional.ecommerceMall.admin.categories.create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(),
      } satisfies IEcommerceMallCategory.ICreate,
    },
  );
  typia.assert(category);
  // 5. Seller creates product
  const product = await api.functional.ecommerceMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        category_id: category.id,
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 6. Seller creates variant
  const variant =
    await api.functional.ecommerceMall.seller.products.variants.create(
      sellerConnection,
      {
        productId: product.id,
        body: {
          skuCode: RandomGenerator.alphaNumeric(10),
          optionValues: [{ key: "color", value: "Red" }],
          stockQuantity: 100,
        } satisfies IEcommerceMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 7. First customer creates shipping address
  const address = await api.functional.ecommerceMall.customer.addresses.create(
    customer1Connection,
    {
      body: {
        recipient_name: RandomGenerator.name(),
        phone_number: RandomGenerator.mobile(),
        street_address: RandomGenerator.paragraph({ sentences: 1 }),
        city: RandomGenerator.name(),
        state_province: RandomGenerator.name(),
        postal_code: RandomGenerator.alphaNumeric(10),
        country: "South Korea",
      } satisfies IEcommerceMallAddress.ICreate,
    },
  );
  typia.assert(address);
  // 8. First customer adds variant to cart
  const cartItem =
    await api.functional.ecommerceMall.customer.cart_items.create(
      customer1Connection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 1,
        } satisfies IEcommerceMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 9. First customer places order (need to deliver first for review eligibility)
  const order = await api.functional.ecommerceMall.customer.orders.create(
    customer1Connection,
    {
      body: {
        shipping_recipient_name: address.recipientName,
        shipping_phone_number: address.phoneNumber,
        shipping_street_address: address.streetAddress,
        shipping_city: address.city,
        shipping_state: address.stateProvince,
        shipping_postal_code: address.postalCode,
        shipping_country: address.country,
      } satisfies IEcommerceMallOrder.ICreate,
    },
  );
  typia.assert(order);
  // Note: In real scenario, seller would ship and customer would confirm delivery
  // For testing purposes, we assume the order item is delivered
  // The review creation endpoint will validate the order item status
  // 10. First customer creates review (this should work if order item is delivered)
  // We'll need to use a review that exists or simulate the review creation
  // Since we can't directly set order item status, we'll create review with valid order item
  const review = await api.functional.ecommerceMall.customer.reviews.create(
    customer1Connection,
    {
      body: {
        order_item_id: order.order_items[0].id,
        product_id: product.id,
        rating: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
        >(),
        content: RandomGenerator.paragraph({ sentences: 2 }),
      } satisfies IEcommerceMallReview.ICreate,
    },
  );
  typia.assert(review);
  // 11. Second customer attempts to delete first customer's review (UNAUTHORIZED)
  await TestValidator.httpError(
    "unauthorized review deletion should fail with 403",
    403,
    async () => {
      await api.functional.ecommerceMall.customer.reviews.erase(
        customer2Connection,
        {
          reviewId: review.id,
        },
      );
    },
  );
  // 12. Verify review still exists and is not deleted
  // Note: We would need a GET endpoint to verify, but since it's not provided,
  // we rely on the httpError validator to confirm the deletion was rejected
}