export async function test_api_order_item_cancellation_requests_view_existing(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceCustomer.IJoin,
  });
  typia.assert(customer);
  // 2. Generate UUIDs for order and order item (in production, these would be from created resources)
  const orderId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  const itemId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  // 3. View cancellation requests for the order item
  const result: IPageIEcommerceCancellationRequest.ISummary =
    await api.functional.ecommerce.customer.orders.items.cancellation_requests.index(
      customerConnection,
      {
        orderId,
        itemId,
        body: {} satisfies IEcommerceCancellationRequest.IRequest,
      },
    );
  typia.assert(result);
  // 4. Validate pagination metadata structure
  TestValidator.predicate(
    "pagination has current page",
    result.pagination.current >= 0,
  );
  TestValidator.predicate("pagination has limit", result.pagination.limit >= 0);
  TestValidator.predicate(
    "pagination has records",
    result.pagination.records >= 0,
  );
  TestValidator.predicate("pagination has pages", result.pagination.pages >= 0);
}
