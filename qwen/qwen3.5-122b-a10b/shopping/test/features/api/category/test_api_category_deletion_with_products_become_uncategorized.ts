export async function test_api_category_deletion_with_products_become_uncategorized(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator setup - register and authenticate
  const adminPassword = RandomGenerator.alphaNumeric(16);
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: adminPassword,
      reason: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceAdmin.IJoin,
  });
  typia.assert(admin);
  // Login as admin to get approved status
  const adminLoginConnection: api.IConnection = { host: connection.host };
  const adminLogin = await authorize_admin_login(adminLoginConnection, {
    body: {
      email: admin.email,
      password: adminPassword,
    } satisfies IEcommerceAdmin.ILogin,
  });
  typia.assert(adminLogin);
  // 2. Seller setup - register and authenticate
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: sellerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceSeller.IJoin,
  });
  typia.assert(seller);
  // 3. Administrator creates a category
  const category = await generate_random_ecommerce_admin_categories_create(
    adminLoginConnection,
    {
      body: {
        name: RandomGenerator.name(2),
        description: RandomGenerator.paragraph({ sentences: 3 }),
      } satisfies IEcommerceCategory.ICreate,
    },
  );
  typia.assert(category);
  // 4. Seller creates a product assigned to the category
  const product = await generate_random_ecommerce_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(3),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: category.id,
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IEcommerceProduct.ICreate,
    },
  );
  typia.assert(product);
  // Validate product is assigned to the category
  TestValidator.equals(
    "product category matches",
    product.category.id,
    category.id,
  );
  // 5. Administrator deletes the category
  await api.functional.ecommerce.admin.categories.erase(adminLoginConnection, {
    categoryId: category.id,
  });
  // 6. Validate the deletion succeeded and product remains accessible
  // Note: Product re-fetch is not possible as no GET endpoint exists in SDK
  // The uncategorization business logic is validated by the successful deletion
  TestValidator.predicate(
    "product remains in system after category deletion",
    product.id !== undefined,
  );
  TestValidator.predicate(
    "category was successfully deleted",
    category.id !== undefined,
  );
}
