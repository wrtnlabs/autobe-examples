/**
 * Test customer adding a product to their wishlist.
 * 1. Customer registers and authenticates
 * 2. Seller registers and creates a product
 * 3. Customer adds the product to wishlist
 * 4. Validate wishlist entry contains correct product details
 * 5. Verify wishlist entry is active with deleted_at=null
 */
export async function test_api_customer_wishlist_product_addition(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer setup - register and authenticate
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      phone_number: null,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  // 2. Seller setup - register and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // Note: In a real scenario, seller would need admin approval before creating products.
  // For this test, we assume the seller is already approved or the system allows product creation.
  // 3. Seller creates a product
  const category_id = typia.random<string & tags.Format<"uuid">>();
  const product = await api.functional.ecommerceMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        category_id,
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 4. Customer adds the product to wishlist
  const wishlist = await api.functional.ecommerceMall.customer.wishlists.create(
    customerConnection,
    {
      body: {
        ecommerce_mall_product_id: product.id,
      } satisfies IEcommerceMallWishlist.ICreate,
    },
  );
  typia.assert(wishlist);
  // 5. Validate wishlist entry
  TestValidator.equals(
    "wishlist entry ID is valid",
    wishlist.id !== undefined,
    true,
  );
  TestValidator.equals("product ID matches", wishlist.product.id, product.id);
  TestValidator.equals(
    "product name matches",
    wishlist.product.name,
    product.name,
  );
  TestValidator.equals("active status is true", wishlist.active, true);
  TestValidator.equals("deleted_at is null", wishlist.deleted_at, null);
  TestValidator.equals(
    "customer ID matches",
    wishlist.customer.id,
    customerAuth.id,
  );
}
