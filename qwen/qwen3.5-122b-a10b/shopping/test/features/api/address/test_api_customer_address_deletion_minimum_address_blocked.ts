export async function test_api_customer_address_deletion_minimum_address_blocked(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer account
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(customer);
  // 2. Create a single shipping address for the customer
  const address =
    await generate_random_ecommerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 3. Attempt to delete the only address - should fail
  await TestValidator.error("cannot delete the only address", async () => {
    await api.functional.ecommerceMall.customer.addresses.erase(
      customerConnection,
      {
        addressId: address.id,
      },
    );
  });
}
