export async function test_api_admin_product_snapshot_view(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth: IEcommerceAdmin.IAuthorized = await authorize_admin_join(
    adminConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        reason: RandomGenerator.paragraph({ sentences: 2 }),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
        ip: typia.random<string & tags.Format<"ipv4">>(),
      } satisfies IEcommerceAdmin.IJoin,
    },
  );
  typia.assert(adminAuth);
  // 2. View specific product snapshot by ID
  const snapshot: IEcommerceProductSnapshot =
    await api.functional.ecommerce.admin.products.snapshots.at(
      adminConnection,
      {
        productId: typia.random<string & tags.Format<"uuid">>(),
        snapshotId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  typia.assert(snapshot);
  // 3. Validate snapshot data integrity
  TestValidator.predicate(
    "snapshot retrieved successfully",
    snapshot.id !== undefined,
  );
  TestValidator.predicate(
    "product reference exists",
    snapshot.ecommerce_product_id !== undefined,
  );
}
