export async function test_api_product_creation_by_approved_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate administrator
  const adminEmail = typia.random<string & tags.Format<"email">>();
  const adminPassword = RandomGenerator.alphaNumeric(16);
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: adminEmail,
      password: adminPassword,
      reason: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceAdmin.IJoin,
  });
  typia.assert(adminAuth);
  // 2. Create seller account (enters pending approval status)
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceSeller.IJoin,
  });
  typia.assert(sellerAuth);
  TestValidator.equals(
    "seller pending approval",
    sellerAuth.approval_status,
    "pending",
  );
  // 3. Administrator logs in to approve seller
  const adminLoginConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminLoginConnection, {
    body: {
      email: adminEmail,
      password: adminPassword,
    } satisfies IEcommerceAdmin.ILogin,
  });
  // 4. Administrator creates product category
  const category = await generate_random_ecommerce_admin_categories_create(
    adminLoginConnection,
    {
      body: {
        name: RandomGenerator.name(2),
        description: RandomGenerator.paragraph({ sentences: 3 }),
      } satisfies IEcommerceCategory.ICreate,
    },
  );
  typia.assert(category);
  TestValidator.predicate("category has UUID", category.id.length > 0);
  // 5. Seller logs in (simulating approval happened)
  const sellerLoginConnection: api.IConnection = { host: connection.host };
  await authorize_seller_login(sellerLoginConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceSeller.ILogin,
  });
  // 6. Seller creates product with required fields
  const product = await generate_random_ecommerce_seller_products_create(
    sellerLoginConnection,
    {
      body: {
        name: RandomGenerator.name(3),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: category.id,
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IEcommerceProduct.ICreate,
    },
  );
  typia.assert(product);
  // 7. Validate product creation
  TestValidator.predicate("product has UUID", product.id.length > 0);
  TestValidator.predicate("product name matches", product.name.length > 0);
  TestValidator.equals(
    "product has category",
    product.category.id,
    category.id,
  );
  TestValidator.equals("product is active", product.deletedAt, null);
  TestValidator.predicate("product has base price", product.basePrice > 0);
  TestValidator.predicate(
    "product has timestamps",
    product.createdAt.length > 0 && product.updatedAt.length > 0,
  );
  TestValidator.equals(
    "product seller reference",
    product.seller.id,
    sellerAuth.id,
  );
}