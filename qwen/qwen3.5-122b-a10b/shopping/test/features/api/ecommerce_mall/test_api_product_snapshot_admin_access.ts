export async function test_api_product_snapshot_admin_access(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator registers and authenticates
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<
        string &
          tags.MinLength<1> &
          tags.MaxLength<255> &
          tags.Format<"email">
      >(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  typia.assert(adminAuth);
  // 2. Seller registers and authenticates
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<
        string &
          tags.MinLength<1> &
          tags.MaxLength<255> &
          tags.Format<"email">
      >(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 3. Seller creates a product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(3),
        description: RandomGenerator.paragraph({ sentences: 5 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 4. Seller edits the product to trigger snapshot creation
  const updatedProduct =
    await api.functional.ecommerceMall.seller.products.update(
      sellerConnection,
      {
        productId: product.id,
        body: {
          name: RandomGenerator.name(4),
          description: RandomGenerator.paragraph({ sentences: 7 }),
          base_price: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<2000>
          >(),
        } satisfies IEcommerceMallProduct.IUpdate,
      },
    );
  typia.assert(updatedProduct);
  // 5. Administrator retrieves a product snapshot
  // Note: In simulation mode, this will return random snapshot data
  // In production, a list endpoint would be needed to get actual snapshot IDs
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  const snapshot = await api.functional.ecommerceMall.products.snapshots.at(
    adminConnection,
    {
      productId: product.id,
      snapshotId: snapshotId,
    },
  );
  typia.assert(snapshot);
  // 6. Validate snapshot structure and content
  TestValidator.equals(
    "snapshot belongs to product",
    snapshot.productId,
    product.id,
  );
  TestValidator.predicate(
    "snapshot has previous values",
    Object.keys(snapshot.previousValues).length > 0,
  );
  TestValidator.predicate(
    "snapshot has current values",
    Object.keys(snapshot.currentValues).length > 0,
  );
  TestValidator.predicate(
    "snapshot has creation timestamp",
    snapshot.createdAt.length > 0,
  );
  // 7. Verify administrator can access snapshot (authorization validation)
  // The successful retrieval above confirms admin has access to product snapshots
  TestValidator.predicate(
    "administrator can access product snapshot",
    snapshot !== null,
  );
}