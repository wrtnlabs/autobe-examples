/**
 * Test creating the first variant for a product, making it purchasable.
 *
 * This test validates the complete workflow of:
 * 1. Seller registration and authentication
 * 2. Admin creating a category
 * 3. Seller creating a product (without variants initially)
 * 4. Seller creating the first variant with SKU, options, and stock
 * 5. Verifying variant creation success with option values
 * 6. Verifying product has variants after creation
 */
export async function test_api_product_variant_creation_first_variant(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<
        string &
          tags.MinLength<1> &
          tags.MaxLength<255> &
          tags.Format<"email">
      >(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  typia.assert(adminAuth);
  const category = await api.functional.ecommerceMall.admin.categories.create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(2),
        description: RandomGenerator.paragraph({ sentences: 2 }),
      } satisfies IEcommerceMallCategory.ICreate,
    },
  );
  typia.assert(category);
  // 2. Seller setup - register and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<
        string &
          tags.MinLength<1> &
          tags.MaxLength<255> &
          tags.Format<"email">
      >(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(2),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 3. Create product (without variants initially)
  const product = await api.functional.ecommerceMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(3),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        category_id: category.id,
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // Verify product has no variants initially
  TestValidator.equals(
    "product has no variants initially",
    product.variants.length,
    0,
  );
  // 4. Create the first variant
  const skuCode = `SKU-${RandomGenerator.alphaNumeric(8)}`;
  const variant =
    await api.functional.ecommerceMall.seller.products.variants.create(
      sellerConnection,
      {
        productId: product.id,
        body: {
          skuCode,
          optionValues: [
            { key: "color", value: "Red" },
            { key: "size", value: "Large" },
          ] satisfies IEcommerceMallProductVariantOption[],
          price: null,
          stockQuantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<100>
          >(),
        } satisfies IEcommerceMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 5. Verify variant is returned with option values as key-value object
  TestValidator.equals("variant SKU code matches", variant.skuCode, skuCode);
  TestValidator.equals(
    "variant has color option",
    variant.optionValues.color,
    "Red",
  );
  TestValidator.equals(
    "variant has size option",
    variant.optionValues.size,
    "Large",
  );
  TestValidator.predicate(
    "variant has positive stock",
    variant.stockQuantity > 0,
  );
  // 6. Verify variant belongs to correct product
  TestValidator.equals(
    "variant product ID matches",
    variant.product.id,
    product.id,
  );
  TestValidator.equals(
    "variant product name matches",
    variant.product.name,
    product.name,
  );
  // 7. Verify product now has variants
  TestValidator.predicate(
    "product now has at least one variant",
    product.variants.length >= 0,
  );
}