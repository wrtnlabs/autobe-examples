/**
 * Test that delivery confirmation is rejected when shipment is already delivered.
 * A customer places an order, seller creates a shipment, and customer confirms delivery.
 * Then attempt to confirm delivery again for the same shipment. Verify that:
 * (1) the second confirmation request is rejected because delivered_at is already set,
 * and (2) the shipment status and order items remain unchanged.
 * This validates the idempotency constraint and prevents duplicate delivery confirmations.
 */
export async function test_api_customer_confirm_delivery_already_delivered_rejection(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin account
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  // 2. Create seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
    },
  });
  // 3. Create customer account
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 4. Admin creates category
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  // 5. Seller creates product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        category_id: category.id,
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      },
    },
  );
  // 6. Seller creates product variant
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          skuCode: RandomGenerator.alphaNumeric(10),
          optionValues: [{ key: "color", value: RandomGenerator.alphabets(5) }],
          stockQuantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<10>
          >(),
        },
      },
    );
  // 7. Customer creates shipping address
  const address =
    await generate_random_ecommerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  // 8. Customer adds variant to cart
  await generate_random_ecommerce_mall_customer_cart_items_create(
    customerConnection,
    {
      body: {
        product_variant_id: variant.id,
        quantity: 1,
      },
    },
  );
  // 9. Customer places order
  const order = await generate_random_ecommerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        shipping_recipient_name: address.recipientName,
        shipping_phone_number: address.phoneNumber,
        shipping_street_address: address.streetAddress,
        shipping_city: address.city,
        shipping_state: address.stateProvince,
        shipping_postal_code: address.postalCode,
        shipping_country: address.country,
      },
    },
  );
  // 10. Seller creates shipment
  const shipment = await generate_random_ecommerce_mall_seller_shipments_create(
    sellerConnection,
    {
      body: {
        trackingNumber: RandomGenerator.alphaNumeric(12),
        carrierName: RandomGenerator.name(),
        shippedAt: new Date().toISOString(),
        orderItemIds: order.order_items.map((item) => item.id),
      },
    },
  );
  // 11. Customer confirms delivery (first time - should succeed)
  const firstConfirmation =
    await api.functional.ecommerceMall.customer.orders.shipments.confirmDelivery(
      customerConnection,
      {
        orderId: order.id,
        shipmentId: shipment.id,
        body: {},
      },
    );
  typia.assert(firstConfirmation);
  // Validate first confirmation succeeded
  TestValidator.predicate(
    "first delivery confirmation has delivered_at set",
    firstConfirmation.delivered_at !== null,
  );
  // 12. Customer attempts to confirm delivery again (should fail)
  await TestValidator.httpError(
    "second delivery confirmation should be rejected for already delivered shipment",
    [400, 409],
    async () => {
      await api.functional.ecommerceMall.customer.orders.shipments.confirmDelivery(
        customerConnection,
        {
          orderId: order.id,
          shipmentId: shipment.id,
          body: {},
        },
      );
    },
  );
  // 13. Validate shipment ID and order ID are tracked correctly
  TestValidator.notEquals(
    "shipment and order IDs are distinct",
    shipment.id,
    order.id,
  );
  // 14. Validate order items were updated to delivered status after first confirmation
  TestValidator.predicate(
    "order items have delivered status after first confirmation",
    order.order_items.every((item) => item.status === "delivered"),
  );
}
