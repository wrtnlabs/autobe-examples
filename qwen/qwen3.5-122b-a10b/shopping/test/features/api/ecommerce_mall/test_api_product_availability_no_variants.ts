export async function test_api_product_availability_no_variants(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 2. Create product without variants (using a valid category UUID)
  // Note: Category must exist in database - using generated UUID for simulation
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Check availability - product should have no variants
  const availability = await api.functional.ecommerceMall.products.availability(
    connection,
    {
      productId: product.id,
    },
  );
  typia.assert(availability);
  // 4. Validate business rule: product without variants is not available
  TestValidator.equals(
    "isAvailable should be false",
    availability.isAvailable,
    false,
  );
  TestValidator.equals(
    "status should be active",
    availability.status,
    "active",
  );
  TestValidator.equals(
    "hasVariants should be false",
    availability.hasVariants,
    false,
  );
  TestValidator.equals(
    "variantCount should be 0",
    availability.variantCount,
    0,
  );
  TestValidator.equals(
    "inStockVariantCount should be 0",
    availability.inStockVariantCount,
    0,
  );
}
