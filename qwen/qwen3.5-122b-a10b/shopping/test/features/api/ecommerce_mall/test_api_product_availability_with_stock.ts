export async function test_api_product_availability_with_stock(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      shop_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(sellerAuth);
  // 2. Create product with variants that have stock
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(3),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      },
    },
  );
  typia.assert(product);
  // 3. Check product availability
  const availability = await api.functional.ecommerceMall.products.availability(
    sellerConnection,
    {
      productId: product.id,
    },
  );
  typia.assert(availability);
  // 4. Validate availability response
  TestValidator.equals("isAvailable is true", availability.isAvailable, true);
  TestValidator.equals("status is active", availability.status, "active");
  TestValidator.equals("hasVariants is true", availability.hasVariants, true);
  TestValidator.equals(
    "variantCount matches product variants",
    availability.variantCount,
    product.variants.length,
  );
  // Count variants with stock > 0
  const inStockCount = product.variants.filter(
    (v) => v.stockQuantity > 0,
  ).length;
  TestValidator.equals(
    "inStockVariantCount matches variants with stock",
    availability.inStockVariantCount,
    inStockCount,
  );
}
