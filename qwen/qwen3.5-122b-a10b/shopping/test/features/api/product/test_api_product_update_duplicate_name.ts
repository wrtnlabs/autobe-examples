/**
 * Test product name uniqueness validation during update.
 * 1. Seller authenticates successfully
 * 2. Admin creates a category for products
 * 3. Seller creates two products with different names
 * 4. Seller attempts to update product1 with product2's name (should fail)
 * 5. Verify error is thrown for duplicate name
 * 6. Product1 remains unchanged (implicit - update failed)
 * 7. Seller successfully updates product1 with unique name
 */
export async function test_api_product_update_duplicate_name(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<
        string & tags.MinLength<1> & tags.MaxLength<255> & tags.Format<"email">
      >(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(2),
      } satisfies IEcommerceMallCategory.ICreate,
    },
  );
  typia.assert(category);
  // 2. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<
        string & tags.MinLength<1> & tags.MaxLength<255> & tags.Format<"email">
      >(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(2),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 3. Create two products with different names
  const product1Name = RandomGenerator.name(2);
  const product2Name = RandomGenerator.name(2);
  const product1 = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: product1Name,
        description: RandomGenerator.paragraph({ sentences: 3 }),
        category_id: category.id,
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product1);
  const product2 = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: product2Name,
        description: RandomGenerator.paragraph({ sentences: 3 }),
        category_id: category.id,
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product2);
  // 4. Attempt to update product1 with product2's name (should fail)
  await TestValidator.error("duplicate name should be rejected", async () => {
    await api.functional.ecommerceMall.seller.products.update(
      sellerConnection,
      {
        productId: product1.id,
        body: {
          name: product2Name,
        } satisfies IEcommerceMallProduct.IUpdate,
      },
    );
  });
  // 5. Successfully update product1 with unique name
  const uniqueName = RandomGenerator.name(2);
  const finalProduct1 =
    await api.functional.ecommerceMall.seller.products.update(
      sellerConnection,
      {
        productId: product1.id,
        body: {
          name: uniqueName,
        } satisfies IEcommerceMallProduct.IUpdate,
      },
    );
  typia.assert(finalProduct1);
  TestValidator.equals("product1 name updated", finalProduct1.name, uniqueName);
}
