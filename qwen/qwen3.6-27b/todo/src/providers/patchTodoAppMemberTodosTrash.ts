export async function patchTodoAppMemberTodosTrash(props: {
  member: MemberPayload;
  body: ITodoAppTodo.ITrashRequest;
}): Promise<IPageITodoAppTodo.ISummary> {
  const page = props.body.page ?? 1;
  const limit = props.body.limit ?? 100;
  const skip = (page - 1) * limit;
  const whereInput = {
    todo_app_member_id: props.member.id,
    NOT: { deleted_at: null },
    ...(props.body.is_completed !== undefined && {
      is_completed: props.body.is_completed,
    }),
  } satisfies Prisma.todo_app_todosWhereInput;
  const orderByDir = typia.assert<Prisma.SortOrder>(props.body.order ?? "desc");
  const sortField = props.body.sort_by;
  const orderByInput =
    sortField === "start_date"
      ? { start_date: { sort: orderByDir, nulls: "last" as const } }
      : sortField === "due_date"
        ? { due_date: { sort: orderByDir, nulls: "last" as const } }
        : sortField === "created_at"
          ? { created_at: orderByDir }
          : { deleted_at: orderByDir };
  const records = await MyGlobal.prisma.todo_app_todos.findMany({
    where: whereInput,
    skip,
    take: limit,
    orderBy: orderByInput,
    ...TodoAppTodoAtSummaryTransformer.select(),
  });
  const total = await MyGlobal.prisma.todo_app_todos.count({
    where: whereInput,
  });
  return {
    pagination: {
      current: page,
      limit,
      records: total,
      pages: Math.ceil(total / limit),
    } satisfies IPage.IPagination,
    data: await ArrayUtil.asyncMap(
      records,
      TodoAppTodoAtSummaryTransformer.transform,
    ),
  };
}


