import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppGuest } from "../../../../api/structures/ITodoAppGuest";
import { postTodoAppAuthGuestJoin } from "../../../../providers/postTodoAppAuthGuestJoin";
import { postTodoAppAuthGuestRefresh } from "../../../../providers/postTodoAppAuthGuestRefresh";

@Controller("/todoApp/auth/guest")
export class TodoappAuthGuestController {
  /**
   * Create a new guest identity and session.
   *
   * Unregistered visitors are tracked via device_fingerprint. This operation creates a guest record in `todo_app_guests` (if not existing) and establishes a session in `todo_app_guest_sessions`.
   *
   * Returns a JWT token granting access to public pages.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Device fingerprint identifying the guest's browser/device. Used to create or retrieve a temporary guest identity.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Service logic: 1) Extract device_fingerprint from
     *   request. 2) Query todo_app_guests WHERE device_fingerprint matches AND
     *   deleted_at IS NULL. 3) If not found, INSERT new guest record. 4) INSERT
     *   new todo_app_guest_sessions linked by guest_id, recording ip, href,
     *   referrer, created_at, and expired_at. 5) Generate JWT token. 6) Return
     *   ITodoAppGuest.IAuthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppGuest.IJoin,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh the guest access token to extend session validity.
   *
   * Validates the existing session in `todo_app_guest_sessions` and the guest status in `todo_app_guests`. Creates a new session record for audit and returns a renewed token.
   *
   * Ensures authenticated guests maintain access to public pages without re-authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Session context for refreshing the access token, including current session identifier.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Service logic: 1) Extract session identifier
     *   (from token/headers). 2) Validate session in todo_app_guest_sessions is
     *   active and not expired. 3) Validate linked guest in todo_app_guests is
     *   not soft-deleted. 4) INSERT new session record updating ip, href,
     *   referrer, created_at, and expired_at. 5) Generate new JWT token. 6)
     *   Return ITodoAppGuest.IAuthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppGuest.IRefresh,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
