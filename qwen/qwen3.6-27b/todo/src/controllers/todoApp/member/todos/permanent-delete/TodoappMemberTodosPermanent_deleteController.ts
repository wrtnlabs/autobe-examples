import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { postTodoAppMemberTodosTodoIdPermanentDelete } from "../../../../../providers/postTodoAppMemberTodosTodoIdPermanentDelete";

@Controller("/todoApp/member/todos/:todoId/permanent-delete")
export class TodoappMemberTodosPermanent_deleteController {
  /**
   * Permanently deletes the specified soft-deleted todo.
   *
   * This operation irretrievably removes the specified todo which must currently reside in the user's trash. All associated edit history entries are cascaded and deleted along with the todo. This action is final and cannot be undone.
   *
   * @param connection
   * @param todoId UUID of the soft-deleted todo to permanently erase from the user's trash.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Authenticate the requesting member to obtain
     *   their member ID. 2. Query `todo_app_todos` for the todo with matching
     *   `id` ({todoId}) AND `todo_app_member_id` matching the authenticated
     *   member ID. 3. If todo does not exist, return 404 Not Found. 4. If
     *   `deleted_at` is NULL, return 400 Bad Request indicating the todo must
     *   first be soft-deleted (moved to trash). 5. If todo does not belong to
     *   the authenticated member, return 403 Forbidden. 6. Begin database
     *   transaction: a. Query `todo_app_edit_histories` for all edit history
     *   entries linked to this specific todo. b. Delete all identified edit
     *   history entries from `todo_app_edit_histories`. c. Delete the todo
     *   record from `todo_app_todos`. d. Commit transaction. 7. Return 204 No
     *   Content on success.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async permanentErase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await postTodoAppMemberTodosTodoIdPermanentDelete({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
