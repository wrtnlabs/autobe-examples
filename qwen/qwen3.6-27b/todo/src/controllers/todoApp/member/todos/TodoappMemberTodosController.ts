import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppTodo } from "../../../../api/structures/IPageITodoAppTodo";
import { ITodoAppTodo } from "../../../../api/structures/ITodoAppTodo";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteTodoAppMemberTodosTodoId } from "../../../../providers/deleteTodoAppMemberTodosTodoId";
import { getTodoAppMemberTodosTodoId } from "../../../../providers/getTodoAppMemberTodosTodoId";
import { patchTodoAppMemberTodos } from "../../../../providers/patchTodoAppMemberTodos";
import { postTodoAppMemberTodos } from "../../../../providers/postTodoAppMemberTodos";
import { postTodoAppMemberTodosTodoIdRestore } from "../../../../providers/postTodoAppMemberTodosTodoIdRestore";
import { putTodoAppMemberTodosTodoId } from "../../../../providers/putTodoAppMemberTodosTodoId";

@Controller("/todoApp/member/todos")
export class TodoappMemberTodosController {
  /**
   * Create a new todo item for the authenticated user.
   *
   * When a todo is created, the title is the only required field. The description, start date, and due date are all optional and can be omitted. The todo is automatically associated with the authenticated member's account and defaults to an incomplete status. Upon successful creation, the full todo record is returned with system-generated fields including the unique ID, creation timestamp, and the member owner reference.
   *
   * @param connection
   * @param body Todo creation data specifying the task title (required) and optional description, start date, and due date.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Create a new todo record in the todo_app_todos
     *   table. Extract the authenticated member's ID from the session context.
     *   Set the todo_app_member_id field to this ID to establish strict
     *   ownership. Set is_completed to false as the default value for newly
     *   created todos. The created_at and updated_at timestamps should be set
     *   to the current time automatically upon insert. The deleted_at field
     *   should remain null for active todos. Only the title, description,
     *   start_date, and due_date fields are accepted from the request body.
     *   After successful insertion, return the complete todo entity including
     *   system-generated fields such as id, created_at, updated_at,
     *   todo_app_member_id, and is_completed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppTodo.ICreate,
  ): Promise<ITodoAppTodo> {
    try {
      return await postTodoAppMemberTodos({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of the authenticated member's active todos with filtering and sorting options.
   *
   * Returns active (non-soft-deleted) todos filtered by completion status and sorted by date fields as specified. Completion status filter options: all (no filter), only complete (is_completed = true), or only incomplete (is_completed = false).
   *
   * Sorting supports creation date, start date, and due date in ascending or descending order. Todos without a start date or due date appear at the end of the sorted list. Cursor-based pagination is used for efficient navigation through large lists.
   *
   * @param connection
   * @param body Search criteria including completion status filter (all/complete/incomplete), sort field and direction, and pagination cursor.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query todo_app_todos table with the following
     *   logic: 1. Authorization: Filter WHERE todo_app_member_id =
     *   authenticated member's UUID from session 2. Soft delete exclusion:
     *   WHERE deleted_at IS NULL to show only active todos 3. Completion
     *   filter: Apply WHERE is_completed = TRUE or FALSE based on
     *   request.status. Omit if status is 'all'. 4. Sorting: ORDER BY requested
     *   field (created_at, start_date, or due_date) ASC or DESC. Use NULLS LAST
     *   clause for start_date and due_date sorting to push null dates to the
     *   end per section 55. 5. Pagination: Use cursor-based pagination based on
     *   the request cursor and page size. 6. Projection: Return summary fields
     *   (id, title, is_completed, start_date, due_date, created_at). Exclude
     *   description for performance. 7. Return IPageITodoAppTodo.ISummary with
     *   items array and pagination metadata (nextCursor, hasNext).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppTodo.IRequest,
  ): Promise<IPageITodoAppTodo.ISummary> {
    try {
      return await patchTodoAppMemberTodos({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the full details of a single todo by its unique identifier.
   *
   * This endpoint returns all information about a specific todo, including its title, description, scheduled dates, and completion status. Only the todo's owner can access this data—requests for todos belonging to other users will be rejected with an authorization error. The returned todo must be in active (non-deleted) state.
   *
   * @param connection
   * @param todoId The UUID of the todo to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query todo_app_todos table by primary key (id)
     *   using the provided todoId UUID parameter. Verify that the authenticated
     *   member's ID matches the todo's todo_app_member_id field to enforce
     *   strict ownership. Reject with 404 Not Found if the todo does not exist
     *   or has been soft-deleted (deleted_at is not null). Reject with 403
     *   Forbidden if the todo belongs to a different member. Return all fields:
     *   id, title, description (nullable), start_date (nullable), due_date
     *   (nullable), is_completed, created_at, updated_at. Do not include the
     *   todo_app_member_id foreign key in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodo> {
    try {
      return await getTodoAppMemberTodosTodoId({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates an existing todo's title, description, start date, or due date. Only the authenticated member who owns the todo can modify it.
   *
   * An active todo's fields are modified based on the provided request body. The title cannot be empty. Optional fields like the description, start date, and due date can be updated, cleared, or left unchanged. The system automatically records a single edit history entry for this update to maintain a complete change log for the todo.
   *
   * Return the fully updated todo record. Return a 404 error if the todo does not exist, belongs to another user, or has already been soft-deleted.
   *
   * @param connection
   * @param todoId UUID identifier of the todo to update. It must belong to the requesting member and not be soft-deleted.
   * @param body Fields to update on the todo. Title is required and must not be empty. Description, start date, and due date are optional and can be set to null or omitted to clear their existing values.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query `todo_app_todos` using `{todoId}`.
   *
   * Assert that `todo_app_member_id` matches the currently authenticated user's ID and that `deleted_at` IS NULL. Return 404 if the todo is not found, is owned by a different user, or has been soft-deleted.
   *
   * Ensure that the `title` provided in the request body is not empty. Fail validation otherwise.
   *
   * Update `title`, `description`, `start_date`, and `due_date` with the values from the request body.
   * Set `updated_at` to the current timestamp.
   *
   * Insert exactly one record into `todo_app_edit_histories` documenting the update timestamp and the fields that were changed by this single save action.
   *
   * Return the fully updated `ITodoAppTodo` record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppTodo.IUpdate,
  ): Promise<ITodoAppTodo> {
    try {
      return await putTodoAppMemberTodosTodoId({
        member,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft deletes a todo, moving it to the trash.
   *
   * The todo remains in the database and its edit history is preserved. It becomes excluded from standard active lists but can be restored or permanently deleted via trash endpoints.
   *
   * @param connection
   * @param todoId Unique identifier of the todo to be soft-deleted.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query todo_app_todos by id. Verify
     *   todo_app_member_id matches the authenticated member. Set deleted_at to
     *   current timestamp. Return 204 No Content.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppMemberTodosTodoId({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Restores a soft-deleted todo (from trash) back to the member's active todo list.
   *
   * Restoring a todo moves it from trash to the active list by clearing the deleted_at timestamp. The todo returns with all original data intact including title, description, start date, due date, and completion status. Only the owning member can restore their own todos. All associated edit history entries are preserved during restoration. Returns the fully restored todo if successful. Rejects with 403 Forbidden if the todo belongs to another member. Rejects with 404 Not Found if the todo does not exist or has already been permanently deleted.
   *
   * @param connection
   * @param todoId Identifier of the todo to restore from trash (scoped to member)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Find the todo by todoId in todo_app_todos table.
     *   Verify the todo exists and belongs to the authenticated member by
     *   checking todo_app_member_id matches the session member. Check that the
     *   todo is in trash state (deleted_at is set and not null). Set deleted_at
     *   to NULL to restore the todo to active state. Update updated_at to
     *   current timestamp. Return the restored todo.
   *
   * If todoId does not exist, return 404 Not Found error. If the todo belongs to another member, return 403 Forbidden error (unauthorized access prevention per Section 56). If the todo is not in trash (deleted_at is null, meaning it is already active), return 409 Conflict error indicating the todo cannot be restored because it is already active.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":todoId/restore")
  public async restore(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodo> {
    try {
      return await postTodoAppMemberTodosTodoIdRestore({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
