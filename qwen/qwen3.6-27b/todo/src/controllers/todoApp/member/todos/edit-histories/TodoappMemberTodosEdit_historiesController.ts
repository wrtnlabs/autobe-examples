import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppEditHistory } from "../../../../../api/structures/IPageITodoAppEditHistory";
import { ITodoAppEditHistory } from "../../../../../api/structures/ITodoAppEditHistory";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberTodosTodoIdEditHistoriesEditHistoryId } from "../../../../../providers/getTodoAppMemberTodosTodoIdEditHistoriesEditHistoryId";
import { patchTodoAppMemberTodosTodoIdEditHistories } from "../../../../../providers/patchTodoAppMemberTodosTodoIdEditHistories";

@Controller("/todoApp/member/todos/:todoId/edit-histories")
export class TodoappMemberTodosEdit_historiesController {
  /**
   * Retrieve the paginated edit history for a specific todo, sorted from most recent to oldest.
   *
   * Each edit history entry records the timestamp of the edit and the new values for any fields that were changed during that edit operation. Fields that remained unchanged during an edit are excluded from the history entry. Only the todo's owner can access its edit history. History entries remain accessible even for soft-deleted (trashed) todos, and are only removed when a todo is permanently deleted from the trash.
   *
   * @param connection
   * @param todoId UUID of the todo whose edit history is being retrieved.
   * @param body Search criteria for listing edit history entries, including pagination parameters such as offset and page size.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the todo_app_edit_histories table for all
     *   history entries where todo_app_todo_id matches the provided todoId.
   *
   * 1. Validate the todoId exists and belong to the authenticated member:
   *    - Query todo_app_todos for the given todoId
   *    - Verify todo_app_member_id matches the authenticated member's ID
   *    - If todo not found or does not belong to the member, return 404 Not Found
   *
   * 2. Query todo_app_edit_histories:
   *    - WHERE todo_app_todo_id = ?
   *    - ORDER BY created_at DESC (most recent first)
   *    - Apply pagination from request body (offset/limit or cursor-based)
   *
   * 3. Each history entry returns:
   *    - id, created_at
   *    - title (nullable - only populated if title was changed)
   *    - description (nullable - only populated if description was changed)
   *    - start_date (nullable - only populated if start_date was changed)
   *    - due_date (nullable - only populated if due_date was changed)
   *
   * 4. Return paginated results with total count for the todo's edit history entries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppEditHistory.IRequest,
  ): Promise<IPageITodoAppEditHistory.ISummary> {
    try {
      return await patchTodoAppMemberTodosTodoIdEditHistories({
        member,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single edit history entry for a specific todo, showing what fields were changed and when the edit occurred.
   *
   * Returns the complete edit history record including the timestamp of the edit and the new values for any fields that were modified during the edit. Fields that were not changed during the edit are returned as null in the history entry. This allows users to view individual edit history records to track specific changes made to their todo.
   *
   * @param connection
   * @param todoId The unique identifier of the todo that owns this edit history entry. Used to scope the edit history record to its parent todo.
   * @param editHistoryId The unique identifier of the specific edit history entry to retrieve. Each edit history entry represents a single edit operation performed on the todo.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the todo_app_edit_histories table to
     *   retrieve a single record where id equals the editHistoryId path
     *   parameter. Before returning, validate that the edit history entry's
     *   todo_app_todo_id matches the provided todoId path parameter to enforce
     *   data isolation. If the edit history entry does not exist or does not
     *   belong to the specified todo, reject the request with an appropriate
     *   error.
   *
   * Return the full edit history entry object containing all fields: id (the unique identifier), created_at (timestamp when the edit was made), title (new title value if the title was changed, null if unchanged), description (new description value if changed, null if unchanged), start_date (new start date if changed, null if unchanged), and due_date (new due date if changed, null if unchanged). Use the todo_app_edit_histories.todo relation to verify the parent todo exists and belongs to the authenticated user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":editHistoryId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedParam("editHistoryId")
    editHistoryId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppEditHistory> {
    try {
      return await getTodoAppMemberTodosTodoIdEditHistoriesEditHistoryId({
        member,
        todoId,
        editHistoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
