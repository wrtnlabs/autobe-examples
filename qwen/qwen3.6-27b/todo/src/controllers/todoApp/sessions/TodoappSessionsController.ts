import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppMemberSession } from "../../../api/structures/IPageITodoAppMemberSession";
import { ITodoAppMemberSession } from "../../../api/structures/ITodoAppMemberSession";
import { getTodoAppSessionsSessionId } from "../../../providers/getTodoAppSessionsSessionId";
import { patchTodoAppSessions } from "../../../providers/patchTodoAppSessions";

@Controller("/todoApp/sessions")
export class TodoappSessionsController {
  /**
   * List the authenticated member's login sessions with pagination, filtering, and sorting.
   *
   * Returns a paginated list of session records showing login times, IP addresses, and expiration times. Each session is created when the member logs in and expires after a set duration or upon logout.
   *
   * The response includes session summaries optimized for display in account management interfaces, showing when and where each login occurred. Sessions can be filtered by active status and date range to help members identify active sessions across their devices for security management purposes.
   *
   * The list is sorted by creation time with newest sessions first by default. Only sessions belonging to the authenticated member are returned; there is no access to any other member's session data.
   *
   * @param connection
   * @param body Search criteria for filtering sessions by active status, date range, sorting preference, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the todo_app_member_sessions table for all
     *   sessions belonging to the authenticated member (resolved from the
     *   active session's todo_app_member_id).
   *
   * Apply optional filtering from the request body:
   * - activeStatus: filter by isActive computed field (active if expired_at > current time, expired otherwise)
   * - created_at range: filter sessions created within a date range
   *
   * Apply sorting based on sortBy parameter (default: createdAt DESC).
   *
   * Apply cursor-based pagination using cursor (session id) and limit parameters.
   *
   * Construct ISummary responses containing: id, ipAddress, href, referrer, createdAt, expiredAt, and computed isActive field.
   *
   * Do NOT include todo_app_member_id in the response since the result is already scoped to the current member.
   *
   * Verify the authenticated member matches the session owner before returning results to prevent unauthorized access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: ITodoAppMemberSession.IRequest,
  ): Promise<IPageITodoAppMemberSession.ISummary> {
    try {
      return await patchTodoAppSessions({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete details of a single member session by its unique identifier.
   *
   * This operation returns all stored information about a specific session, including the associated member account reference, client IP address, entry page URL, referrer source, session creation timestamp, and expiration timestamp. Sessions are created during login and serve as the authentication context for member access to private features.
   *
   * The session record provides full insight into when and where the session was initiated, making it useful for security auditing, session anomaly detection, and authentication troubleshooting.
   *
   * @param connection
   * @param sessionId Unique identifier of the session to retrieve
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the todo_app_member_sessions table for a
     *   single record matching the provided sessionId UUID.
   *
   * Execute:
   * 1. Validate the sessionId parameter is a valid UUID format
   * 2. SELECT * FROM todo_app_member_sessions WHERE id = ?
   * 3. If no record found, return 404 Not Found
   * 4. If record exists, return the complete session object
   *
   * No joins required as this returns a single session record. The todo_app_member_id is returned as-is (foreign key string value).
   *
   * Error handling:
   * - Invalid UUID format: return 400 Bad Request
   * - Session not found: return 404 Not Found
   * - Database errors: return 500 Internal Server Error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMemberSession> {
    try {
      return await getTodoAppSessionsSessionId({
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
