import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoAppMember } from "../../../api/structures/ITodoAppMember";
import { putTodoAppProfile } from "../../../providers/putTodoAppProfile";

@Controller("/todoApp/profile")
export class TodoappProfileController {
  /**
   * Updates the authenticated user's profile information including display name.
   *
   * Only the account owner can modify their own profile; all fields are validated and persisted. The updated display name is immediately available across the application. Profile access is strictly limited to the authenticated user's own account.
   *
   * Display name changes are validated to be non-empty strings. The system automatically updates the modified timestamp when profile changes are saved.
   *
   * @param connection
   * @param body Profile update fields containing the new display name to save.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Retrieve the authenticated member's ID from the
     *   current session context. Query todo_app_members table for the member
     *   record matching the session owner. Validate the incoming display_name
     *   field: must be a non-empty string. Update the display_name column in
     *   the member record. Set updated_at to the current timestamp. Return the
     *   complete updated member record including id, email, display_name,
     *   created_at, updated_at, and deleted_at fields. If the member record is
     *   soft-deleted (deleted_at is not null), reject the update and return a
     *   403 Forbidden error since deleted accounts cannot be modified.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @TypedBody()
    body: ITodoAppMember.IUpdate,
  ): Promise<ITodoAppMember> {
    try {
      return await putTodoAppProfile({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
