import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

/**
 * Permanently deletes the specified soft-deleted todo.
 *
 * This operation irretrievably removes the specified todo which must currently reside in the user's trash. All associated edit history entries are cascaded and deleted along with the todo. This action is final and cannot be undone.
 *
 * @param props.connection
 * @param props.todoId UUID of the soft-deleted todo to permanently erase from the user's trash.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification 1. Authenticate the requesting member to obtain their
 *   member ID. 2. Query `todo_app_todos` for the todo with matching `id`
 *   ({todoId}) AND `todo_app_member_id` matching the authenticated member ID.
 *   3. If todo does not exist, return 404 Not Found. 4. If `deleted_at` is
 *   NULL, return 400 Bad Request indicating the todo must first be soft-deleted
 *   (moved to trash). 5. If todo does not belong to the authenticated member,
 *   return 403 Forbidden. 6. Begin database transaction: a. Query
 *   `todo_app_edit_histories` for all edit history entries linked to this
 *   specific todo. b. Delete all identified edit history entries from
 *   `todo_app_edit_histories`. c. Delete the todo record from `todo_app_todos`.
 *   d. Commit transaction. 7. Return 204 No Content on success.
 * @path /todoApp/member/todos/:todoId/permanent-delete
 * @accessor api.functional.todoApp.member.todos.permanent_delete.permanentErase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function permanentErase(
  connection: IConnection,
  props: permanentErase.Props,
): Promise<void> {
  return true === connection.simulate
    ? permanentErase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...permanentErase.METADATA,
          path: permanentErase.path(props),
          status: null,
        },
      );
}
export namespace permanentErase {
  export type Props = {
    /**
     * UUID of the soft-deleted todo to permanently erase from the user's trash.
     */
    todoId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "POST",
    path: "/todoApp/member/todos/:todoId/permanent-delete",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/member/todos/${encodeURIComponent(props.todoId ?? "null")}/permanent-delete`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: permanentErase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: permanentErase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
