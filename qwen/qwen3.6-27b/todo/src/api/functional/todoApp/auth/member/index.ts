/**
 * Register a new member account with email address and password. The email must be unique and both fields are required.
 *
 * Upon successful registration, a new member account is created with the provided email and hashed password. The display name is optional and can be set during the registration process.
 *
 * If the email address is already associated with an existing account, the registration is rejected with a conflict error. The system validates that all required fields are provided before proceeding.
 *
 * After successful registration, the user can authenticate using the email and password provided during sign up. No session is established automatically; the user must log in separately.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration credentials including email and password for the new account. Display name is optional.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification POST: Create new member account. 1. Validate request:
 *   email and password must be non-empty 2. Check email uniqueness: SELECT by
 *   email - reject 409 if exists 3. Hash password using bcrypt/argon2 4. INSERT
 *   into todo_app_members with: email, password_hash, now() timestamps 5.
 *   display_name is optional - omit or leave null if not provided 6. Return
 *   IAuthorized response
 *
 * Edge cases:
 * - Duplicate email → 409 Conflict
 * - Missing email/password → 400 Bad Request
 *
 * Do NOT create guest records - join is standalone member registration.
 * @path /todoApp/auth/member/join
 * @accessor api.functional.todoApp.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
