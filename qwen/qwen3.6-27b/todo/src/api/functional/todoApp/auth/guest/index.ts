import { ITodoAppGuest } from "../../../../structures/ITodoAppGuest";

/**
 * Create a new guest identity and session.
 *
 * Unregistered visitors are tracked via device_fingerprint. This operation creates a guest record in `todo_app_guests` (if not existing) and establishes a session in `todo_app_guest_sessions`.
 *
 * Returns a JWT token granting access to public pages.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Device fingerprint identifying the guest's browser/device. Used to create or retrieve a temporary guest identity.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Service logic: 1) Extract device_fingerprint from
 *   request. 2) Query todo_app_guests WHERE device_fingerprint matches AND
 *   deleted_at IS NULL. 3) If not found, INSERT new guest record. 4) INSERT new
 *   todo_app_guest_sessions linked by guest_id, recording ip, href, referrer,
 *   created_at, and expired_at. 5) Generate JWT token. 6) Return
 *   ITodoAppGuest.IAuthorized.
 * @path /todoApp/auth/guest/join
 * @accessor api.functional.todoApp.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /**
     * Device fingerprint identifying the guest's browser/device. Used to create or retrieve a temporary guest identity.
     */
    body: ITodoAppGuest.IJoin;
  };
  export type Body = ITodoAppGuest.IJoin;
  export type Response = ITodoAppGuest.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/auth/guest/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/auth/guest/join";
  export const random = (): ITodoAppGuest.IAuthorized =>
    typia.random<ITodoAppGuest.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

