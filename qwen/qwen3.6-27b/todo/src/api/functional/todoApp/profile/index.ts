import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia from "typia";

import { ITodoAppMember } from "../../../structures/ITodoAppMember";

/**
 * Updates the authenticated user's profile information including display name.
 *
 * Only the account owner can modify their own profile; all fields are validated and persisted. The updated display name is immediately available across the application. Profile access is strictly limited to the authenticated user's own account.
 *
 * Display name changes are validated to be non-empty strings. The system automatically updates the modified timestamp when profile changes are saved.
 *
 * @param props.connection
 * @param props.body Profile update fields containing the new display name to save.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Retrieve the authenticated member's ID from the
 *   current session context. Query todo_app_members table for the member record
 *   matching the session owner. Validate the incoming display_name field: must
 *   be a non-empty string. Update the display_name column in the member record.
 *   Set updated_at to the current timestamp. Return the complete updated member
 *   record including id, email, display_name, created_at, updated_at, and
 *   deleted_at fields. If the member record is soft-deleted (deleted_at is not
 *   null), reject the update and return a 403 Forbidden error since deleted
 *   accounts cannot be modified.
 * @path /todoApp/profile
 * @accessor api.functional.todoApp.profile.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Profile update fields containing the new display name to save.
     */
    body: ITodoAppMember.IUpdate;
  };
  export type Body = ITodoAppMember.IUpdate;
  export type Response = ITodoAppMember;

  export const METADATA = {
    method: "PUT",
    path: "/todoApp/profile",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/profile";
  export const random = (): ITodoAppMember => typia.random<ITodoAppMember>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
