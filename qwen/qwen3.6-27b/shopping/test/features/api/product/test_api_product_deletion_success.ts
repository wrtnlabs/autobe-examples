/**
 * Test the primary success path for seller product deletion.
 *
 * An admin creates a category first, then a seller registers and creates a product in that category. The seller then deletes their own product. The system should verify that the authenticated seller is the product owner, check that no variants have active order items (paid/shipped status), no pending cancellation requests, or pending refund requests. When all conditions pass, the product and its variants are soft-deleted by setting deleted_at timestamps, and the operation returns 200 OK with null body. The product is removed from public search results and category listings while preserving internal records for order history integrity.
 *
 * 1. Admin authenticates to the platform.
 * 2. Admin creates a category for product assignment.
 * 3. Seller registers and authenticates with email and credentials.
 * 4. Seller creates a product referencing the category.
 * 5. Seller deletes their own product.
 */
export async function test_api_product_deletion_success(
  connection: api.IConnection,
) {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(8),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommercePlatformAdmin.ILogin,
  });
  // 2. Admin creates category
  const category =
    await generate_random_ecommerce_platform_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 3. Register and authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommercePlatformSeller.IJoin,
  });
  // 4. Seller creates product in the category
  const product =
    await generate_random_ecommerce_platform_seller_products_create(
      sellerConnection,
      {
        body: {
          category_id: category.id,
        },
      },
    );
  typia.assert(product);
  // 5. Seller deletes the product
  await api.functional.ecommercePlatform.seller.products.erase(
    sellerConnection,
    {
      productId: product.id,
    },
  );
}
