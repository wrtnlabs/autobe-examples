import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformGuestSession } from "../../../../api/structures/IEcommercePlatformGuestSession";
import { IPageIEcommercePlatformGuestSession } from "../../../../api/structures/IPageIEcommercePlatformGuestSession";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { getEcommercePlatformGuestSessionsSessionId } from "../../../../providers/getEcommercePlatformGuestSessionsSessionId";
import { patchEcommercePlatformGuestSessions } from "../../../../providers/patchEcommercePlatformGuestSessions";

@Controller("/ecommercePlatform/guest/sessions")
export class EcommerceplatformGuestSessionsController {
  /**
   * List and search user sessions with filtering capabilities.
   *
   * Authenticated customers, sellers, and administrators can retrieve a paginated list of their own account sessions. Sessions represent active and historical authentication events with complete device and timing information.
   *
   * Filters include session status (active, expired, logged out), creation date range, device type, and sorting options. Results are optimized for security dashboards and session management interfaces.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for session listing.
   *
   *             Include filters for session status, creation date range, device information, and sorting preferences. Supports cursor-based pagination for large result sets.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Query the appropriate session table based on the
     *   authenticated user type (ecommerce_platform_customer_sessions for
     *   customers, ecommerce_platform_seller_sessions for sellers,
     *   ecommerce_platform_admin_sessions for admins).
   *
   * Apply filtering logic:
   * - Filter by session status: active (not deleted before now), expired (expired_at before now and not deleted), logged out (deleted)
   * - Apply date range filters on created_at
   * - Optionally filter by device type or IP
   * - Apply pagination with cursor-based or offset-based approach
   *
   * Join with user profile data if needed for display purposes.
   * Return paginated results sorted by created_at descending by default.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IEcommercePlatformGuestSession.IRequest,
  ): Promise<IPageIEcommercePlatformGuestSession.ISummary> {
    try {
      return await patchEcommercePlatformGuestSessions({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete details of a specific platform session by its unique identifier.
   *
   * Returns all session metadata including the owning actor reference, device fingerprint (IP address, URL context), authentication lifecycle timestamps, and optional soft-delete status for customer sessions. This endpoint supports administrative auditing, security monitoring, and technical diagnostics by providing full visibility into active and historical session records.
   *
   * The operation queries all session types (admin, customer, seller, guest) and returns the matching record if found.
   *
   * @param connection
   * @param sessionId Unique identifier of the session record to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Query all four session tables in sequence to
     *   locate the session matching the provided sessionId UUID:
   *
   * 1. ecommerce_platform_admin_sessions - match on id column
   * 2. ecommerce_platform_customer_sessions - match on id column
   * 3. ecommerce_platform_seller_sessions - match on id column
   * 4. ecommerce_platform_guest_sessions - match on id column
   *
   * Return the first match found formatted as IEcommercePlatformSession with appropriate actorType discriminator value.
   *
   * Fields mapping per session type:
   * - All types: id, actorId (FK value), ip, href, referrer, createdAt, expiredAt
   * - Customer sessions only: userAgent, deletedAt (nullable), refreshTokenHash
   *
   * Return 404 Not Found if no session record exists matching the sessionId in any table.
   *
   * This operation requires authenticated admin access for session auditing. No modifications are performed - read-only query.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformGuestSession> {
    try {
      return await getEcommercePlatformGuestSessionsSessionId({
        guest,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
