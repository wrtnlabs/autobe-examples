import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformReview } from "../../../../api/structures/IEcommercePlatformReview";
import { IPageIEcommercePlatformReview } from "../../../../api/structures/IPageIEcommercePlatformReview";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { getEcommercePlatformGuestReviewsReviewId } from "../../../../providers/getEcommercePlatformGuestReviewsReviewId";
import { patchEcommercePlatformGuestReviews } from "../../../../providers/patchEcommercePlatformGuestReviews";

@Controller("/ecommercePlatform/guest/reviews")
export class EcommerceplatformGuestReviewsController {
  /**
   * Search product reviews with criteria filtering and pagination.
   *
   * Returns paginated collection of reviews matching specified search filters. Reviews display customer feedback on products, including star ratings (1-5 scale) and optional text content. Reviews are sorted newest-first by default, consistent with product detail page display requirements.
   *
   * Soft-deleted reviews are excluded from results by default, following business rules for average rating calculations and product evaluation visibility. Non-deleted reviews remain visible even after customer account deletion, attributed as 'deleted user'.
   *
   * The response includes total count of non-deleted matching reviews.
   *
   * @param connection
   * @param body Search criteria including product identifier filter, customer identifier filter, order identifier filter, rating range constraints, text content search, date range filters on created_at or updated_at timestamps, pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Query ecommerce_platform_reviews table. Apply
     *   filtering on product_id, customer_id, order_id, rating range (1-5),
     *   text_content matches, created_at or updated_at date range filters.
   *
   * WHERE deleted_at IS NULL (exclude soft-deleted by default).
   *
   * Default ORDER BY created_at DESC for newest-first sorting.
   *
   * Paginated results using offset-based or cursor-based pagination.
   *
   * JOIN with ecommerce_platform_customers to fetch display_name. When customer deleted_at IS NOT NULL, use 'deleted user'.
   *
   * JOIN with ecommerce_platform_products for product context when needed.
   *
   * Return paginated summary records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IEcommercePlatformReview.IRequest,
  ): Promise<IPageIEcommercePlatformReview.ISummary> {
    try {
      return await patchEcommercePlatformGuestReviews({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single review by its unique identifier.
   *
   * Returns the complete review record including the star rating (1-5), optional text content, associated product information, and reviewer identity. Reviews submitted by users who have since deleted their accounts remain accessible and display 'deleted user' as the reviewer identity. This preserves the review's value for other customers making purchasing decisions while respecting the account deletion.
   *
   * The review includes the timestamp of original submission and last update if the review has been edited by its author.
   *
   * @param connection
   * @param reviewId Unique identifier of the review to retrieve (global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Query the ecommerce_platform_reviews table for
     *   the review with the matching id.
   *
   * Join with ecommerce_platform_products to include product name and basic details in the response.
   * Join with ecommerce_platform_customer_profiles to get the reviewer's display name. If the customer profile's deleted_at is not null, return 'deleted user' as the reviewer identity instead of the display name.
   *
   * Return a 404 error if no review exists with the given ID or if the review has been soft-deleted (deleted_at is not null). Deleted reviews should not be retrievable via this endpoint.
   *
   * Validate that the reviewId is a valid UUID format before querying.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reviewId")
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformReview> {
    try {
      return await getEcommercePlatformGuestReviewsReviewId({
        guest,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
