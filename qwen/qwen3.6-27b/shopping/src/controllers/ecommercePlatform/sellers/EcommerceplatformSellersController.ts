import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformSeller } from "../../../api/structures/IEcommercePlatformSeller";
import { IPageIEcommercePlatformSeller } from "../../../api/structures/IPageIEcommercePlatformSeller";
import { getEcommercePlatformSellersSellerId } from "../../../providers/getEcommercePlatformSellersSellerId";
import { patchEcommercePlatformSellers } from "../../../providers/patchEcommercePlatformSellers";

@Controller("/ecommercePlatform/sellers")
export class EcommerceplatformSellersController {
  /**
   * Search and list seller accounts with filtering and pagination.
   *
   * Administrators can filter sellers by approval status (pending, approved, rejected), ban status, and email. The operation returns a paginated list of seller summaries including their account status, creation date, and associated shop information.
   *
   * This operation is useful for administrative oversight of the seller ecosystem, tracking new seller applications, managing seller approvals, and monitoring seller account health.
   *
   * @param connection
   * @param body Search criteria for filtering seller accounts including email search, approval status filter, ban status filter, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query ecommerce_platform_sellers with LEFT JOIN
     *   to ecommerce_platform_seller_profiles.
   *
   * Apply filters:
   * - approvalStatus: filter by approval_status column
   * - isBanned: filter by is_banned flag
   * - email: partial match using ILIKE '%{email}%'
   *
   * Default sort by created_at DESC.
   *
   * Implement cursor-based pagination using created_at as cursor field.
   *
   * Exclude password_hash from response.
   *
   * Handle soft-deleted sellers (deleted_at is not null) by including them in results but marking status appropriately.
   *
   * Error handling:
   * - 400 for invalid filter parameters
   * - 200 with empty results for no matches
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommercePlatformSeller.IRequest,
  ): Promise<IPageIEcommercePlatformSeller.ISummary> {
    try {
      return await patchEcommercePlatformSellers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single seller account by their unique UUID identifier.
   *
   * Returns comprehensive seller entity information including authentication credentials, approval status, and administrative metadata. This endpoint is essential for viewing seller account details, verifying approval states, and accessing seller profile information for marketplace management and oversight.
   *
   * Related seller profile information (shop_name, shop_description, logo_image_uri) is included when available. Soft-deleted seller accounts remain accessible for audit and compliance purposes.
   *
   * @param connection
   * @param sellerId UUID identifier of the seller account to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the ecommerce_platform_sellers table using
     *   WHERE id = sellerId.
   *
   * Include seller profile information by left joining with ecommerce_platform_seller_profiles on seller_id = sellers.id to fetch shop_name, shop_description, and logo_image_uri when available.
   *
   * Exclude password_hash field from the response for security. The password hash must never be exposed through any API operation.
   *
   * Return 404 Not Found if no seller account exists with the provided sellerId identifier.
   *
   * Handle soft-deleted sellers (where deleted_at is populated). Even soft-deleted accounts should be returned for administrative visibility and audit trail purposes. The response should indicate the account deletion state.
   *
   * Ensure proper authorization checks: only authenticated actors with appropriate permissions can access seller account information. Guests cannot access this endpoint due to sensitive account data exposure risks.
   *
   * Return the complete seller entity including all non-sensitive fields: id, email, approval_status, rejection_reason, is_banned, created_at, updated_at, deleted_at.
   *
   * When seller profile exists, include shop_name, shop_description, logo_image_uri, profile created_at, profile updated_at, profile deleted_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformSeller> {
    try {
      return await getEcommercePlatformSellersSellerId({
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
