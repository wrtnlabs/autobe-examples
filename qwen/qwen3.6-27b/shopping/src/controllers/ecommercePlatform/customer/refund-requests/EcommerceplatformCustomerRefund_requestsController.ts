import { postEcommercePlatformCustomerRefundRequests } from "../../../../providers/postEcommercePlatformCustomerRefundRequests";

@Controller("/ecommercePlatform/customer/refund-requests")
export class EcommerceplatformCustomerRefund_requestsController {
  /**
   * Create a new refund request for a delivered order item.
   *
   * Customers can submit refund requests for order items that have reached delivered status and were delivered within the seven-day refund window. The operation requires the order item identifier to refund and a textual reason explaining the refund request.
   *
   * Upon submission, the refund request is created with a pending status and made available for the seller to review. The seller is automatically identified from the product chain and can subsequently approve or reject the request. The original order item and other items in the same order remain unaffected during the pending period.
   *
   * @param connection
   * @param body Refund request creation payload containing the order item identifier and customer-provided reason for the refund.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Implementation steps:
   *
   * 1. Parse and validate the request body containing orderItemId and refundReason.
   *
   * 2. Verify the authenticated customer has ownership of the specified order item by checking the order_item's parent order's customer_profile_id matches the current customer.
   *
   * 3. Validate the order item status is 'delivered'. Reject with validation error if status is anything else (paid, shipped, cancelled, refunded).
   *
   * 4. Validate the 7-day refund window: check if the order item's updated_at (or the timestamp when status became 'delivered') is within 7 days of the current time. Reject with error if outside the window.
   * n5. Check for existing refund request on this order item via the unique constraint on order_item_id. Reject with conflict error if one already exists (pending, approved, or rejected).
   *
   * 6. Auto-populate seller_profile_id by traversing: order_item → product_variant → product → seller_profile.
   *
   * 7. Create the refund request record with:
   *    - order_item_id: from request
   *    - seller_profile_id: derived from product chain
   *    - refund_reason: from request
   *    - status: 'pending'
   *    - responded_at: null
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   *
   * 8. Create a snapshot record in ecommerce_platform_snapshot_refund_requests to capture the initial state.
   *
   * 9. Return the complete refund request entity in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommercePlatformRefundRequest.ICreate,
  ): Promise<IEcommercePlatformRefundRequest> {
    try {
      return await postEcommercePlatformCustomerRefundRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Paginated collection of refund request summary records including status, reason, seller profile reference, and timestamps.
   *
   * @param connection
   * @param body Search criteria including status, seller profile ID, date ranges for created_at and responded_at fields, and text search on refund_reason field along with pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query ecommerce_platform_refund_requests table
     *   with pagination and filtering capabilities. Join with
     *   ecommerce_platform_seller_profiles when seller_profile_id filter is
     *   applied, and optionally join with ecommerce_platform_order_items for
     *   order item context. Apply the following filters: status (pending |
     *   approved | rejected), seller_profile_id (UUID), created_at date range,
     *   responded_at date range, and refund_reason text search. Enforce access
     *   control based on actor type: sellers can only see refund requests where
     *   seller_profile_id matches their profile; administrators can view all
     *   refund requests. Apply cursor-based pagination using IPage pattern.
     *   Sort by created_at descending by default. Return summary records
     *   containing id, order_item_id, seller_profile_id, refund_reason, status,
     *   responded_at, and created_at fields for efficient list display.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommercePlatformRefundRequest.IRequest,
  ): Promise<IPageIEcommercePlatformRefundRequest.ISummary> {
    try {
      return await patchEcommercePlatformCustomerRefundRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information about a specific refund request identified by its unique universal identifier.
   *
   * Returns the complete refund request entity including the customer-provided refund reason, current approval status, seller response timestamp, and creation timestamps.
   *
   * Use this endpoint to view the current state and details of any refund request in the system.
   *
   * @param connection
   * @param refundRequestId Universal unique identifier of the refund request to retrieve
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the ecommerce_platform_refund_requests
     *   table to find a single record where the id matches the provided
     *   refundRequestId path parameter.
   *
   * Return the complete refund request object including:
   * - id: Primary identifier
   * - order_item_id: Reference to the order item
   * - seller_profile_id: Reference to the seller processing this refund
   * - refund_reason: Text explanation provided by customer
   * - status: Current state (pending, approved, or rejected)
   * - responded_at: When seller responded (null if pending)
   * - created_at: When the request was submitted
   * - updated_at: Last modification timestamp
   *
   * If no refund request exists with the given ID, return a 404 Not Found error.
   *
   * Ensure UUID validation for the refundRequestId path parameter.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":refundRequestId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformRefundRequest> {
    try {
      return await getEcommercePlatformCustomerRefundRequestsRefundRequestId({
        customer,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
