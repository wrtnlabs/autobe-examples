import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformRefundRequest } from "../../../../api/structures/IEcommercePlatformRefundRequest";
import { IPageIEcommercePlatformRefundRequest } from "../../../../api/structures/IPageIEcommercePlatformRefundRequest";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommercePlatformCustomerRefundRequestsRefundRequestId } from "../../../../providers/getEcommercePlatformCustomerRefundRequestsRefundRequestId";
