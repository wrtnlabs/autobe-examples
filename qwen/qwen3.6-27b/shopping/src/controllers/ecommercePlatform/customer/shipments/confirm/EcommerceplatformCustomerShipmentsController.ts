import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformShipment } from "../../../../../api/structures/IEcommercePlatformShipment";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { postEcommercePlatformCustomerShipmentsShipmentIdConfirm } from "../../../../../providers/postEcommercePlatformCustomerShipmentsShipmentIdConfirm";

@Controller("/ecommercePlatform/customer/shipments/:shipmentId/confirm")
export class EcommerceplatformCustomerShipmentsController {
  /**
   * Manually confirm delivery receipt of a shipment package.
   *
   * This endpoint allows customers to manually confirm they have received their package. When called, it updates the shipment's confirmed_at timestamp and transitions all included order items to 'delivered' status. Delivery confirmation operates at the shipment level, affecting all order items within that shipment simultaneously.
   *
   * Manual confirmation stops the 14-day auto-delivery countdown and enables customers to submit refund requests within seven days of delivery confirmation. The system validates that the authenticated customer owns all order items in the shipment before processing the confirmation.
   *
   * @param connection
   * @param shipmentId UUID identifier of the shipment to confirm delivery for
   * @param body Optional confirmation metadata for the delivery confirmation event
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Validate that the authenticated customer owns all
     *   order items in the shipment. Query ecommerce_platform_shipment_items
     *   where shipment_id equals the provided shipmentId, then join with
     *   ecommerce_platform_order_items and ecommerce_platform_orders to verify
     *   the customer_profile_id matches the authenticated customer.
   *
   * If confirmed_at is already set, return 409 Conflict. Update ecommerce_platform_shipments.confirmed_at to current timestamp. Set delivered_at if not already set. Transition all referenced order items' status to 'delivered' through the junction table relationships. Return the updated shipment entity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async confirm(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommercePlatformShipment.IConfirm,
  ): Promise<IEcommercePlatformShipment> {
    try {
      return await postEcommercePlatformCustomerShipmentsShipmentIdConfirm({
        customer,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
