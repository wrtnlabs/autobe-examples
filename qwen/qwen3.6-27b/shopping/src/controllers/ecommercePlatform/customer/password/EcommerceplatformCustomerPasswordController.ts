import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommercePlatformCustomerPasswordReset } from "../../../../api/structures/IEcommercePlatformCustomerPasswordReset";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { postEcommercePlatformCustomerPassword } from "../../../../providers/postEcommercePlatformCustomerPassword";

@Controller("/ecommercePlatform/customer/password")
export class EcommerceplatformCustomerPasswordController {
  /**
   * Change the password for the currently authenticated user.
   *
   * This endpoint allows customers, sellers, and administrators to update their account password by providing their current password for verification and a new password to set. The operation validates that the current password is correct and that the new password differs from it before updating the stored password hash.
   *
   * The password change immediately invalidates all existing sessions for the user, requiring re-authentication with the new credentials.
   *
   * @param connection
   * @param body Password change request containing the current password for verification and the new password to set. Both fields are required.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Extract the authenticated user from the
     *   session context (determine if customer, seller, or admin). 2. Validate
     *   request body contains both currentPassword and newPassword fields. 3.
     *   Validate currentPassword matches the stored password_hash using bcrypt
     *   comparison: - Query ecommerce_platform_customers.password_hash for
     *   customer sessions - Query ecommerce_platform_sellers.password_hash for
     *   seller sessions - Query ecommerce_platform_admins.password_hash for
     *   admin sessions 4. Validate newPassword is different from
     *   currentPassword. 5. Generate a new password hash using bcrypt. 6.
     *   Update the password_hash field in the appropriate user table. 7.
     *   Invalidate all existing active sessions for this user to force
     *   re-login. 8. Return 204 No Content response.
   *
   * Error handling:
   * - Return 400 Bad Request if currentPassword or newPassword is missing or empty
   * - Return 400 Bad Request if newPassword equals currentPassword
   * - Return 401 Unauthorized if currentPassword doesn't match stored hash
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async change(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommercePlatformCustomerPasswordReset.IChange,
  ): Promise<void> {
    try {
      return await postEcommercePlatformCustomerPassword({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
