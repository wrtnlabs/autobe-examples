import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformOrder } from "../../../../api/structures/IEcommercePlatformOrder";
import { IPageIEcommercePlatformOrder } from "../../../../api/structures/IPageIEcommercePlatformOrder";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommercePlatformCustomerOrdersOrderId } from "../../../../providers/getEcommercePlatformCustomerOrdersOrderId";
import { patchEcommercePlatformCustomerOrders } from "../../../../providers/patchEcommercePlatformCustomerOrders";
import { postEcommercePlatformCustomerOrders } from "../../../../providers/postEcommercePlatformCustomerOrders";

@Controller("/ecommercePlatform/customer/orders")
export class EcommerceplatformCustomerOrdersController {
  /**
   * Creates a new order from customer checkout.
   *
   * This endpoint processes a customer's completed shopping cart into a permanent order record after payment confirmation. Each order contains multiple order items representing purchased product variants with their quantities and unit prices at the time of purchase. The shipping address selected during checkout is immutably preserved as the delivery destination.
   *
   * Orders support multi-seller purchases, where items within the same order may originate from different sellers. Each order item maintains independent status tracking throughout the fulfillment lifecycle.
   *
   * The system generates a unique order number for identification and tracking purposes. The initial order status is derived from the collective states of all contained order items.
   *
   * @param connection
   * @param body Order creation request containing customer checkout details, including order items with product variant references, quantities, unit prices, and the shipping address for delivery.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Validate the incoming order creation request
     *   2. Verify all order items reference valid, existing product variants 3.
     *   Confirm sufficient inventory for all requested quantities 4. Create the
     *   order record with system-generated UUID and unique order number 5.
     *   Create each order item with the specified product variant, quantity,
     *   and unit price 6. Link the order to the customer's profile and selected
     *   shipping address 7. Set initial order status (typically 'paid' after
     *   successful payment) 8. Return the complete created order with all items
     *   and preserved shipping address
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommercePlatformOrder.ICreate,
  ): Promise<IEcommercePlatformOrder> {
    try {
      return await postEcommercePlatformCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and list orders with pagination, filtering, and sorting. Returns paginated order summaries sorted by creation date in descending order (newest first) as default.
   *
   * This endpoint supports filtering orders by status (paid, shipped, delivered, cancelled, refunded, partially_completed), order number search, and date range queries. Each order summary includes the order number, creation date, total price aggregated from line items, and overall status derived from constituent item statuses.
   *
   * Authorization varies by actor: customers can only search their own orders, sellers can search orders containing their products, and administrators have platform-wide visibility across all orders.
   *
   * @param connection
   * @param body Search criteria including optional filters for order status (paid, shipped, delivered, cancelled, refunded, partially_completed), order number partial search, creation date range, and pagination parameters for cursor-based browsing.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query ecommerce_platform_orders table with
     *   pagination and filtering support. Apply filters on status, order_number
     *   (partial match), and created_at date ranges. Default sort by created_at
     *   DESC per requirement 342.
   *
   * Join with ecommerce_platform_order_items to calculate total price by summing (quantity * price) for each order. Join with ecommerce_platform_shipping_addresses to include shipping information in summaries.
   *
   * Enforce authorization isolation: filter results by customer_profile_id for authenticated customers, by product variants belonging to seller's products for sellers, return all orders for admins.
   *
   * Apply cursor-based pagination using created_at DESC as the primary sort and UUID as the tiebreaker for consistent page boundaries. Support cursor parameter in request for subsequent pages.
   *
   * Handle edge cases: empty result sets return empty array with nextCursor null, large date ranges still paginate correctly, and derived status calculations reflect current state of child items.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommercePlatformOrder.IRequest,
  ): Promise<IPageIEcommercePlatformOrder.ISummary> {
    try {
      return await patchEcommercePlatformCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete details for a single order by its unique identifier.
   *
   * Returns the full order record including all order line items with product variant details, quantities, and prices, the shipping address where the order was delivered, and associated shipment packages with carrier tracking information.
   *
   * This endpoint serves customers who need to browse their purchase transaction history, view fulfillment status, and track deliveries. Orders are preserved indefinitely for legal compliance and financial audit trails, even if the customer later deletes their account.
   *
   * @param connection
   * @param orderId Unique UUID identifier of the order to retrieve. This is not the order_number field but the internal primary key of the order record.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the ecommerce_platform_orders table using
     *   the provided order UUID as the primary key.
   *
   * Join with ecommerce_platform_order_items to retrieve all line items in the order, including their quantity, price at purchase, and current status.
   *
   * Join with ecommerce_platform_shipping_addresses to retrieve the immutable delivery destination captured at checkout.
   *
   * Join with ecommerce_platform_shipments through ecommerce_platform_shipment_items to retrieve all shipment packages associated with this order's items, including carrier name, tracking number, and delivery confirmation timestamps.
   *
   * Return the complete order object with all related data nested. Validate that the order exists and return 404 Not Found if not found.
   *
   * For customer access, verify the order's ecommerce_platform_customer_profile_id matches the authenticated customer's profile.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformOrder> {
    try {
      return await getEcommercePlatformCustomerOrdersOrderId({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
