import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformSnapshotOrderItem } from "../../../../../../api/structures/IEcommercePlatformSnapshotOrderItem";
import { IPageIEcommercePlatformSnapshotOrderItem } from "../../../../../../api/structures/IPageIEcommercePlatformSnapshotOrderItem";
import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { getEcommercePlatformCustomerOrdersOrderIdItemsItemIdSnapshotsSnapshotId } from "../../../../../../providers/getEcommercePlatformCustomerOrdersOrderIdItemsItemIdSnapshotsSnapshotId";
import { patchEcommercePlatformCustomerOrdersOrderIdItemsItemIdSnapshots } from "../../../../../../providers/patchEcommercePlatformCustomerOrdersOrderIdItemsItemIdSnapshots";

@Controller(
  "/ecommercePlatform/customer/orders/:orderId/items/:itemId/snapshots",
)
export class EcommerceplatformCustomerOrdersItemsSnapshotsController {
  /**
   * Search snapshots for a specific order item within a specific order.
   *
   * This endpoint retrieves immutable snapshot records that preserve the transactional state of an order item at the time of purchase, including quantity and unit price. Snapshots are automatically generated by the system at order creation and cannot be modified or deleted by any user.
   *
   * Customers can access snapshots of their own order items for order history verification and dispute resolution purposes. Snapshots preserve purchase-time details even if the product price or variant details change later.
   *
   * Returns paginated results optimized for list displays and audit trail searches. This is a read-only operation - snapshots are system-generated and cannot be created, modified, or deleted through this API.
   *
   * @param connection
   * @param orderId UUID identifier for the parent order containing the order item
   * @param itemId UUID identifier for the specific order item to retrieve snapshots for
   * @param body Search criteria and pagination parameters for querying order item snapshot records, including date ranges and cursor-based pagination.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query ecommerce_platform_snapshot_order_items
     *   joined with ecommerce_platform_snapshots to retrieve snapshots for the
     *   specified order item.
   *
   * 1. Validate orderId matches an existing order in ecommerce_platform_orders
   * 2. Retrieve the target order item from ecommerce_platform_order_items where id equals itemId
   * 3. Verify the order item belongs to the specified order (ecommerce_platform_order_id equals orderId)
   * 4. Query ecommerce_platform_snapshot_order_items where ecommerce_platform_order_items_id equals itemId
   * 5. Join with ecommerce_platform_snapshots on ecommerce_platform_snapshots_id to get header fields
   * 6. Verify entity_type equals 'order_item' in the snapshots table
   * 7. Apply any search filters and pagination from the request body
   * 8. Return cursor-based pagination results
   *
   * Validation:
   * - Return 404 if orderId does not match any order
   * - Return 404 if itemId does not match any order item
   * - Return 404 if the order item does not belong to the specified orderId
   * - Verify authenticated customer owns the order (ecommerce_platform_customer_profile_id matches)
   * - Snapshots are immutable - no write operations allowed
   * - System-generated data - only read access via index and at operations
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommercePlatformSnapshotOrderItem.IRequest,
  ): Promise<IPageIEcommercePlatformSnapshotOrderItem.ISummary> {
    try {
      return await patchEcommercePlatformCustomerOrdersOrderIdItemsItemIdSnapshots(
        {
          customer,
          orderId,
          itemId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific snapshot record for an order item, showing the quantity and unit price preserved at the moment of purchase.
   *
   * This endpoint supports dispute resolution and historical auditing by providing customers, sellers, and administrators access to the exact transactional details that existed when the purchase was made. The snapshot data is immutable and independent of any subsequent price changes, inventory adjustments, or product modifications.
   *
   * The snapshot preserves the quantity ordered and the unit price paid, as part of the permanent transaction record that is retained indefinitely according to platform data retention policy.
   *
   * @param connection
   * @param orderId UUID of the parent order containing this order item.
   * @param itemId UUID of the specific order item being snapshotted.
   * @param snapshotId UUID of the snapshot record to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Verify the requested snapshot exists by
     *   joining `ecommerce_platform_snapshots` with
     *   `ecommerce_platform_snapshot_order_items` on the 1:1 relationship. 2.
     *   Verify the snapshot's `ecommerce_platform_order_items_id` matches the
     *   `itemId` path parameter, and the order item's
     *   `ecommerce_platform_order_id` matches the `orderId` path parameter. If
     *   mismatch, return 404 (the snapshot does not belong to the specified
     *   order item). 3. Apply authorization checks: customers can only access
     *   snapshots of orders belonging to their own customer profile; sellers
     *   can access snapshots of orders containing their products; admins have
     *   full access. 4. Return the combined snapshot data: header fields (id,
     *   entity_type, created_at) from `ecommerce_platform_snapshots` plus
     *   subtype fields (quantity, unit_price, created_at, updated_at) from
     *   `ecommerce_platform_snapshot_order_items`. 5. Ensure entity_type is
     *   'order_item' to confirm the snapshot is for the correct entity type.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformSnapshotOrderItem> {
    try {
      return await getEcommercePlatformCustomerOrdersOrderIdItemsItemIdSnapshotsSnapshotId(
        {
          customer,
          orderId,
          itemId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
