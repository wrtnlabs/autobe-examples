@Controller("/ecommercePlatform/customer/addresses/default")
export class EcommerceplatformCustomerAddresses_defaultController {
  /**
   * Set a specified shipping address as the authenticated customer's default shipping address.
   *
   * Designates the provided address as the customer's default for use in checkout and order placement. When a new default is set, the system automatically removes the default status from any previously designated default address. Only one address per customer can hold the default designation at any time.
   *
   * The target address must belong to the authenticated customer's profile and must be an active (non-deleted) address. Customers can change their default address at any time.
   *
   * @param connection
   * @param body Contains the identifier of the shipping address to set as the customer's default. The address must belong to the authenticated customer and must be active (not deleted).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Extract addressId from request body and
     *   validate it is a valid UUID. 2. Query
     *   ecommerce_platform_shipping_addresses for the address where id =
     *   addressId AND ecommerce_platform_customer_profile_id =
     *   authenticated_customer_profile_id AND deleted_at IS NULL. 3. If address
     *   not found, return 404 error. 4. If address is already the default
     *   (is_default = true), return the address as-is (idempotent operation).
     *   5. Execute within a transaction: a. UPDATE
     *   ecommerce_platform_shipping_addresses SET is_default = false,
     *   updated_at = NOW() WHERE ecommerce_platform_customer_profile_id =
     *   authenticated_customer_profile_id AND is_default = true AND deleted_at
     *   IS NULL b. UPDATE ecommerce_platform_shipping_addresses SET is_default
     *   = true, updated_at = NOW() WHERE id = addressId 6. Return the updated
     *   address record with all fields including is_default = true. 7. The
   *   @@unique constraint [ecommerce_platform_customer_profile_id,
   *   is_default] ensures only one default exists per customer. 8. Error
   *   handling: - 400 if addressId is missing or invalid format - 404 if
   *   address not found or belongs to another customer - 400 if address is
   *   soft-deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async setDefault(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommercePlatformShippingAddress.ISetDefault,
  ): Promise<IEcommercePlatformShippingAddress> {
    try {
      return await patchEcommercePlatformCustomerAddressesDefault({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
