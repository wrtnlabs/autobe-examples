import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformShippingAddress } from "../../../../api/structures/IEcommercePlatformShippingAddress";
import { IPageIEcommercePlatformShippingAddress } from "../../../../api/structures/IPageIEcommercePlatformShippingAddress";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteEcommercePlatformCustomerAddressesAddressId } from "../../../../providers/deleteEcommercePlatformCustomerAddressesAddressId";
import { getEcommercePlatformCustomerAddressesAddressId } from "../../../../providers/getEcommercePlatformCustomerAddressesAddressId";
import { patchEcommercePlatformCustomerAddresses } from "../../../../providers/patchEcommercePlatformCustomerAddresses";
import { postEcommercePlatformCustomerAddresses } from "../../../../providers/postEcommercePlatformCustomerAddresses";
import { putEcommercePlatformCustomerAddressesAddressId } from "../../../../providers/putEcommercePlatformCustomerAddressesAddressId";

@Controller("/ecommercePlatform/customer/addresses")
export class EcommerceplatformCustomerAddressesController {
  /**
   * Create a new shipping address for the authenticated customer's account.
   *
   * This endpoint allows customers to add new delivery destinations to their address book. Each address captures the complete delivery information including recipient name, contact phone number, and geographic location details. Customers can maintain multiple shipping addresses and designate one as their default for use during checkout.
   *
   * The new address is automatically associated with the creating customer's profile. When setting a new default address, any existing default address for that customer will automatically have its default status removed to maintain the one-default-per-customer constraint.
   *
   * @param connection
   * @param body Shipping address details including recipient information and geographic location components.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the authenticated customer's profile ID
     *   from the authorization context to establish the ownership relationship.
   *
   * Validate that all required address fields are present and properly formatted.
   *
   * If is_default is true in the request body, first update all existing active shipping addresses for this customer to set is_default=false, ensuring the one-default-per-customer constraint is maintained.
   *
   * Insert a new record into ecommerce_platform_shipping_addresses table with:
   * - ecommerce_platform_customer_profile_id from auth context
   * - recipient_name, phone_number, street_address, city, state, postal_code, country from request body
   * - is_default from request body
   * - System-generated id, created_at, updated_at
   * Return the complete created shipping address record including all system-generated fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommercePlatformShippingAddress.ICreate,
  ): Promise<IEcommercePlatformShippingAddress> {
    try {
      return await postEcommercePlatformCustomerAddresses({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of shipping addresses with optional search filters.
   *
   * This endpoint allows customers to browse and search through their saved shipping addresses. Results can be filtered by recipient name, phone number, default status, and creation date range. The response includes pagination metadata for navigating large address collections.
   *
   * Each customer can only access their own shipping addresses. Addresses marked as soft-deleted are excluded from results by default.
   *
   * @param connection
   * @param body Search criteria for filtering shipping addresses including recipient name filter, phone number filter, default status filter, creation date range, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the ecommerce_platform_shipping_addresses
     *   table for addresses belonging to the authenticated customer's profile.
   *
   * Filtering logic:
   * -recipient_name: case-insensitive partial match (LIKE '%value%')
   * - phone_number: exact or partial match
   * - is_default: boolean exact match when provided
   * - created_at range: filter between minCreatedAt and maxCreatedAt
   *
   * Always exclude soft-deleted records where deleted_at is not null.
   *
   * Scope results to the current customer's profile using the foreign key ecommerce_platform_customer_profile_id.
   *
   * Apply sorting by created_at DESC (newest first) by default, or by requested sort field.
   *
   * Return pagination metadata: total count, current page info, and whether more results exist. Use the requested page size with caps (e.g., max 100 per page).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommercePlatformShippingAddress.IRequest,
  ): Promise<IPageIEcommercePlatformShippingAddress.ISummary> {
    try {
      return await patchEcommercePlatformCustomerAddresses({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single shipping address record by its unique identifier.
   *
   * Returns the complete address details including recipient name, contact phone number, and full geographic location breakdown. The response also indicates whether the address is currently designated as the customer's default shipping destination. This operation requires a valid UUID format for the address identifier and returns a 404 error if the record is not found.
   *
   * @param connection
   * @param addressId Unique UUID identifier of the shipping address to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the ecommerce_platform_shipping_addresses
     *   table using the id column matching the addressId path parameter.
   *
   * Retrieve all active columns: recipient_name, phone_number, street_address, city, state, postal_code, country, is_default, created_at, updated_at. Validate the addressId parameter strictly matches the UUID format. Throw a 404 Not Found exception if no matching record exists in the database. Return the matched record mapped to the IEcommercePlatformShippingAddress response type.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":addressId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformShippingAddress> {
    try {
      return await getEcommercePlatformCustomerAddressesAddressId({
        customer,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates an existing shipping address for the authenticated customer.
   *
   * Customers can modify any fields of their saved shipping addresses including recipient name, phone number, street address, city, state or province, postal code, country, and default status. This operation replaces the existing field values with the new data provided.
   *
   * Only the owner of the shipping address can perform updates. When setting an address as the default, the system automatically unsets the previous default address for that customer.
   *
   * @param connection
   * @param addressId UUID of the shipping address to update.
   * @param body Shipping address fields to be updated. Only non-null fields will be applied. Includes recipient name, phone number, street address, city, state, postal code, country, and default status.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Query the
     *   ecommerce_platform_shipping_addresses table for the record matching the
     *   addressId 2. Verify the record exists and is not soft-deleted
     *   (deleted_at IS NULL) 3. Verify ownership by checking
     *   ecommerce_platform_customer_profile_id matches the authenticated
     *   customer's profile 4. If is_default is being set to true, set
     *   is_default to false for all other addresses of the same customer
     *   profile 5. Update all non-null fields from IUpdate payload:
     *   recipient_name, phone_number, street_address, city, state, postal_code,
     *   country, is_default 6. Update the updated_at timestamp to current time
     *   7. Return the updated shipping address record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":addressId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommercePlatformShippingAddress.IUpdate,
  ): Promise<IEcommercePlatformShippingAddress> {
    try {
      return await putEcommercePlatformCustomerAddressesAddressId({
        customer,
        addressId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Deletes a single shipping address from the customer's address book.
   *
   * Removes the address and prevents its use in new orders. Existing orders using this address are unaffected per Section 271. If this is the last saved address, the system permits deletion but requires creating a new address. If this is the default address, the system requires selecting another address as the new default.
   *
   * @param connection
   * @param addressId (global scope) The unique identifier for the shipping address to delete.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query ecommerce_platform_shipping_addresses by id
     *   parameter. Verify the address exists and belongs to an authenticated
     *   customer. Perform soft deletion by setting deleted_at timestamp. If
     *   this was the default address and customer has other addresses, require
     *   selecting a new default. Return the deleted address record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":addressId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommercePlatformCustomerAddressesAddressId({
        customer,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
