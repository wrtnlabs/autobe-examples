import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommercePlatformCheckout } from "../../../../api/structures/IEcommercePlatformCheckout";
import { IEcommercePlatformOrder } from "../../../../api/structures/IEcommercePlatformOrder";
import { IEcommercePlatformShoppingCartItem } from "../../../../api/structures/IEcommercePlatformShoppingCartItem";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommercePlatformCustomerCartStatus } from "../../../../providers/getEcommercePlatformCustomerCartStatus";
import { postEcommercePlatformCustomerCartCheckout } from "../../../../providers/postEcommercePlatformCustomerCartCheckout";

@Controller("/ecommercePlatform/customer/cart")
export class EcommerceplatformCustomerCartController {
  /**
   * Create a confirmed order by checking out all items in the authenticated customer's shopping cart.
   *
   * This endpoint transitions selected cart items into a formal purchase transaction. The system validates that every item in the cart is available — variants must not be deleted and sufficient stock must exist for all requested quantities. If any item is unavailable, the entire checkout is rejected and customers receive a clear error identifying which items need attention.
   *
   * A shipping address is required in the request body to specify the delivery destination. The system captures this address immutably; it cannot be changed after order confirmation.
   *
   * Upon successful checkout, the order is created with all line items populated from the cart, and the cart is automatically cleared. If checkout fails for any reason, cart items are preserved intact so the customer can correct issues and retry.
   *
   * @param connection
   * @param body Shipping address identifier specifying the delivery destination for the order.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the shopping cart for all active (not
     *   soft-deleted) ecommerce_platform_shopping_cart_items belonging to the
     *   authenticated customer.
   *
   * For each cart item, verify availability:
   * - Join with ecommerce_platform_product_variants to check deleted_at is NULL
   * - Calculate available stock by summing quantity_change from ecommerce_platform_inventory_records for that variant
   * - Compare available stock against the requested quantity in the cart
   * - If any item is unavailable (deleted variant or insufficient stock), abort and return 422 Unprocessable Entity with details of which items failed
   *
   * If all items pass validation, proceed with a database transaction:
   * 1. Insert a new ecommerce_platform_orders row with:
   *    - ecommerce_platform_customer_profile_id: look up from authenticated customer via ecommerce_platform_customer_profiles
   *    - ecommerce_platform_shipping_address_id: from request body
   *    - order_number: auto-generated unique string
   *    - status: 'paid'
   * 2. For each cart item, insert an ecommerce_platform_order_items row with:
   *    - ecommerce_platform_order_id: the new order's ID
   *    - ecommerce_platform_product_variant_id: from the cart item
   *    - quantity: from the cart item
   *    - price: fetch the current per-unit price from ecommerce_platform_product_variants
   *    - status: 'paid'
   * 3. Soft-delete all processed ecommerce_platform_shopping_cart_items (set deleted_at)
   * 4. On failure at any step, rollback the entire transaction and return the error to the caller
   *
   * Return the created order with its populated items.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("checkout")
  public async checkout(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommercePlatformCheckout.ICreate,
  ): Promise<IEcommercePlatformOrder> {
    try {
      return await postEcommercePlatformCustomerCartCheckout({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves the current shopping cart status for the authenticated customer. Returns cart items with details, quantities, stock validation warnings, unavailability flags, and total cart price.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query ecommerce_platform_shopping_cart_items
     *   joined with ecommerce_platform_product_variants for variant details,
     *   and ecommerce_platform_products for product details, scoped to the
     *   authenticated customer. Calculate item subtotals and stock availability
     *   for each cart item by summing inventory records, marking items as
     *   unavailable if the stock is zero or the product or variant is deleted.
     *   Calculate the total cart price as the sum of all item subtotals. Return
     *   the complete cart status view.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("status")
  public async status(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IEcommercePlatformShoppingCartItem.IStatus> {
    try {
      return await getEcommercePlatformCustomerCartStatus({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
