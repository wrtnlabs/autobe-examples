import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommercePlatformCustomerProfile } from "../../../../api/structures/IEcommercePlatformCustomerProfile";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putEcommercePlatformCustomerProfile } from "../../../../providers/putEcommercePlatformCustomerProfile";

@Controller("/ecommercePlatform/customer/profile")
export class EcommerceplatformCustomerProfileController {
  /**
   * Updates the authenticated customer's profile information.
   *
   * This endpoint allows customers to modify their display name and phone number. Changes are saved immediately and become visible across all platform contexts where the customer's identity appears, including review pages and order confirmations.
   *
   * Display name is required and serves as the customer's public identity distinct from their login credentials. Phone number is optional and may be removed by setting it to null.
   *
   * @param connection
   * @param body Profile update request containing display name and optional phone number. Display name must be provided and non-empty.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Extract customer_id from authenticated session
     *   context 2. Validate display_name is not empty (required field per
     *   section 419) 3. Query ecommerce_platform_customer_profiles WHERE
     *   ecommerce_platform_customer_id = session.customer_id 4. Update
     *   display_name and phone_number fields in the profile record 5. Set
     *   updated_at to current timestamp 6. Return the updated
     *   IEcommercePlatformCustomerProfile record
   *
   * Important:
   * - Do NOT create snapshot records for profile updates per section 145
   * - Updates are direct modifications, not state transitions
   * - Only session owner's profile can be updated (enforced by auth context)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommercePlatformCustomerProfile.IUpdate,
  ): Promise<IEcommercePlatformCustomerProfile> {
    try {
      return await putEcommercePlatformCustomerProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
