import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformCancellationRequest } from "../../../../api/structures/IEcommercePlatformCancellationRequest";
import { IPageIEcommercePlatformCancellationRequest } from "../../../../api/structures/IPageIEcommercePlatformCancellationRequest";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommercePlatformCustomerCancellationRequestsCancellationRequestId } from "../../../../providers/getEcommercePlatformCustomerCancellationRequestsCancellationRequestId";
import { patchEcommercePlatformCustomerCancellationRequests } from "../../../../providers/patchEcommercePlatformCustomerCancellationRequests";
import { postEcommercePlatformCustomerCancellationRequests } from "../../../../providers/postEcommercePlatformCustomerCancellationRequests";

@Controller("/ecommercePlatform/customer/cancellation-requests")
export class EcommerceplatformCustomerCancellation_requestsController {
  /**
   * Create a cancellation request for a specific order item. The customer submits an individual item cancellation request, providing the order item identifier and a reason for the cancellation request.
   *
   * This operation is restricted to order items that have reached 'paid' status but have not yet been shipped. The system validates eligibility by checking the order item's current status, confirming no active shipment exists, ensuring the customer owns the item, and verifying no pending cancellation request already exists for that item.
   *
   * Once created, the cancellation request enters a 'pending' state and awaits seller review. The seller will subsequently approve or reject the request through a separate operation. The system automatically records the customer from the authenticated session, so the request body only requires the target order item and cancellation reason.
   *
   * @param connection
   * @param body Cancellation request input including the target order item identifier and free-text cancellation reason.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Extract authenticated customer ID from the
     *   session context.
   *
   * 2. Query ecommerce_platform_order_items:
   *    - Verify the order item exists (by request body orderItemId).
   *    - Verify the order item belongs to the authenticated customer by joining ecommerce_platform_orders on orderId and checking orders.customerId matches the session customer.
   *    - Verify the order item status is exactly 'paid'. Reject with 400 if status is 'shipped', 'delivered', 'cancelled', or 'refunded'.
   *
   * 3. Check ecommerce_platform_shipments via ecommerce_platform_shipment_items:
   *    - Reject with 400 if any active shipment record contains this order item.
   *
   * 4. Check ecommerce_platform_cancellation_requests:
   *    - Enforce @@unique constraint on ecommerce_platform_order_item_id.
   *    - Reject with 409 if any cancellation request already exists for this order item (regardless of status).
   *
   * 5. Insert into ecommerce_platform_cancellation_requests:
   *    - id: generate UUID
   *    - ecommerce_platform_order_item_id: from request body
   *    - ecommerce_platform_customer_id: from authenticated session
   *    - reason: from request body
   *    - status: 'pending'
   *    - seller_response_reason: null
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   *
   * 6. Return the newly created cancellation request record with HTTP 201 status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommercePlatformCancellationRequest.ICreate,
  ): Promise<IEcommercePlatformCancellationRequest> {
    try {
      return await postEcommercePlatformCustomerCancellationRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and list cancellation requests with filtering and pagination support.
   *
   * This endpoint retrieves a paginated list of cancellation requests, allowing filtering by status (pending, approved, rejected), customer, order item, date ranges, and other search criteria. Results are returned as summary records optimized for list displays.
   *
   * Customers can view their own cancellation requests, sellers can view requests related to their products, and administrators have access to all cancellation requests on the platform.
   *
   * @param connection
   * @param body Search and filter criteria for cancellation requests, including status filters, text search on reason, date range filters, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the
     *   ecommerce_platform_cancellation_requests table with pagination and
     *   filtering capabilities.
   *
   * Apply search filters based on the request body:
   * - status: filter by cancellation status (pending, approved, rejected)
   * - reason: text search on the cancellation reason field
   * - date ranges: filter by created_at or updated_at timestamps
   * - customer filters: filter by customer identity
   *
   * For customers: restrict results to only their own requests using ecommerce_platform_customer_id.
   * For sellers: join through order_item -> product_variant -> product -> seller_product_profile to find requests for their products.
   * For admins: no additional restrictions.
   *
   * Join with ecommerce_platform_order_items to include order item information in results if requested.
   * Return cursor-based or offset-based pagination based on system configuration.
   *
   * Sort results by created_at descending by default (most recent first).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommercePlatformCancellationRequest.IRequest,
  ): Promise<IPageIEcommercePlatformCancellationRequest.ISummary> {
    try {
      return await patchEcommercePlatformCustomerCancellationRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single cancellation request by its unique identifier.
   *
   * Cancellation requests allow customers to request cancellation of order items that have 'paid' status before shipping. The returned entity includes the request reason, current processing status (pending, approved, or rejected), seller's response reason if rejected, and timestamps for creation and last update.
   *
   * This endpoint supports both customer and seller access to cancellation request details for order management and dispute resolution workflows.
   *
   * @param connection
   * @param cancellationRequestId Unique identifier for the cancellation request. Must be a valid UUID format.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the
     *   ecommerce_platform_cancellation_requests table using the
     *   cancellationRequestId path parameter to retrieve a single cancellation
     *   request record.
   *
   * Implementation steps:
   * 1. Validate the cancellationRequestId is a valid UUID format
   * 2. Execute a SELECT query on ecommerce_platform_cancellation_requests WHERE id = cancellationRequestId
   * 3. Join with ecommerce_platform_order_items to include order item context
   * 4. Join with ecommerce_platform_customers to include customer information
   * 5. Return 404 if the cancellation request does not exist
   * 6. Return 403 if the requesting user is not authorized to view this cancellation request
   * 7. Return the cancellation request entity with all fields including id, ecommerce_platform_order_item_id, reason, status, seller_response_reason, created_at, updated_at
   *
   * Error handling:
   * - 404 Not Found: If no cancellation request exists with the provided ID
   * - 403 Forbidden: If the requesting user does not have permission to view this cancellation request
   * - Request authorization should verify the user is either the customer who created the request or the seller who owns the order item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":cancellationRequestId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cancellationRequestId")
    cancellationRequestId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformCancellationRequest> {
    try {
      return await getEcommercePlatformCustomerCancellationRequestsCancellationRequestId(
        {
          customer,
          cancellationRequestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
