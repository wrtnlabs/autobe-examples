import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformCustomer } from "../../../api/structures/IEcommercePlatformCustomer";
import { IPageIEcommercePlatformCustomer } from "../../../api/structures/IPageIEcommercePlatformCustomer";
import { getEcommercePlatformCustomersCustomerId } from "../../../providers/getEcommercePlatformCustomersCustomerId";
import { patchEcommercePlatformCustomers } from "../../../providers/patchEcommercePlatformCustomers";

@Controller("/ecommercePlatform/customers")
export class EcommerceplatformCustomersController {
  /**
   * Search and list customer accounts on the ecommerce platform.
   *
   * This endpoint retrieves a paginated list of customer records, including their associated profile information such as display names and phone numbers. Sensitive authentication data is excluded from the results.
   *
   * This operation is restricted to platform administrators who need to monitor customer accounts, manage bans, or audit user activity. It supports filtering by email, ban status, and account creation date ranges.
   *
   * @param connection
   * @param body Search criteria and pagination controls for querying customer accounts. Supports filtering by email address, display name, ban status, and account creation date ranges. Includes page size and sorting preferences.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the `ecommerce_platform_customers` table
     *   and LEFT JOIN `ecommerce_platform_customer_profiles` table on
     *   `ecommerce_platform_customers.id =
     *   ecommerce_platform_customer_profiles.ecommerce_platform_customer_id`.
   *
   * Apply search filters from the request body:
   * - `email`: Exact or case-insensitive partial match on `ecommerce_platform_customers.email`.
   * - `displayName`: Case-insensitive partial match on `ecommerce_platform_customer_profiles.display_name`.
   * - `isBanned`: Exact boolean match on `ecommerce_platform_customers.is_banned`.
   * - `createdAtFrom` / `createdAtTo`: Date range filter on `ecommerce_platform_customers.created_at`.
   *
   * Exclude the `password_hash` field from all query results.
   *
   * Verify that the caller has the `admin` role authorization before executing the query.
   *
   * Implement server-side pagination for the result set. Return a `totalCount` and the paginated list of items.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommercePlatformCustomer.IRequest,
  ): Promise<IPageIEcommercePlatformCustomer.ISummary> {
    try {
      return await patchEcommercePlatformCustomers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves the full details of a specific customer account by its unique identifier.
   *
   * This operation provides comprehensive visibility into a customer's registration status, authentication flags, and personalization data. It securely omits sensitive credentials while exposing the linked customer profile information such as display names and phone numbers. The endpoint returns a 404 error if the provided customerId does not match any existing account.
   *
   * @param connection
   * @param customerId The unique UUID identifier of the customer account.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the ecommerce_platform_customers table
     *   filtering by id equal to the {customerId} path parameter. Left join
     *   ecommerce_platform_customer_profiles using
     *   ecommerce_platform_customer_id. Map the result to
     *   IEcommercePlatformCustomer. Exclude password_hash in the response
     *   payload for security. Return HTTP 404 Not Found when the record is
     *   missing or has been soft-deleted. Ensure transaction scope reads only
     *   committed data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerId")
  public async at(
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformCustomer> {
    try {
      return await getEcommercePlatformCustomersCustomerId({
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
