import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommercePlatformAdmin } from "../../../../api/structures/IEcommercePlatformAdmin";
import { postEcommercePlatformAuthAdminJoin } from "../../../../providers/postEcommercePlatformAuthAdminJoin";
import { postEcommercePlatformAuthAdminLogin } from "../../../../providers/postEcommercePlatformAuthAdminLogin";
import { postEcommercePlatformAuthAdminRefresh } from "../../../../providers/postEcommercePlatformAuthAdminRefresh";

@Controller("/ecommercePlatform/auth/admin")
export class EcommerceplatformAuthAdminController {
  /**
   * Register a new administrator account on the ecommerce platform.
   *
   * Creates an administrator account with the provided email and password credentials. The system validates that the email is not already associated with any existing account type on the platform. Upon successful registration, the admin is granted default permissions as a regular administrator (is_super=false).
   *
   * A session record is created in ecommerce_platform_admin_sessions for security auditing, and JWT tokens are issued in the response.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator registration credentials including email and password.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Service creates a new record in
     *   ecommerce_platform_admins with is_super=false (default regular admin
     *   grade) and is_banned=false (active status). Validates email uniqueness
     *   across all account types (customers, sellers, existing admins) —
     *   rejects with 409 if duplicate. Hashes password securely. Creates
     *   session record in ecommerce_platform_admin_sessions capturing IP, href,
     *   and referrer from request context for security auditing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommercePlatformAdmin.IJoin,
  ): Promise<IEcommercePlatformAdmin.IAuthorized> {
    try {
      return await postEcommercePlatformAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an administrator to access platform management features.
   *
   * Validates the provided email and password credentials against registered administrator records. The system checks whether the admin account is banned before allowing login.
   *
   * Successful authentication establishes a new session in ecommerce_platform_admin_sessions and returns JWT tokens for subsequent authenticated requests.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator login credentials with email and password.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Service validates email and password against
     *   ecommerce_platform_admins table. Checks is_banned flag before granting
     *   access — returns 403 if admin is banned. On success, creates session in
     *   ecommerce_platform_admin_sessions with connection metadata. Issues JWT
     *   tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommercePlatformAdmin.ILogin,
  ): Promise<IEcommercePlatformAdmin.IAuthorized> {
    try {
      return await postEcommercePlatformAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew administrator session tokens for continued platform access.
   *
   * Accepts a valid refresh token to extend the administrator's authenticated session. The system validates token expiry and checks the administrator's ban status before issuing new tokens.
   *
   * Token rotation ensures previous refresh tokens become invalid after successful renewal.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Current refresh token for session renewal.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Service validates refresh token against active
     *   sessions in ecommerce_platform_admin_sessions. Checks expired_at
     *   timestamp for validity. Verifies associated admin account is not
     *   banned. If valid, creates new session with fresh expiry and rotates
     *   refresh tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommercePlatformAdmin.IRefresh,
  ): Promise<IEcommercePlatformAdmin.IAuthorized> {
    try {
      return await postEcommercePlatformAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
