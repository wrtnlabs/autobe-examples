import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommercePlatformSeller } from "../../../../api/structures/IEcommercePlatformSeller";
import { postEcommercePlatformAuthSellerJoin } from "../../../../providers/postEcommercePlatformAuthSellerJoin";
import { postEcommercePlatformAuthSellerLogin } from "../../../../providers/postEcommercePlatformAuthSellerLogin";
import { postEcommercePlatformAuthSellerRefresh } from "../../../../providers/postEcommercePlatformAuthSellerRefresh";

@Controller("/ecommercePlatform/auth/seller")
export class EcommerceplatformAuthSellerController {
  /**
   * Register a new seller account with email and password credentials.
   *
   * Seller accounts require administrator approval before selling privileges are granted. Upon registration, the account is created with 'pending' approval status. The email must be unique across all platform accounts (customer, seller, administrator) — duplicate email across any account type results in rejection.
   *
   * After successful registration, the seller can log in but seller-specific operations are restricted until administrator approval. A seller approval request is automatically created and tracked in the ecommerce_platform_seller_approval_requests table.
   *
   * A seller profile is also created simultaneously with the account, establishing the business identity foundation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials for the new seller account.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_platform_sellers for existing
     *   email to enforce cross-account uniqueness (check customers, sellers,
     *   admins tables). If not duplicate, hash password using bcrypt, insert
     *   into ecommerce_platform_sellers with email, password_hash,
     *   approval_status='pending', is_banned=false. Auto-create
     *   ecommerce_platform_seller_approval_requests with status='pending'.
     *   Auto-create ecommerce_platform_seller_profiles with shop_name from
     *   request or default. Generate JWT access and refresh tokens, insert
     *   session into ecommerce_platform_seller_sessions with ip, href, referrer
     *   from request. Return tokens in IAuthorized response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommercePlatformSeller.IJoin,
  ): Promise<IEcommercePlatformSeller.IAuthorized> {
    try {
      return await postEcommercePlatformAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing seller account using email and password credentials.
   *
   * The system validates the email address exists and the password matches the stored hash. Banned sellers (is_banned=true) are denied authentication entirely.
   *
   * Sellers with 'pending' or 'rejected' approval_status can log in and establish a session, though their business operations are restricted by approval status.
   *
   * Upon successful login, a new session record is created in ecommerce_platform_seller_sessions tracking client connection metadata.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials including email and password.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_platform_sellers by email. Check
     *   is_banned=true — reject login if banned. Verify password against
     *   password_hash using bcrypt. Generate JWT access and refresh tokens.
     *   Insert new session record into ecommerce_platform_seller_sessions with
     *   current ip, href, referrer. Return tokens in IAuthorized response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommercePlatformSeller.ILogin,
  ): Promise<IEcommercePlatformSeller.IAuthorized> {
    try {
      return await postEcommercePlatformAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew the seller's authentication tokens using a valid refresh token.
   *
   * When access tokens expire, this operation allows the session to continue without requiring re-login. The refresh token is validated against the session records in ecommerce_platform_seller_sessions, checking expiration and association with a valid seller account.
   *
   * Returns fresh JWT tokens extending the authenticated session lifecycle.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Current refresh token to be renewed.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Validate the provided refresh token. Query
     *   ecommerce_platform_seller_sessions or verify JWT structure with seller
     *   ID. Check token hasn't expired (expired_at > now). Generate new JWT
     *   access and refresh tokens with extended expiry. Return new tokens in
     *   IAuthorized response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommercePlatformSeller.IRefresh,
  ): Promise<IEcommercePlatformSeller.IAuthorized> {
    try {
      return await postEcommercePlatformAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
