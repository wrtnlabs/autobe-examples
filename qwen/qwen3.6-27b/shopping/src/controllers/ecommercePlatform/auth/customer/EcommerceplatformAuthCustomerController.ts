import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommercePlatformCustomer } from "../../../../api/structures/IEcommercePlatformCustomer";
import { postEcommercePlatformAuthCustomerJoin } from "../../../../providers/postEcommercePlatformAuthCustomerJoin";
import { postEcommercePlatformAuthCustomerLogin } from "../../../../providers/postEcommercePlatformAuthCustomerLogin";
import { postEcommercePlatformAuthCustomerRefresh } from "../../../../providers/postEcommercePlatformAuthCustomerRefresh";

@Controller("/ecommercePlatform/auth/customer")
export class EcommerceplatformAuthCustomerController {
  /**
   * Register a new customer account with email and password. Validates uniqueness across all platform account types to prevent duplicate registrations.
   *
   * Upon success, creates customer identity with encrypted password in ecommerce_platform_customers. Initializes customer profile in ecommerce_platform_customer_profiles. Establishes first authentication session with device fingerprint and refresh token lifecycle.
   *
   * Returns JWT access and refresh tokens. Returns 409 Conflict if email is already registered.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Email address and password for the new customer registration. The email must not be associated with any existing account on the platform.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Process customer registration by validating email
     *   uniqueness across all account types (customers, sellers, admins) in
     *   ecommerce_platform_customers and related tables. Hash the password
     *   using bcrypt or equivalent algorithm and store in password_hash column.
     *   Set is_banned to false. Create linked customer_profile in
     *   ecommerce_platform_customer_profiles. Create initial session in
     *   ecommerce_platform_customer_sessions with refresh_token_hash, device
     *   fingerprint (ip, user_agent), and expiration. Return JWT tokens in
     *   IAuthorized response. Return 409 Conflict if email already exists.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommercePlatformCustomer.IJoin,
  ): Promise<IEcommercePlatformCustomer.IAuthorized> {
    try {
      return await postEcommercePlatformAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a customer account using email and password credentials.
   *
   * Verifies the customer exists and is active in ecommerce_platform_customers. Ensures the account is not banned. Validates the password matches the stored hash.
   *
   * Upon success, creates a new session record in ecommerce_platform_customer_sessions tracking device fingerprint and refresh token lifecycle.
   *
   * Returns JWT tokens. Returns 401 Unauthorized for invalid credentials. Returns 403 Forbidden for banned accounts.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Email and password credentials for customer authentication.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Authenticate customer by querying
     *   ecommerce_platform_customers for the provided email with deleted_at is
     *   null. Verify is_banned is false. Compare input password against
     *   password_hash using bcrypt comparison. Create new session in
     *   ecommerce_platform_customer_sessions with hashed refresh_token_hash,
     *   current ip, user_agent, and calculated expiration. Return JWT tokens in
     *   IAuthorized response. Return 401 Unauthorized if invalid credentials or
     *   account not found. Return 403 Forbidden if account is banned.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommercePlatformCustomer.ILogin,
  ): Promise<IEcommercePlatformCustomer.IAuthorized> {
    try {
      return await postEcommercePlatformAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew authentication tokens using a valid refresh token from ecommerce_platform_customer_sessions.
   *
   * Validates the session exists, is not soft-deleted, and has not expired. Implements token rotation policy by generating new access and refresh token pairs, updating session record with the new refresh_token_hash and extended expiration.
   *
   * Returns new JWT tokens. Returns 401 Unauthorized if the refresh token is invalid, expired, or session has been revoked.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Current refresh token for session validation and renewal.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Refresh authentication tokens by matching
     *   refresh_token_hash in ecommerce_platform_customer_sessions where
     *   deleted_at is null and expired_at is in the future. Verify linked
     *   customer exists and is active. Generate new JWT access token and
     *   refresh token. Update session record with new refresh_token_hash,
     *   refresh expired_at, and record updated_at. Return new tokens in
     *   IAuthorized response. Return 401 if token not found, expired, or
     *   session deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommercePlatformCustomer.IRefresh,
  ): Promise<IEcommercePlatformCustomer.IAuthorized> {
    try {
      return await postEcommercePlatformAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
