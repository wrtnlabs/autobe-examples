import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformRefundRequest } from "../../../../api/structures/IEcommercePlatformRefundRequest";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { putEcommercePlatformSellerRefundRequestsRefundRequestId } from "../../../../providers/putEcommercePlatformSellerRefundRequestsRefundRequestId";

@Controller("/ecommercePlatform/seller/refund-requests/:refundRequestId")
export class EcommerceplatformSellerRefund_requestsController {
  /**
   * Update a pending refund request by approving or rejecting it.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request to respond to.
   * @param body Seller's response decision to the refund request, including approval or rejection status and optional notes for the customer.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_platform_refund_requests by id.
     *   Verify the request exists and is in 'pending' status, or reject with
     *   409 Conflict if already approved/rejected.
   *
   * Validate seller authorization: the authenticated seller must match the seller_profile_id on the refund request. If mismatch, return 403 Forbidden.
   *
   * Check the order_item_id linked to the refund request:
   * - Join with ecommerce_platform_order_items to verify the item exists and has 'delivered' status.
   * - On approval: update order item status to 'refunded', process refund payment to the customer, create an inventory record in ecommerce_platform_inventory_records to restore stock for the product variant, compute and update parent order status (refunded if all items refunded, otherwise partially_completed).
   * - On rejection: keep order item status as 'delivered', no inventory changes.
   *
   * Set refunded_at timestamp on the refund_request record. Compute updated_at. Create a snapshot entry via ecommerce_platform_snapshots and ecommerce_platform_snapshot_refund_requests to record the state transition.
   *
   * Return 409 Conflict if refund request status is not 'pending'.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommercePlatformRefundRequest.IUpdate,
  ): Promise<IEcommercePlatformRefundRequest> {
    try {
      return await putEcommercePlatformSellerRefundRequestsRefundRequestId({
        seller,
        refundRequestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
