import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformSnapshotSellerProfile } from "../../../../api/structures/IEcommercePlatformSnapshotSellerProfile";
import { IPageIEcommercePlatformSnapshotSellerProfile } from "../../../../api/structures/IPageIEcommercePlatformSnapshotSellerProfile";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommercePlatformSellerProfileSnapshotsSnapshotId } from "../../../../providers/getEcommercePlatformSellerProfileSnapshotsSnapshotId";
import { patchEcommercePlatformSellerProfileSnapshots } from "../../../../providers/patchEcommercePlatformSellerProfileSnapshots";

@Controller("/ecommercePlatform/seller/profile-snapshots")
export class EcommerceplatformSellerProfile_snapshotsController {
  /**
   * Search and list seller profile snapshots with filtering and pagination.
   *
   * This endpoint retrieves the complete audit trail of seller profile modifications, providing access to historical records of shop name, description, and logo changes. Each snapshot captures the exact before and after state values at the time of modification, serving as an immutable record for dispute resolution and administrative oversight.
   *
   * Administrators can filter snapshots by seller profile identifier, date range, or search within modification details. Results are returned in paginated format, ordered by most recent first, enabling efficient investigation of profile change history across the platform.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering seller profile snapshots by seller identifier, modification date range, and result ordering.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_platform_snapshots table filtered
     *   by entity_type = 'seller_profile'.
   *
   * Join with ecommerce_platform_snapshot_seller_profiles on the snapshot header ID to retrieve detailed state fields:
   * - previous_shop_name, current_shop_name
   * - previous_shop_description, current_shop_description
   * - previous_logo_uri, current_logo_uri
   *
   * Join with ecommerce_platform_seller_profiles on profile ID to link to the seller whose profile was modified.
   *
   * Apply request body filters:
   * - seller profile ID filter (exact match on ecommerce_platform_seller_profiles_id)
   * - optional date range for created_at timestamp
   * - optional pagination parameters (cursor or offset-based)
   *
   * Sort by created_at descending (newest snapshots first).
   *
   * Validate requesting user has administrative privileges for accessing snapshot audit data.
   *
   * Return only seller_profile entity type snapshots; exclude other snapshot types (product, variant, order item, review, cancellation, refund).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommercePlatformSnapshotSellerProfile.IRequest,
  ): Promise<IPageIEcommercePlatformSnapshotSellerProfile.ISummary> {
    try {
      return await patchEcommercePlatformSellerProfileSnapshots({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific seller profile snapshot record showing the complete edit history for a single profile modification event. The response includes the snapshot creation timestamp, entity type identifier, and before-and-after values for all modified profile attributes including shop name, shop description, and logo URI.
   *
   * Seller profile snapshots are automatically created whenever a seller edits their profile, providing an immutable audit trail that cannot be modified or deleted. This data is used for dispute resolution and historical reference.
   *
   * Access is restricted to the seller who owns the profile and platform administrators. Unauthorized users cannot view these records.
   *
   * @param connection
   * @param snapshotId UUID of the snapshot record to retrieve (scoped to seller_profile entity type)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_platform_snapshots table for the
     *   record matching the provided snapshotId UUID.
   *
   * 1. Validate the record exists within the snapshots table
   * 2. Validate the entity_type equals 'seller_profile'; return 404 Not Found if different
   * 3. Join with ecommerce_platform_snapshot_seller_profiles on snapshots.id = subtype.ecommerce_platform_snapshots_id
   * 4. Authorization: Verify authenticated user is either the seller owning the profile or an administrator
   * 5. Return the combined record with snapshot metadata (id, entity_type, created_at), profile reference, and all nullable previous/current fields for shop_name, shop_description, and logo_uri
   *
   * Error handling:
   * - 404 Not Found: Snapshot does not exist or entity_type is not seller_profile
   * - 403 Forbidden: Requester lacks authorization
   * - 422 Unprocessable Content: Invalid entity_type for this endpoint
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformSnapshotSellerProfile> {
    try {
      return await getEcommercePlatformSellerProfileSnapshotsSnapshotId({
        seller,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
