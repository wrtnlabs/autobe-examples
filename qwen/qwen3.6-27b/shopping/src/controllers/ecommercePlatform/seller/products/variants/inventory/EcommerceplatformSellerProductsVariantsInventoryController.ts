import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformInventoryRecord } from "../../../../../../api/structures/IEcommercePlatformInventoryRecord";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getEcommercePlatformSellerProductsProductIdVariantsVariantIdInventoryInventoryId } from "../../../../../../providers/getEcommercePlatformSellerProductsProductIdVariantsVariantIdInventoryInventoryId";
import { patchEcommercePlatformSellerProductsProductIdVariantsVariantIdInventory } from "../../../../../../providers/patchEcommercePlatformSellerProductsProductIdVariantsVariantIdInventory";
import { postEcommercePlatformSellerProductsProductIdVariantsVariantIdInventory } from "../../../../../../providers/postEcommercePlatformSellerProductsProductIdVariantsVariantIdInventory";

@Controller(
  "/ecommercePlatform/seller/products/:productId/variants/:variantId/inventory",
)
export class EcommerceplatformSellerProductsVariantsInventoryController {
  /**
   * Create a new inventory ledger record to adjust stock for a product variant.
   *
   * This operation adds an immutable entry to the inventory history of a specific product variant. Positive quantity values represent stock additions (restocking, cancellations, refunds), while negative values represent stock removals (order fulfillment, loss adjustments). The current stock level for any variant is always computed by summing all quantity_delta values across its inventory records.
   *
   * Only the seller who owns the product can create inventory records for its variants. Each record captures the signed quantity change, business reason, and timestamp - forming a permanent audit trail for dispute resolution and regulatory compliance.
   *
   * @param connection
   * @param productId Product identifier (scoped to enterprise)
   * @param variantId Product variant identifier (scoped to product)
   * @param body Inventory adjustment details including signed quantity change and business reason.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_platform_product_variants to
     *   verify the variant exists and belongs to the specified product.
     *   Validate that the authenticated user is the owner of the product (via
     *   ecommerce_platform_seller_profile_id relationship) or has admin
     *   privileges.
   *
   * Insert a new record into ecommerce_platform_inventory_records with the provided quantity_delta and reason values. The system auto-generates the id (UUID) and created_at (current timestamp).
   *
   * Validate that quantity_delta is non-zero (prevent meaningless zero-adjustments). Return the created inventory record with all fields populated.
   *
   * Edge cases: Return 404 if product or variant not found. Return 403 if user lacks permission (not seller owner and not admin). Return 400 if quantity_delta is zero or reason is empty.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommercePlatformInventoryRecord.ICreate,
  ): Promise<IEcommercePlatformInventoryRecord> {
    try {
      return await postEcommercePlatformSellerProductsProductIdVariantsVariantIdInventory(
        {
          seller,
          productId,
          variantId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Adjusts inventory stock levels for a specific product variant by appending an immutable ledger entry. Use positive quantity deltas for restocking or refund restorations, and negative deltas for manual stock reductions or loss adjustments. Every submission creates a permanent audit trail recording the exact change amount, business reason, and precise timestamp. The actual stock level is derived by summing all quantity deltas for the variant across its complete ledger history.
   *
   * @param connection
   * @param productId Product identifier scoping the variant lookup. Validated against the parent `ecommerce_platform_products` relationship.
   * @param variantId Target product variant identifier for which the inventory adjustment is recorded. Maps directly to `ecommerce_platform_product_variant_id`.
   * @param body Inventory adjustment payload containing the signed integer delta representing the stock change and a descriptive reason documenting the business context for the adjustment.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Validate that the product variant exists, is not
     *   soft-deleted, and belongs to the provided `productId`. Insert a new
     *   record into `ecommerce_platform_inventory_records` mapping `variantId`
     *   to `ecommerce_platform_product_variant_id`. Set `quantity_delta` and
     *   `reason` from the request body. Auto-populate `created_at` with the
     *   current timestamp. Return the fully persisted inventory record. Ensure
     *   transactional integrity so the ledger entry is only committed if
     *   variant validation succeeds. Verify FK constraints and handle
     *   concurrent adjustment attempts safely.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async adjust(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommercePlatformInventoryRecord.ICreate,
  ): Promise<IEcommercePlatformInventoryRecord> {
    try {
      return await patchEcommercePlatformSellerProductsProductIdVariantsVariantIdInventory(
        {
          seller,
          productId,
          variantId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific inventory stock change record for a product variant. Returns the complete immutable ledger entry including the quantity delta amount, business reason, and timestamp of the stock movement event. This endpoint enables sellers to inspect individual stock changes from their product variant's inventory history, including restocking events, order fulfillment deductions, manual adjustments, and cancellation or refund restorations. Inventory records are append-only and never modified, ensuring a complete and trustworthy audit trail for stock tracking and dispute resolution.
   *
   * @param connection
   * @param productId UUID identifier of the parent product containing the variant (scoped to product catalog)
   * @param variantId UUID identifier of the product variant whose inventory was changed (scoped to product)
   * @param inventoryId UUID identifier of the specific inventory ledger entry to retrieve (scoped to variant)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_platform_inventory_records table
     *   for the record matching inventoryId. Validate that the inventory
     *   record's ecommerce_platform_product_variant_id matches the variantId
     *   path parameter, and that the variant's ecommerce_platform_product_id
     *   matches the productId path parameter.
   *
   * Authorization: Sellers can only access inventory records for their own product variants (check sellers → seller_profiles → products → variants relationship). Administrators have full access for platform oversight.
   *
   * Return the complete inventory record with all fields: id, ecommerce_platform_product_variant_id, quantity_delta, reason, created_at. Do not filter on deleted_at as inventory records are never soft-deleted - they are immutable ledger entries.
   *
   * Error handling: Return 404 if inventory record not found, if variantId doesn't match record's foreign key, if productId doesn't match variant's parent product, or if user lacks authorization to access the product variant.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":inventoryId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedParam("inventoryId")
    inventoryId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformInventoryRecord> {
    try {
      return await getEcommercePlatformSellerProductsProductIdVariantsVariantIdInventoryInventoryId(
        {
          seller,
          productId,
          variantId,
          inventoryId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
