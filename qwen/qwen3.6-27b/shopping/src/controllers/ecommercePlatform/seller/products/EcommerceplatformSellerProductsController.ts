import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformProduct } from "../../../../api/structures/IEcommercePlatformProduct";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteEcommercePlatformSellerProductsProductId } from "../../../../providers/deleteEcommercePlatformSellerProductsProductId";
import { postEcommercePlatformSellerProducts } from "../../../../providers/postEcommercePlatformSellerProducts";
import { putEcommercePlatformSellerProductsProductId } from "../../../../providers/putEcommercePlatformSellerProductsProductId";

@Controller("/ecommercePlatform/seller/products")
export class EcommerceplatformSellerProductsController {
  /**
   * Create a new product listing for the authenticated seller's shop.
   *
   * This operation allows approved sellers to add new products to the marketplace with a name, description, category assignment, and base price. The product is automatically associated with the seller's shop profile.
   *
   * Products created through this operation appear in search results and category listings within the assigned category. Products must have at least one variant to be considered purchasable; products without variants appear in search results as unavailable.
   *
   * Only approved sellers can create products. Unapproved or banned sellers cannot access this operation.
   *
   * @param connection
   * @param body Product creation request containing the product name, description, category assignment, and base price. The seller association is automatically derived from the authenticated session.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Validate the authenticated user is an approved
     *   seller by looking up the customer session and confirming seller status.
     *   Fetch the seller profile associated with the seller ID to obtain the
     *   seller_profile_id.
   *
   * Validate the target category exists and is not soft-deleted by querying ecommerce_platform_categories using the categoryId from the request body. Return 404 if the category does not exist or is soft-deleted.
   *
   * Create the product record in ecommerce_platform_products with the following fields:
   * - id: auto-generated UUID
   * - ecommerce_platform_seller_profile_id: from the authenticated seller's profile
   * - name: from request body
   * - description: from request body
   * - ecommerce_platform_category_id: from request body
   * - base_price: from request body
   * - created_at: current timestamp
   * - updated_at: current timestamp
   * - deleted_at: null
   *
   * Generate a snapshot record in ecommerce_platform_snapshots with entity_type set to 'product' if required by domain rules for initial creation.
   *
   * Return the complete product entity including all fields and the assigned seller information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommercePlatformProduct.ICreate,
  ): Promise<IEcommercePlatformProduct> {
    try {
      return await postEcommercePlatformSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product's details including name, description, category assignment, and base price.
   *
   * Only the authenticated seller who owns the product can perform this operation. The system verifies ownership by comparing the seller's profile ID against the product's seller reference. Upon successful update, the product's updated_at timestamp is refreshed and an immutable snapshot is automatically created to preserve the previous state.
   *
   * Product availability status is derived from variant stock levels rather than stored as a separate field. Products without any variants appear in search results but are marked as unavailable.
   *
   * @param connection
   * @param productId UUID identifier of the product to update (global scope)
   * @param body Product update fields including name, description, category selection, and base price. Only the fields provided will be updated; system-owned fields like id, timestamps, and seller ownership cannot be modified.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Verify the authenticated seller owns the product
     *   by comparing seller_id from session against
     *   ecommerce_platform_seller_profile_id in the product record. Load the
     *   current product state and create a snapshot record in
     *   ecommerce_platform_snapshots and ecommerce_platform_snapshot_products
     *   before applying changes. Update name, description,
     *   ecommerce_platform_category_id, and base_price fields. Validate that
     *   the target category exists and is not soft-deleted. Set updated_at
     *   timestamp to current time. Return the fully updated product record with
     *   all current field values. Handle validation errors for missing required
     *   fields, invalid category references, and unauthorized access attempts.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommercePlatformProduct.IUpdate,
  ): Promise<IEcommercePlatformProduct> {
    try {
      return await putEcommercePlatformSellerProductsProductId({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete a product listing by removing it from search results and category navigation while preserving the record for order history integrity.
   *
   * This operation permanently removes the product from public-facing views (search, category browsing) and simultaneously removes all associated variants. Product data is preserved internally through the soft-delete mechanism (deleted_at timestamp) to maintain financial and order history records.
   *
   * Only the seller who owns the product can delete it. Authorization is enforced before the operation proceeds.
   *
   * Deletion is blocked if any of the following conditions exist on the product's variants:
   *
   * - Order items with active status (paid or shipped) that require fulfillment
   * - Pending cancellation requests awaiting seller response
   * - Pending refund requests awaiting seller response
   *
   * To enable product deletion, resolve all pending transactions first. Customers must complete their orders or sellers must respond to cancellation/refund requests before the product can be removed.
   *
   * @param connection
   * @param productId UUID identifier of the product to erase from the marketplace.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Step 1 - Load Product: Query
     *   ecommerce_platform_products by productId (id field). Return 404 Not
     *   Found if not exists.
   *
   * Step 2 - Authorization: Verify authenticated actor is the product owner.
   * - Actor must be the seller whose profile_id matches ecommerce_platform_seller_profile_id
   * - Return 403 Forbidden if unauthorized
   *
   * Step 3 - Deletion Restriction Checks:
   * - Load all variants where ecommerce_platform_product_id = productId
   * - For each variant, check if ANY order_items exist with status IN ('paid', 'shipped')
   *   → If found, return 409 Conflict with message about active orders blocking deletion
   * - For each variant, check if ANY order_items have cancellation_requests with status = 'pending'
   *   → If found, return 409 Conflict with message about pending cancellation requests blocking deletion
   * - For each variant, check if ANY order_items have refund_requests with status = 'pending'
   *   → If found, return 409 Conflict with message about pending refund requests blocking deletion
   *
   * Step 4 - Execute Soft Delete:
   * - Set deleted_at = CURRENT_TIMESTAMP on product record
   * - Soft-delete all variants by setting deleted_at = CURRENT_TIMESTAMP on each
   * - Use database transaction to ensure atomicity
   *
   * Step 5 - Response: Return null body with 200 OK.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommercePlatformSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
