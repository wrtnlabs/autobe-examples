import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformProductVariant } from "../../../../../api/structures/IEcommercePlatformProductVariant";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { deleteEcommercePlatformSellerProductsProductIdVariantsSkuCode } from "../../../../../providers/deleteEcommercePlatformSellerProductsProductIdVariantsSkuCode";
