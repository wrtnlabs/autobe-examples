import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformProductImage } from "../../../../../api/structures/IEcommercePlatformProductImage";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { deleteEcommercePlatformSellerProductsProductIdImagesImageId } from "../../../../../providers/deleteEcommercePlatformSellerProductsProductIdImagesImageId";
import { postEcommercePlatformSellerProductsProductIdImages } from "../../../../../providers/postEcommercePlatformSellerProductsProductIdImages";
import { putEcommercePlatformSellerProductsProductIdImagesImageId } from "../../../../../providers/putEcommercePlatformSellerProductsProductIdImagesImageId";

@Controller("/ecommercePlatform/seller/products/:productId/images")
export class EcommerceplatformSellerProductsImagesController {
  /**
   * Add multiple product images to a product in a single operation.
   *
   * Sellers can upload new images to their products by submitting image URIs. The system appends new images to the existing image collection, automatically assigning display order indices. Each image URI is validated and stored with the next available order position.
   *
   * The operation is restricted to the product's owning seller. Images are immediately visible on the product detail page after creation. The image with the lowest order index serves as the main thumbnail for product listings.
   *
   * @param connection
   * @param productId UUID of the product to add images to.
   * @param body Array of image URIs to add to the product. Each URI points to a hosted image file. Images are appended after existing images with automatically assigned order positions.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_platform_products to validate the
     *   product exists and belongs to the authenticated seller.
   *
   * 1. Validate product ownership: ensure ecommerce_platform_seller_profile_id matches the authenticated seller's profile.
   * 2. Query existing images for the product to determine the next available order_index values (current max + 1).
   * 3. For each image URI in the request array:
   *    - Generate UUID for new record
   *    - Create ecommerce_platform_product_images row with product_id, uri, calculated order_index
   *    - Use database transaction to ensure atomic creation of all images
   * 4. Create snapshot entry in ecommerce_platform_snapshots recording the product image modifications.
   * 5. Return all created image records including their assigned IDs and order indices.
   *
   * Error handling:
   * - 404 if product not found
   * - 403 if seller does not own product
   * - 400 if URI array is empty or contains invalid URIs
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommercePlatformProductImage.ICreate,
  ): Promise<IEcommercePlatformProductImage> {
    try {
      return await postEcommercePlatformSellerProductsProductIdImages({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product image's display order and/or image URL. Sellers can modify the order position to control which image appears as the thumbnail, or replace the image file reference.
   *
   * The order_index determines the display sequence, with lower values appearing first. When the order changes, the thumbnail designation automatically updates to the image with the lowest order value.
   *
   * Only the product's owner can update its images. The product must exist and not be deleted for the operation to succeed.
   *
   * @param connection
   * @param productId The product identifier (global scope)
   * @param imageId The product image identifier (scoped to product)
   * @param body Update payload containing the product image properties to modify. Provide order_index to change display position, or uri to replace the image file reference.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_platform_product_images table by
     *   id matching the imageId parameter.
   *
   * Verify the image's ecommerce_platform_product_id matches the productId path parameter.
   *
   * Verify the parent product belongs to the authenticated seller by joining with ecommerce_platform_products on the productId.
   *
   * Update the allowed fields: order_index and/or uri.
   *
   * Update the updated_at timestamp to current time.
   *
   * Enforce @@unique([ecommerce_platform_product_id, order_index]) constraint - reject update if the new order_index already exists for another image of the same product.
   *
   * Return the updated image record.
   *
   * Handle edge cases:
   * - Return 404 if imageId doesn't exist or doesn't belong to productId
   * - Return 403 if the product doesn't belong to the authenticated seller
   * - Return 409 if order_index conflicts with existing image
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":imageId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommercePlatformProductImage.IUpdate,
  ): Promise<IEcommercePlatformProductImage> {
    try {
      return await putEcommercePlatformSellerProductsProductIdImagesImageId({
        seller,
        productId,
        imageId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Deletes a specific product image by soft-deleting it from the product's image collection.
   *
   * When the deleted image is the main thumbnail, the system automatically designates the next available image (with the lowest order_index among non-deleted images) as the new thumbnail. If the last remaining image is deleted, the product will display without images.
   *
   * Only sellers who own the product or administrators can perform this operation. Image deletion is immediately reflected in all product displays, including search results and category listings.
   *
   * @param connection
   * @param productId UUID of the product that owns the image to be deleted.
   * @param imageId UUID of the product image to be soft-deleted.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Soft-delete the product image record by setting
     *   deleted_at to the current timestamp.
   *
   * 1. Validate the product exists and is not deleted (deleted_at IS NULL).
   * 2. Validate the image exists, belongs to the specified product, and is not already deleted.
   * 3. Check authorization: the authenticated user must be either the product's owner seller or an administrator.
   * 4. Before deletion, check if the image being deleted is the current thumbnail (has the lowest order_index among non-deleted images for this product).
   * 5. If the image is the thumbnail, find the next available non-deleted image with the lowest order_index for this product. This image will become the new thumbnail (no explicit update needed as thumbnail is derived from lowest order_index).
   * 6. Set deleted_at = NOW() on the target image record.
   * 7. Return 204 No Content on success.
   *
   * Error conditions:
   * - 404 if productId does not exist, is deleted, or imageId does not exist or does not belong to the product.
   * - 403 if the user is not the product owner and not an administrator.
   * - 409 if the image is already soft-deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":imageId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommercePlatformSellerProductsProductIdImagesImageId({
        seller,
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
