import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformSnapshot } from "../../../../../api/structures/IEcommercePlatformSnapshot";
import { IEcommercePlatformSnapshotProduct } from "../../../../../api/structures/IEcommercePlatformSnapshotProduct";
import { IPageIEcommercePlatformSnapshot } from "../../../../../api/structures/IPageIEcommercePlatformSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommercePlatformSellerProductsProductIdSnapshotsSnapshotId } from "../../../../../providers/getEcommercePlatformSellerProductsProductIdSnapshotsSnapshotId";
import { patchEcommercePlatformSellerProductsProductIdSnapshots } from "../../../../../providers/patchEcommercePlatformSellerProductsProductIdSnapshots";

@Controller("/ecommercePlatform/seller/products/:productId/snapshots")
export class EcommerceplatformSellerProductsSnapshotsController {
  /**
   * Retrieve a paginated list of all edit snapshots for a specific product.
   *
   * Snapshots are immutable historical records automatically generated whenever a seller edits a product, capturing the complete state of the product's name, description, category assignment, and base price before each modification. This endpoint supports filtering and pagination for browsing the change history of a product.
   *
   * Only the product's owning seller and platform administrators can access snapshots. Snapshots remain accessible even after the product has been soft-deleted.
   *
   * @param connection
   * @param productId UUID of the product whose edit snapshots are being retrieved.
   * @param body Search and pagination criteria for filtering product edit snapshots, including optional date range and text search parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_platform_snapshots joined with
     *   ecommerce_platform_snapshot_products where entity_type = 'product' and
     *   ecommerce_platform_product_id equals the productId path parameter.
   *
   * Join ecommerce_platform_snapshots (header) with ecommerce_platform_snapshot_products (details) on ecommerce_platform_snapshot_id to retrieve both the snapshot timestamp and the product-specific captured fields.
   *
   * Apply search filters from the request body:
   * - Optional date range filter on snapshot created_at
   * - Optional text search on name_current or description_current
   *
   * Enforce authorization: verify the authenticated user is either the product's owning seller (via join through ecommerce_platform_products → ecommerce_platform_seller_profile_id) or an administrator.
   *
   * Return cursor-based or offset-based pagination wrapping snapshot summary records.
   *
   * Include snapshot header fields (id, entity_type, created_at) and product-specific snapshot fields (name_previous, name_current, description_previous, description_current, category_id_current).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommercePlatformSnapshot.IRequest,
  ): Promise<IPageIEcommercePlatformSnapshot.ISummary> {
    try {
      return await patchEcommercePlatformSellerProductsProductIdSnapshots({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific product snapshot record.
   *
   * Returns the historical state of a product listing captured before and after a modification event. Provides audit trail details including name changes, description updates, category reassignments, and snapshot metadata. Accessible by sellers who own the product and administrators for platform oversight.
   *
   * Snapshots are immutable records preserving product history for dispute resolution and data recovery.
   *
   * @param connection
   * @param productId UUID of the product whose snapshot is being retrieved.
   * @param snapshotId UUID of the specific snapshot record to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query `ecommerce_platform_snapshot_products`
     *   joined with `ecommerce_platform_snapshots` on
     *   `ecommerce_platform_snapshot_products.ecommerce_platform_snapshot_id =
     *   ecommerce_platform_snapshots.id`.
   *
   * Filter by:
   * - `ecommerce_platform_snapshot_products.ecommerce_platform_product_id` matches `{productId}` path parameter.
   * - `ecommerce_platform_snapshot_products.id` matches `{snapshotId}` path parameter.
   *
   * Access Control:
   * - Seller can view if `ecommerce_platform_products.ecommerce_platform_seller_profile_id` matches the authenticated seller's profile ID.
   * - Admin can view any product snapshot.
   *
   * Return complete snapshot record including header metadata (`entity_type`, `created_at`) and product-specific state (`name_previous`, `name_current`, `description_previous`, `description_current`, `category_id_current`).
   *
   * Handle 404 if no matching record exists or access is denied. Snapshots are read-only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformSnapshotProduct> {
    try {
      return await getEcommercePlatformSellerProductsProductIdSnapshotsSnapshotId(
        {
          seller,
          productId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
