import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommercePlatformSellerDashboard } from "../../../../api/structures/IEcommercePlatformSellerDashboard";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommercePlatformSellerDashboard } from "../../../../providers/getEcommercePlatformSellerDashboard";

@Controller("/ecommercePlatform/seller/dashboard")
export class EcommerceplatformSellerDashboardController {
  /**
   * Retrieves the seller's dashboard overview containing their current shop status, approval details, and performance statistics.
   *
   * This endpoint returns the seller's current registration status (pending, approved, or rejected) along with the rejection reason if rejected. It aggregates business metrics including the total number of products, total order items, and counts of pending cancellation and refund requests. Shop profile information including name, description, and logo is also included.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Retrieve dashboard data for the currently
     *   authenticated seller. 1. Query `ecommerce_platform_sellers` for
     *   `approval_status` and `rejection_reason`. 2. Query
     *   `ecommerce_platform_seller_profiles` for `shop_name`,
     *   `shop_description`, and `logo_image_uri`. 3. Aggregate `total_products`
     *   by counting active records in `ecommerce_platform_products` linked to
     *   the seller's profile. 4. Aggregate `total_order_items` by counting
     *   records in `ecommerce_platform_order_items` linked to product variants
     *   owned by the seller. 5. Aggregate `total_pending_cancellation_requests`
     *   by counting records in `ecommerce_platform_cancellation_requests` with
     *   status 'pending' for the seller's order items. 6. Aggregate
     *   `total_pending_refund_requests` by counting records in
     *   `ecommerce_platform_refund_requests` with status 'pending' for the
     *   seller's order items. Return the result as
     *   `IEcommercePlatformSellerDashboard`.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IEcommercePlatformSellerDashboard> {
    try {
      return await getEcommercePlatformSellerDashboard({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
