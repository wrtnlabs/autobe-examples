import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformShipmentItem } from "../../../../../api/structures/IEcommercePlatformShipmentItem";
import { IPageIEcommercePlatformShipmentItem } from "../../../../../api/structures/IPageIEcommercePlatformShipmentItem";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommercePlatformSellerShipmentsShipmentIdItemsShipmentItemId } from "../../../../../providers/getEcommercePlatformSellerShipmentsShipmentIdItemsShipmentItemId";
import { patchEcommercePlatformSellerShipmentsShipmentIdItems } from "../../../../../providers/patchEcommercePlatformSellerShipmentsShipmentIdItems";
import { postEcommercePlatformSellerShipmentsShipmentIdItems } from "../../../../../providers/postEcommercePlatformSellerShipmentsShipmentIdItems";

@Controller("/ecommercePlatform/seller/shipments/:shipmentId/items")
export class EcommerceplatformSellerShipmentsItemsController {
  /**
   * Adds one or more order items to an existing shipment, bundling them into a single physical package for combined tracking.
   *
   * All items in the shipment share the same carrier name, tracking number, and delivery confirmation status. Upon assignment, each order item's status transitions from 'paid' to 'shipped'.
   *
   * Order items must belong to the same seller as the shipment, must be in 'paid' status, and cannot already be assigned to another shipment. Each order item can only belong to one shipment package. The operation is transactional — all items are added or none are.
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment to add order items to.
   * @param body Collection of order item identifiers to add to the existing shipment. Each order item must belong to the same seller as the shipment, must be in 'paid' status, and must not already be assigned to another shipment.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification 1. Retrieve the shipment record from
     *   ecommerce_platform_shipments by the shipmentId path parameter. Verify
     *   the shipment exists, is not soft-deleted (deleted_at IS NULL), and
     *   belongs to the authenticated seller's account.
   *
   * 2. Query ecommerce_platform_order_items for the order item IDs provided in the request body. For each order item:
   *    - Verify the item's product variant belongs to the same seller as the shipment (trace via product_variant → product → seller relationship).
   *    - Verify the item's status is 'paid' (not 'shipped', 'delivered', 'cancelled', or 'refunded').
   *    - Verify the item is not already assigned to another shipment by checking ecommerce_platform_shipment_items for an existing record with this order_item_id.
   *
   * 3. If all validations pass, create ecommerce_platform_shipment_items junction records within a single database transaction:
   *    - For each order item, INSERT a new record with shipment_id (from path), order_item_id (from request), and timestamps (created_at/updated_at).
   *    - UPDATE each order item's status from 'paid' to 'shipped'.
   *    - Set the shipment's shipped_at timestamp to current time if not already set.
   *
   * 4. If any validation fails, abort the entire transaction and return an error with details about which items failed validation.
   *
   * 5. Return the created shipment item records.
   *
   * Edge cases:
   * - Reject empty orderItemIds array.
   * - Reject if any item belongs to a different seller.
   * - Reject if any item is already in 'shipped', 'delivered', 'cancelled', or 'refunded' status.
   * - Reject if any item is already assigned to an existing shipment.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommercePlatformShipmentItem.ICreate,
  ): Promise<IEcommercePlatformShipmentItem> {
    try {
      return await postEcommercePlatformSellerShipmentsShipmentIdItems({
        seller,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of order items contained in a specific shipment package.
   *
   * This endpoint returns shipment item records that map order items to their parent shipment, sharing carrier name, tracking number, and shipping date. Each shipment is created by a seller to bundle multiple order items from the same seller into a single physical package for delivery.
   *
   * The response includes item identifiers, order item references, and timestamps. Customers use this to track what items are included in a shipment they are waiting for. Sellers use this to verify which items are grouped in a shipment they dispatched.
   *
   * @param connection
   * @param shipmentId UUID identifier of the shipment package (scoped to global shipment registry).
   * @param body Search criteria including pagination parameters (page number, page size) for retrieving shipment items within the specified shipment package.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_platform_shipment_items table
     *   filtered by ecommerce_platform_shipment_id equal to the provided
     *   shipmentId parameter.
   *
   * Apply pagination from request body (page number, page size). Count total matching records for pagination metadata.
   *
   * Optionally join with ecommerce_platform_order_items on ecommerce_platform_order_item_id to include order item details (quantity, price, status).
   *
   * Optionally join with ecommerce_platform_product_variants through order items for variant information.
   *
   * Return paginated IPageIEcommercePlatformShipmentItem.ISummary containing matched shipment item records with summary fields.
   *
   * Handle edge case where shipmentId does not exist by returning empty paginated result set (no items match).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommercePlatformShipmentItem.IRequest,
  ): Promise<IPageIEcommercePlatformShipmentItem.ISummary> {
    try {
      return await patchEcommercePlatformSellerShipmentsShipmentIdItems({
        seller,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific shipment item record that associates an order item with its corresponding shipment package.
   *
   * Returns the junction record details including both foreign key references to the parent shipment and order item, along with audit timestamps tracking when the association was created and last modified. This endpoint enables customers to view the specific order item's inclusion in a shipment and sellers to verify a particular item's assignment to a delivery package.
   *
   * Returns 404 NOT FOUND when the shipment item record does not exist, or when the shipment item does not belong to the specified parent shipment as validated by the ecommerce_platform_shipment_id foreign key constraint.
   *
   * @param connection
   * @param shipmentId UUID of the parent shipment package that contains this shipment item association.
   * @param shipmentItemId UUID of the specific shipment item record that links an order item to a shipment package.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query the ecommerce_platform_shipment_items table
     *   filtering by the primary key id matching the shipmentItemId path
     *   parameter.
   *
   * Validate that the found record's ecommerce_platform_shipment_id foreign key matches the shipmentId path parameter to ensure the shipment item belongs to the specified parent shipment. Return 404 NOT FOUND if no record matches or if the parent-child relationship validation fails.
   *
   * Verify the referenced shipment exists in ecommerce_platform_shipments table by checking the ecommerce_platform_shipment_id matches a valid shipment id.
   *
   * Verify the referenced order item exists in ecommerce_platform_order_items table by checking the ecommerce_platform_order_item_id matches a valid order item id.
   *
   * Return the complete shipment item entity containing all fields: id, ecommerce_platform_shipment_id, ecommerce_platform_order_item_id, created_at, updated_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentItemId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedParam("shipmentItemId")
    shipmentItemId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformShipmentItem> {
    try {
      return await getEcommercePlatformSellerShipmentsShipmentIdItemsShipmentItemId(
        {
          seller,
          shipmentId,
          shipmentItemId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
