import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformSellerProfile } from "../../../../../api/structures/IEcommercePlatformSellerProfile";
import { IPageIEcommercePlatformSellerProfile } from "../../../../../api/structures/IPageIEcommercePlatformSellerProfile";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommercePlatformAdminSellersSellerIdProfilesProfileId } from "../../../../../providers/getEcommercePlatformAdminSellersSellerIdProfilesProfileId";
import { patchEcommercePlatformAdminSellersSellerIdProfiles } from "../../../../../providers/patchEcommercePlatformAdminSellersSellerIdProfiles";

@Controller("/ecommercePlatform/admin/sellers/:sellerId/profiles")
export class EcommerceplatformAdminSellersProfilesController {
  /**
   * Search and filter seller profiles for a given seller with pagination.
   *
   * This endpoint retrieves seller profile records associated with a specific seller, supporting search filters on shop name, shop description, and other profile attributes. Results are returned in a paginated format suitable for list displays and administrative viewing.
   *
   * @param connection
   * @param sellerId UUID of the seller account to search profiles for. (global scope)
   * @param body Search criteria for seller profile filtering including shop name, shop description, and date range filters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query ecommerce_platform_seller_profiles table
     *   filtered by seller_id matching the sellerId path parameter. Apply
     *   optional search filters from the request body on shop_name (partial
     *   match), shop_description (partial match), logo_image_uri (partial
     *   match), and date ranges on created_at/updated_at. Exclude soft-deleted
     *   records where deleted_at is not null. Join with
     *   ecommerce_platform_sellers to verify seller existence. Apply pagination
     *   using cursor-based or offset-based pagination as configured. Return
     *   paginated summary results even though each seller has exactly one
     *   profile due to @@unique([seller_id]) constraint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommercePlatformSellerProfile.IRequest,
  ): Promise<IPageIEcommercePlatformSellerProfile.ISummary> {
    try {
      return await patchEcommercePlatformAdminSellersSellerIdProfiles({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the full details of a specific seller profile by seller ID and profile ID.
   *
   * This endpoint returns the complete seller profile information including the shop name, shop description, and logo image URI. Seller profiles represent the public-facing merchant identity displayed across product listings, search results, and dedicated seller storefront pages.
   *
   * Customers can access seller profiles to learn about the merchant selling a product. The profile information remains visible even when a seller is suspended, but becomes unavailable if the seller account has been deleted. All profile modifications are automatically tracked via immutable snapshots for audit and dispute resolution purposes.
   *
   * @param connection
   * @param sellerId UUID of the seller account that owns this profile.
   * @param profileId UUID of the seller profile to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query ecommerce_platform_seller_profiles table by
     *   profile id.
   *
   * 1. Validate that the sellerId path parameter corresponds to a valid, non-deleted seller in ecommerce_platform_sellers.
   * 2. Verify the profileId matches the id in ecommerce_platform_seller_profiles.
   * 3. Confirm the seller_id foreign key in ecommerce_platform_seller_profiles matches the provided sellerId to ensure the profile belongs to the specified seller.
   * 4. Return the full profile record including id, seller_id, shop_name, shop_description, logo_image_uri, created_at, updated_at, and deleted_at.
   * 5. If the seller profile has been soft-deleted (deleted_at is not null), return a 404 Not Found response indicating the seller profile is no longer available.
   * 6. If the profileId does not match any existing profile or belongs to a different seller, return 404 Not Found.
   * 7. Public profile data (shop_name, shop_description, logo_image_uri) is visible to customers even if the seller is suspended. Only deleted profiles are hidden.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":profileId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("profileId")
    profileId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformSellerProfile> {
    try {
      return await getEcommercePlatformAdminSellersSellerIdProfilesProfileId({
        admin,
        sellerId,
        profileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
