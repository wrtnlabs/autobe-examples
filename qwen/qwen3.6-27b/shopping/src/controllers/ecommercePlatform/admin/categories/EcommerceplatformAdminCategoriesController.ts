import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformCategory } from "../../../../api/structures/IEcommercePlatformCategory";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteEcommercePlatformAdminCategoriesCategoryId } from "../../../../providers/deleteEcommercePlatformAdminCategoriesCategoryId";
import { postEcommercePlatformAdminCategories } from "../../../../providers/postEcommercePlatformAdminCategories";
import { putEcommercePlatformAdminCategoriesCategoryId } from "../../../../providers/putEcommercePlatformAdminCategoriesCategoryId";

@Controller("/ecommercePlatform/admin/categories")
export class EcommerceplatformAdminCategoriesController {
  /**
   * Create a new product category with a name and description. Administrators can create both top-level categories and subcategories with one level of nesting. The category name must be unique within the same parent scope, and the description must be non-empty. Subcategories can only be created under top-level categories.
   *
   * @param connection
   * @param body Category creation payload including required name and description fields, and optional parent category identifier for subcategory creation.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification 1. Validate the authenticated user has
     *   administrator privileges; reject non-admin requests.
   *
   * 2. Validate name is present and not empty/whitespace-only.
   *
   * 3. Validate description is present and not empty/whitespace-only.
   *
   * 4. If parentEcommercePlatformCategoryId is provided:
   *    - Verify the parent category exists and is active (deleted_at is null)
   *    - Verify the parent category is a root category (its parent_ecommerce_platform_category_id is null)
   *    - If parent is a subcategory, reject with error: nesting limit exceeded
   *
   * 5. Validate name uniqueness within same parent scope:
   *    - Check no existing active category has the same name with the same parent_ecommerce_platform_category_id
   *    - Exclude soft-deleted categories (deleted_at is not null) from uniqueness check
   *    - Reject if duplicate found
   *
   * 6. Insert new record into ecommerce_platform_categories:
   *    - id: auto-generated UUID
   *    - name: from request
   *    - description: from request
   *    - parent_ecommerce_platform_category_id: from request (null if root category)
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   *    - deleted_at: null
   *
   * 7. Return the complete created category record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommercePlatformCategory.ICreate,
  ): Promise<IEcommercePlatformCategory> {
    try {
      return await postEcommercePlatformAdminCategories({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing category's name and description.
   *
   * This endpoint allows administrators to modify category details. Category names must remain unique within the same parent category scope. Both name and description fields must be non-empty when provided. The one-level nesting hierarchy constraint is enforced—subcategories cannot have their own subcategories.
   *
   * Administrators only have permission to edit categories. Requests from customers or sellers will be rejected with an authorization error. If the specified category does not exist or has been soft-deleted, a 404 error is returned.
   *
   * @param connection
   * @param categoryId UUID identifier of the category to update (global scope)
   * @param body Updated category details including name and description fields. Both fields are optional; only provided fields will be updated.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query ecommerce_platform_categories table by id
     *   to retrieve the existing category.
   *
   * Validate that the category exists and is not soft-deleted (deleted_at IS NULL).
   *
   * Apply the update:
   * - Optional name field: validate non-empty string, trim whitespace. Enforce unique constraint by checking @@unique([name, parent_ecommerce_platform_category_id]) does not conflict with another category under the same parent.
   * - Optional description field: validate non-empty string.
   * - Updated category name or description must differ from current values or return success with unchanged data.
   *
   * Update the record with provided fields and set updated_at to current timestamp.
   *
   * Return the updated category entity including id, name, description, parent reference, created_at, updated_at, and deleted_at fields.
   *
   * Edge cases:
   * - Return 404 if category id not found or deleted_at is not null
   * - Return 409 if the proposed name already exists as a sibling under the same parent
   * - Return 400 if name or description is blank/whitespace-only when provided
   * - Authorization middleware must enforce admin-only access
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommercePlatformCategory.IUpdate,
  ): Promise<IEcommercePlatformCategory> {
    try {
      return await putEcommercePlatformAdminCategoriesCategoryId({
        admin,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft deletes a specified category from the platform.
   *
   * When a category is deleted, it is removed from customer browsing lists and search filters, ensuring deleted items do not appear in dropdown selectors or filter options. If the deleted category is a root category, all associated subcategories are also soft-deleted. Products previously linked to the deleted category or its subcategories are dissociated, rendering them uncategorized while preserving all product data. Only platform administrators possess the authority to perform this operation.
   *
   * @param connection
   * @param categoryId The unique identifier of the category to delete.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the `ecommerce_platform_categories` table
     *   by `{categoryId}`. Validate that the requesting actor possesses
     *   administrative privileges. If valid, update the target category record
     *   by setting the `deleted_at` timestamp to the current time. If the
     *   category is a root category (`parent_ecommerce_platform_category_id` is
     *   NULL), execute a cascading soft delete on all directly linked
     *   subcategories by setting their `deleted_at` timestamps. For all
     *   products associated with either the target category or its cascaded
     *   subcategories, update the product records to dissociate them from any
     *   category assignment, transitioning them to an uncategorized state.
     *   Ensure the deleted category and its subcategories are excluded from all
     *   subsequent customer browsing and filtering queries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommercePlatformAdminCategoriesCategoryId({
        admin,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
