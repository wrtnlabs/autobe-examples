import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformSnapshotReview } from "../../../../api/structures/IEcommercePlatformSnapshotReview";
import { IPageIEcommercePlatformSnapshotReview } from "../../../../api/structures/IPageIEcommercePlatformSnapshotReview";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommercePlatformAdminSnapshotReviewsSnapshotReviewId } from "../../../../providers/getEcommercePlatformAdminSnapshotReviewsSnapshotReviewId";
import { patchEcommercePlatformAdminSnapshotReviews } from "../../../../providers/patchEcommercePlatformAdminSnapshotReviews";

@Controller("/ecommercePlatform/admin/snapshot-reviews")
export class EcommerceplatformAdminSnapshot_reviewsController {
  /**
   * Search and filter review snapshot records with pagination support.
   *
   * Review snapshots are immutable audit trail entries automatically generated when customers edit or delete their reviews. Each snapshot preserves both the previous and current state of the review's star rating (1-5) and text content. These records provide verifiable historical data for dispute resolution and platform oversight.
   *
   * Snapshots are sorted newest-first by default. Filters are available for review ID, entity type, date ranges, and content matching. Only read access is provided as snapshots are system-managed immutable records that cannot be modified or deleted by any user.
   *
   * @param connection
   * @param body Search criteria for filtering review snapshots including review ID, date ranges, and rating/content filters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query ecommerce_platform_snapshot_reviews joined
     *   with ecommerce_platform_snapshots to retrieve review snapshot records.
   *
   * Join conditions:
   * - ecommerce_platform_snapshot_reviews.ecommerce_platform_snapshot_id = ecommerce_platform_snapshots.id
   * - Filter ecommerce_platform_snapshots.entity_type = 'review'
   *
   * Apply search filters from request body on:
   * - reviewId: filter by ecommerce_platform_snapshot_reviews.ecommerce_platform_review_id
   * - date range: filter by ecommerce_platform_snapshots.created_at
   * - Content/rating filters: previous_rating, new_rating, previous_content, new_content
   *
   * Return cursor-based pagination using IPageIEcommercePlatformSnapshotReview.ISummary.
   * Default sort: created_at descending (newest first).
   *
   * Snapshots are immutable - no write operations allowed. This is a read-only endpoint accessible by administrators for audit and dispute resolution purposes.
   *
   * Handle cases where referenced reviews may have been deleted (customer deleted their own review).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommercePlatformSnapshotReview.IRequest,
  ): Promise<IPageIEcommercePlatformSnapshotReview.ISummary> {
    try {
      return await patchEcommercePlatformAdminSnapshotReviews({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Return a single immutable snapshot review record capturing the before and after state of a review modification. The response includes the previous star rating (1-5) and text content before any modifications were applied, as well as the new rating and content after the modification. The record also contains the related snapshot header id and review id along with the created and updated timestamps.
   *
   * @param connection
   * @param snapshotReviewId UUID identifier of the snapshot review record.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the ecommerce_platform_snapshot_reviews
     *   table filtered by id matching the provided snapshotReviewId path
     *   parameter. The query retrieves the full snapshot record including: -
     *   id: UUID primary key - ecommerce_platform_snapshot_id: Foreign key
     *   reference to ecommerce_platform_snapshots -
     *   ecommerce_platform_review_id: Foreign key reference to
     *   ecommerce_platform_reviews - previous_rating: Integer representing the
     *   star rating before the modification (null for initial creation) -
     *   previous_content: String text content before the modification (null for
     *   initial creation) - new_rating: Integer representing the star rating
     *   after the modification - new_content: String text content after the
     *   modification - created_at: DateTime snapshot creation timestamp -
     *   updated_at: DateTime snapshot update timestamp
   *
   * This snapshot review record is immutable once created and serves as an audit trail for review edits and deletions. The operation returns a 404 if no matching snapshot review record exists.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotReviewId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("snapshotReviewId")
    snapshotReviewId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformSnapshotReview> {
    try {
      return await getEcommercePlatformAdminSnapshotReviewsSnapshotReviewId({
        admin,
        snapshotReviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
