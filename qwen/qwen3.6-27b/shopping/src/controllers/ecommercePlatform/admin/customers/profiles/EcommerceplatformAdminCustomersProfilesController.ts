import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformCustomerProfile } from "../../../../../api/structures/IEcommercePlatformCustomerProfile";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommercePlatformAdminCustomersCustomerIdProfilesProfileId } from "../../../../../providers/getEcommercePlatformAdminCustomersCustomerIdProfilesProfileId";
import { putEcommercePlatformAdminCustomersCustomerIdProfiles } from "../../../../../providers/putEcommercePlatformAdminCustomersCustomerIdProfiles";

@Controller("/ecommercePlatform/admin/customers/:customerId/profiles")
export class EcommerceplatformAdminCustomersProfilesController {
  /**
   * Update the profile information for a specific customer, allowing changes to display name and phone number.
   *
   * Customers can modify their display name, which appears publicly on reviews, order confirmations, and other customer-facing contexts. The display name is mandatory and cannot be set to empty; it serves as the customer's visible identity on the platform distinct from their login email. The phone number is optional and used by sellers for delivery coordination; it can be set, changed, or removed by setting it to null.
   *
   * When profile changes occur, the system automatically creates an immutable snapshot recording the previous and current values along with the timestamp of the change. This audit trail is retained for platform oversight and cannot be deleted by sellers or administrators.
   *
   * Only the profile owner can perform updates. Customers can view their own profile information and edit their display name and phone number (section 537). Returns the updated profile with all current field values and metadata.
   *
   * @param connection
   * @param customerId UUID of the customer account whose profile is being updated.
   * @param body Profile fields to update. Display name is required and must be non-empty. Phone number is optional and can be set to null to remove it.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification 1. Resolve the customer record from
     *   ecommerce_platform_customers using the customerId path parameter
     *   (UUID).
   *
   * 2. Validate the customer exists, is not soft-deleted (deleted_at IS NULL), and is not banned (is_banned = false) to prevent banned users from updating profiles. If not found or deleted, return 404.
   *
   * 3. Verify the requesting user is authorized to update this profile - must be the profile owner (authenticated customer ID matches customerId). Return 403 if unauthorized.
   *
   * 4. Query the associated profile from ecommerce_platform_customer_profiles using ecommerce_platform_customer_id = customerId. This is a one-to-one relationship enforced by unique constraint (@@unique([ecommerce_platform_customer_id])). Return 404 if profile not found.
   *
   * 5. Validate the request body:
   *    - display_name: must be present and non-empty (length > 0). Reject with 400 if empty or missing per section 419 validation rules.
   *    - phone_number: optional, can be null to remove the phone number
   *
   * 6. Capture the previous state of editable fields (display_name, phone_number) for snapshot creation per section 429.
   *
   * 7. Apply the update to the profile record in a single transaction:
   *    - Set display_name to the validated new value
   *    - Set phone_number to the new value (or null)
   *    - Update updated_at timestamp to current time (UTC)
   *
   * 8. Create an immutable snapshot automatically:
   *    - Record in ecommerce_platform_snapshots with polymorphic subtype linking to ecommerce_platform_snapshot_customer_profiles
   *    - Store: entity type identifier, entity record ID (profile id), timestamp of change
   *    - Store before values (previous display_name, phone_number)
   *    - Store after values (new display_name, phone_number)
   *    - Snapshots are immutable and cannot be deleted per section 429
   *
   * 9. Return the complete updated profile record including all fields (id, ecommerce_platform_customer_id, display_name, phone_number, created_at, updated_at).
   *
   * Error cases:
   * - 404: customer not found or soft-deleted
   * - 404: profile not found (should not occur normally due to one-to-one relationship constraint)
   * - 400: display_name is empty or missing
   * - 403: unauthorized user attempting to update profile
   * - 403: banned customer attempting to update profile
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommercePlatformCustomerProfile.IUpdate,
  ): Promise<IEcommercePlatformCustomerProfile> {
    try {
      return await putEcommercePlatformAdminCustomersCustomerIdProfiles({
        admin,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single customer profile belonging to a specific customer account.
   *
   * Returns the customer profile entity, including the owner customer ID, display name, phone number, and timestamp fields. Customers can view their own profile information. Display name is publicly visible on review pages, order confirmations, and other customer-facing contexts on the platform.
   *
   * This endpoint requires proper authentication and authorization to ensure customers can only access their own profile information.
   *
   * Access Control:
   * - Customers can only view their own profile.
   * - Administrators can view any customer profile for platform oversight.
   * - The endpoint must validate ownership before returning profile details.
   *
   * @param connection
   * @param customerId UUID of the customer account that owns this profile.
   * @param profileId UUID of the customer profile record to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query ecommerce_platform_customer_profiles table
     *   joining with ecommerce_platform_customers to validate the profile
     *   belongs to the specified customer.
   *
   * Implementation Steps:
   * 1. Validate both customerId and profileId are provided as path parameters.
   * 2. Verify the profile exists in ecommerce_platform_customer_profiles with id = profileId.
   * 3. Confirm ownership by checking that the profile's ecommerce_platform_customer_id equals customerId.
   * 4. Check customer is_banned status and ensure deleted_at is null (not soft-deleted).
   * 5. Return the full profile record: id, ecommerce_platform_customer_id, display_name, phone_number, created_at, updated_at, deleted_at.
   * 6. If profile not found or ownership mismatch, return 404 Not Found.
   * 7. If the user accessing the profile is neither the owner nor an admin, return 403 Forbidden.
   *
   * Business Rules:
   * - Display name is required (non-empty) as per profile requirement validation.
   * - Phone number is optional and may be null.
   * - Profile persists independently when the customer account is soft-deleted.
   * - Access control: customers can only access their own profile; admins have broader access.
   * - The deleted_at field indicates a soft-deleted profile; handle appropriately per platform policy.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":profileId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("profileId")
    profileId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformCustomerProfile> {
    try {
      return await getEcommercePlatformAdminCustomersCustomerIdProfilesProfileId(
        {
          admin,
          customerId,
          profileId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
