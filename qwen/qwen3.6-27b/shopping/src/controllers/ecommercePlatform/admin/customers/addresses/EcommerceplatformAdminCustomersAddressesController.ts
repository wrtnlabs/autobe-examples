import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformShippingAddress } from "../../../../../api/structures/IEcommercePlatformShippingAddress";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommercePlatformAdminCustomersCustomerIdAddressesAddressId } from "../../../../../providers/getEcommercePlatformAdminCustomersCustomerIdAddressesAddressId";

@Controller(
  "/ecommercePlatform/admin/customers/:customerId/addresses/:addressId",
)
export class EcommerceplatformAdminCustomersAddressesController {
  /**
   * Retrieves a single shipping address for a specific customer. This endpoint returns detailed address information including recipient name, contact phone, complete geographic details, and default address designation. The address must belong to the specified customer or a 404 error is returned. This operation is used when a customer needs to view the details of a specific saved shipping address.
   *
   * @param connection
   * @param customerId Customer profile identifier. Must be a valid UUID of an existing customer profile.
   * @param addressId Shipping address identifier. Must be a valid UUID of an existing shipping address belonging to the specified customer.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query ecommerce_platform_shipping_addresses table
     *   where id = {addressId} and ecommerce_platform_customer_profile_id =
     *   {customerId}. Verify both the address exists and belongs to the
     *   specified customer. Return 404 if address not found or belongs to
     *   different customer. Check for soft-deleted addresses (deleted_at IS NOT
     *   NULL) and return 404 for deleted addresses. Return full address entity
     *   with all fields including is_default boolean flag.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformShippingAddress> {
    try {
      return await getEcommercePlatformAdminCustomersCustomerIdAddressesAddressId(
        {
          admin,
          customerId,
          addressId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
