import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformSnapshot } from "../../../../../../api/structures/IEcommercePlatformSnapshot";
import { IEcommercePlatformSnapshotVariant } from "../../../../../../api/structures/IEcommercePlatformSnapshotVariant";
import { IPageIEcommercePlatformSnapshotVariant } from "../../../../../../api/structures/IPageIEcommercePlatformSnapshotVariant";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { getEcommercePlatformAdminProductsProductIdVariantsVariantIdSnapshotsSnapshotId } from "../../../../../../providers/getEcommercePlatformAdminProductsProductIdVariantsVariantIdSnapshotsSnapshotId";
import { patchEcommercePlatformAdminProductsProductIdVariantsVariantIdSnapshots } from "../../../../../../providers/patchEcommercePlatformAdminProductsProductIdVariantsVariantIdSnapshots";

@Controller(
  "/ecommercePlatform/admin/products/:productId/variants/:variantId/snapshots",
)
export class EcommerceplatformAdminProductsVariantsSnapshotsController {
  /**
   * This endpoint allows users to search and list product variant snapshots for a specific product and variant. It returns a paginated list of snapshot records containing the SKU code, price, stock quantity, and timestamp at the point in time when the snapshot was created.
   *
   * Sellers can view snapshots of variants from their own products, while platform administrators have full access to any variant snapshot across the marketplace.
   *
   * Snapshots preserve the historical audit trail for product variants, enabling dispute resolution and data integrity checks.
   *
   * @param connection
   * @param productId UUID of the parent product, used to scope the variant snapshots to this specific product.
   * @param variantId UUID of the specific product variant whose snapshots are being requested, scoped to the parent product.
   * @param body Search criteria including date ranges for snapshot creation times, SKU code, price, and stock quantity, as well as pagination parameters like cursor and page size.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the `ecommerce_platform_snapshot_variants`
     *   table, filtering by `ecommerce_platform_product_variant_id` matching
     *   the `variantId` path parameter.
   *
   * Validate that `variantId` actually belongs to the `productId` path parameter by verifying `ecommerce_platform_product_id` matches `productId` in `ecommerce_platform_product_variants`.
   *
   * Apply search filters from the request body on fields like `created_at` (date ranges), `sku_code`, `price`, and `stock_quantity`.
   *
   * Return results as a paginated list using `IPageIEcommercePlatformSnapshotVariant.ISummary`.
   *
   * Authorization: Verify that the authenticated seller owns the product (via `seller_profile_id`), while administrators have unrestricted access.
   *
   * Join `ecommerce_platform_snapshots` to filter `entity_type = 'product_variant'`.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommercePlatformSnapshotVariant.IRequest,
  ): Promise<IPageIEcommercePlatformSnapshotVariant.ISummary> {
    try {
      return await patchEcommercePlatformAdminProductsProductIdVariantsVariantIdSnapshots(
        {
          admin,
          productId,
          variantId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Complete snapshot record containing the variant's state at the time of capture, including SKU code, price, stock quantity, and all normalized option key-value pairs.
   *
   * @param connection
   * @param productId UUID identifying the parent product of the variant being snapshotted.
   * @param variantId UUID identifying the specific product variant that was snapshotted.
   * @param snapshotId UUID identifying the specific snapshot record to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query ecommerce_platform_snapshots table for the
     *   snapshotId, filtering by entity_type = 'product_variant'.
   *
   * Join with ecommerce_platform_snapshot_variants to retrieve variant-specific snapshot data including sku_code, price, stock_quantity at the time of the snapshot.
   *
   * Join with ecommerce_platform_snapshot_variant_options to retrieve all normalized option key-value pairs associated with this variant snapshot.
   *
   * Validate that the productId in the path corresponds to the parent product of the variant (verify ecommerce_platform_product_variants.ecommerce_platform_product_id matches productId).
   *
   * Validate that the variantId in the path corresponds to ecommerce_platform_product_variants.id.
   *
   * Return 404 if the snapshot does not exist or does not belong to the specified variant.
   *
   * Return the complete snapshot record with all nested option values.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformSnapshot.IInvert> {
    try {
      return await getEcommercePlatformAdminProductsProductIdVariantsVariantIdSnapshotsSnapshotId(
        {
          admin,
          productId,
          variantId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
