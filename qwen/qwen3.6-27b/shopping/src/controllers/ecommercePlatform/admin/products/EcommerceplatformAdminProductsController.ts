import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteEcommercePlatformAdminProductsProductId } from "../../../../providers/deleteEcommercePlatformAdminProductsProductId";

@Controller("/ecommercePlatform/admin/products/:productId")
export class EcommerceplatformAdminProductsController {
  /**
   * Soft-delete a product listing by removing it from search results and category navigation while preserving the record for order history integrity.
   *
   * This operation permanently removes the product from public-facing views (search, category browsing) and simultaneously removes all associated variants. Product data is preserved internally through the soft-delete mechanism (deleted_at timestamp) to maintain financial and order history records.
   *
   * Only the seller who owns the product can delete it. Authorization is enforced before the operation proceeds.
   *
   * Deletion is blocked if any of the following conditions exist on the product's variants:
   *
   * - Order items with active status (paid or shipped) that require fulfillment
   * - Pending cancellation requests awaiting seller response
   * - Pending refund requests awaiting seller response
   *
   * To enable product deletion, resolve all pending transactions first. Customers must complete their orders or sellers must respond to cancellation/refund requests before the product can be removed.
   *
   * @param connection
   * @param productId UUID identifier of the product to erase from the marketplace.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Step 1 - Load Product: Query
     *   ecommerce_platform_products by productId (id field). Return 404 Not
     *   Found if not exists.
   *
   * Step 2 - Authorization: Verify authenticated actor is the product owner.
   * - Actor must be the seller whose profile_id matches ecommerce_platform_seller_profile_id
   * - Return 403 Forbidden if unauthorized
   *
   * Step 3 - Deletion Restriction Checks:
   * - Load all variants where ecommerce_platform_product_id = productId
   * - For each variant, check if ANY order_items exist with status IN ('paid', 'shipped')
   *   → If found, return 409 Conflict with message about active orders blocking deletion
   * - For each variant, check if ANY order_items have cancellation_requests with status = 'pending'
   *   → If found, return 409 Conflict with message about pending cancellation requests blocking deletion
   * - For each variant, check if ANY order_items have refund_requests with status = 'pending'
   *   → If found, return 409 Conflict with message about pending refund requests blocking deletion
   *
   * Step 4 - Execute Soft Delete:
   * - Set deleted_at = CURRENT_TIMESTAMP on product record
   * - Soft-delete all variants by setting deleted_at = CURRENT_TIMESTAMP on each
   * - Use database transaction to ensure atomicity
   *
   * Step 5 - Response: Return null body with 200 OK.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommercePlatformAdminProductsProductId({
        admin,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
