import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformAdminAuditLog } from "../../../../api/structures/IEcommercePlatformAdminAuditLog";
import { IPageIEcommercePlatformAdminAuditLog } from "../../../../api/structures/IPageIEcommercePlatformAdminAuditLog";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommercePlatformAdminAuditLogsLogId } from "../../../../providers/getEcommercePlatformAdminAuditLogsLogId";
import { patchEcommercePlatformAdminAuditLogs } from "../../../../providers/patchEcommercePlatformAdminAuditLogs";

@Controller("/ecommercePlatform/admin/audit-logs")
export class EcommerceplatformAdminAudit_logsController {
  /**
   * Search and list administrative audit log records with filtering support.
   *
   * This endpoint retrieves the platform's administrative audit trail, which captures all governance actions including user bans, seller approvals, category management, and order interventions. Audit logs are immutable append-only records that serve as the definitive source for compliance verification and dispute resolution.
   *
   * Administrators can filter results by action type, target entity type, specific entity, performing administrator, and date ranges. Results are returned in paginated format optimized for administrative dashboard displays.
   *
   * The system automatically creates audit records when administrators perform governance operations. Manual creation is not supported. All records are permanent and cannot be deleted or modified.
   *
   * @param connection
   * @param body Search criteria for filtering administrative audit log records.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query ecommerce_platform_admin_audit_logs table
     *   with pagination and filtering.
   *
   * Filtering:
   * - Apply target_type filter for entity type (customer, seller, order_item, product, seller_approval_request, admin_promotion_request)
   * - Apply action filter for governance operation (ban, unban, suspend, unsuspend, approve, reject, force_cancel, force_refund, delete_product, create_category, edit_category, delete_category, promote_admin, demote_admin)
   * - Apply ecommerce_platform_admin_id filter for administrator lookup
   * - Apply target_id filter for specific entity lookup
   * - Apply created_at range filter for date-based queries
   *
   * Pagination:
   * - Use cursor-based pagination for large audit log datasets
   * - Default sort by created_at descending (newest first)
   * - Support configurable page size within system limits
   *
   * Joins:
   * - Join with ecommerce_platform_admins to resolve admin identity information
   * - Avoid joining target entities (polymorphic) unless specifically requested
   *
   * Error handling:
   * - Return empty result set for invalid filter combinations (not errors)
   * - Enforce pagination limits to prevent excessive data transfer
   * - No mutation operations allowed on audit logs (system-generated immutable data)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommercePlatformAdminAuditLog.IRequest,
  ): Promise<IPageIEcommercePlatformAdminAuditLog.ISummary> {
    try {
      return await patchEcommercePlatformAdminAuditLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific administrative audit log record by its unique identifier.
   *
   * The response includes the performing administrator, the target entity type and identifier that was acted upon, the specific governance action performed, the optional justification reason provided by the administrator, and the exact timestamp of the action.
   *
   * @param connection
   * @param logId Unique identifier of the administrative audit log record to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the `ecommerce_platform_admin_audit_logs`
     *   table for a record matching the provided `logId` UUID.
   *
   * Retrieve the complete audit log record including: `id`, `ecommerce_platform_admin_id`, `target_type`, `target_id`, `action`, `reason`, and `created_at`.
   *
   * Map the database columns to the `IEcommercePlatformAdminAuditLog` response DTO. Ensure the requesting user has appropriate administrative permissions to view audit trail records. Return 404 if the log ID does not exist in the immutable append-only ledger.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":logId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("logId")
    logId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformAdminAuditLog> {
    try {
      return await getEcommercePlatformAdminAuditLogsLogId({
        admin,
        logId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
