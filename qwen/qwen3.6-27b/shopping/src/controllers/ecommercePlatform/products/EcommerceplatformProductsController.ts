import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformProduct } from "../../../api/structures/IEcommercePlatformProduct";
import { IPageIEcommercePlatformProduct } from "../../../api/structures/IPageIEcommercePlatformProduct";
import { getEcommercePlatformProductsProductId } from "../../../providers/getEcommercePlatformProductsProductId";
import { patchEcommercePlatformProducts } from "../../../providers/patchEcommercePlatformProducts";

@Controller("/ecommercePlatform/products")
export class EcommerceplatformProductsController {
  /**
   * Search and list products available on the ecommerce platform with support for filtering, sorting, and pagination.
   *
   * This endpoint returns paginated product summaries that can be filtered by category or subcategory, price range, seller identity, product name text search, and availability status. Products with no variants are marked as unavailable but remain visible in search results per platform rules.
   *
   * Soft-deleted products are automatically excluded from results. Each product summary includes the main thumbnail image (lowest order_index), variant count, and availability indicator to help customers identify purchasable items.
   *
   * @param connection
   * @param body Search criteria for product listing including optional filters for category, seller, price range, name search, availability status, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query ecommerce_platform_products table with
     *   WHERE deleted_at IS NULL to exclude soft-deleted products.
   *
   * Apply search filters:
   * - productName: Use trigram-based text search on name column (GIN index available)
   * - categoryId: Exact match on ecommerce_platform_category_id; includes both root categories and subcategories
   * - sellerProfileId: Exact match on ecommerce_platform_seller_profile_id for seller-owned product filtering
   * - minBasePrice / maxBasePrice: Range filter on base_price column
   * - includeUnavailable: When false or null, add EXISTS subquery checking ecommerce_platform_product_variants WHERE deleted_at IS NULL to ensure product has at least one active variant. Products without variants are still returned when includeUnavailable is true.
   *
   * Join with ecommerce_platform_seller_profiles on ecommerce_platform_seller_profile_id to fetch shop_name for summary display.
   * Join with ecommerce_platform_categories on ecommerce_platform_category_id to fetch category name and parent category name.
   * Join with ecommerce_platform_product_images (WHERE deleted_at IS NULL, ORDER BY order_index ASC LIMIT 1) to fetch the main thumbnail URI.
   * Use COUNT EXISTS subquery on ecommerce_platform_product_variants WHERE deleted_at IS NULL to compute variantCount.
   *
   * Sort by requested field: default created_at DESC. Supported sort fields: name, basePrice, createdAt, updatedAt.
   *
   * Apply cursor-based or offset-based pagination per platform pagination strategy.
   *
   * Return paginated results with IPageIEcommercePlatformProduct.ISummary structure containing product id, name, description, basePrice, shopName, categoryName, subcategoryName, thumbnailUri, variantCount, isAvailable, createdAt.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommercePlatformProduct.IRequest,
  ): Promise<IPageIEcommercePlatformProduct.ISummary> {
    try {
      return await patchEcommercePlatformProducts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific product by its unique identifier including variants, images, seller, and category data.
   *
   * Returns the full product entity with all associated data including product variants with their SKU codes and pricing, product images with ordering information, seller shop details, and assigned category information. Only active (non-deleted) products are returned.
   *
   * Deleted products or products belonging to suspended sellers return a 404 Not Found error.
   *
   * @param connection
   * @param productId The unique identifier of the product to retrieve (UUID format, global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the ecommerce_platform_products table for
     *   the product matching the provided productId UUID where deleted_at is
     *   NULL.
   *
   * 1. Validate the productId parameter as a valid UUID format.
   * 2. Perform a SELECT on ecommerce_platform_products WHERE id = ? AND deleted_at IS NULL.
   * 3. If no active product found, return 404 Not Found.
   * 4. Join and include related data:
   *    - ecommerce_platform_product_variants: Fetch all active variants (deleted_at IS NULL) ordered by sku_code, including their variant options from ecommerce_platform_product_variant_options.
   *    - ecommerce_platform_product_images: Fetch all active images (deleted_at IS NULL) ordered by order_index ascending.
   *    - ecommerce_platform_seller_profiles: Include seller shop_name, logo_image_uri, and shop_description.
   *    - ecommerce_platform_categories: Include category name and description.
   * 5. Do not return products belonging to suspended sellers - check seller ban status and return 404 if suspended.
   * 6. Calculate derived fields: variant price range (min/max variant prices if variants have different prices), average rating from reviews if they exist.
   * 7. Return the full product entity with all nested relationships.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformProduct> {
    try {
      return await getEcommercePlatformProductsProductId({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
