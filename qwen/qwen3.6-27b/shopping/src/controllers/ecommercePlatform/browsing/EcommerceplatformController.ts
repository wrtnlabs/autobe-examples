import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommercePlatformCategory } from "../../../api/structures/IEcommercePlatformCategory";
import { getEcommercePlatformBrowsing } from "../../../providers/getEcommercePlatformBrowsing";

@Controller("/ecommercePlatform/browsing")
export class EcommerceplatformController {
  /**
   * Retrieve the complete category hierarchy for product browsing on the platform.
   *
   * This endpoint returns all active categories organized in a parent-child tree structure, enabling customers to navigate products by category. Only categories that have not been deleted are included.
   *
   * Root categories appear as top-level entries while subcategories are nested directly under their respective parent category. This hierarchical representation reflects how categories are displayed in the customer-facing product navigation system.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the ecommerce_platform_categories table to
     *   retrieve all active categories where deleted_at is null. Use the
     *   parent_ecommerce_platform_category_id field to build the hierarchy:
     *   categories with null parent are roots, and categories with a non-null
     *   parent are children of that parent. Only two levels of hierarchy are
     *   supported (root and subcategory). Order root categories by created_at
     *   in descending order for consistent listing with newest categories
     *   first. Join or subselect to nest children under their parent category
     *   records. Return the hierarchical array with each category containing
     *   id, name, description, and a children array.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async browsing(): Promise<IEcommercePlatformCategory.IBrowsing> {
    try {
      return await getEcommercePlatformBrowsing();
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
