import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommercePlatformAdmin } from "../../../api/structures/IEcommercePlatformAdmin";
import { IPageIEcommercePlatformAdmin } from "../../../api/structures/IPageIEcommercePlatformAdmin";
import { getEcommercePlatformAdminsAdminId } from "../../../providers/getEcommercePlatformAdminsAdminId";
import { patchEcommercePlatformAdmins } from "../../../providers/patchEcommercePlatformAdmins";

@Controller("/ecommercePlatform/admins")
export class EcommerceplatformAdminsController {
  /**
   * Browse and search administrator accounts with advanced filtering and pagination. This endpoint is used to view and filter the administrative team for personnel management purposes.
   *
   * Administrators can filter results by grade level (regular or super administrator), account ban status, and creation date ranges. Results are returned in paginated format with summary information including administrator grade, ban status, and timestamps for efficient administrative team management.
   *
   * @param connection
   * @param body Search criteria for filtering administrator accounts. Supports filtering by grade type (is_super), ban status (is_banned), date range filters on account creation date, and pagination controls for result navigation.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the ecommerce_platform_admins table with
     *   filtering and pagination.
   *
   * Implementation logic:
   * 1. Apply soft-delete filter: WHERE deleted_at IS NULL to exclude soft-deleted administrators
   * 2. Apply grade filter: WHERE is_super = requestedValue when isSuper filter is provided
   * 3. Apply ban status filter: WHERE is_banned = requestedValue when isBanned filter is provided
   * 4. Apply date range filters on created_at field
   * 5. Apply sorting: order by created_at DESC by default
   * 6. Apply pagination using limit/skip parameters
   * 7. Return summary projection including: id, is_super, is_banned, created_at, updated_at
   *
   * Edge cases:
   * - Return empty paginated result when no matches found
   * - Validate date range if both start and end dates provided
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommercePlatformAdmin.IRequest,
  ): Promise<IPageIEcommercePlatformAdmin.ISummary> {
    try {
      return await patchEcommercePlatformAdmins({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve full details of a specific administrator account by their unique identifier.
   *
   * Returns the complete administrator entity including their grade classification (regular or super administrator), current active status through ban indicators, and account lifecycle timestamps. Super administrators can view all administrator records. This operation supports administrative oversight by enabling verification of administrator privileges and account states.
   *
   * The isSuper field indicates whether the administrator holds elevated privileges for personnel promotions and demotions. The isBanned field reflects whether the administrator account has been suspended from platform oversight duties.
   *
   * @param connection
   * @param adminId Unique UUID identifier of the administrator account to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Execute a database query on the
     *   ecommerce_platform_admins table using the adminId parameter as a UUID
     *   primary key constraint. Return the complete administrator record
     *   containing isSuper (grade classification), isBanned (active status),
     *   and timestamp fields (createdAt, updatedAt, deletedAt). Return 404 NOT
     *   FOUND if no matching administrator record exists. Handle expired or
     *   soft-deleted administrator records appropriately based on the deletedAt
     *   field presence.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IEcommercePlatformAdmin> {
    try {
      return await getEcommercePlatformAdminsAdminId({
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
