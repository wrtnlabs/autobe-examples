export async function getEcommercePlatformCustomerOrdersOrderIdItemsItemId(props: {
  customer: CustomerPayload;
  orderId: string & tags.Format<"uuid">;
  itemId: string & tags.Format<"uuid">;
}): Promise<IEcommercePlatformOrderItem> {
  const record =
    await MyGlobal.prisma.ecommerce_platform_order_items.findFirstOrThrow({
      ...EcommercePlatformOrderItemTransformer.select(),
      where: {
        id: props.itemId,
        ecommerce_platform_order_id: props.orderId,
        order: {
          customerProfile: {
            id: props.customer.id,
          },
        },
      },
    });
  return await EcommercePlatformOrderItemTransformer.transform(record);
}


