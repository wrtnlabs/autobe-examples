/**
 * Retrieve the complete category hierarchy for product browsing on the platform.
 *
 * This endpoint returns all active categories organized in a parent-child tree structure, enabling customers to navigate products by category. Only categories that have not been deleted are included.
 *
 * Root categories appear as top-level entries while subcategories are nested directly under their respective parent category. This hierarchical representation reflects how categories are displayed in the customer-facing product navigation system.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query the ecommerce_platform_categories table to
 *   retrieve all active categories where deleted_at is null. Use the
 *   parent_ecommerce_platform_category_id field to build the hierarchy:
 *   categories with null parent are roots, and categories with a non-null
 *   parent are children of that parent. Only two levels of hierarchy are
 *   supported (root and subcategory). Order root categories by created_at in
 *   descending order for consistent listing with newest categories first. Join
 *   or subselect to nest children under their parent category records. Return
 *   the hierarchical array with each category containing id, name, description,
 *   and a children array.
 * @path /ecommercePlatform/browsing
 * @accessor api.functional.ecommercePlatform.browsing
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function browsing(
  connection: IConnection,
): Promise<browsing.Response> {
  return true === connection.simulate
    ? browsing.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...browsing.METADATA,
          path: browsing.path(),
          status: null,
        },
      );
}
export namespace browsing {
  export type Response = IEcommercePlatformCategory.IBrowsing;

  export const METADATA = {
    method: "GET",
    path: "/ecommercePlatform/browsing",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommercePlatform/browsing";
  export const random = (): IEcommercePlatformCategory.IBrowsing =>
    typia.random<IEcommercePlatformCategory.IBrowsing>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
