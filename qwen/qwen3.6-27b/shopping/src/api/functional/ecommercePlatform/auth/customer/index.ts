/**
 * Register a new customer account with email and password. Validates uniqueness across all platform account types to prevent duplicate registrations.
 *
 * Upon success, creates customer identity with encrypted password in ecommerce_platform_customers. Initializes customer profile in ecommerce_platform_customer_profiles. Establishes first authentication session with device fingerprint and refresh token lifecycle.
 *
 * Returns JWT access and refresh tokens. Returns 409 Conflict if email is already registered.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Email address and password for the new customer registration. The email must not be associated with any existing account on the platform.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Process customer registration by validating email
 *   uniqueness across all account types (customers, sellers, admins) in
 *   ecommerce_platform_customers and related tables. Hash the password using
 *   bcrypt or equivalent algorithm and store in password_hash column. Set
 *   is_banned to false. Create linked customer_profile in
 *   ecommerce_platform_customer_profiles. Create initial session in
 *   ecommerce_platform_customer_sessions with refresh_token_hash, device
 *   fingerprint (ip, user_agent), and expiration. Return JWT tokens in
 *   IAuthorized response. Return 409 Conflict if email already exists.
 * @path /ecommercePlatform/auth/customer/join
 * @accessor api.functional.ecommercePlatform.auth.customer.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
