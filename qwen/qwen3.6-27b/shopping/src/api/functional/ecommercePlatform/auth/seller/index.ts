/**
 * Register a new seller account with email and password credentials.
 *
 * Seller accounts require administrator approval before selling privileges are granted. Upon registration, the account is created with 'pending' approval status. The email must be unique across all platform accounts (customer, seller, administrator) — duplicate email across any account type results in rejection.
 *
 * After successful registration, the seller can log in but seller-specific operations are restricted until administrator approval. A seller approval request is automatically created and tracked in the ecommerce_platform_seller_approval_requests table.
 *
 * A seller profile is also created simultaneously with the account, establishing the business identity foundation.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration credentials for the new seller account.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Query ecommerce_platform_sellers for existing email
 *   to enforce cross-account uniqueness (check customers, sellers, admins
 *   tables). If not duplicate, hash password using bcrypt, insert into
 *   ecommerce_platform_sellers with email, password_hash,
 *   approval_status='pending', is_banned=false. Auto-create
 *   ecommerce_platform_seller_approval_requests with status='pending'.
 *   Auto-create ecommerce_platform_seller_profiles with shop_name from request
 *   or default. Generate JWT access and refresh tokens, insert session into
 *   ecommerce_platform_seller_sessions with ip, href, referrer from request.
 *   Return tokens in IAuthorized response.
 * @path /ecommercePlatform/auth/seller/join
 * @accessor api.functional.ecommercePlatform.auth.seller.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
