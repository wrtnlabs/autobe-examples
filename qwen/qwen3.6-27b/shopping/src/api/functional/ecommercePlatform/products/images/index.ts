/**
 * Search and list product images belonging to a specific product with optional filtering and pagination.
 *
 * Returns a paginated collection of product image records for the specified product, including image URLs, display order positions, and metadata. Supports filtering by deletion status to show active or archived images. Results are sorted by display order to maintain gallery sequence.
 *
 * Product images are visual assets attached to products, with the lowest order index serving as the main thumbnail shown in search results and category listings. Images marked as deleted (via deleted_at timestamp) are hidden from the product gallery but preserved for snapshot history.
 *
 * @param props.connection
 * @param props.productId UUID of the parent product whose images are being listed
 * @param props.body Search criteria for filtering product images, including deletion status filters, ordering preferences, and pagination parameters.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query the ecommerce_platform_product_images table for
 *   images belonging to the given product ID.
 *
 * 1. Validate the product exists and is accessible by the current user
 * 2. Filter images by ecommerce_platform_product_id matching the path parameter
 * 3. Apply optional filters from the request body:
 *    - Include or exclude soft-deleted images based on deleted_at filter
 *    - Filter by specific ordering criteria
 * 4. Execute query with pagination support (cursor-based or offset-based)
 * 5. Order results by order_index ascending to maintain gallery display sequence
 * 6. Return paginated response with image summaries
 *
 * Edge cases:
 * - Product with no images returns empty list with total=0
 * - All images soft-deleted returns empty list if filter excludes deleted records
 * - Invalid productId returns 404 error
 * @path /ecommercePlatform/products/:productId/images
 * @accessor api.functional.ecommercePlatform.products.images.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
