/**
 * Search and list products available on the ecommerce platform with support for filtering, sorting, and pagination.
 *
 * This endpoint returns paginated product summaries that can be filtered by category or subcategory, price range, seller identity, product name text search, and availability status. Products with no variants are marked as unavailable but remain visible in search results per platform rules.
 *
 * Soft-deleted products are automatically excluded from results. Each product summary includes the main thumbnail image (lowest order_index), variant count, and availability indicator to help customers identify purchasable items.
 *
 * @param props.connection
 * @param props.body Search criteria for product listing including optional filters for category, seller, price range, name search, availability status, and pagination parameters.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query ecommerce_platform_products table with WHERE
 *   deleted_at IS NULL to exclude soft-deleted products.
 *
 * Apply search filters:
 * - productName: Use trigram-based text search on name column (GIN index available)
 * - categoryId: Exact match on ecommerce_platform_category_id; includes both root categories and subcategories
 * - sellerProfileId: Exact match on ecommerce_platform_seller_profile_id for seller-owned product filtering
 * - minBasePrice / maxBasePrice: Range filter on base_price column
 * - includeUnavailable: When false or null, add EXISTS subquery checking ecommerce_platform_product_variants WHERE deleted_at IS NULL to ensure product has at least one active variant. Products without variants are still returned when includeUnavailable is true.
 *
 * Join with ecommerce_platform_seller_profiles on ecommerce_platform_seller_profile_id to fetch shop_name for summary display.
 * Join with ecommerce_platform_categories on ecommerce_platform_category_id to fetch category name and parent category name.
 * Join with ecommerce_platform_product_images (WHERE deleted_at IS NULL, ORDER BY order_index ASC LIMIT 1) to fetch the main thumbnail URI.
 * Use COUNT EXISTS subquery on ecommerce_platform_product_variants WHERE deleted_at IS NULL to compute variantCount.
 *
 * Sort by requested field: default created_at DESC. Supported sort fields: name, basePrice, createdAt, updatedAt.
 *
 * Apply cursor-based or offset-based pagination per platform pagination strategy.
 *
 * Return paginated results with IPageIEcommercePlatformProduct.ISummary structure containing product id, name, description, basePrice, shopName, categoryName, subcategoryName, thumbnailUri, variantCount, isAvailable, createdAt.
 * @path /ecommercePlatform/products
 * @accessor api.functional.ecommercePlatform.products.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
