/**
 * Add multiple product images to a product in a single operation.
 *
 * Sellers can upload new images to their products by submitting image URIs. The system appends new images to the existing image collection, automatically assigning display order indices. Each image URI is validated and stored with the next available order position.
 *
 * The operation is restricted to the product's owning seller. Images are immediately visible on the product detail page after creation. The image with the lowest order index serves as the main thumbnail for product listings.
 *
 * @param props.connection
 * @param props.productId UUID of the product to add images to.
 * @param props.body Array of image URIs to add to the product. Each URI points to a hosted image file. Images are appended after existing images with automatically assigned order positions.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Query ecommerce_platform_products to validate the
 *   product exists and belongs to the authenticated seller.
 *
 * 1. Validate product ownership: ensure ecommerce_platform_seller_profile_id matches the authenticated seller's profile.
 * 2. Query existing images for the product to determine the next available order_index values (current max + 1).
 * 3. For each image URI in the request array:
 *    - Generate UUID for new record
 *    - Create ecommerce_platform_product_images row with product_id, uri, calculated order_index
 *    - Use database transaction to ensure atomic creation of all images
 * 4. Create snapshot entry in ecommerce_platform_snapshots recording the product image modifications.
 * 5. Return all created image records including their assigned IDs and order indices.
 *
 * Error handling:
 * - 404 if product not found
 * - 403 if seller does not own product
 * - 400 if URI array is empty or contains invalid URIs
 * @path /ecommercePlatform/seller/products/:productId/images
 * @accessor api.functional.ecommercePlatform.seller.products.images.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
