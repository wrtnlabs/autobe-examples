export async function change(
  connection: IConnection,
  props: change.Props,
): Promise<void> {
  return true === connection.simulate
    ? change.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...change.METADATA,
          path: change.path(),
          status: null,
        },
        props.body,
      );
}
