import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IEcommercePlatformShipment } from "../../../../structures/IEcommercePlatformShipment";

/**
 * Manually confirm delivery receipt of a shipment package.
 *
 * This endpoint allows customers to manually confirm they have received their package. When called, it updates the shipment's confirmed_at timestamp and transitions all included order items to 'delivered' status. Delivery confirmation operates at the shipment level, affecting all order items within that shipment simultaneously.
 *
 * Manual confirmation stops the 14-day auto-delivery countdown and enables customers to submit refund requests within seven days of delivery confirmation. The system validates that the authenticated customer owns all order items in the shipment before processing the confirmation.
 *
 * @param props.connection
 * @param props.shipmentId UUID identifier of the shipment to confirm delivery for
 * @param props.body Optional confirmation metadata for the delivery confirmation event
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Validate that the authenticated customer owns all
 *   order items in the shipment. Query ecommerce_platform_shipment_items where
 *   shipment_id equals the provided shipmentId, then join with
 *   ecommerce_platform_order_items and ecommerce_platform_orders to verify the
 *   customer_profile_id matches the authenticated customer.
 *
 * If confirmed_at is already set, return 409 Conflict. Update ecommerce_platform_shipments.confirmed_at to current timestamp. Set delivered_at if not already set. Transition all referenced order items' status to 'delivered' through the junction table relationships. Return the updated shipment entity.
 * @path /ecommercePlatform/customer/shipments/:shipmentId/confirm
 * @accessor api.functional.ecommercePlatform.customer.shipments.confirm
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function confirm(
  connection: IConnection,
  props: confirm.Props,
): Promise<confirm.Response> {
  return true === connection.simulate
    ? confirm.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...confirm.METADATA,
          path: confirm.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace confirm {
  export type Props = {
    /**
     * UUID identifier of the shipment to confirm delivery for
     */
    shipmentId: string & tags.Format<"uuid">;

    /**
     * Optional confirmation metadata for the delivery confirmation event
     */
    body: IEcommercePlatformShipment.IConfirm;
  };
  export type Body = IEcommercePlatformShipment.IConfirm;
  export type Response = IEcommercePlatformShipment;

  export const METADATA = {
    method: "POST",
    path: "/ecommercePlatform/customer/shipments/:shipmentId/confirm",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/ecommercePlatform/customer/shipments/${encodeURIComponent(props.shipmentId ?? "null")}/confirm`;
  export const random = (): IEcommercePlatformShipment =>
    typia.random<IEcommercePlatformShipment>();
  export const simulate = (
    connection: IConnection,
    props: confirm.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: confirm.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shipmentId")(() => typia.assert(props.shipmentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
