/**
 * Search and list all order items within a specific order with filtering and pagination support.
 *
 * Order items represent individual line items in a purchase transaction, each capturing a specific product variant, quantity, and price at the time of purchase. Items maintain their own lifecycle status (paid, shipped, delivered, cancelled, or refunded) which operates independently from other items in the same order.
 *
 * This endpoint supports filtering order items by status and browsing large result sets with pagination. It returns comprehensive item details including product variant information, pricing, and current fulfillment state. Multiple sellers may have items in the same order, each with independent tracking and shipping status.
 *
 * @param props.connection
 * @param props.orderNumber Human-readable order number uniquely identifying the parent order (global scope)
 * @param props.body Search criteria including optional status filter (paid, shipped, delivered, cancelled, refunded) and pagination parameters (limit, cursor).
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query ecommerce_platform_order_items by filtering on
 *   ecommerce_platform_order_id where order_number matches the path parameter.
 *
 * 1. Resolve the parent order: Look up ecommerce_platform_orders by unique order_number constraint
 * 2. Apply authorization: Verify the requesting user has access (customer owns the order, seller has items in it, or admin)
 * 3. Filter order items: Join to products and variants to include product details for listing
 * 4. Status filtering: Apply optional status filter from request body (paid, shipped, delivered, cancelled, refunded)
 * 5. Pagination: Apply cursor-based pagination using createdAt timestamp descending, with limit/offset from request
 * 6. Response enrichment: Include related snapshot_order_items data for historical context, shipment status via shipment_items joins, and cancellation/request status if applicable
 * 7. Return paginated response with metadata (total count, cursor tokens)
 *
 * Edge cases:
 * - Return empty list if order exists but has no items (shouldn't occur naturally)
 * - Items from multiple sellers exist simultaneously with different statuses
 * - Price is immutable - reflects purchase-time price from snapshot records
 * @path /ecommercePlatform/customer/orders/:orderNumber/items
 * @accessor api.functional.ecommercePlatform.customer.orders.items.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
