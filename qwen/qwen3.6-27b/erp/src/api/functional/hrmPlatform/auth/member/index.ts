/**
 * Register a new member account and automatically create a default organization.
 *
 * The email must be globally unique across all member accounts, enforced by the database unique constraint on hrm_platform_members. The display_name is required for profile identification shown in employee lists, timesheet headers, and activity logs. Upon successful account creation, the system generates authorization tokens and establishes an initial session in hrm_platform_member_sessions.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Join request containing email, password, and display_name for new account creation.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Service logic: 1) Validate email format and check
 *   uniqueness in hrm_platform_members. 2) Hash the provided password using a
 *   secure algorithm (bcrypt/argon2). 3) Insert a new row into
 *   hrm_platform_members with id (UUID), email, password_hash, display_name,
 *   created_at, updated_at. 4) Create a default organization for the new
 *   member. 5) Generate JWT access and refresh tokens. 6) Create a session
 *   record in hrm_platform_member_sessions with hrm_platform_member_id, ip,
 *   referrer, created_at, expired_at. 7) Return IAuthorized with tokens. Edge
 *   cases: Duplicate email returns 409 Conflict. Missing required fields return
 *   422 Unprocessable Entity.
 * @path /hrmPlatform/auth/member/join
 * @accessor api.functional.hrmPlatform.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
