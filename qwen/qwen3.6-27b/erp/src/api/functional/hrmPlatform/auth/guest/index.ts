/**
 * Guest join operation creates or retrieves an unauthenticated guest profile based on device fingerprint and establishes an initial session for browsing public entry points such as sign-up and login pages.
 *
 * The guest join operation establishes an anonymous identity using the visitor's device fingerprint, providing continuity across public page visits. This operation does not create a user account - guests remain unauthenticated with zero permissions until they complete the registration process to become a member. A device fingerprint is used to identify the visitor's browser and device characteristics.
 *
 * An initial guest session is created with the client IP address, current page URL, referring source URL, and security expiration timestamp. The operation returns authentication tokens that allow the guest to maintain session state while browsing public pages.
 *
 * The device fingerprint links to the hrm_platform_guests profile, and session data is stored in hrm_platform_guest_sessions for tracking and security purposes. Guests possess no role, no permission set, and no access rights to organizational resources.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest registration data including device fingerprint and session context for establishing anonymous visitor identity.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification This operation creates or retrieves a guest profile
 *   based on device fingerprint and establishes an initial guest session for
 *   browsing public entry points.
 *
 * Implementation logic:
 * 1. Validate device_fingerprint is provided and non-empty
 * 2. Find existing guest by device_fingerprint using unique constraint
 * 3. If no guest exists, create new hrm_platform_guests record with: device_fingerprint, created_at, updated_at
 * 4. Create new hrm_platform_guest_sessions record with: hrm_platform_guest_id (from step 2/3), ip, href, referrer (nullable), created_at, expired_at (set to security expiration, e.g., 1 hour from now)
 * 5. Generate guest access token and refresh token
 * 6. Return IAuthorized object containing tokens
 *
 * Edge cases:
 * - device_fingerprint must pass validation (non-empty string, unique constraint)
 * - href and referrer can be very long (up to 80000 chars per schema)
 * - expired_at is mandatory for session invalidation - enforce service level
 * - No email or password fields involved - this is purely anonymous session creation
 * - deleted_at is null (not soft-deleted)
 * @path /hrmPlatform/auth/guest/join
 * @accessor api.functional.hrmPlatform.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
