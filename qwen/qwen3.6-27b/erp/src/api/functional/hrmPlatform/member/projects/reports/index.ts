/**
 * Retrieve budget utilization report showing budget hours versus actual hours logged.
 *
 * Returns budget consumption statistics including total estimated budget hours, actual hours consumed by employees through timelogs, and calculated percentage utilization. Reports include employee breakdowns showing individual hours logged with timelog counts, and billable breakdowns separating client chargeable time from internal organizational work.
 *
 * Budget field represents planned effort in hours while duration_minutes in timelogs represents tracked time in minutes (divided by 60 for hours conversion). Utilization percentage indicates how much of the planned budget has been consumed. Projects with no timelog entries report zero actual hours and zero percent utilization. Projects with null budget fields report null utilization percentage.
 *
 * Employees can only view budget reports for projects where they hold active project membership. Managers can view budget reports for any project within their organization scope. Projects in archived or completed status still display budget utilization for historical reference.
 *
 * @param props.connection
 * @param props.projectId UUID of the project to retrieve budget utilization report for
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Join hrm_platform_projects with hrm_platform_timelogs
 *   where timelog hrm_platform_project_id matches. Filter project by UUID
 *   projectId and current organization context (hrm_platform_organization_id).
 *   Only include timelogs with null deleted_at to exclude deleted timelog
 *   entries. Calculate actual hours as sum(timelog.duration_minutes) / 60.
 *   Calculate utilization percent as (actual_hours / budget) * 100.0 if budget
 *   is not null. Handle null budget (set utilization to null). Handle no
 *   timelogs — actual hours = 0. Group employee breakdowns by
 *   hrm_platform_employee_id, summing duration_minutes and counting timelog
 *   entries per employee. Group billable breakdowns by billable flag, summing
 *   duration_minutes and counting timelog entries for each billability. Return
 *   404 if project not found or not in user's organization context.
 * @path /hrmPlatform/member/projects/:projectId/reports/budget
 * @accessor api.functional.hrmPlatform.member.projects.reports.budget
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
