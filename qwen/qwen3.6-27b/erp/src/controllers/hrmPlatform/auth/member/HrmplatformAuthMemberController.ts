import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformMember } from "../../../../api/structures/IHrmPlatformMember";
import { postHrmPlatformAuthMemberJoin } from "../../../../providers/postHrmPlatformAuthMemberJoin";
import { postHrmPlatformAuthMemberLogin } from "../../../../providers/postHrmPlatformAuthMemberLogin";
import { postHrmPlatformAuthMemberRefresh } from "../../../../providers/postHrmPlatformAuthMemberRefresh";

@Controller("/hrmPlatform/auth/member")
export class HrmplatformAuthMemberController {
  /**
   * Register a new member account and automatically create a default organization.
   *
   * The email must be globally unique across all member accounts, enforced by the database unique constraint on hrm_platform_members. The display_name is required for profile identification shown in employee lists, timesheet headers, and activity logs. Upon successful account creation, the system generates authorization tokens and establishes an initial session in hrm_platform_member_sessions.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Join request containing email, password, and display_name for new account creation.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Service logic: 1) Validate email format and check
     *   uniqueness in hrm_platform_members. 2) Hash the provided password using
     *   a secure algorithm (bcrypt/argon2). 3) Insert a new row into
     *   hrm_platform_members with id (UUID), email, password_hash,
     *   display_name, created_at, updated_at. 4) Create a default organization
     *   for the new member. 5) Generate JWT access and refresh tokens. 6)
     *   Create a session record in hrm_platform_member_sessions with
     *   hrm_platform_member_id, ip, referrer, created_at, expired_at. 7) Return
     *   IAuthorized with tokens. Edge cases: Duplicate email returns 409
     *   Conflict. Missing required fields return 422 Unprocessable Entity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmPlatformMember.IJoin,
  ): Promise<IHrmPlatformMember.IAuthorized> {
    try {
      return await postHrmPlatformAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing member with email and password credentials.
   *
   * The system verifies the provided credentials by comparing the password hash stored in hrm_platform_members. To prevent credential enumeration attacks, the error response does not differentiate between 'user not found' and 'wrong password'. On successful authentication, a new session record is created in hrm_platform_member_sessions capturing the IP address, href, and referrer for security auditing.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials containing email and password for authentication.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Service logic: 1) Query hrm_platform_members by
     *   email with exact match. 2) If not found or deleted_at is not null,
     *   return 401 Unauthorized. 3) Verify the provided password against the
     *   stored password_hash. 4) If password mismatch, return 401 Unauthorized
     *   (identical message to not-found to prevent credential enumeration). 5)
     *   Generate new JWT access and refresh tokens. 6) Create a new session
     *   record in hrm_platform_member_sessions with hrm_platform_member_id, ip,
     *   referrer, created_at, expired_at. 7) Return IAuthorized with tokens.
     *   Edge cases: Soft-deleted accounts are denied access securely.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmPlatformMember.ILogin,
  ): Promise<IHrmPlatformMember.IAuthorized> {
    try {
      return await postHrmPlatformAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew an expiring or expired access token using a valid refresh token.
   *
   * The system validates the refresh token against the member session in hrm_platform_member_sessions and ensures the associated member account in hrm_platform_members is not soft-deleted (deleted_at is null). If the session has expired (expired_at < now), the operation fails and the user must re-authenticate via login. The refreshed token maintains the same member identity and permissions.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token request for token renewal.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Service logic: 1) Extract and validate the
     *   refresh token from the request. 2) Decode the token to identify the
     *   associated hrm_platform_member_id. 3) Query hrm_platform_members by id.
     *   4) Verify the member exists and deleted_at is null. 5) Query
     *   hrm_platform_member_sessions for an active session linked to the member
     *   where expired_at >= current time. 6) Generate a new JWT access token
     *   and a new refresh token. 7) Update the session record's expired_at to
     *   the new expiration time. 8) Return IAuthorized with the new tokens.
     *   Edge cases: Expired or invalid tokens return 401 Unauthorized.
     *   Soft-deleted accounts return 401 Unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IHrmPlatformMember.IRefresh,
  ): Promise<IHrmPlatformMember.IAuthorized> {
    try {
      return await postHrmPlatformAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
