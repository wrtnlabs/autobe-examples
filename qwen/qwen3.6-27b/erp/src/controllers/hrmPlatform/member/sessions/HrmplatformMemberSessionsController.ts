import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformMemberSession } from "../../../../api/structures/IHrmPlatformMemberSession";
import { IPageIHrmPlatformMemberSession } from "../../../../api/structures/IPageIHrmPlatformMemberSession";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberSessionsSessionId } from "../../../../providers/getHrmPlatformMemberSessionsSessionId";
import { patchHrmPlatformMemberSessions } from "../../../../providers/patchHrmPlatformMemberSessions";

@Controller("/hrmPlatform/member/sessions")
export class HrmplatformMemberSessionsController {
  /**
   * Retrieve a paginated list of the authenticated user's active and expired sessions. Sessions represent authentication states including device information (IP address, href), creation timestamp, and expiration status. This endpoint enables users to review where they are currently logged in for security awareness and session management.
   *
   * The list supports filtering by session status (active or expired), date range of session creation, and pagination parameters. Each session record includes device fingerprint information to help users identify unfamiliar login locations. Only the authenticated user's own sessions are returned — cross-user access is strictly prohibited.
   *
   * @param connection
   * @param body Search and filter criteria for querying sessions. Includes optional filters for session status (active or expired), creation date range, and pagination parameters for result set navigation.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_member_sessions table
     *   filtering by hrm_platform_member_id from the authenticated user's
     *   context (NOT from request body). Apply filters from request body:
     *   status (active/expired based on expired_at compared to current time),
     *   date range on created_at, and pagination parameters (cursor, limit).
     *   Join is not required for basic listing.
   *
   * Filter logic:
   * - active status: expired_at > NOW()
   * - expired status: expired_at <= NOW()
   * - date range: created_at BETWEEN startDate AND endDate
   *
   * Return cursor-based pagination with IPageIHrmPlatformMemberSession.ISummary containing: id, ip, href, referrer, created_at, expired_at. Do NOT expose hrm_platform_member_id in response (redundant with authentication context). Enforce strict user-scoped isolation — users can NEVER query other users' sessions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformMemberSession.IRequest,
  ): Promise<IPageIHrmPlatformMemberSession.ISummary> {
    try {
      return await patchHrmPlatformMemberSessions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific session identified by its unique identifier.
   *
   * This endpoint returns the session entity, which includes metadata about the connection, the authenticated resource owner, and temporal attributes such as creation and expiration times.
   *
   * @param connection
   * @param sessionId The unique identifier of the session to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Retrieve session record from the
     *   hrm_platform_member_sessions table.
   *
   * 1. Extract the sessionId path parameter and validate the UUID format.
   * 2. Query the hrm_platform_member_sessions table where id == sessionId.
   * 3. Verify that the session belongs to the authenticated user by checking hrm_platform_member_id.
   * 4. If the record does not exist or belongs to another user, return 404 Not Found.
   * 5. Return the IHrmPlatformMemberSession object.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformMemberSession> {
    try {
      return await getHrmPlatformMemberSessionsSessionId({
        member,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
