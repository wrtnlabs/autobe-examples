import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IReportTime } from "../../../../../api/structures/IReportTime";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchHrmPlatformMemberReportsTime } from "../../../../../providers/patchHrmPlatformMemberReportsTime";

@Controller("/hrmPlatform/member/reports/time")
export class HrmplatformMemberReportsTimeController {
  /**
   * Retrieve aggregated time tracking report with customizable grouping and filtering options.
   *
   * Returns statistics grouped by employee, project, and/or task dimensions, showing total hours, billable hours, and non-billable hours for each group. All results are scoped to the authenticated organization.
   *
   * Grouping dimensions:
   * - Employee: Total hours per employee with billable breakdown
   * - Project: Total hours per project with employee detail
   * - Task: Detailed hours per task with employee and project context
   *
   * Managers and owners can view all employees' time data. Employees can only view their own time unless they have time:manage permission.
   *
   * Filters:
   * - Date range (required)
   * - Specific employee
   * - Specific project
   * - Task-specific breakdown
   *
   * @param connection
   * @param body Time report grouping and filtering criteria including date range, dimensional grouping, and optional filters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Execute SQL aggregation query on
     *   hrm_platform_timelogs with LEFT JOINs to hrm_platform_employees for
     *   names, hrm_platform_projects for project metadata, and
     *   hrm_platform_tasks for task titles.
   *
   * WHERE deleted_at IS NULL
   * AND date >= :from AND date <= :to
   * AND employee_id = :employeeId IF provided
   * AND project_id = :projectId IF provided
   * AND hrm_platform_organization_id = :currentOrgId
   *
   * Calculate grouped statistics:
   * - total_hours = SUM(duration_minutes) / 60
   * - billable_hours = SUM(CASE WHEN billable THEN duration_minutes ELSE 0 END) / 60
   * - non_billable_hours = SUM(CASE WHEN NOT billable THEN duration_minutes ELSE 0 END) / 60
   *
   * GROUP BY selected dimension: employee_id, project_id, task_id
   *
   * Perform authorization check: If employee role without time:manage, filter to current employee_id only..
   *
   * Edge cases:
   * - Empty result: return empty groups array with 0 totals
   * - from > to: return empty result
   * - Invalid IDs: return empty result
   * - Large date range: return full result without pagination
   *
   * Index usage: Leverage @@index([hrm_platform_employee_id, date]), @@index([hrm_platform_project_id, date]), @@index([hrm_platform_task_id, date]) for efficient query execution.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async timeReport(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IReportTime.IRequest,
  ): Promise<IReportTime> {
    try {
      return await patchHrmPlatformMemberReportsTime({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
