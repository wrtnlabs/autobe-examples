import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPersonalDashboardView } from "../../../../api/structures/IPersonalDashboardView";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberPersonalDashboard } from "../../../../providers/getHrmPlatformMemberPersonalDashboard";

@Controller("/hrmPlatform/member/personal-dashboard")
export class HrmplatformMemberPersonal_dashboardController {
  /**
   * Retrieve a personal dashboard summary for the currently authenticated member within their active organization context.
   *
   * Returns aggregated workforce metrics including today's and this week's tracked hours, active timer status, the five most recent timelog entries, pending timesheet information, and open or in-progress task assignments. All data is scoped to the member's employee record in the currently selected organization. The hours-today value sums timelog durations for today's calendar date, while the hours-this-week value sums durations for Monday through Sunday of the current week period.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Resolve the authenticated member's employee
     *   record using the active organization context from the session
     *   (hrm_platform_member_session → hrm_platform_organization_id). Query
     *   hrm_platform_employees with hrm_platform_member_id = session memberId
     *   AND hrm_platform_organization_id = session organizationId.
   *
   * 1. Today's hours: SUM(duration_minutes) / 60 from hrm_platform_timelogs WHERE hrm_platform_employee_id = employee.id AND date >= start_of_today() AND date < start_of_tomorrow() AND deleted_at IS NULL.
   *
   * 2. This week's hours: SUM(duration_minutes) / 60 from hrm_platform_timelogs WHERE hrm_platform_employee_id = employee.id AND date >= start_of_monday() AND date < start_of_next_monday() AND deleted_at IS NULL.
   *
   * 3. Active timer: SELECT from hrm_platform_timers WHERE hrm_platform_employees_id = employee.id AND stopped_at IS NULL AND deleted_at IS NULL. Should return at most one record per employee. Include project name and task title via joins with hrm_platform_projects and hrm_platform_tasks.
   *
   * 4. Recent timelogs: SELECT TOP 5 from hrm_platform_timelogs WHERE hrm_platform_employee_id = employee.id AND deleted_at IS NULL ORDER BY created_at DESC. Include project name and task title via joins.
   *
   * 5. Pending timesheet: SELECT from hrm_platform_timesheets WHERE hrm_platform_employee_id = employee.id AND status IN ('draft', 'submitted') AND deleted_at IS NULL. Return the most recent pending timesheet record.
   *
   * 6. Assigned tasks: SELECT from hrm_platform_tasks WHERE hrm_platform_employee_id = employee.id AND status IN ('open', 'in-progress') AND deleted_at IS NULL LIMIT 5. Include project name via join with hrm_platform_projects.
   *
   * All queries must verify the employee's hrm_platform_organization_id matches the session's active organization context. Return a composed object containing all sections.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IPersonalDashboardView> {
    try {
      return await getHrmPlatformMemberPersonalDashboard({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
