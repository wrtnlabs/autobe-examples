import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformDepartment } from "../../../../api/structures/IHrmPlatformDepartment";
import { IPageIHrmPlatformDepartment } from "../../../../api/structures/IPageIHrmPlatformDepartment";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteHrmPlatformMemberDepartmentsDepartmentId } from "../../../../providers/deleteHrmPlatformMemberDepartmentsDepartmentId";
import { getHrmPlatformMemberDepartmentsDepartmentId } from "../../../../providers/getHrmPlatformMemberDepartmentsDepartmentId";
import { patchHrmPlatformMemberDepartments } from "../../../../providers/patchHrmPlatformMemberDepartments";
import { postHrmPlatformMemberDepartments } from "../../../../providers/postHrmPlatformMemberDepartments";
import { putHrmPlatformMemberDepartmentsDepartmentId } from "../../../../providers/putHrmPlatformMemberDepartmentsDepartmentId";

@Controller("/hrmPlatform/member/departments")
export class HrmplatformMemberDepartmentsController {
  /**
   * Create a new department within the currently selected organization.
   *
   * Departments can be organized into a simple parent-child hierarchy (maximum one nesting level deep) to group employees and organize the company structure. The department name must be unique within the same organization using case-sensitive validation.
   *
   * If a parent department is provided, it must belong to the exact same organization, must not be soft-deleted, and must be a top-level department without a parent itself. Circular references (e.g., assigning a child department to become the parent department) are prevented.
   *
   * @param connection
   * @param body The request body contains the name for the new department, an optional description, and an optional parent department ID for one-level structural nesting.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Extract `hrm_platform_organization_id` from
     *   the authenticated API key's session context. 2. Validate the
     *   `IHrmPlatformDepartment.ICreate` request body. 3. Validate `name` is
     *   not empty. 4. If `parent_department_id` is provided: - Retrieve the
     *   parent department from `hrm_platform_departments`. - Must exist in the
     *   exact same `hrm_platform_organization_id`. - `deleted_at` MUST be null
     *   (active department). - Parent's `hrm_platform_parent_department_id`
     *   MUST be null to enforce the one-level nesting rule. - Parent's `id`
     *   cannot equal the target parent (prevents circular self-reference). 5.
     *   Validate `name` uniqueness against other departments sharing the same
     *   `hrm_platform_organization_id`. - Only compare against active records
     *   (`deleted_at` is null). - Comparison is case-sensitive. 6. Insert new
     *   record into `hrm_platform_departments`: - id: auto-generated UUID -
     *   hrm_platform_organization_id: from session - name: from request -
     *   description: from request (or null) -
     *   hrm_platform_parent_department_id: from request (or null) - created_at:
     *   current timestamp - updated_at: current timestamp - deleted_at: null 7.
     *   Return the newly created department object.
   *
   * Error Conditions:
   * - Return 400 if `name` is empty.
   * - Return 400 if provided `parent_department_id` does not exist.
   * - Return 400 if provided `parent_department_id` belongs to a different organization.
   * - Return 400 if provided `parent_department_id` is soft-deleted.
   * - Return 400 if provided `parent_department_id` already has a parent department (would violate one-level nesting).
   * - Return 400 if `name` violates uniqueness within the organization (case-sensitive).
   * - Return 401 if active session organization context is missing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformDepartment.ICreate,
  ): Promise<IHrmPlatformDepartment> {
    try {
      return await postHrmPlatformMemberDepartments({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of departments within the current organization context, supporting filtering, search, and sorting capabilities.
   *
   * This endpoint returns department summaries optimized for list displays in organizational structure views, employee grouping interfaces, and management dashboards. Results are automatically scoped to the authenticated member's active organization context and enforce multi-tenancy data isolation.
   *
   * **Features:**
   * - Filter by parent department relationship including all (root and child) or specific parent department
   * - Filter by active/deleted status
   * - Search by department name
   * - Sort by name, created_at, updated_at
   * - Cursor-based pagination for large result sets
   * - Results scoped to current organization only
   * - Hierarchical department structure with optional one-level parent nesting
   *
   * @param connection
   * @param body Search criteria for department listing. Parent department relationship for hierarchical filtering by direct parent department ID or null for root-only departments, status filter for active or deleted departments based on the deleted_at column, and case-insensitive name substring search. Sorting parameters specify ordering by name, created_at, or updated_at with ascending or descending direction. Pagination parameters define page number and page size for cursor-based navigation of large result sets.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_departments table scoped to
     *   the authenticated member's active organization context.
   *
   * 1. Validate that the authenticated user has an active organization session
   * 2. Build query filtering by hrm_platform_organization_id matching the session's organization
   * 3. Apply search filters from request body:
   *    - parent_department_id: filter by direct parent relationship (null for root departments)
   *    - status: filter by active/deleted based on deleted_at column
   *    - name_search: case-insensitive LIKE search on name field
   * 4. Apply sorted sorting from request body:
   *    - By name, created_at, updated_at (default: created_at DESC)
   * 5. Apply cursor-based pagination from request body:
   *    - page and size parameters for pagination
   * 6. Execute query with LEFT JOIN on recursive department relationship for parent lookup
   * 7. Return paginated IHrmPlatformDepartment.ISummary records with parent department relationship included
   *
   * Edge cases:
   * - Empty organization returns empty results page
   * - Non-existent parent_department_id filter returns no matching results
   * - Deleted departments excluded by default unless explicitly filtered
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformDepartment.IRequest,
  ): Promise<IPageIHrmPlatformDepartment.ISummary> {
    try {
      return await patchHrmPlatformMemberDepartments({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves the details of a single department including its name, description, parent department reference, and metadata.
   *
   * The department must belong to the currently active organization context. Soft-deleted departments are excluded from results.
   *
   * Only authenticated members can access this endpoint. Guests cannot view department details.
   *
   * @param connection
   * @param departmentId Unique identifier of the department to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_departments table for the
     *   department matching the provided departmentId.
   *
   * Validate that the retrieved department's hrm_platform_organization_id matches the current user's active organization context to enforce data isolation.
   *
   * Return 404 Not Found if no matching active department exists (deleted_at IS NULL).
   *
   * Include parent department reference if hrm_platform_parent_department_id is set. Child departments are not included in this response - those are accessed via separate list operations.
   *
   * Authentication: Only authenticated member actors can access this endpoint. guest actors are forbidden.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":departmentId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformDepartment> {
    try {
      return await getHrmPlatformMemberDepartmentsDepartmentId({
        member,
        departmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates an existing department's details within an organization. Modifies the department name, description, and optional parent department assignment for hierarchical grouping. Validates that the new name is unique within the organization and that any parent department belongs to the same organization without creating circular references or exceeding the one-level nesting limit.
   *
   * @param connection
   * @param departmentId The unique identifier of the department to update.
   * @param body Department details to update, including name, description, and optional parent department assignment.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_departments by id. Validate
     *   the department belongs to the current organization context. Update
     *   name, description, and hrm_platform_parent_department_id. Validate name
     *   is not empty and unique within the organization, excluding the current
     *   department. If parent department ID is provided, validate it exists,
     *   belongs to the same organization, and does not create a circular
     *   reference or violate the one-level nesting constraint. Update
     *   updated_at timestamp. Return the updated department record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":departmentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformDepartment.IUpdate,
  ): Promise<IHrmPlatformDepartment> {
    try {
      return await putHrmPlatformMemberDepartmentsDepartmentId({
        member,
        departmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-deletes a department within the authenticated organization context, preserving historical data while removing it from active organizational structures. Upon deletion, all employees previously assigned to the department are automatically unassigned without deactivation, and any child departments are promoted to top-level status. This operation requires organization management permissions and ensures audit trail continuity through the deleted_at timestamp.
   *
   * The department record remains accessible for historical queries but is excluded from active department listings and structures. Requires org:manage or equivalent department management permissions within the current organization context.
   *
   * @param connection
   * @param departmentId UUID identifier of the department to delete, scoped to the authenticated member's current organization context.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the hrm_platform_departments table using
     *   the departmentId path parameter, ensuring the record belongs to the
     *   authenticated member's current organization context via
     *   hrm_platform_organization_id. Validate that the user possesses the
     *   required org:manage permission; return a 403 Forbidden if unauthorized.
   *
   * Perform the soft-delete by setting the deleted_at column to the current transaction timestamp. Execute cascading reference nullifications within the same transaction:
   * 1. Set hrm_platform_department_id to NULL for all employees in hrm_platform_employees assigned to this department, preserving their accounts and history per Section 219.
   * 2. Set hrm_platform_parent_department_id to NULL for all child departments in hrm_platform_departments, promoting them to top-level status per Section 218.
   *
   * Return the fully updated IHrmPlatformDepartment entity with the populated deleted_at timestamp. Return 404 Not Found if the department does not exist or belongs to a different organization context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":departmentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberDepartmentsDepartmentId({
        member,
        departmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
