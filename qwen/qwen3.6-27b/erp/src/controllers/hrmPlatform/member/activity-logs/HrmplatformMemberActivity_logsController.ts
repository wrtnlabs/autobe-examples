import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformActivityLog } from "../../../../api/structures/IHrmPlatformActivityLog";
import { IPageIHrmPlatformActivityLog } from "../../../../api/structures/IPageIHrmPlatformActivityLog";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberActivityLogsActivityLogId } from "../../../../providers/getHrmPlatformMemberActivityLogsActivityLogId";
import { patchHrmPlatformMemberActivityLogs } from "../../../../providers/patchHrmPlatformMemberActivityLogs";

@Controller("/hrmPlatform/member/activity-logs")
export class HrmplatformMemberActivity_logsController {
  /**
   * Retrieve the full details of a specific activity log entry by its unique identifier.
   *
   * Returns the complete record of an organizational governance event, including the action type that occurred, the target entity affected (with type and display name snapshot), the authenticated member who performed the action, and the exact timestamp of the event.
   *
   * Activity logs are immutable, append-only audit trail entries that capture every significant organizational action such as employee lifecycle changes, contract modifications, project transitions, task status updates, timesheet workflow events, and role assignments. Once created, entries cannot be modified or deleted.
   *
   * Access to activity logs is scoped to the active organization context and governed by the organization manage permission.
   *
   * @param connection
   * @param activityLogId UUID of the activity log entry to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_activity_logs table for a
     *   single record by UUID primary key.
   *
   * Validation:
   * - Verify the activity log belongs to the current organization context (check hrm_platform_organization_id matches the active org).
   * - Verify the caller has org:manage permission to access activity log details.
   * - Return 404 if the activity log does not exist.
   *
   * Query:
   * - SELECT from hrm_platform_activity_logs WHERE id = {activityLogId} AND hrm_platform_organization_id = {currentOrgId}.
   * - Include member details via join on hrm_platform_members using hrm_platform_member_id.
   *
   * Response:
   * - Return the full activity log entry with all fields: id, actionType, entityType, entityId, entityName, createdAt, and member reference.
   * - Include action-specific details from the hrm_platform_activity_log_details subsidiary table if applicable.
   *
   * Error handling:
   * - 404 if no matching record found (either wrong ID or belongs to different organization).
   * - 403 if caller lacks org:manage permission.
   * - No soft-delete or cascading concerns - activity logs are never deleted independently.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":activityLogId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("activityLogId")
    activityLogId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformActivityLog> {
    try {
      return await getHrmPlatformMemberActivityLogsActivityLogId({
        member,
        activityLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and list organization activity log entries with filtering and cursor-based pagination.
   *
   * Returns paginated audit trail records of organizational governance events including employee lifecycle actions, contract changes, project transitions, task status changes, timesheet workflow events, and role assignments. Each entry captures the action type, target entity, acting member, and timestamp. Associated key-value detail records (previous/next values, rejection reasons, etc.) are included inline.
   *
   * Only predefined system-approved actions are logged: employee_invited, employee_deactivated, employee_reactivated, contract_created, contract_edited, project_created, project_archived, project_completed, project_deleted, task_status_changed, timesheet_submitted, timesheet_approved, timesheet_rejected, role_assigned, role_changed.
   *
   * All results are scoped to the active organization context. Supports filtering by action type, entity type, acting member, and date range. Enforces pagination boundary limits on page size.
   *
   * @param connection
   * @param body Search and pagination criteria for activity log queries including action type filter, entity type filter, acting member filter, text search on entity name, date range boundaries, and cursor-based pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_activity_logs scoped to
     *   hrm_platform_organization_id from active session context.
   *
   * Filtering:
   * 1. actionType: Filter by action_type using IN clause (supports array)
   * 2. entityType: Filter by entity_type using IN clause (supports array)
   * 3. memberId: Filter by hrm_platform_member_id
   * 4. dateFrom/dateTo: Filter by created_at range (>= from AND <= to)
   * 5. searchTerm: Filter by entity_name using ILIKE '%searchTerm%'
   *
   * Pagination:
   * - Cursor-based pagination with cursor parameter
   * - If cursor provided: WHERE (created_at < cursor.createdAt) OR (created_at = cursor.createdAt AND id < cursor.id)
   * - Enforce pageSize maximum boundary - reject requests exceeding system limits per Section 192
   * - Sort: created_at DESC, id DESC
   *
   * Include activity_log_details:
   * - Left join hrm_platform_activity_log_details on activity_log_id
   * - Group detail key-value pairs under each log entry
   * - Result shape: { id, actionType, entityType, entityId, entityName, memberId, createdAt, details: [{ key, value }] }
   *
   * Include member info:
   * - Left join hrm_platform_members on hrm_platform_member_id
   * - Include member identifier, email, display name in response
   *
   * No JOIN or FILTER on target entities (employees, projects, etc.) - entity_id and entity_name are stored as-is at time of logging.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformActivityLog.IRequest,
  ): Promise<IPageIHrmPlatformActivityLog.ISummary> {
    try {
      return await patchHrmPlatformMemberActivityLogs({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
