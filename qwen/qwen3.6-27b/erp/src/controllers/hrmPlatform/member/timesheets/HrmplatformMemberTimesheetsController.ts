import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformTimesheet } from "../../../../api/structures/IHrmPlatformTimesheet";
import { IPageIHrmPlatformTimesheet } from "../../../../api/structures/IPageIHrmPlatformTimesheet";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteHrmPlatformMemberTimesheetsTimesheetId } from "../../../../providers/deleteHrmPlatformMemberTimesheetsTimesheetId";
import { getHrmPlatformMemberTimesheetsTimesheetId } from "../../../../providers/getHrmPlatformMemberTimesheetsTimesheetId";
import { patchHrmPlatformMemberTimesheets } from "../../../../providers/patchHrmPlatformMemberTimesheets";
import { postHrmPlatformMemberTimesheets } from "../../../../providers/postHrmPlatformMemberTimesheets";
import { putHrmPlatformMemberTimesheetsTimesheetId } from "../../../../providers/putHrmPlatformMemberTimesheetsTimesheetId";

@Controller("/hrmPlatform/member/timesheets")
export class HrmplatformMemberTimesheetsController {
  /**
   * Create a new draft timesheet for the authenticated employee.
   *
   * Creates a weekly timesheet that aggregates the employee's timelogs for the specified week period. The system automatically calculates the week end date (Sunday), identifies all existing timelogs for that employee within the week, and computes the total hours.
   *
   * The timesheet is created in draft status, allowing the employee to manage associated timelogs before submission. Duplicate timesheets for the same employee and week period are prevented by a unique constraint on the employee and week start date.
   *
   * This operation is scoped to the authenticated employee's own timesheet creation.
   *
   * @param connection
   * @param body Request body containing the week start date for creating a new draft timesheet. The system will calculate the week end date and aggregate existing timelogs.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Extract `week_start_date` from the request
     *   body. 2. Calculate `week_end_date` as the Sunday of the week containing
     *   the `week_start_date`. 3. Query existing `hrm_platform_timelogs` for
     *   the authenticated employee's `hrm_platform_employee_id` where `date`
     *   falls within the calculated week period (`week_start_date` to
     *   `week_end_date`). 4. Calculate `total_hours` by summing
     *   `duration_minutes` from the matched timelogs. 5. Validate the unique
     *   constraint: ensure no existing timesheet exists for the same employee
     *   and `week_start_date`. 6. Create the `hrm_platform_timesheets` record
     *   with: - `hrm_platform_employee_id`: derived from the authenticated
     *   user's employee record. - `week_start_date`: from the request. -
     *   `week_end_date`: calculated value. - `status`: initialized to 'draft'.
     *   - `total_hours`: calculated from aggregated timelogs. 7. Auto-include
     *   any existing timelogs by updating their `hrm_platform_timesheet_id` to
     *   the new timesheet's `id`. 8. Return the newly created timesheet record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformTimesheet.ICreate,
  ): Promise<IHrmPlatformTimesheet> {
    try {
      return await postHrmPlatformMemberTimesheets({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of timesheets with optional filtering by status, week date range, and employee.
   *
   * Timesheets represent weekly work records grouping an employee's timelogs into Monday-to-Sunday periods. Each timesheet tracks the submission and approval workflow through four states: draft (being prepared), submitted (awaiting review), approved (final and locked), and rejected (returned for revision).
   *
   * Employees can only view timesheets belonging to themselves. Members with timesheet approval permissions (time:approve) or time management permissions (time:manage) can view all timesheets across the organization. Results are sorted by week start date in descending order by default.
   *
   * @param connection
   * @param body Search criteria including status filter, week date range, employee filter, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_timesheets table with
     *   pagination and filtering.
   *
   * 1. Apply organization context scoping: filter timesheets by joining hrm_platform_employees to ensure employee belongs to current organization.
   *
   * 2. Authorization check:
   *    - If current member has time:approve or time:manage permission: query all organization timesheets
   *    - Otherwise: filter to only timesheets where hrm_platform_employee_id matches current member's employee record
   *
   * 3. Apply filters from request body:
   *    - status: filter on status column (draft, submitted, approved, rejected)
   *    - weekStartDate and weekEndDate: filter on week_start_date column using range conditions
   *    - employeeId: filter on hrm_platform_employee_id
   *
   * 4. Join with hrm_platform_employees for employee name and department in summary.
   *
   * 5. Join with hrm_platform_members on reviewed_by_member_id for reviewer name when present.
   *
   * 6. Sort by week_start_date descending by default.
   *
   * 7. Apply cursor-based pagination and return paginated result set.
   *
   * 8. Build ISummary for each timesheet including: id, employee name, department name, week dates, status, total hours, submitted date, reviewed date, rejection reason.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformTimesheet.IRequest,
  ): Promise<IPageIHrmPlatformTimesheet.ISummary> {
    try {
      return await patchHrmPlatformMemberTimesheets({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed view of a single timesheet for the specified identifier. Employees access their own weekly submissions for review and resubmission. Managers and organization owners access all submitted timesheets for review, approval, and rejection workflows.
   *
   * Returns full timesheet details with timelog entries, project associations, task breakdowns, automated hour calculations, and workflow status tracking.
   *
   * Authorization enforces organization context—returned timesheet belongs to active organization scope. Draft status permits modifications; submitted and approved status restrict changes pending review completion.
   *
   * @param connection
   * @param timesheetId Unique identifier of the timesheet to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_timesheets for timesheetId.
     *   Join hrm_platform_timelogs to include all timelog entries. Join
     *   hrm_platform_employees for employee information. Join
     *   hrm_platform_projects for project details per timelog. Join
     *   hrm_platform_tasks for task associations.
   *
   * Enforce authorization: employees access own timesheets, managers access all submitted timesheets.
   * Return 403 Forbidden on authorization failure.
   * Return 404 Not Found if timesheet doesn't exist.
   *
   * Returns timesheet with:
   * - id, week metadata, total hours
   * - status: draft/submitted/approved/rejected
   * - Employee reference and details
   * - Submission/approval/rejection metadata
   * - Array of included timelogs
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":timesheetId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformTimesheet> {
    try {
      return await getHrmPlatformMemberTimesheetsTimesheetId({
        member,
        timesheetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a timesheet by managing its included timelogs.
   *
   * This endpoint allows employees to add or remove timelogs from their draft timesheets. The timelogIds array represents the complete set of timelogs to include in the timesheet - any existing timelogs not included in the array are removed, and new timelogs are added. Only timesheets in draft status can be modified. Once submitted, approved, or rejected, timesheets cannot be edited.
   *
   * The employee must own the timesheet to update it. All timelogs must belong to the same employee and fall within the timesheet's week period boundaries.
   *
   * @param connection
   * @param timesheetId UUID of the timesheet to update (scoped to current organization)
   * @param body Array of timelog IDs to include in this timesheet. Timelogs not in the array are removed from the timesheet, and new timelogs are added. Each timelog must belong to the current employee and fall within the timesheet's week period.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Load the hrm_platform_timesheets record by ID.
     *   2. Validate the timesheet exists and belongs to the current employee
     *   (hrm_platform_employee_id matches current user's employee record). 3.
     *   Validate status is 'draft' - reject with 400 if status is 'submitted',
     *   'approved', or 'rejected'. 4. Load all timelog IDs currently associated
     *   (hrm_platform_timesheet_id = timesheetId). 5. Compute additions
     *   (timelogs in request but not currently in timesheet) and removals
     *   (currently in timesheet but not in request). 6. For each timelog to
     *   add: - Load the timelog record - Validate it belongs to the current
     *   employee (hrm_platform_employee_id matches) - Validate its date falls
     *   within [week_start_date, week_end_date] of the timesheet - Validate it
     *   is not already part of another timesheet (hrm_platform_timesheet_id is
     *   null or equals the current timesheetId) - Update
     *   hrm_platform_timesheet_id to the timesheet ID 7. For each timelog to
     *   remove: - Set hrm_platform_timesheet_id to null 8. Recalculate
     *   total_hours by summing duration_minutes / 60.0 for all timelogs with
     *   hrm_platform_timesheet_id = timesheetId 9. Update
     *   hrm_platform_timesheets.total_hours and updated_at fields. 10. Return
     *   the updated timesheet with current timelogs included.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":timesheetId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformTimesheet.IUpdate,
  ): Promise<IHrmPlatformTimesheet> {
    try {
      return await putHrmPlatformMemberTimesheetsTimesheetId({
        member,
        timesheetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a timesheet by its identifier. Only draft or rejected timesheets can be deleted. Submitted timesheets must first be rejected to transition back to a modifiable state. Approved timesheets are permanently locked and cannot be deleted to preserve the authoritative record of weekly work. The operation validates ownership or management permissions, checks status constraints, and cascades deletion to associated timelogs when safe.
   *
   * @param connection
   * @param timesheetId The unique UUID identifier of the timesheet to delete.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_timesheets for the timesheet
     *   by timesheetId.
   *
   * Validation:
   * - Verify timesheet exists
   * - Check authentication: requesting user must be the timesheet's employee OR have timesheet management permission
   * - Validate status constraint: only draft or rejected status timesheets can be deleted
   *   - If status is 'submitted': reject with error requiring rejection processing first to transition to draft
   *   - If status is 'approved': reject with error indicating approved timesheets are permanently locked
   * - For draft/rejected timesheets, proceed with deletion
   *
   * Cascade deletion:
   * - Delete all timelogs in hrm_platform_timelogs that belong to this timesheet
   * - Since draft/rejected timesheets have mutable timelogs not part of approved records, cascading is safe
   * - Verify timelogs are not referenced by other approved timesheets before deletion
   *
   * Transaction: wrap timesheet and timelog deletions in a single transaction for atomicity.
   *
   * Return null on successful deletion.
   *
   * Error cases:
   * - 404 if timesheet not found
   * - 403 if user lacks permission or timesheet belongs to another employee without management access
   * - 409 if timesheet is in submitted state (must reject first)
   * - 409 if timesheet is in approved state (permanently locked)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":timesheetId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberTimesheetsTimesheetId({
        member,
        timesheetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
