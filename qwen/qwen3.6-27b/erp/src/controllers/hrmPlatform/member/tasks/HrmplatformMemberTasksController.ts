  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformTask.IUpdate,
  ): Promise<IHrmPlatformTask> {
    try {
      return await putHrmPlatformMemberTasksTaskId({
        member,
        taskId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete a task within the current organization context, permanently removing it from active views while preserving the record with a deletion timestamp.
   *
   * This operation validates the organizational scope through the active session, verifies project ownership, and enforces several business constraints: tasks with associated timelogs cannot be deleted (to preserve time tracking history), tasks that serve as parents to subtasks cannot be deleted (to prevent accidental cascade of soft deletes), and tasks with active timers running against them cannot be deleted.
   *
   * Only the organization owner or managers with appropriate permissions can delete tasks. Regular employees can only edit tasks they are assigned to. Successful deletion archives the record with a deleted_at timestamp, making it invisible in standard task listings, searches, and reports.
   *
   * Attempting to delete a task that has already been deleted returns a not-found error.
   *
   * @param connection
   * @param taskId UUID of the task to soft-delete (scoped to the current organization context).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Soft-delete operation for hrm_platform_tasks.
   *
   * 1. **Organization Scope**: Verify the current member has an active organization context and the task belongs to a project within that organization.
   *
   * 2. **Task Retrieval**: Query hrm_platform_tasks WHERE id = :taskId AND deleted_at IS NULL in a single SELECT. Include project_id for scope verification.
   *
   * 3. **Ownership Validation**: Verify the task's project belongs to the member's active organization. The member must have Owner or Manager role in the organization, or be the task's assigned employee (for Manager/Employee roles, they can only erase tasks they own/are assigned to).
   *
   * 4. **Timelog Constraint Check**: Query hrm_platform_timelogs for any records where task_id = :taskId AND deleted_at IS NULL. If any exist, reject with an associated timelog prevention error (409 Conflict). This preserves time tracking history.
   *
   * 5. **Subtask Protection Check**: Query hrm_platform_tasks for any records where parent_id = :taskId AND deleted_at IS NULL. If any exist, reject with a subtask dependency error (409 Conflict). Deleting a parent task should not cascade soft-delete its children.
   *
   * 6. **Active Timer Check**: Query hrm_platform_timers for any records where task_id = :taskId (if such a field exists in the timer schema). If an active timer references this task, reject with a timer conflict error.
   *
   * 7. **Execution**: Set deleted_at = NOW() on the task record. This soft-deletes it, making it invisible in normal queries.
   *
   * 8. **Activity Log**: Record an activity_log entry with action type for task deletion, including task_id, project_id, performed_by, and timestamp.
   *
   * 9. **Return**: Return 204 No Content (null response body) on success.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":taskId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberTasksTaskId({
        member,
        taskId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
