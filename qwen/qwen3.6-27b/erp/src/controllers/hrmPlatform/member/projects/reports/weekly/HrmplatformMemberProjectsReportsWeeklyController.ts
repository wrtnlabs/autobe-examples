import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIHrmPlatformProjectWeeklySummary } from "../../../../../../api/structures/IPageIHrmPlatformProjectWeeklySummary";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberProjectsProjectIdReportsWeekly } from "../../../../../../providers/getHrmPlatformMemberProjectsProjectIdReportsWeekly";

@Controller("/hrmPlatform/member/projects/:projectId/reports/weekly")
export class HrmplatformMemberProjectsReportsWeeklyController {
  /**
   * Retrieves paginated week-by-week aggregated time tracking data for a specific project, grouping timelogs by week (Monday through Sunday).
   *
   * Returns weekly summary records with total hours logged, timelog entry count, and distinct employee participation count for each week.
   *
   * Results are ordered by week_start in descending order (most recent weeks first). The endpoint supports cursor-based pagination for navigating large historical datasets.
   *
   * Requires valid project UUID in the path. Returns 404 if the project does not exist or has been soft-deleted.
   *
   * @param connection
   * @param projectId UUID identifier of the project to retrieve weekly time tracking report data for.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_timelogs for timelogs where
     *   hrm_platform_project_id matches the projectId parameter AND deleted_at
     *   IS NULL. GROUP BY week_start (Monday of the week), calculating: -
     *   week_start: Monday timestamp for each week - week_end: Sunday timestamp
     *   for each week - total_hours: SUM(duration_minutes) / 60 converted to
     *   hours - timelogs_count: COUNT of timelog entries for the week -
     *   employee_count: COUNT DISTINCT hrm_platform_employee_id
   *
   * ORDER BY week_start DESC (most recent weeks first)
   * Apply cursor-based pagination for large result sets, returning matching paginated structure with total count, page size, and cursor fields.
   * Return 404 NOT_FOUND if the project does not exist or has been soft-deleted (deleted_at IS NOT NULL).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
  ): Promise<IPageIHrmPlatformProjectWeeklySummary.ISummary> {
    try {
      return await getHrmPlatformMemberProjectsProjectIdReportsWeekly({
        member,
        projectId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
