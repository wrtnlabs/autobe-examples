  /**
   * Create a project membership by assigning an active employee to a project with a specified capacity role.
   *
   * This operation establishes the formal association between an employee and a project, enabling authorized participation in project activities such as time tracking and task assignment. The capacity role determines the employee's permissions within the project — project leads can manage tasks while regular members can only view tasks and log time.
   *
   * The system validates that the employee is active, belongs to the same organization as the project, and is not already assigned to this project. Only users with the project:manage permission can create project memberships.
   *
   * @param connection
   * @param projectId UUID of the project to assign the employee to
   * @param body Employee assignment details including the employee UUID and the capacity role (member or project-lead) for the new project membership.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate path parameter projectId exists and
     *   belongs to current organization context 2. Validate request body
     *   contains employeeId (UUID) and capacityRole (member or project-lead) 3.
     *   Query hrm_platform_employees by employeeId to: a. Verify employee
     *   exists and is not soft-deleted b. Verify employee status is 'active'
     *   (reject if 'deactivated') c. Verify employee belongs to same
     *   organization as the project 4. Check hrm_platform_project_memberships
     *   for existing record with same [employeeId, projectId] composite key —
     *   reject if found 5. Verify current user has project:manage permission
     *   within the organization 6. Insert new record into
     *   hrm_platform_project_memberships with: - id: generate UUID -
     *   hrm_platform_employee_id: from request - hrm_platform_project_id: from
     *   path parameter - capacity_role: from request (member or project-lead) -
     *   created_at: current timestamp - updated_at: current timestamp -
     *   deleted_at: null 7. Return the created membership record with all
     *   fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
