  /**
   * Retrieves a single project membership record.
   *
   * This endpoint retrieves a particular project membership association between an employee and a project within an organization context.
   *
   * Use Cases:
   *
   * - Confirming an employee's role in a specific project
   * - Viewing detailed membership information for audit purposes
   * - Verifying membership existence before modifications
   * - Project leads can manage task assignments and permissions
   *
   * Access Control:
   *
   * - Users can view memberships if they belong to the project's organization
   * - Project members can view memberships in projects they join
   * - Manager or Owner roles have broader visibility across organization projects
   * - The record must not be soft-deleted (deleted_at IS NULL)
   *
   * @param connection
   * @param projectId Unique identifier of the project that this membership belongs to
   * @param membershipId Unique identifier of the project membership to retrieve
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_project_memberships table with
     *   the following logic:
   *
   * 1. Input Validation:
   *    - Ensure projectId is a valid UUID
   *    - Ensure membershipId is a valid UUID
   *
   * 2. Authorization:
   *    - Ensure the user has access to the project (is a member of the project OR is a manager/owner in the current organization)
   *    - The project belongs to the same organization as the current user's organization
   *
   * 3. Query Execution:
   *    SELECT * FROM hrm_platform_project_memberships
   *    WHERE id = {membershipId}
   *    AND hrm_platform_project_id = {projectId}
   *    AND deleted_at IS NULL
   *
   * 4. Validate record exists:
   *    - Return 404 Not Found if query returns null or deleted_at is not null
   *
   * 5. Return response:
   *    - Return single IHrmPlatformProjectMembership object with all fields from the database
   *
   * Edge Cases:
   * - Not exists: Return 404 if no matching record found
   * - Soft deleted: Return 404 if deleted_at is not null
   * - Wrong org: Return 403 if project belongs to a different organization than the current user's org
   * - Invalid UUID: Return 400 if either UUID format is invalid
   * - Permission denied: Return 403 if user lacks permissions
   *
   * Database Schema:
   * Table: hrm_platform_project_memberships
   * - id: Primary key (UUID)
   * - hrm_platform_employee_id: Foreign key to employees (UUID)
   * - hrm_platform_project_id: Foreign key to projects (UUID)
   * - capacity_role: String (member or project-lead)
   * - created_at: DateTime
   * - updated_at: DateTime
   * - deleted_at: DateTime? (soft delete)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
