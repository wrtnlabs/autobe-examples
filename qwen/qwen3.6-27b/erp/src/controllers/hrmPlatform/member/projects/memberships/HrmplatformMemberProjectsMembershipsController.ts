  /**
   * Remove a project membership by soft-deleting the employee-project association record, preventing the employee from further engaging in project activities such as time tracking and task assignment.
   *
   * This operation requires the project:manage permission. The system prevents removal when associated timelogs exist to preserve time tracking attribution integrity. Upon successful deletion, the membership record remains in the database with a deleted_at timestamp, maintaining historical audit trail while disabling active participation.
   *
   * @param connection
   * @param projectId UUID of the project containing this membership
   * @param membershipId UUID of the project membership to remove
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_project_memberships table for
     *   the membership record where id matches membershipId and
     *   hrm_platform_project_id matches projectId.
   *
   * Validation steps:
   * 1. Confirm the authenticated user has project:manage permission in the current organization context
   * 2. Verify the membership exists and is not already soft-deleted (deleted_at IS NULL)
   * 3. Check that no timelogs exist in hrm_platform_timelogs table referencing both this membership's employee (hrm_platform_employee_id) and project (hrm_platform_project_id)
   * 4. If any validation fails, reject with appropriate error message
   *
   * Implementation:
   * - Set deleted_at to current timestamp (soft delete)
   * - Update updated_at timestamp
   * - Return the membership record with deleted_at populated
   * - Audit log the action in hrm_platform_activity_logs if configured for membership removal events
   *
   * Error conditions:
   * - 403 if user lacks project:manage permission
   * - 404 if membership not found or already deleted
   * - 409 if timelogs exist for this employee-project combination
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":membershipId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("membershipId")
    membershipId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberProjectsProjectIdMembershipsMembershipId(
        {
          member,
          projectId,
          membershipId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
