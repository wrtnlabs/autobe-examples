import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IBudgetUtilization } from "../../../../../api/structures/IBudgetUtilization";
import { IHrmPlatformProjectBudgetReport } from "../../../../../api/structures/IHrmPlatformProjectBudgetReport";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberProjectsProjectIdReportsBudget } from "../../../../../providers/getHrmPlatformMemberProjectsProjectIdReportsBudget";
import { getHrmPlatformMemberProjectsProjectIdReportsUtilization } from "../../../../../providers/getHrmPlatformMemberProjectsProjectIdReportsUtilization";

@Controller("/hrmPlatform/member/projects/:projectId/reports")
export class HrmplatformMemberProjectsReportsController {
  /**
   * Retrieve budget utilization report showing budget hours versus actual hours logged.
   *
   * Returns budget consumption statistics including total estimated budget hours, actual hours consumed by employees through timelogs, and calculated percentage utilization. Reports include employee breakdowns showing individual hours logged with timelog counts, and billable breakdowns separating client chargeable time from internal organizational work.
   *
   * Budget field represents planned effort in hours while duration_minutes in timelogs represents tracked time in minutes (divided by 60 for hours conversion). Utilization percentage indicates how much of the planned budget has been consumed. Projects with no timelog entries report zero actual hours and zero percent utilization. Projects with null budget fields report null utilization percentage.
   *
   * Employees can only view budget reports for projects where they hold active project membership. Managers can view budget reports for any project within their organization scope. Projects in archived or completed status still display budget utilization for historical reference.
   *
   * @param connection
   * @param projectId UUID of the project to retrieve budget utilization report for
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Join hrm_platform_projects with
     *   hrm_platform_timelogs where timelog hrm_platform_project_id matches.
     *   Filter project by UUID projectId and current organization context
     *   (hrm_platform_organization_id). Only include timelogs with null
     *   deleted_at to exclude deleted timelog entries. Calculate actual hours
     *   as sum(timelog.duration_minutes) / 60. Calculate utilization percent as
     *   (actual_hours / budget) * 100.0 if budget is not null. Handle null
     *   budget (set utilization to null). Handle no timelogs — actual hours =
     *   0. Group employee breakdowns by hrm_platform_employee_id, summing
     *   duration_minutes and counting timelog entries per employee. Group
     *   billable breakdowns by billable flag, summing duration_minutes and
     *   counting timelog entries for each billability. Return 404 if project
     *   not found or not in user's organization context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("budget")
  public async budget(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformProjectBudgetReport> {
    try {
      return await getHrmPlatformMemberProjectsProjectIdReportsBudget({
        member,
        projectId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve budget utilization metrics for a specific project, comparing budgeted hours against actual hours consumed.
   *
   * Returns the project's configured budget hours, the total actual hours logged by all timelog entries, and the calculated percentage of budget consumed. This endpoint aggregates timelog data across all non-deleted time entries associated with the project.
   *
   * If the project has no budget hours configured (budget is null), the report returns actual hours consumed with budgetHours and percentageConsumed set to null, indicating an unbudgeted project.
   *
   * All timelog entries are included in the calculation, including those associated with specific tasks within the project. Only non-deleted timelogs (deleted_at is null) are considered.
   *
   * @param connection
   * @param projectId The unique identifier of the project to retrieve budget utilization data for.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Extract projectId from path parameters and
     *   validate UUID format 2. Query hrm_platform_projects table for the
     *   project where id = projectId 3. Verify the project belongs to the
     *   user's active organization context (hrm_platform_organization_id
     *   matches) 4. Verify the project is not soft-deleted (deleted_at is null)
     *   5. Query hrm_platform_timelogs to aggregate actual hours: - Filter:
     *   hrm_platform_project_id = projectId AND deleted_at IS NULL - Sum
     *   duration_minutes field across all matching timelogs - Convert to hours
     *   by dividing by 60 - Include timelogs regardless of billable status or
     *   timesheet association 6. Retrieve budgetHours from project.budget field
     *   7. Calculate percentageConsumed: - If budgetHours > 0: (actualHours /
     *   budgetHours) * 100 - If budgetHours is null or 0: percentageConsumed is
     *   null 8. Return IBudgetUtilization response with: projectId, project
     *   name, budgetHours, actualHours, percentageConsumed
   *
   * Error handling:
   * - 404 if project not found
   * - 404 if project is soft-deleted
   * - 403 if project does not belong to user's organization
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("utilization")
  public async utilization(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
  ): Promise<IBudgetUtilization> {
    try {
      return await getHrmPlatformMemberProjectsProjectIdReportsUtilization({
        member,
        projectId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
