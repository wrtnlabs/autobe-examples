export async function test_api_project_time_report_without_budget(
  connection: api.IConnection,
) {
  // 1. Authenticate as member
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {});
  typia.assert(authorized);
  // 2. Create project without budget
  const project = await generate_random_hrm_platform_member_projects_create(
    memberConnection,
    {
      body: { budget: null } satisfies DeepPartial<IHrmPlatformProject.ICreate>,
    },
  );
  typia.assert(project);
  // 3. Retrieve time report for the project
  const report =
    await api.functional.hrmPlatform.member.projects.reports.time.timeReport(
      memberConnection,
      { projectId: project.id },
    );
  typia.assert(report);
}
