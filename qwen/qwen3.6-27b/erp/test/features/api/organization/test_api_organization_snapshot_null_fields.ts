export async function test_api_organization_snapshot_null_fields(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as a member via join (creates a default organization)
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      display_name: "Test Member",
    },
  });
  // 2. Create a snapshot where optional configuration fields are NULL
  const snapshot =
    await api.functional.hrmPlatform.organizations.snapshots.create(
      memberConnection,
      {
        organizationId: authorized.id,
        body: typia.random<IHrmPlatformOrganizationSnapshot>(),
      },
    );
  // 3. Verify the snapshot correctly captures the organization's current state
  typia.assert(snapshot);
}