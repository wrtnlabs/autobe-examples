export async function test_api_product_image_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Setup: Create a seller account and generate a product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 2. Test: Attempt to retrieve a non-existent image for the product
  // Use a fabricated UUID that doesn't exist in the system
  const fakeImageId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "should return error for non-existent product image",
    async () => {
      await api.functional.ecommerceMall.products.images.at(connection, {
        productId: product.id,
        imageId: fakeImageId,
      });
    },
  );
}
