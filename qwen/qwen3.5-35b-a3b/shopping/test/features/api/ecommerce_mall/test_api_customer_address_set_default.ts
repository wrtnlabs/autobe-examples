export async function test_api_customer_address_set_default(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer authentication
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customer);
  // 2. Create shipping address
  const address =
    await generate_random_ecommerce_mall_customer_addresses_create(
      customerConnection,
      {
        body: {
          recipient_name: RandomGenerator.name(),
          recipient_phone: RandomGenerator.mobile(),
          street: RandomGenerator.paragraph({ sentences: 3 }),
          city: RandomGenerator.paragraph({ sentences: 2 }),
          state: RandomGenerator.paragraph({ sentences: 2 }),
        },
      },
    );
  typia.assert(address);
  // 3. Set address as default
  const result =
    await api.functional.ecommerceMall.customer.addresses._default.setDefault(
      customerConnection,
      {
        addressId: address.id,
      },
    );
  typia.assert(result);
  // 4. Validate response
  TestValidator.equals("is_default should be true", result.is_default, true);
}
