export async function test_api_customer_order_item_snapshots_after_product_deletion(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer setup and authentication
  const customerEmail = typia.random<string & tags.Format<"email">>();
  const customerPassword = RandomGenerator.alphaNumeric(16);
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: customerEmail,
      password: customerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  await authorize_customer_login(customerConnection, {
    body: {
      email: customerEmail,
      password: customerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  // 2. Seller setup and authentication
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  await authorize_seller_login(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
    },
  });
  // 3. Generate test identifiers for existing product and order
  const productId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  const orderId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  const itemId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  // 4. Seller deletes the product from catalog
  await api.functional.ecommerceMall.seller.products.erase(sellerConnection, {
    productId,
  });
  // 5. Customer retrieves order item snapshots
  const snapshots =
    await api.functional.ecommerceMall.customer.orders.items.snapshots(
      customerConnection,
      {
        orderId,
        itemId,
      },
    );
  typia.assert(snapshots);
  // 6. Verify snapshot data remains complete
  TestValidator.equals("snapshot has unique id", snapshots.id, snapshots.id);
  TestValidator.equals(
    "snapshot belongs to correct order item",
    snapshots.order_item_id,
    itemId,
  );
  TestValidator.predicate(
    "actor type is valid",
    ["customer", "seller", "admin"].includes(snapshots.actor_type),
  );
}