export async function test_api_customer_refund_request_authorization_boundary(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register first customer (refund request owner)
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customerA);
  // 2. Register second customer (attempting unauthorized access)
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB = await authorize_customer_join(customerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customerB);
  // 3. Test unauthorized access to another customer's refund request
  // Using a random UUID that customer B does not own
  const refundRequestId = typia.random<string & tags.Format<"uuid">>();
  // 4. Customer B attempts to access a refund request they don't own
  // Should return 404 Not Found
  await TestValidator.httpError(
    "unauthorized access to another customer's refund request returns 404",
    404,
    async () => {
      await api.functional.ecommerceMall.customer.refund_requests.at(
        customerBConnection,
        { refundRequestId },
      );
    },
  );
}
