export async function test_api_seller_ban_subtype_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator joins the system
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_administrator_join(adminConnection, {
    body: {
      display_name: RandomGenerator.name(2),
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      grade: "regular",
    } satisfies IEcommerceMallAdministrator.IJoin,
  });
  typia.assert(adminAuth);
  // 2. Generate a random UUID that does not exist in the system
  const invalidUuid = typia.random<string & tags.Format<"uuid">>();
  // 3. Make GET request with invalid UUID and verify 404 response
  await TestValidator.httpError(
    "should return 404 for non-existent ban subtype",
    [404],
    async () => {
      await api.functional.ecommerceMall.administrator.user_ban_of_sellers.at(
        adminConnection,
        {
          banOfSellerId: invalidUuid,
        },
      );
    },
  );
}
