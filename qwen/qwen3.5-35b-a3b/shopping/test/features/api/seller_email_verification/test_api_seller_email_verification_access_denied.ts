export async function test_api_seller_email_verification_access_denied(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create seller A account and get authentication
  const sellerAConnection: api.IConnection = { host: connection.host };
  const sellerA = await authorize_seller_join(sellerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(sellerA);
  // 2. Create seller B account and get authentication
  const sellerBConnection: api.IConnection = { host: connection.host };
  const sellerB = await authorize_seller_join(sellerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(sellerB);
  // 3. Seller A attempts to access seller B's email verification record
  // This should fail with 403 Forbidden due to insufficient permissions
  // Use a random UUID as the verification ID to ensure it doesn't belong to seller A
  await TestValidator.error(
    "seller A cannot access another seller's email verification record",
    async () => {
      await api.functional.ecommerceMall.seller.email_verifications.at(
        sellerAConnection,
        {
          verificationId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
