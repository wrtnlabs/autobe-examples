export async function test_api_order_item_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer account
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallMember.IJoin,
  });
  typia.assert(memberAuth);
  // 2. Generate a non-existent UUID and attempt to retrieve the order item
  const nonExistentId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to retrieve the non-existent order item - should return 404
  await TestValidator.httpError(
    "non-existent order item returns 404",
    404,
    async () =>
      await api.functional.ecommerceMall.member.order_items.getById(
        memberConnection,
        {
          id: nonExistentId,
        },
      ),
  );
}
