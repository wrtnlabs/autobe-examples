export async function test_api_admin_order_item_status_history_no_items(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  // 2. Test with a randomly generated order ID
  // Since we don't have order creation utilities, we test the endpoint's response structure
  const orderId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  // 3. Call the status history endpoint with the order ID
  const result =
    await api.functional.ecommerceMall.admin.orders.items.status_history.statusHistory(
      adminConnection,
      {
        orderId,
      },
    );
  typia.assert(result);
  // 4. Validate that the response has a valid structure with empty status history
  // This tests the endpoint's ability to handle orders with no items
  TestValidator.equals(
    "empty status history array",
    result.statusHistory,
    [] as IEcommerceMallOrder.IStatusHistoryEntry[],
  );
}