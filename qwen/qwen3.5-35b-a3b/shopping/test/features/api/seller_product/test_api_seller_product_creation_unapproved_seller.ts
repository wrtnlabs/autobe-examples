export async function test_api_seller_product_creation_unapproved_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new seller (approval status will be 'pending')
  const joinConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(joinConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(seller);
  // Verify seller has pending approval status
  TestValidator.equals(
    "seller approval status is pending",
    seller.approval_status,
    "pending",
  );
  // 2. Create actor-specific connection for unapproved seller
  const unapprovedSellerConnection: api.IConnection = { host: connection.host };
  unapprovedSellerConnection.headers = { Authorization: seller.token.access };
  // 3. Attempt to create a product with unapproved seller
  // This should fail with 403 Forbidden because seller is not approved
  await TestValidator.error(
    "unapproved seller cannot create products",
    async () => {
      await generate_random_ecommerce_mall_seller_products_create(
        unapprovedSellerConnection,
        {},
      );
    },
  );
}
