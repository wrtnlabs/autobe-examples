export async function test_api_seller_refund_request_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(2),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  // 2. Get seller ID for authorization
  const sellerAuthorized = await authorize_seller_login(sellerConnection, {
    body: {
      email: sellerConnection.headers?.Authorization as string,
      password: "1234",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(sellerAuthorized);
  // 3. Try to retrieve non-existent refund request
  const invalidId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "should return 404 for non-existent refund request",
    404,
    async () => {
      await api.functional.ecommerceMall.seller.refund_requests.at(
        sellerConnection,
        {
          id: invalidId,
        },
      );
    },
  );
}