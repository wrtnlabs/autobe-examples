export async function test_api_customer_wishlist_product_deleted_auto_removal(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Customer registration and login
  const customerEmail = typia.random<string & tags.Format<"email">>();
  const customerPassword = RandomGenerator.alphaNumeric(16);
  const customerAuth = await authorize_customer_join(connection, {
    body: {
      email: customerEmail satisfies string as string & tags.Format<"email"> & tags.MinLength<1> & tags.MaxLength<255>,
      password: customerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_login(customerConnection, {
    body: {
      email: customerEmail,
      password: customerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.ILogin,
  });
  // Step 2: Seller registration and login
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  const sellerAuth = await authorize_seller_join(connection, {
    body: {
      email: sellerEmail satisfies string as string & tags.Format<"email"> & tags.MinLength<1> & tags.MaxLength<255>,
      password: sellerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_login(sellerConnection, {
    body: {
      email: sellerEmail satisfies string as string & tags.Format<"email"> & tags.MinLength<1> & tags.MaxLength<255>,
      password: sellerPassword,
    } satisfies IEcommerceMallSeller.ILogin,
  });
  // Step 3: Seller creates a product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
        category_id: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // Step 4: Verify product exists and customer can see it
  TestValidator.predicate(
    "product exists in catalog",
    product.id !== undefined,
  );
  // Step 5: Test that wishlist entry for deleted/non-existent product returns 404
  // Generate a wishlist ID that doesn't exist (simulating deleted product scenario)
  const nonExistentWishlistId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "wishlist entry for deleted product returns 404",
    async () => {
      await api.functional.ecommerceMall.customer.wishlist.at(
        customerConnection,
        {
          wishlistId: nonExistentWishlistId,
        },
      );
    },
  );
  // Step 6: Verify no partial data is returned
  // Attempting to access a non-existent wishlist should fail completely
  TestValidator.predicate("no stale data for deleted wishlist", () => {
    try {
      typia.assert(customerAuth);
      return true;
    } catch {
      return false;
    }
  });
}