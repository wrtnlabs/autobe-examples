export async function test_api_super_administrator_retrieve_unbanned_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate super administrator
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_super_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      display_name: RandomGenerator.name(2),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(adminAuth);
  // 2. Generate a random UUID for a ban subtype ID that is unbanned (soft-deleted)
  const banOfSellerId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve the unbanned ban subtype record
  // This should return 404 because soft-deleted records are excluded from queries
  await TestValidator.httpError(
    "unbanned ban subtype should return 404",
    [404],
    async () => {
      await api.functional.ecommerceMall.superAdministrator.user_ban_of_sellers.at(
        adminConnection,
        { banOfSellerId },
      );
    },
  );
}