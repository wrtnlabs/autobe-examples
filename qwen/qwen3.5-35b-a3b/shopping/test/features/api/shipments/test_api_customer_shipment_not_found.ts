export async function test_api_customer_shipment_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer setup - register and authenticate
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>() ?? undefined,
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customer);
  // 2. Generate valid UUID format but non-existent shipment ID
  const nonExistentShipmentId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve non-existent shipment - expect 404
  await TestValidator.httpError(
    "should return 404 for non-existent shipment",
    404,
    async () => {
      await api.functional.ecommerceMall.customer.shipments.at(
        customerConnection,
        {
          shipmentId: nonExistentShipmentId,
        },
      );
    },
  );
}
