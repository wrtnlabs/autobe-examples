export async function test_api_seller_approval_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Create a new seller account and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "SecurePass123!",
      display_name: RandomGenerator.name(2),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(seller);
  // Generate a UUID that does not exist in the database
  const nonExistentRequestId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to retrieve the non-existent approval request
  // This should return a 404 error
  await TestValidator.httpError(
    "should return 404 for non-existent approval request",
    404,
    async () =>
      await api.functional.ecommerceMall.seller.seller_approvals.at(
        sellerConnection,
        {
          requestId: nonExistentRequestId,
        },
      ),
  );
}
