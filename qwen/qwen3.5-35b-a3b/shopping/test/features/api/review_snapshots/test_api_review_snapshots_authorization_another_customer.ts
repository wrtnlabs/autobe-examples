export async function test_api_review_snapshots_authorization_another_customer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer A registers
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customerA);
  // 2. Customer B registers
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB = await authorize_customer_join(customerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customerB);
  // 3. Customer A creates a review
  const review: IEcommerceMallReview =
    await api.functional.ecommerceMall.customer.reviews.create(
      customerAConnection,
      {
        body: {
          rating: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
          body: RandomGenerator.paragraph({ sentences: 5 }),
          product_id: typia.random<string & tags.Format<"uuid">>(),
          order_id: typia.random<string & tags.Format<"uuid">>(),
        } satisfies IEcommerceMallReview.ICreate,
      },
    );
  typia.assert(review);
  // 4. Customer B attempts to retrieve snapshots for Customer A's review
  // The system should reject this with 403 Forbidden or 404 Not Found
  await TestValidator.error(
    "another customer cannot access review snapshots",
    async () => {
      await api.functional.ecommerceMall.customer.reviews.snapshots.index(
        customerBConnection,
        {
          reviewId: review.id,
          body: {},
        },
      );
    },
  );
}
