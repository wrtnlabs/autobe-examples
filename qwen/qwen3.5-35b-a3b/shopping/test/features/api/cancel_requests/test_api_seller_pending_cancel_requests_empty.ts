export async function test_api_seller_pending_cancel_requests_empty(
  connection: api.IConnection,
): Promise<void> {
  // 1. Setup: Register and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(2),
    },
  });
  typia.assert(sellerAuth);
  // 2. Setup: Register and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_member_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
    },
  });
  typia.assert(customerAuth);
  // 3. Setup: Seller creates a product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 4. Setup: Seller creates a product variant
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          stock_quantity: 10,
        },
      },
    );
  typia.assert(variant);
  // 5. Setup: Customer creates an order with the variant
  const order = await generate_random_ecommerce_mall_member_orders_create(
    customerConnection,
    {
      body: {
        order_items: [
          {
            product_variant_id: variant.id,
            quantity: 1,
          },
        ],
      },
    },
  );
  typia.assert(order);
  // 6. Test: Seller calls pending cancellation requests endpoint
  const pendingRequests =
    await api.functional.ecommerceMall.seller.seller.cancel_requests.pending.index(
      sellerConnection,
      {
        body: {
          limit: 20,
        },
      },
    );
  typia.assert(pendingRequests);
  // 7. Verify: Empty data array
  TestValidator.equals(
    "pending cancellation requests",
    pendingRequests.data,
    [],
  );
  // 8. Verify: Correct pagination metadata
  TestValidator.equals(
    "pagination current page",
    pendingRequests.pagination.current,
    1,
  );
  TestValidator.equals(
    "pagination limit",
    pendingRequests.pagination.limit,
    20,
  );
  TestValidator.equals(
    "pagination records",
    pendingRequests.pagination.records,
    0,
  );
  TestValidator.equals("pagination pages", pendingRequests.pagination.pages, 0);
}
