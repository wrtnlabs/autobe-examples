export async function test_api_product_snapshot_empty_state(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - register and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  // 2. Seller setup - register and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  // 3. Create product as seller (no edits made yet)
  const product: IEcommerceMallProduct =
    await generate_random_ecommerce_mall_seller_products_create(
      sellerConnection,
      {
        body: {
          name: RandomGenerator.paragraph({ sentences: 2 }),
          description: RandomGenerator.paragraph({ sentences: 5 }),
          base_price: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<100>
          >(),
          category_id: typia.random<string & tags.Format<"uuid">>(),
        } satisfies IEcommerceMallProduct.ICreate,
      },
    );
  typia.assert(product);
  // 4. Query snapshots as admin for newly created product (empty history)
  const snapshots: IPageIEcommerceMallProductSnapshot.ISummary =
    await api.functional.ecommerceMall.admin.products.snapshots.index(
      adminConnection,
      {
        productId: product.id,
        body: {},
      },
    );
  typia.assert(snapshots);
  // 5. Validate empty data array
  TestValidator.equals(
    "snapshots data is empty for new product",
    snapshots.data.length,
    0,
  );
  // 6. Validate pagination metadata
  TestValidator.equals(
    "pagination current page is 1",
    snapshots.pagination.current,
    1,
  );
  TestValidator.equals(
    "pagination records count is 0",
    snapshots.pagination.records,
    0,
  );
  TestValidator.equals(
    "pagination pages count is 0",
    snapshots.pagination.pages,
    0,
  );
  TestValidator.equals(
    "pagination limit is set",
    snapshots.pagination.limit,
    snapshots.pagination.limit,
  );
}
