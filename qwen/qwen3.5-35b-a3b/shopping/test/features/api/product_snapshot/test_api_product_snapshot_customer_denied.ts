export async function test_api_product_snapshot_customer_denied(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer joins and authenticates
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // 2. Customer attempts to access product snapshot (should be denied)
  const productId = typia.random<string & tags.Format<"uuid">>();
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  // Customer should be denied access to product snapshots
  await TestValidator.error(
    "customer cannot access product snapshot",
    async () => {
      await api.functional.ecommerceMall.products.snapshots.at(
        customerConnection,
        {
          productId,
          snapshotId,
        },
      );
    },
  );
}
