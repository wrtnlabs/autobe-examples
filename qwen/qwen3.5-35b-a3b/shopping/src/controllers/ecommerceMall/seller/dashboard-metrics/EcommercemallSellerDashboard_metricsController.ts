import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSellerDashboardMetric } from "../../../../api/structures/IEcommerceMallSellerDashboardMetric";
import { IPageIEcommerceMallSellerDashboardMetric } from "../../../../api/structures/IPageIEcommerceMallSellerDashboardMetric";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerDashboardMetricsMetricsId } from "../../../../providers/getEcommerceMallSellerDashboardMetricsMetricsId";
import { patchEcommerceMallSellerDashboardMetrics } from "../../../../providers/patchEcommerceMallSellerDashboardMetrics";

@Controller("/ecommerceMall/seller/dashboard-metrics")
export class EcommercemallSellerDashboard_metricsController {
  /**
   * Retrieve seller dashboard metrics with optional filtering and pagination.
   *
   * This operation retrieves dashboard metrics data for sellers, including product counts, order counts, and pending request statistics. The metrics are pre-calculated aggregations from related entities (products, order_items, cancellation_requests, refund_requests) and are updated when those records change.
   *
   * ### Features
   * - **Search Filtering**: Filter metrics by date ranges or metric thresholds
   * - **Pagination**: Support for paginated results to handle large datasets efficiently
   * - **Sorting**: Sort results by various metric fields including product count, order item count, or timestamps
   * - **Authorized Access**: Only authenticated sellers can access their own dashboard metrics
   *
   * ### Security
   * - Sellers can only view their own dashboard metrics (not other sellers')
   * - Authentication is required to access this endpoint
   * - Metrics data is pre-calculated for performance and read-only
   *
   * @param connection
   * @param body Search criteria including date range filters, metric value thresholds, pagination parameters, and sorting options.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_seller_dashboard_metrics table with pagination and filtering.
   *
   * 1. Extract seller_id from authentication context (JWT token payload) - the requesting seller's ID
   * 2. Filter by seller_id = authenticated user's seller_id (enforce seller-only access to their own metrics)
   * 3. Apply optional filters on:
   *    - date range on created_at or updated_at
   *    - product_count threshold (gte, lte)
   *    - order_item_count threshold (gte, lte)
   *    - pending_cancellation_count threshold
   *    - pending_refund_count threshold
   * 4. Apply sorting by specified fields (product_count, order_item_count, pending_cancellation_count, pending_refund_count, created_at, updated_at) with direction (asc/desc)
   * 5. Implement cursor-based pagination with page cursor and page limit parameters
   * 6. Calculate total count for pagination metadata
   * 7. Return paginated list of metric summaries
   *
   * Edge Cases:
   * - No metrics found: Return empty array with pagination metadata showing 0 total
   * - Invalid cursor: Return error with appropriate status code
   * - Unauthorized access: Return 403 Forbidden
   * - Invalid filter values: Return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSellerDashboardMetric.IRequest,
  ): Promise<IPageIEcommerceMallSellerDashboardMetric.ISummary> {
    try {
      return await patchEcommerceMallSellerDashboardMetrics({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve seller dashboard metrics for a specific metrics record.
   *
   * Returns complete dashboard metrics data including product count, order item count, pending cancellation requests, and pending refund requests for the specified metrics record. This operation provides sellers with summary statistics about their business performance.
   *
   * The metrics are aggregated from related entities and updated when those records change, providing real-time business insights.
   *
   * @param connection
   * @param metricsId Unique identifier for the dashboard metrics record (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_seller_dashboard_metrics table by id.
   *
   * 1. Validate metricsId is a valid UUID format
   * 2. Fetch the metrics record where id = metricsId
   * 3. Return 404 if record not found
   * 4. Include soft-deleted check - if deleted_at is not null, return 404
   * 5. Return full metrics object with all fields: id, seller_id, product_count, order_item_count, pending_cancellation_count, pending_refund_count, created_at, updated_at
   * 6. No authorization required beyond seller authentication (seller must own this metrics record via seller_id)
   *
   * Edge cases:
   * - metricsId does not exist: return 404 Not Found
   * - metrics record is soft-deleted: return 404 Not Found
   * - Seller tries to access another seller's metrics: return 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":metricsId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("metricsId")
    metricsId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSellerDashboardMetric> {
    try {
      return await getEcommerceMallSellerDashboardMetricsMetricsId({
        seller,
        metricsId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
