import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallProductVariantSnapshot } from "../../../../../../api/structures/IEcommerceMallProductVariantSnapshot";
import { IPageIEcommerceMallProductVariantSnapshot } from "../../../../../../api/structures/IPageIEcommerceMallProductVariantSnapshot";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerProductsProductIdVariantsVariantIdSnapshotsSnapshotId } from "../../../../../../providers/getEcommerceMallSellerProductsProductIdVariantsVariantIdSnapshotsSnapshotId";
import { patchEcommerceMallSellerProductsProductIdVariantsVariantIdSnapshots } from "../../../../../../providers/patchEcommerceMallSellerProductsProductIdVariantsVariantIdSnapshots";

@Controller(
  "/ecommerceMall/seller/products/:productId/variants/:variantId/snapshots",
)
export class EcommercemallSellerProductsVariantsSnapshotsController {
  /**
   * Retrieve all snapshots of a product variant with pagination, filtering, and sorting.
   *
   * This endpoint returns the complete audit history of a specific product variant, showing all changes made to the variant's SKU code, option values, price, and stock quantity over time.
   *
   * ### Access Control
   * - Product owners (sellers) can view snapshots of their own products' variants
   * - Administrators can view snapshots of any product variant
   *
   * ### Snapshot Content
   * Each snapshot includes the SKU code, option values, price, and stock quantity as they existed at the time of the change. Snapshots are immutable and cannot be deleted, preserving the complete modification history.
   *
   * @param connection
   * @param productId UUID identifier of the parent product. The variant must belong to this product.
   * @param variantId UUID identifier of the product variant whose snapshots are being retrieved.
   * @param body Search criteria including pagination parameters, date range filters for snapshot creation time, and sorting options.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_mall_product_variant_snapshots
     *   table filtered by product_id and product_variant_id.
   *
   * 1. Validate that productId and variantId are valid UUIDs
   * 2. Verify variant belongs to the specified product (product_id matches)
   * 3. Verify seller owns the product (for seller authorization) or admin has oversight rights
   * 4. Apply pagination with default page size of 20, maximum 100
   * 5. Apply optional filters on created_at date range
   * 6. Apply optional sorting by created_at (ascending/descending)
   * 7. Return cursor-based pagination for efficient large result sets
   * 8. Each snapshot record includes: id, sku_code, option_values, price, stock_quantity, created_at
   * 9. Join with ecommerce_mall_products to verify product exists and ownership
   * 10. Join with ecommerce_mall_sellers to verify seller ownership when needed
   * 11. Validate that product_variant_id matches the given productId's variants
   * 12. Return 404 if product or variant not found
   * 13. Return 403 if unauthorized to view the snapshots
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallProductVariantSnapshot.IRequest,
  ): Promise<IPageIEcommerceMallProductVariantSnapshot.ISummary> {
    try {
      return await patchEcommerceMallSellerProductsProductIdVariantsVariantIdSnapshots(
        {
          seller,
          productId,
          variantId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific product variant snapshot by its unique identifier.
   *
   * Returns the complete snapshot record preserving the variant state at the time of the original modification, including SKU code, option values, price, stock quantity, and timestamps.
   *
   * Access is restricted to:
   * - The product owner (seller) who can view snapshots of their own product variants
   * - Platform administrators who can view snapshots of any variant for oversight purposes
   *
   * Snapshots are immutable historical records and cannot be modified or deleted once created.
   *
   * @param connection
   * @param productId UUID of the parent product that contains this variant. Used for access validation and hierarchical navigation.
   * @param variantId UUID of the product variant that this snapshot belongs to. Must match the variant reference in the snapshot.
   * @param snapshotId UUID of the specific variant snapshot to retrieve. This is the immutable snapshot identifier created when the variant was last modified.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_mall_product_variant_snapshots
     *   table for the snapshot with the given snapshotId.
   *
   * Authorization:
   * - Seller owner: Verify authenticated user is the seller_id recorded in this snapshot
   * - Administrator: Any administrator can view any variant snapshot
   *
   * Validation:
   * - Confirm the snapshot's product_id matches the productId path parameter
   * - Confirm the snapshot's product_variant_id matches the variantId path parameter
   * - Return 404 if snapshot not found or ID mismatch
   *
   * Data returned includes:
   * - All variant snapshot fields: sku_code, option_values, price, stock_quantity
   * - Timestamps: created_at, updated_at
   * - Related references: product_variant_id, product_id, seller_id
   *
   * Error handling:
   * - 404 Not Found: Snapshot does not exist or belongs to different product/variant
   * - 401 Unauthorized: No authentication provided
   * - 403 Forbidden: User is not the seller owner and is not an administrator
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallProductVariantSnapshot> {
    try {
      return await getEcommerceMallSellerProductsProductIdVariantsVariantIdSnapshotsSnapshotId(
        {
          seller,
          productId,
          variantId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
