  /**
   * Retrieve a filtered and paginated list of historical snapshots for a specific product variant.
   *
   * This operation returns all snapshots associated with a given product variant, preserving the complete state history of the variant including SKU code, option values, pricing, stock quantity, and availability status at each point in time. Snapshots are immutable records created whenever a variant is modified, enabling audit trails and dispute resolution.
   *
   * Sellers can only view snapshots of their own product variants, while administrators have access to view snapshots of any variant on the platform for oversight and compliance purposes. The response includes snapshot metadata such as creation timestamp, change type, and the full state captured at that moment.
   *
   * Supports advanced filtering including change type (created, updated, deleted) and date range queries. Results are paginated using cursor-based pagination to efficiently handle large historical datasets.
   *
   * @param connection
   * @param productId ID of the parent product
   * @param variantId ID of the target variant
   * @param body Search criteria and pagination parameters for variant snapshots
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_product_variant_snapshots table with filters and pagination.
   *
   * Apply filters on change_type (created/updated/deleted) and date range (created_at).
   * Join with ecommerce_mall_product_variants to verify variant ownership.
   * Apply authorization: sellers can only view variants they own, administrators have full access.
   * Verify variant ownership through product ownership.
   * Order results by created_at descending (newest first).
   * Implement cursor-based pagination using created_at for efficient large result set handling.
   * Denormalized options field stored as JSON string - return as string in response.
   * Return snapshot ID, product ID, variant ID, SKU code, options, price, stock quantity, status, and created timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
