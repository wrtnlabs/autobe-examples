import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallStatus } from "../../../../api/structures/IEcommerceMallStatus";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerStatus } from "../../../../providers/getEcommerceMallSellerStatus";

@Controller("/ecommerceMall/seller/status")
export class EcommercemallSellerController {
  /**
   * Retrieve the current operational status and health information of the ecommerce mall platform.
   *
   * This endpoint provides a comprehensive overview of platform availability and key business metrics. It returns the current status of all business categories including order statuses (paid, shipped, delivered, cancelled, refunded, partially completed) and shipment statuses (created, in transit, delivered) as defined in the business rules.
   *
   * The status information is useful for monitoring platform health, troubleshooting issues, and providing external services with real-time platform state information. All status values are derived from the actual database state and reflect the current operational condition of the system.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query system health indicators and business status aggregates. Return platform availability status, active order counts by status, active shipment counts by status, and overall system health score. This endpoint should be lightweight and fast to respond as it may be called frequently by monitoring systems and health check probes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async status(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IEcommerceMallStatus.ISummary> {
    try {
      return await getEcommerceMallSellerStatus({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
