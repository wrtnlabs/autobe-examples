import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShopProfileSnapshot } from "../../../../api/structures/IEcommerceMallShopProfileSnapshot";
import { IPageIEcommerceMallShopProfileSnapshot } from "../../../../api/structures/IPageIEcommerceMallShopProfileSnapshot";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerShopProfileSnapshotsSnapshotId } from "../../../../providers/getEcommerceMallSellerShopProfileSnapshotsSnapshotId";
import { patchEcommerceMallSellerShopProfileSnapshots } from "../../../../providers/patchEcommerceMallSellerShopProfileSnapshots";

@Controller("/ecommerceMall/seller/shop-profile-snapshots")
export class EcommercemallSellerShop_profile_snapshotsController {
  /**
   * Retrieve paginated list of shop profile snapshots with search, filtering, and sorting capabilities.
   *
   * Search and filter shop profile snapshots by shop profile ID, date ranges, or shop name. Results are paginated with cursor-based navigation for efficient large result set handling. Only authorized users (shop owner or administrator) can access these snapshots.
   *
   * Snapshots represent immutable audit records of shop profile modifications including shop name, shop description, and logo image changes. Each snapshot preserves the state at the time of modification.
   *
   * @param connection
   * @param body Search criteria including shop profile ID filter, date range for created_at, shop name text search, pagination parameters, and sorting options.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_mall_shop_profile_snapshots table
     *   with pagination and filtering.
   *
   * Filtering:
   * - Apply filter on ecommerce_mall_shop_profile_id (exact match)
   * - Apply date range filter on created_at (start/end datetime)
   * - Apply text search on shop_name (case-insensitive contains)
   *
   * Sorting:
   * - Default sort: created_at descending (newest first)
   * - Support sort by created_at ascending
   * - Support sort by id ascending
   *
   * Authorization:
   * - Seller: only return snapshots where ecommerce_mall_shop_profile_id matches their shop profile
   * - Administrator: return all snapshots
   *
   * Pagination:
   * - Cursor-based pagination using created_at or id
   * - Support limit/limit size control
   *
   * Join Considerations:
   * - If shop profile data needed for enriched response, join with ecommerce_mall_shop_profiles for shop details
   * - Otherwise return snapshot summary only
   *
   * Error Handling:
   * - Return 404 if requested shop profile_id does not exist (for seller scope filter)
   * - Return 403 if seller attempts to access another seller's snapshots
   * - Return 401 if not authenticated
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallShopProfileSnapshot.IRequest,
  ): Promise<IPageIEcommerceMallShopProfileSnapshot.ISummary> {
    try {
      return await patchEcommerceMallSellerShopProfileSnapshots({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single shop profile snapshot by its unique identifier.
   *
   * This operation returns a shop profile snapshot that was created when a seller modified their shop profile. The snapshot preserves the shop name, shop description, and logo image as they existed at the time of modification, providing an immutable record for audit purposes, dispute resolution, and historical tracking.
   *
   * Access is restricted to the shop owner (seller) who owns the profile and to platform administrators who can view snapshots for dispute resolution and platform oversight. Attempting to access a snapshot owned by another seller will result in an authorization error.
   *
   * @param connection
   * @param snapshotId The unique identifier of the shop profile snapshot to retrieve (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_mall_shop_profile_snapshots table
     *   by id UUID.
   *
   * 1. Extract snapshotId from path parameter and validate it is a valid UUID format.
   * 2. Query the database to find the snapshot record with matching id.
   * 3. If not found, return 404 Not Found with error message.
   * 4. Fetch the related shopProfile relation to include shop profile reference if needed.
   * 5. Check authorization:
   *    - If requesting user is a seller and the snapshot's ecommerce_mall_shop_profile_id matches their seller id, allow access.
   *    - If requesting user is an administrator, allow access.
   *    - Otherwise, return 403 Forbidden with error message.
   * 6. Return the snapshot record with all fields: id, ecommerce_mall_shop_profile_id, shop_name, shop_description, logo_url, created_at.
   *
   * Edge cases:
   * - Snapshot remains accessible even if the seller account is deleted.
   * - Snapshots are immutable - no update or delete operations allowed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShopProfileSnapshot> {
    try {
      return await getEcommerceMallSellerShopProfileSnapshotsSnapshotId({
        seller,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
