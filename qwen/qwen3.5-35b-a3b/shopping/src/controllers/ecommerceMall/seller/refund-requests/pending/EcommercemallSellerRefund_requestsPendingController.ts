import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallRefundRequest } from "../../../../../api/structures/IEcommerceMallRefundRequest";
import { IPageIEcommerceMallRefundRequest } from "../../../../../api/structures/IPageIEcommerceMallRefundRequest";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerRefundRequestsPending } from "../../../../../providers/patchEcommerceMallSellerRefundRequestsPending";

@Controller("/ecommerceMall/seller/refund-requests/pending")
export class EcommercemallSellerRefund_requestsPendingController {
  /**
   * Retrieve a list of pending refund requests awaiting seller response for the authenticated seller's products.
   *
   * This operation returns all refund requests with 'pending' status that were submitted by customers for order items containing the seller's products. Each refund request includes the customer's refund reason, evidence description, delivery date, and the refund request code for reference.
   *
   * The refund request status 'pending' indicates the seller has not yet approved or rejected the refund request. Sellers must review each request and take action through the approve or reject operations. The seller can view customer-provided reasons and any evidence descriptions to make informed decisions.
   *
   * This endpoint is restricted to seller actors only. Customers cannot view pending refund requests through this endpoint - they should use their own refund request listing to see the status of their submissions.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for pending refund requests
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_refund_requests table where status='pending' and the refund request's order item belongs to a product owned by the authenticated seller.
   *
   * Join with:
   * - ecommerce_mall_refund_requests.customer for customer name and email
   * - ecommerce_mall_refund_requests.ecommerce_mall_order_item_id -> ecommerce_mall_order_items.product_snapshot_id -> ecommerce_mall_products.seller_id
   *
   * Filter conditions:
   * - refund_requests.status = 'pending'
   * - order_items.seller_snapshot_id = seller's id (or match via product snapshot to seller)
   * - refund_requests.deleted_at IS NULL (exclude soft-deleted requests)
   *
   * Apply search filters from requestBody on customer name, email, refund reason, delivery date range, and submitted date range.
   *
   * Order results by submitted_at descending (most recent first), then by created_at descending.
   *
   * Return paginated list with:
   * - Page number and size from requestBody
   * - Total count for pagination metadata
   * - Array of refund request summaries
   *
   * Authorization: Seller actor only. The seller_id from JWT token determines which seller's products are included in results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallRefundRequest.IRequest,
  ): Promise<IPageIEcommerceMallRefundRequest.ISummary> {
    try {
      return await patchEcommerceMallSellerRefundRequestsPending({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
