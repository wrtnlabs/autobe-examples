  /**
   * Retrieve a filtered and paginated list of order item snapshot records.
   *
   * This endpoint provides access to immutable audit snapshots that capture order item status changes triggered by cancellation or refund request approvals. Each snapshot preserves the before-and-after status values, the triggering request reference, the seller who processed the change, and the timestamp of the change.
   *
   * Snapshots serve critical purposes in dispute resolution, compliance auditing, and historical tracking of order item lifecycle. The system ensures these records remain immutable once created, providing a trusted source of truth for order status transitions.
   *
   * Supports comprehensive filtering by order item, triggering request type, seller, status changes, and date ranges. Customers can view snapshots for their own order items, sellers can view snapshots they processed, and administrators have full access to all snapshots including soft-deleted records.
   *
   * The response includes paginated snapshot summaries with essential status change information, optimized for list display in audit trails and dispute resolution workflows.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for order item snapshot queries
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_order_item_snapshots table with pagination and filtering.
   *
   * Apply search filters:
   * - order_item_id: exact match UUID filter
   * - cancellation_request_id: exact match UUID filter for snapshots triggered by cancellations
   * - refund_request_id: exact match UUID filter for snapshots triggered by refunds
   * - changed_by_seller_id: seller ID filter for snapshots processed by specific seller
   * - old_status: filter by status before change (paid, shipped, delivered, cancelled, refunded)
   * - new_status: filter by status after change (paid, shipped, delivered, cancelled, refunded)
   * - change_reason: text search in change reason field
   * - created_at_from: filter snapshots created after this datetime
   * - created_at_to: filter snapshots created before this datetime
   * - include_deleted: include soft-deleted snapshots (admin only)
   *
   * Apply sorting:
   * - sortBy: 'createdAt', 'old_status', 'new_status', 'changed_by_seller_id'
   * - sortOrder: 'asc', 'desc'
   *
   * Apply pagination:
   * - page: 1-based page number
   * - pageSize: number of items per page (max 100)
   *
   * Return:
   * - cursor-based pagination for large result sets
   * - snapshot summary data excluding sensitive internal fields
   * - total count and pagination metadata
   *
   * Authorization:
   * - Customers: can only view snapshots where order_item belongs to their orders
   * - Sellers: can only view snapshots where changed_by_seller_id matches their ID
   * - Admins: can view all snapshots with optional include_deleted
   *
   * Edge Cases:
   * - No matching results: return empty data array with pagination metadata
   * - Invalid UUID: reject with validation error
   * - Invalid datetime format: reject with validation error
   * - Unauthorized access: reject with 403 error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
