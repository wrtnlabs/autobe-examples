import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallShippingAnalytic } from "../../../../../api/structures/IEcommerceMallShippingAnalytic";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerAnalyticsShipping } from "../../../../../providers/getEcommerceMallSellerAnalyticsShipping";

@Controller("/ecommerceMall/seller/analytics/shipping")
export class EcommercemallSellerAnalyticsShippingController {
  /**
   * Retrieve comprehensive shipping analytics and metrics for monitoring delivery operations.
   *
   * This operation provides aggregated statistics about shipments including total shipment counts, delivery status breakdowns, carrier performance metrics, and average delivery times. The data is designed for dashboard displays and operational monitoring.
   *
   * The shipping analytics include metrics across all time periods or can be filtered by date range. Sellers can use this to track their shipment performance, while administrators can monitor overall platform shipping health.
   *
   * Data includes shipment status distributions (created, in-transit, delivered, cancelled), carrier usage statistics, and delivery timeline metrics. This information helps identify bottlenecks in the shipping process and monitor fulfillment performance.
   *
   * The endpoint returns summarized metrics rather than detailed shipment records. For individual shipment details, use the /shipments endpoint with specific shipment identifiers.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shipments table to calculate aggregated statistics:
   * 1. Count total shipments grouped by status (created, in-transit, delivered, cancelled)
   * 2. Calculate average delivery time for delivered shipments (from createdAt to confirmedDeliveryAt)
   * 3. Group shipments by carrier to show usage distribution
   * 4. Calculate delivery success rate as percentage of delivered shipments
   * 5. Filter by optional date range if query parameters provided
   * 6. Return aggregated metrics in structured format
   *
   * No write operations - purely analytical query. Data comes from ecommerce_mall_shipments table joined with shipment_items where needed for delivery confirmation tracking.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IEcommerceMallShippingAnalytic> {
    try {
      return await getEcommerceMallSellerAnalyticsShipping({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
