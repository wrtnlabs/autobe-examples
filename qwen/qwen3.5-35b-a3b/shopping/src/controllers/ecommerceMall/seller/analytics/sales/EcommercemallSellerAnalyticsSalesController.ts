import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSalesAnalytic } from "../../../../../api/structures/IEcommerceMallSalesAnalytic";
import { IPageIEcommerceMallSalesAnalytic } from "../../../../../api/structures/IPageIEcommerceMallSalesAnalytic";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerAnalyticsSales } from "../../../../../providers/patchEcommerceMallSellerAnalyticsSales";

@Controller("/ecommerceMall/seller/analytics/sales")
export class EcommercemallSellerAnalyticsSalesController {
  /**
   * Retrieve comprehensive sales analytics and summary statistics for a seller's dashboard.
   *
   * This operation provides aggregated metrics for a seller's shop performance including product count, order item statistics, and pending request counts.
   *
   * The response includes:
   * - Total number of products created by the seller
   * - Count of order items for the seller's products
   * - Number of pending cancellation requests
   * - Number of pending refund requests
   *
   * The endpoint filters data based on the seller identity and calculates real-time statistics from the database.
   *
   * @param connection
   * @param body Search criteria and filters for sales analytics
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_sellers table to retrieve the seller by ID.
   * Join with ecommerce_mall_products to count the seller's products.
   * Join with ecommerce_mall_order_items to count order items for seller's products.
   * Join with ecommerce_mall_cancellation_requests to count pending cancellations (requestStatus = 'pending').
   * Join with ecommerce_mall_refund_requests to count pending refunds (requestStatus = 'pending').
   * Calculate all counts and return the aggregated statistics.
   * Ensure seller has 'approved' status before returning analytics.
   * Include error handling for sellers with no products or order items.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSalesAnalytic.IRequest,
  ): Promise<IPageIEcommerceMallSalesAnalytic.ISummary> {
    try {
      return await patchEcommerceMallSellerAnalyticsSales({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
