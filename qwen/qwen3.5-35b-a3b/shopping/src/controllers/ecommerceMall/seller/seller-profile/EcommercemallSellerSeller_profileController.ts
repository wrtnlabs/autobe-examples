import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallShopProfile } from "../../../../api/structures/IEcommerceMallShopProfile";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { putEcommerceMallSellerSellerProfile } from "../../../../providers/putEcommerceMallSellerSellerProfile";

@Controller("/ecommerceMall/seller/seller-profile")
export class EcommercemallSellerSeller_profileController {
  /**
   * Update the authenticated seller's shop profile including shop name, shop description, or logo image.
   *
   * All three fields are optional and can be updated independently. When any field is modified, the system automatically creates an immutable snapshot record preserving the previous values for audit trail purposes. This snapshot is stored in the shop profile snapshots table and remains accessible even after the seller account is deleted.
   *
   * The updated profile becomes immediately visible to customers viewing the seller's shop. The seller must be in approved status to manage their profile; pending or rejected sellers cannot modify their shop profile.
   *
   * @param connection
   * @param body Optional fields to update in the seller's shop profile. At least one field must be provided.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Extract seller ID from authenticated JWT token (do not use path parameter)
   * 2. Verify seller exists and approval_status = 'approved'
   * 3. Query ecommerce_mall_shop_profiles WHERE seller_id = [auth.sellerId]
   * 4. If profile not found, return 404 Not Found
   * 5. If profile exists and is soft-deleted (deleted_at not null), return 410 Gone
   * 6. Create snapshot BEFORE update:
   *    - Insert into ecommerce_mall_shop_profile_snapshots with current shop_name, shop_description, logo_url
   *    - Use current timestamp for created_at
   * 7. Update profile with new values (only fields provided in request body)
   * 8. Set updated_at to current timestamp
   * 9. Return full updated profile as response
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallShopProfile.IUpdate,
  ): Promise<IEcommerceMallShopProfile> {
    try {
      return await putEcommerceMallSellerSellerProfile({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
