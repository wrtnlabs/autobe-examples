import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShopProfile } from "../../../../api/structures/IEcommerceMallShopProfile";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerShopProfilesShopProfileId } from "../../../../providers/getEcommerceMallSellerShopProfilesShopProfileId";
import { patchEcommerceMallSellerShopProfiles } from "../../../../providers/patchEcommerceMallSellerShopProfiles";
import { putEcommerceMallSellerShopProfilesShopProfileId } from "../../../../providers/putEcommerceMallSellerShopProfilesShopProfileId";

@Controller("/ecommerceMall/seller/shop-profiles")
export class EcommercemallSellerShop_profilesController {
  /**
   * Update the authenticated seller's shop profile with new name, description, or logo.
   *
   * Sellers can modify any combination of shop profile fields at any time. The shop profile includes the shop name (public-facing business name), shop description (business background and policies), and logo image (brand visual identity). Any modification to these fields automatically creates an immutable snapshot record for audit trail purposes.
   *
   * Authentication Required: Seller role. Only the seller whose profile is being updated can access this endpoint.
   *
   * Change Tracking: Every edit creates exactly one snapshot regardless of how many fields are modified. Snapshots preserve the previous values and timestamp, enabling historical review and dispute resolution.
   *
   * Business Impact: Changes to the shop name and logo are immediately visible to customers viewing the seller's profile or products. Updated shop descriptions appear in product listings and seller information pages.
   *
   * @param connection
   * @param body Partial update object containing any combination of optional fields: shop_name, shop_description, or logo_url. At least one field must be provided. The shop_name is required to be 1-100 characters when provided and must be unique across all active seller shop profiles. The shop_description is optional up to 5000 characters. The logo_url is optional and must be a valid URI format.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification PATCH /shop-profiles implementation:
   *
   * 1. Authentication: Verify seller is authenticated and retrieve their seller_id from the session token.
   *
   * 2. Fetch current profile: Query ecommerce_mall_shop_profiles WHERE seller_id = {authenticated_seller_id}. If no profile exists, return 404 Not Found.
   *
   * 3. Validate ownership: Ensure the requesting seller owns this profile.
   *
   * 4. Parse request body: Accept partial update object with optional fields: shop_name?, shop_description?, logo_url?
   *
   * 5. Validate input constraints:
   *    - shop_name: If provided, 1-100 characters, cannot be empty or whitespace-only
   *    - shop_description: If provided, 0-5000 characters, can be null or empty string
   *    - logo_url: If provided, valid URI format (max 80000 characters per schema)
   *
   * 6. Check uniqueness: If shop_name is being changed, verify it's unique across all active seller shop profiles (excluding soft-deleted). If duplicate exists, return 409 Conflict.
   *
   * 7. Update profile: Execute UPDATE ecommerce_mall_shop_profiles SET shop_name, shop_description, logo_url (only for fields provided in request), updated_at = NOW() WHERE id = {profile_id}.
   *
   * 8. Create snapshot: INSERT INTO ecommerce_mall_shop_profile_snapshots with fields: ecommerce_mall_shop_profile_id, shop_name (old value), shop_description (old value), logo_url (old value), created_at = NOW(). The snapshot preserves the state BEFORE the update.
   *
   * 9. Return response: Return the updated profile with new values.
   *
   * Error Handling:
   * - 401 Unauthorized: Seller not authenticated
   * - 403 Forbidden: Seller attempting to update another seller's profile
   * - 404 Not Found: Shop profile not found for this seller
   * - 409 Conflict: New shop name already exists
   * - 400 Bad Request: Invalid input data (constraint violations)
   *
   * Edge Cases:
   * - Empty shop name change: If shop_name provided as empty string or whitespace, reject with 400
   * - Description set to null: Allowed - represents optional field cleared
   * - Logo URL update: Only valid URI accepted
   * - No fields provided: Return 400 Bad Request with error message requiring at least one field
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async patch(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallShopProfile.IUpdate,
  ): Promise<IEcommerceMallShopProfile> {
    try {
      return await patchEcommerceMallSellerShopProfiles({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a shop profile containing the seller's public business identity including shop name, description, and logo image.
   *
   * Returns the complete shop profile with all attributes including timestamps. The shop profile represents the seller's public-facing business presence on the platform, visible to customers browsing products and orders.
   *
   * @param connection
   * @param shopProfileId UUID identifier of the shop profile to retrieve
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_mall_shop_profiles table by id
     *   UUID. Return the full shop profile entity including id, seller_id,
     *   shop_name, shop_description, logo_url, created_at, updated_at, and
     *   deleted_at fields. If the shop profile does not exist (not found),
     *   return 404 error. Respect deleted_at field: if soft-deleted, return 404
     *   or include in response depending on business policy. Join with
     *   ecommerce_mall_sellers table if seller information is needed for the
     *   response, but do not include seller account credentials in the
     *   response. The shop profile contains public-facing business identity
     *   information only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shopProfileId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shopProfileId")
    shopProfileId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShopProfile> {
    try {
      return await getEcommerceMallSellerShopProfilesShopProfileId({
        seller,
        shopProfileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update seller's shop profile with new shop name, description, and/or logo image.
   *
   * Allows approved sellers to modify their public business identity on the platform. All three fields (shop_name, shop_description, logo_url) are optional and can be updated individually or together. Every successful update automatically creates an immutable snapshot preserving the previous state for audit purposes.
   *
   * @param connection
   * @param shopProfileId UUID of the shop profile to update. The shop profile must belong to the authenticated seller.
   * @param body Shop profile fields to update. All fields are optional - provide only the fields you want to change. Every update triggers automatic snapshot creation preserving previous state.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification 1. Verify shopProfileId exists in
     *   ecommerce_mall_shop_profiles table. 2. Verify the requesting seller
     *   owns this shop profile by matching seller_id (from authentication
     *   context) with shop_profile.seller_id. 3. Verify seller is approved
     *   (approval_status = 'approved' in ecommerce_mall_sellers). 4. Reject if
     *   seller is suspended (is_suspended = true). 5. Apply updates to
     *   shop_name, shop_description, logo_url fields from request body. 6. Set
     *   updated_at timestamp to current time. 7. Create snapshot record in
     *   ecommerce_mall_shop_profile_snapshots with: -
     *   ecommerce_mall_shop_profile_id = shopProfileId - shop_name = OLD value
     *   (before update) - shop_description = OLD value (before update) -
     *   logo_url = OLD value (before update) - created_at = NOW() 8. Return
     *   updated shop profile with new values.
   *
   * Error handling:
   * - 404 if shop profile not found
   * - 403 if seller does not own this shop profile
   * - 403 if seller is not approved or is suspended
   * - 422 if shop_name is empty or exceeds reasonable length (e.g., 200 chars)
   * - 422 if shop_description exceeds reasonable length (e.g., 5000 chars)
   * - 422 if logo_url format is invalid (must be valid URI)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shopProfileId")
  public async putByShopprofileid(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shopProfileId")
    shopProfileId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallShopProfile.IUpdate,
  ): Promise<IEcommerceMallShopProfile> {
    try {
      return await putEcommerceMallSellerShopProfilesShopProfileId({
        seller,
        shopProfileId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
