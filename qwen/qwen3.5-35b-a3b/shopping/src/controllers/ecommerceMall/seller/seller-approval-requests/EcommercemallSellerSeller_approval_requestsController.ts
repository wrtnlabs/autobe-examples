import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSellerApprovalRequest } from "../../../../api/structures/IEcommerceMallSellerApprovalRequest";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { postEcommerceMallSellerSellerApprovalRequests } from "../../../../providers/postEcommerceMallSellerSellerApprovalRequests";

@Controller("/ecommerceMall/seller/seller-approval-requests")
export class EcommercemallSellerSeller_approval_requestsController {
  /**
   * Submit a seller registration approval request to join the platform.
   *
   * A seller account (created during registration but awaiting approval) can submit an approval request by providing their reason for wanting to join the platform. This request enters a pending state and is reviewed by an administrator. The seller cannot list products or fulfill orders until the request is approved.
   *
   * Only one active approval request exists per seller at any time. If a previous request was rejected, the seller may submit a new request. Approved requests cannot be resubmitted.
   *
   * The approval status is visible to the seller at all times. Pending sellers cannot access seller dashboard features or create products.
   *
   * @param connection
   * @param body The seller's reason for wanting to join the platform as a seller.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Create a new seller approval request record in
     *   ecommerce_mall_seller_approval_requests table.
   *
   * 1. Validate that the authenticated seller has no active approval request (check @@unique([seller_id]) constraint - query for existing record where seller_id = {authenticated_user_id} AND status = 'pending' AND deleted_at IS NULL).
   *
   * 2. If an active pending request exists, return 409 Conflict with error message.
   *
   * 3. Create new record with:
   *    - id: generate UUID
   *    - seller_id: use authenticated seller's ID
   *    - reviewer_id: null (not yet reviewed)
   *    - status: 'pending'
   *    - request_reason: from request body
   *    - rejection_reason: null
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   *    - deleted_at: null
   *
   * 4. Return the created approval request record.
   *
   * 5. Create a snapshot (ecommerce_mall_seller_approval_requests_snapshots) capturing the initial state upon creation.
   *
   * Error handling:
   * - 409 Conflict: Seller already has an active pending approval request
   * - 401 Unauthorized: Not authenticated or authenticated user is not a seller
   * - 400 Bad Request: Empty or invalid request_reason
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSellerApprovalRequest.ICreate,
  ): Promise<IEcommerceMallSellerApprovalRequest> {
    try {
      return await postEcommerceMallSellerSellerApprovalRequests({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
