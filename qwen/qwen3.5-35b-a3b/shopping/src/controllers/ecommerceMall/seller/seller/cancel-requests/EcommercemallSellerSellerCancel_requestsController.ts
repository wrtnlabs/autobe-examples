import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCancellationRequest } from "../../../../../api/structures/IEcommerceMallCancellationRequest";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerSellerCancelRequestsRequestId } from "../../../../../providers/patchEcommerceMallSellerSellerCancelRequestsRequestId";

@Controller("/ecommerceMall/seller/seller/cancel-requests/:requestId")
export class EcommercemallSellerSellerCancel_requestsController {
  /**
   * Allows sellers to approve or reject customer cancellation requests for order items.
   *
   * This operation enables sellers to review cancellation requests and make a decision on whether to cancel the item and process a refund. Sellers can only respond to requests where the status is 'pending' and the request applies to order items they own.
   *
   * When a request is approved:
   * - The order item status changes to 'cancelled'
   * - Stock quantities are restored to inventory
   * - A refund is processed for the cancelled item
   * - The order status is updated if all items are cancelled
   *
   * When a request is rejected:
   * - The order item remains in its current status
   * - No refund is processed
   * - Stock quantities remain unchanged
   * - The customer is notified of the rejection
   *
   * A snapshot of the request state is created when the seller responds, preserving the original request details for audit purposes.
   *
   * @param connection
   * @param requestId UUID of the cancellation request to update.
   * @param body Update payload for cancellation request status and optional rejection reason.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Verify seller authentication and authorization - seller must own the order item associated with this cancellation request.
   * 2. Load the cancellation request by requestId and verify it exists and is not soft-deleted.
   * 3. Validate that the request status is 'pending' - cannot modify approved or rejected requests.
   * 4. Validate that the request applies to an order item owned by the authenticated seller.
   * 5. Validate the update payload:
   *    - status must be either 'approved' or 'rejected'
   *    - If status is 'rejected', seller_rejection_reason is optional but recommended
   * 6. If status is 'approved':
   *    - Update cancellation request status to 'approved'
   *    - Update order item status to 'cancelled'
   *    - Update order status based on aggregated item statuses
   *    - Restore stock quantities in inventory_records for the product variant
   *    - Process refund for the cancelled item amount
   *    - Set approved_at timestamp
   * 7. If status is 'rejected':
   *    - Update cancellation request status to 'rejected'
   *    - Update seller_rejection_reason if provided
   *    - Set rejected_at timestamp
   * 8. Create a snapshot of the cancellation request state using ecommerce_mall_cancellation_request_snapshots table, capturing:
   *    - Request title, body, reason, status
   *    - approved_at or rejected_at timestamp
   *    - seller_rejection_reason if provided
   * 9. Update the updated_at timestamp on the cancellation request.
   * 10. Return the updated cancellation request with all details including the order item information.
   *
   * Error cases:
   * - 404: Cancellation request not found or soft-deleted
   * - 403: Seller does not own this order item
   * - 409: Request is not in 'pending' status (already approved or rejected)
   * - 400: Invalid status value provided
   * - 401: Unauthorized - seller not authenticated or token expired
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallCancellationRequest.IUpdate,
  ): Promise<IEcommerceMallCancellationRequest> {
    try {
      return await patchEcommerceMallSellerSellerCancelRequestsRequestId({
        seller,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
