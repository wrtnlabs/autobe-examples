import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipment } from "../../../../../api/structures/IEcommerceMallShipment";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { postEcommerceMallSellerOrdersOrderIdShipments } from "../../../../../providers/postEcommerceMallSellerOrdersOrderIdShipments";

@Controller("/ecommerceMall/seller/orders/:orderId/shipments")
export class EcommercemallSellerOrdersShipmentsController {
  /**
   * Create a new shipment for order delivery tracking.
   *
   * This operation allows a seller to create a shipment containing one or more order items from their products. The shipment will be associated with the specified order and used to track package delivery to the customer.
   *
   * When creating a shipment, the seller must provide the carrier name and tracking number for delivery visibility. The system will mark all order items in the shipment as 'shipped' status and link them to the shipment record for tracking.
   *
   * Shipments are seller-scoped - a seller can only include order items from their own products. Different sellers in a multi-seller order must create separate shipments. The tracking information becomes immutable once the shipment is created.
   *
   * Customers can view shipment tracking information on their order detail page, including carrier name, tracking number, creation date, and which items are included in the shipment.
   *
   * @param connection
   * @param orderId The ID of the order to create shipment for
   * @param body Shipment creation data including carrier information and order items to include
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Create a new shipment record with the following business logic:
   *
   * 1. Authorization: Verify the authenticated user is a seller
   * 2. Validate order existence: Find order by {orderId}
   * 3. Filter order items: Query order_items for this order where item_status = 'paid' and the item's product belongs to the authenticated seller
   * 4. Validate seller ownership: Ensure all selected order items belong to the authenticated seller (reject if any item belongs to different seller)
   * 5. Validate item count: Ensure at least one order item is selected
   * 6. Create shipment record: Insert ecommerce_mall_shipments with order_id, seller_id, carrier_name, tracking_number, created_at
   * 7. Create junction records: For each order item, insert into ecommerce_mall_shipment_items linking the shipment and item
   * 8. Update item statuses: Update all selected order_items to set item_status = 'shipped'
   * 9. Return full shipment: Fetch and return the created shipment with included order items
   *
   * Error conditions:
   * - Order not found: 404 Not Found
   * - User not authorized: 403 Forbidden (must be seller who owns the order items)
   * - No eligible items: 400 Bad Request (no items in 'paid' status from this seller)
   * - Mixed seller items: 400 Bad Request (cannot include items from different sellers)
   * - Tracking number required: 400 Bad Request (tracking_number is required)
   * - Carrier name required: 400 Bad Request (carrier_name is required)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallShipment.ICreate,
  ): Promise<IEcommerceMallShipment> {
    try {
      return await postEcommerceMallSellerOrdersOrderIdShipments({
        seller,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
