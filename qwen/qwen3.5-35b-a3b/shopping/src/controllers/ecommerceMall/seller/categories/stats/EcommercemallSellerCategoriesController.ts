import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCategoriesStatistic } from "../../../../../api/structures/IEcommerceMallCategoriesStatistic";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerCategoriesCategoryIdStats } from "../../../../../providers/getEcommerceMallSellerCategoriesCategoryIdStats";

@Controller("/ecommerceMall/seller/categories/:categoryId/stats")
export class EcommercemallSellerCategoriesController {
  /**
   * Retrieve statistical metrics for a specific category including product counts, order statistics, and engagement data.
   *
   * **Purpose**:
   * This endpoint provides a comprehensive view of category performance and contents. It returns aggregated statistics that help administrators monitor category health and enables customers to understand category popularity.
   *
   * **Data Included**:
   * - Total number of products in the category
   * - Active and inactive product counts
   * - Total orders containing category products
   * - Total customers who purchased from this category
   * - Average product rating (if reviews exist)
   *
   * **Security**:
   * Access is granted to all authenticated users. Administrators see additional internal metrics.
   *
   * @param connection
   * @param categoryId UUID of the category to retrieve statistics for.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_categories table for the specified categoryId.
   *
   * **Database Operations**:
   * 1. Fetch category by UUID from ecommerce_mall_categories where id = {categoryId} AND deleted_at IS NULL
   * 2. Join with ecommerce_mall_products table to count products where category_id = {categoryId} AND deleted_at IS NULL
   * 3. Join with ecommerce_mall_order_items and ecommerce_mall_orders to count orders containing products from this category
   * 4. Aggregate review statistics from ecommerce_mall_reviews for products in this category
   * 5. Return aggregated statistics in ICategoriesStatistics.IStats format
   *
   * **Business Rules**:
   * - Category must be soft-deleted (deleted_at IS NULL) to return statistics
   * - If category is soft-deleted, return 404 Not Found
   * - Product counts should exclude soft-deleted products
   * - Empty categories (zero products) return valid stats with zero counts
   * - Guest users (if any) are not authenticated; require login
   *
   * **Edge Cases**:
   * - Category not found: Return 404
   * - Category with no products: Return valid statistics with zero counts
   * - Category with deleted_at set: Return 404
   * - Permission denied: Return 403 if user lacks authentication
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async stats(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCategoriesStatistic.IStat> {
    try {
      return await getEcommerceMallSellerCategoriesCategoryIdStats({
        seller,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
