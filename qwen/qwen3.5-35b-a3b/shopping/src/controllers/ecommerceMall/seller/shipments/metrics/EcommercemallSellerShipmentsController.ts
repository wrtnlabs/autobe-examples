import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallShipmentMetric } from "../../../../../api/structures/IEcommerceMallShipmentMetric";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerShipmentsMetrics } from "../../../../../providers/getEcommerceMallSellerShipmentsMetrics";

@Controller("/ecommerceMall/seller/shipments/metrics")
export class EcommercemallSellerShipmentsController {
  /**
   * Retrieve aggregated shipment statistics and performance metrics.
   *
   * **Metrics Overview**
   * - Total number of shipments in the system
   * - Count of shipments by status (shipped, delivered)
   * - Total order items shipped across all shipments
   * - Delivery rate and performance statistics
   *
   * **Data Scope**
   * - By default, returns metrics for the authenticated user's context (seller can view their own shipment metrics)
   * - Aggregated data from shipment records and shipment items
   * - Includes calculated statistics like delivery rates
   *
   * **Use Cases**
   * - Seller dashboard: view shipment performance and fulfillment metrics
   * - Customer overview: see delivery statistics for their orders
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_shipments table and calculate aggregated metrics.
   *
   * 1. Calculate total shipment count from ecommerce_mall_shipments.
   * 2. Count shipments grouped by status field (shipped, delivered).
   * 3. Sum quantity_shipped from ecommerce_mall_shipment_items for total items shipped.
   * 4. Calculate delivery rate as (delivered_shipments / total_shipments) * 100 if total_shipments > 0.
   * 5. If authenticated user is seller, filter metrics to their shipments only (WHERE seller_id = user_id).
   * 6. Calculate average shipped_at - created_at duration if data available.
   * 7. Return metrics as structured JSON object.
   *
   * Authorization: Seller can view their own shipment metrics. Customer can view delivery metrics for their orders.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async metrics(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IEcommerceMallShipmentMetric> {
    try {
      return await getEcommerceMallSellerShipmentsMetrics({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
