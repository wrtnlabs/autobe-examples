import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipment } from "../../../../api/structures/IEcommerceMallShipment";
import { IPageIEcommerceMallShipment } from "../../../../api/structures/IPageIEcommerceMallShipment";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerShipmentsShipmentId } from "../../../../providers/getEcommerceMallSellerShipmentsShipmentId";
import { patchEcommerceMallSellerShipments } from "../../../../providers/patchEcommerceMallSellerShipments";
import { postEcommerceMallSellerShipments } from "../../../../providers/postEcommerceMallSellerShipments";
import { putEcommerceMallSellerShipmentsShipmentId } from "../../../../providers/putEcommerceMallSellerShipmentsShipmentId";

@Controller("/ecommerceMall/seller/shipments")
export class EcommercemallSellerShipmentsController {
  /**
   * Create a new shipment for order items from a single seller.
   *
   * This operation allows sellers to create shipments for their order items that are in paid status. Each shipment represents a physical package being delivered to a customer and must contain only order items from the same seller. Different sellers always ship separately, even when their products are in the same customer order.
   *
   * When creating a shipment, the seller must provide carrier tracking information including the carrier name, and optionally the carrier phone number and website URL for tracking. All order items included in the shipment will share identical tracking information and will be marked as shipped once the shipment is created.
   *
   * The operation validates that all selected order items belong to the authenticated seller and have paid status (not cancelled, not shipped, and not refunded). Attempting to create shipments for order items from different sellers or with invalid statuses will result in a validation error.
   *
   * Upon successful creation, the system records the shipment with status 'pending', creates junction records linking the shipment to each order item in the ecommerce_mall_shipments_order_items table, and updates the status of all included order items to shipped. These order items can no longer be cancelled by the customer after being shipped.
   *
   * Related operations:
   * - GET /ecommerce_mall/seller/shipments - View shipments created by the seller
   * - GET /ecommerce_mall/seller/orders - View orders with items requiring shipping
   *
   * @param connection
   * @param body Shipment creation request with tracking information and order items to include
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Create a new shipment record for order items from a single seller.
   *
   * Service layer logic:
   * 1. Validate seller authorization - check that the authenticated seller is authorized to create shipments
   * 2. For each order item ID in the request:
   *    - Verify order item exists and is not soft-deleted
   *    - Verify order item's seller_snapshot_id matches the authenticated seller's ID
   *    - Verify order item status is 'paid' (not cancelled, not shipped, not refunded)
   *    - Ensure all order items in the request belong to the same seller
   * 3. Validate tracking information - at least carrier_name must be provided
   * 4. Create shipment record with status='pending', carrier information, and order item mappings
   * 5. Create shipment items records in ecommerce_mall_shipments_order_items junction table for each order item
   * 6. Update all included order items to status='shipped'
   * 7. Return the created shipment with all relationships loaded
   *
   * Database operations:
   * - INSERT into ecommerce_mall_shipments
   * - INSERT into ecommerce_mall_shipments_order_items (one record per order item)
   * - UPDATE ecommerce_mall_order_items set status='shipped' where id in request
   *
   * Business rules and validation:
   * - Reject if any order item is from a different seller
   * - Reject if any order item is cancelled, already shipped, or refunded
   * - Reject if tracking information is incomplete (carrier_name required)
   * - Prevent duplicate shipment creation for same order items
   *
   * Error handling:
   * - 400 Bad Request: Validation failures (wrong seller, invalid status, missing tracking)
   * - 404 Not Found: Order item or seller not found
   * - 409 Conflict: Order item already included in another shipment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallShipment.ICreate,
  ): Promise<IEcommerceMallShipment> {
    try {
      return await postEcommerceMallSellerShipments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of shipments for the authenticated seller with search, filter, and sort capabilities.
   *
   * This operation provides comprehensive shipment visibility for sellers to manage their fulfillment workflow. Sellers can view all shipments they have created, track their delivery status, monitor carrier information, and filter by various criteria such as status, date ranges, and carrier.
   *
   * The response includes essential shipment information optimized for list display, including status, carrier details, tracking count, and key timestamps. Each shipment can be accessed in detail via its individual detail endpoint.
   *
   * Sellers can only view their own shipments. The system enforces data isolation to prevent sellers from accessing another seller's fulfillment data. Shipments are automatically included in the results based on the seller_id relationship defined in the database schema.
   *
   * Related Operations:
   * - GET /shipments/{shipmentId} - View detailed information for a specific shipment
   * - GET /shipments/{shipmentId}/trackingCodes - View all tracking codes for a shipment
   * - GET /orders/{orderId}/shipments - View all shipments for a specific order
   * - PATCH /shipments - Create new shipment for order items (separate create endpoint)
   *
   * Search and Filter Capabilities:
   * Support filtering by shipment status (pending, in-transit, delivered, failed, cancelled), carrier name, date ranges for creation, shipping, and delivery timestamps. Optional sorting by any timestamp field or status.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering shipments
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_shipments table filtering by seller_id (from authenticated seller context) and optional search criteria.
   *
   * Business Logic:
   * 1. Filter shipments where ecommerce_mall_seller_id matches the authenticated seller's ID
   * 2. Apply optional filters: status, carrier_name, date ranges (shipped_at, delivered_at, created_at), order_id reference
   * 3. Join with ecommerce_mall_order_items via shipment_id to include item counts
   * 4. Join with tracking_codes table to summarize tracking count per shipment
   * 5. Support pagination with cursor-based or offset-based approach
   * 6. Support sorting by created_at (default), shipped_at, delivered_at, status
   * 7. Return summary fields optimized for list display
   *
   * Validation:
   * - Reject if seller attempts to access another seller's shipments
   * - Return empty list if no shipments match criteria
   * - Ensure all timestamps are returned in UTC ISO 8601 format
   *
   * Edge Cases:
   * - Handle shipments with null carrier information
   * - Handle shipments with no tracking codes yet
   * - Handle deleted_at timestamps for soft-deleted shipments (exclude from results)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallShipment.IRequest,
  ): Promise<IPageIEcommerceMallShipment.ISummary> {
    try {
      return await patchEcommerceMallSellerShipments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shipment in the marketplace.
   *
   * This operation returns the complete shipment record including carrier tracking information (carrier name, phone, website), current delivery status (pending, in-transit, delivered, failed, or cancelled), and temporal tracking fields (shipped_at, delivered_at, estimated_delivery_at). The response includes the delivery address and references to the parent order and fulfilling seller.
   *
   * Shipment information is primarily accessed by sellers who created the shipment (for fulfillment management), customers who are the recipients (for delivery tracking), and platform administrators (for logistics monitoring). The endpoint validates that the shipment exists and returns not found errors for invalid shipment IDs.
   *
   * This operation should be used after identifying a shipment through list operations (GET /shipments), or when direct shipment ID is available from order confirmation, customer account view, or seller dashboard.
   *
   * @param connection
   * @param shipmentId The unique identifier of the shipment to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_shipments table by id UUID parameter.
   *
   * Validation and Business Logic:
   * 1. Verify shipmentId is a valid UUID format
   * 2. Query shipment record by id (including deleted_at != null check for soft delete if actor permissions allow)
   * 3. If shipment not found, return 404 Not Found
   * 4. For soft-deleted shipments (deleted_at is not null), apply actor-specific access rules:
   *    - Admin/superAdmin: can view deleted shipments for audit purposes
   *    - Seller/customer: may have restricted access to deleted shipments
   * 5. Join with ecommerce_mall_orders to include order reference metadata if needed
   * 6. Join with ecommerce_mall_sellers to include seller reference metadata if needed
   * 7. Return shipment record with all fields (id, ecommerce_mall_order_id, ecommerce_mall_seller_id, carrier_name, carrier_phone, carrier_website, status, shipped_at, delivered_at, estimated_delivery_at, delivery_address, created_at, updated_at, deleted_at)
   *
   * Edge Cases:
   * - Shipment with null carrier fields: return entity with nullable values
   * - Shipment status: return as-is from database (pending, in-transit, delivered, failed, cancelled)
   * - Null temporal fields (shipped_at, delivered_at): return null values in response
   * - Soft-deleted shipment: apply actor-specific access control policy
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShipment> {
    try {
      return await getEcommerceMallSellerShipmentsShipmentId({
        seller,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shipment record with modified delivery information.
   *
   * This operation allows authorized sellers to update shipment details such as delivery address and estimated delivery date. Tracking information (carrier name, phone, website) cannot be modified after shipment creation per business rules.
   *
   * Authorized actors: seller (own shipments only), admin (all shipments)
   *
   * The operation validates that the requesting seller owns the shipment, that requested status transitions are valid, and that only updatable fields are modified. Tracking details (carrier_name, carrier_phone, carrier_website) are immutable after creation and will be rejected if included in the update payload.
   *
   * Related operations:
   * - GET /shipments/{shipmentId} - Retrieve current shipment details before updating
   * - PATCH /shipments - List shipments with filters for monitoring
   * - GET /shipments/{shipmentId}/trackingCodes - View tracking codes for the shipment
   *
   * @param connection
   * @param shipmentId UUID identifier of the shipment to update
   * @param body Update fields for the shipment. Only delivery_address and estimated_delivery_at can be modified. Tracking information (carrier_name, carrier_phone, carrier_website) is immutable after creation and will be rejected if included.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Validate authentication: requester must be seller or admin actor
   * 2. Load shipment by ID from ecommerce_mall_shipments
   * 3. Verify authorization: seller must own shipment (ecommerce_mall_seller_id == authenticated seller ID), admin can update any shipment
   * 4. Validate status transition: if status is being updated, check it's a valid transition from current status
   *    - Valid transitions: pending->in-transit, in-transit->delivered, in-transit->failed, pending->cancelled, in-transit->cancelled
   * 5. Filter update payload: reject any attempt to modify carrier_name, carrier_phone, carrier_website (tracking info is immutable)
   * 6. Update allowed fields only: delivery_address, estimated_delivery_at
   * 7. Set updated_at timestamp to current UTC time
   * 8. Create snapshot record in ecommerce_mall_shipment_snapshots before applying changes (audit trail)
   * 9. Apply UPDATE to ecommerce_mall_shipments table
   * 10. Return complete updated shipment object
   *
   * Error handling:
   * - 404 Not Found: shipment_id does not exist or has been soft deleted
   * - 403 Forbidden: seller attempting to update another seller's shipment
   * - 400 Bad Request: attempting to modify immutable tracking fields, invalid status transition, or invalid data formats
   * 11. Transaction: all changes must be atomic (shipment update + snapshot creation)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shipmentId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallShipment.IUpdate,
  ): Promise<IEcommerceMallShipment> {
    try {
      return await putEcommerceMallSellerShipmentsShipmentId({
        seller,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
