import typia, { tags } from "typia";

import { IEcommerceMallMember } from "../../../../api/structures/IEcommerceMallMember";
import { IPageIEcommerceMallMember } from "../../../../api/structures/IPageIEcommerceMallMember";
import { SuperadministratorAuth } from "../../../../decorators/SuperadministratorAuth";
import { SuperadministratorPayload } from "../../../../decorators/payload/SuperadministratorPayload";
