import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSeller } from "../../../../../api/structures/IEcommerceMallSeller";
import { IEcommerceMallSellerSession } from "../../../../../api/structures/IEcommerceMallSellerSession";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getEcommerceMallAdministratorSellersSellerIdSessionsSessionId } from "../../../../../providers/getEcommerceMallAdministratorSellersSellerIdSessionsSessionId";
import { patchEcommerceMallAdministratorSellersSellerIdSessions } from "../../../../../providers/patchEcommerceMallAdministratorSellersSellerIdSessions";

@Controller("/ecommerceMall/administrator/sellers/:sellerId/sessions")
export class EcommercemallAdministratorSellersSessionsController {
  /**
   * Revoke one or more seller sessions for security or account management purposes.
   *
   * This administrator operation allows forceful session termination for a seller, either targeting specific session tokens or all active sessions at once. The endpoint is typically used when a seller changes their password, gets banned, or needs immediate account security intervention.
   *
   * **Revocation Types**:
   * - Specific sessions: Target individual session IDs for granular control
   * - All sessions: Revoke every active session for the seller (full logout)
   *
   * **Security Considerations**:
   * - Only administrators can perform this operation
   * - Session revocation immediately invalidates access tokens
   * - Seller must re-authenticate to regain platform access
   * - Revoked sessions are marked with deleted_at timestamp for audit trail
   *
   * @param connection
   * @param sellerId The UUID of the seller whose sessions will be revoked.
   * @param body Session revocation request specifying which sessions to target.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification 1. Verify caller has administrator role
     *   (administrator or superAdministrator) 2. Validate sellerId matches
     *   existing ecommerce_mall_sellers record 3. Verify seller is not
     *   soft-deleted (deleted_at IS NULL) 4. Query
     *   ecommerce_mall_seller_sessions where: - ecommerce_mall_seller_id =
     *   sellerId - deleted_at IS NULL (active sessions only) 5. Apply
     *   revocation based on input: - If session_ids provided: update sessions
     *   with those IDs - If all flag set: update ALL active sessions for seller
     *   6. Update each target session: - Set deleted_at = current UTC timestamp
     *   - Set updated_at = current UTC timestamp 7. Clear/access tokens are
     *   automatically invalidated at JWT layer 8. Return list of revoked
     *   session IDs and counts
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async revoke(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallSeller.IRevokeSession,
  ): Promise<IEcommerceMallSeller.IRevokeSessionsResult> {
    try {
      return await patchEcommerceMallAdministratorSellersSellerIdSessions({
        administrator,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific seller session.
   *
   * Returns complete session data including authentication tokens, device information, IP address, referrer URL, and session timestamps. This operation is intended for administrative oversight and debugging purposes.
   *
   * The session data includes JWT tokens and other sensitive information, so this operation should only be accessible to authorized administrators with appropriate permissions. The seller and session must both exist and not be soft-deleted.
   *
   * @param connection
   * @param sellerId The unique identifier of the seller who owns this session.
   * @param sessionId The unique identifier of the session to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Query ecommerce_mall_seller_sessions table by
     *   session ID.
   *
   * 1. Validate that sessionId is a valid UUID format
   * 2. Validate that sellerId is a valid UUID format
   * 3. Verify the session exists and is not soft-deleted (deleted_at IS NULL)
   * 4. Verify the session belongs to the specified seller (ecommerce_mall_seller_id = sellerId)
   * 5. Return the full session entity including all fields
   * 6. If session not found or does not belong to seller, return 404 Not Found
   *
   * Implementation notes:
   * - Join or reference ecommerce_mall_sellers to verify seller exists if needed
   * - Check is_suspended status on seller account - session may still be valid but seller permissions restricted
   * - Tokens (access_token, refresh_token) should be included in response for audit purposes
   * - Return 404 if session is soft-deleted or does not exist
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSellerSession> {
    try {
      return await getEcommerceMallAdministratorSellersSellerIdSessionsSessionId(
        {
          administrator,
          sellerId,
          sessionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
