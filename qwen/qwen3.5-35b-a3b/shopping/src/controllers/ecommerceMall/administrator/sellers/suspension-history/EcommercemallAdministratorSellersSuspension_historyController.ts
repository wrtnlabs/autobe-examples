import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIEcommerceMallSellerSuspension } from "../../../../../api/structures/IPageIEcommerceMallSellerSuspension";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getEcommerceMallAdministratorSellersSellerIdSuspensionHistory } from "../../../../../providers/getEcommerceMallAdministratorSellersSellerIdSuspensionHistory";

@Controller("/ecommerceMall/administrator/sellers/:sellerId/suspension-history")
export class EcommercemallAdministratorSellersSuspension_historyController {
  /**
   * Retrieve the suspension history for a specific seller, including all suspension and unsuspension records with timestamps, reasons, and administrator actions.
   *
   * This endpoint provides administrators with a complete audit trail of when a seller was suspended or unsuspended, why each action was taken, and which administrator performed it. Suspended sellers' products are hidden from customer-facing search and category listings, but they can still process existing orders.
   *
   * Suspension records include:
   * - Suspension start timestamp (suspended_at)
   * - Resolution timestamp if unsuspended (resolved_at)
   * - Reason for suspension or unsuspension
   * - Administrator who performed the action
   *
   * @param connection
   * @param sellerId Unique identifier of the seller whose suspension history is being retrieved.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Query the ecommerce_mall_seller_suspensions table
     *   for all records where seller_id matches the provided UUID.
   *
   * Join with ecommerce_mall_administrators to retrieve the suspendedByAdmin details (name, email) for each suspension record.
   *
   * Sort by suspended_at in descending order (most recent first).
   *
   * Apply standard pagination: return page number, page size, total count, and the slice of records for the current page.
   *
   * Handle edge cases:
   * - If no suspension records exist for the seller, return empty page with total=0.
   * - Seller must exist in ecommerce_mall_sellers before querying suspension history.
   * - Verify caller has administrator or superAdministrator role before allowing access.
   * - Do not include soft-deleted suspension records (where deleted_at is not null).
   *
   * Business rules to enforce:
   * - Suspended sellers have their products hidden from customer search (per Section 785).
   * - Suspended sellers can still process existing orders and fulfill shipments (per Sections 784, 440).
   * - Suspension records are immutable audit trail data.
   *
   * Return suspension record summary with:
   * - id, seller_id, suspended_by_admin_id, suspended_at, resolved_at, reason, created_at
   * - suspendedByAdmin: { id, email, display_name }
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async history(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IPageIEcommerceMallSellerSuspension.ISummary> {
    try {
      return await getEcommerceMallAdministratorSellersSellerIdSuspensionHistory(
        {
          administrator,
          sellerId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
