import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallUserBan } from "../../../../../api/structures/IEcommerceMallUserBan";
import { IEcommerceMallUserBanRequest } from "../../../../../api/structures/IEcommerceMallUserBanRequest";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { patchEcommerceMallAdministratorUsersUserIdBan } from "../../../../../providers/patchEcommerceMallAdministratorUsersUserIdBan";

@Controller("/ecommerceMall/administrator/users/:userId/ban")
export class EcommercemallAdministratorUsersBanController {
  /**
   * Ban or unban a customer or seller account with reason tracking.
   *
   * Ban a user account to prevent login and platform access. When banning a customer, they cannot log in and existing cart is cleared, but order history remains accessible. When banning a seller, they cannot log in and cannot create/edit products, but existing orders remain valid.
   *
   * Unban a previously banned user account, immediately restoring their ability to log in and access platform features. The ban record is retained in the audit trail for compliance purposes.
   *
   * All ban/unban actions are logged with the administrator's identity, timestamp, and reason for audit purposes.
   *
   * @param connection
   * @param userId UUID of the user account to ban or unban
   * @param body Ban or unban action parameters including action type, user type, and ban reason.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Implement ban/unban operation for administrator
     *   accounts.
   *
   * Parameters:
   * - userId: UUID of user to ban/unban (customer or seller)
   * - user_type: 'customer' or 'seller' - determines which subtype table to reference
   *
   * Logic flow for BANNING:
   * 1. Verify administrator is authenticated and has authority
   * 2. Check if user exists (ecommerce_mall_members for customer or ecommerce_mall_sellers for seller)
   * 3. Check if user is already banned (query ecommerce_mall_user_bans with user_type, userId, deleted_at IS NULL)
   * 4. If already banned, return 409 Conflict with existing ban information
   * 5. Create new record in ecommerce_mall_user_bans:
   *    - Set administrator_id from authenticated admin
   *    - Set user_type from request parameter
   *    - Set reason from request body
   *    - Set banned_at to current timestamp
   *    - deleted_at = NULL (active ban)
   * 6. Create corresponding record in subtype table (ecommerce_mall_user_ban_of_customers or ecommerce_mall_user_ban_of_sellers):
   *    - Set ban_id to new ban record id (1:1 relationship)
   *    - Set customer_id or seller_id from userId parameter
   * 7. For customer ban: clear cart contents from cart table
   * 8. Return the created ban record with full details
   *
   * Logic flow for UNBANNING:
   * 1. Verify administrator is authenticated and has authority
   * 2. Query ecommerce_mall_user_bans for active ban (user_type, userId, deleted_at IS NULL)
   * 3. If no active ban found, return 404 Not Found
   * 4. Soft delete the ban record: set deleted_at to current timestamp
   * 5. Soft delete the subtype record: set deleted_at to current timestamp
   * 6. Return the updated ban record showing ban removed
   *
   * Error handling:
   * - 401 Unauthorized: Administrator not authenticated
   * - 403 Forbidden: Administrator lacks ban authority
   * - 404 Not Found: User or ban record not found
   * - 409 Conflict: User already banned
   * - 422 Unprocessable Entity: Invalid user_type or missing reason for ban action
   *
   * Validation:
   * - userId must be valid UUID format
   * - user_type must be 'customer' or 'seller'
   * - reason required when action='ban'
   * - action must be 'ban' or 'unban'
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallUserBanRequest,
  ): Promise<IEcommerceMallUserBan> {
    try {
      return await patchEcommerceMallAdministratorUsersUserIdBan({
        administrator,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
