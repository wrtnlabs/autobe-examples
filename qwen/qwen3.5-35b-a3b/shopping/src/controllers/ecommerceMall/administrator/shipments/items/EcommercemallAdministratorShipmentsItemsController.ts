import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipmentItem } from "../../../../../api/structures/IEcommerceMallShipmentItem";
import { IPageIEcommerceMallShipmentItem } from "../../../../../api/structures/IPageIEcommerceMallShipmentItem";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { patchEcommerceMallAdministratorShipmentsShipmentIdItems } from "../../../../../providers/patchEcommerceMallAdministratorShipmentsShipmentIdItems";

@Controller("/ecommerceMall/administrator/shipments/:shipmentId/items")
export class EcommercemallAdministratorShipmentsItemsController {
  /**
   * List all order items included in a shipment with filtering and pagination support.
   *
   * This endpoint allows sellers to view the complete list of order items that have been grouped into a specific shipment. The response includes summary information for each shipment item along with optional filtering by status, quantity ranges, and date ranges.
   *
   * @param connection
   * @param shipmentId UUID of the shipment to list items for. The requesting seller must own this shipment.
   * @param body Search and filter criteria for listing shipment items, including status filters, quantity ranges, date ranges, pagination, and sorting options.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query ecommerce_mall_shipment_items table filtered by shipment_id = {shipmentId}.
   *
   * Apply filters from request body:
   * - status: filter by shipment item status (pending, shipped, delivered, cancelled)
   * - quantity_shipped_min/max: filter by quantity shipped range
   * - created_at_range: filter by shipment creation date range
   * - sort_by: sort by created_at or quantity_shipped (ascending/descending)
   * - page/cursor: cursor-based pagination parameters
   *
   * Join with ecommerce_mall_order_items for order context if requested.
   *
   * Validate that the requesting seller owns this shipment (seller_id matches).
   *
   * Return paginated results with cursor-based pagination for efficient large result handling.
   *
   * Handle errors:
   * - 404 if shipmentId does not exist
   * - 403 if requester is not the shipment's seller
   * - 400 if filter parameters are invalid
   *
   * Include total count for pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallShipmentItem.IRequest,
  ): Promise<IPageIEcommerceMallShipmentItem.ISummary> {
    try {
      return await patchEcommerceMallAdministratorShipmentsShipmentIdItems({
        administrator,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
