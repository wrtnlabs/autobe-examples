import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrder } from "../../../../api/structures/IEcommerceMallOrder";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getEcommerceMallAdministratorOrdersId } from "../../../../providers/getEcommerceMallAdministratorOrdersId";
import { getEcommerceMallAdministratorOrdersOrderNumber } from "../../../../providers/getEcommerceMallAdministratorOrdersOrderNumber";

@Controller("/ecommerceMall/administrator/orders")
export class EcommercemallAdministratorOrdersController {
  /**
   * Retrieve a single order's complete details for viewing order history and status.
   *
   * This operation returns the full order entity including customer information, shipping address, all order items with product details and prices, and shipment tracking information. Customers can view their own orders while administrators have platform-wide access to all orders.
   *
   * The operation includes:
   * - Order metadata (number, status, total price, dates)
   * - Customer information (name, contact)
   * - Complete shipping address
   * - All order items with product names, variant options, quantities, and prices
   * - Shipment information with carrier and tracking numbers
   * - Delivery status per item
   *
   * This supports order history viewing, dispute resolution, and platform oversight.
   *
   * @param connection
   * @param id Unique identifier of the order to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Retrieve order by UUID and return full details
     *   with all related data.
   *
   * 1. Query ecommerce_mall_orders by id
   * 2. Join with ecommerce_mall_members to get customer information
   * 3. Join with ecommerce_mall_customer_addresses to get shipping address
   * 4. Query all ecommerce_mall_order_items for this order
   * 5. For each order item, join with ecommerce_mall_product_variants to get product details
   * 6. Join with ecommerce_mall_sellers for seller information on each item
   * 7. Query ecommerce_mall_shipments for this order
   * 8. Return complete order entity with all nested data
   *
   * Authorization:
   * - Customers: Only access orders where ecommerce_mall_member_id matches authenticated user
   * - Administrators: Access any order regardless of owner
   *
   * Return 404 if order not found or customer is not authorized.
   * Include deleted_at check - if non-null, return 404 (soft-deleted orders are not accessible).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async getById(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await getEcommerceMallAdministratorOrdersId({
        administrator,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single order by its order number with full details including order items, shipping address, and shipments.
   *
   * This operation returns complete order information for customers to view their purchase history or for administrators to monitor platform transactions. The order details include all line items with product information, variant options, quantities, and prices frozen at checkout time. Shipping address and shipment tracking information are included to provide full visibility into the order lifecycle.
   *
   * @param connection
   * @param orderNumber Unique business-readable order identifier. Format: typically includes date and sequence number (e.g., ORD-20240106-001234). Used for customer-facing order lookup.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Query ecommerce_mall_orders table by order_number
     *   field using exact match. Load the complete order record including all
     *   fields (id, member reference, address reference, order number, status,
     *   total price, timestamps). Join with ecommerce_mall_order_items to fetch
     *   all line items for this order, including variant details, product
     *   information, quantities, and individual item status. Join with
     *   ecommerce_mall_customer_addresses to load the frozen shipping address
     *   at order creation. Join with ecommerce_mall_shipments to retrieve all
     *   shipments associated with this order, including tracking information
     *   and carrier details. Return the aggregated order structure with all
     *   related data. If order is not found (order_number does not exist),
     *   return 404 Not Found. If order is soft-deleted (deleted_at is not
     *   null), still return the order for order history preservation and
     *   administrative oversight. Check authorization: customers can only view
     *   their own orders (member_id matches authenticated user), administrators
     *   can view all orders.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderNumber")
  public async getByOrdernumber(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await getEcommerceMallAdministratorOrdersOrderNumber({
        administrator,
        orderNumber,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
