import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSellerSuspension } from "../../../../api/structures/IEcommerceMallSellerSuspension";
import { IPageIEcommerceMallSellerSuspension } from "../../../../api/structures/IPageIEcommerceMallSellerSuspension";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getEcommerceMallAdministratorSellerSuspensionsSuspensionId } from "../../../../providers/getEcommerceMallAdministratorSellerSuspensionsSuspensionId";
import { patchEcommerceMallAdministratorSellerSuspensions } from "../../../../providers/patchEcommerceMallAdministratorSellerSuspensions";
import { postEcommerceMallAdministratorSellerSuspensions } from "../../../../providers/postEcommerceMallAdministratorSellerSuspensions";

@Controller("/ecommerceMall/administrator/seller-suspensions")
export class EcommercemallAdministratorSeller_suspensionsController {
  /**
   * Suspend a seller's account by creating a suspension record.
   *
   * This endpoint allows administrators to suspend seller accounts for policy violations or other serious issues. When a seller is suspended:
   *
   * - All their products are hidden from search results and category listings
   * - Their products cannot be purchased by customers
   * - They can still process existing orders (ship items, respond to cancellation and refund requests)
   * - They cannot create new products or edit existing products
   * - Suspension actions are logged for audit purposes
   *
   * The suspension takes effect immediately upon creation of the suspension record.
   *
   * **Authorization**: Requires administrator role. Super administrators also have this capability.
   *
   * **Validation**: Seller must exist. Reason field is required and must not be empty.
   *
   * @param connection
   * @param body Suspension request data including the seller to suspend and the reason for suspension.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Create a new seller suspension record in the ecommerce_mall_seller_suspensions table.
   *
   * 1. Authorization: Verify caller has administrator or super-administrator role
   * 2. Validate seller_id exists in ecommerce_mall_sellers
   * 3. Validate reason is provided and not empty
   * 4. Generate new UUID for suspension id
   * 5. Set suspended_at to current timestamp (UTC)
   * 6. Set resolved_at to null (currently suspended)
   * 7. Create record with seller_id, suspended_by_admin_id (from authenticated session), suspended_at, reason
   * 8. Return the created suspension record with all fields
   *
   * Business Rules:
   * - Multiple suspensions can exist for the same seller (audit trail)
   * - Each suspension is immutable once created
   * - Suspension takes effect immediately at suspended_at timestamp
   * - Product visibility changes are triggered by suspension record creation
   *
   * Error Handling:
   * - 401 Unauthorized if caller is not admin/super-admin
   * - 404 Not Found if seller_id does not exist
   * - 400 Bad Request if reason is empty or invalid
   * - 409 Conflict if seller is already suspended (optional business rule)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IEcommerceMallSellerSuspension.ICreate,
  ): Promise<IEcommerceMallSellerSuspension> {
    try {
      return await postEcommerceMallAdministratorSellerSuspensions({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * List and search seller suspension records with pagination, filtering, and sorting capabilities.
   *
   * This endpoint retrieves seller suspension audit records for administrative oversight. Administrators can filter by seller, suspending administrator, date ranges, and suspension status (active/resolved).
   *
   * The response includes paginated results optimized for administrative dashboards and audit review workflows.
   *
   * @param connection
   * @param body Search criteria including seller ID, administrator ID, date range filters, suspension status (active/resolved), pagination parameters, and sorting options.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query ecommerce_mall_seller_suspensions table with soft delete filter (deleted_at IS NULL).
   *
   * Apply search filters on:
   * - seller_id: filter by specific seller
   * - suspended_by_admin_id: filter by suspending administrator
   * - suspended_at: date range filter (from/to)
   * - resolved_at: null for active suspensions, not null for resolved
   * - reason: text search in suspension reason
   *
   * Apply pagination with cursor-based or offset-based approach.
   * Apply sorting on suspended_at, created_at, or seller_id.
   *
   * Join with ecommerce_mall_sellers to include seller shop name and seller email for display purposes.
   * Join with ecommerce_mall_administrators to include administrator name for display purposes.
   *
   * Return suspension status derived from resolved_at: 'active' if null, 'resolved' if not null.
   *
   * Handle edge cases:
   * - No matching records: return empty paginated result
   * - Invalid date ranges: reject with validation error
   * - Soft deleted records: exclude from results
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IEcommerceMallSellerSuspension.IRequest,
  ): Promise<IPageIEcommerceMallSellerSuspension.ISummary> {
    try {
      return await patchEcommerceMallAdministratorSellerSuspensions({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a seller suspension record by its unique identifier.
   *
   * This operation allows administrators to view the complete audit trail of a seller suspension, including the suspension timestamps, reason for suspension, which administrator performed the action, and whether the seller has been unsuspended.
   *
   * @param connection
   * @param suspensionId Unique identifier of the seller suspension record
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query ecommerce_mall_seller_suspensions table by id (UUID).
   *
   * Load full record including:
   * - seller_id reference to ecommerce_mall_sellers
   * - suspended_by_admin_id reference to ecommerce_mall_administrators
   * - suspended_at timestamp
   * - resolved_at timestamp (nullable if currently suspended)
   * - reason text field
   * - created_at and updated_at audit timestamps
   *
   * Authorization: Only administrators (administrator or superAdministrator actors) can access this endpoint.
   *
   * Return 404 if suspension record not found.
   * Return 403 if caller does not have admin privileges.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":suspensionId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("suspensionId")
    suspensionId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSellerSuspension> {
    try {
      return await getEcommerceMallAdministratorSellerSuspensionsSuspensionId({
        administrator,
        suspensionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
