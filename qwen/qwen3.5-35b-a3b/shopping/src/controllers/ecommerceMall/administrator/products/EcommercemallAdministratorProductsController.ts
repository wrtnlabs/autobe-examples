import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallProduct } from "../../../../api/structures/IEcommerceMallProduct";
import { IEcommerceMallProductAnalytic } from "../../../../api/structures/IEcommerceMallProductAnalytic";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getEcommerceMallAdministratorProductsIdAnalytics } from "../../../../providers/getEcommerceMallAdministratorProductsIdAnalytics";
import { putEcommerceMallAdministratorProductsProductId } from "../../../../providers/putEcommerceMallAdministratorProductsProductId";

@Controller("/ecommerceMall/administrator/products")
export class EcommercemallAdministratorProductsController {
  /**
   * Update an existing product's information including category, name, description, and base price.
   *
   * Only the owner seller can update their products. Every update creates an immutable snapshot preserving the previous state for audit trail and compliance. Products without variants remain available but unpurchasable.
   *
   * @param connection
   * @param productId UUID of the product to update
   * @param body Product update fields. All fields are optional except at least one must be provided. Excludes seller_id which is set by authentication.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification 1. Verify authenticated seller owns the product by matching seller_id
   * 2. Validate all input fields:
   *    - category_id: Must reference existing category
   *    - name: Non-empty string (business rule from section 279)
   *    - base_price: Positive number
   * 3. Update product fields in ecommerce_mall_products table
   * 4. Create snapshot in ecommerce_mall_product_snapshots capturing:
   *    - All product fields before update
   *    - Current variant snapshot reference
   *    - Seller profile snapshot reference
   * 5. Return updated product with all details including images and variants
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productId")
  public async update(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallProduct.IUpdate,
  ): Promise<IEcommerceMallProduct> {
    try {
      return await putEcommerceMallAdministratorProductsProductId({
        administrator,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve comprehensive analytics data for a specific product.
   *
   * This endpoint aggregates performance metrics from multiple data sources to provide a complete view of product performance. It combines sales data from order items, inventory levels from product variants, and review statistics to enable sellers and administrators to monitor product health.
   *
   * The analytics data includes total sales volume, revenue metrics, inventory status, review ratings, and stock availability. This endpoint is designed for seller dashboard views and administrator product oversight to enable data-driven decisions about product management, inventory planning, and pricing strategies.
   *
   * **Data Sources**:
   * - Product information from ecommerce_mall_products
   * - Sales data from ecommerce_mall_order_items
   * - Inventory levels from ecommerce_mall_product_variants
   * - Review statistics from ecommerce_mall_product_review_stats
   *
   * @param connection
   * @param id The unique identifier of the product to retrieve analytics for.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Retrieve product analytics by:
   * 1. Validate product {id} exists in ecommerce_mall_products table
   * 2. Check product is not soft-deleted (deleted_at IS NULL)
   * 3. Query all product variants (ecommerce_mall_product_variants) for this product
   * 4. Calculate total sales count from order items where product_variant_id matches variants of this product and status is 'delivered'
   * 5. Calculate total revenue from order items (sum of subtotal for delivered items only)
   * 6. Aggregate total inventory from variants (sum of stock_quantity where stock_quantity > 0)
   * 7. Count total variants and in-stock variants (stock_quantity > 0)
   * 8. Fetch review statistics from ecommerce_mall_product_review_stats for this product
   * 9. Calculate average variant price from variants where price is not null, otherwise use base_price
   * 10. Return aggregated analytics object with all metrics
   *
   * Return 404 if product does not exist or is soft-deleted.
   * Aggregate data from current product state; exclude soft-deleted products.
   * Include seller_id in response for seller verification.
   * Include category_id for context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id/analytics")
  public async analytics(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallProductAnalytic> {
    try {
      return await getEcommerceMallAdministratorProductsIdAnalytics({
        administrator,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
