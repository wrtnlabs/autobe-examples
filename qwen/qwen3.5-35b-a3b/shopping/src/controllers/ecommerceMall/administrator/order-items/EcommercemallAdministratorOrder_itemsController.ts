import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrderItem } from "../../../../api/structures/IEcommerceMallOrderItem";
import { IPageIEcommerceMallOrderItem } from "../../../../api/structures/IPageIEcommerceMallOrderItem";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getEcommerceMallAdministratorOrderItemsId } from "../../../../providers/getEcommerceMallAdministratorOrderItemsId";
import { getEcommerceMallAdministratorOrderItemsOrderItemId } from "../../../../providers/getEcommerceMallAdministratorOrderItemsOrderItemId";
import { patchEcommerceMallAdministratorOrderItems } from "../../../../providers/patchEcommerceMallAdministratorOrderItems";

@Controller("/ecommerceMall/administrator/order-items")
export class EcommercemallAdministratorOrder_itemsController {
  /**
   * Search and list order items with advanced filtering and pagination.
   *
   * Provides administrators and sellers with the ability to search order items across multiple dimensions including status, date ranges, order references, and seller attribution. Supports filtering by individual item status (paid, shipped, delivered, cancelled, refunded), date ranges for creation and updates, order ID lookups, and seller-based queries.
   *
   * This endpoint enables cross-seller order visibility, allowing administrators to see all order items across all sellers and individual sellers to view only their order items. Results are paginated with cursor-based navigation for efficient large result set handling.
   *
   * @param connection
   * @param body Search criteria including status filters, date ranges, order/seller/product references, pagination parameters, and sorting options.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query ecommerce_mall_order_items table with pagination and filtering.
   *
   * Search Criteria:
   * - Filter by status: paid, shipped, delivered, cancelled, refunded
   * - Filter by date ranges: created_at (order creation date), updated_at (last status change)
   * - Filter by order_id: get all items from specific order
   * - Filter by seller_id: get all items from specific seller
   * - Filter by product_variant_id: get items containing specific variant
   * - Sorting: created_at DESC (newest first) as default, support order by quantity, unit_price
   * - Pagination: cursor-based with limit (max 100 items per page)
   *
   * Business Rules:
   * - Sellers only see their own order items (filter by seller_id where request includes seller authentication)
   * - Administrators see all order items across all sellers
   * - Soft-deleted items (deleted_at IS NOT NULL) are excluded from results
   * - Status filtering must use exact enum values: 'paid', 'shipped', 'delivered', 'cancelled', 'refunded'
   *
   * Edge Cases:
   * - Return empty array if no items match criteria
   * - Handle null product_variant_id gracefully (should not occur in valid data)
   * - Validate date range start <= end, return error if invalid
   * - Enforce maximum page size (100 items) to prevent performance issues
   *
   * Implementation Notes:
   * - Use parameterized queries to prevent SQL injection
   * - Index optimization on (ecommerce_mall_order_id, status), (seller_id), (status), (created_at)
   * - Join with ecommerce_mall_orders for order_number if requested
   * - Join with ecommerce_mall_product_variants for variant options if requested
   * - Consider snapshot data for historical price/variant info if needed
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IEcommerceMallOrderItem.IRequest,
  ): Promise<IPageIEcommerceMallOrderItem.ISummary> {
    try {
      return await patchEcommerceMallAdministratorOrderItems({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the full details of a specific order item including product variant information, pricing, status, and associated seller data.
   *
   * This operation returns the complete order item record with all fields preserved at the time of purchase, including the product name, variant options, unit price, quantity, and current status. The response includes seller attribution for accountability and dispute resolution purposes. Order items maintain independent status from their parent order, allowing individual items to be tracked through paid, shipped, delivered, cancelled, and refunded states.
   *
   * @param connection
   * @param id UUID identifier of the order item to retrieve (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification 1. Validate the order item ID exists and is not soft-deleted (deleted_at is null)
   * 2. Fetch the order item record from ecommerce_mall_order_items by ID
   * 3. Include all fields: id, quantity, unit_price, subtotal, status, created_at, updated_at
   * 4. Load related product variant data (product name, variant option_values) for display
   * 5. Load related seller data (seller_id, display_name) for seller attribution
   * 6. Return the complete order item with embedded product and seller information
   * 7. Return 404 Not Found if order item does not exist or is soft-deleted
   * 8. No authorization required for viewing own order items (authorization handled at caller level)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async getById(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrderItem> {
    try {
      return await getEcommerceMallAdministratorOrderItemsId({
        administrator,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single order item with complete details including seller information, product variant reference, pricing, and current status.
   *
   * This operation returns the full order item record with all associated data needed for order tracking and management. The response includes the seller context even when the order item is part of a cross-seller order, allowing clients to display seller-specific information such as shop name and logo.
   *
   * Order items can be accessed by:
   * - Customers: viewing their purchased items and tracking delivery status
   * - Sellers: managing their fulfilled items and handling cancellations/refunds
   * - Administrators: overseeing orders across all sellers for platform management
   *
   * @param connection
   * @param orderItemId Unique identifier of the order item to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query ecommerce_mall_order_items table by id.
   *
   * Steps:
   * 1. Validate orderItemId is a valid UUID format
   * 2. Query order item with seller_id, status, and deleted_at fields
   * 3. Join with ecommerce_mall_sellers to get seller display_name, shop profile data
   * 4. Join with ecommerce_mall_product_variants to get sku_code, product info
   * 5. Join with ecommerce_mall_orders to get order_number, order status
   * 6. Apply soft delete filter: excluded deleted items (deleted_at IS NULL)
   * 7. Validate access permissions based on calling user context:
   *    - Customer: must own the order containing this item
   *    - Seller: must own the seller_id of this item
   *    - Administrator: can access any order item
   * 8. Return 404 if item not found or already deleted
   *
   * Business Rules:
   * - Status must match allowed values: 'paid', 'shipped', 'delivered', 'cancelled', 'refunded'
   * - Cross-seller support: items from different sellers can exist in same order
   * - Historical data preserved: unit_price and subtotal are immutable snapshots from purchase time
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderItemId")
  public async getByOrderitemid(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrderItem> {
    try {
      return await getEcommerceMallAdministratorOrderItemsOrderItemId({
        administrator,
        orderItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
