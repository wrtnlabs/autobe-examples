import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallAdministrator } from "../../../../api/structures/IEcommerceMallAdministrator";
import { IEcommerceMallAdministratorGrade } from "../../../../api/structures/IEcommerceMallAdministratorGrade";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getEcommerceMallAdministratorAdministratorGradesGradeChangeId } from "../../../../providers/getEcommerceMallAdministratorAdministratorGradesGradeChangeId";
import { patchEcommerceMallAdministratorAdministratorGrades } from "../../../../providers/patchEcommerceMallAdministratorAdministratorGrades";

@Controller("/ecommerceMall/administrator/administrator-grades")
export class EcommercemallAdministratorAdministrator_gradesController {
  /**
   * Change administrator grade (promote or demote) with audit trail.
   *
   * This operation allows super administrators to change an administrator's grade from regular to super (promotion) or from super to regular (demotion). Every grade change is recorded in the administrator grades history table with timestamps, the changer's identity, and an optional reason.
   *
   * Super administrators cannot demote themselves through this endpoint - self-demotion is prevented by business rules enforced at the service layer. The operation updates the administrator's grade immediately, granting or removing elevated privileges at once.
   *
   * The system creates immutable snapshots of each grade change for compliance and transparency purposes.
   *
   * @param connection
   * @param body Grade change criteria including target administrator identifier, new grade value, and optional reason for the change.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification 1. Validate that the requesting administrator is
     *   a super administrator (grade === 'super') 2. Validate that the target
     *   administrator_id exists and is not null 3. Validate that the target
     *   administrator is not the same as the requesting administrator (prevent
     *   self-grading) 4. Validate that the new_grade is either 'regular' or
     *   'super' 5. Validate that demotion from 'super' to 'regular' is only for
     *   other super administrators (not self) 6. Update the
     *   ecommerce_mall_administrators table: set grade to new_grade 7. Create a
     *   new record in ecommerce_mall_administrator_grades: - administrator_id:
     *   target administrator id - changed_by: requesting administrator id -
     *   grade: new_grade value - previous_grade: old grade value (from step 5)
     *   - reason: optional reason provided in request - created_at: current
     *   timestamp 8. Create a snapshot record in
     *   ecommerce_mall_administrator_grades_snapshots capturing the old_grade
     *   and new_grade values 9. Return the updated administrator full object
     *   with all fields 10. Throw 403 Forbidden if requesting administrator is
     *   not super 11. Throw 404 Not Found if target administrator does not
     *   exist 12. Throw 400 Bad Request if attempting self-demotion or invalid
     *   grade transition
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IEcommerceMallAdministratorGrade.IRequest,
  ): Promise<IEcommerceMallAdministrator> {
    try {
      return await patchEcommerceMallAdministratorAdministratorGrades({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific administrator grade change record by its unique identifier.
   *
   * This endpoint returns complete details of a single grade change event, including the target administrator, the grade before and after the change, who initiated the change, and optional reason for the modification. The response includes nested administrator information for both the target administrator and the changemaker to provide full context of the grade change event.
   *
   * @param connection
   * @param gradeChangeId Unique identifier of the grade change record to retrieve
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Query ecommerce_mall_administrator_grades table
     *   for the specific record matching the gradeChangeId UUID parameter.
   *
   * Include JOIN operations to fetch related administrator records:
   * - The administrator whose grade was changed (administrator_id foreign key)
   * - The administrator who initiated the change (changed_by foreign key)
   *
   * Calculate snapshot count by counting records in ecommerce_mall_administrator_grades_snapshots where ecommerce_mall_administrator_grade_id matches the record.
   *
   * Return soft-deleted records only if the requesting super administrator has audit override privileges.
   *
   * Validation:
   * - gradeChangeId must be a valid UUID
   * - Return 404 if no matching record exists (or if soft-deleted and not authorized)
   *
   * Error handling:
   * - Invalid UUID format → return 400 Bad Request
   * - Record not found → return 404 Not Found
   * - Unauthorized access to soft-deleted record → return 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":gradeChangeId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("gradeChangeId")
    gradeChangeId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallAdministratorGrade> {
    try {
      return await getEcommerceMallAdministratorAdministratorGradesGradeChangeId(
        {
          administrator,
          gradeChangeId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
