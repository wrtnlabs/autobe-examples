import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallProduct } from "../../../../../api/structures/IEcommerceMallProduct";
import { IPageIEcommerceMallProduct } from "../../../../../api/structures/IPageIEcommerceMallProduct";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { patchEcommerceMallAdministratorCategoriesCategoryIdProducts } from "../../../../../providers/patchEcommerceMallAdministratorCategoriesCategoryIdProducts";

@Controller("/ecommerceMall/administrator/categories/:categoryId/products")
export class EcommercemallAdministratorCategoriesProductsController {
  /**
   * Retrieve a paginated list of products within a specific category with optional search, sorting, and filtering options.
   *
   * **Purpose**:
   * This endpoint allows customers to browse products within a specific category. It supports text search on product name and description, filtering by price range, and sorting by various product attributes.
   *
   * **Features**:
   * - Returns only active products (deleted_at is NULL)
   * - Supports full-text search on product name and description
   * - Allows filtering by price range (base_price)
   * - Supports sorting by name, price, creation date
   * - Returns paginated results with cursor-based pagination for efficient large result sets
   * - Includes basic product information optimized for list displays
   *
   * @param connection
   * @param categoryId Unique identifier of the category to filter products by. Products in subcategories are NOT included - only products directly assigned to this category.
   * @param body Search and filtering criteria for products within the category, including text search, price range filters, sorting options, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Query ecommerce_mall_products table with the
     *   following logic:
   *
   * **Database Query**:
   * - Filter: WHERE category_id = {categoryId} AND deleted_at IS NULL
   * - Apply additional filters from requestBody (name search, price range)
   * - Apply sorting from requestBody (by name, base_price, created_at)
   * - Apply pagination (limit, cursor)
   *
   * **Search Implementation**:
   * - Name search: WHERE name ILIKE '%' || {searchQuery} || '%'
   * - Description search: WHERE description ILIKE '%' || {searchQuery} || '%'
   * - Use PostgreSQL text search with gin_trgm_ops index on name and description columns
   *
   * **Sorting**:
   * - Support sorting by: name (asc/desc), base_price (asc/desc), created_at (asc/desc)
   * - Default sort: created_at DESC (newest first)
   *
   * **Pagination**:
   * - Return cursor-based pagination with nextCursor for navigating to next page
   * - Include total count for page number calculation
   * - Max limit: 50 items per page
   *
   * **Error Handling**:
   * - Return 404 if categoryId does not exist
   * - Return 400 if search query exceeds max length (100 chars)
   * - Return 400 if invalid sort field or direction
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallProduct.IRequest,
  ): Promise<IPageIEcommerceMallProduct.ISummary> {
    try {
      return await patchEcommerceMallAdministratorCategoriesCategoryIdProducts({
        administrator,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
