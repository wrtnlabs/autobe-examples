import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCategoriesSnapshot } from "../../../../../api/structures/IEcommerceMallCategoriesSnapshot";
import { IPageIEcommerceMallCategoriesSnapshot } from "../../../../../api/structures/IPageIEcommerceMallCategoriesSnapshot";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getEcommerceMallAdministratorCategoriesCategoryIdSnapshotsSnapshotId } from "../../../../../providers/getEcommerceMallAdministratorCategoriesCategoryIdSnapshotsSnapshotId";
import { patchEcommerceMallAdministratorCategoriesCategoryIdSnapshots } from "../../../../../providers/patchEcommerceMallAdministratorCategoriesCategoryIdSnapshots";

@Controller("/ecommerceMall/administrator/categories/:categoryId/snapshots")
export class EcommercemallAdministratorCategoriesSnapshotsController {
  /**
   * Retrieve modification snapshots for a specific category.
   *
   * Returns a paginated list of immutable snapshot records that capture when the category was modified. Each snapshot records the category name, description, and parent category at the time of modification, along with which administrator made the change and when.
   *
   * Administrators can review the complete modification history of any category to track changes over time for auditing and compliance purposes.
   *
   * @param connection
   * @param categoryId The UUID of the category to retrieve snapshots for.
   * @param body Pagination, sorting, and filtering criteria for retrieving category snapshots.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Query ecommerce_mall_categories_snapshots table
     *   for all snapshots where category_id matches the provided categoryId
     *   path parameter.
   *
   * Apply pagination: limit, offset, and cursor-based pagination if requested.
   * Apply sorting: sort by created_at (default: descending) or other snapshot fields.
   * Apply filtering: filter by modified_by_id (administrator), date range for created_at, or entity_type (always 'category').
   *
   * Join with ecommerce_mall_administrators to include modified_by administrator details.
   * Join with ecommerce_mall_categories (parent_category) to include parent category details.
   *
   * Validate categoryId exists in ecommerce_mall_categories before querying snapshots.
   * Return 404 if category is not found.
   *
   * Sort snapshots by created_at descending by default to show most recent changes first.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallCategoriesSnapshot.IRequest,
  ): Promise<IPageIEcommerceMallCategoriesSnapshot.ISummary> {
    try {
      return await patchEcommerceMallAdministratorCategoriesCategoryIdSnapshots(
        {
          administrator,
          categoryId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific category snapshot by ID.
   *
   * This operation returns the complete snapshot record for a category modification, including the category name, description, parent relationship, and metadata about when the change was made and by which administrator. Snapshots provide an immutable audit trail of category history.
   *
   * **Access Control**:
   * - Administrators can view any category snapshot
   * - Only administrators have access to snapshot data for audit and oversight purposes
   *
   * @param connection
   * @param categoryId The unique identifier of the category that was modified.
   * @param snapshotId The unique identifier of the category snapshot to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Fetch category snapshot record from
     *   ecommerce_mall_categories_snapshots table where id matches snapshotId
     *   parameter.
   *
   * **Validation**:
   * 1. Validate categoryId and snapshotId are valid UUID format
   * 2. Verify the snapshot's category_id matches the categoryId path parameter (enforce path-scoped access)
   * 3. Verify snapshot exists (return 404 if not found)
   * 4. Verify snapshot's entity_type equals 'category'
   *
   * **Query**:
   * SELECT * FROM ecommerce_mall_categories_snapshots
   * WHERE id = snapshotId
   * AND category_id = categoryId
   * AND entity_type = 'category'
   *
   * **Response**: Return complete snapshot record with all fields.
   *
   * **Error Handling**:
   * - 404 Not Found: Snapshot not found or category_id mismatch
   * - 403 Forbidden: If non-administrator attempts access
   * - 400 Bad Request: Invalid UUID format for path parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCategoriesSnapshot> {
    try {
      return await getEcommerceMallAdministratorCategoriesCategoryIdSnapshotsSnapshotId(
        {
          administrator,
          categoryId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
