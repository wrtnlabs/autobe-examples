import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallMember } from "../../../api/structures/IEcommerceMallMember";
import { IPageIEcommerceMallMember } from "../../../api/structures/IPageIEcommerceMallMember";
import { getEcommerceMallMembersMemberId } from "../../../providers/getEcommerceMallMembersMemberId";
import { patchEcommerceMallMembers } from "../../../providers/patchEcommerceMallMembers";

@Controller("/ecommerceMall/members")
export class EcommercemallMembersController {
  /**
   * Search and list customer members with filtering, sorting, and pagination.
   *
   * This endpoint allows administrators to search the member database with various filters including name, email, registration status, and date ranges. Results are returned as paginated summaries optimized for administrative list displays. The endpoint supports sorting by common fields and implements cursor-based pagination for large result sets.
   *
   * @param connection
   * @param body Search criteria including email filter, display name filter, status filter, date range filters for registration and last activity, sort options, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_mall_members table with pagination and filtering.
   * Apply search filters on email, display_name, status (active/inactive/banned), registration date range.
   * Join with relevant tables for aggregated data (order counts, etc.) if requested.
   * Return cursor-based pagination with nextCursor for navigating large result sets.
   * Validate that requester has administrator permissions before returning member data.
   * Exclude sensitive fields (password hashes, session tokens) from response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommerceMallMember.IRequest,
  ): Promise<IPageIEcommerceMallMember.ISummary> {
    try {
      return await patchEcommerceMallMembers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve customer account details by unique identifier.
   *
   * Returns the full profile information for a specific customer account, including their display name, phone number, and account metadata. This endpoint is used to view customer information in administrative dashboards or customer profile pages.
   *
   * The email field is returned for account identification purposes, but the password hash is never exposed through the API for security reasons.
   *
   * If the requested customer does not exist or has been soft-deleted, a 404 Not Found error is returned. Access to this endpoint requires appropriate administrator or seller actor permissions.
   *
   * @param connection
   * @param memberId Unique identifier for the customer account.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the ecommerce_mall_members table for a single record where id matches the memberId path parameter.
   *
   * Validation:
   * - Verify memberId is a valid UUID format
   * - Check that the member account exists and is not soft-deleted (deleted_at is null)
   * - Return 404 if no matching record found or if deleted_at is set
   *
   * Response construction:
   * - Include: id, email, display_name, phone_number, created_at, updated_at
   * - Exclude: password_hash (security), deleted_at (internal only)
   *
   * Permissions:
   * - Requires administrator or seller actor role
   * - Verify actor has appropriate permission level before returning data
   *
   * Edge cases:
   * - Handle UUID parsing errors with 400 Bad Request
   * - Handle soft-deleted accounts (deleted_at is not null) with 404 Not Found
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":memberId")
  public async at(
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallMember> {
    try {
      return await getEcommerceMallMembersMemberId({
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
