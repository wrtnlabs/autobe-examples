import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallReview } from "../../../../api/structures/IEcommerceMallReview";
import { IPageIEcommerceMallReview } from "../../../../api/structures/IPageIEcommerceMallReview";
import { patchEcommerceMallProductsProductIdReviews } from "../../../../providers/patchEcommerceMallProductsProductIdReviews";

@Controller("/ecommerceMall/products/:productId/reviews")
export class EcommercemallProductsReviewsController {
  /**
   * Retrieve a filtered and paginated list of customer reviews for a specific product.
   *
   * This operation returns all active (non-deleted) reviews for the specified product, sorted by newest first. Each review includes the customer's rating (1-5 stars), optional title, review text, verification status, and author information.
   *
   * Supports advanced filtering by rating range and verified purchase status. Results are paginated using cursor-based pagination for efficient handling of large review sets. The operation excludes soft-deleted reviews to maintain data integrity.
   *
   * Customers can view reviews for any product on the platform. Reviews are displayed on product detail pages to help shoppers make informed purchasing decisions based on customer feedback.
   *
   * @param connection
   * @param productId Product ID to fetch reviews for (global scope)
   * @param body Search criteria and pagination parameters for filtering product reviews
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_mall_reviews table filtered by productId and deleted_at IS NULL.
   * Apply filters: rating range, is_verified_purchase status.
   * Sort by created_at DESC (newest first) by default, support custom sorting.
   * Join with ecommerce_mall_customers for author name display.
   * Exclude soft-deleted reviews (deleted_at IS NULL).
   * Implement cursor-based pagination with created_at as cursor for consistent results.
   * Calculate average rating from non-deleted reviews for product display.
   * Return paginated results with total count for frontend pagination UI.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallReview.IRequest,
  ): Promise<IPageIEcommerceMallReview.ISummary> {
    try {
      return await patchEcommerceMallProductsProductIdReviews({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
