import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallProductReviewStat } from "../../../../api/structures/IEcommerceMallProductReviewStat";
import { getEcommerceMallProductsProductIdStats } from "../../../../providers/getEcommerceMallProductsProductIdStats";

@Controller("/ecommerceMall/products/:productId/stats")
export class EcommercemallProductsStatsController {
  /**
   * Retrieve pre-calculated review statistics for a specific product including average rating, total review count, and rating distribution.
   *
   * Returns aggregated metrics for the product from the review statistics cache, which is automatically updated when reviews are created, modified, or deleted. The average rating is rounded to 2 decimal places (range: 0.0 to 5.0). All rating count fields show the distribution of 1-5 star ratings from non-deleted reviews.
   *
   * @param connection
   * @param productId UUID identifier of the product whose statistics are being requested.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_mall_product_review_stats table by product_id to retrieve the stats record.
   *
   * 1. Validate productId is a valid UUID format
   * 2. Query for stats record where ecommerce_mall_product_id = productId
   * 3. If no stats record exists (product has no reviews), return 404 Not Found with error message
   * 4. Return the complete stats object including:
   *    - id: stats record UUID
   *    - product_id: referenced product UUID
   *    - average_rating: null or float (0.0-5.0, 2 decimal places)
   *    - review_count: integer (0 or positive)
   *    - rating_1_count through rating_5_count: integer distribution
   *    - created_at: when stats were first created
   *    - updated_at: last stats modification time
   *
   * Handle edge cases:
   * - Product with no reviews: stats record may not exist yet (no reviews submitted), return 404
   * - Product with all reviews deleted: stats record exists with review_count=0, average_rating=null, all rating counts=0
   * - Deleted product: stats still accessible (preserved for historical reference)
   *
   * Return 404 if stats record not found. No authorization required for reading public product statistics.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallProductReviewStat> {
    try {
      return await getEcommerceMallProductsProductIdStats({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
