import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallProductSnapshot } from "../../../../api/structures/IEcommerceMallProductSnapshot";
import { IPageIEcommerceMallProductSnapshot } from "../../../../api/structures/IPageIEcommerceMallProductSnapshot";
import { getEcommerceMallProductsProductIdSnapshotsSnapshotId } from "../../../../providers/getEcommerceMallProductsProductIdSnapshotsSnapshotId";
import { patchEcommerceMallProductsProductIdSnapshots } from "../../../../providers/patchEcommerceMallProductsProductIdSnapshots";

@Controller("/ecommerceMall/products/:productId/snapshots")
export class EcommercemallProductsSnapshotsController {
  /**
   * Retrieve a filtered and paginated list of product snapshots for a specific product.
   *
   * This operation returns the complete edit history of a product, capturing all state changes including name, description, price, category assignment, and active status at the time of each edit. Each snapshot preserves the product information as it existed at that moment, including the seller who made the edit.
   *
   * Snapshots are immutable audit records created automatically whenever a seller edits a product. They provide historical accuracy for dispute resolution, compliance audits, and change tracking. The authorization rules are as follows:
   *
   * **Sellers**: Can only view snapshots for products they own. The system validates that the requesting seller is the owner of the product before returning any snapshot data.
   *
   * **Administrators**: Can view snapshots for any product on the platform for oversight purposes, dispute resolution, and compliance audits.
   *
   * The operation supports pagination for large result sets, sorting by creation timestamp (most recent first), and optional date range filtering to narrow results to a specific time period. All snapshots are immutable - this operation only supports reading, never modifying or deleting snapshot records.
   *
   * @param connection
   * @param productId Product identifier to retrieve snapshots for
   * @param body Search criteria and pagination parameters for product snapshots
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the ecommerce_mall_product_snapshots table for records matching the given productId parameter.
   *
   * Apply pagination using cursor-based or offset-based pagination with configurable page size (default 20, max 100) from request body.
   *
   * Sort results by created_at timestamp in descending order (newest first) by default. Support ascending order via request body query parameter.
   *
   * Apply optional date range filtering from request body: created_at >= startDate and created_at <= endDate.
   *
   * Filter by seller ownership: if requester is a seller, only return snapshots where seller_id matches the seller's ID. If requester is an administrator, return all snapshots for the requested product.
   *
   * Join with ecommerce_mall_categories table to include category name and slug when requested.
   *
   * Validate that the productId exists in ecommerce_mall_products table before returning snapshots. Return 404 if product not found.
   *
   * Each snapshot includes: id, product_id, category_id, seller_id, name, description, base_price, is_active, created_at, and seller information (shop name).
   *
   * Do NOT allow any modifications or deletions of snapshots - they are immutable audit records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallProductSnapshot.IRequest,
  ): Promise<IPageIEcommerceMallProductSnapshot.ISummary> {
    try {
      return await patchEcommerceMallProductsProductIdSnapshots({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific product snapshot for dispute resolution and audit purposes.
   *
   * This operation returns the immutable snapshot that preserves the complete product state at the time of a specific edit. Snapshots contain all product details including name, description, base price, category assignment, seller information, and active status as they existed when the snapshot was created.
   *
   * Only the product owner (seller who created the product) and administrators can access product snapshots. This ensures sensitive historical data is only visible to authorized parties who need it for dispute resolution, compliance audits, or change history review.
   *
   * @param connection
   * @param productId UUID of the product this snapshot belongs to
   * @param snapshotId UUID of the specific snapshot to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification 1. Validate that productId and snapshotId are valid UUIDs
   * 2. Query ecommerce_mall_product_snapshots table for the snapshot with matching id = snapshotId AND product_id = productId
   * 3. If snapshot not found, return 404 Not Found
   * 4. Check authorization:
   *    - If requester is admin (regular or super), allow access
   *    - If requester is seller, verify seller_id matches the authenticated seller's ID (owner of the product)
   *    - If requester is customer, deny access (return 403 Forbidden)
   * 5. If unauthorized, return 403 Forbidden
   * 6. If product was deleted, include flag indicating product deletion status but still return snapshot (section 855, 1148)
   * 7. Return snapshot data with all preserved fields: id, product_id, category_id, seller_id, name, description, base_price, is_active, created_at
   * 8. Include product_id and created_at in response metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallProductSnapshot> {
    try {
      return await getEcommerceMallProductsProductIdSnapshotsSnapshotId({
        productId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
