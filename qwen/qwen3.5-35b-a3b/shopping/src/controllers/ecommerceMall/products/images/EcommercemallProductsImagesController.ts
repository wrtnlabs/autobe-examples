import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallProductImage } from "../../../../api/structures/IEcommerceMallProductImage";
import { getEcommerceMallProductsProductIdImages } from "../../../../providers/getEcommerceMallProductsProductIdImages";

@Controller("/ecommerceMall/products/:productId/images")
export class EcommercemallProductsImagesController {
  /**
   * Retrieves all product images for a specific product, ordered by display priority.
   *
   * Returns a list of all active product images associated with the specified product. Images are sorted by display_order in ascending order, with the image having display_order = 1 appearing first as the main/thumbnail image. Each image record includes its unique identifier, image URL, display order position, and creation timestamp.
   *
   * Only active images (not soft-deleted) are returned. Soft-deleted images are identified by a non-null deleted_at timestamp and are excluded from results.
   *
   * @param connection
   * @param productId The unique identifier of the product to retrieve images for.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query ecommerce_mall_product_images table where
     *   product_id matches the path parameter and deleted_at IS NULL (active
     *   images only).
   *
   * Sort results by display_order ascending, then by id ascending for consistent ordering.
   *
   * Return only summary fields: id, image_url, display_order, created_at.
   *
   * Validate that the productId is a valid UUID format.
   *
   * Return 404 Not Found if no images exist for the specified product or if the product does not exist.
   *
   * Note: The product itself must exist for this endpoint to return results. If the product has been deleted, all associated images will also have been cascade-deleted per the database schema constraint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallProductImage.ISummary> {
    try {
      return await getEcommerceMallProductsProductIdImages({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
