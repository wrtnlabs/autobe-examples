import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipmentItem } from "../../../../../../api/structures/IEcommerceMallShipmentItem";
import { IPageIEcommerceMallShipmentItem } from "../../../../../../api/structures/IPageIEcommerceMallShipmentItem";
import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerOrdersOrderIdShipmentsShipmentIdItemsShipmentItemId } from "../../../../../../providers/getEcommerceMallCustomerOrdersOrderIdShipmentsShipmentIdItemsShipmentItemId";
import { patchEcommerceMallCustomerOrdersOrderIdShipmentsShipmentIdItems } from "../../../../../../providers/patchEcommerceMallCustomerOrdersOrderIdShipmentsShipmentIdItems";

@Controller(
  "/ecommerceMall/customer/orders/:orderId/shipments/:shipmentId/items",
)
export class EcommercemallCustomerOrdersShipmentsItemsController {
  /**
   * Retrieve a paginated list of order items contained within a specific shipment for an order.
   *
   * This operation provides advanced search capabilities for order items within a shipment, including filtering by item status (paid, shipped, delivered, cancelled, refunded), seller information, and pagination controls. Each shipment contains one or more order items from the same seller, and all items share the same carrier and tracking information.
   *
   * The operation validates that the order and shipment exist and that the shipment belongs to the specified order. It returns only order items that are associated with the shipment through the junction table (ecommerce_mall_shipment_items), including item quantity, unit price, and current status.
   *
   * Supports comprehensive pagination with configurable page size and sorting options. Response includes shipment item summary information optimized for display in order history and tracking interfaces.
   *
   * @param connection
   * @param orderId Target order's UUID. The order must exist and the shipment must belong to this order.
   * @param shipmentId Target shipment's UUID. The shipment must exist and belong to the specified order. Contains only items from a single seller.
   * @param body Search criteria and pagination parameters for shipment items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_shipment_items table with JOIN to ecommerce_mall_order_items to retrieve complete order item information.
   *
   * Apply filters:
   * - Optional itemStatus filter (paid, shipped, delivered, cancelled, refunded)
   * - Optional date range filter on created_at
   * - Optional search on order orderNumber
   *
   * Validation:
   * 1. Verify order exists and is accessible to the requesting user
   * 2. Verify shipment exists and belongs to the specified order
   * 3. Verify seller_id in shipment matches the requester's seller_id if seller
   *
   * Query the junction table for all items with the given shipment_id.
   * Join with order_items to get item details (quantity, unitPrice, productSnapshot, variantSnapshot, sellerProfileSnapshot).
   * Apply pagination with cursor-based or offset-based pagination.
   * Sort results by created_at (ascending by default) or other supported fields.
   *
   * Return paginated response with:
   * - data: Array of shipment item summaries
   * - pagination: { hasMore, nextCursor or nextPage, total }
   *
   * Error handling:
   * - 404 if order not found
   * - 404 if shipment not found or not belonging to order
   * - 403 if unauthorized (non-owner, non-matching seller)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallShipmentItem.IRequest,
  ): Promise<IPageIEcommerceMallShipmentItem.ISummary> {
    try {
      return await patchEcommerceMallCustomerOrdersOrderIdShipmentsShipmentIdItems(
        {
          customer,
          orderId,
          shipmentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shipment item, which represents the association between an order item and a delivery shipment.
   *
   * This operation returns complete information about a shipment item record, including the linked order item details, shipment tracking information, and timestamps. The shipment item is identified through the hierarchical path parameters: order ID, shipment ID, and shipment item ID.
   *
   * Authorization is restricted to the seller who created the shipment. Customers can view shipment information through the order details endpoint, but cannot directly access shipment items via this endpoint.
   *
   * The operation validates that the order belongs to the customer context, the shipment belongs to the specified order, and the shipment item belongs to the specified shipment. It also verifies that the authenticated seller is the owner of the shipment.
   *
   * SHIPPING CARRIERS: The carrier name and tracking number are provided by third-party shipping providers (e.g., USPS, FedEx, DHL) and are used for package tracking.
   *
   * @param connection
   * @param orderId The unique identifier of the order containing this shipment
   * @param shipmentId The unique identifier of the shipment containing this item
   * @param shipmentItemId The unique identifier of the shipment item record
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Retrieve a specific shipment item by its ID from the ecommerce_mall_shipment_items table.
   *
   * 1. Validate that all path parameters are valid UUIDs
   * 2. Query ecommerce_mall_shipment_items where id = shipmentItemId
   * 3. Join with ecommerce_mall_shipments to verify the shipment exists and is linked to the specified orderId
   * 4. Join with ecommerce_mall_orders to verify the order exists
   * 5. Check that the authenticated user is the seller who created this shipment (shipment.seller_id = current_user.id)
   * 6. Return the shipment item with order item and shipment details
   * 7. Return 404 if the shipment item, shipment, or order does not exist
   * 8. Return 403 if the authenticated user is not the seller who created this shipment
   * 9. Return 404 if the shipment does not belong to the specified order
   *
   * Business rules:
   * - Each order item can belong to exactly one shipment (enforced by @@unique([order_item_id]) on ecommerce_mall_shipment_items)
   * - Shipment items share the same tracking information as their parent shipment
   * - The 14-day auto-delivery process is triggered when a shipment is created
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentItemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedParam("shipmentItemId")
    shipmentItemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShipmentItem> {
    try {
      return await getEcommerceMallCustomerOrdersOrderIdShipmentsShipmentIdItemsShipmentItemId(
        {
          customer,
          orderId,
          shipmentId,
          shipmentItemId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
