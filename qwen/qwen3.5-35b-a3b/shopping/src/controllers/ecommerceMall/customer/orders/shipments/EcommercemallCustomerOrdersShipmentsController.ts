import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipment } from "../../../../../api/structures/IEcommerceMallShipment";
import { IPageIEcommerceMallShipment } from "../../../../../api/structures/IPageIEcommerceMallShipment";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerOrdersOrderIdShipmentsShipmentId } from "../../../../../providers/getEcommerceMallCustomerOrdersOrderIdShipmentsShipmentId";
import { patchEcommerceMallCustomerOrdersOrderIdShipments } from "../../../../../providers/patchEcommerceMallCustomerOrdersOrderIdShipments";

@Controller("/ecommerceMall/customer/orders/:orderId/shipments")
export class EcommercemallCustomerOrdersShipmentsController {
  /**
   * Retrieve a paginated list of shipments associated with a specific order.
   *
   * This operation provides shipment tracking information for an order, including carrier details, tracking numbers, and the order items contained in each shipment. It supports pagination for efficient handling of multiple shipments and optional filtering by date range.
   *
   * The operation respects data isolation rules where customers can view shipments for their own orders, while sellers can only view shipments for order items they sold. Administrators can view all shipments regardless of ownership.
   *
   * Related operations:
   * - GET /orders/{orderId} must be called first to obtain the order details and verify access permissions
   * - GET /orders/{orderId}/items retrieves the order items that are included in shipments
   *
   * @param connection
   * @param orderId The unique identifier of the order whose shipments are to be retrieved.
   * @param body Search criteria and pagination parameters for shipment retrieval
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_shipments table filtered by order_id matching the path parameter.
   * Apply cursor-based pagination using created_at for ordering (newest first).
   * Apply optional filters on carrier_name, tracking_number, and created_at date range.
   * Apply optional sorting by created_at, carrier_name, or tracking_number.
   * For customers: enforce ownership check - only return shipments where the order belongs to the authenticated customer.
   * For sellers: enforce item-level ownership check - return shipments containing order items owned by the authenticated seller.
   * For administrators: return all shipments for the order without ownership checks.
   * Join with ecommerce_mall_shipment_items to include order item IDs in the response.
   * Compute shipment item count per shipment from the joined data.
   * Apply soft delete filtering - only return shipments where deleted_at is NULL.
   * Handle empty result sets by returning pagination metadata with empty data array.
   * Enforce UUID validation for orderId path parameter.
   * Return 404 if order not found or access denied based on actor permissions.
   * Return 400 for invalid pagination parameters (page size out of range, invalid cursor).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallShipment.IRequest,
  ): Promise<IPageIEcommerceMallShipment.ISummary> {
    try {
      return await patchEcommerceMallCustomerOrdersOrderIdShipments({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed shipment information for a specific shipment within an order.
   *
   * This operation returns complete shipment details including carrier information, tracking number, creation date, and all order items included in the shipment. It is primarily used by customers to track their packages and by sellers to manage their shipments.
   *
   * The shipment must belong to the specified order. Customers can only view shipments from orders they placed. Sellers can only view shipments they created. Administrators can view all shipments.
   *
   * Tracking information becomes immutable once the shipment is created. The response includes the carrier name and tracking number that customers can use to track their package through the carrier's website or app.
   *
   * @param connection
   * @param orderId The order that contains this shipment
   * @param shipmentId The specific shipment to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_mall_shipments table for the specific shipment record identified by shipmentId where order_id matches the orderId path parameter.
   *
   * Authorization checks:
   * - If actor is customer: verify the order belongs to the customer (ecommerce_mall_orders.customer_id = current_customer_id)
   * - If actor is seller: verify the shipment was created by this seller (ecommerce_mall_shipments.seller_id = current_seller_id)
   * - If actor is admin: no additional authorization check required
   *
   * Return the complete shipment record including: id, order_id, seller_id, carrier_name, tracking_number, created_at, updated_at.
   *
   * If the shipment does not exist or the actor lacks authorization, return 404 Not Found or 403 Forbidden respectively.
   *
   * Ensure deleted_at is NULL (shipment has not been soft deleted).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShipment> {
    try {
      return await getEcommerceMallCustomerOrdersOrderIdShipmentsShipmentId({
        customer,
        orderId,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
