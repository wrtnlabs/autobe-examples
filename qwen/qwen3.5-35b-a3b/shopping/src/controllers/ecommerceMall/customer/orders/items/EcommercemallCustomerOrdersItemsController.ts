import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrderItem } from "../../../../../api/structures/IEcommerceMallOrderItem";
import { IEcommerceMallOrderItemSnapshot } from "../../../../../api/structures/IEcommerceMallOrderItemSnapshot";
import { IPageIEcommerceMallOrderItem } from "../../../../../api/structures/IPageIEcommerceMallOrderItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerOrdersOrderIdItemsItemId } from "../../../../../providers/getEcommerceMallCustomerOrdersOrderIdItemsItemId";
import { getEcommerceMallCustomerOrdersOrderIdItemsItemIdSnapshots } from "../../../../../providers/getEcommerceMallCustomerOrdersOrderIdItemsItemIdSnapshots";
import { patchEcommerceMallCustomerOrdersOrderIdItems } from "../../../../../providers/patchEcommerceMallCustomerOrdersOrderIdItems";

@Controller("/ecommerceMall/customer/orders/:orderId/items")
export class EcommercemallCustomerOrdersItemsController {
  /**
   * Retrieve a filtered and paginated list of order items within a specific order.
   *
   * This operation provides detailed item-level information for all order items belonging to the specified order, including product details, variant information, pricing, quantities, and current status.
   *
   * Supports filtering by status (paid, shipped, delivered, cancelled, refunded), product variant, and sorting options. Response includes comprehensive item data needed for order history views, seller fulfillment interfaces, and administrative oversight.
   *
   * Each order item represents a distinct product variant purchase within the order and can have its own independent status and cancellation/refund requests.
   *
   * @param connection
   * @param orderId The unique identifier of the parent order.
   * @param body Search criteria and pagination parameters for filtering order items within the order.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_order_items table filtering by ecommerce_mall_order_id (path parameter).
   *
   * Apply optional filters from requestBody:
   * - status: filter by item status (paid, shipped, delivered, cancelled, refunded)
   * - product_name: partial match on product name
   * - variant_sku: exact match on variant SKU
   * - date_range: filter by created_at timestamp range
   *
   * Sort results by created_at (descending) by default, support custom sorting.
   *
   * Apply pagination with configurable page size (default 20, max 100).
   *
   * Join with snapshot tables for immutable product/variant data as denormalized in order_items.
   *
   * Authorization: authenticated customers can view their own orders' items, sellers can view items for their products, administrators can view all items.
   *
   * Handle 404 if order does not exist or user lacks access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallOrderItem.IRequest,
  ): Promise<IPageIEcommerceMallOrderItem.ISummary> {
    try {
      return await patchEcommerceMallCustomerOrdersOrderIdItems({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order item within an order.
   *
   * This operation returns complete details for a single order item identified by its order ID and item ID. The response includes denormalized product information (product name, SKU, variant name), quantity purchased, unit price at purchase time, total price for the line item, and timestamps. Each order item contains references to snapshots of the product, variant, and seller as they existed at order creation time, ensuring historical accuracy.
   *
   * Authorization requirements vary by actor type: customers can view order items only from orders they created, sellers can view order items only for products they own, and administrators with elevated privileges can view all order items regardless of ownership. This ensures data isolation and privacy between customers and sellers.
   *
   * The operation supports order item identification using the unique order number format or UUID-based order ID. When the order item does not exist, is not accessible to the actor, or has been soft deleted, the operation returns a 404 Not Found error. Use this endpoint to display order item details in customer order history, seller sales reports, or administrative review interfaces.
   *
   * @param connection
   * @param orderId Order identifier containing the target order item. Can be UUID or order number format.
   * @param itemId Unique identifier of the order item to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_mall_order_items table to retrieve the order item matching the given orderId and itemId path parameters.
   *
   * Authorization Logic:
   * 1. Retrieve the order to determine ownership
   * 2. Check actor type and permissions:
   *    - For customer actors: verify order.customer_id matches authenticated customer ID
   *    - For seller actors: verify the order item's seller_snapshot_id matches authenticated seller ID or product belongs to seller
   *    - For admin/superAdmin actors: bypass ownership checks, allow viewing all items
   * 3. Return 404 if authorization fails or order item does not exist
   *
   * Query Implementation:
   * 1. Fetch order from ecommerce_mall_orders by orderId
   * 2. Fetch order item from ecommerce_mall_order_items by itemId and verify it belongs to the order
   * 3. Include denormalized fields: product_name, product_sku, variant_name, quantity, unit_price, total_price
   * 4. Verify deleted_at is NULL to ensure item is not soft deleted
   *
   * Error Handling:
   * - Return 404 if order does not exist
   * - Return 404 if order item does not exist or does not belong to the order
   * - Return 404 if item is soft deleted (deleted_at is not NULL)
   * - Return 403 if authenticated actor lacks authorization to view the order item
   *
   * Return the order item record with all fields including timestamps and snapshot references.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrderItem> {
    try {
      return await getEcommerceMallCustomerOrdersOrderIdItemsItemId({
        customer,
        orderId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve historical snapshots of an order item, including product, variant, and seller profile data as they existed at the time of purchase.
   *
   * This operation provides access to immutable point-in-time records that preserve the exact state of the order item when it was created. These snapshots are essential for order verification, dispute resolution, and historical reference, ensuring that customers and administrators can review what was purchased even if the underlying products have been deleted or modified by the seller.
   *
   * The response includes three types of snapshots: the product snapshot capturing product name, description, and pricing at purchase time; the variant snapshot preserving variant options and prices; and the seller profile snapshot showing the shop name and logo as they appeared when the order was placed. These snapshots remain accessible even after products are deleted or sellers close their accounts.
   *
   * Access to this endpoint is restricted to order customers (who can view their own order items) and administrators (who have platform-wide visibility for oversight and dispute resolution purposes). All snapshot access is logged for accountability and audit trail purposes.
   *
   * @param connection
   * @param orderId The unique identifier of the order containing the item
   * @param itemId The unique identifier of the order item within the order
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_mall_order_item_snapshots table for all snapshot records associated with the specified order item (itemId) within the given order (orderId).
   *
   * Validate that the caller has appropriate access: the order customer who owns the order, or an administrator with platform-wide access. Use the order customer relationship from ecommerce_mall_orders.customer_id to verify ownership.
   *
   * Join with product snapshot, variant snapshot, and seller profile snapshot data to return complete historical records. Include snapshot metadata such as created_at timestamp, actor reference (customer_id), and action type.
   *
   * Apply access control based on entity ownership and administrative privileges. Customers can only access snapshots of order items from their own orders. Administrators can access snapshots across all orders.
   *
   * Return the snapshots ordered by created_at in ascending order to show the chronological evolution of the order item's state. Include pagination if the number of snapshots exceeds a reasonable threshold (e.g., 100 records).
   *
   * Ensure all snapshot data includes the preserved product name, variant options, prices, and seller shop information for accurate historical reference. Do not include any data that could be modified or deleted by sellers or customers.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId/snapshots")
  public async snapshots(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrderItemSnapshot> {
    try {
      return await getEcommerceMallCustomerOrdersOrderIdItemsItemIdSnapshots({
        customer,
        orderId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
