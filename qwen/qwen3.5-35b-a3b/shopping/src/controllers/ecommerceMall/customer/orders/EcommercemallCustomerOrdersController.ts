import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrder } from "../../../../api/structures/IEcommerceMallOrder";
import { IPageIEcommerceMallOrder } from "../../../../api/structures/IPageIEcommerceMallOrder";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerOrdersOrderId } from "../../../../providers/getEcommerceMallCustomerOrdersOrderId";
import { patchEcommerceMallCustomerOrders } from "../../../../providers/patchEcommerceMallCustomerOrders";

@Controller("/ecommerceMall/customer/orders")
export class EcommercemallCustomerOrdersController {
  /**
   * Retrieve a filtered and paginated list of customer purchase orders.
   *
   * This operation provides comprehensive search capabilities for order management including status filtering, date range queries, customer identification, payment status checks, and shipment tracking. Users can search by order number, customer email, or product identifiers to locate specific transactions.
   *
   * Supports advanced filtering on order totals, shipping methods, and fulfillment status. The paginated response includes order summary information optimized for dashboard displays and order management interfaces.
   *
   * Customers can view their own orders, while sellers can view orders for products they manage, and administrators have full platform-wide access to all orders.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_orders table with pagination and filtering.
   *
   * Apply search filters on status (pending, paid, shipped, cancelled, refunded), date ranges (created_at, updated_at, paid_at, shipped_at, cancelled_at), customer ID or email, payment method, shipping method, order totals within range, and active/cancelled status.
   *
   * Join with ecommerce_mall_order_items for order item statistics (item count, total quantity) if requested.
   *
   * Optionally join with ecommerce_mall_customers for customer summary information (display name, email) when authorization permits.
   *
   * Order by created_at descending by default, with support for custom sort fields (status, total_amount, customer_name).
   *
   * Implement cursor-based pagination for large result sets with configurable page size (default 20, max 100).
   *
   * Validate authorization: customers see only their own orders, sellers see orders containing their products, admins and super admins see all orders.
   *
   * Return 200 with paginated order summaries on success.
   *
   * Return 401 if unauthorized.
   *
   * Return 400 if pagination parameters are invalid.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallOrder.IRequest,
  ): Promise<IPageIEcommerceMallOrder.ISummary> {
    try {
      return await patchEcommerceMallCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order from the ecommerce platform.
   *
   * This operation returns complete order information including the order number, overall status, customer details, line items with pricing, shipping information, and fulfillment tracking data. The order number is a unique identifier assigned at order creation and is used for customer reference and support inquiries.
   *
   * Only the customer who created the order can view its complete details, unless the requester is an administrator who has platform-wide order visibility. Order information includes the relationship to the customer, all order items with product references, and any associated shipment tracking information.
   *
   * If the order does not exist or the requesting user does not have permission to access it, the operation will return an appropriate error response. The order status reflects the current state of the entire order as derived from the statuses of all order items within it.
   *
   * @param connection
   * @param orderId The unique order identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_mall_orders table for the order with the specified UUID. Join with ecommerce_mall_order_items to retrieve line items, and join with ecommerce_mall_shipments for shipping information if available.
   *
   * Apply authorization check: if the requester is a customer, verify ownership (customer_id matches the authenticated customer). If the requester is an admin, allow access to any order. If the requester is a seller, only provide order items that belong to their products.
   *
   * Return the complete order object including all order items with product snapshot references, shipping details, and calculated totals. Ensure the order status is current based on the latest item statuses.
   *
   * Handle not-found cases by returning 404 if the order UUID does not exist. Handle authorization failures by returning 403 if the customer is not the order owner.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await getEcommerceMallCustomerOrdersOrderId({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
