import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipment } from "../../../../api/structures/IEcommerceMallShipment";
import { IPageIEcommerceMallShipment } from "../../../../api/structures/IPageIEcommerceMallShipment";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerShipmentsShipmentId } from "../../../../providers/getEcommerceMallCustomerShipmentsShipmentId";
import { patchEcommerceMallCustomerShipments } from "../../../../providers/patchEcommerceMallCustomerShipments";

@Controller("/ecommerceMall/customer/shipments")
export class EcommercemallCustomerShipmentsController {
  /**
   * Retrieve a filtered and paginated list of shipments with tracking information.
   *
   * This operation provides advanced search capabilities for viewing shipments across the ecommerce platform. Sellers can view their own shipments created during order fulfillment. Customers can view shipments containing items from their orders. Administrators have full access to view all shipments for oversight purposes.
   *
   * Supports comprehensive filtering by shipment status (pending, shipped, delivered, cancelled), date range, tracking number, and order association. The endpoint implements role-based access control to ensure data isolation between sellers, customers, and administrators.
   *
   * Pagination is handled using cursor-based approach for efficient large dataset navigation. Sorting defaults to creation date in descending order but can be customized by status or tracking update timestamp.
   *
   * Tracking information including carrier name and tracking number is conditionally visible based on shipment status and user role. Cancelled shipments have tracking information hidden from customers, while active shipments display full tracking details to all authorized users. Soft-deleted shipments are excluded from results by default.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for shipment filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_shipments table with pagination and filtering.
   *
   * Apply search filters on:
   * - shipmentStatus: filter by pending/shipped/delivered/cancelled
   * - createdAt: filter by date range (start, end)
   * - trackingNumber: partial match search
   * - sellerId: filter by seller (visible to admins only, otherwise filter by authenticated user)
   * - orderId: filter by order (visible to customer for their orders, admins see all)
   *
   * Authorization rules:
   * - Sellers: Only view shipments they created
   * - Customers: Only view shipments containing their order items
   * - Admins: View all shipments
   *
   * Pagination:
   * - Cursor-based pagination with page token
   * - Configurable page size (10-100 items, default 20)
   * - Sorting: createdAt descending by default
   *
   * Tracking information visibility:
   * - Show tracking info for shipments with status shipped/delivered
   * - Hide tracking info for cancelled shipments
   * - Customers and admins always see tracking info on non-cancelled shipments
   * - Sellers always see their own tracking info
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallShipment.IRequest,
  ): Promise<IPageIEcommerceMallShipment.ISummary> {
    try {
      return await patchEcommerceMallCustomerShipments({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific shipment record with tracking information and associated order items.
   *
   * This operation returns detailed information about a single shipment, including the shipping carrier name, tracking number, creation timestamp, and all order items included in the shipment. The shipment represents a physical package being sent to a customer containing one or more order items from a single seller.
   *
   * Access Control:
   * - Sellers can view all shipments they created
   * - Customers can view shipments for their orders to track delivery
   * - Administrators have full access to view all shipments across the platform
   *
   * The operation validates that the requesting user has permission to access the shipment. If the shipment does not exist or the user lacks authorization, an appropriate error is returned. Shipments with 'cancelled' status still return tracking information for historical reference.
   *
   * Related Operations:
   * - GET /orders/{orderId} - Retrieve order details containing this shipment
   * - PATCH /orders/{orderId}/shipments - List all shipments for an order
   * - PATCH /shipments - List and search shipments with filters
   *
   * The response includes complete tracking information that customers use to monitor package delivery status.
   *
   * @param connection
   * @param shipmentId The unique identifier of the shipment to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_shipments table by shipment ID.
   * 1. Validate shipmentId is a valid UUID format
   * 2. Look up shipment record in ecommerce_mall_shipments
   * 3. Check access control:
   *    - For sellers: verify seller_id matches the requesting seller
   *    - For customers: verify shipment's order_id belongs to customer's orders
   *    - For admins: allow access to all shipments
   * 4. If shipment exists and user has access:
   *    - Return shipment record with all fields (id, orderId, sellerId, carrierName, trackingNumber, createdAt, updatedAt, deletedAt)
   *    - Include associated order items from ecommerce_mall_shipment_items junction table
   * 5. If shipment not found: return 404 error
   * 6. If unauthorized: return 403 error
   * 7. Mark shipment access for audit logging
   *
   * Edge cases:
   * - Shipment may be soft-deleted (deletedAt not null) but still retrievable for historical reference
   * - Order items array may be empty if shipment was created but items not yet assigned (rare)
   * - Tracking number is immutable after shipment creation
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShipment> {
    try {
      return await getEcommerceMallCustomerShipmentsShipmentId({
        customer,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
