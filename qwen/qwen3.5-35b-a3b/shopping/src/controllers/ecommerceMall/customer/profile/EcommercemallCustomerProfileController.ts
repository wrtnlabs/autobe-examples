import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomer } from "../../../../api/structures/IEcommerceMallCustomer";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putEcommerceMallCustomerProfile } from "../../../../providers/putEcommerceMallCustomerProfile";

@Controller("/ecommerceMall/customer/profile")
export class EcommercemallCustomerProfileController {
  /**
   * Update a customer's personal profile information including display name and phone number.
   *
   * This operation allows authenticated customers to modify their profile settings. Customers can update their display name (used on reviews and order documentation) and/or phone number (used for shipping contact information). Both fields can be modified independently or together in a single request.
   *
   * The profile update is validated and saved immediately without requiring additional confirmation. Updated information is reflected across the platform: reviews show the new display name, shipping addresses use the updated phone number, and order history preserves the current profile state.
   *
   * Security: Only the profile owner (authenticated customer) can update their own profile. Customer profiles are private and cannot be viewed or modified by other users.
   *
   * @param connection
   * @param body Profile update data with optional display name and phone number fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Retrieve the authenticated customer's account from the session or authentication token.
   * Query the customer_profile associated with this customer.
   * Validate that any provided display_name meets length and format requirements.
   * Validate that any provided phone_number follows international phone number format.
   * Update only the fields provided in the request body (partial update).
   * Create a snapshot record preserving the previous values before the update.
   * Persist the changes to the database.
   * Return the updated customer profile including the new display name and phone number.
   * Log the profile update for audit trail purposes.
   *
   * Validation Rules:
   * - display_name: 1-100 characters, allowed characters include letters, numbers, spaces, and common punctuation
   * - phone_number: valid international phone number format with country code
   * - Both fields are optional; at least one field must be provided
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCustomer.IUpdate,
  ): Promise<IEcommerceMallCustomer> {
    try {
      return await putEcommerceMallCustomerProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
