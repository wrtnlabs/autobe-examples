import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallAddress } from "../../../../api/structures/IEcommerceMallAddress";
import { IPageIEcommerceMallAddress } from "../../../../api/structures/IPageIEcommerceMallAddress";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteEcommerceMallCustomerAddressesAddressId } from "../../../../providers/deleteEcommerceMallCustomerAddressesAddressId";
import { getEcommerceMallCustomerAddressesAddressId } from "../../../../providers/getEcommerceMallCustomerAddressesAddressId";
import { patchEcommerceMallCustomerAddresses } from "../../../../providers/patchEcommerceMallCustomerAddresses";
import { postEcommerceMallCustomerAddresses } from "../../../../providers/postEcommerceMallCustomerAddresses";

@Controller("/ecommerceMall/customer/addresses")
export class EcommercemallCustomerAddressesController {
  /**
   * Create a new shipping address for the authenticated customer account.
   *
   * This operation enables customers to add delivery locations to their account for use during order placement. Each address stores complete recipient information (name and phone number) and full street address details (street, city, state) required for shipping labels and delivery coordination.
   *
   * The authenticated customer creates addresses associated with their account. All required address fields must be provided during creation: recipient_name, recipient_phone, street, city, and state. Addresses with missing required information are rejected with validation errors.
   *
   * Upon successful creation, the new address is added to the customer's saved addresses list. If the customer has no existing saved addresses, this address is automatically designated as the default address for convenience during checkout. Otherwise, it is created as a non-default address that the customer can set as default through address editing.
   *
   * Addresses are soft-deleted when removed, meaning they are marked as deleted rather than permanently removed from the database. This preserves address information in historical order records even after removal from the customer's active address list. New orders placed after an address update or deletion will use the current active address information.
   *
   * **Authorization**: Only authenticated customers can create addresses. Guest users and unauthenticated visitors cannot access this endpoint.
   *
   * @param connection
   * @param body Shipping address information for the new delivery location.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Extract customer ID from authentication context (JWT token)
   * 2. Validate request body contains all required fields:
   *    - recipient_name: non-empty string
   *    - recipient_phone: non-empty string (may include country code)
   *    - street: non-empty string (may include apartment/suite)
   *    - city: non-empty string
   *    - state: non-empty string
   * 3. Check if customer has existing addresses (query ecommerce_mall_addresses where customer_id = authenticated customer)
   * 4. If customer has no existing addresses, set is_default = true
   * 5. If customer has existing addresses, set is_default = false
   * 6. Insert new record into ecommerce_mall_addresses with:
   *    - id: auto-generated UUID
   *    - ecommerce_mall_customer_id: from authentication
   *    - recipient_name, recipient_phone, street, city, state: from request body
   *    - is_default: determined in step 4-5
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   *    - deleted_at: null (active address)
   * 7. Return the created address record with all fields including generated id
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallAddress.ICreate,
  ): Promise<IEcommerceMallAddress> {
    try {
      return await postEcommerceMallCustomerAddresses({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of shipping addresses belonging to the authenticated customer.
   *
   * This operation provides comprehensive address listing capabilities for the ecommerce_mall_addresses table. Customers can view all their saved shipping addresses from their account settings, including recipient name, recipient phone number, street address, city, state/province, default address status, and creation timestamp. The response includes pagination metadata to handle large address lists efficiently.
   *
   * Addresses are filtered by the authenticated customer's ID, ensuring data isolation between customers. Customers can only retrieve their own addresses. Soft-deleted addresses (records with deleted_at set) are excluded from results to maintain data isolation and order history integrity. Only active addresses can be used for new orders.
   *
   * The operation supports pagination with configurable page size and cursor-based navigation for efficient handling of large datasets. The default address (is_default = true) is clearly identified in each record for checkout convenience.
   *
   * This endpoint is part of the shipping address management functionality, allowing customers to view their saved addresses before creating, editing, or deleting them. The list operation is typically used as a prerequisite for other address management operations such as GET /addresses/{id} or DELETE /addresses/{id}.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for address listing. Includes optional filters on recipient name, city, state, and date range, plus pagination controls.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_addresses table with filters applied.
   *
   * Filtering:
   * - Customer ID: Automatically filtered by authenticated user's ID (data ownership enforcement)
   * - Optional: Recipient name pattern match
   * - Optional: City or state prefix match
   * - Optional: Creation date range
   * - Optional: Address status (if supported)
   *
   * Sorting:
   * - Default: Created at descending (newest first)
   * - Optional: Sort by recipient name (ascending/descending)
   * - Optional: Sort by city (ascending/descending)
   *
   * Pagination:
   * - Cursor-based pagination using created_at timestamp or ID
   * - Configurable page size (default: 20, max: 100)
   * - Return next cursor for pagination continuation
   *
   * Query optimization:
   * - Index on customer_id, created_at, recipient_name
   * - Avoid N+1 queries by joining efficiently
   * - Return summary fields only (no deep nested data)
   *
   * Authorization:
   * - Requires customer authentication
   * - Verify address belongs to authenticated customer (enforce data isolation)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallAddress.IRequest,
  ): Promise<IPageIEcommerceMallAddress.ISummary> {
    try {
      return await patchEcommerceMallCustomerAddresses({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single shipping address by its unique identifier.
   *
   * This operation returns complete information for a specific shipping address, including recipient details (name and phone number), full street address, city, state, and default address status. Only the customer who owns the address can retrieve it.
   *
   * The endpoint enforces data isolation by ensuring customers can only view their own addresses. Attempts to access another customer's address will result in a not found error for security and privacy protection.
   *
   * Soft-deleted addresses are excluded from results to maintain data integrity and prevent access to removed addresses.
   *
   * Related operations:
   * - PATCH /addresses - list all customer addresses with search and pagination
   * - POST /addresses - create a new shipping address
   * - PUT /addresses/{addressId} - update an existing address
   * - DELETE /addresses/{addressId} - remove a shipping address
   *
   * @param connection
   * @param addressId Unique identifier of the shipping address to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_addresses table for the address matching the provided addressId UUID.
   *
   * Validation and authorization:
   * 1. Verify the addressId is a valid UUID format
   * 2. Retrieve the address record from database
   * 3. Verify the address belongs to the currently authenticated customer (check ecommerce_mall_customer_id matches current user's customer ID)
   * 4. Verify the address is not soft-deleted (deleted_at is null)
   *
   * Error handling:
   * - Return 404 Not Found if address does not exist
   * - Return 404 Not Found if address belongs to another customer (treat as not found for security)
   * - Return 404 Not Found if address is soft-deleted
   *
   * Response construction:
   * - Return complete address object with all fields: id, ecommerce_mall_customer_id, recipient_name, recipient_phone, street, city, state, is_default, created_at, updated_at
   * - Do not include deleted_at in response as it indicates soft deletion status
   *
   * Database query:
   * SELECT * FROM ecommerce_mall_addresses
   * WHERE id = $1 AND deleted_at IS NULL
   * LIMIT 1
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":addressId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallAddress> {
    try {
      return await getEcommerceMallCustomerAddressesAddressId({
        customer,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a shipping address from your address book.
   *
   * This operation permanently removes the address from your active address list by marking it as deleted. The address is soft-deleted, meaning the address data is preserved in the database for historical order records but no longer available for new orders or address selection.
   *
   * **Address Requirements**:
   *
   * - The address must belong to the authenticated customer making the request
   * - The address must not be associated with any pending or active orders
   * - If the address is marked as your default shipping address, you must ensure you have at least one other valid address in your address book
   *
   * **Deletion Behavior**:
   *
   * - The deleted_at timestamp is set to the current time, marking the address as deleted
   * - The address is removed from your address list and cannot be selected for new orders
   * - Historical order records retain the original address information at the time of purchase
   * - The deletion is permanent and the address cannot be recovered
   *
   * **Associated Order Validation**:
   *
   * - Addresses linked to orders in active states (waiting for shipping, shipped, cancelled awaiting refund) cannot be deleted
   * - Orders in completed states with no pending transactions do not prevent deletion
   * - The system checks all order associations before permitting deletion
   *
   * **Default Address Handling**:
   *
   * - Deleting your default address requires you to have an alternative address available
   * - The system will not automatically select a new default
   * - You must manually select another address as default through the address update operation
   *
   * This operation is available to authenticated customers only. Unauthenticated users cannot delete addresses.
   *
   * @param connection
   * @param addressId The unique identifier of the shipping address to delete.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Validate customer authentication and extract customer_id from session token
   * 2. Retrieve the address by addressId from ecommerce_mall_addresses where customer_id matches
   * 3. Verify the address belongs to the authenticated customer
   * 4. Check for associated orders in active states:
   *    - Query ecommerce_mall_orders joined with ecommerce_mall_addresses via customer association
   *    - Filter for orders where shipping address_id equals addressId
   *    - Check order status: if ANY order has status in ['waiting_for_shipping', 'shipped', 'cancelled'] with pending refund, return error
   * 5. Check if address is marked as is_default = true
   *    - If true and this is the only address for customer, return error requiring at least one address
   * 6. Set deleted_at to current timestamp in database transaction
   * 7. Create snapshot in ecommerce_mall_address_snapshots before deletion (copy all current fields)
   * 8. Commit transaction
   * 9. Return 204 No Content (or 200 with null body)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":addressId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallCustomerAddressesAddressId({
        customer,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
