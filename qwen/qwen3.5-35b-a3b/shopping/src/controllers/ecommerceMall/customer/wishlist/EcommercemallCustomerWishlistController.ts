import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallWishlist } from "../../../../api/structures/IEcommerceMallWishlist";
import { IPageIEcommerceMallWishlist } from "../../../../api/structures/IPageIEcommerceMallWishlist";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteEcommerceMallCustomerWishlistWishlistId } from "../../../../providers/deleteEcommerceMallCustomerWishlistWishlistId";
import { getEcommerceMallCustomerWishlistWishlistId } from "../../../../providers/getEcommerceMallCustomerWishlistWishlistId";
import { patchEcommerceMallCustomerWishlist } from "../../../../providers/patchEcommerceMallCustomerWishlist";
import { postEcommerceMallCustomerWishlist } from "../../../../providers/postEcommerceMallCustomerWishlist";

@Controller("/ecommerceMall/customer/wishlist")
export class EcommercemallCustomerWishlistController {
  /**
   * Create a new wishlist entry by associating a product with the authenticated customer's wishlist.
   *
   * This operation allows a registered customer to add a product to their personal wishlist for future purchase consideration. The system will create a record linking the customer to the specified product.
   *
   * Security and Authentication:
   * - Requires authenticated customer session
   * - Cannot create wishlist entries for other customers
   * - Banned customers cannot create wishlist entries
   *
   * Business Rules:
   * - Prevents duplicate entries: A customer cannot add the same product to their wishlist multiple times
   * - Product validity: The referenced product must exist and be active (recommended, not enforced at API level)
   * - Customer-product relationship: Each customer can wishlist each product exactly once
   *
   * Error Handling:
   * - Returns 409 Conflict if product is already in customer's wishlist
   * - Returns 404 Not Found if the referenced product does not exist
   * - Returns 401 Unauthorized if customer is not authenticated
   * - Returns 403 Forbidden if customer account is banned
   *
   * Related Operations:
   * - GET /wishlist: List all products in customer's wishlist with pagination and sorting
   * - DELETE /wishlist/{wishlistEntryId}: Remove a specific product from wishlist
   *
   * @param connection
   * @param body Information required to create a wishlist entry
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Extract authenticated customer_id from request context (JWT token)
   * 2. Validate customer_id is not null (authenticated)
   * 3. Validate customer is not banned by querying ecommerce_mall_customers
   * 4. Validate product_id is provided in request body as UUID string
   * 5. Validate product exists by querying ecommerce_mall_products
   * 6. Check for existing wishlist entry with composite unique constraint: (ecommerce_mall_customer_id, ecommerce_mall_product_id)
   * 7. If entry exists, return 409 Conflict with error message 'Product already in wishlist'
   * 8. If not found, insert new record into ecommerce_mall_wishtables with:
   *    - id: auto-generated UUID
   *    - ecommerce_mall_customer_id: from authenticated context
   *    - ecommerce_mall_product_id: from request body
   *    - created_at: current timestamp (NOW())
   *    - updated_at: current timestamp (NOW())
   * 9. Return 201 Created with the created wishlist entry object
   * 10. If database constraint violated (race condition), catch and return 409 Conflict
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallWishlist.ICreate,
  ): Promise<IEcommerceMallWishlist> {
    try {
      return await postEcommerceMallCustomerWishlist({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of products saved in the customer's wishlist, including current stock status and product information.
   *
   * This operation provides the customer with a filtered and sorted view of their wishlist entries. Each wishlist item includes the product's name, base price, current stock status, and availability for purchase. The stock status is dynamically fetched from the product catalog on each request to ensure accuracy.
   *
   * Supports advanced filtering by product availability (in-stock, out-of-stock, all), sorting by creation date, product name, or price. Pagination enables efficient browsing of large wishlists with configurable page sizes.
   *
   * Security: Only the authenticated customer can access their own wishlist. The system validates authentication before processing any request. If the customer is banned, access is denied (section 1170).
   *
   * Related operations:
   * - POST /wishlist - Add a product to the wishlist
   * - DELETE /wishlist/{wishlistId} - Remove a product from the wishlist
   * - GET /products/{productId} - View detailed product information
   *
   * @param connection
   * @param body Search criteria and pagination parameters for wishlist retrieval
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_wishlists table filtered by the authenticated customer's ID.
   *
   * Join with ecommerce_mall_products to fetch current product information including name, basePrice, and isActive status.
   *
   * Apply search filters:
   * - If stockStatus filter provided: filter products where (isActive = true AND stockQuantity > 0) for 'in-stock', or (isActive = false OR stockQuantity = 0) for 'out-of-stock', or no filter for 'all'
   * - If sorting by 'created_at': ORDER BY created_at ASC/DESC
   * - If sorting by 'product_name': ORDER BY products.name ASC/DESC
   * - If sorting by 'price': ORDER BY products.basePrice ASC/DESC
   *
   * Apply pagination with cursor-based or offset-based pagination:
   * - Calculate total count for pagination metadata
   * - Return page data with configurable pageSize (default: 20, max: 100)
   *
   * Return each wishlist entry as IEcommerceMallWishlist.ISummary with:
   * - wishlist entry id and created_at
   * - product id, name, basePrice
   * - stock status: 'in-stock' if product.active AND variant stock > 0, else 'out-of-stock'
   *
   * Business rules:
   * - Validate customer authentication (section 1170)
   * - Allow access only to customer's own wishlist (prevent unauthorized access)
   * - Include products even if out of stock (section 643)
   * - Products deleted by seller are automatically removed from wishlists (section 639)
   * - Handle concurrent wishlist modifications with optimistic locking if needed (section 1326)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallWishlist.IRequest,
  ): Promise<IPageIEcommerceMallWishlist.ISummary> {
    try {
      return await patchEcommerceMallCustomerWishlist({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific wishlist entry from the ecommerce_mall_wishlists table that links a customer to a bookmarked product for future purchase consideration.
   *
   * This operation fetches a single wishlist entry with its unique identifier (id) and includes complete product information for display purposes through a join with the ecommerce_mall_products table. The wishlist entry stores the customer's bookmark of a product at the product level (not specific variants), providing flexibility for customers who want to see all available option combinations at a later time.
   *
   * Only the customer who owns this wishlist entry can access it. The ecommerce_mall_wishlists table enforces a composite unique constraint on (ecommerce_mall_customer_id, ecommerce_mall_product_id), ensuring each customer can only bookmark each product once. The system validates that the authenticated user is the owner before returning the wishlist entry data, preventing unauthorized access to another customer's bookmarks.
   *
   * Related operations:
   * - PATCH /ecommerceMall/customer/wishlist must be pre-executed to get a paginated list of all wishlist entries for a customer. Detailed entry information is obtained by specifying the wishlistId in this path parameter.
   * - POST /ecommerceMall/customer/wishlist is used to add a new product to a customer's wishlist.
   * - DELETE /ecommerceMall/customer/wishlist/{wishlistId} is used to remove a product from a customer's wishlist.
   *
   * Business behaviors referenced:
   * - Automatic removal: When a product is deleted by its seller, THE system SHALL automatically remove it from all customer wishlists (section 246).
   * - Privacy: Wishlist entries are private to the customer who owns them (section 1170).
   * - Pagination: THE wishlist SHALL be paginated when displaying many products (section 9, 47).
   * - Out-of-stock handling: THE system SHALL allow adding out-of-stock products and show the stock status in the wishlist display (section 328).
   *
   * @param connection
   * @param wishlistId The unique identifier of the wishlist entry to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_wishlists table for the entry matching the provided wishlistId path parameter.
   *
   * Authz validation:
   * 1. Verify customer is authenticated via JWT session
   * 2. Validate that the wishlist entry's ecommerce_mall_customer_id matches the authenticated customer's ID
   * 3. Return 404 if wishlist entry not found (to prevent enumeration attacks)
   * 4. Return 403 if authenticated customer does not own the entry (should not occur if audit passes, but defensive check)
   *
   * Query optimization:
   * - Select only required fields to minimize data transfer
   * - Join with ecommerce_mall_products to include product details (name, basePrice, main image URL, stock status, seller info)
   * - Do not join with product variants as wishlist stores product-level bookmarks, not variant selections
   * - Include product availability status from stockQuantity
   *
   * Error handling:
   * - 404 Not Found: If wishlist entry does not exist or customer does not have access
   * - 401 Unauthorized: If no valid authentication token provided
   * - 500 Internal Server Error: If database query fails
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":wishlistId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallWishlist> {
    try {
      return await getEcommerceMallCustomerWishlistWishlistId({
        customer,
        wishlistId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes a wishlist entry from the customer's saved products.
   *
   * This operation deletes a single wishlist record that links a customer to a product they have bookmarked for future purchase consideration. The wishlist entry is identified by its unique UUID.
   *
   * Security and Authorization:
   * - Only the customer who owns this wishlist entry can remove it
   * - Authentication is required - unauthenticated requests will be rejected
   * - The system validates that the customer making the request is the owner of the wishlist entry
   *
   * Behavior:
   * - Removal is immediate and permanent (hard delete)
   * - No confirmation dialog required - single-click removal
   * - The product itself remains on the platform and can be added to the wishlist again
   * - The cascade delete ensures the wishlist entry is removed without orphaned records
   *
   * What is NOT affected:
   * - The product listing remains unchanged and available for purchase
   * - Product availability and stock quantities are unaffected
   * - Product reviews and ratings are preserved
   * - No snapshot or audit record is created (wishlist entries have no audit trail per domain model)
   *
   * Error Handling:
   * - Returns 404 if the wishlist entry does not exist
   * - Returns 403 if the authenticated customer does not own this wishlist entry
   * - Returns 401 if no authentication is provided
   *
   * @param connection
   * @param wishlistId The unique identifier of the wishlist entry to remove
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Delete the wishlist entry matching the wishlistId path parameter.
   *
   * Implementation steps:
   * 1. Authenticate the request and extract customer identity from JWT token
   * 2. Query ecommerce_mall_wishlists table for record where id = wishlistId AND ecommerce_mall_customer_id = authenticated customer's ID
   * 3. If no record found, return 404 Not Found
   * 4. If found but customer ID does not match authenticated user, return 403 Forbidden
   * 5. Delete the record (ON DELETE CASCADE handles FK cleanup)
   * 6. Return 204 No Content on success
   *
   * Database query:
   * DELETE FROM ecommerce_mall_wishlists WHERE id = $1 AND ecommerce_mall_customer_id = $2
   *
   * Validation:
   * - wishlistId must be a valid UUID format
   * - Customer must be authenticated and own the wishlist entry
   * - Only one wishlist entry per customer-product pair exists (enforced by @@unique constraint)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":wishlistId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallCustomerWishlistWishlistId({
        customer,
        wishlistId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
