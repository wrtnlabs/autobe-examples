import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallReview } from "../../../../../api/structures/IEcommerceMallReview";
import { IPageIEcommerceMallReview } from "../../../../../api/structures/IPageIEcommerceMallReview";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchEcommerceMallCustomerReviewsSearch } from "../../../../../providers/patchEcommerceMallCustomerReviewsSearch";

@Controller("/ecommerceMall/customer/reviews/search")
export class EcommercemallCustomerReviewsSearchController {
  /**
   * Search and filter customer reviews for specific products or retrieve your review history.
   *
   * This operation provides review retrieval capabilities with filtering based on product, rating, verification status, and text content. Customers can search reviews for products they are viewing, or filter their own review history using appropriate credentials.
   *
   * The operation filters out deleted reviews automatically, ensuring only active reviews are returned. This aligns with the business rule that deleted reviews should not contribute to average rating calculations or be displayed on product pages.
   *
   * Supports text search using trigram indexing on the review body for flexible content matching. Supports sorting by creation date (newest first by default) or by rating.
   *
   * Pagination is required for efficient handling of large review datasets. The operation returns paginated results with cursor-based navigation for consistent pagination across multiple requests.
   *
   * @param connection
   * @param body Search criteria including filters, pagination, and sorting options
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_mall_reviews table with the following logic:
   *
   * 1. Build WHERE clause:
   *    - Filter by customer_id if provided in request body
   *    - Filter by product_id if provided in request body
   *    - Filter by is_verified_purchase if provided in request body
   *    - Filter by rating range (rating >= min, rating <= max) if provided
   *    - Filter by text search using body gin_trgm_ops index if search term provided
   *    - Always filter: deleted_at IS NULL to exclude deleted reviews
   *
   * 2. JOIN requirements:
   *    - Join with ecommerce_mall_customers to get customer display name (if customer_id not used as filter)
   *    - Handle deleted customer accounts: display 'deleted user' if customer was deleted
   *
   * 3. Sorting:
   *    - Default: created_at DESC (newest first)
   *    - Alternative: rating DESC, rating ASC
   *
   * 4. Pagination:
   *    - Apply page number and page size from request body
   *    - Return cursor-based pagination metadata
   *
   * 5. Response aggregation:
   *    - Return review summary with customer display name (or 'deleted user')
   *    - Include rating stars, title, body excerpt
   *    - Include created_at timestamp
   *
   * 6. Validation:
   *    - Validate rating filter values are integers between 1-5
   *    - Validate page and pageSize are positive integers
   *    - Validate search term length (min 2 chars, max 200 chars)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallReview.IRequest,
  ): Promise<IPageIEcommerceMallReview.ISummary> {
    try {
      return await patchEcommerceMallCustomerReviewsSearch({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
