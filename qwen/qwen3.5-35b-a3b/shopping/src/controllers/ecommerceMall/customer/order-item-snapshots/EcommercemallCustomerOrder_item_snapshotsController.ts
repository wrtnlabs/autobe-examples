import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrderItemSnapshot } from "../../../../api/structures/IEcommerceMallOrderItemSnapshot";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerOrderItemSnapshotsSnapshotId } from "../../../../providers/getEcommerceMallCustomerOrderItemSnapshotsSnapshotId";

@Controller("/ecommerceMall/customer/order-item-snapshots/:snapshotId")
export class EcommercemallCustomerOrder_item_snapshotsController {
  /**
   * Retrieve a single order item snapshot record that captures a status change history event.
   *
   * This endpoint returns the immutable audit snapshot that records when an order item's status changed from one state to another, triggered by either a cancellation request or refund request being processed by a seller.
   *
   * The snapshot contains complete before-and-after status information, the triggering request reference, and the seller who processed the change. This information is used for dispute resolution, compliance tracking, and historical order item status auditing.
   *
   * Authorization requirements:
   * - Customers: Only access snapshots for order items they own (their orders)
   * - Sellers: Only access snapshots for order items from orders they fulfilled
   * - Administrators: Access to any order item snapshot
   *
   * The snapshot is immutable and cannot be modified or deleted once created. This endpoint ensures data integrity by only allowing read access to historical status change records.
   *
   * @param connection
   * @param snapshotId The unique identifier of the order item snapshot to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_order_item_snapshots table by primary key ID.
   *
   * 1. Validate snapshotId is a valid UUID format
   * 2. Verify snapshot exists and is not soft-deleted (deleted_at is null)
   * 3. Authorization check:
   *    - For customers: Verify customer owns the order associated with order_item_id
   *    - For sellers: Verify seller is the changed_by_seller_id or owns products in the order
   *    - For admins: Skip authorization check
   * 4. Join with ecommerce_mall_order_items to validate order_item_id relationship
   * 5. Optionally join with ecommerce_mall_cancellation_requests or ecommerce_mall_refund_requests based on which triggered the snapshot
   * 6. Return snapshot with all fields: id, order_item_id, cancellation_request_id, refund_request_id, changed_by_seller_id, old_status, new_status, change_reason, created_at, updated_at
   * 7. If snapshot not found, return 404 Not Found
   * 8. If authorization fails, return 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrderItemSnapshot> {
    try {
      return await getEcommerceMallCustomerOrderItemSnapshotsSnapshotId({
        customer,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
