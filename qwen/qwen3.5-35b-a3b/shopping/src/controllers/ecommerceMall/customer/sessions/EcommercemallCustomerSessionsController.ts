import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCustomerSession } from "../../../../api/structures/IEcommerceMallCustomerSession";
import { IPageIEcommerceMallCustomerSession } from "../../../../api/structures/IPageIEcommerceMallCustomerSession";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerSessionsSessionId } from "../../../../providers/getEcommerceMallCustomerSessionsSessionId";
import { patchEcommerceMallCustomerSessions } from "../../../../providers/patchEcommerceMallCustomerSessions";

@Controller("/ecommerceMall/customer/sessions")
export class EcommercemallCustomerSessionsController {
  /**
   * Retrieve a list of active sessions for the authenticated customer account.
   *
   * This operation allows customers to monitor their account security by viewing all active sessions across devices. Each session record contains the session identifier, creation timestamp, IP address, request URL, referrer information, and expiration status.
   *
   * Customers can filter sessions by date ranges for last activity time (created_at or updated_at) and by IP address patterns to identify sessions from specific locations or devices. The endpoint supports pagination to efficiently handle customers with many active sessions.
   *
   * Results are sorted by creation date in descending order by default, with the most recent sessions appearing first. Sensitive data such as access and refresh tokens are excluded from the response to maintain security.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for customer session list filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the appropriate session table based on the authenticated user's actor type.
   *
   * For customer sessions: query ecommerce_mall_customer_sessions
   * For seller sessions: query ecommerce_mall_seller_sessions
   * For admin sessions: query ecommerce_mall_admin_sessions
   * For super admin sessions: query ecommerce_mall_super_admin_sessions
   * For guest sessions: query ecommerce_mall_guest_sessions
   *
   * Apply filters from request body:
   * - Filter by status (active/inactive)
   * - Filter by device type if specified
   * - Filter by date range for last activity time
   * - Filter by IP address pattern if specified
   *
   * Implement cursor-based pagination for large result sets.
   * Return session summary information without including sensitive data like refresh tokens.
   *
   * Sort results by creation_timestamp descending (most recent first).
   * Include total count and pagination metadata in response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCustomerSession.IRequest,
  ): Promise<IPageIEcommerceMallCustomerSession.ISummary> {
    try {
      return await patchEcommerceMallCustomerSessions({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific authentication session.
   *
   * This operation provides comprehensive session details including JWT token metadata, connection information, and session lifecycle status. Each session represents an authenticated login event where the user successfully provided valid credentials for their account type (customer, seller, admin, super-admin, or guest).
   *
   * The session data includes the originating client IP address, request origin URL (href), HTTP referrer from the login request, and temporal information showing when the session was created and when it expires. This information is valuable for security auditing, active session management, and troubleshooting authentication issues.
   *
   * Session details are protected by authorization middleware that verifies the requesting actor owns the session or has administrative privileges. The operation returns complete session metadata without exposing sensitive token values directly in the API response.
   *
   * Related operations: List all sessions for the current actor using PATCH /sessions. Terminate a session using DELETE /sessions/{sessionId}.
   *
   * @param connection
   * @param sessionId Unique identifier of the session to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the appropriate session table based on the session owner's actor type.
   *
   * 1. Extract sessionId from path parameter (UUID format)
   * 2. Determine actor type by checking which session table contains the session
   * 3. Verify the requesting actor owns this session or has admin privileges
   * 4. Query session record with full metadata
   * 5. Calculate remaining TTL and current status (active/expired/expiring-soon)
   * 6. Return session details excluding raw token values for security
   *
   * Authorization: Session owner (customer/seller/admin/super-admin/guest) or platform administrator with session management privileges.
   *
   * Error handling: Return 404 if session not found, 403 if unauthorized, 401 if no valid authentication token.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCustomerSession> {
    try {
      return await getEcommerceMallCustomerSessionsSessionId({
        customer,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
