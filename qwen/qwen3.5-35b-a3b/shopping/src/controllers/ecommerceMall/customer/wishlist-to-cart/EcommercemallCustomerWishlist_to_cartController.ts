import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCartItem } from "../../../../api/structures/IEcommerceMallCartItem";
import { IEcommerceMallWishlistToCartRequest } from "../../../../api/structures/IEcommerceMallWishlistToCartRequest";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { postEcommerceMallCustomerWishlistToCart } from "../../../../providers/postEcommerceMallCustomerWishlistToCart";

@Controller("/ecommerceMall/customer/wishlist-to-cart")
export class EcommercemallCustomerWishlist_to_cartController {
  /**
   * Convert a product from your wishlist to a shopping cart item by selecting a specific variant.
   *
   * This operation bridges the wishlist and cart workflows, allowing customers to move a bookmarked product into their purchase preparation. Since wishlists store products (not variants) while carts require specific variant selections, this endpoint requires both the wishlist entry reference and the chosen variant to create a valid cart item.
   *
   * The operation validates that:
   * - The customer is authenticated and owns the wishlist entry
   * - The product exists and is still available
   * - The selected variant belongs to the wishlisted product
   * - The variant has available stock
   *
   * If any validation fails, the operation rejects the request with an appropriate error.
   *
   * After successful execution, the product appears in the customer's cart with the selected variant, quantity of 1, and the price captured at addition time. The wishlist entry remains unchanged, as carts and wishlists maintain independent states (requirement 652).
   *
   * @param connection
   * @param body Identification of the wishlist entry and variant selection for cart addition
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Authenticate the requesting customer from the session token
   * 2. Look up the wishlist entry by wishlistEntryId
   * 3. Validate the wishlist entry belongs to the authenticated customer
   * 4. Fetch the product referenced in the wishlist entry
   * 5. Validate the product exists and is still active (not deleted)
   * 6. Parse the variantId from the request body
   * 7. Fetch the product variant and validate it exists
   * 8. Validate the variant's product_id matches the wishlist entry's product_id
   * 9. Validate the variant is active (is_active = true)
   * 10. Validate the variant has stock_quantity > 0
   * 11. Check if a cart exists for this customer; create if not
   * 12. Check if a cart item already exists for (cart_id, variant_id); if so, increment quantity
   * 13. Insert new cart item with quantity=1, price=variant's current price
   * 14. Update cart's updated_at timestamp
   * 15. Return the created/updated cart item with product and variant details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async transferFromWishlist(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallWishlistToCartRequest,
  ): Promise<IEcommerceMallCartItem> {
    try {
      return await postEcommerceMallCustomerWishlistToCart({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
