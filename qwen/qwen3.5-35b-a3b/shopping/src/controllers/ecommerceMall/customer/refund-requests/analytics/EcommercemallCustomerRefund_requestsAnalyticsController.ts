import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallRefundRequestAnalytic } from "../../../../../api/structures/IEcommerceMallRefundRequestAnalytic";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerRefundRequestsAnalytics } from "../../../../../providers/getEcommerceMallCustomerRefundRequestsAnalytics";

@Controller("/ecommerceMall/customer/refund-requests/analytics")
export class EcommercemallCustomerRefund_requestsAnalyticsController {
  /**
   * Retrieve aggregated statistics and analytics about refund requests across the platform.
   *
   * This operation provides a comprehensive overview of refund request metrics including total counts, status breakdowns, approval rates, and trend data. The data is aggregated from the ecommerce_mall_refund_requests table and can be used for dashboard displays, administrative monitoring, and business intelligence purposes.
   *
   * The analytics include:
   * - Total number of refund requests in the system
   * - Breakdown by status (pending, approved, rejected, refunded)
   * - Approval and rejection rates as percentages
   * - Recent activity statistics (last 30 days, last 7 days)
   * - Average processing time for resolved requests
   * - Seller-level refund statistics (for seller accounts viewing their shop analytics)
   *
   * This operation is typically used by administrators and sellers to monitor platform health and understand refund patterns. The data is computed on-the-fly from the current state of refund request records.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query aggregated statistics from ecommerce_mall_refund_requests table.
   *
   * 1. Calculate total count of all refund requests
   * 2. Group and count requests by status field (pending, approved, rejected, refunded)
   * 3. Calculate approval rate: (approved + refunded) / total * 100
   * 4. Calculate rejection rate: rejected / total * 100
   * 5. For seller context: filter statistics to only include order items owned by the authenticated seller
   * 6. Calculate average time from submitted_at to decision_at for resolved requests (approved/rejected)
   * 7. Count requests created in last 7 days and last 30 days
   * 8. Return all metrics in a single response object
   *
   * Handle edge cases:
   * - Return zero values when no refund requests exist
   * - Handle null decision_at times when calculating average processing time
   * - Exclude soft-deleted records (deleted_at is null)
   * - If seller context exists, join with ecommerce_mall_order_items to filter by seller_snapshot_id
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async getAnalytics(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IEcommerceMallRefundRequestAnalytic> {
    try {
      return await getEcommerceMallCustomerRefundRequestsAnalytics({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
