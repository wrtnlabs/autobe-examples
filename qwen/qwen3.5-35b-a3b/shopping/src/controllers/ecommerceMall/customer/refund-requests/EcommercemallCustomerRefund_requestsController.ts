  /**
   * Retrieve detailed information about a specific refund request.
   *
   * This operation fetches a single refund request record identified by its unique ID, returning complete details including the refund reason, current status (pending/approved/rejected), creation timestamp, deadline for submission (7 days after delivery), and the associated order item reference.
   *
   * **Access Control**:
   * - Customers can view refund requests they created for their order items
   * - Sellers can view refund requests for order items in their shops
   * - Both parties can see the request status and timestamp information
   *
   * **Related Operations**:
   * - `PATCH /refund-requests` (index) to list refund requests with search filters
   * - `PATCH /refund-requests/{refundRequestId}` (update) to respond to a refund request as a seller
   *
   * **Response Contents**:
   * - Request identifier and order item association
   * - Customer-provided refund reason
   * - Current status: pending, approved, or rejected
   * - Time limit deadline calculated from delivery confirmation
   * - Creation and last update timestamps
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_mall_refund_requests table for a record matching the refundRequestId UUID.
   *
   * 1. Validate that refundRequestId is a valid UUID format
   * 2. Execute SELECT query with WHERE id = $1 parameter
   * 3. Apply soft delete filter (deleted_at IS NULL) unless the requesting actor has audit permissions
   * 4. Join with ecommerce_mall_order_items to include order context if needed
   * 5. Calculate and return time_limit deadline if not stored
   * 6. Apply access control checks:
   *    - For customers: verify order_item belongs to their order
   *    - For sellers: verify order_item belongs to their shop's products
   * 7. Return 404 if refund request not found or soft-deleted
   * 8. Return 403 if accessing another user's refund request
   *
   * **Error Handling**:
   * - 404 Not Found: refund request does not exist or has been soft-deleted
   * - 403 Forbidden: actor lacks permission to view this refund request
   * - 400 Bad Request: invalid UUID format for refundRequestId
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":refundRequestId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallRefundRequest> {
    try {
      return await getEcommerceMallCustomerRefundRequestsRefundRequestId({
        customer,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
