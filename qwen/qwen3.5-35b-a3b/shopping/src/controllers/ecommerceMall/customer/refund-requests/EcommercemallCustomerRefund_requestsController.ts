  /**
   * Create a new refund request for a delivered order item.
   *
   * This operation allows customers to request a refund for individual order items that have already been delivered. The system validates that the target order item has a 'delivered' status before creating the refund request, as per business rules only delivered items are eligible for refund requests.
   *
   * The refund request is associated with a specific order item and the customer who places the order. Upon creation, the system automatically generates a snapshot to preserve the initial state of the refund request for audit trail and dispute resolution purposes. The refund request enters a 'Pending' state and will be processed by the seller for approval or rejection.
   *
   * Additionally, the system validates that the refund request is submitted within 7 days of the item's delivery date. If the 7-day window has expired, the refund request creation will be rejected.
   *
   * @param connection
   * @param orderItemId The ID of the order item that the refund request is for. The order item must have a 'delivered' status to be eligible for refund.
   * @param body Required reason text explaining the refund request. The reason cannot be empty. Optional evidence description for additional context.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create a new refund request in the ecommerce_mall_refund_requests table.
   *
   * 1. Validate order item existence and retrieve it from ecommerce_mall_order_items table using the orderItemId path parameter.
   * 2. Verify the order item status equals 'delivered' - if not, return a 400 Bad Request error indicating the item is not eligible for refund.
   * 3. Validate the current customer making the request is the owner of the order containing this order item.
   * 4. Create a new refund request record with:
   *    - orderItemId: from path parameter
   *    - customerId: from authenticated session
   *    - status: 'submitted'
   *    - reason: from request body
   *    - createdAt: current timestamp
   * 5. Create an audit snapshot in ecommerce_mall_refund_request_snapshots table capturing the initial state of the refund request.
   * 6. Create a customer-specific snapshot in ecommerce_mall_refund_request_snapshot_of_customers table.
   * 7. Return the created refund request with full details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":orderItemId")
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallRefundRequest.ICreate,
  ): Promise<IEcommerceMallRefundRequest> {
    try {
      return await postEcommerceMallCustomerRefundRequestsOrderItemId({
        customer,
        orderItemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

