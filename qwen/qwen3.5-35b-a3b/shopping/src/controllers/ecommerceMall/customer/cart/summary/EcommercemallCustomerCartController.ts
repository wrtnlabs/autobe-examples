@Controller("/ecommerceMall/customer/cart/summary")
export class EcommercemallCustomerCartController {
  /**
   * Retrieve a paginated summary of cart items for the authenticated customer's shopping cart.
   *
   * This operation provides comprehensive cart information including all cart items with their product variants, calculated subtotals, item counts, and a breakdown of totals. The response includes variant details (SKU code, option values, price override, current stock availability), product information (name, base price, category), and seller information (shop name) to enable complete cart display and checkout preparation.
   *
   * The endpoint supports advanced filtering and sorting capabilities. Customers can filter by item status (available/unavailable based on current stock), sort by various fields (quantity, price, last modified, item count), and navigate through paginated results. This is essential for carts with many items where displaying all items at once would be impractical.
   *
   * Cart totals are calculated based on prices captured at the time items were added to the cart, not current product prices. This ensures customers see consistent pricing throughout their shopping session and checkout process, as specified in the cart total calculation business rules.
   *
   * The operation validates that the customer owns the cart session and returns an appropriate error if the cart does not exist or belongs to another customer. Items are automatically filtered to exclude unavailable variants (out of stock) when the filter is enabled.
   *
   * @param connection
   * @param body Pagination, filtering, and sorting parameters for cart summary retrieval.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Validate authenticated customer exists and is not banned
   * 2. Retrieve the customer's shopping cart session (ecommerce_mall_shopping_carts) filtered by customer_id
   * 3. If no cart exists or it's been soft-deleted, return empty cart summary with zero totals
   * 4. Query cart items (ecommerce_mall_cart_items) for the cart, joining with:
   *    - ProductVariant (ecommerce_mall_product_variants) for variant details, SKU, option values, stock quantity
   *    - Product (ecommerce_mall_products) for product name, base price, category information
   *    - Seller (ecommerce_mall_sellers) for seller profile shop name
   * 5. Apply filters:
   *    - Filter by status: exclude items where variant stock_quantity is 0 or variant is_active is false (if filterByStatus=true)
   *    - Exclude soft-deleted cart items (deleted_at IS NULL)
   * 6. Apply sorting:
   *    - Supported fields: quantity (DESC/ASC), price (DESC/ASC), updated_at (DESC/ASC), item_count (DESC/ASC)
   *    - Default sort: updated_at DESC (most recently modified items first)
   * 7. Calculate per-item subtotals: quantity × price (price captured at cart addition time)
   * 8. Calculate cart totals:
   *    - Total items count: SUM(quantity)
   *    - Cart total: SUM(quantity �� price)
   *    - Group subtotals by seller_id for breakdown display
   * 9. Apply pagination:
   *    - Return cursor-based or offset-based pagination based on request parameters
   *    - Include total items count and total pages for navigation metadata
   * 10. Build response:
   *     - data: array of ICartSummary.ISummary objects with all item details
   *     - pagination: IPageIEcommerceMallCartSummary pagination metadata
   *     - summary: ICartSummary.ISummary with totals and counts
   * 11. Error handling:
   *     - 404 if customer has no cart
   *     - 403 if customer cannot access cart (ownership validation failure)
   *     - 400 if filter or sort parameters are invalid
   *     - Return cart_id in response even when cart is empty for client reference
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async summary(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallShoppingCart.IRequest,
  ): Promise<IPageIEcommerceMallShoppingCart.ISummary> {
    try {
      return await patchEcommerceMallCustomerCartSummary({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
