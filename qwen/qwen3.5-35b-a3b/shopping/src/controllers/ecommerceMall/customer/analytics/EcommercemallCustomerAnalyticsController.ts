import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallAnalytic } from "../../../../api/structures/IEcommerceMallAnalytic";
import { IPageIEcommerceMallAnalytic } from "../../../../api/structures/IPageIEcommerceMallAnalytic";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchEcommerceMallCustomerAnalytics } from "../../../../providers/patchEcommerceMallCustomerAnalytics";

@Controller("/ecommerceMall/customer/analytics")
export class EcommercemallCustomerAnalyticsController {
  /**
   * Retrieve comprehensive ecommerce analytics and dashboard statistics for business intelligence and monitoring purposes.
   *
   * This operation provides a unified dashboard view combining key business metrics from orders, products, customers, sellers, and reviews. It supports flexible filtering by date range, seller, category, and product to enable targeted business analysis.
   *
   * The response includes aggregated statistics such as total orders, revenue, average order value, product performance metrics, customer activity indicators, and seller performance data. All metrics are derived from the ecommerce_mall_orders, ecommerce_mall_products, ecommerce_mall_customers, ecommerce_mall_sellers, and ecommerce_mall_reviews tables.
   *
   * Filtering options include date range selection for temporal analysis, seller-specific analytics for individual shop performance, category-level metrics for product category analysis, and product-specific views for item-level insights.
   *
   * The endpoint is designed for admin and super administrator access, providing business oversight capabilities as defined in the admin actor privileges and super administrator governance sections.
   *
   * @param connection
   * @param body Analytics search criteria and filtering parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query and aggregate data from multiple entities:
   *
   * 1. Fetch order statistics from ecommerce_mall_orders:
   *    - Count total orders by overall_status (paid, shipped, delivered, cancelled, refunded, partiallyCompleted)
   *    - Calculate total revenue (sum of total_price)
   *    - Compute average order value (total_price AVG)
   *    - Filter by date range (created_at)
   *
   * 2. Fetch product metrics from ecommerce_mall_products:
   *    - Count total active products
   *    - Count products by category (join with ecommerce_mall_categories)
   *    - Calculate average product price (base_price)
   *    - Filter by seller_id and category_id
   *
   * 3. Fetch customer metrics from ecommerce_mall_customers:
   *    - Count total active customers
   *    - Count customers by creation date (registration trends)
   *
   * 4. Fetch seller metrics from ecommerce_mall_sellers:
   *    - Count total sellers by approval_status (pending, approved, rejected)
   *    - Count active sellers (is_banned=false, is_suspended=false)
   *
   * 5. Fetch review metrics from ecommerce_mall_reviews:
   *    - Calculate average rating across all reviews
   *    - Count total active reviews per product
   *
   * 6. Apply requested filters:
   *    - Date range filter (start_date, end_date)
   *    - Seller filter (seller_id)
   *    - Category filter (category_id)
   *    - Product filter (product_id)
   *
   * 7. Sort results according to sort_field and sort_order parameters
   *
   * 8. Apply pagination:
   *    - Return current page number, page size, total count
   *    - Calculate total pages
   *
   * Implementation notes:
   * - Use efficient SQL aggregation queries with GROUP BY for metrics
   * - Join tables only when specific filters are requested
   * - Cache frequently accessed aggregate data with appropriate TTL
   * - Return null for metrics when no data matches filter criteria
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallAnalytic.IRequest,
  ): Promise<IPageIEcommerceMallAnalytic.ISummary> {
    try {
      return await patchEcommerceMallCustomerAnalytics({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
