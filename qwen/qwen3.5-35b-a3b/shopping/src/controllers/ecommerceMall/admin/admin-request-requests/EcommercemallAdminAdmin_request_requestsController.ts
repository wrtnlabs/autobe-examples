  /**
   * Retrieve a filtered and paginated list of administrator access requests from the platform.
   *
   * This operation provides advanced search and filtering capabilities for super administrators to view all administrator access requests (ecommerce_mall_admin_request_requests). Super administrators only - regular administrators cannot view this list. You can filter requests by status (pending, approved, rejected), requester type (customer or seller), creation date ranges, and search terms in the request reason field.
   *
   * The response includes paginated results with request metadata such as request ID, requester information (customer display name or seller shop name), status, reason text, submission timestamp, and resolution details for approved/rejected requests. Each request includes snapshot references in the response only for requests with status 'approved' or 'rejected' as per section 901, which require immutable snapshot tracking for audit trail compliance.
   *
   * Only users with super administrator privileges can access this endpoint. Regular administrators can only view the list without approval/rejection options as defined in section 33.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for admin request requests
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_admin_request_requests table with pagination and filtering.
   *
   * Apply search filters:
   * - status: Filter by request status (pending, approved, rejected)
   * - requester_type: Filter by requester entity type (customer or seller)
   * - date_range: Filter by creation date (created_at between start and end)
   * - reason_search: Text search in the reason field (partial match)
   * - status_change_date_range: Filter by status change timestamp
   * - request_of_customer_id: Filter by specific customer requester
   * - request_of_seller_id: Filter by specific seller requester
   *
   * Join with:
   * - ecommerce_mall_admin_request_request_of_customers for customer request details
   * - ecommerce_mall_admin_request_request_of_sellers for seller request details
   * - ecommerce_mall_customers for customer displayName and email
   * - ecommerce_mall_sellers for seller shopName
   *
   * Pagination: Apply cursor-based pagination with configurable page size (default 20, max 100).
   * Sorting: Support sorting by created_at (ascending/descending) as primary, status as secondary.
   *
   * Authorization: Verify requesting user has super administrator grade.
   * Return: Paginated list of admin request summaries with requester information.
   *
   * Edge cases:
   * - No matching results: Return empty data array with pagination metadata
   * - Invalid date range: Reject with validation error
   * - Missing required pagination parameters: Use defaults
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
