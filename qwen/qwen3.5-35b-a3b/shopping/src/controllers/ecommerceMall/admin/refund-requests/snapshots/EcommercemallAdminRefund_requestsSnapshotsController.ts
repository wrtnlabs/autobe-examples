  /**
   * Retrieve a specific refund request snapshot from the immutable audit trail.
   *
   * This operation returns a single snapshot record that captures the state of a refund request at a specific point in time, typically when a seller responded with approval or rejection. Each snapshot is an immutable record that cannot be modified or deleted once created.
   *
   * The snapshot contains comprehensive before/after value comparisons showing:
   * - Status transitions (pending → approved/rejected)
   * - Reason changes made by customers
   * - Seller response text and rejection reasons
   * - Timestamp of the change for chronological dispute resolution
   * - Actor accountability (which customer, seller, or admin made the change)
   *
   * Authorized actors who can view refund request snapshots include:
   * - The customer who initiated the refund request
   * - The seller who responded to the refund request
   * - Platform administrators (admin and superAdmin actors) for dispute resolution
   *
   * Snapshots are critical for post-delivery dispute resolution, providing an authoritative audit trail of the entire refund request lifecycle from submission through resolution.
   *
   * @param connection
   * @param refundRequestId The unique identifier of the parent refund request
   * @param snapshotId The unique identifier of the snapshot to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Retrieve a single refund request snapshot by ID from the ecommerce_mall_refund_request_snapshots table.
   *
   * 1. Query the database for the snapshot matching the provided snapshotId
   * 2. Verify ownership/authorization:
   *    - Customer actor: verify the snapshot's parent refund request belongs to them (ecommerce_mall_refund_requests.ecommerce_mall_customer_id = actor.id)
   *    - Seller actor: verify the snapshot's parent refund request's order item belongs to a product owned by this seller
   *    - Admin/SuperAdmin actors: always authorized
   * 3. Return the full snapshot record including all before/after values
   * 4. Throw 404 Not Found if snapshotId does not exist
   * 5. Throw 403 Forbidden if the actor does not have access to this snapshot
   * 6. Return the snapshot with all fields populated from the database schema, including:
   *    - id, refund_request_id, actor_type, action_type
   *    - status_before, status_after
   *    - reason_before, reason_after
   *    - response_before, response_after
   *    - metadata_before, metadata_after
   *    - created_at, deleted_at
   *
   * The endpoint provides read-only access to immutable audit records. No modifications are allowed. Snapshots are append-only records created automatically when sellers respond to refund requests.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallRefundRequestSnapshot> {
    try {
      return await getEcommerceMallAdminRefundRequestsRefundRequestIdSnapshotsSnapshotId(
        {
          admin,
          refundRequestId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
