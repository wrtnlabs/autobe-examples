import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipmentItem } from "../../../../../api/structures/IEcommerceMallShipmentItem";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminShipmentItemsShipmentIdItems } from "../../../../../providers/getEcommerceMallAdminShipmentItemsShipmentIdItems";

@Controller("/ecommerceMall/admin/shipmentItems/:shipmentId/items")
export class EcommercemallAdminShipmentitemsItemsController {
  /**
   * Retrieve all shipment items associated with a specific shipment.
   *
   * This operation returns a list of all order items that are being shipped together in the specified shipment. Each shipment item record represents the association between a shipment and an order item for delivery tracking purposes.
   *
   * The response includes shipment item details along with referenced order item information such as product snapshot, variant snapshot, seller profile snapshot, quantity, unit price, and current item status.
   *
   * Sellers can use this operation to view which order items are included in a specific shipment and track the status of items during the shipping process. Customers can view shipment items to understand what items are included in each shipment of their order.
   *
   * The operation returns all non-deleted shipment items associated with the specified shipment ID, ordered by their creation timestamp.
   *
   * @param connection
   * @param shipmentId ID of the shipment to retrieve items for
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_shipment_items table for all records where shipment_id matches the provided shipmentId path parameter and deleted_at is NULL.
   *
   * Join with ecommerce_mall_order_items to include order item details such as itemStatus, quantity, unitPrice, productSnapshot, variantSnapshot, sellerProfileSnapshot, and references to product and variant.
   *
   * Return the shipment item records with their associated order item information, sorted by created_at ascending to show items in creation order.
   *
   * Validate that the shipmentId is a valid UUID format. If no shipment items are found, return an empty array.
   *
   * This operation does not require authorization middleware as shipment item viewing is part of the shipment detail retrieval workflow and is accessible to both sellers (for their own shipments) and customers (for their order shipments).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async getItems(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShipmentItem.ISummary> {
    try {
      return await getEcommerceMallAdminShipmentItemsShipmentIdItems({
        admin,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
