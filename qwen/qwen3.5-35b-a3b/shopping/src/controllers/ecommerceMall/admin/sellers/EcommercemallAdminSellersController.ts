import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSeller } from "../../../../api/structures/IEcommerceMallSeller";
import { IPageIEcommerceMallSeller } from "../../../../api/structures/IPageIEcommerceMallSeller";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminSellersSellerId } from "../../../../providers/getEcommerceMallAdminSellersSellerId";
import { patchEcommerceMallAdminSellers } from "../../../../providers/patchEcommerceMallAdminSellers";

@Controller("/ecommerceMall/admin/sellers")
export class EcommercemallAdminSellersController {
  /**
   * Retrieve a filtered and paginated list of seller accounts registered on the ecommerce platform.
   *
   * This operation provides administrators with the ability to browse all seller accounts, view their approval status (pending, approved, or rejected), and search by email address or registration date range. Sellers are identified by their unique UUID and email address.
   *
   * The response includes seller summary information such as account creation date, current approval status, and whether they have been soft-deleted. Sensitive authentication data (password_hash) is never returned in list responses.
   *
   * Administrators can filter results by approval status to identify pending approvals, approved sellers, or rejected accounts. The operation supports cursor-based pagination for efficient handling of large seller databases.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for seller list
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_sellers table with pagination and filtering.
   *
   * Apply search filters from request body:
   * - status: filter by approval status (pending, approved, rejected)
   * - email: partial email address matching (case-insensitive)
   * - createdAfter: filter sellers registered after this date
   * - createdBefore: filter sellers registered before this date
   * - sortBy: field to sort by (email, createdAt, status)
   * - sortOrder: asc or desc
   * - page: cursor-based pagination page identifier
   * - pageSize: number of results per page (default 20, max 100)
   *
   * Exclude password_hash and deleted_at from response for security and clarity.
   *
   * Return cursor-based pagination with nextCursor for subsequent page requests.
   * Join with ecommerce_mall_seller_approval_requests if approval details are needed (approvalRequestCount, lastApprovalDate).
   *
   * Security: Only admin and superAdmin actors can access. Sellers cannot view the full list.
   *
   * Error handling:
   * - Return 403 if seller actor attempts to access
   * - Return 400 for invalid filter parameters
   * - Return 404 if cursor is invalid or page not found
   *
   * Performance: Use database indexes on email, created_at, and status for efficient querying. Add index on status and created_at for status date range queries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallSeller.IRequest,
  ): Promise<IPageIEcommerceMallSeller.ISummary> {
    try {
      return await patchEcommerceMallAdminSellers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific seller account from the ecommerce_mall platform.
   *
   * This operation returns complete seller account details including the seller's email address, account creation timestamp, last update timestamp, and soft-delete status. The seller's approval status can be determined by checking for associated seller approval request records.
   *
   * **Security and Authorization:**
   *
   * Only authenticated sellers, administrators (admin or superAdmin actors), or authorized system services can access seller account information. Sellers can only retrieve their own account details. Administrators and superAdmins can retrieve any seller's information for platform management purposes.
   *
   * **Related Operations:**
   *
   * - `GET /sellers` (if implemented) would list all sellers
   * - `GET /sellers/{sellerId}/products` retrieves products owned by this seller
   * - `GET /sellers/{sellerId}/approval-request` retrieves approval request details
   * - `GET /sellers/{sellerId}/shipments` retrieves shipments managed by this seller
   *
   * @param connection
   * @param sellerId The unique identifier of the seller account to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_sellers table for a record matching the sellerId UUID.
   *
   * 1. Validate sellerId is a valid UUID format
   * 2. Execute SELECT query: SELECT * FROM ecommerce_mall_sellers WHERE id = $sellerId AND deleted_at IS NULL
   * 3. If soft-deleted records should be retrieved, remove the deleted_at IS NULL filter
   * 4. Return the seller record with all fields: id, email, created_at, updated_at, deleted_at
   * 5. Return 404 Not Found if no seller record exists with the given ID
   * 6. Access control middleware should verify: actor type is seller AND actor_id matches sellerId, OR actor type is admin/superAdmin
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSeller> {
    try {
      return await getEcommerceMallAdminSellersSellerId({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
