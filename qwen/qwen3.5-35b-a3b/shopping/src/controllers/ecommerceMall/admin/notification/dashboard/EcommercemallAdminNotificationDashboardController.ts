import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallNotificationDashboard } from "../../../../../api/structures/IEcommerceMallNotificationDashboard";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminNotificationDashboard } from "../../../../../providers/getEcommerceMallAdminNotificationDashboard";

@Controller("/ecommerceMall/admin/notification/dashboard")
export class EcommercemallAdminNotificationDashboardController {
  /**
   * Retrieve notification dashboard information for the authenticated actor.
   *
   * This operation provides a comprehensive overview of notification status including unread count, recent notifications list, and system-wide alert status. The dashboard aggregates notification data from the ecommerce_mall_notifications table along with notification recipient tracking from ecommerce_mall_notification_recipients.
   *
   * The response includes summary statistics such as total unread notifications, notification categories breakdown, and the 10 most recent notifications with their read status. Actors can quickly assess their notification state without querying individual notification records.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_notifications table filtered by the authenticated actor's notification reference table (ecommerce_mall_notification_of_customers, ecommerce_mall_notification_of_sellers, or ecommerce_mall_notification_of_admins).
   *
   * Join with ecommerce_mall_notification_recipients to track read/unread status.
   *
   * Calculate summary statistics: count of unread notifications, count by notification type/category, and retrieve the 10 most recent notifications ordered by createdAt descending.
   *
   * Actor identification comes from the authentication context - customer, seller, admin, or super-admin sessions are identified via their respective session tables (ecommerce_mall_customer_sessions, ecommerce_mall_seller_sessions, ecommerce_mall_admin_sessions, ecommerce_mall_super_admin_sessions).
   *
   * Only return notification data relevant to the authenticated actor's role and permissions. Admin actors may receive platform-wide notifications while customer and seller actors receive role-specific notifications.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IEcommerceMallNotificationDashboard> {
    try {
      return await getEcommerceMallAdminNotificationDashboard({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
