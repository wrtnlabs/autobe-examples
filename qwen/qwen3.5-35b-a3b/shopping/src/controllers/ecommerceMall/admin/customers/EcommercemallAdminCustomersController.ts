import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCustomer } from "../../../../api/structures/IEcommerceMallCustomer";
import { IPageIEcommerceMallCustomer } from "../../../../api/structures/IPageIEcommerceMallCustomer";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminCustomersCustomerId } from "../../../../providers/getEcommerceMallAdminCustomersCustomerId";
import { patchEcommerceMallAdminCustomers } from "../../../../providers/patchEcommerceMallAdminCustomers";

@Controller("/ecommerceMall/admin/customers")
export class EcommercemallAdminCustomersController {
  /**
   * Retrieve a filtered and paginated list of customer accounts from the ecommerce mall platform.
   *
   * This operation provides advanced search capabilities for administrators to find customer accounts based on various criteria including email address, account status, and registration date range. The response includes paginated results with summary information optimized for list displays.
   *
   * Supports comprehensive pagination with configurable page size and sorting options. Administrators can filter by status (active, suspended, deleted) and search for customers by partial email matching.
   *
   * This endpoint is designed for administrative use to manage customer accounts, investigate issues, and maintain platform oversight.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for customer account list
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_customers table with pagination and filtering.
   *
   * Apply search filters:
   * - Email: Support partial matching (LIKE operator with wildcard)
   * - Status: Filter by exact match (active, suspended, deleted)
   * - Created date range: Filter customers registered within a date range
   * - Deleted status: Include or exclude soft-deleted customers
   *
   * Apply sorting:
   * - Sort by created_at (ascending or descending)
   * - Default sort is by created_at descending
   *
   * Apply pagination:
   * - Cursor-based pagination for large result sets
   * - Support configurable page size (default: 20, max: 100)
   * - Return next cursor for pagination navigation
   *
   * Join operations:
   * - No joins required for summary data
   * - Customer summary includes: id, email, status, created_at
   *
   * Business rules:
   * - Only administrators can access this endpoint
   * - Soft-deleted customers (deleted_at IS NOT NULL) can be excluded from results by default
   * - Suspended customers are included in results but marked as suspended
   * - Password hash is never returned in response (security)
   *
   * Error handling:
   * - Return 403 if caller is not an administrator
   * - Return 400 for invalid pagination parameters
   * - Return 400 for invalid filter values
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallCustomer.IRequest,
  ): Promise<IPageIEcommerceMallCustomer.ISummary> {
    try {
      return await patchEcommerceMallAdminCustomers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific customer account.
   *
   * This operation returns the complete customer profile including the customer's registered email address, display information from their profile, account status, and timestamp information.
   *
   * The requesting actor must be authenticated. Customer accounts can only view their own account details. Administrators and super administrators can view any customer account for oversight and support purposes.
   *
   * The customer record includes the primary authentication email, the customer's display name and phone number from their profile, the timestamp when the account was created, and the current account status. Sensitive authentication fields including password hashes are never exposed through this API.
   *
   * @param connection
   * @param customerId The unique identifier of the customer account to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_customers table by customer ID.
   *
   * 1. Validate that customerId is a valid UUID.
   * 2. Verify requesting actor is authenticated.
   * 3. Check authorization:
   *    - If requesting actor is the customer themselves (customerId matches authenticated user ID), allow access.
   *    - If requesting actor is admin or superAdmin, allow access to any customer.
   *    - Otherwise, return 403 Forbidden.
   * 4. Query ecommerce_mall_customers for the record matching customerId.
   * 5. Include full customer record: id, email, createdAt, updatedAt, status, and related customerProfile.
   * 6. Return 200 OK with customer data, or 404 if customer not found.
   *
   * Database query: SELECT * FROM ecommerce_mall_customers WHERE id = :customerId
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCustomer> {
    try {
      return await getEcommerceMallAdminCustomersCustomerId({
        admin,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
