import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCategorySnapshot } from "../../../../api/structures/IEcommerceMallCategorySnapshot";
import { IPageIEcommerceMallCategorySnapshot } from "../../../../api/structures/IPageIEcommerceMallCategorySnapshot";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminCategorySnapshotsSnapshotId } from "../../../../providers/getEcommerceMallAdminCategorySnapshotsSnapshotId";
import { patchEcommerceMallAdminCategorySnapshots } from "../../../../providers/patchEcommerceMallAdminCategorySnapshots";

@Controller("/ecommerceMall/admin/categorySnapshots")
export class EcommercemallAdminCategorysnapshotsController {
  /**
   * Retrieve a paginated list of category snapshot records for audit and dispute resolution purposes.
   *
   * This operation provides administrators with access to historical category states, capturing all field values at the moment of each category edit. Snapshots are created automatically whenever a category is modified, preserving the category name, description, leaf status, parent relationship, and timestamps.
   *
   * The endpoint supports filtering by original category ID to view the complete change history of a specific category. Results are sortable by snapshot creation timestamp in ascending or descending order. Pagination is implemented using cursor-based approach to handle large audit history efficiently.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for category snapshot queries
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_category_snapshots table with pagination and filtering.
   *
   * Apply filters:
   * - Filter by ecommerceMallCategoryId to retrieve all snapshots for a specific category
   * - Filter by date range on snapshotCreatedAt if provided
   *
   * Sort results by:
   * - snapshotCreatedAt field (default: descending)
   * - id field (alternative sort option)
   *
   * Return cursor-based pagination:
   * - Use snapshotCreatedAt and id for cursor-based navigation
   * - Default page size of 20 items
   * - Maximum page size of 100 items
   *
   * Join with ecommerceMallCategories table to include category name in summary response.
   *
   * Access control: Only authorized administrators can access this endpoint.
   *
   * Return IPageIEcommerceMallCategorySnapshot.ISummary with pagination metadata and snapshot summary data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallCategorySnapshot.IRequest,
  ): Promise<IPageIEcommerceMallCategorySnapshot.ISummary> {
    try {
      return await patchEcommerceMallAdminCategorySnapshots({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific category snapshot by its unique identifier.
   *
   * This endpoint returns an immutable audit snapshot of a category that was captured at a specific point in time during the category's edit history. Snapshots preserve the complete state of the category (including name, description, hierarchy, and leaf status) at the moment of each edit, providing an audit trail for dispute resolution and compliance tracking.
   *
   * Super administrators have full access to view snapshots of all categories across the platform. Each snapshot represents a point-in-time view of the category, including the original creation timestamp and last update timestamp recorded in the snapshot.
   *
   * Category snapshots are immutable and cannot be modified or deleted under any circumstances, ensuring the integrity of the audit trail and historical accuracy of category changes.
   *
   * @param connection
   * @param snapshotId Unique identifier of the category snapshot to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate that snapshotId is a valid UUID format
   * 2. Query ecommerce_mall_category_snapshots table where id = snapshotId
   * 3. Load associated category metadata via ecommerce_mall_category_id relationship
   * 4. Verify requester has admin role authorization
   * 5. Return full snapshot record with all fields:
   *    - id: snapshot unique identifier (UUID)
   *    - ecommerce_mall_category_id: reference to original category
   *    - snapshot_created_at: timestamp when this snapshot was created
   *    - name: category name at snapshot time
   *    - description: category description at snapshot time (nullable)
   *    - is_leaf: boolean indicating leaf node status at snapshot time
   *    - created_at: original category creation timestamp
   *    - updated_at: original category last update timestamp
   *    - parent_category_id: parent category reference at snapshot time (nullable)
   * 6. Handle 404 Not Found if snapshot does not exist
   * 7. Handle 403 Forbidden if requester lacks admin authorization
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCategorySnapshot> {
    try {
      return await getEcommerceMallAdminCategorySnapshotsSnapshotId({
        admin,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
