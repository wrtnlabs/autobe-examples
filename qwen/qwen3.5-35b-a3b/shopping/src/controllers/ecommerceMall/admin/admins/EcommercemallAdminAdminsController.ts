import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallAdmin } from "../../../../api/structures/IEcommerceMallAdmin";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminAdminsAdminId } from "../../../../providers/getEcommerceMallAdminAdminsAdminId";

@Controller("/ecommerceMall/admin/admins/:adminId")
export class EcommercemallAdminAdminsController {
  /**
   * Retrieve a single administrator account by UUID identifier.
   *
   * This operation provides detailed information about a platform administrator account, including their email address, account status, and creation/update timestamps. Administrators have elevated privileges for managing sellers, categories, products, orders, and user accounts across the entire platform.
   *
   * The response includes the administrator's unique identifier, email address, current status (active, suspended, or banned), and audit timestamps. For security purposes, the password hash is never returned in API responses.
   *
   * @param connection
   * @param adminId Target administrator's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_admins table by UUID id. Return the administrator record including id, email, status, created_at, updated_at, and deleted_at fields. Do NOT include the password_hash field in the response for security reasons. Handle 404 Not Found if the administrator id does not exist. The requesting user must be a super administrator with full platform oversight privileges to access this operation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallAdmin> {
    try {
      return await getEcommerceMallAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
