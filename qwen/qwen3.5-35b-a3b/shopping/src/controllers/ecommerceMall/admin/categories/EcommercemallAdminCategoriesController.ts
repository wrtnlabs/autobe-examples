import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCategory } from "../../../../api/structures/IEcommerceMallCategory";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putEcommerceMallAdminCategoriesCategoryId } from "../../../../providers/putEcommerceMallAdminCategoriesCategoryId";

@Controller("/ecommerceMall/admin/categories/:categoryId")
export class EcommercemallAdminCategoriesController {
  /**
   * Update an existing category's name and/or description.
   *
   * This operation allows administrators to modify the name and/or description of an existing category in the product catalog. When a category is updated, the system automatically creates a snapshot to preserve the previous state for audit trail and historical reference.
   *
   * Administrators specify the category identifier and provide the new name and/or description values in the request body. The updated category information becomes immediately visible to customers browsing the category list and product catalog.
   *
   * The category hierarchy remains unchanged during an update operation. Only the category's name and description fields are modifiable. Parent-child relationships cannot be altered through this endpoint.
   *
   * Related Operations:
   * - GET /categories/{categoryId} must be called to retrieve the current category details before editing
   * - PATCH /categories can be used to browse and search all categories
   * - GET /categories/{categoryId}/snapshots retrieves historical snapshots of this category
   *
   * @param connection
   * @param categoryId The unique identifier of the category to update
   * @param body Category update data containing the new name and/or description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Retrieve the category record by categoryId from ecommerce_mall_categories table.
   * Validate that the requesting user has administrator privileges.
   * Update the name and/or description fields based on the request body.
   * Do not update other fields (parentCategoryId, createdAt, updatedAt).
   * Create an ecommerce_mall_category_snapshot record with the previous state of the category.
   * Return the updated category record.
   * Handle validation errors: category not found, invalid name format, insufficient permissions.
   * Apply uniqueness constraint on category name within the same parent level.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallCategory.IUpdate,
  ): Promise<IEcommerceMallCategory> {
    try {
      return await putEcommerceMallAdminCategoriesCategoryId({
        admin,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
