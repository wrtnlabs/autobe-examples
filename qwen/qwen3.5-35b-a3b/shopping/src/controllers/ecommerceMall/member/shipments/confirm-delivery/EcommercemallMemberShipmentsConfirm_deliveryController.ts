import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipment } from "../../../../../api/structures/IEcommerceMallShipment";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchEcommerceMallMemberShipmentsShipmentIdConfirmDelivery } from "../../../../../providers/patchEcommerceMallMemberShipmentsShipmentIdConfirmDelivery";

@Controller("/ecommerceMall/member/shipments/:shipmentId/confirm-delivery")
export class EcommercemallMemberShipmentsConfirm_deliveryController {
  /**
   * Confirm delivery of a shipment received by the customer.
   *
   * This operation allows customers to confirm they have received their shipment, which marks the shipment and all contained order items as delivered. Customers can only confirm delivery for shipments belonging to orders they own. Once a shipment is confirmed as delivered, this action cannot be reversed.
   *
   * The shipment status changes to 'delivered' and the delivered_at timestamp is set to the current time. All order items included in this shipment are also marked as delivered.
   *
   * ### Business Rules
   *
   * - Customer must own the order containing this shipment
   * - Shipment must be in 'shipped' status (already sent, not yet delivered)
   * - Delivery confirmation can only be performed once per shipment
   * - Once confirmed, delivery status cannot be reverted
   * - Customer cannot confirm delivery for shipments they have not received
   * - Delivery confirmation is independent for each shipment, even if multiple shipments belong to the same order
   *
   * @param connection
   * @param shipmentId The unique identifier of the shipment to confirm delivery for.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Verify customer owns the order containing this shipment.
   *
   * Validate shipment exists and is in 'shipped' status.
   *
   * Ensure shipment has not already been confirmed as delivered.
   *
   * Update shipment status to 'delivered' and set delivered_at to current timestamp.
   *
   * Update all ecommerce_mall_shipment_items records for this shipment to set status to 'delivered'.
   *
   * Return the updated shipment record.
   *
   * ### Error Handling
   *
   * - 404 Not Found: Shipment does not exist or has been soft-deleted
   * - 403 Forbidden: Customer does not own the order containing this shipment
   * - 409 Conflict: Shipment is already confirmed as delivered
   * - 400 Bad Request: Shipment is not in 'shipped' status (e.g., already delivered, cancelled)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async confirmDelivery(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShipment> {
    try {
      return await patchEcommerceMallMemberShipmentsShipmentIdConfirmDelivery({
        member,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
