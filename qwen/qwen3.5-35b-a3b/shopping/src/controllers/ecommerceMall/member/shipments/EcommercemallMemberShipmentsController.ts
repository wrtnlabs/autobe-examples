import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipment } from "../../../../api/structures/IEcommerceMallShipment";
import { IPageIEcommerceMallShipment } from "../../../../api/structures/IPageIEcommerceMallShipment";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getEcommerceMallMemberShipmentsShipmentId } from "../../../../providers/getEcommerceMallMemberShipmentsShipmentId";
import { patchEcommerceMallMemberShipments } from "../../../../providers/patchEcommerceMallMemberShipments";

@Controller("/ecommerceMall/member/shipments")
export class EcommercemallMemberShipmentsController {
  /**
   * List shipments for the authenticated seller with pagination and search filters.
   *
   * Returns a paginated list of shipments belonging to the seller, filtered by optional criteria including order ID, status, and date range. Results are sorted by creation date (newest first) by default. Each shipment includes tracking information and status, with embedded order item summaries.
   *
   * This endpoint supports seller-specific filtering (must own the shipments) and is used for seller dashboard and shipment history views. Pagination uses cursor-based approach for efficient large dataset handling.
   *
   * @param connection
   * @param body Search criteria for filtering and paginating shipments. Includes optional filters for order ID, status, date ranges (ship date, delivery date, creation date), sorting options, and pagination parameters (limit, cursor).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Verify seller is authenticated via JWT token
     *   from Authorization header 2. Query ecommerce_mall_shipments table
     *   filtered by seller_id = authenticated seller's ID 3. Apply optional
     *   filters: - order_id: exact match filter - status: filter by 'shipped'
     *   or 'delivered' - shipped_at_after / shipped_at_before: date range
     *   filter - delivered_at_after / delivered_at_before: date range filter 4.
     *   Apply sorting (default: created_at DESC): supports created_at,
     *   shipped_at, delivered_at, status 5. Implement cursor-based pagination:
     *   if cursor provided, use created_at < cursor as offset 6. Apply limit
     *   (max 100 items per page) 7. Return paginated results with cursor-based
     *   pagination metadata 8. Embed shipmentItems summaries for each shipment
     *   (order item details) 9. Calculate and return total count for pagination
     *   UI
   *
   * Business Rules:
   * - Sellers can only see their own shipments (seller_id match)
   * - Soft deleted shipments (deleted_at IS NOT NULL) are excluded
   * - Shipment items are joined and their status included in response
   * - Cursor-based pagination uses created_at timestamp for consistent ordering
   *
   * Error Handling:
   * - 401 Unauthorized: seller not authenticated
   * - 400 Bad Request: invalid cursor format, limit exceeds maximum, invalid sort field
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEcommerceMallShipment.IRequest,
  ): Promise<IPageIEcommerceMallShipment.ISummary> {
    try {
      return await patchEcommerceMallMemberShipments({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single shipment by its unique identifier, returning complete shipment details including tracking information, status, and all contained order items.
   *
   * This operation allows customers to view shipment tracking for their orders and enables sellers to monitor shipments they have created. Authorization checks ensure customers can only view shipments for their orders, while sellers can view shipments for items they own.
   *
   * Returns 404 if the shipment does not exist, has been soft-deleted, or the authenticated user lacks permission to view it.
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment to retrieve. Must be a valid UUID that exists in the database and has not been soft-deleted.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the ecommerce_mall_shipments table for a
     *   single record matching the shipmentId path parameter.
   *
   * 1. Find shipment by id where deleted_at is NULL (soft-delete check)
   * 2. Verify shipment status and timestamps (shipped_at, delivered_at)
   * 3. Join with ecommerce_mall_shipment_items to include all items in this shipment
   * 4. Filter items by shipment status if needed (pending, shipped, delivered, cancelled)
   * 5. Authorization:
   *    - Customer: verify order_id matches order_id of authenticated customer's order
   *    - Seller: verify seller_id matches authenticated seller's ID
   *    - Administrator/SuperAdministrator: no restriction
   * 6. Return 404 if shipment not found, deleted, or unauthorized access
   * 7. Include full shipment entity: id, seller_id, order_id, carrier, tracking_number, status, shipped_at, delivered_at, created_at, updated_at
   * 8. Include shipment_items array with: id, order_item_id, quantity_shipped, status, created_at, updated_at
   * 9. Sort shipment_items by created_at ascending for chronological display
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShipment> {
    try {
      return await getEcommerceMallMemberShipmentsShipmentId({
        member,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
