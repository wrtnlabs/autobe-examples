import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallWishlistItem } from "../../../../../api/structures/IEcommerceMallWishlistItem";
import { IPageIEcommerceMallWishlistItem } from "../../../../../api/structures/IPageIEcommerceMallWishlistItem";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getEcommerceMallMemberWishlistsWishlistIdItemsItemId } from "../../../../../providers/getEcommerceMallMemberWishlistsWishlistIdItemsItemId";
import { patchEcommerceMallMemberWishlistsWishlistIdItems } from "../../../../../providers/patchEcommerceMallMemberWishlistsWishlistIdItems";

@Controller("/ecommerceMall/member/wishlists/:wishlistId/items")
export class EcommercemallMemberWishlistsItemsController {
  /**
   * Retrieve paginated list of products in a customer's wishlist with filtering and sorting options.
   *
   * Returns wishlist items with product details (name, main image, available variants) for display in the wishlist view. Items are grouped by wishlist and can be filtered by product name or availability status.
   *
   * The endpoint supports cursor-based pagination for efficient browsing of large wishlists. Each page displays the same format with product image, name, price range, and stock status.
   *
   * @param connection
   * @param wishlistId The unique identifier of the wishlist (UUID format).
   * @param body Search criteria including pagination parameters (page number, page size), sorting options (by creation date or product name), and filter criteria (product name search, availability status).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query ecommerce_mall_wishlist_items table scoped
     *   to the specified wishlistId from path parameter.
   *
   * Filter conditions:
   * - WHERE ecommerce_mall_wishlist_id = {wishlistId}
   * - WHERE deleted_at IS NULL (exclude soft-deleted items)
   * - Optional: WHERE product name LIKE search term if name_filter provided
   * - Optional: WHERE product availability status if status_filter provided
   *
   * Join with ecommerce_mall_products to fetch product details (name, main image, price range, availability).
   *
   * Sort by created_at (descending) by default, or by name if sort_by=name specified.
   *
   * Apply pagination: page number and page size from request body, default page_size=20.
   *
   * Return IPageIEcommerceMallWishlistItem.ISummary for each item with:
   * - item id, created_at
   * - product id, name, main image URL
   * - price range from variants
   * - availability status
   *
   * Edge cases:
   * - If wishlist does not exist: return 404 Not Found
   * - If user does not own wishlist: return 403 Forbidden (authentication required)
   * - If wishlist has no items: return empty paginated result with 0 items
   * - If product was deleted: the item should already be soft-deleted and excluded from results
   * - If product variant stock is zero: show as unavailable but keep item in wishlist (per requirements)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallWishlistItem.IRequest,
  ): Promise<IPageIEcommerceMallWishlistItem.ISummary> {
    try {
      return await patchEcommerceMallMemberWishlistsWishlistIdItems({
        member,
        wishlistId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single wishlist item from a customer's wishlist.
   *
   * Returns the complete wishlist item record including the referenced product details (name, main image, price), wishlist metadata (name, creation date), and the customer relationship. This operation is scoped to the authenticated customer who owns the wishlist.
   *
   * The response includes the wishlist item's unique identifier, timestamps for creation and last update, and a reference to the wishlisted product with its current catalog information. Soft-deleted items or wishlists are excluded from results.
   *
   * **Authorization**: Only the customer who owns the referenced wishlist can retrieve items from it. Unauthorized access attempts return a 404 error to prevent information leakage.
   *
   * **Error handling**:
   * - 404 Not Found: Item does not exist, wishlist does not exist, or customer does not own the wishlist
   * - 401 Unauthorized: Customer is not authenticated
   *
   * @param connection
   * @param wishlistId The unique identifier of the wishlist containing this item.
   * @param itemId The unique identifier of the wishlist item to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query ecommerce_mall_wishlist_items table by
     *   wishlistId and itemId path parameters.
   *
   * 1. Fetch the wishlist item record where id = itemId AND ecommerce_mall_wishlist_id = wishlistId
   * 2. Join with ecommerce_mall_wishlists to fetch wishlist data (customer reference)
   * 3. Join with ecommerce_mall_products to fetch product data (name, price, images)
   * 4. Validate the authenticated customer owns this wishlist (customer_id match)
   * 5. Return the complete wishlist item with wishlist and product details
   * 6. Return 404 if item not found or customer does not own the wishlist
   *
   * Business rules:
   * - Only the wishlist owner (authenticated customer) can retrieve their wishlist items
   * - The wishlist must be active (deleted_at is NULL)
   * - The item must be active (deleted_at is NULL)
   *
   * Edge cases:
   * - Return 404 if wishlistId does not exist
   * - Return 404 if itemId does not exist in the specified wishlist
   * - Return 404 if the authenticated customer does not own the wishlist
   * - Return 404 if wishlist or item is soft-deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallWishlistItem> {
    try {
      return await getEcommerceMallMemberWishlistsWishlistIdItemsItemId({
        member,
        wishlistId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
