import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallWishlist } from "../../../../api/structures/IEcommerceMallWishlist";
import { IPageIEcommerceMallWishlist } from "../../../../api/structures/IPageIEcommerceMallWishlist";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteEcommerceMallMemberWishlistsWishlistId } from "../../../../providers/deleteEcommerceMallMemberWishlistsWishlistId";
import { getEcommerceMallMemberWishlistsWishlistId } from "../../../../providers/getEcommerceMallMemberWishlistsWishlistId";
import { patchEcommerceMallMemberWishlists } from "../../../../providers/patchEcommerceMallMemberWishlists";
import { postEcommerceMallMemberWishlists } from "../../../../providers/postEcommerceMallMemberWishlists";
import { putEcommerceMallMemberWishlistsWishlistId } from "../../../../providers/putEcommerceMallMemberWishlistsWishlistId";

@Controller("/ecommerceMall/member/wishlists")
export class EcommercemallMemberWishlistsController {
  /**
   * Create a new wishlist for the authenticated member customer.
   *
   * Creates a personal wishlist with the specified name and optional description. The wishlist is associated with the authenticated customer and can store multiple products for later purchase consideration. Optionally, products can be added to the wishlist during creation using the initial_product_ids array.
   *
   * Only registered members can create wishlists. The system validates that all specified products exist and are currently active before creating the wishlist. Products that have been deleted or deactivated are rejected.
   *
   * @param connection
   * @param body Wishlist creation data including name, optional description, and optional initial product list.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Authenticate the request and extract customer_id from the session token
   * 2. Validate request body:
   *    - name: required, 1-100 characters
   *    - description: optional, max 500 characters
   *    - initial_product_ids: optional array of UUIDs, max 100 items
   * 3. For each initial_product_id, verify the product exists and is not deleted (deleted_at IS NULL)
   * 4. Insert new record into ecommerce_mall_wishlists:
   *    - customer_id: from authentication context
   *    - name: from request
   *    - description: from request (nullable)
   *    - created_at: CURRENT_TIMESTAMP
   *    - updated_at: CURRENT_TIMESTAMP
   * 5. For each validated product, insert a record into ecommerce_mall_wishlist_items:
   *    - ecommerce_mall_wishlist_id: new wishlist id
   *    - ecommerce_mall_product_id: product id
   *    - created_at: CURRENT_TIMESTAMP
   *    - updated_at: CURRENT_TIMESTAMP
   * 6. Return the created wishlist with associated items
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEcommerceMallWishlist.ICreate,
  ): Promise<IEcommerceMallWishlist> {
    try {
      return await postEcommerceMallMemberWishlists({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * List all wishlist items for a customer with pagination, filtering, and sorting capabilities.
   *
   * Returns a paginated list of wishlists owned by the authenticated customer. Each wishlist item includes product details (name, images, availability status) and indicates whether the wishlist is active or soft-deleted.
   *
   * The search supports filtering by status (active/soft-deleted), sorting by creation date (ascending/descending), and pagination with cursor-based navigation for large result sets.
   *
   * @param connection
   * @param body Search criteria for wishlist filtering including customer isolation, status filters, date ranges, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query ecommerce_mall_wishlists table with JOIN to ecommerce_mall_products for product details.
   *
   * Filter criteria:
   * - customer_id: REQUIRED - filter by authenticated customer's ID (enforce data isolation)
   * - status: optional - 'active' or 'deleted' to filter by deleted_at null/non-null
   * - created_after: optional - filter wishlists created after timestamp
   * - created_before: optional - filter wishlists created before timestamp
   * - product_id: optional - filter wishlists containing specific product (requires JOIN)
   * - sort: optional - 'created_at_asc' or 'created_at_desc' (default: created_at_desc)
   *
   * Implementation:
   * 1. Extract customer_id from JWT token in request headers
   * 2. Build query with WHERE clause: customer_id = {extracted_id}
   * 3. Apply optional filters for status, date ranges, and product_id
   * 4. Perform LEFT JOIN with ecommerce_mall_products on wishlist_items to get product name, images, and availability
   * 5. Check variant stock levels to determine product availability status
   * 6. Apply pagination: limit=20 (fixed), cursor-based navigation for efficiency
   * 7. Return paginated result with next_cursor if more pages exist
   *
   * Error handling:
   * - Return 404 if customer_id is missing from token
   * - Return 400 if invalid sort parameter or invalid status value
   * - Return 200 OK with empty list if no wishlists found
   *
   * Edge cases:
   * - Products in wishlists may have been deleted - filter them out during query
   * - Soft-deleted wishlists should not be returned unless status='deleted' is specified
   * - Zero-stock variants should show product as unavailable but remain in wishlist
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEcommerceMallWishlist.IRequest,
  ): Promise<IPageIEcommerceMallWishlist.ISummary> {
    try {
      return await patchEcommerceMallMemberWishlists({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single customer wishlist by its identifier, including all wishlist items with product details and availability status.
   *
   * This operation returns the complete wishlist entity with its associated products. Each item includes product metadata (id, name, images, price, availability status) to enable immediate display without additional API calls. Deleted products are automatically excluded from the result.
   *
   * **Business Logic**:
   * - Returns the wishlist with all non-deleted items
   * - Each item shows current product availability based on variant stock levels
   * - Automatically excludes products that have been deleted by sellers
   * - Validates that the wishlist exists and is not soft-deleted
   *
   * @param connection
   * @param wishlistId The unique identifier of the wishlist to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate wishlistId is a valid UUID format
   * 2. Query ecommerce_mall_wishlists table for record with matching id
   * 3. Verify wishlist.deleted_at IS NULL (active wishlist only)
   * 4. If not found, return 404 Not Found
   * 5. Query ecommerce_mall_wishlist_items for items where ecommerce_mall_wishlist_id matches and deleted_at IS NULL
   * 6. For each item, join with ecommerce_mall_products to get product details
   * 7. Calculate availability status: product is available if any variant has stock > 0
   * 8. Return wishlist with items array containing:
   *    - Item metadata (created_at, updated_at)
   *    - Product full details (id, name, images, variants with stock status)
   * 9. Sort items by added date (created_at ascending)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":wishlistId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallWishlist> {
    try {
      return await getEcommerceMallMemberWishlistsWishlistId({
        member,
        wishlistId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing wishlist by replacing its editable attributes.
   *
   * This operation allows a customer to modify their wishlist information. Currently, the only editable field is customer_id, which can be used for data migration or account management scenarios. The updated_at timestamp is automatically modified to reflect the change.
   *
   * ### Security and Validation
   *
   * - The customer making the request must own the wishlist (customer_id in session must match wishlist customer_id)
   * - The wishlist must exist and not be soft-deleted
   * - Customer_id must reference a valid active customer account
   *
   * ### Update Behavior
   *
   * - This is a full replacement operation
   * - Only customer_id can be modified
   * - created_at and id remain unchanged
   * - Soft-deleted wishlists cannot be updated
   *
   * @param connection
   * @param wishlistId The UUID of the wishlist to update
   * @param body Update fields for the wishlist. Only customer_id can be modified.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate that the authenticated customer owns the wishlist by comparing session customer_id with wishlist.customer_id
   * 2. Verify the wishlist exists and is not soft-deleted (deleted_at is NULL)
   * 3. Update the customer_id field with the value from request body
   * 4. Set updated_at to the current timestamp
   * 5. Verify the new customer_id references a valid active customer account in ecommerce_mall_members
   * 6. Return the complete updated wishlist entity with all fields
   * 7. Throw 404 error if wishlist not found
   * 8. Throw 403 error if customer does not own the wishlist
   * 9. Throw 400 error if customer_id is invalid or references a soft-deleted customer
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":wishlistId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallWishlist.IUpdate,
  ): Promise<IEcommerceMallWishlist> {
    try {
      return await putEcommerceMallMemberWishlistsWishlistId({
        member,
        wishlistId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete a customer wishlist and all its associated items.
   *
   * Removes a wishlist from active view by setting deleted_at timestamp. All wishlist items are cascade-deleted. Customers cannot access deleted wishlists. The operation is member-scoped — only the wishlist owner can delete it.
   *
   * **Deletion Behavior**:
   *
   * - Soft delete via deleted_at timestamp (not permanent removal)
   * - Cascade delete to all wishlist items
   * - Products remain intact; only wishlist reference is removed
   * - Cannot be undone; requires recreation of wishlist and re-adding items
   * - Deleted wishlists are excluded from all member wishlist queries
   *
   * @param connection
   * @param wishlistId UUID identifier of the wishlist to delete.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Authenticate member and verify ownership of wishlist
   * 2. Find ecommerce_mall_customer_wishlists where id = wishlistId AND ecommerce_mall_member_id = authenticated_member_id
   * 3. If not found or not owner, return 404 Not Found
   * 4. Check if already soft-deleted (deleted_at is not null), return 409 Conflict
   * 5. Begin database transaction
   * 6. Cascade delete all ecommerce_mall_wishlist_items where ecommerce_mall_wishlist_id = wishlistId (defined by ON DELETE CASCADE in schema)
   * 7. Update wishlist: set deleted_at = NOW(), updated_at = NOW()
   * 8. Commit transaction
   * 9. Return deleted wishlist entity with all fields including deleted_at, updated_at, and is_deleted marker
   *
   * **Error Handling**:
   * - 404 Not Found: Wishlist not found or not owned by authenticated member
   * - 409 Conflict: Wishlist already deleted (soft-deleted)
   * - 401 Unauthorized: Not authenticated
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":wishlistId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallMemberWishlistsWishlistId({
        member,
        wishlistId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
