import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCustomerAddress } from "../../../../../api/structures/IEcommerceMallCustomerAddress";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getEcommerceMallMemberCustomersCustomerIdAddressesAddressId } from "../../../../../providers/getEcommerceMallMemberCustomersCustomerIdAddressesAddressId";

@Controller("/ecommerceMall/member/customers/:customerId/addresses/:addressId")
export class EcommercemallMemberCustomersAddressesController {
  /**
   * Retrieve a specific shipping address belonging to the authenticated customer.
   *
   * This operation returns the complete address entity including recipient name, phone number, street address, city, state/province, postal code, country, and default status. Only addresses belonging to the authenticated customer are accessible.
   *
   * @param connection
   * @param customerId The customer ID that owns this address. Path parameter for authorization context.
   * @param addressId The unique identifier of the address to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query ecommerce_mall_customer_addresses table for a single record matching the provided addressId and customerId.
   *
   * 1. Validate that customerId and addressId are valid UUIDs
   * 2. Verify the address exists and is not soft-deleted (deleted_at IS NULL)
   * 3. Confirm the address belongs to the authenticated customer (ecommerce_mall_member_id = customerId)
   * 4. Return the complete address record including all fields
   *
   * Error handling:
   * - 404 if address not found or belongs to different customer
   * - 404 if address is soft-deleted
   * - 401/403 if customer is not authenticated or not authorized
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCustomerAddress> {
    try {
      return await getEcommerceMallMemberCustomersCustomerIdAddressesAddressId({
        member,
        customerId,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
