import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomerAddress } from "../../../../../api/structures/IEcommerceMallCustomerAddress";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { postEcommerceMallMemberCustomerAddresses } from "../../../../../providers/postEcommerceMallMemberCustomerAddresses";

@Controller("/ecommerceMall/member/customer/addresses")
export class EcommercemallMemberCustomerAddressesController {
  /**
   * Creates a new shipping address for the authenticated customer.
   *
   * The customer can add multiple addresses to their account, each storing recipient information and delivery location details. All address fields must contain valid information. If any required field is missing or invalid, the address creation is rejected.
   *
   * The created address is immediately available for use in future orders. If the customer indicates this should be the default address, any existing default address is updated accordingly.
   *
   * @param connection
   * @param body Address creation data including recipient name, phone number, complete address details, and default flag.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Extract authenticated customer ID from JWT session (ecommerce_mall_member_id)
   * 2. Validate all required fields: recipient_name, phone, street, city, state, postal_code, country
   * 3. If is_default is true, find existing address with is_default=true for this customer and set it to false
   * 4. Insert new address record with auto-generated UUID for id, current timestamp for created_at/updated_at, NULL for deleted_at, and the provided is_default value
   * 5. Return the complete address entity including generated id
   *
   * Error handling:
   * - Return 400 for missing or invalid required fields (recipient_name, phone, street, city, state, postal_code, country cannot be empty)
   * - Return 401 if customer is not authenticated
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEcommerceMallCustomerAddress.ICreate,
  ): Promise<IEcommerceMallCustomerAddress> {
    try {
      return await postEcommerceMallMemberCustomerAddresses({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
