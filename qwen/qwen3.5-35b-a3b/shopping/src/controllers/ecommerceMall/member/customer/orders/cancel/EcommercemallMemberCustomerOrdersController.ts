import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrder } from "../../../../../../api/structures/IEcommerceMallOrder";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { postEcommerceMallMemberCustomerOrdersOrderIdCancel } from "../../../../../../providers/postEcommerceMallMemberCustomerOrdersOrderIdCancel";

@Controller("/ecommerceMall/member/customer/orders/:orderId/cancel")
export class EcommercemallMemberCustomerOrdersController {
  /**
   * Create cancellation requests for all order items in an order.
   *
   * Allows a customer to request cancellation of order items that have not yet been shipped. Each item with 'paid' status can have one pending cancellation request. The request requires a reason text and must be approved by the seller before the item is cancelled and refund processed.
   *
   * Only items with 'paid' status can be cancelled. Items that are 'shipped', 'delivered', 'cancelled', or 'refunded' cannot be cancelled through this endpoint. If an item already has a pending cancellation request, a new request cannot be created.
   *
   * When all items in an order are cancelled, the entire order status becomes 'cancelled'.
   *
   * @param connection
   * @param orderId The unique identifier of the order to cancel items from. Must be owned by the authenticated customer.
   * @param body Cancellation request data containing the reason for cancellation and optional list of specific item IDs to cancel. If itemIds is not provided, all items in the order will be cancelled.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate customer authentication (member
     *   actor) 2. Fetch order by orderId, verify customer is the order owner 3.
     *   Fetch all order items belonging to this order 4. Validate reason text
     *   is provided and non-empty 5. Determine items to cancel: - If itemIds
     *   provided in requestBody, use those - Otherwise, use all items in the
     *   order 6. For each item to cancel: a. Verify item status is 'paid' b.
     *   Check no existing cancellation request with status 'pending' exists for
     *   this item (enforced by @@unique([ecommerce_mall_order_item_id,
     *   status])) c. Verify item hasn't been soft-deleted (deleted_at is null)
     *   7. Create cancellation requests for valid items: - Set status =
     *   'pending' - Set reason from request body - Set
     *   ecommerce_mall_order_item_id, ecommerce_mall_order_id,
     *   ecommerce_mall_seller_id - Create snapshot record
     *   (ecommerce_mall_cancellation_request_snapshots) on creation 8. Return
     *   201 Created with list of created cancellation requests 9. Return 400
     *   Bad Request with details of which items couldn't be cancelled and why
     *   10. Return 404 Not Found if order doesn't exist or customer doesn't own
     *   it
   *
   * Business Rules:
   * - Only items with status 'paid' can be cancelled (Section 612)
   * - Each item can have only one active cancellation request (Section 172)
   * - Cancellation requires seller approval (Section 760)
   * - Customer must provide reason text (Section 400)
   * - When all items are cancelled, order status becomes 'cancelled' (Section 612)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async cancel(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallOrder.ICancelRequest,
  ): Promise<IEcommerceMallOrder.ICancelResponse> {
    try {
      return await postEcommerceMallMemberCustomerOrdersOrderIdCancel({
        member,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
