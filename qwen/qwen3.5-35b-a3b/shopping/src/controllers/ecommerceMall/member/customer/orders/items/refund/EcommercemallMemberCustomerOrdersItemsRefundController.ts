import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallRefundRequest } from "../../../../../../../api/structures/IEcommerceMallRefundRequest";
import { MemberAuth } from "../../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../../decorators/payload/MemberPayload";
import { postEcommerceMallMemberCustomerOrdersOrderIdItemsItemIdRefund } from "../../../../../../../providers/postEcommerceMallMemberCustomerOrdersOrderIdItemsItemIdRefund";

@Controller(
  "/ecommerceMall/member/customer/orders/:orderId/items/:itemId/refund",
)
export class EcommercemallMemberCustomerOrdersItemsRefundController {
  /**
   * Submit a refund request for a specific order item.
   *
   * Customers may request refunds for individual order items with delivered status. The request initiates a seller approval workflow where the seller must approve or reject the refund. Once approved, stock quantities are restored and the order item status changes to refunded. Refund requests are limited to one per item and must be submitted within the platform's refund policy window.
   *
   * Requires authentication as a customer member. The order item must belong to an order placed by the requesting customer and have delivered status.
   *
   * @param connection
   * @param orderId The UUID of the order containing the item. Used to verify order ownership by the requesting customer.
   * @param itemId The UUID of the order item being refunded. Must have delivered status and be owned by the order specified.
   * @param body The refund request details. The reason field is required and describes why the customer is requesting a refund. This field is mandatory and must be provided by the customer.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate customer authentication - ensure
     *   request is from authenticated customer member 2. Load order by orderId
     *   and verify order belongs to requesting customer
     *   (ecommerce_mall_member_id) 3. Load order item by itemId and verify: -
     *   Item belongs to the specified order (ecommerce_mall_order_id matches) -
     *   Item status is 'delivered' - refund requests only allowed for delivered
     *   items - Item is not already refunded (status != 'refunded') 4. Check
     *   for existing refund request on this order item via unique constraint on
     *   order_item_id - If refund request exists with any status (pending,
     *   approved, rejected), return 409 Conflict 5. Create new refund request
     *   record: - Set order_item_id to itemId - Set reason from request body
     *   (required, non-empty) - Set status to 'pending' - Set created_at to
     *   current timestamp - approved_by_seller_id and rejected_by_seller_id
     *   remain null 6. Return the created refund request with full details
   *
   * Error cases:
   * - 404 Not Found: Order or order item not found
   * - 403 Forbidden: Order does not belong to requesting customer
   * - 409 Conflict: Refund request already exists for this item
   * - 400 Bad Request: Order item status is not 'delivered' or reason is missing/empty
   *
   * Business rules enforced:
   * - Per-item refund requests only (one request per order item)
   * - Only delivered items eligible for refund
   * - No duplicate refund requests allowed
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallRefundRequest.ICreate,
  ): Promise<IEcommerceMallRefundRequest> {
    try {
      return await postEcommerceMallMemberCustomerOrdersOrderIdItemsItemIdRefund(
        {
          member,
          orderId,
          itemId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
