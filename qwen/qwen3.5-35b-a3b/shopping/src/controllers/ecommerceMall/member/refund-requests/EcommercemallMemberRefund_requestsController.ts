import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallRefundRequest } from "../../../../api/structures/IEcommerceMallRefundRequest";
import { IPageIEcommerceMallRefundRequest } from "../../../../api/structures/IPageIEcommerceMallRefundRequest";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getEcommerceMallMemberRefundRequestsId } from "../../../../providers/getEcommerceMallMemberRefundRequestsId";
import { patchEcommerceMallMemberRefundRequests } from "../../../../providers/patchEcommerceMallMemberRefundRequests";
import { postEcommerceMallMemberRefundRequests } from "../../../../providers/postEcommerceMallMemberRefundRequests";

@Controller("/ecommerceMall/member/refund-requests")
export class EcommercemallMemberRefund_requestsController {
  /**
   * Create a new refund request for a delivered order item.
   *
   * Customers can request a refund for individual order items that have been delivered. The request requires specifying the order item and providing a reason text. The refund request is created with pending status and requires seller approval before processing. Each order item can have only one refund request.
   *
   * Validation Rules:
   * - Order item must have status "delivered"
   * - Refund request must be within 7 days of delivery date
   * - One refund request per order item (unique constraint enforced)
   * - Reason field is required and cannot be empty
   *
   * @param connection
   * @param body Refund request creation data containing the order item reference and customer-provided reason.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Create a new refund request record for the
     *   authenticated customer's delivered order item.
   *
   * Implementation Steps:
   * 1. Validate customer authentication (member actor)
   * 2. Fetch order item by order_item_id from request body
   * 3. Verify order item belongs to an order placed by the authenticated customer
   * 4. Validate order item status equals "delivered" - reject with 400 if not
   * 5. Calculate delivery date from order_item.created_at or related shipment
   * 6. Validate 7-day window from delivery date - reject with 400 if expired
   * 7. Check for existing refund request for this order_item_id (unique constraint)
   *    - If exists and status not "rejected" or "approved", reject with 409
   * 8. Create refund request record:
   *    - order_item_id: from request
   *    - reason: from request (required, non-empty)
   *    - status: "pending"
   *    - approved_by_seller_id: null
   *    - rejected_by_seller_id: null
   *    - created_at: now()
   *    - updated_at: now()
   *    - id: UUID generated by database
   * 9. Return full refund request entity in response
   *
   * Error Scenarios:
   * - 404: Order item not found
   * - 403: Order item does not belong to customer's order
   * - 400: Order item status is not "delivered"
   * - 400: Refund request outside 7-day window
   * - 409: Refund request already exists for this order item
   * - 400: Reason field is empty or missing
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEcommerceMallRefundRequest.ICreate,
  ): Promise<IEcommerceMallRefundRequest> {
    try {
      return await postEcommerceMallMemberRefundRequests({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve paginated list of refund requests for the authenticated customer.
   *
   * This operation enables customers to view their refund request history with support for filtering by status, date ranges, and sorting options. Each result includes essential summary information about the request, associated order item, and current approval status.
   *
   * @param connection
   * @param body Search criteria including status filter, date ranges, sorting options, and pagination parameters. Status can filter by pending, approved, or rejected. Date range filters use ISO 8601 datetime format. Pagination uses cursor-based approach with limit and cursor parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query ecommerce_mall_refund_requests table
     *   filtered by authenticated customer's order items.
   *
   * 1. Extract customer ID from authenticated session (authorization middleware)
   * 2. Join with ecommerce_mall_order_items to filter only items belonging to customer's orders
   * 3. Apply status filter if provided (pending, approved, rejected)
   * 4. Apply date range filters on created_at or updated_at if provided
   * 5. Support sorting by created_at, updated_at, status, or reason length
   * 6. Implement cursor-based pagination using id field for efficient large result set navigation
   * 7. Return summary fields: id, status, created_at, updated_at, reason (truncated), item (order item id, product name, item status)
   * 8. Handle edge cases: no refunds found, pagination edge cases, invalid filter values
   *
   * Error handling:
   * - 401 Unauthorized if not authenticated
   * - 400 Bad Request if filter parameters are invalid
   * - 404 Not Found if customer has no refund requests (if client prefers explicit error)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEcommerceMallRefundRequest.IRequest,
  ): Promise<IPageIEcommerceMallRefundRequest.ISummary> {
    try {
      return await patchEcommerceMallMemberRefundRequests({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single refund request by its unique identifier.
   *
   * This operation allows users to view the complete details of a specific refund request, including the associated order item, current approval status, seller response (if any), and the customer-provided reason for the refund. Authorization rules determine which refund requests are visible to the requesting user: customers can only view their own refund requests, sellers can view refund requests for order items belonging to their products, and administrators have access to all refund requests on the platform.
   *
   * The response includes the refund request's unique identifier, the associated order item reference, approval status, timestamps for creation and updates, and if applicable, the seller who approved or rejected the request along with any response reason.
   *
   * Refund requests are soft-deletable, and deleted records will not be returned in normal queries.
   *
   * @param connection
   * @param id The unique identifier of the refund request.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate the refund request ID format (UUID).
     *   2. Query ecommerce_mall_refund_requests table for the record with
     *   matching id where deleted_at IS NULL. 3. If not found, return 404 Not
     *   Found. 4. Authorization check: - For customer: verify the refund
     *   request's order item belongs to an order placed by this customer. - For
     *   seller: verify the order item's product is owned by this seller
     *   (order_item.item.product.seller_id = current_seller_id). - For
     *   administrator: allow access to all refund requests. 5. If user lacks
     *   authorization, return 403 Forbidden. 6. Join with
     *   ecommerce_mall_order_items to include order item details (order_id,
     *   product_id, variant_id, quantity, unit_price). 7. Optionally join with
     *   ecommerce_mall_sellers to include seller details for approved_by_seller
     *   and rejected_by_seller. 8. Return the complete refund request object
     *   with all fields. 9. Sort related data by created_at descending if
     *   returning multiple related records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallRefundRequest> {
    try {
      return await getEcommerceMallMemberRefundRequestsId({
        member,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
