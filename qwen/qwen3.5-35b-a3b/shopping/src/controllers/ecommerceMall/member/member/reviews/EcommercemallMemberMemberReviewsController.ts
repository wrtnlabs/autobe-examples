import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallReview } from "../../../../../api/structures/IEcommerceMallReview";
import { IPageIEcommerceMallReview } from "../../../../../api/structures/IPageIEcommerceMallReview";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchEcommerceMallMemberMemberReviews } from "../../../../../providers/patchEcommerceMallMemberMemberReviews";

@Controller("/ecommerceMall/member/member/reviews")
export class EcommercemallMemberMemberReviewsController {
  /**
   * Retrieve paginated list of reviews written by the authenticated member.
   *
   * This endpoint allows members to view all their reviews across products, with support for filtering, sorting, and pagination. Reviews are returned with product information, ratings, and timestamps. Deleted reviews are excluded from results unless explicitly requested for administrative purposes.
   *
   * @param connection
   * @param body Search and filtering criteria for member reviews including rating filters, product filters, date ranges, sorting options, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query ecommerce_mall_reviews table filtering by
     *   member_id from authenticated session.
   *
   * 1. Apply member identity from JWT session token
   * 2. Filter out deleted reviews (deleted_at IS NULL) unless showDeleted=true
   * 3. Apply optional filters:
   *    - rating: exact rating filter (1-5)
   *    - rating_min/rating_max: rating range filter
   *    - product_id: filter by specific product (UUID)
   *    - product_name: search by product name
   *    - created_from/created_to: date range filter
   *    - sort: sorting options (newest, oldest, highest_rating, lowest_rating)
   * 4. Join with ecommerce_mall_products for product details (name, images)
   * 5. Apply cursor-based pagination with limit and after cursor
   * 6. Return paginated response with total count, next cursor, and review summaries
   *
   * Error handling:
   * - Return 401 if not authenticated
   * - Return 400 if invalid filter parameters (rating out of range 1-5)
   * - Return empty array if no reviews match filters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEcommerceMallReview.IRequest,
  ): Promise<IPageIEcommerceMallReview.ISummary> {
    try {
      return await patchEcommerceMallMemberMemberReviews({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
