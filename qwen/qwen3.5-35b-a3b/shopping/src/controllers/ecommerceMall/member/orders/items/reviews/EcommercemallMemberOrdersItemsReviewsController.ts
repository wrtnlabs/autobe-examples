import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCustomerReview } from "../../../../../../api/structures/IEcommerceMallCustomerReview";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { postEcommerceMallMemberOrdersOrderIdItemsItemIdReviews } from "../../../../../../providers/postEcommerceMallMemberOrdersOrderIdItemsItemIdReviews";

@Controller("/ecommerceMall/member/orders/:orderId/items/:itemId/reviews")
export class EcommercemallMemberOrdersItemsReviewsController {
  /**
   * Create a product review after order item delivery.
   *
   * This operation allows a customer to write a review for a product they have purchased. The system enforces strict validation: the order item must have 'delivered' status, and the customer can only write one review per product per order. Reviews include a required rating (1-5 stars) and optional text content.
   *
   * Upon successful creation, the review is associated with the customer, product, order, and specific order item. The product's average rating statistics are automatically updated to include the new review in aggregate calculations.
   *
   * @param connection
   * @param orderId UUID of the order containing the item to be reviewed
   * @param itemId UUID of the specific order item that was delivered and is being reviewed
   * @param body Review data including rating and optional text content. Rating must be between 1 and 5 stars.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a customer review for a delivered order item.
   *
   * Implementation steps:
   * 1. Validate path parameters: orderId and itemId must be valid UUIDs
   * 2. Fetch order_item from ecommerce_mall_order_items by itemId
   * 3. Verify ownership: order_item's order_id must match orderId parameter
   * 4. Verify customer context: authenticated customer_id must match order's customer_id
   * 5. Validate delivery status: order_item.status must be 'delivered'
   *    - If not delivered, return 400 Bad Request with message 'Order item is not delivered yet'
   * 6. Check duplicate review: query ecommerce_mall_customer_reviews for existing review with matching customer_id, product_id, and order_id
   *    - If existing review found, return 409 Conflict with message 'Review already exists for this product in this order'
   * 7. Extract product_id from order_item.product_variant.product_id (via product_variant relationship)
   * 8. Create review record in ecommerce_mall_customer_reviews:
   *    - customer_id: from authenticated user context
   *    - product_id: extracted from order item's product variant
   *    - order_id: from path parameter
   *    - order_item_id: from path parameter
   *    - rating: from request body (validate 1-5 range)
   *    - text: from request body (optional, nullable)
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   * 9. Update ecommerce_mall_product_review_stats:
   *    - Increment review_count
   *    - Increment corresponding rating_N_count based on rating value
   *    - Recalculate average_rating (sum of all ratings / count, rounded to 2 decimals)
   *    - Update updated_at timestamp
   *    - If no stats record exists, create new record
   * 10. Return 201 Created with the newly created review entity (without reviewSnapshots array)
   *
   * Error handling:
   * - 400: Delivery status not met, or rating out of range (1-5)
   * - 404: Order item not found, or order ID mismatch
   * - 409: Duplicate review already exists
   * - 401: Unauthenticated
   * - 403: Customer does not own this order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallCustomerReview.ICreate,
  ): Promise<IEcommerceMallCustomerReview> {
    try {
      return await postEcommerceMallMemberOrdersOrderIdItemsItemIdReviews({
        member,
        orderId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
