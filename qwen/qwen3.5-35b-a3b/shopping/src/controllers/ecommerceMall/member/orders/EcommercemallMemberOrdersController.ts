import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrder } from "../../../../api/structures/IEcommerceMallOrder";
import { IEcommerceMallShipment } from "../../../../api/structures/IEcommerceMallShipment";
import { IPageIEcommerceMallOrder } from "../../../../api/structures/IPageIEcommerceMallOrder";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getEcommerceMallMemberOrdersId } from "../../../../providers/getEcommerceMallMemberOrdersId";
import { getEcommerceMallMemberOrdersOrderIdShipments } from "../../../../providers/getEcommerceMallMemberOrdersOrderIdShipments";
import { patchEcommerceMallMemberOrders } from "../../../../providers/patchEcommerceMallMemberOrders";
import { postEcommerceMallMemberOrders } from "../../../../providers/postEcommerceMallMemberOrders";

@Controller("/ecommerceMall/member/orders")
export class EcommercemallMemberOrdersController {
  /**
   * Create a new order from shopping cart items.
   *
   * Creates an order record with a unique order number when a member completes checkout with successful payment. The order includes all cart items with their quantities and prices frozen at checkout time. Each order item is initialized with 'paid' status pending shipment fulfillment. The shipping address is copied from the member's selected address to preserve the delivery information at purchase time. Order total is calculated as the sum of all item subtotals.
   *
   * @param connection
   * @param body Cart items to order, shipping address ID, and member context. Contains the list of product variants with quantities being ordered, the customer's selected shipping address, and member authentication context.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Create new order record with the following steps:
   *
   * 1. Validate member authentication and get member_id from session
   * 2. Retrieve cart items for authenticated member from cart
   * 3. Verify all cart items still exist and inventory is available
   * 4. Select shipping address by ID from member's addresses (validate existence)
   * 5. Generate unique order_number in format ORD-{YYYYMMDD}-{sequence}
   * 6. Calculate total_price as sum of (variant_price × quantity) for all items
   * 7. Create order record with status='paid'
   * 8. For each cart item, create order_item record:
   *    - Set unit_price and subtotal from variant price at checkout
   *    - Set status='paid'
   *    - Link to seller_id from product_variant
   * 9. Return full order object with order_items embedded
   *
   * Error handling:
   * - 404: Cart item or address not found
   * - 409: Insufficient inventory for any variant
   * - 422: Payment processing failed
   * - 400: Cart is empty or invalid
   *
   * After order creation, clear the cart for the member.
   * Order snapshots should be created to preserve transaction state.
   * Notify seller(s) of new order(s) via integration.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEcommerceMallOrder.ICreate,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await postEcommerceMallMemberOrders({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and list orders with pagination, filtering, and sorting capabilities.
   *
   * Provides paginated access to order records with flexible search criteria including status filtering, date range queries, and sorting options. For customer users, returns only their own orders. For administrators, returns all platform orders.
   *
   * The endpoint supports filtering by order status (paid, shipped, delivered, cancelled, refunded, partially_completed), date ranges for order creation, and sorting by creation date or total price. Results are optimized for customer order history viewing and administrative order oversight.
   *
   * @param connection
   * @param body Search criteria including status filter, date range, sorting options, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query ecommerce_mall_orders table with pagination
     *   and filtering.
   *
   * Authorization:
   * - For member actors: filter by ecommerce_mall_member_id = current_user.id
   * - For administrator/superAdministrator actors: no customer filter, view all orders
   * - Return 404 if authenticated user has no matching orders
   *
   * Filters (from requestBody):
   * - status: optional filter by order status value
   * - startDate: optional ISO date filter (created_at >= startDate)
   * - endDate: optional ISO date filter (created_at <= endDate)
   * - sortBy: sort field (created_at, total_price, order_number)
   * - sortOrder: 'asc' or 'desc' (default: 'desc' for created_at)
   *
   * Pagination:
   * - cursor: optional cursor for cursor-based pagination
   * - limit: number of results per page (default: 20, max: 100)
   *
   * Sorting:
   * - Default: created_at DESC
   * - If sortBy provided, apply that field with sortOrder
   *
   * Response construction:
   * - Join with ecommerce_mall_customer_addresses for shipping_address data
   * - Join with ecommerce_mall_member for customer display_name
   * - Aggregate order item counts from items relation if needed
   * - Apply authorization filters before querying
   * - Return cursor-based pagination with nextCursor/prevCursor if applicable
   *
   * Edge cases:
   * - No results: return empty page with pagination metadata
   * - Invalid date format: return 400 with error message
   * - Invalid sortBy/sortOrder: return 400 or use defaults
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEcommerceMallOrder.IRequest,
  ): Promise<IPageIEcommerceMallOrder.ISummary> {
    try {
      return await patchEcommerceMallMemberOrders({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single order's complete details for viewing order history and status.
   *
   * This operation returns the full order entity including customer information, shipping address, all order items with product details and prices, and shipment tracking information. Customers can view their own orders while administrators have platform-wide access to all orders.
   *
   * The operation includes:
   * - Order metadata (number, status, total price, dates)
   * - Customer information (name, contact)
   * - Complete shipping address
   * - All order items with product names, variant options, quantities, and prices
   * - Shipment information with carrier and tracking numbers
   * - Delivery status per item
   *
   * This supports order history viewing, dispute resolution, and platform oversight.
   *
   * @param connection
   * @param id Unique identifier of the order to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Retrieve order by UUID and return full details
     *   with all related data.
   *
   * 1. Query ecommerce_mall_orders by id
   * 2. Join with ecommerce_mall_members to get customer information
   * 3. Join with ecommerce_mall_customer_addresses to get shipping address
   * 4. Query all ecommerce_mall_order_items for this order
   * 5. For each order item, join with ecommerce_mall_product_variants to get product details
   * 6. Join with ecommerce_mall_sellers for seller information on each item
   * 7. Query ecommerce_mall_shipments for this order
   * 8. Return complete order entity with all nested data
   *
   * Authorization:
   * - Customers: Only access orders where ecommerce_mall_member_id matches authenticated user
   * - Administrators: Access any order regardless of owner
   *
   * Return 404 if order not found or customer is not authorized.
   * Include deleted_at check - if non-null, return 404 (soft-deleted orders are not accessible).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await getEcommerceMallMemberOrdersId({
        member,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve all shipments for a customer order, displaying tracking information and items from each shipment.
   *
   * This endpoint returns all shipments associated with an order, enabling customers to track packages from multiple sellers. Each shipment entry includes carrier name, tracking number, current status, and the order items contained in that shipment. Shipments are returned in chronological order with the most recently created shipment listed first.
   *
   * Customers can view shipment tracking information to monitor delivery progress. The endpoint validates that the requesting customer owns the order before returning shipment data. Sellers and administrators can also view shipments for orders they manage.
   *
   * @param connection
   * @param orderId The unique identifier of the order to retrieve shipments for.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query ecommerce_mall_shipments table filtering by
     *   order_id matching the path parameter.
   *
   * Join with ecommerce_mall_shipment_items to retrieve order items included in each shipment, including item quantity_shipped, status, and timestamps.
   *
   * Include seller information from ecommerce_mall_sellers for each shipment (seller_id and seller name).
   *
   * Include product variant details for each item (product name, variant options) via productVariant join.
   *
   * Filter: Only return shipments where the order belongs to the authenticated customer (or where the customer has admin/super-admin permission).
   *
   * Sort: Order shipments by created_at descending (most recent first).
   *
   * Pagination: Return all shipments for the order (typically 1-5 shipments, no pagination needed for a single order's shipments).
   *
   * Response: Return array of shipment summaries, each containing:
   *   - Shipment id, status, carrier, tracking_number, shipped_at, delivered_at, created_at
   *   - Seller information (id, name from shop profile)
   *   - Array of order items with their quantities, prices, and statuses
   *
   * Validation:
   *   - Verify orderId exists and the authenticated customer owns the order
   *   - Return 404 if order not found
   *   - Return 403 if customer does not own the order
   *   - Return empty array if order has no shipments yet
   *
   * Edge cases:
   *   - Order with items from same seller: 1 shipment
   *   - Order with items from multiple sellers: Multiple shipments
   *   - Shipment created but not yet shipped: status='shipped', tracking info may be null
   *   - Delivery confirmed or auto-delivered: status='delivered', delivered_at set
   *   - Soft-deleted shipments: exclude from results
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId/shipments")
  public async shipments(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShipment.ISummary> {
    try {
      return await getEcommerceMallMemberOrdersOrderIdShipments({
        member,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
