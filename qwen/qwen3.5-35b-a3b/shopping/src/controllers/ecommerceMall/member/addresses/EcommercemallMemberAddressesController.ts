import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCustomerAddress } from "../../../../api/structures/IEcommerceMallCustomerAddress";
import { IPageIEcommerceMallCustomerAddress } from "../../../../api/structures/IPageIEcommerceMallCustomerAddress";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteEcommerceMallMemberAddressesAddressId } from "../../../../providers/deleteEcommerceMallMemberAddressesAddressId";
import { patchEcommerceMallMemberAddresses } from "../../../../providers/patchEcommerceMallMemberAddresses";
import { putEcommerceMallMemberAddressesAddressId } from "../../../../providers/putEcommerceMallMemberAddressesAddressId";

@Controller("/ecommerceMall/member/addresses")
export class EcommercemallMemberAddressesController {
  /**
   * List all shipping addresses for the authenticated customer with pagination and optional filtering.
   *
   * Returns a paginated collection of the customer's saved shipping addresses. Each address includes recipient details, full address information, and default status. The response supports filtering by default status and search by recipient name or city.
   *
   * Addresses that are marked as default are clearly indicated in the response. The operation respects soft-deletion and only returns active addresses (where deleted_at is null).
   *
   * @param connection
   * @param body Search and filter criteria for address list including pagination, default status filter, and text search options.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the ecommerce_mall_customer_addresses table for records belonging to the authenticated customer (filter by ecommerce_mall_member_id from JWT token).
   *
   * Apply optional filters:
   * - is_default: filter addresses by default status (true/false)
   * - recipient_name: partial match search on recipient name (ILIKE)
   * - city: partial match search on city (ILIKE)
   *
   * Apply pagination:
   * - page: 1-based page number (default: 1)
   * - pageSize: items per page (default: 20, max: 100)
   *
   * Sort results by created_at descending (newest first) by default, or by recipient_name/city if specified.
   *
   * Filter out soft-deleted records (deleted_at IS NULL).
   *
   * Return IPageIEcommerceMallCustomerAddress.ISummary with total count, page info, and list of address summaries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEcommerceMallCustomerAddress.IRequest,
  ): Promise<IPageIEcommerceMallCustomerAddress.ISummary> {
    try {
      return await patchEcommerceMallMemberAddresses({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shipping address in the customer's address collection.
   *
   * Modifies the specified shipping address belonging to the authenticated customer. Any of the following fields can be updated: recipient name, phone number, street address, city, state/province, postal code, country, or default status designation.
   *
   * If the address being updated has is_default=true and another address is set as default, the system will automatically unset the default status from the previous default address to maintain the single-default constraint.
   *
   * Soft-deleted addresses cannot be updated; attempting to modify a deleted address will result in a not-found error. Addresses must belong to the authenticated customer; cross-customer modifications are not permitted.
   *
   * @param connection
   * @param addressId Unique identifier of the shipping address to update
   * @param body Updateable fields for the shipping address. Any field not provided will retain its existing value. The is_default field will trigger automatic default reset for other addresses if set to true.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update a customer shipping address in ecommerce_mall_customer_addresses table.
   *
   * 1. Find the address by addressId (UUID) with soft-delete check (deleted_at is NULL).
   * 2. Verify ownership: address.ecommerce_mall_member_id must match the authenticated member's ID.
   * 3. Reject if address is soft-deleted (deleted_at is NOT NULL).
   * 4. Reject if address does not exist.
   * 5. Validate request body fields:
   *    - recipient_name: string, non-empty, max 100 characters
   *    - phone: string, matches phone format, non-empty
   *    - street: string, non-empty, max 200 characters
   *    - city: string, non-empty, max 100 characters
   *    - state: string, non-empty, max 100 characters
   *    - postal_code: string, non-empty, max 20 characters
   *    - country: string, non-empty, max 50 characters
   *    - is_default: boolean (optional)
   * 6. Handle single-default constraint:
   *    - If is_default=true in request, set is_default=false for all other addresses owned by this customer.
   *    - If is_default is not provided, leave existing is_default value unchanged.
   * 7. Update the address with provided fields, set updated_at to current timestamp.
   * 8. Return the updated address object.
   *
   * Error handling:
   * - 404 Not Found: Address does not exist or is soft-deleted.
   * - 403 Forbidden: Address does not belong to the authenticated customer.
   * - 400 Bad Request: Invalid field values or format violations.
   * - 422 Unprocessable Entity: Validation constraints violated (e.g., trying to set multiple addresses as default).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":addressId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallCustomerAddress.IUpdate,
  ): Promise<IEcommerceMallCustomerAddress> {
    try {
      return await putEcommerceMallMemberAddressesAddressId({
        member,
        addressId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a shipping address from the customer's address collection.
   *
   * This operation performs a soft delete by marking the address with a deleted_at timestamp, preserving the address data for historical order references while removing it from active address listings. The operation enforces business rules to prevent deletion of addresses currently in use by pending orders and ensures customers maintain at least one address for checkout purposes.
   *
   * @param connection
   * @param addressId UUID of the customer shipping address to delete (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate that the authenticated customer owns the address identified by addressId
   * 2. Check for any pending orders (paid, shipped, or cancelled status) that reference this address
   *    - If address is referenced by pending order, reject with 409 Conflict error
   * 3. Count the customer's remaining active addresses
   *    - If address is the customer's only address, reject with 409 Conflict error
   * 4. Verify address is not already soft-deleted (deleted_at is NULL)
   *    - If already deleted, reject with 404 Not Found error
   * 5. Set deleted_at to current timestamp for soft delete
   * 6. Update updated_at timestamp
   * 7. Return null response body
   *
   * Error responses:
   * - 401 Unauthorized: Customer not authenticated
   * - 403 Forbidden: Customer does not own this address
   * - 404 Not Found: Address does not exist or already deleted
   * - 409 Conflict: Address is referenced by pending order OR would leave customer with no addresses
   * - 422 Unprocessable Entity: Address data is invalid
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":addressId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallMemberAddressesAddressId({
        member,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
