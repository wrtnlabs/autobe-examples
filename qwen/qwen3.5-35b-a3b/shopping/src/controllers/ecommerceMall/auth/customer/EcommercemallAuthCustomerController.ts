import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomer } from "../../../../api/structures/IEcommerceMallCustomer";
import { postEcommerceMallAuthCustomerJoin } from "../../../../providers/postEcommerceMallAuthCustomerJoin";
import { postEcommerceMallAuthCustomerLogin } from "../../../../providers/postEcommerceMallAuthCustomerLogin";
import { postEcommerceMallAuthCustomerRefresh } from "../../../../providers/postEcommerceMallAuthCustomerRefresh";

@Controller("/ecommerceMall/auth/customer")
export class EcommercemallAuthCustomerController {
  /**
   * Customer registration creates a new account in the ecommerce_mall_customers table with email and password_hash fields. The email must be unique across all registered customers. Password is securely hashed using bcrypt or equivalent before storage. The registration process generates an email verification token stored in the ecommerce_mall_customer_email_verifications table with an expiration time for security.
   *
   * Security considerations: Password must meet minimum complexity requirements as defined in security policies. The system checks for banned status before allowing registration to prevent abuse. After successful registration, the customer receives an unverified account status and must complete email verification before accessing full platform features.
   *
   * Business rules: Email uniqueness is enforced via database unique constraint. Password hashes are never exposed in API responses. Registration requires both email and password. Once account is created, the customer can use the login endpoint to authenticate and receive session tokens.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer registration data including email address and password
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create a new customer account by validating email uniqueness and password security, then store hashed password in ecommerce_mall_customers table. Generate email verification token stored in ecommerce_mall_customer_email_verifications table. Customer must verify email before full access. Check is_banned flag prevents registration if system-wide ban exists. On success, return JWT access token and refresh token in IAuthorized response format with customer_id, token_type, expires_in, and refresh_token.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallCustomer.IJoin,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Customer login validates credentials stored in the ecommerce_mall_customers table. The email is looked up and the password_hash is verified against the provided password using secure cryptographic comparison. The is_banned field is checked to prevent banned customers from authenticating.
   *
   * Security considerations: Upon successful authentication, a new session record is created in the ecommerce_mall_customer_sessions table with connection metadata (IP address, HTTP referrer, and page href) captured for security auditing and session management. JWT tokens are generated with appropriate expiration times. The access token is used for subsequent API requests, while the refresh token enables session renewal without re-authentication.
   *
   * Business rules: Only non-banned customers can authenticate. Failed login attempts should not reveal whether the email or password was incorrect to prevent enumeration attacks. Multiple concurrent sessions are allowed from different devices. Session tokens expire according to the expired_at timestamp in the session table.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer login credentials
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate customer credentials by looking up email in ecommerce_mall_customers table, comparing provided password against stored password_hash using bcrypt verification, checking is_banned flag. If valid and not banned, create session record in ecommerce_mall_customer_sessions table with IP, href, referrer from request headers. Generate JWT access token and refresh token. Return tokens and customer_id in IAuthorized response. If invalid credentials or banned, return appropriate error without revealing which field was incorrect.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallCustomer.ILogin,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Customer token refresh renews the JWT session without requiring password re-entry. The refresh token is validated against the session record in the ecommerce_mall_customer_sessions table, checking that the session has not expired based on the expired_at timestamp.
   *
   * Security considerations: Each successful refresh creates a new session record, allowing the system to track session activity and invalidate old sessions if needed. The refresh token is single-use - once validated, it becomes invalid and a new refresh token is issued along with the new access token. Connection metadata (IP, referrer, href) is captured for audit purposes.
   *
   * Business rules: Only active sessions (where expired_at is in the future) can be refreshed. Expired sessions require re-authentication via the login endpoint. Refresh tokens enable seamless session extension without password entry, improving user experience while maintaining security through session tracking and token rotation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for session renewal
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate refresh token by looking up the session record in ecommerce_mall_customer_sessions table using the session_id embedded in the refresh token. Check that expired_at has not passed. If valid, issue new access token and refresh token pair. Create new session record in ecommerce_mall_customer_sessions table. Return new tokens in IAuthorized response. If refresh token is invalid or expired, return authentication error. This endpoint maintains session continuity without requiring password re-entry.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallCustomer.IRefresh,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
