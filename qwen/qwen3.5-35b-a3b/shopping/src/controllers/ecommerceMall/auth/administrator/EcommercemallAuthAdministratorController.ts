import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallAdministrator } from "../../../../api/structures/IEcommerceMallAdministrator";
import { postEcommerceMallAuthAdministratorJoin } from "../../../../providers/postEcommerceMallAuthAdministratorJoin";
import { postEcommerceMallAuthAdministratorLogin } from "../../../../providers/postEcommerceMallAuthAdministratorLogin";
import { postEcommerceMallAuthAdministratorRefresh } from "../../../../providers/postEcommerceMallAuthAdministratorRefresh";

@Controller("/ecommerceMall/auth/administrator")
export class EcommercemallAuthAdministratorController {
  /**
   * Register a new administrator account for the e-commerce mall platform.
   *
   * Creates a new administrator account with email/password credentials. The administrator is initialized with 'regular' grade, granting standard oversight permissions for managing sellers, categories, products, orders, and users. Super administrator privileges must be granted through grade promotion by an existing super administrator.
   *
   * The registration process validates email uniqueness, password strength, and required field presence. Upon successful registration, the administrator receives a new session with JWT access and refresh tokens for immediate authenticated access to administrative endpoints.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator registration credentials and profile information
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Create new administrator account by validating
     *   email uniqueness and password strength. Hash password using bcrypt. Set
     *   grade to 'regular' by default. Create initial session upon successful
     *   registration. Return JWT tokens for immediate authentication. Validate
     *   email format, password complexity (minimum 8 chars, mixed case,
     *   numbers). Ensure email is unique by checking against existing records.
     *   Set is_banned to false. Create ecommerce_mall_administrator_sessions
     *   record with JWT access and refresh tokens. Set appropriate expiration
     *   times based on security policy.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallAdministrator.IJoin,
  ): Promise<IEcommerceMallAdministrator.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdministratorJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate administrator with email and password credentials to obtain authentication tokens.
   *
   * Validates administrator credentials against the stored password hash in the database. The system checks the is_banned flag to ensure the account has not been suspended. Upon successful authentication, new JWT access and refresh tokens are generated and stored in the ecommerce_mall_administrator_sessions table for audit trail and session management.
   *
   * This operation establishes a new authenticated session for the administrator, enabling access to protected administrative endpoints. The access token is short-lived for security, while the refresh token allows obtaining new access tokens without re-authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator login credentials
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Validate administrator email and password
     *   credentials against stored password_hash in
     *   ecommerce_mall_administrators table. Check is_banned flag - reject if
     *   true. Verify email format and required field presence. Upon successful
     *   validation, generate new JWT access and refresh tokens. Create new
     *   record in ecommerce_mall_administrator_sessions table with
     *   access_token, refresh_token, IP address, referrer, and session
     *   expiration timestamp. Invalidate any existing sessions for this
     *   administrator if session cleanup policy requires it. Return new tokens
     *   and session information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallAdministrator.ILogin,
  ): Promise<IEcommerceMallAdministrator.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdministratorLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew authentication tokens using a valid refresh token.
   *
   * Validates the provided refresh token against the stored token in ecommerce_mall_administrator_sessions. The system verifies the token matches, the session is active (not deleted), and has not expired. If validation succeeds, new JWT access and refresh tokens are generated and the session record is updated with the new credentials.
   *
   * This operation allows administrators to obtain new access tokens without re-authenticating, maintaining their session state while ensuring tokens are rotated periodically for security. Expired or invalid refresh tokens require a full login operation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access tokens
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Validate refresh token from request body against
     *   stored refresh_token in ecommerce_mall_administrator_sessions table.
     *   Verify the session record exists, is not deleted (deleted_at is null),
     *   and has not expired (expired_at > current time). Check administrator
     *   account is not banned. Upon validation, generate new JWT access and
     *   refresh tokens. Update the session record with new tokens and new
     *   expired_at timestamp. Return the new tokens to client. Reject if
     *   refresh token is invalid, expired, or session has been deleted/revoked.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallAdministrator.IRefresh,
  ): Promise<IEcommerceMallAdministrator.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdministratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
