import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallGuest } from "../../../../api/structures/IEcommerceMallGuest";
import { postEcommerceMallAuthGuestJoin } from "../../../../providers/postEcommerceMallAuthGuestJoin";
import { postEcommerceMallAuthGuestRefresh } from "../../../../providers/postEcommerceMallAuthGuestRefresh";

@Controller("/ecommerceMall/auth/guest")
export class EcommercemallAuthGuestController {
  /**
   * Creates a new guest account for unauthenticated platform visitors. This operation validates the provided email and password against business rules, stores the account in the ecommerce_mall_guests table, and generates JWT tokens for temporary access.
   *
   * The registration process performs email uniqueness validation against existing guest accounts in the database. Password validation follows secure hashing practices. Upon successful creation, JWT tokens are generated and the guest_sessions table receives a record with the refresh token for session management.
   *
   * This operation is the entry point for guest actors to gain platform access. Unlike member actors who register persistent accounts, guest registration creates temporary identities suitable for browsing and limited platform interactions without long-term commitments.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration data for new guest account including email and password credentials
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Create a new guest account by collecting email and password credentials. Store credentials in ecommerce_mall_guests table with email uniqueness constraint. Generate JWT access token and refresh token pair, storing refresh token in ecommerce_mall_guest_sessions table with expiration tracking. Token payload includes guestId, email, and actor type 'guest'. Access token expiration: 15 minutes. Refresh token expiration: 7 days. Return authorized response containing tokens and guest profile data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallGuest.IJoin,
  ): Promise<IEcommerceMallGuest.IAuthorized> {
    try {
      return await postEcommerceMallAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes the guest's JWT access token using a valid refresh token from the ecommerce_mall_guest_sessions table. This operation maintains temporary session continuity without requiring re-registration.
   *
   * The refresh token validation process includes verification against the stored token in the database, expiration checking, and token invalidation for security. Upon successful validation, both access and refresh token pairs are regenerated. The old refresh token is immediately invalidated and a new one is stored in the guest_sessions table with updated expiration.
   *
   * This operation enables guest actors to extend their temporary platform access beyond the initial 15-minute access token expiration period. The refresh token has a 7-day validity window, allowing guests to maintain sessions without re-authentication during extended browsing periods.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token data for token renewal operation
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Renew the guest's JWT access token using a valid refresh token. Validate the refresh token against records in ecommerce_mall_guest_sessions table, check expiration status, and verify the token matches the stored refresh token. Upon validation success, generate new access and refresh token pairs. Invalidate old refresh token and store new refresh token in guest_sessions table. Update expiration timestamps in token payload. Return authorized response with new tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallGuest.IRefresh,
  ): Promise<IEcommerceMallGuest.IAuthorized> {
    try {
      return await postEcommerceMallAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
