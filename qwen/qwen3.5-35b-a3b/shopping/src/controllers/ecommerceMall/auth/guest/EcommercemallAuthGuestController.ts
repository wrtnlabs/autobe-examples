import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallGuest } from "../../../../api/structures/IEcommerceMallGuest";
import { postEcommerceMallAuthGuestJoin } from "../../../../providers/postEcommerceMallAuthGuestJoin";
import { postEcommerceMallAuthGuestRefresh } from "../../../../providers/postEcommerceMallAuthGuestRefresh";

@Controller("/ecommerceMall/auth/guest")
export class EcommercemallAuthGuestController {
  /**
   * Register a new guest user or refresh existing guest session.
   *
   * Creates a guest account identified by device fingerprint and establishes a browsing session. The fingerprint uniquely identifies the user's browser/device combination without requiring personal information. Sessions include IP address, current page, and referrer for analytics and session tracking.
   *
   * Guests receive access and refresh tokens for authenticated browsing. The access token is short-lived for security, while the refresh token allows token renewal without re-registration. Sessions expire after 24 hours by default.
   *
   * This operation is required before unauthenticated users can browse the platform. Existing guests are identified by matching fingerprint, allowing session continuation across visits.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest registration and session initiation data
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification 1. Validate request body fields: fingerprint (required, string). 2. Check if guest with fingerprint exists in ecommerce_mall_guests. 3. If exists, update updated_at timestamp. 4. If new, create guest record with fingerprint, set created_at and updated_at. 5. Create guest session in ecommerce_mall_guest_sessions with: guest_id, ip (from request header), href (from request body), referrer (from request header if present), created_at, expired_at (set to now + 24 hours). 6. Generate JWT access token and refresh token. 7. Store session_id in response. 8. Return 201 for new guest, 200 for existing guest.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallGuest.IJoin,
  ): Promise<IEcommerceMallGuest.IAuthorized> {
    try {
      return await postEcommerceMallAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew guest authentication tokens without re-registration.
   *
   * Allows existing guests to obtain new access and refresh tokens using a valid refresh token. The refresh token is validated against the stored session to ensure it hasn't expired or been revoked. Upon successful validation, new tokens are issued with extended expiration.
   *
   * This operation maintains guest session continuity without requiring fingerprint re-submission or additional personal information. It enables guests to continue browsing across multiple visits within their 24-hour session window.
   *
   * Token renewal is required when access tokens expire (short-lived for security) while maintaining the underlying guest account and session record. Invalid or expired refresh tokens will fail validation and require a new join operation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh request with current refresh token
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification 1. Extract refresh token from request body. 2. Validate token format and decode payload. 3. Check if token is expired by comparing with expired_at stored in session. 4. Verify token hasn't been revoked (check deleted_at on session record). 5. If valid, generate new access token and refresh token with 24-hour expiration. 6. Update session record with new tokens and refresh the expired_at timestamp. 7. Return new tokens in IAuthorized response format.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallGuest.IRefresh,
  ): Promise<IEcommerceMallGuest.IAuthorized> {
    try {
      return await postEcommerceMallAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
