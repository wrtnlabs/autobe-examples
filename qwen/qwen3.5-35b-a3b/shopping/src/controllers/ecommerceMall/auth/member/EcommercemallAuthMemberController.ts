import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallMember } from "../../../../api/structures/IEcommerceMallMember";
import { postEcommerceMallAuthMemberJoin } from "../../../../providers/postEcommerceMallAuthMemberJoin";
import { postEcommerceMallAuthMemberLogin } from "../../../../providers/postEcommerceMallAuthMemberLogin";
import { postEcommerceMallAuthMemberRefresh } from "../../../../providers/postEcommerceMallAuthMemberRefresh";

@Controller("/ecommerceMall/auth/member")
export class EcommercemallAuthMemberController {
  /**
   * Register a new customer account on the e-commerce platform.
   *
   * Creates a new member account with email and password credentials. The account is created with email verification required before full activation. An email verification token is generated and sent to the provided email address. The account can authenticate immediately but certain features may be restricted until email verification is completed.
   *
   * The registration process validates email uniqueness against existing accounts in the database. Passwords are hashed using BCrypt with a work factor of 12 for security. After successful registration, JWT tokens are generated and a member session record is created in the ecommerce_mall_member_sessions table.
   *
   * Related operations: login (authenticate after registration), refresh (obtain new tokens), and the email verification flow handled by backend email service.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer registration data including email, password, and optional profile information.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Create new member account in
     *   ecommerce_mall_members table. Hash password with BCrypt before storage.
     *   Create initial email verification record in
     *   ecommerce_mall_member_email_verifications with status='pending'. Send
     *   verification email with token. Return IAuthorized containing
     *   access_token, refresh_token, and expired_at after successful
     *   registration and token generation. Validation: email must be unique,
     *   password must meet complexity requirements (min 8 chars, at least one
     *   uppercase, one lowercase, one digit), display_name optional,
     *   phone_number optional format E.164.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallMember.IJoin,
  ): Promise<IEcommerceMallMember.IAuthorized> {
    try {
      return await postEcommerceMallAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a member customer using email and password credentials.
   *
   * Validates the provided email and password against the stored credentials in the ecommerce_mall_members table. Upon successful authentication, generates JWT access and refresh tokens and creates a session record in the ecommerce_mall_member_sessions table to track the login session.
   *
   * The access token is valid for 1 hour and must be included in the Authorization header for authenticated API requests. The refresh token is valid for 7 days and can be used to obtain new access tokens without re-authenticating. Session metadata including IP address, page URL, and referrer are captured for security auditing and analytics.
   *
   * Related operations: refresh (obtain new tokens when access token expires), logout (end session by client-side token removal). Note: Logout is a client-side operation only - JWT tokens expire naturally and do not require server-side invalidation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials including email and password.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Validate email and password credentials against
     *   ecommerce_mall_members table. Find member record by email using
   *   @@unique([email]) index. Verify password_hash using BCrypt.compare. On
   *   success, create new session in ecommerce_mall_member_sessions with
   *   access_token, refresh_token, ip from request header, href and referrer
   *   from request headers. Update session expired_at to current time + 1
   *   hour for access token, + 7 days for refresh token. Return IAuthorized
   *   with tokens and expiration. On failure: 401 Unauthorized with error
   *   message. Edge cases: account deleted (deleted_at not null) should fail
   *   with account not active error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallMember.ILogin,
  ): Promise<IEcommerceMallMember.IAuthorized> {
    try {
      return await postEcommerceMallAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Obtain new JWT access and refresh tokens using a valid refresh token.
   *
   * Allows authenticated members to obtain fresh tokens without re-entering credentials. The refresh token is validated against the ecommerce_mall_member_sessions table to ensure it exists, has not expired, and belongs to an active session. Upon validation, new access and refresh tokens are generated and the session record is updated with the new token values.
   *
   * This token rotation mechanism enhances security by limiting the lifespan of access tokens while maintaining session continuity. The refresh token must be stored securely on the client and sent with each refresh request. Each refresh operation invalidates the old refresh token, preventing replay attacks.
   *
   * Related operations: login (initial authentication when no tokens exist), join (register new account). Access tokens should be used for all authenticated API requests by including them in the Authorization header.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token from previous authentication session.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Validate refresh token from request body against
     *   ecommerce_mall_member_sessions table using @@unique([access_token])
     *   index lookup (stored in refresh_token column). Check token expired_at >
     *   now. Find corresponding member record. Generate new access_token and
     *   refresh_token. Update session record with new tokens and new
     *   expired_at. Return IAuthorized with new tokens. On failure: 401
     *   Unauthorized. Edge cases: token not found (invalid/used/expired),
     *   session deleted (cascade delete on member deletion), multiple
     *   concurrent sessions (each has own refresh token).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallMember.IRefresh,
  ): Promise<IEcommerceMallMember.IAuthorized> {
    try {
      return await postEcommerceMallAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
