import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSeller } from "../../../../api/structures/IEcommerceMallSeller";
import { postEcommerceMallAuthSellerJoin } from "../../../../providers/postEcommerceMallAuthSellerJoin";
import { postEcommerceMallAuthSellerLogin } from "../../../../providers/postEcommerceMallAuthSellerLogin";
import { postEcommerceMallAuthSellerRefresh } from "../../../../providers/postEcommerceMallAuthSellerRefresh";

@Controller("/ecommerceMall/auth/seller")
export class EcommercemallAuthSellerController {
  /**
   * Register a new seller account on the ecommerce mall platform, enabling the user to begin the process of becoming an approved seller.
   *
   * This operation creates a new seller account in the ecommerce_mall_sellers table with the provided email address and password hash. The account is initially created with approvalStatus set to 'pending', indicating that administrator approval is required before the seller can begin listing products and conducting business. The approval workflow ensures marketplace quality control and seller verification.
   *
   * Upon successful registration, the system generates a JWT access token (valid for 15 minutes) and a refresh token (valid for 7 days) for immediate authenticated access to the seller dashboard and profile management features. Additionally, an email verification token is created in the ecommerce_mall_seller_email_verifications table with a 24-hour expiration, which must be validated before the seller account becomes fully active.
   *
   * Security considerations include unique email validation against existing sellers, password strength requirements (minimum 8 characters with complexity), and automatic ban/suspension flag initialization to false. The operation enforces data integrity by capturing the exact timestamp of account creation in the createdAt field.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration credentials including unique email address and secure password
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Service layer creates a new seller account by: 1) Validating email uniqueness against ecommerce_mall_sellers.email, 2) Validating email format per RFC 5322, 3) Hashing password using bcrypt with cost factor 12, 4) Inserting record into ecommerce_mall_sellers with approvalStatus='pending', isSuspended=false, isBanned=false, 5) Creating email verification token in ecommerce_mall_seller_email_verifications with 24-hour expiration, 6) Generating JWT access token (15-minute validity) and refresh token (7-day validity), 7) Returning token pair with seller profile summary. Business rules: email must be unique, password must meet minimum 8-character requirement with complexity, account starts in pending approval state requiring admin approval before selling privileges are granted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSeller.IJoin,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a seller account using email and password credentials, granting access to the seller dashboard and management features.
   *
   * This operation validates the seller's email address and password against the stored credentials in the ecommerce_mall_sellers table. The system checks that the account is not banned (isBanned=false) and not suspended (isSuspended=false) before proceeding with authentication. Importantly, the account must have approvalStatus set to 'approved' - sellers in pending or rejected states cannot authenticate until an administrator approves their application.
   *
   * Upon successful credential validation, the service layer generates a new access token (15-minute validity) and refresh token (7-day validity), rotates the refresh token for security (old token is invalidated), and records the session in the ecommerce_mall_seller_sessions table. The response includes the token pair along with the seller's profile summary including sellerId, email, shopName (from sellerProfile), and approvalStatus.
   *
   * Security considerations include constant-time password comparison to prevent timing attacks, automatic ban/suspension enforcement, and session tracking for audit purposes. The operation also enforces rate limiting to prevent brute force attacks against seller credentials.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login credentials including email and password
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Service layer validates seller login credentials by: 1) Looking up seller record in ecommerce_mall_sellers by email, 2) Checking if seller isBanned=false and isSuspended=false, 3) Verifying approvalStatus='approved' (pending accounts cannot login), 4) Comparing provided password against stored passwordHash using bcrypt verify, 5) On success, rotating refresh token and generating new access token, 6) Creating session record in ecommerce_mall_seller_sessions table, 7) Returning token pair with seller profile. Business rules: account must be approved by admin, banned or suspended accounts receive authentication failure, password comparison uses constant-time comparison to prevent timing attacks.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSeller.ILogin,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew an expired access token using a valid refresh token, maintaining the seller's authenticated session without requiring re-authentication.
   *
   * This operation enables continuous access to seller dashboard features by validating the refresh token stored in the ecommerce_mall_seller_sessions table. The service layer verifies that the refresh token has not expired (expiresAt timestamp in the future), belongs to an active seller account that is not banned (isBanned=false) and not suspended (isSuspended=false), and has not been used for rotation (ensuring single-use refresh tokens for security).
   *
   * Upon successful validation, the service generates a new access token with 15-minute validity for immediate API access and a new refresh token with 7-day validity. The old refresh token is invalidated to prevent replay attacks, maintaining token rotation security. The response includes both new tokens along with seller profile summary.
   *
   * Security considerations include refresh token rotation (preventing token theft exploitation), session expiration enforcement, and ban/suspension state checking to immediately revoke access for compromised or suspended accounts. The operation enables seamless seller experience without repeated credential entry while maintaining strong security posture through token lifecycle management.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for session renewal
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Service layer validates refresh token by: 1) Extracting refresh token from request body, 2) Looking up token in ecommerce_mall_seller_sessions table, 3) Verifying token has not expired (expiresAt field), 4) Validating seller exists and is not banned/suspended, 5) Generating new access token (15-minute validity), 6) Rotating refresh token (creating new entry in sessions table, invalidating old), 7) Returning new token pair. Business rules: refresh token must be valid and unused for rotation, banned or suspended sellers cannot refresh tokens, token rotation provides defense against token theft.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallSeller.IRefresh,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
