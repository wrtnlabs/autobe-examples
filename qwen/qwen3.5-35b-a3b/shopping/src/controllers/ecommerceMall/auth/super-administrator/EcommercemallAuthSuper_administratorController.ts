import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSuperAdministrator } from "../../../../api/structures/IEcommerceMallSuperAdministrator";
import { postEcommerceMallAuthSuperAdministratorJoin } from "../../../../providers/postEcommerceMallAuthSuperAdministratorJoin";
import { postEcommerceMallAuthSuperAdministratorLogin } from "../../../../providers/postEcommerceMallAuthSuperAdministratorLogin";
import { postEcommerceMallAuthSuperAdministratorRefresh } from "../../../../providers/postEcommerceMallAuthSuperAdministratorRefresh";

@Controller("/ecommerceMall/auth/super-administrator")
export class EcommercemallAuthSuper_administratorController {
  /**
   * Register a new super administrator account for platform oversight operations.
   *
   * Accepts email, display_name, and password to create a new super administrator account. The email is validated for uniqueness and format. The password is securely hashed before storage. Upon successful registration, JWT access and refresh tokens are issued for immediate authentication.
   *
   * This operation is typically used during initial platform setup when creating the first administrative accounts. Super administrators have the highest privilege level including administrator management, seller oversight, and platform-wide controls.
   *
   * Integration with session creation occurs after token issuance.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials for new super administrator account
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Create a new super administrator account by validating email uniqueness, hashing the password, and storing the account with display_name. Return JWT access and refresh tokens after successful registration. Generate IJoin request type with email, password, and display_name fields. Generate IAuthorized response type containing access_token, refresh_token, and superAdministrator summary.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSuperAdministrator.IJoin,
  ): Promise<IEcommerceMallSuperAdministrator.IAuthorized> {
    try {
      return await postEcommerceMallAuthSuperAdministratorJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate and login a super administrator account using email and password credentials.
   *
   * Validates the provided email and password against the stored credentials in the ecommerce_mall_super_administrators table. Upon successful authentication, creates a new session record with client IP, login page URL, and referrer for security auditing. JWT access and refresh tokens are issued for subsequent API access.
   *
   * Super administrators can maintain multiple concurrent sessions. Each session is tracked with creation timestamp, expiration time, and client context for security monitoring and session management.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials for super administrator authentication
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Authenticate a super administrator by validating email and password against stored credentials. Upon successful authentication, create a new session record with IP, href, and referrer. Issue JWT access and refresh tokens. Generate ILogin request type with email and password fields. Generate IAuthorized response type containing tokens and superAdministrator summary.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSuperAdministrator.ILogin,
  ): Promise<IEcommerceMallSuperAdministrator.IAuthorized> {
    try {
      return await postEcommerceMallAuthSuperAdministratorLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew authentication tokens using a valid refresh token.
   *
   * Accepts a refresh token and validates it against the ecommerce_mall_super_administrator_sessions table. If the token is valid and not expired, issues a new pair of access and refresh tokens. The previous tokens remain valid for their original expiration (not immediately invalidated) to allow smooth token rotation.
   *
   * This operation enables continuous platform access without requiring re-authentication. The refresh token has a longer lifespan than the access token, with access tokens requiring frequent renewal while refresh tokens persist across browser sessions.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for token renewal
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Validate the refresh token and issue a new pair of JWT access and refresh tokens. Check the session exists and is valid in ecommerce_mall_super_administrator_sessions. Generate IRefresh request type with refresh_token field. Generate IAuthorized response type containing new tokens and superAdministrator summary.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallSuperAdministrator.IRefresh,
  ): Promise<IEcommerceMallSuperAdministrator.IAuthorized> {
    try {
      return await postEcommerceMallAuthSuperAdministratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
