import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallAdmin } from "../../../../api/structures/IEcommerceMallAdmin";
import { postEcommerceMallAuthAdminJoin } from "../../../../providers/postEcommerceMallAuthAdminJoin";
import { postEcommerceMallAuthAdminLogin } from "../../../../providers/postEcommerceMallAuthAdminLogin";
import { postEcommerceMallAuthAdminRefresh } from "../../../../providers/postEcommerceMallAuthAdminRefresh";

@Controller("/ecommerceMall/auth/admin")
export class EcommercemallAuthAdminController {
  /**
   * This endpoint creates a new administrator account in the ecommerce mall system. Admin accounts represent system administrators with elevated privileges who can manage sellers, categories, products, orders, and user accounts. The super admin grade has additional permissions for managing other administrators.
   *
   * The registration process requires that an admin request has already been submitted through the ecommerce_mall_admin_request_requests table and approved by a super administrator. The service validates the request status before allowing account creation. This ensures that only authorized individuals can become administrators.
   *
   * The admin's email address must be unique across all administrators. The password must be securely hashed using a strong hashing algorithm before storage in the ecommerce_mall_admins table. After successful account creation, JWT tokens are generated for authentication: an access token for API requests and a refresh token for obtaining new access tokens when the current one expires.
   *
   * Related operations: The admin login operation (POST /auth/admin/login) validates credentials for existing accounts. The token refresh operation (POST /auth/admin/refresh) renews expired access tokens.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Admin account registration credentials
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new admin account from a submitted admin request. The service layer validates the admin request status (approved) from ecommerce_mall_admin_request_requests, then creates the admin record in ecommerce_mall_admins with the provided email and passwordHash. The email must be unique in the admin table. After successful creation, generate JWT access and refresh tokens, store the refresh token in ecommerce_mall_admin_sessions, and return the authorized response containing both tokens. Handle unique email constraint violations and invalid admin request status errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallAdmin.IJoin,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint validates administrator credentials and issues JWT authentication tokens. The admin provides their email address and password, which are validated against the stored credentials in the ecommerce_mall_admins table.
   *
   * The service performs the following authentication workflow: (1) Look up the admin record by email address, (2) Verify the email exists and is associated with an admin account, (3) Hash the provided password and compare it against the stored passwordHash field, (4) Check that the admin is not banned or suspended, and (5) Generate JWT tokens if all validations pass.
   *
   * Upon successful authentication, the service creates a new session record in the ecommerce_mall_admin_sessions table storing the refresh token. The access token is returned for use in subsequent API requests, while the refresh token can be used to obtain new access tokens when the current one expires. Tokens follow the JWT standard with configurable expiration times.
   *
   * Related operations: The registration endpoint (POST /auth/admin/join) creates new admin accounts. The token refresh endpoint (POST /auth/admin/refresh) renews expired access tokens without re-authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Admin authentication credentials
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Authenticate an administrator using email and password credentials. The service looks up the admin record in ecommerce_mall_admins by email, validates the provided passwordHash against the stored hash, and checks the admin's active status. Upon successful authentication, generate JWT access and refresh tokens, store the refresh token in ecommerce_mall_admin_sessions, and return the authorized response. Handle errors for non-existent admin accounts, incorrect passwords, and banned administrators.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallAdmin.ILogin,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint provides token refresh functionality for administrators whose access tokens have expired. Instead of requiring re-authentication with email and password, administrators can use their refresh token to obtain new access tokens.
   *
   * The refresh token workflow operates as follows: (1) Extract the refresh token from the request body, (2) Look up the corresponding session in ecommerce_mall_admin_sessions, (3) Validate that the token has not expired using its stored expiration timestamp, (4) Verify the admin account is still active and not banned, (5) Generate new access and refresh tokens, (6) Store the new refresh token in the sessions table, and (7) Return the new tokens to the client.
   *
   * The service may implement refresh token rotation as a security best practice: after a successful refresh, the old refresh token is invalidated and a new one is issued. This prevents replay attacks if a refresh token is compromised. The access token typically has a shorter lifetime (e.g., 15 minutes) while the refresh token has a longer lifetime (e.g., 7 days).
   *
   * Related operations: The login endpoint (POST /auth/admin/login) is used for initial authentication when no tokens are available. The join endpoint (POST /auth/admin/join) creates new admin accounts.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access tokens
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Renew an expired access token using a valid refresh token. The service validates the refresh token from the request body against stored tokens in ecommerce_mall_admin_sessions, verifies the token has not expired, and confirms the admin account is still active. Upon successful validation, generate new JWT access and refresh tokens, optionally rotate the refresh token by storing the new one in ecommerce_mall_admin_sessions, and return the authorized response with the new tokens. Handle errors for invalid, expired, or revoked refresh tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallAdmin.IRefresh,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
