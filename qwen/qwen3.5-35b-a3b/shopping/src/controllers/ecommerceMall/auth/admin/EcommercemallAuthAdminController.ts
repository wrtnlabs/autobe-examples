import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallAdmin } from "../../../../api/structures/IEcommerceMallAdmin";
import { postEcommerceMallAuthAdminJoin } from "../../../../providers/postEcommerceMallAuthAdminJoin";
import { postEcommerceMallAuthAdminLogin } from "../../../../providers/postEcommerceMallAuthAdminLogin";
import { postEcommerceMallAuthAdminRefresh } from "../../../../providers/postEcommerceMallAuthAdminRefresh";

@Controller("/ecommerceMall/auth/admin")
export class EcommercemallAuthAdminController {
  /**
   * This endpoint creates a new administrator account in the platform. Admin accounts have elevated privileges for managing sellers, categories, products, orders, and user accounts across the entire ecommerce mall system.
   *
   * The operation accepts email and password in the request body, validates that the email does not already exist in the ecommerce_mall_admins table, hashes the password using bcrypt before storing in the password_hash column, and inserts a new admin record with active status.
   *
   * Upon successful account creation, the system generates JWT access and refresh tokens stored in ecommerce_mall_admin_sessions table and returns them in the response. A confirmation notification may be sent using the ecommerce_mall_notification_of_admins relationship table.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration data for the new admin account including email and password
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new admin account by inserting record into ecommerce_mall_admins table with email, password_hash, and initial credentials. Validate email uniqueness against existing records in ecommerce_mall_admins. Hash password using bcrypt before storing in password_hash column. Set initial account status to active. Return JWT tokens after successful creation with access_token and refresh_token from ecommerce_mall_admin_sessions. Send confirmation notification using ecommerce_mall_notification_of_admins relationship.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallAdmin.IJoin,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint authenticates admin users by validating their email and password credentials against the stored credentials in the ecommerce_mall_admins table.
   *
   * The operation accepts email and password in the request body, retrieves the corresponding admin record from ecommerce_mall_admins, verifies the password_hash matches the provided password using bcrypt comparison, and upon successful validation generates new JWT access and refresh tokens. These tokens are stored in the ecommerce_mall_admin_sessions table with expiration timestamps.
   *
   * The response includes the access_token for immediate API access and refresh_token for obtaining new access tokens after expiration. If the credentials are invalid or the admin account does not exist, the endpoint returns a 401 unauthorized error.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials including admin email and password
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate email and password credentials against ecommerce_mall_admins table. If credentials match, generate new JWT access token and refresh token pair. Store tokens in ecommerce_mall_admin_sessions table with appropriate expiration timestamps. Return tokens in response with access_token and refresh_token fields. If credentials fail validation, return 401 unauthorized error with appropriate error message.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallAdmin.ILogin,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint renews the admin session by validating and exchanging the refresh token for new JWT access and refresh tokens.
   *
   * The operation accepts the refresh token in the request body, looks up the token in the ecommerce_mall_admin_sessions table to verify it exists and has not expired, and upon successful validation generates a new pair of access and refresh tokens. The new tokens are stored in the ecommerce_mall_admin_sessions table, replacing the old tokens.
   *
   * This operation allows admins to maintain continuous authenticated sessions without requiring re-login, extending access beyond the short-lived access token expiration period. If the refresh token is invalid, expired, or has been revoked, the endpoint returns a 401 unauthorized error and the admin must login again.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access credentials
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate the provided refresh_token against records in ecommerce_mall_admin_sessions table. If valid and not expired, generate new access token and refresh token pair. Update or insert new tokens into ecommerce_mall_admin_sessions table. Return new tokens in response. If refresh token is invalid, expired, or revoked, return 401 unauthorized error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallAdmin.IRefresh,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
