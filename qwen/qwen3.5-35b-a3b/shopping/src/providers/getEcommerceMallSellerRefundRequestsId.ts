export async function getEcommerceMallSellerRefundRequestsId(props: {
  seller: SellerPayload;
  id: string & tags.Format<"uuid">;
}): Promise<IEcommerceMallRefundRequest> {
  const refundRequest =
    await MyGlobal.prisma.ecommerce_mall_refund_requests.findFirstOrThrow({
      ...EcommerceMallRefundRequestTransformer.select(),
      where: {
        id: props.id,
        deleted_at: null,
      },
    });
  const orderItem =
    await MyGlobal.prisma.ecommerce_mall_order_items.findFirstOrThrow({
      where: { id: refundRequest.order_item_id },
      select: {
        id: true,
        seller_id: true,
        ecommerce_mall_product_variant_id: true,
      },
    });
  if (orderItem.seller_id !== props.seller.id) {
    throw new HttpException("Forbidden", 403);
  }
  return await EcommerceMallRefundRequestTransformer.transform(refundRequest);
}


