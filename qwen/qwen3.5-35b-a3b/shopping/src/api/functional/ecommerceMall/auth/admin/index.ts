/**
 * Creates a new administrator account in the ecommerce mall system. This operation allows users to register as administrators by providing their email address and password credentials. The system validates that the email is unique and not already registered, and stores the password in hashed format for security.
 *
 * The registration process creates an admin record in the ecommerce_mall_admins table with the provided credentials. The admin account is initially created with isBanned set to false, indicating an active account status. Email verification is initiated by creating a verification token in the ecommerce_mall_admin_email_verifications table.
 *
 * Upon successful registration, the system generates JWT access and refresh tokens and stores the refresh token in the ecommerce_mall_admin_sessions table for session management. The returned authorized response contains these tokens along with the admin account information, enabling immediate authentication without requiring additional login.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Administrator registration credentials including email and password
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Service layer creates new admin account by:
 * 1. Validating email format and uniqueness against ecommerce_mall_admins.email
 * 2. Validating password complexity requirements
 * 3. Hashing password using bcrypt
 * 4. Creating new record in ecommerce_mall_admins table with email, passwordHash, isBanned=false
 * 5. Generating JWT access token and refresh token
 * 6. Storing refresh token in ecommerce_mall_admin_sessions
 * 7. Creating email verification record in ecommerce_mall_admin_email_verifications
 * 8. Returning authorized response with tokens and admin info
 * @path /ecommerceMall/auth/admin/join
 * @accessor api.functional.ecommerceMall.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
