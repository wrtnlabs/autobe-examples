/**
 * Register a new super administrator account for platform oversight operations.
 *
 * Accepts email, display_name, and password to create a new super administrator account. The email is validated for uniqueness and format. The password is securely hashed before storage. Upon successful registration, JWT access and refresh tokens are issued for immediate authentication.
 *
 * This operation is typically used during initial platform setup when creating the first administrative accounts. Super administrators have the highest privilege level including administrator management, seller oversight, and platform-wide controls.
 *
 * Integration with session creation occurs after token issuance.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration credentials for new super administrator account
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor superAdministrator
 * @x-autobe-specification Create a new super administrator account by
 *   validating email uniqueness, hashing the password, and storing the account
 *   with display_name. Return JWT access and refresh tokens after successful
 *   registration. Generate IJoin request type with email, password, and
 *   display_name fields. Generate IAuthorized response type containing
 *   access_token, refresh_token, and superAdministrator summary.
 * @path /ecommerceMall/auth/super-administrator/join
 * @accessor api.functional.ecommerceMall.auth.super_administrator.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
