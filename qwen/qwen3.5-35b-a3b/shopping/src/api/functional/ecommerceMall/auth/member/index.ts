/**
 * Register a new customer account on the e-commerce platform.
 *
 * Creates a new member account with email and password credentials. The account is created with email verification required before full activation. An email verification token is generated and sent to the provided email address. The account can authenticate immediately but certain features may be restricted until email verification is completed.
 *
 * The registration process validates email uniqueness against existing accounts in the database. Passwords are hashed using BCrypt with a work factor of 12 for security. After successful registration, JWT tokens are generated and a member session record is created in the ecommerce_mall_member_sessions table.
 *
 * Related operations: login (authenticate after registration), refresh (obtain new tokens), and the email verification flow handled by backend email service.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Customer registration data including email, password, and optional profile information.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Create new member account in ecommerce_mall_members
 *   table. Hash password with BCrypt before storage. Create initial email
 *   verification record in ecommerce_mall_member_email_verifications with
 *   status='pending'. Send verification email with token. Return IAuthorized
 *   containing access_token, refresh_token, and expired_at after successful
 *   registration and token generation. Validation: email must be unique,
 *   password must meet complexity requirements (min 8 chars, at least one
 *   uppercase, one lowercase, one digit), display_name optional, phone_number
 *   optional format E.164.
 * @path /ecommerceMall/auth/member/join
 * @accessor api.functional.ecommerceMall.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
