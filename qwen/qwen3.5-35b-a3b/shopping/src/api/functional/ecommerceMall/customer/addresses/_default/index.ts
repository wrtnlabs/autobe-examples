/**
 * Set a customer's shipping address as their default address for faster checkout.
 *
 * This operation allows authenticated customers to designate one of their saved shipping addresses as their default. The default address is automatically pre-selected during checkout and simplifies the order placement process.
 *
 * When an address is set as default, the system automatically unsets any previously designated default address for the same customer. This ensures only one default address exists per customer at any time, as enforced by the database's unique constraint on the (customer, is_default) combination in the ecommerce_mall_addresses table.
 *
 * The operation verifies that the address belongs to the authenticated customer before making the update. Attempts to set another customer's address as default will be rejected with an unauthorized error.
 *
 * The updated address is returned with the new is_default status and all other address fields unchanged. The address remains active and continues to be usable for order placement.
 *
 * **Note**: This operation does not require a request body. The action is performed directly on the address specified in the path parameter.
 *
 * @param props.connection
 * @param props.addressId The unique identifier of the shipping address to set as default.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification 1. Extract addressId from path parameters and validate as UUID format.
 * 2. Authenticate customer via JWT session token.
 * 3. Query ecommerce_mall_addresses for address matching addressId AND ecommerce_mall_customer_id equals authenticated customer ID.
 * 4. If address not found or does not belong to customer, return 404 Not Found or 403 Forbidden.
 * 5. If address.deleted_at is not null, return 400 Bad Request (cannot set deleted address as default).
 * 6. Update address is_default to true.
 * 7. Query all addresses for this customer where is_default=true AND id != addressId.
 * 8. Update all those addresses to is_default=false (cascade unset previous default).
 * 9. Save changes with updated_at timestamp.
 * 10. Return updated address object with new is_default=true.
 * @path /ecommerceMall/customer/addresses/:addressId/default
 * @accessor api.functional.ecommerceMall.customer.addresses._default.setDefault
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function setDefault(
  connection: IConnection,
  props: setDefault.Props,
): Promise<setDefault.Response> {
  return true === connection.simulate
    ? setDefault.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...setDefault.METADATA,
          path: setDefault.path(props),
          status: null,
        },
      );
}
