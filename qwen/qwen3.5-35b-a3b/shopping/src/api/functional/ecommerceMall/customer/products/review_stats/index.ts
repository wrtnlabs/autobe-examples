/**
 * Retrieve aggregated review statistics for a specific product with filtering options.
 *
 * This operation calculates and returns comprehensive statistics about all active reviews for the specified product, including the average rating, total review count, rating distribution across 1-5 stars, and verified purchase metrics.
 *
 * **Data Source**:
 *
 * Retrieves reviews from the ecommerce_mall_reviews table, filtering by the specified product ID and excluding soft-deleted reviews (where deleted_at is null). The endpoint supports multiple filter parameters to narrow down which reviews contribute to the statistics.
 *
 * **Statistics Calculated**:
 *
 * - Average rating across all matching reviews (weighted mean of 1-5 star ratings)
 * - Total review count from all matching reviews
 * - Rating distribution showing how many reviews received each star rating (1-star through 5-star)
 * - Verified purchase count (reviews where is_verified_purchase is true)
 * - Unverified purchase count (reviews from non-verified purchases)
 * - Most recent review date and oldest review date in the set
 *
 * **Filtering Options**:
 *
 * The operation supports optional filtering by verified purchase status, rating range, review date range, and other criteria. If no filters are specified, all active reviews for the product are included in the statistics.
 *
 * @param props.connection
 * @param props.productId The unique identifier of the product for which to retrieve review statistics.
 * @param props.body Optional filter parameters to narrow which reviews contribute to the statistics.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query the ecommerce_mall_reviews table for reviews matching the specified product_id with active status (deleted_at IS NULL).
 *
 * Apply filters from the request body:
 * - is_verified_purchase: filter to only verified or only unverified reviews
 * - rating_min, rating_max: filter reviews by rating range (1-5)
 * - created_at_after, created_at_before: filter reviews by creation date range
 *
 * Calculate aggregation statistics:
 * - AVG(rating) for average rating
 * - COUNT(*) for total count
 * - GROUP BY rating with COUNT for distribution
 * - MIN(created_at), MAX(created_at) for date range
 *
 * Handle edge cases:
 * - Return null/empty stats if no matching reviews exist
 * - Calculate average with NULL-safe arithmetic to avoid division by zero
 * - Ensure rating distribution always includes all 5 rating levels even if count is 0
 *
 * Return response body containing IEcommerceMallProductReviewStatsSummary.
 * @path /ecommerceMall/customer/products/:productId/review-stats
 * @accessor api.functional.ecommerceMall.customer.products.review_stats.getReviewStats
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function getReviewStats(
  connection: IConnection,
  props: getReviewStats.Props,
): Promise<getReviewStats.Response> {
  return true === connection.simulate
    ? getReviewStats.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...getReviewStats.METADATA,
          path: getReviewStats.path(props),
          status: null,
        },
        props.body,
      );
}
