/**
 * Retrieves all product images for a specific product, ordered by display priority.
 *
 * Returns a list of all active product images associated with the specified product. Images are sorted by display_order in ascending order, with the image having display_order = 1 appearing first as the main/thumbnail image. Each image record includes its unique identifier, image URL, display order position, and creation timestamp.
 *
 * Only active images (not soft-deleted) are returned. Soft-deleted images are identified by a non-null deleted_at timestamp and are excluded from results.
 *
 * @param props.connection
 * @param props.productId The unique identifier of the product to retrieve images for.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query ecommerce_mall_product_images table where product_id matches the path parameter and deleted_at IS NULL (active images only).
 *
 * Sort results by display_order ascending, then by id ascending for consistent ordering.
 *
 * Return only summary fields: id, image_url, display_order, created_at.
 *
 * Validate that the productId is a valid UUID format.
 *
 * Return 404 Not Found if no images exist for the specified product or if the product does not exist.
 *
 * Note: The product itself must exist for this endpoint to return results. If the product has been deleted, all associated images will also have been cascade-deleted per the database schema constraint.
 * @path /ecommerceMall/products/:productId/images
 * @accessor api.functional.ecommerceMall.products.images.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * The unique identifier of the product to retrieve images for.
     */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IEcommerceMallProductImage.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/products/:productId/images",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/products/${encodeURIComponent(props.productId ?? "null")}/images`;
  export const random = (): IEcommerceMallProductImage.ISummary =>
    typia.random<IEcommerceMallProductImage.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
