import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IEcommerceMallProductReviewStat } from "../../../../structures/IEcommerceMallProductReviewStat";

/**
 * Retrieve pre-calculated review statistics for a specific product including average rating, total review count, and rating distribution.
 *
 * Returns aggregated metrics for the product from the review statistics cache, which is automatically updated when reviews are created, modified, or deleted. The average rating is rounded to 2 decimal places (range: 0.0 to 5.0). All rating count fields show the distribution of 1-5 star ratings from non-deleted reviews.
 *
 * @param props.connection
 * @param props.productId UUID identifier of the product whose statistics are being requested.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query ecommerce_mall_product_review_stats table by product_id to retrieve the stats record.
 *
 * 1. Validate productId is a valid UUID format
 * 2. Query for stats record where ecommerce_mall_product_id = productId
 * 3. If no stats record exists (product has no reviews), return 404 Not Found with error message
 * 4. Return the complete stats object including:
 *    - id: stats record UUID
 *    - product_id: referenced product UUID
 *    - average_rating: null or float (0.0-5.0, 2 decimal places)
 *    - review_count: integer (0 or positive)
 *    - rating_1_count through rating_5_count: integer distribution
 *    - created_at: when stats were first created
 *    - updated_at: last stats modification time
 *
 * Handle edge cases:
 * - Product with no reviews: stats record may not exist yet (no reviews submitted), return 404
 * - Product with all reviews deleted: stats record exists with review_count=0, average_rating=null, all rating counts=0
 * - Deleted product: stats still accessible (preserved for historical reference)
 *
 * Return 404 if stats record not found. No authorization required for reading public product statistics.
 * @path /ecommerceMall/products/:productId/stats
 * @accessor api.functional.ecommerceMall.products.stats.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * UUID identifier of the product whose statistics are being requested.
     */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IEcommerceMallProductReviewStat;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/products/:productId/stats",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/products/${encodeURIComponent(props.productId ?? "null")}/stats`;
  export const random = (): IEcommerceMallProductReviewStat =>
    typia.random<IEcommerceMallProductReviewStat>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
