/**
 * Retrieve a filtered and paginated list of customer reviews for a specific product.
 *
 * This operation returns all active (non-deleted) reviews for the specified product, sorted by newest first. Each review includes the customer's rating (1-5 stars), optional title, review text, verification status, and author information.
 *
 * Supports advanced filtering by rating range and verified purchase status. Results are paginated using cursor-based pagination for efficient handling of large review sets. The operation excludes soft-deleted reviews to maintain data integrity.
 *
 * Customers can view reviews for any product on the platform. Reviews are displayed on product detail pages to help shoppers make informed purchasing decisions based on customer feedback.
 *
 * @param props.connection
 * @param props.productId Product ID to fetch reviews for (global scope)
 * @param props.body Search criteria and pagination parameters for filtering product reviews
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query ecommerce_mall_reviews table filtered by productId and deleted_at IS NULL.
 * Apply filters: rating range, is_verified_purchase status.
 * Sort by created_at DESC (newest first) by default, support custom sorting.
 * Join with ecommerce_mall_customers for author name display.
 * Exclude soft-deleted reviews (deleted_at IS NULL).
 * Implement cursor-based pagination with created_at as cursor for consistent results.
 * Calculate average rating from non-deleted reviews for product display.
 * Return paginated results with total count for frontend pagination UI.
 * @path /ecommerceMall/products/:productId/reviews
 * @accessor api.functional.ecommerceMall.products.reviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Product ID to fetch reviews for (global scope)
     */
    productId: string & tags.Format<"uuid">;

    /**
     * Search criteria and pagination parameters for filtering product reviews
     */
    body: IEcommerceMallReview.IRequest;
  };
  export type Body = IEcommerceMallReview.IRequest;
  export type Response = IPageIEcommerceMallReview.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerceMall/products/:productId/reviews",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/ecommerceMall/products/${encodeURIComponent(props.productId ?? "null")}/reviews`;
  export const random = (): IPageIEcommerceMallReview.ISummary =>
    typia.random<IPageIEcommerceMallReview.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
