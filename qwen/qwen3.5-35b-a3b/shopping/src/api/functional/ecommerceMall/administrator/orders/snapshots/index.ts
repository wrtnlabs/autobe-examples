/**
 * Retrieve paginated list of order snapshots for a specific order.
 *
 * Order snapshots capture denormalized order state at point-in-time, including customer name, shipping address details, item count, subtotal, shipping fee, and total amount. These snapshots preserve the order information as it existed at snapshot creation time, even if related customer or address data changes later.
 *
 * Relevant parties (order owner, seller, administrators) can view snapshots for dispute resolution and audit purposes. Snapshots are immutable and cannot be deleted.
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the order. The snapshots returned are all snapshots associated with this order.
 * @param props.body Pagination and optional date range filters for order snapshot search.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor administrator
 * @x-autobe-specification Query ecommerce_mall_order_snapshots table filtered by ecommerce_mall_order_id.
 *
 * Apply cursor-based pagination for efficient large result set handling.
 *
 * Optional filtering:
 * - order_date_start: Filter snapshots on or after this date
 * - order_date_end: Filter snapshots on or before this date
 *
 * Sort by order_date descending (newest first) by default.
 *
 * Permissions:
 * - Order owner (member): Can view their own order snapshots
 * - Seller: Can view snapshots for orders containing their products
 * - Administrator: Can view any order snapshots
 *
 * Return snapshot summary with key fields:
 * - id: Snapshot UUID
 * - order_number: Human-readable order number
 * - order_date: Snapshot creation date
 * - customer_name: Customer name at snapshot time
 * - customer_phone: Customer phone at snapshot time
 * - shipping_address: Denormalized shipping address
 * - item_count: Number of order items
 * - subtotal: Subtotal before shipping
 * - shipping_fee: Shipping cost
 * - total_amount: Grand total
 * - order_status: Overall order status at snapshot time
 *
 * Do NOT include soft_delete fields (deleted_at) in response - snapshots are immutable and cannot be deleted.
 * @path /ecommerceMall/administrator/orders/:orderId/snapshots
 * @accessor api.functional.ecommerceMall.administrator.orders.snapshots.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
