/**
 * Retrieve comprehensive review analytics for a specific product.
 *
 * This operation calculates and returns aggregated review statistics for the specified product, including the average star rating (rounded to one decimal place), total number of active reviews, and the distribution of ratings across all five star levels (5-star through 1-star).
 *
 * The operation includes a preview of recent active reviews, displaying up to 10 reviews sorted by newest first. Each review preview contains the customer's display name, star rating, text content (if provided), and creation timestamp.
 *
 * Only active (non-deleted) reviews are included in all calculations and listings. Products with no reviews display an average rating of null and zero review counts.
 *
 * This operation is accessible to all authenticated users (customers and sellers) for browsing product information. Administrators can also access this endpoint for oversight purposes.
 *
 * @param props.connection
 * @param props.productId Product ID to retrieve review analytics for
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification 1. Validate that product_id exists in ecommerce_mall_products table and is active (is_active=true)
 * 2. Query ecommerce_mall_reviews table for all reviews where:
 *    - product_id matches the path parameter productId
 *    - deleted_at is NULL (active reviews only)
 * 3. Calculate aggregate statistics:
 *    - average_rating: SUM(rating) / COUNT(*), rounded to 1 decimal place, or null if no reviews
 *    - total_count: COUNT(*) of active reviews
 *    - rating_distribution: GROUP BY rating with COUNT for ratings 1-5
 * 4. Query recent reviews (limit 10):
 *    - ORDER BY created_at DESC
 *    - SELECT: id, customer.display_name, rating, text_content, created_at
 * 5. Handle edge cases:
 *    - If product not found, return 404 Not Found
 *    - If product has no reviews, return null average_rating and empty reviews array
 *    - If product is inactive, return 404 Not Found
 * 6. Join with ecommerce_mall_customers to get customer display names for review previews
 * 7. Ensure rating calculations exclude deleted reviews from all computations
 * @path /ecommerceMall/admin/reviews/analytics/:productId
 * @accessor api.functional.ecommerceMall.admin.reviews.analytics.getAnalytics
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function getAnalytics(
  connection: IConnection,
  props: getAnalytics.Props,
): Promise<getAnalytics.Response> {
  return true === connection.simulate
    ? getAnalytics.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...getAnalytics.METADATA,
          path: getAnalytics.path(props),
          status: null,
        },
      );
}
export namespace getAnalytics {
  export type Props = {
    /**
     * Product ID to retrieve review analytics for
     */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IReviewAnalyticsResponse;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/admin/reviews/analytics/:productId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/admin/reviews/analytics/${encodeURIComponent(props.productId ?? "null")}`;
  export const random = (): IReviewAnalyticsResponse =>
    typia.random<IReviewAnalyticsResponse>();
  export const simulate = (
    connection: IConnection,
    props: getAnalytics.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: getAnalytics.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
