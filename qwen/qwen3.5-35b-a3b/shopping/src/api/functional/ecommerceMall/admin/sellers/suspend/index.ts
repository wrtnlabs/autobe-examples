import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";

import { IEcommerceMallSeller } from "../../../../../structures/IEcommerceMallSeller";

/**
 * Suspend a seller account, removing their selling privileges while preserving historical order data.
 *
 * This operation sets the seller's is_suspended flag to true, which immediately hides all the seller's products from search results and category listings. The suspension prevents the seller from creating new products or editing existing ones, but allows them to continue processing existing orders including shipping items and responding to cancellation and refund requests.
 *
 * The system creates an immutable snapshot recording the suspension action including the seller's shop name, the administrator who performed the action, the reason for suspension, and the timestamp. An email notification is sent to the seller informing them of the suspension status and reason.
 *
 * A suspended seller account remains in the system indefinitely until manually unsuspended by an administrator. The suspension does not expire automatically and requires explicit administrative intervention to reverse.
 *
 * Only administrators have authorization to perform this operation. Attempting to suspend a seller without proper admin credentials will result in an access denied error.
 *
 * @param props.connection
 * @param props.sellerId UUID of the seller account to suspend
 * @param props.body Suspension request data including optional reason for suspension
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification 1. Validate seller exists and is not already suspended (return 400 if already suspended)
 * 2. Set is_suspended field to true in ecommerce_mall_sellers table
 * 3. Update updated_at timestamp to current server time
 * 4. Hide products from search and category listings by setting product visibility flags
 * 5. Disable seller's product creation and editing capabilities
 * 6. Create immutable snapshot in ecommerce_mall_snapshot_audits table with:
 *    - recordType: 'Seller'
 *    - recordId: sellerId
 *    - changes: suspension action
 *    - oldValues: {is_suspended: false}
 *    - newValues: {is_suspended: true}
 *    - changedAt: current timestamp
 *    - changedBy: admin user ID
 * 7. Send email notification to seller with suspension details and reason
 * 8. Return updated seller entity with is_suspended set to true
 * @path /ecommerceMall/admin/sellers/:sellerId/suspend
 * @accessor api.functional.ecommerceMall.admin.sellers.suspend.suspendSeller
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function suspendSeller(
  connection: IConnection,
  props: suspendSeller.Props,
): Promise<suspendSeller.Response> {
  return true === connection.simulate
    ? suspendSeller.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...suspendSeller.METADATA,
          path: suspendSeller.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace suspendSeller {
  export type Props = {
    /**
     * UUID of the seller account to suspend
     */
    sellerId: string & tags.Format<"uuid">;

    /**
     * Suspension request data including optional reason for suspension
     */
    body: IEcommerceMallSeller.ISuspend;
  };
  export type Body = IEcommerceMallSeller.ISuspend;
  export type Response = IEcommerceMallSeller;

  export const METADATA = {
    method: "POST",
    path: "/ecommerceMall/admin/sellers/:sellerId/suspend",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/ecommerceMall/admin/sellers/${encodeURIComponent(props.sellerId ?? "null")}/suspend`;
  export const random = (): IEcommerceMallSeller =>
    typia.random<IEcommerceMallSeller>();
  export const simulate = (
    connection: IConnection,
    props: suspendSeller.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: suspendSeller.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sellerId")(() => typia.assert(props.sellerId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
