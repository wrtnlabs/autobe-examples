import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IPageIEcommerceMallReviewSnapshot } from "../../../../structures/IPageIEcommerceMallReviewSnapshot";

/**
 * Retrieve the complete audit history of a product review, showing all versions of the review from creation through any edits or deletion.
 *
 * This endpoint returns a paginated list of review snapshots, each capturing the review's state at a specific point in time including the star rating, text content, and timestamp. Snapshots are preserved when reviews are edited or deleted, providing a complete historical record for dispute resolution and audit purposes.
 *
 * Only the review author and platform administrators can access this endpoint. Customers can only view snapshots of their own reviews, while administrators have full visibility into all review snapshots across the platform.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the review whose snapshot history to retrieve. The review must exist in the system.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query ecommerce_mall_review_snapshots table for all snapshots belonging to the specified reviewId.
 * Filter by reviewId path parameter only (GET method cannot have request body).
 * Sort results by version ascending (chronological order) by default.
 * Apply pagination with limit and offset parameters passed as query parameters (handled by framework).
 * Filter out soft-deleted snapshots (where deleted_at is not null).
 * Join with ecommerce_mall_members to include reviewer display name if available.
 * Return paginated response with snapshot summaries.
 * Verify authorization: require review author identity or administrator role.
 * Handle case where reviewId does not exist (return 404 Not Found).
 * Handle case where review has no snapshots (return empty paginated result).
 * @path /ecommerceMall/reviews/:reviewId/snapshots
 * @accessor api.functional.ecommerceMall.reviews.snapshots.retrieveSnapshots
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function retrieveSnapshots(
  connection: IConnection,
  props: retrieveSnapshots.Props,
): Promise<retrieveSnapshots.Response> {
  return true === connection.simulate
    ? retrieveSnapshots.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...retrieveSnapshots.METADATA,
          path: retrieveSnapshots.path(props),
          status: null,
        },
      );
}
export namespace retrieveSnapshots {
  export type Props = {
    /**
     * Unique identifier of the review whose snapshot history to retrieve. The review must exist in the system.
     */
    reviewId: string & tags.Format<"uuid">;
  };
  export type Response = IPageIEcommerceMallReviewSnapshot.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/reviews/:reviewId/snapshots",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/reviews/${encodeURIComponent(props.reviewId ?? "null")}/snapshots`;
  export const random = (): IPageIEcommerceMallReviewSnapshot.ISummary =>
    typia.random<IPageIEcommerceMallReviewSnapshot.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: retrieveSnapshots.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: retrieveSnapshots.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
