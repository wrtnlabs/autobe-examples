/**
 * Exports inventory history records for a product variant as a downloadable CSV file.
 *
 * This operation enables sellers to download a comprehensive export of all inventory transactions for a specific variant, including quantity changes, reasons, timestamps, and cumulative stock levels. The export is useful for auditing, accounting, and inventory reconciliation purposes.
 *
 * The seller must own the variant (the variant's product must belong to them) to export its inventory history. The system validates ownership before generating the export.
 *
 * The exported CSV file includes all inventory records with fields: timestamp, quantity_change, reason, cumulative_stock_level, and variant_id. Records are sorted by timestamp (newest first) for chronological reference.
 *
 * The export operation is read-only and does not modify any inventory records. Once the CSV file is generated, the seller can download it using the returned URI.
 *
 * Related operations:
 * - GET /variants/{variantId} must be pre-executed to verify the variant exists and belongs to the seller before exporting.
 * - PATCH /variants/{variantId}/inventory/history must be used to view inventory history in the browser UI for real-time stock calculation.
 *
 * @param props.connection
 * @param props.variantId ID of the product variant to export inventory history for
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification 1. Validate that variantId is a valid UUID
 * 2. Query ecommerce_mall_product_variants to find the variant by id
 * 3. Verify variant exists and is active (isActive = true)
 * 4. Get the product from product_variants.product_id
 * 5. Check that the requesting seller owns this product (product.seller_id == current_user_id)
 * 6. If not authorized, return 403 Forbidden with error message
 * 7. Query ecommerce_mall_inventory_records for all records where variant_id = variantId
 * 8. Apply optional filters from query parameters:
 *    - startDate: filter records where timestamp >= startDate
 *    - endDate: filter records where timestamp <= endDate
 *    - reason: filter records where reason equals the specified reason (restocking, order_fulfillment, cancellation, refund, adjustment)
 * 9. Sort results by timestamp DESC (newest first)
 * 10. Generate CSV content with headers: timestamp,variant_id,quantity_change,reason,cumulative_stock_level
 * 11. Calculate cumulative stock level by summing quantity_change values in chronological order (oldest to newest)
 * 12. Generate file with UUID filename: inventory-export-{variantId}-{timestamp}.csv
 * 13. Upload CSV to file storage service
 * 14. Return absolute URI to the generated file as string
 * 15. Include proper MIME type: text/csv
 * 16. Set Content-Disposition header for file download
 *
 * Error handling:
 * - 404 Not Found: variant not found or not active
 * - 403 Forbidden: variant does not belong to the seller
 * - 400 Bad Request: invalid filter parameter format
 * - 500 Internal Server Error: file generation or storage failure
 * @path /ecommerceMall/seller/variants/:variantId/inventory/history/export
 * @accessor api.functional.ecommerceMall.seller.variants.inventory.history._export.exportHistory
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function exportHistory(
  connection: IConnection,
  props: exportHistory.Props,
): Promise<exportHistory.Response> {
  return true === connection.simulate
    ? exportHistory.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...exportHistory.METADATA,
          path: exportHistory.path(props),
          status: null,
        },
      );
}
export namespace exportHistory {
  export type Props = {
    /**
     * ID of the product variant to export inventory history for
     */
    variantId: string & tags.Format<"uuid">;
  };
  export type Response = IEcommerceMallInventoryRecord.IExportResult;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/seller/variants/:variantId/inventory/history/export",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/seller/variants/${encodeURIComponent(props.variantId ?? "null")}/inventory/history/export`;
  export const random = (): IEcommerceMallInventoryRecord.IExportResult =>
    typia.random<IEcommerceMallInventoryRecord.IExportResult>();
  export const simulate = (
    connection: IConnection,
    props: exportHistory.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: exportHistory.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("variantId")(() => typia.assert(props.variantId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
