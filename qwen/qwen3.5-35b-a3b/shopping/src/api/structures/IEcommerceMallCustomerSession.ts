import { tags } from "typia";

export namespace IEcommerceMallCustomerSession {
  /**
   * Lightweight session summary for customer session listing. Provides essential session metadata including session identifier, creation timestamp, expiration timestamp, current session status (active or invalidated), IP address for security tracking, and page context (href/referrer). Optimized for account management interfaces showing customer's active sessions across devices.
   */
  export type ISummary = {
    /**
     * Unique session identifier.
     *
     * @x-autobe-database-schema-property id
     * @x-autobe-specification Direct mapping from ecommerce_mall_customer_sessions.id. UUID primary key generated by database.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Session creation timestamp.
     *
     * @x-autobe-database-schema-property created_at
     * @x-autobe-specification Direct mapping from ecommerce_mall_customer_sessions.created_at. Timestamp when the session was created.
     */
    created_at: string & tags.Format<"date-time">;

    /**
     * Session expiration timestamp.
     *
     * @x-autobe-database-schema-property expired_at
     * @x-autobe-specification Direct mapping from ecommerce_mall_customer_sessions.expired_at. Timestamp when the session becomes invalid and requires re-authentication.
     */
    expired_at: string & tags.Format<"date-time">;

    /**
     * IP address of the client making the request.
     *
     * @x-autobe-database-schema-property ip
     * @x-autobe-specification Direct mapping from ecommerce_mall_customer_sessions.ip. IP address captured from client making the request. Optional in SSR where server captures IP.
     */
    ip: string | null;

    /**
     * Page URL where the session was created.
     *
     * @x-autobe-database-schema-property href
     * @x-autobe-specification Direct mapping from ecommerce_mall_customer_sessions.href. Page URL where the session was created, captured from browser history.
     */
    href: string & tags.Format<"uri">;

    /**
     * HTTP referrer header from the client's browser.
     *
     * @x-autobe-database-schema-property referrer
     * @x-autobe-specification Direct mapping from ecommerce_mall_customer_sessions.referrer. HTTP referrer header from the client's browser.
     */
    referrer?: (string & tags.Format<"uri">) | null | undefined;

    /**
     * Current session status: 'active' if session is valid, 'invalidated' if expired.
     *
     * @x-autobe-specification Computed field: Returns 'active' when expired_at > current time, 'invalidated' when expired_at <= current time. This status is used to display session validity in the account management interface.
     */
    sessionStatus: "active" | "invalidated";
  };

  /**
   * Request parameters for filtering and paginating customer sessions. Supports advanced search by session status, creation date range, device information, and location. All fields are optional to allow flexible queries.
   */
  export type IRequest = {
    /**
     * Filter by session status. 'active' for valid sessions, 'invalidated' for expired or terminated sessions.
     *
     * @x-autobe-specification Filters ecommerce_mall_customer_sessions by session_status column. Accepts 'active' or 'invalidated' enum values or null for no filtering.
     */
    status?: "active" | "invalidated" | null | undefined;

    /**
     * Filter sessions created after this date-time. Used with endDate for date range filtering.
     *
     * @x-autobe-specification Filters ecommerce_mall_customer_sessions.created_at >= startDate. Accepts ISO 8601 date-time format or null for no filtering.
     */
    startDate?: (string & tags.Format<"date-time">) | null | undefined;

    /**
     * Filter sessions created before this date-time. Used with startDate for date range filtering.
     *
     * @x-autobe-specification Filters ecommerce_mall_customer_sessions.created_at <= endDate. Accepts ISO 8601 date-time format or null for no filtering.
     */
    endDate?: (string & tags.Format<"date-time">) | null | undefined;

    /**
     * Filter sessions by device type. 'mobile' for mobile devices, 'web' for desktop browsers, 'desktop' for desktop applications.
     *
     * @x-autobe-specification Filters ecommerce_mall_customer_sessions by derived device type from user agent or explicit device marker. Accepts 'mobile', 'web', 'desktop' enum values or null for no filtering.
     */
    deviceType?: "mobile" | "web" | "desktop" | null | undefined;

    /**
     * Search sessions by geographic location. Supports partial match on IP location data or user-provided location strings.
     *
     * @x-autobe-specification Performs text search on IP geolocation data associated with sessions. Accepts any string for partial matching or null for no filtering.
     */
    locationSearch?: string | null | undefined;

    /**
     * Current page number for paginated results (1-indexed).
     *
     * @x-autobe-specification Returns page number starting from 1. Must be integer >= 1. Null defaults to page 1.
     */
    page?: (number & tags.Type<"int32"> & tags.Minimum<1>) | null | undefined;

    /**
     * Maximum number of records to return per page (1-100).
     *
     * @x-autobe-specification Controls page size. Integer between 1 and 100 inclusive. Null defaults to system default (typically 20).
     */
    limit?:
      | (number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<100>)
      | null
      | undefined;

    /**
     * Sort field for results. Options: 'created_at' (by creation date), 'last_activity' (by last activity), 'actor_type' (by user type).
     *
     * @x-autobe-specification Orders query results by specified field. Accepts 'created_at', 'last_activity', 'actor_type' or null for default sort (created_at descending).
     */
    sort?: "created_at" | "last_activity" | "actor_type" | null | undefined;
  };
}
