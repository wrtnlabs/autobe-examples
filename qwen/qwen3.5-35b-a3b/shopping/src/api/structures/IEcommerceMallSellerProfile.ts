import { tags } from "typia";

export namespace IEcommerceMallSellerProfile {
  /**
   * Lightweight seller shop profile summary for administrative dashboards and approval reviews. Contains essential shop identification and branding information including shop name, optional description, and logo image URL. Used when viewing seller profiles in admin interfaces or evaluating seller access requests.
   */
  export type ISummary = {
    /**
     * Unique identifier for the seller shop profile.
     *
     * @x-autobe-specification UUID - unique identifier for this seller shop profile record. Auto-generated by the database on profile creation.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Name of the seller's shop. Required field, maximum 100 characters.
     *
     * @x-autobe-specification Required text field, maximum 100 characters. Must be unique across all seller profiles. This is the public-facing name of the seller's shop.
     */
    shopName: string & tags.MaxLength<100>;

    /**
     * Optional description of the seller's shop. Null if not provided.
     *
     * @x-autobe-specification Nullable text field. Optional description that can be null if the seller has not provided a shop description. Maximum 5000 characters as per requirements.
     */
    shopDescription?: string | null | undefined;

    /**
     * URL of the seller's shop logo image. Null if logo not uploaded.
     *
     * @x-autobe-specification Nullable URI field. URL pointing to the shop logo image, or null if no logo has been uploaded by the seller.
     */
    logoUrl?: (string & tags.Format<"uri">) | null | undefined;

    /**
     * Timestamp when the seller profile was created.
     *
     * @x-autobe-specification Timestamp (timestamptz) when this seller profile was initially created. Auto-generated by the database on profile creation.
     */
    createdAt: string & tags.Format<"date-time">;

    /**
     * Timestamp when the seller profile was last updated.
     *
     * @x-autobe-specification Timestamp (timestamptz) of the last update to this seller profile. Updated automatically by the database on each profile modification.
     */
    updatedAt: string & tags.Format<"date-time">;
  };
}
