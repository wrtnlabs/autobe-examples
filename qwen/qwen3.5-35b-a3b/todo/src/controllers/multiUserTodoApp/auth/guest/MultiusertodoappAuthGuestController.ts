import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoAppGuest } from "../../../../api/structures/IMultiUserTodoAppGuest";
import { postMultiUserTodoAppAuthGuestJoin } from "../../../../providers/postMultiUserTodoAppAuthGuestJoin";
import { postMultiUserTodoAppAuthGuestRefresh } from "../../../../providers/postMultiUserTodoAppAuthGuestRefresh";

@Controller("/multiUserTodoApp/auth/guest")
export class MultiusertodoappAuthGuestController {
  /**
   * User Registration - This endpoint allows unauthenticated visitors to create a new guest account in the multi-user todo application by providing their email address, password, and display name. The email address is validated for proper format using standard email validation patterns and must be unique across all guest accounts in the multi_user_todo_app_guests table. If the email format is invalid or the email is already registered, the request is rejected with an appropriate error.
   *
   * The password is required and must be securely hashed using bcrypt before being stored in the password field of the guest record. Upon successful account creation, the system automatically generates a JWT session by creating an entry in the multi_user_todo_app_guest_sessions table with both access_token and refresh_token values derived from the guest_id and device fingerprint information. This session enables the newly registered guest to perform authenticated operations immediately after registration.
   *
   * The display_name becomes the guest's visible identifier across the application and is stored in the display_name field. This endpoint returns the complete guest account information including the generated authentication token, allowing the client to immediately begin using the authenticated features of the application without a separate login step.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials for creating a new guest account
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Create a new guest account by validating email format, checking email uniqueness against the guests table, hashing the password using bcrypt, and creating a new guest record with the provided email, hashed password, and display_name. After successful account creation, generate a JWT session token by creating a record in the guest_sessions table with access_token and refresh_token derived from the guest_id and device fingerprint. Return the newly created guest account information with the authentication token.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoAppGuest.IJoin,
  ): Promise<IMultiUserTodoAppGuest.IAuthorized> {
    try {
      return await postMultiUserTodoAppAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Token Refresh - This endpoint allows guests to renew their expired JWT session tokens without requiring re-authentication. Guests receive both access_token and refresh_token during registration via the join operation. The refresh_token is used to obtain new access tokens when the original access token expires.
   *
   * The system validates the refresh token by querying the multi_user_todo_app_guest_sessions table for a matching refresh_token record. The token must be valid (not expired, not previously invalidated) and associated with an active guest account in the multi_user_todo_app_guests table. If the token is invalid, expired, or has been used, the refresh request is rejected.
   *
   * Upon successful validation, the system generates a new access_token and refresh_token pair by creating a new guest_sessions record. The old refresh token is invalidated to prevent replay attacks. This ensures that each refresh token can only be used once, maintaining the security of the session. The client receives the new access token and should replace the old one for subsequent authenticated requests.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for renewing the guest session
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Validate the provided refresh token by looking up the corresponding guest_sessions record in the database using the refresh_token field. If the token is valid and not expired, generate a new access_token by creating a new session record with a fresh access_token and refresh_token pair derived from the guest_id and device fingerprint. Invalidate the old refresh token to prevent replay attacks. Return the new access token to the client.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMultiUserTodoAppGuest.IRefresh,
  ): Promise<IMultiUserTodoAppGuest.IAuthorized> {
    try {
      return await postMultiUserTodoAppAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
