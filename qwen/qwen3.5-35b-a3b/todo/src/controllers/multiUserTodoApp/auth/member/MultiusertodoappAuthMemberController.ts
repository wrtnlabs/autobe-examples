import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoAppMember } from "../../../../api/structures/IMultiUserTodoAppMember";
import { postMultiUserTodoAppAuthMemberJoin } from "../../../../providers/postMultiUserTodoAppAuthMemberJoin";
import { postMultiUserTodoAppAuthMemberLogin } from "../../../../providers/postMultiUserTodoAppAuthMemberLogin";
import { postMultiUserTodoAppAuthMemberRefresh } from "../../../../providers/postMultiUserTodoAppAuthMemberRefresh";

@Controller("/multiUserTodoApp/auth/member")
export class MultiusertodoappAuthMemberController {
  /**
   * Registration endpoint for new member accounts in the multi-user todo application. This operation creates a new authenticated user account using email address and password credentials, along with an optional display name for profile identification.
   *
   * The database schema multi_user_todo_app_members stores member information with fields: email for unique identification and login, password for credential validation (stored as hash), displayName for display purposes, createdAt timestamp automatically set when account is created, and updatedAt timestamp updated on profile modifications.
   *
   * Upon successful registration, the system generates JWT session tokens (access_token and refresh_token) stored in the multi_user_todo_app_member_sessions table, enabling immediate authenticated access to the member's private todo resources without requiring a separate login step.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials and profile information for new member account
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create new member account with email, password, and display name. Verify email format and uniqueness, hash password using bcrypt before storing, create member record with createdAt timestamp, generate JWT session tokens (access and refresh) stored in multi_user_todo_app_member_sessions, return member profile and authorization tokens. Password must meet minimum complexity requirements. Return 409 Conflict if email already registered.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoAppMember.IJoin,
  ): Promise<IMultiUserTodoAppMember.IAuthorized> {
    try {
      return await postMultiUserTodoAppAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Login endpoint for member account authentication using email and password credentials. This operation validates the member's credentials against the stored values in the multi_user_todo_app_members table and issues JWT session tokens for authenticated API access.
   *
   * The database schema multi_user_todo_app_members contains the email field for unique user identification and the password field for credential storage (hashed using bcrypt). When a member provides their email and password, the system queries for a matching record, verifies the password hash, and upon validation success, creates new session tokens.
   *
   * The multi_user_todo_app_member_sessions table stores JWT tokens (access_token and refresh_token) with timestamps and device identifiers. Upon successful login, any existing session tokens for that member are invalidated to prevent concurrent session conflicts, ensuring fresh tokens are issued for the new authenticated session.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials for member account authentication
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Authenticate member using email and password credentials. Query multi_user_todo_app_members by email, validate password hash matches stored value, verify account exists and is active. Upon successful authentication, revoke existing refresh tokens and generate new JWT access and refresh tokens stored in multi_user_todo_app_member_sessions. Return member profile with authorization tokens. Return 401 Unauthorized for invalid credentials or non-existent account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoAppMember.ILogin,
  ): Promise<IMultiUserTodoAppMember.IAuthorized> {
    try {
      return await postMultiUserTodoAppAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Token refresh endpoint for renewing expired JWT access tokens without re-authentication. This operation allows members to obtain new access tokens using a valid refresh token from the multi_user_todo_app_member_sessions table, eliminating the need to re-enter credentials.
   *
   * The multi_user_todo_app_member_sessions table contains session records with access_token, refresh_token, member_id, device_fingerprint, created_at, and expires_at fields. The system validates that the provided refresh_token matches a stored session record, verifies the member_id and device_fingerprint match the original session, and checks that the token has not expired.
   *
   * Upon successful validation, the system generates new JWT tokens (access_token with 1-hour expiration, refresh_token with 7-day expiration), stores them in the sessions table, and invalidates the old refresh token to prevent token reuse. This enables seamless authentication without requiring members to log in again.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new authorization tokens
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Refresh expired access token using valid refresh token. Query multi_user_todo_app_member_sessions for matching refresh_token, validate token expiration, member_id, and device_fingerprint match stored values. Upon validation success, generate new access token with extended expiration (1 hour) and new refresh token (7 days), store both in sessions table, invalidate old tokens, and return new authorization tokens. Return 401 Unauthorized for invalid, expired, or mismatched refresh tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMultiUserTodoAppMember.IRefresh,
  ): Promise<IMultiUserTodoAppMember.IAuthorized> {
    try {
      return await postMultiUserTodoAppAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
