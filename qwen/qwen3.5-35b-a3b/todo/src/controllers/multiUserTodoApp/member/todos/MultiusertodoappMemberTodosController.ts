  /**
   * Soft delete a todo by moving it to the trash.
   *
   * This operation permanently removes a todo from the active todo list by setting the deleted_at timestamp to the current datetime. The todo remains in the system and can be viewed in the trash, restored, or permanently deleted.
   *
   * The operation enforces strict ownership validation - users can only delete their own todos. Any attempt to delete another user's todo is rejected with an authorization error.
   *
   * The todo's edit history entries remain intact during soft deletion. They are only permanently removed when the todo is permanently deleted from the trash using the trash deletion endpoint.
   *
   * Related operations:
   * - GET /todos/{todoId}: View todo details before deletion
   * - GET /todos/trash: View deleted todos in trash
   * - PUT /todos/{todoId}/restore: Restore a deleted todo back to the active list
   * - DELETE /todos/{todoId} (permanent): Permanently delete from trash (also deletes edit history)
   *
   * @param connection
   * @param todoId The unique identifier of the todo to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate authentication - require valid member session token
   * 2. Extract todoId from path parameter (UUID format)
   * 3. Query multi_user_todo_app_todos for record matching todoId AND user_id = authenticated user's ID
   * 4. If record not found, return 404 Not Found
   * 5. Check if deleted_at is already non-null - if todo is already in trash, return 409 Conflict
   * 6. Set deleted_at to current UTC timestamp
   * 7. Update updated_at to current UTC timestamp
   * 8. Commit transaction
   * 9. Return 200 OK with the deleted todo object including deletedAt timestamp
   *
   * Error handling:
   * - 401 Unauthorized: No valid authentication token provided
   * - 404 Not Found: Todo does not exist or belongs to another user
   * - 409 Conflict: Todo is already deleted (in trash)
   * - 422 Unprocessable Entity: Invalid todoId format
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
