import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMultiUserTodoMemberSession } from "../../../../api/structures/IMultiUserTodoMemberSession";
import { IPageIMultiUserTodoMemberSession } from "../../../../api/structures/IPageIMultiUserTodoMemberSession";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { getMultiUserTodoGuestSessionsSessionId } from "../../../../providers/getMultiUserTodoGuestSessionsSessionId";
import { patchMultiUserTodoGuestSessions } from "../../../../providers/patchMultiUserTodoGuestSessions";

@Controller("/multiUserTodo/guest/sessions")
export class MultiusertodoGuestSessionsController {
  /**
   * List all sessions associated with the authenticated user with pagination and filtering options.
   *
   * Provides a view into active and expired sessions across all devices and browser tabs where the user is signed in. Each session entry includes client context information such as IP address, referrer source, and last visited URL.
   *
   * @param connection
   * @param body Session search criteria including date range filters, status filter for active or expired sessions, optional IP address pattern matching, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query multi_user_todo_member_sessions table for the authenticated user's sessions.
   *
   * Apply filters:
   * - Date range on created_at if provided (created_at_gte, created_at_lte)
   * - Status filter: active (expired_at > now) or expired (expired_at <= now)
   * - IP address pattern match if provided (ip like)
   * - Pagination parameters: page, limit
   *
   * Return session summary with:
   * - id (session identifier)
   * - multi_user_todo_member_id (owner reference)
   * - ip (client IP address)
   * - href (last visited URL)
   * - referrer (referrer header value)
   * - created_at (session creation timestamp)
   * - expired_at (session expiration timestamp)
   *
   * Sort by created_at descending (most recent first) by default.
   *
   * Join with multi_user_todo_members for display name if needed.
   *
   * Return cursor-based pagination metadata including total count.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IMultiUserTodoMemberSession.IRequest,
  ): Promise<IPageIMultiUserTodoMemberSession.ISummary> {
    try {
      return await patchMultiUserTodoGuestSessions({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve session information for a specific session.
   *
   * Returns full session details including device context (IP address), navigation context (last visited URL and referrer), and session lifecycle information (creation and expiration timestamps). This endpoint is used by members to view their active sessions for security auditing or session management purposes.
   *
   * Authentication is required - members can only view their own sessions. The session must exist and be accessible by the authenticated user.
   *
   * Returns 404 if the session does not exist or belongs to another user. Returns 401 if the request is unauthenticated.
   *
   * @param connection
   * @param sessionId Unique identifier of the session to retrieve (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query the multi_user_todo_member_sessions table for a session matching the sessionId path parameter.
   *
   * 1. Validate that sessionId is a valid UUID format
   * 2. Query session by id = sessionId
   * 3. Verify the session belongs to the authenticated member (multi_user_todo_member_id matches current user)
   * 4. If session not found or doesn't belong to user, return 404 Not Found
   * 5. Return full session record with all fields
   *
   * Field mappings:
   * - id: session UUID
   * - multi_user_todo_member_id: owner member UUID (excluded from response)
   * - ip: client IP address string
   * - href: last visited URL string
   * - referrer: HTTP referrer string
   * - created_at: session creation timestamp (ISO 8601)
   * - expired_at: session expiration timestamp (ISO 8601)
   *
   * Error handling:
   * - 401 Unauthorized: No valid authentication token provided
   * - 404 Not Found: Session does not exist or does not belong to authenticated user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IMultiUserTodoMemberSession> {
    try {
      return await getMultiUserTodoGuestSessionsSessionId({
        guest,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
