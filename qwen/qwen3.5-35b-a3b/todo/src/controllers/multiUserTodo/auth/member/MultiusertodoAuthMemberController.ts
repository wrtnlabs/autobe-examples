import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoMember } from "../../../../api/structures/IMultiUserTodoMember";
import { postMultiUserTodoAuthMemberJoin } from "../../../../providers/postMultiUserTodoAuthMemberJoin";
import { postMultiUserTodoAuthMemberLogin } from "../../../../providers/postMultiUserTodoAuthMemberLogin";
import { postMultiUserTodoAuthMemberRefresh } from "../../../../providers/postMultiUserTodoAuthMemberRefresh";

@Controller("/multiUserTodo/auth/member")
export class MultiusertodoAuthMemberController {
  /**
   * Register a new member account with email and password.
   *
   * Creates a new member account in the multi_user_todo_members table after validating the email format and password requirements. The password is hashed using bcrypt before storage. Upon successful registration, an initial session is created and both access and refresh tokens are returned.
   *
   * Validation ensures the email is in valid format, password is at least 8 characters, and the email is not already registered. Duplicate email addresses return a 409 Conflict error.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration request containing email and password
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Create a new member account with email and
     *   password.
   *
   * 1. Validate email format (valid email pattern)
   * 2. Validate password length (minimum 8 characters)
   * 3. Check if email already exists in multi_user_todo_members
   * 4. Hash password using bcrypt
   * 5. Insert new record into multi_user_todo_members with email, password_hash
   * 6. Create initial session in multi_user_todo_member_sessions with:
   *    - member_id: newly created member id
   *    - ip: from request context or default
   *    - href: from request context or default
   *    - referrer: from request context or default
   *    - created_at: current timestamp
   *    - expired_at: access token expiry (e.g., 1 hour from now)
   *    - Note: refresh token also stored as part of session
   * 7. Return access_token and refresh_token in response
   * 8. Errors: 400 for validation errors, 409 for duplicate email
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoMember.IJoin,
  ): Promise<IMultiUserTodoMember.IAuthorized> {
    try {
      return await postMultiUserTodoAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate member with email and password credentials.
   *
   * Validates the provided email and password against stored credentials in the multi_user_todo_members table. Upon successful authentication, creates a new session record in multi_user_todo_member_sessions and returns access and refresh tokens for subsequent API calls.
   *
   * The password is verified using bcrypt hashing comparison. The account must be active (not soft deleted) to authenticate. Invalid credentials return a 401 Unauthorized error.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login request containing email and password
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Authenticate member with email and password.
   *
   * 1. Validate email format
   * 2. Find member in multi_user_todo_members by email
   * 3. Verify password using bcrypt comparison
   * 4. Check if member account is active (deleted_at is null)
   * 5. Create new session in multi_user_todo_member_sessions:
   *    - member_id: member id
   *    - ip: from request context
   *    - href: from request context
   *    - referrer: from request context
   *    - created_at: current timestamp
   *    - expired_at: token expiry time
   * 6. Return access_token and refresh_token
   * 7. Errors: 400 for validation, 401 for invalid credentials
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoMember.ILogin,
  ): Promise<IMultiUserTodoMember.IAuthorized> {
    try {
      return await postMultiUserTodoAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh access token using a valid refresh token.
   *
   * Validates the refresh token from the multi_user_todo_member_sessions table and issues new access and refresh tokens. The refresh token must be valid and not expired. Upon successful refresh, a new session is created or updated with the new tokens, and the old tokens become invalid.
   *
   * This operation enables seamless token renewal without requiring re-authentication. Expired or invalid refresh tokens return a 401 Unauthorized error.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token request
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Refresh access token using refresh token.
   *
   * 1. Validate refresh token format
   * 2. Find session in multi_user_todo_member_sessions by token
   * 3. Verify session is not expired (expired_at > current time)
   * 4. Verify session is still active (member not deleted)
   * 5. Generate new access and refresh tokens
   * 6. Update or create new session record with new tokens
   * 7. Return new tokens in response
   * 8. Errors: 400 for invalid token format, 401 for expired/invalid token
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMultiUserTodoMember.IRefresh,
  ): Promise<IMultiUserTodoMember.IAuthorized> {
    try {
      return await postMultiUserTodoAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
