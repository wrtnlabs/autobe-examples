import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoGuest } from "../../../../api/structures/IMultiUserTodoGuest";
import { postMultiUserTodoAuthGuestJoin } from "../../../../providers/postMultiUserTodoAuthGuestJoin";
import { postMultiUserTodoAuthGuestRefresh } from "../../../../providers/postMultiUserTodoAuthGuestRefresh";

@Controller("/multiUserTodo/auth/guest")
export class MultiusertodoAuthGuestController {
  /**
   * Create a new guest account with email and password.
   *
   * Registers a new guest user with the provided email and password credentials. The system creates a temporary guest account identified by device fingerprint and stores associated session information for authentication purposes.
   *
   * The endpoint validates the email format and ensures the password meets minimum security requirements (at least 8 characters). Upon successful creation, JWT access and refresh tokens are generated and returned for subsequent authenticated requests.
   *
   * Security considerations: Device fingerprint (user_agent, ip_address) is stored to enable session tracking. Tokens have expiration times and must be refreshed before expiry. Password is hashed before storage.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest account registration credentials
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Create a guest account with email and password. Validate email format and password minimum length. Create multi_user_todo_guests record with fingerprint_hash (from device fingerprint), user_agent, and ip_address. Create associated multi_user_todo_guest_sessions record with ip, created_at, expired_at (set to 1 hour from now). Generate JWT access token and refresh token. Return IMultiUserTodoGuest.IAuthorized with both tokens. Error handling: 400 for validation errors (invalid email format, password less than 8 characters), 409 Conflict if email already exists.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoGuest.IJoin,
  ): Promise<IMultiUserTodoGuest.IAuthorized> {
    try {
      return await postMultiUserTodoAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew an expired access token using a refresh token.
   *
   * This endpoint allows guest users to obtain new JWT tokens without re-authenticating. The provided refresh token is validated against stored sessions in multi_user_todo_guest_sessions. Upon successful validation, new access and refresh tokens are generated.
   *
   * The refresh token has a longer validity period than the access token and is used exclusively for token renewal. After successful refresh, the session's expired_at timestamp is updated to extend the session lifetime.
   *
   * Security considerations: Only valid, non-expired refresh tokens can be used. Each refresh generates a new token pair, invalidating the previous refresh token. This prevents token replay attacks and maintains session security.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for token renewal
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Refresh existing access token using a valid refresh token. Validate the refresh token from the request body. If valid, generate new access token and refresh token pair. Update the session in multi_user_todo_guest_sessions table with new expired_at timestamp (1 hour from now). Return IMultiUserTodoGuest.IAuthorized with new tokens. Error handling: 401 Unauthorized if refresh token is invalid, expired, or malformed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMultiUserTodoGuest.IRefresh,
  ): Promise<IMultiUserTodoGuest.IAuthorized> {
    try {
      return await postMultiUserTodoAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
