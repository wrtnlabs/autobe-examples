import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMultiUserTodoTodo } from "../../../../api/structures/IMultiUserTodoTodo";
import { IPageIMultiUserTodoTodo } from "../../../../api/structures/IPageIMultiUserTodoTodo";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteMultiUserTodoMemberTrashTodoId } from "../../../../providers/deleteMultiUserTodoMemberTrashTodoId";
import { patchMultiUserTodoMemberTrash } from "../../../../providers/patchMultiUserTodoMemberTrash";
import { putMultiUserTodoMemberTrashTodoIdRestore } from "../../../../providers/putMultiUserTodoMemberTrashTodoIdRestore";

@Controller("/multiUserTodo/member/trash")
export class MultiusertodoMemberTrashController {
  /**
   * List user's deleted todos in trash with pagination, filtering, and sorting options.
   *
   * Returns a paginated list of todos that have been soft-deleted and moved to trash. Each user can only view their own trash. The list includes basic todo information (id, title, completion status, dates) optimized for list display.
   *
   * Users can paginate through their trash, filter by completion status, and sort by various date fields. Deleted todos retain all their data and edit history but are excluded from the normal todo list until restored.
   *
   * This endpoint supports cursor-based pagination for efficient handling of large result sets. Sorting is applied after filtering, with null values (missing dates) sorted to the end.
   *
   * @param connection
   * @param body Search criteria for trash todos including pagination, filtering, and sorting parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query multi_user_todo_todos table filtering where is_deleted=true and multi_user_todo_member_id matches the authenticated user's ID.
   *
   * Apply pagination parameters (page, limit) to cursor or offset-based pagination returning paginated results with total count.
   *
   * Apply optional filtering on is_complete status when status parameter is provided (complete/incomplete).
   *
   * Apply optional sorting by created_at, start_date, or due_date field. When sorting by date fields, null values must appear at the end of the result set.
   *
   * Sort order defaults to descending for created_at (newest first), ascending for start_date/due_date (earliest due first).
   *
   * Return only summary fields optimized for list display: id, title, is_complete, start_date, due_date, created_at, deleted_at.
   *
   * Include pagination metadata: total_count, page, limit, total_pages.
   *
   * Validate that the authenticated user has permission (always true since filtering by user ID).
   *
   * Return 200 OK with paginated results and metadata. Handle empty trash gracefully with empty array and zero counts.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IMultiUserTodoTodo.IRequest,
  ): Promise<IPageIMultiUserTodoTodo.ISummary> {
    try {
      return await patchMultiUserTodoMemberTrash({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Restores a todo from trash back to the active todo list with all original properties intact.
   *
   * This operation reverses a soft deletion by clearing the deleted_at timestamp and setting is_deleted to false. The todo returns to the normal todo list with its original title, description, dates, completion status, and edit history preserved.
   *
   * Authentication is required to ensure users can only restore their own deleted todos. The operation validates that the todo exists, belongs to the authenticated user, and is currently in the trash (is_deleted=true) before performing restoration.
   *
   * Errors are returned if the todo is not in trash (already active), the todo does not exist, or the todo belongs to another user.
   *
   * @param connection
   * @param todoId UUID identifier of the todo to restore from trash
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Restore a todo from trash to active list.
   *
   * 1. Validate authentication - extract user_id from access_token in Authorization header
   * 2. Query multi_user_todo_todos by id = todoId AND is_deleted = true
   * 3. Verify the todo's multi_user_todo_member_id matches authenticated user_id
   *    - Return 404 Not Found if todo not found
   *    - Return 404 Not Found if belongs to another user (do not reveal existence)
   * 4. Check if is_deleted is actually true
   *    - Return 400 Bad Request with error message if already active (not in trash)
   * 5. Perform update:
   *    - Set is_deleted = false
   *    - Set deleted_at = null
   *    - Update updated_at to current timestamp
   * 6. Return the full updated todo object
   *
   * Error responses:
   * - 400 Bad Request: todo is already active (is_deleted=false)
   * - 404 Not Found: todo does not exist or does not belong to authenticated user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId/restore")
  public async restore(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<IMultiUserTodoTodo> {
    try {
      return await putMultiUserTodoMemberTrashTodoIdRestore({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a todo from the user's trash, removing all associated data including edit history.
   *
   * This operation performs a complete removal of the todo and all its edit history entries from the system. Unlike soft delete (which moves todos to trash), permanent deletion cannot be undone. The todo's complete edit history is cascade deleted along with the todo itself.
   *
   * Authentication is required. The todo must belong to the authenticated user and must be in the trash (is_deleted=true) before permanent deletion. Attempting to permanently delete an active (non-trashed) todo will fail with an error.
   *
   * @param connection
   * @param todoId UUID identifier of the todo to permanently delete from trash
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate authentication - require valid access_token, extract user_id from JWT token
   * 2. Query multi_user_todo_todos for todo with id = todoId AND multi_user_todo_member_id = user_id
   * 3. Validate todo exists and is_deleted = true (must be in trash)
   * 4. If todo doesn't exist or is not in trash, return 404 Not Found with appropriate error
   * 5. Begin database transaction
   * 6. Delete all multi_user_todo_todos_edits records where todo_id = todoId (cascade delete)
   * 7. Delete the todo record from multi_user_todo_todos
   * 8. Commit transaction
   * 9. Return 200 OK with success message
   *
   * Error handling:
   * - 404 Not Found: Todo doesn't exist or doesn't belong to user, or todo is not in trash
   * - 401 Unauthorized: Missing or invalid access_token
   * - 500 Internal Server Error: Transaction failure
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteMultiUserTodoMemberTrashTodoId({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
