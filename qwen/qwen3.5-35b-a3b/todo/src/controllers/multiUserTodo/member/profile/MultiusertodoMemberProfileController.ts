import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoMember } from "../../../../api/structures/IMultiUserTodoMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putMultiUserTodoMemberProfile } from "../../../../providers/putMultiUserTodoMemberProfile";

@Controller("/multiUserTodo/member/profile")
export class MultiusertodoMemberProfileController {
  /**
   * Update the authenticated user's display name.
   *
   * This endpoint allows a member to change their display name, which serves as their public identity within the todo application. The display name is mandatory and must be provided with each update request.
   *
   * The profile is completely private—users can only update their own profile. The updated display name takes effect immediately and is reflected throughout the application interface.
   *
   * Requires authentication via access_token in the Authorization header.
   *
   * @param connection
   * @param body Profile update data containing the new display name.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Authenticate the user via access_token in the Authorization header (format: Bearer <token>).
   *
   * Extract user_id from the validated token and identify the corresponding member record in multi_user_todo_members table.
   *
   * Validate the request body:
   * - display_name: required, must be a non-empty string, maximum 100 characters
   * - Reject with 400 Bad Request if display_name is missing, empty, or exceeds length limit
   *
   * Execute UPDATE on multi_user_todo_members table:
   * - Set display_name to the provided value
   * - Set updated_at to current timestamp (now)
   *
   * Return the updated member record with display_name, email, and created_at fields.
   *
   * Error handling:
   * - 401 Unauthorized: Missing or invalid access_token
   * - 400 Bad Request: Validation errors on display_name (missing, empty, too long)
   *
   * Notes:
   * - Users cannot modify other users' profiles (authorization enforced via token user_id)
   * - No other profile fields (email, password) can be modified through this endpoint
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IMultiUserTodoMember.IUpdate,
  ): Promise<IMultiUserTodoMember> {
    try {
      return await putMultiUserTodoMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
