import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppGuest } from "../../../../api/structures/ITodoAppGuest";
import { postTodoAppAuthGuestJoin } from "../../../../providers/postTodoAppAuthGuestJoin";
import { postTodoAppAuthGuestRefresh } from "../../../../providers/postTodoAppAuthGuestRefresh";

@Controller("/todoApp/auth/guest")
export class TodoappAuthGuestController {
  /**
   * This API operation creates a new guest account for unauthenticated visitors who wish to register using their email address and password. The endpoint accepts registration credentials and establishes a temporary guest account in the todo_app_guests table, which is designed for unauthenticated visitors who can register and login.
   *
   * The registration process validates the provided email address against the RFC 5322 standard and checks for duplicate entries in the database. The password is hashed using bcrypt before storage in the passwordHash field, ensuring secure credential management. Upon successful registration, the system generates JWT access and refresh tokens that are stored in the todo_app_guest_sessions table for session management.
   *
   * The newly created guest account is immediately activated and ready for use. The client receives both tokens in the response, enabling authenticated access to guest-specific endpoints. Token expiration policies are enforced, with access tokens valid for 15 minutes and refresh tokens valid for 7 days. If email duplication is detected, a 409 Conflict error is returned indicating the email is already registered.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials for new guest account creation
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Create a new guest account by validating email uniqueness and password strength. Hash password using bcrypt before storage. Generate JWT access and refresh tokens. Store session record in todo_app_guest_sessions table with deviceToken for tracking. Validate email format against RFC 5322 standards. Enforce minimum password length (8 characters). Set initial account state to active. Return tokens to client for subsequent authenticated requests. Handle duplicate email conflicts with 409 error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppGuest.IJoin,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API operation refreshes the JWT tokens for an authenticated guest session. It validates the existing refresh token against the stored session records in the todo_app_guest_sessions table to ensure the token is still valid and has not expired.
   *
   * Upon successful validation, the system generates new access and refresh tokens and updates the session record with the new token values. This token rotation strategy helps maintain security by limiting the exposure window of compromised tokens. The old tokens are invalidated to prevent reuse.
   *
   * The operation supports deviceToken-based session correlation, allowing tracking of multiple devices accessing the same guest account. This enables proper session management and security auditing. If the refresh token is invalid, expired, or corrupted, a 401 Unauthorized error is returned, requiring the guest to re-register by calling the join endpoint.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for token renewal
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Validate refresh token from todo_app_guest_sessions table. Verify token has not expired. Issue new access and refresh tokens. Update session record with new token values. Invalidate old tokens on token rotation. Handle token validation failures with 401 Unauthorized. Support deviceToken-based session correlation for multi-device access tracking.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppGuest.IRefresh,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
