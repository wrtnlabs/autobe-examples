import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppMemberSession } from "../../../../api/structures/IPageITodoAppMemberSession";
import { ITodoAppMemberSession } from "../../../../api/structures/ITodoAppMemberSession";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberSessionsSessionId } from "../../../../providers/getTodoAppMemberSessionsSessionId";
import { patchTodoAppMemberSessions } from "../../../../providers/patchTodoAppMemberSessions";

@Controller("/todoApp/member/sessions")
export class TodoappMemberSessionsController {
  /**
   * Retrieve a filtered and paginated list of authentication sessions for the authenticated member across all devices.
   *
   * This operation provides visibility into the member's active and expired authentication sessions, enabling them to monitor device access and manage security. Sessions are retrieved from the todo_app_member_sessions table with support for filtering by status, date ranges, and IP address.
   *
   * Search capabilities include filtering by session status (active/expired), creation date range, expiration date range, and specific IP addresses. Results are paginated using cursor-based pagination for efficient handling of large session histories.
   *
   * Security validation ensures members can only access their own sessions. The authenticated member's ID from the JWT session claim is matched against session records. If the member is not found or authentication fails, a 404 Not Found error is returned.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for session listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the todo_app_member_sessions table where todo_app_member_id matches the authenticated user's ID (from JWT session claim).
   *
   * Apply the following filters:
   * - status: if 'active', filter sessions where expired_at > NOW(); if 'expired', filter where expired_at <= NOW()
   * - created_after: filter sessions where created_at >= value
   * - created_before: filter sessions where created_at <= value
   * - expired_after: filter sessions where expired_at >= value
   * - expired_before: filter sessions where expired_at <= value
   * - ip: exact match on IP address field
   *
   * Apply ordering:
   * - sortBy: 'created_at' or 'expired_at'
   * - sortOrder: 'asc' or 'desc'
   * - nullsLast: when sorting by date fields, sessions without values appear last
   *
   * Apply cursor-based pagination:
   * - cursor: optional pagination token from previous page
   * - direction: 'forward' (after cursor) or 'backward' (before cursor)
   * - take: number of records to return (default: 20, max: 100)
   *
   * Return fields: id, todo_app_member_id, ip, href, referrer, created_at, expired_at, status (computed: active|expired)
   *
   * Security: Authorize only if the authenticated member's ID matches the query criteria. Throw 404 Not Found if member not found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMemberSession.IRequest,
  ): Promise<IPageITodoAppMemberSession.ISummary> {
    try {
      return await patchTodoAppMemberSessions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific member session.
   *
   * This operation returns comprehensive session metadata including the authenticated member's identification, connection details from the login request, and temporal fields for session lifecycle tracking.
   *
   * The session record contains valuable audit information such as the client IP address, request URL, and referrer that was captured when the member logged in. This data is useful for security monitoring, anomaly detection, and troubleshooting authentication issues.
   *
   * Members can only view their own sessions. The system enforces strict data isolation to ensure that one member cannot access session information belonging to another member.
   *
   * Session information includes the creation timestamp, expiration timestamp, and the associated member ID. Expired sessions remain in the database as historical audit records, while active sessions can be identified by comparing the current time against the expiration timestamp.
   *
   * @param connection
   * @param sessionId The unique identifier of the session to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the todo_app_member_sessions table for the session record matching the provided sessionId UUID.
   *
   * 1. Validate that sessionId is a valid UUID format
   * 2. Retrieve the session record including all fields: id, todo_app_member_id, ip, href, referrer, created_at, expired_at
   * 3. Include the related member reference (todo_app_member_id)
   * 4. Enforce authorization: verify the current authenticated member's ID matches the todo_app_member_id on the session record
   * 5. Return 404 if the session does not exist
   * 6. Return 403 if the authenticated member is not the owner of the session
   * 7. Serialize the session object with proper DateTime formatting for created_at and expired_at
   * 8. Include all session fields in the response: id, todoAppMemberId, ip, href, referrer, createdAt, expiredAt
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMemberSession> {
    try {
      return await getTodoAppMemberSessionsSessionId({
        member,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
