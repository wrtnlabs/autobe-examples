import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";
import { ITodoAppUserProfile } from "../../../../api/structures/ITodoAppUserProfile";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberProfile } from "../../../../providers/getTodoAppMemberProfile";
import { putTodoAppMemberProfile } from "../../../../providers/putTodoAppMemberProfile";

@Controller("/todoApp/member/profile")
export class TodoappMemberProfileController {
  /**
   * Retrieve the current authenticated member's profile information including their email address and display name.
   *
   * This operation returns the user's profile details from the todo_app_members table, providing essential account information for display in user-facing interfaces.
   *
   * The response includes the user's email address (used for authentication), their display name (used for personalization and user identification), and account metadata including creation and update timestamps. The deleted_at field indicates if the account has been marked for deletion.
   *
   * This endpoint requires member authentication and returns only the authenticated user's own profile data with strict privacy isolation. Cross-user profile access is not permitted. The operation uses soft deletion tracking via the deleted_at field for account lifecycle management.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve profile from todo_app_members table for the authenticated user identified in the request context.
   *
   * 1. Extract user ID from authenticated session/tokens in request context
   * 2. Query todo_app_members table filtering by id = authenticated_user_id
   * 3. Return email and displayName fields
   * 4. Enforce that the user can only access their own profile
   * 5. Reject if user is not authenticated
   *
   * Database: todo_app_members
   * Fields returned: email, displayName
   * Authorization: member actor only
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<ITodoAppMember> {
    try {
      return await getTodoAppMemberProfile({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated member's profile display name in the `todo_app_user_profiles` table.
   *
   * This operation allows a logged-in user to change their display name, which is visible across all user-facing features of the application. The display name is a customizable identifier stored in the `todo_app_user_profiles` table that the user can modify at any time.
   *
   * The operation validates the new display name against business rules: it must be non-empty, cannot contain prohibited characters, and must not exceed the maximum allowed length. The system enforces a daily change limit (maximum one change per 24 hours) tracked in the `todo_app_user_profiles.last_display_name_change_at` field to prevent abuse.
   *
   * Only the account owner can update their own profile. The operation requires member authentication and will reject any unauthenticated requests. Cross-user profile access is strictly prohibited and will be denied.
   *
   * Upon successful validation and update, the new display name is persisted to the `todo_app_user_profiles` table immediately and reflected across all todos, edit history entries, and other user-related displays where the display name appears.
   *
   * @param connection
   * @param body Profile update data containing the new display name
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Authenticate the requesting user via session token (member actor required)
   * 2. Extract displayName from request body
   * 3. Validate displayName is non-empty string (reject empty or whitespace-only)
   * 4. Validate displayName does not exceed 50 characters (ITodoAppUserProfile.displayName maxLength)
   * 5. Validate displayName does not contain prohibited characters (alphanumeric, spaces, underscores, hyphens only)
   * 6. Check daily change limit from ITodoAppUserProfile.lastDisplayNameChange timestamp
   * 7. If all validations pass, update todo_app_user_profiles.displayName with new value
   * 8. Update todo_app_user_profiles.lastDisplayNameChange to current datetime
   * 9. Return updated profile object with new displayName
   * 10. If validation fails, return 400 error with specific validation message
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppUserProfile.IUpdate,
  ): Promise<ITodoAppUserProfile> {
    try {
      return await putTodoAppMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
