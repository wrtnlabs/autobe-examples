import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageITodoAppTodo } from "../../../../../api/structures/IPageITodoAppTodo";
import { ITodoAppTodo } from "../../../../../api/structures/ITodoAppTodo";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchTodoAppMemberTodosTrash } from "../../../../../providers/patchTodoAppMemberTodosTrash";

@Controller("/todoApp/member/todos/trash")
export class TodoappMemberTodosTrashController {
  /**
   * Retrieve a paginated list of the authenticated member's deleted todos from trash.
   *
   * This operation returns todos that have been soft-deleted (is_deleted=true) and moved to the trash folder. Each deleted todo is displayed with its original creation date, deletion timestamp, title, and completion status from before deletion.
   *
   * The list supports filtering by the todo's completion status before deletion and sorting by creation date, start date, or due date. Todos without date values are consistently placed at the end of sorted results.
   *
   * Only the owner of each todo can view their trash list. Cross-user access is prevented by ownership validation enforced through member authentication.
   *
   * If no deleted todos exist for the member, an empty list is returned with null cursors. The response includes nextCursor and previousCursor for cursor-based navigation through paginated results.
   *
   * @param connection
   * @param body Search criteria including completion status filter, sorting options, and pagination cursor
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query todo_app_todos table with is_deleted=true filter, scoped to authenticated member's ID.
   *
   * Apply filters:
   * - completionStatus: filter by is_complete (all, complete, incomplete)
   * - sortField: sort by created_at, start_date, or due_date
   * - sortOrder: ascending (earliest/oldest first) or descending (latest/newest first)
   *
   * Apply cursor-based pagination:
   * - Extract sort key values from previousCursor or use default for first page
   * - Query with LIMIT (page size) and WHERE clause for pagination key comparison
   * - Return nextCursor/previousCursor based on query result count
   *
   * Return ITodoAppTodo.ISummary objects with: id, title, description, start_date, due_date, is_complete, created_at, deleted_at.
   *
   * Validate:
   * - Member authentication via session
   * - Filter values against allowed completion status enum
   * - Sort field against allowed fields (created_at, start_date, due_date)
   * - Sort order against allowed values (ASC, DESC)
   *
   * Handle edge cases:
   * - No deleted todos → return empty array with null cursors
   * - Tampered/invalid cursor → reject with 400 error
   * - Cursor from different member → reject with 403 error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppTodo.IRequest,
  ): Promise<IPageITodoAppTodo.ISummary> {
    try {
      return await patchTodoAppMemberTodosTrash({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
