/**
 * Create a new guest account with email and password.
 *
 * Registers a new guest user with the provided email and password credentials. The system creates a temporary guest account identified by device fingerprint and stores associated session information for authentication purposes.
 *
 * The endpoint validates the email format and ensures the password meets minimum security requirements (at least 8 characters). Upon successful creation, JWT access and refresh tokens are generated and returned for subsequent authenticated requests.
 *
 * Security considerations: Device fingerprint (user_agent, ip_address) is stored to enable session tracking. Tokens have expiration times and must be refreshed before expiry. Password is hashed before storage.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest account registration credentials
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Create a guest account with email and password. Validate email format and password minimum length. Create multi_user_todo_guests record with fingerprint_hash (from device fingerprint), user_agent, and ip_address. Create associated multi_user_todo_guest_sessions record with ip, created_at, expired_at (set to 1 hour from now). Generate JWT access token and refresh token. Return IMultiUserTodoGuest.IAuthorized with both tokens. Error handling: 400 for validation errors (invalid email format, password less than 8 characters), 409 Conflict if email already exists.
 * @path /multiUserTodo/auth/guest/join
 * @accessor api.functional.multiUserTodo.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
