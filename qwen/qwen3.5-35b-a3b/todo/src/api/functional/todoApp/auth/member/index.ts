/**
 * Creates a new member account in the todo application. This endpoint handles the complete registration flow where a guest transitions to member status.
 *
 * The registration process requires an email address and password. The email must be in valid RFC 5322 format and must be unique across all member accounts - the database enforces this via the unique constraint on todo_app_members.email. Upon successful validation, the system creates a new record in the todo_app_members table with the provided email and a securely hashed password stored in password_hash column.
 *
 * The display_name field is optional during registration. If not provided, the system assigns a default name derived from the email address. This field serves as the user's public-facing identifier throughout the application and appears in all user-facing operations.
 *
 * Security considerations: Passwords are never stored in plain text. The system hashes the password using bcrypt or Argon2 algorithm before storing in the database. The registration endpoint implements rate limiting to prevent brute force attacks during account creation. All responses use HTTPS to protect credentials in transit.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration credentials including email, password, and optional display name
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Create a new member account with email and password. Validate email format (RFC 5322), ensure uniqueness via database unique constraint on todo_app_members.email, hash password using bcrypt or Argon2 before storing in todo_app_members.password_hash. Create the member record with display_name (default if not provided), set created_at and updated_at timestamps. Upon successful creation, issue JWT access and refresh tokens. The JWT payload contains member.id, email, and expiration time. Access token short-lived (15 min), refresh token longer-lived (7 days). Invalidate any existing session if new login occurs while session active.
 * @path /todoApp/auth/member/join
 * @accessor api.functional.todoApp.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
