/**
 * Test that a member cannot access another member's session information.
 * Validates data isolation and authorization enforcement by ensuring
 * one member cannot retrieve another member's session details.
 */
export async function test_api_member_session_another_user_rejected(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create member A account
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberA = await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(memberA);
  // 2. Create member B account
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberB = await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(memberB);
  // 3. Verify we have two distinct members
  TestValidator.notEquals("Members have different IDs", memberA.id, memberB.id);
  // 4. Member A attempts to access member B's session
  // We use member B's member ID as a proxy for their session
  // The system should reject this because it doesn't belong to member A
  await TestValidator.error(
    "member A cannot access member B's session",
    async () => {
      await api.functional.todoApp.member.sessions.at(memberAConnection, {
        sessionId: memberB.id,
      });
    },
  );
}
