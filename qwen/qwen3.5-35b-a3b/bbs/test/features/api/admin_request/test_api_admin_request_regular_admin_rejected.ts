export async function test_api_admin_request_regular_admin_rejected(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register member account who will submit admin request (simulated)
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(member);
  // 2. Register regular administrator account (not super admin)
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(admin);
  // 3. Attempt to access admin requests endpoint with regular admin
  // Should receive 403 Forbidden due to insufficient privileges
  await TestValidator.httpError(
    "regular admin cannot access pending requests",
    403,
    async () => {
      await api.functional.economicPoliticalBoard.admin.requests.index(
        adminConnection,
        {
          body: {
            page: 1,
            limit: 10,
          },
        },
      );
    },
  );
}