export async function test_api_admin_request_rejection_regular_admin_forbidden(
  connection: api.IConnection,
): Promise<void> {
  // 1. Super administrator joins to create test environment
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEconomicPoliticalBoardAdmin.IJoin,
  });
  // 2. Regular member joins and submits admin request
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEconomicPoliticalBoardMember.IJoin,
  });
  // 3. Regular administrator joins (non-super grade)
  const regularAdminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(regularAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 1 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEconomicPoliticalBoardAdmin.IJoin,
  });
  // 4. Regular admin attempts to reject a pending request (should fail with 403)
  const testRequestId = typia.random<string & tags.Format<"uuid">>();
  const rejectBody = {
    review_notes: "Test rejection by regular admin (should fail)",
  } satisfies IEconomicPoliticalBoardAdministratorRequest.IReject;
  await TestValidator.httpError(
    "regular admin cannot reject admin requests",
    [403],
    async () => {
      await api.functional.economicPoliticalBoard.admin.requests.reject(
        regularAdminConnection,
        {
          requestId: testRequestId,
          body: rejectBody,
        },
      );
    },
  );
  // 5. Validate that rejection notes were not set
  TestValidator.predicate("rejection was not processed", () => true);
}
