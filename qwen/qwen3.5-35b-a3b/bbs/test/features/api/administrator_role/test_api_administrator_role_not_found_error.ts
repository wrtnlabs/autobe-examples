export async function test_api_administrator_role_not_found_error(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(adminAuth);
  // 2. Generate a UUID for a non-existent role
  const nonExistentRoleId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve non-existent role and validate 404 error
  await TestValidator.httpError(
    "should return 404 for non-existent role",
    [404],
    async () => {
      await api.functional.economicPoliticalBoard.admin.roles.at(
        adminConnection,
        {
          roleId: nonExistentRoleId,
        },
      );
    },
  );
}
