/**
 * Register a new member account for the Economic Political Board discussion platform.
 *
 * This operation creates a new user account with email and password authentication, along with an associated profile containing displayName and bio. The registration process validates the email format and ensures it is unique in the economic_political_board_users table before creating the account. The password is securely hashed using a strong algorithm (bcrypt or Argon2) and stored as passwordHash in the database.
 *
 * Upon successful registration, a new Profile record is automatically created with the displayName and bio provided during registration. The profile is linked to the user via the userId foreign key relationship. Both the User and Profile records are created within a single database transaction to maintain referential integrity.
 *
 * After account creation, the system generates JWT tokens (access token and refresh token) for authentication. The access token contains the user ID, email, displayName, and member role claims. The refresh token is stored server-side for token renewal. Both tokens are included in the IAuthorized response.
 *
 * The registration endpoint rejects requests with 400 Bad Request if the email is already registered, the password does not meet minimum length requirements, or the displayName/bio have invalid formats. New users are created with isBanned=false, allowing immediate access to member features.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration data including email, password, displayName, and optional bio
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Create a new user account and profile by: 1) Validating email format and uniqueness against economic_political_board_users table, 2) Hashing password using bcrypt or Argon2 before storing as passwordHash, 3) Creating user record with email and passwordHash, 4) Automatically creating associated profile record with displayName from registration data, 5) Checking isBanned flag on creation (should be false for new users), 6) Returning JWT tokens (accessToken, refreshToken) and IAuthorized response with user ID, email, displayName. Reject with 400 if email already exists or validation fails. Reject with 403 if registration endpoint is disabled.
 * @path /economicPoliticalBoard/auth/member/join
 * @accessor api.functional.economicPoliticalBoard.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
