import typia, { tags } from "typia";

import { IEconomicPoliticalBoardSectionPopularTag } from "../../../../../structures/IEconomicPoliticalBoardSectionPopularTag";

/**
 * Retrieves a list of popular tags used within a specific section, ordered by article frequency.
 *
 * This endpoint aggregates tag usage statistics across all articles in the specified section, counting how many articles are associated with each tag. The results are sorted by usage count in descending order to surface the most popular topics within that section.
 *
 * Only public data is returned - all registered users and guests can access section tag popularity information without authentication.
 *
 * The endpoint joins articles with their associated tags to compute popularity metrics based on article count per tag.
 *
 * @param props.connection
 * @param props.sectionId ID of the section to retrieve popular tags for. The section must exist and not be soft-deleted.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query economic_political_board_sections table to verify section exists and is not soft-deleted.
 *
 * Execute a complex SQL query joining economic_political_board_articles, economic_political_board_article_tags, and economic_political_board_tags tables.
 *
 * Apply WHERE clause to filter: articles.section_id = requested section ID, articles.deleted_at IS NULL, tags.deleted_at IS NULL.
 *
 * GROUP BY tag properties to aggregate article counts per tag.
 *
 * ORDER BY article count DESC to sort by popularity.
 *
 * Return results with tag name and usage count for each popular tag.
 * @path /economicPoliticalBoard/member/sections/:sectionId/popular-tags
 * @accessor api.functional.economicPoliticalBoard.member.sections.popular_tags.popularTags
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function popularTags(
  connection: IConnection,
  props: popularTags.Props,
): Promise<popularTags.Response> {
  return true === connection.simulate
    ? popularTags.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...popularTags.METADATA,
          path: popularTags.path(props),
          status: null,
        },
      );
}
export namespace popularTags {
  export type Props = {
    /**
     * ID of the section to retrieve popular tags for. The section must exist and not be soft-deleted.
     */
    sectionId: string & tags.Format<"uuid">;
  };
  export type Response = IEconomicPoliticalBoardSectionPopularTag.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/economicPoliticalBoard/member/sections/:sectionId/popular-tags",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicPoliticalBoard/member/sections/${encodeURIComponent(props.sectionId ?? "null")}/popular-tags`;
  export const random = (): IEconomicPoliticalBoardSectionPopularTag.ISummary =>
    typia.random<IEconomicPoliticalBoardSectionPopularTag.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: popularTags.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: popularTags.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sectionId")(() => typia.assert(props.sectionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
