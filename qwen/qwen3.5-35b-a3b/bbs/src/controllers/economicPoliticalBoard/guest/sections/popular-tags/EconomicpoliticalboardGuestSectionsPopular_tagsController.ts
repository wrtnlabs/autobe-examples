import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicPoliticalBoardSectionPopularTag } from "../../../../../api/structures/IEconomicPoliticalBoardSectionPopularTag";
import { GuestAuth } from "../../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../../decorators/payload/GuestPayload";
import { getEconomicPoliticalBoardGuestSectionsSectionIdPopularTags } from "../../../../../providers/getEconomicPoliticalBoardGuestSectionsSectionIdPopularTags";

@Controller("/economicPoliticalBoard/guest/sections/:sectionId/popular-tags")
export class EconomicpoliticalboardGuestSectionsPopular_tagsController {
  /**
   * Retrieves a list of popular tags used within a specific section, ordered by article frequency.
   *
   * This endpoint aggregates tag usage statistics across all non-deleted articles in the specified section, counting how many articles are associated with each tag. The results are sorted by usage count in descending order to surface the most popular topics within that section.
   *
   * Only public data is returned - all registered users and guests can access section tag popularity information without authentication.
   *
   * The endpoint automatically excludes articles that have been soft-deleted (deleted_at is not null), ensuring that only active content contributes to tag popularity metrics.
   *
   * @param connection
   * @param sectionId ID of the section to retrieve popular tags for. The section must exist and not be soft-deleted.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query economic_political_board_sections table to verify section exists and is not soft-deleted.
   *
   * Execute a complex SQL query joining economic_political_board_articles, economic_political_board_article_tags, and economic_political_board_tags tables.
   *
   * Apply WHERE clause to filter: articles.section_id = requested section ID, articles.deleted_at IS NULL, tags.deleted_at IS NULL.
   *
   * GROUP BY tag properties to aggregate article counts per tag.
   *
   * ORDER BY article count DESC to sort by popularity.
   *
   * Return results with tag name and usage count for each popular tag.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async popularTags(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
  ): Promise<IEconomicPoliticalBoardSectionPopularTag.ISummary> {
    try {
      return await getEconomicPoliticalBoardGuestSectionsSectionIdPopularTags({
        guest,
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
