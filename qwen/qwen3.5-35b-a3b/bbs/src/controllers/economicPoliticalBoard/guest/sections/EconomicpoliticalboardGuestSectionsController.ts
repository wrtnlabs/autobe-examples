import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicPoliticalBoardSection } from "../../../../api/structures/IEconomicPoliticalBoardSection";
import { IPageIEconomicPoliticalBoardSection } from "../../../../api/structures/IPageIEconomicPoliticalBoardSection";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { getEconomicPoliticalBoardGuestSectionsSectionId } from "../../../../providers/getEconomicPoliticalBoardGuestSectionsSectionId";
import { patchEconomicPoliticalBoardGuestSections } from "../../../../providers/patchEconomicPoliticalBoardGuestSections";

@Controller("/economicPoliticalBoard/guest/sections")
export class EconomicpoliticalboardGuestSectionsController {
  /**
   * Retrieve a filtered and paginated list of discussion board sections.
   *
   * This operation provides comprehensive section listing with advanced search capabilities including name matching, creation date filtering, and customizable sorting options (newest first or oldest first).
   *
   * All sections are publicly viewable by guest users, members, and administrators. The response includes section metadata such as unique identifiers, names, descriptions, and creation timestamps.
   *
   * The operation supports cursor-based pagination for efficient retrieval of large section collections. Banned users can still view the section listing but may have restricted article browsing capabilities.
   *
   * Sections are sorted alphabetically by name by default, but can be re-ordered by creation date using query parameters. Soft-deleted sections are excluded from the listing but may be requested explicitly for administrative purposes.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for section listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query economic_political_board_sections table for active sections (deleted_at IS NULL).
   *
   * Apply search filters:
   * - name: partial match (ILIKE with %wildcards)
   * - created_at range: filter by creation date range
   *
   * Apply sorting:
   * - sortBy: 'newest' (created_at DESC), 'oldest' (created_at ASC), or default 'name' (alphabetical ASC)
   *
   * Apply pagination:
   * - page: cursor-based pagination for large result sets
   * - limit: configurable page size (default: 20, max: 100)
   *
   * Response structure:
   * - data: Array of IPageIEconomicPoliticalBoardSection.ISummary
   * - pagination: { page, limit, hasNext, hasPrevious }
   *
   * Authorization:
   * - No authentication required - publicly accessible
   * - Banned users can still access this endpoint
   *
   * Query optimization:
   * - Use index on created_at for date-based sorting
   * - Use unique index on name for name-based filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IEconomicPoliticalBoardSection.IRequest,
  ): Promise<IPageIEconomicPoliticalBoardSection.ISummary> {
    try {
      return await patchEconomicPoliticalBoardGuestSections({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific section in the economic/political discussion board.
   *
   * This endpoint returns the complete section details including the section's unique name, optional description, and timestamps for when it was created and last updated. The response includes the section's internal identifier which can be used for further API calls.
   *
   * Both unauthenticated guests and registered members can access this endpoint to browse available sections. This is a read-only operation that does not modify any data.
   *
   * Soft-deleted sections (where deleted_at is set) are not accessible through this endpoint and will return a 404 Not Found response, ensuring that inactive sections are hidden from public view while preserving historical data.
   *
   * @param connection
   * @param sectionId UUID identifier of the section to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Retrieve a specific section by its UUID identifier from the economic_political_board_sections table.
   *
   * Implementation steps:
   * 1. Parse sectionId from path parameter as UUID
   * 2. Query economic_political_board_sections WHERE id = sectionId
   * 3. Check deleted_at field - if not null, return 404 Not Found (soft deleted sections are hidden)
   * 4. If found and not deleted, return the section with all fields: id, name, description, created_at, updated_at
   * 5. If not found, return 404 Not Found
   *
   * Authorization:
   * - Public access - no authentication required (guests and members can view)
   *
   * Error handling:
   * - 404: Section not found or soft deleted
   * - 400: Invalid UUID format for sectionId
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sectionId")
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
  ): Promise<IEconomicPoliticalBoardSection> {
    try {
      return await getEconomicPoliticalBoardGuestSectionsSectionId({
        guest,
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
