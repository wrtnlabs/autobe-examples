import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicPoliticalBoardArticle } from "../../../../../api/structures/IEconomicPoliticalBoardArticle";
import { IPageIEconomicPoliticalBoardAttachment } from "../../../../../api/structures/IPageIEconomicPoliticalBoardAttachment";
import { GuestAuth } from "../../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../../decorators/payload/GuestPayload";
import { patchEconomicPoliticalBoardGuestArticlesArticleIdAttachments } from "../../../../../providers/patchEconomicPoliticalBoardGuestArticlesArticleIdAttachments";

@Controller("/economicPoliticalBoard/guest/articles/:articleId/attachments")
export class EconomicpoliticalboardGuestArticlesAttachmentsController {
  /**
   * Manage file attachments (add and/or remove) for a specific article in the Economic/Political Discussion Board.
   *
   * This operation allows article owners to attach multiple files to their article or remove existing attachments. Each attachment can be an image or document file stored with its file URL, file type, and original file name.
   *
   * The operation requires an authenticated member or administrator to execute. The request must include valid JWT authentication credentials. The authenticated user must own the target article, which is validated by comparing the user's ID against the article's authorId field. The article must also be in an active (non-deleted) state.
   *
   * The request body supports simultaneous add and remove operations, allowing users to replace attachments in a single API call. When attachments are removed, the corresponding database records and stored files are deleted.
   *
   * Successful operation returns the updated list of all attachments associated with the article after applying the requested changes.
   *
   * **Authentication Required**: This operation requires valid JWT authentication. Guests cannot modify article attachments.
   *
   * **Ownership Validation**: Users can only modify attachments on articles they have created. Attempting to modify another user's article will result in a 403 Forbidden error.
   *
   * **Related Operations**:
   * - `GET /articles/{articleId}` - Retrieve article details including attachment information
   * - `GET /articles/{articleId}/attachments/{attachmentId}` - Retrieve specific attachment details
   * - `DELETE /articles/{articleId}/attachments/{attachmentId}` - Delete individual attachment (alternative to batch remove)
   *
   * @param connection
   * @param articleId The unique identifier of the target article
   * @param body Attachment management operations containing arrays for adding new attachments and removing existing attachment IDs
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification 1. Validate authentication - user must be logged in
   * 2. Retrieve article by articleId from economic_political_board_articles table
   * 3. Validate article exists - return 404 if not found
   * 4. Validate article ownership - compare authenticated user's ID with article.authorId
   * 5. If attachmentId array provided in remove list:
   *    - For each attachmentId, delete corresponding record from economic_political_board_attachments
   *    - Delete associated file from storage
   * 6. If attachments array provided in add list:
   *    - For each attachment, validate file format (mimeType from fileType field)
   *    - Validate file size does not exceed limits from business rules
   *    - Validate file name does not contain prohibited characters
   *    - Create new economic_political_board_attachments record
   *    - Upload file to storage and persist fileUrl
   *    - Set articleId, fileName, fileType, and uploadedAt
   * 7. Return updated list of all attachments for the article from database
   * 8. Handle validation errors: 400 for business rule violations, 401 for unauthenticated, 403 for ownership violation, 404 for not found
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async manageAttachments(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicPoliticalBoardArticle.IManageAttachmentsRequest,
  ): Promise<IPageIEconomicPoliticalBoardAttachment.ISummary> {
    try {
      return await patchEconomicPoliticalBoardGuestArticlesArticleIdAttachments(
        {
          guest,
          articleId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
