import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicPoliticalBoardTag } from "../../../api/structures/IEconomicPoliticalBoardTag";
import { IPageIEconomicPoliticalBoardTag } from "../../../api/structures/IPageIEconomicPoliticalBoardTag";
import { getEconomicPoliticalBoardTagsTagId } from "../../../providers/getEconomicPoliticalBoardTagsTagId";
import { patchEconomicPoliticalBoardTags } from "../../../providers/patchEconomicPoliticalBoardTags";

@Controller("/economicPoliticalBoard/tags")
export class EconomicpoliticalboardTagsController {
  /**
   * Retrieve a filtered and paginated list of all active tags available in the economic/political discussion board system.
   *
   * This operation provides advanced search capabilities including partial name matching, alphabetical sorting, and configurable pagination for efficient browsing of large tag collections. All active tags are publicly accessible regardless of user authentication status.
   *
   * Supports comprehensive filtering by tag name pattern and configurable pagination with default page size of 20 items. The operation excludes soft-deleted tags (those with deleted_at timestamps) to ensure users only see currently active tags. Response includes tag metadata optimized for dropdown selection, autocomplete suggestions, and tag cloud displays.
   *
   * The tag system enables flexible content organization across sections, allowing articles to be discovered through multiple topic associations. Tags are managed through the junction table relationship with articles, and all tags persist even when untagged from articles unless explicitly soft-deleted by administrators.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for tag listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query economic_political_board_tags table with pagination and filtering.
   *
   * Apply search filters:
   * - name: case-insensitive partial matching on tag name
   * - Sorting: alphabetical by tag name (default), or by count if specified
   * - Pagination: offset-based pagination with configurable page and limit
   *
   * Business rules:
   * - Only return active tags (all tags are active in current design)
   * - No ownership restrictions - all users can view all tags
   * - Tags with zero article associations should still be returned
   *
   * Database query:
   * SELECT id, name, COUNT(article_tag.article_id) as article_count
   * FROM economic_political_board_tags tag
   * LEFT JOIN economic_political_board_article_tag article_tag ON tag.id = article_tag.tag_id
   * GROUP BY tag.id, tag.name
   * ORDER BY tag.name ASC
   * LIMIT :limit OFFSET :offset
   *
   * Return cursor-based pagination metadata including total count, current page, and next/previous page indicators.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEconomicPoliticalBoardTag.IRequest,
  ): Promise<IPageIEconomicPoliticalBoardTag.ISummary> {
    try {
      return await patchEconomicPoliticalBoardTags({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single tag resource by its unique identifier.
   *
   * This operation returns the complete details of a tag including its name, creation timestamp, and last update timestamp. Tags are system-wide resources used for content categorization and discovery across articles in the economic/political discussion board.
   *
   * The operation is intended for use cases such as:
   * - Displaying tag information on article pages
   * - Enabling tag-based navigation (clicking a tag to view all articles with that tag)
   * - Showing tag metadata in tag discovery interfaces
   * - Supporting tag filtering in article lists
   *
   * Tags are publicly accessible to all users including guests. The operation returns null for soft-deleted tags (tags where deleted_at is set), effectively hiding archived tags from general discovery while preserving them for audit purposes.
   *
   * @param connection
   * @param tagId The unique identifier of the tag to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification 1. Query the economic_political_board_tags table WHERE id = {tagId} AND deleted_at IS NULL
   * 2. Validate that tagId is a valid UUID format
   * 3. If tag not found (no matching record), return 404 Not Found error
   * 4. If tag exists but is soft-deleted (deleted_at IS NOT NULL), return 404 Not Found (hide archived tags)
   * 5. Join with economic_political_board_article_tags to include article_count (number of articles using this tag) for display purposes
   * 6. Return tag data with fields: id, name, created_at, updated_at, article_count
   * 7. If tag has no articles associated, return article_count as 0
   *
   * Error handling:
   * - 404 Not Found: Tag does not exist or is soft-deleted
   * - 400 Bad Request: Invalid UUID format in tagId parameter
   *
   * Note: Tags are system-wide resources without ownership. No authorization checks required. All users (guest, member, admin) can view tag details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":tagId")
  public async at(
    @TypedParam("tagId")
    tagId: string & tags.Format<"uuid">,
  ): Promise<IEconomicPoliticalBoardTag> {
    try {
      return await getEconomicPoliticalBoardTagsTagId({
        tagId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
