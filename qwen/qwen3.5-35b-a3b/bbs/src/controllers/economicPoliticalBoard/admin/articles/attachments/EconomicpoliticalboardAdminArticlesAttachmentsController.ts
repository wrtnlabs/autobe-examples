import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicPoliticalBoardAttachment } from "../../../../../api/structures/IEconomicPoliticalBoardAttachment";
import { IPageIEconomicPoliticalBoardAttachment } from "../../../../../api/structures/IPageIEconomicPoliticalBoardAttachment";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { deleteEconomicPoliticalBoardAdminArticlesArticleIdAttachmentsAttachmentId } from "../../../../../providers/deleteEconomicPoliticalBoardAdminArticlesArticleIdAttachmentsAttachmentId";
import { patchEconomicPoliticalBoardAdminArticlesArticleIdAttachments } from "../../../../../providers/patchEconomicPoliticalBoardAdminArticlesArticleIdAttachments";
import { postEconomicPoliticalBoardAdminArticlesArticleIdAttachments } from "../../../../../providers/postEconomicPoliticalBoardAdminArticlesArticleIdAttachments";

@Controller("/economicPoliticalBoard/admin/articles/:articleId/attachments")
export class EconomicpoliticalboardAdminArticlesAttachmentsController {
  /**
   * Add a new file attachment to an existing article in the economic/political discussion board.
   *
   * This operation allows authenticated members to upload and associate file attachments with their own articles. Attachments can be images (charts, screenshots, illustrations) or documents (PDF reports, spreadsheets) that support and enhance the article content.
   *
   * The requesting user must own the target article to add attachments. THE system validates that the article exists and that the authenticated user is the article's author before creating the attachment record. Each attachment is associated with the article and can be soft-deleted for audit trail purposes while maintaining the attachment metadata.
   *
   * Attachments are stored in object storage or CDN with metadata preserved including original filename, file type classification, and upload timestamp. The attachment metadata is automatically updated when the attachment is modified.
   *
   * @param connection
   * @param articleId UUID identifier of the article to attach the file to. The user must own this article.
   * @param body File attachment information including storage URL, original filename, and type classification
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new attachment record for the specified article.
   *
   * 1. Validate articleId exists in economic_political_board_articles table
   * 2. Verify authenticated user is the article's author (article.authorId == currentUserId)
   * 3. Validate fileUrl is a valid URI, fileName is provided, fileType is 'image' or 'file'
   * 4. Insert new record into economic_political_board_attachments with articleId, fileUrl, fileName, fileType
   * 5. Set createdAt and updatedAt to current timestamp, deletedAt to NULL
   * 6. Increment commentCount on article (if needed, though this is attachment count not comment count)
   * 7. Return the created attachment entity
   *
   * Error cases:
   * - 404 if article does not exist
   * - 403 if user does not own the article
   * - 400 if fileUrl is invalid, fileName empty, or fileType not 'image' or 'file'
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicPoliticalBoardAttachment.ICreate,
  ): Promise<IEconomicPoliticalBoardAttachment> {
    try {
      return await postEconomicPoliticalBoardAdminArticlesArticleIdAttachments({
        admin,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Manage attachments associated with a specific article in the economic/political discussion board.
   *
   * This operation enables article authors to add new file attachments or remove existing attachments from their articles. Each attachment stored in economic_political_board_attachments contains metadata about uploaded files including file URL, original filename, and file type classification (image or document).
   *
   * Security and Authorization:
   * - Article authors can manage attachments on their own articles (author_id matches authenticated user)
   * - Administrators can manage attachments on any article regardless of authorship
   * - Cross-user attachment operations are rejected with access denied errors if user is not author or admin
   * - Unauthorized attempts to attach to articles owned by other users are logged
   *
   * Request Body:
   * Specify attachments to add or remove using operations array. Each operation indicates action type and target attachment ID (for removal) or file metadata (for addition).
   *
   * Response Body:
   * Returns updated list of all attachments for the article after applying specified operations.
   *
   * @param connection
   * @param articleId The unique identifier of the article to manage attachments for
   * @param body Operations to perform on article attachments
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Authenticate user and extract userId from JWT token
   * 2. Verify article exists and retrieve article record
   * 3. Check authorization:
   *    - If user is admin, allow operation
   *    - If user is article author, allow operation
   *    - Otherwise reject with 403 Forbidden
   * 4. Parse operations array from request body
   * 5. For each 'add' operation:
   *    - Validate required fields (fileUrl, fileName, fileType)
   *    - Validate fileType is 'image' or 'file'
   *    - Insert new record into economic_political_board_attachments with articleId, fileUrl, fileName, fileType, createdAt, updatedAt
   * 6. For each 'remove' operation:
   *    - Verify attachment belongs to article (articleId match)
   *    - Soft delete attachment by setting deleted_at to current timestamp
   * 7. Query all non-deleted attachments for the article
   * 8. Return paginated list of attachments with sorting by createdAt desc
   * 9. Handle errors:
   *    - 404 if article not found
   *    - 403 if user not authorized
   *    - 400 if invalid operation type or missing required fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updateAttachments(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicPoliticalBoardAttachment.IUpdateAttachment,
  ): Promise<IPageIEconomicPoliticalBoardAttachment.ISummary> {
    try {
      return await patchEconomicPoliticalBoardAdminArticlesArticleIdAttachments(
        {
          admin,
          articleId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a file attachment from an article.
   *
   * This endpoint allows authorized users to delete a specific attachment from an article. The requester must either be the article's author or have administrator privileges with delete permissions.
   *
   * The operation performs ownership verification for member accounts - a member can only delete attachments from articles they created. Administrators can delete attachments from any article regardless of authorship.
   *
   * Upon successful deletion, the attachment record is permanently removed from the database and the associated file storage is freed. This action cannot be undone.
   *
   * Related operations:
   * - `GET /articles/{articleId}` retrieves article details including its attachment list
   * - `POST /articles/{articleId}/attachments` (if available) adds new attachments to an article
   * - `DELETE /articles/{articleId}` removes an article and automatically deletes all its attachments
   *
   * @param connection
   * @param articleId The unique identifier of the article containing the attachment
   * @param attachmentId The unique identifier of the attachment to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Verify user authentication - require active session for member or admin role
   * 2. Verify user has sufficient authorization:
   *    - For member: verify article.authorId matches authenticated user's ID
   *    - For admin: verify user has delete content permission (all admins have this)
   * 3. Verify article exists and retrieve its record
   * 4. Verify attachment exists and belongs to the specified article (attachment.articleId == article.id)
   * 5. Delete the attachment record from economic_political_board_attachments table
   * 6. Delete the physical file from storage using fileUrl
   * 7. Return empty 204 No Content response
   *
   * Error handling:
   * - 401 Unauthorized if user is not authenticated
   * - 403 Forbidden if user is member but not article author
   * - 404 Not Found if article or attachment does not exist
   * - 404 Not Found if attachment does not belong to specified article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":attachmentId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEconomicPoliticalBoardAdminArticlesArticleIdAttachmentsAttachmentId(
        {
          admin,
          articleId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
