import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicPoliticalBoardAdministratorRole } from "../../../../api/structures/IEconomicPoliticalBoardAdministratorRole";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchEconomicPoliticalBoardAdminAdministratorsAdminIdDemote } from "../../../../providers/patchEconomicPoliticalBoardAdminAdministratorsAdminIdDemote";
import { patchEconomicPoliticalBoardAdminAdministratorsAdminIdPromote } from "../../../../providers/patchEconomicPoliticalBoardAdminAdministratorsAdminIdPromote";

@Controller("/economicPoliticalBoard/admin/administrators/:adminId")
export class EconomicpoliticalboardAdminAdministratorsController {
  /**
   * Promotes a regular administrator to super administrator status within the Economic/Political Discussion Board system.
   *
   * This operation changes the grade of the specified administrator from 'regular' to 'super', granting elevated privileges including the ability to promote/demote other administrators. The promotion is recorded with the current administrator's ID as the promoter and the current timestamp.
   *
   * Only super administrators can perform this operation. The system explicitly prevents self-promotion (super administrators cannot promote themselves) and rejects attempts to promote administrators who already have super grade or those without administrator status.
   *
   * Successful promotion updates the administrator role record with the new grade level, records the promoting administrator's ID in the promoted_by_user_id field, and sets the promoted_at timestamp to the current time.
   *
   * Related operations:
   * - GET /administrators - View all administrators and their current grades
   * - POST /administrators/{adminId}/demote - Demote super administrator to regular administrator
   * - PATCH /admin-requests/{requestId}/approve - Approve new administrator requests
   *
   * @param connection
   * @param adminId UUID of the regular administrator to promote to super administrator
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query economic_political_board_administrator_roles to verify:
   * 1. Current authenticated user has grade='super' (authorization check)
   * 2. Target administrator with id=adminId exists
   * 3. Target administrator's grade is 'regular' (not already super)
   * 4. Target administrator ID is NOT equal to current user ID (self-promotion prevention)
   *
   * Business logic:
   * 1. Update the target administrator's grade from 'regular' to 'super'
   * 2. Set promoted_by_user_id to the current user's ID
   * 3. Set promoted_at to the current timestamp
   * 4. Persist changes to the database within a transaction
   * 5. Return the updated administrator role record
   *
   * Error handling:
   * - Return 403 Forbidden if current user is not a super administrator
   * - Return 404 Not Found if administrator with adminId does not exist
   * - Return 400 Bad Request if target already has super grade
   * - Return 400 Bad Request if attempting self-promotion
   * - Return 400 Bad Request if target is not an administrator
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("promote")
  public async promote(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IEconomicPoliticalBoardAdministratorRole.ISummary> {
    try {
      return await patchEconomicPoliticalBoardAdminAdministratorsAdminIdPromote(
        {
          admin,
          adminId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Demotes a super administrator to regular administrator grade.
   *
   * This operation changes an administrator's grade from 'super' to 'regular', removing their elevated privileges including the ability to promote/demote other administrators.
   *
   * SECURITY REQUIREMENTS:
   * - Only super administrators can execute this operation
   * - Super administrators CANNOT demote themselves
   * - The target administrator must currently hold 'super' grade
   * - The operation records which super administrator performed the demotion
   *
   * BUSINESS CONTEXT:
   * Administrator grade management is restricted to super administrators only. A super administrator maintains the authority to manage other super administrators' privileges, ensuring proper oversight of administrative access. When a super administrator is demoted, they retain all regular administrator capabilities including section management, content moderation, and user banning.
   *
   * RELATED OPERATIONS:
   * - This operation requires the administrator to have 'super' grade (checked via GET /administrators/{adminId})
   * - Demotion action is logged for audit trail purposes
   * - Super administrator requests are managed via /admin/requests endpoints
   *
   * VALIDATION RULES:
   * - Requester must have grade='super'
   * - Target administrator must have grade='super' before demotion
   * - Requester adminId cannot match target adminId
   * - Target must be an existing administrator
   *
   * @param connection
   * @param adminId UUID of the super administrator to demote
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. VERIFY AUTHORIZATION: Check current authenticated user exists in economic_political_board_administrator_roles with grade='super'
   * 2. VALIDATE TARGET: Verify administrator with {adminId} exists in economic_political_board_administrator_roles with grade='super'
   * 3. SELF-DEMOTE CHECK: Reject if {adminId} equals current user's admin role ID
   * 4. UPDATE GRADE: Update the record's grade field from 'super' to 'regular'
   * 5. UPDATE AUDIT: Set promoted_by_user_id to current user's admin role ID (optional, for tracking)
   * 6. RETURN: Return the updated economic_political_board_administrator_roles record
   * 7. LOG: Record the demotion action in audit trail if available
   *
   * ERROR HANDLING:
   * - 403 Forbidden: Requester is not super administrator
   * - 404 Not Found: Target administrator does not exist or does not have 'super' grade
   * - 409 Conflict: Attempting to demote self
   * - 400 Bad Request: Invalid adminId format
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("demote")
  public async demote(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IEconomicPoliticalBoardAdministratorRole.IUpdate> {
    try {
      return await patchEconomicPoliticalBoardAdminAdministratorsAdminIdDemote({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
