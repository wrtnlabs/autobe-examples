import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEconomicPoliticalBoardGuest } from "../../../../api/structures/IEconomicPoliticalBoardGuest";
import { postEconomicPoliticalBoardAuthGuestJoin } from "../../../../providers/postEconomicPoliticalBoardAuthGuestJoin";
import { postEconomicPoliticalBoardAuthGuestRefresh } from "../../../../providers/postEconomicPoliticalBoardAuthGuestRefresh";

@Controller("/economicPoliticalBoard/auth/guest")
export class EconomicpoliticalboardAuthGuestController {
  /**
   * Register a new user account for the Economic/Political Discussion Board. This operation creates both the User and Profile records in a single transaction.
   *
   * The User table stores the email address (unique constraint), hashed password, banned status, and timestamps. Upon successful registration, a corresponding Profile record is automatically created with the user's display name (defaulted to their email prefix) and an empty bio.
   *
   * Security considerations: Passwords are hashed using bcrypt before storage. Email addresses are validated for format and uniqueness before account creation. Banned users cannot register - the system checks isBanned flag during registration.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials including email address, password, and optionally a display name.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Service: Create new user account and profile. Algorithm: Validate email uniqueness, hash password, create User and Profile records. Steps: 1) Check if email exists in economic_political_board_administrator_roles table 2) Validate email format 3) Validate password length/complexity 4) Hash password using bcrypt 5) Insert into economic_political_board_administrator_roles with email, passwordHash, isBanned=false 6) Insert into economic_political_board_administrator_profiles with userId, displayName (default from email), bio (empty) 7) Generate JWT access token and refresh token 8) Return tokens with user info. Validation: Email format, password min 8 chars, email not already registered.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEconomicPoliticalBoardGuest.IJoin,
  ): Promise<IEconomicPoliticalBoardGuest.IAuthorized> {
    try {
      return await postEconomicPoliticalBoardAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew the authentication access token using a valid refresh token. This operation allows users to maintain their authenticated session without re-entering credentials.
   *
   * The refresh token is validated against the JWT signature and expiration timestamp. If valid, a new access token is issued along with an optional new refresh token. This token rotation pattern enhances security by limiting the lifetime of access tokens while maintaining session continuity.
   *
   * Security considerations: Refresh tokens must be kept secure and should not be shared. If a refresh token is compromised, it can be used to generate new access tokens until expiration. Users should implement secure storage for tokens on the client side.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for generating new access token.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Service: Refresh JWT access token using refresh token. Algorithm: Validate refresh token, check expiration, issue new tokens. Steps: 1) Extract refresh token from request body 2) Verify token signature and expiration 3) If valid, generate new access token and optional new refresh token 4) Return new tokens. Validation: Refresh token must be valid, not expired, and belong to active user. If user is banned, reject refresh request.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEconomicPoliticalBoardGuest.IRefresh,
  ): Promise<IEconomicPoliticalBoardGuest.IAuthorized> {
    try {
      return await postEconomicPoliticalBoardAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
