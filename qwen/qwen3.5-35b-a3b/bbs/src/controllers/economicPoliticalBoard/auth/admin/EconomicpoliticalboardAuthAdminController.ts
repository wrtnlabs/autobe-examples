  /**
   * Administrator account registration for the Economic/Political Discussion Board system.
   *
   * This operation creates a new admin account by validating the provided email and password against system requirements. The email must be unique across all users in the economic_political_board_users table, following standard email format validation. The password undergoes secure hashing using industry-standard algorithms before storage.
   *
   * Upon successful registration, the system automatically creates a corresponding Profile record linked to the new User via userId. The profile is initialized with a default display name (derived from the email prefix) and an empty bio field. The registration also checks for any existing ban records in the economic_political_board_ban_records table - if a ban record exists for this email, the registration is rejected to prevent banned users from circumventing bans.
   *
   * The response includes JWT access and refresh tokens that embed the admin's user ID and email in the claims. If the user already exists in the economic_political_board_administrator_roles table with a registered admin grade (regular or super), those privileges are included in the token. All tokens follow the system's session and token policy defined in the authentication flows.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator registration credentials including email and password
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate email format and uniqueness against economic_political_board_users table. Hash password using secure algorithm (bcrypt/argon2). Create User record with email, passwordHash, createdAt timestamp. Auto-create Profile record with default displayName and empty bio. Check if user was previously banned - if ban record exists, prevent registration. Return JWT access and refresh tokens with admin-specific claims including userId, email, and adminGrade (if already in administrator_roles table).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
