export async function test_api_task_deletion_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create member account and organization
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuthorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      org_name: RandomGenerator.name(),
      org_currency: RandomGenerator.pick(["USD", "EUR", "KRW"]),
      org_description: RandomGenerator.paragraph(),
      org_logo_uri: typia.random<string & tags.Format<"uri">>(),
      org_timezone: RandomGenerator.pick([
        "UTC",
        "Asia/Seoul",
        "America/New_York",
      ]),
      org_fiscal_month: RandomGenerator.pick([1, 4, 7, 10]),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  typia.assert(memberAuthorized);
  // 2. Create task UUID for deletion
  const taskId = typia.random<string & tags.Format<"uuid">>();
  // 3. Delete task with member connection
  const deleteResponse = await api.functional.hrmPlatform.member.tasks.erase(
    memberConnection,
    {
      taskId,
    },
  );
  typia.assert(deleteResponse);
  // 4. Verify 204 No Content (response should be void)
  TestValidator.equals("delete response is void", deleteResponse, undefined);
}
