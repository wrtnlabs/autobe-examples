export async function test_api_member_dashboard_empty_state(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create new member with organization (no additional activity)
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      org_name: RandomGenerator.name(),
      org_currency: typia.random<string>() ?? "USD",
      org_description: RandomGenerator.paragraph(),
      org_logo_uri: typia.random<string & tags.Format<"uri">>(),
      org_timezone: RandomGenerator.pick(["UTC", "Asia/Seoul"]),
      org_fiscal_month: RandomGenerator.pick([1, 4, 7, 10]),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  typia.assert(memberAuth);
  // 2. Call dashboard endpoint
  const dashboard =
    await api.functional.hrmPlatform.member.dashboard.at(memberConnection);
  typia.assert(dashboard);
  // 3. Validate empty state fields
  TestValidator.equals("hoursLoggedToday", dashboard.hoursLoggedToday, 0);
  TestValidator.equals("hoursLoggedThisWeek", dashboard.hoursLoggedThisWeek, 0);
  TestValidator.equals("activeTimer", dashboard.activeTimer, null);
  TestValidator.equals("recentTimelogs", dashboard.recentTimelogs, []);
  TestValidator.equals("pendingTimesheet", dashboard.pendingTimesheet, null);
  TestValidator.equals("assignedTasks", dashboard.assignedTasks, []);
}
