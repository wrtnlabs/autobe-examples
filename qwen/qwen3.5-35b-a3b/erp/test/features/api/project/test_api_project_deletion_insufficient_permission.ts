export async function test_api_project_deletion_insufficient_permission(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create member A (organization owner with project:manage permission)
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberAAuth = await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      org_name: RandomGenerator.name(),
      org_currency: RandomGenerator.pick(["USD", "EUR", "KRW"]),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberAAuth);
  // Step 2: Member A creates a project
  const project = await generate_random_hrm_platform_member_projects_create(
    memberAConnection,
    {
      body: {
        name: RandomGenerator.name(2),
        color_code: "#" + RandomGenerator.alphaNumeric(6),
      },
    },
  );
  typia.assert(project);
  // Step 3: Create member B (separate account, different organization)
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberBAuth = await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      org_name: RandomGenerator.name(),
      org_currency: RandomGenerator.pick(["USD", "EUR", "KRW"]),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberBAuth);
  // Step 4: Attempt to delete project using Member B's credentials
  // Member B belongs to a different organization, so they should not have project:manage permission
  await TestValidator.error(
    "member B cannot delete project from member A's organization",
    async () => {
      await api.functional.hrmPlatform.member.projects.erase(
        memberBConnection,
        {
          projectId: project.id,
        },
      );
    },
  );
  // Step 5: Verify project still exists by attempting to delete it again
  // It should still be protected - project not deleted by the first failed attempt
  await TestValidator.error(
    "project still exists and protected after first failed deletion attempt",
    async () => {
      await api.functional.hrmPlatform.member.projects.erase(
        memberBConnection,
        {
          projectId: project.id,
        },
      );
    },
  );
}
