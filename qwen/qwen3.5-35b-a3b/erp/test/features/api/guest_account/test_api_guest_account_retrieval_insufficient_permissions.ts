export async function test_api_guest_account_retrieval_insufficient_permissions(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin/audit member with guest data permissions
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_member_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmsMember.IJoin,
  });
  typia.assert(adminAuth);
  // Create employee member without guest data permissions
  const employeeConnection: api.IConnection = { host: connection.host };
  const employeeAuth = await authorize_member_join(employeeConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmsMember.IJoin,
  });
  typia.assert(employeeAuth);
  // 2. Employee attempts to retrieve guest account without permissions
  // Should receive 403 Forbidden
  await TestValidator.error(
    "employee without guest permissions should get 403",
    async () => {
      const guestId = typia.random<string & tags.Format<"uuid">>();
      await api.functional.hrms.guests.at(employeeConnection, {
        guestId,
      });
    },
  );
}
