export async function test_api_employee_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Member joins organization
  const joinConnection: api.IConnection = { host: connection.host };
  const joinResult = await authorize_member_join(joinConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234Test!",
      name: RandomGenerator.name(),
      org_name: RandomGenerator.name(),
      org_currency: "KRW",
      org_description: RandomGenerator.paragraph(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(joinResult);
  // 2. Use member connection to retrieve non-existent employee
  const employeeConnection: api.IConnection = { host: connection.host };
  employeeConnection.headers = {
    Authorization: joinResult.token.access,
  };
  try {
    await api.functional.hrmPlatform.member.employees.at(employeeConnection, {
      employeeCode: "INVALID-EMP-CODE-999",
    });
    throw new Error("Expected 404 not found error");
  } catch (error) {
    if (typia.is<api.HttpError>(error)) {
      TestValidator.equals("status code", error.status, 404);
    } else {
      throw new Error("Unexpected error type");
    }
  }
}