export async function test_api_organization_retrieval_unauthorized_access(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create Member A with their organization
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberA = await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmsMember.IJoin,
  });
  typia.assert(memberA);
  // Extract Organization A ID from member A's organization memberships
  const organizationAId = memberA.organization_memberships[0].organization.id;
  // 2. Create Member B with their own organization (separate flow)
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberB = await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmsMember.IJoin,
  });
  typia.assert(memberB);
  // 3. Member B attempts to access Organization A (which they don't belong to)
  // Organization should return 404 because Member B is not a member
  await TestValidator.httpError(
    "should return 404 for unauthorized organization access",
    [404],
    async () => {
      await api.functional.hrms.member.organizations.at(memberBConnection, {
        organizationId: organizationAId,
      });
    },
  );
}
