export async function test_api_timer_discard_no_active_timer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new member (ensures no active timer exists)
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmsMember.IJoin,
  });
  typia.assert(authorized);
  // 2. Verify discard fails with 404 when no active timer exists
  await TestValidator.httpError(
    "discard should fail with 404 when no active timer exists",
    [404],
    async () => {
      await api.functional.hrms.member.timer.discard(memberConnection);
    },
  );
}