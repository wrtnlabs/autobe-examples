export async function test_api_timelog_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create member account
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmsMember.IJoin,
  });
  typia.assert(member);
  // 2. Generate non-existent UUID
  const nonExistentId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve non-existent timelog
  // The API should return 404 Not Found
  await TestValidator.httpError("timelog should return 404", 404, async () => {
    await api.functional.hrms.member.timelogs.at(memberConnection, {
      timelogId: nonExistentId,
    });
  });
}