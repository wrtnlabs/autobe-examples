export async function test_api_project_creation_basic(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register member with organization context
  const memberConnection: api.IConnection = { host: connection.host };
  const auth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      org_name: RandomGenerator.name(),
      org_currency: RandomGenerator.pick(["USD", "EUR", "KRW"]),
      org_description: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(auth);
  // 2. Create project with minimal required fields
  const project = await api.functional.hrmPlatform.member.projects.create(
    memberConnection,
    {
      body: {
        name: RandomGenerator.name(2),
        color_code: RandomGenerator.pick([
          "#FF5733",
          "#33FF57",
          "#3357FF",
          "#F3FF33",
          "#FF33F3",
        ]),
      } satisfies IHrmPlatformProject.ICreate,
    },
  );
  typia.assert(project);
  // 3. Validate project creation
  TestValidator.equals("project status is active", project.status, "active");
  TestValidator.equals(
    "project organization owner is member",
    project.organization.owner.id,
    auth.member.id,
  );
  TestValidator.equals(
    "created_at timestamp exists",
    project.created_at !== undefined,
    true,
  );
  TestValidator.predicate(
    "project has valid UUID id",
    /^[0-9a-f-]{36}$/i.test(project.id),
  );
  TestValidator.predicate(
    "organization has valid UUID id",
    /^[0-9a-f-]{36}$/i.test(project.organization.id),
  );
}
