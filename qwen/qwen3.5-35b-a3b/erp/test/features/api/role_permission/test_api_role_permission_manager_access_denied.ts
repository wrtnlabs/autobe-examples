export async function test_api_role_permission_manager_access_denied(
  connection: api.IConnection,
): Promise<void> {
  // 1. Join as Owner user with full permissions in their organization
  const ownerConnection: api.IConnection = { host: connection.host };
  const owner = await authorize_member_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      org_name: RandomGenerator.name(),
      org_currency: RandomGenerator.pick(["USD", "EUR", "KRW"]),
      org_description: RandomGenerator.paragraph(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  typia.assert(owner);
  // 2. Join as separate member (in their own organization)
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      org_name: RandomGenerator.name(),
      org_currency: RandomGenerator.pick(["USD", "EUR", "KRW"]),
      org_description: RandomGenerator.paragraph(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  typia.assert(member);
  // 3. Owner creates a permission in their organization (as Owner, this should succeed)
  // Since we don't have APIs to create roles or list them, we'll test access control
  // by having the member attempt to assign permissions using the Owner's org context
  // 4. Test that member (without access to Owner's organization) cannot assign permissions
  // The member should be denied because they don't have employee:manage permission
  // in the Owner's organization (they are Owner in their own separate organization)
  await TestValidator.error(
    "member cannot assign permissions to another organization's roles",
    async () => {
      // Member attempts to assign permissions using a placeholder roleId
      // This should fail due to insufficient permissions/access control
      const testRoleId: string & tags.Format<"uuid"> = typia.random<
        string & tags.Format<"uuid">
      >();
      await api.functional.hrmPlatform.member.roles.permissions.create(
        memberConnection,
        {
          roleId: testRoleId,
          body: {
            code: RandomGenerator.alphabets(10),
            description: RandomGenerator.paragraph(),
          } satisfies IHrmPlatformRole.IPermissionCreate,
        },
      );
    },
  );
}
