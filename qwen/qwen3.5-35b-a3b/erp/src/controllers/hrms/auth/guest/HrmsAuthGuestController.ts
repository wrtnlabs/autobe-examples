import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IHrmsGuest } from "../../../../api/structures/IHrmsGuest";
import { postHrmsAuthGuestJoin } from "../../../../providers/postHrmsAuthGuestJoin";
import { postHrmsAuthGuestRefresh } from "../../../../providers/postHrmsAuthGuestRefresh";

@Controller("/hrms/auth/guest")
export class HrmsAuthGuestController {
  /**
   * ## Guest Account Registration
   *
   * This endpoint allows unauthenticated visitors to register as temporary guest users by providing their email address. The system creates a guest account record in the hrms_guests table, which serves as a temporary identity for unauthenticated visitors who need access to certain resources.
   *
   * The registration process captures the device fingerprint from request headers to establish device-based identification for the guest session. This enables the system to track and manage guest sessions across multiple requests while maintaining security boundaries. The email address is validated for format and uniqueness before account creation.
   *
   * Upon successful registration, the system creates an initial session record in the hrms_guest_sessions table, generating both access and refresh tokens. The access token is used for authentication in subsequent API requests, while the refresh token enables token renewal without requiring re-registration.
   *
   * Guest accounts have limited permissions compared to registered member accounts. Guests cannot access organization-specific data, cannot create or join organizations, and have restricted visibility into system resources. This ensures security while allowing unauthenticated visitors to explore public-facing features.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest registration credentials containing email and optional device fingerprint
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Create a new guest account by accepting email address. Generate device fingerprint from client headers. Insert into hrms_guests table. Create initial session in hrms_guest_sessions. Return JWT tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmsGuest.IJoin,
  ): Promise<IHrmsGuest.IAuthorized> {
    try {
      return await postHrmsAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * ## Token Refresh for Guest Sessions
   *
   * This endpoint enables guest users to renew their authentication tokens without re-registering. When a guest's access token expires, they can use their refresh token to obtain a new pair of access and refresh tokens.
   *
   * The refresh operation validates the provided refresh token against records in the hrms_guest_sessions table. The system checks token validity, expiration status, and ensures the session is still active. If validation passes, the system generates new access and refresh tokens and updates the session record in the database.
   *
   * Token renewal maintains the guest's temporary identity while extending their session lifecycle. The process is stateless for access tokens (JWT-based) but updates the session state for refresh token rotation, enhancing security by preventing token replay attacks.
   *
   * Guests should call this endpoint before their access token expires to maintain uninterrupted service. The refresh token has a longer validity period than the access token but is still subject to expiration and rotation policies defined in the hrms_guest_sessions schema.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token from guest session
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Accept refresh token from guest session. Validate token expiry in hrms_guest_sessions table. If valid, generate new access and refresh tokens. Update session record with new tokens and updated expiresAt timestamp. Return new token pair.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IHrmsGuest.IRefresh,
  ): Promise<IHrmsGuest.IAuthorized> {
    try {
      return await postHrmsAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
