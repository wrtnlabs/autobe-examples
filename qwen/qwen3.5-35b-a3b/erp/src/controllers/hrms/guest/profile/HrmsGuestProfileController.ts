import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmsMemberProfile } from "../../../../api/structures/IHrmsMemberProfile";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { putHrmsGuestProfile } from "../../../../providers/putHrmsGuestProfile";

@Controller("/hrms/guest/profile")
export class HrmsGuestProfileController {
  /**
   * Update the current authenticated user's global profile information.
   *
   * This operation allows users to modify their display name, phone number, and/or avatar image. The profile is global and shared across all organizations the user belongs to, meaning any changes will be reflected immediately in all organizational contexts.
   *
   * The display name is a required field that represents the user's name as shown to other users in the system. The phone number is an optional field that may be used for communication purposes. The avatar image is an optional file that provides visual identification.
   *
   * If an update partially fails (e.g., avatar upload succeeds but phone update fails), the entire operation is rolled back and the existing profile information remains unchanged to maintain data consistency.
   *
   * The user must be authenticated to perform this operation. The profile being updated is always the authenticated user's own profile - users cannot modify other users' profiles through this endpoint.
   *
   * @param connection
   * @param body Profile update fields. At least one field must be provided.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query the authenticated user's record from hrms_members table using the user ID from the session token.
   *
   * Validate input parameters:
   * - displayName: Must be non-empty string, maximum length 100 characters
   * - phone: If provided, validate as international E.164 format (optional)
   * - avatarId: Must reference an existing hrms_files record belonging to this user
   *
   * Execute transaction:
   * 1. Begin database transaction
   * 2. Update hrms_members record with new display name if provided
   * 3. Update phone number if provided
   * 4. Update avatar reference (hrms_files.id) if avatarId is provided
   * 5. Set updatedAt timestamp
   * 6. Commit transaction
   *
   * Rollback on any error to maintain consistency.
   *
   * Return updated profile with all current values including the new avatar image URL from hrms_files.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IHrmsMemberProfile.IUpdate,
  ): Promise<IHrmsMemberProfile> {
    try {
      return await putHrmsGuestProfile({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
