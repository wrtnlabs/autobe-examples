import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmsProject } from "../../../../../api/structures/IHrmsProject";
import { IPageIHrmsProject } from "../../../../../api/structures/IPageIHrmsProject";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchHrmsMemberProjectsAnalytics } from "../../../../../providers/patchHrmsMemberProjectsAnalytics";

@Controller("/hrms/member/projects/analytics")
export class HrmsMemberProjectsAnalyticsController {
  /**
   * Retrieve comprehensive analytics data for projects within the organization, including budget utilization, time tracking summaries, and task analysis.
   *
   * This endpoint aggregates data from multiple sources to provide project management insights. It calculates budget utilization percentages by comparing actual hours spent (from timelogs) against budgeted hours (from project records). The endpoint also provides task distribution across projects, showing how work is allocated at the task level.
   *
   * Users with report:view permission can access this analytics data. The endpoint supports filtering by project status (active, archived, completed) to focus on specific project states. Date range filtering allows analysis of time tracking data within custom periods.
   *
   * The response includes aggregated metrics per project such as total planned hours, actual hours logged, budget utilization percentage, and task counts categorized by status (pending, in-progress, completed). Task grouping enables detailed breakdown of time allocation across project tasks.
   *
   * @param connection
   * @param body Analytics filtering and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrms_projects table filtered by organization context (inferred from authenticated user's active organization).
   *
   * Perform LEFT JOIN with hrms_timelogs on project_id to aggregate time tracking data (SUM of duration, COUNT of entries).
   *
   * Perform LEFT JOIN with hrms_tasks on project_id to aggregate task data (COUNT by status).
   *
   * Filter timelogs by date range if provided in request body (date_from, date_to parameters).
   *
   * Filter projects by status if status filter provided (active, archived, completed).
   *
   * Calculate budget utilization: (SUM(timelogs.duration) / projects.budget_hours) * 100, handling null/zero budget_hours case.
   *
   * Apply pagination using cursor-based approach for large result sets.
   *
   * Sort results by provided field (project_name, budget_utilization, actual_hours, created_at) with order direction.
   *
   * Return aggregated results with project metadata, time metrics, task counts, and budget utilization percentage.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmsProject.IRequest,
  ): Promise<IPageIHrmsProject.ISummary> {
    try {
      return await patchHrmsMemberProjectsAnalytics({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
