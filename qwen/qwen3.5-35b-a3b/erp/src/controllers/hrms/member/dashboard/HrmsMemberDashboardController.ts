import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmsProject } from "../../../../api/structures/IHrmsProject";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmsMemberDashboard } from "../../../../providers/getHrmsMemberDashboard";

@Controller("/hrms/member/dashboard")
export class HrmsMemberDashboardController {
  /**
   * Retrieve a personalized dashboard displaying time tracking and organizational metrics tailored to the authenticated user's role and permissions.
   *
   * The dashboard automatically adapts to the user's permission level. Users without report:view permission receive a personal dashboard showing individual metrics including hours logged today and this week, active timer status, recent time entries, pending timesheets, and assigned tasks. This self-service dashboard enables employees to monitor their own time tracking activities and task assignments.
   *
   * Users with report:view permission in their organization context receive an organization dashboard providing management oversight. This includes total active employee count, total hours logged by all employees this week, number of pending timesheets awaiting approval, projects with budget utilization exceeding 80 percent, and the top five employees by hours logged this week. The organization dashboard serves as a leadership tool for monitoring team performance and identifying budget concerns.
   *
   * Every dashboard request is scoped to the user's selected organization context. The endpoint validates that the user belongs to the organization before returning any metrics. The response includes a generation timestamp to indicate when the dashboard data was last refreshed.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query user's selected organization context and evaluate report:view permission.
   *
   * For personal dashboard (no report:view permission):
   * 1. Calculate hours logged today: Sum timelogs created by employee where log_date equals current date in organization timezone
   * 2. Calculate hours logged this week: Sum timelogs from Monday to Sunday of current week
   * 3. Check active timer: Query hrms_timers table for running timer belonging to employee
   * 4. Fetch recent timelogs: Query last 5 timelogs ordered by created_at descending, including project and task references
   * 5. Check pending timesheets: Count submitted timesheets for current week with status awaiting_approval
   * 6. Fetch assigned tasks: Query tasks where assigned_employee_id equals user's employee_id AND status is open or in_progress
   *
   * For organization dashboard (has report:view permission):
   * 1. Query hrms_employees: Count active employees (active = true) in organization
   * 2. Sum timelogs: Calculate total hours logged by all active employees this week (Monday to Sunday)
   * 3. Count pending timesheets: Query timesheets where status = awaiting_approval AND employee belongs to organization
   * 4. Identify budget alerts: Query projects where total_hours_logged / budget_hours > 0.8 AND budget_hours > 0
   * 5. Rank top employees: Group timelogs by employee, sum hours this week, order descending, take top 5
   *
   * Return response with dashboard_type flag, all applicable metrics, and generation timestamp. Apply organization timezone for all date calculations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmsProject> {
    try {
      return await getHrmsMemberDashboard({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
