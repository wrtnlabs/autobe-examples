  /**
   * Create a new organization membership by assigning an existing user to an organization with a specific role.
   *
   * This operation links a registered user (member) to an organization, establishing their membership record and role-based access rights. The membership is the foundation for all organizational access, determining what data the employee can view and what actions they can perform.
   *
   * The requesting user must have the employee:manage permission within the target organization to perform this operation. This permission is typically held by organization owners and managers who are responsible for building their team.
   *
   * Before creating the membership, the system validates that:
   * - The target user account exists and is active
   * - The target organization exists and is accessible to the requesting user
   * - The specified role exists within the organization
   * - No duplicate membership already exists for this member in this organization (enforced by unique constraint on [hrms_organization_id, hrms_member_id])
   * - The role has appropriate permissions that align with organizational policies
   *
   * Upon successful creation, the new membership record is returned with its auto-generated UUID identifier and timestamps. The newly added employee immediately gains access to the organization's data based on their assigned role's permission combination.
   *
   * @param connection
   * @param body Organization membership creation data including member reference, organization reference, and role assignment.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Service layer logic for creating organization membership:
   *
   * 1. Validate employee:manage permission on the requesting user for the target organization.
   *
   * 2. Validate existence and active status of the target member by hrms_member_id using hrms_members table.
   *
   * 3. Validate existence and ownership/access of the target organization by hrms_organization_id using hrms_organizations table.
   *
   * 4. Validate existence and ownership of the target role by hrms_organization_role_id using hrms_organization_roles table, ensuring it belongs to the target organization.
   *
   * 5. Check for duplicate membership by querying hrms_organization_members with where clause: { hrms_member_id, hrms_organization_id, deleted_at: null }.
   *
   * 6. If any validation fails, throw appropriate error (NotFound, Forbidden, Conflict).
   *
   * 7. Insert new record into hrms_organization_members with:
   *    - id: Auto-generated UUID
   *    - hrms_member_id: From request body
   *    - hrms_organization_id: From request body
   *    - hrms_organization_role_id: From request body
   *    - created_at: Current timestamp (transaction time)
   *    - updated_at: Current timestamp (transaction time)
   *    - deleted_at: null
   *
   * 8. Commit transaction and return the newly created membership record.
   *
   * 9. Optionally create an activity log entry recording the membership creation with performed_by user reference.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmsOrganizationMember.ICreate,
  ): Promise<IHrmsOrganizationMember> {
    try {
      return await postHrmsMemberOrganizationMembers({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

