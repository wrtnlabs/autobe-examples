import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmsTimelog } from "../../../../api/structures/IHrmsTimelog";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { patchHrmsMemberMetrics } from "../../../../providers/patchHrmsMemberMetrics";

@Controller("/hrms/member/metrics")
export class HrmsMemberController {
  /**
   * Retrieve aggregated organizational metrics and analytics data.
   *
   * This endpoint provides a comprehensive view of organization-wide metrics including employee statistics, time tracking data, timesheet approval status, and project budget utilization. The metrics are calculated from multiple database entities and presented in a unified response structure.
   *
   * The endpoint supports filtering by date ranges and metric categories to provide focused insights. Users with report:view permission can access organization-level dashboard metrics including total active employees, current week hours logged, pending timesheet approvals, and projects approaching budget limits.
   *
   * Metrics are calculated in real-time from the underlying database to ensure current data. The response includes generation timestamps to indicate when metrics were computed.
   *
   * @param connection
   * @param body Optional filtering criteria for metrics
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve organizational metrics from multiple sources:
   *
   * 1. Active employee count: Query hrms_employees where status='active' and deleted_at IS NULL, count within current organization context
   *
   * 2. Current week hours: Calculate sum of duration_minutes from hrms_timelogs for date range covering Monday to Sunday of current week, exclude deleted timelogs
   *
   * 3. Pending timesheets: Count hrms_timesheets where status='submitted' and deleted_at IS NULL, belongs to organization employees
   *
   * 4. High utilization projects: Select hrms_projects where status IN ('active', 'archived') AND budget_hours IS NOT NULL AND budget_hours > 0, calculate timelog duration sum, filter where utilization > 80%
   *
   * 5. Apply organization context from authentication token
   *
   * 6. Return aggregated metrics with current timestamp
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async metrics(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmsTimelog.IRequest,
  ): Promise<IHrmsTimelog> {
    try {
      return await patchHrmsMemberMetrics({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
