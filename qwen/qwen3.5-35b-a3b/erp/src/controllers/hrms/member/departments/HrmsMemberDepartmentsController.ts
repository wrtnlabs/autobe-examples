import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmsDepartment } from "../../../../api/structures/IHrmsDepartment";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteHrmsMemberDepartmentsDepartmentId } from "../../../../providers/deleteHrmsMemberDepartmentsDepartmentId";
import { getHrmsMemberDepartmentsDepartmentId } from "../../../../providers/getHrmsMemberDepartmentsDepartmentId";
import { putHrmsMemberDepartmentsDepartmentId } from "../../../../providers/putHrmsMemberDepartmentsDepartmentId";

@Controller("/hrms/member/departments/:departmentId")
export class HrmsMemberDepartmentsController {
  /**
   * Retrieve detailed information about a specific organizational department by its unique identifier.
   *
   * This operation returns complete department data including the department name, optional description, parent-child hierarchy relationship, and timestamps for creation and last modification. The response includes the department's organization context and whether the department has been soft deleted.
   *
   * All employees within an organization can view department details. The operation validates that the requested department belongs to the current user's organization and returns a 404 error if the department does not exist, has been soft deleted, or is not accessible within the user's organization context.
   *
   * @param connection
   * @param departmentId Unique identifier of the department to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrms_departments table for a specific department by UUID id.
   * Validate that the department belongs to the current user's organization context.
   * Include organization details and parent department information in the response if present.
   * Handle soft delete: return 404 Not Found if deleted_at is not null.
   * Perform joins to resolve parent department reference and organization reference.
   * Return complete department entity with all fields: id, organization_id, parent_id, name, description, created_at, updated_at, deleted_at.
   * Validate UUID format for departmentId parameter.
   * Enforce organization context isolation - users can only access departments within their organization.
   * Log the view operation in activity log for audit purposes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string & tags.Format<"uuid">,
  ): Promise<IHrmsDepartment> {
    try {
      return await getHrmsMemberDepartmentsDepartmentId({
        member,
        departmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing department's details within an organization.
   *
   * This operation allows users with organization management permission to modify department information including the department name, description, and parent department assignment. The department name must remain unique within the organization after the update.
   *
   * The parent department can be changed to reassign the department to a different parent, or set to null to make it a top-level department. The new parent must exist within the same organization.
   *
   * This operation does not automatically update employees assigned to the department. Employee department assignments remain unchanged when a department's name, description, or parent is modified.
   *
   * All changes are logged in the activity log with the timestamp and the user who performed the update. The updated_at timestamp is automatically updated to reflect when the modification occurred.
   *
   * @param connection
   * @param departmentId Target department's unique identifier
   * @param body Department fields to update (all fields optional for selective update)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrms_departments table to fetch the department record by UUID id.
   * Verify the department exists and belongs to the current organization context.
   * Validate that the requesting user has org:manage permission.
   *
   * For each update field:
   * - name: Check uniqueness constraint against other departments in same organization
   * - description: No special validation required, accepts any string or null
   * - parent_id: Verify parent department exists in same organization if provided
   *
   * Apply updates to the record, set updated_at to current UTC timestamp.
   * Return the complete updated department record.
   * Log the update operation in hrms_activity_logs table with operation type 'department.update'.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmsDepartment.IUpdate,
  ): Promise<IHrmsDepartment> {
    try {
      return await putHrmsMemberDepartmentsDepartmentId({
        member,
        departmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Marks a department as deleted by setting the soft delete timestamp, removing it from active department lists while preserving the record for audit purposes.
   *
   * This operation performs a soft delete on the Department table, marking the department as deleted via the `deleted_at` field. The department record is not physically removed from the database but is excluded from active department queries. This preserves the department's historical data and allows for potential restoration if required.
   *
   * The deletion operation performs strict validation before executing. Child departments must not exist under the target department - if any children are found, the operation is rejected and the user must reassign or delete them first. This prevents accidental loss of department hierarchy structure.
   *
   * Employees with active contracts or time tracking records associated with this department can still have the department soft deleted. Their assignments are simply set to null, removing the association without affecting the employees themselves. The deletion does not affect projects, tasks, or other entities that may reference the department indirectly through employees.
   *
   * The operation requires org:manage permission scoped to the organization. Users without this permission are denied access. The soft delete operation is logged in the activity log, recording the timestamp, user who performed the deletion, and the deleted department's name.
   *
   * @param connection
   * @param departmentId The unique identifier of the department to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve the department record matching the UUID path parameter from hrms_departments table.
   *
   * Perform validation checks:
   * 1. Verify user has org:manage permission for the organization context
   * 2. Check for child departments (where parent_id = target department's id)
   * 3. If child departments exist, reject with error listing blocking children
   * 4. Verify department exists in the same organization as current context
   *
   * Execute deletion:
   * 1. Delete the department record from hrms_departments table
   * 2. Update all employee records to set department_id to null (removes association)
   * 3. Create activity log entry recording: deletion timestamp, user_id, department name
   *
   * Error handling:
   * - 404 Not Found: Department does not exist or organization mismatch
   * - 403 Forbidden: User lacks org:manage permission
   * - 409 Conflict: Child departments exist (include list in error response)
   * - 400 Bad Request: Circular hierarchy detected (prevented during creation, but validate)
   *
   * Transaction requirements: Perform employee updates and department deletion in a single transaction to maintain data consistency.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmsMemberDepartmentsDepartmentId({
        member,
        departmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
