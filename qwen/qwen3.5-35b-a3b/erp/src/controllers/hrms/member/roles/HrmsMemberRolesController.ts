import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmsOrganizationRole } from "../../../../api/structures/IHrmsOrganizationRole";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putHrmsMemberRolesRoleId } from "../../../../providers/putHrmsMemberRolesRoleId";

@Controller("/hrms/member/roles/:roleId")
export class HrmsMemberRolesController {
  /**
   * Update an existing organization role with new name and/or permissions.
   *
   * This operation allows organization owners to modify custom roles created within the organization. The role name and/or permission set can be updated to reflect changing organizational needs.
   *
   * Built-in roles (Owner, Manager, Employee) cannot be updated. These foundational roles have immutable permissions that cannot be modified under any circumstances. The system will reject update attempts for built-in roles.
   *
   * Only users with Owner role in the organization can perform this operation. The system verifies the requesting user's role before processing the update request.
   *
   * When a role is updated, the changes take effect immediately for all members assigned to that role. All permissions associated with the role are replaced by the new permission set.
   *
   * @param connection
   * @param roleId The unique identifier of the role to update
   * @param body Role update data containing fields to modify
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update an organization role record with provided fields.
   *
   * Database Operation:
   * - Update hrms_organization_roles record by roleId
   * - Only allow updates to name and permissions fields
   * - Reject if role is built-in (role is_internal = true or role name in ['Owner', 'Manager', 'Employee'])
   *
   * Security Validation:
   * - Verify user belongs to the organization
   * - Verify user has Owner role in the organization
   * - Reject if user is not an owner
   *
   * Business Logic:
   * - Validate role name is unique within the organization
   * - Validate permissions array contains valid permission strings
   * - Validate role name is not empty and within length limits
   * - Clear role's cache after update to ensure immediate effect
   *
   * Error Handling:
   * - Return 404 if role not found
   * - Return 403 if user is not an organization owner
   * - Return 400 if role is built-in and cannot be modified
   * - Return 400 if role name already exists (duplicate)
   * - Return 400 if permissions array is invalid
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmsOrganizationRole.IUpdate,
  ): Promise<IHrmsOrganizationRole> {
    try {
      return await putHrmsMemberRolesRoleId({
        member,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
