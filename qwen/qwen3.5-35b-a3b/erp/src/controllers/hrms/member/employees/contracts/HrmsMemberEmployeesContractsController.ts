import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmsEmployeeContract } from "../../../../../api/structures/IHrmsEmployeeContract";
import { IPageIHrmsEmployeeContract } from "../../../../../api/structures/IPageIHrmsEmployeeContract";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmsMemberEmployeesEmployeeIdContractsContractId } from "../../../../../providers/getHrmsMemberEmployeesEmployeeIdContractsContractId";
import { patchHrmsMemberEmployeesEmployeeIdContracts } from "../../../../../providers/patchHrmsMemberEmployeesEmployeeIdContracts";
import { postHrmsMemberEmployeesEmployeeIdContracts } from "../../../../../providers/postHrmsMemberEmployeesEmployeeIdContracts";

@Controller("/hrms/member/employees/:employeeId/contracts")
export class HrmsMemberEmployeesContractsController {
  /**
   * Create a new employment contract for an existing employee.
   *
   * This operation allows authorized users to create a new contract record that documents the employment terms for a specific employee. The contract includes the start date, pay rate, pay period (hourly, daily, weekly, or monthly), and working hours per week. An optional notes field may be used to document additional terms or conditions.
   *
   * When a new contract is created, the system automatically terminates the previous active contract by setting its end date to the day before the new contract's start date. This ensures that only one contract is active at any given time while maintaining a complete historical record of all employment terms.
   *
   * Only users with employee management permission can create contracts for employees. Users without this permission are blocked from creating contracts. The system validates that the employee exists and that the requesting user has the necessary permissions before allowing contract creation.
   *
   * @param connection
   * @param employeeId The unique identifier of the employee for whom to create the contract
   * @param body Contract creation data including employment terms and conditions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new hrms_employee_contracts record with the provided contract details.
   *
   * Service layer logic:
   * 1. Validate that the employee exists by querying hrms_employees table using the employeeId path parameter
   * 2. Verify the requesting user has employee management permission (organization_role_permissions with manage_employees flag)
   * 3. Check for any existing active contract (end_date is NULL) for this employee
   * 4. If an active contract exists, update its end_date to the day before the new contract's start_date
   * 5. Insert new contract record with: employee_id, start_date, pay_rate, pay_period, working_hours_per_week, notes (optional)
   * 6. Return the complete created contract with all fields populated
   *
   * Validation rules:
   * - Employee must exist in the system
   * - User must have employee management permission
   * - start_date is required and must be a valid date in the past or present
   * - pay_rate is required and must be a positive numeric value
   * - pay_period must be one of: hourly, daily, weekly, monthly
   * - working_hours_per_week is required and must be a positive number
   * - start_date must not be in the future
   *
   * Edge cases:
   * - If employee has no active contract, simply create the new contract without updating any previous records
   * - If employee is inactive (has an end_date in hrms_employees), still allow contract creation for historical purposes
   * - Handle timezone appropriately when calculating the end_date for the previous contract
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmsEmployeeContract.ICreate,
  ): Promise<IHrmsEmployeeContract> {
    try {
      return await postHrmsMemberEmployeesEmployeeIdContracts({
        member,
        employeeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated and filtered list of all employment contracts for a specific employee.
   *
   * This operation returns the complete contract history for the employee identified by the path parameter, including both active and historical contracts. Each contract record displays the employment terms during that period, including start date, end date (if applicable), pay rate, pay period, and weekly working hours.
   *
   * The endpoint supports advanced filtering by date ranges (start date, end date), contract status (active or past contracts only), and optional sorting by date fields. All filters are optional and can be combined freely.
   *
   * **Authorization Requirements**:
   *
   * Employees can view their own contract history. Users with the employee:view permission can view any employee's contract history within the organization. Past contracts are immutable historical records displayed in read-only mode.
   *
   * @param connection
   * @param employeeId ID of the employee whose contracts to retrieve.
   * @param body Search criteria and pagination parameters for filtering employee contracts.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrms_employee_contracts table filtered by hrms_employee_id matching the employeeId path parameter.
   *
   * Apply optional filters:
   * - start_date_range: Filter contracts where start_date is within the specified range (gte, lt)
   * - end_date_range: Filter contracts where end_date is within the specified range (gte, lt) or is null for ongoing contracts
   * - status: Filter by 'active' (end_date is null) or 'past' (end_date is not null)
   *
   * Apply optional sorting by start_date (ASC/DESC) or end_date (ASC/DESC).
   *
   * Apply cursor-based pagination with configurable page_size (default: 20, max: 100).
   *
   * Return contract summaries excluding notes field for list display efficiency.
   *
   * Ensure the requesting user has authorization to view the employee's contracts (either viewing own contracts or having employee:view permission for the employee's organization).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmsEmployeeContract.IRequest,
  ): Promise<IPageIHrmsEmployeeContract.ISummary> {
    try {
      return await patchHrmsMemberEmployeesEmployeeIdContracts({
        member,
        employeeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific employee employment contract.
   *
   * This operation returns complete contract details for an employee contract identified by its unique identifier. The contract includes comprehensive information about employment terms such as pay rate, pay period classification, working hours per week, and contract date range (start date and optional end date).
   *
   * **Authorization Requirements**:
   *
   * - Employees can view their own contract history regardless of permission level
   * - Users with employee:view permission can view any employee's contract within their organization
   * - Users without these permissions are denied access to contract information
   * - Data isolation rules prevent viewing contracts from other organizations
   *
   * **Response Details**:
   *
   * The response includes the contract's primary key identifier, associated employee reference, contract dates, compensation details (pay rate and pay period), working hours specification, optional notes or additional terms, and system metadata (creation timestamp, last update timestamp). Active contracts are identified by a null end_date, while past contracts have explicit end dates.
   *
   * @param connection
   * @param employeeId Unique identifier of the employee whose contract is being retrieved
   * @param contractId Unique identifier of the contract to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve a single hrms_employee_contracts record by contractId.
   *
   * Query Parameters:
   * - employeeId (path): Filter to ensure the contract belongs to the specified employee
   * - contractId (path): Unique identifier of the contract to retrieve
   *
   * Business Logic:
   * 1. Validate that the contract exists and is not soft-deleted (deleted_at is null)
   * 2. Verify the contract belongs to the specified employee (hrms_employee_id matches employeeId)
   * 3. Check authorization:
   *    - If requesting user is the employee, allow access
   *    - If requesting user has employee:view permission, allow access
   *    - Otherwise, return 403 Forbidden
   * 4. Ensure the contract belongs to the same organization as the requesting user
   * 5. Return the complete contract record with all fields
   *
   * Error Handling:
   * - 404 Not Found: Contract does not exist or is soft-deleted
   * - 403 Forbidden: User lacks permission to view this contract
   * - 400 Bad Request: Invalid UUID format in path parameters
   *
   * Database Query:
   * SELECT * FROM hrms_employee_contracts
   * WHERE id = $1 AND hrms_employee_id = $2 AND deleted_at IS NULL
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":contractId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedParam("contractId")
    contractId: string & tags.Format<"uuid">,
  ): Promise<IHrmsEmployeeContract> {
    try {
      return await getHrmsMemberEmployeesEmployeeIdContractsContractId({
        member,
        employeeId,
        contractId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
