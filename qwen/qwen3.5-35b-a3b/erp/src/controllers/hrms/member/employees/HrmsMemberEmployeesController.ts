import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmsEmployee } from "../../../../api/structures/IHrmsEmployee";
import { IPageIHrmsEmployee } from "../../../../api/structures/IPageIHrmsEmployee";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmsMemberEmployeesEmployeeId } from "../../../../providers/getHrmsMemberEmployeesEmployeeId";
import { patchHrmsMemberEmployees } from "../../../../providers/patchHrmsMemberEmployees";

@Controller("/hrms/member/employees")
export class HrmsMemberEmployeesController {
  /**
   * Retrieve detailed information about a specific employee within the organization.
   *
   * This operation returns complete employee details including display name, job position, employment type, and current employment status. The response includes the employee's organizational context through the organization member relationship and their assigned role within the organization.
   *
   * The employee record includes department assignment if one exists, showing the employee's placement within the organizational structure. Employment type classification (full-time, part-time, contractor, intern) and status (active or deactivated) provide essential context for understanding the employee's current working relationship with the organization.
   *
   * Access to employee information is determined by role-based permissions within the selected organization. Members with employee viewing permission can view all employee records in their organization. Members without this permission can only view their own employee record. Each employee can always view their own employee record and contract information regardless of their role.
   *
   * This endpoint supports organizational visibility needs, team management, and reporting. The employee information returned is appropriate for display in organizational charts, employee directories, and team directories.
   *
   * @param connection
   * @param employeeId UUID identifier of the employee to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrms_employees table by id (UUID format).
   *
   * 1. Validate employeeId is a valid UUID format
   * 2. Fetch employee record from hrms_employees table
   * 3. Join with hrms_organization_members to include user relationship details
   * 4. Join with hrms_organization_roles to include role information
   * 5. Join with hrms_departments to include department details (if assigned)
   * 6. Filter by organization context - only return employees within the user's active organization
   * 7. Check if employee is soft deleted (deleted_at is not null) - exclude from results
   * 8. Return complete employee record with all joined relationships
   *
   * Error handling:
   * - 404 Not Found: Employee record does not exist or belongs to different organization
   * - 404 Not Found: Employee is soft deleted (deleted_at is not null)
   * - 401 Unauthorized: User is not authenticated
   * - 403 Forbidden: User does not have permission to view employee information (based on role permissions)
   *
   * Note: Employee status field indicates active or deactivated state but deactivated employees are still viewable by authorized users for record-keeping purposes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":employeeId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
  ): Promise<IHrmsEmployee> {
    try {
      return await getHrmsMemberEmployeesEmployeeId({
        member,
        employeeId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated and filtered list of employee records within the authenticated user's organization.
   *
   * This operation provides comprehensive search and filtering capabilities for browsing employees. It supports partial text matching on employee display names, filtering by department, employment type, employment status, and creation date ranges. The results include employee summary information optimized for list displays.
   *
   * All employees in the organization are visible to organization members. Users with employee:manage permission can access the complete employee list for administrative operations. The endpoint enforces organization context, ensuring users only see employees from their active organization.
   *
   * The list supports cursor-based pagination for efficient handling of large result sets. Users can control page size and specify sort fields and directions. The operation is read-only and suitable for populating dropdowns, search results, and employee directories.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for employee list filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrms_employees table filtered by organization context (from authenticated user session).
   *
   * Apply search filters:
   * - name: partial text match (ILIKE) on display_name field
   * - email: partial text match on email field
   * - department_id: exact match filter
   * - employment_type: exact match filter
   * - is_active: boolean filter
   * - hired_at: date range filter (min and max)
   * - status: exact match filter
   *
   * Join operations:
   * - LEFT JOIN hrms_organizations for organization context validation
   * - LEFT JOIN hrms_organization_members to verify user's membership
   * - LEFT JOIN hrms_departments for department details (if include_department=true)
   *
   * Pagination:
   * - Use cursor-based pagination for large datasets
   * - default page_size: 20, max page_size: 100
   * - Support both offset-based and cursor-based pagination
   *
   * Sorting:
   * - Default sort: hired_at DESC
   * - Supported fields: display_name, email, hired_at, status, is_active
   * - Sort direction: ASC or DESC
   *
   * Permission validation:
   * - All organization members can view employee list
   * - No additional permissions required for list viewing
   * - Organization context validated from session
   *
   * Return IHrmsEmployee.ISummary objects with fields: id, display_name, email, department (if included), employment_type, is_active, hired_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmsEmployee.IRequest,
  ): Promise<IPageIHrmsEmployee.ISummary> {
    try {
      return await patchHrmsMemberEmployees({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
