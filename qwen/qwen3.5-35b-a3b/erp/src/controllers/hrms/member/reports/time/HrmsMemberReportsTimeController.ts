import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmsTimelog } from "../../../../../api/structures/IHrmsTimelog";
import { IPageIHrmsTimelog } from "../../../../../api/structures/IPageIHrmsTimelog";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchHrmsMemberReportsTime } from "../../../../../providers/patchHrmsMemberReportsTime";

@Controller("/hrms/member/reports/time")
export class HrmsMemberReportsTimeController {
  /**
   * Generate a time tracking report by aggregating timelog data across the organization with configurable grouping and filtering options.
   *
   * This operation calculates total hours, billable hours, and non-billable hours grouped by employee, project, or task as specified. Reports can be filtered by date range, specific employees, projects, and billable status to focus on relevant time tracking data.
   *
   * Users with report:view permission can access organization-level time reports. The report aggregates duration minutes from all matching timelogs in the hrms_timelogs table and converts the results to hours for easy interpretation.
   *
   * Supported grouping options are: employee, project, and task. Any other grouping specification will be rejected with a validation error. The aggregation sums duration_minutes from all relevant timelogs and converts to hours by dividing by 60.
   *
   * The report provides visibility into how time is spent across employees, projects, and tasks within the organization, supporting workload monitoring and resource allocation decisions.
   *
   * @param connection
   * @param body Report generation parameters including grouping, date range, and filters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrms_timelogs table with filters on date range, employee, project, and billable status.
   * Join with hrms_projects to validate project assignments when filtering by project.
   * Join with hrms_tasks to validate task ownership when filtering by task.
   * Group results by grouping option (employee, project, or task) and calculate:
   *   - Total duration minutes (sum of all matching timelogs)
   *   - Billable duration minutes (where billable = true)
   *   - Non-billable duration minutes (where billable = false)
   * Convert all duration values to hours (divide by 60).
   * Validate grouping parameter against allowed values: employee, project, task.
   * Return aggregated report data with group identifiers, group names, and hour calculations.
   * Enforce organization context filter - only return data for the requesting user's organization.
   * Validate user has report:view permission before executing query.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmsTimelog.IRequest,
  ): Promise<IPageIHrmsTimelog.ISummary> {
    try {
      return await patchHrmsMemberReportsTime({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
