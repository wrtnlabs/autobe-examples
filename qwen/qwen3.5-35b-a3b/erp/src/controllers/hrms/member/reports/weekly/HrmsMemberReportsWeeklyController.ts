import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmsTimelog } from "../../../../../api/structures/IHrmsTimelog";
import { IPageIHrmsTimelog } from "../../../../../api/structures/IPageIHrmsTimelog";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchHrmsMemberReportsWeekly } from "../../../../../providers/patchHrmsMemberReportsWeekly";

@Controller("/hrms/member/reports/weekly")
export class HrmsMemberReportsWeeklyController {
  /**
   * Generate a weekly summary report showing time tracking data organized by calendar weeks.
   *
   * This operation aggregates timelog data from hrms_timelogs, grouped by calendar weeks (Monday to Sunday) within a specified date range. For each week, the report calculates three key metrics: total hours logged (sum of duration_minutes converted to hours), total number of timelogs submitted, and the count of unique employees who logged time during that week.
   *
   * The report can be filtered by project to show timelog data for a specific project only. When no project filter is applied, the report includes timelogs from all projects within the user's organization context.
   *
   * Security and Access:
   * - Requires member actor with organization membership
   * - The requesting user must have report:view permission for the organization
   * - Only timelogs from the user's organization are included
   * - Deleted timelogs (deleted_at is not null) are excluded from calculations
   *
   * Parameters:
   * - dateRange.start: ISO 8601 date string specifying the report start date
   * - dateRange.end: ISO 8601 date string specifying the report end date
   * - projectCode: Optional project code for filtering by specific project
   *
   * The report generation timestamp is included in the response to indicate when the report was created.
   *
   * @param connection
   * @param body Weekly report query parameters including date range and optional project filter.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate user has organization membership and report:view permission for the target organization.
   * 2. Parse dateRange.start and dateRange.end parameters. Validate that start date is on or before end date.
   * 3. If projectCode is provided, look up the project within the user's organization. Validate project exists and is accessible.
   * 4. Query hrms_timelogs table:
   *    - Filter by employee_id from users in target organization
   *    - Filter date field within dateRange.start to dateRange.end
   *    - Exclude deleted timelogs (deleted_at IS NULL)
   *    - If projectCode provided, join with hrms_projects and filter by code
   * 5. Calculate weekly aggregations:
   *    - Group timelogs by week (Monday to Sunday)
   *    - For each week: SUM(duration_minutes) / 60 = totalHours
   *    - COUNT(*) = totalTimelogs
   *    - COUNT(DISTINCT employee_id) = uniqueEmployees
   * 6. Return paginated results with weekly rows sorted by week start date ascending.
   * 7. Include generation timestamp (current time) in response metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async generate(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmsTimelog,
  ): Promise<IPageIHrmsTimelog.ISummary> {
    try {
      return await patchHrmsMemberReportsWeekly({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
