import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmsOrganizationRole } from "../../../../../api/structures/IHrmsOrganizationRole";
import { IPageIHrmsOrganizationRole } from "../../../../../api/structures/IPageIHrmsOrganizationRole";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteHrmsMemberOrganizationsOrganizationIdRolesRoleId } from "../../../../../providers/deleteHrmsMemberOrganizationsOrganizationIdRolesRoleId";
import { getHrmsMemberOrganizationsOrganizationIdRolesRoleId } from "../../../../../providers/getHrmsMemberOrganizationsOrganizationIdRolesRoleId";
import { patchHrmsMemberOrganizationsOrganizationIdRoles } from "../../../../../providers/patchHrmsMemberOrganizationsOrganizationIdRoles";
import { postHrmsMemberOrganizationsOrganizationIdRoles } from "../../../../../providers/postHrmsMemberOrganizationsOrganizationIdRoles";

@Controller("/hrms/member/organizations/:organizationId/roles")
export class HrmsMemberOrganizationsRolesController {
  /**
   * Create a new custom role within the specified organization.
   *
   * This operation allows organization owners to define custom roles with specific names and permission combinations tailored to their organizational needs within the hrms_organization_roles table. Each custom role is organization-specific, scoped to the organization_id, and does not affect roles in other organizations. The role name must be unique within the organization and cannot duplicate the names of the three built-in roles (Owner, Manager, Employee).
   *
   * Custom roles are designed to provide flexible access control beyond the standard built-in roles defined in the system. When creating a custom role, you specify a descriptive name and select from the available permission codes following the "category:action" format (e.g., "employee:manage", "time:approve", "project:view"). Each selected permission is automatically stored as a normalized row in the hrms_organization_role_permissions table, with one permission code per row linked to the created role.
   *
   * The role is automatically created with is_builtin set to false in hrms_organization_roles, indicating it can be deleted by organization owners when no employees (hrms_organization_members) are currently assigned to it. Role creation requires organization owner privileges - users without the org:manage permission will receive a 403 Forbidden error.
   *
   * This operation is part of the organization role management workflow. After creating a custom role, you can assign it to organization members via GET /organizations/:id/members/:memberId/role update operation, or modify its permissions via PUT /organizations/:id/roles/:roleId.
   *
   * @param connection
   * @param organizationId Organization ID where the role will be created (global scope)
   * @param body Custom role definition including name and permission combinations
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate that the calling user is an organization owner using the organization_id from the request context
   * 2. Check if the role name already exists in hrms_organization_roles for this organization (unique constraint on organization_id, name)
   * 3. Validate that is_builtin is set to false (custom roles cannot be built-in)
   * 4. Validate that permission codes follow the "category:action" format
   * 5. Begin database transaction
   * 6. Insert new record into hrms_organization_roles with:
   *    - id: auto-generated UUID
   *    - organization_id: from request context or path parameter
   *    - name: from request body
   *    - is_builtin: false
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   * 7. For each permission in the permissions array, insert corresponding records into hrms_organization_role_permissions:
   *    - id: auto-generated UUID
   *    - hrms_organization_role_id: the newly created role's ID
   *    - permission: permission code from request
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   * 8. Commit transaction
   * 9. Return the complete role object with all associated permissions in a single response
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmsOrganizationRole.ICreate,
  ): Promise<IHrmsOrganizationRole> {
    try {
      return await postHrmsMemberOrganizationsOrganizationIdRoles({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated and filtered list of roles within the current organization context.
   *
   * This operation provides advanced search and filtering capabilities for browsing organizational roles. Users can filter roles by built-in status to distinguish between system-defined roles (Owner, Manager, Employee) and custom roles. The response includes role metadata such as name, built-in status, creation timestamp, and the count of members assigned to each role.
   *
   * All roles returned are scoped to the currently selected organization. Users must have appropriate permissions to view role information. Organization owners can manage custom roles, while other users can only view the role information necessary for their access level.
   *
   * The endpoint supports comprehensive pagination with configurable page size and cursor-based navigation for efficient handling of large result sets. Sorting by name or creation date is available to help users locate specific roles quickly.
   *
   * @param connection
   * @param organizationId Target organization's UUID identifier
   * @param body Search criteria and pagination parameters for role listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrms_organization_roles table with organization_id filter.
   *
   * 1. Apply organization context from authentication middleware
   * 2. Validate organizationId parameter matches user's organization context
   * 3. Apply search filters:
   *    - is_builtin: filter by built-in status (true/false)
   *    - name: partial text match on role name
   * 4. Apply sorting if requested (name ASC/DESC, created_at ASC/DESC)
   * 5. Apply cursor-based pagination with page size limit (default 20, max 100)
   * 6. Calculate member count for each role by querying hrms_organization_members
   * 7. Return paginated results with pagination metadata (cursor, hasMore, total count)
   *
   * Validation:
   * - Organization must exist and not be deleted
   * - User must belong to the organization
   * - Organization context must match organizationId
   *
   * Permissions:
   * - view: Role list browsing permission (e.g., org:view or employee:view)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmsOrganizationRole.IRequest,
  ): Promise<IPageIHrmsOrganizationRole.ISummary> {
    try {
      return await patchHrmsMemberOrganizationsOrganizationIdRoles({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific organization role with its full definition and associated permissions.
   *
   * This operation returns the complete role definition including the role name, whether it is a built-in role (owner, manager, or employee) or custom role, and all permissions assigned to this role within the organization.
   *
   * The response includes the role's metadata such as creation timestamp and last update timestamp. All permissions associated with the role are returned as a list of permission codes, each following the format "category:action" (e.g., "employee:manage", "time:approve", "project:view").
   *
   * Only members of the specified organization can retrieve role information. Users with different roles in the same organization would see different permission combinations. The built-in roles (owner, manager, employee) are always available and cannot be deleted.
   *
   * @param connection
   * @param organizationId The organization this role belongs to
   * @param roleId The unique identifier of the role
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrms_organization_roles table for the role matching roleId within the specified organizationId.
   * Verify the role belongs to the requested organization to prevent cross-organization data access.
   * Perform a LEFT JOIN with hrms_organization_role_permissions to fetch all permissions for this role.
   * Filter out soft-deleted records (deleted_at IS NULL).
   * Return role details with permissions array.
   * Enforce that organizationId matches the authenticated user's organization context.
   * Handle 404 if role not found or if user lacks access to this organization.
   * Return 403 if user attempts to access roles outside their organization scope.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":roleId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
  ): Promise<IHrmsOrganizationRole> {
    try {
      return await getHrmsMemberOrganizationsOrganizationIdRolesRoleId({
        member,
        organizationId,
        roleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a custom role from the organization.
   *
   * This operation permanently removes a custom role from the organization's role hierarchy. The role must not have any employees currently assigned to it, otherwise the deletion is rejected.
   *
   * Security and Authorization:
   *
   * Only organization owners can delete custom roles. Built-in roles (Owner, Manager, Employee) cannot be deleted under any circumstances, even by organization owners.
   *
   * The operation validates that the role is not assigned to any employee before allowing deletion. This prevents orphaned employee records without a role assignment.
   *
   * Database Entity Relationship:
   *
   * This operation operates on the hrms_organization_roles table. The role is linked to employees through the hrms_organization_members table, which references the role via hrms_organization_role_id. Each employee can only have one role at a time.
   *
   * Before deletion, the system checks all records in hrms_organization_members to ensure no employee has the role assigned. The unique constraint on [organization_id, name] ensures role names are unique within an organization.
   *
   * Related Operations:
   *
   * Before deleting a role, use GET /organizations/{organizationId}/employees to find employees with the role, then update their role assignments using PUT /organizations/{organizationId}/employees/{employeeId}.
   *
   * Expected Behavior and Error Handling:
   *
   * The operation returns 404 Not Found if the role does not exist in the organization. Returns 403 Forbidden if the role is a built-in role (is_builtin is true). Returns 400 Bad Request if any employee still has the role assigned.
   *
   * Successful deletion permanently removes the role from the database. The is_builtin flag prevents accidental deletion of essential organizational roles.
   *
   * @param connection
   * @param organizationId Organization's unique identifier
   * @param roleId Custom role's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification DELETE the role from hrms_organization_roles table.
   *
   * Service Layer Logic:
   * 1. Verify the role exists in the organization by querying hrms_organization_roles with organization_id and role_id
   * 2. Check if the role is built-in (is_builtin = true) - reject with 403 Forbidden if so
   * 3. Query hrms_organization_members to check if any employee has this role assigned (WHERE hrms_organization_role_id = roleId)
   * 4. If any employee is found with this role, return 400 Bad Request with message about reassigning employees first
   * 5. If no employees are assigned, delete the role record using CASCADE delete from hrms_organization_role_permissions
   * 6. Return 204 No Content on successful deletion
   *
   * Validation Rules:
   * - Role must belong to the specified organization
   * - Role must not be a built-in role (is_builtin = false)
   * - No employees can be currently assigned to the role
   * - Organization must exist and be accessible by the authenticated user
   *
   * Edge Cases:
   * - Role does not exist in the organization: 404 Not Found
   * - Attempt to delete built-in role: 403 Forbidden
   * - Role has assigned employees: 400 Bad Request
   * - User lacks permission to delete roles: 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":roleId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmsMemberOrganizationsOrganizationIdRolesRoleId({
        member,
        organizationId,
        roleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
