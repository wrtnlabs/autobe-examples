import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmsOrganization } from "../../../../api/structures/IHrmsOrganization";
import { IPageIHrmsOrganization } from "../../../../api/structures/IPageIHrmsOrganization";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmsMemberOrganizationsOrganizationId } from "../../../../providers/getHrmsMemberOrganizationsOrganizationId";
import { patchHrmsMemberOrganizations } from "../../../../providers/patchHrmsMemberOrganizations";
import { putHrmsMemberOrganizationsOrganizationId } from "../../../../providers/putHrmsMemberOrganizationsOrganizationId";

@Controller("/hrms/member/organizations")
export class HrmsMemberOrganizationsController {
  /**
   * Retrieve a paginated and filtered list of organizations that the authenticated member belongs to. This endpoint supports advanced search capabilities including name filtering, currency filtering, timezone filtering, and sorting options.
   *
   * The system enforces organization context on every request, ensuring users only see organizations they have membership in. Cross-organization data isolation is strictly maintained, with each organization's data completely separated.
   *
   * All organization listings include essential summary information optimized for display in organization selection interfaces and member profiles. The response provides pagination metadata to navigate through large result sets.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrms_organizations table with pagination and filtering. Join with hrms_organization_members table to filter organizations where the authenticated member has a membership record. Apply search filters on name (partial match), currency, and timezone. Apply sorting on created_at date. Return cursor-based or offset-based pagination with configurable page size. Validate that authenticated member exists and is not soft-deleted. Filter out soft-deleted organizations from results. Return organization summary information with id, name, description, logo_uri, currency, timezone, fiscal_start_month, created_at, and owner_id.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmsOrganization.IRequest,
  ): Promise<IPageIHrmsOrganization.ISummary> {
    try {
      return await patchHrmsMemberOrganizations({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific organization by its unique identifier.
   *
   * This operation returns the complete organization entity including its display name, description, logo, and configuration settings such as currency, timezone, and fiscal calendar start month. The organization owner reference is included but does not include full user details.
   *
   * The operation enforces organization context by validating that the requesting user is a member of the specified organization. Users who belong to multiple organizations can access any organization they are a member of.
   *
   * Soft-deleted organizations (where deleted_at is not null) are not accessible through this endpoint. Attempting to retrieve a deleted organization returns a 404 Not Found response.
   *
   * @param connection
   * @param organizationId Unique identifier of the organization to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve organization entity by UUID from hrms_organizations table.
   *
   * 1. Validate organizationId is a valid UUID format
   * 2. Fetch organization from hrms_organizations WHERE id = organizationId
   * 3. Check if deleted_at IS NULL (soft delete filtering)
   * 4. Verify requesting user is a member of this organization via hrms_organization_members
   * 5. Return full organization entity including:
   *    - id, name, description, logo_uri
   *    - currency, timezone, fiscal_start_month
   *    - owner_id reference (without owner details)
   *    - created_at, updated_at, deleted_at
   * 6. Return 404 if organization not found or user not authorized
   * 7. Return 404 if organization is soft-deleted (deleted_at IS NOT NULL)
   *
   * Permission: User must be organization member (any role).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":organizationId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
  ): Promise<IHrmsOrganization> {
    try {
      return await getHrmsMemberOrganizationsOrganizationId({
        member,
        organizationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing organization's settings and configuration.
   *
   * This operation modifies organization properties including display name, description, logo, currency, timezone, and fiscal year start month. Only users with organization management permissions can perform this operation.
   *
   * The organization name must be unique across all organizations in the system. When updating the name, the system validates that the new name is not already in use by another organization.
   *
   * Organization settings are scoped to the organization context. All updates are applied within the current organization scope identified by the organization ID path parameter.
   *
   * Related operations: `GET /organizations/{organizationId}` to retrieve current organization details, `GET /organizations` to list all user's organizations.
   *
   * @param connection
   * @param organizationId Target organization's unique identifier
   * @param body Organization settings to update
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve the organization record by organizationId from hrms_organizations table. Verify the requesting user has organization management permissions within the target organization through the organization_members join table.
   *
   * Update the following fields based on request body:
   * - name: Validate uniqueness against all organizations (excluding current)
   * - description: Allow null or string value
   * - logo_uri: Allow null or valid URI string (max 80000 characters)
   * - currency: Validate as valid ISO 4217 currency code (3-letter uppercase)
   * - timezone: Validate as valid IANA timezone identifier
   * - fiscal_start_month: Validate integer between 1 and 12
   *
   * Apply updates within a database transaction to ensure consistency. Set updated_at timestamp to current UTC time.
   *
   * Return the complete updated organization record with all fields including id, owner_id, and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":organizationId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmsOrganization.IUpdate,
  ): Promise<IHrmsOrganization> {
    try {
      return await putHrmsMemberOrganizationsOrganizationId({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
