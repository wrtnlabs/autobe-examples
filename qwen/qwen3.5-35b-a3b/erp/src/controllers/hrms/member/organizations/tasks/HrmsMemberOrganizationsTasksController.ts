import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmsTask } from "../../../../../api/structures/IHrmsTask";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { postHrmsMemberOrganizationsProjectIdTasks } from "../../../../../providers/postHrmsMemberOrganizationsProjectIdTasks";

@Controller("/hrms/member/organizations/:projectId/tasks")
export class HrmsMemberOrganizationsTasksController {
  /**
   * Create a new task within a project.
   *
   * This operation allows project leads or users with project management permissions to create new work items that employees will track time against. A task requires a title and must be associated with a specific project.
   *
   * When creating a task, you must specify the project context via the path parameter. The task title is required and must not be empty. Optional fields include description, priority level, estimated hours, due date, assigned employee, and billing flag.
   *
   * By default, newly created tasks are initialized with an 'open' status unless explicitly specified. The assigned employee, if provided, must be a member of the project being created.
   *
   * @param connection
   * @param projectId The ID of the project to create the task within
   * @param body Task creation data including title, description, status, priority, and optional assignment details
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new task within the specified project.
   *
   * 1. Validate user has project management permission or is a project lead for the project
   * 2. Verify the project exists and belongs to the current organization context
   * 3. Validate task title is non-empty
   * 4. Validate priority is one of: low, medium, high, urgent
   * 5. Validate status is one of: open, in-progress, completed, closed
   * 6. If hrms_employee_id provided, verify employee is a member of the project
   * 7. Create the task record with default status of 'open' if not specified
   * 8. Initialize audit trail fields (created_at, updated_at)
   * 9. Return the newly created task with full details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmsTask.ICreate,
  ): Promise<IHrmsTask> {
    try {
      return await postHrmsMemberOrganizationsProjectIdTasks({
        member,
        projectId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
