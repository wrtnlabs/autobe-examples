import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmsOrganization } from "../../../../../api/structures/IHrmsOrganization";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchHrmsMemberOrganizationsSwitch } from "../../../../../providers/patchHrmsMemberOrganizationsSwitch";

@Controller("/hrms/member/organizations/switch")
export class HrmsMemberOrganizations_switchController {
  /**
   * Switch the authenticated user's organization context to a different organization they belong to.
   *
   * This operation allows a member to switch between multiple organizations they have membership in, without requiring logout or re-authentication. The user's session remains active throughout the switch, and all subsequent operations are scoped to the newly selected organization.
   *
   * The operation validates that the target organization exists and that the authenticated user has an active membership in that organization. If either validation fails, the request is rejected.
   *
   * Upon successful switch, the user's organization context is updated, and they immediately gain or lose access to different organizational data including employee records, projects, tasks, timesheets, timelogs, and reports. The user's global account information (display name, avatar, phone) remains unchanged across all organizations.
   *
   * @param connection
   * @param body Target organization ID to switch to
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Extract target organization ID from request body
   * 2. Validate that target organization exists by querying hrms_organizations
   * 3. Validate that authenticated user (from session) has an active membership in target organization by querying hrms_organization_members
   * 4. Check that membership is not soft-deleted (deleted_at is null)
   * 5. Update the user's session context with new organization ID
   * 6. Return the new organization context including organization details
   *
   * Error handling:
   * - 404 if target organization does not exist
   * - 403 if user has no membership in target organization
   * - 400 if organization ID is invalid UUID format
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async switchOrganization(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmsOrganization.IRequest,
  ): Promise<IHrmsOrganization.ISummary> {
    try {
      return await patchHrmsMemberOrganizationsSwitch({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
