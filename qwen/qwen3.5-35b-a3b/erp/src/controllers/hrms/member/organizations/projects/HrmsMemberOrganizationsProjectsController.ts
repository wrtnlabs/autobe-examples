import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmsProject } from "../../../../../api/structures/IHrmsProject";
import { IPageIHrmsProject } from "../../../../../api/structures/IPageIHrmsProject";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchHrmsMemberOrganizationsOrganizationIdProjects } from "../../../../../providers/patchHrmsMemberOrganizationsOrganizationIdProjects";
import { postHrmsMemberOrganizationsOrganizationIdProjects } from "../../../../../providers/postHrmsMemberOrganizationsOrganizationIdProjects";

@Controller("/hrms/member/organizations/:organizationId/projects")
export class HrmsMemberOrganizationsProjectsController {
  /**
   * Create a new project within an organization for tracking work and managing team collaboration.
   *
   * This operation creates a new project record with required name and color code for visual identification. Projects are automatically initialized with active status, enabling immediate time tracking and task management. Users with project management permission can define optional parameters including description, budget hours, start date, and end date to establish project scope and timeline.
   *
   * Projects serve as containers for tasks and team members, providing organizational structure for work initiatives. Each project belongs to a specific organization, ensuring data isolation across different companies or departments. The system does not enforce a maximum number of projects per organization.
   *
   * Successful creation returns the complete project object including system-generated fields like id, timestamps, and initial status. The project is immediately visible to users with project view permission within the same organization.
   *
   * @param connection
   * @param organizationId The unique identifier of the organization where the project will be created
   * @param body Project creation data including name, color code, and optional fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Validate that the requesting user has project:manage permission in the specified organization. Verify the organization exists and the user belongs to it with appropriate access rights.
   *
   * Create new hrms_projects record with the following fields:
   * - id: Generate new UUID
   * - hrms_organization_id: Use organizationId from path parameter
   * - name: From request body (required, non-empty string)
   * - description: From request body (optional string, can be null)
   * - color_code: From request body (required, validate hex color format)
   * - status: Set to 'active' by default
   * - budget_hours: From request body if provided, else null
   * - start_date: From request body if provided, else null
   * - end_date: From request body if provided, else null
   * - created_at: Set to current timestamp
   * - updated_at: Set to current timestamp
   * - deleted_at: null (not soft deleted)
   *
   * Perform unique constraint check: organizationId + name must be unique. If duplicate, reject with 409 Conflict error.
   *
   * After successful creation, return the full project object with all fields. No activity log entry is created for project creation (only for project lifecycle actions like archive/complete per 13).
   *
   * Validation errors: 400 for missing required fields, invalid color format. 403 for insufficient permissions. 404 if organization not found. 409 if project with same name already exists in organization.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmsProject.ICreate,
  ): Promise<IHrmsProject> {
    try {
      return await postHrmsMemberOrganizationsOrganizationIdProjects({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of projects within the specified organization with advanced search and filtering capabilities.
   *
   * This operation supports comprehensive filtering including project name (partial match), status (active/archived/completed), date range filters (start_date, end_date), budget hours range, and custom sorting options. The response includes cursor-based pagination for efficient handling of large result sets.
   *
   * Projects are organized by multi-tenant isolation where each organization maintains its own project collection. Users with project view permission can retrieve projects, while project management permission is required for modification operations. Archived and completed projects remain visible in lists but cannot receive new time tracking entries.
   *
   * @param connection
   * @param organizationId Target organization's ID
   * @param body Search criteria including pagination, filters, and sorting options
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrms_projects table with pagination and organization context validation.
   *
   * 1. Validate organizationId exists and user has access to this organization
   * 2. Apply organization scoping filter: hrms_organization_id = organizationId
   * 3. Build dynamic WHERE clause for search criteria:
   *    - status filter: exact match on status field (active, archived, completed)
   *    - name filter: GIN trigram partial match on name field using %search%
   *    - date range filters: start_date >= startDate, end_date <= endDate
   *    - budget_hours range: budget_hours between min and max values
   * 4. Apply sorting: support sorting by name, status, start_date, end_date, budget_hours
   * 5. Filter out soft-deleted records: deleted_at IS NULL
   * 6. Execute cursor-based pagination using last project ID from previous page
   * 7. Return paginated results with cursor for next page navigation
   * 8. Include total count for pagination metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmsProject.IRequest,
  ): Promise<IPageIHrmsProject.ISummary> {
    try {
      return await patchHrmsMemberOrganizationsOrganizationIdProjects({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
