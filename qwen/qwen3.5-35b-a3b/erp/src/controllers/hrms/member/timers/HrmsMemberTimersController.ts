import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmsTimer } from "../../../../api/structures/IHrmsTimer";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmsMemberTimersTimerId } from "../../../../providers/getHrmsMemberTimersTimerId";
import { patchHrmsMemberTimersTimerId } from "../../../../providers/patchHrmsMemberTimersTimerId";
import { postHrmsMemberTimers } from "../../../../providers/postHrmsMemberTimers";

@Controller("/hrms/member/timers")
export class HrmsMemberTimersController {
  /**
   * Retrieve the details of a specific time tracking timer that is currently running or has been recently stopped.
   *
   * This operation returns the complete timer information including the start timestamp, current elapsed duration in minutes, the associated project and optional task, and the current description. The timer duration is calculated by measuring the time elapsed since the timer was started and is updated in real-time.
   *
   * Only the employee who started the timer can retrieve its details. The system enforces ownership validation to ensure employees cannot access timers started by other employees. This operation requires the timer to exist and be accessible to the requesting employee within their organization context.
   *
   * The retrieved timer includes all metadata necessary for displaying the timer status in the UI, including whether the timer is currently active and the full details of the associated project and task.
   *
   * This operation should be called to display the current timer status to the user or to fetch timer details before performing operations like stopping or discarding the timer.
   *
   * @param connection
   * @param timerId The unique identifier of the timer to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Fetch the timer record from hrms_timers table by UUID identifier.
   *
   * 1. Validate that timerId is a valid UUID format
   * 2. Query hrms_timers table WHERE id = timerId
   * 3. Verify the timer belongs to the requesting employee (check employee_id matches current user's employee)
   * 4. Verify the timer belongs to an organization the user has access to
   * 5. Calculate current elapsed duration by comparing start_at with current timestamp
   * 6. Join with hrms_projects to get project details if project_id is populated
   * 7. Join with hrms_tasks to get task details if task_id is populated
   * 8. Return the complete timer object with all fields
   * 9. Return 404 if timer not found
   * 10. Return 403 if timer belongs to another employee
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":timerId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
  ): Promise<IHrmsTimer> {
    try {
      return await getHrmsMemberTimersTimerId({
        member,
        timerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an active timer's configuration including description, project assignment, and task assignment.
   *
   * This operation allows an employee to modify their currently running timer. The timer must be owned by the authenticated employee and must be in an active state (not deleted). The operation supports partial updates, meaning you can update any combination of the following fields: description, project, or task.
   *
   * When updating the project or task, the system validates that the employee is assigned to the selected project. If a task is specified, it must belong to the selected project. The timer's start_at timestamp remains unchanged to preserve the original elapsed duration calculation.
   *
   * The response includes the updated timer record with the elapsed duration calculated from the start_at timestamp to the current time.
   *
   * The operation is rejected if:
   * - The timer does not exist
   * - The timer is not owned by the authenticated employee
   * - The timer has been deleted (soft delete)
   * - The selected project is not one the employee is assigned to as a project member
   * - The selected task does not belong to the selected project
   * - The employee has been deactivated
   *
   * This operation is commonly used when an employee starts working on a different project or task mid-session, or needs to update the description to better reflect their current work.
   *
   * @param connection
   * @param timerId ID of the timer to update
   * @param body Fields to update on the timer. Any combination of description, project, or task can be provided.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Fetch the timer record from hrms_timers table by timerId path parameter.
   *
   * Validate ownership: Verify that the authenticated employee's ID matches the timer's hrms_employee_id. If not, return 403 Forbidden.
   *
   * Validate soft delete: Check that timer.deleted_at is NULL. If present, return 404 Not Found (timer no longer exists).
   *
   * Validate employee status: Fetch the employee record via hrms_employee_id and check that status is 'active'. If the employee has been deactivated, return 400 Bad Request.
   *
   * Apply partial updates to the request body:
   * - description: Update if provided. Must be non-empty string if present.
   * - project (hrms_project_id): Update if provided. Validate that the employee is assigned to this project by checking hrms_project_members table for membership. If not a member, return 400 Bad Request with error message indicating employee is not assigned to the project.
   * - task (hrms_task_id): Update if provided. First validate that the task belongs to the selected project (check hrms_tasks.hrms_project_id matches the project being set). If the task is from a different project, return 400 Bad Request.
   *
   * Execute UPDATE query on hrms_timers table with provided fields.
   *
   * Calculate elapsed duration: Compute duration in minutes from timer.start_at to current time (NOW()).
   *
   * Return 200 OK with the updated timer record including elapsed duration in the response body.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":timerId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmsTimer.IUpdate,
  ): Promise<IHrmsTimer> {
    try {
      return await patchHrmsMemberTimersTimerId({
        member,
        timerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Start a new time tracking timer for an employee to track work in real-time.
   *
   * This operation allows employees to initiate a timer for tracking time spent on project work. The timer begins counting elapsed time from the moment it starts and can be stopped later to automatically create a timelog entry with the calculated duration.
   *
   * **Ownership and Assignment**:
   * - Only employees can start timers for projects they are assigned to
   * - Project assignment is validated through the hrms_project_members table before allowing timer creation
   * - Employees can optionally assign the timer to a specific task within the selected project
   * - If no task is specified, the timer tracks time at the project level only
   *
   * **Active Timer Constraint**:
   * - Each employee can have at most one active timer at any time
   * - Attempting to start a timer when one is already running will be rejected
   * - This prevents multiple concurrent timers from the same employee
   *
   * **Validation Rules**:
   * - The selected project must exist and belong to the employee's organization
   * - The employee must be an active member of the project (status='active' in hrms_project_members)
   * - The employee must have an active employment status (status='active' in hrms_employees)
   * - If a task is specified, it must belong to the selected project
   * - The employee cannot have another active timer running
   *
   * **Related Operations**:
   * - GET /timers/active - Retrieve current active timer for the employee
   * - PUT /timers/{id} - Update the running timer's description, project, or task
   * - DELETE /timers/{id} - Discard the timer without creating a timelog
   * - POST /timers/{id}/stop - Stop the timer and create a timelog entry
   *
   * @param connection
   * @param body Timer creation information including project, task, and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new timer record in hrms_timers table.
   *
   * Service layer logic:
   * 1. Extract employee_id from authentication context (JWT token)
   * 2. Validate employee exists and has active status by querying hrms_employees
   * 3. Validate hrms_project_id exists and belongs to employee's organization
   * 4. Validate employee is an active member of the project by checking hrms_project_members with status='active'
   * 5. Validate employee has no active timer by querying hrms_timers for existing active timer (deleted_at IS NULL)
   * 6. If hrms_task_id provided, validate it exists and belongs to the selected project
   * 7. Validate employee has not been deactivated (deleted_at IS NULL in hrms_employees)
   * 8. Create timer record with:
   *    - id: UUID (generated)
   *    - hrms_employee_id: from context
   *    - hrms_project_id: from request
   *    - hrms_task_id: from request (nullable)
   *    - start_at: current timestamp
   *    - description: from request (nullable)
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   *    - deleted_at: NULL
   * 9. Return full timer record with employee and project details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmsTimer.ICreate,
  ): Promise<IHrmsTimer> {
    try {
      return await postHrmsMemberTimers({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
