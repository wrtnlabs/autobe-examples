import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IAvatarImageResponse } from "../../../../api/structures/IAvatarImageResponse";
import { IHrmsFileUploadRequest } from "../../../../api/structures/IHrmsFileUploadRequest";
import { IHrmsMember } from "../../../../api/structures/IHrmsMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmsMemberAvatarUserId } from "../../../../providers/getHrmsMemberAvatarUserId";
import { patchHrmsMemberAvatar } from "../../../../providers/patchHrmsMemberAvatar";

@Controller("/hrms/member/avatar")
export class HrmsMemberAvatarController {
  /**
   * Retrieve a user's avatar image for display in the application.
   *
   * This endpoint serves the avatar image associated with a specified user account. The avatar image is shared across all organizations the user belongs to and is used for visual identification in various contexts including activity logs, timesheets, and user mentions.
   *
   * The avatar image is stored as a file in the hrms_files table and referenced by the user record in the hrms_members table. If no custom avatar has been uploaded, the system returns a default placeholder avatar.
   *
   * Access to this endpoint requires the requesting user to have appropriate permissions within the organization context. Organization employees can only access avatar images for users within their organization.
   *
   * @param connection
   * @param userId ID of the user whose avatar is being retrieved
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate userId path parameter and verify it exists in hrms_members table
   * 2. Check if the requesting user has organization membership context
   * 3. Verify data isolation - ensure the avatar belongs to an organization the requester has access to
   * 4. Query hrms_files table to retrieve the avatar file record linked to the user
   * 5. If no custom avatar exists, return the default placeholder avatar URI
   * 6. Return the file URI using contentMediaType 'image/png' or 'image/jpeg' based on file type
   * 7. Handle file retrieval through the hrms_file_uploads workflow if needed
   * 8. Return 404 if user has no avatar or if user does not exist
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async get(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<IAvatarImageResponse> {
    try {
      return await getHrmsMemberAvatarUserId({
        member,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated member's profile avatar image.
   *
   * This endpoint allows users to upload a new avatar image that will replace their current profile picture. The avatar is stored as an HRMS file record and associated with the member account. The uploaded image is displayed across all organizations the user belongs to.
   *
   * The endpoint accepts a file upload request containing the image data. Supported formats include PNG, JPEG, and GIF images. The system validates the uploaded file to ensure it is a valid image and meets size requirements.
   *
   * Upon successful upload, the member record is updated with the new avatar URI. The previous avatar file is soft-deleted if one existed. The updated avatar becomes immediately visible in all user interfaces, activity logs, and member lists.
   *
   * If the upload fails due to validation errors (invalid format, oversized file, network issues), the existing avatar remains unchanged and an appropriate error response is returned.
   *
   * @param connection
   * @param body Avatar image file to upload. The file must be a valid image in PNG, JPEG, or GIF format.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Verify the request is authenticated and obtain the current member ID from the session context.
   * 2. Extract the uploaded file from the multipart/form-data request body.
   * 3. Validate file properties:
   *    - Check file extension is .png, .jpg, or .gif
   *    - Verify MIME type matches the file extension
   *    - Ensure file size is within acceptable limits
   *    - Perform virus scan if configured
   * 4. If validation fails, return 400 Bad Request with specific error message.
   * 5. Create a new hrms_file record with:
   *    - organization_id: null (for member-owned avatar)
   *    - owner_id: current member ID
   *    - owner_type: 'member'
   *    - file_category: 'user_avatar'
   *    - filename: original filename from upload
   *    - storage_path: generated storage path
   *    - mime_type: detected MIME type
   *    - file_size: file size in bytes
   *    - validation_status: 'validated'
   * 6. If a previous avatar exists (lookup by owner_id and file_category), soft-delete it by setting deleted_at timestamp.
   * 7. Update the hrms_members record:
   *    - Set avatar_uri to the new file's storage_path or public URL
   *    - Update updated_at timestamp
   * 8. Commit the transaction.
   * 9. Return the updated member profile with the new avatar URI.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updateAvatar(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmsFileUploadRequest,
  ): Promise<IHrmsMember> {
    try {
      return await patchHrmsMemberAvatar({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
