import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmsFile } from "../../../../api/structures/IHrmsFile";
import { IPageIHrmsFile } from "../../../../api/structures/IPageIHrmsFile";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmsMemberFilesFileId } from "../../../../providers/getHrmsMemberFilesFileId";
import { patchHrmsMemberFiles } from "../../../../providers/patchHrmsMemberFiles";
import { postHrmsMemberFilesFileIdRecover } from "../../../../providers/postHrmsMemberFilesFileIdRecover";

@Controller("/hrms/member/files")
export class HrmsMemberFilesController {
  /**
   * Retrieve a filtered and paginated list of files within the user's organization context.
   *
   * This operation provides comprehensive search capabilities for files including organization logos, user avatars, and document attachments. Users can filter files by category (organization_logo, user_avatar, document), validation status (pending, validated, rejected), ownership type, file size ranges, and creation date ranges.
   *
   * The endpoint supports flexible sorting by any field (filename, file_size, created_at, validation_status) with ascending or descending order. Pagination is implemented using cursor-based or offset-based pagination for efficient handling of large result sets.
   *
   * All returned files are scoped to the user's active organization for multi-tenancy isolation. The response includes file metadata only (not the file content itself), optimized for list views and thumbnails.
   *
   * @param connection
   * @param body Search criteria, filters, pagination, and sorting parameters for file list retrieval.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve files from hrms_files table filtered by organization_id (from authenticated user's context) and additional request filters.
   *
   * Database Query:
   * - Base query: SELECT * FROM hrms_files WHERE organization_id = :organizationId
   * - Apply filters: filename LIKE, file_category =, validation_status =, file_size BETWEEN, created_at BETWEEN, owner_type =, owner_id =
   * - Apply sorting: ORDER BY :sortBy :sortOrder
   * - Apply pagination: LIMIT :pageSize OFFSET :offset (or cursor-based)
   * - Include soft-delete filter: WHERE deleted_at IS NULL
   *
   * Validation:
   * - Validate pagination parameters (page >= 1, pageSize between 10 and 100)
   * - Validate sort fields against allowed columns (filename, file_size, created_at, updated_at, validation_status, file_category)
   * - Validate date range parameters (start_date <= end_date)
   * - Validate file_size values are positive integers
   *
   * Business Logic:
   * - Enforce organization context: only return files from authenticated user's organization
   * - Filter out soft-deleted files (deleted_at IS NULL) unless admin/owner has permission
   * - Return file metadata only (id, filename, storage_path, mime_type, file_size, file_category, validation_status, created_at, updated_at)
   * - Exclude file content from response for security
   *
   * Error Handling:
   * - 400 Bad Request: Invalid pagination or filter parameters
   * - 403 Forbidden: User not in organization context
   * - 404 Not Found: No files match criteria (return empty paginated response with total = 0)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmsFile.IRequest,
  ): Promise<IPageIHrmsFile.ISummary> {
    try {
      return await patchHrmsMemberFiles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed metadata for a specific file in the organization.
   *
   * This operation returns comprehensive information about a file including its original filename, MIME type, file size, storage path, validation status, and category classification. Files are associated with organizations and may have an owner (member) for avatars or be organization-owned for logos and documents.
   *
   * The operation enforces organization context by ensuring the requesting user belongs to the organization that owns the file. Only non-soft-deleted files are accessible. The user must have appropriate permissions to view file metadata within their organization.
   *
   * File metadata is returned in full, suitable for displaying file information in user interfaces such as file galleries, document lists, or profile avatars. The storage_path is provided for subsequent retrieval operations if needed.
   *
   * **Important**: Files can be organization-owned (e.g., organization logos, shared documents) or member-owned (e.g., user profile avatars). Regardless of ownership, all files are scoped to their organization for multi-tenancy isolation.
   *
   * @param connection
   * @param fileId The unique identifier of the file to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrms_files table by fileId with WHERE clause filtering for exact match and deleted_at IS NULL to exclude soft-deleted files.
   *
   * 1. Validate fileId is a valid UUID format
   * 2. Query hrms_files for record where id = :fileId AND deleted_at IS NULL
   * 3. If no record found, return 404 Not Found
   * 4. Verify the user's current organization context matches the file's organization_id
   *    - Get user's organization_members record to determine current active organization
   *    - If file's organization_id differs from user's active organization, return 403 Forbidden
   * 5. Load related organization and owner (if owner_type is 'member') references
   * 6. Return file object with all fields: id, filename, storage_path, mime_type, file_size, file_category, owner_type, owner_id, validation_status, created_at, updated_at
   *
   * Security checks:
   * - File must belong to user's organization (enforced by organization_id foreign key)
   * - File must not be soft-deleted (deleted_at IS NULL)
   * - User must have file:view or equivalent permission for organization scope
   *
   * Validation:
   * - fileId must be valid UUID format
   * - File record must exist in database
   * - File must not be deleted
   * - Organization ownership must match user's context
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":fileId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("fileId")
    fileId: string & tags.Format<"uuid">,
  ): Promise<IHrmsFile> {
    try {
      return await getHrmsMemberFilesFileId({
        member,
        fileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Recovers a soft-deleted file by clearing the deleted_at timestamp, making it active again.
   *
   * This endpoint restores files that were previously marked for deletion by setting deleted_at to null. The file becomes immediately available for use again with all its metadata intact. Only files belonging to the requesting organization can be recovered.
   *
   * The operation validates that:
   * - The file exists in the system
   * - The file is currently marked as deleted (deleted_at is set)
   * - The requesting user has permission to modify files in this organization
   * - The file was not permanently deleted (files permanently deleted cannot be recovered)
   *
   * If the file is already active (deleted_at is null), the operation is rejected with an error indicating no recovery is needed.
   *
   * Recovery operations are logged in the activity log, recording the timestamp, user who performed the recovery, and the recovered file name.
   *
   * Files that can be recovered include:
   * - Organization logo files
   * - User avatar files
   * - Document attachments
   *
   * Organization-wide deletions have no recovery option as noted in the data recovery policy. All data deleted during organization removal is permanently lost.
   *
   * @param connection
   * @param fileId The UUID of the file to recover
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate fileId is a valid UUID format
   * 2. Query hrms_files for the record with matching id
   * 3. Verify the file record exists
   * 4. Verify deleted_at is set (file is soft deleted)
   * 5. Verify the requesting user's organization context matches file.organization_id
   * 6. Verify the requesting user has organization management or admin role
   * 7. Clear the deleted_at field by setting it to null
   * 8. Update the updated_at timestamp to current time
   * 9. Insert an activity log entry with:
   *    - organization_id: the file's organization
   *    - performed_by: the user who performed recovery
   *    - action: 'file_recovered'
   *    - file_name: the filename
   * 10. Return the fully updated IFile object
   *
   * Edge cases:
   * - If file is not found (id doesn't exist): 404 Not Found
   * - If file is already active (deleted_at is null): 409 Conflict with message 'File is already active'
   * - If file belongs to different organization: 403 Forbidden
   * - If user lacks permissions: 403 Forbidden
   * - If file was permanently deleted (cascade deleted): 404 Not Found
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":fileId/recover")
  public async recover(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("fileId")
    fileId: string & tags.Format<"uuid">,
  ): Promise<IHrmsFile> {
    try {
      return await postHrmsMemberFilesFileIdRecover({
        member,
        fileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
