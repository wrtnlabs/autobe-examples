import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmsFile } from "../../../../../api/structures/IHrmsFile";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { postHrmsMemberFilesFileIdPermanentlyDelete } from "../../../../../providers/postHrmsMemberFilesFileIdPermanentlyDelete";

@Controller("/hrms/member/files/:fileId/permanently-delete")
export class HrmsMemberFilesPermanently_deleteController {
  /**
   * Permanently delete a file from the system, removing it from all storage and associated metadata.
   *
   * This operation performs a complete data purge of the specified file, including its storage path, metadata records, and any associated upload history records. Unlike soft deletion which only marks records as deleted, permanent deletion irreversibly removes all traces of the file from the system.
   *
   * **Authorization Requirements**:
   * Only users with organization admin or owner roles can permanently delete files. Regular employees and members without administrative privileges cannot access this endpoint. The requesting user must belong to the same organization that owns the file.
   *
   * **Validation Rules**:
   * - The file must exist and be associated with the requesting organization
   * - The file must not be currently referenced by any active file_uploads records (pending uploads must be resolved first)
   * - The file must not be the current organization logo or a user's active avatar
   * - If the file is referenced by other entities (e.g., document attachments in contracts), those dependencies must be resolved before deletion
   *
   * **Deletion Behavior**:
   * - The file record is completely removed from the hrms_files table (not soft-deleted)
   * - Associated upload history records in hrms_file_uploads are also deleted
   * - Storage paths are invalidated and the physical file should be removed from storage
   * - The operation is irreversible with no recovery mechanism
   *
   * **Related Operations**:
   * - GET /files/{fileId} - Retrieve file metadata before deletion
   * - PUT /files/{fileId} - Update file metadata (if available)
   * - POST /file-uploads - Create new file upload workflow
   * - GET /dashboard/organization - Organization dashboard for file management
   *
   * **Error Handling**:
   * - 404 Not Found: File does not exist or belongs to a different organization
   * - 403 Forbidden: User does not have permission to delete files
   * - 409 Conflict: File is currently in use or has unresolved dependencies
   * - 422 Unprocessable Entity: Validation failed (e.g., file is an active logo/avatar)
   *
   * @param connection
   * @param fileId Unique identifier of the file to permanently delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Extract fileId from path parameter and validate UUID format
   * 2. Query hrms_files table to retrieve the file record
   * 3. Verify file.organization_id matches the organization context from authentication
   * 4. Check file.owner_id and owner_type for ownership validation
   * 5. Verify user has admin or owner role in the organization (check hrms_organization_roles and hrms_organization_members)
   * 6. Check for active dependencies:
   *    - Query hrms_file_uploads for any pending upload records referencing this file_id
   *    - Check if file.file_category is 'organization_logo' - if so, verify no other organization logo is set
   *    - Check if file.file_category is 'user_avatar' and file.owner_id matches a member - verify member can change avatar
   * 7. Validate file has not already been permanently deleted (check deleted_at is not null)
   * 8. Begin database transaction
   * 9. Delete associated upload history from hrms_file_uploads where file_id = fileId
   * 10. Delete the file record from hrms_files where id = fileId
   * 11. Commit transaction and log activity in hrms_activity_logs
   * 12. Return the deleted file information in response body
   * 13. If any step fails, rollback transaction and return appropriate error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async permanentlyDelete(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("fileId")
    fileId: string & tags.Format<"uuid">,
  ): Promise<IHrmsFile> {
    try {
      return await postHrmsMemberFilesFileIdPermanentlyDelete({
        member,
        fileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
