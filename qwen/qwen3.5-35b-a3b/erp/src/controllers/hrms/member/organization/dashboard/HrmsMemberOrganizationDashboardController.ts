import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmsOrganization } from "../../../../../api/structures/IHrmsOrganization";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmsMemberOrganizationDashboard } from "../../../../../providers/getHrmsMemberOrganizationDashboard";

@Controller("/hrms/member/organization/dashboard")
export class HrmsMemberOrganizationDashboardController {
  /**
   * Retrieve the organization dashboard containing key metrics and insights for the currently active organization.
   *
   * This endpoint provides management oversight visibility by aggregating data from multiple sources including employees, timesheets, projects, and timelogs. The dashboard displays the total number of active employees, total hours logged by all employees during the current week (Monday to Sunday), and the count of pending timesheets awaiting approval.
   *
   * The dashboard highlights projects that require attention by identifying those with budget utilization exceeding 80 percent, excluding projects without allocated budget hours. It also ranks the top five employees by total hours logged during the current week, providing insights into workload distribution and team performance.
   *
   * Access to this dashboard is restricted to users with report view permission within the organization. The dashboard data is refreshed on-demand and includes a generation timestamp to indicate when the metrics were calculated.
   *
   * All metrics are scoped to the currently active organization context. Users must have an organization selected to view the dashboard data. The operation validates user permissions before returning any organization-level metrics.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve the organization dashboard by aggregating data from multiple HRMS tables within the current organization context.
   *
   * Query logic:
   * 1. Get total active employees: Count hrms_employees where organization_id matches current context and status is 'active'
   * 2. Calculate total hours this week: Sum duration from hrms_timelogs where employee_id is in active employees and timelog date falls within current week (Monday to Sunday)
   * 3. Count pending timesheets: Count hrms_timesheets where organization_id matches current context, status is 'submitted', and employee_id is in active employees
   * 4. Find high-budget projects: Select hrms_projects where organization_id matches current context, budget_hours exists, and (budget_hours - (SUM of timelog hours)) / budget_hours > 0.80
   * 5. Get top 5 employees: Select hrms_employees who logged time this week, sum their timelog hours, order by total hours descending, limit to 5 rows
   *
   * Permission validation: Check if current user has 'report:view' permission in hrms_organization_role_permissions for their role in the current organization.
   *
   * Return the aggregated dashboard data as a single object. Include the timestamp when the dashboard was generated using UTC time converted to the organization's timezone.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmsOrganization> {
    try {
      return await getHrmsMemberOrganizationDashboard({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
