  /**
   * Assign ownership of a file upload request to a different employee within the organization.
   *
   * This operation reassigns the ownership (member_id) of a file upload request from one employee to another. It is used when an upload was mistakenly initiated by the wrong employee, when ownership needs to be transferred between team members, or when consolidating file uploads under a single employee's account.
   *
   * The upload request must exist within the same organization. Cross-organization ownership transfers are not supported. The target employee must be an active member of the organization.
   *
   * Only users with file management permissions (file:manage) or employee management permissions (employee:manage) within the organization can perform this operation. Regular employees cannot reassign ownership of uploads to other employees.
   *
   * The upload_state and validation_status are preserved during the ownership transfer unless explicitly specified in the request body. The permanent_storage_path remains unchanged if the upload was already validated and stored permanently.
   *
   * @param connection
   * @param uploadRequestId The unique identifier of the file upload request to reassign
   * @param body Ownership assignment details including the new owner and optional fields to update
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate that the upload request exists by loading hrms_file_uploads record with the specified uploadRequestId
   * 2. Verify the upload belongs to the organization context from the request
   * 3. Check user permissions - user must have file:manage or employee:manage permission for the organization
   * 4. Validate that the target member_id in the request body belongs to the same organization
   * 5. Validate that the target member has an active employment status (not deactivated)
   * 6. Update the member_id field to the new owner
   * 7. Update the updated_at timestamp
   * 8. Persist changes to hrms_file_uploads table
   * 9. Return the updated upload request record
   *
   * Business Rules:
   * - Upload requests in 'completed' or 'failed' state can be reassigned
   * - Upload requests in 'validating' state can be reassigned but validation continues with original uploader context preserved for audit purposes
   * - The file_id relationship is not affected - the associated file remains linked to the upload
   * - If permanent_storage_path is set, it remains unchanged
   * - Original uploader information is preserved for audit trail (not explicitly stored but the original member_id change is logged in activity logs if audit feature is enabled)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
