import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmsGuest } from "../../../api/structures/IHrmsGuest";
import { IPageIHrmsGuest } from "../../../api/structures/IPageIHrmsGuest";
import { getHrmsGuestsGuestId } from "../../../providers/getHrmsGuestsGuestId";
import { patchHrmsGuests } from "../../../providers/patchHrmsGuests";

@Controller("/hrms/guests")
export class HrmsGuestsController {
  /**
   * Retrieve a specific guest account by its unique identifier.
   *
   * This operation returns the complete guest record including the device fingerprint that uniquely identifies the visitor's browser/device, IP address, user agent string, and all associated timestamps (creation, last update, and soft-deletion). Guest accounts represent temporary unauthenticated visitor sessions in the system.
   *
   * The endpoint is typically used for administrative purposes such as session auditing, troubleshooting visitor issues, or analyzing visitor patterns. Guest accounts do not require authentication credentials and are identified solely by their device fingerprint.
   *
   * Note: Guest accounts are temporary records that may be soft-deleted when sessions expire. The deleted_at field indicates whether a guest account has been soft-deleted.
   *
   * @param connection
   * @param guestId The unique identifier of the guest account to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the hrms_guests table by the guest ID parameter.
   *
   * Validation:
   * - Verify the guestId is a valid UUID format
   * - Return 404 Not Found if the guest record does not exist
   * - Return 403 Forbidden if the requesting user lacks permission to view guest data (based on organization context and role)
   *
   * Logic:
   * - Fetch the guest record from the database using the ID
   * - Check the deleted_at field to determine if the record is soft-deleted
   * - If deleted_at is not null, the record is considered inactive but can still be retrieved for audit purposes
   * - Return the complete guest entity including device_fingerprint, ip_address, user_agent, created_at, updated_at, and deleted_at fields
   *
   * Security:
   * - Verify the requesting user is authenticated as a member actor
   * - Check that the user has organization context
   * - Verify the user has appropriate permissions to view guest data (admin or audit role required)
   * - Log the access in the activity log for audit trail
   *
   * Error handling:
   * - 404: Guest account with the specified ID does not exist
   * - 403: User lacks permission to view guest data
   * - 400: Invalid UUID format in the guestId parameter
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":guestId")
  public async at(
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<IHrmsGuest> {
    try {
      return await getHrmsGuestsGuestId({
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of guest accounts representing unauthenticated visitors to the platform.
   *
   * This operation provides administrative visibility into guest session activity for security auditing purposes. It supports comprehensive search capabilities including registration date ranges, device fingerprint matching, and session status filtering.
   *
   * Response includes guest summary information such as registration timestamp, last activity time, device fingerprint, and session status. Sensitive authentication token data is excluded from the response for security.
   *
   * Only users with appropriate administrative permissions within an organization can access this endpoint. Each result is scoped to the organization context, showing guest activity within that organization's platform access.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for guest account listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query hrms_guests table with pagination and filtering.
   * Apply search filters on registration date range, device fingerprint partial match, session status, and last activity.
   * Join with hrms_guest_sessions for active session information.
   * Return cursor-based or offset-based pagination for large result sets.
   * Only accessible to users with organization admin permissions.
   * Filter results to only include guests from organizations the user has permission to audit.
   * Sort by last activity descending by default.
   * Exclude sensitive session token data from response for security.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IHrmsGuest.IRequest,
  ): Promise<IPageIHrmsGuest.ISummary> {
    try {
      return await patchHrmsGuests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
