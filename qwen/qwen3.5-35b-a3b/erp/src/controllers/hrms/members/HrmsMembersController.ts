import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmsMember } from "../../../api/structures/IHrmsMember";
import { IPageIHrmsMember } from "../../../api/structures/IPageIHrmsMember";
import { getHrmsMembersMemberId } from "../../../providers/getHrmsMembersMemberId";
import { patchHrmsMembers } from "../../../providers/patchHrmsMembers";

@Controller("/hrms/members")
export class HrmsMembersController {
  /**
   * Retrieve detailed information about a specific member account in the system.
   *
   * This operation returns the complete profile of a registered member, including their authentication credentials (email), display information (display name, avatar), and contact details (phone number). Member accounts represent authenticated users who can belong to multiple organizations and perform actions across the platform.
   *
   * The member record includes timestamps for account creation and last update, along with soft-delete status if the account has been deleted. This operation is typically used by administrators, system managers, or the member themselves to view or verify account information.
   *
   * Authorization requires appropriate permissions based on the member's role and organization context. Organization owners and members with admin permissions can view other members' profiles. Members can always view their own profile information.
   *
   * @param connection
   * @param memberId The unique identifier of the member account to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the hrms_members table by the unique id field (UUID format).
   *
   * Validation steps:
   * 1. Verify the memberId parameter is a valid UUID format
   * 2. Check if the member record exists in the database
   * 3. If the member has deleted_at set, consider whether to return a 404 or include deleted_at in response (soft-delete policy)
   * 4. Validate the requesting user has permission to view this member's profile based on role and organization context
   *
   * Database query:
   * SELECT id, email, password_hash (exclude from response), display_name, avatar_uri, phone_number, created_at, updated_at, deleted_at
   * FROM hrms_members
   * WHERE id = :memberId AND deleted_at IS NULL
   *
   * If deleted_at is present, exclude the password_hash field from the response for security.
   *
   * Include the member's organization memberships count or references if required by the response schema. Do not include password_hash in any response for security reasons.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":memberId")
  public async at(
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<IHrmsMember> {
    try {
      return await getHrmsMembersMemberId({
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated and filtered list of registered member accounts in the system.
   *
   * This operation provides comprehensive search and filtering capabilities for browsing member accounts. Users can search by email address, display name, or phone number using partial matching. The endpoint supports filtering by organization membership, account status (active or soft-deleted), and date ranges for creation and update timestamps.
   *
   * The response includes paginated results with metadata about total count, current page, and available sorting options. Results are optimized for list displays with essential member information including id, email, display name, avatar URI, phone number, organization membership count, and timestamps.
   *
   * Only users with member:read permission can access this operation. The operation enforces organization context and returns only members visible to the requesting user's organization or all members if the user has organization management permissions.
   *
   * Related operations:
   * - GET /members/:id - Retrieve detailed information about a specific member
   * - PUT /members/me - Update the current user's profile
   * - DELETE /members/me - Delete the current user's account
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering member accounts
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the hrms_members table with pagination, filtering, and sorting.
   *
   * Filter logic:
   * - Apply email, display_name, and phone_number partial matching (case-insensitive) when search parameters are provided
   * - Filter by hrms_organization_id when organization context is specified to show only members belonging to that organization
   * - Filter by deleted_at status (null for active, non-null for soft-deleted) when status parameter is provided
   * - Apply created_at range filtering when startDate and endDate are provided
   * - Apply updated_at range filtering when updatedStartDate and updatedEndDate are provided
   *
   * Sorting:
   * - Default sort by created_at descending (newest first)
   * - Support sorting by display_name, email, created_at, updated_at
   * - Support ascending and descending order
   *
   * Pagination:
   * - Implement cursor-based pagination for large result sets
   * - Return total count, page info, and member summary objects
   * - Include pagination metadata for UI navigation
   *
   * Permissions:
   * - Require member:read permission for accessing this endpoint
   * - If user lacks organization management permission, filter results to only members in the user's organization context
   *
   * Join optimization:
   * - Calculate organization membership count without joining hrms_organization_members table (use COUNT query)
   * - Return summary data only, not full member objects with nested relations
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IHrmsMember.IRequest,
  ): Promise<IPageIHrmsMember.ISummary> {
    try {
      return await patchHrmsMembers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
