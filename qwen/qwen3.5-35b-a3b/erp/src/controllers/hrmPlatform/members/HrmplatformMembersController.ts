import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformMember } from "../../../api/structures/IHrmPlatformMember";
import { IPageIHrmPlatformMember } from "../../../api/structures/IPageIHrmPlatformMember";
import { getHrmPlatformMembersMemberId } from "../../../providers/getHrmPlatformMembersMemberId";
import { patchHrmPlatformMembers } from "../../../providers/patchHrmPlatformMembers";

@Controller("/hrmPlatform/members")
export class HrmplatformMembersController {
  /**
   * Search and list member accounts with pagination and filtering capabilities.
   *
   * Retrieves a paginated list of registered member accounts from the system. Supports filtering by email address, display name, active status, and date ranges (creation date, last login, update date). Results are sorted by specified fields with ascending or descending order.
   *
   * This endpoint is designed for administrative oversight of member accounts within the currently selected organization context. All operations are scoped to the member's organization and enforce data isolation boundaries.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for member list query.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query hrm_platform_members table with pagination and filtering.
   *
   * Apply search filters:
   * - email: partial match (LIKE operator) if provided
   * - display_name: partial match (LIKE operator) if provided
   * - is_active: exact match filter
   * - created_at: range filter (gte/lt)
   * - updated_at: range filter (gte/lt)
   * - last_login_at: range filter (gte/lt)
   *
   * Pagination parameters:
   * - cursor: last seen id for cursor-based pagination
   * - limit: number of records per page (default: 20, max: 100)
   *
   * Sorting:
   * - sortBy: field name (email, display_name, is_active, created_at, updated_at, last_login_at)
   * - sortOrder: 'asc' or 'desc' (default: 'desc' for created_at)
   *
   * Implementation requirements:
   * - Enforce organization data isolation - only return members within current organization context
   * - Validate cursor parameter format (UUID)
   * - Apply limit boundaries (20-100)
   * - Return cursor for next page if more results exist
   * - Sort results by created_at descending as default
   * - Log access to member list in activity log with timestamp and user attribution
   * - Return 403 if user lacks permission to view member list
   *
   * Error handling:
   * - Return 400 for invalid cursor format
   * - Return 400 for invalid sortBy field name
   * - Return 400 for invalid sortOrder value
   * - Return 404 if no members found in organization
   *
   * Security:
   * - Do not return password_hash in response
   * - Ensure organization context is enforced on every request
   * - Validate user has proper permissions before returning data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IHrmPlatformMember.IRequest,
  ): Promise<IPageIHrmPlatformMember.ISummary> {
    try {
      return await patchHrmPlatformMembers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single member account by unique identifier.
   *
   * Fetches complete member account information including profile details, authentication status, and account metadata. Returns the full member entity with all accessible fields. Used by administrative interfaces and member profile views to display account information.
   *
   * @param connection
   * @param memberId Unique identifier of the member account to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query hrm_platform_members table by id where id matches the path parameter memberId.
   * Return the complete member record including email, display_name, avatar_uri, phone_number, is_active, last_login_at, created_at, and updated_at fields.
   * If member is soft-deleted (deleted_at is not null), exclude from results or return 404.
   * Verify the requesting user has appropriate permissions to access this member's data based on organization membership context.
   * Apply organization-level data isolation: only return member data if the authenticated user belongs to the same organization as the member's employment records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":memberId")
  public async at(
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformMember> {
    try {
      return await getHrmPlatformMembersMemberId({
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
