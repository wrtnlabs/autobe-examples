import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformOrganization } from "../../../../api/structures/IHrmPlatformOrganization";
import { IPageIHrmPlatformOrganization } from "../../../../api/structures/IPageIHrmPlatformOrganization";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteHrmPlatformMemberOrganizationsOrganizationId } from "../../../../providers/deleteHrmPlatformMemberOrganizationsOrganizationId";
import { getHrmPlatformMemberOrganizationsOrganizationId } from "../../../../providers/getHrmPlatformMemberOrganizationsOrganizationId";
import { patchHrmPlatformMemberOrganizations } from "../../../../providers/patchHrmPlatformMemberOrganizations";
import { postHrmPlatformMemberOrganizations } from "../../../../providers/postHrmPlatformMemberOrganizations";
import { putHrmPlatformMemberOrganizationsOrganizationId } from "../../../../providers/putHrmPlatformMemberOrganizationsOrganizationId";

@Controller("/hrmPlatform/member/organizations")
export class HrmplatformMemberOrganizationsController {
  /**
   * Create a new organization that serves as the tenant boundary for the HRM platform.
   *
   * Creates a new organization record with the authenticated user as the owner. The organization establishes the foundational business structure including data isolation, currency settings, timezone configuration, and fiscal year boundaries.
   *
   * All subsequent employees, projects, departments, and business operations will be scoped to this organization. The organization name must be unique within the owner's context to support users managing multiple organizations.
   *
   * @param connection
   * @param body Organization creation data including owner reference, name, optional description, and configuration settings for currency, timezone, and fiscal year.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Verify authenticated member is making the request
   * 2. Validate organization_name is provided and unique within owner's context
   * 3. Validate fiscal_start_month is between 1 and 12
   * 4. Validate currency and timezone values (use predefined lists or allow free-form)
   * 5. Generate UUID for organization id
   * 6. Set created_at and updated_at to current timestamp
   * 7. Insert organization record with owner_id = authenticated user's id
   * 8. Return full organization record including system-generated fields
   *
   * Error handling:
   * - 400 if name already exists for this owner
   * - 400 if fiscal_start_month is out of range (1-12)
   * - 404 if owner_id is invalid (member not found)
   * - 401 if not authenticated
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformOrganization.ICreate,
  ): Promise<IHrmPlatformOrganization> {
    try {
      return await postHrmPlatformMemberOrganizations({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a paginated list of organizations owned by the authenticated member.
   *
   * This endpoint provides search and filtering capabilities to find organizations. Users can filter by organization name, currency, fiscal start month, and date ranges. The results are sorted by creation date (newest first) by default and support cursor-based pagination for efficient large dataset browsing.
   *
   * Organization data is strictly isolated per owner. Users can only view organizations they own. Soft-deleted organizations are excluded from search results.
   *
   *
   *
   * ### Authentication
   * This endpoint requires authentication. The requesting member must be authenticated and must be the owner of the organizations being retrieved.
   *
   * ### Response Format
   * Returns a paginated list of organization summary records, each containing the organization's core attributes for display in list views.
   *
   * @param connection
   * @param body Search criteria including optional filters and pagination parameters. All fields are optional; omitting all fields returns all organizations for the owner.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_organizations table with pagination and filtering.
   *
   * Search filters:
   * - name: partial match (case-insensitive)
   * - currency: exact match
   * - fiscal_start_month: exact match
   * - date range: created_at between dates
   * - sort: created_at (default desc), name (asc), fiscal_start_month
   *
   * Pagination:
   * - Cursor-based pagination for large datasets
   * - Default page size: 20, max: 100
   * - Sort by created_at descending by default
   *
   * Organization context:
   * - Only return organizations where the requesting member is the owner
   * - Enforce multi-tenancy isolation
   * - Exclude soft-deleted organizations (deleted_at IS NULL)
   *
   * Error handling:
   * - Return 400 for invalid pagination parameters
   * - Return 401 if member not authenticated
   * - Return empty array if no matching organizations
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformOrganization.IRequest,
  ): Promise<IPageIHrmPlatformOrganization.ISummary> {
    try {
      return await patchHrmPlatformMemberOrganizations({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single organization by its unique identifier.
   *
   * Returns the complete organization record including the organization's display name, description, financial configuration (currency and fiscal year start), timezone settings, and audit timestamps. This operation is used when displaying organization details in the UI or when needing to access organization-specific settings.
   *
   * @param connection
   * @param organizationId Unique identifier of the organization to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Fetch the organization record from hrm_platform_organizations table where id matches the path parameter.
   *
   * 1. Query hrm_platform_organizations by id (UUID)
   * 2. Verify the organization exists and is not soft-deleted (deleted_at is null)
   * 3. If soft-deleted, return 404 Not Found
   * 4. Verify the user has access to this organization based on their active organization context
   * 5. Return the complete organization object including all fields
   *
   * Error handling:
   * - 404 if organization not found or is soft-deleted
   * - 404 if user does not have access to this organization
   * - 403 if user tries to access organization outside their scope
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":organizationId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformOrganization> {
    try {
      return await getHrmPlatformMemberOrganizationsOrganizationId({
        member,
        organizationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates an organization's configuration and business details within the user's organization context.
   *
   * Modifies organization attributes including display name, description, currency, timezone, and fiscal year settings. All changes are scoped to the user's currently selected organization to maintain multi-tenancy data isolation.
   *
   * The organization name must be unique within the owner's context. Updates that would create duplicate names (including the current name) are rejected. Only members with appropriate permissions in the organization can perform this operation.
   *
   * After a successful update, the updated_at timestamp is automatically set to the current time.
   *
   * @param connection
   * @param organizationId The unique identifier of the organization to update (UUID format).
   * @param body Organization update data with any combination of fields to modify.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update hrm_platform_organizations table by organization ID.
   *
   * Steps:
   * 1. Verify the organization exists and is not soft-deleted (deleted_at is NULL)
   * 2. Verify the requesting user has appropriate permissions in this organization
   * 3. Validate that the new organization name (if provided) is unique within the owner's context
   * 4. Validate fiscal_start_month is between 1 and 12 if provided
   * 5. Update the organization record with the provided fields: name, description, currency, timezone, fiscal_start_month
   * 6. Update updated_at to current timestamp
   * 7. Return the complete updated organization record
   *
   * Validation rules:
   * - Organization must exist and not be deleted
   * - name must be unique within owner context (excluding current record)
   * - currency must be a valid 3-letter currency code (ISO 4217 format)
   * - timezone must be a valid IANA timezone identifier
   * - fiscal_start_month must be between 1 and 12
   *
   * Errors:
   * - 404: Organization not found or deleted
   * - 403: User lacks permissions in this organization
   * - 400: Validation error (duplicate name, invalid currency/timezone, fiscal month out of range)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":organizationId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformOrganization.IUpdate,
  ): Promise<IHrmPlatformOrganization> {
    try {
      return await putHrmPlatformMemberOrganizationsOrganizationId({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete an organization and all its associated data.
   *
   * This operation performs a hard delete of the organization, which irreversibly removes the organization and all its child records including employees, projects, tasks, timelogs, timesheets, contracts, and departments. Activity logs are retained for audit and compliance purposes.
   *
   * ## Deletion Prerequisites
   *
   * Before deletion, all blocking conditions must be resolved:
   * - All pending timesheets must be resolved (approved or rejected) — no timesheets can be in draft or submitted status
   * - No active employee contracts may exist — all contracts must have an end date
   *
   * ## Authorization
   *
   * Only the organization owner can delete the organization. If you are not the owner, you cannot perform this operation.
   *
   * ## After Deletion
   *
   * The organization and all its data will be permanently removed and cannot be recovered. If the deleted organization was your only organization, your member account remains active but is no longer associated with any organization.
   *
   * @param connection
   * @param organizationId The UUID of the organization to be hard deleted.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Verify current user is the owner of the organization (check owner_id matches authenticated user id)
   * 2. Validate no blocking conditions exist:
   *    - Query hrm_platform_timesheets for any with status NOT IN ('approved', 'rejected') where employee_id belongs to this organization
   *    - Query hrm_platform_contracts for any with end_date NULL or end_date > current_date where employee_id belongs to this organization
   * 3. If blocking conditions exist, return 409 Conflict with details of what is blocking deletion
   * 4. Begin transaction:
   *    - Delete all timelogs for employees in this organization
   *    - Delete all timers for employees in this organization
   *    - Delete all task_histories for tasks in this organization
   *    - Delete all tasks for this organization
   *    - Delete all project_memberships for this organization
   *    - Delete all projects for this organization
   *    - Delete all contracts for employees in this organization
   *    - Delete all employees in this organization
   *    - Delete all departments for this organization
   *    - Delete organization_files for this organization
   *    - Delete the organization record itself
   * 5. Return the deleted organization details before removal
   * 6. Commit transaction
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":organizationId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberOrganizationsOrganizationId({
        member,
        organizationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
