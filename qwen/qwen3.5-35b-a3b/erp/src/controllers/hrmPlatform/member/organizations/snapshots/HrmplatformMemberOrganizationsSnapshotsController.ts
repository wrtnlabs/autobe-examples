import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformOrganizationsSnapshot } from "../../../../../api/structures/IHrmPlatformOrganizationsSnapshot";
import { IPageIHrmPlatformOrganizationsSnapshot } from "../../../../../api/structures/IPageIHrmPlatformOrganizationsSnapshot";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberOrganizationsOrganizationIdSnapshotsSnapshotId } from "../../../../../providers/getHrmPlatformMemberOrganizationsOrganizationIdSnapshotsSnapshotId";
import { patchHrmPlatformMemberOrganizationsOrganizationIdSnapshots } from "../../../../../providers/patchHrmPlatformMemberOrganizationsOrganizationIdSnapshots";
import { postHrmPlatformMemberOrganizationsOrganizationIdSnapshots } from "../../../../../providers/postHrmPlatformMemberOrganizationsOrganizationIdSnapshots";

@Controller("/hrmPlatform/member/organizations/:organizationId/snapshots")
export class HrmplatformMemberOrganizationsSnapshotsController {
  /**
   * Create a point-in-time snapshot of an organization for audit trail and historical tracking.
   *
   * Creates an immutable record of the organization's complete state at a specific moment, including name, description, settings, and configuration. Snapshots are used for compliance, debugging, and historical analysis of organizational changes.
   *
   * Only organization owners can create snapshots. The organization must exist and be in an active or suspended state (not archived) to create a snapshot.
   *
   * @param connection
   * @param organizationId Unique identifier of the organization to create a snapshot for (global scope)
   * @param body Configuration data to capture in the organization snapshot. Includes organization name, description, branding, financial settings, and status. All fields except metadata are required.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Create a new organization snapshot record with
     *   the provided configuration.
   *
   * Validation:
   * 1. Verify organizationId exists in hrm_platform_organizations table
   * 2. Verify the requesting user has organization owner role for this organization
   * 3. Verify organization status is not 'archived' before creating snapshot
   * 4. Validate all input fields against schema constraints
   *
   * Database Operation:
   * 1. Insert new record into hrm_platform_organizations_snapshots table
   * 2. Set id to auto-generated UUID
   * 3. Set hrm_platform_organization_id to the path parameter value
   * 4. Store all provided fields (name, description, logo_uri, currency, timezone, fiscal_start_month, status, metadata)
   * 5. Set created_at to current timestamp with timezone
   *
   * Error Handling:
   * - Return 404 if organization not found
   * - Return 403 if user is not organization owner
   * - Return 400 if organization is archived or input validation fails
   * - Return 409 if snapshot already exists for same timestamp (if timestamp constraint exists)
   *
   * Return the complete created snapshot record including system-generated fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformOrganizationsSnapshot.ICreate,
  ): Promise<IHrmPlatformOrganizationsSnapshot> {
    try {
      return await postHrmPlatformMemberOrganizationsOrganizationIdSnapshots({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * List organization snapshots with pagination and filtering.
   *
   * Retrieves a paginated list of point-in-time snapshots for the specified organization. Each snapshot captures the organization's state (name, description, settings) at a specific moment for audit trail purposes.
   *
   * Returns snapshot records sorted by creation timestamp in descending order (newest first). Supports filtering by date range, status, and search on name field. All operations are scoped to the organization context specified in the path parameter.
   *
   * @param connection
   * @param organizationId UUID of the organization whose snapshots to retrieve.
   * @param body Search criteria including date range filters, status filter, name search, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_organizations_snapshots table
     *   filtered by hrm_platform_organization_id = organizationId.
   *
   * Apply pagination with cursor-based or offset-based approach.
   * Apply search filters: created_at date range, name search, status filter.
   * Sort by created_at DESC by default (newest snapshots first).
   * Include summary fields: id, name, description, currency, timezone, fiscal_start_month, status, created_at.
   *
   * Validate that organizationId exists and user has permission to view organization snapshots.
   * Filter results to only include snapshots belonging to the specified organization.
   * Apply organization data isolation - user can only view snapshots for their current organization context.
   * Return IPageIHrmPlatformOrganizationSnapshot.ISummary structure with pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformOrganizationsSnapshot.IRequest,
  ): Promise<IPageIHrmPlatformOrganizationsSnapshot.ISummary> {
    try {
      return await patchHrmPlatformMemberOrganizationsOrganizationIdSnapshots({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a point-in-time snapshot of an organization's state.
   *
   * Returns the complete snapshot record for the specified organization and snapshot ID. This endpoint is used for auditing and historical analysis, allowing users to view exactly what an organization's data looked like at a specific moment in time.
   *
   * The snapshot includes all organizational attributes captured at the time of creation: name, description, logo, currency, timezone, fiscal year settings, status, and metadata. This provides an immutable record for compliance and historical tracking purposes.
   *
   * @param connection
   * @param organizationId Unique identifier of the parent organization
   * @param snapshotId Unique identifier of the snapshot to retrieve
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_organizations_snapshots table
     *   for the snapshot with matching ID and verify it belongs to the
     *   specified organization.
   *
   * 1. Fetch snapshot record where id = snapshotId AND hrm_platform_organization_id = organizationId
   * 2. Return the full snapshot entity if found
   * 3. Return 404 Not Found if snapshot does not exist or does not belong to the specified organization
   * 4. Return 403 Forbidden if user does not have permission to access the organization
   *
   * The organization context is enforced through the path parameter to ensure proper data isolation and access control.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformOrganizationsSnapshot> {
    try {
      return await getHrmPlatformMemberOrganizationsOrganizationIdSnapshotsSnapshotId(
        {
          member,
          organizationId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
