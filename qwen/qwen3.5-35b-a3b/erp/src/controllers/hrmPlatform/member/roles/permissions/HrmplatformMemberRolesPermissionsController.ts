import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformPermission } from "../../../../../api/structures/IHrmPlatformPermission";
import { IHrmPlatformRole } from "../../../../../api/structures/IHrmPlatformRole";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberRolesRoleIdPermissionsPermissionId } from "../../../../../providers/getHrmPlatformMemberRolesRoleIdPermissionsPermissionId";
import { patchHrmPlatformMemberRolesRoleIdPermissions } from "../../../../../providers/patchHrmPlatformMemberRolesRoleIdPermissions";
import { postHrmPlatformMemberRolesRoleIdPermissions } from "../../../../../providers/postHrmPlatformMemberRolesRoleIdPermissions";

@Controller("/hrmPlatform/member/roles/:roleId/permissions")
export class HrmplatformMemberRolesPermissionsController {
  /**
   * Add a permission to an existing role within the organization.
   *
   * This operation assigns a new permission to a specific role. The permission code must be unique within the organization. The role's organization context is automatically inherited from the target role.
   *
   * ### Permission Assignment Rules
   *
   * - Each permission belongs to exactly one role and one organization
   * - Permission codes follow dot notation (e.g., 'employee.view', 'project.manage')
   * - Code must be unique within the organization scope
   * - Permissions can be assigned to built-in and custom roles
   * - Organization owners can manage permission assignments for all roles
   *
   * @param connection
   * @param roleId UUID of the role to add the permission to.
   * @param body Permission details including the unique permission code and optional description. The organization context is inherited from the target role.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Find role by roleId from hrm_platform_roles table
   * 2. Validate role exists and is not soft-deleted
   * 3. Extract organization_id from the role
   * 4. Check if permission code already exists in the same organization using @@unique([organization_id, code]) constraint
   * 5. Create new hrm_platform_permissions record with:
   *    - id: generate UUID
   *    - role_id: from path parameter
   *    - organization_id: from role
   *    - code: from request body
   *    - description: from request body (nullable)
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   *    - deleted_at: null
   * 6. Return the created permission record
   *
   * Error scenarios:
   * - 404: Role not found or soft-deleted
   * - 409: Permission code already exists in organization
   * - 400: Invalid permission code format
   * - 403: User lacks organization management permissions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformRole.IPermissionCreate,
  ): Promise<IHrmPlatformPermission> {
    try {
      return await postHrmPlatformMemberRolesRoleIdPermissions({
        member,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the permissions assigned to a specific role by specifying which permission codes should be associated with the role.
   *
   * This operation allows organization owners to modify the permission set of a custom role by providing a list of permission codes. When executed, the system will add any new permission codes to the role and remove any codes not included in the request, effectively replacing the existing permission assignment.
   *
   * Built-in roles (Owner, Manager, Employee) cannot have their permissions modified through this operation. Only custom roles (role_kind: 'custom') can have their permissions updated. Attempting to modify permissions of built-in roles will result in an error.
   *
   * @param connection
   * @param roleId UUID of the role whose permissions are being updated.
   * @param body Set of permission codes to assign to the role. The list replaces all existing permission assignments for the role. Only permission codes that exist in the organization are valid. Built-in roles cannot have their permissions modified.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate that the roleId exists in the hrm_platform_roles table and belongs to the requesting organization.
   * 2. Verify the role is a custom role (role_kind = 'custom'). If the role is a built-in role (role_kind = 'built_in'), return 400 Bad Request with error message.
   * 3. Validate the request body contains a non-empty array of permission codes.
   * 4. For each permission code in the request:
   *    a. Validate the permission code exists in the hrm_platform_permissions table and belongs to the same organization.
   *    b. Collect valid permission IDs for assignment.
   * 5. Delete all existing permissions assigned to this role from hrm_platform_permissions.
   * 6. Insert new permission records for each valid permission code, linking them to the roleId.
   * 7. Return the updated role with its new set of permissions.
   * 8. Log the permission change in hrm_platform_activity_logs for audit trail.
   * 9. Error handling: Return 404 if role not found, 403 if user lacks permission to modify roles, 400 for invalid permission codes or built-in role attempts, 409 if permission codes already assigned (should not occur given replace behavior).
   *
   * Business Rules:
   * - Only organization owners can modify role permissions (requires employee:manage permission based on Section 128 and 195).
   * - Permission codes must follow the dot-notation convention (e.g., 'employee.view', 'project.manage').
   * - All permission codes must belong to the same organization as the role.
   * - Changes take effect immediately and apply to all employees assigned to this role.
   * - Built-in roles (Owner, Manager, Employee) are protected and cannot have their permissions modified (Section 45, 190).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformRole.IUpdate,
  ): Promise<IHrmPlatformRole> {
    try {
      return await patchHrmPlatformMemberRolesRoleIdPermissions({
        member,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific permission by its unique identifier within a role.
   *
   * This operation returns the complete permission entity including its code, description, and organizational context. The permission must belong to the specified role for the operation to succeed.
   *
   * Security: Only users with role management permissions within the organization can access this information.
   *
   * @param connection
   * @param roleId UUID identifier of the role containing this permission
   * @param permissionId UUID identifier of the permission to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate that both roleId and permissionId are valid UUID format
   * 2. Verify that the role exists and belongs to the requesting user's organization
   * 3. Query hrm_platform_permissions to find the permission with the given permissionId
   * 4. Validate that the permission's role_id matches the provided roleId
   * 5. If permission doesn't exist or doesn't belong to the role, return 404 Not Found
   * 6. Join with hrm_platform_roles and hrm_platform_organizations to include role name and organization details
   * 7. Return the complete permission entity with all fields (id, code, description, createdAt, updatedAt, role, organization)
   * 8. Handle soft-deleted permissions (deleted_at is not null) - exclude from results
   *
   * Business Rules:
   * - Permissions follow the code convention: 'organization.*', 'employee.*', 'project.*', 'time.*', 'report.*'
   * - Built-in roles (Owner, Manager, Employee) have fixed permission sets that cannot be modified
   * - Custom roles can have any combination of permissions
   * - Multi-tenancy is enforced: user can only access permissions within their organization
   *
   * Error Handling:
   * - 404: Permission not found or does not belong to the specified role
   * - 403: User lacks permissions to view role information
   * - 400: Invalid UUID format in path parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":permissionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedParam("permissionId")
    permissionId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformPermission> {
    try {
      return await getHrmPlatformMemberRolesRoleIdPermissionsPermissionId({
        member,
        roleId,
        permissionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
