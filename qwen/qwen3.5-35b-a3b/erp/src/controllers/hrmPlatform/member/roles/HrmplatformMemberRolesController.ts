import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformRole } from "../../../../api/structures/IHrmPlatformRole";
import { IPageIHrmPlatformRole } from "../../../../api/structures/IPageIHrmPlatformRole";
import { IPlatformRoleAnalytic } from "../../../../api/structures/IPlatformRoleAnalytic";
import { IPlatformRoleStat } from "../../../../api/structures/IPlatformRoleStat";
import { IRolesAnalyticsRequest } from "../../../../api/structures/IRolesAnalyticsRequest";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteHrmPlatformMemberRolesRoleId } from "../../../../providers/deleteHrmPlatformMemberRolesRoleId";
import { getHrmPlatformMemberRolesRoleId } from "../../../../providers/getHrmPlatformMemberRolesRoleId";
import { getHrmPlatformMemberRolesStats } from "../../../../providers/getHrmPlatformMemberRolesStats";
import { patchHrmPlatformMemberRoles } from "../../../../providers/patchHrmPlatformMemberRoles";
import { patchHrmPlatformMemberRolesAnalytics } from "../../../../providers/patchHrmPlatformMemberRolesAnalytics";
import { postHrmPlatformMemberRoles } from "../../../../providers/postHrmPlatformMemberRoles";
import { putHrmPlatformMemberRolesRoleId } from "../../../../providers/putHrmPlatformMemberRolesRoleId";

@Controller("/hrmPlatform/member/roles")
export class HrmplatformMemberRolesController {
  /**
   * Create a new custom role within the organization for managing employee permissions.
   *
   * This operation allows organization owners to define custom roles with unique names and specific permission combinations. The role name must be unique within the organization context. Built-in roles (Owner, Manager, Employee) are protected and cannot be created through this endpoint.
   *
   * After creation, the custom role can be assigned to employees who will inherit its permissions. The role is immediately available for assignment and can be modified or deleted (if no employees are assigned).
   *
   * @param connection
   * @param body Role creation parameters including organization context, name, description, and role classification. Built-in roles cannot be created through this endpoint.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new custom role in the hrm_platform_roles table.
   *
   * Validation Rules:
   * 1. Verify user has organization management permissions (organization:manage)
   * 2. Extract organization_id from user's current organization context (from JWT session)
   * 3. Validate role_kind is 'custom' - reject attempts to create built-in roles
   * 4. Check name uniqueness within organization (case-insensitive comparison)
   * 5. Validate name is not empty and does not exceed 100 characters
   * 6. Ensure organization_id references an existing organization
   * 7. Verify no soft-deleted roles with the same name exist in the organization
   *
   * Business Logic:
   * 1. Generate new UUID for id field
   * 2. Set created_at and updated_at to current UTC timestamp
   * 3. Set role_kind to 'custom' (built-in roles are system-managed)
   * 4. Insert the role record with soft delete support (deleted_at = NULL)
   * 5. Return the complete role object including generated id and timestamps
   *
   * Error Handling:
   * - 403 Forbidden: User lacks organization management permissions
   * - 400 Bad Request: Invalid role_kind value, name too long or empty
   * - 409 Conflict: Role name already exists in the organization (case-insensitive)
   * - 404 Not Found: Organization not found or user's organization context invalid
   *
   * Edge Cases:
   * - Concurrent role creation with same name handled by unique constraint
   * - Built-in role names (Owner, Manager, Employee) should be rejected even for custom roles
   * - Name validation should strip leading/trailing whitespace before uniqueness check
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformRole.ICreate,
  ): Promise<IHrmPlatformRole> {
    try {
      return await postHrmPlatformMemberRoles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * List and search roles within an organization with pagination and filtering.
   *
   * Retrieves a paginated list of roles belonging to the currently active organization. Supports filtering by role name, role kind (built-in or custom), and optional search text. Results can be sorted by name, creation date, or last update date. Built-in roles (Owner, Manager, Employee) are always included unless filtered by role_kind.
   *
   * ### Permissions
   *
   * Users need the `role:view` permission to access this endpoint. The returned roles are scoped to the active organization context.
   *
   * ### Filtering
   *
   * - **name**: Filter by role name (case-sensitive, prefix match)
   * - **role_kind**: Filter by role type ("built_in" or "custom")
   * - **search**: Search across name and description fields (case-insensitive)
   * - **sort**: Sort results by name, created_at, or updated_at
   * - **order**: Sort direction (asc/desc)
   *
   * @param connection
   * @param body Search criteria for roles including filters, pagination, and sorting parameters. Supports filtering by name, role_kind, and search text. Pagination uses offset/limit or cursor-based approach. Sorting supports name, created_at, updated_at fields.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Verify user has role:view permission for the active organization
   * 2. Query hrm_platform_roles table filtered by organization_id = active_context.organization_id
   * 3. Apply soft delete filter: deleted_at IS NULL
   * 4. Apply search filters:
   *    - name: WHERE name LIKE :name (prefix match)
   *    - role_kind: WHERE role_kind = :role_kind
   *    - search: WHERE name ILIKE :search OR description ILIKE :search
   * 5. Apply sorting:
   *    - ORDER BY :sort_field :order (default: created_at DESC)
   * 6. Apply pagination:
   *    - LIMIT :limit, OFFSET :offset (cursor-based pagination preferred for large datasets)
   * 7. Return paginated results with total count
   * 8. Include role permissions count in response (join hrm_platform_permissions for permission count)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformRole.IRequest,
  ): Promise<IPageIHrmPlatformRole.ISummary> {
    try {
      return await patchHrmPlatformMemberRoles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a role by its unique identifier.
   *
   * Returns the complete role entity including its name, description, role kind (built-in or custom), organization reference, and timestamps. This operation is used to display role details in the UI or for validation purposes.
   *
   * Only users with the role:view permission can access this endpoint. The operation validates that the requested role exists and is not soft-deleted.
   *
   * @param connection
   * @param roleId UUID identifier of the role to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_roles table by id (UUID).
   *
   * 1. Validate roleId is a valid UUID format
   * 2. Query the role record where id = roleId
   * 3. Verify role.deleted_at is NULL (not soft-deleted)
   * 4. Check user has role:view permission for the role's organization
   * 5. Return the full role entity with all fields
   *
   * Error handling:
   * - Return 404 if role not found or soft-deleted
   * - Return 403 if user lacks permission
   * - Return 400 if roleId format is invalid
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":roleId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformRole> {
    try {
      return await getHrmPlatformMemberRolesRoleId({
        member,
        roleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing role within the organization.
   *
   * Updates the specified role's attributes including name, description, and associated permissions. Custom roles can be fully modified while built-in roles (Owner, Manager, Employee) are protected from modification. The operation validates that the new role name is unique within the organization (case-insensitive comparison). Only users with the employee:manage permission can perform this operation.
   *
   * The role must exist and not be soft-deleted. For custom roles, all permissions can be modified by assigning or removing them from the role's permission set. Built-in roles return an error if modification is attempted.
   *
   * @param connection
   * @param roleId The UUID identifier of the role to update.
   * @param body Updateable fields for the role including name, description, and permission assignments.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate user has employee:manage permission for the organization.
   * 2. Fetch role by roleId from hrm_platform_roles table.
   * 3. Verify role exists and deleted_at is NULL.
   * 4. If role_kind is 'built_in', return 403 Forbidden error.
   * 5. Validate name uniqueness: if name is provided, check no other role in same organization has the same name (case-insensitive).
   * 6. Apply updates to name, description fields from request body.
   * 7. For permissions: if permissions array is provided, replace all existing permissions with the new set.
   * 8. Update updated_at timestamp to current time.
   * 9. Return the updated role with all fields including updated permissions list.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":roleId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformRole.IUpdate,
  ): Promise<IHrmPlatformRole> {
    try {
      return await putHrmPlatformMemberRolesRoleId({
        member,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a custom role from the organization.
   *
   * This operation removes a custom role from the organization's role hierarchy. Only roles with kind='custom' can be deleted. Built-in roles (Owner, Manager, Employee) are protected and cannot be deleted under any circumstances.
   *
   * Before deletion, the system verifies that no employees are currently assigned to the role. If any employee has the role assigned, the deletion is rejected to prevent accidental access removal.
   *
   * Once deleted, custom roles cannot be recovered. The role's associated permissions are also removed from the organization.
   *
   * @param connection
   * @param roleId Unique identifier of the role to delete. Must be a UUID format.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Verify the role exists and is not soft-deleted (deleted_at is NULL).
   * 2. Check role.kind field: reject with 403 Forbidden if role_kind is 'built_in'.
   * 3. Count assigned employees via hrm_platform_employees WHERE hrm_platform_role_id = roleId AND deleted_at IS NULL.
   * 4. If employee count > 0, reject with 400 Bad Request explaining that all employees must be reassigned first.
   * 5. If all validations pass, perform soft delete by setting deleted_at to current timestamp.
   * 6. Return 204 No Content on success.
   *
   * Error responses:
   * - 404 Not Found: role does not exist or is already deleted
   * - 403 Forbidden: attempting to delete built-in role
   * - 400 Bad Request: role has assigned employees
   *
   * Authorization: Requires organization management permissions for the requesting user's organization.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":roleId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberRolesRoleId({
        member,
        roleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve comprehensive role analytics for the organization, including role distribution statistics, permission usage metrics, and employee assignment counts.
   *
   * ### Overview
   *
   * This endpoint computes aggregate statistics about roles within the organization, including:
   * - Total count of roles by kind (built-in vs custom)
   * - Permission distribution across roles
   * - Employee assignment statistics per role
   * - Role usage metrics for organizational analysis
   *
   * ### Features
   *
   * - **Filter by Role Kind**: Restrict analytics to built-in roles, custom roles, or all roles
   * - **Permission Count Filter**: Filter roles by minimum or maximum permission count
   * - **Employee Assignment Filter**: Filter roles with or without employee assignments
   * - **Name Search**: Search roles by name substring
   *
   * @param connection
   * @param body Analytics query parameters including role kind filter, permission count thresholds, employee assignment filter, and search criteria.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Filter hrm_platform_roles by organization_id (from authentication context)
   * 2. Apply optional filters:
   *    - role_kind: filter by 'built_in' or 'custom'
   *    - min_permission_count / max_permission_count: filter by permission count
   *    - has_employees: true/false to filter roles with/without assignments
   *    - name: substring search on role name (case-insensitive)
   * 3. For each role, count associated permissions from hrm_platform_permissions where deleted_at IS NULL
   * 4. For each role, count assigned employees from hrm_platform_employees where role_id matches
   * 5. Aggregate statistics:
   *    - total_count: total roles after filtering
   *    - built_in_count: count of built-in roles
   *    - custom_count: count of custom roles
   *    - total_permission_count: sum of all permissions across all roles
   *    - roles_with_employees: count of roles with at least one employee
   *    - roles_without_employees: count of roles with zero employees
   * 6. Return role details:
   *    - role id, name, description, role_kind, permission_count, employee_count, is_custom
   * 7. Sort results by name ascending (default), or by employee_count descending if sort_by=employees
   * 8. Support pagination on the role list
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("analytics")
  public async analytics(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IRolesAnalyticsRequest,
  ): Promise<IPlatformRoleAnalytic> {
    try {
      return await patchHrmPlatformMemberRolesAnalytics({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve aggregated statistics about roles within the selected organization.
   *
   * This endpoint provides a comprehensive overview of role distribution across the organization, including the count of roles by type (built-in vs custom), the number of employees assigned to each role, and the frequency of permission usage across all roles.
   *
   * The statistics are calculated in real-time from the current state of the roles, employees, and permissions tables. This data is useful for organizational audits, capacity planning, and compliance reporting.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_roles table to gather organization-wide role statistics.
   *
   * 1. Count total roles, filtering by role_kind:
   *    - Count built-in roles (Owner, Manager, Employee)
   *    - Count custom roles
   *
   * 2. Calculate employee distribution:
   *    - Count employees assigned to each role using hrm_platform_employees.role_id
   *    - Group by role name or ID
   *
   * 3. Aggregate permission statistics:
   *    - Count total permissions across all roles
   *    - Count unique permission codes in use
   *
   * 4. Apply organization scoping:
   *    - All statistics are scoped to the authenticated user's selected organization
   *    - Join hrm_platform_roles.organization_id with the organization context
   *
   * 5. Return structured summary:
   *    - Total roles count
   *    - Employee count per role
   *    - Permission usage metrics
   *
   * No path parameters required. Organization context is implicit from the user's session.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("stats")
  public async stats(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IPlatformRoleStat> {
    try {
      return await getHrmPlatformMemberRolesStats({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
