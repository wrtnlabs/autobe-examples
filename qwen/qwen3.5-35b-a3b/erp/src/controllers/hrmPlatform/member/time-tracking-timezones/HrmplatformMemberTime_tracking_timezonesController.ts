  /**
   * Update the timezone configuration for an organization.
   *
   * Updates the IANA timezone identifier used for time calculations across the organization. This setting affects how timer operations, timelogs, and timesheets display and calculate time for all employees in the organization.
   *
   * The timezone field must be a valid IANA Time Zone Database identifier (e.g., 'Asia/Seoul', 'America/New_York', 'Europe/London'). Invalid timezone identifiers are rejected.
   *
   * Only users with organization management permissions can update timezone settings. The organization context is implicit from the user's current organization selection.
   *
   * The operation validates that the timezone configuration exists and is not soft-deleted before updating. The updated_at timestamp is automatically set to the current time when the update is committed.
   *
   * @param connection
   * @param timezoneId UUID identifier of the timezone configuration to update.
   * @param body Timezone configuration update data containing the new IANA timezone identifier.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate that the user has organization management permissions (org:manage)
   * 2. Extract organization context from the user's current organization selection
   * 3. Find the timezone configuration record by timezoneId
   * 4. Verify the record exists and deleted_at is NULL (not soft-deleted)
   * 5. Verify the record belongs to the user's organization (organization_id match)
   * 6. Validate the provided timezone format: must be valid IANA timezone identifier
   *    - Use IANA Time Zone Database validation
   *    - Reject invalid or custom timezone names
   *    - Accept formats like 'Area/Location' (e.g., 'Asia/Seoul', 'America/New_York')
   * 7. Update the timezone field with the provided value
   * 8. Set updated_at to the current timestamp
   * 9. Return the updated timezone configuration record
   *
   * Edge cases:
   * - If timezoneId not found: return 404 Not Found
   * - If record is soft-deleted: return 404 Not Found
   * - If record belongs to different organization: return 403 Forbidden
   * - If timezone identifier is invalid: return 400 Bad Request with validation error
   * - If user lacks organization management permission: return 403 Forbidden
   *
   * Atomic operations: The update must be atomic - either all changes are committed or none.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
