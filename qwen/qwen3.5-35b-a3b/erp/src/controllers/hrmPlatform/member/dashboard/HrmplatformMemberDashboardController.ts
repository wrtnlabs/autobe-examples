import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformDashboard } from "../../../../api/structures/IHrmPlatformDashboard";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberDashboard } from "../../../../providers/getHrmPlatformMemberDashboard";
import { patchHrmPlatformMemberDashboard } from "../../../../providers/patchHrmPlatformMemberDashboard";

@Controller("/hrmPlatform/member/dashboard")
export class HrmplatformMemberDashboardController {
  /**
   * Retrieve personal dashboard metrics for the authenticated employee.
   *
   * Returns a comprehensive dashboard view including real-time hours tracked today and this week, active timer status, last 5 timelogs, pending timesheet status, and assigned tasks in open or in-progress state.
   *
   * All metrics are scoped to the authenticated employee's organization context. The operation calculates aggregated values from timelogs, timers, timesheets, and tasks tables to provide a complete view of the employee's current work status.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Retrieve personal dashboard data for the
     *   authenticated employee.
   *
   * 1. Get the authenticated employee record using request context (member_id from session -> employee_id in organization context).
   *
   * 2. Calculate hours logged today:
   *    - Query hrm_platform_timelogs where employee_id = current employee and DATE(start_datetime) = current date (in organization timezone).
   *    - Sum duration_minutes and convert to hours.
   *
   * 3. Calculate hours logged this week:
   *    - Determine current week start (Monday) and end (Sunday) based on organization timezone.
   *    - Query hrm_platform_timelogs where employee_id = current employee and start_datetime BETWEEN week_start AND week_end.
   *    - Sum duration_minutes and convert to hours.
   *
   * 4. Get active timer status:
   *    - Query hrm_platform_timers where hrm_platform_employee_id = current employee and status = 'started'.
   *    - Calculate elapsed time from last_tick_at and duration_seconds.
   *    - Return timer details including project and task if associated.
   *
   * 5. Get recent timelogs:
   *    - Query hrm_platform_timelogs where employee_id = current employee.
   *    - Order by created_at DESC, limit 5 entries.
   *    - Include id, start_datetime, end_datetime, duration_minutes, project_id, task_id (if exists), description.
   *
   * 6. Get pending timesheet status:
   *    - Query hrm_platform_timesheets where hrm_platform_employee_id = current employee.
   *    - Find timesheet for current week (start_date within current week).
   *    - Return status, submitted_at, rejected_at, rejection reason if rejected.
   *
   * 7. Get assigned tasks:
   *    - Query hrm_platform_tasks where assigned_employee_id = current employee AND status IN ('TODO', 'IN_PROGRESS').
   *    - Include id, title, status, project_id, due_date.
   *    - Join with projects to get project name.
   *
   * 8. Return aggregated dashboard object with all metrics.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmPlatformDashboard> {
    try {
      return await getHrmPlatformMemberDashboard({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve dashboard metrics for personal or organization view.
   *
   * Personal dashboard displays individual employee metrics including hours logged today, active timer status, recent timelogs, pending timesheet status, and assigned tasks.
   *
   * Organization dashboard displays organization-wide metrics including total active employee count and pending timesheets count. Requires report_view permission to access.
   *
   * All metrics are calculated in real-time from the underlying timelog, timesheet, timer, and employee data to provide accurate, up-to-date reporting.
   *
   * @param connection
   * @param body Filter parameters for dashboard metrics including dashboard type, date range for timelogs, task status filter, and pagination parameters for task list.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Authenticate the request and extract current
     *   user's employee record from session 2. Validate organization context is
     *   present in the request 3. Parse request body to determine dashboard
     *   type (personal or organization) 4. For personal dashboard: - Calculate
     *   hours_logged_today: SUM of all timelogs for this employee where
     *   DATE(start_datetime) = today (in user's timezone) - Get active_timer:
     *   Find timer where employee_id matches and status is 'started' or
     *   'paused', return project and task details with elapsed time - Get
     *   recent_timelogs: Last 5 timelogs for this employee ordered by
     *   created_at DESC - Get pending_timesheet_status: Timesheet for this
     *   employee where start_date of current week, return status and rejection
     *   reason if rejected - Get assigned_tasks: Tasks where
     *   assigned_employee_id matches, status is 'IN_PROGRESS' or 'TODO',
     *   include project name 5. For organization dashboard: - Calculate
     *   total_active_employees: COUNT of employees where status = 'active'
     *   within the organization - Calculate pending_timesheets_count: COUNT of
     *   timesheets where status = 'submitted' within the organization - Verify
     *   user has report_view permission in their role for this organization
     *   (check hrm_platform_permissions where organization_id matches, code =
     *   'report_view') 6. Return aggregated metrics in response body 7. If user
     *   lacks report_view permission and requests organization dashboard,
     *   return 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async metrics(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformDashboard.IRequest,
  ): Promise<IHrmPlatformDashboard.IResponse> {
    try {
      return await patchHrmPlatformMemberDashboard({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
