import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformTaskHistory } from "../../../../../api/structures/IHrmPlatformTaskHistory";
import { IPageIHrmPlatformTaskHistory } from "../../../../../api/structures/IPageIHrmPlatformTaskHistory";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchHrmPlatformMemberTasksTaskIdHistories } from "../../../../../providers/patchHrmPlatformMemberTasksTaskIdHistories";

@Controller("/hrmPlatform/member/tasks/:taskId/histories")
export class HrmplatformMemberTasksHistoriesController {
  /**
   * Retrieve the complete audit history of a task, showing all status changes and modifications.
   *
   * Returns a paginated list of history entries for the specified task. Each entry records when a change occurred, what type of change it was, the previous and new values, and which user made the change.
   *
   * History entries are automatically created by the system whenever a task is modified. Users with view permission for the task can view its complete history, regardless of when the changes occurred.
   *
   * @param connection
   * @param taskId UUID of the task to retrieve history for.
   * @param body Pagination and filtering criteria for task history list.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_task_histories table for all
     *   entries where task_id matches the path parameter.
   *
   * 1. Validate taskId is a valid UUID format
   * 2. Verify the task exists and is not soft-deleted (deleted_at IS NULL)
   * 3. Check user has permission to view the task (either assigned to task or has project management permission)
   * 4. Query history entries with task_id = {taskId}, ordered by changed_at DESC
   * 5. Apply pagination from requestBody: limit, offset, sort by changed_at
   * 6. Only include non-deleted history entries (deleted_at IS NULL)
   * 7. Return paginated results with total count and pagination metadata
   *
   * Edge cases:
   * - Task not found: return 404 Not Found
   * - User lacks permission: return 403 Forbidden
   * - Task has no history: return empty paginated list with total_count: 0 (not error)
   * - History entry cannot be created during status change: rollback status change (atomic operation)
   * - System error retrieving history: return 500 Internal Server Error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformTaskHistory.IRequest,
  ): Promise<IPageIHrmPlatformTaskHistory.ISummary> {
    try {
      return await patchHrmPlatformMemberTasksTaskIdHistories({
        member,
        taskId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
