import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformTask } from "../../../../api/structures/IHrmPlatformTask";
import { IPageIHrmPlatformTask } from "../../../../api/structures/IPageIHrmPlatformTask";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteHrmPlatformMemberTasksTaskId } from "../../../../providers/deleteHrmPlatformMemberTasksTaskId";
import { getHrmPlatformMemberTasksTaskId } from "../../../../providers/getHrmPlatformMemberTasksTaskId";
import { patchHrmPlatformMemberTasks } from "../../../../providers/patchHrmPlatformMemberTasks";
import { postHrmPlatformMemberTasks } from "../../../../providers/postHrmPlatformMemberTasks";
import { putHrmPlatformMemberTasksTaskId } from "../../../../providers/putHrmPlatformMemberTasksTaskId";

@Controller("/hrmPlatform/member/tasks")
export class HrmplatformMemberTasksController {
  /**
   * Create a new task within a project for work tracking and assignment.
   *
   * Creates a task with a unique identifier, associated with a project. Project leads or users with project management permissions can create tasks. The task title is required; description, priority, estimated hours, and due date are optional. Tasks can be created as root tasks or subtasks (max one level of nesting).
   *
   * The system validates user permissions against the target project before creation. Unauthorized users are denied without access to project context.
   *
   * @param connection
   * @param body Task creation data including title, description, project association, and optional fields for assignment, priority, estimated hours, and due date.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate user has permission to create tasks in project (project lead or project management permission per section 508)
   * 2. Validate task title is provided and non-empty
   * 3. Validate if parent_task_id is provided, parent exists, belongs to same project, and is a root task (no existing children with parent to enforce single nesting level)
   * 4. Validate if assigned_employee_id is provided, employee belongs to same organization as project
   * 5. Set status to TODO (default new task status)
   * 6. Set priority to MEDIUM (default priority) if not provided
   * 7. Create task record with auto-generated UUID for id
   * 8. Set created_at and updated_at to current timestamp
   * 9. Return full task object including computed relationships
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformTask.ICreate,
  ): Promise<IHrmPlatformTask> {
    try {
      return await postHrmPlatformMemberTasks({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * List and search tasks within the organization with pagination, filtering, and sorting capabilities.
   *
   * Retrieves tasks that match the provided search criteria. Supports filtering by status (TODO, IN_PROGRESS, IN_REVIEW, DONE), priority (LOW, MEDIUM, HIGH, CRITICAL), project assignment, assigned employee, due date range, and creation date range.
   *
   * Users can paginate through results with cursor-based pagination for efficient large result set handling. Tasks are organization-isolated; users only see tasks from their currently selected organization context.
   *
   * Hierarchical task queries can retrieve child tasks by specifying a parent task ID. Results include summary information optimized for list display, with full details available via the task at endpoint.
   *
   * @param connection
   * @param body Search criteria including status, priority, project, employee, date range filters, sorting, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_tasks table with organization isolation (org_id from user context).
   *
   * Apply search filters from requestBody:
   * - status: filter by exact status (TODO, IN_PROGRESS, IN_REVIEW, DONE)
   * - priority: filter by exact priority (LOW, MEDIUM, HIGH, CRITICAL)
   * - project_id: filter by project
   * - assigned_employee_id: filter by assigned employee
   * - parent_task_id: filter child tasks by parent (hierarchical query)
   * - due_date_after, due_date_before: date range filter
   * - created_after, created_before: creation date range filter
   * - title: partial match search on title field using trigram index
   *
   * Apply sorting from requestBody (sortBy, sortOrder):
   * - sortBy options: created_at, updated_at, due_date, priority, title
   * - sortOrder options: ASC, DESC
   *
   * Apply pagination from requestBody:
   * - limit: maximum 100 items per page
   * - cursor: last task ID from previous page for cursor-based pagination
   *
   * Return IPageIHrmPlatformTask.ISummary with:
   * - items: array of task summaries (excluded: description, parent_task details, children_tasks array to prevent circular references)
   * - totalCount: total matching count
   * - nextCursor: cursor for next page (null if last page)
   *
   * Enforce organization data isolation: only return tasks where project belongs to user's organization (via project_id join with hrm_platform_projects where project.org_id matches user's org_id).
   *
   * Return 404 if organization context not found (edge case).
   * Log task list access for audit trail (activity logging).
   *
   * Handle edge cases:
   * - Empty result set: return paginated response with empty items array
   * - No filters provided: return all tasks for user's organization
   * - Invalid filter values: reject with 400 error
   * - Invalid sort field: default to created_at ASC
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformTask.IRequest,
  ): Promise<IPageIHrmPlatformTask.ISummary> {
    try {
      return await patchHrmPlatformMemberTasks({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single task by its unique identifier.
   *
   * This endpoint returns the complete task entity including title, description, status, priority, assignment details, and timestamps. The task must belong to a project that the requesting user has view access to. If the task does not exist or the user lacks permission, the request is rejected.
   *
   * The task entity includes hierarchical information (parent and children tasks), assigned employee details if applicable, project context, and all relevant metadata for task management operations.
   *
   * @param connection
   * @param taskId Unique identifier of the task to retrieve (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Fetch hrm_platform_tasks record by id from database.
   *
   * 1. Query hrm_platform_tasks where id = {taskId}
   * 2. Verify task exists and deleted_at is null (not soft-deleted)
   * 3. Verify user has project:view permission for task's project_id
   * 4. If user has project:view permission, return task with full entity:
   *    - Include all task fields: id, project_id, parent_task_id, assigned_employee_id, title, description, status, priority, estimated_hours, due_date, created_at, updated_at, deleted_at
   *    - Include related entities: project (id, name), parentTask (if exists, full entity), childrenTasks (array of child task summaries), assignedEmployee (if assigned, employee summary with name and email)
   * 5. If task not found or user lacks permission, return 404 Not Found
   *
   * Edge cases:
   * - Task with parent_task_id: Load and include parent task entity
   * - Task with children: Load and include only summary fields for children (id, title, status, due_date) to prevent excessive data
   * - Unassigned task (assigned_employee_id = null): Return task without employee relationship
   * - Task belongs to different project: Check user's project membership or role-based project:view permission before returning
   *
   * Validation:
   * - taskId must be valid UUID format
   * - rejected: 404 if task does not exist or is soft-deleted
   * - rejected: 403 if user lacks project:view permission for the task's project
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":taskId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformTask> {
    try {
      return await getHrmPlatformMemberTasksTaskId({
        member,
        taskId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing task with new attributes.
   *
   * This operation allows authorized users to modify task properties including title, description, status, priority, assignment, estimated hours, and due date. The user must have project lead role or project management permission in the project associated with the task.
   *
   * Only specific fields can be modified: title, description, status, priority, assigned_employee_id, estimated_hours, and due_date. The project_id is immutable after task creation.
   *
   * Status transitions follow the workflow: TODO → IN_PROGRESS → IN_REVIEW → DONE. Transitions are validated and tracked in the task history table.
   *
   * The operation returns the complete updated task object including all fields.
   *
   * @param connection
   * @param taskId Unique identifier of the task to update.
   * @param body Task fields to update. All fields are optional, allowing partial updates. The project_id cannot be changed after task creation.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate that taskId is a valid UUID format.
   * 2. Query hrm_platform_tasks table to find the task by id.
   * 3. If task not found, return 404 Not Found error.
   * 4. Check soft deletion: if deleted_at is not null, return 404 Not Found error.
   * 5. Query the project_id from the task record.
   * 6. Verify user authorization:
   *    - Check if user has project management permission in the project, OR
   *    - Check if user is assigned as project lead in hrm_platform_project_memberships for this project
   *    - If not authorized, return 403 Forbidden error.
   * 7. Validate any status transition against allowed workflow (TODO → IN_PROGRESS → IN_REVIEW → DONE).
   * 8. Update only provided fields in the request body:
   *    - title: update if provided (required field in DB)
   *    - description: update if provided
   *    - status: update if provided (validate workflow transition)
   *    - priority: update if provided (validate allowed values: LOW, MEDIUM, HIGH, CRITICAL)
   *    - assigned_employee_id: update if provided (validate employee exists in same organization)
   *    - estimated_hours: update if provided (must be >= 0)
   *    - due_date: update if provided
   * 9. Set updated_at timestamp to current time.
   * 10. Save changes to database.
   * 11. Create task history entry in hrm_platform_task_histories table with old and new values for changed fields.
   * 12. Return the complete updated task object.
   *
   * Error cases:
   * - 404: Task not found or already deleted
   * - 403: User not authorized to modify this task
   * - 400: Invalid status transition, invalid priority value, invalid employee ID, estimated_hours < 0, or task_id not matching path parameter
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":taskId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformTask.IUpdate,
  ): Promise<IHrmPlatformTask> {
    try {
      return await putHrmPlatformMemberTasksTaskId({
        member,
        taskId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a task and all its associated history.
   *
   * This operation removes a task from the system along with all its task history entries via cascade deletion. Child tasks (subtasks) are also deleted, including their history.
   *
   * **Authorization**: Requires `project:manage` permission on the project that owns the task.
   *
   * **Irreversible**: Deleted tasks cannot be recovered. This is a permanent deletion with no undo functionality.
   *
   * **Cascade**: All task history entries for the deleted task are automatically removed.
   *
   * @param connection
   * @param taskId UUID of the task to delete.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Verify user is authenticated and has project:manage permission for the project that owns the task.
   * 2. Look up the task by taskId from hrm_platform_tasks.
   * 3. If task not found or deleted_at is not null, return 404 Not Found.
   * 4. Verify the task is owned by the current organization context.
   * 5. Delete the task record from hrm_platform_tasks.
   * 6. Cascade delete all associated hrm_platform_task_histories (handled by database ON DELETE CASCADE).
   * 7. Cascade delete all child tasks (recursive deletion).
   * 8. Return 204 No Content on successful deletion.
   *
   * **Error handling**:
   * - 404: Task not found or already deleted
   * - 403: User lacks project:manage permission
   * - 400: Task has assigned timelogs (if business rule requires)
   * - 500: Database constraint violations or cascade failures
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":taskId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberTasksTaskId({
        member,
        taskId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
