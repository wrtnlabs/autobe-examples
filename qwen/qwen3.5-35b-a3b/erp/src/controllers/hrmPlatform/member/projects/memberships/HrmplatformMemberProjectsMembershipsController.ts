import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformProjectMembership } from "../../../../../api/structures/IHrmPlatformProjectMembership";
import { IPageIHrmPlatformProjectMembership } from "../../../../../api/structures/IPageIHrmPlatformProjectMembership";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteHrmPlatformMemberProjectsProjectIdMembershipsMembershipId } from "../../../../../providers/deleteHrmPlatformMemberProjectsProjectIdMembershipsMembershipId";
import { getHrmPlatformMemberProjectsProjectIdMembershipsMembershipId } from "../../../../../providers/getHrmPlatformMemberProjectsProjectIdMembershipsMembershipId";
import { patchHrmPlatformMemberProjectsProjectIdMemberships } from "../../../../../providers/patchHrmPlatformMemberProjectsProjectIdMemberships";
import { postHrmPlatformMemberProjectsProjectIdMemberships } from "../../../../../providers/postHrmPlatformMemberProjectsProjectIdMemberships";
import { putHrmPlatformMemberProjectsProjectIdMembershipsMembershipId } from "../../../../../providers/putHrmPlatformMemberProjectsProjectIdMembershipsMembershipId";

@Controller("/hrmPlatform/member/projects/:projectId/memberships")
export class HrmplatformMemberProjectsMembershipsController {
  /**
   * Create a new project membership by assigning an employee to a project with a specified role.
   *
   * Assigns an employee to a project as either a member or project lead. The employee must belong to the same organization as the project. The system enforces uniqueness to prevent duplicate memberships for the same employee-project combination.
   *
   * When creating a membership:
   * - The employee is assigned to the project with the specified role
   * - The organization context is automatically verified and recorded
   * - The created_at timestamp is set automatically
   * - A confirmation response includes the full membership record with the generated ID
   *
   * @param connection
   * @param projectId Unique identifier of the project to assign the employee to.
   * @param body Request body containing the employee assignment and role specification. The employee must belong to the same organization as the project. Role must be either 'member' or 'project_lead'.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new project membership record.
   *
   * Service Logic:
   * 1. Validate that the project exists and is not soft-deleted
   * 2. Validate that the employee exists and is not soft-deleted
   * 3. Verify employee belongs to the same organization as the project
   * 4. Check for existing active membership (employee_id + project_id unique constraint)
   * 5. If duplicate detected, reject with 409 Conflict
   * 6. Create membership record with: employee_id, project_id, organization_id (from project), role
   * 7. Set created_at timestamp automatically
   * 8. Return the created membership with generated ID
   *
   * Business Rules:
   * - Employee must be from the same organization as the project
   * - Duplicate memberships (same employee + project) are rejected
   * - Role must be 'member' or 'project_lead'
   * - Only users with employee:manage permission can create memberships
   *
   * Error Handling:
   * - 404: Project not found, Employee not found, or Employee/Project soft-deleted
   * - 409: Duplicate membership already exists for this employee-project combination
   * - 400: Invalid role value or validation errors
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformProjectMembership.ICreate,
  ): Promise<IHrmPlatformProjectMembership> {
    try {
      return await postHrmPlatformMemberProjectsProjectIdMemberships({
        member,
        projectId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve paginated list of project memberships for a specific project.
   *
   * Returns all active memberships for the specified project, filtered by optional criteria such as member role, employee, or assignment date range. Each membership record includes the employee information and their assigned role within the project.
   *
   * The operation supports cursor-based pagination for efficient handling of large result sets. Employees can view all project memberships for projects they have access to, with their role clearly indicated for each membership.
   *
   * @param connection
   * @param projectId UUID of the project whose memberships are being retrieved.
   * @param body Search and pagination criteria for filtering project memberships.
   *
   *             Includes optional filters for member role, employee, assignment date range, and pagination parameters for cursor-based navigation.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_project_memberships table where hrm_platform_project_id matches the path parameter and deleted_at is null.
   *
   * Apply search filters from request body:
   * - role: filter by member or project_lead
   * - employeeId: filter by specific employee
   * - startDate: filter memberships created after date
   * - endDate: filter memberships created before date
   *
   * Join with hrm_platform_employees table to include employee name and email in response.
   *
   * Apply organization context based on user's active organization to ensure data isolation.
   *
   * Return cursor-based pagination with page, limit, and hasNext fields.
   *
   * Sort by created_at descending by default, with option to sort by employee name or role.
   *
   * Validate that the user has appropriate permissions to view project memberships for this project.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformProjectMembership.IRequest,
  ): Promise<IPageIHrmPlatformProjectMembership.ISummary> {
    try {
      return await patchHrmPlatformMemberProjectsProjectIdMemberships({
        member,
        projectId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the details of a specific project membership, showing an employee's assignment to a project.
   *
   * This operation returns the complete membership record including the employee reference, project reference, assigned role (member or project-lead), and timestamps. The membership represents an employee's relationship with a project, including their capacity and participation level within that project.
   *
   * @param connection
   * @param projectId The unique identifier of the project that the membership belongs to. Used for context and validation.
   * @param membershipId The unique identifier of the project membership to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve a project membership by its ID from hrm_platform_project_memberships table.
   *
   * 1. Query the membership where id = {membershipId}
   * 2. Verify the membership's organization matches the active organization context
   * 3. Optionally verify the membership belongs to the specified {projectId} (for additional validation)
   * 4. Return the full membership record including:
   *    - id: membership UUID
   *    - hrm_platform_employee_id: employee UUID
   *    - hrm_platform_project_id: project UUID
   *    - organization_id: organization UUID
   *    - role: 'member' or 'project_lead'
   *    - created_at: creation timestamp
   *    - updated_at: last modification timestamp
   *    - deleted_at: null if active, non-null if soft-deleted
   *
   * Return 404 Not Found if membership does not exist or is soft-deleted.
   * Return 403 Forbidden if user lacks permission to view project memberships.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":membershipId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("membershipId")
    membershipId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformProjectMembership> {
    try {
      return await getHrmPlatformMemberProjectsProjectIdMembershipsMembershipId(
        {
          member,
          projectId,
          membershipId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates an existing project membership to modify the employee's role within the project.
   *
   * The membership role determines the employee's access and capabilities within the project. Roles can be changed from 'member' to 'project-lead' or vice versa by users with employee management permissions.
   *
   * **Role Changes**:
   * - `member`: Standard contributor who can log time, view tasks, and contribute to deliverables
   * - `project-lead`: Management role with task management capabilities including creating, editing, and changing task status
   *
   * **Security**:
   * Only users with the `employee:manage` permission can update project memberships. The operation validates that the employee belongs to the same organization as the project.
   *
   * @param connection
   * @param projectId Unique identifier of the project containing this membership.
   * @param membershipId Unique identifier of the project membership to update.
   * @param body Update data for project membership. Contains the new role assignment for the employee within this project.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Perform a database UPDATE on hrm_platform_project_memberships table.
   *
   * **Implementation Steps**:
   * 1. Validate membership exists and is not soft-deleted (deleted_at IS NULL)
   * 2. Verify the membership's hrm_platform_project_id matches the {projectId} path parameter
   * 3. Verify the membership's organization_id matches the current user's active organization context
   * 4. Update the role field with the new value from request body
   * 5. Update updated_at timestamp to current time
   * 6. Return the complete updated membership record
   *
   * **Validation Rules**:
   * - Role must be one of: "member" or "project-lead"
   * - Membership must exist and be active
   * - Employee (hrm_platform_employee_id) must belong to the same organization as the project
   * - Only users with employee:manage permission can perform this operation
   *
   * **Error Conditions**:
   * - 404: Membership not found or already deleted
   * - 403: User lacks employee:manage permission
   * - 400: Invalid role value or organization mismatch
   * - 409: Employee already has a membership for this project with different role (duplicate prevention)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":membershipId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("membershipId")
    membershipId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformProjectMembership.IUpdate,
  ): Promise<IHrmPlatformProjectMembership> {
    try {
      return await putHrmPlatformMemberProjectsProjectIdMembershipsMembershipId(
        {
          member,
          projectId,
          membershipId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Removes an employee's membership from a project, deleting their assignment while preserving all historical work data.
   *
   * This operation removes the project membership record, which revokes the employee's access to the project for future work. The employee will no longer be able to log time, view tasks, or contribute to the project. However, all historical data including timelogs, timesheets, and task history entries remain intact and are preserved for audit purposes.
   *
   * The operation requires user confirmation to prevent accidental removal. Only users with the `project:manage` permission on the project can perform this operation. The system validates that both the project and the membership exist and that the requester has appropriate permissions before executing the deletion.
   *
   * @param connection
   * @param projectId The unique identifier of the project from which to remove the membership.
   * @param membershipId The unique identifier of the project membership to remove.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Delete the project membership record identified by membershipId.
   *
   * 1. Fetch the membership record from hrm_platform_project_memberships
   * 2. Verify the membership exists and is not already soft-deleted (deleted_at is null)
   * 3. Verify the project exists and is within the same organization
   * 4. Check the current user has project:manage permission for the project
   * 5. Optionally verify the membership is still active (not removed by another process)
   * 6. Perform soft delete by setting deleted_at to current timestamp
   * 7. Return the deleted membership record for confirmation
   *
   * Error cases:
   * - 404 if membership not found or already soft-deleted
   * - 404 if project not found
   * - 403 if user lacks project:manage permission
   * - 409 if membership is currently assigned to active task or has unsubmitted timesheet
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":membershipId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("membershipId")
    membershipId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberProjectsProjectIdMembershipsMembershipId(
        {
          member,
          projectId,
          membershipId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
