import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IProjectAnalytic } from "../../../../../api/structures/IProjectAnalytic";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberProjectsProjectIdAnalytics } from "../../../../../providers/getHrmPlatformMemberProjectsProjectIdAnalytics";

@Controller("/hrmPlatform/member/projects/:projectId/analytics")
export class HrmplatformMemberProjectsAnalyticsController {
  /**
   * Retrieve comprehensive analytics and aggregated statistics for a specific project.
   *
   * This endpoint provides a snapshot of project health and progress by aggregating data from timelogs and tasks. The response includes total hours logged, budget utilization percentage, task status distribution, and member activity metrics.
   *
   * Data sources include:
   * - Timelogs: Sum of duration_minutes grouped by billable/non-billable
   * - Tasks: Count and distribution across status values (TODO, IN_PROGRESS, IN_REVIEW, DONE)
   * - Budget: Comparison of logged hours against budget_hours (if set)
   * - Members: Count of employees with timelogs or task assignments on the project
   *
   * The analytics are computed at query time to reflect real-time project state.
   *
   * @param connection
   * @param projectId UUID identifier of the project to retrieve analytics for.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Fetch project from hrm_platform_projects table
     *   by UUID (projectId). 2. Verify project exists and is not soft-deleted
     *   (deleted_at IS NULL). 3. Compute timelog aggregations: - Total
     *   duration: SUM(duration_minutes) WHERE project_id = projectId AND
     *   deleted_at IS NULL - Billable duration: SUM(duration_minutes) WHERE
     *   project_id = projectId AND billable = true AND deleted_at IS NULL -
     *   Non-billable duration: SUM(duration_minutes) WHERE project_id =
     *   projectId AND billable = false AND deleted_at IS NULL 4. Compute task
     *   aggregations: - Task counts by status: COUNT(*) GROUP BY status WHERE
     *   project_id = projectId AND deleted_at IS NULL 5. Compute budget
     *   utilization: - If budget_hours IS NOT NULL: utilization =
     *   (total_duration_minutes / 60) / budget_hours * 100 - If budget_hours IS
     *   NULL: utilization = NULL 6. Compute member activity: - Count distinct
     *   employees with timelogs OR task assignments in the project 7. Return
     *   aggregated analytics object.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
  ): Promise<IProjectAnalytic> {
    try {
      return await getHrmPlatformMemberProjectsProjectIdAnalytics({
        member,
        projectId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
