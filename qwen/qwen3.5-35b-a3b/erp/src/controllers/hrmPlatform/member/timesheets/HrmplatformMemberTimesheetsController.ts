import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformTimesheet } from "../../../../api/structures/IHrmPlatformTimesheet";
import { IPageIHrmPlatformTimesheet } from "../../../../api/structures/IPageIHrmPlatformTimesheet";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteHrmPlatformMemberTimesheetsTimesheetId } from "../../../../providers/deleteHrmPlatformMemberTimesheetsTimesheetId";
import { getHrmPlatformMemberTimesheetsTimesheetId } from "../../../../providers/getHrmPlatformMemberTimesheetsTimesheetId";
import { patchHrmPlatformMemberTimesheets } from "../../../../providers/patchHrmPlatformMemberTimesheets";
import { postHrmPlatformMemberTimesheets } from "../../../../providers/postHrmPlatformMemberTimesheets";
import { putHrmPlatformMemberTimesheetsTimesheetId } from "../../../../providers/putHrmPlatformMemberTimesheetsTimesheetId";

@Controller("/hrmPlatform/member/timesheets")
export class HrmplatformMemberTimesheetsController {
  /**
   * Create a new timesheet record for tracking work hours across a specific week period.
   *
   * A timesheet represents a collection of timelogs grouped by week for submission and approval workflow. This operation initializes a new timesheet in pending status, which the employee can then populate with timelogs before submitting for manager review.
   *
   * Only employees can create timesheets for themselves. The timesheet must cover a complete work week (Monday to Sunday). Once created in pending status, the timesheet can be modified until it is submitted for approval.
   *
   * @param connection
   * @param body Timesheet creation data including employee assignment, week period, and optional notes.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Create a new timesheet record in
     *   hrm_platform_timesheets table.
   *
   * 1. Validate that start_date represents a Monday and end_date represents a Sunday of the same week.
   * 2. Validate that end_date is exactly 6 days after start_date (7-day week).
   * 3. Verify hrm_platform_employee_id references an existing employee record.
   * 4. Set status to 'pending' (equivalent to draft state in business logic).
   * 5. Set submitted_at, approved_at, rejected_at, cancelled_at to NULL.
   * 6. Set total_hours to NULL (will be calculated from associated timelogs).
   * 7. Set notes to the provided value or NULL if not provided.
   * 8. Generate a new UUID for the id field.
   * 9. Set created_at and updated_at to the current timestamp.
   * 10. Set deleted_at to NULL (record is active).
   * 11. Return the complete created timesheet record.
   *
   * Error cases:
   * - Return 400 if start_date and end_date don't form a valid week.
   * - Return 404 if hrm_platform_employee_id references a non-existent employee.
   * - Return 409 if a timesheet already exists for this employee covering the same week period (based on @@unique([hrm_platform_employee_id, start_date]) constraint).
   * - Return 403 if the requesting user doesn't have permission to create timesheets for this employee.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformTimesheet.ICreate,
  ): Promise<IHrmPlatformTimesheet> {
    try {
      return await postHrmPlatformMemberTimesheets({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of timesheets with search filters and sorting options.
   *
   * This endpoint provides administrative and user-facing access to timesheet records with support for filtering by status, date ranges, and employee. Results are paginated for efficient browsing of large datasets. Users can sort results by various fields including start date, status, or total hours.
   *
   * Timesheet access follows ownership rules: employees can only view their own timesheets, while managers and organization owners can view all timesheets based on their permissions. The endpoint supports filtering by status values: pending, submitted, approved, rejected, or cancelled.
   *
   * @param connection
   * @param body Search criteria including pagination parameters, filter options for status and date ranges, employee ID filter, and sorting configuration.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_timesheets table with
     *   pagination and filtering.
   *
   * Pagination:
   * - Support page number and page size parameters
   * - Return total count and pagination metadata
   * - Use cursor-based or offset-based pagination for large datasets
   *
   * Filtering:
   * - Filter by status: pending, submitted, approved, rejected, cancelled (optional array filter)
   * - Filter by date range: start_date between start and end parameters
   * - Filter by employee_id: optional single employee ID filter for employee users
   * - Apply ownership validation: employees can only filter by their own employee_id
   * - Status filter defaults to all statuses when not specified
   *
   * Sorting:
   * - Support sorting by start_date, end_date, status, total_hours, created_at
   * - Default sort by start_date descending (most recent weeks first)
   * - Allow ascending/descending order
   *
   * Authorization:
   * - Check user role: employee users can only view their own timesheets
   * - Manager/owner users can view all timesheets in the organization
   * - Filter by hrm_platform_employee_id if user is employee
   *
   * Response:
   * - Return paginated results with hrm_platform_timesheet summary data
   * - Include hrm_platform_employee reference for each timesheet
   * - Calculate or retrieve total_hours from timelogs if not precomputed
   * - Return pagination metadata: page, pageSize, totalCount, totalPages
   *
   * Edge Cases:
   * - Handle empty result sets gracefully
   * - Return 404 if requested employee_id doesn't exist (for employee user validation)
   * - Validate date range parameters (start_date must be before end_date)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformTimesheet.IRequest,
  ): Promise<IPageIHrmPlatformTimesheet.ISummary> {
    try {
      return await patchHrmPlatformMemberTimesheets({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single timesheet by ID with complete details including employee information and associated timelogs.
   *
   * ## Access Control
   *
   * This operation enforces strict access control based on user roles:
   *
   * - **Timesheet Owner**: Employees can view their own timesheets regardless of status (draft, submitted, approved, or rejected).
   * - **Manager/Owner**: Managers and organization owners can view all timesheets within their organization for approval and oversight purposes.
   * - **Unauthorized Access**: Returns 403 Forbidden for users without proper authorization.
   *
   * ## Response Content
   *
   * The response includes the complete timesheet record with:
   *
   * - **Basic Information**: Timesheet ID, week period (start_date, end_date), current status
   * - **Workflow Timestamps**: submitted_at, approved_at, rejected_at, cancelled_at timestamps
   * - **Aggregated Data**: Total hours calculated from all included timelogs
   * - **Employee Information**: The owner of the timesheet
   * - **Timelogs**: All timelog entries included in this timesheet with project, task, and duration details
   * - **Status History**: Full workflow status progression for audit purposes
   *
   * @param connection
   * @param timesheetId Unique identifier of the timesheet to retrieve
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Retrieve a single timesheet by ID from
     *   hrm_platform_timesheets table.
   *
   * Query the timesheet record where id = timesheetId parameter.
   *
   * Authorization checks:
   * - If requester is the timesheet owner (hrm_platform_employee_id), allow access.
   * - If requester is a manager/owner in the same organization, allow access.
   * - Otherwise, return 403 Forbidden.
   *
   * Include related data:
   * - Employee information from hrm_platform_employees
   * - Timelogs from hrm_platform_timelogs via hrm_platform_timesheet_timelogs junction table
   *
   * Apply soft delete filter: WHERE deleted_at IS NULL
   *
   * Return full timesheet entity with all fields including:
   * - id, hrm_platform_employee_id, start_date, end_date
   * - status, submitted_at, approved_at, rejected_at, cancelled_at
   * - notes, total_hours
   * - created_at, updated_at, deleted_at
   * - Related employee object
   * - Array of timelog objects from timelogs relation
   *
   * Handle not found: Return 404 if timesheet doesn't exist or is soft-deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":timesheetId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformTimesheet> {
    try {
      return await getHrmPlatformMemberTimesheetsTimesheetId({
        member,
        timesheetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing timesheet record with new notes or other editable fields.
   *
   * This operation allows the timesheet owner or users with time approval permissions to modify timesheet details while the timesheet is in pending or rejected status. Submitted and approved timesheets are locked and cannot be modified through this endpoint.
   *
   * Only the notes field can be updated through this operation. Timesheet status transitions (submission, approval, rejection, cancellation) are handled through separate workflow operations. Once a timesheet is approved, its timelogs become permanently locked and cannot be modified.
   *
   * The operation validates that the authenticated user has appropriate permissions (owner or manager with time approval) and that the timesheet is in a modifiable state before applying changes.
   *
   * @param connection
   * @param timesheetId UUID identifier of the timesheet to update. Must be a valid UUID format.
   * @param body Fields to update on the timesheet. Currently only the notes field can be modified through this operation. Other fields like status, dates, and timesheet totals are controlled by workflow rules and cannot be directly updated.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Retrieve timesheet by ID from
     *   hrm_platform_timesheets table 2. Verify timesheet exists and is not
     *   soft-deleted (deleted_at IS NULL) 3. Check timesheet status - allow
     *   update only if status is 'pending' or 'rejected' 4. Verify
     *   authorization: authenticated user must be timesheet owner OR have time
     *   approval permission for organization 5. If timesheet belongs to
     *   different organization than user's context, reject with 403 6. Validate
     *   request body fields against IHrmPlatformTimesheet.IUpdate schema 7.
     *   Only allow update of 'notes' field - other fields are read-only or
     *   workflow-controlled 8. Update the timesheet record with new values 9.
     *   Update updated_at timestamp to CURRENT_TIMESTAMP 10. Return updated
     *   full timesheet entity with status, owner details, and timelog count
   *
   * Error handling:
   * - 404 Not Found: timesheet does not exist or was soft-deleted
   * - 403 Forbidden: user lacks permission (not owner, no time approval role)
   * - 409 Conflict: timesheet is in submitted or approved status (locked)
   * - 400 Bad Request: invalid field values or schema validation failure
   *
   * Business rules:
   * - Cannot modify dates once timesheet is created
   * - Cannot modify status through this endpoint (use submission/rejection workflows)
   * - Once approved, timelogs are permanently locked
   * - Notes can be modified at any time while timesheet is in pending or rejected status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":timesheetId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformTimesheet.IUpdate,
  ): Promise<IHrmPlatformTimesheet> {
    try {
      return await putHrmPlatformMemberTimesheetsTimesheetId({
        member,
        timesheetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a timesheet record by setting the soft delete timestamp.
   *
   * This operation removes a timesheet from active workflows while preserving the record for audit purposes. Employees can delete their own timesheets, subject to timesheet status restrictions: timesheets in approved status cannot be deleted unless the user has time management permission. Users with time:manage permission can delete any employee's timesheets regardless of status.
   *
   * ### Access Control
   *
   * - **Timesheet Owner**: Can delete their own timesheets if status is pending, submitted, rejected, or cancelled
   * - **Time Management Users**: Users with time:manage permission can delete any employee's timesheets regardless of status or timesheet ownership
   *
   * ### Error Conditions
   *
   * - **Unauthorised**: Requesting user is neither the timesheet owner nor has time management permission
   * - **Timesheet Not Found**: No timesheet exists with the specified ID
   * - **Timesheet in Approved Status**: Timesheet with approved status cannot be deleted by owner (only time management users can delete approved timesheets)
   *
   * @param connection
   * @param timesheetId Unique identifier of the timesheet to delete (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate timesheetId is a valid UUID format 2.
     *   Query hrm_platform_timesheets WHERE id = timesheetId 3. If record not
     *   found, return 404 Not Found with error: "Timesheet not found" 4. Check
     *   authorization: - Load the employee record from hrm_platform_employees
     *   using timesheet.hrm_platform_employee_id - If
     *   timesheet.hrm_platform_employee_id equals current member's ID
     *   (employee), mark as owner-authorized - Load current member's role and
     *   check if role has time:manage permission - If not owner and not has
     *   time:manage permission, return 403 Forbidden 5. Check if timesheet is
     *   in approved status (status = 'approved'): - If approved AND current
     *   user is NOT time management user, return 403 Forbidden - Approved
     *   timesheets can only be deleted by time management users 6. Perform soft
     *   delete: - Update hrm_platform_timesheets SET deleted_at = NOW() WHERE
     *   id = timesheetId - Cascade delete will automatically remove associated
     *   hrm_platform_timesheet_timelogs and hrm_platform_timesheet_actions
     *   records (onDelete: Cascade) 7. Return the soft-deleted timesheet record
     *   with deleted_at timestamp set 8. Response includes: id,
     *   hrm_platform_employee_id, start_date, end_date, status, deleted_at,
     *   notes, total_hours
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":timesheetId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberTimesheetsTimesheetId({
        member,
        timesheetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
