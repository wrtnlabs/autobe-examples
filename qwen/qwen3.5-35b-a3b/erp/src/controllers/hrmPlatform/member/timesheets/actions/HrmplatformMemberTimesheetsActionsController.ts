import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformTimesheetAction } from "../../../../../api/structures/IHrmPlatformTimesheetAction";
import { IPageIHrmPlatformTimesheetAction } from "../../../../../api/structures/IPageIHrmPlatformTimesheetAction";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberTimesheetsTimesheetIdActionsActionId } from "../../../../../providers/getHrmPlatformMemberTimesheetsTimesheetIdActionsActionId";
import { patchHrmPlatformMemberTimesheetsTimesheetIdActions } from "../../../../../providers/patchHrmPlatformMemberTimesheetsTimesheetIdActions";

@Controller("/hrmPlatform/member/timesheets/:timesheetId/actions")
export class HrmplatformMemberTimesheetsActionsController {
  /**
   * Retrieves all action log records for a specific timesheet to provide complete audit trail visibility.
   *
   * This endpoint returns all timesheet lifecycle events including submission, approval, and rejection actions. Each record contains the actor who performed the action, timestamp, action type, and optional notes or feedback.
   *
   * The operation supports filtering by action type and date range, with pagination for efficient browsing of historical audit data.
   *
   * @param connection
   * @param timesheetId The unique identifier of the timesheet to retrieve actions for.
   * @param body Search criteria and pagination parameters for filtering timesheet actions.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_timesheet_actions table with
     *   WHERE clause filtering by hrm_platform_timesheet_id = {timesheetId}.
   *
   * Apply optional filters on:
   * - action: filter by action type (submit, approve, reject)
   * - actor_id: filter by member who performed the action
   * - date ranges: filter by created_at timestamp
   *
   * Apply pagination with cursor or offset/limit pattern.
   *
   * Order results by created_at DESC to show most recent actions first.
   *
   * Return cursor-based pagination for large audit trails.
   *
   * Validate that the timesheet exists before querying actions.
   *
   * Ensure the requesting user has appropriate permissions to view the timesheet's action history based on their organization membership and role.
   *
   * Do not include soft-deleted timesheets in results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformTimesheetAction.IRequest,
  ): Promise<IPageIHrmPlatformTimesheetAction.ISummary> {
    try {
      return await patchHrmPlatformMemberTimesheetsTimesheetIdActions({
        member,
        timesheetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific timesheet action record.
   *
   * Fetches detailed information about a single action in the timesheet lifecycle, including the actor who performed it, the action type (submit/approve/reject), optional notes or feedback, and the timestamp. This endpoint is used to view individual action details within the timesheet audit trail.
   *
   * Authorization: Only users with access to view the associated timesheet can retrieve its actions. Actions are scoped to the organization and respect member permissions.
   *
   * @param connection
   * @param timesheetId The UUID of the timesheet this action belongs to.
   * @param actionId The UUID of the action to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_timesheet_actions table for
     *   the specific action record matching both timesheetId and actionId.
   *
   * 1. Validate that timesheetId and actionId are valid UUID format
   * 2. Fetch the action record with the given actionId
   * 3. Verify the action belongs to the specified timesheetId (foreign key constraint)
   * 4. Check authorization: the requesting user must have permission to view the timesheet
   * 5. Join with hrm_platform_members table to include actor details (member email/name)
   * 6. Return the full action record with all fields including created_at timestamp
   * 7. Handle 404 if action not found or timesheet mismatch
   *
   * Business Rules:
   * - Only members with appropriate role permissions can view timesheet actions
   * - The actor_id field references the member who performed the action
   * - Notes field is nullable and contains optional feedback/rejection reasons
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":actionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
    @TypedParam("actionId")
    actionId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformTimesheetAction> {
    try {
      return await getHrmPlatformMemberTimesheetsTimesheetIdActionsActionId({
        member,
        timesheetId,
        actionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
