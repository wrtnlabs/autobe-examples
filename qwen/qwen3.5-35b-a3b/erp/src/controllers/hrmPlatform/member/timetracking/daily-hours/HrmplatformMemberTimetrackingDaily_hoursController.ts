import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPlatformTimeTrackingDailyHour } from "../../../../../api/structures/IPlatformTimeTrackingDailyHour";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberTimetrackingDailyHours } from "../../../../../providers/getHrmPlatformMemberTimetrackingDailyHours";

@Controller("/hrmPlatform/member/timetracking/daily-hours")
export class HrmplatformMemberTimetrackingDaily_hoursController {
  /**
   * Retrieve the total hours logged by the current employee for today's date.
   *
   * This endpoint calculates the sum of all timelogs created by the authenticated employee where the log date matches the current day in the employee's organization timezone. The result is displayed as a numeric value with unit indication (hours) on the personal dashboard.
   *
   * The calculation respects the organization's timezone configuration to ensure consistent reporting across different geographical regions.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_timelogs table for entries where:
   * - employee_id matches the authenticated user's employee_id
   * - start_datetime date equals today's date in organization timezone
   *
   * Calculate SUM(duration_minutes) from filtered timelogs and convert to hours (divide by 60).
   *
   * Return 0.00 if no timelogs exist for today.
   *
   * Implementation steps:
   * 1. Extract employee_id from authentication context (session token)
   * 2. Query hrm_platform_time_tracking_timezones to get organization timezone
   * 3. Calculate today's date range in organization timezone (00:00:00 to 23:59:59)
   * 4. Filter timelogs by employee_id and date range
   * 5. Calculate SUM(duration_minutes) from filtered results
   * 6. Convert minutes to hours (float)
   * 7. Return response with hours and date context
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IPlatformTimeTrackingDailyHour.IResponse> {
    try {
      return await getHrmPlatformMemberTimetrackingDailyHours({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
