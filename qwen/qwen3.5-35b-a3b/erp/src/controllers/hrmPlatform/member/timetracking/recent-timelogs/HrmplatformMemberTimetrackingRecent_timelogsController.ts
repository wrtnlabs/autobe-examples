import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformTimelog } from "../../../../../api/structures/IHrmPlatformTimelog";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberTimetrackingRecentTimelogs } from "../../../../../providers/getHrmPlatformMemberTimetrackingRecentTimelogs";

@Controller("/hrmPlatform/member/timetracking/recent-timelogs")
export class HrmplatformMemberTimetrackingRecent_timelogsController {
  /**
   * Retrieve the last 5 timelogs created by the authenticated employee for display on the personal dashboard.
   *
   * This endpoint provides a quick view of the employee's most recent time entries, showing the date, duration, associated project, and work description. The timelogs are returned in descending order by creation date, with the most recent entry appearing first. This allows employees to quickly verify their time tracking data has been recorded correctly.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_timelogs table filtered by the
     *   authenticated employee's ID (from JWT token). Order by created_at
     *   descending. Limit results to 5 rows. Join with hrm_platform_projects to
     *   include project name in response. Exclude soft-deleted timelogs
     *   (deleted_at IS NULL). Return full timelog entity data including id,
     *   project reference, task reference (if any), start/end datetimes,
     *   duration, description, billable flag, and timestamps.
   *
   * Authentication: Required (member actor). Authorization: Employee can only access their own timelogs. Error handling: Return 401 if unauthenticated, 403 if employee tries to access another employee's data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async recent(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmPlatformTimelog> {
    try {
      return await getHrmPlatformMemberTimetrackingRecentTimelogs({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
