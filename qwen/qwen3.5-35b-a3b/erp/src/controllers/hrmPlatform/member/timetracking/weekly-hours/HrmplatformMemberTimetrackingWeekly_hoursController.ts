import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformTimesheetWeeklyStat } from "../../../../../api/structures/IHrmPlatformTimesheetWeeklyStat";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberTimetrackingWeeklyHoursEmployeeId } from "../../../../../providers/getHrmPlatformMemberTimetrackingWeeklyHoursEmployeeId";

@Controller("/hrmPlatform/member/timetracking/weekly-hours/:employeeId")
export class HrmplatformMemberTimetrackingWeekly_hoursController {
  /**
   * Retrieve the total hours logged by the employee for the current week (Monday to Sunday).
   *
   * This endpoint provides the weekly hours summary that appears on the personal dashboard, showing the sum of all timelogs with dates falling within the current week's date range. The week calculation follows the standard Monday-to-Sunday pattern used across the timesheet system.
   *
   * Employees can use this metric to monitor their weekly time accumulation and ensure they are meeting their expected working hours. The data is pre-aggregated in the timesheet_weekly_stats table for efficient dashboard performance.
   *
   * @param connection
   * @param employeeId The unique identifier of the employee whose weekly hours are being retrieved.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Retrieve the current week's total hours logged by
     *   the employee from hrm_platform_timesheet_weekly_stats.
   *
   * Implementation steps:
   * 1. Extract the employeeId from the authenticated user's context (from organization-scoped session) or use the path parameter
   * 2. Calculate the current week period: find the Monday (week_start) and Sunday (week_end) for the current week based on the employee's organization timezone
   * 3. Query hrm_platform_timesheet_weekly_stats for the record matching employee_id and week_start for the current week
   * 4. Return the total_hours field from the weekly statistics record
   * 5. If no record exists (employee hasn't logged time yet), return 0.0 hours
   *
   * Business rules:
   * - The week period calculation must align with the timesheet week definition (Monday to Sunday)
   * - Only active timelogs (deleted_at is null) are included in the aggregation
   * - The operation is read-only and does not modify any data
   * - Return 404 if the employee_id is not found or not a valid member of the organization
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformTimesheetWeeklyStat.ISummary> {
    try {
      return await getHrmPlatformMemberTimetrackingWeeklyHoursEmployeeId({
        member,
        employeeId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
