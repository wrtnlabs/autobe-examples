import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformEmployee } from "../../../../api/structures/IHrmPlatformEmployee";
import { IPageIHrmPlatformEmployee } from "../../../../api/structures/IPageIHrmPlatformEmployee";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberEmployeesEmployeeCode } from "../../../../providers/getHrmPlatformMemberEmployeesEmployeeCode";
import { patchHrmPlatformMemberEmployees } from "../../../../providers/patchHrmPlatformMemberEmployees";

@Controller("/hrmPlatform/member/employees")
export class HrmplatformMemberEmployeesController {
  /**
   * Search and list employees within the organization with filters and pagination.
   *
   * Provides a paginated list of employee records with optional filtering by status, department, job level, employment type, employee code, display name, email, and employment date ranges. Supports sorting by various fields including name, hire date, status, and last update time.
   *
   * The endpoint enforces organization data isolation, returning only employees belonging to the user's currently selected organization. Soft-deleted employees are excluded from results.
   *
   * @param connection
   * @param body Search criteria for employee listing including status filter, department filter, name/email/employee code partial match, job level, employment type, employment date range filters, pending status filter, pagination parameters (first, last, cursor), and sorting options.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_employees table with organization-scoped filtering and pagination.
   *
   * Apply search filters from requestBody:
   * - status: filter by employment status (active, on-leave, resigned, invited, pending)
   * - department_id: filter by department (optional null)
   * - employee_code: partial match search
   * - display_name: partial match search
   * - email: partial match search
   * - job_level: exact match filter
   * - employment_type: exact match filter
   * - start_date_gte: filter employees with start_date >= value
   * - start_date_lte: filter employees with start_date <= value
   * - is_pending: filter by pending assignment status (true/false)
   *
   * Apply sorting (default: updated_at DESC):
   * - updated_at, created_at, start_date, status, display_name
   *
   * Enforce organization scoping: all queries scoped to user's active organization.
   *
   * Exclude soft-deleted records where deleted_at IS NOT NULL.
   *
   * Support cursor-based pagination using lastCursor or first parameters.
   *
   * Join with hrm_platform_roles, hrm_platform_departments, and hrm_platform_members for summary fields when requested.
   *
   * Return paginated results with total count, cursor information, and employee summaries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformEmployee.IRequest,
  ): Promise<IPageIHrmPlatformEmployee.ISummary> {
    try {
      return await patchHrmPlatformMemberEmployees({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific employee within the organization.
   *
   * Returns a single employee record with complete profile data including display name, job title, employment details, department assignment, and role information. The operation enforces organization data isolation, ensuring users can only access employees from their currently selected organization.
   *
   * The response includes all employee fields such as employee code, email, job level, employment type, status, and employment dates. Department information is included when assigned, along with the associated role and permissions.
   *
   * @param connection
   * @param employeeCode The unique employee code that identifies this employee within the organization (scoped to organization)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the hrm_platform_employees table for the employee with the given employee_code within the current organization context.
   *
   * 1. Validate that the employee_code exists in the database
   * 2. Verify the employee belongs to the currently active organization (data isolation)
   * 3. If not found or belongs to different organization, return 404 Not Found
   * 4. Load the complete employee record including department and role details
   * 5. Exclude deleted records (where deleted_at is not null)
   * 6. Return the full employee entity with all fields populated
   * 7. Log the access in activity log if required by permission rules
   *
   * Edge cases:
   * - Employee code not found: 404
   * - Employee belongs to different organization: 404
   * - Employee is soft-deleted: 404
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":employeeCode")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeCode")
    employeeCode: string,
  ): Promise<IHrmPlatformEmployee> {
    try {
      return await getHrmPlatformMemberEmployeesEmployeeCode({
        member,
        employeeCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
