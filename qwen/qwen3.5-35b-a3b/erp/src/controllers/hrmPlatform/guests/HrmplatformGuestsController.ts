import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformGuest } from "../../../api/structures/IHrmPlatformGuest";
import { IPageIHrmPlatformGuest } from "../../../api/structures/IPageIHrmPlatformGuest";
import { getHrmPlatformGuestsGuestId } from "../../../providers/getHrmPlatformGuestsGuestId";
import { patchHrmPlatformGuests } from "../../../providers/patchHrmPlatformGuests";

@Controller("/hrmPlatform/guests")
export class HrmplatformGuestsController {
  /**
   * Retrieve paginated list of guest records with search and filtering capabilities.
   *
   * This endpoint provides administrative access to view unauthenticated visitor data identified by device fingerprint. Guests are users who have not yet registered but are accessing the sign-up page.
   *
   * The operation supports filtering by IP address, device identifier patterns, date ranges for creation/update timestamps, and soft-delete status. Results are paginated with cursor-based pagination for efficient retrieval of large result sets.
   *
   * @param connection
   * @param body Search criteria for guest records
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query hrm_platform_guests table with cursor-based
     *   pagination.
   *
   * Apply search filters from requestBody:
   * - device_identifier: exact match or pattern search using ilike
   * - ip_address: exact match or range search
   * - user_agent: pattern search using ilike on gin-indexed column
   * - created_at: date range filter (gte, lte)
   * - updated_at: date range filter (gte, lte)
   * - deleted_at: filter by null (active) or non-null (deleted)
   * - sortBy: sort by created_at, updated_at, ip_address, or device_identifier
   * - sortOrder: ASC or DESC
   * - cursor: for cursor-based pagination
   * - limit: maximum number of records to return
   *
   * Join logic: none required (single table query)
   *
   * Return paginated results with:
   * - data: array of guest summaries
   * - hasNextCursor: boolean indicating if more records exist
   * - nextCursor: base64-encoded cursor string for next page
   *
   * Handle soft-deleted records based on filter:
   * - If deleted_at filter is null or explicitly requested, include deleted records
   * - Otherwise, exclude records where deleted_at is not null
   *
   * Error handling:
   * - Return 400 if invalid cursor format
   * - Return 400 if invalid date range (start > end)
   * - Return 400 if invalid sortBy field
   * - Return 400 if limit exceeds maximum allowed (100)
   *
   * Security: Only authorized administrators can access this endpoint based on role permissions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IHrmPlatformGuest.IRequest,
  ): Promise<IPageIHrmPlatformGuest.ISummary> {
    try {
      return await patchHrmPlatformGuests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve unauthenticated guest information by ID.
   *
   * Fetches guest record identified by UUID for tracking unauthenticated visitor activity. The operation returns device fingerprint, IP address, user agent, and timestamps. Used for sign-up page attribution and access logging before user registration.
   *
   * @param connection
   * @param guestId Unique identifier for the unauthenticated guest session.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query hrm_platform_guests table by id (UUID).
   *
   * 1. Validate guestId is valid UUID format
   * 2. Fetch guest record where id = guestId
   * 3. If not found, return 404 Not Found
   * 4. Return full guest entity including:
   *    - id (UUID)
   *    - device_identifier (string)
   *    - ip_address (string)
   *    - user_agent (string)
   *    - created_at (timestamptz)
   *    - updated_at (timestamptz)
   *    - deleted_at (nullable timestamptz, may be null if not deleted)
   *
   * 5. No authentication required - guests are unauthenticated visitors
   * 6. Do not include organization-specific data (guests have zero organizational access)
   * 7. Log access attempt in activity logs for audit trail
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":guestId")
  public async at(
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformGuest> {
    try {
      return await getHrmPlatformGuestsGuestId({
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
