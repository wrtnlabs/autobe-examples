import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformGuest } from "../../../../api/structures/IHrmPlatformGuest";
import { postHrmPlatformAuthGuestJoin } from "../../../../providers/postHrmPlatformAuthGuestJoin";
import { postHrmPlatformAuthGuestRefresh } from "../../../../providers/postHrmPlatformAuthGuestRefresh";

@Controller("/hrmPlatform/auth/guest")
export class HrmplatformAuthGuestController {
  /**
   * Create a temporary guest session to allow unauthenticated visitors to access the platform. This operation does not require credentials - guests are identified by device fingerprint (device_identifier) and IP address.
   *
   * When a guest first visits the platform, call this endpoint with device_identifier, ip_address, and user_agent. The system checks if a guest with these identifiers already exists and has an active session. If found, the existing session is returned. If not found, a new guest account and session are created.
   *
   * The response includes access_token for immediate API access and refresh_token for token renewal. Guests do not have an organization context (organization_id is null) until they complete registration and become members.
   *
   * Security considerations: device_identifier should be generated using device fingerprinting on the client side. Sessions expire based on refresh_token_expires_at. Expired sessions must be cleaned up from hrm_platform_guest_sessions.
   *
   * Related operations: refresh - renew guest session tokens
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest session creation request with device identification and browser information
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Create a temporary guest session for
     *   unauthenticated visitors. Check if guest exists by device_identifier
     *   and ip_address. If not found, create new guest record with
     *   device_identifier, ip_address, and user_agent. Create
     *   hrm_platform_guest_sessions record with new session_token (JWT), ip
     *   address, user_agent, referrer. Generate access_token and refresh_token
     *   with different expiration times. Set organization_id to null for
     *   guests. Return IAuthorized response with tokens and session info. Edge
     *   cases: duplicate device_identifier should return existing session if
     *   within expiration window. Errors: 409 if device already has active
     *   session, 400 if device_identifier or ip_address missing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmPlatformGuest.IJoin,
  ): Promise<IHrmPlatformGuest.IAuthorized> {
    try {
      return await postHrmPlatformAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew guest session tokens using an existing valid refresh token. This operation allows guests to extend their temporary session without re-authenticating.
   *
   * Call this endpoint with the current refresh_token from a valid guest session. The system validates the token exists in hrm_platform_guest_sessions and has not expired. Upon successful validation, new access_token and refresh_token are generated with fresh expiration times, and the session is updated.
   *
   * The response includes the new tokens in IAuthorized format. The old tokens become invalid immediately after refresh - this prevents token replay attacks. Guests must call this operation before the refresh_token_expires_at to maintain session continuity.
   *
   * Security considerations: If refresh fails (expired token, invalid token), the guest must call join to create a new session. Session metadata like ip_address and user_agent may be updated for security auditing.
   *
   * Related operations: join - create initial guest session
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest session refresh request with existing refresh token
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Refresh an existing guest session token. Validate
     *   the provided refresh_token by looking it up in
     *   hrm_platform_guest_sessions. Check if the session has not expired
     *   (expired_at > NOW()). If valid, generate new access_token and
     *   refresh_token with fresh expiration times. Update the session record
     *   with new tokens. Return IAuthorized response with new tokens. Edge
     *   cases: 401 if token not found, 401 if token expired, 404 if session
     *   deleted. Security: Invalidate old tokens after refresh to prevent
     *   replay attacks.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IHrmPlatformGuest.IRefresh,
  ): Promise<IHrmPlatformGuest.IAuthorized> {
    try {
      return await postHrmPlatformAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
