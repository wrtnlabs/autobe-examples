import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformMember } from "../../../../api/structures/IHrmPlatformMember";
import { postHrmPlatformAuthMemberJoin } from "../../../../providers/postHrmPlatformAuthMemberJoin";
import { postHrmPlatformAuthMemberLogin } from "../../../../providers/postHrmPlatformAuthMemberLogin";
import { postHrmPlatformAuthMemberRefresh } from "../../../../providers/postHrmPlatformAuthMemberRefresh";

@Controller("/hrmPlatform/auth/member")
export class HrmplatformAuthMemberController {
  /**
   * Register a new member account with email and password. This operation creates the member's global identity and requires creating an initial organization as the owner.
   *
   * **Registration Requirements**:
   * - Email: Valid email format, unique (not already registered)
   * - Password: Meets security requirements (min length, complexity)
   * - Organization name: Required field for initial organization creation
   * - Organization currency: Required field (USD, EUR, KRW, etc.)
   * - Organization description: Optional string
   * - Organization logo: Optional file URI
   * - Organization timezone: Optional (defaults to UTC)
   * - Organization fiscal start month: Optional (1-12 for January-December)
   *
   * **Organization Creation**:
   * Upon successful registration, the system creates an organization with the provided details. The newly registered member becomes the Owner of this organization and gains full access to all features.
   *
   * **Token Issuance**:
   * The operation returns access and refresh tokens immediately, allowing the user to authenticate in subsequent requests without additional login.
   *
   * **Error Handling**:
   * - Email already exists: Reject registration
   * - Invalid email format: Reject registration
   * - Password too weak: Reject registration
   * - Organization name missing: Reject registration
   * - Missing required fields: Reject registration
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration request containing email, password, and initial organization details.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification POST /auth/member/join: Create member account with email/password validation. Create initial organization (name required, currency required, description/logo/timezone/fiscalMonth optional). Assign Owner role to user. Store hashed password. Issue initial tokens. Error on duplicate email, missing required fields, invalid email format, password too weak.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmPlatformMember.IJoin,
  ): Promise<IHrmPlatformMember.IAuthorized> {
    try {
      return await postHrmPlatformAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a member using email and password credentials.
   *
   * **Authentication Flow**:
   * - Email: The member's registered email address (used as unique identifier)
   * - Password: The member's account password (verified against stored hash)
   *
   * **Token Issuance**:
   * Upon successful authentication, the system issues:
   * - Access token: Short-lived token for API authorization
   * - Refresh token: Long-lived token for obtaining new access tokens
   * - Session record: Persisted in hrm_platform_member_sessions
   *
   * **Organization Context**:
   * After login, the member must select which organization to work in (per analysis section 24). If the member belongs to only one organization, it is selected by default.
   *
   * **Error Handling**:
   * - Email not found: Reject with authentication error
   * - Invalid password: Reject with authentication error
   * - Account disabled/deleted: Reject with account status error
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login request containing email and password credentials.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification POST /auth/member/login: Validate email/password credentials. Query hrm_platform_members by email. Verify password hash. Issue access token, refresh token. Create session record. Error on invalid credentials, account not found, incorrect password.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmPlatformMember.ILogin,
  ): Promise<IHrmPlatformMember.IAuthorized> {
    try {
      return await postHrmPlatformAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh the access token using a valid refresh token.
   *
   * **Token Refresh Flow**:
   * - Refresh Token: Long-lived token issued during join or login
   * - Session Validation: Query hrm_platform_member_sessions for valid session
   * - Token Renewal: Issue new access token and new refresh token
   * - Session Update: Update session record with new tokens
   *
   * **Token Lifetimes**:
   * - Access tokens are short-lived (e.g., 15 minutes) for security
   * - Refresh tokens are longer-lived (e.g., 7 days) to avoid frequent re-authentication
   * - When refresh token expires, user must re-login
   *
   * **Security Considerations**:
   * - Refresh tokens are single-use: After renewal, the old refresh token is invalidated
   * - Sessions are scoped to member: Each member can have multiple active sessions
   * - Token rotation prevents token theft: Old tokens become invalid after use
   *
   * **Error Handling**:
   * - Invalid refresh token format: Reject with token error
   * - Token expired: Reject with expiration error
   * - Session not found: Reject with session error
   * - Token mismatch: Reject with security error
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token request containing the refresh token.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification POST /auth/member/refresh: Validate refresh token from hrm_platform_member_sessions. Verify token not expired. Create new access token and refresh token. Update session record with new tokens. Error on invalid token, expired token, token not found, mismatched member.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IHrmPlatformMember.IRefresh,
  ): Promise<IHrmPlatformMember.IAuthorized> {
    try {
      return await postHrmPlatformAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
