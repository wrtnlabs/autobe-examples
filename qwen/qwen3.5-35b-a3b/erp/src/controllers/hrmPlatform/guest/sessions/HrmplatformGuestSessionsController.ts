import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformMemberSession } from "../../../../api/structures/IHrmPlatformMemberSession";
import { IPageIHrmPlatformMemberSession } from "../../../../api/structures/IPageIHrmPlatformMemberSession";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { getHrmPlatformGuestSessionsSessionId } from "../../../../providers/getHrmPlatformGuestSessionsSessionId";
import { patchHrmPlatformGuestSessions } from "../../../../providers/patchHrmPlatformGuestSessions";

@Controller("/hrmPlatform/guest/sessions")
export class HrmplatformGuestSessionsController {
  /**
   * Search and list member authentication sessions with pagination, filtering, and sorting capabilities.
   *
   * This endpoint allows members to view all their active sessions, including device information, IP addresses, and token expiration times. Sessions represent authenticated devices where the member has logged in.
   *
   * The response includes session status indicators to help members identify active versus expired sessions. Filtering options allow members to narrow results by organization context, date ranges, or specific sessions.
   *
   * @param connection
   * @param body Search criteria for filtering member sessions. Includes organization context, date ranges, status filters, pagination parameters, and sort options.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Query hrm_platform_member_sessions table with
     *   pagination and filtering.
   *
   * Apply search filters on:
   * - member_id: Filter by member account ID
   * - organization_id: Filter by organization context
   * - date range: Filter by created_at or access_token_expires_at
   * - status: Filter by session active/expired status
   * - ip_address: Search by IP address pattern
   * - user_agent: Search by device/browser pattern
   *
   * Sort results by created_at (descending) as default, with options to sort by:
   * - created_at
   * - access_token_expires_at
   * - refresh_token_expires_at
   *
   * Return cursor-based pagination using created_at timestamps for efficient large result set handling.
   *
   * Calculate session status based on expired_at (null = active, not null = expired).
   *
   * Order results by organization context (current organization first if session has organization_id).
   *
   * Return session summaries excluding sensitive token values (access_token, refresh_token are never exposed in list responses).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IHrmPlatformMemberSession.IRequest,
  ): Promise<IPageIHrmPlatformMemberSession.ISummary> {
    try {
      return await patchHrmPlatformGuestSessions({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information about a specific authentication session.
   *
   * Returns complete session data including JWT token metadata, device fingerprinting information (IP address and user agent), organization context, and session timestamps. This information is used by users to monitor their active sessions across devices and by administrators for security auditing.
   *
   * @param connection
   * @param sessionId Unique identifier of the session to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Query the hrm_platform_member_sessions table by
     *   the session UUID.
   *
   * 1. Find session by id = {sessionId}
   * 2. Return full session record if found
   * 3. Return 404 Not Found if session does not exist
   * 4. Authorization required: session owner or admin role
   * 5. Do NOT expose access_token or refresh_token values in response
   * 6. Include all fields: id, member_id, organization_id, ip_address, user_agent, referrer, created_at, updated_at, access_token_expires_at, refresh_token_expires_at, expired_at
   *
   * Implementation notes:
   * - Use parameter binding for UUID validation
   * - Check session expiration status in response
   * - Organization context is optional (may be null)
   * - Token values are hashed/stored but never returned to client
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformMemberSession> {
    try {
      return await getHrmPlatformGuestSessionsSessionId({
        guest,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
