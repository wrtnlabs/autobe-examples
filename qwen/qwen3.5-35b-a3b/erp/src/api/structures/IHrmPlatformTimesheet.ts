/**
 * Complete timesheet entity representing a weekly collection of timelogs submitted by an employee for approval workflow.
 *
 * ## Timesheet Structure
 *
 * A timesheet tracks work hours for a specific week period (Monday to Sunday). Each timesheet contains multiple timelogs representing individual work sessions on projects and tasks. The timesheet workflow includes statuses: pending (draft), submitted (awaiting approval), approved (manager approved), rejected (returned for corrections), and cancelled.
 *
 * ## Fields
 *
 * ### Core Information
 *
 * - `id`: Unique identifier
 * - `employee`: Owner of the timesheet
 * - `start_date` / `end_date`: Week period covered
 * - `status`: Current workflow state
 * - `notes`: Optional comments or explanations
 *
 * ### Workflow Timestamps
 *
 * - `submitted_at`: When submitted for approval
 * - `approved_at`: When approved by manager
 * - `rejected_at`: When rejected with feedback
 * - `cancelled_at`: When cancelled
 *
 * ### Aggregations
 *
 * - `total_hours`: Sum of all timelog durations in hours
 *
 * ### System Fields
 *
 * - `created_at` / `updated_at`: Record lifecycle timestamps
 * - `deleted_at`: Soft delete marker
 *
 * ### Related Data
 *
 * - `timelogs`: Array of all timelogs included in this timesheet with project, task, and duration details
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
