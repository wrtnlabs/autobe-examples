/**
 * Create a new member account for users who want to join the HRM & Time Tracking Platform.
 *
 * This operation creates a new member account in the hrms_members table. The member table stores user account information including email, hashed password, display name, avatar URL, phone number, and account status. When a user registers, their password is securely hashed using bcrypt before storage to protect sensitive credentials.
 *
 * After successfully creating the member account, the system automatically authenticates the user by generating JWT tokens and storing them in the hrms_member_sessions table. This table manages session data including the access token (short-lived, 15 minutes) and refresh token (longer-lived, 7 days). The user is immediately logged in after registration, eliminating the need for a separate login step.
 *
 * The email field must be unique across all members and follow standard email format validation. The password must meet security requirements (minimum length, complexity). The display name is optional but recommended for profile completeness. The account status is set to 'active' by default upon successful registration.
 *
 * This operation is the entry point for new users to join the system and gain access to organization-specific features.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Member registration data including email, password, and optional display name
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Create a new member account in the hrms_members table with email and password. Hash the password using bcrypt before storing. Create the member record with status 'active' by default. After successful account creation, automatically authenticate the member by creating a new session in hrms_member_sessions table with access and refresh tokens. Set token expiration: access token 15 minutes, refresh token 7 days. Return the member's authorized state including both tokens. Email validation should be performed before account creation to ensure the email is not already registered and follows valid email format.
 * @path /hrms/auth/member/join
 * @accessor api.functional.hrms.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
