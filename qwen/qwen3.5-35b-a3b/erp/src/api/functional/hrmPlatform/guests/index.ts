/**
 * Retrieve paginated list of guest records with search and filtering capabilities.
 *
 * This endpoint provides administrative access to view unauthenticated visitor data identified by device fingerprint. Guests are users who have not yet registered but are accessing the sign-up page.
 *
 * The operation supports filtering by IP address, device identifier patterns, date ranges for creation/update timestamps, and soft-delete status. Results are paginated with cursor-based pagination for efficient retrieval of large result sets.
 *
 * @param props.connection
 * @param props.body Search criteria for guest records
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query hrm_platform_guests table with cursor-based pagination.
 *
 * Apply search filters from requestBody:
 * - device_identifier: exact match or pattern search using ilike
 * - ip_address: exact match or range search
 * - user_agent: pattern search using ilike on gin-indexed column
 * - created_at: date range filter (gte, lte)
 * - updated_at: date range filter (gte, lte)
 * - deleted_at: filter by null (active) or non-null (deleted)
 * - sortBy: sort by created_at, updated_at, ip_address, or device_identifier
 * - sortOrder: ASC or DESC
 * - cursor: for cursor-based pagination
 * - limit: maximum number of records to return
 *
 * Join logic: none required (single table query)
 *
 * Return paginated results with:
 * - data: array of guest summaries
 * - hasNextCursor: boolean indicating if more records exist
 * - nextCursor: base64-encoded cursor string for next page
 *
 * Handle soft-deleted records based on filter:
 * - If deleted_at filter is null or explicitly requested, include deleted records
 * - Otherwise, exclude records where deleted_at is not null
 *
 * Error handling:
 * - Return 400 if invalid cursor format
 * - Return 400 if invalid date range (start > end)
 * - Return 400 if invalid sortBy field
 * - Return 400 if limit exceeds maximum allowed (100)
 *
 * Security: Only authorized administrators can access this endpoint based on role permissions.
 * @path /hrmPlatform/guests
 * @accessor api.functional.hrmPlatform.guests.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria for guest records
     */
    body: IHrmPlatformGuest.IRequest;
  };
  export type Body = IHrmPlatformGuest.IRequest;
  export type Response = IPageIHrmPlatformGuest.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/hrmPlatform/guests",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/hrmPlatform/guests";
  export const random = (): IPageIHrmPlatformGuest.ISummary =>
    typia.random<IPageIHrmPlatformGuest.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

