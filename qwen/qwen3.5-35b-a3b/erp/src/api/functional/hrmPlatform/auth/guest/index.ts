/**
 * Create a temporary guest session to allow unauthenticated visitors to access the platform. This operation does not require credentials - guests are identified by device fingerprint (device_identifier) and IP address.
 *
 * When a guest first visits the platform, call this endpoint with device_identifier, ip_address, and user_agent. The system checks if a guest with these identifiers already exists and has an active session. If found, the existing session is returned. If not found, a new guest account and session are created.
 *
 * The response includes access_token for immediate API access and refresh_token for token renewal. Guests do not have an organization context (organization_id is null) until they complete registration and become members.
 *
 * Security considerations: device_identifier should be generated using device fingerprinting on the client side. Sessions expire based on refresh_token_expires_at. Expired sessions must be cleaned up from hrm_platform_guest_sessions.
 *
 * Related operations: refresh - renew guest session tokens
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest session creation request with device identification and browser information
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Create a temporary guest session for unauthenticated visitors. Check if guest exists by device_identifier and ip_address. If not found, create new guest record with device_identifier, ip_address, and user_agent. Create hrm_platform_guest_sessions record with new session_token (JWT), ip address, user_agent, referrer. Generate access_token and refresh_token with different expiration times. Set organization_id to null for guests. Return IAuthorized response with tokens and session info. Edge cases: duplicate device_identifier should return existing session if within expiration window. Errors: 409 if device already has active session, 400 if device_identifier or ip_address missing.
 * @path /hrmPlatform/auth/guest/join
 * @accessor api.functional.hrmPlatform.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
