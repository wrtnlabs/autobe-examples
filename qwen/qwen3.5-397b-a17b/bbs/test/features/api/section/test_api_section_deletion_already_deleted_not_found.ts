export async function test_api_section_deletion_already_deleted_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - register new admin account
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // 2. Create a section that will be deleted
  const section = await generate_random_discussion_board_admin_sections_create(
    adminConnection,
    {},
  );
  typia.assert(section);
  // 3. Delete the section successfully (first deletion)
  await api.functional.discussionBoard.admin.sections.erase(adminConnection, {
    sectionId: section.id,
  });
  // 4 & 5. Attempt to delete the same section again - should fail with 404
  await TestValidator.error(
    "already deleted section should return 404",
    async () => {
      await api.functional.discussionBoard.admin.sections.erase(
        adminConnection,
        {
          sectionId: section.id,
        },
      );
    },
  );
}
