/**
 * Test that the comment system enforces single-level comment structure without nested replies.
 *
 * This test validates the flat discussion thread model by:
 * 1. Creating an admin account and section
 * 2. Creating a member account and article
 * 3. Creating multiple comments on the article
 * 4. Validating that comments have no parent reference (single-level structure)
 * 5. Validating that comments are associated directly with the article
 * 6. Validating chronological ordering (oldest first)
 */
export async function test_api_comment_single_level_structure(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create section
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  const section = await generate_random_discussion_board_admin_sections_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 1 }),
        description: RandomGenerator.paragraph({ sentences: 2 }),
      } satisfies IDiscussionBoardSection.ICreate,
    },
  );
  typia.assert(section);
  // 2. Member setup - create article
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  const article = await generate_random_discussion_board_member_articles_create(
    memberConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 1 }),
        content: RandomGenerator.content({ paragraphs: 2 }),
        sectionId: section.id,
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // 3. Create multiple comments to test single-level structure
  const comment1 =
    await generate_random_discussion_board_member_articles_comments_create(
      memberConnection,
      {
        params: { articleId: article.id },
        body: {
          content: RandomGenerator.paragraph({ sentences: 2 }),
        } satisfies IDiscussionBoardComment.ICreate,
      },
    );
  typia.assert(comment1);
  // Wait a small amount to ensure different timestamps
  await new Promise((resolve) => setTimeout(resolve, 100));
  const comment2 =
    await generate_random_discussion_board_member_articles_comments_create(
      memberConnection,
      {
        params: { articleId: article.id },
        body: {
          content: RandomGenerator.paragraph({ sentences: 2 }),
        } satisfies IDiscussionBoardComment.ICreate,
      },
    );
  typia.assert(comment2);
  // 4. Validate single-level structure
  // Comment should have article reference, not parent comment reference
  TestValidator.equals(
    "comment1 article matches",
    comment1.article.id,
    article.id,
  );
  TestValidator.equals(
    "comment2 article matches",
    comment2.article.id,
    article.id,
  );
  // Validate comment structure has author information
  TestValidator.predicate("comment1 has author", comment1.author !== undefined);
  TestValidator.predicate("comment2 has author", comment2.author !== undefined);
  // Validate timestamps exist for chronological ordering
  TestValidator.predicate(
    "comment1 has created_at",
    comment1.created_at !== undefined,
  );
  TestValidator.predicate(
    "comment2 has created_at",
    comment2.created_at !== undefined,
  );
  // Validate chronological order (comment1 should be older than comment2)
  const comment1Time = new Date(comment1.created_at).getTime();
  const comment2Time = new Date(comment2.created_at).getTime();
  TestValidator.predicate(
    "comments in chronological order",
    comment1Time <= comment2Time,
  );
  // Validate comment IDs are different
  TestValidator.notEquals("comment IDs differ", comment1.id, comment2.id);
  // Validate deleted_at is null for active comments
  TestValidator.equals("comment1 not deleted", comment1.deleted_at, null);
  TestValidator.equals("comment2 not deleted", comment2.deleted_at, null);
}
