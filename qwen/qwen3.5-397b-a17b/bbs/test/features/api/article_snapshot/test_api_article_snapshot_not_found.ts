export async function test_api_article_snapshot_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - register administrator account
  const adminConnection: api.IConnection = { host: connection.host };
  const adminJoin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(adminJoin);
  // 2. Create section as prerequisite for article creation
  const section = await generate_random_discussion_board_admin_sections_create(
    adminConnection,
    {},
  );
  typia.assert(section);
  // 3. Member setup - register and login to create article
  const memberConnection: api.IConnection = { host: connection.host };
  const memberJoin = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(memberJoin);
  // 4. Create article (this establishes valid article context for snapshot lookup)
  const article = await generate_random_discussion_board_member_articles_create(
    memberConnection,
    {
      body: {
        sectionId: section.id,
      },
    },
  );
  typia.assert(article);
  // 5. Attempt to retrieve non-existent snapshot
  // Generate a valid UUID format that doesn't exist in the system
  const nonExistentSnapshotId = typia.random<string & tags.Format<"uuid">>();
  // Validate that the system returns 404 Not Found for non-existent snapshot
  await TestValidator.httpError(
    "snapshot not found returns 404",
    404,
    async () => {
      await api.functional.discussionBoard.admin.articles.snapshots.at(
        adminConnection,
        {
          articleId: article.id,
          snapshotId: nonExistentSnapshotId,
        },
      );
    },
  );
}
