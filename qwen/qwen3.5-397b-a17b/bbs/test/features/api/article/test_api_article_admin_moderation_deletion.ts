/**
 * Test administrator content moderation capability by deleting an article authored by a different member.
 *
 * This test validates that administrators can delete any article regardless of ownership,
 * demonstrating the moderation authority for community standards enforcement.
 *
 * Test Flow:
 * 1. Administrator registers and authenticates
 * 2. Administrator creates a section for article categorization
 * 3. Regular member registers and authenticates (different user)
 * 4. Member creates an article in the section
 * 5. Administrator deletes the member's article
 * 6. Verify deletion was successful (article inaccessible)
 */
export async function test_api_article_admin_moderation_deletion(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator setup - create admin account and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(adminAuth);
  // 2. Create section for article categorization
  const section = await generate_random_discussion_board_admin_sections_create(
    adminConnection,
    {},
  );
  typia.assert(section);
  // 3. Regular member setup - create member account and authenticate
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(memberAuth);
  // 4. Member creates an article in the section
  const article = await generate_random_discussion_board_member_articles_create(
    memberConnection,
    {
      body: {
        sectionId: section.id,
      },
    },
  );
  typia.assert(article);
  // Verify article was created successfully with correct author and section
  TestValidator.equals(
    "article author is member",
    article.author.id,
    memberAuth.id,
  );
  TestValidator.equals(
    "article section matches",
    article.section.id,
    section.id,
  );
  // 5. Administrator deletes the member's article
  // This validates admin moderation authority - can delete articles they don't own
  await api.functional.discussionBoard.admin.articles.erase(adminConnection, {
    articleId: article.id,
  });
  // 6. Verify deletion
  // The successful erase operation (204 No Content) confirms the article was deleted.
  // Note: Direct 404 verification would require a GET endpoint which is not available in current API set.
  // The absence of errors from the erase call validates the admin's moderation capability.
}
