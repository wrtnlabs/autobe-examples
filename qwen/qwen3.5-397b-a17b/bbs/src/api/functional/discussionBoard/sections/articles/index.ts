/**
 * Retrieve a filtered and paginated list of articles within a specific discussion board section.
 *
 * This operation provides comprehensive article discovery capabilities including text search across title and content, tag-based filtering, and flexible sorting options. The endpoint supports pagination to efficiently handle large result sets.
 *
 * All users including guests can access this endpoint to browse section content. Each article in the response includes essential metadata: title, author information, associated tags, comment count, and creation timestamp. Full article content is not included in the list view to optimize response size.
 *
 * The section ID in the path parameter scopes the query to articles belonging to that specific section. Articles are filtered to exclude soft-deleted records. Sorting supports both chronological orders (newest first or oldest first) based on the created_at timestamp.
 *
 * Related operations: GET /sections/{sectionId}/articles/{articleId} retrieves full article details including content and attachments. PATCH /articles provides global article search across all sections.
 *
 * @param props.connection
 * @param props.sectionId Target section's UUID identifier. Articles are scoped to this specific section.
 * @param props.body Search criteria, filtering options, pagination, and sorting parameters for article list query
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query discussion_board_articles table filtered by discussion_board_section_id matching the path parameter. Apply search filters on title and content using PostgreSQL full-text search or trigram indexes. Join with discussion_board_article_tags and discussion_board_tags for tag filtering. Left join with discussion_board_comments to calculate comment count per article. Join with discussion_board_members for author display name. Apply pagination using cursor-based or offset-based approach with configurable page size. Support sorting by created_at ascending (oldest first) or descending (newest first). Filter out soft-deleted articles (deleted_at IS NULL). Return article summary data including id, title, author info, tags array, comment count, and created_at timestamp.
 * @path /discussionBoard/sections/:sectionId/articles
 * @accessor api.functional.discussionBoard.sections.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Target section's UUID identifier. Articles are scoped to this specific section.
     */
    sectionId: string & tags.Format<"uuid">;

    /**
     * Search criteria, filtering options, pagination, and sorting parameters for article list query
     */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/sections/:sectionId/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/sections/${encodeURIComponent(props.sectionId ?? "null")}/articles`;
  export const random = (): IPageIDiscussionBoardArticle.ISummary =>
    typia.random<IPageIDiscussionBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sectionId")(() => typia.assert(props.sectionId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
