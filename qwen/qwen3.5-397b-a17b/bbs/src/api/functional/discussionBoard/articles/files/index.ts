/**
 * Update and manage file attachments for an article. This operation allows article authors to modify metadata of existing file attachments, reorder files, or remove attachments from their article.
 *
 * The endpoint supports updating file display names, changing file order for presentation, and removing unwanted attachments. All file management operations preserve the underlying file storage while updating the attachment metadata in the discussion_board_article_files table.
 *
 * Only the article author can manage file attachments. The operation validates ownership by checking that the requesting user's ID matches the discussion_board_member_id of the parent article. Attempting to manage files on an article you don't own will result in authorization failure.
 *
 * File removal uses soft deletion by setting the deleted_at timestamp, maintaining audit trail compliance. The operation returns an array of all active file attachments with their current metadata after the updates are applied.
 *
 * @param props.connection
 * @param props.articleId Target article's UUID identifier. Must be a valid article that exists and is owned by the requesting user.
 * @param props.body File attachment management operations including metadata updates and removal instructions for multiple files
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query discussion_board_article_files table filtered by discussion_board_article_id. Validate that the requesting user is the article author (discussion_board_member_id matches). For each file update operation: verify file exists and belongs to the article, update metadata fields (original_name, display order if applicable), or mark deleted_at for soft deletion. Apply all updates in a single transaction for consistency. Return updated file list with all active attachments. Handle concurrent modification conflicts with optimistic locking on updated_at timestamp.
 * @path /discussionBoard/articles/:articleId/files
 * @accessor api.functional.discussionBoard.articles.files.updateFiles
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function updateFiles(
  connection: IConnection,
  props: updateFiles.Props,
): Promise<updateFiles.Response> {
  return true === connection.simulate
    ? updateFiles.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...updateFiles.METADATA,
          path: updateFiles.path(props),
          status: null,
        },
        props.body,
      );
}
