/**
 * Retrieve a specific member's public profile information by their unique identifier.
 *
 * This operation returns comprehensive profile data including the member's display name shown publicly on articles and comments, biography text for personal description, and account status indicating active, suspended, or deleted state. The profile also includes temporal metadata such as account creation timestamp and last update timestamp.
 *
 * The endpoint supports public profile viewing accessible to all actors including guests, members, and administrators. Guests can browse profiles without authentication as part of public content discovery. Members can view other members' profiles to see their discussion contributions. Administrators can view profiles for moderation and user management purposes.
 *
 * Sensitive authentication fields such as email address and password hash are intentionally excluded from the response to protect user privacy and security. The profile response focuses on publicly shareable information that facilitates community interaction and user discovery within the discussion board platform.
 *
 * Related operations include PATCH /members for retrieving the authenticated user's own profile with additional details, PATCH /members/{memberId}/articles for listing articles written by the member, and PATCH /members/{memberId}/comments for listing comments posted by the member.
 *
 * @param props.connection
 * @param props.memberId Target member's UUID identifier
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query discussion_board_members table by primary key UUID.
 *
 * Validate memberId is valid UUID format. Return 404 if member not found or if deleted_at is not null (soft deleted account).
 *
 * Select fields: id, display_name, bio, status, created_at, updated_at. Exclude sensitive fields: email, password_hash.
 *
 * Join with discussion_board_articles to count total articles authored. Join with discussion_board_comments to count total comments posted. Include these counts in response for profile summary.
 *
 * Check member status: if status is 'suspended' or 'deleted', still return profile but may include status indicator for API consumers.
 *
 * Apply data isolation rules: profile data is public, no ownership check required for viewing.
 *
 * Cache profile data with appropriate TTL to reduce database load for frequently viewed profiles.
 * @path /discussionBoard/members/:memberId
 * @accessor api.functional.discussionBoard.members.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Target member's UUID identifier
     */
    memberId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardMember;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/members/:memberId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/members/${encodeURIComponent(props.memberId ?? "null")}`;
  export const random = (): IDiscussionBoardMember =>
    typia.random<IDiscussionBoardMember>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberId")(() => typia.assert(props.memberId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
