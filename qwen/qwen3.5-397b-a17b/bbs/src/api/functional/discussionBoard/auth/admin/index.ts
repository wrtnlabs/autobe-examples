/**
 * Creates a new administrator account with email and password authentication.
 *
 * This endpoint handles administrator registration by creating a new member account with administrator privileges. The operation validates that the email address is unique across all member accounts, applies password security requirements including minimum length and complexity rules, and securely hashes the password before storage. The administrator is created with 'regular' grade level by default, granting capabilities for section management, content deletion, and user banning.
 *
 * The registration process establishes a 1:1 relationship between the discussion_board_members table and discussion_board_admins table through the member_id foreign key. A session record is created in discussion_board_admin_sessions to track the authentication event with connection metadata including IP address, referrer URL, and href for audit trail purposes.
 *
 * Upon successful registration, the operation generates JWT access and refresh tokens. The access token provides short-term authentication for API requests, while the refresh token enables token renewal without re-authentication. Session expiration is enforced based on the expired_at timestamp in the admin_sessions table.
 *
 * This operation is typically used during initial system setup to create the first super administrator, or in environments where administrators are provisioned directly rather than through the admin request workflow. For member-to-admin promotion, use the admin request approval flow instead.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Administrator registration credentials and profile information
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Creates a new administrator account through the registration flow. This operation validates the provided email address for uniqueness, securely hashes the password, and creates both the member account and associated administrator profile in a single transaction. The operation initializes the administrator with 'regular' grade by default. Upon successful registration, generates JWT access and refresh tokens, creates an admin session record with connection metadata (IP address, referrer, href), and returns the authorized response containing tokens and administrator profile information. The session is tracked in discussion_board_admin_sessions for audit compliance.
 * @path /discussionBoard/auth/admin/join
 * @accessor api.functional.discussionBoard.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
