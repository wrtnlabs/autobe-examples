/**
 * Register a new guest user for anonymous browsing access to the discussion board platform.
 *
 * This endpoint creates a guest account identified by a unique device fingerprint, enabling temporary session management without requiring traditional email/password authentication. The device fingerprint is generated from browser/device characteristics to distinguish anonymous visitors. If no fingerprint is provided, the system generates one automatically.
 *
 * The operation creates a new record in the discussion_board_guests table with the device_fingerprint field set to the provided or generated value. It also creates an initial session record in discussion_board_guest_sessions with connection metadata including the client IP address, initial page URL (href), and HTTP referrer header for traffic source tracking.
 *
 * Upon successful registration, the endpoint returns JWT access and refresh tokens in the IDiscussionBoardGuest.IAuthorized response structure. The access token grants temporary browsing permissions, while the refresh token enables session renewal before expiration. Session expiration is configured according to platform policy and stored in the expired_at column of the guest session record.
 *
 * Guests have read-only access to sections, articles, and comments but cannot create content, manage profiles, or access member-only features. This operation is the entry point for anonymous users to access the discussion board platform.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Device fingerprint and connection metadata for guest registration
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Create a new guest account using device fingerprint for anonymous browsing access. Generate a unique device fingerprint if not provided, or use the supplied fingerprint to identify returning guests. Create a new guest session with connection metadata (IP address, page URL, referrer) and set expiration timestamp based on session duration policy. Return JWT access and refresh tokens for authenticated guest browsing. If a guest with the same device fingerprint already exists and is not deleted, reuse the existing guest record. Handle concurrent session creation with proper locking to prevent duplicate guest accounts.
 * @path /discussionBoard/auth/guest/join
 * @accessor api.functional.discussionBoard.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
