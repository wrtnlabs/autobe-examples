/**
 * Register a new member account with email and password authentication.
 *
 * This endpoint creates a new member record in the discussion_board_members table with the provided email address, hashed password, display name, and optional biography text. The email address must be unique across all member accounts and will be used for all future authentication attempts.
 *
 * The password is hashed using bcrypt before being stored in the password_hash column, ensuring that plain text passwords are never persisted. The account status is initialized to 'active', allowing immediate login access.
 *
 * Upon successful registration, an email verification record is created in the discussion_board_member_email_verifications table with a unique token and expiration timestamp. This enables the email verification workflow to confirm the member's email address.
 *
 * The response includes JWT access and refresh tokens for immediate authenticated session establishment, along with the member's profile information including their id, email, display name, and bio.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Member registration information including email, password, and profile details
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Handle member registration by creating a new account in discussion_board_members table. Validate email uniqueness against existing members. Hash the password using bcrypt before storing in password_hash field. Initialize account status as 'active'. Create an email verification record in discussion_board_member_email_verifications table with a unique token and expiration timestamp. Return JWT access and refresh tokens along with member information. Handle duplicate email errors with appropriate validation response.
 * @path /discussionBoard/auth/member/join
 * @accessor api.functional.discussionBoard.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
