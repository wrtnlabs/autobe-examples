/**
 * Permanently delete a specific comment from an article.
 *
 * This operation removes a comment from the discussion board, marking it as deleted via the deleted_at timestamp. The comment content and metadata are preserved for audit purposes but are no longer visible in the article's comment list.
 *
 * Only the comment's author (member) or an administrator can delete the comment. Regular members can only delete their own comments, while administrators have the authority to delete any comment for moderation purposes. The articleId in the path ensures the comment belongs to the specified article before deletion.
 *
 * When a comment is deleted, the article remains intact and other comments on the article are preserved. The comment count on the article is updated accordingly. This operation is irreversible - deleted comments cannot be recovered.
 *
 * If the comment does not exist, has already been deleted, or the user lacks permission (not the author and not an administrator), the request is rejected with an appropriate error response.
 *
 * @param props.connection
 * @param props.articleId Target article's ID. Used to verify the comment belongs to this article before deletion.
 * @param props.commentId Target comment's ID to be deleted.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Delete a specific comment from an article by setting the deleted_at timestamp.
 *
 * Implementation steps:
 * 1. Validate both articleId and commentId are valid UUIDs
 * 2. Verify the comment exists and belongs to the specified article (join discussion_board_comments with discussion_board_articles on discussion_board_article_id)
 * 3. Check authorization: current user must be either the comment author (discussion_board_member_id matches authenticated user) or an administrator
 * 4. Verify the comment is not already deleted (deleted_at is null)
 * 5. Set deleted_at to current timestamp in a database transaction
 * 6. Update the parent article's comment count if cached
 * 7. Return success response
 *
 * Edge cases:
 * - Comment not found: return 404
 * - Comment already deleted: return 404 or 410
 * - Unauthorized (not author, not admin): return 403
 * - Article not found: return 404
 * - Concurrent deletion: use optimistic locking with updated_at timestamp
 * @path /discussionBoard/admin/articles/:articleId/comments/:commentId
 * @accessor api.functional.discussionBoard.admin.articles.comments.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
