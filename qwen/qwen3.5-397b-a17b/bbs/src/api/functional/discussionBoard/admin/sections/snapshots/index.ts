/**
 * Retrieve a paginated list of historical snapshots for a specific discussion board section.
 *
 * This operation provides access to the audit trail of section modifications, allowing administrators to track how a section's name and description have changed over time. Each snapshot represents an immutable, point-in-time capture of the section's state, created automatically when section modifications occur.
 *
 * The snapshots are stored in the discussion_board_section_snapshots table, which maintains an append-only history linked to the parent section through the discussion_board_section_id foreign key. Each snapshot preserves the name and description values as they existed at the time of capture, along with the created_at timestamp indicating when the snapshot was recorded.
 *
 * This endpoint supports filtering by date range to help administrators review changes within specific time periods. Results are paginated to handle potentially large historical records efficiently. The snapshots are indexed by discussion_board_section_id and created_at for optimal query performance.
 *
 * Access to section snapshots is restricted to administrators only, as this audit trail data is used for compliance, moderation review, and change tracking purposes. Regular members and guests cannot access historical section data.
 *
 * The sectionId path parameter must correspond to an existing section in the discussion_board_sections table. If the section has been soft deleted (deleted_at is not null), snapshots may still be accessible for audit purposes depending on business rules.
 *
 * @param props.connection
 * @param props.sectionId Target section's UUID identifier (global scope)
 * @param props.body Filtering criteria and pagination parameters for snapshot search
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query discussion_board_section_snapshots table filtered by discussion_board_section_id matching the sectionId path parameter.
 *
 * Apply pagination using cursor-based or offset-based pagination with configurable page size. Support optional date range filtering on created_at field if provided in request body.
 *
 * Sort results by created_at in descending order (newest first) by default, with option to sort ascending (oldest first) for chronological review.
 *
 * Join with discussion_board_sections table to verify section exists and check deletion status. Return snapshots even if parent section is soft deleted for audit trail completeness.
 *
 * Validate that requesting user has administrator privileges before returning snapshot data. Reject requests from non-administrator users with 403 Forbidden.
 *
 * Handle edge case where section has no snapshots yet (newly created section with no modifications) by returning empty data array with pagination metadata.
 * @path /discussionBoard/admin/sections/:sectionId/snapshots
 * @accessor api.functional.discussionBoard.admin.sections.snapshots.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
