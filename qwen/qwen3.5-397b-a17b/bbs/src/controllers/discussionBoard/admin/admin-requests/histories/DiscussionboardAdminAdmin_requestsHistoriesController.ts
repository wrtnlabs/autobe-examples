import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardAdminRequestHistory } from "../../../../../api/structures/IDiscussionBoardAdminRequestHistory";
import { IPageIDiscussionBoardAdminRequestHistory } from "../../../../../api/structures/IPageIDiscussionBoardAdminRequestHistory";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminAdminRequestsRequestIdHistoriesHistoryId } from "../../../../../providers/getDiscussionBoardAdminAdminRequestsRequestIdHistoriesHistoryId";
import { patchDiscussionBoardAdminAdminRequestsRequestIdHistories } from "../../../../../providers/patchDiscussionBoardAdminAdminRequestsRequestIdHistories";

@Controller("/discussionBoard/admin/admin-requests/:requestId/histories")
export class DiscussionboardAdminAdmin_requestsHistoriesController {
  /**
   * Retrieve the complete audit history of status transitions for an administrator application request.
   *
   * This operation provides full transparency into the admin request review process by returning all recorded status changes from submission through final decision. Each history entry captures the status at that point in time, which super administrator made the decision, the timestamp of the transition, and optionally the rejection reason if the request was denied.
   *
   * The audit trail includes the initial pending status when the member submitted the request, followed by the final decision (approved or rejected) made by a super administrator. This endpoint supports the platform's commitment to administrative transparency and accountability in privilege escalation workflows.
   *
   * Access is restricted to super administrators only, as the history contains sensitive information about administrative decisions and personnel. Regular administrators and members cannot view this audit trail. The requesting administrator must have super administrator grade privileges as defined in the discussion_board_admins.grade field.
   *
   * The histories are returned in chronological order by default (oldest first), showing the complete lifecycle from submission through decision. Pagination is supported for systems with extensive audit trails, though typically an admin request will have only 2-3 history entries (pending → approved/rejected).
   *
   * Related operations: GET /admin-requests/{requestId} retrieves the current state of the admin request. PATCH /admin-requests provides list of all requests with filtering by status.
   *
   * @param connection
   * @param requestId Target admin request's ID (UUID format)
   * @param body Pagination and sorting parameters for history retrieval
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_admin_request_histories table filtered by discussion_board_admin_request_id matching the requestId path parameter.
   *
   * Join with discussion_board_admins table on deciding_admin_id to include administrator information (display name, grade) in the response.
   *
   * Apply pagination parameters (page, limit) from request body. Default sorting by created_at ascending (oldest first) to show chronological progression.
   *
   * Validate that the requesting user has super administrator privileges by checking discussion_board_admins.grade = 'super' for the authenticated admin.
   *
   * Verify the admin request exists by checking discussion_board_admin_requests.id = requestId. Return 404 if not found.
   *
   * Transform each history record to IDiscussionBoardAdminRequestHistory.ISummary format, including: id, status, decidingAdmin (displayName, grade), reason (nullable), createdAt.
   *
   * Handle edge case where request has no histories yet (newly submitted, still pending) - return empty array with pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardAdminRequestHistory.IRequest,
  ): Promise<IPageIDiscussionBoardAdminRequestHistory.ISummary> {
    try {
      return await patchDiscussionBoardAdminAdminRequestsRequestIdHistories({
        admin,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific administrator request status transition from the audit trail.
   *
   * This operation returns a single history entry that captures when an administrator application request's status changed, which super administrator made the decision, and the reason for rejection if applicable. Each history entry provides complete transparency into the privilege escalation workflow and supports administrative audit compliance requirements.
   *
   * The history entry includes the status at the transition point (pending, approved, or rejected), the deciding super administrator's ID, optional rejection reason text, and the exact timestamp when the transition occurred. This information is essential for understanding the complete lifecycle of an administrator application request.
   *
   * Access to this audit trail is restricted to administrators with appropriate permissions. The operation validates that the specified historyId exists and belongs to the admin request identified by requestId, ensuring data integrity and preventing unauthorized access to audit records.
   *
   * Related operations: GET /discussionBoard/admin/admin-requests/{requestId} should be used to retrieve the parent request details, while this operation focuses specifically on individual status transition records within the audit trail.
   *
   * @param connection
   * @param requestId Target administrator request's ID (global scope, UUID format)
   * @param historyId Target history entry's ID (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the discussion_board_admin_request_histories table by historyId. Verify that the history entry belongs to the specified admin request by checking discussion_board_admin_request_id matches requestId. Join with discussion_board_admins table to include deciding administrator information if needed. Return the complete history record including id, discussion_board_admin_request_id, deciding_admin_id, status, reason (nullable), and created_at timestamp. Ensure the requesting user has appropriate permissions (super administrator or the member who submitted the request) to view this audit trail entry.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":historyId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedParam("historyId")
    historyId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAdminRequestHistory> {
    try {
      return await getDiscussionBoardAdminAdminRequestsRequestIdHistoriesHistoryId(
        {
          admin,
          requestId,
          historyId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
