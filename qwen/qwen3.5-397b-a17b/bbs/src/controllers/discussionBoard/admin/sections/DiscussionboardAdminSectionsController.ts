import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardSection } from "../../../../api/structures/IDiscussionBoardSection";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteDiscussionBoardAdminSectionsSectionId } from "../../../../providers/deleteDiscussionBoardAdminSectionsSectionId";
import { postDiscussionBoardAdminSections } from "../../../../providers/postDiscussionBoardAdminSections";
import { putDiscussionBoardAdminSectionsSectionId } from "../../../../providers/putDiscussionBoardAdminSectionsSectionId";

@Controller("/discussionBoard/admin/sections")
export class DiscussionboardAdminSectionsController {
  /**
   * Create a new discussion board section for topic categorization.
   *
   * This operation enables administrators to create new sections that organize articles into distinct topic areas such as Politics, Economy, or Current Affairs. Each section serves as a container for related articles, providing community structure and content discovery capabilities.
   *
   * The section creation requires both a name and description. The name must be unique across all sections and identifies the section's focus area. The description explains the section's purpose and scope to help users understand what type of content belongs in the section.
   *
   * Only administrators can create sections. Regular users and guests do not have permission to create sections. When a section is created, it becomes immediately available for article categorization and appears in the sections list.
   *
   * The system automatically generates a UUID for the section id and records the created_at and updated_at timestamps. The section is created in an active state with deleted_at set to null.
   *
   * @param connection
   * @param body Section creation data with name and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new discussion board section with administrator authorization.
   *
   * 1. Verify the requesting user has administrator privileges
   * 2. Validate request body:
   *    - name: required, non-empty string, must be unique (check @@unique constraint)
   *    - description: required, non-empty string
   * 3. Generate UUID for section id
   * 4. Set created_at and updated_at to current timestamp
   * 5. Set deleted_at to null (active section)
   * 6. Insert new record into discussion_board_sections table
   * 7. Return the complete section entity including generated id and timestamps
   *
   * Handle unique constraint violation on name by returning 409 Conflict error. Ensure transaction atomicity for the insert operation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardSection.ICreate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await postDiscussionBoardAdminSections({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing discussion board section's name and description.
   *
   * This operation allows administrators to modify the properties of an existing section in the discussion board. Sections organize articles into topic categories (e.g., Politics, Economy, Current Affairs), and administrators can update both the section name and description to reflect changes in topic scope or naming conventions.
   *
   * Only administrators have permission to update sections. Regular members and guests cannot modify section properties. The section name must remain unique across all sections - attempting to use a name that already exists will result in a conflict error.
   *
   * The updated section is returned in the response with all current properties including the updated timestamp. This operation does not affect articles already assigned to the section - they remain associated with the section after the update.
   *
   * Related operations: GET /sections/{sectionId} retrieves section details before editing, PATCH /sections lists all sections for selection, DELETE /sections/{sectionId} removes a section entirely.
   *
   * @param connection
   * @param sectionId Target section's UUID identifier
   * @param body Updated section properties including name and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update discussion_board_sections record by UUID primary key.
   *
   * Validate that the authenticated user has administrator role. Reject non-administrator requests with 403 Forbidden.
   *
   * Verify the section exists and is not soft-deleted (deleted_at is null). Return 404 if section not found or deleted.
   *
   * Validate request body: name must be provided and meet length requirements (minimum 1 character, maximum 100 characters), description must be provided and meet length requirements (minimum 1 character, maximum 500 characters). Check name uniqueness against existing sections excluding the current section being updated.
   *
   * Update the section record: set name and description from request body, update updated_at timestamp to current time. Use database transaction to ensure atomic update.
   *
   * Return the updated section entity with all fields including id, name, description, created_at, updated_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sectionId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardSection.IUpdate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await putDiscussionBoardAdminSectionsSectionId({
        admin,
        sectionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a discussion board section from the platform.
   *
   * This operation allows administrators to delete sections that are no longer needed. The section is soft deleted by setting the deleted_at timestamp, which removes it from the list of available sections for article posting and browsing.
   *
   * Section deletion is restricted to administrators only. Regular members and guests cannot delete sections. The operation validates that the section exists and is not already deleted before proceeding.
   *
   * CRITICAL: Section deletion will be rejected if the section contains any articles. This protection prevents accidental loss of user content organized within sections. Administrators must ensure all articles are removed or reassigned before deleting a section.
   *
   * The section's name remains reserved even after deletion due to the unique constraint on the name field. All articles that were categorized under the deleted section become inaccessible and should be handled before section deletion.
   *
   * @param connection
   * @param sectionId Target section's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Soft delete the discussion_board_sections record by setting deleted_at to current timestamp.
   *
   * Implementation steps:
   * 1. Verify requesting user has administrator privileges
   * 2. Query discussion_board_sections by sectionId, excluding already deleted records
   * 3. Validate section exists and is not already deleted
   * 4. Check if any articles exist in discussion_board_articles with this section_id and deleted_at IS NULL
   * 5. If articles exist, reject with 409 Conflict error
   * 6. Update section: set deleted_at = NOW()
   * 7. Return success response
   *
   * Transaction scope: Single table update on discussion_board_sections.
   *
   * Error handling:
   * - 404 Not Found: Section does not exist or already deleted
   * - 409 Conflict: Section contains articles
   * - 403 Forbidden: Non-administrator attempting deletion
   *
   * Authorization: Requires admin actor role.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sectionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminSectionsSectionId({
        admin,
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
