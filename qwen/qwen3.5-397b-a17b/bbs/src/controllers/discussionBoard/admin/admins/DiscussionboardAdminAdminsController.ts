  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAdmin.IRequest,
  ): Promise<IPageIDiscussionBoardAdmin.ISummary> {
    try {
      return await patchDiscussionBoardAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific administrator account.
   *
   * This operation returns comprehensive administrator profile data including the administrator's grade level (regular or super), associated member account information, and account lifecycle timestamps. The administrator grade determines privilege scope: regular administrators can manage sections, delete content, and ban users; super administrators have elevated powers including approving admin requests and managing other administrators' grades.
   *
   * The response includes the administrator's ID, grade level, creation timestamp, last update timestamp, and the associated member's profile information (email, display name, bio, account status). This endpoint is useful for viewing administrator details, verifying administrator status, and displaying administrator profiles to authorized users.
   *
   * Administrators are promoted from existing members through an approval process, maintaining a 1:1 relationship with the original member account. The administrator record preserves the member's identity while granting elevated permissions. If the administrator has been soft deleted (deleted_at is not null), the operation will return a 404 error indicating the administrator is no longer active.
   *
   * This operation requires administrator authentication. Only users with administrator role can access this endpoint to view administrator account details. This restriction ensures that sensitive administrator information including grade levels and account lifecycle data is only visible to authorized personnel with platform governance responsibilities.
   *
   * @param connection
   * @param adminId Target administrator's ID (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the discussion_board_admins table by the adminId path parameter.
   *
   * 1. Validate adminId is a valid UUID format
   * 2. Query discussion_board_admins WHERE id = adminId AND deleted_at IS NULL
   * 3. Join with discussion_board_members on member_id to include member profile information
   * 4. Return the administrator record with embedded member data (display_name, bio, email, status)
   * 5. Handle not found: if no administrator exists with the given ID, return 404
   * 6. Handle soft deleted: if deleted_at is not null, return 404 or indicate inactive status
   * 7. Include grade information to indicate privilege level (regular or super)
   * 8. Include timestamps: created_at (when admin request was approved), updated_at (last grade change or update)
   *
   * Authorization: Require authenticated user (member or admin). Guests may have read-only access to basic administrator profile information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
