import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteDiscussionBoardAdminArticlesArticleId } from "../../../../providers/deleteDiscussionBoardAdminArticlesArticleId";

@Controller("/discussionBoard/admin/articles/:articleId")
export class DiscussionboardAdminArticlesController {
  /**
   * Permanently remove an article from the discussion board.
   *
   * This operation deletes an article and triggers cascade deletion of all associated child entities including file attachments, image attachments, tag assignments, and comments. The article soft delete timestamp (deleted_at) is set to mark the record as deleted while maintaining audit trail compliance.
   *
   * Only the article's author (owner) or administrators can delete an article. Regular users attempting to delete articles they don't own will receive an authorization error. Administrators can delete any article for moderation purposes regardless of ownership.
   *
   * When an article is deleted, all related discussion_board_article_files, discussion_board_article_images, discussion_board_article_tags, and discussion_board_comments records are cascade deleted. The article's deleted_at timestamp is populated to enable audit tracking and cascade deletion compliance.
   *
   * This operation is irreversible. Once deleted, the article and all its associated content cannot be recovered through the API.
   *
   * @param connection
   * @param articleId Target article's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Delete article by setting deleted_at timestamp (soft delete).
   *
   * 1. Verify article exists and is not already deleted
   * 2. Check authorization: allow if current user is article owner (discussion_board_member_id matches) OR has administrator role
   * 3. Begin database transaction
   * 4. Set deleted_at = current timestamp on discussion_board_articles record
   * 5. Cascade delete triggers automatically remove:
   *    - discussion_board_article_files (onDelete: Cascade)
   *    - discussion_board_article_images (onDelete: Cascade)
   *    - discussion_board_article_tags (onDelete: Cascade)
   *    - discussion_board_comments (onDelete: Cascade)
   * 6. Commit transaction
   * 7. Return 204 No Content on success
   *
   * Error handling:
   * - 404 if article not found or already deleted
   * - 403 if user is not owner and not administrator
   * - 409 if concurrent modification detected
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminArticlesArticleId({
        admin,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
