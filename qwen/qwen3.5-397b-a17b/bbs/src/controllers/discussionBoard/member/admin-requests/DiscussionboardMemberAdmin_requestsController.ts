import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardAdminRequest } from "../../../../api/structures/IDiscussionBoardAdminRequest";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { postDiscussionBoardMemberAdminRequests } from "../../../../providers/postDiscussionBoardMemberAdminRequests";

@Controller("/discussionBoard/member/admin-requests")
export class DiscussionboardMemberAdmin_requestsController {
  /**
   * Submit an administrator application request for privilege escalation from member to administrator role.
   *
   * This operation allows authenticated members to request administrator privileges by providing a justification reason. The system creates a new admin request record with initial status set to 'pending' and associates it with the submitting member's account. The request is then placed in the pending queue for super administrator review.
   *
   * Members can only have one pending administrator request at a time. If a member already has a pending request, the system rejects the new submission with a conflict error. Members who already hold administrator privileges cannot submit admin requests. Once submitted, requests cannot be withdrawn or edited by the member.
   *
   * The reason text must be between 50-2000 characters and provide sufficient justification for the administrator privilege request. The system records the submission timestamp for sorting the pending queue and enforcing waiting periods between rejected requests.
   *
   * Super administrators review pending requests using the GET /admin-requests endpoint and process them using PUT /admin-requests/{adminRequestId}/approve or PUT /admin-requests/{adminRequestId}/reject operations. Upon approval, the member is promoted to regular administrator status.
   *
   * @param connection
   * @param body Administrator application request submission with justification reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new administrator application request in the discussion_board_admin_requests table.
   *
   * Implementation steps:
   * 1. Validate the authenticated user is a member (not guest, not already admin)
   * 2. Check if the member already has a pending request by querying discussion_board_admin_requests where member_id equals current user and status equals 'pending'
   * 3. If pending request exists, return 409 Conflict error
   * 4. Validate reason text: required, 50-2000 characters, no prohibited content
   * 5. Create new discussion_board_admin_requests record with:
   *    - id: generated UUID
   *    - member_id: current authenticated member's ID
   *    - admin_id: null (not yet decided)
   *    - reason: validated reason text
   *    - status: 'pending'
   *    - submitted_at: current timestamp
   *    - decided_at: null
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   * 6. Return the created request entity with full details
   *
   * Transaction scope: Single table insert operation, no complex transaction needed.
   *
   * Error handling:
   * - 401 Unauthorized: User not authenticated
   * - 403 Forbidden: User is guest or already has admin privileges
   * - 409 Conflict: Member already has pending request
   * - 400 Bad Request: Reason text validation failure (too short, too long, invalid content)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardAdminRequest.ICreate,
  ): Promise<IDiscussionBoardAdminRequest> {
    try {
      return await postDiscussionBoardMemberAdminRequests({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
