import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardComment } from "../../../../../api/structures/IDiscussionBoardComment";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId";
import { postDiscussionBoardMemberArticlesArticleIdComments } from "../../../../../providers/postDiscussionBoardMemberArticlesArticleIdComments";
import { putDiscussionBoardMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/putDiscussionBoardMemberArticlesArticleIdCommentsCommentId";

@Controller("/discussionBoard/member/articles/:articleId/comments")
export class DiscussionboardMemberArticlesCommentsController {
  /**
   * Create a new comment on an article in the discussion board.
   *
   * This operation allows authenticated members to post single-level comments on articles. The comment is associated with the specified article and the authenticated member who creates it. Comments are displayed in chronological order (oldest first) on the article page.
   *
   * Only registered members can create comments. Guest users and banned users are not permitted to post comments. The article must exist and not be deleted for the comment to be created successfully.
   *
   * The comment content is required and must meet minimum and maximum length validation rules. Upon successful creation, the system records the creation timestamp and returns the complete comment object including author information.
   *
   * Comments support edit and delete operations by their authors. Administrators can also delete any comment for moderation purposes. When an article is deleted, all associated comments are cascade deleted.
   *
   * @param connection
   * @param articleId Target article's ID to post the comment on
   * @param body Comment creation information
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Validate the articleId exists in discussion_board_articles table and deleted_at is null. Verify the authenticated user is a member (not guest) and not banned. Validate comment content meets minimum and maximum length requirements. Insert new record into discussion_board_comments table with: discussion_board_article_id from path parameter, discussion_board_member_id from authenticated session, content from request body, created_at and updated_at set to current timestamp, deleted_at as null. Return the created comment with author information joined from discussion_board_members table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.ICreate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await postDiscussionBoardMemberArticlesArticleIdComments({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing comment on an article. This operation allows comment owners or administrators to modify the comment content while preserving the original creation timestamp.
   *
   * The comment must belong to the specified article, and the requesting user must be either the comment author or an administrator. Only the content field can be modified; the system automatically updates the updated_at timestamp to track modification time.
   *
   * Comments support soft deletion through the deleted_at field. This update operation cannot restore deleted comments. If the comment has been deleted, the operation will fail. The article association and author cannot be changed through this endpoint.
   *
   * Administrators can update any comment regardless of ownership for moderation purposes. Regular members can only update their own comments. The updated comment is returned with full details including author information and timestamps.
   *
   * @param connection
   * @param articleId Parent article's ID (UUID format). Comments are accessed through their parent article.
   * @param commentId Target comment's ID (UUID format) to update.
   * @param body Update information for the comment including modified content.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update an existing comment's content. Query discussion_board_comments table by commentId. Verify articleId matches the comment's discussion_board_article_id for consistency. Validate user is either the comment owner (discussion_board_member_id matches authenticated user) or an administrator. Update content field and set updated_at to current timestamp. Preserve created_at and deleted_at fields. Return updated comment with member and article relationships. Handle concurrent edit conflicts with optimistic locking on updated_at timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardMemberArticlesArticleIdCommentsCommentId({
        member,
        articleId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific comment from a discussion board article.
   *
   * This operation removes a comment from the article's comment list, making it no longer visible to any user. The comment is soft-deleted by setting the deleted_at timestamp in the database, which preserves the record for audit trail and cascade deletion tracking purposes. However, the API does not provide any mechanism to recover or restore deleted comments - once deleted, the comment is permanently inaccessible through the application.
   *
   * Only the comment's author (the member who created it) or an administrator can delete a comment. Regular members can only delete their own comments, while administrators have moderation authority to delete any comment regardless of ownership. The articleId path parameter ensures the comment belongs to the specified article before deletion is processed.
   *
   * When a comment is deleted, the parent article remains intact and all other comments on the article are preserved. The comment is removed from chronological display (oldest-first ordering) and no longer contributes to the article's comment count. This operation implements the business rule that comment deletion is permanent from the user's perspective, even though the database retains the record with a deleted_at timestamp for audit compliance.
   *
   * If the comment does not exist, has already been deleted, the user is not the comment author (and not an administrator), or the comment does not belong to the specified article, the request is rejected with an appropriate error response.
   *
   * @param connection
   * @param articleId Target article's ID. Used to verify the comment belongs to this article before deletion.
   * @param commentId Target comment's ID to be deleted.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Delete a specific comment from an article by setting the deleted_at timestamp.
   *
   * Implementation steps:
   * 1. Validate both articleId and commentId are valid UUIDs
   * 2. Verify the comment exists and belongs to the specified article (join discussion_board_comments with discussion_board_articles on discussion_board_article_id)
   * 3. Check authorization: current user must be either the comment author (discussion_board_member_id matches authenticated user) or an administrator
   * 4. Verify the comment is not already deleted (deleted_at is null)
   * 5. Set deleted_at to current timestamp in a database transaction
   * 6. Update the parent article's comment count if cached
   * 7. Return success response
   *
   * Edge cases:
   * - Comment not found: return 404
   * - Comment already deleted: return 404 or 410
   * - Unauthorized (not author, not admin): return 403
   * - Article not found: return 404
   * - Concurrent deletion: use optimistic locking with updated_at timestamp
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId(
        {
          member,
          articleId,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
