import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardAdminSession } from "../../../../api/structures/IDiscussionBoardAdminSession";
import { IDiscussionBoardMemberSession } from "../../../../api/structures/IDiscussionBoardMemberSession";
import { IPageIDiscussionBoardAdminSession } from "../../../../api/structures/IPageIDiscussionBoardAdminSession";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getDiscussionBoardMemberSessionsSessionId } from "../../../../providers/getDiscussionBoardMemberSessionsSessionId";
import { patchDiscussionBoardMemberSessions } from "../../../../providers/patchDiscussionBoardMemberSessions";

@Controller("/discussionBoard/member/sessions")
export class DiscussionboardMemberSessionsController {
  /**
   * Retrieve a filtered and paginated list of user sessions across the discussion board platform.
   *
   * This administrative operation provides comprehensive session monitoring capabilities for security audit and compliance purposes. Administrators can search sessions by user identifier, IP address, session status (active/expired), and creation time ranges. The endpoint aggregates sessions from member, administrator, and guest session tables.
   *
   * Each session record includes connection metadata (IP address, referrer, href) and temporal fields (created_at, expired_at) for audit trail analysis. This supports security monitoring, suspicious activity detection, and compliance with authentication logging requirements.
   *
   * Access is restricted to administrators only. Regular members and guests cannot view session information. The operation supports pagination for large result sets and sorting by session creation time or expiration time.
   *
   * Related operations: GET /sessions/{sessionId} retrieves detailed session information. Session invalidation is handled through authentication logout flows, not this endpoint.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for session filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query session tables (discussion_board_member_sessions, discussion_board_admin_sessions, discussion_board_guest_sessions) with pagination and filtering.
   *
   * Apply search filters on: user ID (member_id, admin_id, or guest_id), IP address partial match, session status (active if expired_at > now, expired otherwise), creation date range, expiration date range.
   *
   * Join with discussion_board_members and discussion_board_admins to retrieve user display names and account status.
   *
   * Filter out soft-deleted administrator records (deleted_at IS NULL for active admins).
   *
   * Return cursor-based pagination with session summary including: session ID, user type (member/admin/guest), user display name, IP address, creation time, expiration time, status (active/expired).
   *
   * Sort by created_at DESC by default (newest sessions first). Support sorting by expired_at ASC (sessions expiring soonest).
   *
   * Enforce administrator-only access control. Reject requests from non-administrator actors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardAdminSession.IRequest,
  ): Promise<IPageIDiscussionBoardAdminSession.ISummary> {
    try {
      return await patchDiscussionBoardMemberSessions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific member session owned by the authenticated member.
   *
   * This operation provides members access to their own session metadata including connection details and temporal information. Sessions are automatically created during the authentication flow when members log in to the discussion board platform. Each session record contains connection metadata such as IP address, initial page URL (href), and HTTP referrer for security audit purposes.
   *
   * The session details include creation timestamp marking when the authentication occurred and expiration timestamp indicating when the session becomes invalid. This information enables members to monitor their account activity and verify their login history.
   *
   * Access is restricted to the session owner - members can only retrieve sessions associated with their own account. The system validates ownership by matching the session's discussion_board_member_id with the authenticated member's ID. Attempting to access another member's session will result in authorization failure.
   *
   * This operation complements the authentication flow by providing transparency into active and historical sessions. Members can detect unauthorized access by reviewing session details and identifying unfamiliar connection metadata.
   *
   * @param connection
   * @param sessionId Target session's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query discussion_board_member_sessions table by session ID. Validate the requesting user has permission to view this session (either owns the session or has administrator privileges). Join with discussion_board_members to verify ownership if needed. Return session details including connection metadata (IP, href, referrer) and temporal fields (created_at, expired_at). Handle case where session doesn't exist by returning 404. Ensure banned users cannot access session information even with valid session ID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardMemberSession> {
    try {
      return await getDiscussionBoardMemberSessionsSessionId({
        member,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
