/**
 * Retrieve a paginated list of permission definitions available in the system.
 *
 * This endpoint returns the complete catalog of permission codes that can be assigned to roles within the hrm_platform system. Each permission represents a specific capability or access right, such as managing organization settings, viewing employee lists, or approving timesheets.
 *
 * Permissions are system-managed reference data populated during initial setup. The list supports filtering by permission code pattern, description keywords, and active/deleted status. Results are returned with pagination for efficient browsing of the permission catalog.
 *
 * This endpoint is useful for building role management interfaces where administrators need to select permissions when creating or editing custom roles.
 *
 * @param props.connection
 * @param props.body Search criteria including permission code pattern, description keywords, soft-delete status filter, and pagination parameters.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query hrm_platform_permissions table with pagination
 *   and filtering support.
 *
 * Apply search filters:
 * - code: partial match on permission code (e.g., 'employee' matches 'employee:manage', 'employee:view')
 * - description: full-text search on permission description
 * - deleted: filter by soft-delete status (null = active, not null = deleted)
 *
 * Sort results by code ascending by default. Support cursor-based pagination for large result sets.
 *
 * Return IHrmPlatformPermission.ISummary for each item containing id, code, description, and created_at. Exclude deleted records by default unless explicitly requested.
 *
 * No authorization check required beyond basic member authentication - permissions list is visible to all authenticated users for role configuration purposes.
 * @path /hrmPlatform/member/permissions
 * @accessor api.functional.hrmPlatform.member.permissions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
