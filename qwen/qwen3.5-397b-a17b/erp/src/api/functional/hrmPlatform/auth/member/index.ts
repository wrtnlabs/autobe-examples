/**
 * Creates a new member account with email and password authentication credentials.
 *
 * This endpoint enables new users to register for the HRM platform by providing their email address, password, and initial profile information. The email address serves as the unique identifier for authentication and must not already exist in the hrm_platform_members table. The password is securely hashed using bcrypt before storage, ensuring credentials are never stored in plain text.
 *
 * Upon successful registration, the system automatically creates an authentication session and returns JWT tokens (access_token and refresh_token) in the IHrmPlatformMember.IAuthorized response. The access token enables immediate API authentication, while the refresh token allows token renewal without re-authentication. Session metadata including IP address, current page URL (href), and referrer URL are captured for audit trail purposes.
 *
 * The display_name field becomes the user's global profile identifier shown across all organizations they may join. Optional avatar_url and phone_number fields can be provided during registration or updated later through profile management endpoints. The created_at timestamp marks the account creation time, and the account is immediately active for use.
 *
 * This operation integrates with the hrm_platform_members table structure, utilizing the unique email constraint to prevent duplicate accounts. New members can subsequently create or join organizations and perform HRM operations based on their assigned role permissions.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration information for creating a new member account
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Validate email format and uniqueness against hrm_platform_members.email unique constraint. Hash password using bcrypt with appropriate salt rounds. Create member record with provided email, password_hash, display_name, avatar_url, and phone_number. Set created_at and updated_at timestamps. Generate JWT access token and refresh token. Create session record in hrm_platform_member_sessions with tokens, IP, href, referrer, and expired_at. Return IHrmPlatformMember.IAuthorized with tokens and member details.
 * @path /hrmPlatform/auth/member/join
 * @accessor api.functional.hrmPlatform.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
