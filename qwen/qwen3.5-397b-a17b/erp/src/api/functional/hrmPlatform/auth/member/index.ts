/**
 * Register a new member account with email and password.
 *
 * Creates a new member record in hrm_platform_members with the provided email and hashed password. Email must be unique across all members (enforced by unique index). Password must meet security requirements (minimum 8 characters, at least one uppercase, one lowercase, one number). Upon successful registration, an email verification token is created in hrm_platform_member_email_verifications and a verification email is sent.
 *
 * The operation returns JWT access_token (short-lived, typically 15 minutes) and refresh_token (long-lived, typically 7 days) for immediate authentication. New members have no organization membership initially and must create or join an organization to access organization-scoped features.
 *
 * Returns 409 Conflict if email already exists. Returns 400 Bad Request if password does not meet requirements or email format is invalid.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration credentials for new member account creation.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Register a new member account with email and
 *   password. Validate email format and uniqueness against
 *   hrm_platform_members.email. Hash password using bcrypt/argon2. Create
 *   hrm_platform_members record with email and password_hash. Generate email
 *   verification token in hrm_platform_member_email_verifications with
 *   expiration (24 hours). Send verification email asynchronously. Create
 *   initial session in hrm_platform_member_sessions with JWT access_token and
 *   refresh_token. Return tokens with member id and email. New members have no
 *   organization membership initially.
 * @path /hrmPlatform/auth/member/join
 * @accessor api.functional.hrmPlatform.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
