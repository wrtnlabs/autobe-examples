/**
 * Register a new guest account or recognize returning guest by device fingerprint.
 *
 * This endpoint creates a new guest account in the hrm_platform_guests table when a device fingerprint is encountered for the first time. The device_fingerprint field serves as the unique identifier for guest recognition across sessions, enabling continuity without requiring email/password authentication.
 *
 * For returning guests with an existing device_fingerprint, the operation recognizes the guest and issues new session tokens without creating a duplicate account. This supports the temporary, frictionless access model for unauthenticated platform visitors.
 *
 * Upon successful guest registration or recognition, a new session record is created in hrm_platform_guest_sessions with access_token, refresh_token, and connection metadata (ip, href, referrer). The session includes an expired_at timestamp for automatic invalidation.
 *
 * The response contains the guest's authorized tokens (access and refresh) along with guest identification, enabling immediate platform access for temporary visitors.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Device fingerprint for guest identification and recognition.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Create a new guest account using device fingerprint identification. The service generates a unique guest ID and stores the device_fingerprint for future recognition. A new guest session is created with access and refresh tokens, connection metadata (IP, href, referrer), and expiration timestamp. The device_fingerprint must be unique - if a guest with the same fingerprint exists, return the existing guest's tokens instead of creating a duplicate. Tokens are JWT-based with appropriate expiration times for temporary guest access.
 * @path /hrmPlatform/auth/guest/join
 * @accessor api.functional.hrmPlatform.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
