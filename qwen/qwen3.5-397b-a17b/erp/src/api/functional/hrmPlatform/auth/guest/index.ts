/**
 * Register a new guest account for anonymous platform access using device fingerprint identification.
 *
 * This operation creates a temporary guest account in the hrm_platform_guests table with a unique device fingerprint. The device fingerprint serves as the primary identifier for recognizing returning guests without requiring email/password credentials. Upon successful registration, the system generates an initial guest session in hrm_platform_guest_sessions with JWT access and refresh tokens.
 *
 * The request must include a device_fingerprint string that uniquely identifies the client device. The system validates that this fingerprint is not already registered - attempting to join with an existing fingerprint returns a 409 Conflict error. Client metadata including IP address, current page URL (href), and referrer URL are captured from request headers and stored with the session for audit purposes.
 *
 * The response includes the newly created guest ID, access token for authenticated requests, refresh token for token renewal, and the session expiration timestamp. Guests can use these credentials to access guest-scoped endpoints until the session expires. The session expiration is automatically enforced by the database expired_at field.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest registration request with device fingerprint for unique identification.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Create a new guest account identified by device fingerprint. Generate a unique guest ID and store the device fingerprint for future recognition. Create an initial guest session with JWT access and refresh tokens. Set session expiration based on configured timeout (e.g., 24 hours). Capture client metadata (IP, href, referrer) from request headers. Return the guest ID along with access token, refresh token, and expiration timestamp. Validate that device_fingerprint is provided and unique - return 409 Conflict if a guest with the same fingerprint already exists. The guest can use these tokens to access guest-scoped endpoints until session expiration.
 * @path /hrmPlatform/auth/guest/join
 * @accessor api.functional.hrmPlatform.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
