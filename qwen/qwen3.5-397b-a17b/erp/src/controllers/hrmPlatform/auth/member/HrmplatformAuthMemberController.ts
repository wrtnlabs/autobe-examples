import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformMember } from "../../../../api/structures/IHrmPlatformMember";
import { postHrmPlatformAuthMemberJoin } from "../../../../providers/postHrmPlatformAuthMemberJoin";
import { postHrmPlatformAuthMemberLogin } from "../../../../providers/postHrmPlatformAuthMemberLogin";
import { postHrmPlatformAuthMemberRefresh } from "../../../../providers/postHrmPlatformAuthMemberRefresh";

@Controller("/hrmPlatform/auth/member")
export class HrmplatformAuthMemberController {
  /**
   * Register a new member account with email and password.
   *
   * Creates a new member record in hrm_platform_members with the provided email and hashed password. Email must be unique across all members (enforced by unique index). Password must meet security requirements (minimum 8 characters, at least one uppercase, one lowercase, one number). Upon successful registration, an email verification token is created in hrm_platform_member_email_verifications and a verification email is sent.
   *
   * The operation returns JWT access_token (short-lived, typically 15 minutes) and refresh_token (long-lived, typically 7 days) for immediate authentication. New members have no organization membership initially and must create or join an organization to access organization-scoped features.
   *
   * Returns 409 Conflict if email already exists. Returns 400 Bad Request if password does not meet requirements or email format is invalid.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials for new member account creation.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Register a new member account with email and
     *   password. Validate email format and uniqueness against
     *   hrm_platform_members.email. Hash password using bcrypt/argon2. Create
     *   hrm_platform_members record with email and password_hash. Generate
     *   email verification token in hrm_platform_member_email_verifications
     *   with expiration (24 hours). Send verification email asynchronously.
     *   Create initial session in hrm_platform_member_sessions with JWT
     *   access_token and refresh_token. Return tokens with member id and email.
     *   New members have no organization membership initially.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmPlatformMember.IJoin,
  ): Promise<IHrmPlatformMember.IAuthorized> {
    try {
      return await postHrmPlatformAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a member with email and password credentials.
   *
   * Validates the provided email and password against the hrm_platform_members table. Password is verified using bcrypt/argon2 hash comparison. Account must be active (deleted_at is null) and email must be verified (confirmed via hrm_platform_member_email_verifications). Upon successful authentication, a new session record is created in hrm_platform_member_sessions with JWT access_token and refresh_token.
   *
   * The response includes access_token (short-lived, for API requests) and refresh_token (long-lived, for obtaining new access tokens). Session metadata including IP address, page URL, and referrer are recorded in hrm_platform_member_sessions for security audit and session management.
   *
   * Returns 401 Unauthorized if credentials are invalid or account is deactivated. Returns 403 Forbidden if email is not yet verified.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials for member authentication with email and password.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Authenticate member with email and password.
     *   Query hrm_platform_members by email. Verify account is not soft-deleted
     *   (deleted_at is null). Compare provided password with password_hash
     *   using bcrypt/argon2. Verify email is confirmed (check
     *   hrm_platform_member_email_verifications for used token). Create
     *   hrm_platform_member_sessions record with JWT access_token and
     *   refresh_token. Capture IP address, href URL, and referrer for security
     *   audit. Set session expired_at based on refresh token TTL. Return tokens
     *   with member id, email, and session metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmPlatformMember.ILogin,
  ): Promise<IHrmPlatformMember.IAuthorized> {
    try {
      return await postHrmPlatformAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens using a valid refresh token.
   *
   * Validates the provided refresh_token against active sessions in hrm_platform_member_sessions. The session must not be expired (expired_at must be in the future) and the associated member account must be active (deleted_at is null). Token validation includes checking the refresh_token exists and matches an active session.
   *
   * Upon successful validation, returns a new access_token for continued API access. The refresh_token may be rotated (old token invalidated, new token issued) for enhanced security following OAuth 2.0 best practices. Session updated_at is refreshed to track last activity time.
   *
   * Returns 401 Unauthorized if refresh_token is invalid, expired, or the member account is deactivated. Returns 403 Forbidden if session has been explicitly revoked.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access token without re-authentication.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Refresh JWT access token using valid refresh
     *   token. Query hrm_platform_member_sessions by refresh_token. Validate
     *   session exists and is not expired (expired_at > now). Verify associated
     *   member account is active (deleted_at is null). Optionally implement
     *   refresh token rotation (invalidate old token, generate new one). Update
     *   session updated_at timestamp. Generate new access_token with updated
     *   claims. Return new access_token and optionally new refresh_token with
     *   updated expired_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IHrmPlatformMember.IRefresh,
  ): Promise<IHrmPlatformMember.IAuthorized> {
    try {
      return await postHrmPlatformAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
