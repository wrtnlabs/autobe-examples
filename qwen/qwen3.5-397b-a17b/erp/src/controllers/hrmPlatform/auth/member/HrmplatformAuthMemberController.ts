import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformMember } from "../../../../api/structures/IHrmPlatformMember";
import { postHrmPlatformAuthMemberJoin } from "../../../../providers/postHrmPlatformAuthMemberJoin";
import { postHrmPlatformAuthMemberLogin } from "../../../../providers/postHrmPlatformAuthMemberLogin";
import { postHrmPlatformAuthMemberRefresh } from "../../../../providers/postHrmPlatformAuthMemberRefresh";

@Controller("/hrmPlatform/auth/member")
export class HrmplatformAuthMemberController {
  /**
   * Register a new member account on the hrmPlatform system. This operation creates a new user account with email and password credentials, storing the password as a bcrypt hash in the hrm_platform_members table.
   *
   * The registration process validates that the email address is unique across all existing members. Upon successful registration, the system generates a JWT access token and refresh token pair, creating a session record in hrm_platform_member_sessions with token hashes for security. An email verification token is also generated and stored in hrm_platform_member_email_verifications for later email confirmation.
   *
   * The member actor receives full authentication credentials immediately upon registration, allowing immediate access to organization features. Email verification is recommended but not required for initial login access.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration request containing email, password, and display name for new member account creation.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Register new member account. Validate email uniqueness (check hrm_platform_members.email unique constraint). Hash password with bcrypt. Create member record with email, password_hash, display_name. Generate JWT access token (short-lived) and refresh token (long-lived). Create hrm_platform_member_sessions record with token hashes, device info, expiration. Send email verification token via hrm_platform_member_email_verifications. Return tokens in IAuthorized response. Error cases: duplicate email (409), invalid email format (400), weak password (400).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmPlatformMember.IJoin,
  ): Promise<IHrmPlatformMember.IAuthorized> {
    try {
      return await postHrmPlatformAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a member using email and password credentials. This operation validates the provided credentials against the hrm_platform_members table and issues JWT authentication tokens upon successful verification.
   *
   * The login process retrieves the member record by email address, verifies the password using bcrypt hash comparison, and ensures the account is active (deleted_at is null). Upon successful authentication, the system generates a new JWT access token and refresh token pair, storing token hashes in hrm_platform_member_sessions along with device information and session expiration timestamp.
   *
   * The member actor receives full authentication credentials enabling access to organization features based on their assigned roles. Each login creates a new session record for security auditing and token revocation capabilities.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials containing email and password for member authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Authenticate member with email and password. Query hrm_platform_members by email. Verify password hash matches using bcrypt comparison. Check member is not soft-deleted (deleted_at is null). Generate new JWT access token and refresh token. Create hrm_platform_member_sessions record with token hashes, IP, device info, expiration timestamp. Return tokens in IAuthorized response. Error cases: email not found (401), password mismatch (401), deleted account (401).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmPlatformMember.ILogin,
  ): Promise<IHrmPlatformMember.IAuthorized> {
    try {
      return await postHrmPlatformAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT authentication tokens using a valid refresh token. This operation extends the member's authenticated session by issuing a new access token and refresh token pair without requiring re-authentication.
   *
   * The refresh process validates the provided refresh token against the hrm_platform_member_sessions table by comparing token hashes. The system verifies the session exists, has not expired (expired_at is in the future), and the refresh token matches the stored hash. Upon successful validation, new JWT tokens are generated and the session record is updated with new token hashes and an extended expiration timestamp.
   *
   * This operation enables seamless session continuation for the member actor, maintaining authentication state across access token expirations. Token refresh is a security best practice, allowing short-lived access tokens while maintaining long-lived sessions through refresh token rotation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access and refresh token pair.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Refresh JWT access token using valid refresh token. Query hrm_platform_member_sessions by refresh_token_hash. Verify session exists and not expired (expired_at > now). Validate refresh token matches hash. Generate new access token and refresh token pair. Update session record with new token hashes and extended expiration. Return new tokens in IAuthorized response. Error cases: invalid refresh token (401), expired session (401), session not found (401).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IHrmPlatformMember.IRefresh,
  ): Promise<IHrmPlatformMember.IAuthorized> {
    try {
      return await postHrmPlatformAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
