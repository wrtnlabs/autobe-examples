import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformGuest } from "../../../../api/structures/IHrmPlatformGuest";
import { postHrmPlatformAuthGuestJoin } from "../../../../providers/postHrmPlatformAuthGuestJoin";
import { postHrmPlatformAuthGuestRefresh } from "../../../../providers/postHrmPlatformAuthGuestRefresh";

@Controller("/hrmPlatform/auth/guest")
export class HrmplatformAuthGuestController {
  /**
   * Create a guest account and session for unauthenticated visitors accessing the platform.
   *
   * This operation initializes a temporary guest account identified by a device fingerprint. The device fingerprint uniquely identifies the visitor's device and persists across browser sessions. If the client provides a device fingerprint, the system validates its uniqueness. If not provided, the server generates one from request characteristics.
   *
   * Upon successful creation, the operation returns JWT access and refresh tokens in the IHrmPlatformGuest.IAuthorized response. These tokens enable the guest to access public pages and maintain session state. The guest session has a limited lifetime defined by the expired_at timestamp in hrm_platform_guest_sessions.
   *
   * If a guest account with the same device_fingerprint already exists, the operation returns the existing session tokens instead of creating a duplicate. This ensures continuity for returning visitors.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest registration request containing optional device fingerprint and session context.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Create a guest account for unauthenticated visitors. Generate a unique device fingerprint if not provided, or validate uniqueness if client-supplied. Create hrm_platform_guests record with device_fingerprint. Create initial hrm_platform_guest_sessions record with IP, href, referrer from request context. Generate JWT access token and refresh token with expiration timestamps. Return tokens in IAuthorized response. Handle duplicate device_fingerprint by returning existing guest session tokens. Set session expired_at based on platform configuration (typically 24 hours from creation).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmPlatformGuest.IJoin,
  ): Promise<IHrmPlatformGuest.IAuthorized> {
    try {
      return await postHrmPlatformAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens for an existing guest session.
   *
   * This operation allows guests to renew their session tokens before expiration. The client submits the current refresh token, which is validated against the hrm_platform_guest_sessions table. The system verifies that the session has not expired and the associated guest account is still active.
   *
   * Upon successful validation, new access and refresh tokens are generated with updated expiration timestamps. The session's expired_at field is extended to maintain the guest's browsing context. The new tokens are returned in the IHrmPlatformGuest.IAuthorized response.
   *
   * If the refresh token is invalid, the session has expired, or the guest account has been deleted, the operation returns a 401 Unauthorized error. The client must then call the join operation to create a new guest session.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest session refresh request containing the current refresh token.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Refresh guest session tokens. Validate the provided refresh token against hrm_platform_guest_sessions. Check that the session has not expired (expired_at > current time). Verify the hrm_platform_guest_id references an existing, non-deleted guest account. Generate new access token and refresh token pair with updated expiration timestamps. Update the session's expired_at timestamp. Return new tokens in IAuthorized response. Reject with 401 if refresh token is invalid, expired, or guest account is deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IHrmPlatformGuest.IRefresh,
  ): Promise<IHrmPlatformGuest.IAuthorized> {
    try {
      return await postHrmPlatformAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
