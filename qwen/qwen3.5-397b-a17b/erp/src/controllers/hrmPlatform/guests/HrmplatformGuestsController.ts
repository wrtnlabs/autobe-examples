import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformGuest } from "../../../api/structures/IHrmPlatformGuest";
import { IPageIHrmPlatformGuest } from "../../../api/structures/IPageIHrmPlatformGuest";
import { getHrmPlatformGuestsGuestId } from "../../../providers/getHrmPlatformGuestsGuestId";
import { patchHrmPlatformGuests } from "../../../providers/patchHrmPlatformGuests";

@Controller("/hrmPlatform/guests")
export class HrmplatformGuestsController {
  /**
   * Retrieve a filtered and paginated list of guest accounts.
   *
   * This operation provides search capabilities for guest accounts based on device fingerprint patterns and creation date ranges. Guests are unauthenticated visitors who have accessed the platform without creating a member account.
   *
   * The endpoint supports pagination for browsing large result sets and filtering by various criteria including device fingerprint partial matching and temporal ranges. Results are returned as summary objects optimized for list display.
   *
   * Access is restricted to organization members with appropriate administrative permissions. Guest accounts represent temporary platform access and can be converted to member accounts through the registration process.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for guest listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query hrm_platform_guests table with pagination and filtering support. Apply search filters on device_fingerprint using partial matching. Support date range filtering on created_at timestamp. Exclude soft-deleted records (deleted_at is not null) from results by default. Implement cursor-based or offset pagination for efficient large dataset handling. Sort results by created_at descending to show most recent guests first. Join with hrm_platform_guest_sessions if session count statistics are needed in response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IHrmPlatformGuest.IRequest,
  ): Promise<IPageIHrmPlatformGuest.ISummary> {
    try {
      return await patchHrmPlatformGuests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific guest visitor record by unique identifier.
   *
   * This operation returns detailed information about a guest visitor including their device fingerprint, creation timestamp, and session status. Guests are temporary unauthenticated visitors who have not yet created an account or logged into the platform.
   *
   * The guest record provides visibility into pre-authentication visitor state and is used for tracking guest sessions and device identification. This endpoint is typically used during the authentication flow to verify guest status before transitioning to member actor.
   *
   * No authorization is required as guest data is not organization-scoped and represents anonymous visitor state.
   *
   * @param connection
   * @param guestId Target guest's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query hrm_platform_guests table by guestId UUID. Return guest record including device fingerprint, creation timestamp, and associated session information. Join with hrm_platform_guest_sessions if needed to include active session status. Validate that guestId exists and return 404 if not found. No authorization required as this is guest-scoped data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":guestId")
  public async at(
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformGuest> {
    try {
      return await getHrmPlatformGuestsGuestId({
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
