import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformPermission } from "../../../../api/structures/IHrmPlatformPermission";
import { IPageIHrmPlatformPermission } from "../../../../api/structures/IPageIHrmPlatformPermission";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberPermissionsPermissionId } from "../../../../providers/getHrmPlatformMemberPermissionsPermissionId";
import { patchHrmPlatformMemberPermissions } from "../../../../providers/patchHrmPlatformMemberPermissions";

@Controller("/hrmPlatform/member/permissions")
export class HrmplatformMemberPermissionsController {
  /**
   * Retrieve a paginated list of permission definitions available in the system.
   *
   * This endpoint returns the complete catalog of permission codes that can be assigned to roles within the hrm_platform system. Each permission represents a specific capability or access right, such as managing organization settings, viewing employee lists, or approving timesheets.
   *
   * Permissions are system-managed reference data populated during initial setup. The list supports filtering by permission code pattern, description keywords, and active/deleted status. Results are returned with pagination for efficient browsing of the permission catalog.
   *
   * This endpoint is useful for building role management interfaces where administrators need to select permissions when creating or editing custom roles.
   *
   * @param connection
   * @param body Search criteria including permission code pattern, description keywords, soft-delete status filter, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_permissions table with
     *   pagination and filtering support.
   *
   * Apply search filters:
   * - code: partial match on permission code (e.g., 'employee' matches 'employee:manage', 'employee:view')
   * - description: full-text search on permission description
   * - deleted: filter by soft-delete status (null = active, not null = deleted)
   *
   * Sort results by code ascending by default. Support cursor-based pagination for large result sets.
   *
   * Return IHrmPlatformPermission.ISummary for each item containing id, code, description, and created_at. Exclude deleted records by default unless explicitly requested.
   *
   * No authorization check required beyond basic member authentication - permissions list is visible to all authenticated users for role configuration purposes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformPermission.IRequest,
  ): Promise<IPageIHrmPlatformPermission.ISummary> {
    try {
      return await patchHrmPlatformMemberPermissions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single permission record by its unique identifier.
   *
   * This endpoint returns the complete permission details including the permission code (in format 'domain:action' such as org:manage or employee:view), human-readable description, and system timestamps. Permissions are system-managed reference data that define the complete set of capabilities that can be assigned to roles within the hrm_platform system.
   *
   * The permission code uniquely identifies the permission and is used throughout the system for authorization checks. The description helps administrators understand the purpose of each permission when creating or editing custom roles.
   *
   * @param connection
   * @param permissionId Unique identifier of the permission record (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_permissions table by primary
     *   key id (UUID). Return the full permission record including code,
     *   description, created_at, and updated_at fields. Handle 404 Not Found if
     *   permission ID does not exist. No authorization checks required beyond
     *   basic member authentication since permissions are system reference data
     *   visible to all authenticated users.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":permissionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("permissionId")
    permissionId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformPermission> {
    try {
      return await getHrmPlatformMemberPermissionsPermissionId({
        member,
        permissionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
