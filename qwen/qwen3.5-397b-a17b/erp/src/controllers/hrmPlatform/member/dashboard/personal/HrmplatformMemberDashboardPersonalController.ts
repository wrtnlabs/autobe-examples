import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformDashboard } from "../../../../../api/structures/IHrmPlatformDashboard";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchHrmPlatformMemberDashboardPersonal } from "../../../../../providers/patchHrmPlatformMemberDashboardPersonal";

@Controller("/hrmPlatform/member/dashboard/personal")
export class HrmplatformMemberDashboardPersonalController {
  /**
   * Retrieve the authenticated employee's personal dashboard with aggregated time tracking statistics and work overview.
   *
   * This endpoint compiles a comprehensive view of the employee's current work status by querying multiple data sources. The dashboard provides real-time insights into time logged today and this week, active timer sessions, recent time entries, pending timesheet approval status, and assigned tasks requiring attention.
   *
   * The hours today metric sums all timelog durations for the current date in the user's timezone (Asia/Seoul). Hours this week aggregates timelogs from Monday through Sunday of the current week. These calculations exclude timelogs from deleted or archived projects.
   *
   * The active timer section returns the currently running timer if one exists, including the associated project, optional task, start timestamp, and work description. Returns null when no timer is active.
   *
   * Recent timelogs displays the five most recent time entries with project and task context, enabling quick review of recent work activity. Timelogs are ordered by date descending.
   *
   * The pending timesheet section shows the current week's timesheet status, which may be draft (being built), submitted (awaiting approval), approved (locked), or rejected (requires correction). If rejected, the rejection reason is included to guide resubmission.
   *
   * Assigned tasks lists all open and in-progress tasks assigned to the employee across their accessible projects, sorted by due date and priority. This helps employees prioritize their workload.
   *
   * Access is restricted to member actors within their organization context. The employee's organization membership is determined from their authentication session.
   *
   * @param connection
   * @param body Optional filters and sections to include in the dashboard response
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query multiple tables to compile personal dashboard statistics for the authenticated employee.
   *
   * 1. Hours Today: Sum duration_minutes from hrm_platform_timelogs where employee_id matches current user and date = current date (Asia/Seoul timezone).
   *
   * 2. Hours This Week: Sum duration_minutes from hrm_platform_timelogs where employee_id matches and date is within current week (Monday 00:00 to Sunday 23:59 in Asia/Seoul timezone).
   *
   * 3. Active Timer: Query hrm_platform_timers where employee_id matches and stopped_at is null. Return timer with project, task, started_at, and description.
   *
   * 4. Recent Timelogs: Query hrm_platform_timelogs where employee_id matches, ordered by date DESC, limit 5. Include project name, task title, duration, date, billable flag.
   *
   * 5. Pending Timesheet: Query hrm_platform_timesheets where employee_id matches and week_start_date = current week's Monday. Return status (draft/submitted/approved/rejected), total hours, rejection_reason if rejected.
   *
   * 6. Assigned Tasks: Query hrm_platform_tasks where hrm_platform_employee_id matches and status in ('open', 'in-progress'). Include task title, project name, priority, due_date, status.
   *
   * All queries must respect organization context - employee record determines which organization's data to access. Return null for sections with no data (e.g., no active timer, no pending timesheet).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformDashboard.IRequest,
  ): Promise<IHrmPlatformDashboard> {
    try {
      return await patchHrmPlatformMemberDashboardPersonal({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
