import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformProjectDashboard } from "../../../../../api/structures/IHrmPlatformProjectDashboard";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberDashboardProjects } from "../../../../../providers/getHrmPlatformMemberDashboardProjects";

@Controller("/hrmPlatform/member/dashboard/projects")
export class HrmplatformMemberDashboardProjectsController {
  /**
   * Retrieve project dashboard statistics and overview information for the organization.
   *
   * This endpoint provides aggregated project metrics for the organization dashboard, including project counts by status (active, archived, completed), budget utilization statistics, and highlights of projects consuming significant budget percentage. Users with report:view permission can access this data to monitor organizational project health and resource allocation.
   *
   * The response includes summary statistics such as total active projects, projects approaching or exceeding budget thresholds (over 80% utilization), and top projects by hours logged in the current week. This enables managers and owners to quickly assess project performance and identify projects requiring attention.
   *
   * Access is restricted to members with report:view permission within the organization context. All data is isolated to the authenticated user's current organization session.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_projects table filtered by organization_id from session context. Calculate aggregate statistics: count projects by status (active, archived, completed), calculate budget utilization percentage for projects with budget_hours set (actual hours from timelogs / budget_hours * 100), identify projects with budget utilization over 80%. Join with hrm_platform_timelogs to sum actual hours per project for the current week. Return aggregated dashboard data including total project counts, budget utilization metrics, and top projects by hours logged this week. Apply organization data isolation - only return projects belonging to the authenticated user's current organization.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmPlatformProjectDashboard> {
    try {
      return await getHrmPlatformMemberDashboardProjects({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
