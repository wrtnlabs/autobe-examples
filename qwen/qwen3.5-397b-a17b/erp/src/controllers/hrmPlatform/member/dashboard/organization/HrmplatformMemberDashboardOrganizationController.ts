import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformOrganizationDashboard } from "../../../../../api/structures/IHrmPlatformOrganizationDashboard";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchHrmPlatformMemberDashboardOrganization } from "../../../../../providers/patchHrmPlatformMemberDashboardOrganization";

@Controller("/hrmPlatform/member/dashboard/organization")
export class HrmplatformMemberDashboardOrganizationController {
  /**
   * Retrieve organization dashboard statistics and metrics for the current organization context.
   *
   * This operation provides a comprehensive overview of organizational performance including workforce metrics, time tracking statistics, and project health indicators. The dashboard displays total active employees (from hrm_platform_employees where status is 'active'), total hours logged this week (aggregated from hrm_platform_timelogs.duration_minutes), pending timesheets awaiting approval (from hrm_platform_timesheets where status is 'submitted'), projects with budget utilization over 80 percent (from hrm_platform_projects comparing actual hours to budget_hours), and the top 5 employees by hours logged this week.
   *
   * Access to this endpoint requires the report:view permission as defined in the organization's role-based access control. Users without this permission cannot access organization-level reports and dashboards. The data is strictly isolated per organization - users can only see dashboard data for their currently selected organization context from the session.
   *
   * The response includes aggregated statistics computed from multiple data sources: hrm_platform_employees for workforce counts, hrm_platform_timelogs for time tracking data, hrm_platform_timesheets for approval workflow status, and hrm_platform_projects for budget utilization metrics. All queries are scoped to the organization_id from the user's session context to enforce multi-tenant data isolation.
   *
   * Related operations include PATCH /dashboard/personal for individual employee dashboard data, which is accessible to all employees regardless of report:view permission. For detailed employee lists, use PATCH /employees. For detailed timesheet data, use PATCH /timesheets.
   *
   * @param connection
   * @param body Optional filters for customizing dashboard date range and metrics. Includes week_start_date and week_end_date for custom reporting periods. If not provided, defaults to current week (Monday to Sunday) based on organization timezone.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query and aggregate data from multiple tables to compute organization dashboard statistics.
   *
   * 1. Validate user has report:view permission in current organization context
   * 2. Retrieve total count of active employees from hrm_platform_employees where status is active
   * 3. Calculate total hours logged this week by summing timelog durations from hrm_platform_timelogs for current week (Monday-Sunday based on organization timezone)
   * 4. Count pending timesheets from hrm_platform_timesheets where status is 'submitted' or 'approved' awaiting review
   * 5. Query hrm_platform_projects to find projects where actual hours exceed 80% of budget_hours
   * 6. Retrieve top 5 employees by hours logged this week with their total hours
   * 7. Apply date range filters from request body if provided (default to current week)
   * 8. Return aggregated dashboard data as IHrmPlatformOrganizationDashboard
   *
   * Ensure all queries are scoped to the current organization ID from session context for data isolation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformOrganizationDashboard.IRequest,
  ): Promise<IHrmPlatformOrganizationDashboard> {
    try {
      return await patchHrmPlatformMemberDashboardOrganization({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
