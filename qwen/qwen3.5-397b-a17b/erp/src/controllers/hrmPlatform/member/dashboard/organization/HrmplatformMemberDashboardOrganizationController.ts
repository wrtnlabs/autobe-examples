import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformOrganizationDashboard } from "../../../../../api/structures/IHrmPlatformOrganizationDashboard";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberDashboardOrganization } from "../../../../../providers/getHrmPlatformMemberDashboardOrganization";

@Controller("/hrmPlatform/member/dashboard/organization")
export class HrmplatformMemberDashboardOrganizationController {
  /**
   * Retrieves organization dashboard statistics providing an at-a-glance overview of key metrics and activity indicators.
   *
   * This endpoint returns aggregated data including active employee count, total hours logged this week across all employees, number of timesheets pending approval, projects exceeding 80% budget utilization, and the top 5 employees by hours logged in the current week. All metrics are scoped to the currently selected organization context.
   *
   * Access requires the report:view permission. The data is computed in real-time from employee records, timelogs, timesheets, and projects within the organization.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query organization-scoped data to compute
     *   dashboard metrics:
   *
   * 1. Count active employees: SELECT COUNT(*) FROM hrm_platform_employees WHERE organization_id = ? AND status = 'active' AND deleted_at IS NULL
   *
   * 2. Sum hours logged this week: Calculate week start (Monday) and end (Sunday) in organization timezone. SUM(duration_minutes) FROM hrm_platform_timelogs JOIN hrm_platform_employees ON timelogs.hrm_platform_employee_id = employees.id WHERE employees.organization_id = ? AND timelogs.date BETWEEN week_start AND week_end AND timelogs.deleted_at IS NULL. Convert minutes to hours.
   *
   * 3. Count pending timesheets: SELECT COUNT(*) FROM hrm_platform_timesheets JOIN hrm_platform_employees ON timesheets.employee_id = employees.id WHERE employees.organization_id = ? AND timesheets.status = 'submitted' AND timesheets.deleted_at IS NULL
   *
   * 4. Find projects over 80% budget: For each project with budget_hours > 0, calculate actual hours from timelogs this week. Filter where (actual_hours / budget_hours) >= 0.8. Return project id, name, budget_hours, actual_hours, and utilization percentage.
   *
   * 5. Top 5 employees by hours: GROUP BY employee_id, SUM duration_minutes for current week, ORDER BY total DESC LIMIT 5. Join with employee and user profile for display name.
   *
   * Enforce organization context on all queries. Return null for optional fields when no data exists.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmPlatformOrganizationDashboard> {
    try {
      return await getHrmPlatformMemberDashboardOrganization({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
