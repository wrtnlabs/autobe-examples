import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformDepartment } from "../../../../api/structures/IHrmPlatformDepartment";
import { IPageIHrmPlatformDepartment } from "../../../../api/structures/IPageIHrmPlatformDepartment";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteHrmPlatformMemberDepartmentsDepartmentId } from "../../../../providers/deleteHrmPlatformMemberDepartmentsDepartmentId";
import { getHrmPlatformMemberDepartmentsDepartmentId } from "../../../../providers/getHrmPlatformMemberDepartmentsDepartmentId";
import { patchHrmPlatformMemberDepartments } from "../../../../providers/patchHrmPlatformMemberDepartments";
import { postHrmPlatformMemberDepartments } from "../../../../providers/postHrmPlatformMemberDepartments";
import { putHrmPlatformMemberDepartmentsDepartmentId } from "../../../../providers/putHrmPlatformMemberDepartmentsDepartmentId";

@Controller("/hrmPlatform/member/departments")
export class HrmplatformMemberDepartmentsController {
  /**
   * Create a new department within the current organization. This operation establishes a functional grouping for organizing employees and structuring the organizational hierarchy.
   *
   * The department name must be unique within the organization. Attempting to create a department with a duplicate name will result in a 409 Conflict error. An optional parent department can be specified to create a one-level hierarchical structure, where the parent department must be a top-level department (cannot itself have a parent).
   *
   * Requires organization management permission (org:manage). The created department is immediately available for employee assignment and appears in the department list. Child departments are automatically cascade-deleted if their parent department is deleted.
   *
   * @param connection
   * @param body Department creation data including name, optional description, and optional parent department reference
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new department in the user's current organization.
   *
   * 1. Extract organization_id from authenticated session context.
   * 2. Validate user has org:manage permission; reject with 403 if not.
   * 3. Validate request body:
   *    - name: required, non-empty string
   *    - description: optional string
   *    - parent_department_id: optional UUID, must reference existing department in same organization
   * 4. Check name uniqueness: query hrm_platform_departments where organization_id = current org AND name = requested name AND deleted_at IS NULL. If exists, reject with 409 Conflict.
   * 5. Validate hierarchy constraint: if parent_department_id provided, query parent department and verify its parent_department_id IS NULL (one-level nesting only). If parent has its own parent, reject with 400 Bad Request.
   * 6. Insert new record into hrm_platform_departments with generated UUID, current timestamps for created_at/updated_at, null deleted_at.
   * 7. Return created department object.
   * 8. Record activity log entry: action_type='department.created', target_entity='hrm_platform_departments', details include department name and ID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformDepartment.ICreate,
  ): Promise<IHrmPlatformDepartment> {
    try {
      return await postHrmPlatformMemberDepartments({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of departments within the current organization.
   *
   * This operation provides access to all departments in the organization, displaying the hierarchical structure with parent-child relationships. All employees in the organization can view the department list regardless of their role permissions.
   *
   * Supports filtering by department name, description, and parent department assignment. Results include department hierarchy information showing which departments are top-level and which are children of a parent department. The list is paginated for efficient data retrieval.
   *
   * Department names are unique within the organization. The hierarchy is limited to one level of nesting (parent departments can have children, but children cannot have their own children).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for department listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_departments table with organization scope filter.
   * Apply search filters on name (partial match), description (partial match), and parent_id (exact match for filtering by parent department).
   * Join with self-reference to include parent department name in response.
   * Apply pagination with cursor-based or offset-based approach.
   * Sort by parent_id (nulls first for top-level departments), then by name alphabetically.
   * Ensure all results belong to the current organization context from user session.
   * Return IPageIHrmPlatformDepartment.ISummary with pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformDepartment.IRequest,
  ): Promise<IPageIHrmPlatformDepartment.ISummary> {
    try {
      return await patchHrmPlatformMemberDepartments({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific department within the organization.
   *
   * This operation returns the complete department record including its name, description, parent department reference for hierarchical structure, and metadata timestamps. The department must belong to the user's current organization context.
   *
   * All employees in the organization can access this endpoint regardless of their role permissions. The response includes the full department entity suitable for display in department management interfaces or employee assignment workflows. Soft-deleted departments are excluded from results.
   *
   * @param connection
   * @param departmentId Unique identifier of the department (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_departments table by primary key id. Filter to exclude soft-deleted records (deleted_at IS NULL). Join with parent department to include parent_department information if parent_department_id is not null. Verify the department belongs to the user's current organization context for data isolation. Return 404 if department not found or belongs to different organization. Include all department fields: id, organization_id, parent_department_id, name, description, created_at, updated_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":departmentId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformDepartment> {
    try {
      return await getHrmPlatformMemberDepartmentsDepartmentId({
        member,
        departmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing department's attributes within the organization.
   *
   * This operation allows users with organization management permissions to modify department details including name, description, and parent department assignment. The department name must be unique within the organization. When updating the parent department, the system enforces one-level hierarchy constraints: a department can have a parent, but cannot be assigned as a parent if it already has one.
   *
   * The update operation validates that the parent department belongs to the same organization and prevents circular references. All changes are immediately reflected in the department list and employee assignments.
   *
   * @param connection
   * @param departmentId Department identifier (UUID format)
   * @param body Department update fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update department attributes including name, description, and parent department assignment. Query hrm_platform_departments table by departmentId. Validate user has org:manage permission. Verify department belongs to user's current organization. Check name uniqueness within organization (reject if another department has same name). Validate hierarchy constraints: parent department must belong to same organization, cannot assign parent that already has a parent (one-level nesting only), prevent circular references. Update fields: name, description, parent_department_id. Set updated_at timestamp. Return updated department entity. Handle errors: 404 if department not found, 403 if insufficient permissions, 409 if name conflict or hierarchy violation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":departmentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformDepartment.IUpdate,
  ): Promise<IHrmPlatformDepartment> {
    try {
      return await putHrmPlatformMemberDepartmentsDepartmentId({
        member,
        departmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Mark a department as deleted within the organization.
   *
   * This operation performs a soft delete on the department by setting the deleted_at timestamp. Employees assigned to the deleted department have their department assignment set to null. Child departments that had this department as their parent also have their parent assignment set to null, becoming top-level departments.
   *
   * The department record remains in the database but is excluded from normal queries once soft-deleted. This operation requires the org:manage permission.
   *
   * The system records this deletion action in the activity log for audit purposes, including the timestamp, the user who performed the deletion, and the name of the deleted department.
   *
   * @param connection
   * @param departmentId Department identifier (UUID format, scoped to organization)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Delete the department record from hrm_platform_departments table by departmentId.
   *
   * Before deletion, verify the requesting user has org:manage permission for the organization.
   *
   * Update all employees in hrm_platform_employees table that have department_id matching the deleted department, setting department_id to NULL.
   *
   * Update all child departments in hrm_platform_departments table that have parent_department_id matching the deleted department, setting parent_department_id to NULL.
   *
   * Perform the deletion within a database transaction to ensure atomicity.
   *
   * Log the deletion action to hrm_platform_activity_logs with action type 'department.deleted', including the department name and timestamp.
   *
   * Return 204 No Content on successful deletion. Return 403 if user lacks permission. Return 404 if department not found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":departmentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberDepartmentsDepartmentId({
        member,
        departmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
