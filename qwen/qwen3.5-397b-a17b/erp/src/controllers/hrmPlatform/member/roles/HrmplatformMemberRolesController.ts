import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformRole } from "../../../../api/structures/IHrmPlatformRole";
import { IPageIHrmPlatformRole } from "../../../../api/structures/IPageIHrmPlatformRole";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteHrmPlatformMemberRolesRoleId } from "../../../../providers/deleteHrmPlatformMemberRolesRoleId";
import { getHrmPlatformMemberRolesRoleId } from "../../../../providers/getHrmPlatformMemberRolesRoleId";
import { patchHrmPlatformMemberRoles } from "../../../../providers/patchHrmPlatformMemberRoles";
import { postHrmPlatformMemberRoles } from "../../../../providers/postHrmPlatformMemberRoles";
import { putHrmPlatformMemberRolesRoleId } from "../../../../providers/putHrmPlatformMemberRolesRoleId";

@Controller("/hrmPlatform/member/roles")
export class HrmplatformMemberRolesController {
  /**
   * Create a new custom role within an organization.
   *
   * This operation allows organization owners to create custom roles with a specific name, optional description, and a set of permissions. Custom roles provide flexible access control beyond the three built-in roles (Owner, Manager, Employee).
   *
   * The role name must be unique within the organization. Once created, the custom role can be assigned to employees and edited by organization owners. Custom roles can only be deleted when no employees are currently assigned to them.
   *
   * Only users with organization owner privileges can create custom roles. The created role is immediately available for assignment to employees.
   *
   * @param connection
   * @param body Custom role creation data including name, optional description, and permission set
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new custom role in hrm_platform_roles table.
   *
   * 1. Validate user has organization owner permission in the target organization
   * 2. Check no existing role (built-in or custom) has the same name in the organization (unique constraint)
   * 3. Validate permissions array contains only valid permission codes from the nine available permissions
   * 4. Set is_builtin to false for custom roles
   * 5. Generate UUID for id, set created_at and updated_at to current timestamp
   * 6. Insert record with organization_id, name, description, is_builtin=false
   * 7. Return the created role object
   *
   * Edge cases:
   * - Reject if role name already exists in organization (unique constraint violation)
   * - Reject if permissions array contains invalid permission codes
   * - Reject if user lacks org:manage permission
   * - Built-in roles (Owner, Manager, Employee) cannot be created via this endpoint
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformRole.ICreate,
  ): Promise<IHrmPlatformRole> {
    try {
      return await postHrmPlatformMemberRoles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of roles within the current organization.
   *
   * This operation provides search capabilities for viewing roles assigned to employees in the organization. Results include both built-in roles (Owner, Manager, Employee) which are system-defined and cannot be deleted, and custom roles created by organization owners.
   *
   * Users with employee:view permission can view all role assignments. Custom role creation and modification requires employee:manage permission, typically held by organization owners. Built-in roles cannot be deleted but their descriptions may be viewable.
   *
   * Supports filtering by role name (partial match) and builtin status. Response includes role summary information with associated permissions from the role_permissions junction table. Pagination enables efficient browsing of large role collections.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering roles by name, builtin status, and sort order
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_roles table filtered by current organization_id from authentication context. Apply search filters on name (partial match, case-insensitive) and is_builtin boolean. Join with hrm_platform_role_permissions to include permission count in summary. Support pagination with page number and page size parameters. Support sorting by name, created_at, or is_builtin. Exclude soft-deleted roles (deleted_at IS NULL). Return paginated list with total count for client-side pagination UI.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformRole.IRequest,
  ): Promise<IPageIHrmPlatformRole.ISummary> {
    try {
      return await patchHrmPlatformMemberRoles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single role by its unique identifier.
   *
   * This operation returns the complete details of a specific role within the organization, including the role name, description, built-in status, and associated permissions. Built-in roles (Owner, Manager, Employee) are system-defined and cannot be deleted, while custom roles can be created and managed by organization owners.
   *
   * The response includes all role metadata and the set of permissions granted to this role. Permissions are retrieved from the role_permissions junction table and indicate what actions employees assigned to this role can perform within the organization.
   *
   * @param connection
   * @param roleId Unique identifier of the role (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_roles table by roleId UUID. Join with hrm_platform_role_permissions to include associated permissions. Verify the role exists and is not soft-deleted (deleted_at is null). Ensure the role belongs to the user's current organization context for data isolation. Return the complete role entity including id, organization_id, name, description, is_builtin flag, and timestamps. Include permissions array from the junction table relationship. Handle 404 if role not found or belongs to different organization.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":roleId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformRole> {
    try {
      return await getHrmPlatformMemberRolesRoleId({
        member,
        roleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a custom role's name and description within an organization.
   *
   * This operation allows organization owners to modify custom roles they have created. The role name and description can be updated to better reflect the role's purpose or responsibilities. The update is atomic and validates all constraints before applying changes.
   *
   * Built-in roles (Owner, Manager, Employee) cannot be modified through this endpoint. Attempting to update a built-in role will result in a 403 Forbidden error. The new role name must be unique within the organization to satisfy the uniqueness constraint.
   *
   * Only users with organization management permissions can update roles. The response includes the complete updated role object with all fields including timestamps.
   *
   * @param connection
   * @param roleId Role identifier (UUID format)
   * @param body Updated role fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_roles table by roleId UUID. Validate the role exists and is not soft-deleted (deleted_at is null). Check is_builtin flag - if true, reject the request with 403 Forbidden error as built-in roles cannot be modified. Validate the new name is unique within the organization (check @@unique([organization_id, name]) constraint). Update name and description fields. Set updated_at to current timestamp. Return the updated role entity. Handle concurrent update conflicts with optimistic locking if needed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":roleId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformRole.IUpdate,
  ): Promise<IHrmPlatformRole> {
    try {
      return await putHrmPlatformMemberRolesRoleId({
        member,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a custom role from the organization.
   *
   * This operation deletes a custom role that is no longer needed. Built-in roles (Owner, Manager, Employee) cannot be deleted under any circumstances. Custom roles can only be deleted when no employees are currently assigned to them.
   *
   * Before deletion, the system validates that the role exists, is not a built-in role, and has no employee assignments. If employees are assigned to the role, they must be reassigned to a different role before deletion can proceed.
   *
   * Upon successful deletion, the role is permanently removed from the organization. This operation cannot be undone.
   *
   * @param connection
   * @param roleId Role identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Delete a custom role from the organization. First, retrieve the role by ID and verify it exists. Check if is_builtin is true - if so, reject with error (built-in roles cannot be deleted). Query hrm_platform_employees table to check if any employee has role_id matching this role - if employees are assigned, reject with error requiring reassignment first. If validation passes, soft-delete the role by setting deleted_at timestamp. Return 204 No Content on success. Error cases: 404 if role not found, 400 if built-in role, 409 if employees are assigned.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":roleId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberRolesRoleId({
        member,
        roleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
