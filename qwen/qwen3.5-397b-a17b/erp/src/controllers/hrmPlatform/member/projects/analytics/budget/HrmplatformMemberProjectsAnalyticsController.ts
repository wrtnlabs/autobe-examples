import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformProjectBudgetAnalytic } from "../../../../../../api/structures/IHrmPlatformProjectBudgetAnalytic";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberProjectsProjectIdAnalyticsBudget } from "../../../../../../providers/getHrmPlatformMemberProjectsProjectIdAnalyticsBudget";

@Controller("/hrmPlatform/member/projects/:projectId/analytics/budget")
export class HrmplatformMemberProjectsAnalyticsController {
  /**
   * Retrieve budget utilization analytics for a specific project.
   *
   * This endpoint provides real-time budget tracking information by comparing the project's allocated budget hours against the actual hours logged by employees through timelogs. The response includes the budget hours defined on the project, the sum of all time entries recorded against the project, the consumption percentage, and remaining budget hours.
   *
   * The actual hours are calculated by aggregating all timelog durations (duration_minutes field) associated with the project, excluding soft-deleted timelogs. The consumption percentage is computed as (actual_hours / budget_hours) * 100. When budget_hours is null (no budget constraint defined), the percentage and remaining hours fields return null.
   *
   * This operation requires the report:view permission within the organization context. Users with this permission can access budget analytics for any project in their organization. The endpoint is designed for dashboard widgets, budget monitoring reports, and project health visualization components.
   *
   * Related operations include GET /projects/{projectId} for retrieving complete project details and PATCH /projects for searching and filtering projects by various criteria including budget status.
   *
   * @param connection
   * @param projectId Target project's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the hrm_platform_projects table to retrieve the project's budget_hours value. Aggregate timelog durations from hrm_platform_timelogs table filtered by project_id, summing duration_minutes and converting to hours (divide by 60). Calculate budget consumption percentage as (actual_hours / budget_hours) * 100. Handle null budget_hours case by returning null for percentage. Filter timelogs to exclude soft-deleted records. Return project identifier, budget hours, actual hours, consumption percentage, and remaining hours. Ensure organization context validation - verify the requesting user has access to the project's organization. Check report:view permission before allowing access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async budget(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformProjectBudgetAnalytic> {
    try {
      return await getHrmPlatformMemberProjectsProjectIdAnalyticsBudget({
        member,
        projectId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
