import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformTaskHistory } from "../../../../../../api/structures/IHrmPlatformTaskHistory";
import { IPageIHrmPlatformTaskHistory } from "../../../../../../api/structures/IPageIHrmPlatformTaskHistory";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberProjectsProjectIdTasksTaskIdHistoriesHistoryId } from "../../../../../../providers/getHrmPlatformMemberProjectsProjectIdTasksTaskIdHistoriesHistoryId";
import { patchHrmPlatformMemberProjectsProjectIdTasksTaskIdHistories } from "../../../../../../providers/patchHrmPlatformMemberProjectsProjectIdTasksTaskIdHistories";

@Controller("/hrmPlatform/member/projects/:projectId/tasks/:taskId/histories")
export class HrmplatformMemberProjectsTasksHistoriesController {
  /**
   * Retrieve paginated task history entries for a specific task.
   *
   * Returns an immutable audit trail of all status changes for the task, including timestamps, old/new status values, and the member who made each change. History entries are ordered chronologically with newest first by default.
   *
   * Access is restricted to users with project:view permission who are members of the project. The projectId in the path is used for authorization scope verification.
   *
   * @param connection
   * @param projectId Project ID (UUID format) for authorization scope verification.
   * @param taskId Task ID (UUID format) to retrieve history for.
   * @param body Search criteria including optional date range filters, status filters, member filter, pagination cursor, and sort options.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_task_histories table filtered
     *   by hrm_platform_task_id matching the taskId parameter.
   *
   * Verify authorization: user must have project:view or project:manage permission and be assigned to the project (via hrm_platform_project_members).
   *
   * Apply optional filters: date range on created_at, old_status, new_status, hrm_platform_member_id.
   *
   * Support sorting by created_at (asc/desc), default desc (newest first).
   *
   * Implement cursor-based pagination using created_at and id as cursor keys.
   *
   * Join with hrm_platform_members to include member display name in summary response.
   *
   * Return IPageIHrmPlatformTaskHistory.ISummary with pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformTaskHistory.IRequest,
  ): Promise<IPageIHrmPlatformTaskHistory.ISummary> {
    try {
      return await patchHrmPlatformMemberProjectsProjectIdTasksTaskIdHistories({
        member,
        projectId,
        taskId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single task history entry by its unique identifier.
   *
   * This endpoint provides access to the immutable audit trail for a specific task status change. Task history entries capture who made the status transition, when it occurred, and what the status changed from and to. This enables transparency into task workflow progression and accountability for status changes.
   *
   * The response includes the old status, new status, timestamp of the change, and details about the member who performed the action. History entries are append-only and cannot be modified or deleted, ensuring complete audit trail integrity.
   *
   * @param connection
   * @param projectId UUID of the parent project (scoped to organization).
   * @param taskId UUID of the task whose history is being retrieved (scoped to project).
   * @param historyId UUID of the task history entry to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_task_histories table by
     *   historyId. Validate that the history entry belongs to the specified
     *   taskId and that the task belongs to the specified projectId for access
     *   control. Join with hrm_platform_members to include member information
     *   (display name, email) for the user who made the change. Return 404 if
     *   history entry not found or if user lacks permission to view the task.
     *   Ensure organization context isolation by verifying all entities belong
     *   to the same organization.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":historyId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedParam("historyId")
    historyId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformTaskHistory> {
    try {
      return await getHrmPlatformMemberProjectsProjectIdTasksTaskIdHistoriesHistoryId(
        {
          member,
          projectId,
          taskId,
          historyId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
