  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformTaskHistory.IRequest,
  ): Promise<IPageIHrmPlatformTaskHistory.ISummary> {
    try {
      return await patchHrmPlatformMemberProjectsProjectIdTasksTaskIdHistories({
        member,
        projectId,
        taskId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific task history entry by its unique identifier.
   *
   * This operation returns detailed information about a single task status change event, including the timestamp of the change, the previous status, the new status, and the member who made the change. Task history entries are automatically generated by the system whenever a task's status transitions between states (open, in-progress, completed, closed).
   *
   * The endpoint requires the project ID and task ID in the path to enforce proper authorization scoping and ensure the history entry belongs to a task within the specified project. This provides an additional layer of access control beyond the history ID alone.
   *
   * Task history entries are immutable audit trail records that cannot be modified or deleted once created, preserving a complete and accurate record of task progression for compliance and accountability purposes.
   *
   * @param connection
   * @param projectId Project UUID (scoped to organization)
   * @param taskId Task UUID (scoped to project)
   * @param historyId Task history entry UUID (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_task_histories table by primary key (id = historyId).
   *
   * Validate that the history entry's hrm_platform_task_id matches the provided taskId parameter.
   *
   * Validate that the task's hrm_platform_project_id matches the provided projectId parameter.
   *
   * Join with hrm_platform_members to include member information (display name, email) in the response.
   *
   * Join with hrm_platform_tasks to verify task existence and project association.
   *
   * Return 404 if history entry not found, or if taskId/projectId do not match the history's associations.
   *
   * Enforce organization context: verify the project belongs to the user's current organization.
   *
   * Check user has project:view or project:manage permission to access task history.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
