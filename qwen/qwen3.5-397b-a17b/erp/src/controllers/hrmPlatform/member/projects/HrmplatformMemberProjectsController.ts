  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformProject> {
    try {
      return await getHrmPlatformMemberProjectsProjectId({
        member,
        projectId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing project's attributes within the organization. This operation allows users with project:manage permission to modify project details including name, description, color code, status, budget hours, and timeline dates.
   *
   * The endpoint supports partial updates where only provided fields are modified. All fields are optional in the request body, but name and color_code must have been set during creation. Status transitions between active, archived, and completed states are permitted.
   *
   * When updating status to archived or completed, the system enforces business rules that prevent new timelogs from being added to the project. Existing timelogs and tasks remain preserved and viewable. The updated_at timestamp is automatically refreshed on each modification.
   *
   * Project modification events are broadcast to all project members, project leads, and users with project management permissions when budget hours, start date, or end date fields are changed.
   *
   * @param connection
   * @param projectId Project identifier (UUID format)
   * @param body Project update fields. All fields are optional; only provided fields will be updated.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update an existing project in the hrm_platform_projects table. Validate that the requesting user has project:manage permission within the organization. Verify the project exists and is not soft-deleted. Validate organization_id matches the user's current organization context. Update only the provided fields: name (required, non-empty), description (optional), color_code (required, hex format), status (enum: active/archived/completed), budget_hours (optional, positive number or null), start_date (optional, ISO datetime), end_date (optional, ISO datetime). Validate that if status changes to archived or completed, business rules are enforced. Update the updated_at timestamp. Return the complete updated project entity. Throw 404 if project not found, 403 if insufficient permissions, 400 if validation fails.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":projectId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformProject.IUpdate,
  ): Promise<IHrmPlatformProject> {
    try {
      return await putHrmPlatformMemberProjectsProjectId({
        member,
        projectId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a project from the organization by marking it as deleted.
   *
   * This operation soft deletes a project and all its associated tasks and project memberships by setting their deleted_at timestamps. Deletion is only permitted when the project has no timelogs associated with it, ensuring historical time tracking data is preserved. Projects with existing timelogs must be archived or completed instead of deleted.
   *
   * Requires project:manage permission. When a project is deleted, all tasks within the project are marked as deleted, and all project member assignments for that project are revoked. The deletion action is recorded in the activity log with timestamp and user information.
   *
   * The project and its associated data are hidden from normal queries once deleted. Organization administrators may have capabilities to restore soft-deleted projects through separate recovery operations.
   *
   * @param connection
   * @param projectId Project UUID to delete (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Delete project by UUID from hrm_platform_projects table.
   *
   * Validation requirements:
   * 1. Verify project:manage permission for the requesting user
   * 2. Verify project exists and is not already deleted (deleted_at is null)
   * 3. Verify project belongs to the user's current organization
   * 4. Query hrm_platform_timelogs to check if any timelogs exist for this project_id
   * 5. If timelogs exist, reject with 409 Conflict error - project cannot be deleted
   *
   * Deletion logic:
   * 1. Begin database transaction
   * 2. Delete all hrm_platform_tasks where project_id matches (cascade)
   * 3. Delete all hrm_platform_project_members where project_id matches (cascade)
   * 4. Set deleted_at timestamp on hrm_platform_projects record
   * 5. Create activity log entry recording the deletion action
   * 6. Commit transaction
   *
   * Edge cases:
   * - Project with timelogs: reject with clear error message
   * - Project not found: return 404
   * - Insufficient permission: return 403
   * - Project already deleted: return 404
   *
   * All cascading deletions (tasks, project memberships) happen automatically via database foreign key constraints with onDelete: Cascade.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":projectId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberProjectsProjectId({
        member,
        projectId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
