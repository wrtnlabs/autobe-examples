import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformProject } from "../../../../api/structures/IHrmPlatformProject";
import { IPageIHrmPlatformProject } from "../../../../api/structures/IPageIHrmPlatformProject";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteHrmPlatformMemberProjectsProjectId } from "../../../../providers/deleteHrmPlatformMemberProjectsProjectId";
import { getHrmPlatformMemberProjectsProjectId } from "../../../../providers/getHrmPlatformMemberProjectsProjectId";
import { patchHrmPlatformMemberProjects } from "../../../../providers/patchHrmPlatformMemberProjects";
import { postHrmPlatformMemberProjects } from "../../../../providers/postHrmPlatformMemberProjects";
import { putHrmPlatformMemberProjectsProjectId } from "../../../../providers/putHrmPlatformMemberProjectsProjectId";

@Controller("/hrmPlatform/member/projects")
export class HrmplatformMemberProjectsController {
  /**
   * Create a new project within the organization.
   *
   * This operation creates a new project with the specified name, color, and optional details. The project is automatically set to 'active' status upon creation, making it immediately available for task assignment and time tracking. The creating user must have project:manage permission in the current organization context.
   *
   * Required fields include the project name for identification and a hex color code for UI visual distinction. Optional fields allow specifying budget hours for capacity planning, start and end dates for timeline tracking, and a description for additional context.
   *
   * @param connection
   * @param body Project creation data including required name and color code, with optional description, budget hours, and timeline dates.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Validate request body: name (required, non-empty
     *   string), color (required, valid hex color format), description
     *   (optional string), budget_hours (optional positive number), start_date
     *   (optional datetime), end_date (optional datetime).
   *
   * Verify user has project:manage permission in current organization context.
   *
   * Insert new record into hrm_platform_projects table with:
   * - id: generate UUID
   * - organization_id: from authenticated session context
   * - name, color, description, budget_hours, start_date, end_date: from request body
   * - status: 'active' (auto-set)
   * - created_at, updated_at: current timestamp
   * - deleted_at: null
   *
   * Return the complete created project entity including generated id and timestamps.
   *
   * Error handling: return 403 if insufficient permissions, 400 if validation fails (missing required fields, invalid color format, negative budget_hours, end_date before start_date).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformProject.ICreate,
  ): Promise<IHrmPlatformProject> {
    try {
      return await postHrmPlatformMemberProjects({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of projects within the current organization context.
   *
   * This endpoint supports filtering projects by status (active, archived, completed) and text search by project name. Results are paginated using cursor-based pagination for efficient handling of large project lists.
   *
   * All projects returned belong to the currently selected organization. Users must have project:view permission to access this endpoint. The response includes project summary information optimized for list displays, including name, color code, status, and budget hours.
   *
   * @param connection
   * @param body Search criteria including status filter, text search query, and pagination parameters for browsing projects within the organization.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_projects table filtered by
     *   organization_id from the current session context. Apply status filter
     *   if provided (active, archived, completed). Apply text search on name
     *   field using gin_trgm_ops index if search query provided. Implement
     *   cursor-based pagination using created_at timestamp. Join with
     *   hrm_platform_organization_memberships to verify user has project:view
     *   permission through their role. Return IPageIHrmPlatformProject.ISummary
     *   with projects sorted by created_at descending. Handle edge case:
     *   organization has no projects (return empty page).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformProject.IRequest,
  ): Promise<IPageIHrmPlatformProject.ISummary> {
    try {
      return await patchHrmPlatformMemberProjects({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single project by its unique identifier.
   *
   * Returns the complete project record including all attributes: name, description, color code, status, budget hours, start date, end date, and timestamps. This endpoint is used when users need to view detailed information about a specific project.
   *
   * Users with project:view permission can access any project within their organization. The operation enforces multi-tenancy by ensuring the project belongs to the user's current organization context.
   *
   * Returns 404 if the project does not exist, has been deleted, or belongs to a different organization.
   *
   * @param connection
   * @param projectId Unique identifier of the project to retrieve (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_projects table by primary key
     *   id (UUID).
   *
   * Implementation steps:
   * 1. Validate projectId is a valid UUID format
   * 2. Query project where id = projectId AND deleted_at IS NULL
   * 3. Verify the project's organization_id matches the user's current organization context (multi-tenancy enforcement)
   * 4. Check user has project:view permission for the organization
   * 5. Return full project entity including all fields
   *
   * Edge cases:
   * - Return 404 if project not found or deleted_at is not null
   * - Return 403 if user lacks project:view permission
   * - Return 404 if project belongs to different organization (do not reveal existence)
   *
   * No joins required - returns single table data. Do not include related tasks, project members, or timelogs in this response (those have separate endpoints).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":projectId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformProject> {
    try {
      return await getHrmPlatformMemberProjectsProjectId({
        member,
        projectId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates an existing project's details within the organization.
   *
   * This operation allows users with project:manage permission to modify project attributes including name, description, color code, status, budget hours, and timeline dates. The project must exist and belong to an organization where the user has management permissions.
   *
   * Status changes follow business rules: transitioning a project to archived or completed status prevents new timelogs from being recorded against it. Existing timelogs are preserved regardless of status changes. Projects with existing timelogs cannot be reactivated from archived or completed status.
   *
   * The operation validates that required fields (name, color) are provided and properly formatted. Optional fields (description, budget_hours, start_date, end_date) can be updated or cleared by passing null values.
   *
   * @param connection
   * @param projectId Unique identifier of the project to update (UUID format).
   * @param body Project update data including name, description, color code, status, budget hours, and timeline dates. Required fields must be provided; optional fields can be null to clear values.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Update an existing project in the
     *   hrm_platform_projects table. Query by projectId UUID. Validate user has
     *   project:manage permission in the project's organization. Allow updates
     *   to: name (required, non-empty), description (optional), color
     *   (required, valid hex format), status (active/archived/completed),
     *   budget_hours (optional, positive number), start_date (optional),
     *   end_date (optional). Validate status transitions: archived/completed
     *   projects cannot be set back to active if they have timelogs. Update the
     *   updated_at timestamp. Return the full updated project entity. Reject if
     *   project not found or user lacks permission.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":projectId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformProject.IUpdate,
  ): Promise<IHrmPlatformProject> {
    try {
      return await putHrmPlatformMemberProjectsProjectId({
        member,
        projectId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a project from the organization.
   *
   * This operation removes a project and all its associated data including tasks and task histories. Deletion is permanent and cannot be undone.
   *
   * **Authorization**: Requires `project:manage` permission in the current organization context.
   *
   * **Blocking Conditions**: The deletion request is rejected if:
   * - The project has one or more project members assigned (section 92)
   * - The project has one or more timelogs recorded against it (section 160)
   *
   * **Cascade Behavior**: When a project is successfully deleted, all child tasks and task history records are permanently removed. The project itself is permanently deleted from the organization.
   *
   * **Error Handling**: Returns 400 Bad Request if blocking conditions exist, with indication that project members must be removed or timelogs must be deleted/reassigned first.
   *
   * @param connection
   * @param projectId Unique identifier of the project to delete (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Delete a project by UUID after validating
     *   blocking conditions.
   *
   * **Implementation Steps**:
   * 1. Retrieve project by projectId from hrm_platform_projects table
   * 2. Verify project exists and is not already deleted (deleted_at is null)
   * 3. Check for existing project members: query hrm_platform_project_members where project_id = projectId. If count > 0, reject with 400 error.
   * 4. Check for existing timelogs: query hrm_platform_timelogs where project_id = projectId. If count > 0, reject with 400 error.
   * 5. Verify caller has project:manage permission in the project's organization context.
   * 6. Perform hard delete: DELETE FROM hrm_platform_projects WHERE id = projectId (cascade deletes tasks and task_histories via foreign key constraints).
   * 7. Log the deletion action to hrm_platform_activity_logs with action type 'project.deleted'.
   * 8. Return 204 No Content on success.
   *
   * **Edge Cases**:
   * - Project not found: return 404
   * - Project already deleted: return 404
   * - Has project members: return 400 with message "Project has assigned members. Remove all members before deletion."
   * - Has timelogs: return 400 with message "Project has recorded timelogs. Timelogs must be removed or reassigned before deletion."
   * - Insufficient permission: return 403
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":projectId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberProjectsProjectId({
        member,
        projectId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
