  /**
   * Remove an employee from a project by deleting their project membership assignment.
   *
   * This operation revokes the employee's access to the project immediately. The employee can no longer view project details, create timelogs for the project, or access tasks within the project. Historical timelogs associated with the removed member are preserved in the system and remain accessible to the employee.
   *
   * The operation requires project:manage permission in the organization. Both the project and employee must belong to the same organization. The membership is identified by the composite key of project ID and employee ID.
   *
   * This is a permanent deletion that cannot be undone. The employee can be reassigned to the project through a new assignment operation if needed.
   *
   * @param connection
   * @param projectId UUID of the project to remove the member from (scoped to organization).
   * @param employeeId UUID of the employee to remove from the project (scoped to organization).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Delete a project member assignment by removing the record from hrm_platform_project_members table.
   *
   * 1. Verify the requesting user has project:manage permission in the organization.
   * 2. Validate projectId exists and belongs to the user's current organization (check deleted_at is null).
   * 3. Validate employeeId exists and belongs to the same organization.
   * 4. Query hrm_platform_project_members where hrm_platform_project_id = projectId AND hrm_platform_employee_id = employeeId.
   * 5. If no record found, return 404 Not Found.
   * 6. Delete the membership record (hard delete, not soft delete).
   * 7. Return 204 No Content on success.
   *
   * Edge cases:
   * - Project not found or already deleted: 404
   * - Employee not found in organization: 404
   * - Membership record not found: 404
   * - User lacks project:manage permission: 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
