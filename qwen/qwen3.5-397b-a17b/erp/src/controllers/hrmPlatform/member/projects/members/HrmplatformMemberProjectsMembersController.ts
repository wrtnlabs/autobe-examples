  /**
   * Assign an employee to a project as a project member with a designated role.
   *
   * This operation creates a new project membership record, granting the specified employee access to the project. The assigned role determines the employee's capabilities within the project: 'member' role allows viewing tasks and logging time, while 'project-lead' role additionally enables task management operations such as creating and editing tasks.
   *
   * The employee must be active and belong to the same organization as the project. Each employee can be assigned to multiple projects simultaneously, but duplicate assignments to the same project are prevented. The system enforces a unique constraint on the combination of project and employee to ensure each membership is unique.
   *
   * Project membership is a prerequisite for time logging against the project and for task assignment within the project. Only employees with active project membership can create timelogs for that project or be assigned tasks within it.
   *
   * @param connection
   * @param projectId UUID of the project to assign the employee to (scoped to organization).
   * @param body Project membership assignment details including the employee to assign and their role within the project.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new project membership record in hrm_platform_project_members table.
   *
   * Validate that the requesting user has project:manage permission in the organization owning the project.
   *
   * Validate that the project exists and is not soft-deleted.
   *
   * Validate that the employee exists, is active (status='active'), and belongs to the same organization as the project.
   *
   * Check unique constraint: verify no existing membership record with the same hrm_platform_project_id and hrm_platform_employee_id combination. Return conflict error if duplicate assignment exists.
   *
   * Validate role value is either 'member' or 'project-lead'.
   *
   * Insert new record with: hrm_platform_project_id from path, hrm_platform_employee_id from request body, role from request body, generated UUID for id, current timestamp for created_at and updated_at.
   *
   * Return the created project membership record with full entity data including the generated id and timestamps.
   *
   * Edge cases:
   * - Duplicate assignment (same employee already in project) → 409 Conflict
   * - Employee not found or deactivated → 404 Not Found
   * - Project not found → 404 Not Found
   * - Invalid role value → 400 Bad Request
   * - User lacks project:manage permission → 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
