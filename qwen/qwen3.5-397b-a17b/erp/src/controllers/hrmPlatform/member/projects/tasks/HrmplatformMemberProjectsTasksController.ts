  /**
   * Update an existing task within a project.
   *
   * This operation allows project leads or users with project management permission to modify task properties including title, description, status, priority, estimated hours, due date, assigned employee, and parent task relationship. All provided fields are updated while unspecified fields retain their current values.
   *
   * When the task status is changed, a task history entry is automatically created to record the transition including timestamp, old status, new status, and the user who made the change. This audit trail enables tracking of task progression over time.
   *
   * The assigned employee must be a member of the project. Attempts to assign tasks to non-members result in validation errors. Parent task assignment is limited to one level of nesting - subtasks cannot have their own subtasks.
   *
   * Authorization requires either the project-lead role on the containing project or the project:manage permission. Users without these permissions receive access denied errors.
   *
   * @param connection
   * @param projectId The UUID of the parent project containing this task (scoped to organization).
   * @param taskId The UUID of the task to update (scoped to project).
   * @param body Partial update payload containing only the fields to modify. Unspecified fields retain their current values.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Validate user has project:manage permission or is project lead on the specified project.
   *
   * Verify the task exists and belongs to the specified project (hrm_platform_project_id matches projectId).
   *
   * Validate update payload:
   * - If hrm_platform_employee_id is provided, verify the employee is a member of the project via hrm_platform_project_members table
   * - If parent_task_id is provided, verify the parent task belongs to the same project and is not itself a subtask (parent_task_id is null)
   * - Validate status is one of: open, in-progress, completed, closed
   * - Validate priority is one of: low, medium, high, urgent
   * - Validate estimated_hours is positive if provided
   * - Validate due_date is in the future if provided (optional business rule)
   *
   * If status field is being changed:
   * - Query current task status before update
   * - Create hrm_platform_task_histories entry with: task_id, old_status, new_status, changed_by (current user id), created_at (now)
   *
   * Perform UPDATE on hrm_platform_tasks table with provided fields, set updated_at to current timestamp.
   *
   * Return the complete updated task entity including all fields.
   *
   * Handle edge cases:
   * - Task not found: 404 error
   * - Task belongs to different project: 404 or 400 error
   * - Assigned employee not a project member: 400 error with descriptive message
   * - Invalid parent task (not in same project or is subtask): 400 error
   * - Insufficient permissions: 403 error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
