  /**
   * Soft delete a task from a project by marking it as deleted.
   *
   * This operation marks a task as deleted by setting its deleted_at timestamp. The task and its associated data (subtasks, task history) are soft-deleted and hidden from normal queries. Only users with project:manage permission or project leads can perform this operation.
   *
   * When a task is soft-deleted, all child subtasks are also soft-deleted recursively. Task history entries for the deleted task are preserved for audit purposes. This operation does not affect timelogs that may reference the task - those timelogs remain preserved with their task reference intact.
   *
   * The task deletion is recorded in the activity log with the timestamp and the user who performed the deletion. Soft-deleted tasks can potentially be restored by clearing the deleted_at timestamp (if such functionality is provided).
   *
   * @param connection
   * @param projectId Project ID (scoped to organization)
   * @param taskId Task ID to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Delete a task permanently from the project.
   *
   * 1. Verify user has project:manage permission or is a project lead for this project
   * 2. Verify the task exists and belongs to the specified project
   * 3. Verify the task is not soft-deleted already
   * 4. Delete all subtasks recursively (children of this task)
   * 5. Delete all task history entries for this task
   * 6. Delete the task record
   * 7. Record the deletion in activity log with action type 'task.deleted'
   * 8. Return null response
   *
   * Edge cases:
   * - Task with subtasks: delete all subtasks first (cascade)
   * - Task with task history: delete history entries (cascade)
   * - Timelogs referencing task: preserve timelogs, task reference remains but task is gone
   * - User without permission: reject with 403 Forbidden
   * - Task not found: reject with 404 Not Found
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":taskId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberProjectsProjectIdTasksTaskId({
        member,
        projectId,
        taskId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
