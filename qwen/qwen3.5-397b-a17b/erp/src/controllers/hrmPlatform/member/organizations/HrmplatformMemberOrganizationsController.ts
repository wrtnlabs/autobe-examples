import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformOrganization } from "../../../../api/structures/IHrmPlatformOrganization";
import { IPageIHrmPlatformOrganization } from "../../../../api/structures/IPageIHrmPlatformOrganization";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteHrmPlatformMemberOrganizationsOrganizationId } from "../../../../providers/deleteHrmPlatformMemberOrganizationsOrganizationId";
import { getHrmPlatformMemberOrganizationsOrganizationId } from "../../../../providers/getHrmPlatformMemberOrganizationsOrganizationId";
import { patchHrmPlatformMemberOrganizations } from "../../../../providers/patchHrmPlatformMemberOrganizations";
import { postHrmPlatformMemberOrganizations } from "../../../../providers/postHrmPlatformMemberOrganizations";
import { putHrmPlatformMemberOrganizationsOrganizationId } from "../../../../providers/putHrmPlatformMemberOrganizationsOrganizationId";

@Controller("/hrmPlatform/member/organizations")
export class HrmplatformMemberOrganizationsController {
  /**
   * Create a new organization in the multi-tenancy platform.
   *
   * This operation establishes a new independent business unit that operates separately from all other organizations on the platform. The organization serves as the foundational container for all subsequent business entities including employees, projects, tasks, timelogs, timesheets, departments, and roles.
   *
   * Upon creation, the organization is automatically associated with the creating user as the owner. The owner receives full access to all organization features including role management, employee management, and organization settings configuration.
   *
   * All data within the organization is strictly isolated from other organizations. Employees belonging to this organization cannot access or view data from any other organization on the platform.
   *
   * @param connection
   * @param body Organization creation data including the display name, optional description, currency code for financial tracking, timezone for date/time operations, and fiscal year start month for accounting periods.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Insert a new record into the
     *   hrm_platform_organizations table with the provided data.
   *
   * Generate a UUID for the id field. Set created_at and updated_at to the current timestamp. Set deleted_at to null. Validate that name is unique across all organizations. Validate that currency is a valid ISO 4217 3-letter code. Validate that timezone is a valid IANA timezone identifier. Validate that fiscal_start_month is between 1 and 12.
   *
   * After successful insertion, automatically create the organization membership linking the authenticated user to the new organization. Assign the Owner built-in role to the user within this organization context.
   *
   * Return the complete organization entity including all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformOrganization.ICreate,
  ): Promise<IHrmPlatformOrganization> {
    try {
      return await postHrmPlatformMemberOrganizations({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of organizations with search and filtering capabilities.
   *
   * This endpoint allows members to search and browse organizations they have access to. Results are filtered based on the authenticated user's organization memberships and the provided search criteria. The endpoint supports text search by organization name, pagination with cursor-based navigation, and sorting options.
   *
   * Organizations are the foundational multi-tenancy boundary in the platform. Each organization operates independently with its own employees, projects, departments, roles, and data. Users can belong to multiple organizations and this endpoint returns all organizations the user is a member of.
   *
   * @param connection
   * @param body Search criteria for filtering organizations including name search text, pagination parameters, and sorting options.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_organizations table joined
     *   with hrm_platform_organization_memberships to filter organizations the
     *   authenticated user belongs to. Apply name search filter using
     *   case-insensitive partial matching on the name column. Support
     *   pagination with take/limit and skip/cursor parameters. Allow sorting by
     *   name, created_at, or updated_at in ascending or descending order.
     *   Exclude soft-deleted organizations (deleted_at IS NOT NULL). Return
     *   IHrmPlatformOrganization.ISummary for each organization containing id,
     *   name, description, logo_url, currency, timezone, and created_at. Wrap
     *   results in IPageIHrmPlatformOrganization.ISummary with pagination
     *   metadata including total count and cursor information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformOrganization.IRequest,
  ): Promise<IPageIHrmPlatformOrganization.ISummary> {
    try {
      return await patchHrmPlatformMemberOrganizations({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information for a specific organization by its unique identifier.
   *
   * This endpoint returns the complete organization record including all configuration settings such as name, description, logo URL, currency, timezone, and fiscal start month. The organization is the foundational isolation boundary in the multi-tenancy platform, and this operation provides access to organization-level settings.
   *
   * The operation enforces strict organization context validation. Users can only access organizations they belong to through their membership records. Attempting to access an organization without proper membership results in authorization failure.
   *
   * Organization settings include business configuration for financial tracking (currency), date/time operations (timezone), and accounting periods (fiscal start month). The logo URL provides branding for the organization interface.
   *
   * @param connection
   * @param organizationId Unique identifier of the organization to retrieve (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_organizations table by UUID
     *   primary key.
   *
   * Validate that the requesting user has membership in the target organization through hrm_platform_organization_memberships junction table.
   *
   * Return full organization entity including: id, name, description, logo_url, currency, timezone, fiscal_start_month, created_at, updated_at.
   *
   * Exclude deleted_at from response for active organizations.
   *
   * Handle 404 for non-existent organization IDs.
   *
   * Handle 403 for users without organization membership.
   *
   * Ensure soft-deleted organizations (deleted_at IS NOT NULL) are not accessible.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":organizationId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformOrganization> {
    try {
      return await getHrmPlatformMemberOrganizationsOrganizationId({
        member,
        organizationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update organization settings including name, description, logo, currency, timezone, and fiscal year configuration.
   *
   * This endpoint allows organization owners and users with org:manage permission to modify organization configuration. All changes are immediately applied and affect all users within the organization. The currency setting impacts financial reporting and pay rate displays. The timezone setting ensures consistent date/time interpretation across timesheets, timelogs, and deadlines. The fiscal start month determines accounting period boundaries for financial reports.
   *
   * Organization settings are shared across all members. Changes to organization name or logo will be visible to all users in subsequent sessions. The logo_url accepts standard image formats (PNG, JPG, SVG) as a publicly accessible URL.
   *
   * Only users with the org:manage permission can perform this operation. By default, this includes users with the Owner role. Custom roles must be explicitly granted the org:manage permission to update organization settings.
   *
   * @param connection
   * @param organizationId Unique identifier of the organization to update (UUID format, scoped to organizations the user belongs to).
   * @param body Organization settings to update including name, description, logo URL, currency code, timezone, and fiscal year start month. All fields are optional - only provided fields will be updated.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Update organization settings for the specified
     *   organization ID. Query hrm_platform_organizations table by
     *   organizationId. Validate that the requesting user belongs to this
     *   organization and has org:manage permission. Update allowed fields:
     *   name, description, logo_url, currency, timezone, fiscal_start_month.
     *   Validate currency is valid ISO 4217 code (3 letters). Validate timezone
     *   is valid IANA timezone identifier. Validate fiscal_start_month is
     *   between 1-12. Validate name is not empty. Set updated_at timestamp to
     *   current time. Return the updated organization entity. Reject with 403
     *   if user lacks permission. Reject with 404 if organization not found or
     *   user doesn't belong to it. Reject with 400 if validation fails on any
     *   field.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":organizationId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformOrganization.IUpdate,
  ): Promise<IHrmPlatformOrganization> {
    try {
      return await putHrmPlatformMemberOrganizationsOrganizationId({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete an organization and all its associated data.
   *
   * This endpoint allows organization owners to delete their organization. The operation enforces strict preconditions: the requesting user must be the organization owner, all timesheets must be resolved (approved or rejected status), and no employees can be assigned to the organization.
   *
   * When an organization is deleted, the system permanently removes all associated domain data including employees, projects, tasks, timelogs, and timesheets. This deletion is irreversible with no recovery option. The organization owner's user account remains active but is disassociated from the deleted organization. If the owner belongs to other organizations, access to those organizations is preserved.
   *
   * The operation validates deletion eligibility before proceeding. If pending timesheets exist or employees are assigned, the request is rejected with an appropriate error message indicating the blocking condition.
   *
   * @param connection
   * @param organizationId Organization identifier (UUID format, global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Delete organization with cascade deletion of all
     *   related domain data.
   *
   * 1. Authorization: Verify requesting user is the organization owner (has Owner role in this organization).
   *
   * 2. Precondition Validation:
   *    - Query hrm_platform_timesheets for the organization's employees where status is 'draft' or 'submitted'. If any exist, reject with 400 error indicating unresolved timesheets.
   *    - Query hrm_platform_employees where organization_id matches and status is 'active'. If any exist, reject with 400 error indicating employees must be removed first.
   *
   * 3. Cascade Deletion (within transaction):
   *    - Delete all hrm_platform_employee_contracts records for organization's employees
   *    - Delete all hrm_platform_project_members records for organization's projects
   *    - Delete all hrm_platform_task_histories records for organization's tasks
   *    - Delete all hrm_platform_timelogs records for organization's projects
   *    - Delete all hrm_platform_timesheets records for organization's employees
   *    - Delete all hrm_platform_tasks records for organization's projects
   *    - Delete all hrm_platform_project_members records
   *    - Delete all hrm_platform_projects records for the organization
   *    - Delete all hrm_platform_employee_invitations records for the organization
   *    - Delete all hrm_platform_employees records for the organization
   *    - Delete all hrm_platform_department records for the organization
   *    - Delete all hrm_platform_role_permissions records for organization's roles
   *    - Delete all hrm_platform_roles records for the organization
   *    - Delete all hrm_platform_organization_memberships records for this organization
   *    - Set hrm_platform_organizations.deleted_at to current timestamp (soft delete marker)
   *
   * 4. Response: Return 204 No Content on success.
   *
   * 5. Error Handling:
   *    - 403 Forbidden: User is not organization owner
   *    - 400 Bad Request: Unresolved timesheets or active employees exist
   *    - 404 Not Found: Organization does not exist or already deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":organizationId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberOrganizationsOrganizationId({
        member,
        organizationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
