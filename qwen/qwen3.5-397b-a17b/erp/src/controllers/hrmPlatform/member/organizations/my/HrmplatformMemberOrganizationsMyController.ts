import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformOrganization } from "../../../../../api/structures/IHrmPlatformOrganization";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberOrganizationsMy } from "../../../../../providers/getHrmPlatformMemberOrganizationsMy";

@Controller("/hrmPlatform/member/organizations/my")
export class HrmplatformMemberOrganizationsMyController {
  /**
   * Retrieve the currently selected organization context for the authenticated member.
   *
   * This endpoint returns the complete organization details that the user is currently working within. All subsequent API operations are scoped to this organization context, ensuring strict data isolation in the multi-tenant platform.
   *
   * The response includes organization configuration such as name, description, logo image, currency code, timezone, and fiscal year start month. This information is essential for the UI to display organization-specific branding and configure date/time displays according to the organization's settings.
   *
   * Members belonging to multiple organizations must switch organization context to change which organization this endpoint returns. The organization context is maintained throughout the session until explicitly changed or the session ends.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve the currently selected organization for the authenticated member from session context.
   *
   * Query hrm_platform_organizations table using the organization_id stored in the member's active session.
   *
   * Return full organization entity including: id, name, description, logo, currency, timezone, fiscal_start_month, created_at, updated_at.
   *
   * Enforce that the member belongs to this organization by verifying the hrm_platform_employees record exists with matching user_id and organization_id.
   *
   * Return 403 if no organization context is selected or member doesn't belong to the organization.
   *
   * Return 404 if organization not found or is soft-deleted (deleted_at is not null).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmPlatformOrganization> {
    try {
      return await getHrmPlatformMemberOrganizationsMy({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
