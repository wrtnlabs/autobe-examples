import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformTimelog } from "../../../../api/structures/IHrmPlatformTimelog";
import { IHrmPlatformTimer } from "../../../../api/structures/IHrmPlatformTimer";
import { IPageIHrmPlatformTimer } from "../../../../api/structures/IPageIHrmPlatformTimer";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteHrmPlatformMemberTimersTimerId } from "../../../../providers/deleteHrmPlatformMemberTimersTimerId";
import { getHrmPlatformMemberTimersTimerId } from "../../../../providers/getHrmPlatformMemberTimersTimerId";
import { patchHrmPlatformMemberTimers } from "../../../../providers/patchHrmPlatformMemberTimers";
import { patchHrmPlatformMemberTimersTimerIdStop } from "../../../../providers/patchHrmPlatformMemberTimersTimerIdStop";
import { postHrmPlatformMemberTimers } from "../../../../providers/postHrmPlatformMemberTimers";
import { putHrmPlatformMemberTimersTimerId } from "../../../../providers/putHrmPlatformMemberTimersTimerId";

@Controller("/hrmPlatform/member/timers")
export class HrmplatformMemberTimersController {
  /**
   * Create a new timer session for real-time time tracking.
   *
   * This operation initiates a live timer session that allows employees to track work duration in real-time. The employee must select a project they are assigned to, and can optionally specify a task within that project and provide a description of the work being performed.
   *
   * The system enforces that each employee can have at most one active timer at any given time. If the employee already has a running timer, the request will be rejected. The timer records the start timestamp when created and continues running indefinitely until manually stopped or discarded by the employee.
   *
   * While the timer is running, employees can edit the description, change the selected project, or change the task. When stopped, the timer converts to a timelog entry with the calculated duration rounded to the nearest minute. Alternatively, employees can discard the timer without creating any timelog record.
   *
   * This endpoint is accessible only to authenticated member actors who are employees within an organization. The employee_id is automatically derived from the authenticated session context.
   *
   * @param connection
   * @param body Timer creation information including required project and optional task and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new timer record in the hrm_platform_timers table with the following implementation logic:
   *
   * 1. Validate that the authenticated employee exists and is active
   * 2. Check if the employee already has an active timer (stopped_at IS NULL and deleted_at IS NULL)
   * 3. If active timer exists, reject with 409 Conflict error
   * 4. Validate that the provided project_id exists and the employee is assigned to that project (via hrm_platform_project_members)
   * 5. If task_id is provided, validate it exists and belongs to the specified project
   * 6. Create the timer record with:
   *    - employee_id: from authenticated session
   *    - project_id: from request body
   *    - task_id: from request body (nullable)
   *    - started_at: current timestamp
   *    - stopped_at: null
   *    - description: from request body (nullable)
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   *    - deleted_at: null
   * 7. Return the created timer object with full details
   *
   * Transaction scope: Single table insert with validation queries. No complex transaction needed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformTimer.ICreate,
  ): Promise<IHrmPlatformTimer> {
    try {
      return await postHrmPlatformMemberTimers({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of timer records for the authenticated employee.
   *
   * This operation provides search capabilities for timer sessions including filtering by running status (active vs stopped), project association, task assignment, and date ranges. Employees can use this endpoint to view their current running timer as well as historical timer sessions.
   *
   * The endpoint enforces organization data isolation, returning only timers belonging to the authenticated user's employee record within their current organization context. Each employee can have at most one active timer at any time, but may have multiple historical stopped timers.
   *
   * Supports comprehensive pagination with configurable page sizes and sorting options. Response includes timer summary information optimized for list displays, showing start time, project, optional task, description, and current status.
   *
   * Related operations include GET /timers/{timerId} for detailed timer information, PUT /timers/{timerId} for updating a running timer, POST /timers for starting a new timer, and DELETE /timers/{timerId} for discarding a timer without creating a timelog.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for timer list query
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_timers table with pagination and filtering support.
   *
   * Apply search filters on: stopped_at (null for running, not null for stopped), project_id, task_id, started_at date range, description text search.
   *
   * Join with hrm_platform_projects to include project name in summary.
   * Left join with hrm_platform_tasks to include task name when present.
   * Filter by employee_id from authenticated session context.
   * Apply organization isolation through employee's organization_id.
   * Return cursor-based or offset pagination with total count.
   * Sort by started_at descending by default (most recent first).
   *
   * Handle edge case where employee has no timers (return empty array with pagination metadata).
   * Ensure soft-deleted timers (deleted_at not null) are excluded from results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformTimer.IRequest,
  ): Promise<IPageIHrmPlatformTimer.ISummary> {
    try {
      return await patchHrmPlatformMemberTimers({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific timer session by its identifier.
   *
   * This operation returns the complete timer record including the start timestamp when tracking began, the associated project being tracked, the optional task within the project, and the optional description of work being performed. If the timer has been stopped, the stopped_at timestamp is included to enable duration calculation.
   *
   * Only the employee who owns the timer can access this endpoint. The system validates that the requesting employee matches the timer's employee_id field, ensuring strict data isolation between organization members.
   *
   * The response includes all timer attributes necessary for displaying elapsed time calculations in the user interface. Clients can use the started_at timestamp to compute real-time elapsed duration since the timer began.
   *
   * @param connection
   * @param timerId Target timer's unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the hrm_platform_timers table by the provided timerId UUID parameter. Validate that the timer exists and has not been soft deleted (deleted_at is null). Verify that the authenticated employee's ID matches the timer's employee_id field to enforce ownership access control. Return the complete timer record including id, employee_id, project_id, task_id (nullable), started_at, stopped_at (nullable), description (nullable), created_at, and updated_at fields. Join with hrm_platform_projects to include project details if needed for the response DTO. Join with hrm_platform_tasks if task_id is present to include task details. Handle 404 Not Found if timer doesn't exist or employee doesn't have access. Handle 403 Forbidden if timer belongs to a different employee.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":timerId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformTimer> {
    try {
      return await getHrmPlatformMemberTimersTimerId({
        member,
        timerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an active timer's properties during a time tracking session.
   *
   * This operation allows employees to modify their running timer's description, project assignment, and optional task association. Employees can edit these properties independently or together while the timer is actively running. The project must be from the employee's assigned projects, and if a task is specified, it must belong to the selected project.
   *
   * This endpoint supports real-time adjustments to time tracking sessions, enabling employees to correct or refine their timer details as work context changes. The started_at timestamp and employee ownership cannot be modified. Only the timer owner (the employee who started the timer) can perform this update.
   *
   * Related operations include GET /timers/{timerId} for retrieving timer details, POST /timers for starting a new timer, and DELETE /timers/{timerId} for discarding a timer without creating a timelog.
   *
   * @param connection
   * @param timerId Target timer's unique identifier
   * @param body Updatable timer properties for modification
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_timers table by timerId UUID. Verify timer exists and belongs to the authenticated employee (employee_id matches session context). Validate timer is not already stopped (stopped_at is null) - reject if timer is stopped. Validate project_id exists in hrm_platform_projects and employee is assigned to that project via hrm_platform_project_members. If task_id is provided, validate it exists in hrm_platform_tasks and belongs to the selected project (project_id matches). Update description, project_id, and task_id fields atomically. Update updated_at timestamp to current time. Return complete updated timer record. Handle concurrent update conflicts with optimistic locking on updated_at if needed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":timerId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformTimer.IUpdate,
  ): Promise<IHrmPlatformTimer> {
    try {
      return await putHrmPlatformMemberTimersTimerId({
        member,
        timerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Discard a running timer without creating a timelog entry.
   *
   * This operation allows employees to discard their active timer sessions when they started tracking by mistake or no longer need to track time. Discarding a timer permanently removes the timer record without saving any time tracking data.
   *
   * The timer must belong to the requesting employee. Only employees can discard their own timers. This operation implements soft deletion, marking the timer as deleted while preserving audit trail.
   *
   * After discarding, the employee is immediately free to start a new timer. The discard action is irreversible and no record of the tracked time is preserved.
   *
   * Related operations: POST /timers to start a new timer, GET /timers/{timerId} to view timer details before discarding.
   *
   * @param connection
   * @param timerId Target timer's ID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Delete the timer record by setting deleted_at timestamp.
   *
   * 1. Verify timer exists and is not already deleted
   * 2. Verify the timer belongs to the authenticated employee (employee_id matches)
   * 3. Perform soft delete by setting deleted_at to current timestamp
   * 4. Return 204 No Content on success
   *
   * Business rules:
   * - Only the timer owner can discard their timer
   * - Discarding does not create a timelog entry
   * - Operation is irreversible
   * - Frees the employee to start a new timer immediately
   *
   * Edge cases:
   * - Timer not found: return 404
   * - Timer belongs to different employee: return 403
   * - Timer already deleted: return 404
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":timerId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberTimersTimerId({
        member,
        timerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Stop a running timer and automatically create a timelog entry.
   *
   * This endpoint allows employees to stop their active timer session, which triggers automatic timelog creation. The system calculates the work duration by measuring the elapsed time between the timer's start timestamp and the current stop time, then rounds the duration to the nearest minute.
   *
   * The created timelog inherits all tracking context from the timer including the project, optional task, and work description. The billable flag on the timelog defaults to true. After successful execution, the timer's stopped_at field is populated and the timer is no longer considered active.
   *
   * This operation enforces that the timer must exist, must belong to the requesting employee, and must currently be running (stopped_at is null). If the timer was already stopped or does not exist, the request is rejected with an appropriate error response.
   *
   * The single active timer constraint means employees must stop or discard their current timer before starting a new one. This stop operation is the primary pathway for converting live time tracking into permanent timelog records.
   *
   * @param connection
   * @param timerId Target timer's ID (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the hrm_platform_timers table by timerId and verify the timer exists and belongs to the authenticated employee. Check that stopped_at is null to confirm the timer is still running. If any validation fails, return 404 or 400 error.
   *
   * Calculate the duration by computing the difference between current timestamp and started_at, then round to nearest minute (durations under 30 seconds round to 0). Begin a database transaction to ensure atomicity.
   *
   * Create a new record in hrm_platform_timelogs table with: employee_id from timer, project_id from timer, task_id from timer (if present), date extracted from started_at, duration_minutes as calculated, description from timer, billable set to true.
   *
   * Update the timer record by setting stopped_at to current timestamp. Commit the transaction.
   *
   * Return the created timelog object. Log the action to hrm_platform_activity_logs with action type 'timelog_created' and reference to both timer and timelog IDs.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":timerId/stop")
  public async stop(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformTimelog> {
    try {
      return await patchHrmPlatformMemberTimersTimerIdStop({
        member,
        timerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
