import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformTimeReport } from "../../../../../api/structures/IHrmPlatformTimeReport";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchHrmPlatformMemberReportsTime } from "../../../../../providers/patchHrmPlatformMemberReportsTime";

@Controller("/hrmPlatform/member/reports/time")
export class HrmplatformMemberReportsTimeController {
  /**
   * Generate time tracking reports showing total hours logged per employee for a given date range.
   *
   * This endpoint provides aggregated time data for organizational reporting. The report can be grouped by employee, project, or task, and filtered by date range, specific employees, projects, and billable status. Users with report:view permission can access this endpoint to generate time reports for analysis and billing purposes.
   *
   * The report includes breakdown of total hours, billable hours, and non-billable hours. Results are scoped to the current organization context for multi-tenancy data isolation.
   *
   * @param connection
   * @param body Time report search criteria including date range, employee filters, project filters, task filters, billable status filter, and grouping dimension.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_timelogs table with aggregation for time reporting. Apply date range filter on timelog date field. Filter by employee IDs if provided (must be within current organization). Filter by project IDs if provided (must be within current organization). Filter by billable status if specified. Group results by the specified grouping dimension (employee, project, or task). Join with hrm_platform_employees for employee details, hrm_platform_projects for project details, and hrm_platform_tasks for task details when grouping by task. Calculate total duration_minutes, billable duration_minutes, and non-billable duration_minutes for each group. Return aggregated summary records sorted by the grouping dimension. Enforce organization context on all queries for data isolation. Verify user has report:view permission before executing query.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformTimeReport.IRequest,
  ): Promise<IHrmPlatformTimeReport.ISummary> {
    try {
      return await patchHrmPlatformMemberReportsTime({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
