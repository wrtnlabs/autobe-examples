import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformProjectBudgetReport } from "../../../../../api/structures/IHrmPlatformProjectBudgetReport";
import { IPageIHrmPlatformProjectBudgetReport } from "../../../../../api/structures/IPageIHrmPlatformProjectBudgetReport";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchHrmPlatformMemberReportsProjectBudget } from "../../../../../providers/patchHrmPlatformMemberReportsProjectBudget";

@Controller("/hrmPlatform/member/reports/project-budget")
export class HrmplatformMemberReportsProject_budgetController {
  /**
   * Retrieves project budget utilization report showing budgeted hours versus actual hours logged.
   *
   * This report provides insights into project budget consumption by comparing planned budget hours against actual timelog hours. Each project entry shows total budget hours, hours logged, remaining hours, and utilization percentage. Projects without budget hours are excluded from results.
   *
   * The report supports filtering by date range to analyze specific periods, project status to focus on active or archived projects, and billable status to separate client work from internal activities. Results are paginated for efficient data retrieval.
   *
   * @param connection
   * @param body Search criteria for project budget report including date range, project filters, status filter, and billable flag filter.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_projects table joined with
     *   hrm_platform_timelogs for actual hours calculation.
   *
   * Filter projects where budget_hours IS NOT NULL (exclude projects without budget).
   * Calculate actual hours by SUM(duration_minutes) / 60 from timelogs within date range.
   * Join conditions: project.id = timelog.hrm_platform_project_id AND timelog.deleted_at IS NULL.
   *
   * Apply filters:
   * - date_from: timelog.date >= date_from (inclusive)
   * - date_to: timelog.date <= date_to (inclusive)
   * - project_id: filter specific projects if provided
   * - status: filter by project status (active, archived, completed)
   * - billable: filter timelogs by billable flag if provided
   *
   * Group by project and calculate:
   * - budget_hours: from project.budget_hours
   * - actual_hours: SUM(timelog.duration_minutes) / 60
   * - remaining_hours: budget_hours - actual_hours
   * - utilization_percentage: (actual_hours / budget_hours) * 100
   *
   * Return paginated results sorted by utilization percentage descending (highest utilization first).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformProjectBudgetReport.IRequest,
  ): Promise<IPageIHrmPlatformProjectBudgetReport.ISummary> {
    try {
      return await patchHrmPlatformMemberReportsProjectBudget({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
