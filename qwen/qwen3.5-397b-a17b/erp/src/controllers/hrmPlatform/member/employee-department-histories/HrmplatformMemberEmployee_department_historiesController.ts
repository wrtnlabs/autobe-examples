import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformEmployeeDepartmentHistory } from "../../../../api/structures/IHrmPlatformEmployeeDepartmentHistory";
import { IPageIHrmPlatformEmployeeDepartmentHistory } from "../../../../api/structures/IPageIHrmPlatformEmployeeDepartmentHistory";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberEmployeeDepartmentHistoriesHistoryId } from "../../../../providers/getHrmPlatformMemberEmployeeDepartmentHistoriesHistoryId";
import { patchHrmPlatformMemberEmployeeDepartmentHistories } from "../../../../providers/patchHrmPlatformMemberEmployeeDepartmentHistories";

@Controller("/hrmPlatform/member/employee-department-histories")
export class HrmplatformMemberEmployee_department_historiesController {
  /**
   * Retrieve a filtered and paginated list of employee department assignment history records.
   *
   * This operation provides audit trail access for tracking when employees were assigned to or removed from departments. Each history entry captures the employee, the department assignment (null when removed), the member who made the change, and the timestamp of the change.
   *
   * Supports comprehensive filtering by employee, department, change author, and date ranges. Results are paginated with configurable page sizes and sorting options. This endpoint is intended for organizational audit and compliance purposes, allowing users with organization management permissions to review department structure changes over time.
   *
   * The history records are immutable and append-only, providing a complete audit trail of all department assignment changes. When a department is deleted, the department_id in history records remains preserved for historical accuracy.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering employee department history records
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_employee_department_histories table with pagination and filtering.
   *
   * Apply search filters on:
   * - employee_id: Filter by specific employee UUID
   * - department_id: Filter by specific department UUID (include null for removed assignments)
   * - changed_by_id: Filter by member who made the change
   * - changed_at: Filter by date range (from/to)
   * - created_at: Filter by record creation date range
   *
   * Join with hrm_platform_employees for employee details, hrm_platform_departments for department name (handle null), and hrm_platform_members for change author information.
   *
   * Support cursor-based or offset pagination with configurable page size (default 20, max 100).
   *
   * Support sorting by changed_at (descending default), created_at, employee_id.
   *
   * Authorization: Require member actor with org:manage permission.
   *
   * Return summary view with employee name, department name (or null indicator), changed_by name, changed_at timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformEmployeeDepartmentHistory.IRequest,
  ): Promise<IPageIHrmPlatformEmployeeDepartmentHistory.ISummary> {
    try {
      return await patchHrmPlatformMemberEmployeeDepartmentHistories({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific employee department history audit record by its unique identifier.
   *
   * This operation returns detailed information about a single department assignment change event, including which employee was affected, which department they were assigned to (or null if removed from department), which member made the change, and when the change occurred.
   *
   * Employee department histories are immutable audit records that provide a complete trail of organizational structure changes. Each record captures a point-in-time snapshot of a department assignment change, enabling compliance tracking and organizational audit requirements.
   *
   * The response includes the employee reference, department reference (nullable), the member who initiated the change, and timestamps for both the change event and record creation. This data is essential for understanding organizational restructuring history and employee movement patterns within the organization.
   *
   * Access to this endpoint requires appropriate permissions to view employee or organizational audit data. The operation enforces organization context isolation, ensuring users can only access history records within their current organization scope.
   *
   * @param connection
   * @param historyId Target employee department history record's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the hrm_platform_employee_department_histories table by primary key id (UUID format). Join with hrm_platform_employees to include employee details, hrm_platform_departments for department information (left join since department_id is nullable), and hrm_platform_members for the user who made the change. Enforce organization context filtering to ensure data isolation - only return records belonging to the user's current organization. Validate that the historyId parameter is a valid UUID format. Return 404 if no record found with the given ID. Response should include all fields: id, employee_id, department_id (nullable), changed_by_id, changed_at, and created_at with proper ISO 8601 datetime formatting.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":historyId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("historyId")
    historyId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformEmployeeDepartmentHistory> {
    try {
      return await getHrmPlatformMemberEmployeeDepartmentHistoriesHistoryId({
        member,
        historyId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
