import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformActivityLog } from "../../../../api/structures/IHrmPlatformActivityLog";
import { IPageIHrmPlatformActivityLog } from "../../../../api/structures/IPageIHrmPlatformActivityLog";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberActivityLogsActivityLogId } from "../../../../providers/getHrmPlatformMemberActivityLogsActivityLogId";
import { patchHrmPlatformMemberActivityLogs } from "../../../../providers/patchHrmPlatformMemberActivityLogs";

@Controller("/hrmPlatform/member/activity-logs")
export class HrmplatformMemberActivity_logsController {
  /**
   * Retrieves a paginated list of activity log entries for the organization's audit trail.
   *
   * This endpoint provides visibility into significant actions performed within the organization, including employee management, contract modifications, project updates, task status changes, timesheet approvals, and role assignments. Each entry captures the timestamp, the user who performed the action, the action type, the target entity affected, and contextual details.
   *
   * The operation supports filtering by action type to focus on specific categories of events, by user to track actions by specific individuals, and by date range to audit activities within specific time periods. Results are paginated for efficient browsing of historical records.
   *
   * Only users with organization management permissions (org:manage) can access the full activity log to maintain oversight and compliance requirements.
   *
   * @param connection
   * @param body Search criteria including action type filters, user filters, date range filters, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_activity_logs table with
     *   pagination and filtering.
   *
   * Apply filters from request body:
   * - actionType: filter by specific action types (employee:invite, employee:deactivate, employee:reactivate, contract:create, contract:edit, timesheet:submit, timesheet:approve, timesheet:reject, task:status-change, project:create, project:archive, project:complete, project:delete, role:assign, role:change)
   * - userId: filter by specific user who performed the action
   * - dateFrom: filter entries on or after this date
   * - dateTo: filter entries on or before this date
   *
   * Join with hrm_platform_members to include user information in response.
   * Join with hrm_platform_organizations to enforce organization context (data isolation).
   *
   * Return cursor-based pagination for large result sets.
   * Order by createdAt descending (most recent first).
   *
   * Enforce organization context: only return activity logs belonging to the user's current organization.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformActivityLog.IRequest,
  ): Promise<IPageIHrmPlatformActivityLog.ISummary> {
    try {
      return await patchHrmPlatformMemberActivityLogs({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single activity log entry by its unique identifier.
   *
   * This endpoint returns the complete audit trail record including the timestamp, the user who performed the action, action type, target entity information, and contextual details. Activity logs are immutable system-generated records that capture significant organizational actions such as employee changes, contract modifications, project updates, task status changes, timesheet approvals, and role assignments.
   *
   * Access to activity logs requires org:manage permission. The returned entry includes the organization scope, member who performed the action, action type in dot-notation format (e.g., 'employee.invited', 'contract.created'), target entity type and ID, structured details metadata, and the creation timestamp.
   *
   * Activity log entries cannot be modified or deleted through the API to preserve audit trail integrity. Attempts to access activity logs without proper authorization are rejected with an access denied response.
   *
   * @param connection
   * @param activityLogId Unique identifier of the activity log entry (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_activity_logs table by primary
     *   key id (UUID).
   *
   * Implementation steps:
   * 1. Validate the activityLogId parameter is a valid UUID format
   * 2. Verify the requesting user has org:manage permission
   * 3. Retrieve the activity log record joining with hrm_platform_members to get actor information
   * 4. Verify the activity log belongs to the user's current organization context (hrm_platform_organization_id matches)
   * 5. Return the full activity log entity including all fields: id, hrm_platform_organization_id, hrm_platform_member_id, action_type, target_entity_type, target_entity_id, details, created_at
   * 6. Include related member information (user who performed the action) in the response
   *
   * Edge cases:
   * - Return 404 if activity log ID does not exist
   * - Return 403 if user lacks org:manage permission
   * - Return 404 if activity log belongs to a different organization than user's current context
   *
   * No soft delete is implemented - activity logs are immutable and permanently retained.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":activityLogId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("activityLogId")
    activityLogId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformActivityLog> {
    try {
      return await getHrmPlatformMemberActivityLogsActivityLogId({
        member,
        activityLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
