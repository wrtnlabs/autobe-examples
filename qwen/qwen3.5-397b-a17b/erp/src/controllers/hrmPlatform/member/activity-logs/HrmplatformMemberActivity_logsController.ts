import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformActivityLog } from "../../../../api/structures/IHrmPlatformActivityLog";
import { IPageIHrmPlatformActivityLog } from "../../../../api/structures/IPageIHrmPlatformActivityLog";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberActivityLogsActivityLogId } from "../../../../providers/getHrmPlatformMemberActivityLogsActivityLogId";
import { patchHrmPlatformMemberActivityLogs } from "../../../../providers/patchHrmPlatformMemberActivityLogs";

@Controller("/hrmPlatform/member/activity-logs")
export class HrmplatformMemberActivity_logsController {
  /**
   * Retrieve a filtered and paginated list of activity log entries for audit trail review.
   *
   * This operation provides comprehensive search capabilities for organizational activity logs, allowing filtering by action type, member who performed the action, target entity type, and date ranges. Activity logs are automatically generated by the system when significant actions occur such as employee lifecycle events, contract changes, project operations, task status changes, timesheet workflow actions, and role assignments.
   *
   * Only members with org:manage permission can access this endpoint. The response includes summarized activity log information optimized for list displays, with pagination support for large result sets. Results are scoped to the user's current organization context to ensure data isolation.
   *
   * Filters support multiple action types, date range queries using created_at timestamps, and member-based filtering. The endpoint is commonly used for compliance audits, forensic analysis, and organizational activity monitoring.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for activity log filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_activity_logs table with pagination and filtering.
   * Apply search filters on action_type, member_id, target_entity_type, target_entity_id, and created_at date range.
   * Enforce organization context by filtering on organization_id from user's session.
   * Verify user has org:manage permission before executing query.
   * Join with hrm_platform_members table to include member information if needed.
   * Support cursor-based or offset pagination for large result sets.
   * Sort results by created_at DESC by default to show most recent activities first.
   * Return IPageIHrmPlatformActivityLog.ISummary with pagination metadata and data array.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformActivityLog.IRequest,
  ): Promise<IPageIHrmPlatformActivityLog.ISummary> {
    try {
      return await patchHrmPlatformMemberActivityLogs({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific activity log entry by its unique identifier.
   *
   * This operation provides access to detailed information about a single recorded organizational action. Activity logs capture significant events including employee lifecycle changes, contract modifications, project operations, task status changes, timesheet workflow transitions, and role assignments. Each entry includes the member who performed the action, the organization context, action type classification, target entity information, and additional contextual details.
   *
   * Access to this endpoint requires organization management permissions (org:manage). The system enforces strict data isolation, ensuring users can only access activity logs from their currently selected organization context. This prevents cross-organization data exposure even when users belong to multiple organizations.
   *
   * The activity log entry includes comprehensive audit information: the timestamp when the action occurred, the member account attribution, the type of action performed, the entity type and ID that was affected, and optional details containing old/new values or reasons for the action. This information supports compliance requirements, forensic analysis, and organizational transparency.
   *
   * Related operations include PATCH /activity-logs for paginated list retrieval with filtering capabilities, and GET /members/{memberId} for retrieving information about the member who performed the logged action.
   *
   * @param connection
   * @param activityLogId Target activity log entry's unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the hrm_platform_activity_logs table by primary key ID. Validate that the requesting member has org:manage permission in the current organization context. Enforce organization isolation by verifying the activity log's organization_id matches the member's current organization. Join with hrm_platform_members table to include member information if needed for response enrichment. Return the complete activity log entity including all fields: id, member_id, organization_id, action_type, target_entity_type, target_entity_id, details, created_at, updated_at. Handle not-found scenarios when the activity log ID doesn't exist or belongs to a different organization. Ensure soft-deleted records (deleted_at is not null) are excluded from results unless explicitly querying for deleted entries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":activityLogId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("activityLogId")
    activityLogId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformActivityLog> {
    try {
      return await getHrmPlatformMemberActivityLogsActivityLogId({
        member,
        activityLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
