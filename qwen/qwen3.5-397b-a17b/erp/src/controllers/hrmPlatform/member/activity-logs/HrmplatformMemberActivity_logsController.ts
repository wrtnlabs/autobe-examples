import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformActivityLog } from "../../../../api/structures/IHrmPlatformActivityLog";
import { IPageIHrmPlatformActivityLog } from "../../../../api/structures/IPageIHrmPlatformActivityLog";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberActivityLogsActivityLogId } from "../../../../providers/getHrmPlatformMemberActivityLogsActivityLogId";
import { patchHrmPlatformMemberActivityLogs } from "../../../../providers/patchHrmPlatformMemberActivityLogs";

@Controller("/hrmPlatform/member/activity-logs")
export class HrmplatformMemberActivity_logsController {
  /**
   * Retrieve a filtered and paginated list of activity log entries for the organization.
   *
   * This endpoint provides access to the organization's audit trail, allowing users with appropriate permissions to search and browse significant actions that have occurred. Activity logs capture employee lifecycle events, contract changes, project actions, task status changes, timesheet workflow events, and role assignments.
   *
   * Supports filtering by action type, user who performed the action, and date ranges. Results are paginated with configurable page sizes and sorting options. Only users with org:manage permission can access this endpoint.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering activity logs
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_activity_logs table with pagination and filtering capabilities.
   *
   * Apply filters based on request criteria:
   * - actionType: exact match on action_type column
   * - userId: filter by user_id (the actor who performed the action)
   * - dateFrom: created_at >= dateFrom
   * - dateTo: created_at <= dateTo
   * - targetEntityType: filter by target_entity_type column
   *
   * Join with hrm_platform_users to include actor information in summary response.
   * Enforce organization context - only return logs for the current organization.
   * Verify user has org:manage permission before allowing access.
   *
   * Support cursor-based or offset pagination. Default sort by created_at DESC (newest first).
   * Return IHrmPlatformActivityLog.ISummary for each entry with essential fields:
   * id, timestamp, actionType, targetEntity, actor summary, and brief details.
   *
   * Handle edge cases:
   * - Empty result set: return empty array with pagination metadata
   * - Invalid date range: return 400 Bad Request
   * - Unauthorized access: return 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformActivityLog.IRequest,
  ): Promise<IPageIHrmPlatformActivityLog.ISummary> {
    try {
      return await patchHrmPlatformMemberActivityLogs({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific activity log entry by its unique identifier.
   *
   * This operation returns the complete details of a single activity log record from the hrm_platform_activity_logs table, including the timestamp when the action occurred (created_at), the member who performed the action (member_id), the action type classification, the target entity type and ID affected by the action, and any additional metadata stored in the details JSON field. Activity logs are immutable audit records automatically created by the system for significant organizational events such as employee lifecycle changes, contract modifications, project actions, task status changes, timesheet workflow events, and role assignments.
   *
   * Only members with organization management (org:manage) permission can access activity log entries. The operation enforces organization data isolation by verifying the activity log's organization_id matches the authenticated user's current organization context. Records with deleted_at timestamps are excluded from results.
   *
   * @param connection
   * @param activityLogId UUID of the activity log entry to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_activity_logs table by primary key id. Verify the activity log belongs to the user's current organization by checking organization_id matches the authenticated user's organization context. Ensure user has org:manage permission before returning the record. Return the full activity log entry including all fields: id, organization_id, member_id, action_type, target_entity_type, target_entity_id, details, created_at, updated_at. Join with hrm_platform_members table to include actor information if needed for response enrichment. Handle 404 if activity log not found or doesn't belong to user's organization. Activity logs are immutable audit records with no soft delete filtering needed for viewing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":activityLogId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("activityLogId")
    activityLogId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformActivityLog> {
    try {
      return await getHrmPlatformMemberActivityLogsActivityLogId({
        member,
        activityLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
