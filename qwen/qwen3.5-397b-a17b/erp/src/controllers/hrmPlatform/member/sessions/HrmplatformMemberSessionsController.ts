import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformMemberSession } from "../../../../api/structures/IHrmPlatformMemberSession";
import { IPageIHrmPlatformMemberSession } from "../../../../api/structures/IPageIHrmPlatformMemberSession";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberSessionsSessionId } from "../../../../providers/getHrmPlatformMemberSessionsSessionId";
import { patchHrmPlatformMemberSessions } from "../../../../providers/patchHrmPlatformMemberSessions";

@Controller("/hrmPlatform/member/sessions")
export class HrmplatformMemberSessionsController {
  /**
   * Retrieve a filtered and paginated list of active login sessions for the authenticated member.
   *
   * This operation provides session management capabilities allowing users to view their login history across different devices and locations. Sessions include device information, IP addresses, login timestamps, and expiration times.
   *
   * Supports filtering by date ranges, device types, and session status. Results are paginated for efficient browsing of session history. Only the authenticated member's sessions are returned, ensuring data isolation.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for session filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_member_sessions table filtered by the authenticated member's ID.
   * Apply search filters on created_at date range, device_info partial matching, IP address, and expired_at status.
   * Join with hrm_platform_members for member verification.
   * Return cursor-based pagination with session summary information.
   * Exclude sensitive token hashes from response.
   * Filter out expired sessions by default unless explicitly requested.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformMemberSession.IRequest,
  ): Promise<IPageIHrmPlatformMemberSession.ISummary> {
    try {
      return await patchHrmPlatformMemberSessions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific member authentication session.
   *
   * This operation returns complete session metadata including the associated member, client device information, IP address, login context URLs, token hashes for validation, and session timestamps. Session data is useful for security auditing, monitoring active sessions, and troubleshooting authentication issues.
   *
   * The response includes all session attributes: member reference, client IP, original login URL, referrer, access and refresh token hashes, device information (user agent, browser, OS), creation timestamp, and expiration timestamp. Members can access their own session information to monitor account security and manage active login sessions.
   *
   * @param connection
   * @param sessionId Session identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_member_sessions table by session ID (UUID). Return complete session record including member_id, ip, href, referrer, access_token_hash, refresh_token_hash, device_info, created_at, and expired_at. Join with hrm_platform_members to include member email if needed for display. Validate session exists before returning. Return 404 if session not found. This is an admin-only operation requiring appropriate permissions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformMemberSession> {
    try {
      return await getHrmPlatformMemberSessionsSessionId({
        member,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
