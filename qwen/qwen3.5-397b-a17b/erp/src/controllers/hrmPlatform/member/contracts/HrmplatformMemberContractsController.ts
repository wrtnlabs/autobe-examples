import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformEmployeeContract } from "../../../../api/structures/IHrmPlatformEmployeeContract";
import { IPageIHrmPlatformEmployeeContract } from "../../../../api/structures/IPageIHrmPlatformEmployeeContract";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberContractsContractId } from "../../../../providers/getHrmPlatformMemberContractsContractId";
import { patchHrmPlatformMemberContracts } from "../../../../providers/patchHrmPlatformMemberContracts";

@Controller("/hrmPlatform/member/contracts")
export class HrmplatformMemberContractsController {
  /**
   * Retrieve a filtered and paginated list of employee employment contracts.
   *
   * This operation provides advanced search capabilities for viewing contract records across the organization. Users can filter contracts by employee, date ranges, pay period, and contract status (active or historical). The endpoint supports comprehensive pagination with configurable page sizes and sorting options.
   *
   * Access control is enforced based on user permissions: users with employee:manage or employee:view permissions can view any employee's contracts within their organization. Employees can access this endpoint to view their own contracts. The response includes contract summary information optimized for list displays, showing key terms like pay rate, pay period, working hours, and date ranges.
   *
   * Contracts represent the employment terms agreement between an employee and the organization, including compensation structure and working conditions. Each employee can have multiple contracts over time, forming a complete historical record. Only one contract can be active at any given time per employee. Past contracts are immutable historical records that cannot be edited, while the current active contract can be modified.
   *
   * This endpoint is typically used in conjunction with GET /contracts/{contractId} for retrieving detailed contract information. After obtaining the list of contract summaries, users can specify a contract ID to retrieve full contract details including notes and complete temporal information.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for contract list
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_employee_contracts table with pagination and filtering capabilities.
   *
   * Apply search filters on:
   * - hrm_platform_employee_id: filter contracts for specific employee
   * - start_date range: filter contracts by start date range
   * - end_date range: filter contracts by end date range (including null for active contracts)
   * - pay_period: filter by compensation frequency (hourly, daily, weekly, monthly)
   * - is_active: boolean filter for currently active contracts (end_date is null)
   *
   * Join with hrm_platform_employees table to include employee summary information if needed for display.
   *
   * Enforce organization data isolation by filtering contracts through the authenticated user's organization context.
   *
   * Apply permission checks: allow access if user has employee:manage, employee:view permission, or is viewing their own contracts.
   *
   * Return cursor-based or offset pagination with pagination metadata (page, limit, total count) and data array containing contract summaries.
   *
   * Sort results by start_date descending by default to show most recent contracts first. Support custom sorting by start_date, pay_rate, created_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformEmployeeContract.IRequest,
  ): Promise<IPageIHrmPlatformEmployeeContract.ISummary> {
    try {
      return await patchHrmPlatformMemberContracts({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific employee contract by its unique identifier.
   *
   * This operation returns the complete contract record including all employment terms: start date, optional end date (null indicates ongoing contract), pay rate, pay period frequency (hourly, daily, weekly, monthly), working hours per week, and optional notes. The contract is linked to a specific employee through the hrm_platform_employee_id foreign key.
   *
   * Access control enforces two pathways: (1) the employee who owns the contract can always view their own contracts regardless of employment status, and (2) users with employee view permission within the organization can view any employee's contracts for administrative and reporting purposes. This ensures sensitive compensation information remains protected while allowing appropriate administrative access per requirements sections 110 and 246.
   *
   * Past contracts with end dates are immutable historical records, while contracts with null end dates represent the current active employment terms. The response includes creation and update timestamps for audit purposes.
   *
   * @param connection
   * @param contractId Target contract's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_employee_contracts table by contractId UUID primary key.
   *
   * Authorization flow:
   * 1. Retrieve the contract record with employee relation
   * 2. Get the employee's organization context
   * 3. Check if requesting user is the contract owner (employee's user_id matches authenticated user)
   * 4. If not owner, verify user has employee:view permission in that organization
   * 5. Reject with 403 if neither condition is met
   *
   * Return the complete contract object including all fields: id, hrm_platform_employee_id, start_date, end_date, pay_rate, pay_period, working_hours_per_week, notes, created_at, updated_at, deleted_at.
   *
   * Handle soft deletion: if deleted_at is not null, return 404 as the contract has been soft-deleted.
   *
   * Handle not found: if contractId doesn't exist, return 404.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":contractId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("contractId")
    contractId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformEmployeeContract> {
    try {
      return await getHrmPlatformMemberContractsContractId({
        member,
        contractId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
