import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformEmployeeContract } from "../../../../api/structures/IHrmPlatformEmployeeContract";
import { IPageIHrmPlatformEmployeeContract } from "../../../../api/structures/IPageIHrmPlatformEmployeeContract";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberEmployeeContractsContractId } from "../../../../providers/getHrmPlatformMemberEmployeeContractsContractId";
import { patchHrmPlatformMemberEmployeeContracts } from "../../../../providers/patchHrmPlatformMemberEmployeeContracts";
import { postHrmPlatformMemberEmployeeContracts } from "../../../../providers/postHrmPlatformMemberEmployeeContracts";
import { putHrmPlatformMemberEmployeeContractsContractId } from "../../../../providers/putHrmPlatformMemberEmployeeContractsContractId";

@Controller("/hrmPlatform/member/employee-contracts")
export class HrmplatformMemberEmployee_contractsController {
  /**
   * Create a new employment contract for an employee.
   *
   * This endpoint creates a contract record with employment terms including pay rate, pay period, working hours, and employment duration. Users with employee:manage permission can create contracts for any employee in the organization.
   *
   * When creating a new contract for an employee who already has an active contract (end_date is null), the system automatically ends the previous active contract by setting its end_date to the day before the new contract's start_date. This enforces the single active contract rule.
   *
   * The created contract becomes the employee's current active contract. Past contracts are immutable historical records and cannot be modified through this endpoint.
   *
   * @param connection
   * @param body Contract creation data including employee reference, employment period dates, compensation details, and working hours. The end_date is optional - null means the contract is ongoing.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new employee contract record in hrm_platform_employee_contracts table.
   *
   * 1. Validate request body: hrm_platform_employee_id (UUID), start_date (required), end_date (optional), pay_rate (positive number), pay_period (enum: hourly/daily/weekly/monthly), working_hours_per_week (positive integer), notes (optional string).
   *
   * 2. Verify employee exists in hrm_platform_employees table and belongs to the requesting user's organization.
   *
   * 3. Check if employee has an existing active contract (end_date is null). If found, update that contract's end_date to start_date minus one day.
   *
   * 4. Insert new contract record with provided fields. Set created_at and updated_at to current timestamp. Set deleted_at to null.
   *
   * 5. Log the contract creation in hrm_platform_activity_logs with action type 'contract_created'.
   *
   * 6. Return the newly created contract object with all fields including generated id and timestamps.
   *
   * Error handling:
   * - 400 if pay_rate <= 0 or working_hours_per_week <= 0
   * - 400 if pay_period is not one of allowed values
   * - 404 if employee not found
   * - 403 if user lacks employee:manage permission
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformEmployeeContract.ICreate,
  ): Promise<IHrmPlatformEmployeeContract> {
    try {
      return await postHrmPlatformMemberEmployeeContracts({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and list employee contracts with pagination and filtering support.
   *
   * This endpoint retrieves contract records from the organization with support for filtering by employee, date ranges, pay period, and contract status (active vs. historical). Results are paginated for efficient data browsing.
   *
   * Users with employee:manage or employee:view permission can access this endpoint. All results are scoped to the current organization context for data isolation.
   *
   * Active contracts (end_date is null) can be distinguished from historical contracts (end_date is set). Only one contract per employee can be active at a time.
   *
   * @param connection
   * @param body Search criteria including employee filter, date ranges, pay period, contract status, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_employee_contracts table with pagination and filtering.
   *
   * Apply filters from request body:
   * - hrm_platform_employee_id: filter by specific employee
   * - start_date range: filter contracts by start date
   * - end_date range: filter contracts by end date (null for active contracts)
   * - pay_period: filter by compensation frequency
   * - status: active (end_date is null) or historical (end_date is set)
   *
   * Join with hrm_platform_employees to verify organization context and enforce data isolation.
   *
   * Return cursor-based pagination with summary fields optimized for list display.
   *
   * Enforce organization context on every query - contracts from other organizations must not be visible.
   *
   * Sort by created_at descending by default, allow custom sorting via request body.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformEmployeeContract.IRequest,
  ): Promise<IPageIHrmPlatformEmployeeContract.ISummary> {
    try {
      return await patchHrmPlatformMemberEmployeeContracts({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific employee contract by its unique identifier.
   *
   * This endpoint returns the complete details of a single contract record, including employment terms such as pay rate, pay period, working hours, and contract duration. The contract includes both current (ongoing) and historical contracts for an employee.
   *
   * Access to this endpoint is restricted based on organization context and permissions. Employees can always view their own contracts. Users with the employee:view permission can view any employee's contracts within the same organization. Requests for contracts belonging to employees in different organizations are rejected.
   *
   * The response includes all contract fields: start date, end date (null for active contracts), compensation details, working hours, and any associated notes. System-generated timestamps (created_at, updated_at) are included for audit purposes.
   *
   * @param connection
   * @param contractId Unique identifier of the employee contract (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_employee_contracts table by contract ID (UUID). Join with hrm_platform_employees to verify organization context and ownership. Enforce permission checks: allow if requester is the employee themselves OR has employee:view permission in the same organization. Return the complete contract record including id, employee reference, start_date, end_date, pay_rate, pay_period, working_hours_per_week, notes, created_at, updated_at. Filter out soft-deleted records (deleted_at is not null). Handle 404 if contract not found or access denied.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":contractId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("contractId")
    contractId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformEmployeeContract> {
    try {
      return await getHrmPlatformMemberEmployeeContractsContractId({
        member,
        contractId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an employee contract's employment terms and conditions.
   *
   * This operation allows modification of the current active contract for an employee. Only contracts with a null end_date (active contracts) can be updated. Past contracts with an end_date are immutable historical records and cannot be modified.
   *
   * Users with employee:manage permission can update contract details including pay rate, pay period, working hours per week, and optional notes. The start_date cannot be changed as it determines contract chronology and affects automatic ending of previous contracts.
   *
   * When updating a contract, the system validates that the contract is currently active (end_date is null). Attempting to update a past contract will be rejected.
   *
   * @param connection
   * @param contractId Unique identifier of the contract to update (UUID format).
   * @param body Contract update data including pay rate, pay period, working hours, and optional notes. Start date cannot be modified.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_employee_contracts table by contractId UUID. Verify the contract exists and is not soft deleted (deleted_at is null). Check that end_date is null (active contract) - reject if end_date is set (past contract). Validate user has employee:manage permission in the contract's organization (join with hrm_platform_employees to get organization context). Apply updates to pay_rate, pay_period, working_hours_per_week, and notes fields. Do not allow start_date modification. Update updated_at timestamp. Return the updated contract record with full entity data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":contractId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("contractId")
    contractId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformEmployeeContract.IUpdate,
  ): Promise<IHrmPlatformEmployeeContract> {
    try {
      return await putHrmPlatformMemberEmployeeContractsContractId({
        member,
        contractId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
