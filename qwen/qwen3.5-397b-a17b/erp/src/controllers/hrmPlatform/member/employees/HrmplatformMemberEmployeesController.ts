import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformEmployee } from "../../../../api/structures/IHrmPlatformEmployee";
import { IPageIHrmPlatformEmployee } from "../../../../api/structures/IPageIHrmPlatformEmployee";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteHrmPlatformMemberEmployeesEmployeeId } from "../../../../providers/deleteHrmPlatformMemberEmployeesEmployeeId";
import { getHrmPlatformMemberEmployeesEmployeeId } from "../../../../providers/getHrmPlatformMemberEmployeesEmployeeId";
import { patchHrmPlatformMemberEmployees } from "../../../../providers/patchHrmPlatformMemberEmployees";
import { putHrmPlatformMemberEmployeesEmployeeId } from "../../../../providers/putHrmPlatformMemberEmployeesEmployeeId";

@Controller("/hrmPlatform/member/employees")
export class HrmplatformMemberEmployeesController {
  /**
   * Retrieve a filtered and paginated list of employee records within the current organization.
   *
   * This operation provides comprehensive search capabilities for browsing employees across the organization. Users can filter results by department assignment, employment type classification, and activation status. Name-based partial matching supports quick employee lookup.
   *
   * The endpoint enforces organization context - only employees belonging to the current organization are returned. Users with employee:view permission can access this endpoint. Results include employee summary information optimized for list displays, showing role, department, position, employment type, and status.
   *
   * Pagination uses cursor-based approach for efficient large dataset handling. Sorting options allow ordering by name, employment type, or creation date.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for employee listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_employees table with organization_id filter from current session context.
   * Apply search filters: partial name match on user's display name via join to hrm_platform_members, exact match on department_id, employment_type, and status.
   * Join with hrm_platform_roles for role name, hrm_platform_departments for department name, hrm_platform_members for user display name and avatar.
   * Apply pagination with cursor-based approach using created_at or id as cursor key.
   * Support sorting by name (via user display name), employment_type, status, or created_at.
   * Return IPageIHrmPlatformEmployee.ISummary with employee id, user_id, role_id, department_id, position, employment_type, status, and computed user display name.
   * Handle edge case: organization has no employees → return empty page.
   * Validate organization context exists in session.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformEmployee.IRequest,
  ): Promise<IPageIHrmPlatformEmployee.ISummary> {
    try {
      return await patchHrmPlatformMemberEmployees({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific employee within the organization.
   *
   * This operation returns comprehensive employee data including their assigned role, optional department assignment, position title, employment type classification, and activation status. The response includes linked entity information such as role details and department details when applicable.
   *
   * Requires employee:view permission. The employee must belong to the current organization context. Deactivated employees are included in results to allow viewing of historical employee records. Returns 404 if the employee does not exist or belongs to a different organization.
   *
   * @param connection
   * @param employeeId Employee UUID identifier (scoped to current organization)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_employees table by employeeId UUID. Join with hrm_platform_roles to include role details. Left join with hrm_platform_departments to include department details if department_id is not null. Left join with hrm_platform_members to include user profile information (display name, avatar). Verify the employee belongs to the current organization context. Return 404 if employee not found or belongs to different organization. Ensure soft-deleted records (deleted_at is not null) are excluded from results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":employeeId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformEmployee> {
    try {
      return await getHrmPlatformMemberEmployeesEmployeeId({
        member,
        employeeId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an employee record within the organization.
   *
   * This operation allows users with employee:manage permission to modify employee attributes including role assignment, department, position title, employment type, and activation status. When updating the role, the previous role is automatically replaced and the employee immediately gains or loses permissions according to the new role assignment.
   *
   * Department assignment references the hrm_platform_departments table and is optional—can be set to null to remove department association. Role updates reference the hrm_platform_roles table and must point to an existing role within the same organization. Position and employment type fields can be updated to reflect changes in the employee's work arrangement. Status changes between active and deactivated affect the employee's ability to log time, submit timesheets, and access organization features.
   *
   * All attribute changes trigger employee attribute update events recorded in the activity log. Historical actions performed by the employee under previous role assignments remain unchanged. The operation validates that the employee exists within the current organization context and that all referenced entities (role, department) belong to the same organization.
   *
   * @param connection
   * @param employeeId Employee UUID (scoped to current organization)
   * @param body Employee fields to update. Only provided fields will be modified. Omit fields to preserve existing values.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update the hrm_platform_employees record by employeeId UUID.
   *
   * 1. Verify the employee exists and belongs to the current organization context
   * 2. Validate requester has employee:manage permission
   * 3. Validate role_id references an existing role in the same organization
   * 4. If department_id is provided, validate it references an existing department in the same organization
   * 5. Validate employment_type is one of: full-time, part-time, contractor, intern
   * 6. Validate status is one of: active, deactivated
   * 7. Update the employee record with provided fields
   * 8. Return the updated employee entity with all fields
   *
   * Edge cases:
   * - Employee not found: return 404
   * - Insufficient permissions: return 403
   * - Invalid role_id or department_id: return 400
   * - Invalid employment_type or status value: return 400
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":employeeId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformEmployee.IUpdate,
  ): Promise<IHrmPlatformEmployee> {
    try {
      return await putHrmPlatformMemberEmployeesEmployeeId({
        member,
        employeeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Deactivate an employee record by setting their status to deactivated and recording the deletion timestamp.
   *
   * This operation performs a soft delete on the employee record, preserving all historical data including timelogs, timesheets, contracts, and project memberships. The employee's status is changed to 'deactivated' and the deleted_at timestamp is set, preventing further time logging and timesheet submission.
   *
   * Deactivated employees immediately lose access to organization resources but their historical contributions remain preserved for reporting and audit purposes. Users with employee:manage permission can reactivate deactivated employees if needed.
   *
   * This operation requires the 'employee:manage' permission. The system validates that the employee belongs to the current organization context before deactivation.
   *
   * @param connection
   * @param employeeId UUID of the employee record to deactivate (scoped to current organization)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Verify the authenticated user has 'employee:manage' permission in the current organization context. Query hrm_platform_employees table to find the employee record by employeeId. Validate the employee belongs to the current organization (organization_id matches context). Check that the employee is not the sole owner of the organization (would violate account deletion restrictions). Update the employee record: set deleted_at to current timestamp and status to 'deactivated'. Preserve all historical data associations (timelogs, timesheets, contracts, project memberships remain intact). Record the deactivation action in hrm_platform_activity_logs with action type 'employee_deactivated', including timestamp, user who performed the action, and employee details. Return the deactivated employee record. Handle edge cases: employee already deactivated (return current state), employee not found (404), insufficient permissions (403).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":employeeId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformMemberEmployeesEmployeeId({
        member,
        employeeId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
