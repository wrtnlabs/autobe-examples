import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformEmployee } from "../../../../api/structures/IHrmPlatformEmployee";
import { IPageIHrmPlatformEmployee } from "../../../../api/structures/IPageIHrmPlatformEmployee";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberEmployeesEmployeeId } from "../../../../providers/getHrmPlatformMemberEmployeesEmployeeId";
import { patchHrmPlatformMemberEmployees } from "../../../../providers/patchHrmPlatformMemberEmployees";
import { putHrmPlatformMemberEmployeesEmployeeId } from "../../../../providers/putHrmPlatformMemberEmployeesEmployeeId";

@Controller("/hrmPlatform/member/employees")
export class HrmplatformMemberEmployeesController {
  /**
   * Retrieve a paginated list of employees within the current organization with optional filtering and search capabilities.
   *
   * This endpoint supports filtering employees by department, employment type, and status. Name search uses trigram-based fuzzy matching on the position field. Results are paginated using cursor-based pagination for efficient handling of large result sets.
   *
   * All employees returned are scoped to the currently selected organization context. Users must have employee:view permission to access this endpoint. The response includes summary information optimized for list displays, excluding detailed contract history and activity logs.
   *
   * @param connection
   * @param body Search criteria including department filter, employment type filter, status filter, name search query, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_employees table with
     *   organization_id filter from current session context. Apply filters:
     *   department_id (exact match, nullable), employment_type (enum match),
     *   status (enum match: active/deactivated). Apply name search using
     *   position field with trigram similarity (gin_trgm_ops index). Join with
     *   hrm_platform_roles for role name, hrm_platform_departments for
     *   department name, hrm_platform_members for user email. Return
     *   cursor-based pagination with IPageIHrmPlatformEmployee.ISummary
     *   response type. Enforce employee:view permission check. Handle edge
     *   case: empty result set returns page with empty items array and null
     *   cursors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformEmployee.IRequest,
  ): Promise<IPageIHrmPlatformEmployee.ISummary> {
    try {
      return await patchHrmPlatformMemberEmployees({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single employee record by ID.
   *
   * This endpoint returns complete details for a specific employee within the current organization context. The response includes the employee's user account reference, assigned role, department assignment, position title, employment type, and activation status.
   *
   * Organization context is enforced on every request - employees can only be accessed within their belonging organization. Users must have employee:view permission to access this endpoint. The operation returns 404 if the employee does not exist or belongs to a different organization.
   *
   * @param connection
   * @param employeeId UUID of the employee record to retrieve (scoped to current organization).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_platform_employees table by employeeId
     *   UUID. Validate the employee exists and belongs to the current
     *   organization context. Join with hrm_platform_members to include user
     *   account information if needed. Join with hrm_platform_roles to include
     *   role details. Optionally join with hrm_platform_departments for
     *   department information. Return the full employee record with all
     *   fields. Enforce organization context validation - reject if employee
     *   belongs to a different organization. Return 404 if employee not found
     *   or organization mismatch.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":employeeId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformEmployee> {
    try {
      return await getHrmPlatformMemberEmployeesEmployeeId({
        member,
        employeeId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an employee record within the organization.
   *
   * This operation allows authorized users to modify an employee's department assignment, position title, employment type, activation status, and role assignment. All changes are scoped to the current organization context and are enforced by organization data isolation policies.
   *
   * The update operation requires employee:manage permission. When updating the role assignment, the system validates that the target role exists within the organization. When updating the department, the system validates that the department exists within the organization. Department assignment is optional and can be set to null.
   *
   * Employment type changes may affect contract terms and are logged in the activity log. Status changes between active and deactivated affect the employee's ability to log time and submit timesheets. Deactivated employees retain all historical data including timelogs and timesheets.
   *
   * The operation returns the complete updated employee record including all current attributes and relationships.
   *
   * @param connection
   * @param employeeId UUID of the employee record to update (scoped to current organization).
   * @param body Employee update data including department assignment, position title, employment type, activation status, and role assignment. All fields are optional - only provided fields will be updated.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Validate employee:manage permission for the
     *   current user in the organization context.
   *
   * Query hrm_platform_employees table by employeeId UUID, ensuring the record belongs to the current organization.
   *
   * Validate all input fields against business rules:
   * - department_id: must exist in hrm_platform_departments within the organization or be null
   * - role_id: must exist in hrm_platform_roles within the organization
   * - employment_type: must be one of 'full-time', 'part-time', 'contractor', 'intern'
   * - status: must be one of 'active', 'deactivated'
   * - position: optional string, no specific validation
   *
   * Apply updates to the employee record:
   * - Update department_id, position, employment_type, status, role_id as provided
   * - Update updated_at timestamp to current time
   *
   * Log the update action in hrm_platform_activity_logs if role_id or status changed, recording old and new values.
   *
   * Return the complete updated employee record with all fields including relationships.
   *
   * Handle edge cases:
   * - Employee not found: return 404
   * - Invalid department_id or role_id: return 400
   * - Insufficient permissions: return 403
   * - Organization context mismatch: return 404
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":employeeId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformEmployee.IUpdate,
  ): Promise<IHrmPlatformEmployee> {
    try {
      return await putHrmPlatformMemberEmployeesEmployeeId({
        member,
        employeeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
