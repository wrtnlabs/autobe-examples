import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformUserProfile } from "../../../../api/structures/IHrmPlatformUserProfile";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberProfile } from "../../../../providers/getHrmPlatformMemberProfile";
import { putHrmPlatformMemberProfile } from "../../../../providers/putHrmPlatformMemberProfile";

@Controller("/hrmPlatform/member/profile")
export class HrmplatformMemberProfileController {
  /**
   * Retrieve the authenticated user's global profile information.
   *
   * Returns the user's display name, avatar image URL, and phone number. The profile is shared across all organizations the user belongs to, ensuring consistent identity regardless of the current organization context.
   *
   * The profile exists independently from organization membership and remains accessible as long as the user account is active. Changes to profile information propagate immediately across all organization contexts.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the hrm_platform_user_profiles table for the authenticated user's profile record. Join with hrm_platform_members to verify the user exists and is authenticated. Return the complete profile entity with display_name, avatar_url, and phone_number fields. Handle the case where a profile may not exist (newly created account) by returning null or creating a default profile. Enforce that users can only access their own profile - the user ID is derived from the authentication session, not from request parameters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmPlatformUserProfile> {
    try {
      return await getHrmPlatformMemberProfile({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated user's global profile information.
   *
   * This endpoint allows users to modify their profile information including display name, avatar image, and phone number. The profile is global and shared across all organizations the user belongs to, ensuring consistent identity regardless of which organization context the user is working in.
   *
   * Profile changes are propagated immediately across all organization contexts. All users in any organization will see the updated profile information when viewing this user's identity.
   *
   * Validation rules apply to all fields: display name cannot be empty, avatar image must meet file format requirements, and phone number must follow valid formatting rules. If any field fails validation, the entire update is rejected and no changes are applied. At least one field must be changed; requests with no actual changes are rejected.
   *
   * @param connection
   * @param body Profile update request with optional fields for display name, avatar image, and phone number. At least one field must be provided and different from current values.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update the hrm_platform_user_profiles record for the authenticated user.
   *
   * 1. Extract user ID from the authenticated session
   * 2. Validate that at least one field (display_name, avatar_image, phone_number) is provided and different from current values
   * 3. Validate display_name: must not be empty, must contain valid characters
   * 4. Validate avatar_image: must meet acceptable file format requirements (image files)
   * 5. Validate phone_number: must follow valid formatting rules if provided
   * 6. If any validation fails, reject the entire update with appropriate error messages
   * 7. Update the hrm_platform_user_profiles record with the new values
   * 8. The update automatically propagates to all organization contexts (no additional action needed)
   * 9. Return the updated user profile
   *
   * Edge cases:
   * - Reject if no fields are changed (compare with current values)
   * - Reject if display_name is empty or contains invalid characters
   * - Reject if avatar_image is not a valid image format
   * - Reject if phone_number format is invalid
   * - All validations occur before any database changes (atomic validation)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformUserProfile.IUpdate,
  ): Promise<IHrmPlatformUserProfile> {
    try {
      return await putHrmPlatformMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
