import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformMember } from "../../../../api/structures/IHrmPlatformMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putHrmPlatformMemberProfile } from "../../../../providers/putHrmPlatformMemberProfile";

@Controller("/hrmPlatform/member/profile")
export class HrmplatformMemberProfileController {
  /**
   * Update the authenticated member's global profile information including display name, avatar image URL, and phone number.
   *
   * This operation allows members to modify their personal profile attributes that are shared across all organizations they belong to. The display name serves as the primary identifier shown throughout the interface and in activity logs. The avatar URL provides visual personalization, and the phone number enables contact capabilities. All profile changes are applied immediately and reflected across all organization contexts.
   *
   * The member's identity is derived from the authenticated session context, ensuring users can only modify their own profile. The display_name field is required and must be provided in every update request. The avatar_url and phone_number fields are optional and can be set to null to remove existing values.
   *
   * Upon successful update, the system propagates the display_name change to all associated employee records to maintain denormalized search efficiency. This ensures that employee searches and filters remain accurate without requiring joins to the members table.
   *
   * Related operations include GET /profile for retrieving current profile information and POST /auth/login for authentication. Profile edits are restricted to the profile owner - attempts to access or modify another user's profile are rejected.
   *
   * @param connection
   * @param body Profile update data with display name, avatar URL, and phone number
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update the authenticated member's global profile by querying the hrm_platform_members table using the member ID from the session context. Accept display_name (required), avatar_url (optional), and phone_number (optional) fields in the request body. Validate that display_name is provided and not empty. Update the member record with the new profile values and update the updated_at timestamp. After successful update, propagate the display_name change to all associated hrm_platform_employees records to maintain denormalized search efficiency. Return the updated member object. Ensure the operation only modifies the authenticated member's own profile - the member ID must come from session context, not from request parameters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformMember.IUpdate,
  ): Promise<IHrmPlatformMember> {
    try {
      return await putHrmPlatformMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
