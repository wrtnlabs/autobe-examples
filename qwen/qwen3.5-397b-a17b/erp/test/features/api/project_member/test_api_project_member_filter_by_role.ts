export async function test_api_project_member_filter_by_role(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as member
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  typia.assert(authorized);
  // 2. Create a project
  const project = await generate_random_hrm_platform_member_projects_create(
    memberConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        color_code: "#3498db",
      } satisfies IHrmPlatformProject.ICreate,
    },
  );
  typia.assert(project);
  // 3. Create first employee (will be assigned as member role)
  // Note: role_id is required but will be generated by prepare_random_hrm_platform_employee
  const employee1 = await generate_random_hrm_platform_member_employees_create(
    memberConnection,
    {
      body: {
        member_id: authorized.id,
        employment_type: "full-time",
      },
    },
  );
  typia.assert(employee1);
  // 4. Create second employee (will be assigned as project-lead role)
  const employee2 = await generate_random_hrm_platform_member_employees_create(
    memberConnection,
    {
      body: {
        member_id: authorized.id,
        employment_type: "part-time",
      },
    },
  );
  typia.assert(employee2);
  // 5. Assign first employee to project as 'member' role
  const memberAssignment =
    await generate_random_hrm_platform_member_projects_members_create(
      memberConnection,
      {
        params: { projectId: project.id },
        body: {
          hrm_platform_employee_id: employee1.id,
          role: "member",
        } satisfies IHrmPlatformProjectMember.ICreate,
      },
    );
  typia.assert(memberAssignment);
  // 6. Assign second employee to project as 'project-lead' role
  const leadAssignment =
    await generate_random_hrm_platform_member_projects_members_create(
      memberConnection,
      {
        params: { projectId: project.id },
        body: {
          hrm_platform_employee_id: employee2.id,
          role: "project-lead",
        } satisfies IHrmPlatformProjectMember.ICreate,
      },
    );
  typia.assert(leadAssignment);
  // 7. Retrieve all project members without role filter (baseline)
  const allMembers =
    await api.functional.hrmPlatform.member.projects.members.index(
      memberConnection,
      {
        projectId: project.id,
        body: {
          page: 1,
          limit: 10,
        } satisfies IHrmPlatformProjectMember.IRequest,
      },
    );
  typia.assert(allMembers);
  TestValidator.equals("all members count", allMembers.data.length, 2);
  TestValidator.equals(
    "all members pagination records",
    allMembers.pagination.records,
    2,
  );
  // 8. Filter by role='member' - should return only employee1
  const memberOnlyFilter =
    await api.functional.hrmPlatform.member.projects.members.index(
      memberConnection,
      {
        projectId: project.id,
        body: {
          role: "member",
          page: 1,
          limit: 10,
        } satisfies IHrmPlatformProjectMember.IRequest,
      },
    );
  typia.assert(memberOnlyFilter);
  TestValidator.equals("member role count", memberOnlyFilter.data.length, 1);
  TestValidator.equals(
    "member role pagination records",
    memberOnlyFilter.pagination.records,
    1,
  );
  TestValidator.equals(
    "member role employee matches",
    memberOnlyFilter.data[0].employee.id,
    employee1.id,
  );
  TestValidator.equals(
    "member role designation",
    memberOnlyFilter.data[0].role,
    "member",
  );
  // 9. Filter by role='project-lead' - should return only employee2
  const leadOnlyFilter =
    await api.functional.hrmPlatform.member.projects.members.index(
      memberConnection,
      {
        projectId: project.id,
        body: {
          role: "project-lead",
          page: 1,
          limit: 10,
        } satisfies IHrmPlatformProjectMember.IRequest,
      },
    );
  typia.assert(leadOnlyFilter);
  TestValidator.equals(
    "project-lead role count",
    leadOnlyFilter.data.length,
    1,
  );
  TestValidator.equals(
    "project-lead role pagination records",
    leadOnlyFilter.pagination.records,
    1,
  );
  TestValidator.equals(
    "project-lead role employee matches",
    leadOnlyFilter.data[0].employee.id,
    employee2.id,
  );
  TestValidator.equals(
    "project-lead role designation",
    leadOnlyFilter.data[0].role,
    "project-lead",
  );
  // 10. Test edge case: filter with search that returns no results
  const emptySearchFilter =
    await api.functional.hrmPlatform.member.projects.members.index(
      memberConnection,
      {
        projectId: project.id,
        body: {
          search: "NonExistentEmployeeName",
          page: 1,
          limit: 10,
        } satisfies IHrmPlatformProjectMember.IRequest,
      },
    );
  typia.assert(emptySearchFilter);
  TestValidator.equals("empty search count", emptySearchFilter.data.length, 0);
  TestValidator.equals(
    "empty search pagination records",
    emptySearchFilter.pagination.records,
    0,
  );
  TestValidator.equals(
    "empty search pagination pages",
    emptySearchFilter.pagination.pages,
    0,
  );
  // 11. Verify role filter works with pagination
  const paginatedMemberFilter =
    await api.functional.hrmPlatform.member.projects.members.index(
      memberConnection,
      {
        projectId: project.id,
        body: {
          role: "member",
          page: 1,
          limit: 1,
        } satisfies IHrmPlatformProjectMember.IRequest,
      },
    );
  typia.assert(paginatedMemberFilter);
  TestValidator.equals(
    "paginated member count",
    paginatedMemberFilter.data.length,
    1,
  );
  TestValidator.equals(
    "paginated member current page",
    paginatedMemberFilter.pagination.current,
    1,
  );
  TestValidator.equals(
    "paginated member limit",
    paginatedMemberFilter.pagination.limit,
    1,
  );
  TestValidator.equals(
    "paginated member records",
    paginatedMemberFilter.pagination.records,
    1,
  );
  TestValidator.equals(
    "paginated member pages",
    paginatedMemberFilter.pagination.pages,
    1,
  );
}
