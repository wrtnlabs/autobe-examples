export async function test_api_project_membership_role_update_validation(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as member with project management permissions
  const memberAuth = await authorize_member_join(connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      avatar_url: typia.random<(string & tags.Format<"uri">) | null>(),
      phone_number: RandomGenerator.mobile(),
      ip: typia.random<(string & tags.Format<"ipv4">) | null>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  typia.assert(memberAuth);
  // Create member-specific connection for subsequent API calls
  const memberConnection: api.IConnection = { host: connection.host };
  memberConnection.headers = { Authorization: memberAuth.token.access };
  // 2. Create a project
  const project = await generate_random_hrm_platform_member_projects_create(
    memberConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        color_code: "#3498db",
        status: "active",
        description: RandomGenerator.content({ paragraphs: 1 }),
        budget_hours: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<100>
        >(),
      } satisfies IHrmPlatformProject.ICreate,
    },
  );
  typia.assert(project);
  // 3. Create an employee in the organization
  // First, we need to create another member to be the employee
  const employeeMemberAuth = await authorize_member_join(connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      avatar_url: typia.random<(string & tags.Format<"uri">) | null>(),
      phone_number: RandomGenerator.mobile(),
      ip: typia.random<(string & tags.Format<"ipv4">) | null>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  typia.assert(employeeMemberAuth);
  const employeeMemberId = employeeMemberAuth.id;
  // Create employee record using generate function
  // Note: role_id is required but will be generated by prepare_random_hrm_platform_employee
  const employee = await generate_random_hrm_platform_member_employees_create(
    memberConnection,
    {
      body: {
        member_id: employeeMemberId,
        employment_type: "full-time",
        status: "active",
        position: RandomGenerator.name(),
      },
    },
  );
  typia.assert(employee);
  // 4. Create initial project membership with 'member' role
  const membership =
    await generate_random_hrm_platform_member_projects_members_create(
      memberConnection,
      {
        params: {
          projectId: project.id,
        },
        body: {
          hrm_platform_employee_id: employee.id,
          role: "member",
        } satisfies IHrmPlatformProjectMember.ICreate,
      },
    );
  typia.assert(membership);
  // Verify initial membership has 'member' role
  TestValidator.equals("initial role is member", membership.role, "member");
  // 5. Update the membership with role 'member' (valid value, should succeed)
  const updatedMembership1 =
    await api.functional.hrmPlatform.member.projects.members.update(
      memberConnection,
      {
        projectId: project.id,
        membershipId: membership.id,
        body: {
          role: "member",
        } satisfies IHrmPlatformProjectMember.IUpdate,
      },
    );
  typia.assert(updatedMembership1);
  // 6. Verify the membership is updated successfully with role validation
  TestValidator.equals(
    "role remains member after update",
    updatedMembership1.role,
    "member",
  );
  TestValidator.notEquals(
    "updated_at changed on update",
    membership.updated_at,
    updatedMembership1.updated_at,
  );
  // 7. Verify business logic: employee and project references are preserved
  TestValidator.equals(
    "employee id preserved",
    updatedMembership1.employee.id,
    employee.id,
  );
  TestValidator.equals(
    "project id preserved",
    updatedMembership1.project.id,
    project.id,
  );
  TestValidator.equals(
    "employee display name",
    updatedMembership1.employee.display_name,
    employee.display_name,
  );
  TestValidator.equals(
    "project name",
    updatedMembership1.project.name,
    project.name,
  );
  // 8. Test updating role from 'member' to 'project-lead' (valid value)
  const updatedMembership2 =
    await api.functional.hrmPlatform.member.projects.members.update(
      memberConnection,
      {
        projectId: project.id,
        membershipId: membership.id,
        body: {
          role: "project-lead",
        } satisfies IHrmPlatformProjectMember.IUpdate,
      },
    );
  typia.assert(updatedMembership2);
  TestValidator.equals(
    "role changed to project-lead",
    updatedMembership2.role,
    "project-lead",
  );
  TestValidator.notEquals(
    "updated_at changed on role change",
    updatedMembership1.updated_at,
    updatedMembership2.updated_at,
  );
  // 9. Verify employee summary structure (validated by typia.assert, test business fields)
  TestValidator.predicate(
    "employee has valid employment_type",
    ["full-time", "part-time", "contractor", "intern"].includes(
      updatedMembership2.employee.employment_type,
    ),
  );
  TestValidator.predicate(
    "employee has valid status",
    ["active", "deactivated"].includes(updatedMembership2.employee.status),
  );
  // 10. Verify project summary structure (validated by typia.assert, test business fields)
  TestValidator.predicate(
    "project has valid status",
    ["active", "archived", "completed"].includes(
      updatedMembership2.project.status,
    ),
  );
  TestValidator.predicate(
    "project members_count is positive",
    updatedMembership2.project.members_count > 0,
  );
  // 11. Test updating back to 'member' role to verify bidirectional changes work
  const updatedMembership3 =
    await api.functional.hrmPlatform.member.projects.members.update(
      memberConnection,
      {
        projectId: project.id,
        membershipId: membership.id,
        body: {
          role: "member",
        } satisfies IHrmPlatformProjectMember.IUpdate,
      },
    );
  typia.assert(updatedMembership3);
  TestValidator.equals(
    "role changed back to member",
    updatedMembership3.role,
    "member",
  );
  TestValidator.notEquals(
    "updated_at changed again",
    updatedMembership2.updated_at,
    updatedMembership3.updated_at,
  );
}
