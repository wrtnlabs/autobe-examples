export async function test_api_timesheet_approval_draft_status_rejected(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create manager with time:approve permission
  const managerConnection: api.IConnection = { host: connection.host };
  const managerAuth = await authorize_member_join(managerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Manager123!",
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  typia.assert(managerAuth);
  // 2. Create employee (timesheet owner)
  const employeeConnection: api.IConnection = { host: connection.host };
  const employeeAuth = await authorize_member_join(employeeConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Employee123!",
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  typia.assert(employeeAuth);
  // 3. Create employee record in organization (manager creates employee)
  const employee = await generate_random_hrm_platform_member_employees_create(
    managerConnection,
    {
      body: {
        member_id: employeeAuth.id,
      },
    },
  );
  typia.assert(employee);
  // 4. Create timelog for the employee
  const timelog =
    await generate_random_hrm_platform_member_timelogs_create(
      employeeConnection,
      {},
    );
  typia.assert(timelog);
  // 5. Create draft timesheet (NOT submitted)
  const draftTimesheet =
    await generate_random_hrm_platform_member_timesheets_create(
      employeeConnection,
      {},
    );
  typia.assert(draftTimesheet);
  // Verify timesheet is in draft status
  TestValidator.equals(
    "timesheet initial status",
    draftTimesheet.status,
    "draft",
  );
  // 6. Attempt to approve draft timesheet (should fail with 400 error)
  await TestValidator.error("approve draft timesheet should fail", async () => {
    await api.functional.hrmPlatform.member.timesheets.approve(
      managerConnection,
      {
        timesheetId: draftTimesheet.id,
      },
    );
  });
}