export async function test_api_project_member_removal_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register member and authenticate
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Test1234!",
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(member);
  // 2. Create organization (member becomes owner automatically)
  const organization =
    await generate_random_hrm_platform_member_organizations_create(
      memberConnection,
      {},
    );
  typia.assert(organization);
  // 3. Create project within the organization
  const project = await generate_random_hrm_platform_member_projects_create(
    memberConnection,
    {},
  );
  typia.assert(project);
  // 4. Generate a non-existent membership ID (valid UUID format but doesn't exist)
  const nonExistentMembershipId = typia.random<string & tags.Format<"uuid">>();
  // 5. Attempt to delete non-existent membership - should return 404
  await TestValidator.httpError(
    "non-existent membership deletion should return 404",
    404,
    async () => {
      await api.functional.hrmPlatform.member.projects.members.erase(
        memberConnection,
        {
          projectId: project.id,
          membershipId: nonExistentMembershipId,
        },
      );
    },
  );
}
