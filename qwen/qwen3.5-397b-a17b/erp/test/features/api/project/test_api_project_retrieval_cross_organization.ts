export async function test_api_project_retrieval_cross_organization(
  connection: api.IConnection,
): Promise<void> {
  // 1. First member authenticates and sets up organization
  const firstMemberConnection: api.IConnection = { host: connection.host };
  const firstMember = await authorize_member_join(firstMemberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  typia.assert(firstMember);
  // 2. First member creates organization
  const firstOrg =
    await generate_random_hrm_platform_member_organizations_create(
      firstMemberConnection,
      {
        body: {
          name: RandomGenerator.name(),
          currency: "USD",
          timezone: "Asia/Seoul",
          fiscal_start_month: 1,
        } satisfies IHrmPlatformOrganization.ICreate,
      },
    );
  typia.assert(firstOrg);
  // 3. First member creates project within their organization
  const firstProject =
    await generate_random_hrm_platform_member_projects_create(
      firstMemberConnection,
      {
        body: {
          name: RandomGenerator.name(),
          color_code: "#FF5733",
          status: "active",
        } satisfies IHrmPlatformProject.ICreate,
      },
    );
  typia.assert(firstProject);
  // 4. Second member authenticates with separate credentials
  const secondMemberConnection: api.IConnection = { host: connection.host };
  const secondMember = await authorize_member_join(secondMemberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  typia.assert(secondMember);
  // 5. Second member creates their own organization
  const secondOrg =
    await generate_random_hrm_platform_member_organizations_create(
      secondMemberConnection,
      {
        body: {
          name: RandomGenerator.name(),
          currency: "USD",
          timezone: "Asia/Seoul",
          fiscal_start_month: 1,
        } satisfies IHrmPlatformOrganization.ICreate,
      },
    );
  typia.assert(secondOrg);
  // 6. Second member attempts to retrieve first member's project (should fail with 403)
  await TestValidator.error(
    "cross-organization project access forbidden",
    async () => {
      await api.functional.hrmPlatform.member.projects.at(
        secondMemberConnection,
        {
          projectId: firstProject.id,
        },
      );
    },
  );
}
