/**
 * Test attempting to retrieve a timer that does not exist in the system.
 *
 * This test validates the system's error handling for non-existent timer resources:
 * 1. Register a new member account
 * 2. Create an organization and select it as active context
 * 3. Attempt to retrieve a timer using a valid UUID that doesn't exist
 * 4. Verify the API returns a 404 error for the non-existent resource
 *
 * This tests business logic (resource not found) not input validation,
 * as the UUID format is valid but the resource simply doesn't exist.
 */
export async function test_api_timer_retrieval_non_existent_timer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register new member account
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  typia.assert(memberAuth);
  // 2. Create organization
  const organization =
    await generate_random_hrm_platform_member_organizations_create(
      memberConnection,
      {},
    );
  typia.assert(organization);
  // 3. Select the created organization as active context
  const selectedOrg =
    await api.functional.hrmPlatform.member.organizations.select(
      memberConnection,
      {
        organizationId: organization.id,
      },
    );
  typia.assert(selectedOrg);
  // 4. Attempt to retrieve a non-existent timer with valid UUID format
  const nonExistentTimerId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "retrieve non-existent timer should return 404",
    async () => {
      await api.functional.hrmPlatform.member.timers.at(memberConnection, {
        timerId: nonExistentTimerId,
      });
    },
  );
}
