export async function test_api_timer_update_no_active_timer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as member
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  typia.assert(memberAuth);
  // 2. Create organization (member automatically becomes employee)
  const organization =
    await generate_random_hrm_platform_member_organizations_create(
      memberConnection,
      {},
    );
  typia.assert(organization);
  // 3. Create project within the organization
  const project = await generate_random_hrm_platform_member_projects_create(
    memberConnection,
    {},
  );
  typia.assert(project);
  // 4. Attempt to update timer WITHOUT starting one first
  // This should fail because no active timer exists for this employee
  // The business rule requires an active timer session before update is allowed
  await TestValidator.error(
    "update timer without active timer should fail",
    async () => {
      await api.functional.hrmPlatform.member.timers.patch(memberConnection, {
        body: {
          description: "Test description update",
        } satisfies IHrmPlatformTimer.IUpdate,
      });
    },
  );
}
