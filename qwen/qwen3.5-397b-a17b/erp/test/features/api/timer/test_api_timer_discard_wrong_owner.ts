export async function test_api_timer_discard_wrong_owner(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as member A (the attempted discarder)
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberA = await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  typia.assert(memberA);
  // 2. Create a timer for member A (not the target timer)
  const memberATimer = await generate_random_hrm_platform_member_timers_create(
    memberAConnection,
    {},
  );
  typia.assert(memberATimer);
  // 3. Authenticate as member B (the actual timer owner)
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberB = await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  typia.assert(memberB);
  // 4. Create a timer for member B (this is the target timer)
  const memberBTimer = await generate_random_hrm_platform_member_timers_create(
    memberBConnection,
    {},
  );
  typia.assert(memberBTimer);
  // 5. Store member B's timer ID for the deletion attempt
  const targetTimerId = memberBTimer.id;
  // 6. Try to delete member B's timer while authenticated as member A
  // This should fail with 403 Forbidden or 404 Not Found
  await TestValidator.error(
    "member A cannot discard member B's timer",
    async () => {
      await api.functional.hrmPlatform.member.timers.erase(memberAConnection, {
        timerId: targetTimerId,
      });
    },
  );
}
