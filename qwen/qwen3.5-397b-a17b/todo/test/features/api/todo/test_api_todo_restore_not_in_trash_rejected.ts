export async function test_api_todo_restore_not_in_trash_rejected(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate as a member
  const memberConnection: api.IConnection = { host: connection.host };
  const auth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IMultiUserTodoMember.IJoin,
  });
  typia.assert(auth);
  // 2. Create an active todo (NOT deleted, deleted_at is null)
  const todo = await generate_random_multi_user_todo_member_todos_create(
    memberConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 1 }),
      } satisfies IMultiUserTodoTodo.ICreate,
    },
  );
  typia.assert(todo);
  // Verify the todo is in active state (not deleted)
  TestValidator.predicate(
    "todo should be active (not deleted)",
    () => todo.deleted_at === null,
  );
  // 3. Attempt to restore the active todo (should fail)
  // The restore endpoint should reject because todo.deleted_at is null
  await TestValidator.error(
    "restoring non-deleted todo should be rejected",
    async () => {
      await api.functional.multiUserTodo.member.todos.trash.restore(
        memberConnection,
        {
          todoId: todo.id,
        },
      );
    },
  );
}
