export async function test_api_member_session_cross_user_access_denied(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Register first member account (member1)
  const member1Connection: api.IConnection = { host: connection.host };
  const member1Auth = await authorize_member_join(member1Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies ITodoAppMember.IJoin,
  });
  typia.assert(member1Auth);
  // Step 2: Register second member account (member2)
  const member2Connection: api.IConnection = { host: connection.host };
  await authorize_member_join(member2Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies ITodoAppMember.IJoin,
  });
  // Step 3: Attempt to access member1's session using member2's connection
  // This should fail with 404 Not Found to enforce data isolation
  await TestValidator.httpError(
    "member2 cannot access member1's session",
    404,
    async () => {
      await api.functional.todoApp.member.sessions.at(member2Connection, {
        sessionId: member1Auth.id,
      });
    },
  );
}
