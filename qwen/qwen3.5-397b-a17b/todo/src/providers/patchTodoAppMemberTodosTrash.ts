export async function patchTodoAppMemberTodosTrash(props: {
  member: MemberPayload;
  body: ITodoAppTodo.IRequest;
}): Promise<IPageITodoAppTodo.ISummary> {
  const page = props.body.page ?? 1;
  const limit = props.body.limit ?? 20;
  const skip = (page - 1) * limit;
  const whereInput: Prisma.todo_app_todosWhereInput = {
    deleted_at: { not: null },
    todo_app_member_id: props.member.id,
    ...(props.body.completed === "complete" && { completed: true }),
    ...(props.body.completed === "incomplete" && { completed: false }),
  } satisfies Prisma.todo_app_todosWhereInput;
  const orderByInput: Prisma.todo_app_todosOrderByWithRelationInput =
    props.body.sort === "started_at"
      ? { started_at: { sort: props.body.order ?? "asc", nulls: "last" } }
      : props.body.sort === "due_at"
        ? { due_at: { sort: props.body.order ?? "asc", nulls: "last" } }
        : { created_at: props.body.order ?? "asc" };
  const data = await MyGlobal.prisma.todo_app_todos.findMany({
    where: whereInput,
    skip,
    take: limit,
    orderBy: orderByInput,
    ...TodoAppTodoAtSummaryTransformer.select(),
  });
  const total = await MyGlobal.prisma.todo_app_todos.count({
    where: whereInput,
  });
  return {
    data: await ArrayUtil.asyncMap(
      data,
      TodoAppTodoAtSummaryTransformer.transform,
    ),
    pagination: {
      current: page,
      limit: limit,
      records: total,
      pages: Math.ceil(total / limit),
    } satisfies IPage.IPagination,
  };
}
