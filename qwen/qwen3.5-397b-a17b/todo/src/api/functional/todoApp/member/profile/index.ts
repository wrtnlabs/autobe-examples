/**
 * Retrieve the authenticated member's profile information.
 *
 * Returns the current user's profile data including display name and account metadata. This operation requires authentication and returns only the requesting member's own profile - users cannot access other users' profiles in this private todo application.
 *
 * The profile contains the member's display name which identifies them within the application interface. All profile data is private and isolated per user.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query the todo_app_members table for the authenticated member's record using session context.
 *
 * Retrieve display_name, created_at, and updated_at fields. Exclude password_hash and email from response for security.
 *
 * Ensure the member account is not soft-deleted (deleted_at is null). If deleted_at is set, return 401 Unauthorized.
 *
 * Return single member profile record with 200 OK status.
 * @path /todoApp/member/profile
 * @accessor api.functional.todoApp.member.profile.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = ITodoAppMember.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/member/profile",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/member/profile";
  export const random = (): ITodoAppMember.ISummary =>
    typia.random<ITodoAppMember.ISummary>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Update the authenticated user's profile information.
 *
 * This operation allows members to update their profile display name. The display name is the only profile attribute that can be modified through this endpoint. Email and password are not editable through this endpoint - password changes require a separate operation.
 *
 * The updated profile data is returned in the response to confirm the changes. All other profile fields remain unchanged.
 *
 * @param props.connection
 * @param props.body Profile update data containing the new display name value.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Update the display_name field for the authenticated user in todo_app_members table.
 *
 * 1. Extract authenticated user ID from session context
 * 2. Validate display_name if provided (check length constraints per business rules)
 * 3. Update only the display_name field for the member record
 * 4. Return the updated ITodoAppMember entity
 * 5. Handle concurrent update conflicts with optimistic locking if needed
 *
 * Edge cases:
 * - If display_name is not provided in request, keep existing value
 * - Validate display_name meets length requirements
 * - Ensure soft-deleted accounts cannot update profile
 * @path /todoApp/member/profile
 * @accessor api.functional.todoApp.member.profile.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Profile update data containing the new display name value.
     */
    body: ITodoAppMember.IUpdate;
  };
  export type Body = ITodoAppMember.IUpdate;
  export type Response = ITodoAppMember;

  export const METADATA = {
    method: "PUT",
    path: "/todoApp/member/profile",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/member/profile";
  export const random = (): ITodoAppMember => typia.random<ITodoAppMember>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
