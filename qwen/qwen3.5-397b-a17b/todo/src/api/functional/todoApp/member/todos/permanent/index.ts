/**
 * Permanently delete a todo item from the trash along with all associated edit history entries.
 *
 * This operation performs irreversible permanent deletion of a soft-deleted todo. When executed, the system removes the todo record from the database and automatically cascades the deletion to all associated edit history entries in the todo_app_todo_histories table. This ensures no orphaned history records remain after permanent deletion.
 *
 * The operation validates that the requesting member owns the todo before proceeding. Cross-user permanent deletion attempts are rejected to maintain data privacy and isolation boundaries. Only todos that have been soft-deleted (have a deleted_at timestamp) should be permanently deleted through this endpoint.
 *
 * This endpoint is specifically for permanent removal from trash. For soft deletion (moving to trash), use the standard todo delete endpoint. For restoring todos from trash, use the restore endpoint. Once permanent deletion is completed, the todo and its entire edit history cannot be recovered.
 *
 * The cascade deletion ensures referential integrity between todos and their history entries. All modification records, including title changes, description updates, and date modifications, are removed together with the parent todo.
 *
 * @param props.connection
 * @param props.todoId Target todo's ID (UUID format). Must belong to the requesting member and be in trash (soft-deleted).
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query the todo_app_todos table to verify the todo exists and is owned by the requesting member. Validate that the todo has a deleted_at timestamp (is in trash). Begin a database transaction. Delete the todo record from todo_app_todos table. The Cascade constraint on the histories relation automatically removes all associated todo_app_todo_histories entries. Commit the transaction. Return 204 No Content on success. Return 404 if todo not found or doesn't belong to member. Return 400 if todo is not soft-deleted (not in trash). Ensure the operation is idempotent - multiple permanent deletion requests for the same todo should not cause errors after the first successful deletion.
 * @path /todoApp/member/todos/:todoId/permanent
 * @accessor api.functional.todoApp.member.todos.permanent.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Target todo's ID (UUID format). Must belong to the requesting member and be in trash (soft-deleted).
     */
    todoId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/todoApp/member/todos/:todoId/permanent",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/member/todos/${encodeURIComponent(props.todoId ?? "null")}/permanent`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
