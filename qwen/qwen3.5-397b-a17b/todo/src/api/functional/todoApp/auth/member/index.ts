/**
 * Register a new member account with email, password, and display name.
 *
 * This operation creates a new authenticated user account in the todo_app_members table. The email serves as the unique login identifier and must not already exist in the system. The password is securely hashed before storage. The display name is the user-facing identifier within the application.
 *
 * Upon successful registration, the system generates a JWT access token and refresh token, stores them in todo_app_member_sessions with client information (IP address, page href, referrer) for security auditing, and returns both tokens in the response. The member can immediately use the access token for authenticated API requests.
 *
 * Email validation ensures proper format. Password must meet security requirements (minimum length, complexity). Duplicate email addresses return a 409 conflict error. All timestamps (created_at, updated_at) are set automatically.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration credentials and initial profile data for new member account creation.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Create a new member account with email, password, and
 *   display name. Validate email format and uniqueness, hash password securely,
 *   create member record in todo_app_members table, generate JWT access and
 *   refresh tokens, create session record in todo_app_member_sessions table
 *   with client info (ip, href, referrer), return tokens in IAuthorized
 *   response. Handle duplicate email with 409 conflict. Password must meet
 *   minimum security requirements.
 * @path /todoApp/auth/member/join
 * @accessor api.functional.todoApp.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
