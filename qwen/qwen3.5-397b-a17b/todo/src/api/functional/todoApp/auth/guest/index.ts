/**
 * Register a new guest account using device fingerprint for anonymous access.
 *
 * Creates a guest account identified by the unique device fingerprint. The system generates JWT access and refresh tokens for authenticated guest sessions. Access tokens are short-lived for security, while refresh tokens allow obtaining new access tokens without re-registration.
 *
 * The device fingerprint must be unique across all guest accounts. If a guest account already exists for the provided fingerprint, the operation may return existing tokens or create a new session depending on implementation policy.
 *
 * Session metadata including IP address, page URL, and referrer are captured for audit and security purposes. Guest sessions have automatic expiration times for security.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Device fingerprint for guest account identification.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Create a guest account using device fingerprint for anonymous access. Validate device_fingerprint is provided and unique. Create todo_app_guests record with generated UUID. Generate JWT access token (short-lived, e.g., 1 hour) and refresh token (longer-lived, e.g., 7 days). Create todo_app_guest_sessions record linking guest to tokens with IP, href, referrer metadata. Set expired_at based on token lifetime. Return tokens in IAuthorized response. Handle duplicate device_fingerprint by returning existing guest tokens or creating new session.
 * @path /todoApp/auth/guest/join
 * @accessor api.functional.todoApp.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
