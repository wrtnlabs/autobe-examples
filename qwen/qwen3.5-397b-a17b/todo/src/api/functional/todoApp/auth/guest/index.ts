/**
 * Register a new guest account for anonymous users accessing the todo application.
 *
 * This endpoint creates a temporary guest identity using the device fingerprint as the unique identifier. Guest accounts allow unauthenticated users to explore the application and maintain session continuity without requiring email/password registration. The device fingerprint persists across sessions until the user either registers as a member or the guest account is cleaned up.
 *
 * The operation validates that the provided device fingerprint is not already in use by checking the unique constraint on the device_fingerprint column in the todo_app_guests table. If the fingerprint already exists, the operation returns a conflict error. Upon successful validation, a new guest record is created with the current timestamp in the created_at field.
 *
 * After creating the guest account, the service generates JWT access and refresh tokens for authentication. A guest session is also created in the todo_app_guest_sessions table to track the connection metadata including IP address, href, and referrer. The session includes an expiration timestamp for security lifecycle management.
 *
 * This operation is the entry point for guest users. After joining, guests can use the returned access token to authenticate subsequent API requests. When the access token expires, guests can use the refresh token with the /auth/guest/refresh endpoint to obtain new tokens without re-joining.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest registration information with device fingerprint for unique identification.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Create a new guest account using device fingerprint for anonymous access. The service validates that the device fingerprint is unique (not already registered), creates a new guest record with current timestamp, generates JWT access and refresh tokens, creates an initial guest session record with connection metadata (IP, href, referrer), and returns the authorized response with tokens and guest information. The device fingerprint serves as the primary identification mechanism for guest users who haven't registered as members yet.
 * @path /todoApp/auth/guest/join
 * @accessor api.functional.todoApp.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
