/**
 * Creates a new guest account or retrieves existing guest identified by device fingerprint, establishing an authentication session for unauthenticated visitor access.
 *
 * This endpoint serves as the entry point for guest users who have not registered but need temporary access to the application. The device fingerprint uniquely identifies the guest's device or browser, allowing the system to maintain session state across requests without requiring email/password credentials.
 *
 * The operation creates a new todo_app_guests record if the device fingerprint is unrecognized, or returns the existing guest account if the fingerprint has been seen before. A new todo_app_guest_sessions record is always created to track the current session, storing connection metadata including the client IP address, current page URL (href), and referrer URL for security auditing purposes.
 *
 * The guest account includes timestamps for creation (created_at), last update (updated_at), and optional soft deletion (deleted_at). Sessions have explicit expiration timestamps (expired_at) that determine when the authentication tokens become invalid. Guest sessions typically have shorter lifespans than member sessions due to their temporary nature.
 *
 * Upon successful guest creation or retrieval, the endpoint returns JWT access and refresh tokens along with session expiration information. The access token is used for authenticated requests during the session, while the refresh token enables session renewal without requiring re-identification. This operation is essential for the guest-to-member transition pathway, as the guest ID can be referenced during registration to link the new member account to previous guest activity.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Device fingerprint and connection metadata for guest identification and session tracking.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Create a new guest account identified by device fingerprint and establish an initial authentication session. The service generates a unique guest ID, stores the device fingerprint for future recognition, and creates a session record with connection metadata (IP address, current page URL, referrer). Returns JWT access and refresh tokens along with session expiration time. The device fingerprint must be unique - if a guest account already exists for the provided fingerprint, the existing guest is returned with a new session created. Session expiration is set according to guest session policy (typically shorter than member sessions). Implementation: 1) Validate device fingerprint is provided and not empty, 2) Query existing guest by device_fingerprint, 3) If not found, create new todo_app_guests record with unique ID and current timestamps, 4) Create todo_app_guest_sessions record with session metadata and calculated expiration, 5) Generate JWT access token containing guest ID and session ID, 6) Generate JWT refresh token for session renewal, 7) Return authorized response with tokens and expiration.
 * @path /todoApp/auth/guest/join
 * @accessor api.functional.todoApp.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
