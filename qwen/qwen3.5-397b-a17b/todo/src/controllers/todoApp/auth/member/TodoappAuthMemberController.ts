import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";
import { postTodoAppAuthMemberJoin } from "../../../../providers/postTodoAppAuthMemberJoin";
import { postTodoAppAuthMemberLogin } from "../../../../providers/postTodoAppAuthMemberLogin";
import { postTodoAppAuthMemberRefresh } from "../../../../providers/postTodoAppAuthMemberRefresh";

@Controller("/todoApp/auth/member")
export class TodoappAuthMemberController {
  /**
   * Register a new member account with email, password, and display name.
   *
   * This operation creates a new authenticated user account in the todo_app_members table. The email serves as the unique login identifier and must not already exist in the system. The password is securely hashed before storage. The display name is the user-facing identifier within the application.
   *
   * Upon successful registration, the system generates a JWT access token and refresh token, stores them in todo_app_member_sessions with client information (IP address, page href, referrer) for security auditing, and returns both tokens in the response. The member can immediately use the access token for authenticated API requests.
   *
   * Email validation ensures proper format. Password must meet security requirements (minimum length, complexity). Duplicate email addresses return a 409 conflict error. All timestamps (created_at, updated_at) are set automatically.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials and initial profile data for new member account creation.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new member account with email, password, and display name. Validate email format and uniqueness, hash password securely, create member record in todo_app_members table, generate JWT access and refresh tokens, create session record in todo_app_member_sessions table with client info (ip, href, referrer), return tokens in IAuthorized response. Handle duplicate email with 409 conflict. Password must meet minimum security requirements.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppMember.IJoin,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a member with email and password to obtain JWT tokens.
   *
   * This operation validates member credentials against the todo_app_members table. The email is looked up and the provided password is compared against the stored password_hash using secure bcrypt verification. The account must be active (deleted_at is null) to successfully authenticate.
   *
   * Upon successful authentication, the system generates a new JWT access token (short-lived, typically 15-30 minutes) and refresh token (longer-lived, typically 7-30 days), creates a session record in todo_app_member_sessions with client information (IP address, page href, referrer) for security auditing, and returns both tokens in the response.
   *
   * Invalid email or password returns 401 unauthorized. Accounts that have been soft deleted (deleted_at is set) return 403 forbidden. The access token is used in the Authorization header for subsequent API requests.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Authentication credentials for member login.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Authenticate member with email and password. Query todo_app_members by email, verify password_hash matches provided password using bcrypt comparison, check account is not soft deleted (deleted_at is null), generate new JWT access and refresh tokens, create session record in todo_app_member_sessions with client info (ip, href, referrer, expired_at), return tokens in IAuthorized response. Handle invalid credentials with 401 unauthorized. Handle deleted account with 403 forbidden.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppMember.ILogin,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT access and refresh tokens using a valid refresh token.
   *
   * This operation allows members to obtain new authentication tokens without re-entering credentials. The provided refresh token is validated against the todo_app_member_sessions table. The session must exist, not be expired (expired_at must be in the future), and belong to an active member account (deleted_at is null).
   *
   * Upon successful validation, the system generates a new JWT access token and refresh token pair, updates the session record in todo_app_member_sessions with the new tokens, and returns them in the response. This enables continuous authenticated sessions without requiring repeated login.
   *
   * Invalid or expired refresh tokens return 401 unauthorized. Members whose accounts have been soft deleted return 403 forbidden. The refresh token flow maintains session continuity while enforcing security through token expiration.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new authentication tokens.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Refresh JWT tokens using a valid refresh token. Query todo_app_member_sessions by refresh_token, verify session exists and is not expired (expired_at > now), verify the session belongs to an active member (deleted_at is null), generate new JWT access and refresh tokens, update the session record with new tokens, return new tokens in IAuthorized response. Handle invalid or expired refresh token with 401 unauthorized. Optionally rotate refresh tokens by invalidating the old one.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppMember.IRefresh,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
