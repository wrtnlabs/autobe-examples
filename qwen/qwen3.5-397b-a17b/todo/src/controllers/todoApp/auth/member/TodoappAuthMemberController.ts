import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";
import { postTodoAppAuthMemberJoin } from "../../../../providers/postTodoAppAuthMemberJoin";
import { postTodoAppAuthMemberLogin } from "../../../../providers/postTodoAppAuthMemberLogin";
import { postTodoAppAuthMemberRefresh } from "../../../../providers/postTodoAppAuthMemberRefresh";

@Controller("/todoApp/auth/member")
export class TodoappAuthMemberController {
  /**
   * Creates a new member account in the todo application using email and password credentials.
   *
   * This operation registers a new user by creating a record in the todo_app_members table with the provided email address and bcrypt-hashed password. The email must be unique across all member accounts. The display name is required for the user's profile.
   *
   * Upon successful registration, the system generates JWT access and refresh tokens for immediate authentication. The access token is used for subsequent API requests, while the refresh token can be used to obtain new access tokens when the current one expires.
   *
   * Additionally, an email verification record is created in the todo_app_member_email_verifications table with a unique token. This verification token should be sent to the user's email address to confirm their email ownership. The verification token has an expiration time for security purposes.
   *
   * The operation returns the member's authorized session information including both tokens, allowing the user to immediately start using the application while email verification can be completed separately.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration information for new member account creation
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Register a new member account with email and password. The service validates email uniqueness, hashes the password using bcrypt, creates the member record, and generates initial JWT tokens. An email verification token is also created and should be sent to the user's email address. The access token and refresh token are returned for immediate authentication.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppMember.IJoin,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates a registered member using email and password credentials.
   *
   * This operation validates the provided email address and password against the todo_app_members table. The password is verified using bcrypt comparison against the stored password_hash. If credentials are valid, a new session is created.
   *
   * A session record is inserted into the todo_app_member_sessions table containing the JWT access token and refresh token. The session also captures connection metadata including the client IP address, the URL href where login was initiated, and the referrer URL for security auditing and session tracking.
   *
   * The session has an expiration timestamp (expired_at) that determines when the tokens become invalid. Multiple sessions can exist for the same member across different devices or browsers.
   *
   * Upon successful authentication, the operation returns the member's authorized session information with both access and refresh tokens, enabling the client to make authenticated API requests.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials for member authentication
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Authenticate member credentials and establish a session. The service validates email and password, creates a session record in todo_app_member_sessions, and returns JWT tokens. The session tracks IP address, href, and referrer for security auditing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppMember.ILogin,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews authentication tokens using a valid refresh token.
   *
   * This operation allows members to obtain new JWT access and refresh tokens when their current access token has expired or is about to expire. The refresh token is validated against the todo_app_member_sessions table to ensure it exists and has not expired.
   *
   * The service checks the expired_at timestamp in the session record to verify the refresh token is still valid. If the refresh token has expired, the operation fails and the user must re-authenticate by logging in again.
   *
   * Upon successful validation, new access and refresh tokens are generated. The old session record may be updated with the new tokens or invalidated depending on the security policy (single-session vs multi-session support).
   *
   * This operation enables seamless continued access to the application without requiring the user to re-enter credentials, while maintaining security through token expiration and rotation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access tokens
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Refresh an expired or expiring access token using a valid refresh token. The service validates the refresh token against the todo_app_member_sessions table, checks expiration, and issues new tokens. The old session may be invalidated depending on security policy.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppMember.IRefresh,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
