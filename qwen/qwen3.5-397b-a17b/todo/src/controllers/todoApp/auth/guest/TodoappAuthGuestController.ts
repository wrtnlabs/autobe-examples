import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppGuest } from "../../../../api/structures/ITodoAppGuest";
import { postTodoAppAuthGuestJoin } from "../../../../providers/postTodoAppAuthGuestJoin";
import { postTodoAppAuthGuestRefresh } from "../../../../providers/postTodoAppAuthGuestRefresh";

@Controller("/todoApp/auth/guest")
export class TodoappAuthGuestController {
  /**
   * Register a new guest account using device fingerprint for anonymous access.
   *
   * Creates a guest account identified by the unique device fingerprint. The system generates JWT access and refresh tokens for authenticated guest sessions. Access tokens are short-lived for security, while refresh tokens allow obtaining new access tokens without re-registration.
   *
   * The device fingerprint must be unique across all guest accounts. If a guest account already exists for the provided fingerprint, the operation may return existing tokens or create a new session depending on implementation policy.
   *
   * Session metadata including IP address, page URL, and referrer are captured for audit and security purposes. Guest sessions have automatic expiration times for security.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Device fingerprint for guest account identification.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Create a guest account using device fingerprint for anonymous access. Validate device_fingerprint is provided and unique. Create todo_app_guests record with generated UUID. Generate JWT access token (short-lived, e.g., 1 hour) and refresh token (longer-lived, e.g., 7 days). Create todo_app_guest_sessions record linking guest to tokens with IP, href, referrer metadata. Set expired_at based on token lifetime. Return tokens in IAuthorized response. Handle duplicate device_fingerprint by returning existing guest tokens or creating new session.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppGuest.IJoin,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh guest authentication tokens using a valid refresh token.
   *
   * Exchanges a valid refresh token for a new access token and refresh token pair. This operation allows guests to maintain authenticated sessions without re-registering with their device fingerprint.
   *
   * The refresh token must be valid, unexpired, and match an existing session in the database. Invalid or expired tokens result in authentication failure. The operation updates the session expiration timestamp to extend the guest's access period.
   *
   * Token rotation may be implemented for enhanced security, where each refresh invalidates the previous refresh token and issues a new one.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access credentials.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Refresh guest session tokens using valid refresh token. Validate refresh token exists in todo_app_guest_sessions and is not expired. Verify token signature and expiration. Generate new access token and optionally new refresh token. Update session expired_at timestamp. Return new token pair in IAuthorized response. Invalidate old refresh token if rotating. Handle expired/invalid tokens with 401 error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppGuest.IRefresh,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
