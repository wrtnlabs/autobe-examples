import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppMemberSession } from "../../../../api/structures/IPageITodoAppMemberSession";
import { ITodoAppMemberSession } from "../../../../api/structures/ITodoAppMemberSession";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { getTodoAppGuestSessionsSessionId } from "../../../../providers/getTodoAppGuestSessionsSessionId";
import { patchTodoAppGuestSessions } from "../../../../providers/patchTodoAppGuestSessions";

@Controller("/todoApp/guest/sessions")
export class TodoappGuestSessionsController {
  /**
   * Retrieve a paginated list of the authenticated member's active login sessions.
   *
   * This endpoint allows members to view their current and recent login sessions for security auditing. Each session record includes the access token metadata, client information (IP address, login page), and timestamps for creation and expiration.
   *
   * Sessions are filtered to show only those belonging to the authenticated member. The response supports pagination for members with many session records. Use this endpoint to display active devices/sessions in account security settings.
   *
   * @param connection
   * @param body Search criteria including pagination parameters (page, limit), optional status filter (active/expired), and date range filters for session creation time.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query todo_app_member_sessions table filtered by the authenticated member's ID from session context.
   * Apply pagination parameters (page, limit) from request body.
   * Optionally filter by session status (active/expired) based on expired_at comparison with current timestamp.
   * Join with todo_app_members if member profile data needed (typically not required for session list).
   * Return sessions sorted by created_at DESC (most recent first).
   * Ensure authorization middleware validates member authentication before query execution.
   * Handle edge case: member has no sessions (return empty array with pagination metadata).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: ITodoAppMemberSession.IRequest,
  ): Promise<IPageITodoAppMemberSession.ISummary> {
    try {
      return await patchTodoAppGuestSessions({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information about a specific member session.
   *
   * This endpoint returns the session metadata including creation time, expiration time, and client information (IP address, page href, referrer). The session tokens (access_token, refresh_token) are not exposed in the response for security reasons.
   *
   * Members can use this endpoint to view their active sessions and manage their authenticated access. Session information is useful for understanding login history and identifying unrecognized devices or locations.
   *
   * @param connection
   * @param sessionId Session UUID identifier (scoped to authenticated member's sessions only).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query the todo_app_member_sessions table by the provided sessionId UUID.
   *
   * Validate that the sessionId exists and belongs to the authenticated member (data isolation - users can only access their own sessions).
   *
   * Return the session record with all fields except the actual token values (access_token, refresh_token should be omitted or masked in response for security).
   *
   * Handle 404 if session not found or doesn't belong to the member.
   * Handle 403 if member tries to access another member's session.
   *
   * Include member relationship data if needed for the response type.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMemberSession> {
    try {
      return await getTodoAppGuestSessionsSessionId({
        guest,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
