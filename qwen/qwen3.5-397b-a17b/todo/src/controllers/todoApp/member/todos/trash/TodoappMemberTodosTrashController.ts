import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageITodoAppTodo } from "../../../../../api/structures/IPageITodoAppTodo";
import { ITodoAppTodo } from "../../../../../api/structures/ITodoAppTodo";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchTodoAppMemberTodosTrash } from "../../../../../providers/patchTodoAppMemberTodosTrash";

@Controller("/todoApp/member/todos/trash")
export class TodoappMemberTodosTrashController {
  /**
   * Retrieve a paginated list of soft-deleted todos from the trash.
   *
   * This operation provides access to todos that have been moved to trash through soft deletion. Only the owning member can view their own deleted todos, ensuring strict data isolation and privacy. The trash list excludes all active (non-deleted) todos and shows only items where the deleted_at timestamp is set.
   *
   * Supports comprehensive pagination with configurable page sizes, filtering by completion status, and multiple sorting options including creation date, due date, title, and completion status. The response includes todo summary information optimized for list displays, containing essential fields like title, completion status, and deletion timestamp.
   *
   * This endpoint is essential for trash management workflows, allowing users to review deleted items before deciding to restore them or permanently delete them. Pre-execution of this operation is required to obtain the list of deleted todos, after which individual todo details can be retrieved by specifying the todo ID in a separate GET operation, or restoration/permanent deletion can be performed through dedicated endpoints.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for trash list
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query todo_app_todos table with member_id filter and deleted_at IS NOT NULL condition.
   * Apply pagination using cursor-based or offset-based approach for large result sets.
   * Support filtering by completed status boolean field.
   * Support sorting by created_at, due_date, title, completed fields with ascending/descending order.
   * Join with todo_app_members to verify ownership (implicit through member_id filter from authentication context).
   * Exclude todo_app_todo_histories from this query (history accessed separately).
   * Return IPageITodoAppTodo.ISummary with pagination metadata and summary data array.
   * Handle edge cases: empty trash returns empty data array with pagination info, null date fields handled gracefully in sorting.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppTodo.IRequest,
  ): Promise<IPageITodoAppTodo.ISummary> {
    try {
      return await patchTodoAppMemberTodosTrash({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
