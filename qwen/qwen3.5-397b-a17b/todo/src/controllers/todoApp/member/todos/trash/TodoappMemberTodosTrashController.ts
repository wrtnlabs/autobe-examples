import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppTodo } from "../../../../../api/structures/IPageITodoAppTodo";
import { ITodoAppTodo } from "../../../../../api/structures/ITodoAppTodo";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteTodoAppMemberTodosTrashTodoId } from "../../../../../providers/deleteTodoAppMemberTodosTrashTodoId";
import { patchTodoAppMemberTodosTrash } from "../../../../../providers/patchTodoAppMemberTodosTrash";
import { putTodoAppMemberTodosTrashTodoIdRestore } from "../../../../../providers/putTodoAppMemberTodosTrashTodoIdRestore";

@Controller("/todoApp/member/todos/trash")
export class TodoappMemberTodosTrashController {
  /**
   * Retrieve a paginated list of soft-deleted todos from the authenticated member's trash.
   *
   * This endpoint provides access to todos that have been soft-deleted by the member. Soft-deleted todos have their deleted_at timestamp set and no longer appear in the normal todo list. Members can view these deleted todos in the trash to review, restore, or permanently delete them.
   *
   * The operation supports filtering by completion status (completed or incomplete) and sorting by creation date, start date, or due date. When sorting by start date or due date, todos without those dates appear at the end of the list. Results are paginated to handle large numbers of deleted todos efficiently.
   *
   * Only the authenticated member can access their own trash. The system enforces strict data isolation - members cannot view other users' deleted todos under any circumstances. This endpoint requires member authentication and will reject unauthenticated or guest requests.
   *
   * Related operations: POST /todos/{todoId}/restore to restore a deleted todo, DELETE /todos/{todoId}/permanent to permanently delete from trash, PATCH /todos for viewing active todos.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering deleted todos in trash
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query todo_app_todos table with WHERE deleted_at IS NOT NULL AND todo_app_member_id = {authenticated_member_id}.
   *
   * Apply pagination from request body (page, limit) with cursor-based or offset-based pagination.
   *
   * Support filtering by completion status (completed field) if provided in request.
   *
   * Support sorting by created_at, started_at, or due_at with ascending/descending order. Records with NULL started_at or due_at should appear at the end when sorting by those fields.
   *
   * Join with todo_app_todo_edit_histories is NOT required for list view - only basic todo fields needed.
   *
   * Ensure data isolation: only return todos belonging to the authenticated member.
   *
   * Return 401 if user is not authenticated, 200 with empty data array if no deleted todos exist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppTodo.IRequest,
  ): Promise<IPageITodoAppTodo.ISummary> {
    try {
      return await patchTodoAppMemberTodosTrash({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Restore a soft-deleted todo from the trash back to the active todo list.
   *
   * This operation allows members to recover their deleted todos by clearing the soft-delete timestamp. When a todo is restored, it returns to the normal todo list with all its original properties intact including title, description, start date, due date, completion status, and edit history. The creation date of the todo remains unchanged after restoration, maintaining the original creation timeline.
   *
   * The operation validates that the todo exists, belongs to the authenticated member, and is currently in the trash (soft-deleted). If the todo is not deleted or belongs to another user, the request is rejected with an access denied error. Once restored, the todo behaves identically to todos that were never deleted and can be edited, completed, or deleted again.
   *
   * This endpoint is part of the trash management workflow. Members typically use GET /todos/trash to view their deleted todos before deciding which ones to restore. For permanent removal instead of recovery, use DELETE /todos/trash/{todoId}.
   *
   * @param connection
   * @param todoId Target todo's ID to restore from trash
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query todo_app_todos table by todoId with member ownership verification. Validate that the todo exists and belongs to the authenticated member. Verify the todo is currently soft-deleted (deleted_at IS NOT NULL). If not deleted, reject the request as the todo is already active. Update the todo by setting deleted_at to NULL, effectively restoring it to active status. The todo's created_at timestamp remains unchanged per business requirements. Return the complete restored todo entity. Ensure transaction safety - if any validation fails, rollback without changes. Related operations: GET /todos/trash (list deleted todos), DELETE /todos/trash/{todoId} (permanent delete).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId/restore")
  public async restore(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodo> {
    try {
      return await putTodoAppMemberTodosTrashTodoIdRestore({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a todo from the trash, removing it and all associated edit history records from the system.
   *
   * This operation performs irreversible deletion of a soft-deleted todo that currently resides in the user's trash. The todo must have been previously soft-deleted (deleted_at IS NOT NULL) and must be owned by the authenticated member. Upon successful execution, the todo record is permanently removed from the todo_app_todos table, and all associated edit history entries in todo_app_todo_edit_histories are cascade-deleted.
   *
   * This endpoint is specifically for permanent deletion from trash, distinct from the initial soft-delete operation that moves active todos to trash. Once this operation completes, the todo and its complete edit history cannot be recovered.
   *
   * The operation validates that the todo exists, belongs to the authenticated member, and is currently in soft-deleted state. If any of these conditions fail, the request is rejected with an appropriate error response.
   *
   * Related operations: PATCH /todos/trash for viewing trash contents, PATCH /todos/trash/{todoId}/restore for recovering deleted todos.
   *
   * @param connection
   * @param todoId Target todo's unique identifier (UUID format). The todo must be soft-deleted and owned by the authenticated member.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the todo_app_todos table filtering by id = {todoId} AND todo_app_member_id = authenticated_member_id AND deleted_at IS NOT NULL.
   *
   * If no record found, reject with 404 error (todo not found in trash).
   *
   * Begin database transaction.
   *
   * Delete the todo record from todo_app_todos table.
   *
   * Cascade delete automatically removes all related todo_app_todo_edit_histories records via foreign key constraint (onDelete: Cascade).
   *
   * Commit transaction.
   *
   * Return 204 No Content response on success.
   *
   * Validate ownership before deletion to prevent unauthorized access. Ensure the todo is actually soft-deleted (in trash) before allowing permanent deletion.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppMemberTodosTrashTodoId({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
