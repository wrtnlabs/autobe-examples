import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppMemberSession } from "../../../../api/structures/IPageITodoAppMemberSession";
import { ITodoAppMemberSession } from "../../../../api/structures/ITodoAppMemberSession";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberSessionsSessionId } from "../../../../providers/getTodoAppMemberSessionsSessionId";
import { patchTodoAppMemberSessions } from "../../../../providers/patchTodoAppMemberSessions";

@Controller("/todoApp/member/sessions")
export class TodoappMemberSessionsController {
  /**
   * Retrieve a filtered and paginated list of active member sessions for the authenticated user.
   *
   * This operation allows members to view their current login sessions across different devices and locations. Each session includes connection metadata such as IP address, initiation URL, referrer, and expiration time, enabling users to monitor account security and identify unauthorized access.
   *
   * Sessions are filtered to only show those belonging to the authenticated member, ensuring complete data isolation. The endpoint supports pagination for users with many active sessions and provides sorting options by creation date or expiration time.
   *
   * This operation is essential for security awareness, allowing users to review active sessions and identify any suspicious login activity. Combined with logout functionality, users can manage their session security effectively.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for session filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query todo_app_member_sessions table filtered by authenticated member's ID from session context.
   *
   * Apply search filters on IP address, creation date range, expiration status (active/expired), and device information.
   *
   * Support cursor-based pagination for large result sets with configurable page sizes.
   *
   * Sort results by created_at (newest/oldest) or expired_at (earliest/latest) as specified in request.
   *
   * Join with todo_app_members if member profile information is needed in response.
   *
   * Exclude expired sessions by default unless explicitly requested.
   *
   * Validate member ownership before returning any session data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMemberSession.IRequest,
  ): Promise<IPageITodoAppMemberSession.ISummary> {
    try {
      return await patchTodoAppMemberSessions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific authentication session.
   *
   * This operation allows authenticated members to view the details of a particular session, including connection metadata such as IP address, creation timestamp, and expiration time. This is useful for security awareness, allowing users to monitor their active sessions and identify any unauthorized access.
   *
   * The endpoint validates that the requesting user owns the session being queried. Users cannot access session information belonging to other users, enforcing complete data isolation between accounts as specified in the privacy requirements.
   *
   * Session information includes connection details (IP, href, referrer) and temporal information (created_at, expired_at). Sensitive authentication tokens are not exposed in the response for security reasons. This operation is typically used in account security settings where users can review their active sessions.
   *
   * Related operations include logout endpoints for terminating sessions and authentication endpoints for creating new sessions.
   *
   * @param connection
   * @param sessionId Target session's ID (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the todo_app_member_sessions table by the provided sessionId.
   * Validate that the session's member_id matches the authenticated user's ID.
   * If session not found or ownership mismatch, return 404 Not Found.
   * If session exists and user is owner, return the complete session record.
   * Include all fields: id, member_id, access_token, refresh_token, ip, href, referrer, created_at, expired_at.
   * Ensure access_token and refresh_token are handled securely in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMemberSession> {
    try {
      return await getTodoAppMemberSessionsSessionId({
        member,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
