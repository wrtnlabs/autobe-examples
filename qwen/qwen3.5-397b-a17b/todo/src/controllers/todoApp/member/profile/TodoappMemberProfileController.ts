import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberProfile } from "../../../../providers/getTodoAppMemberProfile";
import { putTodoAppMemberProfile } from "../../../../providers/putTodoAppMemberProfile";

@Controller("/todoApp/member/profile")
export class TodoappMemberProfileController {
  /**
   * Retrieve the authenticated member's own profile information from the todo_app_members table.
   *
   * This operation provides access to the member's personal profile data including their registered email address and display name. The profile is retrieved from the todo_app_members table which stores all authenticated user accounts with email/password authentication. The email field serves as the unique authentication credential and account identifier, while the display_name field represents the user's public identifier shown in todo ownership and profile views.
   *
   * Profile information is completely private and isolated. The system enforces strict data ownership boundaries ensuring that members can only access their own profile data. Any attempt to view another user's profile is rejected by the system. The deleted_at field indicates soft-delete status - accounts with a non-null deleted_at value are considered inactive and cannot be accessed.
   *
   * The display name can be edited by members at any time through the profile update endpoint. The email address is immutable through this operation and serves as the permanent authentication credential. Account metadata including created_at and updated_at timestamps provide audit information about the account lifecycle.
   *
   * This endpoint requires active authentication via session token. Unauthenticated guests cannot access profile information. Upon successful authentication, members have exclusive access to their own profile throughout their session. The operation validates that the session token corresponds to an active (non-deleted) member account.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the todo_app_members table for the authenticated user's profile.
   *
   * Extract user ID from the authenticated session token. Query the member record by ID, ensuring the deleted_at field is null (active account). Return email and display_name fields along with account metadata (created_at, updated_at).
   *
   * Enforce strict ownership validation - the authenticated user ID must match the requested profile. Reject any cross-user access attempts with 403 Forbidden.
   *
   * Handle edge cases: session expiration (401 Unauthorized), soft-deleted accounts (404 Not Found), invalid session tokens (401 Unauthorized).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<ITodoAppMember> {
    try {
      return await getTodoAppMemberProfile({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated member's profile information in the todo_app_members table.
   *
   * This operation allows members to modify their profile display name. The display name is required and must be non-empty. When successfully updated, the change is reflected immediately across all user-facing contexts including todo ownership displays.
   *
   * The operation enforces profile privacy by only allowing members to update their own profile. Cross-user profile updates are not permitted. All other account information (email, password hash) remains unchanged during this operation.
   *
   * Profile updates are available to authenticated members at any time while their account is active. The display name change is persisted immediately and atomically. Requests from soft-deleted accounts are rejected.
   *
   * @param connection
   * @param body Profile update data with new display name
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update the authenticated member's display_name field in todo_app_members table.
   *
   * Implementation steps:
   * 1. Extract member ID from authenticated session context
   * 2. Validate display_name is non-empty and not whitespace-only
   * 3. Validate display_name meets length requirements if specified
   * 4. Update todo_app_members record where id equals authenticated member ID
   * 5. Set updated_at timestamp to current time
   * 6. Return updated member record with new display_name
   *
   * Business rules:
   * - Only authenticated members can access this endpoint
   * - display_name is required and cannot be empty
   * - Email and password_hash cannot be modified through this endpoint
   * - Update is atomic - either succeeds completely or fails
   * - updated_at timestamp must be refreshed on successful update
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMember.IUpdate,
  ): Promise<ITodoAppMember> {
    try {
      return await putTodoAppMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
