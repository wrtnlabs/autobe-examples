import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoMember } from "../../../../api/structures/IMultiUserTodoMember";
import { postMultiUserTodoAuthMemberJoin } from "../../../../providers/postMultiUserTodoAuthMemberJoin";
import { postMultiUserTodoAuthMemberLogin } from "../../../../providers/postMultiUserTodoAuthMemberLogin";
import { postMultiUserTodoAuthMemberRefresh } from "../../../../providers/postMultiUserTodoAuthMemberRefresh";

@Controller("/multiUserTodo/auth/member")
export class MultiusertodoAuthMemberController {
  /**
   * Register a new member account with email and password authentication.
   *
   * This operation creates a new member record in the multi_user_todo_members table with the provided email and bcrypt-hashed password. The email field must be unique across all member accounts. Upon successful registration, an email verification token is generated and stored in multi_user_todo_member_email_verifications for account activation.
   *
   * The operation returns access and refresh tokens in the IMultiUserTodoMember.IAuthorized response, along with the newly created member's ID. The member can immediately use these tokens to access authenticated endpoints.
   *
   * Email verification is required to fully activate the account. The verification token expires after a configured period. Members should check their email and complete verification to ensure full account functionality.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials for new member account creation.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Register a new member account with email and password. Validate email format and uniqueness, hash password with bcrypt, create member record in multi_user_todo_members table, generate email verification token in multi_user_todo_member_email_verifications, send verification email, create initial session in multi_user_todo_member_sessions with access and refresh tokens. Return tokens and member info. Handle duplicate email (409), invalid email format (400), weak password (400).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoMember.IJoin,
  ): Promise<IMultiUserTodoMember.IAuthorized> {
    try {
      return await postMultiUserTodoAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a member with email and password credentials.
   *
   * This operation validates the provided email and password against the multi_user_todo_members table. The password is verified using bcrypt hash comparison. The account must not be soft-deleted (deleted_at must be null) to successfully authenticate.
   *
   * Upon successful authentication, a new session record is created in multi_user_todo_member_sessions with the client's IP address, current page URL, and referrer. JWT access and refresh tokens are generated and returned in the IMultiUserTodoMember.IAuthorized response.
   *
   * Failed authentication attempts return 401 Unauthorized. Accounts with unverified emails or soft-deleted accounts return 403 Forbidden with appropriate error messages.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials for member authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Authenticate member with email and password. Validate credentials against multi_user_todo_members table, verify bcrypt password hash, check account not soft-deleted (deleted_at is null), create session in multi_user_todo_member_sessions with client IP and referrer info, generate JWT access and refresh tokens. Return tokens and member info. Handle invalid credentials (401), unverified email (403), deleted account (403).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoMember.ILogin,
  ): Promise<IMultiUserTodoMember.IAuthorized> {
    try {
      return await postMultiUserTodoAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens using a valid refresh token.
   *
   * This operation validates the provided refresh token against existing sessions in the multi_user_todo_member_sessions table. The session must not be expired (expired_at must be in the future) and the associated member account must exist and not be soft-deleted.
   *
   * Upon successful validation, new JWT access and refresh tokens are generated. The session's expired_at timestamp is updated to extend the session duration. The new tokens are returned in the IMultiUserTodoMember.IAuthorized response.
   *
   * This operation enables seamless session continuation without requiring re-authentication. Refresh tokens should be securely stored by clients and rotated on each use for enhanced security.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access tokens.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Refresh access token using valid refresh token. Validate refresh token against multi_user_todo_member_sessions table, check session not expired (expired_at), verify member account exists and is not deleted, generate new access token and optionally new refresh token, update session expired_at. Return new tokens. Handle invalid refresh token (401), expired session (401), deleted account (403).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMultiUserTodoMember.IRefresh,
  ): Promise<IMultiUserTodoMember.IAuthorized> {
    try {
      return await postMultiUserTodoAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
