import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoUserProfile } from "../../../../api/structures/IMultiUserTodoUserProfile";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getMultiUserTodoMemberProfile } from "../../../../providers/getMultiUserTodoMemberProfile";
import { putMultiUserTodoMemberProfile } from "../../../../providers/putMultiUserTodoMemberProfile";

@Controller("/multiUserTodo/member/profile")
export class MultiusertodoMemberProfileController {
  /**
   * Retrieve the current authenticated member's profile information including their display name.
   *
   * This operation returns the profile data for the member associated with the current authentication session. The response includes the user's display name shown in the application interface, along with metadata timestamps for profile creation and last update.
   *
   * Only authenticated members can access this endpoint. Guest users without valid authentication cannot retrieve profile information. The endpoint enforces strict privacy controls - users can only access their own profile linked to their session, with no ability to view other users' profiles.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query multi_user_todo_user_profiles table for the current authenticated member's profile. Join with multi_user_todo_members using multi_user_todo_member_id to verify the profile belongs to the current session user. Return the profile with display_name, created_at, updated_at fields. Ensure deleted_at is null (active profile only). Reject request if user is not authenticated (guest actor). Reject any attempt to access another user's profile - this endpoint only returns the profile linked to the current session's member ID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IMultiUserTodoUserProfile> {
    try {
      return await getMultiUserTodoMemberProfile({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the current authenticated user's profile information including display name.
   *
   * This operation allows members to modify their profile display name. The display name is shown throughout the application to identify the user. Profile changes are saved immediately upon submission and take effect for all subsequent operations.
   *
   * Only the authenticated profile owner can perform this operation. Attempts to access or modify another user's profile are rejected. The display name field is optional and can be updated multiple times without restrictions.
   *
   * @param connection
   * @param body Profile update data with new display name value
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update the authenticated member's user profile display name. Query multi_user_todo_user_profiles table using the authenticated member's ID from session context (multi_user_todo_member_id). Validate display_name meets requirements: optional field, can be updated multiple times. Update the display_name field and set updated_at timestamp. Return the complete updated profile record. Reject requests if member is not authenticated or attempts to modify another user's profile. The unique constraint on multi_user_todo_member_id ensures one profile per member.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IMultiUserTodoUserProfile.IUpdate,
  ): Promise<IMultiUserTodoUserProfile> {
    try {
      return await putMultiUserTodoMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
