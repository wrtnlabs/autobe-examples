import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMultiUserTodoTodo } from "../../../../../api/structures/IMultiUserTodoTodo";
import { IPageIMultiUserTodoTodo } from "../../../../../api/structures/IPageIMultiUserTodoTodo";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteMultiUserTodoMemberTodosTrashTodoId } from "../../../../../providers/deleteMultiUserTodoMemberTodosTrashTodoId";
import { patchMultiUserTodoMemberTodosTrash } from "../../../../../providers/patchMultiUserTodoMemberTodosTrash";
import { postMultiUserTodoMemberTodosTrashTodoIdRestore } from "../../../../../providers/postMultiUserTodoMemberTodosTrashTodoIdRestore";

@Controller("/multiUserTodo/member/todos/trash")
export class MultiusertodoMemberTodosTrashController {
  /**
   * Retrieve a paginated list of soft-deleted todos from the user's trash.
   *
   * This operation provides access to todos that have been deleted by the user but not yet permanently removed. Deleted todos retain all their original attributes including title, description, start date, due date, and completion status. The trash is scoped to the individual user, ensuring privacy isolation - users can only view their own deleted todos.
   *
   * Supports filtering by completion status and sorting by creation date, start date, or due date. Todos without start or due dates appear at the end when sorting by those fields. Pagination is applied to handle large result sets efficiently.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering deleted todos
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query multi_user_todo_todos table with filter deleted_at IS NOT NULL AND multi_user_todo_member_id equals current user's ID.
   * Apply completion status filter if provided (completed_at IS NULL for incomplete, IS NOT NULL for complete).
   * Apply sorting based on request parameters: created_at, started_at, or due_at with direction (ASC/DESC).
   * Handle null started_at and due_at by placing them at the end of sorted results.
   * Use index on [multi_user_todo_member_id, deleted_at, created_at] for efficient filtering.
   * Return paginated results with cursor-based or offset-based pagination.
   * Include total count for pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IMultiUserTodoTodo.IRequest,
  ): Promise<IPageIMultiUserTodoTodo.ISummary> {
    try {
      return await patchMultiUserTodoMemberTodosTrash({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Restore a deleted todo from the trash back to the active todo list.
   *
   * This operation allows users to recover their own deleted todos by clearing the soft delete timestamp. The todo returns to its original state with all properties preserved including title, description, dates, and completion status. The original creation date is maintained, and all edit history entries remain accessible.
   *
   * Only the todo owner can restore their own deleted todos. The operation validates that the todo exists in the user's trash (has a non-null deleted_at timestamp) before allowing restoration. Attempting to restore a todo that is not deleted or does not belong to the user will be rejected.
   *
   * After successful restoration, the todo reappears in normal todo list queries and can be edited, completed, or deleted again.
   *
   * @param connection
   * @param todoId Todo ID to restore from trash (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Validate that the todo exists and belongs to the authenticated user by checking multi_user_todo_member_id matches the session user.
   *
   * Verify the todo is in deleted state (deleted_at is not null). Reject if deleted_at is null with 400 Bad Request indicating todo is not in trash.
   *
   * Clear the deleted_at field by setting it to null to restore the todo to active state.
   *
   * Preserve all other fields unchanged: title, description, started_at, due_at, completed_at, created_at, updated_at.
   *
   * Do not create a new edit history entry for the restore operation itself.
   *
   * Return the full restored todo entity with deleted_at now null.
   *
   * Handle edge cases: todo not found (404), not owned by user (403), not in trash state (400).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":todoId/restore")
  public async restore(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<IMultiUserTodoTodo> {
    try {
      return await postMultiUserTodoMemberTodosTrashTodoIdRestore({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a todo from the trash, removing it and all associated edit history completely.
   *
   * This operation permanently removes a todo that is currently in the trash state. Unlike soft deletion which moves todos to trash, this operation completely erases the todo and all its edit history entries from the system. This action cannot be undone.
   *
   * The todo must be in the deleted state (present in trash) and must be owned by the current user. Attempting to permanently delete a todo that is not in the trash or does not belong to the user will result in an error.
   *
   * Upon successful deletion, the todo and all related edit history records are cascade deleted from the database.
   *
   * @param connection
   * @param todoId Unique identifier of the todo to permanently delete (scoped to current user's trash)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Permanently delete a todo from trash with cascade deletion of edit history.
   *
   * 1. Verify authentication: Ensure request is from an authenticated member
   * 2. Validate todoId format: Must be a valid UUID
   * 3. Query todo by ID with ownership check: SELECT FROM multi_user_todo_todos WHERE id = {todoId} AND multi_user_todo_member_id = {currentUserId}
   * 4. Verify trash state: Check that deleted_at is NOT NULL (todo must be in trash)
   * 5. If todo not found or not in trash: Return 404 Not Found
   * 6. If todo not owned by user: Return 403 Forbidden
   * 7. Execute cascade delete: DELETE FROM multi_user_todo_todos WHERE id = {todoId}
   *    - This automatically deletes all related multi_user_todo_todo_edit_histories via CASCADE constraint
   * 8. Return 204 No Content on success
   *
   * Edge cases:
   * - Todo not in trash (deleted_at is NULL): Reject with 404
   * - Todo owned by different user: Reject with 403
   * - Todo already permanently deleted: Return 404
   * - Invalid UUID format: Return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteMultiUserTodoMemberTodosTrashTodoId({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
