import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMultiUserTodoTodoEditHistory } from "../../../../../api/structures/IMultiUserTodoTodoEditHistory";
import { IPageIMultiUserTodoTodoEditHistory } from "../../../../../api/structures/IPageIMultiUserTodoTodoEditHistory";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getMultiUserTodoMemberTodosTodoIdHistoryHistoryId } from "../../../../../providers/getMultiUserTodoMemberTodosTodoIdHistoryHistoryId";
import { patchMultiUserTodoMemberTodosTodoIdHistory } from "../../../../../providers/patchMultiUserTodoMemberTodosTodoIdHistory";

@Controller("/multiUserTodo/member/todos/:todoId/history")
export class MultiusertodoMemberTodosHistoryController {
  /**
   * Retrieve the edit history of a specific todo with pagination and sorting capabilities.
   *
   * This operation returns a chronological list of all edit history entries for the specified todo, showing what fields were changed and when. Each history entry captures the new values of modified fields (title, description, started_at, due_at) along with the timestamp of when the edit was made.
   *
   * History entries are sorted from most recent to oldest by default. Supports pagination for todos with extensive edit history. Users can only access the edit history of their own todos - attempting to access another user's todo history will be rejected.
   *
   * Edit history is automatically created whenever a todo is successfully edited. Failed edit operations do not create history entries. When a todo is permanently deleted from trash, its entire edit history is also permanently deleted.
   *
   * @param connection
   * @param todoId Todo identifier (UUID format, scoped to current user's todos)
   * @param body Pagination and filtering parameters for edit history search
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query multi_user_todo_todo_edit_histories table filtered by multi_user_todo_todo_id parameter.
   *
   * Implementation steps:
   * 1. Verify the todo exists and belongs to the authenticated user (check multi_user_todo_member_id matches current user)
   * 2. Query edit histories where multi_user_todo_todo_id equals the path parameter
   * 3. Apply sorting by created_at DESC (most recent first) by default
   * 4. Support pagination with page and take parameters
   * 5. Support optional filtering by date range (created_at from/to)
   * 6. Return summary fields: id, created_at, title, description, started_at, due_at
   * 7. Include pagination metadata in response
   *
   * Authorization: Member actor only. Reject if todo does not belong to authenticated user.
   * Error handling: Return 404 if todo not found or does not belong to user. Return 403 if user lacks permission.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMultiUserTodoTodoEditHistory.IRequest,
  ): Promise<IPageIMultiUserTodoTodoEditHistory.ISummary> {
    try {
      return await patchMultiUserTodoMemberTodosTodoIdHistory({
        member,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific edit history entry from the multi_user_todo_todo_edit_histories table.
   *
   * This operation returns detailed information about a single edit made to a todo, including the timestamp of when the edit was made and the new values of any fields that were changed. Only fields that were actually modified during the edit will have values; unchanged fields will be null.
   *
   * Users can only access edit history entries for todos they own through the multi_user_todo_todos relationship. The history entry includes the edit timestamp and any changed field values (title, description, started_at, due_at). Edit histories are cascade deleted when the parent todo is permanently removed.
   *
   * @param connection
   * @param todoId Todo ID (UUID format, identifies the parent todo)
   * @param historyId History entry ID (UUID format, identifies the specific edit)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the multi_user_todo_todo_edit_histories table by history ID.
   *
   * First verify the todo exists and belongs to the current user by checking multi_user_todo_todo_id matches a todo owned by the authenticated member. This prevents unauthorized access to another user's todo history.
   *
   * Return the full history entry with all fields: id, created_at timestamp, and the optional changed field values (title, description, started_at, due_at). Only fields that were actually modified during the edit will contain values; others will be null.
   *
   * Return 404 if the history entry does not exist or if the todo does not belong to the current user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":historyId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedParam("historyId")
    historyId: string & tags.Format<"uuid">,
  ): Promise<IMultiUserTodoTodoEditHistory> {
    try {
      return await getMultiUserTodoMemberTodosTodoIdHistoryHistoryId({
        member,
        todoId,
        historyId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
