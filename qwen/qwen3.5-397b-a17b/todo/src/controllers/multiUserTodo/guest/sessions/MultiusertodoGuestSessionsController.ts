import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMultiUserTodoGuestSession } from "../../../../api/structures/IMultiUserTodoGuestSession";
import { IMultiUserTodoMemberSession } from "../../../../api/structures/IMultiUserTodoMemberSession";
import { IPageIMultiUserTodoGuestSession } from "../../../../api/structures/IPageIMultiUserTodoGuestSession";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { getMultiUserTodoGuestSessionsSessionId } from "../../../../providers/getMultiUserTodoGuestSessionsSessionId";
import { patchMultiUserTodoGuestSessions } from "../../../../providers/patchMultiUserTodoGuestSessions";

@Controller("/multiUserTodo/guest/sessions")
export class MultiusertodoGuestSessionsController {
  /**
   * Retrieve a filtered and paginated list of active user sessions for administrative monitoring.
   *
   * This operation provides session visibility for system administrators, including member and guest sessions with filtering by creation date, expiration status, and session metadata. Sessions are automatically created during authentication and cannot be manually modified.
   *
   * Response includes session summary information with IP addresses, creation timestamps, and expiration times. This endpoint is restricted to administrative users only.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for session filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query session tables (multi_user_todo_member_sessions and multi_user_todo_guest_sessions) with pagination and filtering. This is an admin-only endpoint for monitoring active sessions. Apply filters on creation date range, expiration status, and actor type (member/guest). Join with member/guest tables for user information if requested. Return cursor-based pagination for large result sets. Sessions are append-only - no update operations allowed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IMultiUserTodoGuestSession.IRequest,
  ): Promise<IPageIMultiUserTodoGuestSession.ISummary> {
    try {
      return await patchMultiUserTodoGuestSessions({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific member session.
   *
   * This operation returns complete session data including creation timestamp, expiration time, client IP address, and navigation context (href and referrer) captured at session creation. Sessions are private to their owners and cannot be accessed by other users.
   *
   * The session must belong to the authenticated member making the request. Attempts to access another user's session are rejected with authorization error.
   *
   * @param connection
   * @param sessionId Session identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query multi_user_todo_member_sessions table by session ID UUID. Verify the session belongs to the authenticated member by checking multi_user_todo_member_id matches the current user's ID. Return full session entity with all fields: id, multi_user_todo_member_id, ip, href, referrer, created_at, expired_at. Handle case where session doesn't exist or belongs to different user by returning 404 or 403 error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IMultiUserTodoMemberSession> {
    try {
      return await getMultiUserTodoGuestSessionsSessionId({
        guest,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
