export async function test_api_seller_profile_snapshot_admin_access(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate as a seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 3 }),
      logo_image_url: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 2. Verify seller authentication was successful
  TestValidator.equals(
    "seller email matches",
    sellerAuth.email,
    sellerAuth.email,
  );
  TestValidator.predicate("seller has valid ID", sellerAuth.id !== undefined);
  // 3. Test snapshot retrieval with non-existent snapshot ID
  // This validates that the endpoint properly handles authentication
  // and returns appropriate error for non-existent snapshot
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error("non-existent snapshot returns error", async () => {
    await api.functional.shoppingMall.seller.profile.snapshots.at(
      sellerConnection,
      {
        snapshotId: snapshotId,
      },
    );
  });
}
