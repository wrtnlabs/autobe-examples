/**
 * Test that a customer cannot retrieve order items from another customer's order.
 * Validates proper authorization enforcement ensuring customers can only access their own order items.
 *
 * Workflow:
 * 1. Register two separate customer accounts (Customer A and Customer B)
 * 2. Customer B attempts to retrieve an order item using Customer A's credentials context
 * 3. Validate that the API returns an error when Customer B tries to access another customer's order item
 *
 * Note: This test validates the authorization check mechanism. A complete end-to-end order flow
 * would require address management endpoints which are not available in the current function set.
 */
export async function test_api_order_item_authorization_customer_only(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer A (order owner) - registers and logs in
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "CustomerA1234!",
      nickname: RandomGenerator.name(1),
      phone_number: RandomGenerator.mobile(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerA);
  // 2. Customer B (unauthorized accessor) - registers and logs in
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB = await authorize_customer_join(customerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "CustomerB1234!",
      nickname: RandomGenerator.name(1),
      phone_number: RandomGenerator.mobile(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerB);
  // Verify customers are different
  TestValidator.notEquals("different customers", customerA.id, customerB.id);
  TestValidator.notEquals("different emails", customerA.email, customerB.email);
  // 3. Test authorization: Customer B attempts to access order item
  // This should fail with 403 Forbidden or 404 Not Found
  // The endpoint checks that the authenticated customer owns the order
  await TestValidator.error(
    "customer B cannot access another customer's order item",
    async () => {
      await api.functional.shoppingMall.customer.orders.items.getByOrderidAndItemid(
        customerBConnection,
        {
          orderId: typia.random<string & tags.Format<"uuid">>(),
          itemId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
  // 4. Additional test: Even Customer A cannot access non-existent order items
  // This validates that the endpoint properly validates order/item existence
  await TestValidator.error(
    "customer A cannot access non-existent order item",
    async () => {
      await api.functional.shoppingMall.customer.orders.items.getByOrderidAndItemid(
        customerAConnection,
        {
          orderId: typia.random<string & tags.Format<"uuid">>(),
          itemId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
