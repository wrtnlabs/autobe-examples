/**
 * Test customer retrieval of a specific shipment item.
 *
 * Scenario:
 * 1. Seller registers and creates a product with variant
 * 2. Customer registers and adds the variant to cart
 * 3. Customer places an order
 * 4. Seller creates a shipment for the order item
 * 5. Customer retrieves the shipment item details
 *
 * Validation points:
 * - Shipment item contains correct shipment and order item linkage
 * - Shipment has tracking information (carrier, number, shipped_at)
 * - Order item status is SHIPPED after shipment creation
 * - Product and variant snapshots are preserved
 * - Seller information is included
 */
export async function test_api_shipment_item_retrieve_by_customer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup - register and login
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "SellerPass123!",
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
    },
  });
  typia.assert(sellerAuth);
  // 2. Seller creates product
  const product = await api.functional.shoppingMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        shopping_category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Seller creates product variant
  const variant =
    await api.functional.shoppingMall.seller.products.variants.create(
      sellerConnection,
      {
        productId: product.id,
        body: {
          sku_code: `SKU-${RandomGenerator.alphaNumeric(8)}`,
          price: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
          stock_quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<10>
          >(),
          options: [
            {
              key: "color",
              value: RandomGenerator.pick(["Red", "Blue", "Green"]),
            },
            {
              key: "size",
              value: RandomGenerator.pick(["S", "M", "L", "XL"]),
            },
          ] satisfies IShoppingMallProductVariantOption.ICreate[],
        } satisfies IShoppingMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 4. Customer setup - register and login
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "CustomerPass123!",
      nickname: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    },
  });
  typia.assert(customerAuth);
  // 5. Customer adds variant to cart
  const cartItem =
    await api.functional.shoppingMall.customer.customers.cart.items.create(
      customerConnection,
      {
        body: {
          shopping_mall_product_variant_id: variant.id,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 6. Customer creates order
  const order = await api.functional.shoppingMall.customer.orders.create(
    customerConnection,
    {
      body: {
        addressId: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order);
  // Verify order has items
  TestValidator.predicate("order has items", order.items.length > 0);
  const orderItem = order.items[0];
  // 7. Seller creates shipment with the order item
  const shipment = await api.functional.shoppingMall.seller.shipments.create(
    sellerConnection,
    {
      body: {
        order_item_ids: [orderItem.id],
        tracking_carrier: RandomGenerator.pick(["FedEx", "UPS", "DHL", "USPS"]),
        tracking_number: `TRACK-${RandomGenerator.alphaNumeric(12)}`,
      } satisfies IShoppingMallShipment.ICreate,
    },
  );
  typia.assert(shipment);
  // 8. Customer retrieves the shipment item
  const shipmentItem =
    await api.functional.shoppingMall.customer.shipments.items.at(
      customerConnection,
      {
        shipmentId: shipment.id,
        itemId: orderItem.id,
      },
    );
  typia.assert(shipmentItem);
  // 9. Validate shipment item structure and linkage
  TestValidator.equals(
    "shipment id matches",
    shipmentItem.shipment.id,
    shipment.id,
  );
  TestValidator.equals(
    "order item id matches",
    shipmentItem.orderItem.id,
    orderItem.id,
  );
  // Validate shipment tracking information
  TestValidator.predicate(
    "shipment has tracking carrier",
    shipmentItem.shipment.tracking_carrier !== null,
  );
  TestValidator.predicate(
    "shipment has tracking number",
    shipmentItem.shipment.tracking_number !== null,
  );
  TestValidator.predicate(
    "shipment has shipped_at timestamp",
    shipmentItem.shipment.shipped_at !== null,
  );
  // Validate order item details
  // Note: shipmentItem.orderItem is ISummary (unit_price), orderItem is full type (unitPrice)
  TestValidator.equals(
    "order item quantity matches",
    shipmentItem.orderItem.quantity,
    orderItem.quantity satisfies number as number,
  );
  TestValidator.equals(
    "order item unit price matches",
    shipmentItem.orderItem.unit_price,
    orderItem.unitPrice,
  );
  TestValidator.equals(
    "order item status is SHIPPED",
    shipmentItem.orderItem.status,
    "SHIPPED",
  );
  // Validate product snapshot
  TestValidator.predicate(
    "product snapshot has name",
    shipmentItem.orderItem.productSnapshot.name.length > 0,
  );
  TestValidator.predicate(
    "product snapshot has base price",
    shipmentItem.orderItem.productSnapshot.base_price > 0,
  );
  // Validate product variant snapshot
  TestValidator.predicate(
    "variant snapshot has sku code",
    shipmentItem.orderItem.productVariantSnapshot.sku_code.length > 0,
  );
  TestValidator.predicate(
    "variant snapshot has option values",
    Object.keys(shipmentItem.orderItem.productVariantSnapshot.option_values)
      .length > 0,
  );
  // Validate seller information
  TestValidator.predicate(
    "seller has shop name",
    shipmentItem.orderItem.seller.shop_name.length > 0,
  );
}
