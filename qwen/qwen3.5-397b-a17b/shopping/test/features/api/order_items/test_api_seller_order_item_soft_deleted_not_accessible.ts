/**
 * Test that a seller cannot retrieve a soft-deleted order item.
 *
 * This test verifies:
 * 1. Seller can create product and variant
 * 2. Customer can place order creating order item
 * 3. Seller can access their order item in normal state
 * 4. Soft-deleted order items should return 404 (requires admin delete endpoint)
 *
 * NOTE: The current SDK does not expose an admin endpoint for soft-deleting order items.
 * This test verifies the normal access case. The soft-deletion 404 behavior would require
 * an admin order item deletion endpoint to be added to the SDK.
 */
export async function test_api_seller_order_item_soft_deleted_not_accessible(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Test1234!",
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      logo_image_url: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(seller);
  // 2. Seller creates product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        shopping_category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Seller creates product variant
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku_code: RandomGenerator.alphaNumeric(12),
          price: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
          stock_quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<10>
          >(),
          options: [
            {
              key: "color",
              value: RandomGenerator.pick(["Red", "Blue", "Green"] as const),
            },
          ] satisfies IShoppingMallProductVariantOption.ICreate[],
        } satisfies IShoppingMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 4. Create and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Test1234!",
      nickname: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customer);
  // 5. Customer adds product variant to cart
  const cartItem =
    await generate_random_shopping_mall_customer_customers_cart_items_create(
      customerConnection,
      {
        body: {
          shopping_mall_product_variant_id: variant.id,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 6. Customer creates order (this generates the order item)
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order);
  // Extract the order item ID from the created order
  const orderItemId = order.items[0].id;
  // 7. Verify order item is accessible to seller in normal state
  const orderItem = await api.functional.shoppingMall.seller.order_items.at(
    sellerConnection,
    {
      orderItemId: orderItemId,
    },
  );
  typia.assert(orderItem);
  // Validate the order item contains expected seller and product data
  TestValidator.equals(
    "order item seller matches",
    orderItem.seller.id,
    seller.id,
  );
  TestValidator.equals(
    "order item product snapshot matches",
    orderItem.productSnapshot.id,
    product.id,
  );
  TestValidator.equals(
    "order item variant snapshot matches",
    orderItem.productVariantSnapshot.id,
    variant.id,
  );
  TestValidator.predicate("order item has quantity", orderItem.quantity > 0);
  TestValidator.predicate("order item has unit price", orderItem.unitPrice > 0);
  // 8. Attempt to access soft-deleted order item
  // NOTE: The SDK does not provide an endpoint to soft-delete order items.
  // In production, admin operations or system processes would soft-delete order items,
  // causing this endpoint to return 404 Not Found for deleted items.
  // This test verifies the normal access case; soft-delete behavior requires
  // admin order item deletion endpoint which is not available in current SDK.
  // When soft-delete endpoint becomes available, the test would be:
  // await adminDeleteOrderItem(adminConnection, orderItemId);
  // await TestValidator.httpError("deleted order item returns 404", 404, async () => {
  //   await api.functional.shoppingMall.seller.order_items.at(sellerConnection, {
  //     orderItemId: orderItemId,
  //   });
  // });
}
