export async function test_api_order_item_cancellation_duplicate_request_rejected(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register new customer account
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customer);
  // 2. Create shipping address for the customer
  const address = await generate_random_shopping_mall_customer_addresses_create(
    customerConnection,
    {
      body: {
        recipientName: RandomGenerator.name(),
        recipientPhone: RandomGenerator.mobile(),
        streetAddress: RandomGenerator.paragraph({ sentences: 1 }),
        city: RandomGenerator.name(),
        state: RandomGenerator.name(),
        postalCode: typia.random<string>(),
        country: RandomGenerator.name(),
        isDefault: true,
      } satisfies IShoppingMallAddress.ICreate,
    },
  );
  typia.assert(address);
  // 3. Add product variant to cart
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          shopping_mall_product_variant_id: typia.random<
            string & tags.Format<"uuid">
          >(),
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1>
          >(),
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 4. Create order (this creates order items with 'paid' status)
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        shopping_mall_address_id: address.id,
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order);
  // 5. Extract the first order item ID
  const orderItemId = order.orderItems[0].id;
  TestValidator.predicate(
    "order has at least one item",
    order.orderItems.length > 0,
  );
  TestValidator.equals(
    "order item status is paid",
    order.orderItems[0].status,
    "paid",
  );
  // 6. Submit first cancellation request (should succeed)
  const firstCancellationRequest =
    await generate_random_shopping_mall_customer_order_items_cancellation_requests_create(
      customerConnection,
      {
        params: { orderItemId },
        body: {
          reason: RandomGenerator.paragraph({ sentences: 2 }),
        } satisfies IShoppingMallCancellationRequest.ICreate,
      },
    );
  typia.assert(firstCancellationRequest);
  TestValidator.equals(
    "first request status is pending",
    firstCancellationRequest.status,
    "pending",
  );
  TestValidator.equals(
    "first request order item matches",
    firstCancellationRequest.orderItem.id,
    orderItemId,
  );
  // 7. Attempt to submit second cancellation request for same order item (should fail with 409)
  await TestValidator.error(
    "duplicate cancellation request rejected",
    async () => {
      await api.functional.shoppingMall.customer.order_items.cancellation_requests.create(
        customerConnection,
        {
          orderItemId,
          body: {
            reason: RandomGenerator.paragraph({ sentences: 2 }),
          } satisfies IShoppingMallCancellationRequest.ICreate,
        },
      );
    },
  );
}
