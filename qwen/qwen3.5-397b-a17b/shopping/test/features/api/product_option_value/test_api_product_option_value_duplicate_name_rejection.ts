/**
 * Test business rule validation that prevents duplicate option value names within the same option definition.
 *
 * This test verifies the unique constraint on [shopping_mall_product_option_definition_id, name] that ensures
 * option value names are unique per option definition. The test flow:
 * 1. Authenticate as a seller
 * 2. Create a product
 * 3. Create an option definition (e.g., "Color")
 * 4. Create first option value (e.g., "Red")
 * 5. Attempt to create duplicate option value with same name "Red" under same definition
 * 6. Verify the system rejects the duplicate with appropriate business logic error
 */
export async function test_api_product_option_value_duplicate_name_rejection(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Test1234!",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  // 2. Create a product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Create an option definition (e.g., "Color")
  const optionDefinition =
    await generate_random_shopping_mall_seller_products_option_definitions_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          name: "Color",
        } satisfies IShoppingMallProductOptionDefinition.ICreate,
      },
    );
  typia.assert(optionDefinition);
  // 4. Create first option value (e.g., "Red")
  const optionValueName = "Red";
  const firstOptionValue =
    await generate_random_shopping_mall_seller_products_option_definitions_option_values_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
          optionDefinitionId: optionDefinition.id,
        },
        body: {
          name: optionValueName,
        } satisfies IShoppingMallProductOptionValue.ICreate,
      },
    );
  typia.assert(firstOptionValue);
  // 5. Attempt to create duplicate option value with same name
  // 6. Verify the system rejects the duplicate with business logic error
  await TestValidator.error(
    "duplicate option value name rejection",
    async () => {
      await api.functional.shoppingMall.seller.products.option_definitions.option_values.create(
        sellerConnection,
        {
          productId: product.id,
          optionDefinitionId: optionDefinition.id,
          body: {
            name: optionValueName,
          } satisfies IShoppingMallProductOptionValue.ICreate,
        },
      );
    },
  );
}
