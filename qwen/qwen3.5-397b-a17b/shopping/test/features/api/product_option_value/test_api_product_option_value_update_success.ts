export async function test_api_product_option_value_update_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 2. Create product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Create option definition (e.g., "Color")
  const optionDefinition =
    await generate_random_shopping_mall_seller_products_option_definitions_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          name: "Color",
        } satisfies IShoppingMallProductOptionDefinition.ICreate,
      },
    );
  typia.assert(optionDefinition);
  // 4. Create option value (e.g., "Red")
  const originalOptionValueName = "Red";
  const optionValue =
    await generate_random_shopping_mall_seller_products_option_definitions_option_values_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
          optionDefinitionId: optionDefinition.id,
        },
        body: {
          name: originalOptionValueName,
        } satisfies IShoppingMallProductOptionValue.ICreate,
      },
    );
  typia.assert(optionValue);
  // 5. Update option value name (e.g., "Red" -> "Crimson")
  const newOptionValueName = "Crimson";
  const updatedOptionValue =
    await api.functional.shoppingMall.seller.products.option_definitions.option_values.update(
      sellerConnection,
      {
        productId: product.id,
        optionDefinitionId: optionDefinition.id,
        optionValueId: optionValue.id,
        body: {
          name: newOptionValueName,
        } satisfies IShoppingMallProductOptionValue.IUpdate,
      },
    );
  typia.assert(updatedOptionValue);
  // 6. Validate the update
  TestValidator.equals(
    "option value name updated",
    updatedOptionValue.name,
    newOptionValueName,
  );
  TestValidator.notEquals(
    "updated_at changed",
    optionValue.updated_at,
    updatedOptionValue.updated_at,
  );
  TestValidator.equals(
    "option definition link preserved",
    updatedOptionValue.optionDefinition.id,
    optionDefinition.id,
  );
  TestValidator.predicate(
    "updated timestamp is later",
    new Date(updatedOptionValue.updated_at) > new Date(optionValue.updated_at),
  );
}
