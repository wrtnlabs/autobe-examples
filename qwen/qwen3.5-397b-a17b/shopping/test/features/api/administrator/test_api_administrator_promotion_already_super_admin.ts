export async function test_api_administrator_promotion_already_super_admin(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create super administrator account
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdmin = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallSuperAdmin.IJoin,
  });
  typia.assert(superAdmin);
  // 2. Create regular administrator account (grade: ADMIN by default)
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallAdmin.IJoin,
  });
  typia.assert(admin);
  TestValidator.equals("initial grade is ADMIN", admin.grade, "ADMIN");
  // 3. Promote regular admin to super administrator
  const promoted = await api.functional.shoppingMall.superAdmin.admins.promote(
    superAdminConnection,
    {
      adminId: admin.id,
    },
  );
  typia.assert(promoted);
  TestValidator.equals("grade after promotion", promoted.grade, "SUPER_ADMIN");
  // 4. Attempt to promote the same admin again - should fail (already SUPER_ADMIN)
  await TestValidator.error("cannot promote already super admin", async () => {
    await api.functional.shoppingMall.superAdmin.admins.promote(
      superAdminConnection,
      {
        adminId: admin.id,
      },
    );
  });
}
