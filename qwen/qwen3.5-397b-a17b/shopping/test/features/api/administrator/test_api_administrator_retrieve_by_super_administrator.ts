import { authorize_super_administrator_join } from "../../../authorize/authorize_super_administrator_join";
import { authorize_super_administrator_login } from "../../../authorize/authorize_super_administrator_login";
import { authorize_super_administrator_refresh } from "../../../authorize/authorize_super_administrator_refresh";

export async function test_api_administrator_retrieve_by_super_administrator(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as super administrator
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdminAuth = await authorize_super_administrator_join(
    superAdminConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
        ip: typia.random<string & tags.Format<"ipv4">>(),
      } satisfies IShoppingMallSuperAdministrator.IJoin,
    },
  );
  typia.assert(superAdminAuth);
  // 2. Generate a valid administrator UUID for retrieval
  const administratorId = typia.random<string & tags.Format<"uuid">>();
  // 3. Retrieve administrator information
  const administrator =
    await api.functional.shoppingMall.superAdministrator.administrators.at(
      superAdminConnection,
      {
        administratorId,
      },
    );
  typia.assert(administrator);
  // 4. Verify administrator ID matches the requested ID
  TestValidator.equals(
    "administrator id matches",
    administrator.id,
    administratorId,
  );
}
