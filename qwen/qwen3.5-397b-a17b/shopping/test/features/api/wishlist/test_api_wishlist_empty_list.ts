export async function test_api_wishlist_empty_list(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer joins the platform
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      nickname: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IShoppingMallCustomer.IJoin,
  });
  // 2. Retrieve wishlist without adding any products
  const wishlist =
    await api.functional.shoppingMall.customer.customers.wishlist.index(
      customerConnection,
      {
        body: {} satisfies IShoppingMallWishlist.IRequest,
      },
    );
  typia.assert(wishlist);
  // 3. Validate empty wishlist response
  TestValidator.equals("records count", wishlist.pagination.records, 0);
  TestValidator.equals("pages count", wishlist.pagination.pages, 0);
  TestValidator.equals("current page", wishlist.pagination.current, 1);
  TestValidator.equals("limit", wishlist.pagination.limit, 20);
  TestValidator.equals("data array is empty", wishlist.data.length, 0);
}
