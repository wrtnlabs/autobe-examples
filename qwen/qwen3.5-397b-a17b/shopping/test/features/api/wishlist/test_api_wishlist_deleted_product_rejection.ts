/**
 * Test that customers cannot add deleted products to their wishlist.
 *
 * This test verifies the business rule that prevents adding deleted products
 * to wishlist by:
 * 1. Creating a customer account
 * 2. Creating a seller account and a product
 * 3. Deleting the product
 * 4. Attempting to add the deleted product to customer's wishlist
 * 5. Verifying the system rejects the request
 */
export async function test_api_wishlist_deleted_product_rejection(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer registration
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customer);
  // 2. Seller registration
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(seller);
  // 3. Seller creates a product
  const product = await api.functional.shoppingMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 4. Seller deletes the product
  await api.functional.shoppingMall.seller.products.erase(sellerConnection, {
    productId: product.id,
  });
  // 5. Customer attempts to add deleted product to wishlist
  // 6. Verify the system rejects the request
  await TestValidator.error(
    "deleted product cannot be added to wishlist",
    async () => {
      await api.functional.shoppingMall.customer.wishlist_items.create(
        customerConnection,
        {
          body: {
            product_id: product.id,
          } satisfies IShoppingMallWishlistItem.ICreate,
        },
      );
    },
  );
}
