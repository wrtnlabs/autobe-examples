/**
 * Test error scenario: Customer attempts to remove a product not in their wishlist.
 *
 * This test validates that when a customer tries to remove a product from their
 * wishlist that was never added, the API correctly returns a 404 Not Found response.
 * This ensures proper validation of wishlist membership before deletion.
 *
 * Test Flow:
 * 1. Seller registers and creates a valid product
 * 2. Customer registers (different user, empty wishlist)
 * 3. Customer attempts to remove the seller's product from their wishlist
 * 4. Verify 404 Not Found is returned
 */
export async function test_api_wishlist_product_removal_not_in_wishlist(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup - register and create a product
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      logo_image_url: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        shopping_category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 2. Customer setup - register (different user with empty wishlist)
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      nickname: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  // 3. Attempt to remove product that was never added to wishlist
  // This should return 404 Not Found per specification
  await TestValidator.error(
    "remove product not in wishlist returns 404",
    async () => {
      await api.functional.shoppingMall.customer.customers.wishlist.products.erase(
        customerConnection,
        {
          productId: product.id,
        },
      );
    },
  );
}
