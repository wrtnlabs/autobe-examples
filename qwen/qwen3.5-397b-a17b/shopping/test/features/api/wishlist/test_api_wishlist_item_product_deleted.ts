/**
 * Test the edge case where a customer tries to retrieve a wishlist item
 * after the associated product has been deleted by the seller.
 *
 * Workflow:
 * 1. Customer joins and authenticates
 * 2. Seller joins and authenticates
 * 3. Seller creates a product
 * 4. Customer adds the product to their wishlist
 * 5. Seller deletes the product
 * 6. Customer attempts to retrieve the wishlist item - should return 404 Not Found
 *
 * This validates that deleted products are automatically removed from wishlists
 * through cascade delete, and customers cannot access wishlist items for
 * products that no longer exist.
 */
export async function test_api_wishlist_item_product_deleted(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer authentication
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  // 2. Seller authentication
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 3. Seller creates a product
  const product = await api.functional.shoppingMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 3 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 4. Customer adds the product to their wishlist
  const wishlistItem =
    await api.functional.shoppingMall.customer.wishlist_items.create(
      customerConnection,
      {
        body: {
          product_id: product.id,
        } satisfies IShoppingMallWishlistItem.ICreate,
      },
    );
  typia.assert(wishlistItem);
  // 5. Seller deletes the product (triggers cascade delete of wishlist items)
  await api.functional.shoppingMall.seller.products.erase(sellerConnection, {
    productId: product.id,
  });
  // 6. Customer attempts to retrieve the wishlist item - should return 404
  await TestValidator.error(
    "wishlist item not found after product deletion",
    async () => {
      await api.functional.shoppingMall.customer.wishlist_items.at(
        customerConnection,
        {
          wishlistItemId: wishlistItem.id,
        },
      );
    },
  );
}