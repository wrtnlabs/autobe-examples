/**
 * Test that a seller can retrieve a cancellation request after responding to it.
 *
 * This test verifies that after a seller approves or rejects a cancellation request,
 * they can retrieve the request and see the updated status. The test ensures that
 * the cancellation request state is preserved correctly and all entity references
 * remain intact after the response.
 *
 * Setup Flow:
 * 1. Seller account registration and authentication
 * 2. Customer account registration and authentication
 * 3. Seller creates a product with a variant
 * 4. Customer adds variant to cart and creates an order
 * 5. Customer creates a cancellation request for the order item
 * 6. Seller responds to the cancellation request (approve)
 * 7. Seller retrieves the cancellation request and validates the response
 */
export async function test_api_seller_cancellation_request_retrieval_responded(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 2. Register and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  // 3. Seller creates a product
  const product = await api.functional.shoppingMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 4. Seller creates a product variant
  const variant =
    await api.functional.shoppingMall.seller.products.variants.create(
      sellerConnection,
      {
        productId: product.id,
        body: {
          sku_code: RandomGenerator.alphaNumeric(12),
          price_override: null,
          option_value_ids: [],
        } satisfies IShoppingMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 5. Customer adds the variant to cart
  const cartItem = await api.functional.shoppingMall.customer.cart.items.create(
    customerConnection,
    {
      body: {
        shopping_mall_product_variant_id: variant.id,
        quantity: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
        >(),
      } satisfies IShoppingMallCartItem.ICreate,
    },
  );
  typia.assert(cartItem);
  // 6. Customer creates an order (this requires an address - using random UUID for test)
  const order = await api.functional.shoppingMall.customer.orders.create(
    customerConnection,
    {
      body: {
        shopping_mall_address_id: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order);
  // 7. Get the first order item (should have 'paid' status)
  const orderItem = order.orderItems[0];
  TestValidator.equals("order item exists", orderItem !== undefined, true);
  TestValidator.equals("order item status is paid", orderItem.status, "paid");
  // 8. Customer creates a cancellation request for the order item
  const cancellationRequest =
    await api.functional.shoppingMall.customer.order_items.cancellation_requests.create(
      customerConnection,
      {
        orderItemId: orderItem.id,
        body: {
          reason: RandomGenerator.paragraph({ sentences: 2 }),
        } satisfies IShoppingMallCancellationRequest.ICreate,
      },
    );
  typia.assert(cancellationRequest);
  TestValidator.equals(
    "cancellation request status is pending",
    cancellationRequest.status,
    "pending",
  );
  // 9. Seller responds to the cancellation request (approve)
  const updatedCancellationRequest =
    await api.functional.shoppingMall.seller.cancellation_requests.update(
      sellerConnection,
      {
        cancellationRequestId: cancellationRequest.id,
        body: {
          status: "approved",
          responseReason: RandomGenerator.paragraph({ sentences: 2 }),
        } satisfies IShoppingMallCancellationRequest.IUpdate,
      },
    );
  typia.assert(updatedCancellationRequest);
  TestValidator.equals(
    "cancellation request status is approved",
    updatedCancellationRequest.status,
    "approved",
  );
  // 10. Seller retrieves the cancellation request after responding
  const retrievedCancellationRequest =
    await api.functional.shoppingMall.seller.cancellation_requests.at(
      sellerConnection,
      {
        cancellationRequestId: cancellationRequest.id,
      },
    );
  typia.assert(retrievedCancellationRequest);
  // Validations
  TestValidator.equals(
    "retrieved status is approved",
    retrievedCancellationRequest.status,
    "approved",
  );
  TestValidator.predicate(
    "updated timestamp is later than created timestamp",
    new Date(retrievedCancellationRequest.updatedAt).getTime() >
      new Date(retrievedCancellationRequest.createdAt).getTime(),
  );
  TestValidator.equals(
    "order item reference preserved",
    retrievedCancellationRequest.orderItem.id,
    orderItem.id,
  );
  TestValidator.equals(
    "customer reference preserved",
    retrievedCancellationRequest.customer.id,
    customerAuth.id,
  );
  TestValidator.equals(
    "reason preserved",
    retrievedCancellationRequest.reason,
    cancellationRequest.reason,
  );
}
