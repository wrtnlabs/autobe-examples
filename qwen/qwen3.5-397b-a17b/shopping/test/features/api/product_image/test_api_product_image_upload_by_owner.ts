export async function test_api_product_image_upload_by_owner(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      logo_image_url: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(seller);
  // 2. Create a product (utility handles category ID internally)
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_category_id: typia.random<string & tags.Format<"uuid">>(),
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Upload product image (first image, display_order should be 0)
  const imageUrl = typia.random<string & tags.Format<"uri">>();
  const image =
    await generate_random_shopping_mall_seller_products_images_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          image_url: imageUrl,
          display_order: 0,
        } satisfies IShoppingMallProductImage.ICreate,
      },
    );
  typia.assert(image);
  // 4. Verify image properties
  TestValidator.equals("image_url matches input", image.image_url, imageUrl);
  TestValidator.equals("display_order is 0", image.display_order, 0);
  TestValidator.equals("product id matches", image.product.id, product.id);
  TestValidator.predicate("created_at is valid", image.created_at !== null);
  TestValidator.predicate("updated_at is valid", image.updated_at !== null);
  TestValidator.predicate("deleted_at is null", image.deleted_at === null);
}