export async function test_api_product_option_definition_list_empty_result(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 2. Create a product without any option definitions
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Call the index endpoint to retrieve option definitions (should be empty)
  const response =
    await api.functional.shoppingMall.seller.products.option_definitions.index(
      sellerConnection,
      {
        productId: product.id,
        body: {
          page: 1,
          limit: 20,
        } satisfies IShoppingMallProductOptionDefinition.IRequest,
      },
    );
  typia.assert(response);
  // 4. Verify the response contains an empty data array
  TestValidator.equals("data array is empty", response.data.length, 0);
  // 5. Verify pagination metadata is correct
  TestValidator.equals("records count", response.pagination.records, 0);
  TestValidator.equals("pages count", response.pagination.pages, 0);
  TestValidator.equals("current page", response.pagination.current, 1);
  TestValidator.predicate("limit is positive", response.pagination.limit > 0);
}
