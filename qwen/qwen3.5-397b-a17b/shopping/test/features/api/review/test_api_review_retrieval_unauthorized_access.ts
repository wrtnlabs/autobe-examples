export async function test_api_review_retrieval_unauthorized_access(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup - create seller and product
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(sellerAuth);
  const product = await api.functional.shoppingMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 2. Customer A (review author) setup
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerAAuth = await authorize_customer_join(customerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(customerAAuth);
  // 3. Customer B (unauthorized user) setup
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerBAuth = await authorize_customer_join(customerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(customerBAuth);
  // 4. Customer A creates order using generation utility
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerAConnection,
    {},
  );
  typia.assert(order);
  // 5. Get first shipment and confirm delivery
  if (order.shipments.length > 0) {
    const shipment = order.shipments[0];
    const confirmedShipment =
      await api.functional.shoppingMall.customer.shipments.confirm_delivery.confirmDelivery(
        customerAConnection,
        {
          shipmentId: shipment.id,
        },
      );
    typia.assert(confirmedShipment);
    // 6. Customer A creates review for the product
    const review = await generate_random_shopping_mall_customer_reviews_create(
      customerAConnection,
      {
        body: {
          product_id: product.id,
          order_id: order.id,
        },
      },
    );
    typia.assert(review);
    // 7. Customer B attempts to access customer A's review - should fail with 403
    await TestValidator.error(
      "customer B cannot access customer A's review",
      async () => {
        await api.functional.shoppingMall.reviews.at(customerBConnection, {
          reviewId: review.id,
        });
      },
    );
  }
}
