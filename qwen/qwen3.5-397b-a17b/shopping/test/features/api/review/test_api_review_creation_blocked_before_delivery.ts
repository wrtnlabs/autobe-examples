/**
 * Test that review creation is rejected when order item status is not yet delivered.
 *
 * Validates the business rule that customers can only review products they have actually received. This test completes the full purchase flow up to order creation but deliberately does not create a shipment, leaving the order item in 'paid' status. The member then attempts to submit a review, which should be rejected with HTTP 403 Forbidden.
 *
 * Setup includes administrator creating a category, seller creating a product with variant, member creating an address, adding the variant to cart, and placing an order. The order item remains in 'paid' status since no shipment has been created by the seller.
 *
 * 1. Administrator creates category for product organization.
 * 2. Seller creates product in the category.
 * 3. Seller creates product variant for purchase.
 * 4. Member creates shipping address for order.
 * 5. Member adds product variant to cart.
 * 6. Member places order from cart (order item status is 'paid').
 * 7. Member attempts to create review for order item before delivery.
 * 8. Validates review creation is rejected with 403 Forbidden error.
 */
export async function test_api_review_creation_blocked_before_delivery(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      grade: "regular" as const,
    },
  });
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller creates product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  // 3. Seller creates product variant
  const variant = await generate_random_shopping_mall_seller_variants_create(
    sellerConnection,
    {
      body: {
        shopping_mall_product_id: product.id,
      },
    },
  );
  typia.assert(variant);
  // 4. Member creates account and address
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  const address = await generate_random_shopping_mall_member_addresses_create(
    memberConnection,
    {},
  );
  typia.assert(address);
  // 5. Member adds variant to cart
  const cartItem = await generate_random_shopping_mall_member_cart_items_create(
    memberConnection,
    {
      body: {
        product_variant_id: variant.id,
        quantity: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
        >(),
      },
    },
  );
  typia.assert(cartItem);
  // 6. Member places order (order item status is 'paid')
  const order = await generate_random_shopping_mall_member_orders_create(
    memberConnection,
    {
      body: {
        shopping_mall_customer_address_id: address.id,
      },
    },
  );
  typia.assert(order);
  // Verify order has items and they are in 'paid' status
  TestValidator.predicate("order has items", order.orderItems.length > 0);
  const orderItem = order.orderItems[0];
  TestValidator.equals("order item status is paid", orderItem.status, "paid");
  // 7 & 8. Member attempts to create review before delivery - should fail with 403
  await TestValidator.httpError(
    "review creation blocked before delivery",
    403,
    async () => {
      await api.functional.shoppingMall.member.reviews.create(
        memberConnection,
        {
          body: {
            shopping_mall_product_id: product.id,
            shopping_mall_order_id: order.id,
            shopping_mall_order_item_id: orderItem.id,
            rating: typia.random<
              number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
            >(),
            content: RandomGenerator.paragraph({ sentences: 3 }),
          } satisfies IShoppingMallReview.ICreate,
        },
      );
    },
  );
}
