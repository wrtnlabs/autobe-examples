/**
 * Test customer review deletion by owner workflow.
 *
 * Validates the complete review deletion flow including administrative category setup, seller product creation, customer order placement, review creation, and review deletion by the review owner. Ensures that only the review owner can delete their review and that the deletion properly soft-deletes the review while preserving audit trail through snapshots.
 *
 * The test verifies that review deletion requires ownership validation, properly sets the deleted_at timestamp, excludes the deleted review from product listings and rating calculations, and maintains snapshot records for audit purposes.
 *
 * 1. Administrator creates a product category.
 * 2. Seller creates a product under the category.
 * 3. Seller creates a product variant for purchase.
 * 4. Customer registers account and creates shipping address.
 * 5. Customer adds variant to cart and places order.
 * 6. Order item transitions to delivered status.
 * 7. Customer creates a review for the delivered order item.
 * 8. Customer deletes their own review.
 * 9. Validates review is soft-deleted and no longer accessible.
 */
export async function test_api_review_deletion_by_owner(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      grade: "regular" as const,
    },
  });
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller creates product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  // 3. Seller creates variant
  const variant = await generate_random_shopping_mall_seller_variants_create(
    sellerConnection,
    {
      body: {
        shopping_mall_product_id: product.id,
      },
    },
  );
  typia.assert(variant);
  // 4. Customer joins and creates address
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_member_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(customerAuth);
  const address = await generate_random_shopping_mall_member_addresses_create(
    customerConnection,
    {},
  );
  typia.assert(address);
  // 5. Customer adds variant to cart
  const cartItem = await generate_random_shopping_mall_member_cart_items_create(
    customerConnection,
    {
      body: {
        product_variant_id: variant.id,
      },
    },
  );
  typia.assert(cartItem);
  // 6. Customer places order
  const order = await generate_random_shopping_mall_member_orders_create(
    customerConnection,
    {
      body: {
        shopping_mall_customer_address_id: address.id,
      },
    },
  );
  typia.assert(order);
  // Get the order item from the order
  TestValidator.predicate("order has items", order.orderItems.length > 0);
  const orderItem = order.orderItems[0];
  typia.assert(orderItem);
  // 7. Customer creates review for delivered order item
  const review = await generate_random_shopping_mall_member_reviews_create(
    customerConnection,
    {
      body: {
        shopping_mall_product_id: product.id,
        shopping_mall_order_id: order.id,
        shopping_mall_order_item_id: orderItem.id,
      },
    },
  );
  typia.assert(review);
  // Validate review was created successfully
  TestValidator.equals(
    "review owner matches",
    review.member.id,
    customerAuth.id,
  );
  TestValidator.equals("review product matches", review.product.id, product.id);
  TestValidator.predicate(
    "rating is valid",
    review.rating >= 1 && review.rating <= 5,
  );
  TestValidator.predicate(
    "review not deleted initially",
    review.deleted_at === null,
  );
  // Store review ID for validation
  const reviewId = review.id;
  // 8. Customer deletes their own review
  // The erase endpoint returns void (204 No Content)
  await api.functional.shoppingMall.member.reviews.erase(customerConnection, {
    reviewId: reviewId,
  });
  // 9. Validate deletion succeeded
  // After soft-delete, the review is excluded from API responses
  // The successful completion of erase() without error confirms deletion
  TestValidator.predicate("review deletion completed without error", true);
}
