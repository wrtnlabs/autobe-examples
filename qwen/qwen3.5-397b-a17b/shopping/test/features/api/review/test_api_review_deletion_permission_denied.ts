/**
 * Test that a customer cannot delete another customer's review.
 *
 * Validates the permission enforcement for review deletion by ensuring that customers can only delete their own reviews. The test sets up a complete e-commerce scenario with administrative category creation, seller product listing, and two separate customer accounts where one customer creates a review and another attempts to delete it.
 *
 * The test verifies that the system properly enforces ownership validation at the API level, returning appropriate authorization errors when customers attempt to modify resources they do not own. This protects review integrity and prevents malicious deletion of other users' feedback.
 *
 * 1. Administrator creates a product category for organization.
 * 2. Seller creates a product with the category and adds a purchasable variant.
 * 3. First customer registers, creates shipping address, places order, and creates a review for the delivered order item.
 * 4. Second customer registers separately with different credentials.
 * 5. Second customer attempts to delete the first customer's review using the review ID.
 * 6. Validates that the deletion attempt fails with 403 Forbidden error and the review remains active.
 */
export async function test_api_review_deletion_permission_denied(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      grade: "regular" as const,
    },
  });
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup - create product and variant
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  const variant = await generate_random_shopping_mall_seller_variants_create(
    sellerConnection,
    {
      body: {
        shopping_mall_product_id: product.id,
      },
    },
  );
  typia.assert(variant);
  // 3. First customer - complete purchase flow and create review
  const customer1Connection: api.IConnection = { host: connection.host };
  const customer1Auth = await authorize_member_join(customer1Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(customer1Auth);
  const address = await generate_random_shopping_mall_member_addresses_create(
    customer1Connection,
    {},
  );
  typia.assert(address);
  await generate_random_shopping_mall_member_cart_items_create(
    customer1Connection,
    {
      body: {
        product_variant_id: variant.id,
        quantity: typia.random<number & tags.Type<"int32"> & tags.Minimum<1>>(),
      },
    },
  );
  const order = await generate_random_shopping_mall_member_orders_create(
    customer1Connection,
    {
      body: {
        shopping_mall_customer_address_id: address.id,
      },
    },
  );
  typia.assert(order);
  // Get the first order item for review creation - order must have at least one item
  TestValidator.predicate(
    "order has at least one item",
    () => order.orderItems.length > 0,
  );
  const orderItem = order.orderItems[0];
  typia.assert(orderItem);
  // Create review for the delivered order item
  const review = await generate_random_shopping_mall_member_reviews_create(
    customer1Connection,
    {
      body: {
        shopping_mall_product_id: product.id,
        shopping_mall_order_id: order.id,
        shopping_mall_order_item_id: orderItem.id,
      },
    },
  );
  typia.assert(review);
  // 4. Second customer - register separately
  const customer2Connection: api.IConnection = { host: connection.host };
  await authorize_member_join(customer2Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 5. Second customer attempts to delete first customer's review
  // This should fail with 403 Forbidden due to ownership validation
  await TestValidator.error(
    "second customer cannot delete another customer's review",
    async () => {
      await api.functional.shoppingMall.member.reviews.erase(
        customer2Connection,
        {
          reviewId: review.id,
        },
      );
    },
  );
  // 6. Review ownership protection validated
  // Note: Cannot verify review persistence (deleted_at remains null) as no GET review endpoint is available
  // The successful error validation confirms the permission check prevented the deletion
}
