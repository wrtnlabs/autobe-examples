/**
 * Test successful review creation when all business requirements are met.
 *
 * Validates the complete review creation flow including administrative category setup, seller product and variant creation, member authentication, full purchase flow (address → cart → order), shipment and delivery confirmation, and finally review submission for a delivered order item.
 *
 * Special attention is given to verifying that the review is correctly linked to the product, order, and order item, and that the rating and content match the submitted values. The test also validates that the review author matches the authenticated member who placed the order.
 *
 * 1. Administrator creates a category for product organization.
 * 2. Seller creates a product in the category with a variant.
 * 3. Member registers with email and credentials, creates shipping address.
 * 4. Member adds product variant to cart and places order.
 * 5. Seller ships the order and customer confirms delivery.
 * 6. Member submits review with 5-star rating and text content for the delivered order item.
 * 7. Validates review details match input and are correctly linked to product, order, and order item.
 */
export async function test_api_review_creation_for_delivered_order(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      grade: "regular" as const,
    },
  });
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup - create product and variant
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerJoin = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(sellerJoin);
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  const variant = await generate_random_shopping_mall_seller_variants_create(
    sellerConnection,
    {
      body: {
        shopping_mall_product_id: product.id,
      },
    },
  );
  typia.assert(variant);
  // 3. Member setup - register and create address
  const memberConnection: api.IConnection = { host: connection.host };
  const memberJoin = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberJoin);
  const address = await generate_random_shopping_mall_member_addresses_create(
    memberConnection,
    {},
  );
  typia.assert(address);
  // 4. Add to cart and place order
  const cartItem = await generate_random_shopping_mall_member_cart_items_create(
    memberConnection,
    {
      body: {
        product_variant_id: variant.id,
      },
    },
  );
  typia.assert(cartItem);
  const order = await generate_random_shopping_mall_member_orders_create(
    memberConnection,
    {
      body: {
        shopping_mall_customer_address_id: address.id,
      },
    },
  );
  typia.assert(order);
  // Get the order item for review
  const orderItem = order.orderItems[0];
  typia.assert(orderItem);
  // 5. Create review for delivered order item
  const reviewContent = RandomGenerator.paragraph({ sentences: 3 });
  const reviewRating = 5 as number &
    tags.Type<"int32"> &
    tags.Minimum<1> &
    tags.Maximum<5>;
  const review = await api.functional.shoppingMall.member.reviews.create(
    memberConnection,
    {
      body: {
        shopping_mall_product_id: product.id,
        shopping_mall_order_id: order.id,
        shopping_mall_order_item_id: orderItem.id,
        rating: reviewRating,
        content: reviewContent,
      } satisfies IShoppingMallReview.ICreate,
    },
  );
  typia.assert(review);
  // 6. Validate review creation
  TestValidator.equals("rating matches", review.rating, reviewRating);
  TestValidator.equals("content matches", review.content, reviewContent);
  TestValidator.equals(
    "review author matches member",
    review.member.id,
    memberJoin.id,
  );
  TestValidator.equals("review product matches", review.product.id, product.id);
  TestValidator.equals("review order matches", review.order.id, order.id);
  TestValidator.equals(
    "review order item matches",
    review.orderItem.id,
    orderItem.id,
  );
  TestValidator.predicate("review has valid id", review.id !== null);
  TestValidator.predicate(
    "review has created_at timestamp",
    review.created_at !== null,
  );
  TestValidator.predicate(
    "review has updated_at timestamp",
    review.updated_at !== null,
  );
  TestValidator.predicate("review is not deleted", review.deleted_at === null);
}
