/**
 * Test that a seller can retrieve variant options from an order item snapshot
 * for a product without any configurable options, which should return an empty array.
 *
 * This test verifies the edge case handling for simple products that have no
 * option definitions (no Color, Size, etc.). The variant-options endpoint should
 * return an empty data array with proper pagination metadata when querying a
 * snapshot for a product variant that was created without any option values.
 */
export async function test_api_order_item_snapshot_variant_options_empty_for_simple_product(
  connection: api.IConnection,
): Promise<void> {
  // Store credentials for reuse
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  const customerEmail = typia.random<string & tags.Format<"email">>();
  const customerPassword = RandomGenerator.alphaNumeric(16);
  // 1. Seller setup - register and login
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  // 2. Seller creates simple product WITHOUT option definitions
  const product = await api.functional.shoppingMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Seller creates variant with EMPTY option_value_ids (simple product)
  const variant =
    await api.functional.shoppingMall.seller.products.variants.create(
      sellerConnection,
      {
        productId: product.id,
        body: {
          sku_code: `SIMPLE-${RandomGenerator.alphaNumeric(8)}`,
          price_override: null,
          option_value_ids: [], // Empty array - no configurable options
        } satisfies IShoppingMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  TestValidator.equals(
    "variant has no options",
    variant.variantOptions.length,
    0,
  );
  // 4. Customer setup - register and login
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: customerEmail,
      password: customerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  // 5. Customer creates shipping address
  const address = await api.functional.shoppingMall.customer.addresses.create(
    customerConnection,
    {
      body: {
        recipientName: RandomGenerator.name(),
        recipientPhone: RandomGenerator.mobile(),
        streetAddress: RandomGenerator.paragraph({ sentences: 1 }),
        city: RandomGenerator.name(),
        state: RandomGenerator.name(),
        postalCode: typia.random<string>(),
        country: "South Korea",
        isDefault: true,
      } satisfies IShoppingMallAddress.ICreate,
    },
  );
  typia.assert(address);
  // 6. Customer adds simple product variant to cart
  const cartItem = await api.functional.shoppingMall.customer.cart.items.create(
    customerConnection,
    {
      body: {
        shopping_mall_product_variant_id: variant.id,
        quantity: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
        >(),
      } satisfies IShoppingMallCartItem.ICreate,
    },
  );
  typia.assert(cartItem);
  // 7. Customer places order
  const order = await api.functional.shoppingMall.customer.orders.create(
    customerConnection,
    {
      body: {
        shopping_mall_address_id: address.id,
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order);
  TestValidator.predicate("order has items", order.orderItems.length > 0);
  // Get the order item for the simple product
  const orderItem = order.orderItems[0];
  // 8. Seller retrieves variant options for the order item snapshot
  // This should return empty array since the product has no configurable options
  // Note: Using orderItem.id as snapshotId - in production this would be the actual snapshot ID
  const variantOptionsResult =
    await api.functional.shoppingMall.seller.orders.items.snapshots.variant_options.index(
      sellerConnection,
      {
        itemId: orderItem.id,
        snapshotId: orderItem.id,
        body: {
          page: 1,
          limit: 10,
        } satisfies IShoppingMallOrderItemSnapshotVariantOption.IRequest,
      },
    );
  typia.assert(variantOptionsResult);
  // 9. Validate empty array response with pagination metadata
  TestValidator.equals(
    "variant options array is empty",
    variantOptionsResult.data.length,
    0,
  );
  TestValidator.equals(
    "pagination current page",
    variantOptionsResult.pagination.current,
    1,
  );
  TestValidator.equals(
    "pagination limit",
    variantOptionsResult.pagination.limit,
    10,
  );
  TestValidator.equals(
    "pagination records count",
    variantOptionsResult.pagination.records,
    0,
  );
  TestValidator.equals(
    "pagination total pages",
    variantOptionsResult.pagination.pages,
    0,
  );
}
