/**
 * Test member order item snapshot retrieval success.
 *
 * Validates the complete order item snapshot retrieval workflow including member and seller authentication, product creation with variants, cart operations, order placement, and snapshot retrieval. Ensures that the snapshot correctly preserves the product state at purchase time.
 *
 * Special attention is given to verifying that all snapshot fields are present and accurate: product_name, product_description, variant_price, seller_shop_name, seller_logo_url, options array with key-value pairs, and created_at timestamp.
 *
 * 1. Member registers and authenticates via join operation.
 * 2. Seller registers and authenticates via join operation (separate user).
 * 3. Seller creates a product with name, description, category, and base price.
 * 4. Seller creates a product variant with SKU code and option values.
 * 5. Member adds the product variant to cart.
 * 6. Member places an order to create order items with snapshots.
 * 7. Retrieve the snapshot for the order item using order ID and order item ID.
 * 8. Validate the response contains all required snapshot fields and matches the original product data.
 */
export async function test_api_order_item_snapshot_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Member registration and authentication
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallMember.IJoin,
  });
  typia.assert(memberAuth);
  // 2. Seller registration and authentication
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 3. Seller creates a product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      },
    },
  );
  typia.assert(product);
  // 4. Seller creates a product variant
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku_code: RandomGenerator.alphaNumeric(8),
          option_values: "Color: Red, Size: Large",
          price: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
        },
      },
    );
  typia.assert(variant);
  // 5. Member adds the product variant to cart
  const cartItem = await generate_random_shopping_mall_member_cart_items_create(
    memberConnection,
    {
      body: {
        product_variant_id: variant.id,
        quantity: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
        >(),
      },
    },
  );
  typia.assert(cartItem);
  // 6. Member places an order (requires a customer address - using random UUID for test)
  const order = await generate_random_shopping_mall_member_orders_create(
    memberConnection,
    {
      body: {
        shopping_mall_customer_address_id: typia.random<
          string & tags.Format<"uuid">
        >(),
      },
    },
  );
  typia.assert(order);
  // Verify order has at least one order item
  TestValidator.predicate("order has items", order.orderItems.length > 0);
  // Get the first order item
  const orderItem = order.orderItems[0]!;
  // 7. Retrieve the snapshot for the order item
  const snapshot =
    await api.functional.shoppingMall.member.orders.items.snapshot.at(
      memberConnection,
      {
        orderId: order.id,
        orderItemId: orderItem.id,
      },
    );
  typia.assert(snapshot);
  // 8. Validate snapshot contains all required fields
  TestValidator.equals(
    "product name matches",
    snapshot.product_name,
    product.name,
  );
  TestValidator.equals(
    "product description matches",
    snapshot.product_description,
    product.description,
  );
  TestValidator.equals(
    "variant price matches",
    snapshot.variant_price,
    variant.price ?? product.base_price,
  );
  TestValidator.predicate(
    "seller shop name exists",
    snapshot.seller_shop_name.length > 0,
  );
  TestValidator.predicate("options array exists", snapshot.options.length > 0);
  TestValidator.predicate(
    "created_at is valid date",
    new Date(snapshot.created_at).getTime() > 0,
  );
  // Validate snapshot options have key-value pairs
  const firstOption = snapshot.options[0]!;
  TestValidator.predicate("option has key", firstOption.key.length > 0);
  TestValidator.predicate("option has value", firstOption.value.length > 0);
}
