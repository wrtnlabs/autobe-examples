/**
 * Test error handling when attempting to remove an already deleted cart item.
 *
 * Scenario: A customer removes a cart item, then attempts to remove the same item again.
 * The system should return 404 Not Found without revealing that the item existed.
 *
 * Steps:
 * 1. Customer registers and authenticates
 * 2. Seller creates product with option definition, option value, and variant
 * 3. Customer adds the variant to cart
 * 4. Customer removes the cart item (first deletion succeeds)
 * 5. Customer attempts to remove the same cart item again (should fail with 404)
 *
 * Validations:
 * - Verify the second deletion attempt returns 404 Not Found
 * - Verify the error response does not reveal whether the item existed or belonged to the customer
 * - Verify the cart state remains unchanged after the failed deletion attempt
 */
export async function test_api_cart_item_removal_already_deleted(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer setup - register and login
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  // 2. Seller setup - register and login
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  // 3. Seller creates product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 4. Seller creates option definition
  const optionDefinition =
    await generate_random_shopping_mall_seller_products_option_definitions_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          name: "Color",
        } satisfies IShoppingMallProductOptionDefinition.ICreate,
      },
    );
  typia.assert(optionDefinition);
  // 5. Seller creates option value
  const optionValue =
    await generate_random_shopping_mall_seller_products_option_definitions_option_values_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
          optionDefinitionId: optionDefinition.id,
        },
        body: {
          name: "Red",
        } satisfies IShoppingMallProductOptionValue.ICreate,
      },
    );
  typia.assert(optionValue);
  // 6. Seller creates variant
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku_code: RandomGenerator.alphaNumeric(10),
          price_override: null,
          option_value_ids: [optionValue.id],
        } satisfies IShoppingMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 7. Customer adds variant to cart
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          shopping_mall_product_variant_id: variant.id,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 8. First deletion - should succeed (no response to validate)
  await api.functional.shoppingMall.customer.cart.items.erase(
    customerConnection,
    {
      itemId: cartItem.id,
    },
  );
  // 9. Second deletion - should fail with 404 Not Found
  await TestValidator.error(
    "second deletion should fail with 404",
    async () => {
      await api.functional.shoppingMall.customer.cart.items.erase(
        customerConnection,
        {
          itemId: cartItem.id,
        },
      );
    },
  );
}
