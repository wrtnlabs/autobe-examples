/**
 * Test adding a product variant that is out of stock (zero inventory) to the shopping cart.
 *
 * Validates the complete workflow where a member attempts to add a product variant with zero stock to their shopping cart. This test verifies that the system allows adding out-of-stock variants to cart, as stock validation is deferred to checkout time rather than enforced at cart addition.
 *
 * The test setup involves three actors: an administrator who creates a category, a seller who creates a product and variant (without adding inventory), and a member who attempts to add the out-of-stock variant to their cart.
 *
 * 1. Administrator joins and creates a product category.
 * 2. Seller joins and creates a product under the category.
 * 3. Seller creates a product variant without restocking inventory (zero stock).
 * 4. Member joins to authenticate as a customer.
 * 5. Member adds the out-of-stock variant to cart with specified quantity.
 * 6. Validates cart item is created successfully despite zero stock.
 * 7. Validates the variant's stock_quantity is zero in the response.
 */
export async function test_api_cart_item_out_of_stock_variant(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup: Create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      grade: "regular" as const,
    },
  });
  const category =
    await generate_random_shopping_mall_admin_categories_create(
      adminConnection,
      { body: {} },
    );
  typia.assert(category);
  // 2. Seller setup: Create product and variant
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  // Create variant WITHOUT adding inventory (zero stock)
  const variant = await generate_random_shopping_mall_seller_variants_create(
    sellerConnection,
    {
      body: {
        shopping_mall_product_id: product.id,
      },
    },
  );
  typia.assert(variant);
  // 3. Member setup: Join as customer
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 4. Add out-of-stock variant to cart
  const cartItem = await generate_random_shopping_mall_member_cart_items_create(
    memberConnection,
    {
      body: {
        product_variant_id: variant.id,
        quantity: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
        >(),
      },
    },
  );
  typia.assert(cartItem);
  // 5. Validate cart item was created successfully
  TestValidator.equals(
    "cart item variant matches",
    cartItem.productVariant.id,
    variant.id,
  );
  TestValidator.predicate(
    "cart item quantity is positive",
    cartItem.quantity >= 1,
  );
}