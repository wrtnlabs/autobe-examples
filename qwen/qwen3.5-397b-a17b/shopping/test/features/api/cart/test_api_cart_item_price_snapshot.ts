export async function test_api_cart_item_price_snapshot(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customer);
  // 2. Register and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(seller);
  // 3. Seller creates a product with base price $50
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: 50,
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 4. Seller creates a variant for the product (no price override, uses base price $50)
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku_code: `SKU-${RandomGenerator.alphaNumeric(8)}`,
          price_override: null,
          option_value_ids: [],
        } satisfies IShoppingMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 5. Customer adds the variant to cart with quantity 2 (price captured as $50)
  const cartItem1 =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          shopping_mall_product_variant_id: variant.id,
          quantity: 2,
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem1);
  // Verify initial cart item price is $50
  TestValidator.equals("initial cart item price", cartItem1.price, 50);
  TestValidator.equals("initial cart item quantity", cartItem1.quantity, 2);
  // 6. Seller updates the variant price to $75
  const updatedVariant =
    await api.functional.shoppingMall.seller.products.variants.update(
      sellerConnection,
      {
        productId: product.id,
        variantId: variant.id,
        body: {
          price_override: 75,
        } satisfies IShoppingMallProductVariant.IUpdate,
      },
    );
  typia.assert(updatedVariant);
  TestValidator.equals(
    "updated variant price",
    updatedVariant.priceOverride,
    75,
  );
  // 7. Customer adds the same variant again with quantity 1 (should merge)
  const cartItem2 =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          shopping_mall_product_variant_id: variant.id,
          quantity: 1,
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem2);
  // 8. Verify the merged cart item still shows $50 as the unit price
  TestValidator.equals(
    "merged cart item price (should be original $50, not $75)",
    cartItem2.price,
    50,
  );
  TestValidator.equals(
    "merged cart item quantity (2 + 1 = 3)",
    cartItem2.quantity,
    3,
  );
  // 9. Verify cart total_amount uses captured price ($50 × 3 = $150)
  TestValidator.equals(
    "cart total amount (3 items × $50)",
    cartItem2.cart.total_amount,
    150,
  );
  // Additional validation: price snapshot immutability
  TestValidator.predicate(
    "price snapshot is immutable after capture",
    cartItem2.price === 50 && updatedVariant.priceOverride === 75,
  );
}