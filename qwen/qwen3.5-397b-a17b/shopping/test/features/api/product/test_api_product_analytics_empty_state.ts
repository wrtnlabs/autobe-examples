export async function test_api_product_analytics_empty_state(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 2. Create a new product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Retrieve analytics for the newly created product
  const analytics = await api.functional.shoppingMall.seller.products.analytics(
    sellerConnection,
    {
      productId: product.id,
    },
  );
  typia.assert(analytics);
  // 4. Verify empty state analytics
  TestValidator.equals(
    "totalUnitsSold should be 0",
    analytics.totalUnitsSold,
    0,
  );
  TestValidator.equals("totalRevenue should be 0", analytics.totalRevenue, 0);
  TestValidator.equals("reviewCount should be 0", analytics.reviewCount, 0);
  TestValidator.equals(
    "averageRating should be null",
    analytics.averageRating,
    null,
  );
}
