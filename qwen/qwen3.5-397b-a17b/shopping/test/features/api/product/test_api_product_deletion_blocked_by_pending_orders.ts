/**
 * Test product deletion is blocked when product variants have pending order items.
 *
 * Scenario: A seller attempts to delete a product that has order items in paid or shipped status.
 *
 * Steps:
 * 1. Seller registers and authenticates via join
 * 2. Seller creates a product with variants
 * 3. Customer registers and authenticates via join
 * 4. Customer creates an order with the seller's product, resulting in order items with 'paid' status
 * 5. Seller attempts to delete the product
 * 6. Verify deletion is rejected with 409 Conflict
 * 7. Verify product remains active (not deleted)
 *
 * Expected Results:
 * - DELETE returns 409 Conflict
 * - Error message indicates pending order items block deletion
 * - Product deleted_at remains null
 * - Product variants remain intact
 * - Order history preserved for legal purposes
 *
 * Business Rule: Sellers cannot delete products with pending order items in paid or shipped status to maintain transaction integrity.
 */
export async function test_api_product_deletion_blocked_by_pending_orders(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller registration and authentication
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 2. Seller creates a product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Customer registration and authentication
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  // 4. Customer creates an order with the seller's product
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        shopping_mall_address_id: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order);
  // Verify order contains items with 'paid' status
  TestValidator.predicate("order has items", order.orderItems.length > 0);
  TestValidator.equals(
    "order items have paid status",
    order.orderItems[0].status,
    "paid",
  );
  // 5. Seller attempts to delete the product (should fail with 409 Conflict)
  await TestValidator.httpError(
    "product deletion blocked by pending orders",
    409,
    async () => {
      await api.functional.shoppingMall.seller.products.erase(
        sellerConnection,
        {
          productId: product.id,
        },
      );
    },
  );
  // 6. Verify product ID is still valid (product was not deleted)
  TestValidator.predicate(
    "product ID remains valid after failed deletion",
    product.id !== null,
  );
}
