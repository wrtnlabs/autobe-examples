/**
 * Test administrator product deletion with pending order items.
 *
 * Validates that administrators can delete products even when they have pending order items in paid status. This tests the elevated admin permission that bypasses deletion conditions enforced on sellers, enabling platform oversight for policy violations and content moderation.
 *
 * The test creates a complete order workflow: admin creates category, seller creates product, customer places order creating paid order items, then admin deletes the product. Unlike seller deletion which would fail with pending orders, admin deletion succeeds demonstrating the permission hierarchy.
 *
 * 1. Administrator authenticates and creates a product category.
 * 2. Seller authenticates and creates a product in the category.
 * 3. Customer authenticates and places an order creating paid order items.
 * 4. Administrator deletes the product despite pending orders.
 * 5. Validates deletion completes without error indicating admin bypass works.
 */
export async function test_api_admin_product_deletion_with_pending_orders(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      grade: "regular" as const,
    },
  });
  typia.assert(adminAuth);
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup - create product
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  // 3. Customer setup - place order creating pending order items
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_member_join(customerConnection, {});
  typia.assert(customerAuth);
  const order = await generate_random_shopping_mall_member_orders_create(
    customerConnection,
    {},
  );
  typia.assert(order);
  // Verify order was created with items (paid status)
  TestValidator.predicate("order created", order.id !== null);
  TestValidator.predicate("order has items", order.orderItems.length > 0);
  TestValidator.equals(
    "order items reference product",
    order.orderItems[0].product.id,
    product.id,
  );
  // 4. Admin deletes product despite pending orders
  // This should succeed because admin bypasses deletion conditions
  await api.functional.shoppingMall.admin.products.erase(adminConnection, {
    productId: product.id,
  });
  // 5. Validate deletion succeeded (no error thrown means success)
  // The 204 No Content response indicates successful soft deletion
  TestValidator.predicate(
    "admin deletion succeeded despite pending orders",
    true,
  );
}
