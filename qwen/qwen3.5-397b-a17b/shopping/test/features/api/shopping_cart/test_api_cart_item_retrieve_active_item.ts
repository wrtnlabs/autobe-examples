export async function test_api_cart_item_retrieve_active_item(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer setup - create and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  // 2. Seller setup - create and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 3. Create product using generation function
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 4. Create product variant using generation function
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku_code: `SKU-${RandomGenerator.alphaNumeric(8)}`,
          price_override: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
          option_value_ids: [],
        } satisfies IShoppingMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 5. Add variant to customer cart using generation function
  const cartQuantity = typia.random<
    number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
  >();
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          shopping_mall_product_variant_id: variant.id,
          quantity: cartQuantity,
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 6. Retrieve the cart item by ID
  const retrievedItem =
    await api.functional.shoppingMall.customer.cart.items.at(
      customerConnection,
      {
        itemId: cartItem.id,
      },
    );
  typia.assert(retrievedItem);
  // 7. Validate retrieved item matches the created item
  TestValidator.equals("item ID matches", retrievedItem.id, cartItem.id);
  TestValidator.equals(
    "quantity matches",
    retrievedItem.quantity,
    cartQuantity,
  );
  TestValidator.equals(
    "price snapshot matches",
    retrievedItem.price,
    cartItem.price,
  );
  TestValidator.equals(
    "cart customer matches",
    retrievedItem.cart.customer.id,
    customerAuth.id,
  );
  TestValidator.equals(
    "variant SKU matches",
    retrievedItem.productVariant.sku_code,
    variant.skuCode,
  );
  TestValidator.equals(
    "variant ID matches",
    retrievedItem.productVariant.id,
    variant.id,
  );
  TestValidator.predicate(
    "created_at is valid date-time",
    () =>
      new Date(retrievedItem.created_at).getTime() > 0 &&
      new Date(retrievedItem.created_at).getTime() <= Date.now(),
  );
  TestValidator.predicate(
    "updated_at is valid date-time",
    () =>
      new Date(retrievedItem.updated_at).getTime() > 0 &&
      new Date(retrievedItem.updated_at).getTime() <= Date.now(),
  );
  TestValidator.equals(
    "deleted_at is null (active item)",
    retrievedItem.deleted_at,
    null,
  );
}
