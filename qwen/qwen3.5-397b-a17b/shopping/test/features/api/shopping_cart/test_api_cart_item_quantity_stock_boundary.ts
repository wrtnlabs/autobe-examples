/**
 * Test cart item quantity update with stock availability validation at boundary.
 *
 * Validates the complete cart item quantity update flow including administrative category setup, seller product and variant creation, member authentication, cart item creation, and quantity update at stock boundary. Ensures that the quantity update correctly validates against available stock and returns the updated cart item with proper timestamps.
 *
 * Special attention is given to verifying that the quantity update respects stock limits and that the updated_at timestamp reflects the modification time. The test confirms cart item remains available when quantity matches stock exactly.
 *
 * 1. Administrator creates a product category for organization.
 * 2. Seller registers and creates a product under the category.
 * 3. Seller creates a product variant with SKU and option values.
 * 4. Member registers and authenticates as new customer.
 * 5. Member adds the variant to cart with initial quantity (3).
 * 6. Member updates cart item quantity to boundary value (10).
 * 7. Validates updated quantity matches requested value and timestamp is updated.
 */
export async function test_api_cart_item_quantity_stock_boundary(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      grade: "regular" as const,
    } satisfies IShoppingMallAdmin.IJoin,
  });
  const category =
    await generate_random_shopping_mall_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 2. Seller setup - create product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  // 3. Seller creates variant
  const variant = await generate_random_shopping_mall_seller_variants_create(
    sellerConnection,
    {
      body: {
        shopping_mall_product_id: product.id,
      },
    },
  );
  typia.assert(variant);
  // 4. Member setup - join and authenticate
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallMember.IJoin,
  });
  // 5. Member adds variant to cart with initial quantity
  const initialQuantity = 3;
  const cartItem = await generate_random_shopping_mall_member_cart_items_create(
    memberConnection,
    {
      body: {
        product_variant_id: variant.id,
        quantity: initialQuantity,
      },
    },
  );
  typia.assert(cartItem);
  // 6. Member updates cart item quantity to boundary value (10)
  const boundaryQuantity = 10;
  const updatedCartItem =
    await api.functional.shoppingMall.member.cart.items.update(
      memberConnection,
      {
        cartItemId: cartItem.id,
        body: {
          quantity: boundaryQuantity,
        } satisfies IShoppingMallCartItem.IUpdate,
      },
    );
  typia.assert(updatedCartItem);
  // 7. Validate update results
  TestValidator.equals(
    "cart item ID unchanged",
    updatedCartItem.id,
    cartItem.id,
  );
  TestValidator.equals(
    "quantity updated to boundary",
    updatedCartItem.quantity,
    boundaryQuantity,
  );
  TestValidator.equals(
    "product variant ID unchanged",
    updatedCartItem.productVariant.id,
    variant.id,
  );
  TestValidator.predicate(
    "updated_at timestamp is after created_at",
    new Date(updatedCartItem.updated_at).getTime() >=
      new Date(updatedCartItem.created_at).getTime(),
  );
  TestValidator.predicate(
    "updated_at reflects modification",
    new Date(updatedCartItem.updated_at).getTime() >
      new Date(cartItem.created_at).getTime(),
  );
}