export async function test_api_super_administrator_customer_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register super administrator account
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_administrator_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallSuperAdministrator.IJoin,
  });
  // 2. Attempt to retrieve non-existent customer
  const nonExistentCustomerId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  await TestValidator.httpError(
    "super administrator receives 404 for non-existent customer",
    404,
    async () => {
      await api.functional.shoppingMall.superAdministrator.customers.at(
        superAdminConnection,
        {
          customerId: nonExistentCustomerId,
        },
      );
    },
  );
}
