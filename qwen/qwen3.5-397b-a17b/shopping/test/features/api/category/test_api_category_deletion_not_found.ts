export async function test_api_category_deletion_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator authentication
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallAdministrator.IJoin,
  });
  // 2. Test deleting non-existent category returns 404
  const nonExistentCategoryId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "delete non-existent category returns 404",
    404,
    async () => {
      await api.functional.shoppingMall.administrator.categories.erase(
        adminConnection,
        {
          categoryId: nonExistentCategoryId,
        },
      );
    },
  );
}
