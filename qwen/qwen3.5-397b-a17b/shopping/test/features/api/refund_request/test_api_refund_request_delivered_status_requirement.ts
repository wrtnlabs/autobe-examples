/**
 * Test refund request delivered status requirement.
 *
 * Validates the business rule that refund requests are only accepted for order items with 'delivered' status. The test attempts to create a refund request for an order item with 'paid' status (not yet shipped) and verifies it is rejected by the system.
 *
 * The test ensures that the system correctly rejects refund requests for non-delivered items. This validates the delivered status requirement from business rules sections 87 and 340. Full workflow testing including 'shipped' and 'delivered' status transitions requires shipment creation and delivery confirmation endpoints which are not available in the current SDK function set.
 *
 * 1. Admin creates category for product organization.
 * 2. Seller creates product and variant with stock.
 * 3. Member adds variant to cart, creates address, and places order (order items have 'paid' status).
 * 4. Attempts refund request for 'paid' status item - should be rejected because item is not yet delivered.
 * 5. Validates that the system enforces delivered status requirement for refund requests.
 */
export async function test_api_refund_request_delivered_status_requirement(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      grade: "regular",
    } satisfies IShoppingMallAdmin.IJoin,
  });
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup - create product and variant
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  const variant = await generate_random_shopping_mall_seller_variants_create(
    sellerConnection,
    {
      body: {
        shopping_mall_product_id: product.id,
      },
    },
  );
  typia.assert(variant);
  // 3. Member setup - join, add to cart, create address, place order
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallMember.IJoin,
  });
  await generate_random_shopping_mall_member_cart_items_create(
    memberConnection,
    {
      body: {
        product_variant_id: variant.id,
        quantity: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<2>
        >(),
      },
    },
  );
  const address = await generate_random_shopping_mall_member_addresses_create(
    memberConnection,
    {},
  );
  typia.assert(address);
  const order = await generate_random_shopping_mall_member_orders_create(
    memberConnection,
    {
      body: {
        shopping_mall_customer_address_id: address.id,
      },
    },
  );
  typia.assert(order);
  // Verify order has items with 'paid' status initially
  TestValidator.predicate("order has items", order.orderItems.length > 0);
  const orderItem = order.orderItems[0];
  TestValidator.equals("initial status is paid", orderItem.status, "paid");
  // 4. Attempt refund request for 'paid' status item - should be rejected
  await TestValidator.error(
    "refund request rejected for paid status",
    async () => {
      await api.functional.shoppingMall.member.refund_requests.create(
        memberConnection,
        {
          body: {
            order_item_id: orderItem.id,
            reason: RandomGenerator.paragraph({ sentences: 2 }),
          } satisfies IShoppingMallRefundRequest.ICreate,
        },
      );
    },
  );
  // 5. Validate delivered status requirement
  // The test confirms that refund requests cannot be created for order items
  // with 'paid' status. Full workflow testing including status transitions
  // from 'paid' to 'shipped' to 'delivered' requires shipment creation and
  // delivery confirmation endpoints which are not available in the current
  // SDK function set. The business rule enforcement is validated by the
  // rejection of the refund request for the non-delivered order item.
  TestValidator.predicate(
    "refund request requires delivered status",
    orderItem.status === "paid",
  );
}
