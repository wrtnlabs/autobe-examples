export async function test_api_refund_request_seller_cannot_respond_to_already_responded_request(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 2. Register and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  // 3. Customer creates shipping address
  const address =
    await generate_random_shopping_mall_customer_addresses_create(
      customerConnection,
      {
        body: typia.random<IShoppingMallAddress.ICreate>(),
      },
    );
  typia.assert(address);
  // 4. Customer adds product variant to cart (using random variant UUID for test)
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          shopping_mall_product_variant_id: typia.random<
            string & tags.Format<"uuid">
          >(),
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1>
          >(),
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 5. Customer creates order
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        shopping_mall_address_id: address.id,
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order);
  // Get the first order item for refund request
  const orderItem = order.orderItems[0];
  TestValidator.predicate("order has items", order.orderItems.length > 0);
  // 6. Customer creates refund request for the order item
  const refundRequest =
    await generate_random_shopping_mall_customer_order_items_refund_requests_create(
      customerConnection,
      {
        params: {
          orderItemId: orderItem.id,
        },
        body: {
          reason: RandomGenerator.paragraph({ sentences: 2 }),
        } satisfies IShoppingMallRefundRequest.ICreate,
      },
    );
  typia.assert(refundRequest);
  TestValidator.equals(
    "refund request status is pending",
    refundRequest.status,
    "pending",
  );
  TestValidator.equals(
    "response_reason is null",
    refundRequest.response_reason,
    null,
  );
  TestValidator.equals(
    "responded_at is null",
    refundRequest.responded_at,
    null,
  );
  // 7. Seller responds to the refund request FIRST TIME with status='approved'
  const firstResponse =
    await api.functional.shoppingMall.seller.refund_requests.update(
      sellerConnection,
      {
        refundRequestId: refundRequest.id,
        body: {
          status: "approved",
          response_reason: RandomGenerator.paragraph({ sentences: 2 }),
        } satisfies IShoppingMallRefundRequest.IUpdate,
      },
    );
  typia.assert(firstResponse);
  TestValidator.equals(
    "status after first response",
    firstResponse.status,
    "approved",
  );
  TestValidator.predicate(
    "response_reason is set",
    firstResponse.response_reason !== null,
  );
  TestValidator.predicate(
    "responded_at is set",
    firstResponse.responded_at !== null,
  );
  // 8. Seller attempts to update the SAME refund request AGAIN - MUST FAIL
  await TestValidator.error(
    "seller cannot respond to already responded refund request",
    async () => {
      await api.functional.shoppingMall.seller.refund_requests.update(
        sellerConnection,
        {
          refundRequestId: refundRequest.id,
          body: {
            status: "rejected",
            response_reason: "Second attempt reason",
          } satisfies IShoppingMallRefundRequest.IUpdate,
        },
      );
    },
  );
}