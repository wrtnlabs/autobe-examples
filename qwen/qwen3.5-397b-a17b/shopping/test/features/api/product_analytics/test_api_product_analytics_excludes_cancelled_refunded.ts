export async function test_api_product_analytics_excludes_cancelled_refunded(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup - create and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 2. Create product with variants
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // Create variant for the product
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku_code: RandomGenerator.alphaNumeric(10),
          price_override: product.base_price,
          option_value_ids: [],
        } satisfies IShoppingMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 3. Customer setup - create and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  // 4. Create first order (will request cancellation)
  const order1 = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        shopping_mall_address_id: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order1);
  TestValidator.predicate("order1 has items", order1.orderItems.length > 0);
  // 5. Create second order (will remain valid)
  const order2 = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        shopping_mall_address_id: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order2);
  TestValidator.predicate("order2 has items", order2.orderItems.length > 0);
  // 6. Request cancellation for first order's first item
  const order1Item = order1.orderItems[0];
  const cancellationRequest =
    await generate_random_shopping_mall_customer_order_items_cancellation_requests_create(
      customerConnection,
      {
        params: { orderItemId: order1Item.id },
        body: {
          reason: RandomGenerator.paragraph({ sentences: 2 }),
        } satisfies IShoppingMallCancellationRequest.ICreate,
      },
    );
  typia.assert(cancellationRequest);
  TestValidator.equals(
    "cancellation request status is pending",
    cancellationRequest.status,
    "pending",
  );
  // 7. Get product analytics
  const analytics = await api.functional.shoppingMall.seller.products.analytics(
    sellerConnection,
    {
      productId: product.id,
    },
  );
  typia.assert(analytics);
  // 8. Validate analytics structure and values
  TestValidator.predicate(
    "totalUnitsSold is non-negative integer",
    analytics.totalUnitsSold >= 0,
  );
  TestValidator.predicate(
    "totalRevenue is non-negative",
    analytics.totalRevenue >= 0,
  );
  TestValidator.predicate(
    "reviewCount is non-negative",
    analytics.reviewCount >= 0,
  );
  // averageRating should be null if no reviews, or between 1-5
  if (analytics.averageRating !== null) {
    TestValidator.predicate(
      "averageRating is between 1 and 5",
      analytics.averageRating >= 1 && analytics.averageRating <= 5,
    );
  }
  // 9. Verify analytics endpoint correctly filters by status
  // The analytics should only count order items with status NOT IN ('cancelled', 'refunded')
  // Since cancellationRequest is still 'pending', the order item status hasn't changed yet
  // This validates that the analytics endpoint is working and will exclude items
  // once their status changes to 'cancelled' or 'refunded'
  TestValidator.predicate("analytics returned for product", analytics !== null);
}
