/**
 * Test cancellation request creation for a paid order item.
 *
 * Validates the complete cancellation request workflow including administrative category setup, seller product creation, member ordering, and cancellation request submission. Ensures that the cancellation request is created with correct status, reason, and associations.
 *
 * Special attention is given to verifying that the cancellation request enters 'pending' status awaiting seller review, the reason text is preserved exactly as submitted, and responded_at remains null until the seller responds.
 *
 * 1. Administrator creates a product category.
 * 2. Seller creates a product under that category.
 * 3. Seller creates a product variant with SKU and option values.
 * 4. Member registers with email and credentials.
 * 5. Member adds a shipping address for checkout.
 * 6. Member adds the variant to shopping cart.
 * 7. Member places order, creating order items with 'paid' status.
 * 8. Member submits cancellation request for one order item with reason text.
 * 9. Validates cancellation request details match input and workflow state.
 */
export async function test_api_cancellation_request_creation_for_paid_order_item(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      grade: "regular" as const,
    },
  });
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup - create product
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(sellerAuth);
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  // 3. Seller creates product variant
  const variant = await generate_random_shopping_mall_seller_variants_create(
    sellerConnection,
    {
      body: {
        shopping_mall_product_id: product.id,
      },
    },
  );
  typia.assert(variant);
  // 4. Member setup - register and login
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberAuth);
  // 5. Member adds shipping address
  const address = await generate_random_shopping_mall_member_addresses_create(
    memberConnection,
    {},
  );
  typia.assert(address);
  // 6. Member adds variant to cart
  const cartItem = await generate_random_shopping_mall_member_cart_items_create(
    memberConnection,
    {
      body: {
        product_variant_id: variant.id,
      },
    },
  );
  typia.assert(cartItem);
  // 7. Member places order
  const order = await generate_random_shopping_mall_member_orders_create(
    memberConnection,
    {
      body: {
        shopping_mall_customer_address_id: address.id,
      },
    },
  );
  typia.assert(order);
  // Get the first order item from the order
  const orderItem = order.orderItems[0];
  TestValidator.predicate("order item exists", orderItem !== undefined);
  TestValidator.equals("order item status is paid", orderItem.status, "paid");
  // 8. Member creates cancellation request
  const cancellationReason = "ordered by mistake";
  const cancellationRequest =
    await api.functional.shoppingMall.member.cancellation_requests.create(
      memberConnection,
      {
        body: {
          order_item_id: orderItem.id,
          reason: cancellationReason,
        } satisfies IShoppingMallCancellationRequest.ICreate,
      },
    );
  typia.assert(cancellationRequest);
  // 9. Validate cancellation request
  TestValidator.equals(
    "cancellation request status is pending",
    cancellationRequest.status,
    "pending",
  );
  TestValidator.equals(
    "reason matches input",
    cancellationRequest.reason,
    cancellationReason,
  );
  TestValidator.equals(
    "responded_at is null",
    cancellationRequest.respondedAt,
    null,
  );
  TestValidator.equals(
    "order item reference matches",
    cancellationRequest.orderItem.id,
    orderItem.id,
  );
  TestValidator.equals(
    "customer reference matches",
    cancellationRequest.customer.id,
    memberAuth.id,
  );
}
