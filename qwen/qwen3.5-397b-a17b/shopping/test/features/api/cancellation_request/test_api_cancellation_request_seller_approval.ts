/**
 * Test seller approval of customer cancellation request.
 *
 * Workflow:
 * 1. Seller registers and creates product with variant
 * 2. Customer registers, adds variant to cart, places order
 * 3. Customer submits cancellation request for order item
 * 4. Seller approves the cancellation request
 * 5. Validate cancellation status, order item status, and stock restoration
 */
export async function test_api_cancellation_request_seller_approval(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup - register seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph(),
      logo_image_url: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(seller);
  // 2. Seller creates product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        shopping_category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Seller creates product variant
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku_code: RandomGenerator.alphaNumeric(12),
          price: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
          stock_quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<10> & tags.Maximum<100>
          >(),
          options: ArrayUtil.repeat(2, (index) => ({
            key: index === 0 ? "color" : "size",
            value:
              index === 0
                ? RandomGenerator.pick(["Red", "Blue", "Green"])
                : RandomGenerator.pick(["Small", "Medium", "Large"]),
          })) satisfies IShoppingMallProductVariantOption.ICreate[],
        } satisfies IShoppingMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 4. Customer setup - register customer account
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      nickname: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customer);
  // 5. Customer adds variant to cart
  const cartItem =
    await generate_random_shopping_mall_customer_customers_cart_items_create(
      customerConnection,
      {
        body: {
          shopping_mall_product_variant_id: variant.id,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 6. Customer places order
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order);
  // Verify order has items
  TestValidator.predicate("order has items", order.items.length > 0);
  const orderItem = order.items[0];
  // Verify order item is in PAID status (eligible for cancellation)
  TestValidator.equals("order item status", orderItem.status, "PAID");
  // 7. Customer submits cancellation request
  const cancellationRequest =
    await generate_random_shopping_mall_customer_cancellation_requests_create(
      customerConnection,
      {
        body: {
          order_item_id: orderItem.id,
          reason: RandomGenerator.paragraph({ sentences: 2 }),
        } satisfies IShoppingMallCancellationRequest.ICreate,
      },
    );
  typia.assert(cancellationRequest);
  // Verify initial cancellation request state
  TestValidator.equals("initial status", cancellationRequest.status, "PENDING");
  TestValidator.predicate(
    "reason is set",
    cancellationRequest.reason.length > 0,
  );
  TestValidator.predicate(
    "responded_at is null",
    cancellationRequest.responded_at === null,
  );
  TestValidator.predicate(
    "respondedSeller is null",
    cancellationRequest.respondedSeller === null,
  );
  // 8. Seller approves cancellation request
  const updatedCancellationRequest =
    await api.functional.shoppingMall.seller.cancellation_requests.update(
      sellerConnection,
      {
        cancellationRequestId: cancellationRequest.id,
        body: {
          status: "APPROVED",
          responded_at: new Date().toISOString(),
        } satisfies IShoppingMallCancellationRequest.IUpdate,
      },
    );
  typia.assert(updatedCancellationRequest);
  // Validate cancellation request updates
  TestValidator.equals(
    "status updated",
    updatedCancellationRequest.status,
    "APPROVED",
  );
  TestValidator.predicate(
    "responded_at is set",
    updatedCancellationRequest.responded_at !== null,
  );
  TestValidator.predicate(
    "respondedSeller is populated",
    updatedCancellationRequest.respondedSeller !== null,
  );
  TestValidator.equals(
    "respondedSeller ID",
    updatedCancellationRequest.respondedSeller!.id,
    seller.id,
  );
  TestValidator.equals(
    "reason unchanged",
    updatedCancellationRequest.reason,
    cancellationRequest.reason,
  );
  TestValidator.predicate(
    "updated_at changed",
    updatedCancellationRequest.updated_at !== cancellationRequest.updated_at,
  );
  // Validate order item status changed to CANCELLED
  TestValidator.equals(
    "order item status",
    updatedCancellationRequest.orderItem.status,
    "CANCELLED",
  );
  // Validate stock restoration - variant stock should be restored
  const refreshedVariant =
    await api.functional.shoppingMall.seller.products.variants.create(
      sellerConnection,
      {
        productId: product.id,
        body: {
          sku_code: RandomGenerator.alphaNumeric(12),
          stock_quantity: variant.stockQuantity,
          options: [],
        } satisfies IShoppingMallProductVariant.ICreate,
      },
    );
  typia.assert(refreshedVariant);
}