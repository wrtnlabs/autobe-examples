/**
 * Test that administrators can view snapshots of any review (including reviews they don't own) for dispute resolution and verification purposes.
 *
 * Test Steps:
 * 1. Customer registers and authenticates
 * 2. Administrator registers and authenticates
 * 3. Seller creates a product
 * 4. Customer adds product to cart, creates address, places order
 * 5. Customer writes a review for the product
 * 6. Administrator retrieves the customer's review snapshot
 *
 * Validation Points:
 * - Snapshot retrieval succeeds for administrator
 * - Administrator can access snapshots of reviews they don't own
 * - Snapshot contains complete historical data (rating, content, created_at)
 * - Authorization allows administrator access regardless of review ownership
 *
 * Business Logic Verified:
 * - Administrators have elevated access to view any review snapshot (requirement [69], [356])
 * - Snapshot access control distinguishes between review owner and administrator roles
 * - Supports dispute resolution and administrative verification workflows
 */
export async function test_api_review_snapshot_administrator_access(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer registration and authentication
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  // 2. Administrator registration and authentication
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallAdministrator.IJoin,
  });
  typia.assert(adminAuth);
  // 3. Seller registration and authentication
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 4. Seller creates a product
  const product = await api.functional.shoppingMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 5. Customer creates shipping address
  const address = await api.functional.shoppingMall.customer.addresses.create(
    customerConnection,
    {
      body: {
        recipientName: RandomGenerator.name(),
        recipientPhone: RandomGenerator.mobile(),
        streetAddress: RandomGenerator.paragraph({ sentences: 1 }),
        city: RandomGenerator.name(),
        state: RandomGenerator.name(),
        postalCode: typia.random<string>(),
        country: "South Korea",
      } satisfies IShoppingMallAddress.ICreate,
    },
  );
  typia.assert(address);
  // 6. Customer places order (cart items are handled internally)
  const order = await api.functional.shoppingMall.customer.orders.create(
    customerConnection,
    {
      body: {
        shopping_mall_address_id: address.id,
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order);
  // 7. Customer writes a review for the order item
  const orderItem = order.orderItems[0];
  const review = await api.functional.shoppingMall.customer.reviews.create(
    customerConnection,
    {
      body: {
        product_id: product.id,
        order_id: order.id,
        rating: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
        >(),
        content: RandomGenerator.paragraph({ sentences: 3 }),
      } satisfies IShoppingMallReview.ICreate,
    },
  );
  typia.assert(review);
  // 8. Administrator retrieves the review snapshot
  // This tests that administrators can access snapshots of reviews they don't own
  const snapshot =
    await api.functional.shoppingMall.customer.reviews.snapshots.at(
      adminConnection,
      {
        reviewId: review.id,
        snapshotId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  typia.assert(snapshot);
  // 9. Validate snapshot structure and data integrity
  TestValidator.equals(
    "snapshot review id matches",
    snapshot.review.id,
    review.id,
  );
  TestValidator.predicate(
    "snapshot has valid rating (1-5)",
    snapshot.rating >= 1 && snapshot.rating <= 5,
  );
  TestValidator.predicate(
    "snapshot has created_at timestamp",
    snapshot.created_at !== null,
  );
  TestValidator.predicate(
    "snapshot rating is integer",
    Number.isInteger(snapshot.rating),
  );
  // 10. Validate snapshot contains historical review data
  TestValidator.predicate(
    "snapshot content is string or null",
    snapshot.content === null || typeof snapshot.content === "string",
  );
  TestValidator.equals(
    "snapshot review belongs to customer",
    snapshot.review.customer.id,
    customerAuth.id,
  );
}