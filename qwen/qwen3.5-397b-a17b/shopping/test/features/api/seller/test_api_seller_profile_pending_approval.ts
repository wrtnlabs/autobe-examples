export async function test_api_seller_profile_pending_approval(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(sellerAuth);
  // 2. Submit seller approval request (leave pending, do not approve)
  const approvalRequest =
    await generate_random_shopping_mall_seller_approval_requests_create(
      sellerConnection,
      {
        body: {},
      },
    );
  typia.assert(approvalRequest);
  // Verify approval request is in pending status
  TestValidator.equals(
    "approval request status",
    approvalRequest.status,
    "pending",
  );
  // 3. Register a new customer account
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(customerAuth);
  // 4. Attempt to retrieve pending seller's profile as customer
  // Should throw error (HTTP 404 Not Found) since profile is not accessible for pending sellers
  await TestValidator.error(
    "pending seller profile not accessible",
    async () => {
      await api.functional.shoppingMall.sellers.profile.at(customerConnection, {
        sellerId: sellerAuth.id,
      });
    },
  );
}
