export async function test_api_seller_ban_preserves_existing_orders(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate admin
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(adminAuth);
  // 2. Create seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      logo_image_url: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(sellerAuth);
  const sellerId = sellerAuth.id;
  const shopName = sellerAuth.shop_name;
  // 3. Create product as seller
  const product = await api.functional.shoppingMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        shopping_category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 4. Create product variant
  const variant =
    await api.functional.shoppingMall.seller.products.variants.create(
      sellerConnection,
      {
        productId: product.id,
        body: {
          sku_code: `SKU-${RandomGenerator.alphaNumeric(8)}`,
          price: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
          stock_quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<10>
          >(),
          options: [
            {
              key: "color",
              value: RandomGenerator.pick(["Red", "Blue", "Green"] as const),
            },
            {
              key: "size",
              value: RandomGenerator.pick(["S", "M", "L"] as const),
            },
          ],
        } satisfies IShoppingMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 5. Create and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      nickname: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(customerAuth);
  // 6. Add product variant to customer's cart
  const cartItem =
    await api.functional.shoppingMall.customer.customers.cart.items.create(
      customerConnection,
      {
        body: {
          shopping_mall_product_variant_id: variant.id,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 7. Create order from cart
  const order = await api.functional.shoppingMall.customer.orders.create(
    customerConnection,
    {
      body: {
        addressId: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order);
  const orderId = order.id;
  const orderNumber = order.order_number;
  // Verify order has items from the seller
  TestValidator.predicate("order has items", order.items.length > 0);
  const orderItem = order.items[0];
  TestValidator.equals(
    "order item seller matches",
    orderItem.seller.id,
    sellerId,
  );
  TestValidator.equals(
    "order item shop name matches",
    orderItem.seller.shop_name,
    shopName,
  );
  // 8. Ban the seller account as admin
  await api.functional.shoppingMall.admin.sellers.ban(adminConnection, {
    sellerId: sellerId,
  });
  // 9. Verify order still exists and is accessible after seller ban
  TestValidator.equals("order id preserved after ban", order.id, orderId);
  TestValidator.equals(
    "order number preserved after ban",
    order.order_number,
    orderNumber,
  );
  // 10. Verify seller snapshot in order item preserves shop information
  TestValidator.equals(
    "seller snapshot shop name preserved",
    orderItem.seller.shop_name,
    shopName,
  );
  TestValidator.equals(
    "seller snapshot id preserved",
    orderItem.seller.id,
    sellerId,
  );
  // 11. Verify order item status is valid
  TestValidator.predicate(
    "order item has valid status",
    orderItem.status === "PAID" ||
      orderItem.status === "SHIPPED" ||
      orderItem.status === "DELIVERED" ||
      orderItem.status === "CANCELLED" ||
      orderItem.status === "REFUNDED",
  );
  // 12. Verify product snapshot preserves product information
  TestValidator.predicate(
    "product snapshot has name",
    orderItem.productSnapshot.name.length > 0,
  );
  TestValidator.predicate(
    "product snapshot has base price",
    orderItem.productSnapshot.base_price > 0,
  );
  // 13. Verify variant snapshot preserves variant configuration
  TestValidator.predicate(
    "variant snapshot has SKU code",
    orderItem.productVariantSnapshot.sku_code.length > 0,
  );
  TestValidator.predicate(
    "variant snapshot has stock quantity",
    orderItem.productVariantSnapshot.stock_quantity >= 0,
  );
}
