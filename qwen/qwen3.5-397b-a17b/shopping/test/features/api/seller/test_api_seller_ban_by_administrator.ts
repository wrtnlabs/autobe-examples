/**
 * Test administrator banning a seller account.
 *
 * This test verifies the primary success path where an administrator
 * bans an active seller account. The test creates an admin account,
 * creates a seller account, and then bans the seller using the admin
 * credentials. The ban operation should complete successfully.
 *
 * Note: Login verification before/after ban is tested in separate
 * authentication-focused scenarios.
 */
export async function test_api_seller_ban_by_administrator(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallAdmin.IJoin,
  });
  typia.assert(adminAuth);
  // 2. Create seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      logo_image_url: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 3. Administrator bans the seller
  // The ban operation returns void, successful completion without error
  // indicates the ban was processed successfully
  await api.functional.shoppingMall.admin.sellers.ban(adminConnection, {
    sellerId: sellerAuth.id,
  });
}