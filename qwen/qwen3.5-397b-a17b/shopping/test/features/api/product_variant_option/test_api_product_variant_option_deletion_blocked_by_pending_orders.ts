/**
 * Test that variant option deletion is rejected when the variant has pending order items.
 *
 * This test verifies the business rule that prevents sellers from deleting variant options
 * when there are pending order items (PAID status) associated with that variant.
 *
 * Workflow:
 * 1. Seller registers and creates a product with a variant
 * 2. Variant is configured with options (e.g., color=Red, size=Large)
 * 3. Customer registers, adds variant to cart, and places an order
 * 4. Order creates order items with PAID status
 * 5. Seller attempts to delete a variant option
 * 6. Deletion should fail with 409 Conflict due to pending orders
 */
export async function test_api_product_variant_option_deletion_blocked_by_pending_orders(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup - register account
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPass123!",
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 2. Create product (requires valid category_id in real environment)
  const product = await api.functional.shoppingMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        shopping_category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Create variant with initial option
  const variant =
    await api.functional.shoppingMall.seller.products.variants.create(
      sellerConnection,
      {
        productId: product.id,
        body: {
          sku_code: `SKU-${RandomGenerator.alphaNumeric(8)}`,
          price: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
          stock_quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<10>
          >(),
          options: [
            {
              key: "color",
              value: "Red",
            } satisfies IShoppingMallProductVariantOption.ICreate,
          ],
        } satisfies IShoppingMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 4. Add additional option to the variant (this is the option we'll try to delete)
  const additionalOption =
    await api.functional.shoppingMall.seller.products.variants.options.create(
      sellerConnection,
      {
        productId: product.id,
        variantId: variant.id,
        body: {
          key: "size",
          value: "Large",
        } satisfies IShoppingMallProductVariantOption.ICreate,
      },
    );
  typia.assert(additionalOption);
  // 5. Customer setup - register and login
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPass123!",
      nickname: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  const customerLoginConnection: api.IConnection = { host: connection.host };
  await authorize_customer_login(customerLoginConnection, {
    body: {
      email: customerAuth.email,
      password: "TestPass123!",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IShoppingMallCustomer.ILogin,
  });
  // 6. Customer adds variant to cart
  const cartItem =
    await api.functional.shoppingMall.customer.customers.cart.items.create(
      customerLoginConnection,
      {
        body: {
          shopping_mall_product_variant_id: variant.id,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 7. Customer places order (creates order items with PAID status)
  // Note: Requires valid addressId belonging to customer in real environment
  const order = await api.functional.shoppingMall.customer.orders.create(
    customerLoginConnection,
    {
      body: {
        addressId: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order);
  // Verify order has items with PAID status
  TestValidator.predicate("order has items", order.items.length > 0);
  TestValidator.predicate(
    "order items are PAID",
    order.items.every((item) => item.status === "PAID"),
  );
  // 8. Seller attempts to delete the variant option - should fail with 409 Conflict
  // This verifies the business rule: variants with pending orders cannot be modified
  await TestValidator.httpError(
    "variant option deletion blocked by pending orders",
    409,
    async () => {
      await api.functional.shoppingMall.seller.products.variants.options.erase(
        sellerConnection,
        {
          productId: product.id,
          variantId: variant.id,
          optionId: additionalOption.id,
        },
      );
    },
  );
}
