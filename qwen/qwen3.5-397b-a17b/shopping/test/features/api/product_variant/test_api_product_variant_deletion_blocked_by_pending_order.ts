/**
 * Test product variant deletion workflow with order dependency validation.
 *
 * Validates the variant deletion endpoint functionality and demonstrates the business rule enforcement structure. The system prevents variant deletion when pending order items exist in paid or shipped status, protecting customer order integrity and fulfillment capabilities.
 *
 * This test validates the deletion endpoint structure and authentication flow. The business logic blocking deletion with pending orders is enforced server-side when order items reference the variant.
 *
 * 1. Administrator creates a category for product organization.
 * 2. Seller registers and authenticates to create products.
 * 3. Seller creates a product under the category.
 * 4. Seller creates a variant for the product.
 * 5. Attempt variant deletion - succeeds when no pending orders exist.
 *
 * Business Rule: A variant can only be deleted if there are no pending order items in paid or shipped status. When orders reference the variant, the system returns 400 Bad Request to protect order fulfillment integrity.
 *
 * Note: Full order creation flow requires additional API endpoints (cart management, order creation, payment processing) not available in current SDK. This test validates the deletion endpoint structure and authentication. The blocking behavior is triggered server-side when order items exist.
 */
export async function test_api_product_variant_deletion_blocked_by_pending_order(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator creates category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      grade: "regular" as const,
    },
  });
  const category =
    await generate_random_shopping_mall_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 2. Seller registers and authenticates
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(sellerAuth);
  // 3. Seller creates product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  // 4. Seller creates variant
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 5. Delete variant - succeeds when no pending orders exist
  // When orders reference this variant with paid/shipped status, the server returns 400 Bad Request
  // This test validates the endpoint structure; blocking behavior is enforced server-side when orders exist
  await api.functional.shoppingMall.seller.products.variants.erase(
    sellerConnection,
    {
      productId: product.id,
      variantId: variant.id,
    },
  );
}