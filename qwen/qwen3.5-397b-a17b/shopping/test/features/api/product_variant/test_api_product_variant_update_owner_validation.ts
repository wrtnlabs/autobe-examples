/**
 * Test that a seller cannot update a variant belonging to another seller's product.
 *
 * Validates the ownership constraint that sellers can only modify variants on their own products. The test creates two separate seller accounts, has Seller A create a product with a variant, then attempts to have Seller B update that variant. The update should be rejected with a forbidden error.
 *
 * 1. Administrator creates a category for product assignment.
 * 2. Seller A registers and logs in, then creates a product with the category.
 * 3. Seller A creates a variant on their product.
 * 4. Seller B registers and logs in separately.
 * 5. Seller B attempts to update Seller A's variant using the variant ID.
 * 6. Verify the update request is rejected with a 403 forbidden error indicating the seller does not own the variant.
 */
export async function test_api_product_variant_update_owner_validation(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      grade: "regular" as const,
    },
  });
  const category =
    await generate_random_shopping_mall_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 2. Seller A setup - register and login
  const sellerAConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // Seller A creates a product
  const productA = await generate_random_shopping_mall_seller_products_create(
    sellerAConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(productA);
  // 3. Seller A creates a variant on their product
  const variantA =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerAConnection,
      {
        params: { productId: productA.id },
      },
    );
  typia.assert(variantA);
  // 4. Seller B setup - register and login (different seller)
  const sellerBConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 5. Seller B attempts to update Seller A's variant (should fail)
  await TestValidator.error(
    "Seller B cannot update Seller A's variant",
    async () => {
      await api.functional.shoppingMall.seller.variants.update(
        sellerBConnection,
        {
          variantId: variantA.id,
          body: {
            sku_code: RandomGenerator.alphaNumeric(8),
            option_values: RandomGenerator.paragraph({ sentences: 2 }),
          } satisfies IShoppingMallProductVariant.IUpdate,
        },
      );
    },
  );
}