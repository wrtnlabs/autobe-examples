export async function test_api_shipment_delivery_confirmation_unauthorized_customer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate Customer A (order owner)
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password123!",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerA);
  // 2. Customer A creates a shipping address
  const address = await api.functional.shoppingMall.customer.addresses.create(
    customerAConnection,
    {
      body: {
        recipientName: RandomGenerator.name(),
        recipientPhone: RandomGenerator.mobile(),
        streetAddress: RandomGenerator.paragraph({ sentences: 1 }),
        city: RandomGenerator.name(),
        state: RandomGenerator.name(),
        postalCode: typia.random<string>(),
        country: RandomGenerator.name(),
        isDefault: true,
      } satisfies IShoppingMallAddress.ICreate,
    },
  );
  typia.assert(address);
  // 3. Customer A adds product variant to cart
  const cartItem = await api.functional.shoppingMall.customer.cart.items.create(
    customerAConnection,
    {
      body: {
        shopping_mall_product_variant_id: typia.random<
          string & tags.Format<"uuid">
        >(),
        quantity: typia.random<number & tags.Type<"int32"> & tags.Minimum<1>>(),
      } satisfies IShoppingMallCartItem.ICreate,
    },
  );
  typia.assert(cartItem);
  // 4. Customer A creates an order
  const order = await api.functional.shoppingMall.customer.orders.create(
    customerAConnection,
    {
      body: {
        shopping_mall_address_id: address.id,
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order);
  // Get the first order item ID for shipment creation
  const orderItemId = order.orderItems[0]?.id;
  if (!orderItemId) {
    throw new Error("Order must have at least one order item");
  }
  // 5. Register and authenticate Seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password123!",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(seller);
  // 6. Seller creates shipment for Customer A's order
  const shipment = await api.functional.shoppingMall.seller.shipments.create(
    sellerConnection,
    {
      body: {
        tracking_carrier: RandomGenerator.name(),
        tracking_number: typia.random<string>(),
        order_item_ids: [orderItemId],
      } satisfies IShoppingMallShipment.ICreate,
    },
  );
  typia.assert(shipment);
  // 7. Store the shipment ID
  const shipmentId = shipment.id;
  // 8. Register and authenticate Customer B (unauthorized user)
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB = await authorize_customer_join(customerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password123!",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerB);
  // 9. Customer B attempts to confirm delivery for Customer A's shipment (should fail)
  await TestValidator.error(
    "Customer B cannot confirm delivery for Customer A's shipment",
    async () => {
      await api.functional.shoppingMall.customer.shipments.confirm_delivery.confirmDelivery(
        customerBConnection,
        {
          shipmentId: shipmentId,
        },
      );
    },
  );
}
