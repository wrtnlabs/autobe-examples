/**
 * Test that a customer can successfully retrieve detailed tracking information for a shipment.
 *
 * This test validates the complete workflow:
 * 1. Customer registers and authenticates
 * 2. Seller registers and authenticates
 * 3. Seller creates a product with variants
 * 4. Customer adds variant to cart and creates an order
 * 5. Seller creates a shipment with tracking information
 * 6. Customer retrieves shipment tracking details
 *
 * Validates that the shipment response includes all required fields:
 * - Shipment ID, tracking carrier, tracking number
 * - Delivery lifecycle timestamps (shipped_at, delivered_at, etc.)
 * - Order items with product/variant snapshots
 * - Order summary with order number and status
 */
export async function test_api_shipment_tracking_retrieval_by_customer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer setup - register and authenticate
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      nickname: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  // 2. Seller setup - register and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      logo_image_url: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 3. Seller creates a product
  const product = await api.functional.shoppingMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 1 }),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        shopping_category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 4. Seller creates a product variant with stock
  const variant =
    await api.functional.shoppingMall.seller.products.variants.create(
      sellerConnection,
      {
        productId: product.id,
        body: {
          sku_code: `SKU-${RandomGenerator.alphaNumeric(8)}`,
          price: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
          stock_quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<10> & tags.Maximum<100>
          >(),
          options: [
            {
              key: "color",
              value: RandomGenerator.pick(["Red", "Blue", "Green"]),
            },
            {
              key: "size",
              value: RandomGenerator.pick(["S", "M", "L", "XL"]),
            },
          ] satisfies IShoppingMallProductVariantOption.ICreate[],
        } satisfies IShoppingMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 5. Customer adds the variant to cart
  const cartItem =
    await api.functional.shoppingMall.customer.customers.cart.items.create(
      customerConnection,
      {
        body: {
          shopping_mall_product_variant_id: variant.id,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 6. Customer creates an order (checkout)
  // Note: This requires a valid addressId - using random UUID as placeholder
  const order = await api.functional.shoppingMall.customer.orders.create(
    customerConnection,
    {
      body: {
        addressId: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order);
  TestValidator.predicate("order has items", order.items.length > 0);
  // 7. Seller creates a shipment with tracking information
  const orderItemIds = order.items.map((item) => item.id);
  const shipment = await api.functional.shoppingMall.seller.shipments.create(
    sellerConnection,
    {
      body: {
        order_item_ids: orderItemIds,
        tracking_carrier: RandomGenerator.pick(["FedEx", "UPS", "DHL", "USPS"]),
        tracking_number: `TRACK-${RandomGenerator.alphaNumeric(12)}`,
      } satisfies IShoppingMallShipment.ICreate,
    },
  );
  typia.assert(shipment);
  // 8. Customer retrieves shipment tracking details
  const retrievedShipment =
    await api.functional.shoppingMall.customer.shipments.at(
      customerConnection,
      {
        shipmentId: shipment.id,
      },
    );
  typia.assert(retrievedShipment);
  // Validate shipment structure
  TestValidator.equals(
    "shipment ID matches",
    retrievedShipment.id,
    shipment.id,
  );
  TestValidator.equals(
    "tracking carrier matches",
    retrievedShipment.tracking_carrier,
    shipment.tracking_carrier,
  );
  TestValidator.equals(
    "tracking number matches",
    retrievedShipment.tracking_number,
    shipment.tracking_number,
  );
  TestValidator.predicate(
    "shipped_at timestamp exists",
    retrievedShipment.shipped_at !== null,
  );
  TestValidator.predicate(
    "order items included",
    retrievedShipment.items.length > 0,
  );
  // Validate order summary in shipment
  TestValidator.equals(
    "order number matches",
    retrievedShipment.order.orderNumber,
    order.order_number,
  );
  TestValidator.equals(
    "order total matches",
    retrievedShipment.order.totalPrice,
    order.total_price,
  );
  // Validate order items in shipment
  const firstItem = retrievedShipment.items[0];
  TestValidator.predicate("item has quantity", firstItem.quantity > 0);
  TestValidator.predicate("item has unit price", firstItem.unit_price >= 0);
  TestValidator.predicate(
    "item has product snapshot",
    firstItem.productSnapshot !== null,
  );
  TestValidator.predicate(
    "item has variant snapshot",
    firstItem.productVariantSnapshot !== null,
  );
  TestValidator.predicate("item has seller info", firstItem.seller !== null);
}
