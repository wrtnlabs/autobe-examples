/**
 * Test that an administrator can filter shipment items by fulfillment status.
 *
 * This test validates:
 * 1. Admin authentication and access to shipment endpoints
 * 2. Shipment items filtering by status (SHIPPED, PAID)
 * 3. Response contains only items matching the specified status filter
 * 4. Pagination metadata is correct
 * 5. Filtering works correctly for different status values
 */
export async function test_api_shipment_items_admin_filter_by_status(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate admin
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Admin1234!",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallAdmin.IJoin,
  });
  typia.assert(adminAuth);
  // 2. Create and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Seller1234!",
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      logo_image_url: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 3. Admin approves seller
  const approvedSeller =
    await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
      sellerId: sellerAuth.id,
    });
  typia.assert(approvedSeller);
  TestValidator.equals(
    "seller approval status",
    approvedSeller.approval_status,
    "APPROVED",
  );
  // 4. Seller creates product (requires valid category_id from seed data)
  const product = await api.functional.shoppingMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        shopping_category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 5. Seller creates product variant
  const variant =
    await api.functional.shoppingMall.seller.products.variants.create(
      sellerConnection,
      {
        productId: product.id,
        body: {
          sku_code: `SKU-${RandomGenerator.alphaNumeric(8)}`,
          price: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
          stock_quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<10>
          >(),
          options: [
            {
              key: "color",
              value: RandomGenerator.pick(["Red", "Blue", "Green"]),
            },
          ] satisfies IShoppingMallProductVariantOption.ICreate[],
        } satisfies IShoppingMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 6. Create and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Customer1234!",
      nickname: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  // 7. Customer adds variant to cart
  const cartItem =
    await api.functional.shoppingMall.customer.customers.cart.items.create(
      customerConnection,
      {
        body: {
          shopping_mall_product_variant_id: variant.id,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 8. Customer places order (requires valid addressId from seed data)
  const order = await api.functional.shoppingMall.customer.orders.create(
    customerConnection,
    {
      body: {
        addressId: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order);
  TestValidator.predicate("order has items", order.items.length > 0);
  // 9. Seller creates shipment with order items
  const shipment = await api.functional.shoppingMall.seller.shipments.create(
    sellerConnection,
    {
      body: {
        order_item_ids: order.items.map((item) => item.id),
        tracking_carrier: RandomGenerator.pick(["FedEx", "UPS", "DHL", "USPS"]),
        tracking_number: `TRACK-${RandomGenerator.alphaNumeric(12)}`,
      } satisfies IShoppingMallShipment.ICreate,
    },
  );
  typia.assert(shipment);
  // 10. Admin filters shipment items by SHIPPED status
  const shippedItems =
    await api.functional.shoppingMall.admin.shipments.items.index(
      adminConnection,
      {
        shipmentId: shipment.id,
        body: {
          page: 1,
          limit: 20,
          status: "SHIPPED",
        } satisfies IShoppingMallShipmentItem.IRequest,
      },
    );
  typia.assert(shippedItems);
  TestValidator.predicate(
    "pagination has current page",
    shippedItems.pagination.current >= 1,
  );
  TestValidator.predicate(
    "pagination has valid limit",
    shippedItems.pagination.limit >= 1,
  );
  TestValidator.predicate(
    "pagination has valid records",
    shippedItems.pagination.records >= 0,
  );
  TestValidator.predicate(
    "pagination has valid pages",
    shippedItems.pagination.pages >= 0,
  );
  // Verify all returned items have SHIPPED status
  for (const item of shippedItems.data) {
    TestValidator.equals(
      "item status is SHIPPED",
      item.orderItem.status,
      "SHIPPED",
    );
  }
  // 11. Admin filters shipment items by PAID status
  const paidItems =
    await api.functional.shoppingMall.admin.shipments.items.index(
      adminConnection,
      {
        shipmentId: shipment.id,
        body: {
          page: 1,
          limit: 20,
          status: "PAID",
        } satisfies IShoppingMallShipmentItem.IRequest,
      },
    );
  typia.assert(paidItems);
  TestValidator.predicate(
    "PAID filter pagination valid",
    paidItems.pagination.current >= 1,
  );
  // 12. Admin filters without status (should return all items)
  const allItems =
    await api.functional.shoppingMall.admin.shipments.items.index(
      adminConnection,
      {
        shipmentId: shipment.id,
        body: {
          page: 1,
          limit: 20,
        } satisfies IShoppingMallShipmentItem.IRequest,
      },
    );
  typia.assert(allItems);
  TestValidator.predicate(
    "all items pagination valid",
    allItems.pagination.current >= 1,
  );
  TestValidator.predicate("has items in shipment", allItems.data.length > 0);
}
