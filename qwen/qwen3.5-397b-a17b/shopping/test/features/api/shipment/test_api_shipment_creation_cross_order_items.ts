/**
 * Test cross-order shipment creation where a seller bundles order items from
 * multiple different orders into a single shipment.
 *
 * This test validates that sellers can group items from different orders into
 * the same shipment when shipping to the same customer. The scenario:
 * 1. Seller registers and logs in
 * 2. Seller creates a product with variants
 * 3. Customer registers and logs in
 * 4. Customer places first order with one item
 * 5. Customer places second order with another item from the same seller
 * 6. Seller creates one shipment containing order items from both orders
 * 7. Verify all order items from different orders are included in the shipment
 * 8. Verify all items change to SHIPPED status
 * 9. Verify the shipment is linked to the primary order
 */
export async function test_api_shipment_creation_cross_order_items(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller registration and login
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      logo_image_url: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  const sellerLoginConnection: api.IConnection = { host: connection.host };
  await authorize_seller_login(sellerLoginConnection, {
    body: {
      email: sellerAuth.email,
      password: "1234",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.ILogin,
  });
  // 2. Seller creates product
  const product = await api.functional.shoppingMall.seller.products.create(
    sellerLoginConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        shopping_category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Customer registration and login
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      nickname: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  const customerLoginConnection: api.IConnection = { host: connection.host };
  await authorize_customer_login(customerLoginConnection, {
    body: {
      email: customerAuth.email,
      password: "1234",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IShoppingMallCustomer.ILogin,
  });
  // 4. Customer adds first item to cart and creates first order
  const cartItem1 =
    await api.functional.shoppingMall.customer.customers.cart.items.create(
      customerLoginConnection,
      {
        body: {
          shopping_mall_product_variant_id: typia.random<
            string & tags.Format<"uuid">
          >(),
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem1);
  const firstOrder = await api.functional.shoppingMall.customer.orders.create(
    customerLoginConnection,
    {
      body: {
        addressId: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(firstOrder);
  TestValidator.predicate("first order has items", firstOrder.items.length > 0);
  const firstOrderItem = firstOrder.items[0];
  // 5. Customer adds second item to cart and creates second order
  const cartItem2 =
    await api.functional.shoppingMall.customer.customers.cart.items.create(
      customerLoginConnection,
      {
        body: {
          shopping_mall_product_variant_id: typia.random<
            string & tags.Format<"uuid">
          >(),
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem2);
  const secondOrder = await api.functional.shoppingMall.customer.orders.create(
    customerLoginConnection,
    {
      body: {
        addressId: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(secondOrder);
  TestValidator.predicate(
    "second order has items",
    secondOrder.items.length > 0,
  );
  const secondOrderItem = secondOrder.items[0];
  // 6. Seller creates shipment with items from both orders
  const shipment = await api.functional.shoppingMall.seller.shipments.create(
    sellerLoginConnection,
    {
      body: {
        order_item_ids: [firstOrderItem.id, secondOrderItem.id],
        tracking_carrier: "FedEx",
        tracking_number: typia.random<string>(),
      } satisfies IShoppingMallShipment.ICreate,
    },
  );
  typia.assert(shipment);
  // 7. Verify shipment contains both order items
  TestValidator.predicate(
    "shipment has both items",
    shipment.items.length === 2,
  );
  const shipmentItemIds = shipment.items.map((item) => item.id);
  TestValidator.predicate(
    "first order item in shipment",
    shipmentItemIds.includes(firstOrderItem.id),
  );
  TestValidator.predicate(
    "second order item in shipment",
    shipmentItemIds.includes(secondOrderItem.id),
  );
  // 8. Verify all items changed to SHIPPED status
  for (const item of shipment.items) {
    TestValidator.equals(
      `item ${item.id} status is SHIPPED`,
      item.status,
      "SHIPPED",
    );
  }
  // 9. Verify shipment is linked to primary order (first order)
  TestValidator.equals(
    "shipment linked to first order",
    shipment.order.id,
    firstOrder.id,
  );
}
