/**
 * Test shipment creation for a single order item.
 *
 * This test validates the complete shipment creation workflow:
 * 1. Seller registration and admin approval
 * 2. Customer registration and order placement
 * 3. Seller creates shipment with tracking information
 * 4. Verifies shipment creation and order item status transition to SHIPPED
 */
export async function test_api_shipment_creation_single_item(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and setup admin account
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallAdmin.IJoin,
  });
  typia.assert(admin);
  // 2. Register seller account (starts as PENDING)
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      logo_image_url: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(seller);
  // 3. Admin approves seller registration
  const approvedSeller =
    await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
      sellerId: seller.id,
    });
  typia.assert(approvedSeller);
  TestValidator.equals(
    "seller approval status",
    approvedSeller.approval_status,
    "APPROVED",
  );
  // 4. Seller creates a product using generation function (handles category internally)
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 1 }),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      },
    },
  );
  typia.assert(product);
  // 5. Seller creates a product variant
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        body: {
          sku_code: `SKU-${RandomGenerator.alphaNumeric(10)}`,
          price: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
          stock_quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<10> & tags.Maximum<100>
          >(),
          options: [
            {
              key: "color",
              value: RandomGenerator.pick(["Red", "Blue", "Green", "Black"]),
            },
          ],
        },
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  // 6. Register customer account
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      nickname: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customer);
  // 7. Customer adds product variant to cart
  const cartItem =
    await generate_random_shopping_mall_customer_customers_cart_items_create(
      customerConnection,
      {
        body: {
          shopping_mall_product_variant_id: variant.id,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
        },
      },
    );
  typia.assert(cartItem);
  // 8. Customer creates order using generation function (handles address internally)
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {},
    },
  );
  typia.assert(order);
  TestValidator.predicate("order has items", order.items.length > 0);
  // 9. Get the order item for this seller's product
  const orderItem = order.items[0];
  TestValidator.equals("order item initial status", orderItem.status, "PAID");
  TestValidator.equals("order item seller", orderItem.seller.id, seller.id);
  // 10. Seller creates shipment for the order item
  const shipment = await api.functional.shoppingMall.seller.shipments.create(
    sellerConnection,
    {
      body: {
        order_item_ids: [orderItem.id],
        tracking_carrier: "FedEx",
        tracking_number: "123456789",
      } satisfies IShoppingMallShipment.ICreate,
    },
  );
  typia.assert(shipment);
  // 11. Verify shipment details
  TestValidator.equals("tracking carrier", shipment.tracking_carrier, "FedEx");
  TestValidator.equals(
    "tracking number",
    shipment.tracking_number,
    "123456789",
  );
  TestValidator.predicate("shipped_at is set", shipment.shipped_at !== null);
  TestValidator.predicate(
    "shipment contains order item",
    shipment.items.length > 0,
  );
  TestValidator.equals(
    "shipment order item id",
    shipment.items[0].id,
    orderItem.id,
  );
  // 12. Verify order item status changed to SHIPPED
  TestValidator.equals(
    "order item status after shipment",
    shipment.items[0].status,
    "SHIPPED",
  );
}
