import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallDashboard } from "../../../../../api/structures/IShoppingMallDashboard";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerDashboardSummary } from "../../../../../providers/getShoppingMallSellerDashboardSummary";

@Controller("/shoppingMall/seller/dashboard/summary")
export class ShoppingmallSellerDashboard_summaryController {
  /**
   * Retrieve the seller's shop dashboard summary statistics.
   *
   * This operation provides a quick overview of the seller's shop performance and pending tasks. The summary includes the total number of products listed, total order items across all products, count of pending cancellation requests awaiting seller response, and count of pending refund requests awaiting seller response.
   *
   * This endpoint is designed for the seller dashboard home page, giving sellers an at-a-glance view of their shop status and actionable items requiring attention.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query dashboard statistics for the authenticated seller.
   *
   * 1. Count total products owned by the seller from shopping_mall_products table
   * 2. Count total order items referencing the seller's products from shopping_mall_order_items table
   * 3. Count pending cancellation requests where seller has not yet responded from shopping_mall_cancellation_requests table
   * 4. Count pending refund requests where seller has not yet responded from shopping_mall_refund_requests table
   * 5. Return aggregated statistics as a single summary object
   *
   * Ensure seller authentication is validated before querying. All counts should be current as of query time.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IShoppingMallDashboard.ISummary> {
    try {
      return await getShoppingMallSellerDashboardSummary({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
