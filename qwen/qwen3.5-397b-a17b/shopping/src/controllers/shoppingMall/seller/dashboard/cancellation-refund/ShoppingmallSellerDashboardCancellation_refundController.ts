import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallDashboard } from "../../../../../api/structures/IShoppingMallDashboard";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerDashboardCancellationRefund } from "../../../../../providers/getShoppingMallSellerDashboardCancellationRefund";

@Controller("/shoppingMall/seller/dashboard/cancellation-refund")
export class ShoppingmallSellerDashboardCancellation_refundController {
  /**
   * Retrieves seller dashboard statistics for pending cancellation and refund requests.
   *
   * Returns the count of pending cancellation requests and pending refund requests that are awaiting the seller's review and response. This endpoint provides real-time dashboard metrics to help sellers monitor their order management workload.
   *
   * The counts reflect only requests for order items containing the seller's products. Requests are counted based on their current status being 'pending'. When a seller approves or rejects a request, it is no longer included in the pending count.
   *
   * This endpoint requires seller authentication. Only approved sellers can access their dashboard statistics.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query shopping_mall_cancellation_requests table
     *   filtering by seller's order items and status = 'pending'. Count the
     *   total number of pending cancellation requests.
   *
   * Query shopping_mall_refund_requests table filtering by seller's order items and status = 'pending'. Count the total number of pending refund requests.
   *
   * To filter by seller's order items, join cancellation_requests and refund_requests with shopping_mall_order_items on shopping_mall_order_item_id, then filter by shopping_mall_seller_id matching the authenticated seller's ID.
   *
   * Return both counts in a single response object. No pagination needed as this returns aggregate counts only.
   *
   * Handle edge cases: seller with no pending requests returns counts of 0. If seller account is not approved or is suspended, return appropriate authorization error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IShoppingMallDashboard.ICancellationRefund> {
    try {
      return await getShoppingMallSellerDashboardCancellationRefund({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
