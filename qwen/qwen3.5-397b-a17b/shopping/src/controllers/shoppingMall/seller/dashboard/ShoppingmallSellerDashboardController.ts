import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSellerDashboard } from "../../../../api/structures/IShoppingMallSellerDashboard";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerDashboard } from "../../../../providers/patchShoppingMallSellerDashboard";

@Controller("/shoppingMall/seller/dashboard")
export class ShoppingmallSellerDashboardController {
  /**
   * Retrieve seller dashboard statistics and shop summary information.
   *
   * This operation provides sellers with a comprehensive overview of their shop's current state, including total product count, order item statistics, and pending request counts. The dashboard helps sellers quickly assess their business performance and identify items requiring attention.
   *
   * Returns aggregated counts for products, order items, pending cancellation requests, and pending refund requests. All counts are scoped to the authenticated seller's account. Optional date range filters can be applied to focus on specific time periods using entity creation timestamps.
   *
   * Requires seller authentication. Access is restricted to sellers with approved seller approval request status (shopping_mall_seller_approval_requests.status = 'approved').
   *
   * @param connection
   * @param body Optional filter criteria for dashboard statistics including date range boundaries
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query aggregated statistics for the authenticated seller:
   *
   * 1. Count total products from shopping_mall_products where seller_id matches authenticated seller and deleted_at is null
   * 2. Count total order items from shopping_mall_order_items where seller_id matches and deleted_at is null
   * 3. Count pending cancellation requests from shopping_mall_cancellation_requests where status is 'pending' and linked to seller's order items
   * 4. Count pending refund requests from shopping_mall_refund_requests where status is 'pending' and seller_id matches
   *
   * Apply optional date range filters if provided in request body. Join with order_items table to filter cancellation requests by seller's items. Return single dashboard summary object with all counts.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async summary(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSellerDashboard.IRequest,
  ): Promise<IShoppingMallSellerDashboard> {
    try {
      return await patchShoppingMallSellerDashboard({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
