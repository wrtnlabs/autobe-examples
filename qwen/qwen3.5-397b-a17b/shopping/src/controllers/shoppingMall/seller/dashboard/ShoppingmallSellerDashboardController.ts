import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ISellerDashboard } from "../../../../api/structures/ISellerDashboard";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerDashboard } from "../../../../providers/getShoppingMallSellerDashboard";

@Controller("/shoppingMall/seller/dashboard")
export class ShoppingmallSellerDashboardController {
  /**
   * Retrieve the seller's shop dashboard summary with key metrics.
   *
   * This operation provides sellers with an overview of their shop performance and pending actions requiring their attention. The dashboard displays aggregated statistics including the total number of products listed, total number of order items for their products, count of pending cancellation requests awaiting seller response, and count of pending refund requests awaiting seller response.
   *
   * This endpoint is accessible only to authenticated sellers with approved status. The data is scoped to the authenticated seller's account and cannot be used to view other sellers' dashboards.
   *
   * Related operations include GET /sellers/orders for viewing detailed order items, GET /sellers/cancellation-requests for viewing pending cancellation requests, and GET /sellers/refund-requests for viewing pending refund requests.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the authenticated seller's shop statistics from multiple tables:
   *
   * 1. Product count: COUNT from shopping_mall_products where shopping_seller_id = seller.id AND deleted = false
   * 2. Order item count: COUNT from shopping_mall_order_items where shopping_mall_seller_id = seller.id
   * 3. Pending cancellation count: COUNT from shopping_mall_cancellation_requests where responded_by_seller_id = seller.id AND status = 'PENDING'
   * 4. Pending refund count: COUNT from shopping_mall_refund_requests where responded_by_seller_id = seller.id AND status = 'PENDING'
   *
   * All queries should be executed in a single transaction or parallel queries for performance. Return aggregated counts as ISellerDashboard object. No pagination needed as this is a summary endpoint.
   *
   * Authorization: Verify seller is authenticated and has approval_status = 'APPROVED'. Reject suspended sellers with appropriate error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<ISellerDashboard> {
    try {
      return await getShoppingMallSellerDashboard({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
