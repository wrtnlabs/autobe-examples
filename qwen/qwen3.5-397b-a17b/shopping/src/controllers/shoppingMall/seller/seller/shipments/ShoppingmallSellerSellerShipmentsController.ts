import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallShipment } from "../../../../../api/structures/IPageIShoppingMallShipment";
import { IShoppingMallShipment } from "../../../../../api/structures/IShoppingMallShipment";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerSellerShipmentsShipmentId } from "../../../../../providers/getShoppingMallSellerSellerShipmentsShipmentId";
import { patchShoppingMallSellerSellerShipments } from "../../../../../providers/patchShoppingMallSellerSellerShipments";
import { putShoppingMallSellerSellerShipmentsShipmentId } from "../../../../../providers/putShoppingMallSellerSellerShipmentsShipmentId";

@Controller("/shoppingMall/seller/seller/shipments")
export class ShoppingmallSellerSellerShipmentsController {
  /**
   * Retrieves a paginated list of shipments created by the authenticated seller.
   *
   * This endpoint allows sellers to view and search through all shipments they have created for fulfilling their order items. Sellers can filter shipments by shipping date range, delivery status, carrier name, tracking number, or order code to find specific shipments quickly.
   *
   * The response includes shipment summary information such as carrier name, tracking number, shipping timestamp, delivery status, and the count of order items in each shipment. Results are sorted by shipping date in descending order (newest first) and support pagination for efficient browsing of large shipment histories.
   *
   * Only shipments belonging to the authenticated seller are returned. Soft-deleted shipments are automatically excluded from results.
   *
   * @param connection
   * @param body Search criteria for filtering shipments including date ranges, status filters, text search on carrier and tracking number, order code filter, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query shopping_mall_shipments table filtered by
     *   the authenticated seller's ID from session context. Apply search
     *   filters from request body: shipped_at date range, delivered_at status
     *   filtering, carrier name search, tracking number search, and order code
     *   filtering. Join with shopping_mall_orders to include order code in
     *   response. Join with shopping_mall_order_items to include item count per
     *   shipment. Implement cursor-based or offset pagination based on page and
     *   limit parameters. Sort by shipped_at descending by default (newest
     *   first). Return IPageIShoppingMallShipment.ISummary with pagination
     *   metadata. Ensure soft-deleted shipments (deleted_at not null) are
     *   excluded from results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallShipment.IRequest,
  ): Promise<IPageIShoppingMallShipment.ISummary> {
    try {
      return await patchShoppingMallSellerSellerShipments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shipment created by the seller.
   *
   * This endpoint returns complete shipment details including carrier name, tracking number, shipping timestamp, and delivery confirmation status. Sellers can use this to view tracking information for shipments they have created and monitor delivery progress.
   *
   * The shipment must belong to the authenticated seller. Authorization middleware validates that the seller can only access shipments they created. If the shipment belongs to a different seller or does not exist, the request will be rejected.
   *
   * The response includes all shipment metadata: carrier information for customer tracking, shipped_at timestamp marking when items transitioned to shipped status, and delivered_at timestamp (if delivery has been confirmed either manually by customer or automatically after 14 days).
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment to retrieve (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query shopping_mall_shipments table by shipmentId
     *   UUID.
   *
   * Validate that the shipment exists and belongs to the authenticated seller by checking shopping_mall_seller_id matches the seller's ID from the session.
   *
   * Return the complete shipment record including: id, shopping_mall_order_id, shopping_mall_seller_id, carrier_name, tracking_number, shipped_at, delivered_at, created_at, updated_at.
   *
   * Handle edge cases:
   * - Shipment not found: return 404
   * - Shipment belongs to different seller: return 403 (authorization handles this)
   * - Shipment soft-deleted: return 404
   *
   * No joins required for basic shipment detail. If order items are needed, that would be a separate endpoint or include relationship expansion.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment> {
    try {
      return await getShoppingMallSellerSellerShipmentsShipmentId({
        seller,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update shipment tracking information.
   *
   * This endpoint allows sellers to modify the tracking information for a shipment they created. Sellers can update the carrier name and/or tracking number if they need to correct mistakes or if the carrier information changes before delivery.
   *
   * Tracking information can only be updated while the shipment has not been delivered. Once the delivered_at timestamp is set (either by customer confirmation or automatic delivery after 14 days), the tracking information becomes immutable and cannot be modified.
   *
   * This endpoint is restricted to the seller who owns the shipment. Other sellers and unauthorized users cannot access or modify shipments they do not own.
   *
   * @param connection
   * @param shipmentId The shipment identifier (UUID format).
   * @param body Update payload containing tracking information. Include carrier_name and/or tracking_number to update. Both fields are optional but at least one must be provided.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Update the shopping_mall_shipments record by
     *   shipmentId.
   *
   * Implementation steps:
   * 1. Validate the authenticated user is a seller
   * 2. Query the shipment by id, ensuring shopping_mall_seller_id matches the authenticated seller's id
   * 3. Validate the shipment exists and has not been delivered (delivered_at is null)
   * 4. Allow updating carrier_name and/or tracking_number from the request body
   * 5. Validate carrier_name and tracking_number are non-empty strings (1-255 characters)
   * 6. Do not allow modifying shipped_at, shopping_mall_order_id, shopping_mall_seller_id, or delivered_at
   * 7. Update the record and return the full shipment object
   *
   * Edge cases:
   * - Return 404 if shipment not found or seller doesn't own it
   * - Return 400 if shipment already delivered (delivered_at is not null)
   * - Return 400 if carrier_name or tracking_number is empty or missing
   * - Return 403 if authenticated user is not a seller
   *
   * The shipped_at timestamp remains unchanged (set at creation time). The delivered_at field is controlled by customer delivery confirmation or automatic delivery, not by seller update.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shipmentId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipment.IUpdate,
  ): Promise<IShoppingMallShipment> {
    try {
      return await putShoppingMallSellerSellerShipmentsShipmentId({
        seller,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
