import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallOrderItem } from "../../../../../api/structures/IPageIShoppingMallOrderItem";
import { IShoppingMallOrderItem } from "../../../../../api/structures/IShoppingMallOrderItem";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerSellerOrderItemsOrderItemId } from "../../../../../providers/getShoppingMallSellerSellerOrderItemsOrderItemId";
import { patchShoppingMallSellerSellerOrderItems } from "../../../../../providers/patchShoppingMallSellerSellerOrderItems";

@Controller("/shoppingMall/seller/seller/order-items")
export class ShoppingmallSellerSellerOrder_itemsController {
  /**
   * Retrieves a paginated list of order items belonging to the authenticated seller.
   *
   * This endpoint enables sellers to view and manage their order items through their dashboard. Sellers can filter items by fulfillment status to focus on pending actions such as items awaiting shipment (paid), items in transit (shipped), or items requiring attention (cancelled, refunded). The operation supports date range filtering to query orders from specific time periods.
   *
   * Each order item in the response includes essential information for fulfillment: the order code for customer reference, product details, variant options, quantity, unit price, current status, and shipment tracking information when available. Items are sorted by creation date with newest orders appearing first.
   *
   * The seller context is automatically determined from the authentication session - sellers can only access their own order items. This endpoint is essential for seller order management workflows including preparing shipments, responding to cancellation requests, and processing refunds.
   *
   * @param connection
   * @param body Search criteria for filtering seller's order items including status filter, date range, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query shopping_mall_order_items table filtered by
     *   the authenticated seller's ID from session context. Apply status filter
     *   if provided in request body (allowed values: paid, shipped, delivered,
     *   cancelled, refunded). Support date range filtering on created_at for
     *   order history queries. Implement cursor-based or offset pagination with
     *   limit and page parameters. Join with shopping_mall_orders to include
     *   order code for customer reference. Join with shopping_mall_products for
     *   product name. Join with shopping_mall_product_variants for
     *   option_values and SKU. Join with shopping_mall_shipments for tracking
     *   information when shipped_at is present. Sort by created_at descending
     *   (newest first) by default. Return summary fields optimized for seller
     *   dashboard display: item ID, order code, product name, variant options,
     *   quantity, price, status, shipment tracking info, and timestamps. Handle
     *   case where seller has no order items (empty array with pagination
     *   metadata).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallOrderItem.IRequest,
  ): Promise<IPageIShoppingMallOrderItem.ISummary> {
    try {
      return await patchShoppingMallSellerSellerOrderItems({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order item for the seller's products.
   *
   * This endpoint returns complete order item details including the associated order, product, variant, quantity, price, current fulfillment status, and shipment information if assigned. Sellers use this to view order item details for fulfillment operations such as shipping, tracking, and customer service.
   *
   * The order item must belong to the authenticated seller. If the order item belongs to a different seller, the request is rejected with an authorization error. This ensures sellers can only access and process their own order items within multi-seller orders.
   *
   * The response includes the order item snapshot reference which preserves the product name, description, variant price, and seller shop information at the time of purchase for dispute resolution purposes.
   *
   * @param connection
   * @param orderItemId Unique identifier of the order item to retrieve (UUID format, scoped to seller's products).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query the shopping_mall_order_items table by the
     *   provided orderItemId UUID.
   *
   * Verify that the shopping_mall_seller_id on the order item matches the authenticated seller's ID. If not matched, reject with 403 Forbidden error indicating the seller does not own this order item.
   *
   * Join with shopping_mall_orders to include order code and member information.
   * Join with shopping_mall_products to include product name and details.
   * Join with shopping_mall_product_variants to include SKU code and option values.
   * Left join with shopping_mall_shipments to include tracking information if shipment is assigned.
   * Include reference to the order item snapshot (shopping_mall_order_item_snapshots) which contains denormalized product and seller profile data at purchase time.
   *
   * Return the complete order item entity with all related data. Handle the case where shipment_id is null (item not yet shipped) by returning null for shipment fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderItemId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await getShoppingMallSellerSellerOrderItemsOrderItemId({
        seller,
        orderItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
