import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallOrderItemSnapshot } from "../../../../../../api/structures/IShoppingMallOrderItemSnapshot";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerSellerOrderItemsOrderItemIdSnapshot } from "../../../../../../providers/getShoppingMallSellerSellerOrderItemsOrderItemIdSnapshot";

@Controller("/shoppingMall/seller/seller/order-items/:orderItemId/snapshot")
export class ShoppingmallSellerSellerOrder_itemsSnapshotController {
  /**
   * Retrieves the order item snapshot for a specific order item.
   *
   * This endpoint returns the immutable snapshot capturing the product name, description, variant price, and seller profile information as they existed at the time of purchase. The snapshot ensures order history accuracy even if the original product or seller profile has been modified or deleted since the order was placed.
   *
   * The snapshot includes variant option values (e.g., color, size) stored as key-value pairs in the nested options array. All data is read-only and cannot be modified.
   *
   * @param connection
   * @param orderItemId Order item identifier (UUID format) to retrieve the snapshot for.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_order_item_snapshots table by orderItemId parameter.
   *
   * Join with shopping_mall_order_item_snapshot_options to include all variant option key-value pairs.
   *
   * Verify caller has access to the order item:
   * - Customer: must own the parent order
   * - Seller: must be the seller of the order item
   * - Admin/SuperAdmin: unrestricted access
   *
   * Return 404 if snapshot not found (order item may not have been purchased yet or was created before snapshot system).
   *
   * Return complete snapshot object including:
   * - id, shopping_mall_order_item_id
   * - product_name, product_description
   * - variant_price
   * - seller_shop_name, seller_logo_url
   * - created_at
   * - options array with key-value pairs
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItemSnapshot> {
    try {
      return await getShoppingMallSellerSellerOrderItemsOrderItemIdSnapshot({
        seller,
        orderItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
