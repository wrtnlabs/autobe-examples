import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallShipmentLog } from "../../../../api/structures/IPageIShoppingMallShipmentLog";
import { IShoppingMallShipmentLog } from "../../../../api/structures/IShoppingMallShipmentLog";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerShipmentLogsLogId } from "../../../../providers/getShoppingMallSellerShipmentLogsLogId";
import { patchShoppingMallSellerShipmentLogs } from "../../../../providers/patchShoppingMallSellerShipmentLogs";

@Controller("/shoppingMall/seller/shipment-logs")
export class ShoppingmallSellerShipment_logsController {
  /**
   * Retrieve a filtered and paginated list of shipment lifecycle event logs.
   *
   * This operation provides comprehensive audit trail access for shipment events including creation, tracking updates, delivery confirmations, and automatic delivery timeouts. Supports filtering by shipment ID, event type, actor type, actor ID, status transitions, and creation date ranges.
   *
   * Designed for administrators and sellers to track shipment history and resolve disputes. Results are sorted by creation timestamp in descending order (newest first) with cursor-based pagination for efficient large dataset handling.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering shipment logs
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_shipment_logs table with pagination and filtering capabilities.
   *
   * Apply search filters on: shopping_mall_shipment_id (exact match), event_type (enum: created, tracking_updated, delivery_confirmed, auto_delivered), actor_type (enum: customer, seller, administrator, system), actor_id (UUID match), old_status, new_status, created_at date range.
   *
   * Join with shopping_mall_shipments if shipment details needed in response.
   *
   * Sort by created_at DESC for chronological order with newest events first.
   *
   * Implement cursor-based pagination for large result sets.
   *
   * Return log entries with complete event metadata including status transitions and contextual information.
   *
   * No write operations allowed - this is an immutable audit trail table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallShipmentLog.IRequest,
  ): Promise<IPageIShoppingMallShipmentLog.ISummary> {
    try {
      return await patchShoppingMallSellerShipmentLogs({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific shipment lifecycle event log entry by its unique identifier.
   *
   * This operation provides access to immutable audit records that track all significant events in a shipment's lifecycle. Each log entry captures the event type (created, tracking_updated, delivery_confirmed, auto_delivered), the actor who triggered the event (customer, seller, administrator, or system), status transitions, and contextual metadata.
   *
   * Shipment logs are append-only records used for compliance, dispute resolution, and delivery tracking. The log entry includes timestamps, previous and new status values, and additional context such as carrier information or delivery confirmation details.
   *
   * This endpoint is typically used by administrators for audit purposes or by customers and sellers reviewing shipment history. The returned data helps verify the chronological sequence of shipment events and provides evidence for delivery-related disputes.
   *
   * @param connection
   * @param logId Unique identifier of the shipment log entry (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_shipment_logs table by primary key UUID.
   *
   * Retrieve the complete log entry including: id, shopping_mall_shipment_id, event_type, actor_type, actor_id, old_status, new_status, metadata, and created_at.
   *
   * Join with shopping_mall_shipments table if shipment details are needed for context validation.
   *
   * Return 404 if log ID does not exist.
   *
   * No authorization filtering needed - logs are readable by users with appropriate role-based access (administrators can view all, customers/sellers can view logs for their own shipments).
   *
   * Event types are fixed values: 'created', 'tracking_updated', 'delivery_confirmed', 'auto_delivered'.
   * Actor types are fixed values: 'customer', 'seller', 'administrator', 'system'.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":logId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("logId")
    logId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipmentLog> {
    try {
      return await getShoppingMallSellerShipmentLogsLogId({
        seller,
        logId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
