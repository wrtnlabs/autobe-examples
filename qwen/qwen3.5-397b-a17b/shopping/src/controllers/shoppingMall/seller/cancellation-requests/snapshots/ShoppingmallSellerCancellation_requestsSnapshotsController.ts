import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCancellationRequestSnapshot } from "../../../../../api/structures/IPageIShoppingMallCancellationRequestSnapshot";
import { IShoppingMallCancellationRequestSnapshot } from "../../../../../api/structures/IShoppingMallCancellationRequestSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerCancellationRequestsCancellationRequestIdSnapshotsSnapshotId } from "../../../../../providers/getShoppingMallSellerCancellationRequestsCancellationRequestIdSnapshotsSnapshotId";
import { patchShoppingMallSellerCancellationRequestsCancellationRequestIdSnapshots } from "../../../../../providers/patchShoppingMallSellerCancellationRequestsCancellationRequestIdSnapshots";

@Controller(
  "/shoppingMall/seller/cancellation-requests/:cancellationRequestId/snapshots",
)
export class ShoppingmallSellerCancellation_requestsSnapshotsController {
  /**
   * Retrieves the complete history of state snapshots for a specific cancellation request.
   *
   * This endpoint returns all snapshots created for the specified cancellation request, ordered chronologically by creation time. Each snapshot captures the state of the cancellation request at a significant event: initial submission, seller approval, or seller rejection.
   *
   * Snapshots are immutable audit records that preserve the complete history including status changes, customer's cancellation reason, seller's response reason (if rejected), and review timestamps. This endpoint supports dispute resolution by allowing customers, sellers, and administrators to review the full progression of the cancellation request.
   *
   * The response is paginated to handle cases where many state changes occurred. Results are sorted by created_at in ascending order to show the historical timeline from initial request to current state.
   *
   * @param connection
   * @param cancellationRequestId UUID of the cancellation request to retrieve snapshots for (scoped to the specific cancellation request).
   * @param body Search criteria including optional status filter, reviewed date range filter, and pagination parameters (page, limit, sort).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query
     *   shopping_mall_cancellation_request_snapshots table filtered by
     *   cancellation_request_id parameter.
   *
   * Apply pagination using cursor-based or offset-based pagination from request body (page, limit). Sort results by created_at ASC to show chronological history.
   *
   * Support optional filtering in request body:
   * - status: filter by specific status values (pending, approved, rejected)
   * - reviewedAtFrom/reviewedAtTo: filter by review timestamp range
   *
   * Join with shopping_mall_cancellation_requests to verify the cancellation request exists and caller has permission to view it.
   *
   * Authorization: Allow customer (if matches shopping_mall_member_id), seller (if matches order item's seller), or admin/superAdmin.
   *
   * Return IPageIShoppingMallCancellationRequestSnapshot.ISummary with snapshot summary fields. Include total count for pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("cancellationRequestId")
    cancellationRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCancellationRequestSnapshot.IRequest,
  ): Promise<IPageIShoppingMallCancellationRequestSnapshot.ISummary> {
    try {
      return await patchShoppingMallSellerCancellationRequestsCancellationRequestIdSnapshots(
        {
          seller,
          cancellationRequestId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific cancellation request snapshot by ID.
   *
   * Returns the complete snapshot record capturing the state of a cancellation request at a specific point in time. Snapshots are immutable audit records created when a cancellation request is submitted and when the seller responds (approves or rejects).
   *
   * The snapshot includes the cancellation status, customer's reason, seller's response reason (if rejected), and review timestamp. This endpoint supports dispute resolution by allowing customers, sellers, and administrators to review the historical state of cancellation requests.
   *
   * Access is restricted to the customer who submitted the request, the seller who responded, and administrators.
   *
   * @param connection
   * @param cancellationRequestId UUID of the parent cancellation request (scoped to the specific cancellation request).
   * @param snapshotId UUID of the cancellation request snapshot to retrieve (globally unique).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query
     *   shopping_mall_cancellation_request_snapshots table by snapshot ID.
   *
   * Validate that the snapshotId exists and belongs to the specified cancellationRequestId.
   * Verify caller permissions: allow access only to the customer who submitted the cancellation request, the seller associated with the order item, or administrators.
   *
   * Return the full snapshot record including: id, cancellation_request_id, status, reason, response_reason, reviewed_at, created_at.
   *
   * Handle 404 if snapshot not found or if cancellationRequestId doesn't match.
   * Handle 403 if caller lacks permission to view this snapshot.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("cancellationRequestId")
    cancellationRequestId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCancellationRequestSnapshot> {
    try {
      return await getShoppingMallSellerCancellationRequestsCancellationRequestIdSnapshotsSnapshotId(
        {
          seller,
          cancellationRequestId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
