import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallOrderItemSnapshot } from "../../../../../../api/structures/IShoppingMallOrderItemSnapshot";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerOrdersItemsItemIdSnapshotsSnapshotId } from "../../../../../../providers/getShoppingMallSellerOrdersItemsItemIdSnapshotsSnapshotId";
import { patchShoppingMallSellerOrdersItemsItemIdSnapshots } from "../../../../../../providers/patchShoppingMallSellerOrdersItemsItemIdSnapshots";

@Controller("/shoppingMall/seller/orders/items/:itemId/snapshots")
export class ShoppingmallSellerOrdersItemsSnapshotsController {
  /**
   * Retrieve the immutable snapshot of an order item capturing its state at the time of purchase.
   *
   * This operation returns the historical snapshot preserving the exact product name, description, variant SKU code, price, and seller shop information (name and logo) as they existed when the order was placed. Snapshots are created automatically during checkout and cannot be modified.
   *
   * Snapshots serve critical purposes for dispute resolution, customer support, and audit compliance. They ensure that order records remain accurate even if the original product is modified, the variant is deleted, or the seller changes their shop profile. The snapshot is permanently linked to the order item and retained indefinitely.
   *
   * Access is restricted to the customer who placed the order, the seller who fulfilled it, and administrators. Attempting to access snapshots for order items outside these permissions will result in authorization errors.
   *
   * @param connection
   * @param itemId Order item ID (UUID format, identifies the specific purchased variant)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_order_item_snapshots table filtering by shopping_mall_order_item_id = {itemId}.
   *
   * Validate that the requesting user has permission to view this snapshot:
   * - Customer: must be the owner of the parent order (join shopping_mall_orders to verify customer_id)
   * - Seller: must be the seller of the order item (verify shopping_mall_order_items.shopping_mall_seller_id matches authenticated seller)
   * - Administrator: full access
   *
   * Return 404 if no snapshot exists for the order item (should not occur under normal circumstances as snapshots are created during order placement).
   *
   * Return snapshot fields: id, shopping_mall_order_item_id, product_name, product_description, variant_sku_code, variant_price, seller_shop_name, seller_shop_logo, created_at.
   *
   * Do not allow any modification operations - snapshots are immutable by business rule.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async patchByItemid(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItemSnapshot> {
    try {
      return await patchShoppingMallSellerOrdersItemsItemIdSnapshots({
        seller,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific order item snapshot containing preserved product, variant, and seller information at the time of purchase.
   *
   * This operation returns immutable historical data capturing the exact state of the purchased item when the order was placed. The snapshot includes the product name and description, variant SKU code and price, and seller shop name and logo as they appeared at purchase time. This ensures accurate transaction records even if the original product, variant, or seller profile has been modified or deleted since the order was placed.
   *
   * Snapshots are created automatically by the system when an order is placed and cannot be modified. This endpoint is used for order history display, dispute resolution, and audit trail purposes. Customers, sellers, and administrators can access snapshots for order items they have permission to view.
   *
   * @param connection
   * @param itemId Order item ID (UUID format, scoped to parent order)
   * @param snapshotId Order item snapshot ID (UUID format, globally unique)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_order_item_snapshots table by snapshotId (UUID).
   *
   * Validate that the snapshot exists and is associated with the provided itemId (shopping_mall_order_item_id).
   *
   * Verify caller has permission to access the order item:
   * - Customer: must be the owner of the parent order (join through orderItem → order → customer_id)
   * - Seller: must be the seller of the order item (check orderItem.shopping_mall_seller_id)
   * - Administrator/Super Administrator: full access
   *
   * Return the complete snapshot record including all fields: id, shopping_mall_order_item_id, product_name, product_description, variant_sku_code, variant_price, seller_shop_name, seller_shop_logo, created_at.
   *
   * Handle 404 if snapshot not found or if itemId/snapshotId mismatch.
   * Handle 403 if caller lacks permission to access the order item.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async getByItemidAndSnapshotid(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItemSnapshot> {
    try {
      return await getShoppingMallSellerOrdersItemsItemIdSnapshotsSnapshotId({
        seller,
        itemId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
