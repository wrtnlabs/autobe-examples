import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallAdminPromotionRequest } from "../../../../api/structures/IShoppingMallAdminPromotionRequest";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerAdminPromotionRequestsRequestId } from "../../../../providers/getShoppingMallSellerAdminPromotionRequestsRequestId";
import { postShoppingMallSellerAdminPromotionRequests } from "../../../../providers/postShoppingMallSellerAdminPromotionRequests";

@Controller("/shoppingMall/seller/admin-promotion-requests")
export class ShoppingmallSellerAdmin_promotion_requestsController {
  /**
   * Submit an administrator promotion request.
   *
   * Allows any registered member or seller to request promotion to administrator status. The request must include a reason text explaining why the applicant wants to become an administrator. The system automatically determines the applicant type (member or seller) from the authenticated user's account.
   *
   * Upon submission, the request enters 'pending' status and awaits review by a super administrator. Users can only have one pending promotion request at a time. If a previous request is still pending, the system rejects the new submission.
   *
   * When approved, the applicant becomes a regular administrator. When rejected, the applicant may submit a new request with an updated reason.
   *
   * @param connection
   * @param body Promotion request creation data containing the applicant's reason for requesting administrator privileges.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Create a new admin promotion request record in
     *   shopping_mall_admin_promotion_requests table.
   *
   * 1. Validate authenticated user is member or seller (not already admin/superAdmin)
   * 2. Check for existing pending promotion request for this user - reject if found
   * 3. Determine actor_type from user's role: 'member' for shopping_mall_members, 'seller' for shopping_mall_sellers
   * 4. Create promotion request with status='pending', provided reason, null reviewed_by_super_admin_id, null rejection_note
   * 5. Create corresponding subtype record in shopping_mall_admin_promotion_request_of_members or shopping_mall_admin_promotion_request_of_sellers based on actor_type
   * 6. Return the created promotion request entity
   *
   * Validation: reason must not be empty. Enforce one pending request per user constraint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallAdminPromotionRequest.ICreate,
  ): Promise<IShoppingMallAdminPromotionRequest> {
    try {
      return await postShoppingMallSellerAdminPromotionRequests({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific administrator promotion request by its unique identifier.
   *
   * This endpoint returns the complete details of a promotion request including the applicant's reason for requesting administrator privileges, current status (pending, approved, or rejected), and if rejected, the rejection note provided by the reviewing super administrator. The request also includes metadata such as submission timestamp and the identity of the super administrator who reviewed the request.
   *
   * Authorization: Users can access their own promotion requests. Super administrators can access all promotion requests for review purposes. Regular administrators cannot access promotion request details.
   *
   * The response includes the actor type (member or seller) to identify the applicant type, and the current workflow status to track the request through the approval process.
   *
   * @param connection
   * @param requestId Unique identifier of the promotion request (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query the shopping_mall_admin_promotion_requests
     *   table by primary key ID.
   *
   * Retrieve the full record including: id, reviewed_by_super_admin_id, actor_type, reason, status, rejection_note, created_at, updated_at.
   *
   * Join with shopping_mall_super_admins to include reviewer details if reviewed_by_super_admin_id is not null.
   *
   * Authorization check: Verify the requesting user either owns the request (via subtype tables shopping_mall_admin_promotion_request_of_members or shopping_mall_admin_promotion_request_of_sellers) or has super administrator privileges.
   *
   * Return 404 if the request ID does not exist or has been soft deleted.
   *
   * Return 403 if the user is not authorized to view this request (not the owner and not a super admin).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":requestId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdminPromotionRequest> {
    try {
      return await getShoppingMallSellerAdminPromotionRequestsRequestId({
        seller,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
