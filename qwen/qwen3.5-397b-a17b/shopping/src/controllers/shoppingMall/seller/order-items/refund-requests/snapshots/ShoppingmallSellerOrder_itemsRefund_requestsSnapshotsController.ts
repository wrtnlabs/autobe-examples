  /**
   * Retrieve a specific refund request snapshot by its unique identifier.
   *
   * This operation returns an immutable snapshot of a refund request's state at the moment a seller responded to it. The snapshot preserves the customer's reason, request status, seller's response text, and response timestamp for audit trail and dispute resolution purposes.
   *
   * Snapshots are created automatically when a seller approves or rejects a refund request and cannot be modified or deleted. Access is restricted to the customer who submitted the refund request, the seller who responded to it, and administrators with system oversight privileges.
   *
   * @param connection
   * @param orderItemId Order item UUID (scoped to customer's orders)
   * @param refundRequestId Refund request UUID (scoped to order item)
   * @param snapshotId Refund request snapshot UUID (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_refund_request_snapshots table by snapshot ID.
   *
   * Authorization checks:
   * 1. Verify snapshot exists and belongs to the specified refund request
   * 2. Verify refund request belongs to the specified order item
   * 3. Allow access if: current user is the customer who requested, the seller who responded, or an administrator
   *
   * Return complete snapshot entity including:
   * - id: UUID primary key
   * - shopping_mall_refund_request_id: parent refund request reference
   * - reason: customer's refund reason at snapshot time
   * - status: request status (pending/approved/rejected) at snapshot time
   * - seller_response: seller's response text or rejection reason
   * - responded_at: timestamp when seller responded
   * - created_at: snapshot record creation timestamp
   *
   * Edge cases:
   * - Return 404 if snapshot ID doesn't exist or doesn't match the refund request
   * - Return 404 if refund request doesn't belong to the specified order item
   * - Return 403 if user lacks authorization (not customer, seller, or admin)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequestSnapshot> {
    try {
      return await getShoppingMallSellerOrderItemsOrderItemIdRefundRequestsRefundRequestIdSnapshotsSnapshotId(
        {
          seller,
          orderItemId,
          refundRequestId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
