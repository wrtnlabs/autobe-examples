import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallInventoryRecord } from "../../../../api/structures/IPageIShoppingMallInventoryRecord";
import { IShoppingMallInventoryRecord } from "../../../../api/structures/IShoppingMallInventoryRecord";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerInventoryRecordsInventoryRecordId } from "../../../../providers/getShoppingMallSellerInventoryRecordsInventoryRecordId";
import { patchShoppingMallSellerInventoryRecords } from "../../../../providers/patchShoppingMallSellerInventoryRecords";
import { postShoppingMallSellerInventoryRecords } from "../../../../providers/postShoppingMallSellerInventoryRecords";

@Controller("/shoppingMall/seller/inventory-records")
export class ShoppingmallSellerInventory_recordsController {
  /**
   * Create a manual inventory adjustment record for a product variant.
   *
   * This operation allows sellers to manually adjust inventory levels for their product variants. Positive quantity_change values represent restocking (adding inventory), while negative values represent adjustments for losses, damages, or corrections.
   *
   * Each inventory record must include a reason explaining the adjustment. Records are immutable once created and cannot be modified or deleted.
   *
   * This endpoint is for manual adjustments only. Automatic inventory records are created by the system during order placement, cancellations, and refunds. The seller must own the product variant being adjusted, validated through the product variant's parent product relationship.
   *
   * @param connection
   * @param body Manual inventory adjustment details including variant, quantity change, and reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Create a new inventory record for manual seller adjustment.
   *
   * 1. Validate seller authentication and extract seller_id from session
   * 2. Load product_variant by product_variant_id
   * 3. Traverse product_variant → product to verify seller_id matches authenticated seller
   * 4. Validate quantity_change is non-zero integer
   * 5. Validate reason is non-empty string
   * 6. Create inventory_record with: id (UUID), product_variant_id, quantity_change, reason, created_at (current timestamp)
   * 7. Return created record
   *
   * Business rules:
   * - Records are immutable (no update/delete operations)
   * - quantity_change: positive for restock, negative for adjustment/loss
   * - reason is required and cannot be empty
   * - Seller must own the variant (via product ownership)
   * - Automatic records from orders/cancellations/refunds use system endpoints, not this manual adjustment endpoint
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallInventoryRecord.ICreate,
  ): Promise<IShoppingMallInventoryRecord> {
    try {
      return await postShoppingMallSellerInventoryRecords({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of inventory records for stock quantity change tracking.
   *
   * This operation provides comprehensive inventory history viewing capabilities including filtering by product variant, reason code, and date ranges. Records are sorted by creation timestamp in descending order (newest first) to show recent stock movements prominently.
   *
   * Inventory records are immutable audit trail entries that capture every stock quantity change. Each record shows the quantity change amount (positive for restocking, negative for orders/adjustments), reason code, and timestamp. Current stock quantity is calculated by summing all quantity_change values for a variant.
   *
   * This endpoint supports sellers monitoring their inventory movements and administrators auditing stock changes across the platform. Records are automatically created during order placement, cancellation, refund processing, and manual inventory adjustments.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for inventory records
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_inventory_records table with pagination and filtering.
   *
   * Apply search filters:
   * - productVariantId: filter by specific product variant (UUID)
   * - reason: filter by reason code (exact match or partial)
   * - createdAtFrom: filter records from this timestamp
   * - createdAtTo: filter records until this timestamp
   *
   * Sort by created_at DESC (newest first) by default.
   * Support cursor-based or offset pagination.
   *
   * Authorization: Sellers can only view inventory records for their own product variants. Administrators can view all records. Implement ownership check by joining with shopping_mall_product_variants → shopping_mall_products to verify seller ownership.
   *
   * Return IPageIShoppingMallInventoryRecord.ISummary with pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallInventoryRecord.IRequest,
  ): Promise<IPageIShoppingMallInventoryRecord.ISummary> {
    try {
      return await patchShoppingMallSellerInventoryRecords({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single inventory record by its unique identifier.
   *
   * This operation returns complete details of a specific inventory change event, including the quantity change amount, reason code, and timestamp. Inventory records form an immutable audit trail of all stock movements for product variants.
   *
   * Only sellers can access inventory records, and only for product variants they own. The operation enforces ownership validation through the product variant relationship. Records cannot be modified or deleted once created, ensuring a permanent historical record of all inventory changes.
   *
   * The response includes the product variant reference, enabling sellers to understand which variant's stock was affected by this change event.
   *
   * @param connection
   * @param inventoryRecordId Inventory record UUID (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_inventory_records table by primary key id.
   *
   * Validate that the requesting seller owns the product variant associated with this inventory record through the product_variant_id foreign key relationship.
   *
   * Return the complete inventory record with all fields: id, product_variant_id, quantity_change, reason, and created_at.
   *
   * Handle 404 Not Found if record doesn't exist.
   * Handle 403 Forbidden if seller doesn't own the associated product variant.
   *
   * No modification operations allowed - records are immutable audit trail entries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":inventoryRecordId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("inventoryRecordId")
    inventoryRecordId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallInventoryRecord> {
    try {
      return await getShoppingMallSellerInventoryRecordsInventoryRecordId({
        seller,
        inventoryRecordId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
