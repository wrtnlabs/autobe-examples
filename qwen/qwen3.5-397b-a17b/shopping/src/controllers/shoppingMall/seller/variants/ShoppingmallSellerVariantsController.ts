import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallProductVariant } from "../../../../api/structures/IShoppingMallProductVariant";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { postShoppingMallSellerVariants } from "../../../../providers/postShoppingMallSellerVariants";
import { putShoppingMallSellerVariantsVariantId } from "../../../../providers/putShoppingMallSellerVariantsVariantId";

@Controller("/shoppingMall/seller/variants")
export class ShoppingmallSellerVariantsController {
  /**
   * Create a new product variant for a specific product.
   *
   * Sellers use this endpoint to add variants representing specific SKU combinations (such as color, size, or other option combinations) to their products. Each variant requires a unique SKU code within the product context and human-readable option values for display in cart, orders, and product listings.
   *
   * The variant's price is optional - when not provided, the product's base price applies. Initial stock quantity starts at zero and must be added through the inventory restock endpoint. A product must have at least one variant to be purchasable by customers.
   *
   * The requesting seller must own the product referenced in the request. Duplicate SKU codes within the same product are rejected.
   *
   * @param connection
   * @param body Variant creation data including the parent product ID, unique SKU code, option values for display, and optional price override.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Create a new product variant for a seller's
     *   product. Validate that the seller owns the product referenced by
     *   productId. Check that sku_code is not empty and is unique within the
     *   product (query existing variants with same shopping_mall_product_id and
     *   sku_code). Create the variant record with provided sku_code,
     *   option_values, optional price, and set initial timestamps. Do not
     *   create inventory records here - stock starts at zero and is managed
     *   through separate restock API. Return the created variant entity. Reject
     *   with 403 if seller doesn't own the product. Reject with 409 if sku_code
     *   already exists for the product. Reject with 400 if sku_code is empty or
     *   option_values is empty.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProductVariant.ICreate,
  ): Promise<IShoppingMallProductVariant> {
    try {
      return await postShoppingMallSellerVariants({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product variant with new SKU code, option values, and optional price override.
   *
   * This operation allows sellers to modify their product variants after creation. Sellers can update the SKU code, option values text representation, and price override. The price field is optional - when null, the product's base price applies to this variant.
   *
   * Every variant update creates an immutable snapshot to preserve the previous state for audit trail purposes. The snapshot captures all variant fields at the moment of edit.
   *
   * Sellers can only update variants belonging to their own products. Attempting to update a variant from another seller's product will be rejected. Variants with pending order items or active cancellation/refund requests may have update restrictions to prevent disruption to customer orders.
   *
   * @param connection
   * @param variantId The UUID identifier of the product variant to update.
   * @param body Update payload containing the new SKU code, option values, and optional price override for the variant.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification 1. Validate the variantId exists and is not
     *   soft-deleted. 2. Verify the requesting seller owns the parent product
     *   of this variant (join shopping_mall_product_variants with
     *   shopping_mall_products to check seller_id). 3. Validate request body:
     *   sku_code must be non-empty, option_values must be non-empty, price is
     *   optional. 4. Check that the new sku_code is unique within the same
     *   product (query for existing variants with same shopping_mall_product_id
     *   and sku_code, excluding current variant). 5. Begin transaction: update
     *   the variant fields, set updated_at to current timestamp. 6. Create a
     *   product snapshot record that includes a snapshot of this variant's
     *   previous state. 7. Commit transaction and return the updated variant.
     *   8. Handle errors: variant not found (404), not owner (403), duplicate
     *   SKU (409), validation errors (400).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":variantId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductVariant.IUpdate,
  ): Promise<IShoppingMallProductVariant> {
    try {
      return await putShoppingMallSellerVariantsVariantId({
        seller,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
