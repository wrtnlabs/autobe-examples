import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallProductSnapshot } from "../../../../../api/structures/IPageIShoppingMallProductSnapshot";
import { IShoppingMallProductSnapshot } from "../../../../../api/structures/IShoppingMallProductSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerProductsProductIdSnapshotsSnapshotId } from "../../../../../providers/getShoppingMallSellerProductsProductIdSnapshotsSnapshotId";
import { patchShoppingMallSellerProductsProductIdSnapshots } from "../../../../../providers/patchShoppingMallSellerProductsProductIdSnapshots";

@Controller("/shoppingMall/seller/products/:productId/snapshots")
export class ShoppingmallSellerProductsSnapshotsController {
  /**
   * Retrieve historical snapshots of a specific product.
   *
   * This endpoint returns a paginated list of product snapshots, which are immutable audit records capturing the complete product state at the time of each edit. Each snapshot preserves the product's name, description, category, and base price as they existed when the edit occurred.
   *
   * Sellers can view snapshots of their own products only. Administrators can view snapshots of any product on the platform for oversight purposes. This endpoint supports filtering by creation date range and pagination for efficient browsing of product change history.
   *
   * Snapshots are created automatically when products are edited and cannot be modified or deleted. The snapshots are ordered chronologically with the most recent changes first.
   *
   * @param connection
   * @param productId Product ID (UUID format) identifying the product whose snapshots to retrieve.
   * @param body Search criteria including pagination parameters and optional date range filters for created_at.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_product_snapshots table filtered by shopping_mall_product_id.
   *
   * Authorization: Verify requester is either (1) the seller who owns the product, or (2) an administrator. Reject customers and unauthorized sellers.
   *
   * Apply pagination using cursor-based or offset-based pagination from request body. Support date range filtering on created_at field. Order results by created_at DESC (newest first).
   *
   * Join with shopping_mall_products to verify ownership (for seller authorization). Include snapshot fields: id, shopping_mall_category_id, name, description, base_price, created_at.
   *
   * Return IPageIShoppingMallProductSnapshot.ISummary with pagination metadata (page, limit, total count).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductSnapshot.IRequest,
  ): Promise<IPageIShoppingMallProductSnapshot.ISummary> {
    try {
      return await patchShoppingMallSellerProductsProductIdSnapshots({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific product snapshot by ID.
   *
   * This endpoint returns the complete snapshot record capturing the product state at a specific point in time. Each snapshot preserves the denormalized product fields (name, description, category, base price) when a product was edited, enabling historical tracking and dispute resolution.
   *
   * Sellers can view snapshots of their own products only. Administrators can view snapshots of any product on the platform for oversight purposes. The snapshot includes all captured fields and references to nested variant snapshots.
   *
   * Returns 403 Forbidden if a seller attempts to access a snapshot for a product they do not own. Returns 404 Not Found if the snapshot ID does not exist or the product ID does not match the snapshot's product reference.
   *
   * @param connection
   * @param productId Product ID (UUID format, global scope).
   * @param snapshotId Snapshot ID (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_product_snapshots table by snapshot ID. Verify the snapshot exists and the productId parameter matches the shopping_mall_product_id foreign key. Perform authorization check: if actor is seller, verify they own the product (shopping_mall_products.shopping_mall_seller_id matches authenticated seller); if actor is admin, allow access to any snapshot. Join with shopping_mall_categories to include category details if needed. Return the complete snapshot record including id, product reference, category reference, name, description, base_price, and created_at. Handle 404 for non-existent snapshots or mismatched product IDs. Handle 403 for unauthorized seller access attempts.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductSnapshot> {
    try {
      return await getShoppingMallSellerProductsProductIdSnapshotsSnapshotId({
        seller,
        productId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
