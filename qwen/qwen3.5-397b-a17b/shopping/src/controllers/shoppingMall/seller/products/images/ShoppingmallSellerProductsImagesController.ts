import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallProductImage } from "../../../../../api/structures/IShoppingMallProductImage";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerProductsProductIdImagesImageId } from "../../../../../providers/deleteShoppingMallSellerProductsProductIdImagesImageId";
import { postShoppingMallSellerProductsProductIdImages } from "../../../../../providers/postShoppingMallSellerProductsProductIdImages";
import { putShoppingMallSellerProductsProductIdImages } from "../../../../../providers/putShoppingMallSellerProductsProductIdImages";

@Controller("/shoppingMall/seller/products/:productId/images")
export class ShoppingmallSellerProductsImagesController {
  /**
   * Upload a new product image to a product's image gallery.
   *
   * This endpoint allows sellers to add images to their products. Each product can have multiple images displayed in a gallery sequence. The display_order field determines the image position in the gallery, with lower values appearing first. The image with display_order 0 serves as the main thumbnail shown in product listings and search results.
   *
   * Only the owning seller can upload images to their products. The image URL should point to a valid image file stored in the platform's object storage or CDN. After upload, sellers can reorder images or delete them as needed.
   *
   * @param connection
   * @param productId The UUID of the product to add the image to. The authenticated seller must own this product.
   * @param body Image upload data including the image URL and display order position in the product gallery.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate that the productId exists and belongs to the authenticated seller. Verify the seller has ownership of the product before allowing image upload. Validate the image URL format and ensure it points to an accessible resource. Check that display_order is a non-negative integer. If display_order conflicts with existing images, shift subsequent images to maintain consecutive ordering. Create the product image record with the provided url and display_order. Set created_at and updated_at timestamps automatically. Return the newly created product image entity with all fields including the generated id.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductImage.ICreate,
  ): Promise<IShoppingMallProductImage> {
    try {
      return await postShoppingMallSellerProductsProductIdImages({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Reorder product images by updating their display order sequence.
   *
   * This operation allows sellers to change the display sequence of images for their products. The display order determines how images appear in the product gallery, with the first image (display_order 0) serving as the main thumbnail shown in product listings and search results.
   *
   * Sellers can only reorder images for products they own. The operation accepts an array of image IDs with their new display order values. Display orders should be consecutive integers starting from 0. After reordering, the new first image automatically becomes the main thumbnail.
   *
   * The operation validates that all provided image IDs belong to the specified product and that the seller owns the product. If validation fails, the operation returns an error without making any changes.
   *
   * @param connection
   * @param productId Product ID (UUID format) identifying the product whose images are being reordered.
   * @param body Array of image reorder operations specifying each image ID and its new display order position. Display orders must be consecutive integers starting from 0.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate that the authenticated user is a seller and owns the product identified by productId.
   *
   * Query shopping_mall_product_images table for all images belonging to the product.
   *
   * Validate that all image IDs in the request body belong to this product.
   *
   * Validate that display_order values are consecutive integers starting from 0.
   *
   * Begin database transaction.
   *
   * For each image in the request, update the display_order field with the new value.
   *
   * Commit transaction.
   *
   * Query and return all images for the product in the new order.
   *
   * Error handling: Return 403 if seller doesn't own the product. Return 404 if product or any image ID doesn't exist. Return 400 if display_order values are invalid (not consecutive, duplicate values, or missing images).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductImage.IReorderRequest,
  ): Promise<IShoppingMallProductImage> {
    try {
      return await putShoppingMallSellerProductsProductIdImages({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a product image from a product.
   *
   * This endpoint allows sellers to remove individual images from their products. The image is soft-deleted by setting the deleted_at timestamp, preserving the record for audit trail and snapshot history. If the deleted image was the main thumbnail (first in display order), the system automatically designates the next image in sequence as the new thumbnail.
   *
   * Sellers can only delete images from products they own. The operation validates that the seller owns the product before proceeding. Deletion is blocked if the product has only one active image remaining, as at least one image must always be present on a product.
   *
   * The deleted image information is preserved in product snapshots created at the time of deletion, maintaining historical records for dispute resolution and audit purposes.
   *
   * @param connection
   * @param productId Product ID (UUID format, scoped to seller's owned products)
   * @param imageId Product image ID (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Validate that the authenticated seller owns the product by checking shopping_mall_products.shopping_mall_seller_id matches the seller's ID.
   *
   * 2. Verify the image exists and belongs to the specified product by checking shopping_mall_product_images.shopping_mall_product_id matches productId.
   *
   * 3. Check that the image is not already soft-deleted (deleted_at is null).
   *
   * 4. Count active images on the product. If only one active image exists, reject the deletion with an error indicating at least one image must remain.
   *
   * 5. If the deleted image has display_order 0 (main thumbnail), reorder remaining images so the next image becomes the new thumbnail.
   *
   * 6. Soft-delete the image by setting deleted_at to current timestamp.
   *
   * 7. Trigger creation of a product snapshot to capture the image deletion event, preserving the image state before deletion.
   *
   * 8. Return 204 No Content on success.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":imageId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductIdImagesImageId({
        seller,
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
