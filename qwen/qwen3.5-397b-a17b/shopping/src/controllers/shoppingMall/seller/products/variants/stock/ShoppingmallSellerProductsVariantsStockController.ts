@Controller(
  "/shoppingMall/seller/products/:productId/variants/:variantId/stock",
)
export class ShoppingmallSellerProductsVariantsStockController {
  /**
   * Retrieve the current stock quantity and availability status for a specific product variant.
   *
   * This operation calculates the real-time stock level by summing all inventory record quantity changes for the variant. The response includes the computed stock quantity and an out-of-stock indicator that determines whether the variant can be added to shopping carts.
   *
   * Variants with zero or negative stock are marked as out of stock and cannot be purchased. This endpoint is used by customers during product browsing and by sellers for inventory monitoring.
   *
   * @param connection
   * @param productId Parent product identifier (UUID format)
   * @param variantId Product variant identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_inventory_records table filtering by product_variant_id. Sum all quantity_change values to calculate current stock. Return stock quantity and isOutOfStock boolean (true when stock <= 0). Validate that the variant exists and belongs to the specified product. Include soft-deleted variant check - return 404 if variant is deleted. No joins needed beyond variant existence verification. Stock calculation is a simple SUM aggregation on the inventory records table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductVariant.IStock> {
    try {
      return await getShoppingMallSellerProductsProductIdVariantsVariantIdStock(
        {
          seller,
          productId,
          variantId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
