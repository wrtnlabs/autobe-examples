import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallProduct } from "../../../../api/structures/IShoppingMallProduct";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerProductsProductId } from "../../../../providers/deleteShoppingMallSellerProductsProductId";
import { getShoppingMallSellerProductsProductId } from "../../../../providers/getShoppingMallSellerProductsProductId";
import { postShoppingMallSellerProducts } from "../../../../providers/postShoppingMallSellerProducts";
import { putShoppingMallSellerProductsProductId } from "../../../../providers/putShoppingMallSellerProductsProductId";

@Controller("/shoppingMall/seller/products")
export class ShoppingmallSellerProductsController {
  /**
   * Create a new product listing on the platform.
   *
   * Sellers can create products by providing the product name, description, category assignment, and base price. The product is automatically associated with the authenticated seller who creates it and cannot be transferred to another seller.
   *
   * The product name and description are required fields used for search and display purposes. The category must be a valid category or subcategory ID from the platform's category hierarchy. The base price represents the standard price before any variant-specific adjustments.
   *
   * Upon successful creation, the product is visible in search results and category listings but marked as unavailable until at least one product variant is added. Products must have at least one variant to be purchasable by customers.
   *
   * Sellers who are suspended by administrators cannot create products. Attempting to create a product while suspended results in rejection with an appropriate error message.
   *
   * @param connection
   * @param body Product creation data including name, description, category assignment, and base price. The seller association is derived from authentication context.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Create a new product record in the
     *   shopping_mall_products table.
   *
   * 1. Validate the authenticated user is a seller with active approval status (not suspended).
   * 2. Validate the shopping_mall_category_id exists in shopping_mall_categories table.
   * 3. Validate required fields: name (non-empty string), description (non-empty string), base_price (positive number).
   * 4. Extract seller_id from the authenticated session context (do not accept from request body).
   * 5. Insert new record with: id (UUID), shopping_mall_seller_id, shopping_mall_category_id, name, description, base_price, created_at (current timestamp), updated_at (current timestamp), deleted_at (null).
   * 6. Return the created product record.
   *
   * Error handling:
   * - Reject if seller account is suspended (403 Forbidden).
   * - Reject if category_id does not exist (404 Not Found).
   * - Reject if required fields are missing or invalid (400 Bad Request).
   * - Reject if base_price is zero or negative (400 Bad Request).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProduct.ICreate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await postShoppingMallSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves complete details of a single product by its unique identifier.
   *
   * Returns the full product entity including name, description, base price, category assignment, and seller information. The response includes all product images in display order, with the first image serving as the main thumbnail. All product variants are included with their SKU codes, option value combinations, and optional price overrides.
   *
   * Stock availability for each variant is calculated from the inventory records ledger. Products that are soft deleted (deleted_at is set) return 404 Not Found to hide them from customers while preserving order history references.
   *
   * This endpoint is accessible to all actors including guests for product browsing. The product must exist and be active (not deleted) to be retrieved.
   *
   * @param connection
   * @param productId Unique identifier of the product to retrieve (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query shopping_mall_products table by productId
     *   UUID. Join with shopping_mall_product_images to include all images
     *   ordered by display_order. Join with shopping_mall_product_variants to
     *   include all variants with their option_values and prices. Calculate
     *   stock status from shopping_mall_inventory_records ledger for each
     *   variant. Return 404 if product not found or if deleted_at is not null
     *   (soft deleted products are hidden). Include seller profile information
     *   (shop_name, logo_image_url) from shopping_mall_seller_profiles. Include
     *   category information from shopping_mall_categories.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProduct> {
    try {
      return await getShoppingMallSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product's information.
   *
   * Sellers can update their own products by modifying the name, description, category assignment, and base price. This operation requires product ownership - only the seller who created the product can update it. When a product is updated, the system automatically creates an immutable snapshot preserving the previous state for audit trail and dispute resolution.
   *
   * The updated product information is immediately reflected in search results and category listings. If the seller account is suspended, this operation will be rejected. Product updates trigger snapshot creation that records all field changes including the complete state of all variants at the time of edit.
   *
   * @param connection
   * @param productId Product identifier (UUID format, global scope).
   * @param body Product update data including name, description, category ID, and base price. Excludes system-managed fields.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Validate the productId exists and is not soft
     *   deleted (deleted_at is null). Verify the authenticated seller owns this
     *   product by checking shopping_mall_seller_id matches the seller's ID.
     *   Reject if seller account is suspended. Update the product fields: name,
     *   description, shopping_mall_category_id, and base_price from the request
     *   body. Set updated_at to current timestamp. Automatically create a
     *   product snapshot record in shopping_mall_product_snapshots table with
     *   the complete product state before modification. Also create snapshots
     *   for all associated variants in shopping_mall_product_variant_snapshots.
     *   Return the updated product entity with all fields including
     *   relationships.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProduct.IUpdate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await putShoppingMallSellerProductsProductId({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a product from the platform.
   *
   * Sellers can delete their own products only when specific conditions are met: no pending order items in paid or shipped status for any variant, no pending cancellation requests, and no pending refund requests. When these conditions are satisfied, the product is soft deleted by setting the deleted_at timestamp.
   *
   * Administrators can delete any product on the platform for policy violations, bypassing the standard deletion conditions. This elevated permission enables platform oversight and content moderation.
   *
   * Upon deletion, the product is immediately hidden from search results, category listings, and cannot be purchased. All product variants are also deleted. The product and its snapshots remain accessible for order history and dispute resolution. If the deleted product exists in customer wishlists, it is automatically removed from all wishlists.
   *
   * @param connection
   * @param productId Product identifier (UUID format, global scope)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Delete product by setting deleted_at timestamp
     *   (soft delete). Validate deletion conditions for seller requests: query
     *   order_items for pending paid/shipped status variants, query
     *   cancellation_requests for pending status, query refund_requests for
     *   pending status. Reject with 400 if any pending items exist. For admin
     *   requests, skip condition validation. Set deleted_at to current
     *   timestamp. Cascade delete all product_variants and their
     *   inventory_records. Remove product from all
     *   shopping_mall_wishlist_items. Return 204 No Content on success. Return
     *   403 Forbidden if seller attempts to delete another seller's product.
     *   Return 404 Not Found if product does not exist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
