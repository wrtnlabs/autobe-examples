import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallProduct } from "../../../../api/structures/IShoppingMallProduct";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerProductsProductId } from "../../../../providers/deleteShoppingMallSellerProductsProductId";
import { postShoppingMallSellerProducts } from "../../../../providers/postShoppingMallSellerProducts";
import { putShoppingMallSellerProductsProductId } from "../../../../providers/putShoppingMallSellerProductsProductId";

@Controller("/shoppingMall/seller/products")
export class ShoppingmallSellerProductsController {
  /**
   * Create a new product listing in the shopping mall catalog.
   *
   * This operation allows authenticated sellers to add new products to their catalog. The product becomes immediately visible in search results and category listings upon creation. Each product must have a descriptive name, detailed description, category assignment for organization, and a base price.
   *
   * The authenticated seller's account is automatically associated as the product owner. The product is created with deleted=false, making it immediately available for customers to view and purchase. Products must have at least one variant to be purchasable, though variants can be added after product creation.
   *
   * Only users with seller role can access this endpoint. Customer accounts and guests cannot create products. The category ID must reference an existing active category in the system.
   *
   * @param connection
   * @param body Product creation information with required fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Authenticate the request and verify the user has seller role. Validate that the category ID exists and is not deleted. Create a new shopping_mall_products record with the provided name, description, shopping_category_id, base_price, and the authenticated seller's ID as shopping_seller_id. Set deleted to false, created_at and updated_at to current timestamp. Return the complete product record including the generated UUID. The product is immediately visible in search results. Sellers should add at least one variant using POST /sellers/products/{productId}/variants to make the product purchasable.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProduct.ICreate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await postShoppingMallSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product's information including name, description, category assignment, and base price.
   *
   * This operation allows sellers to modify their own product listings. Only the seller who created the product can update it. The operation validates that the product exists, belongs to the requesting seller, and any new category ID references a valid category. The base price must be a positive number if provided.
   *
   * Before applying any changes, the system automatically creates a product snapshot that captures the complete previous state of the product including all fields, images with display order, and all variants with their SKU codes, option values, prices, and stock quantities. This snapshot ensures historical accuracy for any existing orders referencing this product.
   *
   * Each field in the request body is optional - only the fields provided in the request will be updated. Unspecified fields retain their current values. This allows partial updates without needing to send the entire product object.
   *
   * The operation returns the complete updated product object with all current fields, images, and variants. If the product has been soft deleted (deleted flag is true), the update operation will fail as deleted products cannot be modified.
   *
   * Related operations: POST /sellers/products for creating new products, GET /products/{productId} for retrieving product details, DELETE /sellers/products/{productId} for removing a product, GET /sellers/products/{productId}/snapshots for viewing historical snapshots.
   *
   * @param connection
   * @param productId Target product's unique identifier
   * @param body Product fields to update - all fields are optional, only provided fields will be modified
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Update a product's fields with partial update support.
   *
   * 1. Validate the productId exists in shopping_mall_products table
   * 2. Verify the requesting seller owns this product (shopping_seller_id matches authenticated seller)
   * 3. Verify the product is not soft deleted (deleted = false)
   * 4. For each provided field in request body:
   *    - name: validate non-empty string
   *    - description: validate string (can be null)
   *    - categoryId: validate category exists in shopping_mall_categories
   *    - basePrice: validate positive number (> 0)
   * 5. Create product snapshot BEFORE applying changes:
   *    - Insert into shopping_mall_product_snapshots with all current product fields
   *    - Copy all product images to shopping_mall_product_snapshot_images
   *    - For each variant, create snapshot in shopping_mall_product_variant_snapshots
   *    - Copy variant options to snapshot option tables
   * 6. Apply the updates to shopping_mall_products table
   * 7. Update updated_at timestamp to current time
   * 8. Return the complete updated product with images and variants
   *
   * Transaction scope: Steps 5-7 must be atomic. If snapshot creation fails, no changes are applied.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProduct.IUpdate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await putShoppingMallSellerProductsProductId({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a product from the seller's catalog through soft deletion.
   *
   * This operation allows sellers to delete their own products by setting the deleted flag to true and recording the deletion timestamp. The product becomes hidden from search results, category listings, and browsing interfaces immediately after deletion.
   *
   * **Deletion Validation Rules**
   *
   * The deletion request will be rejected if any of the following conditions exist for any variant of the product:
   *
   * - Pending order items with PAID status
   * - Pending order items with SHIPPED status
   * - Pending cancellation requests (status: PENDING)
   * - Pending refund requests (status: PENDING)
   *
   * Sellers must resolve all pending orders and dispute requests before deleting a product. This ensures customer orders and consumer protection requests are not disrupted by product removal.
   *
   * **Soft Delete Behavior**
   *
   * Deleted products are not physically removed from the database. The product record remains accessible for:
   *
   * - Historical order item references through product snapshots
   * - Administrative oversight and audit trails
   * - Potential recovery operations (admin-only)
   *
   * **Authorization**
   *
   * Only the seller who owns the product can delete it. The system validates that the authenticated seller's ID matches the product's shopping_seller_id field. Attempts to delete another seller's product are rejected with a 403 Forbidden response.
   *
   * **Related Operations**
   *
   * - `GET /products/{productId}` - View product details before deletion
   * - `PUT /sellers/products/{productId}` - Edit product as alternative to deletion
   * - `GET /sellers/products/{productId}/snapshots` - View historical product states
   *
   * @param connection
   * @param productId Target product's unique identifier (UUID format). Must correspond to an existing product in the shopping_mall_products table.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement product soft deletion with comprehensive validation:
   *
   * 1. **Ownership Validation**: Query shopping_mall_products table to verify the authenticated seller's ID matches shopping_seller_id. Reject with 403 if mismatch.
   *
   * 2. **Deletion Condition Checks**: Before setting deleted flag, perform the following queries:
   *    - Join shopping_mall_product_variants with shopping_mall_order_items to find any order items with status IN ('PAID', 'SHIPPED') for any variant of this product
   *    - Join variants with order_items, then left join cancellation_requests where status = 'PENDING'
   *    - Join variants with order_items, then left join refund_requests where status = 'PENDING'
   *    - If any of these queries return results, reject with 400 Bad Request and specific error message indicating which condition failed
   *
   * 3. **Soft Delete Execution**: If all validations pass:
   *    - UPDATE shopping_mall_products SET deleted = true, deleted_at = CURRENT_TIMESTAMP WHERE id = {productId}
   *    - Also soft delete all associated variants: UPDATE shopping_mall_product_variants SET deleted = true, deleted_at = CURRENT_TIMESTAMP WHERE shopping_mall_product_id = {productId}
   *    - Wrap in transaction to ensure atomicity
   *
   * 4. **Response**: Return 204 No Content on success (no response body).
   *
   * 5. **Error Handling**:
   *    - 403 Forbidden: Product belongs to different seller
   *    - 400 Bad Request: Deletion blocked by pending orders/requests (include specific reason)
   *    - 404 Not Found: Product ID does not exist
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
