import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallProduct } from "../../../../../../api/structures/IPageIShoppingMallProduct";
import { IShoppingMallProduct } from "../../../../../../api/structures/IShoppingMallProduct";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerProductsInventoryLowStock } from "../../../../../../providers/patchShoppingMallSellerProductsInventoryLowStock";

@Controller("/shoppingMall/seller/products/inventory/low-stock")
export class ShoppingmallSellerProductsInventoryLow_stockController {
  /**
   * Retrieve a paginated list of products with low stock levels requiring seller attention.
   *
   * This operation aggregates inventory records across all variants of each product to calculate current stock levels. Products are included in the results when their total stock quantity falls below the specified threshold. The response includes product identification information, current stock quantity, and the low-stock threshold for context.
   *
   * This endpoint is designed for seller dashboard use cases, enabling sellers to quickly identify products that need restocking. Results are paginated to handle large product catalogs efficiently.
   *
   * @param connection
   * @param body Low stock threshold and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_products table joined with shopping_mall_product_variants and shopping_mall_inventory_records.
   *
   * For each product, sum all quantity_change values from inventory records across all variants to calculate current stock level.
   *
   * Filter products where total stock quantity is less than the threshold parameter from request body.
   *
   * Only include products owned by the authenticated seller (filter by seller_id from session).
   *
   * Exclude soft-deleted products (deleted_at IS NULL).
   *
   * Apply pagination with limit and offset from request body.
   *
   * Sort by stock quantity ascending (lowest stock first) by default.
   *
   * Return product id, name, sku_codes of variants, current_stock quantity, and threshold used.
   *
   * Handle edge case: products with no inventory records have zero stock.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProduct.ILowStockRequest,
  ): Promise<IPageIShoppingMallProduct.ILowStockSummary> {
    try {
      return await patchShoppingMallSellerProductsInventoryLowStock({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
