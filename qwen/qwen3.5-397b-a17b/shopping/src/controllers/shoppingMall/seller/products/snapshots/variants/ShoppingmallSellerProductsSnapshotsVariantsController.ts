@Controller(
  "/shoppingMall/seller/products/:productId/snapshots/:snapshotId/variants",
)
export class ShoppingmallSellerProductsSnapshotsVariantsController {
  /**
   * Retrieve a filtered and paginated list of product variant snapshots within a specific product snapshot.
   *
   * This operation provides access to the historical state of product variants at the moment a product snapshot was created. Each variant snapshot includes the SKU code, price override, and stock quantity as they existed at that point in time.
   *
   * Supports pagination for snapshots with many variants. Variant snapshots are immutable audit records preserved even after the original variant or product is deleted. Access is restricted to the product's seller and administrators.
   *
   * @param connection
   * @param productId Product ID (UUID format)
   * @param snapshotId Product snapshot ID (UUID format)
   * @param body Pagination and filtering parameters for variant snapshot search
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_product_snapshot_variants table filtered by shopping_mall_product_snapshot_id.
   *
   * Validate that the snapshot belongs to the specified product by checking shopping_mall_product_snapshots table.
   * Verify actor permissions: allow only the product's seller or administrators.
   * Apply pagination with cursor-based or offset-based approach.
   * Join with shopping_mall_product_variant_snapshot_options if option combination details are requested.
   * Return variant snapshots with SKU code, price override, stock quantity, and creation timestamp.
   * Handle case where snapshot has no variants (return empty array with pagination metadata).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductSnapshotVariant.IRequest,
  ): Promise<IPageIShoppingMallProductSnapshotVariant.ISummary> {
    try {
      return await patchShoppingMallSellerProductsProductIdSnapshotsSnapshotIdVariants(
        {
          seller,
          productId,
          snapshotId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific product variant snapshot within a product snapshot.
   *
   * This operation returns the complete state of a product variant at a specific point in time when the parent product snapshot was created. The variant snapshot includes the SKU code, price override value (if any), and stock quantity that were captured immutably for audit and dispute resolution purposes.
   *
   * Variant snapshots are created automatically whenever a product snapshot is generated, preserving all variant states at that moment. These snapshots remain accessible even after the original variant or product is deleted, enabling historical reconstruction and verification.
   *
   * Sellers can access variant snapshots for their own products. Administrators can access variant snapshots for any product on the platform. The response includes the variant snapshot's core fields; related option value combinations can be retrieved through the variant snapshot options endpoint.
   *
   * @param connection
   * @param productId Product ID (global scope, UUID format)
   * @param snapshotId Product snapshot ID (UUID format)
   * @param variantSnapshotId Variant snapshot ID (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_product_snapshot_variants table by variantSnapshotId.
   *
   * Validate that the snapshotId matches the shopping_mall_product_snapshot_id foreign key.
   * Validate that the productId matches the product associated with the snapshot (join through shopping_mall_product_snapshots to verify shopping_mall_product_id).
   *
   * Authorization check: Verify the authenticated user is either the seller who owns the product (through shopping_mall_products.seller_id) or an administrator/superAdministrator.
   *
   * Return the full variant snapshot record including id, sku_code, price_override, stock_quantity, and created_at.
   *
   * Handle 404 if variant snapshot not found or if productId/snapshotId mismatch detected.
   * Handle 403 if user lacks permission to access this product's snapshots.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":variantSnapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
    @TypedParam("variantSnapshotId")
    variantSnapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductSnapshotVariant> {
    try {
      return await getShoppingMallSellerProductsProductIdSnapshotsSnapshotIdVariantsVariantSnapshotId(
        {
          seller,
          productId,
          snapshotId,
          variantSnapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
