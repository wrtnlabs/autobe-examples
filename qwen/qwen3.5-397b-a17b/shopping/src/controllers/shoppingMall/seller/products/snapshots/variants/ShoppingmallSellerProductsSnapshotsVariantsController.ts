import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallProductSnapshotVariant } from "../../../../../../api/structures/IPageIShoppingMallProductSnapshotVariant";
import { IShoppingMallProductSnapshotVariant } from "../../../../../../api/structures/IShoppingMallProductSnapshotVariant";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerProductsProductIdSnapshotsSnapshotIdVariantsVariantSnapshotId } from "../../../../../../providers/getShoppingMallSellerProductsProductIdSnapshotsSnapshotIdVariantsVariantSnapshotId";
