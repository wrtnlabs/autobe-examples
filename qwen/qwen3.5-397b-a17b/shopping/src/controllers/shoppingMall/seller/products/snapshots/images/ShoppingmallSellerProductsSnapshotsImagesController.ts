import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallProductSnapshot } from "../../../../../../api/structures/IShoppingMallProductSnapshot";
import { IShoppingMallProductSnapshotImage } from "../../../../../../api/structures/IShoppingMallProductSnapshotImage";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerProductsProductIdSnapshotsSnapshotIdImagesImageId } from "../../../../../../providers/getShoppingMallSellerProductsProductIdSnapshotsSnapshotIdImagesImageId";
import { patchShoppingMallSellerProductsProductIdSnapshotsSnapshotIdImages } from "../../../../../../providers/patchShoppingMallSellerProductsProductIdSnapshotsSnapshotIdImages";

@Controller(
  "/shoppingMall/seller/products/:productId/snapshots/:snapshotId/images",
)
export class ShoppingmallSellerProductsSnapshotsImagesController {
  /**
   * Update product snapshot image configuration including display order and image URLs.
   *
   * ⚠️ CRITICAL BUSINESS RULE CONFLICT: Product snapshots are designed as IMMUTABLE audit records per requirements sections 60, 170, and 395. Snapshots preserve the complete product state at the time of edit and cannot be modified after creation. This endpoint contradicts the fundamental snapshot design principle.
   *
   * Snapshots exist for dispute resolution, order item references, and historical accuracy. Modifying snapshot images would compromise audit trail integrity and affect all systems relying on snapshot immutability (order items, reviews, cancellation/refund requests).
   *
   * If this operation is truly required, business requirements must be explicitly revised to allow snapshot modifications, fundamentally changing the snapshot concept from immutable audit record to editable historical reference.
   *
   * @param connection
   * @param productId Product ID in UUID format - identifies the product that owns this snapshot (scoped ownership verification)
   * @param snapshotId Snapshot ID in UUID format - identifies the specific product snapshot to update
   * @param body Image configuration update including display order changes, image URL additions, and image removals for the product snapshot.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification ⚠️ CRITICAL: This operation violates the immutability requirement for product snapshots established in business requirements sections 60, 170, and 395. Implementation should be blocked unless requirements are explicitly revised.
   *
   * Implementation steps if approved despite conflict:
   * 1. Verify snapshot exists by querying shopping_mall_product_snapshots WHERE id={snapshotId}
   * 2. Verify snapshot belongs to specified product WHERE shopping_mall_product_id={productId}
   * 3. Verify product exists in shopping_mall_products
   * 4. Authorization: Only product owner (seller) or administrators allowed
   * 5. Update display_order values for existing records in shopping_mall_product_snapshot_images
   * 6. Support adding new image URLs to the snapshot (INSERT new records)
   * 7. Support removing images from snapshot (DELETE or soft-delete records)
   * 8. Execute all changes atomically within database transaction
   * 9. Return updated snapshot image configuration
   *
   * Edge cases:
   * - Snapshot not found → 404 Not Found
   * - Product not found → 404 Not Found
   * - Snapshot doesn't belong to product → 404 Not Found
   * - Unauthorized user (non-owner, non-admin) → 403 Forbidden
   * - Invalid display_order (negative, non-consecutive, duplicates) → 400 Bad Request
   * - Empty image list → 400 Bad Request (snapshots must have at least one image)
   *
   * ⚠️ RECOMMENDATION: Reject this operation. Snapshots are read-only by design for audit trail integrity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductSnapshot.IUpdate,
  ): Promise<IShoppingMallProductSnapshot.ISummary> {
    try {
      return await patchShoppingMallSellerProductsProductIdSnapshotsSnapshotIdImages(
        {
          seller,
          productId,
          snapshotId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific image from a product snapshot.
   *
   * This endpoint returns the complete details of a single image preserved in a product snapshot. Product snapshots capture the complete image state (URLs and display order) at the time of each product edit, creating an immutable audit trail.
   *
   * The image record includes the URL as it existed at snapshot creation time, the display order for gallery presentation, and the timestamp when the snapshot was created. This data is immutable and cannot be modified.
   *
   * Sellers can access images from snapshots of their own products. Administrators can access images from any product snapshot on the platform for oversight purposes. This endpoint supports dispute resolution and historical product state verification.
   *
   * @param connection
   * @param productId Product ID (UUID format, identifies the product owning the snapshot)
   * @param snapshotId Product snapshot ID (UUID format, identifies the specific snapshot)
   * @param imageId Product snapshot image ID (UUID format, identifies the specific image within the snapshot)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_product_snapshot_images table by image ID. Verify the snapshot belongs to the specified product by joining with shopping_mall_product_snapshots on shopping_mall_product_snapshot_id. Verify product ownership: if actor is seller, ensure shopping_mall_products.shopping_mall_seller_id matches authenticated seller; if actor is admin, allow access to any product. Return the complete image record including image_url, display_order, and created_at. Handle 404 if image not found or if snapshot-product relationship doesn't match. Images are immutable snapshot data, so no modification operations allowed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":imageId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductSnapshotImage> {
    try {
      return await getShoppingMallSellerProductsProductIdSnapshotsSnapshotIdImagesImageId(
        {
          seller,
          productId,
          snapshotId,
          imageId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
