import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallSellerProfileSnapshot } from "../../../../api/structures/IPageIShoppingMallSellerProfileSnapshot";
import { IShoppingMallSellerProfileSnapshot } from "../../../../api/structures/IShoppingMallSellerProfileSnapshot";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerProfileSnapshotsSnapshotId } from "../../../../providers/getShoppingMallSellerProfileSnapshotsSnapshotId";
import { patchShoppingMallSellerProfileSnapshots } from "../../../../providers/patchShoppingMallSellerProfileSnapshots";

@Controller("/shoppingMall/seller/profile-snapshots")
export class ShoppingmallSellerProfile_snapshotsController {
  /**
   * Retrieve a paginated list of seller profile snapshots with optional filtering criteria.
   *
   * Seller profile snapshots are immutable historical records created automatically whenever a seller edits their profile (shop name, description, or logo). Each snapshot preserves the exact state of the seller profile at the time of modification, enabling order items to reference the seller profile that existed at purchase time.
   *
   * This endpoint supports filtering by seller profile ID to retrieve snapshots for a specific seller, and date range filtering to query snapshots within a specific time period. Results are ordered by creation timestamp in descending order by default, showing the most recent snapshots first.
   *
   * Snapshots are append-only and cannot be modified or deleted, ensuring a complete audit trail for dispute resolution and historical verification.
   *
   * @param connection
   * @param body Search criteria including seller profile ID filter, creation date range, and pagination parameters for browsing seller profile snapshot history.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_seller_profile_snapshots table with pagination and filtering. Support filtering by shopping_mall_seller_profile_id to get snapshots for a specific seller. Support date range filtering on created_at for chronological queries. Order results by created_at DESC by default to show most recent snapshots first. Implement cursor-based or offset pagination for large result sets. Join with shopping_mall_seller_profiles if seller information is needed in response. Ensure query performance using the composite index on (shopping_mall_seller_profile_id, created_at).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSellerProfileSnapshot.IRequest,
  ): Promise<IPageIShoppingMallSellerProfileSnapshot.ISummary> {
    try {
      return await patchShoppingMallSellerProfileSnapshots({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific seller profile snapshot by its unique identifier.
   *
   * This endpoint returns the complete snapshot record capturing the seller profile state at a specific point in time. The snapshot includes the shop name, shop description, and logo image URL as they existed when the snapshot was created, along with the creation timestamp.
   *
   * Seller profile snapshots are immutable audit records created automatically whenever a seller edits their profile. They cannot be modified or deleted by any user, ensuring a complete historical trail for dispute resolution and order history verification.
   *
   * Access to snapshots is restricted: sellers can only view snapshots of their own profile, while administrators can view any snapshot on the platform. The snapshot is linked to the seller profile through the shopping_mall_seller_profile_id relationship.
   *
   * @param connection
   * @param snapshotId Unique identifier of the seller profile snapshot to retrieve (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_seller_profile_snapshots table by primary key id (UUID).
   *
   * Retrieve single record with all fields: id, shopping_mall_seller_profile_id, shop_name, shop_description, logo_image_url, created_at.
   *
   * Authorization check: verify requesting user is either (a) the owner of the seller profile linked to this snapshot, or (b) an administrator with oversight permissions.
   *
   * Return 404 if snapshot not found or user lacks access permissions.
   *
   * No joins required for basic snapshot retrieval. If caller needs seller profile context, they can use the shopping_mall_seller_profile_id to make a separate call.
   *
   * Snapshot data is immutable - no update or delete operations permitted on this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerProfileSnapshot> {
    try {
      return await getShoppingMallSellerProfileSnapshotsSnapshotId({
        seller,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
