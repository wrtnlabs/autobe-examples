import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallInventoryRecord } from "../../../../../api/structures/IPageIShoppingMallInventoryRecord";
import { IShoppingMallInventoryRecord } from "../../../../../api/structures/IShoppingMallInventoryRecord";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerInventoryHistoryVariantId } from "../../../../../providers/patchShoppingMallSellerInventoryHistoryVariantId";

@Controller("/shoppingMall/seller/inventory/history/:variantId")
export class ShoppingmallSellerInventoryHistoryController {
  /**
   * Retrieve a paginated and filtered list of inventory change records for a specific product variant.
   *
   * This operation provides sellers with complete visibility into their product variant's stock movement history. Each record represents a single inventory change event, whether from manual restocking, adjustments, or automatic updates from orders, cancellations, and refunds.
   *
   * Supports filtering by date range and reason code, with chronological ordering by timestamp. Response includes quantity change amount, reason categorization, and creation timestamp for each record. The inventory history is read-only and immutable, forming a permanent audit trail for stock level verification and dispute resolution.
   *
   * Only accessible for variants owned by the authenticated seller. Returns 404 if the variant does not exist or belongs to a different seller.
   *
   * @param connection
   * @param variantId Product variant identifier (UUID format)
   * @param body Search criteria and pagination parameters for filtering inventory history
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_inventory_records table filtered by product_variant_id.
   *
   * Validate that the variant exists and belongs to the authenticated seller by joining with shopping_mall_product_variants and shopping_mall_products tables.
   *
   * Apply optional filters from request body: date range (created_at between start and end), reason code matching.
   *
   * Order results by created_at descending (newest first) for chronological display.
   *
   * Implement cursor-based or offset pagination with configurable page size.
   *
   * Return summary fields: id, quantity_change, reason, created_at.
   *
   * Handle edge cases: variant not found (404), variant not owned by seller (403), no inventory records (empty array with pagination metadata).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallInventoryRecord.IRequest,
  ): Promise<IPageIShoppingMallInventoryRecord.ISummary> {
    try {
      return await patchShoppingMallSellerInventoryHistoryVariantId({
        seller,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
