import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallProduct } from "../../../api/structures/IPageIShoppingMallProduct";
import { IShoppingMallProduct } from "../../../api/structures/IShoppingMallProduct";
import { getShoppingMallProductsProductId } from "../../../providers/getShoppingMallProductsProductId";
import { patchShoppingMallProducts } from "../../../providers/patchShoppingMallProducts";

@Controller("/shoppingMall/products")
export class ShoppingmallProductsController {
  /**
   * Retrieve a filtered and paginated list of active products from the shopping mall catalog.
   *
   * This operation provides comprehensive product search capabilities including partial name matching, category filtering, price range filtering, and in-stock availability filtering. Results support multiple sorting options including newest first, price ascending, and price descending.
   *
   * Only active products (not deleted by sellers) are included in search results. Each result includes essential product information optimized for listing displays: main image, name, price or price range, seller shop name, and average customer rating.
   *
   * Authentication is not required for browsing products. Results are paginated using cursor-based pagination for efficient navigation through large product catalogs.
   *
   * @param connection
   * @param body Search criteria including name query, category filter, price range, stock availability, pagination, and sorting options
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_products table with pagination and filtering.
   *
   * Apply WHERE deleted_at IS NULL to exclude deleted products.
   * Apply name filter using trigram similarity search (gin_trgm_ops index) for partial matching.
   * Apply category_id filter when provided.
   * Apply price range filters (min_price, max_price) against base_price column.
   * Apply in_stock filter by joining with shopping_mall_product_variants and checking stock_quantity > 0.
   *
   * Support sorting by:
   * - created_at DESC (newest)
   * - base_price ASC (price low-high)
   * - base_price DESC (price high-low)
   *
   * Implement cursor-based pagination with limit and cursor parameters.
   * Return IPageIShoppingMallProduct.ISummary with product summary fields.
   *
   * Join with shopping_mall_sellers for seller shop name.
   * Join with shopping_mall_product_images to get first image (index 0) as thumbnail.
   * Calculate price range if variants have price overrides.
   * Calculate average rating from shopping_mall_reviews.
   *
   * Handle edge cases:
   * - Empty result set: return empty array with null cursor
   * - Invalid cursor: return error
   * - No variants: show base_price, mark as unavailable
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallProduct.IRequest,
  ): Promise<IPageIShoppingMallProduct.ISummary> {
    try {
      return await patchShoppingMallProducts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete details for a specific product by its unique identifier.
   *
   * This operation returns the full product information including name, description, base price, category assignment, seller details, all product images, and available variants. The response includes comprehensive data needed to render a product detail page with all purchasing options.
   *
   * Products that have been deleted by the seller (deleted_at is set) will return a 404 Not Found error. This ensures customers cannot access products that are no longer available on the platform.
   *
   * The product detail includes aggregated rating information calculated from customer reviews, enabling customers to see the average rating and review count before making a purchase decision.
   *
   * @param connection
   * @param productId Product unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_products table by productId UUID.
   * Return 404 if product not found or deleted_at is not null.
   * Join with shopping_mall_sellers to include seller profile information (shop name, logo).
   * Join with shopping_mall_categories to include category hierarchy.
   * Include related shopping_mall_product_images ordered by index (first image is thumbnail).
   * Include related shopping_mall_product_variants with their option values.
   * Calculate average rating from shopping_mall_reviews for this product.
   * Return complete IShoppingMallProduct DTO with all nested relations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProduct> {
    try {
      return await getShoppingMallProductsProductId({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
