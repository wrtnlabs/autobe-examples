import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallReview } from "../../../api/structures/IPageIShoppingMallReview";
import { IShoppingMallReview } from "../../../api/structures/IShoppingMallReview";
import { getShoppingMallReviewsReviewId } from "../../../providers/getShoppingMallReviewsReviewId";
import { patchShoppingMallReviews } from "../../../providers/patchShoppingMallReviews";

@Controller("/shoppingMall/reviews")
export class ShoppingmallReviewsController {
  /**
   * Retrieve a filtered and paginated list of product reviews.
   *
   * This operation provides advanced search capabilities for retrieving customer reviews. Reviews can be filtered by product ID to show all reviews for a specific product, or by customer ID to retrieve a specific customer's reviews. The endpoint supports comprehensive pagination with configurable page sizes and sorting options.
   *
   * Reviews are displayed sorted by newest first by default, showing the most recent feedback at the top. Only non-deleted reviews are included in the results. The response includes review summary information optimized for list displays, including rating, optional text content, and timestamps.
   *
   * This endpoint is commonly used on product detail pages to display customer reviews, or on customer profile pages to show a user's review history.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering reviews
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_reviews table with pagination and filtering.
   *
   * Apply filters:
   * - product_id: Filter reviews for specific product (used on product detail pages)
   * - customer_id: Filter reviews by specific customer (used on customer profile)
   * - deleted_at: Exclude soft-deleted reviews (WHERE deleted_at IS NULL)
   *
   * Sorting: Default sort by created_at DESC (newest first). Support custom sorting by rating, created_at with ASC/DESC options.
   *
   * Pagination: Use cursor-based or offset-based pagination with configurable page size (default 20, max 100).
   *
   * Join with shopping_mall_customers to include reviewer display name. Join with shopping_mall_products to include product name if not filtered by product.
   *
   * Validate that customer_id filter can only be used by the customer themselves or administrators (authorization check).
   *
   * Return IPageIShoppingMallReview.ISummary with review summaries including id, rating, content preview, created_at, updated_at, and reviewer information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallReview.IRequest,
  ): Promise<IPageIShoppingMallReview.ISummary> {
    try {
      return await patchShoppingMallReviews({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific review by its unique identifier.
   *
   * This operation returns the complete review entity including the star rating (1-5), optional text content, and all metadata such as creation and update timestamps. The review is associated with a specific customer, product, and order.
   *
   * Access is restricted to the review author (customer) or administrators. Deleted reviews (with deleted_at set) are not accessible through this endpoint.
   *
   * @param connection
   * @param reviewId Review unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_reviews table by primary key id.
   *
   * Validate that the review exists and is not soft-deleted (deleted_at is null).
   * Verify authorization: requester must be the review's customer_id or an administrator.
   *
   * Return full review entity including:
   * - id, customer_id, product_id, order_id
   * - rating (1-5), content (nullable)
   * - created_at, updated_at
   *
   * If review not found or deleted, return 404.
   * If unauthorized access, return 403.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reviewId")
  public async at(
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReview> {
    try {
      return await getShoppingMallReviewsReviewId({
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
