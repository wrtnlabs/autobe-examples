import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallProduct } from "../../../../../api/structures/IPageIShoppingMallProduct";
import { IShoppingMallProduct } from "../../../../../api/structures/IShoppingMallProduct";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminSellersSellerIdProducts } from "../../../../../providers/patchShoppingMallAdminSellersSellerIdProducts";

@Controller("/shoppingMall/admin/sellers/:sellerId/products")
export class ShoppingmallAdminSellersProductsController {
  /**
   * Retrieve a paginated list of products owned by a specific seller with optional filtering and sorting.
   *
   * This endpoint allows sellers to browse their own product catalog with flexible search criteria. Results are filtered to only show products belonging to the specified seller. The response includes product summaries optimized for list displays, containing essential information like name, base price, category, thumbnail image, and variant statistics.
   *
   * Search filters support full-text search on product name and description, category filtering, price range queries, and status filtering (active vs deleted products). Sorting options include creation date, name, price, and update date in ascending or descending order.
   *
   * Products from suspended sellers are excluded from results. Deleted products (soft-deleted with deleted_at set) are excluded by default but can be included using the status filter for sellers reviewing their deleted catalog.
   *
   * @param connection
   * @param sellerId UUID of the seller whose products to retrieve (scoped to seller ownership).
   * @param body Search criteria including name keyword, category filter, price range, product status (active/deleted), pagination parameters (page, limit), and sorting options (sort field and order).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_products table filtered by shopping_mall_seller_id matching the path parameter. Apply search filters from request body: name (full-text search using gin_trgm_ops index), shopping_mall_category_id, base_price range, deleted_at status (active vs deleted products). Support pagination with cursor-based or offset-based approach. Join with shopping_mall_categories for category name in summary. Join with shopping_mall_product_images to include thumbnail URL (first image by display order). Join with shopping_mall_product_variants to compute min/max variant prices and total stock quantity. Exclude products from suspended sellers. Return IPageIShoppingMallProduct.ISummary with pagination metadata. Handle case where sellerId doesn't exist (404) or seller is suspended (return empty or error per business rules).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProduct.IRequest,
  ): Promise<IPageIShoppingMallProduct.ISummary> {
    try {
      return await patchShoppingMallAdminSellersSellerIdProducts({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
