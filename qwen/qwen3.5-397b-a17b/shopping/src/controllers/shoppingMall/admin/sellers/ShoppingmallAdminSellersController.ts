  /**
   * Ban a seller account, preventing the seller from accessing the platform.
   *
   * This operation allows administrators to ban seller accounts when policy violations or other issues require restricting platform access. When a seller account is banned, the seller cannot log in to the platform using their credentials. The authentication system will reject any login attempts from banned seller accounts.
   *
   * Banning a seller account does not affect existing orders. All orders placed with the banned seller remain in the system and continue through their normal status workflow. The seller's shop name in past orders is preserved and remains visible to customers who purchased from them. Order items belonging to the banned seller continue through fulfillment, cancellation, and refund processes as normal.
   *
   * This operation is restricted to administrators only. Regular customers and sellers cannot access this endpoint. Administrators can later unban the seller account using the corresponding unban endpoint, which restores the seller's login access and selling capabilities.
   *
   * The ban action is immediate and takes effect upon successful completion. Any active sessions for the banned seller should be invalidated by the authentication system.
   *
   * @param connection
   * @param sellerId Target seller account's unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification This operation bans a seller account, preventing the seller from logging into the platform.
   *
   * Implementation steps:
   * 1. Verify the requesting user is an administrator (check session/authorization)
   * 2. Query shopping_mall_sellers table by sellerId
   * 3. Validate seller exists and is not already banned
   * 4. Update seller account status to banned (set appropriate flag in database)
   * 5. Preserve all existing orders - do not modify order records
   * 6. Return success response
   *
   * Business rules:
   * - Banned sellers cannot log in (authentication will reject banned accounts)
   * - Existing orders remain in system for processing
   * - Seller's shop name in past orders remains visible
   * - Order items continue through normal status flow
   * - Administrator can later unban the account via /sellers/{sellerId}/unban
   *
   * Edge cases:
   * - Seller not found: return 404
   * - Seller already banned: return 400 or 409
   * - Non-admin user attempts ban: return 403
   * - Super admin attempting to ban themselves: allowed (no restriction like demotion)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
