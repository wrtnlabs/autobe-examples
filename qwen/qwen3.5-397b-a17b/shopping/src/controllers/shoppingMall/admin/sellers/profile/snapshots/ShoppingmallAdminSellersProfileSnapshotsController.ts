import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageISellerProfileSnapshot } from "../../../../../../api/structures/IPageISellerProfileSnapshot";
import { ISellerProfileSnapshot } from "../../../../../../api/structures/ISellerProfileSnapshot";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminSellersSellerIdProfileSnapshots } from "../../../../../../providers/getShoppingMallAdminSellersSellerIdProfileSnapshots";
import { getShoppingMallAdminSellersSellerIdProfileSnapshotsSnapshotId } from "../../../../../../providers/getShoppingMallAdminSellersSellerIdProfileSnapshotsSnapshotId";

@Controller("/shoppingMall/admin/sellers/:sellerId/profile/snapshots")
export class ShoppingmallAdminSellersProfileSnapshotsController {
  /**
   * Retrieve the history of seller profile snapshots for a specific seller.
   *
   * This operation returns an immutable audit trail of all profile changes made by a seller. Each snapshot captures the state of the seller's profile at a point in time, including shop name, shop description, and logo image URL. Snapshots are automatically created whenever a seller edits their profile.
   *
   * Authorization rules: Sellers can only view snapshots of their own profile. Administrators can view snapshots of any seller profile for oversight and dispute resolution purposes. Snapshots are displayed in chronological order to show the complete history of profile changes.
   *
   * The snapshots remain accessible even if the seller account is deleted, ensuring historical records are preserved for order history and dispute resolution. This endpoint supports pagination to handle sellers with extensive edit histories.
   *
   * @param connection
   * @param sellerId Target seller's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query seller profile snapshots filtered by sellerId. Join with sellers table to verify seller exists. Apply authorization check: allow if authenticated user is the seller themselves or has admin role. Return snapshots in chronological order (newest first). Include pagination support for large snapshot histories. Each snapshot contains shopName, shopDescription, logoImageUrl, and createdAt timestamp. Snapshots are immutable and cannot be modified.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async list(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IPageISellerProfileSnapshot> {
    try {
      return await getShoppingMallAdminSellersSellerIdProfileSnapshots({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific seller profile snapshot by its identifier.
   *
   * This endpoint returns an immutable point-in-time capture of a seller's profile state, including the shop name, shop description, and logo image URL as they existed at the moment the snapshot was created. Seller profile snapshots are automatically generated whenever a seller updates their profile information, preserving the historical state for audit trail and dispute resolution purposes.
   *
   * Access to snapshots is restricted based on user role and ownership. Sellers can only view snapshots of their own profile, ensuring privacy and preventing unauthorized access to other sellers' historical data. Administrators and super administrators have platform-wide access to view any seller's profile snapshots for oversight and dispute resolution purposes. This access control is enforced at the service layer.
   *
   * The snapshot includes the timestamp when it was created, allowing users to track when profile changes occurred. Snapshots are immutable and cannot be modified or deleted, ensuring the integrity of historical records. This endpoint is typically used in conjunction with the list snapshots endpoint to first retrieve snapshot IDs, then fetch detailed information for specific snapshots.
   *
   * If the snapshot does not exist or the requesting user lacks permission to view it, the system returns a 404 Not Found response to prevent information leakage about the existence of snapshots the user cannot access.
   *
   * @param connection
   * @param sellerId Target seller's ID (scopes the snapshot to a specific seller)
   * @param snapshotId Target seller profile snapshot's ID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_seller_profile_snapshots table by snapshotId. Validate that the snapshot exists and is accessible to the requesting user. For seller actors: verify sellerId matches the authenticated seller's ID. For admin/superAdmin actors: allow access to any snapshot. Join with shopping_mall_sellers to include seller profile information (shop_name at time of snapshot). Return the snapshot record with shop_name, shop_description, logo_image_url, created_at timestamp, and snapshot metadata. Handle 404 if snapshot not found or access denied.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<ISellerProfileSnapshot> {
    try {
      return await getShoppingMallAdminSellersSellerIdProfileSnapshotsSnapshotId(
        {
          admin,
          sellerId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
