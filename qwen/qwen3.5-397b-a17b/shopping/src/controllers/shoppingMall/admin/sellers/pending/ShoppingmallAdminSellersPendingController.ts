import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallSeller } from "../../../../../api/structures/IPageIShoppingMallSeller";
import { IShoppingMallSeller } from "../../../../../api/structures/IShoppingMallSeller";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminSellersPending } from "../../../../../providers/patchShoppingMallAdminSellersPending";

@Controller("/shoppingMall/admin/sellers/pending")
export class ShoppingmallAdminSellersPendingController {
  /**
   * Retrieve a paginated list of seller accounts awaiting administrator approval.
   *
   * This endpoint provides administrators with visibility into pending seller registration requests. Each seller record includes essential information for review decisions: email address for communication, shop name and description to understand the business, and submission timestamp to prioritize older requests.
   *
   * Only administrator actors can access this endpoint. The operation supports pagination and sorting to handle large volumes of pending requests. Sellers remain in PENDING status until an administrator explicitly approves or rejects their registration through the corresponding approval endpoints.
   *
   * Related operations include POST /sellers/{sellerId}/approve for approving a seller, POST /sellers/{sellerId}/reject for rejecting with a reason, and GET /sellers/{sellerId} for viewing complete seller details.
   *
   * @param connection
   * @param body Pagination and sorting parameters for pending seller list
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_sellers table filtering by approval_status = 'PENDING'. Join with shopping_mall_admins table to include approver information if available. Apply pagination parameters (page, limit) and sorting (default by created_at ascending to show oldest pending requests first). Return seller summary information including id, email, shop_name, shop_description, created_at, and any additional registration details. Ensure only admin actors can access this endpoint through authentication middleware. Handle empty result set by returning pagination with zero data array.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSeller.IRequest,
  ): Promise<IPageIShoppingMallSeller.ISummary> {
    try {
      return await patchShoppingMallAdminSellersPending({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
