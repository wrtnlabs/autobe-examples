import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallCustomerProfile } from "../../../../../api/structures/IShoppingMallCustomerProfile";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCustomersCustomerIdProfile } from "../../../../../providers/getShoppingMallAdminCustomersCustomerIdProfile";
import { patchShoppingMallAdminCustomersCustomerIdProfile } from "../../../../../providers/patchShoppingMallAdminCustomersCustomerIdProfile";

@Controller("/shoppingMall/admin/customers/:customerId/profile")
export class ShoppingmallAdminCustomersProfileController {
  /**
   * Retrieve a customer's profile information including display name and phone number.
   *
   * This endpoint returns the complete profile data for a specific customer identified by their customer ID. The profile contains the customer's display name shown throughout the platform and their contact phone number used for order notifications and delivery coordination.
   *
   * The customer profile is linked to the base member account and is created automatically upon customer registration. Profile information is editable by the customer through their account settings, and changes take effect immediately across the platform.
   *
   * Access to customer profiles is restricted for privacy. Customers can typically only access their own profile information, while administrators may have oversight capabilities for user management purposes.
   *
   * @param connection
   * @param customerId Unique identifier of the customer account (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the shopping_mall_customer_profiles table by customerId parameter.
   *
   * Join with shopping_mall_members table to verify the customer account exists and is not soft-deleted (deleted_at is null).
   *
   * Return the full customer profile record including id, shopping_mall_member_id, display_name, phone_number, created_at, and updated_at fields.
   *
   * Handle edge cases:
   * - Return 404 if customer profile does not exist
   * - Return 404 if customer account is soft-deleted (deleted_at is not null)
   * - Ensure proper authorization: customer can only access their own profile, admins can access any profile
   *
   * No request body needed for GET operation. Response is the complete IShoppingMallCustomerProfile entity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerProfile> {
    try {
      return await getShoppingMallAdminCustomersCustomerIdProfile({
        admin,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a customer's profile information including display name and phone number.
   *
   * This operation allows customers to modify their profile settings. Both display_name and phone_number are optional fields - only provided fields will be updated, while omitted fields retain their current values. Changes take effect immediately and are reflected across the platform wherever the customer's display name or phone number is shown.
   *
   * The customerId path parameter identifies the customer account to update. Authorization ensures customers can only modify their own profile - attempts to update another customer's profile are rejected. The profile must exist and be active (not soft-deleted) for the update to succeed.
   *
   * @param connection
   * @param customerId Unique identifier of the customer account to update (UUID format, references shopping_mall_members.id).
   * @param body Partial update payload containing profile fields to modify. Both fields are optional - include only the fields you want to change.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update the customer profile identified by customerId path parameter. Query shopping_mall_customer_profiles table where shopping_mall_member_id equals customerId. Validate that the profile exists and is not soft-deleted. Apply partial updates for display_name and/or phone_number fields provided in request body - only update fields that are present, leave others unchanged. Validate display_name and phone_number are strings if provided (both are optional per business rules). Update the updated_at timestamp to current time. Return the complete updated profile including id, shopping_mall_member_id, display_name, phone_number, created_at, and updated_at. Authorization middleware ensures customers can only update their own profile - reject attempts to modify another customer's profile with 403 Forbidden. Return 404 Not Found if customerId does not exist or profile is deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCustomerProfile.IUpdate,
  ): Promise<IShoppingMallCustomerProfile> {
    try {
      return await patchShoppingMallAdminCustomersCustomerIdProfile({
        admin,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
