import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCustomerAddress } from "../../../../../api/structures/IPageIShoppingMallCustomerAddress";
import { IShoppingMallCustomerAddress } from "../../../../../api/structures/IShoppingMallCustomerAddress";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCustomersCustomerIdAddressesAddressId } from "../../../../../providers/getShoppingMallAdminCustomersCustomerIdAddressesAddressId";
import { patchShoppingMallAdminCustomersCustomerIdAddresses } from "../../../../../providers/patchShoppingMallAdminCustomersCustomerIdAddresses";

@Controller("/shoppingMall/admin/customers/:customerId/addresses")
export class ShoppingmallAdminCustomersAddressesController {
  /**
   * Retrieve a paginated list of customer shipping addresses with search and filter capabilities.
   *
   * This endpoint returns all active (non-deleted) shipping addresses belonging to the specified customer. Addresses include complete shipping information such as recipient name, phone number, street address, city, state/province, postal code, and country. The response supports pagination for customers with many saved addresses.
   *
   * Customers can filter addresses by various criteria including default status, recipient name, city, or country. Results can be sorted by creation date or recipient name. Only the authenticated customer's own addresses are returned - addresses are isolated by customer ownership.
   *
   * Soft-deleted addresses (deleted_at is set) are automatically excluded from results. The default address (is_default = true) can be identified for checkout pre-selection purposes.
   *
   * @param connection
   * @param customerId Unique identifier of the customer whose addresses to retrieve (UUID format, scoped to customer account).
   * @param body Search criteria for filtering customer addresses including default status, recipient name, location filters, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_customer_addresses table filtered by shopping_mall_customer_profile_id matching the customerId parameter.
   *
   * Apply WHERE clause: shopping_mall_customer_profile_id = {customerId} AND deleted_at IS NULL.
   *
   * Support request body filters:
   * - is_default: filter by default address status (boolean)
   * - recipient_name: partial match search on recipient name
   * - city: exact or partial match on city
   * - country: exact match on country
   * - postal_code: exact match on postal code
   *
   * Support pagination with take (limit) and skip (offset) or cursor-based pagination.
   * Support sorting by created_at (DESC for newest first), recipient_name (ASC), or city (ASC).
   *
   * Join with shopping_mall_customer_profiles if customer display name is needed in response.
   *
   * Return IPageIShoppingMallCustomerAddress.ISummary with pagination metadata (total count, hasMore, etc.).
   *
   * Validate customerId exists in shopping_mall_members table before querying addresses.
   * Return 404 if customer not found or if customerId doesn't match authenticated user (authorization check).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCustomerAddress.IRequest,
  ): Promise<IPageIShoppingMallCustomerAddress.ISummary> {
    try {
      return await patchShoppingMallAdminCustomersCustomerIdAddresses({
        admin,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific customer shipping address by its unique identifier.
   *
   * This endpoint returns the complete address record including recipient information (name and phone number), full address details (street address, city, state/province, postal code, country), and metadata (default flag, timestamps). The address must belong to the specified customer.
   *
   * The operation verifies ownership by checking that the address's customer profile ID matches the provided customerId. If the address does not exist or does not belong to the customer, a 404 Not Found response is returned. Soft-deleted addresses (deleted_at is not null) are excluded from results.
   *
   * @param connection
   * @param customerId Customer profile UUID (global scope). Identifies the customer who owns the address.
   * @param addressId Address record UUID (scoped to customer). Unique identifier for the specific address within the customer's address list.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the shopping_mall_customer_addresses table by address ID.
   *
   * 1. Validate that both customerId and addressId are valid UUID format.
   * 2. Query shopping_mall_customer_addresses WHERE id = {addressId} AND shopping_mall_customer_profile_id = {customerId} AND deleted_at IS NULL.
   * 3. If no record found, return 404 Not Found.
   * 4. If record found, return the complete address entity with all fields.
   * 5. Ensure the query uses the index on (shopping_mall_customer_profile_id, deleted_at) for efficient lookup.
   *
   * Ownership verification is critical - never return an address that doesn't belong to the specified customer.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":addressId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerAddress> {
    try {
      return await getShoppingMallAdminCustomersCustomerIdAddressesAddressId({
        admin,
        customerId,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
