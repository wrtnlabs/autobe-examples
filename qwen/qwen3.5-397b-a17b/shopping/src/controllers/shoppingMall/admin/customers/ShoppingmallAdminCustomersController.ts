import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallMember } from "../../../../api/structures/IPageIShoppingMallMember";
import { IShoppingMallMember } from "../../../../api/structures/IShoppingMallMember";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCustomersCustomerId } from "../../../../providers/getShoppingMallAdminCustomersCustomerId";
import { patchShoppingMallAdminCustomers } from "../../../../providers/patchShoppingMallAdminCustomers";

@Controller("/shoppingMall/admin/customers")
export class ShoppingmallAdminCustomersController {
  /**
   * Retrieve a paginated list of customer accounts with optional filtering and search capabilities.
   *
   * This endpoint enables administrators to browse customer accounts across the platform. Supports filtering by account status (active, banned, deleted), email address search, and registration date ranges. Results are returned with cursor-based pagination for efficient handling of large datasets.
   *
   * Administrators can use this endpoint to monitor customer accounts, identify banned users, or review deletion requests. The summary response includes essential account information suitable for list displays while excluding sensitive data like password hashes.
   *
   * @param connection
   * @param body Search criteria including email partial match, account status filter, registration date ranges, soft delete date ranges, and pagination parameters (take, cursor).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_members table with pagination and filtering support.
   *
   * Apply search filters:
   * - email: partial match search using LIKE operator
   * - status: exact match filter (active, banned, deleted)
   * - createdAtFrom/createdAtTo: date range filtering on created_at column
   * - deletedAtFrom/deletedAtTo: date range filtering on deleted_at column for soft-deleted accounts
   *
   * Implement cursor-based pagination using created_at timestamp for consistent ordering.
   *
   * Join with shopping_mall_customer_profiles to include display name and phone number in summary response.
   *
   * Exclude password_hash field from response.
   *
   * Return 400 for invalid filter combinations or malformed date ranges.
   *
   * Administrators only - enforce role-based access control.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallMember.IRequest,
  ): Promise<IPageIShoppingMallMember.ISummary> {
    try {
      return await patchShoppingMallAdminCustomers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information for a specific customer account by ID.
   *
   * This endpoint returns the complete customer record including authentication account data from shopping_mall_members and profile information from shopping_mall_customer_profiles. The response includes email, account status, display name, phone number, and timestamps.
   *
   * Administrators can access any customer's details for user management purposes. Customers can access their own profile through this endpoint. The operation joins the member account with the customer profile to provide comprehensive customer information.
   *
   * Returns 404 if the customer ID does not exist or the account has been soft deleted.
   *
   * @param connection
   * @param customerId Customer account UUID identifier (global scope).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_members table by UUID primary key. Join with shopping_mall_customer_profiles on shopping_mall_member_id to include profile data (display_name, phone_number). Filter out soft-deleted records (deleted_at IS NOT NULL). Return the complete member record with embedded profile information. Handle 404 for non-existent or deleted customers. Ensure proper authorization - administrators can access any customer, members can only access their own profile.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallMember> {
    try {
      return await getShoppingMallAdminCustomersCustomerId({
        admin,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
