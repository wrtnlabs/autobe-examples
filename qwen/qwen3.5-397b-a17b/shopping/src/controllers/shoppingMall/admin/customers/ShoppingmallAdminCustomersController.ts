import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCustomer } from "../../../../api/structures/IPageIShoppingMallCustomer";
import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCustomersCustomerId } from "../../../../providers/getShoppingMallAdminCustomersCustomerId";
import { patchShoppingMallAdminCustomers } from "../../../../providers/patchShoppingMallAdminCustomers";
import { postShoppingMallAdminCustomersCustomerIdBan } from "../../../../providers/postShoppingMallAdminCustomersCustomerIdBan";
import { putShoppingMallAdminCustomersCustomerId } from "../../../../providers/putShoppingMallAdminCustomersCustomerId";

@Controller("/shoppingMall/admin/customers")
export class ShoppingmallAdminCustomersController {
  /**
   * Retrieve a filtered and paginated list of customer accounts on the shopping mall platform.
   *
   * This operation provides administrators with comprehensive search capabilities for customer account management. Administrators can filter customers by email address (partial match), display nickname (partial match with trigram index support), registration date range, and account status including active, banned, or soft-deleted states.
   *
   * The endpoint supports flexible pagination with configurable page sizes and multiple sorting options including registration date, email, and nickname. Response includes customer summary information optimized for list displays, excluding sensitive data like password hashes.
   *
   * This operation requires administrator or super administrator authorization. Regular customers and sellers cannot access this endpoint. The operation respects soft deletion by default, excluding deleted accounts unless explicitly requested with a filter parameter.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for customer list query
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_customers table with pagination and filtering. Apply search filters on email (partial match), nickname (partial match using gin_trgm_ops index), created_at date range, and account status (active, banned, deleted based on deleted_at nullability). Support sorting by created_at, email, or nickname. Return cursor-based or offset pagination with configurable page sizes. Join with shopping_mall_orders for order statistics if requested in search criteria. Exclude password_hash from response. Filter out soft-deleted records by default unless explicitly requested by admin. Validate authorization: only admin and superAdmin actors can access this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCustomer.IRequest,
  ): Promise<IPageIShoppingMallCustomer.ISummary> {
    try {
      return await patchShoppingMallAdminCustomers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific customer account by identifier.
   *
   * This operation provides administrators with complete visibility into customer account details for platform management and oversight purposes. The endpoint returns the customer's profile information including email address, display name (nickname), phone number, and account timestamps.
   *
   * Access to this endpoint is restricted to administrator actors. Regular customers cannot access other users' data and should use the session-based GET /customers/profile endpoint to view their own profile. The response excludes sensitive credential information such as password hashes for security.
   *
   * The operation supports viewing both active and soft-deleted customer accounts. Soft-deleted accounts (where deleted_at is populated) are still accessible to administrators for audit and historical reference, preserving order history and review associations while the authentication credentials are removed.
   *
   * Related operations include PATCH /customers for listing customers with pagination and filtering, POST /admin/customers/{customerId}/ban for account restriction, and GET /customers/profile for current user's own profile access.
   *
   * @param connection
   * @param customerId Target customer account's UUID identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the shopping_mall_customers table by the customerId UUID path parameter. Retrieve customer record including id, email, nickname, phone_number, created_at, updated_at, and deleted_at fields. Exclude password_hash from the response for security. Validate that the customer record exists and return 404 if not found. This operation should be restricted to administrator actors only based on the permission matrix - customers can only access their own profile through the session-based /customers/profile endpoint. Implement soft delete filtering: if deleted_at is not null, still return the record for admin viewing but indicate the deleted status. Join with related entities if needed for expanded customer information (orders count, reviews count) in future enhancements.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await getShoppingMallAdminCustomersCustomerId({
        admin,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a customer's profile information including display name and phone number.
   *
   * This operation allows customers to modify their profile details. Both the nickname (display name shown in reviews and public content) and phone number (used for order notifications and delivery coordination) must be provided in the request, even if only one field is being changed. This ensures data consistency and validates that both required fields are present.
   *
   * When the phone number is updated, the change automatically cascades to all shipping addresses associated with the customer account. This ensures consistency between the customer's profile contact information and their saved addresses, preventing delivery coordination issues.
   *
   * The operation validates that the customer can only update their own profile by checking the customerId against the authenticated user's identity. Email addresses and passwords cannot be modified through this endpoint and require separate operations.
   *
   * Related operations include GET /customers/profile for retrieving current profile information, and POST /auth/customer/password/change for password modifications.
   *
   * @param connection
   * @param customerId Target customer's UUID identifier. Must match the authenticated customer's ID for authorization.
   * @param body Profile update information containing display name and phone number
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update the customer profile by modifying nickname and phone_number fields in shopping_mall_customers table.
   *
   * Implementation steps:
   * 1. Validate customerId matches the authenticated customer's ID (customers can only update their own profile)
   * 2. Validate both nickname and phone_number are provided and non-empty per requirements
   * 3. Update the customer record with new nickname and phone_number
   * 4. Cascade phone_number update to all shopping_mall_addresses records belonging to this customer
   * 5. Update the updated_at timestamp
   * 6. Return the updated customer entity
   *
   * Business rules:
   * - Both nickname and phone_number must be provided (cannot update just one)
   * - Phone number changes must cascade to all customer addresses immediately
   * - Customer can only update their own profile (authorization check required)
   * - Email cannot be changed through this endpoint
   * - Password changes require separate endpoint
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":customerId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCustomer.IUpdate,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await putShoppingMallAdminCustomersCustomerId({
        admin,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Ban a customer account, preventing the customer from logging in to the platform and accessing any authenticated features.
   *
   * This operation is restricted to administrators only. When a customer account is banned, the system immediately terminates all active sessions for that customer and prevents any future login attempts using their credentials. The ban action is administrative and used for enforcing platform policies or responding to violations.
   *
   * All existing orders placed by the banned customer are preserved in the system. The customer's order history remains accessible to administrators and sellers for fulfillment purposes. Past orders continue through their normal status workflow (PAID, SHIPPED, DELIVERED) even after the account is banned.
   *
   * This operation is idempotent - banning an already-banned customer succeeds without error. To restore customer access, administrators must use the unban endpoint.
   *
   * Related operations: POST /customers/{customerId}/unban to restore access, GET /admin/customers to view all customer accounts with their ban status.
   *
   * @param connection
   * @param customerId Target customer's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the shopping_mall_customers table to find the customer by the provided customerId UUID. Verify the requesting user has administrator privileges. Update the customer record to set the banned status flag. Terminate all active sessions for the customer by invalidating tokens in shopping_mall_customer_sessions table. Preserve all existing orders - do not modify shopping_mall_orders or shopping_mall_order_items. Return success response. Handle edge cases: customer not found (404), customer already banned (can proceed idempotently), requesting user not admin (403).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":customerId/ban")
  public async ban(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await postShoppingMallAdminCustomersCustomerIdBan({
        admin,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
