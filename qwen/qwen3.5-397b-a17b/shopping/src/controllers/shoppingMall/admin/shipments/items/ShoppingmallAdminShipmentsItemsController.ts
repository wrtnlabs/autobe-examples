import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallShipmentItem } from "../../../../../api/structures/IPageIShoppingMallShipmentItem";
import { IShoppingMallShipmentItem } from "../../../../../api/structures/IShoppingMallShipmentItem";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminShipmentsShipmentIdItemsItemId } from "../../../../../providers/getShoppingMallAdminShipmentsShipmentIdItemsItemId";
import { patchShoppingMallAdminShipmentsShipmentIdItems } from "../../../../../providers/patchShoppingMallAdminShipmentsShipmentIdItems";

@Controller("/shoppingMall/admin/shipments/:shipmentId/items")
export class ShoppingmallAdminShipmentsItemsController {
  /**
   * Retrieve a filtered and paginated list of order items within a specific shipment.
   *
   * This operation provides access to the individual order items that have been grouped into a shipment for delivery. Each shipment contains one or more order items from the same seller, as different sellers always ship separately in different shipments. The endpoint returns item details including product information, variant options, quantity, unit price, and current fulfillment status.
   *
   * Sellers can use this endpoint to view which items are included in a shipment they created, verifying the shipment composition before and after dispatch. Customers can access this endpoint to see which items from their order are being delivered together in the same package with shared tracking information.
   *
   * The operation supports filtering by item status (PAID, SHIPPED, DELIVERED, CANCELLED, REFUNDED) and sorting by various fields. Response includes pagination metadata for navigating large shipments. All items in the same shipment share the same tracking information and transition to shipped status together when the shipment is created.
   *
   * This endpoint is typically used after retrieving the shipment list to examine detailed item composition. The shipment must exist and the requesting actor must have appropriate permissions (seller who created the shipment or customer who placed the order).
   *
   * @param connection
   * @param shipmentId Target shipment's ID (UUID format)
   * @param body Filter criteria and pagination parameters for shipment items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_shipment_items table filtered by shipment_id.
   * Join with shopping_mall_order_items to get item details including product variant, quantity, unit price, and status.
   * Join with shopping_mall_product_variants, shopping_mall_product_snapshots, and shopping_mall_sellers for complete item information.
   * Apply status filter if provided in request body.
   * Support sorting by quantity, unit_price, status, and created_at.
   * Implement cursor-based or offset pagination with configurable page size.
   * Validate that shipment_id exists and requesting actor has access (seller or customer).
   * Return paginated list with shipment item summaries including nested order item details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipmentItem.IRequest,
  ): Promise<IPageIShoppingMallShipmentItem.ISummary> {
    try {
      return await patchShoppingMallAdminShipmentsShipmentIdItems({
        admin,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order item within a shipment.
   *
   * This operation provides access to the linkage between a shipment and an order item, allowing customers and sellers to view which specific order items are included in a particular shipment. The response includes the shipment item record along with related order item details such as product variant information, quantity, unit price, and current fulfillment status.
   *
   * Customers can use this endpoint to verify which items from their order are being shipped together in a specific package. Sellers can use this to confirm the contents of shipments they have created. The endpoint enforces authorization checks to ensure only authorized users (the customer who placed the order or the seller who created the shipment) can access the shipment item details.
   *
   * The shipment item represents the assignment of an order item to a physical shipment package. Each order item can belong to exactly one shipment, and all items in the same shipment share the same tracking information including carrier name and tracking number. This endpoint is typically used in conjunction with shipment tracking views to provide complete visibility into the fulfillment process.
   *
   * Related operations:
   * - GET /shipments/{shipmentId} - View complete shipment information with all items
   * - GET /customers/orders/{orderId} - View order details including all shipments
   * - GET /sellers/shipments - List shipments created by the seller
   *
   * @param connection
   * @param shipmentId Target shipment's ID (UUID format)
   * @param itemId Target order item's ID within the shipment (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the shopping_mall_shipment_items table to retrieve a specific shipment item record.
   *
   * Implementation steps:
   * 1. Validate that the shipmentId exists in shopping_mall_shipments table
   * 2. Validate that the order itemId exists in shopping_mall_order_items table
   * 3. Query shopping_mall_shipment_items where shipment_id equals {shipmentId} AND order_item_id equals {itemId}
   * 4. If record not found, return 404 error
   * 5. Authorization check: verify the authenticated user (customer or seller) has access to this shipment
   *    - For customers: verify the shipment belongs to an order owned by the customer
   *    - For sellers: verify the shipment was created by the seller (all items in shipment belong to seller's products)
   * 6. Join with shopping_mall_order_items to include order item details (product variant, quantity, unit price, status)
   * 7. Join with shopping_mall_shipments to include shipment tracking information (carrier, tracking number, shipped_at)
   * 8. Return the shipment item with related order item and shipment information
   *
   * Edge cases:
   * - Shipment not found: return 404
   * - Order item not found: return 404
   * - Shipment item linkage not found (item not in this shipment): return 404
   * - Unauthorized access: return 403
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipmentItem> {
    try {
      return await getShoppingMallAdminShipmentsShipmentIdItemsItemId({
        admin,
        shipmentId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
