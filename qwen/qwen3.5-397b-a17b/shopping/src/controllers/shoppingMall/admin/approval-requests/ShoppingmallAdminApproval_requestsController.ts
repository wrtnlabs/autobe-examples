import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallSellerApprovalRequest } from "../../../../api/structures/IShoppingMallSellerApprovalRequest";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminApprovalRequestsRequestId } from "../../../../providers/getShoppingMallAdminApprovalRequestsRequestId";
import { putShoppingMallAdminApprovalRequestsRequestId } from "../../../../providers/putShoppingMallAdminApprovalRequestsRequestId";

@Controller("/shoppingMall/admin/approval-requests/:requestId")
export class ShoppingmallAdminApproval_requestsController {
  /**
   * Retrieve detailed information about a specific seller approval request.
   *
   * This endpoint allows administrators to view the complete details of a seller registration approval request including the seller information, current status, rejection reason (if applicable), and timestamps. Admins use this to review pending requests before making approval or rejection decisions.
   *
   * The response includes all request fields: status (pending/approved/rejected), rejection_reason (populated only for rejected requests), reviewed_by_admin_id (populated when reviewed), and audit timestamps.
   *
   * @param connection
   * @param requestId Unique identifier of the seller approval request (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_seller_approval_requests table by primary key id.
   *
   * Join with shopping_mall_sellers to include seller profile information in response.
   * Join with shopping_mall_admins to include reviewing administrator information if reviewed_by_admin_id is not null.
   *
   * Return 404 if request not found or if soft-deleted (deleted_at is not null).
   *
   * Ensure admin authorization is validated before returning data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerApprovalRequest> {
    try {
      return await getShoppingMallAdminApprovalRequestsRequestId({
        admin,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a seller approval request by approving or rejecting it.
   *
   * Administrators use this endpoint to review and make decisions on pending seller registration requests. When approving, the seller gains permission to create products and sell on the platform. When rejecting, administrators must provide a rejection reason that the seller can view to understand what needs to be addressed in a re-application.
   *
   * The operation transitions the request status from 'pending' to either 'approved' or 'rejected'. Only pending requests can be updated. The reviewing administrator's ID is automatically recorded in the reviewed_by_admin_id field. Access is restricted to administrator role users through authentication middleware.
   *
   * @param connection
   * @param requestId Unique identifier of the seller approval request to update (UUID format).
   * @param body Approval decision including new status and optional rejection reason for rejected requests.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_seller_approval_requests by requestId. Validate request exists and status is 'pending'. Validate status transition: only 'approved' or 'rejected' allowed. If status is 'rejected', validate rejection_reason is provided and non-empty. Update status, rejection_reason (if rejecting), reviewed_by_admin_id (current admin from session), and updated_at. If approving, update the seller's approval_status in shopping_mall_sellers table to 'approved'. Return updated approval request entity. Handle concurrent modification by checking updated_at timestamp. Return 404 if not found, 400 if status is not pending or validation fails.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSellerApprovalRequest.IUpdate,
  ): Promise<IShoppingMallSellerApprovalRequest> {
    try {
      return await putShoppingMallAdminApprovalRequestsRequestId({
        admin,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
