import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallOrder } from "../../../../../api/structures/IPageIShoppingMallOrder";
import { IShoppingMallOrder } from "../../../../../api/structures/IShoppingMallOrder";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminAdminOrdersOrderId } from "../../../../../providers/getShoppingMallAdminAdminOrdersOrderId";
import { patchShoppingMallAdminAdminOrders } from "../../../../../providers/patchShoppingMallAdminAdminOrders";

@Controller("/shoppingMall/admin/admin/orders")
export class ShoppingmallAdminAdminOrdersController {
  /**
   * Retrieve a paginated list of all orders on the platform with search and filtering capabilities.
   *
   * This endpoint allows administrators to view and search across all customer orders regardless of ownership. Administrators can filter orders by customer, seller, order status, date ranges, and search by order code. The response includes order summary information optimized for administrative oversight dashboards.
   *
   * Administrators use this endpoint to monitor platform activity, investigate specific orders, and identify orders requiring intervention such as force-cancellation or force-refund operations.
   *
   * @param connection
   * @param body Search criteria including order code partial match, customer ID, seller ID, order status filter, date range filters, pagination parameters (page, limit), and sorting options.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_orders table with pagination and filtering. Join with shopping_mall_members for customer information and shopping_mall_order_items for seller and status aggregation. Apply search filters on order code, member_id, seller_id, status, and created_at date ranges. Support sorting by created_at (newest first by default), code, or total_price. Return cursor-based pagination with IPageIShoppingMallOrder.ISummary response type. Exclude soft-deleted orders (deleted_at IS NOT NULL) from results. Include order item count and current aggregated status in summary.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallOrder.IRequest,
  ): Promise<IPageIShoppingMallOrder.ISummary> {
    try {
      return await patchShoppingMallAdminAdminOrders({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete details of a specific order by its ID.
   *
   * Administrators can access any order on the platform regardless of customer or seller ownership. This endpoint returns the full order details including order number, total price, creation timestamp, and all associated order items with their product snapshots and shipment information.
   *
   * The response includes order items with product name, variant options, quantity, price, and item status. Each order item includes its snapshot preserving the product state at purchase time. Shipments are included with carrier name, tracking number, and delivery timestamps.
   *
   * This endpoint is restricted to administrator and super administrator roles. Regular customers can only access their own orders through a different endpoint.
   *
   * @param connection
   * @param orderId Unique identifier of the order to retrieve (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_orders table by primary key ID. Verify the requesting user has administrator or super_admin role. Eagerly load related order items with their snapshots and snapshot options. Include shipments with their associated order items. Return 404 if order not found or if order is soft-deleted (deleted_at is not null). Join with shopping_mall_members for customer information if needed. Include product snapshot data from shopping_mall_order_item_snapshots and shopping_mall_order_item_snapshot_options tables.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrder> {
    try {
      return await getShoppingMallAdminAdminOrdersOrderId({
        admin,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
