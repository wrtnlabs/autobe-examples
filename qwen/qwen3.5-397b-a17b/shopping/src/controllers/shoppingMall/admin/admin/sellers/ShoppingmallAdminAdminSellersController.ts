import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallSeller } from "../../../../../api/structures/IShoppingMallSeller";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { postShoppingMallAdminAdminSellersSellerIdReject } from "../../../../../providers/postShoppingMallAdminAdminSellersSellerIdReject";
import { postShoppingMallAdminAdminSellersSellerIdSuspend } from "../../../../../providers/postShoppingMallAdminAdminSellersSellerIdSuspend";

@Controller("/shoppingMall/admin/admin/sellers/:sellerId")
export class ShoppingmallAdminAdminSellersController {
  /**
   * Reject a pending seller registration request as an administrator.
   *
   * This operation allows administrators to reject seller registration applications that are in PENDING status. When rejecting a seller registration, administrators must provide a rejection reason explaining why the application was denied. The rejection reason is stored in the seller record and is visible to the rejected seller.
   *
   * Upon rejection, the seller's approval_status is changed to REJECTED, the rejection_reason is recorded, and the approving administrator's ID is linked to the seller account. Rejected sellers can view the rejection reason and submit a new registration request after addressing the issues.
   *
   * Only administrators have access to this endpoint. The seller must be in PENDING status; attempting to reject an already approved or rejected seller will result in an error. This operation is part of the seller approval management workflow described in the platform requirements.
   *
   * @param connection
   * @param sellerId Target seller account's unique identifier (UUID format)
   * @param body Rejection information including the mandatory reason for denying the seller registration
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_sellers table by sellerId. Validate seller exists and approval_status is 'PENDING'. Validate rejection reason is provided and non-empty. Update seller record: set approval_status to 'REJECTED', set rejection_reason to provided value, set approved_by_admin_id to current admin's ID, update updated_at timestamp. Return updated seller object. Error cases: 404 if seller not found, 400 if seller not in PENDING status, 400 if rejection reason missing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("reject")
  public async reject(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSeller.IReject,
  ): Promise<IShoppingMallSeller> {
    try {
      return await postShoppingMallAdminAdminSellersSellerIdReject({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Suspend a seller account, restricting their ability to create or edit products while maintaining access to process existing orders.
   *
   * This operation is exclusively available to administrators and super administrators. When a seller account is suspended, all products from that seller are immediately hidden from search results and category listings. Customers cannot purchase products from suspended sellers. The suspended seller loses the ability to create new products or edit existing product listings.
   *
   * However, suspended sellers retain the capability to process existing orders. This includes creating shipments with tracking information, shipping items to customers, and responding to cancellation and refund requests for their order items. This ensures customer orders are not disrupted by the suspension.
   *
   * The suspension is tracked by setting the suspended boolean field to true on the seller account record. Administrators can later unsuspend the account using the corresponding unsuspend endpoint, which restores product visibility and full seller capabilities.
   *
   * This operation is part of the seller management authority granted to administrators per the platform governance model. It provides a middle-ground enforcement mechanism between full account approval and permanent banning, allowing administrators to restrict seller activities while maintaining order fulfillment obligations.
   *
   * @param connection
   * @param sellerId Target seller account's ID (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Suspend a seller account by setting the suspended field to true on the shopping_mall_sellers table.
   *
   * Implementation steps:
   * 1. Verify the requesting user has admin or superAdmin role
   * 2. Query shopping_mall_sellers table by sellerId (UUID)
   * 3. Validate seller exists and is not already suspended
   * 4. Update the suspended field to true and updated_at timestamp
   * 5. Create audit log entry for the suspension action
   * 6. Return 204 No Content on success
   *
   * Business rules enforced:
   * - While suspended, all products from this seller are hidden from search results and category listings (enforced at query level in product search endpoints)
   * - While suspended, products cannot be purchased (enforced at checkout validation)
   * - While suspended, seller cannot create new products (enforced at product creation endpoint)
   * - While suspended, seller cannot edit existing products (enforced at product update endpoint)
   * - While suspended, seller CAN still process existing orders including shipping items (shipment creation endpoint allows suspended sellers)
   * - While suspended, seller CAN still respond to cancellation and refund requests (cancellation/refund response endpoints allow suspended sellers)
   *
   * Error scenarios:
   * - 404 Not Found: Seller ID does not exist
   * - 400 Bad Request: Seller is already suspended
   * - 403 Forbidden: Requesting user is not an administrator
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("suspend")
  public async suspend(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await postShoppingMallAdminAdminSellersSellerIdSuspend({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
