import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallSeller } from "../../../../../api/structures/IPageIShoppingMallSeller";
import { IShoppingMallSeller } from "../../../../../api/structures/IShoppingMallSeller";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminAdminSellersSellerId } from "../../../../../providers/getShoppingMallAdminAdminSellersSellerId";
import { patchShoppingMallAdminAdminSellers } from "../../../../../providers/patchShoppingMallAdminAdminSellers";

@Controller("/shoppingMall/admin/admin/sellers")
export class ShoppingmallAdminAdminSellersController {
  /**
   * Retrieve a paginated list of all seller accounts on the platform with filtering and search capabilities.
   *
   * This endpoint allows administrators to view and search through all seller accounts regardless of their approval status. Administrators can filter sellers by approval status (pending, approved, rejected), search by email, and filter by registration date range. This supports seller oversight workflows including reviewing pending applications, monitoring approved sellers, and tracking rejected applications.
   *
   * The response includes seller account information such as email, approval status, rejection reason (if applicable), and timestamps. Results are paginated using cursor-based pagination for efficient handling of large seller datasets.
   *
   * @param connection
   * @param body Search criteria including email search, approval status filter, registration date range, and pagination parameters for browsing seller accounts.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_sellers table with pagination and filtering support.
   *
   * Apply search filters:
   * - email: partial match search using LIKE operator
   * - approvalStatus: exact match filter (pending, approved, rejected)
   * - createdAt: date range filtering using gte and lte
   *
   * Join with shopping_mall_seller_profiles to include shop_name in summary response.
   * Join with shopping_mall_seller_approval_requests to get latest approval request details if needed.
   *
   * Implement cursor-based pagination using created_at timestamp for efficient large dataset handling.
   * Order results by created_at DESC (newest first) by default.
   *
   * Authorization: Require admin role. Reject requests from non-admin users with 403 Forbidden.
   *
   * Edge cases:
   * - Return empty array if no sellers match filters
   * - Handle NULL rejection_reason for pending/approved sellers
   * - Exclude soft-deleted sellers (deleted_at IS NOT NULL) from results
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSeller.IRequest,
  ): Promise<IPageIShoppingMallSeller.ISummary> {
    try {
      return await patchShoppingMallAdminAdminSellers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific seller account.
   *
   * This endpoint provides administrators with complete visibility into seller account details including authentication information, approval status, and profile data. Administrators can use this to review seller applications, investigate account issues, or monitor seller activity on the platform.
   *
   * The response includes the seller's email, approval status, rejection reason (if applicable), account timestamps, and embedded seller profile information (shop name, description, logo). This operation is part of the administrator's seller oversight capabilities, enabling them to manage the seller ecosystem effectively.
   *
   * Administrators can view all seller accounts regardless of approval status (pending, approved, or rejected). This endpoint does not include sensitive authentication data such as password hashes.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller account to retrieve (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the shopping_mall_sellers table by the provided sellerId UUID parameter.
   *
   * Join with shopping_mall_seller_profiles table to include profile information (shop_name, shop_description, logo_image_url) in the response. Use LEFT JOIN since profile may not exist for pending/rejected sellers.
   *
   * Return the complete seller record including: id, email, approval_status, rejection_reason, created_at, updated_at, and embedded profile object.
   *
   * Exclude password_hash from the response for security reasons.
   *
   * Handle the case where sellerId does not exist by returning 404 Not Found.
   *
   * This is a read-only operation with no side effects. No authorization checks beyond verifying the caller is an administrator (handled by middleware).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSeller.IInvert> {
    try {
      return await getShoppingMallAdminAdminSellersSellerId({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
