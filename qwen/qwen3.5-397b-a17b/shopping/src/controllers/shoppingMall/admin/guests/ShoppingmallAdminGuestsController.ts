import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallGuest } from "../../../../api/structures/IPageIShoppingMallGuest";
import { IShoppingMallGuest } from "../../../../api/structures/IShoppingMallGuest";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminGuestsGuestId } from "../../../../providers/getShoppingMallAdminGuestsGuestId";
import { patchShoppingMallAdminGuests } from "../../../../providers/patchShoppingMallAdminGuests";

@Controller("/shoppingMall/admin/guests")
export class ShoppingmallAdminGuestsController {
  /**
   * Search and list guest accounts with pagination and filtering capabilities.
   *
   * This endpoint allows administrators to search and browse guest accounts for oversight and security monitoring purposes. Guests are unauthenticated users identified by device fingerprint who have not completed registration. The operation supports filtering by device fingerprint, creation date range, and account status (active or deleted).
   *
   * Results are returned as paginated summaries optimized for administrative list displays. Each guest record includes the device fingerprint, session timestamps, and account status information.
   *
   * @param connection
   * @param body Search criteria including device fingerprint filter, creation date range, account status filter, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query shopping_mall_guests table with pagination
     *   and filtering. Apply search filters on device_fingerprint (partial
     *   match), created_at date range, and deleted_at status (active vs deleted
     *   guests). Join with shopping_mall_guest_sessions if session count or
     *   last activity is requested in response. Return cursor-based pagination
     *   for large result sets. Exclude soft-deleted guests by default unless
     *   explicitly requested. Validate admin authentication before allowing
     *   access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallGuest.IRequest,
  ): Promise<IPageIShoppingMallGuest.ISummary> {
    try {
      return await patchShoppingMallAdminGuests({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a guest account record by ID for system administration purposes.
   *
   * This endpoint provides access to guest account information including device fingerprint and session metadata. Guest accounts are system-managed infrastructure used for temporary session tracking.
   *
   * Note: Per platform security policy, guests have no access to platform features. This endpoint is intended for administrative system management only, not for guest-facing operations. All actual users must register and authenticate before accessing any platform functionality.
   *
   * @param connection
   * @param guestId Guest account unique identifier (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query shopping_mall_guests table by primary key
     *   ID. Return full guest record including device_fingerprint, created_at,
     *   updated_at, and deleted_at fields. Verify guest exists and handle
     *   soft-deleted records appropriately. This operation should be restricted
     *   to administrator access only, as guests have no platform access per
     *   business requirements.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":guestId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallGuest> {
    try {
      return await getShoppingMallAdminGuestsGuestId({
        admin,
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
