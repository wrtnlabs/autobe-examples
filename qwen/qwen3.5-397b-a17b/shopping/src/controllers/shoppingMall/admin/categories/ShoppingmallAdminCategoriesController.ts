import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallCategory } from "../../../../api/structures/IShoppingMallCategory";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { postShoppingMallAdminCategories } from "../../../../providers/postShoppingMallAdminCategories";
import { putShoppingMallAdminCategoriesCategoryId } from "../../../../providers/putShoppingMallAdminCategoriesCategoryId";

@Controller("/shoppingMall/admin/categories")
export class ShoppingmallAdminCategoriesController {
  /**
   * Create a new product classification category in the shopping mall catalog.
   *
   * This operation allows administrators to create categories for organizing products. Categories support a one-level hierarchical structure where top-level categories can have subcategories, but subcategories cannot have their own children. When creating a subcategory, the parent category must be specified and must be a top-level category.
   *
   * The category name must be unique among sibling categories (categories sharing the same parent). Both name and description are required fields. The system automatically records which administrator created the category and maintains timestamps for creation and updates.
   *
   * Only administrators (admin and superAdmin roles) can create categories. Regular customers and sellers cannot access this endpoint. This centralized control ensures consistent product organization across the platform.
   *
   * @param connection
   * @param body Category creation information including name, description, and optional parent category for subcategory creation
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new category in the shopping_mall_categories table. Validate that the requesting user is an administrator (admin or superAdmin role). For subcategory creation, verify the parent_category_id exists and is a top-level category (not already a subcategory) to enforce one-level nesting constraint. Validate name and description are not empty. Check name uniqueness among sibling categories (categories with same parent). Set created_by_admin_id to the authenticated admin's ID. Generate UUID for id. Set created_at and updated_at to current timestamp. Return the complete category object including id, parent_category_id, name, description, and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCategory.ICreate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await postShoppingMallAdminCategories({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product classification category's information. This operation allows administrators to modify a category's name, description, or parent category assignment.
   *
   * Only administrators (admin or superAdmin role) can execute this operation. Regular customers and sellers do not have permission to modify categories. The endpoint validates that the requesting user has appropriate administrative privileges before processing the update.
   *
   * The category name must be unique among sibling categories (categories sharing the same parent). When updating the name, the system checks for duplicates within the same parent category scope. Top-level categories (no parent) must have unique names across all top-level categories. Empty names are rejected.
   *
   * The parent category assignment can be changed to reorganize the category hierarchy. However, the system enforces a strict one-level nesting constraint: a subcategory cannot have its own subcategories. When setting a new parent, the target parent must be a top-level category. Setting parentCategoryId to null converts a subcategory to a top-level category.
   *
   * The description field provides context about what products belong in the category and can be updated freely. All updates modify the updated_at timestamp to track when changes were made.
   *
   * Related operations: POST /admin/categories for creating new categories, DELETE /admin/categories/{categoryId} for removing categories, GET /categories for browsing the category hierarchy.
   *
   * @param connection
   * @param categoryId Target category's UUID identifier
   * @param body Update information for the category with optional fields for partial updates
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the shopping_mall_categories table to find the category by categoryId. Verify the requesting user has admin or superAdmin role; reject with 403 Forbidden if not. Validate that the category exists and is not soft-deleted.
   *
   * For name updates: Check uniqueness among sibling categories (categories with the same parentCategoryId). If the new name duplicates an existing sibling's name, reject with 400 Bad Request.
   *
   * For parentCategoryId changes: Verify the new parent exists and is not a subcategory itself (enforce one-level nesting). If attempting to set a subcategory as parent, reject with 400 Bad Request. If parentCategoryId is set to null, the category becomes a top-level category.
   *
   * Validate that name is not empty if provided. Update the category fields (name, description, parent_category_id) and set updated_at to current timestamp. Return the updated category entity.
   *
   * Edge cases: If updating parentCategoryId, ensure no circular reference is created. Cascade delete behavior is handled by database constraints if parent is deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCategory.IUpdate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await putShoppingMallAdminCategoriesCategoryId({
        admin,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
