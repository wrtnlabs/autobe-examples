import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallSellerProfile } from "../../../../api/structures/IShoppingMallSellerProfile";
import { getShoppingMallSellersSellerIdProfile } from "../../../../providers/getShoppingMallSellersSellerIdProfile";
import { putShoppingMallSellersProfile } from "../../../../providers/putShoppingMallSellersProfile";

@Controller("/shoppingMall/sellers")
export class ShoppingmallSellersProfileController {
  /**
   * Retrieve a seller's shop profile information including shop name, description, and logo image.
   *
   * This operation provides public access to seller profile details that customers view when browsing the seller's shop. The profile includes the shop name displayed to customers, a description providing business details, and a logo image URL for brand identification.
   *
   * The seller profile is linked to the seller account through a one-to-one relationship. Profile information is visible to all users including customers, administrators, and the seller themselves. Every edit to the seller profile creates an immutable snapshot for audit trail and dispute resolution.
   *
   * Returns 404 if the seller does not exist or if the seller's profile has been deleted.
   *
   * @param connection
   * @param sellerId Seller account identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_seller_profiles table by seller_id foreign key.
   *
   * Join with shopping_mall_sellers to verify seller exists and is not soft-deleted.
   *
   * Return the complete profile entity including shop_name, description, logo_image_uri, created_at, and updated_at.
   *
   * Handle edge cases:
   * - Seller not found: return 404
   * - Profile deleted (deleted_at is not null): return 404
   * - Seller account deleted: return 404
   *
   * No authorization check required - seller profiles are publicly visible to all users including guests.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId/profile")
  public async at(
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerProfile> {
    try {
      return await getShoppingMallSellersSellerIdProfile({
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated seller's shop profile information.
   *
   * This operation allows sellers to modify their shop name, shop description, and logo image URI. All profile fields are optional in the update request - only provided fields will be modified. The shop name is displayed to customers throughout the platform, the description provides business details, and the logo image serves as brand identification.
   *
   * Every successful update creates an immutable snapshot in shopping_mall_seller_profile_snapshots that preserves the previous state for audit trail and dispute resolution. Sellers can view their own snapshot history, and administrators can view snapshots of any seller profile.
   *
   * The operation validates that the seller has an approved approval request status. Sellers with pending or rejected approval status cannot modify their profile. All input fields are validated for length and format constraints.
   *
   * @param connection
   * @param body Seller profile update fields - all optional, only provided fields will be updated
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Update the shopping_mall_seller_profiles record for the authenticated seller.
   *
   * 1. Extract seller_id from JWT authentication token
   * 2. Query shopping_mall_seller_profiles WHERE seller_id = {authenticated_seller_id} AND deleted_at IS NULL
   * 3. Validate input fields:
   *    - shop_name: if provided, must be 1-200 characters
   *    - description: if provided, must be 0-2000 characters
   *    - logo_image_uri: if provided, must be valid URI format, max 80000 characters
   * 4. Check seller approval status via shopping_mall_seller_approval_requests - reject if not approved
   * 5. Before updating, create snapshot record in shopping_mall_seller_profile_snapshots with previous values
   * 6. Update the profile with new values, set updated_at to current timestamp
   * 7. Return the complete updated profile entity
   *
   * Edge cases:
   * - Seller not found: return 404
   * - Seller not approved: return 403
   * - Invalid URI format: return 400
   * - Concurrent modification: use optimistic locking with updated_at
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put("profile")
  public async update(
    @TypedBody()
    body: IShoppingMallSellerProfile.IUpdate,
  ): Promise<IShoppingMallSellerProfile> {
    try {
      return await putShoppingMallSellersProfile({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
