import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCategory } from "../../../api/structures/IPageIShoppingMallCategory";
import { IShoppingMallCategory } from "../../../api/structures/IShoppingMallCategory";
import { getShoppingMallCategoriesCategoryId } from "../../../providers/getShoppingMallCategoriesCategoryId";
import { patchShoppingMallCategories } from "../../../providers/patchShoppingMallCategories";

@Controller("/shoppingMall/categories")
export class ShoppingmallCategoriesController {
  /**
   * Retrieve a paginated list of categories with optional filtering and search capabilities.
   *
   * This endpoint returns all categories in the system, supporting filtering by parent category to retrieve subcategories, text search by category name, and pagination for large result sets. Categories are organized in a two-tier hierarchy where top-level categories have no parent and subcategories belong to exactly one parent category.
   *
   * Customers can browse all categories to explore products. Administrators use this endpoint to manage the category catalog. When viewing a parent category, customers see all products in that category and its subcategories. Subcategories cannot have their own subcategories, enforcing one level of nesting only.
   *
   * @param connection
   * @param body Search criteria including parent category ID filter for subcategory retrieval, text search for category name matching, and pagination parameters for result set navigation.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query shopping_mall_categories table with
     *   pagination support. Apply filters based on request criteria: parentId
     *   for subcategory filtering, search term for name matching using LIKE
     *   operator. Sort by display order or creation date. Join with product
     *   count aggregation if requested. Return cursor-based or offset
     *   pagination with category summary objects including id, name,
     *   description, parentId, and product count. Handle empty result sets
     *   gracefully.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallCategory.IRequest,
  ): Promise<IPageIShoppingMallCategory.ISummary> {
    try {
      return await patchShoppingMallCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific category by its unique identifier.
   *
   * This endpoint returns the complete category record including the category name, description, parent category reference (if this is a subcategory), and timestamps. Customers can use this to view category details when browsing the product catalog. Administrators can use this to view category information before editing or managing the category.
   *
   * The category hierarchy is limited to one level of nesting. If the parent_id field is populated, this category is a subcategory of the referenced parent category. If parent_id is null, this is a top-level category. Products assigned to this category will be visible when customers browse this category or its parent category (if applicable).
   *
   * @param connection
   * @param categoryId Unique identifier of the category to retrieve (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the shopping_mall_categories table by the
     *   provided categoryId UUID parameter.
   *
   * Retrieve the complete category record including: id, parent_id, name, description, created_at, updated_at, deleted_at.
   *
   * If parent_id is not null, optionally join with the parent category to include parent category details in the response for client convenience.
   *
   * Return 404 error if the category does not exist or has been soft deleted (deleted_at is not null).
   *
   * No authentication required for basic category viewing - accessible to guest, customer, seller, and admin actors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async at(
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCategory> {
    try {
      return await getShoppingMallCategoriesCategoryId({
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
