import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCategory } from "../../../api/structures/IPageIShoppingMallCategory";
import { IShoppingMallCategory } from "../../../api/structures/IShoppingMallCategory";
import { getShoppingMallCategoriesCategoryId } from "../../../providers/getShoppingMallCategoriesCategoryId";
import { patchShoppingMallCategories } from "../../../providers/patchShoppingMallCategories";

@Controller("/shoppingMall/categories")
export class ShoppingmallCategoriesController {
  /**
   * Retrieve a filtered and paginated list of product categories from the shopping mall catalog.
   *
   * This operation provides comprehensive search capabilities for browsing the category hierarchy. Users can filter categories by parent category to retrieve subcategories, search by category name or description using partial text matching, and apply standard pagination controls. The endpoint supports sorting by creation date, name, or update date.
   *
   * All platform actors including customers, sellers, administrators, and super administrators can access this endpoint. Category browsing is a fundamental feature for product discovery and navigation. Customers use categories to find products, sellers reference categories when creating products, and administrators manage the category structure.
   *
   * The response includes category summary information optimized for list displays, containing essential fields like id, name, description, and parent category reference. For detailed category information including nested subcategories, use the GET /categories/{categoryId} endpoint.
   *
   * Categories follow a one-level nesting hierarchy where subcategories can have a parent category but cannot have their own subcategories. Category names are unique within the same parent level, ensuring consistent organization across the platform.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for category listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_categories table with pagination and filtering support.
   *
   * Apply search filters on name (partial match), description (partial match), and parent_category_id (exact match for subcategory retrieval). Support sorting by created_at, updated_at, or name in ascending or descending order.
   *
   * Implement cursor-based or offset pagination with configurable page size. Filter out soft-deleted categories (deleted_at IS NULL) by default unless explicitly requested.
   *
   * Join with parent category data when parent_category_id is not null to include parent category name in response. For subcategory queries, include sibling count or other metadata if needed for UI display.
   *
   * Ensure query performance with indexes on parent_category_id, created_at, and name fields. Handle edge cases: empty result sets, invalid parent category references, and pagination beyond available data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallCategory.IRequest,
  ): Promise<IPageIShoppingMallCategory.ISummary> {
    try {
      return await patchShoppingMallCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific product category by its unique identifier.
   *
   * This operation returns complete category information including the category's name, description, and hierarchical position within the category structure. If the category has a parent category, the response includes parent category details to indicate its place in the hierarchy.
   *
   * The response also includes all direct subcategories of the requested category, enabling clients to display the category tree for navigation purposes. Categories support one level of nesting only, so subcategories will not have their own subcategories.
   *
   * Categories are managed exclusively by administrators, but this endpoint is publicly accessible to all users including guests, customers, sellers, and administrators. This allows customers to browse the category structure when searching for products.
   *
   * Only active (non-deleted) categories are returned. Soft-deleted categories are excluded from the response. Related operations include PATCH /categories for listing all categories with pagination and filtering, POST /admin/categories for creating new categories (administrator only), PUT /admin/categories/{categoryId} for updating category details (administrator only), and DELETE /admin/categories/{categoryId} for removing categories (administrator only).
   *
   * @param connection
   * @param categoryId Unique identifier of the target category to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_categories table by primary key categoryId.
   *
   * Retrieve the category record including id, name, description, and parentCategoryId fields.
   *
   * If parentCategoryId exists, include parent category information (id, name) to show hierarchy position.
   *
   * Query all direct subcategories where parentCategoryId equals the requested categoryId.
   *
   * Return category with nested subcategories array containing id, name, description for each child.
   *
   * Handle 404 error when categoryId does not exist in the database.
   *
   * No authentication required - categories are publicly accessible to all users including guests.
   *
   * No soft delete filter needed as categories table does not have deleted_at column based on schema analysis.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async at(
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCategory> {
    try {
      return await getShoppingMallCategoriesCategoryId({
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
