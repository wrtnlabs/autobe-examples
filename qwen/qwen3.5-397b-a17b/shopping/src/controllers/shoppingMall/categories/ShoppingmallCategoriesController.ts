import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCategory } from "../../../api/structures/IPageIShoppingMallCategory";
import { IShoppingMallCategory } from "../../../api/structures/IShoppingMallCategory";
import { getShoppingMallCategoriesCategoryId } from "../../../providers/getShoppingMallCategoriesCategoryId";
import { getShoppingMallCategoriesTree } from "../../../providers/getShoppingMallCategoriesTree";
import { patchShoppingMallCategories } from "../../../providers/patchShoppingMallCategories";

@Controller("/shoppingMall/categories")
export class ShoppingmallCategoriesController {
  /**
   * Retrieve a filtered and paginated list of product categories.
   *
   * This operation provides category browsing capabilities for customers and category management views for administrators. Supports filtering by parent category to retrieve subcategories, text search by category name, and configurable pagination.
   *
   * Categories are organized in a one-level hierarchy: top-level categories have no parent, while subcategories reference a parent category. When viewing a category, customers see all products assigned to that category and its subcategories.
   *
   * Only administrators can create, edit, or delete categories. All authenticated users can browse the category list for product discovery.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for category listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_categories table with pagination and filtering support.
   *
   * Apply filters:
   * - parent_id: filter by parent category (null for top-level categories, UUID for subcategories)
   * - search: partial match on category name
   * - deleted_at: exclude soft-deleted categories for non-admin users
   *
   * Support cursor-based pagination with configurable page size and sorting options (created_at, name, updated_at).
   *
   * Return category summaries including id, name, description, parent_id, and hasChildren flag for UI tree rendering.
   *
   * Authorization: Allow customer and administrator roles. Exclude soft-deleted categories from customer results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallCategory.IRequest,
  ): Promise<IPageIShoppingMallCategory.ISummary> {
    try {
      return await patchShoppingMallCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific category by its unique identifier.
   *
   * This operation returns the complete category information including the category name, description, parent category reference (if it's a subcategory), and timestamps. Customers use this endpoint to view category details when navigating the product catalog. Administrators use it when managing the category structure.
   *
   * The response includes the parent_id field which indicates whether this is a top-level category (null) or a subcategory (references parent category ID). This enables clients to reconstruct the category hierarchy for navigation purposes.
   *
   * Note: Soft-deleted categories (deleted_at is not null) are not accessible through this endpoint. To access soft-deleted categories for recovery purposes, administrators should use the category management endpoints.
   *
   * @param connection
   * @param categoryId Category unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_categories table by the provided categoryId UUID parameter.
   *
   * Return the full category entity including id, parent_id, name, description, created_at, updated_at, and deleted_at fields.
   *
   * If category not found, return 404 error.
   *
   * If category is soft-deleted (deleted_at is not null), return 404 for non-administrator users. Administrators may access soft-deleted categories for management purposes.
   *
   * No joins required - single table query.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async at(
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCategory> {
    try {
      return await getShoppingMallCategoriesCategoryId({
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete category hierarchy as a tree structure for browsing and navigation.
   *
   * This operation returns all active categories organized in a two-level hierarchical structure. Top-level categories are returned with their associated subcategories nested within. Each category includes its identifier, name, and description for display purposes.
   *
   * The tree structure enables customers to navigate the product classification system efficiently. Parent categories appear at the root level with their subcategories nested as children arrays. Only active categories (not soft-deleted) are included in the response.
   *
   * This endpoint is accessible to all authenticated users for product discovery and browsing. The hierarchical format matches the UI requirements for category navigation components.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_categories table for all active categories (deleted_at IS NULL).
   *
   * Build hierarchical tree structure:
   * 1. Fetch all top-level categories (parent_id IS NULL)
   * 2. For each top-level category, fetch its direct subcategories (parent_id = category.id)
   * 3. Nest subcategories within parent's children array
   * 4. Return only two levels (subcategories cannot have their own children per business rules)
   *
   * Include fields: id, parent_id, name, description for each category.
   * Sort categories by created_at or name for consistent ordering.
   * Ensure soft-deleted categories (deleted_at NOT NULL) are excluded from results.
   *
   * No authentication required beyond basic user session - accessible to customers and administrators.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("tree")
  public async tree(): Promise<IShoppingMallCategory.ITree> {
    try {
      return await getShoppingMallCategoriesTree();
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
