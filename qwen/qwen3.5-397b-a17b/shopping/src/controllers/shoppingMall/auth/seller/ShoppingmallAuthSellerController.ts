import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { postShoppingMallAuthSellerJoin } from "../../../../providers/postShoppingMallAuthSellerJoin";
import { postShoppingMallAuthSellerLogin } from "../../../../providers/postShoppingMallAuthSellerLogin";
import { postShoppingMallAuthSellerRefresh } from "../../../../providers/postShoppingMallAuthSellerRefresh";

@Controller("/shoppingMall/auth/seller")
export class ShoppingmallAuthSellerController {
  /**
   * Register a new seller account on the shopping mall platform. This operation creates a seller identity with email and password authentication credentials in the shopping_mall_sellers table.
   *
   * Upon successful registration, the system generates an email verification token stored in shopping_mall_seller_email_verifications and sends a verification email to the provided address. The seller must verify their email before the account becomes fully active.
   *
   * The registration returns JWT access and refresh tokens for immediate authentication. However, the seller account requires administrator approval through the seller approval workflow (shopping_mall_seller_approval_requests) before gaining privileges to list products and manage inventory.
   *
   * Email addresses must be unique across all seller accounts. Passwords are hashed using bcrypt before storage. The operation validates email format, password strength requirements, and checks for existing accounts.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration credentials including email for authentication and communication, and password for account security.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Register a new seller account with email and password. Creates a record in shopping_mall_sellers table with bcrypt hashed password. Generates an email verification token in shopping_mall_seller_email_verifications table and sends verification email. Returns JWT access and refresh tokens upon successful registration. The seller account is created but requires administrator approval via shopping_mall_seller_approval_requests before gaining selling privileges. Email must be unique across all sellers. Password must meet security requirements (minimum length, complexity). Implementation: 1) Validate email format and uniqueness, 2) Validate password strength, 3) Hash password with bcrypt, 4) Insert seller record, 5) Generate verification token with expiration, 6) Insert email verification record, 7) Generate JWT tokens, 8) Create session record in shopping_mall_seller_sessions, 9) Return tokens with seller ID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.IJoin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a seller account using email and password credentials. This operation validates the provided credentials against the shopping_mall_sellers table.
   *
   * The system verifies the password by comparing it with the stored bcrypt password_hash. Upon successful authentication, JWT access and refresh tokens are generated and returned to the client.
   *
   * A session record is created in shopping_mall_seller_sessions table containing the seller ID, client IP address, page URL (href), referrer URL, creation timestamp, and expiration timestamp. This session tracking enables security monitoring and session management.
   *
   * The operation returns an error if the email does not exist, the password is incorrect, or the account has been soft deleted. Successful login provides immediate access to seller dashboard and management features, though product listing privileges require administrator approval status.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller authentication credentials including registered email address and password for identity verification.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Authenticate seller with email and password credentials. Validates credentials against shopping_mall_sellers table by comparing provided password with stored bcrypt password_hash. On successful authentication, creates a session record in shopping_mall_seller_sessions table with IP address, href, referrer, and expiration timestamp. Returns JWT access and refresh tokens. Implementation: 1) Find seller by email, 2) Verify password against password_hash using bcrypt comparison, 3) Check account is not soft deleted (deleted_at is null), 4) Generate JWT access and refresh tokens, 5) Create session record with client metadata, 6) Return tokens with seller ID and session expiration.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.ILogin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens using a valid refresh token. This operation extends the seller's authenticated session without requiring re-entry of credentials.
   *
   * The system validates the provided refresh token against active sessions in the shopping_mall_seller_sessions table. The session must not have expired (expired_at timestamp must be in the future) and the seller account must remain active (deleted_at must be null).
   *
   * Upon successful validation, a new JWT access token and refresh token pair is generated. The session record's expiration timestamp is updated to extend the session lifetime.
   *
   * This operation enables seamless continued access to seller features without interrupting the user experience. Refresh tokens should be rotated on each use for enhanced security. The operation returns an error if the refresh token is invalid, expired, or the associated account has been deleted.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new authentication tokens. The token must be valid and associated with an active seller session.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Refresh JWT access token using a valid refresh token. Validates the refresh token against active sessions in shopping_mall_seller_sessions table. Checks session has not expired (expired_at is in the future) and seller account is still active (deleted_at is null). Generates new access and refresh token pair. Implementation: 1) Validate refresh token signature and extract seller ID, 2) Query shopping_mall_seller_sessions for matching session, 3) Verify session expired_at is in the future, 4) Verify seller deleted_at is null, 5) Generate new JWT access and refresh tokens, 6) Update session expired_at timestamp, 7) Return new token pair.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallSeller.IRefresh,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
