import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { postShoppingMallAuthSellerJoin } from "../../../../providers/postShoppingMallAuthSellerJoin";
import { postShoppingMallAuthSellerLogin } from "../../../../providers/postShoppingMallAuthSellerLogin";
import { postShoppingMallAuthSellerRefresh } from "../../../../providers/postShoppingMallAuthSellerRefresh";

@Controller("/shoppingMall/auth/seller")
export class ShoppingmallAuthSellerController {
  /**
   * Register a new seller account on the platform.
   *
   * Creates a seller account with the provided email and password. The account starts with approval_status 'pending' and requires administrator approval before the seller can list products or process orders. An email verification token is generated and sent to the provided email address.
   *
   * Upon successful registration, the operation returns JWT access and refresh tokens for immediate authentication. The seller can browse the platform but cannot perform seller-specific operations until their approval_status changes to 'approved'.
   *
   * Email must be unique across all seller accounts. Password is hashed using bcrypt before storage. If a seller application was previously rejected, they can register again with the same email after their old account is soft deleted.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration credentials and profile information.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Register a new seller account with email and
     *   password. Create shopping_mall_sellers record with
     *   approval_status='pending'. Generate email verification token in
     *   shopping_mall_seller_email_verifications table. Send verification
     *   email. Return JWT access and refresh tokens. Seller cannot sell until
     *   admin approves (approval_status='approved').
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.IJoin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a seller account with email and password.
   *
   * Validates the provided credentials against the stored password hash in the shopping_mall_sellers table. The seller account must be active (deleted_at IS NULL) and have approval_status 'approved' to successfully authenticate.
   *
   * Upon successful authentication, a new session record is created in shopping_mall_seller_sessions with client metadata (IP address, page URL, referrer) for security auditing. The session has an expiration timestamp typically set to 7-30 days.
   *
   * Returns JWT access and refresh tokens. The access token is used for authenticated API requests, while the refresh token can be used to obtain new access tokens via the refresh endpoint. Sellers with 'pending' or 'rejected' approval status cannot login and must wait for admin approval or re-apply.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login credentials.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Authenticate seller with email and password.
     *   Validate credentials against shopping_mall_sellers.password_hash. Check
     *   account is not soft deleted (deleted_at IS NULL). Verify
     *   approval_status is 'approved' - reject if 'pending' or 'rejected'.
     *   Create session record in shopping_mall_seller_sessions with IP, href,
     *   referrer, expired_at. Return JWT access and refresh tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.ILogin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens using a valid refresh token.
   *
   * Validates the provided refresh token against existing sessions in the shopping_mall_seller_sessions table. The session must not be expired (expired_at must be in the future) and the associated seller account must still be active (deleted_at IS NULL) and approved (approval_status='approved').
   *
   * Generates a new JWT access token and returns it along with the refresh token. This operation allows sellers to maintain authenticated sessions without re-entering credentials. If refresh token rotation is enabled, a new refresh token is also issued and the old one is invalidated.
   *
   * This endpoint is called automatically by client applications when the access token is about to expire. Sellers whose accounts have been suspended, deleted, or had their approval revoked will receive an authentication error.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access token.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Refresh JWT access token using valid refresh
     *   token. Validate refresh token against shopping_mall_seller_sessions.
     *   Check session is not expired (expired_at > now). Verify seller account
     *   is still active and approved. Generate new access token and optionally
     *   new refresh token. Update session expired_at if rotating refresh
     *   tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallSeller.IRefresh,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
