import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { postShoppingMallAuthSellerJoin } from "../../../../providers/postShoppingMallAuthSellerJoin";
import { postShoppingMallAuthSellerLogin } from "../../../../providers/postShoppingMallAuthSellerLogin";
import { postShoppingMallAuthSellerRefresh } from "../../../../providers/postShoppingMallAuthSellerRefresh";

@Controller("/shoppingMall/auth/seller")
export class ShoppingmallAuthSellerController {
  /**
   * Register a new seller account with email, password, and shop information.
   *
   * This endpoint creates a new seller account in the shopping mall platform. The seller registration requires email, password, and basic shop information including shop name and description. Upon successful registration, the seller account is created with approval_status set to 'PENDING', requiring administrator review before the seller can list products and manage inventory.
   *
   * The registration process stores the seller's credentials securely with bcrypt password hashing. An email verification token is automatically generated and sent to the provided email address through the shopping_mall_seller_email_verifications table. The seller must verify their email before the account becomes fully active, though admin approval is still required separately.
   *
   * Authentication considerations include email uniqueness validation against existing sellers and admins, password strength requirements, and prevention of duplicate shop names. The response includes JWT access and refresh tokens, allowing immediate authenticated access, though certain seller operations remain restricted until admin approval is granted.
   *
   * Related operations include POST /auth/seller/login for returning sellers, and sellers can check their approval status through the dashboard or profile endpoints after registration.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration information including credentials and shop details.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Service layer creates seller account transactionally: (1) Validate email uniqueness across sellers and admins, (2) Hash password using bcrypt, (3) Create shopping_mall_sellers record with approval_status='PENDING', (4) Create email verification token in shopping_mall_seller_email_verifications, (5) Generate JWT access and refresh tokens, (6) Create session record in shopping_mall_seller_sessions with IP/href/referrer metadata, (7) Return IShoppingMallSeller.IAuthorized with tokens and seller info. Transaction rolls back on any failure. Email verification is sent asynchronously.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.IJoin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate seller with email and password credentials.
   *
   * This endpoint validates seller credentials and establishes an authenticated session. The seller provides their registered email address and password, which are verified against the shopping_mall_sellers table. Upon successful authentication, the system generates JWT access and refresh tokens for subsequent API requests.
   *
   * The login process performs several validation checks: verifying the email exists in the sellers table, comparing the provided password against the stored bcrypt password_hash, checking that the account is not soft-deleted (deleted_at is null), and validating the account is not suspended. Note that sellers with approval_status='PENDING' or 'REJECTED' can still login to check their status, but cannot perform seller operations requiring approval.
   *
   * Session tracking is implemented through the shopping_mall_seller_sessions table, which records each login with connection metadata including IP address, request URL (href), and referrer. This creates an audit trail for security monitoring. The session record includes an expiration timestamp (expired_at) that enforces session lifetime limits.
   *
   * The response contains JWT tokens in the IShoppingMallSeller.IAuthorized format. The access token is used for authenticating subsequent API requests, while the refresh token enables obtaining new access tokens without re-authentication. Related operations include POST /auth/seller/join for new registration and POST /auth/seller/refresh for token renewal.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login credentials with email and password.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Service layer authentication flow: (1) Query shopping_mall_sellers by email, (2) Verify account not deleted (deleted_at is null), (3) Compare password using bcrypt against password_hash, (4) Check account not suspended, (5) Generate JWT access token (short-lived) and refresh token (long-lived), (6) Create session record in shopping_mall_seller_sessions with ip, href, referrer, expired_at, (7) Return IShoppingMallSeller.IAuthorized with tokens, seller id, email, shop_name, approval_status. Failed authentication returns 401 without revealing whether email or password was incorrect.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.ILogin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT access token using a valid refresh token.
   *
   * This endpoint enables sellers to obtain new access tokens without re-authenticating with credentials. When the short-lived access token expires, the seller can present their refresh token to this endpoint to receive a new access token (and optionally a new refresh token through token rotation).
   *
   * The refresh token validation process verifies the token against active sessions in the shopping_mall_seller_sessions table. The system checks that the session has not expired (expired_at is in the future), the seller account still exists and is not soft-deleted, and the account has not been suspended since the session was created. If any of these conditions fail, the refresh request is rejected and the seller must re-authenticate.
   *
   * Token rotation can be implemented for enhanced security: each refresh operation invalidates the old refresh token and issues a new one. This limits the window of opportunity if a refresh token is compromised. The session record is updated with new expiration timestamps during the refresh operation.
   *
   * This endpoint requires no authentication decorator since it operates on the refresh token itself rather than an access token. The refresh token is typically sent in the request body or as a secure HTTP-only cookie. Related operations include POST /auth/seller/login for initial authentication and the general pattern of including access tokens in Authorization headers for protected endpoints.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access token.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Service layer token refresh: (1) Extract refresh token from request body, (2) Query shopping_mall_seller_sessions to find matching session (token stored or derived), (3) Verify session not expired (expired_at > now), (4) Verify seller account exists and not deleted/suspended, (5) Generate new JWT access token with updated claims, (6) Optionally generate new refresh token and update session, (7) Return IShoppingMallSeller.IAuthorized with new tokens. Invalid or expired tokens return 401. Session cleanup removes expired sessions periodically.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallSeller.IRefresh,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
