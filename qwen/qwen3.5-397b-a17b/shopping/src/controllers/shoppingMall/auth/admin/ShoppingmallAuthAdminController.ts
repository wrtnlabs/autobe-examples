import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallAdmin } from "../../../../api/structures/IShoppingMallAdmin";
import { postShoppingMallAuthAdminJoin } from "../../../../providers/postShoppingMallAuthAdminJoin";
import { postShoppingMallAuthAdminLogin } from "../../../../providers/postShoppingMallAuthAdminLogin";
import { postShoppingMallAuthAdminRefresh } from "../../../../providers/postShoppingMallAuthAdminRefresh";

@Controller("/shoppingMall/auth/admin")
export class ShoppingmallAuthAdminController {
  /**
   * Creates an administrator account when a promotion request is approved by a super administrator.
   *
   * This operation is invoked by the system after a super administrator approves an admin promotion request. It creates the administrator account record in shopping_mall_admins with the provided email, password, and grade level. The email must be unique across all administrator accounts.
   *
   * The operation validates that the associated promotion request exists and is in approved status. It generates a bcrypt hash for the password and establishes the link to the underlying member account. Upon successful creation, JWT access and refresh tokens are generated and returned for immediate authentication.
   *
   * Authentication is not required for this operation as it is triggered by the approval workflow. The operation returns IShoppingMallAdmin.IAuthorized containing the access token, refresh token, and expiration time.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator account creation details from approved promotion request.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Create administrator account through approved
     *   promotion workflow. When a member or seller's admin promotion request
     *   is approved by a super administrator, this operation creates the admin
     *   account record. Validate email uniqueness across all admin accounts.
     *   Generate bcrypt password hash from provided password. Set grade based
     *   on promotion request type (regular or super). Link to existing member
     *   account via member_id. Return JWT access and refresh tokens for
     *   immediate authentication. Reject if email already exists in admins
     *   table or if promotion request is not in approved state.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.IJoin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates administrator credentials and establishes a login session.
   *
   * This operation validates the administrator's email and password against the shopping_mall_admins table. The email must exist and the password hash must match the provided password using bcrypt verification. The operation also checks that the administrator account is not banned (banned_at is null) - banned administrators cannot log in.
   *
   * Upon successful authentication, a new session record is created in shopping_mall_admin_sessions with JWT access and refresh tokens. The session captures client information including IP address, href, and referrer for security auditing. The expired_at timestamp is set based on the session duration policy.
   *
   * The operation returns IShoppingMallAdmin.IAuthorized containing the access token for API authentication, refresh token for token renewal, and the expiration timestamp. Failed authentication attempts return 401 Unauthorized.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator login credentials.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Authenticate administrator credentials and create
     *   JWT session. Validate email exists in shopping_mall_admins table.
     *   Verify password hash matches provided password using bcrypt comparison.
     *   Check banned_at is null - reject login if administrator is banned.
     *   Create new session record in shopping_mall_admin_sessions with access
     *   token, refresh token, client IP, and timestamps. Set expired_at based
     *   on session duration policy. Return JWT tokens and expiration time.
     *   Reject with 401 if email not found, password mismatch, or account is
     *   banned.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.ILogin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews administrator authentication tokens using a valid refresh token.
   *
   * This operation validates the provided refresh token against the shopping_mall_admin_sessions table. The refresh token must exist in an active session record and the session's expired_at timestamp must be in the future. The operation also verifies that the associated administrator account is not banned.
   *
   * Upon successful validation, new JWT access and refresh tokens are generated. The refresh token may be rotated for enhanced security (invalidating the old token). The session record is updated with the new tokens.
   *
   * The operation returns IShoppingMallAdmin.IAuthorized containing the new access token, refresh token, and expiration timestamp. This allows administrators to maintain authenticated sessions without re-entering credentials. Failed token validation returns 401 Unauthorized.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access tokens.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Refresh JWT access token using valid refresh
     *   token. Validate refresh token exists in shopping_mall_admin_sessions
     *   table and matches the provided token. Check session expired_at is in
     *   the future - reject if session has expired. Verify the associated
     *   administrator account is not banned. Generate new access token and
     *   optionally rotate refresh token. Update session record with new tokens.
     *   Return new JWT tokens and expiration time. Reject with 401 if refresh
     *   token is invalid, session is expired, or administrator is banned.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallAdmin.IRefresh,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
