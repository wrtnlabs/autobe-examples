import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";
import { postShoppingMallAuthCustomerJoin } from "../../../../providers/postShoppingMallAuthCustomerJoin";
import { postShoppingMallAuthCustomerLogin } from "../../../../providers/postShoppingMallAuthCustomerLogin";
import { postShoppingMallAuthCustomerRefresh } from "../../../../providers/postShoppingMallAuthCustomerRefresh";

@Controller("/shoppingMall/auth/customer")
export class ShoppingmallAuthCustomerController {
  /**
   * Registers a new customer account with email and password credentials.
   *
   * This endpoint creates a new customer record in the shopping_mall_customers table with the provided email address and bcrypt-hashed password. The email must be unique across all customer accounts. Upon successful registration, the system automatically authenticates the customer by generating JWT access and refresh tokens.
   *
   * The registration process includes creating a session record in the shopping_mall_customer_sessions table to track the login session with connection metadata including IP address, initial page URL, and referrer. This enables security auditing and session management.
   *
   * The response includes the customer's authorized status with access token, refresh token, and expiration information. The customer can immediately use these tokens to access protected endpoints requiring customer authentication.
   *
   * Related operations include POST /auth/customer/login for existing customers and POST /auth/customer/refresh for token renewal.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer registration credentials including email and password.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Handles customer registration by creating a new customer account with email and password. The service validates email uniqueness against the shopping_mall_customers table, hashes the password using bcrypt, and creates the customer record. Upon successful registration, generates JWT access and refresh tokens and creates a session record in shopping_mall_customer_sessions with connection metadata (IP, href, referrer). Returns the authorized customer information including tokens for immediate authentication.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.IJoin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an existing customer with email and password credentials.
   *
   * This endpoint validates the provided email and password against the shopping_mall_customers table. The service retrieves the customer record by email address and verifies the bcrypt-hashed password. The authentication fails if the email does not exist, the password is incorrect, or the account has been soft deleted (deleted_at is not null).
   *
   * Upon successful authentication, the system generates JWT access and refresh tokens and creates a new session record in the shopping_mall_customer_sessions table. The session includes connection metadata such as IP address, initial page URL, and referrer for security auditing purposes.
   *
   * The response contains the authorized customer information including the access token, refresh token, and expiration timestamp. Customers use these tokens to access protected endpoints requiring customer authentication.
   *
   * Related operations include POST /auth/customer/join for new registration and POST /auth/customer/refresh for token renewal without re-authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer login credentials with email and password.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Authenticates customer credentials by validating email and password against the shopping_mall_customers table. The service retrieves the customer record by email, verifies the bcrypt password hash, checks that the account is not soft deleted (deleted_at is null), and generates JWT access and refresh tokens. Creates a new session record in shopping_mall_customer_sessions with connection metadata. Returns authorized customer information with tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.ILogin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes JWT access token using a valid refresh token.
   *
   * This endpoint enables customers to obtain new access tokens without re-authenticating with credentials. The service validates the provided refresh token against active sessions in the shopping_mall_customer_sessions table, ensuring the session has not expired based on the expired_at timestamp.
   *
   * The refresh operation also verifies that the associated customer account still exists and has not been soft deleted (deleted_at is null). If the customer account has been deleted or suspended, the refresh request is rejected.
   *
   * Upon successful validation, the system generates new access and refresh tokens and creates a new session record in shopping_mall_customer_sessions for token rotation. This approach maintains security by limiting token lifetime while providing seamless authentication continuity.
   *
   * The response includes the updated authorized customer information with new access token, refresh token, and expiration timestamp. This operation is essential for maintaining long-lived user sessions without requiring repeated credential entry.
   *
   * Related operations include POST /auth/customer/login for initial authentication and POST /auth/customer/join for new customer registration.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access tokens.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Refreshes JWT access token using a valid refresh token. The service validates the refresh token against active sessions in shopping_mall_customer_sessions, checks the session has not expired (expired_at), verifies the associated customer account exists and is not soft deleted, then generates new access and refresh tokens. Creates a new session record for token rotation. Returns updated authorized customer information with new tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallCustomer.IRefresh,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
