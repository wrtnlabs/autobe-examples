import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";
import { postShoppingMallAuthCustomerJoin } from "../../../../providers/postShoppingMallAuthCustomerJoin";
import { postShoppingMallAuthCustomerLogin } from "../../../../providers/postShoppingMallAuthCustomerLogin";
import { postShoppingMallAuthCustomerRefresh } from "../../../../providers/postShoppingMallAuthCustomerRefresh";

@Controller("/shoppingMall/auth/customer")
export class ShoppingmallAuthCustomerController {
  /**
   * Creates a new customer account in the shopping mall system. The endpoint accepts email and password credentials, validates that the email is not already registered, and ensures the password meets security requirements.
   *
   * Upon successful registration, the system creates a customer record in the shopping_mall_customers table with a bcrypt hashed password. An email verification token is automatically generated and stored in shopping_mall_customer_email_verifications table with an expiration timestamp. The customer receives JWT access and refresh tokens for immediate system access.
   *
   * The customer should verify their email address using the verifyEmail endpoint with the token sent to their email. Unverified accounts may have limited functionality depending on business rules.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer registration credentials including email and password for account creation.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Register new customer account with email and password. Validate email uniqueness and password strength. Create customer record with hashed password. Generate email verification token and send verification email. Return JWT tokens for immediate authentication. Email verification can be completed later via verifyEmail endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.IJoin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an existing customer using their email and password credentials. The endpoint validates the provided credentials against the shopping_mall_customers table, verifying the password hash matches and the account is active (not soft deleted).
   *
   * Upon successful authentication, the system generates a new JWT access token and refresh token pair. A session record is created in the shopping_mall_customer_sessions table, capturing the client's IP address, application URL, and referrer information along with the session expiration timestamp.
   *
   * The response includes the JWT tokens for API authentication and basic customer information. The access token should be included in the Authorization header for subsequent API requests. The refresh token is used to obtain new access tokens when the current one expires.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer login credentials with email and password for authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Authenticate customer with email and password. Validate credentials against shopping_mall_customers table. Verify account is not deleted. Generate JWT access and refresh tokens. Create session record in shopping_mall_customer_sessions with client information (ip, href, referrer) and expiration timestamp. Return tokens and customer info.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.ILogin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews the customer's authentication tokens using a valid refresh token. This endpoint allows customers to obtain new access tokens without re-entering their credentials when the current access token expires.
   *
   * The system validates the provided refresh token against the shopping_mall_customer_sessions table, ensuring the session exists and has not passed its expiration timestamp (expired_at). The customer account is also verified to be active and not soft deleted.
   *
   * Upon successful validation, a new JWT access token and refresh token pair is generated. The session record is updated with the new tokens and a fresh expiration timestamp. The old refresh token becomes invalid, implementing a rotating refresh token strategy for enhanced security.
   *
   * This operation enables seamless continued authentication for customers with valid sessions while maintaining security through token rotation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access token without re-authentication.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Refresh JWT access token using valid refresh token. Validate refresh token against shopping_mall_customer_sessions table. Check session is not expired (expired_at). Verify customer account is still active. Generate new access and refresh token pair. Update session record with new tokens and expiration. Return new tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallCustomer.IRefresh,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
