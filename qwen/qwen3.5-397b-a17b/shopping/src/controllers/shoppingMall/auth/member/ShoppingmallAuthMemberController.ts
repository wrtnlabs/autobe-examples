import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallMember } from "../../../../api/structures/IShoppingMallMember";
import { postShoppingMallAuthMemberJoin } from "../../../../providers/postShoppingMallAuthMemberJoin";
import { postShoppingMallAuthMemberLogin } from "../../../../providers/postShoppingMallAuthMemberLogin";
import { postShoppingMallAuthMemberRefresh } from "../../../../providers/postShoppingMallAuthMemberRefresh";

@Controller("/shoppingMall/auth/member")
export class ShoppingmallAuthMemberController {
  /**
   * Register a new customer account with email and password credentials.
   *
   * This operation creates a new member account in the shopping_mall_members table. The email must be unique across all existing member accounts. The password is hashed using bcrypt before storage for security.
   *
   * Upon successful registration, the system generates JWT access and refresh tokens and creates a session record in shopping_mall_member_sessions. The response includes both tokens for immediate authentication.
   *
   * Email verification is handled separately through the email verification flow. The account is created with 'active' status, allowing immediate login access.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials for new member account creation.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create new member account with email and password. Validate email uniqueness against shopping_mall_members table. Hash password using bcrypt before storing. Create member record with status 'active'. Generate JWT access and refresh tokens. Create session record in shopping_mall_member_sessions with client context (ip, href, referrer). Return tokens in IShoppingMallMember.IAuthorized response. Reject if email already exists (409 Conflict) or validation fails (400 Bad Request).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallMember.IJoin,
  ): Promise<IShoppingMallMember.IAuthorized> {
    try {
      return await postShoppingMallAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a registered customer with email and password credentials.
   *
   * This operation validates the provided email and password against the shopping_mall_members table. The password is verified using bcrypt hash comparison.
   *
   * Account status is checked: only 'active' accounts can login. Accounts with 'banned' status (administrator action) or 'deleted' status (soft-deleted) are rejected with 403 Forbidden.
   *
   * Upon successful authentication, the system generates new JWT access and refresh tokens and creates a session record in shopping_mall_member_sessions with client context information (IP, page URL, referrer) for security auditing.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials for member authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Authenticate member with email and password. Query shopping_mall_members by email. Verify password hash matches using bcrypt comparison. Check account status is 'active' (reject 'banned' or 'deleted' with 403 Forbidden). Generate new JWT access and refresh tokens. Create session record in shopping_mall_member_sessions with client context. Return tokens in IShoppingMallMember.IAuthorized response. Reject invalid credentials with 401 Unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallMember.ILogin,
  ): Promise<IShoppingMallMember.IAuthorized> {
    try {
      return await postShoppingMallAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens using a valid refresh token.
   *
   * This operation exchanges a valid refresh token for a new pair of access and refresh tokens. The refresh token is validated against the shopping_mall_member_sessions table.
   *
   * The session must not be expired (expired_at must be in the future). Invalid or expired refresh tokens are rejected with 401 Unauthorized.
   *
   * Upon successful validation, new JWT access and refresh tokens are generated and the session record is updated with the new tokens and extended expiration time. This allows clients to maintain authenticated sessions without requiring re-authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new authentication tokens.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Refresh JWT tokens using valid refresh token. Validate refresh token against shopping_mall_member_sessions table. Check session not expired (expired_at > current time). Generate new access and refresh token pair. Update session record with new tokens and extended expiration. Return new tokens in IShoppingMallMember.IAuthorized response. Reject invalid or expired refresh token with 401 Unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallMember.IRefresh,
  ): Promise<IShoppingMallMember.IAuthorized> {
    try {
      return await postShoppingMallAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
