import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallGuest } from "../../../../api/structures/IShoppingMallGuest";
import { postShoppingMallAuthGuestJoin } from "../../../../providers/postShoppingMallAuthGuestJoin";
import { postShoppingMallAuthGuestRefresh } from "../../../../providers/postShoppingMallAuthGuestRefresh";

@Controller("/shoppingMall/auth/guest")
export class ShoppingmallAuthGuestController {
  /**
   * Register a new guest user or retrieve existing guest session using device fingerprint.
   *
   * Creates a temporary guest account identified by device fingerprint for unauthenticated browsing. If a guest with the same device fingerprint already exists, returns the existing guest's session tokens. New guests receive a UUID and short-lived JWT tokens for platform access.
   *
   * The device_fingerprint uniquely identifies the guest's device and enables session persistence across page views. Guest sessions have shorter expiration times (typically 24 hours) compared to registered users for security purposes.
   *
   * Request must include device_fingerprint string. Optional ip, href, and referrer fields capture connection metadata for security monitoring and analytics. Response includes guest id, access token, refresh token, and expiration timestamp.
   *
   * Guest accounts can be upgraded to full customer accounts through the registration process, preserving cart and wishlist data.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest registration request with device fingerprint and optional connection metadata.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Create a guest account using device fingerprint
     *   and generate JWT session tokens. Validate device_fingerprint is
     *   provided and not empty. Check if guest with same device_fingerprint
     *   already exists - if yes, return existing guest tokens. If new, create
     *   shopping_mall_guests record with generated UUID and current timestamps.
     *   Create shopping_mall_guest_sessions record with access token, refresh
     *   token, expiration time (short-lived for guests, e.g., 24 hours), and
     *   connection metadata (ip, href, referrer from request headers). Return
     *   IShoppingMallGuest.IAuthorized with guest id, access token, refresh
     *   token, and expired_at timestamp. Handle concurrent session creation
     *   gracefully.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallGuest.IJoin,
  ): Promise<IShoppingMallGuest.IAuthorized> {
    try {
      return await postShoppingMallAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh expired guest session tokens to maintain platform access.
   *
   * Extends guest session validity by issuing new JWT access and refresh tokens. Requires a valid, non-expired refresh token from previous join or refresh operation.
   *
   * Guest sessions have short expiration times for security. This operation allows guests to maintain their session without re-registration. The refresh token must be valid and not expired - expired tokens require a new join operation.
   *
   * Request must include refresh_token string. Optional ip, href, and referrer fields update connection metadata. Response includes guest id, new access token, new refresh token, and updated expiration timestamp.
   *
   * Use this operation before the access token expires to maintain uninterrupted guest browsing experience. Refresh tokens can be used multiple times until they expire.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest token refresh request with current refresh token and optional connection metadata.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Refresh guest session tokens using valid refresh
     *   token. Validate refresh token exists and is not expired. Query
     *   shopping_mall_guest_sessions by refresh token. Check expired_at
     *   timestamp - if expired, return 401. If valid, generate new access token
     *   and refresh token pair. Update shopping_mall_guest_sessions with new
     *   tokens and extended expired_at timestamp. Return
     *   IShoppingMallGuest.IAuthorized with refreshed tokens. Handle invalid or
     *   expired tokens with appropriate error responses.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallGuest.IRefresh,
  ): Promise<IShoppingMallGuest.IAuthorized> {
    try {
      return await postShoppingMallAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
