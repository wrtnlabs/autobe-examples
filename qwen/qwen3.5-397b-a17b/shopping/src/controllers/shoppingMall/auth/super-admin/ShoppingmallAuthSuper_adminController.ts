import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSuperAdmin } from "../../../../api/structures/IShoppingMallSuperAdmin";
import { postShoppingMallAuthSuperAdminJoin } from "../../../../providers/postShoppingMallAuthSuperAdminJoin";
import { postShoppingMallAuthSuperAdminLogin } from "../../../../providers/postShoppingMallAuthSuperAdminLogin";
import { postShoppingMallAuthSuperAdminRefresh } from "../../../../providers/postShoppingMallAuthSuperAdminRefresh";

@Controller("/shoppingMall/auth/super-admin")
export class ShoppingmallAuthSuper_adminController {
  /**
   * Register a new super administrator account with email and password.
   *
   * This endpoint creates a new super administrator account in the shopping_mall_super_admins table. The email must be unique across all super administrator accounts. The password is hashed using bcrypt before storage for security.
   *
   * Upon successful registration, the system generates JWT access and refresh tokens, returning them in the IShoppingMallSuperAdmin.IAuthorized response. The account is immediately active with full super administrator privileges.
   *
   * Validation includes email format verification, password strength requirements, and uniqueness checks. Returns 409 Conflict if the email is already registered.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials for new super administrator account.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor superAdmin
     * @x-autobe-specification Create a new super administrator account.
     *   Validate email uniqueness across all super admin accounts. Hash the
     *   password using bcrypt before storing. Generate initial JWT access and
     *   refresh tokens upon successful registration. Return the authorized
     *   response with tokens and basic account info. Reject if email already
     *   exists or password does not meet security requirements.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSuperAdmin.IJoin,
  ): Promise<IShoppingMallSuperAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthSuperAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate super administrator with email and password credentials.
   *
   * This endpoint validates the provided email and password against the shopping_mall_super_admins table. The password is compared against the stored bcrypt hash. The account must not be soft-deleted (deleted_at must be null).
   *
   * Upon successful authentication, the system generates JWT access and refresh tokens and creates a session record in shopping_mall_super_admin_sessions capturing IP address, href, and referrer for security auditing.
   *
   * Returns 401 Unauthorized if credentials are invalid or account is deleted. Token expiration is enforced per security policy.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials for super administrator authentication.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor superAdmin
     * @x-autobe-specification Authenticate super administrator credentials.
     *   Query shopping_mall_super_admins by email, verify password hash matches
     *   using bcrypt comparison. Check account is not soft-deleted (deleted_at
     *   is null). Generate new JWT access and refresh tokens with appropriate
     *   expiration. Create session record in shopping_mall_super_admin_sessions
     *   with IP and navigation metadata. Return authorized response with
     *   tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSuperAdmin.ILogin,
  ): Promise<IShoppingMallSuperAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthSuperAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens for super administrator using refresh token.
   *
   * This endpoint validates the provided refresh token and issues a new access token and refresh token pair. The refresh token is validated against the shopping_mall_super_admin_sessions table to ensure it has not expired and the associated session is still valid.
   *
   * The system verifies the super administrator account exists in shopping_mall_super_admins and is not soft-deleted. A new token pair is generated with updated expiration times.
   *
   * Returns 401 Unauthorized if the refresh token is invalid, expired, or the account has been deleted. This operation enables seamless session continuation without requiring re-authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access and refresh token pair.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor superAdmin
     * @x-autobe-specification Refresh JWT access token using valid refresh
     *   token. Validate the refresh token against
     *   shopping_mall_super_admin_sessions table, checking it has not expired
     *   (expired_at is in the future). Verify the associated super
     *   administrator account exists and is not deleted. Generate new access
     *   and refresh token pair. Update session record with new expiration.
     *   Return authorized response with new tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallSuperAdmin.IRefresh,
  ): Promise<IShoppingMallSuperAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthSuperAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
