import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSuperAdmin } from "../../../../api/structures/IShoppingMallSuperAdmin";
import { postShoppingMallAuthSuperAdminJoin } from "../../../../providers/postShoppingMallAuthSuperAdminJoin";
import { postShoppingMallAuthSuperAdminLogin } from "../../../../providers/postShoppingMallAuthSuperAdminLogin";
import { postShoppingMallAuthSuperAdminRefresh } from "../../../../providers/postShoppingMallAuthSuperAdminRefresh";

@Controller("/shoppingMall/auth/superAdmin")
export class ShoppingmallAuthSuperadminController {
  /**
   * This endpoint enables super administrator account registration for the shopping mall platform. Super administrators hold the highest privilege level and can manage other administrators, approve admin promotion requests, and oversee all platform operations.
   *
   * The registration process validates that the provided email address is unique across all super administrator accounts, as the email column in shopping_mall_super_admins has a unique constraint. The password is securely hashed using bcrypt before storage in the password_hash field. Upon successful account creation, the system generates JWT access and refresh tokens for immediate authentication.
   *
   * A session record is created in the shopping_mall_super_admin_sessions table, capturing the super_admin_id reference, client IP address, page href where login was initiated, HTTP referrer, session creation timestamp, and expiration timestamp. This enables audit trail and session management capabilities.
   *
   * The response includes the newly created super administrator account information along with valid access and refresh tokens. The access token is used for subsequent authenticated API requests, while the refresh token enables obtaining new access tokens without re-authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Super administrator registration credentials including email and password for account creation.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Create a new super administrator account with email and password credentials. The service validates email uniqueness against existing super_admins records, hashes the password using bcrypt, and creates the account record. Upon successful registration, generates JWT access and refresh tokens, creates a session record in shopping_mall_super_admin_sessions with client metadata (IP, href, referrer), and returns the authorized response with tokens and account information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSuperAdmin.IJoin,
  ): Promise<IShoppingMallSuperAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthSuperAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint authenticates super administrator credentials and establishes an authenticated session. Super administrators possess the highest privilege level on the platform with capabilities including administrator grade management, admin promotion request processing, and full platform oversight.
   *
   * The authentication process queries the shopping_mall_super_admins table by the provided email address, which is indexed for efficient lookup. The provided password is compared against the stored password_hash using bcrypt verification. The system also validates that the account is active by ensuring the deleted_at timestamp is null, confirming the account has not been soft deleted.
   *
   * Upon successful authentication, the system generates a pair of JWT tokens: an access token for API authorization and a refresh token for obtaining new access tokens. A session record is persisted in the shopping_mall_super_admin_sessions table, linking to the super_admin_id and capturing connection metadata including the client IP address, the full URL (href) where authentication was initiated, and the HTTP referrer header.
   *
   * The session includes created_at and expired_at timestamps to manage session lifecycle. The response returns the authenticated super administrator's account information along with the generated tokens for use in subsequent authenticated requests.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Super administrator authentication credentials with email and password for session establishment.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Authenticate super administrator credentials and establish a new session. The service validates the email exists in shopping_mall_super_admins, verifies the password against the stored password_hash using bcrypt comparison, checks the account is not soft deleted (deleted_at is null), and upon success generates JWT access and refresh tokens. Creates a session record in shopping_mall_super_admin_sessions with client connection metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSuperAdmin.ILogin,
  ): Promise<IShoppingMallSuperAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthSuperAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint enables super administrators to renew their access tokens without re-authenticating with credentials. JWT access tokens have limited lifespans for security, and this refresh mechanism allows continuous authenticated sessions while maintaining security boundaries.
   *
   * The refresh process validates the provided refresh token against active sessions in the shopping_mall_super_admin_sessions table. The system verifies that the session's expired_at timestamp is in the future, confirming the session remains valid. It also confirms the associated super administrator account in shopping_mall_super_admins exists and has not been soft deleted (deleted_at is null).
   *
   * Upon successful validation, the system generates a new access token with refreshed expiration. For enhanced security, the refresh token can be rotated by invalidating the current session and creating a new session record with updated expired_at timestamp. This prevents refresh token reuse attacks and maintains session integrity.
   *
   * The response returns a fresh pair of access and refresh tokens along with the super administrator account information. This enables seamless continuation of authenticated operations without requiring the super administrator to re-enter credentials.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access token without re-authentication.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Refresh an expiring access token using a valid refresh token. The service validates the refresh token against active sessions in shopping_mall_super_admin_sessions, verifies the session has not expired (expired_at is in the future), confirms the associated super administrator account exists and is active, and generates a new access token. Optionally rotates the refresh token for enhanced security by invalidating the old session and creating a new one.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallSuperAdmin.IRefresh,
  ): Promise<IShoppingMallSuperAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthSuperAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
