import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSuperAdministrator } from "../../../../api/structures/IShoppingMallSuperAdministrator";
import { postShoppingMallAuthSuperAdministratorJoin } from "../../../../providers/postShoppingMallAuthSuperAdministratorJoin";
import { postShoppingMallAuthSuperAdministratorLogin } from "../../../../providers/postShoppingMallAuthSuperAdministratorLogin";
import { postShoppingMallAuthSuperAdministratorRefresh } from "../../../../providers/postShoppingMallAuthSuperAdministratorRefresh";

@Controller("/shoppingMall/auth/superAdministrator")
export class ShoppingmallAuthSuperadministratorController {
  /**
   * Register a new super administrator account in the system. This endpoint creates a super administrator account with email and password authentication credentials.
   *
   * The email address must be unique across all super administrator accounts and will be used for login. The password is hashed using bcrypt before storage for security. Upon successful registration, the system generates JWT access and refresh tokens for immediate authentication.
   *
   * This operation creates a session record in shopping_mall_super_administrator_sessions table, storing the access token, refresh token, client IP address, and session metadata. The account is immediately active upon registration.
   *
   * Email validation ensures proper format. Password requirements should meet security standards. Duplicate email addresses will be rejected with a conflict error.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials for new super administrator account creation.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Register a new super administrator account. Validate email format and uniqueness against existing accounts. Hash the password using bcrypt before storing. Create the account record with current timestamp. Generate initial JWT access and refresh tokens. Store session information including IP address and client details. Return tokens and account information to the client.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSuperAdministrator.IJoin,
  ): Promise<IShoppingMallSuperAdministrator.IAuthorized> {
    try {
      return await postShoppingMallAuthSuperAdministratorJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a super administrator using email and password credentials. This endpoint validates the provided credentials and issues JWT tokens for API access.
   *
   * The system verifies the email address exists in the shopping_mall_super_administrators table and that the account is not soft deleted (deleted_at is null). The provided password is compared against the stored bcrypt password hash.
   *
   * Upon successful authentication, new JWT access and refresh tokens are generated and stored in the shopping_mall_super_administrator_sessions table along with client metadata including IP address, request URL, and referrer. The session expiration is set according to system configuration.
   *
   * Invalid credentials return an authentication error. Soft deleted accounts cannot login. Multiple failed login attempts may trigger security measures.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials for super administrator authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Authenticate super administrator credentials. Validate email exists and is not soft deleted. Verify password hash matches provided password. Generate new JWT access and refresh tokens. Create session record with client metadata. Return tokens and account information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSuperAdministrator.ILogin,
  ): Promise<IShoppingMallSuperAdministrator.IAuthorized> {
    try {
      return await postShoppingMallAuthSuperAdministratorLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens for an authenticated super administrator session. This endpoint allows clients to obtain new JWT tokens using a valid refresh token without requiring re-authentication.
   *
   * The system validates the provided refresh token against the shopping_mall_super_administrator_sessions table, ensuring the token exists, matches an active session, and has not expired. The associated super administrator account is verified to exist and not be soft deleted.
   *
   * Upon successful validation, new JWT access and refresh tokens are generated. The session record is updated with the new tokens, maintaining the same session metadata. The old refresh token is invalidated and replaced.
   *
   * Expired refresh tokens return an authentication error. Deleted or suspended accounts cannot refresh tokens. Clients should use this endpoint before the access token expires to maintain continuous authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new authentication tokens.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Refresh JWT access token using valid refresh token. Validate refresh token exists in session table and is not expired. Verify the associated account exists and is not soft deleted. Generate new access and refresh tokens. Update session record with new tokens. Return new token pair.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallSuperAdministrator.IRefresh,
  ): Promise<IShoppingMallSuperAdministrator.IAuthorized> {
    try {
      return await postShoppingMallAuthSuperAdministratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
