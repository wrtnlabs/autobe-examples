import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCustomer } from "../../../../api/structures/IPageIShoppingMallCustomer";
import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";
import { SuperadministratorAuth } from "../../../../decorators/SuperadministratorAuth";
import { SuperadministratorPayload } from "../../../../decorators/payload/SuperadministratorPayload";
import { getShoppingMallSuperAdministratorCustomersCustomerId } from "../../../../providers/getShoppingMallSuperAdministratorCustomersCustomerId";
import { patchShoppingMallSuperAdministratorCustomers } from "../../../../providers/patchShoppingMallSuperAdministratorCustomers";

@Controller("/shoppingMall/superAdministrator/customers")
export class ShoppingmallSuperadministratorCustomersController {
  /**
   * Retrieve a filtered and paginated list of customer accounts.
   *
   * This operation provides administrators with advanced search capabilities for managing customer accounts. Supports filtering by email pattern, registration date ranges, and account status (active/deleted).
   *
   * Returns customer summary information including email, display name, phone number, and account creation date. Results are paginated with configurable page sizes and sorting options for efficient browsing of large customer datasets.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for customer listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Query shopping_mall_customers table with left join to shopping_mall_customer_profiles for display name and phone number.
   * Apply search filters on email (partial match), created_at date range, and deleted_at status.
   * Support pagination with cursor-based or offset-based approach.
   * Allow sorting by created_at (newest/oldest), email (ascending/descending).
   * Exclude password_hash from response.
   * Return customer summaries with profile information.
   * Admin-only access required.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SuperadministratorAuth()
    superAdministrator: SuperadministratorPayload,
    @TypedBody()
    body: IShoppingMallCustomer.IRequest,
  ): Promise<IPageIShoppingMallCustomer.ISummary> {
    try {
      return await patchShoppingMallSuperAdministratorCustomers({
        superAdministrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a complete customer account by unique identifier.
   *
   * This operation returns the full customer record including authentication credentials (email), account timestamps, and linked profile information (display name, phone number). The customer profile is eagerly loaded as a nested object.
   *
   * Administrators can retrieve any customer account for account management purposes. Customers can only retrieve their own profile. Returns 404 if the customer ID does not exist or the account has been soft deleted.
   *
   * @param connection
   * @param customerId Customer account unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Query shopping_mall_customers table by UUID primary key. Perform LEFT JOIN with shopping_mall_customer_profiles on shopping_mall_customer_id to include profile data. Filter out soft-deleted records (deleted_at IS NOT NULL). Return the complete customer entity with nested profile object. Validate customerId is a valid UUID format. Return 404 if no matching active customer found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerId")
  public async at(
    @SuperadministratorAuth()
    superAdministrator: SuperadministratorPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await getShoppingMallSuperAdministratorCustomersCustomerId({
        superAdministrator,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
