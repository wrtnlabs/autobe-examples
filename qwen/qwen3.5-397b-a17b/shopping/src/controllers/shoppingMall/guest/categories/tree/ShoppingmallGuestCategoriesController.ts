import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCategory } from "../../../../../api/structures/IShoppingMallCategory";
import { GuestAuth } from "../../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../../decorators/payload/GuestPayload";
import { getShoppingMallGuestCategoriesTree } from "../../../../../providers/getShoppingMallGuestCategoriesTree";

@Controller("/shoppingMall/guest/categories/tree")
export class ShoppingmallGuestCategoriesController {
  /**
   * Retrieves the complete category hierarchy with top-level categories and their nested subcategories.
   *
   * Returns all categories organized in a tree structure where each top-level category includes its direct subcategories if any exist. This endpoint supports customer browsing and product discovery by providing the full category navigation structure in a single request.
   *
   * The hierarchy is limited to two levels maximum: top-level categories and their immediate subcategories. Subcategories cannot have their own children. Products are not included in this response - use the category products endpoint to retrieve products within a specific category.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query shopping_mall_categories table to retrieve all categories. Organize results into a tree structure by grouping subcategories under their parent category using the parentId foreign key. Top-level categories (where parentId is null) form the root level. For each top-level category, include an array of its direct subcategories. Sort categories by creation order or alphabetical order by name. Return the complete tree structure in a single response without pagination since category count is typically small.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async tree(
    @GuestAuth()
    guest: GuestPayload,
  ): Promise<IShoppingMallCategory.ITree> {
    try {
      return await getShoppingMallGuestCategoriesTree({
        guest,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
