import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomerProfile } from "../../../../api/structures/IShoppingMallCustomerProfile";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getShoppingMallMemberProfile } from "../../../../providers/getShoppingMallMemberProfile";
import { putShoppingMallMemberProfile } from "../../../../providers/putShoppingMallMemberProfile";

@Controller("/shoppingMall/member/profile")
export class ShoppingmallMemberProfileController {
  /**
   * Retrieves the authenticated customer's profile information including display name and phone number.
   *
   * This endpoint returns the complete customer profile associated with the currently authenticated member account. The profile contains the customer's display name shown throughout the platform and their contact phone number used for order notifications and delivery coordination.
   *
   * The customer profile is created automatically upon member registration and maintains a one-to-one relationship with the member account. Profile data is editable by the customer through the update profile endpoint.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query shopping_mall_customer_profiles table
     *   filtering by the authenticated member's ID from session token.
   *
   * Join with shopping_mall_members to verify the member account exists and is active.
   *
   * Return the complete customer profile record including display_name, phone_number, created_at, and updated_at.
   *
   * Exclude deleted_at from response if profile is active (not soft deleted).
   *
   * Return 404 if no profile exists for the authenticated member.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IShoppingMallCustomerProfile> {
    try {
      return await getShoppingMallMemberProfile({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated customer's profile information.
   *
   * This endpoint allows customers to modify their display name and phone number. Changes take effect immediately and are reflected across the platform where the customer's profile information is displayed.
   *
   * Profile updates are restricted to the customer's own profile. The system automatically identifies the customer from the authentication session. Any attempt to modify another customer's profile is rejected.
   *
   * Both display_name and phone_number are optional fields. Customers can update either or both fields in a single request. Unspecified fields retain their current values.
   *
   * @param connection
   * @param body Profile update data containing optional display name and phone number fields. At least one field should be provided.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Update the shopping_mall_customer_profiles record
     *   for the authenticated member.
   *
   * 1. Extract member ID from authentication session context
   * 2. Query shopping_mall_customer_profiles where shopping_mall_member_id equals the authenticated member's ID
   * 3. Validate that the profile exists (customer profile should exist for all registered members)
   * 4. Apply updates to display_name and/or phone_number from request body
   * 5. Update the updated_at timestamp to current time
   * 6. Return the complete updated profile entity
   *
   * Edge cases:
   * - If profile not found, return 404 (should not happen for registered members)
   * - If validation fails on field formats, return 400 with validation errors
   * - Ensure atomic update operation
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IShoppingMallCustomerProfile.IUpdate,
  ): Promise<IShoppingMallCustomerProfile> {
    try {
      return await putShoppingMallMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
