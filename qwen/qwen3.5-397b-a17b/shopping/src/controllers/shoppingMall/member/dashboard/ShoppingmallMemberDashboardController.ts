import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSellerDashboard } from "../../../../api/structures/IShoppingMallSellerDashboard";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getShoppingMallMemberDashboard } from "../../../../providers/getShoppingMallMemberDashboard";

@Controller("/shoppingMall/member/dashboard")
export class ShoppingmallMemberDashboardController {
  /**
   * Retrieves the seller's dashboard summary with key statistics about their shop performance.
   *
   * Returns aggregated metrics including total product count, total order item count, pending cancellation request count, and pending refund request count. This endpoint provides sellers with a quick overview of their shop status upon login or dashboard access.
   *
   * The dashboard data is scoped to the authenticated seller's account only. Sellers can view these statistics to monitor their business activity and pending customer requests requiring attention.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the authenticated seller's dashboard
     *   statistics:
   *
   * 1. Count products from shopping_mall_products table where seller_id matches authenticated seller
   * 2. Count order items from shopping_mall_order_items table where seller_id matches authenticated seller
   * 3. Count pending cancellation requests from shopping_mall_cancellation_requests table where seller_id matches and status is 'pending'
   * 4. Count pending refund requests from shopping_mall_refund_requests table where seller_id matches and status is 'pending'
   *
   * Return aggregated dashboard summary object. No pagination needed as this returns single summary record. Ensure seller is authenticated and has approved seller status before returning data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IShoppingMallSellerDashboard> {
    try {
      return await getShoppingMallMemberDashboard({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
