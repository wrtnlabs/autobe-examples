import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallShipment } from "../../../../../api/structures/IPageIShoppingMallShipment";
import { IShoppingMallShipment } from "../../../../../api/structures/IShoppingMallShipment";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getShoppingMallMemberOrdersOrderIdShipmentsShipmentId } from "../../../../../providers/getShoppingMallMemberOrdersOrderIdShipmentsShipmentId";
import { patchShoppingMallMemberOrdersOrderIdShipments } from "../../../../../providers/patchShoppingMallMemberOrdersOrderIdShipments";

@Controller("/shoppingMall/member/orders/:orderId/shipments")
export class ShoppingmallMemberOrdersShipmentsController {
  /**
   * Retrieves a paginated list of shipments associated with a specific order.
   *
   * This endpoint returns all shipments created for the given order. Each shipment contains tracking information including carrier name and tracking number, along with timestamps for shipping and delivery events. Multiple shipments may exist for a single order when items come from different sellers, as each seller creates separate shipments.
   *
   * The response includes shipment status derived from shipped_at and delivered_at timestamps. Shipments without delivered_at are considered in-transit. Customers can use this to track their order fulfillment progress. Sellers can view shipments they have created. Administrators have oversight access to all shipments.
   *
   * Results are paginated and sorted by creation date (newest first). Filter criteria can be applied via the request body to narrow results by status, date range, or seller.
   *
   * @param connection
   * @param orderId UUID identifier of the order to retrieve shipments for. References shopping_mall_orders.id.
   * @param body Search and pagination criteria for filtering shipments. Includes optional filters for status, date ranges, and seller, along with pagination parameters for controlling result set size and cursor position.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query shopping_mall_shipments table filtered by shopping_mall_order_id matching the orderId path parameter. Join with shopping_mall_sellers to include seller information in response. Apply pagination using cursor-based or offset-based approach. Support filtering by status (via shipped_at/delivered_at), date ranges, and seller. Return shipments sorted by created_at descending (newest first). Ensure authorization: customers can only view shipments for their own orders, sellers can view shipments for their own shipments, admins can view all shipments. Handle case where order has no shipments yet (return empty array).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipment.IRequest,
  ): Promise<IPageIShoppingMallShipment.ISummary> {
    try {
      return await patchShoppingMallMemberOrdersOrderIdShipments({
        member,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shipment within an order.
   *
   * This endpoint returns complete shipment details including carrier information, tracking number, shipping and delivery timestamps, and all order items contained in the shipment. Customers can view shipments for their own orders. Sellers can view shipments containing their order items. Administrators can view any shipment on the platform.
   *
   * The shipment detail includes the list of order items grouped in this shipment, enabling customers to track which products are in each physical package. Each order item shows product details, variant options, quantity, price, and current fulfillment status.
   *
   * Access is restricted based on user role: customers can only access shipments from their own orders, sellers can access shipments containing their products, and administrators have full access to all shipments.
   *
   * @param connection
   * @param orderId UUID of the parent order containing this shipment.
   * @param shipmentId UUID of the shipment to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query shopping_mall_shipments table by shipment ID with order ID validation.
   *
   * 1. Verify the shipment exists and is not soft-deleted (deleted_at is null).
   * 2. Validate that the shipment belongs to the specified order (shopping_mall_order_id matches orderId parameter).
   * 3. Check authorization: customer must own the order (member_id matches authenticated user), seller must be the shipper (shopping_mall_seller_id matches authenticated seller), or user must be admin/superAdmin.
   * 4. Join with shopping_mall_order_items to retrieve all items in this shipment.
   * 5. Join with shopping_mall_products and shopping_mall_product_variants for item details.
   * 6. Return shipment with embedded order items array.
   *
   * Edge cases:
   * - Return 404 if shipment not found or doesn't belong to specified order
   * - Return 404 if shipment is soft-deleted
   * - Return 403 if user lacks authorization to view this shipment
   * - Handle null delivered_at for shipments not yet delivered
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment> {
    try {
      return await getShoppingMallMemberOrdersOrderIdShipmentsShipmentId({
        member,
        orderId,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
