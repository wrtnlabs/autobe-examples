import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallOrder } from "../../../../api/structures/IPageIShoppingMallOrder";
import { IShoppingMallOrder } from "../../../../api/structures/IShoppingMallOrder";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getShoppingMallMemberOrdersOrderId } from "../../../../providers/getShoppingMallMemberOrdersOrderId";
import { patchShoppingMallMemberOrders } from "../../../../providers/patchShoppingMallMemberOrders";
import { postShoppingMallMemberOrders } from "../../../../providers/postShoppingMallMemberOrders";

@Controller("/shoppingMall/member/orders")
export class ShoppingmallMemberOrdersController {
  /**
   * Place a new order by processing the customer's shopping cart items into a permanent order record.
   *
   * This endpoint creates a complete order transaction, capturing all cart items with their product details, prices, and quantities at the time of purchase. The system generates a unique order code for customer reference and calculates the total order value. Each order item is linked to its product, variant, and seller for fulfillment tracking.
   *
   * Upon successful order creation, the customer's cart items are removed, inventory records are created to deduct stock quantities, and the order enters the 'paid' status awaiting seller shipment. The operation is atomic - if any step fails (payment, inventory deduction, order item creation), the entire transaction is rolled back.
   *
   * The returned order object includes all order items with their initial 'paid' status. Shipments are created later by sellers when they fulfill the order items.
   *
   * @param connection
   * @param body Order creation request containing shipping address reference and optional payment method information. The cart items are automatically converted to order items - no need to specify them explicitly as they come from the customer's active cart.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Create a new order for the authenticated customer
     *   through the following steps:
   *
   * 1. Validate the customer's cart exists and contains at least one item
   * 2. Retrieve all cart items with their associated product variants
   * 3. Validate all variants are available (not deleted, have sufficient stock)
   * 4. Calculate total price from cart items (quantity × variant price or product base price)
   * 5. Generate unique order code (format: date-based + sequence)
   * 6. Create shopping_mall_orders record with member_id, code, total_price, timestamps
   * 7. For each cart item, create shopping_mall_order_items record with:
   *    - shopping_mall_order_id (new order)
   *    - shopping_mall_product_id
   *    - shopping_mall_product_variant_id
   *    - shopping_mall_seller_id (from variant's product)
   *    - quantity, price (snapshot at purchase time)
   *    - status: 'paid'
   *    - timestamps
   * 8. Create inventory records for each variant to deduct stock quantities
   * 9. Remove all cart items from the customer's cart
   * 10. Return the complete order object with all order items
   *
   * Use database transaction to ensure atomicity. If any step fails, rollback entire operation. Return appropriate error responses for insufficient stock, deleted variants, or payment failures.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IShoppingMallOrder.ICreate,
  ): Promise<IShoppingMallOrder> {
    try {
      return await postShoppingMallMemberOrders({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of customer orders with filtering and sorting capabilities.
   *
   * This endpoint allows customers to browse their order history with flexible search criteria. Orders are sorted by creation date (newest first) by default. Customers can filter orders by status, date ranges, and search by order code.
   *
   * The operation returns order summaries optimized for list display, including order code, total price, status, and item count. Full order details with items and shipments are available through the GET /orders/{orderId} endpoint.
   *
   * Authentication required: Only the authenticated customer's orders are returned. Administrators have separate oversight endpoints for viewing all platform orders.
   *
   * @param connection
   * @param body Search criteria including status filters, order code search, date range filters, pagination parameters (page, limit), and sorting options (field, direction).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query shopping_mall_orders table filtered by the
     *   authenticated member's member_id. Apply pagination using cursor-based
     *   or offset-based approach. Support filtering by: status (exact match or
     *   array), created_at date range (gte/lte), order code search (partial
     *   match). Support sorting by created_at (asc/desc), total_price
     *   (asc/desc). Default sort: created_at DESC. Join with
     *   shopping_mall_order_items to compute item count per order. Exclude
     *   soft-deleted orders (deleted_at IS NULL). Return
     *   IPageIShoppingMallOrder.ISummary with pagination metadata (page, limit,
     *   total count, hasMore). Handle empty result sets gracefully. Validate
     *   date range formats. Reject invalid status values.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IShoppingMallOrder.IRequest,
  ): Promise<IPageIShoppingMallOrder.ISummary> {
    try {
      return await patchShoppingMallMemberOrders({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves the complete details of a specific order including order items, product snapshots, and shipment tracking information.
   *
   * This endpoint returns a single order with all its constituent data: order metadata (code, total price, timestamps), the list of order items with product details and variant options, associated shipments with carrier and tracking information, and the shipping address used for the order.
   *
   * Customers can only access their own orders. The order items include snapshot data preserving the product name, description, variant price, and seller shop information at the time of purchase. Each shipment shows tracking number, carrier name, and delivery status.
   *
   * @param connection
   * @param orderId Order UUID identifier (primary key).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query shopping_mall_orders table by UUID primary
     *   key. Verify the authenticated customer's member_id matches the order's
     *   member_id for authorization. Eager load related
     *   shopping_mall_order_items with their shopping_mall_order_item_snapshots
     *   and shopping_mall_order_item_snapshot_options. Include
     *   shopping_mall_shipments with carrier and tracking details. Join with
     *   shopping_mall_customer_addresses to include the shipping address
     *   snapshot if available. Return 404 if order not found or access denied.
     *   Do not include soft-deleted orders unless explicitly requested for
     *   admin oversight.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrder> {
    try {
      return await getShoppingMallMemberOrdersOrderId({
        member,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
