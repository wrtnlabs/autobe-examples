@Controller("/shoppingMall/member/orders/:orderId/items/:orderItemId/snapshot")
export class ShoppingmallMemberOrdersItemsSnapshotController {
  /**
   * Retrieve the snapshot of a specific order item showing the product name, description, variant price, and seller profile information as they appeared at the time of purchase.
   *
   * This endpoint provides read-only access to the immutable order item snapshot, which preserves the exact state of the product and seller profile when the order was placed. This ensures accurate order history even if the original product has been modified or deleted, or if the seller has changed their shop name or logo.
   *
   * Customers can access snapshots for their own order items through their order history. Sellers can view snapshots for order items containing their products. Administrators can view any order item snapshot on the platform for dispute resolution and oversight purposes.
   *
   * The snapshot includes the product name, product description, variant price paid, seller shop name, and seller logo URL as they existed at purchase time. This endpoint is essential for customer order history viewing, seller order fulfillment reference, and administrative dispute resolution.
   *
   * @param connection
   * @param orderId UUID of the parent order containing this order item (used for authorization and verification scope).
   * @param orderItemId UUID of the order item whose snapshot is being retrieved.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the shopping_mall_order_item_snapshots table by joining with shopping_mall_order_items to verify the orderId matches the orderItemId.
   *
   * First, verify the orderItemId belongs to the specified orderId by checking shopping_mall_order_items where id = orderItemId AND shopping_mall_order_id = orderId. If no match, return 404.
   *
   * Then retrieve the snapshot from shopping_mall_order_item_snapshots where shopping_mall_order_item_id = orderItemId.
   *
   * Apply authorization checks:
   * - Customer (member): Verify the order's member_id matches the authenticated customer's ID
   * - Seller: Verify the order item's shopping_mall_seller_id matches the authenticated seller's ID
   * - Admin/Super Admin: Allow access to any snapshot
   *
   * Return the full snapshot record including product_name, product_description, variant_price, seller_shop_name, seller_logo_url, and created_at.
   *
   * If no snapshot exists for the order item (should not happen in normal operation), return 404.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItemSnapshot> {
    try {
      return await getShoppingMallMemberOrdersOrderIdItemsOrderItemIdSnapshot({
        member,
        orderId,
        orderItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
