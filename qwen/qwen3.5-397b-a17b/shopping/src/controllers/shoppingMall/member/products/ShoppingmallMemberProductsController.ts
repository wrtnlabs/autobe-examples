import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallProduct } from "../../../../api/structures/IPageIShoppingMallProduct";
import { IShoppingMallProduct } from "../../../../api/structures/IShoppingMallProduct";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getShoppingMallMemberProductsProductId } from "../../../../providers/getShoppingMallMemberProductsProductId";
import { patchShoppingMallMemberProducts } from "../../../../providers/patchShoppingMallMemberProducts";

@Controller("/shoppingMall/member/products")
export class ShoppingmallMemberProductsController {
  /**
   * Search and list products with pagination, filtering, and sorting capabilities.
   *
   * This endpoint provides comprehensive product discovery functionality for customers and guests. Users can search products by name, filter by category, apply price range constraints, and filter by stock availability. Results are returned in paginated format with configurable page size.
   *
   * The search supports full-text matching on product name and description fields. Category filtering includes products from the specified category and can optionally include subcategories. Price range filters accept minimum and maximum values. Stock filtering shows only products with at least one variant having positive inventory.
   *
   * Sorting options include relevance (for text search), price (ascending or descending), newest (by created_at), and name (alphabetical). The default sort is by relevance when searching, or by newest when browsing without search terms.
   *
   * Guest users can access this endpoint to browse the catalog. Results exclude products from suspended sellers and soft-deleted products.
   *
   * @param connection
   * @param body Search criteria including product name query, category filter, price range, stock availability filter, sorting options, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query shopping_mall_products table with pagination and filtering.
   *
   * Apply search filters:
   * - name: Full-text search using gin_trgm_ops index on name and description columns
   * - shopping_mall_category_id: Filter by category, optionally include subcategories by joining children
   * - minPrice/maxPrice: Filter base_price within range
   * - inStock: Join with shopping_mall_product_variants and filter where stock_quantity > 0
   * - seller status: Join with shopping_mall_sellers and exclude where approval_status != 'approved' or deleted_at is set
   *
   * Exclude soft-deleted products (deleted_at IS NULL).
   *
   * Apply sorting based on sort parameter:
   * - 'relevance': Order by text search score (when name query provided)
   * - 'price_asc': ORDER BY base_price ASC
   * - 'price_desc': ORDER BY base_price DESC
   * - 'newest': ORDER BY created_at DESC
   * - 'name_asc': ORDER BY name ASC
   *
   * Implement cursor-based or offset pagination. Return IPageIShoppingMallProduct.ISummary with product summary fields including id, name, base_price, category info, seller info, first image URL, and stock status.
   *
   * Handle edge cases:
   * - Empty result set: Return page with empty items array
   * - Invalid category ID: Return 404
   * - Invalid price range (min > max): Return validation error
   * - Page size exceeds maximum: Cap at maximum allowed
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IShoppingMallProduct.IRequest,
  ): Promise<IPageIShoppingMallProduct.ISummary> {
    try {
      return await patchShoppingMallMemberProducts({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves complete details of a single product by its unique identifier.
   *
   * Returns the full product entity including name, description, base price, category assignment, and seller information. The response includes all product images in display order, with the first image serving as the main thumbnail. All product variants are included with their SKU codes, option value combinations, and optional price overrides.
   *
   * Stock availability for each variant is calculated from the inventory records ledger. Products that are soft deleted (deleted_at is set) return 404 Not Found to hide them from customers while preserving order history references.
   *
   * This endpoint is accessible to all actors including guests for product browsing. The product must exist and be active (not deleted) to be retrieved.
   *
   * @param connection
   * @param productId Unique identifier of the product to retrieve (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query shopping_mall_products table by productId UUID. Join with shopping_mall_product_images to include all images ordered by display_order. Join with shopping_mall_product_variants to include all variants with their option_values and prices. Calculate stock status from shopping_mall_inventory_records ledger for each variant. Return 404 if product not found or if deleted_at is not null (soft deleted products are hidden). Include seller profile information (shop_name, logo_image_url) from shopping_mall_seller_profiles. Include category information from shopping_mall_categories.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProduct> {
    try {
      return await getShoppingMallMemberProductsProductId({
        member,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
