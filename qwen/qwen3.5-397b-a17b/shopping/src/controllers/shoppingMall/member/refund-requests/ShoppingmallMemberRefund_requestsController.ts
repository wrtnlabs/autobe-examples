import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallRefundRequest } from "../../../../api/structures/IPageIShoppingMallRefundRequest";
import { IShoppingMallRefundRequest } from "../../../../api/structures/IShoppingMallRefundRequest";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getShoppingMallMemberRefundRequestsRefundRequestId } from "../../../../providers/getShoppingMallMemberRefundRequestsRefundRequestId";
import { patchShoppingMallMemberRefundRequests } from "../../../../providers/patchShoppingMallMemberRefundRequests";
import { postShoppingMallMemberRefundRequests } from "../../../../providers/postShoppingMallMemberRefundRequests";

@Controller("/shoppingMall/member/refund-requests")
export class ShoppingmallMemberRefund_requestsController {
  /**
   * Create a refund request for a delivered order item.
   *
   * Customers can request a refund for individual order items that have been delivered. The refund request must be submitted within 7 days of the item's delivery date. Each order item can have only one refund request.
   *
   * The request requires the order item ID and a reason text explaining why the customer wants a refund. The reason is mandatory and must be provided at submission time.
   *
   * The system validates that the order item has 'delivered' status, belongs to the requesting customer, and is within the 7-day refund window. If any validation fails, the request is rejected with an appropriate error response.
   *
   * Upon successful creation, the refund request enters 'pending' status awaiting seller review. The seller can then approve or reject the request through separate endpoints.
   *
   * @param connection
   * @param body Refund request creation data including the order item ID and customer's reason for the refund.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a refund request for a delivered order item. Validate that the order item exists and has 'delivered' status. Verify the order item belongs to the requesting customer (member). Check that the refund request is within 7 days of the item's delivery date. Ensure the reason field is not empty. Verify no existing refund request exists for this order item (unique constraint on shopping_mall_order_item_id). Create the refund request record with status 'pending'. Return the created refund request entity. If validation fails at any step, return appropriate error response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IShoppingMallRefundRequest.ICreate,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await postShoppingMallMemberRefundRequests({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of refund requests with filtering and search capabilities.
   *
   * This endpoint provides customers and administrators with the ability to browse refund requests. Customers see only their own refund requests, while administrators can view all refund requests across the platform for oversight and management purposes.
   *
   * **Search and Filtering**
   *
   * Supports filtering by refund status (pending, approved, rejected) to find requests in specific workflow states. Date range filters allow searching by creation date to locate requests from specific time periods. Additional filters may include order item references or product searches.
   *
   * **Response Data**
   *
   * Returns summary information for each refund request including the request ID, current status, customer reason, associated order item details, product information, and timestamps. Full refund request details can be retrieved via the GET /refund-requests/{refundRequestId} endpoint.
   *
   * **Authorization**
   *
   * Members can only access their own refund requests. Administrators and super administrators have platform-wide visibility to all refund requests for oversight and intervention purposes.
   *
   * @param connection
   * @param body Search criteria for filtering refund requests including status, date ranges, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query shopping_mall_refund_requests table with pagination and filtering. Apply status filter (pending/approved/rejected), date range filters on created_at. For member actors, filter by shopping_mall_member_id to show only their own requests. For admin/superAdmin actors, return all requests platform-wide. Join with shopping_mall_order_items to include product name, variant details, and order information. Join with shopping_mall_products for product thumbnail. Return cursor-based pagination with summary fields including id, status, reason, order item details, product info, and timestamps. Sort by created_at descending by default (newest first).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IShoppingMallRefundRequest.IRequest,
  ): Promise<IPageIShoppingMallRefundRequest.ISummary> {
    try {
      return await patchShoppingMallMemberRefundRequests({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific refund request by its unique identifier.
   *
   * This operation returns the complete details of a refund request including the customer's reason, current review status, and timestamps. The refund request contains information about which order item is being refunded and which customer submitted the request.
   *
   * Access is restricted to the customer who submitted the refund request and the seller who owns the order item. Administrators can also access any refund request for oversight purposes.
   *
   * The response includes all refund request fields: member ID, order item ID, reason text, status (pending/approved/rejected), review timestamp, and audit timestamps.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request to retrieve (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query shopping_mall_refund_requests table by primary key UUID.
   *
   * Validate the refundRequestId parameter is a valid UUID format.
   * Retrieve the refund request record including all fields: shopping_mall_member_id, shopping_mall_order_item_id, reason, status, reviewed_at, created_at, updated_at, deleted_at.
   *
   * Authorization check: Verify the requesting user is either (1) the customer who submitted the refund request (matching shopping_mall_member_id), (2) the seller who owns the order item (join with shopping_mall_order_items to get shopping_mall_seller_id), or (3) an administrator with oversight permissions.
   *
   * If refund request not found or user lacks permission, return 404.
   * If refund request is soft-deleted (deleted_at is not null), return 404.
   *
   * Return the full IShoppingMallRefundRequest entity with all fields populated.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":refundRequestId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await getShoppingMallMemberRefundRequestsRefundRequestId({
        member,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
