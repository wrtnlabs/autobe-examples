import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallRefundRequestSnapshot } from "../../../../../api/structures/IPageIShoppingMallRefundRequestSnapshot";
import { IShoppingMallRefundRequestSnapshot } from "../../../../../api/structures/IShoppingMallRefundRequestSnapshot";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getShoppingMallMemberRefundRequestsRefundRequestIdSnapshotsSnapshotId } from "../../../../../providers/getShoppingMallMemberRefundRequestsRefundRequestIdSnapshotsSnapshotId";
import { patchShoppingMallMemberRefundRequestsRefundRequestIdSnapshots } from "../../../../../providers/patchShoppingMallMemberRefundRequestsRefundRequestIdSnapshots";

@Controller("/shoppingMall/member/refund-requests/:refundRequestId/snapshots")
export class ShoppingmallMemberRefund_requestsSnapshotsController {
  /**
   * Retrieve the complete history of state changes for a specific refund request.
   *
   * This endpoint returns all snapshots associated with a refund request, ordered chronologically by creation timestamp. Each snapshot captures the refund request status, customer reason, and seller response details at a specific moment in time, providing an immutable audit trail for dispute resolution.
   *
   * Snapshots are created automatically whenever the refund request status changes or when the seller responds to the request. The snapshot chain preserves the full lifecycle from initial submission through final resolution, including all intermediate states.
   *
   * Results are paginated and support filtering by status and date range. The snapshots are ordered by created_at in ascending order to show the progression of state changes from oldest to newest.
   *
   * @param connection
   * @param refundRequestId UUID of the refund request to retrieve snapshots for (scoped to the refund request).
   * @param body Search criteria including status filter, created_at date range, and pagination parameters (page, limit, sort).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query shopping_mall_refund_request_snapshots
     *   table filtered by shopping_mall_refund_request_id parameter.
   *
   * Apply pagination with cursor-based or offset-based pagination. Support filtering by status field (pending, approved, rejected) and created_at date range.
   *
   * Order results by created_at ascending to show chronological progression of state changes.
   *
   * Join with shopping_mall_refund_requests to verify the refund request exists and caller has permission to access it.
   *
   * Return IPageIShoppingMallRefundRequestSnapshot.ISummary with snapshot summary fields: id, status, reason, seller_response_type, seller_response_comment, created_at.
   *
   * Handle edge cases: refund request not found (404), no snapshots exist (return empty page), caller lacks permission (403).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallRefundRequestSnapshot.IRequest,
  ): Promise<IPageIShoppingMallRefundRequestSnapshot.ISummary> {
    try {
      return await patchShoppingMallMemberRefundRequestsRefundRequestIdSnapshots(
        {
          member,
          refundRequestId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific refund request snapshot by ID.
   *
   * Returns the complete snapshot record preserving the state of a refund request at a specific moment in time. Snapshots are immutable audit trail records created whenever a refund request status changes or when the seller responds to the request.
   *
   * The snapshot includes the refund request status, customer's reason, and seller's response details (if any) at the time the snapshot was created. This enables tracking the full history of state transitions and supports dispute resolution.
   *
   * @param connection
   * @param refundRequestId UUID of the parent refund request (scoped to the refund request being queried).
   * @param snapshotId UUID of the snapshot record to retrieve (globally unique identifier).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query shopping_mall_refund_request_snapshots
     *   table by snapshot ID.
   *
   * Validate that the snapshot exists and belongs to the specified refund request by checking shopping_mall_refund_request_id matches the path parameter.
   *
   * Return the full snapshot record including: id, shopping_mall_refund_request_id, status, reason, seller_response_type, seller_response_comment, and created_at.
   *
   * Handle 404 if snapshot not found or if snapshot doesn't belong to the specified refund request.
   *
   * No authorization check needed here - authorization middleware handles access control based on refund request ownership (customers see their own, sellers see related to their products, admins see all).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequestSnapshot> {
    try {
      return await getShoppingMallMemberRefundRequestsRefundRequestIdSnapshotsSnapshotId(
        {
          member,
          refundRequestId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
