import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCart } from "../../../../api/structures/IShoppingMallCart";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getShoppingMallMemberCart } from "../../../../providers/getShoppingMallMemberCart";

@Controller("/shoppingMall/member/cart")
export class ShoppingmallMemberCartController {
  /**
   * Retrieve the authenticated customer's shopping cart with all cart items.
   *
   * Returns the customer's personal shopping cart containing all items they have added for potential purchase. Each cart item includes the product variant details, quantity, and pricing information. The cart belongs exclusively to the authenticated customer and cannot be accessed by other users.
   *
   * The response includes the cart metadata (creation and update timestamps) and all cart items with their associated product variant information. Cart total price is calculated dynamically from the cart items and is not stored in the database.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query shopping_mall_carts table filtering by
     *   authenticated member's ID. Join with shopping_mall_cart_items to
     *   retrieve all items in the cart. Join with
     *   shopping_mall_product_variants to get variant details including option
     *   values. Join with shopping_mall_products to get product names and
     *   descriptions. Return the cart entity with nested items array. If cart
     *   doesn't exist, return null or create empty cart. Handle soft-deleted
     *   carts appropriately.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IShoppingMallCart.IInvert> {
    try {
      return await getShoppingMallMemberCart({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
