import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallReview } from "../../../../api/structures/IShoppingMallReview";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteShoppingMallMemberReviewsReviewId } from "../../../../providers/deleteShoppingMallMemberReviewsReviewId";
import { postShoppingMallMemberReviews } from "../../../../providers/postShoppingMallMemberReviews";
import { putShoppingMallMemberReviewsReviewId } from "../../../../providers/putShoppingMallMemberReviewsReviewId";

@Controller("/shoppingMall/member/reviews")
export class ShoppingmallMemberReviewsController {
  /**
   * Create a new product review for a delivered order item.
   *
   * This operation allows customers to submit reviews for products they have purchased and received. A review can only be created after the order item status is 'delivered', ensuring customers have actually received the product before providing feedback.
   *
   * Each review requires a mandatory star rating from 1 to 5 stars. The text content is optional, allowing customers to leave rating-only reviews or provide detailed written feedback. The system enforces one review per order item through a unique constraint on the order item reference.
   *
   * Reviews are associated with the customer account, product, order, and specific order item. This linkage enables verification of purchase history and delivery status before allowing review creation. Once created, reviews are displayed on the product detail page sorted by newest first.
   *
   * @param connection
   * @param body Review creation data including the product, order, order item references, mandatory star rating, and optional text content.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new review record in shopping_mall_reviews table.
   *
   * 1. Validate request body: rating must be integer 1-5, content is optional string
   * 2. Verify the authenticated customer owns the order_item by joining order_items -> orders -> member_id
   * 3. Verify the order_item status is 'delivered' before allowing review creation
   * 4. Check unique constraint on shopping_mall_order_item_id - reject if review already exists for this order item
   * 5. Insert review with: id (UUID), shopping_mall_member_id (from session), shopping_mall_product_id, shopping_mall_order_id, shopping_mall_order_item_id, rating, content (nullable), created_at, updated_at
   * 6. Return the created review entity with all fields
   * 7. Handle unique constraint violation with 409 Conflict if review already exists for order item
   * 8. Handle delivery status check failure with 403 Forbidden if order item not delivered
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IShoppingMallReview.ICreate,
  ): Promise<IShoppingMallReview> {
    try {
      return await postShoppingMallMemberReviews({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing review's rating and/or text content.
   *
   * This endpoint allows customers to modify their own reviews after submission. Customers can update the star rating (1-5 stars) and/or the optional text content. The review must exist and not be deleted.
   *
   * Only the customer who created the review can edit it. If a customer attempts to edit another customer's review, the request is rejected with a 403 Forbidden error. If the review does not exist or has been deleted, the request is rejected with a 404 Not Found error.
   *
   * Every review edit automatically creates a review snapshot that preserves the previous state including the rating and text content before the change. This ensures a complete history of all changes is maintained for dispute resolution. Snapshots are immutable and cannot be deleted.
   *
   * The rating must be between 1 and 5 stars inclusive. The content field is optional and can be updated to any text value or set to null to remove the text content while keeping the rating.
   *
   * @param connection
   * @param reviewId The unique identifier of the review to update (UUID format).
   * @param body Update payload containing the new rating and/or text content for the review.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update the review identified by reviewId with the provided rating and/or content.
   *
   * 1. Validate reviewId format (UUID)
   * 2. Query shopping_mall_reviews table for the review with matching id
   * 3. Verify review exists and deleted_at is null (not soft deleted)
   * 4. Verify ownership: check that shopping_mall_member_id matches the authenticated customer's ID
   * 5. If ownership check fails, return 403 Forbidden
   * 6. Validate rating: must be integer between 1 and 5 inclusive
   * 7. Validate content: can be string or null
   * 8. Create a review snapshot before updating: insert into shopping_mall_review_snapshots with current review state (rating, content, timestamps)
   * 9. Update the review record with new rating and/or content
   * 10. Update updated_at timestamp to current time
   * 11. Return the updated review object with all fields
   *
   * Edge cases:
   * - Review not found: return 404
   * - Review is soft deleted: return 404
   * - Not the review owner: return 403
   * - Rating outside 1-5 range: return 400 Bad Request
   * - Concurrent edit: use optimistic locking if implemented
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":reviewId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReview.IUpdate,
  ): Promise<IShoppingMallReview> {
    try {
      return await putShoppingMallMemberReviewsReviewId({
        member,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a customer's own review from the system.
   *
   * This operation allows customers to delete reviews they have written. When a review is deleted, it is soft-deleted by setting the deleted_at timestamp, which removes it from public view on product detail pages and excludes it from average rating calculations. The review content is no longer accessible through normal queries but remains in the database for audit purposes.
   *
   * Review snapshots created during previous edits are preserved and cannot be deleted, maintaining a complete historical audit trail. Only the customer who created the review can delete it - attempts to delete another customer's review are rejected with a permission error.
   *
   * After deletion, the product's average rating is recalculated excluding this review. If no non-deleted reviews remain for the product, no average rating is displayed.
   *
   * @param connection
   * @param reviewId Unique identifier of the review to delete (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Authenticate the requesting customer and extract their member ID from the session.
   *
   * 2. Query the shopping_mall_reviews table to find the review by the provided reviewId.
   *
   * 3. If review not found, return 404 Not Found error.
   *
   * 4. Validate ownership: compare the review's shopping_mall_member_id with the authenticated customer's member ID. If they don't match, return 403 Forbidden error (customer can only delete their own reviews).
   *
   * 5. Check if review is already deleted (deleted_at is not null). If already deleted, return 404 Not Found (treat as non-existent).
   *
   * 6. Perform soft deletion: update the review's deleted_at field to the current timestamp.
   *
   * 7. Create a review snapshot before deletion to preserve the final state (rating, content, timestamps) for audit trail. Insert into shopping_mall_review_snapshots table.
   *
   * 8. Return 204 No Content response (successful deletion with no response body).
   *
   * Edge cases:
   * - Review not found: 404
   * - Not the review owner: 403 Forbidden
   * - Already deleted review: 404
   * - Database transaction failure: rollback and return 500 Internal Server Error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reviewId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallMemberReviewsReviewId({
        member,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
