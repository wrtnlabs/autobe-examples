import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCustomerAddress } from "../../../../api/structures/IPageIShoppingMallCustomerAddress";
import { IShoppingMallCustomerAddress } from "../../../../api/structures/IShoppingMallCustomerAddress";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteShoppingMallMemberAddressesAddressId } from "../../../../providers/deleteShoppingMallMemberAddressesAddressId";
import { getShoppingMallMemberAddressesAddressId } from "../../../../providers/getShoppingMallMemberAddressesAddressId";
import { patchShoppingMallMemberAddresses } from "../../../../providers/patchShoppingMallMemberAddresses";
import { postShoppingMallMemberAddresses } from "../../../../providers/postShoppingMallMemberAddresses";
import { putShoppingMallMemberAddressesAddressId } from "../../../../providers/putShoppingMallMemberAddressesAddressId";

@Controller("/shoppingMall/member/addresses")
export class ShoppingmallMemberAddressesController {
  /**
   * Create a new shipping address for the authenticated customer.
   *
   * This endpoint allows customers to add a new shipping address to their account. Each address includes complete delivery information: recipient name, phone number, street address, city, state/province, postal code, and country. Customers can optionally designate the new address as their default shipping address.
   *
   * The created address is immediately available for selection during checkout and in future orders. Customers can maintain multiple addresses without limit. If is_default is set to true, the system automatically updates any existing default address to false, ensuring only one default address per customer.
   *
   * @param connection
   * @param body Address creation details including recipient information, full address components, and optional default designation flag.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new customer address record in shopping_mall_customer_addresses table.
   *
   * 1. Extract customer profile ID from authenticated session context (not from request body)
   * 2. Validate all required address fields: recipient_name, recipient_phone, street_address, city, state_province, postal_code, country
   * 3. If is_default is true, begin transaction and update existing default address for this customer to is_default=false
   * 4. Insert new address record with generated UUID, customer profile ID, and provided address fields
   * 5. Set created_at and updated_at to current timestamp, deleted_at to null
   * 6. Return the complete created address entity including generated id
   *
   * Ensure customer can only create addresses for their own profile (enforced by session context). No limit on number of addresses per customer.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IShoppingMallCustomerAddress.ICreate,
  ): Promise<IShoppingMallCustomerAddress> {
    try {
      return await postShoppingMallMemberAddresses({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of the authenticated customer's saved shipping addresses.
   *
   * This endpoint returns all active (non-deleted) shipping addresses associated with the customer's account. Customers can filter addresses by recipient name, city, country, or default status to quickly locate specific addresses in their address book.
   *
   * The response includes complete address details for each entry, along with pagination metadata for navigating large address collections. Addresses are ordered by creation date (newest first) to surface recently added addresses prominently.
   *
   * Only the authenticated customer can access their own addresses. The system enforces strict ownership validation to prevent unauthorized access to other customers' address information.
   *
   * @param connection
   * @param body Search and pagination criteria for filtering customer addresses. Includes optional filters for recipient name partial match, city exact match, country exact match, and default address flag. Pagination parameters control page size and cursor-based navigation.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query shopping_mall_customer_addresses table filtered by the authenticated customer's profile ID. Apply search filters on recipient_name (partial match), city (exact match), country (exact match), and is_default (boolean match). Exclude soft-deleted records (deleted_at IS NULL). Support cursor-based pagination using created_at for ordering. Join with shopping_mall_customer_profiles to verify ownership. Return IPageIShoppingMallCustomerAddress.ISummary with pagination metadata. Validate that the requesting user is a member actor (customer). If no addresses found, return empty page with zero items.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IShoppingMallCustomerAddress.IRequest,
  ): Promise<IPageIShoppingMallCustomerAddress.ISummary> {
    try {
      return await patchShoppingMallMemberAddresses({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information for a specific customer shipping address by its unique identifier.
   *
   * This endpoint returns the complete address record including recipient name, phone number, street address, city, state/province, postal code, country, and default address flag. The address must belong to the authenticated customer - attempting to access another customer's address will result in an authorization error.
   *
   * The response includes the full address object with all fields necessary for display in address management interfaces or pre-filling checkout forms. Soft-deleted addresses (where deleted_at is set) are not accessible through this endpoint.
   *
   * @param connection
   * @param addressId Unique identifier of the address to retrieve (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the shopping_mall_customer_addresses table by the provided addressId UUID.
   *
   * 1. Validate the addressId is a valid UUID format.
   * 2. Query the database for the address record with matching id.
   * 3. Verify the address belongs to the authenticated customer by checking shopping_mall_customer_profile_id matches the customer's profile ID from the session.
   * 4. Ensure the address is not soft-deleted (deleted_at IS NULL).
   * 5. Return the full address entity if found and authorized.
   * 6. Return 404 Not Found if the address does not exist, belongs to another customer, or is soft-deleted.
   *
   * The query should select all columns: id, shopping_mall_customer_profile_id, recipient_name, recipient_phone, street_address, city, state_province, postal_code, country, is_default, created_at, updated_at, deleted_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":addressId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerAddress> {
    try {
      return await getShoppingMallMemberAddressesAddressId({
        member,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing customer shipping address with new delivery information.
   *
   * This operation allows customers to modify any of their saved addresses including recipient name, phone number, and complete address details (street, city, state/province, postal code, country). Customers can also change the default address designation.
   *
   * All address fields are validated for required values and proper formatting. When setting an address as default (is_default=true), the system automatically updates all other addresses for the same customer to non-default status, ensuring exactly one default address per customer at any time.
   *
   * Ownership verification is enforced - customers can only update addresses they own. Attempting to update another customer's address results in authorization failure.
   *
   * @param connection
   * @param addressId Unique identifier of the address to update (UUID format).
   * @param body Address update data including recipient information, full address details, and default designation flag. All fields are optional - only provided fields will be updated.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update an existing customer address. Query shopping_mall_customer_addresses table by addressId. Verify the address belongs to the authenticated customer by joining with shopping_mall_customer_profiles and checking the shopping_mall_customer_profile_id matches the customer's profile ID. Validate all provided fields: recipient_name (required, non-empty string), recipient_phone (required, valid phone format), street_address (required), city (required), state_province (required), postal_code (required), country (required), is_default (boolean). If is_default is set to true, update all other addresses for the same customer to is_default=false to maintain exactly one default address per customer. Update the updated_at timestamp to current time. Return the complete updated address record. Handle 404 if address not found. Handle 403 if address does not belong to the authenticated customer.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":addressId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCustomerAddress.IUpdate,
  ): Promise<IShoppingMallCustomerAddress> {
    try {
      return await putShoppingMallMemberAddressesAddressId({
        member,
        addressId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a customer's shipping address from their account.
   *
   * This operation permanently removes an address from the customer's active address list using soft deletion. The address record is marked as deleted and will no longer appear in address listings or be available for selection during checkout.
   *
   * Before deletion, the system validates that the address is not currently set as the customer's default shipping address. If the address is the default, the customer must first update another address to be the default before this deletion can proceed.
   *
   * Deleted addresses cannot be recovered. However, address information in existing order snapshots remains preserved for historical records and dispute resolution purposes.
   *
   * @param connection
   * @param addressId Unique identifier of the address to delete (UUID format, scoped to customer ownership).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Delete the customer address by setting the deleted_at timestamp to the current time.
   *
   * Implementation steps:
   * 1. Verify the address exists and belongs to the authenticated customer by joining with shopping_mall_customer_profiles
   * 2. Validate that the address is not marked as is_default=true
   * 3. If the address is the default, return a validation error requiring the customer to set a different default address first
   * 4. Soft delete by updating deleted_at to current timestamp
   * 5. Return 204 No Content on success
   *
   * Business rules:
   * - Only the address owner can delete their own address
   * - Default addresses cannot be deleted without first reassigning the default flag to another address
   * - Soft delete preserves the record for order snapshot integrity
   * - The deleted_at index enables efficient filtering of active addresses
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":addressId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallMemberAddressesAddressId({
        member,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
