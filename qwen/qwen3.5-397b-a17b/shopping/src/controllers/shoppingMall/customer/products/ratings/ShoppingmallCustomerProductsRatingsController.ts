import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallProductRating } from "../../../../../api/structures/IShoppingMallProductRating";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerProductsProductIdRatings } from "../../../../../providers/getShoppingMallCustomerProductsProductIdRatings";

@Controller("/shoppingMall/customer/products/:productId/ratings")
export class ShoppingmallCustomerProductsRatingsController {
  /**
   * Retrieve the average rating and total review count for a specific product.
   *
   * This operation returns the aggregated rating information for a product, including the average rating calculated from all non-deleted reviews and the total count of reviews. The average rating is computed by summing all rating values from non-deleted reviews and dividing by the count of non-deleted reviews.
   *
   * If a product has no non-deleted reviews, the average rating will be null. Deleted reviews are excluded from both the average calculation and the total count. This ensures the displayed rating reflects current customer sentiment.
   *
   * @param connection
   * @param productId Product UUID (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_reviews table filtering by product_id and excluding soft-deleted reviews (deleted_at IS NOT NULL). Calculate average rating using AVG(rating) function on non-deleted reviews. Count total non-deleted reviews using COUNT(*). Return null for averageRating if no reviews exist. Join with shopping_mall_products to verify product exists. Handle case where product has no reviews by returning averageRating as null and totalReviews as 0.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductRating> {
    try {
      return await getShoppingMallCustomerProductsProductIdRatings({
        customer,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
