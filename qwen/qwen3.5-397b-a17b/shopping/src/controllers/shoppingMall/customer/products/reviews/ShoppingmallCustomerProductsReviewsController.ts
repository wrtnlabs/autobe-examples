import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallReview } from "../../../../../api/structures/IPageIShoppingMallReview";
import { IShoppingMallReview } from "../../../../../api/structures/IShoppingMallReview";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerProductsProductIdReviews } from "../../../../../providers/patchShoppingMallCustomerProductsProductIdReviews";

@Controller("/shoppingMall/customer/products/:productId/reviews")
export class ShoppingmallCustomerProductsReviewsController {
  /**
   * Retrieve a paginated list of customer reviews for a specific product.
   *
   * This operation returns all non-deleted reviews for the specified product, sorted by newest first (most recently created or edited reviews at the top). Each review includes the rating (1-5 stars), optional text content, creation timestamp, and customer information.
   *
   * Reviews are only visible if they have not been deleted by their authors. The response includes pagination metadata to support browsing large review sets. This endpoint is publicly accessible to all customers viewing the product detail page.
   *
   * @param connection
   * @param productId Product UUID to retrieve reviews for
   * @param body Pagination and sorting parameters for review list
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_reviews table filtering by product_id and excluding deleted records (deleted_at IS NULL). Join with shopping_mall_customers to include customer display name. Order by created_at DESC to show newest reviews first. Apply cursor-based pagination with configurable page size. Calculate average rating from all non-deleted reviews for the product and include in response metadata. Return 404 if product does not exist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReview.IRequest,
  ): Promise<IPageIShoppingMallReview.ISummary> {
    try {
      return await patchShoppingMallCustomerProductsProductIdReviews({
        customer,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
