import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallRefundRequestSnapshot } from "../../../../api/structures/IShoppingMallRefundRequestSnapshot";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerRefundRequestSnapshotsSnapshotId } from "../../../../providers/getShoppingMallCustomerRefundRequestSnapshotsSnapshotId";

@Controller("/shoppingMall/customer/refund-request-snapshots/:snapshotId")
export class ShoppingmallCustomerRefund_request_snapshotsController {
  /**
   * Retrieve a specific refund request snapshot by its unique identifier.
   *
   * This endpoint provides detailed access to an immutable point-in-time capture of a refund request state. Refund request snapshots preserve the complete state of a refund request at the moment a seller responds, including the request status, customer's refund reason, seller's response decision, and all relevant timestamps. These snapshots form part of the refund audit trail and support transparency in dispute resolution.
   *
   * The snapshot includes comprehensive information about the refund request context: the associated order item, the customer who submitted the request, the seller who responded (if applicable), delivery confirmation timestamp for 7-day refund validation, and the complete timeline from request submission through seller response. All timestamps are captured for historical accuracy and compliance verification.
   *
   * Access to refund request snapshots is restricted to relevant parties for privacy and dispute resolution purposes. The customer who submitted the refund request can view all snapshots for their requests. The seller who responded to the refund request can view snapshots for refund requests on their order items. Administrators can view any refund request snapshot on the platform for oversight and dispute mediation. This access control ensures transparent dispute resolution while maintaining appropriate data boundaries.
   *
   * Snapshots are immutable and append-only. Once created when a seller responds to a refund request, they cannot be modified or deleted. This ensures the integrity of the audit trail and provides reliable evidence for dispute resolution. Multiple snapshots for the same refund request create a complete history showing how the request progressed through the system.
   *
   * @param connection
   * @param snapshotId Target refund request snapshot's unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_refund_request_snapshots table by primary key (snapshotId UUID). Join with shopping_mall_refund_requests to verify the snapshot exists and retrieve parent request context. Join with shopping_mall_order_items to include order item details. Join with shopping_mall_customers for customer information. Left join with shopping_mall_sellers for responded_by_seller_id if not null.
   *
   * Authorization check: Verify requesting actor is one of:
   * 1. The customer who submitted the refund request (customer_id matches authenticated customer)
   * 2. The seller who responded (responded_by_seller_id matches authenticated seller)
   * 3. An administrator (admin or superAdmin role)
   *
   * Return 404 if snapshot not found or access denied (to avoid leaking existence of unauthorized snapshots). Return complete snapshot object with all fields: id, refund_request_id, order_item_id, customer_id, responded_by_seller_id, reason, status, delivered_at, requested_at, responded_at, snapshot_at, created_at.
   *
   * Include related entity summaries in response: order item reference, customer reference, seller reference (if responded).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequestSnapshot> {
    try {
      return await getShoppingMallCustomerRefundRequestSnapshotsSnapshotId({
        customer,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
