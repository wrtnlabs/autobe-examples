import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCancellationRequest } from "../../../../api/structures/IPageIShoppingMallCancellationRequest";
import { IShoppingMallCancellationRequest } from "../../../../api/structures/IShoppingMallCancellationRequest";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerCancellationRequestsCancellationRequestId } from "../../../../providers/getShoppingMallCustomerCancellationRequestsCancellationRequestId";
import { patchShoppingMallCustomerCancellationRequests } from "../../../../providers/patchShoppingMallCustomerCancellationRequests";
import { postShoppingMallCustomerCancellationRequests } from "../../../../providers/postShoppingMallCustomerCancellationRequests";

@Controller("/shoppingMall/customer/cancellation-requests")
export class ShoppingmallCustomerCancellation_requestsController {
  /**
   * Submit a cancellation request for a specific order item in the shopping mall platform.
   *
   * This operation allows customers to request cancellation of individual order items that have been paid but not yet shipped. Each cancellation request applies to one order item only, not the entire order, enabling customers to cancel specific items while other items in the same order continue processing normally. The request must include a reason text explaining why the customer wants to cancel the item.
   *
   * The system performs comprehensive validation before accepting the request. The order item must exist and have PAID status. Items that have already been shipped, delivered, cancelled, or refunded are not eligible for cancellation. The requesting customer must be the owner of the order containing the item. Only one pending cancellation request per order item is allowed - if a previous request for the same item is still in PENDING status, the new request is rejected.
   *
   * Upon successful submission, the cancellation request is created with PENDING status in the shopping_mall_cancellation_requests table. The request includes the customer's reason text, references the target order_item_id, and records the requested_at timestamp. The status workflow transitions from PENDING to either APPROVED or REJECTED based on the seller's response. Once submitted, the cancellation request cannot be withdrawn or modified by the customer.
   *
   * Related operations: Use GET /shoppingMall/cancellation-requests/{id} to view cancellation request details and track status. Use PATCH /shoppingMall/orders/{orderId}/items to view order items and their current status before requesting cancellation.
   *
   * @param connection
   * @param body Cancellation request creation data containing the target order item identifier and cancellation reason. The order_item_id must reference a valid order item with PAID status owned by the requesting customer. The reason field must be a non-empty text string explaining why the customer wants to cancel the item. Note: customer_id is automatically derived from the authenticated session and status defaults to PENDING - do not include these in the request body.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create a new cancellation request for an order item. Validate that the order item exists and has PAID status. Verify the requesting customer owns the order (order belongs to customer's order). Check that no pending cancellation request already exists for this order item. Create cancellation request record with status PENDING, linking to order_item_id and customer_id from session. Return the created cancellation request with full details including id, orderItemId, customerId, reason, status, and requestedAt timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCancellationRequest.ICreate,
  ): Promise<IShoppingMallCancellationRequest> {
    try {
      return await postShoppingMallCustomerCancellationRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of cancellation requests for order items.
   *
   * This operation provides comprehensive search capabilities for viewing cancellation requests with filtering by status (PENDING, APPROVED, REJECTED), date ranges, and specific order items. The endpoint supports actor-based data isolation: customers see only their own cancellation requests, sellers see requests for order items from their products, and administrators can view all requests across the platform.
   *
   * Each cancellation request in the response includes the reason for cancellation, current status, timestamps for request and response, and summarized information about the associated order item including product name, variant details, and order number. For requests that have been responded to, the response includes seller information and response timestamp.
   *
   * The operation supports pagination with configurable page size and sorting options, defaulting to newest requests first. Results are filtered to exclude soft-deleted cancellation request records, ensuring only active requests are returned.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering cancellation requests
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_cancellation_requests table with pagination and filtering based on actor context.
   *
   * Authorization logic:
   * - customer: Filter by customer_id = authenticated customer's ID
   * - seller: Join with shopping_mall_order_items on order_item_id, filter by shopping_mall_seller_id = authenticated seller's ID
   * - admin/superAdmin: No filter, return all requests
   *
   * Apply search filters from request body:
   * - status: Filter by cancellation status (PENDING, APPROVED, REJECTED)
   * - requestedAtFrom/requestedAtTo: Filter by requested_at timestamp range
   * - orderItemId: Filter by specific order item
   *
   * Join with shopping_mall_order_items to include order item details (product name, variant info, order number).
   * Join with shopping_mall_customers for customer display name.
   * Join with shopping_mall_sellers for seller shop name (when responded).
   *
   * Return cursor-based or offset pagination with configurable page size (default 20, max 100).
   * Sort by requested_at DESC by default (newest first).
   *
   * Edge cases:
   * - Return empty array if no matching requests
   * - Include responded_at and responded_by_seller information only when status is not PENDING
   * - Soft-deleted cancellation requests should be excluded from results
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCancellationRequest.IRequest,
  ): Promise<IPageIShoppingMallCancellationRequest.ISummary> {
    try {
      return await patchShoppingMallCustomerCancellationRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific cancellation request for an order item.
   *
   * This endpoint provides comprehensive details about a cancellation request submitted by a customer, including the cancellation reason, current status (PENDING, APPROVED, or REJECTED), submission timestamp, and seller response information when available. The response includes references to the related order item, customer, and responding seller.
   *
   * Access is restricted to the customer who submitted the cancellation request, the seller who owns the order item being cancelled, and platform administrators. This ensures proper data isolation and privacy while allowing all relevant parties to track the cancellation request status.
   *
   * The cancellation request status follows a workflow: PENDING (awaiting seller response) → APPROVED or REJECTED (seller has responded). When status is PENDING, the responded_at and responded_by_seller_id fields will be null. Once the seller responds, these fields are populated with the response timestamp and seller identifier.
   *
   * This operation is typically used after listing cancellation requests via PATCH /cancellation-requests to view detailed information about a specific request. The cancellation request data is preserved immutably in cancellation request snapshots for audit and dispute resolution purposes.
   *
   * @param connection
   * @param cancellationRequestId Target cancellation request's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the shopping_mall_cancellation_requests table by the cancellation request ID.
   *
   * Validate that the authenticated actor has access to this cancellation request:
   * - Customer: must match the customer_id field
   * - Seller: must match the responded_by_seller_id OR own the order item (via order_item_id → order → seller)
   * - Admin/SuperAdmin: always authorized
   *
   * Join with shopping_mall_order_items to include order item details in response.
   * Join with shopping_mall_customers to include customer information.
   * Left join with shopping_mall_sellers to include seller response information (nullable).
   *
   * Return the complete cancellation request record with all fields including:
   * - id, order_item_id, customer_id, responded_by_seller_id
   * - reason, status (PENDING/APPROVED/REJECTED)
   * - requested_at, responded_at (nullable)
   * - created_at, updated_at, deleted_at
   *
   * Handle soft deletion: exclude records where deleted_at is not null unless actor is admin.
   *
   * Throw 404 if cancellation request not found or access denied (do not reveal existence to unauthorized users).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":cancellationRequestId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cancellationRequestId")
    cancellationRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCancellationRequest> {
    try {
      return await getShoppingMallCustomerCancellationRequestsCancellationRequestId(
        {
          customer,
          cancellationRequestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
