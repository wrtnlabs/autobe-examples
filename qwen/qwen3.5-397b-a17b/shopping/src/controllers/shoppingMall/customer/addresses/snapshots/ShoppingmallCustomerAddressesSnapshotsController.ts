import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallAddressSnapshot } from "../../../../../api/structures/IPageIShoppingMallAddressSnapshot";
import { IShoppingMallAddressSnapshot } from "../../../../../api/structures/IShoppingMallAddressSnapshot";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerAddressesAddressIdSnapshotsSnapshotId } from "../../../../../providers/getShoppingMallCustomerAddressesAddressIdSnapshotsSnapshotId";
import { patchShoppingMallCustomerAddressesAddressIdSnapshots } from "../../../../../providers/patchShoppingMallCustomerAddressesAddressIdSnapshots";

@Controller("/shoppingMall/customer/addresses/:addressId/snapshots")
export class ShoppingmallCustomerAddressesSnapshotsController {
  /**
   * Retrieve a paginated list of historical snapshots for a specific customer address.
   *
   * This operation provides access to the immutable audit trail of all changes made to an address. Each snapshot captures the complete state of the address at the moment of modification, including recipient name, phone number, street address, city, state/province, postal code, country, and default designation flag.
   *
   * Snapshots are automatically created whenever an address is modified and cannot be altered or deleted. This endpoint allows customers to review their address history for verification and dispute resolution purposes. Results are ordered by creation timestamp (newest first) and support pagination for efficient browsing of historical records.
   *
   * @param connection
   * @param addressId Address UUID (scoped to customer)
   * @param body Pagination and optional filtering criteria for snapshot history
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_address_snapshots table filtered by shopping_mall_address_id matching the path parameter.
   *
   * Apply pagination with cursor-based or offset-based approach. Default page size 20, maximum 100.
   * Sort by created_at descending (newest first) by default. Support custom sorting via request body.
   *
   * Validate that the requesting customer owns the address (shopping_mall_addresses.shopping_mall_customer_id matches authenticated customer).
   * Return 404 if address does not exist or belongs to another customer.
   *
   * Include snapshot fields: id, recipient_name, recipient_phone, street_address, city, state, postal_code, country, is_default, created_at.
   * Use the index on [shopping_mall_address_id, created_at] for efficient querying.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAddressSnapshot.IRequest,
  ): Promise<IPageIShoppingMallAddressSnapshot.ISummary> {
    try {
      return await patchShoppingMallCustomerAddressesAddressIdSnapshots({
        customer,
        addressId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific address snapshot by its unique identifier.
   *
   * This operation returns an immutable historical record of an address at a specific point in time. Address snapshots are automatically created whenever an address is modified, capturing the complete state including recipient name, phone number, and all address fields at that moment.
   *
   * Snapshots serve as an audit trail for dispute resolution and historical tracking. Once created, snapshots cannot be modified or deleted by any user, ensuring permanent records of all address changes.
   *
   * The requesting customer must own both the address and the snapshot. Attempts to access snapshots belonging to other customers or non-existent addresses will be rejected.
   *
   * @param connection
   * @param addressId UUID of the parent address (customer-owned)
   * @param snapshotId UUID of the address snapshot to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_address_snapshots table by snapshot ID.
   *
   * Validate that the snapshot exists and belongs to the specified address by checking shopping_mall_address_id matches the addressId parameter.
   *
   * Verify address ownership by joining with shopping_mall_addresses and confirming shopping_mall_customer_id matches the authenticated customer's ID.
   *
   * Return the complete snapshot record including all fields: id, shopping_mall_address_id, recipient_name, recipient_phone, street_address, city, state, postal_code, country, is_default, and created_at.
   *
   * Handle edge cases: snapshot not found (404), address not found (404), unauthorized access - snapshot belongs to different customer (403).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAddressSnapshot> {
    try {
      return await getShoppingMallCustomerAddressesAddressIdSnapshotsSnapshotId(
        {
          customer,
          addressId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
