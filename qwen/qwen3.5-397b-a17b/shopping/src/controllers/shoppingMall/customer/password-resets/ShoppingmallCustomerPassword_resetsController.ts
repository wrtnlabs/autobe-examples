import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCustomerPasswordReset } from "../../../../api/structures/IPageIShoppingMallCustomerPasswordReset";
import { IShoppingMallCustomerPasswordReset } from "../../../../api/structures/IShoppingMallCustomerPasswordReset";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerPasswordResetsResetId } from "../../../../providers/getShoppingMallCustomerPasswordResetsResetId";
import { patchShoppingMallCustomerPasswordResets } from "../../../../providers/patchShoppingMallCustomerPasswordResets";

@Controller("/shoppingMall/customer/password-resets")
export class ShoppingmallCustomerPassword_resetsController {
  /**
   * Search and list password reset requests across all actor types in the platform with advanced filtering and pagination capabilities.
   *
   * This operation provides administrators with comprehensive oversight of password reset activity throughout the shopping mall platform. It aggregates reset requests from customer, seller, administrator, and super administrator accounts, enabling security monitoring and audit trail review.
   *
   * The endpoint supports filtering by actor type, creation date ranges, expiration status, and token consumption status. Administrators can identify patterns such as multiple reset requests from single accounts, expired unused tokens, or potential security concerns requiring investigation.
   *
   * Response includes paginated results with reset token metadata, associated actor information, and status indicators. All existing sessions are terminated after successful password change as per security requirements.
   *
   * Authorization requires admin or superAdmin actor privileges. Customer and seller actors cannot access this endpoint as password reset oversight is a platform administration function.
   *
   * @param connection
   * @param body Search criteria for password reset requests including actor type filtering, date ranges, consumption status, and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query all four password reset tables (shopping_mall_customer_password_resets, shopping_mall_seller_password_resets, shopping_mall_admin_password_resets, shopping_mall_super_admin_password_resets) with unified search criteria. Apply filtering by actorType (customer/seller/admin/superAdmin), date ranges (created_at, expires_at), consumption status (consumed_at/used_at null or present), and expiration status. Join with parent actor tables to retrieve email and account information. Implement cursor-based pagination for large result sets. Sort by created_at descending by default. Validate admin/superAdmin authorization before execution. Return unified summary format with actor type indicator for each reset record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCustomerPasswordReset.IRequest,
  ): Promise<IPageIShoppingMallCustomerPasswordReset.ISummary> {
    try {
      return await patchShoppingMallCustomerPasswordResets({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific password reset request record by its unique identifier.
   *
   * This operation provides administrators with visibility into password reset requests for audit and security monitoring purposes. The endpoint returns detailed information about a password reset request including when it was created, when it expires, and whether it has been used or consumed.
   *
   * Access to this endpoint is restricted to administrator and super administrator actors only. Regular customers and sellers cannot view password reset records through this API. The response excludes sensitive token data (token hash or raw token) for security reasons, showing only metadata about the reset request.
   *
   * The password reset record indicates its current state: active (not expired and not used), expired (past the expiration timestamp), or consumed (successfully used to reset password). This information helps administrators track password reset activity and identify potential security concerns such as multiple reset requests or unusual patterns.
   *
   * @param connection
   * @param resetId Unique identifier of the password reset record (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the appropriate password reset table based on actor context (customer, seller, admin, or super-admin password resets). Verify the requesting user has administrator privileges to access password reset audit records. Return password reset record details including creation timestamp, expiration status, and consumption/usage status without exposing the actual token hash or raw token value. Validate that the resetId exists and return 404 if not found. Include expiration status calculation (expired if expired_at/expires_at < current time). Include usage status (consumed/used if consumed_at/used_at is not null).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":resetId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("resetId")
    resetId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerPasswordReset> {
    try {
      return await getShoppingMallCustomerPasswordResetsResetId({
        customer,
        resetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
