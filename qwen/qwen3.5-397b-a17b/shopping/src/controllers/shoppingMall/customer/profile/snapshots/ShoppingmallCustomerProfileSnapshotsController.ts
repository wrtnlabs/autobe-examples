import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallSellerProfileSnapshot } from "../../../../../api/structures/IPageIShoppingMallSellerProfileSnapshot";
import { IShoppingMallSellerProfileSnapshot } from "../../../../../api/structures/IShoppingMallSellerProfileSnapshot";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerProfileSnapshotsSnapshotId } from "../../../../../providers/getShoppingMallCustomerProfileSnapshotsSnapshotId";
import { patchShoppingMallCustomerProfileSnapshots } from "../../../../../providers/patchShoppingMallCustomerProfileSnapshots";

@Controller("/shoppingMall/customer/profile/snapshots")
export class ShoppingmallCustomerProfileSnapshotsController {
  /**
   * Retrieve a paginated list of seller profile snapshots for the authenticated seller's shop profile.
   *
   * This operation provides access to the complete audit history of seller profile changes. Each snapshot represents the complete state of the seller profile at a specific moment in time, including shop name, description, and logo image. Snapshots are automatically created whenever the seller edits their profile information.
   *
   * Supports date range filtering to find snapshots from specific time periods. Results are sorted by creation timestamp in descending order (newest first). Pagination enables efficient browsing of extensive snapshot histories.
   *
   * Snapshots are immutable records that cannot be modified or deleted. This endpoint is accessible to sellers viewing their own profile history and administrators viewing any seller's profile history for oversight purposes.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering seller profile snapshots
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_seller_profile_snapshots table with pagination and filtering.
   *
   * Filter by shopping_mall_seller_profile_id based on authenticated seller's profile (or any profile for administrators).
   * Apply date range filters on created_at if provided in request body.
   * Sort by created_at descending (newest first).
   * Return cursor-based pagination with configurable page size.
   * Join with shopping_mall_seller_profiles to include profile context if needed.
   * Ensure snapshots are returned in chronological order for timeline display.
   * Handle edge case: return empty array if no snapshots exist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallSellerProfileSnapshot.IRequest,
  ): Promise<IPageIShoppingMallSellerProfileSnapshot.ISummary> {
    try {
      return await patchShoppingMallCustomerProfileSnapshots({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific seller profile snapshot by its unique identifier.
   *
   * This operation returns the complete state of a seller profile at a specific point in time, including the shop name, description, and logo image URL that were active when the snapshot was created. Snapshots are automatically generated whenever a seller modifies their profile information.
   *
   * Snapshots are immutable audit records that cannot be modified or deleted. This endpoint is accessible to the seller who owns the profile and administrators for dispute resolution and compliance purposes. The snapshot includes the creation timestamp indicating when the profile change occurred.
   *
   * @param connection
   * @param snapshotId Unique identifier of the seller profile snapshot (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_seller_profile_snapshots table by snapshot ID UUID.
   *
   * Validate that the requesting user has permission to view this snapshot:
   * - Seller actors can view snapshots of their own profile (join with shopping_mall_sellers and shopping_mall_seller_profiles to verify ownership)
   * - Administrator and superAdministrator actors can view any snapshot
   *
   * Return the complete snapshot entity including id, shopping_mall_seller_profile_id, shop_name, description, logo_image_uri, and created_at.
   *
   * If snapshot ID does not exist, return 404 Not Found.
   * If user lacks permission, return 403 Forbidden.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerProfileSnapshot> {
    try {
      return await getShoppingMallCustomerProfileSnapshotsSnapshotId({
        customer,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
