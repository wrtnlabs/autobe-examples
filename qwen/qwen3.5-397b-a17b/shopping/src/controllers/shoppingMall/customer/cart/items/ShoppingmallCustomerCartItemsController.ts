import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallCartItem } from "../../../../../api/structures/IShoppingMallCartItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { deleteShoppingMallCustomerCartItemsItemId } from "../../../../../providers/deleteShoppingMallCustomerCartItemsItemId";
import { getShoppingMallCustomerCartItemsItemId } from "../../../../../providers/getShoppingMallCustomerCartItemsItemId";
import { postShoppingMallCustomerCartItems } from "../../../../../providers/postShoppingMallCustomerCartItems";
import { putShoppingMallCustomerCartItemsCartItemId } from "../../../../../providers/putShoppingMallCustomerCartItemsCartItemId";
import { putShoppingMallCustomerCartItemsItemId } from "../../../../../providers/putShoppingMallCustomerCartItemsItemId";

@Controller("/shoppingMall/customer/cart/items")
export class ShoppingmallCustomerCartItemsController {
  /**
   * Update the quantity of a cart item or remove it from the shopping cart.
   *
   * This operation allows customers to modify the quantity of an existing cart item. The quantity can be increased or decreased, but must remain at least 1. Setting the quantity to 0 or using the remove flag will delete the item from the cart. The cart total is automatically recalculated after the update.
   *
   * Cart items are marked as unavailable if the product variant has been deleted by the seller or is out of stock. Unavailable items cannot be updated and will return an error. The operation validates that the cart item belongs to the authenticated customer.
   *
   * @param connection
   * @param cartItemId Cart item UUID (global scope)
   * @param body Cart item update request with quantity or removal flag
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update shopping_mall_cart_items record by cartItemId. Validate that the cart item exists and belongs to the authenticated customer's cart (join with shopping_mall_carts on customer_id). Check that the item is not soft deleted (deleted_at is null). If quantity is provided and >= 1, update the quantity field and set updated_at. If quantity is 0 or remove flag is true, perform soft delete by setting deleted_at to current timestamp. Validate that the product variant still exists and is purchasable. Return 404 if cart item not found. Return 400 if quantity < 0. Return 400 if item is unavailable (variant deleted or out of stock). Return updated cart item on success.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":cartItemId")
  public async putByCartitemid(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartItemId")
    cartItemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCartItem.IUpdate,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await putShoppingMallCustomerCartItemsCartItemId({
        customer,
        cartItemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific shopping cart item by its unique identifier within the customer's cart.
   *
   * This operation returns the complete details of a single active cart item, including the product variant reference, quantity, unit price snapshot, and temporal metadata. The price field represents the unit price captured at the time the item was added to the cart, ensuring consistent display and checkout calculation even if the product variant's price changes later.
   *
   * Cart items are subsidiary entities belonging to a customer's shopping cart. Each item references a specific product variant and maintains a unique constraint on (cart_id, product_variant_id) to prevent duplicate variants within the same cart. Only active (non-deleted) items are returned through this endpoint.
   *
   * The cart item includes soft delete support via the deleted_at field. Items with a non-null deleted_at value are considered removed from the cart and are excluded from this operation's results. This ensures customers only see active items in their cart.
   *
   * @param connection
   * @param itemId Cart item UUID (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the shopping_mall_cart_items table by the provided item UUID.
   *
   * 1. Validate the itemId is a valid UUID format
   * 2. Query shopping_mall_cart_items WHERE id = itemId
   * 3. Include soft-deleted items in the result (do not filter by deleted_at)
   * 4. Join with shopping_mall_product_variants if variant details are needed in response
   * 5. Join with shopping_mall_carts to verify cart ownership if authorization is required
   * 6. Return 404 if no cart item exists with the given ID
   * 7. Return the full IShoppingMallCartItem entity with all fields
   *
   * Authorization: Verify the requesting customer owns the cart containing this item (via cart.customer_id match with authenticated user).
   *
   * Edge cases:
   * - Item not found: return 404
   * - Item belongs to different customer: return 404 or 403 based on authorization policy
   * - Soft-deleted item: still return the entity (deleted_at will be populated)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await getShoppingMallCustomerCartItemsItemId({
        customer,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the quantity of a specific item in the customer's shopping cart.
   *
   * This operation allows customers to modify the quantity of an existing cart item. When the quantity is updated, the cart total price is recalculated to reflect the change. Customers can adjust quantities at any time before proceeding to checkout.
   *
   * Setting the quantity to zero removes the item from the cart entirely. The item must belong to the authenticated customer's cart. Attempting to update an item from another customer's cart will result in an authorization error. If the item does not exist or has been removed, a not found error is returned.
   *
   * @param connection
   * @param itemId Cart item UUID (global scope)
   * @param body Updated quantity for the cart item. Set to 0 to remove the item from cart.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_cart_items table by itemId.
   * Verify the cart item belongs to the authenticated customer by joining with shopping_mall_carts on cart_id.
   * Validate quantity is a positive integer (minimum 1).
   * Update the quantity field and set updated_at to current timestamp.
   * Return the updated cart item with all fields including price snapshot.
   * Handle edge cases: item not found (404), item belongs to different customer (403), invalid quantity (400).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":itemId")
  public async putByItemid(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCartItem.IUpdate,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await putShoppingMallCustomerCartItemsItemId({
        customer,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a specific item from the customer's shopping cart.
   *
   * This operation allows customers to delete individual cart items by their unique identifier. When an item is removed, it is soft-deleted from the cart and the cart total is recalculated. The removal affects only the specified item, leaving all other cart items unchanged.
   *
   * Removing a cart item does not affect the customer's wishlist - products saved to the wishlist remain intact. If the item was unavailable (out of stock or deleted product), it can still be removed from the cart using this endpoint.
   *
   * The operation implements soft-delete behavior, marking the item with a deleted_at timestamp rather than permanently removing it from the database for audit trail purposes.
   *
   * @param connection
   * @param itemId Cart item unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Delete the cart item with the given itemId from the shopping_mall_cart_items table.
   *
   * 1. Verify the cart item exists and belongs to the authenticated customer's cart by joining with shopping_mall_carts on shopping_mall_cart_id
   * 2. Check that deleted_at is null (item not already removed)
   * 3. Soft-delete by setting deleted_at to current timestamp
   * 4. Recalculate cart total by summing (price * quantity) for all non-deleted items in the cart
   * 5. Return success with no response body
   *
   * Edge cases:
   * - Item already deleted: return 404 Not Found
   * - Item belongs to different customer's cart: return 404 Not Found (do not reveal existence)
   * - Cart itself is deleted: return 404 Not Found
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":itemId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerCartItemsItemId({
        customer,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Add a product variant to the customer's shopping cart.
   *
   * This operation adds a specified product variant to the authenticated customer's cart with the requested quantity. If the same variant already exists in the cart, the quantities are combined rather than creating a duplicate entry. The unit price is captured as a snapshot from the product variant at the time of addition, ensuring consistent pricing even if the variant's price changes later.
   *
   * The cart persists across sessions, so items remain in the cart until the customer removes them or completes a purchase. After successful order placement, items included in the order are automatically removed from the cart.
   *
   * Requests are rejected if the product variant does not exist, has been deleted by the seller, or is out of stock. The quantity must be at least 1. The response includes the created or updated cart item with the captured price snapshot and current quantity.
   *
   * @param connection
   * @param body Product variant identifier and quantity to add to cart
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Retrieve the authenticated customer's active cart from shopping_mall_carts using customer_id (from session token).
   * 2. If no cart exists, create a new cart record for the customer.
   * 3. Query shopping_mall_product_variants to verify the variant exists and is active (deleted_at is null).
   * 4. Check if a cart item already exists for this (cart_id, product_variant_id) pair.
   * 5. If exists: update the quantity by adding the new quantity to existing quantity, update updated_at.
   * 6. If not exists: create new cart item with price snapshot from variant.price_override (or parent product base price if override is null).
   * 7. Set created_at for new items, updated_at for all operations.
   * 8. Return the cart item entity with all fields including the captured price.
   * 9. Handle edge cases: variant not found (404), variant deleted (400), invalid quantity <= 0 (400).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCartItem.ICreate,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await postShoppingMallCustomerCartItems({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
