import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCancellationRequest } from "../../../../../api/structures/IPageIShoppingMallCancellationRequest";
import { IShoppingMallCancellationRequest } from "../../../../../api/structures/IShoppingMallCancellationRequest";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrderItemsOrderItemIdCancellationRequestsCancellationRequestId } from "../../../../../providers/getShoppingMallCustomerOrderItemsOrderItemIdCancellationRequestsCancellationRequestId";
import { patchShoppingMallCustomerOrderItemsOrderItemIdCancellationRequests } from "../../../../../providers/patchShoppingMallCustomerOrderItemsOrderItemIdCancellationRequests";
import { postShoppingMallCustomerOrderItemsOrderItemIdCancellationRequests } from "../../../../../providers/postShoppingMallCustomerOrderItemsOrderItemIdCancellationRequests";

@Controller(
  "/shoppingMall/customer/order-items/:orderItemId/cancellation-requests",
)
export class ShoppingmallCustomerOrder_itemsCancellation_requestsController {
  /**
   * Create a cancellation request for a specific order item.
   *
   * This operation allows customers to request cancellation of individual order items that have paid status. The customer must provide a reason explaining why they want to cancel the item. The cancellation request is submitted to the seller responsible for that order item for review.
   *
   * Only order items with paid status can be cancelled. Items with shipped, delivered, cancelled, or refunded status will be rejected. Each cancellation request targets one order item and does not affect other items in the same order.
   *
   * Upon successful creation, the cancellation request enters pending status and awaits seller approval or rejection. The seller can respond to the request, which creates a snapshot of the request state at the time of response.
   *
   * @param connection
   * @param orderItemId UUID of the order item to cancel (scoped to the order)
   * @param body Cancellation request creation data with reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create a new cancellation request for the specified order item.
   *
   * 1. Validate the order item exists and has status 'paid'. Reject if status is shipped, delivered, cancelled, or refunded.
   * 2. Verify the authenticated customer is the owner of the order (via order's customer_id).
   * 3. Check that no active cancellation request already exists for this order item (status = pending).
   * 4. Create cancellation request with: shopping_mall_order_item_id = orderItemId, shopping_mall_customer_id = authenticated user's ID, reason = from request body, status = 'pending', created_at = now, updated_at = now.
   * 5. Return the created cancellation request with full details.
   *
   * Error handling:
   * - 404 if order item not found
   * - 400 if order item status is not 'paid'
   * - 409 if pending cancellation request already exists for this order item
   * - 403 if authenticated customer is not the order owner
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCancellationRequest.ICreate,
  ): Promise<IShoppingMallCancellationRequest> {
    try {
      return await postShoppingMallCustomerOrderItemsOrderItemIdCancellationRequests(
        {
          customer,
          orderItemId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of cancellation requests for a specific order item.
   *
   * This operation provides access to cancellation requests associated with a particular order item. Customers can view their own cancellation requests, while sellers can view requests for order items belonging to their products. The endpoint supports filtering by cancellation status (pending, approved, rejected) and includes pagination for efficient data retrieval.
   *
   * Each cancellation request includes the customer's reason for cancellation, current status, and timestamps. The response is optimized for list displays with summary information suitable for UI rendering.
   *
   * @param connection
   * @param orderItemId Order item UUID (scoped to specific order)
   * @param body Filter criteria and pagination parameters for cancellation request search
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_cancellation_requests table filtered by shopping_mall_order_item_id path parameter.
   *
   * Apply status filter from request body if provided (pending, approved, or rejected).
   * Join with shopping_mall_customers to include customer information in response.
   * Implement cursor-based pagination with configurable page size.
   *
   * Authorization: Customer can only access their own cancellation requests. Seller can access requests for order items belonging to their products.
   *
   * Return 404 if order item does not exist. Return empty array if no cancellation requests match the criteria.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCancellationRequest.IRequest,
  ): Promise<IPageIShoppingMallCancellationRequest.ISummary> {
    try {
      return await patchShoppingMallCustomerOrderItemsOrderItemIdCancellationRequests(
        {
          customer,
          orderItemId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific cancellation request for an order item by its unique identifier.
   *
   * This operation returns the complete cancellation request details including the customer's cancellation reason, current approval status (pending, approved, or rejected), and timestamps. The endpoint validates that the cancellation request belongs to the specified order item before returning the data.
   *
   * Access is restricted to the customer who created the cancellation request or the seller associated with the order item. This ensures proper data isolation while allowing both parties to track the cancellation workflow. The response includes all fields necessary to understand the request state and history.
   *
   * @param connection
   * @param orderItemId Order item ID (scoped to order)
   * @param cancellationRequestId Cancellation request ID (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_cancellation_requests table by primary key (cancellationRequestId).
   *
   * Validate that the cancellation request's shopping_mall_order_item_id matches the provided orderItemId parameter. Return 404 if no match found or if the cancellation request has been soft deleted (deleted_at is not null).
   *
   * Include customer information by joining with shopping_mall_customers table.
   * Return the full cancellation request entity with id, order_item_id, customer_id, reason, status, created_at, and updated_at fields.
   *
   * Handle edge cases:
   * - Return 404 if cancellation request not found
   * - Return 404 if orderItemId doesn't match the request's order item
   * - Return 403 if caller is not the customer who created the request or the seller of the order item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":cancellationRequestId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
    @TypedParam("cancellationRequestId")
    cancellationRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCancellationRequest> {
    try {
      return await getShoppingMallCustomerOrderItemsOrderItemIdCancellationRequestsCancellationRequestId(
        {
          customer,
          orderItemId,
          cancellationRequestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
