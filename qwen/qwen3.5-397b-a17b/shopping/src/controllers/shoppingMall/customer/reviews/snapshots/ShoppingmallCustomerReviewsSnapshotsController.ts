import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallReviewSnapshot } from "../../../../../api/structures/IPageIShoppingMallReviewSnapshot";
import { IShoppingMallReviewSnapshot } from "../../../../../api/structures/IShoppingMallReviewSnapshot";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerReviewsReviewIdSnapshotsSnapshotId } from "../../../../../providers/getShoppingMallCustomerReviewsReviewIdSnapshotsSnapshotId";
import { patchShoppingMallCustomerReviewsReviewIdSnapshots } from "../../../../../providers/patchShoppingMallCustomerReviewsReviewIdSnapshots";

@Controller("/shoppingMall/customer/reviews/:reviewId/snapshots")
export class ShoppingmallCustomerReviewsSnapshotsController {
  /**
   * Retrieve a paginated list of edit snapshots for a specific review.
   *
   * This operation returns the complete edit history of a review, with each snapshot capturing the rating and content at the time of modification. Snapshots are created automatically whenever a review is edited and preserve the previous state for audit trail and dispute resolution purposes.
   *
   * Snapshots are immutable and cannot be modified or deleted. This endpoint supports pagination for reviews with extensive edit histories. Only the review author and administrators can access review snapshots.
   *
   * @param connection
   * @param reviewId UUID of the review to retrieve snapshots for
   * @param body Pagination and sorting parameters for snapshot history
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_review_snapshots table filtered by shopping_mall_review_id matching the reviewId path parameter.
   *
   * Apply authorization check: allow access only if authenticated user is the review owner (customer_id matches) or has administrator role.
   *
   * Return snapshots ordered by created_at descending (newest first) with cursor-based pagination.
   *
   * Join with shopping_mall_reviews to verify review existence and ownership.
   *
   * Handle edge case: return empty array if review has no edit history (no snapshots exist).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewSnapshot.IRequest,
  ): Promise<IPageIShoppingMallReviewSnapshot.ISummary> {
    try {
      return await patchShoppingMallCustomerReviewsReviewIdSnapshots({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific review snapshot by its unique identifier.
   *
   * This operation returns the immutable snapshot of a review at a specific point in time, capturing the rating and content before an edit was made. Snapshots are created automatically whenever a customer edits their review, preserving the complete history of changes for audit trail and dispute resolution purposes.
   *
   * Snapshots are immutable and retained indefinitely, even if the parent review is soft-deleted. This ensures complete historical records are available for dispute resolution and compliance purposes.
   *
   * Customers can view snapshots of their own reviews to track their edit history. Administrators can view snapshots of any review for verification and dispute resolution. The snapshot includes the rating (1-5 stars), optional text content, and the timestamp when the snapshot was created.
   *
   * @param connection
   * @param reviewId UUID of the parent review (global scope)
   * @param snapshotId UUID of the review snapshot (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_review_snapshots table by snapshot ID.
   *
   * Validate that the snapshot exists and belongs to the specified review.
   * Check authorization: allow if requester is the review owner (customer_id matches authenticated user) or is an administrator.
   *
   * Join with shopping_mall_reviews to verify the review relationship and obtain customer_id for authorization check.
   *
   * Return the complete snapshot record including id, shopping_mall_review_id, rating, content, and created_at.
   *
   * Handle 404 if snapshot not found or does not belong to the specified review.
   * Handle 403 if requester is not authorized to view this snapshot.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReviewSnapshot> {
    try {
      return await getShoppingMallCustomerReviewsReviewIdSnapshotsSnapshotId({
        customer,
        reviewId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
