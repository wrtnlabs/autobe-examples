import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../../api/structures/IShoppingMallCustomer";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerCustomersProfile } from "../../../../../providers/putShoppingMallCustomerCustomersProfile";

@Controller("/shoppingMall/customer/customers/profile")
export class ShoppingmallCustomerCustomersProfileController {
  /**
   * Update the authenticated customer's profile information including display name and phone number.
   *
   * This operation allows authenticated customers to modify their profile information stored in the shopping_mall_customers table. Customers can update their nickname (display name) which appears on reviews and public-facing content, and/or their phone number used for order notifications and delivery coordination.
   *
   * Profile updates are subject to validation checks. The operation will be rejected if the customer account has been soft deleted (deleted_at is not null) or if the account is banned by an administrator. Both fields accept updates independently - customers can modify either or both fields in a single request.
   *
   * When the phone number is updated, the change automatically cascades to all existing shipping address records associated with the customer through the shopping_mall_addresses table, ensuring consistency between the profile and saved addresses. The updated_at timestamp is refreshed to track when the profile was last modified. This operation requires the customer to be authenticated via their session token.
   *
   * @param connection
   * @param body Profile update information with optional display name and/or phone number
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update the authenticated customer's profile information in the shopping_mall_customers table. Extract customer ID from authentication session token. Validate account status: reject if deleted_at is not null (account deleted), or if account is banned by administrator. Validate request body: both displayName and phoneNumber must be provided and non-empty, reject if either is missing or empty. Update nickname and phone_number fields in the database. When phone_number changes, cascade the update to all address records associated with this customer by updating the phone_number field in each shopping_mall_addresses record. Update the updated_at timestamp to current time. Return the complete updated customer profile. Handle concurrent updates with optimistic locking using updated_at timestamp comparison.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCustomer.IUpdate,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await putShoppingMallCustomerCustomersProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
