import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallAdminPromotionRequest } from "../../../../api/structures/IShoppingMallAdminPromotionRequest";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerAdminPromotionRequestsRequestId } from "../../../../providers/getShoppingMallCustomerAdminPromotionRequestsRequestId";
import { postShoppingMallCustomerAdminPromotionRequests } from "../../../../providers/postShoppingMallCustomerAdminPromotionRequests";

@Controller("/shoppingMall/customer/admin-promotion-requests")
export class ShoppingmallCustomerAdmin_promotion_requestsController {
  /**
   * Submit a request to become an administrator on the platform.
   *
   * This operation allows any authenticated user, whether a customer or seller, to apply for administrator access. The request must include a reason text explaining why the user wants to become an administrator. Upon submission, the request enters a pending state awaiting review by super administrators.
   *
   * The system automatically determines the applicant type from the authenticated session. Each user can have only one pending promotion request at a time. If a user submits a new request while a previous one is still pending, the previous pending request is automatically cancelled.
   *
   * Once submitted, super administrators can review the request and either approve it (granting administrator access) or reject it with a reason. The requesting user can view the status of their request through the detail endpoint.
   *
   * @param connection
   * @param body Request body for creating an administrator promotion request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create a new administrator promotion request for the authenticated user.
   *
   * Implementation steps:
   * 1. Extract authenticated user ID and session ID from request context (customer or seller)
   * 2. Determine actor_type based on user type ('customer' or 'seller')
   * 3. Validate reason field: must be non-empty string
   * 4. Check for existing pending request by the same user
   * 5. If pending request exists, cancel it (set status to 'rejected' or soft delete) before creating new one
   * 6. Create new shopping_mall_admin_promotion_requests record with:
   *    - actor_type: determined from user type
   *    - reason: from request body
   *    - status: 'pending'
   *    - created_at: current timestamp
   * 7. Create corresponding subtype record:
   *    - For customers: shopping_mall_admin_promotion_request_of_customers with customer_id and customer_session_id
   *    - For sellers: shopping_mall_admin_promotion_request_of_sellers with seller_id and seller_session_id
   * 8. Return the created promotion request entity
   *
   * Validation:
   * - Reason must be non-empty (trim and check length > 0)
   * - User must be authenticated (customer or seller session required)
   * - Only one pending request allowed per user at a time
   *
   * Error handling:
   * - 400: Empty or missing reason
   * - 401: Not authenticated
   * - Return created entity on success
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallAdminPromotionRequest.ICreate,
  ): Promise<IShoppingMallAdminPromotionRequest> {
    try {
      return await postShoppingMallCustomerAdminPromotionRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific administrator promotion request by its unique identifier.
   *
   * This operation returns the complete details of an administrator promotion request including the applicant's reason for requesting admin access, current approval status (pending, approved, or rejected), and if rejected, the rejection reason provided by the super administrator. The response also includes timestamps for submission and last modification.
   *
   * Authorization: Users can view their own promotion requests. Super administrators can view all promotion requests for review purposes. Regular administrators cannot access this endpoint.
   *
   * The request includes polymorphic ownership information indicating whether the submitter is a customer or seller actor.
   *
   * @param connection
   * @param requestId Unique identifier of the promotion request (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_admin_promotion_requests table by primary key id.
   *
   * Include related subtype information: join with shopping_mall_admin_promotion_request_of_customers or shopping_mall_admin_promotion_request_of_sellers based on actor_type discriminator to retrieve the submitter's actor information.
   *
   * Authorization check: Verify the requesting user either (1) is the submitter of this request (matches shopping_mall_customer_id or shopping_mall_seller_id), or (2) has super administrator role.
   *
   * Return 404 if request not found or soft-deleted (deleted_at is not null).
   * Return 403 if user lacks permission to view this request.
   *
   * Response includes: id, actor_type, reason, status, rejection_reason (nullable), created_at, updated_at, and submitter actor reference.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":requestId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdminPromotionRequest> {
    try {
      return await getShoppingMallCustomerAdminPromotionRequestsRequestId({
        customer,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
