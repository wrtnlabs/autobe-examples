import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallWishlistItem } from "../../../../api/structures/IPageIShoppingMallWishlistItem";
import { IShoppingMallWishlistItem } from "../../../../api/structures/IShoppingMallWishlistItem";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteShoppingMallCustomerWishlistItemsWishlistItemId } from "../../../../providers/deleteShoppingMallCustomerWishlistItemsWishlistItemId";
import { getShoppingMallCustomerWishlistItemsWishlistItemId } from "../../../../providers/getShoppingMallCustomerWishlistItemsWishlistItemId";
import { patchShoppingMallCustomerWishlistItems } from "../../../../providers/patchShoppingMallCustomerWishlistItems";
import { postShoppingMallCustomerWishlistItems } from "../../../../providers/postShoppingMallCustomerWishlistItems";

@Controller("/shoppingMall/customer/wishlist-items")
export class ShoppingmallCustomerWishlist_itemsController {
  /**
   * Add a product to the authenticated customer's personal wishlist.
   *
   * This operation creates a new wishlist entry linking the customer to a product they are interested in for future purchase consideration. The wishlist stores products at the product level, not specific variants, allowing customers to track entire products rather than particular option combinations.
   *
   * The system enforces duplicate prevention - if the product already exists in the customer's wishlist, the request is rejected. The product must exist and not be deleted by the seller. The customer must be authenticated to access this feature.
   *
   * Upon successful addition, the wishlist entry is created with a timestamp for sorting and pagination purposes. The created entry includes the product reference and creation timestamp.
   *
   * @param connection
   * @param body Product identifier to add to wishlist. Only product_id is required; customer_id is automatically derived from the authenticated session.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create a new wishlist item for the authenticated customer.
   *
   * 1. Extract customer_id from authenticated session token
   * 2. Validate product_id exists in shopping_mall_products table
   * 3. Check product.deleted_at is null (product not deleted)
   * 4. Check for existing wishlist entry: query shopping_mall_wishlist_items where customer_id and product_id match
   * 5. If duplicate exists, return 409 Conflict error
   * 6. If product deleted or not found, return 404 Not Found error
   * 7. Insert new record into shopping_mall_wishlist_items with customer_id, product_id, created_at, updated_at
   * 8. Return created wishlist item with full entity data
   *
   * Edge cases:
   * - Product deleted by seller: reject with 404
   * - Duplicate wishlist entry: reject with 409
   * - Unauthenticated request: reject with 401
   * - Invalid product_id format: reject with 400
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallWishlistItem.ICreate,
  ): Promise<IShoppingMallWishlistItem> {
    try {
      return await postShoppingMallCustomerWishlistItems({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of products in the authenticated customer's wishlist.
   *
   * This operation returns all products the customer has saved to their wishlist, including product details such as main image, name, price or price range, seller shop name, and current availability status. The wishlist displays products at the product level rather than specific variants.
   *
   * Supports pagination with configurable page sizes and sorting by addition date (newest or oldest first). Each wishlist item shows whether the product is still available for purchase or has been deleted/unavailable. Products automatically removed from wishlists when deleted by sellers are not included in results.
   *
   * Only the authenticated customer can access their own wishlist. The operation filters results to show only products that are currently available on the platform.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for wishlist items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_wishlist_items table filtered by authenticated customer's ID.
   *
   * Join with shopping_mall_products to retrieve product information including name, description, base price, and main image (first product image).
   * Join with shopping_mall_sellers through product to get seller shop name.
   * Join with shopping_mall_product_variants to calculate price range if multiple variants exist.
   * Check variant stock quantities to determine availability status.
   *
   * Apply pagination using cursor-based or offset pagination on created_at field.
   * Support sorting by created_at ascending or descending.
   *
   * Filter out wishlist items where product has been soft deleted (deleted_at is not null).
   * Filter out products where all variants are out of stock if in-stock-only filter is applied.
   *
   * Return IPageIShoppingMallWishlistItem.ISummary with wishlist items containing product summary information and availability indicators.
   *
   * Handle edge cases:
   * - Empty wishlist: return empty page with zero items
   * - All products unavailable: return empty results or items marked unavailable based on requirement
   * - Invalid pagination parameters: use defaults
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallWishlistItem.IRequest,
  ): Promise<IPageIShoppingMallWishlistItem.ISummary> {
    try {
      return await patchShoppingMallCustomerWishlistItems({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific wishlist item by its unique identifier.
   *
   * This operation returns detailed information about a single product saved in the customer's wishlist, including the product details such as name, description, main image, base price or price range, seller information, and average rating.
   *
   * The wishlist item is scoped to the authenticated customer's account. Customers can only access wishlist items that belong to their own wishlist. If the product has been deleted by the seller or is no longer available, the wishlist item will not be found.
   *
   * This endpoint is useful for displaying detailed product information when a customer clicks on a specific item from their wishlist view.
   *
   * @param connection
   * @param wishlistItemId Wishlist item UUID (scoped to authenticated customer's wishlist)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_wishlist_items table by the provided wishlistItemId UUID.
   *
   * Verify that the wishlist item belongs to the authenticated customer by checking customer_id matches the session user.
   *
   * Join with shopping_mall_products to retrieve complete product information including name, description, category, and seller details.
   *
   * Join with shopping_mall_sellers to get seller shop name and profile information.
   *
   * Include product's main image (first image from shopping_mall_product_images where product_id matches).
   *
   * Calculate price range if product has multiple variants with different prices.
   *
   * Include average rating from shopping_mall_reviews if reviews exist for the product.
   *
   * Return 404 if wishlist item not found or does not belong to authenticated customer.
   *
   * Return 404 if product has been deleted (cascade delete would have removed wishlist item).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":wishlistItemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistItemId")
    wishlistItemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallWishlistItem> {
    try {
      return await getShoppingMallCustomerWishlistItemsWishlistItemId({
        customer,
        wishlistItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a specific product from the customer's wishlist.
   *
   * This operation permanently deletes a wishlist item entry, removing the association between the customer and the saved product. The deletion is immediate and cannot be undone.
   *
   * Only the customer who owns the wishlist can remove items from it. If the wishlist item does not exist or has already been removed (including automatic cleanup when a product is deleted), the request is rejected. The removal of a product from the wishlist does not affect the product itself or other customers' wishlists.
   *
   * @param connection
   * @param wishlistItemId Wishlist item UUID (scoped to customer)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Delete the wishlist item record by UUID from shopping_mall_wishlist_items table.
   *
   * Validate that the wishlist item exists and belongs to the authenticated customer. Check that the item is not already soft-deleted (deleted_at is null). Perform soft delete by setting deleted_at timestamp to current time.
   *
   * Return 404 if the wishlist item does not exist or does not belong to the customer. Return 404 if the item was already deleted (including automatic cleanup from product deletion). No response body on successful deletion.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":wishlistItemId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistItemId")
    wishlistItemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerWishlistItemsWishlistItemId({
        customer,
        wishlistItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
