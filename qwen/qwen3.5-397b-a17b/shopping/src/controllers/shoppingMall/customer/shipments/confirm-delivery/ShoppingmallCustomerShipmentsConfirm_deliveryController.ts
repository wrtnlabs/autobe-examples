import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallShipment } from "../../../../../api/structures/IShoppingMallShipment";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerShipmentsShipmentIdConfirmDelivery } from "../../../../../providers/putShoppingMallCustomerShipmentsShipmentIdConfirmDelivery";

@Controller("/shoppingMall/customer/shipments/:shipmentId/confirm-delivery")
export class ShoppingmallCustomerShipmentsConfirm_deliveryController {
  /**
   * Confirm delivery of a shipment by the customer.
   *
   * This operation allows customers to manually confirm that they have received a shipment. When delivery is confirmed, all order items contained in the shipment automatically transition to delivered status. This enables customers to write reviews for the delivered products.
   *
   * If the customer does not manually confirm delivery, order items automatically change to delivered status after 14 days from the shipped date. The confirmation action records the confirmed_at timestamp on the shipment.
   *
   * Only the customer who placed the order can confirm delivery for the shipment. The shipment must be in shipped status (not yet delivered) to be eligible for confirmation.
   *
   * @param connection
   * @param shipmentId Shipment ID to confirm delivery (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update the shipment's confirmed_at field to the current timestamp when the customer confirms delivery.
   *
   * Validate that the shipment exists and is in shipped status (not already delivered). Verify that the authenticated customer is the owner of the order containing the shipment's order items. Update all order items in the shipment to status 'delivered' in a transaction. Return the updated shipment with the confirmed_at timestamp populated.
   *
   * Reject the request if: shipment not found, shipment already confirmed/delivered, or customer is not authorized to confirm this shipment.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async confirmDelivery(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment> {
    try {
      return await putShoppingMallCustomerShipmentsShipmentIdConfirmDelivery({
        customer,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
