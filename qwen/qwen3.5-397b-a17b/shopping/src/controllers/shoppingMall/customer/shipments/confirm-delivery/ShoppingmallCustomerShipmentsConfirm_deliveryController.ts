import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallShipment } from "../../../../../api/structures/IShoppingMallShipment";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { postShoppingMallCustomerShipmentsShipmentIdConfirmDelivery } from "../../../../../providers/postShoppingMallCustomerShipmentsShipmentIdConfirmDelivery";

@Controller("/shoppingMall/customer/shipments/:shipmentId/confirm-delivery")
export class ShoppingmallCustomerShipmentsConfirm_deliveryController {
  /**
   * Confirm delivery receipt for a shipment by the customer.
   *
   * This endpoint allows customers to manually confirm that they have received a shipment. When delivery is confirmed, the system updates the shipment's delivery_confirmed_at timestamp and changes the status of all order items in that shipment to DELIVERED. This confirmation triggers the completion of the order fulfillment process for those items.
   *
   * Only the customer who placed the order containing this shipment can confirm delivery. The shipment must have been previously shipped (shipped_at timestamp set) and not already delivery confirmed. If the customer does not manually confirm delivery, the system automatically confirms delivery 14 days after the shipped_at timestamp.
   *
   * After successful confirmation, all order items in the shipment become eligible for review submission. Customers can view the delivery confirmation status in their order history and shipment tracking pages.
   *
   * @param connection
   * @param shipmentId Target shipment's ID to confirm delivery for
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate that the shipment exists and belongs to an order owned by the authenticated customer. Verify the shipment has been shipped (shipped_at is not null) and not yet delivery confirmed. Update the shipment's delivery_confirmed_at timestamp to current time. Update all order items linked to this shipment through shopping_mall_shipment_items to status 'DELIVERED'. Return the updated shipment with delivery confirmation timestamp. Reject if shipment doesn't exist, customer doesn't own the order, or shipment already confirmed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async confirmDelivery(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment> {
    try {
      return await postShoppingMallCustomerShipmentsShipmentIdConfirmDelivery({
        customer,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
