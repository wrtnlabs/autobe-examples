import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallShipment } from "../../../../api/structures/IPageIShoppingMallShipment";
import { IShoppingMallShipment } from "../../../../api/structures/IShoppingMallShipment";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerShipmentsShipmentId } from "../../../../providers/getShoppingMallCustomerShipmentsShipmentId";
import { patchShoppingMallCustomerShipments } from "../../../../providers/patchShoppingMallCustomerShipments";
import { putShoppingMallCustomerShipmentsShipmentId } from "../../../../providers/putShoppingMallCustomerShipmentsShipmentId";

@Controller("/shoppingMall/customer/shipments")
export class ShoppingmallCustomerShipmentsController {
  /**
   * Retrieve a filtered and paginated list of shipment records with tracking information.
   *
   * This operation provides comprehensive shipment search capabilities for both sellers and customers. Sellers can view shipments they have created for their order items, while customers can view shipments associated with their orders. The endpoint supports filtering by order ID, shipment status, and date ranges to help users find specific shipments efficiently.
   *
   * Each shipment in the response includes tracking carrier name, tracking number, and key delivery lifecycle timestamps including shipped date, delivered date, and delivery confirmation date. The operation returns summarized shipment information optimized for list displays, with full shipment details available through the detail retrieval endpoint.
   *
   * Supports comprehensive pagination with configurable page sizes and sorting options. Results are sorted by creation date (newest first) by default. Soft-deleted shipments are automatically excluded from the result set.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering shipments
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_shipments table with pagination and filtering support. Join with shopping_mall_shipment_items to include order item information. For seller access, filter shipments by order items belonging to the seller's products. For customer access, filter shipments by orders belonging to the customer. Support filtering by order ID, shipment status (shipped, delivered), and date ranges. Include tracking carrier, tracking number, and delivery timestamps in response. Apply cursor-based pagination for large result sets. Ensure soft-deleted shipments are excluded from results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallShipment.IRequest,
  ): Promise<IPageIShoppingMallShipment.ISummary> {
    try {
      return await patchShoppingMallCustomerShipments({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed tracking information for a specific shipment.
   *
   * This endpoint provides complete shipment details including carrier name, tracking number, and delivery lifecycle timestamps. The response includes all order items contained within the shipment, allowing customers to see which products are being delivered together.
   *
   * Shipment tracking information displays the carrier name (e.g., FedEx, UPS, DHL, USPS) and the tracking number provided by the carrier for package tracking. The delivery lifecycle is tracked through multiple timestamps: shipped_at when the seller handed the package to the carrier, delivered_at when the carrier marked the package as delivered, delivery_confirmed_at when the customer manually confirmed receipt, and auto_delivered_at which is system-calculated as shipped_at plus 14 days for automatic delivery confirmation.
   *
   * This operation is accessible to customers viewing shipments for their orders and sellers managing shipments they have created. The endpoint validates user authorization based on order ownership or seller identity.
   *
   * Related operations include GET /customers/orders/{id} for viewing complete order details with all shipments, and POST /customers/shipments/{id}/confirm-delivery for customers to manually confirm delivery receipt.
   *
   * @param connection
   * @param shipmentId Target shipment's UUID identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the shopping_mall_shipments table by the shipment ID path parameter.
   *
   * Join with shopping_mall_shipment_items to retrieve all order items included in this shipment, then join with shopping_mall_order_items to get complete item details including product variant information.
   *
   * Return shipment tracking information: tracking_carrier, tracking_number, shipped_at, delivered_at, delivery_confirmed_at, and auto_delivered_at timestamps.
   *
   * Validate that the requesting user has permission to view this shipment: either the customer who placed the order (via shopping_mall_order_id) or the seller who created the shipment.
   *
   * Handle soft-deleted shipments by returning 404 if deleted_at is not null.
   *
   * Include related order item information: item IDs, product names, variant options, quantities, and current status for each item in the shipment.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment> {
    try {
      return await getShoppingMallCustomerShipmentsShipmentId({
        customer,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update tracking information for an existing shipment.
   *
   * This operation allows sellers to modify the tracking details of a shipment they have created. Sellers can update the carrier name and tracking number to correct errors or provide updated shipping information.
   *
   * The shipment must belong to the authenticated seller. The system validates ownership by checking the relationship between the shipment and the seller through the order items. Only sellers can update shipment tracking information; customers can only view tracking details.
   *
   * Tracking information includes the shipping carrier name (e.g., FedEx, UPS, DHL, USPS) and the tracking number provided by the carrier. These fields are used for package tracking throughout the delivery lifecycle.
   *
   * Related operations:
   * - POST /sellers/shipments: Create a new shipment with initial tracking information
   * - GET /shipments/{shipmentId}: View shipment tracking details
   * - POST /shipments/{shipmentId}/confirm-delivery: Customer confirms delivery receipt
   *
   * @param connection
   * @param shipmentId Target shipment's unique identifier (UUID format)
   * @param body Updated tracking information for the shipment
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update tracking information for an existing shipment.
   *
   * Implementation steps:
   * 1. Authenticate the request and verify actor is a seller
   * 2. Query shopping_mall_shipments table by shipmentId
   * 3. Validate the authenticated seller owns this shipment (check seller_id through order_items relationship)
   * 4. Validate tracking_carrier is non-empty string (e.g., FedEx, UPS, DHL, USPS)
   * 5. Validate tracking_number is non-empty string
   * 6. Update tracking_carrier and tracking_number fields in the shipment record
   * 7. Update the updated_at timestamp
   * 8. Return the complete updated shipment object
   *
   * Business rules:
   * - Only the seller who created the shipment can update it
   * - Tracking information can be updated even after shipment is created
   * - If shipped_at is already set, updates should be allowed (tracking corrections)
   * - Validation: carrier name and tracking number must be provided
   *
   * Edge cases:
   * - Shipment not found: return 404
   * - Seller doesn't own shipment: return 403
   * - Shipment already soft-deleted: return 404
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shipmentId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipment.IUpdate,
  ): Promise<IShoppingMallShipment> {
    try {
      return await putShoppingMallCustomerShipmentsShipmentId({
        customer,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
