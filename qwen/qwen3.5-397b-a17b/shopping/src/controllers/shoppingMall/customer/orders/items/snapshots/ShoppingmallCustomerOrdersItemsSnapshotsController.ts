import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallOrderItemSnapshot } from "../../../../../../api/structures/IPageIShoppingMallOrderItemSnapshot";
import { IShoppingMallOrderItemSnapshot } from "../../../../../../api/structures/IShoppingMallOrderItemSnapshot";
import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersOrderIdItemsItemIdSnapshotsSnapshotId } from "../../../../../../providers/getShoppingMallCustomerOrdersOrderIdItemsItemIdSnapshotsSnapshotId";
import { patchShoppingMallCustomerOrdersOrderIdItemsItemIdSnapshots } from "../../../../../../providers/patchShoppingMallCustomerOrdersOrderIdItemsItemIdSnapshots";

@Controller("/shoppingMall/customer/orders/:orderId/items/:itemId/snapshots")
export class ShoppingmallCustomerOrdersItemsSnapshotsController {
  /**
   * Retrieve snapshots of an order item capturing its state at the time of purchase.
   *
   * This operation returns immutable snapshots that preserve the complete state of the order item including product name, description, variant SKU code, variant price, and seller shop information (name and logo) as they existed when the order was placed. These snapshots ensure accurate historical information for dispute resolution and audit purposes.
   *
   * Snapshots are created automatically when an order is placed and cannot be modified or deleted. Each order item has exactly one snapshot. The snapshots can be viewed by the customer who placed the order and the seller of the order item. Administrators can view snapshots of any order item on the platform.
   *
   * This endpoint requires proper authorization - only the order owner (customer) or the seller of the order item can access the snapshots. The orderId parameter establishes the order context, while itemId identifies the specific order item within that order.
   *
   * @param connection
   * @param orderId Order ID (UUID format)
   * @param itemId Order item ID (UUID format)
   * @param body Pagination and sorting parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_order_item_snapshots table filtered by shopping_mall_order_item_id.
   *
   * First validate that the order item exists by checking shopping_mall_order_items with the provided itemId and that it belongs to the order specified by orderId.
   *
   * Verify authorization: the requesting user must be either (1) the customer who placed the order (shopping_mall_orders.customer_id matches authenticated customer), or (2) the seller of the order item (shopping_mall_order_items.shopping_mall_seller_id matches authenticated seller), or (3) an administrator.
   *
   * Join with shopping_mall_order_items to verify the relationship between orderId and itemId.
   *
   * Return the snapshot record with all fields: id, product_name, product_description, variant_sku_code, variant_price, seller_shop_name, seller_shop_logo, created_at.
   *
   * Since each order item has exactly one snapshot (unique constraint), pagination will typically return a single record. Use standard pagination response format for consistency.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderItemSnapshot.IRequest,
  ): Promise<IPageIShoppingMallOrderItemSnapshot.ISummary> {
    try {
      return await patchShoppingMallCustomerOrdersOrderIdItemsItemIdSnapshots({
        customer,
        orderId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific order item snapshot by its identifier.
   *
   * This operation returns the immutable snapshot of an order item, preserving the exact state of the product, variant, and seller profile at the time of purchase. Snapshots are created automatically when an order is placed and cannot be modified.
   *
   * The snapshot includes the product name, description, variant SKU code, variant price, seller shop name, and seller shop logo as they appeared at purchase time. This ensures accurate historical information for dispute resolution, customer support, and audit trail purposes.
   *
   * The path parameters validate that the snapshot belongs to the specified order and order item, ensuring proper access control and data integrity.
   *
   * @param connection
   * @param orderId Order ID (UUID format)
   * @param itemId Order item ID (UUID format)
   * @param snapshotId Order item snapshot ID (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_order_item_snapshots table by snapshot ID.
   *
   * Validate that the snapshot exists and belongs to the specified order item:
   * 1. Load snapshot by snapshotId
   * 2. Verify snapshot.shopping_mall_order_item_id matches itemId
   * 3. Load order item by itemId
   * 4. Verify order item.shopping_mall_order_id matches orderId
   * 5. Return snapshot if all validations pass
   *
   * Return 404 if snapshot not found or if hierarchy validation fails (snapshot doesn't belong to specified order/item).
   *
   * No authorization check in this operation - authorization middleware handles access control (customer can view their own order snapshots, seller can view snapshots for their order items, admin can view any snapshot).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItemSnapshot> {
    try {
      return await getShoppingMallCustomerOrdersOrderIdItemsItemIdSnapshotsSnapshotId(
        {
          customer,
          orderId,
          itemId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
