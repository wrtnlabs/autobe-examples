import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallOrderItem } from "../../../../../api/structures/IPageIShoppingMallOrderItem";
import { IShoppingMallOrderItem } from "../../../../../api/structures/IShoppingMallOrderItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersOrderIdItemsItemId } from "../../../../../providers/getShoppingMallCustomerOrdersOrderIdItemsItemId";
import { patchShoppingMallCustomerOrdersOrderIdItems } from "../../../../../providers/patchShoppingMallCustomerOrdersOrderIdItems";

@Controller("/shoppingMall/customer/orders/:orderId/items")
export class ShoppingmallCustomerOrdersItemsController {
  /**
   * Retrieve a filtered and paginated list of order items within a specific order.
   *
   * This operation provides detailed access to individual items within an order, supporting status-based filtering to identify items at different fulfillment stages. Each order item represents a purchased product variant with its quantity, price, and current status tracked independently.
   *
   * Supports comprehensive pagination with configurable page sizes and sorting options. Response includes order item summary information with product details, variant options, and seller information optimized for list displays. Useful for order detail views, seller fulfillment dashboards, and administrative order management.
   *
   * Authorization requirements vary by actor: customers can only access items from their own orders, sellers can access items containing their products, and administrators have full access to all order items.
   *
   * @param connection
   * @param orderId Order ID (UUID format, scoped to specific order)
   * @param body Search criteria including status filters, pagination, and sorting parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_order_items table filtered by shopping_mall_order_id. Apply status filters if provided in request body (paid, shipped, delivered, cancelled, refunded). Support pagination with cursor-based or offset-based approach. Join with shopping_mall_products for product name, shopping_mall_product_variants for variant options, and shopping_mall_sellers for seller information. Return order item summaries optimized for list display. Validate that orderId exists in shopping_mall_orders table. Apply authorization: customers can only access their own orders, sellers can access items from their products, administrators can access all orders. Handle edge case where order has no items (return empty page). Sort by created_at descending by default, allow override via request body.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderItem.IRequest,
  ): Promise<IPageIShoppingMallOrderItem.ISummary> {
    try {
      return await patchShoppingMallCustomerOrdersOrderIdItems({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order item within an order.
   *
   * This operation returns complete details of an individual order item including the purchased product, variant, quantity, unit price, and current item status. The order item represents one SKU purchased by a customer as part of a larger order.
   *
   * Customers can access order items from their own orders only. The response includes all item metadata necessary for displaying order details, tracking item status through the fulfillment lifecycle, and supporting cancellation or refund workflows.
   *
   * The order item status indicates the current fulfillment state: paid, shipped, delivered, cancelled, or refunded. Each item in an order can have an independent status, enabling partial shipment and individual item cancellation scenarios.
   *
   * @param connection
   * @param orderId Order ID (UUID format)
   * @param itemId Order item ID (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_order_items table by primary key ID.
   *
   * Validate that the order item exists and belongs to the specified order by checking shopping_mall_order_id matches the orderId parameter.
   *
   * Verify customer authorization: ensure the parent order's customer_id matches the authenticated customer's ID.
   *
   * Join with shopping_mall_products to include product name and details.
   * Join with shopping_mall_product_variants to include variant option information.
   * Join with shopping_mall_sellers to include seller shop information.
   *
   * Return the complete order item record with all fields: id, quantity, price, status, created_at, updated_at.
   *
   * Handle edge cases:
   * - Order item not found: return 404
   * - Order item belongs to different order: return 404
   * - Customer not authorized to view this order: return 403
   * - Soft-deleted order item: return 404
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await getShoppingMallCustomerOrdersOrderIdItemsItemId({
        customer,
        orderId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
