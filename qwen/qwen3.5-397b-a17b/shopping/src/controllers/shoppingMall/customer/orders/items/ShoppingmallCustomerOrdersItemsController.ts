import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallOrderItem } from "../../../../../api/structures/IPageIShoppingMallOrderItem";
import { IShoppingMallOrderItem } from "../../../../../api/structures/IShoppingMallOrderItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersOrderIdItemsItemId } from "../../../../../providers/getShoppingMallCustomerOrdersOrderIdItemsItemId";
import { getShoppingMallCustomerOrdersOrderIdItemsOrderItemId } from "../../../../../providers/getShoppingMallCustomerOrdersOrderIdItemsOrderItemId";
import { patchShoppingMallCustomerOrdersOrderIdItems } from "../../../../../providers/patchShoppingMallCustomerOrdersOrderIdItems";

@Controller("/shoppingMall/customer/orders/:orderId/items")
export class ShoppingmallCustomerOrdersItemsController {
  /**
   * Retrieve a filtered and paginated list of order items within a specific order.
   *
   * This operation provides detailed listing of all line items contained in an order, with support for filtering by item status, date ranges, and other criteria. Each order item represents a specific product variant purchase with quantity and unit price captured at order time.
   *
   * Order items maintain dual references: current entities (product variant, seller) for operational purposes and historical snapshots (product snapshot, product variant snapshot) for order history integrity. This ensures order records remain accurate even if products or variants change after purchase.
   *
   * Item statuses follow a workflow: PAID (payment confirmed), SHIPPED (sent to customer), DELIVERED (received by customer), CANCELLED (order cancelled before shipment), or REFUNDED (refund processed after delivery). Each item's status is managed independently from other items in the same order.
   *
   * Authorization requires the user to either own the order (customer) or have administrative privileges. Response includes order item summary information with product details, variant options, pricing, status, and seller information optimized for list displays.
   *
   * @param connection
   * @param orderId Target order's ID (UUID format)
   * @param body Search criteria and pagination parameters for filtering order items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_order_items table filtered by shopping_mall_order_id. Apply search filters from request body including status filtering, date ranges, and seller filtering. Join with shopping_mall_product_variants for current product info, shopping_mall_product_snapshots for historical product state, shopping_mall_product_variant_snapshots for historical variant state, and shopping_mall_sellers for seller information. Implement cursor-based pagination for large result sets. Validate that requesting user has access to the order (customer owns order or user is admin). Return order item summaries optimized for list displays with product name, variant options, quantity, unit price, item status, and seller info.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderItem.IRequest,
  ): Promise<IPageIShoppingMallOrderItem.ISummary> {
    try {
      return await patchShoppingMallCustomerOrdersOrderIdItems({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order item within a customer's order.
   *
   * This operation provides comprehensive details about a single purchased item including the product variant configuration, quantity, unit price, current fulfillment status, and references to historical product snapshots. The order item maintains dual references to both current entities (for operational purposes) and historical snapshots (for order history integrity).
   *
   * Customers can only access order items belonging to their own orders. The endpoint validates that the specified orderId belongs to the authenticated customer before returning the item details. This ensures proper data isolation and prevents unauthorized access to other customers' purchase history.
   *
   * The order item status indicates the current fulfillment state: PAID (payment confirmed), SHIPPED (sent to customer), DELIVERED (received by customer), CANCELLED (order cancelled before shipment), or REFUNDED (refund processed after delivery). This status is essential for determining eligible actions such as cancellation requests, refund requests, or review creation.
   *
   * Related operations include GET /orders/{orderId} for viewing the complete order with all items, POST /customers/order-items/{itemId}/cancellation for requesting cancellation, POST /customers/order-items/{itemId}/refund for requesting refunds, and POST /customers/order-items/{itemId}/review for creating product reviews.
   *
   * @param connection
   * @param orderId Target order's ID (UUID format, scoped to customer's orders)
   * @param orderItemId Target order item's ID (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the shopping_mall_order_items table for the specified orderItemId. Validate that the parent order (via shopping_mall_order_id) belongs to the authenticated customer by joining with shopping_mall_orders table and checking customer_id matches the session user. Return 404 if order item not found or if order belongs to different customer.
   *
   * Include related entity data through joins or separate queries:
   * - Product variant details from shopping_mall_product_variants (sku_code, option_values)
   * - Product snapshot from shopping_mall_product_snapshots (name, description, base_price)
   * - Product variant snapshot from shopping_mall_product_variant_snapshots (option_values, price, stock_quantity at order time)
   * - Seller information from shopping_mall_sellers (shop_name)
   *
   * Transform the database record to IShoppingMallOrderItem response DTO, mapping status enum and formatting timestamps. Ensure all snapshot references are populated for historical accuracy.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderItemId")
  public async getByOrderidAndOrderitemid(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await getShoppingMallCustomerOrdersOrderIdItemsOrderItemId({
        customer,
        orderId,
        orderItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order item within a customer's order.
   *
   * This operation returns comprehensive details about a single purchased item including the product variant configuration, quantity, unit price, current fulfillment status, and references to historical snapshots that preserve the product state at order time. The order item maintains dual references: current entities (product variant, seller) for operational purposes and historical snapshots (product snapshot, product variant snapshot) ensuring order records remain accurate even if products or variants are modified after purchase.
   *
   * The order item status indicates the current fulfillment state: PAID (payment confirmed), SHIPPED (sent to customer), DELIVERED (received by customer), CANCELLED (order cancelled before shipment), or REFUNDED (refund processed after delivery). Each order item maintains its own independent status separate from other items in the same order.
   *
   * This endpoint is accessible to the customer who owns the order, the seller who listed the product, and administrators. The orderId path parameter ensures the item is retrieved within the context of its parent order, providing proper authorization scope.
   *
   * Related operations include GET /customers/orders for viewing the complete order list, GET /customers/orders/{orderId} for full order details, POST /customers/order-items/{itemId}/cancellation for requesting item cancellation, POST /customers/order-items/{itemId}/refund for requesting item refund, and POST /customers/order-items/{itemId}/review for submitting a product review after delivery.
   *
   * @param connection
   * @param orderId Target order's ID (UUID format)
   * @param itemId Target order item's ID (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the shopping_mall_order_items table by itemId and verify the shopping_mall_order_id matches the provided orderId path parameter.
   *
   * Join with shopping_mall_product_snapshots to retrieve the historical product state (name, description, base price, category) at order time.
   *
   * Join with shopping_mall_product_variant_snapshots to retrieve the historical variant state (SKU code, option values, price, stock quantity) at order time.
   *
   * Join with shopping_mall_sellers to retrieve current seller information (shop name, shop description).
   *
   * Verify authorization: the authenticated user must be either (1) the customer who owns the order (shopping_mall_orders.customer_id matches authenticated customer), (2) the seller who listed the product (shopping_mall_order_items.shopping_mall_seller_id matches authenticated seller), or (3) an administrator.
   *
   * Return the order item with all joined snapshot and seller data. If the order item is soft-deleted (deleted_at is not null) and the user is not an administrator, return 404 Not Found.
   *
   * Handle edge cases: if orderId does not exist, return 404. If itemId does not exist or does not belong to the specified orderId, return 404. If user lacks authorization, return 403 Forbidden.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async getByOrderidAndItemid(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await getShoppingMallCustomerOrdersOrderIdItemsItemId({
        customer,
        orderId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
