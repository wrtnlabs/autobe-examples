import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallAdminPromotionRequest } from "../../../../api/structures/IPageIShoppingMallAdminPromotionRequest";
import { IShoppingMallAdminPromotionRequest } from "../../../../api/structures/IShoppingMallAdminPromotionRequest";
