import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallAdministrator } from "../../../../api/structures/IPageIShoppingMallAdministrator";
import { IShoppingMallAdministrator } from "../../../../api/structures/IShoppingMallAdministrator";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { getShoppingMallSuperAdminAdministratorsAdministratorId } from "../../../../providers/getShoppingMallSuperAdminAdministratorsAdministratorId";
import { patchShoppingMallSuperAdminAdministrators } from "../../../../providers/patchShoppingMallSuperAdminAdministrators";
import { putShoppingMallSuperAdminAdministratorsAdministratorId } from "../../../../providers/putShoppingMallSuperAdminAdministratorsAdministratorId";

@Controller("/shoppingMall/superAdmin/administrators")
export class ShoppingmallSuperadminAdministratorsController {
  /**
   * Retrieves a paginated list of administrators on the platform with filtering and search capabilities.
   *
   * This endpoint allows administrators to browse all administrator accounts, filter by grade level and status, and search for specific administrators. The response includes administrator profile information, grade level, account status, and creation timestamps.
   *
   * Administrators can filter results by grade (regular or super), account status (active, banned, or deleted), and registration date range. The endpoint supports pagination for large result sets. Only authenticated administrators can access this endpoint.
   *
   * @param connection
   * @param body Search criteria for filtering administrators including grade level, account status, date ranges, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor superAdmin
     * @x-autobe-specification Query shopping_mall_administrators table with
     *   pagination and filtering. Join with shopping_mall_admins to access
     *   banned_at status and email. Join with shopping_mall_members to access
     *   member profile information (display name, phone). Apply filters: grade
     *   (regular/super), status (active/banned/deleted based on deleted_at and
     *   banned_at), date range on created_at. Return paginated results with
     *   cursor-based pagination. Only administrators can access this endpoint.
     *   Exclude currently logged-in administrator from results if needed for
     *   security. Sort by created_at descending by default.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IShoppingMallAdministrator.IRequest,
  ): Promise<IPageIShoppingMallAdministrator.ISummary> {
    try {
      return await patchShoppingMallSuperAdminAdministrators({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information about a specific administrator account.
   *
   * This endpoint returns the complete administrator profile including grade level (regular or super), associated member account reference, and account status timestamps. Super administrators use this operation to view administrator details when managing grade levels or reviewing administrator accounts.
   *
   * The response includes the administrator's grade, creation timestamp, last update timestamp, and soft delete status. The associated member account information can be accessed through the member relationship for complete user context.
   *
   * @param connection
   * @param administratorId Unique identifier of the administrator account (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor superAdmin
     * @x-autobe-specification Query the shopping_mall_administrators table by
     *   the provided administratorId UUID.
   *
   * Return the full administrator record including: id, shopping_mall_member_id, grade, created_at, updated_at, deleted_at.
   *
   * Join with shopping_mall_members table if member profile information is needed in the response.
   *
   * Return 404 if administrator not found or if the record is soft-deleted and caller lacks permission to view deleted records.
   *
   * Ensure caller has appropriate administrator privileges to access this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":administratorId")
  public async at(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("administratorId")
    administratorId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdministrator> {
    try {
      return await getShoppingMallSuperAdminAdministratorsAdministratorId({
        superAdmin,
        administratorId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an administrator's profile information including grade level.
   *
   * This endpoint allows super administrators to modify administrator attributes, primarily used for grade management operations such as promoting regular administrators to super administrator status or demoting other super administrators to regular administrator.
   *
   * Super administrators can promote regular administrators to super administrator grade. Super administrators can demote other super administrators to regular administrator grade. However, super administrators cannot demote themselves to regular administrator - this self-demotion prohibition ensures the platform always retains at least one super administrator with full administrative capabilities.
   *
   * Regular administrators cannot use this endpoint to change administrator grades. When an administrator is demoted, their administrator profile is soft deleted (deleted_at timestamp set) while preserving the base member account and audit trails.
   *
   * @param connection
   * @param administratorId Unique identifier of the administrator to update (UUID format).
   * @param body Update request containing administrator fields to modify. Grade field controls promotion/demotion operations.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor superAdmin
     * @x-autobe-specification Update the administrator record identified by
     *   administratorId.
   *
   * 1. Authentication: Require super administrator authentication. Reject requests from regular administrators or non-admin users.
   *
   * 2. Authorization: Verify the authenticated user is a super administrator. For demotion operations (changing grade from 'super' to 'regular'), validate that the target administratorId is NOT the same as the authenticated user's administrator ID (self-demotion prohibition).
   *
   * 3. Validation:
   *    - Verify administratorId exists in shopping_mall_administrators table
   *    - Verify administrator is not already soft deleted (deleted_at is null)
   *    - Validate grade value is either 'regular' or 'super'
   *    - If grade change requested, verify authenticated user has permission
   *
   * 4. Database Operations:
   *    - For grade promotion (regular → super): Update grade field to 'super', set updated_at
   *    - For grade demotion (super → regular): Set deleted_at timestamp (soft delete), update grade to 'regular', set updated_at
   *    - For other field updates: Update respective fields, set updated_at
   *
   * 5. Response: Return the updated IShoppingMallAdministrator entity with all current field values.
   *
   * 6. Error Handling:
   *    - 404: Administrator not found or already soft deleted
   *    - 403: Regular administrator attempting grade changes, or super admin attempting self-demotion
   *    - 400: Invalid grade value or validation failures
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":administratorId")
  public async update(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("administratorId")
    administratorId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdministrator.IUpdate,
  ): Promise<IShoppingMallAdministrator> {
    try {
      return await putShoppingMallSuperAdminAdministratorsAdministratorId({
        superAdmin,
        administratorId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
