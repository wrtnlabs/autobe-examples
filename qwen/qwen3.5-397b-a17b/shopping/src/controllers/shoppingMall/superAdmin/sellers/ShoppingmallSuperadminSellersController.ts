import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { putShoppingMallSuperAdminSellersSellerId } from "../../../../providers/putShoppingMallSuperAdminSellersSellerId";

@Controller("/shoppingMall/superAdmin/sellers/:sellerId")
export class ShoppingmallSuperadminSellersController {
  /**
   * Update a seller's shop profile information including name, description, and logo image.
   *
   * This operation allows modification of seller profile attributes that represent the shop's public-facing identity. Sellers can update their own shop profile to reflect changes in branding, business description, or visual identity. Administrators can also update any seller's profile for platform management purposes.
   *
   * The update operation modifies the shop_name, shop_description, and logo_image_url fields of the seller record. Changes to these fields are significant as they affect how the shop appears to customers throughout the platform. The shop_name serves as the primary identifier for the seller's store, shop_description provides detailed information about products and business focus, and logo_image_url displays the shop's visual brand.
   *
   * Authorization requires either seller actor updating their own profile (sellerId must match authenticated seller's ID) or admin actor with platform management privileges. When a seller updates their profile, the system automatically creates a snapshot to preserve the historical state before changes are applied, enabling audit trail and version tracking.
   *
   * This endpoint is typically used after initial seller registration approval, allowing sellers to refine their shop presentation as their business evolves. Profile updates take effect immediately and are reflected in all customer-facing views of the seller's shop and products.
   *
   * @param connection
   * @param sellerId Target seller's unique identifier (UUID format)
   * @param body Seller profile update information with shop branding fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Update seller profile by sellerId path parameter.
   *
   * 1. Validate sellerId exists and is not soft deleted
   * 2. Check authorization: authenticated seller's ID matches sellerId OR user has admin role
   * 3. Validate request body fields:
   *    - shop_name: required, non-empty string, max length validation
   *    - shop_description: optional string, max length validation
   *    - logo_image_url: optional string, valid URL format, max 80000 characters
   * 4. Query shopping_mall_sellers table for target seller
   * 5. Create snapshot record before applying changes (capture current state)
   * 6. Update fields: shop_name, shop_description, logo_image_url
   * 7. Update updated_at timestamp to current time
   * 8. Return updated seller entity with all fields
   *
   * Edge cases:
   * - Seller not found: return 404
   * - Unauthorized (wrong seller updating another's profile): return 403
   * - Invalid URL format for logo_image_url: return 400
   * - Empty shop_name: return 400
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSeller.IUpdate,
  ): Promise<IShoppingMallSeller> {
    try {
      return await putShoppingMallSuperAdminSellersSellerId({
        superAdmin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
