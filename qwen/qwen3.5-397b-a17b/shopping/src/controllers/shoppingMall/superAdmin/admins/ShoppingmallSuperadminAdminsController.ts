import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallAdmin } from "../../../../api/structures/IPageIShoppingMallAdmin";
import { IShoppingMallAdmin } from "../../../../api/structures/IShoppingMallAdmin";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { getShoppingMallSuperAdminAdminsAdminId } from "../../../../providers/getShoppingMallSuperAdminAdminsAdminId";
import { patchShoppingMallSuperAdminAdmins } from "../../../../providers/patchShoppingMallSuperAdminAdmins";
import { putShoppingMallSuperAdminAdminsAdminId } from "../../../../providers/putShoppingMallSuperAdminAdminsAdminId";

@Controller("/shoppingMall/superAdmin/admins")
export class ShoppingmallSuperadminAdminsController {
  /**
   * Retrieve a paginated list of administrator accounts with search and filtering capabilities.
   *
   * This endpoint allows super administrators to browse all administrator accounts on the platform, including both regular administrators and super administrators. The operation supports filtering by administrator grade level, ban status, email search, and creation date ranges.
   *
   * Administrators can use this endpoint to monitor administrator accounts, find specific administrators by email, or review administrators by their permission level. The response includes summary information for each administrator optimized for list display.
   *
   * Only super administrators can access this endpoint to view all administrators. Regular administrators cannot list other administrators. Banned and soft-deleted administrators can be included in results using appropriate filters for audit purposes.
   *
   * @param connection
   * @param body Search criteria including email search, grade filter, ban status filter, deletion status filter, date range filters, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor superAdmin
     * @x-autobe-specification Query the shopping_mall_admins table with
     *   pagination and filtering support.
   *
   * Apply search filters:
   * - Email: partial match search on email field
   * - Grade: exact match filter for 'regular' or 'super'
   * - Banned status: filter by banned_at null (active) or not null (banned)
   * - Deleted status: filter by deleted_at null (active) or not null (removed)
   * - Date range: filter by created_at within specified range
   *
   * Join with shopping_mall_administrators table if grade information from the profile is needed, though grade is duplicated in shopping_mall_admins.
   *
   * Apply cursor-based or offset pagination based on request parameters.
   *
   * Sort results by created_at descending (newest first) by default, with optional sort field and order overrides.
   *
   * Return IPageIShoppingMallAdmin.ISummary with pagination metadata (page, limit, total count).
   *
   * Exclude password_hash from response. Include id, email, grade, banned_at, created_at, and computed status fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IShoppingMallAdmin.IRequest,
  ): Promise<IPageIShoppingMallAdmin.ISummary> {
    try {
      return await patchShoppingMallSuperAdminAdmins({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single administrator account by unique identifier.
   *
   * This endpoint returns the complete administrator profile including grade level (regular or super), ban status, and account metadata. Super administrators use this operation to view administrator details before performing grade management operations such as promotions or demotions.
   *
   * The response includes the administrator's email, grade level, ban status timestamp, and account creation/modification timestamps. The password_hash field is never exposed through this API for security reasons.
   *
   * Administrators can view other administrator accounts for oversight purposes. Regular administrators can view all administrators except super administrators. Super administrators have full visibility into all administrator accounts including other super administrators.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor superAdmin
     * @x-autobe-specification Query shopping_mall_admins table by primary key
     *   id (UUID). Return the full administrator record excluding password_hash
     *   field for security. Join with shopping_mall_members if member profile
     *   information is needed. Validate that the requesting user has
     *   administrator privileges. For regular administrators, restrict access
     *   to super administrator records. Handle 404 Not Found when adminId does
     *   not exist or record is soft-deleted. Handle 403 Forbidden when regular
     *   administrator attempts to access super administrator details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await getShoppingMallSuperAdminAdminsAdminId({
        superAdmin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an administrator account's grade level and ban status.
   *
   * This endpoint allows super administrators to promote regular administrators to super administrator grade, demote other super administrators to regular administrator grade, or ban/unban administrator accounts. The operation modifies the administrator's permission level and access status.
   *
   * Super administrators cannot demote themselves through this endpoint to prevent privilege escalation vulnerabilities. When banning an administrator, the banned_at timestamp is set, preventing login while preserving audit trails. Unbanning clears the banned_at timestamp.
   *
   * The administrator's email and password cannot be modified through this endpoint as they are authentication credentials managed through separate account management operations.
   *
   * @param connection
   * @param adminId Administrator account ID (UUID format).
   * @param body Administrator update data including grade level and ban status. Email and password cannot be updated through this endpoint.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor superAdmin
     * @x-autobe-specification Update shopping_mall_admins record by adminId
     *   UUID.
   *
   * Validate that the requesting user is a super administrator.
   * Validate that the super administrator is not attempting to demote themselves (check if adminId matches the requester's ID and new grade is 'regular').
   *
   * For grade updates: verify grade value is either 'regular' or 'super'. Update the grade field in the database.
   *
   * For ban status updates: if banned_at is provided, set the timestamp; if null is provided, clear the banned_at field to unban.
   *
   * Do not allow updates to email or password_hash fields through this endpoint - these are authentication credentials managed separately.
   *
   * Return the updated administrator record with all fields.
   *
   * Handle edge cases: admin not found (404), insufficient permissions (403), self-demotion attempt (403).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdmin.IUpdate,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await putShoppingMallSuperAdminAdminsAdminId({
        superAdmin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
