import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { deleteShoppingMallAdministratorProductsProductId } from "../../../../providers/deleteShoppingMallAdministratorProductsProductId";

@Controller("/shoppingMall/administrator/products/:productId")
export class ShoppingmallAdministratorProductsController {
  /**
   * Permanently delete a product and all its associated variants from the seller's catalog.
   *
   * This operation removes the product from search results and category listings. The deletion is subject to business constraints: the product cannot be deleted if any variant has pending order items with paid or shipped status, or if there are any pending cancellation or refund requests for any variant.
   *
   * When a product is deleted, all associated product variants and their inventory records are automatically deleted through cascade deletion. Product snapshots are preserved for historical order records and remain accessible to the seller and administrators. Deleted products cannot be recovered through the API.
   *
   * @param connection
   * @param productId Product ID (UUID format, global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Delete a product by productId after validating business constraints.
   *
   * 1. Verify the product exists and belongs to the authenticated seller (check seller_id matches).
   * 2. Check for pending order items: Query shopping_mall_order_items where shopping_mall_product_id = productId AND status IN ('paid', 'shipped'). If any exist, reject with 409 Conflict.
   * 3. Check for pending cancellation requests: Query shopping_mall_cancellation_requests joined with order_items where product matches AND status = 'pending'. If any exist, reject with 409 Conflict.
   * 4. Check for pending refund requests: Query shopping_mall_refund_requests joined with order_items where product matches AND status = 'pending'. If any exist, reject with 409 Conflict.
   * 5. If all validations pass, soft-delete the product by setting deleted_at to current timestamp.
   * 6. Cascade deletion automatically removes all shopping_mall_product_variants (onDelete: Cascade).
   * 7. Return 204 No Content on success.
   *
   * Error cases:
   * - 404 Not Found: Product does not exist or already deleted
   * - 403 Forbidden: Product does not belong to the authenticated seller
   * - 409 Conflict: Deletion blocked due to pending orders or requests
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdministratorProductsProductId({
        administrator,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
