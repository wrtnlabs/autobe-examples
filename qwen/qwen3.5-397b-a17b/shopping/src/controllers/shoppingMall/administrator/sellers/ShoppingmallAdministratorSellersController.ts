import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallSeller } from "../../../../api/structures/IPageIShoppingMallSeller";
import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getShoppingMallAdministratorSellersSellerId } from "../../../../providers/getShoppingMallAdministratorSellersSellerId";
import { patchShoppingMallAdministratorSellers } from "../../../../providers/patchShoppingMallAdministratorSellers";

@Controller("/shoppingMall/administrator/sellers")
export class ShoppingmallAdministratorSellersController {
  /**
   * Retrieve a filtered and paginated list of seller accounts on the platform.
   *
   * This operation provides administrators with comprehensive seller account management capabilities including email-based search, approval status filtering, and account creation date range queries. The endpoint supports pagination for browsing large seller populations.
   *
   * Returns seller summary information including email, account creation date, and current approval status. Approval status is derived from the most recent approval request in shopping_mall_seller_approval_requests table. Results can be sorted by creation date or email.
   *
   * @param connection
   * @param body Search criteria including email filter, approval status filter, date range, and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query shopping_mall_sellers table with pagination and filtering. Join with shopping_mall_seller_approval_requests to get current approval status (use latest request per seller by submitted_at DESC). Apply search filters on email (partial match), status (exact match: pending/approved/rejected), and created_at date range. Exclude soft-deleted sellers (deleted_at IS NULL). Return cursor-based pagination with configurable page size. Sort by created_at DESC by default, support email ASC/DESC. Do not include seller profile data in summary - that requires separate endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IShoppingMallSeller.IRequest,
  ): Promise<IPageIShoppingMallSeller.ISummary> {
    try {
      return await patchShoppingMallAdministratorSellers({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific seller account including their shop profile.
   *
   * This operation returns the seller's authentication account details along with their public shop profile containing shop name, description, and logo image. The response includes the complete seller profile information that customers view when browsing seller shops.
   *
   * Administrators use this endpoint to review seller accounts during the approval process. Customers use this to view seller shop information before making purchases. The operation returns 404 if the seller does not exist or has been deleted.
   *
   * @param connection
   * @param sellerId Seller account UUID identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query shopping_mall_sellers table by UUID primary key.
   * Join with shopping_mall_seller_profiles on seller_id to include profile information.
   * Return seller with nested profile object using IInvert pattern.
   * Handle 404 for non-existent or soft-deleted sellers.
   * Exclude password_hash from response for security.
   * Ensure profile is included even if null (seller registered but profile not yet created).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSeller.IInvert> {
    try {
      return await getShoppingMallAdministratorSellersSellerId({
        administrator,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
