import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallSellerProfileSnapshot } from "../../../../../../api/structures/IPageIShoppingMallSellerProfileSnapshot";
import { IShoppingMallSellerProfileSnapshot } from "../../../../../../api/structures/IShoppingMallSellerProfileSnapshot";
import { AdministratorAuth } from "../../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../../decorators/payload/AdministratorPayload";
import { getShoppingMallAdministratorSellersSellerIdProfileSnapshotsSnapshotId } from "../../../../../../providers/getShoppingMallAdministratorSellersSellerIdProfileSnapshotsSnapshotId";
import { patchShoppingMallAdministratorSellersSellerIdProfileSnapshots } from "../../../../../../providers/patchShoppingMallAdministratorSellersSellerIdProfileSnapshots";

@Controller("/shoppingMall/administrator/sellers/:sellerId/profile/snapshots")
export class ShoppingmallAdministratorSellersProfileSnapshotsController {
  /**
   * Retrieve a paginated list of seller profile snapshots for a specific seller.
   *
   * This operation provides access to the immutable audit trail of all changes made to a seller's shop profile. Each snapshot preserves the complete state of the shop name, description, and logo image at the moment of modification, along with the timestamp when the change was made.
   *
   * Sellers can view snapshots of their own profile to track changes over time. Administrators can view snapshots of any seller's profile for oversight and dispute resolution purposes. Snapshots are created automatically whenever the seller updates their profile information and cannot be modified or deleted.
   *
   * Supports filtering by date range and pagination for navigating through snapshot history. Results are sorted by creation timestamp in descending order (newest first) by default.
   *
   * @param connection
   * @param sellerId Seller account ID (UUID format)
   * @param body Pagination and optional date range filtering parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query shopping_mall_seller_profile_snapshots table joined with shopping_mall_seller_profiles on shopping_mall_seller_profile_id = shopping_mall_seller_profiles.id, filtered by shopping_mall_seller_profiles.seller_id = {sellerId}.
   *
   * Apply pagination parameters (page, limit) from request body. Support optional date range filtering (fromDate, toDate) to limit snapshots by created_at timestamp.
   *
   * Sort results by created_at DESC by default. Return IPageIShoppingMallSellerProfileSnapshot.ISummary with snapshot metadata including id, shop_name, description, logo_image_uri, and created_at.
   *
   * Validate seller exists and is accessible by authenticated user (seller can only access own snapshots, administrators can access any). Return 404 if seller not found or deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSellerProfileSnapshot.IRequest,
  ): Promise<IPageIShoppingMallSellerProfileSnapshot.ISummary> {
    try {
      return await patchShoppingMallAdministratorSellersSellerIdProfileSnapshots(
        {
          administrator,
          sellerId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific seller profile snapshot by its unique identifier.
   *
   * This operation returns the complete state of a seller's shop profile at a specific point in time, including the shop name, description, and logo image URL that were active when the snapshot was created. Snapshots are automatically generated whenever a seller updates their profile information.
   *
   * Snapshots are immutable audit records used for dispute resolution and historical verification. Both sellers and administrators can access snapshot history, while customers can view current seller profiles but not historical snapshots.
   *
   * The snapshot includes the timestamp when it was created, allowing users to understand the chronological sequence of profile changes.
   *
   * @param connection
   * @param sellerId Seller ID (UUID format)
   * @param snapshotId Snapshot ID (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query shopping_mall_seller_profile_snapshots table by snapshot ID.
   *
   * Validate that the snapshotId exists and belongs to the specified sellerId by joining with shopping_mall_seller_profiles on sellerProfile relation.
   *
   * Return the complete snapshot record including id, shopping_mall_seller_profile_id, shop_name, description, logo_image_uri, and created_at.
   *
   * If snapshot not found or sellerId mismatch, return 404 Not Found.
   *
   * No authorization check needed here - authorization middleware handles actor permissions based on endpoint configuration.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerProfileSnapshot> {
    try {
      return await getShoppingMallAdministratorSellersSellerIdProfileSnapshotsSnapshotId(
        {
          administrator,
          sellerId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
