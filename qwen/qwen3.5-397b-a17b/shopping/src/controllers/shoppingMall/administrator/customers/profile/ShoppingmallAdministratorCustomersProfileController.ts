import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallCustomerProfile } from "../../../../../api/structures/IShoppingMallCustomerProfile";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getShoppingMallAdministratorCustomersCustomerIdProfile } from "../../../../../providers/getShoppingMallAdministratorCustomersCustomerIdProfile";

@Controller("/shoppingMall/administrator/customers/:customerId/profile")
export class ShoppingmallAdministratorCustomersProfileController {
  /**
   * Retrieve a customer's profile information by customer ID.
   *
   * This operation returns the complete profile data for a specific customer, including their display name and phone number. The display name is shown to sellers and other users throughout the platform, including on reviews and order confirmations. The phone number is used for order-related communications and shipping purposes.
   *
   * The profile is linked to the customer's authentication account and can be edited by the customer at any time. Profile edits do not create snapshots; only the current profile values are maintained.
   *
   * @param connection
   * @param customerId Customer's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query shopping_mall_customer_profiles table filtering by shopping_mall_customer_id matching the customerId path parameter.
   *
   * Join with shopping_mall_customers to verify the customer exists and is not soft deleted (deleted_at IS NULL).
   *
   * Return the full profile entity including display_name, phone_number, and timestamps.
   *
   * Handle 404 if customer or profile does not exist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerProfile> {
    try {
      return await getShoppingMallAdministratorCustomersCustomerIdProfile({
        administrator,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
