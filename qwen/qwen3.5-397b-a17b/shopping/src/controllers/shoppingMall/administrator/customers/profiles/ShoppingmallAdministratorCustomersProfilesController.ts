import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomerProfile } from "../../../../../api/structures/IShoppingMallCustomerProfile";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { putShoppingMallAdministratorCustomersProfiles } from "../../../../../providers/putShoppingMallAdministratorCustomersProfiles";

@Controller("/shoppingMall/administrator/customers/profiles")
export class ShoppingmallAdministratorCustomersProfilesController {
  /**
   * Update the authenticated customer's profile information including display name and phone number.
   *
   * This operation allows customers to modify their profile details that are shown in orders, reviews, and profile pages. The display name identifies the customer to other users, while the phone number is used for order notifications and support communications.
   *
   * Profile updates are applied immediately and reflected across the platform. Each profile modification creates an immutable snapshot in shopping_mall_customer_profile_snapshots for audit trail purposes, recording the previous values and change timestamp.
   *
   * Only the authenticated customer can update their own profile. The operation validates that provided values meet format requirements before persisting changes.
   *
   * @param connection
   * @param body Profile fields to update - display name and/or phone number
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Update shopping_mall_customer_profiles record for the authenticated customer.
   *
   * 1. Extract customer ID from authenticated session token
   * 2. Validate request body fields:
   *    - display_name: non-empty string, trimmed
   *    - phone_number: valid phone number format
   * 3. Query shopping_mall_customer_profiles by shopping_mall_customer_id
   * 4. If profile not found, return 404 error
   * 5. Create snapshot record in shopping_mall_customer_profile_snapshots with old values before update
   * 6. Update display_name and phone_number fields
   * 7. Set updated_at to current timestamp
   * 8. Return updated profile object
   *
   * Edge cases:
   * - Profile doesn't exist: return 404
   * - Invalid phone format: return 400 validation error
   * - Empty display name: return 400 validation error
   * - Concurrent updates: use optimistic locking via updated_at
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IShoppingMallCustomerProfile.IUpdate,
  ): Promise<IShoppingMallCustomerProfile> {
    try {
      return await putShoppingMallAdministratorCustomersProfiles({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
