import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallCartItem } from "../../../../../api/structures/IShoppingMallCartItem";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getShoppingMallAdministratorCartsCartIdItemsItemId } from "../../../../../providers/getShoppingMallAdministratorCartsCartIdItemsItemId";
import { patchShoppingMallAdministratorCartsCartIdItems } from "../../../../../providers/patchShoppingMallAdministratorCartsCartIdItems";

@Controller("/shoppingMall/administrator/carts/:cartId/items")
export class ShoppingmallAdministratorCartsItemsController {
  /**
   * Update quantities or remove items in a customer's shopping cart.
   *
   * This operation allows customers to modify existing cart items by changing quantities or removing items entirely. Multiple items can be updated in a single request for efficient cart management. When quantity is set to 0 or the remove flag is true, the item is soft deleted from the cart.
   *
   * The cart total price is recalculated based on the updated quantities. Items marked as unavailable (due to out of stock variants or deleted products) cannot be modified and will be ignored in the update operation.
   *
   * Only the cart owner (authenticated customer) can modify their cart items. Attempts to modify another customer's cart will be rejected.
   *
   * @param connection
   * @param cartId Cart ID (UUID format)
   * @param body Cart item updates with quantity changes or removal flags
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Validate that the cartId exists and belongs to the authenticated customer. For each item update in the request body: verify the cart item exists and is not soft deleted, check that the item is not marked as unavailable. If quantity is provided and greater than 0, update the quantity field. If quantity is 0 or remove flag is true, set deleted_at timestamp to current time. Validate that quantity does not exceed available stock for the variant. After all updates, recalculate cart totals. Return the updated cart items with their current state including availability status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCartItem.IUpdate,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await patchShoppingMallAdministratorCartsCartIdItems({
        administrator,
        cartId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific item from a customer's shopping cart by its unique identifier.
   *
   * This operation returns the complete details of a single cart item including the product variant reference, quantity, unit price snapshot captured at time of addition, and timestamps. The cart item is accessed through its parent cart to ensure proper data isolation and ownership validation.
   *
   * The unit price is denormalized as a snapshot to maintain consistent display and checkout calculation even if the product variant's price changes after the item was added to the cart. This operation verifies that the cart item belongs to the specified cart and has not been soft deleted.
   *
   * @param connection
   * @param cartId Cart unique identifier (UUID)
   * @param itemId Cart item unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query shopping_mall_cart_items table by item ID with cart ID verification.
   *
   * 1. Verify cart exists and belongs to authenticated customer (data isolation)
   * 2. Verify cart item exists with matching cart_id and item id
   * 3. Verify cart item is not soft deleted (deleted_at is null)
   * 4. Join with shopping_mall_product_variants to include variant details
   * 5. Join with shopping_mall_products for product name and image information
   * 6. Return full cart item entity with variant and product details
   *
   * Edge cases:
   * - Cart not found → 404
   * - Cart item not found → 404
   * - Cart item belongs to different cart → 404
   * - Cart item is soft deleted → 404
   * - Customer does not own the cart → 403
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await getShoppingMallAdministratorCartsCartIdItemsItemId({
        administrator,
        cartId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
