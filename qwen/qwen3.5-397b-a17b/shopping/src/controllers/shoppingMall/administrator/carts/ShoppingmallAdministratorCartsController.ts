import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCart } from "../../../../api/structures/IPageIShoppingMallCart";
import { IShoppingMallCart } from "../../../../api/structures/IShoppingMallCart";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getShoppingMallAdministratorCartsCartId } from "../../../../providers/getShoppingMallAdministratorCartsCartId";
import { patchShoppingMallAdministratorCarts } from "../../../../providers/patchShoppingMallAdministratorCarts";

@Controller("/shoppingMall/administrator/carts")
export class ShoppingmallAdministratorCartsController {
  /**
   * Retrieve a filtered and paginated list of shopping carts.
   *
   * This operation provides administrative visibility into customer carts with advanced search capabilities including customer filtering, creation date ranges, and cart status filtering (active vs deleted).
   *
   * Supports comprehensive pagination with configurable page sizes and sorting options. Response includes cart summary information optimized for list displays, excluding detailed cart items for performance.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for cart listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query shopping_mall_carts table with pagination and filtering.
   * Apply search filters on customer_id, creation date range, and deleted_at status.
   * Join with shopping_mall_customers for customer information if requested.
   * Join with shopping_mall_cart_items for item count aggregation.
   * Exclude soft-deleted carts by default unless explicitly requested.
   * Return cursor-based pagination for large result sets.
   * Ensure proper indexing on customer_id and created_at for query performance.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IShoppingMallCart.IRequest,
  ): Promise<IPageIShoppingMallCart.ISummary> {
    try {
      return await patchShoppingMallAdministratorCarts({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific shopping cart by its unique identifier.
   *
   * This operation returns the complete cart entity including all cart items with their product variant details, quantities, prices, and subtotals. The cart belongs to a specific customer and persists across sessions, serving as a staging area for items intended for purchase.
   *
   * The response includes the cart's metadata (creation date, last update) and an array of cart items. Each item contains the product variant reference, quantity, unit price snapshot, and calculated subtotal. Items marked as unavailable (deleted variants or out of stock) are indicated in the response.
   *
   * Customers can only access their own carts. Attempting to access another customer's cart will result in an authorization error.
   *
   * @param connection
   * @param cartId Cart unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query shopping_mall_carts table by primary key ID.
   *
   * Include eager loading of cart items via the items relation, joining with shopping_mall_product_variants to get variant details.
   *
   * Filter to exclude soft-deleted items (deleted_at IS NULL) from the items array.
   *
   * Verify the cart's customer_id matches the authenticated user's ID for authorization.
   *
   * Return 404 if cart not found or does not belong to the authenticated customer.
   *
   * Calculate subtotal for each item (price × quantity) and total cart value in the service layer if not denormalized in the response type.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":cartId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCart> {
    try {
      return await getShoppingMallAdministratorCartsCartId({
        administrator,
        cartId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
