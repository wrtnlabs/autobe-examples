import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallSellerApprovalRequest } from "../../../../api/structures/IShoppingMallSellerApprovalRequest";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getShoppingMallAdministratorApprovalRequestsRequestId } from "../../../../providers/getShoppingMallAdministratorApprovalRequestsRequestId";
import { putShoppingMallAdministratorApprovalRequestsRequestId } from "../../../../providers/putShoppingMallAdministratorApprovalRequestsRequestId";

@Controller("/shoppingMall/administrator/approval-requests/:requestId")
export class ShoppingmallAdministratorApproval_requestsController {
  /**
   * Retrieve a specific seller approval request by its unique identifier.
   *
   * This operation returns the complete details of a seller approval request including the current approval status (pending, approved, or rejected), rejection reason if applicable, and all relevant timestamps (submission time, review time). Sellers can use this endpoint to check their registration status, while administrators can access request details during the review process.
   *
   * The response includes the seller ID, reviewing administrator ID (if reviewed), status, rejection reason (for rejected requests), and audit timestamps. This endpoint is essential for sellers to understand their onboarding progress and for administrators to make informed approval decisions.
   *
   * @param connection
   * @param requestId Unique identifier of the seller approval request (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query shopping_mall_seller_approval_requests table by primary key ID.
   *
   * Retrieve the complete record including: id, seller_id, administrator_id, status, rejection_reason, submitted_at, reviewed_at, created_at, updated_at, deleted_at.
   *
   * Join with shopping_mall_sellers to include seller profile information if needed for display.
   * Join with shopping_mall_administrators to include reviewer information if administrator_id is not null.
   *
   * Validate that the record exists and is not soft-deleted (deleted_at is null).
   * Return 404 if record not found or soft-deleted.
   *
   * Authorization: Sellers can only access their own approval requests (seller_id matches authenticated user). Administrators can access all requests for review purposes.
   *
   * Edge cases: Return null for administrator_id and rejection_reason when status is pending. Ensure reviewed_at is populated only when status is approved or rejected.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerApprovalRequest> {
    try {
      return await getShoppingMallAdministratorApprovalRequestsRequestId({
        administrator,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a seller approval request by reviewing and approving or rejecting it.
   *
   * This operation allows administrators to review pending seller registration requests and make approval decisions. When approving, the status changes to approved and the seller gains selling privileges. When rejecting, the status changes to rejected and a rejection reason must be provided.
   *
   * The operation updates the reviewed_at timestamp to record when the administrator made the decision. Only pending requests can be updated - approved or rejected requests cannot be modified through this endpoint.
   *
   * Administrators must be authenticated to access this endpoint. The seller who submitted the request is notified of the decision through the status change.
   *
   * @param connection
   * @param requestId Approval request UUID (global scope)
   * @param body Review decision with status and optional rejection reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query shopping_mall_seller_approval_requests table by requestId UUID.
   *
   * Validate that the request exists and is in pending status. Reject with 400/422 if status is already approved or rejected.
   *
   * Validate administrator_id is provided in the update payload and references a valid administrator.
   *
   * If status is 'rejected', validate rejection_reason is provided and non-empty.
   *
   * Update the record: set status, administrator_id, rejection_reason (if rejected), and reviewed_at to current timestamp.
   *
   * Return the complete updated IShoppingMallSellerApprovalRequest entity.
   *
   * Handle concurrent updates with optimistic locking on updated_at if applicable.
   *
   * Return 404 if request not found, 400/422 if validation fails, 403 if not authorized as administrator.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSellerApprovalRequest.IUpdate,
  ): Promise<IShoppingMallSellerApprovalRequest> {
    try {
      return await putShoppingMallAdministratorApprovalRequestsRequestId({
        administrator,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
