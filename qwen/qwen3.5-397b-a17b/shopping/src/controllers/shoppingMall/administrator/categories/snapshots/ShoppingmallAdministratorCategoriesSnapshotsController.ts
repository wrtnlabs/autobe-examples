import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCategorySnapshot } from "../../../../../api/structures/IPageIShoppingMallCategorySnapshot";
import { IShoppingMallCategorySnapshot } from "../../../../../api/structures/IShoppingMallCategorySnapshot";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getShoppingMallAdministratorCategoriesCategoryIdSnapshotsSnapshotId } from "../../../../../providers/getShoppingMallAdministratorCategoriesCategoryIdSnapshotsSnapshotId";
import { patchShoppingMallAdministratorCategoriesCategoryIdSnapshots } from "../../../../../providers/patchShoppingMallAdministratorCategoriesCategoryIdSnapshots";

@Controller("/shoppingMall/administrator/categories/:categoryId/snapshots")
export class ShoppingmallAdministratorCategoriesSnapshotsController {
  /**
   * Retrieve historical snapshots of a specific category for audit and historical reconstruction purposes.
   *
   * This operation returns a paginated list of all snapshots created for the specified category. Each snapshot captures the complete state of the category at a point in time, including the category name, description, and parent category relationship as they existed when the snapshot was created.
   *
   * Category snapshots are automatically created whenever a category is modified and are preserved immutably. They cannot be modified or deleted. This endpoint is accessible to administrators who manage categories and need to track changes over time.
   *
   * Supports filtering by date range and sorting options to facilitate reviewing changes over specific time periods.
   *
   * @param connection
   * @param categoryId Category UUID (global scope)
   * @param body Optional filtering and pagination parameters for snapshot search
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query shopping_mall_category_snapshots table filtering by shopping_mall_category_id matching the categoryId path parameter.
   *
   * Apply pagination with cursor-based or offset-based pagination support. Default sort by created_at descending (newest first).
   *
   * Support optional filtering in request body: createdAfter, createdBefore date range filters, and sortBy options (created_at asc/desc).
   *
   * Return snapshot summary information including id, name, description, parent_id, and created_at. Do not include relation data - snapshots are standalone historical records.
   *
   * Validate that the categoryId exists in shopping_mall_categories table before querying snapshots. Return 404 if category not found.
   *
   * Authorization: Require administrator role. Regular customers and sellers cannot access category snapshots.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCategorySnapshot.IRequest,
  ): Promise<IPageIShoppingMallCategorySnapshot.ISummary> {
    try {
      return await patchShoppingMallAdministratorCategoriesCategoryIdSnapshots({
        administrator,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific category snapshot by its unique identifier.
   *
   * This operation returns an immutable snapshot record that captures the complete state of a category at a specific point in time. Snapshots include the category name, description, and parent category relationship as they existed when the snapshot was created.
   *
   * Category snapshots are automatically created by the system whenever a category is modified, providing an audit trail for historical reconstruction and dispute resolution. Snapshots cannot be modified or deleted once created.
   *
   * Administrators can view snapshots of any category. Sellers and customers do not have access to category snapshots as categories are administrator-managed entities.
   *
   * @param connection
   * @param categoryId Category ID (scope validator - snapshot must belong to this category)
   * @param snapshotId Snapshot ID to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query shopping_mall_category_snapshots table by snapshotId.
   *
   * Validate that the snapshot's shopping_mall_category_id matches the provided categoryId parameter to ensure referential integrity and prevent unauthorized access.
   *
   * Verify administrator authorization before returning the snapshot.
   *
   * Return the complete snapshot record including id, shopping_mall_category_id, name, description, parent_id, and created_at.
   *
   * Return 404 if snapshot not found or if snapshot does not belong to the specified category.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCategorySnapshot> {
    try {
      return await getShoppingMallAdministratorCategoriesCategoryIdSnapshotsSnapshotId(
        {
          administrator,
          categoryId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
