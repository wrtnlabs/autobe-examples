/**
 * Retrieve paginated list of customer reviews for a specific product.
 *
 * This endpoint returns all non-deleted reviews for the specified product, sorted by newest first to show recent customer feedback prominently. The response includes review summaries with rating, optional content, customer information, and creation timestamp.
 *
 * Reviews are filtered to exclude soft-deleted entries, ensuring only active customer feedback is displayed. The average product rating is calculated from these non-deleted reviews and displayed separately on product pages.
 *
 * The endpoint supports pagination parameters for efficient browsing of large review collections. Additional filters may include rating range, date range, and content search criteria.
 *
 * @param props.connection
 * @param props.productId Product identifier (UUID format) to filter reviews.
 * @param props.body Search criteria including pagination parameters, rating filters, date range, and sorting options for product reviews.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query shopping_mall_reviews table filtered by
 *   shopping_mall_product_id. Exclude soft-deleted reviews (deleted_at IS NOT
 *   NULL). Sort by created_at DESC (newest first). Apply pagination using
 *   cursor-based or offset-based approach. Join with shopping_mall_members to
 *   include customer display name in response. Return
 *   IPageIShoppingMallReview.ISummary with pagination metadata. Validate
 *   productId exists in shopping_mall_products table before querying reviews.
 * @path /shoppingMall/products/:productId/reviews
 * @accessor api.functional.shoppingMall.products.reviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Product identifier (UUID format) to filter reviews.
     */
    productId: string & tags.Format<"uuid">;

    /**
     * Search criteria including pagination parameters, rating filters, date range, and sorting options for product reviews.
     */
    body: IShoppingMallReview.IRequest;
  };
  export type Body = IShoppingMallReview.IRequest;
  export type Response = IPageIShoppingMallReview.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/products/:productId/reviews",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/products/${encodeURIComponent(props.productId ?? "null")}/reviews`;
  export const random = (): IPageIShoppingMallReview.ISummary =>
    typia.random<IPageIShoppingMallReview.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
