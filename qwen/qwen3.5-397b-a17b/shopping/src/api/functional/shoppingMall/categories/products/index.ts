/**
 * Retrieve a paginated list of products within a specific category.
 *
 * This endpoint allows customers to browse all active products assigned to the specified category. Only products directly assigned to this category are returned - products in subcategories are not automatically included and must be accessed by navigating to those subcategories explicitly.
 *
 * The response includes product summary information optimized for list displays: product name, base price, main image, seller shop name, average rating, and review count. Products that have been soft-deleted by sellers (deleted flag set to true) are excluded from the results.
 *
 * Pagination is supported through query parameters to handle large product catalogs efficiently. Results are sorted by creation date (newest first) by default, with options to sort by price or name.
 *
 * Returns a 404 error if the category does not exist or has been deleted by an administrator.
 *
 * @param props.connection
 * @param props.categoryId Target category's UUID identifier (global scope)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query shopping_mall_products table filtering by shopping_category_id = {categoryId} AND deleted = false.
 *
 * Join with shopping_mall_sellers to include seller shop information in response.
 * Join with shopping_mall_product_images to include main product image (lowest display_order).
 * Calculate average rating and review count from shopping_mall_reviews table.
 *
 * Apply pagination with cursor-based or offset-based approach (page, limit query parameters).
 * Support sorting by created_at (newest first by default), price, or name.
 *
 * Return 404 if category not found or category is soft-deleted (deleted_at IS NOT NULL).
 * Return empty array if category exists but has no active products.
 * @path /shoppingMall/categories/:categoryId/products
 * @accessor api.functional.shoppingMall.categories.products.list
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function list(
  connection: IConnection,
  props: list.Props,
): Promise<list.Response> {
  return true === connection.simulate
    ? list.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...list.METADATA,
          path: list.path(props),
          status: null,
        },
      );
}
export namespace list {
  export type Props = {
    /**
     * Target category's UUID identifier (global scope)
     */
    categoryId: string & tags.Format<"uuid">;
  };
  export type Response = IPageIShoppingMallProduct.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/categories/:categoryId/products",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/categories/${encodeURIComponent(props.categoryId ?? "null")}/products`;
  export const random = (): IPageIShoppingMallProduct.ISummary =>
    typia.random<IPageIShoppingMallProduct.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: list.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: list.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("categoryId")(() => typia.assert(props.categoryId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
