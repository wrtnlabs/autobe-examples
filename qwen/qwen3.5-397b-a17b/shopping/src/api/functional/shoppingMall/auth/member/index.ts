/**
 * Register a new customer account with email and password credentials.
 *
 * This operation creates a new member account in the shopping_mall_members table. The email must be unique across all existing member accounts. The password is hashed using bcrypt before storage for security.
 *
 * Upon successful registration, the system generates JWT access and refresh tokens and creates a session record in shopping_mall_member_sessions. The response includes both tokens for immediate authentication.
 *
 * Email verification is handled separately through the email verification flow. The account is created with 'active' status, allowing immediate login access.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration credentials for new member account creation.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Create new member account with email and password.
 *   Validate email uniqueness against shopping_mall_members table. Hash
 *   password using bcrypt before storing. Create member record with status
 *   'active'. Generate JWT access and refresh tokens. Create session record in
 *   shopping_mall_member_sessions with client context (ip, href, referrer).
 *   Return tokens in IShoppingMallMember.IAuthorized response. Reject if email
 *   already exists (409 Conflict) or validation fails (400 Bad Request).
 * @path /shoppingMall/auth/member/join
 * @accessor api.functional.shoppingMall.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
