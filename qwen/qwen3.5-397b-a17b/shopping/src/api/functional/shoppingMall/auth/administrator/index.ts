/**
 * Register a new administrator account for the shopping mall system. This endpoint creates an administrator account with the provided email and password credentials.
 *
 * The email address must be unique across all administrator accounts. The password will be securely hashed using bcrypt before storage. Upon successful registration, the system generates JWT access and refresh tokens for immediate authentication.
 *
 * Administrators manage seller approvals, categories, products, orders, and user accounts within the shopping mall platform. This operation establishes the initial credentials for administrator access.
 *
 * Returns authentication tokens on success. Fails with conflict error if the email address is already registered to an existing administrator account.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Administrator registration credentials including email and password for account creation.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor administrator
 * @x-autobe-specification Create new administrator account with email and password. Validate email uniqueness against existing administrators. Hash password using bcrypt before storing. Generate JWT access and refresh tokens upon successful registration. Return tokens in response. Reject if email already exists or validation fails.
 * @path /shoppingMall/auth/administrator/join
 * @accessor api.functional.shoppingMall.auth.administrator.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
