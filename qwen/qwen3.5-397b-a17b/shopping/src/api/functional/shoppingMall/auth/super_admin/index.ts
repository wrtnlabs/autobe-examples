/**
 * Register a new super administrator account with email and password.
 *
 * This endpoint creates a new super administrator account in the shopping_mall_super_admins table. The email must be unique across all super administrator accounts. The password is hashed using bcrypt before storage for security.
 *
 * Upon successful registration, the system generates JWT access and refresh tokens, returning them in the IShoppingMallSuperAdmin.IAuthorized response. The account is immediately active with full super administrator privileges.
 *
 * Validation includes email format verification, password strength requirements, and uniqueness checks. Returns 409 Conflict if the email is already registered.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration credentials for new super administrator account.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor superAdmin
 * @x-autobe-specification Create a new super administrator account. Validate
 *   email uniqueness across all super admin accounts. Hash the password using
 *   bcrypt before storing. Generate initial JWT access and refresh tokens upon
 *   successful registration. Return the authorized response with tokens and
 *   basic account info. Reject if email already exists or password does not
 *   meet security requirements.
 * @path /shoppingMall/auth/super-admin/join
 * @accessor api.functional.shoppingMall.auth.super_admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
