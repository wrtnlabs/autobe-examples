/**
 * Register a new administrator account for platform management access.
 *
 * This endpoint creates a new administrator account in the shopping_mall_admins table with the provided email and password. The email must be unique across all administrator accounts and is validated for proper format. The password is securely hashed using bcrypt before storage.
 *
 * The administrator grade is automatically set to ADMIN upon registration. SUPER_ADMIN grade can only be assigned through the promotion process managed by existing super administrators via the admin promotion endpoints.
 *
 * Upon successful registration, the endpoint returns JWT access and refresh tokens in the IShoppingMallAdmin.IAuthorized response, allowing immediate authentication without requiring a separate login call. The access token is used for authenticated requests to administrator endpoints, while the refresh token is used to obtain new access tokens when the current one expires.
 *
 * This operation is public and does not require authentication. It is typically used during initial platform setup or when new administrators are being onboarded through the registration process.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Administrator registration credentials including email and password.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Create a new administrator account with email and password. Validates email uniqueness across all administrator accounts. Stores bcrypt-hashed password securely. Sets initial grade to ADMIN (super admin assignment requires promotion by existing super admin). Creates the administrator record in shopping_mall_admins table with generated UUID. Returns JWT access and refresh tokens for immediate authentication. Email should be validated for proper format. Password should meet minimum security requirements (length, complexity). The grade field defaults to ADMIN as SUPER_ADMIN can only be assigned through promotion by existing super administrators.
 * @path /shoppingMall/auth/admin/join
 * @accessor api.functional.shoppingMall.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
