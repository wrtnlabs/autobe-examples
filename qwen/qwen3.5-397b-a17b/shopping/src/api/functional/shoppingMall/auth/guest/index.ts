/**
 * Register a new guest user or retrieve existing guest session using device fingerprint.
 *
 * Creates a temporary guest account identified by device fingerprint for unauthenticated browsing. If a guest with the same device fingerprint already exists, returns the existing guest's session tokens. New guests receive a UUID and short-lived JWT tokens for platform access.
 *
 * The device_fingerprint uniquely identifies the guest's device and enables session persistence across page views. Guest sessions have shorter expiration times (typically 24 hours) compared to registered users for security purposes.
 *
 * Request must include device_fingerprint string. Optional ip, href, and referrer fields capture connection metadata for security monitoring and analytics. Response includes guest id, access token, refresh token, and expiration timestamp.
 *
 * Guest accounts can be upgraded to full customer accounts through the registration process, preserving cart and wishlist data.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest registration request with device fingerprint and optional connection metadata.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Create a guest account using device fingerprint and
 *   generate JWT session tokens. Validate device_fingerprint is provided and
 *   not empty. Check if guest with same device_fingerprint already exists - if
 *   yes, return existing guest tokens. If new, create shopping_mall_guests
 *   record with generated UUID and current timestamps. Create
 *   shopping_mall_guest_sessions record with access token, refresh token,
 *   expiration time (short-lived for guests, e.g., 24 hours), and connection
 *   metadata (ip, href, referrer from request headers). Return
 *   IShoppingMallGuest.IAuthorized with guest id, access token, refresh token,
 *   and expired_at timestamp. Handle concurrent session creation gracefully.
 * @path /shoppingMall/auth/guest/join
 * @accessor api.functional.shoppingMall.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
