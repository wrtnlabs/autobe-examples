/**
 * Register a new seller account on the platform.
 *
 * Creates a seller account with the provided email and password. The account starts with approval_status 'pending' and requires administrator approval before the seller can list products or process orders. An email verification token is generated and sent to the provided email address.
 *
 * Upon successful registration, the operation returns JWT access and refresh tokens for immediate authentication. The seller can browse the platform but cannot perform seller-specific operations until their approval_status changes to 'approved'.
 *
 * Email must be unique across all seller accounts. Password is hashed using bcrypt before storage. If a seller application was previously rejected, they can register again with the same email after their old account is soft deleted.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Seller registration credentials and profile information.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Register a new seller account with email and
 *   password. Create shopping_mall_sellers record with
 *   approval_status='pending'. Generate email verification token in
 *   shopping_mall_seller_email_verifications table. Send verification email.
 *   Return JWT access and refresh tokens. Seller cannot sell until admin
 *   approves (approval_status='approved').
 * @path /shoppingMall/auth/seller/join
 * @accessor api.functional.shoppingMall.auth.seller.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
