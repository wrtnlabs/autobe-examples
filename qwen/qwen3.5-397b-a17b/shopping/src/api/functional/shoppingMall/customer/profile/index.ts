/**
 * Update the authenticated customer's profile information including display name and phone number.
 *
 * This operation allows customers to modify their profile details that are displayed throughout the platform. The display name appears on reviews, order confirmations, and profile pages visible to sellers and other users. The phone number is used for order-related communications and shipping notifications.
 *
 * Profile updates are applied immediately and reflected across all platform features. Each modification creates an immutable snapshot in the audit trail, preserving the previous display name and phone number values for data recovery and dispute resolution purposes. The updated_at timestamp is automatically updated to track when the last modification occurred.
 *
 * This PUT operation requires complete resource representation - both display_name and phone_number fields must be provided in the request body, even if unchanged.
 *
 * @param props.connection
 * @param props.body Complete profile update data with display name and phone number
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Update shopping_mall_customer_profiles record for the authenticated customer.
 *
 * 1. Extract customer ID from authenticated session token
 * 2. Validate request body: display_name (non-empty string), phone_number (valid format)
 * 3. Query shopping_mall_customer_profiles WHERE shopping_mall_customer_id = {customerId} AND deleted_at IS NULL
 * 4. If profile not found, return 404 Not Found
 * 5. Update display_name and phone_number fields
 * 6. Set updated_at to current timestamp
 * 7. Return updated profile entity
 *
 * Validation rules:
 * - display_name: required, non-empty string, no length restrictions per business rules
 * - phone_number: required, valid phone number format for customer's country
 *
 * No snapshot creation required - profile edits maintain only current values per requirements.
 * @path /shoppingMall/customer/profile
 * @accessor api.functional.shoppingMall.customer.profile.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
