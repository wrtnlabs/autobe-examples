import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IShoppingMallProductRating } from "../../../../../structures/IShoppingMallProductRating";

/**
 * Retrieve the average rating and total review count for a specific product.
 *
 * This operation returns the aggregated rating information for a product, including the average rating calculated from all non-deleted reviews and the total count of reviews. The average rating is computed by summing all rating values from non-deleted reviews and dividing by the count of non-deleted reviews.
 *
 * If a product has no non-deleted reviews, the average rating will be null. Deleted reviews are excluded from both the average calculation and the total count. This ensures the displayed rating reflects current customer sentiment.
 *
 * @param props.connection
 * @param props.productId Product UUID (global scope)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query shopping_mall_reviews table filtering by product_id and excluding soft-deleted reviews (deleted_at IS NOT NULL). Calculate average rating using AVG(rating) function on non-deleted reviews. Count total non-deleted reviews using COUNT(*). Return null for averageRating if no reviews exist. Join with shopping_mall_products to verify product exists. Handle case where product has no reviews by returning averageRating as null and totalReviews as 0.
 * @path /shoppingMall/customer/products/:productId/ratings
 * @accessor api.functional.shoppingMall.customer.products.ratings.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Product UUID (global scope)
     */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallProductRating;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/products/:productId/ratings",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/products/${encodeURIComponent(props.productId ?? "null")}/ratings`;
  export const random = (): IShoppingMallProductRating =>
    typia.random<IShoppingMallProductRating>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
