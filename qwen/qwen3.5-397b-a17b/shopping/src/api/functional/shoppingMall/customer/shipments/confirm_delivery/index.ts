import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IShoppingMallShipment } from "../../../../../structures/IShoppingMallShipment";

/**
 * Confirm delivery receipt for a shipment by the customer.
 *
 * This endpoint allows customers to manually confirm that they have received a shipment. When delivery is confirmed, the system updates the shipment's delivery_confirmed_at timestamp and changes the status of all order items in that shipment to DELIVERED. This confirmation triggers the completion of the order fulfillment process for those items.
 *
 * Only the customer who placed the order containing this shipment can confirm delivery. The shipment must have been previously shipped (shipped_at timestamp set) and not already delivery confirmed. If the customer does not manually confirm delivery, the system automatically confirms delivery 14 days after the shipped_at timestamp.
 *
 * After successful confirmation, all order items in the shipment become eligible for review submission. Customers can view the delivery confirmation status in their order history and shipment tracking pages.
 *
 * @param props.connection
 * @param props.shipmentId Target shipment's ID to confirm delivery for
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Validate that the shipment exists and belongs to an order owned by the authenticated customer. Verify the shipment has been shipped (shipped_at is not null) and not yet delivery confirmed. Update the shipment's delivery_confirmed_at timestamp to current time. Update all order items linked to this shipment through shopping_mall_shipment_items to status 'DELIVERED'. Return the updated shipment with delivery confirmation timestamp. Reject if shipment doesn't exist, customer doesn't own the order, or shipment already confirmed.
 * @path /shoppingMall/customer/shipments/:shipmentId/confirm-delivery
 * @accessor api.functional.shoppingMall.customer.shipments.confirm_delivery.confirmDelivery
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function confirmDelivery(
  connection: IConnection,
  props: confirmDelivery.Props,
): Promise<confirmDelivery.Response> {
  return true === connection.simulate
    ? confirmDelivery.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...confirmDelivery.METADATA,
          path: confirmDelivery.path(props),
          status: null,
        },
      );
}
export namespace confirmDelivery {
  export type Props = {
    /**
     * Target shipment's ID to confirm delivery for
     */
    shipmentId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallShipment;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/customer/shipments/:shipmentId/confirm-delivery",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/shipments/${encodeURIComponent(props.shipmentId ?? "null")}/confirm-delivery`;
  export const random = (): IShoppingMallShipment =>
    typia.random<IShoppingMallShipment>();
  export const simulate = (
    connection: IConnection,
    props: confirmDelivery.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: confirmDelivery.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shipmentId")(() => typia.assert(props.shipmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
