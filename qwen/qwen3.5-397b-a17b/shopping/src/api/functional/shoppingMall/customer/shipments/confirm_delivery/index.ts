import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IShoppingMallShipment } from "../../../../../structures/IShoppingMallShipment";

/**
 * Confirm delivery of a shipment by the customer.
 *
 * This operation allows customers to manually confirm that they have received a shipment. When delivery is confirmed, all order items contained in the shipment automatically transition to delivered status. This enables customers to write reviews for the delivered products.
 *
 * If the customer does not manually confirm delivery, order items automatically change to delivered status after 14 days from the shipped date. The confirmation action records the confirmed_at timestamp on the shipment.
 *
 * Only the customer who placed the order can confirm delivery for the shipment. The shipment must be in shipped status (not yet delivered) to be eligible for confirmation.
 *
 * @param props.connection
 * @param props.shipmentId Shipment ID to confirm delivery (UUID format)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Update the shipment's confirmed_at field to the current timestamp when the customer confirms delivery.
 *
 * Validate that the shipment exists and is in shipped status (not already delivered). Verify that the authenticated customer is the owner of the order containing the shipment's order items. Update all order items in the shipment to status 'delivered' in a transaction. Return the updated shipment with the confirmed_at timestamp populated.
 *
 * Reject the request if: shipment not found, shipment already confirmed/delivered, or customer is not authorized to confirm this shipment.
 * @path /shoppingMall/customer/shipments/:shipmentId/confirm-delivery
 * @accessor api.functional.shoppingMall.customer.shipments.confirm_delivery.confirmDelivery
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function confirmDelivery(
  connection: IConnection,
  props: confirmDelivery.Props,
): Promise<confirmDelivery.Response> {
  return true === connection.simulate
    ? confirmDelivery.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...confirmDelivery.METADATA,
          path: confirmDelivery.path(props),
          status: null,
        },
      );
}
export namespace confirmDelivery {
  export type Props = {
    /**
     * Shipment ID to confirm delivery (UUID format)
     */
    shipmentId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallShipment;

  export const METADATA = {
    method: "PUT",
    path: "/shoppingMall/customer/shipments/:shipmentId/confirm-delivery",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/shipments/${encodeURIComponent(props.shipmentId ?? "null")}/confirm-delivery`;
  export const random = (): IShoppingMallShipment =>
    typia.random<IShoppingMallShipment>();
  export const simulate = (
    connection: IConnection,
    props: confirmDelivery.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: confirmDelivery.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shipmentId")(() => typia.assert(props.shipmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
