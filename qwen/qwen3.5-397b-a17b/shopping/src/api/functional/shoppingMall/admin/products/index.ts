/**
 * Retrieves complete details of a single product by its unique identifier.
 *
 * Returns the full product entity including name, description, base price, category assignment, and seller information. The response includes all product images in display order, with the first image serving as the main thumbnail. All product variants are included with their SKU codes, option value combinations, and optional price overrides.
 *
 * Stock availability for each variant is calculated from the inventory records ledger. Products that are soft deleted (deleted_at is set) return 404 Not Found to hide them from customers while preserving order history references.
 *
 * This endpoint is accessible to all actors including guests for product browsing. The product must exist and be active (not deleted) to be retrieved.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the product to retrieve (UUID format).
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query shopping_mall_products table by productId UUID.
 *   Join with shopping_mall_product_images to include all images ordered by
 *   display_order. Join with shopping_mall_product_variants to include all
 *   variants with their option_values and prices. Calculate stock status from
 *   shopping_mall_inventory_records ledger for each variant. Return 404 if
 *   product not found or if deleted_at is not null (soft deleted products are
 *   hidden). Include seller profile information (shop_name, logo_image_url)
 *   from shopping_mall_seller_profiles. Include category information from
 *   shopping_mall_categories.
 * @path /shoppingMall/admin/products/:productId
 * @accessor api.functional.shoppingMall.admin.products.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the product to retrieve (UUID format).
     */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallProduct;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/admin/products/:productId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/products/${encodeURIComponent(props.productId ?? "null")}`;
  export const random = (): IShoppingMallProduct =>
    typia.random<IShoppingMallProduct>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

