export async function test_api_search_query_retrieval_by_id(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: typia.random<IDiscussionBoardAdmin.IJoin>(),
  });
  // Retrieve a search query by a randomly generated query ID
  const searchQuery = await api.functional.discussionBoard.search.queries.at(
    adminConnection,
    {
      queryId: typia.random<string>(),
    },
  );
  typia.assert(searchQuery);
}
