export async function test_api_admin_ban_record_not_found_handling(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "12341234",
      display_name: RandomGenerator.name(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Attempt to retrieve non-existent ban record
  const fakeBanId = "00000000-0000-0000-0000-000000000000";
  await TestValidator.error(
    "should return 404 for non-existent ban",
    async () => {
      await api.functional.discussionBoard.admin.bans.at(adminConnection, {
        banId: fakeBanId,
      });
    },
  );
}
