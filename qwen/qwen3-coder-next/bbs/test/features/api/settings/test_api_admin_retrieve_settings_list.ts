export async function test_api_admin_retrieve_settings_list(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {},
  });
  // 2. Retrieve system settings
  const settings =
    await api.functional.discussionBoard.admin.settings.index(adminConnection);
  typia.assert(settings);
  // 3. Validate response is not null/undefined
  TestValidator.predicate(
    "settings object exists",
    settings !== null && settings !== undefined,
  );
}
