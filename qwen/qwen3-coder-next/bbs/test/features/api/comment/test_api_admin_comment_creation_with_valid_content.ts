/**
 * Test admin comment creation with valid content.
 * 1. Authenticate as admin
 * 2. Create a comment with valid content
 * 3. Verify comment creation succeeds
 */
export async function test_api_admin_comment_creation_with_valid_content(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: typia.random<IDiscussionBoardAdmin.IJoin>(),
  });
  // 2. Create a comment with valid content
  const commentContent = RandomGenerator.paragraph({ sentences: 2 });
  const comment = await generate_random_discussion_board_admin_comments_create(
    adminConnection,
    {
      body: {
        content: commentContent,
      } satisfies IDiscussionBoardArticleComment.ICreate,
    },
  );
  typia.assert(comment);
  // 3. Verify comment creation succeeded
  typia.assert(comment);
}
