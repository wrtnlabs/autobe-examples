/**
 * Search articles across the entire discussion board system.
 *
 * This operation provides comprehensive search functionality allowing users to search articles by title, content, and apply tag-based filtering. The search supports case-insensitive matching, partial word matching, and phrase searching.
 *
 * The search functionality enables users to find relevant discussions on economic and political topics by searching through article titles and content bodies. Tag filtering allows users to narrow results to specific topics or categories.
 *
 * The operation supports comprehensive pagination with configurable page sizes and sorting. Results include article summary information optimized for search result displays.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query discussion_board_articles table with full-text search capabilities.
 * Apply search filters on title and content fields using case-insensitive matching.
 * Support tag-based filtering by joining with discussion_board_article_tags table.
 * Support pagination with configurable page sizes and offsets.
 * Return paginated list of article summaries optimized for search result displays.
 * @path /discussionBoard/search
 * @accessor api.functional.discussionBoard.search
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function search(
  connection: IConnection,
  props: search.Props,
): Promise<search.Response> {
  return true === connection.simulate
    ? search.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...search.METADATA,
          path: search.path(),
          status: null,
        },
        props.body,
      );
}
export namespace search {
  export type Props = {
    /**
     * Search criteria and pagination parameters
     */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/search",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/search";
  export const random = (): IPageIDiscussionBoardArticle.ISummary =>
    typia.random<IPageIDiscussionBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: search.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: search.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
