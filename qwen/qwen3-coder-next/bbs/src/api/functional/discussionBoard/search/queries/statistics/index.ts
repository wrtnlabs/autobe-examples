import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardSearchQuery } from "../../../../../structures/IDiscussionBoardSearchQuery";

/**
 * Retrieve comprehensive search statistics and analytics for the discussion board search system.
 *
 * This endpoint provides detailed analytics about search behavior, query patterns, and search effectiveness. It aggregates data from search queries, click tracking, and result positioning to generate insights about user search behavior and search performance metrics.
 *
 * ## Search Statistics Categories
 *
 * ### Query Statistics
 * - Total search volume and frequency
 * - Popular search terms and their ranking
 * - Search query volume over time periods
 * - Unique vs repeated search queries
 *
 * ### Click Statistics
 * - Click-through rates by search result position
 * - Most/least clicked search results
 * - User engagement patterns with search results
 * - Session-based click analysis
 *
 * ### Relevance Metrics
 * - Average relevance scores for different query types
 * - Performance metrics by search term
 * - Search result positioning effectiveness
 * - User behavior correlation with ranking
 *
 * ## Authorization
 *
 * All authenticated users can access search statistics. The system provides aggregate analytics without exposing individual user data or personal search history.
 *
 * ## Usage Context
 *
 * This endpoint is designed for:
 * - Admin dashboard search analytics displays
 * - Search quality monitoring and improvement
 * - User behavior analysis for search optimization
 * - Performance reporting and KPI tracking
 *
 * @param props.connection
 * @param props.body Statistics query parameters for filtering and aggregating search analytics
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Aggregate search statistics from multiple models:
 * 1. Query statistics from discussion_board_search_queries (count, dates, parameters)
 * 2. Click-through rates from discussion_board_search_clicks (join with queries)
 * 3. Result positioning and relevance from discussion_board_search_results
 * 4. Filter by date range if provided in request body
 * 5. Group and aggregate data by query terms, dates, and result positions
 * 6. Calculate click-through rates and relevance metrics
 * 7. Return comprehensive statistics with pagination support
 * @path /discussionBoard/search/queries/statistics
 * @accessor api.functional.discussionBoard.search.queries.statistics.indexStatistics
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function indexStatistics(
  connection: IConnection,
  props: indexStatistics.Props,
): Promise<indexStatistics.Response> {
  return true === connection.simulate
    ? indexStatistics.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...indexStatistics.METADATA,
          path: indexStatistics.path(),
          status: null,
        },
        props.body,
      );
}
export namespace indexStatistics {
  export type Props = {
    /**
     * Statistics query parameters for filtering and aggregating search analytics
     */
    body: IDiscussionBoardSearchQuery.IRequest;
  };
  export type Body = IDiscussionBoardSearchQuery.IRequest;
  export type Response = IDiscussionBoardSearchQuery.IStatistic;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/search/queries/statistics",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/search/queries/statistics";
  export const random = (): IDiscussionBoardSearchQuery.IStatistic =>
    typia.random<IDiscussionBoardSearchQuery.IStatistic>();
  export const simulate = (
    connection: IConnection,
    props: indexStatistics.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: indexStatistics.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
