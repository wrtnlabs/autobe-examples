/**
 * Retrieve detailed information about a specific search result from the discussion board search analytics system.
 *
 * This API operation fetches individual search result records that track user interactions with search results, including positioning, relevance scoring, and content snippet context. It provides detailed analytics data about how specific search terms match content and user engagement patterns.
 *
 * The operation supports comprehensive search result tracking with detailed metadata about result relevance, user click behavior, and position tracking within search result lists.
 *
 * @param props.connection
 * @param props.resultId Target search result's unique identifier
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query discussion_board_search_results table by primary key ID. Retrieve complete search result record including position, relevance score, and content snippet. Join with related discussion_board_articles for article details. Return search result entity with all field values including timestamp and positioning data.
 * @path /discussionBoard/search/results/:resultId
 * @accessor api.functional.discussionBoard.search.results.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Target search result's unique identifier
     */
    resultId: string;
  };
  export type Response = IDiscussionBoardSearchResult;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/search/results/:resultId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/search/results/${encodeURIComponent(props.resultId ?? "null")}`;
  export const random = (): IDiscussionBoardSearchResult =>
    typia.random<IDiscussionBoardSearchResult>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("resultId")(() => typia.assert(props.resultId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
