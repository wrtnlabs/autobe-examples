/**
 * Retrieve a specific search query record for administrative or analytical purposes.
 *
 * This operation provides access to individual search query records stored in the system. Search queries are tracked for analytics purposes to understand user search patterns, popular search terms, and search effectiveness.
 *
 * The search query record contains the original search text, any additional search parameters that were used, the number of results returned, and the timestamp when the search was performed. This data is valuable for administrative review, analytical reporting, and understanding how users interact with the search functionality.
 *
 * Note that this endpoint provides read-only access to search query metadata and does not include any personally identifiable information about the user who performed the search, as guest sessions are used for unauthenticated users.
 *
 * @param props.connection
 * @param props.queryId The unique identifier of the search query record
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query the discussion_board_search_queries table using the provided query ID. Retrieve the complete search query record including the search text, parameters, results count, and creation timestamp. Return the record as a single object.
 * @path /discussionBoard/search/queries/:queryId
 * @accessor api.functional.discussionBoard.search.queries.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * The unique identifier of the search query record
     */
    queryId: string;
  };
  export type Response = IDiscussionBoardSearchQuery;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/search/queries/:queryId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/search/queries/${encodeURIComponent(props.queryId ?? "null")}`;
  export const random = (): IDiscussionBoardSearchQuery =>
    typia.random<IDiscussionBoardSearchQuery>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("queryId")(() => typia.assert(props.queryId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

