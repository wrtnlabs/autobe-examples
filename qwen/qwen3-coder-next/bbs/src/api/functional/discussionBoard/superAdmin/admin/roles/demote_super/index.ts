/**
 * Demote a super administrator to regular administrator grade.
 *
 * This operation downgrades a user's administrative privileges from super administrator to regular administrator. The user retains all regular administrative capabilities (content moderation, section management, user banning) but loses super administrator-specific abilities (promoting/demoting other super administrators, viewing all system data).
 *
 * This operation is typically used when a super administrator voluntarily steps down from their elevated privileges or when organizational requirements change administrative roles.
 *
 * **Security Context:** Only super administrators can execute this operation. The system verifies the requesting user's super admin status before allowing grade demotion.
 *
 * @param props.connection
 * @param props.userId User ID of the super administrator to demote to regular admin
 * @param props.body Demotion confirmation and metadata
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor superAdmin
 * @x-autobe-specification Update discussion_board_admins_roles record for the specified user_id.
 * Change the grade field from 'super' to 'regular'.
 * Verify the requesting user has super admin privileges.
 * Log the demotion action in the system audit logs.
 * Return the updated admin role record with new 'regular' grade.
 * @path /discussionBoard/superAdmin/admin/roles/:userId/demote-super
 * @accessor api.functional.discussionBoard.superAdmin.admin.roles.demote_super.demoteSuper
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function demoteSuper(
  connection: IConnection,
  props: demoteSuper.Props,
): Promise<demoteSuper.Response> {
  return true === connection.simulate
    ? demoteSuper.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...demoteSuper.METADATA,
          path: demoteSuper.path(props),
          status: null,
        },
        props.body,
      );
}
