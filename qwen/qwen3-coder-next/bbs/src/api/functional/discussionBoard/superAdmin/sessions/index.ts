/**
 * Retrieve detailed information about a specific user session.
 *
 * This operation fetches comprehensive session data including authentication timestamps, validity status, device information, and connection context. It's designed for session management, debugging, and administrative oversight of user authentication activity.
 *
 * The session data includes temporal information for tracking user engagement patterns, security audit trails, and technical metadata for troubleshooting authentication issues.
 *
 * @param props.connection
 * @param props.sessionId Unique session identifier for the user session
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor superAdmin
 * @x-autobe-specification Query discussion_board_member_sessions table by primary key ID.
 * Retrieve single session record with all fields including timestamps, validity flag, connection metadata, and member reference.
 * Return null if session not found or has expired.
 * Format timestamps in ISO 8601 format for consistency.
 * @path /discussionBoard/superAdmin/sessions/:sessionId
 * @accessor api.functional.discussionBoard.superAdmin.sessions.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique session identifier for the user session
     */
    sessionId: string;
  };
  export type Response = IDiscussionBoardMemberSession;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/superAdmin/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/superAdmin/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): IDiscussionBoardMemberSession =>
    typia.random<IDiscussionBoardMemberSession>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
