import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardBansAppeal } from "../../../../../structures/IDiscussionBoardBansAppeal";

/**
 * Submit an appeal against a user ban decision.
 *
 * This API endpoint allows banned users to formally appeal their ban by submitting their reasoning and justification. The appeal is stored in the system for review by administrators.
 *
 * The endpoint requires the ban record identifier and the user's appeal explanation. Once submitted, the appeal enters a pending state and can be reviewed by administrators with appropriate privileges.
 *
 * Administrators can review pending appeals through separate endpoints and make decisions to approve or reject the ban appeal. The appeal system provides users with an opportunity to contest ban decisions while maintaining proper administrative oversight.
 *
 * @param props.connection
 * @param props.banRecordId Target ban record's ID
 * @param props.body Appeal submission with reason and ban record reference
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor superAdmin
 * @x-autobe-specification Insert a new appeal record into discussion_board_bans_appeals table.
 * Use provided ban_record_id to reference the ban, current user as user_id,
 * set status to 'pending', and store appeal_reason from request body.
 * No review notes or reviewed_by_id initially since appeal is new.
 * Return the created appeal record with generated ID and timestamps.
 * @path /discussionBoard/superAdmin/moderation/queue/:banRecordId
 * @accessor api.functional.discussionBoard.superAdmin.moderation.queue.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Target ban record's ID
     */
    banRecordId: string;

    /**
     * Appeal submission with reason and ban record reference
     */
    body: IDiscussionBoardBansAppeal.ICreate;
  };
  export type Body = IDiscussionBoardBansAppeal.ICreate;
  export type Response = IDiscussionBoardBansAppeal;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/superAdmin/moderation/queue/:banRecordId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/superAdmin/moderation/queue/${encodeURIComponent(props.banRecordId ?? "null")}`;
  export const random = (): IDiscussionBoardBansAppeal =>
    typia.random<IDiscussionBoardBansAppeal>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("banRecordId")(() => typia.assert(props.banRecordId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
