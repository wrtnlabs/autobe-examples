/**
 * Upload files to an article. This operation allows users to attach multiple files to an article, with each file stored with its metadata including original filename, file size, file type, and upload timestamp.
 *
 * @param props.connection
 * @param props.articleId Target article's ID
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor superAdmin
 * @x-autobe-specification Upload files to an article by creating FileAttachment records. Validate that the user is authenticated and not banned. Enforce file size and type limits. Associate files with the specified article. Return all file metadata including file URL.
 * @path /discussionBoard/superAdmin/articles/:articleId/files
 * @accessor api.functional.discussionBoard.superAdmin.articles.files.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
      );
}
export namespace create {
  export type Props = {
    /**
     * Target article's ID
     */
    articleId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardArticleFile;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/superAdmin/articles/:articleId/files",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/superAdmin/articles/${encodeURIComponent(props.articleId ?? "null")}/files`;
  export const random = (): IDiscussionBoardArticleFile =>
    typia.random<IDiscussionBoardArticleFile>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

