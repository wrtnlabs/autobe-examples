/**
 * Retrieve a paginated list of banned users for administrative monitoring.
 *
 * This operation provides visibility into all currently banned users in the system. Administrators can view comprehensive ban information including the user's display name, email, creation timestamp, and account status.
 *
 * The response includes pagination metadata and allows for efficient browsing of the banned users list. Each banned user entry shows their current account status and creation details for audit purposes.
 *
 * Banned users are identified by having `is_active = false` in the members table.
 *
 * @param props.connection
 * @param props.body Pagination parameters and search criteria
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor superAdmin
 * @x-autobe-specification Query banned users from discussion_board_members table where is_active is false.
 * Return display_name, email, created_at, banned_at, ban_reason, and ban_issuer_id fields.
 * Apply pagination with configurable page size and offset.
 * Support sorting by ban timestamp (newest/oldest) and search by user name.
 * Return paginated result with metadata including total count, current page, and total pages.
 * @path /discussionBoard/superAdmin/bans
 * @accessor api.functional.discussionBoard.superAdmin.bans.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Pagination parameters and search criteria
     */
    body: IDiscussionBoardMember.IRequest;
  };
  export type Body = IDiscussionBoardMember.IRequest;
  export type Response = IPageIDiscussionBoardMember.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/superAdmin/bans",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/superAdmin/bans";
  export const random = (): IPageIDiscussionBoardMember.ISummary =>
    typia.random<IPageIDiscussionBoardMember.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
