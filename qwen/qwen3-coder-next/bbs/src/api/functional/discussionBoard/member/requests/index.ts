/**
 * Submit a request to become an administrator.
 *
 * This endpoint allows registered members to apply for administrator privileges. The request includes a reason text explaining why the user should be granted administrator access.
 *
 * @param props.connection
 * @param props.body Administrator request details
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Create a new administrator request for the authenticated user.
 * @path /discussionBoard/member/requests
 * @accessor api.functional.discussionBoard.member.requests.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Administrator request details
     */
    body: IDiscussionBoardAdministratorRequest.ICreate;
  };
  export type Body = IDiscussionBoardAdministratorRequest.ICreate;
  export type Response = IDiscussionBoardAdministratorRequest;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/member/requests",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/member/requests";
  export const random = (): IDiscussionBoardAdministratorRequest =>
    typia.random<IDiscussionBoardAdministratorRequest>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
