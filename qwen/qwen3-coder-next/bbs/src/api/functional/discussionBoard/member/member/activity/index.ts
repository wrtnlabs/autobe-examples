export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = IDiscussionBoardMemberSession.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/member/member/activity",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/member/member/activity";
  export const random = (): IDiscussionBoardMemberSession.ISummary =>
    typia.random<IDiscussionBoardMemberSession.ISummary>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
