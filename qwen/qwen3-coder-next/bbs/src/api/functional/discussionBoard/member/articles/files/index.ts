import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardArticleFile } from "../../../../../structures/IDiscussionBoardArticleFile";

/**
 * Bulk upload files to an article
 *
 * This operation allows the article owner to upload multiple files to an article. Files are stored with unique identifiers and associated with the article for later retrieval.
 *
 * ## Security Considerations
 *
 * Only the article owner or administrators can upload files to an article. This ensures that only authorized users can add content to existing articles.
 *
 * ## File Storage
 *
 * Uploaded files are stored with unique identifiers and associated with the article. The file metadata is stored in the discussion_board_article_files table including original filename, stored path, MIME type, and file size.
 *
 * ## Authorization
 *
 * This operation requires member authentication. Only the article owner or administrators can upload files to an article.
 *
 * ## Related Operations
 *
 * - GET /articles/{articleId}/files/:fileId - Download a specific file
 * - DELETE /articles/{articleId}/files/:fileId - Delete a specific file from the article
 *
 * @param props.connection
 * @param props.articleId Target article's unique identifier
 * @param props.body Bulk file upload request
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Process multipart form data with multiple files. Generate unique identifiers for each file. Store file metadata in discussion_board_article_files table. Associate files with the article via article_id foreign key. Return array of IArticleFile metadata with all file information.
 * @path /discussionBoard/member/articles/:articleId/files
 * @accessor api.functional.discussionBoard.member.articles.files.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Target article's unique identifier
     */
    articleId: string;

    /**
     * Bulk file upload request
     */
    body: IDiscussionBoardArticleFile.ICreate;
  };
  export type Body = IDiscussionBoardArticleFile.ICreate;
  export type Response = IDiscussionBoardArticleFile;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/member/articles/:articleId/files",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/member/articles/${encodeURIComponent(props.articleId ?? "null")}/files`;
  export const random = (): IDiscussionBoardArticleFile =>
    typia.random<IDiscussionBoardArticleFile>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
