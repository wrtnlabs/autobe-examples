/**
 * ## Guest Session Join Operation
 *
 * This operation creates a new guest session for unauthenticated users accessing the discussion board. Guest users don't have credentials like passwords - they access the system anonymously through temporary session tokens.
 *
 * ### Purpose and Functionality
 *
 * The join operation initializes a new guest session by:
 * 1. Creating a new record in the `discussion_board_guests` table with a unique session token
 * 2. Setting up an initial session in `discussion_board_guest_sessions` with connection metadata
 * 3. Generating both access and refresh tokens for the guest session
 * 4. Returning session information including token expiration times
 *
 * ### Database Implementation
 *
 * The operation involves:
 * - Inserting into `discussion_board_guests` table with auto-generated UUID and session token
 * - Inserting into `discussion_board_guest_sessions` table with connection metadata (IP, referrer, href)
 * - Setting `expired_at` timestamp based on session timeout policy (typically 30 minutes)
 * - Storing `created_at` and `updated_at` timestamps in UTC format
 * - The `deleted_at` field remains null as guest sessions are not typically soft-deleted
 *
 * ### Security Considerations
 *
 * - Session tokens must be cryptographically secure random strings
 * - IP addresses are stored for security auditing purposes
 * - Referrer and href tracking helps understand user acquisition sources
 * - Sessions automatically expire after the timeout period
 * - No sensitive user data is stored in guest sessions
 *
 * ### Request Requirements
 *
 * The request may optionally include:
 * - IP address (extracted from request headers if not provided)
 * - Referrer URL (from HTTP referer header)
 * - Current page href (from request context)
 *
 * ### Response Structure
 *
 * The response returns an `IDiscussionBoardGuest.IAuthorized` object containing:
 * - Access token for immediate authentication
 * - Refresh token for session renewal
 * - Token expiration timestamps
 * - Session metadata including guest ID and session token
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Request body for creating a new guest session
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Create new guest session by generating session token and storing initial session metadata (IP address, referrer, current page). Returns the session token and expiration information.
 * @path /discussionBoard/auth/guest/join
 * @accessor api.functional.discussionBoard.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
