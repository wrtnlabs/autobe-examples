/**
 * Member registration endpoint for creating new account credentials in the Discussion Board application. This operation validates and stores member information including email, password hash, display name, and bio. The system ensures email uniqueness, applies password strength validation, and creates a new member record in the discussion_board_members table with the 'member' role. Upon successful registration, JWT access and refresh tokens are generated, the refresh token is stored in discussion_board_member_sessions with expiration, and both tokens are returned in the response.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration request body containing member credentials and profile information.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Member registration operation creates a new member account in the discussion_board_members table. The service layer validates email uniqueness, applies password hashing using bcrypt or similar secure algorithm, and stores the member with default role 'member', is_banned as false. The operation should include validation for email format, password strength requirements (minimum length, complexity), and display name constraints (1-100 characters). Upon successful registration, the operation generates JWT access and refresh tokens, stores the refresh token in the discussion_board_member_sessions table with expiration, and returns both tokens.
 * @path /discussionBoard/auth/member/join
 * @accessor api.functional.discussionBoard.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
