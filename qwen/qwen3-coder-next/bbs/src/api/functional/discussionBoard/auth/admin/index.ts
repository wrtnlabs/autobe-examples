/**
 * Admin registration endpoint that creates a new administrator account with email/password authentication. The system validates that the email is unique across all admin accounts, hashes the password using bcrypt algorithm, and creates a new admin record in the database with the provided display_name, email, and password_hash. The new admin is created with is_active set to true and is_super_admin set to false (regular administrator). The operation returns an authorized response containing access and refresh tokens for immediate authentication.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Request body for admin registration with email, password, and display name.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Handle admin registration by validating email uniqueness, hashing password with bcrypt, and creating admin record with provided display_name. Set is_active to true and is_super_admin to false by default. Return authorized response with tokens.
 * @path /discussionBoard/auth/admin/join
 * @accessor api.functional.discussionBoard.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
