/**
 * Super Admin Join Operation
 *
 * This API endpoint handles registration for super administrator accounts. Super administrators have complete system access and can manage all administrative functions including promoting regular admins to super admin status and demoting super admins to regular admin status.
 *
 * ## Purpose and Functionality
 *
 * The join operation creates new super admin accounts with the highest level of system control. It performs validation of the email address (must be unique), securely hashes the password using industry-standard algorithms, and creates the admin record in the system.
 *
 * ## Authentication Implementation
 *
 * The system stores passwords using bcrypt encryption with appropriate cost factors. Email addresses are verified through a token-based verification process before accounts become fully active. The registration process automatically logs in the user upon successful completion.
 *
 * ## Security Considerations
 *
 * This operation includes comprehensive security measures:
 * - Password complexity requirements to prevent weak passwords
 * - Email uniqueness validation to prevent account conflicts
 * - Secure password hashing using bcrypt
 * - Email verification through time-limited tokens
 * - Session creation for immediate access after registration
 * - Audit logging of registration events
 *
 * ## Database Schema Integration
 *
 * This operation directly interacts with the discussion_board_super_admins table which stores:
 * - Email address (unique)
 * - Password hash (bcrypt encrypted)
 * - Created and updated timestamps
 * - Email verification status
 * - Super admin role identifier
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration information for super admin account
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor superAdmin
 * @x-autobe-specification Process user registration for super admin account. Validate unique email, hash password with bcrypt, create admin record with emailVerified set to false, generate verification token, send verification email. If registration succeeds, automatically log in the user by creating a session token.
 * @path /discussionBoard/auth/super-admin/join
 * @accessor api.functional.discussionBoard.auth.super_admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
