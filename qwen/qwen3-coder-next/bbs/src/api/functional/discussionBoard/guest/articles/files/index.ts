/**
 * Retrieve all file attachments for a specific article.
 *
 * This operation returns a paginated list of all file attachments associated with the specified article. Each file attachment includes metadata such as the original filename, file type, storage path, and file size.
 *
 * ## Access Control
 * - Users must have permission to view the parent article to access its file attachments
 * - Article authors can access their article's files
 * - Administrators can access files for any article
 * - Guests can access files for publicly visible articles
 *
 * ## Use Cases
 * - Displaying download links for all files attached to an article
 * - Loading article attachments in a file browser interface
 * - Implementing bulk download functionality for article attachments
 *
 * @param props.connection
 * @param props.articleId Article's unique identifier
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Query discussion_board_article_files table filtered by discussion_board_article_id.
 * Implement pagination with configurable page size (default 10, max 100).
 * Return file metadata excluding sensitive information.
 * Apply soft delete filtering to exclude deleted files.
 * Implement access control to ensure user can view the parent article.
 * @path /discussionBoard/guest/articles/:articleId/files
 * @accessor api.functional.discussionBoard.guest.articles.files.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Article's unique identifier
     */
    articleId: string;
  };
  export type Response = IPageIDiscussionBoardArticleFile.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/guest/articles/:articleId/files",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/guest/articles/${encodeURIComponent(props.articleId ?? "null")}/files`;
  export const random = (): IPageIDiscussionBoardArticleFile.ISummary =>
    typia.random<IPageIDiscussionBoardArticleFile.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

