/**
 * Retrieve detailed information about a specific article.
 *
 * This operation fetches the complete article content including title, body, author information, timestamps, and associated metadata. It provides comprehensive article details for display to users viewing individual articles.
 *
 * Security considerations:
 * - Users can only access articles from sections they have permission to view
 * - Administrator and super administrator roles have access to view all articles regardless of section permissions
 * - Guest users can view articles from public sections but cannot access restricted content
 *
 * The operation returns complete article information including all attached files and images, making it suitable for full article page display.
 *
 * @param props.connection
 * @param props.articleId The unique identifier of the article to retrieve
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Query the discussion_board_articles table by articleId to retrieve complete article details.
 * Join with discussion_board_members table to fetch author information.
 * Join with discussion_board_article_files table to retrieve attached files.
 * Join with discussion_board_article_images table to retrieve attached images.
 * Join with discussion_board_article_tags table to retrieve associated tags.
 * Return the complete article entity with all nested relationships.
 * Handle cases where article does not exist by returning appropriate error response.
 * @path /discussionBoard/guest/articles/:articleId
 * @accessor api.functional.discussionBoard.guest.articles.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * The unique identifier of the article to retrieve
     */
    articleId: string;
  };
  export type Response = IDiscussionBoardArticle;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/guest/articles/:articleId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/guest/articles/${encodeURIComponent(props.articleId ?? "null")}`;
  export const random = (): IDiscussionBoardArticle =>
    typia.random<IDiscussionBoardArticle>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
