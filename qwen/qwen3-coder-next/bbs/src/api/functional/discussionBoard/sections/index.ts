import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardSection } from "../../../structures/IDiscussionBoardSection";
import { IPageIDiscussionBoardSection } from "../../../structures/IPageIDiscussionBoardSection";

/**
 * Retrieve a filtered and paginated list of content sections.
 *
 * This operation provides advanced search and filtering capabilities for content sections in the discussion board system. Users can search by section name and description, filter by specific section IDs, and sort results by creation date.
 *
 * The system supports comprehensive pagination with configurable page sizes, enabling efficient browsing of section lists even for large datasets.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query discussion_board_sections table with pagination and filtering.
 * Apply search filters on name and description fields.
 * Support filtering by specific section IDs.
 * Sort by createdAt timestamp (newest or oldest first).
 * Return paginated results with total count and page metadata.
 * @path /discussionBoard/sections
 * @accessor api.functional.discussionBoard.sections.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and pagination parameters
     */
    body: IDiscussionBoardSection.IRequest;
  };
  export type Body = IDiscussionBoardSection.IRequest;
  export type Response = IPageIDiscussionBoardSection.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/sections",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/sections";
  export const random = (): IPageIDiscussionBoardSection.ISummary =>
    typia.random<IPageIDiscussionBoardSection.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Retrieve detailed information about a specific section.
 *
 * This operation fetches the complete details of a section including its name, description, and creation timestamp. It provides comprehensive section information for users who want to understand the section's purpose and content focus.
 *
 * The operation is publicly accessible as section browsing is a fundamental feature of the discussion board system. No authentication is required to view section details, aligning with the public nature of content organization in the discussion board.
 *
 * Section details are essential for both new users exploring available topics and regular users who want to understand the section's scope before browsing articles.
 *
 * @param props.connection
 * @param props.sectionId Target section's UUID identifier
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query discussion_board_sections table by UUID ID.
 * Return complete section information including name, description, and creation timestamp.
 * Return error NOT_FOUND_001 if section does not exist.
 * No authorization required - section browsing is public.
 * @path /discussionBoard/sections/:sectionId
 * @accessor api.functional.discussionBoard.sections.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Target section's UUID identifier
     */
    sectionId: string;
  };
  export type Response = IDiscussionBoardSection;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/sections/:sectionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/sections/${encodeURIComponent(props.sectionId ?? "null")}`;
  export const random = (): IDiscussionBoardSection =>
    typia.random<IDiscussionBoardSection>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sectionId")(() => typia.assert(props.sectionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
