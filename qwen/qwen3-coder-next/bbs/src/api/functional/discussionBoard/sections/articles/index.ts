import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";

import { IDiscussionBoardArticle } from "../../../../structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../structures/IPageIDiscussionBoardArticle";

/**
 * Search and retrieve articles within a specific section.
 *
 * This operation allows searching articles within a specific section by title and content. Supports text search with partial matching, pagination with configurable page sizes, and sorting by creation date (newest first by default).
 *
 * The section context is provided via the sectionId path parameter, ensuring articles are scoped to the requested section. Only active (non-deleted) articles are returned. This operation uses the discussion_board_articles table which stores article content with title, author reference, section assignment, and timestamps.
 *
 * The search functionality leverages PostgreSQL trigram indexing for flexible text matching on both title and content fields, enabling partial word matches and approximate matching. Results are paginated to prevent overwhelming responses for large result sets.
 *
 * Related operations:
 * - GET /discussionBoard/sections - List all available sections
 * - GET /discussionBoard/articles/{articleId} - Retrieve a specific article by ID
 * - POST /discussionBoard/sections/{sectionId}/articles - Create a new article in a section (member/admin only)
 *
 * @param props.connection
 * @param props.sectionId Target section's unique identifier (UUID)
 * @param props.body Search criteria and pagination parameters
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query discussion_board_articles table filtered by section_id path parameter. Apply text search on title and content fields, support pagination with limit/offset, and sorting by created_at. Return paginated list of article summaries.
 * @path /discussionBoard/sections/:sectionId/articles
 * @accessor api.functional.discussionBoard.sections.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Target section's unique identifier (UUID)
     */
    sectionId: string & tags.Format<"uuid">;

    /**
     * Search criteria and pagination parameters
     */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/sections/:sectionId/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/sections/${encodeURIComponent(props.sectionId ?? "null")}/articles`;
  export const random = (): IPageIDiscussionBoardArticle.ISummary =>
    typia.random<IPageIDiscussionBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sectionId")(() => typia.assert(props.sectionId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
