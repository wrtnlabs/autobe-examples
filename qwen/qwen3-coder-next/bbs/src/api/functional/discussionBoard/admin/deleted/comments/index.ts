import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardArticleComment } from "../../../../../structures/IDiscussionBoardArticleComment";

/**
 * Bulk deletion of comments from the discussion board.
 *
 * This operation permanently removes multiple comments from the system in a single batch request. It supports deletion of comments by their authors or by administrators with appropriate permissions. Each deletion is properly recorded for audit purposes.
 *
 * The operation applies to the discussion_board_comments table and uses the system's soft-delete mechanism by setting the deleted_at timestamp. Comments marked as deleted remain in the database but are excluded from normal queries and API responses.
 *
 * @param props.connection
 * @param props.body IDs of comments to delete in batch
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Process bulk deletion of comments by their IDs.
 *
 * 1. Extract comment IDs from request body
 * 2. Validate that each comment ID exists in discussion_board_comments table
 * 3. Verify user authorization:
 *    - Comment authors can delete their own comments
 *    - Administrators can delete any comment
 *    - Regular users cannot delete others' comments
 * 4. For each authorized comment:
 *    - Set deleted_at timestamp to current time
 *    - Update updated_at timestamp
 *    - Log deletion action for audit
 * 5. Return count of successfully deleted comments
 * 6. Handle partial failures gracefully
 * 7. Return appropriate error status for unauthorized deletions
 * @path /discussionBoard/admin/deleted/comments
 * @accessor api.functional.discussionBoard.admin.deleted.comments.bulkErase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function bulkErase(
  connection: IConnection,
  props: bulkErase.Props,
): Promise<bulkErase.Response> {
  return true === connection.simulate
    ? bulkErase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...bulkErase.METADATA,
          path: bulkErase.path(),
          status: null,
        },
        props.body,
      );
}
export namespace bulkErase {
  export type Props = {
    /**
     * IDs of comments to delete in batch
     */
    body: IDiscussionBoardArticleComment.IRequest;
  };
  export type Body = IDiscussionBoardArticleComment.IRequest;
  export type Response = IDiscussionBoardArticleComment.IDeleteResponse;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/admin/deleted/comments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/admin/deleted/comments";
  export const random = (): IDiscussionBoardArticleComment.IDeleteResponse =>
    typia.random<IDiscussionBoardArticleComment.IDeleteResponse>();
  export const simulate = (
    connection: IConnection,
    props: bulkErase.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: bulkErase.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
