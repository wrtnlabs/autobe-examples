import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardMember } from "../../../../structures/IDiscussionBoardMember";

/**
 * Ban a user account, immediately deactivating their access to the system.
 *
 * This operation permanently deactivates the target user's account by setting is_active to false. The user's existing articles and comments remain visible to other users, but the user cannot log in or perform any actions.
 *
 * When a user is banned:
 * - All active sessions are immediately invalidated
 * - The user is logged out from all devices
 * - The is_active field is set to false
 * - The ban reason and administrator information are recorded
 * - All existing content remains accessible to other users
 * - The banned user's display name may be replaced with "Banned User" in public displays
 *
 * @param props.connection
 * @param props.id Target user's unique identifier
 * @param props.body Ban information including the reason for banning the user
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Update discussion_board_members table to set is_active = false for the specified user ID.
 * Record the current administrator ID (from JWT) and timestamp.
 * Invalidate all active sessions for the banned user by clearing session records.
 * Log the administrative action for audit purposes.
 * Use transaction to ensure atomicity of the database update and session cleanup.
 * @path /discussionBoard/admin/users/:id/ban
 * @accessor api.functional.discussionBoard.admin.users.ban
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function ban(
  connection: IConnection,
  props: ban.Props,
): Promise<void> {
  return true === connection.simulate
    ? ban.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...ban.METADATA,
          path: ban.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace ban {
  export type Props = {
    /**
     * Target user's unique identifier
     */
    id: string;

    /**
     * Ban information including the reason for banning the user
     */
    body: IDiscussionBoardMember.IBanRequest;
  };
  export type Body = IDiscussionBoardMember.IBanRequest;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/admin/users/:id/ban",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/admin/users/${encodeURIComponent(props.id ?? "null")}/ban`;
  export const random = (): void => typia.random<void>();
  export const simulate = (connection: IConnection, props: ban.Props): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: ban.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("id")(() => typia.assert(props.id));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
