/**
 * Retrieve a specific system configuration parameter by its unique configuration key.
 *
 * This operation fetches a single system configuration from the discussion_board_system_settings table. It's designed to retrieve individual configuration parameters that control system behavior, feature flags, and operational settings.
 *
 * The configuration key must be provided as a path parameter. The system supports both active and inactive configurations, allowing retrieval of both current and archived configuration values.
 *
 * Security Considerations:
 * - System configuration may contain sensitive operational parameters
 * - Administrators should have read access to view all configurations
 * - Configuration values may include API keys, secrets, or other sensitive data that should be properly secured
 * - Audit logging should track configuration access for compliance purposes
 *
 * The system supports category-based organization for easier configuration management and retrieval.
 *
 * Related Operations:
 * - GET /settings - Retrieve all active configurations (paginated list)
 * - PATCH /settings - Update existing configuration parameters
 * - POST /settings - Create new configuration parameters
 * - DELETE /settings/{settingId} - Deactivate configuration parameters (soft delete)
 *
 * @param props.connection
 * @param props.settingId Unique configuration key identifier. This corresponds to the config_key field in the discussion_board_system_settings table which is marked as unique.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query discussion_board_system_settings table by config_key field.
 * Return single record with all fields: id, config_key, config_value, description, category, is_enabled, created_at, updated_at, deleted_at.
 * Return 404 if config_key not found in database.
 * Handle soft-deleted configurations appropriately based on business requirements.
 * @path /discussionBoard/admin/settings/:settingId
 * @accessor api.functional.discussionBoard.admin.settings.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique configuration key identifier. This corresponds to the config_key field in the discussion_board_system_settings table which is marked as unique.
     */
    settingId: string;
  };
  export type Response = IDiscussionBoardSystemSetting;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/admin/settings/:settingId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/admin/settings/${encodeURIComponent(props.settingId ?? "null")}`;
  export const random = (): IDiscussionBoardSystemSetting =>
    typia.random<IDiscussionBoardSystemSetting>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("settingId")(() => typia.assert(props.settingId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

