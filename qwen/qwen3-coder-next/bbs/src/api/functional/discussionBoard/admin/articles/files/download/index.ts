import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardArticleFile } from "../../../../../../structures/IDiscussionBoardArticleFile";

/**
 * Download a specific file attached to an article.
 *
 * This endpoint retrieves the metadata and serves the file content for attachment files that have been attached to articles. Users must have permission to access the parent article to download its attachments.
 *
 * Security considerations include verifying user authorization for the parent article and preventing unauthorized file access. The system should serve files with appropriate content type headers based on the file's MIME type.
 *
 * This operation is related to:
 * - GET /articles/{articleId}/files - List all files attached to an article
 * - POST /articles/{articleId}/files - Upload files to an article
 * - DELETE /articles/{articleId}/files/{fileId} - Remove a file from an article
 *
 * The download flow validates user permissions, retrieves the file by unique identifier, and streams it to the user with appropriate content type headers.
 *
 * @param props.connection
 * @param props.articleId ID of the article containing the attachment file
 * @param props.fileId ID of the file to download
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Retrieve article file by articleId and fileId from discussion_board_article_files table.
 * Validate user authorization to access the parent article.
 * Generate temporary signed URL for file download if using cloud storage.
 * Return file metadata including download URL, MIME type, original filename, and file size.
 * Support resumable downloads for large files over 10 MB.
 * @path /discussionBoard/admin/articles/:articleId/files/:fileId/download
 * @accessor api.functional.discussionBoard.admin.articles.files.download.downloadFile
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function downloadFile(
  connection: IConnection,
  props: downloadFile.Props,
): Promise<downloadFile.Response> {
  return true === connection.simulate
    ? downloadFile.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...downloadFile.METADATA,
          path: downloadFile.path(props),
          status: null,
        },
      );
}
export namespace downloadFile {
  export type Props = {
    /**
     * ID of the article containing the attachment file
     */
    articleId: string;

    /**
     * ID of the file to download
     */
    fileId: string;
  };
  export type Response = IDiscussionBoardArticleFile.IDownload;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/admin/articles/:articleId/files/:fileId/download",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/admin/articles/${encodeURIComponent(props.articleId ?? "null")}/files/${encodeURIComponent(props.fileId ?? "null")}/download`;
  export const random = (): IDiscussionBoardArticleFile.IDownload =>
    typia.random<IDiscussionBoardArticleFile.IDownload>();
  export const simulate = (
    connection: IConnection,
    props: downloadFile.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: downloadFile.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.param("fileId")(() => typia.assert(props.fileId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
