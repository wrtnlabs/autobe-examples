/**
 * Create a new discussion section for content categorization.
 *
 * This operation allows administrators to create new sections in the discussion board, enabling organized content categorization. Each section must have a unique name and can include an optional detailed description explaining the section's purpose and scope.
 *
 * Security considerations: Only users with administrator permissions can create sections. Regular members and guests attempting to use this endpoint will receive a 403 Forbidden response.
 *
 * The system enforces unique section names across the entire discussion board to prevent confusion and maintain organized content structure. When a section is created, it becomes immediately available for article posting.
 *
 * Related API operations:
 * - GET /sections: Retrieve list of all available sections
 * - PUT /sections/{id}: Update section information
 * - DELETE /sections/{id}: Remove a section from the discussion board
 *
 * @param props.connection
 * @param props.body Section creation information including unique name and optional description
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Create a new discussion board section with the provided name and description.
 *
 * 1. Validate input data:
 *    - Check that 'name' field is provided and not empty
 *    - Check that 'name' length is within limits (1-100 characters)
 *    - Check that 'description' length is within limits (if provided, 1-1000 characters)
 *    - Check that 'name' is unique across all sections
 *    - Verify user has administrator permissions
 *
 * 2. Create new section record in database:
 *    - Generate new UUID for section id
 *    - Set created_at and updated_at to current timestamp
 *    - Store name and description
 *
 * 3. Return created section with all fields including timestamps
 *
 * Handle validation errors with appropriate HTTP status codes and error messages.
 * @path /discussionBoard/admin/sections
 * @accessor api.functional.discussionBoard.admin.sections.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
