import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardComment } from "../../../structures/IDiscussionBoardComment";

/**
 * Retrieve detailed information about a specific comment.
 *
 * This operation fetches a single comment by its unique identifier. The system checks the user's role and permissions to determine what information to return. Regular members can only view active (non-deleted) comments, while administrators have the ability to view deleted comments for auditing purposes.
 *
 * When a comment is soft-deleted (deleted_at is not null), regular users will see an appropriate error message indicating the comment is not available, while administrators will see the comment with its deletion timestamp.
 *
 * The operation returns the complete comment information including author details, content, timestamps, and associated article context.
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the comment to retrieve
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query discussion_board_comments table by id. Check user role: regular users only see comments where deleted_at is null; administrators see all comments. If comment is deleted and user is not admin, return error 'Comment not found'. Join with discussion_board_members for author information. Return full comment record with all fields including deleted_at timestamp for admin users.
 * @path /discussionBoard/comments/:commentId
 * @accessor api.functional.discussionBoard.comments.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the comment to retrieve
     */
    commentId: string;
  };
  export type Response = IDiscussionBoardComment;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/comments/:commentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/comments/${encodeURIComponent(props.commentId ?? "null")}`;
  export const random = (): IDiscussionBoardComment =>
    typia.random<IDiscussionBoardComment>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
