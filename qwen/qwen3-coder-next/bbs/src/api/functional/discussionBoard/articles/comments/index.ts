import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardComment } from "../../../../structures/IDiscussionBoardComment";
import { IPageIDiscussionBoardComment } from "../../../../structures/IPageIDiscussionBoardComment";

/**
 * Retrieve all comments associated with a specific article for discussion engagement.
 *
 * This endpoint provides access to the complete comment history for a given article, displaying all non-deleted comments in chronological order. Comments are sorted from oldest to newest by default, supporting both guest viewing and member participation.
 *
 * The operation supports comprehensive pagination with configurable page sizes and sorting options. Response includes comment author information, content, creation timestamps, and pagination metadata for efficient client-side rendering of comment threads.
 *
 * Security and permissions:
 * - Available to all users (guests can view comments on articles)
 * - Deleted comments are hidden from public display
 * - Comment count is tracked and displayed on articles
 *
 * The endpoint aligns with the article's comment section functionality, providing the backend API for the frontend comment display component.
 *
 * @param props.connection
 * @param props.articleId ID of the target article whose comments are being retrieved. This corresponds to discussion_board_articles.id and filters all comments to only those associated with this specific article.
 * @param props.body Pagination and sorting parameters for comment retrieval
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query discussion_board_comments table filtered by article_id path parameter.
 * Apply chronological sorting (oldest first by default, newest first when request body sortBy is 'newest').
 * Implement pagination with configurable page size (default: 20, max: 100).
 * Return paginated list of comment summaries including author display name, content, and timestamps.
 * Filter out soft-deleted comments (deleted_at IS NULL) unless user has administrative privileges.
 * @path /discussionBoard/articles/:articleId/comments
 * @accessor api.functional.discussionBoard.articles.comments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * ID of the target article whose comments are being retrieved. This corresponds to discussion_board_articles.id and filters all comments to only those associated with this specific article.
     */
    articleId: string;

    /**
     * Pagination and sorting parameters for comment retrieval
     */
    body: IDiscussionBoardComment.IRequest;
  };
  export type Body = IDiscussionBoardComment.IRequest;
  export type Response = IPageIDiscussionBoardComment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/articles/:articleId/comments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/comments`;
  export const random = (): IPageIDiscussionBoardComment.ISummary =>
    typia.random<IPageIDiscussionBoardComment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
