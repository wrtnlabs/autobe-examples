/**
 * Retrieve detailed information about a specific article by its ID.
 *
 * This operation provides access to a single article's complete information including its title, content, author details, associated section, tags, and file attachments. It supports the core functionality of viewing article content and metadata.
 *
 * The operation enforces data isolation by verifying the user has appropriate permissions to view the article. Soft-deleted articles are not returned in results. This endpoint is essential for the article detail page functionality in the discussion board system.
 *
 * @param props.connection
 * @param props.articleId Target article's unique identifier (UUID)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query discussion_board_articles table by id, join with sections, authors (members/admins/super_admins/guests), tags, and file attachments. Handle soft-deleted articles by checking deleted_at IS NULL. Return complete article object with all related data.
 * @path /discussionBoard/articles/:articleId
 * @accessor api.functional.discussionBoard.articles.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Target article's unique identifier (UUID)
     */
    articleId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardArticle;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/articles/:articleId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}`;
  export const random = (): IDiscussionBoardArticle =>
    typia.random<IDiscussionBoardArticle>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Search for articles across the discussion board with comprehensive filtering and pagination.
 *
 * This operation provides advanced search capabilities including keyword matching against article titles and content, tag-based filtering, and section-specific searches. The system performs case-insensitive partial matching on search terms, allowing users to find articles even with partial keyword input.
 *
 * Supports multiple search criteria combined with AND logic: search terms, tags, and section filtering. Results are returned with pagination to handle large result sets efficiently. The search excludes articles that have been soft-deleted from the system.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query discussion_board_articles table with pagination and search filters.
 * Apply case-insensitive partial matching on title and content fields.
 * Support tag-based filtering by joining with discussion_board_article_tags table.
 * Apply section filtering if section_id parameter provided.
 * Exclude soft-deleted articles (deleted_at IS NULL).
 * Return results sorted by created_at descending by default.
 * @path /discussionBoard/articles/search
 * @accessor api.functional.discussionBoard.articles.search
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
