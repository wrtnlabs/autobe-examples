import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";

/**
 * Download a specific file attachment from an article.
 *
 * This operation retrieves and delivers a file that has been attached to an article. Users can download files from articles they have permission to view based on their role and the article's visibility settings.
 *
 * The system verifies access rights before delivering the file content and ensures the file attachment belongs to the specified article.
 *
 * @param props.connection
 * @param props.articleId Target article's ID
 * @param props.fileId Target file's ID
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query discussion_board_article_files table for record matching articleId and fileId. Verify user has access to the article (guest for public, member for viewable, admin for all). Return file content using stored file_url with appropriate content-type header.
 * @path /discussionBoard/articles/:articleId/files/:fileId/download
 * @accessor api.functional.discussionBoard.articles.files.download.downloadFile
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function downloadFile(
  connection: IConnection,
  props: downloadFile.Props,
): Promise<void> {
  return true === connection.simulate
    ? downloadFile.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...downloadFile.METADATA,
          path: downloadFile.path(props),
          status: null,
        },
      );
}
export namespace downloadFile {
  export type Props = {
    /**
     * Target article's ID
     */
    articleId: string & tags.Format<"uuid">;

    /**
     * Target file's ID
     */
    fileId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/articles/:articleId/files/:fileId/download",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/files/${encodeURIComponent(props.fileId ?? "null")}/download`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: downloadFile.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: downloadFile.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.param("fileId")(() => typia.assert(props.fileId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
