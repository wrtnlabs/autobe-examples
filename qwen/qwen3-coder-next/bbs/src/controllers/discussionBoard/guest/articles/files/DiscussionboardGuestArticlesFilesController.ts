import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardArticleFile } from "../../../../../api/structures/IDiscussionBoardArticleFile";
import { IPageIDiscussionBoardArticleFile } from "../../../../../api/structures/IPageIDiscussionBoardArticleFile";
import { GuestAuth } from "../../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../../decorators/payload/GuestPayload";
import { getDiscussionBoardGuestArticlesArticleIdFiles } from "../../../../../providers/getDiscussionBoardGuestArticlesArticleIdFiles";
import { getDiscussionBoardGuestArticlesArticleIdFilesFileIdDownload } from "../../../../../providers/getDiscussionBoardGuestArticlesArticleIdFilesFileIdDownload";

@Controller("/discussionBoard/guest/articles/:articleId/files")
export class DiscussionboardGuestArticlesFilesController {
  /**
   * Retrieve all file attachments for a specific article.
   *
   * This operation returns a paginated list of all file attachments associated with the specified article. Each file attachment includes metadata such as the original filename, file type, storage path, and file size.
   *
   * ## Access Control
   * - Users must have permission to view the parent article to access its file attachments
   * - Article authors can access their article's files
   * - Administrators can access files for any article
   * - Guests can access files for publicly visible articles
   *
   * ## Use Cases
   * - Displaying download links for all files attached to an article
   * - Loading article attachments in a file browser interface
   * - Implementing bulk download functionality for article attachments
   *
   * @param connection
   * @param articleId Article's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query discussion_board_article_files table filtered by discussion_board_article_id.
   * Implement pagination with configurable page size (default 10, max 100).
   * Return file metadata excluding sensitive information.
   * Apply soft delete filtering to exclude deleted files.
   * Implement access control to ensure user can view the parent article.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("articleId")
    articleId: string,
  ): Promise<IPageIDiscussionBoardArticleFile.ISummary> {
    try {
      return await getDiscussionBoardGuestArticlesArticleIdFiles({
        guest,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific file attachment from an article.
   *
   * This operation retrieves a file attachment that was previously uploaded to an article on the discussion board. Users can download any file attachment by specifying both the article identifier and the specific file identifier.
   *
   * ## Security Considerations
   *
   * - File access is restricted to authorized users with proper permissions
   * - The system validates that the file exists and is accessible
   * - File paths are validated to prevent directory traversal attacks
   * - Article existence is verified before file access is granted
   *
   * ## File Access
   *
   * When the download is successful, the system returns the file metadata including original filename, file type, and size information. The actual file can be downloaded using the stored path.
   *
   * @param connection
   * @param articleId Target article's unique identifier
   * @param fileId Target file's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Retrieve file attachment from discussion_board_article_files table by joining with discussion_board_articles to validate file exists.
   * Validate user permissions before accessing file.
   * Return stored_path as URI string for file download.
   * Handle soft-deleted files by returning 404.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":fileId/download")
  public async download(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("articleId")
    articleId: string,
    @TypedParam("fileId")
    fileId: string,
  ): Promise<IDiscussionBoardArticleFile> {
    try {
      return await getDiscussionBoardGuestArticlesArticleIdFilesFileIdDownload({
        guest,
        articleId,
        fileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
