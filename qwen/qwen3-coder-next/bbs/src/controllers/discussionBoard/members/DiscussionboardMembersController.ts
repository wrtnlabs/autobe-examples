import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardMember } from "../../../api/structures/IDiscussionBoardMember";
import { IPageIDiscussionBoardMember } from "../../../api/structures/IPageIDiscussionBoardMember";
import { getDiscussionBoardMembersMemberId } from "../../../providers/getDiscussionBoardMembersMemberId";
import { patchDiscussionBoardMembers } from "../../../providers/patchDiscussionBoardMembers";

@Controller("/discussionBoard/members")
export class DiscussionboardMembersController {
  /**
   * Retrieve a filtered and paginated list of discussion board members.
   *
   * This operation provides advanced search and filtering capabilities including active status filtering, admin role filtering, and partial name/email matching.
   *
   * Supports comprehensive pagination with configurable page sizes and sorting. Response includes member summary information optimized for list displays.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_members table with pagination and filtering.
   * Apply search filters on display_name, email, is_active status, is_admin status, and is_super_admin status.
   * Use PostgreSQL full-text search for display name and bio fields using trigram operations.
   * Return cursor-based pagination for large result sets.
   * Include only active members by default unless explicitly filtering for inactive/banned users.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardMember.IRequest,
  ): Promise<IPageIDiscussionBoardMember.ISummary> {
    try {
      return await patchDiscussionBoardMembers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a member's profile information.
   *
   * This operation provides access to individual member profiles. The level of detail returned depends on the requester's authentication status and role. Authenticated members can view enhanced profile information, while guests receive limited publicly available data.
   *
   * The system implements role-based access control to protect member privacy. Regular members can view basic profile information, while administrators have access to additional system information such as account status and administrative roles.
   *
   * @param connection
   * @param memberId Target member's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_members table by primary key to retrieve member profile.
   * Apply field redaction based on requester role:
   * - Guests: Return only id, email, displayName, createdAt
   * - Members: Return additional bio, profileImage if available
   * - Admins: Return all fields including accountStatus, lastLoginAt
   * Join with related tables for member statistics (article count, comment count).
   * Return 404 if member not found. Implement proper authorization middleware before execution.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":memberId")
  public async at(
    @TypedParam("memberId")
    memberId: string,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await getDiscussionBoardMembersMemberId({
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
