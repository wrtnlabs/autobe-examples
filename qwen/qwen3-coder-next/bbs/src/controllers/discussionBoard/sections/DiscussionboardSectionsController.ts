import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSection } from "../../../api/structures/IDiscussionBoardSection";
import { getDiscussionBoardSectionsSectionId } from "../../../providers/getDiscussionBoardSectionsSectionId";
import { patchDiscussionBoardSections } from "../../../providers/patchDiscussionBoardSections";

@Controller("/discussionBoard/sections")
export class DiscussionboardSectionsController {
  /**
   * Permanently update an existing section in the discussion board.
   *
   * This operation allows administrators to modify the name and description of existing sections. When a section is updated, the system automatically updates the updated_at timestamp.
   *
   * The operation supports partial updates - you can update the name, description, or both simultaneously. The section must exist and be accessible to the current administrator for the update to succeed.
   *
   * @param connection
   * @param body Section update parameters including optional name and description fields.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Update discussion_board_sections table record with partial field updates.
   * Apply update to section identified by current admin context.
   * Update the updated_at timestamp to current timestamp.
   * Maintain soft delete integrity (ignore deleted_at records).
   * Return updated section record with current values.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @TypedBody()
    body: IDiscussionBoardSection.IUpdate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await patchDiscussionBoardSections({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific discussion board section.
   *
   * This operation provides comprehensive section details including the section name, description, and timestamps. It allows users to understand the purpose and scope of each section before browsing its content.
   *
   * ## Security Considerations
   *
   * This operation is publicly accessible and does not require authentication. Both guest and authenticated users can view section information. The operation does not expose sensitive data and is designed for browsing purposes.
   *
   * ## Database Relationships
   *
   * This operation retrieves section information from the discussion_board_sections table. The section serves as a container for articles and provides organizational structure for the discussion board. Articles in this section can be retrieved through the related operation that lists articles within a specific section.
   *
   * ## Validation and Business Logic
   *
   * The operation validates that the requested section ID exists in the database. If the section has been deleted (soft deleted), the operation handles it appropriately. No special business logic applies to section retrieval beyond standard database lookup.
   *
   * ## Related Operations
   *
   * - GET /sections: Retrieve a paginated list of all sections
   * - POST /sections: Create a new section (admin only)
   * - PUT /sections/{sectionId}: Update section information (admin only)
   * - DELETE /sections/{sectionId}: Delete a section (admin only)
   * - GET /sections/{sectionId}/articles: List articles within a specific section
   *
   * ## Expected Behavior
   *
   * When a section exists, the operation returns the section details including name, description, and timestamps. If the section does not exist, the operation returns a 404 Not Found response. Soft-deleted sections are handled according to the system's soft-delete policy.
   *
   * @param connection
   * @param sectionId Unique identifier of the section to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Retrieve section information from discussion_board_sections table by ID.
   * Query the database using the section ID parameter.
   * Return the section record with all fields including id, name, description, created_at, updated_at, and deleted_at.
   * Handle cases where section does not exist or has been soft-deleted.
   * Return appropriate HTTP status codes (200 for success, 404 for not found).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sectionId")
  public async at(
    @TypedParam("sectionId")
    sectionId: string,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await getDiscussionBoardSectionsSectionId({
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
