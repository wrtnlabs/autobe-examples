import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSection } from "../../../api/structures/IDiscussionBoardSection";
import { IPageIDiscussionBoardSection } from "../../../api/structures/IPageIDiscussionBoardSection";
import { getDiscussionBoardSectionsSectionId } from "../../../providers/getDiscussionBoardSectionsSectionId";
import { patchDiscussionBoardSections } from "../../../providers/patchDiscussionBoardSections";

@Controller("/discussionBoard/sections")
export class DiscussionboardSectionsController {
  /**
   * Retrieve a filtered and paginated list of content sections.
   *
   * This operation provides advanced search and filtering capabilities for content sections in the discussion board system. Users can search by section name and description, filter by specific section IDs, and sort results by creation date.
   *
   * The system supports comprehensive pagination with configurable page sizes, enabling efficient browsing of section lists even for large datasets.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_sections table with pagination and filtering.
   * Apply search filters on name and description fields.
   * Support filtering by specific section IDs.
   * Sort by createdAt timestamp (newest or oldest first).
   * Return paginated results with total count and page metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardSection.IRequest,
  ): Promise<IPageIDiscussionBoardSection.ISummary> {
    try {
      return await patchDiscussionBoardSections({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific section.
   *
   * This operation fetches the complete details of a section including its name, description, and creation timestamp. It provides comprehensive section information for users who want to understand the section's purpose and content focus.
   *
   * The operation is publicly accessible as section browsing is a fundamental feature of the discussion board system. No authentication is required to view section details, aligning with the public nature of content organization in the discussion board.
   *
   * Section details are essential for both new users exploring available topics and regular users who want to understand the section's scope before browsing articles.
   *
   * @param connection
   * @param sectionId Target section's UUID identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_sections table by UUID ID.
   * Return complete section information including name, description, and creation timestamp.
   * Return error NOT_FOUND_001 if section does not exist.
   * No authorization required - section browsing is public.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sectionId")
  public async at(
    @TypedParam("sectionId")
    sectionId: string,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await getDiscussionBoardSectionsSectionId({
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
