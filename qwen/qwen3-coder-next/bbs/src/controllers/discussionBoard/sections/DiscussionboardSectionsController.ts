import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardSection } from "../../../api/structures/IDiscussionBoardSection";
import { IPageIDiscussionBoardSection } from "../../../api/structures/IPageIDiscussionBoardSection";
import { getDiscussionBoardSectionsSectionId } from "../../../providers/getDiscussionBoardSectionsSectionId";
import { patchDiscussionBoardSections } from "../../../providers/patchDiscussionBoardSections";

@Controller("/discussionBoard/sections")
export class DiscussionboardSectionsController {
  /**
   * Retrieve a paginated list of discussion sections.
   *
   * This operation provides comprehensive section listing functionality including pagination controls, creation time ordering, and article count statistics. Users can navigate through sections efficiently with configurable page sizes.
   *
   * The sections are retrieved from the discussion_board_sections table which stores topic categories with name and description fields. Each section includes the count of articles associated with it for content organization purposes. Sections are ordered by creation time in descending order (newest first) to show most recently created sections first.
   *
   * The system enforces uniqueness of section names through the @@unique([name]) constraint and uses created_at, updated_at, and deleted_at timestamp fields for proper version tracking and soft deletion support.
   *
   * Supports comprehensive pagination with configurable page sizes and sorting. Response includes section summary information optimized for list displays.
   *
   * @param connection
   * @param body Pagination parameters for section listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_sections table with pagination and filtering. Return sections ordered by creation time (newest first). Include section name, description, and article count for each. Support configurable page size and return total count in response metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardSection.IRequest,
  ): Promise<IPageIDiscussionBoardSection.ISummary> {
    try {
      return await patchDiscussionBoardSections({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific section.
   *
   * This operation fetches a single section by its unique name identifier. The section contains its name, description, and timestamps for creation and updates.
   *
   * Access control: Guest and member users can view section details. The operation returns 404 Not Found if the section does not exist.
   *
   * @param connection
   * @param sectionId Unique identifier of the section to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_sections table by id field. Return section record with all fields (id, name, description, created_at, updated_at, deleted_at). Nojoins required for this simple lookup.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sectionId")
  public async at(
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await getDiscussionBoardSectionsSectionId({
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
