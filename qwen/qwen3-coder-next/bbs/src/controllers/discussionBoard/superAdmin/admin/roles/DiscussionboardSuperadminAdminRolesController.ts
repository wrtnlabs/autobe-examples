import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardAdminsRole } from "../../../../../api/structures/IDiscussionBoardAdminsRole";
import { SuperadminAuth } from "../../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../../decorators/payload/SuperadminPayload";
import { getDiscussionBoardSuperAdminAdminRolesRoleId } from "../../../../../providers/getDiscussionBoardSuperAdminAdminRolesRoleId";
import { patchDiscussionBoardSuperAdminAdminRoles } from "../../../../../providers/patchDiscussionBoardSuperAdminAdminRoles";

@Controller("/discussionBoard/superAdmin/admin/roles")
export class DiscussionboardSuperadminAdminRolesController {
  /**
   * Admin Role Management Operation
   *
   * This API endpoint manages the administrative role hierarchy within the discussion board system. It provides capabilities for promoting regular administrators to super administrators and demoting super administrators to regular administrator status.
   *
   * ## Role Hierarchy and Authorization
   *
   * The discussion board implements a two-tier administrator system:
   *
   * - **Regular Administrator**: Standard administrative privileges for content moderation, user management, and section management
   * - **Super Administrator**: Complete system access including the ability to promote and demote other administrators
   *
   * ## Security Considerations
   *
   * This endpoint is restricted to super administrator users only. All role changes are logged in the audit system for accountability and compliance purposes.
   *
   * ## Business Logic
   *
   * - Super administrators can promote regular administrators to super administrator status
   * - Super administrators can demote other super administrators to regular administrator status
   * - A super administrator cannot demote themselves to prevent administrative gaps
   * - All role changes require explicit confirmation and are recorded in the audit log
   *
   * ## Audit Trail
   *
   * Every role change operation records:
   * - Theacting super administrator (for accountability)
   * - The target user being modified
   * - The action performed (promotion or demotion)
   * - Timestamp and system context
   *
   * @param connection
   * @param body Admin role management request with target user and action specification
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Process admin role management operations for promoting regular admins to super admin and demoting super admins to regular admin.
   *
   * The endpoint accepts a request body with:
   * - userId: The target user's ID
   * - action: Either 'promoteToSuper' or 'demoteToAdmin'
   *
   * Implementation steps:
   * 1. Verify caller is super admin
   * 2. Load target user's current admin status
   * 3. Validate action is valid (e.g., cannot demote self)
   * 4. Update user's admin grade in the database
   * 5. Record audit log entry with acting admin, target user, action, and timestamp
   * 6. Return updated user information with new role status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async manageRole(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IDiscussionBoardAdminsRole.IManageRequest,
  ): Promise<IDiscussionBoardAdminsRole> {
    try {
      return await patchDiscussionBoardSuperAdminAdminRoles({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific administrator role.
   *
   * This operation fetches the complete administrator role details including the role name, description, and associated permissions from the discussion_board_admins_roles table. It provides comprehensive information about the role's capabilities and scope.
   *
   * The operation requires appropriate authorization based on the user's current role. Regular administrators can view their own role information, while super administrators can view all administrator roles in the system.
   *
   * @param connection
   * @param roleId Unique identifier of the administrator role to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Retrieve a specific administrator role from the discussion_board_admins_roles table by its ID. Validate user authorization before returning the role details. Return 404 if role not found, 403 if unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":roleId")
  public async at(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("roleId")
    roleId: string,
  ): Promise<IDiscussionBoardAdminsRole> {
    try {
      return await getDiscussionBoardSuperAdminAdminRolesRoleId({
        superAdmin,
        roleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
