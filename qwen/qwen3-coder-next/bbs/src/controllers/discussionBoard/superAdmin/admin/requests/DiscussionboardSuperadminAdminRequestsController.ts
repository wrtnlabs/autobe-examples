import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardAdminsRequest } from "../../../../../api/structures/IDiscussionBoardAdminsRequest";
import { SuperadminAuth } from "../../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../../decorators/payload/SuperadminPayload";
import { patchDiscussionBoardSuperAdminAdminRequestsRequestIdReject } from "../../../../../providers/patchDiscussionBoardSuperAdminAdminRequestsRequestIdReject";
import { putDiscussionBoardSuperAdminAdminRequestsRequestId } from "../../../../../providers/putDiscussionBoardSuperAdminAdminRequestsRequestId";
import { putDiscussionBoardSuperAdminAdminRequestsRequestIdApprove } from "../../../../../providers/putDiscussionBoardSuperAdminAdminRequestsRequestIdApprove";

@Controller("/discussionBoard/superAdmin/admin/requests/:requestId")
export class DiscussionboardSuperadminAdminRequestsController {
  /**
   * Update an administrator request with new information.
   *
   * This operation updates an existing administrator request with new data including the reason for the request, current status (pending/approved/rejected), and administrative processing information. Only super administrators have permission to update administrator requests.
   *
   * The operation requires the unique request identifier (requestId) to locate the specific request to update. When updating, the system validates that the user has super administrator privileges and that the request status transitions are valid.
   *
   * This endpoint is specifically designed for the administrator request processing workflow, allowing super administrators to modify request details as the request moves through the approval process from pending to either approved or rejected status.
   *
   * @param connection
   * @param requestId Unique identifier of the administrator request to update.
   * @param body Update information for the administrator request.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Update discussion_board_admins_requests table record by primary key ID.
   * Validate user has administrative privileges before allowing updates.
   * Enforce valid status transitions (pending -> approved/rejected).
   * Update admin_id or super_admin_id when request is processed.
   * Record current timestamp in updated_at field.
   * Return updated request with all fields including timestamps and relationship references.
   * Handle cases where requestId does not exist by returning appropriate error response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("requestId")
    requestId: string,
    @TypedBody()
    body: IDiscussionBoardAdminsRequest.IUpdate,
  ): Promise<IDiscussionBoardAdminsRequest> {
    try {
      return await putDiscussionBoardSuperAdminAdminRequestsRequestId({
        superAdmin,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Approve an administrator request.
   *
   * This operation approves a pending administrator request, granting the requesting user administrator privileges. The system will update the request status to 'approved', record the timestamp of approval, and associate the approving administrator with the request.
   *
   * Administrators can process administrator requests submitted by regular users who want to gain administrative capabilities on the platform. Only super administrators can promote users to super administrator status, but regular administrators can approve requests for regular administrator privileges.
   *
   * The approval action triggers the creation of an administrator role for the requesting user, enabling them to access the administrator dashboard and perform administrative functions.
   *
   * This operation is idempotent - calling it on an already approved request will not change the outcome.
   *
   * @param connection
   * @param requestId The unique identifier of the administrator request to approve. This is the primary key from the discussion_board_admins_requests table.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Update the administrator request status to 'approved' and record the approving administrator.
   *
   * Steps:
   * 1. Validate the requesting user exists in discussion_board_members table
   * 2. Update the discussion_board_admins_requests record with:
   *    - Set status to 'approved'
   *    - Set approved_at to current timestamp
   *    - Set admin_id to current administrator's user ID
   * 3. Create an entry in discussion_board_admins_roles table for the requesting user with grade 'regular'
   * 4. Log the administrative action for audit purposes
   * 5. Return the updated administrator request record with all related data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put("approve")
  public async approve(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("requestId")
    requestId: string,
  ): Promise<IDiscussionBoardAdminsRequest> {
    try {
      return await putDiscussionBoardSuperAdminAdminRequestsRequestIdApprove({
        superAdmin,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Reject an administrator request and notify the requesting user.
   *
   * This operation allows authorized administrators to reject pending administrator requests submitted by regular users. When a request is rejected, the system updates the request status, records the rejection details including the rejecting administrator and timestamp, and notifies the requesting user of the decision.
   *
   * The rejection functionality provides administrators with the ability to decline administrator privilege requests when the requesting user does not meet the required qualifications or when the request does not align with community needs. Administrators should provide appropriate feedback when rejecting requests to help users understand why their request was declined.
   *
   * This operation requires administrator privileges and appropriate authorization to prevent unauthorized manipulation of administrator requests.
   *
   * @param connection
   * @param requestId Target administrator request's UUID identifier.
   * @param body Rejection details including administrative feedback.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Process administrator request rejection.
   * Query the discussion_board_admins_requests table by requestId to locate the pending request.
   * Update the request status to 'rejected' and set the admin_id to the current administrator's ID.
   * Record the rejection timestamp in the approved_at field.
   * Log the administrative action in the discussion_board_admins_requests record.
   * Query the discussion_board_members table to retrieve the requesting user's information.
   * Send a notification to the requesting user explaining the rejection decision.
   * Return the updated request record with rejection details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("reject")
  public async reject(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("requestId")
    requestId: string,
    @TypedBody()
    body: IDiscussionBoardAdminsRequest.IReject,
  ): Promise<IDiscussionBoardAdminsRequest> {
    try {
      return await patchDiscussionBoardSuperAdminAdminRequestsRequestIdReject({
        superAdmin,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
