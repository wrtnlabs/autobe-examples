import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardAdministratorRequest } from "../../../../api/structures/IDiscussionBoardAdministratorRequest";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { getDiscussionBoardSuperAdminRequestsRequestId } from "../../../../providers/getDiscussionBoardSuperAdminRequestsRequestId";
import { patchDiscussionBoardSuperAdminRequestsRequestIdReject } from "../../../../providers/patchDiscussionBoardSuperAdminRequestsRequestIdReject";
import { postDiscussionBoardSuperAdminRequestsRequestIdApprove } from "../../../../providers/postDiscussionBoardSuperAdminRequestsRequestIdApprove";
import { putDiscussionBoardSuperAdminRequestsRequestId } from "../../../../providers/putDiscussionBoardSuperAdminRequestsRequestId";

@Controller("/discussionBoard/superAdmin/requests/:requestId")
export class DiscussionboardSuperadminRequestsController {
  /**
   * Retrieve detailed information about a specific administrator request.
   *
   * This endpoint allows super administrators to view complete details about a single administrator request, including the submitter's information, request reason, current status, timestamps, and processing information if applicable.
   *
   * The endpoint provides comprehensive information about the administrator request for review and decision-making purposes.
   *
   * @param connection
   * @param requestId Target administrator request's UUID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query discussion_board_administrator_requests table by primary key (UUID). Join with submitter discussion_board_members table to include submitter information. Join with processor discussion_board_super_admins table if processed. Verify caller is super administrator before returning the request.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAdministratorRequest> {
    try {
      return await getDiscussionBoardSuperAdminRequestsRequestId({
        superAdmin,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an administrator request by its unique identifier.
   *
   * This API endpoint allows complete replacement of an existing administrator request record. The operation supports updating the request status from pending to either approved or rejected, and provides functionality for super administrators to record rejection reasons when denying requests.
   *
   * The update operation follows strict business rules: only super administrators can approve or reject administrator requests, requests with non-pending status cannot be modified, and rejection reasons are mandatory when the status is changed to rejected. The system automatically records which super administrator processed the request and the timestamp of processing.
   *
   * @param connection
   * @param requestId The unique identifier of the administrator request to update
   * @param body Updated administrator request information
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Update an administrator request by ID. This endpoint allows complete replacement of an existing administrator request record. Valid only for pending requests. The update can change the request status from 'pending' to either 'approved' or 'rejected', and when rejecting, the rejection reason field must be populated. The processor's super admin ID is automatically set from the authenticated session. Implements validation: status must be 'pending' for update, rejection reason required when status is 'rejected', and only super administrators can process requests.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardAdministratorRequest.IUpdate,
  ): Promise<IDiscussionBoardAdministratorRequest> {
    try {
      return await putDiscussionBoardSuperAdminRequestsRequestId({
        superAdmin,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Approve a pending administrator request to grant administrator privileges.
   *
   * This endpoint allows super administrators to approve pending administrator requests submitted by members. When approved, the requesting user is granted administrator privileges and the request status is updated to 'approved'.
   *
   * The operation records the approval timestamp in the `processed_at` field and links the approving super administrator to the request record via the `processed_by_super_admin_id` field.
   *
   * This is a hard operation with no soft deletion support as the database schema does not include deletion tracking fields.
   *
   * @param connection
   * @param requestId The unique identifier of the administrator request to approve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Process administrator request approval for super admin privileges. Retrieve the administrator request by ID, validate it is in 'pending' status, update status to 'approved', record the processing timestamp, grant administrator privileges to the user, and return the updated request record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("approve")
  public async approve(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAdministratorRequest> {
    try {
      return await postDiscussionBoardSuperAdminRequestsRequestIdApprove({
        superAdmin,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Reject an administrator request by a super administrator.
   *
   * This operation allows super administrators to formally reject pending administrator requests submitted by members who want to be promoted to administrator roles. When a request is rejected, the super administrator must provide a detailed rejection reason that explains why the request was denied.
   *
   * The operation enforces business rules to maintain system integrity: it prevents super administrators from rejecting their own requests (conflict of interest), ensures only pending requests can be processed, and records the exact timestamp when the rejection occurred. The rejection reason is stored and remains visible to the requesting user for transparency.
   *
   * @param connection
   * @param requestId Unique identifier of the administrator request to reject. Must be the UUID of an existing pending request.
   * @param body Rejection reason and request metadata
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Reject a pending administrator request by setting its status to 'rejected' and recording the super administrator who processed it. Update the processed_at timestamp and rejection_reason fields. Validate that the request exists, is currently pending, and that the processing super administrator is not the same as the submitter (conflict of interest prevention).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("reject")
  public async reject(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardAdministratorRequest.IUpdate,
  ): Promise<IDiscussionBoardAdministratorRequest> {
    try {
      return await patchDiscussionBoardSuperAdminRequestsRequestIdReject({
        superAdmin,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
