import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardArticleComment } from "../../../../../api/structures/IDiscussionBoardArticleComment";
import { SuperadminAuth } from "../../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../../decorators/payload/SuperadminPayload";
import { postDiscussionBoardSuperAdminDeletedComments } from "../../../../../providers/postDiscussionBoardSuperAdminDeletedComments";

@Controller("/discussionBoard/superAdmin/deleted/comments")
export class DiscussionboardSuperadminDeletedCommentsController {
  /**
   * Bulk deletion of comments from the discussion board.
   *
   * This operation permanently removes multiple comments from the system in a single batch request. It supports deletion of comments by their authors or by administrators with appropriate permissions. Each deletion is properly recorded for audit purposes.
   *
   * The operation applies to the discussion_board_comments table and uses the system's soft-delete mechanism by setting the deleted_at timestamp. Comments marked as deleted remain in the database but are excluded from normal queries and API responses.
   *
   * @param connection
   * @param body IDs of comments to delete in batch
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Process bulk deletion of comments by their IDs.
   *
   * 1. Extract comment IDs from request body
   * 2. Validate that each comment ID exists in discussion_board_comments table
   * 3. Verify user authorization:
   *    - Comment authors can delete their own comments
   *    - Administrators can delete any comment
   *    - Regular users cannot delete others' comments
   * 4. For each authorized comment:
   *    - Set deleted_at timestamp to current time
   *    - Update updated_at timestamp
   *    - Log deletion action for audit
   * 5. Return count of successfully deleted comments
   * 6. Handle partial failures gracefully
   * 7. Return appropriate error status for unauthorized deletions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async bulkErase(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IDiscussionBoardArticleComment.IRequest,
  ): Promise<IDiscussionBoardArticleComment.IDeleteResponse> {
    try {
      return await postDiscussionBoardSuperAdminDeletedComments({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
