import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardBanRecord } from "../../../../../api/structures/IDiscussionBoardBanRecord";
import { SuperadminAuth } from "../../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../../decorators/payload/SuperadminPayload";
import { deleteDiscussionBoardSuperAdminActorsActorIdBan } from "../../../../../providers/deleteDiscussionBoardSuperAdminActorsActorIdBan";
import { getDiscussionBoardSuperAdminActorsBanStatus } from "../../../../../providers/getDiscussionBoardSuperAdminActorsBanStatus";
import { postDiscussionBoardSuperAdminActorsBan } from "../../../../../providers/postDiscussionBoardSuperAdminActorsBan";

@Controller("/discussionBoard/superAdmin/actors")
export class DiscussionboardSuperadminActorsBanController {
  /**
   * Ban a user account with a specified reason.
   *
   * This operation permanently bans a user account, preventing them from logging in and accessing the system. The ban includes a mandatory reason field that must be provided by the administrator.
   *
   * ## Authorization
   *
   * This operation requires administrator privileges (admin or superAdmin role). Regular users cannot perform user banning.
   *
   * ## Request Requirements
   *
   * - Target user ID must be provided in the request body
   * - Ban reason is mandatory and cannot be empty
   * - Administrators cannot ban users with higher or equal privilege level
   * - Self-banning attempts are rejected
   *
   * ## Behavior
   *
   * When a user is banned:
   * - Their active sessions are invalidated
   * - They are prevented from logging in
   * - Their existing content remains visible
   * - A BanRecord is created with the provided reason and timestamp
   *
   * @param connection
   * @param body Ban request payload containing target user and reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Create a ban record for the target user. Validate that the requesting user has admin privileges, verify ban reason is provided, check for self-ban attempt, and create the BanRecord entry in the database with current timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("ban")
  public async create(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IDiscussionBoardBanRecord.IRequest,
  ): Promise<IDiscussionBoardBanRecord> {
    try {
      return await postDiscussionBoardSuperAdminActorsBan({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Unban a user by lifting their active ban record.
   *
   * This operation removes a user ban by updating the ban record's deletion timestamp, effectively unbanning the user. The ban record is preserved for audit purposes but marked as no longer active.
   *
   * ## Behavior
   *
   * When a user is unbanned:
   * - The ban record's `deleted_at` timestamp is set to the current timestamp
   * - The user's `is_banned` status is updated to false
   * - The user regains full platform access including login and content creation
   * - All previous content remains intact and accessible
   * - The ban record is preserved for audit trail purposes
   *
   * ## Security Considerations
   *
   * - Only super administrators can unban users
   * - The operation requires valid authentication token
   * - Unban actions are logged with timestamp and administrator reference
   * - Banned users cannot unban themselves
   *
   * ## Related Operations
   *
   * - `POST /discussionBoard/members/{memberId}/ban` — Create a new ban record for a user
   * - `GET /discussionBoard/members/{memberId}/ban` — Retrieve current ban status
   * - `PATCH /discussionBoard/bans` — Search/list all active ban records
   *
   * @param connection
   * @param actorId Target actor's unique identifier
   * @param body Optional unban reason and additional context
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Update discussion_board_ban_records table by setting deleted_at to current timestamp for active ban record of specified actor ID. Verify ban record exists and is not already soft-deleted. Also update discussion_board_members.is_banned to false when unbanning. Use database transaction to ensure both operations succeed or fail together.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":actorId/ban")
  public async erase(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("actorId")
    actorId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardBanRecord.IUpdate,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardSuperAdminActorsActorIdBan({
        superAdmin,
        actorId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the current user's ban status from the system.
   *
   * This endpoint checks if the currently authenticated user has an active ban record and returns their ban status information. The response includes whether the user is currently banned, the ban reason if banned, and relevant timestamps.
   *
   * This operation is available to all authenticated users to check their own ban status, helping users understand their current ability to interact with the platform.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query the discussion_board_ban_records table for active ban records for the currently authenticated user. Return the first active ban record (where unbanned_at is null) if one exists, or indicate the user is not currently banned.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("ban/status")
  public async status(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
  ): Promise<IDiscussionBoardBanRecord.IStatus> {
    try {
      return await getDiscussionBoardSuperAdminActorsBanStatus({
        superAdmin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
