import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSection } from "../../../../api/structures/IDiscussionBoardSection";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { deleteDiscussionBoardSuperAdminSectionsSectionId } from "../../../../providers/deleteDiscussionBoardSuperAdminSectionsSectionId";
import { postDiscussionBoardSuperAdminSections } from "../../../../providers/postDiscussionBoardSuperAdminSections";
import { putDiscussionBoardSuperAdminSectionsSectionId } from "../../../../providers/putDiscussionBoardSuperAdminSectionsSectionId";

@Controller("/discussionBoard/superAdmin/sections")
export class DiscussionboardSuperadminSectionsController {
  /**
   * Create a new section for organizing discussion board articles.
   *
   * This endpoint allows authorized administrators to create new content categories that users can browse and filter articles by. Each section provides a unique namespace for organizing discussions around specific economic or political topics.
   *
   * The system enforces name uniqueness across all sections to prevent confusion and maintains referential integrity with associated articles.
   *
   * @param connection
   * @param body Section creation data with name and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Create a new section in the discussion_board_sections table.
   * Validate name uniqueness using database constraint or explicit query.
   * Generate UUID for id field if not provided.
   * Set created_at to current timestamp.
   * Return created section with all fields including auto-generated values.
   * Handle database constraint violations with appropriate error response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IDiscussionBoardSection.ICreate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await postDiscussionBoardSuperAdminSections({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing section's information.
   *
   * This endpoint allows authorized administrators to modify section details including name and description. Section names must remain unique across the system to prevent confusion in section browsing.
   *
   * Security Considerations:
   * - Only administrators and super administrators can perform this operation
   * - Section name changes require uniqueness validation
   * - Description updates have no length restrictions beyond practical limits
   *
   * Database Schema Relationship:
   * This operation directly manipulates the discussion_board_sections table, updating the name and description fields while preserving the section's creation timestamp and other system-managed data.
   *
   * @param connection
   * @param sectionId Unique identifier of the section to update
   * @param body Section update information including name and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Update discussion_board_sections table by sectionId.
   * Validate name uniqueness before update.
   * Update name and description fields.
   * Return updated section record.
   * Handle unique constraint violations with appropriate error response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sectionId")
  public async update(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("sectionId")
    sectionId: string,
    @TypedBody()
    body: IDiscussionBoardSection.IUpdate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await putDiscussionBoardSuperAdminSectionsSectionId({
        superAdmin,
        sectionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific section from the discussion board system.
   *
   * This operation permanently removes a section identified by its UUID. The operation handles sections that may contain articles according to the system's configuration.
   *
   * When a section contains articles, the system will either move them to a default fallback section (specified by system configuration) or return an error indicating that articles must be handled first, depending on the system's configuration.
   *
   * Only users with administrative privileges can perform this operation. Regular users attempting to delete sections will receive a permission denied error.
   *
   * @param connection
   * @param sectionId The unique identifier of the section to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Delete a section from the discussion_board_sections table by its UUID.
   *
   * 1. Verify the user has administrative privileges
   * 2. Retrieve the section by the provided UUID
   * 3. Check if the section contains any articles by querying the discussion_board_articles table
   * 4. If articles exist:
   *    - Check system configuration for handling articles during section deletion
   *    - If configured to move articles: update articles' section_id to the default fallback section UUID
   *    - If configured to prevent deletion: return SECTION_NOT_EMPTY error
   * 5. Delete the section from the database
   * 6. Return success confirmation
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sectionId")
  public async erase(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("sectionId")
    sectionId: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardSuperAdminSectionsSectionId({
        superAdmin,
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
