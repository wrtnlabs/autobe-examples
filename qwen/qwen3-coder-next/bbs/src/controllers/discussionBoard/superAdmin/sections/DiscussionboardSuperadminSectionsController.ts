import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardSection } from "../../../../api/structures/IDiscussionBoardSection";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { deleteDiscussionBoardSuperAdminSectionsSectionId } from "../../../../providers/deleteDiscussionBoardSuperAdminSectionsSectionId";
import { patchDiscussionBoardSuperAdminSectionsSectionId } from "../../../../providers/patchDiscussionBoardSuperAdminSectionsSectionId";
import { postDiscussionBoardSuperAdminSections } from "../../../../providers/postDiscussionBoardSuperAdminSections";

@Controller("/discussionBoard/superAdmin/sections")
export class DiscussionboardSuperadminSectionsController {
  /**
   * Update an existing section's name and description.
   *
   * This endpoint allows administrators to modify the name and description of an existing section. Only users with admin or superAdmin privileges can perform this operation.
   *
   * The section name must be unique across all sections on the platform. The operation updates the section's metadata while preserving all associated articles and content.
   *
   * After successful update, the updated section information is returned with the new name and description values.
   *
   * @param connection
   * @param sectionId The unique identifier of the section to update
   * @param body Section update data including name and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Update discussion_board_sections record with id matching sectionId parameter. Verify the updating user has admin or superAdmin role. Ensure the new name is unique across all sections (excluding current section). Update updated_at timestamp automatically. Return updated section record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":sectionId")
  public async update(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardSection.IUpdate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await patchDiscussionBoardSuperAdminSectionsSectionId({
        superAdmin,
        sectionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a discussion section from the platform.
   *
   * This operation permanently removes a discussion section identified by its section ID. Only administrators have permission to delete sections, as section management is a privileged administrative operation.
   *
   * Before deletion, the system validates that the section contains no articles. If articles exist in the section, the operation is rejected to prevent orphaned article records. This ensures data integrity and prevents accidental loss of article content.
   *
   * The operation implements soft deletion by setting the deleted_at timestamp rather than physically removing the section record from the database. This allows for potential recovery scenarios and maintains referential integrity with related records.
   *
   * Error handling includes validation for non-existent section IDs, unauthorized access attempts, and attempts to delete sections that contain articles.
   *
   * @param connection
   * @param sectionId The unique identifier of the section to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Delete a discussion section by ID. Before deletion, verify the section exists and has zero associated articles. If the section contains articles, reject the request with an appropriate error message indicating the article count. When deletion is successful, mark the section as deleted by setting the deleted_at timestamp (soft delete). Handle authorization to ensure only admin actors can perform this operation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sectionId")
  public async erase(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardSuperAdminSectionsSectionId({
        superAdmin,
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new discussion section to categorize and organize articles within the discussion board.
   *
   * This operation allows administrators to establish new topic categories for articles. Each section must have a unique name and descriptive text that explains its purpose and content focus.
   *
   * The section name serves as the primary identifier for the category and must be unique across all sections in the system. The description field provides additional context about the section's scope and the types of articles that belong there.
   *
   * When successful, the operation returns the complete section information including the system-generated ID and creation/update timestamps. The new section becomes immediately available for article categorization.
   *
   * @param connection
   * @param body Section creation request with name and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Create new discussion section with name and description. Validate name uniqueness across all sections. Enforce 1-100 character limit on name. Generate section ID (UUID). Set created_at and updated_at to current timestamp. Soft-delete capability available via deleted_at field. Return 409 Conflict if name already exists.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IDiscussionBoardSection.ICreate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await postDiscussionBoardSuperAdminSections({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
