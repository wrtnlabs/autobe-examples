import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardMemberSession } from "../../../../api/structures/IDiscussionBoardMemberSession";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { getDiscussionBoardSuperAdminSessionsSessionId } from "../../../../providers/getDiscussionBoardSuperAdminSessionsSessionId";
import { patchDiscussionBoardSuperAdminSessions } from "../../../../providers/patchDiscussionBoardSuperAdminSessions";

@Controller("/discussionBoard/superAdmin/sessions")
export class DiscussionboardSuperadminSessionsController {
  /**
   * Invalidate current user's active session by marking it as invalid.
   *
   * This operation terminates the current user session by updating the session validity status. When executed, the system will mark the current session (identified by the authentication token) as invalid, preventing further use of this session token for authentication purposes.
   *
   * This is commonly used for logout functionality or when a user wants to terminate their current session for security reasons. The system maintains audit records of this action for security monitoring purposes.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Update discussion_board_member_sessions table is_valid field to false for current user's active session.
   * Identify session by current authenticated user's member ID from authentication token.
   * Set is_valid to false and update expired_at timestamp to current time.
   * Return updated session status with new validity state and expiration timestamp.
   * Log this action for security audit purposes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async invalidate(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
  ): Promise<IDiscussionBoardMemberSession> {
    try {
      return await patchDiscussionBoardSuperAdminSessions({
        superAdmin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific user session.
   *
   * This operation fetches comprehensive session data including authentication timestamps, validity status, device information, and connection context. It's designed for session management, debugging, and administrative oversight of user authentication activity.
   *
   * The session data includes temporal information for tracking user engagement patterns, security audit trails, and technical metadata for troubleshooting authentication issues.
   *
   * @param connection
   * @param sessionId Unique session identifier for the user session
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query discussion_board_member_sessions table by primary key ID.
   * Retrieve single session record with all fields including timestamps, validity flag, connection metadata, and member reference.
   * Return null if session not found or has expired.
   * Format timestamps in ISO 8601 format for consistency.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("sessionId")
    sessionId: string,
  ): Promise<IDiscussionBoardMemberSession> {
    try {
      return await getDiscussionBoardSuperAdminSessionsSessionId({
        superAdmin,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
