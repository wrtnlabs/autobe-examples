import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardAdmin } from "../../../../api/structures/IDiscussionBoardAdmin";
import { IPageIDiscussionBoardAdmin } from "../../../../api/structures/IPageIDiscussionBoardAdmin";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { getDiscussionBoardSuperAdminAdminsAdminId } from "../../../../providers/getDiscussionBoardSuperAdminAdminsAdminId";
import { patchDiscussionBoardSuperAdminAdmins } from "../../../../providers/patchDiscussionBoardSuperAdminAdmins";

@Controller("/discussionBoard/superAdmin/admins")
export class DiscussionboardSuperadminAdminsController {
  /**
   * Retrieve a filtered and paginated list of administrator accounts.
   *
   * This operation provides advanced search and filtering capabilities for administrator accounts, allowing filtering by admin type (regular or super admin), status (active/inactive), and search terms.
   *
   * Supports comprehensive pagination with configurable page sizes and sorting options. Response includes administrator summary information optimized for list displays.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query discussion_board_admins and discussion_board_super_admins tables with pagination and filtering.
   * Apply search filters on display_name, email, and is_active status.
   * Filter by is_super_admin to distinguish between regular and super administrators.
   * Return cursor-based pagination for large result sets.
   * Combine results from both admin tables to provide unified admin view.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IDiscussionBoardAdmin.IRequest,
  ): Promise<IPageIDiscussionBoardAdmin.ISummary> {
    try {
      return await patchDiscussionBoardSuperAdminAdmins({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific administrator account by their unique identifier.
   *
   * This operation fetches complete administrator profile information including display name, email address, admin status (regular vs super administrator), account activation status, and creation/update timestamps.
   *
   * The operation requires the requesting user to have administrator privileges (regular admin or super admin) to access administrator account details.
   *
   * @param connection
   * @param adminId Target administrator's unique identifier (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query discussion_board_admins table by UUID id field.
   * Return display_name, email, is_super_admin, is_active, created_at, updated_at, and deleted_at fields.
   * Implement admin-level authorization check before executing query.
   * Return 404 if admin not found or if soft-deleted.
   * Use database-specific UUID comparison for id field.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("adminId")
    adminId: string,
  ): Promise<IDiscussionBoardAdmin> {
    try {
      return await getDiscussionBoardSuperAdminAdminsAdminId({
        superAdmin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
