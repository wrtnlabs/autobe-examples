import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardMember } from "../../../../api/structures/IDiscussionBoardMember";
import { IPageIDiscussionBoardMember } from "../../../../api/structures/IPageIDiscussionBoardMember";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { patchDiscussionBoardSuperAdminBans } from "../../../../providers/patchDiscussionBoardSuperAdminBans";

@Controller("/discussionBoard/superAdmin/bans")
export class DiscussionboardSuperadminBansController {
  /**
   * Retrieve a paginated list of banned users for administrative monitoring.
   *
   * This operation provides visibility into all currently banned users in the system. Administrators can view comprehensive ban information including the user's display name, email, creation timestamp, and account status.
   *
   * The response includes pagination metadata and allows for efficient browsing of the banned users list. Each banned user entry shows their current account status and creation details for audit purposes.
   *
   * Banned users are identified by having `is_active = false` in the members table.
   *
   * @param connection
   * @param body Pagination parameters and search criteria
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query banned users from discussion_board_members table where is_active is false.
   * Return display_name, email, created_at, banned_at, ban_reason, and ban_issuer_id fields.
   * Apply pagination with configurable page size and offset.
   * Support sorting by ban timestamp (newest/oldest) and search by user name.
   * Return paginated result with metadata including total count, current page, and total pages.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IDiscussionBoardMember.IRequest,
  ): Promise<IPageIDiscussionBoardMember.ISummary> {
    try {
      return await patchDiscussionBoardSuperAdminBans({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
