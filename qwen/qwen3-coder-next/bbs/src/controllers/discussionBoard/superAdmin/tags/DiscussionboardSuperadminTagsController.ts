import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardTag } from "../../../../api/structures/IDiscussionBoardTag";
import { IPageIDiscussionBoardTag } from "../../../../api/structures/IPageIDiscussionBoardTag";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { deleteDiscussionBoardSuperAdminTagsTagId } from "../../../../providers/deleteDiscussionBoardSuperAdminTagsTagId";
import { getDiscussionBoardSuperAdminTags } from "../../../../providers/getDiscussionBoardSuperAdminTags";
import { postDiscussionBoardSuperAdminTags } from "../../../../providers/postDiscussionBoardSuperAdminTags";

@Controller("/discussionBoard/superAdmin/tags")
export class DiscussionboardSuperadminTagsController {
  /**
   * Retrieve a paginated list of all discussion board tags.
   *
   * This endpoint provides access to all available tags used for content categorization across the discussion board. Tags enable users to organize and filter articles by topics of interest. Each tag represents a unique category or keyword that can be associated with multiple articles.
   *
   * The response provides a paginated list of tags with their names and creation timestamps, suitable for displaying tag clouds, selection dropdowns, or filtering interfaces.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query the discussion_board_tags table to retrieve all tags. Implement pagination with configurable page and limit parameters. Return tags sorted by creation timestamp in descending order (newest first) by default. Support optional sorting by oldest first. Apply the same filtering logic as other paginated list operations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
  ): Promise<IPageIDiscussionBoardTag.ISummary> {
    try {
      return await getDiscussionBoardSuperAdminTags({
        superAdmin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new tag for content categorization.
   *
   * This operation allows authorized administrators to create new tags that can be associated with articles. Tags enable content organization and filtering by topic areas.
   *
   * Administrators must provide a unique tag name that will be used to categorize and filter articles across the discussion board. The system enforces uniqueness constraints to prevent duplicate tags.
   *
   * This operation is restricted to super administrators to maintain proper access control and ensure only authorized personnel can modify the tag system.
   *
   * @param connection
   * @param body Tag creation information including name
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Create a new tag record in the discussion_board_tags table.
   * Validate that the tag name is unique and not empty.
   * Hash the tag name for normalization if required.
   * Return the created tag with its generated ID and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IDiscussionBoardTag.ICreate,
  ): Promise<IDiscussionBoardTag> {
    try {
      return await postDiscussionBoardSuperAdminTags({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a tag from the discussion board.
   *
   * This operation permanently removes a tag from the system. Tags are used to categorize and filter articles by topics of interest. When a tag is deleted, it will no longer be available for associating with articles.
   *
   * The operation requires the unique identifier of the tag to be deleted. Upon successful deletion, the tag will be permanently removed from the discussion_board_tags table and will no longer appear in tag lists or be available for article categorization.
   *
   * @param connection
   * @param tagId Unique identifier of the tag to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Delete a tag from the discussion_board_tags table by its UUID identifier.
   * Query the table by id field and delete the matching record.
   * Verify the tag exists before deletion and return appropriate error if not found.
   * This is a hard delete operation - the tag will be permanently removed from the database.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":tagId")
  public async erase(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("tagId")
    tagId: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardSuperAdminTagsTagId({
        superAdmin,
        tagId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
