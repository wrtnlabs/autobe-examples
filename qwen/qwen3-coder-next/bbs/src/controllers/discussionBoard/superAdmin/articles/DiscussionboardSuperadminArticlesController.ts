import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { deleteDiscussionBoardSuperAdminArticlesArticleId } from "../../../../providers/deleteDiscussionBoardSuperAdminArticlesArticleId";
import { getDiscussionBoardSuperAdminArticlesArticleId } from "../../../../providers/getDiscussionBoardSuperAdminArticlesArticleId";
import { patchDiscussionBoardSuperAdminArticlesArticleIdPin } from "../../../../providers/patchDiscussionBoardSuperAdminArticlesArticleIdPin";
import { putDiscussionBoardSuperAdminArticlesArticleId } from "../../../../providers/putDiscussionBoardSuperAdminArticlesArticleId";

@Controller("/discussionBoard/superAdmin/articles/:articleId")
export class DiscussionboardSuperadminArticlesController {
  /**
   * Retrieve detailed information about a specific article.
   *
   * This operation fetches the complete article content including title, body, author information, timestamps, and associated metadata. It provides comprehensive article details for display to users viewing individual articles.
   *
   * Security considerations:
   * - Users can only access articles from sections they have permission to view
   * - Administrator and super administrator roles have access to view all articles regardless of section permissions
   * - Guest users can view articles from public sections but cannot access restricted content
   *
   * The operation returns complete article information including all attached files and images, making it suitable for full article page display.
   *
   * @param connection
   * @param articleId The unique identifier of the article to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query the discussion_board_articles table by articleId to retrieve complete article details.
   * Join with discussion_board_members table to fetch author information.
   * Join with discussion_board_article_files table to retrieve attached files.
   * Join with discussion_board_article_images table to retrieve attached images.
   * Join with discussion_board_article_tags table to retrieve associated tags.
   * Return the complete article entity with all nested relationships.
   * Handle cases where article does not exist by returning appropriate error response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("articleId")
    articleId: string,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await getDiscussionBoardSuperAdminArticlesArticleId({
        superAdmin,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing article on the discussion board.
   *
   * This operation allows article authors or administrators to modify existing articles. Regular members can only update articles they authored, while administrators can update any article on the platform.
   *
   * When an article is updated, the system preserves the original creation timestamp while updating the last modification timestamp. All article metadata, including authorship and section association, remains unchanged during the update process.
   *
   * The operation supports partial updates - you can modify any combination of the updatable fields without needing to provide all fields. Missing fields remain unchanged in the database.
   *
   * @param connection
   * @param articleId Target article's unique identifier
   * @param body Article update information
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Update an existing article in the discussion_board_articles table.
   * Query the article by ID and verify the user has permission (either is the author or has administrator role).
   * Apply updates to title, content, view_count, updated_at fields.
   * Return the complete updated article record.
   * Validate that the article exists and belongs to the user or the user is an administrator.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("articleId")
    articleId: string,
    @TypedBody()
    body: IDiscussionBoardArticle.IUpdate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await putDiscussionBoardSuperAdminArticlesArticleId({
        superAdmin,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an article from the discussion board.
   *
   * This operation permanently removes an article and all its associated content from the discussion board. When executed, it will also delete all file attachments, image attachments, and remove all article-tag relationships.
   *
   * Security considerations:
   * - Only the article author or administrators can delete articles
   * - Deletion is permanent and cannot be undone
   *
   * This operation is related to:
   * - GET /sections/{sectionId}/articles/{articleId} - to view article details before deletion
   * - POST /sections/{sectionId}/articles - to create new articles
   * - PUT /sections/{sectionId}/articles/{articleId} - to update existing articles
   *
   * @param connection
   * @param articleId The unique identifier of the article to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Delete an article from the discussion_board_articles table by its ID.
   * 1. Retrieve the article by ID
   * 2. Verify user authorization (article author or administrator)
   * 3. Delete all related discussion_board_article_files records
   * 4. Delete all related discussion_board_article_images records
   * 5. Delete all related discussion_board_article_tags records
   * 6. Delete the article record
   * 7. Return success response
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("articleId")
    articleId: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardSuperAdminArticlesArticleId({
        superAdmin,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Pin an article to promote its visibility.
   *
   * This operation allows authorized users (typically administrators or the original author) to pin an article, which will typically cause it to appear at the top of article lists or in featured sections for increased visibility.
   *
   * The pin status is a content management feature that helps highlight important or time-sensitive articles. When an article is pinned, it may be displayed with a special indicator and prioritized in listing queries.
   *
   * Security considerations: Only administrators or the original article author should be able to pin articles. The system should verify appropriate permissions before allowing pin operations.
   *
   * @param connection
   * @param articleId Target article's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Update the pinned status of a discussion board article.
   *
   * Retrieve the article by articleId from discussion_board_articles table.
   * Validate that the requesting user is either the article author or an administrator.
   * Update the article's pinned status to true.
   * Return success response with no body content.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("pin")
  public async pin(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("articleId")
    articleId: string,
  ): Promise<void> {
    try {
      return await patchDiscussionBoardSuperAdminArticlesArticleIdPin({
        superAdmin,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
