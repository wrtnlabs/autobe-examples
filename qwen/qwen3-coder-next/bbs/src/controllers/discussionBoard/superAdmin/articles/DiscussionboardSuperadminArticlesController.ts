import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { deleteDiscussionBoardSuperAdminArticlesArticleId } from "../../../../providers/deleteDiscussionBoardSuperAdminArticlesArticleId";
import { putDiscussionBoardSuperAdminArticlesArticleId } from "../../../../providers/putDiscussionBoardSuperAdminArticlesArticleId";

@Controller("/discussionBoard/superAdmin/articles/:articleId")
export class DiscussionboardSuperadminArticlesController {
  /**
   * Update an existing article with new content.
   *
   * This operation allows the article author or administrators to modify the article's title, content, section assignment, and tags. Only the original author of an article or users with administrator privileges can perform this update.
   *
   * When updating an article, the system validates that the new section_id exists and the author_id remains unchanged (articles cannot be reassigned to different authors). Tags are replaced entirely with the new set provided in the request.
   *
   * Security considerations:
   * - Authors can only update their own articles
   * - Administrators and super administrators can update any article
   * - Guest users cannot update any articles
   *
   * @param connection
   * @param articleId Target article's unique identifier
   * @param body Article update information including new title, content, section, and tags
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Update article in discussion_board_articles table with new title, content, and section_id.
   * Verify user authorization (author or admin).
   * Validate section_id references existing section.
   * Validate title (1-200 chars) and content (min 1 char).
   * Replace tags with provided array (delete existing, create new tag associations).
   * Update updated_at timestamp to current time.
   * Return complete article record with author and section details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticle.IUpdate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await putDiscussionBoardSuperAdminArticlesArticleId({
        superAdmin,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an article and all associated data from the system.
   *
   * This operation permanently removes an article from the discussion board system, including all associated attachments, images, and comments. The operation is available to authenticated users for their own articles and to administrators for any article.
   *
   * When a user deletes their own article, the system confirms the user is the article author before proceeding with deletion. When an administrator deletes an article, the system verifies administrative privileges and logs the administrative action for audit purposes.
   *
   * The deletion cascades to all related data: all file attachments, all image attachments, all comments, and all tag associations are removed. The operation preserves system integrity and relationships by removing all dependent records.
   *
   * After successful deletion, the article is no longer accessible through any API endpoints and cannot be recovered. This is a permanent operation with no soft-delete behavior.
   *
   * @param connection
   * @param articleId Target article's unique identifier (UUID).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Delete article and cascade delete all associated data.
   * Query discussion_board_articles by articleId with author_id for ownership verification.
   * When user is not owner and not admin, return 403 Forbidden.
   * Delete all related discussion_board_article_files records.
   * Delete all related discussion_board_article_images records.
   * Delete all related discussion_board_comments records.
   * Delete all related discussion_board_article_tags records.
   * Delete the article record from discussion_board_articles.
   * Return HTTP 200 with success confirmation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("articleId")
    articleId: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardSuperAdminArticlesArticleId({
        superAdmin,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
