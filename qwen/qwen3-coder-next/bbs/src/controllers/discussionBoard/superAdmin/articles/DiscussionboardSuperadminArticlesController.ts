import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { deleteDiscussionBoardSuperAdminArticlesArticleId } from "../../../../providers/deleteDiscussionBoardSuperAdminArticlesArticleId";
import { patchDiscussionBoardSuperAdminArticlesArticleId } from "../../../../providers/patchDiscussionBoardSuperAdminArticlesArticleId";

@Controller("/discussionBoard/superAdmin/articles/:articleId")
export class DiscussionboardSuperadminArticlesController {
  /**
   * Update an existing article's content and metadata.
   *
   * This operation allows article authors to modify their own article's title, content, and associated metadata including file attachments, image attachments, and tags. Users can update the article title (1-500 characters), edit the main content, add or remove file attachments, and modify tag associations.
   *
   * The system enforces strict validation rules including title length constraints, content non-empty requirements, and ownership verification. Only the original article author can modify the article content. The system maintains referential integrity with all related entities including file attachments, image attachments, and tag associations.
   *
   * When updating tags, the system automatically creates or deletes ArticleTag records to reflect the new tag associations. File attachments are managed through their parent article and are updated atomically with the article content.
   *
   * @param connection
   * @param articleId Target article's unique identifier
   * @param body Article update request with modified content and metadata
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Update existing article by ID. Verify user ownership before allowing modification. Enforce article title length between 1-500 characters and require non-empty content. Process file/image attachment updates atomically. Update article tags by creating/deleting ArticleTag records as needed. Increment article version number for optimistic concurrency control. Return updated article entity with all related data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticle.IUpdate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await patchDiscussionBoardSuperAdminArticlesArticleId({
        superAdmin,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete an article and all associated content from the discussion board.
   *
   * This operation removes an article, along with all its comments, file attachments, and tag associations, from the system. The deletion is immediate and irreversible with no recovery mechanism once completed.
   *
   * Authorization: the operation can be performed by the original article author or by users with administrator privileges. Non-authors attempting to delete an article will receive a 403 Forbidden response.
   *
   * @param connection
   * @param articleId The unique identifier of the article to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Delete an article by its ID. This operation permanently removes the article and all associated content including comments, file attachments, and tag relationships. Authorization: the article's author or an administrator with appropriate permissions. Validate that the article exists before deletion. On successful deletion, return 204 No Content. If the article does not exist, return 404 Not Found. If the user lacks authorization, return 403 Forbidden.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardSuperAdminArticlesArticleId({
        superAdmin,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
