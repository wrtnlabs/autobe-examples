import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIDiscussionBoardArticle } from "../../../../api/structures/IPageIDiscussionBoardArticle";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { getDiscussionBoardSuperAdminRecommendations } from "../../../../providers/getDiscussionBoardSuperAdminRecommendations";

@Controller("/discussionBoard/superAdmin/recommendations")
export class DiscussionboardSuperadminRecommendationsController {
  /**
   * Retrieve personalized article recommendations for the current user.
   *
   * This endpoint provides content suggestions tailored to the user's interests, reading history, and profile preferences. The recommendation algorithm considers multiple factors including the user's previously viewed articles, topics of interest, popular content within their network, and content similarity metrics.
   *
   * The recommendations help users discover relevant articles they might find interesting based on their engagement patterns and the system's understanding of their preferences.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query article recommendations based on user profile and engagement history.
   * Join discussion_board_articles with discussion_board_members for user preference analysis.
   * Use search indices for content similarity matching.
   * Return articles sorted by relevance score and recency.
   * Apply pagination for large result sets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await getDiscussionBoardSuperAdminRecommendations({
        superAdmin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
