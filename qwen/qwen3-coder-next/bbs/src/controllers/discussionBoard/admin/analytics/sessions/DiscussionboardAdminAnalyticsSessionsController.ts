import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardGuestSession } from "../../../../../api/structures/IDiscussionBoardGuestSession";
import { IPageIDiscussionBoardGuestSession } from "../../../../../api/structures/IPageIDiscussionBoardGuestSession";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchDiscussionBoardAdminAnalyticsSessions } from "../../../../../providers/patchDiscussionBoardAdminAnalyticsSessions";

@Controller("/discussionBoard/admin/analytics/sessions")
export class DiscussionboardAdminAnalyticsSessionsController {
  /**
   * Retrieve session analytics and usage statistics for the discussion board platform.
   *
   * This endpoint provides comprehensive analytics data including active sessions, session duration statistics, peak usage times, and user engagement metrics. The analytics help administrators understand platform usage patterns and make informed decisions about resource allocation and feature improvements.
   *
   * Supports filtering by date range, user role (guest, member, admin, super admin), and activity patterns. Response includes aggregated statistics optimized for analytics dashboards and reporting tools.
   *
   * @param connection
   * @param body Analytics query criteria and filtering parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query session analytics from all actor session tables (admin, member, super admin, guest). Support filtering by date range, user role, session duration, and activity patterns. Return aggregated statistics with pagination for large result sets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardGuestSession.IRequest,
  ): Promise<IPageIDiscussionBoardGuestSession.ISummary> {
    try {
      return await patchDiscussionBoardAdminAnalyticsSessions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
