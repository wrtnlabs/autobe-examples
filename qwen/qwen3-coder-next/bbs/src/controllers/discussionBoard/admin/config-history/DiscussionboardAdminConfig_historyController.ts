import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSystemConfigHistory } from "../../../../api/structures/IDiscussionBoardSystemConfigHistory";
import { IPageIDiscussionBoardSystemConfigHistory } from "../../../../api/structures/IPageIDiscussionBoardSystemConfigHistory";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminConfigHistory } from "../../../../providers/getDiscussionBoardAdminConfigHistory";
import { getDiscussionBoardAdminConfigHistoryHistoryId } from "../../../../providers/getDiscussionBoardAdminConfigHistoryHistoryId";

@Controller("/discussionBoard/admin/config-history")
export class DiscussionboardAdminConfig_historyController {
  /**
   * Retrieve a specific system configuration history record by its unique identifier.
   *
   * This operation fetches detailed information about a specific system configuration snapshot from the historical record. The system configuration history maintains a complete audit trail of all configuration changes, enabling administrators to review past configurations, understand when changes were made, and identify who made specific configuration modifications.
   *
   * The operation provides comprehensive information about each configuration snapshot including the version number, complete configuration data in JSON format, the administrator who made the change, and the timestamp of when the change occurred. This enables thorough audit trail capabilities and rollback planning.
   *
   * @param connection
   * @param historyId System configuration history record's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_system_config_histories table by primary key (id).
   * Return complete configuration record including all fields: id, admin_id, version, config_data, change_reason, created_at.
   * Join with discussion_board_admins table to get administrator name when admin_id is present.
   * Return 404 error if no configuration history record exists with the given historyId.
   * Format the response as a single configuration history record object.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":historyId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("historyId")
    historyId: string,
  ): Promise<IDiscussionBoardSystemConfigHistory> {
    try {
      return await getDiscussionBoardAdminConfigHistoryHistoryId({
        admin,
        historyId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of system configuration history records.
   *
   * This operation provides access to the system configuration history table which tracks historical versions of system configuration with version numbers, configuration data, admin references, and change timestamps for full audit trail and rollback capability.
   *
   * The endpoint returns configuration snapshots that include:
   * - Configuration version numbers for ordering and identification
   * - Complete configuration data as JSON strings
   * - Change reasons explaining why each configuration change was made
   * - Administrator information for audit purposes
   * - Timestamps for tracking when configurations were recorded
   *
   * This functionality is essential for system administrators who need to:
   * - Review historical configuration changes
   * - Track who made specific configuration modifications
   * - Understand the evolution of system settings over time
   * - Support rollback scenarios by examining previous configuration states
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_system_config_histories table with optional version filter.
   * Apply pagination with configurable page size.
   * Include related admin information for audit trail.
   * Order results by version number descending to show most recent configurations first.
   * Return configuration data, change reasons, and timestamps for each history record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IPageIDiscussionBoardSystemConfigHistory> {
    try {
      return await getDiscussionBoardAdminConfigHistory({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
