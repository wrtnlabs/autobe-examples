import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardMember } from "../../../../api/structures/IDiscussionBoardMember";
import { IPageIDiscussionBoardMember } from "../../../../api/structures/IPageIDiscussionBoardMember";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteDiscussionBoardAdminBansBanId } from "../../../../providers/deleteDiscussionBoardAdminBansBanId";
import { getDiscussionBoardAdminBansBanId } from "../../../../providers/getDiscussionBoardAdminBansBanId";
import { patchDiscussionBoardAdminBans } from "../../../../providers/patchDiscussionBoardAdminBans";

@Controller("/discussionBoard/admin/bans")
export class DiscussionboardAdminBansController {
  /**
   * Retrieve detailed information about a specific ban record.
   *
   * This operation fetches comprehensive information about a ban record from the system, including the banned user details, ban reason, timestamps, and the administrator who issued the ban. It provides full visibility into the ban record for administrative review and auditing purposes.
   *
   * The endpoint supports access for administrators and super administrators only, ensuring that only authorized personnel can view detailed ban information. This maintains data integrity while providing necessary oversight capabilities.
   *
   * @param connection
   * @param banId Target ban's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the discussion_board_bans table by banId to retrieve detailed ban information. Join with discussion_board_members to get banned user details and discussion_board_admins to get the banning administrator information. Include ban reason, timestamps, and active status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":banId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("banId")
    banId: string,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await getDiscussionBoardAdminBansBanId({
        admin,
        banId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a user ban and restore their active status.
   *
   * This operation performs a soft delete on the ban record by setting the deleted_at timestamp, effectively removing the ban status from the user account and allowing them to immediately log in and use the system. When a ban is soft deleted, the user's account status is updated to active, and all previous content they created remains visible to other users.
   *
   * The operation requires administrator or super administrator privileges to execute. The ban ID parameter identifies which ban record to soft delete from the system.
   *
   * @param connection
   * @param banId Unique identifier of the ban record to remove
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Remove user ban from discussion_board_members table.
   * Find user by banId and update banned_at, banned_by_id, unban_at fields to null.
   * Set status to 'active'.
   * Return success response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":banId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("banId")
    banId: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminBansBanId({
        admin,
        banId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of banned user accounts.
   *
   * This operation provides administrative capabilities to view all users who have been banned from the system. Administrators can filter banned users by various criteria including ban reason, ban timestamp ranges, and user profile information.
   *
   * The system manages account bans by setting is_active = false on user records rather than permanent deletion. This approach preserves user data and content history while preventing banned users from accessing the system. When a user is banned, their existing articles and comments remain visible to maintain content integrity.
   *
   * This operation supports comprehensive pagination with configurable page sizes, allowing administrators to efficiently navigate through large numbers of banned users.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering banned users
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_members table filtered by is_active = false to identify banned users.
   * Apply search filters on display_name and ban reason if provided.
   * Include ban timestamp and administrator information in response.
   * Return paginated results with configurable page sizes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardMember.IRequest,
  ): Promise<IPageIDiscussionBoardMember.ISummary> {
    try {
      return await patchDiscussionBoardAdminBans({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
