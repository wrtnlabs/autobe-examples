import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardBanRecord } from "../../../../api/structures/IDiscussionBoardBanRecord";
import { IPageIDiscussionBoardBanRecord } from "../../../../api/structures/IPageIDiscussionBoardBanRecord";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminBansBanId } from "../../../../providers/getDiscussionBoardAdminBansBanId";
import { patchDiscussionBoardAdminBans } from "../../../../providers/patchDiscussionBoardAdminBans";
import { postDiscussionBoardAdminBans } from "../../../../providers/postDiscussionBoardAdminBans";
import { putDiscussionBoardAdminBansBanId } from "../../../../providers/putDiscussionBoardAdminBansBanId";

@Controller("/discussionBoard/admin/bans")
export class DiscussionboardAdminBansController {
  /**
   * Create a new user ban record.
   *
   * This operation allows administrators to ban users by creating a ban record with a required ban reason. When a user is banned, they lose the ability to log in to the system while all their existing articles, comments, and other content remain visible and preserved.
   *
   * The ban record captures important metadata including the timestamp when the ban was imposed, the administrator who created the ban, and the reason for the ban. The system automatically tracks when the ban record was created and last updated.
   *
   * Only administrators with appropriate permissions can create ban records. The operation requires a detailed ban reason to be provided, ensuring accountability for banning decisions.
   *
   * @param connection
   * @param body Ban record creation request containing user ID and ban reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new ban record in the discussion_board_ban_records table. Set banned_at to current timestamp, created_at and updated_at to current timestamp. Administrator ID is extracted from the authenticated session. Return the created ban record with all fields including auto-generated IDs and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardBanRecord.ICreate,
  ): Promise<IDiscussionBoardBanRecord> {
    try {
      return await postDiscussionBoardAdminBans({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of user ban records.
   *
   * This endpoint provides comprehensive search and filtering capabilities for ban records. Administrators can filter ban records by the banned user, the administrator who created the ban, date ranges, and whether the ban is currently active or inactive.
   *
   * The endpoint supports pagination with configurable page sizes and sorting options. Results are ordered by ban creation time by default, with the most recent bans appearing first.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for ban records
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_ban_records table with pagination and filtering. Support filtering by user ID, administrator ID, date ranges (banned_at), and ban status (active/inactive). Order results by banned_at descending by default.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardBanRecord.IRequest,
  ): Promise<IPageIDiscussionBoardBanRecord.ISummary> {
    try {
      return await patchDiscussionBoardAdminBans({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific user ban record.
   *
   * This endpoint provides comprehensive ban record details including the banned user information, the administrator who created the ban, the ban reason, timestamps, and current ban status.
   *
   * The response includes:
   * - Complete banned user information
   * - Administrator details who issued the ban
   * - Full ban timeline with banned_at and unbanned_at timestamps
   * - Current ban status (active or resolved)
   *
   * @param connection
   * @param banId Unique identifier of the ban record
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_ban_records table by ID, join with discussion_board_members (banned user) and discussion_board_admins (administrator) tables. Return ban record with full user and admin details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":banId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("banId")
    banId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardBanRecord> {
    try {
      return await getDiscussionBoardAdminBansBanId({
        admin,
        banId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a user ban record with new information or unban the user.
   *
   * This endpoint allows administrators to modify existing ban records or unban users by providing appropriate reasons. When unbanning, the system records the unban reason and timestamp while preserving the ban history.
   *
   * The operation requires administrator privileges to ensure only authorized personnel can modify user ban status.
   *
   * @param connection
   * @param banId The unique identifier of the ban record to update
   * @param body Update information for the ban record
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update ban record information. Accept ban reason updates and optional unban reason for lifting bans. Validate admin authorization and proper state transitions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":banId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("banId")
    banId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardBanRecord.IUpdate,
  ): Promise<IDiscussionBoardBanRecord> {
    try {
      return await putDiscussionBoardAdminBansBanId({
        admin,
        banId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
