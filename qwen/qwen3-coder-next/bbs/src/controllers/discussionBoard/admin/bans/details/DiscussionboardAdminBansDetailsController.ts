import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardBanRecord } from "../../../../../api/structures/IDiscussionBoardBanRecord";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminBansUserIdDetails } from "../../../../../providers/getDiscussionBoardAdminBansUserIdDetails";

@Controller("/discussionBoard/admin/bans/:userId/details")
export class DiscussionboardAdminBansDetailsController {
  /**
   * Retrieve comprehensive ban details for a specific user.
   *
   * This endpoint provides detailed information about a user's ban status including the ban reason, timestamps, and administrative actions taken. It returns all available data from the ban record including who issued the ban and when the ban was imposed.
   *
   * The operation is accessible to administrators who need to review ban history and details for specific users.
   *
   * @param connection
   * @param userId The unique identifier of the banned user
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the discussion_board_ban_records table using the provided userId path parameter. Join with discussion_board_members to get banned user details and discussion_board_admins to get administrator information. Return the complete ban record including all timestamps and reasons. Handle cases where user has no ban record by returning 404 Not Found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardBanRecord.ISummary> {
    try {
      return await getDiscussionBoardAdminBansUserIdDetails({
        admin,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
