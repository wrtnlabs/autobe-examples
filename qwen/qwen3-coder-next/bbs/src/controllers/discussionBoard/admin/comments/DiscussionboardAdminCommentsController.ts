import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardArticleComment } from "../../../../api/structures/IDiscussionBoardArticleComment";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { postDiscussionBoardAdminComments } from "../../../../providers/postDiscussionBoardAdminComments";

@Controller("/discussionBoard/admin/comments")
export class DiscussionboardAdminCommentsController {
  /**
   * Create a new comment on an article.
   *
   * This endpoint allows authenticated users to add comments to existing articles. The comment will be associated with the specified article and the currently authenticated user.
   *
   * Security considerations:
   * - Users must be authenticated to create comments
   * - Banned users cannot create comments
   * - Comment content must meet length requirements
   *
   * Database relationships:
   * - Comment is linked to the author (member) via foreign key
   * - Comment is linked to the article via foreign key
   * - Creating a comment increments the article's comment count
   *
   * Validation rules:
   * - Comment content must be between minimum and maximum length
   * - Article must exist before comment can be created
   * - User must not be banned from commenting
   *
   * Related operations:
   * - GET /articles/{articleId}/comments to view comments on an article
   * - PUT /comments/{commentId} to edit your own comment
   * - DELETE /comments/{commentId} to delete your own comment
   *
   * @param connection
   * @param body Comment creation input
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create new comment on specified article.
   *
   * 1. Extract comment content from request body
   * 2. Verify user is authenticated (extract from JWT token)
   * 3. Validate user is not banned
   * 4. Validate comment content length requirements
   * 5. Create comment record in database with:
   *    - Content from request body
   *    - Author ID from authenticated user
   *    - Article ID from request body
   *    - Timestamps (createdAt, updatedAt)
   * 6. Increment article's comment count
   * 7. Return created comment with full details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardArticleComment.ICreate,
  ): Promise<IDiscussionBoardArticleComment> {
    try {
      return await postDiscussionBoardAdminComments({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
