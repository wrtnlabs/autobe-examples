import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardComment } from "../../../../api/structures/IDiscussionBoardComment";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteDiscussionBoardAdminCommentsCommentId } from "../../../../providers/deleteDiscussionBoardAdminCommentsCommentId";
import { putDiscussionBoardAdminCommentsCommentId } from "../../../../providers/putDiscussionBoardAdminCommentsCommentId";

@Controller("/discussionBoard/admin/comments/:commentId")
export class DiscussionboardAdminCommentsController {
  /**
   * Update an existing comment on an article.
   *
   * This operation allows the comment owner or an administrator to modify the content of an existing comment. The comment's updated_at timestamp is automatically refreshed to reflect the modification time.
   *
   * **Authorization:**
   * - Comment owner (author of the comment)
   * - Administrators with appropriate permissions
   *
   * **Behavior:**
   * - Comment owner can update their own comment content
   * - Administrators can update any comment's content
   * - The updated_at timestamp is automatically set to current time
   * - No changes to created_at timestamp
   *
   * **Related Operations:**
   * - GET /articles/{articleId}/comments - Retrieve comments list to see updated content
   * - GET /comments/{commentId} - Retrieve specific comment details after update
   *
   * **Error Scenarios:**
   * - Comment not found → Return error "Comment not found"
   * - Unauthorized access → Return error "You are not authorized to update this comment"
   * - Invalid content → Return error "Invalid comment content"
   *
   * @param connection
   * @param commentId Target comment's unique identifier
   * @param body Comment update request with new content
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update comment content in discussion_board_comments table.
   * Load comment by id with author relation for authorization check.
   * Verify requester is comment author or admin.
   * Update content field and set updated_at to current timestamp.
   * Return updated comment with author information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("commentId")
    commentId: string,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardAdminCommentsCommentId({
        admin,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a comment from the discussion board.
   *
   * This endpoint allows comment authors or administrators to permanently remove a comment from the system. When successful, the comment is removed and the associated article's comment count is decremented.
   *
   * **Authorization:**
   * - Comment author can delete their own comment
   * - Administrators can delete any comment
   *
   * **Behavior:**
   * - Comment record permanently removed from database
   * - Article's comment count decremented
   * - No cascading deletion (nested comments not supported)
   * - Audit logging for administrator-initiated deletions
   *
   * **Error Scenarios:**
   * - Comment not found → Return error message "Comment not found"
   * - Not authorized → Return error message "You are not authorized to delete this comment"
   * - Database operation failure → Return error message "Comment deletion failed. Please try again."
   *
   * **Related Operations:**
   * - GET /articles/{id}/comments - List comments for article
   * - POST /articles/{id}/comments - Create comment on article
   * - PUT /comments/{id} - Update comment content
   *
   * @param connection
   * @param commentId The UUID identifier of the comment to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Delete comment from database by ID. Before deletion, verify user authorization (comment author or admin). Decrement the associated article's comment count. Log the deletion action for administrator-initiated deletions. Handle soft delete if required by business logic.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("commentId")
    commentId: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminCommentsCommentId({
        admin,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
