import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSystemLog } from "../../../../api/structures/IDiscussionBoardSystemLog";
import { IPageIDiscussionBoardSystemLog } from "../../../../api/structures/IPageIDiscussionBoardSystemLog";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminLogs } from "../../../../providers/getDiscussionBoardAdminLogs";
import { getDiscussionBoardAdminLogsLogId } from "../../../../providers/getDiscussionBoardAdminLogsLogId";

@Controller("/discussionBoard/admin/logs")
export class DiscussionboardAdminLogsController {
  /**
   * Retrieve a specific system audit log entry by its unique identifier.
   *
   * This operation fetches detailed information about system events including configuration changes, administrative actions, and other important system activities. Each audit log entry contains comprehensive information about what event occurred, who performed it, when it happened, and what was affected.
   *
   * The response includes all audit trail details such as the actor information, event type classification, severity level, target entity affected, and the before/after state values for tracking changes. This information is essential for security auditing, compliance verification, and debugging system issues.
   *
   * Security considerations:
   * - All users can access audit logs (read-only access)
   * - Admin and super admin users have full access to all audit information
   * - Audit logs contain sensitive security-related information
   *
   * Related operations:
   * - GET /logs with search parameters would provide filtered audit log lists
   * - Other system configuration or administrative operations may be logged in this table
   *
   * @param connection
   * @param logId Unique identifier of the system log entry
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the discussion_board_system_logs table by id (UUID) to retrieve a single audit log entry. The operation should join with actor tables (discussion_board_members, discussion_board_admins, discussion_board_super_admins, discussion_board_guests) based on actor_type to get actor details. Return complete log entry including all metadata fields, old/new state values, and actor session information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":logId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("logId")
    logId: string,
  ): Promise<IDiscussionBoardSystemLog> {
    try {
      return await getDiscussionBoardAdminLogsLogId({
        admin,
        logId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of system audit logs.
   *
   * This operation provides comprehensive audit trail capabilities by querying the system logs table. It supports advanced filtering including event type categorization, severity level filtering, date range constraints, and full-text search on log descriptions.
   *
   * The system logs table records all significant system events including configuration changes, administrative actions, and important system activities. Each log entry captures the event type, severity level, actor responsible, affected targets, and before/after values for comprehensive audit trail purposes.
   *
   * Supports comprehensive pagination with configurable page sizes and sorting options. Response includes system log summary information optimized for audit dashboard displays.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_system_logs table with pagination and filtering.
   * Apply search filters on description, event type, severity, and date range.
   * Join with actor tables (discussion_board_members, discussion_board_admins, discussion_board_super_admins, discussion_board_guests) for actor information.
   * Return paginated results with metadata for audit dashboard displays.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IPageIDiscussionBoardSystemLog> {
    try {
      return await getDiscussionBoardAdminLogs({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
