import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardBansAppeal } from "../../../../../../api/structures/IDiscussionBoardBansAppeal";
import { IPageIDiscussionBoardBansAppeal } from "../../../../../../api/structures/IPageIDiscussionBoardBansAppeal";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { patchDiscussionBoardAdminAdminsBansAppeals } from "../../../../../../providers/patchDiscussionBoardAdminAdminsBansAppeals";
import { patchDiscussionBoardAdminAdminsBansAppealsAppealId } from "../../../../../../providers/patchDiscussionBoardAdminAdminsBansAppealsAppealId";

@Controller("/discussionBoard/admin/admins/bans/appeals")
export class DiscussionboardAdminAdminsBansAppealsController {
  /**
   * Retrieve a filtered and paginated list of user ban appeals for administrative review.
   *
   * This operation provides administrators with comprehensive access to all user appeals against ban decisions, enabling them to review, process, and respond to appeals according to established administrative procedures.
   *
   * The system supports advanced filtering capabilities including search by ban reason keywords, user information, status filtering (pending/approved/rejected), date range filtering, and administrative review status. Response includes appeal summary information optimized for administrative dashboards and review workflows.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for appeal filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_bans_appeals table with pagination and comprehensive filtering.
   * Apply filters on ban record details, user information, appeal status, and review timestamps.
   * Join with discussion_board_bans_ban_records and discussion_board_members for complete appeal context.
   * Return cursor-based pagination for large result sets with support for complex multi-criteria filtering.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardBansAppeal.IRequest,
  ): Promise<IPageIDiscussionBoardBansAppeal.ISummary> {
    try {
      return await patchDiscussionBoardAdminAdminsBansAppeals({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Review and process a ban appeal with administrative decision.
   *
   * This operation allows authorized administrators to review appeals submitted by banned users who are requesting reconsideration of their ban decision. The administrator can approve the appeal to unban the user or reject it to maintain the ban.
   *
   * When processing an appeal, administrators must provide a decision status (approved or rejected) and may include review notes explaining their reasoning. The system automatically handles the consequences of approval (unbanning the user) or rejection (maintaining the ban).
   *
   * @param connection
   * @param appealId The unique identifier of the ban appeal to review
   * @param body Appeal review decision and administrator notes
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Process ban appeal review by updating status and review notes.
   * 1. Validate appeal ID exists and is active
   * 2. Update appeal status (approved/rejected) based on decision
   * 3. If approved: automatically unban the user and remove ban record
   * 4. If rejected: maintain current ban status
   * 5. Record administrator review notes
   * 6. Update timestamps and log the administrative action
   * 7. Return updated appeal record with all details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":appealId")
  public async process(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("appealId")
    appealId: string,
    @TypedBody()
    body: IDiscussionBoardBansAppeal.IRequest,
  ): Promise<IDiscussionBoardBansAppeal> {
    try {
      return await patchDiscussionBoardAdminAdminsBansAppealsAppealId({
        admin,
        appealId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
