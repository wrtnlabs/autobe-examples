import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardBansBanRecord } from "../../../../../api/structures/IDiscussionBoardBansBanRecord";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { deleteDiscussionBoardAdminAdminsBansBanRecordId } from "../../../../../providers/deleteDiscussionBoardAdminAdminsBansBanRecordId";
import { getDiscussionBoardAdminAdminsBans } from "../../../../../providers/getDiscussionBoardAdminAdminsBans";
import { putDiscussionBoardAdminAdminsBansBanRecordId } from "../../../../../providers/putDiscussionBoardAdminAdminsBansBanRecordId";

@Controller("/discussionBoard/admin/admins/bans")
export class DiscussionboardAdminAdminsBansController {
  /**
   * Retrieve a list of all banned users with their ban details.
   *
   * This operation provides administrators with comprehensive visibility into currently banned users, enabling effective user management and moderation. The system displays all banned users with their ban reason, duration, and administrative information.
   *
   * The operation supports comprehensive filtering and sorting capabilities to help administrators efficiently manage the banned users list. Response includes detailed ban information for each user including reason, start time, end time (for temporary bans), and the administrator who created the ban.
   *
   * This is the administrative counterparty to the user-facing ban restrictions, providing the management interface for overseeing banned users.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the discussion_board_bans_ban_records table to retrieve all active (non-soft-deleted) ban records.
   * Join with discussion_board_members to get user information for banned users.
   * Join with discussion_board_admins to get information about the administrator who created the ban.
   * Filter out soft-deleted records (deleted_at IS NULL).
   * Apply pagination, search, and sorting as per standard list operations.
   * Return comprehensive ban information including start_time, end_time, reason, and administrative details.
   * Ensure the response includes all necessary information for ban management and audit purposes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IDiscussionBoardBansBanRecord.ISummary> {
    try {
      return await getDiscussionBoardAdminAdminsBans({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing ban record with new information.
   *
   * This operation allows administrators to modify the details of an existing ban record. It can be used to extend temporary bans by updating the end_time, modify the ban reason, or update other ban record fields.
   *
   * When updating a ban record, the system preserves the original creation timestamp and only updates the fields provided in the request body. All audit information including the administrator who created the ban and the original start time remains unchanged.
   *
   * @param connection
   * @param banRecordId The unique identifier of the ban record to update
   * @param body Updated ban record information
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update a ban record in the discussion_board_bans_ban_records table by ID.
   * Validate that the user has administrator privileges before allowing updates.
   * Only update fields that are provided in the request body (end_time, reason).
   * Preserve all other fields including created_at, updated_at, and admin_id.
   * Return the updated ban record with all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":banRecordId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("banRecordId")
    banRecordId: string,
    @TypedBody()
    body: IDiscussionBoardBansBanRecord.IUpdate,
  ): Promise<IDiscussionBoardBansBanRecord> {
    try {
      return await putDiscussionBoardAdminAdminsBansBanRecordId({
        admin,
        banRecordId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific ban record from the discussion board ban system.
   *
   * This operation permanently removes a ban record from the system, effectively un-banning the user and restoring their full access to the platform. The ban record is completely removed from the database, and the user's account status is updated to active.
   *
   * This operation should be used when administrators need to reverse ban decisions, correct误ban cases, or remove outdated ban records. The deletion is permanent and cannot be undone.
   *
   * @param connection
   * @param banRecordId Unique identifier of the ban record to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Delete a ban record from the discussion_board_bans_ban_records table by its unique identifier. Remove the ban record permanently from the database, update the associated user's ban status to active, and log the administrative action for audit purposes. Return 204 No Content on successful deletion.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":banRecordId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("banRecordId")
    banRecordId: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminAdminsBansBanRecordId({
        admin,
        banRecordId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
