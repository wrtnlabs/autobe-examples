import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardAdministratorRequest } from "../../../../api/structures/IDiscussionBoardAdministratorRequest";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminRequestsRequestId } from "../../../../providers/getDiscussionBoardAdminRequestsRequestId";

@Controller("/discussionBoard/admin/requests/:requestId")
export class DiscussionboardAdminRequestsController {
  /**
   * Retrieve detailed information about a specific administrator request.
   *
   * This endpoint allows super administrators to view complete details about a single administrator request, including the submitter's information, request reason, current status, timestamps, and processing information if applicable.
   *
   * The endpoint provides comprehensive information about the administrator request for review and decision-making purposes.
   *
   * @param connection
   * @param requestId Target administrator request's UUID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_administrator_requests table by primary key (UUID). Join with submitter discussion_board_members table to include submitter information. Join with processor discussion_board_super_admins table if processed. Verify caller is super administrator before returning the request.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAdministratorRequest> {
    try {
      return await getDiscussionBoardAdminRequestsRequestId({
        admin,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
