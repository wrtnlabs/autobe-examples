import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardFlag } from "../../../../../api/structures/IDiscussionBoardFlag";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { postDiscussionBoardAdminModerationFlags } from "../../../../../providers/postDiscussionBoardAdminModerationFlags";

@Controller("/discussionBoard/admin/moderation/flags")
export class DiscussionboardAdminModerationFlagsController {
  /**
   * Create a content flag report for moderation review
   *
   * This endpoint allows authenticated users to report inappropriate or violating content (such as articles, comments, or other user-generated content) for administrative review. Content flagging is a key component of the community moderation system, enabling users to help maintain a respectful and constructive discussion environment.
   *
   * When a user submits a flag report, the system records detailed information about the reported content, the nature of the violation, and any additional context provided by the reporting user. This information is then made available to administrators for review and appropriate action.
   *
   * Flag reports are used by administrators to:
   * - Identify potentially violating content that may require removal
   * - Track patterns of inappropriate behavior by specific users
   * - Maintain a record of community moderation actions
   * - Provide transparency in the moderation process
   *
   * Note: This endpoint does not immediately remove content or take any action against the content creator. It only creates a flag report for administrative review. Actual moderation actions are taken through separate administrative endpoints.
   *
   * @param connection
   * @param body Content flag report details including target content, reason, and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new content flag report in the discussion_board_flags table.
   *
   * 1. Extract flag details from request body:
   *    - target_type: 'article' or 'comment'
   *    - target_id: UUID of the target content
   *    - reason: Flag reason text
   *    - description: Optional additional context
   *
   * 2. Verify that the target content exists and is accessible
   *
   * 3. Create flag record with:
   *    - Generated UUID
   *    - Reporting user's ID (from authentication)
   *    - Provided flag details
   *    - Current timestamp
   *    - Initial status of 'pending'
   *
   * 4. Return the created flag record
   *
   * 5. Handle errors for:
   *    - Invalid target content
   *    - Missing required fields
   *    - Unauthorized users
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardFlag.ICreate,
  ): Promise<IDiscussionBoardFlag> {
    try {
      return await postDiscussionBoardAdminModerationFlags({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
