import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardArticleFile } from "../../../../../../api/structures/IDiscussionBoardArticleFile";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminArticlesArticleIdFilesFileIdDownload } from "../../../../../../providers/getDiscussionBoardAdminArticlesArticleIdFilesFileIdDownload";

@Controller("/discussionBoard/admin/articles/:articleId/files/:fileId/download")
export class DiscussionboardAdminArticlesFilesDownloadController {
  /**
   * Download a specific file attached to an article.
   *
   * This endpoint retrieves the metadata and serves the file content for attachment files that have been attached to articles. Users must have permission to access the parent article to download its attachments.
   *
   * Security considerations include verifying user authorization for the parent article and preventing unauthorized file access. The system should serve files with appropriate content type headers based on the file's MIME type.
   *
   * This operation is related to:
   * - GET /articles/{articleId}/files - List all files attached to an article
   * - POST /articles/{articleId}/files - Upload files to an article
   * - DELETE /articles/{articleId}/files/{fileId} - Remove a file from an article
   *
   * The download flow validates user permissions, retrieves the file by unique identifier, and streams it to the user with appropriate content type headers.
   *
   * @param connection
   * @param articleId ID of the article containing the attachment file
   * @param fileId ID of the file to download
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Retrieve article file by articleId and fileId from discussion_board_article_files table.
   * Validate user authorization to access the parent article.
   * Generate temporary signed URL for file download if using cloud storage.
   * Return file metadata including download URL, MIME type, original filename, and file size.
   * Support resumable downloads for large files over 10 MB.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async downloadFile(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string,
    @TypedParam("fileId")
    fileId: string,
  ): Promise<IDiscussionBoardArticleFile.IDownload> {
    try {
      return await getDiscussionBoardAdminArticlesArticleIdFilesFileIdDownload({
        admin,
        articleId,
        fileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
