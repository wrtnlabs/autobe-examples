import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardArticleTag } from "../../../../../api/structures/IDiscussionBoardArticleTag";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { deleteDiscussionBoardAdminArticlesArticleIdTagsTagId } from "../../../../../providers/deleteDiscussionBoardAdminArticlesArticleIdTagsTagId";
import { postDiscussionBoardAdminArticlesArticleIdTags } from "../../../../../providers/postDiscussionBoardAdminArticlesArticleIdTags";

@Controller("/discussionBoard/admin/articles/:articleId/tags")
export class DiscussionboardAdminArticlesTagsController {
  /**
   * Associate one or more tags with an existing article in the discussion board.
   *
   * This operation allows authenticated users to add new tags to an article they have access to. The article must already exist in the system before tags can be associated with it. Each tag is validated for length and content restrictions.
   *
   * Tag management provides better content organization and enables users to find related articles through tag filtering. Tags are case-insensitive and normalized for consistency across the system.
   *
   * @param connection
   * @param articleId The unique identifier of the article to tag
   * @param body List of tag names to associate with the article
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Process article tag association by:
   *
   * 1. Validate article existence using provided articleId path parameter
   * 2. Parse and normalize incoming tag list (trim whitespace, lowercase)
   * 3. Validate each tag meets length requirements (2-50 characters)
   * 4. Create or retrieve tag records in discussion_board_tags table
   * 5. Create junction records in discussion_board_article_tags table linking article to tags
   * 6. Return list of associated tags with proper structure
   * 7. Handle validation errors with specific error messages for each invalid tag
   * 8. Ensure transactional consistency for tag association operations
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async createTags(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string,
    @TypedBody()
    body: IDiscussionBoardArticleTag.ICreate,
  ): Promise<IDiscussionBoardArticleTag> {
    try {
      return await postDiscussionBoardAdminArticlesArticleIdTags({
        admin,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a specific tag from an article.
   *
   * This operation allows the article author or administrators to remove tags from articles. The tag removal does not delete the tag itself from the system - it only removes the association between the tag and the article.
   *
   * For article authors, they can remove any tag from their own articles. For administrators, they can remove tags from any article on the platform.
   *
   * Security considerations:
   * - Authors can only remove tags from their own articles
   * - Administrators can remove tags from any article
   * - Super administrators can remove tags from any article
   * - Guest users cannot perform this operation
   *
   * @param connection
   * @param articleId Target article's UUID identifier
   * @param tagId Tag's UUID identifier to remove from the article
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Delete operation to remove article-tag relationship from discussion_board_article_tags table.
   *
   * 1. Validate user permissions:
   *    - If not admin: verify user is article author
   *    - If admin: allow operation
   *
   * 2. Find the article-tag relationship record:
   *    - Query discussion_board_article_tags table
   *    - Filter by bbs_article_id (articleId) and tag_id (tagId)
   *
   * 3. Delete the relationship:
   *    - Remove the article-tag association record
   *    - Use CASCADE delete to maintain referential integrity
   *
   * 4. Return success response
   *
   * No response body required for this delete operation. Just return success status code 200.
   *
   * Edge cases:
   * - If article or tag doesn't exist: return 404
   * - If user lacks permission: return 403
   * - If relationship doesn't exist: return 404 or 200 (idempotent)
   *
   * This operation is idempotent - calling it multiple times with the same parameters should not cause errors. For idempotent behavior, return 200 even if the relationship doesn't exist. The operation only removes the association, not the tag itself from the system.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":tagId")
  public async eraseTag(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string,
    @TypedParam("tagId")
    tagId: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminArticlesArticleIdTagsTagId({
        admin,
        articleId,
        tagId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
