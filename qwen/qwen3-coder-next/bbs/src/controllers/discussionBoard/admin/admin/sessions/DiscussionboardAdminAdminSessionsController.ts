import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardAdminSession } from "../../../../../api/structures/IDiscussionBoardAdminSession";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminAdminSessionsSessionId } from "../../../../../providers/getDiscussionBoardAdminAdminSessionsSessionId";

@Controller("/discussionBoard/admin/admin/sessions/:sessionId")
export class DiscussionboardAdminAdminSessionsController {
  /**
   * Retrieve detailed information about a specific administrator session.
   *
   * This operation fetches comprehensive session details for an administrator's login session, including authentication tokens, client metadata, and temporal information. It is designed for administrative oversight and security auditing purposes.
   *
   * **Security Considerations:**
   * - Only accessible by super administrators
   * - Exposes sensitive session information including access and refresh tokens
   * - Includes IP address and user agent for security tracking
   * - Timestamps provide complete session lifecycle visibility
   *
   * **Audit Purpose:**
   * - Track administrator activity and access patterns
   * - Investigate potential security incidents
   * - Monitor session duration and geographic access
   * - Compliance and forensic analysis
   *
   * @param connection
   * @param sessionId Unique identifier of the administrator session to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_admin_sessions table by session ID to retrieve comprehensive session information.
   * Include access_token, refresh_token, IP address, user agent, and all temporal fields.
   * Join with discussion_board_admins table to get administrator display name and email.
   * Return complete session record for audit and administration purposes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sessionId")
    sessionId: string,
  ): Promise<IDiscussionBoardAdminSession> {
    try {
      return await getDiscussionBoardAdminAdminSessionsSessionId({
        admin,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
