import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardAdminSession } from "../../../../../api/structures/IDiscussionBoardAdminSession";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminAdminSessionsSessionId } from "../../../../../providers/getDiscussionBoardAdminAdminSessionsSessionId";

@Controller("/discussionBoard/admin/admin/sessions/:sessionId")
export class DiscussionboardAdminAdminSessionsController {
  /**
   * Retrieve detailed information about a specific admin session.
   *
   * This operation allows authorized super administrators to view comprehensive session details for security auditing and monitoring purposes. The session information includes connection context, temporal data, and user interaction details.
   *
   * The endpoint provides visibility into admin user activity, enabling security teams to track session origins, durations, and patterns for compliance and investigation purposes.
   *
   * @param connection
   * @param sessionId The unique identifier of the admin session
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Retrieve admin session record from discussion_board_admin_sessions table using the session UUID.
   *
   * Query the session by its primary key id.
   * Join with discussion_board_admins table to retrieve associated admin user information.
   * Return complete session details including ip, href, referrer, created_at, and expired_at timestamps.
   *
   * Return 404 if session not found or if the requesting admin does not have super administrator privileges.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sessionId")
    sessionId: string,
  ): Promise<IDiscussionBoardAdminSession> {
    try {
      return await getDiscussionBoardAdminAdminSessionsSessionId({
        admin,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
