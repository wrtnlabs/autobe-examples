import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardArticleImage } from "../../../../api/structures/IDiscussionBoardArticleImage";
import { deleteDiscussionBoardArticlesArticleIdImagesImageId } from "../../../../providers/deleteDiscussionBoardArticlesArticleIdImagesImageId";
import { getDiscussionBoardArticlesArticleIdImagesImageId } from "../../../../providers/getDiscussionBoardArticlesArticleIdImagesImageId";
import { postDiscussionBoardArticlesArticleIdImages } from "../../../../providers/postDiscussionBoardArticlesArticleIdImages";

@Controller("/discussionBoard/articles/:articleId/images")
export class DiscussionboardArticlesImagesController {
  /**
   * Upload an image file and associate it with an article.
   *
   * This endpoint accepts file upload information and creates a metadata record in the discussion_board_article_images table. The image will be linked to the specified article and can be later retrieved or deleted through dedicated endpoints.
   *
   * The system will store the original filename, generate a unique stored path, record the MIME type, and track the file size for quota management purposes.
   *
   * **CRITICAL**: This system uses JSON-based file references, NOT multipart/form-data. Upload the file separately and provide the file URI in the request body.
   *
   * @param connection
   * @param articleId Target article's UUID identifier
   * @param body Image upload information including file URI and metadata
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Handle multipart form data file upload and create discussion_board_article_images record.
   * Extract original filename and MIME type from uploaded file.
   * Generate unique stored_path using UUID or timestamp-based naming.
   * Record file_size in bytes.
   * Create database record with articleId foreign key relationship.
   * Return uploaded image metadata with stored_path as URI for download.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedParam("articleId")
    articleId: string,
    @TypedBody()
    body: IDiscussionBoardArticleImage.ICreate,
  ): Promise<IDiscussionBoardArticleImage> {
    try {
      return await postDiscussionBoardArticlesArticleIdImages({
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Download a specific image attached to an article.
   *
   * This operation retrieves an image file that was previously uploaded to an article. Any user can access this endpoint to view or download the image, as images attached to articles are publicly accessible.
   *
   * The image is returned as a binary stream with appropriate content-type headers based on the file's MIME type.
   *
   * @param connection
   * @param articleId Target article's unique identifier
   * @param imageId Target image's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_article_images table by imageId to retrieve image metadata.
   * Verify the image belongs to the specified articleId.
   * Return the file stream with appropriate content-type based on MIME type.
   * Include proper content-disposition headers for download.
   * Handle cases where image is not found or deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":imageId")
  public async at(
    @TypedParam("articleId")
    articleId: string,
    @TypedParam("imageId")
    imageId: string,
  ): Promise<IDiscussionBoardArticleImage> {
    try {
      return await getDiscussionBoardArticlesArticleIdImagesImageId({
        articleId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific image attachment from an article.
   *
   * This operation permanently removes an image file that was previously attached to an article. The image will be deleted from the storage system and removed from the article's image collection.
   *
   * ## Authorization
   * - Article owner (author of the article)
   * - Administrator or Super Administrator
   *
   * ## Effects
   * - Image file is permanently deleted from storage
   * - Image metadata is removed from database
   * - Article's image count is decremented
   * - The article content remains intact without the removed image
   *
   * @param connection
   * @param articleId The unique identifier of the article containing the image
   * @param imageId The unique identifier of the image to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Delete image attachment from article by ID.
   *
   * Implementation steps:
   * 1. Verify user authorization (article owner or admin)
   * 2. Retrieve article by articleId
   * 3. Retrieve image by imageId associated with the article
   * 4. Delete image file from storage system
   * 5. Remove image metadata from database
   * 6. Update article's image count
   * 7. Return success response
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":imageId")
  public async eraseImage(
    @TypedParam("articleId")
    articleId: string,
    @TypedParam("imageId")
    imageId: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardArticlesArticleIdImagesImageId({
        articleId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
