import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardArticle } from "../../../api/structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../api/structures/IPageIDiscussionBoardArticle";
import { getDiscussionBoardArticlesArticleId } from "../../../providers/getDiscussionBoardArticlesArticleId";
import { patchDiscussionBoardArticles } from "../../../providers/patchDiscussionBoardArticles";

@Controller("/discussionBoard/articles")
export class DiscussionboardArticlesController {
  /**
   * Search and retrieve filtered paginated list of discussion board articles.
   *
   * This operation provides comprehensive search and filtering capabilities for economic and political discussion board articles. Users can filter articles by section, tag, and apply various sorting options to organize results according to their preferences.
   *
   * The search functionality supports both text-based search across article titles and content, as well as structured filtering through section and tag selection. Results are returned in a paginated format with configurable page sizes and sorting options.
   *
   * This endpoint serves as the primary interface for browsing articles on the discussion board, supporting both guest users (public browsing) and authenticated users (with potential personalized filtering options).
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_articles table with pagination and filtering.
   * Apply filters for section_id, tag_name, and search query on title/content.
   * Support sorting by created_at (newest/oldest) and updated_at (newest/oldest).
   * Return paginated results with total count and current page information.
   * Handle soft-deleted articles by excluding them from results.
   * Use database indexes for optimized search performance.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific article.
   *
   * This endpoint provides comprehensive article details including the title, content, author information, associated tags, and any attached files or images. It is designed for displaying the complete article content to users.
   *
   * Security considerations: This is a public endpoint that does not require authentication. Any user, including guests, can view articles. The system should ensure that sensitive information is not exposed through this endpoint.
   *
   * The article content is stored in the database and returned as plain text or formatted HTML depending on the editor used. Tags and attachments are loaded as related entities to provide a complete article view.
   *
   * @param connection
   * @param articleId The unique identifier of the article to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the discussion_board_articles table by the provided article ID.
   * Join with discussion_board_members to fetch author details.
   * Join with discussion_board_article_tags and discussion_board_tags to fetch associated tags.
   * Join with discussion_board_article_files and discussion_board_article_images to fetch attachments.
   * Return the complete article object with all related entities.
   * Handle case where article ID does not exist by returning 404 not found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @TypedParam("articleId")
    articleId: string,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await getDiscussionBoardArticlesArticleId({
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
