import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { getDiscussionBoardArticlesArticleIdFilesFileIdDownload } from "../../../../../providers/getDiscussionBoardArticlesArticleIdFilesFileIdDownload";

@Controller("/discussionBoard/articles/:articleId/files/:fileId/download")
export class DiscussionboardArticlesFilesDownloadController {
  /**
   * Download a specific file attachment from an article.
   *
   * This operation retrieves and delivers a file that has been attached to an article. Users can download files from articles they have permission to view based on their role and the article's visibility settings.
   *
   * The system verifies access rights before delivering the file content and ensures the file attachment belongs to the specified article.
   *
   * @param connection
   * @param articleId Target article's ID
   * @param fileId Target file's ID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_article_files table for record matching articleId and fileId. Verify user has access to the article (guest for public, member for viewable, admin for all). Return file content using stored file_url with appropriate content-type header.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async downloadFile(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("fileId")
    fileId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await getDiscussionBoardArticlesArticleIdFilesFileIdDownload({
        articleId,
        fileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
