import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSearchIndex } from "../../../../api/structures/IDiscussionBoardSearchIndex";
import { IPageIDiscussionBoardSearchIndex } from "../../../../api/structures/IPageIDiscussionBoardSearchIndex";
import { getDiscussionBoardSearchIndices } from "../../../../providers/getDiscussionBoardSearchIndices";
import { getDiscussionBoardSearchIndicesArticleId } from "../../../../providers/getDiscussionBoardSearchIndicesArticleId";
import { postDiscussionBoardSearchIndices } from "../../../../providers/postDiscussionBoardSearchIndices";

@Controller("/discussionBoard/search/indices")
export class DiscussionboardSearchIndicesController {
  /**
   * Retrieve a paginated list of search indices for article content.
   *
   * This operation provides access to the search index system that enables efficient full-text search functionality across the discussion board. The search indices contain indexed title and content text along with trigram representations for fuzzy text matching support.
   *
   * The search indices are automatically maintained by the system to support fast search queries. Each search index record references its source article and contains pre-computed text data optimized for search operations. The trigram-based fuzzy matching allows for better result accuracy when users search with partial matches or typos.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_search_indices table for search index records.
   * Return search index entries with their associated article references.
   * Include indexed title text, content text, and trigram representations.
   * Support pagination with configurable page size.
   * Filter by article_id if provided as query parameter.
   * OrderBy created_at DESC for newest first, ASC for oldest first.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(): Promise<IPageIDiscussionBoardSearchIndex> {
    try {
      return await getDiscussionBoardSearchIndices();
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new search index record for efficient article search functionality.
   *
   * This endpoint creates search index entries that enable fast full-text search across the discussion board. The search index stores both title and content text with trigram representations for fuzzy text matching, supporting efficient partial matching and typo-tolerant searches.
   *
   * The index is used by the search functionality to quickly locate articles matching user queries without scanning the entire article database. Each index record references its source article and includes both plain text for standard search and trigram data for fuzzy matching capabilities.
   *
   * This operation is typically called automatically by the system when articles are created or updated, ensuring search indices remain current with content changes. Manual index creation may be needed for backfill operations or data recovery scenarios.
   *
   * @param connection
   * @param body Search index creation data including article reference and content to index
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Create search index records for article search functionality.
   *
   * 1. Accept request with article_id, title, content, and optional trigram fields
   * 2. Validate article_id references an existing article (check discussion_board_articles table)
   * 3. Create search index record in discussion_board_search_indices table
   * 4. Generate trigram representations for title and content using database functions
   * 5. Set created_at and updated_at timestamps to current time
   * 6. Return created index record with all fields including database-generated timestamps
   *
   * The operation should handle potential unique constraint violations if index already exists for the article, returning appropriate error response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: IDiscussionBoardSearchIndex.ICreate,
  ): Promise<IDiscussionBoardSearchIndex> {
    try {
      return await postDiscussionBoardSearchIndices({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve search index data for a specific article
   *
   * This endpoint fetches the search index information associated with a given article ID. The search index contains the pre-processed content and title data that has been prepared for efficient searching within the discussion board system. The index includes both the original title and content fields, as well as trigram representations that enable fuzzy text matching capabilities.
   *
   * The search index is automatically generated when articles are created or updated, ensuring that all searchable content is properly indexed for fast retrieval. This endpoint provides access to the indexed data that powers the discussion board's search functionality.
   *
   * ## Security and Permissions
   *
   * This endpoint is publicly accessible - no authentication required. Any user (including guests) can retrieve search index data for any article, as the search index only contains non-sensitive text data that is already publicly available through the article itself.
   *
   * ## Search Index Structure
   *
   * The search index includes:
   * - Original title text for title-based searching
   * - Original content text for full-content search
   * - Trigram representations for fuzzy text matching
   * - Timestamps for indexing and updates
   *
   * ## Relationship to Article Data
   *
   * The search index is tightly coupled with the article entity. When an article is deleted, its search index is also automatically removed. The index serves as a denormalized data structure optimized for search performance, containing only the text elements needed for searching without duplicating all article metadata.
   *
   * @param connection
   * @param articleId UUID of the article whose search index should be retrieved
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the discussion_board_search_indices table using the article_id parameter to find the search index record for the specified article. Return the indexed title, content, and trigram fields along with timestamps. Use eager loading to fetch related article information if needed. Implement proper error handling for cases where no search index exists for the given article ID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @TypedParam("articleId")
    articleId: string,
  ): Promise<IDiscussionBoardSearchIndex> {
    try {
      return await getDiscussionBoardSearchIndicesArticleId({
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
