import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSearchQuery } from "../../../../../api/structures/IDiscussionBoardSearchQuery";
import { patchDiscussionBoardSearchQueriesStatistics } from "../../../../../providers/patchDiscussionBoardSearchQueriesStatistics";

@Controller("/discussionBoard/search/queries/statistics")
export class DiscussionboardSearchQueriesStatisticsController {
  /**
   * Retrieve comprehensive search statistics and analytics for the discussion board search system.
   *
   * This endpoint provides detailed analytics about search behavior, query patterns, and search effectiveness. It aggregates data from search queries, click tracking, and result positioning to generate insights about user search behavior and search performance metrics.
   *
   * ## Search Statistics Categories
   *
   * ### Query Statistics
   * - Total search volume and frequency
   * - Popular search terms and their ranking
   * - Search query volume over time periods
   * - Unique vs repeated search queries
   *
   * ### Click Statistics
   * - Click-through rates by search result position
   * - Most/least clicked search results
   * - User engagement patterns with search results
   * - Session-based click analysis
   *
   * ### Relevance Metrics
   * - Average relevance scores for different query types
   * - Performance metrics by search term
   * - Search result positioning effectiveness
   * - User behavior correlation with ranking
   *
   * ## Authorization
   *
   * All authenticated users can access search statistics. The system provides aggregate analytics without exposing individual user data or personal search history.
   *
   * ## Usage Context
   *
   * This endpoint is designed for:
   * - Admin dashboard search analytics displays
   * - Search quality monitoring and improvement
   * - User behavior analysis for search optimization
   * - Performance reporting and KPI tracking
   *
   * @param connection
   * @param body Statistics query parameters for filtering and aggregating search analytics
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Aggregate search statistics from multiple models:
   * 1. Query statistics from discussion_board_search_queries (count, dates, parameters)
   * 2. Click-through rates from discussion_board_search_clicks (join with queries)
   * 3. Result positioning and relevance from discussion_board_search_results
   * 4. Filter by date range if provided in request body
   * 5. Group and aggregate data by query terms, dates, and result positions
   * 6. Calculate click-through rates and relevance metrics
   * 7. Return comprehensive statistics with pagination support
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async indexStatistics(
    @TypedBody()
    body: IDiscussionBoardSearchQuery.IRequest,
  ): Promise<IDiscussionBoardSearchQuery.IStatistic> {
    try {
      return await patchDiscussionBoardSearchQueriesStatistics({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
