import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSearchBehavior } from "../../../../api/structures/IDiscussionBoardSearchBehavior";
import { patchDiscussionBoardSearchBehavior } from "../../../../providers/patchDiscussionBoardSearchBehavior";

@Controller("/discussionBoard/search/behavior")
export class DiscussionboardSearchBehaviorController {
  /**
   * Record search behavior interactions for analytics and relevance ranking.
   *
   * This endpoint captures detailed information about user search behavior including which search queries were performed, which search results were clicked, and the context of those interactions. The data collected helps improve search relevance, understand user patterns, and enhance the overall search experience on the discussion board.
   *
   * The system tracks search queries, result clicks, and user sessions to provide comprehensive analytics on search effectiveness and user engagement patterns.
   *
   * @param connection
   * @param body Search behavior data including query information, clicked results, and user context
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Record search behavior data from user interactions with search results. Insert into discussion_board_search_clicks table with query and result references, user information (if authenticated), session tracking, and result positioning. Capture timestamp for temporal analysis and IP address for analytics while respecting privacy considerations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async record(
    @TypedBody()
    body: IDiscussionBoardSearchBehavior.ICreate,
  ): Promise<IDiscussionBoardSearchBehavior> {
    try {
      return await patchDiscussionBoardSearchBehavior({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
