import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardArticle } from "../../../api/structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../api/structures/IPageIDiscussionBoardArticle";
import { patchDiscussionBoardSearch } from "../../../providers/patchDiscussionBoardSearch";

@Controller("/discussionBoard/search")
export class DiscussionboardController {
  /**
   * Search articles across the entire discussion board system.
   *
   * This operation provides comprehensive search functionality allowing users to search articles by title, content, and apply tag-based filtering. The search supports case-insensitive matching, partial word matching, and phrase searching.
   *
   * The search functionality enables users to find relevant discussions on economic and political topics by searching through article titles and content bodies. Tag filtering allows users to narrow results to specific topics or categories.
   *
   * The operation supports comprehensive pagination with configurable page sizes and sorting. Results include article summary information optimized for search result displays.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_articles table with full-text search capabilities.
   * Apply search filters on title and content fields using case-insensitive matching.
   * Support tag-based filtering by joining with discussion_board_article_tags table.
   * Support pagination with configurable page sizes and offsets.
   * Return paginated list of article summaries optimized for search result displays.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardSearch({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
