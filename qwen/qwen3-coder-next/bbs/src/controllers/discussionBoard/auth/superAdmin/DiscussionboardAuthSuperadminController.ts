import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSuperAdmin } from "../../../../api/structures/IDiscussionBoardSuperAdmin";
import { postDiscussionBoardAuthSuperAdminJoin } from "../../../../providers/postDiscussionBoardAuthSuperAdminJoin";
import { postDiscussionBoardAuthSuperAdminLogin } from "../../../../providers/postDiscussionBoardAuthSuperAdminLogin";
import { postDiscussionBoardAuthSuperAdminRefresh } from "../../../../providers/postDiscussionBoardAuthSuperAdminRefresh";

@Controller("/discussionBoard/auth/superAdmin")
export class DiscussionboardAuthSuperadminController {
  /**
   * Register a new super admin account. This endpoint creates a new super administrator account with the provided email and password. The password is hashed before storage. Upon successful registration, the system creates a new session and returns JWT access and refresh tokens. This operation is only available for new super admin account creation.
   *
   * The registration process validates the email format, checks for duplicate emails, validates password strength, and stores the password using secure hashing. After successful registration, a new session is created and JWT tokens are generated.
   *
   * This operation uses the IDiscussionBoardSuperAdmin.IJoin request body type and returns IDiscussionBoardSuperAdmin.IAuthorized with tokens.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration request body for super admin account
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Validate super admin credentials, create session, and return JWT tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardSuperAdmin.IJoin,
  ): Promise<IDiscussionBoardSuperAdmin.IAuthorized> {
    try {
      return await postDiscussionBoardAuthSuperAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate super admin credentials and establish a new session. This endpoint validates the provided email and password against the stored credentials. Upon successful authentication, the system creates a new session and returns JWT access and refresh tokens.
   *
   * The login process validates the email format, checks if the account exists, verifies the password hash, and confirms the account is not suspended. If authentication succeeds, new JWT tokens are generated and returned.
   *
   * This operation uses the IDiscussionBoardSuperAdmin.ILogin request body type and returns IDiscussionBoardSuperAdmin.IAuthorized with tokens.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login request body for super admin authentication
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Authenticate super admin credentials, create session, and return JWT tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardSuperAdmin.ILogin,
  ): Promise<IDiscussionBoardSuperAdmin.IAuthorized> {
    try {
      return await postDiscussionBoardAuthSuperAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens using a valid refresh token. This endpoint validates the provided refresh token and generates new access and refresh tokens. The refresh token rotation pattern is used for security - the old refresh token is invalidated and a new one is issued.
   *
   * The refresh process validates the refresh token signature, checks token expiration, verifies the token hasn't been revoked, and creates a new session with fresh tokens. This operation maintains session continuity while enhancing security through token rotation.
   *
   * This operation uses the IDiscussionBoardSuperAdmin.IRefresh request body type and returns IDiscussionBoardSuperAdmin.IAuthorized with tokens.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh request body for super admin
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Validate refresh token, create new session, and return new JWT tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardSuperAdmin.IRefresh,
  ): Promise<IDiscussionBoardSuperAdmin.IAuthorized> {
    try {
      return await postDiscussionBoardAuthSuperAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
