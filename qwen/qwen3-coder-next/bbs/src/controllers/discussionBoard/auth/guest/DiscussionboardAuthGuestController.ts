import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardGuest } from "../../../../api/structures/IDiscussionBoardGuest";
import { postDiscussionBoardAuthGuestJoin } from "../../../../providers/postDiscussionBoardAuthGuestJoin";
import { postDiscussionBoardAuthGuestRefresh } from "../../../../providers/postDiscussionBoardAuthGuestRefresh";

@Controller("/discussionBoard/auth/guest")
export class DiscussionboardAuthGuestController {
  /**
   * Guest join operation creates a new temporary session for unauthenticated users. This operation accepts no request body since guests don't have credentials. The system generates a unique session identifier and returns it in the authorized response. This is the only way for guests to authenticate - they don't have passwords or email-based verification. Guest sessions are tracked via session_id and expire after a reasonable inactivity period.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest session creation request with session identifier.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Generate session_id token for new guest session.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardGuest.IJoin,
  ): Promise<IDiscussionBoardGuest.IAuthorized> {
    try {
      return await postDiscussionBoardAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Guest refresh operation validates and extends an existing guest session. This operation accepts the current session identifier in the request body and returns new session tokens if the session is still valid. The system verifies the session exists and has not expired. If valid, it returns updated tokens and refreshes the session lifetime. This allows guests to maintain their session across extended browsing periods.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest session refresh request with current session identifier.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Renew guest session token using existing session_id.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardGuest.IRefresh,
  ): Promise<IDiscussionBoardGuest.IAuthorized> {
    try {
      return await postDiscussionBoardAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
