import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardMember } from "../../../../api/structures/IDiscussionBoardMember";
import { postDiscussionBoardAuthMemberJoin } from "../../../../providers/postDiscussionBoardAuthMemberJoin";
import { postDiscussionBoardAuthMemberLogin } from "../../../../providers/postDiscussionBoardAuthMemberLogin";
import { postDiscussionBoardAuthMemberRefresh } from "../../../../providers/postDiscussionBoardAuthMemberRefresh";

@Controller("/discussionBoard/auth/member")
export class DiscussionboardAuthMemberController {
  /**
   * Member registration endpoint for creating new account credentials in the Discussion Board application. This operation validates and stores member information including email, password hash, display name, and bio. The system ensures email uniqueness, applies password strength validation, and creates a new member record in the discussion_board_members table with the 'member' role. Upon successful registration, JWT access and refresh tokens are generated, the refresh token is stored in discussion_board_member_sessions with expiration, and both tokens are returned in the response.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration request body containing member credentials and profile information.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Member registration operation creates a new member account in the discussion_board_members table. The service layer validates email uniqueness, applies password hashing using bcrypt or similar secure algorithm, and stores the member with default role 'member', is_banned as false. The operation should include validation for email format, password strength requirements (minimum length, complexity), and display name constraints (1-100 characters). Upon successful registration, the operation generates JWT access and refresh tokens, stores the refresh token in the discussion_board_member_sessions table with expiration, and returns both tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardMember.IJoin,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postDiscussionBoardAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Member login endpoint for authenticating existing credentials and establishing JWT session. This operation validates member email and password against the stored credentials in discussion_board_members table. The system checks account status (not banned), validates password hash, and ensures the account hasn't been soft-deleted. Upon successful authentication, new JWT access and refresh tokens are generated, stored in discussion_board_member_sessions table with expiration timestamp, and returned in the response body. The operation supports secure password verification using bcrypt or similar hashing algorithm.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login request body containing member email and password credentials.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Member login operation authenticates existing member credentials against the discussion_board_members table. The service layer retrieves the member by email, validates the password hash, checks if the account is banned (is_banned = false), and verifies the role is 'member'. Upon successful authentication, the operation generates new JWT access and refresh tokens, updates or creates a session record in discussion_board_member_sessions with the current timestamp and expiration, and returns both tokens. The operation should handle various error cases: email not found, invalid password, banned account, and deleted account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardMember.ILogin,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postDiscussionBoardAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Token refresh endpoint for renewing JWT access and refresh tokens. This operation validates the provided refresh token against discussion_board_member_sessions table to ensure it hasn't expired and the member account is still valid. The system checks for soft-deleted accounts and banned status. Upon successful validation, new JWT access and refresh tokens are generated, the session record is updated with the new refresh token and expiration timestamp, and both tokens are returned. This implements token rotation for enhanced security.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token request body containing the current refresh token.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Token refresh operation validates the refresh token against the discussion_board_member_sessions table. The service layer looks up the refresh token record, verifies it hasn't expired, and checks that the associated member account is still valid (not deleted, not banned). If valid, the operation generates new JWT access and refresh tokens, updates the session record with the new refresh token and expiration timestamp, and returns both tokens. The operation should handle error cases: expired refresh token, invalid token, deleted member account, and banned account. The refresh token should be rotation-enabled for security.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardMember.IRefresh,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postDiscussionBoardAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
