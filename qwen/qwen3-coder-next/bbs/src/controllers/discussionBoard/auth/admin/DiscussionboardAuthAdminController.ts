import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardAdmin } from "../../../../api/structures/IDiscussionBoardAdmin";
import { postDiscussionBoardAuthAdminJoin } from "../../../../providers/postDiscussionBoardAuthAdminJoin";
import { postDiscussionBoardAuthAdminLogin } from "../../../../providers/postDiscussionBoardAuthAdminLogin";
import { postDiscussionBoardAuthAdminRefresh } from "../../../../providers/postDiscussionBoardAuthAdminRefresh";

@Controller("/discussionBoard/auth/admin")
export class DiscussionboardAuthAdminController {
  /**
   * Admin registration operation that creates a new administrator account with email authentication credentials. This endpoint is for registering new admin users who will have administrative privileges to manage sections, delete content, and ban users.
   *
   * The registration process validates that the email address is unique and not already registered, ensures the password meets security requirements (minimum length, complexity), and stores a hashed version of the password for security. The display name must be unique and within the 1-100 character limit as defined in the database schema. After successful registration, the admin account is created in the discussion_board_admins table with default role of 'admin' and is_banned set to false.
   *
   * The operation returns JWT access and refresh tokens upon successful registration, allowing the new admin to immediately authenticate. The session is tracked in the discussion_board_admin_sessions table with appropriate expiration times. This registration flow is specifically designed for admin actors and follows different validation rules than member or guest registrations to ensure security and proper administrative access control.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration request body for creating new admin accounts.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification The join operation validates email uniqueness, password strength (minimum 8 characters with mixed case, numbers, and special characters), and display name format. It creates the admin record in discussion_board_admins with email, hashed password, display_name, and default role 'admin'. The operation also creates a session record in discussion_board_admin_sessions and generates both access and refresh JWT tokens with appropriate expiration times.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardAdmin.IJoin,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postDiscussionBoardAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Admin login operation that authenticates administrator credentials and establishes a authenticated session with JWT tokens. This endpoint validates the admin's email and password against the stored credentials in the discussion_board_admins table.
   *
   * The login process first verifies that the provided email exists in the database and checks if the account is banned (is_banned = true). If banned, the operation returns an error preventing login. The password is verified against the hashed password_hash field using secure comparison. Upon successful authentication, the operation generates new JWT access and refresh tokens and stores them in the discussion_board_admin_sessions table with appropriate expiration times.
   *
   * The access token has a shorter expiration (typically 15-30 minutes) for secure short-term access, while the refresh token has a longer expiration (typically 7-14 days) for maintaining sessions. The operation returns both tokens so the client can continue authenticated requests and refresh tokens when the access token expires. This login flow is specifically designed for admin actors with the same security requirements as member login but with admin-specific validation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login request body for admin authentication with email and password.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification The login operation retrieves the admin record by email from discussion_board_admins, verifies the password_hash using bcrypt or similar secure hashing algorithm, checks is_banned status, and creates a session record in discussion_board_admin_sessions with generated tokens. Both access_token and refresh_token are returned with their expiration times. The operation handles banned account rejection, invalid credentials, and non-existent email scenarios.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardAdmin.ILogin,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postDiscussionBoardAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Token refresh operation that renews the JWT authentication session for admin users. This endpoint validates the refresh token and issues new access and refresh tokens to maintain an authenticated session without requiring the user to re-enter their credentials.
   *
   * The refresh process retrieves the admin's session from the discussion_board_admin_sessions table using the provided refresh token. It validates that the session exists, the refresh token hasn't expired, and the admin account hasn't been banned since the session was created. If validation passes, the operation generates new JWT access and refresh tokens, updates the session record with the new refresh token, and returns both tokens to the client.
   *
   * This operation is crucial for maintaining continuous admin access to administrative features without forcing frequent re-authentication. The refresh token expiration is typically set to 7-14 days, after which the user must log in again. This ensures security while providing convenience for administrators who need sustained access to management features.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh request body containing the refresh token to obtain new JWT tokens.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification The refresh operation retrieves the session from discussion_board_admin_sessions using the provided refresh_token, validates the session hasn't expired, checks if the admin is_banned, generates new access and refresh tokens, updates the session record with the new refresh_token (for token rotation), and returns both tokens. The operation handles expired token rejection, banned account session invalidation, and invalid session scenarios.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardAdmin.IRefresh,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postDiscussionBoardAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
