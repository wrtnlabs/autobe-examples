import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardMemberSession } from "../../../../../api/structures/IDiscussionBoardMemberSession";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getDiscussionBoardMemberMemberActivity } from "../../../../../providers/getDiscussionBoardMemberMemberActivity";

@Controller("/discussionBoard/member/member/activity")
export class DiscussionboardMemberMemberActivityController {
  /**
   * Retrieve comprehensive member activity summary including ban history, administrator requests, and session information.
   *
   * This endpoint provides authenticated members with a detailed view of their account activity, including any ban records (bans and unbans), administrator privilege requests they have submitted, and their login session history. The activity summary helps members understand their account status and track their interactions with the administrative system.
   *
   * The endpoint aggregates data from three primary sources: ban records for the user, administrator requests submitted by the user, and session activity history.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Aggregate user activity data from ban_records, administrator_requests, and member_sessions tables. Query all ban records for the authenticated user, all administrator requests submitted by the user, and recent session activity. Return comprehensive activity summary including ban status, request history, and session information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IDiscussionBoardMemberSession.ISummary> {
    try {
      return await getDiscussionBoardMemberMemberActivity({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
