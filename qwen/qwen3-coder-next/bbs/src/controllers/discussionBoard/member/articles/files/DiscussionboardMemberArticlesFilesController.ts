import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardArticleFile } from "../../../../../api/structures/IDiscussionBoardArticleFile";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { postDiscussionBoardMemberArticlesArticleIdFiles } from "../../../../../providers/postDiscussionBoardMemberArticlesArticleIdFiles";

@Controller("/discussionBoard/member/articles/:articleId/files")
export class DiscussionboardMemberArticlesFilesController {
  /**
   * Bulk upload files to an article
   *
   * This operation allows the article owner to upload multiple files to an article. Files are stored with unique identifiers and associated with the article for later retrieval.
   *
   * ## Security Considerations
   *
   * Only the article owner or administrators can upload files to an article. This ensures that only authorized users can add content to existing articles.
   *
   * ## File Storage
   *
   * Uploaded files are stored with unique identifiers and associated with the article. The file metadata is stored in the discussion_board_article_files table including original filename, stored path, MIME type, and file size.
   *
   * ## Authorization
   *
   * This operation requires member authentication. Only the article owner or administrators can upload files to an article.
   *
   * ## Related Operations
   *
   * - GET /articles/{articleId}/files/:fileId - Download a specific file
   * - DELETE /articles/{articleId}/files/:fileId - Delete a specific file from the article
   *
   * @param connection
   * @param articleId Target article's unique identifier
   * @param body Bulk file upload request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Process multipart form data with multiple files. Generate unique identifiers for each file. Store file metadata in discussion_board_article_files table. Associate files with the article via article_id foreign key. Return array of IArticleFile metadata with all file information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string,
    @TypedBody()
    body: IDiscussionBoardArticleFile.ICreate,
  ): Promise<IDiscussionBoardArticleFile> {
    try {
      return await postDiscussionBoardMemberArticlesArticleIdFiles({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
