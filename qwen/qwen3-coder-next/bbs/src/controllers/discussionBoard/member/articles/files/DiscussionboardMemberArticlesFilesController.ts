import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardArticleFile } from "../../../../../api/structures/IDiscussionBoardArticleFile";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberArticlesArticleIdFilesFileId } from "../../../../../providers/deleteDiscussionBoardMemberArticlesArticleIdFilesFileId";
import { postDiscussionBoardMemberArticlesArticleIdFiles } from "../../../../../providers/postDiscussionBoardMemberArticlesArticleIdFiles";

@Controller("/discussionBoard/member/articles/:articleId/files")
export class DiscussionboardMemberArticlesFilesController {
  /**
   * Upload files to an article. This operation allows users to attach multiple files to an article, with each file stored with its metadata including original filename, file size, file type, and upload timestamp.
   *
   * @param connection
   * @param articleId Target article's ID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Upload files to an article by creating FileAttachment records. Validate that the user is authenticated and not banned. Enforce file size and type limits. Associate files with the specified article. Return all file metadata including file URL.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticleFile> {
    try {
      return await postDiscussionBoardMemberArticlesArticleIdFiles({
        member,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a specific file attachment from an article by marking it as deleted.
   *
   * This operation performs a soft delete on the file attachment record by setting the deleted_at timestamp, making the file inaccessible through normal API operations while preserving the record for audit purposes.
   *
   * Authorization: Users can only delete files they originally uploaded, unless they have administrator privileges. This restriction is enforced by the business logic layer.
   *
   * Related: To view deleted files, use the list operation with appropriate filters.
   *
   * @param connection
   * @param articleId The ID of the article containing the file attachment
   * @param fileId The ID of the file attachment to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Delete the file attachment record from the database. Cascade delete the associated file from storage. Ensure the file belongs to the specified article before deletion. Return 204 No Content on success.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":fileId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("fileId")
    fileId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberArticlesArticleIdFilesFileId({
        member,
        articleId,
        fileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
