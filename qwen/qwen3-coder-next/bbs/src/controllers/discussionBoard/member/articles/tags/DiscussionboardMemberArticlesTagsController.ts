import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardArticle } from "../../../../../api/structures/IDiscussionBoardArticle";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberArticlesArticleIdTagsTagId } from "../../../../../providers/deleteDiscussionBoardMemberArticlesArticleIdTagsTagId";
import { postDiscussionBoardMemberArticlesArticleIdTags } from "../../../../../providers/postDiscussionBoardMemberArticlesArticleIdTags";

@Controller("/discussionBoard/member/articles/:articleId/tags")
export class DiscussionboardMemberArticlesTagsController {
  /**
   * Associate tags with an existing article.
   *
   * This endpoint allows users to add one or more tags to an article by specifying tag names in the request body. The system automatically creates new tags if they don't already exist, and establishes the associations in the article_tags junction table.
   *
   * Users can provide multiple tag names simultaneously. Each tag name is processed individually, with the system creating the tag if needed and linking it to the specified article.
   *
   * @param connection
   * @param articleId The unique identifier of the article to associate tags with
   * @param body List of tag names to associate with the article
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create tag associations for an article. Parse the list of tag names from the request body, create new tag records if they don't exist, and establish associations in the discussion_board_article_tags table. Ensure the article exists before creating associations. Return success confirmation with count of tags added.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async addTags(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticle.ITagsRequest,
  ): Promise<IDiscussionBoardArticle.ITagsResponse> {
    try {
      return await postDiscussionBoardMemberArticlesArticleIdTags({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove the association between an article and a tag.
   *
   * This operation deletes the ArticleTag junction record that links a specific article to a specific tag. When executed, the association is removed while preserving both the article content and the tag record itself. This follows the business rule that tags should persist even after they are no longer associated with any articles.
   *
   * The operation requires the requesting user to have access to the article. It validates that both the article and tag exist before attempting to remove the association. If either entity does not exist, the operation returns a 404 error. If the association has already been removed, the operation succeeds with a 204 status.
   *
   * @param connection
   * @param articleId The unique identifier of the article from which to remove the tag
   * @param tagId The unique identifier of the tag to be removed from the article
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Delete ArticleTag junction record linking the specified article and tag.
   * Verify article exists and is accessible to requesting user.
   * Remove the association record while preserving both article and tag entities.
   * Handle edge cases: non-existent article, non-existent tag, already removed association.
   * Maintain referential integrity with no cascading deletions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":tagId")
  public async removeArticleTag(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("tagId")
    tagId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberArticlesArticleIdTagsTagId({
        member,
        articleId,
        tagId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
