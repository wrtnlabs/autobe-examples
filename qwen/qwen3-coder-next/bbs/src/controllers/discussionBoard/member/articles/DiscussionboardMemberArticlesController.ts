import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberArticlesArticleId } from "../../../../providers/deleteDiscussionBoardMemberArticlesArticleId";
import { postDiscussionBoardMemberArticles } from "../../../../providers/postDiscussionBoardMemberArticles";
import { putDiscussionBoardMemberArticlesArticleId } from "../../../../providers/putDiscussionBoardMemberArticlesArticleId";

@Controller("/discussionBoard/member/articles")
export class DiscussionboardMemberArticlesController {
  /**
   * Create a new article for discussion on economic or political topics.
   *
   * This endpoint allows authenticated members to publish articles to the discussion board. The article is immediately published and visible to other users. When creating an article, the system automatically sets the author to the currently authenticated user, records the creation timestamp, and associates the article with the specified section.
   *
   * Article creation requires a title, content, and section assignment. Tags can be provided to categorize the article for search and filtering. Files and images can be uploaded as part of the article creation or added later through dedicated endpoints.
   *
   * After creation, the article appears in the section's article list and can be commented on by other users. The original author retains ownership and can edit or delete the article at any time.
   *
   * @param connection
   * @param body Article creation data including title, content, section assignment, and optional tags and attachments
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new article in the discussion_board_articles table.
   *
   * 1. Extract currently authenticated user ID from JWT token
   * 2. Validate sectionId exists in discussion_board_sections table
   * 3. Validate any provided tag names exist or will be created in discussion_board_tags
   * 4. Create article record with:
   *    - title, content, section_id from request
   *    - author_id from authenticated user
   *    - created_at and updated_at timestamps
   *    - status set to 'published'
   * 5. Handle tag associations in discussion_board_article_tags junction table
   * 6. For file uploads, create records in discussion_board_article_files with article_id reference
   * 7. For image uploads, create records in discussion_board_article_images with article_id reference
   * 8. Return complete article with nested relationships loaded
   * 9. Increment section's article_count
   * 10. Update author's article_count
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.ICreate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await postDiscussionBoardMemberArticles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing article with new content.
   *
   * This operation allows the article author or administrators to modify an existing article's title, content, and section assignment. Only authenticated users who created the article or users with administrator privileges can perform this update.
   *
   * Articles can be updated to change their content, add new tags, or move them between sections. The system ensures that only authorized users can modify articles and maintains data integrity throughout the update process.
   *
   * Security considerations:
   * - Authors can only update their own articles
   * - Administrators and super administrators can update any article
   * - Guest users cannot update any articles
   *
   * @param connection
   * @param articleId Target article's unique identifier
   * @param body Article update information including new title, content, section, and tags
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update article in discussion_board_articles table with new title, content, and section_id.
   * Verify user authorization (author or admin).
   * Validate section_id references existing section.
   * Validate title (1-200 chars) and content (min 1 char).
   * Replace tags with provided array (delete existing, create new tag associations).
   * Update updated_at timestamp to current time.
   * Return complete article record with author and section details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":articleId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticle.IUpdate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await putDiscussionBoardMemberArticlesArticleId({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an article and all associated data from the system.
   *
   * This operation permanently removes an article from the discussion board system, including all associated attachments, images, and comments. The operation is available to authenticated users for their own articles and to administrators for any article.
   *
   * When a user deletes their own article, the system confirms the user is the article author before proceeding with deletion. When an administrator deletes an article, the system verifies administrative privileges and logs the administrative action for audit purposes.
   *
   * The deletion cascades to all related data: all file attachments, all image attachments, all comments, and all tag associations are removed. The operation preserves system integrity and relationships by removing all dependent records.
   *
   * After successful deletion, the article is no longer accessible through any API endpoints and cannot be recovered. This is a permanent operation with no soft-delete behavior.
   *
   * @param connection
   * @param articleId Target article's unique identifier (UUID).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Delete article and cascade delete all associated data.
   * Query discussion_board_articles by articleId with author_id for ownership verification.
   * When user is not owner and not admin, return 403 Forbidden.
   * Delete all related discussion_board_article_files records.
   * Delete all related discussion_board_article_images records.
   * Delete all related discussion_board_comments records.
   * Delete all related discussion_board_article_tags records.
   * Delete the article record from discussion_board_articles.
   * Return HTTP 200 with success confirmation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":articleId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberArticlesArticleId({
        member,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
