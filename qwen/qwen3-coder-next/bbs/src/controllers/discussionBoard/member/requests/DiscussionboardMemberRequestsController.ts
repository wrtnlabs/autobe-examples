import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardAdministratorRequest } from "../../../../api/structures/IDiscussionBoardAdministratorRequest";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { postDiscussionBoardMemberRequests } from "../../../../providers/postDiscussionBoardMemberRequests";

@Controller("/discussionBoard/member/requests")
export class DiscussionboardMemberRequestsController {
  /**
   * Submit a request to become an administrator.
   *
   * This endpoint allows registered members to apply for administrator privileges. The request includes a reason text explaining why the user should be granted administrator access.
   *
   * @param connection
   * @param body Administrator request details
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new administrator request for the authenticated user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardAdministratorRequest.ICreate,
  ): Promise<IDiscussionBoardAdministratorRequest> {
    try {
      return await postDiscussionBoardMemberRequests({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
