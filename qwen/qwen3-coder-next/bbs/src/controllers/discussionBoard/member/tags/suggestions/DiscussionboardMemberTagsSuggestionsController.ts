import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardTag } from "../../../../../api/structures/IDiscussionBoardTag";
import { IPageIDiscussionBoardTag } from "../../../../../api/structures/IPageIDiscussionBoardTag";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchDiscussionBoardMemberTagsSuggestions } from "../../../../../providers/patchDiscussionBoardMemberTagsSuggestions";

@Controller("/discussionBoard/member/tags/suggestions")
export class DiscussionboardMemberTagsSuggestionsController {
  /**
   * Retrieve tag suggestions for autocomplete and tag selection.
   *
   * This operation provides intelligent tag suggestions to help users quickly find and select appropriate tags when creating or editing content. It supports partial name matching to enable responsive autocomplete functionality as users type tag names.
   *
   * The endpoint accepts a search query parameter and returns a paginated list of matching tags sorted by relevance and frequency. This helps users discover existing tags and avoid creating duplicate tags with slightly different naming conventions.
   *
   * @param connection
   * @param body Search query for tag suggestions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query discussion_board_tags table for tag suggestions matching the search query.
   * Filter tags by name partial matching.
   * Sort by relevance score and frequency count.
   * Return paginated results with tag name and count information.
   * Exclude tags that have been soft-deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardTag.IRequest,
  ): Promise<IPageIDiscussionBoardTag> {
    try {
      return await patchDiscussionBoardMemberTagsSuggestions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
