import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardBansAppeal } from "../../../../../api/structures/IDiscussionBoardBansAppeal";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { postDiscussionBoardMemberBansAppeals } from "../../../../../providers/postDiscussionBoardMemberBansAppeals";

@Controller("/discussionBoard/member/bans/appeals")
export class DiscussionboardMemberBansAppealsController {
  /**
   * Create a new ban appeal record
   *
   * This endpoint allows banned users to submit an appeal against their ban decision. Users can provide detailed explanations and justification for why they believe their ban should be reviewed and potentially lifted.
   *
   * The system will create an appeal record with status 'pending' and assign it to the appropriate administrator for review. The appeal process provides transparency and fairness to the ban system by allowing users to contest ban decisions.
   *
   * For administrative use, see GET /admin/appeals to view all pending appeals, and PATCH /admin/appeals/{id}/approve or PATCH /admin/appeals/{id}/reject to process appeals.
   *
   * @param connection
   * @param body Ban appeal creation parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create new appeal record in discussion_board_bans_appeals table with the specified ban_record_id and appeal_reason. Set status to 'pending' automatically. The ban_record_id should reference an existing ban record in discussion_board_bans_ban_records. The appeal_reason should contain the user's explanation text.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardBansAppeal.ICreate,
  ): Promise<IDiscussionBoardBansAppeal> {
    try {
      return await postDiscussionBoardMemberBansAppeals({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
