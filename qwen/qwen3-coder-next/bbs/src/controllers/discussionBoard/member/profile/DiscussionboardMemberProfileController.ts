import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardMember } from "../../../../api/structures/IDiscussionBoardMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putDiscussionBoardMemberProfile } from "../../../../providers/putDiscussionBoardMemberProfile";

@Controller("/discussionBoard/member/profile")
export class DiscussionboardMemberProfileController {
  /**
   * Update the authenticated user's own profile information.
   *
   * This endpoint allows members to modify their display name and bio text. The operation updates the profile information for the currently authenticated user, ensuring that only the profile owner can make these changes.
   *
   * **Security Considerations:**
   * - Only the authenticated user can update their own profile
   * - Display name validation: 2-50 characters
   * - Bio validation: max 500 characters
   * - No offensive or inappropriate content allowed
   *
   * **Business Logic:**
   * - Updates are applied immediately to the database
   * - The updated_at timestamp is automatically refreshed
   * - Returns the complete updated profile for confirmation
   *
   * **Related Operations:**
   * - GET /users/profile - Get own profile (view current profile)
   * - GET /users/:id/profile - Get other user's profile (read-only)
   * - DELETE /users/profile - Delete own account (account deletion)
   *
   * @param connection
   * @param body Profile update request containing display name and bio text
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update the authenticated user's profile in discussion_board_members table.
   * Validate display_name (2-50 chars) and bio (max 500 chars).
   * Use the authenticated user's ID from JWT token to identify the record.
   * Update the display_name and bio fields with validated values.
   * Set updated_at to current timestamp.
   * Return the complete updated user record with all fields.
   * Throw error if user not found (404) or validation fails (400).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardMember.IUpdate,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await putDiscussionBoardMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
