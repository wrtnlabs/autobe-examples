import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardGuest } from "../../../api/structures/IDiscussionBoardGuest";
import { IPageIDiscussionBoardGuest } from "../../../api/structures/IPageIDiscussionBoardGuest";
import { getDiscussionBoardGuestsGuestId } from "../../../providers/getDiscussionBoardGuestsGuestId";
import { patchDiscussionBoardGuests } from "../../../providers/patchDiscussionBoardGuests";

@Controller("/discussionBoard/guests")
export class DiscussionboardGuestsController {
  /**
   * Retrieve a paginated list of guest users who have visited the discussion board without authentication.
   *
   * This operation provides visibility into unauthenticated user activity by returning guest sessions identified by their device fingerprints and IP addresses. The system tracks when guests first visit and their last interaction, enabling administrators to monitor platform engagement from non-registered users.
   *
   * ## Security Considerations
   *
   * Guest data is considered public analytics information and is accessible to authenticated users. The system does not expose sensitive personal information but maintains privacy by using anonymized identifiers.
   *
   * ## Implementation Notes
   *
   * This endpoint supports pagination and filtering by session activity dates to enable efficient querying of large guest datasets.
   *
   * @param connection
   * @param body Search and pagination parameters for guest sessions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_guests table with pagination support.
   * Filter by creation/update timestamps to find active sessions.
   * Return paginated list with device fingerprint and IP address information.
   * Sort by creation date descending to show most recent sessions first.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardGuest.IRequest,
  ): Promise<IPageIDiscussionBoardGuest.ISummary> {
    try {
      return await patchDiscussionBoardGuests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a guest user session.
   *
   * This operation fetches comprehensive details about a guest user's session from the discussion_board_guests table. Guest sessions are created for users who browse the discussion board without logging in, using device fingerprinting and IP tracking to identify unique visitors.
   *
   * The returned information includes the guest's IP address, unique device fingerprint, and session timestamps. This data is primarily used for security monitoring, analytics, and administrative oversight of platform activity.
   *
   * This endpoint is designed for administrative use cases where platform operators need to investigate guest activity patterns or track specific guest sessions for security purposes.
   *
   * @param connection
   * @param guestId Unique identifier of the guest session
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the discussion_board_guests table by UUID to retrieve guest session details.
   * Return the complete guest record including ip_address, device_fingerprint, created_at, and updated_at fields.
   * Handle case where guestId doesn't exist by returning 404 Not Found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":guestId")
  public async at(
    @TypedParam("guestId")
    guestId: string,
  ): Promise<IDiscussionBoardGuest> {
    try {
      return await getDiscussionBoardGuestsGuestId({
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
