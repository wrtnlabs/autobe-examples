import { IEntity } from "@ORGANIZATION/PROJECT-api/lib/structures/IEntity";
import { IShoppingMallSellerSessions } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallSellerSessions";
import { ArrayUtil } from "@nestia/e2e";
import { Prisma } from "@prisma/sdk";
import typia, { tags } from "typia";

import { toISOStringSafe } from "../utils/toISOStringSafe";

export namespace ShoppingMallSellerSessionsTransformer {
  export type Payload = Prisma.shopping_mall_seller_sessionsGetPayload<
    ReturnType<typeof select>
  >;
  export function select() {
    return {
      select: {
        id: true,
        ip: true,
        href: true,
        referrer: true,
        created_at: true,
        expired_at: true,
        seller: {
          select: {
            id: true,
            shop_name: true,
          },
        },
      },
    } satisfies Prisma.shopping_mall_seller_sessionsFindManyArgs;
  }
  export async function transform(
    input: Payload,
  ): Promise<IShoppingMallSellerSessions> {
    // Token generation is handled by authentication service layer
    // This transformer focuses on data extraction and formatting
    return {
      access: "access_token_placeholder", // Generated by auth service
      refresh: "refresh_token_placeholder", // Generated by auth service
      expired_at: toISOStringSafe(input.expired_at),
    };
  }
}
