import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallOrderRefundRequest } from "../../../../api/structures/IPageIShoppingMallOrderRefundRequest";
import { IShoppingMallOrderRefundRequest } from "../../../../api/structures/IShoppingMallOrderRefundRequest";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerRefundRequests } from "../../../../providers/getShoppingMallSellerRefundRequests";
import { patchShoppingMallSellerRefundRequests } from "../../../../providers/patchShoppingMallSellerRefundRequests";
import { putShoppingMallSellerRefundRequestsRequestIdReject } from "../../../../providers/putShoppingMallSellerRefundRequestsRequestIdReject";

@Controller("/shoppingMall/seller/refund-requests")
export class ShoppingmallSellerRefund_requestsController {
  /**
   * Retrieve a paginated list of refund requests initiated by the current customer.
   *
   * This endpoint allows customers to view all refund requests they have submitted for their delivered order items. The list includes refund requests with various statuses (pending, approved, rejected) and provides comprehensive information about each refund including the associated order item, product details, and current status.
   *
   * Security Considerations:
   * - Only refund requests created by the authenticated customer are returned
   * - Sellers can only see refund requests for their own products
   * - Administrators can view all refund requests across the platform
   *
   * Database Relationships:
   * - Each refund request is linked to an order item
   * - Refund requests are associated with customers and sellers
   * - Status logs maintain audit history of all status changes
   *
   * Related Operations:
   * - POST /refund-requests: Submit a new refund request
   * - PUT /refund-requests/{id}/approve: Seller approves a refund request
   * - PUT /refund-requests/{id}/reject: Seller rejects a refund request
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_order_refund_requests table with customer context.
   * Apply filters based on actor role:
   * - Customer: only refund requests where customer_id matches current user
   * - Seller: only refund requests where seller_id matches current seller
   * - Admin: all refund requests
   * Apply status filter if provided (pending/approved/rejected)
   * Return paginated results with pagination info (total, page, limit, hasMore)
   * Include related order item, product, and seller information for summary display
   * Use soft-delete filtering (deleted_at IS NULL)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IPageIShoppingMallOrderRefundRequest.ISummary> {
    try {
      return await getShoppingMallSellerRefundRequests({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of refund requests.
   *
   * This operation provides comprehensive search capabilities for refund requests including filtering by status, date range, customer, and order information. Supports full pagination with configurable page sizes and sorting options.
   *
   * The refund request system allows customers to request refunds for delivered items within 7 days of delivery, with sellers able to approve or reject requests. This endpoint provides visibility into all refund activities on the platform.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query order_refund_requests table with pagination and filtering.
   * Apply filters on status, customer_id, order_id, created_at date range.
   * Support sorting by created_at, updated_at.
   * Return cursor-based pagination for large result sets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IPageIShoppingMallOrderRefundRequest.ISummary> {
    try {
      return await patchShoppingMallSellerRefundRequests({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Reject a pending refund request for a delivered order item.
   *
   * This endpoint allows sellers to formally reject customer-initiated refund requests. When a seller rejects a refund request, the order item maintains its current "delivered" status and no stock restoration or payment refund occurs.
   *
   * ## Security Considerations
   *
   * - Sellers can only reject refund requests for their own products
   * - Refund requests must have status "pending" to be rejected
   * - Sellers must provide a rejection reason explaining why the refund is denied
   * - Rejection is irreversible - once rejected, the customer cannot proceed with this refund request
   *
   * ## Business Logic
   *
   * - This endpoint is for sellers to reject refund requests after careful review
   * - Common reasons for rejection: customer-provided reason is invalid, product was not as described claim is unfounded, or return window has expired
   * - When rejected, the system maintains audit trail through status log entries
   * - The refund request status changes from "pending" to "rejected"
   *
   * ## Relationship to Other Operations
   *
   * - `GET /refund-requests/:requestId` - Retrieve refund request details (pre-execution for review)
   * - `GET /sellers/refund-requests` - List all pending refund requests for the seller (list view)
   * - `POST /orders/:orderId/items/:itemId/refund-request` - Customer creates new refund request
   * - `PUT /refund-requests/:requestId/approve` - Seller approves refund request instead of rejecting
   *
   * @param connection
   * @param requestId Target refund request's unique identifier
   * @param body Rejection reason and request metadata
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Update shopping_mall_order_refund_requests table status to 'rejected' with rejection_reason.
   * Query refund request by ID and verify seller_id matches authenticated seller.
   * Validate refund request status is 'pending' before allowing rejection.
   * Create status log entry in shopping_mall_order_refund_request_logs with new_status='rejected', old_status='pending'.
   * Store rejection_reason in the refund request record.
   * Return updated refund request details with new status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":requestId/reject")
  public async reject(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("requestId")
    requestId: string,
    @TypedBody()
    body: IShoppingMallOrderRefundRequest.IReject,
  ): Promise<void> {
    try {
      return await putShoppingMallSellerRefundRequestsRequestIdReject({
        seller,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
