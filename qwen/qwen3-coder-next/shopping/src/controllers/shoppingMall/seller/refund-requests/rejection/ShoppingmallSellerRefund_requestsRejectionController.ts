import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallOrderRefundRequest } from "../../../../../api/structures/IShoppingMallOrderRefundRequest";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerRefundRequestsRequestIdRejection } from "../../../../../providers/putShoppingMallSellerRefundRequestsRequestIdRejection";

@Controller("/shoppingMall/seller/refund-requests/:requestId/rejection")
export class ShoppingmallSellerRefund_requestsRejectionController {
  /**
   * Seller rejects a refund request for a delivered order item.
   *
   * This endpoint allows sellers to formally reject customer refund requests when the refund criteria are not met or when the seller disputes the refund justification. Upon rejection, the order item status remains unchanged (typically "delivered"), and the refund process is terminated.
   *
   * ## Business Context
   *
   * Refund requests can only be submitted for order items with status "delivered" and must be requested within 7 days of delivery. When a seller rejects a refund request, they must provide a clear rejection reason that explains why the refund is not appropriate.
   *
   * ## Authorization
   *
   * - Only sellers associated with the order item can reject refund requests
   * - The seller must be authenticated and authorized for the specific order
   * - Administrators can force-refund items but typically do not use this rejection endpoint
   *
   * ## Related Operations
   *
   * - POST /refund-requests: Customer initiates refund request
   * - PUT /refund-requests/{requestId}/approval: Seller approves refund request
   * - GET /refund-requests/{requestId}: Retrieve refund request details
   * - GET /refund-requests: List pending refund requests for seller
   *
   * ## Workflow
   *
   * 1. Customer submits refund request for delivered item
   * 2. Seller receives notification of pending refund request
   * 3. Seller reviews the request and decides to reject
   * 4. Seller calls this endpoint with rejection_reason
   * 5. System updates refund request status to "rejected"
   * 6. System logs the rejection in refund request history
   * 7. Customer receives notification of rejection
   *
   * ## Error Conditions
   *
   * - 404 Not Found: Refund request does not exist or seller is not associated
   * - 409 Conflict: Refund request already approved, rejected, or cancelled
   * - 422 Unprocessable Entity: Rejection reason is empty or invalid
   *
   * @param connection
   * @param requestId Refund request identifier (UUID)
   * @param body Seller rejection reason for the refund request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Process seller rejection of a refund request.
   * 1. Retrieve refund request by ID and verify seller association
   * 2. Validate refund request status is 'pending' (not already approved/rejected)
   * 3. Validate rejection_reason is provided and not empty
   * 4. Update refund request status to 'rejected'
   * 5. Set rejection_reason to the provided value
   * 6. Create refund request status log entry with 'rejected' status
   * 7. Return updated refund request with rejection details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async reject(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("requestId")
    requestId: string,
    @TypedBody()
    body: IShoppingMallOrderRefundRequest.IRejection,
  ): Promise<IShoppingMallOrderRefundRequest> {
    try {
      return await putShoppingMallSellerRefundRequestsRequestIdRejection({
        seller,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
