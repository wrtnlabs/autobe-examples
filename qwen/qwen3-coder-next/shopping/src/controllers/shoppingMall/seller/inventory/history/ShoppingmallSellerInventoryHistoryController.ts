import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallInventoryHistory } from "../../../../../api/structures/IPageIShoppingMallInventoryHistory";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerInventoryHistoryVariantId } from "../../../../../providers/getShoppingMallSellerInventoryHistoryVariantId";
import { patchShoppingMallSellerInventoryHistory } from "../../../../../providers/patchShoppingMallSellerInventoryHistory";

@Controller("/shoppingMall/seller/inventory/history")
export class ShoppingmallSellerInventoryHistoryController {
  /**
   * This endpoint is designed for inventory history management but there is no valid PATCH operation for inventory history records as they are immutable audit trails. Inventory history records are created automatically by system operations when inventory changes occur through dedicated POST endpoints for restocking and adjustments. The PATCH method is inappropriate for this endpoint as it would imply modifying historical records, which contradicts the immutable audit trail design principle.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification The PATCH /inventory/history endpoint is not a valid operation because inventory history records are immutable audit trails. When inventory changes occur through POST /sellers/me/inventory (restock or adjustment), the system automatically creates immutable history records. This endpoint should be removed or the user should be directed to use POST /sellers/me/inventory for inventory adjustments.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async invalidEndpoint(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<void> {
    try {
      return await patchShoppingMallSellerInventoryHistory({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve inventory history records for a specific product variant.
   *
   * This operation provides a complete audit trail of all inventory transactions for a specified product variant. The history includes restocking, sales, adjustments, cancellations, and refunds with detailed information about each transaction including quantity changes, reasons, and timestamps.
   *
   * The operation returns a paginated list of inventory history records sorted chronologically with newest first, allowing users to track the complete inventory movement history for the specified variant.
   *
   * @param connection
   * @param variantId Target product variant's ID. References shopping_mall_product_variants.id.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query inventory_histories table for the specified variant ID.
   * Filter records where shopping_mall_product_variant_id equals the path parameter.
   * Order results by created_at descending (newest first).
   * Apply pagination with configurable page and limit parameters.
   * Return paginated result with total count and data array.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":variantId")
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("variantId")
    variantId: string,
  ): Promise<IPageIShoppingMallInventoryHistory> {
    try {
      return await getShoppingMallSellerInventoryHistoryVariantId({
        seller,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
