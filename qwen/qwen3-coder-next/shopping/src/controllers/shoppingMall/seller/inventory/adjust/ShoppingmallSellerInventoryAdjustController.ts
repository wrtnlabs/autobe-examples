import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallInventoryHistory } from "../../../../../api/structures/IShoppingMallInventoryHistory";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { postShoppingMallSellerInventoryAdjust } from "../../../../../providers/postShoppingMallSellerInventoryAdjust";

@Controller("/shoppingMall/seller/inventory/adjust")
export class ShoppingmallSellerInventoryAdjustController {
  /**
   * Manually adjust product variant inventory stock quantities.
   *
   * This API endpoint allows authorized sellers and administrators to manually adjust the stock quantity of product variants for various business reasons including restocking from suppliers, recording losses or damages, and correcting inventory discrepancies.
   *
   * The operation creates a new inventory history record that permanently tracks the stock change with full audit information including the adjustment reason, quantity change, timestamp, and the actor who performed the adjustment.
   *
   * All inventory adjustments are logged in the shopping_mall_inventory_histories table with reason codes that categorize the type of adjustment performed.
   *
   * Refer to IShoppingMallInventoryHistory.ICreate schema for request body structure.
   *
   * @param connection
   * @param body Inventory adjustment request with variant reference, quantity change, and reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Create inventory history record for manual stock adjustment.
   * 1. Validate authentication and authorization (seller or admin)
   * 2. Validate variant exists and belongs to seller (for sellers)
   * 3. Validate reason code is one of: 'restock', 'adjustment', 'loss', 'correction'
   * 4. Validate quantity is non-zero integer
   * 5. Create inventory history record with positive/negative quantity
   * 6. Update current stock quantity in shopping_mall_variant_stocks
   * 7. Return successful response with inventory history details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async adjustInventory(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallInventoryHistory.ICreate,
  ): Promise<void> {
    try {
      return await postShoppingMallSellerInventoryAdjust({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
