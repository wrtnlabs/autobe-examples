import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallInventoryHistory } from "../../../../../api/structures/IShoppingMallInventoryHistory";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { postShoppingMallSellerInventoryAddVariantId } from "../../../../../providers/postShoppingMallSellerInventoryAddVariantId";

@Controller("/shoppingMall/seller/inventory/add/:variantId")
export class ShoppingmallSellerInventoryAddController {
  /**
   * Add inventory stock to a product variant.
   *
   * This operation allows sellers to increase the stock quantity of a specific product variant by recording a positive inventory history record. This is typically used when receiving supplier shipments, returning items from customers, or manually adding stock to the inventory.
   *
   * The system validates that the quantity is positive and creates a permanent inventory history record with the specified reason code. The current stock quantity for the variant is automatically updated by summing all inventory history records.
   *
   * @param connection
   * @param variantId Target variant ID
   * @param body Inventory restocking request with quantity and reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Process inventory restocking request for variant.
   *
   * 1. Validate variant exists and belongs to authenticated seller
   * 2. Validate quantity is positive integer
   * 3. Validate reason is one of: 'order', 'order_cancellation', 'refund', 'restock', 'adjustment', 'loss'
   * 4. Create inventory history record with positive quantity
   * 5. Update variant's stock_quantity by adding quantity_change
   * 6. Return created inventory history record with full details
   * 7. Log audit trail for compliance
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async addInventory(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("variantId")
    variantId: string,
    @TypedBody()
    body: IShoppingMallInventoryHistory.ICreate,
  ): Promise<IShoppingMallInventoryHistory> {
    try {
      return await postShoppingMallSellerInventoryAddVariantId({
        seller,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
