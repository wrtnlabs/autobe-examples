import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallVariantStocks } from "../../../../api/structures/IShoppingMallVariantStocks";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerVariantStocksVariantId } from "../../../../providers/getShoppingMallSellerVariantStocksVariantId";
import { patchShoppingMallSellerVariantStocksVariantId } from "../../../../providers/patchShoppingMallSellerVariantStocksVariantId";

@Controller("/shoppingMall/seller/variant-stocks/:variantId")
export class ShoppingmallSellerVariant_stocksController {
  /**
   * Retrieve detailed stock information for a specific product variant.
   *
   * This endpoint provides current stock availability and tracking information for a single product variant. The stock information includes the current quantity available for sale and timestamps for when the stock record was created and last updated.
   *
   * This operation is useful for checking real-time stock levels before adding items to cart or during checkout processing.
   *
   * **Seller Ownership Validation**: Sellers can only view stock information for variants belonging to their own products. The system automatically filters to ensure sellers cannot access other sellers' variant stock data.
   *
   * @param connection
   * @param variantId Target variant's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_variant_stocks table by product_variant_id foreign key. Returns current_quantity, created_at, and updated_at fields. Uses Prisma's findUnique or findFirst with where clause on product_variant_id.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("variantId")
    variantId: string,
  ): Promise<IShoppingMallVariantStocks> {
    try {
      return await getShoppingMallSellerVariantStocksVariantId({
        seller,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update stock quantity for a product variant through inventory adjustment.
   *
   * This operation records a stock adjustment (either restocking or subtraction) in the inventory history system. Stock quantities are not directly updated but are calculated as the sum of all inventory history records for each variant. This ensures complete audit trail and prevents inconsistent stock states.
   *
   * ## Business Rules
   *
   * - Stock adjustments must specify a quantity (positive for restocking, negative for subtraction)
   * - Stock reason must be provided (e.g., "supplier shipment", "damage", "loss")
   * - Stock cannot go negative through this operation
   * - All adjustments create immutable inventory history records
   * - Product variants must exist and be owned by the requesting seller
   *
   * ## Security Considerations
   *
   * - Only sellers can adjust stock for their own products
   * - Administrators can adjust stock for any variant
   * - All adjustments are logged for audit purposes
   *
   * @param connection
   * @param variantId Target product variant's unique identifier (UUID)
   * @param body Stock adjustment details including quantity change and reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Process inventory adjustment for a product variant.
   * 1. Validate variant exists and belongs to requesting seller (unless admin)
   * 2. Create inventory history record with positive/negative quantity change
   * 3. Update current stock quantity in shopping_mall_variant_stocks
   * 4. Record adjustment timestamp and reason
   * 5. Return updated stock information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async adjust(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("variantId")
    variantId: string,
    @TypedBody()
    body: IShoppingMallVariantStocks.IAdjustment,
  ): Promise<void> {
    try {
      return await patchShoppingMallSellerVariantStocksVariantId({
        seller,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
