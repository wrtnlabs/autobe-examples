import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSellerSetting } from "../../../../api/structures/IShoppingMallSellerSetting";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerSettings } from "../../../../providers/putShoppingMallSellerSettings";

@Controller("/shoppingMall/seller/settings")
export class ShoppingmallSellerSettingsController {
  /**
   * Update seller shop configuration settings
   *
   * This operation allows sellers to modify their storefront configuration settings including visual theme, layout preferences, and display options that customize how their shop appears to customers.
   *
   * The seller's identity is determined from the authenticated session, so the operation updates the seller's own shopping_mall_seller_settings record. The operation updates all configurable settings in a single request, allowing sellers to customize their entire storefront appearance at once.
   *
   * Only sellers with active accounts can modify their settings. Administrators cannot modify seller settings through this endpoint.
   *
   * This operation is related to GET /api/sellers/profile which retrieves the current seller profile and settings information.
   *
   * @param connection
   * @param body Seller shop configuration settings to update
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Update seller shopping_mall_seller_settings record identified by seller ID from JWT. Accept all configurable settings fields and update them in a single transaction. Validate that all theme_mode values are in the allowed set. Return updated settings record with all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSellerSetting.IUpdate,
  ): Promise<IShoppingMallSellerSetting> {
    try {
      return await putShoppingMallSellerSettings({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
