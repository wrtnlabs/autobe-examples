@Controller("/shoppingMall/seller/cancel-requests/:requestId/rejection")
export class ShoppingmallSellerCancel_requestsRejectionController {
  /**
   * Reject a customer's cancellation request for an order item.
   *
   * This endpoint allows sellers to formally reject cancellation requests submitted by customers. When a seller rejects a cancellation request, the order item continues with its current status (typically "paid" or "shipped") and no refund or inventory restoration occurs.
   *
   * ## Security and Authorization
   *
   * Only the seller who owns the product in the order item can reject cancellation requests. The system validates that the authenticated seller has authority over the order item associated with the cancellation request.
   *
   * ## Cancellation Request Lifecycle
   *
   * When a seller rejects a cancellation request:
   *
   * - The cancellation request status changes from "pending" to "rejected"
   * - The rejection_reason field is populated with the seller's explanation (required)
   * - The responded_at timestamp is set to the current timestamp
   * - The order item status remains unchanged
   * - No inventory restoration occurs
   * - No refund processing is triggered
   *
   * ## Related Operations
   *
   * - `PUT /cancel-requests/{requestId}/approval` - Approve a cancellation request
   * - `GET /orders/:orderId/items/:itemId/cancellation-request` - View cancellation request details
   *
   * ## Business Rules
   *
   * - Cancellation requests can only be rejected while status is "pending"
   * - Once rejected, the cancellation request state is locked and cannot be modified
   * - Sellers must provide a rejection reason when rejecting
   * - Rejection notifications should be sent to the customer
   *
   * @param connection
   * @param requestId Target cancellation request's unique identifier
   * @param body Rejection response with reason (required). Must include a detailed explanation for why the cancellation is being rejected.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Update shopping_mall_order_cancellation_requests table to reject the cancellation request.
   *
   * 1. Find the cancellation request by id withFOR UPDATE locking
   * 2. Validate the request status is "pending"
   * 3. Validate the authenticated seller owns the order item
   * 4. Update status to "rejected" and populate rejection_reason
   * 5. Set responded_at to current timestamp
   * 6. Return the updated cancellation request record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async reject(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("requestId")
    requestId: string,
    @TypedBody()
    body: IShoppingMallOrderCancellationRequest.IUpdate,
  ): Promise<IShoppingMallOrderCancellationRequest> {
    try {
      return await putShoppingMallSellerCancelRequestsRequestIdRejection({
        seller,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
