import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallShipment } from "../../../../../api/structures/IShoppingMallShipment";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerShipmentsShipmentIdItems } from "../../../../../providers/patchShoppingMallSellerShipmentsShipmentIdItems";

@Controller("/shoppingMall/seller/shipments/:shipmentId/items")
export class ShoppingmallSellerShipmentsItemsController {
  /**
   * Add order items to an existing shipment
   *
   * This operation allows sellers to add additional order items to a shipment that has already been created. This flexibility supports various shipping scenarios where sellers may need to:
   *
   * - Bundle multiple order items into a single shipment
   * - Add items to an existing shipment if they were missed initially
   * - Split orders across multiple shipments as needed
   * - Manage partial shipments for complex orders
   *
   * The shipment must be in a state that allows item additions (typically before items are shipped). This operation supports the seller's control over their own shipping processes while maintaining the relationship between shipments and order items.
   *
   * ### Security and Authorization
   *
   * Only the seller who owns the order items being added can perform this operation. The system validates:
   *
   * - The shipment belongs to the seller attempting the operation
   * - The order items being added belong to the same seller
   * - The shipment is in an appropriate state for item additions
   *
   * ### Related Operations
   *
   * - `GET /shipments/{shipmentId}` - Retrieve shipment details including current items
   * - `GET /shipments` - List shipments for the seller
   * - `PUT /shipments/{shipmentId}` - Update shipment information (tracking, status)
   * - `DELETE /shipments/{shipmentId}` - Cancel a shipment
   *
   * @param connection
   * @param shipmentId Shipment ID to add items to
   * @param body List of order item IDs to add to the shipment
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Add order items to an existing shipment by creating records in the shopping_mall_shipment_items junction table.
   * 1. Validate shipment exists and belongs to the seller
   * 2. Validate each order item exists and belongs to the same seller
   * 3. Validate shipment state allows item additions (not already shipped or delivered)
   * 4. Create shipment_item records for each order item
   * 5. Update shipment's updated_at timestamp
   * 6. Return updated shipment with all items
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async addItems(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string,
    @TypedBody()
    body: IShoppingMallShipment.ICreateItem,
  ): Promise<IShoppingMallShipment.ISummary> {
    try {
      return await patchShoppingMallSellerShipmentsShipmentIdItems({
        seller,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
