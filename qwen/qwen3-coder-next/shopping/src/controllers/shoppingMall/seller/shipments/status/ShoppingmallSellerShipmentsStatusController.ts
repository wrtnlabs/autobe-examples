import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallShipment } from "../../../../../api/structures/IShoppingMallShipment";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerShipmentsShipmentIdStatus } from "../../../../../providers/patchShoppingMallSellerShipmentsShipmentIdStatus";

@Controller("/shoppingMall/seller/shipments/:shipmentId/status")
export class ShoppingmallSellerShipmentsStatusController {
  /**
   * Update the status of a shipment.
   *
   * This operation allows sellers or administrators to update the status of a shipment, creating a new status log entry in the history. The shipment status can be changed from pending to shipped, in_transit, out_for_delivery, delivered, or cancelled. Each status change creates an immutable record in the shipment status logs table for audit trail and compliance purposes.
   *
   * ## Business Logic
   *
   * - Status transitions must follow valid business rules
   * - Only authorized users (shipment seller or administrators) can update status
   * - The operation creates both a new status log entry and updates the shipment's current status
   * - Automatic delivery confirmation cannot override manual status changes
   *
   * ## Status Values
   *
   * - `pending`: Waiting for processing
   * - `shipped`: Out for delivery
   * - `in_transit`: Moving between facilities
   * - `out_for_delivery`: Final delivery attempt
   * - `delivered`: Successfully delivered
   * - `cancelled`: Shipment cancelled
   *
   * ## Related Operations
   *
   * - `GET /shipments/{shipmentId}`: Retrieve shipment details including status history
   * - `GET /shipments/{shipmentId}/status`: Retrieve current shipment status
   *
   * ## Authorization
   *
   * - Sellers can update status for their own shipments
   * - Administrators can update status for any shipment
   *
   * @param connection
   * @param shipmentId Target shipment's unique identifier
   * @param body Status update information including new status value and optional notes
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Update shipment status by creating a new status log entry.
   * 1. Validate shipment exists and belongs to the user (if seller)
   * 2. Validate status transition is allowed
   * 3. Create new status log entry with provided status and status_message
   * 4. Update shipment status to the new value
   * 5. Set shipped_at timestamp if status changes to 'shipped'
   * 6. Set auto_confirmed_at if status changes to 'delivered'
   * 7. Return success response without body
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updateStatus(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string,
    @TypedBody()
    body: IShoppingMallShipment.IRequest,
  ): Promise<void> {
    try {
      return await patchShoppingMallSellerShipmentsShipmentIdStatus({
        seller,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
