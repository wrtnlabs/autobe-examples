import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSalesAnalytic } from "../../../../../api/structures/IShoppingMallSalesAnalytic";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerAnalyticsSales } from "../../../../../providers/getShoppingMallSellerAnalyticsSales";

@Controller("/shoppingMall/seller/analytics/sales")
export class ShoppingmallSellerAnalyticsSalesController {
  /**
   * Retrieve comprehensive sales analytics and statistics for the shopping mall platform.
   *
   * This endpoint provides super administrators with aggregated sales data, including total sales amounts, order volume statistics, average order values, and sales trends over time. The analytics help administrators monitor platform performance, identify business trends, and make data-driven decisions.
   *
   * The endpoint supports date range filtering to analyze specific time periods and provides both overall platform metrics and breakdowns by various dimensions including seller performance and category sales.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query sales analytics data from order and payment records.
   * Filter by date range parameters (start_date, end_date) for time-based analysis.
   * Calculate total sales amount, number of orders, and average order value.
   * Group data by time period (daily, weekly, monthly) as needed.
   * Return aggregated metrics including sales trends and performance indicators.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async salesAnalytics(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IShoppingMallSalesAnalytic> {
    try {
      return await getShoppingMallSellerAnalyticsSales({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
