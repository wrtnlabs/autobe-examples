import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallProduct } from "../../../../../api/structures/IPageIShoppingMallProduct";
import { IShoppingMallProduct } from "../../../../../api/structures/IShoppingMallProduct";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerAnalyticsProducts } from "../../../../../providers/patchShoppingMallSellerAnalyticsProducts";

@Controller("/shoppingMall/seller/analytics/products")
export class ShoppingmallSellerAnalyticsProductsController {
  /**
   * Retrieve comprehensive product analytics and performance metrics.
   *
   * This endpoint provides aggregated product performance data including view statistics, conversion rates, inventory turnover metrics, price competitiveness analysis, and customer rating trends. The analytics data helps administrators monitor product performance, identify trending products, and make data-driven business decisions.
   *
   * ## Data Sources and Aggregation
   *
   * Product analytics data is aggregated from multiple sources:
   * - Product views and clicks from product browsing activity
   * - Order items from completed purchases
   * - Inventory history records for stock movement analysis
   * - Customer reviews and ratings
   * - Shipping and delivery performance
   *
   * ## Metrics Included
   *
   * - **View Metrics**: Total views, unique viewers, view-to-purchase conversion
   * - **Sales Metrics**: Units sold, revenue generated, average order value
   * - **Inventory Metrics**: Turnover rate, stock levels, restocking frequency
   * - **Customer Feedback**: Average rating, review count, rating trends
   * - **Performance Trends**: Day-over-day, week-over-week, month-over-month changes
   *
   * @param connection
   * @param body Analytics query parameters for filtering and sorting
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query product analytics data by joining product performance metrics from multiple sources.
   * Calculate view counts from product page views, conversion rates from order items, inventory turnover from history records.
   * Aggregate customer ratings from reviews and calculate performance trends over time periods.
   * Return paginated results with comprehensive product performance metrics.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProduct.IRequest,
  ): Promise<IPageIShoppingMallProduct.ISummary> {
    try {
      return await patchShoppingMallSellerAnalyticsProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
