import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallOrderCancellationRequest } from "../../../../api/structures/IPageIShoppingMallOrderCancellationRequest";
import { IShoppingMallOrderCancellationRequest } from "../../../../api/structures/IShoppingMallOrderCancellationRequest";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerCancellationRequests } from "../../../../providers/patchShoppingMallSellerCancellationRequests";
import { putShoppingMallSellerCancellationRequestsRequestIdApprove } from "../../../../providers/putShoppingMallSellerCancellationRequestsRequestIdApprove";
import { putShoppingMallSellerCancellationRequestsRequestIdReject } from "../../../../providers/putShoppingMallSellerCancellationRequestsRequestIdReject";

@Controller("/shoppingMall/seller/cancellation-requests")
export class ShoppingmallSellerCancellation_requestsController {
  /**
   * Retrieve a paginated list of cancellation requests for seller's order items.
   *
   * This operation allows sellers to view all cancellation requests associated with their products. Sellers can filter requests by status (pending, approved, rejected) and view detailed information about each request including the customer, order item, reason, and response status.
   *
   * The operation supports comprehensive search and filtering capabilities including date ranges, order information, and response status to help sellers efficiently manage cancellation workflows. The results are populated from the shopping_mall_order_cancellation_requests table, which tracks the complete lifecycle of cancellation requests from creation through seller response.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for cancellation requests
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query order_cancellation_requests table with seller authorization.
   * Filter by seller's products through order items.
   * Support status filtering (pending/approved/rejected), date range filtering, and order search.
   * Join with customers, order_items, and products to populate request details.
   * Return paginated results with complete cancellation request information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallOrderCancellationRequest.IRequest,
  ): Promise<IPageIShoppingMallOrderCancellationRequest.ISummary> {
    try {
      return await patchShoppingMallSellerCancellationRequests({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Approve a pending cancellation request for an order item.
   *
   * This endpoint allows sellers to approve a customer's cancellation request for an order item. When a cancellation request is approved, the system will cancel the order item, restore stock quantities for the purchased variant, and process the refund.
   *
   * ## Business Logic
   *
   * - Only cancellation requests with status "pending" can be approved
   * - The requesting customer receives notification when the request is approved
   * - Stock quantities are automatically restored via inventory history with reason "cancellation"
   * - A refund transaction is initiated for the cancelled item
   *
   * ## Authorization
   *
   * - Seller actors can approve cancellation requests for their own products
   * - The seller must be the owner of the product associated with the order item
   * - Sellers cannot approve cancellation requests for other sellers' products
   *
   * ## Related Operations
   *
   * - After approval, the order item status changes to "cancelled"
   * - Related: POST /orders/:orderId/items/:itemId/cancel-request (customer creates request)
   * - Related: PUT /cancellation-requests/:requestId/reject (seller rejects request)
   *
   * @param connection
   * @param requestId The unique identifier of the cancellation request to approve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Process cancellation request approval for sellers:
   * 1. Retrieve cancellation request by ID from path parameter
   * 2. Validate request status is "pending"
   * 3. Verify seller owns the product (through order item relationship)
   * 4. Create cancellation request log with from_status: "pending", to_status: "approved"
   * 5. Update cancellation request status to "approved" and set responded_at timestamp
   * 6. Restore stock quantity for the order item's variant
   * 7. Create inventory history record with reason "cancellation"
   * 8. Initiate refund transaction for the cancelled item
   * 9. Return the updated cancellation request with full details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":requestId/approve")
  public async approve(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("requestId")
    requestId: string,
  ): Promise<IShoppingMallOrderCancellationRequest> {
    try {
      return await putShoppingMallSellerCancellationRequestsRequestIdApprove({
        seller,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Reject a customer's cancellation request with a detailed rejection reason.
   *
   * This operation allows sellers to formally reject cancellation requests submitted by customers for order items. The seller must provide a clear rejection reason explaining why the cancellation is not approved.
   *
   * The cancellation request status transitions from "pending" to "rejected", and the system records the rejection in the audit log history. The order item continues normal processing as if no cancellation request was ever made.
   *
   * This operation is part of the complete cancellation workflow that includes:
   * - GET /cancellation-requests for listing pending requests
   * - PUT /cancellation-requests/{requestId}/approve for approval
   * - POST /cancellation-requests for creating new requests (customer-side)
   *
   * @param connection
   * @param requestId The unique identifier of the cancellation request to reject
   * @param body Rejection details including the reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Update cancellation request status to rejected.
   *
   * Process:
   * 1. Load cancellation request by ID
   * 2. Validate request status is 'pending'
   * 3. Validate seller owns the order item
   * 4. Update request status to 'rejected'
   * 5. Set rejection_reason from request body
   * 6. Create cancellation request log entry
   * 7. Update responded_at timestamp
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":requestId/reject")
  public async reject(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("requestId")
    requestId: string,
    @TypedBody()
    body: IShoppingMallOrderCancellationRequest.IReject,
  ): Promise<void> {
    try {
      return await putShoppingMallSellerCancellationRequestsRequestIdReject({
        seller,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
