import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallShipment } from "../../../../../../api/structures/IPageIShoppingMallShipment";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerSellerShipmentsPending } from "../../../../../../providers/getShoppingMallSellerSellerShipmentsPending";

@Controller("/shoppingMall/seller/seller/shipments/pending")
export class ShoppingmallSellerSellerShipmentsPendingController {
  /**
   * Retrieve a list of pending shipments for the seller that require tracking information.
   *
   * This endpoint provides sellers with access to their pending shipments that have been created but do not yet have tracking information entered. Sellers can use this list to manage their shipping workflow and add tracking details to complete the shipment process.
   *
   * The endpoint returns paginated results with essential shipment information including order item details, shipping address, and current shipment status. This supports the seller's shipping management workflow where they need to track which shipments are pending tracking information.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_shipments table to find shipments with status 'pending' (waiting for tracking information) for the current seller. Join with shopping_mall_order_items to get order item details. Apply pagination and filtering based on seller context. Return paginated list of shipment summaries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IPageIShoppingMallShipment.ISummary> {
    try {
      return await getShoppingMallSellerSellerShipmentsPending({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
