import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallReviewSnapshot } from "../../../../../../api/structures/IPageIShoppingMallReviewSnapshot";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerSellerReviewsReviewIdSnapshots } from "../../../../../../providers/getShoppingMallSellerSellerReviewsReviewIdSnapshots";

@Controller("/shoppingMall/seller/seller/reviews/:reviewId/snapshots")
export class ShoppingmallSellerSellerReviewsSnapshotsController {
  /**
   * Retrieve complete history of changes to a specific customer review.
   *
   * This operation provides sellers with historical snapshots of reviews for products they manage. Sellers can view the complete historical state of reviews to understand how customer feedback has evolved over time, enabling them to provide informed and contextually appropriate responses.
   *
   * The system preserves complete snapshots of reviews at each modification point, including the rating, text content, and timestamp of each change. This creates an immutable audit trail that supports dispute resolution and historical analysis.
   *
   * Sellers can access review snapshots for products associated with their shop, providing transparency into the review history and enabling well-informed seller responses.
   *
   * @param connection
   * @param reviewId Target review's unique identifier in UUID format. This is the shopping_mall_reviews.id of the review whose snapshots you want to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_review_snapshots table for all snapshots of specified review.
   * Filter by shopping_mall_review_id matching the provided reviewId path parameter.
   * Order results by created_at timestamp in descending order (newest first).
   * Return paginated results with configurable page size and offset.
   * Include all snapshot fields: id, shopping_mall_review_id, customer_id, product_id, rating, text, edited_at, created_at.
   * Return complete relationship data for customer and product references.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("reviewId")
    reviewId: string,
  ): Promise<IPageIShoppingMallReviewSnapshot.ISummary> {
    try {
      return await getShoppingMallSellerSellerReviewsReviewIdSnapshots({
        seller,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
