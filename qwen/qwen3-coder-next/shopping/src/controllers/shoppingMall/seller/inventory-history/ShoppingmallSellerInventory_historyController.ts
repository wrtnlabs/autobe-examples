@Controller("/shoppingMall/seller/inventory-history")
export class ShoppingmallSellerInventory_historyController {
  /**
   * Retrieve a filtered and paginated list of inventory history records.
   *
   * This operation provides comprehensive inventory tracking capabilities allowing sellers and administrators to view the complete history of stock quantity changes for product variants. Each record shows the quantity change (positive for restocking, negative for deductions), the reason for the change, and timestamp information.
   *
   * The system creates inventory history records for:
   * - Order placements (negative quantities)
   * - Order cancellations (positive quantities)
   * - Order refunds (positive quantities)
   * - Manual restocking (positive quantities)
   * - Inventory adjustments (positive or negative quantities)
   * - Stock losses or damages (negative quantities)
   *
   * This audit trail enables complete stock reconciliation and analysis of inventory movement patterns over time.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for inventory history
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_inventory_histories table with pagination and filtering.
   * Apply search filters on variant ID, seller ID, order item ID, reason codes, and date range.
   * Join with related entities for complete context (variant details, seller information, order item details).
   * Return paginated results with summary information optimized for history display.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallInventoryHistory.IRequest,
  ): Promise<IPageIShoppingMallInventoryHistory.ISummary> {
    try {
      return await patchShoppingMallSellerInventoryHistory({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
