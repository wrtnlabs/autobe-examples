import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSellerStatistic } from "../../../../api/structures/IShoppingMallSellerStatistic";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerDashboard } from "../../../../providers/getShoppingMallSellerDashboard";

@Controller("/shoppingMall/seller/dashboard")
export class ShoppingmallSellerDashboardController {
  /**
   * Retrieve seller dashboard summary statistics.
   *
   * This operation provides a quick overview of the seller's shop performance by returning aggregated statistics including total active products, total order items, and pending request counts.
   *
   * The statistics are pre-calculated and stored in the shopping_mall_seller_statistics table, providing real-time metrics without expensive database queries.
   *
   * ### Security Considerations
   * This operation requires seller authentication. Only the authenticated seller can access their own statistics. No additional authorization roles or permissions are required beyond the seller role.
   *
   * ### Relationship to Database Entities
   * The operation retrieves data from the shopping_mall_seller_statistics table, which contains pre-calculated summary metrics for each seller's shop. This approach avoids expensive aggregate queries and provides fast access to dashboard statistics.
   *
   * ### Business Logic
   * - The statistics are calculated automatically by the system
   * - Only the authenticated seller can view their own statistics
   * - The operation returns a summary view optimized for dashboard display
   * - No pagination or filtering is provided as this is a single summary record
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_seller_statistics table for the current seller's statistics.
   * Return only the summary fields: total_products, total_order_items, pending_cancellation_requests, pending_refund_requests.
   * Use the authenticated seller's ID to filter the record.
   * Return the statistics as a simple JSON object with the four metrics.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IShoppingMallSellerStatistic.IDashboard> {
    try {
      return await getShoppingMallSellerDashboard({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
