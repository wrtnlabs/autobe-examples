import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallInventoryHistory } from "../../../../../api/structures/IShoppingMallInventoryHistory";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { postShoppingMallSellerInventoryHistoriesAdjustment } from "../../../../../providers/postShoppingMallSellerInventoryHistoriesAdjustment";

@Controller("/shoppingMall/seller/inventory-histories/adjustment")
export class ShoppingmallSellerInventory_historiesAdjustmentController {
  /**
   * Manually adjust inventory stock quantities for product variants.
   *
   * This operation allows sellers to perform manual inventory adjustments including restocking (adding stock), deductions (removing stock for losses), or corrections (adjusting system discrepancies). Each adjustment creates a permanent inventory history record with full audit trail.
   *
   * The system supports multiple adjustment types through the reason field, which categorizes the business justification for the stock change. Positive quantity values add stock to inventory, while negative quantity values deduct from available stock.
   *
   * Security Considerations: Only authenticated sellers can perform inventory adjustments. The system automatically records which seller performed the adjustment and when, ensuring complete audit trail for inventory modifications.
   *
   * @param connection
   * @param body Inventory adjustment request containing variant identifier, quantity change, and adjustment reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Process inventory adjustment request by creating inventory history records and updating variant stock quantities.
   * 1. Validate requested variant belongs to seller's products
   * 2. Validate quantity is a non-zero integer
   * 3. Validate reason is one of allowed values: 'restock', 'loss', 'adjustment'
   * 4. Create inventory history record with negative quantity for deduction or positive for restock
   * 5. Update variant stock quantity by adding quantity_change
   * 6. Create product snapshot for audit trail
   * 7. Return success with created inventory history record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async adjust(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallInventoryHistory.ICreate,
  ): Promise<IShoppingMallInventoryHistory> {
    try {
      return await postShoppingMallSellerInventoryHistoriesAdjustment({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
