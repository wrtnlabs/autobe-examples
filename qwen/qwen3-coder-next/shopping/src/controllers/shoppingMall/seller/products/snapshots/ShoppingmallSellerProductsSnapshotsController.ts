import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallProductSnapshot } from "../../../../../api/structures/IPageIShoppingMallProductSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerProductsProductIdSnapshots } from "../../../../../providers/getShoppingMallSellerProductsProductIdSnapshots";

@Controller("/shoppingMall/seller/products/:productId/snapshots")
export class ShoppingmallSellerProductsSnapshotsController {
  /**
   * Retrieve complete history of all snapshots for a specific product.
   *
   * This operation provides comprehensive version history for product auditing, dispute resolution, and compliance purposes. Each snapshot captures the complete product state (name, description, category, price, images, variants) at a specific point in time.
   *
   * The snapshots are returned in reverse chronological order with newest snapshots appearing first. This endpoint is essential for administrators to track product changes over time and for sellers to review their product history.
   *
   * All snapshots are preserved permanently regardless of product deletion status, ensuring complete audit trail for legal and business purposes.
   *
   * @param connection
   * @param productId Target product's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_product_snapshots table filtered by shopping_mall_product_id. Order by snapshot_timestamp descending (newest first) and snapshot_version descending for version ordering. Return the most recent snapshot object with all fields as they were captured at snapshot time.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
  ): Promise<IPageIShoppingMallProductSnapshot.ISummary> {
    try {
      return await getShoppingMallSellerProductsProductIdSnapshots({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
