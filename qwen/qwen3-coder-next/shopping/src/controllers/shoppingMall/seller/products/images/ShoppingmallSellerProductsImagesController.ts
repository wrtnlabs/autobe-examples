import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallProductImage } from "../../../../../api/structures/IShoppingMallProductImage";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerProductsProductIdImagesImageId } from "../../../../../providers/deleteShoppingMallSellerProductsProductIdImagesImageId";
import { getShoppingMallSellerProductsProductIdImages } from "../../../../../providers/getShoppingMallSellerProductsProductIdImages";
import { postShoppingMallSellerProductsProductIdImages } from "../../../../../providers/postShoppingMallSellerProductsProductIdImages";
import { putShoppingMallSellerProductsProductIdImages } from "../../../../../providers/putShoppingMallSellerProductsProductIdImages";

@Controller("/shoppingMall/seller/products/:productId/images")
export class ShoppingmallSellerProductsImagesController {
  /**
   * Retrieve all images for a specific product.
   *
   * This endpoint returns all images associated with the specified product, ordered by their display order (sort_order). The images are presented in the sequence they should be displayed in the product gallery or image carousel.
   *
   * This operation is used by customers viewing product details to see all available product images, including the main thumbnail and additional product photos uploaded by the seller.
   *
   * @param connection
   * @param productId Product ID (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_product_images table filtered by shopping_mall_product_id.
   * Return all images ordered by sort_order ascending.
   * Return image URL and sort order for each image.
   * Validate product exists and is not deleted before retrieving images.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
  ): Promise<IShoppingMallProductImage> {
    try {
      return await getShoppingMallSellerProductsProductIdImages({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Upload images to a product.
   *
   * This operation allows sellers to upload multiple images to their product gallery. The uploaded images are associated with the specified product and become part of the product's image collection.
   *
   * **Image Handling:**
   * - Sellers can upload multiple images in a single batch operation
   * - The first image in the upload becomes the main thumbnail for product listings
   * - Images are validated for format and size before storage
   * - Image order can be changed after upload using the reorder endpoint
   *
   * **Security Considerations:**
   * - Only authenticated sellers can upload images to their own products
   * - Image formats are validated (JPEG, PNG, WebP)
   * - File size limits are enforced
   * - Products must exist and belong to the authenticated seller
   *
   * **Related Operations:**
   * - After uploading images, sellers may need to reorder them using the reorder endpoint
   * - The first image automatically becomes the main thumbnail for product displays
   * - Product snapshots are created when images are uploaded to maintain history
   *
   * @param connection
   * @param productId Target product's ID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Process image upload request for product:
   * 1. Validate product exists and belongs to authenticated seller
   * 2. Extract image files from multipart/form-data request body
   * 3. Validate each image format (JPEG, PNG, WebP) and size
   * 4. Store images in appropriate storage system
   * 5. Create product_image records with order index
   * 6. Set first image as main thumbnail
   * 7. Create product snapshot for audit trail
   * 8. Return image URLs for uploaded images
   *
   * Business rules:
   * - Product must belong to authenticated seller
   * - Maximum image count: 10 per upload
   * - Maximum file size: 5MB per image
   * - Required formats: JPEG, PNG, WebP
   * - Minimum dimensions: 100x100 pixels
   * - Maximum dimensions: 5000x5000 pixels
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async upload(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
  ): Promise<void> {
    try {
      return await postShoppingMallSellerProductsProductIdImages({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Reorder product images for a specific product
   *
   * This endpoint allows sellers to change the display order of their product images. The image gallery will be reorganized according to the order provided in the request body.
   *
   * **Security & Authorization**:
   * - Only the product owner (seller) can reorder images
   * - The system validates that the seller owns the product before allowing reordering
   * - All reordering actions are logged for audit trail purposes
   *
   * **Business Logic**:
   * - The first image ID in the array will be assigned sort_order = 1
   * - Each subsequent image gets incremented sort_order value
   * - The product's main thumbnail will automatically update to the first image in the new order
   * - All image reorderings are recorded in product snapshots for historical tracking
   *
   * @param connection
   * @param productId Target product's ID
   * @param body New order of image IDs for the product
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Update product image sort_order values based on provided ID array. Query all images for the product, iterate through the provided order array, and update each image's sort_order field accordingly. Create product snapshot after reordering to preserve the state before changes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async reorder(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IShoppingMallProductImage.IReorder,
  ): Promise<void> {
    try {
      return await putShoppingMallSellerProductsProductIdImages({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific product image from a product.
   *
   * This operation permanently removes a product image from the product's image collection. When the main thumbnail (first image) is deleted, the next image in the order automatically becomes the new main thumbnail.
   *
   * **Security Considerations:**
   * - Only the product owner (seller) can delete images from their products
   * - Administrators can delete any product image for policy enforcement
   * - Deleted images are permanently removed from storage
   *
   * **Related Operations:**
   * - POST /products/{productId}/images - Upload new images
   * - PUT /products/{productId}/images/reorder - Reorder images
   * - PUT /products/{productId} - Update product (includes image array handling)
   *
   * **Business Rules:**
   * - Product must exist and be owned by the seller (or admin override)
   * - Image must belong to the specified product
   * - At least one image must remain after deletion (cannot delete all images)
   *
   * @param connection
   * @param productId Target product's unique identifier
   * @param imageId Target product image's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Delete product image from shopping_mall_product_images table.
   * 1. Verify seller ownership or admin privileges
   * 2. Load product and image records
   * 3. Verify image belongs to product
   * 4. Check minimum image count (at least 1 required)
   * 5. Delete image record from database
   * 6. Delete physical image file from storage
   * 7. Update image order indices for remaining images
   * 8. Set new main thumbnail if deleted image was first
   * 9. Create product snapshot documenting image deletion
   * 10. Return success response with deleted image details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":imageId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedParam("imageId")
    imageId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductIdImagesImageId({
        seller,
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
