import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IArrayIShoppingMallProductImage } from "../../../../../api/structures/IArrayIShoppingMallProductImage";
import { IShoppingMallProductImage } from "../../../../../api/structures/IShoppingMallProductImage";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerProductsProductIdImagesImageId } from "../../../../../providers/deleteShoppingMallSellerProductsProductIdImagesImageId";
import { postShoppingMallSellerProductsProductIdImages } from "../../../../../providers/postShoppingMallSellerProductsProductIdImages";

@Controller("/shoppingMall/seller/products/:productId/images")
export class ShoppingmallSellerProductsImagesController {
  /**
   * Upload product images for a specific product in the shopping mall platform.
   *
   * This operation allows authorized sellers to upload one or more images for their products. Images are associated with the specified product and stored with proper ordering information. Each uploaded image becomes part of the product's image gallery and is linked to the seller's product record.
   *
   * Security considerations: Only sellers who own the product can upload images. The system validates product ownership and seller permissions before processing uploads.
   *
   * Relationship to database entities: This operation creates records in the shopping_mall_product_images table, linking images to the target product through the shopping_mall_product_id foreign key. The display_order field ensures proper image ordering for the product gallery.
   *
   * Validation rules: Images must be valid file formats (typically JPEG, PNG, GIF). The system validates file size limits and format restrictions before storing images. Each product can have multiple images with sequential display ordering.
   *
   * Related API operations: This operation works in conjunction with GET /products/{productId} which displays product details including images, and GET /sellers/me/products which lists seller's products for image management.
   *
   * @param connection
   * @param productId Unique identifier of the product to upload images for. Must be a valid UUID format identifying the target product in the shopping_mall_products table.
   * @param body Image upload data including file references and display order
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Process product image uploads for the specified product. Validate product ownership and seller permissions. Create shopping_mall_product_images records with proper file references and display ordering. Handle multiple image uploads in a single request with proper transaction management. Return uploaded image records with assigned IDs and display orders.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async uploadImages(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IShoppingMallProductImage.ICreate,
  ): Promise<IArrayIShoppingMallProductImage> {
    try {
      return await postShoppingMallSellerProductsProductIdImages({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific product image from the product image library.
   *
   * This operation permanently removes a product image record from the system. When an image is deleted, it is removed from all displays and the product will no longer show that image. If the deleted image was the main thumbnail (first in display order), the system will automatically update the product's thumbnail to show the new first image.
   *
   * **Authorization**: Only the seller who owns the product or administrators can delete product images. Customers and other users do not have permission to delete images.
   *
   * **Business Logic**:
   * - The image must belong to the specified product (validation check)
   * - At least one image must remain after deletion (if product has been published)
   * - Deleting an image does not create a snapshot (only structural change)
   * - The system will automatically reorder remaining images after deletion
   *
   * @param connection
   * @param productId Target product's unique identifier
   * @param imageId Target image's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Delete a specific product image record from the shopping_mall_product_images table.
   *
   * 1. Verify the image exists and belongs to the specified product
   * 2. Check that at least one image will remain after deletion (if product has been published)
   * 3. Delete the product image record from the database
   * 4. Reorder remaining images to fill the gap in display_order sequence
   * 5. If the deleted image was first, update product thumbnail reference
   * 6. Return 204 No Content on success
   * 7. Return appropriate error codes for validation failures
   *
   * Handle the following error conditions:
   * - Image not found: 404 with error code "IMAGE_NOT_FOUND"
   * - Image doesn't belong to product: 403 with error code "IMAGE_NOT_OWNED"
   * - Would leave product with zero images: 400 with error code "PRODUCT_NEEDS_AT_LEAST_ONE_IMAGE"
   * - Seller lacks permission: 403 with error code "IMAGE_PERMISSION_DENIED"
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":imageId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedParam("imageId")
    imageId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductIdImagesImageId({
        seller,
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
