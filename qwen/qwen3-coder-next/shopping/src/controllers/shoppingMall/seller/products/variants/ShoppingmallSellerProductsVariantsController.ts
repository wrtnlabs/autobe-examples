import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallProductVariant } from "../../../../../api/structures/IPageIShoppingMallProductVariant";
import { IShoppingMallProductVariant } from "../../../../../api/structures/IShoppingMallProductVariant";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerProductsProductIdVariantsVariantId } from "../../../../../providers/deleteShoppingMallSellerProductsProductIdVariantsVariantId";
import { patchShoppingMallSellerProductsProductIdVariants } from "../../../../../providers/patchShoppingMallSellerProductsProductIdVariants";
import { postShoppingMallSellerProductsProductIdVariants } from "../../../../../providers/postShoppingMallSellerProductsProductIdVariants";
import { putShoppingMallSellerProductsProductIdVariantsVariantId } from "../../../../../providers/putShoppingMallSellerProductsProductIdVariantsVariantId";

@Controller("/shoppingMall/seller/products/:productId/variants")
export class ShoppingmallSellerProductsVariantsController {
  /**
   * Add a new variant to an existing product.
   *
   * This endpoint allows sellers to create additional variants for their products, enabling multiple configurations such as different colors, sizes, or other option combinations. Each variant must have a unique SKU code within the product and can have its own price override and initial stock quantity.
   *
   * The system validates that the product belongs to the seller making the request and that the SKU code is unique across all variants of this product. All variant data is stored with snapshots for audit trail and dispute resolution purposes.
   *
   * **Authorization**: This operation is available to sellers who own the product or to administrators for platform oversight.
   *
   * **Business Context**: This operation supports the seller's ability to expand their product catalog with multiple variants without creating separate product entries, maintaining consistency in product information while allowing flexible configuration options for customers.
   *
   * @param connection
   * @param productId The unique identifier of the product to which the variant will be added. This must be a valid product ID that belongs to the seller making the request.
   * @param body Information required to create a new product variant
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Add a new variant to an existing product. Validate that:
   * 1. Product exists and belongs to the seller
   * 2. Product variant does not already exist with same SKU code
   * 3. Create product variant record with provided SKU code, price override (if any)
   * 4. Create product variant snapshots for audit trail
   * 5. Create initial inventory history record with stock quantity
   * 6. Update product variant current stock quantity
   * 7. Return newly created variant with all details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IShoppingMallProductVariant.ICreate,
  ): Promise<IShoppingMallProductVariant> {
    try {
      return await postShoppingMallSellerProductsProductIdVariants({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of all variants for a specific product.
   *
   * This endpoint provides comprehensive variant data for product customization and selection. Each variant represents a specific configuration (e.g., "Red / Large") with its own SKU code, pricing options, and current stock availability.
   *
   * The endpoint returns paginated variant details including option values, price overrides (if any), current stock quantities, and SKU codes. This information enables customers to make informed purchasing decisions by showing them all available product configurations and their current availability.
   *
   * All variants are returned regardless of stock status, allowing customers to see all available options even if some are currently out of stock. The stock quantity field indicates current availability for each variant.
   *
   * The product ID in the path parameter uniquely identifies which product's variants to retrieve. All variants belong to the same parent product and share the same option structure.
   *
   * Supports comprehensive pagination with configurable page sizes and sorting options. Response includes variant summary information optimized for list displays.
   *
   * **Authorization**: This endpoint requires seller authentication. Sellers can only access variants for products they own or have permission to view.
   *
   * @param connection
   * @param productId Product ID - the unique identifier of the product whose variants to retrieve
   * @param body Pagination and filtering parameters for variant list
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the shopping_mall_product_variants table for all variants associated with the given product ID.
   * Filter variants where shopping_mall_product_id = :productId.
   * Select all variant fields including id, sku_code, price_override, stock_quantity, and shopping_mall_product_id.
   * Join with shopping_mall_product_variant_option_values table to get normalized option values for each variant.
   * Implement pagination with configurable page size and cursor-based navigation.
   * Return paginated results with IPageIShoppingMallProductVariant.ISummary container.
   * No stock validation required - return all variants regardless of availability.
   * Cache results briefly to reduce repeated queries for popular products.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IShoppingMallProductVariant.IRequest,
  ): Promise<IPageIShoppingMallProductVariant.ISummary> {
    try {
      return await patchShoppingMallSellerProductsProductIdVariants({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product variant with new information.
   *
   * This operation allows sellers to modify product variant details including SKU code, option values, and price overrides. The product variant is identified by its unique ID, and the seller must own the parent product to perform this update.
   *
   * The update operation supports modifying the SKU code (for inventory tracking), option values (for product configuration like color/size), and price override (to set variant-specific pricing different from the product base price).
   *
   * All variant updates create complete snapshots preserving the previous state for audit trail and dispute resolution. The system enforces business rules including SKU code uniqueness within products and validates that variant edits don't conflict with existing order items.
   *
   * @param connection
   * @param productId Parent product identifier. This is the unique UUID of the product that contains this variant.
   * @param variantId Target variant identifier. This is the unique UUID of the specific variant being updated.
   * @param body Update information for the product variant
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Update shopping_mall_product_variants table with new SKU code, option values, and price override.
   *
   * 1. Retrieve target variant by ID and validate ownership (seller owns parent product)
   * 2. Validate SKU code uniqueness within the same product
   * 3. Update variant fields in database
   * 4. Create variant snapshot preserving previous state
   * 5. Update product snapshot with new variant information
   * 6. Return updated variant with all current values
   *
   * Business rules:
   * - SKU code must be unique within the same product
   * - Option values must match existing option structure
   * - Price override must be positive number or null
   * - Validation against pending order items is performed but doesn't block updates
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":variantId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedParam("variantId")
    variantId: string,
    @TypedBody()
    body: IShoppingMallProductVariant.IUpdate,
  ): Promise<IShoppingMallProductVariant> {
    try {
      return await putShoppingMallSellerProductsProductIdVariantsVariantId({
        seller,
        productId,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a product variant from the seller's product catalog.
   *
   * This operation permanently removes a product variant and its associated inventory records. The operation includes strict validation to ensure data integrity and prevent deletion of variants that are part of active order processes.
   *
   * **Business Rules:**
   * - Variants can only be deleted when no pending order items exist
   * - Validation checks for paid or shipped order items
   * - Verification of no pending cancellation or refund requests
   * - All inventory history records remain for audit purposes
   * - Product snapshots are automatically created preserving variant state at deletion time
   *
   * **Security:**
   * - Seller ownership verification - only the product owner can delete variants
   * - Authorization checks ensure sellers can only modify their own products
   * - Audit trail records the deletion action and responsible seller
   *
   * **Edge Cases:**
   * - Deletion blocked if variant has any paid/shipped order items
   * - Deletion blocked if variant has pending cancellation requests
   * - Deletion blocked if variant has pending refund requests
   * - All order item references preserved even after variant deletion
   * - Product snapshots created to maintain historical variant data
   *
   * @param connection
   * @param productId Product identifier
   * @param variantId Product variant identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Delete a product variant with comprehensive validation.
   *
   * 1. Load product variant and verify seller ownership
   * 2. Check for paid/shipped order items referencing this variant
   * 3. Check for pending cancellation requests for this variant
   * 4. Check for pending refund requests for this variant
   * 5. If any validation fails, return conflict error with details
   * 6. If validation passes, create product snapshot preserving variant state
   * 7. Delete the variant record
   * 8. Delete all inventory history records for this variant
   * 9. Return success response with deleted variant data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":variantId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedParam("variantId")
    variantId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductIdVariantsVariantId({
        seller,
        productId,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
