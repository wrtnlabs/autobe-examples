import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallProductVariant } from "../../../../../api/structures/IShoppingMallProductVariant";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerProductsProductIdVariantsVariantId } from "../../../../../providers/deleteShoppingMallSellerProductsProductIdVariantsVariantId";
import { postShoppingMallSellerProductsProductIdVariants } from "../../../../../providers/postShoppingMallSellerProductsProductIdVariants";
import { putShoppingMallSellerProductsProductIdVariantsVariantId } from "../../../../../providers/putShoppingMallSellerProductsProductIdVariantsVariantId";

@Controller("/shoppingMall/seller/products/:productId/variants")
export class ShoppingmallSellerProductsVariantsController {
  /**
   * Add new product variants to an existing product
   *
   * This endpoint allows sellers to create additional variants for their products, enabling more product configurations such as different sizes, colors, or other customizable attributes.
   *
   * Each variant must have a unique SKU code and can optionally override the base product price. The stock quantity is initialized when creating the variant, and inventory tracking begins immediately.
   *
   * Only sellers with appropriate permissions can add variants to their own products. Customers and other sellers cannot create variants for products they don't own.
   *
   * @param connection
   * @param productId The unique identifier of the product to which variants will be added
   * @param body Information about the new product variant to be created
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Create a new product variant for the specified product.
   *
   * 1. Validate that the product exists and belongs to the current seller (for authorization)
   * 2. Validate that the SKU code is unique within the product
   * 3. Create the new product variant record with provided data
   * 4. Initialize stock quantity with the provided value
   * 5. Set is_active to true by default
   * 6. Return the complete created variant including generated ID and timestamps
   *
   * Business rules:
   * - SKU codes must be unique within each product (not globally unique)
   * - Stock quantity should be a non-negative integer
   * - Price override can be null (uses product base price) or a positive number
   * - All variants must be associated with a valid product ID
   * - Sellers can only add variants to their own products
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async createVariant(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IShoppingMallProductVariant.ICreate,
  ): Promise<IShoppingMallProductVariant> {
    try {
      return await postShoppingMallSellerProductsProductIdVariants({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a product variant with new SKU, options, and pricing information.
   *
   * This API endpoint allows sellers to modify existing product variant information including the stock keeping unit (SKU) code, option values (such as size, color combinations), and optional price overrides. The operation updates the variant's core attributes while maintaining the existing relationship to its parent product.
   *
   * The SKU code must remain unique across all variants belonging to the same seller, and option values must maintain consistency with the product's defined option structure. Price overrides can be set to customize variant pricing relative to the base product price, or set to null to use the product's default pricing.
   *
   * Security considerations include ensuring only the product owner (seller) can modify their variants, and validating that all changes comply with business rules around SKU uniqueness and option structure consistency.
   *
   * @param connection
   * @param productId Unique identifier of the product containing this variant
   * @param variantId Unique identifier of the specific variant to update
   * @param body Updated variant information including SKU, options, and price
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Update product variant information in the database.
   *
   * 1. Load the specific product variant by product ID and variant ID
   * 2. Validate that the current user is the owner of this product (seller)
   * 3. Update the variant fields with provided request data
   * 4. Validate SKU uniqueness across seller's variants
   * 5. Validate option values structure against product options
   * 6. Save updated variant to database
   * 7. Return updated variant with all current values
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":variantId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedParam("variantId")
    variantId: string,
    @TypedBody()
    body: IShoppingMallProductVariant.IUpdate,
  ): Promise<IShoppingMallProductVariant> {
    try {
      return await putShoppingMallSellerProductsProductIdVariantsVariantId({
        seller,
        productId,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a product variant from the product catalog.
   *
   * This endpoint allows sellers to permanently remove a specific variant from their product. Before deletion, the system validates that the variant belongs to the seller's product and checks for any pending order items.
   *
   * **Security Considerations:**
   * - Only the product owner (seller) can delete variants from their products
   * - System validates seller ownership before allowing deletion
   * - Deletion is restricted if any order items reference this variant
   * - Inventory history records are preserved for audit purposes
   *
   * **Business Logic:**
   * - Product must have at least one variant remaining after deletion
   * - Cannot delete variants with pending order items
   * - Inventory history records are preserved but the variant is removed from active catalog
   * - Product snapshots are created to preserve state at time of deletion
   *
   * **Related Database Entities:**
   * - shopping_mall_product_variants: The variant table being modified
   * - shopping_mall_product_snapshots: Snapshots created to preserve product state
   * - shopping_mall_inventory_histories: Inventory history preserved during deletion
   *
   * @param connection
   * @param productId Target product's unique identifier
   * @param variantId Target variant's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Delete a specific product variant by verifying seller ownership and checking for pending order items.
   *
   * 1. Load product variant by ID and verify it exists
   * 2. Verify the variant belongs to the seller's product
   * 3. Check for any order items referencing this variant
   * 4. Check for pending cancellation or refund requests
   * 5. Validate that product will have at least one variant remaining
   * 6. If validation passes, delete the variant record
   * 7. If validation fails, return appropriate error codes
   * 8. Create product snapshot preserving state before deletion
   * 9. Update product's active variant count
   * 10. Log deletion in product edit history
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":variantId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedParam("variantId")
    variantId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductIdVariantsVariantId({
        seller,
        productId,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
