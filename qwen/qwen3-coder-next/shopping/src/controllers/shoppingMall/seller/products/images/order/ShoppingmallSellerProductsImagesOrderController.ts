import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallProductImage } from "../../../../../../api/structures/IShoppingMallProductImage";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerProductsProductIdImagesOrder } from "../../../../../../providers/putShoppingMallSellerProductsProductIdImagesOrder";

@Controller("/shoppingMall/seller/products/:productId/images/order")
export class ShoppingmallSellerProductsImagesOrderController {
  /**
   * Reorder product images for a specific product
   *
   * This API endpoint allows authorized users to change the display order of product images. The order is critical for product presentation as it determines which image appears first in galleries and which image is used as the primary thumbnail.
   *
   * ## Authorization
   *
   * - Sellers can reorder images for their own products
   * - Administrators can reorder images for any product
   * - Customer access is not permitted for this operation
   *
   * ## Implementation Details
   *
   * - Validates that all image IDs belong to the specified product
   * - Ensures no duplicate image IDs in the reorder request
   * - Updates display_order field for each image based on array position
   * - The first image in the array gets display_order = 0
   * - All images must be associated with the specified product
   *
   * ## Business Rules
   *
   * - At least one image must remain after reordering (cannot clear all images)
   * - All image IDs in the request must exist and belong to the specified product
   * - No duplicate image IDs allowed in the reorder array
   * - The operation maintains referential integrity with the product
   *
   * @param connection
   * @param productId Unique identifier of the product whose images need to be reordered
   * @param body Request body containing the new order of image IDs
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Update display order for product images in the shopping_mall_product_images table.
   *
   * ## Implementation Steps
   *
   * 1. **Authentication & Authorization**
   *    - Verify user is authenticated via JWT token
   *    - Check if user is seller of the product OR administrator
   *    - Return 403 if unauthorized
   *
   * 2. **Input Validation**
   *    - Validate productId is a valid UUID format
   *    - Validate imageIds array is not empty
   *    - Validate no duplicate image IDs in the array
   *    - Validate all image IDs exist in database
   *
   * 3. **Authorization Check**
   *    - Query product to verify ownership (if seller)
   *    - Verify all images belong to the specified product
   *    - Return 404 if product not found
   *    - Return 403 if unauthorized access attempt
   *
   * 4. **Image Order Update**
   *    - Iterate through imageIds array with index
   *    - Update display_order for each image ID
   *    - First image gets display_order = 0
   *    - Second image gets display_order = 1, etc.
   *    - Use database transaction for atomic update
   *
   * 5. **Query Updated Images**
   *    - Retrieve all images for the product
   *    - Sort by display_order ascending
   *    - Return formatted image list
   *
   * ## Database Queries
   *
   * - SELECT product WHERE id = productId (ownership verification)
   * - SELECT images WHERE id IN (imageIds) AND shopping_mall_product_id = productId
   * - UPDATE shopping_mall_product_images SET display_order = index WHERE id = imageId
   * - SELECT * FROM shopping_mall_product_images WHERE shopping_mall_product_id = productId ORDER BY display_order
   *
   * ## Error Handling
   *
   * - Product not found (404)
   * - Unauthorized access (403)
   * - Invalid product ID format (400)
   * - Empty image array (400)
   * - Duplicate image IDs (400)
   * - Image IDs not belonging to product (400)
   * - Transaction failure (500)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async reorderImages(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IShoppingMallProductImage.IReorder,
  ): Promise<IShoppingMallProductImage> {
    try {
      return await putShoppingMallSellerProductsProductIdImagesOrder({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
