import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallProductVariantSnapshot } from "../../../../api/structures/IPageIShoppingMallProductVariantSnapshot";
import { IShoppingMallProductVariant } from "../../../../api/structures/IShoppingMallProductVariant";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerVariantsVariantId } from "../../../../providers/getShoppingMallSellerVariantsVariantId";
import { getShoppingMallSellerVariantsVariantIdSnapshots } from "../../../../providers/getShoppingMallSellerVariantsVariantIdSnapshots";

@Controller("/shoppingMall/seller/variants/:variantId")
export class ShoppingmallSellerVariantsController {
  /**
   * Retrieve historical snapshots of a specific product variant for audit and history tracking.
   *
   * This endpoint provides a complete audit trail showing how a product variant's characteristics have changed over time. Each snapshot captures the variant's SKU code, option values, price override, and stock quantity at the time of the original product editing operation.
   *
   * The snapshots are stored permanently for dispute resolution and audit purposes, preserving the exact state of the variant when it was part of an order or when significant changes occurred.
   *
   * @param connection
   * @param variantId Target product variant's UUID identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_product_variant_snapshots table where product_snapshot_id is derived from variant's product. Join with shopping_mall_product_snapshots to filter by variant's parent product. Order results by created_at descending to show most recent snapshots first. Return paginated list of variant snapshot summaries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("snapshots")
  public async snapshots(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("variantId")
    variantId: string,
  ): Promise<IPageIShoppingMallProductVariantSnapshot.ISummary> {
    try {
      return await getShoppingMallSellerVariantsVariantIdSnapshots({
        seller,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific product variant including its SKU code, pricing, stock quantity, and option values.
   *
   * This operation provides sellers with complete details about a product variant they own, including current stock levels, price information, and all option values that define the variant configuration.
   *
   * The operation includes security checks to ensure only the seller who owns the product containing this variant can access its details. Sellers can use this information to manage inventory, update variant details, or process orders for this specific configuration.
   *
   * @param connection
   * @param variantId Unique identifier of the product variant to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_product_variants table by variant ID. Include relation to parent product for ownership verification. Join with shopping_mall_product_variant_option_values for normalized option values. Include shopping_mall_variant_stocks for current stock quantity. Return complete variant details including parent product information and option values.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("variantId")
    variantId: string,
  ): Promise<IShoppingMallProductVariant> {
    try {
      return await getShoppingMallSellerVariantsVariantId({
        seller,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
