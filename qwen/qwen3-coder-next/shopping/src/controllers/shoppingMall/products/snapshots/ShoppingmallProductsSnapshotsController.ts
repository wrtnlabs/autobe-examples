import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IApiError } from "../../../../api/structures/IApiError";
import { IShoppingMallProductSnapshot } from "../../../../api/structures/IShoppingMallProductSnapshot";
import { getShoppingMallProductsProductIdSnapshotsSnapshotId } from "../../../../providers/getShoppingMallProductsProductIdSnapshotsSnapshotId";
import { patchShoppingMallProductsProductIdSnapshots } from "../../../../providers/patchShoppingMallProductsProductIdSnapshots";

@Controller("/shoppingMall/products/:productId/snapshots")
export class ShoppingmallProductsSnapshotsController {
  /**
   * Update a product snapshot
   *
   * This operation is not supported for product snapshots. Product snapshots are immutable audit records that are automatically created when products are edited. They cannot be manually updated through API operations.
   *
   * If you need to modify product information, use the product update endpoint instead:
   * - PATCH /sellers/me/products/:id
   * - PATCH /admin/products/:id
   *
   * Snapshot records preserve the exact state of products at specific points in time for audit, compliance, and dispute resolution purposes. Any attempts to modify snapshots would compromise their integrity as audit trails.
   *
   * @param connection
   * @param productId The unique identifier of the product whose snapshot is being accessed
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification This operation should not be implemented as a PATCH endpoint. Product snapshots are immutable audit records created automatically during product edits. The system should return a 405 Method Not Allowed error with an appropriate error message explaining that snapshots cannot be updated through API operations.
   *
   * If this endpoint is required for API consistency, implement it to return a 405 Method Not Allowed status with a clear error message directing users to use the product update endpoint instead.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @TypedParam("productId")
    productId: string,
  ): Promise<IApiError.IForbidden> {
    try {
      return await patchShoppingMallProductsProductIdSnapshots({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve specific product snapshot details
   *
   * This API endpoint retrieves detailed information about a specific product snapshot from the shopping_mall_product_snapshots table. Product snapshots preserve the complete state of products at specific points in time, supporting audit trails and historical reference.
   *
   * The snapshot includes the product name, description, category, base price, publication status, and stock quantity as they existed when the snapshot was created. Each snapshot is associated with a specific product and includes the timestamp of when the snapshot was taken, along with information about which user performed the edit that triggered the snapshot creation.
   *
   * This functionality supports dispute resolution, historical product analysis, and compliance requirements by providing immutable access to product state at any point in time.
   *
   * @param connection
   * @param productId Target product's UUID identifier
   * @param snapshotId Target snapshot's UUID identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_product_snapshots table by productId and snapshotId. Join with shopping_mall_products table to verify product ownership and existence. Return complete snapshot record including all product fields preserved at time of snapshot creation. Implement access control: customers/sellers can only view their own product snapshots, admins can view all snapshots. Return 404 if snapshot not found for the given product, 403 if unauthorized access attempted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async atSnapshot(
    @TypedParam("productId")
    productId: string,
    @TypedParam("snapshotId")
    snapshotId: string,
  ): Promise<IShoppingMallProductSnapshot> {
    try {
      return await getShoppingMallProductsProductIdSnapshotsSnapshotId({
        productId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
