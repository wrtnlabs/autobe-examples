import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallProductVariant } from "../../../../api/structures/IShoppingMallProductVariant";
import { patchShoppingMallProductsProductIdVariants } from "../../../../providers/patchShoppingMallProductsProductIdVariants";

@Controller("/shoppingMall/products/:productId/variants")
export class ShoppingmallProductsVariantsController {
  /**
   * Update product variant information including SKU code, option values, price overrides, stock quantities, and active status for a specific product variant.
   *
   * This operation allows sellers to modify existing product variant details after initial creation. The variant can be updated with new SKU codes, updated option values for product configurations, price overrides that differ from the base product price, current stock quantity levels, and activation status.
   *
   * This update functionality supports dynamic inventory management and price adjustments that sellers may need to make based on real-time business requirements and stock levels.
   *
   * @param connection
   * @param productId The unique identifier of the product variant to be updated
   * @param body Updated variant information including SKU, option values, price override, stock quantity, and active status
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Update product variant record with new SKU, option values, price override, stock quantity, and active status. Retrieve the product first to ensure the variant belongs to it, then apply partial updates to the specified variant fields. Update the timestamp for updated_at field.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IShoppingMallProductVariant.IUpdate,
  ): Promise<IShoppingMallProductVariant> {
    try {
      return await patchShoppingMallProductsProductIdVariants({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
