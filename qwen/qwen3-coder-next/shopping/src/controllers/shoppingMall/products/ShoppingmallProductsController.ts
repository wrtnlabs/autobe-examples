import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallProduct } from "../../../api/structures/IPageIShoppingMallProduct";
import { IShoppingMallProduct } from "../../../api/structures/IShoppingMallProduct";
import { getShoppingMallProductsProductId } from "../../../providers/getShoppingMallProductsProductId";
import { patchShoppingMallProducts } from "../../../providers/patchShoppingMallProducts";

@Controller("/shoppingMall/products")
export class ShoppingmallProductsController {
  /**
   * Retrieve a filtered, sorted, and paginated list of products.
   *
   * This operation provides comprehensive product search capabilities including filtering by category, price range, and stock availability, along with multiple sorting options and pagination support.
   *
   * The search supports cross-seller product discovery, allowing customers to find products from any seller on the platform.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query products table with pagination and filtering support.
   * Apply category filter to include products in specified category and subcategories.
   * Apply price range filter with minimum and maximum price constraints.
   * Apply in-stock filter to show only products with available variants.
   * Support sorting by newest (created_at DESC), price ASC, and price DESC.
   * Return paginated results with configurable page size (default 20).
   * Include product summary information with main image, name, base price or price range, seller name, and average rating.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallProduct.IRequest,
  ): Promise<IPageIShoppingMallProduct.ISummary> {
    try {
      return await patchShoppingMallProducts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific product including its variants, images, and seller information.
   *
   * This endpoint provides the comprehensive product detail view that customers see when browsing products in the shopping mall. It returns the complete product information including all associated images ordered by display sequence, all available variants with their pricing and stock levels, and the seller's shop information.
   *
   * The product detail page serves as the central hub for product information, allowing customers to view comprehensive specifications, see available options, check stock availability, and understand the seller's credentials before making purchasing decisions.
   *
   * Security considerations include ensuring only active (non-deleted) products are accessible. Products marked as deleted or removed by administrators will not be returned. The product's category hierarchy provides context for product classification and browsing navigation.
   *
   * The `productId` parameter references the `shopping_mall_products.id` field which is a UUID type identifier.
   *
   * @param connection
   * @param productId Target product's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_products table by primary key ID. Join with shopping_mall_categories for category information. Join with shopping_mall_sellers for seller profile information. Left join with shopping_mall_product_images to get all images ordered by sort_order. Left join with shopping_mall_product_variants to get all available variants for this product. Filter by is_deleted = false to exclude soft-deleted products. Return complete product structure with nested relations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @TypedParam("productId")
    productId: string,
  ): Promise<IShoppingMallProduct> {
    try {
      return await getShoppingMallProductsProductId({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
