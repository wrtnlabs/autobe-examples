import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallProduct } from "../../../api/structures/IPageIShoppingMallProduct";
import { IShoppingMallProduct } from "../../../api/structures/IShoppingMallProduct";
import { getShoppingMallProductsProductId } from "../../../providers/getShoppingMallProductsProductId";
import { patchShoppingMallProducts } from "../../../providers/patchShoppingMallProducts";

@Controller("/shoppingMall/products")
export class ShoppingmallProductsController {
  /**
   * Retrieve detailed information about a specific product including all variants, images, and seller information.
   *
   * This endpoint provides comprehensive product details for the product detail page, including all available variants with their pricing and stock levels, product images in display order, and the seller's shop information.
   *
   * The product information includes complete description, category hierarchy, pricing details, and current availability status. Variant information shows all available options with their specific prices and stock quantities.
   *
   * This API operation is designed for customers who want to view detailed product information before making a purchase decision.
   *
   * @param connection
   * @param productId Target product's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_products table by ID to retrieve product details.
   * Join with shopping_mall_product_variants for all variants.
   * Join with shopping_mall_product_images for images ordered by display order.
   * Join with shopping_mall_sellers for seller profile information.
   * Return complete product object with nested variants and images arrays.
   * Handle soft delete by filtering out products with deleted_at timestamp.
   * Use UUID-based lookup for productId parameter.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @TypedParam("productId")
    productId: string,
  ): Promise<IShoppingMallProduct> {
    try {
      return await getShoppingMallProductsProductId({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and filter products with comprehensive search capabilities.
   *
   * This operation provides advanced search functionality including name-based searching, category filtering, price range filtering, and stock availability filtering. The system supports sorting by multiple criteria and returns paginated results optimized for e-commerce product listings.
   *
   * Customers can search across all sellers' products with filters for category hierarchy, price ranges, and stock availability. The search supports partial name matching and case-insensitive results.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_products table with pagination, search, filtering, and sorting.
   *
   * Apply search filters on product name using partial matching (ILIKE with % wildcards).
   * Filter by category including subcategories using recursive category relationship.
   * Filter by price range using base_price field with min/max constraints.
   * Filter by stock availability using shopping_mall_product_variants table with stock_quantity > 0.
   * Join with shopping_mall_subcategories for category filtering.
   * Apply sorting: newest (created_at DESC), price-asc (base_price ASC), price-desc (base_price DESC).
   * Return paginated results with 20 items per page default.
   * Optimize with appropriate indexes on created_at, base_price, and full-text search on description.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallProduct.IRequest,
  ): Promise<IPageIShoppingMallProduct.ISummary> {
    try {
      return await patchShoppingMallProducts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
