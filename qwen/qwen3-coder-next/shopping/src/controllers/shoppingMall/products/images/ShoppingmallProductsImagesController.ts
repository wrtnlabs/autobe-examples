import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallProductImage } from "../../../../api/structures/IPageIShoppingMallProductImage";
import { IShoppingMallProductImage } from "../../../../api/structures/IShoppingMallProductImage";
import { patchShoppingMallProductsProductIdImages } from "../../../../providers/patchShoppingMallProductsProductIdImages";

@Controller("/shoppingMall/products/:productId/images")
export class ShoppingmallProductsImagesController {
  /**
   * Reorder images for a specific product.
   *
   * This operation allows sellers to change the display order of their product images. The first image (display_order: 1) is typically used as the main product thumbnail in listings and product detail pages.
   *
   * Sellers must have ownership of the product to reorder its images. This operation updates the display_order values for the specified images, which affects the visual presentation order throughout the platform.
   *
   * @param connection
   * @param productId Target product's UUID identifier
   * @param body Image order update payload with new display order mappings
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Update display_order values for product images. Validate seller ownership of product before allowing reordering. Update all specified image order values atomically. Return complete updated image list after reordering.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async reorder(
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IShoppingMallProductImage.IOrder,
  ): Promise<IPageIShoppingMallProductImage> {
    try {
      return await patchShoppingMallProductsProductIdImages({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
