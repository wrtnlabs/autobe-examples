import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallInventoryHistory } from "../../../../api/structures/IShoppingMallInventoryHistory";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerAvailabilityCleanup } from "../../../../providers/patchShoppingMallCustomerAvailabilityCleanup";

@Controller("/shoppingMall/customer/availability-cleanup")
export class ShoppingmallCustomerAvailability_cleanupController {
  /**
   * System maintenance operation to clean up and update product availability status across the platform.
   *
   * This endpoint performs bulk availability cleanup tasks including: updating out-of-stock status for variants, removing unavailable items from customer carts and wishlists, synchronizing inventory availability status, and ensuring data consistency across the platform.
   *
   * This is a system maintenance operation typically called by scheduled jobs or administrative processes to maintain data integrity and improve user experience by ensuring only available products are shown for purchase.
   *
   * @param connection
   * @param body Cleanup configuration options for availability maintenance
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Perform system maintenance to clean up product availability status.
   *
   * 1. Update all product variants where stock quantity is 0 to mark as unavailable
   * 2. Remove cart items where the variant is no longer available (stock = 0 or variant deleted)
   * 3. Remove wishlist entries where the product has no available variants
   * 4. Update inventory availability status across all variants
   * 5. Ensure consistency between inventory records and product availability display
   * 6. Return summary of items cleaned up and variants updated
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async cleanupAvailability(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallInventoryHistory.ICleanupRequest,
  ): Promise<IShoppingMallInventoryHistory.ICleanupResponse> {
    try {
      return await patchShoppingMallCustomerAvailabilityCleanup({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
