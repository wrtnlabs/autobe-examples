import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallReviewSnapshot } from "../../../../../api/structures/IShoppingMallReviewSnapshot";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerReviewsReviewIdSnapshots } from "../../../../../providers/getShoppingMallCustomerReviewsReviewIdSnapshots";

@Controller("/shoppingMall/customer/reviews/:reviewId/snapshots")
export class ShoppingmallCustomerReviewsSnapshotsController {
  /**
   * Retrieve the complete audit history of a specific review.
   *
   * This operation provides access to all historical snapshots of a review, allowing customers and administrators to view the complete modification history. Each snapshot preserves the review's complete state at a specific point in time, including the rating, text content, and timestamp of the modification.
   *
   * This functionality is essential for dispute resolution, allowing both customers and sellers to verify the complete history of review changes. Administrators can use this audit trail to investigate policy violations and ensure data integrity.
   *
   * The system creates a snapshot every time a review is modified or deleted, preserving the complete state for compliance and legal purposes. All snapshots are immutable and cannot be altered after creation.
   *
   * @param connection
   * @param reviewId The unique identifier of the review for which to retrieve historical snapshots.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the review snapshots table for the specified review ID. Order results chronologically by snapshot timestamp. Return complete snapshot data including rating, text content, timestamps, and user information. Implement authorization check to ensure only review owner or administrator can access the snapshots.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string,
  ): Promise<IShoppingMallReviewSnapshot.ISummary> {
    try {
      return await getShoppingMallCustomerReviewsReviewIdSnapshots({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
