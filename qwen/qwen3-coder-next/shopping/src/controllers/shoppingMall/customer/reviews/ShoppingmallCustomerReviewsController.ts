import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallReview } from "../../../../api/structures/IShoppingMallReview";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteShoppingMallCustomerReviewsReviewId } from "../../../../providers/deleteShoppingMallCustomerReviewsReviewId";
import { patchShoppingMallCustomerReviewsReviewId } from "../../../../providers/patchShoppingMallCustomerReviewsReviewId";

@Controller("/shoppingMall/customer/reviews/:reviewId")
export class ShoppingmallCustomerReviewsController {
  /**
   * Update an existing customer review for a product.
   *
   * This operation allows customers to modify their previously submitted reviews by updating the star rating and/or text content. When a review is updated, the system automatically creates a new snapshot preserving the previous state, ensuring complete audit trail for all review changes.
   *
   * The review must be associated with an order item that has status "delivered". Customers can only update reviews they personally wrote - they cannot modify reviews written by other users. This update functionality enables customers to correct typos, adjust ratings, or add additional feedback after their initial submission.
   *
   * When successful, the updated review includes all current information along with a reference to the most recent snapshot, allowing clients to track the review's history and retrieve previous versions if needed.
   *
   * @param connection
   * @param reviewId Target review's unique identifier (UUID format).
   * @param body Update data for the review including new rating and/or content.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update customer review by ID.
   * Fetch review by path parameter reviewId.
   * Verify ownership: review.customer_id must match current user's customer_id.
   * Validate: associated order_item must have status "delivered".
   * If text is provided, update review.content with new value.
   * If rating is provided, update review.rating with new value (1-5).
   * Create new snapshot in shopping_mall_review_snapshots table preserving previous state.
   * Return updated review with all fields and snapshot reference.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string,
    @TypedBody()
    body: IShoppingMallReview.IUpdate,
  ): Promise<IShoppingMallReview> {
    try {
      return await patchShoppingMallCustomerReviewsReviewId({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a customer review for a product.
   *
   * This operation permanently removes a customer review from the platform. Reviews can be deleted by the customer who wrote the review or by administrators for policy violations.
   *
   * **Security and Authorization**
   *
   * - Only the customer who wrote the review can delete their own review
   * - Administrators can delete any review for policy violations
   * - Review snapshots are created before deletion to preserve audit history
   * - The original review content and rating are preserved in snapshots for historical accuracy
   *
   * **Snapshot Preservation**
   *
   * When a review is deleted:
   * - A complete snapshot of the review state is created at the time of deletion
   * - The snapshot preserves the rating, text content, and timestamp
   * - The snapshot links to the original review for audit trail purposes
   * - Review snapshots are immutable and cannot be deleted
   *
   * **Related Operations**
   *
   * - `GET /products/:id/reviews` retrieves product reviews including deleted ones (marked as deleted)
   * - `GET /products/:id/rating` recalculates average rating excluding deleted reviews
   * - `POST /customers/me/products/:productId/reviews` create new reviews for products
   * - `PATCH /customers/me/products/:productId/reviews/:reviewId` edit existing reviews
   *
   * **Error Handling**
   *
   * The operation may return the following error codes:
   * - `REVIEW_NOT_FOUND`: Review does not exist
   * - `REVIEW_NOT_AUTHOR`: Customer attempted to delete another customer's review
   * - `REVIEW_DELETE_FAILED`: Review deletion failed due to system error
   * - `REVIEW_HAS_PENDING_REFUND`: Review associated with pending refund request
   * - `REVIEW_HAS_PENDING_CANCELLATION`: Review associated with pending cancellation request
   *
   * @param connection
   * @param reviewId Target review's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Delete a customer review and create a snapshot for audit purposes.
   *
   * Query the shopping_mall_reviews table by the provided reviewId.
   * Verify that the current user is either the review author or an administrator.
   * If verification passes, create a snapshot in the shopping_mall_review_snapshots table with:
   * - Current review rating
   * - Current review content (or '[review deleted]' if already deleted)
   * - Current timestamp as edited_at if editing, or null if immediate deletion
   * - Current timestamp as created_at for the snapshot
   * - Link to the original review ID
   * - Link to the customer who wrote the review
   * - Link to the product that was reviewed
   *
   * After snapshot creation, permanently delete the review record from shopping_mall_reviews.
   * Update the product's average rating by recalculating from remaining reviews.
   * Return the deleted review as a summary with fields: id, customer_id, order_item_id, rating, content, deleted status, and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string,
  ): Promise<IShoppingMallReview.ISummary> {
    try {
      return await deleteShoppingMallCustomerReviewsReviewId({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
