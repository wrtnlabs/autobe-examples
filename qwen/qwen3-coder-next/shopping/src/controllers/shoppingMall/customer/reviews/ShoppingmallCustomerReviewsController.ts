import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallReview } from "../../../../api/structures/IPageIShoppingMallReview";
import { IShoppingMallReview } from "../../../../api/structures/IShoppingMallReview";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteShoppingMallCustomerReviewsReviewId } from "../../../../providers/deleteShoppingMallCustomerReviewsReviewId";
import { getShoppingMallCustomerReviewsReviewId } from "../../../../providers/getShoppingMallCustomerReviewsReviewId";
import { patchShoppingMallCustomerReviews } from "../../../../providers/patchShoppingMallCustomerReviews";
import { postShoppingMallCustomerReviews } from "../../../../providers/postShoppingMallCustomerReviews";

@Controller("/shoppingMall/customer/reviews")
export class ShoppingmallCustomerReviewsController {
  /**
   * Write a product review for a purchased item
   *
   * This endpoint allows customers to submit reviews for products they have purchased and received. Reviews are an essential part of the platform's social commerce features, helping other customers make informed purchasing decisions.
   *
   * Only customers who have completed their purchases (item status "delivered") are eligible to write reviews. The system enforces a one-review-per-product-per-order policy to prevent review flooding and ensure quality feedback.
   *
   * The review system supports:
   * - Rating submission (1 to 5 stars, required)
   * - Optional text content for detailed feedback
   * - Review snapshots for audit trail
   * - Average rating calculation from active reviews
   * - Customer help votes for quality assessment
   *
   * @param connection
   * @param body Review creation data including rating and optional text content
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create a new review record for a product.
   *
   * Validation:
   * - Verify customer has purchased the product (check order item status is "delivered")
   * - Verify customer has not already reviewed this product in this order
   * - Validate rating is between 1-5 stars
   * - Validate text content is within length limits (up to 2000 characters)
   *
   * Processing:
   * - Create review record with customer ID, product ID, order ID, rating, and text content
   * - Set review status to "active"
   * - Create review snapshot
   * - Recalculate product average rating
   * - Return created review with full details
   *
   * Error handling:
   * - Return 400 if customer hasn't purchased the product
   * - Return 400 if customer already reviewed this product in this order
   * - Return 422 if validation fails (invalid rating range, text too long)
   * - Return 404 if product doesn't exist
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallReview.ICreate,
  ): Promise<IShoppingMallReview> {
    try {
      return await postShoppingMallCustomerReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of product reviews.
   *
   * This operation provides comprehensive search and filtering capabilities for product reviews, allowing customers to view reviews for specific products with various filter options including rating range, date range, and sorting preferences.
   *
   * All reviews displayed are non-deleted reviews that have been approved for public viewing. The system calculates average ratings from these active reviews for product pages.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_reviews table with filtering by product_id, rating range, and date range.
   * Apply pagination with configurable page size.
   * Sort by created_at (newest first) or rating (highest first).
   * Return only non-deleted reviews (is_deleted = false).
   * Include average rating calculation and review count per product.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallReview.IRequest,
  ): Promise<IPageIShoppingMallReview.ISummary> {
    try {
      return await patchShoppingMallCustomerReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific customer review.
   *
   * This endpoint fetches a single review by its ID, including the review rating, text content, creation timestamp, and related metadata. The system performs authorization checks to ensure customers can only view their own reviews unless they have administrative privileges.
   *
   * The operation handles the soft delete status of reviews through the is_deleted flag and deleted_at timestamp fields. For deleted reviews, access control is enforced based on the requesting user's role and ownership relationship to the review.
   *
   * The response includes complete review details along with related metadata such as helpful votes count and reviewer profile information. For deleted reviews, appropriate status codes are returned based on user permissions.
   *
   * @param connection
   * @param reviewId The unique identifier of the review to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_reviews table by primary key ID.
   * Check is_deleted flag and deleted_at timestamp for soft delete status.
   * Perform authorization validation:
   * - If customer: verify review.customer_id matches requesting customer_id
   * - If admin: allow access to all reviews
   * - If unauthorized: return 403 Forbidden
   * For soft-deleted reviews, check role permissions:
   * - Customer viewing their own deleted review: return 404 Not Found
   * - Admin viewing deleted review: return review with is_deleted flag
   * - Other customers viewing deleted review: return 404 Not Found
   * Include related data: review snapshots count, helpful votes count.
   * Return complete review information including product and order references.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reviewId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string,
  ): Promise<IShoppingMallReview> {
    try {
      return await getShoppingMallCustomerReviewsReviewId({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a customer review.
   *
   * This operation permanently removes a review from active display while preserving the database record for audit and historical purposes.
   *
   * The review will be immediately hidden from product review listings and will no longer contribute to product average ratings. However, the review record and associated snapshots are preserved for compliance and dispute resolution.
   *
   * **Authorization:**
   * - Customers can delete only their own reviews
   * - Administrators can delete any review
   *
   * **Important Notes:**
   * - This performs a soft delete (marks is_deleted flag, sets deleted_at timestamp)
   * - The review record remains in the database for audit trail
   * - Review snapshots are created before deletion
   * - Product average ratings are automatically recalculated after deletion
   *
   * @param connection
   * @param reviewId Target review's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Perform soft delete on shopping_mall_reviews record.
   * 1. Verify ownership (customer can only delete their own) or admin permission
   * 2. Mark review as deleted (is_deleted = true, set deleted_at timestamp)
   * 3. Create review snapshot with deletion state
   * 4. Update product's average rating by excluding this review
   * 5. Return success confirmation with deleted review details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reviewId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerReviewsReviewId({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
