import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerProfile } from "../../../../providers/putShoppingMallCustomerProfile";

@Controller("/shoppingMall/customer/profile")
export class ShoppingmallCustomerProfileController {
  /**
   * Update customer profile information including display name and phone number.
   *
   * This endpoint allows authenticated customers to modify their personal profile information. Customers can update their display name (shown to other users during transactions and reviews) and phone number (used for contact and order notifications).
   *
   * The profile data is stored in the shopping_mall_customers table with appropriate validation rules ensuring data integrity and security. This operation focuses on profile information management and does not involve soft delete functionality - it is a direct record update operation.
   *
   * Security Considerations:
   * - Authentication required via customer session
   * - Customers can only update their own profile
   * - Input validation for name format and phone number standards
   * - Timestamp recording for audit trail
   *
   * Relationship to Database:
   * - Updates shopping_mall_customers table
   * - Maintains customer account information
   * - Preserves authentication credentials
   * - Updates profile-related fields only
   *
   * @param connection
   * @param body Customer profile update request with display name and phone number
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update customer profile information in the shopping_mall_customers table. Accept display_name and phone_number in request body, validate field formats, and update the customer record with current timestamp. Return complete customer profile with all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async updateProfile(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCustomer.IUpdate,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await putShoppingMallCustomerProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
