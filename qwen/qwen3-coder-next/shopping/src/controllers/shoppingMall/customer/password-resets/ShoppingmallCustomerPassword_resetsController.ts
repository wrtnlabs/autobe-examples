import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IAutoBeSuccess } from "../../../../api/structures/IAutoBeSuccess";
import { IShoppingMallCustomerPasswordReset } from "../../../../api/structures/IShoppingMallCustomerPasswordReset";
import { postShoppingMallCustomerPasswordResets } from "../../../../providers/postShoppingMallCustomerPasswordResets";

@Controller("/shoppingMall/customer/password-resets")
export class ShoppingmallCustomerPassword_resetsController {
  /**
   * Initiate the password reset process for customer accounts.
   *
   * This operation generates a secure password reset token that will be sent to the customer's registered email address. The token has a limited lifetime and can only be used once to change the account password.
   *
   * **Security Features**:
   * - Tokens are generated as UUIDs for security
   * - Each token has a defined expiration time (typically 24 hours)
   * - Once used, tokens are marked as consumed and cannot be reused
   * - The system prevents abuse by tracking token generation frequency
   * - Email existence is not revealed to prevent enumeration attacks
   *
   * **Workflow**:
   * 1. Customer submits their email address
   * 2. System validates email format
   * 3. System generates a secure UUID token
   * 4. Token is stored with expiration timestamp
   * 5. Reset instructions are sent to the customer's email
   *
   * This operation is the first step in the password recovery workflow. Customers may need to call this operation multiple times if their token expires or they need a new reset link.
   *
   * @param connection
   * @param body Password reset request payload containing the customer's email address for which to generate a reset token.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Create a new password reset token for the customer's account.
   * 1. Validate that the provided email exists in the system
   * 2. Generate a new UUID token for the reset request
   * 3. Set the expiration time (typically 24 hours from creation)
   * 4. Create a record in shopping_mall_customer_password_resets table
   * 5. Return success response without exposing sensitive information
   *
   * This operation should not reveal whether an email exists in the system to prevent email enumeration attacks. Always return success for valid request format.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: IShoppingMallCustomerPasswordReset.ICreate,
  ): Promise<IAutoBeSuccess.IResponse> {
    try {
      return await postShoppingMallCustomerPasswordResets({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
