  /**
   * Submit a cancellation request for an order item.
   *
   * This API endpoint allows customers to request cancellation of their purchased order items. The cancellation request must include a reason explaining why the customer wants to cancel the purchase.
   *
   * **Eligibility Requirements:**
   * - Only order items with status "paid" can be cancelled
   * - Items already shipped cannot be cancelled (must use refund process instead)
   * - Items already delivered cannot be cancelled (must use refund process instead)
   * - Cancellation is performed per order item, not per entire order
   *
   * **Request Process:**
   * 1. Customer initiates cancellation request with specific item and reason
   * 2. System creates cancellation request record with timestamp and status "pending"
   * 3. Seller receives notification of the pending cancellation request
   * 4. Seller can approve or reject the request with explanation
   * 5. If approved, stock quantities are restored and payment is refunded
   * 6. If rejected, the order item continues processing normally
   *
   * **Workflow Details:**
   * - Cancellation requests are tracked with full audit trail
   * - All request and response history is preserved as snapshots
   * - Stock restoration occurs only after approval
   * - Refund processing follows the same workflow as direct refunds
   * - Order status is recalculated after cancellation is processed
   *
   * **Security Considerations:**
   * - Only the customer who placed the order can request cancellation
   * - Sellers can only respond to cancellation requests for their own products
   * - Administrators can force-cancel items for policy violations
   * - All cancellation activities are logged for dispute resolution
   *
   * **Related Operations:**
   * - POST /sellers/me/order-items/:itemId/cancellation-requests/:requestId - Seller approves/rejects cancellation
   * - PATCH /admin/orders/:orderId/items/:itemId/cancel - Admin force-cancel item
   * - POST /customers/me/orders/:orderId/items/:itemId/refund-requests - Refund request (for delivered items)
   *
   * @param connection
   * @param orderId The unique identifier of the order containing the item
   * @param itemId The unique identifier of the specific order item to cancel
   * @param body Reason for requesting order item cancellation
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Creates a new cancellation request for a specific order item.
   *
   * Implementation Steps:
   * 1. Retrieve the order item using orderId and itemId path parameters
   * 2. Validate the order item exists and belongs to the requesting customer
   * 3. Check that order item status is "paid" (only eligible status for cancellation)
   * 4. Validate the request reason is provided and not empty
   * 5. Create cancellation request record with:
   *    - order_item_id referencing the order item
   *    - customer_id from authenticated session
   *    - reason from request body
   *    - status set to "pending"
   *    - timestamps for creation
   * 6. Notify the seller who provided the product
   * 7. Return success response with cancellation request ID
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
