import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallReview } from "../../../../../../api/structures/IShoppingMallReview";
import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { postShoppingMallCustomerOrdersOrderIdItemsItemIdReviews } from "../../../../../../providers/postShoppingMallCustomerOrdersOrderIdItemsItemIdReviews";

@Controller("/shoppingMall/customer/orders/:orderId/items/:itemId/reviews")
export class ShoppingmallCustomerOrdersItemsReviewsController {
  /**
   * Write a product review for a delivered order item
   *
   * This endpoint allows customers to submit reviews for products they have purchased and received. Reviews include a star rating (1-5) and optional text content that provides feedback about the purchased product.
   *
   * Security and Authorization:
   * - Only customers who purchased the specific order item can write a review
   * - The system validates that the customer has actually purchased the item
   * - Each order item can have only one review per customer (enforced by unique constraint)
   * - Reviews cannot be written for items that have not been delivered yet
   *
   * Database Integration:
   * The operation creates a record in the shopping_mall_reviews table with the customer's ID (from authentication), the order item ID (from path parameter), the rating score, and optional content text. The system automatically generates the review ID and creation timestamp.
   *
   * Business Rules:
   * - Rating must be an integer between 1 and 5 (inclusive)
   * - Content is optional but cannot exceed maximum length if implemented
   * - Review can only be written after the order item status is 'delivered'
   * - Attempting to write multiple reviews for the same order item will result in a conflict error
   *
   * @param connection
   * @param orderId Target order's unique identifier
   * @param itemId Target order item's unique identifier
   * @param body Review content and rating information
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create a new product review record in the shopping_mall_reviews table.
   * 1. Extract customer_id from JWT authentication token
   * 2. Validate that orderId and itemId path parameters are valid UUIDs
   * 3. Query shopping_mall_order_items table to verify:
   *    - Order item exists with matching orderId and itemId
   *    - Order item.customer_id matches authenticated customer_id (ownership verification)
   *    - Order item status is 'delivered' (review eligibility)
   * 4. Validate request body:
   *    - rating is required, must be integer between 1-5
   *    - content is optional, must be string if provided
   * 5. Create review record with:
   *    - id: generated UUID
   *    - customer_id: from authentication
   *    - order_item_id: from path parameter
   *    - rating: from request body
   *    - content: from request body (nullable)
   *    - created_at: current timestamp
   * 6. Update product_review_ratings table to recalculate average rating
   * 7. Return complete review record with all database-generated fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedParam("itemId")
    itemId: string,
    @TypedBody()
    body: IShoppingMallReview.ICreate,
  ): Promise<IShoppingMallReview> {
    try {
      return await postShoppingMallCustomerOrdersOrderIdItemsItemIdReviews({
        customer,
        orderId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
