import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallOrder } from "../../../../api/structures/IPageIShoppingMallOrder";
import { IShoppingMallOrder } from "../../../../api/structures/IShoppingMallOrder";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersOrderId } from "../../../../providers/getShoppingMallCustomerOrdersOrderId";
import { patchShoppingMallCustomerOrders } from "../../../../providers/patchShoppingMallCustomerOrders";

@Controller("/shoppingMall/customer/orders")
export class ShoppingmallCustomerOrdersController {
  /**
   * Retrieve a filtered and paginated list of orders.
   *
   * This operation provides comprehensive order search capabilities with filtering by status, date range, customer, and seller. It supports different access levels based on user role - customers see their own orders, sellers see their order items, and administrators see all orders.
   *
   * The endpoint supports advanced filtering including order status (paid/shipped/delivered/cancelled/refunded), date range filtering for order creation dates, and sorting by creation date (newest first by default).
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_orders table with pagination and filtering.
   * Apply role-based access control - customers only see their own orders, sellers see their order items, admins see all.
   * Support filtering by status, date range, and optional customer/seller ID filters.
   * Order results by created_at timestamp descending (newest first).
   * Return paginated list with order summary information including basic status and total price details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallOrder.IRequest,
  ): Promise<IPageIShoppingMallOrder.ISummary> {
    try {
      return await patchShoppingMallCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific order.
   *
   * This operation fetches the complete details of an order including all associated items, shipments, customer information, and current status. It supports both customer-specific order viewing and administrator oversight capabilities.
   *
   * **Customer Access:**
   * - Customers can only view their own orders
   * - Requires authentication via JWT token
   * - Returns 403 Forbidden if accessing another customer's order
   *
   * **Administrator Access:**
   * - Administrators can view any order on the platform
   * - Used for dispute resolution and order oversight
   * - Complete order history and status information available
   *
   * @param connection
   * @param orderId The unique identifier of the order to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_orders table by orderId.
   * Join with shopping_mall_order_items to fetch all order items.
   * Join with shopping_mall_shipments to fetch associated shipments.
   * Join with shopping_mall_order_item_status_logs for status change history.
   * Apply authorization check: customer can only see their own orders, admin can see all.
   * Return complete order with nested items, shipments, and status logs.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string,
  ): Promise<IShoppingMallOrder> {
    try {
      return await getShoppingMallCustomerOrdersOrderId({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
