import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallShipment } from "../../../../../api/structures/IPageIShoppingMallShipment";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersOrderIdShipments } from "../../../../../providers/getShoppingMallCustomerOrdersOrderIdShipments";

@Controller("/shoppingMall/customer/orders/:orderId/shipments")
export class ShoppingmallCustomerOrdersShipmentsController {
  /**
   * Retrieve all shipments belonging to a specific order.
   *
   * This endpoint returns a paginated list of all physical shipments associated with the specified order. Each shipment represents a package sent from a seller to the customer and includes shipping carrier information, tracking numbers, and delivery status.
   *
   * The shipments are retrieved by joining the shopping_mall_shipments table with shopping_mall_order_items, finding all shipments where the associated order item belongs to the specified order. This allows customers and sellers to view complete shipping information for order tracking and delivery monitoring.
   *
   * @param connection
   * @param orderId Target order's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_shipments table by joining with shopping_mall_order_items. Filter shipments where order_items.shopping_mall_order_id matches the orderId parameter. Include carrier information, tracking numbers, and delivery status. Return paginated results with sorting by creation timestamp (newest first).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string,
  ): Promise<IPageIShoppingMallShipment> {
    try {
      return await getShoppingMallCustomerOrdersOrderIdShipments({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
