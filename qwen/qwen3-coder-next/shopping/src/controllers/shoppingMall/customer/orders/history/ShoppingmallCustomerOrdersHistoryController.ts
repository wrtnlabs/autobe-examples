import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallOrder } from "../../../../../api/structures/IPageIShoppingMallOrder";
import { IShoppingMallOrder } from "../../../../../api/structures/IShoppingMallOrder";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerOrdersHistory } from "../../../../../providers/patchShoppingMallCustomerOrdersHistory";

@Controller("/shoppingMall/customer/orders/history")
export class ShoppingmallCustomerOrdersHistoryController {
  /**
   * Retrieve a paginated list of customer order history.
   *
   * This operation provides access to all past and current orders placed by the authenticated customer. It supports comprehensive pagination with configurable page sizes and sorting by newest first (default behavior).
   *
   * The endpoint returns order summary information optimized for order history displays, including order number, date, total price, and overall order status derived from its items.
   *
   * @param connection
   * @param body Pagination and sorting parameters for order history
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_orders table filtered by authenticated customer ID.
   * Apply pagination with configurable page size and offset.
   * Sort by created_at in descending order (newest first).
   * Return paginated results with order summary information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallOrder.IRequest,
  ): Promise<IPageIShoppingMallOrder.ISummary> {
    try {
      return await patchShoppingMallCustomerOrdersHistory({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
