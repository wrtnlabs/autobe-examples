import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallOrderItem } from "../../../../../api/structures/IPageIShoppingMallOrderItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersOrderIdItems } from "../../../../../providers/getShoppingMallCustomerOrdersOrderIdItems";

@Controller("/shoppingMall/customer/orders/:orderId/items")
export class ShoppingmallCustomerOrdersItemsController {
  /**
   * Retrieve all order items associated with a specific order.
   *
   * This endpoint provides comprehensive access to order items for both customer self-service and administrative oversight purposes. Customers can view their own order items to track purchase history, while administrators can access all order items across the platform for dispute resolution, order management, and compliance purposes.
   *
   * The operation returns detailed information about each order item including the product name, variant options, quantity, unit price, total price, and current status. This enables customers and administrators to understand the complete composition of any order on the platform.
   *
   * @param connection
   * @param orderId Target order's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_order_items table filtered by shopping_mall_order_id path parameter. Apply appropriate authorization checks - customers can only access their own order items, administrators can view all. Return paginated results with item details including product name, variant options, quantity, pricing, and status. Implement proper sorting by created_at timestamp for consistent ordering.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string,
  ): Promise<IPageIShoppingMallOrderItem.ISummary> {
    try {
      return await getShoppingMallCustomerOrdersOrderIdItems({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
