import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallShoppingCart } from "../../../../../api/structures/IShoppingMallShoppingCart";
import { IShoppingMallShoppingCartItem } from "../../../../../api/structures/IShoppingMallShoppingCartItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { deleteShoppingMallCustomerCartsItemsCartItemId } from "../../../../../providers/deleteShoppingMallCustomerCartsItemsCartItemId";
import { postShoppingMallCustomerCartsItems } from "../../../../../providers/postShoppingMallCustomerCartsItems";
import { putShoppingMallCustomerCartsItemsCartItemId } from "../../../../../providers/putShoppingMallCustomerCartsItemsCartItemId";

@Controller("/shoppingMall/customer/carts/items")
export class ShoppingmallCustomerCartsItemsController {
  /**
   * Add product variant to customer's shopping cart.
   *
   * This operation allows customers to add product variants to their shopping cart with specified quantities. When a customer adds a variant that already exists in their cart, the system automatically combines quantities rather than creating duplicate cart items.
   *
   * The operation validates stock availability, product availability, and enforces quantity limits. It supports the complete shopping cart workflow from initial item addition through checkout.
   *
   * Security considerations: Customers can only add items to their own cart. The system enforces customer ownership through authentication.
   *
   * @param connection
   * @param body Product variant and quantity for cart addition
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Add product variant to customer's shopping cart. Validates stock availability, handles quantity combination for existing variants, and creates new cart item records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallShoppingCartItem.ICreate,
  ): Promise<IShoppingMallShoppingCartItem> {
    try {
      return await postShoppingMallCustomerCartsItems({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shopping cart item with new quantity.
   *
   * This endpoint allows customers to modify the quantity of a specific product variant in their shopping cart. The cart item is identified by its cart item ID, and the new quantity is specified in the request body.
   *
   * When updating cart quantity, the system validates that the new quantity does not exceed the available stock for that product variant. The cart item's updated_at timestamp is automatically refreshed to reflect the modification.
   *
   * After updating the cart item, the system recalculates the cart totals for all items in the customer's shopping cart. This ensures accurate pricing information is available for checkout.
   *
   * @param connection
   * @param cartItemId Cart item identifier
   * @param body New quantity for the cart item
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update shopping cart item quantity for the authenticated customer.
   *
   * 1. Retrieve cart item by ID with customer ownership verification
   * 2. Validate new quantity is positive integer
   * 3. Validate new quantity does not exceed available stock for variant
   * 4. Update cart item quantity in database
   * 5. Update cart item updated_at timestamp
   * 6. Recalculate cart totals for customer
   * 7. Return updated cart item with current state
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":cartItemId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartItemId")
    cartItemId: string,
    @TypedBody()
    body: IShoppingMallShoppingCart.IUpdate,
  ): Promise<IShoppingMallShoppingCart> {
    try {
      return await putShoppingMallCustomerCartsItemsCartItemId({
        customer,
        cartItemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific shopping cart item for the authenticated customer.
   *
   * This operation removes a shopping cart item from the customer's cart. The customer must be authenticated and can only delete their own cart items.
   *
   * The cart item is identified by its unique ID in the path parameter. The system validates that the authenticated customer owns the cart item before deletion.
   *
   * If the cart item exists and belongs to the customer, it is permanently removed from the customer's cart. The operation does not affect other cart items or the customer's account.
   *
   * This operation is typically called after the customer decides to remove an item from their shopping cart during the browsing or checkout process.
   *
   * Related operations:
   *
   * - GET /cart: Retrieve the customer's current cart with all items
   * - POST /cart/items: Add a new item to the customer's cart
   * - PUT /cart/items/:itemId: Update the quantity of an existing cart item
   *
   * @param connection
   * @param cartItemId The unique identifier of the shopping cart item to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Delete a shopping cart item record by ID.
   *
   * The service should:
   *
   * 1. Extract cartItemId from path parameter
   * 2. Load authenticated customer ID from JWT token
   * 3. Query shopping_mall_shopping_carts table for record where id = cartItemId AND shopping_mall_customer_id = customerId
   * 4. If record not found, throw NotFoundError
   * 5. If record found, delete the record from shopping_mall_shopping_carts table
   * 6. Return HTTP 204 No Content response
   *
   * Business rules:
   *
   * - Only the cart item owner can delete their cart items
   * - Cart items cannot be deleted by other customers or sellers
   * - System admins cannot delete customer cart items (unlike orders/products)
   * - Deletion is permanent (no soft delete)
   * - Cart item quantity is reduced to 0 (effectively removed)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":cartItemId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartItemId")
    cartItemId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerCartsItemsCartItemId({
        customer,
        cartItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
