import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallShoppingCart } from "../../../../api/structures/IPageIShoppingMallShoppingCart";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerCarts } from "../../../../providers/getShoppingMallCustomerCarts";

@Controller("/shoppingMall/customer/carts")
export class ShoppingmallCustomerCartsController {
  /**
   * Retrieve all shopping cart items for the authenticated customer.
   *
   * This operation provides comprehensive shopping cart information including product variant details, stock availability, and pricing information. The system displays stock warnings for items with insufficient stock and marks items as unavailable when variants are completely out of stock, preventing checkout with invalid items.
   *
   * This is a read-only operation that requires customer authentication. The response includes paginated results with configurable page sizes.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_shopping_carts table joined with shopping_mall_product_variants and shopping_mall_products tables.
   * Include variant option values for product identification.
   * Calculate stock availability compared to cart quantity.
   * Mark items as unavailable when variant is deleted or quantity is 0.
   * Return all cart items for the authenticated customer.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IPageIShoppingMallShoppingCart.ISummary> {
    try {
      return await getShoppingMallCustomerCarts({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
