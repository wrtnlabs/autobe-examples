import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCartItem } from "../../../../../api/structures/IShoppingMallCartItem";
import { IShoppingMallShoppingCart } from "../../../../../api/structures/IShoppingMallShoppingCart";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { deleteShoppingMallCustomerCartItemsCartItemId } from "../../../../../providers/deleteShoppingMallCustomerCartItemsCartItemId";
import { postShoppingMallCustomerCartItems } from "../../../../../providers/postShoppingMallCustomerCartItems";
import { putShoppingMallCustomerCartItemsCartItemId } from "../../../../../providers/putShoppingMallCustomerCartItemsCartItemId";

@Controller("/shoppingMall/customer/cart/items")
export class ShoppingmallCustomerCartItemsController {
  /**
   * Add a product variant to the customer's shopping cart.
   *
   * This operation creates a new cart item when a customer wants to add a specific product variant to their cart. The system performs several validation checks including stock availability verification and quantity validation.
   *
   * When adding items to cart, the system validates that:
   * - The customer is authenticated
   * - The variant exists and is available
   * - Stock quantity is sufficient for the requested quantity
   * - The cart does not exceed maximum item count
   *
   * If the same variant is already in the cart, the system combines quantities instead of creating duplicate line items. The quantity must be a positive integer and cannot exceed available stock.
   *
   * @param connection
   * @param body Cart item creation request with variant and quantity
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create shopping cart item for customer. Validate customer authentication, variant availability, and stock quantity. Check if variant already exists in customer's cart - if so, combine quantities instead of creating duplicate item. Create new cart item record with customer_id, variant_id, quantity, and current timestamp. Return created cart item with computed subtotal (quantity × variant price).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallShoppingCart.ICreate,
  ): Promise<IShoppingMallShoppingCart.ISummary> {
    try {
      return await postShoppingMallCustomerCartItems({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing cart item with new quantity.
   *
   * This operation allows customers to modify the quantity of a product variant in their shopping cart. The system validates that the requested quantity does not exceed available stock and handles cases where the product variant becomes unavailable.
   *
   * The cart item update respects the business rules established during cart creation: quantities are combined when the same variant is added, and unavailable items are marked appropriately. Stock validation ensures customers cannot order more items than available.
   *
   * When a variant's stock is insufficient, the system displays a warning in the cart. When a variant is deleted or goes out of stock, the item is marked as unavailable in the cart. This update operation enforces these same validation rules at the time of modification.
   *
   * @param connection
   * @param cartItemId Target cart item's unique identifier
   * @param body Update request containing new quantity for the cart item
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update the quantity of a shopping cart item identified by cartItemId.
   *
   * 1. Load the cart item by ID and verify it belongs to the authenticated customer
   * 2. Validate that the new quantity is a positive integer
   * 3. Check stock availability for the variant by querying variant stock quantity
   * 4. If stock is insufficient, return validation error
   * 5. If the variant has been deleted or is no longer available, mark item as unavailable
   * 6. Update the cart item quantity in database
   * 7. Return the updated cart item with recalculated subtotal
   * 8. Handle edge cases: deleted variant, out of stock, stock change during update
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":cartItemId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartItemId")
    cartItemId: string,
    @TypedBody()
    body: IShoppingMallCartItem.IUpdate,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await putShoppingMallCustomerCartItemsCartItemId({
        customer,
        cartItemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove an item from the customer's shopping cart.
   *
   * This operation permanently removes the specified cart item record from the database. After removal, the customer's cart totals will be automatically recalculated based on the remaining items.
   *
   * The system validates that the cart item belongs to the authenticated customer before deletion to prevent unauthorized removal of other customers' cart items.
   *
   * @param connection
   * @param cartItemId The unique identifier of the cart item to remove
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Delete a specific shopping cart item by its ID.
   * 1. Retrieve cart item by ID
   * 2. Validate ownership (customer_id matches authenticated user)
   * 3. Delete cart item record from database
   * 4. Return success response with removed item details or null
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":cartItemId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartItemId")
    cartItemId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerCartItemsCartItemId({
        customer,
        cartItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
