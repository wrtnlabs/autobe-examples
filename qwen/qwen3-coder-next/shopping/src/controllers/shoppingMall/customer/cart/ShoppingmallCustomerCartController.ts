import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallShoppingCart } from "../../../../api/structures/IPageIShoppingMallShoppingCart";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerCart } from "../../../../providers/getShoppingMallCustomerCart";

@Controller("/shoppingMall/customer/cart")
export class ShoppingmallCustomerCartController {
  /**
   * Retrieve the customer's shopping cart with all items and product details.
   *
   * This operation fetches all items in the current customer's shopping cart, including detailed product information, variant options, and pricing. The cart is specific to each customer and shows all products they have added for potential purchase.
   *
   * Security considerations: Customers can only access their own cart. The system enforces customer ownership validation.
   *
   * The response includes pagination support for large cart items and displays product thumbnails, names, and prices for easy browsing.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_shopping_carts table joined with product variants and main products.
   * Filter by current customer's ID from authentication context.
   * Include product images, variant options, and pricing information.
   * Return paginated results with configurable page size.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IPageIShoppingMallShoppingCart.ISummary> {
    try {
      return await getShoppingMallCustomerCart({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
