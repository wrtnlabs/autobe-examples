import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSystemConfiguration } from "../../../../api/structures/IShoppingMallSystemConfiguration";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerStatus } from "../../../../providers/getShoppingMallCustomerStatus";

@Controller("/shoppingMall/customer/status")
export class ShoppingmallCustomerController {
  /**
   * Retrieve system health status and platform information.
   *
   * This endpoint provides a simple health check for the shopping mall platform, returning the current operational status and system information. It can be used by load balancers, monitoring services, or administrators to quickly verify that the platform is running.
   *
   * The response includes the current system status, the current timestamp, and basic service information.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Return system health status with current timestamp and service information. Simple read-only endpoint that checks database connectivity and basic service health.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async status(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IShoppingMallSystemConfiguration> {
    try {
      return await getShoppingMallCustomerStatus({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
