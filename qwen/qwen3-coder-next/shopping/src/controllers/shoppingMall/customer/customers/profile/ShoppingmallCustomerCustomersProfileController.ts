import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../../api/structures/IShoppingMallCustomer";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerCustomersProfile } from "../../../../../providers/putShoppingMallCustomerCustomersProfile";

@Controller("/shoppingMall/customer/customers/profile")
export class ShoppingmallCustomerCustomersProfileController {
  /**
   * Update customer profile information.
   *
   * This endpoint allows authenticated customers to update their profile information including display name and phone number. The system validates the phone number format and updates the customer record.
   *
   * The updated profile information is immediately reflected across the platform, and any changes are persisted to the database.
   *
   * @param connection
   * @param body Customer profile update data
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update customer profile in shopping_mall_customers table.
   * Validate display_name length (1-50 characters) and phone_number format.
   * Update updated_at timestamp.
   * Return updated customer record with all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async updateProfile(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCustomer.IUpdate,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await putShoppingMallCustomerCustomersProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
