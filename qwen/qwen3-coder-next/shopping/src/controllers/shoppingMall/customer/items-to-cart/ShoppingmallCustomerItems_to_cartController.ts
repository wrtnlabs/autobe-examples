import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCart } from "../../../../api/structures/IShoppingMallCart";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { postShoppingMallCustomerItemsToCart } from "../../../../providers/postShoppingMallCustomerItemsToCart";

@Controller("/shoppingMall/customer/items-to-cart")
export class ShoppingmallCustomerItems_to_cartController {
  /**
   * Add product variant to customer shopping cart
   *
   * This operation allows authenticated customers to add specific product variants to their shopping cart for potential future purchase. The shopping cart serves as an intermediate state between product browsing and final order placement, enabling customers to collect multiple items before proceeding to checkout.
   *
   * The operation handles several important business rules:
   *
   * - **Duplicate Prevention**: If the same variant is already in the cart, quantities are combined rather than creating duplicate entries, ensuring clean cart management
   * - **Stock Validation**: The system validates that sufficient stock is available before adding the item, preventing invalid cart additions
   * - **Customer Ownership**: Cart items are automatically associated with the authenticated customer, ensuring proper cart isolation between users
   * - **Availability Monitoring**: Cart items remain synchronized with product availability - items become unavailable if variants are deleted or run out of stock
   * - **Quantity Management**: Customers can later modify quantities or remove items from their cart before checkout
   *
   * From a user experience perspective, this operation enables the core shopping workflow where customers can browse products, add items to their cart for review, adjust quantities, and eventually proceed to checkout when ready to purchase. The cart serves as a temporary holding area that preserves customers' selection while they continue shopping or prepare for final purchase.
   *
   * The cart item lifecycle includes creation with quantity selection, potential quantity modifications, availability updates as stock changes, and eventual removal either through successful order placement (which clears the cart) or manual deletion by the customer.
   *
   * @param connection
   * @param body Cart item creation data including variant selection and quantity
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create new shopping cart item by associating a product variant with the authenticated customer. Validate that requested quantity does not exceed available stock. If cart item already exists for same variant, increment quantity instead of creating duplicate. Link cart item to authenticated customer's profile automatically. Set created_at timestamp to current time and updated_at to same value. Return complete cart item with all related data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async addToCart(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCart.ICreate,
  ): Promise<IShoppingMallCart> {
    try {
      return await postShoppingMallCustomerItemsToCart({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
