import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallShipment } from "../../../../api/structures/IPageIShoppingMallShipment";
import { IShoppingMallOrderDeliveryConfirmation } from "../../../../api/structures/IShoppingMallOrderDeliveryConfirmation";
import { IShoppingMallShipment } from "../../../../api/structures/IShoppingMallShipment";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerShipments } from "../../../../providers/patchShoppingMallCustomerShipments";
import { postShoppingMallCustomerShipmentsShipmentIdConfirm } from "../../../../providers/postShoppingMallCustomerShipmentsShipmentIdConfirm";

@Controller("/shoppingMall/customer/shipments")
export class ShoppingmallCustomerShipmentsController {
  /**
   * Confirm receipt of a shipment.
   *
   * This endpoint allows customers to manually confirm that they have received their shipment. Upon confirmation, all items in the shipment change their status to "delivered", enabling customers to write reviews for the products.
   *
   * The system also supports automatic delivery confirmation when customers do not manually confirm within 14 days of shipment. Once a shipment is marked as delivered (either manually or automatically), no further delivery confirmation is possible.
   *
   * @param connection
   * @param shipmentId Shipment ID to confirm delivery for
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Process shipment delivery confirmation:
   * 1. Validate shipment exists and belongs to customer
   * 2. Verify shipment status is 'shipped' (not already delivered)
   * 3. Check customer authorization (only order owner can confirm)
   * 4. Create delivery confirmation record with IP address and timestamp
   * 5. Update shipment status to 'delivered'
   * 6. Update all shipment items to 'delivered' status
   * 7. Update order status based on item statuses
   * 8. Log confirmation event for audit trail
   * 9. Return success response with confirmation timestamp
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":shipmentId/confirm")
  public async confirm(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string,
  ): Promise<IShoppingMallOrderDeliveryConfirmation.IResponse> {
    try {
      return await postShoppingMallCustomerShipmentsShipmentIdConfirm({
        customer,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of shipment records for the authenticated customer.
   *
   * This operation provides customers with access to all their order shipments, enabling them to track delivery status, view carrier information, and monitor the progress of their purchased items. The endpoint supports filtering by shipment status and date range to help customers find specific shipments efficiently.
   *
   * Security considerations include ensuring customers can only access their own shipments through the authenticated customer context. The response includes tracking information from shipping carriers and delivery confirmation timestamps.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for shipment filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_shipments table with pagination and filtering. Join with shopping_mall_orders and shopping_mall_order_items to get complete shipment details. Apply status filtering (pending, in_transit, delivered, cancelled) and date range filtering. Include tracking information from carrier. Return paginated results with total count for client-side pagination controls.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallShipment.IRequest,
  ): Promise<IPageIShoppingMallShipment> {
    try {
      return await patchShoppingMallCustomerShipments({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
