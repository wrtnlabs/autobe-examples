import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallShipment } from "../../../../../api/structures/IShoppingMallShipment";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerShipmentsShipmentIdTracking } from "../../../../../providers/getShoppingMallCustomerShipmentsShipmentIdTracking";

@Controller("/shoppingMall/customer/shipments/:shipmentId/tracking")
export class ShoppingmallCustomerShipmentsTrackingController {
  /**
   * Retrieve tracking information for a specific shipment.
   *
   * This endpoint provides detailed tracking information for a shipment including the carrier name, tracking number, current status, and timestamps for shipping, customer confirmation, and automatic confirmation.
   *
   * ## Security Considerations
   *
   * - Only the seller who created the shipment and the customer who placed the order can access this information
   * - Authentication is required to access shipment tracking details
   * - Authorization checks ensure sellers can only view their own shipments and customers can only view their own orders' shipments
   *
   * ## Database Entities
   *
   * This endpoint retrieves data from the `shopping_mall_shipments` table which contains:
   * - `id`: Primary key for the shipment
   * - `shopping_mall_order_id`: Reference to the order this shipment belongs to
   * - `shopping_mall_seller_id`: Reference to the seller who created this shipment
   * - `tracking_number`: Unique tracking number provided by the carrier
   * - `tracking_carrier`: Name of the shipping carrier
   * - `status`: Current status of the shipment (pending, in_transit, delivered, cancelled)
   * - `shipped_at`: Timestamp when the seller shipped the items
   * - `customer_confirmed_at`: Timestamp when the customer manually confirmed delivery
   * - `auto_confirmed_at`: Timestamp when delivery was automatically confirmed after 14 days
   * - `cancelled_at`: Timestamp when the shipment was cancelled
   *
   * ## Related Operations
   *
   * - `GET /shipments` - List all shipments for the authenticated user (seller or customer)
   * - `POST /shipments` - Create a new shipment (seller only)
   * - `PUT /shipments/{shipmentId}` - Update shipment tracking information (seller only)
   *
   * ## Expected Behavior
   *
   * - Returns 404 if the shipment does not exist or the user does not have permission to view it
   * - Returns 401 if the user is not authenticated
   * - Returns the complete shipment tracking information including all timestamps
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment to retrieve tracking information for
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_shipments table by id to retrieve complete shipment tracking information. Include the order and seller relationships to ensure proper authorization. Return shipment details with all tracking fields including shipped_at, customer_confirmed_at, auto_confirmed_at, and cancelled_at timestamps if they exist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string,
  ): Promise<IShoppingMallShipment> {
    try {
      return await getShoppingMallCustomerShipmentsShipmentIdTracking({
        customer,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
