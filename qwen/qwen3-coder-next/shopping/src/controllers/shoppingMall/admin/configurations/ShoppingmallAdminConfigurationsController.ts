import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallSystemConfiguration } from "../../../../api/structures/IPageIShoppingMallSystemConfiguration";
import { IShoppingMallSystemConfiguration } from "../../../../api/structures/IShoppingMallSystemConfiguration";
import { IShoppingMallSystemConfigurationValue } from "../../../../api/structures/IShoppingMallSystemConfigurationValue";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminConfigurations } from "../../../../providers/patchShoppingMallAdminConfigurations";
import { postShoppingMallAdminConfigurations } from "../../../../providers/postShoppingMallAdminConfigurations";
import { putShoppingMallAdminConfigurationsConfigurationId } from "../../../../providers/putShoppingMallAdminConfigurationsConfigurationId";

@Controller("/shoppingMall/admin/configurations")
export class ShoppingmallAdminConfigurationsController {
  /**
   * Create a new system configuration setting for the shopping mall platform.
   *
   * This endpoint allows administrators to add new configuration settings that affect the entire platform. Configuration settings can include theme preferences, feature flags, and global system parameters.
   *
   * The configuration is created with a unique configuration key that serves as the identifier for this setting. The configuration can be categorized for organizational purposes and can be enabled or disabled as needed.
   *
   * When a configuration is created, the system automatically initializes it with a default active value and creates the configuration record in the database. Administrators can later modify configuration values through the dedicated configuration value management endpoints.
   *
   * @param connection
   * @param body Configuration setting creation parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new shopping_mall_system_configurations record with provided configuration details.
   * Generate unique UUID for configuration ID.
   * Set created_at and updated_at timestamps to current time.
   * Initialize is_enabled flag based on request parameter.
   * Create initial shopping_mall_system_configuration_values record with is_active flag.
   * Return full configuration object including generated ID and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSystemConfiguration.ICreate,
  ): Promise<IShoppingMallSystemConfiguration> {
    try {
      return await postShoppingMallAdminConfigurations({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Query system configuration settings with search filters and pagination.
   *
   * This operation provides administrators with comprehensive access to view and filter system configuration settings across the platform. It supports filtering by configuration key, category, and active status, enabling efficient configuration management and audit operations.
   *
   * The system configuration system allows administrators to manage platform-wide settings including theme preferences, feature flags, and global parameters that affect the entire shopping mall platform. All configuration changes are tracked with audit logs for compliance purposes.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_system_configurations table with pagination and filtering.
   * Apply search filters on config_key, category, and is_enabled status.
   * Include related configuration values with their current states.
   * Return paginated results with comprehensive configuration metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSystemConfiguration.IRequest,
  ): Promise<IPageIShoppingMallSystemConfiguration.ISummary> {
    try {
      return await patchShoppingMallAdminConfigurations({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update system configuration setting
   *
   * This API endpoint allows administrators to modify the values of system-wide configuration settings. Configuration settings control various platform parameters such as feature flags, thresholds, and global system behavior. The update operation creates a new version of the configuration value while preserving the previous versions in the history.
   *
   * The endpoint requires a valid configuration identifier and accepts the updated configuration value in the appropriate data type format. Administrative authorization is required to perform this operation.
   *
   * The system maintains a complete audit trail of all configuration changes through the system audit logs table, recording who made the change, when it was made, and what values were modified.
   *
   * @param connection
   * @param configurationId Unique identifier of the configuration setting to update
   * @param body Updated configuration value with data type specification
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update shopping_mall_system_configuration_values record by configurationId.
   * Validate administrative access before allowing update.
   * Archive existing configuration value by setting is_active = false and deleted_at = now().
   * Create new configuration value record with provided data and is_active = true.
   * Record audit log entry for the configuration change.
   * Return the newly created configuration value record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":configurationId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("configurationId")
    configurationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSystemConfigurationValue.ICreate,
  ): Promise<IShoppingMallSystemConfigurationValue> {
    try {
      return await putShoppingMallAdminConfigurationsConfigurationId({
        admin,
        configurationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
