import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { postShoppingMallAdminCustomersCustomerIdUnbans } from "../../../../../providers/postShoppingMallAdminCustomersCustomerIdUnbans";

@Controller("/shoppingMall/admin/customers/:customerId/unbans")
export class ShoppingmallAdminCustomersUnbansController {
  /**
   * Unban a customer account to restore their access to platform features.
   *
   * This operation allows administrators to reverse customer bans, restoring the customer's ability to log in to their account and access all platform features. When a customer is unbanned, their account status changes from 'banned' to 'active', their authentication capability is restored, and they can resume normal platform usage.
   *
   * The system will notify the customer of the account restoration via their preferred communication channels. All previously preserved customer data (order history, wishlist, shopping cart) will be restored and accessible upon their next login.
   *
   * This operation is part of the customer account management system and is typically used when customers have completed their ban period or when bans were issued in error that have been reviewed and reversed by administrators.
   *
   * @param connection
   * @param customerId The unique identifier of the customer account to unban
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update customer account status from 'banned' to 'active' in the shopping_mall_customers table. Record the unban action in system audit logs with timestamp, administrator ID, and reason. Invalidate any active sessions for the customer. Notify the customer via email and app notification of account restoration. Return the updated customer record with status 'active'.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async unban(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string,
  ): Promise<void> {
    try {
      return await postShoppingMallAdminCustomersCustomerIdUnbans({
        admin,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
