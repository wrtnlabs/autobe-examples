import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallSystematicLog } from "../../../../api/structures/IPageIShoppingMallSystematicLog";
import { IShoppingMallSystematicConfig } from "../../../../api/structures/IShoppingMallSystematicConfig";
import { IShoppingMallSystematicLog } from "../../../../api/structures/IShoppingMallSystematicLog";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminLogsLogId } from "../../../../providers/getShoppingMallAdminLogsLogId";
import { patchShoppingMallAdminLogs } from "../../../../providers/patchShoppingMallAdminLogs";
import { patchShoppingMallAdminLogsAnalytics } from "../../../../providers/patchShoppingMallAdminLogsAnalytics";

@Controller("/shoppingMall/admin/logs")
export class ShoppingmallAdminLogsController {
  /**
   * Retrieve filtered and paginated system event logs for monitoring and debugging purposes.
   *
   * This operation provides comprehensive log retrieval capabilities with multi-criteria filtering including date ranges, log levels, event types, components, and search filters. It supports detailed log analysis and troubleshooting workflows.
   *
   * The system maintains comprehensive audit trails for security and compliance purposes, with logs stored for minimum 90 days. Log access is restricted to authorized administrators and super administrators based on the specific log content and sensitivity.
   *
   * @param connection
   * @param body Log query criteria including date ranges, log levels, components, and search filters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the shopping_mall_systematic_logs table with comprehensive filtering and pagination support. Apply filters for date ranges, log levels, event types, components, and user IDs. Join with related tables for enriched log context. Return cursor-based pagination for efficient large dataset handling. Implement access control based on user role (admin/superAdmin only).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSystematicLog.IRequest,
  ): Promise<IPageIShoppingMallSystematicLog.ISummary> {
    try {
      return await patchShoppingMallAdminLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific system event log entry.
   *
   * This operation provides access to individual system logs that track all system events including errors, warnings, info messages, and debug information. It supports comprehensive debugging and monitoring by providing complete log details including timestamps, severity levels, component names, and contextual information.
   *
   * The operation retrieves complete log entry information with all available details including request context, performance metrics, and stack traces for error-level events. This enables developers and administrators to investigate specific events with full context and detailed diagnostic information.
   *
   * @param connection
   * @param logId Target log entry's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_systematic_logs table by ID to retrieve complete log entry.
   * Return all fields including timestamp, severity, component, message, context, trace_id, user_id, ip, method, path, status_code, duration_ms, and stack_trace.
   * Handle cases where log entry doesn't exist with appropriate error response.
   * Include performance metrics and stack trace for error-level events when available.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":logId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("logId")
    logId: string,
  ): Promise<IShoppingMallSystematicLog> {
    try {
      return await getShoppingMallAdminLogsLogId({
        admin,
        logId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve comprehensive system analytics and operational insights.
   *
   * This operation provides aggregate analytics data across the platform's systematic monitoring system, including error rates, response times, uptime statistics, and resource utilization metrics. The analytics are derived from the systematic logs and status records, providing actionable insights for system health monitoring and performance optimization.
   *
   * This endpoint serves as the primary interface for system administrators and platform operators to understand overall platform performance, identify trends, and make informed decisions about system maintenance and resource allocation.
   *
   * @param connection
   * @param body Analytics query parameters and filters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query systematic logs and status records to compute aggregate analytics.
   * Filter logs by time range, severity, and component.
   * Calculate metrics including error rates, average response times, uptime percentages, and resource utilization.
   * Combine data from shopping_mall_systematic_logs and shopping_mall_systematic_statuses tables.
   * Return time-series data for trend analysis and point-in-time snapshots for current status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("analytics")
  public async analytics(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSystematicConfig.IRequest,
  ): Promise<IShoppingMallSystematicConfig.IResponse> {
    try {
      return await patchShoppingMallAdminLogsAnalytics({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
