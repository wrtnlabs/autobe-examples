import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCategory } from "../../../../api/structures/IShoppingMallCategory";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteShoppingMallAdminCategoriesCategoryId } from "../../../../providers/deleteShoppingMallAdminCategoriesCategoryId";
import { postShoppingMallAdminCategories } from "../../../../providers/postShoppingMallAdminCategories";
import { putShoppingMallAdminCategoriesCategoryId } from "../../../../providers/putShoppingMallAdminCategoriesCategoryId";

@Controller("/shoppingMall/admin/categories")
export class ShoppingmallAdminCategoriesController {
  /**
   * Create a new product category for organizing the e-commerce catalog.
   *
   * This endpoint allows administrators to define new top-level categories that can be used to categorize products. Categories enable hierarchical navigation and product discovery for customers. Each category can have multiple subcategories but only one parent category.
   *
   * Category creation requires administrative privileges and enforces name uniqueness across the platform. Once created, categories can be used to classify products and provide organized browsing experiences for customers.
   *
   * @param connection
   * @param body Category creation data including name and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new shopping_mall_categories record with the provided name and description.
   * Validate that category name is unique across the platform.
   * Return the newly created category with system-generated fields (id, timestamps).
   * Ensure proper timestamp formatting with timestamptz types.
   * Enforce authorization check to verify admin/superAdmin role access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCategory.ICreate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await postShoppingMallAdminCategories({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product category's information.
   *
   * This operation allows authorized administrators to modify the details of existing product categories in the platform's category hierarchy. Administrators can update category names and descriptions to maintain accurate product organization and navigation.
   *
   * Security considerations: This operation requires administrator or super administrator privileges. Regular customers and sellers cannot modify category information.
   *
   * The operation preserves category ID and automatically manages timestamp fields for audit tracking. The system maintains complete history of all category changes through snapshot records for compliance and dispute resolution purposes.
   *
   * @param connection
   * @param categoryId Unique identifier of the category to update
   * @param body Category update data containing new name and description values
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update the specified category with new name and description values. Load existing category, validate administrator permissions, apply updates to name and description fields, update timestamps (updated_at), and return the updated category record. Ensure category exists before attempting update.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string,
    @TypedBody()
    body: IShoppingMallCategory.IUpdate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await putShoppingMallAdminCategoriesCategoryId({
        admin,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a product category from the system.
   *
   * This operation permanently removes a category from the platform. When a category is deleted, all products that belonged to that category are automatically reclassified as 'uncategorized' to maintain product accessibility.
   *
   * The operation requires administrative authorization - either regular admin or super admin role. This ensures only authorized personnel can modify the category hierarchy, protecting the platform's product organization structure.
   *
   * Security considerations include verifying the requesting user has appropriate admin privileges before performing the deletion.
   *
   * @param connection
   * @param categoryId Unique identifier of the category to be deleted
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Delete product category from the database.
   *
   * 1. Verify user has admin or super admin role
   * 2. Find category by ID
   * 3. Check if category exists and is not already deleted
   * 4. Delete category record from shopping_mall_categories table
   * 5. Update all products in that category to 'uncategorized' status
   * 6. Return success response
   *
   * Error handling:
   * - 401: Unauthorized if user lacks admin privileges
   * - 403: Forbidden if user lacks required permissions
   * - 404: Not found if category ID does not exist
   * - 409: Conflict if category has products that cannot be uncategorized
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCategoriesCategoryId({
        admin,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
