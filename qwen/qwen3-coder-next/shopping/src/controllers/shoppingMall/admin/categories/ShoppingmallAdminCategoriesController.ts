import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallCategory } from "../../../../api/structures/IPageIShoppingMallCategory";
import { IShoppingMallCategory } from "../../../../api/structures/IShoppingMallCategory";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteShoppingMallAdminCategoriesCategoryId } from "../../../../providers/deleteShoppingMallAdminCategoriesCategoryId";
import { patchShoppingMallAdminCategories } from "../../../../providers/patchShoppingMallAdminCategories";
import { postShoppingMallAdminCategories } from "../../../../providers/postShoppingMallAdminCategories";
import { putShoppingMallAdminCategoriesCategoryId } from "../../../../providers/putShoppingMallAdminCategoriesCategoryId";

@Controller("/shoppingMall/admin/categories")
export class ShoppingmallAdminCategoriesController {
  /**
   * Create a new product category in the shopping mall platform.
   *
   * This operation allows administrators to establish product category structure that organizes products throughout the platform. Categories can be created as root categories (top-level) or as subcategories under existing parent categories.
   *
   * Category hierarchy supports exactly one level of nesting - categories can have a parent but cannot have subcategories. This two-level structure (root category → subcategory) maintains simplicity while providing sufficient organization for product catalog management.
   *
   * **Authorization:** This operation requires administrator privileges. Only users with admin role can create new categories.
   *
   * **Hierarchy Rules:**
   * - Root categories have no parent category (parent_category_id is null)
   * - Subcategories must specify a valid parent category ID
   * - Subcategories inherit from their parent category in the hierarchy
   * - Category hierarchy cannot exceed two levels deep
   *
   * **Uniqueness:** Category names must be unique within the same parent category. Two root categories cannot have the same name, and two subcategories under the same parent cannot have the same name.
   *
   * **Business Impact:** Category creation affects the entire platform's product organization. All products must belong to a valid category, so category structure directly impacts product catalog organization and customer browsing experience.
   *
   * @param connection
   * @param body Category creation parameters including name, description, and optional parent category reference
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create new category record in shopping_mall_categories table.
   * Validate category name uniqueness within parent category.
   * Handle both root category creation (null parent_category_id) and subcategory creation (parent_category_id reference).
   * Return created category with auto-generated ID and hierarchy information.
   * Log administrative action for audit trail.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCategory.ICreate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await postShoppingMallAdminCategories({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of product categories.
   *
   * This operation provides comprehensive category browsing capabilities for customers navigating the product catalog. Categories are organized in a two-level hierarchy where root categories can have subcategories, but subcategories cannot have further nesting.
   *
   * Customers can filter categories by parent relationship, search by name, and browse the complete category tree structure. The response includes category summaries optimized for list displays with essential information for navigation.
   *
   * This operation is essential for category browsing in product discovery workflows and supports the complete category navigation experience across the shopping mall platform.
   *
   * @param connection
   * @param body Category search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_categories table with pagination and filtering.
   * Support filtering by parent_category_id for hierarchical navigation.
   * Support search by name with case-insensitive partial matching.
   * Include subcategory_count in response for UI tree display.
   * Return paginated results with configurable page size.
   * Apply default sorting by name ascending.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCategory.IRequest,
  ): Promise<IPageIShoppingMallCategory.ISummary> {
    try {
      return await patchShoppingMallAdminCategories({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing category in the category hierarchy.
   *
   * This operation allows administrators to modify category information including the display name, description, and parent category relationship. The system enforces a two-level hierarchy where categories can have at most one parent category.
   *
   * **Security and Authorization:**
   *
   * - **ADMIN-ONLY OPERATION**: This endpoint is exclusively accessible to administrator accounts with appropriate permissions
   * - Customer and seller accounts will receive 403 Forbidden responses
   * - Admin accounts must have category management permissions to modify category structure
   * - All changes create immutable snapshots for audit trail
   *
   * **Database Structure:**
   *
   * - Modifies the shopping_mall_categories table
   * - Creates category snapshot before changes
   * - Preserves parent-child relationship constraints
   * - Updates timestamps for audit purposes
   * - Uses soft delete pattern with deleted_at field
   *
   * **Business Rules:**
   *
   * - Category name must be unique within the same parent category
   * - Cannot create circular category relationships
   * - Parent category cannot be the category itself
   * - Subcategories inherit from parent category
   * - Category hierarchy cannot exceed two levels deep
   * - Soft delete is implemented using deleted_at timestamp field
   *
   * **Related Operations:**
   *
   * - `GET /categories` - List all categories for parent selection
   * - `POST /categories` - Create new category
   * - `DELETE /categories/{categoryId}` - Delete category (soft delete)
   *
   * **Expected Behavior:**
   *
   * - Returns updated category with new values
   * - Creates snapshot of category before changes
   * - Updates updated_at timestamp
   * - Maintains category hierarchy integrity
   * - Excludes soft-deleted categories from update operations
   *
   * @param connection
   * @param categoryId Target category's unique identifier
   * @param body Category update information
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update the shopping_mall_categories table with new category information.
   *
   * 1. Load target category by ID, verify it exists and is not soft-deleted
   * 2. Validate update data:
   *    - Category name must be unique within the same parent
   *    - Cannot create circular relationships
   *    - Parent category cannot be the category itself
   *    - Category hierarchy cannot exceed two levels
   * 3. Create category snapshot with current state before changes
   * 4. Update category fields (name, description, parent_category_id)
   * 5. Update updated_at timestamp
   * 6. Return updated category record
   * 7. Ensure database transaction atomicity
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string,
    @TypedBody()
    body: IShoppingMallCategory.IUpdate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await putShoppingMallAdminCategoriesCategoryId({
        admin,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a product category from the shopping mall platform.
   *
   * This operation permanently removes a product category from the platform's category hierarchy. When a category is deleted:
   *
   * - All products currently assigned to this category become uncategorized (category_id set to null)
   * - The category's name and description are preserved in a snapshot for historical reference
   * - Any subcategories under this category must be deleted first (parent-child relationship enforcement)
   * - The deletion creates an immutable audit log entry for compliance purposes
   *
   * The operation is restricted to administrator roles only, ensuring that only authorized personnel can modify the platform's category structure. This maintains data integrity and prevents accidental category removal that could impact product organization and customer navigation.
   *
   * Related Operations:
   * - GET /categories - Retrieve the complete category hierarchy
   * - POST /categories - Create new categories (administrative only)
   * - PUT /categories/{categoryId} - Update category information
   *
   * @param connection
   * @param categoryId Unique identifier of the category to delete (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Delete shopping_mall_categories table record by categoryId.
   * Before deletion:
   * 1. Verify the category has no subcategories (check parent_category_id references)
   * 2. If subcategories exist, return error 409 Conflict
   * 3. Move all products in this category to uncategorized (UPDATE shopping_mall_products SET category_id = NULL WHERE category_id = :categoryId)
   * 4. Create category snapshot preserving name and description for audit trail
   * 5. Soft delete the category (update deleted_at timestamp)
   * 6. Log deletion event to system audit log
   * 7. Return success response
   *
   * Use Prisma transaction for atomicity: move products, create snapshot, soft delete category, log audit event.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCategoriesCategoryId({
        admin,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
