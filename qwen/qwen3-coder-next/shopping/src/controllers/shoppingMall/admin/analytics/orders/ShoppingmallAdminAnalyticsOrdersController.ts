import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallOrder } from "../../../../../api/structures/IPageIShoppingMallOrder";
import { IShoppingMallOrder } from "../../../../../api/structures/IShoppingMallOrder";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminAnalyticsOrders } from "../../../../../providers/patchShoppingMallAdminAnalyticsOrders";

@Controller("/shoppingMall/admin/analytics/orders")
export class ShoppingmallAdminAnalyticsOrdersController {
  /**
   * Retrieve aggregated order analytics and metrics for the dashboard.
   *
   * This operation provides comprehensive order statistics including total order volume, revenue metrics, order status breakdowns, and performance indicators. The analytics are designed for administrative oversight and seller dashboard reporting.
   *
   * Key features include:
   * - Total order counts and revenue aggregation
   * - Order status breakdowns (paid, shipped, delivered, cancelled, refunded)
   * - Time-based trend analysis with configurable date ranges
   * - Seller-specific or platform-wide analytics
   * - Category performance insights
   * - Customer behavior metrics
   *
   * @param connection
   * @param body Analytics request parameters including date range, filters, and aggregation options
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query order analytics from shopping_mall_orders table with aggregations.
   * Apply date range filtering using created_at between start and end dates.
   * Apply status filtering for order status breakdowns.
   * Optionally filter by seller_id for seller-specific analytics.
   * Optionally filter by category_id for category performance.
   * Calculate aggregations: total_orders, total_revenue, avg_order_value, status_counts, monthly_trends.
   * Group by time period for trend analysis when requested.
   * Return analytics summary with breakdowns and trend data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallOrder.IRequest,
  ): Promise<IPageIShoppingMallOrder.IAnalytic> {
    try {
      return await patchShoppingMallAdminAnalyticsOrders({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
