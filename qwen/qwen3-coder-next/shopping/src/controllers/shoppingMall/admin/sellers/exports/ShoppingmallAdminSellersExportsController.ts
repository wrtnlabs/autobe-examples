import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSellerExports } from "../../../../../api/structures/IShoppingMallSellerExports";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminSellersSellerIdExports } from "../../../../../providers/patchShoppingMallAdminSellersSellerIdExports";

@Controller("/shoppingMall/admin/sellers/:sellerId/exports")
export class ShoppingmallAdminSellersExportsController {
  /**
   * Update seller data export request status and complete export process.
   *
   * This operation allows administrators to process pending seller export requests, update their status through the processing lifecycle, and provide completion results including file storage URLs or error information.
   *
   * ## Export Request Lifecycle
   *
   * Seller data exports are initiated by sellers for GDPR compliance and administrative oversight. The export request status follows this lifecycle:
   *
   * 1. **Pending**: Seller initiates export request with format (JSON/CSV/XML) and scope (profile/products/orders/inventory/all) preferences
   * 2. **Processing**: Administrator begins processing the export request
   * 3. **Completed**: Export finished successfully with file URL provided for download
   * 4. **Failed**: Export failed with error message recorded for troubleshooting
   *
   * ## Administrator Oversight
   *
   * This is an administrative function that allows platform administrators to:
   *
   * - Process pending export requests from sellers
   * - Monitor export processing progress
   * - Provide completion results (file URLs for successful exports)
   * - Record error information for failed exports
   * - Maintain audit trail of export processing actions
   *
   * ## Security and Compliance
   *
   * Seller data exports contain sensitive information including customer profile data, order history, product listings, and financial information. The system tracks:
   *
   * - Request timestamp (requested_at) for SLA monitoring
   * - Processing start time (started_at)
   * - Completion time (completed_at) for success cases
   * - Failure time (failed_at) and error messages for debugging
   * - File storage URL (file_url) for completed exports
   *
   * All export activities are logged in the system for compliance auditing.
   *
   * @param connection
   * @param sellerId Target seller's unique identifier (UUID format)
   * @param body Export request status update information including status transition, file URL for completed exports, or error message for failed exports
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Process seller data export request status updates through the export lifecycle.
   * Update export request status from pending to processing, then to completed or failed.
   * Store file URLs for successful exports or error messages for failed exports.
   * Track processing timestamps for audit trail and SLA monitoring.
   * Validate administrator authorization before processing export requests.
   * Update related seller statistics after export completion.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updateExportStatus(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string,
    @TypedBody()
    body: IShoppingMallSellerExports.IRequest,
  ): Promise<IShoppingMallSellerExports> {
    try {
      return await patchShoppingMallAdminSellersSellerIdExports({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
