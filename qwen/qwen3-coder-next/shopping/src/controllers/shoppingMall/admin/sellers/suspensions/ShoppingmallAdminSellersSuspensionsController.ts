import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSeller } from "../../../../../api/structures/IShoppingMallSeller";
import { IShoppingMallSellerSuspension } from "../../../../../api/structures/IShoppingMallSellerSuspension";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminSellersSellerIdSuspensions } from "../../../../../providers/patchShoppingMallAdminSellersSellerIdSuspensions";
import { postShoppingMallAdminSellersSellerIdSuspensions } from "../../../../../providers/postShoppingMallAdminSellersSellerIdSuspensions";

@Controller("/shoppingMall/admin/sellers/:sellerId/suspensions")
export class ShoppingmallAdminSellersSuspensionsController {
  /**
   * Create a temporary suspension for a seller account
   *
   * This operation temporarily disables a seller's ability to create new products, edit existing products, and process new orders while preserving their existing business operations including order fulfillment and customer service capabilities.
   *
   * The suspension can be configured with various block settings to control exactly which seller capabilities are restricted during the suspension period. All suspensions are logged in the shopping_mall_seller_suspensions table for comprehensive audit trail and dispute resolution purposes.
   *
   * This suspension system is designed to handle both administrator-initiated suspensions (for policy violations, compliance issues, or platform maintenance) and seller-initiated voluntary suspensions (for temporary business closures or personal reasons).
   *
   * **Suspension Block Controls:**
   *
   * - `full_block`: Completely blocks seller account access if true, or allows limited access if false
   * - `hide_products`: Hides all seller products from search results and category listings
   * - `block_orders`: Prevents seller from processing new order shipments
   * - `block_login`: Prevents seller from logging into their account
   *
   * **Suspension Status Flow:**
   *
   * 1. `pending` - Suspension created but not yet approved by administrator
   * 2. `approved` - Administrator has approved the suspension, making it active
   * 3. `active` - Suspension is currently in effect
   * 4. `expired` - Suspension period has naturally ended (if duration was specified)
   * 5. `revoked` - Administrator has提前 terminated the suspension early
   * 6. `rejected` - Administrator has rejected the pending suspension request
   *
   * **Business Rules:**
   *
   * - Sellers can request suspensions for their own accounts (e.g., for planned closures)
   * - Administrator suspensions are typically for policy violations or compliance issues
   * - When a suspension is revoked, the seller's account and capabilities are immediately restored
   * - The suspension history is permanently preserved in the database for audit purposes
   *
   * @param connection
   * @param sellerId Target seller's unique identifier for the suspension
   * @param body Suspension details including reason, duration, and block settings
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new seller suspension record in the shopping_mall_seller_suspensions table.
   *
   * 1. Validate that the seller exists (shopping_mall_sellers.id matches sellerId path parameter)
   * 2. Validate the request body fields: reason (required, string), duration_days (optional, integer), appeal_allowed (optional, boolean), full_block (optional, boolean), hide_products (optional, boolean), block_orders (optional, boolean), block_login (optional, boolean), admin_id (optional, string for seller-initiated), started_at (optional, datetime, defaults to current timestamp)
   * 3. Create the suspension record with status 'pending' initially
   * 4. If admin_id is provided, set admin_id field; otherwise null for seller-initiated
   * 5. If administrator_id is provided in request, set approving_admin_id to that value for immediate approval
   * 6. Set approved_at to current timestamp if immediate approval
   * 7. Set ended_at based on started_at + duration_days if duration is specified
   * 8. Return the created suspension record with all database-generated fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string,
    @TypedBody()
    body: IShoppingMallSellerSuspension.ICreate,
  ): Promise<IShoppingMallSellerSuspension> {
    try {
      return await postShoppingMallAdminSellersSellerIdSuspensions({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Manage seller account suspensions for temporary disablement while preserving business continuity.
   *
   * This endpoint allows administrators to suspend or unsuspend seller accounts, temporarily disabling selling capabilities while allowing sellers to continue processing existing orders. Suspended sellers can ship items from existing orders, respond to cancellation and refund requests, but cannot create new products or edit existing products.
   *
   * When a seller is suspended, their products are hidden from search and category listings, preventing new purchases while maintaining order fulfillment capabilities. The suspension system provides a fair intermediate enforcement action that protects the platform while preserving seller business continuity.
   *
   * This operation supports both suspension (temporary disablement) and unsuspension (restore to active status) operations through the same endpoint, allowing flexible management of seller account status.
   *
   * @param connection
   * @param sellerId Target seller's unique identifier
   * @param body Suspension management request with action type and optional reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Process seller suspension management operations. Handle both suspension and unsuspension of seller accounts while preserving business continuity. Update seller status in database, manage product visibility, maintain suspension history for audit trail, and notify affected sellers of status changes. Ensure proper authorization checks for administrative access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updateSuspension(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string,
    @TypedBody()
    body: IShoppingMallSeller.ISuspensionRequest,
  ): Promise<IShoppingMallSeller.ISuspension> {
    try {
      return await patchShoppingMallAdminSellersSellerIdSuspensions({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
