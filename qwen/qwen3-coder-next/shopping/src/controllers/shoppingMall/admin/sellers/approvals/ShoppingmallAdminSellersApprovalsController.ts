import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSellerProfile } from "../../../../../api/structures/IShoppingMallSellerProfile";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { postShoppingMallAdminSellersSellerIdApprovals } from "../../../../../providers/postShoppingMallAdminSellersSellerIdApprovals";

@Controller("/shoppingMall/admin/sellers/:sellerId/approvals")
export class ShoppingmallAdminSellersApprovalsController {
  /**
   * Approve or reject a pending seller registration
   *
   * This API endpoint handles the seller registration approval workflow. When a seller registers on the platform, their account is created with 'pending_admin_approval' status. Administrators must review the registration and either approve or reject it.
   *
   * When a seller is approved, their account status changes to 'active' and they gain full selling capabilities. When rejected, the rejection reason must be provided and stored, and the seller can submit a new registration request after addressing the rejection reasons.
   *
   * This operation creates a seller approval record as part of the audit trail and preserves the seller profile state at the time of approval decision.
   *
   * @param connection
   * @param sellerId Seller account ID requiring approval
   * @param body Seller approval decision with optional rejection reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Process seller registration approval decision.
   * 1. Validate sellerId path parameter and verify seller exists with 'pending_admin_approval' status
   * 2. Validate request body contains approval action ('approve' or 'reject')
   * 3. If rejecting, validate rejection_reason is provided and meets length requirements
   * 4. Update seller status based on approval decision
   * 5. Create seller_approval record with decision, reason, and timestamp
   * 6. Create seller_profile_snapshot preserving current seller state
   * 7. Return approved/rejected seller information with updated status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async approveSellerRegistration(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string,
    @TypedBody()
    body: IShoppingMallSellerProfile.IApproval,
  ): Promise<void> {
    try {
      return await postShoppingMallAdminSellersSellerIdApprovals({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
