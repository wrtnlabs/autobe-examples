import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallSystemMigration } from "../../../../api/structures/IPageIShoppingMallSystemMigration";
import { IShoppingMallSystemMigration } from "../../../../api/structures/IShoppingMallSystemMigration";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminMigrations } from "../../../../providers/patchShoppingMallAdminMigrations";

@Controller("/shoppingMall/admin/migrations")
export class ShoppingmallAdminMigrationsController {
  /**
   * Retrieve a paginated list of database migration history records.
   *
   * This operation provides visibility into the system's database schema evolution by listing all executed migrations with their metadata. It shows when each migration was applied, which administrator executed it, and tracks the migration file name and content hash for integrity verification.
   *
   * The system uses this migration history to ensure database consistency and track schema changes across deployments. Each migration record includes the timestamp of execution, the administrator responsible, and cryptographic hash of the migration file content for integrity verification.
   *
   * For comprehensive migration management, use this endpoint alongside the database schema definitions to understand the complete current state of the database structure.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for migration history
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_system_migrations table with pagination and filtering. Join with shopping_mall_admins to include administrator information. Order results by executed_at timestamp descending (newest first). Support filtering by migration name and date range. Return cursor-based pagination for large result sets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSystemMigration.IRequest,
  ): Promise<IPageIShoppingMallSystemMigration.ISummary> {
    try {
      return await patchShoppingMallAdminMigrations({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
