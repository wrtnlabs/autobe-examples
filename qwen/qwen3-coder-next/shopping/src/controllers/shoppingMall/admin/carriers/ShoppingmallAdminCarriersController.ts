import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallShippingCarrier } from "../../../../api/structures/IPageIShoppingMallShippingCarrier";
import { IShoppingMallShippingCarrier } from "../../../../api/structures/IShoppingMallShippingCarrier";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteShoppingMallAdminCarriersCarrierId } from "../../../../providers/deleteShoppingMallAdminCarriersCarrierId";
import { getShoppingMallAdminCarriersCarrierId } from "../../../../providers/getShoppingMallAdminCarriersCarrierId";
import { patchShoppingMallAdminCarriers } from "../../../../providers/patchShoppingMallAdminCarriers";
import { postShoppingMallAdminCarriers } from "../../../../providers/postShoppingMallAdminCarriers";
import { putShoppingMallAdminCarriersCarrierId } from "../../../../providers/putShoppingMallAdminCarriersCarrierId";

@Controller("/shoppingMall/admin/carriers")
export class ShoppingmallAdminCarriersController {
  /**
   * Register a new shipping carrier integration for the Shopping Mall platform.
   *
   * This operation allows administrators to onboard new shipping carriers (such as FedEx, UPS, DHL) by providing their API credentials, endpoints, and configuration settings. Once registered, carriers can be used for automated shipping label generation, tracking, and delivery notifications.
   *
   * Only administrators with appropriate permissions can register new shipping carriers. The carrier code must be unique and is used internally to reference the carrier in other tables.
   *
   * @param connection
   * @param body Shipping carrier registration information
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new shipping carrier record in the database with provided credentials and configuration.
   * Validate unique carrier code constraint.
   * Return the created carrier with generated ID and timestamps.
   * Log the administrative action for audit trail purposes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallShippingCarrier.ICreate,
  ): Promise<IShoppingMallShippingCarrier> {
    try {
      return await postShoppingMallAdminCarriers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of shipping carrier configurations.
   *
   * This operation provides comprehensive access to all shipping carriers configured in the platform, allowing administrators to search, filter, and browse through carrier configurations for operational oversight and management purposes.
   *
   * Carriers can be filtered by enabled status, search by name or code, and paginated for efficient data retrieval. The operation supports the complete set of shipping carrier configuration fields including API endpoints, authentication credentials, and account numbers.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_shipping_carriers table with pagination and optional filtering.
   * Support filtering by is_enabled status to show only active carriers.
   * Support search by carrier name or code for快速查找.
   * Return paginated results with current stock information.
   * Apply standard排序 by created_at timestamp for consistent ordering.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IPageIShoppingMallShippingCarrier.ISummary> {
    try {
      return await patchShoppingMallAdminCarriers({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shipping carrier configuration.
   *
   * This operation fetches the complete configuration details for a shipping carrier including API endpoint information, authentication credentials, and account details. This is essential for sellers and administrators who need to view carrier setup information for shipping label generation and tracking integration.
   *
   * ## Security Considerations
   *
   * This endpoint returns sensitive authentication information (API key, API secret) that should only be accessible to authorized users. The response includes credentials needed for carrier API integration but excludes soft-deleted records.
   *
   * ## Authorization
   *
   * This endpoint is restricted to:
   * - **seller**: Can view carrier configurations for their own orders
   * - **admin**: Full access to all carrier configurations for platform-wide management
   *
   * ## Database Structure
   *
   * This operation accesses the shopping_mall_shipping_carriers table which stores:
   * - Carrier identification (id, code, name)
   * - API connection details (endpoint, key, secret, account number)
   * - Status configuration (enabled/disabled)
   * - Timestamps for creation and updates
   * - Soft delete marker (deleted_at) for archived carrier configurations
   *
   * ## Related Operations
   *
   * - GET /carriers - List all active carriers
   * - PATCH /carriers - Search and filter carriers
   * - POST /carriers - Create new carrier configuration (admin only)
   * - PUT /carriers/{carrierId} - Update carrier configuration (admin only)
   * - DELETE /carriers/{carrierId} - Delete carrier configuration (admin only)
   *
   * @param connection
   * @param carrierId Unique identifier of the shipping carrier to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_shipping_carriers table by primary key ID.
   * Return complete carrier configuration including API credentials, account number, and status.
   * Filter out soft-deleted records (deleted_at IS NULL).
   * Return 404 if carrier not found or has been soft-deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":carrierId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("carrierId")
    carrierId: string,
  ): Promise<IShoppingMallShippingCarrier> {
    try {
      return await getShoppingMallAdminCarriersCarrierId({
        admin,
        carrierId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update shipping carrier configuration
   *
   * This API endpoint allows administrators to modify the configuration of an existing shipping carrier, including API credentials, endpoint URLs, account numbers, and enablement status. The operation updates the carrier's connection settings while preserving the historical carrier configuration through snapshot mechanisms.
   *
   * The carrier code remains immutable after creation to ensure referential integrity across the system, while all other configuration fields can be modified. This operation requires administrator privileges to prevent unauthorized sellers from modifying carrier configurations that could affect shipping operations across the platform.
   *
   * When a carrier configuration is updated, the system preserves historical configurations through snapshot records to maintain audit trails for shipping operations and regulatory compliance. The carrier's code serves as the primary identifier and cannot be changed once set.
   *
   * This operation is part of the administrator system and requires admin-level access. Only administrators can modify carrier configurations to ensure platform-wide shipping integrity.
   *
   * @param connection
   * @param carrierId Unique carrier identifier (UUID format)
   * @param body Carrier configuration update request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update shipping carrier configuration record with new values.
   * Use carrierId path parameter to identify the target carrier.
   * Validate carrier exists before update.
   * Preserve carrier code immutability (do not allow updating the code field).
   * Update is_enabled status for enabling/disabling carrier.
   * Update api_endpoint, api_key, api_secret, account_number fields with new values.
   * Create carrier snapshot preserving previous state.
   * Return updated carrier record with all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":carrierId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("carrierId")
    carrierId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShippingCarrier.IUpdate,
  ): Promise<IShoppingMallShippingCarrier> {
    try {
      return await putShoppingMallAdminCarriersCarrierId({
        admin,
        carrierId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a shipping carrier configuration from the system.
   *
   * This operation performs a soft delete of a shipping carrier by marking it as deleted without permanently removing the record from the database. This approach preserves historical shipment records and maintains referential integrity with existing data.
   *
   * ## Security and Authorization
   *
   * Only administrators with appropriate privileges can delete shipping carrier configurations. Sellers and customers do not have access to this operation.
   *
   * ## Business Rules
   *
   * - The carrier must exist and not be already deleted
   * - The carrier should not be referenced by active seller configurations
   * - The carrier should not be referenced by existing shipments
   * - If dependencies exist, the deletion is blocked and appropriate error codes are returned
   *
   * ## Related Operations
   *
   * - GET /carriers/{carrierId} - Retrieve carrier details before deletion
   * - PATCH /carriers/{carrierId} - Update carrier configuration
   * - POST /carriers - Create new carrier configuration
   * - GET /carriers - List all carriers (including soft-deleted ones with filter)
   *
   * @param connection
   * @param carrierId Unique identifier of the shipping carrier to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Delete a shipping carrier configuration by performing a soft delete. The operation should:
   * 1. Validate the carrierId exists and belongs to the shopping_mall_shipping_carriers table
   * 2. Check that no active seller configurations reference this carrier
   * 3. Check that no existing shipments reference this carrier
   * 4. Update the carrier record by setting deleted_at to the current timestamp
   * 5. Return the updated carrier record with deleted_at timestamp
   * 6. Log the deletion action for audit purposes
   * 7. Handle dependency validation errors with appropriate error codes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":carrierId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("carrierId")
    carrierId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCarriersCarrierId({
        admin,
        carrierId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
