import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallShippingCarrierConfig } from "../../../../../api/structures/IPageIShoppingMallShippingCarrierConfig";
import { IShoppingMallShippingCarrierConfig } from "../../../../../api/structures/IShoppingMallShippingCarrierConfig";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCarriersCarrierIdConfigs } from "../../../../../providers/getShoppingMallAdminCarriersCarrierIdConfigs";
import { getShoppingMallAdminCarriersCarrierIdConfigsConfigKey } from "../../../../../providers/getShoppingMallAdminCarriersCarrierIdConfigsConfigKey";
import { patchShoppingMallAdminCarriersCarrierIdConfigs } from "../../../../../providers/patchShoppingMallAdminCarriersCarrierIdConfigs";

@Controller("/shoppingMall/admin/carriers/:carrierId/configs")
export class ShoppingmallAdminCarriersConfigsController {
  /**
   * Retrieve all configuration options for a specific shipping carrier.
   *
   * This operation fetches all key-value configuration pairs associated with the specified shipping carrier. The configuration options include carrier-specific settings such as weight units, dimension units, API endpoint URLs, and other integration parameters stored in the shopping_mall_shipping_carrier_configs table.
   *
   * The operation requires valid authentication and authorization. Only administrators and sellers with appropriate permissions can access carrier configurations for operational purposes.
   *
   * @param connection
   * @param carrierId Target shipping carrier's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the shopping_mall_shipping_carrier_configs table filtered by the carrier_id path parameter. The carrierId parameter should be validated as a valid UUID. Return all configuration records with their key-value pairs. Include proper error handling for non-existent carrier IDs.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async getByCarrierid(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("carrierId")
    carrierId: string,
  ): Promise<IPageIShoppingMallShippingCarrierConfig> {
    try {
      return await getShoppingMallAdminCarriersCarrierIdConfigs({
        admin,
        carrierId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update configuration options for a shipping carrier integration.
   *
   * This operation allows authorized users to update carrier-specific configuration parameters stored as key-value pairs. These configuration options normalize carrier-specific settings such as weight units, dimension units, API endpoints, and other carrier-specific parameters that are required for integration with external shipping providers like FedEx, UPS, DHL, etc.
   *
   * The operation requires valid carrier ID in the path parameter and a JSON object containing key-value pairs for the configuration parameters to update. All configuration updates are validated against the carrier's schema and stored in the carrier_configs table with proper audit trails.
   *
   * @param connection
   * @param carrierId Target shipping carrier's unique identifier (UUID format)
   * @param body Carrier configuration options as key-value pairs to update
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update shipping carrier configuration options by key-value pairs.
   *
   * 1. Validate carrier ID from path parameter exists in shopping_mall_shipping_carriers table
   * 2. Validate request body contains valid configuration key-value pairs
   * 3. For each configuration key in the request:
   *    - If key exists, update the value in shopping_mall_shipping_carrier_configs table
   *    - If key doesn't exist, create new configuration record
   * 4. Update updated_at timestamp for affected records
   * 5. Return success response with updated configuration
   * 6. Handle carrier not found error (404)
   * 7. Handle validation errors for invalid key-value pairs (400)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updateConfigs(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("carrierId")
    carrierId: string,
    @TypedBody()
    body: IShoppingMallShippingCarrierConfig.IRequest,
  ): Promise<IShoppingMallShippingCarrierConfig.IRequest> {
    try {
      return await patchShoppingMallAdminCarriersCarrierIdConfigs({
        admin,
        carrierId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific shipping carrier configuration parameter.
   *
   * This operation fetches an individual configuration value for a shipping carrier integration. The configuration is identified by the carrier's unique identifier and the configuration parameter key name. This allows clients to retrieve specific carrier settings such as API endpoints, authentication credentials, or other carrier-specific parameters.
   *
   * The configuration values are stored in normalized key-value pairs, with each configuration parameter stored as a separate row in the database. This approach maintains First Normal Form (1NF) and enables efficient querying of individual configuration parameters.
   *
   * @param connection
   * @param carrierId The unique identifier of the shipping carrier
   * @param configKey The configuration parameter key name
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_shipping_carrier_configs table where shopping_mall_shipping_carrier_id matches carrierId and key matches configKey. Return the value field as a string. Return 404 if configuration not found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":configKey")
  public async getByCarrieridAndConfigkey(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("carrierId")
    carrierId: string,
    @TypedParam("configKey")
    configKey: string,
  ): Promise<IShoppingMallShippingCarrierConfig> {
    try {
      return await getShoppingMallAdminCarriersCarrierIdConfigsConfigKey({
        admin,
        carrierId,
        configKey,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
