import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallAdminDashboard } from "../../../../api/structures/IShoppingMallAdminDashboard";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminStatistics } from "../../../../providers/getShoppingMallAdminStatistics";

@Controller("/shoppingMall/admin/statistics")
export class ShoppingmallAdminStatisticsController {
  /**
   * Retrieve comprehensive platform statistics for dashboard and analytics purposes.
   *
   * This endpoint provides aggregated metrics including product counts, order summaries, revenue statistics, customer insights, and seller performance metrics. The endpoint supports role-based filtering to return relevant statistics for the authenticated user.
   *
   * For sellers, statistics include their own shop metrics. For administrators, statistics include platform-wide metrics.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Aggregate and calculate platform statistics from database.
   * Calculate product counts, order totals, revenue metrics, customer insights.
   * Implement role-based filtering: sellers see own metrics, admins see platform-wide.
   * Return aggregated statistics without pagination or detailed records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IShoppingMallAdminDashboard> {
    try {
      return await getShoppingMallAdminStatistics({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
