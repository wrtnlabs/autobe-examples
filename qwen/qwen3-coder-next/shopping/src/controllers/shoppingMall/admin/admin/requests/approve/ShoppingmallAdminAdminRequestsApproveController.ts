import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSellerApproval } from "../../../../../../api/structures/IShoppingMallSellerApproval";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminAdminRequestsRequestIdApprove } from "../../../../../../providers/putShoppingMallAdminAdminRequestsRequestIdApprove";

@Controller("/shoppingMall/admin/admin/requests/:requestId/approve")
export class ShoppingmallAdminAdminRequestsApproveController {
  /**
   * Approve a pending seller registration or administrator request.
   *
   * This operation allows administrators to approve pending registration requests from sellers or users who have applied for administrator privileges. When approved, the requester's account status is updated to active and they gain appropriate permissions.
   *
   * ## Request Validation
   *
   * - The request must exist and have status "pending"
   * - Only administrators with appropriate permissions can approve requests
   * - System logs the approval action for audit trail
   *
   * ## Post-Approval Actions
   *
   * - Updates requester's account status to "approved"
   * - Enables seller selling capabilities if it was a seller registration
   * - Grants administrator privileges if it was an administrator request
   * - Sends notification to the requester about approval
   * - Records approval timestamp and administrator information for audit
   *
   * @param connection
   * @param requestId The unique identifier of the registration request to approve
   * @param body Approval action confirmation
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Approve pending seller registration or administrator request by ID.
   *
   * 1. Validate request exists with status "pending"
   * 2. Check administrator permissions
   * 3. Update request status to "approved"
   * 4. Update requester account status to "approved"
   * 5. Log approval action in audit trail
   * 6. Send notification to requester
   * 7. Return approval confirmation with updated request details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async approveRequest(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("requestId")
    requestId: string,
    @TypedBody()
    body: IShoppingMallSellerApproval.IApprovalRequest,
  ): Promise<IShoppingMallSellerApproval.IApprovalResponse> {
    try {
      return await putShoppingMallAdminAdminRequestsRequestIdApprove({
        admin,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
