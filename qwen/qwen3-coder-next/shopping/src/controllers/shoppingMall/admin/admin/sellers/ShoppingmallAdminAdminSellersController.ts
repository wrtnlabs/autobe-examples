import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallSeller } from "../../../../../api/structures/IPageIShoppingMallSeller";
import { IShoppingMallSeller } from "../../../../../api/structures/IShoppingMallSeller";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminAdminSellersSellerId } from "../../../../../providers/getShoppingMallAdminAdminSellersSellerId";
import { patchShoppingMallAdminAdminSellers } from "../../../../../providers/patchShoppingMallAdminAdminSellers";

@Controller("/shoppingMall/admin/admin/sellers")
export class ShoppingmallAdminAdminSellersController {
  /**
   * Retrieve a filtered and paginated list of seller accounts for administrative oversight.
   *
   * This operation provides comprehensive seller management capabilities allowing administrators to view all registered sellers on the platform with advanced filtering options. Supports filtering by approval status (pending, approved, rejected), suspension status, and registration date ranges.
   *
   * The operation returns seller summary information optimized for administrative dashboards and list displays. For detailed seller information, use the individual seller detail endpoint.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_sellers table with pagination and filtering.
   * Filter by approval_status, suspension_status, and registration date range.
   * Support comprehensive search on shop_name using trigram similarity.
   * Return paginated results with seller summary information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSeller.IRequest,
  ): Promise<IPageIShoppingMallSeller.ISummary> {
    try {
      return await patchShoppingMallAdminAdminSellers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific seller including their profile details, approval status, shop configuration, and current operational status.
   *
   * This endpoint provides comprehensive seller information for administrative oversight, allowing administrators to review seller accounts, check approval status, view shop configuration details, and monitor seller operational status.
   *
   * The response includes seller profile information such as shop name, description, logo, approval status, and when the seller was approved. It also includes seller settings like theme configuration, store preferences, shipping settings, and business hours. Additionally, the response provides seller statistics including total products, order items, pending cancellation requests, and pending refund requests.
   *
   * Security considerations: This is an administrator-only endpoint that requires elevated privileges to access seller account details. Sellers cannot access this endpoint for their own account information.
   *
   * This endpoint is related to other seller management operations including listing all sellers (GET /admin/sellers), approving seller registrations (PUT /admin/sellers/{sellerId}/approve), rejecting seller registrations (PUT /admin/sellers/{sellerId}/reject), suspending seller accounts (PUT /admin/sellers/{sellerId}/suspend), and unsuspending seller accounts (PUT /admin/sellers/{sellerId}/unsuspend).
   *
   * @param connection
   * @param sellerId Seller's unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_sellers table for seller record with ID matching path parameter.
   * Left join shopping_mall_seller_profiles for shop profile information.
   * Left join shopping_mall_seller_settings for store configuration settings.
   * Left join shopping_mall_seller_statistics for seller dashboard statistics.
   * Return single seller object with embedded profile, settings, and statistics data.
   * Handle cases where seller, profile, settings, or statistics records may not exist.
   * Return 404 error if seller with specified ID does not exist.
   * Only administrators can access this endpoint - enforce authorization check.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string,
  ): Promise<IShoppingMallSeller> {
    try {
      return await getShoppingMallAdminAdminSellersSellerId({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
