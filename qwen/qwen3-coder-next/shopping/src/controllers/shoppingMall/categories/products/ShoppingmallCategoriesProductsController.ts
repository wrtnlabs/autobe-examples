import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallProduct } from "../../../../api/structures/IPageIShoppingMallProduct";
import { patchShoppingMallCategoriesCategoryIdProducts } from "../../../../providers/patchShoppingMallCategoriesCategoryIdProducts";

@Controller("/shoppingMall/categories/:categoryId/products")
export class ShoppingmallCategoriesProductsController {
  /**
   * Retrieve all products in a specific category.
   *
   * This endpoint provides category-based product browsing, allowing customers to explore products organized by category hierarchy. When a customer selects a category, this endpoint returns all products assigned to that category including products in subcategories if configured.
   *
   * The endpoint supports navigation of the category structure and enables customers to browse products by category. The products returned include those directly assigned to the category as well as products in subcategories (if the system is configured to include subcategory products).
   *
   * The response includes product summary information optimized for list displays, showing main images, product names, prices, and seller information.
   *
   * @param connection
   * @param categoryId Target category's ID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_products table filtered by shopping_mall_category_id.
   * Join with shopping_mall_sellers for seller information.
   * Join with shopping_mall_categories for category information.
   * Apply category_id filter from path parameter.
   * Support pagination with configurable page size.
   * Return paginated list of product summaries with seller information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("categoryId")
    categoryId: string,
  ): Promise<IPageIShoppingMallProduct.ISummary> {
    try {
      return await patchShoppingMallCategoriesCategoryIdProducts({
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
