import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallCategory } from "../../../api/structures/IPageIShoppingMallCategory";
import { IShoppingMallCategory } from "../../../api/structures/IShoppingMallCategory";
import { getShoppingMallCategoriesCategoryId } from "../../../providers/getShoppingMallCategoriesCategoryId";
import { getShoppingMallCategoriesHierarchy } from "../../../providers/getShoppingMallCategoriesHierarchy";
import { patchShoppingMallCategories } from "../../../providers/patchShoppingMallCategories";

@Controller("/shoppingMall/categories")
export class ShoppingmallCategoriesController {
  /**
   * Retrieve a filtered, searched, and paginated list of product categories and subcategories.
   *
   * This operation provides comprehensive category management capabilities for administrative oversight, enabling platform administrators to browse, search, and filter the complete category hierarchy including both top-level categories and their associated subcategories.
   *
   * The operation supports advanced filtering by category name, description keywords, creation date ranges, and soft-delete status. Response includes category summary information optimized for list displays and administrative overview.
   *
   * Security considerations: This endpoint is restricted to administrator and super administrator roles only. Regular customers and sellers cannot access category management functionality.
   *
   * Relationship to underlying entities: This operation combines data from shopping_mall_categories (parent categories) and shopping_mall_subcategories (child subcategories), providing a unified view of the complete category taxonomy for platform administration.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_categories table with pagination and filtering. Join with shopping_mall_subcategories for subcategory information. Apply search filters on name and description fields. Support filtering by creation date range and soft-delete status. Return paginated results with category summaries including subcategory counts.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallCategory.IRequest,
  ): Promise<IPageIShoppingMallCategory.ISummary> {
    try {
      return await patchShoppingMallCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific product category by its unique identifier.
   *
   * This endpoint provides comprehensive category details including the category name, description, and all associated subcategories. It supports the product catalog browsing functionality by enabling customers and sellers to explore specific category information and its hierarchical structure.
   *
   * The endpoint returns complete category metadata including timestamps for creation, last update, and soft deletion status. All categories can be accessed publicly without authentication requirements.
   *
   * @param connection
   * @param categoryId Target category's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_categories table by ID to retrieve complete category information.
   * Join with shopping_mall_subcategories to fetch all associated subcategories.
   * Return category details including name, description, timestamps, and soft delete status.
   * Include all subcategories linked to this category with their details.
   * Return 404 if category does not exist or has been soft-deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async at(
    @TypedParam("categoryId")
    categoryId: string,
  ): Promise<IShoppingMallCategory> {
    try {
      return await getShoppingMallCategoriesCategoryId({
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the hierarchical structure of product categories for navigation.
   *
   * This endpoint provides the organization of top-level categories with their associated subcategories, enabling customers to browse and filter products by category hierarchy. The response includes essential category information optimized for navigation interfaces.
   *
   * Categories represent product groupings at the top level, while subcategories provide more specific product classifications within each category. This hierarchical structure enables efficient product discovery and filtering functionality.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_categories table for all active (non-deleted) categories.
   * Join with shopping_mall_subcategories to retrieve subcategories for each category.
   * Filter by deleted_at IS NULL for categories and subcategories.
   * Return hierarchical structure with categories containing their subcategories arrays.
   * Sort categories by created_at timestamp, subcategories by created_at timestamp.
   * Return complete category and subcategory details including names and descriptions.
   * No pagination required - return entire hierarchy in single response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("hierarchy")
  public async hierarchy(): Promise<IShoppingMallCategory.ISummary> {
    try {
      return await getShoppingMallCategoriesHierarchy();
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
