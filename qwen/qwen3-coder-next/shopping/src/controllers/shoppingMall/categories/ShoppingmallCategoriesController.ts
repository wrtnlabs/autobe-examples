import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallCategory } from "../../../api/structures/IPageIShoppingMallCategory";
import { IShoppingMallCategory } from "../../../api/structures/IShoppingMallCategory";
import { getShoppingMallCategories } from "../../../providers/getShoppingMallCategories";
import { getShoppingMallCategoriesHierarchy } from "../../../providers/getShoppingMallCategoriesHierarchy";

@Controller("/shoppingMall/categories")
export class ShoppingmallCategoriesController {
  /**
   * Retrieve a paginated list of all active product categories.
   *
   * This operation provides comprehensive category browsing functionality for the shopping mall platform. Categories are organized in a hierarchical structure with one level of nesting (parent categories can have subcategories).
   *
   * The response includes complete category information including names, descriptions, parent-child relationships, and product counts for each category. This enables customers to navigate the category tree and discover products through category browsing.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_categories table for active (non-deleted) categories.
   * Support pagination with configurable page size and offset.
   * Include parent category information for hierarchical display.
   * Count products in each category and subcategories.
   * Return complete category tree structure optimized for navigation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(): Promise<IPageIShoppingMallCategory.ISummary> {
    try {
      return await getShoppingMallCategories();
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete two-level category hierarchy for the shopping mall platform.
   *
   * This operation returns all categories organized in a hierarchical structure where each category may have zero or more subcategories. The system implements a two-level category hierarchy where categories can have exactly one parent category, supporting up to two levels of nesting (root categories and their subcategories).
   *
   * The category hierarchy is primarily used for:
   * - Customer product browsing and navigation
   * - Category selection during product searches
   * - Hierarchical category display in navigation menus
   * - Breadcrumb navigation generation
   *
   * Security and Authorization:
   * - This is a public endpoint available to all users (guests, customers, sellers, and administrators)
   * - No authentication required for accessing category hierarchy
   * - All active categories are visible regardless of user role
   *
   * Database Schema Reference:
   * The operation queries the `shopping_mall_categories` table which contains:
   * - Category ID (primary key)
   * - Category name (unique within parent category)
   * - Category description
   * - Parent category reference (nullable for root categories)
   * - Timestamps for creation and updates
   *
   * The response includes:
   * - Root categories (those with no parent category)
   * - For each root category, its subcategories (those with that category as parent)
   * - Complete category information including names, descriptions, and hierarchical relationships
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the shopping_mall_categories table to retrieve all categories.
   * Build hierarchical structure by grouping categories by parent category ID.
   * Root categories have NULL parent_category_id.
   * Subcategories have parent_category_id referencing their parent category.
   * Return nested structure with root categories and their children arrays.
   * Optimize with single query using self-join or application-level grouping.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("hierarchy")
  public async hierarchy(): Promise<IShoppingMallCategory.IInvert> {
    try {
      return await getShoppingMallCategoriesHierarchy();
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
