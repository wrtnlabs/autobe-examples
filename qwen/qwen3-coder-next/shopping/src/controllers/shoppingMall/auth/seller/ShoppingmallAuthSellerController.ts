import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { postShoppingMallAuthSellerJoin } from "../../../../providers/postShoppingMallAuthSellerJoin";
import { postShoppingMallAuthSellerLogin } from "../../../../providers/postShoppingMallAuthSellerLogin";
import { postShoppingMallAuthSellerRefresh } from "../../../../providers/postShoppingMallAuthSellerRefresh";

@Controller("/shoppingMall/auth/seller")
export class ShoppingmallAuthSellerController {
  /**
   * Seller account registration endpoint that creates new seller accounts in the system. This operation handles the complete seller registration workflow including email/password authentication setup, initial shop profile creation with name and description, and account status initialization to "pending" for administrator approval.
   *
   * The registration process captures essential seller information such as shop name for customer visibility, shop description for business presentation, and logo image reference for brand recognition. All credentials are securely hashed using bcrypt with appropriate salt rounds before storage in the database.
   *
   * This endpoint is publicly accessible to enable seller onboarding while ensuring data integrity through validation of unique email addresses and proper password strength requirements.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration request containing authentication credentials and shop profile information.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification The join operation processes seller registration by first validating email uniqueness and password strength requirements. Upon validation success, the system hashes the password using bcrypt with 10 salt rounds, creates the seller record with status "pending", and initializes the shop profile with provided name and description. If logo image ID is provided, it's associated with the seller account. Finally, JWT access token (30-minute expiry) and refresh token (7-day expiry) are generated and returned to the client for immediate authentication.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.IJoin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Seller authentication endpoint that validates email and password credentials to establish authenticated sessions. This operation verifies seller identity against the stored password hash in the database and generates JWT tokens for secure session management.
   *
   * The login process supports all seller account statuses including "pending" (awaiting approval), "approved" (active), "rejected" (application denied), and "suspended" (temporarily disabled). Each authentication event is logged for security auditing and suspicious activity detection.
   *
   * This endpoint implements rate limiting and account lockout mechanisms to prevent brute force attacks while maintaining secure access for legitimate sellers.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login request containing email address and plaintext password for authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification The login operation validates seller credentials by first looking up the seller record by email address. If found, it compares the provided password against the stored bcrypt hash using constant-time comparison to prevent timing attacks. Upon successful authentication, the system generates JWT access token (30-minute expiry) with seller ID, role, and permissions, plus refresh token (7-day expiry) for session continuity. All authentication events are logged with timestamp, IP address, and user agent for security auditing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.ILogin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Token refresh endpoint that renews expired JWT access tokens using valid refresh tokens. This operation extends authenticated sessions without requiring sellers to re-enter their credentials, providing seamless user experience while maintaining security through token rotation.
   *
   * The refresh process validates refresh tokens against the session records in the database and issues new access tokens with updated expiration times. This endpoint is crucial for maintaining continuous seller access during extended usage periods while ensuring security through regular token rotation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh request containing valid refresh token for session renewal.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification The refresh operation validates the provided refresh token against the session records in the database, checking for token validity, expiration, and matching seller account. Upon validation success, the system generates new JWT access token (30-minute expiry) with updated timestamp and permissions, plus a new refresh token (7-day expiry) with rotated secret for security. The old refresh token is invalidated to prevent reuse, implementing token rotation for enhanced security.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallSeller.IRefresh,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
