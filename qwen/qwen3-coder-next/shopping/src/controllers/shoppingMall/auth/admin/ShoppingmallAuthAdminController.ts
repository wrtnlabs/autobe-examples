import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallAdmin } from "../../../../api/structures/IShoppingMallAdmin";
import { postShoppingMallAuthAdminJoin } from "../../../../providers/postShoppingMallAuthAdminJoin";
import { postShoppingMallAuthAdminLogin } from "../../../../providers/postShoppingMallAuthAdminLogin";
import { postShoppingMallAuthAdminRefresh } from "../../../../providers/postShoppingMallAuthAdminRefresh";

@Controller("/shoppingMall/auth/admin")
export class ShoppingmallAuthAdminController {
  /**
   * Register a new administrator account for the shopping mall platform.
   *
   * This endpoint allows system administrators or super administrators to create new administrator accounts for platform management purposes.
   *
   * ## Security Considerations
   *
   * - Passwords must be securely hashed using bcrypt with cost factor 12
   * - Email addresses must be validated for proper format
   * - Only users with appropriate administrative privileges can create new administrators
   * - The operation creates an admin record with role_grade='admin'
   * - All administrator activities are logged for audit compliance
   *
   * ## Implementation Details
   *
   * - Validates email format and password strength requirements
   * - Checks for existing admin with same email address
   * - Creates admin record with provided email, hashed password, and default role_grade
   * - Returns success response with admin details
   * - Generates JWT tokens for the newly created administrator
   *
   * ## Related Operations
   *
   * - `POST /auth/admin/login` - Login operation for the created admin
   * - `POST /auth/admin/refresh` - Token refresh for the created admin
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator registration information including email and password credentials.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Hash the password using bcrypt with cost factor 12. Create a new admin account with the provided email, hashed password, and role_grade='admin'. Return the created admin record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.IJoin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate administrator access to the shopping mall platform.
   *
   * This endpoint validates administrator credentials and establishes a secure authenticated session using JWT tokens.
   *
   * ## Security Considerations
   *
   * - Validates email address exists and belongs to an admin account
   * - Verifies password matches the stored bcrypt hash
   * - Checks that admin account is not soft-deleted or suspended
   * - Rate limiting applied to prevent credential stuffing attacks
   * - Failed authentication attempts are logged for security monitoring
   *
   * ## Implementation Details
   *
   * - Validates email format and checks admin exists with that email
   * - Verifies password hash matches stored password_hash field
   * - Checks account status (not deleted, not suspended)
   * - Generates JWT access token with 30-minute expiration
   * - Generates JWT refresh token with 7-day expiration
   * - Returns both tokens and admin profile information
   * - Updates last login timestamp on successful authentication
   *
   * ## Related Operations
   *
   * - `POST /auth/admin/join` - Registration operation for new admins
   * - `POST /auth/admin/refresh` - Token refresh for maintaining session
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator login credentials including email address and password.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Verify admin email and password match stored credentials. Generate JWT access token (30 minutes) and refresh token (7 days). Return both tokens and admin profile information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.ILogin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew administrator authentication session using refresh tokens.
   *
   * This endpoint allows administrators to obtain new access tokens without re-authenticating with their password, maintaining secure session continuity.
   *
   * ## Security Considerations
   *
   * - Validates refresh token format and signature
   * - Verifies refresh token matches the one stored in admin's session
   * - Checks refresh token expiration (7 days from creation)
   * - Invalidates old refresh token and generates new one
   * - Logs token refresh events for security auditing
   *
   * ## Implementation Details
   *
   * - Validates provided refresh token against stored token in admin_sessions table
   * - Verifies refresh token has not expired
   * - Generates new JWT access token with 30-minute expiration
   * - Optionally generates new refresh token with 7-day expiration
   * - Updates session record with new refresh token
   * - Returns both tokens and admin profile information
   * - Implements token rotation for enhanced security
   *
   * ## Related Operations
   *
   * - `POST /auth/admin/join` - Initial registration with both tokens
   * - `POST /auth/admin/login` - Initial authentication with both tokens
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator refresh token for session renewal.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate refresh token, verify it matches stored refresh token for the admin. Generate new JWT access token (30 minutes) and optionally new refresh token. Return updated tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallAdmin.IRefresh,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
