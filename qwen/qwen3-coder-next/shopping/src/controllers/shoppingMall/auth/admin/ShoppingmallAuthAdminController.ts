import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallAdmin } from "../../../../api/structures/IShoppingMallAdmin";
import { postShoppingMallAuthAdminJoin } from "../../../../providers/postShoppingMallAuthAdminJoin";
import { postShoppingMallAuthAdminLogin } from "../../../../providers/postShoppingMallAuthAdminLogin";
import { postShoppingMallAuthAdminRefresh } from "../../../../providers/postShoppingMallAuthAdminRefresh";

@Controller("/shoppingMall/auth/admin")
export class ShoppingmallAuthAdminController {
  /**
   * Admin account registration operation that creates a new administrator account in the system. This endpoint allows new administrators to register with the platform by providing their email address and password. The registration process validates email uniqueness and password strength, then creates the admin account with an initial status of 'pending' until activated by a super administrator. The operation returns authentication tokens and admin profile information upon successful registration.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration request payload containing admin account credentials
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Admin registration service handles account creation for administrator accounts. The service validates email uniqueness using the shopping_mall_admins table, checks password complexity requirements, and creates a new admin record with status 'pending'. Upon successful creation, JWT access and refresh tokens are generated with admin role claims. The access token has a 30-minute lifetime, while the refresh token has a 7-day lifetime. All passwords are securely hashed using bcrypt before storage. The operation returns the admin profile with display_name and status information along with authentication tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.IJoin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Admin account authentication operation that validates administrator credentials and establishes a new authenticated session. This endpoint allows registered administrators to log in to the system using their email address and password. The operation validates credentials against the shopping_mall_admins table, checks account status (must be active), and generates new JWT tokens upon successful authentication. The operation supports both regular login and password-based authentication flows.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login request payload containing admin credentials
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Admin login service handles authentication for administrator accounts. The service retrieves the admin record by email from the shopping_mall_admins table, validates the password hash using bcrypt, and checks account status (must not be suspended or deleted). Upon successful validation, the service generates JWT tokens with admin role claims and includes the admin's display_name and status in the response payload. The access token is valid for 30 minutes and the refresh token for 7 days. Failed login attempts increment a failure counter and may trigger temporary account lockout after threshold.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.ILogin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authentication token refresh operation that renews the access token using a valid refresh token. This endpoint allows administrators to extend their authenticated session without re-authenticating with their credentials. The operation validates the refresh token against the session store, verifies it hasn't expired, and generates new access and refresh tokens. This is the standard JWT token refresh flow supporting session continuity for long-running admin workflows.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token request payload
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Admin token refresh service handles JWT token renewal for administrator sessions. The service validates the provided refresh token against the session store, checks expiration time, and verifies it belongs to a valid admin account. Upon successful validation, the service generates new access and refresh tokens with fresh expiration times. The refresh token rotation ensures security by invalidating old refresh tokens when new ones are issued. This operation supports session continuation for admin workflows that require extended access periods without requiring frequent re-authentication.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallAdmin.IRefresh,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
