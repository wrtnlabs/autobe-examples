import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCategory } from "../../../api/structures/IEcommerceMallCategory";
import { getEcommerceMallCategories } from "../../../providers/getEcommerceMallCategories";
import { getEcommerceMallCategoriesCategoryId } from "../../../providers/getEcommerceMallCategoriesCategoryId";
import { patchEcommerceMallCategoriesId } from "../../../providers/patchEcommerceMallCategoriesId";

@Controller("/ecommerceMall/categories")
export class EcommercemallCategoriesController {
  /**
   * Update an existing category's name and description.
   *
   * This operation allows administrators to modify category metadata including the category name and description. It is designed for category management workflows where administrators need to update category information while maintaining category hierarchy integrity.
   *
   * The operation enforces strict validation rules:
   * - Name must be unique among categories that share the same parent
   * - One-level nesting constraint is enforced (no subcategory nesting beyond one level)
   * - Cyclic parent-child relationships are prevented
   *
   * Security considerations: Only administrators can update categories. Non-administrative users attempting this operation will be rejected with a 403 Forbidden response.
   *
   * Related operations:
   * - GET /categories: List all categories for browsing
   * - POST /categories: Create a new category
   * - DELETE /categories/:id: Delete a category (with product reassignment workflow)
   * - PATCH /categories/:id/default: Set category as default (if applicable)
   *
   * @param connection
   * @param id Category ID to update
   * @param body Category update request with name and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Update category name and description for admin-only category management. Enforce name uniqueness under same parent, one-level nesting constraint, and prevent cyclic relationships. Update only category.name and category.description fields, preserve category.parentId unless explicitly changed. Return updated category with all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":id")
  public async update(
    @TypedParam("id")
    id: string,
    @TypedBody()
    body: IEcommerceMallCategory.IUpdate,
  ): Promise<IEcommerceMallCategory> {
    try {
      return await patchEcommerceMallCategoriesId({
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific category including its hierarchical structure and subcategories.
   *
   * This operation provides comprehensive category details including the category name, description, parent-child relationships, and nested subcategories (up to one level deep as per the one-level nesting restriction). It supports category browsing experiences where customers need to understand the full category hierarchy and children when navigating the product catalog.
   *
   * Security Considerations: This is a read-only operation available to all users including guests. No authentication or authorization is required for viewing category information.
   *
   * Database Entity Relationships: The category entity supports hierarchical nesting through self-referencing relationships. A category can have a parent category (for subcategories) and child categories (for subcategories of this category). The one-level nesting restriction ensures that subcategories cannot have their own children, limiting the hierarchy depth to two levels total.
   *
   * @param connection
   * @param categoryId Target category's unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_mall_categories table by primary key id.
   * Return complete category object including parent category reference if exists.
   * Include child categories as nested array (one level deep only).
   * Enforce one-level nesting validation: only include direct children, do not recurse further.
   * Use categoryId path parameter to look up the category by its UUID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async getByCategoryid(
    @TypedParam("categoryId")
    categoryId: string,
  ): Promise<IEcommerceMallCategory> {
    try {
      return await getEcommerceMallCategoriesCategoryId({
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete category hierarchy for browsing and product discovery.
   *
   * This operation returns all top-level categories with their direct subcategories (one level deep) in a hierarchical structure. Customers use this endpoint to browse product categories when shopping, while administrators can view the category structure for oversight purposes.
   *
   * The response includes category names, descriptions, and their parent-child relationships. Top-level categories (where parentId is null) are returned at the root level, and each top-level category includes its subcategories if any exist. Subcategories cannot have further children due to the one-level nesting restriction.
   *
   * Security considerations:
   * - This is a public read-only endpoint accessible to all users
   * - No authentication required for browsing categories
   * - Administrators have additional write access to create/update/delete categories
   * - The system enforces one-level nesting depth (subcategories cannot have children)
   *
   * Related operations:
   * - POST /categories: Create a new category (admin only)
   * - PATCH /categories/{id}: Update an existing category (admin only)
   * - DELETE /categories/{id}: Delete a category (admin only)
   * - GET /categories/{id}: Get details for a specific category
   * - GET /products: Search and filter products (uses categories for filtering)
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_mall_categories table to retrieve hierarchical category structure.
   * Load all top-level categories (where parent_category_id is null).
   * For each top-level category, load its direct subcategories (where parent_category_id matches the category's id).
   * Apply one-level nesting constraint: subcategories must not have children.
   * Sort top-level categories alphabetically by name.
   * Sort subcategories alphabetically by name within each parent.
   * Return hierarchical structure with categories and their nested subcategories.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async get(): Promise<IEcommerceMallCategory> {
    try {
      return await getEcommerceMallCategories();
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
