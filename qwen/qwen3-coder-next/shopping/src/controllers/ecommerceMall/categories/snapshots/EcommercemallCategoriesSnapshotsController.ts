import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCategory } from "../../../../api/structures/IEcommerceMallCategory";
import { IPageIEcommerceMallCategory } from "../../../../api/structures/IPageIEcommerceMallCategory";
import { getEcommerceMallCategoriesCategoryIdSnapshotsSnapshotId } from "../../../../providers/getEcommerceMallCategoriesCategoryIdSnapshotsSnapshotId";
import { patchEcommerceMallCategoriesCategoryIdSnapshots } from "../../../../providers/patchEcommerceMallCategoriesCategoryIdSnapshots";

@Controller("/ecommerceMall/categories/:categoryId/snapshots")
export class EcommercemallCategoriesSnapshotsController {
  /**
   * Retrieve a specific category edit history snapshot.
   *
   * This endpoint provides access to the immutable audit trail records that preserve the category name and description at the time of each edit. These snapshots are created automatically whenever an administrator modifies a category and cannot be modified or deleted after creation.
   *
   * The snapshot contains both the category state before the edit and after the edit, enabling complete historical review of all changes made to category information. This is useful for auditing purposes, dispute resolution, and understanding the evolution of category data over time.
   *
   * Only administrators with appropriate permissions can access category edit history snapshots. Regular customers and sellers do not have access to this administrative functionality.
   *
   * @param connection
   * @param categoryId Target category's unique identifier
   * @param snapshotId Target snapshot's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the ecommerce_mall_category_snapshots table by categoryId and snapshotId to retrieve the specific edit history record.
   * Join with ecommerce_mall_admins to include administrator information if the snapshot was created by an admin.
   * Return the complete snapshot record including before_name, before_description, after_name, after_description, snapshot_type, and created_at fields.
   * Ensure the snapshot belongs to the specified category by validating the category_id foreign key relationship.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @TypedParam("categoryId")
    categoryId: string,
    @TypedParam("snapshotId")
    snapshotId: string,
  ): Promise<IEcommerceMallCategory> {
    try {
      return await getEcommerceMallCategoriesCategoryIdSnapshotsSnapshotId({
        categoryId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve historical snapshots of category changes.
   *
   * This operation provides complete visibility into the edit history for a specific category. Each snapshot records the category name and description at the time of changes made by administrators, preserving both the "before" and "after" states for audit purposes.
   *
   * The operation returns snapshots ordered by creation timestamp (newest first by default) with pagination support. Each snapshot includes the administrator who performed the edit (when available), the snapshot type, and the complete category state changes.
   *
   * This endpoint is designed for administrators and sellers who need to review category change history for compliance, dispute resolution, or change tracking purposes.
   *
   * @param connection
   * @param categoryId Category ID (UUID format) to filter snapshots
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_mall_category_snapshots table filtered by category_id path parameter. Apply pagination and timestamp-based ordering. Return snapshot summaries with essential metadata (id, snapshot_type, timestamps) and state information (before/after name and description). Include optional admin information when available. Use cursor-based pagination for efficient large result set handling.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("categoryId")
    categoryId: string,
  ): Promise<IPageIEcommerceMallCategory.ISummary> {
    try {
      return await patchEcommerceMallCategoriesCategoryIdSnapshots({
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
