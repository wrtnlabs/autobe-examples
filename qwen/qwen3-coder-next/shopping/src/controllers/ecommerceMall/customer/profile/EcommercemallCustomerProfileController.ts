import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomerProfile } from "../../../../api/structures/IEcommerceMallCustomerProfile";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putEcommerceMallCustomerProfile } from "../../../../providers/putEcommerceMallCustomerProfile";

@Controller("/ecommerceMall/customer/profile")
export class EcommercemallCustomerProfileController {
  /**
   * Update customer profile information
   *
   * This operation allows customers to update their display name and phone number in their profile. The profile contains the customer's public display information and contact details used for shipping and customer service purposes.
   *
   * Security and Authorization
   *
   * - Only authenticated customers can update their own profile
   * - Customers cannot modify other customers' profile data
   * - Profile updates are audited for security purposes
   *
   * Profile Fields
   *
   * - display_name: The public name shown in orders, reviews, and customer service interactions
   * - phone_number: Contact number used for shipping verification and customer service
   *
   * Validation Rules
   *
   * - display_name must be non-empty and cannot exceed 100 characters
   * - phone_number must contain at least 7 digits for valid contact
   *
   * Historical Data Preservation
   *
   * Profile updates only affect future interactions. All historical orders, reviews, and address records retain the profile data as it existed at the time of creation to ensure data integrity and audit trail consistency.
   *
   * @param connection
   * @param body Customer profile update request body with display name and phone number
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update the authenticated customer's profile in ecommerce_mall_customer_profiles table.
   *
   * 1. Retrieve the authenticated customer's user_id from the request context (JWT token)
   * 2. Find the customer profile record with WHERE user_id = {customerUserId}
   * 3. Apply validation:
   *    - display_name: must be non-empty and <= 100 characters
   *    - phone_number: must contain at least 7 digits
   * 4. Update the profile record with new values
   * 5. Return the updated profile record
   *
   * Use direct UPDATE query on customer_profiles table. Handle unique constraint violations for phone_number if another active customer has the same number. Return 409 if phone number uniqueness constraint is violated.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCustomerProfile.IUpdate,
  ): Promise<IEcommerceMallCustomerProfile> {
    try {
      return await putEcommerceMallCustomerProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
