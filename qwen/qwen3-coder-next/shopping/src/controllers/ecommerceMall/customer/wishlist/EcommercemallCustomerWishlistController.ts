import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallWishlistItem } from "../../../../api/structures/IEcommerceMallWishlistItem";
import { IPageIEcommerceMallWishlistItem } from "../../../../api/structures/IPageIEcommerceMallWishlistItem";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteEcommerceMallCustomerWishlistProductId } from "../../../../providers/deleteEcommerceMallCustomerWishlistProductId";
import { patchEcommerceMallCustomerWishlist } from "../../../../providers/patchEcommerceMallCustomerWishlist";
import { postEcommerceMallCustomerWishlistProductId } from "../../../../providers/postEcommerceMallCustomerWishlistProductId";

@Controller("/ecommerceMall/customer/wishlist")
export class EcommercemallCustomerWishlistController {
  /**
   * Retrieve a paginated list of products saved to the current customer's wishlist.
   *
   * This operation allows customers to browse their saved wishlist items with comprehensive search and filtering capabilities. Customers can filter products by various criteria, sort results by different attributes, and navigate through large result sets using pagination. The response includes detailed product information for each wishlist item, enabling customers to review their saved products and make purchase decisions.
   *
   * **Access Control**: This endpoint is restricted to authenticated customers. Customers can only access their own wishlist items and cannot view other customers' wishlists. Sellers and administrators are denied access to customer wishlist data.
   *
   * **Relationship to Database**: This operation queries the `ecommerce_mall_wishlist_items` table joined with `ecommerce_mall_products` to retrieve complete product information for items in the customer's wishlist. The wishlist items table has a composite unique constraint on `(customer_id, product_id)` ensuring no duplicate products per customer.
   *
   * **Filtering Capabilities**: Supports filtering by product availability status, price ranges, and category associations. Customers can search for specific products using partial name matching.
   *
   * **Pagination and Sorting**: Implements cursor-based pagination for efficient handling of large wishlists with configurable page sizes. Supports sorting by creation date (newest first by default) and product attributes.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for wishlist items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_wishlist_items table joined with ecommerce_mall_products for the authenticated customer.
   * Apply search filters on product name, category, and availability status.
   * Support pagination with configurable page sizes and sorting options.
   * Return cursor-based pagination for efficient large result set handling.
   * Ensure all results are filtered by the authenticated customer's ID to enforce privacy.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallWishlistItem.IRequest,
  ): Promise<IPageIEcommerceMallWishlistItem.ISummary> {
    try {
      return await patchEcommerceMallCustomerWishlist({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Add a product to the customer's wishlist.
   *
   * This operation creates a new wishlist item when a customer selects a product to save for future purchase. Each customer can have only one wishlist item per product (duplicate prevention). The system automatically associates the wishlist item with the authenticated customer and validates that the target product exists and is not a draft or deleted product.
   *
   * When successful, the operation returns the newly created wishlist item including the product details. If the product is already in the customer's wishlist, the operation returns a duplicate item error. If the product has been deleted by the seller, the operation returns a product not found error.
   *
   * @param connection
   * @param productId Product ID to add to wishlist
   * @param body Request to add a product to the wishlist
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create a new wishlist item for the authenticated customer.
   * 1. Extract productId from path parameter
   * 2. Load authenticated customer's ID from JWT token
   * 3. Verify product exists in database and is not deleted
   * 4. Check for existing wishlist item with same customer_id and product_id
   * 5. If duplicate exists, return error
   * 6. Create new wishlist_item record with current timestamp
   * 7. Return created wishlist item with product details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":productId")
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IEcommerceMallWishlistItem.ICreate,
  ): Promise<IEcommerceMallWishlistItem> {
    try {
      return await postEcommerceMallCustomerWishlistProductId({
        customer,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a product from the customer's wishlist.
   *
   * This operation permanently deletes the wishlist item for the specified product from the current customer's wishlist.
   *
   * The system automatically handles the deletion of wishlist items when their referenced products are deleted by sellers, ensuring wishlist integrity without requiring manual intervention.
   *
   * Security Considerations:
   * - Only the customer who owns the wishlist item can remove it
   * - The system enforces ownership validation before deletion
   * - Sellers, other customers, and administrators cannot remove another customer's wishlist items
   *
   * @param connection
   * @param productId The unique identifier of the product to remove from the wishlist
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Delete the wishlist item where customerId matches the authenticated user and productId matches the path parameter.
   *
   * Implement the following validation:
   * 1. Verify the authenticated user is a customer
   * 2. Check that the wishlist item exists and belongs to the customer
   * 3. If not found, return 404 error
   * 4. Perform immediate hard deletion (no soft-delete column)
   * 5. Return 204 No Content on success
   *
   * This operation does not require transaction handling as it's a single-table delete operation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productId")
    productId: string,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallCustomerWishlistProductId({
        customer,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
