import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallOrder } from "../../../../api/structures/IEcommerceMallOrder";
import { IPageIEcommerceMallOrder } from "../../../../api/structures/IPageIEcommerceMallOrder";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerOrdersOrderId } from "../../../../providers/getEcommerceMallCustomerOrdersOrderId";
import { patchEcommerceMallCustomerOrders } from "../../../../providers/patchEcommerceMallCustomerOrders";
import { postEcommerceMallCustomerOrders } from "../../../../providers/postEcommerceMallCustomerOrders";

@Controller("/ecommerceMall/customer/orders")
export class EcommercemallCustomerOrdersController {
  /**
   * Create a new order from customer shopping cart items.
   *
   * This endpoint processes a customer's shopping cart and creates a formal order. The operation validates all cart items, calculates the total price, creates the order record with preserved snapshot data (product name, description, variant options, and prices at purchase time), and reduces inventory atomically.
   *
   * **Customer Authentication Required**: Only authenticated customers can create orders. The system automatically associates the order with the authenticated customer's account.
   *
   * **Order Status Calculation**: The order's overall status is derived from the collective status of its order items:
   * - 'paid' - all items have been paid for
   * - 'shipped' - at least one item is shipped, but none are delivered
   * - 'delivered' - all items have been delivered
   * - 'cancelled' - all items have been cancelled
   * - 'refunded' - all items have been refunded
   * - 'partiallyCompleted' - mixed states among items
   *
   * **Data Preservation**: The system captures complete snapshots of all relevant data at order creation time including:
   * - Product name, description, and variant options
   * - Product price at purchase time
   * - Seller profile information
   * - Shipping address details
   * - Customer profile information
   *
   * **Inventory Management**: Stock quantities are atomically reduced for each variant when the order is created, preventing overselling.
   *
   * **Related Operations**:
   * - Before calling this endpoint, customers should call POST /checkout/validate to validate cart items and receive warnings
   * - After order creation, customers can call GET /orders/:id to retrieve order details
   * - Sellers can then create shipments by calling POST /shipments
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Process customer shopping cart and create order record with snapshot data.
   *
   * 1. Validate customer authentication (must be customer role)
   * 2. Load customer's shopping cart items with variant and product details
   * 3. Validate cart items: check product availability, variant stock, minimum quantity (1)
   * 4. Calculate total price: sum of (product_price * quantity) for all cart items
   * 5. Create order record with:
   *    - customer_id from authenticated session
   *    - shipping_address_id from cart or default address
   *    - calculated total_price
   *    - order_status = 'paid' initially
   * 6. For each cart item, create order_item with snapshot data:
   *    - product_name, product_description, variant_options (snapshots)
   *    - product_price (snapshot at purchase time)
   *    - quantity, item_status = 'paid'
   * 7. Reduce inventory: for each variant, create inventory record with negative quantity change (reason: 'order')
   * 8. Clear cart items after successful order creation
   * 9. Return complete order details with derived status and related entities
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await postEcommerceMallCustomerOrders({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of customer orders.
   *
   * This operation provides comprehensive order search capabilities including status filtering (paid, shipped, delivered, cancelled, refunded, partiallyCompleted), date range filtering, seller filtering, and total price range filtering.
   *
   * Orders are displayed in reverse chronological order with newest orders first. The response includes order summary information optimized for list displays.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_orders table with pagination and filtering.
   * Apply filters on order_status, created_at date range, customer_id, shipping_address_id, and total_price range.
   * Sort by created_at in descending order (newest first).
   * Return cursor-based pagination for large result sets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallOrder.IRequest,
  ): Promise<IPageIEcommerceMallOrder.ISummary> {
    try {
      return await patchEcommerceMallCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order including all order items, shipments, and shipping address.
   *
   * This operation allows customers to view the complete details of an order they placed. It returns the order header information, list of order items with their snapshot data, shipping address used at checkout, and all shipments associated with the order. Sellers can view order details for their own order items, and administrators can view any order.
   *
   * The response includes the order's total price, status derived from order items, and timestamps for creation and updates. Each order item displays product name, variant options, quantity, price, and item status. Shipment information includes carrier name, tracking number, and status. Shipping address shows the complete address information as it was at checkout time.
   *
   * @param connection
   * @param orderId Target order's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_orders table for the specified order ID, verifying customer ownership (for customer access) or seller ownership (for seller access). Join with ecommerce_mall_order_items to retrieve all order items with their product snapshots. Join with ecommerce_mall_shipments to retrieve associated shipments, and join with ecommerce_mall_shipment_items to link shipments to order items. Use soft delete filtering on orders (deleted_at IS NULL) if applicable. Return complete order information including all related entities.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await getEcommerceMallCustomerOrdersOrderId({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
