import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCancellationRequest } from "../../../../../api/structures/IEcommerceMallCancellationRequest";
import { IPageIEcommerceMallOrderItem } from "../../../../../api/structures/IPageIEcommerceMallOrderItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerOrdersOrderIdItems } from "../../../../../providers/getEcommerceMallCustomerOrdersOrderIdItems";
import { patchEcommerceMallCustomerOrdersOrderIdItemsOrderItemIdCancel } from "../../../../../providers/patchEcommerceMallCustomerOrdersOrderIdItemsOrderItemIdCancel";

@Controller("/ecommerceMall/customer/orders/:orderId/items")
export class EcommercemallCustomerOrdersItemsController {
  /**
   * Retrieve all order items belonging to a specific order.
   *
   * This operation returns a paginated list of all items purchased in the specified order. Each order item includes product details (name, description), variant options (color, size, etc.), quantity purchased, price at checkout time, and current fulfillment status (paid, shipped, delivered, cancelled, refunded).
   *
   * For multi-seller orders, the response includes items from all sellers involved in the order, with each item indicating its associated seller via the seller_id field.
   *
   * This operation is read-only and does not modify any order or item state. The order items returned are immutable snapshots captured at the time the order was placed, preserving historical product and variant data.
   *
   * @param connection
   * @param orderId Target order's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_order_items table filtered by order_id path parameter. Include product, variant, and seller relations for each order item. Apply pagination with configurable page size. Return item status, product_name, product_description, variant_options, product_price, quantity, and seller_id fields. Ensure order items belong to the specified order and respect customer authorization (customer can only view their own orders).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string,
  ): Promise<IPageIEcommerceMallOrderItem.ISummary> {
    try {
      return await getEcommerceMallCustomerOrdersOrderIdItems({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Request cancellation of a specific order item.
   *
   * This endpoint allows customers to submit a cancellation request for a specific order item that has been paid but not yet shipped. The cancellation request will be associated with the specific order item, the customer making the request, and the seller responsible for fulfillment.
   *
   * **Status Requirements**: Only order items with status 'paid' can be cancelled. Items that have already been shipped, delivered, cancelled, or refunded cannot be cancelled through this endpoint.
   *
   * **Request Validation**: The system will verify that the order item exists and belongs to the requesting customer. If a cancellation request already exists for this order item, the request will be rejected.
   *
   * **Business Rules**:
   * - Only customers who placed the order can request cancellation
   * - Items must have status 'paid' (not yet shipped)
   * - Only one active cancellation request per order item
   * - Seller will receive the request and can approve or reject it
   *
   * @param connection
   * @param orderId Unique identifier of the order
   * @param orderItemId Unique identifier of the order item to cancel
   * @param body Cancellation request information including the reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate that the order item exists and belongs to the requesting customer. Verify the order item status is 'paid' before allowing cancellation. Create a cancellation request record with status 'pending' linked to the order item, customer, and seller. Ensure no other active cancellation request exists for this order item. Return the created cancellation request with status 'pending'.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":orderItemId/cancel")
  public async cancel(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedParam("orderItemId")
    orderItemId: string,
    @TypedBody()
    body: IEcommerceMallCancellationRequest.ICreate,
  ): Promise<IEcommerceMallCancellationRequest> {
    try {
      return await patchEcommerceMallCustomerOrdersOrderIdItemsOrderItemIdCancel(
        {
          customer,
          orderId,
          orderItemId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
