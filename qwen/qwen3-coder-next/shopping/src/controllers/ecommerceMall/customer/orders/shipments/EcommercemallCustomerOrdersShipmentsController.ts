import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIEcommerceMallShipment } from "../../../../../api/structures/IPageIEcommerceMallShipment";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchEcommerceMallCustomerOrdersOrderIdShipments } from "../../../../../providers/patchEcommerceMallCustomerOrdersOrderIdShipments";

@Controller("/ecommerceMall/customer/orders/:orderId/shipments")
export class EcommercemallCustomerOrdersShipmentsController {
  /**
   * Retrieve all shipments for a specific order.
   *
   * This endpoint returns all shipment records associated with the given order ID. Each shipment represents a physical package created by a seller when shipping items from the order. Multiple shipments may exist for a single order when items belong to different sellers.
   *
   * The response includes carrier information, tracking numbers, shipment status, and creation timestamps. Shipment items reference the order items that are included in each physical package, enabling customers to see which specific products are included in each shipment.
   *
   * @param connection
   * @param orderId Target order's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_shipments table filtered by ecommerce_mall_order_id parameter.
   * Join with ecommerce_mall_sellers to include seller profile information.
   * Include shipment_items count for each shipment to show item quantities.
   * Order results by created_at descending to show newest shipments first.
   * Return paginated list using IPageIShipment.ISummary response structure.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string,
  ): Promise<IPageIEcommerceMallShipment.ISummary> {
    try {
      return await patchEcommerceMallCustomerOrdersOrderIdShipments({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
