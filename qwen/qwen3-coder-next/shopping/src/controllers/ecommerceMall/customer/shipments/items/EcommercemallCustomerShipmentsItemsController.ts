import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIEcommerceMallShipmentItem } from "../../../../../api/structures/IPageIEcommerceMallShipmentItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerShipmentsShipmentIdItems } from "../../../../../providers/getEcommerceMallCustomerShipmentsShipmentIdItems";

@Controller("/ecommerceMall/customer/shipments/:shipmentId/items")
export class EcommercemallCustomerShipmentsItemsController {
  /**
   * Retrieve all order items included in a specific shipment.
   *
   * This operation returns the complete list of shipment items associated with the given shipment, showing which order items are included in this physical package. Each shipment item links the shipment to an order item, providing visibility into the package contents.
   *
   * This operation is essential for sellers to verify what items they are shipping and for system administrators to confirm shipment contents during order fulfillment or dispute resolution. The response includes complete details about each order item including product information, quantities, and pricing.
   *
   * The operation enforces seller data isolation - only the seller who created the shipment can access its items. Sellers can only view shipments they personally created, and cannot access shipments created by other sellers. This ensures proper data isolation per business requirements.
   *
   * For tracking and delivery purposes, this operation works together with shipment tracking endpoints to provide complete shipment visibility from creation through delivery.
   *
   * @param connection
   * @param shipmentId Target shipment's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shipment_items table filtered by shipment_id equal to the provided shipment ID. Join with order_items table to get complete order item details. Apply pagination and support filtering/sorting on shipment item properties. Validate that the requesting seller owns the shipment (shipment.seller_id matches active seller) before returning results. Use seller-scoped data isolation to ensure sellers only access their own shipments.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async search(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string,
  ): Promise<IPageIEcommerceMallShipmentItem.ISummary> {
    try {
      return await getEcommerceMallCustomerShipmentsShipmentIdItems({
        customer,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
