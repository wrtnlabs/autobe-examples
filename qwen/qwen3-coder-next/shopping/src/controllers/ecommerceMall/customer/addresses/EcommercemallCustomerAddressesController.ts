import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallAddress } from "../../../../api/structures/IEcommerceMallAddress";
import { IPageIEcommerceMallAddress } from "../../../../api/structures/IPageIEcommerceMallAddress";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteEcommerceMallCustomerAddressesAddressId } from "../../../../providers/deleteEcommerceMallCustomerAddressesAddressId";
import { getEcommerceMallCustomerAddressesAddressId } from "../../../../providers/getEcommerceMallCustomerAddressesAddressId";
import { patchEcommerceMallCustomerAddresses } from "../../../../providers/patchEcommerceMallCustomerAddresses";
import { postEcommerceMallCustomerAddresses } from "../../../../providers/postEcommerceMallCustomerAddresses";
import { putEcommerceMallCustomerAddressesAddressId } from "../../../../providers/putEcommerceMallCustomerAddressesAddressId";

@Controller("/ecommerceMall/customer/addresses")
export class EcommercemallCustomerAddressesController {
  /**
   * Create a new shipping address for the authenticated customer.
   *
   * This operation allows customers to add new shipping addresses to their account. All required address fields must be provided including recipient name, phone number, street address, city, state/province, postal code, and country. The system validates all fields and creates a new address record associated with the customer's profile.
   *
   * When a customer has multiple addresses, they can select any address during checkout. The system allows up to 20 addresses per customer account and supports duplicate addresses (same content as separate records). Each address is independently manageable.
   *
   * @param connection
   * @param body Address creation data with all required fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create a new address in ecommerce_mall_addresses table.
   * Validate all required fields: recipient_name, phone_number, street_address, city, state_province, postal_code, country.
   * Link new address to authenticated customer's profile via customer_profile_id.
   * Set is_default flag based on business rules: if no existing address exists, mark as default; otherwise keep existing default.
   * Return created address with generated id.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallAddress.ICreate,
  ): Promise<IEcommerceMallAddress> {
    try {
      return await postEcommerceMallCustomerAddresses({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of customer addresses with search and filter capabilities.
   *
   * This operation provides advanced search capabilities for customer addresses including filtering by default status and partial text matching on recipient name, street address, and city fields. The system supports multiple addresses per customer with duplicate address support, allowing independent management of each address instance.
   *
   * All addresses are owned by the authenticated customer, ensuring data isolation where customers can only view and manage their own addresses. The system enforces a maximum of 20 addresses per customer account and maintains exactly one default shipping address at all times.
   *
   * Addresses are preserved for historical order integrity even when deleted, and the system automatically reassigns default status when addresses are modified or removed.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for address listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_addresses table with pagination and filtering.
   * Apply search filters on is_default flag, recipient_name, street_address, and city using trigram similarity for partial matching.
   * Sort by created_at descending by default, with is_default addresses appearing first.
   * Return paginated list of address summaries optimized for display in address management UI.
   * Implement ownership validation to ensure only authenticated customer can access their addresses.
   * Enforce maximum 20 address limit when creating new addresses.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallAddress.IRequest,
  ): Promise<IPageIEcommerceMallAddress.ISummary> {
    try {
      return await patchEcommerceMallCustomerAddresses({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific shipping address by its unique identifier.
   *
   * This operation allows customers to view detailed information about a specific address they have previously saved. The system enforces strict ownership validation to ensure customers can only access their own addresses. This endpoint supports the address management workflow by providing detailed address information for display, editing, or checkout purposes.
   *
   * The address data includes all shipping details (recipient name, phone number, street address, city, state/province, postal code, and country) and the default shipping designation flag. For addresses associated with existing orders, the system preserves historical accuracy by preventing deletion while still allowing retrieval of address details.
   *
   * Security is enforced at the service layer through customer ownership validation, ensuring that customers cannot access addresses belonging to other accounts. System administrators have elevated access to view all addresses for account management purposes.
   *
   * @param connection
   * @param addressId Target address's unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_addresses table by primary key id. Validate customer ownership by checking user_id matches authenticated customer's user ID. Include soft-deleted records check. Return complete address record with all shipping details and is_default flag. Handle NotFoundError for non-existent or unauthorized address access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":addressId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string,
  ): Promise<IEcommerceMallAddress> {
    try {
      return await getEcommerceMallCustomerAddressesAddressId({
        customer,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific shipping address for the authenticated customer.
   *
   * This operation allows customers to modify their saved address information including recipient name, phone number, street address, city, state/province, postal code, and country. The address must belong to the authenticated customer's profile. Only the customer who owns the address can perform updates - customers cannot modify addresses belonging to other users.
   *
   * Security is enforced at the service layer by validating that the authenticated customer's profile ID matches the address's customer_profile_id. If the address is currently set as the default shipping address, this operation preserves the default status. The system validates all updated fields against the same requirements as address creation including phone number format and postal code format.
   *
   * This operation directly corresponds to the ecommerce_mall_addresses table in the database, which stores all shipping address information for customer accounts. Each customer can have multiple addresses, and one address can be marked as the default shipping address for convenience. Historical address data for past orders is preserved even when the address record is updated, ensuring order fulfillment accuracy.
   *
   * @param connection
   * @param addressId Target address's unique identifier
   * @param body Address update request with new values
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update ecommerce_mall_addresses record by ID. Validate that authenticated customer's profile_id matches address.customer_profile_id. Apply field updates for recipient_name, phone_number, street_address, city, state_province, postal_code, country. Validate phone number format and postal code format. Preserve is_default flag unless explicitly changed. Update updated_at timestamp to current time. Return updated address record with all fields including id, customer_profile_id, user_id.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":addressId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string,
    @TypedBody()
    body: IEcommerceMallAddress.IUpdate,
  ): Promise<IEcommerceMallAddress> {
    try {
      return await putEcommerceMallCustomerAddressesAddressId({
        customer,
        addressId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific shipping address from the customer's address book.
   *
   * This endpoint removes an address that was previously created by the authenticated customer. The operation includes comprehensive validation to ensure data integrity and business rule compliance.
   *
   * **Security and Authorization:**
   * - Only the address owner can delete their addresses
   * - Access to addresses belonging to other customers is strictly prohibited
   * - Customer authentication is required via JWT token
   *
   * **Business Validation Rules:**
   * - The address must be owned by the authenticated customer
   * - If the address is the only address, deletion is prevented
   * - If the address is the default address for any active or completed orders, deletion is prevented
   * - If the address is associated with pending, shipped, or delivered orders, deletion is prevented
   * - If deletion succeeds and the address was the default, another address is automatically assigned as default
   * - If deletion succeeds and no other addresses remain, the default flag is cleared
   *
   * **Cascading Behavior:**
   * - Address records for historical orders are preserved in the database
   * - Only addresses not referenced by any active or completed orders can be deleted
   * - Order history with address snapshots remains intact regardless of address deletion
   *
   * **Edge Cases:**
   * - Attempting to delete the only remaining address returns an error
   * - Attempting to delete an address used in active orders returns an error
   * - Attempting to delete an address belonging to another customer returns a 404 error to prevent information leakage
   *
   * @param connection
   * @param addressId Target address's ID (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Delete customer address with comprehensive validation and business rule enforcement.
   *
   * 1. **Authorization Check**: Validate that the authenticated customer matches the address owner (user_id). Return 404 if ownership fails to prevent information leakage.
   *
   * 2. **Address Existence Check**: Fetch address by id where user_id matches authenticated customer. Return 404 if not found.
   *
   * 3. **Default Address Validation**:
   *    - Check if this is the only address for the customer. If true, return error 400.
   *    - Check if this address is marked as default (is_default = true). If true, proceed but prepare to reassign default.
   *
   * 4. **Active Order Lock Check**:
   *    - Query orders where shipping_address_id = addressId AND order_status IN ('paid', 'shipped', 'delivered')
   *    - If any orders found, return error 400: 'Address is associated with active or completed orders and cannot be deleted'
   *
   * 5. **Default Reassignment**:
   *    - If address is_default = true and other addresses exist:
   *      - Update another address to is_default = true (oldest remaining address)
   *    - If address is_default = true and no other addresses exist:
   *      - No reassignment needed (will be cleared by cascade)
   *
   * 6. **Soft Delete**: Set deleted_at = CURRENT_TIMESTAMP on the address record
   *
   * 7. **Return**: No content (204 No Content)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":addressId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallCustomerAddressesAddressId({
        customer,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
