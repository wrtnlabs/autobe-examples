import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerProductsProductIdVariantsPreview } from "../../../../../../providers/getEcommerceMallCustomerProductsProductIdVariantsPreview";

@Controller("/ecommerceMall/customer/products/:productId/variants/preview")
export class EcommercemallCustomerProductsVariantsController {
  /**
   * @param connection
   * @param productId Target product's ID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async preview(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productId")
    productId: string,
  ): Promise<void> {
    try {
      return await getEcommerceMallCustomerProductsProductIdVariantsPreview({
        customer,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
