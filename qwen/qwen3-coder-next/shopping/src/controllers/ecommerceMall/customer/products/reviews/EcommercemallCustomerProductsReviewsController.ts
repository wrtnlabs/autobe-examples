import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallReview } from "../../../../../api/structures/IEcommerceMallReview";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { postEcommerceMallCustomerProductsProductIdReviews } from "../../../../../providers/postEcommerceMallCustomerProductsProductIdReviews";

@Controller("/ecommerceMall/customer/products/:productId/reviews")
export class EcommercemallCustomerProductsReviewsController {
  /**
   * Submit a new review for a product after purchase.
   *
   * This operation allows customers to submit a review for a product they have purchased. The review includes a rating (1-5 stars) and optional text content describing their experience. Before submission, the system validates that the customer has purchased the product through an order and that they have not already submitted a review for this product within the same order.
   *
   * ## Requirements
   *
   * To submit a review, you must:
   * 1. Be an authenticated customer
   * 2. Have purchased the product through an order
   * 3. Not have already submitted a review for this product in the same order
   * 4. Provide a rating between 1 (inclusive) and 5 (inclusive)
   * 5. Provide optional text content up to 10,000 characters
   *
   * ## Validation
   *
   * The system will reject the request if:
   * - You have not purchased this product
   * - You have already submitted a review for this product in the same order
   * - The rating is outside the 1-5 range
   * - The text content exceeds 10,000 characters
   *
   * ## Response
   *
   * Upon successful submission, the system will:
   * 1. Create a new review record in the database
   * 2. Calculate and update the product's average rating
   * 3. Increment the product's review count
   * 4. Return the newly created review with its ID, timestamps, and snapshot data
   *
   * ## Related Operations
   *
   * - **GET /products/{productId}/reviews** - Retrieve existing reviews for a product
   * - **PATCH /reviews/{reviewId}** - Update your own review (creates snapshot)
   * - **DELETE /reviews/{reviewId}** - Delete your own review (preserves snapshot)
   *
   * @param connection
   * @param productId Target product's UUID identifier.
   * @param body Review content including rating (1-5) and optional text content.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create a new review record in the ecommerce_mall_reviews table. Validate that the authenticated customer has purchased the product through an order item and that they have not already submitted a review for this product in the same order. Enforce rating range 1-5 and text content length limit. Calculate and update the product's average rating and review count after successful creation. Return the created review with generated ID and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IEcommerceMallReview.ICreate,
  ): Promise<IEcommerceMallReview> {
    try {
      return await postEcommerceMallCustomerProductsProductIdReviews({
        customer,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
