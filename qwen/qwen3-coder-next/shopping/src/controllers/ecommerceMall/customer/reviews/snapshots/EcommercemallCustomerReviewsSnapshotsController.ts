import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallReview } from "../../../../../api/structures/IEcommerceMallReview";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerReviewsReviewIdSnapshots } from "../../../../../providers/getEcommerceMallCustomerReviewsReviewIdSnapshots";

@Controller("/ecommerceMall/customer/reviews/:reviewId/snapshots")
export class EcommercemallCustomerReviewsSnapshotsController {
  /**
   * Retrieve the complete edit history and audit trail for a specific review.
   *
   * This operation returns all review snapshots associated with the specified review ID. Each snapshot captures the review's state (rating and text content) at a specific point in time, providing a complete history of all edits and modifications made to the review.
   *
   * The snapshots are returned in chronological order (newest first) and include metadata about when each edit occurred. This audit trail enables dispute resolution, customer support investigations, and quality assurance reviews.
   *
   * Access Control:
   * - Customers can view snapshots for their own reviews
   * - Sellers can view snapshots for reviews on their products
   * - Administrators can view snapshots for any review
   *
   * Business Context:
   * Review snapshots are automatically created whenever a customer edits their review or marks it for deletion. Each snapshot preserves the rating value and text content exactly as they existed at the time of the edit, ensuring an immutable audit trail for compliance and dispute resolution purposes.
   *
   * @param connection
   * @param reviewId Target review's ID (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_review_snapshots table filtered by review_id (ecommerce_mall_review_id).
   * Return all snapshots ordered by created_at in descending order (newest first).
   * Return complete snapshot records including rating, text_content, snapshot_type, and created_at.
   * No pagination needed - snapshots are typically limited in数量.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string,
  ): Promise<IEcommerceMallReview> {
    try {
      return await getEcommerceMallCustomerReviewsReviewIdSnapshots({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
