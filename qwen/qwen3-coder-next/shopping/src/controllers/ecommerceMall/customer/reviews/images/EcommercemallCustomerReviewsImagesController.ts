import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallReviewImage } from "../../../../../api/structures/IEcommerceMallReviewImage";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { postEcommerceMallCustomerReviewsReviewIdImages } from "../../../../../providers/postEcommerceMallCustomerReviewsReviewIdImages";

@Controller("/ecommerceMall/customer/reviews/:reviewId/images")
export class EcommercemallCustomerReviewsImagesController {
  /**
   * Upload images to a customer review.
   *
   * This operation allows the customer who wrote a review to add one or more images that provide visual context or evidence supporting their review. The images are associated with the specific review identified by reviewId in the path parameter.
   *
   * Only the customer who owns the review (determined by reviewing_customer_id matching the authenticated customer's user ID) can upload images to that review. Seller users and other customers are not permitted to upload images to reviews they do not own.
   *
   * When images are uploaded, they are stored with a sort_order value that maintains the display order for the review's image gallery. The first image uploaded receives sort_order=1, subsequent images increment sequentially.
   *
   * This operation supports the customer's review authoring workflow by enabling them to add visual content that helps communicate their experience with the product. Multiple images can be uploaded through multiple calls to this endpoint, and the system maintains the ordering of images as they are added.
   *
   * @param connection
   * @param reviewId ID of the review to which images will be added. Must belong to the authenticated customer.
   * @param body Upload metadata for review image
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Upload review image by:
   * 1. Validate reviewId exists and belongs to authenticated customer
   * 2. Check review is not soft-deleted (deleted_at is null)
   * 3. Generate unique filename for uploaded image
   * 4. Store image in object storage and record URL
   * 5. Query existing images for the review to determine next sort_order
   * 6. Create new review image with computed sort_order
   * 7. Return created review image with full details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async createReviewImage(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallReviewImage.ICreate,
  ): Promise<IEcommerceMallReviewImage> {
    try {
      return await postEcommerceMallCustomerReviewsReviewIdImages({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
