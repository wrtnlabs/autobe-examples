import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCartValidationResult } from "../../../../../api/structures/IEcommerceMallCartValidationResult";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerCartValidation } from "../../../../../providers/getEcommerceMallCustomerCartValidation";
import { patchEcommerceMallCustomerCartValidation } from "../../../../../providers/patchEcommerceMallCustomerCartValidation";

@Controller("/ecommerceMall/customer/cart/validation")
export class EcommercemallCustomerCartValidationController {
  /**
   * Validate customer cart items for checkout readiness.
   *
   * This endpoint checks the current state of all items in the customer's shopping cart to ensure they meet checkout requirements. It validates that all cart items are associated with active, non-suspended sellers, that all variants are available and in stock, and that sufficient stock exists for requested quantities.
   *
   * The validation results are returned as warnings and a list of unavailable items. Items failing validation cannot be included in checkout until removed or adjusted by the customer.
   *
   * Security considerations: This endpoint only validates items belonging to the authenticated customer. The cart is isolated per user and cannot be accessed by other users.
   *
   * Related operations:
   * - GET /cart: Retrieve current cart contents
   * - POST /cart/items: Add items to cart (includes validation)
   * - POST /checkout/validate: Validate cart before creating order
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query all cart items for the authenticated customer.
   * Check each cart item's variant against current stock and availability.
   * Verify the seller associated with each cart item is active and not suspended.
   * Return validation warnings for items that are out of stock or associated with suspended sellers.
   * Include unavailable items list with specific reasons for each failure.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async get(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<void> {
    try {
      return await getEcommerceMallCustomerCartValidation({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Validate the customer's shopping cart for checkout eligibility.
   *
   * This operation performs comprehensive validation of all cart items to determine their eligibility for checkout. It checks each item's variant availability, stock quantity, seller status, and other business rules that must pass before an order can be created.
   *
   * The validation examines:
   * - Whether each cart item's product variant still exists (not deleted)
   * - Whether each variant has sufficient stock for the requested quantity
   * - Whether each variant's seller is active and not suspended
   * - Whether all items belong to the same seller (cross-seller cart limitation)
   *
   * The response provides detailed information about each item's validation status, including specific reasons for any failures. Items that fail validation are marked as unavailable and cannot be included in the checkout process.
   *
   * After successful validation, the customer can proceed with checkout. If any items fail validation, the customer must remove or modify those items before attempting checkout again.
   *
   * @param connection
   * @param body Validation options and filter criteria
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate all cart items for the authenticated customer.
   * Query cart_items table joined with product_variants and sellers tables.
   * For each cart item, check:
   * 1. Variant exists (deleted_at is null)
   * 2. Variant stock_quantity >= cart_item.quantity
   * 3. Seller is not suspended (is_suspended = false)
   * 4. All items belong to same seller (cross-seller validation)
   * Return validation results with availability status and failure reasons for each item.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async patch(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCartValidationResult.IRequest,
  ): Promise<IEcommerceMallCartValidationResult.ISummary> {
    try {
      return await patchEcommerceMallCustomerCartValidation({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
