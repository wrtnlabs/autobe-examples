import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallReview } from "../../../../api/structures/IEcommerceMallReview";
import { patchEcommerceMallProductsProductIdReviews } from "../../../../providers/patchEcommerceMallProductsProductIdReviews";

@Controller("/ecommerceMall/products/:productId/reviews")
export class EcommercemallProductsReviewsController {
  /**
   * Update an existing customer review for a product.
   *
   * This endpoint allows the review owner to modify their review content, including the rating (1-5 stars) and optional text. When a review is updated, the system creates a new snapshot preserving the previous state for audit and dispute resolution purposes. The original review remains active with updated fields, while the previous version is archived in the review snapshots table.
   *
   * Security and permissions:
   * - Only the review owner (customer who wrote the review) can update their review
   * - Sellers can view review snapshots for their products but cannot modify reviews
   * - Administrators can view all reviews and snapshots for platform oversight
   * - The system prevents updates to reviews that have been deleted (soft-deleted)
   *
   * The update operation enforces business rules:
   * - Rating must be an integer between 1 (inclusive) and 5 (inclusive)
   * - Text content must not exceed 10,000 characters
   * - A review can only be updated if the associated product is still available (not deleted)
   * - If the product was deleted, the review can still be updated but the product will be marked as unavailable in the response
   *
   * The system creates a review snapshot with type 'edit' on each update, capturing the previous rating and text content. This snapshot history is accessible to sellers and administrators for dispute resolution.
   *
   * Related operations:
   * - GET /products/{productId}/reviews: Retrieve product reviews
   * - POST /products/{productId}/reviews: Write a new review
   * - GET /reviews/{reviewId}/snapshots: View review edit history (snapshot list)
   *
   * @param connection
   * @param productId Target product ID (UUID)
   * @param body Review update request with rating (1-5) and optional text content
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Update existing review by reviewId with validation. Enforce rating 1-5 range, text max 10,000 chars. Create review snapshot with type 'edit' on update. Soft-delete reviews by setting deleted_at timestamp. Return updated review with current state. Ensure review ownership verification and product availability check.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IEcommerceMallReview.IRequest,
  ): Promise<IEcommerceMallReview> {
    try {
      return await patchEcommerceMallProductsProductIdReviews({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
