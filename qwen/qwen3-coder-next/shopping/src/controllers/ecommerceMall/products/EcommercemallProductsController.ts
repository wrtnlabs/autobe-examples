import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallProduct } from "../../../api/structures/IEcommerceMallProduct";
import { IPageIEcommerceMallCustomer } from "../../../api/structures/IPageIEcommerceMallCustomer";
import { IPageIEcommerceMallProduct } from "../../../api/structures/IPageIEcommerceMallProduct";
import { getEcommerceMallProductsProductId } from "../../../providers/getEcommerceMallProductsProductId";
import { patchEcommerceMallProducts } from "../../../providers/patchEcommerceMallProducts";
import { patchEcommerceMallProductsSearch } from "../../../providers/patchEcommerceMallProductsSearch";

@Controller("/ecommerceMall/products")
export class EcommercemallProductsController {
  /**
   * Retrieve a filtered and paginated list of products.
   *
   * This operation provides comprehensive search and filtering capabilities for products in the e-commerce mall. It allows filtering by category, price range, and stock availability, with multiple sorting options.
   *
   * **Filtering Options**:
   * - Category filtering to narrow products to specific categories
   * - Price range filtering with minimum and maximum price constraints
   * - Stock availability filtering to show only in-stock products
   * - Support for text search on product names and descriptions
   *
   * **Sorting Options**:
   * - Newest products first (default)
   * - Price ascending
   * - Price descending
   *
   * **Pagination Support**:
   * - Configurable page size with default values
   * - Cursor-based pagination for efficient large dataset handling
   * - Total count of matching products included in response
   *
   * This endpoint is designed for both guest browsing and authenticated customer searches. The system enforces rate limiting with 30 requests per minute to prevent abuse.
   *
   * **Security Considerations**:
   * - Only active products (is_available=true and deleted_at=null) are returned
   * - Products from suspended sellers are automatically excluded
   * - Price filters are applied on the base_price field with proper numeric validation
   *
   * **Related Operations**:
   * - GET /products/:id - Retrieve detailed information for a specific product
   * - POST /products - Create a new product (seller-only operation)
   * - PATCH /products/:id - Update an existing product (seller-only operation)
   *
   * **Error Handling**:
   * - Invalid category IDs return 400 Bad Request
   * - Invalid price ranges (min > max) return 400 Bad Request
   * - Invalid sort options return 400 Bad Request
   * - Rate limiting may return 429 Too Many Requests
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the ecommerce_mall_products table with filtering, sorting, and pagination. Apply filters for category_id, min_price, max_price, and in_stock status. Exclude products from suspended sellers and soft-deleted products. Return cursor-based pagination with configurable page sizes. Sort by created_at (newest first), base_price ascending, or base_price descending based on request parameters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommerceMallProduct.IRequest,
  ): Promise<IPageIEcommerceMallCustomer.ISummary> {
    try {
      return await patchEcommerceMallProducts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific product.
   *
   * This operation fetches the complete product details including name, description, base price, availability status, and associated metadata. It returns comprehensive product information optimized for product detail pages.
   *
   * **Access Control**: Available to all authenticated users (customer, seller, admin). Public access is not permitted for this endpoint.
   *
   * **Product Availability**: Products with non-null `deleted_at` timestamps are filtered out and return "not found" status, consistent with customer-facing product listing behavior.
   *
   * **Related Operations**:
   * - `GET /products` (index) — List products with filters and pagination
   * - `POST /products` (create) — Create a new product (seller only)
   * - `PATCH /products/{id}` (update) — Update product details (seller only)
   * - `DELETE /products/{id}` (erase) — Delete product (seller only)
   *
   * @param connection
   * @param productId Target product's UUID identifier.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_mall_products table by id (UUID). Join with ecommerce_mall_sellers for seller shop name and ecommerce_mall_categories for category name and hierarchy. Apply soft-delete filter (deleted_at IS NULL). Return product details including seller_id, category_id, name, description, base_price, is_available, timestamps, and nested seller/category objects.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @TypedParam("productId")
    productId: string,
  ): Promise<IEcommerceMallProduct> {
    try {
      return await getEcommerceMallProductsProductId({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and filter products with comprehensive search and browsing capabilities.
   *
   * This operation provides advanced product search functionality allowing customers to search by product name, filter by category (including subcategories), filter by price range (minimum and maximum), filter for in-stock products only, and sort by various criteria. The search results follow the product search and listing expectations defined in the business requirements, ensuring consistent browsing experience across the platform.
   *
   * ## Search Capabilities
   * - Keyword search by product name
   * - Category filtering with automatic subcategory inclusion
   * - Price range filtering (minimum and maximum)
   * - In-stock only filtering
   * - Multiple sort options: newest, price ascending, price descending
   *
   * ## Filtering Details
   * - Category filtering includes products from both parent and child categories
   * - In-stock filtering excludes products where all variants have zero stock
   * - Products from suspended sellers are excluded regardless of filter combination
   *
   * ## Response Information
   * - Products displayed with main image thumbnail, name, seller shop name, base price or price range, and average rating
   * - Products with no variants are marked as unavailable
   * - Out-of-stock variants are indicated in listings
   *
   * ## Error Handling
   * - Empty search terms return no results unless combined with filters
   * - Deleted products are excluded from search results
   * - Invalid category references are handled gracefully
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_mall_products table with pagination and comprehensive filtering.
   * Join with ecommerce_mall_product_variants for stock quantity and price information.
   * Apply category filter including subcategories using hierarchical category query.
   * Apply price range filtering on product base_price.
   * Apply in_stock filter excluding products where all variants have zero stock.
   * Apply search filters on product name using case-insensitive matching.
   * Join with ecommerce_mall_sellers to exclude suspended sellers.
   * Support pagination with configurable page size (default 20 items per page).
   * Support sorting by newest (created_at DESC), price_asc (base_price ASC), price_desc (base_price DESC).
   * Return cursor-based pagination for large result sets.
   * Optimize queries with existing indexes on created_at, base_price, is_available, seller_id, and name (gin_trgm_ops).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("search")
  public async search(
    @TypedBody()
    body: IEcommerceMallProduct.IRequest,
  ): Promise<IPageIEcommerceMallProduct.ISummary> {
    try {
      return await patchEcommerceMallProductsSearch({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
