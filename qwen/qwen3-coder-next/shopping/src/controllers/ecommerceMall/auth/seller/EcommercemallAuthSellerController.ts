import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSeller } from "../../../../api/structures/IEcommerceMallSeller";
import { postEcommerceMallAuthSellerJoin } from "../../../../providers/postEcommerceMallAuthSellerJoin";
import { postEcommerceMallAuthSellerLogin } from "../../../../providers/postEcommerceMallAuthSellerLogin";
import { postEcommerceMallAuthSellerRefresh } from "../../../../providers/postEcommerceMallAuthSellerRefresh";

@Controller("/ecommerceMall/auth/seller")
export class EcommercemallAuthSellerController {
  /**
   * Seller registration endpoint that creates a new seller account in the system. The registration process involves:
   *
   * 1. **Email validation**: Checks that the email is unique and properly formatted
   * 2. **Password hashing**: Uses bcrypt to securely hash the password before storage
   * 3. **Seller record creation**: Creates a record in the ecommerce_mall_sellers table with approval_status set to 'pending' (requires admin approval before first login)
   * 4. **Initial profile setup**: Creates corresponding seller profile with shop_name from registration data
   *
   * The created seller account remains in 'pending' state until an administrator approves the registration. During this pending state, login attempts will be rejected even with correct credentials. This approval workflow ensures platform quality control and prevents unauthorized seller accounts.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration request containing email, password, and shop information
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Process seller registration by creating an ecommerce_mall_sellers record with pending approval status. Validate email uniqueness, hash password using bcrypt, and return seller credentials for first login.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSeller.IJoin,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Seller login endpoint that authenticates sellers and issues JWT tokens. The authentication process includes:
   *
   * 1. **Email lookup**: Retrieves seller record from ecommerce_mall_sellers by email
   * 2. **Password verification**: Uses bcrypt to compare provided password with stored password_hash
   * 3. **Account status validation**: Verifies the seller account meets all requirements:
   * - Account is not soft-deleted (deleted_at is null)
   * - Account is not suspended (is_suspended is false)
   * - Approval status is 'approved' (seller registration was approved by admin)
   * 4. **JWT token generation**: Creates access and refresh tokens with seller ID and role claims
   *
   * The login endpoint ensures that only approved, active seller accounts can authenticate. Sellers with pending approval, rejected registration, or suspended status will receive authentication failures even with correct credentials. This multi-layer validation maintains platform security and compliance with the seller approval workflow.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login request containing email and password credentials
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Process seller login by validating email/password against ecommerce_mall_sellers record. Check account status (not deleted, not suspended, approval_status='approved') before generating JWT tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSeller.ILogin,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Seller token refresh endpoint that renews authentication tokens using a refresh token. This operation:
   *
   * 1. **Refresh token validation**: Looks up the refresh token in ecommerce_mall_seller_sessions table
   * 2. **Session verification**: Confirms the session is still valid (not expired, seller account still active)
   * 3. **Token rotation**: Generates new access and refresh tokens according to security policy
   * 4. **Session update**: Updates the session record with new refresh token if rotation is enabled
   *
   * The refresh endpoint maintains security through token rotation and ensures sellers maintain authenticated access during their session lifetime. It respects the session policies defined for the seller authentication system, including token expiration times and rotation policies.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh request containing the current refresh token
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Process token refresh by validating refresh token against ecommerce_mall_seller_sessions table. Generate new access token and optionally new refresh token if rotation policy is configured.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallSeller.IRefresh,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
