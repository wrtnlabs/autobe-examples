import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallAdmin } from "../../../../api/structures/IEcommerceMallAdmin";
import { postEcommerceMallAuthAdminJoin } from "../../../../providers/postEcommerceMallAuthAdminJoin";
import { postEcommerceMallAuthAdminLogin } from "../../../../providers/postEcommerceMallAuthAdminLogin";
import { postEcommerceMallAuthAdminRefresh } from "../../../../providers/postEcommerceMallAuthAdminRefresh";

@Controller("/ecommerceMall/auth/admin")
export class EcommercemallAuthAdminController {
  /**
   * Register a new admin account for the platform administration system.
   *
   * ## Purpose
   *
   * This operation creates a new admin account with email/password credentials, enabling
   * the user to access the platform administration system. Admin accounts require
   * email/password authentication and their sessions are tracked in the admin_sessions
   * table for security auditing.
   *
   * ## Implementation Details
   *
   * The operation validates the email format and checks for uniqueness in the
   * ecommerce_mall_admins table. The password is securely hashed before storage.
   * The new admin record is created with the provided credentials and initial
   * grade assignment (regular or super). The operation supports the password reset
   * functionality by ensuring the created admin can receive reset tokens through
   * the ecommerce_mall_admin_password_resets table.
   *
   * ## Security Considerations
   *
   * Admin registration should be restricted to authorized personnel. The email
   * validation prevents duplicate accounts, and the password hashing ensures
   * credentials are not stored in plain text. The admin's initial grade determines
   * their privilege level (regular vs super administrator).
   *
   * ## Related Operations
   *
   * - Login: After registration, admins can authenticate using the /auth/login/admin
   * endpoint.
   * - Password Reset: If admins forget their password, they can request a reset
   * through the password reset flow using the ecommerce_mall_admin_password_resets
   * table.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration information for new admin account
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create new admin record in ecommerce_mall_admins table with hashed password. Validate email uniqueness, hash password with bcrypt, assign initial grade, and return JWT tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallAdmin.IJoin,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate admin user with email and password to establish a session.
   *
   * ## Purpose
   *
   * This operation validates admin credentials and creates a new JWT session in the
   * ecommerce_mall_admin_sessions table. Successful authentication returns access
   * and refresh tokens for continued API access.
   *
   * ## Implementation Details
   *
   * The operation retrieves the admin record from ecommerce_mall_admins by email
   * and validates the password hash. If credentials are valid, a new session record
   * is created in ecommerce_mall_admin_sessions with the client's IP address,
   * request URL, and referrer for security auditing. The access token has a short
   * expiration (e.g., 15-30 minutes) while the refresh token lasts longer (e.g.,
   * 7 days).
   *
   * ## Security Considerations
   *
   * Admin authentication is treated with higher security than regular users due to
   * the elevated privileges. The session tracking captures IP and request metadata
   * for audit trail purposes. Failed login attempts should be monitored for
   * potential brute force attacks.
   *
   * ## Related Operations
   *
   * - Refresh: Use the refresh token to obtain new access tokens when the current
   * one expires.
   * - Logout: Client discards tokens (server-side invalidation is not implemented
   * as JWTs are stateless).
   * - Password Reset: Admins can request password reset if they forget their
   * credentials.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Admin credentials for authentication
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate admin credentials against ecommerce_mall_admins table. Create session record in ecommerce_mall_admin_sessions with IP and referrer tracking. Generate access and refresh JWT tokens with appropriate expiration.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallAdmin.ILogin,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew expired access tokens using a valid refresh token.
   *
   * ## Purpose
   *
   * This operation extends an admin's authenticated session by exchanging a valid
   * refresh token for new access and refresh tokens. This maintains session continuity
   * without requiring re-authentication.
   *
   * ## Implementation Details
   *
   * The operation validates the refresh token and checks the admin_sessions table
   * for an active session. If the refresh token is valid and the session exists,
   * new JWT tokens are generated. The session's expired_at timestamp is extended
   * to maintain the session lifetime up to the refresh token's maximum duration.
   *
   * ## Security Considerations
   *
   * Refresh token rotation can be implemented for enhanced security by invalidating
   * the old refresh token and issuing a new one. The operation ensures that only
   * currently active sessions can obtain new tokens, preventing use of expired or
   * revoked sessions.
   *
   * ## Related Operations
   *
   * - Login: Initial authentication operation that provides refresh tokens.
   * - Logout: Client discards tokens to terminate session.
   * - Password Reset: Changes password invalidates existing sessions requiring
   * re-authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for session renewal
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate refresh token from request body against admin_sessions table. Generate new access and refresh JWT tokens. Extend session expiration while maintaining security constraints.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallAdmin.IRefresh,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
