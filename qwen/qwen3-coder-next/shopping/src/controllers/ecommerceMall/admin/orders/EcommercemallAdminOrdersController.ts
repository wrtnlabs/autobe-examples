import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallOrder } from "../../../../api/structures/IEcommerceMallOrder";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminOrdersOrderId } from "../../../../providers/getEcommerceMallAdminOrdersOrderId";
import { putEcommerceMallAdminOrdersOrderId } from "../../../../providers/putEcommerceMallAdminOrdersOrderId";

@Controller("/ecommerceMall/admin/orders/:orderId")
export class EcommercemallAdminOrdersController {
  /**
   * Retrieve detailed information about a specific order including all order items, shipments, and shipping address.
   *
   * This operation allows customers to view the complete details of an order they placed. It returns the order header information, list of order items with their snapshot data, shipping address used at checkout, and all shipments associated with the order. Sellers can view order details for their own order items, and administrators can view any order.
   *
   * The response includes the order's total price, status derived from order items, and timestamps for creation and updates. Each order item displays product name, variant options, quantity, price, and item status. Shipment information includes carrier name, tracking number, and status. Shipping address shows the complete address information as it was at checkout time.
   *
   * @param connection
   * @param orderId Target order's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_orders table for the specified order ID, verifying customer ownership (for customer access) or seller ownership (for seller access). Join with ecommerce_mall_order_items to retrieve all order items with their product snapshots. Join with ecommerce_mall_shipments to retrieve associated shipments, and join with ecommerce_mall_shipment_items to link shipments to order items. Use soft delete filtering on orders (deleted_at IS NULL) if applicable. Return complete order information including all related entities.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await getEcommerceMallAdminOrdersOrderId({
        admin,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing order with valid modifications.
   *
   * This operation allows updating specific aspects of an order that have not yet been fulfilled. It supports updating the shipping address before the order is shipped and modifying item quantities before processing begins.
   *
   * The system enforces strict state-based validation:
   * - Orders in paid status may have address changes but not item quantity changes
   * - Orders in shipped or delivered status are locked from modifications
   * - Cancellation or refund requests block updates until resolved
   * - Sellers can only update items related to their products in the order
   *
   * When an order is updated, the system recalculates the total price and validates inventory availability for any quantity changes.
   *
   * @param connection
   * @param orderId Target order's unique identifier
   * @param body Order update request with optional shipping address change and item quantity modifications
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Process order update with state-based validation.
   * 1. Load order with all order items, verifying customer ownership or admin access
   * 2. Validate order status is not shipped/delivered/cancelled/refunded
   * 3. If shippingAddressId provided, validate it belongs to customer
   * 4. If order items quantities updated, validate inventory availability
   * 5. Recalculate total price based on updated item quantities
   * 6. Update order record with new fields
   * 7. Return updated order with current status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedBody()
    body: IEcommerceMallOrder.IUpdate,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await putEcommerceMallAdminOrdersOrderId({
        admin,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
