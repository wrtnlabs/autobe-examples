import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCategory } from "../../../../api/structures/IEcommerceMallCategory";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteEcommerceMallAdminCategoriesCategoryId } from "../../../../providers/deleteEcommerceMallAdminCategoriesCategoryId";
import { postEcommerceMallAdminCategories } from "../../../../providers/postEcommerceMallAdminCategories";
import { putEcommerceMallAdminCategoriesCategoryId } from "../../../../providers/putEcommerceMallAdminCategoriesCategoryId";

@Controller("/ecommerceMall/admin/categories")
export class EcommercemallAdminCategoriesController {
  /**
   * Update an existing category's details.
   *
   * This operation allows authorized administrators to modify category information including name, description, and parent category assignment. The system enforces name uniqueness within each parent category, allowing multiple categories with the same name only if they have different parents.
   *
   * Security considerations:
   * - Only users with admin role can perform this operation
   * - Request must include valid authentication token
   * - Category name must be unique among siblings (categories with same parent)
   * - Parent category must exist if specified
   *
   * The update operation preserves the category's creation timestamp while updating the modified timestamp. All existing product assignments and subcategory relationships remain intact unless explicitly changed through parent_category_id update.
   *
   * @param connection
   * @param categoryId Target category's unique identifier (UUID)
   * @param body Category update request with new details
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update category details in ecommerce_mall_categories table.
   * Verify user has admin role before processing.
   * Fetch existing category by id from path parameter.
   * Validate new name is unique among siblings (same parent_category_id).
   * If parent_category_id is provided, verify it exists and is not the category itself or a descendant.
   * Apply updates to name, description, parent_category_id fields.
   * Return updated category with all fields including timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string,
    @TypedBody()
    body: IEcommerceMallCategory.IUpdate,
  ): Promise<IEcommerceMallCategory> {
    try {
      return await putEcommerceMallAdminCategoriesCategoryId({
        admin,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a category from the system.
   *
   * This operation permanently removes a category from the platform. Only administrators have permission to delete categories. When a category is deleted, all products assigned to that category are automatically reassigned to the parent category if it exists, or marked as uncategorized if there is no parent.
   *
   * **Authorization**: This operation is restricted to users with the 'admin' role. Non-administrative users will receive a 403 Forbidden response.
   *
   * **Business Rules**:
   * - Categories can be deleted at any nesting level
   * - When a category with products is deleted, products are reassigned to the parent category or marked as uncategorized
   * - Deletion does not cascade to products - products remain on the platform
   * - If a category has subcategories, those must be reassigned or deleted first
   *
   * **Related Operations**:
   * - Use GET /categories/{id} to view category details before deletion
   * - Use POST /categories to create new categories
   * - Use PATCH /categories/{id} to update category information
   *
   * @param connection
   * @param categoryId Category's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Delete category by ID and reassign associated products.
   * 1. Validate admin authentication and authorization
   * 2. Retrieve category by ID and verify it exists
   * 3. If category has products, reassign them to parent category or mark uncategorized
   * 4. If category has subcategories, reassign them to parent or delete recursively
   * 5. Delete the category from the database
   * 6. Return 204 No Content on success or appropriate error codes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallAdminCategoriesCategoryId({
        admin,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new product category in the system.
   *
   * This operation allows administrators to create a new category for organizing products. Categories support a one-level hierarchy where subcategories can be created under top-level categories, but subcategories cannot have their own children.
   *
   * The operation validates that the parent category (if provided) is either null (for root-level categories) or a valid existing category that itself has no parent. This ensures the one-level nesting restriction is enforced.
   *
   * @param connection
   * @param body Category creation data
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new category in ecommerce_mall_categories table with name, optional description, and optional parent_category_id.
   * Validate that parent_category_id is either null or refers to a root-level category (parent_category_id IS NULL).
   * Reject the request if parent_category_id references a subcategory.
   * Generate a new UUID for the category ID.
   * Return the complete created category with all system fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallCategory.ICreate,
  ): Promise<IEcommerceMallCategory> {
    try {
      return await postEcommerceMallAdminCategories({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
