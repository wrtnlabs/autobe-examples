  /**
   * Create an administrator-initiated order override action.
   *
   * This operation allows administrators to perform force cancellation or refund actions on order items, creating a permanent audit trail record. The override action is applied to a specific order item and includes detailed documentation of the administrative decision.
   *
   * Administrators must provide the target order item identifier, specify the action type (cancel or refund), and include a reason for the override. The system creates a new order override record linking the administrator, customer, seller, and affected order items.
   *
   * The operation is restricted to administrator roles with appropriate permissions. Regular customers, sellers, and guests cannot access this endpoint. All override actions are permanently recorded in the system for compliance and dispute resolution purposes.
   *
   * @param connection
   * @param body Request body containing order override details
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create new order override record with provided order_item_id, action_type, and reason. Validate that order_item_id exists and belongs to active order. Link to current admin user (authenticated). Create audit trail record with timestamp. Return created order override with all related references.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
