import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallProductDeletion } from "../../../../api/structures/IEcommerceMallProductDeletion";
import { IPageIEcommerceMallProductDeletion } from "../../../../api/structures/IPageIEcommerceMallProductDeletion";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminProductDeletionsProductDeletionId } from "../../../../providers/getEcommerceMallAdminProductDeletionsProductDeletionId";
import { patchEcommerceMallAdminProductDeletions } from "../../../../providers/patchEcommerceMallAdminProductDeletions";
import { postEcommerceMallAdminProductDeletions } from "../../../../providers/postEcommerceMallAdminProductDeletions";

@Controller("/ecommerceMall/admin/product-deletions")
export class EcommercemallAdminProduct_deletionsController {
  /**
   * Create a product deletion request for administrator-initiated product removal due to policy violations.
   *
   * This endpoint allows administrators to formally request the deletion of a product for policy violations, initiating a review workflow. When an administrator identifies a product that violates platform policies, they can submit a deletion request with detailed reasoning. The request enters a pending status and can be approved or rejected by authorized administrators.
   *
   * The product deletion process is carefully designed to preserve audit trail and maintain data integrity:
   * - Product snapshots are preserved to maintain historical record of product information
   * - Order snapshots are preserved to maintain order history
   * - The original product is marked as deleted but remains in the system for audit purposes
   * - All deletion requests are logged with timestamps and responsible administrators
   *
   * The system enforces strict validation:
   * - Only administrators with appropriate privileges can submit deletion requests
   * - Product must exist and be available for deletion
   * - Deletion request must include a valid reason
   * - The deletion process follows a workflow that preserves business data integrity
   *
   * @param connection
   * @param body Product deletion request information including the product to delete and reason for deletion
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new product deletion request record in the ecommerce_mall_product_deletions table.
   * 1. Validate that the current user is an administrator
   * 2. Validate that the product_id references an existing product
   * 3. Validate that the reason field is not empty
   * 4. Create the deletion request with status 'pending'
   * 5. Set the admin_id to the current administrator's ID
   * 6. Return the created record with all timestamps
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallProductDeletion.ICreate,
  ): Promise<IEcommerceMallProductDeletion> {
    try {
      return await postEcommerceMallAdminProductDeletions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of product deletion requests with filtering capabilities.
   *
   * This endpoint provides administrators with a comprehensive view of all product deletion requests stored in the `ecommerce_mall_product_deletions` table. It supports filtering by product, requesting administrator, and request status to enable efficient review workflows. The deletion requests represent administrative actions to remove products from the platform, typically due to policy violations, copyright issues, or other administrative decisions.
   *
   * The `ecommerce_mall_product_deletions` table stores records of administrator-initiated product deletion requests, including the reason for deletion, current status, approval notes, and timestamps for when requests were created, updated, and processed.
   *
   * Administrators can filter deletion requests by:
   * - Specific product ID to review all deletion attempts for a particular product
   * - Administrator ID to see deletion requests initiated by a specific admin
   * - Status to focus on pending, approved, or rejected requests
   *
   * Each deletion request includes the reason provided by the initiating administrator, the current status, and any approval notes from responding administrators. Deleted products remain accessible in order history and snapshots but do not appear in search or category listings.
   *
   * @param connection
   * @param body Filter criteria and pagination parameters for product deletion requests
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_product_deletions table with filtering and pagination support.
   * Apply filters for product_id, admin_id, and status when provided.
   * Support ordering by created_at (descending for newest first) and pagination with cursor or offset.
   * Return deletion requests with full details including related admin and product information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallProductDeletion.IRequest,
  ): Promise<IPageIEcommerceMallProductDeletion.ISummary> {
    try {
      return await patchEcommerceMallAdminProductDeletions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific administrator-initiated product deletion request.
   *
   * This operation allows administrators to retrieve detailed information about a specific product deletion request by its unique identifier. The system ensures that only authorized administrators can access deletion request details, maintaining proper authorization controls and audit trail access.
   *
   * The deletion request includes comprehensive information about the product being deleted, the administrator who initiated the deletion, the reason for deletion, the current status (pending|approved|rejected), and any approval notes or timestamps. This enables administrators to review deletion requests, track deletion history, and maintain oversight of product management activities.
   *
   * All deletion request records are preserved permanently for audit compliance, and this operation provides read-only access to these historical records without any modification capabilities.
   *
   * @param connection
   * @param productDeletionId Product deletion request's UUID identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_product_deletions table for the deletion request with the provided UUID productDeletionId parameter. Verify the current administrator has permission to view deletion requests. Return the complete deletion request record including all related information (product, admin, reason, status, timestamps, approval notes). If no deletion request is found, return a 404 Not Found error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productDeletionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("productDeletionId")
    productDeletionId: string,
  ): Promise<IEcommerceMallProductDeletion> {
    try {
      return await getEcommerceMallAdminProductDeletionsProductDeletionId({
        admin,
        productDeletionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
