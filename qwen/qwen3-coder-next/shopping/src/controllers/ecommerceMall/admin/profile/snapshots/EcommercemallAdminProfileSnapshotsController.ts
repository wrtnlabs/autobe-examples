import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallShopProfile } from "../../../../../api/structures/IEcommerceMallShopProfile";
import { IPageIEcommerceMallShopProfile } from "../../../../../api/structures/IPageIEcommerceMallShopProfile";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminProfileSnapshotsSnapshotId } from "../../../../../providers/getEcommerceMallAdminProfileSnapshotsSnapshotId";
import { patchEcommerceMallAdminProfileSnapshots } from "../../../../../providers/patchEcommerceMallAdminProfileSnapshots";

@Controller("/ecommerceMall/admin/profile/snapshots")
export class EcommercemallAdminProfileSnapshotsController {
  /**
   * Retrieve a paginated list of seller profile snapshots.
   *
   * This operation provides access to immutable historical snapshots of seller shop profiles. Each snapshot captures the complete shop profile state (shop name, description, logo URL, approval status) at the moment of edit, preserving this historical data for audit trail and dispute resolution purposes.
   *
   * Profile snapshots are created automatically whenever a seller edits their shop profile. These snapshots are immutable and cannot be modified after creation. They support comprehensive filtering by seller ID and timestamp ranges.
   *
   * This operation is designed for sellers to view their own profile history and for administrators to review profile states at specific points in time for dispute resolution or compliance purposes.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_shop_profile_snapshots table with pagination and filtering.
   * Filter by seller ID (from authentication context) to retrieve only snapshots for current seller.
   * Support filtering by timestamp ranges (created_at before/after) for date-based queries.
   * Join with ecommerce_mall_shop_profiles for profile details at snapshot time.
   * Return cursor-based pagination for large result sets ordered by created_at descending (newest first).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallShopProfile.IRequest,
  ): Promise<IPageIEcommerceMallShopProfile.ISummary> {
    try {
      return await patchEcommerceMallAdminProfileSnapshots({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific profile snapshot by its unique identifier.
   *
   * This operation fetches a detailed profile snapshot that was automatically created when a customer or seller edited their profile. The snapshot preserves the exact state of the profile fields at the moment of the edit, including the previous values and new values of all changed fields.
   *
   * ## Access Control
   * - **Customers** can retrieve their own profile snapshots
   * - **Administrators** can retrieve any profile snapshot for dispute resolution or compliance purposes
   *
   * ## Snapshot Content
   * Each profile snapshot includes:
   * - Timestamp of the edit
   * - Previous values of display name and phone number (for customer) or shop name, description, and logo URL (for seller)
   * - New values of the changed fields
   * - User ID who performed the edit
   * - Snapshot type indicating whether it was an edit snapshot
   *
   * ## Immutable Historical Data
   * Profile snapshots are immutable and cannot be modified or deleted. They serve as an audit trail for profile changes and support dispute resolution by preserving the profile state at specific points in time.
   *
   * @param connection
   * @param snapshotId Unique identifier of the profile snapshot to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Retrieve profile snapshot by snapshotId from the database.
   * Validate access control: ensure requester owns the snapshot or is an admin.
   * Return full snapshot record including timestamp, previous values, new values, and user ID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("snapshotId")
    snapshotId: string,
  ): Promise<IEcommerceMallShopProfile> {
    try {
      return await getEcommerceMallAdminProfileSnapshotsSnapshotId({
        admin,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
