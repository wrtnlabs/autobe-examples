import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallUserBan } from "../../../../api/structures/IEcommerceMallUserBan";
import { IPageIEcommerceMallUserBan } from "../../../../api/structures/IPageIEcommerceMallUserBan";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminUserBansUserBanId } from "../../../../providers/getEcommerceMallAdminUserBansUserBanId";
import { patchEcommerceMallAdminUserBans } from "../../../../providers/patchEcommerceMallAdminUserBans";
import { patchEcommerceMallAdminUserBansUserBanIdUnban } from "../../../../providers/patchEcommerceMallAdminUserBansUserBanIdUnban";
