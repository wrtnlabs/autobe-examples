import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallIntegrationLog } from "../../../../api/structures/IEcommerceMallIntegrationLog";
import { IPageIEcommerceMallIntegrationLog } from "../../../../api/structures/IPageIEcommerceMallIntegrationLog";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminIntegrationLogsLogId } from "../../../../providers/getEcommerceMallAdminIntegrationLogsLogId";
import { patchEcommerceMallAdminIntegrationLogs } from "../../../../providers/patchEcommerceMallAdminIntegrationLogs";

@Controller("/ecommerceMall/admin/integration-logs")
export class EcommercemallAdminIntegration_logsController {
  /**
   * Retrieve filtered and paginated integration logs from external API interactions.
   *
   * This operation provides comprehensive search and filtering capabilities for integration logs that track interactions with external services including payment gateways, shipping carriers, and other third-party APIs. It enables debugging, monitoring, and auditing of external service communications.
   *
   * The operation supports multiple filtering dimensions including service type (payment, shipping, external_api), status (success|failure|timeout), date ranges, request/response durations, and error conditions. This allows technical teams to investigate specific integration issues, monitor system health, and analyze external service performance.
   *
   * Response includes essential log information optimized for list displays, with full log details available through individual log retrieval operations if needed.
   *
   * Security: Access is restricted to admin actors only. Regular customers and sellers cannot access integration logs as they contain sensitive technical implementation details about external service configurations.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_integration_logs table with pagination and filtering.
   *
   * Apply filters on service_type (payment|shipping|external_api), status (success|failure|timeout), request_date (date range), error_message (partial match), and duration_ms (min/max).
   *
   * Join with related tables if additional context is needed (e.g., linking to orders for payment logs).
   *
   * Return paginated results with essential log information.
   *
   * Implement cursor-based pagination for large result sets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallIntegrationLog.IRequest,
  ): Promise<IPageIEcommerceMallIntegrationLog.ISummary> {
    try {
      return await patchEcommerceMallAdminIntegrationLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific external API integration log entry.
   *
   * This operation fetches the complete record of an external API integration call, including payment gateway transactions, shipping carrier interactions, and other third-party service communications. The log contains comprehensive request and response details for debugging, audit trail, and monitoring purposes.
   *
   * This operation requires appropriate administrative permissions to access integration logs. Regular customers and sellers do not have permission to view integration logs.
   *
   * @param connection
   * @param logId Target integration log's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_integration_logs table by the provided logId to retrieve a single integration log entry. Return all fields including integration_type, api_endpoint, request/response headers and bodies, response status, error_message, and duration_ms. Verify user has administrative permissions before returning the log data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":logId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("logId")
    logId: string,
  ): Promise<IEcommerceMallIntegrationLog> {
    try {
      return await getEcommerceMallAdminIntegrationLogsLogId({
        admin,
        logId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
