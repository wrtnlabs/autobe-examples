  /**
   * Retrieve detailed information about a specific administrator request.
   *
   * This endpoint fetches the complete details of an administrator request using its unique identifier. The request contains information about a user's application for administrative privileges including the requesting user's account details, the reason text provided during application, the current status of the request (pending, approved, or rejected), and the timeline of all status changes.
   *
   * The system maintains an immutable record of each admin request, preserving the original state at creation time. Status changes are logged separately while the original request content remains unchanged, providing an audit trail for compliance and administrative review.
   *
   * Only super administrators have access to view administrator requests. Regular administrators and regular users cannot access this endpoint.
   *
   * The operation supports retrieving requests at any stage of their lifecycle, including:
   * - Pending requests awaiting super administrator review
   * - Approved requests that resulted in admin role assignment
   * - Rejected requests with documented rejection reasons
   *
   * Related operations:
   * - `GET /admin-requests/pending` to list all pending requests (super admin only)
   * - `POST /admin-requests` to submit a new admin request (authenticated users)
   * - `PATCH /admin-requests/{id}/approve` to approve a pending request (super admin only)
   * - `PATCH /admin-requests/{id}/reject` to reject a pending request (super admin only)
   *
   * **Validation Rules:**
   * - The admin request ID must exist in the system
   * - Only super administrators can access this endpoint
   * - Access attempts by unauthorized users are logged for security audit
   *
   * @param connection
   * @param adminRequestId Unique identifier of the administrator request to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_admin_requests table by primary ID to retrieve a single admin request.
   * Include related user information via join to ecommerce_mall_admins or ecommerce_mall_customers or ecommerce_mall_sellers tables to get requesting user details.
   * Return the complete admin request record with all fields including status, reason, approval notes, and timestamps.
   * If no request exists with the given ID, return 404 Not Found.
   * Only allow super administrators (grade='super') to access this endpoint. For non-super admins or non-admins, return 403 Forbidden without disclosing which requests exist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
