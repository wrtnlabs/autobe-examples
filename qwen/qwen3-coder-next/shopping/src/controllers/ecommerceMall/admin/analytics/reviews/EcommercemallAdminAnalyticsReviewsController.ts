import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallReview } from "../../../../../api/structures/IEcommerceMallReview";
import { IPageIEcommerceMallReview } from "../../../../../api/structures/IPageIEcommerceMallReview";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchEcommerceMallAdminAnalyticsReviews } from "../../../../../providers/patchEcommerceMallAdminAnalyticsReviews";

@Controller("/ecommerceMall/admin/analytics/reviews")
export class EcommercemallAdminAnalyticsReviewsController {
  /**
   * Retrieve aggregated review analytics and statistics for products.
   *
   * This endpoint provides statistical summaries and analytics about customer reviews across products in the system. It calculates aggregate metrics such as average ratings, total review counts, rating distributions (1-5 star breakdowns), and time-based trends.
   *
   * The analytics data is automatically calculated by the system based on review data. The system manages this analytics data as a derived metric from the ecommerce_mall_reviews table, and it does not require manual input or management.
   *
   * This endpoint supports filtering by product, time range, and other criteria to generate targeted analytics reports. Administrators and sellers can use these analytics to understand customer sentiment, identify product quality issues, and track review patterns over time.
   *
   * The analytics are derived from the ecommerce_mall_reviews table, and the query excludes soft-deleted reviews (where deleted_at IS NULL) to ensure accurate statistics. For detailed review edit history, administrators and sellers can access the ecommerce_mall_review_snapshots table separately.
   *
   * @param connection
   * @param body Analytics query criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_reviews table with analytics aggregations.
   * Calculate average ratings using AVG() with ROUND() to one decimal place.
   * Count total reviews using COUNT(), excluding deleted reviews.
   * Calculate rating distribution using conditional aggregation for each star rating (1-5).
   * Support filtering by product_id, time range (created_at range), and rating range.
   * Support pagination with offset/limit or cursor-based pagination.
   * Include seller_id filtering for seller-specific analytics.
   * Return paginated analytics summary with calculated statistics.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallReview.IRequest,
  ): Promise<IPageIEcommerceMallReview.ISummary> {
    try {
      return await patchEcommerceMallAdminAnalyticsReviews({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
