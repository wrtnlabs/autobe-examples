  /**
   * Update seller registration approval status.
   *
   * This operation allows administrators to approve or reject seller registration requests. When a registration is approved, the seller account becomes active and can start listing products. When rejected, the seller receives a rejection reason and may resubmit their registration.
   *
   * The operation enforces the following business rules:
   * - Only administrators can approve or reject seller registrations
   * - Rejection requires providing a rejection reason
   * - Once approved, the seller account becomes active and can create products
   * - Once rejected, the seller can resubmit a new registration request
   *
   * The approval status transitions are strictly controlled:
   * - pending → approved (seller account becomes active)
   * - pending → rejected (seller receives rejection reason)
   * - rejected → pending (seller resubmits registration)
   * - approved → suspended (seller suspension by admin)
   *
   * This operation is critical for the seller onboarding workflow and ensures proper administrative oversight of seller accounts.
   *
   * @param connection
   * @param sellerRegistrationId Unique identifier of the seller registration request
   * @param body Approval status update and optional rejection reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update the seller registration approval status in the ecommerce_mall_seller_registrations table.
   * 1. Load the registration record by sellerRegistrationId (id field)
   * 2. Validate the current status is 'pending' or 'rejected' (only these states can be updated)
   * 3. Apply the approval_status from request body
   * 4. If approval_status is 'rejected', require and store rejection_reason
   * 5. If approval_status is 'approved', set responded_at to current timestamp
   * 6. Update the record with the new status and optional rejection_reason/response timestamp
   * 7. Return the updated registration record
   * 8. Implement proper error handling for invalid status transitions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sellerRegistrationId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerRegistrationId")
    sellerRegistrationId: string,
    @TypedBody()
    body: IEcommerceMallSellerRegistration.IUpdate,
  ): Promise<IEcommerceMallSellerRegistration> {
    try {
      return await putEcommerceMallAdminSellerRegistrationsSellerRegistrationId(
        {
          admin,
          sellerRegistrationId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Approve or reject a pending seller registration request.
   *
   * This operation allows administrators to review seller registration requests and make a decision to approve or reject the seller's application. When an administrator approves a seller registration, the seller's account becomes active and they can begin using the platform to manage products and process orders. When rejecting a seller registration, the administrator must provide a rejection reason explaining why the application was denied.
   *
   * Only administrators with appropriate permissions can access this endpoint. Regular administrators and super administrators can approve or reject seller registrations. The system enforces that rejection reasons are provided when rejecting a registration request, ensuring sellers receive clear feedback on why their application was denied.
   *
   * The operation updates the approval status field of the seller registration request, sets the responded_at timestamp to the current time, and stores the rejection reason if the request is being rejected. After approval, the associated seller account transitions to an active state and can begin using platform features.
   *
   * Related operations:
   * - GET /admin/sellers/pending - List pending seller approvals to identify registrations requiring review
   * - PATCH /admin/sellers/:id/suspend - Suspend an already approved seller account if policy violations occur
   * - GET /admin/sellers/:id/orders - View orders from an approved seller for oversight purposes
   *
   * @param connection
   * @param sellerRegistrationId Seller registration request ID
   * @param body Approval decision and optional rejection reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update ecommerce_mall_seller_registrations table to set approval_status and responded_at.
   * Validate that the incoming administrator has regular or super admin role.
   * Validate that the seller registration exists and has approval_status = 'pending'.
   * When approval_status = 'approved': set approval_status to 'approved', null rejection_reason, set responded_at.
   * When approval_status = 'rejected': require rejection_reason field to be non-empty string, set approval_status to 'rejected', set responded_at.
   * Update responded_at to current timestamp.
   * Return updated registration request with all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
