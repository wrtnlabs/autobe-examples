import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallShipment } from "../../../../../api/structures/IEcommerceMallShipment";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminShipmentsShipmentIdTracking } from "../../../../../providers/getEcommerceMallAdminShipmentsShipmentIdTracking";

@Controller("/ecommerceMall/admin/shipments/:shipmentId/tracking")
export class EcommercemallAdminShipmentsTrackingController {
  /**
   * Retrieve tracking information for a specific shipment.
   *
   * This operation provides visibility into shipment delivery status by returning the carrier name and tracking number associated with the shipment. The tracking information enables customers and sellers to monitor delivery progress through the carrier's tracking system.
   *
   * Security and Access:
   * - Shipment owners (sellers who created the shipment) can access tracking information
   * - Order customers can view tracking for shipments in their orders
   * - Administrative users have full tracking access for oversight purposes
   *
   * Database Relationships:
   * - Links to ecommerce_mall_shipments table for tracking data storage
   * - Carrier name and tracking number are stored as optional fields
   * - Tracking information becomes immutable after customer delivery confirmation
   *
   * Business Rules:
   * - Tracking information may be pending (empty values) if not yet provided by seller
   * - Once shipment status changes to 'shipped', tracking details are locked from modification
   * - Delivery confirmation (customer action or 14-day auto-confirmation) triggers immutable tracking state
   *
   * Related Operations:
   * - POST /shipments - Create shipment and optionally provide initial tracking
   * - GET /orders/:id/shipments - List all shipments for an order
   * - PATCH /order-items/:itemId/delivery-confirmed - Confirm delivery via shipment
   *
   * @param connection
   * @param shipmentId Target shipment's ID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_shipments table by id to retrieve tracking information.
   * Return carrier_name and tracking_number fields.
   * Return empty values if tracking is not yet provided.
   * Ensure shipment exists and belongs to requesting actor's scope.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shipmentId")
    shipmentId: string,
  ): Promise<IEcommerceMallShipment.ITracking> {
    try {
      return await getEcommerceMallAdminShipmentsShipmentIdTracking({
        admin,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
