import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallRefundRequest } from "../../../../../../../api/structures/IEcommerceMallRefundRequest";
import { SellerAuth } from "../../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerOrdersOrderIdItemsOrderItemIdRefundApprove } from "../../../../../../../providers/patchEcommerceMallSellerOrdersOrderIdItemsOrderItemIdRefundApprove";

@Controller(
  "/ecommerceMall/seller/orders/:orderId/items/:orderItemId/refund/approve",
)
export class EcommercemallSellerOrdersItemsRefundApproveController {
  /**
   * Approve a pending refund request for an order item.
   *
   * This operation allows the seller of a product to approve a customer-initiated refund request. The seller can only approve refund requests associated with products they own.
   *
   * When a seller approves a refund request, the system will:
   *
   * 1. Update the refund request status to "approved"
   * 2. Create an immutable snapshot of the request state at the time of approval for audit purposes
   * 3. Restore the variant's stock quantity by creating an inventory record with reason "refund"
   * 4. Update the associated order item status to "refunded"
   * 5. Initiate refund payment processing to the customer
   *
   * Security: Only the seller who created the product associated with the order item can approve the refund request. Attempting to approve a refund request for another seller's product will result in an error.
   *
   * Related operations:
   *
   * - `PATCH /orders/{orderId}/items/{orderItemId}/refund` - Customer requests a refund for an order item
   * - `PATCH /orders/{orderId}/items/{orderItemId}/refund/reject` - Seller rejects a refund request
   * - `GET /orders/{orderId}/items/{orderItemId}/refund` - Retrieve refund request details
   * - `PATCH /orders/{orderId}/items/{orderItemId}/approve-cancel` - Seller approves a cancellation request
   *
   * **Validation Requirements**
   *
   * - The refund request status must be "pending" - no action can be taken on already-approved or rejected requests
   * - The order item status must be "delivered" - refunds can only be requested for delivered items
   * - The seller must be the owner of the product associated with the order item
   * - The refund request must exist and be associated with the specified order item
   *
   * **Post-Approval Behavior**
   *
   * After approval, the system automatically processes the refund payment to the customer and updates the inventory system to restore the sold quantity to stock. The customer will receive notifications about the refund approval and payment processing status.
   *
   * @param connection
   * @param orderId Target order's UUID identifier
   * @param orderItemId Target order item's UUID identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Process seller approval for a pending refund request:
   *
   * 1. Query refund request by order_item_id, verify status is 'pending'
   * 2. Verify seller_id matches current authenticated seller (ownership validation)
   * 3. Verify order item status is 'delivered'
   * 4. Begin transaction:
   *    - Update refund request status to 'approved' and set responded_at timestamp
   *    - Create refund_request_snapshot with current state before response
   *    - Create inventory record with quantity +1 and reason 'refund' to restore stock
   *    - Update order_item status to 'refunded'
   *    - If all items in order are refunded, update order status to 'refunded'
   * 5. Execute refund payment through payment gateway integration
   * 6. Create notification for customer about approval
   * 7. Commit transaction
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async approveRefund(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedParam("orderItemId")
    orderItemId: string,
  ): Promise<IEcommerceMallRefundRequest> {
    try {
      return await patchEcommerceMallSellerOrdersOrderIdItemsOrderItemIdRefundApprove(
        {
          seller,
          orderId,
          orderItemId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
