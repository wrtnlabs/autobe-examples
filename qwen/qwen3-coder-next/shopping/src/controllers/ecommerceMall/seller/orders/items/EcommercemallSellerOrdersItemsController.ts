import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIEcommerceMallOrderItem } from "../../../../../api/structures/IPageIEcommerceMallOrderItem";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerOrdersOrderIdItems } from "../../../../../providers/getEcommerceMallSellerOrdersOrderIdItems";

@Controller("/ecommerceMall/seller/orders/:orderId/items")
export class EcommercemallSellerOrdersItemsController {
  /**
   * Retrieve all order items belonging to a specific order.
   *
   * This operation returns a paginated list of all items purchased in the specified order. Each order item includes product details (name, description), variant options (color, size, etc.), quantity purchased, price at checkout time, and current fulfillment status (paid, shipped, delivered, cancelled, refunded).
   *
   * For multi-seller orders, the response includes items from all sellers involved in the order, with each item indicating its associated seller via the seller_id field.
   *
   * This operation is read-only and does not modify any order or item state. The order items returned are immutable snapshots captured at the time the order was placed, preserving historical product and variant data.
   *
   * @param connection
   * @param orderId Target order's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_order_items table filtered by order_id path parameter. Include product, variant, and seller relations for each order item. Apply pagination with configurable page size. Return item status, product_name, product_description, variant_options, product_price, quantity, and seller_id fields. Ensure order items belong to the specified order and respect customer authorization (customer can only view their own orders).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string,
  ): Promise<IPageIEcommerceMallOrderItem.ISummary> {
    try {
      return await getEcommerceMallSellerOrdersOrderIdItems({
        seller,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
