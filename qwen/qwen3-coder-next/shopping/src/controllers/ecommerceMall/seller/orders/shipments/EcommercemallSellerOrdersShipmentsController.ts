import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallShipment } from "../../../../../api/structures/IEcommerceMallShipment";
import { IPageIEcommerceMallShipment } from "../../../../../api/structures/IPageIEcommerceMallShipment";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerOrdersOrderIdShipments } from "../../../../../providers/patchEcommerceMallSellerOrdersOrderIdShipments";
import { postEcommerceMallSellerOrdersOrderIdShipments } from "../../../../../providers/postEcommerceMallSellerOrdersOrderIdShipments";

@Controller("/ecommerceMall/seller/orders/:orderId/shipments")
export class EcommercemallSellerOrdersShipmentsController {
  /**
   * Create a new shipment for an order.
   *
   * This endpoint allows sellers to create shipments for their order items within a specific order. When a seller creates a shipment, they select which order items to include and provide optional carrier name and tracking number information.
   *
   * For orders containing items from multiple sellers, each seller must create their own shipment for their respective items. A single order can have multiple shipments from different sellers, and each shipment can include one or more order items.
   *
   * The system enforces that only the seller who owns the selected order items may create the shipment, preventing cross-seller shipment creation.
   *
   * @param connection
   * @param orderId Order ID to create shipment for
   * @param body Shipment creation request including selected order items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Create a new shipment record for the specified order.
   * - Validate that the active seller owns all included order items
   * - Create a shipment record linked to the order and seller
   * - Create shipment item records for each selected order item
   * - Store optional carrier_name and tracking_number if provided
   * - Return the created shipment with all shipment items
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedBody()
    body: IEcommerceMallShipment.ICreate,
  ): Promise<IEcommerceMallShipment> {
    try {
      return await postEcommerceMallSellerOrdersOrderIdShipments({
        seller,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve all shipments for a specific order.
   *
   * This endpoint returns all shipment records associated with the given order ID. Each shipment represents a physical package created by a seller when shipping items from the order. Multiple shipments may exist for a single order when items belong to different sellers.
   *
   * The response includes carrier information, tracking numbers, shipment status, and creation timestamps. Shipment items reference the order items that are included in each physical package, enabling customers to see which specific products are included in each shipment.
   *
   * @param connection
   * @param orderId Target order's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_shipments table filtered by ecommerce_mall_order_id parameter.
   * Join with ecommerce_mall_sellers to include seller profile information.
   * Include shipment_items count for each shipment to show item quantities.
   * Order results by created_at descending to show newest shipments first.
   * Return paginated list using IPageIShipment.ISummary response structure.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string,
  ): Promise<IPageIEcommerceMallShipment.ISummary> {
    try {
      return await patchEcommerceMallSellerOrdersOrderIdShipments({
        seller,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
