import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { SellerAuth } from "../../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerOrdersOrderIdItemsOrderItemIdCancelApprove } from "../../../../../../../providers/patchEcommerceMallSellerOrdersOrderIdItemsOrderItemIdCancelApprove";

@Controller(
  "/ecommerceMall/seller/orders/:orderId/items/:orderItemId/cancel/approve",
)
export class EcommercemallSellerOrdersItemsCancelApproveController {
  /**
   * Approve a pending cancellation request for a specific order item.
   *
   * This operation allows the seller of an order item to approve a customer's cancellation request. When approved, the system transitions the cancellation request status to approved, changes the order item status to cancelled, and restores the inventory stock for the cancelled variant.
   *
   * ## Business Logic and Validation
   *
   * - The requesting user must be authenticated as a seller
   * - The seller must be the owner of the order item (via seller_id match)
   * - The order item must have an associated pending cancellation request
   * - The order item status must be 'paid' (not yet shipped)
   * - Stock restoration is validated before approval
   *
   * ## Side Effects
   *
   * - Cancellation request status transitions to 'approved' with responded_at timestamp
   * - Order item status changes to 'cancelled'
   * - Inventory record created with positive quantity change and reason 'cancel'
   * - Order status is recalculated based on remaining items
   *
   * ## Error Conditions
   *
   * - Returns 403 if seller is not the owner of the order item
   * - Returns 404 if no pending cancellation request exists for the order item
   * - Returns 409 if order item is already cancelled or shipped
   * - Returns 409 if stock restoration fails due to insufficient inventory
   *
   * @param connection
   * @param orderId Target order's unique identifier
   * @param orderItemId Target order item's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Approve a pending cancellation request for an order item.
   *
   * 1. Validate seller ownership: Confirm the seller_id in the path matches the authenticated seller's userId and that the order item belongs to this seller
   * 2. Retrieve cancellation request: Find the cancellation request associated with the order_item_id, ensuring it exists and has status 'pending'
   * 3. Validate order item status: Confirm the order item status is 'paid' (not shipped/delivered)
   * 4. Validate stock availability: Ensure sufficient stock for restock operation (inventory_records with variant_id matching order_item.variant_id)
   * 5. Transactionally execute:
   *    - Update cancellation_request status to 'approved' and set responded_at to current timestamp
   *    - Update order_item status to 'cancelled'
   *    - Create inventory_record with positive quantity_change and reason 'cancel'
   *    - Update order status by recalculating from order_items
   * 6. Return 200 on success, 403/404/409 on validation failures
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async approveCancellation(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedParam("orderItemId")
    orderItemId: string,
  ): Promise<void> {
    try {
      return await patchEcommerceMallSellerOrdersOrderIdItemsOrderItemIdCancelApprove(
        {
          seller,
          orderId,
          orderItemId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
