import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallProductVariant } from "../../../../../api/structures/IEcommerceMallProductVariant";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { deleteEcommerceMallSellerProductsProductIdVariantsVariantId } from "../../../../../providers/deleteEcommerceMallSellerProductsProductIdVariantsVariantId";
import { getEcommerceMallSellerProductsProductIdVariants } from "../../../../../providers/getEcommerceMallSellerProductsProductIdVariants";
import { patchEcommerceMallSellerProductsProductIdVariantsVariantId } from "../../../../../providers/patchEcommerceMallSellerProductsProductIdVariantsVariantId";
import { postEcommerceMallSellerProductsProductIdVariants } from "../../../../../providers/postEcommerceMallSellerProductsProductIdVariants";

@Controller("/ecommerceMall/seller/products/:productId/variants")
export class EcommercemallSellerProductsVariantsController {
  /**
   * Retrieve a paginated list of product variants (SKUs) for a specific product.
   *
   * This operation provides access to all available option combinations for a product, such as different colors, sizes, or other configurable attributes. Each variant includes its unique SKU code, optional price override (which falls back to the product's base price if not specified), and current stock quantity.
   *
   * From a customer perspective, this endpoint enables product detail pages to display all available purchase options. From a seller perspective, it allows review of the variants associated with their products. The operation respects the business rule that products with zero variants are marked as unavailable and cannot be purchased.
   *
   * **Authorization**: Accessible by customers, sellers, and administrators. Seller access is limited to their own products. Administrator access includes all products for oversight purposes.
   *
   * **Related Operations**:
   * - `GET /products/{id}` retrieves the product details including basic information
   * - `GET /products/{id}/snapshots` retrieves historical product snapshots
   * - `POST /products/{id}/variants` creates new variants for products (seller only)
   *
   * @param connection
   * @param productId Target product's ID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_product_variants table filtered by product_id matching the path parameter productId. Include soft-deleted variants only for administrative access. Return list of variant summaries including SKU code, price override, and current stock quantity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
  ): Promise<IEcommerceMallProductVariant.ISummary> {
    try {
      return await getEcommerceMallSellerProductsProductIdVariants({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new product variant (SKU) for an existing product.
   *
   * This operation allows sellers to add new variant options (such as color, size, or other customizable attributes) to an existing product. Each variant must have a unique SKU code across all products in the system and can optionally have a price override that takes precedence over the product's base price.
   *
   * The system enforces the business rule that every product must have at least one variant to be considered purchasable. When creating a variant, the stock quantity is initialized to zero and inventory must be added separately through inventory adjustment operations.
   *
   * Variants support soft deletion and preserve historical data for order continuity. Deleted variants remain visible in order history but cannot be purchased by new customers.
   *
   * @param connection
   * @param productId The unique identifier of the product to add the variant to
   * @param body Variant creation data including SKU code, option values, and optional price override
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Create a new product variant record in the ecommerce_mall_product_variants table.
   * 1. Validate that the product with given productId exists and is not deleted
   * 2. Check that the sku_code is unique across all variants (enforced by @@unique([sku_code]))
   * 3. Create new variant record with:
   *    - product_id from path parameter
   *    - sku_code from request body
   *    - price_override from request body (null if not provided)
   *    - stock_quantity initialized to 0
   *    - created_at and updated_at set to current timestamp
   * 4. Return created variant with all fields including generated timestamps
   * 5. Handle unique constraint violations gracefully with appropriate error response
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IEcommerceMallProductVariant.ICreate,
  ): Promise<IEcommerceMallProductVariant> {
    try {
      return await postEcommerceMallSellerProductsProductIdVariants({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific product variant's details.
   *
   * This operation allows sellers to modify an existing product variant including its SKU code and price override. The SKU code must remain unique across all variants in the platform.
   *
   * When updating the SKU code, the system validates global uniqueness across all product variants. Price overrides allow variant-specific pricing that takes precedence over the product base price. Stock quantity cannot be directly updated through this endpoint - stock changes must be performed through dedicated inventory record operations.
   *
   * This operation is available to sellers managing their own products and administrators for product oversight. Sellers can only update variants belonging to products they own.
   *
   * @param connection
   * @param productId Target product's unique identifier
   * @param variantId Target variant's unique identifier
   * @param body Variant update request with new SKU code and price override
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Update product variant details including SKU code, price override, and stock quantity.
   * 1. Verify user has permission to modify variant (seller owns product or admin)
   * 2. Load current variant and validate it belongs to specified product
   * 3. Validate new SKU code is globally unique across all variants
   * 4. Apply updates to sku_code, price_override, and stock_quantity
   * 5. Update updated_at timestamp
   * 6. Return updated variant with current stock quantity calculated from inventory records
   * 7. If SKU uniqueness violation occurs, return 409 Conflict with appropriate error message
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":variantId")
  public async updateVariant(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedParam("variantId")
    variantId: string,
    @TypedBody()
    body: IEcommerceMallProductVariant.IUpdate,
  ): Promise<IEcommerceMallProductVariant> {
    try {
      return await patchEcommerceMallSellerProductsProductIdVariantsVariantId({
        seller,
        productId,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a product variant (SKU) from a product.
   *
   * This operation permanently removes a product variant from the product catalog. Before deletion, the system validates that no order items exist for this variant with status 'paid' or 'shipped' and that no pending cancellation or refund requests exist for the variant. Additionally, the product must retain at least one variant after deletion.
   *
   * The operation is only available to the seller who owns the product. It enforces business rules to prevent deletion of variants with pending or completed orders and ensures product availability.
   *
   * Related operations:
   * - GET /products/{id}/variants - List product variants
   * - POST /products/{id}/variants - Add new variant
   * - PATCH /products/variants/{variantId} - Update variant
   *
   * @param connection
   * @param productId Product's ID
   * @param variantId Variant's ID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Delete a product variant with validation checks:
   * 1. Verify the product belongs to the current seller
   * 2. Verify no order items exist for this variant with status 'paid' or 'shipped'
   * 3. Verify no pending cancellation or refund requests exist for this variant
   * 4. Verify at least one variant remains after deletion
   * 5. Mark the variant as deleted (soft delete via deleted_at)
   * 6. Delete associated inventory records
   * 7. Return the deleted variant object
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":variantId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedParam("variantId")
    variantId: string,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallSellerProductsProductIdVariantsVariantId({
        seller,
        productId,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
