import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallProductImage } from "../../../../../api/structures/IEcommerceMallProductImage";
import { IPageIEcommerceMallProductImage } from "../../../../../api/structures/IPageIEcommerceMallProductImage";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { deleteEcommerceMallSellerProductsProductIdImagesImageId } from "../../../../../providers/deleteEcommerceMallSellerProductsProductIdImagesImageId";
import { getEcommerceMallSellerProductsProductIdImages } from "../../../../../providers/getEcommerceMallSellerProductsProductIdImages";
import { patchEcommerceMallSellerProductsProductIdImages } from "../../../../../providers/patchEcommerceMallSellerProductsProductIdImages";
import { postEcommerceMallSellerProductsProductIdImages } from "../../../../../providers/postEcommerceMallSellerProductsProductIdImages";

@Controller("/ecommerceMall/seller/products/:productId/images")
export class EcommercemallSellerProductsImagesController {
  /**
   * Retrieve all images associated with a specific product.
   *
   * This operation returns the complete image gallery for a product including all uploaded images in their configured sort order. Each image includes its URL, sort index, and whether it is designated as the main thumbnail. The images are ordered by their sort_order field to ensure consistent display across the application.
   *
   * Only images associated with the specified product are returned. The operation supports retrieving all images for a product without pagination since typical products have a limited number of images. For products with many images, consider implementing cursor-based pagination in future versions.
   *
   * @param connection
   * @param productId Target product's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_product_images table filtered by product_id. Order results by sort_order ascending to maintain the configured image sequence. Include all active images (deleted_at IS NULL). Return image URLs, sort order indices, and main thumbnail flags. This operation provides the complete product image gallery for display in product detail views and listings.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
  ): Promise<IEcommerceMallProductImage.ISummary> {
    try {
      return await getEcommerceMallSellerProductsProductIdImages({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Upload product images for a specific product.
   *
   * This operation allows sellers to upload one or more images for their products. Each uploaded image is associated with the product and automatically assigned a sortOrder based on the current number of images. The first image uploaded becomes the main thumbnail displayed in product listings.
   *
   * The system enforces seller ownership validation - sellers can only upload images for products they own. Images are permanently linked to the product and cannot be shared across different products. All uploaded images become part of the product's visual identity and will be preserved in product snapshots created during future edits.
   *
   * When multiple images are uploaded in a single request, they are assigned sequential sortOrder values starting from the next available position. The existing image order remains unchanged for previously uploaded images.
   *
   * @param connection
   * @param productId Target product's unique identifier
   * @param body List of image files to upload for the product
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Upload one or more product images for the specified product.
   *
   * 1. Verify seller owns the product by checking ecommerce_mall_products.seller_id matches the authenticated user's ID
   * 2. If product has existing images, determine the next sortOrder as MAX(sort_order) + 1
   * 3. For each uploaded image:
   *    - Generate unique image URLs (store image in file system)
   *    - Insert into ecommerce_mall_product_images with:
   *      - product_id = productId parameter
   *      - image_url = uploaded image URL
   *      - sort_order = next available sortOrder (incrementing)
   *      - is_main = false for all new uploads (existing main image remains)
   *      - created_at, updated_at = current timestamp
   *      - deleted_at = null
   * 4. Return 201 Created with uploaded image details
   * 5. If product ownership verification fails, return 403 Forbidden
   * 6. If product is soft-deleted, return 404 Not Found
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async upload(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IEcommerceMallProductImage.IUpload,
  ): Promise<IEcommerceMallProductImage> {
    try {
      return await postEcommerceMallSellerProductsProductIdImages({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Reorder product images for the specified product.
   *
   * This operation allows sellers to change the display order of images associated with their product. The system maintains image ordering through sort_order integers, ensuring contiguous sequence starting at 1 after reordering.
   *
   * Security: Only sellers who own the product can reorder its images. The system verifies seller ownership before processing the request. If the product does not belong to the acting seller, the operation is rejected.
   *
   * While reordering, the system prevents concurrent edits to avoid race conditions. All images for the specified product must maintain unique, contiguous sort_order values after the reorder completes. If an image is deleted during reordering, the system applies the deletion and updates remaining indices after the reorder completes.
   *
   * This operation integrates with product snapshots - when a product is edited, product snapshots preserve the image order at that point in time.
   *
   * @param connection
   * @param productId Target product's UUID identifier
   * @param body Image reordering instructions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_product_images table filtered by product_id.
   *
   * 1. Load existing images for the product
   * 2. Validate that all images belong to the same product
   * 3. Process reorder instructions from request body
   * 4. Update sort_order for each image according to new sequence
   * 5. Ensure contiguous sequence starting at 1 after reordering
   * 6. If reorder includes invalid image ID or conflict, reject request and preserve existing order
   * 7. Return paginated list of updated product images
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IEcommerceMallProductImage.IRequest,
  ): Promise<IPageIEcommerceMallProductImage.ISummary> {
    try {
      return await patchEcommerceMallSellerProductsProductIdImages({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific product image from a product.
   *
   * This operation permanently removes a product image from active use while preserving it in any existing product snapshots. Sellers can delete any image except when it would leave the product without any images.
   *
   * ## Authorization
   * - Only the seller who owns the product can delete its images
   * - The system verifies seller ownership before processing the deletion
   *
   * ## Business Rules
   * - At least one image must remain after deletion
   * - If the deleted image was the main image (is_main=true), the next image in sort order is promoted to main
   * - The deleted image is preserved in product snapshots and cannot be deleted from storage if referenced by any snapshot
   *
   * ## Image Reordering
   * - After deletion, remaining images are reordered to maintain contiguous sort_order indices starting at 1
   *
   * @param connection
   * @param productId Target product's unique identifier
   * @param imageId Target product image's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_product_images table by imageId and verify it belongs to productId. Verify the acting seller owns the product via ecommerce_mall_products.seller_id. Check that at least one image remains after deletion; reject if attempting to delete the last image. Delete the image record and recompute sort_order for remaining images to maintain contiguous sequence starting at 1. Promote the next image to main (is_main=true) if the deleted image was the main image. Preserve the image in any existing product snapshots.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":imageId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallSellerProductsProductIdImagesImageId({
        seller,
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
