import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallReview } from "../../../../../api/structures/IEcommerceMallReview";
import { IPageIEcommerceMallReview } from "../../../../../api/structures/IPageIEcommerceMallReview";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerAnalyticsReviews } from "../../../../../providers/patchEcommerceMallSellerAnalyticsReviews";

@Controller("/ecommerceMall/seller/analytics/reviews")
export class EcommercemallSellerAnalyticsReviewsController {
  /**
   * Retrieve aggregated review analytics and statistics for products.
   *
   * This endpoint provides statistical summaries and analytics about customer reviews across products in the system. It calculates aggregate metrics such as average ratings, total review counts, rating distributions (1-5 star breakdowns), and time-based trends.
   *
   * The analytics data is automatically calculated by the system based on review data and does not require manual input or management. This endpoint supports filtering by product, time range, and other criteria to generate targeted analytics reports.
   *
   * Administrators and sellers can use these analytics to understand customer sentiment, identify product quality issues, and track review patterns over time. The analytics are derived from the ecommerce_mall_reviews table and its relationships with ecommerce_mall_review_snapshots for historical review data.
   *
   * @param connection
   * @param body Analytics query criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_reviews table with analytics aggregations.
   * Calculate average ratings using AVG() with ROUND() to one decimal place.
   * Count total reviews using COUNT(), excluding deleted reviews.
   * Calculate rating distribution using conditional aggregation for each star rating (1-5).
   * Support filtering by product_id, time range (created_at range), and rating range.
   * Support pagination with offset/limit or cursor-based pagination.
   * Include seller_id filtering for seller-specific analytics.
   * Return paginated analytics summary with calculated statistics.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallReview.IRequest,
  ): Promise<IPageIEcommerceMallReview.ISummary> {
    try {
      return await patchEcommerceMallSellerAnalyticsReviews({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
