import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallDashboard } from "../../../../../api/structures/IEcommerceMallDashboard";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerAnalyticsDashboard } from "../../../../../providers/patchEcommerceMallSellerAnalyticsDashboard";
import { patchEcommerceMallSellerAnalyticsDashboardStats } from "../../../../../providers/patchEcommerceMallSellerAnalyticsDashboardStats";

@Controller("/ecommerceMall/seller/analytics/dashboard")
export class EcommercemallSellerAnalyticsDashboardController {
  /**
   * Retrieve seller dashboard statistics and performance metrics.
   *
   * This operation provides essential seller analytics including total active product count, pending cancellation and refund request counts, order item summaries with sales volume and revenue statistics. The data is filtered to only include products and orders belonging to the authenticated seller.
   *
   * The operation supports filtering by order item status to get breakdowns for paid, shipped, delivered, cancelled, and refunded items. Response includes aggregated metrics optimized for dashboard display and summary views.
   *
   * @param connection
   * @param body Request parameters for filtering and pagination
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query seller's active products, pending cancellation requests, pending refund requests, and order item statistics.
   * Join ecommerce_mall_products (seller_id, deleted_at IS NULL), ecommerce_mall_cancellation_requests (seller_id, status='pending'), ecommerce_mall_refund_requests (seller_id, status='pending'), and ecommerce_mall_order_items (seller_id, optional item_status filter).
   * Aggregate: count of active products, count of pending cancellation requests, count of pending refund requests, count of order items per status (paid, shipped, delivered, cancelled, refunded), sum of item totals by status.
   * Apply seller context from authenticated user's seller profile.
   * Return summary statistics without individual records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("stats")
  public async stats(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallDashboard.IRequest,
  ): Promise<IEcommerceMallDashboard.ISummary> {
    try {
      return await patchEcommerceMallSellerAnalyticsDashboardStats({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve aggregated seller dashboard statistics for product and order performance.
   *
   * This operation provides a comprehensive overview of seller business performance including product inventory counts, pending request monitoring, and sales analytics. The dashboard statistics are calculated from active (non-deleted) products and all-time order data for products owned by the authenticated seller.
   *
   * Security Considerations:
   * - Only accessible by authenticated sellers
   * - Data is scoped to products owned by the authenticated seller
   * - Excludes products from suspended sellers in aggregated metrics
   * - Does not expose customer or order-level detail
   *
   * Related Operations:
   * - GET /sellers/dashboard/order-items retrieves filtered order items list with pagination for detailed viewing
   * - GET /products provides product listing for inventory management
   * - PATCH /order-items/:itemId/approve-cancel handles individual cancellation approvals
   * - PATCH /order-items/:itemId/approve-refund handles individual refund approvals
   *
   * @param connection
   * @param body Dashboard statistics query parameters and filters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Calculate seller dashboard statistics by querying the ecommerce_mall_products and ecommerce_mall_order_items tables.
   * 1. Count active products: COUNT(*) WHERE sellerId matches authenticated seller AND deletedAt IS NULL
   * 2. Count pending cancellation requests: COUNT(*) WHERE sellerId matches authenticated seller AND status = 'pending'
   * 3. Count pending refund requests: COUNT(*) WHERE sellerId matches authenticated seller AND status = 'pending'
   * 4. Total order items sold: COUNT(*) WHERE sellerId matches authenticated seller
   * 5. Product performance: GROUP BY productId SUM(quantity) as total_units, SUM(productPrice * quantity) as total_revenue
   * 6. Apply optional filters from request body (date range, category filters)
   * 7. Return aggregated statistics as IEcommerceMallDashboard
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallDashboard.IRequest,
  ): Promise<IEcommerceMallDashboard.ISummary> {
    try {
      return await patchEcommerceMallSellerAnalyticsDashboard({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
