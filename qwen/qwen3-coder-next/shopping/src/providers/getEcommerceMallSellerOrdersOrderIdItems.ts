export async function getEcommerceMallSellerOrdersOrderIdItems(props: {
  seller: SellerPayload;
  orderId: string;
}): Promise<IPageIEcommerceMallOrderItem.ISummary> {
  const page = 1;
  const limit = 20;
  const skip = (page - 1) * limit;
  const data = await MyGlobal.prisma.ecommerce_mall_order_items.findMany({
    where: { order_id: props.orderId },
    skip,
    take: limit,
    orderBy: { created_at: "desc" },
    ...EcommerceMallOrderItemAtSummaryTransformer.select(),
  });
  const total = await MyGlobal.prisma.ecommerce_mall_order_items.count({
    where: { order_id: props.orderId },
  });
  const records = await ArrayUtil.asyncMap(
    data,
    EcommerceMallOrderItemAtSummaryTransformer.transform,
  );
  return {
    pagination: {
      current: page as number & tags.Type<"int32"> & tags.Minimum<0>,
      limit: limit as number & tags.Type<"int32"> & tags.Minimum<0>,
      records: total as number & tags.Type<"int32"> & tags.Minimum<0>,
      pages: Math.ceil(total / limit) as number &
        tags.Type<"int32"> &
        tags.Minimum<0>,
    } satisfies IPage.IPagination,
    data: records,
  } satisfies IPageIEcommerceMallOrderItem.ISummary;
}
