export async function getEcommerceMallCustomerCancellationRequestsCancellationRequestId(props: {
  customer: CustomerPayload;
  cancellationRequestId: string;
}): Promise<IEcommerceMallCancellationRequest> {
  // Query the cancellation request with joined data using the transformer's select
  const request =
    await MyGlobal.prisma.ecommerce_mall_cancellation_requests.findUniqueOrThrow(
      {
        where: { id: props.cancellationRequestId },
        ...EcommerceMallCancellationRequestTransformer.select(),
      },
    );
  // Authorization check: only the customer who created the request can access it
  if (request.customer.id !== props.customer.id) {
    throw new HttpException("Forbidden", 403);
  }
  // Transform the result using the loaded transformer
  return await EcommerceMallCancellationRequestTransformer.transform(request);
}
