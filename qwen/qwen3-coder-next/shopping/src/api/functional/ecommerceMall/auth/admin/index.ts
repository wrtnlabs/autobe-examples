/**
 * Register a new admin account for the platform administration system.
 *
 * ## Purpose
 *
 * This operation creates a new admin account with email/password credentials, enabling
 * the user to access the platform administration system. Admin accounts require
 * email/password authentication and their sessions are tracked in the admin_sessions
 * table for security auditing.
 *
 * ## Implementation Details
 *
 * The operation validates the email format and checks for uniqueness in the
 * ecommerce_mall_admins table. The password is securely hashed before storage.
 * The new admin record is created with the provided credentials and initial
 * grade assignment (regular or super). The operation supports the password reset
 * functionality by ensuring the created admin can receive reset tokens through
 * the ecommerce_mall_admin_password_resets table.
 *
 * ## Security Considerations
 *
 * Admin registration should be restricted to authorized personnel. The email
 * validation prevents duplicate accounts, and the password hashing ensures
 * credentials are not stored in plain text. The admin's initial grade determines
 * their privilege level (regular vs super administrator).
 *
 * ## Related Operations
 *
 * - Login: After registration, admins can authenticate using the /auth/login/admin
 * endpoint.
 * - Password Reset: If admins forget their password, they can request a reset
 * through the password reset flow using the ecommerce_mall_admin_password_resets
 * table.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration information for new admin account
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Create new admin record in ecommerce_mall_admins table with hashed password. Validate email uniqueness, hash password with bcrypt, assign initial grade, and return JWT tokens.
 * @path /ecommerceMall/auth/admin/join
 * @accessor api.functional.ecommerceMall.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
