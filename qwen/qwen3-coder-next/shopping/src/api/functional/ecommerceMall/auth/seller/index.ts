/**
 * Seller registration endpoint that creates a new seller account in the system. The registration process involves:
 *
 * 1. **Email validation**: Checks that the email is unique and properly formatted
 * 2. **Password hashing**: Uses bcrypt to securely hash the password before storage
 * 3. **Seller record creation**: Creates a record in the ecommerce_mall_sellers table with approval_status set to 'pending' (requires admin approval before first login)
 * 4. **Initial profile setup**: Creates corresponding seller profile with shop_name from registration data
 *
 * The created seller account remains in 'pending' state until an administrator approves the registration. During this pending state, login attempts will be rejected even with correct credentials. This approval workflow ensures platform quality control and prevents unauthorized seller accounts.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Seller registration request containing email, password, and shop information
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Process seller registration by creating an ecommerce_mall_sellers record with pending approval status. Validate email uniqueness, hash password using bcrypt, and return seller credentials for first login.
 * @path /ecommerceMall/auth/seller/join
 * @accessor api.functional.ecommerceMall.auth.seller.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
