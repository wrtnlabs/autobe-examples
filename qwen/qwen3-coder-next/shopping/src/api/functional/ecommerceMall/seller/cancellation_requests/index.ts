/**
 * Retrieve details of a specific cancellation request by its ID.
 *
 * This endpoint allows customers, sellers, and administrators to access detailed information about a cancellation request, including the cancellation reason, current status (pending, approved, or rejected), timestamp of the seller's response (if any), and creation/update timestamps.
 *
 * Security Considerations:
 * - Customers can only access their own cancellation requests
 * - Sellers can only access cancellation requests for their own products
 * - Administrators have access to all cancellation requests for oversight purposes
 *
 * The cancellation request is linked to an order item and contains snapshot data capturing the state at the time of the request. This supports dispute resolution and audit compliance requirements.
 *
 * @param props.connection
 * @param props.cancellationRequestId Target cancellation request's ID
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Query ecommerce_mall_cancellation_requests table by id to retrieve the cancellation request.
 * Include joined data for order_item, customer, and seller.
 * Apply authorization checks: customer can only access their own requests, seller can only access requests for their products, admin has full access.
 * Return the full cancellation request record with all fields including status, reason, responded_at, and timestamps.
 * @path /ecommerceMall/seller/cancellation-requests/:cancellationRequestId
 * @accessor api.functional.ecommerceMall.seller.cancellation_requests.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Target cancellation request's ID
     */
    cancellationRequestId: string;
  };
  export type Response = IEcommerceMallCancellationRequest;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/seller/cancellation-requests/:cancellationRequestId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/seller/cancellation-requests/${encodeURIComponent(props.cancellationRequestId ?? "null")}`;
  export const random = (): IEcommerceMallCancellationRequest =>
    typia.random<IEcommerceMallCancellationRequest>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("cancellationRequestId")(() =>
        typia.assert(props.cancellationRequestId),
      );
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
