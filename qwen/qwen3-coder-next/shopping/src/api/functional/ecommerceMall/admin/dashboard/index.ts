/**
 * Retrieve seller dashboard statistics for product and order performance tracking.
 *
 * This endpoint provides sellers with a comprehensive overview of their store performance including total active products count, pending cancellation request count, pending refund request count, and total order items sold. These statistics are essential for sellers to monitor their business metrics at a glance.
 *
 * Access control ensures that only authenticated sellers can retrieve their dashboard statistics. If a seller account is suspended, the endpoint returns an appropriate error response. The statistics are calculated from the seller's perspective, counting only their own products and order items.
 *
 * The dashboard statistics are updated in real-time as sellers process orders, respond to cancellation and refund requests, or modify their product inventory. This provides immediate visibility into their store performance.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query seller dashboard statistics from the database. Calculate total products count (excluding deleted), pending cancellation request count, pending refund request count, and total order items sold. All counts are filtered by the authenticated seller's ID. Return the statistics as a summary DTO.
 * @path /ecommerceMall/admin/dashboard
 * @accessor api.functional.ecommerceMall.admin.dashboard.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = IEcommerceMallDashboard.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/admin/dashboard",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerceMall/admin/dashboard";
  export const random = (): IEcommerceMallDashboard.ISummary =>
    typia.random<IEcommerceMallDashboard.ISummary>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
