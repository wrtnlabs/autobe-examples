import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IPageIEcommerceMallShipment } from "../../../../../structures/IPageIEcommerceMallShipment";

/**
 * Retrieve all shipments for a specific order.
 *
 * This endpoint returns all shipment records associated with the given order ID. Each shipment represents a physical package created by a seller when shipping items from the order. Multiple shipments may exist for a single order when items belong to different sellers.
 *
 * The response includes carrier information, tracking numbers, shipment status, and creation timestamps. Shipment items reference the order items that are included in each physical package, enabling customers to see which specific products are included in each shipment.
 *
 * @param props.connection
 * @param props.orderId Target order's unique identifier
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query ecommerce_mall_shipments table filtered by ecommerce_mall_order_id parameter.
 * Join with ecommerce_mall_sellers to include seller profile information.
 * Include shipment_items count for each shipment to show item quantities.
 * Order results by created_at descending to show newest shipments first.
 * Return paginated list using IPageIShipment.ISummary response structure.
 * @path /ecommerceMall/admin/orders/:orderId/shipments
 * @accessor api.functional.ecommerceMall.admin.orders.shipments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Target order's unique identifier
     */
    orderId: string;
  };
  export type Response = IPageIEcommerceMallShipment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerceMall/admin/orders/:orderId/shipments",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/admin/orders/${encodeURIComponent(props.orderId ?? "null")}/shipments`;
  export const random = (): IPageIEcommerceMallShipment.ISummary =>
    typia.random<IPageIEcommerceMallShipment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderId")(() => typia.assert(props.orderId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
