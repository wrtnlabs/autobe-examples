import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IEcommerceMallReviewImage } from "../../../../structures/IEcommerceMallReviewImage";

/**
 * Retrieve all images associated with a specific review.
 *
 * This operation returns all images uploaded to support a customer review, providing visual context for the review content. The images are returned in the order specified by the seller when they were uploaded, with the sort_order field determining display sequence.
 *
 * Access control rules:
 * - Review author (customer) can view their own review images
 * - Seller who received the review can view images for reviews on their products
 * - Administrators and super administrators can view all review images for moderation purposes
 * - Guests and other customers cannot access review images
 *
 * When a review is deleted, its associated images are also automatically removed from the system to maintain data integrity and prevent orphaned files.
 *
 * @param props.connection
 * @param props.reviewId Target review's unique identifier
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query the ecommerce_mall_review_images table joined with ecommerce_mall_reviews to find all images for the specified review ID.
 * Apply authorization checks:
 * - If customer: verify review.customer_id matches authenticated user ID or review order_item_id belongs to authenticated user's orders
 * - If seller: verify review.product_id belongs to authenticated seller's products
 * - If admin: allow access without restrictions
 * Return all images ordered by sort_order ascending.
 * Return the image_url, sort_order, and creation timestamp for each image.
 * @path /ecommerceMall/reviews/:reviewId/images
 * @accessor api.functional.ecommerceMall.reviews.images.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Target review's unique identifier
     */
    reviewId: string;
  };
  export type Response = IEcommerceMallReviewImage;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/reviews/:reviewId/images",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/reviews/${encodeURIComponent(props.reviewId ?? "null")}/images`;
  export const random = (): IEcommerceMallReviewImage =>
    typia.random<IEcommerceMallReviewImage>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
