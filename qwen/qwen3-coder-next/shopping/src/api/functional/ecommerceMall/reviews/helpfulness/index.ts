import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IEcommerceMallReview } from "../../../../structures/IEcommerceMallReview";

/**
 * Retrieve helpfulness vote statistics for a specific review.
 *
 * This operation provides helpfulness vote statistics for a review, showing how many customers found the review helpful versus unhelpful. It also indicates whether the current customer has cast a helpfulness vote on this review.
 *
 * The helpfulness vote system allows customers to vote on review quality - marking reviews as helpful (upvote) or unhelpful (downvote). This helps surface high-quality reviews to other customers and provides feedback to review authors.
 *
 * Only the total counts and the current customer's vote status are returned. Individual voter identities are not exposed to protect voter privacy.
 *
 * @param props.connection
 * @param props.reviewId Target review's ID
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query the ecommerce_mall_review_helpfulness_votes table to count helpful and unhelpful votes for the specified review. Also check if the current customer has voted on this review. Return the counts and vote status as a summary object.
 * @path /ecommerceMall/reviews/:reviewId/helpfulness
 * @accessor api.functional.ecommerceMall.reviews.helpfulness.getHelpfulness
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function getHelpfulness(
  connection: IConnection,
  props: getHelpfulness.Props,
): Promise<getHelpfulness.Response> {
  return true === connection.simulate
    ? getHelpfulness.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...getHelpfulness.METADATA,
          path: getHelpfulness.path(props),
          status: null,
        },
      );
}
export namespace getHelpfulness {
  export type Props = {
    /**
     * Target review's ID
     */
    reviewId: string;
  };
  export type Response = IEcommerceMallReview.IHelpfulness;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/reviews/:reviewId/helpfulness",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/reviews/${encodeURIComponent(props.reviewId ?? "null")}/helpfulness`;
  export const random = (): IEcommerceMallReview.IHelpfulness =>
    typia.random<IEcommerceMallReview.IHelpfulness>();
  export const simulate = (
    connection: IConnection,
    props: getHelpfulness.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: getHelpfulness.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
