import { IEcommerceMallCustomerProfile } from "../../../../../structures/IEcommerceMallCustomerProfile";

/**
 * Retrieve the current authenticated customer's profile information.
 *
 * This endpoint returns the customer's display name and phone number that are stored in their profile. The profile is automatically created when a customer account is registered and is subsidiary to the customer account—it cannot exist independently.
 *
 * The operation requires authentication and returns the profile of the authenticated customer only. Profile data is used for public display (display name) and contact purposes (phone number for shipping and customer service).
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Retrieve the customer profile record from ecommerce_mall_customer_profiles table where user_id matches the authenticated customer's ID.
 * Join with ecommerce_mall_customers table to verify the customer account exists and is active.
 * Return the profile record with display_name and phone_number fields.
 * @path /ecommerceMall/customer/customers/me
 * @accessor api.functional.ecommerceMall.customer.customers.me.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = IEcommerceMallCustomerProfile;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/customer/customers/me",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerceMall/customer/customers/me";
  export const random = (): IEcommerceMallCustomerProfile =>
    typia.random<IEcommerceMallCustomerProfile>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
