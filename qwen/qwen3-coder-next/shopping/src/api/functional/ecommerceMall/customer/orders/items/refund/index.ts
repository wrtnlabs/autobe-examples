/**
 * Submit a refund request for an order item
 *
 * This operation allows customers to request refunds for delivered order items. The system enforces strict validation rules including a 7-day refund window from delivery date. When approved, the system restores stock quantity and updates order item status to 'refunded'.
 *
 * ### Validation Rules
 * - Refund requests must be submitted within 7 days of item delivery
 * - Refund requests for cancelled items are rejected immediately
 * - The system preserves the original item price and variant options at time of refund
 * - Stock quantity is restored via inventory records with reference to the order item
 *
 * ### Order Status Impact
 * - Single item order: Status becomes 'refunded' when item status changes to 'refunded'
 * - Multiple item order: Status becomes 'partiallyCompleted' when some items are refunded
 * - Order status is recalculated based on remaining items after refund processing
 *
 * ### Business Logic
 * - The system creates snapshots of refund requests at submission and approval/rejection time
 * - Other items in the same order continue their normal fulfillment process
 * - Sellers are notified of refund requests and can approve or reject them
 *
 * ### Security Considerations
 * - Only the customer who purchased the item can submit refund requests
 * - Sellers can only approve/reject refund requests for their own items
 * - Admin users can override refund decisions through administrative interfaces
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the parent order
 * @param props.orderItemId Unique identifier of the order item to refund
 * @param props.body Refund request details including reason for refund
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Process refund request for an order item.
 * 1. Validate that the order item exists and belongs to the customer
 * 2. Check that the order item status is 'delivered'
 * 3. Verify the delivery date is within 7-day refund window
 * 4. Reject refund requests for cancelled items
 * 5. Create a refund request with status 'pending' and save snapshot
 * 6. Return success response with refund request details
 * @path /ecommerceMall/customer/orders/:orderId/items/:orderItemId/refund
 * @accessor api.functional.ecommerceMall.customer.orders.items.refund.requestRefund
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestRefund(
  connection: IConnection,
  props: requestRefund.Props,
): Promise<requestRefund.Response> {
  return true === connection.simulate
    ? requestRefund.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestRefund.METADATA,
          path: requestRefund.path(props),
          status: null,
        },
        props.body,
      );
}
