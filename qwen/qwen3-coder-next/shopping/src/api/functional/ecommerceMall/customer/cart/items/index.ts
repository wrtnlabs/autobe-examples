/**
 * Add a product variant to the customer's shopping cart.
 *
 * This endpoint allows authenticated customers to add items to their cart. The system validates that the variant exists, is in stock, and the requested quantity is available. If the variant already exists in the customer's cart, the quantities are combined. Cart items are private to each customer and never shared between accounts. When a cart item is added or updated, the system immediately recalculates and persists the cart total.
 *
 * **Security & Privacy:**
 * - Customer authentication is required
 * - Cart items are isolated per customer account
 * - Cart items from suspended sellers are hidden from view
 * - Customers cannot access or modify other customers' cart items
 *
 * **Quantity Management:**
 * - Minimum quantity is 1
 * - Maximum quantity is limited by available stock for the variant
 * - If the same variant already exists in cart, quantities are combined
 *
 * **Availability Checks:**
 * - Validates that the variant exists and is not deleted
 * - Verifies the seller account is not suspended
 * - Checks that sufficient stock is available
 * - Marks items as unavailable if variant is out of stock or seller is suspended
 *
 * @param props.connection
 * @param props.body Cart item creation request with variant selection and quantity
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Add a new cart item or update existing cart item quantity.
 *
 * 1. Authenticate customer using session/JWT token
 * 2. Retrieve variant by id from request body
 * 3. Validate variant exists and is not deleted
 * 4. Validate seller account is not suspended
 * 5. Validate requested quantity (min 1, max available stock)
 * 6. Check if cart item already exists for user_id + variant_id
 * 7. IF exists: update quantity (existing + new)
 *    ELSE: create new cart item with requested quantity
 * 8. Return created/updated cart item with calculated subtotal
 * 9. Log audit trail for cart modification
 * @path /ecommerceMall/customer/cart/items
 * @accessor api.functional.ecommerceMall.customer.cart.items.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
