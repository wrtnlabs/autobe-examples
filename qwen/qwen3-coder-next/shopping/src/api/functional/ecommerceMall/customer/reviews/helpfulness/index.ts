/**
 * Cast a helpfulness vote on a review.
 *
 * This operation allows customers to indicate that they found a review helpful. Each customer can cast only one helpfulness vote per review. The system tracks the vote timestamp and maintains referential integrity with both the review and customer accounts.
 *
 * When a customer casts a helpfulness vote, the system:
 * - Creates a new record linking the customer to the review
 * - Records the timestamp of the vote
 * - Updates the review's helpfulness metrics
 *
 * Security considerations:
 * - Only authenticated customers can cast helpfulness votes
 * - Each customer can vote only once per review
 * - Customers cannot vote on their own reviews
 * - Deleted reviews cannot receive helpfulness votes
 *
 * This operation supports the platform's quality assessment system by enabling the community to identify valuable reviews.
 *
 * @param props.connection
 * @param props.reviewId Target review's ID
 * @param props.body Helpfulness vote data (contains only review context - customer_id from auth)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Create a new helpfulness vote record in ecommerce_mall_review_helpfulness_votes table.
 *
 * Process:
 * 1. Validate reviewId exists and is not deleted
 * 2. Validate customer is authenticated and not the review author
 * 3. Check for existing vote from this customer on this review
 * 4. Create vote record with current timestamp
 * 5. Update review's helpfulness metrics (total votes, vote ratio)
 *
 * Error handling:
 * - Review not found or deleted: 404 Not Found
 * - Customer is review author: 400 Bad Request
 * - Duplicate vote: 400 Bad Request
 * - Unauthorized: 401 Unauthorized
 *
 * Database transaction ensures atomic vote creation and metric updates.
 * @path /ecommerceMall/customer/reviews/:reviewId/helpfulness
 * @accessor api.functional.ecommerceMall.customer.reviews.helpfulness.voteHelpfulness
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function voteHelpfulness(
  connection: IConnection,
  props: voteHelpfulness.Props,
): Promise<void> {
  return true === connection.simulate
    ? voteHelpfulness.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...voteHelpfulness.METADATA,
          path: voteHelpfulness.path(props),
          status: null,
        },
        props.body,
      );
}
