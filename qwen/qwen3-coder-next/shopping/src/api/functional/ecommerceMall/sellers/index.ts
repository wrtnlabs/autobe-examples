import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia from "typia";

import { IEcommerceMallSeller } from "../../../structures/IEcommerceMallSeller";

/**
 * Retrieve public seller profile information.
 *
 * This endpoint allows anyone to view a seller's shop profile details without requiring authentication. It returns essential information about the seller's shop including their store name, description, logo URL, and current approval status.
 *
 * Security considerations:
 * - No authentication required - this is a public endpoint
 * - Only returns non-sensitive seller profile information
 * - Does not expose private account details like email or password
 * - Respects seller account status (suspended sellers' profiles remain visible but with status indication)
 *
 * Relationship to database entities:
 * - References the ecommerce_mall_sellers table for seller account information
 * - Returns seller profile fields that are intentionally made public
 * - Does not include sensitive fields like password_hash or internal status flags
 *
 * Related endpoints:
 * - GET /sellers/me/profile - Get current authenticated seller's profile (requires authentication)
 * - PATCH /sellers/me/profile - Update current seller's profile (requires authentication)
 * - GET /sellers/:id - Get seller details (alternative path format)
 *
 * @param props.connection
 * @param props.sellerId Target seller's unique identifier
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query ecommerce_mall_sellers table by seller ID to retrieve public profile fields including shop_name, shop_description, logo_url, and approval_status. Return seller profile information with appropriate status indication. Handle cases where seller is suspended or account is deleted.
 * @path /ecommerceMall/sellers/:sellerId
 * @accessor api.functional.ecommerceMall.sellers.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Target seller's unique identifier
     */
    sellerId: string;
  };
  export type Response = IEcommerceMallSeller;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/sellers/:sellerId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/sellers/${encodeURIComponent(props.sellerId ?? "null")}`;
  export const random = (): IEcommerceMallSeller =>
    typia.random<IEcommerceMallSeller>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sellerId")(() => typia.assert(props.sellerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
