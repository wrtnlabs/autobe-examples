/**
 * Retrieve filtered and paginated product search results with comprehensive filtering capabilities.
 *
 * This operation provides advanced product search functionality allowing customers to search by product name and description, filter by category (including subcategories), apply price range constraints, and filter for in-stock products only. Results are returned in paginated format with configurable sorting options.
 *
 * ## Features
 * - Full-text search on product names and descriptions from the shopping_mall_products table
 * - Category-based filtering with subcategory support through shopping_mall_categories hierarchy
 * - Price range filtering on the base_price field
 * - Stock availability filtering (in-stock only) by checking shopping_mall_variant_stocks.current_quantity > 0
 * - Configurable pagination with page and limit parameters
 * - Sorting by creation date (newest first), price (low to high, high to low), and relevance
 * - Soft delete handling through is_deleted and deleted_at fields
 *
 * ## Security
 * - Search results exclude soft-deleted products (is_deleted = true)
 * - Only products with valid categories and active sellers are included in results
 * - Stock information is computed from inventory history to ensure accuracy
 *
 * @param props.connection
 * @param props.body Search criteria including query text, category filter, price range, in-stock flag, page, limit, and sorting options
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query shopping_mall_products table with full-text search on name and description.
 * Apply category filter including subcategories using category_id hierarchy.
 * Apply price range filters on base_price field.
 * Apply in-stock filter by checking shopping_mall_variant_stocks.current_quantity > 0.
 * Support pagination with configurable page and limit parameters.
 * Support sorting by created_at (newest first), base_price (asc/desc), and relevance.
 * Join with shopping_mall_categories for category hierarchy, shopping_mall_variant_stocks for stock status.
 * Return paginated product summaries with basic information optimized for search result display.
 * @path /shoppingMall/search/products
 * @accessor api.functional.shoppingMall.search.products.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria including query text, category filter, price range, in-stock flag, page, limit, and sorting options
     */
    body: IShoppingMallProduct.IRequest;
  };
  export type Body = IShoppingMallProduct.IRequest;
  export type Response = IPageIShoppingMallProduct.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/search/products",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/search/products";
  export const random = (): IPageIShoppingMallProduct.ISummary =>
    typia.random<IPageIShoppingMallProduct.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
