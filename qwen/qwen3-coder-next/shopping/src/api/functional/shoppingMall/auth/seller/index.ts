/**
 * Seller registration endpoint for new business users to create accounts on the shopping mall platform.
 *
 * This API operation allows business users to register as sellers and begin the seller onboarding process. Upon successful registration, the seller account is created in 'pending' approval status, and the user receives temporary credentials for initial authentication.
 *
 * ## Business Context
 *
 * Sellers represent business entities that want to list products and manage their own shops on the platform. The registration process captures essential business information including shop name, description, and logo. All new sellers start with 'pending' approval status and must wait for administrator approval before gaining full seller privileges.
 *
 * ## Security Considerations
 *
 * The registration process validates email uniqueness, enforces password strength requirements, and creates initial session tokens for immediate temporary access. The registration triggers email verification and creates a seller record linked to the customer account.
 *
 * ## Database Integration
 *
 * This operation creates records in multiple tables:
 * - shopping_mall_customers: Customer account with kind='seller'
 * - shopping_mall_sellers: Seller-specific information with approval_status='pending'
 * - shopping_mall_seller_sessions: Initial authentication session
 * - shopping_mall_seller_email_verifications: Email verification token
 *
 * ## Related Operations
 *
 * - Login: Used after registration to obtain permanent credentials
 * - Refresh: Used to renew access tokens without re-authentication
 * - Profile Update: Used after approval to configure shop settings
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Seller registration information including email, password, and shop details.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Seller registration flow: 1) Validate email uniqueness and password strength, 2) Create customer record with kind='seller', 3) Create seller record with approval_status='pending' and provided shop information, 4) Generate initial session tokens, 5) Create email verification token, 6) Send verification email, 7) Return authorized response with tokens and seller details. All operations wrapped in transaction for atomicity.
 * @path /shoppingMall/auth/seller/join
 * @accessor api.functional.shoppingMall.auth.seller.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
