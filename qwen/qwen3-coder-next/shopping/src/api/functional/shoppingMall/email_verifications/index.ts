import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../structures/IShoppingMallCustomer";

/**
 * Confirm email verification using a verification token.
 *
 * This operation allows customers to verify their email address after registration by providing a verification token that was sent to their email address. The token has a limited lifetime (typically 24-48 hours) and can only be used once.
 *
 * ## Verification Process
 *
 * When a customer registers, the system generates a unique verification token and sends it to the customer's email address. The customer clicks the verification link in the email, which calls this endpoint with the token. The system validates the token and marks the customer's email as verified.
 *
 * ## Token Validation
 *
 * The system validates the verification token by:
 * - Checking that the token exists in the database
 * - Verifying that the token has not expired
 * - Ensuring that the token has not been used before
 *
 * If the token is valid, the system marks it as used, updates the customer's email verification status, and returns the customer profile information. If the token is invalid, expired, or already used, the system returns an appropriate error message.
 *
 * ## Security Considerations
 *
 * This endpoint is critical for account security. The system must validate tokens securely and prevent token reuse. Expired tokens should be automatically invalidated by the system.
 *
 * ## Related Operations
 *
 * - `POST /api/customers/register` - Register new customer and send verification email
 * - `POST /api/customers/password/reset-request` - Request password reset token
 * - `POST /api/customers/password/reset` - Reset password with token
 *
 * @param props.connection
 * @param props.token Email verification token
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query shopping_mall_customer_email_verifications table for the token.
 * Validate that the token exists and is not expired.
 * Validate that the token has not been used (used_at is null).
 * If valid, mark the token as used (set used_at to current timestamp).
 * Mark the associated customer's email as verified.
 * Return customer profile information with verification status.
 * Handle token validation errors (not found, expired, already used).
 * @path /shoppingMall/email-verifications/:token
 * @accessor api.functional.shoppingMall.email_verifications.verify
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function verify(
  connection: IConnection,
  props: verify.Props,
): Promise<verify.Response> {
  return true === connection.simulate
    ? verify.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verify.METADATA,
          path: verify.path(props),
          status: null,
        },
      );
}
export namespace verify {
  export type Props = {
    /**
     * Email verification token
     */
    token: string;
  };
  export type Response = IShoppingMallCustomer;

  export const METADATA = {
    method: "PUT",
    path: "/shoppingMall/email-verifications/:token",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/email-verifications/${encodeURIComponent(props.token ?? "null")}`;
  export const random = (): IShoppingMallCustomer =>
    typia.random<IShoppingMallCustomer>();
  export const simulate = (
    connection: IConnection,
    props: verify.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: verify.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("token")(() => typia.assert(props.token));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
