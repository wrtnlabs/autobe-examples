import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IPageIShoppingMallShipment } from "../../../../../structures/IPageIShoppingMallShipment";

/**
 * Retrieve all shipments belonging to a specific order.
 *
 * This endpoint returns a paginated list of all physical shipments associated with the specified order. Each shipment represents a package sent from a seller to the customer and includes shipping carrier information, tracking numbers, and delivery status.
 *
 * The shipments are retrieved by joining the shopping_mall_shipments table with shopping_mall_order_items, finding all shipments where the associated order item belongs to the specified order. This allows customers and sellers to view complete shipping information for order tracking and delivery monitoring.
 *
 * @param props.connection
 * @param props.orderId Target order's unique identifier
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query shopping_mall_shipments table by joining with shopping_mall_order_items. Filter shipments where order_items.shopping_mall_order_id matches the orderId parameter. Include carrier information, tracking numbers, and delivery status. Return paginated results with sorting by creation timestamp (newest first).
 * @path /shoppingMall/customer/orders/:orderId/shipments
 * @accessor api.functional.shoppingMall.customer.orders.shipments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Target order's unique identifier
     */
    orderId: string;
  };
  export type Response = IPageIShoppingMallShipment;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/orders/:orderId/shipments",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/orders/${encodeURIComponent(props.orderId ?? "null")}/shipments`;
  export const random = (): IPageIShoppingMallShipment =>
    typia.random<IPageIShoppingMallShipment>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderId")(() => typia.assert(props.orderId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
