/**
 * Confirm receipt of a shipment.
 *
 * This endpoint allows customers to manually confirm that they have received their shipment. Upon confirmation, all items in the shipment change their status to "delivered", enabling customers to write reviews for the products.
 *
 * The system also supports automatic delivery confirmation when customers do not manually confirm within 14 days of shipment. Once a shipment is marked as delivered (either manually or automatically), no further delivery confirmation is possible.
 *
 * @param props.connection
 * @param props.shipmentId Shipment ID to confirm delivery for
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Process shipment delivery confirmation:
 * 1. Validate shipment exists and belongs to customer
 * 2. Verify shipment status is 'shipped' (not already delivered)
 * 3. Check customer authorization (only order owner can confirm)
 * 4. Create delivery confirmation record with IP address and timestamp
 * 5. Update shipment status to 'delivered'
 * 6. Update all shipment items to 'delivered' status
 * 7. Update order status based on item statuses
 * 8. Log confirmation event for audit trail
 * 9. Return success response with confirmation timestamp
 * @path /shoppingMall/customer/shipments/:shipmentId/confirm
 * @accessor api.functional.shoppingMall.customer.shipments.confirm
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function confirm(
  connection: IConnection,
  props: confirm.Props,
): Promise<confirm.Response> {
  return true === connection.simulate
    ? confirm.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...confirm.METADATA,
          path: confirm.path(props),
          status: null,
        },
      );
}
export namespace confirm {
  export type Props = {
    /**
     * Shipment ID to confirm delivery for
     */
    shipmentId: string;
  };
  export type Response = IShoppingMallOrderDeliveryConfirmation.IResponse;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/customer/shipments/:shipmentId/confirm",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/shipments/${encodeURIComponent(props.shipmentId ?? "null")}/confirm`;
  export const random = (): IShoppingMallOrderDeliveryConfirmation.IResponse =>
    typia.random<IShoppingMallOrderDeliveryConfirmation.IResponse>();
  export const simulate = (
    connection: IConnection,
    props: confirm.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: confirm.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shipmentId")(() => typia.assert(props.shipmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

