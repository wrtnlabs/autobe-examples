import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallCustomerAddress } from "../../../../../structures/IShoppingMallCustomerAddress";

/**
 * Set an address as the default shipping address for the customer.
 *
 * This operation updates the specified address to have is_default = true, while automatically clearing the default flag from all other addresses belonging to the same customer. This ensures only one address can be marked as default per customer at any time.
 *
 * The operation validates that the address exists and belongs to the requesting customer. If the address has been soft-deleted, the operation will fail. The default address is automatically used in checkout processes and for automated communications when no specific address is selected.
 *
 * @param props.connection
 * @param props.addressId Target address's unique identifier (UUID)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Update shopping_mall_customer_addresses.is_default to true for the specified addressId.
 * Before updating, verify the address exists and belongs to the authenticated customer.
 * Use a database transaction to:
 * 1. Fetch the address record by id
 * 2. Verify it belongs to the authenticated customer (shopping_mall_customer_id matches)
 * 3. Update is_default = true for the specified address
 * 4. Update is_default = false for all other addresses of the same customer
 * 5. Return the updated address record
 * Handle soft-delete by rejecting requests for deleted addresses.
 * @path /shoppingMall/customer/addresses/:addressId/default
 * @accessor api.functional.shoppingMall.customer.addresses._default.setDefault
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function setDefault(
  connection: IConnection,
  props: setDefault.Props,
): Promise<setDefault.Response> {
  return true === connection.simulate
    ? setDefault.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...setDefault.METADATA,
          path: setDefault.path(props),
          status: null,
        },
      );
}
export namespace setDefault {
  export type Props = {
    /**
     * Target address's unique identifier (UUID)
     */
    addressId: string;
  };
  export type Response = IShoppingMallCustomerAddress;

  export const METADATA = {
    method: "PUT",
    path: "/shoppingMall/customer/addresses/:addressId/default",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/addresses/${encodeURIComponent(props.addressId ?? "null")}/default`;
  export const random = (): IShoppingMallCustomerAddress =>
    typia.random<IShoppingMallCustomerAddress>();
  export const simulate = (
    connection: IConnection,
    props: setDefault.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: setDefault.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("addressId")(() => typia.assert(props.addressId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
