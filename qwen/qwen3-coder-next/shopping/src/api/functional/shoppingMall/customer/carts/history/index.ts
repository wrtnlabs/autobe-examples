import typia from "typia";

import { IPageIShoppingMallCartHistory } from "../../../../../structures/IPageIShoppingMallCartHistory";

/**
 * Retrieve complete shopping cart modification history for a specific cart.
 *
 * This endpoint provides comprehensive audit trail functionality for shopping cart activities. Customers can view their complete cart modification history including all additions, quantity updates, item removals, and checkout events.
 *
 * The history maintains a complete record of cart state changes for customer reference and dispute resolution purposes. Each history entry captures the complete cart item state at the time of modification, including product information, variant details, quantities, and pricing.
 *
 * Security considerations ensure that customers can only access their own cart history through proper authentication and authorization checks.
 *
 * @param props.connection
 * @param props.cartId Target shopping cart's unique identifier.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query shopping_mall_cart_histories table for cart modification history.
 * Filter records by shopping_mall_cart_id path parameter.
 * Order results by created_at timestamp in descending order (newest first).
 * Return complete history records including operation_type, created_at, and item_json fields.
 * Implement pagination with configurable page size and cursor-based navigation.
 * Apply authentication to ensure customers can only access their own cart history.
 * @path /shoppingMall/customer/carts/:cartId/history
 * @accessor api.functional.shoppingMall.customer.carts.history.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Target shopping cart's unique identifier.
     */
    cartId: string;
  };
  export type Response = IPageIShoppingMallCartHistory;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/carts/:cartId/history",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/carts/${encodeURIComponent(props.cartId ?? "null")}/history`;
  export const random = (): IPageIShoppingMallCartHistory =>
    typia.random<IPageIShoppingMallCartHistory>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("cartId")(() => typia.assert(props.cartId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
