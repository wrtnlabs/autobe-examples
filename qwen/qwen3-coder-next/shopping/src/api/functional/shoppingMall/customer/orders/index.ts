/**
 * Retrieve a filtered and paginated list of orders.
 *
 * This operation provides comprehensive order search capabilities with filtering by status, date range, customer, and seller. It supports different access levels based on user role - customers see their own orders, sellers see their order items, and administrators see all orders.
 *
 * The endpoint supports advanced filtering including order status (paid/shipped/delivered/cancelled/refunded), date range filtering for order creation dates, and sorting by creation date (newest first by default).
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query shopping_mall_orders table with pagination and filtering.
 * Apply role-based access control - customers only see their own orders, sellers see their order items, admins see all.
 * Support filtering by status, date range, and optional customer/seller ID filters.
 * Order results by created_at timestamp descending (newest first).
 * Return paginated list with order summary information including basic status and total price details.
 * @path /shoppingMall/customer/orders
 * @accessor api.functional.shoppingMall.customer.orders.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
