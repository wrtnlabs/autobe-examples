import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IPageIShoppingMallProduct } from "../../../../structures/IPageIShoppingMallProduct";

/**
 * Retrieve all products in a specific category.
 *
 * This endpoint provides category-based product browsing, allowing customers to explore products organized by category hierarchy. When a customer selects a category, this endpoint returns all products assigned to that category including products in subcategories if configured.
 *
 * The endpoint supports navigation of the category structure and enables customers to browse products by category. The products returned include those directly assigned to the category as well as products in subcategories (if the system is configured to include subcategory products).
 *
 * The response includes product summary information optimized for list displays, showing main images, product names, prices, and seller information.
 *
 * @param props.connection
 * @param props.categoryId Target category's ID
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query shopping_mall_products table filtered by shopping_mall_category_id.
 * Join with shopping_mall_sellers for seller information.
 * Join with shopping_mall_categories for category information.
 * Apply category_id filter from path parameter.
 * Support pagination with configurable page size.
 * Return paginated list of product summaries with seller information.
 * @path /shoppingMall/categories/:categoryId/products
 * @accessor api.functional.shoppingMall.categories.products.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Target category's ID
     */
    categoryId: string;
  };
  export type Response = IPageIShoppingMallProduct.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/categories/:categoryId/products",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/categories/${encodeURIComponent(props.categoryId ?? "null")}/products`;
  export const random = (): IPageIShoppingMallProduct.ISummary =>
    typia.random<IPageIShoppingMallProduct.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("categoryId")(() => typia.assert(props.categoryId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
