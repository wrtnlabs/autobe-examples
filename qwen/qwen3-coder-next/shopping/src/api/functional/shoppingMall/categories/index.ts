/**
 * Retrieve a filtered, searched, and paginated list of product categories and subcategories.
 *
 * This operation provides comprehensive category management capabilities for administrative oversight, enabling platform administrators to browse, search, and filter the complete category hierarchy including both top-level categories and their associated subcategories.
 *
 * The operation supports advanced filtering by category name, description keywords, creation date ranges, and soft-delete status. Response includes category summary information optimized for list displays and administrative overview.
 *
 * Security considerations: This endpoint is restricted to administrator and super administrator roles only. Regular customers and sellers cannot access category management functionality.
 *
 * Relationship to underlying entities: This operation combines data from shopping_mall_categories (parent categories) and shopping_mall_subcategories (child subcategories), providing a unified view of the complete category taxonomy for platform administration.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query shopping_mall_categories table with pagination and filtering. Join with shopping_mall_subcategories for subcategory information. Apply search filters on name and description fields. Support filtering by creation date range and soft-delete status. Return paginated results with category summaries including subcategory counts.
 * @path /shoppingMall/categories
 * @accessor api.functional.shoppingMall.categories.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and pagination parameters
     */
    body: IShoppingMallCategory.IRequest;
  };
  export type Body = IShoppingMallCategory.IRequest;
  export type Response = IPageIShoppingMallCategory.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/categories",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/categories";
  export const random = (): IPageIShoppingMallCategory.ISummary =>
    typia.random<IPageIShoppingMallCategory.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

