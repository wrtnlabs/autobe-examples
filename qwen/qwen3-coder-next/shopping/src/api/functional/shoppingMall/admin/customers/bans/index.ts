import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../../structures/IShoppingMallCustomer";

/**
 * Permanently ban a customer account to prevent platform abuse and protect other users.
 *
 * This operation permanently bans a customer account, preventing the customer from logging into their account and accessing any platform features. All active customer sessions are immediately invalidated, shopping cart contents are cleared, and the customer's active orders are hidden from public view.
 *
 * When a customer is banned:
 * - Login attempts are denied with ACCOUNT_BANNED error code
 * - All active sessions are invalidated
 * - Shopping cart contents are cleared
 * - Active orders are hidden from public view
 * - Ban action is logged with timestamp and administrator information
 *
 * This operation should be used sparingly and only for severe policy violations or abusive behavior. Administrators should document the reason for ban and consider whether the ban should be temporary or permanent.
 *
 * @param props.connection
 * @param props.customerId ID of the customer to ban
 * @param props.body Ban request information (reason, duration)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Process customer ban request from administrator. Update customer status to 'banned', invalidate all active sessions, clear shopping cart contents, hide active orders from public view, and log the ban action with timestamp and administrator information. Return the updated customer information with ban status.
 * @path /shoppingMall/admin/customers/:customerId/bans
 * @accessor api.functional.shoppingMall.admin.customers.bans.ban
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function ban(
  connection: IConnection,
  props: ban.Props,
): Promise<ban.Response> {
  return true === connection.simulate
    ? ban.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...ban.METADATA,
          path: ban.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace ban {
  export type Props = {
    /**
     * ID of the customer to ban
     */
    customerId: string;

    /**
     * Ban request information (reason, duration)
     */
    body: IShoppingMallCustomer.IBan;
  };
  export type Body = IShoppingMallCustomer.IBan;
  export type Response = IShoppingMallCustomer;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/admin/customers/:customerId/bans",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/admin/customers/${encodeURIComponent(props.customerId ?? "null")}/bans`;
  export const random = (): IShoppingMallCustomer =>
    typia.random<IShoppingMallCustomer>();
  export const simulate = (
    connection: IConnection,
    props: ban.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: ban.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("customerId")(() => typia.assert(props.customerId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
