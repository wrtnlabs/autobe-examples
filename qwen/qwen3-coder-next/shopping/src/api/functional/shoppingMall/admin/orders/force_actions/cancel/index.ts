/**
 * Force-cancel order items or entire order by administrator authority.
 *
 * This administrative operation allows authorized administrators to cancel order items or entire orders to resolve disputes, protect customer interests, or handle exceptional circumstances. When an order or items are force-cancelled, the system processes refunds for paid items, restores inventory quantities for the cancelled items, updates order item statuses to "cancelled", and updates the overall order status based on the remaining items.
 *
 * The operation supports two modes:
 * - **Force-cancel specific items**: Cancel selected order items within an order
 * - **Force-cancel entire order**: Cancel all items in the order
 *
 * The system ensures that inventory is properly restored, refunds are processed for paid items, and a complete audit trail is maintained for compliance purposes.
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the order to be cancelled
 * @param props.body Force cancellation request containing cancellation details and selected items
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Process force cancellation request by administrators.
 * 1. Validate administrator has appropriate permissions (regular or super administrator)
 * 2. Load the order by orderId and verify it exists
 * 3. If itemIds are provided, cancel specific items; otherwise cancel entire order
 * 4. For each cancelled item:
 *    - Update order item status to "cancelled"
 *    - Create inventory history record with reason "administrator cancellation"
 *    - Create refund transaction if item was paid
 *    - Create cancellation request snapshot
 * 5. Update order status based on remaining items
 * 6. Log administrator action with timestamp, reason, and actor information
 * 7. Return updated order with cancelled items and restored inventory
 * @path /shoppingMall/admin/orders/:orderId/force-actions/cancel
 * @accessor api.functional.shoppingMall.admin.orders.force_actions.cancel.forceCancel
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function forceCancel(
  connection: IConnection,
  props: forceCancel.Props,
): Promise<forceCancel.Response> {
  return true === connection.simulate
    ? forceCancel.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...forceCancel.METADATA,
          path: forceCancel.path(props),
          status: null,
        },
        props.body,
      );
}
