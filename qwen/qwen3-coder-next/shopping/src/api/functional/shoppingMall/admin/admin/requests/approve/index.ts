export async function approveRequest(
  connection: IConnection,
  props: approveRequest.Props,
): Promise<approveRequest.Response> {
  return true === connection.simulate
    ? approveRequest.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...approveRequest.METADATA,
          path: approveRequest.path(props),
          status: null,
        },
        props.body,
      );
}
