import { IShoppingMallCategory } from "../../../../../structures/IShoppingMallCategory";

/**
 * Retrieve comprehensive overview statistics for product categories and subcategories.
 *
 * This administrative endpoint provides system-wide category analytics and metrics that help administrators understand the current state of the product catalog organization. The overview includes counts of active categories and subcategories, helping administrators monitor catalog structure and identify areas that may need attention.
 *
 * ## Security Considerations
 *
 * This endpoint is restricted to administrator actors only (admin and superAdmin roles). Regular customers and sellers do not have access to this administrative functionality. The endpoint provides system-wide overview data without exposing sensitive individual records.
 *
 * ## Database Entities
 *
 * The endpoint retrieves statistics from:
 * - shopping_mall_categories: Top-level product categories
 * - shopping_mall_subcategories: Subcategories nested under categories
 * - Both tables support soft-delete functionality with deleted_at timestamp
 *
 * ## Related Operations
 *
 * This overview endpoint complements the detailed category management operations:
 * - GET /admin/categories/:id - Retrieve specific category details
 * - GET /admin/products - List all products with category filtering
 * - GET /admin/categories - Full category list with pagination
 *
 * ## Expected Usage
 *
 * Administrators typically call this endpoint when accessing the categories management dashboard or when needing quick system statistics about the catalog organization structure.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Retrieve aggregate statistics from shopping_mall_categories and shopping_mall_subcategories tables.
 *
 * 1. Query shopping_mall_categories to count:
 *    - Total categories (where deleted_at is null)
 *    - Active categories (categories without soft-delete)
 *
 * 2. Query shopping_mall_subcategories to count:
 *    - Total subcategories (where deleted_at is null)
 *    - Active subcategories (subcategories without soft-delete)
 *
 * 3. Return combined statistics as IAdminShoppingMallCategoryOverview with counts and totals.
 *
 * This is a read-only operation with no database modifications required.
 * @path /shoppingMall/admin/admin/categories/overview
 * @accessor api.functional.shoppingMall.admin.admin.categories.overview
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function overview(
  connection: IConnection,
): Promise<overview.Response> {
  return true === connection.simulate
    ? overview.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...overview.METADATA,
          path: overview.path(),
          status: null,
        },
      );
}
export namespace overview {
  export type Response = IShoppingMallCategory;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/admin/admin/categories/overview",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/admin/categories/overview";
  export const random = (): IShoppingMallCategory =>
    typia.random<IShoppingMallCategory>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
