import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallOrder } from "../../../../../structures/IShoppingMallOrder";

export * as cancel from "./cancel/index";

/**
 * Force refund an entire order by updating all order items to 'refunded' status and restoring inventory quantities.
 *
 * This endpoint allows administrators to manually refund an entire order when customers request refunds or when sellers cannot process refunds. All order items are updated to 'refunded' status, inventory is restored for each item, and refund payment records are created.
 *
 * **Authorization:** Administrator role required.
 *
 * **Related Operations:**
 * - `GET /orders/{orderId}` - View order details before refund
 * - `POST /orders/{orderId}/items/{itemId}/force-refund` - Force refund single order item
 * - `POST /api/customers/orders/:orderId/items/:itemId/refund-request` - Customer-initiated refund request
 *
 * @param props.connection
 * @param props.orderId Order ID to refund
 * @param props.body Refund request information including reason for administrator action
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Process order refund by updating all order items and restoring inventory.
 *
 * 1. Retrieve order with all items using orderId path parameter
 * 2. Validate order can be refunded (must be 'paid' or 'shipped' status)
 * 3. Update each order item status to 'refunded'
 * 4. Restore inventory quantities by creating positive inventory records
 * 5. Create refund payment records for each refunded item
 * 6. Update order status to 'refunded' (all items refunded)
 * 7. Log administrator action with timestamp and reason
 * 8. Return updated order details
 * @path /shoppingMall/admin/orders/:orderId/force-actions/refund
 * @accessor api.functional.shoppingMall.admin.orders.force_actions.refund
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function refund(
  connection: IConnection,
  props: refund.Props,
): Promise<refund.Response> {
  return true === connection.simulate
    ? refund.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...refund.METADATA,
          path: refund.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace refund {
  export type Props = {
    /**
     * Order ID to refund
     */
    orderId: string;

    /**
     * Refund request information including reason for administrator action
     */
    body: IShoppingMallOrder.IRequest;
  };
  export type Body = IShoppingMallOrder.IRequest;
  export type Response = IShoppingMallOrder;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/admin/orders/:orderId/force-actions/refund",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/admin/orders/${encodeURIComponent(props.orderId ?? "null")}/force-actions/refund`;
  export const random = (): IShoppingMallOrder =>
    typia.random<IShoppingMallOrder>();
  export const simulate = (
    connection: IConnection,
    props: refund.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: refund.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderId")(() => typia.assert(props.orderId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
