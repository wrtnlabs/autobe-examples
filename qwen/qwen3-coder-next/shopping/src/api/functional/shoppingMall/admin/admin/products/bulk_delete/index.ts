export async function bulkDelete(
  connection: IConnection,
  props: bulkDelete.Props,
): Promise<bulkDelete.Response> {
  return true === connection.simulate
    ? bulkDelete.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...bulkDelete.METADATA,
          path: bulkDelete.path(),
          status: null,
        },
        props.body,
      );
}
