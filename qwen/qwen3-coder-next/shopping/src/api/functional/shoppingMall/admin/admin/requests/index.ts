/**
 * Reject an administrator promotion request with a specified rejection reason.
 *
 * This operation allows administrators to formally reject administrator promotion requests submitted by users. When an administrator rejects a request, the system records the rejection reason and updates the request status accordingly.
 *
 * The rejection provides clear feedback to the requesting user about why their administrator promotion was denied, allowing them to understand the decision and potentially resubmit a new request with improved justification.
 *
 * **Authorization:** Administrators with appropriate privileges can reject administrator requests. Super administrators have full rejection authority.
 *
 * **Related Operations:**
 * - `GET /admin/admin-requests` - List pending administrator requests for review
 * - `PUT /admin/admin-requests/{requestId}/approve` - Approve administrator request
 * - `POST /api/administrators` - Submit new administrator promotion request
 *
 * @param props.connection
 * @param props.requestId Administrator promotion request ID to reject
 * @param props.body Rejection request with reason for declining administrator promotion
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Process administrator request rejection with validation and audit logging.
 *
 * 1. Validate request exists and is in pending status
 * 2. Validate administrative authorization (regular or super administrator)
 * 3. Validate rejection reason is provided and non-empty
 * 4. Update request status to rejected
 * 5. Create rejection log entry with timestamp and rejecting administrator
 * 6. Send notification to requesting user with rejection reason
 * 7. Return rejection confirmation with updated request details
 *
 * Error handling includes request not found, unauthorized access, invalid status, and missing rejection reason.
 * @path /shoppingMall/admin/admin/requests/:requestId/reject
 * @accessor api.functional.shoppingMall.admin.admin.requests.reject
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
