/**
 * Retrieve a list of administrator promotion/demotion requests.
 *
 * This operation provides comprehensive visibility into all administrator account management requests submitted by customers and sellers who wish to gain administrator privileges. It supports filtering by request status and comprehensive pagination for large result sets.
 *
 * ## Security and Authorization
 *
 * Only authenticated users with administrator privileges can access this endpoint. The operation enforces role-based access control to ensure that only authorized administrators can view and manage administrator requests.
 *
 * ## Request Status Workflow
 *
 * Administrator requests go through a well-defined status workflow:
 *
 * 1. **Pending**: Request submitted, awaiting administrator review
 * 2. **Approved**: Request approved by super administrator
 * 3. **Rejected**: Request rejected by super administrator with rejection reason
 *
 * The status workflow ensures proper audit trail and accountability for all administrator privilege changes.
 *
 * ## Response Structure
 *
 * The response includes comprehensive information about each request:
 *
 * - Request identifier and status
 * - User information (email, display name)
 * - Request timestamp
 * - Reason provided by the user
 * - Response details (if approved or rejected)
 * - Timestamps for all status changes
 *
 * ## Related Operations
 *
 * This operation works in conjunction with other administrator management endpoints:
 *
 * - POST /admin/requests - Submit administrator request (for customers/sellers)
 * - PUT /admin/requests/{requestId}/approve - Approve administrator request (for super administrators)
 * - PUT /admin/requests/{requestId}/reject - Reject administrator request (for super administrators)
 * - GET /admin/administrators - List all administrators
 *
 * ## Use Cases
 *
 * This endpoint is primarily used by:
 *
 * - Super administrators reviewing pending administrator requests
 * - Regular administrators monitoring administrator activity
 * - System auditors tracking administrator privilege changes
 *
 * The comprehensive pagination and filtering support enables efficient handling of large request volumes in production environments.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query shopping_mall_admin_requests table with pagination and filtering.
 * Apply status filters (pending, approved, rejected) and date range filters.
 * Include user information (email, name) from related tables.
 * Return cursor-based pagination for large result sets.
 * Support sorting by created_at, updated_at, and status.
 * @path /shoppingMall/admin/admin/requests
 * @accessor api.functional.shoppingMall.admin.admin.requests.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
