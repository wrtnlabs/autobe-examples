import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallProductReviewRating } from "../../../../structures/IShoppingMallProductReviewRating";

/**
 * Retrieve the average rating and review count for a specific product.
 *
 * This endpoint provides product rating metrics that help customers evaluate product quality before making purchase decisions. The average rating is calculated from customer reviews and displayed as a decimal value (e.g., 4.5 stars) on a 1.0-5.0 scale.
 *
 * ## Rating System Overview
 *
 * The shopping mall platform implements a comprehensive product rating system where customers can rate products on a 5-star scale after completing purchases. These ratings are aggregated and stored in the product_review_ratings table to provide quick access to rating information without real-time calculations.
 *
 * ## Business Purpose
 *
 * - **Customer Decision Support**: Helps potential buyers evaluate product quality before purchase
 * - **Product Visibility**: Higher-rated products may receive preferential placement in search results
 * - **Seller Feedback**: Provides sellers with aggregate feedback on their products
 * - **Quality Assurance**: Enables identification of products that may need quality improvements
 *
 * ## Rating Calculation Methodology
 *
 * - Average ratings are calculated from all non-deleted customer reviews for each product
 * - The calculation excludes reviews that have been soft-deleted by their authors
 * - Ratings are updated automatically when reviews are added, edited, or removed
 * - The system maintains a running average for efficient retrieval
 * - The rating table itself has a deleted_at field for soft deletion of the rating record
 *
 * ## Display Considerations
 *
 * - Average ratings are typically displayed alongside product listings in search results
 * - Product detail pages show the complete rating breakdown with star visualizations
 * - Sellers can view their products' average ratings in their dashboard
 * - Administrators can review overall rating patterns across their platform
 *
 * ## Related Endpoints
 *
 * - `GET /products/{id}/reviews` - Retrieve individual customer reviews for detailed feedback
 * - `GET /customers/me/products/{productId}/reviews` - Check if customer has already reviewed the product
 * - `GET /products` - Search and filter products with rating-based sorting options
 *
 * ## Performance Optimization
 *
 * This endpoint queries a pre-aggregated table rather than calculating ratings in real-time, ensuring fast response times even with large numbers of reviews. The database maintains the rating metrics automatically through triggers or scheduled updates.
 *
 * @param props.connection
 * @param props.productId The unique identifier of the product to retrieve rating information for.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query the shopping_mall_product_review_ratings table to retrieve average_rating and review_count for the specified product_id. Use the path parameter productId to filter the specific product rating record. Return the rating metrics as a JSON response. This is a simple lookup operation that accesses pre-aggregated rating data.
 * @path /shoppingMall/products/:productId/rating
 * @accessor api.functional.shoppingMall.products.rating.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * The unique identifier of the product to retrieve rating information for.
     */
    productId: string;
  };
  export type Response = IShoppingMallProductReviewRating;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/products/:productId/rating",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/products/${encodeURIComponent(props.productId ?? "null")}/rating`;
  export const random = (): IShoppingMallProductReviewRating =>
    typia.random<IShoppingMallProductReviewRating>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
