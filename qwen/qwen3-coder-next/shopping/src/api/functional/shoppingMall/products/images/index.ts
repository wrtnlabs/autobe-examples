import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IPageIShoppingMallProductImage } from "../../../../structures/IPageIShoppingMallProductImage";
import { IShoppingMallProductImage } from "../../../../structures/IShoppingMallProductImage";

/**
 * Reorder images for a specific product.
 *
 * This operation allows sellers to change the display order of their product images. The first image (display_order: 1) is typically used as the main product thumbnail in listings and product detail pages.
 *
 * Sellers must have ownership of the product to reorder its images. This operation updates the display_order values for the specified images, which affects the visual presentation order throughout the platform.
 *
 * @param props.connection
 * @param props.productId Target product's UUID identifier
 * @param props.body Image order update payload with new display order mappings
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Update display_order values for product images. Validate seller ownership of product before allowing reordering. Update all specified image order values atomically. Return complete updated image list after reordering.
 * @path /shoppingMall/products/:productId/images
 * @accessor api.functional.shoppingMall.products.images.reorder
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function reorder(
  connection: IConnection,
  props: reorder.Props,
): Promise<reorder.Response> {
  return true === connection.simulate
    ? reorder.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...reorder.METADATA,
          path: reorder.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace reorder {
  export type Props = {
    /**
     * Target product's UUID identifier
     */
    productId: string;

    /**
     * Image order update payload with new display order mappings
     */
    body: IShoppingMallProductImage.IOrder;
  };
  export type Body = IShoppingMallProductImage.IOrder;
  export type Response = IPageIShoppingMallProductImage;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/products/:productId/images",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/products/${encodeURIComponent(props.productId ?? "null")}/images`;
  export const random = (): IPageIShoppingMallProductImage =>
    typia.random<IPageIShoppingMallProductImage>();
  export const simulate = (
    connection: IConnection,
    props: reorder.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: reorder.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
