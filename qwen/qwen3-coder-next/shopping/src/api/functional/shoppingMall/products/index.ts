/**
 * Retrieve detailed information about a specific product including all variants, images, and seller information.
 *
 * This endpoint provides comprehensive product details for the product detail page, including all available variants with their pricing and stock levels, product images in display order, and the seller's shop information.
 *
 * The product information includes complete description, category hierarchy, pricing details, and current availability status. Variant information shows all available options with their specific prices and stock quantities.
 *
 * This API operation is designed for customers who want to view detailed product information before making a purchase decision.
 *
 * @param props.connection
 * @param props.productId Target product's unique identifier
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query shopping_mall_products table by ID to retrieve product details.
 * Join with shopping_mall_product_variants for all variants.
 * Join with shopping_mall_product_images for images ordered by display order.
 * Join with shopping_mall_sellers for seller profile information.
 * Return complete product object with nested variants and images arrays.
 * Handle soft delete by filtering out products with deleted_at timestamp.
 * Use UUID-based lookup for productId parameter.
 * @path /shoppingMall/products/:productId
 * @accessor api.functional.shoppingMall.products.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Target product's unique identifier
     */
    productId: string;
  };
  export type Response = IShoppingMallProduct;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/products/:productId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/products/${encodeURIComponent(props.productId ?? "null")}`;
  export const random = (): IShoppingMallProduct =>
    typia.random<IShoppingMallProduct>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

