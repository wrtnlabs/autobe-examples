/**
 * Update an existing customer review for a product.
 *
 * This endpoint allows customers to modify their previously submitted reviews. Reviews can only be updated if they belong to the customer and have not been deleted. The system maintains an immutable audit trail by creating review snapshots whenever reviews are edited.
 *
 * **Authorization**: Customer-only endpoint. Customers can only update their own reviews.
 *
 * **Business Rules**:
 * - Reviews can only be updated by the customer who wrote them
 * - Reviews must be for products that have been delivered (order item status must be "delivered")
 * - Rating must be between 1-5 stars
 * - Content cannot exceed 2000 characters
 * - The system creates a review snapshot preserving the previous state for audit purposes
 *
 * **Related Operations**:
 * - POST /customers/me/products/{productId}/reviews - Create a new review
 * - GET /customers/me/products/{productId}/reviews/{reviewId}/snapshots - View review history
 * - DELETE /customers/me/products/{productId}/reviews/{reviewId} - Delete a review
 *
 * @param props.connection
 * @param props.productId Target product's unique identifier
 * @param props.body Review update information including optional rating and content
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Update existing review for product.
 * Query shopping_mall_reviews table by review ID.
 * Verify customer ownership and that order item status is "delivered".
 * If review exists and is owned by customer, create review snapshot preserving previous state.
 * Update review rating (1-5) and/or content fields if provided.
 * Return updated review record.
 * Throw error if review not found or customer doesn't own it.
 * @path /shoppingMall/products/:productId/reviews
 * @accessor api.functional.shoppingMall.products.reviews.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Target product's unique identifier
     */
    productId: string;

    /**
     * Review update information including optional rating and content
     */
    body: IShoppingMallReview.IUpdate;
  };
  export type Body = IShoppingMallReview.IUpdate;
  export type Response = IShoppingMallReview;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/products/:productId/reviews",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/products/${encodeURIComponent(props.productId ?? "null")}/reviews`;
  export const random = (): IShoppingMallReview =>
    typia.random<IShoppingMallReview>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
