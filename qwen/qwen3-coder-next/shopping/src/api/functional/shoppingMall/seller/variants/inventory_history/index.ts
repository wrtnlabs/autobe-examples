export async function inventoryHistory(
  connection: IConnection,
  props: inventoryHistory.Props,
): Promise<inventoryHistory.Response> {
  return true === connection.simulate
    ? inventoryHistory.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...inventoryHistory.METADATA,
          path: inventoryHistory.path(props),
          status: null,
        },
      );
}
export namespace inventoryHistory {
  export type Props = {
    /**
     * The unique identifier of the product variant whose inventory history should be retrieved. This is the primary key from the shopping_mall_product_variants table.
     */
    variantId: string & tags.Format<"uuid">;
  };
  export type Response = IPageIShoppingMallInventoryHistory;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/seller/variants/:variantId/inventory-history",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/seller/variants/${encodeURIComponent(props.variantId ?? "null")}/inventory-history`;
  export const random = (): IPageIShoppingMallInventoryHistory =>
    typia.random<IPageIShoppingMallInventoryHistory>();
  export const simulate = (
    connection: IConnection,
    props: inventoryHistory.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: inventoryHistory.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("variantId")(() => typia.assert(props.variantId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
