import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallShipment } from "../../../../../structures/IShoppingMallShipment";

/**
 * Add order items to an existing shipment
 *
 * This operation allows sellers to add additional order items to a shipment that has already been created. This flexibility supports various shipping scenarios where sellers may need to:
 *
 * - Bundle multiple order items into a single shipment
 * - Add items to an existing shipment if they were missed initially
 * - Split orders across multiple shipments as needed
 * - Manage partial shipments for complex orders
 *
 * The shipment must be in a state that allows item additions (typically before items are shipped). This operation supports the seller's control over their own shipping processes while maintaining the relationship between shipments and order items.
 *
 * ### Security and Authorization
 *
 * Only the seller who owns the order items being added can perform this operation. The system validates:
 *
 * - The shipment belongs to the seller attempting the operation
 * - The order items being added belong to the same seller
 * - The shipment is in an appropriate state for item additions
 *
 * ### Related Operations
 *
 * - `GET /shipments/{shipmentId}` - Retrieve shipment details including current items
 * - `GET /shipments` - List shipments for the seller
 * - `PUT /shipments/{shipmentId}` - Update shipment information (tracking, status)
 * - `DELETE /shipments/{shipmentId}` - Cancel a shipment
 *
 * @param props.connection
 * @param props.shipmentId Shipment ID to add items to
 * @param props.body List of order item IDs to add to the shipment
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Add order items to an existing shipment by creating records in the shopping_mall_shipment_items junction table.
 * 1. Validate shipment exists and belongs to the seller
 * 2. Validate each order item exists and belongs to the same seller
 * 3. Validate shipment state allows item additions (not already shipped or delivered)
 * 4. Create shipment_item records for each order item
 * 5. Update shipment's updated_at timestamp
 * 6. Return updated shipment with all items
 * @path /shoppingMall/seller/shipments/:shipmentId/items
 * @accessor api.functional.shoppingMall.seller.shipments.items.addItems
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function addItems(
  connection: IConnection,
  props: addItems.Props,
): Promise<addItems.Response> {
  return true === connection.simulate
    ? addItems.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...addItems.METADATA,
          path: addItems.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace addItems {
  export type Props = {
    /**
     * Shipment ID to add items to
     */
    shipmentId: string;

    /**
     * List of order item IDs to add to the shipment
     */
    body: IShoppingMallShipment.ICreateItem;
  };
  export type Body = IShoppingMallShipment.ICreateItem;
  export type Response = IShoppingMallShipment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/seller/shipments/:shipmentId/items",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/seller/shipments/${encodeURIComponent(props.shipmentId ?? "null")}/items`;
  export const random = (): IShoppingMallShipment.ISummary =>
    typia.random<IShoppingMallShipment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: addItems.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: addItems.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shipmentId")(() => typia.assert(props.shipmentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
