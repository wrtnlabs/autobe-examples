/**
 * Retrieve inventory history records for a specific product variant.
 *
 * This operation provides a complete audit trail of all inventory transactions for a specified product variant. The history includes restocking, sales, adjustments, cancellations, and refunds with detailed information about each transaction including quantity changes, reasons, and timestamps.
 *
 * The operation returns a paginated list of inventory history records sorted chronologically with newest first, allowing users to track the complete inventory movement history for the specified variant.
 *
 * @param props.connection
 * @param props.variantId Target product variant's ID. References shopping_mall_product_variants.id.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Query inventory_histories table for the specified variant ID.
 * Filter records where shopping_mall_product_variant_id equals the path parameter.
 * Order results by created_at descending (newest first).
 * Apply pagination with configurable page and limit parameters.
 * Return paginated result with total count and data array.
 * @path /shoppingMall/seller/inventory/history/:variantId
 * @accessor api.functional.shoppingMall.seller.inventory.history.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Target product variant's ID. References shopping_mall_product_variants.id.
     */
    variantId: string;
  };
  export type Response = IPageIShoppingMallInventoryHistory;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/seller/inventory/history/:variantId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/seller/inventory/history/${encodeURIComponent(props.variantId ?? "null")}`;
  export const random = (): IPageIShoppingMallInventoryHistory =>
    typia.random<IPageIShoppingMallInventoryHistory>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("variantId")(() => typia.assert(props.variantId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
