import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";

import { IShoppingMallDeliveryAutoConfirmation } from "../../../../../structures/IShoppingMallDeliveryAutoConfirmation";

/**
 * Creates an automatic delivery confirmation record for a shipment when the customer does not manually confirm delivery within the 14-day window.
 *
 * This endpoint is called by the system's automated job that processes shipments which have not been manually confirmed by customers. When a customer receives a shipment, they have 14 days to confirm receipt. If they do not confirm within this period, the system automatically creates a delivery confirmation record to finalize the delivery status and enable features like review writing.
 *
 * The automatic confirmation process:
 * - Runs as a daily batch job at 02:00 UTC
 * - Identifies shipments with status "shipped" that were created 14+ days ago
 * - Verifies no manual confirmation exists for those shipments
 * - Creates automatic confirmation records with the timestamp of day 14
 * - Updates all order items in the shipment to "delivered" status
 *
 * Security considerations:
 * - Only system-initiated (internal service user)
 * - Cannot override existing manual confirmations
 * - Immutable audit trail for delivery confirmation timing
 *
 * Relationship to related operations:
 * - `GET /shipments/{shipmentId}/auto-confirmations` (not yet designed) - View existing automatic confirmations
 * - `GET /orders/{orderId}/items` - View order items that are now delivered
 * - `GET /products/{productId}/reviews` - Customers can now write reviews after automatic delivery confirmation
 *
 * @param props.connection
 * @param props.shipmentId Shipment ID for automatic delivery confirmation
 * @param props.body Automatic delivery confirmation creation request
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Create automatic delivery confirmation record in shopping_mall_delivery_auto_confirmations table.
 *
 * 1. Validate shipment exists and has status 'shipped' or 'in_transit'
 * 2. Verify no manual delivery confirmation exists for this shipment
 * 3. Create delivery_auto_confirmation record with:
 *    - shopping_mall_shipment_id (from path parameter)
 *    - confirmed_at = CURRENT_TIMESTAMP (UTC) or day 14 timestamp
 *    - auto_confirmed_by = 'system_job'
 * 4. Update related shipment items status to 'delivered'
 * 5. Update parent order status based on all items
 * 6. Return created confirmation record
 *
 * Business rules:
 * - Cannot create if manual confirmation already exists
 * - Only system process can call this endpoint
 * - Creates immutable audit trail for delivery status
 * - Updates all related order items to 'delivered' status
 * @path /shoppingMall/seller/shipments/:shipmentId/auto-confirmations
 * @accessor api.functional.shoppingMall.seller.shipments.auto_confirmations.autoConfirm
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function autoConfirm(
  connection: IConnection,
  props: autoConfirm.Props,
): Promise<autoConfirm.Response> {
  return true === connection.simulate
    ? autoConfirm.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...autoConfirm.METADATA,
          path: autoConfirm.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace autoConfirm {
  export type Props = {
    /**
     * Shipment ID for automatic delivery confirmation
     */
    shipmentId: string & tags.Format<"uuid">;

    /**
     * Automatic delivery confirmation creation request
     */
    body: IShoppingMallDeliveryAutoConfirmation.ICreate;
  };
  export type Body = IShoppingMallDeliveryAutoConfirmation.ICreate;
  export type Response = IShoppingMallDeliveryAutoConfirmation;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/seller/shipments/:shipmentId/auto-confirmations",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/seller/shipments/${encodeURIComponent(props.shipmentId ?? "null")}/auto-confirmations`;
  export const random = (): IShoppingMallDeliveryAutoConfirmation =>
    typia.random<IShoppingMallDeliveryAutoConfirmation>();
  export const simulate = (
    connection: IConnection,
    props: autoConfirm.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: autoConfirm.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shipmentId")(() => typia.assert(props.shipmentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
