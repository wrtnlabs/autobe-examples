import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallSellerPasswordResetRequest } from "../../../../structures/IShoppingMallSellerPasswordResetRequest";
import { IShoppingMallSellerPasswordResetRequestResponse } from "../../../../structures/IShoppingMallSellerPasswordResetRequestResponse";

/**
 * Initiate seller password reset request
 *
 * This endpoint allows sellers to request a password reset for their account. When a seller forgets their password, they can submit their email address to receive a password reset link via email.
 *
 * The system validates the email address and creates a password reset token in the shopping_mall_seller_password_resets table. A reset link containing the token is then sent to the seller's registered email address.
 *
 * This operation is part of the seller authentication workflow and supports password recovery for sellers who have forgotten their current password.
 *
 * @param props.connection
 * @param props.body Password reset request data including seller email address
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Process password reset request for seller accounts.
 *
 * 1. Validate email format and check if seller exists in shopping_mall_sellers table
 * 2. Create a new record in shopping_mall_seller_password_resets table with:
 *    - Unique token (UUID-based)
 *    - Expiration timestamp (2 hours from creation)
 *    - Timestamps for created_at and updated_at
 * 3. Generate password reset URL with token
 * 4. Send email with reset link containing the token
 * 5. Return success response with reset request ID
 *
 * This is an idempotent operation - multiple requests for the same email will create multiple reset tokens but each token can only be used once.
 * If seller doesn't exist, still return success to prevent email enumeration attacks.
 * The reset token expires after 2 hours for security purposes.
 * @path /shoppingMall/seller/password-resets
 * @accessor api.functional.shoppingMall.seller.password_resets.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<requestPasswordReset.Response> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestPasswordReset {
  export type Props = {
    /**
     * Password reset request data including seller email address
     */
    body: IShoppingMallSellerPasswordResetRequest;
  };
  export type Body = IShoppingMallSellerPasswordResetRequest;
  export type Response = IShoppingMallSellerPasswordResetRequestResponse;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/seller/password-resets",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/seller/password-resets";
  export const random = (): IShoppingMallSellerPasswordResetRequestResponse =>
    typia.random<IShoppingMallSellerPasswordResetRequestResponse>();
  export const simulate = (
    connection: IConnection,
    props: requestPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
