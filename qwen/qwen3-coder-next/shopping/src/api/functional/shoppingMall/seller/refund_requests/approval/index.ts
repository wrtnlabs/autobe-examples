/**
 * Approve a refund request by updating its status from pending to approved.
 *
 * This operation allows sellers to approve customer refund requests for delivered items. When approved, the system restores stock quantities and updates the order item status to "refunded".
 *
 * Security considerations:
 * - Only the seller associated with the order item can approve the refund request
 * - The request must be in "pending" status
 * - All status changes are logged for audit trail purposes
 *
 * This operation relates to:
 * - GET /refund-requests/{requestId} - Retrieve refund request details
 * - PATCH /refund-requests/{requestId}/rejection - Reject the refund request
 *
 * @param props.connection
 * @param props.requestId The unique identifier of the refund request to approve
 * @param props.body Approval action for the refund request
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Approve a refund request by updating its status from pending to approved.
 *
 * Implementation steps:
 *
 * 1. Validate the refund request exists and is in "pending" status
 * 2. Verify the requesting seller is the seller associated with the order item
 * 3. Update the refund request status to "approved"
 * 4. Create a refund request status log entry (old_status: "pending", new_status: "approved")
 * 5. Restore the stock quantity for the purchased variant
 * 6. Create an inventory history record with reason "refund"
 * 7. Initiate refund transaction through payment gateway
 * 8. Update the order item status to "refunded"
 * 9. Update the order status calculation
 * 10. Send notification to customer about approved refund
 * 11. Return the updated refund request with new status
 *
 * Error handling:
 * - 404: Refund request not found
 * - 403: Seller not authorized to approve this refund request
 * - 409: Refund request is already approved/rejected
 * - 422: Refund amount exceeds original payment amount
 * - 500: Payment gateway refund processing failed
 *
 * This operation is the counter-operation to rejection and should only be callable by the seller associated with the order item being refunded.
 * @path /shoppingMall/seller/refund-requests/:requestId/approval
 * @accessor api.functional.shoppingMall.seller.refund_requests.approval.approve
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function approve(
  connection: IConnection,
  props: approve.Props,
): Promise<approve.Response> {
  return true === connection.simulate
    ? approve.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...approve.METADATA,
          path: approve.path(props),
          status: null,
        },
        props.body,
      );
}
