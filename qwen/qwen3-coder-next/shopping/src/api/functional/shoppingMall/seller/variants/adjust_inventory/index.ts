/**
 * Adjust inventory stock quantity for a product variant.
 *
 * This operation allows sellers to manually adjust inventory quantities through positive restocking or negative deductions. The system records each adjustment as an inventory history entry with appropriate reason codes and timestamps.
 *
 * Security and Authorization:
 * - Only the seller who owns the variant can perform adjustments
 * - System validates seller ownership before processing
 * - All adjustments require a documented reason
 *
 * Stock Level Validation:
 * - Negative adjustments cannot cause stock to go below zero
 * - If adjustment would result in negative stock, operation is blocked
 * - Error message must specify current stock level and required adjustment
 *
 * Reason Codes:
 * - 'restock': Positive quantity for supplier shipments or returns from customers
 * - 'adjustment': General inventory corrections (counting errors, data corrections)
 * - 'loss': Negative quantity for damage, theft, or unaccounted losses
 * - 'breakage': Negative quantity for damaged goods
 *
 * Related Operations:
 * - GET /variants/{variantId}/inventory-history to view complete adjustment history
 * - GET /sellers/products to list all seller variants for selection
 *
 * @param props.connection
 * @param props.variantId Target product variant ID (UUID)
 * @param props.body Stock quantity adjustment request
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Execute inventory adjustment for target product variant.
 *
 * 1. Load target variant by ID and verify seller ownership
 * 2. Validate request quantity is a valid integer
 * 3. Calculate new stock quantity (current + quantity_change)
 * 4. If new stock would be negative, reject with error showing current stock
 * 5. Create inventory history record with:
 *    - variant_id: from path parameter
 *    - quantity_change: from request body
 *    - reason: from request body ('adjustment' or 'loss')
 *    - seller_id: authenticated seller ID
 *    - metadata: optional JSON notes
 * 6. Update variant stock_quantity field with new calculation
 * 7. Return created inventory history record
 * @path /shoppingMall/seller/variants/:variantId/adjust-inventory
 * @accessor api.functional.shoppingMall.seller.variants.adjust_inventory.adjustInventory
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function adjustInventory(
  connection: IConnection,
  props: adjustInventory.Props,
): Promise<adjustInventory.Response> {
  return true === connection.simulate
    ? adjustInventory.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...adjustInventory.METADATA,
          path: adjustInventory.path(props),
          status: null,
        },
        props.body,
      );
}
