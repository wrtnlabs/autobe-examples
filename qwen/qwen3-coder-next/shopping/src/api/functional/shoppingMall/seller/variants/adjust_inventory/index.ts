  export const random = (): IShoppingMallInventoryHistory =>
    typia.random<IShoppingMallInventoryHistory>();
  export const simulate = (
    connection: IConnection,
    props: adjustInventory.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: adjustInventory.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("variantId")(() => typia.assert(props.variantId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
