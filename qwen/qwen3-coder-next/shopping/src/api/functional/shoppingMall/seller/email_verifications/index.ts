/**
 * Verify seller email address using a verification token.
 *
 * This endpoint validates email verification tokens that are sent to sellers during the registration process. Sellers receive an email with a verification link containing a unique token. When the seller clicks this link or submits the token through this API, the system validates the token and confirms their email address.
 *
 * The email verification process is a critical security measure that ensures:
 * - Only legitimate email addresses can be used for seller registration
 * - Sellers cannot register with fake or unavailable email addresses
 * - The platform maintains accurate contact information for all sellers
 * - Compliance with anti-spam and email verification regulations
 *
 * After successful email verification, sellers can proceed to complete their registration process and access seller dashboard features once approved by administrators.
 *
 * @param props.connection
 * @param props.body Email verification token from registration email
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Validate seller email verification token and confirm email address.
 * 1. Extract token from request body
 * 2. Look up verification record by token
 * 3. Validate token is not expired
 * 4. Validate token is not already used
 * 5. If valid, mark verification as completed
 * 6. Update seller account status to 'verified'
 * 7. Return success response
 * 8. Handle expired token with appropriate error
 * 9. Handle invalid/used token with appropriate error
 * @path /shoppingMall/seller/email-verifications
 * @accessor api.functional.shoppingMall.seller.email_verifications.verifyEmail
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function verifyEmail(
  connection: IConnection,
  props: verifyEmail.Props,
): Promise<verifyEmail.Response> {
  return true === connection.simulate
    ? verifyEmail.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verifyEmail.METADATA,
          path: verifyEmail.path(),
          status: null,
        },
        props.body,
      );
}
export namespace verifyEmail {
  export type Props = {
    /**
     * Email verification token from registration email
     */
    body: IShoppingMallSellerEmailVerification.ICreate;
  };
  export type Body = IShoppingMallSellerEmailVerification.ICreate;
  export type Response = IShoppingMallSellerEmailVerification;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/seller/email-verifications",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/seller/email-verifications";
  export const random = (): IShoppingMallSellerEmailVerification =>
    typia.random<IShoppingMallSellerEmailVerification>();
  export const simulate = (
    connection: IConnection,
    props: verifyEmail.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: verifyEmail.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
