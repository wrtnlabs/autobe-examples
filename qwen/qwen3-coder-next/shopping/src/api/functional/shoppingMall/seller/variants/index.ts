/**
 * Retrieve historical snapshots of a specific product variant for audit and history tracking.
 *
 * This endpoint provides a complete audit trail showing how a product variant's characteristics have changed over time. Each snapshot captures the variant's SKU code, option values, price override, and stock quantity at the time of the original product editing operation.
 *
 * The snapshots are stored permanently for dispute resolution and audit purposes, preserving the exact state of the variant when it was part of an order or when significant changes occurred.
 *
 * @param props.connection
 * @param props.variantId Target product variant's UUID identifier
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Query shopping_mall_product_variant_snapshots table where product_snapshot_id is derived from variant's product. Join with shopping_mall_product_snapshots to filter by variant's parent product. Order results by created_at descending to show most recent snapshots first. Return paginated list of variant snapshot summaries.
 * @path /shoppingMall/seller/variants/:variantId/snapshots
 * @accessor api.functional.shoppingMall.seller.variants.snapshots
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function snapshots(
  connection: IConnection,
  props: snapshots.Props,
): Promise<snapshots.Response> {
  return true === connection.simulate
    ? snapshots.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...snapshots.METADATA,
          path: snapshots.path(props),
          status: null,
        },
      );
}
export namespace snapshots {
  export type Props = {
    /**
     * Target product variant's UUID identifier
     */
    variantId: string;
  };
  export type Response = IPageIShoppingMallProductVariantSnapshot.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/seller/variants/:variantId/snapshots",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/seller/variants/${encodeURIComponent(props.variantId ?? "null")}/snapshots`;
  export const random = (): IPageIShoppingMallProductVariantSnapshot.ISummary =>
    typia.random<IPageIShoppingMallProductVariantSnapshot.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: snapshots.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: snapshots.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("variantId")(() => typia.assert(props.variantId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

