/**
 * Restock inventory for a specific product variant.
 *
 * This endpoint allows sellers to add stock to their product variants. When restocking is completed, a positive inventory history record is created and the current stock quantity is increased.
 *
 * Security considerations:
 * - Only authenticated sellers can restock their own variants
 * - Sellers cannot restock variants from other sellers
 * - The system validates that the seller owns the product variant
 *
 * The restocking operation creates an immutable audit trail through inventory history records that track:
 * - Exact quantity added
 * - Reason for restocking (e.g., "supplier shipment", "return from customer")
 * - Timestamp of the transaction
 * - Seller who performed the operation
 * - Associated product variant
 *
 * Related operations:
 * - GET /inventory/variants/{variantId}/history - Retrieve inventory history for audit purposes
 * - POST /inventory/variants/{variantId}/adjust - For inventory adjustments (not restocking)
 *
 * @param props.connection
 * @param props.variantId Product variant ID to restock
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Execute inventory restocking operation for product variant. Query product variant by ID and verify seller ownership. Create inventory history record with positive quantity change. Update variant stock quantity in shopping_mall_variant_stocks table. Return success response with updated stock information.
 * @path /shoppingMall/seller/inventory/restock/:variantId
 * @accessor api.functional.shoppingMall.seller.inventory.restock
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function restock(
  connection: IConnection,
  props: restock.Props,
): Promise<restock.Response> {
  return true === connection.simulate
    ? restock.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...restock.METADATA,
          path: restock.path(props),
          status: null,
        },
      );
}
export namespace restock {
  export type Props = {
    /**
     * Product variant ID to restock
     */
    variantId: string;
  };
  export type Response = IShoppingMallInventoryHistory.IInvert;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/seller/inventory/restock/:variantId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/seller/inventory/restock/${encodeURIComponent(props.variantId ?? "null")}`;
  export const random = (): IShoppingMallInventoryHistory.IInvert =>
    typia.random<IShoppingMallInventoryHistory.IInvert>();
  export const simulate = (
    connection: IConnection,
    props: restock.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: restock.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("variantId")(() => typia.assert(props.variantId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
