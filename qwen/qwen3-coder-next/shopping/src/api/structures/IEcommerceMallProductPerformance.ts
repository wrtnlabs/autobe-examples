import { tags } from "typia";

export namespace IEcommerceMallProductPerformance {
  /**
   * Product performance summary with aggregated sales, engagement, and review metrics.
   */
  export type ISummary = {
    /**
     * Product unique identifier.
     *
     * @x-autobe-specification Aggregated product identifier. Retrieved from ecommerce_mall_products.id as the primary key for this product performance summary.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Product display name.
     *
     * @x-autobe-specification Aggregated product name. Retrieved from ecommerce_mall_products.name as the product display name.
     */
    name: string;

    /**
     * Product base price.
     *
     * @x-autobe-specification Aggregated product base price. Retrieved from ecommerce_mall_products.base_price as the product base price in currency units.
     */
    base_price: number;

    /**
     * Product availability status.
     *
     * @x-autobe-specification Aggregated product availability. Retrieved from ecommerce_mall_products.is_available as the product availability status.
     */
    is_available: boolean;

    /**
     * Total units sold across all order items for this product.
     *
     * @x-autobe-specification Aggregated SUM of quantities from ecommerce_mall_order_items joined to products. Represents total units sold across all order items for this product.
     */
    total_quantity_sold: number & tags.Type<"int32">;

    /**
     * Total revenue generated by this product.
     *
     * @x-autobe-specification SUM of (order_items.quantity * order_items.product_price) from ecommerce_mall_order_items joined to products. Represents total revenue generated by this product.
     */
    total_revenue: number;

    /**
     * Average customer rating (1-5 stars) for this product.
     *
     * @x-autobe-specification AVG of reviews.rating from ecommerce_mall_reviews joined to products. Null if no reviews exist.
     */
    average_rating: number;

    /**
     * Number of customer reviews for this product.
     *
     * @x-autobe-specification COUNT of non-deleted reviews from ecommerce_mall_reviews joined to products.
     */
    review_count: number & tags.Type<"int32">;

    /**
     * Number of times this product has been viewed.
     *
     * @x-autobe-specification Aggregated view count from tracking system or analytics logs joined to products.
     */
    view_count: number & tags.Type<"int32">;

    /**
     * Number of times this product has been added to customer wishlists.
     *
     * @x-autobe-specification COUNT of wishlist items from ecommerce_mall_wishlist_items joined to products. Number of customers who saved this product to their wishlist.
     */
    wishlist_count: number & tags.Type<"int32">;

    /**
     * Number of times this product is currently in customer shopping carts.
     *
     * @x-autobe-specification COUNT of cart items from ecommerce_mall_cart_items joined to products. Number of active cart occurrences of this product.
     */
    cart_count: number & tags.Type<"int32">;

    /**
     * Product creation timestamp.
     *
     * @x-autobe-specification Aggregated product creation timestamp. Retrieved from ecommerce_mall_products.created_at as when the product was created.
     */
    created_at: string & tags.Format<"date-time">;
  };

  /**
   * Query parameters for filtering product performance analytics results. Supports filtering by seller, category, date ranges, sales metrics, inventory thresholds, and search. Pagination parameters included for result set navigation.
   */
  export type IRequest = {
    /**
     * Seller identifier for filtering performance by specific seller.
     *
     * @x-autobe-specification Filter by seller product ID from JWT context. Used to filter products by the authenticated seller. Maps to ecommerce_mall_products.seller_id.
     */
    seller_id?: (string & tags.Format<"uuid">) | undefined;

    /**
     * Category identifier for filtering performance by product category.
     *
     * @x-autobe-specification Filter by category ID. Used to filter products by category. Maps to ecommerce_mall_products.category_id.
     */
    category_id?: (string & tags.Format<"uuid">) | undefined;

    /**
     * Start date for filtering products by creation time (inclusive).
     *
     * @x-autobe-specification Filter products created on or after this timestamp. Used to filter products by creation time. Maps to ecommerce_mall_products.created_at.
     */
    created_from?: (string & tags.Format<"date-time">) | undefined;

    /**
     * End date for filtering products by creation time (exclusive).
     *
     * @x-autobe-specification Filter products created before this timestamp. Used to filter products by creation time. Maps to ecommerce_mall_products.created_at.
     */
    created_to?: (string & tags.Format<"date-time">) | undefined;

    /**
     * Start date for filtering products by last update time (inclusive).
     *
     * @x-autobe-specification Filter products updated on or after this timestamp. Used to filter products by last update time. Maps to ecommerce_mall_products.updated_at.
     */
    updated_from?: (string & tags.Format<"date-time">) | undefined;

    /**
     * End date for filtering products by last update time (exclusive).
     *
     * @x-autobe-specification Filter products updated before this timestamp. Used to filter products by last update time. Maps to ecommerce_mall_products.updated_at.
     */
    updated_to?: (string & tags.Format<"date-time">) | undefined;

    /**
     * Minimum number of units sold threshold for filtering products.
     *
     * @x-autobe-specification Filter products with sales volume greater than or equal to this value. Aggregated from ecommerce_mall_order_items.
     */
    min_sales?: (number & tags.Type<"int32"> & tags.Minimum<0>) | undefined;

    /**
     * Maximum number of units sold threshold for filtering products.
     *
     * @x-autobe-specification Filter products with sales volume less than or equal to this value. Aggregated from ecommerce_mall_order_items.
     */
    max_sales?: (number & tags.Type<"int32"> & tags.Minimum<0>) | undefined;

    /**
     * Minimum revenue threshold in currency units for filtering products.
     *
     * @x-autobe-specification Filter products with total revenue greater than or equal to this value. Calculated from ecommerce_mall_order_items.
     */
    min_revenue?: (number & tags.Minimum<0>) | undefined;

    /**
     * Maximum revenue threshold in currency units for filtering products.
     *
     * @x-autobe-specification Filter products with total revenue less than or equal to this value. Calculated from ecommerce_mall_order_items.
     */
    max_revenue?: (number & tags.Minimum<0>) | undefined;

    /**
     * Minimum stock level threshold for filtering available products.
     *
     * @x-autobe-specification Filter products with stock quantity greater than or equal to this value. Aggregated from ecommerce_mall_product_variants and inventory records.
     */
    min_stock?: (number & tags.Type<"int32"> & tags.Minimum<0>) | undefined;

    /**
     * Maximum stock level threshold for filtering products.
     *
     * @x-autobe-specification Filter products with stock quantity less than or equal to this value. Aggregated from ecommerce_mall_product_variants and inventory records.
     */
    max_stock?: (number & tags.Type<"int32"> & tags.Minimum<0>) | undefined;

    /**
     * Minimum average rating threshold (1-5 scale) for filtering products.
     *
     * @x-autobe-specification Filter products with average rating greater than or equal to this value (1-5 scale). Aggregated from ecommerce_mall_reviews.
     */
    min_average_rating?:
      | (number & tags.Minimum<0> & tags.Maximum<5>)
      | undefined;

    /**
     * Maximum average rating threshold (1-5 scale) for filtering products.
     *
     * @x-autobe-specification Filter products with average rating less than or equal to this value (1-5 scale). Aggregated from ecommerce_mall_reviews.
     */
    max_average_rating?:
      | (number & tags.Minimum<0> & tags.Maximum<5>)
      | undefined;

    /**
     * Search query string for filtering products by name or description match.
     *
     * @x-autobe-specification Full-text search on product name and description. Uses database full-text search capabilities.
     */
    search?: string | undefined;

    /**
     * Page number for paginated result sets (default: 1).
     *
     * @x-autobe-specification Pagination page number (1-indexed). Used for paginated result sets.
     */
    page?:
      | (number & tags.Type<"int32"> & tags.Default<1> & tags.Minimum<1>)
      | undefined;

    /**
     * Maximum number of records per page (default: 20, max: 100).
     *
     * @x-autobe-specification Maximum number of records per page (max 100). Used for paginated result sets.
     */
    limit?:
      | (number &
          tags.Type<"int32"> &
          tags.Default<20> &
          tags.Minimum<1> &
          tags.Maximum<100>)
      | undefined;
  };
}
