export async function test_api_system_logs_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin authentication
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      name: RandomGenerator.name(),
    } satisfies IShoppingMallAdmin.IJoin,
  });
  // 2. Try to retrieve non-existent log entry
  const nonExistentId = "00000000-0000-0000-0000-000000000000";
  await TestValidator.error("non-existent log not found", async () => {
    await api.functional.shoppingMall.admin.logs.at(adminConnection, {
      logId: nonExistentId,
    });
  });
}
