export async function test_api_shipment_tracking_retrieval_by_customer(
  connection: api.IConnection,
) {
  // 1. Create seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email"> & tags.MinLength<1>>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  // 2. Create customer account
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email"> & tags.MinLength<1>>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      phone: RandomGenerator.mobile(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // 3. Customer creates order (without product needed)
  const order =
    await api.functional.ecommerceMall.customer.orders.create(
      customerConnection,
    );
  typia.assert(order);
  // 4. Seller creates shipment
  const shipment =
    await api.functional.ecommerceMall.seller.orders.shipments.create(
      sellerConnection,
      {
        orderId: order.id,
        body: {
          order_items: [order.order_items[0].id],
          carrier_name: "Kuroneko Yamato",
          tracking_number: "123456789",
        } satisfies IEcommerceMallShipment.ICreate,
      },
    );
  typia.assert(shipment);
  // 5. Customer retrieves tracking
  const tracking =
    await api.functional.ecommerceMall.customer.shipments.tracking.at(
      customerConnection,
      {
        shipmentId: shipment.id,
      },
    );
  typia.assert(tracking);
  // 6. Validate tracking data
  TestValidator.equals(
    "carrier name matches",
    tracking.carrier_name,
    "Kuroneko Yamato",
  );
  TestValidator.equals(
    "tracking number matches",
    tracking.tracking_number,
    "123456789",
  );
}
