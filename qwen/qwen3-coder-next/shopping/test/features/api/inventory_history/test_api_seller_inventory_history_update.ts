export async function test_api_seller_inventory_history_update(
  connection: api.IConnection,
): Promise<void> {
  // Create actor-specific connections
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      name: RandomGenerator.name(),
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shopName: RandomGenerator.name(3),
      shopDescription: RandomGenerator.paragraph({ sentences: 2 }),
    } satisfies IShoppingMallSeller.IJoin,
  });
  // Create a product with inventory for testing
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: typia.random<IShoppingMallProduct.ICreate>(),
    },
  );
  typia.assert(product);
  // Test that invalidEndpoint returns expected result
  const output =
    await api.functional.shoppingMall.seller.inventory.history.invalidEndpoint(
      sellerConnection,
    );
  typia.assert(output);
}
