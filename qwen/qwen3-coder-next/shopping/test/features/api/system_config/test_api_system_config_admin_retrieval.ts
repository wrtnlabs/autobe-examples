export async function test_api_system_config_admin_retrieval(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin authentication setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: typia.random<IShoppingMallAdmin.IJoin>(),
  });
  // 2. Generate a random config ID for testing
  const configId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve non-existent configuration (should succeed with null/undefined)
  // Since the scenario doesn't specify that the config must exist, we test the basic retrieval
  const result = await api.functional.shoppingMall.admin.configs.at(
    adminConnection,
    {
      configId,
    },
  );
  typia.assert(result);
}
