export async function test_api_seller_product_analytics_with_filters(
  connection: api.IConnection,
): Promise<void> {
  // Create seller-specific connection
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {},
  });
  // Call analytics endpoint with minimal valid request
  const result =
    await api.functional.shoppingMall.seller.analytics.products.index(
      sellerConnection,
      {
        body: {},
      },
    );
  typia.assert(result);
  // Validate basic response structure
  TestValidator.predicate("has analytics data", Array.isArray(result.data));
  TestValidator.equals("pagination exists", typeof result.pagination, "object");
}
