export async function test_api_admin_profile_snapshot_retrieval(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin account
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  typia.assert(admin);
  // 2. Admin retrieves a specific profile snapshot
  // Create a random snapshot ID to test retrieval
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  const retrievedSnapshot =
    await api.functional.ecommerceMall.admin.profile.snapshots.at(
      adminConnection,
      { snapshotId },
    );
  typia.assert(retrievedSnapshot);
  // 3. Validate snapshot content
  TestValidator.equals("snapshot ID matches", retrievedSnapshot.id, snapshotId);
}
