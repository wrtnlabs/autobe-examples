export async function test_api_seller_retrieve_pending_shipment(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller registration and login
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 2. Create product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
        is_available: true,
        category_id: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Customer registration and login
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.MinLength<1> & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      phone: RandomGenerator.mobile(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  // 4. Create order
  const order =
    await api.functional.ecommerceMall.customer.orders.create(
      customerConnection,
    );
  typia.assert(order);
  // 5. Verify order has items
  const orderItems = order.order_items;
  if (orderItems.length === 0) {
    throw new Error("Order must have at least one order item");
  }
  // 6. Create shipment without carrier/tracking info
  const shipment =
    await api.functional.ecommerceMall.seller.orders.shipments.create(
      sellerConnection,
      {
        orderId: order.id,
        body: {
          order_items: orderItems.map(
            (item: IEcommerceMallOrderItem.ISummary) => item.id,
          ),
          carrier_name: null,
          tracking_number: null,
        } satisfies IEcommerceMallShipment.ICreate,
      },
    );
  typia.assert(shipment);
  // 7. Retrieve shipment
  const retrievedShipment =
    await api.functional.ecommerceMall.seller.shipments.at(sellerConnection, {
      shipmentId: shipment.id,
    });
  typia.assert(retrievedShipment);
  // 8. Validate shipment details
  TestValidator.equals(
    "carrier name is null",
    retrievedShipment.carrier_name,
    null,
  );
  TestValidator.equals(
    "tracking number is null",
    retrievedShipment.tracking_number,
    null,
  );
  TestValidator.predicate(
    "shipment items present",
    (retrievedShipment.shipment_item_count ?? 0) > 0,
  );
  TestValidator.equals(
    "seller matches",
    retrievedShipment.seller.id,
    product.seller.id,
  );
  TestValidator.equals("order matches", retrievedShipment.order.id, order.id);
}
