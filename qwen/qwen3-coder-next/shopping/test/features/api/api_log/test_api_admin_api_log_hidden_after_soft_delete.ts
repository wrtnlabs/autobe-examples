export async function test_api_admin_api_log_hidden_after_soft_delete(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  // Create an API log entry with non-null deleted_at (soft-deleted)
  const softDeletedLogId = typia.random<string & tags.Format<"uuid">>();
  const logResponse = await api.functional.ecommerceMall.admin.api_logs.at(
    adminConnection,
    {
      logId: softDeletedLogId,
    },
  );
  typia.assert(logResponse);
}
