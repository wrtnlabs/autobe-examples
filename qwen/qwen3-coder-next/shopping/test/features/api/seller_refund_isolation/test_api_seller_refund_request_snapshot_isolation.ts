export async function test_api_seller_refund_request_snapshot_isolation(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller A registers and logs in
  const sellerAConnection: api.IConnection = { host: connection.host };
  const sellerA = await authorize_seller_join(sellerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(sellerA);
  // 2. Seller A creates a product
  const productA = await api.functional.ecommerceMall.seller.products.create(
    sellerAConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 3 }),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<0>
        >(),
        is_available: true,
        category_id: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(productA);
  // 3. Seller B registers and logs in
  const sellerBConnection: api.IConnection = { host: connection.host };
  const sellerB = await authorize_seller_join(sellerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(sellerB);
  // 4. Seller B attempts to access refund request snapshots for a random refund request ID
  // This simulates trying to access a refund request they are not involved in
  const randomRefundRequestId = typia.random<string & tags.Format<"uuid">>();
  // 5. Verify that Seller B cannot access the refund request snapshots
  await TestValidator.error(
    "seller B unauthorized for foreign refund request",
    async () => {
      const result =
        await api.functional.ecommerceMall.seller.refund_requests.snapshots.index(
          sellerBConnection,
          {
            refundRequestId: randomRefundRequestId,
          },
        );
      typia.assert(result);
      // If the API returns empty results instead of an error,
      // verify that the result is indeed empty
      TestValidator.equals(
        "no snapshots for unauthorized request",
        result.data.length,
        0,
      );
    },
  );
}
