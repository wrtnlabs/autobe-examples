export async function test_api_product_deletion_list_admin_view_all(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  // Get product deletion list with empty filter object
  const output =
    await api.functional.ecommerceMall.admin.product_deletions.index(
      adminConnection,
      {
        body: typia.random<IEcommerceMallProductDeletion.IRequest>(),
      },
    );
  typia.assert(output);
  // Validate structure
  TestValidator.equals("has pagination", output.pagination.current, 1);
  TestValidator.equals("has pagination limit", output.pagination.limit, 20);
  TestValidator.predicate("has data array", Array.isArray(output.data));
}
