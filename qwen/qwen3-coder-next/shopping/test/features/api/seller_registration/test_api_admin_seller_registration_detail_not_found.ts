export async function test_api_admin_seller_registration_detail_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin account
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  // 2. Attempt to retrieve non-existent seller registration
  const invalidId = "00000000-0000-0000-0000-000000000000";
  await TestValidator.httpError(
    "should return 404 for non-existent registration",
    404,
    async () =>
      await api.functional.ecommerceMall.admin.seller_registrations.at(
        adminConnection,
        {
          sellerRegistrationId: invalidId,
        },
      ),
  );
}
