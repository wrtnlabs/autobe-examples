export async function test_api_customer_shipment_retrieval_access_denied(
  connection: api.IConnection,
): Promise<void> {
  // Create first customer
  const customer1Connection: api.IConnection = { host: connection.host };
  const customer1 = await authorize_customer_join(customer1Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      name: RandomGenerator.name(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customer1);
  // Create second customer
  const customer2Connection: api.IConnection = { host: connection.host };
  const customer2 = await authorize_customer_join(customer2Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      name: RandomGenerator.name(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customer2);
  // Create a shipment for customer 1 (using a valid shipment ID)
  const shipmentId = "00000000-0000-0000-0000-000000000001";
  // Customer 2 attempts to access customer 1's shipment
  // This should return 403 Forbidden error
  await TestValidator.error(
    "customer 2 cannot access customer 1's shipment",
    async () => {
      await api.functional.shoppingMall.customer.shipments.at(
        customer2Connection,
        {
          shipmentId,
        },
      );
    },
  );
}
