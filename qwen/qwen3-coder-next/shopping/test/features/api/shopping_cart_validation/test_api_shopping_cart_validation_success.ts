export async function test_api_shopping_cart_validation_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create customer and authenticate
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      name: RandomGenerator.name(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(authorized);
  // 2. Prepare valid cart validation request
  const body = {} satisfies IShoppingMallCart.IValidateRequest;
  // 3. Execute cart validation
  const result = await api.functional.shoppingMall.customer.validate(
    customerConnection,
    { body },
  );
  typia.assert(result);
}
