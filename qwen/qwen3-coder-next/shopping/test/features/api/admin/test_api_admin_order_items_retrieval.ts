export async function test_api_admin_order_items_retrieval(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.MinLength<1> & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  // Create customer connection and place an order
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.MinLength<1> & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      phone: RandomGenerator.mobile(),
    },
  });
  // Customer creates an order
  const order =
    await api.functional.ecommerceMall.customer.orders.create(
      customerConnection,
    );
  typia.assert(order);
  // Admin retrieves order items
  const result = await api.functional.ecommerceMall.admin.orders.items.at(
    adminConnection,
    {
      orderId: order.id,
    },
  );
  typia.assert(result);
  // Verify pagination structure
  TestValidator.equals("pagination exists", result.pagination.current, 1);
  TestValidator.predicate("has records", result.pagination.records > 0);
  TestValidator.predicate("has data", result.data.length > 0);
  // Verify order items have required structure
  for (const item of result.data) {
    TestValidator.equals(
      "has product_name",
      typeof item.product_name,
      "string",
    );
    TestValidator.equals("has quantity", item.quantity >= 1, true);
    TestValidator.equals("has product", item.product !== undefined, true);
    TestValidator.equals("has variant", item.variant !== undefined, true);
    TestValidator.equals("has seller", item.seller !== undefined, true);
  }
}