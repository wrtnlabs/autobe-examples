export async function test_api_shopping_mall_price_calculation_complete_breakdown(
  connection: api.IConnection,
): Promise<void> {
  // Authenticate as customer to access protected endpoint
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: typia.random<IShoppingMallCustomer.IJoin>(),
  });
  // Call price calculation endpoint
  const priceCalculation =
    await api.functional.shoppingMall.customer.price_calculation.calculatePrice(
      customerConnection,
    );
  typia.assert(priceCalculation);
  // Verify the response is valid (since DTO has no fields, basic validation is sufficient)
  TestValidator.predicate("price calculation successful", true);
}
