export async function test_api_admin_order_with_multiple_items_and_shipments(
  connection: api.IConnection,
): Promise<void> {
  // Setup: Create admin connection for order retrieval
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  // Customer creates an order (API only accepts connection parameter)
  const order =
    await api.functional.ecommerceMall.customer.orders.create(connection);
  typia.assert(order);
  // Admin retrieves the order details to validate
  const adminOrder = await api.functional.ecommerceMall.admin.orders.at(
    adminConnection,
    {
      orderId: order.id,
    },
  );
  typia.assert(adminOrder);
  // Validate order properties
  TestValidator.equals("order has customer info", !!adminOrder.customer, true);
  TestValidator.equals(
    "order has shipping address",
    !!adminOrder.shippingAddress,
    true,
  );
  TestValidator.predicate(
    "order has order items",
    adminOrder.order_items.length > 0,
  );
  TestValidator.predicate("order has total price", adminOrder.total_price >= 0);
}
