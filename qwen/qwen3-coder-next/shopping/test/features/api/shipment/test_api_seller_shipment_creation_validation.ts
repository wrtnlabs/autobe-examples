export async function test_api_seller_shipment_creation_validation(
  connection: api.IConnection,
): Promise<void> {
  // Create authenticated seller connection
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerToken = await authorize_seller_join(sellerConnection, {
    body: {
      name: RandomGenerator.name(2),
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shopName: RandomGenerator.name(3),
      shopDescription: RandomGenerator.paragraph({ sentences: 2 }),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerToken);
  // Create a new connection with the seller's JWT token
  const sellerAuthConnection: api.IConnection = {
    host: connection.host,
    headers: {
      Authorization: sellerToken.token.access,
    },
  };
}
