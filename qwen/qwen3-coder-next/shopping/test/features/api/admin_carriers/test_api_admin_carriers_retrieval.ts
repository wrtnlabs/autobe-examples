export async function test_api_admin_carriers_retrieval(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Admin1234!" as string & tags.Format<"password">,
    } satisfies IShoppingMallAdmin.IJoin,
  });
  // Call the carriers retrieval endpoint
  const response =
    await api.functional.shoppingMall.admin.carriers.index(adminConnection);
  // Validate complete response structure
  typia.assert<IPageIShoppingMallShippingCarrier.ISummary>(response);
}
