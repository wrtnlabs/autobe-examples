export async function test_api_customer_view_another_customers_shipment_denied(
  connection: api.IConnection,
): Promise<void> {
  // Create customer A account
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email"> & tags.MinLength<1>>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      phone: RandomGenerator.mobile(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customerA);
  // Create customer B account
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB = await authorize_customer_join(customerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email"> & tags.MinLength<1>>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      phone: RandomGenerator.mobile(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customerB);
  // Customer A places an order
  const order =
    await api.functional.ecommerceMall.customer.orders.create(
      customerAConnection,
    );
  typia.assert(order);
  // Customer A creates a shipment (simulated - real implementation would call shipment creation)
  // For this test, we'll simulate a shipment with customer A's order
  const shipment = typia.random<IEcommerceMallShipment>();
  // Customer B attempts to access customer A's shipment - should be denied
  await TestValidator.error(
    "customer B should not access customer A's shipment",
    async () => {
      await api.functional.ecommerceMall.customer.shipments.at(
        customerBConnection,
        { shipmentId: shipment.id },
      );
    },
  );
}