export async function test_api_customer_order_creation_fails_with_invalid_cart(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.MinLength<1> & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      phone: RandomGenerator.mobile(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customer);
  // 2. Create order - endpoint requires authenticated customer
  // This test verifies the basic order creation workflow for authenticated customers
  await api.functional.ecommerceMall.customer.orders.create(customerConnection);
}
