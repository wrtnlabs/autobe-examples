export async function test_api_organization_access_denied_to_other_org(
  connection: api.IConnection,
): Promise<void> {
  // Create first member
  const member1Connection: api.IConnection = { host: connection.host };
  const member1 = await authorize_member_join(member1Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
      display_name: RandomGenerator.name(),
    },
  });
  typia.assert(member1);
  // Create organization for first member
  const org1 = await generate_random_hrm_tracker_member_organizations_create(
    member1Connection,
    {},
  );
  typia.assert(org1);
  // Create second member
  const member2Connection: api.IConnection = { host: connection.host };
  const member2 = await authorize_member_join(member2Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
      display_name: RandomGenerator.name(),
    },
  });
  typia.assert(member2);
  // Create organization for second member
  const org2 = await generate_random_hrm_tracker_member_organizations_create(
    member2Connection,
    {},
  );
  typia.assert(org2);
  // First member attempts to retrieve second member's organization - should fail with 404
  await TestValidator.error("access denied to other org", async () => {
    await api.functional.hrmTracker.member.organizations.at(member1Connection, {
      organizationId: org2.id,
    });
  });
}
