export async function test_api_project_retrieval_nonexistent_id(
  connection: api.IConnection,
): Promise<void> {
  // 1. Join as member to get authentication token
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
      display_name: RandomGenerator.name(),
      phone: null,
    } satisfies IHrmTrackerMember.IJoin,
  });
  typia.assert(member);
  // 2. Attempt to retrieve non-existent project
  const nonExistentProjectId = typia.random<string & tags.Format<"uuid">>();
  // 3. Validate 404 error for non-existent project
  await TestValidator.error("project not found error", async () => {
    await api.functional.hrmTracker.member.projects.at(memberConnection, {
      projectId: nonExistentProjectId,
    });
  });
}
