export async function test_api_invitation_cancellation_success(
  connection: api.IConnection,
): Promise<void> {
  // Create member with employee:manage permission
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
      display_name: RandomGenerator.name(),
    } satisfies IHrmTrackerMember.IJoin,
  });
  // Generate a valid UUID for invitation testing
  const validInvitationId = typia.random<string & tags.Format<"uuid">>();
  // Cancel the invitation (endpoint returns void on success)
  await api.functional.hrmTracker.member.invitations.cancel(memberConnection, {
    invitationId: validInvitationId,
  });
}
