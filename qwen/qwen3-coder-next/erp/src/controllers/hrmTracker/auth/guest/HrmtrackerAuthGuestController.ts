import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerGuest } from "../../../../api/structures/IHrmTrackerGuest";
import { postHrmTrackerAuthGuestJoin } from "../../../../providers/postHrmTrackerAuthGuestJoin";
import { postHrmTrackerAuthGuestRefresh } from "../../../../providers/postHrmTrackerAuthGuestRefresh";

@Controller("/hrmTracker/auth/guest")
export class HrmtrackerAuthGuestController {
  /**
   * Guest registration endpoint allows unauthenticated users to create a guest account. Guests can sign up using email and password, which enables them to later join organizations.
   *
   * **Authentication Flow**: When a guest registers, the system generates a unique device fingerprint if not provided, creates a guest record with encrypted password hash using BCrypt, and sets the email address. The created_at and updated_at timestamps are automatically populated with the current timestamp. The guest then receives authentication tokens to access the system before joining an organization.
   *
   * **Database Integration**: The operation inserts into the hrm_tracker_guests table with the device_fingerprint, email, password_hash, and default timestamps. Upon successful registration, the guest can use the refresh endpoint to renew their session tokens.
   *
   * **Security Considerations**: Passwords must be encrypted using BCrypt before storage. The system validates email format and uniqueness before creating the guest record. The deleted_at field remains NULL for active guest accounts.
   *
   * **Related Operations**: After guest registration, users can use the refresh endpoint to obtain new access tokens. When ready to join an organization, guests can upgrade to member status.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body for guest registration with authentication credentials.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Create new guest account by generating unique device fingerprint or linking to existing guest via email. Encrypt password using BCrypt, store guest record with created_at timestamp. Return authorized response with access and refresh tokens upon successful creation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmTrackerGuest.IJoin,
  ): Promise<IHrmTrackerGuest.IAuthorized> {
    try {
      return await postHrmTrackerAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Token refresh endpoint allows guests to obtain new access tokens using a valid refresh token without re-authenticating. This is essential for maintaining session continuity without requiring users to re-register.
   *
   * **Authentication Flow**: When a guest's access token expires, they can use their refresh token to obtain new tokens. The system validates the refresh token, checks its expiration, and generates new access and refresh token pairs. The guest record's updated_at timestamp is refreshed to reflect the token renewal activity.
   *
   * **Database Integration**: The operation updates the hrm_tracker_guests table's updated_at field with the current timestamp. The refresh token validation ensures that only legitimate token renewals are processed. If the refresh token is invalid or expired, the request is rejected.
   *
   * **Security Considerations**: Refresh tokens must be validated for authenticity and expiration before issuing new tokens. The system maintains token rotation security by invalidating old refresh tokens when new ones are issued. All token operations use secure cryptographic practices.
   *
   * **Related Operations**: This operation complements the join endpoint by providing token lifecycle management. Guests who haven't registered yet should use the join endpoint to create their account first.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body for token refresh containing the current refresh token.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Validate refresh token, check expiration, generate new access and refresh tokens. Update guest record's updated_at timestamp. Return new tokens in IAuthorized response format.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IHrmTrackerGuest.IRefresh,
  ): Promise<IHrmTrackerGuest.IAuthorized> {
    try {
      return await postHrmTrackerAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
