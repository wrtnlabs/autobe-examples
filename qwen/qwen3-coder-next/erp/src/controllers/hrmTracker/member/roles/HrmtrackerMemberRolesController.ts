import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerRole } from "../../../../api/structures/IHrmTrackerRole";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { postHrmTrackerMemberRoles } from "../../../../providers/postHrmTrackerMemberRoles";
import { putHrmTrackerMemberRolesRoleId } from "../../../../providers/putHrmTrackerMemberRolesRoleId";

@Controller("/hrmTracker/member/roles")
export class HrmtrackerMemberRolesController {
  /**
   * Create a new custom role within the organization.
   *
   * This operation allows organization owners and users with employee:manage permission to define a new custom role with a unique name and assign one or more permissions. Custom roles supplement the built-in roles (Owner, Manager, Employee) and enable fine-grained access control tailored to the organization's structure.
   *
   * Each role must have a name that is unique within the organization, cannot reuse built-in role names, and must be assigned at least one permission. The role is created with the current timestamp and no employees are assigned by default. Role assignments to employees are performed via separate role assignment endpoints.
   *
   * Role change events are automatically logged in the activity log with details of who performed the change, when, and what the prior and new roles were.
   *
   * @param connection
   * @param body Role creation parameters including name, optional description, and permission assignments
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new role record with name, description, is_custom=true, and assigned permissions.
   *
   * 1. Validate: organization context from member actor, employee:manage or owner permission.
   * 2. Check: role name must be unique within organization (no duplicate name).
   * 3. Check: role name must not match built-in role names (Owner, Manager, Employee).
   * 4. Validate: at least one permission is assigned.
   * 5. Create role with is_custom=true, is_default=false.
   * 6. Insert into hrm_tracker_role_permissions to assign permissions.
   * 7. Log activity in hrm_tracker_activity_logs with role change details.
   * 8. Return created role with assigned permissions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTrackerRole.ICreate,
  ): Promise<IHrmTrackerRole> {
    try {
      return await postHrmTrackerMemberRoles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing role's configuration within the organization.
   *
   * This endpoint allows organization owners and users with employee:manage permission to modify the name, description, and other properties of a role. You can change a custom role's name, description, and its default status, as well as toggle the is_custom flag for custom roles. This operation performs a full update, so all mutable fields in the request body will overwrite the current values.
   *
   * Security considerations include that only organization owners or users with employee:manage permission can perform this operation. Built-in roles (is_custom=false) are protected from deletion but can be updated. Custom roles can be updated freely. The updated_at timestamp is automatically refreshed.
   *
   * Relationship to underlying entities: This operation modifies the hrm_tracker_roles table, which is organization-scoped and isolated per organization. The updated role affects all employees currently assigned to it through the employee-role mapping table.
   *
   * @param connection
   * @param roleId Target role's unique identifier (UUID)
   * @param body Role update request with new values for mutable fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update hrm_tracker_roles table by id with request body fields. Validate organization ownership via hrm_tracker_employee_roles join. Prevent modifying built-in roles (is_custom=false). Ensure custom role name uniqueness within organization. Update only mutable fields: name, description, is_custom, is_default. Automatically refresh updated_at timestamp. Record activity log entry for role change. Validate no employees assigned before soft-delete operations if needed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":roleId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string,
    @TypedBody()
    body: IHrmTrackerRole.IUpdate,
  ): Promise<IHrmTrackerRole> {
    try {
      return await putHrmTrackerMemberRolesRoleId({
        member,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
