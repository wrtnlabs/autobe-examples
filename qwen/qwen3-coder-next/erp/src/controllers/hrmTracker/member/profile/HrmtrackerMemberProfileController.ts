import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerMember } from "../../../../api/structures/IHrmTrackerMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmTrackerMemberProfile } from "../../../../providers/getHrmTrackerMemberProfile";
import { putHrmTrackerMemberProfile } from "../../../../providers/putHrmTrackerMemberProfile";

@Controller("/hrmTracker/member/profile")
export class HrmtrackerMemberProfileController {
  /**
   * Retrieve the authenticated member's global profile information.
   *
   * This operation returns the complete profile details of the currently authenticated member account. The profile data includes the global display name, avatar image URL, contact phone number, and email verification status that is shared across all organizations the member belongs to.
   *
   * The operation requires valid authentication and returns only the profile data for the authenticated member. No other member profiles can be accessed through this endpoint. This aligns with the business rule that each member has a single global profile consistent across all organizations they belong to.
   *
   * All profile fields returned by this endpoint are part of the global profile shared across organizations, including display name, avatar image reference, phone number, and email verification status. Department, position, and employment type information are organization-specific and are not included in this global profile response.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve the authenticated member's profile from hrm_tracker_members table using the member ID from authentication context.
   * Return the global profile fields: display_name, avatar_url, phone, email_verified, created_at, updated_at, email, status.
   * Do not return password_hash or any sensitive authentication data.
   * Ensure the operation uses the authenticated member's ID derived from the security context, not a path parameter.
   * Return 404 if the member account is soft-deleted (deleted_at is not null).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmTrackerMember> {
    try {
      return await getHrmTrackerMemberProfile({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated member's global profile information.
   *
   * This endpoint allows members to update their own profile data, which includes their display name, avatar image URL, and contact phone number. The profile is global and shared across all organizations the member belongs to.
   *
   * Only the authenticated member can update their own profile. Members cannot update other users' profile information. The display name must be provided and should be appropriate for organizational use. The avatar URL should point to an accessible image resource. The phone number is optional but should follow standard formatting if provided.
   *
   * Profile updates are not tracked in activity logs - changes to profile information do not generate audit records according to business rules. The global profile consistency rule ensures that profile changes are immediately visible across all organizational contexts the member belongs to.
   *
   * If the member leaves an organization, their profile data persists independently and remains accessible when they join other organizations.
   *
   * @param connection
   * @param body Profile update request data
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update the authenticated member's global profile in the hrm_tracker_members table.
   *
   * 1. Extract the authenticated member ID from the request context (JWT token or session).
   * 2. Load the current member record from hrm_tracker_members table using the member ID.
   * 3. Validate that the authenticated member ID matches the target member record (prevent unauthorized updates).
   * 4. Apply partial updates for provided fields: display_name, avatar_url, phone.
   * 5. Validate the display_name is provided and not empty.
   * 6. Validate avatar_url format if provided (must be valid URL string).
   * 7. Update the updated_at timestamp to current time.
   * 8. Save the updated member record to the database.
   * 9. Return the updated member profile data.
   *
   * No activity log entry is generated for profile updates per business rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async updateProfile(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTrackerMember.IUpdate,
  ): Promise<IHrmTrackerMember> {
    try {
      return await putHrmTrackerMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
