import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerDepartment } from "../../../../api/structures/IHrmTrackerDepartment";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteHrmTrackerMemberDepartmentsDepartmentId } from "../../../../providers/deleteHrmTrackerMemberDepartmentsDepartmentId";
import { postHrmTrackerMemberDepartments } from "../../../../providers/postHrmTrackerMemberDepartments";
import { putHrmTrackerMemberDepartmentsDepartmentId } from "../../../../providers/putHrmTrackerMemberDepartmentsDepartmentId";

@Controller("/hrmTracker/member/departments")
export class HrmtrackerMemberDepartmentsController {
  /**
   * Create a new department within the organization.
   *
   * This operation allows users with org:manage permission to create new organizational units (departments). Each department belongs to the current organization context and can optionally have a parent department, but only one level of nesting is allowed (no grandparent departments). The department name must be unique within the same organization.
   *
   * Security and Permissions: Only users with the org:manage permission are authorized to create new departments. The system automatically associates the new department with the authenticated user's organization context.
   *
   * Validation Rules:
   * - Department name must be unique within the organization
   * - Parent department (if provided) must belong to the same organization
   * - Circular parent-child references are prohibited
   * - Only one level of hierarchy is allowed (no grandchild departments)
   *
   * This operation supports the standard department management workflow where administrators can organize employees into hierarchical units while maintaining strict data integrity rules.
   *
   * @param connection
   * @param body Department creation parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new department record with name, optional description, and optional parent department. Validate that the department name is unique within the current organization context. Verify that the parent department (if provided) belongs to the same organization. Check that only one level of hierarchy is maintained (no grandparent departments). Prevent circular parent-child references. Return the newly created department with all fields including timestamps and soft-delete status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTrackerDepartment.ICreate,
  ): Promise<IHrmTrackerDepartment> {
    try {
      return await postHrmTrackerMemberDepartments({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing department by ID.
   *
   * This operation updates the department's name, description, and parent department relationship. It enforces the following business rules:
   *
   * - Only users with org:manage permission in the department's organization can perform this operation.
   * - The department name must be unique within its organization. Attempting to set a name that already exists in the same organization will result in a validation error.
   * - The department hierarchy supports only one level of nesting. A department cannot have more than one parent, and grandchild departments are not allowed.
   * - The parent department must belong to the same organization as the department being updated. Cross-organization parent-child relationships are prohibited.
   * - No circular dependencies are allowed in the department structure. Any operation that would create a circular parent-child reference is blocked.
   * - The parent_id field is optional. Setting it to null places the department at the top level of the hierarchy.
   *
   * This operation is typically used by administrative users to reorganize the company structure, rename departments, or adjust reporting relationships. It should be used with caution to maintain data integrity and prevent accidental misconfigurations of the organizational hierarchy.
   *
   * Related operations:
   *
   * - `GET /hrmTracker/member/departments/{departmentId}` - Retrieve detailed information about a specific department
   * - `PATCH /hrmTracker/member/departments` - Search and list departments with filters and pagination
   * - `POST /hrmTracker/member/departments` - Create a new department
   * - `DELETE /hrmTracker/member/departments/{departmentId}` - Delete a department
   *
   * @param connection
   * @param departmentId Target department's ID
   * @param body Department update request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update hrm_tracker_departments record by id.
   * 1. Verify org:manage permission in department's organization
   * 2. Fetch existing department and validate it exists and is not deleted
   * 3. Validate new name is unique within same organization (excluding current record)
   * 4. If parent_id provided, verify it belongs to same organization and no circular reference
   * 5. Update name, description, parent_id fields
   * 6. Update updated_at timestamp
   * 7. Return updated department record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":departmentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string,
    @TypedBody()
    body: IHrmTrackerDepartment.IUpdate,
  ): Promise<IHrmTrackerDepartment> {
    try {
      return await putHrmTrackerMemberDepartmentsDepartmentId({
        member,
        departmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a department record from the organization's structure.
   *
   * This operation permanently deletes the specified department from the system. The deletion is irreversible and immediately removes the department from the organizational hierarchy.
   *
   * To maintain data integrity, this operation includes a validation check that prevents deletion if any employees are currently assigned to the department. If employees exist, the operation is rejected to avoid orphaned department references.
   *
   * For departments with assigned employees, the system requires employees to be reassigned or the department to be empty before deletion can proceed. This ensures all employee records maintain valid department associations.
   *
   * @param connection
   * @param departmentId Target department's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Delete a department record by ID with employee count validation.
   *
   * 1. Verify department exists and belongs to current organization context
   * 2. Check for assigned employees using hrm_tracker_employees.department_id
   * 3. If employees exist, reject with 'department_has_employees' error
   * 4. Perform soft-delete by setting deleted_at to current timestamp
   * 5. Set employee.department_id to null for all employees in this department
   * 6. Return deleted department record with updated deleted_at timestamp
   *
   * Soft-delete is implemented using the deleted_at column. The department
   * remains in database with timestamp but is excluded from normal queries.
   *
   * Transaction: Delete department record and nullify employee references atomically.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":departmentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string,
  ): Promise<void> {
    try {
      return await deleteHrmTrackerMemberDepartmentsDepartmentId({
        member,
        departmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
