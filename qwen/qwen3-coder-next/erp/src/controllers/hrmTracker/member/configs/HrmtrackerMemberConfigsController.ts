import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerSystemConfig } from "../../../../api/structures/IHrmTrackerSystemConfig";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmTrackerMemberConfigsConfigKey } from "../../../../providers/getHrmTrackerMemberConfigsConfigKey";
import { patchHrmTrackerMemberConfigs } from "../../../../providers/patchHrmTrackerMemberConfigs";
import { postHrmTrackerMemberConfigs } from "../../../../providers/postHrmTrackerMemberConfigs";

@Controller("/hrmTracker/member/configs")
export class HrmtrackerMemberConfigsController {
  /**
   * Create a new system configuration entry for the current organization.
   *
   * This operation allows any authenticated member to add a new configuration key-value pair to the organization's system configuration settings. Each configuration key must be unique within an organization, and the value is stored as a string for maximum flexibility.
   *
   * The configuration entry is automatically associated with the organization context of the authenticated user's active session. The system enforces uniqueness of keys within each organization, preventing duplicate configuration entries.
   *
   * @param connection
   * @param body Configuration key and value to create
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new system configuration record in hrm_tracker_system_configs table.
   *
   * 1. Extract hrm_tracker_organization_id from the user's active session context.
   * 2. Validate that the key is not empty and follows naming conventions.
   * 3. Check for existing configuration with the same key in the same organization to prevent duplicates.
   * 4. Create the configuration record with provided key, value, and organization context.
   * 5. Return the created configuration with id, key, value, and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTrackerSystemConfig.ICreate,
  ): Promise<IHrmTrackerSystemConfig> {
    try {
      return await postHrmTrackerMemberConfigs({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update organization system configuration settings.
   *
   * This operation allows authorized users to update system configuration settings stored as key-value pairs per organization. Configuration settings include fiscal start month, currency, timezone, and other organizational preferences.
   *
   * The operation accepts individual configuration key updates and applies them to the organization's configuration records. All updates are applied in a single transaction, ensuring consistency across the configuration store.
   *
   * Each configuration update requires validation of both the configuration key and its value format. Invalid keys or malformed values will cause the entire transaction to roll back, maintaining data integrity.
   *
   * @param connection
   * @param body Array of configuration key-value pairs to update
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update hrm_tracker_system_configs records for the authenticated user's organization context.
   *
   * 1. Retrieve the organization ID from the authenticated user's session.
   * 2. For each configuration update in the request body:
   *    - Validate the configuration key against the predefined set of valid keys.
   *    - Validate the configuration value format (e.g., timezone, currency).
   *    - Update the value field in hrm_tracker_system_configs.
   *    - Update the updated_at timestamp to the current time.
   * 3. Apply all updates within a single database transaction.
   * 4. If any validation fails or database update encounters an error, roll back the entire transaction.
   * 5. Return the updated configuration records for all successfully updated keys.
   * 6. Handle edge cases: key not found, invalid key format, value validation failure.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTrackerSystemConfig.IRequest,
  ): Promise<IHrmTrackerSystemConfig> {
    try {
      return await patchHrmTrackerMemberConfigs({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific organization configuration by its key.
   *
   * This operation fetches a single configuration setting from the system configuration table. The configuration is scoped to the organization of the authenticated actor. Only the configuration key and its stored value are returned.
   *
   * Configuration values are stored as strings to support flexible data types (e.g., 'true' for booleans, '2024-01-01' for dates). The application layer is responsible for parsing and type conversion based on the configuration key.
   *
   * @param connection
   * @param configKey Configuration key name (unique per organization)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_tracker_system_configs table by organization ID (from actor context) and configuration key. Return single record's key and value fields. Filter by non-null deleted_at to exclude soft-deleted records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":configKey")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("configKey")
    configKey: string,
  ): Promise<IHrmTrackerSystemConfig> {
    try {
      return await getHrmTrackerMemberConfigsConfigKey({
        member,
        configKey,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
