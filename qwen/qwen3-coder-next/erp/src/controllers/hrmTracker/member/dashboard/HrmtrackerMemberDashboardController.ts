import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerDashboard } from "../../../../api/structures/IHrmTrackerDashboard";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmTrackerMemberDashboard } from "../../../../providers/getHrmTrackerMemberDashboard";

@Controller("/hrmTracker/member/dashboard")
export class HrmtrackerMemberDashboardController {
  /**
   * Retrieve organizational dashboard overview for members.
   *
   * This endpoint provides a comprehensive dashboard view for members with report:view permissions, displaying key organizational statistics, pending invitations, recent activity logs, and current timelog summaries. The dashboard is designed for administrators and managers to quickly assess organizational health and identify pending actions.
   *
   * The dashboard aggregates data from multiple sources including activity logs for recent system events, pending invitations for onboarding tracking, and timelog summaries for workforce activity. All data is filtered by the member's organization context to ensure proper multi-tenancy isolation.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Aggregate dashboard data from hrm_tracker_activity_logs, hrm_tracker_pending_invitations, and hrm_tracker_timelogs tables. Calculate summary statistics for organization activity including pending invitation counts, recent activity log summaries, and current timelog aggregates. Filter all data by the member's organization context. Join with related tables for employee and department context. Return comprehensive dashboard summary object.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmTrackerDashboard> {
    try {
      return await getHrmTrackerMemberDashboard({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
