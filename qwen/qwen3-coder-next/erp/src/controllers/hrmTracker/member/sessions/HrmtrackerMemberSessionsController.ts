import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerMemberSession } from "../../../../api/structures/IHrmTrackerMemberSession";
import { IPageIHrmTrackerMemberSession } from "../../../../api/structures/IPageIHrmTrackerMemberSession";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmTrackerMemberSessionsSessionId } from "../../../../providers/getHrmTrackerMemberSessionsSessionId";
import { patchHrmTrackerMemberSessions } from "../../../../providers/patchHrmTrackerMemberSessions";

@Controller("/hrmTracker/member/sessions")
export class HrmtrackerMemberSessionsController {
  /**
   * Retrieve a filtered and paginated list of active authentication sessions.
   *
   * This operation provides advanced search and filtering capabilities for member sessions stored in the hrm_tracker_member_sessions table. It allows administrators and authorized members to view session history, identify active sessions, and monitor access patterns.
   *
   * The endpoint supports filtering by member identifier, date range (created_at, expires_at), IP address, and session status (active/revoked). Pagination enables handling large result sets efficiently. Response includes session summary information with token metadata and connection details for security auditing and access management purposes.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for session filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_tracker_member_sessions table with pagination and filtering. Filter by member_id for specific user's sessions, date ranges for created_at and expires_at, ip address matching, and revoked_at null check for active status. Order by created_at descending (newest first). Return cursor-based pagination for large result sets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTrackerMemberSession.IRequest,
  ): Promise<IPageIHrmTrackerMemberSession.ISummary> {
    try {
      return await patchHrmTrackerMemberSessions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific JWT session token.
   *
   * This operation fetches a single session record from the member_sessions table, providing complete visibility into the session's metadata including connection details and activity timeline. The returned data includes client connection information and session lifecycle timestamps.
   *
   * Session data is highly sensitive and should only be accessible to system administrators or security auditors. The operation supports security investigations, compliance audits, and troubleshooting by providing a complete audit trail of active and revoked sessions.
   *
   * This endpoint is designed for administrative use cases only. Regular API authentication should not require retrieving session records directly—client applications should use the standard access token refresh flow instead.
   *
   * @param connection
   * @param sessionId Target session's UUID identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_tracker_member_sessions table by id (UUID).
   * Return complete session record including access_token, refresh_token, ip, user_agent, created_at, expires_at, revoked_at, and last_activity_at.
   * If session not found, return 404 Not Found.
   * If session is revoked (revoked_at present), return 403 Forbidden.
   * Apply organization-level authorization to ensure caller has permission to view session data for the associated member.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("sessionId")
    sessionId: string,
  ): Promise<IHrmTrackerMemberSession> {
    try {
      return await getHrmTrackerMemberSessionsSessionId({
        member,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
