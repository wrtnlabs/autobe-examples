import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerTimer } from "../../../../../api/structures/IHrmTrackerTimer";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmTrackerMemberTimersStatus } from "../../../../../providers/getHrmTrackerMemberTimersStatus";

@Controller("/hrmTracker/member/timers/status")
export class HrmtrackerMemberTimersStatusController {
  /**
   * Retrieve the current active timer status for the authenticated employee.
   *
   * This operation returns details about the employee's currently running timer, including the start timestamp, selected project, optional task, and description. If the employee has no active timer, the endpoint returns null.
   *
   * The timer data updates in real-time, so any changes made to the active timer are immediately reflected in the response. This endpoint is designed to provide a live view of the employee's current time tracking session.
   *
   * Access is limited to authenticated members with employee scope. The response only contains the authenticated employee's own active timer.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the hrm_tracker_timers table for the currently active timer associated with the authenticated employee. Use the employee ID from the authentication context to filter. Return the complete timer record if it exists, or null if no active timer is found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmTrackerTimer> {
    try {
      return await getHrmTrackerMemberTimersStatus({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
