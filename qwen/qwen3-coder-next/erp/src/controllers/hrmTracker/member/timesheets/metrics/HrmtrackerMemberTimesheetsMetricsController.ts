import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerTimesheet } from "../../../../../api/structures/IHrmTrackerTimesheet";
import { IPageIHrmTrackerTimesheet } from "../../../../../api/structures/IPageIHrmTrackerTimesheet";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchHrmTrackerMemberTimesheetsMetrics } from "../../../../../providers/patchHrmTrackerMemberTimesheetsMetrics";

@Controller("/hrmTracker/member/timesheets/metrics")
export class HrmtrackerMemberTimesheetsMetricsController {
  /**
   * Retrieve aggregated timesheet metrics and analytics for dashboard and reporting purposes.
   *
   * This operation provides comprehensive analytics on employee time tracking across the organization. It aggregates timelogs from timesheets to deliver insights including total hours worked, time breakdowns by project and task, productivity trends, and employee contribution metrics.
   *
   * The operation supports flexible filtering to analyze time data across different dimensions including date ranges, employees, projects, and tasks. Users can generate reports for specific time periods, individual employees, or organizational-wide summaries.
   *
   * This analytics endpoint is designed for use by HR managers, project leads, and executives who need visibility into team productivity and time allocation without accessing individual timesheet details.
   *
   * Security:
   * - Users with time:view_all permission can view all employees' timesheet metrics
   * - Regular employees can only view their own timesheet metrics
   * - Project leads can view metrics for all employees assigned to their projects
   *
   * The operation aggregates data from the hrm_tracker_timelogs table joined through hrm_tracker_timesheets, calculating totals, averages, and breakdowns based on the applied filters. It supports complex multi-dimensional analysis while maintaining data isolation based on user permissions.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for metrics aggregation
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query aggregated timelogs metrics from hrm_tracker_timelogs joined with hrm_tracker_timesheets.
   * Apply filters for date range (week_start_date, week_end_date), employee ID, project ID, task ID.
   * Calculate total hours, averages, and breakdowns by project/task/employee.
   * Apply organization-level data isolation based on user permissions (time:view_all or project membership).
   * Return paginated summary statistics rather than individual timelog records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTrackerTimesheet.IRequest,
  ): Promise<IPageIHrmTrackerTimesheet.ISummary> {
    try {
      return await patchHrmTrackerMemberTimesheetsMetrics({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
