@Controller("/hrmTracker/member/timesheets")
export class HrmtrackerMemberTimesheetsController {
  /**
   * Submit a draft timesheet for manager approval.
   *
   * This operation allows employees to submit their draft timesheets for manager review and approval. When a timesheet is submitted, its status changes from 'draft' to 'submitted', making it available for users with time:approve permission to approve or reject.
   *
   * The submitted timesheet is locked from further employee modifications until it is either approved or rejected by an authorized manager. If rejected, the timesheet returns to 'draft' status for revision and resubmission.
   *
   * Security:
   * - Only the employee who owns the timesheet can submit it
   * - Only timesheets with status 'draft' can be submitted
   * - Timesheets with already-locked timelogs cannot be submitted
   * - Organization membership is verified for data isolation
   *
   * Related operations:
   * - GET /timesheets/{id} (retrieve a specific timesheet)
   * - GET /timesheets (list employee's timesheets)
   * - PATCH /timesheets/{id}/approve (approve a submitted timesheet)
   * - PATCH /timesheets/{id}/reject (reject a submitted timesheet)
   *
   * @param connection
   * @param body Timesheet submission request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Submit a draft timesheet by changing its status from 'draft' to 'submitted'.
   *
   * 1. Validate that the authenticated employee matches the timesheet's employee_id
   * 2. Verify the timesheet exists and has status 'draft'
   * 3. Verify the timesheet has no locked timelogs (i.e., it's not part of an already approved timesheet)
   * 4. Update timesheet status to 'submitted'
   * 5. Set submitted_at timestamp to current time
   * 6. Return the updated timesheet record
   *
   * Implementation notes:
   * - Enforce organization-based multi-tenancy
   * - Use transaction to ensure atomic status update
   * - Return 409 Conflict if timesheet is already submitted or approved
   * - Return 403 Forbidden if employee doesn't own the timesheet
   * - Log the submission event for audit trail
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTrackerTimesheet.ISubmit,
  ): Promise<IHrmTrackerTimesheet> {
    try {
      return await postHrmTrackerMemberTimesheets({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of timesheet records.
   *
   * This operation provides comprehensive search and filtering capabilities for timesheets across the organization. Users can filter by employee, timesheet status (draft, submitted, approved, rejected), date range, and organization context. The endpoint supports efficient data browsing for time tracking management, payroll processing, and approval workflows.
   *
   * ## Security and Authorization
   *
   * Access to this endpoint is controlled through role-based permissions:
   *
   * - Standard employees can only view their own timesheets (when employee_id matches their own record)
   * - Managers with time:approve permission can view all timesheets in their organization for approval purposes
   * - Administrators with time:view_all permission can view all timesheets across the organization including historical records
   *
   * The system enforces data isolation based on the member's organizational context and permission scope. Unauthorized access attempts to view other employees' timesheets without proper permissions are rejected.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for timesheet filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_tracker_timesheets table with pagination and filtering.
   * Apply filters for employee_id (if restricted by permissions), status, week_start_date, week_end_date, and organization_id.
   * Join with hrm_tracker_employees for employee details and hrm_tracker_timesheet_timelogs for timelog aggregation.
   * Calculate total_hours from associated timelogs.
   * Return paginated results with timesheet summary information optimized for list displays.
   * Enforce authorization: members can only view their own timesheets unless they have time:approve or time:view_all permissions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTrackerTimesheet.IRequest,
  ): Promise<IPageIHrmTrackerTimesheet.ISummary> {
    try {
      return await patchHrmTrackerMemberTimesheets({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific timesheet by its unique identifier.
   *
   * This operation fetches a complete timesheet record, including all associated timelogs, for the specified employee and week. The timesheet contains detailed time tracking information used for payroll processing and billing purposes.
   *
   * **Authorization Requirements:**
   * - Users can retrieve their own timesheets
   * - Users with time:approve permission can view all timesheets across the organization
   * - Users with time:view_all permission can view timesheet data including locked timelogs
   *
   * **Timesheet Statuses:**
   * - `draft`: Timesheet is being created, timelogs can be modified
   * - `submitted`: Timesheet submitted for approval, timelogs locked from employee edits
   * - `approved`: Timesheet approved by manager, all timelogs fully locked
   * - `rejected`: Timesheet rejected for revision, returns to draft status
   *
   * @param connection
   * @param timesheetId Unique identifier of the timesheet record
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_tracker_timesheets table by UUID identifier. Join with hrm_tracker_employees for employee reference and hrm_tracker_organizations for organization context. Include all related timelogs from hrm_tracker_timelogs via hrm_tracker_timesheet_timelogs junction table. Apply authorization checks: user must own the timesheet, have time:approve permission, or have time:view_all permission. Return timesheet with full employee and organization details, approval status, and calculated total hours.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":timesheetId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string,
  ): Promise<IHrmTrackerTimesheet> {
    try {
      return await getHrmTrackerMemberTimesheetsTimesheetId({
        member,
        timesheetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing timesheet record for an employee.
   *
   * This operation allows employees to update draft timesheets by modifying the status, recalculating total_hours, or updating the rejection_reason when the timesheet is rejected. Only timesheets in draft status can be updated directly; submitted timesheets must first be rejected by a manager before further edits.
   *
   * The update operation validates that the timesheet belongs to the employee's organization and follows strict state transition rules. For example, a draft timesheet can be updated with new timelog calculations, but a submitted timesheet cannot be directly modified - it must first be rejected by a manager with a rejection reason.
   *
   * **State Transitions:**
   *
   * - Draft → Draft: Employee can update status, total_hours, rejection_reason
   * - Submitted → Draft: Requires prior rejection with rejection_reason
   * - Approved/Rejected: Cannot be updated (operation blocked)
   *
   * **Security:**
   *
   * - Employees can only update their own timesheets or timesheets within their organization
   * - Timesheets from other organizations are inaccessible
   * - All updates are logged with updated_at timestamp
   *
   * @param connection
   * @param timesheetId Target timesheet's UUID identifier
   * @param body Timesheet update request with updatable fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_tracker_timesheets table by id with organization and employee joins. Validate timesheet status is draft or rejected (not approved/submitted). Check employee ownership or organization access. Update status, total_hours, rejection_reason fields with current timestamp. Apply strict state transition validation - reject updates that violate transition rules. Return updated timesheet record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":timesheetId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string,
    @TypedBody()
    body: IHrmTrackerTimesheet.IUpdate,
  ): Promise<IHrmTrackerTimesheet> {
    try {
      return await putHrmTrackerMemberTimesheetsTimesheetId({
        member,
        timesheetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a timesheet record from the system.
   *
   * This operation permanently removes a timesheet (status: draft or submitted) from the database. Timesheets with status approved or rejected are protected and cannot be deleted. Deletion also removes all associated timesheet-timelogjunction records, but timelogs themselves are preserved as they may be referenced elsewhere.
   *
   * The operation enforces ownership and permission controls:
   * - Employees can delete their own draft/submitted timesheets
   * - Users with time:manage permission can delete any timesheet regardless of ownership or status
   * - Deletion is blocked if the timesheet has status approved or rejected
   * - Organization deletion is blocked if pending timesheets exist, so this endpoint provides a mechanism to clear pending timesheets to unblock organization deletion
   *
   * After deletion, the timesheet is permanently removed and cannot be restored. All associated junction records (timesheet-timelog links) are also deleted, but the underlying timelog records remain intact.
   *
   * @param connection
   * @param timesheetId Target timesheet's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Delete a timesheet record by ID. Apply soft-delete using deleted_at timestamp. Ensure timesheet status is draft or submitted (approved/rejected timesheets are protected). Remove all associated hrm_tracker_timesheet_timelogs records via cascade. Preserve underlying timelogs. Enforce authorization: employee can delete own timesheets only; time:manage permission bypasses ownership check.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":timesheetId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string,
  ): Promise<void> {
    try {
      return await deleteHrmTrackerMemberTimesheetsTimesheetId({
        member,
        timesheetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Approve a submitted timesheet.
   *
   * This operation allows users with time:approve permission to approve a submitted timesheet. Upon approval, the timesheet status changes to approved, the reviewed at timestamp is recorded, and the reviewer is logged. All timelogs included in an approved timesheet become locked: employees and even users with time:manage permission cannot edit or delete them. Approved timesheets cannot be modified or rejected after approval.
   *
   * Security and Permissions:
   *
   * - Only users with time:approve permission can approve timesheets
   * - Only timesheets in submitted status can be approved
   * - The timesheet must belong to the same organization as the requesting user
   * - Approving a timesheet with no timelogs is blocked
   *
   * Status Transitions:
   *
   * - draft → submitted (employee submits)
   * - submitted → approved (manager approves) - this operation
   * - submitted → draft (manager rejects with reason)
   * - approved, rejected → no further transitions
   *
   * Related Operations:
   *
   * - POST /timesheets/{timesheetId}/reject — Reject a submitted timesheet with a reason
   * - GET /timesheets/{timesheetId} — Retrieve timesheet details including approval status
   * - GET /timesheets — Search timesheets by status for approval workflow
   *
   * @param connection
   * @param timesheetId Target timesheet's ID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Approve a submitted timesheet for payroll or billing.
   *
   * 1. Load the target timesheet by ID.
   * 2. Validate organization context matches the timesheet's organization.
   * 3. Verify the user has time:approve permission.
   * 4. Verify the timesheet status is 'submitted'.
   * 5. Verify the timesheet contains at least one timelog.
   * 6. Update status to 'approved', set reviewed_at to current timestamp, and set reviewed_by_member_id to the current user's member ID.
   * 7. Lock all timelogs in the timesheet (set locked flag or mark as non-editable).
   * 8. Return the updated timesheet.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":timesheetId/approve")
  public async approve(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string,
  ): Promise<IHrmTrackerTimesheet> {
    try {
      return await postHrmTrackerMemberTimesheetsTimesheetIdApprove({
        member,
        timesheetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Reject a submitted timesheet.
   *
   * This operation allows authorized reviewers to reject a timesheet that is in submitted status. Upon rejection, the timesheet returns to draft status for the employee to revise and resubmit. The rejection reason is stored for audit purposes and to provide clear feedback to the employee.
   *
   * The operation enforces strict authorization: only users with the time:approve permission can reject timesheets. Users without this authority receive a permission denied error. Additionally, rejection without a reason is blocked, ensuring employees receive clear feedback. Rejection is only allowed on submitted timesheets; draft or already approved/rejected timesheets cannot be processed.
   *
   * This operation is part of the timesheet approval workflow alongside timesheet approval and submission operations. Rejected timesheets are excluded from approval queues but remain visible to both employees and reviewers for revision and resubmission.
   *
   * @param connection
   * @param timesheetId Target timesheet's ID
   * @param body Rejection reason and metadata
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Process timesheet rejection for hrm_tracker_timesheets table. Verify user has time:approve permission, confirm timesheet is in submitted status, require rejection reason in request body, update status to draft, set rejection_reason, update reviewed_by_member_id and reviewed_at timestamps. Return updated timesheet record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":timesheetId/reject")
  public async reject(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string,
    @TypedBody()
    body: IHrmTrackerTimesheet.IReject,
  ): Promise<IHrmTrackerTimesheet> {
    try {
      return await postHrmTrackerMemberTimesheetsTimesheetIdReject({
        member,
        timesheetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Submit a draft timesheet for approval.
   *
   * This operation transitions a timesheet from draft status to submitted status, initiating the approval workflow. Only the employee who owns the timesheet can perform this action. The timesheet must contain at least one timelog, there must be no duplicate timesheet for the same week, and no active timer can exist for the employee at submission time.
   *
   * When successful, the timesheet status changes to submitted, the submitted_at timestamp is recorded, and all associated timelogs become locked to prevent further modifications. The timesheet is then available for review by users with time:approve permission.
   *
   * This operation enforces strict business rules to maintain data integrity and prevent conflicting time entries.
   *
   * @param connection
   * @param timesheetId Target timesheet's unique identifier
   * @param body Request body to submit a draft timesheet for approval
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Transition timesheet status from draft to submitted. Validate: (1) timesheet exists and belongs to requesting employee, (2) timesheet has at least one timelog, (3) no duplicate timesheet for same week exists, (4) no active timer for employee. Update status field, set submitted_at timestamp, and lock associated timelogs.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":timesheetId/submit")
  public async submit(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string,
    @TypedBody()
    body: IHrmTrackerTimesheet.IUpdate,
  ): Promise<IHrmTrackerTimesheet> {
    try {
      return await postHrmTrackerMemberTimesheetsTimesheetIdSubmit({
        member,
        timesheetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
