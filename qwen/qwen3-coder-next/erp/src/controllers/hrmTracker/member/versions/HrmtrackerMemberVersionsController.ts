import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerSystemVersion } from "../../../../api/structures/IHrmTrackerSystemVersion";
import { IPageIHrmTrackerSystemVersion } from "../../../../api/structures/IPageIHrmTrackerSystemVersion";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmTrackerMemberVersionsVersion } from "../../../../providers/getHrmTrackerMemberVersionsVersion";
import { patchHrmTrackerMemberVersions } from "../../../../providers/patchHrmTrackerMemberVersions";

@Controller("/hrmTracker/member/versions")
export class HrmtrackerMemberVersionsController {
  /**
   * Retrieve a specific database schema version by its version identifier.
   *
   * This operation fetches detailed information about a specific database migration version including the version identifier, application timestamp, and optional rollback version reference.
   *
   * The operation requires exact version matching and returns a single schema version record with full details about when it was applied and any rollback relationship.
   *
   * @param connection
   * @param version Target schema version's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_tracker_system_versions table by version identifier.
   * Return the version record including applied_at timestamp and optional rollback_version.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":version")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("version")
    version: string,
  ): Promise<IHrmTrackerSystemVersion> {
    try {
      return await getHrmTrackerMemberVersionsVersion({
        member,
        version,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of system schema version records.
   *
   * This operation provides advanced search capabilities for database migration versions including version identifier filtering, applied date ranges, and rollback version status. It allows administrators to browse the history of applied schema migrations and identify which versions are currently active or have been rolled back.
   *
   * The system versions table tracks all schema migrations applied to the database, providing a complete audit trail of schema changes over time. Each record includes the version identifier, timestamp when it was applied, and optionally references the previous version for rollback tracking.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_tracker_system_versions table with pagination and filtering.
   * Apply search filters on version identifier, applied_at date range, and rollback_version presence.
   * Support filtering for versions that have been rolled back versus current active versions.
   * Return cursor-based pagination for large result sets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTrackerSystemVersion.IRequest,
  ): Promise<IPageIHrmTrackerSystemVersion.ISummary> {
    try {
      return await patchHrmTrackerMemberVersions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
