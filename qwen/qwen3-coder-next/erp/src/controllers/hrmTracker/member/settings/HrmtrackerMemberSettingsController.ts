import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerOrganization } from "../../../../api/structures/IHrmTrackerOrganization";
import { IHrmTrackerOrganizationSetting } from "../../../../api/structures/IHrmTrackerOrganizationSetting";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmTrackerMemberSettings } from "../../../../providers/getHrmTrackerMemberSettings";
import { putHrmTrackerMemberSettings } from "../../../../providers/putHrmTrackerMemberSettings";

@Controller("/hrmTracker/member/settings")
export class HrmtrackerMemberSettingsController {
  /**
   * Retrieve organization configuration settings for the current organization context.
   *
   * This operation returns the organization's fiscal start month, currency code, timezone, display name, and logo URL. It is designed for authorized users who need to view current organizational preferences and configuration.
   *
   * Security and Permissions:
   * - Requires the org:manage permission to access organization settings
   * - The operation always retrieves settings for the organization in the current context
   * - Analysis sections confirm that organization owners can edit settings, while other roles with org:manage can view settings
   *
   * Database Entity:
   * - Uses the hrm_tracker_organization_settings table which stores configuration for each organization
   * - Returns the single active settings record for the current organization context
   * - Fields include fiscal_start_month (1-12), currency (ISO 4217 code), timezone (IANA name), name (display name), and logo_url (image URL)
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_tracker_organization_settings table for the current organization context.
   * Return fiscal_start_month, currency, timezone, name, and logo_url fields.
   * Ensure the operation uses the organization ID from the current session context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmTrackerOrganizationSetting> {
    try {
      return await getHrmTrackerMemberSettings({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update organization configuration settings.
   *
   * This operation allows organization owners to modify key configuration settings including the organization name, description, logo image URI, currency code, timezone, and fiscal year start month.
   *
   * Security and Authorization: This endpoint is restricted to users with the owner role in the current organization. Users with other roles (manager, employee, or custom roles) cannot modify these settings. The organization context is derived from the user's active organization selection in the session.
   *
   * Settings Fields:
   * - name: Organization display name
   * - description: Organization description
   * - logo_image_uri: URI/URL pointing to the organization logo image
   * - currency: Three-letter currency code (e.g., USD, EUR, KRW)
   * - timezone: IANA timezone identifier (e.g., Asia/Seoul, America/New_York)
   * - fiscal_start_month: Integer month (1-12) marking the fiscal year start
   *
   * Validation: All field updates are validated against domain constraints. The name field must remain globally unique. The logo_image_uri must be a valid URI if provided.
   *
   * @param connection
   * @param body Settings update payload with configurable organization fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update organization settings in hrm_tracker_organizations table based on user's active organization context. Fetch organization by organization context from session, verify user has owner role, then update fields: name, description, logo_image_uri, currency, timezone, fiscal_start_month. Apply validation for uniqueness and URI format. Return updated organization record with full details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async updateSettings(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTrackerOrganization.ISettingsUpdate,
  ): Promise<IHrmTrackerOrganization> {
    try {
      return await putHrmTrackerMemberSettings({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
