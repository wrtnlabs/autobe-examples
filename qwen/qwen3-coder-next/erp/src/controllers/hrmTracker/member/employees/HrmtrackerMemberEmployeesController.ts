import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerEmployee } from "../../../../api/structures/IHrmTrackerEmployee";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { postHrmTrackerMemberEmployees } from "../../../../providers/postHrmTrackerMemberEmployees";
import { putHrmTrackerMemberEmployeesEmployeeId } from "../../../../providers/putHrmTrackerMemberEmployeesEmployeeId";

@Controller("/hrmTracker/member/employees")
export class HrmtrackerMemberEmployeesController {
  /**
   * Create a new employee record linked to an organization.
   *
   * This endpoint allows authorized users to add a new employee to the organization by linking an existing user account with organization-specific details such as employment type, position, and optional role/department assignments. The employee record becomes active upon creation.
   *
   * **Security and Authorization:**
   * - Requires employee:manage permission to create new employee records
   * - Employee must belong to exactly one organization
   * - Employee status is set to 'active' by default upon creation
   * - Deactivated employees (status='deactivated') retain historical data but cannot log time or submit timesheets
   *
   * **Business Rules:**
   * - Employment type must be one of the predefined values: 'full-time', 'part-time', 'contractor', 'intern'
   * - Status must be 'active' or 'deactivated'
   * - Role and department are optional but must belong to the same organization as the employee
   * - Employee records maintain audit trail through created_at and updated_at timestamps
   *
   * **Relationships:**
   * - Links to hrm_tracker_members (user) for authentication context
   * - Links to hrm_tracker_organizations for data isolation
   * - Optional links to hrm_tracker_roles and hrm_tracker_departments
   * - If referenced role or department is deleted, the foreign key is set to NULL
   *
   * **Error Conditions:**
   * - Duplicate error when same user is already assigned as employee in the organization
   * - Validation error for invalid employment_type or status values
   * - Reference errors if role_id or department_id belongs to different organization
   * - Department deletion behavior: when department is deleted, employee.department_id becomes NULL but employee record remains active
   *
   * @param connection
   * @param body Employee creation data including organization, user, employment type, and optional role/department
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create employee record by inserting into hrm_tracker_employees table.
   *
   * 1. Input validation:
   *    - employment_type must be one of: 'full-time', 'part-time', 'contractor', 'intern'
   *    - status must be one of: 'active', 'deactivated'
   *    - role_id and department_id must belong to same organization as employee
   *    - Check for duplicate: organization_id + user_id must be unique
   *
   * 2. Database operation:
   *    - Insert into hrm_tracker_employees with provided fields
   *    - Set created_at and updated_at to current timestamp
   *    - Set deleted_at to NULL for active employee
   *
   * 3. Return created employee with complete object including generated timestamps
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTrackerEmployee.ICreate,
  ): Promise<IHrmTrackerEmployee> {
    try {
      return await postHrmTrackerMemberEmployees({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing employee record within an organization.
   *
   * This operation updates the details of an employee including their assigned role, department, status (active/deactivated), employment type, and position title. All updates are scoped to the organization context of the authenticated employee.
   *
   * Security & Permissions: Only users with employee:manage permission can perform this operation. The system validates that the target employee belongs to the authenticated organization and that role and department assignments exist within the same organization.
   *
   * Business Rules:
   * - If department_id is set to null, the employee loses their department assignment (as per 'Department Assignment Is Optional for Employees')
   * - Setting department_id to an invalid department or one belonging to a different organization is rejected
   * - If the role_id is changed, the employee immediately inherits all permissions assigned to that role
   * - Deactivated employees (status='deactivated') retain their historical data but lose the ability to log time or submit timesheets
   *
   * Relationships & Dependencies:
   * - The role must belong to the same organization as the employee
   * - The department must belong to the same organization as the employee
   * - An employee can only be assigned to a role that exists within the same organization
   *
   * Edge Cases:
   * - Attempting to assign a role or department from a different organization is rejected
   * - Attempting to deactivate an employee does not delete their historical records (timelogs, timesheets, tasks)
   * - Updating an employee with status='deactivated' preserves all historical data while preventing future time logging
   *
   * @param connection
   * @param employeeId Target employee's unique identifier
   * @param body Employee update request with optional fields for role, department, status, employment type, and position
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_tracker_employees by id and verify organization context matches authenticated session.
   * Update the employee record with provided fields: role_id, department_id, status, employment_type, position.
   * Validate that role_id (if provided) belongs to the same organization.
   * Validate that department_id (if provided) belongs to the same organization.
   * If status='deactivated', ensure deleted_at is set to current timestamp.
   * If status='active', ensure deleted_at is set to NULL.
   * Update updated_at to current timestamp.
   * Return the complete updated employee record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":employeeId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string,
    @TypedBody()
    body: IHrmTrackerEmployee.IUpdate,
  ): Promise<IHrmTrackerEmployee> {
    try {
      return await putHrmTrackerMemberEmployeesEmployeeId({
        member,
        employeeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
