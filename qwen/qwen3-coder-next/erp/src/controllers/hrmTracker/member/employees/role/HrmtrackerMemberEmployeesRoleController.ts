import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerEmployee } from "../../../../../api/structures/IHrmTrackerEmployee";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { postHrmTrackerMemberEmployeesEmployeeIdRole } from "../../../../../providers/postHrmTrackerMemberEmployeesEmployeeIdRole";

@Controller("/hrmTracker/member/employees/:employeeId/role")
export class HrmtrackerMemberEmployeesRoleController {
  /**
   * Assign a role to an employee within their organization.
   *
   * This operation assigns a specific role to an employee, replacing any existing role assignment. The employee must belong to the same organization as the user performing the assignment. Only users with employee:manage permission or organization owners can perform this operation.
   *
   * The operation is fully auditable: the system records who performed the assignment, when it occurred, and the prior and new role assignments in the activity log. The role assignment takes effect immediately for all subsequent operations and permissions checks.
   *
   * @param connection
   * @param employeeId Unique identifier of the employee to assign a role to
   * @param body Role assignment request payload
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Assign a role to an employee by updating the hrm_tracker_employees.role_id field with the provided role_id from the request body.
   *
   * - Fetch employee by ID and verify it belongs to the requesting user's organization
   * - Fetch role by ID and verify it belongs to the same organization
   * - Check authorization: only owners or users with employee:manage permission can perform this operation
   * - Update the employee's role_id to the new role_id
   * - Record the role assignment change in the activity log with details about who performed the change, when, and the prior and new roles
   * - Return the updated employee information including the new role assignment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async assign(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string,
    @TypedBody()
    body: IHrmTrackerEmployee.IAssign,
  ): Promise<void> {
    try {
      return await postHrmTrackerMemberEmployeesEmployeeIdRole({
        member,
        employeeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
