import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerProject } from "../../../../api/structures/IHrmTrackerProject";
import { IPageIHrmTrackerProject } from "../../../../api/structures/IPageIHrmTrackerProject";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmTrackerMemberProjectsProjectId } from "../../../../providers/getHrmTrackerMemberProjectsProjectId";
import { patchHrmTrackerMemberProjects } from "../../../../providers/patchHrmTrackerMemberProjects";
import { postHrmTrackerMemberProjects } from "../../../../providers/postHrmTrackerMemberProjects";
import { putHrmTrackerMemberProjectsProjectId } from "../../../../providers/putHrmTrackerMemberProjectsProjectId";

@Controller("/hrmTracker/member/projects")
export class HrmtrackerMemberProjectsController {
  /**
   * Create a new project to represent a work initiative.
   *
   * This operation creates a new project with the specified name, color, and optional metadata including description, budget hours, and date range. Projects serve as containers for tasks and time tracking within an organization.
   *
   * Security considerations: Users must have project:manage permission to create projects. The project is automatically associated with the current organization context. The name and color code are required fields - the operation will fail if either is missing.
   *
   * Relationship to underlying database entities: The project entity belongs to exactly one organization and can contain multiple tasks, project members, and timelogs. Creation establishes the initial active state, and status transitions are tracked in the activity log.
   *
   * Validation rules: The name must be provided and cannot be empty. The color code is required for UI display purposes. Budget hours, if provided, must be a non-negative number. Start date must be before end date if both are provided.
   *
   * Related API operations: GET /projects retrieves the project list. PATCH /projects/{id} updates an existing project. GET /projects/{id} retrieves detailed project information.
   *
   * @param connection
   * @param body Project creation data including name, color, description, and optional budget and dates
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new project within the current organization context. Validate required fields (name, color). Set status to active on creation. Generate unique identifier. Record creation timestamp. Return complete project object with all fields including generated ID and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTrackerProject.ICreate,
  ): Promise<IHrmTrackerProject> {
    try {
      return await postHrmTrackerMemberProjects({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of project records.
   *
   * This operation provides comprehensive search and filtering capabilities for organizational projects. Users can filter projects by status (active, archived, completed), name patterns, date ranges (start_date, end_date), and budget thresholds. The response includes essential project summary information optimized for list displays.
   *
   * Projects are organization-scoped, ensuring users only access projects within their assigned organizations. The search supports both simple pattern matching and range queries for flexible project discovery.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_tracker_projects table with organization-scoped filtering. Apply filters on name (partial match), status, start_date range, end_date range, and budget_hours thresholds. Return paginated results using cursor or offset-based pagination. Include project_members count and task/timelog summary statistics.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTrackerProject.IRequest,
  ): Promise<IPageIHrmTrackerProject.ISummary> {
    try {
      return await patchHrmTrackerMemberProjects({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific project.
   *
   * This operation fetches the complete project details including name, description, color code, status, budget information, and date ranges. The project must belong to the current organization context.
   *
   * Employees assigned to the project can always view it. Users with project:view permission can access project details across the organization.
   *
   * Database schema:
   * - id: UUID identifier for the project record
   * - name: Project name (required, max 255 characters)
   * - description: Optional project description in markdown format
   * - color: Color code for UI visualization (hex format)
   * - status: Project status ('active', 'archived', 'completed')
   * - budget_hours: Total budgeted hours for the project (optional)
   * - start_date: Project start date (optional)
   * - end_date: Project end date (optional)
   * - created_at: Record creation timestamp
   * - updated_at: Last update timestamp
   * - deleted_at: Soft delete timestamp (null if not deleted)
   *
   * @param connection
   * @param projectId Target project's UUID identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_tracker_projects table by id with organization context enforcement.
   * Join with organization to verify current session organization matches.
   * Return single project record with all fields. Handle soft delete by excluding deleted_at records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":projectId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string,
  ): Promise<IHrmTrackerProject> {
    try {
      return await getHrmTrackerMemberProjectsProjectId({
        member,
        projectId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing project with new information.
   *
   * This operation allows authorized users to modify a project's core attributes including its name, description, color code, status, budget hours, and scheduling dates. Only active projects can accept new timelogs; archived or completed projects preserve historical data but cannot be reactivated to active status.
   *
   * Security and Authorization: Users with project:manage permission are authorized to perform project updates. The operation validates that the project exists within the current organization context and has not been soft-deleted.
   *
   * Data Integrity: The project status transition workflow is enforced—projects cannot transition from archived or completed states back to active. All status changes are tracked in the activity log for audit purposes.
   *
   * @param connection
   * @param projectId Target project's UUID identifier
   * @param body Update request with project attributes
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update hrm_tracker_projects table by id. Join with hrm_tracker_organizations to verify organization context. Validate project exists and is not soft-deleted. Apply partial updates to name, description, color, status, budget_hours, start_date, end_date. Enforce business rules: status can only transition from active to archived/completed; archived/completed projects cannot be reactivated. Update updated_at timestamp. Soft delete support via deleted_at column.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":projectId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string,
    @TypedBody()
    body: IHrmTrackerProject.IUpdate,
  ): Promise<void> {
    try {
      return await putHrmTrackerMemberProjectsProjectId({
        member,
        projectId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
