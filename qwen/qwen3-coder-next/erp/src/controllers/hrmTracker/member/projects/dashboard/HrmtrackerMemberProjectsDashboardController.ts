import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerProject } from "../../../../../api/structures/IHrmTrackerProject";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmTrackerMemberProjectsProjectIdDashboard } from "../../../../../providers/getHrmTrackerMemberProjectsProjectIdDashboard";

@Controller("/hrmTracker/member/projects/:projectId/dashboard")
export class HrmtrackerMemberProjectsDashboardController {
  /**
   * Retrieve comprehensive dashboard information for a specific project.
   *
   * This endpoint provides project members with a complete overview of the selected project, including project details, activity summaries, and relevant metrics. Only employees assigned to the project (either as regular members or project leads) can access this dashboard data.
   *
   * The dashboard includes project name, description, color code, current status, budget information, schedule dates, and recent activity logs. This provides a centralized view for team members to understand project progress and context without navigating through multiple screens.
   *
   * Related database schema: hrm_tracker_projects table contains project information including name, description, status, color, budget, start_date, end_date, and other project metadata.
   *
   * @param connection
   * @param projectId Target project's UUID identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_tracker_projects table by ID to retrieve project details. Join with hrm_tracker_project_members to verify the current employee is assigned to the project (either as member or project-lead). Include related hrm_tracker_timelogs and hrm_tracker_tasks for activity summary. Filter by project ID and employee assignment. Return project details with activity counts and recent status changes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string,
  ): Promise<IHrmTrackerProject> {
    try {
      return await getHrmTrackerMemberProjectsProjectIdDashboard({
        member,
        projectId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
