import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerTask } from "../../../../../api/structures/IHrmTrackerTask";
import { IPageIHrmTrackerTask } from "../../../../../api/structures/IPageIHrmTrackerTask";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmTrackerMemberProjectsProjectIdTasksTaskId } from "../../../../../providers/getHrmTrackerMemberProjectsProjectIdTasksTaskId";
import { patchHrmTrackerMemberProjectsProjectIdTasks } from "../../../../../providers/patchHrmTrackerMemberProjectsProjectIdTasks";
import { postHrmTrackerMemberProjectsProjectIdTasks } from "../../../../../providers/postHrmTrackerMemberProjectsProjectIdTasks";
import { putHrmTrackerMemberProjectsProjectIdTasksTaskId } from "../../../../../providers/putHrmTrackerMemberProjectsProjectIdTasksTaskId";

@Controller("/hrmTracker/member/projects/:projectId/tasks")
export class HrmtrackerMemberProjectsTasksController {
  /**
   * Create a new task within a project.
   *
   * This operation creates a new task under the specified project. Only employees who are members of the project (assigned as member or project-lead) can be assigned to the task. The creating user must have either the project:manage permission or be a project-lead for the specific project to create tasks.
   *
   * Tasks can be created as subtasks of an existing parent task, with only one level of nesting allowed. The assigned employee must already be assigned to the project as a project member. The task includes optional estimated hours, due date, priority, and status fields.
   *
   * Status and priority values are constrained to predefined categories. The task is created in the context of the specified project and inherits the project's organization for multi-tenancy isolation.
   *
   * Related operations:
   * - GET /projects/{projectId}/tasks - Retrieve list of tasks in the project
   * - GET /projects/{projectId}/tasks/{taskId} - Retrieve a specific task
   * - PUT /projects/{projectId}/tasks/{taskId} - Update a task
   *
   * @param connection
   * @param projectId UUID of the project to create the task in
   * @param body Task creation data including title, optional description, priority, status, assignment, estimated hours, due date, and optional parent task for subtasks
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new task record in hrm_tracker_tasks table.
   * Validate that:
   * 1. Project exists and is not deleted
   * 2. User has project:manage permission OR is project-lead for the project
   * 3. If assigned_employee_id provided, verify employee is project member
   * 4. If parent_task_id provided, verify parent task exists and belongs to same project
   * 5. Validate status and priority values against allowed enums
   * 6. Generate new UUID for task id
   * 7. Set created_at and updated_at to current timestamp
   * 8. Insert record with all provided fields
   * 9. Return created task with full details
   *
   * Handle error cases for invalid project, unauthorized access, non-member assignment, and invalid status/priority values.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string,
    @TypedBody()
    body: IHrmTrackerTask.ICreate,
  ): Promise<IHrmTrackerTask> {
    try {
      return await postHrmTrackerMemberProjectsProjectIdTasks({
        member,
        projectId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of tasks within a specific project.
   *
   * This operation allows employees assigned to a project (as members or project leads) to view tasks with comprehensive search, filtering, and sorting capabilities. Users can filter tasks by status, priority, assigned employee, and search by title or description using full-text search. Results are sorted according to the specified criteria and paginated for efficient data retrieval.
   *
   * Tasks in archived or completed projects are included in the list but cannot be edited. The endpoint enforces project-level access control, ensuring employees can only access tasks from projects they are assigned to. This operation supports both personal task views and organizational project task views depending on the user's role and permissions.
   *
   * @param connection
   * @param projectId Target project's UUID identifier
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_tracker_tasks table with pagination and filtering.
   * Filter by project_id from path parameter.
   * Apply search filters on title (gin_trgm_ops), description (gin_trgm_ops), status, priority, and assigned_employee_id.
   * Support pagination with configurable page size and cursor-based navigation.
   * Include status, priority, title, due_date, and assigned employee information in response.
   * Validate that the requesting user is a project member before returning results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string,
    @TypedBody()
    body: IHrmTrackerTask.IRequest,
  ): Promise<IPageIHrmTrackerTask.ISummary> {
    try {
      return await patchHrmTrackerMemberProjectsProjectIdTasks({
        member,
        projectId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific task within a project context.
   *
   * This operation retrieves a single task by its identifier within the specified project. It ensures the task belongs to the project identified by projectId and provides access to the task's complete details including status, priority, assignment, and timing information.
   *
   * Security and Permissions:
   *
   * - Employees can access tasks in projects they are assigned to as members or project leads
   * - Project leads and users with project:manage permission have full access to task information
   * - The operation validates that the task belongs to the specified project
   * - Soft-deleted tasks are not returned
   *
   * Task Assignment:
   *
   * - The assigned_employee_id field indicates which project member is responsible for the task
   * - Only employees who are members of the project can be assigned to tasks within that project
   * - Project leads and users with project:manage permission can view task assignments for all project members
   *
   * Related Operations:
   *
   * - PATCH /projects/{projectId}/tasks lists tasks within a project with filtering and pagination
   * - PUT /projects/{projectId}/tasks/{taskId} updates task details
   * - DELETE /projects/{projectId}/tasks/{taskId} removes a task from a project
   * - POST /projects/{projectId}/tasks creates a new task within a project
   * - GET /tasks/{taskId}/history retrieves the status change history for a specific task
   *
   * @param connection
   * @param projectId Target project's UUID identifier
   * @param taskId Target task's UUID identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_tracker_tasks table with the given projectId and taskId.
   * Join with hrm_tracker_projects to verify the task belongs to the specified project.
   * Check soft delete (deleted_at IS NULL).
   * Return the complete task record with all fields including assigned employee information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":taskId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string,
    @TypedParam("taskId")
    taskId: string,
  ): Promise<IHrmTrackerTask> {
    try {
      return await getHrmTrackerMemberProjectsProjectIdTasksTaskId({
        member,
        projectId,
        taskId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific task within a project.
   *
   * This operation allows updating task details including title, description, status, priority, estimated hours, and due date. Only employees assigned to the project (as members or project-lead) or users with project:manage permission can update tasks.
   *
   * The task must belong to the specified project. Status changes are automatically recorded in the task history for audit purposes. Estimated hours and due date can be adjusted as project requirements change.
   *
   * @param connection
   * @param projectId Target project's UUID identifier
   * @param taskId Target task's UUID identifier
   * @param body Task update request with all updatable fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update task in hrm_tracker_tasks table with provided fields.
   * Validate that project_id matches path projectId.
   * Validate assigned_employee_id is project member.
   * Validate status is one of allowed states.
   * Update estimated_hours and due_date fields if provided.
   * Return updated task with project reference.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":taskId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string,
    @TypedParam("taskId")
    taskId: string,
    @TypedBody()
    body: IHrmTrackerTask.IUpdate,
  ): Promise<IHrmTrackerTask> {
    try {
      return await putHrmTrackerMemberProjectsProjectIdTasksTaskId({
        member,
        projectId,
        taskId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
