import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerTask } from "../../../../../../api/structures/IHrmTrackerTask";
import { IHrmTrackerTaskHistory } from "../../../../../../api/structures/IHrmTrackerTaskHistory";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { getHrmTrackerMemberProjectsProjectIdTasksTaskIdTaskHistoriesTaskHistoryId } from "../../../../../../providers/getHrmTrackerMemberProjectsProjectIdTasksTaskIdTaskHistoriesTaskHistoryId";
import { patchHrmTrackerMemberProjectsProjectIdTasksTaskIdTaskHistories } from "../../../../../../providers/patchHrmTrackerMemberProjectsProjectIdTasksTaskIdTaskHistories";

@Controller(
  "/hrmTracker/member/projects/:projectId/tasks/:taskId/taskHistories",
)
export class HrmtrackerMemberProjectsTasksTaskhistoriesController {
  /**
   * Update a specific task's status within a project.
   *
   * This operation allows authorized users to change a task's status (open, in-progress, completed, closed). Only employees with project:manage permission or project leads for the task's project can change task status. The system automatically records who made the change, when it was made, and what the previous and new status values were.
   *
   * ## Authorization
   *
   * - Users with project:manage permission in the organization can change any task status
   * - Project leads for the task's project can change task status
   * - Regular project members cannot change task status
   *
   * ## Business Rules
   *
   * - Task status must be one of: open, in-progress, completed, closed
   * - Status change is only allowed if the project is active (not archived or completed)
   * - The system automatically creates a history record with old and new status values
   * - The task must belong to the specified project
   *
   * ## Related Operations
   *
   * - GET /projects/{projectId}/tasks to list tasks in a project
   * - GET /projects/{projectId}/tasks/{taskId} to retrieve task details
   * - GET /projects/{projectId}/tasks/{taskId}/taskHistories to view status change history
   *
   * @param connection
   * @param projectId Target project's ID
   * @param taskId Target task's ID
   * @param body Task status update request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Find the project by ID and verify it exists and is active. Find the task by ID and verify it belongs to the project. Verify the user has permission to change task status (project:manage or project lead). Update task status. Create a new history record with old status and new status. Return the updated task.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string,
    @TypedParam("taskId")
    taskId: string,
    @TypedBody()
    body: IHrmTrackerTask.IUpdate,
  ): Promise<IHrmTrackerTask> {
    try {
      return await patchHrmTrackerMemberProjectsProjectIdTasksTaskIdTaskHistories(
        {
          member,
          projectId,
          taskId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific task status change history record.
   *
   * This operation fetches detailed information about a single task status change event from the audit trail. Each task history entry captures when a task's status was modified, including the previous and new status values, the employee who made the change, and the exact timestamp of the modification.
   *
   * The operation supports the following task status values: open, in-progress, completed, and closed. The history provides a complete audit trail showing the evolution of a task's status over time.
   *
   * This operation excludes soft-deleted records (where deleted_at is not null). Only active history records are returned.
   *
   * Authorization: Employees with project:manage permission or employees assigned to the project (as members or project-lead) can retrieve task history records for tasks within their organization.
   *
   * @param connection
   * @param projectId Target project's unique identifier
   * @param taskId Target task's unique identifier
   * @param taskHistoryId Target task history's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_tracker_task_histories table by taskHistoryId (primary key).
   * Join with hrm_tracker_employees for actor information.
   * Verify employee has project:manage permission or is assigned to the project containing the task.
   * Filter by organization_id to ensure multi-tenancy isolation.
   * Return complete task history record with all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":taskHistoryId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string,
    @TypedParam("taskId")
    taskId: string,
    @TypedParam("taskHistoryId")
    taskHistoryId: string,
  ): Promise<IHrmTrackerTaskHistory> {
    try {
      return await getHrmTrackerMemberProjectsProjectIdTasksTaskIdTaskHistoriesTaskHistoryId(
        {
          member,
          projectId,
          taskId,
          taskHistoryId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
