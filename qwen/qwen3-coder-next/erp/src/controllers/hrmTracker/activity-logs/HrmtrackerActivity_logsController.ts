import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTrackerActivityLog } from "../../../api/structures/IHrmTrackerActivityLog";
import { IPageIHrmTrackerActivityLog } from "../../../api/structures/IPageIHrmTrackerActivityLog";
import { getHrmTrackerActivityLogsActivityLogId } from "../../../providers/getHrmTrackerActivityLogsActivityLogId";
import { patchHrmTrackerActivityLogs } from "../../../providers/patchHrmTrackerActivityLogs";

@Controller("/hrmTracker/activity-logs")
export class HrmtrackerActivity_logsController {
  /**
   * Retrieve a specific activity log entry by its unique identifier.
   *
   * This operation fetches a single activity log entry from the system's audit trail. The activity log records significant business actions such as employee invitations, deactivations, contract changes, project lifecycle events, task status changes, timesheet workflow actions, and role assignments.
   *
   * The operation enforces strict authorization: only users with org:manage permission can view activity logs. Users without this permission will receive a permission denied response. All activity log entries are strictly scoped to the currently selected organization context.
   *
   * The target entity information shows what was affected by the action and includes the entity type (e.g., 'employee', 'contract', 'project', 'task', 'timesheet', 'role', 'pending_invitation', 'organization') and its unique identifier. The action_type field contains one of the predefined action types that were generated by the system in response to business events.
   *
   * @param connection
   * @param activityLogId Target activity log's UUID identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query hrm_tracker_activity_logs table by UUID ID.
   * Apply org:manage authorization check before retrieving.
   * Join with hrm_tracker_members or hrm_tracker_guests for actor details.
   * Return complete activity log record with all fields including target_entity_type, target_entity_id, action_type, and created_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":activityLogId")
  public async at(
    @TypedParam("activityLogId")
    activityLogId: string,
  ): Promise<IHrmTrackerActivityLog> {
    try {
      return await getHrmTrackerActivityLogsActivityLogId({
        activityLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of activity log entries with filtering and sorting capabilities.
   *
   * This operation provides comprehensive filtering options for activity logs, allowing administrators to search by actor (member or guest), target entity type and ID, action type, and date ranges. The activity log serves as an audit trail for accountability, capturing all significant business actions within an organization.
   *
   * Security and Authorization: Only users with org:manage permission can access activity logs. This ensures that sensitive audit information is restricted to authorized personnel only. The system automatically generates all activity log entries in response to key organizational actions such as employee invitations, contract changes, project status updates, task status changes, timesheet workflow actions, and role assignments.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query hrm_tracker_activity_logs table with pagination and filtering.
   * Apply filters on actorMember/actorGuest (if exists), target_entity_type, target_entity_id, action_type, and created_at date range.
   * Support sorting by created_at (default descending for newest first).
   * Return paginated results with IPageIHrmTrackerActivityLog.ISummary structure.
   * Authorization check: org:manage permission required for access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IHrmTrackerActivityLog.IRequest,
  ): Promise<IPageIHrmTrackerActivityLog.ISummary> {
    try {
      return await patchHrmTrackerActivityLogs({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
