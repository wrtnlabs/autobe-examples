/**
 * Retrieve an aggregated activity summary for a specific project.
 *
 * This operation returns a summary of all activity logs related to a specific project, providing insights into project activity patterns over time. The summary includes aggregated data such as total activity count, activity breakdown by type, and timestamps of first and last activities.
 *
 * **Authorization:**
 * - Members with project:view permission can view activity summaries for projects they are assigned to
 * - Deactivated employees retain visibility of their historical project activity summaries
 * - The operation respects organization data isolation - activity logs from other organizations are never exposed
 *
 * **Activity Log Types:**
 * The summary includes all activity log types related to the project, including:
 * - Employee management actions (invited, deactivated, reactivated)
 * - Contract changes (created, edited)
 * - Project lifecycle events (created, archived, completed, deleted)
 * - Task status changes
 * - Timesheet workflow actions (submitted, approved, rejected)
 * - Role assignments and changes
 *
 * **Data Persistence:**
 * Activity logs are preserved even when projects are archived or completed, ensuring complete historical visibility. Deactivated employees' activity contributions remain in the summary.
 *
 * @param props.connection
 * @param props.projectId Target project's unique identifier
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query hrm_tracker_activity_logs table filtered by hrm_tracker_projects.id.
 * Join with hrm_tracker_employees and hrm_tracker_members to include actor information.
 * Group activity logs by date and action_type to compute summary statistics.
 * Return total count, activity breakdown by type, date range of activities, and most recent activity timestamp.
 * Apply organization-level data isolation to ensure only activities within the member's current organization context are returned.
 * Handle archived/completed projects by including all historical activity logs.
 * Return 404 if project does not exist or member lacks permission to view it.
 * @path /hrmTracker/member/projects/:projectId/activity-summary
 * @accessor api.functional.hrmTracker.member.projects.activity_summary.summary
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function summary(
  connection: IConnection,
  props: summary.Props,
): Promise<summary.Response> {
  return true === connection.simulate
    ? summary.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...summary.METADATA,
          path: summary.path(props),
          status: null,
        },
      );
}
export namespace summary {
  export type Props = {
    /**
     * Target project's unique identifier
     */
    projectId: string;
  };
  export type Response = IHrmTrackerProject.ISummaryActivity;

  export const METADATA = {
    method: "GET",
    path: "/hrmTracker/member/projects/:projectId/activity-summary",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/hrmTracker/member/projects/${encodeURIComponent(props.projectId ?? "null")}/activity-summary`;
  export const random = (): IHrmTrackerProject.ISummaryActivity =>
    typia.random<IHrmTrackerProject.ISummaryActivity>();
  export const simulate = (
    connection: IConnection,
    props: summary.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: summary.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("projectId")(() => typia.assert(props.projectId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
