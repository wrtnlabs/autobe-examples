/**
 * Retrieve a specific activity log entry by its unique identifier.
 *
 * This operation fetches a single activity log entry from the system's audit trail. The activity log records significant business actions such as employee invitations, deactivations, contract changes, project lifecycle events, task status changes, timesheet workflow actions, and role assignments.
 *
 * The operation enforces strict authorization: only users with org:manage permission can view activity logs. Users without this permission will receive a permission denied response. All activity log entries are strictly scoped to the currently selected organization context.
 *
 * The target entity information shows what was affected by the action and includes the entity type (e.g., 'employee', 'contract', 'project', 'task', 'timesheet', 'role', 'pending_invitation', 'organization') and its unique identifier. The action_type field contains one of the predefined action types that were generated by the system in response to business events.
 *
 * @param props.connection
 * @param props.activityLogId Target activity log's UUID identifier
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query hrm_tracker_activity_logs table by UUID ID.
 * Apply org:manage authorization check before retrieving.
 * Join with hrm_tracker_members or hrm_tracker_guests for actor details.
 * Return complete activity log record with all fields including target_entity_type, target_entity_id, action_type, and created_at.
 * @path /hrmTracker/activity-logs/:activityLogId
 * @accessor api.functional.hrmTracker.activity_logs.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Target activity log's UUID identifier
     */
    activityLogId: string;
  };
  export type Response = IHrmTrackerActivityLog;

  export const METADATA = {
    method: "GET",
    path: "/hrmTracker/activity-logs/:activityLogId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/hrmTracker/activity-logs/${encodeURIComponent(props.activityLogId ?? "null")}`;
  export const random = (): IHrmTrackerActivityLog =>
    typia.random<IHrmTrackerActivityLog>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("activityLogId")(() => typia.assert(props.activityLogId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

