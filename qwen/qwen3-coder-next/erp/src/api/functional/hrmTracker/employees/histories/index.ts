import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia from "typia";

import { IHrmTrackerEmployeeHistory } from "../../../../structures/IHrmTrackerEmployeeHistory";

/**
 * Retrieve the complete audit history of changes made to a specific employee record.
 *
 * This operation returns a chronological list of historical snapshots capturing all significant changes to the employee record including role assignments, status transitions, department changes, and position updates. Each history entry represents the employee state immediately after a change was made, providing a complete point-in-time audit trail for compliance and review purposes.
 *
 * The endpoint filters historical records by the specified employee identifier and returns them in reverse chronological order with the most recent changes appearing first. Users can navigate through the history using pagination controls to review historical states at any point in time.
 *
 * @param props.connection
 * @param props.employeeId Target employee's unique identifier (UUID)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query hrm_tracker_employee_histories table filtered by employee_id path parameter.
 * Order by created_at DESC to show most recent changes first.
 * Support pagination with configurable page size.
 * Return paginated list of historical employee record states.
 * Include employee, changedBy, organization, role, and department relationship data.
 * @path /hrmTracker/employees/:employeeId/histories
 * @accessor api.functional.hrmTracker.employees.histories.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Target employee's unique identifier (UUID)
     */
    employeeId: string;
  };
  export type Response = IHrmTrackerEmployeeHistory;

  export const METADATA = {
    method: "GET",
    path: "/hrmTracker/employees/:employeeId/histories",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/hrmTracker/employees/${encodeURIComponent(props.employeeId ?? "null")}/histories`;
  export const random = (): IHrmTrackerEmployeeHistory =>
    typia.random<IHrmTrackerEmployeeHistory>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("employeeId")(() => typia.assert(props.employeeId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
