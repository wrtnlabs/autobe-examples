/**
 * # User Registration (Join)
 *
 * This endpoint allows new users to register for the Todo application by providing their email address and password. Upon successful registration, a new user account is created in the system and the user receives authentication tokens to access protected resources.
 *
 * ## Purpose and Functionality
 *
 * The registration endpoint creates a new user account with the provided email and password. It performs validation to ensure:
 *
 * - Email format is valid and follows standard email patterns
 * - Password meets minimum security requirements (at least 8 characters)
 * - Email address is unique and not already registered in the system
 * - All required fields are provided and valid
 *
 * ## Implementation Details
 *
 * The implementation follows these steps:
 *
 * 1. **Input Validation**: The system validates the provided email and password against format requirements and business rules
 * 2. **Email Uniqueness Check**: The system verifies that the provided email address is not already in use by another user
 * 3. **Password Hashing**: The plain-text password is securely hashed using bcrypt with an appropriate cost factor before storage
 * 4. **User Record Creation**: A new user record is created in the todo_app_users table with the email, hashed password, and automatically generated user ID
 * 5. **Token Generation**: Authentication tokens (access and refresh) are generated and returned to the client
 * 6. **Initial Profile Setup**: Default profile information is initialized based on the email address
 *
 * ## Authentication Workflow Integration
 *
 * This registration endpoint is the starting point of the authentication workflow:
 *
 * - After successful registration, users receive authentication tokens that can be used for subsequent API calls
 * - The generated tokens follow the standard JWT pattern with appropriate expiration times (30 minutes for access tokens, 30 days for refresh tokens)
 * - Registered users can then proceed to use the login endpoint if they need to re-authenticate
 *
 * ## Security Considerations
 *
 * The registration process implements several security measures:
 *
 * - Passwords are never stored in plain text and are always hashed using bcrypt
 * - Email validation prevents malformed or potentially malicious email addresses
 * - Unique email constraint prevents duplicate account creation
 * - No information about existing users is revealed in error responses to prevent email enumeration attacks
 *
 * ## Related Operations
 *
 * - **Login**: After registration, users can use the `/auth/user/login` endpoint to authenticate and receive new tokens
 * - **Token Refresh**: If access tokens expire, users can use the `/auth/user/refresh` endpoint to obtain new tokens using their refresh token
 *
 * ## Request and Response Format
 *
 * The endpoint accepts a JSON object with email and password fields and returns a JSON object containing user information and authentication tokens.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body User registration request containing email and password
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor user
 * @x-autobe-specification Implement user registration by creating a new user record in the todo_app_users table. Hash the password using bcrypt, validate email format and uniqueness, create initial session tokens, and return the authorized response with access and refresh tokens.
 * @path /todoApp/auth/user/join
 * @accessor api.functional.todoApp.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
