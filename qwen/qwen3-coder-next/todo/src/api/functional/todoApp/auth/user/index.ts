import { ITodoAppUser } from "../../../../structures/ITodoAppUser";

/**
 * User registration endpoint that creates a new account in the Todo application. The endpoint accepts email address and password, validates the email format and uniqueness, enforces password strength requirements, and creates a new user account in active state. The password is securely hashed before storage using bcrypt algorithm to ensure security.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration information including email address and password
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor user
 * @x-autobe-specification Register a new user account with email and password. Validate email format and uniqueness, hash the password using bcrypt, and create a new user record in the database with active status.
 * @path /todoApp/auth/user/join
 * @accessor api.functional.todoApp.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /**
     * Registration information including email address and password
     */
    body: ITodoAppUser.IJoin;
  };
  export type Body = ITodoAppUser.IJoin;
  export type Response = ITodoAppUser.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/auth/user/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/auth/user/join";
  export const random = (): ITodoAppUser.IAuthorized =>
    typia.random<ITodoAppUser.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

