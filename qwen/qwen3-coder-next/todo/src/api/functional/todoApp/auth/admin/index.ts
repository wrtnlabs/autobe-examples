/**
 * Register a new system administrator account.
 *
 * This endpoint creates a new admin account in the todo_app_admins table. It requires a unique email address and a securely hashed password. The system validates the email format, checks for uniqueness, and creates the admin record with proper timestamps.
 *
 * Security Considerations:
 * - Password must meet complexity requirements
 * - Email must be unique and valid format
 * - Password is hashed using bcrypt before storage
 * - Initial account state is active (deleted_at = NULL)
 *
 * Database Schema:
 * The operation creates a record in the todo_app_admins table with:
 * - id: UUID generated by the system
 * - email: User-provided email address
 * - password_hash: bcrypt-hashed password
 * - created_at: Current timestamp (timestamptz)
 * - updated_at: Current timestamp (timestamptz)
 * - deleted_at: NULL (active account)
 *
 * Error Handling:
 * - 400: Invalid email format or password policy violation
 * - 409: Duplicate email address
 * - 500: Database insertion failure
 *
 * Related Operations:
 * - Login: After registration, user can authenticate with email/password
 * - Account deletion: Can permanently remove admin account if needed
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration request containing admin credentials
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Admin registration endpoint. Creates new admin account with email and password. Validates email format and uniqueness, hashes password with bcrypt, creates admin record, and returns JWT tokens.
 * @path /todoApp/auth/admin/join
 * @accessor api.functional.todoApp.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
