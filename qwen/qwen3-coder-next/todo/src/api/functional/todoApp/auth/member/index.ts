/**
 * Register a new member account by creating a new member record with email and password hash. This operation creates the associated user account and profile records required for member authentication. Upon successful registration, the system generates JWT access and refresh tokens for the newly created member session. This is the first step in the authentication workflow and enables the member to access protected resources.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration information for a new member account
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Handle member registration by creating new member account with email and password hash. Creates associated user account and profile records. Returns JWT tokens for session.
 * @path /todoApp/auth/member/join
 * @accessor api.functional.todoApp.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /**
     * Registration information for a new member account
     */
    body: ITodoAppMemberSession.IJoin;
  };
  export type Body = ITodoAppMemberSession.IJoin;
  export type Response = ITodoAppMemberSession.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/auth/member/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/auth/member/join";
  export const random = (): ITodoAppMemberSession.IAuthorized =>
    typia.random<ITodoAppMemberSession.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

