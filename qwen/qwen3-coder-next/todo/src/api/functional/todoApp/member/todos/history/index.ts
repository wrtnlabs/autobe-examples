import { ITodoAppEditHistoryEntry } from "../../../../../structures/ITodoAppEditHistoryEntry";

/**
 * Retrieve edit history for a specific todo.
 *
 * This operation returns all edit history entries for the given todo, sorted from most recent to oldest by timestamp. Each history entry contains timestamps and changed field values with their previous and new states.
 *
 * Security: Only the owner of the todo can view its history. Users cannot access history for other users' todos under any circumstances.
 *
 * The operation returns history entries sorted by creation timestamp in descending order (most recent first).
 *
 * @param props.connection
 * @param props.todoId Target todo's ID
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query todo_app_edit_history_entries table joined with todo_app_todos to retrieve edit history for the specified todo. Filter by todo_app_todos.id = todoId and todo_app_todos.todo_app_user_id = current user's ID to enforce ownership. Sort results by created_at in descending order (most recent first). Return list of history entries sorted by creation timestamp.
 * @path /todoApp/member/todos/:todoId/history
 * @accessor api.functional.todoApp.member.todos.history.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Target todo's ID
     */
    todoId: string;
  };
  export type Response = ITodoAppEditHistoryEntry;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/member/todos/:todoId/history",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/member/todos/${encodeURIComponent(props.todoId ?? "null")}/history`;
  export const random = (): ITodoAppEditHistoryEntry =>
    typia.random<ITodoAppEditHistoryEntry>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
