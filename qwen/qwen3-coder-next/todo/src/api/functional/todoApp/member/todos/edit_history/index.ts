import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IPageITodoAppTodoEdit } from "../../../../../structures/IPageITodoAppTodoEdit";

/**
 * Retrieve the complete edit history for a specific todo item.
 *
 * This endpoint provides a chronological record of all field-level changes made to a todo item. Each history entry captures exactly what values were changed during an edit operation, including the previous value and new value for each modified field (title, description, start date, and due date).
 *
 * The edit history is automatically created whenever a user modifies any editable field of a todo. Only the todo owner can access its edit history, ensuring complete data isolation between users. This provides an audit trail of all changes made to the todo item over time.
 *
 * History entries are returned in reverse chronological order (most recent first), allowing users to quickly see the latest changes. Each entry includes the timestamp of the edit and detailed information about which fields were changed and what the value changes were.
 *
 * **Important**: This operation follows user-level isolation - the system verifies the todo belongs to the current authenticated user before returning history. Only todos not marked with `is_trashed = true` should be accessible through this endpoint (though the todo may still have `deleted_at` set for hard deletion scenarios).
 *
 * @param props.connection
 * @param props.todoId Target todo's ID
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query todo_app_todo_edits table filtered by todo_id from path parameter.
 * Apply user-level isolation by verifying the todo belongs to the current authenticated user before querying history.
 * Sort results by edited_at descending (most recent first).
 * Return paginated results using offset/limit pagination.
 * Include all history fields: id, todo_id, edited_at, previous_title, new_title, previous_description, new_description, previous_start_date, new_start_date, previous_due_date, new_due_date, created_at, updated_at.
 * @path /todoApp/member/todos/:todoId/edit-history
 * @accessor api.functional.todoApp.member.todos.edit_history.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Target todo's ID
     */
    todoId: string;
  };
  export type Response = IPageITodoAppTodoEdit;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/member/todos/:todoId/edit-history",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/member/todos/${encodeURIComponent(props.todoId ?? "null")}/edit-history`;
  export const random = (): IPageITodoAppTodoEdit =>
    typia.random<IPageITodoAppTodoEdit>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
