import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia from "typia";

import { ITodoAppTodo } from "../../../../../structures/ITodoAppTodo";

/**
 * Toggle a todo's completion status for the current user.
 *
 * This operation allows members to toggle the completion status of their own todos. The completion status toggle is performed by updating the `is_complete` field based on the toggle request body parameter.
 *
 * Security and authorization:
 * - Only the owner of the todo can toggle its completion status
 * - Attempting to toggle completion status of another user's todo will be rejected
 * - Completion status is part of the todo's core state and reflects task progress
 *
 * The operation supports both marking as complete (setting is_complete to true) and marking as incomplete (setting is_complete to false).
 *
 * Related operations:
 * - GET /todos/{todoId} - Retrieve the current completion status
 * - GET /todos - List todos with filtering by completion status
 * - PATCH /todos/{todoId}/complete - Directly mark as complete
 * - PATCH /todos/{todoId}/incomplete - Directly mark as incomplete
 *
 * @param props.connection
 * @param props.todoId Target todo's unique identifier
 * @param props.body Toggle completion status request
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Update the is_complete field of todo_app_todos table by setting it to the opposite of its current value based on the request body parameter.
 *
 * 1. Retrieve the todo by id and validate ownership (todo_app_user_id must match current user's id)
 * 2. Update the is_complete field based on the toggle request body parameter
 * 3. Update the updated_at timestamp to current time
 * 4. Return the updated todo record
 *
 * Implement proper error handling for:
 * - Todo not found
 * - Todo ownership validation failure
 * - Invalid toggle request body
 * @path /todoApp/member/todos/:todoId/toggle-complete
 * @accessor api.functional.todoApp.member.todos.toggle_complete.toggleComplete
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function toggleComplete(
  connection: IConnection,
  props: toggleComplete.Props,
): Promise<toggleComplete.Response> {
  return true === connection.simulate
    ? toggleComplete.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...toggleComplete.METADATA,
          path: toggleComplete.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace toggleComplete {
  export type Props = {
    /**
     * Target todo's unique identifier
     */
    todoId: string;

    /**
     * Toggle completion status request
     */
    body: ITodoAppTodo.IToggleComplete;
  };
  export type Body = ITodoAppTodo.IToggleComplete;
  export type Response = ITodoAppTodo.IUpdate;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/member/todos/:todoId/toggle-complete",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todoApp/member/todos/${encodeURIComponent(props.todoId ?? "null")}/toggle-complete`;
  export const random = (): ITodoAppTodo.IUpdate =>
    typia.random<ITodoAppTodo.IUpdate>();
  export const simulate = (
    connection: IConnection,
    props: toggleComplete.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: toggleComplete.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
