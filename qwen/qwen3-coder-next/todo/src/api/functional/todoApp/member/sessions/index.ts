/**
 * Retrieve detailed information about a specific session.
 *
 * This endpoint provides comprehensive details about a member's active session, including authentication metadata, connection information, and session validity period. It is used to inspect current session status for security auditing or troubleshooting purposes.
 *
 * Sessions contain sensitive authentication tokens and connection metadata. Access is restricted to the session owner or administrators.
 *
 * @param props.connection
 * @param props.sessionId Unique identifier of the session to retrieve
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query todo_app_member_sessions table by session ID. Return session details including member reference, IP, user agent, tokens, and expiration timestamps.
 * @path /todoApp/member/sessions/:sessionId
 * @accessor api.functional.todoApp.member.sessions.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the session to retrieve
     */
    sessionId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppMemberSession;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/member/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/member/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): ITodoAppMemberSession =>
    typia.random<ITodoAppMemberSession>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
