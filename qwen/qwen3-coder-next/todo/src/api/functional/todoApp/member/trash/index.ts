/**
 * Permanently delete a todo from the trash.
 *
 * This operation permanently removes a todo from the trash (soft-deleted state) and all associated edit history entries. Once permanently deleted, the todo and its edit history cannot be recovered.
 *
 * Only members can access their own todos' trash entries. The system enforces user isolation at the application level, ensuring members can only permanently delete their own deleted todos.
 *
 * This operation is idempotent - attempting to permanently delete a todo that has already been permanently deleted will result in a 404 Not Found response.
 *
 * For restoring a todo from trash instead of permanent deletion, use POST /trash/{id}/restore.
 *
 * @param props.connection
 * @param props.todoId Target todo's unique identifier
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Permanently delete a todo from trash:
 * 1. Verify the todo exists and belongs to the current user
 * 2. Verify the todo is in trash state (is_trashed = true)
 * 3. Verify the todo has not been permanently deleted already
 * 4. Delete all associated edit history entries for this todo
 * 5. Permanently delete the todo record from the database
 * 6. Return 204 No Content on success
 * 7. Return 404 Not Found if todo doesn't exist or already permanently deleted
 * 8. Handle edge case: if todo was restored from trash and then deleted again, follow same flow
 * @path /todoApp/member/trash/:todoId
 * @accessor api.functional.todoApp.member.trash.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
