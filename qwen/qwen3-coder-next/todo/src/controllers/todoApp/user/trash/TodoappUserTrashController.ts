import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageITodoAppTodo } from "../../../../api/structures/IPageITodoAppTodo";
import { ITodoAppTodo } from "../../../../api/structures/ITodoAppTodo";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { deleteTodoAppUserTrashTodoId } from "../../../../providers/deleteTodoAppUserTrashTodoId";
import { patchTodoAppUserTrash } from "../../../../providers/patchTodoAppUserTrash";
import { patchTodoAppUserTrashTodoIdRestore } from "../../../../providers/patchTodoAppUserTrashTodoIdRestore";

@Controller("/todoApp/user/trash")
export class TodoappUserTrashController {
  /**
   * Retrieve and manage deleted todos (trash) with advanced filtering and pagination.
   *
   * This operation provides comprehensive trash management capabilities allowing users to view their deleted todos, apply filters, and perform bulk operations on trash items.
   *
   * The endpoint supports pagination with configurable page size and supports filtering by completion status at deletion time. All todos returned have is_deleted = true (soft-deleted items) and belong to the authenticated user.
   *
   * Users can view their trash items with essential information including the title, completion status at deletion time, original start date, original due date, and deletion timestamp.
   *
   * This operation directly accesses the todo_app_todos table where is_deleted = true. Deleted todos remain in the database with is_deleted flag set and are excluded from normal todo list views until permanently deleted or restored.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for trash management
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_app_todos table with is_deleted = true filter to retrieve deleted todos only.
   * Apply pagination with configurable page and limit parameters.
   * Support filtering by completion status (is_complete) at the time of deletion.
   * Sort results by deletion timestamp (deleted_at) in descending order by default.
   * Return paginated results with total count and proper pagination metadata.
   * Handle edge cases for null date values when sorting.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTodo.IRequest,
  ): Promise<IPageITodoAppTodo.ISummary> {
    try {
      return await patchTodoAppUserTrash({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Restore a deleted todo from trash
   *
   * This operation restores a previously deleted todo by removing the soft-delete marker and making it visible in the normal todo list again. The restoration process preserves all original todo data including completion status, description, and date fields, while maintaining all edit history entries.
   *
   * The operation verifies user ownership by checking the authenticated user ID before allowing restoration. If the todo exists in the user's trash, it is moved back to the active todo list immediately with all original metadata preserved. The todo's completion status, start date, due date, and all edit history remain unchanged during the restoration process.
   *
   * This endpoint is part of the trash management system that allows users to recover accidentally deleted todos or intentionally restore items from their trash. Users can also permanently delete todos from trash if they no longer need them.
   *
   * @param connection
   * @param todoId ID of the todo to restore from trash
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Restore a todo by removing soft-delete marker.
   * Query todo_app_todos table with user ID filter and todo ID.
   * Verify todo exists and is marked as deleted (isDeleted = true).
   * Update todo to set isDeleted = false and updatedAt = NOW().
   * Return restored todo with all original data preserved.
   * Handle 404 error if todo not found or not owned by user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":todoId/restore")
  public async restore(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string,
  ): Promise<ITodoAppTodo> {
    try {
      return await patchTodoAppUserTrashTodoIdRestore({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a todo from trash.
   *
   * This operation permanently removes a todo that is currently in the user's trash. Unlike soft deletion which marks todos as deleted, this operation completely removes the todo record from the database along with all associated edit history entries.
   *
   * The operation verifies that the requested todo exists in trash and belongs to the authenticated user. If the todo does not exist in trash or does not belong to the current user, the operation returns an appropriate error without revealing whether the todo ever existed.
   *
   * @param connection
   * @param todoId Target todo's ID in UUID format
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Delete todo from trash completely by removing todo record and all associated edit history entries.
   * Query todo_app_todos table where id matches todoId and isDeleted is true.
   * Verify user ownership by checking userId matches authenticated user from JWT token.
   * If verification fails, return 404 error without revealing resource existence.
   * If verification succeeds, delete todo record and all associated edit history entries from todo_app_todo_histories table.
   * Return success confirmation response with status message.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserTrashTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
