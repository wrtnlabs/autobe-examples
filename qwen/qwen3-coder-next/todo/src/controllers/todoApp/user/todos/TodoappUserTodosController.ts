import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageITodoAppTodo } from "../../../../api/structures/IPageITodoAppTodo";
import { ITodoAppTodo } from "../../../../api/structures/ITodoAppTodo";
import { ITodoAppTodoHistory } from "../../../../api/structures/ITodoAppTodoHistory";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { deleteTodoAppUserTodosTodoId } from "../../../../providers/deleteTodoAppUserTodosTodoId";
import { getTodoAppUserTodosTodoId } from "../../../../providers/getTodoAppUserTodosTodoId";
import { getTodoAppUserTodosTodoIdHistory } from "../../../../providers/getTodoAppUserTodosTodoIdHistory";
import { patchTodoAppUserTodos } from "../../../../providers/patchTodoAppUserTodos";
import { postTodoAppUserTodos } from "../../../../providers/postTodoAppUserTodos";
import { putTodoAppUserTodosTodoId } from "../../../../providers/putTodoAppUserTodosTodoId";

@Controller("/todoApp/user/todos")
export class TodoappUserTodosController {
  /**
   * Retrieve a single todo item by its unique identifier.
   *
   * This operation fetches complete details for a specific todo item including its title, description, optional start and due dates, completion status, and timestamps. The operation enforces strict user privacy - users can only access their own todo items and receive a 404 error for todos owned by other users.
   *
   * The operation handles both active todos (is_deleted = false) and deleted todos in the trash (is_deleted = true). When a todo is soft-deleted, it remains accessible via this endpoint until permanently deleted, allowing for potential restoration scenarios.
   *
   * @param connection
   * @param todoId Unique identifier of the todo item (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_app_todos table by id and authenticated user ID from JWT token.
   * Verify ownership by matching todo_app_user_id with authenticated user ID.
   * Return full todo record with all fields including title, description, start_date, due_date, is_complete, is_deleted, created_at, updated_at, and deleted_at.
   * Handle both active (is_deleted = false) and trash (is_deleted = true) todos.
   * Return 404 for non-existent or foreign owned todos to prevent information leakage.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string,
  ): Promise<ITodoAppTodo> {
    try {
      return await getTodoAppUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo item's details.
   *
   * This operation allows users to modify the title, description, start date, and due date of their own todo items. The todo must belong to the authenticated user, and all changes are subject to validation rules including title length constraints and date format requirements.
   *
   * The operation automatically creates an edit history entry to track all changes made to the todo item. Every field change is recorded in the history with timestamps and previous values for audit trail purposes.
   *
   * Users can only edit their own todos. Attempts to edit another user's todo will result in a 404 error for security purposes (to prevent probing for other users' data existence).
   *
   * @param connection
   * @param todoId Unique identifier of the todo item to update (UUID format)
   * @param body Update request containing the fields to modify for the todo item. All fields are optional - only provided fields will be updated.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo by ID with user_id filter from JWT token.
   * Validate that todo exists and belongs to authenticated user.
   * Apply partial updates for all provided fields.
   * Create edit history entry with previous values before updating.
   * Return updated todo with all fields.
   * Handle validation errors for invalid title (empty, whitespace-only) and date formats.
   * Return 404 if todo not found or belongs to different user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string,
    @TypedBody()
    body: ITodoAppTodo.IUpdate,
  ): Promise<ITodoAppTodo> {
    try {
      return await putTodoAppUserTodosTodoId({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete a specific todo item and move it to the user's trash.
   *
   * This operation marks a todo item as deleted without permanently removing it from the database. The todo's data remains intact and can be restored later if needed. Once deleted, the todo automatically disappears from normal todo list views and becomes available in the user's personal trash folder.
   *
   * The deletion is performed by setting the is_deleted flag to true and recording the deletion timestamp in the deleted_at field. All other todo fields (title, description, dates, completion status) are preserved in their current state. The todo remains in the database with these markers until the user either restores it or permanently deletes it from the trash.
   *
   * Each user can only soft-delete their own todos. The system automatically enforces user ownership through the authenticated user's ID, preventing access to other users' todo items.
   *
   * @param connection
   * @param todoId Target todo's UUID identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Soft-delete todo from todo_app_todos table by setting is_deleted = true and deleted_at = current timestamp.
   *
   * Parameters:
   * - Extract todoId from path parameter (UUID format)
   * - Validate todoId is valid UUID
   * - Query todo where id = todoId AND todo_app_user_id = authenticated userId
   * - If not found, throw 404 error
   * - Update todo: set is_deleted = true, deleted_at = now()
   * - Return success response with message
   *
   * Error handling:
   * - 404 if todo not found or belongs to another user
   * - 400 if todoId is invalid UUID format
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new todo item for the authenticated user.
   *
   * This endpoint allows users to create personal task items with title, optional description, and optional date fields. The system automatically generates unique IDs, sets initial timestamps, and enforces user privacy boundaries by associating the todo with the authenticated user's account.
   *
   * All created todos start with isComplete = false and isDeleted = false. Users can only create todos for themselves - the system automatically associates the todo with the authenticated user's user_id from the JWT token.
   *
   * @param connection
   * @param body Todo creation data including title and optional fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Create new todo item in the todo_app_todos table.
   * 1. Extract user_id from JWT authentication token
   * 2. Validate request body fields against schema constraints
   * 3. Generate unique UUID for todo id
   * 4. Set createdAt and updatedAt to current timestamp
   * 5. Set isComplete = false, isDeleted = false as defaults
   * 6. Insert record into database
   * 7. Return created todo with all fields including generated timestamps
   *
   * Validation rules:
   * - title: required, non-empty string (1-255 characters)
   * - description: optional, 0-10,000 characters if provided
   * - startDate: optional, ISO 8601 datetime format
   * - dueDate: optional, ISO 8601 datetime format
   *
   * Error handling:
   * - Invalid user authentication: 401 Unauthorized
   * - Invalid request body: 400 Bad Request
   * - Database error: 500 Internal Server Error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTodo.ICreate,
  ): Promise<ITodoAppTodo> {
    try {
      return await postTodoAppUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of todo items for the authenticated user.
   *
   * This operation provides advanced search and filtering capabilities including status filtering (all, complete, incomplete), sorting by multiple fields (createdAt, startDate, dueDate), and comprehensive pagination support. The response includes only todos owned by the authenticated user, ensuring complete data isolation and privacy.
   *
   * Supports flexible sorting options with configurable order (ascending/descending) for different date fields. The system handles NULL date values appropriately in sorting operations, treating them as 'end of range' for proper ordering.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_app_todos table with user-specific filtering using JWT-authenticated user_id.
   * Apply status filter (is_complete = true/false for complete/incomplete, no filter for all).
   * Support sorting by created_at, start_date, due_date with configurable order.
   * Handle NULL date values by using COALESCE or CASE statements for proper null sorting.
   * Implement cursor-based pagination for large result sets.
   * Return TodoAppTodo.ISummary type with essential fields optimized for list displays.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTodo.IRequest,
  ): Promise<IPageITodoAppTodo.ISummary> {
    try {
      return await patchTodoAppUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete edit history for a specific todo item.
   *
   * This operation returns all historical changes made to a todo item, showing what fields were modified and their previous values. Each history entry captures the exact timestamp of when the edit occurred (edited_at) and maintains a complete audit trail of all modifications.
   *
   * Access is strictly restricted to the todo owner only. The system first verifies that the authenticated user (extracted from JWT token) owns the requested todo item before querying the history. Users cannot view edit history for todos belonging to other users.
   *
   * The history entries are automatically sorted by edited_at timestamp in descending order, displaying the most recent edits first. This follows the database schema's @index([todo_id, edited_at]) for efficient querying.
   *
   * @param connection
   * @param todoId Unique identifier of the todo item whose history is being requested
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_app_todo_histories table filtered by todo_id and authenticated user ownership.
   * Join with todo_app_todos table to verify user ownership before querying history.
   * Sort results by edited_at DESC (most recent first).
   * Return all history fields including editedAt, previousTitle, previousDescription, previousStartDate, previousDueDate.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId/history")
  public async history(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string,
  ): Promise<ITodoAppTodoHistory> {
    try {
      return await getTodoAppUserTodosTodoIdHistory({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
