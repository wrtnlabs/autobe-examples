import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageITodoAppTodoEditHistory } from "../../../../../api/structures/IPageITodoAppTodoEditHistory";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoAppUserTodosTodoIdHistory } from "../../../../../providers/getTodoAppUserTodosTodoIdHistory";

@Controller("/todoApp/user/todos/:todoId/history")
export class TodoappUserTodosHistoryController {
  /**
   * Retrieve a paginated list of edit history entries for a specific todo item.
   *
   * This operation returns a chronological list of all edit history entries for the specified todo item, showing the state of the todo fields (title, description, start date, due date) before each edit. The edit history provides a complete audit trail of how the todo item has evolved over time.
   *
   * Access to edit history is restricted to the todo item owner only. Attempts to access history for todo items belonging to other users will be denied.
   *
   * Related operations:
   * - GET /todos/{todoId} - retrieve the current state of the todo item
   * - PATCH /todos - search and filter edit history entries
   * - POST /todos - create new todo items
   *
   * Note: This operation only retrieves edit history entries for active (non-deleted) todo items. Deleted todo items may have different access patterns.
   *
   * @param connection
   * @param todoId Target todo item's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_app_todo_edit_histories table filtering by todo_id matching the path parameter todoId.
   * Sort results by created_at in descending order (most recent first).
   * Apply pagination with configurable page size.
   * Return IPageITodoAppTodoEditHistory.ISummary with history entries containing: id, title_before, description_before, start_date_before, due_date_before, created_at, user_id.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string,
  ): Promise<IPageITodoAppTodoEditHistory.ISummary> {
    try {
      return await getTodoAppUserTodosTodoIdHistory({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
