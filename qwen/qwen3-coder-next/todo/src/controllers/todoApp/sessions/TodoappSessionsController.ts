import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageITodoAppUserSession } from "../../../api/structures/IPageITodoAppUserSession";
import { ITodoAppUserSession } from "../../../api/structures/ITodoAppUserSession";
import { getTodoAppSessionsSessionId } from "../../../providers/getTodoAppSessionsSessionId";
import { patchTodoAppSessions } from "../../../providers/patchTodoAppSessions";

@Controller("/todoApp/sessions")
export class TodoappSessionsController {
  /**
   * Retrieve a filtered and paginated list of user authentication sessions.
   *
   * This operation provides comprehensive session management capabilities including filtering by user, IP address, date ranges, and session expiration status. Supports advanced search features for security monitoring and session auditing.
   *
   * The response includes session summary information optimized for list displays with pagination support for large result sets.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query todo_app_user_sessions table with pagination and filtering.
   * Join with todo_app_users for user information when requested.
   * Apply filters for user_id, IP address, created_at date range, expired_at status (active/expired), and referrer URL.
   * Sort by created_at (default desc), expired_at, and ip address.
   * Return cursor-based pagination for efficient large result set handling.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: ITodoAppUserSession.IRequest,
  ): Promise<IPageITodoAppUserSession.ISummary> {
    try {
      return await patchTodoAppSessions({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific user session.
   *
   * This operation fetches comprehensive session details including client connection information, authentication timestamps, and session lifecycle data. It provides visibility into active user sessions for security monitoring and session management purposes.
   *
   * The response includes detailed metadata about how and when the session was established, including client IP address, page URL, and referrer information. Session expiration timing is also included to support session lifecycle management.
   *
   * The operation enforces complete user privacy - users can only access their own sessions. Attempting to retrieve another user's session returns a generic "not found" error to prevent session enumeration attacks.
   *
   * @param connection
   * @param sessionId Unique identifier of the session to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query todo_app_user_sessions table by session ID and user ID from JWT token. Join with todo_app_users table to include user information in response. Validate that the session belongs to the authenticated user. Return session details with client metadata, creation timestamp, and expiration timestamp. Implement strict ownership verification to prevent cross-user session access. Use database-level filtering to ensure users can only see their own sessions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @TypedParam("sessionId")
    sessionId: string,
  ): Promise<ITodoAppUserSession> {
    try {
      return await getTodoAppSessionsSessionId({
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
