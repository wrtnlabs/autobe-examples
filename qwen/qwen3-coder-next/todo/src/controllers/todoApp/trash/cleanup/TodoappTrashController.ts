import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoAppTrashCleanupResponse } from "../../../../api/structures/ITodoAppTrashCleanupResponse";
import { postTodoAppTrashCleanup } from "../../../../providers/postTodoAppTrashCleanup";

@Controller("/todoApp/trash/cleanup")
export class TodoappTrashController {
  /**
   * Permanently delete todo items from trash that exceed the retention period.
   *
   * This system operation permanently removes todo items that have been in the trash longer than the configured retention period (typically 30 days). It processes all trash records where the deletion timestamp exceeds the retention threshold and removes both the trash records and their associated todo items permanently.
   *
   * This operation is designed for automated system execution and is not intended for regular user interaction.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Scan todo_app_todo_trashes table for records where deleted_at is older than retention period (typically 30 days).
   * Delete those trash records and their associated todo items permanently.
   * Count the total number of items deleted and return in response body.
   * This operation does not require any user input parameters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async cleanup(): Promise<ITodoAppTrashCleanupResponse> {
    try {
      return await postTodoAppTrashCleanup();
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
