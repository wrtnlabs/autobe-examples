import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppAdminSession } from "../../../../api/structures/ITodoAppAdminSession";
import { postTodoAppAuthAdminJoin } from "../../../../providers/postTodoAppAuthAdminJoin";
import { postTodoAppAuthAdminLogin } from "../../../../providers/postTodoAppAuthAdminLogin";
import { postTodoAppAuthAdminRefresh } from "../../../../providers/postTodoAppAuthAdminRefresh";

@Controller("/todoApp/auth/admin")
export class TodoappAuthAdminController {
  /**
   * Admin Registration Operation
   *
   * This endpoint handles the registration of new system administrators for the Todo application. It creates a new admin account in the todo_app_admins table with the provided email address and securely hashed password.
   *
   * The operation performs several critical security checks:
   *
   * 1. **Email Uniqueness Validation**: Before creating a new admin account, the system verifies that the provided email address is not already registered. Each email must be unique across all admin accounts. If an admin with the given email already exists, the operation returns an error response indicating the email is already in use.
   *
   * 2. **Password Security**: The provided password is securely hashed using the bcrypt algorithm before being stored in the database. This ensures that even if the database is compromised, passwords remain protected. The original password is never stored in plain text.
   *
   * 3. **Account State**: New admin accounts are created in an active state with null deleted_at timestamps. The account can be suspended later through administrative actions.
   *
   * 4. **Database Integration**: The operation directly interacts with the todo_app_admins table, inserting the new admin record with all required fields including the hashed password, creation timestamps, and null values for soft-delete tracking.
   *
   * Security considerations include proper input validation, secure password hashing, and prevention of information disclosure during error responses. The operation returns appropriate HTTP status codes (201 Created for success, 409 Conflict for duplicate email, 400 Bad Request for validation errors).
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration request body containing admin email and password for creating a new admin account.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Handle admin registration by creating a new admin account in the todo_app_admins table. Hash the password using bcrypt before storage. Validate email uniqueness and return appropriate error for duplicate emails.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppAdminSession.IJoin,
  ): Promise<ITodoAppAdminSession.IAuthorized> {
    try {
      return await postTodoAppAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Admin Login Operation
   *
   * This endpoint handles the authentication of system administrators seeking to access the Todo application. It validates admin credentials against the stored credentials in the todo_app_admins table and establishes an authenticated session using JWT tokens.
   *
   * The authentication process involves several security-critical steps:
   *
   * 1. **Credential Validation**: The system retrieves the admin record by email address and verifies the provided password against the stored bcrypt hash in the password_hash field. This comparison is performed using constant-time comparison to prevent timing attacks.
   *
   * 2. **Session Management**: Upon successful authentication, the system generates both an access token (for immediate API authentication) and a refresh token (for session renewal). These tokens are stored in the todo_app_admin_sessions table along with connection metadata including IP address, referrer, and target URL path.
   *
   * 3. **Account Status Check**: The operation verifies that the admin account is not suspended or deleted by checking the deleted_at field. Suspended accounts cannot authenticate even with valid credentials.
   *
   * 4. **Security Audit Trail**: Each login creates a session record in todo_app_admin_sessions, enabling security auditing and monitoring of admin access patterns. The session includes timestamps for tracking and management.
   *
   * 5. **Token Expiration**: The operation sets appropriate expiration times for both access and refresh tokens, following the session and token policy defined in the system configuration.
   *
   * The operation returns appropriate HTTP status codes (200 OK for success, 401 Unauthorized for invalid credentials, 403 Forbidden for suspended accounts).
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login request body containing admin email and password for authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Authenticate admin credentials by validating email and password against the todo_app_admins table. Generate JWT access and refresh tokens stored in the todo_app_admin_sessions table. Return tokens on successful authentication.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppAdminSession.ILogin,
  ): Promise<ITodoAppAdminSession.IAuthorized> {
    try {
      return await postTodoAppAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Admin Token Refresh Operation
   *
   * This endpoint handles the renewal of authentication tokens for system administrators with an existing valid session. It uses refresh tokens to obtain new access tokens without requiring re-authentication, maintaining secure session management.
   *
   * The token refresh process includes several important security and operational aspects:
   *
   * 1. **Refresh Token Validation**: The system validates the provided refresh token against the stored token in the todo_app_admin_sessions table. This validation includes checking the token signature, expiration time, and ensuring the token matches the stored value.
   *
   * 2. **Session Verification**: Before issuing new tokens, the system verifies that the session is still valid by checking the session record exists and has not been invalidated (deleted_at is null). This prevents the use of tokens from terminated sessions.
   *
   * 3. **Token Rotation**: Following security best practices, the operation generates new tokens for both access and refresh, implementing token rotation to limit the impact of token compromise.
   *
   * 4. **Session Metadata**: The refresh operation updates the session metadata including the last refresh timestamp, maintaining accurate session activity records for auditing purposes.
   *
   * 5. **Expiry Management**: The operation sets appropriate expiration times for the new tokens based on the configured session policy, ensuring seamless continuation of the admin's authenticated session.
   *
   * 6. **Database Update**: The system updates the session record in the todo_app_admin_sessions table with the new refresh token and updated_at timestamp.
   *
   * The operation returns appropriate HTTP status codes (200 OK for successful refresh, 401 Unauthorized for invalid or expired refresh token, 403 Forbidden for terminated sessions).
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh request body containing the refresh token for renewing admin authentication.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Refresh admin authentication tokens by validating the refresh token stored in the todo_app_admin_sessions table. Generate new access and refresh tokens upon successful validation, maintaining session continuity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppAdminSession.IRefresh,
  ): Promise<ITodoAppAdminSession.IAuthorized> {
    try {
      return await postTodoAppAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
