import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppAdminSession } from "../../../../api/structures/ITodoAppAdminSession";
import { postTodoAppAuthAdminJoin } from "../../../../providers/postTodoAppAuthAdminJoin";
import { postTodoAppAuthAdminLogin } from "../../../../providers/postTodoAppAuthAdminLogin";
import { postTodoAppAuthAdminRefresh } from "../../../../providers/postTodoAppAuthAdminRefresh";

@Controller("/todoApp/auth/admin")
export class TodoappAuthAdminController {
  /**
   * Register a new system administrator account.
   *
   * This endpoint creates a new admin account in the todo_app_admins table. It requires a unique email address and a securely hashed password. The system validates the email format, checks for uniqueness, and creates the admin record with proper timestamps.
   *
   * Security Considerations:
   * - Password must meet complexity requirements
   * - Email must be unique and valid format
   * - Password is hashed using bcrypt before storage
   * - Initial account state is active (deleted_at = NULL)
   *
   * Database Schema:
   * The operation creates a record in the todo_app_admins table with:
   * - id: UUID generated by the system
   * - email: User-provided email address
   * - password_hash: bcrypt-hashed password
   * - created_at: Current timestamp (timestamptz)
   * - updated_at: Current timestamp (timestamptz)
   * - deleted_at: NULL (active account)
   *
   * Error Handling:
   * - 400: Invalid email format or password policy violation
   * - 409: Duplicate email address
   * - 500: Database insertion failure
   *
   * Related Operations:
   * - Login: After registration, user can authenticate with email/password
   * - Account deletion: Can permanently remove admin account if needed
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration request containing admin credentials
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Admin registration endpoint. Creates new admin account with email and password. Validates email format and uniqueness, hashes password with bcrypt, creates admin record, and returns JWT tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppAdminSession.IJoin,
  ): Promise<ITodoAppAdminSession.IAuthorized> {
    try {
      return await postTodoAppAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an administrator and receive JWT tokens.
   *
   * This endpoint validates admin credentials against the todo_app_admins table. It verifies the email exists, checks the password hash, and generates both access and refresh tokens if authentication succeeds.
   *
   * Authentication Flow:
   * 1. Lookup admin by email from todo_app_admins table
   * 2. Verify account is not soft-deleted (deleted_at = NULL)
   * 3. Verify password matches bcrypt hash in password_hash field
   * 4. Generate JWT access token (typically 15-30 minutes expiry)
   * 5. Generate JWT refresh token (typically 7-30 days expiry)
   * 6. Store refresh token in todo_app_admin_sessions table for revocation
   * 7. Return tokens and admin info (id, email, displayName if available)
   *
   * Security Considerations:
   * - Password verification uses bcrypt comparison
   * - Session tokens are cryptographically signed
   * - Token revocation supported via session table
   * - Rate limiting recommended to prevent brute force attacks
   * - Failed attempts should be logged for security monitoring
   *
   * Database Schema Interaction:
   * - Reads from todo_app_admins table for credential verification
   * - Creates record in todo_app_admin_sessions table for refresh token management
   * - Updates updated_at timestamp on successful authentication
   *
   * Error Handling:
   * - 400: Missing email or password
   * - 401: Invalid credentials or soft-deleted account
   * - 429: Rate limit exceeded
   * - 500: Token generation or database failure
   *
   * Related Operations:
   * - Refresh: Use refresh token to get new access token
   * - Logout: Revoke session (if implemented)
   * - Password change: Update password after authentication
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login request containing admin credentials
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Admin authentication endpoint. Validates email and password, generates JWT tokens, and returns access/refresh tokens with user info.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppAdminSession.ILogin,
  ): Promise<ITodoAppAdminSession.IAuthorized> {
    try {
      return await postTodoAppAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens using a valid refresh token.
   *
   * This endpoint allows administrators to obtain a new access token without re-authenticating. It validates the refresh token against the stored session in the database and issues a new access token if the refresh token is still valid.
   *
   * Token Flow:
   * 1. Extract refresh token from request headers or body
   * 2. Lookup session in todo_app_admin_sessions table
   * 3. Verify refresh token is not expired
   * 4. Verify refresh token is not revoked
   * 5. Generate new JWT access token (15-30 minutes expiry)
   * 6. Optionally rotate refresh token (new refresh token for security)
   * 7. Return new access token (and new refresh token if rotated)
   *
   * Security Considerations:
   * - Refresh tokens have longer expiry (7-30 days) than access tokens
   * - Token rotation recommended for improved security
   * - Session revocation invalidates all tokens
   * - Refresh token should be transmitted over HTTPS only
   * - Device binding can prevent token theft
   *
   * Database Schema Interaction:
   * - Reads from todo_app_admin_sessions table for token validation
   * - Updates session record if token rotation is enabled
   * - Checks session expiration and revocation status
   * - Updates last_activity_at timestamp
   *
   * Error Handling:
   * - 400: Missing or malformed refresh token
   * - 401: Invalid, expired, or revoked refresh token
   * - 403: Session no longer valid
   * - 500: Token generation or database failure
   *
   * Related Operations:
   * - Login: Initial authentication to obtain refresh token
   * - Logout: Revoke session to invalidate all tokens
   * - Token validation: Check current token status
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token request
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Token refresh endpoint. Validates refresh token, issues new access token, and updates session record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppAdminSession.IRefresh,
  ): Promise<ITodoAppAdminSession.IAuthorized> {
    try {
      return await postTodoAppAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
