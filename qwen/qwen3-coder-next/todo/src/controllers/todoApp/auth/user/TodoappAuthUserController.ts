import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppUser } from "../../../../api/structures/ITodoAppUser";
import { postTodoAppAuthUserJoin } from "../../../../providers/postTodoAppAuthUserJoin";
import { postTodoAppAuthUserLogin } from "../../../../providers/postTodoAppAuthUserLogin";
import { postTodoAppAuthUserRefresh } from "../../../../providers/postTodoAppAuthUserRefresh";

@Controller("/todoApp/auth/user")
export class TodoappAuthUserController {
  /**
   * User registration endpoint that creates a new account in the Todo application. The endpoint accepts email address and password, validates the email format and uniqueness, enforces password strength requirements, and creates a new user account in active state. The password is securely hashed before storage using bcrypt algorithm to ensure security.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration information including email address and password
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Register a new user account with email and password. Validate email format and uniqueness, hash the password using bcrypt, and create a new user record in the database with active status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.IJoin,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postTodoAppAuthUserJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * User login endpoint that authenticates credentials and issues JWT tokens. The endpoint validates the provided email and password against stored credentials, checks if the account is active and not deleted, and issues access and refresh tokens upon successful authentication. The password verification uses bcrypt comparison to ensure secure authentication. Generic error messages are returned to prevent user enumeration attacks.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials including email address and password
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Authenticate user credentials and issue JWT tokens. Validate email and password, check account status, and issue access and refresh tokens upon successful authentication.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.ILogin,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postTodoAppAuthUserLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Token refresh endpoint that issues new access tokens using valid refresh tokens. The endpoint validates the refresh token, checks if it hasn't expired, and issues a new access token. The system may implement refresh token rotation for enhanced security where a new refresh token is issued alongside the access token. This endpoint enables users to maintain authenticated sessions without re-authenticating.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for token renewal
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Refresh access token using valid refresh token. Validate refresh token, issue new access token, and optionally issue new refresh token if rotation is enabled.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppUser.IRefresh,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postTodoAppAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
