import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppMemberSession } from "../../../../api/structures/ITodoAppMemberSession";
import { postTodoAppAuthMemberJoin } from "../../../../providers/postTodoAppAuthMemberJoin";
import { postTodoAppAuthMemberLogin } from "../../../../providers/postTodoAppAuthMemberLogin";
import { postTodoAppAuthMemberRefresh } from "../../../../providers/postTodoAppAuthMemberRefresh";

@Controller("/todoApp/auth/member")
export class TodoappAuthMemberController {
  /**
   * Register a new member account by creating a new member record with email and password hash. This operation creates the associated user account and profile records required for member authentication. Upon successful registration, the system generates JWT access and refresh tokens for the newly created member session. This is the first step in the authentication workflow and enables the member to access protected resources.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration information for a new member account
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Handle member registration by creating new member account with email and password hash. Creates associated user account and profile records. Returns JWT tokens for session.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppMemberSession.IJoin,
  ): Promise<ITodoAppMemberSession.IAuthorized> {
    try {
      return await postTodoAppAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a member by validating their email and password hash against the stored credentials. This login operation verifies the member's identity and creates a new session if authentication is successful. Upon successful authentication, the system generates JWT access and refresh tokens that enable the member to access protected resources. This is the core authentication workflow for member users.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials containing email and password hash for authentication
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Authenticate member credentials by validating email and password hash. Creates session and returns JWT tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppMemberSession.ILogin,
  ): Promise<ITodoAppMemberSession.IAuthorized> {
    try {
      return await postTodoAppAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh the JWT access token by validating the provided refresh token. This operation extends the session validity and generates a new access token while invalidating the refresh token. Token refresh is essential for maintaining continuous access without requiring members to re-authenticate frequently. This operation enhances user experience while maintaining security through token rotation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token request containing the current refresh token
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Refresh JWT access token using refresh token. Extends session validity and generates new access token.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppMemberSession.IRefresh,
  ): Promise<ITodoAppMemberSession.IAuthorized> {
    try {
      return await postTodoAppAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
