import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIScheduledTodoActivity } from "../../../../../api/structures/IPageIScheduledTodoActivity";
import { IScheduledTodoActivity } from "../../../../../api/structures/IScheduledTodoActivity";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchTodoAppMemberAnalyticsActivities } from "../../../../../providers/patchTodoAppMemberAnalyticsActivities";

@Controller("/todoApp/member/analytics/activities")
export class TodoappMemberAnalyticsActivitiesController {
  /**
   * Retrieve filtered and paginated activity analytics data for todos.
   *
   * This operation provides comprehensive activity analytics for todo items including creation patterns, completion rates, editing frequency, and date-based distributions. Users can filter activities by date range, completion status, and sort by various activity metrics. The response includes aggregated statistics optimized for dashboard displays and analytics reports.
   *
   * The activity data is derived from the todo_app_todos and todo_app_todo_edits tables, tracking when todos were created, completed, modified, and how often they were edited. This enables users to analyze their productivity patterns, identify peak activity times, and understand their todo management habits.
   *
   * Supports comprehensive filtering including date ranges for creation/last-edit times, completion status, and activity frequency thresholds. Pagination allows efficient retrieval of large result sets with configurable page sizes and sorting options for different analytical perspectives.
   *
   * @param connection
   * @param body Activity search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query todo_app_todos and todo_app_todo_edits tables to aggregate activity statistics. Filter by date range, completion status, and edit frequency. Group by activity type (creation, completion, editing) with counts and timestamps. Support pagination with offset/limit and sorting by creation date, completion date, edit frequency. Return paginated activity summaries with aggregate statistics.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IScheduledTodoActivity.IRequest,
  ): Promise<IPageIScheduledTodoActivity.ISummary> {
    try {
      return await patchTodoAppMemberAnalyticsActivities({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
