import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageITodoAppTodo } from "../../../../api/structures/IPageITodoAppTodo";
import { ITodoAppTodo } from "../../../../api/structures/ITodoAppTodo";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteTodoAppMemberTodosTodoId } from "../../../../providers/deleteTodoAppMemberTodosTodoId";
import { getTodoAppMemberTodosTodoId } from "../../../../providers/getTodoAppMemberTodosTodoId";
import { patchTodoAppMemberTodos } from "../../../../providers/patchTodoAppMemberTodos";
import { postTodoAppMemberTodos } from "../../../../providers/postTodoAppMemberTodos";

@Controller("/todoApp/member/todos")
export class TodoappMemberTodosController {
  /**
   * Retrieve a specific todo item by its unique identifier.
   *
   * This operation fetches a single todo item from the user's todo list using the todo's UUID. The system ensures that only the todo's owner can access their own todo items, enforcing complete data isolation between users.
   *
   * The operation returns the complete todo details including the title, description, optional start and due dates, completion status, and trash state. This allows clients to display the full todo information for detailed view or editing operations.
   *
   * Security is enforced at the application level by filtering todos based on the authenticated user's ID, ensuring users cannot access todos belonging to other users.
   *
   * @param connection
   * @param todoId Target todo's unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query todo_app_todos table by ID and authenticated user ID.
   * Verify todo exists and belongs to the requesting user.
   * Return complete todo record including title, description, start_date, due_date, is_complete, is_trashed, created_at, and updated_at fields.
   * Return 404 if todo not found or does not belong to user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string,
  ): Promise<ITodoAppTodo> {
    try {
      return await getTodoAppMemberTodosTodoId({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a todo from the user's trash or soft delete a todo.
   *
   * This operation handles two scenarios:
   * 1. Soft delete: If the todo exists but is not already trashed, mark it as trashed
   * 2. Permanent delete: If the todo is already trashed, permanently remove it and its edit history
   *
   * Only the todo's owner can perform this operation. The system enforces user-level isolation to prevent accessing todos created by other users.
   *
   * After a soft delete, the todo will be hidden from normal todo list queries but preserved in the system for potential restoration from the trash. After a permanent delete, the todo and all associated edit history are irreversibly removed.
   *
   * @param connection
   * @param todoId Target todo's unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Soft delete the target todo by setting is_trashed=true.
   * 1. Query todo by id with user context validation (ensure todo belongs to current user)
   * 2. Set is_trashed=true on the todo
   * 3. Update updated_at timestamp
   * 4. Return the updated todo object
   * 5. Apply user-level isolation filter to ensure only current user's todo can be modified
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string,
  ): Promise<void> {
    try {
      return await deleteTodoAppMemberTodosTodoId({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new todo item for the authenticated user.
   *
   * This operation allows members to create new todo items with their required title and optional metadata including description, start date, and due date. Each todo is automatically associated with the authenticated user through the user context.
   *
   * All newly created todos start with isComplete=false and isTrashed=false by default. The todo is immediately visible in the user's active todo list after creation.
   *
   * This operation enforces strong user-level data isolation - users can only create todos for themselves and cannot create todos on behalf of other users.
   *
   * @param connection
   * @param body Creation request for a new todo item
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new todo item in todo_app_todos table.
   * 1. Extract authenticated user ID from request context
   * 2. Validate request body against ITodoAppTodo.ICreate schema
   * 3. Set is_complete=false and is_trashed=false as defaults
   * 4. Set created_at and updated_at to current timestamp
   * 5. Insert new record with user ID and validated fields
   * 6. Return the complete created todo item including auto-generated fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppTodo.ICreate,
  ): Promise<ITodoAppTodo> {
    try {
      return await postTodoAppMemberTodos({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of todos created by the authenticated user.
   *
   * This operation provides comprehensive filtering and sorting capabilities for todo items. Users can filter by completion status, view only their active todos, and sort by multiple fields including creation date, start date, and due date. The response includes pagination metadata and todo summary information optimized for list displays.
   *
   * All todos returned belong to the authenticated user due to strict ownership isolation. Users cannot access todos created by other users under any circumstances.
   *
   * @param connection
   * @param body Query parameters for filtering, sorting, and pagination
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query todo_app_todos table with user-based isolation filtering.
   * Apply completion status filter (is_complete) if provided in request.
   * Apply date range filters (start_date, due_date) if provided.
   * Support sorting by created_at, start_date, due_date in ascending or descending order.
   * Implement offset-based pagination with configurable page_size and offset.
   * Exclude trashed todos (is_trashed = true) from this list (use /trash endpoint for deleted todos).
   * Return paginated result set with metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppTodo.IRequest,
  ): Promise<IPageITodoAppTodo.ISummary> {
    try {
      return await patchTodoAppMemberTodos({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
