import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppEditHistoryEntry } from "../../../../../api/structures/IPageITodoAppEditHistoryEntry";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberTodosTodoIdHistory } from "../../../../../providers/getTodoAppMemberTodosTodoIdHistory";

@Controller("/todoApp/member/todos/:todoId/history")
export class TodoappMemberTodosHistoryController {
  /**
   * Retrieve the edit history for a specific todo item.
   *
   * This operation provides an audit trail of all field changes made to the todo, including previous and new values for title, description, start date, and due date. Each edit history entry captures exactly which fields were modified and their values before and after the change.
   *
   * Security and Access Control:
   * - Users can only view edit history for their own todos
   * - Request will be rejected if the todo does not belong to the requesting user
   * - Cross-user history access attempts are logged as security events
   * - Users cannot infer the existence of other users' todos through this endpoint
   *
   * Data Integrity:
   * - History entries are immutable once created
   * - Each edit operation creates exactly one history entry
   * - Entries capture only fields that actually changed
   * - History entries are retained with their parent todo item
   *
   * This endpoint is typically used to show users a complete change history of their todo items, helping them track modifications over time.
   *
   * @param connection
   * @param todoId Target todo's unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query todo_app_edit_history_entries table joined with todo_app_todo_edits to get edit history for the specified todo. Filter by todo_app_todo_edit_id referencing the target todo. Join with todo_app_todos to verify user ownership before returning any data. Apply user-level isolation to ensure users can only access their own todo history. Sort results from most recent to oldest by created_at timestamp. Return paginated results with cursor-based pagination for large result sets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<IPageITodoAppEditHistoryEntry.ISummary> {
    try {
      return await getTodoAppMemberTodosTodoIdHistory({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
