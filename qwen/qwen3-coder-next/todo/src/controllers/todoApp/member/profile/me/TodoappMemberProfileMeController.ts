import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoAppProfile } from "../../../../../api/structures/ITodoAppProfile";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberProfileMe } from "../../../../../providers/getTodoAppMemberProfileMe";
import { patchTodoAppMemberProfileMe } from "../../../../../providers/patchTodoAppMemberProfileMe";

@Controller("/todoApp/member/profile/me")
export class TodoappMemberProfileMeController {
  /**
   * Retrieve the authenticated user's own profile information.
   *
   * This operation fetches the current user's profile details including their display name and timestamps. The profile is automatically scoped to the authenticated user based on their session token - no explicit user identifier is needed in the request as the system identifies the user from their authentication credentials.
   *
   * Security Considerations:
   * - This operation is restricted to authenticated members only
   * - Users can only access their own profile - attempts to access other users' profiles are silently ignored
   * - No other users' profile information can be discovered or accessed
   *
   * Relationship to Database:
   * - References the todo_app_profiles table with fields: displayName, createdAt, updatedAt
   * - Profile is automatically scoped to the authenticated user's userId
   * - Follows the personal profile-only access rule enforced at the application level
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the todo_app_profiles table where userId matches the authenticated user's ID from their session token.
   * Return the displayName, createdAt, and updatedAt fields for the user's profile.
   * If no profile exists for the user, return a 404 Not Found response.
   * Enforce that only the authenticated user can access their own profile - reject any attempt to access another user's profile.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<ITodoAppProfile> {
    try {
      return await getTodoAppMemberProfileMe({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated user's profile display name.
   *
   * This operation allows members to update their own profile's display name field. The system enforces strict validation: the display name must be between 1 and 100 characters, cannot consist solely of whitespace, and must be unique within the user's profile context.
   *
   * **Security and Authorization**
   * This operation is restricted to authenticated members. Users can only update their own profile - the system verifies the authenticated user's identity before allowing modifications to their profile data. The operation does not expose any mechanisms to discover or access other users' profiles.
   *
   * **Database Integration**
   * This operation directly modifies the todo_app_profiles table. It updates the display_name field and automatically refreshes the updated_at timestamp to reflect the modification time. The operation respects the one-to-one relationship between users and profiles, ensuring each user maintains exactly one profile record.
   *
   * **Validation Rules**
   * The display name must:
   * - Be between 1 and 100 characters in length
   * - Not consist solely of whitespace characters
   * - Be unique for the user's profile
   * - Not be empty or whitespace-only
   * - Not exceed the 100 character maximum length
   *
   * **Related Operations**
   * - GET /todoApp/member/profile/me retrieves the current user's profile
   * - POST /auth/register automatically creates a profile during user registration
   * - Account deletion cascades to profile deletion
   * - Profile display shows the updated name after successful updates
   *
   * @param connection
   * @param body Request body containing the display name for profile update
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update the profile for the authenticated user by modifying the display_name field in the todo_app_profiles table.
   * 1. Extract user_id from the authenticated session/token
   * 2. Validate request body contains display_name field with proper validation rules
   * 3. Verify display_name length is between 1 and 100 characters
   * 4. Verify display_name is not whitespace-only
   * 5. Check uniqueness constraint for display_name per user
   * 6. Update the todo_app_profiles record where todo_app_user_id matches the authenticated user
   * 7. Update the updated_at timestamp to current time
   * 8. Return the updated profile record
   * 9. Handle validation errors with appropriate HTTP status codes (400 for invalid input)
   * 10. Handle ownership verification failures with 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppProfile.IUpdate,
  ): Promise<ITodoAppProfile> {
    try {
      return await patchTodoAppMemberProfileMe({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
