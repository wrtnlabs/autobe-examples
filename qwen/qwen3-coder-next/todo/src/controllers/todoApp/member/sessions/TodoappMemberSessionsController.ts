import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppGuestSession } from "../../../../api/structures/IPageITodoAppGuestSession";
import { ITodoAppMemberSession } from "../../../../api/structures/ITodoAppMemberSession";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberSessionsSessionId } from "../../../../providers/getTodoAppMemberSessionsSessionId";
import { patchTodoAppMemberSessions } from "../../../../providers/patchTodoAppMemberSessions";

@Controller("/todoApp/member/sessions")
export class TodoappMemberSessionsController {
  /**
   * Retrieve a paginated list of active sessions for the authenticated user.
   *
   * This operation allows users to view all their active sessions across different devices and locations. Sessions are tracked with connection metadata including IP address, user agent, and timestamps.
   *
   * The system supports multiple session types: member sessions for authenticated users, admin sessions for administrators, and guest sessions for unauthenticated access. Users can view their active sessions and manage them accordingly.
   *
   * Response includes session summary information optimized for listing displays.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query session tables (todo_app_member_sessions, todo_app_admin_sessions, todo_app_guest_sessions) based on authenticated user context. Support filtering by session type and pagination. Return paginated list of active sessions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IPageITodoAppGuestSession.ISummary> {
    try {
      return await patchTodoAppMemberSessions({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific session.
   *
   * This endpoint provides comprehensive details about a member's active session, including authentication metadata, connection information, and session validity period. It is used to inspect current session status for security auditing or troubleshooting purposes.
   *
   * Sessions contain sensitive authentication tokens and connection metadata. Access is restricted to the session owner or administrators.
   *
   * @param connection
   * @param sessionId Unique identifier of the session to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query todo_app_member_sessions table by session ID. Return session details including member reference, IP, user agent, tokens, and expiration timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMemberSession> {
    try {
      return await getTodoAppMemberSessionsSessionId({
        member,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
