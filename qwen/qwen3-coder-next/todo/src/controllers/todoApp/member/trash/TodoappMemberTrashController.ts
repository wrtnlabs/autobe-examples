import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppTodo } from "../../../../api/structures/IPageITodoAppTodo";
import { ITodoAppTodo } from "../../../../api/structures/ITodoAppTodo";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteTodoAppMemberTrashTodoId } from "../../../../providers/deleteTodoAppMemberTrashTodoId";
import { patchTodoAppMemberTrash } from "../../../../providers/patchTodoAppMemberTrash";
import { postTodoAppMemberTrashTodoIdRestore } from "../../../../providers/postTodoAppMemberTrashTodoIdRestore";

@Controller("/todoApp/member/trash")
export class TodoappMemberTrashController {
  /**
   * Retrieve a paginated list of deleted todos (in trash) belonging to the authenticated user.
   *
   * This operation returns all todos that have been soft-deleted by the user but not yet permanently deleted. The list includes the complete todo data necessary for restoration operations, including title, description, dates, and completion status.
   *
   * Users can only access their own deleted todos - the system automatically filters by the authenticated user's ID. The endpoint supports filtering by completion status and sorting by various date fields through the request body parameters.
   *
   * @param connection
   * @param body Trash list query parameters including filters, sorting, and pagination settings
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query todo_app_todos table joined with todo_app_todo_trashes to find all deleted todos (deleted_at non-null, permanently_deleted_at null) belonging to the authenticated user. Apply user-level filtering using the authenticated user ID from the session. Support filtering by completion status (completed=true/false/all) and sorting by createdAt, startDate, dueDate in ascending/descending order. Return paginated results with configurable page size and cursor-based pagination for large result sets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppTodo.IRequest,
  ): Promise<IPageITodoAppTodo> {
    try {
      return await patchTodoAppMemberTrash({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Restore a todo from the trash back to active state.
   *
   * This endpoint moves a todo that was previously marked as trashed (is_trashed = true) back to the user's active todo list. The todo's completion status and all edit history are preserved during restoration.
   *
   * Security: Only the authenticated user who owns the todo can restore it. Users cannot restore todos that belong to other users or have been permanently deleted.
   *
   * Business rules:
   * - Todo must be in trashed state (is_trashed = true)
   * - Todo must not have been permanently deleted
   * - User must be authenticated as the todo's owner
   * - Edit history entries remain intact during restoration
   * - Todo is immediately available in the active list after restoration
   *
   * @param connection
   * @param todoId Target todo's unique identifier (UUID) that needs to be restored from trash
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Restore soft-deleted todo from trash to active state. Update todo_app_todos.is_trashed to false and set todo_app_todo_trashes.restored_at to current timestamp. Implement complete business logic for todo restoration including cascade handling and error conditions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":todoId/restore")
  public async restore(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodo> {
    try {
      return await postTodoAppMemberTrashTodoIdRestore({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a todo from the trash.
   *
   * This operation completely removes a todo from the system with no possibility of recovery. When a user permanently deletes a todo, the system:
   *
   * 1. Removes the todo record entirely from the database
   * 2. Deletes all associated edit history entries
   * 3. Updates the trash record to mark permanent deletion with timestamp
   *
   * This action is distinct from the soft delete operation. Once permanently deleted, the todo and its history are unrecoverable.
   *
   * @param connection
   * @param todoId UUID of the todo to permanently delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Find the todo trash record by todoId. If found, permanently delete the todo record and all associated edit history entries. Set the permanently_deleted_at timestamp in the trash record. Ensure cascading deletion removes all edit history entries linked to this todo.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async permanent(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppMemberTrashTodoId({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
