export async function test_api_todo_soft_delete_not_owned(
  connection: api.IConnection,
): Promise<void> {
  // 1. Member A registers and creates todo
  const memberAConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
    } satisfies ITodoAppMemberSession.IJoin,
  });
  const todoA = await generate_random_todo_app_member_todos_create(
    memberAConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
      } satisfies ITodoAppTodo.ICreate,
    },
  );
  typia.assert(todoA);
  // 2. Member B registers
  const memberBConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
    } satisfies ITodoAppMemberSession.IJoin,
  });
  // 3. Member B attempts to delete member A's todo (should fail with 404)
  await TestValidator.httpError(
    "member B cannot delete member A's todo",
    404,
    async () => {
      await api.functional.todoApp.member.todos.erase(memberBConnection, {
        todoId: todoA.id,
      });
    },
  );
}
