export async function test_api_administrator_request_create_as_seller_actor(
  connection: api.IConnection,
): Promise<void> {
  // Scenario: Administrator request creation by a seller actor with valid reason
  // - Authenticate with a seller user who intends to request administrator role
  // - Submit request body with actor_type "seller" and a valid detailed reason
  // - Assert HTTP 201 response with status 'pending'
  // - Verify the request record matches the input with autogenerated UUID and timestamps
  // - Confirm that the request can be retrieved in subsequent queries
  const sellerJoinConnection: api.IConnection = { host: connection.host };
  const sellerJoinBody: IShoppingMallSeller.IJoin =
    typia.random<IShoppingMallSeller.IJoin>();
  const sellerAuth = await authorize_seller_join(sellerJoinConnection, {
    body: sellerJoinBody,
  });
  typia.assert(sellerAuth);
  const sellerLoginConnection: api.IConnection = { host: connection.host };
  // Using login credentials same as joinProps or generated details depends on IShoppingMallSeller.ILogin
  // Since the fields are empty object, we reuse sellerJoinBody as ILogin for compatibility
  const sellerLoginBody: IShoppingMallSeller.ILogin =
    sellerJoinBody as IShoppingMallSeller.ILogin;
  const sellerLoggedIn = await authorize_seller_login(sellerLoginConnection, {
    body: sellerLoginBody,
  });
  typia.assert(sellerLoggedIn);
  const sellerConnection: api.IConnection = { host: connection.host };
  sellerConnection.headers = { Authorization: sellerLoggedIn.token.access };
  const reason = RandomGenerator.paragraph({ sentences: 2 });
  const requestCreateBody: IShoppingMallAdministratorRequest.ICreate = {
    actor_type: "seller",
    reason,
  };
  const requestRaw =
    await api.functional.shoppingMall.administrator.administrator.requests.create(
      sellerConnection,
      {
        body: requestCreateBody,
      },
    );
  const request = requestRaw as any;
  typia.assert(request);
  TestValidator.equals(
    "actor_type equals seller",
    request.actor_type,
    "seller",
  );
  TestValidator.equals("request reason matches", request.reason, reason);
  TestValidator.equals("request status pending", request.status, "pending");
  // ID should be a UUID v4 - Validate format UUID by simple regex
  TestValidator.predicate(
    "request id is UUID",
    /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/.test(
      request.id,
    ),
  );
  // Validate timestamps exist and are in ISO 8601 format
  TestValidator.predicate(
    "created_at format",
    typeof request.created_at === "string" &&
      !isNaN(Date.parse(request.created_at)),
  );
  TestValidator.predicate(
    "updated_at format",
    typeof request.updated_at === "string" &&
      !isNaN(Date.parse(request.updated_at)),
  );
}
