export async function test_api_customer_shipment_confirmations_list_pagination(
  connection: api.IConnection,
): Promise<void> {
  // Actor-specific customer connection
  const customerConnection: api.IConnection = { host: connection.host };
  // Authorize a new customer joining
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {} satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  // Update connection headers with token
  customerConnection.headers = {
    Authorization: customerAuth.token.access,
  };
  // Actor-specific seller connection
  const sellerConnection: api.IConnection = { host: connection.host };
  // Authorize seller join
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {} as Partial<IShoppingMallSeller.IJoin> | undefined,
  });
  typia.assert(sellerAuth);
  // Update seller connection headers with token
  sellerConnection.headers = {
    Authorization: sellerAuth.token.access,
  };
  // Seller creates a shipment as prerequisite
  const shipment = await generate_random_shopping_mall_seller_shipments_create(
    sellerConnection,
    {
      body: undefined,
    },
  );
  typia.assert(shipment);
  // Normally, shipment confirmations are generated by the system with delivery confirmation, but since no create API for shipment_confirmation is provided, we assume shipment confirmations exist for the customer from system perspective.
  // Attempt to retrieve shipment confirmations list with no filter by authenticated customer
  // (empty body to represent no filters)
  const page =
    await api.functional.shoppingMall.customer.shipment_confirmations.index(
      customerConnection,
      {
        body: {},
      },
    );
  typia.assert(page);
  // Validate pagination info
  TestValidator.predicate(
    "pagination current page is >= 1",
    page.pagination.current >= 1,
  );
  TestValidator.predicate(
    "pagination limit is >= 0",
    page.pagination.limit >= 0,
  );
  TestValidator.predicate(
    "pagination pages is >= 0",
    page.pagination.pages >= 0,
  );
  TestValidator.predicate(
    "pagination records is >= 0",
    page.pagination.records >= 0,
  );
  // Validate each data record is valid
  page.data.forEach((item) => {
    typia.assert(item);
    // We can only verify each item has valid id and shipment id (UUID formats guaranteed by typia.assert)
  });
  // Additional business logic: Confirm that all shipment_confirmations belong to authenticated customer
  // But since we lack the customer ID in the shipment confirmation summary, and no user id linkage is given in the DTO, we can't assert customer ownership with given DTOs, so skip this check.
  // Confirm unauthenticated user access is denied
  const unauthenticatedConnection: api.IConnection = { host: connection.host };
  await TestValidator.error("unauthenticated user access denied", async () => {
    await api.functional.shoppingMall.customer.shipment_confirmations.index(
      unauthenticatedConnection,
      {
        body: {},
      },
    );
  });
}
