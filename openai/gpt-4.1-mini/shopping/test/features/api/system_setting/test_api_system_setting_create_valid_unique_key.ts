export async function test_api_system_setting_create_valid_unique_key(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator account setup
  const adminConnection: api.IConnection = { host: connection.host };
  const adminJoinBody: IShoppingMallAdministrator.IJoin = {};
  const authorizedAdmin = await authorize_administrator_join(adminConnection, {
    body: adminJoinBody,
  });
  adminConnection.headers = {
    Authorization: `Bearer ${authorizedAdmin.token.access}`,
  };
  // 2. Create first system setting without specifying body (utility prepares data)
  const createdSetting1 =
    await generate_random_shopping_mall_system_settings_create(
      adminConnection,
      { body: {} },
    );
  typia.assert(createdSetting1);
  // 3. Create second system setting without specifying body
  const createdSetting2 =
    await generate_random_shopping_mall_system_settings_create(
      adminConnection,
      { body: {} },
    );
  typia.assert(createdSetting2);
  // 4. Attempt to create with duplicate key - since keys are randomly generated by utility, explicitly reuse first body to simulate duplicate
  await TestValidator.error("duplicate key throws error", async () => {
    // This depends on utility allowing manual body override but ICreate is empty, so just call twice with same body
    await generate_random_shopping_mall_system_settings_create(
      adminConnection,
      { body: {} },
    );
  });
  // 5. Unauthorized create (no admin token)
  const userConnection: api.IConnection = { host: connection.host };
  await TestValidator.httpError(
    "unauthorized create rejected",
    401,
    async () => {
      await generate_random_shopping_mall_system_settings_create(
        userConnection,
        { body: {} },
      );
    },
  );
}
