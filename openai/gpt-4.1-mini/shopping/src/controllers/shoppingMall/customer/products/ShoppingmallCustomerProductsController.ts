import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallCustomerProducts } from "../../../../providers/patchShoppingMallCustomerProducts";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerProductsProductCode } from "../../../../providers/getShoppingMallCustomerProductsProductCode";

import { IPageIShoppingMallProduct } from "../../../../api/structures/IPageIShoppingMallProduct";
import { IShoppingMallProduct } from "../../../../api/structures/IShoppingMallProduct";

@Controller("/shoppingMall/customer/products")
export class ShoppingmallCustomerProductsController {
  /**
   * Search and retrieve a filtered, paginated list of shopping mall platform
   * products.
   *
   * Retrieve a filtered and paginated list of ShoppingMall products from the
   * system. This operation provides advanced search capabilities allowing
   * filtering by product name, unique code, assigned category, and brand, with
   * support for pagination and sorting.
   *
   * Results exclude soft deleted products (identified by null deleted_at).
   * Pagination parameters include page size and page number.
   *
   * Security considerations include role-based access control; typically, this
   * endpoint is open to authenticated users including customers, sellers, and
   * admins.
   *
   * The operation returns a paginated response containing a summary view of
   * product information suitable for listings.
   *
   * This operation integrates directly with the ShoppingMallProduct entity in
   * the Prisma schema, mapping all available fields except soft-deleted
   * records.
   *
   * Related operations include product creation, updating, detail retrieval,
   * and deletion.
   *
   * This endpoint is part of the Product Catalog group.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for product filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallProduct.IRequest,
  ): Promise<IPageIShoppingMallProduct.ISummary> {
    try {
      return await patchShoppingMallCustomerProducts({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed product information by unique productCode.
   *
   * Retrieve detailed product information identified by the unique productCode.
   * The product corresponds to the shopping_mall_products table which stores
   * product metadata including descriptive text, brand, and timestamps.
   *
   * Authorization is open to authenticated users (admins, sellers, and
   * customers) to view the product catalog. No request body is needed as this
   * is a simple retrieval.
   *
   * The productCode path parameter uniquely identifies the product across the
   * platform, derived from the code column which is unique and human-readable.
   *
   * The response returns the complete product entity with all details excluding
   * soft deleted products.
   *
   * Errors will occur if the productCode does not correspond to any existing
   * product or if the product is deleted.
   *
   * Other operations like listing products or viewing SKUs support workflows
   * that complement this retrieval.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target product
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productCode")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productCode")
    productCode: string,
  ): Promise<IShoppingMallProduct> {
    try {
      return await getShoppingMallCustomerProductsProductCode({
        customer,
        productCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
