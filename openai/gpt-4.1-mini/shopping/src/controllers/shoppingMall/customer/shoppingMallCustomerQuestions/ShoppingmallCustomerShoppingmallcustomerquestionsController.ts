import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerShoppingMallCustomerQuestions } from "../../../../providers/postShoppingMallCustomerShoppingMallCustomerQuestions";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerShoppingMallCustomerQuestionsShoppingMallCustomerQuestionId } from "../../../../providers/putShoppingMallCustomerShoppingMallCustomerQuestionsShoppingMallCustomerQuestionId";
import { deleteShoppingMallCustomerShoppingMallCustomerQuestionsShoppingMallCustomerQuestionId } from "../../../../providers/deleteShoppingMallCustomerShoppingMallCustomerQuestionsShoppingMallCustomerQuestionId";

import { IShoppingMallCustomerQuestion } from "../../../../api/structures/IShoppingMallCustomerQuestion";

@Controller("/shoppingMall/customer/shoppingMallCustomerQuestions")
export class ShoppingmallCustomerShoppingmallcustomerquestionsController {
  /**
   * Create a new customer question in the shopping mall.
   *
   * Create a new customer question record linked to a customer and their active
   * session.
   *
   * This API is intended for customers to submit inquiries regarding products
   * or orders within the shopping mall. The question includes a title and
   * detailed body text.
   *
   * Security: The operation requires authentication of the customer user. The
   * system automatically records creation and update timestamps.
   *
   * The created question supports moderation workflows via soft deletes and is
   * linked to a separate answer entity managed by sellers.
   *
   * Related operations: Update question (PUT
   * /shoppingMallCustomerQuestions/{shoppingMallCustomerQuestionId}).
   *
   * @param connection
   * @param body The creation data for the new customer question.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCustomerQuestion.ICreate,
  ): Promise<IShoppingMallCustomerQuestion> {
    try {
      return await postShoppingMallCustomerShoppingMallCustomerQuestions({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing customer question.
   *
   * Update the title and body of a customer question identified by its unique
   * question ID.
   *
   * This API allows the customer to modify their previously submitted question,
   * maintaining linkages to their customer and session records.
   *
   * Security: Only the owner customer or authorized personnel can perform this
   * update. Timestamps for update are handled automatically.
   *
   * Related operations: Create question (POST /shoppingMallCustomerQuestions).
   *
   * @param connection
   * @param shoppingMallCustomerQuestionId Unique identifier of the customer
   *   question to update
   * @param body The update data for the customer question.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shoppingMallCustomerQuestionId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shoppingMallCustomerQuestionId")
    shoppingMallCustomerQuestionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCustomerQuestion.IUpdate,
  ): Promise<IShoppingMallCustomerQuestion> {
    try {
      return await putShoppingMallCustomerShoppingMallCustomerQuestionsShoppingMallCustomerQuestionId(
        {
          customer,
          shoppingMallCustomerQuestionId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a shopping mall customer question by ID.
   *
   * Permanently remove a specific shopping mall customer question identified by
   * its unique ID.
   *
   * This operation deletes the question record from the database. It does not
   * soft-delete but permanently removes the record.
   *
   * Security and authorization checks should ensure only permitted users can
   * delete questions.
   *
   * This operation relates to the shopping_mall_customer_questions table and
   * must verify the presence of the question before deleting.
   *
   * Related operations: retrieval of customer questions, creation of new
   * questions, and answering of questions via the related answers endpoint.
   *
   * @param connection
   * @param shoppingMallCustomerQuestionId Unique identifier of the shopping
   *   mall customer question to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":shoppingMallCustomerQuestionId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shoppingMallCustomerQuestionId")
    shoppingMallCustomerQuestionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerShoppingMallCustomerQuestionsShoppingMallCustomerQuestionId(
        {
          customer,
          shoppingMallCustomerQuestionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
