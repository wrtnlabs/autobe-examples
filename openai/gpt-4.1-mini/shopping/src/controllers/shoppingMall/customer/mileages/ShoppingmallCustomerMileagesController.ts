import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerMileages } from "../../../../providers/postShoppingMallCustomerMileages";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerMileages } from "../../../../providers/patchShoppingMallCustomerMileages";
import { getShoppingMallCustomerMileagesMileageId } from "../../../../providers/getShoppingMallCustomerMileagesMileageId";
import { putShoppingMallCustomerMileagesMileageId } from "../../../../providers/putShoppingMallCustomerMileagesMileageId";

import { IShoppingMallMileage } from "../../../../api/structures/IShoppingMallMileage";
import { IPageIShoppingMallMileage } from "../../../../api/structures/IPageIShoppingMallMileage";

@Controller("/shoppingMall/customer/mileages")
export class ShoppingmallCustomerMileagesController {
  /**
   * Create a new customer mileage record in shopping mall system.
   *
   * Create a new mileage record linked to a shopping mall customer.
   *
   * This operation allows authorized users to add a mileage record,
   * representing reward points earned by a customer.
   *
   * The mileage record stores the number of points, optional expiration date,
   * and audit timestamps. The `shopping_mall_customer_id` must reference a
   * valid customer.
   *
   * Security: Only authorized actors can perform this operation. Input
   * validation ensures points are positive integers and dates are valid.
   *
   * Related operations: Updating a mileage record (PUT /mileages/{mileageId}),
   * retrieving mileage summaries.
   *
   * This operation strictly adheres to the shopping_mall_mileages Prisma model,
   * ensuring data integrity and compliance.
   *
   * @param connection
   * @param body New mileage record creation data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallMileage.ICreate,
  ): Promise<IShoppingMallMileage> {
    try {
      return await postShoppingMallCustomerMileages({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of shopping mall mileages.
   *
   * Retrieve a filtered and paginated list of mileage records accumulated by
   * customers in the shopping mall platform. This operation supports complex
   * filtering criteria including customer ID, point ranges, expiration dates,
   * and active status to facilitate detailed management of mileage points.
   *
   * Pagination and sorting options permit flexible presentation in UI and
   * reporting tools, optimizing performance for large datasets.
   *
   * Security considerations ensure that only authorized users with appropriate
   * scopes can view mileage data, protecting sensitive customer reward
   * information.
   *
   * This operation is backed by the shopping_mall_mileages table in Prisma
   * schema, reflecting all available fields including point totals, timestamps,
   * and soft delete markers for data integrity and auditability.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   mileages
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallMileage.IRequest,
  ): Promise<IPageIShoppingMallMileage.ISummary> {
    try {
      return await patchShoppingMallCustomerMileages({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific shopping mall mileage record.
   *
   * Retrieve detailed information for a single mileage record identified by its
   * unique mileage ID. This includes total points accumulated, expiration date
   * if any, customer association, and timestamps for creation, update, and
   * deletion.
   *
   * Access is restricted to authorized users to ensure privacy and security of
   * customer reward data.
   *
   * Based on the shopping_mall_mileages table schema, this operation validates
   * the UUID format for the mileageId parameter and returns full details on
   * success.
   *
   * @param connection
   * @param mileageId Unique identifier of the target mileage record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":mileageId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("mileageId")
    mileageId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallMileage> {
    try {
      return await getShoppingMallCustomerMileagesMileageId({
        customer,
        mileageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a customer mileage record by ID.
   *
   * Update an existing mileage record by ID.
   *
   * This operation enables authorized users to modify mileage points,
   * expiration date, and related audit information for a specified mileage
   * record.
   *
   * The mileageId path parameter uniquely identifies the record to update.
   * Validation ensures all input fields conform to schema constraints.
   *
   * Security: Access is restricted to authorized actors to prevent unauthorized
   * modifications.
   *
   * Related operations: Creating mileage (POST /mileages), querying mileage
   * data.
   *
   * This operation is deeply aligned with the shopping_mall_mileages Prisma
   * model, ensuring all updates comply with database integrity constraints.
   *
   * @param connection
   * @param mileageId Unique identifier of the target mileage record
   * @param body Mileage record update data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":mileageId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("mileageId")
    mileageId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallMileage.IUpdate,
  ): Promise<IShoppingMallMileage> {
    try {
      return await putShoppingMallCustomerMileagesMileageId({
        customer,
        mileageId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
