import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallCustomerShoppingMallShipments } from "../../../../providers/patchShoppingMallCustomerShoppingMallShipments";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerShoppingMallShipmentsShoppingMallShipmentId } from "../../../../providers/getShoppingMallCustomerShoppingMallShipmentsShoppingMallShipmentId";

import { IPageIShoppingMallShipment } from "../../../../api/structures/IPageIShoppingMallShipment";
import { IShoppingMallShipment } from "../../../../api/structures/IShoppingMallShipment";

@Controller("/shoppingMall/customer/shoppingMallShipments")
export class ShoppingmallCustomerShoppingmallshipmentsController {
  /**
   * Search and retrieve shipments with filtering and pagination.
   *
   * Retrieve a paginated and filtered list of shipment records in the shopping
   * mall system.
   *
   * This operation provides advanced search capabilities to filter shipments by
   * status, order, shipment date, and shipping provider. It includes pagination
   * controls to handle large result sets efficiently.
   *
   * Security considerations include authentication with the "customer" actor
   * role to ensure that only authorized users can access shipment data. Proper
   * filtering is enforced to protect sensitive customer and order details.
   *
   * This relates to the shopping_mall_shipments table in the Prisma schema,
   * reflecting all defined fields and their relationships for comprehensive
   * shipment management.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for shipments
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallShipment.IRequest,
  ): Promise<IPageIShoppingMallShipment.ISummary> {
    try {
      return await patchShoppingMallCustomerShoppingMallShipments({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve shipment details by shipment ID.
   *
   * Retrieve detailed information for a specific shopping mall shipment by its
   * unique identifier.
   *
   * This operation returns full shipment details including related order and
   * shipment tracking information.
   *
   * Access control is enforced to allow only authorized users with a valid
   * session and proper permissions.
   *
   * The operation operates on the shopping_mall_shipments table as defined in
   * the Prisma schema.
   *
   * @param connection
   * @param shoppingMallShipmentId Unique identifier of the target shipment
   *   record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shoppingMallShipmentId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shoppingMallShipmentId")
    shoppingMallShipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment> {
    try {
      return await getShoppingMallCustomerShoppingMallShipmentsShoppingMallShipmentId(
        {
          customer,
          shoppingMallShipmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
