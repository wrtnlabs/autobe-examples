import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallShipmentConfirmation } from "../../../../api/structures/IShoppingMallShipmentConfirmation";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerShipmentConfirmationsShipmentConfirmationId } from "../../../../providers/getShoppingMallCustomerShipmentConfirmationsShipmentConfirmationId";
import { patchShoppingMallCustomerShipmentConfirmations } from "../../../../providers/patchShoppingMallCustomerShipmentConfirmations";
import { postShoppingMallCustomerShipmentConfirmations } from "../../../../providers/postShoppingMallCustomerShipmentConfirmations";

@Controller("/shoppingMall/customer/shipmentConfirmations")
export class ShoppingmallCustomerShipmentconfirmationsController {
  /**
   * Create a new shipment confirmation record when a customer confirms delivery of a shipment. The confirmation includes the shipment ID and timestamp of confirmation.
   *
   * This endpoint is crucial in the order shipping lifecycle, enabling customers to signal that they have received the shipment. Upon successful creation, the system may trigger status updates to the associated order items and notify sellers of delivery confirmation.
   *
   * The shipment confirmation entity is stored in the shopping_mall_shipment_confirmations table, which contains details including the shipment reference and delivery confirmation timestamp.
   *
   * Security: This operation requires authentication of the customer actor ensuring only authorized customers can confirm shipment deliveries.
   *
   * Related operations include GET endpoints to view shipment details and order item statuses, plus other order management APIs.
   *
   * Errors handled include invalid shipment IDs, unauthorized access, and duplicate confirmations.
   *
   * @param connection
   * @param body Request data to create a shipment confirmation
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement as a POST operation inserting a new record into shopping_mall_shipment_confirmations table. Validate the shipmentId is valid and belongs to the authenticating customer. Record the confirmation timestamp as current time if not provided. Use database transactions to maintain consistency. Upon success, return the created shipment confirmation record. Handle errors like invalid shipmentId and unauthorized access with proper HTTP status codes and messages. Invoke related event handlers for order item status updates.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async createShipmentConfirmation(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallShipmentConfirmation.ICreate,
  ): Promise<IShoppingMallShipmentConfirmation> {
    try {
      return await postShoppingMallCustomerShipmentConfirmations({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API operation allows authenticated customers to confirm the delivery of shipments they have received. Upon confirmation, the shipment confirmation record is updated with the timestamp of confirmation, and the statuses of the associated shipment items and order items are updated to 'delivered'.
   *
   * The endpoint interacts with the shopping_mall_shipment_confirmations table, which records delivery confirmations at shipment level including the delivery confirmation timestamp.
   *
   * Security is enforced by allowing only authenticated customers to perform this action, ensuring that delivery confirmation is valid and trusted.
   *
   * The operation supports typical error handling for unauthorized access and invalid shipment confirmation data. It is closely related to the shipment tracking and order item status management functionality.
   *
   * Clients can use this operation in conjunction with shipment tracking endpoints to provide a complete view of shipment status and customer interactions.
   *
   * @param connection
   * @param body Delivery confirmation details to update shipment confirmation status
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement PATCH /shipmentConfirmations to process delivery confirmation updates.
   *
   * The service layer validates customer authentication and shipment existence.
   *
   * Update the shopping_mall_shipment_confirmations record with the confirmation timestamp.
   *
   * Update all related shipment items and order items statuses to 'delivered'.
   *
   * Ensure transaction atomicity to maintain data consistency.
   *
   * Return the updated shipment confirmation record.
   *
   * Handle errors for invalid input or unauthorized access appropriately.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updateDeliveryConfirmation(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallShipmentConfirmation.IUpdate,
  ): Promise<IShoppingMallShipmentConfirmation> {
    try {
      return await patchShoppingMallCustomerShipmentConfirmations({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shipment confirmation identified by its unique shipmentConfirmationId.
   *
   * This endpoint is used by customers and administrators to obtain confirmation data for shipments related to customer orders. The shipment confirmation includes details such as the timestamp of confirmation and linkage to the corresponding shipment.
   *
   * Authorization is required to ensure that only the owner customer, related sellers, or authorized administrators can access this data.
   *
   * This operation directly queries the shopping_mall_shipment_confirmations table storing immutable records of delivery confirmations made by customers, ensuring traceability and audit compliance.
   *
   * No request body is required as the identifier in the path is sufficient to fetch the resource.
   *
   * Expected responses include the complete shipment confirmation entity data with fields such as confirmation timestamp, shipment ID, and other relevant metadata.
   *
   * Associated operations include listing shipment confirmations for customers and sellers, managing shipment tracking entries, and viewing order shipment statuses.
   *
   * @param connection
   * @param shipmentConfirmationId Unique identifier of the shipment confirmation (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the shopping_mall_shipment_confirmations table by shipmentConfirmationId using a primary key lookup for efficient retrieval.
   * Ensure the request includes authorization validation to verify access rights for the requesting user (customer, seller, or administrator).
   * Return the shipment confirmation record containing confirmation timestamp and related shipment linkage.
   * Handle errors for not found (404) or unauthorized access (403).
   * No request body is needed.
   * Cache responses appropriately to optimize repeated access.
   *
   * This operation is part of the shipment and delivery confirmation features within the shopping mall platform, intended for customer order tracking and administrative oversight.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentConfirmationId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentConfirmationId")
    shipmentConfirmationId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipmentConfirmation> {
    try {
      return await getShoppingMallCustomerShipmentConfirmationsShipmentConfirmationId(
        {
          customer,
          shipmentConfirmationId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
