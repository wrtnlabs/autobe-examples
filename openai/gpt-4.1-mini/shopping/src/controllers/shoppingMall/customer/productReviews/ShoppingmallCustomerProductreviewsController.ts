import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerProductReviews } from "../../../../providers/postShoppingMallCustomerProductReviews";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteShoppingMallCustomerProductReviewsId } from "../../../../providers/deleteShoppingMallCustomerProductReviewsId";

import { IShoppingMallProductReview } from "../../../../api/structures/IShoppingMallProductReview";

@Controller("/shoppingMall/customer/productReviews")
export class ShoppingmallCustomerProductreviewsController {
  /**
   * Create a new product review linked to a product SKU, customer, and order.
   *
   * This operation allows authenticated customers to submit product reviews for
   * products they have purchased. The submitted review includes a numeric
   * rating from 1 to 5 and optional textual comments up to 1000 characters. The
   * system enforces that reviews can only be submitted for legitimate product
   * SKUs associated with the customer's completed orders.
   *
   * The review is created with a default moderation status (e.g., "pending") to
   * enable content moderation workflows before public display. This ensures
   * quality control and compliance with platform standards.
   *
   * Security considerations require that only customers who have purchased the
   * product can submit reviews, preventing fraudulent or spam reviews. Proper
   * authorization checks must be enforced on this endpoint.
   *
   * This operation is related to the shopping_mall_product_reviews table and
   * requires valid references to shopping_mall_product_skus,
   * shopping_mall_customers, and shopping_mall_orders tables. Validation rules
   * ensure rating values are between 1 and 5 inclusive.
   *
   * The API responds with the created review entity including timestamps and
   * current moderation status.
   *
   * @param connection
   * @param body Product review creation details including rating and optional
   *   text
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallProductReview.ICreate,
  ): Promise<IShoppingMallProductReview> {
    try {
      return await postShoppingMallCustomerProductReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a product review by its unique ID.
   *
   * This DELETE operation permanently removes a product review from the
   * platform's database. The shopping_mall_product_reviews table contains
   * customer-submitted reviews linked to specific product SKUs, customers, and
   * orders.
   *
   * The operation requires the unique identifier (UUID) of the target review to
   * locate and delete the record. This action is irreversible, resulting in the
   * permanent removal of the review and all associated data.
   *
   * Security considerations mandate this endpoint be accessible only by
   * authorized users such as admins, sellers, or the customer who created the
   * review, ensuring review deletion is managed properly.
   *
   * No request body is needed for this delete operation.
   *
   * No response body or confirmation message is returned; success is implied by
   * HTTP 204 status.
   *
   * Related operations include reviewing moderation queue management and review
   * creation.
   *
   * Be aware that this is a hard delete operation, deleting data completely
   * from the database.
   *
   * @param connection
   * @param id Unique UUID identifier of the product review to remove.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerProductReviewsId({
        customer,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
