import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerRefundRequests } from "../../../../providers/postShoppingMallCustomerRefundRequests";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerRefundRequests } from "../../../../providers/patchShoppingMallCustomerRefundRequests";
import { getShoppingMallCustomerRefundRequestsRefundRequestId } from "../../../../providers/getShoppingMallCustomerRefundRequestsRefundRequestId";

import { IShoppingMallRefundRequest } from "../../../../api/structures/IShoppingMallRefundRequest";
import { IPageIShoppingMallRefundRequest } from "../../../../api/structures/IPageIShoppingMallRefundRequest";

@Controller("/shoppingMall/customer/refundRequests")
export class ShoppingmallCustomerRefundrequestsController {
  /**
   * Create a new refund request for an order in the shopping mall platform. The
   * request must specify the refund amount, reason, and the associated order
   * ID.
   *
   * Security: Only authenticated customers or support staff can create refund
   * requests. Validation will be done to ensure refund amounts are valid and
   * orders are eligible.
   *
   * The request payload corresponds directly to the
   * shopping_mall_refund_requests Prisma model's create DTO, excluding managed
   * fields such as timestamps and status defaults which are handled
   * internally.
   *
   * Related operations include viewing refund status and updating or canceling
   * refund requests via other APIs.
   *
   * @param connection
   * @param body Payload to create a refund request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallRefundRequest.ICreate,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await postShoppingMallCustomerRefundRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of refund requests submitted by customers.
   * Supports filtering by refund status, request date, and other search
   * criteria.
   *
   * Authorization: Requires at least authenticated customer authorization to
   * view refund requests. Access can be further restricted based on user roles
   * and ownership.
   *
   * Response data includes refund amount, reason, status, request and
   * processing timestamps as defined in the underlying Prisma table
   * shopping_mall_refund_requests.
   *
   * Related operations: Separate endpoints should handle creation, updating,
   * and deletion of refund requests as per business logic.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for refund request
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallRefundRequest.IRequest,
  ): Promise<IPageIShoppingMallRefundRequest.ISummary> {
    try {
      return await patchShoppingMallCustomerRefundRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific refund request by its unique identifier. This endpoint
   * returns all pertinent information about the request including refund
   * amount, reason, current status, when it was requested, and when it was
   * processed if applicable.
   *
   * Security: Access to this endpoint may require appropriate authorization as
   * refund data is sensitive and linked to financial transactions. Only
   * authorized users such as admin or refund processors can view the details.
   *
   * The operation ties directly to the shopping_mall_refund_requests table from
   * the Prisma schema, ensuring accurate reflection of the stored data
   * including audit timestamps and soft deletion status.
   *
   * Related operations include creating a refund request and managing its
   * lifecycle through external workflows.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":refundRequestId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await getShoppingMallCustomerRefundRequestsRefundRequestId({
        customer,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
