import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerPayments } from "../../../../providers/postShoppingMallCustomerPayments";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerPaymentsId } from "../../../../providers/putShoppingMallCustomerPaymentsId";

import { IShoppingMallPayment } from "../../../../api/structures/IShoppingMallPayment";

@Controller("/shoppingMall/customer/payments")
export class ShoppingmallCustomerPaymentsController {
  /**
   * Create a new payment record for an order.
   *
   * Creates a new payment record linked to a specified order identified by its
   * unique order ID (UUID). The payment record includes payment method (e.g.,
   * credit_card, bank_transfer), payment status (e.g., pending, completed,
   * failed), payment amount matching the order total, and payment date. This
   * operation ensures secure handling and validation of payment data and
   * requires an authenticated customer to perform the action.
   *
   * Security considerations include authorization validation and data integrity
   * checks. Invalid payment details or unknown orders will result in errors.
   *
   * This operation acts on the shopping_mall_payments table as defined in the
   * Prisma schema, inserting new payment information for order fulfillment.
   *
   * @param connection
   * @param body Information required to create a new payment record for an
   *   order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async createPayment(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallPayment.ICreate,
  ): Promise<IShoppingMallPayment> {
    try {
      return await postShoppingMallCustomerPayments({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing payment record by ID.
   *
   * Updates details of an existing payment identified by its unique ID. The
   * payment to update is specified by the 'id' path parameter, which follows
   * UUID format. Only authorized customers may update their payment
   * information.
   *
   * Request body includes payment method, payment status, payment amount, and
   * payment date.
   *
   * Errors occur if the payment ID is not found or data is invalid.
   *
   * This operation performs updates on the shopping_mall_payments table per the
   * Prisma schema.
   *
   * @param connection
   * @param id Unique identifier of the payment record to update
   * @param body Fields for updating the payment record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async updatePayment(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallPayment.IUpdate,
  ): Promise<IShoppingMallPayment> {
    try {
      return await putShoppingMallCustomerPaymentsId({
        customer,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
