import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerCouponsCouponCodeRedemptions } from "../../../../../providers/postShoppingMallCustomerCouponsCouponCodeRedemptions";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerCouponsCouponCodeRedemptionsRedemptionId } from "../../../../../providers/putShoppingMallCustomerCouponsCouponCodeRedemptionsRedemptionId";

import { IShoppingMallCouponRedemption } from "../../../../../api/structures/IShoppingMallCouponRedemption";

@Controller("/shoppingMall/customer/coupons/:couponCode/redemptions")
export class ShoppingmallCustomerCouponsRedemptionsController {
  /**
   * Create a coupon redemption for the given coupon code.
   *
   * Create a new coupon redemption under a specific coupon identified by its
   * unique couponCode.
   *
   * This operation records the details of the redemption event, including the
   * customer, order, date, and status. It ensures that coupon usage rules are
   * enforced, such as limits per customer and coupon expiration dates.
   *
   * Security: Only authorized users such as customers or system services can
   * create redemptions. Validation includes verifying coupon status and
   * eligibility.
   *
   * The operation interacts with the shopping_mall_coupon_redemptions table in
   * the database, inserting a new row and updating dependent statistics.
   *
   * Related operation: updating a coupon redemption via the PUT request on
   * /coupons/{couponCode}/redemptions/{redemptionId}.
   *
   * @param connection
   * @param couponCode Unique business identifier code of the target coupon
   *   (global scope)
   * @param body Coupon redemption creation details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("couponCode")
    couponCode: string,
    @TypedBody()
    body: IShoppingMallCouponRedemption.ICreate,
  ): Promise<IShoppingMallCouponRedemption> {
    try {
      return await postShoppingMallCustomerCouponsCouponCodeRedemptions({
        customer,
        couponCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a coupon redemption by redemptionId for the given coupon code.
   *
   * Update a coupon redemption identified by redemptionId under the specific
   * coupon code.
   *
   * Allows modification of redemption details such as status, redemption date,
   * or associated customer/order information.
   *
   * Security: Only authorized users such as customers or system services can
   * update redemption records. Validation ensures data consistency.
   *
   * This operation works on the shopping_mall_coupon_redemptions table in the
   * database, modifying the existing redemption entry.
   *
   * Related operation: create a redemption via POST to
   * /coupons/{couponCode}/redemptions.
   *
   * @param connection
   * @param couponCode Unique business identifier code of the target coupon
   *   (global scope)
   * @param redemptionId Unique identifier of the coupon redemption record
   * @param body Coupon redemption update details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":redemptionId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("couponCode")
    couponCode: string,
    @TypedParam("redemptionId")
    redemptionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCouponRedemption.IUpdate,
  ): Promise<IShoppingMallCouponRedemption> {
    try {
      return await putShoppingMallCustomerCouponsCouponCodeRedemptionsRedemptionId(
        {
          customer,
          couponCode,
          redemptionId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
