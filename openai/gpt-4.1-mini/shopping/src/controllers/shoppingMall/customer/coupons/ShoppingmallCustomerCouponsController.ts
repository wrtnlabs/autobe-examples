import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallCustomerCoupons } from "../../../../providers/patchShoppingMallCustomerCoupons";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerCouponsCouponCode } from "../../../../providers/getShoppingMallCustomerCouponsCouponCode";

import { IPageIShoppingMallCoupon } from "../../../../api/structures/IPageIShoppingMallCoupon";
import { IShoppingMallCoupon } from "../../../../api/structures/IShoppingMallCoupon";

@Controller("/shoppingMall/customer/coupons")
export class ShoppingmallCustomerCouponsController {
  /**
   * Retrieve a paginated and filtered list of coupons.
   *
   * Retrieve and search through the list of shopping mall coupons using
   * advanced filtering, searching, and pagination parameters.
   *
   * This API endpoint supports search by coupon code, type, date range for
   * coupon validity, and filtering based on deletion status (active or deleted)
   * using the deleted_at field.
   *
   * Clients can paginate results with customizable page size and page number,
   * and sort by various coupon attributes like start_date, end_date, or
   * discount_value.
   *
   * Security: Only authenticated customers are allowed to list coupons. Data
   * returned includes all coupon details except for soft-deleted coupons unless
   * explicitly filtered.
   *
   * This operation operates on the shopping_mall_coupons table as defined in
   * the Prisma DB schema. The response body returns a paginated list of coupon
   * summaries conforming to the IShoppingMallCoupon.ISummary interface.
   *
   * @param connection
   * @param body Search and pagination parameters for filtering coupons
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCoupon.IRequest,
  ): Promise<IPageIShoppingMallCoupon.ISummary> {
    try {
      return await patchShoppingMallCustomerCoupons({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed coupon information by code.
   *
   * Fetch detailed information about a specific coupon identified by its unique
   * coupon code.
   *
   * This operation provides all coupon attributes including code, type,
   * discount value, validity range, and timestamps. The couponCode path
   * parameter uniquely identifies the coupon resource using the code unique
   * index as defined in the shopping_mall_coupons Prisma model to ensure
   * uniqueness.
   *
   * Security: Only authenticated customers can retrieve coupon details.
   * Soft-deleted coupons are excluded by default.
   *
   * This operation corresponds to the shopping_mall_coupons table in the
   * database.
   *
   * @param connection
   * @param couponCode Unique code identifying the target coupon (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":couponCode")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("couponCode")
    couponCode: string,
  ): Promise<IShoppingMallCoupon> {
    try {
      return await getShoppingMallCustomerCouponsCouponCode({
        customer,
        couponCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
