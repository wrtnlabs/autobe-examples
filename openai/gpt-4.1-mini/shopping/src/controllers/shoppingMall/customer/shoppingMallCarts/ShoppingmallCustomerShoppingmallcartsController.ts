  /**
   * Create a new shopping mall cart.
   *
   * This operation allows authenticated customers to create a new shopping mall
   * cart, which represents a persistent collection of selected product SKUs
   * intended for purchase.
   *
   * Each cart must be associated with a customer through a valid customer ID.
   * Optionally, it can be linked to a specific customer session for enhanced
   * tracking across sessions.
   *
   * The system records creation and update timestamps automatically. The cart
   * can also be soft deleted by setting the 'deleted_at' timestamp, but this is
   * managed internally and not part of this operation.
   *
   * Security: Only authenticated users with the 'customer' actor can create
   * carts. The operation enforces ownership checks and validates referenced
   * customer and session IDs.
   *
   * Related APIs: Update cart (PUT /shoppingMallCarts/{shoppingMallCartId}) for
   * modifying existing carts.
   *
   * @param connection
   * @param body Shopping mall cart creation payload
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
