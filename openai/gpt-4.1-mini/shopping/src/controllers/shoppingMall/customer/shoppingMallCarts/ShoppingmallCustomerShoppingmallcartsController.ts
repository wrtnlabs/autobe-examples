  /**
   * Get details of a shopping mall cart by ID.
   *
   * Retrieve detailed information of a specific shopping mall cart by its
   * unique ID.
   *
   * This operation allows authorized users to fetch all pertinent data related
   * to a single shopping cart, including customer association, session linkage,
   * creation and update timestamps, and soft deletion status.
   *
   * The operation ensures that the cart exists and is accessible based on the
   * provided identifier, returning comprehensive cart metadata to facilitate
   * checkout workflows, cart editing, or analytics.
   *
   * Security restrictions apply to ensure only the owning user or authorized
   * parties can perform this query.
   *
   * This API directly reflects the structure and constraints of the
   * shopping_mall_carts Prisma table.
   *
   * @param connection
   * @param shoppingMallCartId Unique identifier of the target shopping mall
   *   cart
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shoppingMallCartId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shoppingMallCartId")
    shoppingMallCartId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCart> {
    try {
      return await getShoppingMallCustomerShoppingMallCartsShoppingMallCartId({
        customer,
        shoppingMallCartId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shopping mall cart.
   *
   * This operation allows authenticated customers to update details of an
   * existing shopping mall cart by specifying its unique identifier.
   *
   * Fields such as 'updated_at' can be modified to reflect the latest changes.
   * Soft deletion can be indicated by setting 'deleted_at' timestamp, which is
   * nullable.
   *
   * The operation validates that the cart belongs to the requesting user and
   * ensures referential integrity with the associated customer and session.
   *
   * Security considerations include strict ownership validation and
   * authorization checks for the 'customer' actor.
   *
   * Related APIs: Create cart (POST /shoppingMallCarts) for creating new carts.
   *
   * @param connection
   * @param shoppingMallCartId Unique identifier of the target shopping mall
   *   cart (UUID)
   * @param body Shopping mall cart update payload
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
