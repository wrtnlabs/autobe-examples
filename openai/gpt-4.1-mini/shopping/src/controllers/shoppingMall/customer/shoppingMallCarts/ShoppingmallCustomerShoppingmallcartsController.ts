import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerShoppingMallCarts } from "../../../../providers/postShoppingMallCustomerShoppingMallCarts";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerShoppingMallCarts } from "../../../../providers/patchShoppingMallCustomerShoppingMallCarts";
import { getShoppingMallCustomerShoppingMallCartsShoppingMallCartId } from "../../../../providers/getShoppingMallCustomerShoppingMallCartsShoppingMallCartId";
