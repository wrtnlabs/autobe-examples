import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallCustomerCustomerInquiriesId } from "../../../../providers/getShoppingMallCustomerCustomerInquiriesId";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerCustomerInquiriesId } from "../../../../providers/putShoppingMallCustomerCustomerInquiriesId";
import { deleteShoppingMallCustomerCustomerInquiriesId } from "../../../../providers/deleteShoppingMallCustomerCustomerInquiriesId";
import { postShoppingMallCustomerCustomerInquiries } from "../../../../providers/postShoppingMallCustomerCustomerInquiries";

import { IShoppingMallCustomerInquiry } from "../../../../api/structures/IShoppingMallCustomerInquiry";

@Controller("/shoppingMall/customer/customerInquiries")
export class ShoppingmallCustomerCustomerinquiriesController {
  /**
   * Retrieve detailed information of a specific customer inquiry.
   *
   * Retrieve detailed information about a specific customer inquiry using its
   * unique identifier.
   *
   * This endpoint allows users or authorized actors to fetch all relevant
   * information regarding a customer's inquiry including the content, status,
   * and timestamps. It ensures secure access by restricting to authenticated
   * customers.
   *
   * The API interacts directly with the shopping_mall_customer_inquiries table
   * as defined in the Prisma schema and returns structured data compliant with
   * the schema.
   *
   * Proper validation and authorization checks are enforced to ensure data
   * privacy and integrity.
   *
   * @param connection
   * @param id Unique identifier of the customer inquiry
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerInquiry> {
    try {
      return await getShoppingMallCustomerCustomerInquiriesId({
        customer,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific customer inquiry.
   *
   * Update the details of a specific customer inquiry in the shopping mall
   * platform.
   *
   * This endpoint allows authenticated customers to modify the inquiry title,
   * detailed body content, and the current status of the inquiry. It is
   * intended for managing ongoing customer support tickets to reflect progress
   * or changes requested by the customer.
   *
   * Security considerations include ensuring only the owner of the inquiry or
   * authorized support staff may perform updates. The operation ensures data
   * consistency by updating the 'updated_at' timestamp to reflect the last
   * modification time.
   *
   * The operation directly manipulates data in the
   * 'shopping_mall_customer_inquiries' Prisma table, referencing related
   * customer and session information as foreign keys.
   *
   * @param connection
   * @param id Unique UUID identifier of the target customer inquiry
   * @param body Customer inquiry update payload with title, body, and status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCustomerInquiry.IUpdate,
  ): Promise<IShoppingMallCustomerInquiry> {
    try {
      return await putShoppingMallCustomerCustomerInquiriesId({
        customer,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific customer inquiry.
   *
   * Permanently remove a specific customer inquiry from the shopping mall
   * platform.
   *
   * This endpoint performs a hard deletion of the inquiry record identified by
   * its unique 'id'. It is intended to support scenarios such as user-requested
   * removal of their own inquiries or administrative cleanup of resolved
   * cases.
   *
   * Security measures ensure that only authorized customers can perform this
   * operation to prevent accidental or malicious data loss.
   *
   * The operation directly affects the 'shopping_mall_customer_inquiries'
   * Prisma table and deletes the record permanently, bypassing any soft
   * deletion mechanisms.
   *
   * @param connection
   * @param id Unique UUID identifier of the target customer inquiry
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerCustomerInquiriesId({
        customer,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new customer inquiry allowing authenticated customers to submit
   * questions, complaints, or feedback.
   *
   * This endpoint accepts inquiry creation data conforming to the
   * IShoppingMallCustomerInquiry.ICreate schema. It validates user
   * authentication and input data before storing the inquiry.
   *
   * The created inquiry record is returned with a unique identifier and
   * timestamps confirming successful creation.
   *
   * Strict validation ensures data consistency and security throughout the
   * process.
   *
   * @param connection
   * @param body Customer inquiry creation payload
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCustomerInquiry.ICreate,
  ): Promise<IShoppingMallCustomerInquiry> {
    try {
      return await postShoppingMallCustomerCustomerInquiries({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
