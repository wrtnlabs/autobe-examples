  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("saleId")
    saleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSaleReview.ICreate,
  ): Promise<IShoppingMallSaleReview> {
    try {
      return await postShoppingMallCustomerSalesSaleIdReviews({
        customer,
        saleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a customer review for a specific sale in the shopping mall platform.
   *
   * This operation enables authenticated customers to modify their submitted review, including the star rating (integer 1-5) and optional textual feedback. The review is identified uniquely by both saleId and reviewId to ensure correct resource targeting.
   *
   * Authorization is required ensuring only the authoring customer can update their own review. The operation maintains review integrity and traceability by modifying rating and body fields.
   *
   * The underlying database entity is shopping_mall_sale_reviews, which relates reviews to sales and customers. The update operation executes a full replacement of review content.
   *
   * Related operations include creating new reviews (POST /customers/sales/{saleId}/reviews) and deleting reviews (DELETE /customers/sales/{saleId}/reviews/{reviewId}).
   *
   * Error responses cover unauthorized access, review not found, and validation violations on rating value.
   *
   * @param connection
   * @param saleId UUID of the sale to which the review belongs
   * @param reviewId UUID of the review to update
   * @param body Updated review data including star rating and optional review text
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification The implementation involves verifying customer ownership of the review identified by reviewId linked to saleId. Validation must ensure rating field is an integer between 1 and 5 inclusive. The optional body text is updated if provided. The update is transactional to ensure data integrity. On success, the updated review entity is retrieved and returned.
   *
   * Database query updates shopping_mall_sale_reviews table filtering by id = reviewId and shopping_mall_sale_id = saleId with new values for rating and optional body. Cascade updates maintain referential integrity.
   *
   * Unauthorized users receive an error. Input validation errors are handled gracefully. This operation is part of customer review management workflows.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
