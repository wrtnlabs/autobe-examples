import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerShoppingMallArticles } from "../../../../providers/postShoppingMallCustomerShoppingMallArticles";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerShoppingMallArticles } from "../../../../providers/patchShoppingMallCustomerShoppingMallArticles";
import { putShoppingMallCustomerShoppingMallArticlesShoppingMallArticleId } from "../../../../providers/putShoppingMallCustomerShoppingMallArticlesShoppingMallArticleId";
import { deleteShoppingMallCustomerShoppingMallArticlesShoppingMallArticleId } from "../../../../providers/deleteShoppingMallCustomerShoppingMallArticlesShoppingMallArticleId";

import { IShoppingMallArticle } from "../../../../api/structures/IShoppingMallArticle";
import { IPageIShoppingMallArticle } from "../../../../api/structures/IPageIShoppingMallArticle";

@Controller("/shoppingMall/customer/shoppingMallArticles")
export class ShoppingmallCustomerShoppingmallarticlesController {
  /**
   * Create a new shopping mall article.
   *
   * Authenticated users with sufficient permissions may submit article details
   * through the request body. The system validates required fields such as
   * title and content, associates the article with relevant categories and
   * metadata, and persists the data.
   *
   * Upon successful creation, the full article entity is returned including its
   * assigned unique identifier and timestamps. Unauthorized attempts or
   * validation failures will be rejected with appropriate error responses.
   *
   * @param connection
   * @param body Request body for creating a shopping mall article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallArticle.ICreate,
  ): Promise<IShoppingMallArticle> {
    try {
      return await postShoppingMallCustomerShoppingMallArticles({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve paginated list of shopping mall articles.
   *
   * Retrieve a filtered and paginated list of user-posted articles from the
   * shopping mall platform.
   *
   * This operation accepts complex search parameters via its request body to
   * filter articles by title, body content, authorship, category, and creation
   * date ranges.
   *
   * Results are returned in a paginated format including summary information
   * for each article.
   *
   * Security considerations include access control to ensure only authenticated
   * customers can access the articles. The operation interacts with the
   * shopping_mall_articles table, respecting soft deletion by omitting records
   * with deleted_at timestamps.
   *
   * Related operations include single article retrieval, article creation, and
   * article updates (not shown here).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   articles
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallArticle.IRequest,
  ): Promise<IPageIShoppingMallArticle.ISummary> {
    try {
      return await patchShoppingMallCustomerShoppingMallArticles({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a shopping mall article by its ID.
   *
   * Update an existing shopping mall article specified by its UUID identifier.
   *
   * This operation allows updating the article's title, body content, and
   * category association while preserving relations to its author and
   * category.
   *
   * Security restrictions ensure only authorized users (article authors or
   * admins) can perform updates. The system enforces the uniqueness constraint
   * on the article title for the author to maintain content consistency.
   *
   * The article's updated_at timestamp is automatically refreshed to indicate
   * the modification time.
   *
   * Other operations: Create article (POST /shoppingMallArticles), Delete
   * article (DELETE /shoppingMallArticles/{shoppingMallArticleId}), Retrieve
   * article (GET /shoppingMallArticles/{shoppingMallArticleId}).
   *
   * @param connection
   * @param shoppingMallArticleId Unique identifier (UUID) of the target
   *   shopping mall article
   * @param body Data required for updating a shopping mall article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shoppingMallArticleId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shoppingMallArticleId")
    shoppingMallArticleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallArticle.IUpdate,
  ): Promise<IShoppingMallArticle> {
    try {
      return await putShoppingMallCustomerShoppingMallArticlesShoppingMallArticleId(
        {
          customer,
          shoppingMallArticleId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a shopping mall article by its ID.
   *
   * Delete a shopping mall article by its unique identifier.
   *
   * This operation performs a hard delete, permanently removing the article and
   * its associated comments.
   *
   * Security constraints ensure only authorized users (article authors or
   * admins) can execute this action.
   *
   * Other operations: Create article (POST /shoppingMallArticles), Retrieve
   * article (GET /shoppingMallArticles/{shoppingMallArticleId}), Update article
   * (PUT /shoppingMallArticles/{shoppingMallArticleId}).
   *
   * @param connection
   * @param shoppingMallArticleId Unique identifier (UUID) of the article to
   *   delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":shoppingMallArticleId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shoppingMallArticleId")
    shoppingMallArticleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerShoppingMallArticlesShoppingMallArticleId(
        {
          customer,
          shoppingMallArticleId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
