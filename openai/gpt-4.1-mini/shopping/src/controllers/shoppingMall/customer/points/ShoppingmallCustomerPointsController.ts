import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallCustomerPointsPointId } from "../../../../providers/getShoppingMallCustomerPointsPointId";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { postShoppingMallCustomerPoints } from "../../../../providers/postShoppingMallCustomerPoints";

import { IShoppingMallPoints } from "../../../../api/structures/IShoppingMallPoints";

@Controller("/shoppingMall/customer/points")
export class ShoppingmallCustomerPointsController {
  /**
   * Get detailed information of a specific customer loyalty point record.
   *
   * Retrieve the detailed information for a specific customer loyalty point
   * record identified by its unique point ID.
   *
   * This endpoint fetches the full details of the point record, including the
   * current balance of points the customer has accrued, timestamps of creation
   * and last update, and any soft deletion timestamp.
   *
   * Security: Access to this endpoint requires appropriate authorization,
   * ensuring only permitted actors can view sensitive customer point data.
   *
   * This API operation directly maps to the shopping_mall_points Prisma table
   * and respects the database schema structure, providing a single point of
   * truth for customer loyalty points.
   *
   * Related operations: Create new point record (POST /points).
   *
   * @param connection
   * @param pointId Unique identifier of the customer point record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":pointId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("pointId")
    pointId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallPoints> {
    try {
      return await getShoppingMallCustomerPointsPointId({
        customer,
        pointId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create new customer loyalty point record.
   *
   * Create a new loyalty point record associated with a customer.
   *
   * This operation adds a points record reflecting the credited points for the
   * customer under loyalty or promotional programs. The request must include
   * the customer identifier and initial balance of points.
   *
   * Security: Only authorized users with permission to create point records can
   * execute this operation.
   *
   * The created record will include system-generated timestamps for creation
   * and updates managed internally.
   *
   * Upon success, the full point record is returned.
   *
   * Related operations: Retrieve point record details (GET /points/{pointId}).
   *
   * @param connection
   * @param body New customer point record creation payload
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallPoints.ICreate,
  ): Promise<IShoppingMallPoints> {
    try {
      return await postShoppingMallCustomerPoints({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
