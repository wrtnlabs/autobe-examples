import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerShoppingMallFavoriteSellers } from "../../../../../providers/postShoppingMallCustomerShoppingMallFavoriteSellers";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerShoppingMallFavoriteSellers } from "../../../../../providers/patchShoppingMallCustomerShoppingMallFavoriteSellers";
import { getShoppingMallCustomerShoppingMallFavoriteSellersFavoriteSellerId } from "../../../../../providers/getShoppingMallCustomerShoppingMallFavoriteSellersFavoriteSellerId";
import { putShoppingMallCustomerShoppingMallFavoriteSellersId } from "../../../../../providers/putShoppingMallCustomerShoppingMallFavoriteSellersId";
import { deleteShoppingMallCustomerShoppingMallFavoriteSellersId } from "../../../../../providers/deleteShoppingMallCustomerShoppingMallFavoriteSellersId";

import { IShoppingMallFavoriteSeller } from "../../../../../api/structures/IShoppingMallFavoriteSeller";
import { IPageIShoppingMallFavoriteSeller } from "../../../../../api/structures/IPageIShoppingMallFavoriteSeller";

@Controller("/shoppingMall/customer/shoppingMall/favoriteSellers")
export class ShoppingmallCustomerShoppingmallFavoritesellersController {
  /**
   * Create a new favorite seller for the authenticated customer.
   *
   * Add a seller to the customer's favorite sellers list.
   *
   * This POST operation creates a new record in the favorite sellers database
   * table, associating the authenticated customer with the specified seller. It
   * allows customers to quickly mark sellers for future reference or
   * promotional notifications.
   *
   * Security considerations include ensuring that the customer is authenticated
   * and authorized to create favorite seller entries. Validation will confirm
   * the seller exists and prevent duplicates.
   *
   * The API consumes the favorite seller creation data and returns the complete
   * record upon successful creation.
   *
   * Related operations: PUT /shoppingMall/favoriteSellers/{id} to update
   * favorite seller details or notes.
   *
   * @param connection
   * @param body Favorite seller creation data including seller and customer
   *   references
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallFavoriteSeller.ICreate,
  ): Promise<IShoppingMallFavoriteSeller> {
    try {
      return await postShoppingMallCustomerShoppingMallFavoriteSellers({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve paginated list of favorite sellers.
   *
   * Retrieve a filtered and paginated list of favorite sellers in the shopping
   * mall platform.
   *
   * This operation allows authenticated customers to browse their list of
   * favorite sellers with support for filtering and pagination to improve
   * usability in scenarios where a customer favorites many sellers.
   *
   * Only customers themselves or authorized users can access this list. The API
   * supports sorting by date added or seller name. Security is enforced to
   * prevent unauthorized access.
   *
   * It queries the shopping_mall_favorite_sellers table as defined in the
   * Prisma schema, returning summaries optimized for list display.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for favorite sellers
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallFavoriteSeller.IRequest,
  ): Promise<IPageIShoppingMallFavoriteSeller.ISummary> {
    try {
      return await patchShoppingMallCustomerShoppingMallFavoriteSellers({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve favorite seller details by ID.
   *
   * Retrieve details of a specific favorite seller by its unique identifier.
   *
   * This operation fetches complete favorite seller information from the
   * shopping_mall_favorite_sellers table defined in the Prisma schema.
   *
   * Authorization ensures only the owner or permitted users can access this
   * record. The returned data aids in UI rendering for managing favorite
   * sellers.
   *
   * Path parameter favoriteSellerId must be a UUID identifying the target
   * favorite seller record.
   *
   * @param connection
   * @param favoriteSellerId Unique identifier of the target favorite seller
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":favoriteSellerId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("favoriteSellerId")
    favoriteSellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallFavoriteSeller> {
    try {
      return await getShoppingMallCustomerShoppingMallFavoriteSellersFavoriteSellerId(
        {
          customer,
          favoriteSellerId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a favorite seller by ID for the authenticated customer.
   *
   * Update favorite seller details by favorite seller ID.
   *
   * This PUT operation modifies existing favorite seller data for the
   * authenticated customer based on the unique favorite seller ID provided in
   * the path. Customers can update notes, status, or other mutable fields.
   *
   * Security enforcement verifies ownership to prevent unauthorized access or
   * modification of other customers' favorite sellers.
   *
   * Successful updates return the updated favorite seller record.
   *
   * API clients should handle possible validation errors if update data is
   * invalid or the favorite seller does not exist.
   *
   * @param connection
   * @param id Unique identifier (UUID) of the favorite seller record to update
   * @param body Favorite seller update data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallFavoriteSeller.IUpdate,
  ): Promise<IShoppingMallFavoriteSeller> {
    try {
      return await putShoppingMallCustomerShoppingMallFavoriteSellersId({
        customer,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a favorite seller relationship by ID.
   *
   * This DELETE operation removes an existing favorite seller relationship
   * identified by its unique ID from the shopping mall database.
   *
   * It is a final removal operation that permanently deletes the record,
   * eliminating the association between the customer and the seller.
   *
   * Security considerations include permissions ensuring only authenticated
   * customers can delete their own favorite sellers. There is no request body
   * since the deletion is based solely on the path parameter.
   *
   * This operation complements the favorite sellers listing and creation
   * endpoints, allowing customers to manage their favorite sellers
   * dynamically.
   *
   * @param connection
   * @param id Unique identifier of the favorite seller relationship to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerShoppingMallFavoriteSellersId({
        customer,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
