import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerProfile } from "../../../../providers/getShoppingMallCustomerProfile";
import { putShoppingMallCustomerProfile } from "../../../../providers/putShoppingMallCustomerProfile";

@Controller("/shoppingMall/customer/profile")
export class ShoppingmallCustomerProfileController {
  /**
   * Retrieve the authenticated customer's profile information including email, display name, and phone number. This endpoint returns the customer's current profile details stored in the shopping_mall_customers table.
   *
   * This operation accesses the primary key id internally via authentication and does not require any path parameters.
   *
   * Only the owning authenticated customer should have access to this endpoint, ensuring privacy and security.
   *
   * This operation returns the customer's profile data in a consistent DTO format for easy use by frontend clients.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_customers table using authenticated user's id from session
   * Return the customer's profile information including id, email, displayName, phoneNumber
   * No path parameters needed
   * No request body
   * Use appropriate error handling for cases when user is not found or not authenticated
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await getShoppingMallCustomerProfile({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated customer's profile information including display name and phone number.
   *
   * This operation allows customers to modify their profile details stored in the shopping_mall_customers database table. The authenticated customer is identified from the session context; hence no customer ID is required in the path.
   *
   * The request body accepts the fields display_name and phone_number, which are both optional and can be updated independently.
   *
   * The response returns the full customer profile with all current values as stored in the database.
   *
   * Authorization is limited to the authenticated customer only. Attempting to update another customer's profile is not permitted.
   *
   * This operation enforces validation and business logic to ensure data integrity and consistency.
   *
   * @param connection
   * @param body The customer's profile data to update, including display name and phone number.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Authenticate the customer making the request.
   * 2. Extract the customer ID from the session context.
   * 3. Validate the request body for allowed fields: display_name and phone_number.
   * 4. Update the corresponding fields in the shopping_mall_customers table.
   * 5. Return the updated customer profile as the response body.
   * 6. Handle validation errors and unauthorized attempts appropriately.
   * 7. No path parameters are required as the customer is identified via authentication.
   * 8. Ensure transactional integrity and error handling for database interactions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCustomer.IUpdate,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await putShoppingMallCustomerProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
