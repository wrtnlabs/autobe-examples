import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerOrderCancellations } from "../../../../providers/postShoppingMallCustomerOrderCancellations";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerOrderCancellationsOrderCancellationId } from "../../../../providers/putShoppingMallCustomerOrderCancellationsOrderCancellationId";

import { IShoppingMallOrderCancellation } from "../../../../api/structures/IShoppingMallOrderCancellation";

@Controller("/shoppingMall/customer/orderCancellations")
export class ShoppingmallCustomerOrdercancellationsController {
  /**
   * Create a new order cancellation request for a specific order in the
   * shopping mall system.
   *
   * This operation allows authenticated customers to submit cancellation
   * requests specifying reasons and relevant details. It validates input data
   * against business rules ensuring the order is eligible for cancellation.
   *
   * Security: Only authenticated customers or users with proper roles can
   * create cancellation requests. The cancellation is tracked and managed
   * according to system policies.
   *
   * Related operations include updating cancellation requests (PUT
   * /orderCancellations/{orderCancellationId}) and listing cancellations for
   * order management.
   *
   * @param connection
   * @param body Order cancellation creation data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallOrderCancellation.ICreate,
  ): Promise<IShoppingMallOrderCancellation> {
    try {
      return await postShoppingMallCustomerOrderCancellations({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing order cancellation request by its unique identifier.
   *
   * This operation allows authorized users, typically customers or
   * administrators, to modify details of cancellation requests including status
   * updates such as approval or rejection.
   *
   * Security: Access controls ensure only users with appropriate permissions
   * can update cancellation requests.
   *
   * Related endpoints include creating new cancellations (POST
   * /orderCancellations) and retrieving cancellations for review and
   * management.
   *
   * @param connection
   * @param orderCancellationId Unique identifier of the order cancellation to
   *   update
   * @param body Order cancellation update data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":orderCancellationId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCancellationId")
    orderCancellationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderCancellation.IUpdate,
  ): Promise<IShoppingMallOrderCancellation> {
    try {
      return await putShoppingMallCustomerOrderCancellationsOrderCancellationId(
        {
          customer,
          orderCancellationId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
