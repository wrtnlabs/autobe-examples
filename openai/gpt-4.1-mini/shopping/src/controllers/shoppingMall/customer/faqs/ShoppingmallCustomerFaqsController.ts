import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerFaqs } from "../../../../providers/postShoppingMallCustomerFaqs";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerFaqsId } from "../../../../providers/putShoppingMallCustomerFaqsId";

import { IShoppingMallFaq } from "../../../../api/structures/IShoppingMallFaq";

@Controller("/shoppingMall/customer/faqs")
export class ShoppingmallCustomerFaqsController {
  /**
   * Create a new FAQ entry in the shopping mall platform.
   *
   * This operation allows authorized users to add new frequently asked
   * questions to the system. Each FAQ consists of a question and an answer to
   * assist customers in resolving common issues.
   *
   * Security: Only authenticated users with proper permissions can create FAQs.
   * Input data is validated to comply with content policies and length limits.
   *
   * Related operations include updating existing FAQ entries (PUT /faqs/{id}),
   * and retrieving FAQ lists for display.
   *
   * @param connection
   * @param body Data structure for creating a new FAQ entry
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallFaq.ICreate,
  ): Promise<IShoppingMallFaq> {
    try {
      return await postShoppingMallCustomerFaqs({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing FAQ entry in the shopping mall platform by FAQ unique
   * identifier.
   *
   * This operation enables authorized users to modify the question or answer
   * content of an existing FAQ record. Used primarily for correcting or
   * improving FAQ content.
   *
   * Security: Only users with edit permissions may perform this operation.
   * Input validation ensures updated fields meet required formats and lengths.
   *
   * Related operations include creating new FAQs (POST /faqs) and retrieving
   * FAQ details or lists.
   *
   * @param connection
   * @param id Unique identifier of the FAQ entry to update
   * @param body Data structure for updating an existing FAQ entry
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallFaq.IUpdate,
  ): Promise<IShoppingMallFaq> {
    try {
      return await putShoppingMallCustomerFaqsId({
        customer,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
