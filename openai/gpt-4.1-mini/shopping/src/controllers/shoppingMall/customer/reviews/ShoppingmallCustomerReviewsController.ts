import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallReview } from "../../../../api/structures/IPageIShoppingMallReview";
import { IShoppingMallReview } from "../../../../api/structures/IShoppingMallReview";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteShoppingMallCustomerReviewsReviewId } from "../../../../providers/deleteShoppingMallCustomerReviewsReviewId";
import { getShoppingMallCustomerReviewsReviewId } from "../../../../providers/getShoppingMallCustomerReviewsReviewId";
import { patchShoppingMallCustomerReviews } from "../../../../providers/patchShoppingMallCustomerReviews";
import { postShoppingMallCustomerReviews } from "../../../../providers/postShoppingMallCustomerReviews";
import { putShoppingMallCustomerReviewsReviewId } from "../../../../providers/putShoppingMallCustomerReviewsReviewId";

@Controller("/shoppingMall/customer/reviews")
export class ShoppingmallCustomerReviewsController {
  /**
   * Create a new product review for a purchased product.
   *
   * This endpoint allows authenticated customers to submit a one-time review for each product they bought and received as part of an order.
   *
   * The request body must include the star rating (1 to 5) and may contain optional textual comments.
   *
   * Business logic ensures that customers can only create reviews for products they have purchased and that have been delivered.
   *
   * Each review creation triggers immutability by snapshotting the review data for audit and dispute resolution.
   *
   * This operation strictly accepts POST requests with the review creation data.
   *
   * The response returns the detailed review information including rating, content, associated order item, and timestamps.
   *
   * Related operations include PUT /reviews/{reviewId} for editing and DELETE /reviews/{reviewId} for deletion preserving snapshots.
   *
   * This endpoint is part of the customer review management feature in the shopping mall platform.
   *
   * @param connection
   * @param body Product review creation payload
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Handle POST to /reviews by validating customer authentication and purchase evidence.
   * Verify the product and order item have been delivered and no existing review exists.
   * Create the shopping_mall_reviews record with rating, content, and references to order item and product variant.
   * Save immutable snapshots of the review upon creation.
   * Return newly created review entity details.
   * Handle errors such as duplicate reviews, unauthorized access, and validation failures.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallReview.ICreate,
  ): Promise<IShoppingMallReview> {
    try {
      return await postShoppingMallCustomerReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of customer product reviews along with star ratings and optional textual content.
   *
   * This API operation facilitates advanced search capabilities for customer reviews in the shopping mall platform. It supports filtering by customer ID, order ID, order item ID, rating boundaries, creation and update date ranges, and soft deletion status.
   *
   * The operation excludes deleted reviews by default, but allows inclusion based on search parameters. It returns results with pagination metadata for efficient display in client applications.
   *
   * Authorization is required. This operation is accessible to authenticated customers, sellers, and administrators with the necessary permissions.
   *
   * This operation is part of a larger review lifecycle, complementing:
   * - `POST /shoppingMall/customer/reviews` to create a new review
   * - `PUT /shoppingMall/customer/reviews/{reviewId}` to update an existing review
   * - `DELETE /shoppingMall/customer/reviews/{reviewId}` to delete a review permanently
   *
   * Client applications should handle validation errors related to search criteria, pagination parameters, and authorization failures appropriately.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for customer reviews.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Perform a paginated query on shopping_mall_reviews table applying search filters:
   * - customer_id, order_id, order_item_id equality filters
   * - rating range filter (min/max)
   * - created_at and updated_at date range filters
   * - include/exclude soft deleted reviews based on deleted_at filter
   * Return results as IPageIShoppingMallReview.ISummary with pagination metadata.
   * Request body type is IShoppingMallReview.IRequest containing search parameters.
   * No path parameters as this is a collection search operation.
   * Handle validation errors for pagination and search parameters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallReview.IRequest,
  ): Promise<IPageIShoppingMallReview.ISummary> {
    try {
      return await patchShoppingMallCustomerReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a product review.
   *
   * This operation returns the full details of a customer review for a purchased product, including the star rating and optional textual content. The review is uniquely identified by reviewId, which corresponds to the review's primary key UUID.
   *
   * Security considerations require that only authorized users such as the review author or administrators can access the review details.
   *
   * The review entity relates to customers, orders, and order items, ensuring that reviews are only for verified transactions.
   *
   * The operation supports auditing and historical integrity by including creation and update timestamps, and optional deletion timestamp to indicate if the review has been removed.
   *
   * Errors such as invalid or non-existent reviewId should be handled gracefully with appropriate error codes.
   *
   * Related API operations include endpoints for creating, updating, and deleting reviews.
   *
   * @param connection
   * @param reviewId Unique identifier of the product review (UUID).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the shopping_mall_reviews table to fetch the review record by the primary key reviewId.
   *
   * Validate the reviewId path parameter as UUID format.
   *
   * Authorize access to ensure only the review author (customer) or administrators can view the review.
   *
   * Return all fields of the review including id, customer_id, order_id, order_item_id, rating, body, created_at, updated_at, deleted_at.
   *
   * Handle not found cases with 404 error.
   *
   * No request body is needed.
   *
   * Response body uses IShoppingMallReview type to represent the review entity with complete details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reviewId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReview> {
    try {
      return await getShoppingMallCustomerReviewsReviewId({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing customer product review by reviewId.
   *
   * This operation allows an authenticated customer to modify their previously submitted review for a product. The review must have been posted after delivery, and changes include updating the star rating (1-5) and optional textual feedback.
   *
   * Each edit creates an immutable snapshot of the prior review for audit and historical tracking.
   *
   * Only the owner customer of the review is authorized to perform this update.
   *
   * The reviewId path parameter uniquely identifies the review record in the database.
   *
   * Request fields validate rating bounds and text length.
   *
   * Successful updates return the full updated review object reflecting all stored fields.
   *
   * Related operations include POST /customers/reviews for creating new reviews and DELETE /customers/reviews/{reviewId} for deleting reviews.
   *
   * Error handling covers authorization failures, validation errors on input, and non-existent reviewId lookup.
   *
   * This operation corresponds to the shopping_mall_reviews table and leverages snapshot tables internally during audit recording.
   *
   * @param connection
   * @param reviewId Unique identifier of the review to update
   * @param body Review update details
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement update using PUT /reviews/{reviewId}.
   *
   * Validate reviewId as UUID path parameter.
   *
   * Check that the authenticated customer owns the review.
   *
   * Validate request body rating (1-5) and optional text field constraints.
   *
   * Perform update on shopping_mall_reviews table for the reviewId.
   *
   * Create new snapshot record in shopping_mall_review_snapshots after update.
   *
   * Return updated review record with all fields.
   *
   * Handle errors for unauthorized access, not found reviewId, and validation failures.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":reviewId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReview.IUpdate,
  ): Promise<IShoppingMallReview> {
    try {
      return await putShoppingMallCustomerReviewsReviewId({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently deletes a product review identified by the path parameter reviewId.
   *
   * This operation is intended for authenticated customers to remove their own reviews post-delivery. Deleting a review will permanently remove it from the shopping_mall_reviews table, including all associated data.
   *
   * Authorization: Only customers who authored the review can perform this action.
   *
   * The shopping_mall_reviews table contains fields for id, customer_id, order_id, order_item_id, rating, body, created_at, updated_at, and deleted_at (soft delete timestamp). This operation performs a hard delete ignoring soft delete timestamps.
   *
   * No request body required.
   *
   * Related operations:
   * - POST /customers/reviews to create reviews
   * - PUT /customers/reviews/{reviewId} to edit reviews
   *
   * Error Handling:
   * - Returns 404 if the reviewId does not exist.
   * - Returns 403 if the user is not authorized to delete the review.
   *
   * Success Response:
   * - HTTP 204 No Content with empty body indicating successful permanent deletion.
   *
   * @param connection
   * @param reviewId Unique identifier of the review to delete (UUID).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Execute a hard delete SQL command to remove the shopping_mall_reviews record by id equal to reviewId.
   * Validate caller authorization to confirm the customer is the review owner.
   * On success, return HTTP 204 No Content.
   * On failure, return appropriate HTTP error codes.
   * No request body is involved.
   * Use UUID type validation for reviewId parameter.
   * Ensure audit logging if required by system policies.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reviewId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerReviewsReviewId({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
