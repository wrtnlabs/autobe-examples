import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerShoppingMallProductReviews } from "../../../../providers/postShoppingMallCustomerShoppingMallProductReviews";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerShoppingMallProductReviewsShoppingMallProductReviewId } from "../../../../providers/putShoppingMallCustomerShoppingMallProductReviewsShoppingMallProductReviewId";

import { IShoppingMallProductReview } from "../../../../api/structures/IShoppingMallProductReview";

@Controller("/shoppingMall/customer/shoppingMallProductReviews")
export class ShoppingmallCustomerShoppingmallproductreviewsController {
  /**
   * Creates a new product review submitted by an authenticated customer in the
   * shopping mall platform.
   *
   * The operation requires all review details such as the star rating, title
   * headline, detailed textual feedback, and moderation status. It also
   * requires references to the reviewed product, the customer authoring the
   * review, and the customer's active session at the time of submission to
   * ensure authenticity and traceability.
   *
   * This operation automatically records creation and update timestamps for the
   * review entry. The moderation status field is set by the client to indicate
   * whether the review is pending, approved, or rejected.
   *
   * Only authenticated customers with valid sessions can create product
   * reviews.
   *
   * Related operations include updating a review (PUT
   * /shoppingMallProductReviews/{shoppingMallProductReviewId}).
   *
   * @param connection
   * @param body New product review creation payload
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallProductReview.ICreate,
  ): Promise<IShoppingMallProductReview> {
    try {
      return await postShoppingMallCustomerShoppingMallProductReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates a product review entry based on the unique review identifier
   * provided in the path.
   *
   * The client can modify review details including star rating, summary title,
   * detailed text, and moderation status. The review remains linked to the
   * original product, customer, and customer session for auditability.
   *
   * This operation automatically updates the modification timestamp upon
   * success.
   *
   * Permission checks ensure that only authorized users, usually the original
   * author or administrators, can perform updates.
   *
   * Related operations include creation (POST /shoppingMallProductReviews) and
   * retrieval (GET /shoppingMallProductReviews/{shoppingMallProductReviewId}).
   *
   * @param connection
   * @param shoppingMallProductReviewId Unique identifier of the target product
   *   review
   * @param body Updated product review data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shoppingMallProductReviewId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shoppingMallProductReviewId")
    shoppingMallProductReviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductReview.IUpdate,
  ): Promise<IShoppingMallProductReview> {
    try {
      return await putShoppingMallCustomerShoppingMallProductReviewsShoppingMallProductReviewId(
        {
          customer,
          shoppingMallProductReviewId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
