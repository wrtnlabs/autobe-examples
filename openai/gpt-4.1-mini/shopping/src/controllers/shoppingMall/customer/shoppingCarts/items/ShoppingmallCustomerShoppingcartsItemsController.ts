import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerShoppingCartsCartIdItems } from "../../../../../providers/postShoppingMallCustomerShoppingCartsCartIdItems";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerShoppingCartsCartIdItems } from "../../../../../providers/patchShoppingMallCustomerShoppingCartsCartIdItems";
import { getShoppingMallCustomerShoppingCartsCartIdItemsItemId } from "../../../../../providers/getShoppingMallCustomerShoppingCartsCartIdItemsItemId";
import { putShoppingMallCustomerShoppingCartsCartIdItemsItemId } from "../../../../../providers/putShoppingMallCustomerShoppingCartsCartIdItemsItemId";
import { deleteShoppingMallCustomerShoppingCartsCartIdItemsItemId } from "../../../../../providers/deleteShoppingMallCustomerShoppingCartsCartIdItemsItemId";

import { IShoppingMallCartItem } from "../../../../../api/structures/IShoppingMallCartItem";
import { IPageIShoppingMallCartItem } from "../../../../../api/structures/IPageIShoppingMallCartItem";
import { IShoppingMallShoppingCartItem } from "../../../../../api/structures/IShoppingMallShoppingCartItem";

@Controller("/shoppingMall/customer/shoppingCarts/:cartId/items")
export class ShoppingmallCustomerShoppingcartsItemsController {
  /**
   * Add a new item to a shopping cart.
   *
   * Add a new product SKU item to the customer's shopping cart. The client
   * provides the shopping cart identifier and a request body specifying the SKU
   * and quantity to add.
   *
   * This operation requires authentication and ensures the SKU is valid and can
   * be added to the cart. Quantity validation should prevent adding more items
   * than are available in inventory.
   *
   * Successful addition results in the cart item being included in the cart,
   * retrievable by the GET item operation.
   *
   * This endpoint facilitates seamless shopping cart management for
   * authenticated users.
   *
   * @param connection
   * @param cartId Unique identifier of the shopping cart
   * @param body Details of the product SKU and quantity to add to the cart
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCartItem.ICreate,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await postShoppingMallCustomerShoppingCartsCartIdItems({
        customer,
        cartId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Modify shopping cart items by patching items associated with a shopping
   * cart identified by UUID cartId.
   *
   * Allows the authenticated customer to modify the items in their shopping
   * cart identified by cartId.
   *
   * This includes adding new items, updating quantities of existing items, or
   * removing items.
   *
   * The shopping cart items are stored in shopping_mall_cart_items and linked
   * to the specific cart.
   *
   * The system validates that SKUs exist, inventory supports requested
   * quantities, and the user owns the cart.
   *
   * The operation supports partial updates via PATCH method.
   *
   * The response returns a paginated summary list of updated cart items
   * reflecting current cart state.
   *
   * Related operations: retrieving cart contents, deleting cart.
   *
   * Error handling includes SKU availability checking, quantity validation,
   * ownership verification.
   *
   * @param connection
   * @param cartId Unique UUID identifier of the shopping cart.
   * @param body Patch data for modifying shopping cart items.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShoppingCartItem.IRequest,
  ): Promise<IPageIShoppingMallCartItem.ISummary> {
    try {
      return await patchShoppingMallCustomerShoppingCartsCartIdItems({
        customer,
        cartId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific cart item by cartId and itemId.
   *
   * Retrieve detailed information about a specific item inside a customer's
   * shopping cart. This operation verifies the existence of the cart item by
   * its unique ID as well as the cart it belongs to, ensuring proper
   * client-side data display and interaction.
   *
   * The endpoint requires the client to provide the shopping cart identifier
   * and the specific cart item identifier as path parameters. These parameters
   * correspond directly to the shopping_mall_shopping_carts and
   * shopping_mall_cart_items tables respectively.
   *
   * Security considerations include ensuring the user is authenticated and
   * authorized to access the specified cart and its items. Proper authorization
   * checks should be implemented in the service layer.
   *
   * This operation fetches the cart item record including quantity and linked
   * product SKU information, allowing UI clients to render cart contents and
   * enable subsequent update or removal actions.
   *
   * @param connection
   * @param cartId Unique identifier of the shopping cart
   * @param itemId Unique identifier of the cart item within the cart
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await getShoppingMallCustomerShoppingCartsCartIdItemsItemId({
        customer,
        cartId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update quantity of a cart item in a shopping cart.
   *
   * Update an existing item in the shopping cart identified by the unique item
   * ID and associated cart ID. The operation changes the quantity of the SKU
   * and may update other mutable fields if present.
   *
   * This endpoint is secured and can only be accessed by authenticated
   * customers. It validates that the item belongs to the specified cart and the
   * user has permission to modify it.
   *
   * The system checks that the quantity value is positive and reflects the
   * change in inventory reservation and cart total calculations.
   *
   * This operation is critical for user-driven cart management during shopping
   * sessions.
   *
   * @param connection
   * @param cartId Unique identifier of the target shopping cart
   * @param itemId Unique identifier of the cart item to update
   * @param body Object containing updated quantity information for the cart
   *   item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":itemId")
  public async updateCartItem(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCartItem.IUpdate,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await putShoppingMallCustomerShoppingCartsCartIdItemsItemId({
        customer,
        cartId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove an item from a shopping cart.
   *
   * Delete a shopping cart item identified by itemId from the specified cart
   * identified by cartId. This operation requires customer authentication to
   * prevent unauthorized deletions.
   *
   * The system updates the cart state immediately, confirming the item removal.
   * No request or response body is required.
   *
   * This complements cart item addition and update endpoints, providing
   * complete item lifecycle management within the shopping cart context.
   *
   * @param connection
   * @param cartId Unique identifier of the target shopping cart
   * @param itemId Unique identifier of the cart item to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":itemId")
  public async eraseCartItem(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerShoppingCartsCartIdItemsItemId({
        customer,
        cartId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
