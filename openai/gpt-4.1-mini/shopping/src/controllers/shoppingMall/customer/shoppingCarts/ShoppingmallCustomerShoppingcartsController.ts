import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerShoppingCarts } from "../../../../providers/postShoppingMallCustomerShoppingCarts";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerShoppingCarts } from "../../../../providers/patchShoppingMallCustomerShoppingCarts";
import { getShoppingMallCustomerShoppingCartsId } from "../../../../providers/getShoppingMallCustomerShoppingCartsId";
import { putShoppingMallCustomerShoppingCartsId } from "../../../../providers/putShoppingMallCustomerShoppingCartsId";
import { deleteShoppingMallCustomerShoppingCartsId } from "../../../../providers/deleteShoppingMallCustomerShoppingCartsId";

import { IShoppingMallShoppingCart } from "../../../../api/structures/IShoppingMallShoppingCart";
import { IPageIShoppingMallShoppingCart } from "../../../../api/structures/IPageIShoppingMallShoppingCart";

@Controller("/shoppingMall/customer/shoppingCarts")
export class ShoppingmallCustomerShoppingcartsController {
  /**
   * Create a new shopping cart for a customer session.
   *
   * This API endpoint allows authenticated customers to create a new shopping
   * cart tied to their user account and current session. The shopping cart
   * stores the current selection of product SKUs and quantities, providing
   * persistence across devices and sessions.
   *
   * The cart belongs to exactly one customer and one session. If a cart already
   * exists for the customer-session pair, creation should fail or replace the
   * existing cart depending on business rules. The system supports soft
   * deletion of carts via nullable deleted_at timestamps.
   *
   * Security considerations require the requesting customer to be authenticated
   * with proper session information. The cart data is isolated per customer and
   * session to ensure user privacy and data integrity.
   *
   * Business logic validation includes verifying the existence of the customer
   * and session IDs provided before allowing cart creation. The API caller must
   * ensure that product SKUs exist before adding to the cart items.
   *
   * Related operations include updating the cart, deleting items, and querying
   * the cart contents.
   *
   * On successful creation, the new cart entity is returned with all details
   * including IDs and timestamps.
   *
   * @param connection
   * @param body Shopping cart creation data with customer and session
   *   identifiers
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallShoppingCart.ICreate,
  ): Promise<IShoppingMallShoppingCart> {
    try {
      return await postShoppingMallCustomerShoppingCarts({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of shopping carts.
   *
   * Retrieve a filtered and paginated list of shopping carts associated with
   * customers and their sessions. This operation supports rich filtering
   * options such as filtering by customer ID, customer session ID, and date
   * filters for creation and last update. The result is a paginated summary of
   * shopping carts optimized for display in lists.
   *
   * Authorization is required, typically restricted to authenticated customers
   * or admins. Users can only access carts they own unless authorized as
   * admin.
   *
   * This operation operates on the shopping_mall_shopping_carts table, ensuring
   * strict conformance to its schema including soft deletion logic where
   * applicable.
   *
   * Clients need to provide search criteria encapsulated in the request body of
   * type IShoppingMallShoppingCart.IRequest with pagination parameters. The
   * response returns a paginated summary of shopping carts.
   *
   * This API is designed as a PATCH method applying complex queries for list
   * retrieval.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   shopping carts
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallShoppingCart.IRequest,
  ): Promise<IPageIShoppingMallShoppingCart.ISummary> {
    try {
      return await patchShoppingMallCustomerShoppingCarts({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific shopping cart by ID.
   *
   * Retrieve detailed shopping cart information including all cart items and
   * the linked customer session by cart UUID.
   *
   * Access is limited to the owning customer or authorized administrators.
   *
   * This operation maps directly to the shopping_mall_shopping_carts table and
   * related tables such as cart items.
   *
   * Proper validation of path parameters ensures security and data integrity.
   *
   * @param connection
   * @param id Unique identifier of the shopping cart (UUID)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShoppingCart> {
    try {
      return await getShoppingMallCustomerShoppingCartsId({
        customer,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shopping cart by its unique ID.
   *
   * This API operation enables authenticated customers to update their existing
   * shopping cart specified by its unique ID. It can update properties such as
   * linked customer ID, session ID, or other attributes defined by the cart
   * creation model.
   *
   * Only authorized customers or system roles can perform this update. The
   * operation preserves data integrity by validating the existence of
   * referenced customer and session IDs and ensuring no duplication of carts
   * per customer-session pair occurs.
   *
   * The soft deleted carts cannot be updated unless restored. Validation
   * failures, such as invalid IDs or unauthorized access, result in clear error
   * responses.
   *
   * On success, the updated cart entity is returned with current data including
   * timestamps.
   *
   * This operation complements the cart creation endpoint and is part of the
   * shopping cart management suite.
   *
   * @param connection
   * @param id Unique identifier of the target shopping cart
   * @param body Updated shopping cart data for modification
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShoppingCart.IUpdate,
  ): Promise<IShoppingMallShoppingCart> {
    try {
      return await putShoppingMallCustomerShoppingCartsId({
        customer,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a shopping cart by its unique UUID identifier from the
   * shopping_mall_shopping_carts table.
   *
   * This endpoint allows the authenticated customer to delete a specific
   * shopping cart by providing its UUID identifier.
   *
   * The shopping cart holds items selected for purchase. Deleting the cart
   * permanently removes it from the database.
   *
   * Security considerations require the request to be authenticated as the
   * owning customer to prevent unauthorized removals.
   *
   * This performs a hard delete operation, as the underlying Prisma schema
   * indicates a nullable "deleted_at" field, but no soft delete mechanism is
   * handled automatically.
   *
   * The operation does not require a request body and does not return a
   * response body upon successful deletion.
   *
   * Related operations: retreiving cart details, managing cart items.
   *
   * Error handling includes validation of cart ID and ownership verification
   * before deletion.
   *
   * @param connection
   * @param id Unique UUID identifier of the target shopping cart to delete.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerShoppingCartsId({
        customer,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
