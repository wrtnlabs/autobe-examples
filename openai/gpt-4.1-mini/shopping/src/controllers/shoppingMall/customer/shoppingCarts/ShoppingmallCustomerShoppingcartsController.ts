import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallCustomerShoppingCartsShoppingCartId } from "../../../../providers/getShoppingMallCustomerShoppingCartsShoppingCartId";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerShoppingCartsShoppingCartId } from "../../../../providers/putShoppingMallCustomerShoppingCartsShoppingCartId";
import { deleteShoppingMallCustomerShoppingCartsShoppingCartId } from "../../../../providers/deleteShoppingMallCustomerShoppingCartsShoppingCartId";
import { postShoppingMallCustomerShoppingCarts } from "../../../../providers/postShoppingMallCustomerShoppingCarts";

import { IShoppingMallShoppingCart } from "../../../../api/structures/IShoppingMallShoppingCart";

@Controller("/shoppingMall/customer/shoppingCarts")
export class ShoppingmallCustomerShoppingcartsController {
  /**
   * Retrieve a specific shopping cart by ID.
   *
   * Retrieve the full details of a specific shopping cart by its unique
   * identifier.
   *
   * This operation allows any authenticated customer to access their own
   * shopping cart details. The shopping cart is identified by a unique UUID
   * exposed as the shoppingCartId in the URL path parameter.
   *
   * Security considerations include verifying that the requester owns the
   * shopping cart or has sufficient permissions to view it. The shopping cart
   * includes references to customer information and the collection of items
   * currently in the cart.
   *
   * This operation integrates with the shopping_mall_shopping_carts table from
   * the Prisma schema, ensuring all returned fields reflect current database
   * state. Validation ensures the shoppingCartId conforms to UUID format to
   * prevent injection attacks.
   *
   * Related operations: create a new shopping cart (POST /shoppingCarts).
   *
   * @param connection
   * @param shoppingCartId Unique identifier of the target shopping cart (UUID)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shoppingCartId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shoppingCartId")
    shoppingCartId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShoppingCart> {
    try {
      return await getShoppingMallCustomerShoppingCartsShoppingCartId({
        customer,
        shoppingCartId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a shopping cart by ID.
   *
   * Update a shopping cart by its unique identifier, shoppingCartId. The
   * shopping cart is associated with a specific customer and optionally linked
   * to a customer's active session.
   *
   * This operation allows authenticated customers to update their shopping cart
   * details, such as active session information and timestamps.
   *
   * Security measures ensure only customers can update their own carts. The
   * operation validates that the referenced shopping cart exists and the
   * customer is authorized.
   *
   * Related operations include retrieving, deleting shopping carts, and
   * managing items within carts.
   *
   * This corresponds directly to the shopping_mall_shopping_carts table in the
   * Prisma schema.
   *
   * @param connection
   * @param shoppingCartId Unique identifier (UUID) of the target shopping cart
   * @param body Request payload to update shopping cart fields excluding the
   *   cart identifier
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shoppingCartId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shoppingCartId")
    shoppingCartId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShoppingCart.IUpdate,
  ): Promise<IShoppingMallShoppingCart> {
    try {
      return await putShoppingMallCustomerShoppingCartsShoppingCartId({
        customer,
        shoppingCartId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a shopping cart by ID.
   *
   * Delete a shopping cart permanently by its unique identifier shoppingCartId.
   * Only authorized customers can perform this operation.
   *
   * This operation validates the existence of the cart and customer's
   * authorization before deletion.
   *
   * Related operations include retrieving and updating shopping carts, as well
   * as managing cart items.
   *
   * This operation directly manipulates the shopping_mall_shopping_carts Prisma
   * table.
   *
   * @param connection
   * @param shoppingCartId Unique identifier (UUID) of the target shopping cart
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":shoppingCartId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shoppingCartId")
    shoppingCartId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerShoppingCartsShoppingCartId({
        customer,
        shoppingCartId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new shopping cart associated with the authenticated customer.
   *
   * This operation allows any authenticated customer to create a new shopping
   * cart, which can then be populated with item selections and proceed through
   * checkout.
   *
   * Validation rules enforce that the cart creation data matches the expected
   * schema and that the cart is linked to the correct customer.
   *
   * Security includes verifying the authenticated customer and preventing
   * unauthorized cart creation.
   *
   * The created shopping cart is returned, including its identifier and initial
   * state.
   *
   * Related operations: fetch existing cart (GET
   * /shoppingCarts/{shoppingCartId}).
   *
   * @param connection
   * @param body Shopping cart creation payload
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallShoppingCart.ICreate,
  ): Promise<IShoppingMallShoppingCart> {
    try {
      return await postShoppingMallCustomerShoppingCarts({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
