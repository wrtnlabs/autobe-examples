import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallCustomerSkuInventoriesId } from "../../../../providers/getShoppingMallCustomerSkuInventoriesId";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";

import { IShoppingMallSkuInventory } from "../../../../api/structures/IShoppingMallSkuInventory";

@Controller("/shoppingMall/customer/skuInventories/:id")
export class ShoppingmallCustomerSkuinventoriesController {
  /**
   * Get detailed SKU inventory data by unique inventory ID.
   *
   * Retrieve the inventory record for a specified product SKU by its unique
   * inventory ID. This operation enables viewing detailed SKU inventory
   * information, including quantity available and current stock status such as
   * 'in stock' or 'out of stock'. It supports operational workflows such as
   * inventory audits, frontend availability checks, and administrative stock
   * monitoring.
   *
   * Security considerations include restricting this operation to authenticated
   * users such as customers, sellers, and admins who need inventory visibility.
   * Unauthorized users or guests do not have access to sensitive inventory
   * data.
   *
   * The underlying database table is shopping_mall_sku_inventories, which
   * tracks inventory quantities and stock status per SKU. The primary key is
   * the UUID id provided as a path parameter.
   *
   * This operation does not allow modification and is read-only. It returns the
   * full inventory record with timestamps and status flags.
   *
   * If the specified inventory ID does not exist, the system shall return a 404
   * Not Found error.
   *
   * Expected behavior includes proper authentication, data retrieval, and
   * compliance with data privacy policies.
   *
   * @param connection
   * @param id Unique identifier of the SKU inventory record to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSkuInventory> {
    try {
      return await getShoppingMallCustomerSkuInventoriesId({
        customer,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
