import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getShoppingMallCustomerShipmentTrackingsId } from "../../../../providers/getShoppingMallCustomerShipmentTrackingsId";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";

import { IShoppingMallShipmentTracking } from "../../../../api/structures/IShoppingMallShipmentTracking";

@Controller("/shoppingMall/customer/shipmentTrackings/:id")
export class ShoppingmallCustomerShipmenttrackingsController {
  /**
   * Retrieve shipment tracking information by ID from
   * shopping_mall_shipment_trackings.
   *
   * Retrieve detailed shipment tracking information for a specific shipment
   * identified by its unique ID. This endpoint accesses the
   * shopping_mall_shipment_trackings table which captures carrier-provided
   * tracking numbers, shipping carrier names, current shipment status, shipment
   * and delivery timestamps, and metadata.
   *
   * Security considerations require that only authorized actors such as
   * customers associated with the order, sellers managing the shipment, or
   * admin users can access this sensitive shipment tracking data.
   *
   * The response includes all relevant tracking fields reflecting the current
   * shipping lifecycle stage, allowing user interfaces to provide accurate and
   * timely shipment status updates.
   *
   * This operation is a read-only GET and requires the shipmentTracking ID as
   * the path parameter. Validation ensures the shipment ID exists, and proper
   * authorization is enforced.
   *
   * @param connection
   * @param id Unique identifier of the shipment tracking record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string,
  ): Promise<IShoppingMallShipmentTracking> {
    try {
      return await getShoppingMallCustomerShipmentTrackingsId({
        customer,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
