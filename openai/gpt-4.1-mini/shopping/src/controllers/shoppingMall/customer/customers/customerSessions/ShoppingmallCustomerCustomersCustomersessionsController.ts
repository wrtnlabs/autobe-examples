import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallCustomerCustomersCustomerIdCustomerSessionsCustomerSessionId } from "../../../../../providers/getShoppingMallCustomerCustomersCustomerIdCustomerSessionsCustomerSessionId";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { postShoppingMallCustomerCustomersCustomerIdCustomerSessions } from "../../../../../providers/postShoppingMallCustomerCustomersCustomerIdCustomerSessions";

import { IShoppingMallCustomerSession } from "../../../../../api/structures/IShoppingMallCustomerSession";

@Controller("/shoppingMall/customer/customers/:customerId/customerSessions")
export class ShoppingmallCustomerCustomersCustomersessionsController {
  /**
   * Retrieve authenticated customer session by session ID for a given customer.
   *
   * Retrieve a detailed authenticated customer session record associated with
   * the specified registered customer.
   *
   * This operation obtains session metadata including IP address, connection
   * URL, referrer URL, and timestamps indicating session creation and expiry.
   *
   * Access control: This endpoint requires authentication and is restricted to
   * authorized user actors managing the specified customer's sessions.
   *
   * This operation is implemented on the shopping_mall_customer_sessions table
   * as per the Prisma schema, with the session linked to the customer by the
   * shopping_mall_customer_id foreign key.
   *
   * See also the session creation API: POST
   * /customers/{customerId}/customerSessions/{customerSessionId}.
   *
   * @param connection
   * @param customerId UUID of the registered customer user
   * @param customerSessionId UUID of the customer session record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerSessionId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("customerSessionId")
    customerSessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerSession> {
    try {
      return await getShoppingMallCustomerCustomersCustomerIdCustomerSessionsCustomerSessionId(
        {
          customer,
          customerId,
          customerSessionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create new authenticated customer session for a registered customer.
   *
   * Create a new authenticated customer session record associated with the
   * given registered customer.
   *
   * The client must supply connection details including IP address, referrer
   * URL, and connection URL as part of the request body.
   *
   * Security considerations: Only authorized customer users may create session
   * records under their own account.
   *
   * This operation interfaces with the shopping_mall_customer_sessions table as
   * defined in the Prisma schema.
   *
   * See also the session retrieval API: GET
   * /customers/{customerId}/customerSessions/{customerSessionId}.
   *
   * @param connection
   * @param customerId UUID of the registered customer user
   * @param body Required information to create a new customer session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCustomerSession.ICreate,
  ): Promise<IShoppingMallCustomerSession> {
    try {
      return await postShoppingMallCustomerCustomersCustomerIdCustomerSessions({
        customer,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
