import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putShoppingMallCustomerCustomersId } from "../../../../providers/putShoppingMallCustomerCustomersId";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";

@Controller("/shoppingMall/customer/customers/:id")
export class ShoppingmallCustomerCustomersController {
  /**
   * Update a shopping mall customer by ID.
   *
   * Update the information of a specific shopping mall customer by their unique
   * UUID. The fields updated include email, password_hash, nickname,
   * created_at, updated_at, and deleted_at timestamps.
   *
   * Security ensures that only authenticated customers or authorized admins can
   * perform this action.
   *
   * The operation requires a valid customer id parameter to identify the target
   * and a request body containing the fields to update.
   *
   * Responses provide the updated customer entity confirmation.
   *
   * Incorrect id or unauthorized access will result in relevant errors.
   *
   * @param connection
   * @param id Unique identifier of the target customer
   * @param body Payload containing fields to update for the customer entity
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async updateCustomer(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCustomer.IUpdate,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await putShoppingMallCustomerCustomersId({
        customer,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
