import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postShoppingMallCustomerShoppingMallCategories } from "../../../../providers/postShoppingMallCustomerShoppingMallCategories";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";

import { IShoppingMallShoppingMallCategory } from "../../../../api/structures/IShoppingMallShoppingMallCategory";

@Controller("/shoppingMall/customer/shoppingMallCategories")
export class ShoppingmallCustomerShoppingmallcategoriesController {
  /**
   * Create a new product category in the shopping mall.
   *
   * This operation allows authenticated users to add new categories to organize
   * products within the mall catalog.
   *
   * Validation rules ensure uniqueness of the category code and appropriate
   * category naming conventions as defined in the Prisma schema.
   *
   * Security applies authentication and authorization checks to allow only
   * permitted users to create categories.
   *
   * The created category becomes available immediately for product assignment
   * and browsing.
   *
   * Related operations include retrieving category details (GET
   * /shoppingMallCategories/{categoryName}) and listing all categories (if
   * available).
   *
   * @param connection
   * @param body Payload to create a new shopping mall product category
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallShoppingMallCategory.ICreate,
  ): Promise<IShoppingMallShoppingMallCategory> {
    try {
      return await postShoppingMallCustomerShoppingMallCategories({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
