import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerWishlistsWishlistIdItems } from "../../../../../providers/postShoppingMallCustomerWishlistsWishlistIdItems";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerWishlistsWishlistIdItems } from "../../../../../providers/patchShoppingMallCustomerWishlistsWishlistIdItems";
import { getShoppingMallCustomerWishlistsWishlistIdItemsItemId } from "../../../../../providers/getShoppingMallCustomerWishlistsWishlistIdItemsItemId";
import { putShoppingMallCustomerWishlistsWishlistIdItemsItemId } from "../../../../../providers/putShoppingMallCustomerWishlistsWishlistIdItemsItemId";
import { deleteShoppingMallCustomerWishlistsWishlistIdItemsItemId } from "../../../../../providers/deleteShoppingMallCustomerWishlistsWishlistIdItemsItemId";

import { IShoppingMallWishlistItem } from "../../../../../api/structures/IShoppingMallWishlistItem";
import { IPageIShoppingMallWishlistItem } from "../../../../../api/structures/IPageIShoppingMallWishlistItem";

@Controller("/shoppingMall/customer/wishlists/:wishlistId/items")
export class ShoppingmallCustomerWishlistsItemsController {
  /**
   * Add a new item to the wishlist.
   *
   * Add a new product SKU item to a customer's wishlist by specifying the SKU
   * and desired quantity. This operation validates the input request body
   * against the IShoppingMallWishlistItem.ICreate interface, ensuring that SKU
   * codes and quantities meet business rules.
   *
   * Only authenticated customers are authorized to perform this operation. The
   * operation associates the new wishlist item with the given wishlist
   * identified by the wishlistId path parameter.
   *
   * After successful creation, the operation returns the detailed wishlist item
   * data including identifiers, SKU reference, quantity, and audit timestamps.
   *
   * This API operation supports personalizing customer shopping experience by
   * enabling users to compile desired items for future purchases.
   *
   * @param connection
   * @param wishlistId Unique identifier of the target wishlist
   * @param body New wishlist item creation data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string,
    @TypedBody()
    body: IShoppingMallWishlistItem.ICreate,
  ): Promise<IShoppingMallWishlistItem> {
    try {
      return await postShoppingMallCustomerWishlistsWishlistIdItems({
        customer,
        wishlistId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Modify and query wishlist items within a specific customer's wishlist.
   *
   * This PATCH endpoint enables authenticated customers to modify and retrieve
   * wishlist items within their wishlist. Operations allowed include adding
   * items by SKU, updating quantities, and removing items. The request body
   * adheres to the IShoppingMallWishlistItem.IRequest DTO schema specifying
   * item changes and query filters.
   *
   * The response is a paginated summary list of wishlist items filtered by the
   * request parameters.
   *
   * Only the owning customer may perform these operations, which require
   * authorization. The wishlist is identified by an UUID path parameter.
   *
   * @param connection
   * @param wishlistId Unique UUID identifier of the target wishlist
   * @param body Criteria and data for modifying wishlist items
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallWishlistItem.IRequest,
  ): Promise<IPageIShoppingMallWishlistItem.ISummary> {
    try {
      return await patchShoppingMallCustomerWishlistsWishlistIdItems({
        customer,
        wishlistId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific wishlist item.
   *
   * Retrieve detailed information about a specific item in a customer's
   * wishlist. This operation fetches data from the shopping_mall_wishlist_items
   * table, which keeps track of SKUs added by customers to their personal
   * wishlists. The details include the quantity of the SKU wished for and
   * timestamps reflecting creation and last update.
   *
   * Users must provide both the unique wishlist identifier and the unique item
   * identifier to obtain the wishlist item information. Security restrictions
   * require the user to be authenticated as a customer owner of the wishlist.
   *
   * The response returns all relevant details for the wishlist item, mapped
   * according to the IShoppingMallWishlistItem interface. No modifications or
   * deletions are performed by this operation; it is a read-only retrieval.
   *
   * Usage of this API helps in personalizing user experiences by showing saved
   * favorite items or planned future purchases.
   *
   * @param connection
   * @param wishlistId Unique identifier of the target wishlist
   * @param itemId Unique identifier of the target wishlist item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string,
    @TypedParam("itemId")
    itemId: string,
  ): Promise<IShoppingMallWishlistItem> {
    try {
      return await getShoppingMallCustomerWishlistsWishlistIdItemsItemId({
        customer,
        wishlistId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a customer's wishlist item by wishlistId and itemId.
   *
   * Update a specific item in a customer's wishlist identified by wishlistId
   * and itemId. This operation allows modification of the quantity or other
   * allowed properties of the wishlist item as recorded in the
   * shopping_mall_wishlist_items table. It requires ownership validation to
   * ensure only the owning customer can update their wishlist items.
   *
   * Security considerations include verifying the authenticated user matches
   * the wishlist owner and validating the item exists and belongs to the
   * correct wishlist.
   *
   * The underlying database entity is the shopping_mall_wishlist_items table
   * which stores the wishlist item details such as the customer linked
   * wishlist, product SKU, and quantity.
   *
   * Validation rules ensure the quantity is positive and the SKU exists.
   *
   * This operation typically complements creation and deletion of wishlist
   * items, supporting full wishlist management by the customer.
   *
   * Error handling includes 404 responses for missing wishlist or item entities
   * and 403 for unauthorized access.
   *
   * @param connection
   * @param wishlistId Unique identifier of the target wishlist
   * @param itemId Unique identifier of the wishlist item to update
   * @param body Request payload containing updated wishlist item data such as
   *   quantity
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":itemId")
  public async updateWishlistItem(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string,
    @TypedParam("itemId")
    itemId: string,
    @TypedBody()
    body: IShoppingMallWishlistItem.IUpdate,
  ): Promise<IShoppingMallWishlistItem> {
    try {
      return await putShoppingMallCustomerWishlistsWishlistIdItemsItemId({
        customer,
        wishlistId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a wishlist item by wishlistId and itemId.
   *
   * Deletes a specific wishlist item from a customer wishlist by wishlistId and
   * itemId identifiers. This operation physically removes the wishlist item
   * record from the shopping_mall_wishlist_items database table.
   *
   * Security considerations dictate that only authenticated users owning the
   * wishlist and item may perform this delete operation.
   *
   * If the wishlist or item does not exist, a 404 error response is expected.
   *
   * This operation complements wishlist item creation and update endpoints,
   * facilitating full lifecycle management of wishlist contents.
   *
   * After deletion, associated data such as the wishlist summary remain
   * unaffected.
   *
   * @param connection
   * @param wishlistId Unique identifier of the target wishlist
   * @param itemId Unique identifier of the wishlist item to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":itemId")
  public async eraseWishlistItem(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string,
    @TypedParam("itemId")
    itemId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerWishlistsWishlistIdItemsItemId({
        customer,
        wishlistId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
