import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerWishlists } from "../../../../providers/postShoppingMallCustomerWishlists";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerWishlists } from "../../../../providers/patchShoppingMallCustomerWishlists";
import { getShoppingMallCustomerWishlistsId } from "../../../../providers/getShoppingMallCustomerWishlistsId";
import { putShoppingMallCustomerWishlistsId } from "../../../../providers/putShoppingMallCustomerWishlistsId";
import { deleteShoppingMallCustomerWishlistsId } from "../../../../providers/deleteShoppingMallCustomerWishlistsId";

import { IShoppingMallWishlist } from "../../../../api/structures/IShoppingMallWishlist";
import { IPageIShoppingMallWishlist } from "../../../../api/structures/IPageIShoppingMallWishlist";

@Controller("/shoppingMall/customer/wishlists")
export class ShoppingmallCustomerWishlistsController {
  /**
   * Create a new wishlist for an authenticated customer.
   *
   * This operation allows an authenticated customer to create a new wishlist in
   * the shopping mall system. The wishlist is tied to the customer's unique ID
   * and their current session, enabling persistent tracking of desired products
   * independently of the shopping cart. The action is restricted to authorized
   * customers to ensure personal data security and prevent unauthorized
   * wishlist creation.
   *
   * Upon receiving the creation request, the system validates the provided data
   * to ensure it references valid customer and session IDs from the
   * shopping_mall_customers and shopping_mall_customer_sessions tables
   * respectively. The system then stores a new wishlist record with timestamps
   * for creation and last update.
   *
   * Because wishlists are associated with user sessions, this operation ensures
   * that separate wishlists can be managed accurately and persistently as
   * customers log in from different devices or sessions. The security context
   * enforced by authentication prevents unauthorized access.
   *
   * The response returns the created wishlist entity confirming successful
   * creation with all relevant persisted information.
   *
   * No request body is included as creation details are captured implicitly by
   * authenticated user context and session.
   *
   * This operation does not allow public or unauthenticated access and requires
   * the 'customer' role.
   *
   * Failed validations or unauthorized access attempts result in appropriate
   * HTTP 4xx errors.
   *
   * Expected usage patterns include wishlist creation during session
   * initialization or user-initiated wishlist management workflows.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IShoppingMallWishlist> {
    try {
      return await postShoppingMallCustomerWishlists({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve filtered paginated list of wishlists.
   *
   * Retrieve a filtered, paginated list of shopping mall wishlists. This
   * operation allows clients to perform search and filtering on wishlists
   * belonging to customers, supporting pagination with configurable page size
   * and sorting options.
   *
   * Security considerations include restricting access to authenticated
   * customers for their own wishlists. It integrates with the
   * shopping_mall_wishlists table, reflecting fields such as customer id,
   * session id, timestamps, and soft deletion status.
   *
   * The response returns a paged collection of wishlist summary information
   * optimized for list rendering. Related detailed item information is
   * accessible through other endpoints. Proper authorization and ownership
   * verification are required to prevent unauthorized access.
   *
   * @param connection
   * @param body Request body containing filtering criteria, search parameters,
   *   pagination, and sorting options for wishlists
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallWishlist.IRequest,
  ): Promise<IPageIShoppingMallWishlist.ISummary> {
    try {
      return await patchShoppingMallCustomerWishlists({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed wishlist information by UUID.
   *
   * Retrieve detailed information of a specific wishlist identified by its
   * unique UUID. This operation allows authenticated customers to fetch their
   * wishlist data for viewing or further updating via separate operations.
   *
   * The endpoint uses a path parameter 'id', which is the UUID of the wishlist.
   * It returns the full entity with all details including associations to
   * customer, session, and timestamps.
   *
   * This operation is secured for access only by the owning customer to protect
   * privacy.
   *
   * @param connection
   * @param id Unique identifier of the target wishlist (UUID)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallWishlist> {
    try {
      return await getShoppingMallCustomerWishlistsId({
        customer,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing wishlist identified by ID.
   *
   * Allows an authenticated customer to update an existing wishlist by
   * specifying the wishlist ID path parameter. The update payload follows the
   * IShoppingMallWishlist.IUpdate DTO structure detailing allowed modifiable
   * fields. The operation enforces ownership and authentication via 'customer'
   * authorization actor ensuring secure and appropriate data modifications.
   *
   * If the provided wishlist ID does not exist or is not owned by the
   * authenticated customer, the system will reject the update with 404 or 403
   * errors accordingly.
   *
   * Request validation ensures compliance with DTO schema and business rules.
   *
   * No deletion or soft delete is performed here; the update modifies existing
   * wishlist records.
   *
   * Success returns the updated wishlist entity reflecting all applied changes.
   *
   * @param connection
   * @param id Unique identifier of the wishlist to update (UUID)
   * @param body The wishlist update payload
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallWishlist.IUpdate,
  ): Promise<IShoppingMallWishlist> {
    try {
      return await putShoppingMallCustomerWishlistsId({
        customer,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a customer's wishlist by unique UUID identifier.
   *
   * This DELETE endpoint allows an authenticated customer to permanently delete
   * their wishlist by specifying the wishlist's UUID. The wishlist represents a
   * collection of product SKUs saved by the customer across sessions and
   * devices. Only the owning customer can perform this operation.
   *
   * This operation corresponds to the shopping_mall_wishlists table. It does
   * not accept a request body and does not return any response body.
   *
   * @param connection
   * @param id Unique UUID identifier of the target wishlist
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerWishlistsId({
        customer,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
