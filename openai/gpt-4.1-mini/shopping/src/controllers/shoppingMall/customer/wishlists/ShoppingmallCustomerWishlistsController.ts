import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerWishlists } from "../../../../providers/postShoppingMallCustomerWishlists";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerWishlists } from "../../../../providers/patchShoppingMallCustomerWishlists";
import { getShoppingMallCustomerWishlistsWishlistId } from "../../../../providers/getShoppingMallCustomerWishlistsWishlistId";
import { putShoppingMallCustomerWishlistsWishlistId } from "../../../../providers/putShoppingMallCustomerWishlistsWishlistId";
import { deleteShoppingMallCustomerWishlistsWishlistId } from "../../../../providers/deleteShoppingMallCustomerWishlistsWishlistId";

import { IShoppingMallWishlist } from "../../../../api/structures/IShoppingMallWishlist";
import { IPageIShoppingMallWishlist } from "../../../../api/structures/IPageIShoppingMallWishlist";

@Controller("/shoppingMall/customer/wishlists")
export class ShoppingmallCustomerWishlistsController {
  /**
   * Create a new customer wishlist.
   *
   * Create a new wishlist for a customer in the system.
   *
   * This operation allows authenticated customers to create wishlists
   * containing their desired products for future purchases.
   *
   * The client must provide all necessary wishlist data conforming to the
   * IShoppingMallWishlist.ICreate type, excluding server-generated fields.
   *
   * Security constraints ensure wishlist ownership and validity.
   *
   * This operation corresponds to creation in the shopping_mall_wishlists
   * Prisma table.
   *
   * @param connection
   * @param body Data required to create a new wishlist
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallWishlist.ICreate,
  ): Promise<IShoppingMallWishlist> {
    try {
      return await postShoppingMallCustomerWishlists({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve customer wishlists.
   *
   * Retrieves a list of wishlists filtered by criteria supplied in the request
   * body. The operation supports pagination, sorting, and filtering to
   * efficiently handle large datasets.
   *
   * Authenticated customers can view and search their own wishlists.
   * Administrators may have access to broader wishlist data based on
   * authorization.
   *
   * This PATCH operation is associated with the shopping_mall_wishlists Prisma
   * table, using corresponding search request and summary response DTO types.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for wishlist
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallWishlist.IRequest,
  ): Promise<IPageIShoppingMallWishlist.ISummary> {
    try {
      return await patchShoppingMallCustomerWishlists({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get detailed information of a specific customer wishlist.
   *
   * Retrieve the detailed information of a customer wishlist by its unique
   * identifier.
   *
   * This operation allows authenticated customers to fetch a specific
   * wishlist's details including its items, creation date, and related customer
   * information.
   *
   * Security considerations ensure that only the owner of the wishlist or
   * authorized roles can access the data.
   *
   * This operation corresponds to the shopping_mall_wishlists table in the
   * Prisma schema, returning all wishlist fields.
   *
   * @param connection
   * @param wishlistId Unique identifier of the target wishlist
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":wishlistId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallWishlist> {
    try {
      return await getShoppingMallCustomerWishlistsWishlistId({
        customer,
        wishlistId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update customer wishlist details by wishlist ID.
   *
   * Update an existing customer wishlist by its unique ID.
   *
   * This operation allows authenticated customers to modify the details of
   * their wishlists, including renaming and changing attributes. It validates
   * ownership to ensure only the owning customer can update their wishlist.
   *
   * The request must specify the unique wishlist identifier in the path, using
   * the UUID format. The request body contains the fields to update. The soft
   * deletion status is respected; updates to soft-deleted wishlists are
   * disallowed.
   *
   * Security: Only authenticated customers can perform this operation, and
   * ownership validation is performed.
   *
   * Related operations include deleting wishlists and retrieving wishlist
   * details.
   *
   * @param connection
   * @param wishlistId Unique identifier of the customer wishlist to update.
   * @param body Wishlist update payload containing modifiable properties.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":wishlistId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallWishlist.IUpdate,
  ): Promise<IShoppingMallWishlist> {
    try {
      return await putShoppingMallCustomerWishlistsWishlistId({
        customer,
        wishlistId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a customer wishlist by wishlist ID.
   *
   * Delete a wishlist permanently by its unique ID.
   *
   * This operation enables authenticated customers to remove their wishlists
   * completely from the system. This deletion is permanent and cannot be
   * undone.
   *
   * The wishlist is identified via a UUID path parameter. Authorization checks
   * ensure only the owner can delete their wishlist.
   *
   * Related operations include updating wishlists and retrieving wishlist
   * details.
   *
   * All associated wishlist items will also be removed to maintain data
   * integrity.
   *
   * No soft delete is applied; this is a hard delete operation.
   *
   * @param connection
   * @param wishlistId Unique identifier of the customer wishlist to delete.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":wishlistId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerWishlistsWishlistId({
        customer,
        wishlistId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
