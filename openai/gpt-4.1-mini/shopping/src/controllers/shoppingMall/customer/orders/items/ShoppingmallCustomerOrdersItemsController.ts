import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerOrdersOrderCodeItems } from "../../../../../providers/postShoppingMallCustomerOrdersOrderCodeItems";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerOrdersOrderCodeItems } from "../../../../../providers/patchShoppingMallCustomerOrdersOrderCodeItems";
import { getShoppingMallCustomerOrdersOrderCodeItemsItemId } from "../../../../../providers/getShoppingMallCustomerOrdersOrderCodeItemsItemId";
import { putShoppingMallCustomerOrdersOrderCodeItemsItemId } from "../../../../../providers/putShoppingMallCustomerOrdersOrderCodeItemsItemId";
import { deleteShoppingMallCustomerOrdersOrderCodeItemsItemId } from "../../../../../providers/deleteShoppingMallCustomerOrdersOrderCodeItemsItemId";

import { IShoppingMallOrderItem } from "../../../../../api/structures/IShoppingMallOrderItem";
import { IPageIShoppingMallOrderItem } from "../../../../../api/structures/IPageIShoppingMallOrderItem";

@Controller("/shoppingMall/customer/orders/:orderCode/items")
export class ShoppingmallCustomerOrdersItemsController {
  /**
   * Add a new item to a specific order by order code.
   *
   * This POST operation adds a new item to an existing order specified by the
   * order code.
   *
   * Path parameter orderCode uniquely identifies the order in which the item
   * will be added.
   *
   * The request body must include the SKU ID, quantity, unit price, and total
   * price for the new item.
   *
   * Authorization is limited to customers who own the order, sellers managing
   * order contents, and admins.
   *
   * The response returns the created order item entity with all details.
   *
   * Error handling includes validation of SKU existence, order ownership, and
   * quantity constraints.
   *
   * @param connection
   * @param orderCode Unique code identifying the order (global scope).
   * @param body Creation info of the order item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedBody()
    body: IShoppingMallOrderItem.ICreate,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await postShoppingMallCustomerOrdersOrderCodeItems({
        customer,
        orderCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve paginated list of order items by order code with search and
   * filtering.
   *
   * Retrieve a filtered and paginated list of items belonging to a specific
   * shopping mall order given by the unique orderCode. This allows complex
   * queries on the order items, including filtering, sorting, and pagination.
   *
   * The orderCode path parameter uniquely identifies the order to query.
   *
   * Authorization is granted to roles "admin", "customer", and "seller" to
   * allow appropriate access based on user rights.
   *
   * The request body contains search criteria for order items, and the response
   * contains a paginated summary list of matching items.
   *
   * This complements other order management endpoints providing order details,
   * cancellations, and refund processing.
   *
   * @param connection
   * @param orderCode Unique business identifier code of the target order
   * @param body Search criteria and pagination parameters for order item
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedBody()
    body: IShoppingMallOrderItem.IRequest,
  ): Promise<IPageIShoppingMallOrderItem.ISummary> {
    try {
      return await patchShoppingMallCustomerOrdersOrderCodeItems({
        customer,
        orderCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order item within an order
   * by order code and item ID.
   *
   * This GET operation fetches detailed information about a specific order item
   * associated with a given order using the order code and the item ID as path
   * parameters.
   *
   * The orderCode parameter uniquely identifies the customer's order in the
   * shopping_mall_orders table, linking to multiple order items.
   *
   * The itemId parameter identifies the specific line item from the
   * shopping_mall_order_items table that belongs to the order. This allows
   * retrieval of quantity, unit price, SKU information, and other relevant item
   * details.
   *
   * Authorization is typically limited to authenticated customers (the order
   * owner), sellers who sold the product SKU in the order, and administrative
   * users with full access.
   *
   * The operation returns a detailed order item object including quantity and
   * pricing, enabling clients to display order contents accurately.
   *
   * Errors are handled by returning appropriate HTTP status codes if the order
   * or item is not found or if the caller is unauthorized.
   *
   * @param connection
   * @param orderCode Unique code identifying the order (global scope).
   * @param itemId Unique identifier of the order item.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await getShoppingMallCustomerOrdersOrderCodeItemsItemId({
        customer,
        orderCode,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an order item for a specific order (shopping_mall_order_items).
   *
   * Update a specific item within an existing order by modifying its quantity,
   * unit price, or total price. This operation accepts the order code to
   * identify the order and the item ID to specify the line item. It validates
   * the updated values to ensure integrity.
   *
   * Only authorized customers or administrative users can perform this update.
   * Partial or full updates to the order item fields are allowed following
   * validation rules.
   *
   * This operation modifies the shopping_mall_order_items table as defined in
   * the Prisma schema, maintaining consistency and referential integrity with
   * the parent shopping_mall_orders entity.
   *
   * Returns the updated order item details upon successful modification.
   *
   * @param connection
   * @param orderCode Unique order code used for business reference and lookup
   *   (global scope)
   * @param itemId Unique identifier of the target order item
   * @param body Data fields to update for the specified order item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":itemId")
  public async updateItem(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderItem.IUpdate,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await putShoppingMallCustomerOrdersOrderCodeItemsItemId({
        customer,
        orderCode,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an order item from a specific order (shopping_mall_order_items).
   *
   * Delete a specific item from an existing order identified by order code and
   * item ID. This operation permanently removes the order item from the
   * shopping_mall_order_items table.
   *
   * Only authorized customers or admin users can perform this operation.
   * Post-deletion, the system updates the parent order totals and related
   * references.
   *
   * This is a hard delete operation, removing all traces of the order item from
   * the database.
   *
   * @param connection
   * @param orderCode Unique order code used for business reference and lookup
   *   (global scope)
   * @param itemId Unique identifier of the target order item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":itemId")
  public async eraseItem(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerOrdersOrderCodeItemsItemId({
        customer,
        orderCode,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
