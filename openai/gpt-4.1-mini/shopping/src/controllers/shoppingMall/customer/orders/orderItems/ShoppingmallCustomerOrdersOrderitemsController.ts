import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallCustomerOrdersOrderIdOrderItemsOrderItemId } from "../../../../../providers/getShoppingMallCustomerOrdersOrderIdOrderItemsOrderItemId";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerOrdersOrderIdOrderItemsOrderItemId } from "../../../../../providers/putShoppingMallCustomerOrdersOrderIdOrderItemsOrderItemId";
import { deleteShoppingMallCustomerOrdersOrderIdOrderItemsOrderItemId } from "../../../../../providers/deleteShoppingMallCustomerOrdersOrderIdOrderItemsOrderItemId";
import { postShoppingMallCustomerOrdersOrderIdOrderItems } from "../../../../../providers/postShoppingMallCustomerOrdersOrderIdOrderItems";

import { IShoppingMallOrderItem } from "../../../../../api/structures/IShoppingMallOrderItem";

@Controller("/shoppingMall/customer/orders/:orderId/orderItems")
export class ShoppingmallCustomerOrdersOrderitemsController {
  /**
   * Retrieve a specific order item from a customer order.
   *
   * Retrieve detailed information for a specific order item belonging to a
   * given order identified by orderId and orderItemId.
   *
   * This operation supports customer or administration use cases for viewing
   * product variant purchases included in orders.
   *
   * Security: Access should be limited to authorized users, such as the order
   * owner or mall administrators.
   *
   * The shopping_mall_order_items database table includes foreign keys to the
   * parent order and the product variant, and this endpoint reflects these
   * relationships.
   *
   * Validation ensures that the order and order item exist and correspond to
   * each other, preventing invalid data retrievals.
   *
   * Related operations include creating order items under an order and listing
   * all order items for an order.
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @param orderItemId Unique identifier of the target order item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderItemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await getShoppingMallCustomerOrdersOrderIdOrderItemsOrderItemId({
        customer,
        orderId,
        orderItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific order item within an order.
   *
   * Update an existing order item within a customer's order.
   *
   * This operation allows an authenticated customer to modify details of a
   * purchased product variant (order item) within a specific order. It supports
   * updating quantity and pricing information.
   *
   * Security: Only authenticated customers with ownership or appropriate
   * permissions can update order items.
   *
   * The operation maps to the shopping_mall_order_items Prisma table, using
   * orderId and orderItemId as unique identifiers.
   *
   * Successful update returns the modified order item entity.
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @param orderItemId Unique identifier of the target order item
   * @param body Updated details of the order item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":orderItemId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderItem.IUpdate,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await putShoppingMallCustomerOrdersOrderIdOrderItemsOrderItemId({
        customer,
        orderId,
        orderItemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific order item within an order.
   *
   * Permanently delete an order item from a customer's order.
   *
   * This operation permanently removes an order item record, identified by the
   * orderId and orderItemId, from the shopping_mall_order_items Prisma table.
   *
   * Security: Only authenticated customers owning the order or authorized
   * personnel may delete order items.
   *
   * Deletion is hard and irreversible; no soft delete mechanisms are
   * implemented.
   *
   * No content is returned after successful deletion.
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @param orderItemId Unique identifier of the target order item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":orderItemId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerOrdersOrderIdOrderItemsOrderItemId(
        {
          customer,
          orderId,
          orderItemId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new order item within a customer order.
   *
   * Create a new order item within an existing order specified by orderId.
   *
   * The request body must provide details including product variant ID,
   * quantity, unit price, and total price.
   *
   * Security: Only authorized users can add items to their orders.
   *
   * The creation process validates product availability and price accuracy.
   *
   * Upon success, the new order item information is returned.
   *
   * Related operations include updating and deleting order items.
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @param body Creation data for a new shopping mall order item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderItem.ICreate,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await postShoppingMallCustomerOrdersOrderIdOrderItems({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
