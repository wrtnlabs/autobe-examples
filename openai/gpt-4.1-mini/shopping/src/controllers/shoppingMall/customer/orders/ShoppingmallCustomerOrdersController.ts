import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerOrders } from "../../../../providers/postShoppingMallCustomerOrders";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerOrders } from "../../../../providers/patchShoppingMallCustomerOrders";
import { getShoppingMallCustomerOrdersOrderId } from "../../../../providers/getShoppingMallCustomerOrdersOrderId";
import { putShoppingMallCustomerOrdersOrderId } from "../../../../providers/putShoppingMallCustomerOrdersOrderId";

import { IShoppingMallOrder } from "../../../../api/structures/IShoppingMallOrder";
import { IPageIShoppingMallOrder } from "../../../../api/structures/IPageIShoppingMallOrder";

@Controller("/shoppingMall/customer/orders")
export class ShoppingmallCustomerOrdersController {
  /**
   * Create a new order representing a customer purchase in the shopping mall.
   *
   * This operation accepts detailed information about the order, including the
   * customer and seller identifiers, order status, payment status, total order
   * amount, and the shipping address at the time of order placement.
   *
   * Security considerations require that only authenticated users with the
   * proper roles can create an order. The operation validates that the order
   * number is unique and associates the order with existing customer and seller
   * records.
   *
   * The created order will be timestamped and become part of the system's order
   * history. Related operations include updating the order information via PUT
   * /orders/{orderId}.
   *
   * @param connection
   * @param body Order data to create a new shopping mall order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallOrder.ICreate,
  ): Promise<IShoppingMallOrder> {
    try {
      return await postShoppingMallCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of shopping mall orders. This
   * operation allows clients to search orders by order number, status, payment
   * status, customer, seller, or date ranges.
   *
   * The operation supports comprehensive pagination options with sorting
   * capabilities. Sorting can be done by creation date, order number, or total
   * amount.
   *
   * Security considerations include restricting access to authenticated users,
   * and applying user-level filtering based on roles (e.g., customers see own
   * orders, sellers see related orders, admins see all). Pagination limits and
   * search filters prevent overloading the system.
   *
   * This operation corresponds to the shopping_mall_orders table defined in
   * Prisma schema, returning a paged summary of order details optimized for
   * list presentation.
   *
   * @param connection
   * @param body Search criteria and pagination options for order listing
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallOrder.IRequest,
  ): Promise<IPageIShoppingMallOrder.ISummary> {
    try {
      return await patchShoppingMallCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shopping mall order.
   *
   * This operation requires the order's unique identifier (UUID). It returns
   * full details including the customer and seller associations, order number,
   * status information, payment information, total amount, and lifecycle
   * timestamps.
   *
   * Security considerations restrict access to authenticated users who must
   * have rightful ownership or permissions to view the order. Attempts to
   * access unauthorized orders will be denied.
   *
   * This operation directly queries the shopping_mall_orders table as defined
   * in the Prisma schema.
   *
   * Related operations include the list operation (PATCH /orders) for filtered
   * searching, and order creation handled in a different part of the system.
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrder> {
    try {
      return await getShoppingMallCustomerOrdersOrderId({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the details of an existing order in the shopping mall.
   *
   * This operation allows modification of order properties including order
   * status, payment status, total amount, and shipping address.
   *
   * The order is identified by the unique UUID orderId provided in the path
   * parameter.
   *
   * Security requires the user to be authenticated and authorized to modify the
   * order. The operation ensures the provided orderId corresponds to an
   * existing order.
   *
   * Related operations include creating new orders via POST /orders and
   * retrieving orders by ID with GET /orders/{orderId}.
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @param body Updated data for the existing shopping mall order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":orderId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrder.IUpdate,
  ): Promise<IShoppingMallOrder> {
    try {
      return await putShoppingMallCustomerOrdersOrderId({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
