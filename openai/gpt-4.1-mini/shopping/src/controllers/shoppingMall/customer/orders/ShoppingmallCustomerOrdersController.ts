import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallOrder } from "../../../../api/structures/IPageIShoppingMallOrder";
import { IShoppingMallOrder } from "../../../../api/structures/IShoppingMallOrder";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersOrderId } from "../../../../providers/getShoppingMallCustomerOrdersOrderId";
import { patchShoppingMallCustomerOrders } from "../../../../providers/patchShoppingMallCustomerOrders";

@Controller("/shoppingMall/customer/orders")
export class ShoppingmallCustomerOrdersController {
  /**
   * Retrieve filtered and paginated list of customer orders in the shopping mall platform.
   *
   * This operation allows clients to search orders by various criteria including order status (paid, shipped, delivered, cancelled, refunded, partially_completed), order number, customer ID, and creation date ranges.
   *
   * Supports pagination and sorting options to handle large datasets efficiently.
   *
   * Only authorized actors such as administrators (all orders) and customers (their own orders) can access this endpoint.
   *
   * The operation reflects the shopping_mall_orders schema, leveraging its fields such as order_number, total_price, total_quantity, order_status, created_at, and relations to customers and order items.
   *
   * Business logic ensures that customers can only view their own orders, whereas administrators can view all orders.
   *
   * The response returns a paginated list of order summaries including key details to facilitate UI order listing and management.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for order listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement a paging and filtering query on shopping_mall_orders table.
   *
   * Search filters include order_status, order_number (partial match), customer ID, and creation date range.
   *
   * Apply pagination and sorting based on the request body parameters.
   *
   * For customer actors, restrict results to orders where shopping_mall_customer_id matches the authorized customer ID.
   *
   * Join with shopping_mall_customers to include customer display names if needed in summaries.
   *
   * Return paginated results with IPageIShoppingMallOrder.ISummary DTO including order_number, total_price, total_quantity, order_status, and timestamps.
   *
   * Handle authorization and validation in the service layer prior to DB query execution.
   *
   * Edge cases: handle empty or null filters gracefully, return empty results if no matches, handle invalid pagination parameters with validation errors.
   *
   * No request path parameters.
   *
   * Method PATCH with requestBody mandatory and responseBody mandatory.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallOrder.IRequest,
  ): Promise<IPageIShoppingMallOrder.ISummary> {
    try {
      return await patchShoppingMallCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a detailed customer order by its unique ID.
   *
   * This endpoint allows authenticated customers and administrators to access full order information including total price, total quantity, order status, creation, and update timestamps.
   *
   * Security considerations include validating that the requester owns the order or has appropriate admin permissions.
   *
   * The underlying database entity is shopping_mall_orders which stores the order summary and relationships to the customer.
   *
   * The API returns detailed order data consistent with the database schema fields. This endpoint is critical for order history views and order management features.
   *
   * If the specified orderId does not exist, the operation should return a 404 not found response.
   *
   * This operation has no request body as it is a GET method.
   *
   * Related operations include POST /orders to create new orders and PATCH /orders for listing/searching orders.
   *
   * Ensure proper indexing on shopping_mall_customer_id for efficient queries.
   *
   * @param connection
   * @param orderId Unique identifier of the customer order (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_orders table by primary key 'id' matching 'orderId' path parameter.
   * Validate the requestor's authorization to access the order.
   * Return a single order record with all fields including total_price, total_quantity, and order_status.
   * Return 404 error if not found.
   * No request body is required.
   * Set response body schema to IShoppingMallOrder type.
   *
   * Ensure to use parameter 'orderId' as UUID string in the backend service layer.
   *
   * Optimize queries with an index on shopping_mall_customer_id and created_at for customer order retrieval.
   *
   * Log the access for auditing purposes.
   *
   * This operation fits typical GET retrieval conventions for primary key-based resources.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrder> {
    try {
      return await getShoppingMallCustomerOrdersOrderId({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
