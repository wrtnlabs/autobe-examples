import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { getShoppingMallCustomerOrdersOrderCode } from "../../../../providers/getShoppingMallCustomerOrdersOrderCode";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerOrdersOrderCode } from "../../../../providers/putShoppingMallCustomerOrdersOrderCode";
import { deleteShoppingMallCustomerOrdersOrderCode } from "../../../../providers/deleteShoppingMallCustomerOrdersOrderCode";
import { postShoppingMallCustomerOrders } from "../../../../providers/postShoppingMallCustomerOrders";

import { IShoppingMallOrder } from "../../../../api/structures/IShoppingMallOrder";

@Controller("/shoppingMall/customer/orders")
export class ShoppingmallCustomerOrdersController {
  /**
   * Retrieve detailed shopping order information by order code.
   *
   * Retrieve complete detailed information for a specific shopping order by its
   * unique order code. This operation provides all relevant order data
   * including line items, payments, shipment tracking, reviews, audit trails,
   * cancellations, refunds, and return shipments.
   *
   * Access is restricted to authorized users such as administrators and the
   * owning customer. The endpoint respects data privacy and enforces role-based
   * access control.
   *
   * The shopping_mall_orders table defines the main data structure, while
   * related tables enrich the response with comprehensive order context. This
   * operation returns detailed order information essential for UI displays and
   * backend processing.
   *
   * @param connection
   * @param orderCode Unique business identifier code of the target shopping
   *   order (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderCode")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
  ): Promise<IShoppingMallOrder> {
    try {
      return await getShoppingMallCustomerOrdersOrderCode({
        customer,
        orderCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update details of a customer order by orderCode.
   *
   * Update an existing customer order using the unique orderCode. This allows
   * changes to order status, payment status, shipping address, or other
   * permissible fields.
   *
   * Authorization ensures only rightful customers or authorized actors perform
   * updates. Input validation maintains data integrity and consistent order
   * states.
   *
   * This operation supports business-friendly URLs leveraging orderCode as a
   * path parameter, aligning with the schema and operational rules.
   *
   * Errors such as forbidden state transitions or unauthorized access are
   * properly returned.
   *
   * @param connection
   * @param orderCode Unique business identifier code of the target order
   *   (global scope)
   * @param body The update payload for modifying order details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":orderCode")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedBody()
    body: IShoppingMallOrder.IUpdate,
  ): Promise<IShoppingMallOrder> {
    try {
      return await putShoppingMallCustomerOrdersOrderCode({
        customer,
        orderCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Hard delete operation to permanently remove a shopping mall order by its
   * code.
   *
   * This API operation performs a hard delete of an order record from the
   * shopping_mall_orders table based on the unique orderCode. It is intended to
   * be used for customer or administrative order cancellations that permanently
   * remove the order data.
   *
   * Only authorized actors with the role "admin" or "customer" can access this
   * endpoint. It ensures only admins or the order-owning customer can delete
   * the order, providing security and preventing unauthorized deletions.
   *
   * The path parameter orderCode uniquely identifies the order within the
   * system, ensuring unambiguous targeting for deletion. Since
   * shopping_mall_orders include a deleted_at column, soft delete could be
   * used, but this operation intentionally performs permanent deletion as
   * specified.
   *
   * No request body is required and no content is returned in the response,
   * indicating that a successful call results in the removal of the order
   * record. Errors are returned if the orderCode does not exist or if the
   * requester lacks permissions.
   *
   * Related operations include retrieving order details, managing order items,
   * and processing refunds or cancellations with separate endpoints.
   *
   * @param connection
   * @param orderCode Unique business identifier code of the target order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":orderCode")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerOrdersOrderCode({
        customer,
        orderCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new customer order.
   *
   * Create a new order for an authenticated customer in the ShoppingMall
   * system. The API accepts order creation data such as cart items, quantities,
   * shipping address, and payment information. It validates the availability of
   * each product SKU and ensures atomic order creation, including payment
   * processing.
   *
   * Only customers with active sessions may perform this operation. The system
   * manages orders based on the 'shopping_mall_orders' schema, generating
   * unique order codes, statuses, payment statuses, and tracking creation
   * timestamps.
   *
   * In cases of insufficient stock or payment failure, the API returns clear
   * error messages. This operation forms the foundation for the purchase
   * workflow.
   *
   * @param connection
   * @param body Order creation request containing customer, shipping, and item
   *   details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallOrder.ICreate,
  ): Promise<IShoppingMallOrder> {
    try {
      return await postShoppingMallCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
