import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallCustomerReturnShipments } from "../../../../providers/patchShoppingMallCustomerReturnShipments";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerReturnShipmentsId } from "../../../../providers/getShoppingMallCustomerReturnShipmentsId";

import { IPageIShoppingMallReturnShipment } from "../../../../api/structures/IPageIShoppingMallReturnShipment";
import { IShoppingMallReturnShipment } from "../../../../api/structures/IShoppingMallReturnShipment";

@Controller("/shoppingMall/customer/returnShipments")
export class ShoppingmallCustomerReturnshipmentsController {
  /**
   * Retrieve paginated return shipment records with filters and sort options.
   *
   * Retrieve a filtered and paginated list of return shipments recorded in the
   * system. Each return shipment is linked to a refund request and the customer
   * who initiated it. The listing includes detailed information such as the
   * shipping carrier, tracking number, current status of the return shipment,
   * and relevant timestamps.
   *
   * This operation supports advanced filtering options, sorting by alert dates
   * and statuses, and full pagination controls to efficiently handle large
   * datasets.
   *
   * Security considerations include limiting access to authorized users such as
   * customers viewing their own return shipments or administrators with
   * platform-wide oversight. This operation is designed for read-only access to
   * ensure data integrity and is typically used by customer service interfaces
   * or user dashboards.
   *
   * Underlying database table: shopping_mall_return_shipments.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for return shipments.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallReturnShipment.IRequest,
  ): Promise<IPageIShoppingMallReturnShipment.ISummary> {
    try {
      return await patchShoppingMallCustomerReturnShipments({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve return shipment detail by unique identifier.
   *
   * Retrieve detailed information about a specific return shipment by ID. The
   * data includes shipment carrier, tracking number, and current status of the
   * return process. The operation validates the existence of the target return
   * shipment and returns 404 if not found.
   *
   * Appropriate authorization ensures only owners or admins can access this
   * sensitive data. This enables customer support agents and customers to track
   * return processing thoroughly.
   *
   * The response includes links to associated refund requests and customer
   * account information for complete context.
   *
   * @param connection
   * @param id Unique identifier of the target return shipment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReturnShipment> {
    try {
      return await getShoppingMallCustomerReturnShipmentsId({
        customer,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
