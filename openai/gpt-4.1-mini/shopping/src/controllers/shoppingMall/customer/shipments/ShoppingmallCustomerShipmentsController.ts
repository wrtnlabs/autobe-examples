import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerShipments } from "../../../../providers/postShoppingMallCustomerShipments";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerShipments } from "../../../../providers/patchShoppingMallCustomerShipments";
import { getShoppingMallCustomerShipmentsShipmentId } from "../../../../providers/getShoppingMallCustomerShipmentsShipmentId";

import { IShoppingMallShipment } from "../../../../api/structures/IShoppingMallShipment";
import { IPageIShoppingMallShipment } from "../../../../api/structures/IPageIShoppingMallShipment";

@Controller("/shoppingMall/customer/shipments")
export class ShoppingmallCustomerShipmentsController {
  /**
   * Create a new shipment record in shopping_mall_shipments.
   *
   * Create a new shipment record representing the shipping details of an order.
   *
   * Authorized shipment managers or system processes can use this endpoint to
   * record shipment initiation details including the shipping carrier, tracking
   * number, and initial shipment status.
   *
   * Validation ensures that the referenced order exists and is valid for
   * shipping. The shipment status must comply with acceptable status codes
   * managed by the system.
   *
   * The operation supports optional timestamps for when the shipment was
   * dispatched and delivered to allow tracking updates.
   *
   * Security requires authentication of the caller with sufficient permissions.
   *
   * The created shipment is linked to exactly one order as per the
   * shopping_mall_shipments model.
   *
   * Related operations include retrieval of shipment details and order updates
   * reflecting shipment status.
   *
   * @param connection
   * @param body The shipment creation data including carrier, tracking number,
   *   status, and associated order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallShipment.ICreate,
  ): Promise<IShoppingMallShipment> {
    try {
      return await postShoppingMallCustomerShipments({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve shipments with filtering and pagination.
   *
   * Retrieve a list of shipment records with complex filtering and pagination
   * support. This operation enables clients to query shipments by carrier,
   * status, tracking number, and date ranges, facilitating logistics
   * management.
   *
   * Security: Access to shipment data requires authenticated user roles.
   * Permissions are checked to ensure users can only view authorized shipment
   * records.
   *
   * The response includes shipment summary data optimized for list views with
   * key fields like tracking numbers, shipment status, and dates.
   *
   * This operation acts on the shopping_mall_shipments table and integrates
   * with the related shopping_mall_orders through the foreign key
   * shopping_mall_order_id.
   *
   * Related operations: Retrieve single shipment detail (GET
   * /shipments/{shipmentId}), create shipment record (POST /shipments).
   *
   * @param connection
   * @param body Filter and pagination parameters for shipments search
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallShipment.IRequest,
  ): Promise<IPageIShoppingMallShipment.ISummary> {
    try {
      return await patchShoppingMallCustomerShipments({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed shipment information by shipmentId from
   * shopping_mall_shipments.
   *
   * Retrieve a specific shipment record by its unique identifier.
   *
   * This endpoint allows clients to access the full details of a shipment
   * including the carrier handling the delivery, tracking number, current
   * shipment status, timestamps when the shipment was dispatched and delivered,
   * and related order information.
   *
   * Security considerations include ensuring only authorized users with
   * appropriate roles can access shipment details, as shipment information may
   * be sensitive. Authorization is required via authenticated users.
   *
   * This operation corresponds to the shopping_mall_shipments Prisma model,
   * providing a direct mapping to its fields without filters or pagination.
   *
   * No request body is needed as the shipment ID uniquely identifies the
   * resource.
   *
   * Related operations include creating shipments and updating orders as the
   * shipment progresses.
   *
   * @param connection
   * @param shipmentId Unique identifier of the target shipment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment> {
    try {
      return await getShoppingMallCustomerShipmentsShipmentId({
        customer,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
