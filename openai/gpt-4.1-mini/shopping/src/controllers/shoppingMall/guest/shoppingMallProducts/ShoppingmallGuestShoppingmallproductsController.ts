import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallGuestShoppingMallProducts } from "../../../../providers/patchShoppingMallGuestShoppingMallProducts";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { getShoppingMallGuestShoppingMallProductsProductCode } from "../../../../providers/getShoppingMallGuestShoppingMallProductsProductCode";

import { IPageIShoppingMallProduct } from "../../../../api/structures/IPageIShoppingMallProduct";
import { IShoppingMallProduct } from "../../../../api/structures/IShoppingMallProduct";

@Controller("/shoppingMall/guest/shoppingMallProducts")
export class ShoppingmallGuestShoppingmallproductsController {
  /**
   * Search and retrieve a filtered, paginated list of shopping mall products.
   *
   * Retrieve a filtered and paginated list of shopping mall products that are
   * available in the marketplace. This supports searching by product code,
   * name, description, and filtering by active status.
   *
   * Pagination is supported to improve performance and user experience when
   * browsing large product catalogs. Only authenticated customers and guests
   * can access this operation.
   *
   * This operation is associated with the shopping_mall_products table in the
   * Prisma schema, enforcing all related business logic, filtering, and
   * querying semantics.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   shopping mall products
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IShoppingMallProduct.IRequest,
  ): Promise<IPageIShoppingMallProduct.ISummary> {
    try {
      return await patchShoppingMallGuestShoppingMallProducts({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a shopping mall product by productCode.
   *
   * Retrieve detailed information about a shopping mall product identified
   * uniquely by its productCode.
   *
   * This operation provides users with comprehensive product information
   * including name, description, active status, and timestamps related to
   * creation, updates, and soft deletion.
   *
   * Authentication is required, allowing only guest users and registered
   * customers to access product details.
   *
   * The path parameter productCode serves as a unique identifier at the global
   * level.
   *
   * This operation directly interacts with the shopping_mall_products table in
   * the Prisma schema to ensure accurate data retrieval.
   *
   * @param connection
   * @param productCode Unique business code identifying the target shopping
   *   mall product (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productCode")
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("productCode")
    productCode: string,
  ): Promise<IShoppingMallProduct> {
    try {
      return await getShoppingMallGuestShoppingMallProductsProductCode({
        guest,
        productCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
