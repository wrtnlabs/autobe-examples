import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postShoppingMallGuestCustomers } from "../../../../providers/postShoppingMallGuestCustomers";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";

@Controller("/shoppingMall/guest/customers")
export class ShoppingmallGuestCustomersController {
  /**
   * Create a new shopping mall customer account.
   *
   * Create a new customer account in the shopping mall platform.
   *
   * This operation allows prospective customers to register by providing all
   * necessary customer information. The system validates the customer's details
   * against business rules such as unique email address and proper contact
   * information. Upon successful creation, the customer record is stored in the
   * "shopping_mall_customers" database table.
   *
   * Security and authorization considerations require that only unauthenticated
   * users can access this registration endpoint to prevent abuse. Data
   * integrity is maintained by enforcing unique constraints and field
   * validations. The operation integrates with ancillary services such as email
   * confirmation and default profile settings upon customer registration.
   *
   * Related operations include updating customer profiles via PUT
   * /customers/{customerId} and retrieving customer information.
   *
   * @param connection
   * @param body Customer creation payload according to
   *   IShoppingMallCustomer.ICreate schema
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IShoppingMallCustomer.ICreate,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await postShoppingMallGuestCustomers({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
