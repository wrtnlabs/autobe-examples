import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallShoppingMallArticlesShoppingMallArticleId } from "../../../providers/getShoppingMallShoppingMallArticlesShoppingMallArticleId";

import { IShoppingMallArticle } from "../../../api/structures/IShoppingMallArticle";

@Controller("/shoppingMall/shoppingMallArticles/:shoppingMallArticleId")
export class ShoppingmallShoppingmallarticlesController {
  /**
   * Get a shopping mall article by its unique identifier.
   *
   * Retrieve detailed information about a specific shopping mall article.
   *
   * This GET operation fetches the article identified by the
   * shoppingMallArticleId parameter. It returns all relevant fields such as
   * title, content, author information, creation and update timestamps, and any
   * related metadata as defined in the shopping_mall_articles table.
   *
   * The endpoint is publicly accessible and intended for use in article display
   * views or detail pages. It ensures retrieval of consistent article data as
   * stored in the database. Errors will be returned if the ID does not
   * correspond to any existing article.
   *
   * @param connection
   * @param shoppingMallArticleId Unique identifier of the shopping mall article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("shoppingMallArticleId")
    shoppingMallArticleId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallArticle> {
    try {
      return await getShoppingMallShoppingMallArticlesShoppingMallArticleId({
        shoppingMallArticleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
