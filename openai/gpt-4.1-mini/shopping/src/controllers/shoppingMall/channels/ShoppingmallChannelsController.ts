import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallChannels } from "../../../providers/patchShoppingMallChannels";
import { getShoppingMallChannelsChannelCode } from "../../../providers/getShoppingMallChannelsChannelCode";

import { IPageIShoppingMallChannelDefinition } from "../../../api/structures/IPageIShoppingMallChannelDefinition";
import { IShoppingMallChannelDefinition } from "../../../api/structures/IShoppingMallChannelDefinition";

@Controller("/shoppingMall/channels")
export class ShoppingmallChannelsController {
  /**
   * Retrieve paginated list of shopping mall channels with filtering options.
   *
   * Retrieve a filtered, paginated list of shopping mall platform channels from
   * the system. This operation supports advanced search and sorting features to
   * explore channel definitions based on code, name, or description. Channels
   * may have parent-child hierarchical relationships, which are reflected in
   * the data.
   *
   * The operation integrates with the shopping_mall_channel_definitions
   * database table, encompassing all fields such as channel code, name,
   * description, and timestamps. It allows users to efficiently query and
   * navigate the operational or communication channels of the e-commerce
   * platform.
   *
   * Security considerations include rate limiting and access restrictions,
   * ensuring only authorized users or public access according to the business
   * policy.
   *
   * This API does not require path parameters and supports complex filters in
   * the request body for pagination and search queries.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for shopping mall
   *   channels
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallChannelDefinition.IRequest,
  ): Promise<IPageIShoppingMallChannelDefinition.ISummary> {
    try {
      return await patchShoppingMallChannels({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a shopping mall channel by its unique code.
   *
   * Retrieve detailed information about a specific shopping mall platform
   * channel by its unique code. This includes channel identifiers, names,
   * descriptions, and hierarchical parent information if applicable.
   *
   * Security constraints dictate that only authorized users may access channel
   * details accordingly, though in many cases such information may be public.
   *
   * The parameter channelCode refers to the globally unique business identifier
   * of the channel enabling user-friendly URLs and direct resource access.
   *
   * This is a read-only GET operation with no request body and a detailed
   * response body with full channel data.
   *
   * @param connection
   * @param channelCode Unique business identifier code of the target shopping
   *   mall channel (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":channelCode")
  public async at(
    @TypedParam("channelCode")
    channelCode: string,
  ): Promise<IShoppingMallChannelDefinition> {
    try {
      return await getShoppingMallChannelsChannelCode({
        channelCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
