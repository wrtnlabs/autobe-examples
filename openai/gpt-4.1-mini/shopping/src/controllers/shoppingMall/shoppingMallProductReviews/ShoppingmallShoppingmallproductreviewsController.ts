import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallShoppingMallProductReviews } from "../../../providers/patchShoppingMallShoppingMallProductReviews";
import { getShoppingMallShoppingMallProductReviewsShoppingMallProductReviewId } from "../../../providers/getShoppingMallShoppingMallProductReviewsShoppingMallProductReviewId";

import { IPageIShoppingMallProductReview } from "../../../api/structures/IPageIShoppingMallProductReview";
import { IShoppingMallProductReview } from "../../../api/structures/IShoppingMallProductReview";

@Controller("/shoppingMall/shoppingMallProductReviews")
export class ShoppingmallShoppingmallproductreviewsController {
  /**
   * Retrieve a paginated and searchable list of product reviews submitted by
   * customers.
   *
   * This operation allows filtering by review rating, moderation status, and
   * text search on review title and body fields. Pagination options enable
   * clients to specify page size and index.
   *
   * The product reviews are linked to specific products and customers, ensuring
   * authenticity and traceability. Deleted reviews are excluded by default.
   *
   * Security: Public read-only access is permitted as reviews are generally
   * public-facing content. Sensitive details such as author sessions are not
   * exposed through this API.
   *
   * Related operations include single review retrieval (`GET
   * /shoppingMallProductReviews/{shoppingMallProductReviewId}`).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering product
   *   reviews
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallProductReview.IRequest,
  ): Promise<IPageIShoppingMallProductReview.ISummary> {
    try {
      return await patchShoppingMallShoppingMallProductReviews({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific product review by its unique identifier.
   *
   * This operation returns comprehensive review details including the star
   * rating, title, body text, and moderation status. The review is linked to a
   * specific product and customer for authenticity.
   *
   * Security considerations: This endpoint is publicly accessible to allow
   * storefronts and clients to display detailed review information.
   * Modification of reviews is handled through other protected APIs.
   *
   * Path Parameter: `shoppingMallProductReviewId` corresponds to the UUID of
   * the target product review.
   *
   * @param connection
   * @param shoppingMallProductReviewId Unique identifier of the target product
   *   review
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shoppingMallProductReviewId")
  public async at(
    @TypedParam("shoppingMallProductReviewId")
    shoppingMallProductReviewId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductReview> {
    try {
      return await getShoppingMallShoppingMallProductReviewsShoppingMallProductReviewId(
        {
          shoppingMallProductReviewId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
