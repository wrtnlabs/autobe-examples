import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallShoppingMallCategories } from "../../../providers/patchShoppingMallShoppingMallCategories";
import { getShoppingMallShoppingMallCategoriesCategoryName } from "../../../providers/getShoppingMallShoppingMallCategoriesCategoryName";

import { IPageIShoppingMallCategory } from "../../../api/structures/IPageIShoppingMallCategory";
import { IShoppingMallCategory } from "../../../api/structures/IShoppingMallCategory";
import { IShoppingMallShoppingMallCategory } from "../../../api/structures/IShoppingMallShoppingMallCategory";

@Controller("/shoppingMall/shoppingMallCategories")
export class ShoppingmallShoppingmallcategoriesController {
  /**
   * Retrieve a filtered and paginated list of shopping mall product categories.
   *
   * This operation supports advanced search and filtering capabilities
   * including category name, status, and creation date filters. Pagination
   * parameters control page size and offset. Sorting options allow ordering by
   * name or creation date.
   *
   * Security considerations include rate limiting and data visibility
   * restrictions based on user roles. The response includes summary information
   * optimized for category list displays.
   *
   * Related operations: Get category details (GET
   * /shoppingMallCategories/{categoryId}), Create category (POST
   * /shoppingMallCategories).
   *
   * @param connection
   * @param body Search and pagination criteria for shopping mall categories
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallCategory.IRequest,
  ): Promise<IPageIShoppingMallCategory.ISummary> {
    try {
      return await patchShoppingMallShoppingMallCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific product category in the
   * shopping mall by categoryName.
   *
   * This operation allows clients to fetch full category details, including
   * descriptive metadata, hierarchy information, and display settings as
   * defined in the shopping_mall_categories Prisma model.
   *
   * Security considerations include verifying that the category exists and is
   * accessible. This endpoint is publicly accessible as categories are
   * typically public data supporting browsing features.
   *
   * Related operations include category creation (POST /shoppingMallCategories)
   * for adding new categories and category list retrieval (if available).
   *
   * Errors returned when the specified categoryName does not exist or is
   * malformed.
   *
   * @param connection
   * @param categoryName Unique business identifier code of the category (global
   *   scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryName")
  public async at(
    @TypedParam("categoryName")
    categoryName: string,
  ): Promise<IShoppingMallShoppingMallCategory> {
    try {
      return await getShoppingMallShoppingMallCategoriesCategoryName({
        categoryName,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
