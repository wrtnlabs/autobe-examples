import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallShoppingMallChannels } from "../../../providers/patchShoppingMallShoppingMallChannels";
import { getShoppingMallShoppingMallChannelsChannelCode } from "../../../providers/getShoppingMallShoppingMallChannelsChannelCode";

import { IPageIShoppingMallChannel } from "../../../api/structures/IPageIShoppingMallChannel";
import { IShoppingMallChannel } from "../../../api/structures/IShoppingMallChannel";

@Controller("/shoppingMall/shoppingMallChannels")
export class ShoppingmallShoppingmallchannelsController {
  /**
   * Search and retrieve a list of shopping mall channels.
   *
   * Retrieve a filtered and paginated list of shopping mall channels within the
   * e-commerce platform.
   *
   * This operation supports advanced search parameters such as channel names,
   * codes, statuses, and other relevant filters. Pagination and sorting by
   * different fields are also supported to facilitate efficient browsing.
   *
   * Security considerations include ensuring only authorized users can access
   * detailed channel information, while general listings are publicly
   * accessible.
   *
   * The operation integrates with the shopping_mall_channels database table,
   * reflecting all fields and relationships defined therein. It is designed for
   * use by clients needing to display or manage channel listings.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for shopping mall
   *   channels
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallChannel.IRequest,
  ): Promise<IPageIShoppingMallChannel.ISummary> {
    try {
      return await patchShoppingMallShoppingMallChannels({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a shopping mall channel by channelCode.
   *
   * Retrieve detailed information about a specific shopping mall channel by its
   * unique channelCode.
   *
   * This operation is commonly used to show channel details or to manage
   * channel configurations. It validates the existence of the channel and
   * returns all its associated data fields.
   *
   * Security and authorization ensure that only authorized users can access
   * sensitive channel details while general information remains accessible as
   * configured.
   *
   * The parameter channelCode corresponds to the unique code field in the
   * shopping_mall_channels table and serves as the primary key to look up the
   * channel.
   *
   * @param connection
   * @param channelCode Unique business identifier code of the target shopping
   *   mall channel (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":channelCode")
  public async at(
    @TypedParam("channelCode")
    channelCode: string,
  ): Promise<IShoppingMallChannel> {
    try {
      return await getShoppingMallShoppingMallChannelsChannelCode({
        channelCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
