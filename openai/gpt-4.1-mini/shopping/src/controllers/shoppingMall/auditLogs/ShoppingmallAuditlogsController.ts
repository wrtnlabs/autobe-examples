import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallAdministratorAuditLog } from "../../../api/structures/IPageIShoppingMallAdministratorAuditLog";
import { IShoppingMallAdministratorAuditLog } from "../../../api/structures/IShoppingMallAdministratorAuditLog";
import { getShoppingMallAuditLogsId } from "../../../providers/getShoppingMallAuditLogsId";
import { patchShoppingMallAuditLogs } from "../../../providers/patchShoppingMallAuditLogs";

@Controller("/shoppingMall/auditLogs")
export class ShoppingmallAuditlogsController {
  /**
   * Retrieve filtered and paginated audit log records from the shopping mall platform.
   *
   * This operation allows authorized users, typically administrators, to search audit logs by event type, actor type, actor ID, IP address, date ranges, and supports pagination for efficient data retrieval.
   *
   * Audit logs capture critical system events such as login attempts, order creations, product updates, and administrative actions.
   *
   * Security considerations require that only authorized roles have access to this sensitive audit information.
   *
   * Filtering parameters enable fine-grained search across large volumes of logs, supporting compliance audits and forensic investigations.
   *
   * The response includes audit log summaries with key fields excluding potentially sensitive metadata.
   *
   * Related operations include detailed GET access to individual audit log entries and write operations are not supported to preserve audit integrity.
   *
   * The 'shopping_mall_audit_logs' table schema guides the request filtering fields and response structure.
   *
   * @param connection
   * @param body Filter criteria and pagination options for audit log search
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the 'shopping_mall_audit_logs' table with filters on eventType, actorType, actorId, IP, and createdAt date range.
   * Support pagination with limit and offset parameters.
   * Ensure query is optimized with indexes on created_at and actor_id.
   * Only authorized administrator actors can access this endpoint.
   * Return paginated list of audit log summaries excluding metadata field.
   * Handle edge cases such as no matching records gracefully.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallAdministratorAuditLog.IRequest,
  ): Promise<IPageIShoppingMallAdministratorAuditLog.ISummary> {
    try {
      return await patchShoppingMallAuditLogs({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific audit log entry by its unique ID.
   *
   * This operation allows authorized administrative users to access comprehensive audit details including event type, description, actor details (type and ID), IP address, user agent, and JSON-formatted metadata. It supports security, compliance investigations, and system auditing.
   *
   * The audit logs table stores immutable records of system and user activities with timestamped creation and updates. The deletion timestamp field is present for record keeping but this API returns all records without filtering on deletion status.
   *
   * The primary key 'id' must be specified as a UUID to uniquely identify the log entry.
   *
   * This endpoint is intended for use by system administrators and auditors with necessary permissions.
   *
   * Note: This read-only API operation does not alter any data.
   *
   * @param connection
   * @param id Unique identifier (UUID) of the audit log entry to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Implement GET /auditLogs/{id} to query shopping_mall_audit_logs table by primary key 'id'.
   * Fetch all fields including event_type, description, actor_type, actor_id, ip, user_agent, metadata, created_at, updated_at, and deleted_at.
   * Return 404 if the log entry does not exist.
   * Ensure access control to restrict use to administrators and authorized auditors only.
   * No request body needed as the key uniquely identifies the resource.
   * Response uses IShoppingMallAuditLog with full audit log details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdministratorAuditLog> {
    try {
      return await getShoppingMallAuditLogsId({
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
