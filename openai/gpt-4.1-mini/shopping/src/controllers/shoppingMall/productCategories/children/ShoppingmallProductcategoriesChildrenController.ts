import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallProductCategoriesParentIdChildren } from "../../../../providers/patchShoppingMallProductCategoriesParentIdChildren";
import { getShoppingMallProductCategoriesParentIdChildrenChildId } from "../../../../providers/getShoppingMallProductCategoriesParentIdChildrenChildId";

import { IPageIShoppingMallProductCategory } from "../../../../api/structures/IPageIShoppingMallProductCategory";
import { IShoppingMallProductCategory } from "../../../../api/structures/IShoppingMallProductCategory";

@Controller("/shoppingMall/productCategories/:parentId/children")
export class ShoppingmallProductcategoriesChildrenController {
  /**
   * List child product categories under a parent category.
   *
   * Retrieve a list of the immediate child categories under the specified
   * parent category in the product category hierarchy. This allows users and
   * administrators to browse category subtrees dynamically, supporting infinite
   * category nesting levels.
   *
   * The operation requires the UUID of the parent category and will return all
   * child categories immediately nested under it. Filtering and pagination
   * parameters can be specified in the request body to control the result set
   * size and ordering.
   *
   * This operation exposes the shopping_mall_product_categories table from the
   * Prisma schema, including relevant fields like id, parent_id, name, and
   * description. It is essential for constructing dynamic product category
   * trees for various frontend navigation and search filters.
   *
   * Authorization is public, accessible without authentication as category
   * browsing is a fundamental capability. This operation does not modify any
   * data and provides read-only access.
   *
   * Client applications can use this to load categories hierarchically,
   * rendering category menus or filter lists by traversing parent and child
   * relationships.
   *
   * Errors are returned for invalid parentId format or if the parent category
   * does not exist.
   *
   * @param connection
   * @param parentId Unique identifier of the parent product category
   * @param body Search and pagination parameters for child category listing
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("parentId")
    parentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductCategory.IRequest,
  ): Promise<IPageIShoppingMallProductCategory.ISummary> {
    try {
      return await patchShoppingMallProductCategoriesParentIdChildren({
        parentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get details of a specific child product category.
   *
   * Retrieve detailed information about a specific child product category
   * identified by childId under the specified parent category parentId.
   *
   * The response includes category name, description, timestamps, and
   * hierarchical relational data. This supports frontend and backend functions
   * related to category browsing, management, and validation.
   *
   * This operation accesses the shopping_mall_product_categories table
   * described in the Prisma schema and respects hierarchical parent-child
   * constraints in the database.
   *
   * No authentication is required as it provides publicly accessible category
   * information.
   *
   * Errors are returned for invalid or non-existent category ids.
   *
   * @param connection
   * @param parentId Unique identifier of the parent product category
   * @param childId Unique identifier of the child product category
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":childId")
  public async at(
    @TypedParam("parentId")
    parentId: string & tags.Format<"uuid">,
    @TypedParam("childId")
    childId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductCategory> {
    try {
      return await getShoppingMallProductCategoriesParentIdChildrenChildId({
        parentId,
        childId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
