import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallProductCategories } from "../../../providers/patchShoppingMallProductCategories";

import { IPageIShoppingMallProductCategory } from "../../../api/structures/IPageIShoppingMallProductCategory";
import { IShoppingMallProductCategory } from "../../../api/structures/IShoppingMallProductCategory";

@Controller("/shoppingMall/productCategories")
export class ShoppingmallProductcategoriesController {
  /**
   * Search and retrieve filtered paginated list of product categories.
   *
   * Retrieve a filtered and paginated list of shopping mall product categories.
   * Supports complex search capabilities including partial name matching,
   * description filtering, and hierarchical parent category filtering.
   *
   * This operation returns a paginated list suitable for browsing and
   * navigation in product management interfaces. It integrates directly with
   * the shopping_mall_product_categories table, reflecting all current
   * categories including creation and update timestamps.
   *
   * Security is not required for read-only access to categories.
   *
   * Parameters include no path parameters.
   *
   * The request body accepts filter criteria, pagination, and sorting options
   * encapsulated in IShoppingMallProductCategory.IRequest.
   *
   * The response body contains paginated summaries of product categories,
   * IPageIShoppingMallProductCategory.ISummary, optimized for list rendering.
   *
   * This operation aligns with product management and catalog browsing
   * workflows.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for product
   *   categories
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallProductCategory.IRequest,
  ): Promise<IPageIShoppingMallProductCategory.ISummary> {
    try {
      return await patchShoppingMallProductCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
