import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallAdministratorRequest } from "../../../../../api/structures/IShoppingMallAdministratorRequest";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { postShoppingMallAdministratorRequestsRequestIdApprove } from "../../../../../providers/postShoppingMallAdministratorRequestsRequestIdApprove";

@Controller("/shoppingMall/administrator/requests/:requestId/approve")
export class ShoppingmallAdministratorRequestsApproveController {
  /**
   * Approve a pending administrator request identified by the unique requestId.
   *
   * This operation allows authorized administrators to approve requests from customers or sellers who want to become administrators. The approval updates the request's status field to 'approved'.
   *
   * Security ensures only administrators can perform this action.
   *
   * The operation affects the shopping_mall_administrator_requests table, which stores polymorphic actor requests with reason and current status tracking. Soft delete is supported and respected.
   *
   * Note that this is a state-change operation, so it uses POST method with no request body.
   *
   * Clients must provide the UUID of the administrator request to approve in the path parameter.
   *
   * The response returns the updated administrator request entity including all metadata fields.
   *
   * @param connection
   * @param requestId UUID of the administrator request to be approved.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Upon receiving the requestId in the path, validate that the request exists and is in 'pending' status. Check that the caller is authorized as an administrator.
   *
   * Update the status field to 'approved' and set updated_at to current timestamp.
   *
   * Return the full updated record of shopping_mall_administrator_requests identified by requestId.
   *
   * Handle error responses if requestId does not exist, is already approved/rejected, or caller lacks permissions.
   *
   * No request body is required.
   *
   * This operation is transactional and idempotent regarding repeated calls on the same requestId.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async approveAdministratorRequest(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdministratorRequest> {
    try {
      return await postShoppingMallAdministratorRequestsRequestIdApprove({
        administrator,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
