import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallSeller } from "../../../../api/structures/IPageIShoppingMallSeller";
import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getShoppingMallAdministratorSellersSellerId } from "../../../../providers/getShoppingMallAdministratorSellersSellerId";
import { patchShoppingMallAdministratorSellers } from "../../../../providers/patchShoppingMallAdministratorSellers";

@Controller("/shoppingMall/administrator/sellers")
export class ShoppingmallAdministratorSellersController {
  /**
   * Retrieve a filtered and paginated list of sellers registered on the shopping mall platform.
   *
   * This operation supports advanced search features including filtering by approval status, suspension status, registration date ranges, and keyword search on seller profiles.
   *
   * Only authorized administrators can perform this operation.
   *
   * The shopping_mall_sellers table stores all registered sellers with details such as approval status and profile data.
   *
   * This endpoint allows efficient management and oversight of seller accounts through pagination and filtering.
   *
   * Clients can refine queries to locate sellers by specific criteria and receive summarized information for display in administrative interfaces.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for sellers
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the shopping_mall_sellers table with supplied filters from IShoppingMallSeller.IRequest including approval status, suspension status, and keywords.
   * Support pagination parameters for page size and cursor.
   * Return results as IPageIShoppingMallSeller.ISummary containing seller summaries.
   * Validate that requesters have administrator privileges before execution.
   * Handle edge cases such as no matching sellers by returning empty page data.
   * Ensure compliance with security and data access policies for sensitive information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IShoppingMallSeller.IRequest,
  ): Promise<IPageIShoppingMallSeller.ISummary> {
    try {
      return await patchShoppingMallAdministratorSellers({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed profile information for a specific seller by their unique identifier (UUID).
   *
   * This endpoint allows authenticated customers, the seller themselves, and administrators to view the seller's profile information including shop name, description, logo URI, approval status, and rejection reason if applicable.
   *
   * The underlying data is based on the `shopping_mall_sellers` table which stores seller authentication credentials and profile data. This read-only operation does not alter any data.
   *
   * Authorization rules ensure that access is restricted to authenticated customers, the seller themselves, and administrators.
   *
   * No request body is needed since this is a GET operation.
   *
   * Related operations include:
   * - PUT /sellers/{sellerId} for updating seller profile information
   * - GET /admins/sellers for listing all sellers
   * - POST /sellers/signup for creating new seller accounts
   *
   * Error handling includes returning 404 if the sellerId is not found.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Implement GET /sellers/{sellerId} to query the shopping_mall_sellers table for the record with matching id = sellerId.
   * Validate sellerId format as UUID.
   * Return all relevant fields: email, shop_name, shop_description, logo_uri, approval_status, rejection_reason, created_at, updated_at.
   * No request body is processed.
   * Apply authorization to allow access only to authenticated customers, the seller themselves, and administrators.
   * Handle not found error with HTTP 404 response.
   * Use standard JSON serialization for response using IShoppingMallSeller schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSeller> {
    try {
      return await getShoppingMallAdministratorSellersSellerId({
        administrator,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
