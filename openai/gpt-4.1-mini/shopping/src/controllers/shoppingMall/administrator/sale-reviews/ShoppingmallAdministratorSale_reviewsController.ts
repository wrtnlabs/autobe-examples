import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallSaleReview } from "../../../../api/structures/IPageIShoppingMallSaleReview";
import { IShoppingMallSaleReview } from "../../../../api/structures/IShoppingMallSaleReview";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getShoppingMallAdministratorSaleReviewsReviewId } from "../../../../providers/getShoppingMallAdministratorSaleReviewsReviewId";
import { patchShoppingMallAdministratorSaleReviews } from "../../../../providers/patchShoppingMallAdministratorSaleReviews";

@Controller("/shoppingMall/administrator/sale-reviews")
export class ShoppingmallAdministratorSale_reviewsController {
  /**
   * Retrieve a filtered, paginated list of sale reviews submitted by customers for products.
   *
   * This operation enables searching by sale ID, customer ID, star rating, and full-text search in review bodies. Pagination supports page size and cursor.
   *
   * Only customers who are members and administrators are authorized to access this endpoint to browse and manage reviews.
   *
   * The reviews are sourced from the shopping_mall_sale_reviews table which stores star ratings and optional textual feedback linked to sales and customers.
   *
   * This endpoint supports efficient and flexible review browsing for product evaluation and customer experience insights.
   *
   * No write operations are exposed; review creation, editing, and deletion follow separate APIs tied to order completion and customer actions.
   *
   * See also GET /sale-reviews/{reviewId} for single review retrieval.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for sale reviews
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Implement search and listing logic on the shopping_mall_sale_reviews table. Support filters for sale ID, customer ID, rating, and text search on review body. Provide cursor-based pagination.
   *
   * Return paginated list of sale review summaries optimized for list rendering.
   *
   * Pagination parameters include page size and cursor. Validate inputs and authorize actors as members or admins.
   *
   * No mutation operations are performed by this endpoint.
   *
   * Log access events for audit and monitoring.
   *
   * Handle errors gracefully and return structured error responses.
   *
   * Ensure security by enforcing authorization checks.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IShoppingMallSaleReview.IRequest,
  ): Promise<IPageIShoppingMallSaleReview.ISummary> {
    try {
      return await patchShoppingMallAdministratorSaleReviews({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific sale review identified by its unique review ID.
   *
   * This operation allows authorized customers and administrators to access the star rating, optional textual feedback, creation/update timestamps, and other details of the review.
   *
   * The sale review is linked to a distinct sale and customer, ensuring traceability and ownership.
   *
   * This operation requires the review ID as a UUID path parameter.
   *
   * Security and authorization must ensure only the review authoring customer or administrators can access this review.
   *
   * Related operations include listing reviews for a sale and creating or editing reviews by customers.
   *
   * @param connection
   * @param reviewId Unique identifier (UUID) of the sale review to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Implement a service layer method to query the shopping_mall_sale_reviews table by primary key `id` equal to the `reviewId` path parameter.
   *
   * Ensure query filters out records where `deleted_at` IS NOT NULL to avoid returning soft deleted reviews.
   *
   * The query should eagerly join the related sale and customer entities only if necessary for authorization checks.
   *
   * Return the full review record mapped to the IShoppingMallSaleReview type.
   *
   * Handle 404 Not Found if no such review exists or it is soft deleted.
   *
   * This operation requires access control ensuring only the owning customer or an administrator may access.
   *
   * Return a 200 response with the review data when found, or 404 if not found or soft deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reviewId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSaleReview.IAt> {
    try {
      return await getShoppingMallAdministratorSaleReviewsReviewId({
        administrator,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
