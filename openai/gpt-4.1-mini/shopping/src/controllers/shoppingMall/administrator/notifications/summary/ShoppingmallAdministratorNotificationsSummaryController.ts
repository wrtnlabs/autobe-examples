import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallUserNotification } from "../../../../../api/structures/IPageIShoppingMallUserNotification";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getShoppingMallAdministratorNotificationsSummary } from "../../../../../providers/getShoppingMallAdministratorNotificationsSummary";

@Controller("/shoppingMall/administrator/notifications/summary")
export class ShoppingmallAdministratorNotificationsSummaryController {
  /**
   * Retrieve a summarized list of notifications for the authenticated user.
   *
   * This API returns notification title, body, delivery status, read status, and linked template information.
   *
   * It integrates data from shopping_mall_user_notifications to show user-specific notifications, including delivered and read timestamps.
   *
   * The operation supports user roles such as customers, sellers, and administrators, returning only notifications owned by the current user.
   *
   * Related tables:
   * - shopping_mall_user_notifications (owner-specific notifications)
   * - shopping_mall_notification_templates (template details)
   * - shopping_mall_notification_deliveries (delivery statuses and channels)
   * - shopping_mall_notification_logs (event history)
   *
   * This operation does NOT allow creation, update, or deletion; it is read-only for notification summaries.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query shopping_mall_user_notifications filtering by owner_id using the authenticated user's ID.
   * Join shopping_mall_notification_templates to get the template_code and template_name.
   * Aggregate delivery statuses from shopping_mall_notification_deliveries for each user notification.
   * Return a paginated list of summarized notifications including title, body, is_read flag, delivered_at, read_at timestamps, and template info.
   * Ensure efficient querying with indexes on owner_id and created_at.
   * Handle potential null values for optional URL and image_url fields.
   * Authorize by verifying user's identity and ownership of notifications.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
  ): Promise<IPageIShoppingMallUserNotification.ISummary> {
    try {
      return await getShoppingMallAdministratorNotificationsSummary({
        administrator,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
