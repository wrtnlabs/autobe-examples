import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCategory } from "../../../../api/structures/IPageIShoppingMallCategory";
import { IShoppingMallCategory } from "../../../../api/structures/IShoppingMallCategory";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getShoppingMallAdministratorCategoriesCategoryId } from "../../../../providers/getShoppingMallAdministratorCategoriesCategoryId";
import { patchShoppingMallAdministratorCategories } from "../../../../providers/patchShoppingMallAdministratorCategories";
import { postShoppingMallAdministratorCategories } from "../../../../providers/postShoppingMallAdministratorCategories";
import { putShoppingMallAdministratorCategoriesCategoryId } from "../../../../providers/putShoppingMallAdministratorCategoriesCategoryId";

@Controller("/shoppingMall/administrator/categories")
export class ShoppingmallAdministratorCategoriesController {
  /**
   * Create a new product category entry in the system, supporting optional parent category to allow a single-level categorization hierarchy. This operation is restricted to authenticated administrators only.
   *
   * The category name must be unique within the scope of its parent category (or globally if no parent). This uniqueness conforms to the composite unique constraint defined on parent_category_id and name.
   *
   * Security: Only administrators have permission to invoke this endpoint. Unauthorized access will result in 403 Forbidden.
   *
   * Validation: The request body must include a non-empty name string and a description. The parentCategoryId is optional and can be used to nest categories under existing parent categories. The system automatically manages timestamps for creation and update events.
   *
   * No soft deletion is implemented in this operation; records are created permanently.
   *
   * Related operations:
   * - GET /categories for browsing existing categories
   * - PUT /categories/{categoryId} for updating a category
   * - DELETE /categories/{categoryId} for removing a category, which causes associated products to become uncategorized.
   *
   * Error Handling:
   * - 400 Bad Request for validation failures
   * - 403 Forbidden for unauthorized users
   * - 409 Conflict if category name duplicates an existing one in the same scope.
   *
   * @param connection
   * @param body Information needed to create a new product category, including optional parent category.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Validate admin authorization.
   * Validate request body contains required fields "name" and "description".
   * Optional "parentCategoryId" field allows nesting.
   * Check that name is unique within the scope of the parent category ID.
   * Insert a new record into shopping_mall_categories table with data from request body.
   * Set created_at and updated_at timestamps automatically.
   * Return the created category record as response.
   * Handle errors for validation, authorization, and uniqueness conflicts appropriately.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async createCategory(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IShoppingMallCategory.ICreate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await postShoppingMallAdministratorCategories({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of product categories including support for hierarchical subcategories through parentCategoryId filtering.
   *
   * This operation allows clients to search categories by name with partial matching, filter by parent category ID to get subcategories, and paginate results for performance.
   *
   * Only not-deleted categories (deleted_at IS NULL) are returned to ensure active data.
   *
   * This endpoint is used by customers, sellers, and administrators to browse and display categories within the shopping mall platform.
   *
   * Parameters:
   * - None in path.
   *
   * Request Body:
   * - Includes filters for category name, parent category ID, and pagination options.
   *
   * Response:
   * - Paginated list of category summaries with essential fields.
   *
   * Related Operations:
   * - GET /categories/{categoryId}/products to list products under a specific category.
   * - POST /admins/categories for administrators to create new categories.
   * - PUT /admins/categories/{categoryId} for administrators to update category info.
   * - DELETE /admins/categories/{categoryId} for administrators to delete categories.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for category listing.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Perform a query on shopping_mall_categories filtering by name (case-insensitive partial match), parent_category_id, and excluding records where deleted_at is not null.
   * Apply pagination with limit, offset, and sorting by name or creation date as specified in IShoppingMallCategory.IRequest.
   * Return results as a paginated collection of IShoppingMallCategory.ISummary.
   * Ensure query efficiency by indexing on name and parent_category_id.
   * Support optional filtering by parent_category_id to retrieve subcategories only.
   * No path parameters since composite unique constraint is on [parent_category_id, name] with parent context in request.
   * This operation is read-only and accessible by customers, sellers, and administrators with appropriate roles and authentication.
   * No request body duplication with path parameters, as path has none.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IShoppingMallCategory.IRequest,
  ): Promise<IPageIShoppingMallCategory.ISummary> {
    try {
      return await patchShoppingMallAdministratorCategories({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific product category identified by categoryId.
   *
   * This endpoint returns full details including name, description, hierarchical parent category if applicable, and timestamps. It supports browsing products grouped under categories for customers and administrators alike.
   *
   * Authorization is generally public as customers browse product categories, but clients must be authenticated to access restricted categories if any.
   *
   * This operation uses the shopping_mall_categories model which allows one level of subcategory nesting via the parentCategory relationship. The categoryId is the primary key (UUID) uniquely identifying the requested category.
   *
   * Related operations include GET /categories for listing all categories and GET /categories/{categoryId}/products for products in the category.
   *
   * All timestamps are in UTC and formatted as ISO 8601 strings.
   *
   * @param connection
   * @param categoryId Unique identifier of the product category as UUID.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the shopping_mall_categories table by primary key categoryId.
   * Load associated parentCategory if exists to enable nested category display.
   * Handle cases where categoryId does not exist by returning 404 Not Found.
   * No side effects or mutations performed.
   * Response includes all columns: id, parent_category_id, name, description, created_at, updated_at, deleted_at.
   * Validate categoryId as UUID format.
   * Cache results where appropriate to reduce database load for frequent category browsing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCategory> {
    try {
      return await getShoppingMallAdministratorCategoriesCategoryId({
        administrator,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product category identified by its unique ID.
   *
   * This API operation allows administrators to update the name and description of a category in the shopping mall platform. Categories are organized hierarchically with optional single-level subcategories through a parentCategory relationship.
   *
   * Only authenticated administrators have permissions to perform this update. Proper validation ensures the uniqueness of the category name scoped to its parent category.
   *
   * The updated category details are returned in the response.
   *
   * Related operations:
   * - GET /categories for listing categories
   * - POST /categories for creating new categories
   * - DELETE /categories/{categoryId} for deleting categories
   *
   * Error handling includes validation errors for duplicate name within the same parent and authorization errors for non-admin users.
   *
   * @param connection
   * @param categoryId Unique identifier of the category to update, as UUID string.
   * @param body Updated name and description of the category
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Service layer must validate administrator role before processing.
   *
   * Validate that the new category name is unique within the parentCategory scope.
   *
   * Perform update on shopping_mall_categories table for the record with id = categoryId.
   *
   * Reject requests with duplicate name under same parent_category_id with appropriate validation error.
   *
   * Return the updated category entity.
   *
   * Log the update action for audit.
   *
   * No changes to subcategories in this operation.
   *
   * Handle concurrency and transactional integrity.
   *
   * Ensure updated_at timestamp is refreshed.
   *
   * Respond with standard error codes for authorization failure and validation errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async updateCategory(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCategory.IUpdate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await putShoppingMallAdministratorCategoriesCategoryId({
        administrator,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
