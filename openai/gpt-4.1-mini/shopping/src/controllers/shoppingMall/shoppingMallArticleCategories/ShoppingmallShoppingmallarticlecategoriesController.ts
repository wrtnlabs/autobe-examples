import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallShoppingMallArticleCategories } from "../../../providers/patchShoppingMallShoppingMallArticleCategories";
import { getShoppingMallShoppingMallArticleCategoriesShoppingMallArticleCategoryId } from "../../../providers/getShoppingMallShoppingMallArticleCategoriesShoppingMallArticleCategoryId";

import { IPageIShoppingMallArticleCategory } from "../../../api/structures/IPageIShoppingMallArticleCategory";
import { IShoppingMallArticleCategory } from "../../../api/structures/IShoppingMallArticleCategory";

@Controller("/shoppingMall/shoppingMallArticleCategories")
export class ShoppingmallShoppingmallarticlecategoriesController {
  /**
   * Search and retrieve a filtered, paginated list of shopping mall article
   * categories.
   *
   * Retrieve a filtered and paginated list of article categories within the
   * shopping mall platform.
   *
   * This operation allows users to search and filter article categories by
   * criteria such as name or parent category, with support for pagination and
   * sorting to manage large data sets effectively.
   *
   * Security considerations include access control to authorized users and
   * protection of sensitive category information. The categories have
   * hierarchical structure, and filtering supports parent-child relationships.
   *
   * This operation interfaces with the shopping_mall_article_categories table
   * ensuring response consistency with the database schema.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for article
   *   categories
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallArticleCategory.IRequest,
  ): Promise<IPageIShoppingMallArticleCategory.ISummary> {
    try {
      return await patchShoppingMallShoppingMallArticleCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed shopping mall article category information by ID.
   *
   * Retrieve detailed information about a specific article category by its
   * unique identifier.
   *
   * This operation returns all properties of the category including
   * hierarchical relationships within the shopping mall article categories.
   *
   * Access requires authorization to protect sensitive information and maintain
   * integrity.
   *
   * It corresponds to the shopping_mall_article_categories Prisma table,
   * ensuring data consistency.
   *
   * @param connection
   * @param shoppingMallArticleCategoryId Unique identifier of the target
   *   shopping mall article category (UUID)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shoppingMallArticleCategoryId")
  public async at(
    @TypedParam("shoppingMallArticleCategoryId")
    shoppingMallArticleCategoryId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallArticleCategory> {
    try {
      return await getShoppingMallShoppingMallArticleCategoriesShoppingMallArticleCategoryId(
        {
          shoppingMallArticleCategoryId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
