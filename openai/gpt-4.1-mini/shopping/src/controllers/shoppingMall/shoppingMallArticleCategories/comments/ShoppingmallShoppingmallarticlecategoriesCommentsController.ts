import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallShoppingMallArticleCategoriesShoppingMallArticleCategoryIdComments } from "../../../../providers/patchShoppingMallShoppingMallArticleCategoriesShoppingMallArticleCategoryIdComments";
import { getShoppingMallShoppingMallArticleCategoriesShoppingMallArticleCategoryIdCommentsShoppingMallArticleCommentId } from "../../../../providers/getShoppingMallShoppingMallArticleCategoriesShoppingMallArticleCategoryIdCommentsShoppingMallArticleCommentId";

import { IPageIShoppingMallArticleComment } from "../../../../api/structures/IPageIShoppingMallArticleComment";
import { IShoppingMallArticleComment } from "../../../../api/structures/IShoppingMallArticleComment";

@Controller(
  "/shoppingMall/shoppingMallArticleCategories/:shoppingMallArticleCategoryId/comments",
)
export class ShoppingmallShoppingmallarticlecategoriesCommentsController {
  /**
   * Retrieve comments of a shopping mall article category with paging and
   * filtering.
   *
   * Retrieve a filtered, sorted, and paginated list of comments related to a
   * specific shopping mall article category.
   *
   * This operation allows users to search and browse comments effectively, with
   * support for various filters such as date ranges, author, and content
   * keywords.
   *
   * Security measures ensure that users can only access comments appropriate to
   * their authorization level.
   *
   * The resulting response provides summarized comment information optimized
   * for list display.
   *
   * This operation is essential for displaying user feedback and discussions
   * associated with article categories.
   *
   * @param connection
   * @param shoppingMallArticleCategoryId Unique identifier of the shopping mall
   *   article category whose comments are being retrieved
   * @param body Search criteria and pagination parameters for filtering
   *   shopping mall article comments
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("shoppingMallArticleCategoryId")
    shoppingMallArticleCategoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallArticleComment.IRequest,
  ): Promise<IPageIShoppingMallArticleComment.ISummary> {
    try {
      return await patchShoppingMallShoppingMallArticleCategoriesShoppingMallArticleCategoryIdComments(
        {
          shoppingMallArticleCategoryId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get a specific comment from shopping mall article category.
   *
   * Retrieve detailed information of a specific article comment within a given
   * shopping mall article category.
   *
   * This operation fetches the comment identified by its unique comment ID
   * (`shoppingMallArticleCommentId`) that belongs to the specified article
   * category identified by `shoppingMallArticleCategoryId`. It provides
   * detailed data including the comment content, timestamps, and associations
   * to the article and user if applicable.
   *
   * Security: Access is allowed publicly ([]), assuming comments are public
   * content. The system enforces referential integrity by verifying that the
   * comment belongs to the provided article category. The operation facilitates
   * display of individual user comments in user interfaces and moderation
   * tools.
   *
   * Related operations: Creating a new comment (POST
   * /shoppingMallArticleCategories/{shoppingMallArticleCategoryId}/comments).
   *
   * @param connection
   * @param shoppingMallArticleCategoryId Unique identifier of the target
   *   shopping mall article category (UUID format)
   * @param shoppingMallArticleCommentId Unique identifier of the target
   *   shopping mall article comment (UUID format)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shoppingMallArticleCommentId")
  public async at(
    @TypedParam("shoppingMallArticleCategoryId")
    shoppingMallArticleCategoryId: string & tags.Format<"uuid">,
    @TypedParam("shoppingMallArticleCommentId")
    shoppingMallArticleCommentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallArticleComment> {
    try {
      return await getShoppingMallShoppingMallArticleCategoriesShoppingMallArticleCategoryIdCommentsShoppingMallArticleCommentId(
        {
          shoppingMallArticleCategoryId,
          shoppingMallArticleCommentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
