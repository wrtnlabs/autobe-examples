import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteShoppingMallAdminMileagesMileageId } from "../../../../providers/deleteShoppingMallAdminMileagesMileageId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

@Controller("/shoppingMall/admin/mileages/:mileageId")
export class ShoppingmallAdminMileagesController {
  /**
   * Permanently deletes a customer mileage record identified by mileageId. This
   * endpoint is intended for administrative or internal use to remove mileage
   * points, for example in case of customer account closure or data
   * correction.
   *
   * Security: This operation requires proper authorization to prevent
   * accidental or malicious data loss.
   *
   * As a hard delete, the record is completely removed from the database and
   * cannot be recovered.
   *
   * Related operations include retrieval of mileage records and adjustments via
   * other endpoints.
   *
   * @param connection
   * @param mileageId Unique identifier of the customer mileage record to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("mileageId")
    mileageId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminMileagesMileageId({
        admin,
        mileageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
