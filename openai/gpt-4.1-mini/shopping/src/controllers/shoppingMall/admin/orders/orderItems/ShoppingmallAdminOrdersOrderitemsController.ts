import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminOrdersOrderIdOrderItems } from "../../../../../providers/patchShoppingMallAdminOrdersOrderIdOrderItems";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IPageIShoppingMallOrderItem } from "../../../../../api/structures/IPageIShoppingMallOrderItem";
import { IShoppingMallOrderItem } from "../../../../../api/structures/IShoppingMallOrderItem";

@Controller("/shoppingMall/admin/orders/:orderId/orderItems")
export class ShoppingmallAdminOrdersOrderitemsController {
  /**
   * Retrieve a filtered, sorted, and paginated list of order items associated
   * with a specific shopping mall order.
   *
   * This operation supports complex query parameters allowing authorized users
   * to specify filters such as product variant attributes, quantity ranges, and
   * pricing limits. Pagination parameters enable segmented retrievals optimized
   * for large orders.
   *
   * Security mechanisms ensure only authenticated and authorized actors, such
   * as administrators or sales agents, can access detailed order item data.
   *
   * The response returns summaries of shopping_mall_order_items entries linked
   * to the specified order, encompassing quantity, unit price, and total
   * pricing details.
   *
   * This operation relies on the shopping_mall_order_items subsidiary Prisma
   * schema entity, guaranteeing consistency and conformity with database
   * integrity constraints.
   *
   * Related operations include order creation, update, and order detail
   * retrieval.
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @param body Search criteria and pagination parameters for filtering
   *   shopping mall order items
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderItem.IRequest,
  ): Promise<IPageIShoppingMallOrderItem.ISummary> {
    try {
      return await patchShoppingMallAdminOrdersOrderIdOrderItems({
        admin,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
