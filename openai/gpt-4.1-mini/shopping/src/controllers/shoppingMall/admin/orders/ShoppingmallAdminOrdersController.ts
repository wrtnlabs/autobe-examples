import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallAdminOrders } from "../../../../providers/patchShoppingMallAdminOrders";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminOrdersOrderCode } from "../../../../providers/getShoppingMallAdminOrdersOrderCode";
import { deleteShoppingMallAdminOrdersOrderCode } from "../../../../providers/deleteShoppingMallAdminOrdersOrderCode";

import { IPageIShoppingMallOrder } from "../../../../api/structures/IPageIShoppingMallOrder";
import { IShoppingMallOrder } from "../../../../api/structures/IShoppingMallOrder";

@Controller("/shoppingMall/admin/orders")
export class ShoppingmallAdminOrdersController {
  /**
   * Search and retrieve a filtered, paginated list of shopping orders.
   *
   * Retrieve a filtered and paginated list of shopping orders from the system.
   * This operation enables searching orders based on multiple criteria
   * including order status, payment status, creation date range, customer
   * information, and total amount ranges.
   *
   * It returns a paginated collection of orders with summary information
   * suitable for dashboard displays or administrative views. Searching supports
   * sorting options and flexible filtering parameters to streamline finding
   * relevant orders.
   *
   * Security considerations include restricting access to authorized users such
   * as administrators or specific user roles. The endpoint is optimized for
   * performance with indexed filtering and pagination.
   *
   * This operation integrates with the shopping_mall_orders table as defined in
   * the Prisma schema, leveraging related tables for enriched order context. It
   * excludes direct manipulation or creation, focusing solely on retrieval and
   * search capabilities.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   shopping orders
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallOrder.IRequest,
  ): Promise<IPageIShoppingMallOrder.ISummary> {
    try {
      return await patchShoppingMallAdminOrders({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed shopping order information by order code.
   *
   * Retrieve complete detailed information for a specific shopping order by its
   * unique order code. This operation provides all relevant order data
   * including line items, payments, shipment tracking, reviews, audit trails,
   * cancellations, refunds, and return shipments.
   *
   * Access is restricted to authorized users such as administrators and the
   * owning customer. The endpoint respects data privacy and enforces role-based
   * access control.
   *
   * The shopping_mall_orders table defines the main data structure, while
   * related tables enrich the response with comprehensive order context. This
   * operation returns detailed order information essential for UI displays and
   * backend processing.
   *
   * @param connection
   * @param orderCode Unique business identifier code of the target shopping
   *   order (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderCode")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderCode")
    orderCode: string,
  ): Promise<IShoppingMallOrder> {
    try {
      return await getShoppingMallAdminOrdersOrderCode({
        admin,
        orderCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Hard delete operation to permanently remove a shopping mall order by its
   * code.
   *
   * This API operation performs a hard delete of an order record from the
   * shopping_mall_orders table based on the unique orderCode. It is intended to
   * be used for customer or administrative order cancellations that permanently
   * remove the order data.
   *
   * Only authorized actors with the role "admin" or "customer" can access this
   * endpoint. It ensures only admins or the order-owning customer can delete
   * the order, providing security and preventing unauthorized deletions.
   *
   * The path parameter orderCode uniquely identifies the order within the
   * system, ensuring unambiguous targeting for deletion. Since
   * shopping_mall_orders include a deleted_at column, soft delete could be
   * used, but this operation intentionally performs permanent deletion as
   * specified.
   *
   * No request body is required and no content is returned in the response,
   * indicating that a successful call results in the removal of the order
   * record. Errors are returned if the orderCode does not exist or if the
   * requester lacks permissions.
   *
   * Related operations include retrieving order details, managing order items,
   * and processing refunds or cancellations with separate endpoints.
   *
   * @param connection
   * @param orderCode Unique business identifier code of the target order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":orderCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderCode")
    orderCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminOrdersOrderCode({
        admin,
        orderCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
