import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteShoppingMallAdminOrdersOrderId } from "../../../../providers/deleteShoppingMallAdminOrdersOrderId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

@Controller("/shoppingMall/admin/orders/:orderId")
export class ShoppingmallAdminOrdersController {
  /**
   * Permanently removes a shopping mall customer order from the system.
   *
   * This operation allows authorized users to erase an order record identified
   * by its unique UUID. Deletion involves removing the order from the database,
   * including dependent order items and any linked transactional data, ensuring
   * data integrity is maintained.
   *
   * Security considerations require that only actors with permissions to manage
   * orders can invoke this API. Proper error handling is implemented for cases
   * where the order does not exist or user lacks authorization.
   *
   * This API operates on the shopping_mall_orders table as defined in the
   * Prisma schema, ensuring consistent business logic and data validation.
   *
   * Related API operations include order creation, updating, and retrieval
   * endpoints.
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminOrdersOrderId({
        admin,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
