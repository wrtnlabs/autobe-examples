import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminOrderCancellations } from "../../../../providers/patchShoppingMallAdminOrderCancellations";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminOrderCancellationsOrderCancellationId } from "../../../../providers/getShoppingMallAdminOrderCancellationsOrderCancellationId";

import { IPageIShoppingMallOrderCancellation } from "../../../../api/structures/IPageIShoppingMallOrderCancellation";
import { IShoppingMallOrderCancellation } from "../../../../api/structures/IShoppingMallOrderCancellation";

@Controller("/shoppingMall/admin/orderCancellations")
export class ShoppingmallAdminOrdercancellationsController {
  /**
   * Search and retrieve paginated order cancellation requests.
   *
   * Retrieve a filtered and paginated list of order cancellation requests in
   * the system. This operation allows clients to query cancellation requests by
   * various criteria such as status, customer, or date range, enabling
   * effective monitoring and management.
   *
   * The operation integrates with the shopping_mall_order_cancellations Prisma
   * table, fetching details including cancellation reason, status, timestamps,
   * and linked order and customer information. Pagination and sorting
   * parameters help tailor the data to user needs.
   *
   * Security considerations include restricting access to authenticated actors
   * with administrative or customer roles. Sensitive data exposure is limited
   * based on permission levels.
   *
   * The response returns a paginated collection of order cancellation summaries
   * optimized for list views.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for order
   *   cancellations
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallOrderCancellation.IRequest,
  ): Promise<IPageIShoppingMallOrderCancellation.ISummary> {
    try {
      return await patchShoppingMallAdminOrderCancellations({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve an order cancellation request by its ID.
   *
   * Retrieve detailed information for a specific order cancellation request
   * identified by its ID. This operation enables clients to fetch full details
   * including cancellation reasons, status, associated order and customer
   * data.
   *
   * It operates on the shopping_mall_order_cancellations table in the Prisma
   * schema and ensures the record exists and is accessible by authorized
   * actors.
   *
   * Authorization is required, typically for admin users or the customer who
   * owns the cancellation request. Proper error handling is performed if the
   * cancellation ID does not exist.
   *
   * This operation complements the list retrieval operation GET
   * /orderCancellations for detailed inspection of cancellation requests.
   *
   * @param connection
   * @param orderCancellationId Unique identifier of the target order
   *   cancellation request (UUID format)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderCancellationId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderCancellationId")
    orderCancellationId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderCancellation> {
    try {
      return await getShoppingMallAdminOrderCancellationsOrderCancellationId({
        admin,
        orderCancellationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
