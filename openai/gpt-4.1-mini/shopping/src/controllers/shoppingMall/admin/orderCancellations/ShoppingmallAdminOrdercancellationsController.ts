import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminOrderCancellations } from "../../../../providers/patchShoppingMallAdminOrderCancellations";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminOrderCancellationsOrderCancellationId } from "../../../../providers/getShoppingMallAdminOrderCancellationsOrderCancellationId";
import { deleteShoppingMallAdminOrderCancellationsOrderCancellationId } from "../../../../providers/deleteShoppingMallAdminOrderCancellationsOrderCancellationId";

import { IPageIShoppingMallOrderCancellation } from "../../../../api/structures/IPageIShoppingMallOrderCancellation";
import { IShoppingMallOrderCancellation } from "../../../../api/structures/IShoppingMallOrderCancellation";

@Controller("/shoppingMall/admin/orderCancellations")
export class ShoppingmallAdminOrdercancellationsController {
  /**
   * Retrieve a paginated list of shopping mall order cancellation requests
   * submitted by customers. This operation supports filtering cancellation
   * requests by customer ID, status, submission date, and other relevant
   * criteria.
   *
   * The operation provides pagination and sorting options to handle large
   * volumes of data efficiently. Authorized users such as administrators can
   * use this endpoint to monitor cancellation trends, respond to requests
   * promptly, and manage order cancellations effectively.
   *
   * Security considerations include restricting access to authenticated
   * administrative and customer service actors only, ensuring the privacy and
   * integrity of cancellation data. Related operations include retrieving
   * individual cancellation request details and updating request statuses.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for order
   *   cancellation filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallOrderCancellation.IRequest,
  ): Promise<IPageIShoppingMallOrderCancellation.ISummary> {
    try {
      return await patchShoppingMallAdminOrderCancellations({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order cancellation request
   * using its unique identifier.
   *
   * This endpoint returns all relevant details needed to review and process a
   * cancellation request, including the associated order, customer, reason for
   * cancellation, and current status.
   *
   * Access is restricted to administrators and customer service personnel for
   * privacy and security. This operation is essential for managing individual
   * cancellation workflows and customer interactions.
   *
   * @param connection
   * @param orderCancellationId Unique identifier of the target order
   *   cancellation request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderCancellationId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderCancellationId")
    orderCancellationId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderCancellation> {
    try {
      return await getShoppingMallAdminOrderCancellationsOrderCancellationId({
        admin,
        orderCancellationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently deletes a single order cancellation request. The request is
   * identified by its unique UUID `orderCancellationId`.
   *
   * Security: This operation requires appropriate authorization since it
   * deletes important data records. Only authorized user roles should access
   * this endpoint.
   *
   * Underlying data: The endpoint operates on the
   * shopping_mall_order_cancellations table, which records order cancellation
   * requests including reasons, status, timestamps, and deletion markers.
   *
   * Validation: The endpoint validates the existence of the cancellation
   * request matching the given ID before deletion. If no matching record is
   * found, a suitable error is returned.
   *
   * Related operations: Design includes creation and retrieval endpoints for
   * cancellation requests which should be implemented separately to offer full
   * CRUD functionality.
   *
   * @param connection
   * @param orderCancellationId Unique UUID identifier of the order cancellation
   *   request to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":orderCancellationId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderCancellationId")
    orderCancellationId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminOrderCancellationsOrderCancellationId(
        {
          admin,
          orderCancellationId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
