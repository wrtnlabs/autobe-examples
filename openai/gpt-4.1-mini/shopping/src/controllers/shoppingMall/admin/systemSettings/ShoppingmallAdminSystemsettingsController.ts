import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminSystemSettings } from "../../../../providers/postShoppingMallAdminSystemSettings";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminSystemSettings } from "../../../../providers/patchShoppingMallAdminSystemSettings";
import { getShoppingMallAdminSystemSettingsId } from "../../../../providers/getShoppingMallAdminSystemSettingsId";
import { putShoppingMallAdminSystemSettingsId } from "../../../../providers/putShoppingMallAdminSystemSettingsId";
import { deleteShoppingMallAdminSystemSettingsId } from "../../../../providers/deleteShoppingMallAdminSystemSettingsId";

import { IShoppingMallSystemSetting } from "../../../../api/structures/IShoppingMallSystemSetting";
import { IPageIShoppingMallSystemSetting } from "../../../../api/structures/IPageIShoppingMallSystemSetting";

@Controller("/shoppingMall/admin/systemSettings")
export class ShoppingmallAdminSystemsettingsController {
  /**
   * Create a new system setting record in shopping_mall_system_settings.
   *
   * Create a new system setting in the platform configuration. This operation
   * allows administrators to define new key-value pairs that affect the
   * behavior and settings of the shopping mall backend system.
   *
   * Only authorized admin users can perform this operation to ensure system
   * integrity and prevent unauthorized changes.
   *
   * The request requires providing a unique key identifier and associated
   * value, with optional descriptive information.
   *
   * Upon successful creation, the system returns the full system setting record
   * including timestamps.
   *
   * This operation does not handle updates or deletions; those are managed with
   * specialized endpoints.
   *
   * @param connection
   * @param body Payload containing new system setting information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSystemSetting.ICreate,
  ): Promise<IShoppingMallSystemSetting> {
    try {
      return await postShoppingMallAdminSystemSettings({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve system settings with filters and pagination.
   *
   * Retrieve a filtered and paginated list of system settings from the
   * platform. This operation supports advanced search capabilities on the
   * system settings database table corresponding to
   * 'shopping_mall_system_settings'. Clients can filter by key, value, and
   * description with full-text search capabilities for flexible querying.
   *
   * This operation requires authentication for admin users who manage system
   * configurations. Returned results include essential system setting fields
   * with pagination metadata to facilitate large dataset navigation.
   *
   * Business logic enforces that only active (non-soft-deleted) settings are
   * retrieved. This operation does not modify data and is read-only.
   *
   * The response returns a paginated summary of system setting records matching
   * the filtering criteria, aiding in platform administration and diagnostics.
   *
   * @param connection
   * @param body Search parameters and pagination info for system settings
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSystemSetting.IRequest,
  ): Promise<IPageIShoppingMallSystemSetting.ISummary> {
    try {
      return await patchShoppingMallAdminSystemSettings({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed system setting information by ID.
   *
   * Get detailed system setting information by ID from
   * 'shopping_mall_system_settings' table. This operation returns all fields of
   * the targeted system setting including key and value with timestamps.
   *
   * Only authenticated admin users may access this endpoint to ensure sensitive
   * configuration data is protected.
   *
   * The operation performs no data modification and is strictly for retrieval,
   * supporting administrative review and configuration management.
   *
   * Error handling includes returning not found errors if the specified ID does
   * not correspond to an existing active record.
   *
   * @param connection
   * @param id Unique identifier of the target system setting
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSystemSetting> {
    try {
      return await getShoppingMallAdminSystemSettingsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing system setting record by ID in
   * shopping_mall_system_settings.
   *
   * Update an existing system setting identified by its unique UUID. This
   * operation permits modifying the key, value, and description of the system
   * setting.
   *
   * Only authorized admin users can perform updates.
   *
   * The system returns the updated record reflecting changes and modified
   * timestamps.
   *
   * The operation expects the UUID of the system setting as a path parameter
   * and the updated data in the request body.
   *
   * No response body is returned for errors, which are handled by standard HTTP
   * status codes.
   *
   * @param connection
   * @param id Unique identifier of the system setting to update
   * @param body Payload containing updated system setting information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSystemSetting.IUpdate,
  ): Promise<IShoppingMallSystemSetting> {
    try {
      return await putShoppingMallAdminSystemSettingsId({
        admin,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific system setting by its unique ID.
   *
   * This DELETE endpoint allows authorized users to permanently erase a
   * specific system setting from the system settings table of the shopping mall
   * platform. The target setting is identified by its UUID primary key passed
   * as a path parameter.
   *
   * The operation is critical for maintaining the global configuration of the
   * shopping platform and must be secured to prevent unauthorized
   * modifications.
   *
   * The 'shopping_mall_system_settings' table includes a 'deleted_at' column,
   * indicating that soft delete might be implemented; however, this operation
   * performs a hard delete permanently removing the record from the database.
   * Deleted settings cannot be restored, so caution is advised.
   *
   * Only users with administrative privileges should be authorized to execute
   * this operation to avoid misconfiguration.
   *
   * No request body is required and the response body is null upon success.
   * Appropriate HTTP status codes indicate operation result.
   *
   * Related operations include listing and updating system settings.
   *
   * @param connection
   * @param id Unique UUID identifier of the target system setting to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async eraseSystemSetting(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminSystemSettingsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
