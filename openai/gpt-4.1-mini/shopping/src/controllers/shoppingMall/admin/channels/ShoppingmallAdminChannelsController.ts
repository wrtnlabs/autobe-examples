import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallAdminChannels } from "../../../../providers/postShoppingMallAdminChannels";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminChannelsChannelCode } from "../../../../providers/putShoppingMallAdminChannelsChannelCode";
import { deleteShoppingMallAdminChannelsChannelCode } from "../../../../providers/deleteShoppingMallAdminChannelsChannelCode";

import { IShoppingMallChannelDefinition } from "../../../../api/structures/IShoppingMallChannelDefinition";

@Controller("/shoppingMall/admin/channels")
export class ShoppingmallAdminChannelsController {
  /**
   * Create a new shopping mall communication or operational channel.
   *
   * Create a new communication or operational channel in the shopping mall
   * platform. This endpoint supports hierarchical channel organization by
   * optionally associating the new channel with an existing parent channel,
   * facilitating nested groupings.
   *
   * Security considerations require that this operation be restricted to
   * authorized users with channel creation permissions.
   *
   * The operation maps directly to the shopping_mall_channel_definitions table,
   * preserving all relevant fields including the unique channel code, name,
   * optional description, and timestamps.
   *
   * Inputs must comply with defined formats and uniqueness constraints to avoid
   * conflicts. Upon successful creation, the operation returns the full channel
   * data.
   *
   * This operation should be used in conjunction with the update operation for
   * maintenance and modification of existing channels.
   *
   * @param connection
   * @param body Information needed to create a new channel, including optional
   *   parent reference, unique code, and descriptive name.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallChannelDefinition.ICreate,
  ): Promise<IShoppingMallChannelDefinition> {
    try {
      return await postShoppingMallAdminChannels({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a shopping mall channel identified by channelCode.
   *
   * Update an existing shopping mall communication or operational channel by
   * its unique channelCode. This endpoint allows changing the channel's name,
   * description, or reassigning its parent channel to reorganize hierarchies.
   *
   * Security: Access is restricted to privileged users with administrative
   * rights.
   *
   * The operation affects the shopping_mall_channel_definitions table, ensuring
   * data consistency and validation of all fields.
   *
   * It complements the create operation that initially adds new channels to the
   * system.
   *
   * @param connection
   * @param channelCode Unique code identifying the target channel (global
   *   scope)
   * @param body Updated channel information including name, description, and
   *   optional new parent
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":channelCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("channelCode")
    channelCode: string,
    @TypedBody()
    body: IShoppingMallChannelDefinition.IUpdate,
  ): Promise<IShoppingMallChannelDefinition> {
    try {
      return await putShoppingMallAdminChannelsChannelCode({
        admin,
        channelCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a channel definition by its unique channelCode.
   *
   * Deletes an existing channel definition identified by its unique
   * channelCode. This operation permanently removes the channel record from the
   * shopping_mall_channel_definitions table. Only users with the 'admin' role
   * have permission to perform this deletion to safeguard system integrity.
   *
   * The path parameter channelCode uniquely identifies the channel to delete,
   * corresponding to the unique channel_code field in the database.
   *
   * Upon successful deletion, any child channels associated with the deleted
   * channel will also be removed according to the cascading delete rules
   * defined in the schema.
   *
   * If the specified channelCode does not exist, a suitable error response will
   * be returned to indicate not found.
   *
   * Security considerations: Only authenticated admins should be allowed to
   * call this endpoint. Deletion actions are logged and audited to prevent
   * unintended data loss.
   *
   * This operation has no request body and returns no response body.
   *
   * Because the Prisma table shopping_mall_channel_definitions includes a
   * deleted_at field, soft deletion is possible, but this API performs a hard
   * delete to remove data permanently.
   *
   * @param connection
   * @param channelCode Unique business identifier code of the target channel
   *   definition (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":channelCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("channelCode")
    channelCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminChannelsChannelCode({
        admin,
        channelCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
