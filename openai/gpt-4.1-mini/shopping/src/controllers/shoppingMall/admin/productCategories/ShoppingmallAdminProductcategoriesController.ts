import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallAdminProductCategoriesId } from "../../../../providers/getShoppingMallAdminProductCategoriesId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminProductCategoriesId } from "../../../../providers/putShoppingMallAdminProductCategoriesId";
import { deleteShoppingMallAdminProductCategoriesId } from "../../../../providers/deleteShoppingMallAdminProductCategoriesId";
import { postShoppingMallAdminProductCategories } from "../../../../providers/postShoppingMallAdminProductCategories";

import { IShoppingMallProductCategory } from "../../../../api/structures/IShoppingMallProductCategory";

@Controller("/shoppingMall/admin/productCategories")
export class ShoppingmallAdminProductcategoriesController {
  /**
   * Retrieve a product category by id from shopping_mall_product_categories.
   *
   * Retrieve detailed information about a specific product category by its
   * unique identifier.
   *
   * This operation fetches the product category from the
   * shopping_mall_product_categories table, providing all attributes including
   * name, description, parent category reference, creation and update
   * timestamps, and soft delete status.
   *
   * Access to this endpoint requires valid authentication with proper
   * authorization. The data returned is used for category management and
   * navigation purposes.
   *
   * All referenced attributes are directly from the Prisma schema for
   * shopping_mall_product_categories, ensuring comprehensive category data is
   * provided. Error handling includes not found errors for invalid ids.
   *
   * @param connection
   * @param id Unique identifier of the target product category
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductCategory> {
    try {
      return await getShoppingMallAdminProductCategoriesId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a product category by its unique ID.
   *
   * Update an existing product category in the shopping mall platform. This
   * operation allows the authorized user to change the category's name,
   * description, and parent category, preserving the hierarchical structure.
   *
   * The system enforces uniqueness of category names among sibling categories
   * to prevent conflicts.
   *
   * Only authenticated users with appropriate permissions (such as sellers or
   * admins) can perform this operation.
   *
   * Proper error handling must be implemented to manage validation failures
   * such as duplicate category names or invalid parent references.
   *
   * @param connection
   * @param id Unique identifier of the target product category
   * @param body Data needed to update a product category
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductCategory.IUpdate,
  ): Promise<IShoppingMallProductCategory> {
    try {
      return await putShoppingMallAdminProductCategoriesId({
        admin,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a product category by its unique ID.
   *
   * Permanently delete a product category identified by its unique UUID. This
   * operation checks for the existence of any products under the category,
   * preventing deletion if dependent products exist to maintain data
   * integrity.
   *
   * This is a hard delete operation, permanently removing the category from the
   * database.
   *
   * Authorization is limited to seller and admin roles only.
   *
   * @param connection
   * @param id Unique identifier of the target product category
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminProductCategoriesId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new product category in shopping_mall_product_categories.
   *
   * Create a new product category with the specified name, optional
   * description, and optional parent category reference.
   *
   * Business rules require that category names be unique among sibling
   * categories. Input data validation is performed against the
   * shopping_mall_product_categories schema.
   *
   * Authorized users such as admins and sellers may perform this operation.
   * Successful creation returns the new category record.
   *
   * Appropriate error messages are issued on validation failures, name
   * conflicts, or authorization denials.
   *
   * @param connection
   * @param body New product category create info
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallProductCategory.ICreate,
  ): Promise<IShoppingMallProductCategory> {
    try {
      return await postShoppingMallAdminProductCategories({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
