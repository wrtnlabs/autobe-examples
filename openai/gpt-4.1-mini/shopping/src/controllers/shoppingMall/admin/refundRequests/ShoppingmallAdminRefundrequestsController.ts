import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallAdminRefundRequestsRefundRequestId } from "../../../../providers/getShoppingMallAdminRefundRequestsRefundRequestId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminRefundRequestsRefundRequestId } from "../../../../providers/putShoppingMallAdminRefundRequestsRefundRequestId";
import { deleteShoppingMallAdminRefundRequestsRefundRequestId } from "../../../../providers/deleteShoppingMallAdminRefundRequestsRefundRequestId";

import { IShoppingMallRefundRequest } from "../../../../api/structures/IShoppingMallRefundRequest";

@Controller("/shoppingMall/admin/refundRequests/:refundRequestId")
export class ShoppingmallAdminRefundrequestsController {
  /**
   * Retrieve a specific refund request by its unique identifier. This endpoint
   * returns all pertinent information about the request including refund
   * amount, reason, current status, when it was requested, and when it was
   * processed if applicable.
   *
   * Security: Access to this endpoint may require appropriate authorization as
   * refund data is sensitive and linked to financial transactions. Only
   * authorized users such as admin or refund processors can view the details.
   *
   * The operation ties directly to the shopping_mall_refund_requests table from
   * the Prisma schema, ensuring accurate reflection of the stored data
   * including audit timestamps and soft deletion status.
   *
   * Related operations include creating a refund request and managing its
   * lifecycle through external workflows.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await getShoppingMallAdminRefundRequestsRefundRequestId({
        admin,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update details of an existing refund request by specifying its unique
   * identifier.
   *
   * This operation enables authorized users to adjust refund amounts, change
   * refund reasons, update the refund status, as well as set the processed
   * timestamp if applicable.
   *
   * It maps directly to the shopping_mall_refund_requests table and enforces
   * that only valid refund statuses can be set through the system. The
   * operation ensures that timestamps used are in ISO 8601 format and that
   * refund amounts are non-negative.
   *
   * Security constraints require authentication and role-based permissions. The
   * updated refund request will be returned in the response.
   *
   * Related API operations include reading refund request details and deleting
   * refund requests.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request
   * @param body Data needed to update the refund request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallRefundRequest.IUpdate,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await putShoppingMallAdminRefundRequestsRefundRequestId({
        admin,
        refundRequestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a refund request permanently from the system by its unique
   * identifier.
   *
   * This hard delete operation removes the record completely, ensuring no
   * residual data remains.
   *
   * Only authorized users such as administrators can perform this action,
   * maintaining system security and integrity.
   *
   * Related API operations include retrieving and updating refund requests.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminRefundRequestsRefundRequestId({
        admin,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
