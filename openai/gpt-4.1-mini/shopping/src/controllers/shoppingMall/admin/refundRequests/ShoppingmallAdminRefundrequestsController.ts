import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminRefundRequests } from "../../../../providers/patchShoppingMallAdminRefundRequests";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminRefundRequestsId } from "../../../../providers/getShoppingMallAdminRefundRequestsId";

import { IPageIShoppingMallRefundRequest } from "../../../../api/structures/IPageIShoppingMallRefundRequest";
import { IShoppingMallRefundRequest } from "../../../../api/structures/IShoppingMallRefundRequest";

@Controller("/shoppingMall/admin/refundRequests")
export class ShoppingmallAdminRefundrequestsController {
  /**
   * Search and retrieve a paginated list of refund requests.
   *
   * Retrieve a filtered and paginated list of refund requests in the shopping
   * mall platform. This API endpoint supports detailed querying capabilities
   * including filtering by refund status, customer identity, order association,
   * and timestamps.
   *
   * The operation is secured and typically accessible by administrators or
   * customer service representatives responsible for managing refund workflows
   * and customer issues. The retrieved data includes refund amounts, reasons,
   * statuses, and timestamps, enabling comprehensive overview and audit of
   * refund activities.
   *
   * This operation interacts directly with the shopping_mall_refund_requests
   * table which maintains detailed refund request data linked to orders and
   * customers. It enables efficient processing of customer refund claims and
   * integrates with related order and return shipment information.
   *
   * Validation rules ensure proper pagination parameters and valid filters for
   * refund status and customer identity. Error handling covers invalid requests
   * and unauthorized data access.
   *
   * This endpoint is typically the first step in administrative workflows to
   * review and process refund requests, and may be combined with detail
   * retrieval and update operations for full management.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for refund requests
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallRefundRequest.IRequest,
  ): Promise<IPageIShoppingMallRefundRequest.ISummary> {
    try {
      return await patchShoppingMallAdminRefundRequests({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed refund request information by ID.
   *
   * Retrieve detailed information about a specific refund request by its unique
   * identifier. This endpoint is essential for administrators or customer
   * service agents who need to review individual refund request details,
   * supporting decision making for approval, rejection, or further inquiry.
   *
   * The data returned includes refund amounts, reasons, statuses, and
   * timestamps. It provides comprehensive traceability linked to the original
   * order and customer. Access is restricted to authorized actors to protect
   * sensitive customer and financial data.
   *
   * This operation uses the shopping_mall_refund_requests Prisma table,
   * ensuring accurate and current refund request information. It complements
   * list retrieval and management APIs to provide full refund processing
   * capabilities.
   *
   * Error handling addresses cases where the requested refund ID does not exist
   * or access is denied due to insufficient permissions.
   *
   * @param connection
   * @param id Unique identifier of the refund request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await getShoppingMallAdminRefundRequestsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
