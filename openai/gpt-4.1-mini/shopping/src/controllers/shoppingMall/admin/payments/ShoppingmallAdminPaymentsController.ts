import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminPayments } from "../../../../providers/postShoppingMallAdminPayments";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminPayments } from "../../../../providers/patchShoppingMallAdminPayments";
import { getShoppingMallAdminPaymentsPaymentId } from "../../../../providers/getShoppingMallAdminPaymentsPaymentId";
import { putShoppingMallAdminPaymentsPaymentId } from "../../../../providers/putShoppingMallAdminPaymentsPaymentId";
import { deleteShoppingMallAdminPaymentsPaymentId } from "../../../../providers/deleteShoppingMallAdminPaymentsPaymentId";

import { IShoppingMallPayment } from "../../../../api/structures/IShoppingMallPayment";
import { IPageIShoppingMallPayment } from "../../../../api/structures/IPageIShoppingMallPayment";

@Controller("/shoppingMall/admin/payments")
export class ShoppingmallAdminPaymentsController {
  /**
   * Create a new payment record for an order.
   *
   * Create a new payment in the shopping mall payment system.
   *
   * This API enables authorized users such as admins or sellers to record a
   * payment transaction associated with a specific order. The payment details
   * include the payment method (e.g., credit card, PayPal), status (e.g.,
   * completed, pending), amount paid, external transaction identifier, and the
   * payment date.
   *
   * Security considerations include validation to ensure the referenced order
   * exists and is active. The external transaction ID must be unique to avoid
   * duplication errors.
   *
   * Timestamps for creation and last update are automatically managed by the
   * system. Soft deletion is supported via a nullable deleted_at timestamp to
   * allow recovery.
   *
   * This operation uses the "shopping_mall_payments" table from the Prisma
   * schema, leveraging all defined fields for data integrity and business
   * logic.
   *
   * Related operations include updating payments via PUT /payments/{paymentId}.
   *
   * @param connection
   * @param body Payment creation payload, containing order linkage and payment
   *   details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPayment.ICreate,
  ): Promise<IShoppingMallPayment> {
    try {
      return await postShoppingMallAdminPayments({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve paginated list of payment records.
   *
   * Retrieve a list of payment transactions with advanced search and filtering
   * capabilities.
   *
   * This operation enables clients to query payment records based on multiple
   * criteria including payment method, payment status, amount ranges, and
   * payment dates. The response includes pagination support to handle large
   * datasets efficiently.
   *
   * Security Considerations: Access to this endpoint should be controlled to
   * prevent exposure of sensitive payment details. Typically, only authorized
   * staff or systems can query payment data.
   *
   * Data Source: Operates on the shopping_mall_payments table containing
   * payment details linked one-to-one to orders. The payment data includes
   * metadata like transaction IDs, payment dates, and statuses.
   *
   * Related Operations: To get details of a specific payment, use GET
   * /payments/{paymentId}.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering payment
   *   records
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPayment.IRequest,
  ): Promise<IPageIShoppingMallPayment.ISummary> {
    try {
      return await patchShoppingMallAdminPayments({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve payment details by paymentId.
   *
   * Retrieve detailed information about a specific payment identified by its
   * paymentId.
   *
   * This operation allows authorized users to view all particulars of a payment
   * record, including method, status, amount, external transaction tracking ID,
   * and creation/modification timestamps.
   *
   * Security: Access to individual payment details must be restricted to
   * authorized roles to protect sensitive financial data.
   *
   * Database Relationship: Each payment is uniquely associated with a shopping
   * order via a one-to-one relation.
   *
   * Related Operations: Use PATCH /payments for searching payments and POST
   * /payments for creation if applicable.
   *
   * @param connection
   * @param paymentId Unique identifier of the target payment record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":paymentId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("paymentId")
    paymentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallPayment> {
    try {
      return await getShoppingMallAdminPaymentsPaymentId({
        admin,
        paymentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing payment record.
   *
   * Update payment details for an existing payment record in the shopping mall
   * payment system.
   *
   * Authorized users such as administrators and sellers can update payment
   * method, status, amount, external transaction ID, and payment date for a
   * specified payment record identified by its unique payment ID.
   *
   * Concurrency and uniqueness checks are performed to ensure data consistency.
   * The related order linkage cannot be changed once set.
   *
   * Timestamps for last update are maintained automatically. This operation
   * supports soft deletion monitoring via the deleted_at field but does not
   * perform deletion itself.
   *
   * It operates on the "shopping_mall_payments" table as defined in the Prisma
   * schema, ensuring all business and validation rules are reflected.
   *
   * Related operations include creating payments via POST /payments.
   *
   * @param connection
   * @param paymentId Unique identifier of the target payment record
   * @param body Payment update payload containing modifiable payment fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":paymentId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("paymentId")
    paymentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallPayment.IUpdate,
  ): Promise<IShoppingMallPayment> {
    try {
      return await putShoppingMallAdminPaymentsPaymentId({
        admin,
        paymentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a specific payment record by paymentId.
   *
   * Permanently deletes an existing payment record by its unique identifier.
   * This API ensures that the payment linked to an order is fully removed from
   * the system, including transaction details and timestamps.
   *
   * Security: This operation requires authenticated users with sufficient
   * privileges to delete payment records. Proper validations ensure that the
   * payment exists and is not referenced elsewhere before deletion.
   *
   * This operation directly manipulates the shopping_mall_payments table,
   * enforcing consistency with the related shopping_mall_orders table via the
   * foreign key shopping_mall_order_id.
   *
   * Clients must specify the exact payment ID to remove the payment. No request
   * body is required for this DELETE operation.
   *
   * Related operations: Creating a payment (POST /payments), retrieving payment
   * details (GET /payments/{paymentId}).
   *
   * @param connection
   * @param paymentId Unique identifier of the payment to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":paymentId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("paymentId")
    paymentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminPaymentsPaymentId({
        admin,
        paymentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
