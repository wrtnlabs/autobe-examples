import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminPayments } from "../../../../providers/patchShoppingMallAdminPayments";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminPaymentsPaymentId } from "../../../../providers/getShoppingMallAdminPaymentsPaymentId";
import { deleteShoppingMallAdminPaymentsId } from "../../../../providers/deleteShoppingMallAdminPaymentsId";

import { IPageIShoppingMallPayment } from "../../../../api/structures/IPageIShoppingMallPayment";
import { IShoppingMallPayment } from "../../../../api/structures/IShoppingMallPayment";

@Controller("/shoppingMall/admin/payments")
export class ShoppingmallAdminPaymentsController {
  /**
   * Retrieve a paginated list of shopping mall payment records.
   *
   * This operation allows authorized users (e.g., admin) to search, filter, and
   * retrieve payment records related to orders placed on the shopping mall
   * platform.
   *
   * Payments contain critical information including payment methods, statuses,
   * amounts, and timestamps. This API supports pagination and sorting to
   * efficiently handle large volumes of payment data.
   *
   * Security considerations include restricting access to authorized actors
   * such as admins to protect sensitive financial transaction data.
   *
   * The operation closely integrates with the shopping_mall_payments Prisma
   * table which tracks payment details linked to orders. The data returned
   * reflects the latest payment status and amount information.
   *
   * Clients can use this endpoint to build payment dashboards, financial
   * reports, and audit logs consistent with business rules and compliance
   * requirements.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   shopping mall payments
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPayment.IRequest,
  ): Promise<IPageIShoppingMallPayment.ISummary> {
    try {
      return await patchShoppingMallAdminPayments({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific payment record.
   *
   * This operation fetches detailed payment information by payment ID from the
   * shopping mall backend system.
   *
   * The payment record includes the payment method used (e.g., credit card,
   * bank transfer), current payment status (e.g., pending, completed, failed),
   * payment amount, and the date/time the payment was made.
   *
   * Access to this endpoint is restricted to admins due to the sensitive
   * financial nature of the data.
   *
   * The operation closely corresponds to the shopping_mall_payments Prisma
   * table and is critical for financial auditing, troubleshooting payment
   * issues, and providing customer support.
   *
   * Path parameter `paymentId` identifies the exact payment record to retrieve.
   *
   * @param connection
   * @param paymentId Unique identifier of the target payment record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":paymentId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("paymentId")
    paymentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallPayment> {
    try {
      return await getShoppingMallAdminPaymentsPaymentId({
        admin,
        paymentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a payment record by its unique identifier.
   *
   * This API endpoint allows authorized actors to permanently delete a payment
   * record specified by its unique identifier (id) in the
   * shopping_mall_payments table. This operation is irreversible and removes
   * all data associated with the payment record from the database.
   *
   * Security is crucial as this operation should only be accessible by actors
   * with sufficient privileges to avoid accidental or malicious removals. Since
   * payments are critical financial data, deletion requires careful control.
   *
   * The path parameter `id` denotes the unique identifier of the payment to be
   * deleted. The operation does not require a request body and does not return
   * a response body upon successful deletion.
   *
   * This operation interacts directly with the shopping_mall_payments table
   * ensuring consistent removal of payment data.
   *
   * @param connection
   * @param id Unique identifier of the payment record to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminPaymentsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
