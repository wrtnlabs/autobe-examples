import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminCustomers } from "../../../../providers/patchShoppingMallAdminCustomers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCustomersCustomerId } from "../../../../providers/getShoppingMallAdminCustomersCustomerId";
import { deleteShoppingMallAdminCustomersCustomerId } from "../../../../providers/deleteShoppingMallAdminCustomersCustomerId";

import { IPageIShoppingMallCustomer } from "../../../../api/structures/IPageIShoppingMallCustomer";
import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";

@Controller("/shoppingMall/admin/customers")
export class ShoppingmallAdminCustomersController {
  /**
   * Search and retrieve a paginated list of shopping mall customers.
   *
   * Retrieve a comprehensive and configurable list of customers from the
   * shopping mall database.
   *
   * This operation supports complex queries to filter customers by various
   * attributes such as registration date, status, and personal details. Sorting
   * and pagination capabilities are provided to handle large datasets
   * effectively.
   *
   * Security: Typically restricted to administrators or authorized personnel,
   * with appropriate authentication and authorization checks in place.
   * Sensitive customer information is protected based on the caller's
   * authorization level.
   *
   * This endpoint serves as a key component for customer management, reporting,
   * and support operations, referencing the shopping_mall_customers table
   * schema and related business logic.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   customers
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCustomer.IRequest,
  ): Promise<IPageIShoppingMallCustomer.ISummary> {
    try {
      return await patchShoppingMallAdminCustomers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed customer information by customerId.
   *
   * Retrieve detailed information about a specific customer from the shopping
   * mall database.
   *
   * This operation returns the full customer record matching the provided
   * unique identifier. It is designed for administrative and support use cases
   * where comprehensive customer details are necessary.
   *
   * Authorization checks ensure only permitted actors, typically admins, can
   * access this sensitive information.
   *
   * This operation interacts with the shopping_mall_customers table and adheres
   * to database constraints and privacy policies.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await getShoppingMallAdminCustomersCustomerId({
        admin,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a customer by UUID.
   *
   * Permanently delete a customer identified by UUID from the shopping mall
   * system.
   *
   * This operation allows administrators to remove customer data completely. It
   * is a destructive operation and should be performed with caution.
   *
   * Security: Only administrators can perform this deletion. Authorization
   * checks must be strictly enforced to prevent unauthorized removals.
   *
   * There is no request body for this operation. On success, no content is
   * returned. Error scenarios include not found or unauthorized access.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":customerId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCustomersCustomerId({
        admin,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
