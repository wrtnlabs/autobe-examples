import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminCustomers } from "../../../../providers/patchShoppingMallAdminCustomers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCustomersId } from "../../../../providers/getShoppingMallAdminCustomersId";
import { deleteShoppingMallAdminCustomersId } from "../../../../providers/deleteShoppingMallAdminCustomersId";

import { IPageIShoppingMallCustomer } from "../../../../api/structures/IPageIShoppingMallCustomer";
import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";

@Controller("/shoppingMall/admin/customers")
export class ShoppingmallAdminCustomersController {
  /**
   * Search and retrieve a filtered, paginated list of shopping mall customers.
   *
   * Retrieve a filtered and paginated list of shopping mall customers from the
   * system. This operation supports advanced search capabilities enabling
   * clients to filter customers by properties such as email domain, nickname,
   * account creation date, and deletion status.
   *
   * The response includes customer summary information optimized for display in
   * user interfaces requiring paginated lists. The operation takes into account
   * unique email constraints and applies indexing on relevant fields for
   * performance.
   *
   * Security and permissions require that only authorized actors (admins) can
   * access this data, as it contains sensitive user information. Data delivery
   * respects soft deletion status, excluding logically deleted customer
   * accounts from results.
   *
   * Typical usage includes administrative management tools, analytics
   * dashboards, or bulk email campaign preparations where a list of customers
   * is required.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for customer
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCustomer.IRequest,
  ): Promise<IPageIShoppingMallCustomer.ISummary> {
    try {
      return await patchShoppingMallAdminCustomers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a shopping mall customer by unique ID.
   *
   * Retrieve detailed information of a single shopping mall customer by its
   * unique identifier. This operation fetches complete record fields including
   * email, password hash, nickname, and timestamps.
   *
   * Security considerations restrict access to admins due to sensitive personal
   * information and authentication data. The operation respects soft deletion,
   * excluding deleted customers unless specifically overridden in queries.
   *
   * The path parameter uses the 'id' field of type UUID, corresponding to the
   * customer's primary key. Validations ensure the format is a proper UUID
   * string.
   *
   * Errors are handled by returning appropriate status codes for not found or
   * unauthorized access.
   *
   * Related operations include listing customers with paging and filtering to
   * complement this detailed retrieval.
   *
   * @param connection
   * @param id Unique identifier of the target customer
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await getShoppingMallAdminCustomersId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a shopping mall customer by ID.
   *
   * Permanently delete a shopping mall customer identified by their UUID id.
   * This is a hard delete removing all related data with cascading.
   *
   * Only authorized admin users may perform this operation.
   *
   * No request body is required.
   *
   * After successful deletion, no content is returned.
   *
   * @param connection
   * @param id Unique identifier of the customer to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async eraseCustomer(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCustomersId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
