import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminSellerProfiles } from "../../../../providers/patchShoppingMallAdminSellerProfiles";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminSellerProfilesId } from "../../../../providers/getShoppingMallAdminSellerProfilesId";
import { deleteShoppingMallAdminSellerProfilesId } from "../../../../providers/deleteShoppingMallAdminSellerProfilesId";

import { IPageIShoppingMallSellerProfile } from "../../../../api/structures/IPageIShoppingMallSellerProfile";
import { IShoppingMallSellerProfile } from "../../../../api/structures/IShoppingMallSellerProfile";

@Controller("/shoppingMall/admin/sellerProfiles")
export class ShoppingmallAdminSellerprofilesController {
  /**
   * Retrieve a paginated list of seller profiles with filtering and pagination
   * support.
   *
   * Retrieve a paginated list of seller profiles registered on the shoppingMall
   * platform. This operation allows authorized users to search and filter
   * seller profiles based on criteria such as store name, contact email, and
   * profile description.
   *
   * The seller profiles represent detailed business information associated with
   * individual sellers, including store name, business registration number, and
   * contact details. The operation ensures data integrity and security by
   * applying appropriate authorization to restrict access.
   *
   * This endpoint is typically used by admins or authorized personnel to manage
   * and view seller information. The filtered list supports pagination for
   * efficient loading and browsing. Error handling ensures graceful degradation
   * when invalid parameters are supplied or if access is denied.
   *
   * This operation corresponds to full access to the
   * shopping_mall_seller_profiles Prisma table.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering seller
   *   profiles
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSellerProfile.IRequest,
  ): Promise<IPageIShoppingMallSellerProfile.ISummary> {
    try {
      return await patchShoppingMallAdminSellerProfiles({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single seller profile by unique ID.
   *
   * Retrieve detailed information for a specific seller profile by ID. This
   * operation returns comprehensive data including store name, business
   * registration number, and contact details.
   *
   * Access is restricted to authorized roles such as admins to protect
   * sensitive seller data.
   *
   * The operation validates the existence of the seller profile and returns
   * appropriate errors if not found. It integrates directly with the
   * shopping_mall_seller_profiles table in Prisma schema.
   *
   * @param connection
   * @param id Unique identifier of the target seller profile
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerProfile> {
    try {
      return await getShoppingMallAdminSellerProfilesId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a seller profile by ID.
   *
   * This DELETE API operation permanently removes a seller profile from the
   * shopping mall platform's database using the unique identifier.
   *
   * The seller profile contains business and contact information associated
   * with a seller account. Deletion of the profile will cascade and remove
   * relevant links.
   *
   * Security considerations include validating that the requester is authorized
   * to delete this seller profile, typically requiring admin or owning seller
   * privileges.
   *
   * Referencing the shopping_mall_seller_profiles Prisma schema, this operation
   * performs a hard delete, removing the entire record permanently and cannot
   * be recovered.
   *
   * No request body is required for this operation since the seller profile ID
   * in the path fully identifies the resource to delete.
   *
   * Successful execution results in no content response, confirming removal.
   *
   * This operation is generally used when a seller account is being closed or
   * cleaned up in the system.
   *
   * @param connection
   * @param id Unique identifier of the seller profile to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async eraseSellerProfile(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminSellerProfilesId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
