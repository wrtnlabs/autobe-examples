import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallAdminShoppingMallPermissions } from "../../../../providers/postShoppingMallAdminShoppingMallPermissions";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminShoppingMallPermissions } from "../../../../providers/patchShoppingMallAdminShoppingMallPermissions";
import { getShoppingMallAdminShoppingMallPermissionsName } from "../../../../providers/getShoppingMallAdminShoppingMallPermissionsName";
import { putShoppingMallAdminShoppingMallPermissionsName } from "../../../../providers/putShoppingMallAdminShoppingMallPermissionsName";
import { deleteShoppingMallAdminShoppingMallPermissionsName } from "../../../../providers/deleteShoppingMallAdminShoppingMallPermissionsName";

import { IShoppingMallPermission } from "../../../../api/structures/IShoppingMallPermission";
import { IPageIShoppingMallPermission } from "../../../../api/structures/IPageIShoppingMallPermission";

@Controller("/shoppingMall/admin/shoppingMallPermissions")
export class ShoppingmallAdminShoppingmallpermissionsController {
  /**
   * Create a new shopping mall permission.
   *
   * Creates a new permission entity within the shopping mall backend system.
   * This permission defines a specific access right that can be assigned to
   * users or roles.
   *
   * The operation requires the unique permission `name`, a display `label`, and
   * optionally a comprehensive `description` to explain the permission's
   * purpose.
   *
   * Security and validation ensure that permission names are unique and conform
   * to naming conventions.
   *
   * On success, the newly created permission object is returned.
   *
   * Use this API to manage granular access control policies dynamically within
   * the platform.
   *
   * @param connection
   * @param body The permission information to create
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPermission.ICreate,
  ): Promise<IShoppingMallPermission> {
    try {
      return await postShoppingMallAdminShoppingMallPermissions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated list of shopping mall permissions.
   *
   * Retrieve a filtered and paginated list of shopping mall permissions from
   * the system. The permissions define what actions administrators can perform
   * within the shopping mall platform.
   *
   * This supports efficient permission management, allowing administrators to
   * find specific permissions based on name, label, or description.
   *
   * Security considerations: Access restricted to authorized administrative
   * users only.
   *
   * Related operations include creating permissions, updating roles, and
   * managing user role assignments.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for permission
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPermission.IRequest,
  ): Promise<IPageIShoppingMallPermission.ISummary> {
    try {
      return await patchShoppingMallAdminShoppingMallPermissions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a shopping mall permission by its unique name.
   *
   * This operation allows clients to fetch detailed information about a
   * specific shopping mall permission identified by its unique name.
   *
   * The response includes the permission's unique internal name, its
   * human-readable label, and an optional detailed description explaining its
   * scope and usage within the shopping platform.
   *
   * Security: Access to this endpoint should be carefully controlled, usually
   * allowing only administrative or authorization service actors to ensure
   * permission data integrity.
   *
   * Parameters:
   *
   * - `name`: The unique permission identifier used internally in the system.
   *
   * This operation is fundamental for implementing fine-grained access controls
   * and is typically used in conjunction with role or user permission
   * assignment APIs.
   *
   * @param connection
   * @param name Unique permission identifier name of the target shopping mall
   *   permission (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":name")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("name")
    name: string,
  ): Promise<IShoppingMallPermission> {
    try {
      return await getShoppingMallAdminShoppingMallPermissionsName({
        admin,
        name,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a shopping mall permission by unique name.
   *
   * Update a specific shopping mall permission, identified by its unique
   * 'name'. The operation allows changing the label and detailed description of
   * the permission to reflect changes in access control policies.
   *
   * Only administrators have permissions to execute this operation to maintain
   * security and consistency of access rights across the platform.
   *
   * The response returns the updated permission entity with all details after
   * modification.
   *
   * Related operations include deleting permissions via DELETE method on the
   * same path to remove obsolete entries.
   *
   * @param connection
   * @param name Unique permission identifier for internal use
   * @param body Updated permission information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":name")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("name")
    name: string,
    @TypedBody()
    body: IShoppingMallPermission.ICreate,
  ): Promise<IShoppingMallPermission> {
    try {
      return await putShoppingMallAdminShoppingMallPermissionsName({
        admin,
        name,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a shopping mall permission by unique name.
   *
   * Delete a specific shopping mall permission by its unique name.
   *
   * This operation permanently removes the permission entry from the database
   * and revokes its availability for role or user assignment.
   *
   * Only administrators are authorized to execute this operation to protect
   * system security.
   *
   * The deletion is irreversible and requires caution due to its potential
   * impact on access policies.
   *
   * @param connection
   * @param name Unique permission identifier for internal use
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":name")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("name")
    name: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminShoppingMallPermissionsName({
        admin,
        name,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
