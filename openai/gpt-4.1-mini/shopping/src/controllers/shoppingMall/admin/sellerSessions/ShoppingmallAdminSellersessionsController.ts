import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminSellerSessions } from "../../../../providers/patchShoppingMallAdminSellerSessions";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminSellerSessionsId } from "../../../../providers/getShoppingMallAdminSellerSessionsId";

import { IPageIShoppingMallSellerSession } from "../../../../api/structures/IPageIShoppingMallSellerSession";
import { IShoppingMallSellerSession } from "../../../../api/structures/IShoppingMallSellerSession";

@Controller("/shoppingMall/admin/sellerSessions")
export class ShoppingmallAdminSellersessionsController {
  /**
   * Search and retrieve filtered, paginated seller sessions.
   *
   * Retrieve a filtered and paginated list of seller sessions.
   *
   * This operation supports searching seller sessions by various properties
   * such as seller ID, IP, URL href, referrer, and timestamps.
   *
   * Pagination and sorting parameters can be provided in the request body for
   * flexible querying.
   *
   * The response includes summarized seller session data optimized for listing.
   *
   * Security considerations include restricting access to authorized
   * administrative users to prevent sensitive session data exposure.
   *
   * Errors related to invalid query parameters or unauthorized access will be
   * returned accordingly.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for seller sessions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSellerSession.IRequest,
  ): Promise<IPageIShoppingMallSellerSession.ISummary> {
    try {
      return await patchShoppingMallAdminSellerSessions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve seller session information by ID.
   *
   * Retrieve detailed information about a seller's authentication session using
   * its unique ID. This operation is essential for managing and auditing seller
   * login sessions on the platform.
   *
   * Security considerations: This endpoint requires appropriate authentication
   * and authorization ensuring only authorized actors can access seller session
   * information. Typically used by admin users or security services.
   *
   * This operation is directly related to the shopping_mall_seller_sessions
   * table which stores all session details for seller users. It provides
   * visibility into session details such as IP addresses, URLs, and
   * timestamps.
   *
   * No request body is needed as it fetches data based on the path parameter.
   *
   * Typical usage includes session monitoring, security auditing, and user
   * session management. The system will respond with a 404 if the session ID
   * does not exist.
   *
   * @param connection
   * @param id Unique identifier of the seller session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerSession> {
    try {
      return await getShoppingMallAdminSellerSessionsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
