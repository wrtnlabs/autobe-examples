import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallAdminShoppingMallCustomers } from "../../../../providers/patchShoppingMallAdminShoppingMallCustomers";
