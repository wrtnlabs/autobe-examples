import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminStockAdjustments } from "../../../../providers/postShoppingMallAdminStockAdjustments";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminStockAdjustments } from "../../../../providers/patchShoppingMallAdminStockAdjustments";
import { getShoppingMallAdminStockAdjustmentsId } from "../../../../providers/getShoppingMallAdminStockAdjustmentsId";
import { putShoppingMallAdminStockAdjustmentsId } from "../../../../providers/putShoppingMallAdminStockAdjustmentsId";
import { deleteShoppingMallAdminStockAdjustmentsId } from "../../../../providers/deleteShoppingMallAdminStockAdjustmentsId";

import { IShoppingMallStockAdjustment } from "../../../../api/structures/IShoppingMallStockAdjustment";
import { IPageIShoppingMallStockAdjustment } from "../../../../api/structures/IPageIShoppingMallStockAdjustment";

@Controller("/shoppingMall/admin/stockAdjustments")
export class ShoppingmallAdminStockadjustmentsController {
  /**
   * Create a new SKU stock adjustment record.
   *
   * Creates a new inventory stock adjustment record to track additions,
   * subtractions, reservations, or releases of SKU stock. The adjustment
   * captures the quantity changed, the actor type (customer, seller, admin),
   * and actor ID to maintain an audit trail. This operation ensures inventory
   * consistency by validating that the SKU exists and the adjustment type is
   * valid. It supports operational integrity by logging stock movements caused
   * by different actors.
   *
   * Security considerations include authenticating the actor and restricting
   * adjustment types. The operation is pivotal for accurate inventory
   * management and prevents overselling or stock miscalculations.
   *
   * This manipulates the shopping_mall_stock_adjustments table according to the
   * Prisma schema, storing all relevant adjustment details for SKU inventory
   * management.
   *
   * @param connection
   * @param body Information about the stock adjustment to be created
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallStockAdjustment.ICreate,
  ): Promise<IShoppingMallStockAdjustment> {
    try {
      return await postShoppingMallAdminStockAdjustments({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve paginated stock adjustment records for product SKUs.
   *
   * Retrieve a paginated list of inventory stock adjustments applied to product
   * SKUs within the shopping mall platform. These records document quantity
   * changes resulting from stock additions, subtractions, reservations for
   * orders, and releases of reserved stock.
   *
   * The operation enables clients to perform advanced filtering and searching
   * by SKU, adjustment type, actor type, and other criteria, alongside sorting
   * and pagination.
   *
   * Security considerations require that only authorized roles such as admins,
   * sellers, or system components with inventory management permissions can
   * access these records due to sensitivity.
   *
   * This operation interacts with the shopping_mall_stock_adjustments table in
   * the Prisma schema.
   *
   * The system records the actor responsible for each adjustment (customer,
   * seller, or admin) along with precise adjustments quantities and timestamps.
   * This functionality is key to maintaining inventory accuracy and
   * traceability across the platform.
   *
   * Errors such as invalid filters or unauthorized access are handled
   * gracefully with appropriate HTTP status codes and error messages.
   *
   * @param connection
   * @param body Filtering and pagination parameters for stock adjustments
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallStockAdjustment.IRequest,
  ): Promise<IPageIShoppingMallStockAdjustment.ISummary> {
    try {
      return await patchShoppingMallAdminStockAdjustments({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific stock adjustment record by its ID.
   *
   * Retrieve full details of a stock adjustment by its unique identifier. The
   * record includes the SKU affected, adjustment type (addition, subtraction,
   * reservation, or release), quantity change, actor type (customer, seller,
   * admin), actor ID who made the adjustment, and timestamp.
   *
   * Only authorized users such as admins and sellers may access this detailed
   * information.
   *
   * Errors for non-existent IDs or unauthorized access are managed with
   * standard HTTP error responses.
   *
   * @param connection
   * @param id Unique identifier of the stock adjustment record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallStockAdjustment> {
    try {
      return await getShoppingMallAdminStockAdjustmentsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing SKU stock adjustment record.
   *
   * Updates an existing stock adjustment record by ID. Allows correction or
   * update of adjustment details such as type, quantity, and actor information.
   * Ensures robust audit trail and inventory consistency. This operation acts
   * on shopping_mall_stock_adjustments table in Prisma schema.
   *
   * Security requires authentication of the updating actor and appropriate
   * authorization to modify stock data. Invalid updates resulting in
   * inconsistent inventory states must be rejected by the backend business
   * logic.
   *
   * This PATCH operation supports maintenance and error correction in stock
   * management workflows.
   *
   * @param connection
   * @param id Unique identifier of the stock adjustment record to update
   * @param body Updated stock adjustment information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallStockAdjustment.IUpdate,
  ): Promise<IShoppingMallStockAdjustment> {
    try {
      return await putShoppingMallAdminStockAdjustmentsId({
        admin,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a shopping mall stock adjustment by ID.
   *
   * This DELETE operation removes an existing shopping mall stock adjustment
   * record from the database. It requires the stock adjustment's unique
   * identifier as the path parameter. Only admin users are authorized to
   * perform this deletion, reflecting the need to tightly control modification
   * of critical inventory audit records.
   *
   * The operation performs a permanent, hard delete as the stock adjustments
   * schema does not have soft delete columns. There is no request body or
   * response body data. The operation returns a 204 No Content status upon
   * successful processing.
   *
   * There are no further dependencies for this endpoint, but it should be used
   * with caution due to the audit importance of stock adjustment data.
   *
   * @param connection
   * @param id Unique identifier of the stock adjustment to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async eraseStockAdjustment(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminStockAdjustmentsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
