import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminReviewModerationQueues } from "../../../../providers/patchShoppingMallAdminReviewModerationQueues";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminReviewModerationQueuesId } from "../../../../providers/getShoppingMallAdminReviewModerationQueuesId";

import { IPageIShoppingMallReviewModerationQueue } from "../../../../api/structures/IPageIShoppingMallReviewModerationQueue";
import { IShoppingMallReviewModerationQueue } from "../../../../api/structures/IShoppingMallReviewModerationQueue";

@Controller("/shoppingMall/admin/reviewModerationQueues")
export class ShoppingmallAdminReviewmoderationqueuesController {
  /**
   * Search and retrieve product review moderation queue entries with filtering
   * and pagination.
   *
   * Retrieve a filtered and paginated list of product review moderation queue
   * entries. The shopping_mall_review_moderation_queues table contains reviews
   * flagged for manual moderation or requiring admin attention.
   *
   * This operation supports advanced filtering by status, flagged reasons,
   * moderator notes, and similar fields, alongside pagination and sorting to
   * efficiently manage large volumes of queued reviews.
   *
   * Security requires this endpoint to be accessible only by authorized roles
   * such as 'admin' to prevent unauthorized access to sensitive review
   * content.
   *
   * The request body carries the search parameters, specifying filters and
   * pagination options.
   *
   * The response returns a paginated summary list of moderation queue entries
   * matching the search criteria.
   *
   * Related operations include reviewing and updating moderation queue entries,
   * creating reviews, and managing product reviews.
   *
   * This operation enables admin users to review, approve, or reject flagged
   * reviews systematically.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering review
   *   moderation queues
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallReviewModerationQueue.IRequest,
  ): Promise<IPageIShoppingMallReviewModerationQueue.ISummary> {
    try {
      return await patchShoppingMallAdminReviewModerationQueues({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a review moderation queue entry by ID from
   * shopping_mall_review_moderation_queues.
   *
   * Retrieve a review moderation queue entry by its unique ID from the shopping
   * mall platform. This endpoint is designed for administrative users
   * responsible for moderating flagged product reviews. The moderation queue
   * contains reviews that have been flagged for potential content issues or
   * require manual evaluation before approving or rejecting their public
   * display.
   *
   * This operation securely accesses the shopping_mall_review_moderation_queues
   * table, ensuring only authorized actors can view sensitive moderation data
   * including flagged reasons, moderator notes, and current status.
   *
   * The review moderation entry includes timestamps for creation and updates,
   * supporting audit trails. Failed or unauthorized access attempts are handled
   * gracefully with appropriate error codes.
   *
   * This operation complements review CRUD APIs by enabling moderation
   * workflows in the admin dashboard, forming an essential part of the product
   * quality control process.
   *
   * Expected input is a UUID path parameter identifying the specific moderation
   * queue entry.
   *
   * @param connection
   * @param id Unique identifier of the target review moderation queue entry
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReviewModerationQueue> {
    try {
      return await getShoppingMallAdminReviewModerationQueuesId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
