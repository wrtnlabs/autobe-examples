import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteShoppingMallAdminFaqsId } from "../../../../providers/deleteShoppingMallAdminFaqsId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

@Controller("/shoppingMall/admin/faqs/:id")
export class ShoppingmallAdminFaqsController {
  /**
   * Delete a FAQ entry by its unique identifier (admin only).
   *
   * Permanently removes the FAQ entry identified by the specified unique
   * identifier from the shopping mall platform's FAQ system.
   *
   * This operation is intended solely for administrators who manage the FAQ
   * content. Deletion is irreversible and permanently removes the data from the
   * system.
   *
   * Security considerations include strict authorization to prevent
   * unauthorized deletion attempts. The endpoint ensures the caller is
   * authenticated and has appropriate admin privileges.
   *
   * Refer to the Prisma schema for shopping_mall_faqs for detailed data
   * structure and constraints.
   *
   * @param connection
   * @param id Unique identifier of the target FAQ entry
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminFaqsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
