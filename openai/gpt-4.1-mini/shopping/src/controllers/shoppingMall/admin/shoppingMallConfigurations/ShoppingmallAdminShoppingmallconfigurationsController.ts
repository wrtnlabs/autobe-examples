import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallAdminShoppingMallConfigurations } from "../../../../providers/postShoppingMallAdminShoppingMallConfigurations";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminShoppingMallConfigurations } from "../../../../providers/patchShoppingMallAdminShoppingMallConfigurations";
import { putShoppingMallAdminShoppingMallConfigurationsKey } from "../../../../providers/putShoppingMallAdminShoppingMallConfigurationsKey";
import { deleteShoppingMallAdminShoppingMallConfigurationsKey } from "../../../../providers/deleteShoppingMallAdminShoppingMallConfigurationsKey";

import { IShoppingMallConfiguration } from "../../../../api/structures/IShoppingMallConfiguration";
import { IPageIShoppingMallConfiguration } from "../../../../api/structures/IPageIShoppingMallConfiguration";

@Controller("/shoppingMall/admin/shoppingMallConfigurations")
export class ShoppingmallAdminShoppingmallconfigurationsController {
  /**
   * Create a new shopping mall configuration.
   *
   * Create a new configuration entry in the shopping mall system.
   *
   * This operation stores a new key-value pair into the
   * shopping_mall_configurations table, allowing the dynamic addition of system
   * settings.
   *
   * Only users with administrative privileges or authorized roles may perform
   * this operation to prevent unauthorized configuration changes.
   *
   * The created configuration is immediately effective and can be retrieved
   * using the key-based lookup operation.
   *
   * Validation is performed to ensure the uniqueness of the key and correctness
   * of stored values.
   *
   * Related operations: Retrieve configuration by key (GET
   * /shoppingMallConfigurations/{key}).
   *
   * @param connection
   * @param body Payload to create a new shopping mall configuration entry
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallConfiguration.ICreate,
  ): Promise<IShoppingMallConfiguration> {
    try {
      return await postShoppingMallAdminShoppingMallConfigurations({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve filtered, paginated shopping mall configurations.
   *
   * Retrieve a list of shopping mall system configurations with optional
   * filters. This operation supports pagination, sorting, and keyword searching
   * to efficiently browse configuration settings.
   *
   * The configurations represent key-value pairs used for system-wide settings
   * and preferences. Only authorized administrative users can access this
   * endpoint to prevent unauthorized modifications or disclosure of sensitive
   * platform configurations.
   *
   * The response includes paginated summaries of configuration entries,
   * allowing clients to browse large sets of configuration data smoothly. No
   * request body is needed since this is a search operation using PATCH
   * semantics to support complex queries.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for shopping mall
   *   configurations
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallConfiguration.IRequest,
  ): Promise<IPageIShoppingMallConfiguration.ISummary> {
    try {
      return await patchShoppingMallAdminShoppingMallConfigurations({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update configuration value identified by key.
   *
   * Update the configuration value associated with a specific configuration key
   * in the shopping mall system.
   *
   * This operation allows authenticated users with appropriate permissions to
   * modify system configuration settings. Each configuration setting is
   * identified by a unique key. The update request includes the new value for
   * the configuration.
   *
   * Security considerations include ensuring only authorized actors can modify
   * system configurations to maintain system integrity and prevent unauthorized
   * changes. The operation validates the existence of the key before applying
   * updates.
   *
   * This operation interfaces directly with the ShoppingMallConfigurations
   * Prisma model, ensuring the updated value is consistent with database
   * constraints and business rules.
   *
   * @param connection
   * @param key Unique key identifying the configuration setting within the
   *   shopping mall system
   * @param body Update payload containing the new configuration value
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":key")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("key")
    key: string,
    @TypedBody()
    body: IShoppingMallConfiguration.IUpdate,
  ): Promise<IShoppingMallConfiguration> {
    try {
      return await putShoppingMallAdminShoppingMallConfigurationsKey({
        admin,
        key,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete configuration identified by key.
   *
   * Delete the configuration entry specified by the unique key from the
   * system's configuration store.
   *
   * This operation permits authenticated administrative users to permanently
   * remove a configuration setting. Deletion is a hard delete; the
   * configuration record is removed entirely from the database and cannot be
   * recovered.
   *
   * Security controls ensure only admins can perform this operation due to its
   * critical impact on system behavior. The operation validates the existence
   * of the specified configuration key before deletion.
   *
   * This operation interacts with the ShoppingMallConfigurations Prisma schema
   * for precise and consistent removal of configuration data.
   *
   * @param connection
   * @param key Unique key identifying the configuration setting within the
   *   shopping mall system
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":key")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("key")
    key: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminShoppingMallConfigurationsKey({
        admin,
        key,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
