import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallAdminShoppingMallProductCategories } from "../../../../providers/postShoppingMallAdminShoppingMallProductCategories";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminShoppingMallProductCategoriesCategoryCode } from "../../../../providers/putShoppingMallAdminShoppingMallProductCategoriesCategoryCode";
import { deleteShoppingMallAdminShoppingMallProductCategoriesCategoryCode } from "../../../../providers/deleteShoppingMallAdminShoppingMallProductCategoriesCategoryCode";

import { IShoppingMallProductCategory } from "../../../../api/structures/IShoppingMallProductCategory";

@Controller("/shoppingMall/admin/shoppingMallProductCategories")
export class ShoppingmallAdminShoppingmallproductcategoriesController {
  /**
   * Create a new shopping mall product category.
   *
   * Create a new product category in the shopping mall platform.
   *
   * This operation allows authorized users to add a product category which
   * helps organize and classify products. Each category must have a unique code
   * and a name.
   *
   * Categories can be hierarchical; here the creation assumes a top-level
   * category without a parent. Parent categories can be assigned later.
   *
   * Security: Only authenticated admin users should be able to create
   * categories.
   *
   * Related operations: Update category (PUT
   * /shoppingMallProductCategories/{categoryCode}), List categories (GET
   * /shoppingMallProductCategories).
   *
   * @param connection
   * @param body Data needed to create a shopping mall product category
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallProductCategory.ICreate,
  ): Promise<IShoppingMallProductCategory> {
    try {
      return await postShoppingMallAdminShoppingMallProductCategories({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shopping mall product category.
   *
   * Update an existing product category by its unique code.
   *
   * Authorized admin users can modify the category's name and description, and
   * can soft-delete the category by setting deleted_at.
   *
   * The category code itself is immutable and used as the unique identifier in
   * the path.
   *
   * Proper validation is performed to ensure the category exists before update.
   *
   * Related operations: Create category (POST /shoppingMallProductCategories),
   * List categories (GET /shoppingMallProductCategories).
   *
   * @param connection
   * @param categoryCode Unique business identifier code of the target product
   *   category (global scope)
   * @param body Update data for the shopping mall product category
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryCode")
    categoryCode: string,
    @TypedBody()
    body: IShoppingMallProductCategory.IUpdate,
  ): Promise<IShoppingMallProductCategory> {
    try {
      return await putShoppingMallAdminShoppingMallProductCategoriesCategoryCode(
        {
          admin,
          categoryCode,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a shopping mall product category by code.
   *
   * Permanently deletes a product category in the shopping mall by its unique
   * code.
   *
   * This operation allows authorized administrators to remove a product
   * category identified by its globally unique code. Deleting a category
   * affects all products classified under it and may require careful management
   * to avoid orphaned products.
   *
   * Security: Only users with administrative privileges should access this
   * endpoint. The request validates the category code's existence before
   * deletion to prevent errors.
   *
   * Upon successful deletion, the category is completely removed from the
   * database and cannot be recovered. This endpoint supports maintaining an
   * accurate and up-to-date product catalog structure.
   *
   * @param connection
   * @param categoryCode Unique business identifier code of the target product
   *   category (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryCode")
    categoryCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminShoppingMallProductCategoriesCategoryCode(
        {
          admin,
          categoryCode,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
