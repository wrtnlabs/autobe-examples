import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminShoppingMallSellers } from "../../../../providers/postShoppingMallAdminShoppingMallSellers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminShoppingMallSellers } from "../../../../providers/patchShoppingMallAdminShoppingMallSellers";
import { getShoppingMallAdminShoppingMallSellersShoppingMallSellerId } from "../../../../providers/getShoppingMallAdminShoppingMallSellersShoppingMallSellerId";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { IPageIShoppingMallSeller } from "../../../../api/structures/IPageIShoppingMallSeller";

@Controller("/shoppingMall/admin/shoppingMallSellers")
export class ShoppingmallAdminShoppingmallsellersController {
  /**
   * Create a new shopping mall seller registration.
   *
   * Create a new shopping mall seller with provided registration details.
   *
   * This operation allows the system or administrators to register new sellers
   * who can then manage product listings and fulfill orders in the shopping
   * mall.
   *
   * The provided email must be unique, and password hash must be securely
   * generated before submission.
   *
   * Upon success, the newly registered seller's full details are returned.
   *
   * Security: Access to this endpoint requires administrator privileges to
   * prevent unauthorized registrations.
   *
   * Related operations: GET /shoppingMallSellers/{shoppingMallSellerId}
   * retrieves individual seller details.
   *
   * @param connection
   * @param body Shopping mall seller creation data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSeller.ICreate,
  ): Promise<IShoppingMallSeller> {
    try {
      return await postShoppingMallAdminShoppingMallSellers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * List and search shopping mall sellers with pagination.
   *
   * Retrieve a filtered and paginated list of registered shopping mall seller
   * users.
   *
   * This operation supports complex search criteria including seller
   * attributes, login email, and creation dates.
   *
   * Security: Restricted to authorized administrative users to manage sellers.
   *
   * Response includes seller summaries optimized for list display.
   *
   * Related operations: Create seller (POST /shoppingMallSellers), update
   * seller (PUT /shoppingMallSellers/{id}), delete seller (DELETE
   * /shoppingMallSellers/{id}).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering seller
   *   users
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSeller.IRequest,
  ): Promise<IPageIShoppingMallSeller.ISummary> {
    try {
      return await patchShoppingMallAdminShoppingMallSellers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific shopping mall seller by ID.
   *
   * Retrieve the full details of a registered shopping mall seller using their
   * unique seller ID.
   *
   * This operation returns information needed for seller management in the
   * shopping mall platform. The seller data includes email, password hash
   * (usually omitted in responses for security), and record timestamps.
   *
   * Security: Access to this endpoint requires proper authentication and
   * authorization to protect sensitive seller credentials and personal data.
   *
   * Related operations: Use the POST /shoppingMallSellers to create new seller
   * registrations.
   *
   * @param connection
   * @param shoppingMallSellerId Unique identifier of the target shopping mall
   *   seller (UUID)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shoppingMallSellerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shoppingMallSellerId")
    shoppingMallSellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSeller> {
    try {
      return await getShoppingMallAdminShoppingMallSellersShoppingMallSellerId({
        admin,
        shoppingMallSellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
