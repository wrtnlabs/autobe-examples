import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteShoppingMallAdminGuestsGuestId } from "../../../../providers/deleteShoppingMallAdminGuestsGuestId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

@Controller("/shoppingMall/admin/guests/:guestId")
export class ShoppingmallAdminGuestsController {
  /**
   * Delete a guest user by guestId.
   *
   * Delete a guest user identified by guestId from the shopping mall platform.
   *
   * This operation performs a permanent deletion of the guest record and all
   * related session data.
   *
   * Only administrators have permission to delete guest users.
   *
   * The guest data will be removed irreversibly for privacy compliance and data
   * hygiene.
   *
   * @param connection
   * @param guestId Unique identifier of the target guest user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminGuestsGuestId({
        admin,
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
