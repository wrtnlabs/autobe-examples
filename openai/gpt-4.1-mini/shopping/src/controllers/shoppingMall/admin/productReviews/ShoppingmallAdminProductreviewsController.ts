import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminProductReviews } from "../../../../providers/patchShoppingMallAdminProductReviews";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminProductReviewsId } from "../../../../providers/getShoppingMallAdminProductReviewsId";
import { putShoppingMallAdminProductReviewsId } from "../../../../providers/putShoppingMallAdminProductReviewsId";
import { deleteShoppingMallAdminProductReviewsId } from "../../../../providers/deleteShoppingMallAdminProductReviewsId";

import { IPageIShoppingMallProductReview } from "../../../../api/structures/IPageIShoppingMallProductReview";
import { IShoppingMallProductReview } from "../../../../api/structures/IShoppingMallProductReview";

@Controller("/shoppingMall/admin/productReviews")
export class ShoppingmallAdminProductreviewsController {
  /**
   * Search and retrieve a filtered, paginated list of shopping mall product
   * reviews.
   *
   * Retrieve a filtered and paginated list of product reviews from the system.
   * This operation provides the capability to search and filter reviews based
   * on product SKU, customer ID, order ID, rating, and moderation status.
   *
   * The shopping_mall_product_reviews table stores customer-submitted ratings
   * and textual feedback associated with specific product SKUs. Reviews are
   * linked to both customer and order entities to verify purchase status.
   *
   * Search results return only approved reviews by default, with options to
   * include pending or rejected reviews for admin-level querying. The response
   * returns summary information optimized for list display, including rating
   * and a snippet of review text.
   *
   * Security considerations: This endpoint is restricted to users with admin
   * roles due to the sensitive nature of review content and moderation status.
   * Customers can access their own reviews through separate endpoints.
   *
   * The operation follows PATCH method semantics to support complex querying
   * and pagination scenarios.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering product
   *   review records
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallProductReview.IRequest,
  ): Promise<IPageIShoppingMallProductReview.ISummary> {
    try {
      return await patchShoppingMallAdminProductReviews({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed product review information by ID.
   *
   * Retrieve detailed information for a specific product review by its unique
   * identifier.
   *
   * This operation returns full review data including rating, textual content,
   * moderation status, and links to the associated product SKU, customer, and
   * order entities.
   *
   * Security considerations include ensuring only authorized users
   * (specifically admins) can view any review details, given the sensitive
   * moderation information present.
   *
   * Errors for missing or invalid IDs will be handled gracefully with
   * appropriate HTTP error responses.
   *
   * This operation uses the GET method and includes the review ID as a path
   * parameter.
   *
   * @param connection
   * @param id Unique identifier of the target product review
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductReview> {
    try {
      return await getShoppingMallAdminProductReviewsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a product review's rating, content, or moderation status by ID.
   *
   * Update an existing product review by its unique ID. Allows modification of
   * the rating, review content, and moderation status. This operation is
   * primarily intended for administrators or moderators to manage review
   * content and approval status.
   *
   * Security constraints prevent unauthorized users from modifying reviews they
   * do not own. The operation will validate that all changes comply with input
   * constraints such as rating range and allowed moderation states.
   *
   * This operation directly affects the shopping_mall_product_reviews table and
   * enforces robust authorization checks to maintain data integrity and
   * trustworthiness of product reviews.
   *
   * On success, the updated review data is returned, reflecting all changes
   * including timestamps.
   *
   * @param connection
   * @param id Unique identifier of the product review to update
   * @param body Product review update details including rating, review body,
   *   and moderation status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductReview.IUpdate,
  ): Promise<IShoppingMallProductReview> {
    try {
      return await putShoppingMallAdminProductReviewsId({
        admin,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a product review by its unique ID.
   *
   * This DELETE operation permanently removes a product review from the
   * platform's database. The shopping_mall_product_reviews table contains
   * customer-submitted reviews linked to specific product SKUs, customers, and
   * orders.
   *
   * The operation requires the unique identifier (UUID) of the target review to
   * locate and delete the record. This action is irreversible, resulting in the
   * permanent removal of the review and all associated data.
   *
   * Security considerations mandate this endpoint be accessible only by
   * authorized users such as admins, sellers, or the customer who created the
   * review, ensuring review deletion is managed properly.
   *
   * No request body is needed for this delete operation.
   *
   * No response body or confirmation message is returned; success is implied by
   * HTTP 204 status.
   *
   * Related operations include reviewing moderation queue management and review
   * creation.
   *
   * Be aware that this is a hard delete operation, deleting data completely
   * from the database.
   *
   * @param connection
   * @param id Unique UUID identifier of the product review to remove.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminProductReviewsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
