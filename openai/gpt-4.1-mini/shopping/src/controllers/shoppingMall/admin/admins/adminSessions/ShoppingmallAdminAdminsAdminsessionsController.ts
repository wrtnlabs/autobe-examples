import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminAdminsAdminIdAdminSessions } from "../../../../../providers/postShoppingMallAdminAdminsAdminIdAdminSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminAdminsAdminIdAdminSessions } from "../../../../../providers/patchShoppingMallAdminAdminsAdminIdAdminSessions";
import { getShoppingMallAdminAdminsAdminIdAdminSessionsAdminSessionId } from "../../../../../providers/getShoppingMallAdminAdminsAdminIdAdminSessionsAdminSessionId";
import { putShoppingMallAdminAdminsAdminIdAdminSessionsAdminSessionId } from "../../../../../providers/putShoppingMallAdminAdminsAdminIdAdminSessionsAdminSessionId";
import { deleteShoppingMallAdminAdminsAdminIdAdminSessionsAdminSessionId } from "../../../../../providers/deleteShoppingMallAdminAdminsAdminIdAdminSessionsAdminSessionId";

import { IShoppingMallAdminSession } from "../../../../../api/structures/IShoppingMallAdminSession";
import { IPageIShoppingMallAdminSession } from "../../../../../api/structures/IPageIShoppingMallAdminSession";

@Controller("/shoppingMall/admin/admins/:adminId/adminSessions")
export class ShoppingmallAdminAdminsAdminsessionsController {
  /**
   * Create a new admin session for an admin user.
   *
   * Create a new admin session for the specified admin.
   *
   * This operation enables secure creation of session records when
   * administrators log in. It records critical session data such as session
   * tokens and login timestamps.
   *
   * Security considerations ensure that only authorized admins or system
   * components can establish new sessions. The adminId path parameter ties the
   * session record to a specific administrator.
   *
   * Related operations: Retrieve specific admin session (GET
   * /admins/{adminId}/adminSessions/{adminSessionId}).
   *
   * @param connection
   * @param adminId Unique identifier of the target admin user
   * @param body Admin session creation payload
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdminSession.ICreate,
  ): Promise<IShoppingMallAdminSession> {
    try {
      return await postShoppingMallAdminAdminsAdminIdAdminSessions({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * List active sessions of a specific admin user.
   *
   * Retrieve a list of all active sessions belonging to a specified admin user.
   *
   * This information helps administrators monitor logged-in sessions across
   * devices.
   *
   * Access is limited to users with administrative privileges to protect
   * sensitive session data.
   *
   * Pagination and filtering options are available to manage large numbers of
   * sessions effectively.
   *
   * This operation integrates with the shopping_mall_admin_sessions table
   * filtered by adminId, reflecting real-time active session information for
   * the targeted admin user.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IPageIShoppingMallAdminSession.ISummary> {
    try {
      return await patchShoppingMallAdminAdminsAdminIdAdminSessions({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get a specific admin session by adminId and adminSessionId.
   *
   * Retrieve detailed information about a specific admin session tied to a
   * specified administrator.
   *
   * This operation serves administrative users to audit and monitor session
   * activity for security and management. It fetches session metadata including
   * login timestamp, IP address, and session duration.
   *
   * Security considerations include strict access control ensuring only
   * authorized administrators can access sensitive session records. The session
   * data conforms to the definitions in the shopping_mall_admin_sessions Prisma
   * table.
   *
   * Related operations: Creating new admin sessions (POST
   * /admins/{adminId}/adminSessions).
   *
   * @param connection
   * @param adminId Unique identifier of the target admin user
   * @param adminSessionId Unique identifier of the admin session record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminSessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("adminSessionId")
    adminSessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdminSession> {
    try {
      return await getShoppingMallAdminAdminsAdminIdAdminSessionsAdminSessionId(
        {
          admin,
          adminId,
          adminSessionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an adminSession record for a specific admin.
   *
   * Update an existing adminSession record for the specified admin.
   *
   * This operation allows administrators to modify the details of their active
   * sessions. Parameters include session expiration and status fields, enabling
   * secure management of administrative access sessions.
   *
   * Security: Access is restricted to admin actors to protect session
   * integrity. The adminId and adminSessionId act as unique identifiers for the
   * session to be updated.
   *
   * The operation utilizes the shopping_mall_admin_sessions Prisma table,
   * ensuring that all updates adhere to the database schema validation and
   * constraints.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin
   * @param adminSessionId Unique identifier of the target admin session
   * @param body Data payload for updating the adminSession
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminSessionId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("adminSessionId")
    adminSessionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdminSession.IUpdate,
  ): Promise<IShoppingMallAdminSession> {
    try {
      return await putShoppingMallAdminAdminsAdminIdAdminSessionsAdminSessionId(
        {
          admin,
          adminId,
          adminSessionId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an adminSession record for a specific admin.
   *
   * Permanently remove an adminSession for a specified admin.
   *
   * This operation deletes the targeted session record from the database,
   * freeing up resources and enhancing security by removing stale or
   * unauthorized administrative sessions.
   *
   * Security: Restricted to admin actors to prevent unauthorized session
   * deletion, maintaining high security standards.
   *
   * The operation works on the shopping_mall_admin_sessions Prisma table,
   * enforcing schema-level constraints to ensure valid deletion targets.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin
   * @param adminSessionId Unique identifier of the target admin session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminSessionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("adminSessionId")
    adminSessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminAdminsAdminIdAdminSessionsAdminSessionId(
        {
          admin,
          adminId,
          adminSessionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
