import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminAdmins } from "../../../../providers/patchShoppingMallAdminAdmins";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminAdminsId } from "../../../../providers/getShoppingMallAdminAdminsId";
import { putShoppingMallAdminAdminsId } from "../../../../providers/putShoppingMallAdminAdminsId";
import { deleteShoppingMallAdminAdminsId } from "../../../../providers/deleteShoppingMallAdminAdminsId";

import { IPageIShoppingMallAdmin } from "../../../../api/structures/IPageIShoppingMallAdmin";
import { IShoppingMallAdmin } from "../../../../api/structures/IShoppingMallAdmin";

@Controller("/shoppingMall/admin/admins")
export class ShoppingmallAdminAdminsController {
  /**
   * Search and retrieve a paginated list of admin users.
   *
   * Retrieve a filtered and paginated list of shopping mall admin users from
   * the system. This operation supports querying admins by criteria such as
   * email, full name, status, and creation date.
   *
   * It provides essential data for admin management dashboards, enabling
   * filtering, sorting, and pagination for usability.
   *
   * Security considerations: only authorized admin users can perform this
   * operation.
   *
   * The operation uses the shopping_mall_admins table as its data source, and
   * returns summarized admin user data optimized for display in lists.
   *
   * No request body is needed; the query parameters support filtering and
   * pagination.
   *
   * Expected response contains a paginated list of admin summaries.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for admin filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAdmin.IRequest,
  ): Promise<IPageIShoppingMallAdmin.ISummary> {
    try {
      return await patchShoppingMallAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific admin user from the
   * shopping_mall_admins table.
   *
   * This operation provides comprehensive information about a specific platform
   * administrator identified by their unique UUID. It ensures secure access to
   * admin profile data essential for administrative functions and auditing.
   * Access is restricted to authenticated users with admin-level privileges.
   *
   * The shopping_mall_admins table stores the core data for admins including
   * their email, hashed password, full name, and timestamps for creation,
   * update and optional soft deletion. This operation returns all active
   * records including users who might be soft deleted.
   *
   * The operation is a GET method and does not require a request body. Path
   * parameter 'id' must be a valid UUID representing the admin user.
   *
   * This operation is primarily used by system administrators and internal
   * services for management, authentication, and audit purposes. It is critical
   * that access is strictly controlled to ensure security and privacy of
   * administrator accounts.
   *
   * Error handling includes returning appropriate HTTP status codes for invalid
   * or missing IDs, unauthorized access, and not found entities.
   *
   * @param connection
   * @param id Unique identifier of the target admin user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await getShoppingMallAdminAdminsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update admin user details identified by ID in the shopping_mall_admins
   * table.
   *
   * This operation allows authorized system administrators to update the
   * information of an existing admin user identified by their UUID. Updates may
   * include email address and full name. The operation validates request data
   * to ensure uniqueness of email and proper formatting.
   *
   * The shopping_mall_admins table contains core data defining admin users,
   * including authentication information and timestamps. This operation
   * supports critical user management lifecycle tasks such as profile update
   * and role maintenance.
   *
   * The API operation expects a PUT method with a request body conforming to
   * the IShoppingMallAdmin.IUpdate DTO structure and a path parameter 'id'
   * (UUID) to identify the admin user to update.
   *
   * Proper authorization is required; only admin actors can perform this
   * operation. Errors handle invalid IDs, validation failures, and unauthorized
   * attempts securely.
   *
   * Response returns the updated admin user object reflecting modified fields
   * and timestamps.
   *
   * @param connection
   * @param id Unique identifier of the target admin user
   * @param body Updated admin user information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdmin.IUpdate,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await putShoppingMallAdminAdminsId({
        admin,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an admin user account by its unique ID.
   *
   * Permanently delete the admin user account identified by the unique UUID id.
   * This operation removes all data associated with the admin user from the
   * database permanently.
   *
   * Only authorized admin users with sufficient permissions can invoke this
   * operation to prevent unauthorized account deletions.
   *
   * The underlying entity corresponds to the 'shopping_mall_admins' Prisma
   * model, which includes email, password hash, and name information.
   *
   * No request body is required for this operation; it simply requires the
   * admin ID in the path.
   *
   * This endpoint performs a hard delete removing the record from persistence
   * with no recovery possible. Audit logging should record this deletion
   * separately.
   *
   * @param connection
   * @param id Unique identifier of the admin user (UUID)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminAdminsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
