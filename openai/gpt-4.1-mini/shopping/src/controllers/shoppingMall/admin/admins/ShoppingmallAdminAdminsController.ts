import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminAdmins } from "../../../../providers/postShoppingMallAdminAdmins";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminAdmins } from "../../../../providers/patchShoppingMallAdminAdmins";
import { getShoppingMallAdminAdminsAdminId } from "../../../../providers/getShoppingMallAdminAdminsAdminId";
import { putShoppingMallAdminAdminsAdminId } from "../../../../providers/putShoppingMallAdminAdminsAdminId";
import { deleteShoppingMallAdminAdminsAdminId } from "../../../../providers/deleteShoppingMallAdminAdminsAdminId";

import { IShoppingMallAdmin } from "../../../../api/structures/IShoppingMallAdmin";
import { IPageIShoppingMallAdmin } from "../../../../api/structures/IPageIShoppingMallAdmin";

@Controller("/shoppingMall/admin/admins")
export class ShoppingmallAdminAdminsController {
  /**
   * Create a new admin user in the shopping mall platform.
   *
   * This API endpoint enables the creation of a new administrative user for the
   * shopping mall platform.
   *
   * It requires authentication details and profile information necessary for
   * establishing a secure admin account. The operation validates the uniqueness
   * of usernames and enforces password policies. Only system components or
   * privileged users with appropriate access can perform this operation.
   *
   * Upon successful creation, the new admin user's information is returned,
   * excluding sensitive credential fields. This operation interfaces directly
   * with the shopping_mall_admins table as defined in the Prisma schema.
   *
   * Related operations include updating admin information via PUT
   * /admins/{adminId} and reading admin data through other GET endpoints.
   *
   * @param connection
   * @param body Admin user creation data conforming to the
   *   IShoppingMallAdmin.ICreate type
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAdmin.ICreate,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await postShoppingMallAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of shopping mall admins.
   *
   * Retrieve a paginated and filtered list of shopping mall admins from the
   * system. This operation provides advanced search capabilities to find admins
   * based on various criteria including admin name, email, role, and account
   * status.
   *
   * The operation supports pagination with configurable page sizes and sorting
   * options. Sorting and filtering controls enable efficient management of
   * admins in the platform.
   *
   * Security considerations restrict this operation to users with
   * administrative privileges only. Data returned respects privacy
   * considerations and only exposes non-sensitive admin fields suited for
   * administrative overview.
   *
   * This operation operates on the shopping_mall_admins Prisma database table
   * and integrates with the existing admin management workflows within the
   * shopping mall platform system.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   shopping mall admins
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAdmin.IRequest,
  ): Promise<IPageIShoppingMallAdmin.ISummary> {
    try {
      return await patchShoppingMallAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shopping mall admin user.
   *
   * Retrieve detailed information about a shopping mall administrative user
   * specified by the unique identifier.
   *
   * Security controls restrict access to authorized administrative users only.
   * The requesting user must have the appropriate permissions to view admin
   * user profiles.
   *
   * The response contains comprehensive profile data for the admin including
   * contact information and roles.
   *
   * This operation requires the admin user to be identified by the adminId path
   * parameter, which corresponds to the unique identifier field in the
   * shopping_mall_admins Prisma schema.
   *
   * This API endpoint is essential for administrative user management workflows
   * within the shopping mall platform.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin user (UUID)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await getShoppingMallAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update existing admin user information.
   *
   * This API endpoint allows updating details of an existing administrative
   * user identified by adminId.
   *
   * The operation validates incoming update data against schema constraints and
   * enforces security policies to maintain system integrity. It affects only
   * mutable fields; sensitive or authentication-related data is carefully
   * managed.
   *
   * Upon successful update, the latest admin user data is returned reflecting
   * the changes. This operation manipulates records from the
   * shopping_mall_admins table.
   *
   * Related operations include creation of admin users via POST /admins and
   * retrieving admin details through GET endpoints.
   *
   * @param connection
   * @param adminId Unique identifier of the admin user to update
   * @param body Admin user update data conforming to the
   *   IShoppingMallAdmin.IUpdate type
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdmin.IUpdate,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await putShoppingMallAdminAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific admin user by ID.
   *
   * Permanently removes an admin user record from the shopping mall platform.
   *
   * This action is irreversible and completely deletes all associated data for
   * the admin user.
   *
   * Only users with administrative authorization can perform this deletion to
   * prevent unauthorized removal of critical access accounts.
   *
   * No soft-delete functionality is implemented; the record is permanently
   * removed from the database.
   *
   * Related operations include fetching admin information and managing admin
   * sessions for active users.
   *
   * @param connection
   * @param adminId Unique identifier of the admin user to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
