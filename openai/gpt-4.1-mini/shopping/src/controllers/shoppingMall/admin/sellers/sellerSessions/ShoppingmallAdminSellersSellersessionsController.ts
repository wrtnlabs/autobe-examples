import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminSellersSellerIdSellerSessions } from "../../../../../providers/patchShoppingMallAdminSellersSellerIdSellerSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IPageIShoppingMallSellerSession } from "../../../../../api/structures/IPageIShoppingMallSellerSession";
import { IShoppingMallSellerSession } from "../../../../../api/structures/IShoppingMallSellerSession";

@Controller("/shoppingMall/admin/sellers/:sellerId/sellerSessions")
export class ShoppingmallAdminSellersSellersessionsController {
  /**
   * Search and retrieve seller session records by seller ID.
   *
   * Retrieve paginated session records of a specified seller user.
   *
   * This operation allows authorized users to view detailed connection sessions
   * associated with a specific seller. Each session record includes IP address,
   * URL of origin, referrer information, creation timestamp, and session
   * expiration.
   *
   * Security: Only administrators or authorized personnel can access this data
   * due to sensitive session information.
   *
   * This operation interacts with the `shopping_mall_seller_sessions` table,
   * filtered by the seller's unique UUID.
   *
   * Related operations: Delete seller (DELETE /sellers/{sellerId}) to remove
   * seller account and associated sessions.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller user
   * @param body Search criteria and pagination parameters for filtering seller
   *   sessions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSellerSession.IRequest,
  ): Promise<IPageIShoppingMallSellerSession.ISummary> {
    try {
      return await patchShoppingMallAdminSellersSellerIdSellerSessions({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
