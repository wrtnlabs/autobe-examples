import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminSellers } from "../../../../providers/postShoppingMallAdminSellers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminSellers } from "../../../../providers/patchShoppingMallAdminSellers";
import { getShoppingMallAdminSellersSellerId } from "../../../../providers/getShoppingMallAdminSellersSellerId";
import { putShoppingMallAdminSellersSellerId } from "../../../../providers/putShoppingMallAdminSellersSellerId";
import { deleteShoppingMallAdminSellersSellerId } from "../../../../providers/deleteShoppingMallAdminSellersSellerId";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { IPageIShoppingMallSeller } from "../../../../api/structures/IPageIShoppingMallSeller";

@Controller("/shoppingMall/admin/sellers")
export class ShoppingmallAdminSellersController {
  /**
   * Create a new seller account in the shopping mall platform.
   *
   * This operation allows authorized personnel to register new sellers by
   * providing required seller information including name, contact data, and
   * business details. Data validation ensures the uniqueness and completeness
   * of crucial identifying fields.
   *
   * Security: Only administrative roles or authorized systems can create new
   * sellers to prevent unauthorized registrations and maintain platform
   * integrity.
   *
   * This create operation impacts the shopping_mall_sellers table and interacts
   * with related entities such as seller sessions and product listings managed
   * by sellers.
   *
   * @param connection
   * @param body Seller creation request parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSeller.ICreate,
  ): Promise<IShoppingMallSeller> {
    try {
      return await postShoppingMallAdminSellers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of sellers.
   *
   * Retrieve a filtered and paginated list of seller accounts managing product
   * listings in the shopping mall platform.
   *
   * This operation allows clients to specify search criteria including seller
   * name, status, business status, and email filters. It provides pagination
   * and sorting support for efficient browsing through large numbers of
   * sellers.
   *
   * Security considerations ensure only authorized users can access seller
   * data, respecting privacy by limiting exposure of sensitive fields such as
   * password hashes.
   *
   * This operation interfaces directly with the shopping_mall_sellers Prisma
   * table, incorporating all its fields except password hashes for privacy
   * reasons. It supports filtering based on the unique email and seller
   * status.
   *
   * Related operations include retrieving a seller by ID (`GET
   * /sellers/{sellerId}`) and updating seller statuses or information.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering seller
   *   accounts
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSeller.IRequest,
  ): Promise<IPageIShoppingMallSeller.ISummary> {
    try {
      return await patchShoppingMallAdminSellers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve seller user details by ID.
   *
   * Retrieve detailed information for a specific seller user identified by
   * sellerId.
   *
   * This operation enables administrators to view comprehensive details of a
   * seller account, including business name, email, status, and lifecycle
   * timestamps. The password hash is deliberately excluded from the response
   * for security.
   *
   * Security access is limited to users with administrative privileges to avoid
   * exposing sensitive seller data to unauthorized parties.
   *
   * It directly corresponds to the shopping_mall_sellers Prisma table and
   * expects a UUID identifier for sellerId.
   *
   * Related operations include listing sellers and updating seller data.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSeller> {
    try {
      return await getShoppingMallAdminSellersSellerId({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update seller account information.
   *
   * Update an existing seller account by seller ID.
   *
   * Only authorized administrative users or the seller themselves can update
   * the seller information. The operation validates the updated data and
   * ensures no duplicate or conflicting information is introduced.
   *
   * Security measures prevent unauthorized modifications. Update changes
   * propagate to related systems such as product catalogs and seller session
   * management.
   *
   * This operation modifies the shopping_mall_sellers table, strictly
   * validating all input fields.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller
   * @param body Seller update request parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sellerId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSeller.IUpdate,
  ): Promise<IShoppingMallSeller> {
    try {
      return await putShoppingMallAdminSellersSellerId({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a seller user by UUID ID.
   *
   * Permanently delete the seller user identified by the provided seller ID.
   *
   * This operation allows administrators to completely remove a seller account
   * from the system. Deletion includes all seller metadata such as email, name,
   * status, and business status.
   *
   * Security: Only administrators with appropriate permissions should invoke
   * this operation. Deletion is irreversible and linked product listings must
   * be carefully managed separately.
   *
   * This operation interfaces directly with the `shopping_mall_sellers`
   * database table, and the seller is identified by their unique UUID primary
   * key.
   *
   * Related operations: Searching seller sessions (PATCH
   * /sellers/{sellerId}/sellerSessions) to view active sessions before
   * deletion.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sellerId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminSellersSellerId({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
