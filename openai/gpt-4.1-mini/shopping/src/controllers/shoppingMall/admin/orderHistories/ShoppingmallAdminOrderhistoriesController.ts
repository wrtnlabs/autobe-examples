import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminOrderHistories } from "../../../../providers/patchShoppingMallAdminOrderHistories";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminOrderHistoriesId } from "../../../../providers/getShoppingMallAdminOrderHistoriesId";

import { IPageIShoppingMallOrderHistory } from "../../../../api/structures/IPageIShoppingMallOrderHistory";
import { IShoppingMallOrderHistory } from "../../../../api/structures/IShoppingMallOrderHistory";

@Controller("/shoppingMall/admin/orderHistories")
export class ShoppingmallAdminOrderhistoriesController {
  /**
   * Retrieve filtered, paginated list of order histories.
   *
   * Retrieve a detailed, paginated collection of order history records from the
   * system. Each order history record captures a snapshot of order status,
   * payment status, shipment status, and total amount at a specific point in
   * time, enabling thorough historical auditing and reporting.
   *
   * This operation supports advanced search capabilities for filtering order
   * histories by various criteria such as date ranges, order statuses, and
   * payment states. Pagination parameters allow clients to manage the volume of
   * data returned per request, enhancing performance and usability.
   *
   * Access to this operation requires authentication as an admin user, ensuring
   * sensitive historical data is protected against unauthorized access. Proper
   * authorization controls prevent leakage of confidential order information
   * outside administrative channels.
   *
   * This operation interfaces directly with the shopping_mall_order_histories
   * table defined in the Prisma schema, making use of all relevant fields for
   * accurate representation of order lifecycle events. The response includes
   * paginated, summarized order history information optimized for
   * administrative dashboard displays.
   *
   * @param connection
   * @param body Search parameters and pagination options for order histories
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallOrderHistory.IRequest,
  ): Promise<IPageIShoppingMallOrderHistory.ISummary> {
    try {
      return await patchShoppingMallAdminOrderHistories({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve single order history record by ID.
   *
   * Retrieve detailed information for a specific order history record by its
   * unique identifier. This operation returns full lifecycle status including
   * order status, payment status, shipment status, and associated financial
   * totals.
   *
   * Access is restricted to users with admin privileges, reflecting the
   * sensitive nature of historical order data and audit trail requirements. The
   * operation is critical for administrative review, compliance, and detailed
   * transaction tracking.
   *
   * The underlying database entity is shopping_mall_order_histories, and this
   * operation maps directly to its primary key query with no data mutation
   * involved.
   *
   * @param connection
   * @param id Unique identifier of the target order history record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderHistory> {
    try {
      return await getShoppingMallAdminOrderHistoriesId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
