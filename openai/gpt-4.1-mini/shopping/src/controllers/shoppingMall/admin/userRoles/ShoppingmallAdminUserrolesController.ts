  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallUserRole.IUpdate,
  ): Promise<IShoppingMallUserRole> {
    try {
      return await putShoppingMallAdminUserRolesId({
        admin,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a user role by its unique ID from shopping_mall_user_roles table.
   *
   * This operation permanently removes the specified user role from the system.
   * User roles define the permissions granted to users, such as admin,
   * customer, or seller roles, and are critical for enforcing access control.
   *
   * Only authorized admin users can perform this operation to maintain
   * security. The deletion is a hard delete, meaning the user role record will
   * be completely removed and cannot be recovered.
   *
   * This API operation directly manipulates the shopping_mall_user_roles
   * entity, referencing its primary key id for deletion. No request body is
   * required.
   *
   * Related operations include listing user roles and creating or updating user
   * roles for role management.
   *
   * Error handling includes checking that the given id exists and the requester
   * has authorization, otherwise appropriate error responses are returned.
   *
   * @param connection
   * @param id Unique identifier of the user role to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
