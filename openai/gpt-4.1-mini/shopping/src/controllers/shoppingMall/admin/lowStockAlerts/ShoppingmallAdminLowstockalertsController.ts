import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminLowStockAlerts } from "../../../../providers/postShoppingMallAdminLowStockAlerts";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminLowStockAlerts } from "../../../../providers/patchShoppingMallAdminLowStockAlerts";
import { putShoppingMallAdminLowStockAlertsId } from "../../../../providers/putShoppingMallAdminLowStockAlertsId";
import { deleteShoppingMallAdminLowStockAlertsId } from "../../../../providers/deleteShoppingMallAdminLowStockAlertsId";

import { IShoppingMallLowStockAlert } from "../../../../api/structures/IShoppingMallLowStockAlert";
import { IPageIShoppingMallLowStockAlert } from "../../../../api/structures/IPageIShoppingMallLowStockAlert";

@Controller("/shoppingMall/admin/lowStockAlerts")
export class ShoppingmallAdminLowstockalertsController {
  /**
   * Create a new Low Stock Alert record for an SKU.
   *
   * Create a new Low Stock Alert to monitor SKU inventory levels and notify
   * relevant parties.
   *
   * The alert records the SKU's unique identifier, alert time, and resolution
   * status.
   *
   * Security requires that only authorized users, such as inventory managers or
   * admins, can create alerts to ensure integrity.
   *
   * The system should reject invalid SKU references and timestamps not
   * conforming to ISO 8601.
   *
   * This operation enables proactive stock management and operational
   * responsiveness.
   *
   * @param connection
   * @param body Low Stock Alert creation data including SKU reference, alert
   *   timestamp, and initial resolution state.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallLowStockAlert.ICreate,
  ): Promise<IShoppingMallLowStockAlert> {
    try {
      return await postShoppingMallAdminLowStockAlerts({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve paginated list of low stock alerts.
   *
   * Retrieve paginated low stock alert records identifying SKUs with inventory
   * under configured thresholds. The API supports complex search, filtering,
   * and pagination parameters passed in the request body defined by
   * IShoppingMallLowStockAlert.IRequest for precise querying.
   *
   * Authorized users with admin roles can list low stock alerts to manage
   * inventory proactively. Each alert showsSKU details, alert timestamp, and
   * resolved status, aiding decision making. The response provides low stock
   * alert summaries paginated for scalable access.
   *
   * This operation is read-only and does not modify alert records or SKU
   * inventories directly. It is critical for inventory control and
   * administrative oversight.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for low stock alert
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallLowStockAlert.IRequest,
  ): Promise<IPageIShoppingMallLowStockAlert.ISummary> {
    try {
      return await patchShoppingMallAdminLowStockAlerts({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a low stock alert by ID.
   *
   * Update an existing low stock alert record identified by its unique ID. This
   * operation allows modifying alert attributes such as resolution status and
   * resolution timestamp.
   *
   * The shopping_mall_low_stock_alerts table entries represent alert events
   * triggered when stock levels of product SKUs fall below predefined
   * thresholds. Accurate updating ensures effective inventory monitoring and
   * notification workflows.
   *
   * Security considerations require that only authenticated and authorized
   * users, such as sellers or administrators, can update low stock alert
   * records to prevent tampering.
   *
   * This operation provides essential functionality to manage low stock alerts
   * lifecycle, supporting inventory replenishment and operational continuity.
   *
   * Related operations include creating low stock alerts (automatically by the
   * system), retrieving alert details, and marking alerts as resolved.
   *
   * The operation performs a hard update of the alert record within the
   * underlying PostgreSQL database with concurrency and validation checks
   * enforced at the service layer.
   *
   * @param connection
   * @param id Unique identifier of the low stock alert to update
   * @param body Low stock alert update data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallLowStockAlert.IUpdate,
  ): Promise<IShoppingMallLowStockAlert> {
    try {
      return await putShoppingMallAdminLowStockAlertsId({
        admin,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Hard delete a low stock alert by ID.
   *
   * Delete a low stock alert by its unique identifier from the database. This
   * operation permanently removes the alert record from inventory management.
   *
   * Only authorized users (seller or admin) are permitted to perform this
   * deletion. Deletion is irreversible.
   *
   * This operation is critical for maintaining a clean and accurate set of
   * inventory alerts, eliminating outdated or incorrect alert records.
   *
   * Related operations include creating new alerts and updating existing
   * alerts' statuses.
   *
   * @param connection
   * @param id Unique identifier of the low stock alert to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminLowStockAlertsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
