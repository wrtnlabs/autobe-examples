import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallAdminShoppingMallChannels } from "../../../../providers/postShoppingMallAdminShoppingMallChannels";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminShoppingMallChannelsChannelCode } from "../../../../providers/putShoppingMallAdminShoppingMallChannelsChannelCode";
import { deleteShoppingMallAdminShoppingMallChannelsChannelCode } from "../../../../providers/deleteShoppingMallAdminShoppingMallChannelsChannelCode";

import { IShoppingMallChannel } from "../../../../api/structures/IShoppingMallChannel";

@Controller("/shoppingMall/admin/shoppingMallChannels")
export class ShoppingmallAdminShoppingmallchannelsController {
  /**
   * Create a new shopping mall channel to represent a distinct entry point or
   * marketplace within the platform.
   *
   * This operation allows authorized users to register a channel by specifying
   * a unique code and a user-friendly name. The system automatically manages
   * creation and update timestamps.
   *
   * Security: Appropriate authorization is required to create channels to
   * prevent duplication and unauthorized additions. The channel code must be
   * unique system-wide.
   *
   * Related operations include updating channel details (PUT
   * /shoppingMallChannels/{channelCode}) and listing channels for management
   * purposes.
   *
   * @param connection
   * @param body Information required to create a shopping mall channel
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallChannel.ICreate,
  ): Promise<IShoppingMallChannel> {
    try {
      return await postShoppingMallAdminShoppingMallChannels({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shopping mall channel.
   *
   * Update the details of an existing shopping mall channel identified by its
   * unique code.
   *
   * This operation enables authorized users to modify the display name of the
   * channel. The unique code serves as the identifier to fetch and update the
   * correct channel record.
   *
   * Security: Only users with admin privileges may perform this update to
   * maintain control over channel information and prevent conflicts.
   *
   * This operation is related to channel creation (POST /shoppingMallChannels)
   * and channel listing APIs.
   *
   * @param connection
   * @param channelCode Unique business identifier code of the target shopping
   *   mall channel (global scope)
   * @param body Updated information for the shopping mall channel
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":channelCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("channelCode")
    channelCode: string,
    @TypedBody()
    body: IShoppingMallChannel.IUpdate,
  ): Promise<IShoppingMallChannel> {
    try {
      return await putShoppingMallAdminShoppingMallChannelsChannelCode({
        admin,
        channelCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a shopping mall channel by its unique code.
   *
   * Permanently deletes the channel identified by the provided unique channel
   * code from the shopping mall platform.
   *
   * This operation targets the shopping_mall_channels table, where channels
   * represent the main entry points or marketplaces. Channels organize sections
   * and categories for the shopping experience.
   *
   * Authorization is required to ensure only permitted administrators can
   * perform deletions, preventing accidental or malicious removal.
   *
   * Since this is a hard delete, the channel data is removed entirely from the
   * database and cannot be recovered.
   *
   * Related operations include listing all channels and managing sections
   * within a channel.
   *
   * @param connection
   * @param channelCode Unique business identifier code of the target channel
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":channelCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("channelCode")
    channelCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminShoppingMallChannelsChannelCode({
        admin,
        channelCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
