import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminPlatformConfigs } from "../../../../providers/postShoppingMallAdminPlatformConfigs";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminPlatformConfigs } from "../../../../providers/patchShoppingMallAdminPlatformConfigs";
import { getShoppingMallAdminPlatformConfigsId } from "../../../../providers/getShoppingMallAdminPlatformConfigsId";
import { putShoppingMallAdminPlatformConfigsId } from "../../../../providers/putShoppingMallAdminPlatformConfigsId";
import { deleteShoppingMallAdminPlatformConfigsId } from "../../../../providers/deleteShoppingMallAdminPlatformConfigsId";

import { IShoppingMallPlatformConfig } from "../../../../api/structures/IShoppingMallPlatformConfig";
import { IPageIShoppingMallPlatformConfig } from "../../../../api/structures/IPageIShoppingMallPlatformConfig";

@Controller("/shoppingMall/admin/platformConfigs")
export class ShoppingmallAdminPlatformconfigsController {
  /**
   * Create a new shopping mall platform configuration entry. This endpoint
   * allows administrators to define new system-wide configuration parameters
   * that affect platform operation.
   *
   * The operation requires unique config_name to prevent conflicts.
   * Descriptions can be provided optionally to explain the purpose of the
   * configuration.
   *
   * Authorization is strictly enforced to allow only admins to perform this
   * operation.
   *
   * Upon successful creation, the newly created configuration object is
   * returned including all timestamps.
   *
   * Concurrent creations of configurations with duplicate names SHALL be
   * rejected by the system.
   *
   * @param connection
   * @param body Creation info of the platform configuration
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPlatformConfig.ICreate,
  ): Promise<IShoppingMallPlatformConfig> {
    try {
      return await postShoppingMallAdminPlatformConfigs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve platform configuration entries with filtering and
   * pagination.
   *
   * Retrieve a filtered and paginated list of platform configuration entries
   * maintained by the shopping mall platform system. This operation supports
   * complex search criteria such as filtering by configuration names, values,
   * and enablement status.
   *
   * The data model corresponds to the 'shopping_mall_platform_configs' table
   * which stores platform-specific settings including names, values, and
   * descriptive metadata.
   *
   * Security constraints limit access to administrative users only.
   *
   * The request body allows specifying search and pagination parameters using a
   * defined IRequest DTO.
   *
   * The response contains a paginated summary list of matching config entries
   * for display or integration purposes.
   *
   * Supports integrations with admin dashboards or system management tools.
   *
   * Clients must handle pagination and sorting using provided parameters.
   *
   * Related operations include specific config detail retrieval, creation,
   * update, and deletion endpoints.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for platform
   *   configuration entries
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async indexPlatformConfig(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPlatformConfig.IRequest,
  ): Promise<IPageIShoppingMallPlatformConfig.ISummary> {
    try {
      return await patchShoppingMallAdminPlatformConfigs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single shopping mall platform configuration.
   *
   * Retrieve the details of a single shopping mall platform configuration by
   * its unique identifier. This operation fetches configuration parameters that
   * govern the shopping platform's behavior, including feature flags and
   * environment settings.
   *
   * Only authorized users can access this endpoint to prevent unauthorized
   * reading of sensitive configuration data.
   *
   * The shopping_mall_platform_configs table stores these configurations with
   * creation and update timestamps, along with a soft-delete field. This
   * endpoint returns the data without exposing deleted entries.
   *
   * If the specified configuration ID does not exist or has been deleted, the
   * system SHALL respond with an appropriate error message informing the
   * client.
   *
   * This operation complements POST /platformConfigs for creating new
   * configurations.
   *
   * @param connection
   * @param id Unique identifier of the target platform configuration
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallPlatformConfig> {
    try {
      return await getShoppingMallAdminPlatformConfigsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing platform configuration for the shopping mall platform.
   *
   * Update an existing platform configuration entry in the shopping mall
   * platform. This operation enables modifying configuration name and value
   * parameters that control feature toggles, versioning, or
   * environment-specific behaviors within the platform.
   *
   * The operation uses the 'id' path parameter to locate the target
   * configuration record and applies changes to the 'config_name' and
   * 'config_value' fields as provided in the request body. Data validation
   * ensures 'config_name' uniqueness is preserved.
   *
   * Security requires appropriate admin-level authorization to prevent
   * unauthorized configuration changes impacting platform stability. The
   * operation preserves the soft delete field 'deleted_at' to allow recovery or
   * logical removal of configurations.
   *
   * This corresponds to the shopping_mall_platform_configs table as defined in
   * the Prisma schema, which includes fields for description and timestamps to
   * track the lifecycle of each configuration entry.
   *
   * Error handling includes validation errors for duplicate config_name or
   * invalid data formats. Attempted updates to soft-deleted records may return
   * not found or forbidden responses depending on implementation.
   *
   * @param connection
   * @param id Unique identifier of the platform configuration to update
   * @param body Updated platform configuration details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string,
    @TypedBody()
    body: IShoppingMallPlatformConfig.IUpdate,
  ): Promise<IShoppingMallPlatformConfig> {
    try {
      return await putShoppingMallAdminPlatformConfigsId({
        admin,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an existing platform configuration by ID.
   *
   * Delete a platform configuration from the shopping mall platform system by
   * its unique identifier. This operation permanently removes the configuration
   * entry from the database.
   *
   * Security requires admin authentication and authorization to ensure only
   * authorized personnel may remove critical platform settings.
   *
   * Deletion will fail if the specified configuration does not exist, throwing
   * not found errors.
   *
   * This corresponds to the shopping_mall_platform_configs table as defined in
   * the Prisma schema, which holds all mutable platform configuration values.
   *
   * No request body is required or accepted for this operation.
   *
   * @param connection
   * @param id Unique identifier of the platform configuration to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminPlatformConfigsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
