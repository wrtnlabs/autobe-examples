import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminCustomerSessions } from "../../../../providers/patchShoppingMallAdminCustomerSessions";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCustomerSessionsSessionId } from "../../../../providers/getShoppingMallAdminCustomerSessionsSessionId";

import { IPageIShoppingMallCustomerSession } from "../../../../api/structures/IPageIShoppingMallCustomerSession";
import { IShoppingMallCustomerSession } from "../../../../api/structures/IShoppingMallCustomerSession";

@Controller("/shoppingMall/admin/customerSessions")
export class ShoppingmallAdminCustomersessionsController {
  /**
   * Search and retrieve a filtered, paginated list of customer sessions.
   *
   * Retrieve a filtered and paginated list of customer authentication sessions
   * from the system. This operation enables advanced search capabilities
   * allowing filtering on IP address, referrer, and session validity.
   *
   * Customer sessions represent login instances tied to a specific customer,
   * recording metadata such as the originating IP address, session creation
   * time, and expiration. This information is critical for monitoring
   * authentication security and session activity.
   *
   * Search results include pagination controls to efficiently navigate large
   * datasets of sessions. Appropriate authorization ensures only authorized
   * actors like admins can access this sensitive session information.
   *
   * This operation integrates with the shopping_mall_customer_sessions table
   * defined in the Prisma schema, incorporating all fields relevant for session
   * tracking and management.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for customer session
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCustomerSession.IRequest,
  ): Promise<IPageIShoppingMallCustomerSession.ISummary> {
    try {
      return await patchShoppingMallAdminCustomerSessions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific customer session by ID.
   *
   * Fetch detailed information of a specific customer authentication session by
   * its unique identifier. The record includes all relevant data from the
   * shopping_mall_customer_sessions table such as origin IP, session creation
   * time, and expiration date.
   *
   * This operation is critical for security audits and session management by
   * authorized administrators.
   *
   * The sessionId parameter uniquely identifies the session record and must be
   * provided as a UUID string.
   *
   * This operation only returns the session entity and does not return request
   * or response bodies for creation or modification.
   *
   * @param connection
   * @param sessionId Unique identifier of the customer session (UUID)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerSession> {
    try {
      return await getShoppingMallAdminCustomerSessionsSessionId({
        admin,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
