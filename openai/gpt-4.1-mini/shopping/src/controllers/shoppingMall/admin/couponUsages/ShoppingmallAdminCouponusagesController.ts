import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminCouponUsages } from "../../../../providers/postShoppingMallAdminCouponUsages";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminCouponUsages } from "../../../../providers/patchShoppingMallAdminCouponUsages";
import { getShoppingMallAdminCouponUsagesCouponUsageId } from "../../../../providers/getShoppingMallAdminCouponUsagesCouponUsageId";
import { putShoppingMallAdminCouponUsagesCouponUsageId } from "../../../../providers/putShoppingMallAdminCouponUsagesCouponUsageId";
import { deleteShoppingMallAdminCouponUsagesCouponUsageId } from "../../../../providers/deleteShoppingMallAdminCouponUsagesCouponUsageId";

import { IShoppingMallCouponUsage } from "../../../../api/structures/IShoppingMallCouponUsage";
import { IPageIShoppingMallCouponUsage } from "../../../../api/structures/IPageIShoppingMallCouponUsage";

@Controller("/shoppingMall/admin/couponUsages")
export class ShoppingmallAdminCouponusagesController {
  /**
   * Create a new coupon usage record.
   *
   * Submit a new coupon usage record to the system.
   *
   * This operation validates the input data, including coupon identification
   * and customer association, then creates a new coupon usage entry.
   *
   * Security: Typically restricted to authenticated users or system processes
   * authorized to record coupon usage.
   *
   * Upon successful creation, the operation returns the full coupon usage
   * entity with all stored attributes.
   *
   * Related operations include retrieving usage history and updating coupon
   * usage data where applicable.
   *
   * @param connection
   * @param body New coupon usage creation data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCouponUsage.ICreate,
  ): Promise<IShoppingMallCouponUsage> {
    try {
      return await postShoppingMallAdminCouponUsages({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve paginated coupon usage records.
   *
   * Retrieve a filtered and paginated list of coupon usage records from the
   * shopping mall platform.
   *
   * This operation supports advanced search parameters, including filtering by
   * coupon code, customer ID, order association, and usage date range.
   * Pagination and sorting options enable efficient browsing of large
   * datasets.
   *
   * Access is typically limited to administrative users or analysts who need to
   * audit coupon consumption or analyze promotional effectiveness.
   *
   * The response contains summary representations of coupon usage records,
   * optimized for display in paginated lists.
   *
   * Related operations: Viewing specific coupon usage details (GET
   * /couponUsages/{usageId}), deleting coupons (DELETE /coupons/{couponCode}).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering coupon
   *   usage records
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCouponUsage.IRequest,
  ): Promise<IPageIShoppingMallCouponUsage.ISummary> {
    try {
      return await patchShoppingMallAdminCouponUsages({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get coupon usage details by couponUsageId.
   *
   * Retrieve detailed information about a specific coupon usage by its unique
   * identifier.
   *
   * This endpoint is a read-only operation that fetches all relevant fields
   * associated with the coupon usage, such as the coupon applied, the customer,
   * usage date, and any related metadata.
   *
   * Security considerations: Access might be restricted to users with valid
   * authentication tokens or administrative permissions to prevent unauthorized
   * data access.
   *
   * The operation returns a full representation of the coupon usage entity,
   * useful for audits, customer service, or usage analytics.
   *
   * @param connection
   * @param couponUsageId Unique identifier of the coupon usage record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":couponUsageId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("couponUsageId")
    couponUsageId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCouponUsage> {
    try {
      return await getShoppingMallAdminCouponUsagesCouponUsageId({
        admin,
        couponUsageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a coupon usage record by ID.
   *
   * Update an existing coupon usage record that tracks the redemption of
   * coupons by customers in the shopping mall. The record includes references
   * to the related coupon, customer, and customer session during which the
   * coupon was used.
   *
   * This operation is crucial for maintaining accurate audit logs and
   * correcting order linkage if needed. The update may include changes to the
   * order ID associated with usage or the usage timestamp.
   *
   * Security considerations restrict modification to authorized system
   * administrators or designated sales personnel. Audit fields such as
   * updated_at are automatically managed.
   *
   * Related operations include retrieval (GET /couponUsages/{couponUsageId})
   * and deletion (DELETE /couponUsages/{couponUsageId}).
   *
   * @param connection
   * @param couponUsageId Unique identifier of the target coupon usage record
   * @param body Data fields for updating the coupon usage record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":couponUsageId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("couponUsageId")
    couponUsageId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCouponUsage.IUpdate,
  ): Promise<IShoppingMallCouponUsage> {
    try {
      return await putShoppingMallAdminCouponUsagesCouponUsageId({
        admin,
        couponUsageId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a coupon usage record by ID.
   *
   * Delete an existing coupon usage record to remove its usage history from the
   * system.
   *
   * This operation permanently removes the record from the shopping mall
   * database, eliminating all associated data and preventing further
   * reference.
   *
   * Security is paramount; only authorized platform administrators may perform
   * this operation. Deletion requests are logged for compliance.
   *
   * Related operations include update (PUT /couponUsages/{couponUsageId}) and
   * retrieval (GET /couponUsages/{couponUsageId}).
   *
   * @param connection
   * @param couponUsageId Unique identifier of the coupon usage record to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":couponUsageId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("couponUsageId")
    couponUsageId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCouponUsagesCouponUsageId({
        admin,
        couponUsageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
