import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminShoppingMallShipments } from "../../../../providers/postShoppingMallAdminShoppingMallShipments";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminShoppingMallShipmentsShoppingMallShipmentId } from "../../../../providers/putShoppingMallAdminShoppingMallShipmentsShoppingMallShipmentId";
import { deleteShoppingMallAdminShoppingMallShipmentsShoppingMallShipmentId } from "../../../../providers/deleteShoppingMallAdminShoppingMallShipmentsShoppingMallShipmentId";

import { IShoppingMallShipment } from "../../../../api/structures/IShoppingMallShipment";

@Controller("/shoppingMall/admin/shoppingMallShipments")
export class ShoppingmallAdminShoppingmallshipmentsController {
  /**
   * Create a new shipment record for an order in the shopping mall platform.
   *
   * Create a new shipment record in the shopping mall platform for an order.
   *
   * This operation allows authorized users to record shipment information
   * including shipping method, tracking number, and status for a specific order
   * identified by shoppingMallOrderId. The shipment status can reflect stages
   * such as pending, shipped, in_transit, or delivered.
   *
   * Timestamps for creation and last update are recorded automatically by the
   * system.
   *
   * Only authorized users with permissions to manage shipments should access
   * this operation.
   *
   * Related operations: update shipment (PUT
   * /shoppingMallShipments/{shoppingMallShipmentId}).
   *
   * @param connection
   * @param body Information needed to create a new shipment record including
   *   associated order, shipping method, tracking number, and shipment status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallShipment.ICreate,
  ): Promise<IShoppingMallShipment> {
    try {
      return await postShoppingMallAdminShoppingMallShipments({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shipment record by shipment ID in the shopping mall
   * platform.
   *
   * Update an existing shipment record identified by shoppingMallShipmentId.
   *
   * Authorized users can update shipping method, tracking number, and shipment
   * status fields. The shipment record is linked to an order via
   * shoppingMallOrderId which is not modifiable through this operation.
   *
   * Update timestamps are set automatically.
   *
   * Proper authorization is required to ensure shipment data integrity.
   *
   * Related operations: create shipment (POST /shoppingMallShipments).
   *
   * @param connection
   * @param shoppingMallShipmentId Unique identifier (UUID) of the shipment
   *   record to be updated
   * @param body Information for updating shipment record fields such as
   *   shipping method and status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shoppingMallShipmentId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shoppingMallShipmentId")
    shoppingMallShipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipment.IUpdate,
  ): Promise<IShoppingMallShipment> {
    try {
      return await putShoppingMallAdminShoppingMallShipmentsShoppingMallShipmentId(
        {
          admin,
          shoppingMallShipmentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific shipment record in the shopping mall platform.
   *
   * This operation deletes a shopping mall shipment entry identified by its
   * unique shipment ID.
   *
   * The deletion is permanent and removes the shipment record and all
   * associated references from the system.
   *
   * Security measures ensure that only authorized users can perform this
   * deletion to prevent accidental or unauthorized removals.
   *
   * Relationships to orders and shipments are handled by database constraints
   * or cascading rules to maintain data integrity.
   *
   * @param connection
   * @param shoppingMallShipmentId Unique identifier of the shopping mall
   *   shipment to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":shoppingMallShipmentId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shoppingMallShipmentId")
    shoppingMallShipmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminShoppingMallShipmentsShoppingMallShipmentId(
        {
          admin,
          shoppingMallShipmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
