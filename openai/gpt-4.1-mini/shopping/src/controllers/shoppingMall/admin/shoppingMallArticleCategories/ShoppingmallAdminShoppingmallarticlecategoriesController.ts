  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shoppingMallArticleCategoryId")
    shoppingMallArticleCategoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallArticleCategory.IUpdate,
  ): Promise<IShoppingMallArticleCategory> {
    try {
      return await putShoppingMallAdminShoppingMallArticleCategoriesShoppingMallArticleCategoryId(
        {
          admin,
          shoppingMallArticleCategoryId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a shopping mall article category by its ID.
   *
   * Permanently deletes a shopping mall article category identified by the
   * given unique identifier.
   *
   * This operation removes the category record from the database entirely and
   * does not perform soft deletion or archival.
   *
   * Proper authorization checks are required to ensure only users with
   * appropriate permissions can delete categories.
   *
   * Deleting a category impacts all linked articles and may require further
   * cascading or cleanup in related entities.
   *
   * @param connection
   * @param shoppingMallArticleCategoryId Unique identifier of the shopping mall
   *   article category to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
