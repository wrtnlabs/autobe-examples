import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { putShoppingMallAdminShoppingMallArticleCategoriesShoppingMallArticleCategoryIdCommentsShoppingMallArticleCommentId } from "../../../../../providers/putShoppingMallAdminShoppingMallArticleCategoriesShoppingMallArticleCategoryIdCommentsShoppingMallArticleCommentId";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { deleteShoppingMallAdminShoppingMallArticleCategoriesShoppingMallArticleCategoryIdCommentsShoppingMallArticleCommentId } from "../../../../../providers/deleteShoppingMallAdminShoppingMallArticleCategoriesShoppingMallArticleCategoryIdCommentsShoppingMallArticleCommentId";

import { IShoppingMallArticleComment } from "../../../../../api/structures/IShoppingMallArticleComment";

@Controller(
  "/shoppingMall/admin/shoppingMallArticleCategories/:shoppingMallArticleCategoryId/comments/:shoppingMallArticleCommentId",
)
export class ShoppingmallAdminShoppingmallarticlecategoriesCommentsController {
  /**
   * Update a comment within a shopping mall article category.
   *
   * Update a comment under a specified article category in the shopping mall
   * platform.
   *
   * This endpoint allows authenticated users with appropriate permissions to
   * modify the content and metadata of an existing article comment. The update
   * operation checks for the existence of both the article category and the
   * comment before applying changes.
   *
   * Security: Only authorized users such as admins or the original comment
   * author can perform this update. Input validation ensures that the updated
   * data conforms to schema constraints to maintain data integrity.
   *
   * Related operations: GET to retrieve comments, DELETE to remove comments
   * under the same category.
   *
   * @param connection
   * @param shoppingMallArticleCategoryId Unique identifier of the target
   *   shopping mall article category
   * @param shoppingMallArticleCommentId Unique identifier of the target
   *   shopping mall article comment
   * @param body Updated shopping mall article comment object
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shoppingMallArticleCategoryId")
    shoppingMallArticleCategoryId: string,
    @TypedParam("shoppingMallArticleCommentId")
    shoppingMallArticleCommentId: string,
    @TypedBody()
    body: IShoppingMallArticleComment.IUpdate,
  ): Promise<IShoppingMallArticleComment> {
    try {
      return await putShoppingMallAdminShoppingMallArticleCategoriesShoppingMallArticleCategoryIdCommentsShoppingMallArticleCommentId(
        {
          admin,
          shoppingMallArticleCategoryId,
          shoppingMallArticleCommentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a comment within a shopping mall article category.
   *
   * Delete a comment from a specified article category in the shopping mall
   * platform.
   *
   * This endpoint allows authorized users to permanently remove an existing
   * comment. Deletion is irreversible and the comment data will no longer be
   * available.
   *
   * Security: Only users with admin privileges can perform this deletion to
   * prevent unauthorized data loss.
   *
   * Related operations: GET to retrieve comments, PUT to update comments within
   * the same category.
   *
   * @param connection
   * @param shoppingMallArticleCategoryId Unique identifier of the target
   *   shopping mall article category
   * @param shoppingMallArticleCommentId Unique identifier of the target
   *   shopping mall article comment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shoppingMallArticleCategoryId")
    shoppingMallArticleCategoryId: string,
    @TypedParam("shoppingMallArticleCommentId")
    shoppingMallArticleCommentId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminShoppingMallArticleCategoriesShoppingMallArticleCategoryIdCommentsShoppingMallArticleCommentId(
        {
          admin,
          shoppingMallArticleCategoryId,
          shoppingMallArticleCommentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
