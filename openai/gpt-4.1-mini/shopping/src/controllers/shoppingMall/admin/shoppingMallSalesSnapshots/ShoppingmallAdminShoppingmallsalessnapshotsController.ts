import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminShoppingMallSalesSnapshots } from "../../../../providers/patchShoppingMallAdminShoppingMallSalesSnapshots";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminShoppingMallSalesSnapshotsId } from "../../../../providers/getShoppingMallAdminShoppingMallSalesSnapshotsId";

import { IPageIShoppingMallSalesSnapshot } from "../../../../api/structures/IPageIShoppingMallSalesSnapshot";
import { IShoppingMallSalesSnapshot } from "../../../../api/structures/IShoppingMallSalesSnapshot";

@Controller("/shoppingMall/admin/shoppingMallSalesSnapshots")
export class ShoppingmallAdminShoppingmallsalessnapshotsController {
  /**
   * Search and retrieve paginated sales snapshots.
   *
   * Retrieve a filtered and paginated list of sales snapshots in the shopping
   * mall system.
   *
   * This operation provides advanced searching capabilities for historical
   * sales snapshot records, allowing users to filter by various attributes
   * including snapshot date, product identifiers, and sales performance
   * metrics.
   *
   * The response includes a paginated list of summarized sales snapshot data
   * optimized for display in management dashboards and analytics tools.
   *
   * Access to this operation requires administrative privileges due to the
   * sensitive nature of sales data and its impact on business insights.
   *
   * Related operations include creating new snapshots (performed automatically
   * by the system), viewing detailed snapshots, and querying current sales data
   * for comparison.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for sales snapshots
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSalesSnapshot.IRequest,
  ): Promise<IPageIShoppingMallSalesSnapshot.ISummary> {
    try {
      return await patchShoppingMallAdminShoppingMallSalesSnapshots({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single shopping mall sales snapshot by ID.
   *
   * Retrieve detailed information about a single sales snapshot in the shopping
   * mall system.
   *
   * This operation allows authorized users to access historical snapshot data
   * captured for auditing and sales analysis.
   *
   * Security considerations include limiting access to authorized actors. The
   * operation references the shoppingMallSalesSnapshots table, ensuring data
   * returned aligns with the stored snapshot state at the point of capture.
   *
   * The operation will raise errors if the snapshot with the provided ID does
   * not exist. Related operations include listing all snapshots via PATCH
   * /shoppingMallSalesSnapshots and possibly creating new snapshots via
   * internal processes.
   *
   * @param connection
   * @param id Unique identifier of the target sales snapshot
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSalesSnapshot> {
    try {
      return await getShoppingMallAdminShoppingMallSalesSnapshotsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
