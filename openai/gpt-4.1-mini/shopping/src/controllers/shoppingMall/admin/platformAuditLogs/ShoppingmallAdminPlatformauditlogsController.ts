import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminPlatformAuditLogs } from "../../../../providers/patchShoppingMallAdminPlatformAuditLogs";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminPlatformAuditLogsId } from "../../../../providers/getShoppingMallAdminPlatformAuditLogsId";

import { IPageIShoppingMallPlatformAuditLog } from "../../../../api/structures/IPageIShoppingMallPlatformAuditLog";
import { IShoppingMallPlatformAuditLog } from "../../../../api/structures/IShoppingMallPlatformAuditLog";

@Controller("/shoppingMall/admin/platformAuditLogs")
export class ShoppingmallAdminPlatformauditlogsController {
  /**
   * Search and retrieve filtered admin platform audit logs.
   *
   * Retrieve a filtered and paginated list of platform audit logs. Each log
   * entry includes the admin user, event type, detailed event description, and
   * timestamp.
   *
   * The operation supports advanced search parameters including filtering by
   * event type and date ranges to facilitate security audits and operational
   * monitoring.
   *
   * Access to audit logs is restricted to admin users due to sensitivity of the
   * data.
   *
   * This API operation is read-only and corresponds to the
   * shopping_mall_platform_audit_logs entity.
   *
   * Error handling covers validation of search parameters and pagination inputs
   * with appropriate error responses.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for audit log
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IPageIShoppingMallPlatformAuditLog.IRequest,
  ): Promise<IPageIShoppingMallPlatformAuditLog.ISummary> {
    try {
      return await patchShoppingMallAdminPlatformAuditLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a detailed platform audit log entry by its unique ID from the
   * shopping mall platform audit logs.
   *
   * This GET operation fetches a single shopping mall platform audit log
   * identified by the unique `id` path parameter. Each audit log records
   * critical administrative events, including the admin user responsible (if
   * applicable), the type of event such as login or change, description of the
   * event, and the creation timestamp.
   *
   * Access to this endpoint is restricted to authenticated admin users to
   * ensure audit data confidentiality and security. The operation enforces
   * strict authorization, permitting only users with admin privileges.
   *
   * Returns a detailed audit log record from the
   * `shopping_mall_platform_audit_logs` database table, allowing system
   * administrators to investigate and track important system actions. No
   * modifications are made to data; this is a safe, read-only query.
   *
   * Error handling includes returning appropriate error codes if the specified
   * `id` does not exist or the user lacks permissions.
   *
   * @param connection
   * @param id Unique identifier of the platform audit log entry
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallPlatformAuditLog> {
    try {
      return await getShoppingMallAdminPlatformAuditLogsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
