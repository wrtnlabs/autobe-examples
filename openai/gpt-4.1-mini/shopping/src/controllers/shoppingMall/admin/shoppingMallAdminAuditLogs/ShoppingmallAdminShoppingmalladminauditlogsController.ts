import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminShoppingMallAdminAuditLogs } from "../../../../providers/patchShoppingMallAdminShoppingMallAdminAuditLogs";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminShoppingMallAdminAuditLogsId } from "../../../../providers/getShoppingMallAdminShoppingMallAdminAuditLogsId";

import { IPageIShoppingMallAdminAuditLog } from "../../../../api/structures/IPageIShoppingMallAdminAuditLog";
import { IShoppingMallAdminAuditLog } from "../../../../api/structures/IShoppingMallAdminAuditLog";

@Controller("/shoppingMall/admin/shoppingMallAdminAuditLogs")
export class ShoppingmallAdminShoppingmalladminauditlogsController {
  /**
   * Search and retrieve admin audit logs with filtering and pagination.
   *
   * Retrieve a filtered and paginated list of administrator audit logs from the
   * shopping mall platform. This operation supports advanced search criteria
   * allowing administrators to filter logs based on action types, timestamps,
   * user identifiers, and other relevant metadata.
   *
   * The audit logs are immutable snapshot records designed for compliance and
   * security auditing. Access is strictly limited to administrators with
   * appropriate authorization.
   *
   * Security measures include rate limiting and stringent access controls to
   * ensure audit data confidentiality and integrity. This operation integrates
   * with the shopping_mall_admin_audit_logs snapshot table, returning paginated
   * audit log summary records optimized for administrative review.
   *
   * @param connection
   * @param body Filtering and pagination parameters for searching admin audit
   *   logs
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAdminAuditLog.IRequest,
  ): Promise<IPageIShoppingMallAdminAuditLog.ISummary> {
    try {
      return await patchShoppingMallAdminShoppingMallAdminAuditLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve specific admin audit log entry by ID.
   *
   * Retrieve detailed information about a single administrator audit log entry
   * identified by its unique UUID from the shopping mall platform. This
   * includes comprehensive immutable audit data such as the action performed,
   * the administrator who performed it, the timestamp, and any associated
   * metadata.
   *
   * Access is strictly limited to users with administrator privileges due to
   * the sensitive nature of audit information.
   *
   * This operation integrates directly with the shopping_mall_admin_audit_logs
   * snapshot table and ensures a consistent, secure, and performant retrieval
   * of audit records.
   *
   * @param connection
   * @param id Unique UUID of the admin audit log entry
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdminAuditLog> {
    try {
      return await getShoppingMallAdminShoppingMallAdminAuditLogsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
