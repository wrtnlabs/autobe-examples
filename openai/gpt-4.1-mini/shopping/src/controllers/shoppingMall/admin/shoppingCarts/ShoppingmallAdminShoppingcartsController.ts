import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallAdminShoppingCarts } from "../../../../providers/patchShoppingMallAdminShoppingCarts";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

import { IPageIShoppingMallShoppingCart } from "../../../../api/structures/IPageIShoppingMallShoppingCart";
import { IShoppingMallShoppingCart } from "../../../../api/structures/IShoppingMallShoppingCart";

@Controller("/shoppingMall/admin/shoppingCarts")
export class ShoppingmallAdminShoppingcartsController {
  /**
   * Search and retrieve customer shopping carts.
   *
   * Search and retrieve a paginated list of customer shopping carts in the
   * shopping mall platform.
   *
   * This operation supports advanced filtering based on customer identifiers,
   * creation dates, and cart status. Sorting and pagination ensure scalable
   * listing even with large data volumes.
   *
   * Access control restricts viewing to authorized users, typically platform
   * administrators or customer support. Returned data includes cart summaries
   * optimized for display in list views.
   *
   * Errors are raised for invalid search parameters. Related endpoints include
   * individual cart retrieval and cart modification operations.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for shopping carts
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallShoppingCart.IRequest,
  ): Promise<IPageIShoppingMallShoppingCart.ISummary> {
    try {
      return await patchShoppingMallAdminShoppingCarts({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
