import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallAdminCustomerInquiries } from "../../../../providers/patchShoppingMallAdminCustomerInquiries";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

import { IPageIShoppingMallCustomerInquiry } from "../../../../api/structures/IPageIShoppingMallCustomerInquiry";
import { IShoppingMallCustomerInquiry } from "../../../../api/structures/IShoppingMallCustomerInquiry";

@Controller("/shoppingMall/admin/customerInquiries")
export class ShoppingmallAdminCustomerinquiriesController {
  /**
   * Search and retrieve a paginated list of customer inquiries.
   *
   * Retrieve a filtered and paginated list of customer inquiries submitted by
   * users of the shopping mall platform.
   *
   * This operation supports advanced search capabilities, allowing filtering by
   * inquiry status, customer email or ID, submission date ranges, and keywords
   * in the inquiry content.
   *
   * Pagination parameters allow controlling the size and number of pages
   * returned, ensuring efficient data retrieval for UI display.
   *
   * Security: Access to customer inquiries may be restricted to customer
   * support staff or administrators to protect user privacy.
   *
   * Integrates with the ShoppingMallCustomerInquiries Prisma table, utilizing
   * all searchable fields defined in the schema.
   *
   * Related operations: Viewing inquiry details (GET
   * /customerInquiries/{inquiryId}), answering inquiries (POST
   * /customerInquiries/{inquiryId}/answer).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   customer inquiries
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCustomerInquiry.IRequest,
  ): Promise<IPageIShoppingMallCustomerInquiry.ISummary> {
    try {
      return await patchShoppingMallAdminCustomerInquiries({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
