import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallAdminShoppingMallPayments } from "../../../../providers/patchShoppingMallAdminShoppingMallPayments";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

import { IPageIShoppingMallPayment } from "../../../../api/structures/IPageIShoppingMallPayment";
import { IShoppingMallPayment } from "../../../../api/structures/IShoppingMallPayment";

@Controller("/shoppingMall/admin/shoppingMallPayments")
export class ShoppingmallAdminShoppingmallpaymentsController {
  /**
   * Search and retrieve a filtered, paginated list of payments.
   *
   * Retrieve a filtered, paginated list of payments within the shopping mall
   * platform.
   *
   * Clients can provide advanced filtering options in the request to query
   * payments by various criteria such as status, date range, payment type, and
   * associated order details.
   *
   * The response includes summaries of each payment matching the criteria,
   * along with pagination metadata. Access is restricted to administrators for
   * confidentiality and financial compliance.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for payment filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPayment.IRequest,
  ): Promise<IPageIShoppingMallPayment.ISummary> {
    try {
      return await patchShoppingMallAdminShoppingMallPayments({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
