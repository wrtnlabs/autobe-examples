import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminCouponsCouponCodeRedemptions } from "../../../../../providers/patchShoppingMallAdminCouponsCouponCodeRedemptions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCouponsCouponCodeRedemptionsRedemptionId } from "../../../../../providers/getShoppingMallAdminCouponsCouponCodeRedemptionsRedemptionId";
import { deleteShoppingMallAdminCouponsCouponCodeRedemptionsRedemptionId } from "../../../../../providers/deleteShoppingMallAdminCouponsCouponCodeRedemptionsRedemptionId";

import { IPageIShoppingMallCouponRedemption } from "../../../../../api/structures/IPageIShoppingMallCouponRedemption";
import { IShoppingMallCouponRedemption } from "../../../../../api/structures/IShoppingMallCouponRedemption";

@Controller("/shoppingMall/admin/coupons/:couponCode/redemptions")
export class ShoppingmallAdminCouponsRedemptionsController {
  /**
   * Search and retrieve paginated coupon redemption records for a coupon.
   *
   * Retrieve a filtered and paginated list of coupon redemptions for the
   * specified coupon identified by couponCode.
   *
   * This operation allows clients to search and filter coupon redemption
   * records associated with a particular coupon. It supports pagination to
   * handle large result sets efficiently and sorting by various redemption
   * attributes.
   *
   * Security considerations include validating user permissions to view
   * redemption records. Typical users for this API are administrators and
   * coupon management staff who need detailed views of coupon usage.
   *
   * This operation interacts directly with the shopping_mall_coupon_redemptions
   * table in the Prisma schema, including references to customers and orders
   * associated with each redemption.
   *
   * @param connection
   * @param couponCode Unique business identifier code of the target coupon
   *   (global scope)
   * @param body Search criteria and pagination parameters for coupon
   *   redemptions filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("couponCode")
    couponCode: string,
    @TypedBody()
    body: IShoppingMallCouponRedemption.IRequest,
  ): Promise<IPageIShoppingMallCouponRedemption.ISummary> {
    try {
      return await patchShoppingMallAdminCouponsCouponCodeRedemptions({
        admin,
        couponCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve coupon redemption details by redemptionId.
   *
   * Retrieve a single coupon redemption record by its unique redemptionId
   * associated with the specified couponCode.
   *
   * The operation fetches all details relevant to the coupon redemption,
   * enabling administrative users to review redemption history accurately.
   *
   * Security: Access is limited to users with admin role to protect sensitive
   * coupon redemption data.
   *
   * This API operation maps to the shopping_mall_coupon_redemptions table in
   * the Prisma schema and returns the full redemption object.
   *
   * @param connection
   * @param couponCode Unique business identifier code of the target coupon
   *   (global scope)
   * @param redemptionId Unique identifier of the coupon redemption
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":redemptionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("couponCode")
    couponCode: string,
    @TypedParam("redemptionId")
    redemptionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCouponRedemption> {
    try {
      return await getShoppingMallAdminCouponsCouponCodeRedemptionsRedemptionId(
        {
          admin,
          couponCode,
          redemptionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific coupon redemption by coupon code and redemption ID.
   *
   * Permanently removes a coupon redemption record from the system. This
   * enables administrators or authorized users to revoke a previously recorded
   * redemption of a coupon by a customer, which may be necessary in cases of
   * error or fraud.
   *
   * The operation requires both the unique coupon code and the redemption
   * record identifier to ensure precise targeting. This is a hard delete
   * removing the record entirely from the database.
   *
   * Access to this endpoint should be restricted to authorized users with admin
   * or equivalent permissions since it affects marketing coupon usage
   * statistics and customer entitlements.
   *
   * Related operations include managing coupons themselves and querying
   * redemption lists.
   *
   * @param connection
   * @param couponCode Unique business identifier code of the target coupon
   *   (global scope)
   * @param redemptionId Unique identifier of the target coupon redemption
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":redemptionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("couponCode")
    couponCode: string,
    @TypedParam("redemptionId")
    redemptionId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCouponsCouponCodeRedemptionsRedemptionId(
        {
          admin,
          couponCode,
          redemptionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
