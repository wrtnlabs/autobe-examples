import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallAdminCoupons } from "../../../../providers/postShoppingMallAdminCoupons";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminCoupons } from "../../../../providers/patchShoppingMallAdminCoupons";
import { getShoppingMallAdminCouponsCouponCode } from "../../../../providers/getShoppingMallAdminCouponsCouponCode";
import { putShoppingMallAdminCouponsCouponCode } from "../../../../providers/putShoppingMallAdminCouponsCouponCode";
import { deleteShoppingMallAdminCouponsCouponCode } from "../../../../providers/deleteShoppingMallAdminCouponsCouponCode";

import { IShoppingMallCoupon } from "../../../../api/structures/IShoppingMallCoupon";
import { IPageIShoppingMallCoupon } from "../../../../api/structures/IPageIShoppingMallCoupon";

@Controller("/shoppingMall/admin/coupons")
export class ShoppingmallAdminCouponsController {
  /**
   * Create a new marketing coupon.
   *
   * This API operation allows administrative users to create new marketing
   * coupons by providing necessary coupon attributes such as code, discount
   * type, discount value, validity periods, and optional usage restrictions.
   *
   * Coupons serve as promotional tools to offer discounts to customers during
   * checkout. The system validates the uniqueness of the coupon code and
   * enforces all business rules regarding discount values and date windows.
   *
   * Only users with admin privileges can perform this action to ensure control
   * over promotional activities.
   *
   * Related operations include retrieving coupon details and listing all
   * coupons.
   *
   * @param connection
   * @param body Data required to create a new shopping mall coupon
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCoupon.ICreate,
  ): Promise<IShoppingMallCoupon> {
    try {
      return await postShoppingMallAdminCoupons({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated list of shopping mall coupons.
   *
   * Retrieve and search through the list of marketing coupons configured in the
   * shopping mall platform.
   *
   * This operation supports advanced filtering and sorting capabilities,
   * allowing admins to find coupons by code, expiration date, discount amount,
   * and usage limitations.
   *
   * Security: Access to this listing is restricted to administrative roles to
   * prevent unauthorized viewing or modification.
   *
   * The response includes summary information of coupons suitable for list
   * displays, along with metadata for pagination to support efficient
   * browsing.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for coupon filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCoupon.IRequest,
  ): Promise<IPageIShoppingMallCoupon.ISummary> {
    try {
      return await patchShoppingMallAdminCoupons({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific coupon by coupon code.
   *
   * This API operation fetches the details of a specific marketing coupon
   * identified by its unique coupon code.
   *
   * The coupon is part of the shopping mall promotional system that manages
   * discount offers for customers. Users can query active, expired, or disabled
   * coupons to view their attributes including discount type, value, validity
   * period, and usage restrictions.
   *
   * Security considerations ensure only authorized users access this
   * information. The coupon code is validated to be unique, and the system
   * returns comprehensive details or an error if not found.
   *
   * This operation has no request body as parameters only include the coupon
   * code in the URL.
   *
   * Related operations include creating new coupons and listing all available
   * coupons.
   *
   * @param connection
   * @param couponCode Unique business identifier code of the target coupon
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":couponCode")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("couponCode")
    couponCode: string,
  ): Promise<IShoppingMallCoupon> {
    try {
      return await getShoppingMallAdminCouponsCouponCode({
        admin,
        couponCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a coupon by its unique code.
   *
   * Update an existing marketing coupon by its unique code.
   *
   * This operation enables administrators to modify the properties of a coupon,
   * including discount amounts, usage restrictions, and validity dates. Only
   * authorized admin users can perform this update, ensuring secure management
   * of promotional tools.
   *
   * The couponCode path parameter uniquely identifies the coupon, referencing
   * the shopping_mall_coupons table's unique code field.
   *
   * Proper validation is performed to ensure updated values conform to business
   * rules and schema constraints. Unauthorized users cannot access this
   * endpoint.
   *
   * Related operations include creating a coupon (POST /coupons) and deleting a
   * coupon (DELETE /coupons/{couponCode}).
   *
   * @param connection
   * @param couponCode Unique business identifier code of the target coupon
   *   (global scope)
   * @param body Payload containing updated coupon details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":couponCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("couponCode")
    couponCode: string,
    @TypedBody()
    body: IShoppingMallCoupon.IUpdate,
  ): Promise<IShoppingMallCoupon> {
    try {
      return await putShoppingMallAdminCouponsCouponCode({
        admin,
        couponCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a coupon by its unique code permanently from the system.
   *
   * This operation allows authorized administrators to remove a coupon,
   * preventing any further usage or reference in the shopping mall system. It
   * performs a hard delete, permanently eliminating the coupon record from the
   * database.
   *
   * The couponCode parameter specifies the target coupon definitively by
   * referencing the unique code field in the shopping_mall_coupons table.
   *
   * Only users with admin privileges can access this endpoint, maintaining
   * system integrity and security.
   *
   * Related operations: Update coupon (PUT /coupons/{couponCode}), Create
   * coupon (POST /coupons).
   *
   * @param connection
   * @param couponCode Unique business identifier code of the target coupon
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":couponCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("couponCode")
    couponCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCouponsCouponCode({
        admin,
        couponCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
