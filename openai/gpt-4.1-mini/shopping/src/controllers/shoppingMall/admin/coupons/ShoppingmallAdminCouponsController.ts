import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallAdminCoupons } from "../../../../providers/postShoppingMallAdminCoupons";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminCouponsCouponCode } from "../../../../providers/putShoppingMallAdminCouponsCouponCode";
import { deleteShoppingMallAdminCouponsCouponCode } from "../../../../providers/deleteShoppingMallAdminCouponsCouponCode";

import { IShoppingMallCoupon } from "../../../../api/structures/IShoppingMallCoupon";

@Controller("/shoppingMall/admin/coupons")
export class ShoppingmallAdminCouponsController {
  /**
   * Create a new promotional coupon that customers can use to receive discounts
   * when shopping. The coupon must include a unique code that cannot be
   * duplicated in the system to ensure each promotion is distinct. The type of
   * coupon defines the discount method, such as percentage or fixed amount. The
   * discount_value sets the amount or percentage of the discount applied.
   *
   * This operation requires authentication and authorization to prevent
   * unauthorized coupon creation. Only privileged users such as platform
   * administrators should be allowed to create coupons.
   *
   * The validity period is specified using start_date and end_date timestamps
   * that define when the coupon can be used. The coupon also supports soft
   * deletion, so deleted coupons are marked with a deleted_at timestamp without
   * removal from the database.
   *
   * Related operations include updating existing coupons and retrieving coupon
   * details.
   *
   * Security considerations include validating unique coupon codes, verifying
   * discount values, and enforcing start and end date logic.
   *
   * @param connection
   * @param body Coupon creation payload containing unique code, type, discount
   *   value, and validity period
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCoupon.ICreate,
  ): Promise<IShoppingMallCoupon> {
    try {
      return await postShoppingMallAdminCoupons({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update properties of an existing coupon identified by its unique
   * couponCode. This allows administrators to adjust the discount type, amount,
   * or validity dates of promotional campaigns.
   *
   * Authentication and appropriate permissions are required to perform updates
   * on coupons. Only authorized admins can modify coupon data.
   *
   * The couponCode path parameter uniquely identifies the coupon within the
   * system. It maps to the code field which is marked unique in the Prisma
   * schema.
   *
   * The operation validates that the updated coupon code remains unique and the
   * discount value remains valid for the given coupon type. Soft deletion
   * status can be maintained but not manipulated directly.
   *
   * Related operations include coupon creation and retrieval of coupon details.
   *
   * Security includes access control, validation of inputs, and stable
   * persistence of coupon data without data corruption or duplication errors.
   *
   * @param connection
   * @param couponCode Unique business identifier code of the target coupon
   *   (global scope)
   * @param body Coupon update payload containing modified fields for the coupon
   *   identified by couponCode
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":couponCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("couponCode")
    couponCode: string,
    @TypedBody()
    body: IShoppingMallCoupon.IUpdate,
  ): Promise<IShoppingMallCoupon> {
    try {
      return await putShoppingMallAdminCouponsCouponCode({
        admin,
        couponCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete the coupon identified by the given couponCode from the
   * shopping mall platform.
   *
   * This operation is restricted to administrative users due to the critical
   * nature of coupon management. Coupons represent special promotions and
   * discounts, so improper deletion could affect sales and customer
   * experience.
   *
   * The couponCode path parameter uniquely identifies the coupon to delete,
   * based on the unique code field defined in the shopping_mall_coupons table.
   * The operation performs hard deletion, permanently removing the record from
   * the database.
   *
   * There is no request body since the coupon code in the path suffices to
   * identify the record. Successful execution results in the permanent removal
   * of the coupon, and associated coupon usages become invalid.
   *
   * Authorization: Only users with admin roles are allowed to perform this
   * operation.
   *
   * Related operations: Creating coupons (POST /coupons), retrieving coupons
   * (GET /coupons/{couponCode}), viewing coupon usage records (PATCH
   * /couponUsages).
   *
   * @param connection
   * @param couponCode Unique business identifier code of the target coupon
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":couponCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("couponCode")
    couponCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCouponsCouponCode({
        admin,
        couponCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
