import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminShoppingMallOrderCancellations } from "../../../../providers/postShoppingMallAdminShoppingMallOrderCancellations";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminShoppingMallOrderCancellations } from "../../../../providers/patchShoppingMallAdminShoppingMallOrderCancellations";
import { getShoppingMallAdminShoppingMallOrderCancellationsShoppingMallOrderCancellationId } from "../../../../providers/getShoppingMallAdminShoppingMallOrderCancellationsShoppingMallOrderCancellationId";

import { IShoppingMallOrderCancellation } from "../../../../api/structures/IShoppingMallOrderCancellation";
import { IPageIShoppingMallOrderCancellation } from "../../../../api/structures/IPageIShoppingMallOrderCancellation";

@Controller("/shoppingMall/admin/shoppingMallOrderCancellations")
export class ShoppingmallAdminShoppingmallordercancellationsController {
  /**
   * Create a new shopping mall order cancellation request with the provided
   * cancellation details.
   *
   * This operation initiates the cancellation workflow, enabling customers to
   * request order cancellations with valid reasons. Submitted data is validated
   * against the shopping_mall_order_cancellations schema to ensure completeness
   * and correctness.
   *
   * Authorization restricts access to authorized roles including customers,
   * sellers, and admins, ensuring only legitimate requests can be created.
   *
   * The response includes the full newly created cancellation record.
   *
   * Related endpoints include retrieving existing cancellations (GET
   * /shoppingMallOrderCancellations/{id}) and searching multiple
   * cancellations.
   *
   * @param connection
   * @param body Order cancellation request data adhering to
   *   IShoppingMallOrderCancellation.ICreate
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallOrderCancellation.ICreate,
  ): Promise<IShoppingMallOrderCancellation> {
    try {
      return await postShoppingMallAdminShoppingMallOrderCancellations({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve order cancellation requests.
   *
   * Retrieve a filtered and paginated list of customer-submitted order
   * cancellation requests.
   *
   * This operation allows administrative users to search cancellations based on
   * multiple criteria such as date requested, order ID, customer ID, and
   * cancellation status.
   *
   * The results provide summarized information for display in administrative
   * interfaces for order management and customer support.
   *
   * Authorization ensures only users with administrative roles can access this
   * sensitive information.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for order
   *   cancellation filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallOrderCancellation.IRequest,
  ): Promise<IPageIShoppingMallOrderCancellation.ISummary> {
    try {
      return await patchShoppingMallAdminShoppingMallOrderCancellations({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific shopping mall order cancellation request.
   *
   * Retrieve detailed information about a specific shopping mall order
   * cancellation using its unique identifier.
   *
   * This operation supports customer service and administrative workflows by
   * providing insights into the reasons, statuses, and details of individual
   * cancellation requests. It returns all data fields as defined in the
   * shopping_mall_order_cancellations database table.
   *
   * Security measures ensure only authorized actors such as customers, sellers,
   * or admins can access cancellation details to protect sensitive
   * transactional information.
   *
   * Related operations include creating new cancellation requests (POST
   * /shoppingMallOrderCancellations) and searching/listing order
   * cancellations.
   *
   * @param connection
   * @param shoppingMallOrderCancellationId Unique UUID identifier of the
   *   shopping mall order cancellation request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shoppingMallOrderCancellationId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shoppingMallOrderCancellationId")
    shoppingMallOrderCancellationId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderCancellation> {
    try {
      return await getShoppingMallAdminShoppingMallOrderCancellationsShoppingMallOrderCancellationId(
        {
          admin,
          shoppingMallOrderCancellationId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
