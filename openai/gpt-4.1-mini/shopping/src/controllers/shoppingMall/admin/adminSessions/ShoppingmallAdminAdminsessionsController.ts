import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminAdminSessions } from "../../../../providers/patchShoppingMallAdminAdminSessions";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminAdminSessionsId } from "../../../../providers/getShoppingMallAdminAdminSessionsId";

import { IPageIShoppingMallAdminSession } from "../../../../api/structures/IPageIShoppingMallAdminSession";
import { IShoppingMallAdminSession } from "../../../../api/structures/IShoppingMallAdminSession";

@Controller("/shoppingMall/admin/adminSessions")
export class ShoppingmallAdminAdminsessionsController {
  /**
   * List and search admin user sessions with filters and pagination.
   *
   * Retrieve a paged and filtered list of admin user sessions.
   *
   * Admins can filter sessions by admin user ID, session creation timestamp,
   * and expiration status.
   *
   * The operation returns summarized session information including IP,
   * referrer, and timestamps.
   *
   * Authorization is required for admin actors to access sensitive session
   * data.
   *
   * Supports pagination, sorting, and search parameters as per
   * 'IShoppingMallAdminSession.IRequest' schema in the request body.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for admin sessions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAdminSession.IRequest,
  ): Promise<IPageIShoppingMallAdminSession.ISummary> {
    try {
      return await patchShoppingMallAdminAdminSessions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed shopping mall admin session by ID.
   *
   * Retrieve detailed information of a shopping mall admin session using its
   * unique identifier. This session represents an authenticated login instance
   * for an admin user, capturing relevant security data such as IP address,
   * initiation URL, and session expiration (if any).
   *
   * Authentication and authorization are required, limiting access to admin
   * roles exclusively to protect sensitive security information.
   *
   * The data returned includes all fields from the shopping_mall_admin_sessions
   * table, excluding soft-deleted entries. This operation helps administrators
   * monitor active and historical sessions, supporting security compliance and
   * incident response.
   *
   * Path parameter `id` corresponds to the UUID of the target admin session.
   *
   * No request body is required. The response returns a single admin session
   * record matching the specified ID. If the record does not exist or is
   * soft-deleted, a 404 response is expected.
   *
   * Successful response returns the complete shopping_mall_admin_sessions
   * object representing the admin session.
   *
   * Related operations include listing all admin sessions (not implemented
   * here) and creating admin sessions upon login (system-internal).
   *
   * @param connection
   * @param id Unique identifier (UUID) of the admin session to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdminSession> {
    try {
      return await getShoppingMallAdminAdminSessionsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
