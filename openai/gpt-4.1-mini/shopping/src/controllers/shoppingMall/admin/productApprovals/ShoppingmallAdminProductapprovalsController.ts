import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminProductApprovals } from "../../../../providers/patchShoppingMallAdminProductApprovals";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminProductApprovalsId } from "../../../../providers/getShoppingMallAdminProductApprovalsId";

import { IPageIShoppingMallProductApproval } from "../../../../api/structures/IPageIShoppingMallProductApproval";
import { IShoppingMallProductApproval } from "../../../../api/structures/IShoppingMallProductApproval";

@Controller("/shoppingMall/admin/productApprovals")
export class ShoppingmallAdminProductapprovalsController {
  /**
   * Retrieve a list of product approval records for admin review.
   *
   * Retrieve a paginated, filterable list of product approval records
   * maintained in the shopping_mall_product_approvals table. Each record links
   * to a product and an admin who approved or rejected it and includes a status
   * and optional reason for rejection.
   *
   * This operation is intended for platform administrators managing product
   * moderation workflows. Only authenticated admins can access this endpoint.
   *
   * The product approval records reflect the state of seller-submitted products
   * awaiting admin approval, showing status such as pending, approved, or
   * rejected. The list enables admins to efficiently review and take further
   * actions.
   *
   * Security considerations involve restricting access to admin roles. The
   * system must handle large result sets with pagination to ensure performance
   * and usability.
   *
   * Related API operations include single product approval retrieval, product
   * listing endpoints, and admin dashboard features.
   *
   * This query uses the shopping_mall_product_approvals table for sustained
   * product moderation tracking.
   *
   * @param connection
   * @param body Search parameters and pagination filters for product approvals
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallProductApproval.IRequest,
  ): Promise<IPageIShoppingMallProductApproval.ISummary> {
    try {
      return await patchShoppingMallAdminProductApprovals({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single product approval record by ID.
   *
   * Retrieve detailed information for a specific product approval identified by
   * its unique ID from the system.
   *
   * This operation supports administrative workflows where admins view the
   * status and details of product approvals for quality control, compliance,
   * and moderation.
   *
   * Security: Access is restricted to platform administrators only.
   *
   * Details include the referenced product, admin user, approval status, reason
   * for status, and timestamps for creation and last updates.
   *
   * This is essential for deep inspection following up administrative product
   * approval processes.
   *
   * Related operations include the product approvals list endpoint and product
   * management features.
   *
   * @param connection
   * @param id Unique identifier of the target product approval record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductApproval> {
    try {
      return await getShoppingMallAdminProductApprovalsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
