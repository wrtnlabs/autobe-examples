import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminAdminActivities } from "../../../../providers/patchShoppingMallAdminAdminActivities";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminAdminActivitiesId } from "../../../../providers/getShoppingMallAdminAdminActivitiesId";

import { IPageIShoppingMallAdminActivity } from "../../../../api/structures/IPageIShoppingMallAdminActivity";
import { IShoppingMallAdminActivity } from "../../../../api/structures/IShoppingMallAdminActivity";

@Controller("/shoppingMall/admin/adminActivities")
export class ShoppingmallAdminAdminactivitiesController {
  /**
   * Search and retrieve a filtered, paginated list of shopping mall admin
   * activities.
   *
   * Retrieve a filtered and paginated list of administrative activities
   * recorded in the platform. Each activity log entry records the admin user
   * who performed the action, a descriptive message detailing the nature of the
   * activity, and timestamps marking when the action occurred and any
   * subsequent updates.
   *
   * This operation supports pagination and filtering to allow administrators to
   * efficiently query large volumes of audit log data by relevant criteria such
   * as date ranges or specific admin users.
   *
   * Security considerations require that only admins can access this endpoint
   * to protect sensitive operational data. Logs are immutable and cannot be
   * altered by users.
   *
   * The underlying data corresponds to the shopping_mall_admin_activities
   * table, ensuring accurate real-time reflection of admin actions logged in
   * the system.
   *
   * This operation complements endpoints that retrieve individual admin
   * activity details and supports regulatory compliance through system activity
   * tracing.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for admin activity
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAdminActivity.IRequest,
  ): Promise<IPageIShoppingMallAdminActivity.ISummary> {
    try {
      return await patchShoppingMallAdminAdminActivities({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific shopping mall admin activity by ID.
   *
   * Retrieve comprehensive details of a single shopping mall admin activity log
   * entry by its ID. The response includes the unique identifier of the
   * activity, the admin user responsible, a detailed description of the logged
   * action, and timestamps reflecting when the entry was created and last
   * updated.
   *
   * Access to this endpoint is restricted to admin users to protect sensitive
   * audit information.
   *
   * This enables audit review, compliance monitoring, and forensic
   * investigation of administrative actions within the platform.
   *
   * The underlying data is sourced from the shopping_mall_admin_activities
   * table in the Prisma schema, ensuring fidelity and consistency.
   *
   * @param connection
   * @param id Unique identifier of the target admin activity log entry
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdminActivity> {
    try {
      return await getShoppingMallAdminAdminActivitiesId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
