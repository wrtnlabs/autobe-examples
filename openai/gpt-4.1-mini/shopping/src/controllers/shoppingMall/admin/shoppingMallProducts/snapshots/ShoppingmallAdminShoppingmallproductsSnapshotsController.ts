import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminShoppingMallProductsSnapshots } from "../../../../../providers/patchShoppingMallAdminShoppingMallProductsSnapshots";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminShoppingMallProductsSnapshotsId } from "../../../../../providers/getShoppingMallAdminShoppingMallProductsSnapshotsId";

import { IPageIShoppingMallProductSnapshot } from "../../../../../api/structures/IPageIShoppingMallProductSnapshot";
import { IShoppingMallProductSnapshot } from "../../../../../api/structures/IShoppingMallProductSnapshot";

@Controller("/shoppingMall/admin/shoppingMallProducts/snapshots")
export class ShoppingmallAdminShoppingmallproductsSnapshotsController {
  /**
   * Retrieve a filtered and paginated list of shopping mall product snapshots
   * representing historical product data at specific points in time.
   *
   * Clients can use various search criteria such as snapshot date ranges,
   * product identifiers, and status filters to find relevant snapshots.
   * Pagination controls allow efficient browsing through large datasets.
   *
   * Security considerations include ensuring only authorized users can access
   * snapshots due to potential sensitive historical data.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for product snapshot
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallProductSnapshot.IRequest,
  ): Promise<IPageIShoppingMallProductSnapshot.ISummary> {
    try {
      return await patchShoppingMallAdminShoppingMallProductsSnapshots({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a shopping mall product snapshot by its
   * unique identifier.
   *
   * This is typically used by administrators to view historical product
   * information for audit, compliance, or troubleshooting purposes.
   *
   * Access is restricted to authorized admin users to protect sensitive
   * historical data.
   *
   * @param connection
   * @param id Unique identifier of the target shopping mall product snapshot
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductSnapshot> {
    try {
      return await getShoppingMallAdminShoppingMallProductsSnapshotsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
