import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminPoints } from "../../../../providers/patchShoppingMallAdminPoints";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminPointsPointId } from "../../../../providers/putShoppingMallAdminPointsPointId";
import { deleteShoppingMallAdminPointsPointId } from "../../../../providers/deleteShoppingMallAdminPointsPointId";

import { IPageIShoppingMallPoints } from "../../../../api/structures/IPageIShoppingMallPoints";
import { IShoppingMallPoints } from "../../../../api/structures/IShoppingMallPoints";
import { IShoppingMallPoint } from "../../../../api/structures/IShoppingMallPoint";

@Controller("/shoppingMall/admin/points")
export class ShoppingmallAdminPointsController {
  /**
   * Retrieve a paginated list of shopping mall customer points based on complex
   * search parameters. This operation allows clients to filter by customer,
   * point balance ranges, date ranges, and sort results as needed.
   *
   * Response includes summary information that enables display in paginated
   * grids or reports.
   *
   * Security: Access is typically limited to administrative or customer service
   * roles that need detailed loyalty program insights.
   *
   * Related operations include creating and updating point records through
   * other endpoints.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for customer points
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPoints.IRequest,
  ): Promise<IPageIShoppingMallPoints.ISummary> {
    try {
      return await patchShoppingMallAdminPoints({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing customer point record identified by its unique ID.
   *
   * This operation allows the authorized user to modify fields such as the
   * current point balance and soft deletion timestamp. It ensures that point
   * balances reflect recent transactions or manual adjustments.
   *
   * Security considerations include ensuring that only users with the
   * appropriate roles can perform point modifications, preventing fraudulent
   * changes.
   *
   * Related operations are retrieving point details and deleting a point
   * record.
   *
   * The fields 'created_at' and 'updated_at' are managed by the system and not
   * exposed for update.
   *
   * Errors occur if the specified point ID does not exist.
   *
   * @param connection
   * @param pointId Unique identifier of the target point record
   * @param body Data payload for updating the point record fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":pointId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("pointId")
    pointId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallPoint.IUpdate,
  ): Promise<IShoppingMallPoint> {
    try {
      return await putShoppingMallAdminPointsPointId({
        admin,
        pointId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Deletes a loyalty point record identified by its unique ID. This operation
   * performs a hard deletion, permanently removing the record from the
   * database.
   *
   * Security considerations restrict this operation to admin users only due to
   * the irreversible nature of the removal.
   *
   * Related operations include updating point records and retrieving point
   * details.
   *
   * Errors occur if the specified point ID does not exist.
   *
   * @param connection
   * @param pointId Unique identifier of the target point record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":pointId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("pointId")
    pointId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminPointsPointId({
        admin,
        pointId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
