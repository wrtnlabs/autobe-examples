import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallFaqs } from "../../../providers/patchShoppingMallFaqs";
import { getShoppingMallFaqsId } from "../../../providers/getShoppingMallFaqsId";

import { IPageIShoppingMallFaq } from "../../../api/structures/IPageIShoppingMallFaq";
import { IShoppingMallFaq } from "../../../api/structures/IShoppingMallFaq";

@Controller("/shoppingMall/faqs")
export class ShoppingmallFaqsController {
  /**
   * Search and retrieve a paginated list of shopping mall FAQs.
   *
   * Retrieve a paginated list of frequently asked questions (FAQs) available in
   * the shopping mall platform.
   *
   * This operation allows clients to perform complex search queries filtering
   * FAQs by keywords, associated categories, and FAQ status. Pagination
   * parameters help manage large result sets and sorting options enable
   * ordering results by date, popularity, or relevance.
   *
   * Access to this operation is public and requires no authentication, enabling
   * anonymous users to browse FAQ content for self-service support.
   *
   * This operation interfaces with the shopping_mall_faqs table, returning
   * summaries of FAQ entries optimized for listing contexts.
   *
   * @param connection
   * @param body Search and pagination parameters for filtering FAQs
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallFaq.IRequest,
  ): Promise<IPageIShoppingMallFaq.ISummary> {
    try {
      return await patchShoppingMallFaqs({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve single FAQ details by ID.
   *
   * Retrieve detailed information of a specific FAQ entry by its unique
   * identifier.
   *
   * This operation provides full FAQ content including question, answer,
   * creation and modification metadata.
   *
   * It serves public read-only access allowing any user to view FAQ details
   * without authentication.
   *
   * The ID parameter is a UUID referencing the target FAQ in the database.
   *
   * @param connection
   * @param id Unique identifier of the target FAQ entry
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallFaq> {
    try {
      return await getShoppingMallFaqsId({
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
