import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallSaleReview } from "../../../../api/structures/IPageIShoppingMallSaleReview";
import { IShoppingMallSaleReview } from "../../../../api/structures/IShoppingMallSaleReview";
import { getShoppingMallSalesSaleIdReviewsReviewId } from "../../../../providers/getShoppingMallSalesSaleIdReviewsReviewId";
import { patchShoppingMallSalesSaleIdReviews } from "../../../../providers/patchShoppingMallSalesSaleIdReviews";

@Controller("/shoppingMall/sales/:saleId/reviews")
export class ShoppingmallSalesReviewsController {
  /**
   * Retrieve a paginated, filtered list of customer reviews for a specific sale product listing. The reviews include star ratings and optional text, authored by customers after delivery. Each review is linked to a sale and customer with traceability.
   *
   * This operation allows clients to search, filter, and paginate through reviews for the given saleId, supporting sorting and optional review text matching.
   *
   * Authorization should ensure only appropriate actors (e.g., customers and administrators) can access this data.
   *
   * The reviews correspond to the shopping_mall_sale_reviews table, which stores rating (1-5 stars) and optional body text, along with creation, update, and soft deletion timestamps.
   *
   * Typical usages include product detail pages displaying customer feedback, aggregated ratings, and review moderation.
   *
   * Refer to related operations for creating, updating, and deleting reviews, typically managed by customers via other endpoints.
   *
   * This endpoint does not allow modification; it is purely for searching and reading review data.
   *
   * @param connection
   * @param saleId UUID of the sale whose reviews are being searched
   * @param body Search criteria and pagination parameters for sale reviews
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the shopping_mall_sale_reviews table filtering by saleId path parameter. Apply search filters from IShoppingMallSaleReview.IRequest (e.g., rating range, keyword text in review body). Support pagination with page size and cursor or offset.
   *
   * Return paginated list of reviews as IPageIShoppingMallSaleReview.ISummary.
   *
   * Exclude reviews marked as soft-deleted (deleted_at IS NULL).
   *
   * Implement database joins to load customer info as needed.
   *
   * Perform validation on saleId being a valid UUID.
   *
   * Ensure optimized text search on review body with indexes.
   *
   * Support sorting by creation date and rating.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("saleId")
    saleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSaleReview.IRequest,
  ): Promise<IPageIShoppingMallSaleReview.ISummary> {
    try {
      return await patchShoppingMallSalesSaleIdReviews({
        saleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific review associated with a sale.
   *
   * This operation fetches the full details of a customer review for a given sale identified by `saleId` and the specific review identifier `reviewId`. It includes star rating, review text, timestamps, and author information.
   *
   * Only authenticated users with permission to view sales reviews may access this endpoint. The review is linked to the shopping mall sales and sale reviews tables in the database schema, ensuring data integrity and accuracy.
   *
   * This endpoint supports client applications displaying individual review details for customers, sellers, and administrators.
   *
   * Errors are returned if the `saleId` or `reviewId` do not exist or if access is unauthorized.
   *
   * @param connection
   * @param saleId Identifier of the target sale
   * @param reviewId Identifier of the sale review
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Implement GET method to query the shopping_mall_sale_reviews table filtering records by composite key of saleId and reviewId. Validate that saleId and reviewId exist and belong together.
   * Use joins to include related data such as customer profile and sale basic info if needed.
   * Return 404 if the review does not exist or is unauthorized.
   * No request body is expected.
   * Response body should conform to the IShoppingMallSaleReview schema representing the review's full detail.
   * Use efficient indexing on saleId and reviewId for fast retrieval.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reviewId")
  public async at(
    @TypedParam("saleId")
    saleId: string & tags.Format<"uuid">,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSaleReview> {
    try {
      return await getShoppingMallSalesSaleIdReviewsReviewId({
        saleId,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
