import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { postShoppingMallAuthSellerJoin } from "../../../../providers/postShoppingMallAuthSellerJoin";
import { postShoppingMallAuthSellerLogin } from "../../../../providers/postShoppingMallAuthSellerLogin";
import { postShoppingMallAuthSellerRefresh } from "../../../../providers/postShoppingMallAuthSellerRefresh";

@Controller("/shoppingMall/auth/seller")
export class ShoppingmallAuthSellerController {
  /**
   * This API endpoint handles seller account registration, accepting email and password for creating a new seller account. It securely stores password hash, sets approval_status to 'pending', and triggers email verification token creation. The registration process ensures the email is unique and not already in use. It supports the initial onboarding of sellers into the platform before admin approval. Security measures include hashing passwords and preventing duplicate registrations.
   *
   * This operation is crucial for establishing a seller's credentials for subsequent login and authenticated actions.
   *
   * Related operations include login and refresh token to manage session lifecycle.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration data for creating a new account.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification This operation implements seller registration (join) by accepting seller email and password in IShoppingMallSeller.IJoin and returning authorized session tokens in IShoppingMallSeller.IAuthorized. The service layer will validate the uniqueness of email against seller records, hash the password securely before storing, create seller record with pending approval status, and initiate email verification by generating a token stored in seller_email_verifications table. The operation returns JWT tokens for immediate session if applicable or pending state. Edge cases include duplicate email error and validation failures. Integration with email verification ensures only approved sellers can fully activate.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.IJoin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API endpoint performs seller authentication by validating the email and password provided in the request body. It securely compares the password hash stored in the sellers table and upon successful verification, returns JWT tokens required for authenticated sessions. Invalid login attempts are rejected with appropriate error responses.
   *
   * This operation is fundamental to seller access to protected resources and subsequent interactions with the platform.
   *
   * Related operations are join for account creation and refresh for token renewal.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login credentials including email and password.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification This operation handles seller login by validating credentials against stored seller email and password hash. Upon successful validation, JWT tokens are issued for session management. Invalid credentials result in errors. The operation uses the IShoppingMallSeller.ILogin request DTO containing email and password properties. The response IShoppingMallSeller.IAuthorized returns access and refresh tokens along with authentication metadata. This supports secure seller authentication and session state establishment.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.ILogin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API endpoint refreshes the seller's authentication tokens by accepting a refresh token and returning new JWT tokens. The refresh token is validated against the stored sessions and if valid, new access and refresh tokens are issued to maintain continuous authentication without requiring login.
   *
   * This operation is key to sustaining secure session lifecycles with minimal user interruption.
   *
   * Related operations include login for initial authentication and join for account registration.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token request payload for renewing authentication tokens.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification This operation issues new JWT tokens based on a valid refresh token presented in the IShoppingMallSeller.IRefresh request body. It validates the refresh token against active sessions in the seller_sessions table, revokes tokens as necessary, and maintains security by renewing access and refresh tokens. The response includes refreshed token information encapsulated in IShoppingMallSeller.IAuthorized. This enables continuous authenticated session management without repeated login.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallSeller.IRefresh,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
