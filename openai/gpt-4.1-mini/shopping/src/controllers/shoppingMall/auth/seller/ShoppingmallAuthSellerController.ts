import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { postShoppingMallAuthSellerJoin } from "../../../../providers/postShoppingMallAuthSellerJoin";
import { postShoppingMallAuthSellerLogin } from "../../../../providers/postShoppingMallAuthSellerLogin";
import { postShoppingMallAuthSellerRefresh } from "../../../../providers/postShoppingMallAuthSellerRefresh";

@Controller("/shoppingMall/auth/seller")
export class ShoppingmallAuthSellerController {
  /**
   * This API operation enables new sellers to register for the platform. It accepts their registration details including email and password, securely stores their credentials, and creates a new seller account with a pending approval status. This aligns with the 'seller' actor authentication process, requiring account creation before login. Security measures include validation and password hashing. The operation returns an authorization token to the newly registered seller.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Payload for new seller registration.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Service layer handles new seller registration by validating input data, hashing password securely, and storing the new seller record with pending approval status. No login required at registration. JWT token is issued after successful join for immediate access or pending status. Database validation ensures unique emails. Handles errors for duplicate emails and validation failures.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.IJoin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API operation allows registered sellers to authenticate by providing their email and password. Upon successful verification, it issues a JWT token that authorizes subsequent requests. This is essential for member-type actors like sellers to access protected resources. Security includes input validation and token generation with expiration.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Payload for seller login credentials.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Handles seller login by verifying provided credentials against stored records. Validates email and password, and upon success issues a JWT authorization token. Incorrect credentials produce authentication failure response. Employs secure password comparison and timing attack prevention. Supports session management features as per schema if applicable.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.ILogin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API operation provides authenticated sellers the capability to refresh their JWT access tokens using a valid refresh token. This allows maintaining a continuous session without re-authentication. Security measures include validation of the refresh token, expiration checks, and issuance of new authorization tokens.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Payload requiring refresh token for session continuation.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Processes token refresh requests to issue new JWT tokens extending the session validity for authenticated sellers. Validates the refresh token from the request body, checks its expiration and revocation status in the database. Issues a new access token and refresh token if valid. Implements security checks to prevent replay attacks and abuse.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallSeller.IRefresh,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
