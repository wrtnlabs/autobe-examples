import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallAdministrator } from "../../../../api/structures/IShoppingMallAdministrator";
import { postShoppingMallAuthAdministratorJoin } from "../../../../providers/postShoppingMallAuthAdministratorJoin";
import { postShoppingMallAuthAdministratorLogin } from "../../../../providers/postShoppingMallAuthAdministratorLogin";
import { postShoppingMallAuthAdministratorRefresh } from "../../../../providers/postShoppingMallAuthAdministratorRefresh";

@Controller("/shoppingMall/auth/administrator")
export class ShoppingmallAuthAdministratorController {
  /**
   * This POST API endpoint allows new administrators to create accounts within the shopping mall platform. It accepts join request data including credentials necessary for account creation such as email and password. Upon successful registration, the API returns an authorization payload containing JWT access and refresh tokens for authenticated session management. This endpoint ensures new administrators can securely register and gain access to the admin features of the platform.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator join request containing necessary credentials and registration info.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification This operation handles administrator registration ('join') by receiving join details such as email and password, validating input, creating a new administrator account with appropriate role assignment, and returning authorization tokens upon successful creation. Password storage and security compliance are handled at the service layer. This operation integrates with JWT token generation to provide clients with access and refresh tokens to authenticate future requests.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdministrator.IJoin,
  ): Promise<IShoppingMallAdministrator.IAuthorized> {
    try {
      return await postShoppingMallAuthAdministratorJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This POST API endpoint enables administrators to log in using their credentials. It validates the provided email and password combination against the stored administrator accounts. Upon successful authentication, the API returns authorization tokens (JWT) allowing continued access to protected admin resources. This endpoint is critical for secure administrator access control and session establishment.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator login request containing credentials for authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification This operation processes administrator login by validating submitted credentials against stored records, authenticating the administrator, and returning fresh JWT access and refresh tokens. It validates email and password, checks user status, and integrates with session management services to establish authenticated sessions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdministrator.ILogin,
  ): Promise<IShoppingMallAdministrator.IAuthorized> {
    try {
      return await postShoppingMallAuthAdministratorLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This POST API endpoint allows administrators to refresh their JWT access tokens using a valid refresh token. It accepts a refresh request containing the refresh token, validates it, and returns new authorization tokens for uninterrupted authenticated access. This operation supports secure session management by refreshing tokens without requiring credentials input repeatedly.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator token refresh request containing the refresh token.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification This operation handles token refresh requests from authenticated administrators. It validates the provided refresh token, issues new access and refresh tokens upon validation success, ensuring continuous secure access without re-login. The operation verifies token integrity and expiry before updating session tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallAdministrator.IRefresh,
  ): Promise<IShoppingMallAdministrator.IAuthorized> {
    try {
      return await postShoppingMallAuthAdministratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
