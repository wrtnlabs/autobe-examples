import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallAdministrator } from "../../../../api/structures/IShoppingMallAdministrator";
import { postShoppingMallAuthAdministratorJoin } from "../../../../providers/postShoppingMallAuthAdministratorJoin";
import { postShoppingMallAuthAdministratorLogin } from "../../../../providers/postShoppingMallAuthAdministratorLogin";
import { postShoppingMallAuthAdministratorRefresh } from "../../../../providers/postShoppingMallAuthAdministratorRefresh";

@Controller("/shoppingMall/auth/administrator")
export class ShoppingmallAuthAdministratorController {
  /**
   * Allows an administrator to register a new account on the shopping mall platform. The operation receives a request conforming to IShoppingMallAdministrator.IJoin schema with email and password details. Upon success, it returns JWT authorization data via IShoppingMallAdministrator.IAuthorized schema. This endpoint is publicly accessible without prior authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator join request payload including email and password.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Handles administrator account creation by validating and registering new administrators using email and password, storing securely, and generating JWT authorization tokens as per schema specifications.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdministrator.IJoin,
  ): Promise<IShoppingMallAdministrator.IAuthorized> {
    try {
      return await postShoppingMallAuthAdministratorJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Allows an administrator to log in using valid credentials. The request body adheres to IShoppingMallAdministrator.ILogin schema for email and password. Success returns authorization tokens wrapped in IShoppingMallAdministrator.IAuthorized schema. This endpoint does not require prior authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator login request payload with email and password.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Validates administrator credentials and issues JWT access tokens upon successful authentication, enabling administrator session management.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdministrator.ILogin,
  ): Promise<IShoppingMallAdministrator.IAuthorized> {
    try {
      return await postShoppingMallAuthAdministratorLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Enables administrators to renew their JWT tokens to maintain an active session. Accepts a refresh token under the IShoppingMallAdministrator.IRefresh schema and responds with refreshed authorization tokens in IShoppingMallAdministrator.IAuthorized schema. No authentication is required to perform this operation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator token refresh request payload with refresh token.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Allows an administrator to refresh JWT tokens for ongoing session management by validating refresh tokens and issuing new tokens as per schema definitions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallAdministrator.IRefresh,
  ): Promise<IShoppingMallAdministrator.IAuthorized> {
    try {
      return await postShoppingMallAuthAdministratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
