import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";
import { postShoppingMallAuthCustomerJoin } from "../../../../providers/postShoppingMallAuthCustomerJoin";
import { postShoppingMallAuthCustomerLogin } from "../../../../providers/postShoppingMallAuthCustomerLogin";
import { postShoppingMallAuthCustomerRefresh } from "../../../../providers/postShoppingMallAuthCustomerRefresh";

@Controller("/shoppingMall/auth/customer")
export class ShoppingmallAuthCustomerController {
  /**
   * This API endpoint enables new customers to register an account with the shopping mall platform.
   *
   * The primary input fields are `email` and `password` which correspond to the `email` and `password_hash` fields in the `shopping_mall_customers` database table.
   *
   * The system ensures email uniqueness and securely stores the password as a hash.
   *
   * Successful registration returns authorization tokens encapsulated in the response type IShoppingMallCustomer.IAuthorized, which clients use to authenticate subsequent requests.
   *
   * This endpoint is public and does not require prior authentication.
   *
   * Flow:
   * - The client submits email and password.
   * - The service hashes the password and saves the record.
   * - On success, the service returns access and refresh tokens.
   *
   * Errors include duplicate email and invalid input validation failures.
   *
   * This operation is critical for membership onboarding and must be secure and performant.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body The request body for customer registration containing email and password credentials.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification This join operation creates a new customer account by accepting email and password credentials. The service will hash the password and store the email and hashed password in the customers table. It validates email uniqueness and returns an authorization token upon successful registration.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.IJoin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API endpoint allows existing customers to log in to their account using email and password.
   *
   * It uses the `email` and `password_hash` fields in the `shopping_mall_customers` database table to validate credentials.
   *
   * Upon successful authentication, it returns authorization tokens including access and refresh tokens.
   *
   * This endpoint is public and requires no prior authentication.
   *
   * Flow:
   * - The client sends email and password.
   * - The service verifies the password by hashing and comparing.
   * - On success, it returns new access and refresh tokens.
   *
   * Invalid credentials return appropriate error responses.
   *
   * This operation provides core authentication functionality enabling member access.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body The request body for customer login containing email and password credentials.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification This login operation authenticates existing customers by verifying their email and password against stored credentials. Upon successful validation, it issues new authorization tokens for session management.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.ILogin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API endpoint refreshes authorization tokens for authenticated customers.
   *
   * Clients provide a valid refresh token to obtain a new access token without re-entering credentials.
   *
   * This helps maintain user sessions securely.
   *
   * The endpoint is public as it does not require current access token, only the refresh token.
   *
   * Flow:
   * - Client submits refresh token.
   * - Service validates the refresh token.
   * - On success, service issues new access and refresh tokens.
   *
   * Expired or invalid refresh tokens return error responses.
   *
   * This operation is essential for secure session management with JWT token expiration.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body The request body containing the refresh token to renew authorization.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification This refresh operation renews a customer's access token using a valid refresh token to maintain session continuity without requiring re-authentication.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallCustomer.IRefresh,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
