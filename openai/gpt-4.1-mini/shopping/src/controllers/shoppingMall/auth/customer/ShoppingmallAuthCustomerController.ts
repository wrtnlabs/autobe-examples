import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";
import { postShoppingMallAuthCustomerJoin } from "../../../../providers/postShoppingMallAuthCustomerJoin";
import { postShoppingMallAuthCustomerLogin } from "../../../../providers/postShoppingMallAuthCustomerLogin";
import { postShoppingMallAuthCustomerRefresh } from "../../../../providers/postShoppingMallAuthCustomerRefresh";

@Controller("/shoppingMall/auth/customer")
export class ShoppingmallAuthCustomerController {
  /**
   * This API endpoint allows new customers to register an account in the shopping mall platform. It accepts user registration data including email and password, enforcing validation rules like unique email constraints from the database schema. Upon successful registration, the response returns authorized session information with JWT tokens enabling authenticated usage of the platform.
   *
   * From a security perspective, user credentials are validated and stored securely. No authentication is required to access this endpoint since it serves anonymous users wishing to join the platform.
   *
   * This operation is part of the overall authentication workflow, preceding login and token refresh. Client applications should first call this endpoint to create accounts before attempting logins.
   *
   * This endpoint complies with security and business requirements established for member actors in the shopping mall system.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer join request data containing necessary credentials for account creation.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification This operation implements customer registration (join) by accepting join credentials (such as email and password) based on schema requirements. Service layer will validate uniqueness and password strength before creating a new customer record. It uses POST method at path /auth/customer/join with request body of IShoppingMallCustomer.IJoin type. Responses return IShoppingMallCustomer.IAuthorized containing JWT tokens and session info. This is a public endpoint requiring no authentication.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.IJoin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API endpoint enables existing customers to authenticate themselves by providing valid email and password credentials. Upon successful login, the response returns authorized session information including access and refresh JWT tokens.
   *
   * The operation references customer authentication fields in the database schema to validate credentials securely. Incorrect credentials will result in authentication failure errors.
   *
   * This login operation complements registration (join) and token refresh endpoints in the customer authentication lifecycle.
   *
   * No authentication is required to access this endpoint since it supports anonymous users attempting to authenticate.
   *
   * Client applications should use this endpoint to establish authenticated sessions after account creation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer login request with credentials for authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification This operation implements customer login by validating email and password credentials against the database records. It uses POST method at path /auth/customer/login with request body of IShoppingMallCustomer.ILogin type. Successful validation returns authorized session details with JWT tokens in the response. This endpoint requires no prior authentication and is publicly accessible.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.ILogin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API endpoint refreshes customer's JWT authentication tokens to maintain an active session without re-entering login credentials. It accepts a refresh token and issues a new access token along with updated refresh tokens.
   *
   * This operation relies on secure validation of the provided refresh token based on the schema's authentication token fields. Invalid or expired tokens are rejected with appropriate error responses.
   *
   * Token refresh is essential for maintaining authentication state in stateless JWT-based systems.
   *
   * This endpoint integrates with registration and login endpoints to ensure seamless customer authentication lifecycle management.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer token refresh request containing refresh token.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification This operation implements JWT token refresh by accepting a valid refresh token and issuing a new access token. It uses POST method at path /auth/customer/refresh with request body of IShoppingMallCustomer.IRefresh type. Successful processing returns fresh authorized session data with updated JWT tokens. This endpoint is publicly accessible and requires no pre-authentication.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallCustomer.IRefresh,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
