import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postShoppingMallCustomers } from "../../../providers/postShoppingMallCustomers";

import { IShoppingMallCustomer } from "../../../api/structures/IShoppingMallCustomer";

@Controller("/shoppingMall/customers")
export class ShoppingmallCustomersController {
  /**
   * Create a new shopping mall customer account.
   *
   * Create a new customer account with email and password authentication in the
   * shopping mall system.
   *
   * The operation requires specifying the customer's unique email address,
   * hashed password for security, and full name. Upon successful creation, the
   * customer's profile is available for shopping activities.
   *
   * Security: Password hashing is expected before sending this request; the API
   * stores the hashed password as is.
   *
   * The created_at and updated_at timestamps are automatically managed by the
   * system.
   *
   * Dependent operations: Updating customer info via PUT
   * /customers/{customerId}.
   *
   * @param connection
   * @param body Customer signup data including email, hashed password, and full
   *   name
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: IShoppingMallCustomer.ICreate,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await postShoppingMallCustomers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
