import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallGuests } from "../../../providers/postShoppingMallGuests";
import { patchShoppingMallGuests } from "../../../providers/patchShoppingMallGuests";
import { getShoppingMallGuestsGuestId } from "../../../providers/getShoppingMallGuestsGuestId";
import { putShoppingMallGuestsGuestId } from "../../../providers/putShoppingMallGuestsGuestId";

import { IShoppingMallGuest } from "../../../api/structures/IShoppingMallGuest";
import { IPageIShoppingMallGuest } from "../../../api/structures/IPageIShoppingMallGuest";

@Controller("/shoppingMall/guests")
export class ShoppingmallGuestsController {
  /**
   * Create a new guest user record.
   *
   * Create a new guest user entry in the system. This operation allows
   * unauthenticated visitors to register as guests, enabling limited access and
   * interaction with the shopping mall platform.
   *
   * The guest record is stored in the `shopping_mall_guests` table, capturing
   * essential information such as session details and device metadata to
   * support session continuity and personalized experience.
   *
   * Security: This endpoint is public and does not require authentication, but
   * the system imposes rate limits to prevent abuse and ensure performance.
   *
   * Related operations: Update guest (PUT /guests/{guestId}) to modify guest
   * information.
   *
   * @param connection
   * @param body Guest creation data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: IShoppingMallGuest.ICreate,
  ): Promise<IShoppingMallGuest> {
    try {
      return await postShoppingMallGuests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and filter guest users with pagination.
   *
   * Retrieve a paginated list of guest users currently or previously browsing
   * the shopping mall platform.
   *
   * This operation supports advanced filtering, sorting, and pagination to
   * locate guest users based on various criteria including guestId, session
   * activity, and browsing patterns. It interacts with the shopping_mall_guests
   * table, utilizing all available fields and relationships as defined in the
   * Prisma schema.
   *
   * Security considerations include restricting access to authorized roles or
   * systems that require insight into guest user analytics and monitoring. Rate
   * limiting and data access policies should be enforced to protect user
   * privacy.
   *
   * Related operations include retrieving guest user details by ID (GET
   * /guests/{guestId}).
   *
   * @param connection
   * @param body Filter and pagination request for guest users
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallGuest.IRequest,
  ): Promise<IPageIShoppingMallGuest.ISummary> {
    try {
      return await patchShoppingMallGuests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get guest user details by guestId.
   *
   * Retrieve detailed information about a specific guest user by their unique
   * identifier.
   *
   * This includes all guest-related data fields from the shopping_mall_guests
   * table such as creation timestamp, session details, expiration, and
   * metadata.
   *
   * Access is restricted to authorized personnel or systems monitoring guest
   * activity. Proper authorization and auditing are required to maintain
   * privacy.
   *
   * Related endpoints include PATCH /guests for searching and listing guest
   * users.
   *
   * @param connection
   * @param guestId Unique identifier of the target guest user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":guestId")
  public async at(
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallGuest> {
    try {
      return await getShoppingMallGuestsGuestId({
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update guest user record.
   *
   * Update an existing guest's information in the system using their unique
   * identifier.
   *
   * This allows session continuity and data updates for guest users who
   * partially interact with the platform without full authentication.
   *
   * The operation acts on the `shopping_mall_guests` table, ensuring only
   * allowed fields are updated. The guestId path parameter uniquely identifies
   * the guest record.
   *
   * Security: Public endpoint with no authentication required, but rate
   * limiting applies to prevent abuse.
   *
   * Related operations: Create guest (POST /guests) for new guest registration.
   *
   * @param connection
   * @param guestId Unique identifier of the guest user
   * @param body Guest update data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":guestId")
  public async update(
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallGuest.IUpdate,
  ): Promise<IShoppingMallGuest> {
    try {
      return await putShoppingMallGuestsGuestId({
        guestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
