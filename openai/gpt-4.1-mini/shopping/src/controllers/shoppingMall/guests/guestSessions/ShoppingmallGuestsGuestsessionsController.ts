import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallGuestsGuestIdGuestSessionsGuestSessionId } from "../../../../providers/getShoppingMallGuestsGuestIdGuestSessionsGuestSessionId";
import { postShoppingMallGuestsGuestIdGuestSessions } from "../../../../providers/postShoppingMallGuestsGuestIdGuestSessions";

import { IShoppingMallGuestSession } from "../../../../api/structures/IShoppingMallGuestSession";

@Controller("/shoppingMall/guests/:guestId/guestSessions")
export class ShoppingmallGuestsGuestsessionsController {
  /**
   * Retrieve a specific guest session for a guest user.
   *
   * Retrieve detailed information about a single guest session linked to a
   * particular guest user.
   *
   * This operation fetches the session connection context including IP address,
   * referer URL, connection origin, and timestamps. The session record is
   * associated with a guest user identified by guestId.
   *
   * Security considerations: This endpoint is public-accessible without
   * authentication as guests are anonymous users with minimal privileges.
   *
   * This operational endpoint aligns with the shopping_mall_guest_sessions
   * Prisma table, providing insight into guest session activities.
   *
   * Related operations include creating a guest session (POST
   * /guests/{guestId}/guestSessions) for tracking new connections.
   *
   * @param connection
   * @param guestId Unique identifier of the target guest user
   * @param guestSessionId Unique identifier of the target guest session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":guestSessionId")
  public async at(
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
    @TypedParam("guestSessionId")
    guestSessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallGuestSession> {
    try {
      return await getShoppingMallGuestsGuestIdGuestSessionsGuestSessionId({
        guestId,
        guestSessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new guest session for a guest user.
   *
   * Create a new session record for a guest user to track their connection
   * context.
   *
   * The operation records guest session details including IP address,
   * connection origin URL, referrer URL, and creation timestamps.
   *
   * This process helps monitor guest activity anonymously and supports session
   * lifecycle management.
   *
   * Security: As guests are anonymous, this endpoint is public and requires no
   * authentication.
   *
   * The created session will have a unique identifier and can be retrieved or
   * managed using corresponding GET endpoint.
   *
   * This operation corresponds to the creation function on the
   * shopping_mall_guest_sessions Prisma table.
   *
   * @param connection
   * @param guestId Unique identifier of the target guest user
   * @param body Guest session creation information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallGuestSession.ICreate,
  ): Promise<IShoppingMallGuestSession> {
    try {
      return await postShoppingMallGuestsGuestIdGuestSessions({
        guestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
