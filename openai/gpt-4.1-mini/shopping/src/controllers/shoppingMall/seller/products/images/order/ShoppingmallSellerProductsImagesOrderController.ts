@Controller("/shoppingMall/seller/products/:productId/images/order")
export class ShoppingmallSellerProductsImagesOrderController {
  /**
   * Reorder images for a product by updating their display order values.
   *
   * This operation enables sellers to change the visual order of product images. The images are identified by IDs scoped under the product specified by the productId parameter.
   *
   * Only authorized sellers can perform this update.
   *
   * The data model is shopping_mall_product_images, where display_order determines image position, with the lowest value as the thumbnail.
   *
   * Validation ensures all images belong to the product and display_order values are unique.
   *
   * The updated images list is returned sorted by display_order.
   *
   * Related endpoints: GET /sellers/products/{productId}/images, POST /sellers/products/{productId}/images.
   *
   * Updates are atomic and validated, errors provide clear feedback.
   *
   *
   * @param connection
   * @param productId Target product's ID in UUID format
   * @param body List of product image IDs with their updated display order to apply to the specified product.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification - Input productId path parameter and array of imageId-order pairs in request body.
   * - Validate image ownership and uniqueness of display orders.
   * - Update display_order fields atomically in transaction.
   * - Return updated images array sorted by display_order.
   * - Handle validation errors with 400 responses.
   * - Authorization limited to owning seller.
   * - Update timestamps accordingly.
   * - Trigger product snapshot updates on change.
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updateImageOrder(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductImage.IUpdateOrder,
  ): Promise<IPageIShoppingMallProductImage.ISummary> {
    try {
      return await patchShoppingMallSellerProductsProductIdImagesOrder({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
