import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { postShoppingMallSellerProductsProductCodeSkus } from "../../../../../providers/postShoppingMallSellerProductsProductCodeSkus";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerProductsProductCodeSkus } from "../../../../../providers/patchShoppingMallSellerProductsProductCodeSkus";
import { getShoppingMallSellerProductsProductCodeSkusSkuCode } from "../../../../../providers/getShoppingMallSellerProductsProductCodeSkusSkuCode";
import { putShoppingMallSellerProductsProductCodeSkusSkuCode } from "../../../../../providers/putShoppingMallSellerProductsProductCodeSkusSkuCode";
import { deleteShoppingMallSellerProductsProductCodeSkusSkuCode } from "../../../../../providers/deleteShoppingMallSellerProductsProductCodeSkusSkuCode";

import { IShoppingMallProductSku } from "../../../../../api/structures/IShoppingMallProductSku";
import { IPageIShoppingMallProductSku } from "../../../../../api/structures/IPageIShoppingMallProductSku";

@Controller("/shoppingMall/seller/products/:productCode/skus")
export class ShoppingmallSellerProductsSkusController {
  /**
   * Create a new SKU variant for a specific product in ShoppingMallProductSku
   * table.
   *
   * This API endpoint allows authorized sellers and administrators to add new
   * product SKUs (Stock Keeping Units) for a specific product identified by its
   * unique productCode. Each SKU represents a distinct variant with unique
   * attributes such as color, size, or other options, and includes pricing
   * information.
   *
   * The endpoint strictly enforces the uniqueness of SKU codes platform-wide
   * and associates the SKU with its parent product through the productCode,
   * ensuring consistency and data integrity.
   *
   * Security considerations ensure only authorized actors ('seller' and
   * 'admin') can create SKUs. Input validation checks for the presence of
   * required fields and adherence to format constraints.
   *
   * Related operations include: updating SKU details via PUT
   * /products/{productCode}/skus/{skuCode}, and retrieving product or SKU data
   * through other product catalog endpoints.
   *
   * The operation performs a hard creation; the new SKU is persisted and
   * immediately available after execution. Errors due to duplicate sku_code or
   * invalid productCode are handled gracefully.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target product
   *   (global scope)
   * @param body Creation info of a new product SKU variant associated with the
   *   product
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async createSku(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productCode")
    productCode: string,
    @TypedBody()
    body: IShoppingMallProductSku.ICreate,
  ): Promise<IShoppingMallProductSku> {
    try {
      return await postShoppingMallSellerProductsProductCodeSkus({
        seller,
        productCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of SKUs for a product.
   *
   * Retrieve a filtered and paginated list of SKUs for a specific product. Each
   * SKU represents a distinct variant of the product with attributes such as
   * color, size, and pricing information. The operation requires the unique
   * product code to identify the product context and returns SKU summary
   * information optimized for listing. It supports advanced query capabilities,
   * including filtering by SKU attributes, pagination, and sorting.
   *
   * Security considerations include access control to ensure only authorized
   * users such as sellers managing the product or admins can retrieve SKU
   * details. Public access is restricted to safeguard inventory and pricing
   * data.
   *
   * This operation interfaces with the shopping_mall_product_skus table, which
   * stores SKU details including SKU codes, prices, variant attributes stored
   * as JSON, and soft deletion timestamps. The operation excludes soft-deleted
   * SKUs from results. Pagination parameters allow clients to navigate large
   * SKU sets efficiently.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target product
   *   (global scope)
   * @param body Search criteria and pagination parameters for SKU filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productCode")
    productCode: string,
    @TypedBody()
    body: IShoppingMallProductSku.IRequest,
  ): Promise<IPageIShoppingMallProductSku.ISummary> {
    try {
      return await patchShoppingMallSellerProductsProductCodeSkus({
        seller,
        productCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific SKU for a product.
   *
   * Retrieve detailed SKU information for a specific SKU code belonging to a
   * product identified by product code. The SKU includes pricing, variant
   * attributes encoded in JSON, and timestamps. Authorized users such as
   * sellers and admins can access this endpoint to view or manage SKU details.
   *
   * The SKU code uniquely identifies the SKU globally, ensuring precise
   * retrieval. Compliance with soft deletion ensures only active SKUs are
   * returned.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target product
   *   (global scope)
   * @param skuCode Unique SKU code identifying the specific product variant
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":skuCode")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productCode")
    productCode: string,
    @TypedParam("skuCode")
    skuCode: string,
  ): Promise<IShoppingMallProductSku> {
    try {
      return await getShoppingMallSellerProductsProductCodeSkusSkuCode({
        seller,
        productCode,
        skuCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing SKU variant of a given product in ShoppingMallProductSku
   * table.
   *
   * This API endpoint allows authorized sellers and administrators to update
   * details of an existing SKU variant identified by skuCode for a specific
   * product identified by productCode. The SKU details updated include pricing,
   * variant attribute JSON, and other modifiable fields.
   *
   * The endpoint requires both productCode and skuCode as path parameters to
   * precisely identify the SKU within the product context, respecting composite
   * uniqueness constraints.
   *
   * Only 'seller' and 'admin' actors are permitted, enforcing secure
   * modification rights.
   *
   * Related operations include creating SKUs via POST
   * /products/{productCode}/skus and retrieving SKU or product data.
   *
   * The update is a hard modification; fields are overwritten with input data,
   * and the updated SKU is saved persistently. Validation errors or attempting
   * to update nonexistent SKUs result in appropriate error responses.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target product
   *   (global scope)
   * @param skuCode Unique SKU code of the target SKU variant within the
   *   platform (global scope)
   * @param body Update info of an existing product SKU variant
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":skuCode")
  public async updateSku(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productCode")
    productCode: string,
    @TypedParam("skuCode")
    skuCode: string,
    @TypedBody()
    body: IShoppingMallProductSku.IUpdate,
  ): Promise<IShoppingMallProductSku> {
    try {
      return await putShoppingMallSellerProductsProductCodeSkusSkuCode({
        seller,
        productCode,
        skuCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific SKU variant identified by skuCode for a product
   * identified by productCode.
   *
   * This endpoint allows authenticated users with appropriate permissions to
   * delete an individual SKU variant of a product within the shopping mall. The
   * operation requires precise identification of both the parent product and
   * the SKU variant by their unique business codes.
   *
   * Security measures restrict deletions to authorized actors only, ensuring
   * that users cannot delete SKUs arbitrarily.
   *
   * Upon successful execution, the targeted SKU record is permanently removed
   * from the database. Partial or cascading deletes must be handled by database
   * constraints.
   *
   * This endpoint is singular and idempotent, and it does not return a response
   * body to confirm deletion.
   *
   * It relates directly to the shopping_mall_product_skus Prisma model
   * representing SKU variants linked to their respective products.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target product
   *   (global scope)
   * @param skuCode Unique business identifier code of the target SKU variant
   *   within the product (scoped to product)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":skuCode")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productCode")
    productCode: string,
    @TypedParam("skuCode")
    skuCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductCodeSkusSkuCode({
        seller,
        productCode,
        skuCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
