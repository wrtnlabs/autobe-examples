import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallProduct } from "../../../../api/structures/IPageIShoppingMallProduct";
import { IShoppingMallProduct } from "../../../../api/structures/IShoppingMallProduct";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerProductsProductId } from "../../../../providers/deleteShoppingMallSellerProductsProductId";
import { getShoppingMallSellerProductsProductId } from "../../../../providers/getShoppingMallSellerProductsProductId";
import { patchShoppingMallSellerProducts } from "../../../../providers/patchShoppingMallSellerProducts";
import { postShoppingMallSellerProducts } from "../../../../providers/postShoppingMallSellerProducts";
import { putShoppingMallSellerProductsProductId } from "../../../../providers/putShoppingMallSellerProductsProductId";

@Controller("/shoppingMall/seller/products")
export class ShoppingmallSellerProductsController {
  /**
   * Create a new product in the shopping mall platform.
   *
   * This operation allows an authenticated seller to add a new product to their catalog by specifying product details such as name, description, subcategory, and base price.
   *
   * The created product will be assigned to the seller based on their authenticated session. The product is initially active with no deletion timestamp.
   *
   * Authorization: This operation is accessible only to authenticated sellers.
   *
   * Validation and Constraints:
   * - Product name must be unique for the seller.
   * - The product subcategory ID must reference an existing subcategory.
   *
   * Related operations:
   * - PUT /products/{productId}: Update product details.
   * - DELETE /products/{productId}: Delete a product if no pending orders or refund requests.
   * - GET /products/{productId}/snapshots: View snapshots for audit and history purposes.
   *
   * This API follows RESTful conventions and returns the newly created product entity with all its fields.
   *
   * @param connection
   * @param body Product creation payload with name, description, subcategory, and base price.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement service logic to validate the request body and authenticate the seller.
   * Check uniqueness of the product name scoped to the seller.
   * Verify that the provided product_subcategory_id exists and is not soft-deleted.
   * Create a new record in shopping_mall_products with the provided data and current timestamps.
   * Return the full product entity including generated id and timestamps.
   * Handle errors such as duplicate product names or invalid subcategory references with appropriate HTTP status codes.
   * Maintain consistency with transaction management and audit logging as per platform standards.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProduct.ICreate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await postShoppingMallSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of shopping mall products based on search and filter criteria.
   *
   * This operation allows customers to search products by name, filter by product subcategory, price range, and stock availability.
   *
   * Products are represented with summary information suitable for listing, including seller and category references.
   *
   * Only active (not soft deleted) products are included.
   *
   * Supports sorting by newest first, price ascending, or price descending.
   *
   * Authorization is not restricted; accessible to customers and guests.
   *
   * Related operations include GET /products/{productId} to fetch product details and GET /categories to navigate categories.
   *
   * Handles pagination to efficiently manage large product datasets with cursor or offset-based mechanism.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for product list retrieval
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_products table filtering by:
   * - name with case-insensitive partial match
   * - optional product_subcategory_id
   * - price range fields (minPrice, maxPrice)
   * - stock availability (inStock boolean)
   * Join seller and product_subcategory tables to include display info.
   * Apply sorting as requested:
   * - newest first by created_at descending
   * - price ascending
   * - price descending
   * Return paginated results with pagination metadata.
   * Cache results to improve performance.
   * Validate request parameters for allowed ranges and types.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProduct.IRequest,
  ): Promise<IPageIShoppingMallProduct.ISummary> {
    try {
      return await patchShoppingMallSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific product identified by its unique productId.
   *
   * This operation queries the shopping_mall_products table to fetch all relevant product data including name, description, base price, and associations with the seller and product subcategory.
   *
   * The retrieved product information supports customer browsing and product detail examination, ensuring that only existing and active (non-deleted) products can be retrieved.
   *
   * Authorization checks should ensure the caller has the rights to view product details.
   *
   * Validation rules:
   * - The productId path parameter must be a valid UUID.
   * - Only products that are not soft deleted (deleted_at is null) are retrievable.
   *
   * Related operations:
   * - PATCH /products for listing/searching products
   * - POST /products for creating new products
   * - PUT /products/{productId} for updating product details
   * - DELETE /products/{productId} for deleting a product
   *
   * Error handling:
   * - Return 404 Not Found if productId does not exist or product is deleted.
   * - Return 400 Bad Request if productId is not a valid UUID.
   *
   * This operation plays a critical role in customer product detail pages and product management UI.
   *
   * @param connection
   * @param productId Unique identifier of the product (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Perform a SELECT query on shopping_mall_products filtering by id = productId and deleted_at IS NULL.
   * Include related entities like seller and product subcategory only as references for DTO mapping.
   * Ensure authorization by verifying user's roles and permissions to view product details.
   * Validate productId as a UUID before query execution.
   * Return 404 if product is not found or is soft deleted.
   * No request body for this GET method.
   * Response body must conform to IShoppingMallProduct type including all product columns and nested relationships as per schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProduct> {
    try {
      return await getShoppingMallSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product's details including name, description, base price, and category affiliation.
   *
   * This operation targets the shopping_mall_products entity which represents products created by sellers. Product details such as name, description, and base price can be updated. The product is linked to a seller and a product subcategory which can also be changed.
   *
   * Security is critical: only the owning seller or system administrators should have access permissions to modify product data.
   *
   * Validation must ensure the productId is valid and refers to an existing record. Changes to the product may trigger snapshot creation externally to preserve history.
   *
   * This operation does not handle product variants or images directly; those have their own dedicated endpoints.
   *
   * Related operations include POST /products for creation and GET /products/{productId} for detail retrieval.
   *
   * Error handling must return appropriate HTTP status codes for unauthorized access, validation failures, and not found conditions.
   *
   * @param connection
   * @param productId The UUID of the product to update.
   * @param body Product update information including name, description, base price, and subcategory.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement validation to confirm the authenticated user is the product owner or an administrator.
   *
   * Use the productId path parameter to locate the existing product record in the shopping_mall_products table.
   *
   * Update the product name, description, base price, and product_subcategory_id fields as provided in the request body.
   *
   * Save changes in a transactional manner.
   *
   * Trigger snapshot creation process outside of this API operation to record pre-update state.
   *
   * Reject changes that violate unique constraints such as seller_id + name uniqueness.
   *
   * Respond with the updated product entity data.
   *
   * Handle error cases:
   * - Return 404 if productId does not exist
   * - Return 403 if unauthorized
   * - Return 400 for validation errors
   *
   * This operation does not modify related variant or image entities; those must be managed by separate API operations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProduct.IUpdate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await putShoppingMallSellerProductsProductId({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This DELETE operation permanently removes a product identified by `productId` from the system. It verifies that the product exists and belongs to the authenticated seller, preventing unauthorized deletions.
   *
   * Before deletion, the service verifies there are no pending order items or cancellation/refund requests linked to the product variants. If such pending requests exist, the operation returns an error indicating deletion is not allowed.
   *
   * On successful deletion, the product record, along with all associated product variants and inventory records, is completely removed from the database. This operation bypasses the `deleted_at` field and performs a hard delete.
   *
   * Authorization is required and validated against the seller owning the product.
   *
   * This operation complements product creation and update operations, and can be used in seller product management dashboards.
   *
   * Related operations:
   * - POST /shoppingMall/seller/products (create)
   * - PUT /shoppingMall/seller/products/{productId} (update)
   * - GET /shoppingMall/seller/products/{productId}/snapshots (view snapshots)
   *
   * @param connection
   * @param productId Identifier of the product to delete (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Validate the seller's authentication and authorization to delete the specified product.
   * 2. Check existence of the product by productId.
   * 3. Verify no pending order items or active cancellation/refund requests exist for any variant of the product.
   * 4. Delete all associated product variants.
   * 5. Delete the product record itself.
   * 6. Delete related inventory records and snapshots if applicable.
   * 7. Return the deleted product details in the response body.
   * 8. Handle errors for unauthorized access, not found, or business rule violations.
   * 9. Log the deletion operation for auditing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProduct> {
    try {
      return await deleteShoppingMallSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
