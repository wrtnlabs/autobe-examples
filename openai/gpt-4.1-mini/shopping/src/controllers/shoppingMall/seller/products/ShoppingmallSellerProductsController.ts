import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallSellerProducts } from "../../../../providers/postShoppingMallSellerProducts";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerProducts } from "../../../../providers/patchShoppingMallSellerProducts";
import { getShoppingMallSellerProductsProductCode } from "../../../../providers/getShoppingMallSellerProductsProductCode";
import { putShoppingMallSellerProductsProductCode } from "../../../../providers/putShoppingMallSellerProductsProductCode";
import { deleteShoppingMallSellerProductsProductCode } from "../../../../providers/deleteShoppingMallSellerProductsProductCode";

import { IShoppingMallProduct } from "../../../../api/structures/IShoppingMallProduct";
import { IPageIShoppingMallProduct } from "../../../../api/structures/IPageIShoppingMallProduct";

@Controller("/shoppingMall/seller/products")
export class ShoppingmallSellerProductsController {
  /**
   * Create a new product entity in the catalog.
   *
   * Create a new product entry in the product catalog. The request body must
   * conform to the IShoppingMallProduct.ICreate structure that includes unique
   * product code, descriptive naming, and optional brand field.
   *
   * Authorization is required for sellers and admins to ensure only authorized
   * personnel can add new products.
   *
   * The response returns the full product entity with all created data
   * including assigned timestamps.
   *
   * Validation will ensure no duplicate product codes and completeness of
   * required fields.
   *
   * @param connection
   * @param body Product creation data including unique code and descriptive
   *   attributes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProduct.ICreate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await postShoppingMallSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of shopping mall platform
   * products.
   *
   * Retrieve a filtered and paginated list of ShoppingMall products from the
   * system. This operation provides advanced search capabilities allowing
   * filtering by product name, unique code, assigned category, and brand, with
   * support for pagination and sorting.
   *
   * Results exclude soft deleted products (identified by null deleted_at).
   * Pagination parameters include page size and page number.
   *
   * Security considerations include role-based access control; typically, this
   * endpoint is open to authenticated users including customers, sellers, and
   * admins.
   *
   * The operation returns a paginated response containing a summary view of
   * product information suitable for listings.
   *
   * This operation integrates directly with the ShoppingMallProduct entity in
   * the Prisma schema, mapping all available fields except soft-deleted
   * records.
   *
   * Related operations include product creation, updating, detail retrieval,
   * and deletion.
   *
   * This endpoint is part of the Product Catalog group.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for product filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProduct.IRequest,
  ): Promise<IPageIShoppingMallProduct.ISummary> {
    try {
      return await patchShoppingMallSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed product information by unique productCode.
   *
   * Retrieve detailed product information identified by the unique productCode.
   * The product corresponds to the shopping_mall_products table which stores
   * product metadata including descriptive text, brand, and timestamps.
   *
   * Authorization is open to authenticated users (admins, sellers, and
   * customers) to view the product catalog. No request body is needed as this
   * is a simple retrieval.
   *
   * The productCode path parameter uniquely identifies the product across the
   * platform, derived from the code column which is unique and human-readable.
   *
   * The response returns the complete product entity with all details excluding
   * soft deleted products.
   *
   * Errors will occur if the productCode does not correspond to any existing
   * product or if the product is deleted.
   *
   * Other operations like listing products or viewing SKUs support workflows
   * that complement this retrieval.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target product
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productCode")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productCode")
    productCode: string,
  ): Promise<IShoppingMallProduct> {
    try {
      return await getShoppingMallSellerProductsProductCode({
        seller,
        productCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update product details by unique product code.
   *
   * Update a product's main details such as name, description, and brand by
   * specifying the product's unique code. This API enforces validation of
   * inputs and prevents modification of immutable fields such as the product's
   * code or creation date.
   *
   * The operation requires appropriate authentication with admin or seller
   * roles ensuring that only authorized users can update product information.
   *
   * The product entity is tightly linked to SKUs representing its variants.
   * This update operation does not modify SKUs but ensures category
   * consistency.
   *
   * Input validation ensures that the product name is non-empty and
   * descriptions are optional. The API rejects invalid or unauthorized requests
   * gracefully.
   *
   * This operation pairs with the DELETE /products/{productCode} endpoint to
   * allow complete lifecycle management of products.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target product
   *   (global scope)
   * @param body Updated product information: name, description, brand
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productCode")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productCode")
    productCode: string,
    @TypedBody()
    body: IShoppingMallProduct.IUpdate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await putShoppingMallSellerProductsProductCode({
        seller,
        productCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete product by unique product code.
   *
   * Permanently delete a product by its unique product code. This is a hard
   * delete operation removing the record and all child entities including SKUs
   * and approvals.
   *
   * Access is restricted to admin and seller roles only to protect data
   * integrity and prevent accidental deletions.
   *
   * This operation does not return a response body as confirmation is implicit
   * through the HTTP response status.
   *
   * Use with caution as this operation cannot be undone.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target product
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productCode")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productCode")
    productCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductCode({
        seller,
        productCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
