import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallProduct } from "../../../../api/structures/IPageIShoppingMallProduct";
import { IShoppingMallProduct } from "../../../../api/structures/IShoppingMallProduct";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerProductsProductId } from "../../../../providers/deleteShoppingMallSellerProductsProductId";
import { getShoppingMallSellerProductsProductId } from "../../../../providers/getShoppingMallSellerProductsProductId";
import { patchShoppingMallSellerProducts } from "../../../../providers/patchShoppingMallSellerProducts";
import { postShoppingMallSellerProducts } from "../../../../providers/postShoppingMallSellerProducts";
import { putShoppingMallSellerProductsProductId } from "../../../../providers/putShoppingMallSellerProductsProductId";

@Controller("/shoppingMall/seller/products")
export class ShoppingmallSellerProductsController {
  /**
   * Create a new product entry in the shopping mall platform.
   *
   * This operation allows authenticated sellers to create products with required information including name, description, product subcategory association, and base price. These fields must conform to the validation rules enforced by the database schema.
   *
   * Security and permissions require the caller to be an authenticated and approved seller.
   *
   * The operation persists the product record linked to the seller and associates it with the specified product subcategory. On success, it returns the full product entity including generated fields like ID and timestamps.
   *
   * This operation adheres strictly to business rules ensuring products belong solely to the creating seller, and the subcategory must exist. Further validation and snapshot creation occur downstream.
   *
   * Related operations include:
   * - GET /sellers/products to list seller's products
   * - PUT /sellers/products/{productId} to update an existing product
   * - DELETE /sellers/products/{productId} for product removal
   *
   * Error cases handle invalid subcategory IDs, unauthorized access, and validation failures.
   *
   * This endpoint does not support soft deletion or snapshot retrieval, which are managed separately.
   *
   * @param connection
   * @param body Product creation details.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Verify the caller is an authenticated approved seller.
   * 2. Validate the request body fields according to the IShoppingMallProducts.ICreate schema.
   * 3. Check that the specified product_subcategory_id exists and is active.
   * 4. Insert a new record into shopping_mall_products with the provided data, linking to the seller.
   * 5. Return the created product entity including its generated ID and timestamps.
   * 6. Trigger downstream snapshot creation asynchronously.
   * 7. Handle and respond with appropriate HTTP error codes for validation errors and unauthorized access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProduct.ICreate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await postShoppingMallSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of products available in the shopping mall. This operation supports advanced search criteria including filtering by product name, category, subcategory, seller, and price range.
   *
   * The results include summary information optimized for list display, such as product name, base price, and category/subcategory names.
   *
   * Security: This endpoint is publicly accessible for browsing products but restricts visibility to products not deleted (deleted_at is null).
   *
   * Database schema references:
   * - shopping_mall_products: main product information
   * - shopping_mall_product_subcategories: product categorization hierarchy
   * - shopping_mall_product_categories: top-level product category
   *
   * Validation rules ensure proper pagination and sorting.
   *
   * Related operations: GET /products/{productId} for single product detail.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for products
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the shopping_mall_products table with filters on product name, seller ID, product category and subcategory IDs, and base price range.
   * Include only products where deleted_at IS NULL to exclude deleted products.
   * Join with shopping_mall_product_subcategories and shopping_mall_product_categories to get category names for response.
   * Implement cursor or offset pagination for efficient large dataset handling.
   * Allow sorting by base_price, name, or creation date.
   * Return paginated summary including product ID, name, base price, and category details.
   * Validate all incoming request body parameters strictly.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProduct.IRequest,
  ): Promise<IPageIShoppingMallProduct.ISummary> {
    try {
      return await patchShoppingMallSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific product identified by its unique UUID productId.
   *
   * The product entity includes key attributes such as name, description, associated category (including hierarchical subcategory details), base price, and seller ownership.
   *
   * This operation enables customers to view product details for potential purchase decisions and allows sellers and administrators to view product states including snapshots from edits for audit and compliance purposes.
   *
   * Security wise, this endpoint is publicly accessible to customer actors for browsing products.
   *
   * The underlying implementation will query the shopping_mall_products table joined with related category and seller tables to assemble the full product data.
   *
   * If the product does not exist, the standard 404 Not Found error will be returned.
   *
   * This operation pairs with listing/search endpoints to provide a complete product browsing experience.
   *
   * @param connection
   * @param productId Globally unique identifier of the product
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Perform a database query on shopping_mall_products filtering by productId with exact match.
   * Join shopping_mall_product_categories and shopping_mall_product_subcategories to fetch category hierarchy details.
   * Join shopping_mall_sellers to obtain seller profile information.
   * Enforce visibility rules to exclude deleted products.
   * Return the detailed product entity structure as defined by IShoppingMallProduct.
   * Return 404 if the productId does not exist.
   *
   * No request body is required.
   *
   * No specific authorization restrictions as this is a public browse endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProduct> {
    try {
      return await getShoppingMallSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product by its unique identifier.
   *
   * This endpoint allows authorized sellers or administrators to modify product details such as name, description, category, and base price. Every update triggers immutable snapshot creation to preserve historical product states for audit and dispute resolution.
   *
   * Security and Authorization:
   * - Only the product owner seller or administrators can update product information.
   *
   * Database Entity Relationship:
   * - This operation interacts with the shopping_mall_products table which stores product information.
   * - On successful update, a snapshot recording the previous state of the product and its variants is created.
   *
   * Validation and Business Rules:
   * - The product must belong to the seller performing the update unless the actor is an administrator.
   * - Product updates are restricted when there are pending orders or cancellation/refund requests for any variants.
   *
   * Related Operations:
   * - Use GET /products/{productId} to retrieve product details.
   * - Use POST /sellers/products to create new products.
   * - Use DELETE /sellers/products/{productId} to delete a product.
   *
   * Error Handling:
   * - Return 404 if the product does not exist.
   * - Return 403 if the user is unauthorized to update the product.
   *
   * Expected behavior:
   * - Returns the updated product entity including the new state after modifications.
   *
   * @param connection
   * @param productId Unique identifier of the product to update, formatted as UUID
   * @param body Product update request payload
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Validate the productId path parameter as a UUID.
   * 2. Authenticate the requesting user as a seller or administrator.
   * 3. Verify product ownership or admin rights.
   * 4. Check for pending orders or cancellation/refund requests on product variants; block update if any exist.
   * 5. Validate request body fields according to IShoppingMallProduct.IUpdate schema.
   * 6. Update the shopping_mall_products table record.
   * 7. Create an immutable snapshot of previous product and variant states.
   * 8. Return the updated product record including all fields according to IShoppingMallProduct schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProduct.IUpdate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await putShoppingMallSellerProductsProductId({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Deletes the product identified by the productId path parameter from the shopping mall product catalog. This operation performs a direct and permanent removal of the product record, including its variants and associated inventory records, from the database.
   *
   * This deletion can be performed by the owning seller only if there are no pending orders (paid or shipped) or outstanding cancellation/refund requests for the product. Administrators may also perform this operation for policy enforcement.
   *
   * Security is enforced to restrict this operation to authenticated sellers with ownership rights or authorized administrators.
   *
   * Related operations for further management and viewing of products include:
   * - GET /shoppingMall/seller/products/{productId} to retrieve detailed product information.
   * - GET /shoppingMall/admin/products for administrators to view all products.
   *
   * Errors from attempts to delete products violating business rules will return appropriate HTTP status codes and error messages, detailing the reason for rejection.
   *
   * @param connection
   * @param productId Unique identifier of the product to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification This API operation performs a permanent deletion of a product identified by the productId path parameter.
   *
   * Implementation steps:
   * - Validate the productId format as UUID.
   * - Authenticate the user as seller owning the product or as an administrator.
   * - Check business constraints: no pending paid/shipped orders or cancellation/refund requests linking to the product.
   * - If constraints are satisfied, within a database transaction delete the product record from shopping_mall_products and cascade delete related variants and inventory.
   * - Invalidate any related caches and update search indexes.
   * - Return successful HTTP status with no response body.
   * - Handle errors for unauthorized access, not found productId, or business rule violation with appropriate HTTP status codes and messages.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
