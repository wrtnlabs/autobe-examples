import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerSkuInventories } from "../../../../providers/postShoppingMallSellerSkuInventories";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerSkuInventories } from "../../../../providers/patchShoppingMallSellerSkuInventories";
import { getShoppingMallSellerSkuInventoriesId } from "../../../../providers/getShoppingMallSellerSkuInventoriesId";
import { putShoppingMallSellerSkuInventoriesId } from "../../../../providers/putShoppingMallSellerSkuInventoriesId";
import { deleteShoppingMallSellerSkuInventoriesId } from "../../../../providers/deleteShoppingMallSellerSkuInventoriesId";

import { IShoppingMallSkuInventory } from "../../../../api/structures/IShoppingMallSkuInventory";
import { IPageIShoppingMallSkuInventory } from "../../../../api/structures/IPageIShoppingMallSkuInventory";

@Controller("/shoppingMall/seller/skuInventories")
export class ShoppingmallSellerSkuinventoriesController {
  /**
   * Create a SKU inventory record for stock tracking and management.
   *
   * Create a new SKU inventory record for a product SKU with specified quantity
   * and stock status. This operation allows authorized sellers or admins to add
   * inventory information to track stock levels per SKU.
   *
   * Input validation requires non-negative quantity and valid stock status
   * values such as 'in stock', 'out of stock', or 'backordered'. The SKU ID
   * must reference an existing product SKU.
   *
   * Security policies restrict access to seller and admin roles. The operation
   * records creation and update timestamps automatically.
   *
   * On success, the system returns the newly created inventory object including
   * its unique ID.
   *
   * Failure scenarios include attempting to create an inventory record for a
   * non-existent SKU or providing invalid data.
   *
   * @param connection
   * @param body New SKU inventory creation payload including SKU id, quantity,
   *   and stock status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSkuInventory.ICreate,
  ): Promise<IShoppingMallSkuInventory> {
    try {
      return await postShoppingMallSellerSkuInventories({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve filtered, paginated list of SKU inventories.
   *
   * Retrieve a filtered and paginated list of SKU inventory statuses from the
   * platform. This operation supports complex search criteria allowing
   * authorized users such as admin and sellers to monitor SKU stock levels,
   * filter by product SKU codes, stock status, quantity thresholds, and page
   * through large inventory sets.
   *
   * The retrieved dataset supports adjustments and alert generation workflows
   * by providing current inventory and stock status details per SKU. This
   * read-only search operation assists in proactive inventory management and
   * operational planning.
   *
   * Security measures ensure only permitted actors access this sensitive
   * inventory data. The operation returns concise SKU inventory summaries
   * optimized for list display with pagination and sorting features.
   *
   * Query parameters are specified in the request body, and results are
   * returned in a paginated format to ensure scalable client consumption of
   * inventory records.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for SKU inventory
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSkuInventory.IRequest,
  ): Promise<IPageIShoppingMallSkuInventory.ISummary> {
    try {
      return await patchShoppingMallSellerSkuInventories({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get detailed SKU inventory data by unique inventory ID.
   *
   * Retrieve the inventory record for a specified product SKU by its unique
   * inventory ID. This operation enables viewing detailed SKU inventory
   * information, including quantity available and current stock status such as
   * 'in stock' or 'out of stock'. It supports operational workflows such as
   * inventory audits, frontend availability checks, and administrative stock
   * monitoring.
   *
   * Security considerations include restricting this operation to authenticated
   * users such as customers, sellers, and admins who need inventory visibility.
   * Unauthorized users or guests do not have access to sensitive inventory
   * data.
   *
   * The underlying database table is shopping_mall_sku_inventories, which
   * tracks inventory quantities and stock status per SKU. The primary key is
   * the UUID id provided as a path parameter.
   *
   * This operation does not allow modification and is read-only. It returns the
   * full inventory record with timestamps and status flags.
   *
   * If the specified inventory ID does not exist, the system shall return a 404
   * Not Found error.
   *
   * Expected behavior includes proper authentication, data retrieval, and
   * compliance with data privacy policies.
   *
   * @param connection
   * @param id Unique identifier of the SKU inventory record to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSkuInventory> {
    try {
      return await getShoppingMallSellerSkuInventoriesId({
        seller,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update SKU inventory record by ID in shopping mall.
   *
   * Update the current inventory record for a specific product SKU in the
   * system. This operation allows authorized actors, such as sellers or admins,
   * to modify the quantity of items available and update the stock status
   * accordingly.
   *
   * The inventory record is uniquely identified by the inventory `id` provided
   * as a path parameter. The operation requires full replacement of inventory
   * details for the targeted SKU. It expects valid values for quantity and
   * stock status to maintain data accuracy and ensure proper stock management.
   *
   * Security considerations dictate that only authorized actors can perform
   * this update. The system must enforce validation rules preventing negative
   * quantities and ensuring valid stock status values.
   *
   * This operation interfaces directly with the `shopping_mall_sku_inventories`
   * Prisma table, managing current inventory states for product SKUs. It plays
   * a vital role in inventory control, preventing overselling and enabling
   * accurate product availability information across the shopping mall
   * platform.
   *
   * This operation is used together with the corresponding DELETE operation to
   * manage the inventory lifecycle comprehensively.
   *
   * @param connection
   * @param id Unique identifier of the SKU inventory record to update
   * @param body Updated inventory details for the SKU
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSkuInventory.IUpdate,
  ): Promise<IShoppingMallSkuInventory> {
    try {
      return await putShoppingMallSellerSkuInventoriesId({
        seller,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete SKU inventory record by ID.
   *
   * Permanently delete the SKU inventory record by its unique ID. This
   * operation removes the record from the database and cannot be undone.
   *
   * Authorized actors only such as sellers and admins may perform this action.
   *
   * Deleting a SKU inventory record can impact stock control and product
   * availability; appropriate use is required.
   *
   * @param connection
   * @param id Unique identifier of the SKU inventory record to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerSkuInventoriesId({
        seller,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
