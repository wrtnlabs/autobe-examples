import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putShoppingMallSellerLowStockAlertsId } from "../../../../providers/putShoppingMallSellerLowStockAlertsId";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerLowStockAlertsId } from "../../../../providers/deleteShoppingMallSellerLowStockAlertsId";

import { IShoppingMallLowStockAlert } from "../../../../api/structures/IShoppingMallLowStockAlert";

@Controller("/shoppingMall/seller/lowStockAlerts/:id")
export class ShoppingmallSellerLowstockalertsController {
  /**
   * Update a low stock alert by ID.
   *
   * Update an existing low stock alert record identified by its unique ID. This
   * operation allows modifying alert attributes such as resolution status and
   * resolution timestamp.
   *
   * The shopping_mall_low_stock_alerts table entries represent alert events
   * triggered when stock levels of product SKUs fall below predefined
   * thresholds. Accurate updating ensures effective inventory monitoring and
   * notification workflows.
   *
   * Security considerations require that only authenticated and authorized
   * users, such as sellers or administrators, can update low stock alert
   * records to prevent tampering.
   *
   * This operation provides essential functionality to manage low stock alerts
   * lifecycle, supporting inventory replenishment and operational continuity.
   *
   * Related operations include creating low stock alerts (automatically by the
   * system), retrieving alert details, and marking alerts as resolved.
   *
   * The operation performs a hard update of the alert record within the
   * underlying PostgreSQL database with concurrency and validation checks
   * enforced at the service layer.
   *
   * @param connection
   * @param id Unique identifier of the low stock alert to update
   * @param body Low stock alert update data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallLowStockAlert.IUpdate,
  ): Promise<IShoppingMallLowStockAlert> {
    try {
      return await putShoppingMallSellerLowStockAlertsId({
        seller,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Hard delete a low stock alert by ID.
   *
   * Delete a low stock alert by its unique identifier from the database. This
   * operation permanently removes the alert record from inventory management.
   *
   * Only authorized users (seller or admin) are permitted to perform this
   * deletion. Deletion is irreversible.
   *
   * This operation is critical for maintaining a clean and accurate set of
   * inventory alerts, eliminating outdated or incorrect alert records.
   *
   * Related operations include creating new alerts and updating existing
   * alerts' statuses.
   *
   * @param connection
   * @param id Unique identifier of the low stock alert to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerLowStockAlertsId({
        seller,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
