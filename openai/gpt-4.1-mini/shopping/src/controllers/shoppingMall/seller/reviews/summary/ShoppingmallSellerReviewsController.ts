import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSaleReview } from "../../../../../api/structures/IShoppingMallSaleReview";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerReviewsSummary } from "../../../../../providers/getShoppingMallSellerReviewsSummary";

@Controller("/shoppingMall/seller/reviews/summary")
export class ShoppingmallSellerReviewsController {
  /**
   * Retrieve summary statistics of product and sale reviews including average star ratings, total counts, and possibly textual analysis of review feedback.
   *
   * This endpoint aggregates ratings from the shopping_mall_product_reviews and shopping_mall_sale_reviews tables, providing an overview useful for dashboards, product listings, or sales insights.
   *
   * Users with appropriate access (customers, sellers, administrators) can utilize this API to understand overall customer sentiment and review distributions.
   *
   * This is a read-only operation that integrates data from multiple tables.
   *
   * No parameters are required as this is a global summary endpoint.
   *
   * The operation can be used together with detailed review retrieval APIs to offer comprehensive review management and display.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the shopping_mall_product_reviews and shopping_mall_sale_reviews tables to compute aggregate data such as average star ratings, total review counts, and distribution histograms.
   * Optimize queries for performance with appropriate indexing.
   * Return a summarized response object containing average ratings and counts for both products and sales.
   * No request body or path parameters needed.
   * Ensure proper authorization checks based on user roles for summary visibility.
   * Handle cases when there are no reviews (returning zero counts and null averages).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async summary(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IShoppingMallSaleReview> {
    try {
      return await getShoppingMallSellerReviewsSummary({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
