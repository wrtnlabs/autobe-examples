import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerStockAdjustments } from "../../../../providers/postShoppingMallSellerStockAdjustments";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerStockAdjustments } from "../../../../providers/patchShoppingMallSellerStockAdjustments";
import { getShoppingMallSellerStockAdjustmentsId } from "../../../../providers/getShoppingMallSellerStockAdjustmentsId";

import { IShoppingMallStockAdjustment } from "../../../../api/structures/IShoppingMallStockAdjustment";
import { IPageIShoppingMallStockAdjustment } from "../../../../api/structures/IPageIShoppingMallStockAdjustment";

@Controller("/shoppingMall/seller/stockAdjustments")
export class ShoppingmallSellerStockadjustmentsController {
  /**
   * Create a new SKU stock adjustment record.
   *
   * Creates a new inventory stock adjustment record to track additions,
   * subtractions, reservations, or releases of SKU stock. The adjustment
   * captures the quantity changed, the actor type (customer, seller, admin),
   * and actor ID to maintain an audit trail. This operation ensures inventory
   * consistency by validating that the SKU exists and the adjustment type is
   * valid. It supports operational integrity by logging stock movements caused
   * by different actors.
   *
   * Security considerations include authenticating the actor and restricting
   * adjustment types. The operation is pivotal for accurate inventory
   * management and prevents overselling or stock miscalculations.
   *
   * This manipulates the shopping_mall_stock_adjustments table according to the
   * Prisma schema, storing all relevant adjustment details for SKU inventory
   * management.
   *
   * @param connection
   * @param body Information about the stock adjustment to be created
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallStockAdjustment.ICreate,
  ): Promise<IShoppingMallStockAdjustment> {
    try {
      return await postShoppingMallSellerStockAdjustments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve paginated stock adjustment records for product SKUs.
   *
   * Retrieve a paginated list of inventory stock adjustments applied to product
   * SKUs within the shopping mall platform. These records document quantity
   * changes resulting from stock additions, subtractions, reservations for
   * orders, and releases of reserved stock.
   *
   * The operation enables clients to perform advanced filtering and searching
   * by SKU, adjustment type, actor type, and other criteria, alongside sorting
   * and pagination.
   *
   * Security considerations require that only authorized roles such as admins,
   * sellers, or system components with inventory management permissions can
   * access these records due to sensitivity.
   *
   * This operation interacts with the shopping_mall_stock_adjustments table in
   * the Prisma schema.
   *
   * The system records the actor responsible for each adjustment (customer,
   * seller, or admin) along with precise adjustments quantities and timestamps.
   * This functionality is key to maintaining inventory accuracy and
   * traceability across the platform.
   *
   * Errors such as invalid filters or unauthorized access are handled
   * gracefully with appropriate HTTP status codes and error messages.
   *
   * @param connection
   * @param body Filtering and pagination parameters for stock adjustments
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallStockAdjustment.IRequest,
  ): Promise<IPageIShoppingMallStockAdjustment.ISummary> {
    try {
      return await patchShoppingMallSellerStockAdjustments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific stock adjustment record by its ID.
   *
   * Retrieve full details of a stock adjustment by its unique identifier. The
   * record includes the SKU affected, adjustment type (addition, subtraction,
   * reservation, or release), quantity change, actor type (customer, seller,
   * admin), actor ID who made the adjustment, and timestamp.
   *
   * Only authorized users such as admins and sellers may access this detailed
   * information.
   *
   * Errors for non-existent IDs or unauthorized access are managed with
   * standard HTTP error responses.
   *
   * @param connection
   * @param id Unique identifier of the stock adjustment record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallStockAdjustment> {
    try {
      return await getShoppingMallSellerStockAdjustmentsId({
        seller,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
