import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putShoppingMallSellerShipmentsShipmentId } from "../../../../providers/putShoppingMallSellerShipmentsShipmentId";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerShipmentsShipmentId } from "../../../../providers/deleteShoppingMallSellerShipmentsShipmentId";

import { IShoppingMallShipment } from "../../../../api/structures/IShoppingMallShipment";

@Controller("/shoppingMall/seller/shipments/:shipmentId")
export class ShoppingmallSellerShipmentsController {
  /**
   * Update shipment details by shipment ID.
   *
   * Update an existing shipment's details in the system identified by the
   * shipment ID.
   *
   * This operation allows authorized users such as sellers and admins to modify
   * shipment information including carriers, tracking numbers, expected
   * delivery dates, and shipment status updates.
   *
   * Security considerations include verification of user roles to prevent
   * unauthorized modifications. The shipment ID must uniquely identify the
   * shipment record, ensuring precise updates.
   *
   * The updated shipment reflects the current state of the physical shipment
   * process. Other related operations include retrieving shipment details (GET)
   * and deleting shipments when appropriate.
   *
   * @param connection
   * @param shipmentId Unique identifier of the target shipment
   * @param body Data for updating the shipment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipment.IUpdate,
  ): Promise<IShoppingMallShipment> {
    try {
      return await putShoppingMallSellerShipmentsShipmentId({
        seller,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete shipment permanently by shipment ID.
   *
   * Permanently delete the shipment identified by shipment ID from the system.
   *
   * This hard delete operation removes all shipment data irrevocably. It
   * requires strict authorization, typically limited to admins and sellers with
   * the necessary permissions.
   *
   * This operation ensures data cleanup but eliminates the possibility of
   * recovery. It should be used with care to avoid loss of critical shipment
   * records.
   *
   * Related operations include shipment creation, update, and retrieval.
   *
   * @param connection
   * @param shipmentId Unique identifier of the target shipment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerShipmentsShipmentId({
        seller,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
