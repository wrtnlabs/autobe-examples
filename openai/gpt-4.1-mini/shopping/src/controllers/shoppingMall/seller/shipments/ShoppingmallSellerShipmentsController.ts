import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallShipment } from "../../../../api/structures/IPageIShoppingMallShipment";
import { IShoppingMallShipment } from "../../../../api/structures/IShoppingMallShipment";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerShipmentsShipmentId } from "../../../../providers/deleteShoppingMallSellerShipmentsShipmentId";
import { getShoppingMallSellerShipmentsShipmentId } from "../../../../providers/getShoppingMallSellerShipmentsShipmentId";
import { patchShoppingMallSellerShipments } from "../../../../providers/patchShoppingMallSellerShipments";
import { postShoppingMallSellerShipments } from "../../../../providers/postShoppingMallSellerShipments";
import { putShoppingMallSellerShipmentsShipmentId } from "../../../../providers/putShoppingMallSellerShipmentsShipmentId";

@Controller("/shoppingMall/seller/shipments")
export class ShoppingmallSellerShipmentsController {
  /**
   * This API operation allows an authenticated seller to create a shipment grouping one or more order items they are responsible for shipping. The seller provides the shipment details including carrier name, tracking number, and the list of order items to be included in the shipment.
   *
   * Upon successful creation, the system will update the statuses of the included order items to "shipped" and save shipment tracking information for customer visibility and order fulfillment tracking.
   *
   * Security: Only authenticated sellers who own the relevant orders can create shipments. The system enforces that only items associated with the seller can be included.
   *
   * This operation primarily interacts with the following database tables:
   *
   * - `shopping_mall_shipments`: Stores shipment records created by sellers.
   * - `shopping_mall_shipment_order_items`: Links shipments to specific order items included in each shipment.
   * - `shopping_mall_shipment_trackings`: Holds tracking details such as carrier name and tracking number.
   *
   * Validation includes verifying order items are in the correct state for shipping (e.g., paid but not yet shipped). Transactional integrity ensures that partial updates do not occur.
   *
   * Related operations include `GET /sellers/orders` to list eligible order items for shipping and `PUT /sellers/orders/items/{orderItemId}/ship` for individual item shipment status updates. This bulk creation operation streamlines shipment grouping.
   *
   *
   * @param connection
   * @param body Shipment creation details including carrier info and order items to be shipped.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Authenticate seller making the request.
   * 2. Validate request body including carrier info and order item IDs.
   * 3. Query order items to confirm ownership, status (paid, not shipped), and eligibility.
   * 4. Begin database transaction.
   * 5. Insert new shipment record into shopping_mall_shipments with carrier and tracking info.
   * 6. Insert records into shopping_mall_shipment_order_items linking shipment to order items.
   * 7. Insert tracking record into shopping_mall_shipment_trackings with carrier and tracking number.
   * 8. Update status of order items to "shipped".
   * 9. Commit transaction.
   * 10. Return created shipment information in response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallShipment.ICreate,
  ): Promise<IShoppingMallShipment> {
    try {
      return await postShoppingMallSellerShipments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of shipments within the shopping mall platform.
   *
   * This endpoint allows clients to search shipments by various criteria such as status, seller ID, and creation dates. Shipments represent packages created by sellers containing grouped order items for shipping. The operation supports pagination and sorting to handle large datasets efficiently.
   *
   * Authorization is required to ensure only permitted actors (sellers, admins) can access shipment data.
   *
   * The shipment entity includes details such as the seller who created it, its current status, and timestamps recording its lifecycle stages. This endpoint is crucial for managing shipping workflows and tracking shipment progress.
   *
   * Related operations include POST /shipments for creating new shipments and GET /shipments/{shipmentId} for fetching shipment detail.
   *
   * @param connection
   * @param body Search criteria and pagination for shipments
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement pagination with offset, limit, and sorting based on creation date and status.
   * Support filtering on shipment status, seller ID, and created_at timestamp range.
   * Query shopping_mall_shipments table with provided filters.
   * Return paginated summary of shipments using IPageIShoppingMallShipment.ISummary type.
   * Ensure authorization constraints are enforced at service layer.
   * Handle edge cases such as empty result sets and invalid filter values gracefully.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallShipment.IRequest,
  ): Promise<IPageIShoppingMallShipment.ISummary> {
    try {
      return await patchShoppingMallSellerShipments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a seller shipment including shipment status, timestamps, and seller reference.
   *
   * This API operation supports sellers to review their shipment records as well as administrators to monitor shipment statuses. The shipment resource includes key fields such as shipment ID, seller ID and profile, status, creation and update timestamps.
   *
   * The operation verifies existence and ownership for sellers, and provides immutable shipment data consistent with the shopping mall's shipping management processes.
   *
   * Related operations include shipment item management and tracking updates performed by sellers, as well as customer viewing of shipment tracking details.
   *
   * @param connection
   * @param shipmentId The unique identifier of the shipment (UUID).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement a service method to query the shopping_mall_shipments table by shipmentId filtering out soft-deleted records (deleted_at IS NULL).
   * Include the seller relation data to provide seller details for the shipment.
   * Return 404 if the shipmentId does not exist or is soft-deleted.
   * Authorization: allow access to the seller owning the shipment and administrators.
   * No requestBody since GET method.
   * Response: return complete shipment entity data using IShoppingMallShipment schema.
   * Log accesses for auditing shipment detail views.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment> {
    try {
      return await getShoppingMallSellerShipmentsShipmentId({
        seller,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a shipment resource fully with new details such as carrier name, tracking number, shipped items, and shipment status. The shipment groups order items from sellers for shipping and tracking purposes. Updating shipment involves validating and modifying shipment's carrier, tracking info, and linked order items for shipment accuracy.
   *
   * Access control: Typically restricted to authenticated sellers and administrators managing shipment logistics.
   *
   * The underlying database entity `shopping_mall_shipments` stores shipment information. Fields include ID (UUID), seller reference, carrier name, tracking number, shipment date, and status. Relationships to `shopping_mall_shipment_order_items` indicate which order items are included in the shipment.
   *
   * Validation includes ensuring shipmentId exists, linked order items are valid and belong to the seller, and status transitions are consistent with business rules.
   *
   * Related operations include creating shipments (POST /shipments), viewing shipments (GET /shipments/{shipmentId}), and confirming delivery (POST /customers/orders/confirm-delivery/{shipmentId}).
   *
   * Errors are handled with appropriate HTTP status codes for not found, validation failure, or unauthorized access.
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment to update
   * @param body Payload containing updated shipment details
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Service Layer:
   * - Validate shipmentId as UUID.
   * - Check existence of shipment in shopping_mall_shipments.
   * - Authenticate that the user is authorized seller or admin.
   * - Validate request body with IShoppingMallShipment.IUpdate schema.
   * - Update shipment fields: carrier, tracking number, status.
   * - Update or replace linked shipment order items as per request.
   * - Enforce business rules on status transitions.
   * - Persist changes within transaction to maintain consistency.
   * - Return updated shipment entity with full details.
   *
   * Database Queries:
   * - SELECT shipment by shipmentId.
   * - UPDATE shipments table with new fields.
   * - Manage relations in shipment_order_items table.
   *
   * Error Handling:
   * - 404 if shipment not found.
   * - 400 if validation fails.
   * - 403 if unauthorized.
   *
   * Integration:
   * - Notify relevant systems on shipment update if needed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shipmentId")
  public async updateShipment(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipment.IUpdate,
  ): Promise<IShoppingMallShipment> {
    try {
      return await putShoppingMallSellerShipmentsShipmentId({
        seller,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API permanently removes a shipment record specified by the shipment ID path parameter.
   *
   * The shipment entity represents packages created by sellers containing grouped order items for shipping. The system manages shipment lifecycle including statuses such as pending, shipped, delivered, and cancelled. This endpoint deletes the shipment, updating any dependent order item statuses as required.
   *
   * Access to this operation is restricted to authorized sellers and administrators.
   *
   * The shipment ID is a UUID string path parameter.
   *
   * @param connection
   * @param shipmentId UUID string identifier of the shipment to delete.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Perform authorization check for the actor to ensure permission to delete shipments.
   * Validate the shipmentId as UUID.
   * Execute a transaction to delete the shipment record targeting shopping_mall_shipments by id.
   * Cascade deletion or update related shipment items (shopping_mall_shipment_order_items) accordingly.
   * Return success with empty body to indicate permanent deletion.
   * Handle errors if shipment is not found or deletion is disallowed.
   * Log deletion audit for compliance tracking.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":shipmentId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerShipmentsShipmentId({
        seller,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
