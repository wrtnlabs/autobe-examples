import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallShipmentTracking } from "../../../../../api/structures/IShoppingMallShipmentTracking";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { postShoppingMallSellerShipmentsShipmentIdTracking } from "../../../../../providers/postShoppingMallSellerShipmentsShipmentIdTracking";

@Controller("/shoppingMall/seller/shipments/:shipmentId/tracking")
export class ShoppingmallSellerShipmentsTrackingController {
  /**
   * Create a new tracking record for a specific shipment.
   *
   * This operation allows sellers to provide and update shipping carrier and tracking numbers associated with a shipment for order tracking.
   *
   * The operation updates the shopping_mall_shipment_trackings table by inserting a new record linked to the specified shipment ID.
   *
   * Only sellers authorized for the shipment can perform this operation.
   *
   * Path parameter shipmentId is a UUID referencing shopping_mall_shipments.id.
   *
   * Request body must include carrierName and trackingNumber.
   *
   * Upon success, the newly created shipment tracking record is returned, including timestamps.
   *
   * Related operations include GET /shipments/{shipmentId} to retrieve shipment details and tracking info.
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment
   * @param body Tracking information to add to the shipment
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate shipment existence and seller authorization. Insert a new record into shopping_mall_shipment_trackings with the given carrier_name and tracking_number, linking to the shipmentId. Populate created_at and updated_at timestamps automatically. Return the newly created shipment tracking record as response. Handle errors for invalid shipmentId, unauthorized access, and duplicate tracking numbers if applicable.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async createTracking(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipmentTracking.ICreate,
  ): Promise<IShoppingMallShipmentTracking> {
    try {
      return await postShoppingMallSellerShipmentsShipmentIdTracking({
        seller,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
