import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallSellerShoppingMallProducts } from "../../../../providers/postShoppingMallSellerShoppingMallProducts";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerShoppingMallProductsProductCode } from "../../../../providers/putShoppingMallSellerShoppingMallProductsProductCode";
import { deleteShoppingMallSellerShoppingMallProductsProductCode } from "../../../../providers/deleteShoppingMallSellerShoppingMallProductsProductCode";

import { IShoppingMallProduct } from "../../../../api/structures/IShoppingMallProduct";

@Controller("/shoppingMall/seller/shoppingMallProducts")
export class ShoppingmallSellerShoppingmallproductsController {
  /**
   * Allows authenticated sellers or administrators to create a new product
   * record.
   *
   * The product code must be unique and follow business standards for
   * identification.
   *
   * Detailed product attributes include title, optional description, brand, and
   * linkage to a category.
   *
   * Server-generated timestamps ensure tracking of record creation and latest
   * updates.
   *
   * Proper authorization is enforced to limit product creation to verified
   * entities.
   *
   * The response returns the created product entity including generated
   * identifiers and timestamps.
   *
   * @param connection
   * @param body Complete information for creating a shopping mall product
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProduct.ICreate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await postShoppingMallSellerShoppingMallProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a shopping mall product's details including title, description,
   * brand, and category association.
   *
   * This operation identifies the target product using the unique productCode
   * path parameter. It allows authorized sellers or administrators to modify
   * product information to keep data current and accurate.
   *
   * Only products that have not been soft-deleted (deleted_at null) can be
   * updated. The category reference (shopping_mall_category_id) must point to a
   * valid category in the product catalog.
   *
   * Proper validation ensures the business rules are respected, including
   * unique codes and referential integrity. The update is logged internally for
   * audit purposes.
   *
   * Related operations include product creation, deletion, and retrieval
   * endpoints that allow full lifecycle management of mall products.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target shopping
   *   mall product (global scope)
   * @param body Updated product data for modification
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productCode")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productCode")
    productCode: string,
    @TypedBody()
    body: IShoppingMallProduct.IUpdate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await putShoppingMallSellerShoppingMallProductsProductCode({
        seller,
        productCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a shopping mall product using the unique productCode
   * path parameter.
   *
   * This operation removes the product record entirely from the database and
   * cannot be undone. It is restricted to authorized sellers and administrators
   * to prevent accidental data loss.
   *
   * Usage of this endpoint should consider cascading effects on related
   * entities like variants, inventory, and order data.
   *
   * Complementary endpoints allow product creation and updates to manage
   * lifecycle.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target shopping
   *   mall product (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productCode")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productCode")
    productCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerShoppingMallProductsProductCode({
        seller,
        productCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
