import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallUserNotification } from "../../../../../api/structures/IPageIShoppingMallUserNotification";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerNotificationsSummary } from "../../../../../providers/getShoppingMallSellerNotificationsSummary";

@Controller("/shoppingMall/seller/notifications/summary")
export class ShoppingmallSellerNotificationsSummaryController {
  /**
   * Retrieve a summarized list of notifications specific to the authenticated seller user.
   *
   * This API provides notification titles, bodies, delivery statuses, read statuses, and linked template information.
   *
   * It queries the shopping_mall_user_notifications table for notifications owned by the current authenticated seller.
   * Join with shopping_mall_notification_templates to obtain template code and name.
   * Aggregate delivery statuses from shopping_mall_notification_deliveries for delivery timestamps.
   *
   * Only notifications owned by the authenticated seller are returned, ensuring strict access control.
   *
   * This operation is read-only and does not support creation, update, or deletion.
   *
   * Related database tables:
   * - shopping_mall_user_notifications: User-specific notification records
   * - shopping_mall_notification_templates: Notification template details
   * - shopping_mall_notification_deliveries: Delivery status tracking
   * - shopping_mall_notification_logs: Notification event logs
   *
   * No system-generated data is modified by this operation. It serves to provide a user-facing notification summary.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_user_notifications filtering by owner_id using the authenticated user's ID.
   * Join shopping_mall_notification_templates to get the template_code and template_name.
   * Aggregate delivery statuses from shopping_mall_notification_deliveries for each user notification.
   * Return a paginated list of summarized notifications including title, body, is_read flag, delivered_at, read_at timestamps, and template info.
   * Ensure efficient querying with indexes on owner_id and created_at.
   * Handle potential null values for optional URL and image_url fields.
   * Authorize by verifying user's identity and ownership of notifications.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IPageIShoppingMallUserNotification.ISummary> {
    try {
      return await getShoppingMallSellerNotificationsSummary({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
