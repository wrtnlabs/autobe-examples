import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSellerDashboard } from "../../../../api/structures/IShoppingMallSellerDashboard";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerDashboard } from "../../../../providers/getShoppingMallSellerDashboard";

@Controller("/shoppingMall/seller/dashboard")
export class ShoppingmallSellerDashboardController {
  /**
   * Retrieve an overview dashboard for the authenticated seller, aggregating data across the seller's products and related order activities including pending cancellations and refunds.
   *
   * This endpoint returns summary statistics such as total product count, total order items count, counts of pending cancellation and refund requests, and a list of order items filtered optionally by status.
   *
   * Security constraints enforce that only authenticated sellers with an approved status can access this resource.
   *
   * The dashboard aggregates multiple data sources:
   * - shopping_mall_sellers: validated authenticated user
   * - shopping_mall_products: count products by seller
   * - shopping_mall_order_items: count and list order items by product variants belonging to seller
   * - shopping_mall_cancellation_requests and shopping_mall_refund_requests: pending request counts filtered by seller
   *
   * No request body is provided since filters are query parameters and context-based.
   *
   * This operation enables sellers to monitor key metrics and manage order fulfillment efficiently.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification The implementation should perform the following steps:
   *
   * 1. Authenticate and authorize the user as a seller who has an approved status.
   * 2. Query shopping_mall_products for the seller's ID to count total products.
   * 3. Query shopping_mall_order_items linked through product variants to count total order items.
   * 4. Query shopping_mall_cancellation_requests and shopping_mall_refund_requests to count the pending requests associated with the seller.
   * 5. Provide optional filtering capability on order item lists by status, supporting pagination and sorting.
   * 6. Construct a detailed response that includes the counts and the filtered list of order items.
   * 7. Handle potential errors such as unauthorized access, missing seller profile, or database errors.
   * 8. Ensure queries are optimized, possibly using joins and indexes on foreign keys.
   *
   * This endpoint returns JSON data tailored for frontend dashboard display, optimized for performance and usability.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async getSellerDashboard(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IShoppingMallSellerDashboard> {
    try {
      return await getShoppingMallSellerDashboard({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
