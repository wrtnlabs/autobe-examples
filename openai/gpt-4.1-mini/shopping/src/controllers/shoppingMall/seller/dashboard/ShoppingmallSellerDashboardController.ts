import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSellerSellerDashboard } from "../../../../api/structures/IShoppingMallSellerSellerDashboard";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerDashboard } from "../../../../providers/getShoppingMallSellerDashboard";

@Controller("/shoppingMall/seller/dashboard")
export class ShoppingmallSellerDashboardController {
  /**
   * Retrieve the seller dashboard overview providing key metrics and filtered order item lists.
   *
   * This endpoint allows an authenticated and approved seller to access metrics including total products, total order items, and the count of pending cancellation and refund requests. It supports filtering order items by status with pagination capabilities.
   *
   * The operation draws data primarily from the `shopping_mall_sellers`, `shopping_mall_products`, and `shopping_mall_order_items` tables. Relationships between sellers, their products, and order items are queried and aggregated accordingly.
   *
   * Access is restricted to sellers with `approved` status who are not suspended. Suspended sellers are denied access.
   *
   * This operation is essential to the seller workflow, enabling effective management of shop performance and order processing.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Authenticate the seller actor, verify approval status is 'approved' and not suspended.
   * 2. Query shopping_mall_products table to count total products for the seller.
   * 3. Query shopping_mall_order_items joined with shopping_mall_products by product_variant ownership to count total order items and pending cancellation/refund requests.
   * 4. Support filtering order items by order item status within the dashboard.
   * 5. Paginate order item lists to ensure UI responsiveness.
   * 6. Return a consolidated response DTO matching IShoppingMallSellerDashboard including counts and detail lists.
   * 7. Implement caching strategies for dashboard data to optimize performance.
   * 8. Log access events and track usage statistics for monitoring.
   * 9. Handle error cases for unauthenticated, unapproved, or suspended sellers with appropriate HTTP error responses.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IShoppingMallSellerSellerDashboard> {
    try {
      return await getShoppingMallSellerDashboard({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
