import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerSellerProfiles } from "../../../../providers/postShoppingMallSellerSellerProfiles";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerSellerProfilesId } from "../../../../providers/putShoppingMallSellerSellerProfilesId";
import { deleteShoppingMallSellerSellerProfilesId } from "../../../../providers/deleteShoppingMallSellerSellerProfilesId";

import { IShoppingMallSellerProfile } from "../../../../api/structures/IShoppingMallSellerProfile";

@Controller("/shoppingMall/seller/sellerProfiles")
export class ShoppingmallSellerSellerprofilesController {
  /**
   * Create a new seller profile record in the database with provided business
   * and contact details.
   *
   * Create a new seller profile with detailed business and contact information
   * on the shopping mall platform. This API allows authorized systems or
   * administrators to register seller profile data including store name,
   * business registration number, and contact details.
   *
   * The operation enforces uniqueness constraints on seller ID and contact
   * email to prevent duplicate profiles. The 'contact_email' field ensures
   * reliable communication.
   *
   * Security considerations include validation of the authenticated seller
   * context. Timestamps for creation and updates are managed automatically to
   * support auditing and data integrity.
   *
   * This operation does not include soft deletion fields in its creation input,
   * focusing on active profile creation only.
   *
   * @param connection
   * @param body Information required to create a new seller profile.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSellerProfile.ICreate,
  ): Promise<IShoppingMallSellerProfile> {
    try {
      return await postShoppingMallSellerSellerProfiles({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the seller profile identified by ID with provided information.
   *
   * Update an existing seller profile's business and contact information. This
   * operation allows modification of fields such as store name, business
   * registration number, contact email, contact phone number, and profile
   * description.
   *
   * The seller profile is identified by its unique ID in the path parameter.
   *
   * Uniqueness of contact email is enforced during update, and all
   * modifications are timestamped to maintain audit trails.
   *
   * This operation requires authentication as a seller to ensure only
   * authorized modifications.
   *
   * No soft deletion is controlled by this endpoint; it strictly updates active
   * profile fields.
   *
   * @param connection
   * @param id Unique identifier of the seller profile to update
   * @param body Seller profile update data containing modifiable properties.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSellerProfile.IUpdate,
  ): Promise<IShoppingMallSellerProfile> {
    try {
      return await putShoppingMallSellerSellerProfilesId({
        seller,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a seller profile by ID.
   *
   * This DELETE API operation permanently removes a seller profile from the
   * shopping mall platform's database using the unique identifier.
   *
   * The seller profile contains business and contact information associated
   * with a seller account. Deletion of the profile will cascade and remove
   * relevant links.
   *
   * Security considerations include validating that the requester is authorized
   * to delete this seller profile, typically requiring admin or owning seller
   * privileges.
   *
   * Referencing the shopping_mall_seller_profiles Prisma schema, this operation
   * performs a hard delete, removing the entire record permanently and cannot
   * be recovered.
   *
   * No request body is required for this operation since the seller profile ID
   * in the path fully identifies the resource to delete.
   *
   * Successful execution results in no content response, confirming removal.
   *
   * This operation is generally used when a seller account is being closed or
   * cleaned up in the system.
   *
   * @param connection
   * @param id Unique identifier of the seller profile to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async eraseSellerProfile(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerSellerProfilesId({
        seller,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
