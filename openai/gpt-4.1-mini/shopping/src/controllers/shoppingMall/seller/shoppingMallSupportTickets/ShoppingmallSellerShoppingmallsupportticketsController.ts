import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerShoppingMallSupportTickets } from "../../../../providers/postShoppingMallSellerShoppingMallSupportTickets";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerShoppingMallSupportTicketsShoppingMallSupportTicketId } from "../../../../providers/putShoppingMallSellerShoppingMallSupportTicketsShoppingMallSupportTicketId";

import { IShoppingMallSupportTicket } from "../../../../api/structures/IShoppingMallSupportTicket";

@Controller("/shoppingMall/seller/shoppingMallSupportTickets")
export class ShoppingmallSellerShoppingmallsupportticketsController {
  /**
   * Create a new shopping mall support ticket.
   *
   * Create a new support ticket for customers or sellers in the ShoppingMall
   * platform.
   *
   * This operation accepts detailed ticket information including the issue
   * title and description. Tickets are associated with a submitting customer or
   * seller and include session identifiers to provide context. The initial
   * status is set on creation and managed through workflow operations later.
   *
   * Security considerations require authentication as a customer or seller. The
   * system validates referenced customer or seller identities and session
   * information. Typical usage includes issue reporting, feature requests, and
   * general inquiries.
   *
   * Related operations include updating existing tickets via PUT
   * /shoppingMallSupportTickets/{shoppingMallSupportTicketId}.
   *
   * @param connection
   * @param body Support ticket creation payload
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSupportTicket.ICreate,
  ): Promise<IShoppingMallSupportTicket> {
    try {
      return await postShoppingMallSellerShoppingMallSupportTickets({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update shopping mall support ticket by ID.
   *
   * Update an existing shopping mall support ticket specified by the ticket ID.
   *
   * This operation allows modification of ticket details including title,
   * description, and status. It requires authentication as the user associated
   * with the ticket or an authorized seller. The ticket's last updated
   * timestamp is recorded automatically.
   *
   * Security checks confirm the caller's authorization to update the ticket and
   * validate status transitions. Related auditing and session context update
   * workflows are linked.
   *
   * This API uses the ticket UUID as the path parameter since the identifier is
   * a UUID and no global unique code is defined.
   *
   * Related operations: Create support ticket (POST
   * /shoppingMallSupportTickets).
   *
   * @param connection
   * @param shoppingMallSupportTicketId Unique UUID identifier of the shopping
   *   mall support ticket
   * @param body Support ticket update payload
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shoppingMallSupportTicketId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shoppingMallSupportTicketId")
    shoppingMallSupportTicketId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSupportTicket.IUpdate,
  ): Promise<IShoppingMallSupportTicket> {
    try {
      return await putShoppingMallSellerShoppingMallSupportTicketsShoppingMallSupportTicketId(
        {
          seller,
          shoppingMallSupportTicketId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
