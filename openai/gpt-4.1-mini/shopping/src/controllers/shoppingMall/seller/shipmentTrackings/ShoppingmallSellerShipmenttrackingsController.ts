import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerShipmentTrackings } from "../../../../providers/postShoppingMallSellerShipmentTrackings";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerShipmentTrackings } from "../../../../providers/patchShoppingMallSellerShipmentTrackings";
import { getShoppingMallSellerShipmentTrackingsId } from "../../../../providers/getShoppingMallSellerShipmentTrackingsId";
import { putShoppingMallSellerShipmentTrackingsId } from "../../../../providers/putShoppingMallSellerShipmentTrackingsId";
import { deleteShoppingMallSellerShipmentTrackingsId } from "../../../../providers/deleteShoppingMallSellerShipmentTrackingsId";

import { IShoppingMallShipmentTracking } from "../../../../api/structures/IShoppingMallShipmentTracking";
import { IPageIShoppingMallShipmentTracking } from "../../../../api/structures/IPageIShoppingMallShipmentTracking";

@Controller("/shoppingMall/seller/shipmentTrackings")
export class ShoppingmallSellerShipmenttrackingsController {
  /**
   * Create a shipment tracking record linked to an order.
   *
   * Create a new shipment tracking record for an order. This endpoint records
   * the tracking number, shipping carrier, shipment status, shipment and
   * delivery dates, and ties the shipment to the order identified by its ID.
   *
   * Security measures ensure that only authorized actors including sellers for
   * their own orders or admins can perform this operation.
   *
   * The request body requires all necessary data to define the shipment
   * tracking record. The response returns the detailed shipment tracking data
   * stored.
   *
   * This is a standard POST creation operation without query parameters.
   *
   * @param connection
   * @param body Shipment tracking creation data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallShipmentTracking.ICreate,
  ): Promise<IShoppingMallShipmentTracking> {
    try {
      return await postShoppingMallSellerShipmentTrackings({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve paginated shipment tracking entries.
   *
   * Retrieve a paginated list of shipment tracking records based on search
   * criteria from the shopping_mall_shipment_trackings table. The operation
   * supports complex search filters, full-text search on tracking numbers and
   * carrier names, status-based filtering, and time range queries for shipment
   * events.
   *
   * Security considerations mandate that only authorized admin or seller actors
   * can access shipment data to protect customer order privacy and prevent
   * unauthorized data exposure.
   *
   * The response includes paginated summaries of shipment tracking information
   * suitable for dashboard or reporting UI components. The request body
   * specifies search parameters such as tracking number keywords, carrier
   * filters, shipping status, and pagination controls.
   *
   * @param connection
   * @param body Search parameters and pagination options for shipment tracking
   *   entries
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallShipmentTracking.IRequest,
  ): Promise<IPageIShoppingMallShipmentTracking.ISummary> {
    try {
      return await patchShoppingMallSellerShipmentTrackings({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve shipment tracking information by ID from
   * shopping_mall_shipment_trackings.
   *
   * Retrieve detailed shipment tracking information for a specific shipment
   * identified by its unique ID. This endpoint accesses the
   * shopping_mall_shipment_trackings table which captures carrier-provided
   * tracking numbers, shipping carrier names, current shipment status, shipment
   * and delivery timestamps, and metadata.
   *
   * Security considerations require that only authorized actors such as
   * customers associated with the order, sellers managing the shipment, or
   * admin users can access this sensitive shipment tracking data.
   *
   * The response includes all relevant tracking fields reflecting the current
   * shipping lifecycle stage, allowing user interfaces to provide accurate and
   * timely shipment status updates.
   *
   * This operation is a read-only GET and requires the shipmentTracking ID as
   * the path parameter. Validation ensures the shipment ID exists, and proper
   * authorization is enforced.
   *
   * @param connection
   * @param id Unique identifier of the shipment tracking record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("id")
    id: string,
  ): Promise<IShoppingMallShipmentTracking> {
    try {
      return await getShoppingMallSellerShipmentTrackingsId({
        seller,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update shipment tracking record by ID in shopping_mall_shipment_trackings
   * table.
   *
   * Update shipment tracking information for a specific order. This operation
   * allows authorized users to modify the tracking number, carrier, and
   * shipping status, as well as update shipment and delivery timestamps. Proper
   * validation ensures integrity and consistency of shipment data.
   *
   * Security considerations mandate that only authorized actors such as admins
   * or sellers with appropriate permissions can update shipment tracking
   * records. The operation verifies the existence of the shipment tracking
   * entry with the given ID and applies all changes atomically.
   *
   * This operation directly affects the shopping_mall_shipment_trackings table
   * in the database, which stores shipment details linked to individual orders.
   * Clients must ensure that updated data adheres to allowed status
   * enumerations and business rules regarding shipping lifecycle.
   *
   * Related API operations include GET for shipment tracking retrieval and
   * DELETE for removal of shipment tracking records.
   *
   * Expected behavior includes returning the fully updated shipment tracking
   * object on success. Errors include 404 if the record does not exist, and 403
   * for unauthorized access.
   *
   * @param connection
   * @param id Unique identifier of the target shipment tracking record
   * @param body Updated shipment tracking information for complete replacement
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async updateShipmentTracking(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipmentTracking.IUpdate,
  ): Promise<IShoppingMallShipmentTracking> {
    try {
      return await putShoppingMallSellerShipmentTrackingsId({
        seller,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete shipment tracking record by ID from shopping_mall_shipment_trackings
   * table.
   *
   * Permanently remove a shipment tracking record using its unique ID. This
   * hard delete operation deletes the record from the
   * shopping_mall_shipment_trackings table irrevocably.
   *
   * Only authorized users such as admins and sellers are allowed to delete
   * shipment tracking data.
   *
   * Appropriate error responses include 404 not found and 403 forbidden for
   * unauthorized users.
   *
   * This operation helps clean up obsolete shipment tracking data in the
   * system.
   *
   * @param connection
   * @param id Unique identifier of the shipment tracking record to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async eraseShipmentTracking(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerShipmentTrackingsId({
        seller,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
