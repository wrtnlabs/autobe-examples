import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putShoppingMallSellerShoppingMallSellersShoppingMallSellerId } from "../../../../providers/putShoppingMallSellerShoppingMallSellersShoppingMallSellerId";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerShoppingMallSellersShoppingMallSellerId } from "../../../../providers/deleteShoppingMallSellerShoppingMallSellersShoppingMallSellerId";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";

@Controller("/shoppingMall/seller/shoppingMallSellers/:shoppingMallSellerId")
export class ShoppingmallSellerShoppingmallsellersController {
  /**
   * Update the information of a specific seller in the shopping mall system.
   *
   * This endpoint allows authenticated sellers to update their profile and
   * relevant business details. The operation requires the shoppingMallSellerId
   * path parameter, which uniquely identifies the seller to be updated. The
   * request body must conform to the IShoppingMallSeller.IUpdate DTO,
   * reflecting the fields editable by the user.
   *
   * Security constraints ensure only authorized sellers can perform updates on
   * their own records. The system performs necessary validation and concurrency
   * control.
   *
   * Related operations include retrieving seller details via GET
   * /shoppingMallSellers/{shoppingMallSellerId} and deleting a seller via
   * DELETE /shoppingMallSellers/{shoppingMallSellerId}.
   *
   * @param connection
   * @param shoppingMallSellerId Unique identifier of the shopping mall seller
   *   to update
   * @param body Updated seller information conforming to
   *   IShoppingMallSeller.IUpdate
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shoppingMallSellerId")
    shoppingMallSellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSeller.IUpdate,
  ): Promise<IShoppingMallSeller> {
    try {
      return await putShoppingMallSellerShoppingMallSellersShoppingMallSellerId(
        {
          seller,
          shoppingMallSellerId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a specific seller from the shopping mall system.
   *
   * This operation allows authenticated sellers to delete their own accounts.
   * The seller to be deleted is identified by the shoppingMallSellerId path
   * parameter. Upon successful execution, the seller's data is permanently
   * deleted.
   *
   * Security measures ensure that only the owner seller can perform the
   * deletion. There is no request body for this operation.
   *
   * Related operations include updating seller information via PUT
   * /shoppingMallSellers/{shoppingMallSellerId} and retrieving seller details.
   *
   * This is a hard delete operation; no soft deletion is performed.
   *
   * @param connection
   * @param shoppingMallSellerId Unique identifier of the shopping mall seller
   *   to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shoppingMallSellerId")
    shoppingMallSellerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerShoppingMallSellersShoppingMallSellerId(
        {
          seller,
          shoppingMallSellerId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
