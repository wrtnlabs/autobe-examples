import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putShoppingMallSellerRefundRequestsRefundRequestId } from "../../../../providers/putShoppingMallSellerRefundRequestsRefundRequestId";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";

import { IShoppingMallRefundRequest } from "../../../../api/structures/IShoppingMallRefundRequest";

@Controller("/shoppingMall/seller/refundRequests/:refundRequestId")
export class ShoppingmallSellerRefundrequestsController {
  /**
   * Update details of an existing refund request by specifying its unique
   * identifier.
   *
   * This operation enables authorized users to adjust refund amounts, change
   * refund reasons, update the refund status, as well as set the processed
   * timestamp if applicable.
   *
   * It maps directly to the shopping_mall_refund_requests table and enforces
   * that only valid refund statuses can be set through the system. The
   * operation ensures that timestamps used are in ISO 8601 format and that
   * refund amounts are non-negative.
   *
   * Security constraints require authentication and role-based permissions. The
   * updated refund request will be returned in the response.
   *
   * Related API operations include reading refund request details and deleting
   * refund requests.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request
   * @param body Data needed to update the refund request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallRefundRequest.IUpdate,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await putShoppingMallSellerRefundRequestsRefundRequestId({
        seller,
        refundRequestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
