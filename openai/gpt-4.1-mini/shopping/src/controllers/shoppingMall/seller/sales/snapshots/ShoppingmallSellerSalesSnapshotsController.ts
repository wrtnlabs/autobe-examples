import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallSaleSnapshot } from "../../../../../api/structures/IPageIShoppingMallSaleSnapshot";
import { IShoppingMallSaleSnapshot } from "../../../../../api/structures/IShoppingMallSaleSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerSalesSaleIdSnapshotsSnapshotId } from "../../../../../providers/getShoppingMallSellerSalesSaleIdSnapshotsSnapshotId";
import { patchShoppingMallSellerSalesSaleIdSnapshots } from "../../../../../providers/patchShoppingMallSellerSalesSaleIdSnapshots";

@Controller("/shoppingMall/seller/sales/:saleId/snapshots")
export class ShoppingmallSellerSalesSnapshotsController {
  /**
   * Retrieve a filtered and paginated list of snapshots for a specific sale entity in the shopping mall platform.
   *
   * These snapshots provide an immutable audit trail of all changes made to the sale listing, preserving previous states for dispute resolution and history tracking.
   *
   * Only authorized actors such as sales managers, administrators, or the sale owner may access this information to review change history.
   *
   * The response includes summary information for each snapshot, including timestamp, changed fields, and brief change descriptions.
   *
   * Filtering options support date ranges and specific change types, combined with cursor or offset pagination to handle large volumes efficiently.
   *
   * For large data sets, pagination ensures system responsiveness and minimizes load on the database and network.
   *
   * No modifications are allowed via this endpoint, preserving snapshot immutability.
   *
   * @param connection
   * @param saleId Unique identifier of the sale (UUID format) to retrieve snapshots for
   * @param body Search criteria and pagination parameters for sale snapshot listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification This operation queries the shopping_mall_sale_snapshots table filtered by saleId path parameter.
   * It supports pagination using offset or cursor with page size limits in the request body.
   * Filtering criteria include timestamp ranges and change type filters from request body properties.
   * The query results are mapped to the IShoppingMallSaleSnapshot.ISummary DTO for efficient transmission.
   * Authorization checks ensure only authorized actors can read snapshots for the sale.
   * No data modifications occur. Read-only operation.
   * Response includes pagination metadata and list data array.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleId")
    saleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSaleSnapshot.IRequest,
  ): Promise<IPageIShoppingMallSaleSnapshot.ISummary> {
    try {
      return await patchShoppingMallSellerSalesSaleIdSnapshots({
        seller,
        saleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific sale snapshot by its unique snapshot identifier and associated sale identifier.
   *
   * This operation provides access to an immutable historical snapshot capturing the state of a sale at a particular time. It supports auditing, historical viewing, and dispute resolution.
   *
   * Access is restricted to authorized users such as administrators and perhaps the seller owning the sale, ensuring sensitive snapshot data security.
   *
   * Parameters include saleId and snapshotId, both UUID format strings identifying the targeted sale and snapshot respectively.
   *
   * No request body is needed as this is a retrieval operation.
   *
   * The response contains the full detailed snapshot entity, preserving all relevant sale data at the snapshot time.
   *
   * Refer to the shopping_mall_sale_snapshots database schema for full snapshot field details.
   *
   * @param connection
   * @param saleId Unique identifier of the sale whose snapshot is being requested, in UUID format.
   * @param snapshotId Unique identifier of the snapshot of the sale to retrieve, in UUID format.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement authorization middleware to allow only administrators and owning sellers access to this snapshot.
   *
   * Retrieve the immutable snapshot from the shopping_mall_sale_snapshots table using saleId and snapshotId.
   *
   * Ensure the snapshot corresponds to the specified sale to prevent data leakage.
   *
   * Respond with serialized IShoppingMallSaleSnapshot data structure.
   *
   * Log access events for audit trail.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleId")
    saleId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSaleSnapshot> {
    try {
      return await getShoppingMallSellerSalesSaleIdSnapshotsSnapshotId({
        seller,
        saleId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
