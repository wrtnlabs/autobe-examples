import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallSellerSellers } from "../../../../providers/patchShoppingMallSellerSellers";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerSellersId } from "../../../../providers/getShoppingMallSellerSellersId";
import { putShoppingMallSellerSellersId } from "../../../../providers/putShoppingMallSellerSellersId";

import { IPageIShoppingMallSeller } from "../../../../api/structures/IPageIShoppingMallSeller";
import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";

@Controller("/shoppingMall/seller/sellers")
export class ShoppingmallSellerSellersController {
  /**
   * Search and retrieve a filtered, paginated list of sellers.
   *
   * Retrieve a filtered and paginated list of registered sellers on the
   * shopping mall platform. This operation allows clients to submit search
   * parameters such as email, store name, creation date, and other criteria
   * using the request body.
   *
   * The response includes a paginated list of seller summaries that match the
   * specified filters, supporting efficient browsing and management of
   * sellers.
   *
   * Authentication and authorization are required, supporting access to admin
   * and seller user actors.
   *
   * This operation maps directly to the shopping_mall_sellers database table,
   * utilizing indexed fields prominently for efficient search.
   *
   * Pagination helps optimize data transfer and user experience for large
   * datasets.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for seller filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async indexSellers(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSeller.IRequest,
  ): Promise<IPageIShoppingMallSeller.ISummary> {
    try {
      return await patchShoppingMallSellerSellers({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed seller account information by seller ID.
   *
   * Retrieve the full profile data for a seller by their unique
   * system-generated UUID identifier. This includes critical contact and
   * authentication information excluding private or sensitive tokens.
   *
   * Only authorized users with seller or admin roles may access this endpoint
   * to protect personal and business data.
   *
   * The response includes all seller fields defined in the
   * shopping_mall_sellers Prisma table except sensitive fields like
   * `password_hash`.
   *
   * This is a read-only operation without modifying database state.
   *
   * Errors will include 404 for seller not found and 403 for unauthorized
   * access.
   *
   * The GET /sellers/{id} endpoint serves as the primary means to fetch
   * individual seller account details and is often used within seller
   * management dashboards and admin control panels.
   *
   * @param connection
   * @param id Unique identifier of the seller (UUID)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSeller.ISummary> {
    try {
      return await getShoppingMallSellerSellersId({
        seller,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing seller account's profile information by seller ID.
   *
   * Update the profile information of a seller, including fields like email,
   * store name, and password hash. The update operation requires the seller's
   * unique UUID and the updated data in the request body.
   *
   * Authorization is limited to the seller themselves or admin users.
   * Validation applies to all fields including ensuring email uniqueness and
   * proper field formats.
   *
   * On success, the updated seller record reflecting the changes is returned.
   * Failure cases include not found or unauthorized attempts.
   *
   * PUT /sellers/{id} is essential for seller self-service profile management
   * and admin user operations.
   *
   * @param connection
   * @param id Unique identifier of the seller (UUID)
   * @param body Updated profile information for the seller account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSeller.IUpdate,
  ): Promise<IShoppingMallSeller> {
    try {
      return await putShoppingMallSellerSellersId({
        seller,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
