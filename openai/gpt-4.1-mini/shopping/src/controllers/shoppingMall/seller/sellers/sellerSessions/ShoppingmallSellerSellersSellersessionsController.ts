import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallSellerSellersSellerIdSellerSessionsSellerSessionId } from "../../../../../providers/getShoppingMallSellerSellersSellerIdSellerSessionsSellerSessionId";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerSellersSellerIdSellerSessionsSellerSessionId } from "../../../../../providers/putShoppingMallSellerSellersSellerIdSellerSessionsSellerSessionId";
import { deleteShoppingMallSellerSellersSellerIdSellerSessionsSellerSessionId } from "../../../../../providers/deleteShoppingMallSellerSellersSellerIdSellerSessionsSellerSessionId";
import { postShoppingMallSellerSellersSellerIdSellerSessions } from "../../../../../providers/postShoppingMallSellerSellersSellerIdSellerSessions";

import { IShoppingMallSellerSession } from "../../../../../api/structures/IShoppingMallSellerSession";

@Controller("/shoppingMall/seller/sellers/:sellerId/sellerSessions")
export class ShoppingmallSellerSellersSellersessionsController {
  /**
   * Get details of a specific seller session from the shopping mall system.
   *
   * Retrieve the details of a seller's session by providing the seller
   * identifier and the session identifier.
   *
   * This endpoint allows authorized users to view specific session information,
   * including connection IP, referrer URLs, and active timestamps.
   *
   * Security is managed by restricting access to authenticated users authorized
   * to manage or audit seller sessions.
   *
   * The operation references the shopping_mall_seller_sessions Prisma schema
   * which links sessions to seller users. It provides a comprehensive
   * single-record retrieval useful for session monitoring or troubleshooting.
   *
   * Related operations include listing sessions for a seller and creating new
   * sessions.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller user
   * @param sellerSessionId Unique identifier of the seller's session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerSessionId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("sellerSessionId")
    sellerSessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerSession> {
    try {
      return await getShoppingMallSellerSellersSellerIdSellerSessionsSellerSessionId(
        {
          seller,
          sellerId,
          sellerSessionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a seller's session information.
   *
   * Update an existing seller session associated with a specific seller. This
   * operation ensures sellers can maintain control over their active sessions,
   * updating session metadata such as expiration time and status.
   *
   * The operation strictly requires authentication and authorization of the
   * seller who owns the session. Data integrity is preserved by validating that
   * the seller session referenced belongs to the specified seller.
   *
   * Security considerations include protection against unauthorized session
   * modifications. The system enforces ownership verification so that no seller
   * can update sessions belonging to others.
   *
   * This operation relates to the seller session data structure defined in the
   * shopping mall Prisma schema and interacts with seller entity records.
   *
   * Related operations include creating a session (handled separately),
   * deleting a session (this specification), and retrieving session details
   * (not shown here).
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller
   * @param sellerSessionId Unique identifier of the target seller session
   * @param body Seller session update data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sellerSessionId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("sellerSessionId")
    sellerSessionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSellerSession.IUpdate,
  ): Promise<IShoppingMallSellerSession> {
    try {
      return await putShoppingMallSellerSellersSellerIdSellerSessionsSellerSessionId(
        {
          seller,
          sellerId,
          sellerSessionId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a seller's session.
   *
   * Delete a specific seller session belonging to a seller. This is a hard
   * delete operation that removes the session from the database.
   *
   * Only authenticated sellers authorized to access the session can perform
   * this action. The operation ensures ownership to prevent unauthorized
   * deletions.
   *
   * After deletion, the session is invalidated and cannot be used for further
   * authentication.
   *
   * This targets the seller session data model in the shopping mall Prisma
   * schema, integral to session lifecycle management.
   *
   * Related operations include updating a session and creating new sessions.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller
   * @param sellerSessionId Unique identifier of the target seller session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sellerSessionId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("sellerSessionId")
    sellerSessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerSellersSellerIdSellerSessionsSellerSessionId(
        {
          seller,
          sellerId,
          sellerSessionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new session for a seller user.
   *
   * Create a new session record for a seller user in the shopping mall system.
   *
   * This endpoint supports recording session connection context like IP
   * address, referrer, and timestamps.
   *
   * Security is enforced to allow only authenticated users with permissions to
   * create sessions for their seller accounts.
   *
   * The request body follows the IShoppingMallSellerSession.ICreate DTO schema
   * ensuring all required session fields except seller identifier are
   * provided.
   *
   * Related operations include retrieving session details and listing sessions
   * per seller.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller user
   * @param body Data for creating a new seller session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSellerSession.ICreate,
  ): Promise<IShoppingMallSellerSession> {
    try {
      return await postShoppingMallSellerSellersSellerIdSellerSessions({
        seller,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
