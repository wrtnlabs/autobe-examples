import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerShoppingMallArticleCategories } from "../../../../providers/postShoppingMallSellerShoppingMallArticleCategories";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerShoppingMallArticleCategoriesShoppingMallArticleCategoryId } from "../../../../providers/putShoppingMallSellerShoppingMallArticleCategoriesShoppingMallArticleCategoryId";

import { IShoppingMallArticleCategory } from "../../../../api/structures/IShoppingMallArticleCategory";

@Controller("/shoppingMall/seller/shoppingMallArticleCategories")
export class ShoppingmallSellerShoppingmallarticlecategoriesController {
  /**
   * Create a new shopping mall article category.
   *
   * Creates a new article category within the shopping mall platform to enable
   * hierarchical organization of articles.
   *
   * Only authorized actors such as customers, sellers, or admins can create
   * article categories.
   *
   * Each category must have a unique name within the platform. Optionally, a
   * parent category can be specified to establish hierarchy.
   *
   * The system automatically manages timestamps for creation, update, and
   * optional soft deletion.
   *
   * Related operations: Update category (PUT
   * /shoppingMallArticleCategories/{shoppingMallArticleCategoryId}).
   *
   * @param connection
   * @param body The data required to create a shopping mall article category.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallArticleCategory.ICreate,
  ): Promise<IShoppingMallArticleCategory> {
    try {
      return await postShoppingMallSellerShoppingMallArticleCategories({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shopping mall article category.
   *
   * Updates an existing article category identified by its unique identifier
   * within the shopping mall platform.
   *
   * Authorized actors (customer, seller, admin) can modify the category's name,
   * description, and parent category to adjust its hierarchical
   * classification.
   *
   * The system manages update timestamps automatically and enforces uniqueness
   * on category names.
   *
   * Related operations: Create category (POST /shoppingMallArticleCategories).
   *
   * @param connection
   * @param shoppingMallArticleCategoryId Unique identifier of the shopping mall
   *   article category to update (UUID format).
   * @param body Updated fields for the shopping mall article category.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shoppingMallArticleCategoryId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shoppingMallArticleCategoryId")
    shoppingMallArticleCategoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallArticleCategory.IUpdate,
  ): Promise<IShoppingMallArticleCategory> {
    try {
      return await putShoppingMallSellerShoppingMallArticleCategoriesShoppingMallArticleCategoryId(
        {
          seller,
          shoppingMallArticleCategoryId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
