import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallInventoryHistory } from "../../../../../api/structures/IShoppingMallInventoryHistory";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerInventorySummary } from "../../../../../providers/getShoppingMallSellerInventorySummary";

@Controller("/shoppingMall/seller/inventory/summary")
export class ShoppingmallSellerInventorySummaryController {
  /**
   * Retrieve a comprehensive summary of inventory status for all product variants in the shopping mall platform.
   *
   * This operation aggregates stock levels, variant counts, and other key inventory metrics to assist sellers and administrators in monitoring overall stock health.
   *
   * Authorization is required for sellers and administrators to access inventory summaries.
   *
   * The underlying data is derived from the `shopping_mall_inventory_histories` table for stock movement records and the `shopping_mall_product_variants` table for current stock per variant.
   *
   * No parameters or request body are required as this is a read-only GET operation.
   *
   * Related operations include per-variant inventory history retrieval and detailed product stock inquiries.
   *
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Execute aggregated queries over shopping_mall_product_variants and shopping_mall_inventory_histories to calculate total stock, total variants, total products, and stock movement statistics.
   * Ensure query performance with proper indexing, use caching if suitable.
   * Implement authorization guards for seller and administrator roles.
   * Return data as IShoppingMallInventorySummary DTO for uniform structure.
   * Handle edge cases such as no products or no inventory gracefully.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async summaryInventory(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IShoppingMallInventoryHistory> {
    try {
      return await getShoppingMallSellerInventorySummary({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
