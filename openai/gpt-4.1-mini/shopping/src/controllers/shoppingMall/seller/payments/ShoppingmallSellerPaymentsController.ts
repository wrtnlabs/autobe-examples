import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerPayments } from "../../../../providers/postShoppingMallSellerPayments";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerPaymentsPaymentId } from "../../../../providers/putShoppingMallSellerPaymentsPaymentId";

import { IShoppingMallPayment } from "../../../../api/structures/IShoppingMallPayment";

@Controller("/shoppingMall/seller/payments")
export class ShoppingmallSellerPaymentsController {
  /**
   * Create a new payment in the shopping mall payment system.
   *
   * This API enables authorized users such as admins or sellers to record a
   * payment transaction associated with a specific order. The payment details
   * include the payment method (e.g., credit card, PayPal), status (e.g.,
   * completed, pending), amount paid, external transaction identifier, and the
   * payment date.
   *
   * Security considerations include validation to ensure the referenced order
   * exists and is active. The external transaction ID must be unique to avoid
   * duplication errors.
   *
   * Timestamps for creation and last update are automatically managed by the
   * system. Soft deletion is supported via a nullable deleted_at timestamp to
   * allow recovery.
   *
   * This operation uses the "shopping_mall_payments" table from the Prisma
   * schema, leveraging all defined fields for data integrity and business
   * logic.
   *
   * Related operations include updating payments via PUT /payments/{paymentId}.
   *
   * @param connection
   * @param body Payment creation payload, containing order linkage and payment
   *   details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallPayment.ICreate,
  ): Promise<IShoppingMallPayment> {
    try {
      return await postShoppingMallSellerPayments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update payment details for an existing payment record in the shopping mall
   * payment system.
   *
   * Authorized users such as administrators and sellers can update payment
   * method, status, amount, external transaction ID, and payment date for a
   * specified payment record identified by its unique payment ID.
   *
   * Concurrency and uniqueness checks are performed to ensure data consistency.
   * The related order linkage cannot be changed once set.
   *
   * Timestamps for last update are maintained automatically. This operation
   * supports soft deletion monitoring via the deleted_at field but does not
   * perform deletion itself.
   *
   * It operates on the "shopping_mall_payments" table as defined in the Prisma
   * schema, ensuring all business and validation rules are reflected.
   *
   * Related operations include creating payments via POST /payments.
   *
   * @param connection
   * @param paymentId Unique identifier of the target payment record
   * @param body Payment update payload containing modifiable payment fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":paymentId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("paymentId")
    paymentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallPayment.IUpdate,
  ): Promise<IShoppingMallPayment> {
    try {
      return await putShoppingMallSellerPaymentsPaymentId({
        seller,
        paymentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
