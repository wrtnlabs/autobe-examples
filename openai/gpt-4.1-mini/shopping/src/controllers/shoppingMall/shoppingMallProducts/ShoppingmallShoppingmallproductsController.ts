import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallShoppingMallProducts } from "../../../providers/patchShoppingMallShoppingMallProducts";
import { getShoppingMallShoppingMallProductsProductCode } from "../../../providers/getShoppingMallShoppingMallProductsProductCode";

import { IPageIShoppingMallProduct } from "../../../api/structures/IPageIShoppingMallProduct";
import { IShoppingMallProduct } from "../../../api/structures/IShoppingMallProduct";

@Controller("/shoppingMall/shoppingMallProducts")
export class ShoppingmallShoppingmallproductsController {
  /**
   * Retrieve filtered, paginated list of shopping mall products.
   *
   * Retrieve a filtered and paginated list of shopping mall products.
   *
   * This operation enables clients to search and browse products using multiple
   * filtering criteria such as category, brand, code, or text search on titles
   * and descriptions.
   *
   * Pagination parameters allow clients to control the size and number of
   * result pages for efficient data consumption.
   *
   * Security controls restrict access to authenticated users or authorized
   * roles as appropriate.
   *
   * The data is sourced from the shopping_mall_products Prisma table, including
   * support for soft deletion via the deleted_at field. Related operations
   * include fetching individual products and managing product creations and
   * updates.
   *
   * @param connection
   * @param body Filtering criteria and pagination parameters for product search
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallProduct.IRequest,
  ): Promise<IPageIShoppingMallProduct.ISummary> {
    try {
      return await patchShoppingMallShoppingMallProducts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a shopping mall product by product code.
   *
   * Fetch detailed product information by providing the unique productCode.
   *
   * This operation retrieves a complete product entity including description,
   * brand, timestamps for creation and updates, and soft deletion status if
   * applicable.
   *
   * It is a publicly accessible endpoint and does not require authentication.
   *
   * The productCode is the primary business identifier unique across all
   * products.
   *
   * The response is structured based on the shopping_mall_products entity as
   * defined by the Prisma schema.
   *
   * @param connection
   * @param productCode Unique product code for business identification (global
   *   scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productCode")
  public async at(
    @TypedParam("productCode")
    productCode: string,
  ): Promise<IShoppingMallProduct> {
    try {
      return await getShoppingMallShoppingMallProductsProductCode({
        productCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
