import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallMvShoppingMallDailySales } from "../../../providers/patchShoppingMallMvShoppingMallDailySales";
import { getShoppingMallMvShoppingMallDailySalesId } from "../../../providers/getShoppingMallMvShoppingMallDailySalesId";

import { IPageIShoppingMallMvShoppingMallDailySale } from "../../../api/structures/IPageIShoppingMallMvShoppingMallDailySale";
import { IShoppingMallMvShoppingMallDailySale } from "../../../api/structures/IShoppingMallMvShoppingMallDailySale";

@Controller("/shoppingMall/mvShoppingMallDailySales")
export class ShoppingmallMvshoppingmalldailysalesController {
  /**
   * Retrieve a filtered and paginated list of daily sales summary records from
   * the mv_shopping_mall_daily_sales materialized view.
   *
   * This operation supports advanced filtering by sales date and other
   * criteria, sorting, and pagination to efficiently explore daily sales
   * trends.
   *
   * Security considerations: This endpoint is public and does not require
   * authentication as the data is aggregated and non-sensitive.
   *
   * The materialized view aggregates transactional sales data into daily
   * snapshots representing total number of orders, total sales amount, and
   * total items sold on each day.
   *
   * This resource is read-only; clients cannot modify the data.
   *
   * Related operations: Retrieve individual day summary with GET
   * /mvShoppingMallDailySales/{id}.
   *
   * @param connection
   * @param body Search and pagination parameters for daily sales summaries
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallMvShoppingMallDailySale.IRequest,
  ): Promise<IPageIShoppingMallMvShoppingMallDailySale.ISummary> {
    try {
      return await patchShoppingMallMvShoppingMallDailySales({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific daily sales summary by
   * unique identifier.
   *
   * The sales summary contains total orders, total sales amount, and total
   * items sold for the given sales date.
   *
   * Security: This endpoint is public and read-only since the data is
   * aggregated and non-sensitive.
   *
   * This operation involves no data modification and serves analytics and
   * monitoring use cases.
   *
   * Related operation: List summary with PATCH /mvShoppingMallDailySales.
   *
   * @param connection
   * @param id Unique identifier (UUID) of the daily sales summary record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallMvShoppingMallDailySale> {
    try {
      return await getShoppingMallMvShoppingMallDailySalesId({
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
