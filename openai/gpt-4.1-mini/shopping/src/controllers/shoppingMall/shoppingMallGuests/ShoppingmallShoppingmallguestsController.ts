import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallShoppingMallGuests } from "../../../providers/postShoppingMallShoppingMallGuests";
import { patchShoppingMallShoppingMallGuests } from "../../../providers/patchShoppingMallShoppingMallGuests";
import { getShoppingMallShoppingMallGuestsShoppingMallGuestId } from "../../../providers/getShoppingMallShoppingMallGuestsShoppingMallGuestId";

import { IShoppingMallGuest } from "../../../api/structures/IShoppingMallGuest";
import { IPageIShoppingMallGuest } from "../../../api/structures/IPageIShoppingMallGuest";

@Controller("/shoppingMall/shoppingMallGuests")
export class ShoppingmallShoppingmallguestsController {
  /**
   * Create a new shopping mall guest user record.
   *
   * This operation allows the system to register a new guest user for the
   * shopping mall, who can browse the product catalog without authentication.
   *
   * The operation accepts a creation payload defining necessary guest session
   * data as per the shopping_mall_guests Prisma schema, excluding server-side
   * managed fields such as timestamps and IDs which are auto-generated.
   *
   * Upon successful creation, the server returns the full guest record,
   * including assigned unique identifier and timestamps to support session
   * management and analytics.
   *
   * No authentication is required for this operation as it supports guest users
   * who are anonymous visitors.
   *
   * This operation corresponds to the shopping_mall_guests table in the Prisma
   * schema, reflecting all fields relevant for guest session management.
   *
   * @param connection
   * @param body Data required to create a new shopping mall guest user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: IShoppingMallGuest.ICreate,
  ): Promise<IShoppingMallGuest> {
    try {
      return await postShoppingMallShoppingMallGuests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and list paginated shopping mall guest users.
   *
   * Retrieve a paginated and optionally filtered list of guest users visiting
   * the shopping mall platform.
   *
   * This operation provides analytic access to guest data, capturing
   * non-authenticated session records from the shopping_mall_guests table.
   *
   * Security: Guest data is considered public and does not include sensitive
   * personal information, enabling unauthenticated endpoints.
   *
   * Query parameters include filtering options such as date ranges and
   * pagination controls to refine guest data retrieval.
   *
   * The response consists of summarized guest records, facilitating effective
   * monitoring and analysis of guest activity.
   *
   * Related operations include guest session tracking and user analytics.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   shopping mall guests
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallGuest.IRequest,
  ): Promise<IPageIShoppingMallGuest.ISummary> {
    try {
      return await patchShoppingMallShoppingMallGuests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific shopping mall guest user.
   *
   * This operation retrieves detailed information about a specific shopping
   * mall guest user who is browsing the e-commerce mall without
   * authentication.
   *
   * Guest users do not have personal accounts or login credentials; instead,
   * this operation uses a unique guest session identifier to fetch session and
   * browsing data. The data includes creation and update timestamps, supporting
   * client-side session display and analytic tracking.
   *
   * Security considerations include the public nature of guest browsing; no
   * authentication is required to access this data, but only valid guest IDs
   * are serviced. Improper or malformed IDs result in standard HTTP 404 or 400
   * errors.
   *
   * This operation corresponds directly to the shopping_mall_guests table in
   * the Prisma schema, respecting its structure and constraints.
   *
   * @param connection
   * @param shoppingMallGuestId Unique identifier of the target shopping mall
   *   guest user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shoppingMallGuestId")
  public async at(
    @TypedParam("shoppingMallGuestId")
    shoppingMallGuestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallGuest> {
    try {
      return await getShoppingMallShoppingMallGuestsShoppingMallGuestId({
        shoppingMallGuestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
