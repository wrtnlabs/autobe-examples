import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallShoppingMallProductCategories } from "../../../providers/patchShoppingMallShoppingMallProductCategories";
import { getShoppingMallShoppingMallProductCategoriesCategoryCode } from "../../../providers/getShoppingMallShoppingMallProductCategoriesCategoryCode";

import { IPageIShoppingMallProductCategory } from "../../../api/structures/IPageIShoppingMallProductCategory";
import { IShoppingMallProductCategory } from "../../../api/structures/IShoppingMallProductCategory";

@Controller("/shoppingMall/shoppingMallProductCategories")
export class ShoppingmallShoppingmallproductcategoriesController {
  /**
   * Search and retrieve a filtered, paginated list of shopping mall product
   * categories.
   *
   * Retrieve a filtered and paginated list of shopping mall product categories.
   *
   * This operation provides advanced search capabilities for product categories
   * allowing filtering by name, parent category, creation date, and other
   * relevant properties. Pagination and sorting options enable efficient
   * navigation through large numbers of categories.
   *
   * Security considerations include proper authorization for accessing category
   * details and ensuring sensitive configuration fields are not exposed to
   * unauthorized users.
   *
   * The underlying data is based on the shopping_mall_product_categories table
   * defined in the Prisma schema, including hierarchical relationships to
   * support parent-child category structures and attributes that describe
   * category metadata.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for product
   *   categories filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallProductCategory.IRequest,
  ): Promise<IPageIShoppingMallProductCategory.ISummary> {
    try {
      return await patchShoppingMallShoppingMallProductCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve shopping mall product category by unique code.
   *
   * Retrieve detailed information about a specific shopping mall product
   * category identified by its unique code.
   *
   * This operation fetches detailed metadata and hierarchical relationships for
   * the target category, enabling clients to display comprehensive category
   * details.
   *
   * The categoryCode URL parameter identifies the category by its unique
   * business code, ensuring precise lookup.
   *
   * Security considerations require authorization checks to prevent
   * unauthorized data access.
   *
   * The operation relates directly to the shopping_mall_product_categories
   * table in the Prisma schema.
   *
   * @param connection
   * @param categoryCode Unique business identifier code of the target product
   *   category (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryCode")
  public async at(
    @TypedParam("categoryCode")
    categoryCode: string,
  ): Promise<IShoppingMallProductCategory> {
    try {
      return await getShoppingMallShoppingMallProductCategoriesCategoryCode({
        categoryCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
