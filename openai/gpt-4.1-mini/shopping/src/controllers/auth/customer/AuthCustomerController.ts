import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthCustomerJoin } from "../../../providers/postAuthCustomerJoin";
import { postAuthCustomerLogin } from "../../../providers/postAuthCustomerLogin";
import { postAuthCustomerRefresh } from "../../../providers/postAuthCustomerRefresh";
import { CustomerAuth } from "../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../decorators/payload/CustomerPayload";

import { IShoppingMallCustomer } from "../../../api/structures/IShoppingMallCustomer";

@Controller("/auth/customer")
export class AuthCustomerController {
  /**
   * Register new customer account and issue JWT token for authentication.
   *
   * This API operation enables new customers to register by providing their
   * email and password. It corresponds to the shopping_mall_customers table's
   * email and password_hash fields which store the secure login credentials.
   * Upon successful registration, an authorization token is issued to the
   * customer to enable authenticated interactions within the shopping mall
   * platform.
   *
   * The customer's full name can also be registered. The created_at and
   * updated_at fields are set automatically to track record timestamps. If a
   * customer account is soft deleted (deleted_at not null), it will not allow
   * login or interactions.
   *
   * This operation requires no authentication and is public, allowing new users
   * to join the service by creating an account. Password hashing and validation
   * occur internally.
   *
   * The response returns an IShoppingMallCustomer.IAuthorized type containing
   * the authorization tokens and basic user info.
   *
   * Related operations include login, refresh, and password management
   * endpoints that work together to handle authentication life cycle.
   *
   * @param connection
   * @param body Request body for customer registration, including email,
   *   password, and name.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.ICreate,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postAuthCustomerJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate customer credentials and issue JWT token.
   *
   * This API operation allows registered customers to log in by providing their
   * email and password. It authenticates against the shopping_mall_customers
   * table's email and password_hash fields.
   *
   * Successful authentication yields a JWT token for session management. Login
   * failures due to incorrect credentials are handled with proper error
   * messages.
   *
   * This is a public endpoint and does not require an existing token. It is
   * part of the overall authentication flow along with join and refresh
   * operations.
   *
   * Clients should use the issued token for subsequent authenticated requests.
   *
   * Related endpoints include join for registration and refresh for token
   * renewal.
   *
   * @param connection
   * @param body Request body for customer login with email and password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.ILogin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postAuthCustomerLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT token for authenticated customer.
   *
   * This API operation allows customers to refresh their JWT tokens using a
   * valid refresh token. It interacts with the shopping_mall_customers table to
   * validate the existing refresh token and issue a new one.
   *
   * Refresh tokens extend the validity of the user's authentication session
   * without forcing a full login.
   *
   * This endpoint requires authentication with a valid refresh token and
   * returns a new authorized token set.
   *
   * It supports session continuity and security management.
   *
   * Related operations are join for initial registration and login for
   * credential authentication.
   *
   * @param connection
   * @param body Request body containing refresh token for session continuation.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCustomer.IRefresh,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postAuthCustomerRefresh({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
