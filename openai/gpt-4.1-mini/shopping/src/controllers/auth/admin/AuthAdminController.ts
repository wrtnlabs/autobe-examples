import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { AdminAuth } from "../../../decorators/AdminAuth";
import { AdminPayload } from "../../../decorators/payload/AdminPayload";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { IShoppingMallAdmin } from "../../../api/structures/IShoppingMallAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * This API operation handles administrator account registration for the
   * shopping mall platform. It uses the shopping_mall_admins table wherein each
   * admin has a unique email used as their login ID and a hashed password
   * stored securely. The endpoint registers new admins, stores their
   * credentials securely, and issues JWT token pairs for immediate authorized
   * access. Security measures include validation of input, password hashing,
   * and prevention of duplicate registrations via unique email enforcement.
   * This operation is publicly accessible as it is the entry point for new
   * administrators on the platform. Related operations include login and
   * refresh token renewal.
   *
   * @param connection
   * @param body Administrator registration input data including email and
   *   plaintext password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAdmin.IJoin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API operation enables administrators to login to the shopping mall
   * platform. It verifies the admin's email and password against hashed
   * credentials in the shopping_mall_admins table. Upon successful
   * authentication, a JWT authorized token pair is issued for platform access.
   * Security best practices including rate limiting, account lockout on
   * repeated failed attempts, and secure token handling are implemented. The
   * endpoint is public for credential submission. Related operations include
   * registration (join) and token refresh.
   *
   * @param connection
   * @param body Administrator login credentials including email and password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAdmin.ILogin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API operation refreshes JWT tokens for authenticated administrators on
   * the shopping mall platform. Using a valid refresh token, it issues a new
   * set of access and refresh tokens for continued secure access. The operation
   * mandates valid token validation routines and is accessible only to
   * authenticated admin actors. Related operations include login and join for
   * full authentication lifecycle management.
   *
   * @param connection
   * @param body Refresh token submission for JWT renewal.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAdmin.IRefresh,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
