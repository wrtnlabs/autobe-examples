import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthSellerJoin } from "../../../providers/postAuthSellerJoin";
import { SellerAuth } from "../../../decorators/SellerAuth";
import { SellerPayload } from "../../../decorators/payload/SellerPayload";
import { postAuthSellerLogin } from "../../../providers/postAuthSellerLogin";
import { postAuthSellerRefresh } from "../../../providers/postAuthSellerRefresh";

import { IShoppingMallSeller } from "../../../api/structures/IShoppingMallSeller";

@Controller("/auth/seller")
export class AuthSellerController {
  /**
   * Create a new seller account and issue authorization tokens.
   *
   * This API endpoint allows new sellers to register an account on the
   * platform. It requires the client to provide necessary signup details,
   * notably a unique email and a password that will be hashed and stored in the
   * 'password_hash' field of the 'shopping_mall_sellers' table. Upon successful
   * registration, the operation issues JWT authorization tokens conforming to
   * 'IShoppingMallSeller.IAuthorized', enabling authenticated sessions.
   *
   * Security measures ensure that email uniqueness is validated before account
   * creation and password hashing follows best practices for credential
   * protection. This endpoint does not require prior authentication, making it
   * publicly accessible.
   *
   * The seller account status fields such as 'status' and 'business_status' are
   * initialized according to system defaults specified in the database schema
   * comments, ensuring consistent lifecycle management.
   *
   * JWT issuance and securing token payload rely on integrating with the
   * broader authorization workflow, linking seamlessly with subsequent login
   * and refresh operations.
   *
   * For comprehensive user lifecycle management, this operation is complemented
   * by login and access token refresh endpoints under the same '/auth/seller'
   * path prefix.
   *
   * @param connection
   * @param body Payload for creating a seller account.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSeller.ICreate,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerJoin({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate seller credentials and provide authorization tokens.
   *
   * This API endpoint allows seller users to log in by verifying their
   * credentials against stored data. It requires the email and password in the
   * request body, matching against 'email' and 'password_hash' fields in the
   * 'shopping_mall_sellers' table.
   *
   * Successful authentication returns JWT tokens that authorize access to
   * protected endpoints, carrying claims relevant to seller identity and
   * authorization scope.
   *
   * Security measures include password hashing verification and account status
   * checks via 'status' fields to prevent suspended or deactivated users from
   * logging in.
   *
   * This endpoint is publicly accessible allowing any existing seller to
   * authenticate and receive tokens for session management.
   *
   * It works in conjunction with the join and refresh endpoints to fully
   * support the seller authentication lifecycle.
   *
   * @param connection
   * @param body Credentials required for seller login.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSeller.ILogin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerLogin({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT tokens for authenticated seller users.
   *
   * This API endpoint enables seller users to refresh their JWT tokens by
   * presenting a valid refresh token. Upon validation, the endpoint issues new
   * access tokens along with refresh tokens as per the
   * 'IShoppingMallSeller.IAuthorized' schema.
   *
   * The refresh operation safeguards session continuity without forcing the
   * seller to re-authenticate frequently.
   *
   * Security checks validate the refresh token's authenticity and expiration,
   * ensuring tokens cannot be fraudulently reused.
   *
   * This endpoint is restricted to authenticated users holding valid refresh
   * tokens and is a critical component of the seller authentication lifecycle.
   *
   * It complements the join and login endpoints to form a complete
   * authentication and session management suite for sellers.
   *
   * @param connection
   * @param body Refresh token information.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSeller.IRefresh,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerRefresh({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
