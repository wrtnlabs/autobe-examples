import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthSellerJoin } from "../../../providers/postAuthSellerJoin";
import { SellerAuth } from "../../../decorators/SellerAuth";
import { SellerPayload } from "../../../decorators/payload/SellerPayload";
import { postAuthSellerLogin } from "../../../providers/postAuthSellerLogin";
import { postAuthSellerRefresh } from "../../../providers/postAuthSellerRefresh";

import { IShoppingMallSeller } from "../../../api/structures/IShoppingMallSeller";

@Controller("/auth/seller")
export class AuthSellerController {
  /**
   * Registers a new seller account in the shopping mall system using the
   * 'shopping_mall_sellers' table.
   *
   * This join operation allows a prospective seller to create an account by
   * providing necessary information such as email, password, and store name.
   * The operation ensures the uniqueness of the email address per seller
   * account by checking the 'email' field in the 'shopping_mall_sellers' table.
   * On success, a new seller record is created with hashed password stored in
   * 'password_hash'. The system emits JWT tokens for authentication and
   * authorization. This endpoint provides a public entry point for user
   * onboarding into the seller actor category. Security considerations include
   * enforcing strong password hashing and validation before user creation.
   * Related operations include login and token refresh for continuous
   * authentication management.
   *
   * @param connection
   * @param body Request body for creating a new seller account with
   *   registration information.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSeller.ICreate,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerJoin({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates a seller and issues JWT tokens for authorization using the
   * 'shopping_mall_sellers' table.
   *
   * Sellers provide their login email and password to authenticate and gain
   * access to protected resources. The login operation verifies that the
   * 'email' exists and the password matches the securely stored
   * 'password_hash'. On successful authentication, JWT tokens are issued to
   * maintain session state. Security policies such as account lockout on
   * multiple failed attempts are enforced via business logic integrating with
   * the 'shopping_mall_sellers' entity. Related to seller registration and
   * token refresh endpoints.
   *
   * @param connection
   * @param body Request body containing seller login credentials.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSeller.ILogin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerLogin({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes JWT access token for a seller using a valid refresh token linked
   * to the 'shopping_mall_sellers' table.
   *
   * A seller uses a valid refresh token to obtain a new JWT access token,
   * extending their authenticated session without re-authentication. This
   * operation validates the refresh token and issues fresh tokens upon success.
   * This improves security by limiting exposure of long-lived tokens. The
   * operation interacts with the 'shopping_mall_sellers' entity to confirm
   * valid seller sessions. This endpoint complements the join and login
   * endpoints in the authentication lifecycle.
   *
   * @param connection
   * @param body Request body containing the refresh token for token renewal.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSeller.IRefresh,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerRefresh({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
