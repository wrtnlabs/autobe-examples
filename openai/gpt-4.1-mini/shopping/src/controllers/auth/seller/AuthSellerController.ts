import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthSellerJoin } from "../../../providers/postAuthSellerJoin";
import { SellerAuth } from "../../../decorators/SellerAuth";
import { SellerPayload } from "../../../decorators/payload/SellerPayload";
import { postAuthSellerLogin } from "../../../providers/postAuthSellerLogin";
import { postAuthSellerRefresh } from "../../../providers/postAuthSellerRefresh";

import { IShoppingMallSeller } from "../../../api/structures/IShoppingMallSeller";

@Controller("/auth/seller")
export class AuthSellerController {
  /**
   * This operation registers a new seller user, creating a persistent account
   * in the system. It utilizes the shopping_mall_sellers table fields to
   * validate registration inputs and ensure data integrity. Upon successful
   * registration, the system issues JWT tokens for authenticated interactions.
   * Security validation, uniqueness checks, and password policies are enforced
   * as per the schema. This endpoint is public and requires no prior
   * authentication.
   *
   * The operation interfaces directly with the shopping_mall_sellers schema,
   * ensuring that all fields needed to create a new seller record exist and
   * meet validation rules.
   *
   * This join endpoint is foundational for onboarding sellers to the platform.
   *
   * Security best practices are applied, including input sanitization and
   * password hashing.
   *
   * This operation relates to login and refresh endpoints that complete the
   * authentication workflow.
   *
   * @param connection
   * @param body Request body to create a new seller account.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSeller.ICreate,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerJoin({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation authenticates a seller user by verifying login credentials
   * against the shopping_mall_sellers schema fields. It returns authorized JWT
   * tokens upon success, enabling secure access to protected resources.
   * Security measures include rate limiting, credential hashing verification,
   * and token expiration control.
   *
   * The login endpoint is part of the core seller authentication workflow.
   *
   * It complements the join and refresh endpoints in the authentication
   * lifecycle.
   *
   * The Prisma schema fields such as email and password hash are directly
   * involved in the authentication validation.
   *
   * This endpoint operates publicly without requiring prior authentication.
   *
   * @param connection
   * @param body Seller login credentials.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSeller.ILogin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerLogin({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation refreshes JWT access tokens for the seller user using a
   * valid refresh token to maintain session continuity and security. It ensures
   * refreshed tokens reflect the current seller authorization status as stored
   * in the shopping_mall_sellers schema.
   *
   * The refresh endpoint completes the authentication lifecycle alongside join
   * and login.
   *
   * Token invalidation and expiry are managed to prevent misuse.
   *
   * This endpoint requires a valid refresh token for access.
   *
   * The seller actor is authenticated before refreshing tokens.
   *
   * @param connection
   * @param body Request body containing refresh token.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSeller.IRefresh,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerRefresh({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
