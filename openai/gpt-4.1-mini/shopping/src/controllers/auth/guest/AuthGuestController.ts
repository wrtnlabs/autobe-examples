import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthGuestJoin } from "../../../providers/postAuthGuestJoin";
import { GuestAuth } from "../../../decorators/GuestAuth";
import { GuestPayload } from "../../../decorators/payload/GuestPayload";
import { postAuthGuestRefresh } from "../../../providers/postAuthGuestRefresh";

import { IShoppingMallGuest } from "../../../api/structures/IShoppingMallGuest";

@Controller("/auth/guest")
export class AuthGuestController {
  /**
   * Register a temporary guest account and issue authorization tokens.
   *
   * Enables unauthenticated users (guest) to register temporary guest accounts.
   * The operation uses the 'shopping_mall_guests' Prisma table for storing
   * guest user records with minimal required fields. Upon successful
   * registration, the system returns JWT authorization tokens for access
   * control during the guest session.
   *
   * The operation facilitates limited access to protected resources without
   * traditional login credentials, ensuring secure temporary sessions and
   * prevention of abuse via token management.
   *
   * It integrates with the refresh token operation to maintain session
   * continuity and is a critical step in the guest user authentication
   * lifecycle.
   *
   * Security policies include rate limiting and session expiration to protect
   * the platform.
   *
   * Related operations include '/auth/guest/refresh' and logout endpoints for
   * session management.
   *
   * @param connection
   * @param body Payload for guest registration; conforms to
   *   IShoppingMallGuest.IJoin schema.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IShoppingMallGuest.IJoin,
  ): Promise<IShoppingMallGuest.IAuthorized> {
    try {
      return await postAuthGuestJoin({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh temporary authorization tokens for guest users.
   *
   * Allows guest users to obtain new JWT authorization tokens by submitting
   * valid refresh tokens. Validates refresh tokens against the
   * 'shopping_mall_guest_sessions' table to ensure session validity.
   *
   * Access requires a valid refresh token assigned during registration or a
   * prior refresh.
   *
   * Security policies enforce token revocation and expiration to safeguard
   * guest sessions.
   *
   * This operation works alongside the join process to support continuous guest
   * authentication.
   *
   * It is essential for maintaining secure, persistent guest access to
   * protected resources.
   *
   * @param connection
   * @param body Payload containing a valid refresh token; conforms to
   *   IShoppingMallGuest.IRefresh schema.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IShoppingMallGuest.IRefresh,
  ): Promise<IShoppingMallGuest.IAuthorized> {
    try {
      return await postAuthGuestRefresh({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
