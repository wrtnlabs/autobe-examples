import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallSeller } from "../../../structures/IShoppingMallSeller";

/**
 * This operation registers a new seller user, creating a persistent account in
 * the system. It utilizes the shopping_mall_sellers table fields to validate
 * registration inputs and ensure data integrity. Upon successful registration,
 * the system issues JWT tokens for authenticated interactions. Security
 * validation, uniqueness checks, and password policies are enforced as per the
 * schema. This endpoint is public and requires no prior authentication.
 *
 * The operation interfaces directly with the shopping_mall_sellers schema,
 * ensuring that all fields needed to create a new seller record exist and meet
 * validation rules.
 *
 * This join endpoint is foundational for onboarding sellers to the platform.
 *
 * Security best practices are applied, including input sanitization and
 * password hashing.
 *
 * This operation relates to login and refresh endpoints that complete the
 * authentication workflow.
 *
 * @param props.connection
 * @param props.body Request body to create a new seller account.
 * @setHeader token.access Authorization
 *
 * @path /auth/seller/join
 * @accessor api.functional.auth.seller.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /** Request body to create a new seller account. */
    body: IShoppingMallSeller.ICreate;
  };
  export type Body = IShoppingMallSeller.ICreate;
  export type Response = IShoppingMallSeller.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/seller/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/seller/join";
  export const random = (): IShoppingMallSeller.IAuthorized =>
    typia.random<IShoppingMallSeller.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

