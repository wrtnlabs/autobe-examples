import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallSeller } from "../../../structures/IShoppingMallSeller";

/**
 * Create a new seller account and issue authorization tokens.
 *
 * This API endpoint allows new sellers to register an account on the platform.
 * It requires the client to provide necessary signup details, notably a unique
 * email and a password that will be hashed and stored in the 'password_hash'
 * field of the 'shopping_mall_sellers' table. Upon successful registration, the
 * operation issues JWT authorization tokens conforming to
 * 'IShoppingMallSeller.IAuthorized', enabling authenticated sessions.
 *
 * Security measures ensure that email uniqueness is validated before account
 * creation and password hashing follows best practices for credential
 * protection. This endpoint does not require prior authentication, making it
 * publicly accessible.
 *
 * The seller account status fields such as 'status' and 'business_status' are
 * initialized according to system defaults specified in the database schema
 * comments, ensuring consistent lifecycle management.
 *
 * JWT issuance and securing token payload rely on integrating with the broader
 * authorization workflow, linking seamlessly with subsequent login and refresh
 * operations.
 *
 * For comprehensive user lifecycle management, this operation is complemented
 * by login and access token refresh endpoints under the same '/auth/seller'
 * path prefix.
 *
 * @param props.connection
 * @param props.body Payload for creating a seller account.
 * @setHeader token.access Authorization
 *
 * @path /auth/seller/join
 * @accessor api.functional.auth.seller.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /** Payload for creating a seller account. */
    body: IShoppingMallSeller.ICreate;
  };
  export type Body = IShoppingMallSeller.ICreate;
  export type Response = IShoppingMallSeller.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/seller/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/seller/join";
  export const random = (): IShoppingMallSeller.IAuthorized =>
    typia.random<IShoppingMallSeller.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

