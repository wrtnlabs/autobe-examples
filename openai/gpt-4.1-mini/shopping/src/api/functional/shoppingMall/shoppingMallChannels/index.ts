  export type Props = {
    /** Search criteria and pagination parameters for shopping mall channels */
    body: IShoppingMallChannel.IRequest;
  };
  export type Body = IShoppingMallChannel.IRequest;
  export type Response = IPageIShoppingMallChannel.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/shoppingMallChannels",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/shoppingMallChannels";
  export const random = (): IPageIShoppingMallChannel.ISummary =>
    typia.random<IPageIShoppingMallChannel.ISummary>();
