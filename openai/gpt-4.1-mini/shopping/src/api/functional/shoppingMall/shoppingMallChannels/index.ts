/**
 * Search and retrieve a list of shopping mall channels.
 *
 * Retrieve a filtered and paginated list of shopping mall channels within the
 * e-commerce platform.
 *
 * This operation supports advanced search parameters such as channel names,
 * codes, statuses, and other relevant filters. Pagination and sorting by
 * different fields are also supported to facilitate efficient browsing.
 *
 * Security considerations include ensuring only authorized users can access
 * detailed channel information, while general listings are publicly
 * accessible.
 *
 * The operation integrates with the shopping_mall_channels database table,
 * reflecting all fields and relationships defined therein. It is designed for
 * use by clients needing to display or manage channel listings.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for shopping mall
 *   channels
 * @path /shoppingMall/shoppingMallChannels
 * @accessor api.functional.shoppingMall.shoppingMallChannels.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
