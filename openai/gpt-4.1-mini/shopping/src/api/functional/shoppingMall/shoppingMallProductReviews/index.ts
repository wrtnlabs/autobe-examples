/**
 * List and search shopping mall product reviews with filtering and pagination.
 *
 * Retrieve a paginated and searchable list of product reviews submitted by
 * customers.
 *
 * This operation allows filtering by review rating, moderation status, and text
 * search on review title and body fields. Pagination options enable clients to
 * specify page size and index.
 *
 * The product reviews are linked to specific products and customers, ensuring
 * authenticity and traceability. Deleted reviews are excluded by default.
 *
 * Security: Public read-only access is permitted as reviews are generally
 * public-facing content. Sensitive details such as author sessions are not
 * exposed through this API.
 *
 * Related operations include single review retrieval (`GET
 * /shoppingMallProductReviews/{shoppingMallProductReviewId}`).
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for filtering
 *   product reviews
 * @path /shoppingMall/shoppingMallProductReviews
 * @accessor api.functional.shoppingMall.shoppingMallProductReviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
