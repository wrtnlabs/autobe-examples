import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCustomer } from "../../../structures/IShoppingMallCustomer";

/**
 * Create a new shopping mall customer account.
 *
 * Create a new customer account with email and password authentication in the
 * shopping mall system.
 *
 * The operation requires specifying the customer's unique email address, hashed
 * password for security, and full name. Upon successful creation, the
 * customer's profile is available for shopping activities.
 *
 * Security: Password hashing is expected before sending this request; the API
 * stores the hashed password as is.
 *
 * The created_at and updated_at timestamps are automatically managed by the
 * system.
 *
 * Dependent operations: Updating customer info via PUT /customers/{customerId}.
 *
 * @param props.connection
 * @param props.body Customer signup data including email, hashed password, and
 *   full name
 * @path /shoppingMall/customers
 * @accessor api.functional.shoppingMall.customers.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** Customer signup data including email, hashed password, and full name */
    body: IShoppingMallCustomer.ICreate;
  };
  export type Body = IShoppingMallCustomer.ICreate;
  export type Response = IShoppingMallCustomer;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/customers",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/customers";
  export const random = (): IShoppingMallCustomer =>
    typia.random<IShoppingMallCustomer>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
