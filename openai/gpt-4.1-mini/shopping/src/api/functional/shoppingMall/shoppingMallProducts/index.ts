/**
 * Retrieve a filtered and paginated list of shopping mall products.
 *
 * This operation enables clients to search and browse products using multiple
 * filtering criteria such as category, brand, code, or text search on titles
 * and descriptions.
 *
 * Pagination parameters allow clients to control the size and number of result
 * pages for efficient data consumption.
 *
 * Security controls restrict access to authenticated users or authorized roles
 * as appropriate.
 *
 * The data is sourced from the shopping_mall_products Prisma table, including
 * support for soft deletion via the deleted_at field. Related operations
 * include fetching individual products and managing product creations and
 * updates.
 *
 * @param props.connection
 * @param props.body Filtering criteria and pagination parameters for product
 *   search
 * @path /shoppingMall/shoppingMallProducts
 * @accessor api.functional.shoppingMall.shoppingMallProducts.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Filtering criteria and pagination parameters for product search */
    body: IShoppingMallProduct.IRequest;
  };
  export type Body = IShoppingMallProduct.IRequest;
  export type Response = IPageIShoppingMallProduct.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/shoppingMallProducts",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/shoppingMallProducts";
  export const random = (): IPageIShoppingMallProduct.ISummary =>
    typia.random<IPageIShoppingMallProduct.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

