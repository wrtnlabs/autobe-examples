/**
 * Retrieve a specific guest session for a guest user.
 *
 * Retrieve detailed information about a single guest session linked to a
 * particular guest user.
 *
 * This operation fetches the session connection context including IP address,
 * referer URL, connection origin, and timestamps. The session record is
 * associated with a guest user identified by guestId.
 *
 * Security considerations: This endpoint is public-accessible without
 * authentication as guests are anonymous users with minimal privileges.
 *
 * This operational endpoint aligns with the shopping_mall_guest_sessions Prisma
 * table, providing insight into guest session activities.
 *
 * Related operations include creating a guest session (POST
 * /guests/{guestId}/guestSessions) for tracking new connections.
 *
 * @param props.connection
 * @param props.guestId Unique identifier of the target guest user
 * @param props.guestSessionId Unique identifier of the target guest session
 * @path /shoppingMall/guests/:guestId/guestSessions/:guestSessionId
 * @accessor api.functional.shoppingMall.guests.guestSessions.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target guest user */
    guestId: string & tags.Format<"uuid">;

    /** Unique identifier of the target guest session */
    guestSessionId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallGuestSession;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/guests/:guestId/guestSessions/:guestSessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/guests/${encodeURIComponent(props.guestId ?? "null")}/guestSessions/${encodeURIComponent(props.guestSessionId ?? "null")}`;
  export const random = (): IShoppingMallGuestSession =>
    typia.random<IShoppingMallGuestSession>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("guestId")(() => typia.assert(props.guestId));
      assert.param("guestSessionId")(() => typia.assert(props.guestSessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

