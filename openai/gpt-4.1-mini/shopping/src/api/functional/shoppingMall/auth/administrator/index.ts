import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallAdministrator } from "../../../../structures/IShoppingMallAdministrator";

/**
 * Allows an administrator to register a new account on the shopping mall platform. The operation receives a request conforming to IShoppingMallAdministrator.IJoin schema with email and password details. Upon success, it returns JWT authorization data via IShoppingMallAdministrator.IAuthorized schema. This endpoint is publicly accessible without prior authentication.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Administrator join request payload including email and password.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor administrator
 * @x-autobe-specification Handles administrator account creation by validating and registering new administrators using email and password, storing securely, and generating JWT authorization tokens as per schema specifications.
 * @path /shoppingMall/auth/administrator/join
 * @accessor api.functional.shoppingMall.auth.administrator.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /**
     * Administrator join request payload including email and password.
     */
    body: IShoppingMallAdministrator.IJoin;
  };
  export type Body = IShoppingMallAdministrator.IJoin;
  export type Response = IShoppingMallAdministrator.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/auth/administrator/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/auth/administrator/join";
  export const random = (): IShoppingMallAdministrator.IAuthorized =>
    typia.random<IShoppingMallAdministrator.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

