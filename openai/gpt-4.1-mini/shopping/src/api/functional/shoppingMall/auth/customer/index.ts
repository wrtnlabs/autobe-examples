/**
 * This API endpoint allows new customers to register an account in the shopping mall platform. It accepts user registration data including email and password, enforcing validation rules like unique email constraints from the database schema. Upon successful registration, the response returns authorized session information with JWT tokens enabling authenticated usage of the platform.
 *
 * From a security perspective, user credentials are validated and stored securely. No authentication is required to access this endpoint since it serves anonymous users wishing to join the platform.
 *
 * This operation is part of the overall authentication workflow, preceding login and token refresh. Client applications should first call this endpoint to create accounts before attempting logins.
 *
 * This endpoint complies with security and business requirements established for member actors in the shopping mall system.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Customer join request data containing necessary credentials for account creation.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification This operation implements customer registration (join) by accepting join credentials (such as email and password) based on schema requirements. Service layer will validate uniqueness and password strength before creating a new customer record. It uses POST method at path /auth/customer/join with request body of IShoppingMallCustomer.IJoin type. Responses return IShoppingMallCustomer.IAuthorized containing JWT tokens and session info. This is a public endpoint requiring no authentication.
 * @path /shoppingMall/auth/customer/join
 * @accessor api.functional.shoppingMall.auth.customer.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
