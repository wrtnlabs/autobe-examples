import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallFaq } from "../../../structures/IShoppingMallFaq";
import { IPageIShoppingMallFaq } from "../../../structures/IPageIShoppingMallFaq";

/**
 * Search and retrieve a paginated list of shopping mall FAQs.
 *
 * Retrieve a paginated list of frequently asked questions (FAQs) available in
 * the shopping mall platform.
 *
 * This operation allows clients to perform complex search queries filtering
 * FAQs by keywords, associated categories, and FAQ status. Pagination
 * parameters help manage large result sets and sorting options enable ordering
 * results by date, popularity, or relevance.
 *
 * Access to this operation is public and requires no authentication, enabling
 * anonymous users to browse FAQ content for self-service support.
 *
 * This operation interfaces with the shopping_mall_faqs table, returning
 * summaries of FAQ entries optimized for listing contexts.
 *
 * @param props.connection
 * @param props.body Search and pagination parameters for filtering FAQs
 * @path /shoppingMall/faqs
 * @accessor api.functional.shoppingMall.faqs.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search and pagination parameters for filtering FAQs */
    body: IShoppingMallFaq.IRequest;
  };
  export type Body = IShoppingMallFaq.IRequest;
  export type Response = IPageIShoppingMallFaq.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/faqs",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/faqs";
  export const random = (): IPageIShoppingMallFaq.ISummary =>
    typia.random<IPageIShoppingMallFaq.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Retrieve single FAQ details by ID.
 *
 * Retrieve detailed information of a specific FAQ entry by its unique
 * identifier.
 *
 * This operation provides full FAQ content including question, answer, creation
 * and modification metadata.
 *
 * It serves public read-only access allowing any user to view FAQ details
 * without authentication.
 *
 * The ID parameter is a UUID referencing the target FAQ in the database.
 *
 * @param props.connection
 * @param props.id Unique identifier of the target FAQ entry
 * @path /shoppingMall/faqs/:id
 * @accessor api.functional.shoppingMall.faqs.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target FAQ entry */
    id: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallFaq;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/faqs/:id",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/faqs/${encodeURIComponent(props.id ?? "null")}`;
  export const random = (): IShoppingMallFaq =>
    typia.random<IShoppingMallFaq>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("id")(() => typia.assert(props.id));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
