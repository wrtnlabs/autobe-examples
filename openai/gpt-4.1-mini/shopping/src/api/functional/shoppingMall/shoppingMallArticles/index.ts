import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallArticle } from "../../../structures/IShoppingMallArticle";

/**
 * Get a shopping mall article by its unique identifier.
 *
 * Retrieve detailed information about a specific shopping mall article.
 *
 * This GET operation fetches the article identified by the
 * shoppingMallArticleId parameter. It returns all relevant fields such as
 * title, content, author information, creation and update timestamps, and any
 * related metadata as defined in the shopping_mall_articles table.
 *
 * The endpoint is publicly accessible and intended for use in article display
 * views or detail pages. It ensures retrieval of consistent article data as
 * stored in the database. Errors will be returned if the ID does not correspond
 * to any existing article.
 *
 * @param props.connection
 * @param props.shoppingMallArticleId Unique identifier of the shopping mall
 *   article
 * @path /shoppingMall/shoppingMallArticles/:shoppingMallArticleId
 * @accessor api.functional.shoppingMall.shoppingMallArticles.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the shopping mall article */
    shoppingMallArticleId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallArticle;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/shoppingMallArticles/:shoppingMallArticleId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/shoppingMallArticles/${encodeURIComponent(props.shoppingMallArticleId ?? "null")}`;
  export const random = (): IShoppingMallArticle =>
    typia.random<IShoppingMallArticle>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shoppingMallArticleId")(() =>
        typia.assert(props.shoppingMallArticleId),
      );
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
