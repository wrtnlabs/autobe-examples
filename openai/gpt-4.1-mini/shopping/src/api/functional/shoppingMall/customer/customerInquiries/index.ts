/**
 * Retrieve detailed information of a specific customer inquiry.
 *
 * Retrieve detailed information about a specific customer inquiry using its
 * unique identifier.
 *
 * This endpoint allows users or authorized actors to fetch all relevant
 * information regarding a customer's inquiry including the content, status, and
 * timestamps. It ensures secure access by restricting to authenticated
 * customers.
 *
 * The API interacts directly with the shopping_mall_customer_inquiries table as
 * defined in the Prisma schema and returns structured data compliant with the
 * schema.
 *
 * Proper validation and authorization checks are enforced to ensure data
 * privacy and integrity.
 *
 * @param props.connection
 * @param props.id Unique identifier of the customer inquiry
 * @path /shoppingMall/customer/customerInquiries/:id
 * @accessor api.functional.shoppingMall.customer.customerInquiries.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the customer inquiry */
    id: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallCustomerInquiry;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/customerInquiries/:id",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/customerInquiries/${encodeURIComponent(props.id ?? "null")}`;
  export const random = (): IShoppingMallCustomerInquiry =>
    typia.random<IShoppingMallCustomerInquiry>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("id")(() => typia.assert(props.id));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

