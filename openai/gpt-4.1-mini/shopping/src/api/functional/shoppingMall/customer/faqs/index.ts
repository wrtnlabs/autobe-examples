import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallFaq } from "../../../../structures/IShoppingMallFaq";

/**
 * Create a new FAQ entry in the shopping mall platform.
 *
 * This operation allows authorized users to add new frequently asked questions
 * to the system. Each FAQ consists of a question and an answer to assist
 * customers in resolving common issues.
 *
 * Security: Only authenticated users with proper permissions can create FAQs.
 * Input data is validated to comply with content policies and length limits.
 *
 * Related operations include updating existing FAQ entries (PUT /faqs/{id}),
 * and retrieving FAQ lists for display.
 *
 * @param props.connection
 * @param props.body Data structure for creating a new FAQ entry
 * @path /shoppingMall/customer/faqs
 * @accessor api.functional.shoppingMall.customer.faqs.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** Data structure for creating a new FAQ entry */
    body: IShoppingMallFaq.ICreate;
  };
  export type Body = IShoppingMallFaq.ICreate;
  export type Response = IShoppingMallFaq;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/customer/faqs",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/customer/faqs";
  export const random = (): IShoppingMallFaq =>
    typia.random<IShoppingMallFaq>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

