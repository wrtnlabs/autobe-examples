/**
 * Get detailed information of a specific customer loyalty point record.
 *
 * Retrieve the detailed information for a specific customer loyalty point
 * record identified by its unique point ID.
 *
 * This endpoint fetches the full details of the point record, including the
 * current balance of points the customer has accrued, timestamps of creation
 * and last update, and any soft deletion timestamp.
 *
 * Security: Access to this endpoint requires appropriate authorization,
 * ensuring only permitted actors can view sensitive customer point data.
 *
 * This API operation directly maps to the shopping_mall_points Prisma table and
 * respects the database schema structure, providing a single point of truth for
 * customer loyalty points.
 *
 * Related operations: Create new point record (POST /points).
 *
 * @param props.connection
 * @param props.pointId Unique identifier of the customer point record
 * @path /shoppingMall/customer/points/:pointId
 * @accessor api.functional.shoppingMall.customer.points.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the customer point record */
    pointId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallPoints;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/points/:pointId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/points/${encodeURIComponent(props.pointId ?? "null")}`;
  export const random = (): IShoppingMallPoints =>
    typia.random<IShoppingMallPoints>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("pointId")(() => typia.assert(props.pointId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

