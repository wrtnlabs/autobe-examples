/**
 * Retrieve a paginated list of seller answers for the specified shopping mall
 * customer question.
 *
 * This operation accepts search and pagination parameters in the body to filter
 * and page through the answers.
 *
 * Security ensures that only authorized users can access answer data.
 *
 * This operation is part of the question-answer management flow in the system,
 * linked to the shopping_mall_question_answers table.
 *
 * Related operations: create/update/delete of answers, customer question
 * management.
 *
 * @param props.connection
 * @param props.shoppingMallCustomerQuestionId Unique identifier of the target
 *   customer question to retrieve answers for
 * @param props.body Filtering, sorting and pagination parameters for retrieving
 *   seller answers
 * @path /shoppingMall/customer/shoppingMallCustomerQuestions/:shoppingMallCustomerQuestionId/shoppingMallQuestionAnswers
 * @accessor api.functional.shoppingMall.customer.shoppingMallCustomerQuestions.shoppingMallQuestionAnswers.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target customer question to retrieve answers
     * for
     */
    shoppingMallCustomerQuestionId: string & tags.Format<"uuid">;

    /**
     * Filtering, sorting and pagination parameters for retrieving seller
     * answers
     */
    body: IShoppingMallQuestionAnswer.IRequest;
  };
  export type Body = IShoppingMallQuestionAnswer.IRequest;
  export type Response = IPageIShoppingMallQuestionAnswer.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/customer/shoppingMallCustomerQuestions/:shoppingMallCustomerQuestionId/shoppingMallQuestionAnswers",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/customer/shoppingMallCustomerQuestions/${encodeURIComponent(props.shoppingMallCustomerQuestionId ?? "null")}/shoppingMallQuestionAnswers`;
  export const random = (): IPageIShoppingMallQuestionAnswer.ISummary =>
    typia.random<IPageIShoppingMallQuestionAnswer.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shoppingMallCustomerQuestionId")(() =>
        typia.assert(props.shoppingMallCustomerQuestionId),
      );
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

