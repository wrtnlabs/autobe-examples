import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallShipmentTracking } from "../../../../structures/IShoppingMallShipmentTracking";

/**
 * Retrieve shipment tracking information by ID from
 * shopping_mall_shipment_trackings.
 *
 * Retrieve detailed shipment tracking information for a specific shipment
 * identified by its unique ID. This endpoint accesses the
 * shopping_mall_shipment_trackings table which captures carrier-provided
 * tracking numbers, shipping carrier names, current shipment status, shipment
 * and delivery timestamps, and metadata.
 *
 * Security considerations require that only authorized actors such as customers
 * associated with the order, sellers managing the shipment, or admin users can
 * access this sensitive shipment tracking data.
 *
 * The response includes all relevant tracking fields reflecting the current
 * shipping lifecycle stage, allowing user interfaces to provide accurate and
 * timely shipment status updates.
 *
 * This operation is a read-only GET and requires the shipmentTracking ID as the
 * path parameter. Validation ensures the shipment ID exists, and proper
 * authorization is enforced.
 *
 * @param props.connection
 * @param props.id Unique identifier of the shipment tracking record
 * @path /shoppingMall/customer/shipmentTrackings/:id
 * @accessor api.functional.shoppingMall.customer.shipmentTrackings.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the shipment tracking record */
    id: string;
  };
  export type Response = IShoppingMallShipmentTracking;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/shipmentTrackings/:id",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/shipmentTrackings/${encodeURIComponent(props.id ?? "null")}`;
  export const random = (): IShoppingMallShipmentTracking =>
    typia.random<IShoppingMallShipmentTracking>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("id")(() => typia.assert(props.id));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
