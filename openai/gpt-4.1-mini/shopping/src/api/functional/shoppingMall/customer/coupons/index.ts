/**
 * Retrieve and search through the list of shopping mall coupons using advanced
 * filtering, searching, and pagination parameters.
 *
 * This API endpoint supports search by coupon code, type, date range for coupon
 * validity, and filtering based on deletion status (active or deleted) using
 * the deleted_at field.
 *
 * Clients can paginate results with customizable page size and page number, and
 * sort by various coupon attributes like start_date, end_date, or
 * discount_value.
 *
 * Security: Only authenticated customers are allowed to list coupons. Data
 * returned includes all coupon details except for soft-deleted coupons unless
 * explicitly filtered.
 *
 * This operation operates on the shopping_mall_coupons table as defined in the
 * Prisma DB schema. The response body returns a paginated list of coupon
 * summaries conforming to the IShoppingMallCoupon.ISummary interface.
 *
 * @param props.connection
 * @param props.body Search and pagination parameters for filtering coupons
 * @path /shoppingMall/customer/coupons
 * @accessor api.functional.shoppingMall.customer.coupons.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search and pagination parameters for filtering coupons */
    body: IShoppingMallCoupon.IRequest;
  };
  export type Body = IShoppingMallCoupon.IRequest;
  export type Response = IPageIShoppingMallCoupon.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/customer/coupons",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/customer/coupons";
  export const random = (): IPageIShoppingMallCoupon.ISummary =>
    typia.random<IPageIShoppingMallCoupon.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

