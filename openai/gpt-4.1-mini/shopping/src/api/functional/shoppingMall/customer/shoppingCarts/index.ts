/**
 * Retrieve a specific shopping cart by ID.
 *
 * Retrieve the full details of a specific shopping cart by its unique
 * identifier.
 *
 * This operation allows any authenticated customer to access their own shopping
 * cart details. The shopping cart is identified by a unique UUID exposed as the
 * shoppingCartId in the URL path parameter.
 *
 * Security considerations include verifying that the requester owns the
 * shopping cart or has sufficient permissions to view it. The shopping cart
 * includes references to customer information and the collection of items
 * currently in the cart.
 *
 * This operation integrates with the shopping_mall_shopping_carts table from
 * the Prisma schema, ensuring all returned fields reflect current database
 * state. Validation ensures the shoppingCartId conforms to UUID format to
 * prevent injection attacks.
 *
 * Related operations: create a new shopping cart (POST /shoppingCarts).
 *
 * @param props.connection
 * @param props.shoppingCartId Unique identifier of the target shopping cart
 *   (UUID)
 * @path /shoppingMall/customer/shoppingCarts/:shoppingCartId
 * @accessor api.functional.shoppingMall.customer.shoppingCarts.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target shopping cart (UUID) */
    shoppingCartId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallShoppingCart;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/shoppingCarts/:shoppingCartId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/shoppingCarts/${encodeURIComponent(props.shoppingCartId ?? "null")}`;
  export const random = (): IShoppingMallShoppingCart =>
    typia.random<IShoppingMallShoppingCart>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shoppingCartId")(() => typia.assert(props.shoppingCartId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

