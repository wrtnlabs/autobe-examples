import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallChannelDefinition } from "../../../../structures/IShoppingMallChannelDefinition";

/**
 * Get a specific child channel by its unique code under a parent channel
 * identified by code in shopping_mall_channel_definitions.
 *
 * Retrieve a child channel entity that belongs to a specific parent channel in
 * the shopping mall platform's communication channel hierarchy. Both parent and
 * child channels are uniquely identified by their respective code strings.
 *
 * This operation enables clients to fetch detailed information about a child
 * channel including its name, description, creation timestamps, and
 * hierarchical relationships.
 *
 * Access to this operation should be public as channel information is generally
 * non-sensitive or used for navigation purposes. The operation relies on the
 * shopping_mall_channel_definitions table, which supports soft delete and
 * maintains audit timestamps.
 *
 * Parameters represent path variables for the parent channel code and the child
 * channel code, both required to correctly identify the nested resource. This
 * ensures no ambiguity in channel hierarchy traversal.
 *
 * The response returns detailed properties of the child channel as defined by
 * the IShoppingMallChannelDefinition type.
 *
 * @param props.connection
 * @param props.channelCode Unique business identifier code of the parent
 *   channel (global scope)
 * @param props.childChannelCode Unique business identifier code of the child
 *   channel within the parent channel (scoped to parent)
 * @path /shoppingMall/channels/:channelCode/children/:childChannelCode
 * @accessor api.functional.shoppingMall.channels.children.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique business identifier code of the parent channel (global scope) */
    channelCode: string;

    /**
     * Unique business identifier code of the child channel within the
     * parent channel (scoped to parent)
     */
    childChannelCode: string;
  };
  export type Response = IShoppingMallChannelDefinition;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/channels/:channelCode/children/:childChannelCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/channels/${encodeURIComponent(props.channelCode ?? "null")}/children/${encodeURIComponent(props.childChannelCode ?? "null")}`;
  export const random = (): IShoppingMallChannelDefinition =>
    typia.random<IShoppingMallChannelDefinition>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("channelCode")(() => typia.assert(props.channelCode));
      assert.param("childChannelCode")(() =>
        typia.assert(props.childChannelCode),
      );
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
