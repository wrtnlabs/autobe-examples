import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallConfiguration } from "../../../structures/IShoppingMallConfiguration";

/**
 * Retrieve a shopping mall configuration by key.
 *
 * Retrieve the details of a shopping mall configuration identified by its
 * unique key.
 *
 * This operation fetches the configuration entry from the
 * shopping_mall_configurations table, which stores key-value pairs defining
 * various system-wide settings and preferences.
 *
 * Only authorized users or systems that have access permissions can retrieve
 * sensitive or critical configuration values.
 *
 * The response includes the complete configuration entry including the key,
 * value, description, and relevant metadata.
 *
 * @param props.connection
 * @param props.key Unique key of the configuration entry
 * @path /shoppingMall/shoppingMallConfigurations/:key
 * @accessor api.functional.shoppingMall.shoppingMallConfigurations.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique key of the configuration entry */
    key: string;
  };
  export type Response = IShoppingMallConfiguration;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/shoppingMallConfigurations/:key",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/shoppingMallConfigurations/${encodeURIComponent(props.key ?? "null")}`;
  export const random = (): IShoppingMallConfiguration =>
    typia.random<IShoppingMallConfiguration>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("key")(() => typia.assert(props.key));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
