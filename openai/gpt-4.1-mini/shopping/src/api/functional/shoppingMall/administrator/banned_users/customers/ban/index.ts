import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";

import { IShoppingMallBannedUser } from "../../../../../../structures/IShoppingMallBannedUser";

/**
 * Ban a customer user by their unique customerId. This operation is intended solely for administrators to restrict a customer's login access by recording the ban in the `shopping_mall_banned_users` database table.
 *
 * This operation ensures that the customer's order history and related data remain preserved for audit and compliance purposes.
 *
 * The request body is null as the ban reason and metadata are managed internally by the system.
 *
 * Only administrators are authorized to perform this operation.
 *
 * Errors returned include 404 if the customer does not exist, and 403 for unauthorized access.
 *
 * Related operations include unbanning customers and querying banned user lists via separate endpoints.
 *
 * @param props.connection
 * @param props.customerId Target customer UUID globally identifying the customer to ban
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor administrator
 * @x-autobe-specification Validate administrator authorization before execution.
 *
 * Locate target customer by customerId, verify existence.
 *
 * If customer already banned, return existing ban record.
 *
 * If not banned, create a new banned user record in shopping_mall_banned_users with ban reason and timestamps.
 *
 * Ensure transactional consistency.
 *
 * Return the banned user summary after successful ban application.
 *
 * Log the action in audit logs for compliance.
 *
 * Handle errors for non-existent customer or unauthorized access properly.
 *
 * No request body; path parameter provides the customer ID.
 * @path /shoppingMall/administrator/banned-users/customers/:customerId/ban
 * @accessor api.functional.shoppingMall.administrator.banned_users.customers.ban.banCustomer
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function banCustomer(
  connection: IConnection,
  props: banCustomer.Props,
): Promise<banCustomer.Response> {
  return true === connection.simulate
    ? banCustomer.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...banCustomer.METADATA,
          path: banCustomer.path(props),
          status: null,
        },
      );
}
export namespace banCustomer {
  export type Props = {
    /**
     * Target customer UUID globally identifying the customer to ban
     */
    customerId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallBannedUser;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/administrator/banned-users/customers/:customerId/ban",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/administrator/banned-users/customers/${encodeURIComponent(props.customerId ?? "null")}/ban`;
  export const random = (): IShoppingMallBannedUser =>
    typia.random<IShoppingMallBannedUser>();
  export const simulate = (
    connection: IConnection,
    props: banCustomer.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: banCustomer.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("customerId")(() => typia.assert(props.customerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
