import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductSnapshot } from "../../../../../structures/IShoppingMallProductSnapshot";
import { IPageIShoppingMallProductSnapshot } from "../../../../../structures/IPageIShoppingMallProductSnapshot";

/**
 * Retrieve a filtered and paginated list of shopping mall product snapshots
 * representing historical product data at specific points in time.
 *
 * Clients can use various search criteria such as snapshot date ranges, product
 * identifiers, and status filters to find relevant snapshots. Pagination
 * controls allow efficient browsing through large datasets.
 *
 * Security considerations include ensuring only authorized users can access
 * snapshots due to potential sensitive historical data.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for product
 *   snapshot filtering
 * @path /shoppingMall/admin/shoppingMallProducts/snapshots
 * @accessor api.functional.shoppingMall.admin.shoppingMallProducts.snapshots.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and pagination parameters for product snapshot
     * filtering
     */
    body: IShoppingMallProductSnapshot.IRequest;
  };
  export type Body = IShoppingMallProductSnapshot.IRequest;
  export type Response = IPageIShoppingMallProductSnapshot.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/shoppingMallProducts/snapshots",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/shoppingMall/admin/shoppingMallProducts/snapshots";
  export const random = (): IPageIShoppingMallProductSnapshot.ISummary =>
    typia.random<IPageIShoppingMallProductSnapshot.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

