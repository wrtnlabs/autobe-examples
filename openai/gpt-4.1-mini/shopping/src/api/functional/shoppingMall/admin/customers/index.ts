/**
 * Search and retrieve a filtered, paginated list of shopping mall customers.
 *
 * Retrieve a filtered and paginated list of shopping mall customers from the
 * system. This operation supports advanced search capabilities enabling clients
 * to filter customers by properties such as email domain, nickname, account
 * creation date, and deletion status.
 *
 * The response includes customer summary information optimized for display in
 * user interfaces requiring paginated lists. The operation takes into account
 * unique email constraints and applies indexing on relevant fields for
 * performance.
 *
 * Security and permissions require that only authorized actors (admins) can
 * access this data, as it contains sensitive user information. Data delivery
 * respects soft deletion status, excluding logically deleted customer accounts
 * from results.
 *
 * Typical usage includes administrative management tools, analytics dashboards,
 * or bulk email campaign preparations where a list of customers is required.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for customer
 *   filtering
 * @path /shoppingMall/admin/customers
 * @accessor api.functional.shoppingMall.admin.customers.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for customer filtering */
    body: IShoppingMallCustomer.IRequest;
  };
  export type Body = IShoppingMallCustomer.IRequest;
  export type Response = IPageIShoppingMallCustomer.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/customers",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/customers";
  export const random = (): IPageIShoppingMallCustomer.ISummary =>
    typia.random<IPageIShoppingMallCustomer.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

