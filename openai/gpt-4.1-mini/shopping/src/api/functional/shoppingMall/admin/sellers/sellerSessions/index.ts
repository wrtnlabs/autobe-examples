/**
 * Search and retrieve seller session records by seller ID.
 *
 * Retrieve paginated session records of a specified seller user.
 *
 * This operation allows authorized users to view detailed connection sessions
 * associated with a specific seller. Each session record includes IP address,
 * URL of origin, referrer information, creation timestamp, and session
 * expiration.
 *
 * Security: Only administrators or authorized personnel can access this data
 * due to sensitive session information.
 *
 * This operation interacts with the `shopping_mall_seller_sessions` table,
 * filtered by the seller's unique UUID.
 *
 * Related operations: Delete seller (DELETE /sellers/{sellerId}) to remove
 * seller account and associated sessions.
 *
 * @param props.connection
 * @param props.sellerId Unique identifier of the target seller user
 * @param props.body Search criteria and pagination parameters for filtering
 *   seller sessions
 * @path /shoppingMall/admin/sellers/:sellerId/sellerSessions
 * @accessor api.functional.shoppingMall.admin.sellers.sellerSessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
