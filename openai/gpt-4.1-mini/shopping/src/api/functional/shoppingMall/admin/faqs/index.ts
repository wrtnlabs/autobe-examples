import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Delete a FAQ entry by its unique identifier (admin only).
 *
 * Permanently removes the FAQ entry identified by the specified unique
 * identifier from the shopping mall platform's FAQ system.
 *
 * This operation is intended solely for administrators who manage the FAQ
 * content. Deletion is irreversible and permanently removes the data from the
 * system.
 *
 * Security considerations include strict authorization to prevent unauthorized
 * deletion attempts. The endpoint ensures the caller is authenticated and has
 * appropriate admin privileges.
 *
 * Refer to the Prisma schema for shopping_mall_faqs for detailed data structure
 * and constraints.
 *
 * @param props.connection
 * @param props.id Unique identifier of the target FAQ entry
 * @path /shoppingMall/admin/faqs/:id
 * @accessor api.functional.shoppingMall.admin.faqs.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the target FAQ entry */
    id: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/admin/faqs/:id",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/faqs/${encodeURIComponent(props.id ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("id")(() => typia.assert(props.id));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
