import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallPayment } from "../../../../structures/IShoppingMallPayment";
import { IPageIShoppingMallPayment } from "../../../../structures/IPageIShoppingMallPayment";

/**
 * Retrieve a paginated list of shopping mall payment records.
 *
 * This operation allows authorized users (e.g., admin) to search, filter, and
 * retrieve payment records related to orders placed on the shopping mall
 * platform.
 *
 * Payments contain critical information including payment methods, statuses,
 * amounts, and timestamps. This API supports pagination and sorting to
 * efficiently handle large volumes of payment data.
 *
 * Security considerations include restricting access to authorized actors such
 * as admins to protect sensitive financial transaction data.
 *
 * The operation closely integrates with the shopping_mall_payments Prisma table
 * which tracks payment details linked to orders. The data returned reflects the
 * latest payment status and amount information.
 *
 * Clients can use this endpoint to build payment dashboards, financial reports,
 * and audit logs consistent with business rules and compliance requirements.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for filtering
 *   shopping mall payments
 * @path /shoppingMall/admin/payments
 * @accessor api.functional.shoppingMall.admin.payments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and pagination parameters for filtering shopping mall
     * payments
     */
    body: IShoppingMallPayment.IRequest;
  };
  export type Body = IShoppingMallPayment.IRequest;
  export type Response = IPageIShoppingMallPayment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/payments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/payments";
  export const random = (): IPageIShoppingMallPayment.ISummary =>
    typia.random<IPageIShoppingMallPayment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

