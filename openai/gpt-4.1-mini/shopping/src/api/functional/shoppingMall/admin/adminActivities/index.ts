/**
 * Search and retrieve a filtered, paginated list of shopping mall admin
 * activities.
 *
 * Retrieve a filtered and paginated list of administrative activities recorded
 * in the platform. Each activity log entry records the admin user who performed
 * the action, a descriptive message detailing the nature of the activity, and
 * timestamps marking when the action occurred and any subsequent updates.
 *
 * This operation supports pagination and filtering to allow administrators to
 * efficiently query large volumes of audit log data by relevant criteria such
 * as date ranges or specific admin users.
 *
 * Security considerations require that only admins can access this endpoint to
 * protect sensitive operational data. Logs are immutable and cannot be altered
 * by users.
 *
 * The underlying data corresponds to the shopping_mall_admin_activities table,
 * ensuring accurate real-time reflection of admin actions logged in the
 * system.
 *
 * This operation complements endpoints that retrieve individual admin activity
 * details and supports regulatory compliance through system activity tracing.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for admin
 *   activity filtering
 * @path /shoppingMall/admin/adminActivities
 * @accessor api.functional.shoppingMall.admin.adminActivities.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and pagination parameters for admin activity
     * filtering
     */
    body: IShoppingMallAdminActivity.IRequest;
  };
  export type Body = IShoppingMallAdminActivity.IRequest;
  export type Response = IPageIShoppingMallAdminActivity.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/adminActivities",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/adminActivities";
  export const random = (): IPageIShoppingMallAdminActivity.ISummary =>
    typia.random<IPageIShoppingMallAdminActivity.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

