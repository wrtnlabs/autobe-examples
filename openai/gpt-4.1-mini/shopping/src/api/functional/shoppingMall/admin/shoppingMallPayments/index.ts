/**
 * Search and retrieve a filtered, paginated list of payments.
 *
 * Retrieve a filtered, paginated list of payments within the shopping mall
 * platform.
 *
 * Clients can provide advanced filtering options in the request to query
 * payments by various criteria such as status, date range, payment type, and
 * associated order details.
 *
 * The response includes summaries of each payment matching the criteria, along
 * with pagination metadata. Access is restricted to administrators for
 * confidentiality and financial compliance.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for payment
 *   filtering
 * @path /shoppingMall/admin/shoppingMallPayments
 * @accessor api.functional.shoppingMall.admin.shoppingMallPayments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for payment filtering */
    body: IShoppingMallPayment.IRequest;
  };
  export type Body = IShoppingMallPayment.IRequest;
  export type Response = IPageIShoppingMallPayment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/shoppingMallPayments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/shoppingMallPayments";
  export const random = (): IPageIShoppingMallPayment.ISummary =>
    typia.random<IPageIShoppingMallPayment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
