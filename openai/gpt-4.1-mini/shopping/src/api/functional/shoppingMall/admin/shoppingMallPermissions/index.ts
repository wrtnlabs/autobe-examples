/**
 * Creates a new permission entity within the shopping mall backend system. This
 * permission defines a specific access right that can be assigned to users or
 * roles.
 *
 * The operation requires the unique permission `name`, a display `label`, and
 * optionally a comprehensive `description` to explain the permission's
 * purpose.
 *
 * Security and validation ensure that permission names are unique and conform
 * to naming conventions.
 *
 * On success, the newly created permission object is returned.
 *
 * Use this API to manage granular access control policies dynamically within
 * the platform.
 *
 * @param props.connection
 * @param props.body The permission information to create
 * @path /shoppingMall/admin/shoppingMallPermissions
 * @accessor api.functional.shoppingMall.admin.shoppingMallPermissions.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
