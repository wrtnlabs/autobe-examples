/**
 * Update an existing shopping mall guest record by its unique id.
 *
 * This operation allows guest users to modify guest session details and
 * browsing related metadata. The request body must conform to the
 * IShoppingMallGuest.IUpdate schema, ensuring only valid fields can be
 * updated.
 *
 * Security: Only guest users can perform updates. Authorization is validated
 * against their role.
 *
 * This operation modifies records in the shopping_mall_guests table, which
 * holds guest session info for non-logged-in visitors.
 *
 * Related operations: GET at /shoppingMallGuests/{shoppingMallGuestId}, DELETE
 * at /shoppingMallGuests/{shoppingMallGuestId}.
 *
 * @param props.connection
 * @param props.shoppingMallGuestId Unique identifier of the shopping mall guest
 *   to update
 * @param props.body Data for updating a shopping mall guest record
 * @path /shoppingMall/guest/shoppingMallGuests/:shoppingMallGuestId
 * @accessor api.functional.shoppingMall.guest.shoppingMallGuests.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /** Unique identifier of the shopping mall guest to update */
    shoppingMallGuestId: string & tags.Format<"uuid">;

    /** Data for updating a shopping mall guest record */
    body: IShoppingMallGuest.IUpdate;
  };
  export type Body = IShoppingMallGuest.IUpdate;
  export type Response = IShoppingMallGuest;

  export const METADATA = {
    method: "PUT",
    path: "/shoppingMall/guest/shoppingMallGuests/:shoppingMallGuestId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/guest/shoppingMallGuests/${encodeURIComponent(props.shoppingMallGuestId ?? "null")}`;
  export const random = (): IShoppingMallGuest =>
    typia.random<IShoppingMallGuest>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shoppingMallGuestId")(() =>
        typia.assert(props.shoppingMallGuestId),
      );
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

