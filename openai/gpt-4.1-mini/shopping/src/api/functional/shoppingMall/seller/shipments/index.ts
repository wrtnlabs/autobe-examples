import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallShipment } from "../../../../structures/IShoppingMallShipment";

/**
 * Update an existing shipment's details in the system identified by the
 * shipment ID.
 *
 * This operation allows authorized users such as sellers and admins to modify
 * shipment information including carriers, tracking numbers, expected delivery
 * dates, and shipment status updates.
 *
 * Security considerations include verification of user roles to prevent
 * unauthorized modifications. The shipment ID must uniquely identify the
 * shipment record, ensuring precise updates.
 *
 * The updated shipment reflects the current state of the physical shipment
 * process. Other related operations include retrieving shipment details (GET)
 * and deleting shipments when appropriate.
 *
 * @param props.connection
 * @param props.shipmentId Unique identifier of the target shipment
 * @param props.body Data for updating the shipment
 * @path /shoppingMall/seller/shipments/:shipmentId
 * @accessor api.functional.shoppingMall.seller.shipments.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /** Unique identifier of the target shipment */
    shipmentId: string & tags.Format<"uuid">;

    /** Data for updating the shipment */
    body: IShoppingMallShipment.IUpdate;
  };
  export type Body = IShoppingMallShipment.IUpdate;
  export type Response = IShoppingMallShipment;

  export const METADATA = {
    method: "PUT",
    path: "/shoppingMall/seller/shipments/:shipmentId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/seller/shipments/${encodeURIComponent(props.shipmentId ?? "null")}`;
  export const random = (): IShoppingMallShipment =>
    typia.random<IShoppingMallShipment>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shipmentId")(() => typia.assert(props.shipmentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

