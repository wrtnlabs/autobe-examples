import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getDiscussionBoardDiscussionBoardArticlesId } from "../../../providers/getDiscussionBoardDiscussionBoardArticlesId";

import { IDiscussionBoardArticle } from "../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/discussionBoardArticles/:id")
export class DiscussionboardDiscussionboardarticlesController {
  /**
   * Get a specific discussion board article by its UUID.
   *
   * Retrieve detailed information of a discussion board article by its unique
   * identifier.
   *
   * This operation fetches the full details of an article, including title,
   * content, author reference, creation and update timestamps, and the soft
   * deletion timestamp if applicable.
   *
   * It ensures only active articles (not soft-deleted) are returned in typical
   * use cases. Access is generally public, allowing any user or guest to view
   * the article content.
   *
   * Related operations include listing articles (POST /discussionBoardArticles
   * with filtering) and managing attachments/comments handled by separate
   * endpoints.
   *
   * @param connection
   * @param id Unique identifier of the target discussion board article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await getDiscussionBoardDiscussionBoardArticlesId({
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
