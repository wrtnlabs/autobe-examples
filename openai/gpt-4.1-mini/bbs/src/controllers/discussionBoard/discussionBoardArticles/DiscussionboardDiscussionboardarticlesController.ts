import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardDiscussionBoardArticles } from "../../../providers/patchDiscussionBoardDiscussionBoardArticles";
import { getDiscussionBoardDiscussionBoardArticlesArticleId } from "../../../providers/getDiscussionBoardDiscussionBoardArticlesArticleId";

import { IPageIDiscussionBoardArticle } from "../../../api/structures/IPageIDiscussionBoardArticle";
import { IDiscussionBoardArticle } from "../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/discussionBoardArticles")
export class DiscussionboardDiscussionboardarticlesController {
  /**
   * Retrieve paginated list of discussion board articles with search
   * capabilities.
   *
   * Retrieve a filtered and paginated list of discussion board articles from
   * the system. This operation allows clients, including guest users, to search
   * for articles based on title or content using efficient trigram-based text
   * search indexes in the database.
   *
   * The response includes metadata about pagination to navigate large article
   * collections. Only articles that have not been soft deleted (deleted_at is
   * null) are included to ensure that removed content is not shown.
   *
   * Security considerations permit public access without authentication, as
   * articles are meant to be browseable by all visitors without modification
   * rights.
   *
   * This operation interacts exclusively with the discussion_board_articles
   * table, referencing all standard fields such as title, content_markdown,
   * created_at, and updated_at. It does not include attachments directly but
   * serves as a primary entry point to articles that may be enriched by other
   * endpoints providing attachments separately.
   *
   * Validation rules ensure compatibility with the pagination request object
   * and respect user permissions implicitly by providing read-only data.
   *
   * Related API operations include GET /discussionBoardArticles/{articleId} to
   * retrieve detailed article content and associated attachments.
   *
   * This is a read-only operation, utilizing PATCH method to allow complex
   * search/filter request payloads.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for discussion board
   *   articles
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardDiscussionBoardArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed discussion board article by ID.
   *
   * Retrieve detailed information of a single discussion board article by its
   * unique identifier. This operation is accessible to all users, including
   * guests, allowing public read access.
   *
   * The retrieved article includes the title, markdown content, and timestamps
   * indicating creation and last update. The operation excludes articles that
   * are soft deleted.
   *
   * Security considerations allow unauthenticated access as articles are
   * publicly visible. The operation parameter articleId is required and
   * validated as a UUID which uniquely identifies the target article.
   *
   * No request body is required for this GET operation. The response returns
   * the full article entity, facilitating detailed display in clients.
   *
   * Related operations include PATCH /discussionBoardArticles for list
   * retrieval and attachment endpoints for associated files.
   *
   * @param connection
   * @param articleId Unique identifier of the target discussion board article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await getDiscussionBoardDiscussionBoardArticlesArticleId({
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
