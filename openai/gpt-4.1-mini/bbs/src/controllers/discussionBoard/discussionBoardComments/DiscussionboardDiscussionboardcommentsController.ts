import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getDiscussionBoardDiscussionBoardCommentsId } from "../../../providers/getDiscussionBoardDiscussionBoardCommentsId";

import { IDiscussionBoardComment } from "../../../api/structures/IDiscussionBoardComment";

@Controller("/discussionBoard/discussionBoardComments/:id")
export class DiscussionboardDiscussionboardcommentsController {
  /**
   * Retrieve detailed information of a discussion board comment by ID.
   *
   * Retrieve a single discussion board comment by its unique identifier.
   *
   * This operation returns the full details of the comment, including its text
   * content, timestamps for creation, last update, and soft deletion status, as
   * well as references to the associated article and the member who authored
   * the comment.
   *
   * Security: Access to this endpoint is unrestricted (public endpoint) for
   * viewing purposes only.
   *
   * The comment's id parameter is a UUID string uniquely identifying the
   * comment. There is no request body because this is a simple GET operation.
   *
   * Related operations include listing comments (POST /discussionBoardComments)
   * and creating comments (POST /discussionBoardComments).
   *
   * @param connection
   * @param id UUID string uniquely identifying the discussion board comment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await getDiscussionBoardDiscussionBoardCommentsId({
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
