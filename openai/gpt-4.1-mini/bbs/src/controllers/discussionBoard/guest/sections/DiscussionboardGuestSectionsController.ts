import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardSection } from "../../../../api/structures/IDiscussionBoardSection";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { getDiscussionBoardGuestSectionsSectionId } from "../../../../providers/getDiscussionBoardGuestSectionsSectionId";
import { patchDiscussionBoardGuestSectionsSectionId } from "../../../../providers/patchDiscussionBoardGuestSectionsSectionId";

@Controller("/discussionBoard/guest/sections/:sectionId")
export class DiscussionboardGuestSectionsController {
  /**
   * Retrieve detailed information about a specific discussion board section by its unique identifier.
   *
   * This operation enables users to view the section's name and description, supporting browsing and content discovery on the discussion board.
   *
   * Security considerations: This endpoint is publicly accessible; no authentication is required.
   *
   * Database entity: discussion_board_sections contains the persistent record of board sections with unique names and descriptive texts.
   *
   * Validation rules: The sectionId path parameter must be a valid UUID corresponding to an existing section.
   *
   * Related operations: Use GET /sections to list all sections. Use GET /sections/{sectionId}/articles to browse articles within the section.
   *
   * Expected behavior: Returns 404 if the sectionId does not correspond to any existing section.
   *
   * Error handling: Proper HTTP status codes will be returned for not found or invalid ID formats.
   *
   * This operation strictly retrieves information without modifying any data.
   *
   * @param connection
   * @param sectionId Unique identifier of the target discussion board section
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Implement GET handler to load a section entity by sectionId from discussion_board_sections table.
   *
   * Perform UUID validation on sectionId path parameter.
   *
   * Query the database for a section record matching sectionId.
   *
   * If found, return the IDiscussionBoardSection data structure including name, description, and metadata.
   *
   * If not found, return 404 response.
   *
   * No request body required.
   *
   * This operation is publicly accessible without authentication.
   *
   * This strictly reads the persistent data and does not allow modification.
   *
   * It complements the GET /sections list endpoint and the articles list endpoint under this section.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await getDiscussionBoardGuestSectionsSectionId({
        guest,
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing discussion board section's name and/or description.
   *
   * This operation allows administrators to modify the metadata of a section, including changing its unique name and detailed description. It ensures that only authorized administrator actors can perform the update.
   *
   * The section entity is identified uniquely by its UUID `sectionId`. Changes are validated to ensure the name remains unique across the system as per business rules.
   *
   * Security: Only users with administrator privileges may perform this operation.
   *
   * Related operations:
   * - POST /sections to create new sections
   * - DELETE /sections/{sectionId} to delete a section
   *
   * Errors:
   * - 404 if the sectionId does not exist
   * - 409 if attempting to update to a non-unique name
   *
   * @param connection
   * @param sectionId UUID of the discussion board section to update.
   * @param body Partial or full update information for the discussion board section.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification 1. Validate the `sectionId` path parameter exists and is a UUID.
   * 2. Authenticate the user and verify administrator role.
   * 3. Parse and validate the request body adhering to IDiscussionBoardSection.IUpdate schema.
   * 4. Check that if `name` is being updated, it does not conflict with any existing section names.
   * 5. Update the section's `name` and `description` fields if provided.
   * 6. Persist changes in database respecting timestamps.
   * 7. Return the updated section data as IDiscussionBoardSection.
   * 8. Handle errors such as not found or name conflicts with appropriate HTTP status codes and messages.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updateSection(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardSection.IUpdate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await patchDiscussionBoardGuestSectionsSectionId({
        guest,
        sectionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
