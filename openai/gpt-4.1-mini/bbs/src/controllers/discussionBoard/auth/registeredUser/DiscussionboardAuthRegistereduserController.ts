import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardRegisteredUser } from "../../../../api/structures/IDiscussionBoardRegisteredUser";
import { postDiscussionBoardAuthRegisteredUserJoin } from "../../../../providers/postDiscussionBoardAuthRegisteredUserJoin";
import { postDiscussionBoardAuthRegisteredUserLogin } from "../../../../providers/postDiscussionBoardAuthRegisteredUserLogin";
import { postDiscussionBoardAuthRegisteredUserRefresh } from "../../../../providers/postDiscussionBoardAuthRegisteredUserRefresh";

@Controller("/discussionBoard/auth/registeredUser")
export class DiscussionboardAuthRegistereduserController {
  /**
   * This operation enables a new registered user to create an account in the discussion board system. It requires unique email and password credentials supplied in the request body. The system validates that the email does not already exist, applies password hashing securely, and stores the user profile including display name and optional bio. On success, it returns an authorization token and user details confirming successful registration.
   *
   * Security considerations include validation of email format and password strength, rejection of duplicate email registrations, and secure password storage techniques. This operation is unauthenticated, allowing new users to join the platform.
   *
   * This operation complements the login and refresh token operations to form a complete user authentication flow for registered users.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Data required for a registered user to join the platform including email, password, display name, and optional bio.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor registeredUser
   * @x-autobe-specification Service logic to validate user registration details including unique email validation, password hashing, and creation of registered user account with profile defaults. Ensure email uniqueness and enforce password security policies. Store new user record with current timestamps and empty ban status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardRegisteredUser.IJoin,
  ): Promise<IDiscussionBoardRegisteredUser.IAuthorized> {
    try {
      return await postDiscussionBoardAuthRegisteredUserJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation validates the email and password credentials of a registered user attempting to log in. It confirms that the provided credentials match a stored user record that is not banned. On successful authentication, an authorization token is issued allowing access to protected resources.
   *
   * Security considerations include secure password comparison, lockout policies on multiple failed attempts, and exclusion of banned users from authentication.
   *
   * This operation relies on the join operation for initial user account creation and the refresh operation for ongoing token renewal.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials including email and password for registered user authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor registeredUser
   * @x-autobe-specification Authenticate the registered user's credentials by verifying the provided email and password hash against stored values. On successful validation, issue a JWT authorization token. If the user is banned, reject the login attempt with an appropriate error message.
   *
   * This operation is critical for secure access control and ensures only registered, non-banned users can obtain authenticated sessions. It integrates with token refresh and join operations to manage user authentication lifecycle.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardRegisteredUser.ILogin,
  ): Promise<IDiscussionBoardRegisteredUser.IAuthorized> {
    try {
      return await postDiscussionBoardAuthRegisteredUserLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation accepts a valid JWT refresh token from a registered user and issues new authorization tokens. It ensures session continuity by verifying token validity and renewing access without requiring user login each time.
   *
   * Security best practices require refresh tokens to have limited lifespan and revocation mechanisms. This operation is unauthenticated, relying on the provided refresh token for validation.
   *
   * Together with join and login, this operation completes the standard authentication flow for registered users.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token payload allowing session renewal for registered users.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor registeredUser
   * @x-autobe-specification Process JWT refresh token presented by authenticated registered user to renew access tokens without requiring login credentials every session. Validate refresh token authenticity and expiration. Issue new access and refresh tokens upon successful validation.
   *
   * This operation is essential to maintaining continuous secure session access without exposing user credentials repeatedly. It complements join and login operations, enabling seamless token lifecycle management.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardRegisteredUser.IRefresh,
  ): Promise<IDiscussionBoardRegisteredUser.IAuthorized> {
    try {
      return await postDiscussionBoardAuthRegisteredUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
