import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardAdministrator } from "../../../../api/structures/IDiscussionBoardAdministrator";
import { postDiscussionBoardAuthAdministratorJoin } from "../../../../providers/postDiscussionBoardAuthAdministratorJoin";
import { postDiscussionBoardAuthAdministratorLogin } from "../../../../providers/postDiscussionBoardAuthAdministratorLogin";
import { postDiscussionBoardAuthAdministratorRefresh } from "../../../../providers/postDiscussionBoardAuthAdministratorRefresh";

@Controller("/discussionBoard/auth/administrator")
export class DiscussionboardAuthAdministratorController {
  /**
   * Registers a new administrator account in the discussion board system. The join operation allows creation of administrator credentials and stores them securely in the database. This operation includes validation on email uniqueness and password strength as per business rules outlined in 'User Account Management' and 'Administrator System' sections of the requirements. After successful registration, the system returns an authorization payload containing JWT tokens to enable immediate authenticated access for the new administrator.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator join request payload.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification This operation handles the registration of a new administrator account. It validates the input data ensuring uniqueness of email and secure password storage. The backend performs necessary hashing of passwords and stores the administrator record in the database. This operation allows new administrators to be created securely and ensures they receive an authorization response with tokens upon successful registration.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardAdministrator.IJoin,
  ): Promise<IDiscussionBoardAdministrator.IAuthorized> {
    try {
      return await postDiscussionBoardAuthAdministratorJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Logs in an existing administrator, validating credentials securely and issuing JWT tokens for authenticated session management. This operation is critical to enforce secure access control for administrator-level users who have elevated permissions including content moderation, user bans, and system configuration.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator login request payload.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification This operation validates administrator credentials and generates a set of JWT tokens if authentication succeeds. It checks the administrator's email and password against the stored hashed credentials in the database. On success, it issues access and refresh tokens encoded with appropriate claims reflecting administrator role and permissions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardAdministrator.ILogin,
  ): Promise<IDiscussionBoardAdministrator.IAuthorized> {
    try {
      return await postDiscussionBoardAuthAdministratorLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes JWT tokens for an authenticated administrator to maintain session validity. This operation supports seamless user experience by allowing token renewal before expiration. Secure validation of the refresh token is performed to prevent unauthorized access.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator token refresh request payload.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification This operation provides a token refresh endpoint that accepts a refresh token and issues a new access token to extend the administrator's authenticated session without requiring re-login. It validates the refresh token for authenticity and expiration and generates a new access token with updated expiration time.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardAdministrator.IRefresh,
  ): Promise<IDiscussionBoardAdministrator.IAuthorized> {
    try {
      return await postDiscussionBoardAuthAdministratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
