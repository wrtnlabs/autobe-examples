import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSuperAdministrator } from "../../../../api/structures/IDiscussionBoardSuperAdministrator";
import { postDiscussionBoardAuthSuperAdministratorJoin } from "../../../../providers/postDiscussionBoardAuthSuperAdministratorJoin";
import { postDiscussionBoardAuthSuperAdministratorLogin } from "../../../../providers/postDiscussionBoardAuthSuperAdministratorLogin";
import { postDiscussionBoardAuthSuperAdministratorRefresh } from "../../../../providers/postDiscussionBoardAuthSuperAdministratorRefresh";

@Controller("/discussionBoard/auth/superAdministrator")
export class DiscussionboardAuthSuperadministratorController {
  /**
   * POST /auth/superAdministrator/join allows a new super administrator to register an account by providing a unique email and password. This creates a record in the discussion_board_super_administrators table with hashed password storage for security. The operation ensures email uniqueness and triggers sending of confirmation processes if applicable. The response returns a JWT authorized object representing successful registration and immediate authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Payload to create a super administrator account, including email and password.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification This operation registers a new super administrator account using email and password. It will validate the uniqueness of the email and store a hashed password in the discussion_board_super_administrators table. The response contains JWT tokens and authentication details in IAuthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardSuperAdministrator.IJoin,
  ): Promise<IDiscussionBoardSuperAdministrator.IAuthorized> {
    try {
      return await postDiscussionBoardAuthSuperAdministratorJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * POST /auth/superAdministrator/login authenticates a super administrator with email and password credentials stored in the discussion_board_super_administrators table. The password is verified against the hashed password. On success, a JWT authorized object is returned containing access and refresh tokens to manage the session securely.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials for super administrator including email and password.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification This operation authenticates a super administrator's credentials by verifying the email and password. On success, it returns JWT tokens for session management.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardSuperAdministrator.ILogin,
  ): Promise<IDiscussionBoardSuperAdministrator.IAuthorized> {
    try {
      return await postDiscussionBoardAuthSuperAdministratorLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * POST /auth/superAdministrator/refresh renews JWT authentication tokens using a valid refresh token issued at login or previous refresh. This operation extends the session lifetime securely without requiring re-entry of credentials. The response contains new JWT authorized tokens for continued access.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token payload to renew JWT authentication tokens for super administrator.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification This operation refreshes JWT tokens for authenticated super administrators, enabling prolonged sessions without re-login. Requires valid refresh token.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardSuperAdministrator.IRefresh,
  ): Promise<IDiscussionBoardSuperAdministrator.IAuthorized> {
    try {
      return await postDiscussionBoardAuthSuperAdministratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
