import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSuperAdministrator } from "../../../../api/structures/IDiscussionBoardSuperAdministrator";
import { postDiscussionBoardAuthSuperAdministratorJoin } from "../../../../providers/postDiscussionBoardAuthSuperAdministratorJoin";
import { postDiscussionBoardAuthSuperAdministratorLogin } from "../../../../providers/postDiscussionBoardAuthSuperAdministratorLogin";
import { postDiscussionBoardAuthSuperAdministratorRefresh } from "../../../../providers/postDiscussionBoardAuthSuperAdministratorRefresh";

@Controller("/discussionBoard/auth/superAdministrator")
export class DiscussionboardAuthSuperadministratorController {
  /**
   * Allows new superAdministrator users to register by providing an email and password. The endpoint validates the request, creates user credentials, and generates authorization tokens for immediate authenticated access. Ensures security best practices for credential handling and token issuance.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Payload to register a new superAdministrator account.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification This operation handles the registration of a new superAdministrator user. The service layer ensures the uniqueness of the email and stores hashed passwords securely. The system issues JWT tokens with superAdministrator claims upon successful registration. Validation of input credentials and error handling for duplicate registrations are implemented.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardSuperAdministrator.IJoin,
  ): Promise<IDiscussionBoardSuperAdministrator.IAuthorized> {
    try {
      return await postDiscussionBoardAuthSuperAdministratorJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates superAdministrator users using email and password, returning JWT tokens for access and refresh to maintain sessions and secure resource access. Protects against brute force attacks and supports performance requirements.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Credentials for login by superAdministrator.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Authenticates a superAdministrator user's credentials against stored email and password. On success, issues JWT access and refresh tokens embedding proper role claims. Invalid credentials result in clear error messages and response codes within stipulated security timing constraints.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardSuperAdministrator.ILogin,
  ): Promise<IDiscussionBoardSuperAdministrator.IAuthorized> {
    try {
      return await postDiscussionBoardAuthSuperAdministratorLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Handles refresh token requests for superAdministrator users, ensuring secure re-issuance of JWT tokens to extend authenticated sessions without requiring login.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token request payload for superAdministrator.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Exchanges a valid refresh token for new JWT access and refresh tokens for superAdministrator users. Validates token freshness and signature to prevent token reuse attacks. Maintains continuous secure sessions without requiring re-authentication.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardSuperAdministrator.IRefresh,
  ): Promise<IDiscussionBoardSuperAdministrator.IAuthorized> {
    try {
      return await postDiscussionBoardAuthSuperAdministratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
