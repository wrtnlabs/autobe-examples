import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardGuest } from "../../../../api/structures/IDiscussionBoardGuest";
import { postDiscussionBoardAuthGuestJoin } from "../../../../providers/postDiscussionBoardAuthGuestJoin";
import { postDiscussionBoardAuthGuestRefresh } from "../../../../providers/postDiscussionBoardAuthGuestRefresh";

@Controller("/discussionBoard/auth/guest")
export class DiscussionboardAuthGuestController {
  /**
   * This API operation allows an unauthenticated guest to join the system by creating a temporary guest identity. It requires the client to provide device fingerprint and other anonymous metadata. Upon success, a JWT token is issued for session continuation. It references discussion_board_guests database columns such as device_fingerprint, user_agent, ip_address, and anonymous_id to create the guest record. This enables session tracking without compromising PII and supports limited feature access as per guest actor permissions. No login credentials are needed or accepted.
   *
   * The 'join' operation is essential because guests must have a way to obtain a valid guest token for authentication in subsequent requests. The JWT token enables stateless authentication and quick session resurrection via refresh tokens.
   *
   * The client must provide device fingerprint, IP address, and user agent information to uniquely identify their session. This prevents abuse and allows session management for guest users.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest user join request payload with device fingerprint, IP, user agent, and optional anonymous ID.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification This operation implements guest user sign-up by creating a temporary guest record with device fingerprint, IP address, user agent, and anonymous identifier. It generates JWT credentials for the guest to enable limited access and browsing features without full registration. The service stores guest data in discussion_board_guests table and returns a token with expiration.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardGuest.IJoin,
  ): Promise<IDiscussionBoardGuest.IAuthorized> {
    try {
      return await postDiscussionBoardAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API operation allows an existing guest session to renew its JWT token before expiration. It requires the client to present a valid refresh token associated with a temporary guest session. The server verifies the session's validity using related database fields such as expired_at and device fingerprint to prevent misuse.
   *
   * Refreshing the token extends the guest user's authenticated session without forced re-joining or re-authentication, preserving a smooth user experience. Successful refresh returns a new JWT token and refresh token pair. This is critical for stateless JWT authentication design enabling guests to browse with temporary credentials.
   *
   * No user credentials or login workflows are involved since guests do not hold persistent accounts.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest user token refresh request with refresh token.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification This operation refreshes the JWT token for a temporary guest session. It validates the existing token's expiry and issues a new token with extended expiration. The session information is verified against the stored guest session records, ensuring the device fingerprint and anonymous ID are consistent. This provides continuous authentication for guest users without requiring credentials.
   *
   * The operation relies on discussion_board_guest_sessions table for validating session timestamps such as created_at and expired_at to ensure session validity before token refresh.
   *
   * Upon successful refresh, a new JWT token is issued allowing the guest session to continue seamlessly.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardGuest.IRefresh,
  ): Promise<IDiscussionBoardGuest.IAuthorized> {
    try {
      return await postDiscussionBoardAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
