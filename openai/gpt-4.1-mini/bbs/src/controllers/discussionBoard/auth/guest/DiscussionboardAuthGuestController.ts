import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardGuest } from "../../../../api/structures/IDiscussionBoardGuest";
import { postDiscussionBoardAuthGuestJoin } from "../../../../providers/postDiscussionBoardAuthGuestJoin";
import { postDiscussionBoardAuthGuestRefresh } from "../../../../providers/postDiscussionBoardAuthGuestRefresh";

@Controller("/discussionBoard/auth/guest")
export class DiscussionboardAuthGuestController {
  /**
   * This endpoint allows unauthenticated users (guest) to obtain a temporary guest account through a join operation. The operation creates a guest session that issues JWT tokens enabling limited access to browse content. It does not require traditional login credentials since guests are anonymous. The operation is idempotent for unique identification factors such as device fingerprinting or anonymous tokens if applicable.
   *
   * The operation implements a POST request to /auth/guest/join.
   *
   * Security considerations ensure no password or email is required. The response returns tokens structured as IDiscussionBoardGuest.IAuthorized, supporting JWT-based stateless auth.
   *
   * This API operation is the entry point for guests into the system, allowing seamless anonymous access while enabling token refresh when needed.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body for guest join operation containing identification and minimal info required.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification The join operation for guest creates a new guest session using minimal identification information, returning authorization tokens. It involves creation of temporary guest session, possibly with device or environment data, but no user credentials.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardGuest.IJoin,
  ): Promise<IDiscussionBoardGuest.IAuthorized> {
    try {
      return await postDiscussionBoardAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint enables guests (unauthenticated) to refresh their JWT authentication tokens without rejoining or logging in. It requires a valid refresh token issued during the join operation. The operation helps maintain continuous but temporary access without user credentials.
   *
   * The API is a POST request to /auth/guest/refresh.
   *
   * Security consideration includes validation of refresh token and rejection of invalid or expired tokens. The response returns new tokens packaged in IDiscussionBoardGuest.IAuthorized.
   *
   * Use of this operation is essential to support stateless JWT auth token lifecycle management for guest users.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body to refresh guest JWT token containing the refresh token.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification The refresh operation for guest allows renewal of JWT tokens using a valid refresh token. It does not require login credentials since guests are unauthenticated. This operation verifies and issues new tokens for continued guest session access over token expiration.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardGuest.IRefresh,
  ): Promise<IDiscussionBoardGuest.IAuthorized> {
    try {
      return await postDiscussionBoardAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
