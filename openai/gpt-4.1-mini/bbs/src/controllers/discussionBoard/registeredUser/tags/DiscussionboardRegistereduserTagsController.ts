import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardArticleTag } from "../../../../api/structures/IDiscussionBoardArticleTag";
import { IDiscussionBoardTag } from "../../../../api/structures/IDiscussionBoardTag";
import { IPageIDiscussionBoardArticleTag } from "../../../../api/structures/IPageIDiscussionBoardArticleTag";
import { RegistereduserAuth } from "../../../../decorators/RegistereduserAuth";
import { RegistereduserPayload } from "../../../../decorators/payload/RegistereduserPayload";
import { getDiscussionBoardRegisteredUserTagsTagId } from "../../../../providers/getDiscussionBoardRegisteredUserTagsTagId";
import { patchDiscussionBoardRegisteredUserTags } from "../../../../providers/patchDiscussionBoardRegisteredUserTags";

@Controller("/discussionBoard/registeredUser/tags")
export class DiscussionboardRegistereduserTagsController {
  /**
   * Retrieve a filtered and paginated list of article tags used in the discussion board.
   *
   * This operation allows for specifying search criteria such as tag names or usage frequency to efficiently browse tag data.
   *
   * No path parameters are required since tags are globally unique by their code.
   *
   * Supports pagination and sorting to enable smooth client navigation through large tag sets.
   *
   * This endpoint is publicly accessible supporting all user types including guests, registered users, and administrators.
   *
   * Related operations include listing articles filtered by tags or managing tags associated with articles.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for article tags
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor registeredUser
   * @x-autobe-specification Service layer queries discussion_board_article_tags with filters from IDiscussionBoardArticleTag.IRequest.
   * Apply pagination and sorting parameters.
   * Return results as IPageIDiscussionBoardArticleTag.ISummary paginated responses.
   * No complex transactions needed.
   * Handle invalid filter input gracefully with clear error messages.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @RegistereduserAuth()
    registeredUser: RegistereduserPayload,
    @TypedBody()
    body: IDiscussionBoardArticleTag.IRequest,
  ): Promise<IPageIDiscussionBoardArticleTag.ISummary> {
    try {
      return await patchDiscussionBoardRegisteredUserTags({
        registeredUser,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a tag used for article categorization in the discussion board.
   *
   * This operation accesses the discussion_board_tags table which stores unique tags with their creation, update, and optional deletion timestamps.
   *
   * It is publicly accessible to allow clients to query tag information for filtering UI or article tagging purposes.
   *
   * No authentication is required to perform this operation.
   *
   * The operation returns full tag details including id, unique name, and timestamps.
   *
   * This endpoint is related to article search and filtering APIs which utilize tags to narrow down article lists.
   *
   * @param connection
   * @param tagId UUID of the tag to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor registeredUser
   * @x-autobe-specification Query the discussion_board_tags table using the provided tagId.
   * Validate the UUID format of tagId path parameter.
   * Return all relevant fields of the tag record including id, name, created_at, updated_at, and deleted_at if present.
   * Handle cases where the tag does not exist by returning a 404 error.
   * No request body required.
   * Operation does not require authentication or authorization.
   * Implement efficient database lookup using primary key index for id.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":tagId")
  public async at(
    @RegistereduserAuth()
    registeredUser: RegistereduserPayload,
    @TypedParam("tagId")
    tagId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardTag> {
    try {
      return await getDiscussionBoardRegisteredUserTagsTagId({
        registeredUser,
        tagId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
