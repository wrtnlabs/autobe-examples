import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminDiscussionBoardMembersDiscussionBoardMemberIdSessions } from "../../../../../providers/patchDiscussionBoardAdminDiscussionBoardMembersDiscussionBoardMemberIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminDiscussionBoardMembersDiscussionBoardMemberIdSessionsSessionId } from "../../../../../providers/getDiscussionBoardAdminDiscussionBoardMembersDiscussionBoardMemberIdSessionsSessionId";
import { deleteDiscussionBoardAdminDiscussionBoardMembersDiscussionBoardMemberIdSessionsSessionId } from "../../../../../providers/deleteDiscussionBoardAdminDiscussionBoardMembersDiscussionBoardMemberIdSessionsSessionId";

import { IPageIDiscussionBoardMemberSessions } from "../../../../../api/structures/IPageIDiscussionBoardMemberSessions";
import { IDiscussionBoardMemberSessions } from "../../../../../api/structures/IDiscussionBoardMemberSessions";

@Controller(
  "/discussionBoard/admin/discussionBoardMembers/:discussionBoardMemberId/sessions",
)
export class DiscussionboardAdminDiscussionboardmembersSessionsController {
  /**
   * Retrieve a filtered and paginated list of active session records for a
   * specific discussion board member.
   *
   * This operation allows administrative users to query active sessions by
   * member ID to monitor login states, audit authentication activities, and
   * manage sessions effectively. Filtering, pagination, and sorting
   * capabilities enhance session management usability.
   *
   * Security considerations include restricting access to authorized actors
   * only to protect sensitive session identifiers and connection details. The
   * member ID parameter guarantees that sessions returned are scoped to the
   * specified member only.
   *
   * This operation directly queries the discussion_board_member_sessions table
   * as defined in the Prisma schema, ensuring accurate retrieval of live and
   * expired sessions linked to the member.
   *
   * Related operations include retrieving individual session details via GET
   * /discussionBoardMembers/{discussionBoardMemberId}/sessions/{sessionId} and
   * administrative session management actions.
   *
   * @param connection
   * @param discussionBoardMemberId Unique identifier of the discussion board
   *   member whose sessions are being queried
   * @param body Search criteria and pagination parameters for filtering
   *   discussion board member sessions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("discussionBoardMemberId")
    discussionBoardMemberId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardMemberSessions.IRequest,
  ): Promise<IPageIDiscussionBoardMemberSessions.ISummary> {
    try {
      return await patchDiscussionBoardAdminDiscussionBoardMembersDiscussionBoardMemberIdSessions(
        {
          admin,
          discussionBoardMemberId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific session belonging to a
   * discussion board member.
   *
   * This operation allows authorized administrative actors to inspect
   * individual session records, viewing IP address, connection URLs, referrer
   * data, and session timing including creation and expiry.
   *
   * Security is paramount; access is restricted to authorized roles only,
   * ensuring sensitive session details remain confidential. The path parameters
   * discussionBoardMemberId and sessionId ensure the session is uniquely
   * identified within the member's scope.
   *
   * This operation leverages the discussion_board_member_sessions Prisma table
   * schema, guaranteeing precise data retrieval consistent with the underlying
   * database structure.
   *
   * Related operations include listing multiple sessions via PATCH
   * /discussionBoardMembers/{discussionBoardMemberId}/sessions for overview and
   * monitoring.
   *
   * @param connection
   * @param discussionBoardMemberId Unique identifier of the discussion board
   *   member who owns the session
   * @param sessionId Unique identifier of the target session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("discussionBoardMemberId")
    discussionBoardMemberId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardMemberSessions> {
    try {
      return await getDiscussionBoardAdminDiscussionBoardMembersDiscussionBoardMemberIdSessionsSessionId(
        {
          admin,
          discussionBoardMemberId,
          sessionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation permanently deletes a specific session associated with a
   * registered discussion board member.
   *
   * The session is uniquely identified by a composite of the member's ID and
   * session ID path parameters. Once deleted, the session is no longer valid
   * and the member must reauthenticate to regain access.
   *
   * Security: Only the system or authorized administrators are allowed to erase
   * member sessions. This operation requires appropriate authentication and
   * authorization checks.
   *
   * This API directly manipulates the discussion_board_member_sessions table
   * and performs a hard delete of the session record.
   *
   * Related operations: List sessions (GET
   * /discussionBoardMembers/{discussionBoardMemberId}/sessions), create session
   * (handled internally).
   *
   * @param connection
   * @param discussionBoardMemberId Unique identifier of the discussion board
   *   member
   * @param sessionId Unique identifier of the member's session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("discussionBoardMemberId")
    discussionBoardMemberId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminDiscussionBoardMembersDiscussionBoardMemberIdSessionsSessionId(
        {
          admin,
          discussionBoardMemberId,
          sessionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
