import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminDiscussionBoardMembers } from "../../../../providers/patchDiscussionBoardAdminDiscussionBoardMembers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminDiscussionBoardMembersDiscussionBoardMemberId } from "../../../../providers/getDiscussionBoardAdminDiscussionBoardMembersDiscussionBoardMemberId";

import { IPageIDiscussionBoardDiscussionBoardMember } from "../../../../api/structures/IPageIDiscussionBoardDiscussionBoardMember";
import { IDiscussionBoardDiscussionBoardMember } from "../../../../api/structures/IDiscussionBoardDiscussionBoardMember";

@Controller("/discussionBoard/admin/discussionBoardMembers")
export class DiscussionboardAdminDiscussionboardmembersController {
  /**
   * Retrieve a paginated list of discussion board members filtered by provided
   * search parameters.
   *
   * Supports advanced filtering such as username, registration date ranges,
   * status, and roles. The response includes summary information optimized for
   * display rather than full member details.
   *
   * Security: Access is restricted to authorized roles such as administrators
   * and moderators to protect personal member data.
   *
   * Related operations include member detail retrieval and member management
   * endpoints.
   *
   * @param connection
   * @param body Search criteria and pagination options for discussion board
   *   members
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardDiscussionBoardMember.IRequest,
  ): Promise<IPageIDiscussionBoardDiscussionBoardMember.ISummary> {
    try {
      return await patchDiscussionBoardAdminDiscussionBoardMembers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a registered discussion board member by their unique
   * identifier.
   *
   * This operation returns all accessible member properties except sensitive
   * fields like password_hash.
   *
   * Security considerations: Access is typically restricted to authenticated
   * users or administrators. Proper authorization checks must be enforced to
   * prevent unauthorized data exposure.
   *
   * This operation corresponds to the GET
   * /discussionBoard/admin/discussionBoardMembers/{discussionBoardMemberId}
   * endpoint and maps directly to the discussion_board_member table. It
   * provides the foundational read access for member information across the
   * discussion board system.
   *
   * @param connection
   * @param discussionBoardMemberId Unique identifier (UUID) of the discussion
   *   board member to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":discussionBoardMemberId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("discussionBoardMemberId")
    discussionBoardMemberId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardDiscussionBoardMember> {
    try {
      return await getDiscussionBoardAdminDiscussionBoardMembersDiscussionBoardMemberId(
        {
          admin,
          discussionBoardMemberId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
