import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardDiscussionBoardGuests } from "../../../providers/postDiscussionBoardDiscussionBoardGuests";
import { putDiscussionBoardDiscussionBoardGuestsDiscussionBoardGuestId } from "../../../providers/putDiscussionBoardDiscussionBoardGuestsDiscussionBoardGuestId";

import { IDiscussionBoardGuest } from "../../../api/structures/IDiscussionBoardGuest";

@Controller("/discussionBoard/discussionBoardGuests")
export class DiscussionboardDiscussionboardguestsController {
  /**
   * Create a new discussion board guest user in the system.
   *
   * This operation allows the creation of an unauthenticated guest visitor with
   * a display nickname. Guests are intended for read-only access and minimal
   * interaction. The system manages created_at and updated_at timestamps
   * automatically.
   *
   * This endpoint is designed for public access with no authentication
   * required. It provides a way to uniquely identify guest interactions while
   * ensuring privacy.
   *
   * The operation corresponds to the discussion_board_guest Prisma table, which
   * has fields for nickname and timestamps.
   *
   * Related operations include updating guest info (PUT
   * /discussionBoardGuests/{discussionBoardGuestId}) and retrieving guest
   * details if needed.
   *
   * @param connection
   * @param body Guest user display nickname
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: IDiscussionBoardGuest.ICreate,
  ): Promise<IDiscussionBoardGuest> {
    try {
      return await postDiscussionBoardDiscussionBoardGuests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the information of an existing discussion board guest user
   * identified by their unique ID.
   *
   * This operation enables modification of the guest's display nickname. The
   * updated_at timestamp is automatically set to the current time upon update.
   *
   * Soft deletion is indicated by the deleted_at field, but actual deletion
   * operations are handled separately.
   *
   * Authorization is not required as these are guest users, but usage should
   * consider that guests have minimal privileges and no authentication.
   *
   * This operation aligns with the discussion_board_guest table in the Prisma
   * schema.
   *
   * Related operations include creation of new guests (POST
   * /discussionBoardGuests) and potential retrieval of guest info.
   *
   * @param connection
   * @param discussionBoardGuestId Unique identifier of the target discussion
   *   board guest user
   * @param body Updated guest user display nickname
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":discussionBoardGuestId")
  public async update(
    @TypedParam("discussionBoardGuestId")
    discussionBoardGuestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardGuest.IUpdate,
  ): Promise<IDiscussionBoardGuest> {
    try {
      return await putDiscussionBoardDiscussionBoardGuestsDiscussionBoardGuestId(
        {
          discussionBoardGuestId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
