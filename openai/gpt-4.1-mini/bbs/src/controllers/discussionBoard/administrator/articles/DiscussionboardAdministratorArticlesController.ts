import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../api/structures/IPageIDiscussionBoardArticle";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { deleteDiscussionBoardAdministratorArticlesArticleId } from "../../../../providers/deleteDiscussionBoardAdministratorArticlesArticleId";
import { getDiscussionBoardAdministratorArticlesArticleId } from "../../../../providers/getDiscussionBoardAdministratorArticlesArticleId";
import { patchDiscussionBoardAdministratorArticles } from "../../../../providers/patchDiscussionBoardAdministratorArticles";

@Controller("/discussionBoard/administrator/articles")
export class DiscussionboardAdministratorArticlesController {
  /**
   * Retrieve a paginated list of articles in the discussion board system with detailed filtering, sorting and search capabilities.
   *
   * This operation allows clients to specify search criteria including article title keywords, content keywords, section ID, tag filters, and sorting preferences (newest first or oldest first).
   *
   * Articles are returned as summaries including title, author display name, tags, comment count, and posted timestamp.
   *
   * Only non-deleted articles are included. Pagination parameters support efficient response sizes. This enables dynamic browsing and search of discussion board articles.
   *
   * Security: This operation is accessible to all actors including guest users with no restrictions.
   *
   * Related operations:
   * - GET /articles/{articleId} to retrieve full article details
   * - PATCH /articles for search and list with pagination
   * - POST /articles to create articles (registered users only)
   * - PUT /articles/{articleId} to update articles (authors or admins)
   * - DELETE /articles/{articleId} for deletions (authors or admins)
   *
   * @param connection
   * @param body Search criteria and pagination parameters for listing articles
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query discussion_board_articles joined with discussion_board_registered_users (author) and discussion_board_article_tags (tags). Support search by title and content keywords with trigram indexes. Filter by section_id and multiple selected tags. Sort by created_at ascending or descending based on sorting parameter. Use cursor-based pagination with limit and cursor parameters. Return article summary data including title, author display name, comment count, and post time. Implement security checks to allow only viewing non-deleted articles. Return paginated IPageIDiscussionBoardArticle.ISummary list.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardAdministratorArticles({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a detailed view of a single discussion board article.
   *
   * This operation returns the full details of the specified article including its title, content, author information, attached files and images, associated tags, and timestamps for creation and last update.
   *
   * The response aggregates related entities: author as a registered user, article files, article images, and tags linked via junction tables. It excludes soft-deleted records, ensuring only active content is returned.
   *
   * This API operation is essential for rendering the article details page where users can fully read the article, download attachments, and view images.
   *
   * No request body is required as the requested article identifier is provided by the path parameter.
   *
   * Authorization: Open for all users including guests and registered members.
   *
   * References discussion_board_articles and related schemas for comprehensive data completeness.
   *
   * @param connection
   * @param articleId The UUID of the target article.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Implementation consists of querying the discussion_board_articles table by primary key articleId. Filter out records with non-null deleted_at to exclude deleted articles.
   *
   * Include joins to discussion_board_registered_users table to retrieve author details by registered_user_id.
   *
   * Cascade query includes article files from discussion_board_article_files ordered by display_order ascending.
   * Include article images from discussion_board_article_images ordered by display_order ascending.
   * Include article tags by joining discussion_board_article_tag_mappings and discussion_board_tags to collect tag names.
   *
   * Return a detailed IDiscussionBoardArticles DTO object representing the full article data and related collections.
   *
   * Handle errors for non-existent articleId by returning HTTP 404 Not Found.
   *
   * Operation does not require request body.
   *
   * No path parameter transformations or validations beyond standard UUID checks.
   *
   * This operation is idempotent and safe, suitable for GET.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await getDiscussionBoardAdministratorArticlesArticleId({
        administrator,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific article identified by its unique UUID.
   *
   * This operation allows the author of the article or an administrator to permanently remove the article from the discussion board. All comments and related attachments of the article will also be removed as part of cascading delete operations defined in the database schema.
   *
   * Authorization is required: only the article's author or users with administrative privileges may perform this action.
   *
   * Path Parameter:
   * - articleId: The UUID of the article to delete, uniquely identifying the record in the discussion_board_articles table.
   *
   * Behavior:
   * - The article and all associated data (comments, files, images, tag mappings) are permanently deleted.
   * - No response body content is returned if the operation succeeds.
   * - Appropriate error responses are expected if the article does not exist or authorization fails.
   *
   * This endpoint is critical for content lifecycle management and ensures that users and administrators can manage content responsibly and efficiently.
   *
   * @param connection
   * @param articleId Unique identifier (UUID) of the article to delete.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Perform authorization checks to confirm the requester is either the article author or has administrative privileges. Validate the UUID format of 'articleId'. Execute a database transaction to delete the article from discussion_board_articles where id matches 'articleId'. This deletion cascades to all related comments, files, images, and tag mappings as per relational constraints. Return proper HTTP status codes: 204 No Content on success, 404 Not Found if no article matches, 403 Forbidden if unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":articleId")
  public async erase(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdministratorArticlesArticleId({
        administrator,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
