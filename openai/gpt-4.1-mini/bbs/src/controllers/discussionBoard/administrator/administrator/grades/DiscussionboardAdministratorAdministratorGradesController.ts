import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardAdministratorGrade } from "../../../../../api/structures/IDiscussionBoardAdministratorGrade";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getDiscussionBoardAdministratorAdministratorGradesGradeId } from "../../../../../providers/getDiscussionBoardAdministratorAdministratorGradesGradeId";
import { patchDiscussionBoardAdministratorAdministratorGrades } from "../../../../../providers/patchDiscussionBoardAdministratorAdministratorGrades";

@Controller("/discussionBoard/administrator/administrator/grades")
export class DiscussionboardAdministratorAdministratorGradesController {
  /**
   * This API operation allows super administrators to update the grades of administrators within the discussion board system. Administrator grades consist of two types: regular administrators and super administrators.
   *
   * Security considerations mandate only authenticated super administrators have permission to perform grade updates. The system enforces strict business rules prohibiting a super administrator from demoting themselves to maintain administrative integrity.
   *
   * The operation targets the underlying database entities discussion_board_administrators and discussion_board_administrator_grades. Grade changes are recorded and managed in the discussion_board_administrator_grades table, reflecting administrator roles and permissions.
   *
   * Validation logic ensures the target administrator exists and only valid grade transitions occur. The API responds with the updated administrator grade record upon successful completion.
   *
   * This operation works in conjunction with related endpoints managing administrator requests and session authentication, providing a consistent administrative control interface.
   *
   * Errors including unauthorized access, invalid grade change attempts, or non-existent target administrators are handled gracefully with descriptive HTTP status codes.
   *
   * Usage of HTTP PATCH method aligns with operation semantics, representing partial resource updates focused on administrator grade changes.
   *
   *
   * @param connection
   * @param body Request body containing administrator grade update details.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Implement service logic to accept requests from authenticated super administrator users. Validate authorization to ensure only super administrators may invoke.
   *
   * Parse the request body containing target administrator identifier and desired grade update. Check that the target administrator exists in the system.
   *
   * Enforce business rules:
   * - Allow promotion from regular to super administrator.
   * - Allow demotion from super to regular administrator, but deny if the actor is demoting themselves.
   *
   * Perform database transaction updating the administrator's grade in the discussion_board_administrator_grades or related table.
   *
   * Return the updated administrator grade record reflecting the new grade.
   *
   * Handle errors such as unauthorized access, target not found, or invalid grade transitions with appropriate HTTP status codes and messages.
   *
   * Ensure atomicity and consistency during the grade update operation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updateAdministratorGrades(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IDiscussionBoardAdministratorGrade.IUpdate,
  ): Promise<IDiscussionBoardAdministratorGrade> {
    try {
      return await patchDiscussionBoardAdministratorAdministratorGrades({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific administrator grade by its unique identifier.
   *
   * This API operation enables clients to fetch the properties of an administrator grade, including its unique name, description of permissions, and the permission level.
   *
   * Only authorized actors should have access to this API to prevent unauthorized exposure of admin grade definitions.
   *
   * The underlying database entity is discussion_board_administrator_grades, which stores grade details. This endpoint enables viewing role distinctions for administrators to enable role-based access control.
   *
   * All fields from the database table are included except the soft deletion timestamp, which should not be exposed.
   *
   * This endpoint complements other admin management APIs such as promoting or demoting administrators, submitting admin requests, and managing bans.
   *
   * No side-effects occur from this read operation. Errors include not found if the given gradeId does not exist.
   *
   * @param connection
   * @param gradeId Unique identifier of the administrator grade
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query discussion_board_administrator_grades table by primary key id = gradeId. Exclude records with deleted_at set (soft deleted). Return all fields except deleted_at.
   *
   * Authorize access to administrator roles only.
   *
   * Handle errors for non-existent gradeId by returning 404 Not Found.
   *
   * No request body is required since this is a GET operation.
   *
   * Use Prisma's findUniqueOrThrow with filtering on deleted_at null for implementation.
   *
   * Return full administrator grade entity as response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":gradeId")
  public async atAdministratorGrade(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("gradeId")
    gradeId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAdministratorGrade> {
    try {
      return await getDiscussionBoardAdministratorAdministratorGradesGradeId({
        administrator,
        gradeId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
