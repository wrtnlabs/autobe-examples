import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardComment } from "../../../../api/structures/IDiscussionBoardComment";
import { IPageIDiscussionBoardComment } from "../../../../api/structures/IPageIDiscussionBoardComment";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { deleteDiscussionBoardAdministratorCommentsCommentId } from "../../../../providers/deleteDiscussionBoardAdministratorCommentsCommentId";
import { getDiscussionBoardAdministratorCommentsCommentId } from "../../../../providers/getDiscussionBoardAdministratorCommentsCommentId";
import { patchDiscussionBoardAdministratorComments } from "../../../../providers/patchDiscussionBoardAdministratorComments";

@Controller("/discussionBoard/administrator/comments")
export class DiscussionboardAdministratorCommentsController {
  /**
   * Retrieve a paginated list of comments posted on articles within the discussion board.
   *
   * This operation enables users to search comments by content, filter by author or article ID, and sort by posting date.
   *
   * Accessible to registered users and above. The operation supports pagination to efficiently browse large comment volumes.
   *
   * The underlying discussion_board_comments table records each comment's content, author, article it belongs to, timestamps, and soft deletion status. This endpoint excludes soft-deleted comments from results.
   *
   * Related operations include GET /comments/{id} (retrieve single comment), POST /comments (create new comment), PUT /comments/{id} (update comment), and DELETE /comments/{id} (delete comment).
   *
   * This operation plays a central role in enabling comment browsing and moderation features.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for comment list retrieval
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query discussion_board_comments table filtering by content keywords, author ID, article ID, and created_at date range.
   * Exclude comments with non-null deleted_at (soft-deleted).
   * Support pagination with cursor or offset along with limit.
   * Sort results by created_at ascending or descending based on request.
   * Return paginated comment summaries including comment ID, content snippet, author display name, article ID, and timestamps.
   * Ensure query uses appropriate indexes on author, article, and content columns.
   * Manage access control to allow only authenticated users to query comments.
   *
   * Integrate related data by joining with discussion_board_registered_users for author information and discussion_board_articles for article context if requested.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IDiscussionBoardComment.IRequest,
  ): Promise<IPageIDiscussionBoardComment.ISummary> {
    try {
      return await patchDiscussionBoardAdministratorComments({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific comment by its unique identifier.
   *
   * This API operation fetches detailed information about the comment, including its content, the author details, creation and update timestamps.
   *
   * The comment entity corresponds directly to the discussion_board_comments table in the database which stores user-written comments linked to articles. The entity includes fields for comment content, author reference, and timestamps for creation and update.
   *
   * Security: This operation allows public read access (including guests) to comment data since comments are publicly visible on articles.
   *
   * The response includes all necessary fields to display the comment fully, supporting article views and user profile displays.
   *
   * No input modification is allowed; this endpoint is read-only.
   *
   * Related operations:
   * - To list comments on an article: GET /articles/{articleId}/comments
   * - To create a comment: POST /comments
   * - To update a comment: PUT /comments/{commentId}
   * - To delete a comment: DELETE /comments/{commentId}
   *
   * @param connection
   * @param commentId UUID of the target comment
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Fetch the comment record by ID from the discussion_board_comments table.
   * Ensure the comment is not soft deleted (deleted_at is null).
   * Join with discussion_board_registered_users table to retrieve author details.
   * Return all fields required to fully represent the comment entity as per the IDiscussionBoardComment schema.
   * No request body, no transaction needed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":commentId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await getDiscussionBoardAdministratorCommentsCommentId({
        administrator,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Deletes a comment identified by the unique commentId from the discussion board.
   *
   * This operation allows authorized users, including the comment author and administrators, to remove comments. Upon successful deletion, the comment record is permanently removed from the database.
   *
   * Security considerations ensure only authorized users can delete comments, preventing unauthorized data loss.
   *
   * This operation manipulates the `discussion_board_comments` table directly, referencing its primary key column `id` represented by the path parameter `commentId`.
   *
   * Error handling includes 404 Not Found for non-existent comments and 403 Forbidden for unauthorized attempts.
   *
   * Related operations include GET /discussionBoard/administrator/comments/{commentId} for retrieving comment details and PATCH /discussionBoard/administrator/comments for listing and searching comments.
   *
   * This operation supports moderation capabilities to ensure content quality and compliance with community standards.
   *
   * @param connection
   * @param commentId The unique identifier (UUID) of the comment to delete.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification To implement this DELETE /comments/{commentId} operation, validate the commentId path parameter as UUID.
   * Verify that the requesting user is authorized (either comment author or administrator).
   * Check if the comment exists. If not, return 404.
   * If authorized, perform a permanent deletion of the comment record from the discussion_board_comments table.
   * Ensure relational integrity by cascading deletes as defined in database relations.
   * Handle concurrency and transactional consistency.
   * Log the deletion event for audit purposes.
   * Return a 204 No Content response on success.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdministratorCommentsCommentId({
        administrator,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
