import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../api/structures/IPageIDiscussionBoardArticle";
import { SuperadministratorAuth } from "../../../../decorators/SuperadministratorAuth";
import { SuperadministratorPayload } from "../../../../decorators/payload/SuperadministratorPayload";
import { getDiscussionBoardSuperAdministratorArticlesArticleId } from "../../../../providers/getDiscussionBoardSuperAdministratorArticlesArticleId";
import { patchDiscussionBoardSuperAdministratorArticles } from "../../../../providers/patchDiscussionBoardSuperAdministratorArticles";

@Controller("/discussionBoard/superAdministrator/articles")
export class DiscussionboardSuperadministratorArticlesController {
  /**
   * Retrieve a paginated and filtered list of articles from the discussion board system.
   *
   * This endpoint enables users to search articles by title and content keywords, filter by section and tags, and sort results by posting time either newest first or oldest first.
   *
   * The response provides article summaries including title, author information, tags, comment counts, and posted timestamp to support quick browsing.
   *
   * Authorization is not required as articles are publicly accessible.
   *
   * This operation queries the 'discussion_board_articles' table joined with 'discussion_board_article_tags' and related tables to apply tag filters.
   *
   * Multiple indexes optimize text search on title and content fields.
   *
   * The pagination supports typical cursor or offset based paging techniques with page size limits.
   *
   * Related operations:
   * - GET /sections/{sectionId}/articles for section-limited paged listing
   * - GET /articles/{articleId} for detailed article view
   *
   * Error handling includes validation for pagination parameters and safe filtering inputs.
   *
   * @param connection
   * @param body Search and filter criteria for articles with pagination
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Implement a PATCH /articles endpoint that accepts a request body matching IDiscussionBoardArticle.IRequest including filters for title keywords, content keywords, sectionId, tags (multiple), pagination parameters (page number, page size), and sorting order.
   *
   * Perform database queries on 'discussion_board_articles' with joins to 'discussion_board_article_tags' to filter by tags if provided.
   *
   * Use index-supported full-text search for filtering on title and content using trigram indexes.
   *
   * Return paginated results using the IPageIDiscussionBoardArticle.ISummary schema with pagination metadata.
   *
   * No path parameters.
   *
   * This operation is publicly accessible without authentication.
   *
   * Ensure robust input validation on pagination and filtering to prevent injection and ensure performant queries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SuperadministratorAuth()
    superAdministrator: SuperadministratorPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardSuperAdministratorArticles({
        superAdministrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the full details of an article including title, content, attachments, images, tags, author information, and posting timestamps.
   *
   * This endpoint supports public viewing of articles by any user, including guests and registered users.
   *
   * Access to this operation does not require authentication.
   *
   * The article entity is represented by the IDiscussionBoardArticle type, which includes relationships to attached files, images, tags, and the author user profile.
   *
   * This operation complements the article list retrieval and article creation endpoints.
   *
   * Errors such as non-existent article IDs are handled with appropriate HTTP response codes.
   *
   * The articleId parameter corresponds to the UUID of the target article in the discussion_board_articles database table.
   *
   * Specification:
   * - Query the discussion_board_articles table by articleId UUID.
   * - Fetch related attached files and images from discussion_board_article_files and discussion_board_article_images.
   * - Retrieve tags linked via discussion_board_article_tag_mappings and discussion_board_article_tags.
   * - Include author details from discussion_board_registered_users.
   * - Return a shaped response conforming to IDiscussionBoardArticle schema.
   *
   * @param connection
   * @param articleId UUID of the target article
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Service Layer Logic:
   * - Validate articleId path parameter as a UUID.
   * - Query database for the article record by primary key articleId.
   * - If not found, return 404 Not Found.
   * - Join related tables: article files, images, tags, and author profile.
   * - Assemble all data into a single response DTO conforming to IDiscussionBoardArticle.
   *
   * Database Queries:
   * - SELECT * FROM discussion_board_articles WHERE id = :articleId;
   * - SELECT * FROM discussion_board_article_files WHERE article_id = :articleId ORDER BY display_order ASC;
   * - SELECT * FROM discussion_board_article_images WHERE article_id = :articleId ORDER BY display_order ASC;
   * - Join discussion_board_article_tag_mappings and discussion_board_article_tags to get tags.
   * - JOIN discussion_board_registered_users ON discussion_board_articles.author_id = discussion_board_registered_users.id
   *
   * Business Rules:
   * - Only existing articles can be retrieved.
   * - No authentication required for read access.
   * - Attachments and images are returned with their metadata.
   *
   * Edge Cases and Error Handling:
   * - 404 if article does not exist.
   * - 400 if articleId format is invalid.
   *
   * Related APIs:
   * - GET /sections/{sectionId}/articles for article lists.
   * - POST /articles for article creation.
   * - PATCH /articles/{articleId} for article editing.
   * - DELETE /articles/{articleId} for article deletion.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @SuperadministratorAuth()
    superAdministrator: SuperadministratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await getDiscussionBoardSuperAdministratorArticlesArticleId({
        superAdministrator,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
