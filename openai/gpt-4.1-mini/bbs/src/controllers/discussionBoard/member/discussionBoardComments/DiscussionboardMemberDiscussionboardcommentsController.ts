import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberDiscussionBoardComments } from "../../../../providers/postDiscussionBoardMemberDiscussionBoardComments";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { patchDiscussionBoardMemberDiscussionBoardComments } from "../../../../providers/patchDiscussionBoardMemberDiscussionBoardComments";
import { putDiscussionBoardMemberDiscussionBoardCommentsId } from "../../../../providers/putDiscussionBoardMemberDiscussionBoardCommentsId";
import { deleteDiscussionBoardMemberDiscussionBoardCommentsId } from "../../../../providers/deleteDiscussionBoardMemberDiscussionBoardCommentsId";

import { IDiscussionBoardComment } from "../../../../api/structures/IDiscussionBoardComment";
import { IPageIDiscussionBoardComment } from "../../../../api/structures/IPageIDiscussionBoardComment";

@Controller("/discussionBoard/member/discussionBoardComments")
export class DiscussionboardMemberDiscussionboardcommentsController {
  /**
   * Create a new discussion board comment to an article.
   *
   * This operation allows authenticated users to post textual comments linked
   * to specific articles on the discussion board. The request body must include
   * the comment content and references to the article ID and author member ID.
   *
   * Security: Authentication is required to ensure the creating member is
   * valid. The system validates that the article ID exists and that the member
   * has the right to post comments.
   *
   * The response returns the created comment with all its properties including
   * timestamps.
   *
   * Related operations include retrieving comment details (GET
   * /discussionBoardComments/{id}) and managing comments.
   *
   * @param connection
   * @param body Request body for creating a discussion board comment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardComment.ICreate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await postDiscussionBoardMemberDiscussionBoardComments({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve discussion board comments with filters and pagination.
   *
   * Retrieve a paginated list of discussion board comments that match the
   * specified search criteria.
   *
   * This operation supports filtering by article, author, content keywords,
   * creation dates, and supports sorting and pagination for efficient
   * browsing.
   *
   * Only authorized users may access this endpoint. Returned results include
   * summary view information optimized for listing.
   *
   * Related operations: Use POST /discussionBoardComments to create comments,
   * GET /discussionBoardComments/{id} to retrieve comment details, and
   * PUT/DELETE operations for updates and removal.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for discussion board
   *   comments filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardComment.IRequest,
  ): Promise<IPageIDiscussionBoardComment.ISummary> {
    try {
      return await patchDiscussionBoardMemberDiscussionBoardComments({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a user comment on the discussion board.
   *
   * Update the text content of an existing discussion board comment.
   *
   * This operation allows the author of the comment to change the content of
   * their comment in the discussion board system. The comment is identified
   * uniquely by its ID.
   *
   * Security is enforced such that only the comment's author or authorized
   * members can perform this update.
   *
   * The discussion_board_comments table manages comments with fields including
   * content, timestamps for creation, update, and optional soft deletion
   * timestamps. This operation does not delete or restore comments, only
   * updates existing content.
   *
   * Validation ensures the new content meets any length or format requirements
   * specified in the business rules.
   *
   * Related operations include creating new comments (POST
   * /articles/{articleId}/comments), deleting comments (DELETE
   * /discussionBoardComments/{id}), and retrieving comments.
   *
   * @param connection
   * @param id Unique identifier of the target discussion board comment
   * @param body New content data for the discussion board comment update
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardMemberDiscussionBoardCommentsId({
        member,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a user comment from the discussion board.
   *
   * Permanently remove a discussion board comment identified by its unique ID.
   *
   * This hard delete operation removes the record from the
   * discussion_board_comments table in the Prisma schema. It does not perform
   * soft deletion or mark the comment as inactive.
   *
   * Security is enforced so that only authorized members or administrators can
   * delete comments.
   *
   * There is no request body and no response content upon successful deletion.
   *
   * Related operations are create, update, and list comments.
   *
   * @param connection
   * @param id Unique identifier of the target discussion board comment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberDiscussionBoardCommentsId({
        member,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
