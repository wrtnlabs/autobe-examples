import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberDiscussionBoardArticles } from "../../../../providers/postDiscussionBoardMemberDiscussionBoardArticles";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { patchDiscussionBoardMemberDiscussionBoardArticles } from "../../../../providers/patchDiscussionBoardMemberDiscussionBoardArticles";
import { putDiscussionBoardMemberDiscussionBoardArticlesId } from "../../../../providers/putDiscussionBoardMemberDiscussionBoardArticlesId";
import { deleteDiscussionBoardMemberDiscussionBoardArticlesId } from "../../../../providers/deleteDiscussionBoardMemberDiscussionBoardArticlesId";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticles } from "../../../../api/structures/IPageIDiscussionBoardArticles";
import { IDiscussionBoardArticles } from "../../../../api/structures/IDiscussionBoardArticles";

@Controller("/discussionBoard/member/discussionBoardArticles")
export class DiscussionboardMemberDiscussionboardarticlesController {
  /**
   * Create a new discussion board article with title and content.
   *
   * Only authenticated members can create articles. The author is assigned
   * automatically based on the current user session.
   *
   * Attachments are uploaded separately and linked to the article after
   * creation.
   *
   * Validation occurs against the discussion_board_articles schema to ensure
   * data consistency.
   *
   * Upon success, the full details of the created article are returned.
   *
   * Related operations include getting article details (GET
   * /discussionBoardArticles/{id}) and updating or deleting articles.
   *
   * @param connection
   * @param body Creation request for a discussion board article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.ICreate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await postDiscussionBoardMemberDiscussionBoardArticles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered, paginated list of discussion board articles from the
   * system.
   *
   * This operation supports complex search and filtering by article title,
   * content keywords, categories, and author identification.
   *
   * Pagination parameters allow clients to specify page size and page number to
   * efficiently browse articles.
   *
   * Security considerations include authorization checks to ensure members can
   * only view articles they are allowed to see. Filtering and sorting support
   * enable refined and efficient data retrieval.
   *
   * This endpoint returns article summaries optimized for list views.
   *
   * Related operations include creating new articles, getting detailed
   * information, and managing article revisions.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for article filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardArticles.IRequest,
  ): Promise<IPageIDiscussionBoardArticles.ISummary> {
    try {
      return await patchDiscussionBoardMemberDiscussionBoardArticles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing discussion board article identified by its unique ID.
   *
   * This API endpoint allows authorized users to modify the title and content
   * of an article.
   *
   * Security: This operation enforces permissions, allowing only the original
   * article author or administrative roles to update it.
   *
   * The article's timestamps are updated accordingly.
   *
   * Related endpoints include article retrieval and deletion to manage full
   * lifecycle.
   *
   * @param connection
   * @param id Unique identifier of the discussion board article to update
   * @param body Article update data containing title and content
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticle.IUpdate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await putDiscussionBoardMemberDiscussionBoardArticlesId({
        member,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a discussion board article permanently by its unique ID.
   *
   * Only authorized users such as the article's author or admin roles can
   * perform this action.
   *
   * This deletion is irreversible and removes all related content from the
   * database.
   *
   * The operation does not require a request body and returns no content upon
   * success.
   *
   * @param connection
   * @param id Unique identifier of the discussion board article to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberDiscussionBoardArticlesId({
        member,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
