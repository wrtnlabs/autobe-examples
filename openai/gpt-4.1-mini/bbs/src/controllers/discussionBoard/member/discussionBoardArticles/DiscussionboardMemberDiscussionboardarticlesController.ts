import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberDiscussionBoardArticles } from "../../../../providers/postDiscussionBoardMemberDiscussionBoardArticles";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putDiscussionBoardMemberDiscussionBoardArticlesArticleId } from "../../../../providers/putDiscussionBoardMemberDiscussionBoardArticlesArticleId";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/member/discussionBoardArticles")
export class DiscussionboardMemberDiscussionboardarticlesController {
  /**
   * Create a new article with optional multiple attachments in the discussion
   * board.
   *
   * This operation allows authenticated members to create new articles on the
   * economic and political discussion board. Each article must include a title
   * and markdown content, following schema constraints such as title length
   * limited to 200 characters and content stored as markdown text.
   *
   * The operation supports attaching multiple files or images to the article,
   * each attachment including filename, file type, and file URL. Attachments
   * are securely associated to the created article. Uploads are validated
   * against business rules, such as maximum allowed size and supported
   * formats.
   *
   * Security measures restrict this operation to authenticated members only,
   * ensuring guests cannot create content. The system applies all validation
   * rules and error handling as per business requirements to ensure data
   * integrity and user permissions are respected.
   *
   * @param connection
   * @param body Creation information for a discussion board article including
   *   optional attachments
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.ICreate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await postDiscussionBoardMemberDiscussionBoardArticles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing article and its attachments by article ID.
   *
   * This operation enables authenticated members to update their own articles
   * in the economic and political discussion board. The update can modify the
   * article title and markdown content subject to length and format
   * validations.
   *
   * The operation also supports updating attachments, including adding new
   * files or removing existing ones, while maintaining secure links between
   * articles and attachments.
   *
   * Authorization checks ensure that only the article owner or administrators
   * can perform update operations, preventing unauthorized edits. Validation
   * rules and business logic are enforced thoroughly to maintain data
   * integrity.
   *
   * This endpoint expects the target article to be specified by its unique UUID
   * path parameter articleId, which identifies the article to update.
   *
   * @param connection
   * @param articleId Unique identifier of the target discussion board article
   * @param body Update information for the discussion board article including
   *   optional attachment changes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":articleId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticle.IUpdate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await putDiscussionBoardMemberDiscussionBoardArticlesArticleId({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
