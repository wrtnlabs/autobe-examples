import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { AdminAuth } from "../../../decorators/AdminAuth";
import { AdminPayload } from "../../../decorators/payload/AdminPayload";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { IEconPolDiscussionBoardAdmin } from "../../../api/structures/IEconPolDiscussionBoardAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Administrator registration endpoint for econPolDiscussionBoard admins.
   *
   * This endpoint provides the functionality to register a new administrator
   * account within the econPolDiscussionBoard system. It securely accepts admin
   * credentials such as username and password and stores them in the
   * corresponding database table with password hashing. The operation issues
   * JWT access and refresh tokens upon successful registration. The admin actor
   * is authorized for system-level management tasks including content
   * moderation and user account control. Security measures include password
   * hashing and validation policies enforced at the provider level. Related
   * operations include /auth/admin/login for authentication and
   * /auth/admin/refresh for token renewal.
   *
   * @param connection
   * @param body Admin registration request body including necessary credentials
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEconPolDiscussionBoardAdmin.IJoin,
  ): Promise<IEconPolDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Administrator login endpoint for econPolDiscussionBoard admins.
   *
   * This endpoint handles administrator login and authentication for the
   * econPolDiscussionBoard system. It verifies provided credentials against
   * database stored hashes in the admin table and issues JWT tokens for access.
   * The operation supports secure authentication workflows and session
   * management. Security policies and token expiration conform to system
   * standards. This complements related operations such as join (registration)
   * and refresh (token renewal).
   *
   * @param connection
   * @param body Admin login request body with username and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEconPolDiscussionBoardAdmin.ILogin,
  ): Promise<IEconPolDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Administrator token refresh endpoint for econPolDiscussionBoard admins.
   *
   * This endpoint allows administrators to refresh their JWT access tokens in
   * the econPolDiscussionBoard system securely. It requires the submission of a
   * valid refresh token which is validated against the admin records in the
   * database. Successful validation results in issuance of new access and
   * refresh tokens to maintain an authenticated session without re-login. This
   * supports seamless security and user experience. Related operations include
   * /auth/admin/login and /auth/admin/join.
   *
   * @param connection
   * @param body Token refresh request body containing a valid refresh token
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEconPolDiscussionBoardAdmin.IRefresh,
  ): Promise<IEconPolDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
