import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { AdminAuth } from "../../../decorators/AdminAuth";
import { AdminPayload } from "../../../decorators/payload/AdminPayload";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { IDiscussionBoardAdmin } from "../../../api/structures/IDiscussionBoardAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Register a new admin by providing necessary information such as username,
   * email, and password, stored securely within the discussion_board_admin
   * table. Upon successful registration, initial JWT tokens are issued for
   * authentication. This operation enables the creation of admin users with
   * full permissions needed to manage the discussion board system and its
   * content responsibly. Security practices ensure passwords are hashed and
   * only authorized admins can manage sensitive data.
   *
   * @param connection
   * @param body Admin registration request payload
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAdmin.IJoin,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate administrator credentials provided during login to generate
   * JWT access tokens for managing the discussion board system. Ensures only
   * authorized users with valid credentials gain administrative access,
   * referencing stored password hashes and account statuses in the
   * discussion_board_admin table. This endpoint forms an essential part of the
   * admin authentication workflow.
   *
   * @param connection
   * @param body Admin login request payload
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAdmin.ILogin,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh admin JWT access tokens using a valid refresh token to maintain an
   * active authenticated session without re-login. Ensures continued access to
   * administrative features by validating refresh token status and expiration
   * within session records or tokens stored for the discussion_board_admin
   * actor. This endpoint is critical for secure session management.
   *
   * @param connection
   * @param body Admin token refresh request payload
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAdmin.IRefresh,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
