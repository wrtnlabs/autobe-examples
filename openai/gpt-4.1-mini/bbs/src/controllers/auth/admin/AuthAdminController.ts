import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { AdminAuth } from "../../../decorators/AdminAuth";
import { AdminPayload } from "../../../decorators/payload/AdminPayload";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { IDiscussionBoardAdmin } from "../../../api/structures/IDiscussionBoardAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Register a new admin account in the discussion board system using the
   * discussion_board_admins table.
   *
   * This operation enables administrators to register accounts in the
   * discussion board system. It creates a new admin user with a unique email
   * and securely hashed password. The operation persists the user in the
   * 'discussion_board_admins' table, setting 'created_at' and 'updated_at'
   * timestamps, with 'deleted_at' initially null indicating an active account.
   * Upon successful account creation, the system issues JWT-based access and
   * refresh tokens, enabling session management and authenticated requests.
   * This operation is open publicly (no prior authentication) to allow new
   * admin registrations. It forms the entry point for admin onboarding within
   * the authentication workflow.
   *
   * @param connection
   * @param body Admin registration information including email and password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAdmin.IJoin,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate admin credentials and obtain JWT tokens for session management
   * using discussion_board_admins and discussion_board_admin_sessions tables.
   *
   * This operation authenticates an existing administrator using email and
   * password credentials. It validates the provided credentials against the
   * stored 'password_hash' in 'discussion_board_admins'. On success, it creates
   * a session record in 'discussion_board_admin_sessions' associating login
   * metadata (e.g., IP, user agent). The system issues fresh JWT access and
   * refresh tokens, enabling authenticated API calls. This operation is public,
   * allowing admins to log in independently. It integrates with other security
   * mechanisms like rate limiting and account lockout policies to protect
   * against brute force attacks.
   *
   * @param connection
   * @param body Admin login credentials including email and password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAdmin.ILogin,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT tokens for an authenticated admin using valid refresh tokens
   * and session records.
   *
   * This operation allows an authenticated administrator to refresh their JWT
   * access tokens using a valid refresh token. It validates the refresh token
   * against active sessions maintained within
   * 'discussion_board_admin_sessions'. Upon successful validation, it issues
   * new access and refresh JWT tokens, extending session validity and enabling
   * continued authenticated API requests. This operation requires
   * authentication and is essential for maintaining secure admin sessions
   * without re-login.
   *
   * @param connection
   * @param body Refresh token for obtaining new access tokens.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAdmin.IRefresh,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
