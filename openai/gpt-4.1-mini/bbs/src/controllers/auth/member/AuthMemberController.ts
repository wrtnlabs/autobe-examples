import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthMemberJoin } from "../../../providers/postAuthMemberJoin";
import { MemberAuth } from "../../../decorators/MemberAuth";
import { MemberPayload } from "../../../decorators/payload/MemberPayload";
import { postAuthMemberLogin } from "../../../providers/postAuthMemberLogin";
import { postAuthMemberRefresh } from "../../../providers/postAuthMemberRefresh";

import { IDiscussionBoardMember } from "../../../api/structures/IDiscussionBoardMember";

@Controller("/auth/member")
export class AuthMemberController {
  /**
   * Creates a new discussion board member account and issues JWT tokens.
   *
   * Creates a new member account by registering the user's email and password.
   * This process involves securely storing the password hash in the
   * discussion_board_members table. The operation ensures the uniqueness of the
   * email to maintain user account integrity. Upon successful creation, the
   * system issues JWT tokens for authenticated session management. This
   * operation is public and does not require prior authentication, allowing new
   * users to join the discussion board platform.
   *
   * @param connection
   * @param body Member registration credentials including email and password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardMember.ICreate,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postAuthMemberJoin({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates member and returns JWT tokens.
   *
   * Authenticates a member user by verifying their email and password. Uses the
   * password_hash stored in discussion_board_members. If credentials match an
   * active member account (deleted_at is null), this operation returns access
   * and refresh JWT tokens encapsulated in the
   * IDiscussionBoardMember.IAuthorized response type. The operation is public
   * and intended for member login purposes.
   *
   * @param connection
   * @param body Member login credentials including email and password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardMember.ILogin,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postAuthMemberLogin({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes member JWT token.
   *
   * Refreshes the JWT token for a member user to extend session validity
   * without requiring re-login. Uses a valid refresh token to issue new access
   * and refresh tokens. The operation ensures the account exists and is active
   * in discussion_board_members. Returns updated JWT tokens in the
   * IDiscussionBoardMember.IAuthorized response type.
   *
   * @param connection
   * @param body Refresh token for obtaining new JWT tokens.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardMember.IRefresh,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postAuthMemberRefresh({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
