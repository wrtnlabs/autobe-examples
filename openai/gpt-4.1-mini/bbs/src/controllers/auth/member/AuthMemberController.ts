import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthMemberJoin } from "../../../providers/postAuthMemberJoin";
import { MemberAuth } from "../../../decorators/MemberAuth";
import { MemberPayload } from "../../../decorators/payload/MemberPayload";
import { postAuthMemberLogin } from "../../../providers/postAuthMemberLogin";
import { postAuthMemberRefresh } from "../../../providers/postAuthMemberRefresh";

import { IEconPolDiscussionBoardMember } from "../../../api/structures/IEconPolDiscussionBoardMember";

@Controller("/auth/member")
export class AuthMemberController {
  /**
   * Register a new authenticated member account
   * (econ_pol_discussion_board_members).
   *
   * This API endpoint allows new members to register an account on the
   * econPolDiscussionBoard service. The member entity consists of fields such
   * as username, email, and password_hash representing credentials and contact
   * information essential for authentication. The member's password is securely
   * hashed and stored to protect account security.
   *
   * Upon success, the endpoint returns JWT tokens authorizing the member's
   * access to protected resources.
   *
   * Only unauthenticated users can access this endpoint to create new accounts.
   *
   * Related operations include login for active members and refresh to renew
   * expired tokens.
   *
   * @param connection
   * @param body Join request body containing new member credentials and
   *   information.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEconPolDiscussionBoardMember.ICreate,
  ): Promise<IEconPolDiscussionBoardMember.IAuthorized> {
    try {
      return await postAuthMemberJoin({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate member and issue JWT access tokens
   * (econ_pol_discussion_board_members).
   *
   * This endpoint performs member login, validating credentials against stored
   * username/email and hashed password in econ_pol_discussion_board_members.
   * Successful login returns JWT tokens authorizing member access.
   *
   * Only unauthenticated users should call this endpoint with correct
   * credentials.
   *
   * This operation works together with join for account creation and refresh
   * for renewing tokens.
   *
   * @param connection
   * @param body Login request body containing member credentials
   *   (username/email and password).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEconPolDiscussionBoardMember.ILogin,
  ): Promise<IEconPolDiscussionBoardMember.IAuthorized> {
    try {
      return await postAuthMemberLogin({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT tokens for member sessions (econ_pol_discussion_board_members).
   *
   * This endpoint refreshes JWT access tokens for authenticated members on
   * econPolDiscussionBoard. Clients provide valid refresh tokens to obtain new
   * access tokens without re-entering credentials.
   *
   * This helps maintain persistent sessions for members.
   *
   * Related operations include login to authenticate and join to register new
   * members.
   *
   * @param connection
   * @param body Refresh request body containing refresh token information.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEconPolDiscussionBoardMember.IRefresh,
  ): Promise<IEconPolDiscussionBoardMember.IAuthorized> {
    try {
      return await postAuthMemberRefresh({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
