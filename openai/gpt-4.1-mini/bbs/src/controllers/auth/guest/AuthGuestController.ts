import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthGuestJoin } from "../../../providers/postAuthGuestJoin";
import { postAuthGuestRefresh } from "../../../providers/postAuthGuestRefresh";

import { IDiscussionBoardGuest } from "../../../api/structures/IDiscussionBoardGuest";
import { IGuest } from "../../../api/structures/IGuest";

@Controller("/auth/guest")
export class AuthGuestController {
  /**
   * Guest user registration via temporary session creation for JWT token
   * issuance.
   *
   * This endpoint allows unauthenticated guest users to join the system by
   * creating a temporary guest session and obtaining JWT tokens for limited
   * access. No credential login is required since guests are not permanent
   * users. The operation issues access and refresh tokens valid for guest
   * session usage, enabling limited reading privileges. It references
   * principals of guest sessions managed outside of typical member or admin
   * database user tables. This operation is public and requires no actor
   * authentication. It complements the refresh endpoint for token renewal.
   *
   * This operation relies on temporary session creation with no stored password
   * or email.
   *
   * Security considerations include limited token privileges scoped to guests
   * and short token lifetimes.
   *
   * Related operations include the refresh operation, which handles token
   * renewal without requiring re-authentication.
   *
   * This API endpoint corresponds conceptually to the guest actor type with
   * limited authentication capability.
   *
   * @param connection
   * @param body Information required to create a temporary guest session and
   *   obtain JWT tokens. Typically contains minimal or no data.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IGuest.IJoin,
  ): Promise<IDiscussionBoardGuest.IAuthorized> {
    try {
      return await postAuthGuestJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT tokens for guest user sessions using a refresh token.
   *
   * This endpoint refreshes JWT access tokens for guest users based on their
   * valid refresh tokens. It does not require login credentials and extends
   * guest session access securely without reauthentication. Tokens issued
   * reflect limited guest privileges and expire soon after issuance.
   *
   * Proper validation of refresh tokens is mandatory to prevent unauthorized
   * extension of guest access.
   *
   * This operation complements the join endpoint which creates the initial
   * guest session.
   *
   * This API endpoint is specific to the guest actor and maintains session
   * security based on JWT refresh procedure.
   *
   * No typical user database record is referenced, only JWT verification and
   * token issuance logic are invoked.
   *
   * Security best practice includes short-lived access and refresh tokens with
   * limited scopes for guests.
   *
   * @param connection
   * @param body Refresh token information for renewing access tokens for guest
   *   sessions.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IGuest.IRefresh,
  ): Promise<IDiscussionBoardGuest.IAuthorized> {
    try {
      return await postAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
