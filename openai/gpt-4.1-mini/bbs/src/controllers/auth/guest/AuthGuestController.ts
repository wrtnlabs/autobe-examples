import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthGuestJoin } from "../../../providers/postAuthGuestJoin";
import { GuestAuth } from "../../../decorators/GuestAuth";
import { GuestPayload } from "../../../decorators/payload/GuestPayload";
import { postAuthGuestRefresh } from "../../../providers/postAuthGuestRefresh";

import { IEconPolDiscussionBoardGuest } from "../../../api/structures/IEconPolDiscussionBoardGuest";

@Controller("/auth/guest")
export class AuthGuestController {
  /**
   * Create guest user account and issue temporary JWT tokens.
   *
   * This operation creates a new guest user account in the
   * econ_pol_discussion_board_guests table, enabling guests to interact with
   * the system in an unauthenticated session mode. It issues initial JWT tokens
   * for temporary access. The join operation leverages the absence of password
   * requirements in the guest schema and focuses on session initiation.
   *
   * The operation does not require credentials and is accessible publicly
   * without authentication, serving to track guest activity and session state.
   *
   * This operation complements the refresh token process to maintain guest
   * sessions without explicit login.
   *
   * Security considerations include ensuring no elevated permissions are
   * granted to guest accounts and tokens are scoped appropriately to limit
   * access.
   *
   * Related operations: refresh - to renew tokens and extend sessions for the
   * guest user.
   *
   * @param connection
   * @param body New guest creation request payload.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IEconPolDiscussionBoardGuest.ICreate,
  ): Promise<IEconPolDiscussionBoardGuest.IAuthorized> {
    try {
      return await postAuthGuestJoin({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh guest user's temporary access tokens.
   *
   * This operation takes a valid guest refresh token and returns a new set of
   * JWT tokens, enabling continued temporary session access without creating a
   * new guest account. It ensures session continuity for guest users in the
   * econ_pol_discussion_board_guests table.
   *
   * Access to this endpoint requires a valid refresh token and is limited to
   * guest actor scope.
   *
   * Security measures include validation of refresh tokens and token
   * invalidation upon expiration or logout.
   *
   * Related operations include join - which creates the initial guest account
   * and issues tokens.
   *
   * This operation completes the guest authentication lifecycle with token
   * renewal capabilities.
   *
   * @param connection
   * @param body Refresh token request payload.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IEconPolDiscussionBoardGuest.IRequestRefresh,
  ): Promise<IEconPolDiscussionBoardGuest.IAuthorized> {
    try {
      return await postAuthGuestRefresh({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
