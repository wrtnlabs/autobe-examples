import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthGuestJoin } from "../../../providers/postAuthGuestJoin";
import { GuestAuth } from "../../../decorators/GuestAuth";
import { GuestPayload } from "../../../decorators/payload/GuestPayload";
import { postAuthGuestRefresh } from "../../../providers/postAuthGuestRefresh";

import { IDiscussionBoardGuest } from "../../../api/structures/IDiscussionBoardGuest";

@Controller("/auth/guest")
export class AuthGuestController {
  /**
   * Create a temporary guest account and issue access tokens (no authentication
   * required).
   *
   * This operation enables unauthenticated users (guest actor) to register
   * temporary guest accounts. It creates basic records in the guest data table
   * and issues short-lived JWT tokens to allow read-only access to public
   * articles and discussions. No credentials or password are needed since
   * guests do not log in traditionally. This operation complements the
   * subsequent token refresh operation to maintain session continuity.
   *
   * Implementation details: A temporary guest record is created in the
   * discussion_board_guest table with minimal required fields. Token issuance
   * follows JWT standards leveraged by the application.
   *
   * Actor-specific integration: Specifically designed for the guest actor role
   * with limited permissions and no login capabilities.
   *
   * Security: Since this is a public endpoint, careful rate limiting and
   * validation are expected to avoid abuse. No password or sensitive data is
   * handled.
   *
   * Related operations: This operation works with the refresh endpoint to
   * maintain stateless session tokens across visits.
   *
   * @param connection
   * @param body Join request body for guest registration without credential
   *   fields
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IDiscussionBoardGuest.IJoin,
  ): Promise<IDiscussionBoardGuest.IAuthorized> {
    try {
      return await postAuthGuestJoin({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh the access tokens using a valid refresh token for guests.
   *
   * This operation enables token renewal for temporary guest accounts. The
   * client must provide a valid refresh token obtained from a prior join or
   * refresh operation. Upon validation, new JWT access and refresh tokens are
   * issued to permit continued read-only access without requiring
   * re-registration.
   *
   * Implementation details: Refresh token validity and revocation mechanisms
   * rely on the discussion_board_guest sessions tables and JWT standards.
   *
   * Actor-specific integration: This endpoint is restricted to guests, ensuring
   * tokens are only refreshed for authorized guest sessions.
   *
   * Security: Implementing short token lifetimes and proper validation is
   * essential to prevent token abuse.
   *
   * Related operations: Works closely with the join operation to maintain
   * stateless session continuity for guest users.
   *
   * @param connection
   * @param body Refresh token request body
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IDiscussionBoardGuest.IRefresh,
  ): Promise<IDiscussionBoardGuest.IAuthorized> {
    try {
      return await postAuthGuestRefresh({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
