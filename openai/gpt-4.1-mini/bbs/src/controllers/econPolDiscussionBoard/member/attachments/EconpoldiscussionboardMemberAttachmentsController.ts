import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteEconPolDiscussionBoardMemberAttachmentsId } from "../../../../providers/deleteEconPolDiscussionBoardMemberAttachmentsId";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";

@Controller("/econPolDiscussionBoard/member/attachments/:id")
export class EconpoldiscussionboardMemberAttachmentsController {
  /**
   * Delete an attachment by ID.
   *
   * Delete an attachment by its unique ID.
   *
   * This permanently removes the attachment record and frees associated
   * storage. Users with appropriate permissions can delete attachments to
   * manage article content.
   *
   * Authorization ensures that only the uploader or administrators can perform
   * deletion operations.
   *
   * This directly manipulates the econ_pol_discussion_board_attachments table
   * to remove the specified record.
   *
   * @param connection
   * @param id Unique identifier of the target attachment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEconPolDiscussionBoardMemberAttachmentsId({
        member,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
