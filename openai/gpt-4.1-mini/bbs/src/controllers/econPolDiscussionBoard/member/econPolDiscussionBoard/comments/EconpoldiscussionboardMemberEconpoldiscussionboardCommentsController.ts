import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchEconPolDiscussionBoardMemberEconPolDiscussionBoardComments } from "../../../../../providers/patchEconPolDiscussionBoardMemberEconPolDiscussionBoardComments";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getEconPolDiscussionBoardMemberEconPolDiscussionBoardCommentsCommentId } from "../../../../../providers/getEconPolDiscussionBoardMemberEconPolDiscussionBoardCommentsCommentId";
import { putEconPolDiscussionBoardMemberEconPolDiscussionBoardCommentsCommentId } from "../../../../../providers/putEconPolDiscussionBoardMemberEconPolDiscussionBoardCommentsCommentId";
import { deleteEconPolDiscussionBoardMemberEconPolDiscussionBoardCommentsCommentId } from "../../../../../providers/deleteEconPolDiscussionBoardMemberEconPolDiscussionBoardCommentsCommentId";

import { IPageIEconPolDiscussionBoardComment } from "../../../../../api/structures/IPageIEconPolDiscussionBoardComment";
import { IEconPolDiscussionBoardComment } from "../../../../../api/structures/IEconPolDiscussionBoardComment";

@Controller("/econPolDiscussionBoard/member/econPolDiscussionBoard/comments")
export class EconpoldiscussionboardMemberEconpoldiscussionboardCommentsController {
  /**
   * Retrieve a filtered, paginated list of discussion board comments.
   *
   * Retrieve a list of comments posted by members on articles in the
   * econPolDiscussionBoard. This operation allows clients to filter comments
   * based on criteria such as the associated article, author member, and date
   * ranges, with support for pagination.
   *
   * It references the EconPolDiscussionBoardComments table, which tracks
   * comment body content, author information, article association, nested
   * comment replies via parent comment references, and timestamps for
   * auditing.
   *
   * Authorization requires the member role to query comments. The operation
   * returns a paginated collection of comment summaries matching filter
   * criteria.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for comments on the
   *   econPolDiscussionBoard
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEconPolDiscussionBoardComment.IRequest,
  ): Promise<IPageIEconPolDiscussionBoardComment.ISummary> {
    try {
      return await patchEconPolDiscussionBoardMemberEconPolDiscussionBoardComments(
        {
          member,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single discussion board comment by comment ID.
   *
   * Retrieve detailed information of a single comment from the
   * econPolDiscussionBoard.
   *
   * The comment includes the body text, author member ID, related article ID,
   * optional parent comment for replies, and timestamps for creation and last
   * update.
   *
   * The operation requires member authorization, ensuring only authorized
   * members can access comment details.
   *
   * Errors are returned if the comment ID does not match an existing record.
   *
   * @param connection
   * @param commentId Unique identifier of the target comment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":commentId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IEconPolDiscussionBoardComment> {
    try {
      return await getEconPolDiscussionBoardMemberEconPolDiscussionBoardCommentsCommentId(
        {
          member,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a comment by ID.
   *
   * Update an existing comment identified by comment ID on
   * econPolDiscussionBoard.
   *
   * Members can modify their own comment text and nesting. Body text length and
   * nesting depth limits apply.
   *
   * The operation updates the updatedAt timestamp automatically.
   *
   * Related operations include creation and detail retrieval of comments.
   *
   * Authorization ensures only the comment's author can update.
   *
   * This endpoint supports effective management of member comments.
   *
   * @param connection
   * @param commentId UUID of the target comment to update
   * @param body Comment update data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconPolDiscussionBoardComment.IUpdate,
  ): Promise<IEconPolDiscussionBoardComment> {
    try {
      return await putEconPolDiscussionBoardMemberEconPolDiscussionBoardCommentsCommentId(
        {
          member,
          commentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a comment from econPolDiscussionBoard by comment ID.
   *
   * Delete an existing comment on the economic and political discussion board.
   *
   * This operation permanently deletes the comment specified by the unique
   * comment ID from the econPolDiscussionBoard system. It is intended for
   * authenticated users with the right privileges, such as the comment author
   * or moderators.
   *
   * The comment deletion is a hard delete that removes all data associated with
   * the comment. There is no soft delete or archive. Deleted comments cannot be
   * recovered.
   *
   * Security: The operation enforces access controls to ensure only authorized
   * actors can delete comments. Attempts to delete non-existent comments return
   * appropriate error responses.
   *
   * Related operations: Use POST /econPolDiscussionBoard/comments to create
   * comments, PUT /econPolDiscussionBoard/comments/{commentId} to update
   * comments, and PATCH /econPolDiscussionBoard/comments to list comments.
   *
   * @param connection
   * @param commentId Unique identifier of the target comment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEconPolDiscussionBoardMemberEconPolDiscussionBoardCommentsCommentId(
        {
          member,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
