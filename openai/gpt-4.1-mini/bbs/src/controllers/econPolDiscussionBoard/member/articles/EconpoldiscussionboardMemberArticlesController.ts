import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getEconPolDiscussionBoardMemberArticlesId } from "../../../../providers/getEconPolDiscussionBoardMemberArticlesId";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putEconPolDiscussionBoardMemberArticlesId } from "../../../../providers/putEconPolDiscussionBoardMemberArticlesId";
import { deleteEconPolDiscussionBoardMemberArticlesId } from "../../../../providers/deleteEconPolDiscussionBoardMemberArticlesId";
import { postEconPolDiscussionBoardMemberArticles } from "../../../../providers/postEconPolDiscussionBoardMemberArticles";

import { IEconPolDiscussionBoardArticle } from "../../../../api/structures/IEconPolDiscussionBoardArticle";

@Controller("/econPolDiscussionBoard/member/articles")
export class EconpoldiscussionboardMemberArticlesController {
  /**
   * Retrieve a single discussion board article by its unique ID.
   *
   * Retrieve detailed information about a specific article in the
   * econPolDiscussionBoard system, identified by its unique UUID. This includes
   * title, full content, author identification, and timestamps for creation and
   * last update.
   *
   * The article corresponds to a record in the
   * econ_pol_discussion_board_articles table. The endpoint supports audit and
   * traceability by linking each article to its member author.
   *
   * Access is restricted to authorized users with permissions to view article
   * details.
   *
   * @param connection
   * @param id Unique identifier (UUID) of the target article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IEconPolDiscussionBoardArticle> {
    try {
      return await getEconPolDiscussionBoardMemberArticlesId({
        member,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing article on EconPolDiscussionBoard by unique identifier.
   *
   * Members can modify their own articles by updating title, content, and
   * attachments. This operation requires authentication and confirms that the
   * user owns the article to perform updates.
   *
   * Input is validated similar to creation, with length restrictions and
   * sanitization applied. Unauthorized attempts are rejected with appropriate
   * error responses.
   *
   * Related operations include creation (POST /articles) and deletion (DELETE
   * /articles/{id}).
   *
   * @param connection
   * @param id Unique identifier of the article to update
   * @param body Request body to update article fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconPolDiscussionBoardArticle.IUpdate,
  ): Promise<IEconPolDiscussionBoardArticle> {
    try {
      return await putEconPolDiscussionBoardMemberArticlesId({
        member,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove an article by ID.
   *
   * Delete an article from the EconPolDiscussionBoard by its unique identifier.
   *
   * This operation permanently removes the specified article from the database,
   * including its content, attachments metadata, and any linked resources.
   *
   * Authorization is required; only authenticated members are allowed to
   * perform this deletion to maintain content integrity and prevent misuse.
   *
   * No content is returned in the response. Successful deletion implies the
   * article can no longer be viewed or restored via the API.
   *
   * @param connection
   * @param id Unique identifier of the article to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEconPolDiscussionBoardMemberArticlesId({
        member,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new article post on the economic and political discussion board.
   *
   * This operation allows authenticated members to submit a new article with a
   * title and textual content. Attachments, if any, can be linked during
   * creation by specifying attachment details. The authorId is derived from the
   * logged-in member and hence is not part of the input body.
   *
   * Security considerations include verifying that the member is authenticated
   * and authorized to post. Input validation enforces content length
   * restrictions and sanitizes content to prevent XSS attacks.
   *
   * The newly created article is immediately visible in public listings and
   * supports subsequent editing or commenting. Related endpoints include
   * updating (PUT /articles/{id}) and deleting the article.
   *
   * @param connection
   * @param body Request body to create a new article with title, content and
   *   attachment links
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEconPolDiscussionBoardArticle.ICreate,
  ): Promise<IEconPolDiscussionBoardArticle> {
    try {
      return await postEconPolDiscussionBoardMemberArticles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
