import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getEconPolDiscussionBoardMemberArticlesIdAttachments } from "../../../../../providers/getEconPolDiscussionBoardMemberArticlesIdAttachments";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { postEconPolDiscussionBoardMemberArticlesIdAttachments } from "../../../../../providers/postEconPolDiscussionBoardMemberArticlesIdAttachments";

import { IEconPolDiscussionBoardAttachment } from "../../../../../api/structures/IEconPolDiscussionBoardAttachment";

@Controller("/econPolDiscussionBoard/member/articles/:id/attachments")
export class EconpoldiscussionboardMemberArticlesAttachmentsController {
  /**
   * Get list of attachments for an article.
   *
   * Retrieve all attachments for a specific article by its unique identifier.
   *
   * This operation returns a list of attachments including images and files
   * associated with the article. It allows clients to view all media linked to
   * the article's content.
   *
   * Security considerations include ensuring that only authorized users can
   * access attachments of articles they have permission to view. The response
   * includes attachment metadata including type, URL, file name, and upload
   * timestamp.
   *
   * This operation interacts with the econ_pol_discussion_board_attachments
   * table to gather all related attachments by article ID.
   *
   * @param connection
   * @param id Unique identifier of the target article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IEconPolDiscussionBoardAttachment.ISummary> {
    try {
      return await getEconPolDiscussionBoardMemberArticlesIdAttachments({
        member,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Upload attachment to article.
   *
   * Upload an attachment (image or file) for a specified article identified by
   * its unique ID.
   *
   * Attachments can be images or other file types, each upload is associated
   * directly with the article.
   *
   * The operation requires authenticated member permissions to associate new
   * attachments with articles.
   *
   * Upon successful upload, the attachment metadata including URL and file
   * information is returned to the client.
   *
   * @param connection
   * @param id Unique identifier of the target article to attach the file
   * @param body Attachment upload data including type, url, and fileName
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconPolDiscussionBoardAttachment.ICreate,
  ): Promise<IEconPolDiscussionBoardAttachment> {
    try {
      return await postEconPolDiscussionBoardMemberArticlesIdAttachments({
        member,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
