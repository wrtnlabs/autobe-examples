import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchEconPolDiscussionBoardArticles } from "../../../providers/patchEconPolDiscussionBoardArticles";

import { IPageIEconPolDiscussionBoardArticle } from "../../../api/structures/IPageIEconPolDiscussionBoardArticle";
import { IEconPolDiscussionBoardArticle } from "../../../api/structures/IEconPolDiscussionBoardArticle";

@Controller("/econPolDiscussionBoard/articles")
export class EconpoldiscussionboardArticlesController {
  /**
   * Retrieve a filtered, paginated list of discussion board articles.
   *
   * Retrieve a filtered and paginated list of articles from the
   * econPolDiscussionBoard system. This operation allows clients to specify
   * search criteria including pagination parameters to navigate through large
   * sets of articles.
   *
   * Articles are plain-text posts created by authenticated members, with each
   * containing an ID, title, content snippet, author reference, and timestamps
   * for creation and update. The operation supports efficient querying and
   * sorting based on these fields.
   *
   * Security considerations require that only authorized clients access article
   * lists, with potential restrictions based on user roles or visibility
   * settings. The response contains article summaries optimized for list
   * display, excluding large content bodies to improve performance.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   articles
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEconPolDiscussionBoardArticle.IRequest,
  ): Promise<IPageIEconPolDiscussionBoardArticle.ISummary> {
    try {
      return await patchEconPolDiscussionBoardArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
