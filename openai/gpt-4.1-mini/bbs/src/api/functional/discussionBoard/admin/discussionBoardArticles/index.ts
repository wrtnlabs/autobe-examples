/**
 * Permanently delete a specific discussion board article.
 *
 * Permanently deletes a discussion board article identified by its unique UUID.
 * This operation ensures complete removal of the article and all associated
 * discussion board attachments. Only users with 'admin' actor authorization are
 * allowed to perform this deletion to maintain content integrity and security.
 *
 * The parameter 'articleId' is the UUID of the article targeted for deletion.
 * Proper authorization checks must be applied to prevent unauthorized
 * removals.
 *
 * No request body is necessary, and no response body is returned upon
 * successful deletion. Handling of errors such as non-existent article IDs or
 * unauthorized access should follow standard API error conventions.
 *
 * This operation is vital for administrative management of content lifecycle
 * and is part of complete CRUD support for articles within the discussion board
 * system.
 *
 * @param props.connection
 * @param props.articleId Unique identifier (UUID) of the discussion board
 *   article to delete
 * @path /discussionBoard/admin/discussionBoardArticles/:articleId
 * @accessor api.functional.discussionBoard.admin.discussionBoardArticles.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier (UUID) of the discussion board article to delete */
    articleId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/admin/discussionBoardArticles/:articleId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/admin/discussionBoardArticles/${encodeURIComponent(props.articleId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
