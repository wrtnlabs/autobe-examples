import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardComment } from "../../../structures/IDiscussionBoardComment";

/**
 * Retrieve detailed information of a discussion board comment by ID.
 *
 * Retrieve a single discussion board comment by its unique identifier.
 *
 * This operation returns the full details of the comment, including its text
 * content, timestamps for creation, last update, and soft deletion status, as
 * well as references to the associated article and the member who authored the
 * comment.
 *
 * Security: Access to this endpoint is unrestricted (public endpoint) for
 * viewing purposes only.
 *
 * The comment's id parameter is a UUID string uniquely identifying the comment.
 * There is no request body because this is a simple GET operation.
 *
 * Related operations include listing comments (POST /discussionBoardComments)
 * and creating comments (POST /discussionBoardComments).
 *
 * @param props.connection
 * @param props.id UUID string uniquely identifying the discussion board comment
 * @path /discussionBoard/discussionBoardComments/:id
 * @accessor api.functional.discussionBoard.discussionBoardComments.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** UUID string uniquely identifying the discussion board comment */
    id: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardComment;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/discussionBoardComments/:id",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/discussionBoardComments/${encodeURIComponent(props.id ?? "null")}`;
  export const random = (): IDiscussionBoardComment =>
    typia.random<IDiscussionBoardComment>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("id")(() => typia.assert(props.id));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
