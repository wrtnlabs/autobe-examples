import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardArticle } from "../../../structures/IDiscussionBoardArticle";

/**
 * Get a specific discussion board article by its UUID.
 *
 * Retrieve detailed information of a discussion board article by its unique
 * identifier.
 *
 * This operation fetches the full details of an article, including title,
 * content, author reference, creation and update timestamps, and the soft
 * deletion timestamp if applicable.
 *
 * It ensures only active articles (not soft-deleted) are returned in typical
 * use cases. Access is generally public, allowing any user or guest to view the
 * article content.
 *
 * Related operations include listing articles (POST /discussionBoardArticles
 * with filtering) and managing attachments/comments handled by separate
 * endpoints.
 *
 * @param props.connection
 * @param props.id Unique identifier of the target discussion board article
 * @path /discussionBoard/discussionBoardArticles/:id
 * @accessor api.functional.discussionBoard.discussionBoardArticles.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target discussion board article */
    id: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardArticle;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/discussionBoardArticles/:id",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/discussionBoardArticles/${encodeURIComponent(props.id ?? "null")}`;
  export const random = (): IDiscussionBoardArticle =>
    typia.random<IDiscussionBoardArticle>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("id")(() => typia.assert(props.id));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
