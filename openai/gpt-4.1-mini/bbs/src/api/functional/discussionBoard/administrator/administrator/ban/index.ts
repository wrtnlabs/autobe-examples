import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";

import { IDiscussionBoardUserBan } from "../../../../../structures/IDiscussionBoardUserBan";

/**
 * Create a ban record for a registered user by providing a mandatory reason for banning.
 *
 * This operation is restricted to administrators who have the privilege to ban users. It records the ban reason in the `discussion_board_user_bans` database entity for audit purposes. The ban prevents the user from logging in while retaining their content on the platform.
 *
 * The operation accepts the registered user's unique UUID as a path parameter and a JSON body containing the ban reason.
 *
 * Administrators calling this endpoint must have valid credentials and appropriate role authorization.
 *
 * Errors and edge cases include invalid user ID, missing ban reason, and database transaction failures.
 *
 * This endpoint complements the unban operation for reversing bans and the list banned users operation for audit trail.
 *
 * Response returns confirmation indicating if the ban was successfully recorded.
 *
 * @param props.connection
 * @param props.registeredUserId UUID of the registered user to ban
 * @param props.body Ban reason and details
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor administrator
 * @x-autobe-specification Validate the administrator's authorization.
 * Verify the registeredUserId exists and corresponds to a registered user.
 * Require the ban reason in the request body.
 * Create a new record in discussion_board_user_bans with user ID, reason, and current timestamp.
 * Reject the user login attempts after ban.
 * Handle database errors and rollback if insertion fails.
 * Return a success response with boolean status indicating ban success.
 *
 * This operation must be atomic and transactional to prevent partial ban state.
 *
 * Enforce logging of the ban action for audit trail.
 *
 * This API requires authentication with administrator roles.
 * @path /discussionBoard/administrator/administrator/ban/:registeredUserId
 * @accessor api.functional.discussionBoard.administrator.administrator.ban.banUser
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function banUser(
  connection: IConnection,
  props: banUser.Props,
): Promise<banUser.Response> {
  return true === connection.simulate
    ? banUser.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...banUser.METADATA,
          path: banUser.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace banUser {
  export type Props = {
    /**
     * UUID of the registered user to ban
     */
    registeredUserId: string & tags.Format<"uuid">;

    /**
     * Ban reason and details
     */
    body: IDiscussionBoardUserBan.ICreate;
  };
  export type Body = IDiscussionBoardUserBan.ICreate;
  export type Response = IDiscussionBoardUserBan;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/administrator/administrator/ban/:registeredUserId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/administrator/administrator/ban/${encodeURIComponent(props.registeredUserId ?? "null")}`;
  export const random = (): IDiscussionBoardUserBan =>
    typia.random<IDiscussionBoardUserBan>();
  export const simulate = (
    connection: IConnection,
    props: banUser.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: banUser.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("registeredUserId")(() =>
        typia.assert(props.registeredUserId),
      );
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
