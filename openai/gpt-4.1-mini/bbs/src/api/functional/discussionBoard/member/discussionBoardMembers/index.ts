/**
 * Update an existing discussion board member's details including email,
 * nickname, and password.
 *
 * This operation requires authorization, typically reserved for authenticated
 * members who have permission to modify their own data.
 *
 * Security measures include validation of the updated email (uniqueness and
 * format) and secure handling of password hash updates. Soft deletion state and
 * timestamps are managed internally.
 *
 * Related operations include creating new members (POST
 * /discussionBoardMembers) and retrieving member details (GET
 * /discussionBoardMembers/{discussionBoardMemberId}).
 *
 * @param props.connection
 * @param props.discussionBoardMemberId Unique identifier of the discussion
 *   board member to update
 * @param props.body Data required to update a discussion board member
 * @path /discussionBoard/member/discussionBoardMembers/:discussionBoardMemberId
 * @accessor api.functional.discussionBoard.member.discussionBoardMembers.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
