/**
 * This endpoint allows unauthenticated users (guest) to obtain a temporary guest account through a join operation. The operation creates a guest session that issues JWT tokens enabling limited access to browse content. It does not require traditional login credentials since guests are anonymous. The operation is idempotent for unique identification factors such as device fingerprinting or anonymous tokens if applicable.
 *
 * The operation implements a POST request to /auth/guest/join.
 *
 * Security considerations ensure no password or email is required. The response returns tokens structured as IDiscussionBoardGuest.IAuthorized, supporting JWT-based stateless auth.
 *
 * This API operation is the entry point for guests into the system, allowing seamless anonymous access while enabling token refresh when needed.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Request body for guest join operation containing identification and minimal info required.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification The join operation for guest creates a new guest session using minimal identification information, returning authorization tokens. It involves creation of temporary guest session, possibly with device or environment data, but no user credentials.
 * @path /discussionBoard/auth/guest/join
 * @accessor api.functional.discussionBoard.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /**
     * Request body for guest join operation containing identification and minimal info required.
     */
    body: IDiscussionBoardGuest.IJoin;
  };
  export type Body = IDiscussionBoardGuest.IJoin;
  export type Response = IDiscussionBoardGuest.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/auth/guest/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/auth/guest/join";
  export const random = (): IDiscussionBoardGuest.IAuthorized =>
    typia.random<IDiscussionBoardGuest.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

