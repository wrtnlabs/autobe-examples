/**
 * Administrator registration API allows new administrators to create accounts by providing required credentials such as email and password. The system enforces uniqueness of email, hashes passwords securely, and generates authorization tokens for immediate use.
 *
 * This operation exposes the public endpoint for account creation and returns an authorization token on success. It is the entry point to gaining access to administrative capabilities.
 *
 * The API interacts with the 'discussion_board_administrators' database table to store user credentials and with token generation services to produce JWT tokens.
 *
 * Usage of this endpoint requires no prior authentication.
 *
 * Related operations include login and refresh endpoints which authenticate and maintain session state respectively.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Request body for administrator registration.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor administrator
 * @x-autobe-specification This API endpoint handles administrator registration (join). It validates the provided registration data including email and password, ensures the uniqueness of the email address, hashes the password, creates a new administrator account with default grade and stores it securely. Upon successful registration, the system generates JWT tokens for authorization, encapsulated in the response.
 *
 * Implementation includes validation of input data as per IDiscussionBoardAdministrator.IJoin schema, uniqueness check on the email field in 'discussion_board_administrators' table, secure hashing of the password, creation of the administrator record, and generation of JWT access and refresh tokens.
 *
 * Security considerations ensure that password hashing uses industry best practices and that tokens are securely signed. Potential errors include email already in use or validation failures.
 *
 * This operation is typically followed by a login operation for subsequent authentications.
 * @path /discussionBoard/auth/administrator/join
 * @accessor api.functional.discussionBoard.auth.administrator.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
