/**
 * POST /auth/superAdministrator/join allows a new super administrator to register an account by providing a unique email and password. This creates a record in the discussion_board_super_administrators table with hashed password storage for security. The operation ensures email uniqueness and triggers sending of confirmation processes if applicable. The response returns a JWT authorized object representing successful registration and immediate authentication.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Payload to create a super administrator account, including email and password.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor superAdministrator
 * @x-autobe-specification This operation registers a new super administrator account using email and password. It will validate the uniqueness of the email and store a hashed password in the discussion_board_super_administrators table. The response contains JWT tokens and authentication details in IAuthorized.
 * @path /discussionBoard/auth/superAdministrator/join
 * @accessor api.functional.discussionBoard.auth.superAdministrator.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
