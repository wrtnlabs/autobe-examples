/**
 * Allows new superAdministrator users to register by providing an email and password. The endpoint validates the request, creates user credentials, and generates authorization tokens for immediate authenticated access. Ensures security best practices for credential handling and token issuance.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Payload to register a new superAdministrator account.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor superAdministrator
 * @x-autobe-specification This operation handles the registration of a new superAdministrator user. The service layer ensures the uniqueness of the email and stores hashed passwords securely. The system issues JWT tokens with superAdministrator claims upon successful registration. Validation of input credentials and error handling for duplicate registrations are implemented.
 * @path /discussionBoard/auth/superAdministrator/join
 * @accessor api.functional.discussionBoard.auth.superAdministrator.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
