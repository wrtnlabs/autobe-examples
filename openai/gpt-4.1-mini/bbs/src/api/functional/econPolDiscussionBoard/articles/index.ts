import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconPolDiscussionBoardArticle } from "../../../structures/IEconPolDiscussionBoardArticle";
import { IPageIEconPolDiscussionBoardArticle } from "../../../structures/IPageIEconPolDiscussionBoardArticle";

/**
 * Retrieve a filtered, paginated list of discussion board articles.
 *
 * Retrieve a filtered and paginated list of articles from the
 * econPolDiscussionBoard system. This operation allows clients to specify
 * search criteria including pagination parameters to navigate through large
 * sets of articles.
 *
 * Articles are plain-text posts created by authenticated members, with each
 * containing an ID, title, content snippet, author reference, and timestamps
 * for creation and update. The operation supports efficient querying and
 * sorting based on these fields.
 *
 * Security considerations require that only authorized clients access article
 * lists, with potential restrictions based on user roles or visibility
 * settings. The response contains article summaries optimized for list display,
 * excluding large content bodies to improve performance.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for filtering
 *   articles
 * @path /econPolDiscussionBoard/articles
 * @accessor api.functional.econPolDiscussionBoard.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for filtering articles */
    body: IEconPolDiscussionBoardArticle.IRequest;
  };
  export type Body = IEconPolDiscussionBoardArticle.IRequest;
  export type Response = IPageIEconPolDiscussionBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/econPolDiscussionBoard/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/econPolDiscussionBoard/articles";
  export const random = (): IPageIEconPolDiscussionBoardArticle.ISummary =>
    typia.random<IPageIEconPolDiscussionBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
