import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconPolDiscussionBoardAttachment } from "../../../../../structures/IEconPolDiscussionBoardAttachment";

/**
 * Get list of attachments for an article.
 *
 * Retrieve all attachments for a specific article by its unique identifier.
 *
 * This operation returns a list of attachments including images and files
 * associated with the article. It allows clients to view all media linked to
 * the article's content.
 *
 * Security considerations include ensuring that only authorized users can
 * access attachments of articles they have permission to view. The response
 * includes attachment metadata including type, URL, file name, and upload
 * timestamp.
 *
 * This operation interacts with the econ_pol_discussion_board_attachments table
 * to gather all related attachments by article ID.
 *
 * @param props.connection
 * @param props.id Unique identifier of the target article
 * @path /econPolDiscussionBoard/member/articles/:id/attachments
 * @accessor api.functional.econPolDiscussionBoard.member.articles.attachments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target article */
    id: string & tags.Format<"uuid">;
  };
  export type Response = IEconPolDiscussionBoardAttachment.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/econPolDiscussionBoard/member/articles/:id/attachments",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/econPolDiscussionBoard/member/articles/${encodeURIComponent(props.id ?? "null")}/attachments`;
  export const random = (): IEconPolDiscussionBoardAttachment.ISummary =>
    typia.random<IEconPolDiscussionBoardAttachment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("id")(() => typia.assert(props.id));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Upload attachment to article.
 *
 * Upload an attachment (image or file) for a specified article identified by
 * its unique ID.
 *
 * Attachments can be images or other file types, each upload is associated
 * directly with the article.
 *
 * The operation requires authenticated member permissions to associate new
 * attachments with articles.
 *
 * Upon successful upload, the attachment metadata including URL and file
 * information is returned to the client.
 *
 * @param props.connection
 * @param props.id Unique identifier of the target article to attach the file
 * @param props.body Attachment upload data including type, url, and fileName
 * @path /econPolDiscussionBoard/member/articles/:id/attachments
 * @accessor api.functional.econPolDiscussionBoard.member.articles.attachments.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
