/**
 * Retrieve a single discussion board article by its unique ID.
 *
 * Retrieve detailed information about a specific article in the
 * econPolDiscussionBoard system, identified by its unique UUID. This includes
 * title, full content, author identification, and timestamps for creation and
 * last update.
 *
 * The article corresponds to a record in the econ_pol_discussion_board_articles
 * table. The endpoint supports audit and traceability by linking each article
 * to its member author.
 *
 * Access is restricted to authorized users with permissions to view article
 * details.
 *
 * @param props.connection
 * @param props.id Unique identifier (UUID) of the target article
 * @path /econPolDiscussionBoard/member/articles/:id
 * @accessor api.functional.econPolDiscussionBoard.member.articles.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier (UUID) of the target article */
    id: string & tags.Format<"uuid">;
  };
  export type Response = IEconPolDiscussionBoardArticle;

  export const METADATA = {
    method: "GET",
    path: "/econPolDiscussionBoard/member/articles/:id",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/econPolDiscussionBoard/member/articles/${encodeURIComponent(props.id ?? "null")}`;
  export const random = (): IEconPolDiscussionBoardArticle =>
    typia.random<IEconPolDiscussionBoardArticle>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("id")(() => typia.assert(props.id));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

