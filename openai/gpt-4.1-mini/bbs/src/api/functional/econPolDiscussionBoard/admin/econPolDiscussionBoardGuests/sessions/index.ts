export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target econPolDiscussionBoardGuest */
    guestId: string & tags.Format<"uuid">;

    /** Search criteria and pagination parameters for guest session filtering */
    body: IEconPolDiscussionBoardGuestSession.IRequest;
  };
  export type Body = IEconPolDiscussionBoardGuestSession.IRequest;
  export type Response = IPageIEconPolDiscussionBoardGuestSession.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/econPolDiscussionBoard/admin/econPolDiscussionBoardGuests/:guestId/sessions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/econPolDiscussionBoard/admin/econPolDiscussionBoardGuests/${encodeURIComponent(props.guestId ?? "null")}/sessions`;
  export const random = (): IPageIEconPolDiscussionBoardGuestSession.ISummary =>
    typia.random<IPageIEconPolDiscussionBoardGuestSession.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("guestId")(() => typia.assert(props.guestId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
