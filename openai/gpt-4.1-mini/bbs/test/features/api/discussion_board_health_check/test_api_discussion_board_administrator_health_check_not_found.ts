export async function test_api_discussion_board_administrator_health_check_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator join for authentication
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  typia.assert(adminAuth);
  adminConnection.headers ??= {};
  adminConnection.headers.Authorization = adminAuth.token.access;
  // 2. Attempt to retrieve health check with non-existent UUID
  const invalidId = typia.random<string & tags.Format<"uuid">>();
  // 3. Expect 404 Not Found error
  await TestValidator.httpError("health check not found", 404, async () => {
    await api.functional.discussionBoard.administrator.healthChecks.at(
      adminConnection,
      { id: invalidId },
    );
  });
}
