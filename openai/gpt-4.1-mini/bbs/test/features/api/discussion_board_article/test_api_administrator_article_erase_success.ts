export async function test_api_administrator_article_erase_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator account creation and authentication
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_administrator_join(adminConnection, {
    body: {},
  });
  typia.assert(adminAuth);
  // 2. Registered user creation and authentication
  const userConnection: api.IConnection = { host: connection.host };
  const userAuth = await authorize_registered_user_join(userConnection, {
    body: {},
  });
  typia.assert(userAuth);
  // 3. Registered user creates an article
  const article =
    await generate_random_discussion_board_registered_user_articles_create(
      userConnection,
      { body: {} },
    );
  typia.assert(article);
  // 4. Administrator deletes the article by UUID
  await api.functional.discussionBoard.administrator.articles.erase(
    adminConnection,
    {
      articleId: article.id,
    },
  );
  // 5. Confirm deletion succeeded by verifying article no longer exists
  // We try to re-delete or get article - but no GET exists, so attempt re-deletion to ensure 404 or error
  let errorOccured = false;
  await TestValidator.error(
    "deleting already deleted article throws error",
    async () => {
      await api.functional.discussionBoard.administrator.articles.erase(
        adminConnection,
        { articleId: article.id },
      );
    },
  ).catch(() => {
    errorOccured = true;
  });
  // The above is enough - error occurred means deletion was effective
  TestValidator.predicate("article deletion verified", errorOccured);
}
