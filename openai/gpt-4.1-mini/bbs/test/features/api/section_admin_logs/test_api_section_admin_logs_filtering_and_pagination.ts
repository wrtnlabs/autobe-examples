export async function test_api_section_admin_logs_filtering_and_pagination(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as super administrator by join.
  const superAdminOriginalConnection: api.IConnection = {
    host: connection.host,
  };
  const superAdmin = await authorize_super_administrator_join(
    superAdminOriginalConnection,
    { body: {} },
  );
  typia.assert(superAdmin);
  const superAdminConnection: api.IConnection = { host: connection.host };
  superAdminConnection.headers = { Authorization: superAdmin.token.access };
  // 2. Create a discussion board section.
  // We need administrator connection to create section.
  // So create administrator join and login.
  const adminOriginalConnection: api.IConnection = { host: connection.host };
  const adminJoinBody = {
    email: typia.random<string & typia.tags.Format<"email">>(),
    password: RandomGenerator.alphaNumeric(12),
  };
  const admin = await authorize_administrator_join(adminOriginalConnection, {
    body: adminJoinBody,
  });
  typia.assert(admin);
  const adminConnection: api.IConnection = { host: connection.host };
  adminConnection.headers = { Authorization: admin.token.access };
  // 2. Create section
  const section =
    await generate_random_discussion_board_administrator_sections_create(
      adminConnection,
      {
        body: {
          name: RandomGenerator.name(),
          description: RandomGenerator.paragraph(),
        },
      },
    );
  typia.assert(section);
  // 3. Simulate generating multiple section admin logs
  // Actually, logs should be generated by admin actions
  // Here simulate by waiting some time and making multiple section creations
  // to generate logs.
  // For real tests, logs should exist by actual operations.
  // To ensure logs by the same administrator, create 2 more sections
  await generate_random_discussion_board_administrator_sections_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph(),
      },
    },
  );
  await generate_random_discussion_board_administrator_sections_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph(),
      },
    },
  );
  // Wait for a while to ensure difference in createdAt timestamps
  await new Promise((r) => setTimeout(r, 1000));
  // 4. Call the patch endpoint with administratorId filter, createdAtGte and createdAtLte for date range and pagination.
  const now = new Date();
  const past = new Date(now.getTime() - 60000); // 1 min ago
  const requestBody = {
    administratorId: admin.id,
    createdAtGte: past.toISOString(),
    createdAtLte: now.toISOString(),
    page: 1,
    limit: 10,
  } satisfies api.functional.discussionBoard.superAdministrator.sectionAdminLogs.index.Body;
  const response =
    await api.functional.discussionBoard.superAdministrator.sectionAdminLogs.index(
      superAdminConnection,
      { body: requestBody },
    );
  typia.assert(response);
  // 5. Verify response contains only logs by the specified administrator and within the date range.
  for (const log of response.data) {
    TestValidator.equals("log administratorId", log.administrator.id, admin.id);
    TestValidator.predicate(
      "log createdAt after createdAtGte",
      log.createdAt >= past.toISOString(),
    );
    TestValidator.predicate(
      "log createdAt before createdAtLte",
      log.createdAt <= now.toISOString(),
    );
  }
  // 6. Validate pagination metadata is accurate with total records.
  TestValidator.predicate(
    "pagination current page is 1",
    response.pagination.current === 1,
  );
  TestValidator.predicate(
    "pagination limit is 10",
    response.pagination.limit === 10,
  );
  TestValidator.predicate(
    "pagination records is non-negative",
    response.pagination.records >= 0,
  );
  TestValidator.predicate(
    "pagination pages is non-negative",
    response.pagination.pages >= 0,
  );
  TestValidator.predicate(
    "pagination pages consistent with records and limit",
    response.pagination.pages ===
      (response.pagination.records === 0
        ? 0
        : Math.ceil(response.pagination.records / response.pagination.limit)),
  );
  // 7. Confirm that unauthorized roles cannot access this endpoint.
  // Try accessing with administrator (non-super) connection
  // Login administrator
  const adminLogin = await authorize_administrator_login(
    adminOriginalConnection,
    {
      body: {
        email: adminJoinBody.email,
        password: adminJoinBody.password,
        href: "http://localhost/login",
        referrer: "http://localhost/referrer",
        ip: null,
      },
    },
  );
  typia.assert(adminLogin);
  const adminLoginConnection: api.IConnection = { host: connection.host };
  adminLoginConnection.headers = { Authorization: adminLogin.token.access };
  await TestValidator.httpError(
    "administrator cannot access section admin logs endpoint",
    403,
    async () =>
      await api.functional.discussionBoard.superAdministrator.sectionAdminLogs.index(
        adminLoginConnection,
        { body: requestBody },
      ),
  );
}
