export async function test_api_discussion_board_section_create_duplicate_name(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator authentication
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_administrator_join(adminConnection, {
    body: {
      email: `admin_${RandomGenerator.alphaNumeric(6)}@test.com`,
      password: "password123",
    },
  });
  typia.assert(adminAuth);
  adminConnection.headers = { Authorization: adminAuth.token.access };
  // 2. Create a section with random valid data
  const firstSection =
    await generate_random_discussion_board_administrator_sections_create(
      adminConnection,
      {},
    );
  typia.assert(firstSection);
  // 3. Try to create another section with the same name (should fail)
  const duplicateBody = {
    name: firstSection.name,
    description: RandomGenerator.paragraph({ sentences: 2 }),
  } satisfies IDiscussionBoardSection.ICreate;
  await TestValidator.error(
    "duplicate section name",
    async () =>
      await generate_random_discussion_board_administrator_sections_create(
        adminConnection,
        { body: duplicateBody },
      ),
  );
}
