export async function test_api_discussion_board_tag_create_unique_and_duplicate_name(
  connection: api.IConnection,
): Promise<void> {
  // Economic/Political Discussion Board: Tag creation with unique name and rejection of duplicate name
  // 1. Register and authenticate a new registered user
  const userConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_registered_user_join(userConnection, {
    body: {},
  });
  userConnection.headers = {
    Authorization: `Bearer ${authorized.token.access}`,
  };
  // 2. Create the first tag (randomly generated by utility)
  const firstTag = await generate_random_discussion_board_tags_create(
    userConnection,
    {},
  );
  typia.assert(firstTag);
  // 3. Attempt to create a duplicate tag with the same name, expect error
  await TestValidator.error(
    "Duplicate tag name creation should be rejected",
    async () => {
      await generate_random_discussion_board_tags_create(userConnection, {
        body: {},
      });
    },
  );
}
