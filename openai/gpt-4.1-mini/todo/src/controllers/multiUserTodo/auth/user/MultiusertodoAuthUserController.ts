import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoUser } from "../../../../api/structures/IMultiUserTodoUser";
import { postMultiUserTodoAuthUserJoin } from "../../../../providers/postMultiUserTodoAuthUserJoin";
import { postMultiUserTodoAuthUserLogin } from "../../../../providers/postMultiUserTodoAuthUserLogin";
import { postMultiUserTodoAuthUserRefresh } from "../../../../providers/postMultiUserTodoAuthUserRefresh";

@Controller("/multiUserTodo/auth/user")
export class MultiusertodoAuthUserController {
  /**
   * This operation allows new users of kind "user" to register for the multi-user todo application by providing email and password as specified in IMultiUserTodoUser.IJoin. The system validates uniqueness of email and password complexity per security requirements. After successful registration, a JWT token is generated and returned in IMultiUserTodoUser.IAuthorized response allowing immediate authenticated access.
   *
   * Security considerations prevent duplicate email registration. Passwords are hashed securely.
   *
   * This join operation is the entry point to create user accounts and is necessary before login and refresh can be used.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body User registration data
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Implement join logic using user registration service. Validate email uniqueness, password complexity, and create new user record. Issue JWT token upon success. Handle duplicate email conflicts, validation errors. Ensure password is securely hashed before storage.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoUser.IJoin,
  ): Promise<IMultiUserTodoUser.IAuthorized> {
    try {
      return await postMultiUserTodoAuthUserJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation allows an existing user of kind "user" to log in to the multi-user todo application by providing valid email and password credentials as specified in IMultiUserTodoUser.ILogin. Upon successful authentication, a JWT authorization token is returned which allows further API access.
   *
   * Security checks prevent unauthorized access by validating credentials.
   *
   * Login is required for members and admins to authenticate existing accounts.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body User login credentials
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Implement login logic using authentication service. Validate user's email and password against stored credentials. On success, generate JWT token for authorization and return in IMultiUserTodoUser.IAuthorized response. Handle invalid credentials and account status checks.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoUser.ILogin,
  ): Promise<IMultiUserTodoUser.IAuthorized> {
    try {
      return await postMultiUserTodoAuthUserLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation allows an authenticated user of kind "user" to refresh their JWT authorization tokens by providing a valid refresh token as specified in IMultiUserTodoUser.IRefresh. On successful validation of the refresh token, a new JWT authorization token is issued, allowing uninterrupted access without re-login.
   *
   * This is critical for maintaining secure and continuous sessions.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh request
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Implement token refresh logic to accept a refresh token and issue a new JWT authorization token for continued access. Validate refresh token integrity and expiration before issuing new tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMultiUserTodoUser.IRefresh,
  ): Promise<IMultiUserTodoUser.IAuthorized> {
    try {
      return await postMultiUserTodoAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
