import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoUser } from "../../../../api/structures/IMultiUserTodoUser";
import { postMultiUserTodoAuthUserJoin } from "../../../../providers/postMultiUserTodoAuthUserJoin";
import { postMultiUserTodoAuthUserLogin } from "../../../../providers/postMultiUserTodoAuthUserLogin";
import { postMultiUserTodoAuthUserRefresh } from "../../../../providers/postMultiUserTodoAuthUserRefresh";

@Controller("/multiUserTodo/auth/user")
export class MultiusertodoAuthUserController {
  /**
   * This API operation allows an unauthenticated user to register a new account by providing a unique email and password, fulfilling the join operation requirements for the user actor. The underlying database schema supports unique email constraints and hashed password storage, ensuring secure user credentials management. Post-registration, the system issues JWT tokens encapsulated in the authorized response type allowing immediate authenticated interactions. This operation is publicly accessible as it creates new user accounts.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Join request payload with email and password credentials
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Service layer will create a new user record upon successful validation of email uniqueness and password complexity rules. Passwords will be hashed before storage. The operation creates JWT tokens for authenticated sessions upon success. Database transaction handled to rollback on failure. Validation errors are returned for duplicate email or invalid inputs. Integration with email verification system possible but out of scope here.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoUser.IJoin,
  ): Promise<IMultiUserTodoUser.IAuthorized> {
    try {
      return await postMultiUserTodoAuthUserJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API operation enables registered users to authenticate by providing email and password credentials, fulfilling the login operation requirements for the user actor. It validates credentials against securely stored hashed passwords in the user database table. Upon successful authentication, JWT tokens are issued to maintain session state securely. The operation is essential for members to access protected resources and performs credential validation securely.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login request with email and password to authenticate user
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Service layer authenticates user credentials by verifying submitted email and password against stored hashed password. Upon success, generates new JWT access and refresh tokens. Returns authorized response DTO with tokens and user identity. Authentication failures return appropriate HTTP 401 errors. This operation is securely rate-limited to prevent brute-force attacks.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoUser.ILogin,
  ): Promise<IMultiUserTodoUser.IAuthorized> {
    try {
      return await postMultiUserTodoAuthUserLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API operation allows authenticated users to refresh their JWT tokens using a valid refresh token, fulfilling the token refresh operation requirements for the user actor. It securely manages token lifecycle ensuring continuous access without repeated logins. The operation requires only the refresh token and returns a new authorized response with up-to-date tokens. This enhances user experience and session security, complying with JWT token management policies.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh request with refresh token to renew access tokens
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Service layer verifies the provided refresh token from request payload. If valid and not expired, new access and refresh JWT tokens are generated and returned. Implements token rotation and revocation mechanisms as per security policies. Invalid or expired tokens result in HTTP 401 errors. This operation supports maintaining authenticated sessions without requiring user credentials each time.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMultiUserTodoUser.IRefresh,
  ): Promise<IMultiUserTodoUser.IAuthorized> {
    try {
      return await postMultiUserTodoAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
