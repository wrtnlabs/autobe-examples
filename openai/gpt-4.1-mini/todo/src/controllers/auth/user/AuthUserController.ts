import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { UserAuth } from "../../../decorators/UserAuth";
import { UserPayload } from "../../../decorators/payload/UserPayload";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoListUser } from "../../../api/structures/ITodoListUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Register a new user account in the 'todo_list_users' table.
   *
   * Register a new user account in the Todo list application's user entity.
   * This operation creates a user record with a unique email and securely
   * hashed password, represented by the 'password_hash' field in the
   * 'todo_list_users' Prisma model. As part of the authentication system, it
   * issues initial JWT tokens upon successful registration, enabling the user
   * to access protected resources.
   *
   * The operation is public and does not require prior authentication,
   * consistent with typical join flows for member users.
   *
   * The user's email must be unique, as enforced by the 'email' field unique
   * index. The password is never stored in plain text, ensuring secure login
   * practices.
   *
   * This operation is the entry point for new users to become authenticated
   * members and is foundational for all subsequent user actions in the Todo
   * list system.
   *
   * Related operations include login and token refresh, which validate
   * credentials and maintain session continuity.
   *
   * @param connection
   * @param body User registration data payload containing required fields for
   *   account creation.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.ICreate,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a user and issue JWT tokens from 'todo_list_users' table.
   *
   * Authenticate a registered user by verifying email and password in
   * 'todo_list_users' table. This operation compares provided credentials
   * against stored hashed passwords represented by the 'password_hash' field.
   * Successful login issues JWT tokens for access and refresh.
   *
   * Security considerations include safeguarding password hashes and rate
   * limiting to prevent brute force attacks.
   *
   * This operation is public and marks the start of an authenticated session
   * for a user.
   *
   * Related API operations are user registration (/auth/user/join) and token
   * refresh (/auth/user/refresh).
   *
   * @param connection
   * @param body User login credentials payload.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.ILogin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT authentication tokens for user.
   *
   * Refresh authentication JWT tokens for the user, allowing continuous
   * authenticated sessions without requiring login credentials again. The
   * operation leverages existing user identification data in the
   * 'todo_list_users' table.
   *
   * Token refresh enhances security by issuing new tokens only when presented
   * with a valid refresh token.
   *
   * This endpoint is restricted to authenticated users with valid refresh
   * tokens.
   *
   * It complements join and login operations forming the core authentication
   * flow.
   *
   * @param connection
   * @param body Payload containing refresh token for renewing authentication
   *   tokens.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.IRefresh,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
