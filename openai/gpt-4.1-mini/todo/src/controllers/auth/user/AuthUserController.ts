import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { UserAuth } from "../../../decorators/UserAuth";
import { UserPayload } from "../../../decorators/payload/UserPayload";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoUser } from "../../../api/structures/ITodoUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Create new member user account for todo_users table.
   *
   * This API endpoint enables registration of new user accounts in the
   * todo_users table, specifically for members who are authenticated users
   * managing their personal todo list items. It expects email and password hash
   * (hashed client-side or server-side) to be securely stored. The operation
   * creates a new todo_users record with created_at and updated_at timestamps,
   * generating unique user ID and issuing authorization tokens upon successful
   * account creation. Security measures ensure passwords are properly hashed
   * and stored securely. The registration process does not require any prior
   * authentication and is open for new users joining the system. It is a
   * critical starting point for user authentication workflows, followed by
   * login and refresh token maintenance.
   *
   * @param connection
   * @param body User registration information for creating a new todo_users
   *   record
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUser.ICreate,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate member user and issue tokens for todo_users table.
   *
   * This API endpoint manages user login for the todo_users table, designed for
   * members who authenticate using email and password. It verifies provided
   * credentials against stored password hashes and creates a new session record
   * in todo_user_sessions for tracking. Upon success, it issues JWT tokens,
   * including access and refresh tokens, containing user ID and permissions
   * array. Security best practices mandate that passwords are securely compared
   * and never exposed. Login is the gateway operation enabling authorized
   * access to personal todo list items and associated operations. This endpoint
   * is publicly accessible and essential for authentication.
   *
   * @param connection
   * @param body Login credentials for existing user
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUser.ILogin,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT tokens for member users in todo_users table.
   *
   * This API endpoint enables refreshing of JWT tokens for member users in the
   * todo_users table. It accepts a valid refresh token, validates token expiry
   * and session status, then issues new access and refresh tokens to maintain
   * user authentication state. This preserves security by limiting the lifespan
   * of access tokens while providing seamless session extension. The operation
   * is critical to token lifecycle management and is publicly accessible for
   * authorized token renewal procedures. Refresh tokens expire in line with
   * session expiration policies.
   *
   * @param connection
   * @param body Refresh token information for renewing access
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUser.IRefresh,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
