import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserTwoFactorEnable } from "../../../../../providers/postAuthUserTwoFactorEnable";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoListTodoListUser } from "../../../../../api/structures/ITodoListTodoListUser";

@Controller("/auth/user/two-factor/enable")
export class AuthUserTwo_factorEnableController {
  /**
   * Allows users to enable two-factor authentication for their accounts using
   * fields and tokens defined in the 'todo_list_users' table.
   *
   * Improves security posture by requiring additional authentication factors.
   *
   * Includes token generation and validation mechanisms.
   *
   * Part of extended authentication features when schema supports them.
   *
   * Omitted if the todo_list_users schema lacks 2FA-related fields.
   *
   * @param connection
   * @param body 2FA enablement request conforming to
   *   ITodoListUser.IEnableTwoFactor schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async enableTwoFactor(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodoListUser.IEnableTwoFactor,
  ): Promise<void> {
    try {
      return await postAuthUserTwoFactorEnable({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
