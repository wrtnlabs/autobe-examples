import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserPasswordChange } from "../../../../../providers/postAuthUserPasswordChange";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoListTodoListUser } from "../../../../../api/structures/ITodoListTodoListUser";

@Controller("/auth/user/password/change")
export class AuthUserPasswordChangeController {
  /**
   * Change user password in todo_list_users table.
   *
   * Allows a registered user to securely change their password providing
   * current and new password data. This operation utilizes fields defined in
   * the 'todo_list_users' schema to perform validation and update.
   *
   * Supports enforcing password complexity and security policies.
   *
   * Critical for user account security and session integrity.
   *
   * Requires proper validation of current password before changes are applied.
   *
   * Only available if schema supports relevant password fields.
   *
   * @param connection
   * @param body Password change request conforming to
   *   ITodoListUser.IChangePassword schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async changePassword(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodoListUser.IChangePassword,
  ): Promise<void> {
    try {
      return await postAuthUserPasswordChange({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
