import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserEmailVerify } from "../../../../../providers/postAuthUserEmailVerify";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoListTodoListUser } from "../../../../../api/structures/ITodoListTodoListUser";

@Controller("/auth/user/email/verify")
export class AuthUserEmailVerifyController {
  /**
   * This operation enables registered users to verify their email addresses as
   * part of account confirmation. It utilizes verification fields and tokens in
   * the 'todo_list_users' schema to update verification status.
   *
   * Ensures security through validation and token expiration controls.
   *
   * Necessary for email-based verification workflows.
   *
   * Integration with authentication systems provides full user lifecycle
   * support.
   *
   * Excluded if the schema does not support email verification.
   *
   * @param connection
   * @param body Email verification data conforming to
   *   ITodoListUser.IVerifyEmail schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async verifyEmail(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodoListUser.IVerifyEmail,
  ): Promise<void> {
    try {
      return await postAuthUserEmailVerify({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
