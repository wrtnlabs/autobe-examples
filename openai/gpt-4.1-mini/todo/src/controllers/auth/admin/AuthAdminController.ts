import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { AdminAuth } from "../../../decorators/AdminAuth";
import { AdminPayload } from "../../../decorators/payload/AdminPayload";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { ITodoListAdmin } from "../../../api/structures/ITodoListAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Register a new admin account in the Todo List system.
   *
   * This API operation facilitates the registration of a new administrator
   * account within the Todo List system. It directly interfaces with the
   * todo_list_admins Prisma table storing admin credentials such as email and
   * hashed password.
   *
   * Security measures include validation of unique admin email addresses and
   * secure password hashing before storing in the database.
   *
   * Admins created through this endpoint possess full administrative privileges
   * for managing users and todo items.
   *
   * All input data is strictly validated for format correctness, and security
   * policies are enforced to prevent unauthorized account creation.
   *
   * Following successful registration, an authorized JWT token response is
   * returned, facilitating authenticated sessions within the administration
   * interface.
   *
   * @param connection
   * @param body Request payload to register a new admin user.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.ICreate,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an admin and issue access tokens.
   *
   * This API operation manages administrative user login for the Todo List
   * application. It verifies provided email and password credentials against
   * the stored hashed password in the todo_list_admins Prisma table.
   *
   * Successful authentication results in the issuance of JWT tokens that
   * authorize access to protected administrative resources.
   *
   * Security best practices ensure that password hashes are never exposed, and
   * all authentication attempts are logged for audit purposes.
   *
   * The operation requires accurate and verified credentials, failing which
   * access is denied with appropriate error responses.
   *
   * This login endpoint is a critical component of the administration security
   * model, enabling controlled access to all backend resources linked to admin
   * operations.
   *
   * @param connection
   * @param body Admin login credentials payload.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.ILogin,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh admin access tokens using a valid refresh token.
   *
   * This API operation provides token refresh capabilities for administrators
   * of the Todo List application. It accepts a valid refresh token and issues
   * new JWT access and refresh tokens upon verification.
   *
   * The operation ensures that only authenticated admin users can maintain
   * active sessions, preventing unauthorized access due to token expiry.
   *
   * Token revocation, expiration policies, and refresh limits are enforced to
   * maintain security integrity.
   *
   * This refresh endpoint is vital for smooth user experiences in the admin
   * interface, avoiding frequent logins.
   *
   * Proper error handling ensures that invalid or expired refresh tokens cause
   * session termination and reauthentication requirements.
   *
   * @param connection
   * @param body Payload containing the refresh token for the admin.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.IRefresh,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
