import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthGuestJoin } from "../../../providers/postAuthGuestJoin";
import { GuestAuth } from "../../../decorators/GuestAuth";
import { GuestPayload } from "../../../decorators/payload/GuestPayload";
import { postAuthGuestRefresh } from "../../../providers/postAuthGuestRefresh";

import { ITodoListGuest } from "../../../api/structures/ITodoListGuest";

@Controller("/auth/guest")
export class AuthGuestController {
  /**
   * This operation enables unauthenticated users to register temporary guest
   * accounts. It creates a limited-access guest record in the database,
   * providing minimal permissions suitable for public resource viewing. The
   * database fields involved typically include the guest identifier and any
   * session linkage if applicable. This process does not require credentials,
   * allowing fast onboarding for temporary access. The operation's security
   * considerations involve limiting permissions for guests and secure issuance
   * of temporary JWT tokens. It integrates with the refresh operation to renew
   * guest tokens as necessary.
   *
   * @param connection
   * @param body Guest join request body with necessary join information.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: ITodoListGuest.IJoin,
  ): Promise<ITodoListGuest.IAuthorized> {
    try {
      return await postAuthGuestJoin({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation allows guest users to renew their JWT access tokens by
   * providing a valid refresh token. It maintains session continuity for
   * temporary guest accounts with limited permissions. The underlying database
   * schema supports token validity checks and expiration management for guest
   * sessions. Security considerations include validating the refresh token,
   * preventing token theft, and limiting refresh capabilities to guests only.
   * The integration complements the join operation to ensure seamless temporary
   * access.
   *
   * @param connection
   * @param body Refresh token request body containing the refresh token string.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: ITodoListGuest.IRefresh,
  ): Promise<ITodoListGuest.IAuthorized> {
    try {
      return await postAuthGuestRefresh({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
