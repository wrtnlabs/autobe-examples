import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthGuestJoin } from "../../../providers/postAuthGuestJoin";
import { GuestAuth } from "../../../decorators/GuestAuth";
import { GuestPayload } from "../../../decorators/payload/GuestPayload";
import { postAuthGuestRefresh } from "../../../providers/postAuthGuestRefresh";

import { ITodoAppGuest } from "../../../api/structures/ITodoAppGuest";

@Controller("/auth/guest")
export class AuthGuestController {
  /**
   * This endpoint allows unauthenticated users to register as guest users. It
   * creates a temporary guest account, issuing initial JWT tokens for session
   * management. The operation corresponds to the 'todo_app_guests' database
   * table representing guest entities. No credential login is needed as guests
   * have implicit limited access. The operation is public and requires no prior
   * authentication.
   *
   * Security considerations focus on preventing abuse of guest registrations
   * through rate limiting and request validation. Token issuance follows
   * stateless JWT patterns ensuring secure short-term access.
   *
   * This operation initiates the guest authentication lifecycle providing
   * tokens necessary for accessing guest-level resources.
   *
   * Related operations include the refresh token endpoint which enables token
   * renewal without re-registration.
   *
   * Clients should call POST /auth/guest/join to create a new guest user
   * session and receive authorized tokens.
   *
   * @param connection
   * @param body Payload for registering a new guest user.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: ITodoAppGuest.IJoin,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postAuthGuestJoin({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint allows guest users to refresh their JWT access tokens,
   * extending their authenticated session without the need to re-register. It
   * validates the provided refresh token against the guest session information
   * stored in the 'todo_app_guests' table.
   *
   * The operation ensures seamless guest user experience through token
   * lifecycle management. It is restricted to authenticated guests presenting
   * valid refresh tokens.
   *
   * Upon successful validation, new JWT tokens are issued following secure
   * token handling practices.
   *
   * This operation complements the join operation, maintaining temporary
   * authenticated sessions.
   *
   * Clients should call POST /auth/guest/refresh with a valid refresh token in
   * the request body.
   *
   * @param connection
   * @param body Payload containing the guest refresh token for JWT renewal.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: ITodoAppGuest.IRefresh,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postAuthGuestRefresh({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
