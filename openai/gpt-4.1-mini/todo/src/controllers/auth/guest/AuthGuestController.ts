import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthGuestJoin } from "../../../providers/postAuthGuestJoin";
import { GuestAuth } from "../../../decorators/GuestAuth";
import { GuestPayload } from "../../../decorators/payload/GuestPayload";
import { postAuthGuestRefresh } from "../../../providers/postAuthGuestRefresh";

import { ITodoListTodoListGuest } from "../../../api/structures/ITodoListTodoListGuest";

@Controller("/auth/guest")
export class AuthGuestController {
  /**
   * Guest user registration operation creating temporary guest account with JWT
   * tokens.
   *
   * This API operation allows unauthenticated guest users to register a
   * temporary account. It creates a guest record in the todo_list_guests table,
   * issuing JWT authorization tokens for limited interaction. This endpoint
   * requires no authentication and serves as the entry point for guest access.
   *
   * @param connection
   * @param body Guest account creation request payload matching
   *   todo_list_guests schema.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: ITodoListTodoListGuest.ICreate,
  ): Promise<ITodoListTodoListGuest.IAuthorized> {
    try {
      return await postAuthGuestJoin({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT tokens for guest user to maintain session continuity.
   *
   * This endpoint refreshes JWT access tokens for a guest user using a valid
   * refresh token. It validates the refresh token, issues new access tokens,
   * and provides continued access for guest users as defined in the
   * todo_list_guests schema. This endpoint requires an authorized refresh token
   * for security.
   *
   * @param connection
   * @param body Payload containing guest user's refresh token to validate and
   *   renew access tokens.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: ITodoListTodoListGuest.IRefresh,
  ): Promise<ITodoListTodoListGuest.IAuthorized> {
    try {
      return await postAuthGuestRefresh({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
