import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthTodoListMemberJoin } from "../../../providers/postAuthTodoListMemberJoin";
import { postAuthTodoListMemberLogin } from "../../../providers/postAuthTodoListMemberLogin";
import { postAuthTodoListMemberRefresh } from "../../../providers/postAuthTodoListMemberRefresh";

import { ITodoListTodolistmember } from "../../../api/structures/ITodoListTodolistmember";

@Controller("/auth/todoListMember")
export class AuthTodolistmemberController {
  /**
   * Register a new todoListMember account (todo_list_todolistmembers table) and
   * issue initial JWT tokens.
   *
   * This API endpoint registers a new todoListMember (regular authenticated
   * user) by creating a new record in the todo_list_todolistmembers table,
   * using supplied registration information such as email, password, and other
   * required authentication fields confirmed by schema. All required
   * validations, such as unique email and password policy, are enforced at both
   * the database and application logic levels.
   *
   * Upon successful registration, the endpoint issues JWT access and refresh
   * tokens through the ITodoListTodoListMember.IAuthorized DTO contract, with
   * minimal user information. Security is carefully managed: only public-safe
   * account details are returned, and sensitive data (e.g., password hashes) is
   * never included in the payload. Failed registration attempts due to
   * validation, duplication, or policy violation return precise errors
   * referencing validation logic and schema/business rules.
   *
   * This endpoint is directly related to the todo_list_todolistmembers Prisma
   * DB table, reflecting its field requirements and unique constraints.
   * Registration success implies immediate authentication via JWT. The security
   * design restricts data visibility to the registering user only, safeguarding
   * system integrity.
   *
   * Future authentication flows (login and token refresh) depend on successful
   * user creation here. Registration is the only entry for new todoListMember
   * accounts.
   *
   * Related endpoints: /auth/todoListMember/login for authentication,
   * /auth/todoListMember/refresh for token renewal.
   *
   * @param connection
   * @param body Registration data for new todoListMember. Must include all
   *   required fields for todo_list_todolistmembers as defined in the schema.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListTodolistmember.ICreate,
  ): Promise<ITodoListTodolistmember.IAuthorized> {
    try {
      return await postAuthTodoListMemberJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a todoListMember using credentials and issue JWT tokens
   * (todo_list_todolistmembers table).
   *
   * Authenticate a todoListMember by verifying their credentials (such as email
   * and password) against the todo_list_todolistmembers table. Only actors with
   * valid, existing accounts in the table and proper credentials will be
   * authenticated. Secure password comparison, account state checks, and
   * validation error handling are all built using schema-enforced fields.
   *
   * JWT tokens (access and refresh) are issued upon successful login through
   * the ITodoListTodoListMember.IAuthorized DTO. No sensitive authentication
   * data is ever returned in the payload; only session-safe and necessary user
   * information is included.
   *
   * Account lockout, password retry limitations, and disabling policies are
   * enforced as per schema and requirements; failures always provide clear
   * error responses indicating reason for denial, referencing both business and
   * DB rules.
   *
   * This endpoint is directly dependent on successful registration using
   * /auth/todoListMember/join, and it must work in concert with the refresh
   * endpoint for token renewal. The login operation is public and does not
   * require prior authentication.
   *
   * @param connection
   * @param body Login credentials for todoListMember account (must include
   *   fields validated in schema, such as email and password).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListTodolistmember.ILogin,
  ): Promise<ITodoListTodolistmember.IAuthorized> {
    try {
      return await postAuthTodoListMemberLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT tokens for an authenticated todoListMember using the session
   * table.
   *
   * Refresh JWT tokens for an authenticated todoListMember session. The
   * endpoint uses the todo_list_todolistmember_sessions table to validate the
   * provided refresh token (checking for existence, expiry, revocation, and
   * association with an active todoListMember account) before issuing new
   * tokens. All relevant validation and session management rules are enforced
   * at both schema and application levels.
   *
   * A valid, non-expired refresh token is required in the request body; invalid
   * or revoked tokens will fail securely with a clear error response. No user
   * account or sensitive session state is returned except new tokens (as
   * ITodoListTodoListMember.IAuthorized contract). The entire workflow matches
   * business and system security requirements for session renewal.
   *
   * Credential compromise and replay attack risks are mitigated based on
   * field-verified logic enforced in the session schema, and only accounts in
   * active state may obtain refreshed tokens through this endpoint.
   *
   * This operation should be used in conjunction with
   * /auth/todoListMember/login and /auth/todoListMember/join endpoints for a
   * complete authentication lifecycle.
   *
   * Related resources include the underlying todo_list_todolistmember_sessions
   * schema.
   *
   * @param connection
   * @param body Refresh token payload (must match schema-defined fields for
   *   token validation).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListTodolistmember.IRefresh,
  ): Promise<ITodoListTodolistmember.IAuthorized> {
    try {
      return await postAuthTodoListMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
