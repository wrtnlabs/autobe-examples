import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { getTodoListTodoListMemberActorsMe } from "../../../../../providers/getTodoListTodoListMemberActorsMe";
import { TodolistmemberAuth } from "../../../../../decorators/TodolistmemberAuth";
import { TodolistmemberPayload } from "../../../../../decorators/payload/TodolistmemberPayload";
import { putTodoListTodoListMemberActorsMe } from "../../../../../providers/putTodoListTodoListMemberActorsMe";
import { deleteTodoListTodoListMemberActorsMe } from "../../../../../providers/deleteTodoListTodoListMemberActorsMe";

import { ITodoListTodolistmember } from "../../../../../api/structures/ITodoListTodolistmember";

@Controller("/todoList/todoListMember/actors/me")
export class TodolistTodolistmemberActorsMeController {
  /**
   * Retrieve authenticated user's todoListMember profile from the database.
   *
   * Retrieve the authenticated user's account information in the Todo List
   * application.
   *
   * This endpoint provides the current todoListMember with their account
   * details, such as email and account creation date, directly from the
   * todo_list_todolistmembers table. The response excludes sensitive data like
   * the password hash, complying with privacy and security requirements.
   *
   * Access to this operation is strictly limited to the authenticated session's
   * user. Attempts to access this endpoint without authentication result in an
   * error, and unauthorized attempts to access another user's data are
   * prevented by business logic and session validation. There is no
   * administrative override or sharing; every account is strictly personal.
   *
   * This operation integrates with business rules enforcing strict data
   * isolation. It should be used by frontends for displaying user profile
   * information or confirming successful login. Related endpoints include
   * updating personal account information or deleting one's account.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TodolistmemberAuth()
    todoListMember: TodolistmemberPayload,
  ): Promise<ITodoListTodolistmember> {
    try {
      return await getTodoListTodoListMemberActorsMe({
        todoListMember,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update authenticated user's todoListMember account email.
   *
   * Update the email address associated with the authenticated user's
   * todoListMember account.
   *
   * This endpoint processes requests from the logged-in user to change their
   * own email address, as long as the new email conforms to uniqueness and
   * format rules defined in the todo_list_todolistmembers table. All other
   * fields are either immutable via this endpoint or handled through dedicated
   * flows.
   *
   * Ownership is strictly enforced by session validation. Attempts to update
   * other attributes (e.g., password) or other users' data via this endpoint
   * are rejected at both the API level and in the business logic. The system
   * ensures the requested email remains unique, and changes trigger the
   * appropriate updated_at timestamp. Security and privacy best practices
   * ensure sensitive data is never accepted or returned.
   *
   * Related operations for password or account deletion are implemented
   * separately. This update flow requires authentication and only affects the
   * session owner's data.
   *
   * @param connection
   * @param body New email address to update for the authenticated user's own
   *   account. Must be unique and valid.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @TodolistmemberAuth()
    todoListMember: TodolistmemberPayload,
    @TypedBody()
    body: ITodoListTodolistmember.IUpdate,
  ): Promise<ITodoListTodolistmember> {
    try {
      return await putTodoListTodoListMemberActorsMe({
        todoListMember,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete the authenticated todo list member's account
   * (todo_list_todolistmembers table).
   *
   * Delete the currently authenticated todo list member account and all
   * personal data.
   *
   * This operation allows a user to permanently erase their own account from
   * the application, securing irreversible removal of their personal data, todo
   * items, and all session information. Once deleted, the account and all
   * associated resources become unrecoverable.
   *
   * Security enforcement strictly ensures that users can only delete their own
   * account by verifying authentication and ownership and that the operation
   * cannot be triggered for other users' accounts. The system ensures
   * compliance with data privacy and erasure regulations.
   *
   * This endpoint is critical for user autonomy and privacy, and must enforce
   * that account deletion triggers cascading removal of all related items and
   * sessions. Post-deletion, the user is immediately signed out and must
   * register anew to use the service again.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @TodolistmemberAuth()
    todoListMember: TodolistmemberPayload,
  ): Promise<void> {
    try {
      return await deleteTodoListTodoListMemberActorsMe({
        todoListMember,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
