import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoListTodoListMemberTodos } from "../../../../providers/postTodoListTodoListMemberTodos";
import { TodolistmemberAuth } from "../../../../decorators/TodolistmemberAuth";
import { TodolistmemberPayload } from "../../../../decorators/payload/TodolistmemberPayload";
import { patchTodoListTodoListMemberTodos } from "../../../../providers/patchTodoListTodoListMemberTodos";
import { getTodoListTodoListMemberTodosTodoId } from "../../../../providers/getTodoListTodoListMemberTodosTodoId";
import { putTodoListTodoListMemberTodosTodoId } from "../../../../providers/putTodoListTodoListMemberTodosTodoId";
import { deleteTodoListTodoListMemberTodosTodoId } from "../../../../providers/deleteTodoListTodoListMemberTodosTodoId";

import { ITodoListTodo } from "../../../../api/structures/ITodoListTodo";
import { IPageITodoListTodo } from "../../../../api/structures/IPageITodoListTodo";

@Controller("/todoList/todoListMember/todos")
export class TodolistTodolistmemberTodosController {
  /**
   * Create a new todo in the todo_list_todos table for the authenticated user.
   *
   * Create a new todo item for the authenticated user. This endpoint allows a
   * user to add a new task to their private collection of todos. Each todo must
   * have a unique title (per user) and may include an optional longer
   * description along with its initial completion status (which defaults to
   * incomplete if omitted).
   *
   * Only the owner can create todos; there is no support for public, shared, or
   * admin-managed task creation. Security is strictly enforced through
   * authentication, ensuring users cannot create todos for other accounts. The
   * timestamps for creation and the most recent update are set server-side and
   * are not client-modifiable.
   *
   * Input validation checks title length (1-100 characters, non-blank),
   * optional description (up to 1000 characters), and that initial completion
   * status is boolean. Uniqueness of a todo’s title is enforced at both
   * business and database layer for every individual user. Related endpoints
   * include updating and deleting todos (by ID) which also require strict
   * ownership.
   *
   * @param connection
   * @param body Creation payload for a new todo, including unique title,
   *   optional description, and initial completion status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TodolistmemberAuth()
    todoListMember: TodolistmemberPayload,
    @TypedBody()
    body: ITodoListTodo.ICreate,
  ): Promise<ITodoListTodo> {
    try {
      return await postTodoListTodoListMemberTodos({
        todoListMember,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated list of personal todo_list_todos records
   * for the authenticated user.
   *
   * Retrieve a filtered and paginated list of the authenticated user's todo
   * items, including support for filtering by completion status, date ranges,
   * and search terms on title or description.
   *
   * This operation strictly enforces per-user data boundaries as described in
   * the prisma schema and requirements analysis. Only the currently
   * authenticated todoListMember can retrieve their own todos; no collaborative
   * or administrative listing is permitted. The operation validates that
   * pagination and filter queries adhere to business rules, such as creation
   * and update date ordering, and rate limiting.
   *
   * The todo_list_todos schema mandates field validation: title (1-100 chars,
   * unique per user), description (up to 1000 chars), is_complete (boolean),
   * and timestamps. Clients may sort results and filter by these properties as
   * allowed. All response data is guaranteed to be owned by the authenticated
   * user and paginated for performance and quota enforcement. If no todos exist
   * for the user, an empty, but paginated, result is returned.
   *
   * @param connection
   * @param body Advanced search, filter, sort, and pagination parameters for
   *   retrieving the authenticated user's todo items.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TodolistmemberAuth()
    todoListMember: TodolistmemberPayload,
    @TypedBody()
    body: ITodoListTodo.IRequest,
  ): Promise<IPageITodoListTodo.ISummary> {
    try {
      return await patchTodoListTodoListMemberTodos({
        todoListMember,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific todo_list_todos record owned
   * by the authenticated user.
   *
   * Retrieve complete details of a single todo item by its unique identifier,
   * strictly limited to the authenticated user's own data as defined by the
   * todo_list_todos Prisma schema.
   *
   * Access is permitted only if the todo's todo_list_todolistmember_id matches
   * the current session; otherwise, a clear error is returned as per
   * requirements. The response includes all fields: title, description,
   * is_complete, timestamps, and completed_at as applicable. Attempting to
   * retrieve another user's todo or a non-existent ID results in a permission
   * or not found error, with no data leakage.
   *
   * All business constraints from the requirements are enforced, including:
   * field validation, ownership, and the irreversibility of deletions (no
   * recovery for removed items). The operation forms part of the minimal CRUD
   * suite for personal todo management.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo (owned by the
   *   authenticated todoListMember).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @TodolistmemberAuth()
    todoListMember: TodolistmemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodo> {
    try {
      return await getTodoListTodoListMemberTodosTodoId({
        todoListMember,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo in the todo_list_todos table, identified by todoId,
   * for the authenticated user.
   *
   * Update the details of an existing todo item that belongs to the
   * authenticated user. This includes changing its title (which must remain
   * unique for the user), updating its description, or toggling completion
   * status. The completed_at field will be set or cleared automatically based
   * on is_complete status.
   *
   * The endpoint requires authentication and only allows the todo’s actual
   * owner to apply updates. Security and data isolation are enforced through
   * user-token verification and strict ownership checks. All input fields are
   * validated according to business logic and Prisma schema constraints; no
   * cross-user updates or admin overrides are allowed.
   *
   * If the title is updated, it must not duplicate another of the user's todos.
   * The operation automatically updates timestamps for auditability and
   * preserves referential integrity to the owning user.
   *
   * @param connection
   * @param todoId The unique identifier (UUID) of the todo to update, as
   *   assigned at creation.
   * @param body Full or partial update data for the todo, including new title,
   *   description, and/or completion status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @TodolistmemberAuth()
    todoListMember: TodolistmemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListTodo.IUpdate,
  ): Promise<ITodoListTodo> {
    try {
      return await putTodoListTodoListMemberTodosTodoId({
        todoListMember,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a specific todo from the authenticated user's list
   * (todo_list_todos table).
   *
   * Delete a specific todo item from the Todo List application.
   *
   * This operation allows an authenticated user to permanently remove a todo
   * item identified by its unique identifier. Upon invocation, the system
   * performs an authorization check to ensure that only the owner of the todo
   * may execute this operation. The deletion is irreversible; all data
   * associated with the todo is removed from persistent storage, and there is
   * no soft delete or recovery provided. The operation enforces all validation
   * and business rules defined by the 'todo_list_todos' table schema, including
   * checks for foreign key integrity and any additional deletion
   * prerequisites.
   *
   * Security is enforced at the application service layer, requiring the
   * authenticated user to be the owner of the target todo. No data is returned
   * if the deletion is successful, and clients should handle both success and
   * any failure conditions (such as attempting to delete a non-existent or
   * inaccessible todo) according to standard error response patterns. This
   * endpoint operates independently of the authentication/session mechanism,
   * focusing solely on todo resource cleanup within a member's list.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item belonging to the
   *   Todo List application member
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @TodolistmemberAuth()
    todoListMember: TodolistmemberPayload,
    @TypedParam("todoId")
    todoId: string,
  ): Promise<void> {
    try {
      return await deleteTodoListTodoListMemberTodosTodoId({
        todoListMember,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
