import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoListTodoListGuestsId } from "../../../providers/getTodoListTodoListGuestsId";
import { postTodoListTodoListGuests } from "../../../providers/postTodoListTodoListGuests";

import { ITodoListGuest } from "../../../api/structures/ITodoListGuest";

@Controller("/todoList/todoListGuests")
export class TodolistTodolistguestsController {
  /**
   * Retrieve details of a specific Todo List guest by ID.
   *
   * Retrieve detailed information of a registered guest identified by their
   * unique ID within the Todo List system.
   *
   * This operation allows any requester to obtain information about a guest
   * user using their unique UUID. The guest data includes all personal and
   * session-related details stored, enabling viewing the guest's profile.
   *
   * Security considerations include public accessibility as guests are
   * non-authenticated users. The endpoint requires precise identification of
   * the guest via the path parameter.
   *
   * This operation maps directly to the TodoListGuests Prisma table, reflecting
   * the structure and contents of guest records in the database.
   *
   * @param connection
   * @param id Unique identifier of the Todo List guest
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<ITodoListGuest> {
    try {
      return await getTodoListTodoListGuestsId({
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new Todo List guest.
   *
   * Create a new guest user within the Todo List system.
   *
   * This operation allows registering a guest user by submitting guest details.
   * The server generates a unique identifier and stores the guest data
   * accordingly.
   *
   * No authentication is required since this is for guest creation. Proper
   * validation and storage mechanisms ensure data integrity.
   *
   * Related operations include retrieving guest details and listing guests.
   *
   * @param connection
   * @param body Data needed to create a new Todo List guest
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: ITodoListGuest.ICreate,
  ): Promise<ITodoListGuest> {
    try {
      return await postTodoListTodoListGuests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
