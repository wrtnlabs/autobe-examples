import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListTodoListGuests } from "../../../providers/patchTodoListTodoListGuests";
import { getTodoListTodoListGuestsId } from "../../../providers/getTodoListTodoListGuestsId";

import { IPageITodoListTodoListGuest } from "../../../api/structures/IPageITodoListTodoListGuest";
import { ITodoListTodoListGuest } from "../../../api/structures/ITodoListTodoListGuest";

@Controller("/todoList/todoListGuests")
export class TodolistTodolistguestsController {
  /**
   * Search and retrieve a filtered, paginated list of guest todo items.
   *
   * Retrieve a filtered and paginated list of guest todo items stored in the
   * system. This operation provides advanced search features for finding todo
   * entries by criteria including partial content matching, completion status,
   * priority levels, and date ranges for creation and updates.
   *
   * The operation supports comprehensive pagination with options for page size,
   * number, and sorting order. Guests can efficiently browse and search their
   * todo items with rich filters.
   *
   * Security considerations include limiting access only to public
   * unauthenticated access since these entries are associated with guests. No
   * authentication actors required.
   *
   * This operation interacts with the todo_list_guests table as defined in the
   * Prisma schema, utilizing all defined fields for filtering and projection.
   * The response is a paginated list of summarized todo items optimized for
   * guest client display.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for guest todo items
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: ITodoListTodoListGuest.IRequest,
  ): Promise<IPageITodoListTodoListGuest.ISummary> {
    try {
      return await patchTodoListTodoListGuests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a guest todo item by id.
   *
   * Retrieve detailed information on a guest todo item by its unique
   * identifier.
   *
   * This operation allows clients to read a single todo entry for a guest by
   * specifying its id. It returns all fields defined for guest todo items
   * including content, completion status, priority, and timestamps.
   *
   * Security is managed by the public access nature of guest todo items. This
   * endpoint is available without authentication.
   *
   * This operation corresponds directly to the todo_list_guests Prisma table
   * and retrieves one entity by its primary key id.
   *
   * @param connection
   * @param id Unique identifier of the guest todo item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodoListGuest> {
    try {
      return await getTodoListTodoListGuestsId({
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
