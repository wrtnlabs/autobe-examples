import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteTodoListAdminTodoListUsersId } from "../../../../providers/deleteTodoListAdminTodoListUsersId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

@Controller("/todoList/admin/todoListUsers/:id")
export class TodolistAdminTodolistusersController {
  /**
   * Delete a registered todo list user by ID.
   *
   * Permanently delete a registered user by their unique identifier from the
   * todo list system.
   *
   * This operation allows authorized actors to perform a permanent removal of
   * the user record identified by the provided UUID. All associated user data
   * will be erased without recovery options.
   *
   * Security is paramount as deleting a user affects related system resources
   * and permissions. Only administrators or authorized system roles should have
   * access to perform this operation.
   *
   * This operation interacts directly with the todo_list_users table where user
   * authentication credentials and profile data are stored.
   *
   * Use with caution: deleting a user is irreversible and will impact all
   * user-related services and data.
   *
   * @param connection
   * @param id Unique identifier of the target todo list user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminTodoListUsersId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
