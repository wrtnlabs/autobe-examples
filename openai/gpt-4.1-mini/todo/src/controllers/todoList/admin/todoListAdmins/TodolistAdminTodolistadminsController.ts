import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListAdminTodoListAdmins } from "../../../../providers/patchTodoListAdminTodoListAdmins";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getTodoListAdminTodoListAdminsId } from "../../../../providers/getTodoListAdminTodoListAdminsId";
import { putTodoListAdminTodoListAdminsId } from "../../../../providers/putTodoListAdminTodoListAdminsId";
import { deleteTodoListAdminTodoListAdminsId } from "../../../../providers/deleteTodoListAdminTodoListAdminsId";

import { IPageITodoListAdmin } from "../../../../api/structures/IPageITodoListAdmin";
import { ITodoListAdmin } from "../../../../api/structures/ITodoListAdmin";

@Controller("/todoList/admin/todoListAdmins")
export class TodolistAdminTodolistadminsController {
  /**
   * Retrieve a filtered and paginated list of Todo List administrators.
   *
   * Retrieve a paginated list of administrators in the Todo List application.
   * This operation supports advanced filtering options based on the admin's
   * email, creation date, and update timestamps, allowing administrators to
   * search and manage account records effectively.
   *
   * Security considerations include limiting access to authenticated
   * administrators only, enforcing rate-limiting on queries, and ensuring that
   * sensitive fields like password_hash are never exposed in the response.
   *
   * The response provides summarized information optimized for overview
   * displays, including email and timestamps but excluding sensitive details
   * such as password hashes.
   *
   * This operation corresponds to the todo_list_admins table in the Prisma
   * schema.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for querying
   *   administrators
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.IRequest,
  ): Promise<IPageITodoListAdmin.ISummary> {
    try {
      return await patchTodoListAdminTodoListAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a Todo List administrator by ID.
   *
   * Retrieve detailed information of a single administrator by their unique
   * UUID identifier from the todo_list_admins table.
   *
   * This operation requires administrative authorization to ensure sensitive
   * admin account data including email and timestamps is securely accessed.
   *
   * Sensitive information like password_hash is not exposed in the response.
   *
   * This endpoint supports administrative auditing and management of
   * administrator accounts.
   *
   * @param connection
   * @param id Unique identifier of the target Todo List administrator
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<ITodoListAdmin> {
    try {
      return await getTodoListAdminTodoListAdminsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing TodoListAdmin by id.
   *
   * Update an existing administrator's account in the Todo List system.
   *
   * This operation requires the admin's unique UUID 'id' as a path parameter.
   * The request body must include the fields to update such as email and
   * password_hash.
   *
   * The operation will update timestamps to reflect changes. It is intended for
   * administrative use only.
   *
   * Proper authorization is required to perform this update.
   *
   * Related operations include delete (erase) on the same entity.
   *
   * @param connection
   * @param id Unique identifier of the target TodoListAdmin
   * @param body Update data for the TodoListAdmin entity
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListAdmin.IUpdate,
  ): Promise<ITodoListAdmin> {
    try {
      return await putTodoListAdminTodoListAdminsId({
        admin,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a TodoListAdmin by id.
   *
   * Permanently remove an administrator account from the Todo List system.
   *
   * This operation requires the admin's unique UUID 'id' as a path parameter.
   * It performs a hard delete.
   *
   * The operation is restricted to authorized administrative users only.
   *
   * Related operations include update on the same entity.
   *
   * @param connection
   * @param id Unique identifier of the target TodoListAdmin
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminTodoListAdminsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
