import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchTodoListAdminTodoListGuests } from "../../../../providers/patchTodoListAdminTodoListGuests";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

import { IPageITodoListGuest } from "../../../../api/structures/IPageITodoListGuest";
import { ITodoListGuest } from "../../../../api/structures/ITodoListGuest";

@Controller("/todoList/admin/todoListGuests")
export class TodolistAdminTodolistguestsController {
  /**
   * Search and retrieve a filtered, paginated list of guest visitors.
   *
   * Retrieve a filtered and paginated list of guest visitors to the Todo List
   * application.
   *
   * This operation allows administrative users to search, filter, and sort
   * guest visitor records recorded in the 'todo_list_guests' table. Guests
   * represent anonymous users who interact with the platform without
   * registration, identified primarily via visitor IP addresses.
   *
   * The request body supports complex querying, including pagination controls,
   * sorting options, and search filters based on guest attributes and
   * timestamps.
   *
   * The response body returns paged summaries of guest data optimized for list
   * consumption. This enables administrators to monitor guest traffic patterns
   * and perform analytical operations on anonymous visitors for system insights
   * and maintenance purposes.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for guest visitors
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListGuest.IRequest,
  ): Promise<IPageITodoListGuest.ISummary> {
    try {
      return await patchTodoListAdminTodoListGuests({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
