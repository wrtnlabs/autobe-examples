import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoListUserTodoListUserSessions } from "../../../../providers/postTodoListUserTodoListUserSessions";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoListUserTodoListUserSessions } from "../../../../providers/patchTodoListUserTodoListUserSessions";
import { getTodoListUserTodoListUserSessionsId } from "../../../../providers/getTodoListUserTodoListUserSessionsId";
import { putTodoListUserTodoListUserSessionsId } from "../../../../providers/putTodoListUserTodoListUserSessionsId";

import { ITodoListUserSession } from "../../../../api/structures/ITodoListUserSession";
import { IPageITodoListUserSession } from "../../../../api/structures/IPageITodoListUserSession";

@Controller("/todoList/user/todoListUserSessions")
export class TodolistUserTodolistusersessionsController {
  /**
   * Create a new authenticated user session for the Todo List service.
   *
   * Create a new user session in the system for an authenticated Todo List
   * user.
   *
   * This operation accepts session details such as the IP address, accessed
   * URL, referrer URL, and user ownership. It registers a new session record in
   * the todo_list_user_sessions table, associating it with the specified
   * authenticated user.
   *
   * Security: Only authenticated users can create sessions. The
   * todo_list_user_id field must reference an existing user. Proper validation
   * ensures session expiry and audit readiness.
   *
   * The created session allows the system to track active and historical
   * sessions for the user to support features such as login history, session
   * revocation, and usage analytics.
   *
   * @param connection
   * @param body User session creation payload with IP, referring URL, accessed
   *   URL, session expiration and ownership details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUserSession.ICreate,
  ): Promise<ITodoListUserSession> {
    try {
      return await postTodoListUserTodoListUserSessions({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated list of todo list user sessions.
   *
   * Retrieve a paginated list of active and historical user sessions in the
   * todo list system.
   *
   * This operation supports advanced filtering capabilities, including
   * filtering by user identifiers, session status, creation date ranges, and
   * expiration timestamps. Sorting is available by creation and last access
   * time.
   *
   * Users with 'user' or 'guest' roles are authorized to perform this
   * operation, providing necessary oversight and management functionality for
   * sessions accessible by these actors.
   *
   * This operation operates on the todo_list_user_sessions table in Prisma
   * schema, returning paginated session data with relevant fields for oversight
   * and management.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for user session
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUserSession.IRequest,
  ): Promise<IPageITodoListUserSession.ISummary> {
    try {
      return await patchTodoListUserTodoListUserSessions({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific todo list user session by ID.
   *
   * Retrieve detailed information about a specific user session by its unique
   * identifier.
   *
   * This operation allows users with 'user' or 'guest' roles to access detailed
   * information about their sessions or sessions they have visibility over. The
   * session id uniquely identifies the record within the
   * todo_list_user_sessions table, and the response includes all relevant
   * session details as defined by the Prisma schema.
   *
   * @param connection
   * @param id Unique identifier of the target user session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListUserTodoListUserSessionsId({
        user,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update authenticated user session details by session ID.
   *
   * Update attributes of an existing authenticated user session.
   *
   * This operation modifies fields like IP address, accessed URL, referrer URL,
   * and expiration timestamps using the todo_list_user_sessions table. The
   * session to update is identified by its unique ID provided as a path
   * parameter.
   *
   * Security: Only the owning user or privileged roles can perform updates.
   * Validation ensures session ownership and exists.
   *
   * Successful update returns the updated session record with current details
   * of the user session.
   *
   * @param connection
   * @param id Unique identifier of the target user session
   * @param body Payload to update the user session properties
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUserSession.IUpdate,
  ): Promise<ITodoListUserSession> {
    try {
      return await putTodoListUserTodoListUserSessionsId({
        user,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
