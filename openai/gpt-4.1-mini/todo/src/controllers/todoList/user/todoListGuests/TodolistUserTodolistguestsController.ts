import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putTodoListUserTodoListGuestsId } from "../../../../providers/putTodoListUserTodoListGuestsId";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { deleteTodoListUserTodoListGuestsId } from "../../../../providers/deleteTodoListUserTodoListGuestsId";

import { ITodoListGuest } from "../../../../api/structures/ITodoListGuest";

@Controller("/todoList/user/todoListGuests/:id")
export class TodolistUserTodolistguestsController {
  /**
   * Update a specific Todo List guest by ID.
   *
   * Update a specific guest's information in the Todo List guest tracking
   * system.
   *
   * This operation allows modifications to existing guest records identified by
   * their unique UUID. Users of this API can update details such as visitor_ip
   * to track guests accurately.
   *
   * Security considerations ensure that only authorized users can perform
   * updates. Validation ensures the guest ID exists before applying changes.
   *
   * This operation interacts with the todo_list_guests table and requires
   * precise UUID paths to avoid misidentification.
   *
   * @param connection
   * @param id Unique identifier of the target todoListGuest
   * @param body Updated guest information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListGuest.IUpdate,
  ): Promise<ITodoListGuest> {
    try {
      return await putTodoListUserTodoListGuestsId({
        user,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific Todo List guest by ID.
   *
   * Delete a guest record permanently from the system.
   *
   * This operation is used for removing guest visitor records that are no
   * longer needed in the Todo List application.
   *
   * It acts directly on the todo_list_guests table ensuring the guest
   * identified by the UUID is removed from the database.
   *
   * Data loss is irreversible; clients should confirm before calling this API.
   *
   * @param connection
   * @param id Unique identifier of the target todoListGuest
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListUserTodoListGuestsId({
        user,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
