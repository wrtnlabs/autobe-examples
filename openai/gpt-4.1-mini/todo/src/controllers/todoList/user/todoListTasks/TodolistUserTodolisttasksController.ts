import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoListUserTodoListTasks } from "../../../../providers/postTodoListUserTodoListTasks";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoListUserTodoListTasks } from "../../../../providers/patchTodoListUserTodoListTasks";
import { getTodoListUserTodoListTasksId } from "../../../../providers/getTodoListUserTodoListTasksId";
import { putTodoListUserTodoListTasksId } from "../../../../providers/putTodoListUserTodoListTasksId";
import { deleteTodoListUserTodoListTasksId } from "../../../../providers/deleteTodoListUserTodoListTasksId";

import { ITodoListTask } from "../../../../api/structures/ITodoListTask";
import { IPageITodoListTask } from "../../../../api/structures/IPageITodoListTask";

@Controller("/todoList/user/todoListTasks")
export class TodolistUserTodolisttasksController {
  /**
   * Create a new todo task owned by the authenticated user.
   *
   * The client provides task attributes such as title and an optional detailed
   * description.
   *
   * Security: Only authenticated users can create tasks. The user ID is derived
   * from the authentication context.
   *
   * Upon successful creation, the system returns the full task record including
   * system-generated timestamps and status fields.
   *
   * Related operations include task retrieval and updates for managing task
   * lifecycle.
   *
   * @param connection
   * @param body Details required for creating a new todo task
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTask.ICreate,
  ): Promise<ITodoListTask> {
    try {
      return await postTodoListUserTodoListTasks({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of todo tasks.
   *
   * Retrieve a filtered and paginated list of todo tasks managed by
   * authenticated users.
   *
   * This operation allows users to query tasks with flexible filters including
   * completion status, partial title matching, and sort options.
   *
   * Pagination controls including page size and index allow efficient data
   * browsing for potentially large task lists.
   *
   * Security restricts access so users can only view and search their own tasks
   * to protect privacy.
   *
   * This operation accesses the todo_list_tasks table and exposes all relevant
   * task properties except owner user ID to client applications.
   *
   * Related operations include task creation, update, and deletion.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for task filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTask.IRequest,
  ): Promise<IPageITodoListTask.ISummary> {
    try {
      return await patchTodoListUserTodoListTasks({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific todo task by ID.
   *
   * Retrieve detailed information of a specific todo task by its unique
   * identifier.
   *
   * This operation allows authenticated users to fetch all data about their
   * task including title, optional description, completion state, and
   * timestamps.
   *
   * Security: Only the owning user may retrieve their task data. The task is
   * identified by its UUID.
   *
   * The operation queries the todo_list_tasks table directly and returns a
   * complete representation of the task.
   *
   * Related operations include task creation and updating for managing task
   * lifecycle.
   *
   * @param connection
   * @param id Unique identifier of the todo task
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<ITodoListTask> {
    try {
      return await getTodoListUserTodoListTasksId({
        user,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo list task by its unique identifier.
   *
   * Update a specific todo list task by providing its unique UUID identifier in
   * the path parameter.
   *
   * This operation allows authenticated users to modify the task's title,
   * description, completion state, and timestamps. The todo_list_user_id is
   * managed internally and not user-modifiable.
   *
   * Security: Only the owning user may update their tasks. Input data is
   * validated against schema constraints including string lengths and boolean
   * flags.
   *
   * This operation directly modifies a resource in the todo_list_tasks table as
   * defined in the Prisma schema, ensuring data integrity and proper task
   * lifecycle management.
   *
   * Related operations: Delete a task (DELETE /todoListTasks/{id}) to remove a
   * task permanently.
   *
   * @param connection
   * @param id Unique identifier (UUID) of the todo list task to update
   * @param body Updated information for the todo list task
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListTask.IUpdate,
  ): Promise<ITodoListTask> {
    try {
      return await putTodoListUserTodoListTasksId({
        user,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Erase an existing todo list task by its unique identifier.
   *
   * Permanently remove a specific todo list task from the system by its unique
   * UUID identifier provided in the path parameter.
   *
   * This operation executes a hard delete, fully removing the record from the
   * todo_list_tasks table. Once deleted, the task cannot be recovered.
   *
   * Security considerations ensure only the owning user may delete their tasks.
   * Proper authorization prevents accidental or malicious deletions.
   *
   * Related operations: Update a task (PUT /todoListTasks/{id}) to modify task
   * details.
   *
   * @param connection
   * @param id Unique identifier (UUID) of the todo list task to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListUserTodoListTasksId({
        user,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
