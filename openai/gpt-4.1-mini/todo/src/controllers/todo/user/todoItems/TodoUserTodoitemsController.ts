import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoUserTodoItems } from "../../../../providers/postTodoUserTodoItems";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoUserTodoItems } from "../../../../providers/patchTodoUserTodoItems";
import { getTodoUserTodoItemsTodoItemId } from "../../../../providers/getTodoUserTodoItemsTodoItemId";
import { putTodoUserTodoItemsTodoItemId } from "../../../../providers/putTodoUserTodoItemsTodoItemId";
import { deleteTodoUserTodoItemsTodoItemId } from "../../../../providers/deleteTodoUserTodoItemsTodoItemId";

import { ITodoItem } from "../../../../api/structures/ITodoItem";
import { IPageITodoItem } from "../../../../api/structures/IPageITodoItem";

@Controller("/todo/user/todoItems")
export class TodoUserTodoitemsController {
  /**
   * Create a new todo item for the authenticated user.
   *
   * Create a new todo item associated with the authenticated user. This
   * operation stores the task description, its pending/completed status,
   * optional due date, and timestamps for creation and update. The
   * todo_todo_items table manages these entries and enforces attributes like
   * max description length and valid status values.
   *
   * Security ensures only users with proper authentication can create items,
   * associating the created task to their unique user ID.
   *
   * Validation covers string length, allowed status values, and due_date
   * constraints, with error responses returning clear messages on invalid
   * inputs.
   *
   * This operation will return the complete todo item entity upon successful
   * creation.
   *
   * @param connection
   * @param body Payload containing new todo item details, including
   *   description, status, and optional due date
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoItem.ICreate,
  ): Promise<ITodoItem> {
    try {
      return await postTodoUserTodoItems({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of user's todo items.
   *
   * Retrieve a filtered, paginated list of todo items belonging to the
   * authenticated user. This operation provides advanced search, filtering, and
   * sorting capabilities allowing clients to request todo items based on status
   * (either 'pending' or 'completed'), due date ranges, and partial matching on
   * the description field.
   *
   * The result is paged to improve performance and usability, supporting
   * configurable page size and page number. Sorting is supported by fields such
   * as creation date and due date, with ascending or descending order.
   *
   * Security considerations include enforcing user ownership by filtering
   * results to only include todo items owned by the authenticated user,
   * preventing unauthorized access. The operation requires authentication as
   * the user actor.
   *
   * The operation interfaces directly with the todo_todo_items table as defined
   * in the Prisma schema, respecting all defined fields including soft deletion
   * support where deleted items are excluded from results.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering user's
   *   todo items
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoItem.IRequest,
  ): Promise<IPageITodoItem.ISummary> {
    try {
      return await patchTodoUserTodoItems({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific todo item by ID.
   *
   * Retrieve detailed information of a specific todo item identified by its
   * unique UUID. The operation enforces ownership validation, allowing access
   * only to the authenticated user who owns the todo item.
   *
   * The todo item data includes the task description, current status ('pending'
   * or 'completed'), optional due date, and audit timestamps for creation and
   * last update. Soft deleted items are inaccessible.
   *
   * Security is paramount; unauthorized access attempts are rejected with
   * errors. This operation corresponds directly to the todo_todo_items table in
   * the Prisma schema and is accessible only by authenticated users.
   *
   * @param connection
   * @param todoItemId Unique identifier of the target todo item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoItemId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoItemId")
    todoItemId: string & tags.Format<"uuid">,
  ): Promise<ITodoItem> {
    try {
      return await getTodoUserTodoItemsTodoItemId({
        user,
        todoItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo item by ID for the authenticated user.
   *
   * Update an existing todo item by its unique identifier for an authenticated
   * user. This modifies the description, status, due date, and records updated
   * timestamps.
   *
   * Ownership is strictly enforced; only the owner can update their todo items.
   * Validation of input data ensures compliance with allowed status values and
   * description length.
   *
   * The todo_todo_items table holds the persistent entity data and relations to
   * the owning user.
   *
   * Successful operation returns the updated todo item record.
   *
   * @param connection
   * @param todoItemId Unique identifier of the target todo item (UUID)
   * @param body Update payload containing changes to the todo item's attributes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoItemId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoItemId")
    todoItemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoItem.IUpdate,
  ): Promise<ITodoItem> {
    try {
      return await putTodoUserTodoItemsTodoItemId({
        user,
        todoItemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific todo item permanently by its unique ID.
   *
   * This API operation allows an authenticated user to permanently remove one
   * of their todo items from the system. It interacts with the todo_todo_items
   * table, which maintains all todo task records owned by users.
   *
   * The operation requires the unique identifier of the todo item to delete as
   * a path parameter. The identifier is the UUID primary key of the
   * todo_todo_items table's id field. Authorization is enforced to ensure only
   * the owner of the todo item can delete it.
   *
   * Upon execution, the system performs a hard delete on the record,
   * permanently removing it from the database with no recovery option. This
   * aligns with the business rule that deleted todo items are irrecoverable.
   *
   * This endpoint accepts no request body and does not return a response body.
   * Errors are returned if the item does not exist or the requester lacks
   * authorization.
   *
   * @param connection
   * @param todoItemId Unique identifier of the todo item to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoItemId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoItemId")
    todoItemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoUserTodoItemsTodoItemId({
        user,
        todoItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
