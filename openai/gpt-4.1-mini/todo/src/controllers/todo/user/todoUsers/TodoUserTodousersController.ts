import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchTodoUserTodoUsers } from "../../../../providers/patchTodoUserTodoUsers";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoUserTodoUsersTodoUserEmail } from "../../../../providers/getTodoUserTodoUsersTodoUserEmail";
import { putTodoUserTodoUsersTodoUserEmail } from "../../../../providers/putTodoUserTodoUsersTodoUserEmail";
import { deleteTodoUserTodoUsersTodoUserEmail } from "../../../../providers/deleteTodoUserTodoUsersTodoUserEmail";

import { IPageITodoUser } from "../../../../api/structures/IPageITodoUser";
import { ITodoUser } from "../../../../api/structures/ITodoUser";

@Controller("/todo/user/todoUsers")
export class TodoUserTodousersController {
  /**
   * Search and retrieve a filtered, paginated list of todo users.
   *
   * Retrieve a filtered and paginated list of todo user accounts from the
   * system.
   *
   * This operation supports advanced search capabilities, including filtering
   * by email, pagination with configurable page sizes (typically up to 50 per
   * page), and sorting by creation date or other allowed fields.
   *
   * Security considerations restrict this endpoint to administrative users to
   * prevent unauthorized access to sensitive user information. The response
   * includes summary information of todo users without exposing sensitive data
   * such as password hashes.
   *
   * The data conforms exactly to the todo_users table schema, reflecting the
   * current state of users including possible soft deletions indicated by
   * deleted_at.
   *
   * This endpoint integrates with authentication and user management functions
   * to allow effective administration of user accounts.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering todo
   *   user accounts
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUser.IRequest,
  ): Promise<IPageITodoUser.ISummary> {
    try {
      return await patchTodoUserTodoUsers({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single todo user by unique email address.
   *
   * Retrieve detailed information about a single todo user by their unique
   * email address.
   *
   * This operation requires exactly one path parameter: todoUserEmail, which
   * corresponds to the unique email field globally scoped in the todo_users
   * table.
   *
   * Access to this endpoint requires authenticated privileges to ensure user
   * privacy and security.
   *
   * The returned data includes all user fields from the todo_users table except
   * their sessions, which are accessed separately.
   *
   * This operation is critical for user profile management and auditing
   * purposes.
   *
   * @param connection
   * @param todoUserEmail Unique email address of the todo user (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoUserEmail")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoUserEmail")
    todoUserEmail: string,
  ): Promise<ITodoUser> {
    try {
      return await getTodoUserTodoUsersTodoUserEmail({
        user,
        todoUserEmail,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update todo user account identified by email.
   *
   * Update existing todo user account identified by email.
   *
   * The email is the unique business identifier for users and is used in the
   * URL path parameter to identify the target user account for update. Only
   * authenticated principals with appropriate rights can update user records.
   *
   * The operation accepts the updated user data in the request body, including
   * password hash and timestamps while preserving user identity by email.
   * Partial updates are not supported; the full update data as per
   * ITodoTodoUser.IUpdate is required.
   *
   * This endpoint ensures secure and auditable updates to user account
   * information and according to the Prisma schema for todo_users, enforcing
   * uniqueness and integrity constraints.
   *
   * Path parameter `todoUserEmail` ensures that the user is uniquely identified
   * by email (global scope), improving URL readability and API usability.
   *
   * @param connection
   * @param todoUserEmail Unique business identifier code of the target todo
   *   user (global scope)
   * @param body Full updated user information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoUserEmail")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoUserEmail")
    todoUserEmail: string,
    @TypedBody()
    body: ITodoUser.IUpdate,
  ): Promise<ITodoUser> {
    try {
      return await putTodoUserTodoUsersTodoUserEmail({
        user,
        todoUserEmail,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a todo user permanently identified by email.
   *
   * This API endpoint deletes a todo user account permanently based on the
   * unique email address that identifies the user in the todo_users table.
   *
   * The email address is used as the unique business identifier (global scope)
   * and must be provided as the path parameter 'todoUserEmail'. This operation
   * cascades the deletion to related user sessions and todo items to prevent
   * orphaned data.
   *
   * Access to this endpoint is restricted to authorized users with the 'user'
   * role, who have privileges to remove user accounts.
   *
   * This deletion is irreversible, removing all user-related data permanently
   * from the system.
   *
   * Security considerations include ensuring only authorized actors can execute
   * this delete and audit trails maintain a record of deletions.
   *
   * No request body is required for this operation.
   *
   * The response body is null, indicating success without content.
   *
   * @param connection
   * @param todoUserEmail Unique business identifier email address of the todo
   *   user (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoUserEmail")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoUserEmail")
    todoUserEmail: string,
  ): Promise<void> {
    try {
      return await deleteTodoUserTodoUsersTodoUserEmail({
        user,
        todoUserEmail,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
