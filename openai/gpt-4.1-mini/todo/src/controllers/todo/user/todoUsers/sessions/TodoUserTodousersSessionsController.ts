import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoUserTodoUsersTodoUserEmailSessions } from "../../../../../providers/postTodoUserTodoUsersTodoUserEmailSessions";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { patchTodoUserTodoUsersTodoUserEmailSessions } from "../../../../../providers/patchTodoUserTodoUsersTodoUserEmailSessions";
import { getTodoUserTodoUsersTodoUserEmailSessionsId } from "../../../../../providers/getTodoUserTodoUsersTodoUserEmailSessionsId";
import { putTodoUserTodoUsersTodoUserEmailSessionsId } from "../../../../../providers/putTodoUserTodoUsersTodoUserEmailSessionsId";
import { deleteTodoUserTodoUsersTodoUserEmailSessionsId } from "../../../../../providers/deleteTodoUserTodoUsersTodoUserEmailSessionsId";

import { ITodoUserSession } from "../../../../../api/structures/ITodoUserSession";
import { IPageITodoUserSession } from "../../../../../api/structures/IPageITodoUserSession";

@Controller("/todo/user/todoUsers/:todoUserEmail/sessions")
export class TodoUserTodousersSessionsController {
  /**
   * Create a new user session for a specified todo user email.
   *
   * Create a new user session for the specified user by their email. The system
   * stores session metadata such as IP address, href, and referrer. Creation
   * timestamp is set by the system.
   *
   * Only the authenticated user can create sessions for their own account for
   * security reasons.
   *
   * The request body contains the necessary session data to initiate a new
   * session.
   *
   * The response returns the full session object including the generated
   * session UUID.
   *
   * @param connection
   * @param todoUserEmail Unique email address of the user creating the session
   *   (global scope)
   * @param body Session creation details including IP, href, and referrer
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoUserEmail")
    todoUserEmail: string,
    @TypedBody()
    body: ITodoUserSession.ICreate,
  ): Promise<ITodoUserSession> {
    try {
      return await postTodoUserTodoUsersTodoUserEmailSessions({
        user,
        todoUserEmail,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * List todo user sessions by user email with pagination and filtering.
   *
   * Retrieve a paginated and filtered list of todo user sessions for a specific
   * todo user identified by their email address.
   *
   * The 'todoUserEmail' path parameter uniquely identifies the parent user
   * within the system at a global scope.
   *
   * This operation supports pagination, search, and filtering via the request
   * body conforming to ITodoUserSession.IRequest.
   *
   * Access is restricted to authorized users with the 'user' role.
   *
   * The response contains paginated summary information of user sessions,
   * including IP addresses, creation timestamps, and expiration details.
   *
   * Proper validation and authorization checks apply to ensure users can only
   * view sessions they are permitted to.
   *
   * Errors are returned for unauthorized access or invalid parameters.
   *
   * This operation is critical for auditing user activity and managing session
   * security.
   *
   * @param connection
   * @param todoUserEmail Unique business identifier email address of the todo
   *   user (global scope)
   * @param body Search criteria and pagination parameters for todo user
   *   sessions filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoUserEmail")
    todoUserEmail: string,
    @TypedBody()
    body: ITodoUserSession.IRequest,
  ): Promise<IPageITodoUserSession.ISummary> {
    try {
      return await patchTodoUserTodoUsersTodoUserEmailSessions({
        user,
        todoUserEmail,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single user session by user email and session ID from
   * todo_user_sessions.
   *
   * Retrieve a specific todo user session by user email and session ID from the
   * todo_user_sessions table. The operation returns complete session details,
   * including IP address, href, referrer, and timestamps for creation and
   * expiration.
   *
   * Authorization is required and restricts access to the authenticated user
   * associated with the email to prevent unauthorized session access.
   *
   * The parameters are the user's unique email address and the session ID,
   * ensuring precise retrieval of the session record.
   *
   * The response includes the detailed session object corresponding to the
   * requested session ID linked to the specific user email.
   *
   * Error handling includes managing cases where the session or user does not
   * exist, returning appropriate error status codes.
   *
   * @param connection
   * @param todoUserEmail Unique email address of the target user (global scope)
   *   for whom the session belongs
   * @param id UUID of the session to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoUserEmail")
    todoUserEmail: string,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<ITodoUserSession> {
    try {
      return await getTodoUserTodoUsersTodoUserEmailSessionsId({
        user,
        todoUserEmail,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific todo user session by user email and session ID.
   *
   * Update an existing authenticated user session by specifying the user's
   * email and session ID. This operation modifies session data including client
   * IP, referrer, and the originating URL. Only valid authenticated users may
   * update their session information. The session record is linked to the
   * todo_users table and the users are uniquely identified by email. Ownership
   * checks and authorization are enforced to prevent unauthorized
   * modifications. This operation corresponds to the todo_user_sessions Prisma
   * table.
   *
   * Security considerations include verifying the authenticity of the user and
   * restricting access to only their session records. Incorrect session update
   * requests are rejected with appropriate error responses.
   *
   * This operation is intended to be used during session management, including
   * session refresh or update of client metadata. Related operations include
   * session creation and deletion endpoints.
   *
   * Failure to provide valid identifiers or payload results in errors. The
   * system requires the todoUserEmail (user email) and session id as path
   * parameters, and requires the body to conform to ITodoUserSession.IUpdate
   * type.
   *
   * @param connection
   * @param todoUserEmail Unique email address of the target todo user (global
   *   scope)
   * @param id Unique identifier of the target session
   * @param body Update payload for a todo user session including IP, href, and
   *   referrer fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoUserEmail")
    todoUserEmail: string,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoUserSession.IUpdate,
  ): Promise<ITodoUserSession> {
    try {
      return await putTodoUserTodoUsersTodoUserEmailSessionsId({
        user,
        todoUserEmail,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific todo user session by user email and session ID.
   *
   * Permanently delete a todo user session, identified by the user's email and
   * session UUID. This operation invalidates the session and deletes all
   * associated data. Authorization is required to ensure users can only delete
   * their own sessions.
   *
   * This corresponds to the todo_user_sessions table in Prisma schema and
   * supports user logout and session revocation workflows.
   *
   * No request body is needed for this delete operation. The operation requires
   * `todoUserEmail` and `id` path parameters specifying the user and session.
   *
   * Deleting a session is irreversible and affects authentication clients
   * relying on the session's JWT tokens.
   *
   * @param connection
   * @param todoUserEmail Unique email address of the target todo user (global
   *   scope)
   * @param id Unique identifier of the target session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoUserEmail")
    todoUserEmail: string,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoUserTodoUsersTodoUserEmailSessionsId({
        user,
        todoUserEmail,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
