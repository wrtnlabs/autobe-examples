import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postTodoTodoUsers } from "../../../providers/postTodoTodoUsers";

import { ITodoUser } from "../../../api/structures/ITodoUser";

@Controller("/todo/todoUsers")
export class TodoTodousersController {
  /**
   * Create a new todo user account.
   *
   * Create a new authenticated user account in the system.
   *
   * This operation receives user registration data including a unique email and
   * a securely hashed password. Upon successful validation, the system creates
   * a new user record with automatically generated UUID and timestamps for
   * creation and update.
   *
   * The operation ensures the email provided is unique and forbids duplicate
   * registrations. The created user record includes the email, hashed password,
   * and audit timestamps. Deleted users are marked with an optional deleted_at
   * timestamp but this operation creates active users only.
   *
   * This endpoint is public and does not require prior authentication, enabling
   * new user registrations. Error responses may include duplicate email or
   * validation failures.
   *
   * This operation directly maps to the todo_users Prisma schema model,
   * respecting all defined constraints and relations.
   *
   * @param connection
   * @param body User registration data including email and password hash
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: ITodoUser.ICreate,
  ): Promise<ITodoUser> {
    try {
      return await postTodoTodoUsers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
