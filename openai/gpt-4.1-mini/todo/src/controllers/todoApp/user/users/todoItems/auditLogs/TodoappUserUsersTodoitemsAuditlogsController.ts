import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppUserUsersUserIdTodoItemsTodoItemIdAuditLogs } from "../../../../../../providers/postTodoAppUserUsersUserIdTodoItemsTodoItemIdAuditLogs";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";
import { deleteTodoAppUserUsersUserIdTodoItemsTodoItemIdAuditLogsAuditLogId } from "../../../../../../providers/deleteTodoAppUserUsersUserIdTodoItemsTodoItemIdAuditLogsAuditLogId";

import { ITodoAppTodoItemAuditLog } from "../../../../../../api/structures/ITodoAppTodoItemAuditLog";

@Controller("/todoApp/user/users/:userId/todoItems/:todoItemId/auditLogs")
export class TodoappUserUsersTodoitemsAuditlogsController {
  /**
   * Create a new audit log entry for a specific todo item owned by a user.
   *
   * This operation creates an audit record associated with the todo item
   * identified by todoItemId under the user identified by userId in the todoApp
   * system. The audit logs capture events such as creation, modification, or
   * status changes to todo items for tracking and history purposes.
   *
   * The operation enforces path parameter constraints on userId and todoItemId,
   * both expected to be UUIDs representing the unique user and todo item. The
   * request body must conform to the ITodoAppTodoItemAuditLog.ICreate
   * interface, specifying the content and metadata of the audit log.
   *
   * Security considerations ensure that only authorized users or system
   * components can create audit logs. This maintains data integrity and
   * complies with privacy requirements by scoping audit logs to their
   * respective owners.
   *
   * Responses include the complete audit log entry following
   * ITodoAppTodoItemAuditLog interface, confirming successful creation and
   * providing audit metadata for client use.
   *
   * @param connection
   * @param userId Unique identifier of the user owning the todo item
   * @param todoItemId Unique identifier of the todo item owned by the user
   * @param body Information needed to create a new audit log entry for the todo
   *   item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("todoItemId")
    todoItemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppTodoItemAuditLog.ICreate,
  ): Promise<ITodoAppTodoItemAuditLog> {
    try {
      return await postTodoAppUserUsersUserIdTodoItemsTodoItemIdAuditLogs({
        user,
        userId,
        todoItemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation permanently removes a specific audit log entry from the
   * todo_app_todo_item_audit_logs table in the todoApp database, identified
   * uniquely by the auditLogId path parameter.
   *
   * The audit log entry is associated with a particular todo item belonging to
   * a specific user, referenced by todoItemId and userId respectively. This
   * operation enables authorized users or administrators to delete audit trail
   * records related to todo items, supporting proper management of audit
   * history.
   *
   * Security considerations require that only those with appropriate
   * permissions (resource owners or authorized administrators) can perform this
   * deletion. No request body is required as the necessary identifiers are
   * provided in the URL path parameters.
   *
   * Following deletion, no content is returned in the response body, confirming
   * permanent removal of the audit log record. This operation aligns with
   * RESTful deletion semantics and provides an essential function for audit log
   * maintenance within the todoApp system.
   *
   * @param connection
   * @param userId Unique identifier of the user who owns the todo item
   * @param todoItemId Unique identifier of the todo item to which the audit log
   *   belongs
   * @param auditLogId Unique identifier of the audit log entry to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":auditLogId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("todoItemId")
    todoItemId: string & tags.Format<"uuid">,
    @TypedParam("auditLogId")
    auditLogId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserUsersUserIdTodoItemsTodoItemIdAuditLogsAuditLogId(
        {
          user,
          userId,
          todoItemId,
          auditLogId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
