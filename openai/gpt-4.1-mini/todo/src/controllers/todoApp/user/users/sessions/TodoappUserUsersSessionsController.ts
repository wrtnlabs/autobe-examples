import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppUserUsersUserIdSessions } from "../../../../../providers/postTodoAppUserUsersUserIdSessions";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { deleteTodoAppUserUsersUserIdSessionsSessionId } from "../../../../../providers/deleteTodoAppUserUsersUserIdSessionsSessionId";

@Controller("/todoApp/user/users/:userId/sessions")
export class TodoappUserUsersSessionsController {
  /**
   * This endpoint is forbidden by system architectural policies; session
   * management including session creation is handled exclusively by specialized
   * authentication microservices. As such, no API operation is implemented here
   * for creating user sessions.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async createUserSessionForbidden(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await postTodoAppUserUsersUserIdSessions({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a user session identified by userId and sessionId from the todoApp
   * system.
   *
   * This operation permanently removes the user's session record from the
   * database table todo_app_user_sessions. Manual session deletion allows users
   * to revoke their authentication tokens and terminate active sessions for
   * security or account management purposes.
   *
   * The userId parameter specifies the unique identifier of the user who owns
   * the session. The sessionId parameter identifies the specific session to
   * delete.
   *
   * Only the session explicitly targeted by the parameters will be removed.
   * This is a hard delete operation; no recovery is possible after completion.
   *
   * Authorization checks ensure only the session owner or authorized admins can
   * perform this operation.
   *
   * Related operations include: GET /users/{userId}/sessions to list sessions,
   * and POST /users/{userId}/sessions to create new sessions.
   *
   * @param connection
   * @param userId Unique identifier of the user who owns the session
   * @param sessionId Unique identifier of the session to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
