import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppUserUsers } from "../../../../providers/patchTodoAppUserUsers";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoAppUserUsersUserId } from "../../../../providers/getTodoAppUserUsersUserId";
import { putTodoAppUserUsersUserId } from "../../../../providers/putTodoAppUserUsersUserId";
import { deleteTodoAppUserUsersUserId } from "../../../../providers/deleteTodoAppUserUsersUserId";

import { IPageITodoAppUser } from "../../../../api/structures/IPageITodoAppUser";
import { ITodoAppUser } from "../../../../api/structures/ITodoAppUser";

@Controller("/todoApp/user/users")
export class TodoappUserUsersController {
  /**
   * Retrieve a filtered and paginated list of todoApp users. This operation
   * supports searching users based on various criteria such as username, email,
   * registration date, and status.
   *
   * The todo_app_users table represents registered users in the todoApp system,
   * storing personal and authentication-related information.
   *
   * Security considerations ensure that users can only access appropriately
   * authorized information, protecting sensitive data. Pagination and sorting
   * options enhance usability and performance when dealing with large user
   * datasets.
   *
   * This endpoint is crucial for user management, administrative overview, or
   * social features relying on user data aggregation.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for user filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppUser.IRequest,
  ): Promise<IPageITodoAppUser.ISummary> {
    try {
      return await patchTodoAppUserUsers({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific user in the todoApp system by
   * their unique user ID.
   *
   * This operation directly accesses the todo_app_users database table that
   * stores user account and profile information. The user is identified
   * uniquely by a UUID passed in the path parameter.
   *
   * Security: Access to this endpoint is restricted to authenticated users to
   * protect private information. The authorization is enforced for the actor
   * role 'user'.
   *
   * This retrieval operation supports the client UI and administrative tools
   * requiring user details for profile viewing, account management, or support
   * purposes.
   *
   * This endpoint does not accept a request body as it is used purely for data
   * retrieval.
   *
   * Related operations: POST /users to create users, PATCH /users for searching
   * users, PUT /users/{userId} for updates, DELETE /users/{userId} for
   * removals.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUser> {
    try {
      return await getTodoAppUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the specified user account identified by the userId parameter. This
   * operation allows an authenticated user to modify their own account
   * information. The todo_app_users table stores all user data, including
   * credentials, profile details, and account status.
   *
   * This operation requires the user to be authenticated as the owner of the
   * account to ensure data privacy and security. The update replaces existing
   * user information with the submitted payload, respecting all schema
   * validations. Proper error handling will address cases of invalid data or
   * unauthorized access.
   *
   * Related operations: GET /users/{userId} to retrieve user details, PATCH
   * /users to search users, DELETE /users/{userId} to delete a user account.
   *
   * @param connection
   * @param userId Unique identifier of the user to update
   * @param body User account update payload conforming to ITodoAppUser.IUpdate
   *   schema
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUser.IUpdate,
  ): Promise<ITodoAppUser> {
    try {
      return await putTodoAppUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation permanently deletes a user record from the todo_app_users
   * table in the todoApp database. The userId parameter, a UUID, specifies the
   * target user to be removed.
   *
   * Only authenticated users (authorizationActors: ["user"]) are permitted to
   * perform this action, ensuring that deletion rights are controlled.
   *
   * Upon successful deletion, the user record is irrevocably removed, with no
   * response content returned, conforming to REST standards.
   *
   * Security considerations include validation of the userId parameter and
   * authentication enforcement to prevent unauthorized deletions.
   *
   * @param connection
   * @param userId Unique identifier of the target user account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
