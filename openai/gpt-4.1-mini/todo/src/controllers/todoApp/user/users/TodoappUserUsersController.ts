import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putTodoAppUserUsersUserId } from "../../../../providers/putTodoAppUserUsersUserId";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { deleteTodoAppUserUsersUserId } from "../../../../providers/deleteTodoAppUserUsersUserId";

import { ITodoAppUser } from "../../../../api/structures/ITodoAppUser";

@Controller("/todoApp/user/users/:userId")
export class TodoappUserUsersController {
  /**
   * Update an existing user's information in the todoApp system.
   *
   * This operation targets the `todo_app_users` database entity to modify user
   * details securely. Only authorized actors should perform this operation.
   *
   * The path parameter `userId` accepts a UUID identifying the user. The
   * request body must conform to `ITodoAppUser.IUpdate` type, containing the
   * fields to update. The system performs necessary validation and updates the
   * user record accordingly.
   *
   * Upon successful update, the full updated user entity is returned in the
   * response with all currently stored details.
   *
   * Users may update personal data such as name, email, password, and other
   * profile information according to system policies and validation rules.
   *
   * Related operations include GET /users/{userId} for retrieval and PATCH
   * /users for listing and searching users.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @param body Request body containing user update information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUser.IUpdate,
  ): Promise<ITodoAppUser> {
    try {
      return await putTodoAppUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes a registered user from the todoApp system.
   *
   * This operation targets the todo_app_users table representing all registered
   * users with their authentication credentials and profile information.
   *
   * Only authorized actors, typically administrators, can invoke this endpoint
   * to delete users. This helps maintain data security and prevents
   * unauthorized deletions.
   *
   * No request body is needed as the user to delete is specified solely by the
   * unique UUID path parameter.
   *
   * Upon invocation, the user record and all related personal todo list data
   * are permanently removed from the database. There is no response body as per
   * RESTful delete operation conventions.
   *
   * @param connection
   * @param userId Unique identifier of the user to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
