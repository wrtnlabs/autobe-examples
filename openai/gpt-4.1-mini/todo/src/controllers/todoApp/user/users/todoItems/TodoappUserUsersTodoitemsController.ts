import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppUserUsersUserIdTodoItems } from "../../../../../providers/postTodoAppUserUsersUserIdTodoItems";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { putTodoAppUserUsersUserIdTodoItemsTodoItemId } from "../../../../../providers/putTodoAppUserUsersUserIdTodoItemsTodoItemId";
import { deleteTodoAppUserUsersUserIdTodoItemsTodoItemId } from "../../../../../providers/deleteTodoAppUserUsersUserIdTodoItemsTodoItemId";

import { ITodoAppTodoItem } from "../../../../../api/structures/ITodoAppTodoItem";

@Controller("/todoApp/user/users/:userId/todoItems")
export class TodoappUserUsersTodoitemsController {
  /**
   * Creates a new todo item for the specified user in their personal todo list.
   *
   * This operation inserts a new record into the todo_app_todo_items table. The
   * userId path parameter uniquely identifies the owner of the todo item and
   * guarantees user data isolation.
   *
   * The request body must supply the todo item details such as the task
   * description, completion status, and any deadlines or priorities. The system
   * validates the input fields against the ITodoAppTodoItem.ICreate schema.
   *
   * Security ensures only authorized users can add todo items to their own
   * lists. The response returns the created todo item with all persistent
   * fields, confirming successful creation and persistence.
   *
   * Related operations include GET /users/{userId}/todoItems for listing and
   * PATCH /users/{userId}/todoItems/{todoItemId} for updates, enabling full
   * lifecycle management of user todos.
   *
   * @param connection
   * @param userId Unique identifier of the target user who owns the todo list
   * @param body Todo item creation payload containing task details and metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppTodoItem.ICreate,
  ): Promise<ITodoAppTodoItem> {
    try {
      return await postTodoAppUserUsersUserIdTodoItems({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo item of a specific user in the todoApp system.
   *
   * This operation allows authenticated users to modify properties of their
   * todo items such as the title, description, due date, completion status, and
   * priority. It operates on the todoAppTodoItems table representing individual
   * todo list entries linked to specific users.
   *
   * The operation requires the userId and todoItemId path parameters to
   * precisely identify the todo item to be updated. The entire update payload
   * is submitted in the request body following the ITodoAppTodoItem.IUpdate
   * structure.
   *
   * Security measures must ensure that only the owner user can update their
   * todo items, enforcing strict access control and privacy. The operation
   * returns the updated todo item details for confirmation.
   *
   * Consistency and validation are important, including checks for valid user
   * and todo item existence, correct UUID formats, and adherence to business
   * rules on todo item state transitions.
   *
   * Related operations include creating todo items (POST
   * /users/{userId}/todoItems), retrieving todo items (GET
   * /users/{userId}/todoItems/{todoItemId}), and deleting todo items (DELETE
   * /users/{userId}/todoItems/{todoItemId}).
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @param todoItemId Unique identifier of the target todo item
   * @param body New data for updating the todo item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoItemId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("todoItemId")
    todoItemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppTodoItem.IUpdate,
  ): Promise<ITodoAppTodoItem> {
    try {
      return await putTodoAppUserUsersUserIdTodoItemsTodoItemId({
        user,
        userId,
        todoItemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a specific todo item owned by a user identified by
   * 'userId' and the todo item identified by 'todoItemId' from the TodoApp
   * system.
   *
   * This operation removes the record from 'todo_app_todo_items' table in the
   * database. The deletion is irreversible, and the todo item will no longer be
   * accessible or recoverable after this operation.
   *
   * Authorization must ensure the requesting user matches the 'userId' path
   * parameter to prevent unauthorized deletion of other users' todo items.
   *
   * No request body is needed as the resource and identification are fully
   * determined by the URL path parameters.
   *
   * Response for this operation is typically no content (204 No Content), and
   * no response body is returned.
   *
   * Related operations include creating todo items (POST
   * /users/{userId}/todoItems) and updating todo items (PUT
   * /users/{userId}/todoItems/{todoItemId}).
   *
   * @param connection
   * @param userId Unique identifier of the user who owns the todo item
   * @param todoItemId Unique identifier of the todo item to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoItemId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("todoItemId")
    todoItemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserUsersUserIdTodoItemsTodoItemId({
        user,
        userId,
        todoItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
