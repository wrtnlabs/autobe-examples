import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppUserUsersEmailVerifications } from "../../../../../../providers/postTodoAppUserUsersEmailVerifications";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";
import { patchTodoAppUserUsersEmailVerifications } from "../../../../../../providers/patchTodoAppUserUsersEmailVerifications";
import { getTodoAppUserUsersEmailVerificationsUserEmailVerificationId } from "../../../../../../providers/getTodoAppUserUsersEmailVerificationsUserEmailVerificationId";
import { putTodoAppUserUsersEmailVerificationsUserEmailVerificationId } from "../../../../../../providers/putTodoAppUserUsersEmailVerificationsUserEmailVerificationId";
import { deleteTodoAppUserUsersEmailVerificationsUserEmailVerificationId } from "../../../../../../providers/deleteTodoAppUserUsersEmailVerificationsUserEmailVerificationId";

import { ITodoAppUserEmailVerification } from "../../../../../../api/structures/ITodoAppUserEmailVerification";

@Controller("/todoApp/user/users/email/verifications")
export class TodoappUserUsersEmailVerificationsController {
  /**
   * Create a new email verification request for a user within the todoApp
   * system.
   *
   * This operation enables users to initiate the email verification process by
   * submitting required data to generate a verification token linked to their
   * user account.
   *
   * The endpoint maps to the database table todo_app_user_email_verifications,
   * which stores information such as verification tokens, expiration
   * timestamps, and user references.
   *
   * Security considerations include validating that the requesting user has
   * proper authorization to initiate verification for the specified user, and
   * protections against token reuse or replay attacks.
   *
   * This operation is essential for managing user identity verification
   * workflows and ensuring that only verified email addresses are associated
   * with user accounts.
   *
   * Related operations include user registration (handled elsewhere), login,
   * and password reset endpoints that rely on verified user email identities.
   *
   * @param connection
   * @param body Request body schema for creating a new user email verification
   *   request.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppUserEmailVerification.ICreate,
  ): Promise<ITodoAppUserEmailVerification> {
    try {
      return await postTodoAppUserUsersEmailVerifications({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update or confirm the email verification status of a user within the
   * todoApp system.
   *
   * This operation supports partial updates to a user's email verification
   * record, enabling users to input verification tokens or statuses obtained
   * through email confirmation flows.
   *
   * The underlying database entity is `todo_app_user_email_verifications`,
   * which tracks the verification attempts and statuses for user emails.
   *
   * Security considerations restrict access to authenticated users only,
   * ensuring users can only modify their own verification information.
   *
   * The operation is idempotent with PATCH semantics and supports extensible
   * validation and business rules applied upon verification state changes.
   *
   * @param connection
   * @param body Partial update request to the user's email verification record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppUserEmailVerification.IRequest,
  ): Promise<ITodoAppUserEmailVerification> {
    try {
      return await patchTodoAppUserUsersEmailVerifications({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific user email verification record
   * from the TodoApp system.
   *
   * This operation fetches a single record identified by the
   * userEmailVerificationId, representing the verification status of a user's
   * email address. It includes information such as verification token,
   * expiration, verification status, associated user ID, creation and update
   * timestamps.
   *
   * Security: Access to this endpoint requires proper authorization to ensure
   * that only the verified user or authorized system actors can access
   * sensitive verification details.
   *
   * The underlying database table is todo_app_user_email_verifications, and all
   * data fields exposed correspond directly to this schema's definitions.
   *
   * Related operations include creation of verification records (POST
   * /users/email/verifications) and listing verifications (PATCH
   * /users/email/verifications).
   *
   * @param connection
   * @param userEmailVerificationId Unique identifier of the target user email
   *   verification record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userEmailVerificationId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userEmailVerificationId")
    userEmailVerificationId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUserEmailVerification> {
    try {
      return await getTodoAppUserUsersEmailVerificationsUserEmailVerificationId(
        {
          user,
          userEmailVerificationId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a user email verification record by its unique identifier in the
   * todoApp system.
   *
   * This operation allows authorized users to modify the details of an existing
   * email verification entry. It acts on the todo_app_user_email_verifications
   * table which holds verification status, token, and timestamps related to
   * user email confirmation.
   *
   * The path parameter 'userEmailVerificationId' identifies the specific email
   * verification record by UUID. The request body must include the fields
   * allowed to be updated as defined by the
   * ITodoAppUserEmailVerification.IUpdate schema.
   *
   * The response returns the full updated email verification resource. This
   * endpoint is essential for processes such as confirming or invalidating
   * email verification tokens securely.
   *
   * Security considerations: Only the owning user or authorized admins should
   * be allowed to perform this update. Input validation applies to ensure token
   * integrity and status correctness.
   *
   * Related operations: GET
   * /users/email/verifications/{userEmailVerificationId} to retrieve the
   * record, POST to create new verification entries.
   *
   * @param connection
   * @param userEmailVerificationId Unique identifier of the target user email
   *   verification record
   * @param body Update payload for user email verification record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userEmailVerificationId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userEmailVerificationId")
    userEmailVerificationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUserEmailVerification.IUpdate,
  ): Promise<ITodoAppUserEmailVerification> {
    try {
      return await putTodoAppUserUsersEmailVerificationsUserEmailVerificationId(
        {
          user,
          userEmailVerificationId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a user email verification record by its unique identifier.
   *
   * This operation allows authorized users or administrators to remove a single
   * email verification entry stored in the todo_app_user_email_verifications
   * table. The record identified by the userEmailVerificationId path parameter
   * will be permanently deleted, invalidating any verification code stored
   * therein.
   *
   * Security: Only authenticated users with proper permissions can perform this
   * operation to prevent unauthorized removal of verification codes.
   *
   * Database Relation: The operation maps directly to the
   * todo_app_user_email_verifications database table, leveraging the id field
   * as the unique identifier.
   *
   * Behavior: The deletion is a hard delete, meaning the record is removed
   * entirely from the database. No soft deletion or archival is performed.
   *
   * Related Operations: Operations to create or list email verification codes
   * complement this endpoint, enabling full lifecycle management of user email
   * verifications.
   *
   * @param connection
   * @param userEmailVerificationId Unique identifier of the user email
   *   verification record to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userEmailVerificationId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userEmailVerificationId")
    userEmailVerificationId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserUsersEmailVerificationsUserEmailVerificationId(
        {
          user,
          userEmailVerificationId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
