  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userRoleId")
    userRoleId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppRole> {
    try {
      return await getTodoAppUserUsersRolesUserRoleId({
        user,
        userRoleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

