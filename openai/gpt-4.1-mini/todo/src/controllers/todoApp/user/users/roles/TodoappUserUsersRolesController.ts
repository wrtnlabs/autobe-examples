import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppUserUsersUserIdRoles } from "../../../../../providers/postTodoAppUserUsersUserIdRoles";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { patchTodoAppUserUsersUserIdRoles } from "../../../../../providers/patchTodoAppUserUsersUserIdRoles";
import { getTodoAppUserUsersUserIdRolesUserRoleId } from "../../../../../providers/getTodoAppUserUsersUserIdRolesUserRoleId";
import { putTodoAppUserUsersUserIdRolesUserRoleId } from "../../../../../providers/putTodoAppUserUsersUserIdRolesUserRoleId";
import { deleteTodoAppUserUsersUserIdRolesUserRoleId } from "../../../../../providers/deleteTodoAppUserUsersUserIdRolesUserRoleId";

import { ITodoAppUserRole } from "../../../../../api/structures/ITodoAppUserRole";

@Controller("/todoApp/user/users/:userId/roles")
export class TodoappUserUsersRolesController {
  /**
   * Assign new roles to a specific user identified by the UUID userId within
   * the todoApp system.
   *
   * This operation enables authenticated users to assign roles that determine
   * permissions and access levels for the target user. The role assignment is
   * critical to enforcing security policies and user segregation in the
   * system.
   *
   * The userId path parameter must be a valid UUID string corresponding to the
   * existing user in the database. The request includes the detailed role data
   * to be assigned, structured as per the ITodoAppUserRole.ICreate DTO.
   *
   * Upon successful assignment, the operation returns the details of the
   * assigned role, confirming the current status and attributes of the user's
   * roles.
   *
   * Security: Access to this endpoint is restricted to authenticated users with
   * proper privileges. Misuse or unauthorized access attempts should be handled
   * by appropriate authorization middleware.
   *
   * @param connection
   * @param userId Unique identifier of the target user as a UUID string
   * @param body Role assignment details for creating a new user role
   *   association
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUserRole.ICreate,
  ): Promise<ITodoAppUserRole> {
    try {
      return await postTodoAppUserUsersUserIdRoles({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the roles assigned to a specific user in the system.
   *
   * This operation enables users to assign new roles or remove existing roles
   * from their profile. It operates on the association between users and roles
   * managed through the todo_app_user_roles database table.
   *
   * The user to update is identified by the userId path parameter, a UUID
   * corresponding to a record in the todo_app_users table.
   *
   * This operation requires user-level authorization as only authenticated
   * users can modify their role assignments.
   *
   * The request body specifies role updates using the ITodoAppUserRole.IRequest
   * type, while the response confirms the updated role data as
   * ITodoAppUserRole.
   *
   * This endpoint is pivotal for dynamic and secure management of user
   * permissions within the TodoApp environment.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @param body Request body containing role update information for the user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updateRoles(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUserRole.IRequest,
  ): Promise<ITodoAppUserRole> {
    try {
      return await patchTodoAppUserUsersUserIdRoles({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific role assigned to a user in
   * the todoApp system.
   *
   * This operation fetches the user role assignment identified by the composite
   * keys userId and userRoleId, corresponding to the specific record in the
   * todo_app_user_roles table. It enables inspection of the relationship
   * between a user and their role for purposes such as access control and
   * authorization management.
   *
   * Security considerations dictate that only authenticated users, typically
   * the user themselves or administrators, can access this data to prevent
   * unauthorized role disclosures.
   *
   * Parameters userId and userRoleId must be valid UUIDs uniquely identifying
   * the user and the role association. The response includes all relevant
   * fields defined in the database schema for the user role entity.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @param userRoleId Unique identifier of the user role assignment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userRoleId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("userRoleId")
    userRoleId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUserRole> {
    try {
      return await getTodoAppUserUsersUserIdRolesUserRoleId({
        user,
        userId,
        userRoleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates an existing user role associated with a specific user in the
   * todoApp system.
   *
   * This operation allows authorized authenticated users to modify the details
   * of a given user role assigned to a user identified by the provided userId
   * and userRoleId. The user roles entity governs the permissions and access
   * levels within the application and is tightly coupled with the user
   * identity.
   *
   * Security considerations require that only authenticated users with
   * sufficient privileges may perform this operation. The operation validates
   * the existence of both the user and the user role and ensures the updates
   * adhere to business rules defined in the user roles management.
   *
   * This operation operates on the `todo_app_user_roles` database table mapped
   * to the `ITodoAppUserRole` entity. It is part of the user management feature
   * set ensuring proper role maintenance and access control.
   *
   * Related API operations include `GET /users/{userId}/roles` to list roles
   * and `POST /users/{userId}/roles` to create new roles.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @param userRoleId Unique identifier of the target user role
   * @param body Update payload for the ITodoAppUserRole entity excluding userId
   *   and userRoleId path parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userRoleId")
  public async updateUserRole(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("userRoleId")
    userRoleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUserRole.IUpdate,
  ): Promise<ITodoAppUserRole> {
    try {
      return await putTodoAppUserUsersUserIdRolesUserRoleId({
        user,
        userId,
        userRoleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation permanently deletes a role association from a user in the
   * todoApp system.
   *
   * It requires specifying the user and the specific role link to remove via
   * the unique identifiers userId and userRoleId in the path parameters.
   *
   * Only authenticated users have permission to manage their own roles,
   * ensuring access control is maintained.
   *
   * The DELETE method requires no request body, and upon success, the operation
   * returns no content.
   *
   * This endpoint is critical for maintaining user roles and permissions,
   * directly supporting todoApp's privacy and access control strategies.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @param userRoleId Unique identifier of the user-role association to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userRoleId")
  public async eraseUserRole(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("userRoleId")
    userRoleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserUsersUserIdRolesUserRoleId({
        user,
        userId,
        userRoleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
