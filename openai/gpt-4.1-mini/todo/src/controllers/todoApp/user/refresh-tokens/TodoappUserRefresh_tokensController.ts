import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppUserRefreshTokens } from "../../../../providers/postTodoAppUserRefreshTokens";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoAppUserRefreshTokens } from "../../../../providers/patchTodoAppUserRefreshTokens";
import { putTodoAppUserRefreshTokensRefreshTokenId } from "../../../../providers/putTodoAppUserRefreshTokensRefreshTokenId";
import { deleteTodoAppUserRefreshTokensRefreshTokenId } from "../../../../providers/deleteTodoAppUserRefreshTokensRefreshTokenId";

import { ITodoAppRefreshToken } from "../../../../api/structures/ITodoAppRefreshToken";

@Controller("/todoApp/user/refresh-tokens")
export class TodoappUserRefresh_tokensController {
  /**
   * Create a new refresh token in the system. This operation enables
   * authenticated users or guests to obtain a new refresh token, which is
   * essential for maintaining a valid authentication session without having to
   * re-login.
   *
   * This API operation works on the todo_app_refresh_tokens database table,
   * which stores token details and expiration information. It requires
   * supplying valid token creation data, including the associated user or guest
   * identifier, token value, and expiry timestamps.
   *
   * Security: Only users and guests are authorized to call this endpoint to
   * ensure that refresh tokens are appropriately issued and managed under
   * authentication rules.
   *
   * Related operations: This typically works alongside access token issuance
   * endpoints and user session management APIs to provide a complete
   * authentication experience.
   *
   * @param connection
   * @param body The information needed to create a new refresh token record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppRefreshToken.ICreate,
  ): Promise<ITodoAppRefreshToken> {
    try {
      return await postTodoAppUserRefreshTokens({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh the authentication access token using a valid refresh token.
   *
   * This operation accepts a refresh token linked to an authenticated user and
   * issues a new access token.
   *
   * It operates on the todo_app_refresh_tokens table which stores refresh
   * tokens for user sessions. Only authenticated users have permission to
   * refresh tokens.
   *
   * The request body must contain the relevant refresh token data as defined in
   * the ITodoAppRefreshToken.IRequest DTO.
   *
   * The response returns the refreshed token entity providing updated token
   * details for continued authentication.
   *
   * Security considerations include validation of token integrity, expiration,
   * and user authorization checks.
   *
   * This operation uses the PATCH HTTP method to represent partial update of
   * token state and session renewal.
   *
   * Related operations include the POST /auth/login endpoint for initial login
   * token issuance.
   *
   * @param connection
   * @param body Payload to refresh the authentication token
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async patch(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppRefreshToken.IRequest,
  ): Promise<ITodoAppRefreshToken> {
    try {
      return await patchTodoAppUserRefreshTokens({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing refresh token in the todoApp system by its unique
   * identifier.
   *
   * This operation modifies properties of a refresh token issued to an
   * authenticated user, enabling management of token expiration and revocation
   * status. The refresh tokens are stored in the todo_app_refresh_tokens
   * database table, which includes fields for token value, expiration
   * timestamp, revocation flags, and user association.
   *
   * Only the owner user of the refresh token can perform this update, enforcing
   * security and preventing unauthorized usage. The refreshTokenId path
   * parameter uniquely identifies the token record to be updated.
   *
   * On successful update, the refreshed token entity is returned with current
   * details reflecting any changes. This operation is essential for maintaining
   * secure and valid user sessions, supporting token lifecycle management
   * within authentication workflows.
   *
   * Related operations include creating new refresh tokens during login and
   * deleting tokens upon logout or expiration.
   *
   * @param connection
   * @param refreshTokenId Unique UUID identifier of the refresh token to update
   * @param body Update details for the refresh token
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":refreshTokenId")
  public async putByRefreshtokenid(
    @UserAuth()
    user: UserPayload,
    @TypedParam("refreshTokenId")
    refreshTokenId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppRefreshToken.IUpdate,
  ): Promise<ITodoAppRefreshToken> {
    try {
      return await putTodoAppUserRefreshTokensRefreshTokenId({
        user,
        refreshTokenId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently deletes a refresh token identified by its unique ID from the
   * todoApp system.
   *
   * This operation interacts directly with the todo_app_refresh_tokens table in
   * the database, removing the specified token record to invalidate the session
   * and prevent further use of the token for authentication.
   *
   * Only authenticated users are permitted to perform this operation to ensure
   * token security and prevent unauthorized invalidation of active sessions.
   *
   * Deleting a refresh token is irreversible and effectively logs out the user
   * session associated with the token.
   *
   * Typical use cases include user logout processes or administrative token
   * management tasks.
   *
   * No request body is required, and the response contains no content
   * indicating successful deletion.
   *
   * This is a hard delete operation removing the token record entirely from the
   * database, reflecting the importance of securely managing authentication
   * tokens.
   *
   * @param connection
   * @param refreshTokenId Unique identifier of the refresh token to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":refreshTokenId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("refreshTokenId")
    refreshTokenId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserRefreshTokensRefreshTokenId({
        user,
        refreshTokenId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
