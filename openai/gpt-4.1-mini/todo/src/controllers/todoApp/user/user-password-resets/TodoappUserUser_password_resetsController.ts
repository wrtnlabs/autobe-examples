import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppUserUserPasswordResets } from "../../../../providers/patchTodoAppUserUserPasswordResets";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { putTodoAppUserUserPasswordResetsUserPasswordResetId } from "../../../../providers/putTodoAppUserUserPasswordResetsUserPasswordResetId";
import { deleteTodoAppUserUserPasswordResetsUserPasswordResetId } from "../../../../providers/deleteTodoAppUserUserPasswordResetsUserPasswordResetId";

import { IPageITodoAppUserPasswordReset } from "../../../../api/structures/IPageITodoAppUserPasswordReset";
import { ITodoAppUserPasswordReset } from "../../../../api/structures/ITodoAppUserPasswordReset";

@Controller("/todoApp/user/user-password-resets")
export class TodoappUserUser_password_resetsController {
  /**
   * Retrieve a filtered and paginated list of user password reset requests in
   * the todoApp system.
   *
   * This operation interfaces with the todo_app_user_password_resets database
   * table, providing advanced search functionality to find password reset
   * entries based on criteria such as token value, creation date ranges,
   * expiration status, and associated user identifiers.
   *
   * Security: Access to this endpoint is restricted to authenticated users with
   * the 'user' actor, ensuring confidentiality of password reset information.
   * The operation supports pagination and sorting to handle potentially large
   * result sets efficiently.
   *
   * This search operation facilitates user account recovery workflows, allowing
   * users or authorized personnel to review active or expired password reset
   * tokens. It integrates with authentication and session management systems
   * for security enforcement.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for user password
   *   reset entries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppUserPasswordReset.IRequest,
  ): Promise<IPageITodoAppUserPasswordReset.ISummary> {
    try {
      return await patchTodoAppUserUserPasswordResets({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a user password reset entry in the todoApp system.
   *
   * This operation modifies an existing user password reset record identified
   * by the given path parameter userPasswordResetId. The entity corresponds to
   * the `todo_app_user_password_resets` table which stores tokens and statuses
   * used for password resets. Users can update fields such as reset tokens,
   * expiration timestamps, and usage flags. The operation enforces strict
   * authentication, permitting only authorized users to update their reset
   * information.
   *
   * Security considerations include validation of token integrity and
   * expiration, ensuring that password resets are only processed for valid and
   * non-expired tokens. This protects user accounts against unauthorized access
   * and replay attacks.
   *
   * The operation includes comprehensive input validation against the database
   * schema, adherence to authorization policies restricting operation access to
   * authenticated users, and ensures data consistency and integrity upon
   * update.
   *
   * @param connection
   * @param userPasswordResetId Unique identifier of the target user password
   *   reset record
   * @param body Request body for updating user password reset information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userPasswordResetId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userPasswordResetId")
    userPasswordResetId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUserPasswordReset.IUpdate,
  ): Promise<ITodoAppUserPasswordReset> {
    try {
      return await putTodoAppUserUserPasswordResetsUserPasswordResetId({
        user,
        userPasswordResetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation permanently deletes a user password reset entry from the
   * todo_app_user_password_resets table. The password reset record is
   * identified by the unique userPasswordResetId provided in the path
   * parameter.
   *
   * This endpoint is part of the account security workflow allowing
   * authenticated users to invalidate their password reset requests if they are
   * no longer needed or to clean up expired reset tokens.
   *
   * Security considerations include restricting access to only authorized users
   * to prevent malicious deletion attempts.
   *
   * The deletion is final with no recovery option, and no response body is
   * returned upon successful deletion.
   *
   * @param connection
   * @param userPasswordResetId Unique identifier of the target user password
   *   reset entry
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userPasswordResetId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userPasswordResetId")
    userPasswordResetId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserUserPasswordResetsUserPasswordResetId({
        user,
        userPasswordResetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
