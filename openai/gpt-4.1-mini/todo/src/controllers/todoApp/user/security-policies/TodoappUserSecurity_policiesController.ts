import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppUserSecurityPolicies } from "../../../../providers/postTodoAppUserSecurityPolicies";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoAppUserSecurityPolicies } from "../../../../providers/patchTodoAppUserSecurityPolicies";
import { getTodoAppUserSecurityPoliciesSecurityPolicyId } from "../../../../providers/getTodoAppUserSecurityPoliciesSecurityPolicyId";
import { putTodoAppUserSecurityPoliciesSecurityPolicyId } from "../../../../providers/putTodoAppUserSecurityPoliciesSecurityPolicyId";
import { deleteTodoAppUserSecurityPoliciesSecurityPolicyId } from "../../../../providers/deleteTodoAppUserSecurityPoliciesSecurityPolicyId";

import { ITodoAppSecurityPolicy } from "../../../../api/structures/ITodoAppSecurityPolicy";
import { IPageITodoAppSecurityPolicy } from "../../../../api/structures/IPageITodoAppSecurityPolicy";

@Controller("/todoApp/user/security-policies")
export class TodoappUserSecurity_policiesController {
  /**
   * Create a new security policy within the todoApp system.
   *
   * This operation allows authenticated users to add new security policy
   * entries to the system's security policy repository. Each policy defines
   * specific rules and permissions that govern user behaviors and system
   * operations.
   *
   * The operation expects well-formed requests conforming to the
   * ITodoAppSecurityPolicy.ICreate DTO structure, ensuring consistent and
   * validated data input. On success, the newly created policy record is
   * returned following the ITodoAppSecurityPolicy schema.
   *
   * Security considerations include strict authorization requirements, ensuring
   * only valid users can create policies. Input validation and uniqueness
   * enforcement are critical to maintaining system integrity.
   *
   * This interface complements other security management endpoints by providing
   * policy creation capabilities. It is essential for administrators managing
   * fine-grained security configurations.
   *
   * @param connection
   * @param body Payload containing the security policy creation data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppSecurityPolicy.ICreate,
  ): Promise<ITodoAppSecurityPolicy> {
    try {
      return await postTodoAppUserSecurityPolicies({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of todoApp security policies from
   * the system.
   *
   * This endpoint allows clients to specify complex search criteria and
   * pagination parameters in the request body to query security policies
   * effectively. It operates on the todo_app_security_policies table,
   * incorporating all relevant fields and relationships defined within the
   * database schema.
   *
   * The operation enforces user authentication to ensure that only authorized
   * users can access policy data, maintaining system security and integrity.
   *
   * This API is essential for administrative tools that monitor, manage, and
   * audit security policies across the todoApp platform, facilitating
   * compliance and role-based access control.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   security policies
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppSecurityPolicy.IRequest,
  ): Promise<IPageITodoAppSecurityPolicy.ISummary> {
    try {
      return await patchTodoAppUserSecurityPolicies({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation fetches the full details of a single security policy
   * identified by its unique ID in the todo_app_security_policies table.
   *
   * The security policy entity governs access control rules for various
   * components of the todoApp. Retrieving this information enables
   * administrative or user-level clients to understand the current policies
   * enforced within the system.
   *
   * Security considerations require that only authenticated users can access
   * this endpoint, preventing unauthorized disclosure of security
   * configurations.
   *
   * The operation requires the securityPolicyId as a path parameter, which
   * corresponds to the UUID primary key of the security policy. The response
   * returns the complete ITodoAppSecurityPolicy interface mapping the database
   * schema fields.
   *
   * This endpoint does not support request bodies, reflecting standard GET
   * operation semantics.
   *
   * Related operations include listing all security policies (PATCH
   * /security-policies) and updating a policy (PUT
   * /security-policies/{securityPolicyId}).
   *
   * @param connection
   * @param securityPolicyId Unique identifier of the target security policy
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":securityPolicyId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("securityPolicyId")
    securityPolicyId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppSecurityPolicy> {
    try {
      return await getTodoAppUserSecurityPoliciesSecurityPolicyId({
        user,
        securityPolicyId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing security policy in the todo_app_security_policies table.
   *
   * This operation allows an authenticated user to modify security policy
   * details identified by a unique UUID securityPolicyId. The security policy
   * defines access rules and permissions vital for securing user resources and
   * application functionality within the TodoApp platform.
   *
   * Security considerations ensure only authorized authenticated users can
   * perform updates. Detailed validation is performed on request data that must
   * comply with the schema constraints.
   *
   * The path parameter securityPolicyId corresponds to the policy's unique
   * identifier in UUID format. The request body must follow the
   * ITodoAppSecurityPolicy.IUpdate structure, specifying which fields to
   * modify.
   *
   * The response provides the full updated security policy entity confirming
   * the successful update.
   *
   * Related operations include retrieval (GET) of security policies and
   * creation (POST) of new policies for initial setup.
   *
   * @param connection
   * @param securityPolicyId Unique identifier of the target security policy
   *   (UUID)
   * @param body The security policy update payload following
   *   ITodoAppSecurityPolicy.IUpdate schema
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":securityPolicyId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("securityPolicyId")
    securityPolicyId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppSecurityPolicy.IUpdate,
  ): Promise<ITodoAppSecurityPolicy> {
    try {
      return await putTodoAppUserSecurityPoliciesSecurityPolicyId({
        user,
        securityPolicyId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes the specified security policy identified by
   * securityPolicyId from the todoApp system.
   *
   * This operation targets the todo_app_security_policies table where security
   * policies are stored. The securityPolicyId path parameter is used to
   * precisely locate and delete the desired record.
   *
   * Only authorized users with appropriate permissions can perform this
   * operation to ensure system security and policy integrity. On successful
   * deletion, no content is returned.
   *
   * This endpoint is critical for maintaining an up-to-date security
   * configuration by allowing obsolete or compromised security policies to be
   * cleanly removed.
   *
   * Related operations include creation and update endpoints for security
   * policies which manage policy lifecycle.
   *
   * @param connection
   * @param securityPolicyId Unique identifier of the security policy to be
   *   deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":securityPolicyId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("securityPolicyId")
    securityPolicyId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserSecurityPoliciesSecurityPolicyId({
        user,
        securityPolicyId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
