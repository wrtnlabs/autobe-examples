import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppUserRoles } from "../../../../providers/postTodoAppUserRoles";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoAppUserRoles } from "../../../../providers/patchTodoAppUserRoles";
import { getTodoAppUserRolesRoleCode } from "../../../../providers/getTodoAppUserRolesRoleCode";
import { putTodoAppUserRolesRoleCode } from "../../../../providers/putTodoAppUserRolesRoleCode";
import { deleteTodoAppUserRolesRoleCode } from "../../../../providers/deleteTodoAppUserRolesRoleCode";

import { ITodoAppRole } from "../../../../api/structures/ITodoAppRole";
import { IPageITodoAppRole } from "../../../../api/structures/IPageITodoAppRole";

@Controller("/todoApp/user/roles")
export class TodoappUserRolesController {
  /**
   * Create a new user role in the todoApp system.
   *
   * This API operation allows administrators or authorized users to define new
   * roles which encapsulate permissions and access levels.
   *
   * The role information is stored in the todo_app_roles database table,
   * including role name, description, and permission settings.
   *
   * Creating a role enhances the user management capabilities by enabling
   * flexible and granular access control.
   *
   * Refer to the todo_app_roles table schema for detailed field definitions and
   * validation rules.
   *
   * Security considerations include authorization checks ensuring only
   * privileged users can create roles.
   *
   * @param connection
   * @param body Request payload containing the new role details to be created
   *   in the system.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppRole.ICreate,
  ): Promise<ITodoAppRole> {
    try {
      return await postTodoAppUserRoles({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of user roles within the todoApp
   * system. The roles are defined in the todo_app_roles table in the database
   * schema and include all relevant properties that describe the role's
   * attributes and permissions.
   *
   * This operation allows clients to specify complex search criteria, filtering
   * options, and sorting preferences within the request body to narrow down the
   * list of roles returned. Pagination support is included to manage large
   * result sets efficiently.
   *
   * Security considerations should ensure that only authorized users, such as
   * administrators, can access the list of roles. Appropriate validation of
   * request parameters is applied to maintain data integrity and
   * confidentiality.
   *
   * This endpoint serves as a foundational operation for role administration
   * and management within the todoApp platform, providing necessary role data
   * to client applications.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for role filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppRole.IRequest,
  ): Promise<IPageITodoAppRole.ISummary> {
    try {
      return await patchTodoAppUserRoles({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a single user role by its unique code in
   * the todoApp system.
   *
   * This operation fetches the role entity from the todo_app_roles table, which
   * defines application roles and their corresponding permissions and access
   * levels. It uses the roleCode path parameter as the unique business
   * identifier (code) scoped globally within the roles table.
   *
   * The operation returns a complete role object including its code, name, and
   * description as defined in the database. This allows client applications or
   * administrative tools to display or manage role information accurately.
   *
   * Security considerations include ensuring that only authorized users,
   * typically administrators, can access this endpoint to prevent unauthorized
   * disclosure of role definitions and permission settings. The database schema
   * enforces the uniqueness of the roleCode ensuring reliable lookup.
   *
   * Related operations include role listing, creation, and updates which should
   * be implemented for full role management capabilities.
   *
   * @param connection
   * @param roleCode Unique business identifier code of the target role (global
   *   scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":roleCode")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("roleCode")
    roleCode: string & tags.Format<"uuid">,
  ): Promise<ITodoAppRole> {
    try {
      return await getTodoAppUserRolesRoleCode({
        user,
        roleCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing user role in the todoApp system.
   *
   * This operation allows administrators to update role details, including name
   * and permissions, for an existing role identified by its unique code. The
   * roleCode parameter in the path specifies the target role namespace within
   * the system, ensuring precise updates.
   *
   * Security considerations: Only authorized administrative users can perform
   * this operation due to the sensitive nature of role management. Validation
   * is performed on updated fields to ensure data integrity and compliance with
   * business rules.
   *
   * This operation directly manipulates the todo_app_roles table in the
   * database, reflecting changes in the role management module.
   *
   * Related operations include GET /roles/{roleCode} for retrieving role
   * details and DELETE /roles/{roleCode} for role removal.
   *
   * @param connection
   * @param roleCode Unique business identifier code of the target role (global
   *   scope)
   * @param body Updated role information for the specified roleCode
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":roleCode")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("roleCode")
    roleCode: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppRole.IUpdate,
  ): Promise<ITodoAppRole> {
    try {
      return await putTodoAppUserRolesRoleCode({
        user,
        roleCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Deletes a role identified by its unique roleCode from the todoApp system.
   *
   * This API operation permanently removes the role record from the
   * todo_app_roles table. The role is uniquely identified using the roleCode
   * path parameter, which corresponds to the unique code field in the database
   * schema ensuring unambiguous target selection.
   *
   * Use of this operation requires administrative privileges, as deleting a
   * role may impact user permissions and system security. Proper authorization
   * checks must be enforced before executing the deletion.
   *
   * No request body is needed since the operation is fully specified by the
   * path parameter. Upon successful deletion, no content is returned.
   *
   * Related operations include role creation and role listing endpoints that
   * manage role lifecycle comprehensively.
   *
   * @param connection
   * @param roleCode Unique business identifier code of the target role (global
   *   scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":roleCode")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("roleCode")
    roleCode: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserRolesRoleCode({
        user,
        roleCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
