import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppUserRoles } from "../../../../providers/postTodoAppUserRoles";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoAppUserRoles } from "../../../../providers/patchTodoAppUserRoles";
import { getTodoAppUserRolesRoleCode } from "../../../../providers/getTodoAppUserRolesRoleCode";
import { putTodoAppUserRolesRoleCode } from "../../../../providers/putTodoAppUserRolesRoleCode";

import { ITodoAppRole } from "../../../../api/structures/ITodoAppRole";
import { IPageITodoAppRole } from "../../../../api/structures/IPageITodoAppRole";

@Controller("/todoApp/user/roles")
export class TodoappUserRolesController {
  /**
   * Create a new user role in the todoApp system.
   *
   * This operation allows authenticated users to define roles that specify
   * access control and permissions within the todoApp. The todo_app_roles model
   * defines the structure of roles, ensuring consistent role data.
   *
   * Only authorized users can access this endpoint to maintain security
   * integrity.
   *
   * The request body must follow the ITodoAppRole.ICreate DTO specification for
   * role creation. Upon success, the full details of the newly created role are
   * returned.
   *
   * @param connection
   * @param body Payload containing the role creation data as per todo_app_roles
   *   schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppRole.ICreate,
  ): Promise<ITodoAppRole> {
    try {
      return await postTodoAppUserRoles({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of todoApp application roles from
   * the system. This operation corresponds to the todo_app_roles database
   * table, which defines roles with associated permissions and access levels.
   *
   * This endpoint allows authenticated users to query roles using various
   * search filters and pagination options provided in the request body. It
   * supports efficient browsing and management of roles within the system.
   *
   * Access controls ensure only authorized users can access this endpoint,
   * safeguarding sensitive role information from unauthorized access.
   *
   * The response consists of a paginated collection of role summaries, which
   * includes essential role details optimized for user overview and does not
   * expose internal system metadata unnecessarily.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering roles
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppRole.IRequest,
  ): Promise<IPageITodoAppRole.ISummary> {
    try {
      return await patchTodoAppUserRoles({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information about a specific application role identified
   * by its unique roleCode.
   *
   * This operation interfaces with the todo_app_roles database table, which
   * defines roles and their permissions within the todoApp system. It supports
   * authorized users in managing role configurations and understanding access
   * levels.
   *
   * Authenticated users can fetch role data by specifying the roleCode, which
   * uniquely identifies each role globally. This helps enforce security and
   * permission standards by controlling role visibility.
   *
   * No request body is required since this is a read-only operation. The
   * endpoint restricts access to authenticated users only, enhancing system
   * security.
   *
   * @param connection
   * @param roleCode Unique business identifier code of the target role (global
   *   scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":roleCode")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("roleCode")
    roleCode: number & tags.Minimum<1> & tags.Maximum<128> & tags.MultipleOf<1>,
  ): Promise<ITodoAppRole> {
    try {
      return await getTodoAppUserRolesRoleCode({
        user,
        roleCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing role in the todoApp system identified by its unique
   * business code.
   *
   * This operation allows authenticated users to change the properties of a
   * specific role within the system. The role is identified by the 'roleCode'
   * path parameter, representing a human-readable unique business code.
   *
   * The request body must conform to the ITodoAppRole.IUpdate DTO, which
   * includes all fields that are allowed to be updated. This strict typing
   * enforces validation and prevents unauthorized or accidental changes to
   * immutable properties.
   *
   * Security is essential; only users with the 'user' actor are allowed to
   * execute this operation, preventing unauthorized access.
   *
   * Upon success, the operation returns the updated concrete role entity,
   * reflecting all applied changes. This response follows the ITodoAppRole
   * schema and provides the client with a reliable current state of the role.
   *
   * This operation maps to the todo_app_roles table in the database where role
   * metadata and permission data are stored. Proper validation and
   * authorization ensure alignment between API and data store.
   *
   * Related operations include POST /roles to create new roles and GET
   * /roles/{roleCode} to retrieve role details.
   *
   * @param connection
   * @param roleCode Unique business identifier code of the target role (global
   *   scope)
   * @param body Update data for the targeted role. Accepts ITodoAppRole.IUpdate
   *   DTO structures.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":roleCode")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("roleCode")
    roleCode: number & tags.Minimum<1> & tags.MultipleOf<0.5>,
    @TypedBody()
    body: ITodoAppRole.IUpdate,
  ): Promise<ITodoAppRole> {
    try {
      return await putTodoAppUserRolesRoleCode({
        user,
        roleCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
