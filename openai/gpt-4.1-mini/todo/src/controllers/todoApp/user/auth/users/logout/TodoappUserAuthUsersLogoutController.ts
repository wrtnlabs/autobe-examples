import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postTodoAppUserAuthUsersLogout } from "../../../../../../providers/postTodoAppUserAuthUsersLogout";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";

@Controller("/todoApp/user/auth/users/logout")
export class TodoappUserAuthUsersLogoutController {
  /**
   * This endpoint is for user logout functionality, which is managed by a
   * specialized authentication service and not handled by this API operation
   * generator.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async erase(
    @UserAuth()
    user: UserPayload,
  ): Promise<void> {
    try {
      return await postTodoAppUserAuthUsersLogout({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
