import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppUserUserSessions } from "../../../../providers/patchTodoAppUserUserSessions";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoAppUserUserSessionsUserSessionId } from "../../../../providers/getTodoAppUserUserSessionsUserSessionId";

import { IPageITodoAppUserSession } from "../../../../api/structures/IPageITodoAppUserSession";
import { ITodoAppUserSession } from "../../../../api/structures/ITodoAppUserSession";

@Controller("/todoApp/user/user-sessions")
export class TodoappUserUser_sessionsController {
  /**
   * Retrieve a filtered and paginated list of user sessions in the todoApp
   * system. This operation enables authenticated users to query their active
   * and inactive sessions with flexible search criteria, including session
   * status, creation date ranges, expiration checks, IP address filters, and
   * device user agent matching. The underlying database table is
   * todo_app_user_sessions, which stores session tokens, refresh tokens, user
   * associations, login timestamps, client IP addresses, user agent details,
   * and expiration metadata.
   *
   * Security considerations include ensuring that users can only access their
   * own session records, supporting GDPR compliance with easy session
   * revocation and auditing. This operation is critical for user account
   * management, enabling viewing and controlling of concurrent session
   * activities.
   *
   * The request body supports pagination parameters such as page number, page
   * size, and sorting options, enabling scalable and performant retrieval of
   * session lists.
   *
   * Expected responses include a paginated list of session summaries,
   * contributing to user dashboard functionality and account security
   * monitoring.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering user
   *   sessions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppUserSession.IRequest,
  ): Promise<IPageITodoAppUserSession.ISummary> {
    try {
      return await patchTodoAppUserUserSessions({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific user session identified by its
   * unique session ID in the todoApp system.
   *
   * This operation accesses the todo_app_user_sessions table, which stores
   * authentication session records including session tokens, expiry, associated
   * user ID, and metadata such as creation and update timestamps.
   *
   * Security considerations apply to ensure only authorized users can access
   * their own session details. The operation validates that the session ID
   * exists and belongs to the requesting user. Any unauthorized access attempts
   * result in appropriate error responses.
   *
   * This operation is read-only and does not modify session data. Related
   * operations include session management endpoints such as session creation
   * and deletion.
   *
   * @param connection
   * @param userSessionId Unique identifier of the target user session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userSessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userSessionId")
    userSessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUserSession> {
    try {
      return await getTodoAppUserUserSessionsUserSessionId({
        user,
        userSessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
