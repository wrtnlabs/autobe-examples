import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppUserTodoItemAuditLogs } from "../../../../providers/patchTodoAppUserTodoItemAuditLogs";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoAppUserTodoItemAuditLogsAuditLogId } from "../../../../providers/getTodoAppUserTodoItemAuditLogsAuditLogId";

import { IPageITodoAppTodoItemAuditLog } from "../../../../api/structures/IPageITodoAppTodoItemAuditLog";
import { ITodoAppTodoItemAuditLog } from "../../../../api/structures/ITodoAppTodoItemAuditLog";

@Controller("/todoApp/user/todo-item-audit-logs")
export class TodoappUserTodo_item_audit_logsController {
  /**
   * Retrieve a filtered and paginated list of todo item audit log entries from
   * the system. This operation corresponds to the todo_app_todo_item_audit_logs
   * table in the database, which maintains records of changes, actions, and
   * events related to todo items for traceability and auditing purposes.
   *
   * Clients can specify detailed search criteria including filtering by todo
   * item identifiers, timestamps, user identifiers who made changes, and action
   * types. Pagination and sorting are supported to manage potentially large
   * datasets efficiently.
   *
   * Authorization is required for authenticated users, ensuring that sensitive
   * audit information is only accessible to users with appropriate permissions.
   * This operation helps users and administrators monitor todo item activities,
   * investigate changes, and maintain accountability within the system.
   *
   * The request body supports comprehensive filtering criteria encapsulated in
   * ITodoAppTodoItemAuditLog.IRequest, enabling sophisticated queries. The
   * response provides paginated summaries of matching audit log entries in
   * IPageITodoAppTodoItemAuditLog.ISummary format, optimizing response size and
   * performance.
   *
   * Related operations include creating and updating todo items, which generate
   * audit logs implicitly within the system business logic.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for todo item audit
   *   logs filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTodoItemAuditLog.IRequest,
  ): Promise<IPageITodoAppTodoItemAuditLog.ISummary> {
    try {
      return await patchTodoAppUserTodoItemAuditLogs({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific todo item audit log identified
   * by its unique UUID.
   *
   * This endpoint exposes the todo_app_todo_item_audit_logs table where all
   * audit actions (create, update, delete) on todo items are logged for
   * compliance and tracking purposes.
   *
   * Access to this endpoint is limited to authenticated users with the
   * appropriate permissions to ensure audit log confidentiality and prevent
   * unauthorized data exposure. Proper authorization and security auditing are
   * necessary when using this operation.
   *
   * @param connection
   * @param auditLogId Unique identifier of the target todo item audit log entry
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":auditLogId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("auditLogId")
    auditLogId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodoItemAuditLog> {
    try {
      return await getTodoAppUserTodoItemAuditLogsAuditLogId({
        user,
        auditLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
