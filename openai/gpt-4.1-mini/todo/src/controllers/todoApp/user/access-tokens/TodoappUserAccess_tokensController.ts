import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppUserAccessTokens } from "../../../../providers/patchTodoAppUserAccessTokens";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { putTodoAppUserAccessTokensAccessTokenId } from "../../../../providers/putTodoAppUserAccessTokensAccessTokenId";
import { deleteTodoAppUserAccessTokensAccessTokenId } from "../../../../providers/deleteTodoAppUserAccessTokensAccessTokenId";

import { IPageITodoAppAccessToken } from "../../../../api/structures/IPageITodoAppAccessToken";
import { ITodoAppAccessToken } from "../../../../api/structures/ITodoAppAccessToken";

@Controller("/todoApp/user/access-tokens")
export class TodoappUserAccess_tokensController {
  /**
   * Retrieve a filtered, paginated list of todoApp access tokens stored in the
   * system.
   *
   * This operation enables authorized users to query access tokens using
   * multiple filter criteria including user association, token validity,
   * expiration dates, and token type. It supports pagination to allow browsing
   * through large sets of tokens efficiently.
   *
   * The access tokens represented correspond to the todo_app_access_tokens
   * database model which securely holds token strings and related metadata for
   * authentication purposes. The API ensures that only authenticated users with
   * appropriate privileges can access this data safely.
   *
   * Advanced filtering includes searching by user ID, token creation and
   * expiration timestamps, and token status flags to manage token lifecycle and
   * audits.
   *
   * This endpoint is part of the authentication management suite, and
   * integrates tightly with related operations such as creating, revoking, or
   * refreshing tokens.
   *
   * Security: Only users authorized as "user" may access this endpoint with
   * appropriate backend filtering.
   *
   * Usage example: A user might use this endpoint to list all their own active
   * tokens for auditing or to find expired tokens pending cleanup.
   *
   * @param connection
   * @param body Search and filter criteria for listing todoApp access tokens
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppAccessToken.IRequest,
  ): Promise<IPageITodoAppAccessToken.ISummary> {
    try {
      return await patchTodoAppUserAccessTokens({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing access token in the todoApp system by its unique
   * identifier.
   *
   * This operation allows authorized users to modify details of an issued
   * access token such as expiration times or revocation flags. The access token
   * is identified by the accessTokenId path parameter which references the
   * unique identifier in the todo_app_access_tokens database table.
   *
   * Security considerations restrict this operation to authenticated users who
   * own the token. The operation ensures data integrity and consistent state of
   * issued tokens used for authentication and session management throughout the
   * todoApp service.
   *
   * The request body must provide the fields to update within the access token
   * entity, adhering to the ITodoAppAccessToken.IUpdate schema which
   * encapsulates modifiable token properties.
   *
   * This API operation corresponds directly to the todo_app_access_tokens table
   * structure, enabling effective management of authentication tokens with
   * transactional consistency and appropriate authorization enforcement.
   *
   * Related operations: GET /access-tokens/{accessTokenId} to retrieve
   * information about a single access token, DELETE
   * /access-tokens/{accessTokenId} to revoke or remove tokens permanently.
   *
   * @param connection
   * @param accessTokenId Unique identifier of the access token to update
   * @param body Updated details of the access token
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":accessTokenId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("accessTokenId")
    accessTokenId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppAccessToken.IUpdate,
  ): Promise<ITodoAppAccessToken> {
    try {
      return await putTodoAppUserAccessTokensAccessTokenId({
        user,
        accessTokenId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an existing access token from the system, permanently removing it
   * from the todo_app_access_tokens table.
   *
   * This operation invalidates the specified access token, preventing any
   * further use for authentication. It is designed as a hard delete operation,
   * removing the token record from the database entirely.
   *
   * Access token deletion is sensitive and requires authenticated user
   * authorization to prevent unauthorized revocation of tokens.
   *
   * This API uses the accessTokenId parameter in the path to uniquely identify
   * the token to delete. No request body is needed, and no response body is
   * returned, following RESTful best practices for delete operations.
   *
   * @param connection
   * @param accessTokenId Unique identifier of the access token to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":accessTokenId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("accessTokenId")
    accessTokenId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserAccessTokensAccessTokenId({
        user,
        accessTokenId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
