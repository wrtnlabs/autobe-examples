import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppUserTodoItems } from "../../../../providers/postTodoAppUserTodoItems";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoAppUserTodoItems } from "../../../../providers/patchTodoAppUserTodoItems";
import { getTodoAppUserTodoItemsTodoItemId } from "../../../../providers/getTodoAppUserTodoItemsTodoItemId";
import { putTodoAppUserTodoItemsTodoItemId } from "../../../../providers/putTodoAppUserTodoItemsTodoItemId";
import { deleteTodoAppUserTodoItemsTodoItemId } from "../../../../providers/deleteTodoAppUserTodoItemsTodoItemId";

import { ITodoAppTodoItem } from "../../../../api/structures/ITodoAppTodoItem";
import { IPageITodoAppTodoItem } from "../../../../api/structures/IPageITodoAppTodoItem";

@Controller("/todoApp/user/todo-items")
export class TodoappUserTodo_itemsController {
  /**
   * Create a new todo item in the todoApp system.
   *
   * This operation allows an authenticated user to add a new task to their
   * personal todo list. The submitted data must comply with the
   * todo_app_todo_items table schema, including fields like title, description,
   * due date, and completion status.
   *
   * Security is enforced by restricting the operation to authenticated users
   * only. The user identification is derived from the JWT token of the
   * authenticated session, and the todo item is associated automatically with
   * the user.
   *
   * Upon successful creation, the complete todo item data as stored in the
   * database is returned in the response.
   *
   * This operation references the todo_app_todo_items table structure and
   * ensures data consistency and validity according to the defined schema
   * constraints.
   *
   * @param connection
   * @param body Payload structure for creating a new todo item complying with
   *   todo_app_todo_items schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTodoItem.ICreate,
  ): Promise<ITodoAppTodoItem> {
    try {
      return await postTodoAppUserTodoItems({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of todo items belonging to the
   * authenticated user. This operation queries the todo_app_todo_items table to
   * fetch todo items with various filtering criteria such as status, priority,
   * due dates, and keyword search.
   *
   * The response contains a paginated summary of todo items matching the
   * request filters. The operation enforces user-level data isolation,
   * returning only the todo items owned by the authenticated user.
   *
   * This endpoint is crucial for enabling users to efficiently manage and
   * browse their personal todo lists with flexible search and sorting
   * capabilities. Due to its read-only nature, it does not modify any data.
   *
   * Security measures include authentication actor restriction to 'user' and
   * validation of filtering parameters to prevent unauthorized data access or
   * potential abuse.
   *
   * Related operations include POST /todo-items (create new todo item), PUT
   * /todo-items/{todoItemId} (update existing todo item), and DELETE
   * /todo-items/{todoItemId} (remove todo item).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for todo item
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTodoItem.IRequest,
  ): Promise<IPageITodoAppTodoItem.ISummary> {
    try {
      return await patchTodoAppUserTodoItems({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific todo item identified by its
   * unique UUID.
   *
   * This operation fetches the todo item from the todo_app_todo_items table in
   * the database. The todo item includes properties such as title, description,
   * due date, completion status, creation timestamp, and update timestamp. The
   * data returned is the full representation of the todo item.
   *
   * Security: Only authenticated users are allowed to access their own todo
   * items. The system enforces user-specific data isolation ensuring no user
   * can see another user's todo items.
   *
   * This API endpoint is critical for client applications to display detailed
   * task information for the logged-in user, supporting task management
   * workflows.
   *
   * @param connection
   * @param todoItemId Unique identifier of the todo item to retrieve (UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoItemId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoItemId")
    todoItemId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodoItem> {
    try {
      return await getTodoAppUserTodoItemsTodoItemId({
        user,
        todoItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo item identified by the unique todoItemId within the
   * todoApp system.
   *
   * This operation allows authenticated users to modify the properties of their
   * personal todo items, including content, completion status, and associated
   * metadata.
   *
   * Security: Only the owner of the todo item or authorized users can perform
   * this update, ensuring data privacy and integrity in a multi-user
   * environment.
   *
   * The todo_app_todo_items table holds the persistent representation of todo
   * items, with fields including id, user_id, content, is_completed,
   * created_at, and updated_at.
   *
   * Validation is applied to ensure the provided data adheres to business rules
   * and schema constraints.
   *
   * Related operations include POST /todo-items for creating new items, GET
   * /todo-items/{todoItemId} for retrieval, and DELETE /todo-items/{todoItemId}
   * for removal.
   *
   * @param connection
   * @param todoItemId Unique identifier of the todo item to update
   * @param body Updated data for the todo item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoItemId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoItemId")
    todoItemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppTodoItem.IUpdate,
  ): Promise<ITodoAppTodoItem> {
    try {
      return await putTodoAppUserTodoItemsTodoItemId({
        user,
        todoItemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation deletes a specific todo item identified by its unique ID
   * from the user's personal todo list.
   *
   * The todo_app_todo_items entity represents a single todo task associated
   * with a user. Deletion of a todo item is a permanent action that removes the
   * record from the database irreversibly.
   *
   * Security measures ensure that only the owner of the todo item
   * (authenticated user) can perform this operation to maintain privacy and
   * data security.
   *
   * No request body is needed as the path parameter uniquely identifies the
   * resource. The system will validate the todoItemId and check user ownership
   * before allowing the deletion process.
   *
   * Failure responses include unauthorized access or not found errors if the
   * todo item does not exist or does not belong to the user.
   *
   * @param connection
   * @param todoItemId Unique identifier of the todo item to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoItemId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoItemId")
    todoItemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserTodoItemsTodoItemId({
        user,
        todoItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
