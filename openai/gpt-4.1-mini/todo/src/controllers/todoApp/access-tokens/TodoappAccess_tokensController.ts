import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoAppAccessTokensAccessTokenId } from "../../../providers/getTodoAppAccessTokensAccessTokenId";
import { postTodoAppAccessTokens } from "../../../providers/postTodoAppAccessTokens";

import { ITodoAppAccessToken } from "../../../api/structures/ITodoAppAccessToken";

@Controller("/todoApp/access-tokens")
export class TodoappAccess_tokensController {
  /**
   * Retrieve detailed information about a specific access token from the
   * todo_app_access_tokens table in the todoApp system.
   *
   * This operation allows clients to fetch and display comprehensive
   * information about the access token identified by the accessTokenId path
   * parameter. Access tokens are critical security credentials used for session
   * management and API access authentication.
   *
   * Security considerations forbid broad public access to this endpoint. Access
   * tokens are sensitive and must be handled with strict authorization
   * controls. Typically, only the owner user or system administrators should
   * have permission to call this endpoint.
   *
   * This GET endpoint has no request body as it simply retrieves existing token
   * data. The response includes the full representation of the token as defined
   * in the database schema, facilitating auditing and session verification.
   *
   * Related operations include token creation and validation endpoints, which
   * manage the lifecycle of access tokens in the authentication subsystem.
   *
   * @param connection
   * @param accessTokenId Unique identifier of the target access token
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":accessTokenId")
  public async at(
    @TypedParam("accessTokenId")
    accessTokenId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppAccessToken> {
    try {
      return await getTodoAppAccessTokensAccessTokenId({
        accessTokenId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new access token in the todoApp system.
   *
   * This operation allows clients to obtain a new access token by providing
   * valid credentials or refresh token details as defined in the
   * `todo_app_access_tokens` database schema. The access token issued grants
   * the holder authentication rights to access protected user data and perform
   * user-specific operations within the todoApp environment.
   *
   * Security considerations include validation of input credentials and refresh
   * tokens, preventing unauthorized token issuance. The operation does not
   * require prior authentication, allowing users to authenticate and receive
   * tokens.
   *
   * This endpoint is foundational for user session management, supporting
   * stateless authentication practices. Related operations may include token
   * refresh and token revocation endpoints.
   *
   * @param connection
   * @param body Request body for creating a new access token
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: ITodoAppAccessToken.ICreate,
  ): Promise<ITodoAppAccessToken> {
    try {
      return await postTodoAppAccessTokens({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
