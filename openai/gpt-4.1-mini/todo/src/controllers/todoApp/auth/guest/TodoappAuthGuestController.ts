import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postTodoAppAuthGuestJoin } from "../../../../providers/postTodoAppAuthGuestJoin";
import { postTodoAppAuthGuestRefresh } from "../../../../providers/postTodoAppAuthGuestRefresh";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";

import { ITodoAppGuest } from "../../../../api/structures/ITodoAppGuest";

@Controller("/todoApp/auth/guest")
export class TodoappAuthGuestController {
  /**
   * This API operation allows temporary guests to register by creating a new
   * guest account in the system. The operation is public and does not require
   * prior authentication. It creates a new record in the 'todo_app_guests'
   * table, initializing fields to represent a guest user with a limited
   * lifetime. It issues an initial JWT access token and refresh token for
   * session management.
   *
   * Security considerations include ensuring that this is a minimal access
   * account and that tokens are generated according to system security
   * policies. This operation is the entry point for unauthenticated users who
   * want to interact with the system as guests.
   *
   * The creation process involves persisting guest user data with appropriate
   * default and timestamp fields as defined in the database schema.
   *
   * Implementers should ensure adherence to token expiration and renewal
   * policies consistent with guest sessions.
   *
   * This API works in conjunction with the refresh token operation to maintain
   * guest session continuity.
   *
   * @param connection
   * @param body Guest join request payload
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppGuest.IJoin,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API operation refreshes JWT tokens for an existing guest user session.
   * It requires a valid refresh token to be presented and validates the token
   * against stored values in the 'todo_app_guests' table or associated token
   * management tables.
   *
   * The operation issues new access and refresh tokens if the presented refresh
   * token is valid and not expired. This enables seamless session continuation
   * for guest users without requiring re-registration.
   *
   * Security considerations include validating token integrity and revocation
   * status. The operation contributes to robust guest session management while
   * maintaining minimal access privileges.
   *
   * Implementers must ensure that refresh tokens have limited lifetimes and are
   * rotated accordingly.
   *
   * This refresh operation complements the initial join operation and together
   * they provide a complete guest authentication lifecycle.
   *
   * @param connection
   * @param body Guest token refresh request payload
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: ITodoAppGuest.IRefresh,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestRefresh({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
