import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postTodoAppAuthUserJoin } from "../../../../providers/postTodoAppAuthUserJoin";
import { postTodoAppAuthUserLogin } from "../../../../providers/postTodoAppAuthUserLogin";
import { postTodoAppAuthUserRefresh } from "../../../../providers/postTodoAppAuthUserRefresh";

import { ITodoAppUser } from "../../../../api/structures/ITodoAppUser";

@Controller("/todoApp/auth/user")
export class TodoappAuthUserController {
  /**
   * This operation enables new users to register an account with the todoApp
   * system. It accepts necessary user details and securely stores user
   * credentials including password hash in the todo_app_users table. Upon
   * successful registration, the system issues initial JWT access and refresh
   * tokens encapsulated in the IAuthorized interface for user actor.
   *
   * The registration workflow validates uniqueness constraints on username or
   * email fields. It integrates with related secure token mechanisms to ensure
   * account security and readiness for subsequent login operations.
   *
   * User actor access is public and does not require authentication. This is
   * the entry point for new user onboarding.
   *
   * Security considerations include input validation, secure password storage,
   * and protection against registration abuse.
   *
   * This operation complements login and refresh token management endpoints,
   * providing the essential registration function required for member users.
   *
   * @param connection
   * @param body User registration request payload.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.IJoin,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postTodoAppAuthUserJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * The login operation authenticates a registered user by validating provided
   * credentials against stored hashed password in the todo_app_users table.
   * Successful authentication returns JWT access and refresh tokens within the
   * ITodoAppUser.IAuthorized response structure.
   *
   * This operation requires public access as it is the gateway to authenticated
   * sessions for user actor.
   *
   * It verifies credential correctness securely and supports scenarios such as
   * locked or disabled accounts through appropriate error responses.
   *
   * Integration with token refresh and password reset workflows ensure cohesive
   * authentication lifecycle management.
   *
   * Security controls include rate limiting, secure password comparison, and
   * protection against brute force attacks, ensuring safe authentication
   * access.
   *
   * @param connection
   * @param body User login request payload.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.ILogin,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postTodoAppAuthUserLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation allows authenticated users to renew their JWT access tokens
   * using a valid refresh token associated with their session, tracked in the
   * todo_app_refresh_tokens table.
   *
   * It ensures continuous secure access without requiring users to repeatedly
   * log in. Refresh tokens are validated for expiration and integrity before
   * issuing new access tokens.
   *
   * This endpoint requires a valid refresh token to be submitted securely and
   * is accessible to authenticated user actor sessions.
   *
   * Security measures include refresh token revocation upon logout or
   * suspicious activity.
   *
   * This operation integrates with login and join endpoints to maintain
   * seamless token lifecycle management for user authentication.
   *
   * @param connection
   * @param body Token refresh request payload.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppUser.IRefresh,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postTodoAppAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
