import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppGuestsGuestIdSessions } from "../../../../providers/postTodoAppGuestsGuestIdSessions";
import { deleteTodoAppGuestsGuestIdSessionsSessionId } from "../../../../providers/deleteTodoAppGuestsGuestIdSessionsSessionId";

import { ITodoAppGuestSession } from "../../../../api/structures/ITodoAppGuestSession";

@Controller("/todoApp/guests/:guestId/sessions")
export class TodoappGuestsSessionsController {
  /**
   * Create a new session for a guest user identified by the guestId path
   * parameter. This operation manages session lifecycle for unauthenticated
   * guest users in the TodoApp system. It stores session tokens and related
   * metadata in the todo_app_guest_sessions database table.
   *
   * This API allows guests to initiate sessions enabling temporary access to
   * application features without full user registration. Sessions are tied
   * explicitly to guest identifiers ensuring isolation and privacy.
   *
   * The operation accepts a request body of type ITodoAppGuestSession.ICreate
   * reflecting the necessary data to establish a session such as token strings,
   * expiration timestamps, and client metadata.
   *
   * Upon successful creation, the operation returns the full
   * ITodoAppGuestSession entity representing the new session record, including
   * its unique identifier and timestamps.
   *
   * Being a guest-level operation, this endpoint requires no authentication and
   * is accessible publicly.
   *
   * This operation conforms to RESTful creation semantics using HTTP POST
   * method at the resource path '/guests/{guestId}/sessions'.
   *
   * It integrates tightly with the todo_app_guest_sessions database table as
   * defined in the schema.
   *
   * @param connection
   * @param guestId Unique identifier of the guest user
   * @param body Data required to create a new guest session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppGuestSession.ICreate,
  ): Promise<ITodoAppGuestSession> {
    try {
      return await postTodoAppGuestsGuestIdSessions({
        guestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation deletes a specific authentication session belonging to a
   * guest user in the todoApp system.
   *
   * The endpoint identifies the session to delete by the guest's unique ID
   * (guestId) and the session's unique ID (sessionId). These IDs correspond to
   * the primary keys defined in the todo_app_guest_sessions database table.
   *
   * Deleting a guest session effectively logs out the guest by invalidating the
   * associated session token, preventing any further actions authenticated by
   * that session.
   *
   * This is a security-sensitive operation that ensures session lifecycle
   * management for unauthenticated guest users, helping maintain overall system
   * security and resource management.
   *
   * No request body is required for this operation. The response is empty,
   * indicating successful deletion without additional return data.
   *
   * Related operations might include creating guest sessions or managing
   * registered user sessions.
   *
   * @param connection
   * @param guestId Unique identifier of the target guest user session's guest.
   * @param sessionId Unique identifier of the target guest user session.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppGuestsGuestIdSessionsSessionId({
        guestId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
