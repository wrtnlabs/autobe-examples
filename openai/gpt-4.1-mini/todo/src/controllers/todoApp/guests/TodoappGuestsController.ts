import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppGuests } from "../../../providers/patchTodoAppGuests";
import { deleteTodoAppGuestsGuestId } from "../../../providers/deleteTodoAppGuestsGuestId";

import { IPageITodoAppGuest } from "../../../api/structures/IPageITodoAppGuest";
import { ITodoAppGuest } from "../../../api/structures/ITodoAppGuest";

@Controller("/todoApp/guests")
export class TodoappGuestsController {
  /**
   * Retrieve a filtered and paginated list of guest users from the system. This
   * operation queries the todo_app_guests entity as defined in the database
   * schema and supports comprehensive filtering, sorting, and pagination
   * capabilities through request parameters.
   *
   * This endpoint provides clients with flexible search options to efficiently
   * locate guests based on multiple criteria such as creation date, status, or
   * other guest-specific attributes. The response returns a paginated summary
   * list to optimize data transfer and display performance.
   *
   * This operation is publicly accessible as it pertains to guest data, which
   * by definition does not require user authentication. Security considerations
   * include rate limiting and input validation to prevent abuse.
   *
   * Related API operations might include GET /guests/{guestId} for retrieving
   * individual guest details.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering guests
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: ITodoAppGuest.IRequest,
  ): Promise<IPageITodoAppGuest.ISummary> {
    try {
      return await patchTodoAppGuests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a guest user account from the TodoApp system identified by the
   * guestId parameter.
   *
   * This operation removes the guest record permanently from the database's
   * `todo_app_guests` table.
   *
   * The operation enforces proper authorization to prevent unauthorized guest
   * deletions and preserves data integrity. The guestId must be a valid UUID
   * corresponding to an existing guest record.
   *
   * There is no request body payload as the resource identity is fully
   * specified by the URL path parameter. The response body is empty to reflect
   * successful deletion without returning content.
   *
   * This endpoint follows RESTful API design principles and is intended for
   * internal or admin use cases managing guest users.
   *
   * Related operations include listing guests and registering new guest
   * accounts.
   *
   * @param connection
   * @param guestId Unique identifier of the guest user to be deleted, as a UUID
   *   string.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":guestId")
  public async erase(
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppGuestsGuestId({
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
