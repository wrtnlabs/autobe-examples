import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoAppGuestGuestsGuestId } from "../../../../providers/getTodoAppGuestGuestsGuestId";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { putTodoAppGuestGuestsGuestId } from "../../../../providers/putTodoAppGuestGuestsGuestId";

import { ITodoAppGuest } from "../../../../api/structures/ITodoAppGuest";

@Controller("/todoApp/guest/guests/:guestId")
export class TodoappGuestGuestsController {
  /**
   * Retrieve detailed information for a guest user identified by their unique
   * guest ID in the TodoApp system.
   *
   * This operation accesses the todo_app_guests database table, which stores
   * guest user details such as unique identifiers and metadata relevant to
   * unauthenticated sessions.
   *
   * The guestId path parameter is required and must be a valid UUID that
   * correspondingly identifies a single guest user record. This endpoint
   * enables clients or systems to retrieve guest user context securely,
   * supporting session and access management for guest users.
   *
   * Security considerations include limiting access exclusively to the guest
   * user actor class. The operation does not allow modification; it is a
   * read-only retrieval endpoint.
   *
   * This API is crucial for scenarios where guest user context is needed
   * without requiring full user registration, supporting flexible user flows
   * and temporary interactions.
   *
   * @param connection
   * @param guestId Unique identifier UUID of the guest user to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppGuest> {
    try {
      return await getTodoAppGuestGuestsGuestId({
        guest,
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing guest user in the TodoApp system.
   *
   * This operation allows authenticated guest users to update their own
   * information stored in the todo_app_guests table of the database. Guests can
   * modify their personal details as permitted by the system.
   *
   * The guestId path parameter uniquely identifies the guest user record to
   * update. The request body must include the updatable guest fields using the
   * ITodoAppGuest.IUpdate type.
   *
   * Security checks ensure that only the authenticated guest user can update
   * their own information, enforcing proper authorization.
   *
   * This operation returns the full updated guest user entity after successful
   * update.
   *
   * Related operations: GET /guests/{guestId} to retrieve guest details, POST
   * /guests to create a new guest user.
   *
   * @param connection
   * @param guestId Unique identifier of the guest user
   * @param body Updatable guest user information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppGuest.IUpdate,
  ): Promise<ITodoAppGuest> {
    try {
      return await putTodoAppGuestGuestsGuestId({
        guest,
        guestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
