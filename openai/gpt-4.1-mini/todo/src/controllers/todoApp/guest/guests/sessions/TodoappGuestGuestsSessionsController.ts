import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppGuestGuestsGuestIdSessions } from "../../../../../providers/patchTodoAppGuestGuestsGuestIdSessions";
import { GuestAuth } from "../../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../../decorators/payload/GuestPayload";
import { getTodoAppGuestGuestsGuestIdSessionsSessionId } from "../../../../../providers/getTodoAppGuestGuestsGuestIdSessionsSessionId";
import { putTodoAppGuestGuestsGuestIdSessionsSessionId } from "../../../../../providers/putTodoAppGuestGuestsGuestIdSessionsSessionId";

import { IPageITodoAppGuestSession } from "../../../../../api/structures/IPageITodoAppGuestSession";
import { ITodoAppGuestSession } from "../../../../../api/structures/ITodoAppGuestSession";

@Controller("/todoApp/guest/guests/:guestId/sessions")
export class TodoappGuestGuestsSessionsController {
  /**
   * Retrieve a filtered and paginated list of sessions for a specific guest
   * user identified by the guestId UUID. This operation targets the
   * todo_app_guest_sessions table, which tracks authentication sessions created
   * for guest users in the todoApp system.
   *
   * The path parameter guestId uniquely identifies the guest user whose
   * sessions are being queried. The request body supports advanced filtering
   * options such as date ranges, session status, and related metadata, enabling
   * clients to perform customized searches and generate paginated results.
   *
   * Security considerations restrict this operation's access exclusively to
   * authenticated guests, preventing unauthorized users from viewing sensitive
   * session information. The response provides summarized session details
   * optimized for list display, including session identifiers, creation
   * timestamps, and expiration data.
   *
   * This operation facilitates monitoring and management of guest
   * authentication sessions, supporting security auditing and user experience
   * enhancements within the todoApp environment.
   *
   * @param connection
   * @param guestId Unique identifier of the guest user (UUID)
   * @param body Search criteria and pagination parameters for guest session
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppGuestSession.IRequest,
  ): Promise<IPageITodoAppGuestSession.ISummary> {
    try {
      return await patchTodoAppGuestGuestsGuestIdSessions({
        guest,
        guestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific guest session for the todoApp
   * system.
   *
   * This operation fetches the session record identified by the sessionId
   * parameter for the guest identified by guestId. It corresponds to the
   * todo_app_guest_sessions table in the database schema, which stores session
   * details such as creation time, last activity, expiration, and other
   * metadata related to guest authentication sessions.
   *
   * Security considerations restrict access to the owning guest user, ensuring
   * session details are private to each guest. Proper validation of the UUID
   * parameters is performed to match valid sessions only.
   *
   * This endpoint is frequently used for session management features, auditing
   * guest activity, or assisting in troubleshooting authentication issues
   * involving guest users.
   *
   * Related operations include endpoints for listing all sessions of a guest,
   * creating new sessions during guest login, or deleting sessions upon logout
   * or expiration.
   *
   * @param connection
   * @param guestId Unique identifier of the target guest user
   * @param sessionId Unique identifier of the specific guest session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppGuestSession> {
    try {
      return await getTodoAppGuestGuestsGuestIdSessionsSessionId({
        guest,
        guestId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing guest session in the todoApp system.
   *
   * This operation allows a guest user to update their session details
   * identified by the guestId and sessionId path parameters. The guest session
   * entity stores authentication and lifecycle information related to guest
   * usage of the todoApp platform.
   *
   * Security considerations ensure that only the guest associated with the
   * session can perform updates. Validation rules apply to the session
   * attributes to maintain data consistency and integrity.
   *
   * This operation maps directly to the todo_app_guest_sessions table in the
   * database schema, interacting with all fields defined there for update. The
   * response returns the updated guest session object for confirmation and
   * further client-side processing.
   *
   * @param connection
   * @param guestId Unique identifier of the guest user
   * @param sessionId Unique identifier of the guest session
   * @param body Guest session update payload
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sessionId")
  public async update(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppGuestSession.IUpdate,
  ): Promise<ITodoAppGuestSession> {
    try {
      return await putTodoAppGuestGuestsGuestIdSessionsSessionId({
        guest,
        guestId,
        sessionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
