import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoAppUserPasswordResetsUserPasswordResetId } from "../../../providers/getTodoAppUserPasswordResetsUserPasswordResetId";
import { postTodoAppUserPasswordResets } from "../../../providers/postTodoAppUserPasswordResets";

import { ITodoAppUserPasswordReset } from "../../../api/structures/ITodoAppUserPasswordReset";

@Controller("/todoApp/user-password-resets")
export class TodoappUser_password_resetsController {
  /**
   * Retrieve a specific user password reset record by its unique identifier.
   *
   * This operation fetches the detailed information of the password reset token
   * issued for a user. It includes token value, expiration time, and related
   * metadata stored in the todo_app_user_password_resets table.
   *
   * This endpoint supports verification flows where password reset tokens need
   * to be validated or reviewed.
   *
   * Security considerations: Access to this endpoint should be controlled to
   * prevent token leakage. Actual authentication and authorization policies are
   * enforced outside of this API contract.
   *
   * No request body is needed as the single identifier in the path fully
   * specifies the target record.
   *
   * @param connection
   * @param userPasswordResetId Unique identifier of the target user password
   *   reset record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userPasswordResetId")
  public async at(
    @TypedParam("userPasswordResetId")
    userPasswordResetId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUserPasswordReset> {
    try {
      return await getTodoAppUserPasswordResetsUserPasswordResetId({
        userPasswordResetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Initiate a password reset request for a user in the todoApp system.
   *
   * This operation allows any user, including unauthenticated guests, to create
   * a password reset request by submitting the necessary information (such as
   * their registered email). The backend generates a reset token and
   * expiration, storing this in the todo_app_user_password_resets table. This
   * supports the overall user authentication and account recovery workflow.
   *
   * Security: Publicly accessible endpoint designed with appropriate validation
   * and anti-abuse mechanisms to prevent spamming or enumeration attacks. No
   * authentication is required to access this resource.
   *
   * Data Model: Operates directly on the todo_app_user_password_resets database
   * table, inserting a new record representing the reset request. Fields
   * include reset token, expiration, and user linkage.
   *
   * Related Operations: User authentication and password change endpoints
   * handle subsequent steps after this request is created.
   *
   * This endpoint returns the full details of the created password reset
   * request, enabling clients to confirm successful initiation.
   *
   * @param connection
   * @param body Payload containing information required to create a password
   *   reset request.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: ITodoAppUserPasswordReset.ICreate,
  ): Promise<ITodoAppUserPasswordReset> {
    try {
      return await postTodoAppUserPasswordResets({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
