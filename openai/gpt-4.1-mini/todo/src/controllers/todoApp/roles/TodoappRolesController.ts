import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteTodoAppRolesRoleCode } from "../../../providers/deleteTodoAppRolesRoleCode";

@Controller("/todoApp/roles/:roleCode")
export class TodoappRolesController {
  /**
   * Permanently removes a role identified by its unique roleCode from the
   * todo_app_roles table.
   *
   * This operation is crucial for role management within the todoApp platform,
   * allowing for deletion of roles that are no longer needed or valid. It
   * operates on a globally unique roleCode which serves as the identifier in
   * the API path parameter.
   *
   * Since the 'admin' actor is not defined in the system actors list, this
   * operation is exposed without specific user-level authorization constraints.
   * In a production environment, careful access control is recommended.
   *
   * No request body is necessary for this operation. Successful execution
   * results in the permanent deletion of the role record with no response body
   * content.
   *
   * Related operations include role creation and listing.
   *
   * @param connection
   * @param roleCode Unique business identifier code of the target role (global
   *   scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @TypedParam("roleCode")
    roleCode: number & tags.MultipleOf<0.01>,
  ): Promise<void> {
    try {
      return await deleteTodoAppRolesRoleCode({
        roleCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
