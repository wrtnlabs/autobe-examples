/**
 * This API operation represents a generic authorization activity for the member
 * actor that does not involve authentication-related actions. It serves as a
 * placeholder for other authorization functionalities the member may require.
 *
 * This operation requires the caller to be authenticated as a member user.
 *
 * Use this endpoint as a template for non-authentication authorization tasks.
 *
 * It complements the join, login, and refresh endpoints to provide a full
 * authorization scope.
 *
 * Security controls are enforced by verifying the member's authenticated
 * status.
 *
 * @param props.connection
 * @path /auth/user/authorization-activity
 * @accessor api.functional.auth.user.authorization_activity.authorizationActivity
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function authorizationActivity(
  connection: IConnection,
): Promise<void> {
  return true === connection.simulate
    ? authorizationActivity.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...authorizationActivity.METADATA,
          path: authorizationActivity.path(),
          status: null,
        },
      );
}
export namespace authorizationActivity {
  export const METADATA = {
    method: "GET",
    path: "/auth/user/authorization-activity",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/authorization-activity";
  export const random = (): void => typia.random<void>();
  export const simulate = (_connection: IConnection): void => {
    return random();
  };
}
