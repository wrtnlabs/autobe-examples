/**
 * Retrieve a specific user password reset record by its unique identifier.
 *
 * This operation fetches the detailed information of the password reset token
 * issued for a user. It includes token value, expiration time, and related
 * metadata stored in the todo_app_user_password_resets table.
 *
 * This endpoint supports verification flows where password reset tokens need to
 * be validated or reviewed.
 *
 * Security considerations: Access to this endpoint should be controlled to
 * prevent token leakage. Actual authentication and authorization policies are
 * enforced outside of this API contract.
 *
 * No request body is needed as the single identifier in the path fully
 * specifies the target record.
 *
 * @param props.connection
 * @param props.userPasswordResetId Unique identifier of the target user
 *   password reset record
 * @path /todoApp/user-password-resets/:userPasswordResetId
 * @accessor api.functional.todoApp.user_password_resets.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target user password reset record */
    userPasswordResetId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppUserPasswordReset;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/user-password-resets/:userPasswordResetId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/user-password-resets/${encodeURIComponent(props.userPasswordResetId ?? "null")}`;
  export const random = (): ITodoAppUserPasswordReset =>
    typia.random<ITodoAppUserPasswordReset>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userPasswordResetId")(() =>
        typia.assert(props.userPasswordResetId),
      );
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

