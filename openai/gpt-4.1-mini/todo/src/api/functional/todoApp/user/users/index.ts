/**
 * Update an existing user's information in the todoApp system.
 *
 * This operation targets the `todo_app_users` database entity to modify user
 * details securely. Only authorized actors should perform this operation.
 *
 * The path parameter `userId` accepts a UUID identifying the user. The request
 * body must conform to `ITodoAppUser.IUpdate` type, containing the fields to
 * update. The system performs necessary validation and updates the user record
 * accordingly.
 *
 * Upon successful update, the full updated user entity is returned in the
 * response with all currently stored details.
 *
 * Users may update personal data such as name, email, password, and other
 * profile information according to system policies and validation rules.
 *
 * Related operations include GET /users/{userId} for retrieval and PATCH /users
 * for listing and searching users.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the target user
 * @param props.body Request body containing user update information
 * @path /todoApp/user/users/:userId
 * @accessor api.functional.todoApp.user.users.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /** Unique identifier of the target user */
    userId: string & tags.Format<"uuid">;

    /** Request body containing user update information */
    body: ITodoAppUser.IUpdate;
  };
  export type Body = ITodoAppUser.IUpdate;
  export type Response = ITodoAppUser;

  export const METADATA = {
    method: "PUT",
    path: "/todoApp/user/users/:userId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todoApp/user/users/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): ITodoAppUser => typia.random<ITodoAppUser>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

