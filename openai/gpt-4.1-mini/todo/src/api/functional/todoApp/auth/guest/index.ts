/**
 * This API operation allows temporary guests to register by creating a new
 * guest account in the system. The operation is public and does not require
 * prior authentication. It creates a new record in the 'todo_app_guests' table,
 * initializing fields to represent a guest user with a limited lifetime. It
 * issues an initial JWT access token and refresh token for session management.
 *
 * Security considerations include ensuring that this is a minimal access
 * account and that tokens are generated according to system security policies.
 * This operation is the entry point for unauthenticated users who want to
 * interact with the system as guests.
 *
 * The creation process involves persisting guest user data with appropriate
 * default and timestamp fields as defined in the database schema.
 *
 * Implementers should ensure adherence to token expiration and renewal policies
 * consistent with guest sessions.
 *
 * This API works in conjunction with the refresh token operation to maintain
 * guest session continuity.
 *
 * @param props.connection
 * @param props.body Guest join request payload
 * @setHeader token.access Authorization
 *
 * @path /todoApp/auth/guest/join
 * @accessor api.functional.todoApp.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
