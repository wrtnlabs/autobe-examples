import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppUser } from "../../../../structures/ITodoAppUser";

/**
 * This operation enables new users to register an account with the todoApp
 * system. It accepts necessary user details and securely stores user
 * credentials including password hash in the todo_app_users table. Upon
 * successful registration, the system issues initial JWT access and refresh
 * tokens encapsulated in the IAuthorized interface for user actor.
 *
 * The registration workflow validates uniqueness constraints on username or
 * email fields. It integrates with related secure token mechanisms to ensure
 * account security and readiness for subsequent login operations.
 *
 * User actor access is public and does not require authentication. This is the
 * entry point for new user onboarding.
 *
 * Security considerations include input validation, secure password storage,
 * and protection against registration abuse.
 *
 * This operation complements login and refresh token management endpoints,
 * providing the essential registration function required for member users.
 *
 * @param props.connection
 * @param props.body User registration request payload.
 * @setHeader token.access Authorization
 *
 * @path /todoApp/auth/user/join
 * @accessor api.functional.todoApp.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /** User registration request payload. */
    body: ITodoAppUser.IJoin;
  };
  export type Body = ITodoAppUser.IJoin;
  export type Response = ITodoAppUser.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/auth/user/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/auth/user/join";
  export const random = (): ITodoAppUser.IAuthorized =>
    typia.random<ITodoAppUser.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

