import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppAccessToken } from "../../../structures/ITodoAppAccessToken";

/**
 * Retrieve detailed information about a specific access token from the
 * todo_app_access_tokens table in the todoApp system.
 *
 * This operation allows clients to fetch and display comprehensive information
 * about the access token identified by the accessTokenId path parameter. Access
 * tokens are critical security credentials used for session management and API
 * access authentication.
 *
 * Security considerations forbid broad public access to this endpoint. Access
 * tokens are sensitive and must be handled with strict authorization controls.
 * Typically, only the owner user or system administrators should have
 * permission to call this endpoint.
 *
 * This GET endpoint has no request body as it simply retrieves existing token
 * data. The response includes the full representation of the token as defined
 * in the database schema, facilitating auditing and session verification.
 *
 * Related operations include token creation and validation endpoints, which
 * manage the lifecycle of access tokens in the authentication subsystem.
 *
 * @param props.connection
 * @param props.accessTokenId Unique identifier of the target access token
 * @path /todoApp/access-tokens/:accessTokenId
 * @accessor api.functional.todoApp.access_tokens.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target access token */
    accessTokenId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppAccessToken;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/access-tokens/:accessTokenId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/access-tokens/${encodeURIComponent(props.accessTokenId ?? "null")}`;
  export const random = (): ITodoAppAccessToken =>
    typia.random<ITodoAppAccessToken>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("accessTokenId")(() => typia.assert(props.accessTokenId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

