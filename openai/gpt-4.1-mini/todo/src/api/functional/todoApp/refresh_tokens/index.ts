import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppRefreshToken } from "../../../structures/ITodoAppRefreshToken";

/**
 * Retrieve detailed information about a specific refresh token identified by
 * its UUID in the todo_app_refresh_tokens table.
 *
 * This operation allows clients or internal services to inspect the metadata,
 * expiration, and associations of the refresh token. This facilitates robust
 * session management, token validation, and revocation processes.
 *
 * The refresh token entity includes the unique token string, related user or
 * guest references, timestamps for issuance and expiry, and any related
 * metadata stored in JSON format. The data helps maintain security by enabling
 * checks on token usage and lifecycle.
 *
 * This endpoint is public and does not require authenticated user access,
 * making it suitable for system-level introspection or external verification
 * workflows.
 *
 * It follows REST conventions for single resource retrieval by UUID.
 *
 * Related operations may include token creation and revocation endpoints that
 * modify the refresh token store.
 *
 * @param props.connection
 * @param props.refreshTokenId Unique identifier of the target refresh token,
 *   represented as a UUID.
 * @path /todoApp/refresh-tokens/:refreshTokenId
 * @accessor api.functional.todoApp.refresh_tokens.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target refresh token, represented as a UUID. */
    refreshTokenId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppRefreshToken;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/refresh-tokens/:refreshTokenId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/refresh-tokens/${encodeURIComponent(props.refreshTokenId ?? "null")}`;
  export const random = (): ITodoAppRefreshToken =>
    typia.random<ITodoAppRefreshToken>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("refreshTokenId")(() => typia.assert(props.refreshTokenId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
