import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Permanently removes a role identified by its unique roleCode from the
 * todo_app_roles table.
 *
 * This operation is crucial for role management within the todoApp platform,
 * allowing for deletion of roles that are no longer needed or valid. It
 * operates on a globally unique roleCode which serves as the identifier in the
 * API path parameter.
 *
 * Since the 'admin' actor is not defined in the system actors list, this
 * operation is exposed without specific user-level authorization constraints.
 * In a production environment, careful access control is recommended.
 *
 * No request body is necessary for this operation. Successful execution results
 * in the permanent deletion of the role record with no response body content.
 *
 * Related operations include role creation and listing.
 *
 * @param props.connection
 * @param props.roleCode Unique business identifier code of the target role
 *   (global scope)
 * @path /todoApp/roles/:roleCode
 * @accessor api.functional.todoApp.roles.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique business identifier code of the target role (global scope) */
    roleCode: number & tags.MultipleOf<0.01>;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/todoApp/roles/:roleCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/roles/${encodeURIComponent(props.roleCode ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("roleCode")(() => typia.assert(props.roleCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
