import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppConfiguration } from "../../../structures/ITodoAppConfiguration";

/**
 * Retrieve a specific configuration record from the todo_app_configurations
 * table by its unique identifier.
 *
 * This operation allows clients to fetch detailed configuration settings that
 * control various aspects of the todoApp system. The configurationId path
 * parameter uniquely identifies the target configuration.
 *
 * As this endpoint is read-only, it ensures data integrity by providing no
 * modification capabilities. This endpoint is public, requiring no
 * authentication or authorization actors.
 *
 * The response returns the full configuration entity with all associated fields
 * as defined in the database schema, enabling clients to obtain precise and
 * complete configuration information.
 *
 * @param props.connection
 * @param props.configurationId Unique identifier of the configuration record.
 * @path /todoApp/configurations/:configurationId
 * @accessor api.functional.todoApp.configurations.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the configuration record. */
    configurationId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppConfiguration;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/configurations/:configurationId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/configurations/${encodeURIComponent(props.configurationId ?? "null")}`;
  export const random = (): ITodoAppConfiguration =>
    typia.random<ITodoAppConfiguration>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("configurationId")(() =>
        typia.assert(props.configurationId),
      );
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
