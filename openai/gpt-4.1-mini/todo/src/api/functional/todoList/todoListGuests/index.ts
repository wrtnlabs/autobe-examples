import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListGuest } from "../../../structures/ITodoListGuest";

/**
 * Retrieve details of a specific Todo List guest by ID.
 *
 * Retrieve detailed information of a registered guest identified by their
 * unique ID within the Todo List system.
 *
 * This operation allows any requester to obtain information about a guest user
 * using their unique UUID. The guest data includes all personal and
 * session-related details stored, enabling viewing the guest's profile.
 *
 * Security considerations include public accessibility as guests are
 * non-authenticated users. The endpoint requires precise identification of the
 * guest via the path parameter.
 *
 * This operation maps directly to the TodoListGuests Prisma table, reflecting
 * the structure and contents of guest records in the database.
 *
 * @param props.connection
 * @param props.id Unique identifier of the Todo List guest
 * @path /todoList/todoListGuests/:id
 * @accessor api.functional.todoList.todoListGuests.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the Todo List guest */
    id: string & tags.Format<"uuid">;
  };
  export type Response = ITodoListGuest;

  export const METADATA = {
    method: "GET",
    path: "/todoList/todoListGuests/:id",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoList/todoListGuests/${encodeURIComponent(props.id ?? "null")}`;
  export const random = (): ITodoListGuest => typia.random<ITodoListGuest>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("id")(() => typia.assert(props.id));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

