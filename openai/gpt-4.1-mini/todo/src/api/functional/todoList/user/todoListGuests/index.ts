/**
 * Update a specific Todo List guest by ID.
 *
 * Update a specific guest's information in the Todo List guest tracking system.
 *
 * This operation allows modifications to existing guest records identified by
 * their unique UUID. Users of this API can update details such as visitor_ip to
 * track guests accurately.
 *
 * Security considerations ensure that only authorized users can perform
 * updates. Validation ensures the guest ID exists before applying changes.
 *
 * This operation interacts with the todo_list_guests table and requires precise
 * UUID paths to avoid misidentification.
 *
 * @param props.connection
 * @param props.id Unique identifier of the target todoListGuest
 * @param props.body Updated guest information
 * @path /todoList/user/todoListGuests/:id
 * @accessor api.functional.todoList.user.todoListGuests.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /** Unique identifier of the target todoListGuest */
    id: string & tags.Format<"uuid">;

    /** Updated guest information */
    body: ITodoListGuest.IUpdate;
  };
  export type Body = ITodoListGuest.IUpdate;
  export type Response = ITodoListGuest;

  export const METADATA = {
    method: "PUT",
    path: "/todoList/user/todoListGuests/:id",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todoList/user/todoListGuests/${encodeURIComponent(props.id ?? "null")}`;
  export const random = (): ITodoListGuest => typia.random<ITodoListGuest>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("id")(() => typia.assert(props.id));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

