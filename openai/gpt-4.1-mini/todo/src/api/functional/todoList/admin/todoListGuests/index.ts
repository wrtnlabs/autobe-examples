import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListGuest } from "../../../../structures/ITodoListGuest";
import { IPageITodoListGuest } from "../../../../structures/IPageITodoListGuest";

/**
 * Search and retrieve a filtered, paginated list of guest visitors.
 *
 * Retrieve a filtered and paginated list of guest visitors to the Todo List
 * application.
 *
 * This operation allows administrative users to search, filter, and sort guest
 * visitor records recorded in the 'todo_list_guests' table. Guests represent
 * anonymous users who interact with the platform without registration,
 * identified primarily via visitor IP addresses.
 *
 * The request body supports complex querying, including pagination controls,
 * sorting options, and search filters based on guest attributes and
 * timestamps.
 *
 * The response body returns paged summaries of guest data optimized for list
 * consumption. This enables administrators to monitor guest traffic patterns
 * and perform analytical operations on anonymous visitors for system insights
 * and maintenance purposes.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for guest
 *   visitors filtering
 * @path /todoList/admin/todoListGuests
 * @accessor api.functional.todoList.admin.todoListGuests.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and pagination parameters for guest visitors
     * filtering
     */
    body: ITodoListGuest.IRequest;
  };
  export type Body = ITodoListGuest.IRequest;
  export type Response = IPageITodoListGuest.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoList/admin/todoListGuests",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoList/admin/todoListGuests";
  export const random = (): IPageITodoListGuest.ISummary =>
    typia.random<IPageITodoListGuest.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
