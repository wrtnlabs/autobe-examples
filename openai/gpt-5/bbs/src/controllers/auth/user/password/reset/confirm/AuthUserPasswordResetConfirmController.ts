import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";

import { ICivicBoardPasswordResetTokenOfUser } from "../../../../../../api/structures/ICivicBoardPasswordResetTokenOfUser";

@Controller("/auth/user/password/reset/confirm")
export class AuthUserPasswordResetConfirmController {
  /**
   * Consume civic_board_password_reset_tokens to set a new
   * civic_board_users.password_hash for the associated user.
   *
   * This operation consumes a password reset token to set a new credential
   * for a member account. It reads civic_board_password_reset_tokens by
   * civic_board_password_reset_tokens.token, checking actor_type equals
   * "user", that civic_board_password_reset_tokens.expires_at is still in the
   * future, and that civic_board_password_reset_tokens.used is false. On
   * success, it resolves the target user through
   * civic_board_password_reset_token_of_users using the pair
   * civic_board_password_reset_token_of_users.civic_board_password_reset_token_id
   * and civic_board_password_reset_token_of_users.civic_board_user_id.
   *
   * The user’s credential is updated by computing a new hash and writing it
   * to civic_board_users.password_hash while updating
   * civic_board_users.updated_at. After the change, previously active
   * sessions may be ended by setting civic_board_user_sessions.expired_at for
   * that user’s other sessions as a security measure.
   *
   * The reset token is marked consumed by setting
   * civic_board_password_reset_tokens.used to true and
   * civic_board_password_reset_tokens.used_at to the current UTC time to
   * prevent reuse.
   *
   * This operation is public and does not require the member to be signed in.
   * It is intended to follow POST /auth/user/password/reset/request which
   * created the token.
   *
   * A success acknowledgement is returned. Implementations may also append an
   * audit entry into civic_board_audit_logs with an action such as
   * "auth.password_reset.confirm" and the outcome for traceability.
   *
   * @param connection
   * @param body Token and new password for password reset confirmation.
   * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
   */
  @TypedRoute.Post()
  public async confirmPasswordReset(
    @TypedBody()
    body: ICivicBoardPasswordResetTokenOfUser.IConfirm,
  ): Promise<ICivicBoardPasswordResetTokenOfUser.ISummary> {
    body;
    return typia.random<ICivicBoardPasswordResetTokenOfUser.ISummary>();
  }
}
