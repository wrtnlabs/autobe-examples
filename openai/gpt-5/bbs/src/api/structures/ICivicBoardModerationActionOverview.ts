import { IECivicBoardContentStatus } from "./IECivicBoardContentStatus";

/**
 * Consolidated moderation dashboard overview for administrators. This DTO is
 * computed by aggregating across multiple Prisma models: civic_board_reports
 * (user-submitted reports and statuses), civic_board_moderation_actions (admin
 * resolutions), civic_board_posts (status/time fields), and
 * civic_board_comments (status/time fields). No single table maps to this type;
 * it is produced by SQL aggregations and business logic at read time. Includes
 * pending counts, resolved-by-decision breakdowns, recent decision trends, and
 * visibility distributions.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ICivicBoardModerationActionOverview = {
  /**
   * Timestamp (UTC) when this overview snapshot was computed. Computed at
   * read time, not persisted. Useful alongside civic_board_audit_logs when
   * auditing dashboard accesses.
   */
  generated_at: string & tags.Format<"date-time">;

  /**
   * Aggregations derived from civic_board_reports (main report metadata) with
   * specialization integrity from civic_board_report_of_posts /
   * civic_board_report_of_comments.
   */
  reports: ICivicBoardModerationActionOverview.IReportsSnapshot;

  /**
   * Recent administrative resolution trends derived from
   * civic_board_moderation_actions, grouped into per-day buckets and decision
   * counts.
   */
  moderation_actions: ICivicBoardModerationActionOverview.IModerationActionSnapshot;

  /**
   * Distribution of content visibility for posts and comments based on
   * civic_board_posts.status and civic_board_comments.status.
   */
  content_visibility: ICivicBoardModerationActionOverview.IContentVisibilitySnapshot;
};
export namespace ICivicBoardModerationActionOverview {
  /**
   * Aggregated snapshot of the reports pipeline based on civic_board_reports
   * and civic_board_moderation_actions. Designed for admin overview cards and
   * charts.
   */
  export type IReportsSnapshot = {
    /**
     * Number of reports currently pending review (e.g.,
     * civic_board_reports.status = 'pending' per application logic).
     * Excludes soft-deleted rows (deleted_at IS NULL filter expected).
     */
    pending_count: number & tags.Type<"int32"> & tags.Minimum<0>;

    /**
     * Number of reports that have been resolved (e.g., linked
     * civic_board_moderation_actions present, or civic_board_reports.status
     * = 'resolved').
     */
    resolved_count: number & tags.Type<"int32"> & tags.Minimum<0>;

    /**
     * Total number of currently retained reports (pending + resolved) from
     * civic_board_reports where deleted_at IS NULL.
     */
    total_count: number & tags.Type<"int32"> & tags.Minimum<0>;

    /**
     * Breakdown of resolved reports by the moderation decision captured in
     * civic_board_moderation_actions.decision (e.g., 'No Action', 'Hide',
     * 'Delete').
     */
    resolved_by_decision: ICivicBoardModerationActionOverview.IDecisionCount[];
  };

  /**
   * Count of moderation actions grouped by a single decision value. The
   * decision maps directly to civic_board_moderation_actions.decision
   * (constrained by IEModerationDecision), and count is a non‑negative
   * integer representing how many actions with that decision occurred in the
   * bucket (0 permitted).
   */
  export type IDecisionCount = {
    /**
     * Resolution outcome grouped from
     * civic_board_moderation_actions.decision. Values are constrained by
     * IEModerationDecision (e.g., "No Action", "Hide", "Delete").
     */
    decision: IECivicBoardModerationActionDecision;

    /**
     * Non-negative count of moderation actions for the given decision
     * within the aggregation bucket (may be 0).
     */
    count: number & tags.Type<"int32"> & tags.Minimum<0>;
  };

  /**
   * Recent moderation activity trends grouped by calendar day and anchored to
   * the overview snapshot’s generated_at (UTC) timestamp. Each series
   * contains a fixed number of UTC calendar‑day buckets (7 and 30
   * respectively), ordered ascending by date, and MUST include zero‑activity
   * days to satisfy the fixed bucket counts. For each day’s bucket
   * (ICivicBoardModerationOverview.IDecisionTrendBucket), providers SHOULD
   * include one ICivicBoardModerationOverview.IDecisionCount per value of
   * IEModerationDecision (e.g., "No Action", "Hide", "Delete"), allowing zero
   * counts for decisions that did not occur, to promote a consistent array
   * shape across buckets.
   */
  export type IModerationActionSnapshot = {
    /**
     * Exactly 7 UTC calendar-day buckets for the last 7 days (inclusive),
     * ordered by date ascending. This series is anchored to
     * ICivicBoardModerationOverview.generated_at (UTC). Providers MUST
     * include a bucket for every day in the window, even when there were
     * zero moderation actions that day.
     */
    last_7_days: ICivicBoardModerationActionOverview.IDecisionTrendBucket[] &
      tags.MinItems<7> &
      tags.MaxItems<7>;

    /**
     * Exactly 30 UTC calendar-day buckets for the last 30 days (inclusive),
     * ordered by date ascending. This series is anchored to
     * ICivicBoardModerationOverview.generated_at (UTC). Providers MUST
     * include a bucket for every day in the window, even when there were
     * zero moderation actions that day.
     */
    last_30_days: ICivicBoardModerationActionOverview.IDecisionTrendBucket[] &
      tags.MinItems<30> &
      tags.MaxItems<30>;
  };

  /**
   * Per-day aggregation bucket of moderation actions with decision
   * breakdowns.
   */
  export type IDecisionTrendBucket = {
    /**
     * UTC calendar date for this bucket (YYYY-MM-DD) typically derived from
     * civic_board_moderation_actions.created_at.
     */
    date: string & tags.Format<"date">;

    /** Decision counts for this date. */
    decisions: ICivicBoardModerationActionOverview.IDecisionCount[];
  };

  /**
   * Visibility distribution for posts and comments based on their status
   * fields.
   */
  export type IContentVisibilitySnapshot = {
    /**
     * Counts of civic_board_posts grouped by status (Published | Hidden |
     * Deleted).
     */
    posts_by_status: ICivicBoardModerationActionOverview.IVisibilityStatusCount[];

    /**
     * Counts of civic_board_comments grouped by status (Published | Hidden
     * | Deleted).
     */
    comments_by_status: ICivicBoardModerationActionOverview.IVisibilityStatusCount[];
  };

  /** Count of records for a specific content visibility status. */
  export type IVisibilityStatusCount = {
    /**
     * Business visibility state from civic_board_posts.status or
     * civic_board_comments.status.
     */
    status: IECivicBoardContentStatus;

    /** Number of records in this status. */
    count: number & tags.Type<"int32"> & tags.Minimum<0>;
  };
}
