import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { ICivicBoardUserSession } from "../../../../../structures/ICivicBoardUserSession";

/**
 * Revoke other sessions by updating civic_board_user_sessions.expired_at for
 * all of the caller’s other sessions.
 *
 * This operation revokes all sessions belonging to the authenticated member
 * except the one used to call this endpoint. The server locates rows in
 * civic_board_user_sessions via civic_board_user_sessions.civic_board_user_id
 * and sets civic_board_user_sessions.expired_at for each session that is
 * currently active and not the present session.
 *
 * This is a security-focused operation intended to clean up stale or
 * potentially compromised sessions. It leaves the current session intact and
 * does not modify civic_board_users fields such as email, display_name, or
 * suspended. Audit logging may record the action for traceability.
 *
 * The endpoint requires an authenticated context and relies on the caller
 * identity from authorization to scope the revocation to the correct account.
 * No path parameters are necessary.
 *
 * Use this endpoint after password changes or other sensitive updates to ensure
 * that tokens derived from other sessions can no longer be used.
 *
 * A brief acknowledgement is returned indicating completion of the revocation.
 *
 * @param props.connection
 * @path /auth/user/logout/others
 * @accessor api.functional.auth.user._logout.others.logoutOthers
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logoutOthers(
  connection: IConnection,
): Promise<logoutOthers.Response> {
  return true === connection.simulate
    ? logoutOthers.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logoutOthers.METADATA,
          path: logoutOthers.path(),
          status: null,
        },
      );
}
export namespace logoutOthers {
  export type Response = ICivicBoardUserSession.ISummary;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/logout/others",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/logout/others";
  export const random = (): ICivicBoardUserSession.ISummary =>
    typia.random<ICivicBoardUserSession.ISummary>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
