import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ICivicBoardPasswordResetTokenOfUser } from "../../../../../../structures/ICivicBoardPasswordResetTokenOfUser";

/**
 * Consume civic_board_password_reset_tokens to set a new
 * civic_board_users.password_hash for the associated user.
 *
 * This operation consumes a password reset token to set a new credential for a
 * member account. It reads civic_board_password_reset_tokens by
 * civic_board_password_reset_tokens.token, checking actor_type equals "user",
 * that civic_board_password_reset_tokens.expires_at is still in the future, and
 * that civic_board_password_reset_tokens.used is false. On success, it resolves
 * the target user through civic_board_password_reset_token_of_users using the
 * pair
 * civic_board_password_reset_token_of_users.civic_board_password_reset_token_id
 * and civic_board_password_reset_token_of_users.civic_board_user_id.
 *
 * The user’s credential is updated by computing a new hash and writing it to
 * civic_board_users.password_hash while updating civic_board_users.updated_at.
 * After the change, previously active sessions may be ended by setting
 * civic_board_user_sessions.expired_at for that user’s other sessions as a
 * security measure.
 *
 * The reset token is marked consumed by setting
 * civic_board_password_reset_tokens.used to true and
 * civic_board_password_reset_tokens.used_at to the current UTC time to prevent
 * reuse.
 *
 * This operation is public and does not require the member to be signed in. It
 * is intended to follow POST /auth/user/password/reset/request which created
 * the token.
 *
 * A success acknowledgement is returned. Implementations may also append an
 * audit entry into civic_board_audit_logs with an action such as
 * "auth.password_reset.confirm" and the outcome for traceability.
 *
 * @param props.connection
 * @param props.body Token and new password for password reset confirmation.
 * @path /auth/user/password/reset/confirm
 * @accessor api.functional.auth.user.password.reset.confirm.confirmPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function confirmPasswordReset(
  connection: IConnection,
  props: confirmPasswordReset.Props,
): Promise<confirmPasswordReset.Response> {
  return true === connection.simulate
    ? confirmPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...confirmPasswordReset.METADATA,
          path: confirmPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace confirmPasswordReset {
  export type Props = {
    /** Token and new password for password reset confirmation. */
    body: ICivicBoardPasswordResetTokenOfUser.IConfirm;
  };
  export type Body = ICivicBoardPasswordResetTokenOfUser.IConfirm;
  export type Response = ICivicBoardPasswordResetTokenOfUser.ISummary;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/reset/confirm",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/reset/confirm";
  export const random = (): ICivicBoardPasswordResetTokenOfUser.ISummary =>
    typia.random<ICivicBoardPasswordResetTokenOfUser.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: confirmPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: confirmPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
