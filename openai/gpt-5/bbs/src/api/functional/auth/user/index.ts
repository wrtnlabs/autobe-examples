/**
 * Register a new member in civic_board_users and return authorized tokens.
 *
 * This operation registers a new member account by creating a record in
 * civic_board_users. It consumes the submitted email to populate
 * civic_board_users.email, stores a cryptographic password hash in
 * civic_board_users.password_hash, and saves the user-facing name in
 * civic_board_users.display_name. New accounts are created with
 * civic_board_users.email_verified set to false and civic_board_users.suspended
 * set to false. Timestamps civic_board_users.created_at and
 * civic_board_users.updated_at are set to the current UTC time.
 *
 * Upon successful creation, the system records a session entry in
 * civic_board_user_sessions tied with
 * civic_board_user_sessions.civic_board_user_id to the new user. Connection
 * context from the request is captured in civic_board_user_sessions.ip,
 * civic_board_user_sessions.href, and civic_board_user_sessions.referrer with
 * civic_board_user_sessions.created_at set to the current UTC time. The session
 * remains active until civic_board_user_sessions.expired_at is populated by a
 * later logout or session revocation.
 *
 * If email confirmation is required, an email verification token is produced by
 * inserting a row into civic_board_email_verifications with actor_type set to
 * "user", email mirrored into civic_board_email_verifications.email, a unique
 * civic_board_email_verifications.token, and
 * civic_board_email_verifications.expires_at scheduled according to policy
 * while civic_board_email_verifications.used remains false. The token is linked
 * to the user by creating a specialization row in
 * civic_board_email_verification_of_users referencing
 * civic_board_email_verification_of_users.civic_board_email_verification_id and
 * civic_board_email_verification_of_users.civic_board_user_id.
 *
 * Security logic enforces uniqueness on civic_board_users.email (per the
 * @@unique constraint) and applies initial eligibility rules using
 * civic_board_users.email_verified and civic_board_users.suspended. Passwords
 * are never persisted in plain text; only civic_board_users.password_hash is
 * stored.
 *
 * Related operations include POST /auth/user/login for subsequent
 * authentications, POST /auth/user/email/verify/request for re-sending
 * verification tokens, and POST /auth/user/email/verify/confirm for token
 * confirmation. Failures such as duplicate email or invalid input yield clear
 * validation errors while preserving safe behavior.
 *
 * On success, this endpoint issues an authorized response containing access
 * credentials appropriate for subsequent requests and may optionally record an
 * audit entry in civic_board_audit_logs using fields like actor_type, action,
 * outcome, and created_at to provide compliance visibility.
 *
 * @param props.connection
 * @param props.body Registration payload containing email, password, and
 *   display name.
 * @setHeader token.access Authorization
 *
 * @path /auth/user/join
 * @accessor api.functional.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
