/**
 * Update civic_board_users.password_hash for the current member and revoke
 * other sessions.
 *
 * This operation changes the password for the signed-in member. It first
 * validates the submitted current credential against
 * civic_board_users.password_hash. When the check succeeds and the account is
 * eligible (civic_board_users.suspended is false), it computes a new hash and
 * writes it to civic_board_users.password_hash, updating
 * civic_board_users.updated_at.
 *
 * To protect the account, the server should revoke other concurrent sessions by
 * populating civic_board_user_sessions.expired_at for all sessions linked via
 * civic_board_user_sessions.civic_board_user_id except the current session. The
 * current session remains valid so the user can continue operating after the
 * password change.
 *
 * This endpoint requires an authenticated context and uses the caller’s
 * civic_board_users.id; no explicit user identifier is passed in the path.
 * Business logic may enforce password complexity policies while ensuring the
 * database persists only the hash in civic_board_users.password_hash.
 *
 * Typical errors include incorrect current password, attempts by accounts
 * marked as suspended via civic_board_users.suspended, and constraint
 * violations in password policies. On success, the response returns a concise
 * outcome description.
 *
 * Use this endpoint in conjunction with POST /auth/user/logout/others when you
 * need to proactively terminate other sessions even without changing the
 * password.
 *
 * @param props.connection
 * @param props.body Current and new password for an in-session password change.
 * @path /auth/user/password
 * @accessor api.functional.auth.user.password.updatePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function updatePassword(
  connection: IConnection,
  props: updatePassword.Props,
): Promise<updatePassword.Response> {
  return true === connection.simulate
    ? updatePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...updatePassword.METADATA,
          path: updatePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace updatePassword {
  export type Props = {
    /** Current and new password for an in-session password change. */
    body: ICivicBoardUserPassword.IUpdate;
  };
  export type Body = ICivicBoardUserPassword.IUpdate;
  export type Response = ICivicBoardUserPassword.ISummary;

  export const METADATA = {
    method: "PUT",
    path: "/auth/user/password",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password";
  export const random = (): ICivicBoardUserPassword.ISummary =>
    typia.random<ICivicBoardUserPassword.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: updatePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: updatePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
