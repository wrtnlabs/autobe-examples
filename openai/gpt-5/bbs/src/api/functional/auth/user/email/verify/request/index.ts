/**
 * Create an email verification token in civic_board_email_verifications linked
 * to the current civic_board_users row.
 *
 * This operation helps a signed-in member obtain a fresh email verification
 * token. It creates a token in civic_board_email_verifications with actor_type
 * set to "user", copies the current account email into
 * civic_board_email_verifications.email, stores a newly generated
 * civic_board_email_verifications.token, sets
 * civic_board_email_verifications.expires_at in UTC, and leaves
 * civic_board_email_verifications.used as false with
 * civic_board_email_verifications.used_at null until confirmation.
 *
 * The token is strictly associated to the member by creating a companion row in
 * civic_board_email_verification_of_users that references
 * civic_board_email_verification_of_users.civic_board_email_verification_id and
 * civic_board_email_verification_of_users.civic_board_user_id. These links
 * ensure unambiguous ownership and later confirmation can set
 * civic_board_users.email_verified to true.
 *
 * Because this is a user-initiated action, it requires an authenticated context
 * and uses the current principal’s civic_board_users.id. No email address needs
 * to be passed if the server reads it from civic_board_users.email, but the
 * request may include optional metadata used for delivery.
 *
 * On success, the server may enqueue delivery and returns an acknowledgement
 * payload. Errors include attempting to request tokens for accounts that do not
 * exist or sending when the member is already verified according to
 * civic_board_users.email_verified.
 *
 * This endpoint is commonly used with POST /auth/user/email/verify/confirm,
 * which consumes the token and flips the civic_board_users.email_verified flag
 * upon success.
 *
 * @param props.connection
 * @param props.body Optional parameters for sending email verification (e.g.,
 *   delivery hints).
 * @path /auth/user/email/verify/request
 * @accessor api.functional.auth.user.email.verify.request.requestEmailVerification
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestEmailVerification(
  connection: IConnection,
  props: requestEmailVerification.Props,
): Promise<requestEmailVerification.Response> {
  return true === connection.simulate
    ? requestEmailVerification.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestEmailVerification.METADATA,
          path: requestEmailVerification.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestEmailVerification {
  export type Props = {
    /**
     * Optional parameters for sending email verification (e.g., delivery
     * hints).
     */
    body: ICivicBoardEmailVerificationOfUser.IRequest;
  };
  export type Body = ICivicBoardEmailVerificationOfUser.IRequest;
  export type Response = ICivicBoardEmailVerificationOfUser.ISummary;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/email/verify/request",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/email/verify/request";
  export const random = (): ICivicBoardEmailVerificationOfUser.ISummary =>
    typia.random<ICivicBoardEmailVerificationOfUser.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: requestEmailVerification.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestEmailVerification.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
