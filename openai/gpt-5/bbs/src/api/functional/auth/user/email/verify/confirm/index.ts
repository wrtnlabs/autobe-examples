import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ICivicBoardEmailVerificationOfUser } from "../../../../../../structures/ICivicBoardEmailVerificationOfUser";

/**
 * Confirm email by consuming civic_board_email_verifications and updating
 * civic_board_users.email_verified.
 *
 * This operation consumes a previously issued verification token to confirm
 * email ownership. It looks up a record in civic_board_email_verifications by
 * civic_board_email_verifications.token, ensuring actor_type equals "user",
 * civic_board_email_verifications.expires_at is in the future, and
 * civic_board_email_verifications.used is false. On success, it marks
 * civic_board_email_verifications.used as true and sets
 * civic_board_email_verifications.used_at to the current UTC time.
 *
 * To update the account, it follows the specialization link from
 * civic_board_email_verification_of_users, reading
 * civic_board_email_verification_of_users.civic_board_email_verification_id and
 * civic_board_email_verification_of_users.civic_board_user_id to identify the
 * target user row in civic_board_users and sets
 * civic_board_users.email_verified to true. The account’s
 * civic_board_users.updated_at is updated to reflect the change.
 *
 * Security considerations include preventing replay after
 * civic_board_email_verifications.used is set, validating the token lifetime
 * using civic_board_email_verifications.expires_at, and ensuring the token’s
 * actor_type matches a member account. The operation avoids exposing whether
 * specific emails exist by using generic error messages when validation fails.
 *
 * This confirmation endpoint is typically reached from an emailed link and does
 * not require an authenticated session. It aligns with the issuance endpoint
 * POST /auth/user/email/verify/request which generates the token.
 *
 * Upon success, a simple acknowledgement is returned, and the system may log an
 * event to civic_board_audit_logs for compliance visibility without coupling
 * through foreign keys.
 *
 * @param props.connection
 * @param props.body Verification token payload for email confirmation.
 * @path /auth/user/email/verify/confirm
 * @accessor api.functional.auth.user.email.verify.confirm.confirmEmailVerification
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function confirmEmailVerification(
  connection: IConnection,
  props: confirmEmailVerification.Props,
): Promise<confirmEmailVerification.Response> {
  return true === connection.simulate
    ? confirmEmailVerification.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...confirmEmailVerification.METADATA,
          path: confirmEmailVerification.path(),
          status: null,
        },
        props.body,
      );
}
export namespace confirmEmailVerification {
  export type Props = {
    /** Verification token payload for email confirmation. */
    body: ICivicBoardEmailVerificationOfUser.IConfirm;
  };
  export type Body = ICivicBoardEmailVerificationOfUser.IConfirm;
  export type Response = ICivicBoardEmailVerificationOfUser.ISummary;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/email/verify/confirm",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/email/verify/confirm";
  export const random = (): ICivicBoardEmailVerificationOfUser.ISummary =>
    typia.random<ICivicBoardEmailVerificationOfUser.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: confirmEmailVerification.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: confirmEmailVerification.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
