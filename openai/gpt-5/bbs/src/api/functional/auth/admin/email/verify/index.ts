import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ICivicBoardEmailVerificationConfirm } from "../../../../../structures/ICivicBoardEmailVerificationConfirm";
import { ICivicBoardAdmin } from "../../../../../structures/ICivicBoardAdmin";

/**
 * Verify admin email using civic_board_email_verifications and update
 * civic_board_admins.email_verified.
 *
 * This endpoint verifies the administrator’s email using the polymorphic token
 * store civic_board_email_verifications. The token row carries actor_type (here
 * "admin"), token (unique), expires_at, used, used_at, and timestamps
 * created_at/updated_at. Tokens that are expired or already used are rejected.
 *
 * The admin-specific binding is enforced by
 * civic_board_email_verification_of_admins, which references both the main
 * token and the target civic_board_admins row via civic_board_admin_id. This
 * guarantees that the verification applies to the intended account.
 *
 * Upon successful verification, the admin’s civic_board_admins record is
 * updated: email_verified is set to true. Other fields such as suspended,
 * display_name, created_at, and updated_at preserve the administrator’s state
 * and audit history; deleted_at participates only in retention workflows
 * unrelated to verification.
 *
 * Security considerations include idempotency (re-verification attempts with
 * the same token yield a consistent outcome) and rate control on invalid
 * attempts using civic_board_rate_limits. Implementations may optionally write
 * to civic_board_audit_logs with an action like
 * "admin.email_verification.verify" to support investigations.
 *
 * Related operations: /auth/admin/email/verification to request a token and
 * /auth/admin/join to create a new admin whose email_verified flag begins as
 * false until verification completes.
 *
 * @param props.connection
 * @param props.body Verification token consumption payload.
 * @path /auth/admin/email/verify
 * @accessor api.functional.auth.admin.email.verify.verifyEmail
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function verifyEmail(
  connection: IConnection,
  props: verifyEmail.Props,
): Promise<verifyEmail.Response> {
  return true === connection.simulate
    ? verifyEmail.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verifyEmail.METADATA,
          path: verifyEmail.path(),
          status: null,
        },
        props.body,
      );
}
export namespace verifyEmail {
  export type Props = {
    /** Verification token consumption payload. */
    body: ICivicBoardEmailVerificationConfirm.ICreate;
  };
  export type Body = ICivicBoardEmailVerificationConfirm.ICreate;
  export type Response = ICivicBoardAdmin.ISecurityOutcome;

  export const METADATA = {
    method: "POST",
    path: "/auth/admin/email/verify",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/admin/email/verify";
  export const random = (): ICivicBoardAdmin.ISecurityOutcome =>
    typia.random<ICivicBoardAdmin.ISecurityOutcome>();
  export const simulate = (
    connection: IConnection,
    props: verifyEmail.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: verifyEmail.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
