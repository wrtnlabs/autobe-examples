import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ICivicBoardEmailVerification } from "../../../../../structures/ICivicBoardEmailVerification";

/**
 * Create an email verification token for an admin using
 * civic_board_email_verifications and link via
 * civic_board_email_verification_of_admins.
 *
 * This operation prepares the email confirmation workflow for an administrator.
 * It inserts a token into civic_board_email_verifications using
 * actor_type="admin" and the admin’s email. The token lifecycle is described by
 * fields token, expires_at, used, used_at, and timestamps
 * created_at/updated_at. A retention-oriented deleted_at field exists for
 * policy control.
 *
 * To bind the token to the admin identity, a 1:1 specialization row is written
 * to civic_board_email_verification_of_admins with
 * civic_board_email_verification_id and civic_board_admin_id. This table
 * enforces uniqueness on the main token reference and records created_at for
 * auditability.
 *
 * The admin identity itself resides in civic_board_admins, which holds email,
 * password_hash, display_name, email_verified, and suspended, together with
 * created_at and updated_at timestamps. The request does not modify
 * civic_board_admins; email_verified remains unchanged until confirmation.
 *
 * Security considerations include limiting repeated requests using
 * civic_board_rate_limits (e.g., a scope such as "email_verification.request").
 * Additionally, audit trails may be recorded in civic_board_audit_logs with
 * action names like "admin.email_verification.request" without introducing
 * foreign keys.
 *
 * Related operation: /auth/admin/email/verify consumes the token and flips
 * email_verified to true on the admin record when valid.
 *
 * @param props.connection
 * @param props.body Request to issue an email verification token for the
 *   authenticated admin.
 * @path /auth/admin/email/verification
 * @accessor api.functional.auth.admin.email.verification.requestEmailVerification
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestEmailVerification(
  connection: IConnection,
  props: requestEmailVerification.Props,
): Promise<requestEmailVerification.Response> {
  return true === connection.simulate
    ? requestEmailVerification.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestEmailVerification.METADATA,
          path: requestEmailVerification.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestEmailVerification {
  export type Props = {
    /**
     * Request to issue an email verification token for the authenticated
     * admin.
     */
    body: ICivicBoardEmailVerification.ICreate;
  };
  export type Body = ICivicBoardEmailVerification.ICreate;
  export type Response = ICivicBoardEmailVerification.ISummary;

  export const METADATA = {
    method: "POST",
    path: "/auth/admin/email/verification",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/admin/email/verification";
  export const random = (): ICivicBoardEmailVerification.ISummary =>
    typia.random<ICivicBoardEmailVerification.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: requestEmailVerification.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestEmailVerification.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
