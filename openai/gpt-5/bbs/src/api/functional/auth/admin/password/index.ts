import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ICivicBoardAdminPassword } from "../../../../structures/ICivicBoardAdminPassword";
import { ICivicBoardAdmin } from "../../../../structures/ICivicBoardAdmin";
export * as reset from "./reset/index";

/**
 * Update civic_board_admins.password_hash for the authenticated admin and
 * expire prior sessions in civic_board_admin_sessions.
 *
 * This operation updates the administrator’s password within civic_board_admins
 * by replacing password_hash upon verifying the supplied current password. The
 * admin’s other attributes—email, display_name, email_verified, suspended—are
 * left intact; updated_at reflects the modification moment.
 *
 * To enforce security hygiene, it revokes historical sessions in
 * civic_board_admin_sessions for the same civic_board_admin_id by writing
 * expired_at. Each session stores ip, href, referrer, and created_at to support
 * investigative needs.
 *
 * This change is an authenticated action restricted to the admin actor. The
 * request is recorded in business audit trails where required using
 * civic_board_audit_logs (actor_type="admin", action like
 * "admin.password.change").
 *
 * Rate limiting can be applied with civic_board_rate_limits for scopes such as
 * "password.change" to mitigate abuse. The retention-oriented deleted_at column
 * on related tables does not participate in this flow.
 *
 * Related operations: /auth/admin/logout to end the current session immediately
 * after a rotation and /auth/admin/sessions/revoke to explicitly revoke
 * sessions beyond the automated revocation strategy.
 *
 * @param props.connection
 * @param props.body Authenticated password change payload (current and new
 *   password).
 * @path /auth/admin/password
 * @accessor api.functional.auth.admin.password.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<changePassword.Response> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /** Authenticated password change payload (current and new password). */
    body: ICivicBoardAdminPassword.IUpdate;
  };
  export type Body = ICivicBoardAdminPassword.IUpdate;
  export type Response = ICivicBoardAdmin.ISecurityOutcome;

  export const METADATA = {
    method: "PUT",
    path: "/auth/admin/password",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/admin/password";
  export const random = (): ICivicBoardAdmin.ISecurityOutcome =>
    typia.random<ICivicBoardAdmin.ISecurityOutcome>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
