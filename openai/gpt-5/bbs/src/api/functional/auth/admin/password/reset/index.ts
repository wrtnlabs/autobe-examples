import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ICivicBoardPasswordResetTokenOfAdminConfirm } from "../../../../../structures/ICivicBoardPasswordResetTokenOfAdminConfirm";
import { ICivicBoardAdmin } from "../../../../../structures/ICivicBoardAdmin";
export * as request from "./request/index";

/**
 * Reset an admin password using civic_board_password_reset_tokens and update
 * civic_board_admins.password_hash.
 *
 * This endpoint finalizes admin password recovery. It validates the provided
 * token against civic_board_password_reset_tokens (actor_type, token,
 * expires_at, used, used_at, created_at, updated_at, deleted_at). The admin
 * specialization civic_board_password_reset_token_of_admins ensures the token
 * applies to a specific civic_board_admins row.
 *
 * When validation succeeds, the admin’s password_hash is replaced in
 * civic_board_admins. Other fields—email, display_name, email_verified,
 * suspended—remain unchanged, preserving the account’s identity and status.
 * Timestamps updated_at and created_at reflect standard audit semantics.
 *
 * For session hygiene, existing administrator sessions recorded in
 * civic_board_admin_sessions (id bound by civic_board_admin_id) should be ended
 * by setting expired_at, ensuring prior tokens cannot be refreshed. The session
 * ledger also carries ip, href, referrer, and created_at for investigation
 * use.
 *
 * Security considerations include idempotent handling of reused tokens (already
 * used) and rate limiting failed attempts via civic_board_rate_limits with an
 * appropriate scope. Optionally, an audit event may be written to
 * civic_board_audit_logs noting success or failure.
 *
 * Related operations: /auth/admin/password/reset/request to issue tokens and
 * /auth/admin/login to authenticate with the new password.
 *
 * @param props.connection
 * @param props.body Password reset confirmation payload (token and new
 *   password).
 * @path /auth/admin/password/reset
 * @accessor api.functional.auth.admin.password.reset.resetPassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resetPassword(
  connection: IConnection,
  props: resetPassword.Props,
): Promise<resetPassword.Response> {
  return true === connection.simulate
    ? resetPassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resetPassword.METADATA,
          path: resetPassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resetPassword {
  export type Props = {
    /** Password reset confirmation payload (token and new password). */
    body: ICivicBoardPasswordResetTokenOfAdminConfirm.ICreate;
  };
  export type Body = ICivicBoardPasswordResetTokenOfAdminConfirm.ICreate;
  export type Response = ICivicBoardAdmin.ISecurityOutcome;

  export const METADATA = {
    method: "POST",
    path: "/auth/admin/password/reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/admin/password/reset";
  export const random = (): ICivicBoardAdmin.ISecurityOutcome =>
    typia.random<ICivicBoardAdmin.ISecurityOutcome>();
  export const simulate = (
    connection: IConnection,
    props: resetPassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resetPassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
