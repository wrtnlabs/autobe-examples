import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ICivicBoardAdminSessionsRevoke } from "../../../../../structures/ICivicBoardAdminSessionsRevoke";
import { ICivicBoardAdmin } from "../../../../../structures/ICivicBoardAdmin";

/**
 * Revoke administrator sessions by setting expired_at in
 * civic_board_admin_sessions for the authenticated admin.
 *
 * This security operation targets session hygiene by ending one or more
 * sessions recorded in civic_board_admin_sessions for the same
 * civic_board_admin_id. Each session row provides ip, href, referrer,
 * created_at, and an optional expired_at to indicate termination time.
 * Implementations may support options such as revoking all sessions or all
 * except the current session.
 *
 * The administrator record in civic_board_admins (email, password_hash,
 * display_name, email_verified, suspended) remains unchanged; only session rows
 * are updated. The operation strengthens account safety after password changes
 * or when suspicious activity is detected.
 *
 * To provide visibility, systems can add an audit entry to
 * civic_board_audit_logs with an action like "admin.sessions.revoke". Rate
 * limiting can leverage civic_board_rate_limits under a scope such as
 * "sessions.revoke" to prevent excessive churn.
 *
 * No path parameters are used; targeting is expressed in the request body. The
 * outcome is a summarized security result indicating how many sessions were
 * affected.
 *
 * Related operations: /auth/admin/password to rotate credentials and
 * /auth/admin/logout to end only the current session.
 *
 * @param props.connection
 * @param props.body Session revocation request (e.g., all or allExceptCurrent).
 * @path /auth/admin/sessions/revoke
 * @accessor api.functional.auth.admin.sessions.revoke.revokeSessions
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function revokeSessions(
  connection: IConnection,
  props: revokeSessions.Props,
): Promise<revokeSessions.Response> {
  return true === connection.simulate
    ? revokeSessions.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...revokeSessions.METADATA,
          path: revokeSessions.path(),
          status: null,
        },
        props.body,
      );
}
export namespace revokeSessions {
  export type Props = {
    /** Session revocation request (e.g., all or allExceptCurrent). */
    body: ICivicBoardAdminSessionsRevoke.ICreate;
  };
  export type Body = ICivicBoardAdminSessionsRevoke.ICreate;
  export type Response = ICivicBoardAdmin.ISecurityOutcome;

  export const METADATA = {
    method: "POST",
    path: "/auth/admin/sessions/revoke",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/admin/sessions/revoke";
  export const random = (): ICivicBoardAdmin.ISecurityOutcome =>
    typia.random<ICivicBoardAdmin.ISecurityOutcome>();
  export const simulate = (
    connection: IConnection,
    props: revokeSessions.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: revokeSessions.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
