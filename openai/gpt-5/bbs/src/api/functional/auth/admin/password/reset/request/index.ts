import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ICivicBoardPasswordResetTokenOfAdmin } from "../../../../../../structures/ICivicBoardPasswordResetTokenOfAdmin";
import { ICivicBoardPasswordResetToken } from "../../../../../../structures/ICivicBoardPasswordResetToken";

/**
 * Request an admin password reset token using civic_board_password_reset_tokens
 * and link via civic_board_password_reset_token_of_admins.
 *
 * This operation enables administrators to request a password reset by creating
 * a token in civic_board_password_reset_tokens. The token row includes
 * actor_type="admin", token (unique), expires_at, used flag, and used_at
 * timestamp to capture consumption. created_at/updated_at timestamps and a
 * retention-oriented deleted_at column support lifecycle control.
 *
 * To associate the token with a specific administrator, a 1:1 specialization is
 * created in civic_board_password_reset_token_of_admins using
 * civic_board_password_reset_token_id and civic_board_admin_id. This design
 * preserves normalization and guarantees referential integrity for recovery
 * flows.
 *
 * The admin identity table civic_board_admins (email, password_hash,
 * display_name, email_verified, suspended) is not altered by the request. The
 * request only provisions recovery credentials for a subsequent password
 * update.
 *
 * Security and abuse mitigation can leverage civic_board_rate_limits to
 * throttle requests per email or actor context. Additionally, the system may
 * record the event into civic_board_audit_logs with a clear action label such
 * as "admin.password_reset.request".
 *
 * The complementary operation /auth/admin/password/reset consumes the token to
 * set a new password and revoke existing sessions where appropriate.
 *
 * @param props.connection
 * @param props.body Admin password reset request payload (typically contains
 *   email).
 * @path /auth/admin/password/reset/request
 * @accessor api.functional.auth.admin.password.reset.request.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<requestPasswordReset.Response> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestPasswordReset {
  export type Props = {
    /** Admin password reset request payload (typically contains email). */
    body: ICivicBoardPasswordResetTokenOfAdmin.ICreate;
  };
  export type Body = ICivicBoardPasswordResetTokenOfAdmin.ICreate;
  export type Response = ICivicBoardPasswordResetToken.ISummary;

  export const METADATA = {
    method: "POST",
    path: "/auth/admin/password/reset/request",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/admin/password/reset/request";
  export const random = (): ICivicBoardPasswordResetToken.ISummary =>
    typia.random<ICivicBoardPasswordResetToken.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: requestPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
