/**
 * Register a new administrator in civic_board_admins and return admin
 * authorization.
 *
 * This endpoint registers a new administrator using the civic_board_admins
 * table. The table stores the credential hash in password_hash, the unique
 * email in email, the public-facing display_name, and two control flags
 * email_verified and suspended that govern posting/moderation eligibility.
 * Creation and update moments are tracked in created_at and updated_at, while
 * deleted_at exists for retention governance but is not used during
 * registration.
 *
 * On successful creation, an authenticated context is established by inserting
 * into civic_board_admin_sessions. This relation requires civic_board_admin_id
 * and captures ip, href, and referrer together with created_at. Session records
 * can later be marked ended via expired_at by security flows such as logout or
 * password changes.
 *
 * For verification, the system may issue a token in
 * civic_board_email_verifications with actor_type="admin", email, token,
 * expires_at, and used=false. The token is linked specifically to the new admin
 * through civic_board_email_verification_of_admins, which enforces a 1:1
 * mapping to the main token and requires civic_board_admin_id. These
 * verification structures enable later confirmation that flips email_verified
 * to true on the admin record.
 *
 * Security considerations include enforcing @@unique([email]) on
 * civic_board_admins to prevent duplicate accounts and checking the suspended
 * flag to avoid creating active sessions for prohibited identities. Audit
 * trails for the registration event can be recorded in civic_board_audit_logs
 * using actor_type and action fields without introducing FKs.
 *
 * Related operations are /auth/admin/login for credential authentication,
 * /auth/admin/email/verification to request verification tokens, and
 * /auth/admin/email/verify to consume a token. Password recovery is available
 * through /auth/admin/password/reset/request and /auth/admin/password/reset
 * using the password reset token tables designed for admin actors.
 *
 * @param props.connection
 * @param props.body Admin registration payload including email, password, and
 *   display name.
 * @setHeader token.access Authorization
 *
 * @path /auth/admin/join
 * @accessor api.functional.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
