import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ICivicBoardCommentReactionCount } from "../../../../../structures/ICivicBoardCommentReactionCount";

/**
 * Get active reaction count for a comment using civic_board_comment_reactions.
 *
 * Return the total number of active reactions for a single comment by counting
 * rows in civic_board_comment_reactions filtered by civic_board_comment_id and
 * deleted_at being NULL. Per the Prisma schema, civic_board_comment_reactions
 * includes id (UUID primary key), civic_board_user_id (reacting user),
 * civic_board_comment_id (target comment), created_at, updated_at, and a
 * deleted_at timestamp used to indicate that a prior reaction has been toggled
 * off. Only reactions with deleted_at = NULL are included in the count.
 *
 * This operation must apply visibility and moderation semantics from
 * civic_board_comments and the parent civic_board_posts record. Comments carry
 * a status field with expected values "Published", "Hidden", or "Deleted" and
 * timestamps for published_at, edited_at, created_at, updated_at, and optional
 * deleted_at. If either the comment or its parent post is not visible to the
 * requesting actor (for example, status indicates non-public visibility), the
 * provider should enforce not-available outcomes according to the project’s
 * exception handling guidance. For visible comments, the aggregation proceeds
 * normally and returns the active count.
 *
 * Feature flags and guardrails are captured in civic_board_reaction_policies.
 * When reactions are disabled globally or disallowed specifically on comments
 * (allow_on_comments = false), the count should effectively be zero while
 * returning a successful response. This endpoint is public read and does not
 * expose personal information; it only returns a computed number. Related
 * endpoints include comment detail retrieval and any reaction toggle endpoints,
 * which would influence the number of active reactions and therefore the count
 * reported here.
 *
 * Error handling follows the civicBoard exception handling rules. Invalid or
 * non-visible identifiers should result in not-available outcomes; transient
 * infrastructure failures should map to retry guidance. Any rate limiting for
 * read operations should follow minimal anti-abuse policies if enabled.
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the target comment (UUID).
 * @path /civicBoard/comments/:commentId/reactions/count
 * @accessor api.functional.civicBoard.comments.reactions.count.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target comment (UUID). */
    commentId: string & tags.Format<"uuid">;
  };
  export type Response = ICivicBoardCommentReactionCount;

  export const METADATA = {
    method: "GET",
    path: "/civicBoard/comments/:commentId/reactions/count",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/civicBoard/comments/${encodeURIComponent(props.commentId ?? "null")}/reactions/count`;
  export const random = (): ICivicBoardCommentReactionCount =>
    typia.random<ICivicBoardCommentReactionCount>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
