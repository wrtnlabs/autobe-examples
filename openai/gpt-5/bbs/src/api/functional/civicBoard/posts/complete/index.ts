import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ICivicBoardPostComplete } from "../../../../structures/ICivicBoardPostComplete";

/**
 * Get a complete composition view of one post from civic_board_posts with
 * attachments and comments.
 *
 * This endpoint returns a fully composed view for a single post stored in
 * civic_board_posts. The table defines title, body, and lifecycle status
 * ("Published", "Hidden", or "Deleted"). Publication timestamp is stored in
 * published_at with optional edited_at for within-window edits, and standard
 * auditing fields created_at/updated_at are present. The composition includes
 * the author’s display_name from civic_board_users without exposing email,
 * reflecting the schema’s privacy design where email is not intended for public
 * display.
 *
 * Attachments are drawn from civic_board_post_attachments, which records
 * immutable file metadata including uri (string URI), original_filename,
 * content_type (e.g., image/jpeg, image/png, image/gif, application/pdf),
 * byte_size, and optional image_width/image_height. Comments are aggregated
 * from civic_board_comments (body, status, published_at, optional edited_at)
 * and are typically sorted oldest-first for display as specified in business
 * requirements. For richer experiences, provider logic MAY also compute
 * reaction counts by reading civic_board_post_reactions and
 * civic_board_comment_reactions; these tables represent single-like toggles
 * using deleted_at to indicate inactive reactions.
 *
 * Security and visibility rules apply: Public readers may access posts only
 * when status is "Published". When status is "Hidden" or "Deleted", access
 * SHOULD be limited to administrators (civic_board_admins) and, where policy
 * allows, the original author (civic_board_users). Attachments inherit the
 * parent post’s visibility; hidden or deleted posts MUST prevent public access
 * to their attachments. Provider logic MUST enforce these checks before
 * returning composed data. The endpoint accepts no request body and returns a
 * single denormalized DTO ICivicBoardPostComplete capturing post core fields,
 * author display information, attachments, comments (oldest-first), and
 * optional computed aggregates.
 *
 * Related operations: For listing views and search, clients typically call
 * collection endpoints (e.g., posts index/search) and then fetch this complete
 * composition for a selected post. Administrative moderation workflows create
 * records in civic_board_moderation_actions and may change the post status;
 * clients should account for status transitions between list and detail reads.
 *
 * @param props.connection
 * @param props.postId Unique identifier (UUID) of the target post in
 *   civic_board_posts.
 * @path /civicBoard/posts/:postId/complete
 * @accessor api.functional.civicBoard.posts.complete.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier (UUID) of the target post in civic_board_posts. */
    postId: string & tags.Format<"uuid">;
  };
  export type Response = ICivicBoardPostComplete;

  export const METADATA = {
    method: "GET",
    path: "/civicBoard/posts/:postId/complete",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/civicBoard/posts/${encodeURIComponent(props.postId ?? "null")}/complete`;
  export const random = (): ICivicBoardPostComplete =>
    typia.random<ICivicBoardPostComplete>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
