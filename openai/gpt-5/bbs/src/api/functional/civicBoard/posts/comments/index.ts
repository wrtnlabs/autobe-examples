/**
 * List and search comments of a post from civic_board_comments with pagination
 * and oldest-first defaults.
 *
 * Retrieve a filtered and paginated list of plain-text comments under a
 * specific post. The underlying Prisma model civic_board_comments defines each
 * comment’s body, lifecycle status ("Published", "Hidden", "Deleted"),
 * published_at, optional edited_at within the 15-minute window, and audit
 * timestamps (created_at, updated_at). The table comment notes emphasize that
 * comments are text-only in the minimal scope and are listed oldest-first under
 * a post; attachments are not supported.
 *
 * Security and visibility: Public readers may access only comments that are
 * visible for the target post (typically status "Published"). Records marked as
 * "Hidden" or "Deleted" must not be returned to public readers, even though
 * civic_board_comments also tracks a deleted_at timestamp for retention/purge
 * policies. Authorization is enforced in provider logic based on the
 * authenticated actor. This endpoint itself is public for reading.
 *
 * Database relationships: Each comment references its parent post via
 * civic_board_post_id (FK to civic_board_posts.id) and the author via
 * civic_board_user_id (FK to civic_board_users.id). An optional authoring
 * session (civic_board_user_session_id) may exist for audit context and is
 * nullable per schema comments.
 *
 * Validation and business rules: The request body DTO
 * (ICivicBoardComment.IRequest) carries search and pagination parameters such
 * as keyword search against body (aligned with the GIN trigram index), author
 * filtering by civic_board_user_id, date range filtering using
 * created_at/published_at, and sorting (default oldest-first by created_at).
 * The path parameter postId provides the scope and must not be duplicated
 * inside the request body. Results honor page size constraints consistent with
 * performance targets.
 *
 * Related operations: Use GET /civicBoard/posts/{postId}/comments/{commentId}
 * to fetch a single comment’s details. When fetching a post detail, clients
 * typically call the post detail endpoint first, then use this listing endpoint
 * to page through comments as needed.
 *
 * Errors and behavior: If the post does not exist or is not visible to the
 * requester, provider logic returns an empty list or an appropriate
 * not-available outcome. When no comments match the filters, the response is an
 * empty page with zero total count. Rate limiting, if any, is handled
 * separately from this read path.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the target post whose comments are
 *   being listed (UUID).
 * @param props.body Search, filter, sort, and pagination parameters for
 *   comments under the specified post (do not repeat the path postId).
 * @path /civicBoard/posts/:postId/comments
 * @accessor api.functional.civicBoard.posts.comments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target post whose comments are being listed
     * (UUID).
     */
    postId: string & tags.Format<"uuid">;

    /**
     * Search, filter, sort, and pagination parameters for comments under
     * the specified post (do not repeat the path postId).
     */
    body: ICivicBoardComment.IRequest;
  };
  export type Body = ICivicBoardComment.IRequest;
  export type Response = IPageICivicBoardComment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/civicBoard/posts/:postId/comments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/civicBoard/posts/${encodeURIComponent(props.postId ?? "null")}/comments`;
  export const random = (): IPageICivicBoardComment.ISummary =>
    typia.random<IPageICivicBoardComment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

