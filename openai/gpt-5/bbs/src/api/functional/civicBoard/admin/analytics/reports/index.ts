/**
 * Administrative analytics for reports based on civic_board_reports and related
 * specialization tables.
 *
 * Retrieve administrative analytics summarizing user-submitted content reports.
 * The computation is anchored on the civic_board_reports table, whose columns
 * include reason (categorical reason such as Spam/Harassment/Off-topic/Other),
 * optional note, status (queue state like "pending" or "resolved"), and
 * created_at/updated_at timestamps. The specialization tables
 * civic_board_report_of_posts and civic_board_report_of_comments bind each
 * report to its concrete target and reporter identity. Their composite
 * uniqueness constraints (user+post or user+comment) allow detection of
 * duplicates for analytics purposes without over-counting.
 *
 * This endpoint is restricted to administrative actors because it exposes
 * system-level operational insights. Use it to monitor volume over time, top
 * reasons, resolution funnel, and distribution across posts versus comments.
 * Implementations may optionally join to civic_board_moderation_actions to
 * attribute decisions (e.g., "Hide", "Delete", "No Action") and to Articles
 * tables (civic_board_posts, civic_board_comments) when filtering by current
 * content status is necessary for policy reviews. The analytics query respects
 * the provided filters and time windows and returns only aggregate structures;
 * it never returns personal emails or raw free-text notes.
 *
 * From a data-model perspective, analytics derive from:
 *
 * - Civic_board_reports: core event rows with reason, status, created_at.
 * - Civic_board_report_of_posts / civic_board_report_of_comments: target-type
 *   discrimination, reporter and session context, and uniqueness guarantees to
 *   avoid double-counting.
 * - Civic_board_moderation_actions: one-to-one resolution records per report,
 *   enabling breakdowns by decision.
 *
 * Validation rules follow the underlying schema: reason and status filters must
 * align with values stored in civic_board_reports; date filters apply to
 * created_at ranges; and target-type accepts only post or comment determined by
 * the specialization linkage. When no data matches, the endpoint returns zeroed
 * totals with empty arrays. Authorization failures return an access-denied
 * outcome, and malformed filters result in validation errors describing which
 * field is incorrect.
 *
 * @param props.connection
 * @param props.body Filter, grouping, and pagination-like parameters for
 *   computing report analytics (time window on created_at, reason/status,
 *   target-type).
 * @path /civicBoard/admin/analytics/reports
 * @accessor api.functional.civicBoard.admin.analytics.reports.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Filter, grouping, and pagination-like parameters for computing report
     * analytics (time window on created_at, reason/status, target-type).
     */
    body: ICivicBoardReport.IRequest;
  };
  export type Body = ICivicBoardReport.IRequest;
  export type Response = ICivicBoardReportAnalytics;

  export const METADATA = {
    method: "PATCH",
    path: "/civicBoard/admin/analytics/reports",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/civicBoard/admin/analytics/reports";
  export const random = (): ICivicBoardReportAnalytics =>
    typia.random<ICivicBoardReportAnalytics>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
