/**
 * Search and paginate civic_board_reports for the admin moderation queue.
 *
 * Retrieve an administrator-facing queue of reports from civic_board_reports.
 * Each report row stores the categorical reason (reason), an optional note
 * (note), a workflow status string (status), and auditable timestamps
 * (created_at, updated_at). The schema comment clarifies that this table is the
 * moderator queue and that exactly one specialization must exist in either
 * civic_board_report_of_posts or civic_board_report_of_comments, which binds
 * the report to its concrete target. Use these relations when the UI needs to
 * show target type or reporter context; however, core filtering in this
 * operation focuses on fields physically present in civic_board_reports.
 *
 * Access to this listing is restricted to administrators because reports may
 * contain sensitive context and moderation notes. The operation is intended for
 * back-office workflows such as triage, bulk review, and time-based monitoring.
 * While reporters can query their own submissions via specialization-specific
 * endpoints, the generic /reports list is reserved for admin use to prevent
 * information disclosure.
 *
 * From a data relationship standpoint, civic_board_reports has a 1:1
 * association with one specialization row and an optional 1:1 association to a
 * civic_board_moderation_actions row recording the final decision (Hide,
 * Delete, or No Action). Duplicate-report prevention is enforced at the
 * specialization layer via composite unique constraints (for example, user +
 * post or user + comment), and not on the civic_board_reports base table
 * itself—providers should rely on those constraints when composing queries.
 *
 * Validation and business logic include filtering by status (e.g., pending vs
 * resolved), reason categories, and created_at ranges using the actual columns
 * present in the table. Since civic_board_reports includes a deleted_at column,
 * soft-deleted records are excluded by default unless an explicit
 * include-deleted flag is provided by the request body; this matches retention
 * and audit expectations.
 *
 * This operation is designed to pair with GET /reports/{reportId} for detailed
 * inspection and with moderation action creation endpoints (not defined here)
 * that write to civic_board_moderation_actions. Errors to expect include
 * authorization failures for non-admin actors and empty result sets when
 * filters yield no matches. Pagination is stable and results are ordered by
 * created_at desc by default, with optional sort overrides.
 *
 * @param props.connection
 * @param props.body Search criteria, pagination, and sorting options for admin
 *   review of reports. Filters must target columns on civic_board_reports
 *   (e.g., status, reason, created_at range).
 * @path /civicBoard/admin/reports
 * @accessor api.functional.civicBoard.admin.reports.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
