/**
 * Remove a specific comment from civic_board_comments under a given post by
 * marking it Deleted.
 *
 * Remove a specific comment from public visibility under the designated post.
 * According to the civic_board_comments Prisma model, each comment has columns
 * id (UUID), civic_board_post_id (UUID), civic_board_user_id (UUID), body
 * (String), status (String), published_at (DateTime), edited_at (DateTime?),
 * created_at (DateTime), updated_at (DateTime), and deleted_at (DateTime?).
 * This operation targets a single row in civic_board_comments identified by
 * {commentId} and scoped by {postId}. The provider will set status to "Deleted"
 * and populate deleted_at to indicate the comment is no longer visible while
 * retaining auditable timestamps in created_at and updated_at.
 *
 * Security and permissions: Access is restricted to authenticated actors. A
 * regular user may remove only their own comment; an administrator may remove
 * any comment for moderation. The civic_board_user_sessions relation present in
 * the schema enables audit context but is optional at deletion time. Attempts
 * by a non-owner user to remove another user’s comment must be denied.
 *
 * Entity relationships: The civic_board_comments.post relation points to
 * civic_board_posts via civic_board_post_id, ensuring the comment belongs to
 * the path’s {postId}. This endpoint validates that the comment’s
 * civic_board_post_id matches the provided {postId} before proceeding. The
 * author relation to civic_board_users remains intact. No attachments exist on
 * comments in this schema, so there is no additional file cleanup required.
 *
 * Validation and business rules: The provider should verify that the comment
 * currently exists and is not already in a removed state (status already
 * "Deleted"). If the parent post is already removed, the comment is not
 * publicly visible; removing again should be idempotent from the caller
 * perspective. Ownership checks ensure only the author or an admin can perform
 * the operation.
 *
 * Related operations: Clients typically fetch comments via the post detail
 * endpoint or a comments listing. After removal, the comment should no longer
 * appear in public listings. Administrative audit logging can be recorded in
 * civic_board_audit_logs with action like "comment.delete" and an outcome
 * string, though that table is managed by the system and not exposed via manual
 * write APIs.
 *
 * Error handling: If either {postId} or {commentId} does not correspond to a
 * visible, matching record, respond with a not-available outcome. If the actor
 * lacks permission, respond with a permission-denied outcome. This operation
 * performs a hard removal of visibility by updating status and timestamps; no
 * physical row deletion is performed by this endpoint.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the target post (UUID) that owns the
 *   comment.
 * @param props.commentId Unique identifier of the target comment within the
 *   specified post (UUID).
 * @path /civicBoard/admin/posts/:postId/comments/:commentId
 * @accessor api.functional.civicBoard.admin.posts.comments.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the target post (UUID) that owns the comment. */
    postId: string & tags.Format<"uuid">;

    /**
     * Unique identifier of the target comment within the specified post
     * (UUID).
     */
    commentId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/civicBoard/admin/posts/:postId/comments/:commentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/civicBoard/admin/posts/${encodeURIComponent(props.postId ?? "null")}/comments/${encodeURIComponent(props.commentId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
      assert.param("commentId")(() => typia.assert(props.commentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
