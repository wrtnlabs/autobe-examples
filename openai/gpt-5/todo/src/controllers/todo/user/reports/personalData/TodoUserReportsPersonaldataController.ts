import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoUserReportsPersonalData } from "../../../../../providers/postTodoUserReportsPersonalData";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoUserReportsPersonalDataExportId } from "../../../../../providers/getTodoUserReportsPersonalDataExportId";

import { ITodoUserPersonalDataExport } from "../../../../../api/structures/ITodoUserPersonalDataExport";

@Controller("/todo/user/reports/personalData")
export class TodoUserReportsPersonaldataController {
  /**
   * Create a personal data export composed from todo_users and todo_todos
   * (read-only).
   *
   * Create a personal data export for the authenticated user by reading from
   * the todo_users and todo_todos models. The todo_users model provides id,
   * email, and timestamps; although it stores a password_hash for
   * authentication, that sensitive field is never exported. The todo_todos
   * model contains a required single-line title, optional description, optional
   * date-only due_date interpreted at the application layer, a boolean
   * completed state, and created_at/updated_at timestamps. Ownership is
   * enforced with the todo_user_id foreign key so each todo belongs to exactly
   * one user.
   *
   * Security and permissions: only an authenticated user can request their own
   * export. The provider resolves the current principal from the active session
   * and restricts reads to rows where todo_user_id equals the requesting user’s
   * id. The operation is read-only with respect to domain tables. For
   * observability, the system may append an event into the system-wide audit
   * table; such auditing is internal-only and not exposed as a public write
   * API. The export never includes sensitive authentication material (e.g.,
   * password_hash) or session internals.
   *
   * Behavior and validations: a new export resource reference is returned
   * containing an exportId (UUID) and status metadata. If the user has no
   * todos, the export still includes the user’s account identifiers with an
   * empty todos collection. Implementations SHOULD apply rate
   * limiting/cooldowns to prevent abuse. Overdue/due-today indicators—if
   * included by the export schema—are computed at generation time based on
   * due_date using a consistent timezone policy (default: Asia/Seoul when the
   * user has not selected a timezone).
   *
   * @param connection
   * @param body Optional parameters controlling export options for the
   *   authenticated user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUserPersonalDataExport.ICreate,
  ): Promise<ITodoUserPersonalDataExport> {
    try {
      return await postTodoUserReportsPersonalData({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get a personal data export by exportId for the authenticated user.
   *
   * Return the personal data export created for the authenticated user. The
   * export aggregates user account identifiers from todo_users (id, email,
   * created_at, updated_at) and owned todos from todo_todos (id, title,
   * description, due_date, completed, created_at, updated_at) filtered by
   * ownership through todo_user_id. The models’ schema comments emphasize
   * strict one-user ownership for todos and deterministic timestamps for
   * ordering and audit expectations. Sensitive authentication material such as
   * password_hash and session internals are explicitly excluded from export
   * content and retrieval payloads.
   *
   * Access control ensures only the user who initiated the export can retrieve
   * it. Unauthenticated requests are denied, and users cannot access export
   * results belonging to other principals. The retrieval is read-only with
   * respect to domain tables and returns export metadata and, if applicable, a
   * download URI for the generated artifact (e.g., JSON). Items hard-deleted
   * prior to export creation are not present because todo_todos uses permanent
   * deletion in MVP. If the artifact has expired, clients should re-create an
   * export via POST /todo/user/reports/personalData.
   *
   * Error handling includes: not found (unknown or expired exportId),
   * permission denial (export not owned by requester), and artifact expiry
   * requiring regeneration. Due/overdue indicators—if present in the
   * artifact—are computed by application logic using date-only semantics and a
   * consistent timezone policy (default Asia/Seoul when user-specific timezone
   * is not configured).
   *
   * @param connection
   * @param exportId Unique identifier of the export job to retrieve (UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":exportId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("exportId")
    exportId: string & tags.Format<"uuid">,
  ): Promise<ITodoUserPersonalDataExport> {
    try {
      return await getTodoUserReportsPersonalDataExportId({
        user,
        exportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
