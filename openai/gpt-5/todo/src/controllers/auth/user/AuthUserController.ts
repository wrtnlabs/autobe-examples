import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";
import { postAuthUserLogout } from "../../../providers/postAuthUserLogout";
import { UserAuth } from "../../../decorators/UserAuth";
import { UserPayload } from "../../../decorators/payload/UserPayload";

import { ITodoUser } from "../../../api/structures/ITodoUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Create a new account in todo_users and establish an initial session.
   *
   * This endpoint creates an authenticating user account backed by the Actors
   * schema model todo_users. It persists the unique login identifier in email
   * and stores only a secure password hash in password_hash, never the
   * plaintext secret. Timestamps created_at and updated_at are set according to
   * application policy. The table-level uniqueness declared by
   *
   * @param connection
   * @param body Registration data including unique email and password that will
   *   be hashed.
   * @@unique([email]) ensures one account per email.
   *
   * Upon successful account creation, a login session is established using
   * the todo_user_sessions model. A new row is inserted with todo_user_id
   * referencing the newly created todo_users.id along with connection context
   * captured in ip, href, and referrer and the creation time in created_at.
   * The session life cycle can later be concluded by writing expired_at in
   * the same table.
   *
   * For end-to-end observability, the Systematic.todo_audit_events model is
   * used to append an auth-category record. The event references the acting
   * user via todo_user_id, optionally the originating session via
   * todo_user_session_id, describes the actor_type ("user"), sets category to
   * "auth", action to "register", and records success along with any message,
   * ip, href, and referrer as available.
   *
   * Security considerations include hashing the supplied password prior to
   * persistence into password_hash and never returning sensitive secrets.
   * Tokens are minted for the caller after persistence; the data source of
   * truth for identities remains todo_users and for sessions remains
   * todo_user_sessions.
   *
   * Related operations: POST /auth/user/login authenticates existing
   * accounts; POST /auth/user/refresh rotates tokens based on a valid refresh
   * token. Error handling should map database unique constraint violations
   * for email to a business message indicating that the email is already in
   * use, and validation should follow the requirements’ minimum password
   * strength rules before creating the record.
   *
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoUser.IJoin,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate against todo_users and record a new session in
   * todo_user_sessions.
   *
   * This endpoint validates a user's credentials against the todo_users model.
   * The unique identifier email is used to locate the account and the supplied
   * password is verified by comparing after hashing to the stored
   * password_hash. On success, updated_at on todo_users may be set by
   * application policy to reflect account activity.
   *
   * A new session is recorded in the todo_user_sessions model to capture
   * connection context. The row stores todo_user_id linking to todo_users.id,
   * ip, href, referrer for context, and created_at for the session start.
   * Session termination is modeled by setting expired_at later.
   *
   * For observability, an auth audit record is appended to todo_audit_events
   * with actor_type set to "user", category set to "auth", action "login",
   * success true or false depending on outcome, and optional references to
   * todo_user_id and todo_user_session_id as appropriate. The event may also
   * include ip, href, and referrer for security review.
   *
   * Security notes: only the hash in password_hash is ever read; plaintext is
   * never stored. On successful authentication, JWT credentials are minted for
   * the caller; identity persists in todo_users while session context persists
   * in todo_user_sessions.
   *
   * Related operations include POST /auth/user/join for initial registration
   * and POST /auth/user/refresh for token renewal. On failure (e.g., account
   * not found by email or hash mismatch), respond with a generic
   * invalid-credentials business message without disclosing whether the account
   * exists.
   *
   * @param connection
   * @param body Login credentials including email and password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoUser.ILogin,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh user access credentials with session context tracked via
   * todo_user_sessions.
   *
   * This endpoint exchanges a valid refresh token for new access credentials.
   * While token material is not stored in the schema, renewal is tied at the
   * business level to the authenticated actor defined in todo_users.
   * Implementations commonly associate the refresh with a session in
   * todo_user_sessions by referencing todo_user_id and capturing ip, href,
   * referrer, and created_at when establishing or rotating session context.
   *
   * The todo_user_sessions model supports tracking session lifecycle by
   * allowing an eventual write to expired_at to mark the session closed, while
   * active sessions have expired_at as null. This provides clear separation
   * between token issuance and session state representation.
   *
   * For traceability, an auth-category event is appended to todo_audit_events
   * with actor_type "user", category "auth", action "refresh", success flag,
   * and optional references todo_user_id and todo_user_session_id. The event
   * can also store ip, href, and referrer for security analytics.
   *
   * Security considerations include validating the refresh token’s integrity
   * and ensuring it corresponds to the intended user context before minting new
   * credentials. No plaintext secrets are persisted; user credentials remain in
   * todo_users.password_hash as a hash only.
   *
   * Related endpoints: POST /auth/user/login to authenticate and establish
   * sessions; POST /auth/user/join to register an account. If a presented
   * refresh token is invalid or expired per business rules, return a denial
   * that does not disclose internal validation details.
   *
   * @param connection
   * @param body Refresh request containing the refresh token or equivalent
   *   renewal proof.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoUser.IRefresh,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * End the current session by updating expired_at in todo_user_sessions and
   * record an audit event.
   *
   * This endpoint terminates the caller’s current authenticated session. The
   * session model todo_user_sessions captures the lifecycle; the server marks
   * the session ended by writing a timestamp to expired_at while retaining
   * todo_user_id, ip, href, referrer, and created_at as historical context.
   * Active sessions have expired_at as null; after logout it is populated.
   *
   * The action is performed on behalf of the authenticated actor defined in
   * todo_users, but no changes are made to email or password_hash in the
   * todo_users model.
   *
   * An audit record is appended in todo_audit_events identifying actor_type as
   * "user", category as "auth", action as "logout", success as true on
   * successful termination, and optionally referencing both todo_user_id and
   * todo_user_session_id. Additional context like ip, href, and referrer may be
   * captured.
   *
   * Security posture: terminating the session prevents further use of the
   * associated credentials for protected actions tied to that session. Token
   * revocation/blacklist strategy is implementation-defined and not persisted
   * in the schema; session state is the durable representation.
   *
   * Related operations: POST /auth/user/login to establish a new session after
   * logout; POST /auth/user/refresh to rotate tokens for active sessions.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("logout")
  public async logout(
    @UserAuth()
    user: UserPayload,
  ): Promise<void> {
    try {
      return await postAuthUserLogout({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
