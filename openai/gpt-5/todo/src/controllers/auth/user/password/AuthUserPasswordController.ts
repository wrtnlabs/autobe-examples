import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { putAuthUserPassword } from "../../../../providers/putAuthUserPassword";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";

import { ITodoUser } from "../../../../api/structures/ITodoUser";

@Controller("/auth/user/password")
export class AuthUserPasswordController {
  /**
   * Change the authenticated user’s password by updating password_hash in
   * todo_users.
   *
   * This endpoint enables password rotation for the authenticated actor stored
   * in todo_users. The server verifies the submitted current password by
   * hashing and comparing to password_hash and, on success, persists a newly
   * hashed secret into password_hash. The updated_at timestamp on todo_users is
   * advanced to reflect the credential change.
   *
   * No modification is required to session rows in todo_user_sessions for the
   * operation itself; however, downstream policy may choose to terminate or
   * rotate sessions separately. The session model holds contextual fields ip,
   * href, referrer, created_at, and an optional expired_at for lifecycle
   * tracking.
   *
   * An audit trail entry is appended in todo_audit_events with actor_type
   * "user", category "auth", action "change_password", and success reflecting
   * the outcome. The record can reference todo_user_id and optionally
   * todo_user_session_id and include ip, href, and referrer for security
   * review.
   *
   * Security considerations include enforcing minimum password quality before
   * updating password_hash, avoiding disclosure of whether the current password
   * matched, and preventing plaintext handling beyond transient verification.
   * Only the hash is persisted.
   *
   * Related operations: POST /auth/user/login for subsequent re-authentication
   * where policy requires; POST /auth/user/logout to terminate sessions; POST
   * /auth/user/refresh for token rotation where applicable.
   *
   * @param connection
   * @param body Old and new password values to validate and persist after
   *   hashing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async changePassword(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUser.IUpdatePassword,
  ): Promise<ITodoUser> {
    try {
      return await putAuthUserPassword({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
