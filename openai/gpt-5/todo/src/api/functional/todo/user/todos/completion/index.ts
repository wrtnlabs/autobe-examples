import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoTodoCompletion } from "../../../../../structures/ITodoTodoCompletion";
import { ITodoTodo } from "../../../../../structures/ITodoTodo";

/**
 * Update the `completed` field of a todo_todos record and return the updated
 * entity.
 *
 * Set the `completed` flag of a personal todo item to either true (mark
 * complete) or false (reopen). The underlying Prisma model `todo_todos` defines
 * `completed` as a boolean field, with additional fields including `id` (UUID),
 * `todo_user_id` (owner reference), `title`, `description`, optional
 * `due_date`, and timestamps `created_at` and `updated_at`. Application logic
 * interprets `due_date` as a date-only concept and computes overdue/due-today
 * states without storing derived flags.
 *
 * Security and permissions: access is restricted to the authenticated owner
 * (`todo_todos.todo_user_id` equals the requester). Requests from other users
 * must be denied without disclosing existence. The actor is the "user" role;
 * provider code should attribute the action and may record a corresponding
 * entry in `todo_audit_events` for observability.
 *
 * Business logic and validation: the request body conveys the target state for
 * `completed`. The operation is idempotent: if the requested state equals the
 * current database value, the provider returns success with the current
 * representation. On successful update, `updated_at` should be refreshed for
 * consistent secondary ordering. The response returns the full `todo_todos`
 * entity to allow clients to render current values, including `completed`,
 * `due_date`, and timestamps.
 *
 * Error handling: if `todoId` does not correspond to an existing owned record,
 * respond with a not-available outcome; for ownership violations, deny access.
 * Transient errors should support safe retries without duplicate side effects.
 *
 * @param props.connection
 * @param props.todoId UUID of the target todo (`todo_todos.id`).
 * @param props.body Desired completion state for the todo item (`completed:
 *   boolean`).
 * @path /todo/user/todos/:todoId/completion
 * @accessor api.functional.todo.user.todos.completion.updateCompletion
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function updateCompletion(
  connection: IConnection,
  props: updateCompletion.Props,
): Promise<updateCompletion.Response> {
  return true === connection.simulate
    ? updateCompletion.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...updateCompletion.METADATA,
          path: updateCompletion.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace updateCompletion {
  export type Props = {
    /** UUID of the target todo (`todo_todos.id`). */
    todoId: string & tags.Format<"uuid">;

    /** Desired completion state for the todo item (`completed: boolean`). */
    body: ITodoTodoCompletion.IUpdate;
  };
  export type Body = ITodoTodoCompletion.IUpdate;
  export type Response = ITodoTodo;

  export const METADATA = {
    method: "PUT",
    path: "/todo/user/todos/:todoId/completion",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todo/user/todos/${encodeURIComponent(props.todoId ?? "null")}/completion`;
  export const random = (): ITodoTodo => typia.random<ITodoTodo>();
  export const simulate = (
    connection: IConnection,
    props: updateCompletion.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: updateCompletion.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
