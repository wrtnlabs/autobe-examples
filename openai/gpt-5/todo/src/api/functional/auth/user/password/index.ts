import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoUser } from "../../../../structures/ITodoUser";

/**
 * Change the authenticated user’s password by updating password_hash in
 * todo_users.
 *
 * This endpoint enables password rotation for the authenticated actor stored in
 * todo_users. The server verifies the submitted current password by hashing and
 * comparing to password_hash and, on success, persists a newly hashed secret
 * into password_hash. The updated_at timestamp on todo_users is advanced to
 * reflect the credential change.
 *
 * No modification is required to session rows in todo_user_sessions for the
 * operation itself; however, downstream policy may choose to terminate or
 * rotate sessions separately. The session model holds contextual fields ip,
 * href, referrer, created_at, and an optional expired_at for lifecycle
 * tracking.
 *
 * An audit trail entry is appended in todo_audit_events with actor_type "user",
 * category "auth", action "change_password", and success reflecting the
 * outcome. The record can reference todo_user_id and optionally
 * todo_user_session_id and include ip, href, and referrer for security review.
 *
 * Security considerations include enforcing minimum password quality before
 * updating password_hash, avoiding disclosure of whether the current password
 * matched, and preventing plaintext handling beyond transient verification.
 * Only the hash is persisted.
 *
 * Related operations: POST /auth/user/login for subsequent re-authentication
 * where policy requires; POST /auth/user/logout to terminate sessions; POST
 * /auth/user/refresh for token rotation where applicable.
 *
 * @param props.connection
 * @param props.body Old and new password values to validate and persist after
 *   hashing.
 * @path /auth/user/password
 * @accessor api.functional.auth.user.password.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<changePassword.Response> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /** Old and new password values to validate and persist after hashing. */
    body: ITodoUser.IUpdatePassword;
  };
  export type Body = ITodoUser.IUpdatePassword;
  export type Response = ITodoUser;

  export const METADATA = {
    method: "PUT",
    path: "/auth/user/password",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password";
  export const random = (): ITodoUser => typia.random<ITodoUser>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
