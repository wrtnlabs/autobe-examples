/**
 * Expire all active sessions in todo_user_sessions for the authenticated user.
 *
 * This endpoint performs a bulk session invalidation for the authenticated user
 * by updating the session records stored in todo_user_sessions. Each active
 * session (expired_at is null) associated with the user’s todo_user_id is
 * marked ended by writing expired_at. Contextual fields such as ip, href,
 * referrer, and created_at remain for historical analysis.
 *
 * User identity and credentials in todo_users (email and password_hash) are not
 * altered by this operation. The action focuses solely on session lifecycle
 * management.
 *
 * A corresponding audit trail row is appended in todo_audit_events with
 * actor_type "user", category "auth", action "logout_all", success flag, and
 * references to todo_user_id. The entry may include ip, href, and referrer
 * describing the caller context initiating the bulk termination.
 *
 * Security considerations: expiring all sessions is a defensive measure after
 * credential changes or suspicious activity. After this operation, protected
 * actions require new authentication to create fresh session rows.
 *
 * Related operations: PUT /auth/user/password to rotate credentials; POST
 * /auth/user/login to establish a new session; POST /auth/user/refresh to
 * rotate tokens for any subsequently created sessions.
 *
 * @param props.connection
 * @path /auth/user/sessions/expire
 * @accessor api.functional.auth.user.sessions.expire.logoutAllSessions
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logoutAllSessions(
  connection: IConnection,
): Promise<void> {
  return true === connection.simulate
    ? logoutAllSessions.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logoutAllSessions.METADATA,
          path: logoutAllSessions.path(),
          status: null,
        },
      );
}
export namespace logoutAllSessions {
  export const METADATA = {
    method: "POST",
    path: "/auth/user/sessions/expire",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/sessions/expire";
  export const random = (): void => typia.random<void>();
  export const simulate = (_connection: IConnection): void => {
    return random();
  };
}
