/**
 * Create a new account in todo_users and establish an initial session.
 *
 * This endpoint creates an authenticating user account backed by the Actors
 * schema model todo_users. It persists the unique login identifier in email and
 * stores only a secure password hash in password_hash, never the plaintext
 * secret. Timestamps created_at and updated_at are set according to application
 * policy. The table-level uniqueness declared by @@unique([email]) ensures one
 * account per email.
 *
 * Upon successful account creation, a login session is established using the
 * todo_user_sessions model. A new row is inserted with todo_user_id referencing
 * the newly created todo_users.id along with connection context captured in ip,
 * href, and referrer and the creation time in created_at. The session life
 * cycle can later be concluded by writing expired_at in the same table.
 *
 * For end-to-end observability, the Systematic.todo_audit_events model is used
 * to append an auth-category record. The event references the acting user via
 * todo_user_id, optionally the originating session via todo_user_session_id,
 * describes the actor_type ("user"), sets category to "auth", action to
 * "register", and records success along with any message, ip, href, and
 * referrer as available.
 *
 * Security considerations include hashing the supplied password prior to
 * persistence into password_hash and never returning sensitive secrets. Tokens
 * are minted for the caller after persistence; the data source of truth for
 * identities remains todo_users and for sessions remains todo_user_sessions.
 *
 * Related operations: POST /auth/user/login authenticates existing accounts;
 * POST /auth/user/refresh rotates tokens based on a valid refresh token. Error
 * handling should map database unique constraint violations for email to a
 * business message indicating that the email is already in use, and validation
 * should follow the requirements’ minimum password strength rules before
 * creating the record.
 *
 * @param props.connection
 * @param props.body Registration data including unique email and password that
 *   will be hashed.
 * @setHeader token.access Authorization
 *
 * @path /auth/user/join
 * @accessor api.functional.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /**
     * Registration data including unique email and password that will be
     * hashed.
     */
    body: ITodoUser.IJoin;
  };
  export type Body = ITodoUser.IJoin;
  export type Response = ITodoUser.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/join";
  export const random = (): ITodoUser.IAuthorized =>
    typia.random<ITodoUser.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

