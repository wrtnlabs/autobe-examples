export async function test_api_order_item_detail_other_customer_forbidden(
  connection: api.IConnection,
): Promise<void> {
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(customerA);
  const paymentAttempt =
    await generate_random_shopping_mall_customer_payment_attempts_create(
      customerAConnection,
      {
        body: {
          amount: 100,
          gateway_provider: RandomGenerator.alphabets(8),
        },
      },
    );
  typia.assert(paymentAttempt);
  const finalizedAttempt =
    await api.functional.shoppingMall.customer.paymentAttempts.update(
      customerAConnection,
      {
        paymentAttemptId: paymentAttempt.id,
        body: {
          status: "succeeded",
          gateway_provider: paymentAttempt.gateway_provider,
          gateway_reference: RandomGenerator.alphaNumeric(12),
          failure_reason: null,
          processed_at: new Date().toISOString(),
        } satisfies IShoppingMallPaymentAttempt.IUpdate,
      },
    );
  typia.assert(finalizedAttempt);
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB = await authorize_customer_join(customerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(customerB);
  await TestValidator.httpError(
    "other customer cannot read another customer's order item detail",
    [403, 404],
    async () => {
      await api.functional.shoppingMall.customer.orders.items.at(
        customerBConnection,
        {
          orderCode: typia.random<string & tags.Format<"uuid">>(),
          itemId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
