export async function test_api_wishlist_entry_deleted_product_unavailable(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {});
  typia.assert(authorized);
  await TestValidator.httpError(
    "deleted-product wishlist entry is unavailable",
    404,
    async () => {
      await api.functional.shoppingMall.customer.wishlistEntries.at(
        customerConnection,
        {
          wishlistEntryId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
