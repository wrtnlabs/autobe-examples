export async function test_api_seller_profile_snapshot_history_administrator_filtered_browse(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = {
    host: connection.host,
  };
  await authorize_administrator_join(administratorConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallAdministrator.IJoin,
  });
  const changedAtFrom = new Date(
    Date.now() - 1000 * 60 * 60 * 24 * 30,
  ).toISOString();
  const changedAtTo = new Date().toISOString();
  const request = {
    search: RandomGenerator.alphabets(6).toLowerCase(),
    changedAtFrom,
    changedAtTo,
    sortBy: "changed_at",
    sortOrder: "asc",
    page: 1,
    limit: 10,
  } satisfies IShoppingMallSellerProfileSnapshot.IRequest;
  await TestValidator.error(
    "administrator cannot browse snapshots for non-existent seller profile id",
    async () => {
      await api.functional.shoppingMall.administrator.seller_profiles.snapshots.index(
        administratorConnection,
        {
          sellerProfileId: typia.random<string & tags.Format<"uuid">>(),
          body: request,
        },
      );
    },
  );
}
