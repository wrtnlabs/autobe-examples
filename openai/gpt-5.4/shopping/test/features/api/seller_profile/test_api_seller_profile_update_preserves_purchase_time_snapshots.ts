export async function test_api_seller_profile_update_preserves_purchase_time_snapshots(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerJoin = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerJoin);
  const updateBody = {
    displayName: RandomGenerator.name(),
    phoneNumber: RandomGenerator.mobile(),
  } satisfies IShoppingMallCustomerProfile.IUpdate;
  const updatedProfile =
    await api.functional.shoppingMall.seller.profile.update(sellerConnection, {
      body: updateBody,
    });
  typia.assert(updatedProfile);
  TestValidator.equals(
    "updated display name matches request",
    updatedProfile.displayName,
    updateBody.displayName,
  );
  TestValidator.equals(
    "updated phone number matches request",
    updatedProfile.phoneNumber,
    updateBody.phoneNumber,
  );
}
