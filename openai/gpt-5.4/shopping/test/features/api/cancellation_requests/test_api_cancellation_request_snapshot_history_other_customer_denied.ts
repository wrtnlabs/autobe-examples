export async function test_api_cancellation_request_snapshot_history_other_customer_denied(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = {
    host: connection.host,
  };
  const ownerAuth = await authorize_customer_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(ownerAuth);
  const foreignCancellationRequest =
    await generate_random_shopping_mall_customer_cancellation_requests_create(
      ownerConnection,
      {},
    );
  typia.assert(foreignCancellationRequest);
  TestValidator.equals(
    "foreign cancellation request belongs to owner customer",
    foreignCancellationRequest.customer.id,
    ownerAuth.id,
  );
  const otherCustomerConnection: api.IConnection = {
    host: connection.host,
  };
  const otherCustomerAuth = await authorize_customer_join(
    otherCustomerConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
        ip: typia.random<string & tags.Format<"ipv4">>(),
      },
    },
  );
  typia.assert(otherCustomerAuth);
  TestValidator.notEquals(
    "other customer is distinct from owner",
    otherCustomerAuth.id,
    ownerAuth.id,
  );
  const requestBody = {
    page: 1,
    limit: 10,
    sort: "desc",
  } satisfies IShoppingMallCancellationRequestSnapshot.IRequest;
  await TestValidator.httpError(
    "other customer cannot access foreign cancellation request snapshot history",
    [403, 404],
    async () => {
      await api.functional.shoppingMall.customer.cancellation_requests.snapshots.index(
        otherCustomerConnection,
        {
          cancellationRequestId: foreignCancellationRequest.id,
          body: requestBody,
        },
      );
    },
  );
}
