export async function test_api_customer_account_detail_governance_read(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert<IShoppingMallCustomer.IAuthorized>(customer);
  const administratorConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(administratorConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallAdministrator.IJoin,
  });
  const account = await api.functional.shoppingMall.customers.at(
    administratorConnection,
    {
      customerId: customer.id,
    },
  );
  typia.assert<IShoppingMallCustomer>(account);
  TestValidator.equals(
    "returned customer id matches requested id",
    account.id,
    customer.id,
  );
  TestValidator.equals(
    "active customer banned_at is null",
    account.banned_at,
    null,
  );
  TestValidator.equals(
    "active customer deleted_at is null",
    account.deleted_at,
    null,
  );
  TestValidator.predicate(
    "created_at is populated",
    account.created_at.length > 0,
  );
  TestValidator.predicate(
    "updated_at is populated",
    account.updated_at.length > 0,
  );
}
