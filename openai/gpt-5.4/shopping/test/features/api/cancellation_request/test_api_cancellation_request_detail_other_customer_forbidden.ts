export async function test_api_cancellation_request_detail_other_customer_forbidden(
  connection: api.IConnection,
): Promise<void> {
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA: IShoppingMallCustomer.IAuthorized =
    await authorize_customer_join(customerAConnection, {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
        ip: typia.random<string & tags.Format<"ipv4">>(),
      },
    });
  typia.assert(customerA);
  const cancellationRequest: IShoppingMallCancellationRequest =
    await generate_random_shopping_mall_customer_cancellation_requests_create(
      customerAConnection,
      {
        body: {
          reason: RandomGenerator.paragraph({ sentences: 3 }),
        },
      },
    );
  typia.assert(cancellationRequest);
  TestValidator.equals(
    "cancellation request belongs to customer A",
    cancellationRequest.customer.id,
    customerA.id,
  );
  TestValidator.predicate(
    "cancellation request has an id",
    cancellationRequest.id.length > 0,
  );
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB: IShoppingMallCustomer.IAuthorized =
    await authorize_customer_join(customerBConnection, {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
        ip: typia.random<string & tags.Format<"ipv4">>(),
      },
    });
  typia.assert(customerB);
  TestValidator.notEquals(
    "customer A and B are distinct accounts",
    customerA.id,
    customerB.id,
  );
  await TestValidator.httpError(
    "other customer cannot read cancellation request detail",
    [403, 404],
    async () => {
      await api.functional.shoppingMall.customer.cancellation_requests.at(
        customerBConnection,
        {
          cancellationRequestId: cancellationRequest.id,
        },
      );
    },
  );
}
