export async function test_api_cancellation_request_response_terminal_state_rejected(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  const body = {
    status: "rejected",
    decisionNote: null,
  } satisfies IShoppingMallCancellationRequest.IResponse;
  await TestValidator.httpError(
    "seller cannot respond to a non-processable cancellation request",
    [400, 403, 404, 409, 422],
    async () => {
      await api.functional.shoppingMall.seller.cancellationRequests.responses.create(
        sellerConnection,
        {
          cancellationRequestId: typia.random<string & tags.Format<"uuid">>(),
          body,
        },
      );
    },
  );
}
