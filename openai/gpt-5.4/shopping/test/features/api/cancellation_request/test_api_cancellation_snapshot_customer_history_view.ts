export async function test_api_cancellation_snapshot_customer_history_view(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16) satisfies string as string &
        tags.Format<"password">,
      href: "https://example.com/shopping-mall/cancellations",
      referrer: "https://example.com/shopping-mall/orders",
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(customer);
  await TestValidator.error(
    "customer cannot retrieve an unavailable cancellation snapshot without prepared owned history",
    async () => {
      await api.functional.shoppingMall.customer.cancellation_requests.snapshots.at(
        customerConnection,
        {
          cancellationRequestId: typia.random<string & tags.Format<"uuid">>(),
          snapshotId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
