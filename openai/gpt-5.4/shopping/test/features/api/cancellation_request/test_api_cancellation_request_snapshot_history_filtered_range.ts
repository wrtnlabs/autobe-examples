export async function test_api_cancellation_request_snapshot_history_filtered_range(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(customer);
  const createdAtFrom = new Date(
    Date.now() - 1000 * 60 * 60 * 24,
  ).toISOString();
  const createdAtTo = new Date().toISOString();
  const body = {
    page: 1,
    limit: 10,
    sort: "asc",
    createdAtFrom,
    createdAtTo,
  } satisfies IShoppingMallCancellationRequestSnapshot.IRequest;
  await TestValidator.httpError(
    "snapshot history requires an existing and accessible cancellation request",
    [403, 404],
    async () => {
      await api.functional.shoppingMall.customer.cancellation_requests.snapshots.index(
        customerConnection,
        {
          cancellationRequestId: typia.random<string & tags.Format<"uuid">>(),
          body,
        },
      );
    },
  );
}
