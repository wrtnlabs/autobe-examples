export async function test_api_administrator_detail_non_admin_forbidden(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = {
    host: connection.host,
  };
  const administrator = await authorize_administrator_join(
    administratorConnection,
    {},
  );
  typia.assert(administrator);
  const customerConnection: api.IConnection = {
    host: connection.host,
  };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  await TestValidator.httpError(
    "customer cannot access administrator detail",
    [401, 403],
    async () => {
      await api.functional.shoppingMall.administrators.at(customerConnection, {
        administratorId: administrator.id,
      });
    },
  );
}
