export async function test_api_review_snapshot_history_deleted_review(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16) satisfies string as string &
        tags.Format<"password">,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customer);
  const reviewId = typia.random<string & tags.Format<"uuid">>();
  const request = {
    sort: "created_at_desc",
    page: 1 satisfies number as number & tags.Type<"int32"> & tags.Minimum<1>,
    limit: 10 satisfies number as number &
      tags.Type<"int32"> &
      tags.Minimum<1> &
      tags.Maximum<100>,
  } satisfies IShoppingMallReviewSnapshot.IRequest;
  await TestValidator.error(
    "deleted-review snapshot history lookup fails when the scoped review cannot be provisioned",
    async () => {
      await api.functional.shoppingMall.customer.reviews.snapshots.index(
        customerConnection,
        {
          reviewId,
          body: request,
        },
      );
    },
  );
}
