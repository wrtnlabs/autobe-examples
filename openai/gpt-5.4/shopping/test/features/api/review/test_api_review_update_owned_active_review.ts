export async function test_api_review_update_owned_active_review(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  const updateBody = {
    rating: 5 satisfies number as number & tags.Type<"int32">,
    content: RandomGenerator.content({ paragraphs: 2 }),
  } satisfies IShoppingMallReview.IUpdate;
  await TestValidator.httpError(
    "updating a non-existent owned review is rejected",
    [404, 403],
    async () => {
      await api.functional.shoppingMall.customer.reviews.update(
        customerConnection,
        {
          reviewId: typia.random<string & tags.Format<"uuid">>(),
          body: updateBody,
        },
      );
    },
  );
}
