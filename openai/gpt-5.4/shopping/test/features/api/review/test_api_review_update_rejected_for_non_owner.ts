export async function test_api_review_update_rejected_for_non_owner(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = {
    host: connection.host,
  };
  const owner = await authorize_customer_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(owner);
  const actingCustomerConnection: api.IConnection = {
    host: connection.host,
  };
  const actingCustomer = await authorize_customer_join(
    actingCustomerConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: typia.random<string & tags.Format<"password">>(),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
        ip: typia.random<string & tags.Format<"ipv4">>(),
      },
    },
  );
  typia.assert(actingCustomer);
  TestValidator.notEquals(
    "customers must be distinct",
    owner.id,
    actingCustomer.id,
  );
  const reviewId = typia.random<string & tags.Format<"uuid">>();
  const body = {
    rating: typia.random<number & tags.Type<"int32">>(),
    content: RandomGenerator.paragraph({ sentences: 3 }),
  } satisfies IShoppingMallReview.IUpdate;
  await TestValidator.httpError(
    "non-owner cannot update another customer's review",
    [403, 404],
    async () => {
      await api.functional.shoppingMall.customer.reviews.update(
        actingCustomerConnection,
        {
          reviewId,
          body,
        },
      );
    },
  );
}
