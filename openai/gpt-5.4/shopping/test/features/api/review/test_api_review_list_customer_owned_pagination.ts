export async function test_api_review_list_customer_owned_pagination(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(authorized);
  const request = {
    page: 1 satisfies number as number & tags.Type<"int32"> & tags.Minimum<1>,
    limit: 10 satisfies number as number &
      tags.Type<"int32"> &
      tags.Minimum<1> &
      tags.Maximum<100>,
  } satisfies IShoppingMallReview.IRequest;
  const page = await api.functional.shoppingMall.customer.reviews.index(
    customerConnection,
    {
      body: request,
    },
  );
  typia.assert(page);
  TestValidator.equals(
    "pagination current reflects requested page",
    page.pagination.current,
    request.page,
  );
  TestValidator.equals(
    "pagination limit reflects requested limit",
    page.pagination.limit,
    request.limit,
  );
  TestValidator.predicate(
    "data length is bounded by pagination limit",
    page.data.length <= page.pagination.limit,
  );
  TestValidator.predicate(
    "pagination pages follow records and limit formula",
    page.pagination.records === 0
      ? page.pagination.pages === 0
      : page.pagination.pages ===
          Math.ceil(page.pagination.records / page.pagination.limit),
  );
  for (const review of page.data) {
    TestValidator.equals(
      "review belongs to authenticated customer",
      review.customer.id,
      authorized.id,
    );
    TestValidator.equals(
      "review customer email matches authenticated customer",
      review.customer.email,
      authorized.email,
    );
  }
}
