export async function test_api_shipment_create_already_assigned_item_rejected(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(sellerAuth);
  const product =
    await generate_random_shopping_mall_seller_seller_products_create(
      sellerConnection,
      {
        body: {
          shopping_mall_category_id: null,
          name: RandomGenerator.name(2),
          description: RandomGenerator.content({ paragraphs: 2 }),
          base_price: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >() satisfies number as number,
          status: "active",
        } satisfies IShoppingMallProduct.ICreate,
      },
    );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
        body: {
          sku_code: RandomGenerator.alphaNumeric(12),
          option_summary: RandomGenerator.paragraph({ sentences: 3 }),
          price: (product.base_price + 500) satisfies number as number,
        } satisfies IShoppingMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  const inventoryRecord =
    await generate_random_shopping_mall_seller_seller_products_variants_inventory_records_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
          variantId: variant.id,
        },
        body: {
          quantity_change: 10 satisfies number as number,
          reason: RandomGenerator.paragraph({ sentences: 2 }),
          occurred_at: new Date().toISOString(),
        } satisfies IShoppingMallInventoryRecord.ICreate,
      },
    );
  typia.assert(inventoryRecord);
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  const shippingAddress =
    await generate_random_shopping_mall_customer_shipping_addresses_create(
      customerConnection,
      {
        body: {
          recipient_name: RandomGenerator.name(),
          phone_number: RandomGenerator.mobile(),
          street_address: RandomGenerator.paragraph({ sentences: 3 }),
          city: RandomGenerator.name(1),
          state_province: RandomGenerator.name(1),
          postal_code: RandomGenerator.alphaNumeric(8),
          country: RandomGenerator.name(1),
          is_default: true,
        } satisfies IShoppingMallShippingAddress.ICreate,
      },
    );
  typia.assert(shippingAddress);
  const paymentAttempt =
    await generate_random_shopping_mall_customer_payment_attempts_create(
      customerConnection,
      {
        body: {
          amount: ((variant.price ?? product.base_price) *
            1) satisfies number as number,
          gateway_provider: RandomGenerator.alphaNumeric(8),
        } satisfies IShoppingMallPaymentAttempt.ICreate,
      },
    );
  typia.assert(paymentAttempt);
  await TestValidator.error(
    "shipment creation rejects non-existent or unavailable order item assignment",
    async () => {
      await api.functional.shoppingMall.seller.shipments.create(
        sellerConnection,
        {
          body: {
            orderItemIds: [typia.random<string & tags.Format<"uuid">>()],
            trackingInfo: {
              carrier_name: RandomGenerator.name(1),
              tracking_number: RandomGenerator.alphaNumeric(18),
              tracking_url: typia.random<string & tags.Format<"uri">>(),
            } satisfies IShoppingMallTrackingInfo.ICreate,
          } satisfies IShoppingMallShipment.ICreate,
        },
      );
    },
  );
  TestValidator.equals(
    "seller context remains authenticated",
    sellerConnection.headers?.Authorization,
    sellerAuth.token.access,
  );
  TestValidator.equals(
    "customer context remains authenticated",
    customerConnection.headers?.Authorization,
    customerAuth.token.access,
  );
  TestValidator.equals(
    "payment attempt belongs to created customer",
    paymentAttempt.customer.id,
    customerAuth.id,
  );
  TestValidator.equals(
    "product belongs to seller",
    product.seller.id,
    sellerAuth.id,
  );
  TestValidator.equals(
    "variant belongs to created product",
    variant.product.id,
    product.id,
  );
  TestValidator.equals(
    "inventory record belongs to created variant",
    inventoryRecord.productVariant.id,
    variant.id,
  );
}
