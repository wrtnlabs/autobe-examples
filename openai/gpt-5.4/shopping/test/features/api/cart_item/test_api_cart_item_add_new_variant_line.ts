export async function test_api_cart_item_add_new_variant_line(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(authorized);
  const quantity = 3;
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          quantity,
        },
      },
    );
  typia.assert(cartItem);
  TestValidator.equals(
    "cart item quantity matches request",
    cartItem.quantity,
    quantity,
  );
  TestValidator.equals("cart item is active", cartItem.deleted_at, null);
  const expectedUnitPrice =
    cartItem.productVariant.price ?? cartItem.product.base_price;
  TestValidator.equals(
    "unit price reflects effective selling price",
    cartItem.unit_price,
    expectedUnitPrice,
  );
  TestValidator.equals(
    "subtotal equals unit price multiplied by quantity",
    cartItem.subtotal,
    cartItem.unit_price * cartItem.quantity,
  );
  TestValidator.equals(
    "availability indicates item is eligible for checkout",
    cartItem.availability,
    true,
  );
}
