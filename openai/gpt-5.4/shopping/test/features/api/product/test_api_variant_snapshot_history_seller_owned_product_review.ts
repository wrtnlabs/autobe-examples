export async function test_api_variant_snapshot_history_seller_owned_product_review(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(seller);
  const product =
    await generate_random_shopping_mall_seller_seller_products_create(
      sellerConnection,
      {
        body: {
          shopping_mall_category_id: null,
          name: RandomGenerator.name(2),
          description: RandomGenerator.content({ paragraphs: 2 }),
          base_price: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1>
          >() satisfies number as number,
          status: RandomGenerator.pick(["sale", "draft", "active"] as const),
        } satisfies IShoppingMallProduct.ICreate,
      },
    );
  typia.assert(product);
  TestValidator.equals(
    "seller owns created product",
    product.seller.id,
    seller.id,
  );
  const request = {
    page: 1,
    limit: 10,
    sort: "-created_at",
  } satisfies IShoppingMallProductVariantSnapshot.IRequest;
  const nonexistentProductSnapshotId = typia.random<
    string & tags.Format<"uuid">
  >();
  await TestValidator.httpError(
    "variant snapshot history rejects nonexistent owned product snapshot",
    [400, 404, 422],
    async () => {
      await api.functional.shoppingMall.seller.products.snapshots.variant_snapshots.index(
        sellerConnection,
        {
          productId: product.id,
          productSnapshotId: nonexistentProductSnapshotId,
          body: request,
        },
      );
    },
  );
}
