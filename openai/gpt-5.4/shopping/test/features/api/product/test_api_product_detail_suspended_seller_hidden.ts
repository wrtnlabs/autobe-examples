export async function test_api_product_detail_suspended_seller_hidden(
  connection: api.IConnection,
): Promise<void> {
  const publicConnection: api.IConnection = {
    host: connection.host,
    headers: connection.headers,
    simulate: connection.simulate,
    logger: connection.logger,
    encryption: connection.encryption,
    options: connection.options,
    fetch: connection.fetch,
  };
  const productId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "suspended seller product detail is hidden from public access",
    [403, 404],
    async () => {
      await api.functional.shoppingMall.products.at(publicConnection, {
        productId,
      });
    },
  );
}
