export async function test_api_product_snapshot_history_other_seller_forbidden(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = { host: connection.host };
  const ownerAuth = await authorize_seller_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(ownerAuth);
  const product =
    await generate_random_shopping_mall_seller_seller_products_create(
      ownerConnection,
      {
        body: {
          shopping_mall_category_id: null,
          name: RandomGenerator.name(),
          description: RandomGenerator.content({ paragraphs: 2 }),
          base_price: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1>
          >(),
          status: RandomGenerator.alphabets(8),
        } satisfies IShoppingMallProduct.ICreate,
      },
    );
  typia.assert(product);
  const otherSellerConnection: api.IConnection = { host: connection.host };
  const otherSellerAuth = await authorize_seller_join(otherSellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(otherSellerAuth);
  TestValidator.equals(
    "product owner matches owner seller",
    product.seller.id,
    ownerAuth.id,
  );
  TestValidator.notEquals(
    "product owner differs from requesting seller",
    product.seller.id,
    otherSellerAuth.id,
  );
  const request = {
    sort: "created_at_desc",
    page: 1,
    limit: 10,
  } satisfies IShoppingMallProductSnapshot.IRequest;
  await TestValidator.httpError(
    "other seller cannot view foreign product snapshot history",
    403,
    async () => {
      await api.functional.shoppingMall.seller.products.snapshots.index(
        otherSellerConnection,
        {
          productId: product.id,
          body: request,
        },
      );
    },
  );
}
