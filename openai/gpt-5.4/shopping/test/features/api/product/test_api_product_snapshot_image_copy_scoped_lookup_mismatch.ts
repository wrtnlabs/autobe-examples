export async function test_api_product_snapshot_image_copy_scoped_lookup_mismatch(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = {
    host: connection.host,
  };
  const administrator = await authorize_administrator_join(
    administratorConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: typia.random<string & tags.Format<"password">>(),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
      },
    },
  );
  typia.assert(administrator);
  const sellerConnection: api.IConnection = {
    host: connection.host,
  };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(seller);
  const product =
    await generate_random_shopping_mall_seller_seller_products_create(
      sellerConnection,
      {
        body: {
          name: RandomGenerator.name(),
          description: RandomGenerator.content({ paragraphs: 2 }),
          base_price: 1000,
          status: RandomGenerator.alphabets(8),
          shopping_mall_category_id: null,
        },
      },
    );
  typia.assert(product);
  const missingSnapshotId = typia.random<string & tags.Format<"uuid">>();
  const missingImageCopyId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "administrator cannot resolve image copy outside the product snapshot scope",
    async () => {
      await api.functional.shoppingMall.administrator.products.snapshots.image_copies.at(
        administratorConnection,
        {
          productId: product.id,
          productSnapshotId: missingSnapshotId,
          imageCopyId: missingImageCopyId,
        },
      );
    },
  );
}
