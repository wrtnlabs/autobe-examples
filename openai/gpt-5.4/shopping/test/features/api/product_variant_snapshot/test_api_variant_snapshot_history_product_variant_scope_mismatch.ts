export async function test_api_variant_snapshot_history_product_variant_scope_mismatch(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = {
    host: connection.host,
  };
  await authorize_administrator_join(administratorConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallAdministrator.IJoin,
  });
  const productId = typia.random<string & tags.Format<"uuid">>();
  const variantId = typia.random<string & tags.Format<"uuid">>();
  const request = {
    page: 1,
    limit: 10,
  } satisfies IShoppingMallProductVariantSnapshot.IRequest;
  await TestValidator.httpError(
    "administrator variant snapshot history rejects mismatched product and variant scope",
    [400, 404, 422],
    async () => {
      await api.functional.shoppingMall.administrator.products.variants.snapshots.index(
        administratorConnection,
        {
          productId,
          variantId,
          body: request,
        },
      );
    },
  );
}
