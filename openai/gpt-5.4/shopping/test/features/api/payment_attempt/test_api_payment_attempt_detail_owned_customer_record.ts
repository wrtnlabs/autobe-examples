export async function test_api_payment_attempt_detail_owned_customer_record(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16) satisfies string as string &
        tags.Format<"password">,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(authorized);
  await TestValidator.httpError(
    "unavailable owned payment attempt detail rejects when no creatable attempt exists",
    [403, 404],
    async () => {
      await api.functional.shoppingMall.customer.paymentAttempts.at(
        customerConnection,
        {
          paymentAttemptId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
