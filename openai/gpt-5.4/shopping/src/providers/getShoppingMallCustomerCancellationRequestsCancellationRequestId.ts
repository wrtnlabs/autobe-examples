export async function getShoppingMallCustomerCancellationRequestsCancellationRequestId(props: {
  customer: CustomerPayload;
  cancellationRequestId: string & tags.Format<"uuid">;
}): Promise<IShoppingMallCancellationRequest> {
  const cancellationRequest =
    await MyGlobal.prisma.shopping_mall_cancellation_requests.findFirstOrThrow({
      where: {
        id: props.cancellationRequestId,
        deleted_at: null,
      },
      select: {
        shopping_mall_customer_id: true,
        ...ShoppingMallCancellationRequestTransformer.select().select,
      },
    });
  if (cancellationRequest.shopping_mall_customer_id !== props.customer.id) {
    throw new HttpException("Forbidden", 403);
  }
  return await ShoppingMallCancellationRequestTransformer.transform(
    cancellationRequest,
  );
}
