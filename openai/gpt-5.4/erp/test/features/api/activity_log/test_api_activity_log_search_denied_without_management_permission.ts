export async function test_api_activity_log_search_denied_without_management_permission(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_owner_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(authorized);
  const request = {
    page: 1,
    limit: 10,
    sort: "-created_at",
  } satisfies IHrmTimeTrackingActivityLog.IRequest;
  await TestValidator.httpError(
    "activity log search is denied without management permission",
    [401, 403],
    async () => {
      await api.functional.hrmTimeTracking.owner.activityLogs.search(
        ownerConnection,
        {
          body: request,
        },
      );
    },
  );
}
