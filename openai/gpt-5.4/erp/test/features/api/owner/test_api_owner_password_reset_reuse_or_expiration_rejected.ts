import { authorize_owner_join } from "../../../authorize/authorize_owner_join";
import { authorize_owner_login } from "../../../authorize/authorize_owner_login";
import { authorize_owner_refresh } from "../../../authorize/authorize_owner_refresh";

export async function test_api_owner_password_reset_reuse_or_expiration_rejected(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = { host: connection.host };
  const owner = await authorize_owner_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IHrmTimeTrackingOwner.IJoin,
  });
  typia.assert(owner);
  const guestConnection: api.IConnection = { host: connection.host };
  const body = {
    token: RandomGenerator.alphaNumeric(32),
    password: typia.random<string & tags.Format<"password">>(),
  } satisfies IHrmTimeTrackingOwnerPasswordReset.IUpdate;
  await TestValidator.error(
    "rejects reuse or expiration attempt for unavailable reset record",
    async () => {
      await api.functional.hrmTimeTracking.owner.password_resets.update(
        guestConnection,
        {
          passwordResetId: typia.random<string & tags.Format<"uuid">>(),
          body,
        },
      );
    },
  );
}
