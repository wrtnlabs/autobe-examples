export async function test_api_timesheet_snapshot_history_organization_boundary(
  connection: api.IConnection,
): Promise<void> {
  const employeeConnection: api.IConnection = { host: connection.host };
  const employeeAuth = await authorize_employee_join(employeeConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(employeeAuth);
  const timesheet =
    await generate_random_hrm_time_tracking_employee_timesheets_create(
      employeeConnection,
      {},
    );
  typia.assert(timesheet);
  const managerConnection: api.IConnection = { host: connection.host };
  const managerAuth = await authorize_manager_join(managerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(managerAuth);
  await TestValidator.httpError(
    "manager cannot access snapshot history outside active organization scope",
    [403, 404],
    async () => {
      await api.functional.hrmTimeTracking.manager.timesheets.snapshots.index(
        managerConnection,
        {
          timesheetId: timesheet.id,
          body: {
            page: 1,
            limit: 10,
            sort: "-id",
          } satisfies IHrmTimeTrackingTimesheetSnapshot.IRequest,
        },
      );
    },
  );
}
