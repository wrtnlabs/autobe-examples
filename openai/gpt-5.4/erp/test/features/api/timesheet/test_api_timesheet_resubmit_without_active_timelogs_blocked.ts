export async function test_api_timesheet_resubmit_without_active_timelogs_blocked(
  connection: api.IConnection,
): Promise<void> {
  const employeeConnection: api.IConnection = {
    host: connection.host,
  };
  const authorized: IHrmTimeTrackingEmployee.IAuthorized =
    await authorize_employee_join(employeeConnection, {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
        ip: typia.random<string & tags.Format<"ipv4">>(),
      } satisfies IHrmTimeTrackingEmployee.IJoin,
    });
  typia.assert(authorized);
  await TestValidator.error(
    "resubmit blocked when target timesheet is unavailable for employee",
    async () => {
      await api.functional.hrmTimeTracking.employee.timesheets.resubmit(
        employeeConnection,
        {
          timesheetId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
