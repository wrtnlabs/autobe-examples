export async function test_api_timesheet_approval_locks_included_timelogs(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = { host: connection.host };
  await authorize_owner_join(ownerConnection, {});
  await TestValidator.httpError(
    "approving a non-existent timesheet fails when no submitted timesheet setup API exists",
    [404, 409, 422],
    async () => {
      await api.functional.hrmTimeTracking.owner.timesheets.approve(
        ownerConnection,
        {
          timesheetId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
