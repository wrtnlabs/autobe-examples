export async function test_api_employee_contract_history_other_organization_rejected(
  connection: api.IConnection,
): Promise<void> {
  const managerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_manager_join(managerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(authorized);
  const employeeId = typia.random<string & tags.Format<"uuid">>();
  const body = {
    page: 1,
    limit: 10,
    sort: "start_date",
    direction: "desc",
    status: "all",
  } satisfies IHrmTimeTrackingEmployeeContract.IRequest;
  await TestValidator.httpError(
    "rejects contract history access for out-of-scope employee",
    [403, 404],
    async () => {
      await api.functional.hrmTimeTracking.manager.employees.contracts.index(
        managerConnection,
        {
          employeeId,
          body,
        },
      );
    },
  );
}
