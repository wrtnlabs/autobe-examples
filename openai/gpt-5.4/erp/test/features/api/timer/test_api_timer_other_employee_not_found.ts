export async function test_api_timer_other_employee_not_found(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = { host: connection.host };
  const owner = await authorize_employee_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(owner);
  const otherEmployeeConnection: api.IConnection = { host: connection.host };
  const otherEmployee = await authorize_employee_join(otherEmployeeConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(otherEmployee);
  const timerId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "other employee cannot read inaccessible timer as not found",
    404,
    async () => {
      await api.functional.hrmTimeTracking.employee.timers.at(
        otherEmployeeConnection,
        { timerId },
      );
    },
  );
}
