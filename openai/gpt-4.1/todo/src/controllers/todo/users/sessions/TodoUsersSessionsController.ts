import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoUsersUserIdSessions } from "../../../../providers/patchTodoUsersUserIdSessions";
import { getTodoUsersUserIdSessionsSessionId } from "../../../../providers/getTodoUsersUserIdSessionsSessionId";

import { IPageITodoUserSession } from "../../../../api/structures/IPageITodoUserSession";
import { ITodoUserSession } from "../../../../api/structures/ITodoUserSession";

@Controller("/todo/users/:userId/sessions")
export class TodoUsersSessionsController {
  /**
   * List and search all sessions for a given user (todo_user_sessions table,
   * public view).
   *
   * Retrieve a paginated, filterable list of authentication sessions associated
   * with the specified user in the Todo List application.
   *
   * This operation provides support for investigating account activity,
   * tracking abnormal login patterns, or reviewing system security posture. The
   * response includes session metadata such as login IP, HTTP referrer, and
   * session initiation URL, which enables complete traceability per privacy and
   * audit requirements. The API provides robust query capabilities, allowing
   * session lookups based on time created, expiration status, or other
   * attributes.
   *
   * All data returned is sourced directly from the todo_user_sessions table,
   * whose schema includes strong guarantees on audit trace completeness.
   * Attempts to access this endpoint rely on business-specific design; generic
   * read-only session data is not privileged. No session manipulation
   * (creation, update, revocation) is supported. Similar endpoints include GET
   * /users/{userId}/sessions/{sessionId} for per-session detail, but this is
   * the list/index operation for review across multiple sessions.
   *
   * @param connection
   * @param userId Unique identifier of the target user whose sessions will be
   *   listed
   * @param body Session search filters and pagination configuration for the
   *   index operation. Queries may specify time range, status, and sort
   *   options.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoUserSession.IRequest,
  ): Promise<IPageITodoUserSession.ISummary> {
    try {
      return await patchTodoUsersUserIdSessions({
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * View full details of a specific session for a user (todo_user_sessions
   * table, public view).
   *
   * Fetch the complete metadata and audit information for an individual
   * authentication session for a given user in the Todo application.
   *
   * This endpoint is for audit or review purposes and displays all data stored
   * in the todo_user_sessions table for the specific login session identified
   * by both userId and sessionId. Returned data includes origin IP address,
   * referer URL, session creation and expiration information, all as required
   * for system compliance.
   *
   * System returns data traceable to the owning user (todo_users). If the
   * specified session does not exist or is not linked to the given user, a
   * not-found or permission-denied error is triggered. This API never exposes
   * session tokens/credentials and does not allow session deletion or updates.
   * For bulk session review, PATCH /users/{userId}/sessions should be used.
   *
   * @param connection
   * @param userId Unique identifier of the user owning the session
   * @param sessionId Unique session record identifier (UUID) within the
   *   todo_user_sessions table
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoUserSession> {
    try {
      return await getTodoUsersUserIdSessionsSessionId({
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
