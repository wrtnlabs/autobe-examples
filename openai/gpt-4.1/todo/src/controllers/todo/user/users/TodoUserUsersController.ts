import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoUserUsers } from "../../../../providers/patchTodoUserUsers";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoUserUsersUserId } from "../../../../providers/getTodoUserUsersUserId";
import { putTodoUserUsersUserId } from "../../../../providers/putTodoUserUsersUserId";
import { deleteTodoUserUsersUserId } from "../../../../providers/deleteTodoUserUsersUserId";

import { IPageITodoUser } from "../../../../api/structures/IPageITodoUser";
import { ITodoUser } from "../../../../api/structures/ITodoUser";

@Controller("/todo/user/users")
export class TodoUserUsersController {
  /**
   * Search and retrieve a filtered, paginated list of user accounts
   * (todo_users).
   *
   * Retrieve a paginated and filtered list of user accounts in the system.
   *
   * This operation returns user summary information such as unique identifier
   * and email. Filtering and searching are primarily used internally, as each
   * user can only access their own account due to strict access controls
   * described in the functional requirements and enforced by the underlying
   * Prisma schema. The purpose is to allow queries like self-profile viewing or
   * email existence checks, not global user enumeration.
   *
   * Security is paramount: only the authenticated user can see their own
   * information—no user can see others' data. The operation enforces this by
   * requiring the session's userId to match the returned entity. Fields in the
   * response conform to the todo_users schema, ensuring consistency and
   * reliability. Invalid or unauthenticated requests will result in
   * authentication or validation errors per error-handling requirements.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering user
   *   accounts. Used for querying own account or implementing self-service
   *   queries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUser.IRequest,
  ): Promise<IPageITodoUser.ISummary> {
    try {
      return await patchTodoUserUsers({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detail information for a user account (todo_users) by userId.
   *
   * Retrieve detailed information for a specific user account by ID.
   *
   * This operation enables a user to fetch their own profile data using their
   * unique userId. Access is strictly limited: authenticated users can only
   * request their own information, and the system rigorously enforces this via
   * ID/user session matching and validation logic.
   *
   * The returned data structure aligns exactly with the todo_users schema,
   * providing all relevant metadata regarding the user's account and supporting
   * robust client-side profile management. Unauthorized or out-of-scope access
   * attempts are blocked and logged in accordance with system security
   * requirements.
   *
   * @param connection
   * @param userId Unique identifier of the target user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoUser> {
    try {
      return await getTodoUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a todo user’s account (todo_users table).
   *
   * Update the account information for a specific user in the Todo List
   * application.
   *
   * This endpoint enables changes to the user's email address or password,
   * provided the correct user identifier is supplied. The operation enforces
   * strong data validation: email addresses must be unique, and password
   * updates require a secure hash format, as outlined in the underlying Prisma
   * schema's field descriptions. Both successful and failed update attempts are
   * accurately timestamped for auditability via the user's updated_at column.
   *
   * Security is critical: only authenticated users are permitted to update
   * their own account, and all sensitive operations (especially password
   * changes) require re-authentication with the valid current password or a
   * secure session. Implementation must guard against privilege escalation and
   * prevent modification of other users' records.
   *
   * The request body is validated for syntactic correctness (email format,
   * password strength, and compliance with application constraints). Unknown or
   * extra fields are disregarded. Any update triggers a refresh of the
   * updated_at timestamp and ensures the system’s integrity is maintained
   * throughout the process.
   *
   * @param connection
   * @param userId Unique identifier of the target user account to update.
   * @param body Data to update the user account, such as new email or password
   *   hash.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoUser.IUpdate,
  ): Promise<ITodoUser> {
    try {
      return await putTodoUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a todo user account (todo_users table).
   *
   * Delete the specified user account from the Todo List application.
   *
   * When this operation is invoked, the identified user’s record is immediately
   * removed from the database, following cascading delete behavior as described
   * in the prisma schema documentation. This ensures that all sessions, todos,
   * and related user-specific records are also removed for compliance and
   * privacy purposes.
   *
   * Only an authenticated user may delete their own account. Access controls
   * must prevent users from deleting accounts that do not belong to them. The
   * operation is designed to preserve system integrity and guarantee that no
   * residual personal data remains after a user-initiated account removal.
   *
   * @param connection
   * @param userId Unique identifier of the user account to delete.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoUser> {
    try {
      return await deleteTodoUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
