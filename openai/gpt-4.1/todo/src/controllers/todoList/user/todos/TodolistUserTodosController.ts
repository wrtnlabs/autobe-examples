import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoListUserTodos } from "../../../../providers/postTodoListUserTodos";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoListUserTodos } from "../../../../providers/patchTodoListUserTodos";
import { getTodoListUserTodosTodoId } from "../../../../providers/getTodoListUserTodosTodoId";
import { putTodoListUserTodosTodoId } from "../../../../providers/putTodoListUserTodosTodoId";
import { deleteTodoListUserTodosTodoId } from "../../../../providers/deleteTodoListUserTodosTodoId";

import { ITodoListTodo } from "../../../../api/structures/ITodoListTodo";
import { IPageITodoListTodo } from "../../../../api/structures/IPageITodoListTodo";

@Controller("/todoList/user/todos")
export class TodolistUserTodosController {
  /**
   * Create a new todo item (todo_list_todos table).
   *
   * This API endpoint enables an authenticated user to create a new todo item
   * in their own task list. The primary use is to record actionable tasks and
   * reminders that are unique to the owning user. Only the authenticated user
   * may create tasks for themselves—no cross-user or shared creation is
   * supported for data privacy and boundary enforcement.
   *
   * The operation will validate that the title is provided, non-empty, and does
   * not exceed 100 characters. Uniqueness of the title is enforced within the
   * user's own todos, preventing accidental duplication but allowing other
   * users to use the same title independently. Optional description text, if
   * present, must also adhere to a 1000-character limit. The status is
   * initially set as 'incomplete', and timestamps for creation and update are
   * automatically generated server-side. The task becomes visible only to its
   * creator.
   *
   * If a creation attempt violates uniqueness or field length constraints, the
   * API returns descriptive error messages. Successful creation returns the
   * fully detailed todo item, including metadata such as timestamps and current
   * status. This operation integrates tightly with the todo_list_todos schema
   * as documented in the database.
   *
   * @param connection
   * @param body Payload for creating a new todo item. Must include a
   *   user-unique title and may contain an optional description.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.ICreate,
  ): Promise<ITodoListTodo> {
    try {
      return await postTodoListUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and paginate the authenticated user's todo items with advanced
   * filters.
   *
   * Retrieve a filtered and paginated list of personal todo items for the
   * current user. The operation supports advanced search queries including
   * keyword search of the task name or description, status filtering (completed
   * or not), filtering by date and other relevant constraints supported by the
   * database schema.
   *
   * The request supports pagination with standard page and page size
   * parameters, as well as sorting by task due date and/or creation order.
   * Results include todo summary data for each item, optimized for list
   * rendering. All filtering and query logic is enforced server-side, so only
   * matching items are returned to the requesting user based on their session.
   *
   * Security is enforced by limiting results to todos owned by the
   * authenticated user, and rate limiting protects against abusive list
   * queries. Only todos belonging to the requester are shown. Related endpoints
   * are available for viewing details and modifying tasks.
   *
   * @param connection
   * @param body Query filters, pagination, and sorting options for listing the
   *   authenticated user's todos.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.IRequest,
  ): Promise<IPageITodoListTodo.ISummary> {
    try {
      return await patchTodoListUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details for one of the authenticated user's todos by ID.
   *
   * Retrieve the full details of a single todo item by its unique identifier.
   * The operation provides the complete task information for the authenticated
   * user, such as task name, description, status, due date, and timestamps,
   * reflecting the exact entity as stored in the database.
   *
   * This endpoint requires the user to specify the todoId path parameter, which
   * uniquely identifies the user's own task. If the todo belonging to the user
   * is not found, an error is returned. Security checks enforce that users can
   * only view their own tasks, with access denied for unauthorized requests.
   *
   * This operation is associated with the inspection of a single todo entity
   * for user review or client detail display. It is commonly paired with search
   * and modify endpoints for full task management functionality.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item to retrieve for the
   *   current user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string,
  ): Promise<ITodoListTodo> {
    try {
      return await getTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo item (todo_list_todos table) by id.
   *
   * This API endpoint allows an authenticated user to update their own todo
   * item. The primary goal is to let users edit details of their tasks such as
   * the title, description, or completion state. Every update operation is
   * strictly validated for user ownership, ensuring data privacy and
   * security—only the owner can change their own records.
   *
   * Title edits must remain non-empty, within 100-character limits, and unique
   * for the current user. Description, if supplied, is subject to the same
   * 1000-character limit as during creation. Status transitions are validated
   * to ensure logical consistency: changing from 'incomplete' to 'complete'
   * sets the completion timestamp; reverting the status clears it. The
   * 'updated_at' timestamp is modified on every update to ensure full
   * auditability.
   *
   * Any attempt to update a todo owned by another user, violate length
   * constraints, or duplicate a title within the user's set will generate clear
   * failure responses. The updated todo item is returned in full, reflecting
   * all modifications and current state. Integration is tightly bound to the
   * todo_list_todos model and its business requirements.
   *
   * @param connection
   * @param todoId Unique identifier (UUID) of the todo item to update, owned by
   *   the authenticated user.
   * @param body Payload for updating an existing todo item. Fields may include
   *   title, description, and/or status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListTodo.IUpdate,
  ): Promise<ITodoListTodo> {
    try {
      return await putTodoListUserTodosTodoId({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a single todo item from the todo_list_todos table.
   *
   * Permanently remove an individual todo item owned by the authenticated user.
   * This operation is intended for situations where a user wishes to eliminate
   * a completed or obsolete task from their personal todo list, as managed in
   * the 'todo_list_todos' table.
   *
   * The endpoint accepts the todo identifier as a required path parameter.
   * Prior to deletion, the backend confirms that the caller is both
   * authenticated and the registered owner of the task, as mandated by the
   * foreign key constraint to user accounts. All deletion requests targeting
   * tasks not belonging to the user are automatically rejected, upholding
   * strict partitioning and privacy.
   *
   * Deletion is irreversible—unlike soft deletion, no recovery or restoration
   * is possible after this operation. Security policies enforce that only the
   * authenticated task owner may initiate deletion. Attempts to delete
   * already-removed or non-existent todos will return an appropriate error.
   * Related operations include create (POST /todos), update (PUT
   * /todos/{todoId}), and query (GET/PATCH methods on todos).
   *
   * @param connection
   * @param todoId Unique identifier of the todo item to delete (UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
