import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListUserUsers } from "../../../../providers/patchTodoListUserUsers";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoListUserUsersEmail } from "../../../../providers/getTodoListUserUsersEmail";
import { putTodoListUserUsersEmail } from "../../../../providers/putTodoListUserUsersEmail";
import { deleteTodoListUserUsersEmail } from "../../../../providers/deleteTodoListUserUsersEmail";

import { IPageITodoListUser } from "../../../../api/structures/IPageITodoListUser";
import { ITodoListUser } from "../../../../api/structures/ITodoListUser";

@Controller("/todoList/user/users")
export class TodolistUserUsersController {
  /**
   * Retrieve a filtered and paginated list of registered user accounts in the
   * Todo List service.
   *
   * This operation allows authenticated users to search for users based on
   * supported criteria, with the ability to paginate results, apply filters,
   * and sort by relevant user fields. It is implemented to support large user
   * lists, enabling efficient management and auditing functions.
   *
   * The endpoint supports secure access limited to authenticated users, and all
   * returned data should comply with access controls defined in requirements
   * and schema. Related endpoints allow qualified users to view details of a
   * specific user by email.
   *
   * @param connection
   * @param body Search and pagination parameters for user filtering.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.IRequest,
  ): Promise<IPageITodoListUser.ISummary> {
    try {
      return await patchTodoListUserUsers({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific registered user in the Todo
   * List service, identified by their email address.
   *
   * This operation is intended for use by authenticated users and enables user
   * lookup, display cases, and support handling. It returns all available user
   * fields, subject to any access-control rules defined in requirements or
   * schema.
   *
   * No user-editing or sensitive system-controlled fields are exposed or
   * modifiable, ensuring robust security and privacy best practices. Related
   * operations include user search (PATCH /users) and other account or display
   * tools.
   *
   * @param connection
   * @param email Unique email address of the registered user (global scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":email")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("email")
    email: string & tags.Format<"email">,
  ): Promise<ITodoListUser> {
    try {
      return await getTodoListUserUsersEmail({
        user,
        email,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a Todo List user account by specifying the user's unique email
   * address and providing new values for updatable fields.
   *
   * Only authenticated users are permitted to update their own credentials. The
   * update payload is restricted to password changes—email is immutable to
   * ensure persistence of the user's identity for business logic and audit
   * purposes. The system hashes the new password before storing it.
   *
   * Ownership and authentication are rigidly enforced: a user must provide a
   * valid session token, and attempts to update other users' accounts result in
   * an authorization error. The updatedAt field is set by the system
   * automatically upon successful update, while createdAt remains unchanged.
   *
   * If the specified email does not match an existing user, or if authorization
   * fails, the operation returns an error in natural language. Related
   * operations include self-profile retrieval (GET /users/{email}), account
   * deletion (DELETE /users/{email}), and Todo management operations
   * (restricted to the authenticated user).
   *
   * @param connection
   * @param email Globally unique email address of the user (serves as the
   *   user's business identifier for account access; must already exist).
   * @param body Updated user information. Only password is updatable; email is
   *   immutable.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":email")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("email")
    email: string & tags.Format<"email">,
    @TypedBody()
    body: ITodoListUser.IUpdate,
  ): Promise<ITodoListUser> {
    try {
      return await putTodoListUserUsersEmail({
        user,
        email,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a user account from the Todo List service by specifying
   * the unique, registered email address of the account. This operation is
   * available only to the authenticated owner of the corresponding user account
   * and requires a valid session token for authorization.
   *
   * Upon successful request, the system removes all user-specific
   * data—including the user record and all associated Todos—without recovery or
   * backup, in accordance with strict privacy requirements. The process is
   * non-reversible, and all access tokens and sessions for the user are
   * immediately invalidated.
   *
   * Authorization failures, attempts to delete other users' accounts, or
   * requests with non-existent email addresses result in a natural language
   * error response explicitly stating the cause. This operation complements
   * other self-service account features such as password reset (external to
   * this system) and Todo management (for the authenticated user only).
   *
   * @param connection
   * @param email Globally unique email address of the user to be deleted.
   *   Identifies which account and associated data to remove permanently.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":email")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("email")
    email: string & tags.Format<"email">,
  ): Promise<void> {
    try {
      return await deleteTodoListUserUsersEmail({
        user,
        email,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
