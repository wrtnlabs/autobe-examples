import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListUserUsers } from "../../../../providers/patchTodoListUserUsers";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoListUserUsersUserId } from "../../../../providers/getTodoListUserUsersUserId";
import { putTodoListUserUsersUserId } from "../../../../providers/putTodoListUserUsersUserId";
import { deleteTodoListUserUsersUserId } from "../../../../providers/deleteTodoListUserUsersUserId";

import { IPageITodoListUser } from "../../../../api/structures/IPageITodoListUser";
import { ITodoListUser } from "../../../../api/structures/ITodoListUser";

@Controller("/todoList/user/users")
export class TodolistUserUsersController {
  /**
   * Retrieve a paginated and filterable list of user accounts from the
   * todo_list_users table.
   *
   * Fetch a filtered and paginated list of all registered user accounts in the
   * Todo List system.
   *
   * This operation is intended for administrative use only. It exposes user
   * emails and identity fields solely for security auditing, investigating
   * registration issues, or for compliance with business reporting
   * requirements. This endpoint never exposes password hashes or sensitive
   * authentication materials in the response; such details are strictly
   * internal.
   *
   * Filtering, pagination, and future extensibility for searching by various
   * criteria are supported by request body parameters. The underlying table
   * enforces uniqueness on the email field, assuring that all users listed are
   * uniquely identified. As per the data minimization requirement, the fields
   * returned include only email and minimally necessary identity details. No
   * profile, role, or irreversibly deleted accounts are involved, per the
   * schema and business policy.
   *
   * All usage is strictly governed by strong authentication and authorization
   * policies, and only system administrators have access to this data. Common
   * uses include reviewing system registrations, identifying duplicate or
   * fraudulent emails, and compliance reporting.
   *
   * @param connection
   * @param body Optional search and pagination parameters for user list
   *   retrieval.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.IRequest,
  ): Promise<IPageITodoListUser.ISummary> {
    try {
      return await patchTodoListUserUsers({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve non-sensitive details of a single user from the todo_list_users
   * table by unique ID.
   *
   * Fetch non-sensitive detail for a specific registered user account,
   * identified by unique system ID.
   *
   * This administrative endpoint is used for investigation, compliance, or
   * technical debugging. The only data accessible are minimal user account
   * identifiers (such as email); password hashes are never provided. The
   * 'userId' parameter matches the primary key in the todo_list_users table.
   *
   * All user account access is tightly governed by authentication and
   * authorization checks: only system administrators are permitted to view user
   * account records. This operation is never exposed to end-users or used for
   * self-service, authentication, or registration workflows. All requested
   * information must be in compliance with the data minimization and hard
   * deletion business policy.
   *
   * @param connection
   * @param userId Unique identifier of the target user account (UUID primary
   *   key in todo_list_users).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUser> {
    try {
      return await getTodoListUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing Todo List user account by userId (todo_list_users
   * table).
   *
   * Update the details for a single Todo List user account as identified by
   * their unique userId.
   *
   * This API operation allows modification of user-specific properties
   * including email and password. The input requires the full payload of
   * mutable fields in the user table. Security best practices mandate that
   * emails remain unique within the system and password hashes are never stored
   * in plaintext. All write actions are immediately committed to the database,
   * as there is no support for soft deletion or audit trails.
   *
   * This endpoint is protected: only the authenticated user may update their
   * own account. Updates to the user account do not affect any user-created
   * todos or other records, but maintaining an up-to-date email ensures
   * continued access and notifications. Any attempt to update non-existent
   * fields or protected properties will result in a validation error. All
   * updates trigger a full validation and the updated user record is returned
   * on success.
   *
   * @param connection
   * @param userId Unique identifier of the target user account
   * @param body Updated data for the user account, such as a new email or
   *   password hash. Must comply with all validation rules and uniqueness
   *   constraints.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUser.IUpdate,
  ): Promise<ITodoListUser> {
    try {
      return await putTodoListUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a Todo List user account by userId (todo_list_users
   * table).
   *
   * Permanently remove a Todo List user account as specified by the userId.
   * This operation enforces the policy that all account deletions are hard
   * deletes: once a user is deleted, all credentials and personal data are
   * removed and cannot be recovered. No soft delete or retention period is
   * implemented in this application.
   *
   * The endpoint is strictly protected so that only the account owner may
   * delete their own record. Cascading effects are limited; todos previously
   * owned by the deleted user may remain in the system as orphaned records or
   * will be subject to hard deletion by related business rules, depending on
   * foreign key constraints. Data minimization requirements are enforced to
   * prevent retention of any personal information after deletion. Improper
   * requests or missing records result in error responses.
   *
   * @param connection
   * @param userId Unique identifier of the target user account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
