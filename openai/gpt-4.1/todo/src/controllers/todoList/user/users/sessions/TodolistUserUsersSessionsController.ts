import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteTodoListUserUsersEmailSessionsSessionId } from "../../../../../providers/deleteTodoListUserUsersEmailSessionsSessionId";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

@Controller("/todoList/user/users/:email/sessions/:sessionId")
export class TodolistUserUsersSessionsController {
  /**
   * Delete a specific user session from the todo_list_user_sessions table by
   * email and sessionId with full ownership enforcement.
   *
   * This endpoint allows an authenticated user to permanently delete
   * (invalidate) one of their own active or expired sessions using the
   * sessionId and their registered email. The operation irrevocably removes the
   * session from the database, preventing further use of associated tokens and
   * enforcing strict account security.
   *
   * Ownership checks guarantee users may not delete sessions associated with
   * any other email. All security and access validations are performed before
   * deletion; failure in any check results in denial and an appropriate error.
   *
   * This operation references the todo_list_user_sessions model and its
   * relationship to todo_list_users. No soft delete or recovery is possible;
   * once removed, the session cannot be referenced or re-activated. Used for
   * both voluntary logout (of another device) and in response to detected
   * suspicious activity.
   *
   * @param connection
   * @param email Globally unique, verified email address of the user who owns
   *   the session (global scope).
   * @param sessionId Globally unique session identifier to be deleted,
   *   associated with the user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("email")
    email: string,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListUserUsersEmailSessionsSessionId({
        user,
        email,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
