import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListUsersUserIdSessions } from "../../../../providers/patchTodoListUsersUserIdSessions";
import { getTodoListUsersUserIdSessionsSessionId } from "../../../../providers/getTodoListUsersUserIdSessionsSessionId";

import { IPageITodoListUserSession } from "../../../../api/structures/IPageITodoListUserSession";
import { ITodoListUserSession } from "../../../../api/structures/ITodoListUserSession";

@Controller("/todoList/users/:userId/sessions")
export class TodolistUsersSessionsController {
  /**
   * Search and retrieve a filtered, paginated list of user sessions
   * (todo_list_user_sessions) for a specific user account.
   *
   * Obtain a complete login and session activity history for a specific user by
   * searching and filtering their todo_list_user_sessions records. This
   * endpoint supports complex queries with pagination, sorting, creation date
   * filtering, and IP-based lookup, giving detailed insight into the user's
   * recent and historical authentication events.
   *
   * Authorization is restricted by system configuration; due to constraints
   * only the "user" actor is available, so this endpoint is set as public (no
   * explicit actor). Session records include information such as session
   * initiation time, expiration or revocation time, source IP, user
   * agent/referrer, and associated user ID. This API is strictly read-only for
   * analysis, and session creation or deletion is handled through the
   * authentication subsystem, not this endpoint.
   *
   * This operation reflects the subsidiary nature of the
   * todo_list_user_sessions table, which does not support independent creation
   * or manual deletion of sessions. Modifications and new sessions are managed
   * exclusively through the authentication subsystem, so this API is strictly
   * read-only.
   *
   * @param connection
   * @param userId Unique identifier (UUID) of the user whose sessions are being
   *   queried.
   * @param body Search criteria and pagination parameters for advanced session
   *   filtering, sorting, and retrieval for the selected user ID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUserSession.IRequest,
  ): Promise<IPageITodoListUserSession.ISummary> {
    try {
      return await patchTodoListUsersUserIdSessions({
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific user session
   * (todo_list_user_sessions) by sessionId for the specified userId.
   *
   * Fetch all field details for a single user session, including activity
   * timestamp, IP, login context, and expiration or revocation status. This
   * endpoint is designed for audit and forensic analysis, supporting full
   * field-level data extraction for a single session instance. The API loads
   * the session record, validates user-session linkage, and exposes all related
   * audit fields according to the session schema. This is a read-only
   * operation: session creation, modification, and deletion must be handled
   * through the authentication system, not this endpoint.
   *
   * @param connection
   * @param userId Unique identifier (UUID) of the user who owns the session.
   * @param sessionId Unique identifier (UUID) of the session to retrieve
   *   details for.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListUsersUserIdSessionsSessionId({
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
