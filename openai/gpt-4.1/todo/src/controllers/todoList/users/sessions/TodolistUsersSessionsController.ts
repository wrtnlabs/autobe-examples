import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListUsersEmailSessions } from "../../../../providers/patchTodoListUsersEmailSessions";
import { getTodoListUsersEmailSessionsSessionId } from "../../../../providers/getTodoListUsersEmailSessionsSessionId";

import { IPageITodoListUserSession } from "../../../../api/structures/IPageITodoListUserSession";
import { ITodoListUserSession } from "../../../../api/structures/ITodoListUserSession";

@Controller("/todoList/users/:email/sessions")
export class TodolistUsersSessionsController {
  /**
   * Retrieve all session records for a user by unique email from
   * todo_list_user_sessions table.
   *
   * Fetch a paginated collection of user session records for the specified Todo
   * List user, using their global email address as a unique identifier.
   *
   * This endpoint is designed for system administrators and security personnel
   * to trace session activity for a particular user account. Each session
   * record includes metadata such as IP address, originating URL, referrer,
   * session creation timestamp, and expiry state. This operation can be used
   * for regulatory compliance, security incident response, or reviewing
   * concurrent device usage by a single user.
   *
   * The endpoint operates in accordance with the strict privacy and isolation
   * guarantees enforced by the todo_list_users schema. Only administrators are
   * permitted to access detailed session records, and no sensitive
   * authentication token material is ever returned. Pagination and filtering
   * are supported in the request body for large user histories. Record
   * retrieval is sorted by session creation time, with most recent logins
   * first.
   *
   * @param connection
   * @param email User email address serving as globally unique identifier for
   *   the Todo List account (global scope).
   * @param body Request body specifying session filtering, pagination, and
   *   sorting criteria for session search.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("email")
    email: string,
    @TypedBody()
    body: ITodoListUserSession.IRequest,
  ): Promise<IPageITodoListUserSession.ISummary> {
    try {
      return await patchTodoListUsersEmailSessions({
        email,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a user session by email and sessionId from
   * todo_list_user_sessions table.
   *
   * Fetch full details for a single authenticated user session record from the
   * todo_list_user_sessions table. Both the user's globally unique email and
   * the session's unique ID (UUID) must be specified to identify the target
   * session entry.
   *
   * The returned data includes session metadata: originating IP address,
   * connection URL and referrer, session creation timestamp, and expiration
   * state. No sensitive authentication material or personal Todo data is ever
   * exposed via this endpoint.
   *
   * This endpoint is intended for system administrators performing session
   * audits or advanced troubleshooting. Access is strictly limited to users
   * with administrative privileges. Checks that the specified email corresponds
   * to an existing user account and that the sessionId is valid and associated
   * with that user. Error responses are provided if either does not match.
   *
   * @param connection
   * @param email Globally unique email address of the user account (global
   *   scope).
   * @param sessionId Globally unique identifier of the user session (UUID;
   *   scoped to email).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @TypedParam("email")
    email: string,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListUsersEmailSessionsSessionId({
        email,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
