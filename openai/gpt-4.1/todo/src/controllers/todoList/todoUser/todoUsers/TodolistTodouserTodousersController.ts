import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoListTodoUserTodoUsersTodoUserId } from "../../../../providers/getTodoListTodoUserTodoUsersTodoUserId";
import { TodouserAuth } from "../../../../decorators/TodouserAuth";
import { TodouserPayload } from "../../../../decorators/payload/TodouserPayload";
import { putTodoListTodoUserTodoUsersTodoUserId } from "../../../../providers/putTodoListTodoUserTodoUsersTodoUserId";
import { deleteTodoListTodoUserTodoUsersTodoUserId } from "../../../../providers/deleteTodoListTodoUserTodoUsersTodoUserId";

import { ITodoListTodouser } from "../../../../api/structures/ITodoListTodouser";

@Controller("/todoList/todoUser/todoUsers/:todoUserId")
export class TodolistTodouserTodousersController {
  /**
   * Retrieve the profile of an authenticated todo user by ID from the
   * todo_list_todousers table.
   *
   * Retrieve the profile information of a todoUser using their unique
   * identifier. This operation ensures that only the authenticated user can
   * access their own profile data. Multiple business and privacy rules apply:
   * the requesting user must be authenticated, and the todoUserId path
   * parameter must match their own ID.
   *
   * Returned information includes id, email, created_at, and updated_at fields.
   * Sensitive attributes like password_hash are excluded from the response for
   * security. If a user requests information for an ID that does not exist or
   * that does not belong to them, access is denied and no data is returned.
   * Error handling addresses cases of unauthorized access and non-existent
   * users, returning appropriate business errors without leaking sensitive
   * data.
   *
   * @param connection
   * @param todoUserId Unique identifier of the target todo user account (UUID,
   *   global scope). This must match the authenticated user's ID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TodouserAuth()
    todoUser: TodouserPayload,
    @TypedParam("todoUserId")
    todoUserId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodouser> {
    try {
      return await getTodoListTodoUserTodoUsersTodoUserId({
        todoUser,
        todoUserId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update email or password for the authenticated todo user in the
   * todo_list_todousers table.
   *
   * Update the profile information for the currently authenticated todoUser.
   * This operation supports modification of the user's email and/or password,
   * requiring input validation for uniqueness and format. Only the
   * authenticated user can invoke this action for their own profile, enforced
   * strictly by matching the todoUserId parameter.
   *
   * Email changes are subject to uniqueness checks: if the new email is already
   * registered by another user, the update is rejected with a business error.
   * Password updates require submission of a valid, secure password hash rather
   * than plaintext. The system does not return sensitive values such as
   * password_hash. The updated_at field is always updated automatically upon
   * successful modification. Any attempt to update another user's account, to
   * use an invalid ID, or to violate unique/format constraints results in
   * business errors.
   *
   * @param connection
   * @param todoUserId Unique identifier of the target todo user account (UUID,
   *   global scope). This must match the authenticated user's ID.
   * @param body Fields for updating the todo user's email and/or password.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @TodouserAuth()
    todoUser: TodouserPayload,
    @TypedParam("todoUserId")
    todoUserId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListTodouser.IUpdate,
  ): Promise<ITodoListTodouser> {
    try {
      return await putTodoListTodoUserTodoUsersTodoUserId({
        todoUser,
        todoUserId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete an authenticated todoUser account and all related data
   * from todo_list_todousers table.
   *
   * This operation permanently removes the authenticated user's account and all
   * associated records from the todo_list_todousers table in the database. All
   * session records (todo_list_todouser_sessions) and todos (todo_list_todos)
   * owned by this user are also deleted via relational cascade, guaranteeing
   * complete erasure of all private data upon account deletion.
   *
   * Only the authenticated user may perform this deletion operation, enforced
   * with strict ownership checks at the business logic layer. If a user
   * attempts to delete another user's account or submits an invalid user ID,
   * the system will return a business-level error and will not leak any
   * information about account existence or structure.
   *
   * Once performed, the deletion is irreversible and data cannot be restored.
   * This operation aligns with all privacy, security, and data retention
   * business rules specified for the todo list application.
   *
   * @param connection
   * @param todoUserId Unique identifier of the target authenticated todoUser
   *   account (must match the requesting user's id).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @TodouserAuth()
    todoUser: TodouserPayload,
    @TypedParam("todoUserId")
    todoUserId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListTodoUserTodoUsersTodoUserId({
        todoUser,
        todoUserId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
