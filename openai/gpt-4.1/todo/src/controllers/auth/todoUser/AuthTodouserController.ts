import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthTodoUserJoin } from "../../../providers/postAuthTodoUserJoin";
import { postAuthTodoUserLogin } from "../../../providers/postAuthTodoUserLogin";
import { postAuthTodoUserRefresh } from "../../../providers/postAuthTodoUserRefresh";

import { ITodoListTodouser } from "../../../api/structures/ITodoListTodouser";

@Controller("/auth/todoUser")
export class AuthTodouserController {
  /**
   * Registers a new todoUser in the 'todo_list_todousers' table, initializing
   * credentials and profile audit fields.
   *
   * This registration endpoint allows a prospective todoUser to create a new
   * account by supplying a unique email and a password. The Prisma schema
   * 'todo_list_todousers' guarantees email uniqueness and enforces secure
   * credential storage by requiring a 'password_hash' field. Registration data
   * must include the email and password, with the password processed into a
   * secure hash. On success, the new user's 'id', creation timestamp
   * ('created_at'), and update timestamp ('updated_at') are system-assigned,
   * providing a reliable audit record. The request fails if the email already
   * exists, reflecting the Prisma '@@unique([email])' constraint. This
   * operation is essential for initializing authenticated sessions and serves
   * as the entry point for all user-specific business logic. Security is
   * paramount; passwords are never stored or transmitted in plaintext, and
   * comprehensive validation is strictly enforced. The join operation is
   * closely related to 'login' and 'refresh', which together implement the full
   * authentication lifecycle for todoUsers. All field-level behavior described
   * here directly references the schema's comments and enforced constraints.
   *
   * @param connection
   * @param body Email and password to register a new todoUser (will be hashed
   *   for storage).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListTodouser.IVerifyJoin,
  ): Promise<ITodoListTodouser.IAuthorized> {
    try {
      return await postAuthTodoUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates a todoUser against email/password in 'todo_list_todousers',
   * and establishes a session in 'todo_list_todouser_sessions'.
   *
   * This login API authenticates a todoUser by verifying their email and
   * password, directly referencing the 'email' and 'password_hash' columns of
   * 'todo_list_todousers'. On successful authentication, the service generates
   * access and refresh JWT tokens, sets up a new session in
   * 'todo_list_todouser_sessions' capturing audit metadata like IP and referer,
   * and ensures all logic aligns with schema constraints. Passwords are
   * processed as secure hashes, and no plaintext credentials ever leave the
   * service boundary. Authentication is strictly validated: emails must exist
   * and passwords must match the stored hash, per schema documentation. Failed
   * authentication can be rate-limited using session audit trails. This
   * operation is central to all further authenticated operations—only users
   * with valid sessions, as established here, can later refresh tokens or
   * access user-specific APIs. The login function is directly paired with
   * registration ('join') and token renewal ('refresh'), collectively providing
   * a complete secure authentication workflow. Schema-driven validation
   * enforces robust security and integrity at every step.
   *
   * @param connection
   * @param body Email and password for sign-in (password will be securely
   *   checked with password_hash).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListTodouser.IVerifyLogin,
  ): Promise<ITodoListTodouser.IAuthorized> {
    try {
      return await postAuthTodoUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes JWT tokens for an active todoUser session, validating
   * 'expired_at' in 'todo_list_todouser_sessions'.
   *
   * This token refresh operation enables a todoUser to obtain new access and
   * refresh JWT tokens by submitting a valid, non-expired refresh token. The
   * endpoint uses the 'todo_list_todouser_sessions' 'expired_at' field to check
   * session validity, ensuring that only active sessions can be renewed. Tokens
   * are tightly linked to the owning user and session record via the Prisma
   * foreign key 'todo_list_todouser_id'. A refreshed session entry is created
   * if eligible, capturing audit details. Invalid, expired, or previously
   * revoked refresh tokens are rejected, in strict accordance with the session
   * management business rules and schema documentation. The operation directly
   * implements all refresh logic described in the system authentication
   * requirements, providing secure, closely-audited token lifecycle management
   * based entirely on the relationships and fields in the session schema. It is
   * fundamental to enforcing secure session lifecycles, complementing login and
   * join operations.
   *
   * @param connection
   * @param body Refresh token (and relevant session metadata) to renew
   *   authentication for todoUser.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListTodouser.IVerifyRefresh,
  ): Promise<ITodoListTodouser.IAuthorized> {
    try {
      return await postAuthTodoUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
