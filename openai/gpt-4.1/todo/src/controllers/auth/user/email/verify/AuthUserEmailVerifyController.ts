import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserEmailVerify } from "../../../../../providers/postAuthUserEmailVerify";

import { ITodoListUser } from "../../../../../api/structures/ITodoListUser";

@Controller("/auth/user/email/verify")
export class AuthUserEmailVerifyController {
  /**
   * Verify new user email (todo_list_users) to activate account.
   *
   * This endpoint is used to complete user registration by verifying the
   * one-time token provided after signup. The token must exactly match the
   * value stored in email_verification_token field on todo_list_users for the
   * requesting user. Upon successful verification, is_verified is set to true
   * and email_verification_token/email_verification_sent_at are cleared.
   *
   * Successful verification unlocks the account for login and access to all
   * self-managed features.
   *
   * If the token is invalid, expired, or not found for the supplied email
   * address, the operation fails gracefully with a generic error.
   *
   * This flow is mandatory per requirements and is directly tied to account
   * activation lifecycle.
   *
   * Verification tokens are only valid for a set time after registration; after
   * expiration, a new registration or resend process must be initiated.
   *
   * @param connection
   * @param body Email and verification token information for account
   *   activation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async verifyEmail(
    @TypedBody()
    body: ITodoListUser.IVerifyEmail,
  ): Promise<ITodoListUser.IVerificationResult> {
    try {
      return await postAuthUserEmailVerify({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
