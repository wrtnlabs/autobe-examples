import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserPasswordChange } from "../../../../../providers/postAuthUserPasswordChange";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoUser } from "../../../../../api/structures/ITodoUser";

@Controller("/auth/user/password/change")
export class AuthUserPasswordChangeController {
  /**
   * Change current password for the authenticated user in 'todo_users',
   * updating password hash and session expiry.
   *
   * This operation enables an authenticated user to change their own password,
   * enforcing identity via current session and verifying the old password
   * against 'todo_users.password_hash'. The new password is hashed and stored,
   * then the 'updated_at' timestamp is updated. All user sessions (records in
   * 'todo_user_sessions') are invalidated by updating their 'expired_at' field,
   * ensuring that only future logins will succeed with the new credentials.
   *
   * The endpoint requires the old and new passwords, the former for validation
   * and the latter for updating. Failure returns a generic error, never
   * indicating which credential is wrong. Security policies and audit trail
   * constraints (not shown here) are upheld at all points. No other user data
   * is modified.
   *
   * This is the correct operation for enforcing password rotation, recovery
   * from compromise, and conformance to password strength rules.
   *
   * Related endpoints: session refresh (for re-login), password reset for
   * forgotten passwords.
   *
   * @param connection
   * @param body Old and new passwords for credential update. Checks old, hashes
   *   and stores new (must meet policy).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async changePassword(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUser.IChangePassword,
  ): Promise<ITodoUser.IChangePasswordResult> {
    try {
      return await postAuthUserPasswordChange({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
