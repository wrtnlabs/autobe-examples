import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserPasswordResetRequest } from "../../../../../../providers/postAuthUserPasswordResetRequest";

import { ITodoListUser } from "../../../../../../api/structures/ITodoListUser";

@Controller("/auth/user/password/reset/request")
export class AuthUserPasswordResetRequestController {
  /**
   * Request password reset for eligible user in todo_list_users.
   *
   * This endpoint initiates a secure password reset request. The email provided
   * is checked against todo_list_users. If the user exists, a
   * reset_password_token is generated, reset_password_sent_at is set, and the
   * user is notified via email. If the user does not exist or is ineligible
   * (deleted, locked), the response is identical for privacy/protection.
   *
   * The reset token is valid for a fixed period (see requirements); after
   * expiration, the process must be started again.
   *
   * This operation does not return user existence or eligibility—in every case,
   * the response is generic to avoid information leakage as mandated in
   * requirements.
   *
   * This operation is mandatory for account recovery and complies with sent_at
   * and token storage in the schema.
   *
   * Subsequent reset steps validate token and allow password update. All
   * session tokens are revoked upon completion.
   *
   * @param connection
   * @param body User email address for resetting password (no information
   *   leakage allowed).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async requestPasswordReset(
    @TypedBody()
    body: ITodoListUser.IResetPasswordRequest,
  ): Promise<ITodoListUser.IResetPasswordRequestResult> {
    try {
      return await postAuthUserPasswordResetRequest({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
