import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserPasswordReset } from "../../../../../providers/postAuthUserPasswordReset";

import { ITodoListUser } from "../../../../../api/structures/ITodoListUser";

@Controller("/auth/user/password/reset")
export class AuthUserPasswordResetController {
  /**
   * Reset user password for todo_list_users with valid token and new password.
   *
   * This endpoint completes the password reset process by consuming a valid
   * reset_password_token, a new password, and updating the user's
   * password_hash. It checks token validity (matches and not expired), and on
   * success, immediately wipes the reset_password_token and
   * reset_password_sent_at fields and saves the new hash.
   *
   * All current sessions and tokens are force-revoked for complete account
   * protection (see audit requirements in sessions table).
   *
   * Password requirements (min 8 chars, required letter and number) are
   * strictly enforced as per requirements.
   *
   * On error (e.g., invalid/expired token), response is generic to prevent
   * information leakage.
   *
   * Upon successful reset, user can only log in with new password and existing
   * tokens are invalid.
   *
   * @param connection
   * @param body Password reset submission: token and new password.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async resetPassword(
    @TypedBody()
    body: ITodoListUser.IResetPassword,
  ): Promise<ITodoListUser.IResetPasswordResult> {
    try {
      return await postAuthUserPasswordReset({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
