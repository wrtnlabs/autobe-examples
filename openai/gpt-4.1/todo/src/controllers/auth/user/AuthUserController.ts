import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoListUser } from "../../../api/structures/ITodoListUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Register a new user account and receive authentication tokens
   * (todo_list_users table).
   *
   * This endpoint allows registration and onboarding of a new registered user
   * by inserting a record into the user database table, validating unique
   * fields such as email according to schema constraints, and issuing
   * authentication tokens as described in the user requirements. The
   * registration logic enforces the password policy, field uniqueness, and all
   * validation rules defined in the Prisma schema for the user table. The
   * endpoint is unauthenticated and available for public registration.
   *
   * Upon success, it returns a token-based authentication DTO
   * (ITodoListUser.IAuthorized) containing the access and refresh tokens, user
   * ID, and any meta-information as described in the schema comments. Any
   * fields returned are strictly those defined in the user schema. Error
   * responses are structured based on unique constraint or validation failures.
   * The authentication workflow is completed on registration: no email
   * verification or multi-factor is enforced unless explicitly described in the
   * schema.
   *
   * This endpoint is part of the user authentication suite (join, login,
   * refresh) and is distinct from profile or user management APIs. Fields and
   * data provided to this operation are strictly those defined in the user
   * schema. Security policies for registration rate limiting, input sanitation,
   * and auditing are enforced where described in requirements. Related
   * operations include login and refresh, which are needed after registration
   * for continued session management.
   *
   * The endpoint aligns with modern public API practices for onboarding and can
   * be integrated into automated registration flows. It does not allow
   * duplicate registrations or bypass field validation rules. All relevant
   * business and validation rules from requirements are enforced.
   *
   * It is recommended to review the field requirements in the user schema
   * before implementing client integration or custom UI flows.
   *
   * @param connection
   * @param body Registration data for a new user as defined in the
   *   todo_list_users Prisma schema. Fields must include only those defined for
   *   the user entity.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ICreate,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate existing user with credentials and receive tokens
   * (todo_list_users table).
   *
   * This operation allows a registered user to authenticate by sending their
   * credentials (typically email and password, referencing actual user table
   * fields) to determine access. The endpoint checks the credentials against
   * the stored values in the todo_list_users Prisma schema. On a successful
   * match, a new JWT access/refresh token pair is issued and structured as an
   * ITodoListUser.IAuthorized DTO.
   *
   * All credential validation and security policies (password hashes, failed
   * login attempts, account status checks) use fields defined in the user
   * schema. The endpoint is part of the user authentication suite and enables
   * further authenticated API use. Security and validation policies (rate
   * limiting, input sanitation) are enforced per requirements and available
   * schema constraints.
   *
   * It returns only the tokens and necessary user/session information as
   * defined by requirements and schema, with no exposure of additional PII. The
   * login route is unauthenticated for input but issues tokens only on
   * successful credential match.
   *
   * Error responses are clearly defined: invalid combinations receive a generic
   * failure message per best security practices. This endpoint, combined with
   * join and refresh, forms the complete authentication system for the user
   * actor.
   *
   * @param connection
   * @param body Login credentials for an existing user from todo_list_users
   *   Prisma schema (e.g., email, password). Only use fields that exist in the
   *   schema.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ILogin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh user JWT tokens with a valid refresh token (todo_list_users table).
   *
   * Allows an authenticated user to refresh their access and refresh tokens by
   * presenting a valid (unexpired) refresh token. The endpoint checks token
   * validity and session continuity based on fields and structures supported by
   * the todo_list_users and (optionally) todo_list_user_sessions schemas. It
   * returns a new ITodoListUser.IAuthorized DTO containing refreshed tokens,
   * user identity (as in schema), and meta/session info. Any session management
   * is performed per requirements and schema capability.
   *
   * Input and output strictly follow schema field requirements and only use
   * session or user fields that are present. The endpoint is used after login
   * or registration to keep user sessions alive without re-authenticating with
   * credentials. Security, expiration, and session policies are applied per
   * requirements and schema design.
   *
   * Related endpoints: login, join (for session initiation); this endpoint
   * forms the last leg of the authentication suite. Error responses are generic
   * to prevent token enumeration or abuse. The endpoint cannot be used for
   * other session or account management operations.
   *
   * @param connection
   * @param body The refresh token, as defined in requirements and schema. Only
   *   actual fields are accepted.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListUser.IRefresh,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
