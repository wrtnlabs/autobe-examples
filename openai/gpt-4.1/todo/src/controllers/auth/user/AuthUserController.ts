import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoListUser } from "../../../api/structures/ITodoListUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Registers a new user account in the user table and issues initial
   * authentication tokens.
   *
   * This operation registers a new user (member) account and provides the
   * initial authentication tokens in accordance with the user table's business
   * meaning. The endpoint validates all required registration fields as
   * provided in the request DTO, applying policy rules from requirements and
   * matching validations to Prisma schema constraints. The operation uses
   * secure password hashing (as defined in business logic, relying on password
   * field existence in user schema) to protect credentials at rest. Unique
   * constraints (e.g., unique email or username) are enforced by the underlying
   * database and mapped to clear, security-conscious error responses. The
   * registration flow is designed to strictly follow privacy requirements and
   * personal data handling policies. New user registrations often initialize
   * default application state, such as an empty Todo list or profile, per the
   * user journey in requirements. After successful user creation, the endpoint
   * responds with the authorized token DTO required by the system's login state
   * and later business logic. Registration is always the entry point for the
   * user authentication journey, and this endpoint is referenced by the login
   * and refresh flows as a prerequisite for account ownership.
   *
   * @param connection
   * @param body DTO for creating a new user. Must match ITodoListUser.ICreate
   *   schema from components.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ICreate,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates a registered user from the user table and returns
   * authentication tokens.
   *
   * This endpoint authenticates a member-user (user) using credentials defined
   * in the user schema (e.g., email/username and password), with password
   * verification matching secure practices. Requests failing credential
   * validation are rejected with generic error messaging to avoid information
   * leakage. Successful authentication leads to JWT token issuance and allows
   * downstream API access by the user. The login operation relies on the
   * registration (join) flow as a business prerequisite; only pre-existing
   * users can sign in. Security, rate limits, and lockout rules from
   * requirements/scenario documentation (where loaded) are applied by the
   * provider/controller. The endpoint's business logic integrates tightly with
   * all user-specific resources (todos) by establishing authenticated session
   * context. All user-initiated sessions are governed by this login operation
   * as the root of their authentication lineage.
   *
   * @param connection
   * @param body DTO for user login including credentials. Must match
   *   ITodoListUser.ILogin schema from components.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ILogin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes authentication tokens for a user in the user table using a valid
   * refresh token.
   *
   * Enables token refresh for an authenticated user, provided a valid refresh
   * token is supplied. Security policies regarding token expiration, session
   * invalidation, and rotation are enforced as specified in requirements and
   * infrastructure (such as user_sessions, if present). The endpoint embodies
   * the stateless nature of JWT authentication, forming a critical part of the
   * user login/refresh workflow. It inherits security and validation
   * requirements from login and join operations; only previously authenticated
   * users may refresh tokens. The refresh mechanism seamlessly extends user
   * session duration within the policy limits documented in the requirements or
   * modeled in schema/session tables.
   *
   * @param connection
   * @param body DTO for user token refresh containing the refresh token. Must
   *   match ITodoListUser.IRefresh schema from components.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListUser.IRefresh,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
