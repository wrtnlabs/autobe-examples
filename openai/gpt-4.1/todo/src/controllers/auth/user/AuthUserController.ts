import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";
import { postAuthUserUnlock } from "../../../providers/postAuthUserUnlock";

import { ITodoListUser } from "../../../api/structures/ITodoListUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Register a new user in the todo_list_users table.
   *
   * This endpoint enables a new user to register for the Todo List application.
   * The todo_list_users schema requires a unique email (field: email) and a
   * securely hashed password (field: password_hash). Upon successful creation,
   * a new user record is stored with is_verified set to false,
   * email_verification_token generated, and email_verification_sent_at set.
   *
   * The registration process enforces strict uniqueness on the email field and
   * adheres to password policy (minimum length, includes letters and numbers).
   * Immediate email verification is required—users cannot access other system
   * features until the is_verified flag is true (see is_verified field in
   * schema).
   *
   * Registration details are stored in todo_list_users with lifecycle metadata,
   * supporting further steps such as email verification.
   *
   * Significant error cases include duplicate or invalid email (rejected via
   * unique index and validation), and non-compliant password (explained to
   * user).
   *
   * After registration, the user should immediately receive an email
   * verification request; no further actions are allowed until completed.
   *
   * @param connection
   * @param body User registration details: valid unique email and strong
   *   password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.IJoin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate user for todo_list_users and create session record.
   *
   * This endpoint processes user login. Credentials are checked by matching the
   * email (unique, field: email) and secure password (password_hash field,
   * using secure verification operations). Login is blocked if the user's
   * is_verified is false, the locked flag is true (with locked_at optionally
   * set), or deleted_at is non-null.
   *
   * Each successful login creates a record in todo_list_user_sessions,
   * capturing session-related metadata (ip, href, referrer, created_at). All
   * issued JWT tokens are scoped to the user and session, supporting later
   * revocation.
   *
   * Login attempts are audited; repeated failures toggle locked/locked_at
   * according to business rules from requirements. If a user is locked out
   * (locked = true), login is denied pending reset/unlock flow.
   *
   * This endpoint does not reveal whether email or password was incorrect for
   * security. All failed responses are generic.
   *
   * Login is the sole means of initiating authenticated user sessions; all
   * further API access requires a valid token from this flow.
   *
   * @param connection
   * @param body User login credentials: email and password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ILogin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh access/refresh tokens for authenticated user via session and
   * todo_list_users.
   *
   * This endpoint enables a user to maintain a valid session by refreshing
   * their JWT tokens. It verifies that the provided refresh token is active and
   * corresponds to a valid, active session in todo_list_user_sessions.
   *
   * Additional validation checks that the user's account is not locked (locked
   * field), email is verified (is_verified field), and deleted_at is null. If
   * any of these conditions fail, refresh is denied.
   *
   * Upon success, new tokens are generated and session renewal is logged
   * (session table fields: created_at, expired_at updated as needed).
   *
   * Refresh tokens can only be used as long as the session is active and valid
   * per expiration policy. Audit compliance is enforced for all refresh
   * actions.
   *
   * Token refresh is the sole mechanism for extending active user sessions
   * without logging in again.
   *
   * @param connection
   * @param body Refresh token and device/session context.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListUser.IRefresh,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Unlock locked user account in todo_list_users after lockout.
   *
   * This endpoint allows an eligible user to restore access to a locked
   * account. It verifies that the locked field is set (locked = true, locked_at
   * populated), and the provided unlock process or token matches business rules
   * (may involve password reset, cooldown, or manual admin action).
   *
   * Once verified, the locked flag is cleared, locked_at is set to null, and
   * the account is eligible for login again.
   *
   * All unlock operations are fully audited using fields in the user and
   * session audit tables (locked, locked_at, and related session records).
   *
   * Business rules for unlock are defined in requirements and commonly involve
   * enforced cooldown or secure validation.
   *
   * On success, user may immediately attempt login with their regular
   * credentials.
   *
   * @param connection
   * @param body Required data per unlock process (e.g., unlock token,
   *   validation steps).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("unlock")
  public async unlock(
    @TypedBody()
    body: ITodoListUser.IUnlock,
  ): Promise<ITodoListUser.IUnlockResult> {
    try {
      return await postAuthUserUnlock({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
