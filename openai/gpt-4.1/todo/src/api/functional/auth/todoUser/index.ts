/**
 * Registers a new todoUser in the 'todo_list_todousers' table, initializing
 * credentials and profile audit fields.
 *
 * This registration endpoint allows a prospective todoUser to create a new
 * account by supplying a unique email and a password. The Prisma schema
 * 'todo_list_todousers' guarantees email uniqueness and enforces secure
 * credential storage by requiring a 'password_hash' field. Registration data
 * must include the email and password, with the password processed into a
 * secure hash. On success, the new user's 'id', creation timestamp
 * ('created_at'), and update timestamp ('updated_at') are system-assigned,
 * providing a reliable audit record. The request fails if the email already
 * exists, reflecting the Prisma '@@unique([email])' constraint. This operation
 * is essential for initializing authenticated sessions and serves as the entry
 * point for all user-specific business logic. Security is paramount; passwords
 * are never stored or transmitted in plaintext, and comprehensive validation is
 * strictly enforced. The join operation is closely related to 'login' and
 * 'refresh', which together implement the full authentication lifecycle for
 * todoUsers. All field-level behavior described here directly references the
 * schema's comments and enforced constraints.
 *
 * @param props.connection
 * @param props.body Email and password to register a new todoUser (will be
 *   hashed for storage).
 * @setHeader token.access Authorization
 *
 * @path /auth/todoUser/join
 * @accessor api.functional.auth.todoUser.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
