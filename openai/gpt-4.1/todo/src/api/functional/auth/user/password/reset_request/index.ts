import { ITodoUser } from "../../../../../structures/ITodoUser";

/**
 * Initiate password reset by issuing recovery token to email if found in
 * 'todo_users'.
 *
 * This operation initiates the password reset process for a user, conforming to
 * the system's policy for secure account recovery. The endpoint receives an
 * email address and, if it matches an entry in 'todo_users', sends a one-time
 * password reset token to that address. The email field is validated for format
 * and referenced via the unique constraint on 'todo_users.email'.
 *
 * No information about account existence is disclosed in the response, and
 * failure scenarios are handled generically. The password reset token is
 * time-limited, typically valid for 15–30 minutes, and is stored only in a
 * system-maintained context, never in the user table. Business logic for actual
 * password reset is handled separately via token consumption. The operation is
 * required for users who've lost their password or cannot access their account
 * using normal credentials.
 *
 * This endpoint is only accessible to non-authenticated users—those who need to
 * recover access. Limits on request frequency should be applied to prevent
 * abuse but are outside schema scope.
 *
 * Related operations: password reset document redemption (not shown),
 * login/join, session refresh. Security logging and rate limiting are implied.
 *
 * @param props.connection
 * @param props.body Registered email for password reset initiation. No other
 *   fields.
 * @path /auth/user/password/reset-request
 * @accessor api.functional.auth.user.password.reset_request.resetPassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resetPassword(
  connection: IConnection,
  props: resetPassword.Props,
): Promise<resetPassword.Response> {
  return true === connection.simulate
    ? resetPassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resetPassword.METADATA,
          path: resetPassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resetPassword {
  export type Props = {
    /** Registered email for password reset initiation. No other fields. */
    body: ITodoUser.IResetPasswordRequest;
  };
  export type Body = ITodoUser.IResetPasswordRequest;
  export type Response = ITodoUser.IResetPasswordResponse;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/reset-request",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/reset-request";
  export const random = (): ITodoUser.IResetPasswordResponse =>
    typia.random<ITodoUser.IResetPasswordResponse>();
  export const simulate = (
    connection: IConnection,
    props: resetPassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resetPassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
