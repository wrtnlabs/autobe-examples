import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUser } from "../../../../../structures/ITodoListUser";

/**
 * Verify new user email (todo_list_users) to activate account.
 *
 * This endpoint is used to complete user registration by verifying the one-time
 * token provided after signup. The token must exactly match the value stored in
 * email_verification_token field on todo_list_users for the requesting user.
 * Upon successful verification, is_verified is set to true and
 * email_verification_token/email_verification_sent_at are cleared.
 *
 * Successful verification unlocks the account for login and access to all
 * self-managed features.
 *
 * If the token is invalid, expired, or not found for the supplied email
 * address, the operation fails gracefully with a generic error.
 *
 * This flow is mandatory per requirements and is directly tied to account
 * activation lifecycle.
 *
 * Verification tokens are only valid for a set time after registration; after
 * expiration, a new registration or resend process must be initiated.
 *
 * @param props.connection
 * @param props.body Email and verification token information for account
 *   activation.
 * @path /auth/user/email/verify
 * @accessor api.functional.auth.user.email.verify.verifyEmail
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function verifyEmail(
  connection: IConnection,
  props: verifyEmail.Props,
): Promise<verifyEmail.Response> {
  return true === connection.simulate
    ? verifyEmail.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verifyEmail.METADATA,
          path: verifyEmail.path(),
          status: null,
        },
        props.body,
      );
}
export namespace verifyEmail {
  export type Props = {
    /** Email and verification token information for account activation. */
    body: ITodoListUser.IVerifyEmail;
  };
  export type Body = ITodoListUser.IVerifyEmail;
  export type Response = ITodoListUser.IVerificationResult;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/email/verify",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/email/verify";
  export const random = (): ITodoListUser.IVerificationResult =>
    typia.random<ITodoListUser.IVerificationResult>();
  export const simulate = (
    connection: IConnection,
    props: verifyEmail.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: verifyEmail.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
