import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUser } from "../../../../../../structures/ITodoListUser";

/**
 * Request password reset for eligible user in todo_list_users.
 *
 * This endpoint initiates a secure password reset request. The email provided
 * is checked against todo_list_users. If the user exists, a
 * reset_password_token is generated, reset_password_sent_at is set, and the
 * user is notified via email. If the user does not exist or is ineligible
 * (deleted, locked), the response is identical for privacy/protection.
 *
 * The reset token is valid for a fixed period (see requirements); after
 * expiration, the process must be started again.
 *
 * This operation does not return user existence or eligibility—in every case,
 * the response is generic to avoid information leakage as mandated in
 * requirements.
 *
 * This operation is mandatory for account recovery and complies with sent_at
 * and token storage in the schema.
 *
 * Subsequent reset steps validate token and allow password update. All session
 * tokens are revoked upon completion.
 *
 * @param props.connection
 * @param props.body User email address for resetting password (no information
 *   leakage allowed).
 * @path /auth/user/password/reset/request
 * @accessor api.functional.auth.user.password.reset.request.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<requestPasswordReset.Response> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestPasswordReset {
  export type Props = {
    /**
     * User email address for resetting password (no information leakage
     * allowed).
     */
    body: ITodoListUser.IResetPasswordRequest;
  };
  export type Body = ITodoListUser.IResetPasswordRequest;
  export type Response = ITodoListUser.IResetPasswordRequestResult;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/reset/request",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/reset/request";
  export const random = (): ITodoListUser.IResetPasswordRequestResult =>
    typia.random<ITodoListUser.IResetPasswordRequestResult>();
  export const simulate = (
    connection: IConnection,
    props: requestPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
