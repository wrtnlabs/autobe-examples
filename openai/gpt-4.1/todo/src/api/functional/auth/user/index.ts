/**
 * Registers a new user account in the user table and issues initial
 * authentication tokens.
 *
 * This operation registers a new user (member) account and provides the initial
 * authentication tokens in accordance with the user table's business meaning.
 * The endpoint validates all required registration fields as provided in the
 * request DTO, applying policy rules from requirements and matching validations
 * to Prisma schema constraints. The operation uses secure password hashing (as
 * defined in business logic, relying on password field existence in user
 * schema) to protect credentials at rest. Unique constraints (e.g., unique
 * email or username) are enforced by the underlying database and mapped to
 * clear, security-conscious error responses. The registration flow is designed
 * to strictly follow privacy requirements and personal data handling policies.
 * New user registrations often initialize default application state, such as an
 * empty Todo list or profile, per the user journey in requirements. After
 * successful user creation, the endpoint responds with the authorized token DTO
 * required by the system's login state and later business logic. Registration
 * is always the entry point for the user authentication journey, and this
 * endpoint is referenced by the login and refresh flows as a prerequisite for
 * account ownership.
 *
 * @param props.connection
 * @param props.body DTO for creating a new user. Must match
 *   ITodoListUser.ICreate schema from components.
 * @setHeader token.access Authorization
 *
 * @path /auth/user/join
 * @accessor api.functional.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
