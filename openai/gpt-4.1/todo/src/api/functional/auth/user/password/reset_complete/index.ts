import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoUser } from "../../../../../structures/ITodoUser";

/**
 * Reset user password in 'todo_users' (given a valid reset token); update hash
 * and 'updated_at'.
 *
 * This endpoint performs the actual password reset, redeeming a one-time-use,
 * time-limited reset token that was previously issued. The reset token is
 * validated, and if valid, the new password provided is hashed following the
 * same policy as registration. The 'password_hash' field in 'todo_users' is
 * replaced, and the 'updated_at' timestamp is updated to indicate account
 * change.
 *
 * If the token is missing, expired, or already redeemed, the operation fails
 * generically, giving no clues about account existence or token state. Upon
 * success, the user can immediately login with the new password.
 *
 * Only the token and password, both validated for format and policy, are
 * processed, with no side-effects elsewhere in the user table. This ensures
 * privacy and secure account recovery, per documented requirements.
 *
 * Related authentication flows: forgot password (initiation), login, session
 * refresh. Audit logging and token invalidation are system responsibilities,
 * not user facing.
 *
 * @param props.connection
 * @param props.body Token and new password to set. Password must meet policy.
 * @path /auth/user/password/reset-complete
 * @accessor api.functional.auth.user.password.reset_complete.completePasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function completePasswordReset(
  connection: IConnection,
  props: completePasswordReset.Props,
): Promise<completePasswordReset.Response> {
  return true === connection.simulate
    ? completePasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...completePasswordReset.METADATA,
          path: completePasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace completePasswordReset {
  export type Props = {
    /** Token and new password to set. Password must meet policy. */
    body: ITodoUser.IResetPasswordComplete;
  };
  export type Body = ITodoUser.IResetPasswordComplete;
  export type Response = ITodoUser.IResetPasswordResult;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/reset-complete",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/reset-complete";
  export const random = (): ITodoUser.IResetPasswordResult =>
    typia.random<ITodoUser.IResetPasswordResult>();
  export const simulate = (
    connection: IConnection,
    props: completePasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: completePasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
