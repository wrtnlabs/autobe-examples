import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoUser } from "../../../../../structures/ITodoUser";

/**
 * Change current password for the authenticated user in 'todo_users', updating
 * password hash and session expiry.
 *
 * This operation enables an authenticated user to change their own password,
 * enforcing identity via current session and verifying the old password against
 * 'todo_users.password_hash'. The new password is hashed and stored, then the
 * 'updated_at' timestamp is updated. All user sessions (records in
 * 'todo_user_sessions') are invalidated by updating their 'expired_at' field,
 * ensuring that only future logins will succeed with the new credentials.
 *
 * The endpoint requires the old and new passwords, the former for validation
 * and the latter for updating. Failure returns a generic error, never
 * indicating which credential is wrong. Security policies and audit trail
 * constraints (not shown here) are upheld at all points. No other user data is
 * modified.
 *
 * This is the correct operation for enforcing password rotation, recovery from
 * compromise, and conformance to password strength rules.
 *
 * Related endpoints: session refresh (for re-login), password reset for
 * forgotten passwords.
 *
 * @param props.connection
 * @param props.body Old and new passwords for credential update. Checks old,
 *   hashes and stores new (must meet policy).
 * @path /auth/user/password/change
 * @accessor api.functional.auth.user.password.change.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<changePassword.Response> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /**
     * Old and new passwords for credential update. Checks old, hashes and
     * stores new (must meet policy).
     */
    body: ITodoUser.IChangePassword;
  };
  export type Body = ITodoUser.IChangePassword;
  export type Response = ITodoUser.IChangePasswordResult;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/change",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/change";
  export const random = (): ITodoUser.IChangePasswordResult =>
    typia.random<ITodoUser.IChangePasswordResult>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
