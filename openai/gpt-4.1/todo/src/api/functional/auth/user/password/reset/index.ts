import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUser } from "../../../../../structures/ITodoListUser";
export * as request from "./request/index";

/**
 * Reset user password for todo_list_users with valid token and new password.
 *
 * This endpoint completes the password reset process by consuming a valid
 * reset_password_token, a new password, and updating the user's password_hash.
 * It checks token validity (matches and not expired), and on success,
 * immediately wipes the reset_password_token and reset_password_sent_at fields
 * and saves the new hash.
 *
 * All current sessions and tokens are force-revoked for complete account
 * protection (see audit requirements in sessions table).
 *
 * Password requirements (min 8 chars, required letter and number) are strictly
 * enforced as per requirements.
 *
 * On error (e.g., invalid/expired token), response is generic to prevent
 * information leakage.
 *
 * Upon successful reset, user can only log in with new password and existing
 * tokens are invalid.
 *
 * @param props.connection
 * @param props.body Password reset submission: token and new password.
 * @path /auth/user/password/reset
 * @accessor api.functional.auth.user.password.reset.resetPassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resetPassword(
  connection: IConnection,
  props: resetPassword.Props,
): Promise<resetPassword.Response> {
  return true === connection.simulate
    ? resetPassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resetPassword.METADATA,
          path: resetPassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resetPassword {
  export type Props = {
    /** Password reset submission: token and new password. */
    body: ITodoListUser.IResetPassword;
  };
  export type Body = ITodoListUser.IResetPassword;
  export type Response = ITodoListUser.IResetPasswordResult;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/reset";
  export const random = (): ITodoListUser.IResetPasswordResult =>
    typia.random<ITodoListUser.IResetPasswordResult>();
  export const simulate = (
    connection: IConnection,
    props: resetPassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resetPassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
