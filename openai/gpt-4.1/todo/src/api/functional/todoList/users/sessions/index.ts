/**
 * Search and retrieve a filtered, paginated list of user sessions
 * (todo_list_user_sessions) for a specific user account.
 *
 * Obtain a complete login and session activity history for a specific user by
 * searching and filtering their todo_list_user_sessions records. This endpoint
 * supports complex queries with pagination, sorting, creation date filtering,
 * and IP-based lookup, giving detailed insight into the user's recent and
 * historical authentication events.
 *
 * Authorization is restricted by system configuration; due to constraints only
 * the "user" actor is available, so this endpoint is set as public (no explicit
 * actor). Session records include information such as session initiation time,
 * expiration or revocation time, source IP, user agent/referrer, and associated
 * user ID. This API is strictly read-only for analysis, and session creation or
 * deletion is handled through the authentication subsystem, not this endpoint.
 *
 * This operation reflects the subsidiary nature of the todo_list_user_sessions
 * table, which does not support independent creation or manual deletion of
 * sessions. Modifications and new sessions are managed exclusively through the
 * authentication subsystem, so this API is strictly read-only.
 *
 * @param props.connection
 * @param props.userId Unique identifier (UUID) of the user whose sessions are
 *   being queried.
 * @param props.body Search criteria and pagination parameters for advanced
 *   session filtering, sorting, and retrieval for the selected user ID.
 * @path /todoList/users/:userId/sessions
 * @accessor api.functional.todoList.users.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
