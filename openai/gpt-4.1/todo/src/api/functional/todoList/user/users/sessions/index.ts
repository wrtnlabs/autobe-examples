import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Delete a specific user session from the todo_list_user_sessions table by
 * email and sessionId with full ownership enforcement.
 *
 * This endpoint allows an authenticated user to permanently delete (invalidate)
 * one of their own active or expired sessions using the sessionId and their
 * registered email. The operation irrevocably removes the session from the
 * database, preventing further use of associated tokens and enforcing strict
 * account security.
 *
 * Ownership checks guarantee users may not delete sessions associated with any
 * other email. All security and access validations are performed before
 * deletion; failure in any check results in denial and an appropriate error.
 *
 * This operation references the todo_list_user_sessions model and its
 * relationship to todo_list_users. No soft delete or recovery is possible; once
 * removed, the session cannot be referenced or re-activated. Used for both
 * voluntary logout (of another device) and in response to detected suspicious
 * activity.
 *
 * @param props.connection
 * @param props.email Globally unique, verified email address of the user who
 *   owns the session (global scope).
 * @param props.sessionId Globally unique session identifier to be deleted,
 *   associated with the user.
 * @path /todoList/user/users/:email/sessions/:sessionId
 * @accessor api.functional.todoList.user.users.sessions.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Globally unique, verified email address of the user who owns the
     * session (global scope).
     */
    email: string;

    /**
     * Globally unique session identifier to be deleted, associated with the
     * user.
     */
    sessionId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/todoList/user/users/:email/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoList/user/users/${encodeURIComponent(props.email ?? "null")}/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("email")(() => typia.assert(props.email));
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
