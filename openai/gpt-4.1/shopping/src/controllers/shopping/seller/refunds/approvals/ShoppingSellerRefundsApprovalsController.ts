import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingSellerRefundsRefundRequestIdApprovals } from "../../../../../providers/patchShoppingSellerRefundsRefundRequestIdApprovals";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";

import { IPageIShoppingRefundApproval } from "../../../../../api/structures/IPageIShoppingRefundApproval";
import { IShoppingRefundApproval } from "../../../../../api/structures/IShoppingRefundApproval";

@Controller("/shopping/seller/refunds/:refundRequestId/approvals")
export class ShoppingSellerRefundsApprovalsController {
  /**
   * Search and list approval/rejection actions for a given refund request
   * (shopping_refund_approvals table).
   *
   * Enables authorized users or admins to retrieve a paginated list of all
   * seller and admin approval or rejection records tied to a particular refund
   * request. This supports business audit, regulatory review, and dispute
   * investigation by exposing an authoritative record of all actions taken on
   * refund status transitions.
   *
   * The endpoint supports advanced filtering—by actor, action type
   * (approval/rejection), and time window—as well as paginated delivery of
   * result sets using request parameters. Access is limited to authorized
   * actors to ensure privacy, and sensitive rationale/notes are selectively
   * shown based on the actor requesting the data (full detail for admin,
   * business-safe versions for customers).
   *
   * Related operations include GET for single approval records and PATCH with
   * search criteria across multiple refund requests for admin/business
   * analytics. Errors are returned if the refund request does not exist or the
   * actor lacks permission.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request this
   *   approval action belongs to (global scope).
   * @param body Paging, filtering, and search criteria for refund approval
   *   records (actor, action, date, etc.).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingRefundApproval.IRequest,
  ): Promise<IPageIShoppingRefundApproval.ISummary> {
    try {
      return await patchShoppingSellerRefundsRefundRequestIdApprovals({
        seller,
        refundRequestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
