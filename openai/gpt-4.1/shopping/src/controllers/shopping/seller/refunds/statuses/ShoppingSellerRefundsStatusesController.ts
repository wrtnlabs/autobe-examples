import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingSellerRefundsRefundRequestIdStatuses } from "../../../../../providers/patchShoppingSellerRefundsRefundRequestIdStatuses";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingSellerRefundsRefundRequestIdStatusesStatusHistoryId } from "../../../../../providers/getShoppingSellerRefundsRefundRequestIdStatusesStatusHistoryId";

import { IPageIShoppingRefundStatusHistory } from "../../../../../api/structures/IPageIShoppingRefundStatusHistory";
import { IShoppingRefundStatusHistory } from "../../../../../api/structures/IShoppingRefundStatusHistory";

@Controller("/shopping/seller/refunds/:refundRequestId/statuses")
export class ShoppingSellerRefundsStatusesController {
  /**
   * Retrieve the paginated status history for a refund request
   * (shopping_refund_status_histories).
   *
   * Retrieves the chronological list of all status changes applied to a
   * specific refund request. This includes every state transition, the actor
   * who performed it (customer, seller, admin), timestamp, and any attached
   * context or notes. Enables compliance and support teams to review the full
   * workflow of a refund/return/cancellation case.
   *
   * The operation supports advanced filtering by actor type, specific statuses,
   * and date ranges when supplied in the request body. Pagination parameters
   * allow results to be batched and sorted for efficient navigation in case of
   * extensive audit trails. Consumers of this endpoint typically include admins
   * reviewing compliance, sellers overseeing requests involving their
   * products/orders, and customers tracking the lifecycle of their refund
   * claims.
   *
   * The input refundRequestId must identify an existing refund request, and the
   * caller must be authorized for the underlying business context. Any status
   * history found is returned in order from oldest to newest unless sorting
   * options are specified. Error responses occur if the request does not exist,
   * or if the actor lacks permission to view the refund's history.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the target refund request to
   *   retrieve its status history (UUID format, global scope).
   * @param body Criteria for filtering, sorting, and paginating the list of
   *   refund status histories. This may include actor type, specific status
   *   transitions, date ranges, and sort order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingRefundStatusHistory.IRequest,
  ): Promise<IPageIShoppingRefundStatusHistory> {
    try {
      return await patchShoppingSellerRefundsRefundRequestIdStatuses({
        seller,
        refundRequestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific refund request status transition history entry
   * (shopping_refund_status_histories table).
   *
   * Provides detailed information for a status transition event from the refund
   * workflow's audit trail. Typically used for displaying the full context of
   * refund approval/escalation steps, including the actor, timestamp,
   * previous/new statuses, and rationale provided.
   *
   * Only allowed actors (the refund applicant, participating seller, or admins)
   * are permitted to access the entry. Sensitive notes or context must be
   * filtered based on user type, with customer/seller seeing only
   * business-appropriate commentary, while admin can view all audit details.
   *
   * Related operations for viewing the entire history can be implemented as a
   * collection endpoint on /refunds/{refundRequestId}/statuses. This endpoint
   * is for individual entry lookup, and returns all available fields subject to
   * visibility rules.
   *
   * If the record does not exist or the actor is not authorized, an error must
   * be returned (not found or forbidden as appropriate).
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request (global
   *   scope).
   * @param statusHistoryId Unique identifier of the specific status history
   *   entry (scoped to refund request).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":statusHistoryId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedParam("statusHistoryId")
    statusHistoryId: string & tags.Format<"uuid">,
  ): Promise<IShoppingRefundStatusHistory> {
    try {
      return await getShoppingSellerRefundsRefundRequestIdStatusesStatusHistoryId(
        {
          seller,
          refundRequestId,
          statusHistoryId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
