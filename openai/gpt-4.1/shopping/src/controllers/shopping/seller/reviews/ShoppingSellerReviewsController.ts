import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingSellerReviews } from "../../../../providers/patchShoppingSellerReviews";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingSellerReviewsReviewId } from "../../../../providers/getShoppingSellerReviewsReviewId";

import { IPageIShoppingReview } from "../../../../api/structures/IPageIShoppingReview";
import { IShoppingReview } from "../../../../api/structures/IShoppingReview";

@Controller("/shopping/seller/reviews")
export class ShoppingSellerReviewsController {
  /**
   * Search and retrieve filtered, paginated list of product reviews
   * (shopping_reviews).
   *
   * Retrieve a filtered, paginated list of product reviews submitted by
   * customers for products and SKUs on the shopping mall platform. This
   * operation allows searching by review state, star rating, associated product
   * or SKU, customer ID, order line, keywords within comments, and date range.
   * The response includes review summary information for admin, seller, or
   * customer display, showing each review's unique identifiers, rating,
   * truncated comment, state, creation/update dates, and author details per
   * role permissions.
   *
   * Pagination and sorting are fully supported via the request body parameters,
   * with page size and offset controls. Security is enforced according to the
   * actor accessing the endpoint—admins may access all reviews, sellers those
   * for their products, and customers only their own. Integration with review
   * moderation and abuse workflows is supported. Errors include unauthorized
   * access, invalid parameters, and exceeded page size limits.
   *
   * @param connection
   * @param body Review search and filter criteria including pagination and
   *   advanced filters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingReview.IRequest,
  ): Promise<IPageIShoppingReview.ISummary> {
    try {
      return await patchShoppingSellerReviews({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete details for a single product review from shopping_reviews
   * table.
   *
   * Retrieve the complete record and associated data for a specific customer
   * product review by its unique reviewId (UUID, PK in shopping_reviews
   * schema). This operation is used to display all review information in
   * detail, including full text, rating, state, reviewer details, attachments,
   * and audit history if allowed. The returned data includes all fields and
   * relationships (customer, SKU, order line), for detailed view or moderation
   * workflows.
   *
   * Security and access control are based on role: customers access their own
   * reviews, sellers see reviews for their products, admins may access all.
   * Reference integrity and soft deletion are respected; if the review does not
   * exist, is deleted, or access is denied, an error or null is returned.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review (UUID as PK of
   *   shopping_reviews)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reviewId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IShoppingReview> {
    try {
      return await getShoppingSellerReviewsReviewId({
        seller,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
