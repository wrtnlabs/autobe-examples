import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingSellerInventorySkuCodeAlerts } from "../../../../../providers/patchShoppingSellerInventorySkuCodeAlerts";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingSellerInventorySkuCodeAlertsAlertId } from "../../../../../providers/getShoppingSellerInventorySkuCodeAlertsAlertId";

import { IPageIShoppingInventoryAlert } from "../../../../../api/structures/IPageIShoppingInventoryAlert";
import { IShoppingInventoryAlert } from "../../../../../api/structures/IShoppingInventoryAlert";

@Controller("/shopping/seller/inventory/:skuCode/alerts")
export class ShoppingSellerInventoryAlertsController {
  /**
   * Search and retrieve all inventory alerts for a specific SKU.
   *
   * Retrieve a list of all inventory alerts for a specified SKU by code. This
   * includes both active and resolved alerts, allowing sellers or admins to
   * monitor supply issues such as low stock, out-of-stock, manual overrides, or
   * detected anomalies.
   *
   * The operation supports filtering by alert type, status
   * (resolved/unresolved), date ranges for triggered or resolved events, and
   * search by context note. Querying alerts is crucial for timely restocking
   * and risk management, ensuring that inventory managers are notified of
   * potential issues tracked by the Prisma schema. Result is paginated, with
   * total alert count, alert details, and optional resolution context per
   * alert.
   *
   * This endpoint references the shopping_inventory_alerts table, which is
   * closely related to the shopping_skus entity through the SKU code and to the
   * underlying inventory monitoring system. Role-based access control can limit
   * visibility: sellers only see their own SKUs, whereas admins have global
   * scope for platform health monitoring.
   *
   * @param connection
   * @param skuCode Globally unique business code identifying the target SKU
   *   (global scope)
   * @param body Search and filter criteria for inventory alerts related to the
   *   SKU, such as alert type, resolved status, and trigger/resolution date
   *   ranges.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("skuCode")
    skuCode: string,
    @TypedBody()
    body: IShoppingInventoryAlert.IRequest,
  ): Promise<IPageIShoppingInventoryAlert> {
    try {
      return await patchShoppingSellerInventorySkuCodeAlerts({
        seller,
        skuCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed inventory alert by alertId for a specific SKU code.
   *
   * Retrieve full details of a single inventory alert identified by alertId for
   * the given SKU code. This operation allows sellers and admins to review the
   * root cause, timeline, context, and status updates for critical inventory
   * signals related to a product variant.
   *
   * The operation draws on the shopping_inventory_alerts table from the Prisma
   * schema, ensuring that the requested alert exists for the specified SKU. The
   * full context note, trigger events, resolution actions, actor metadata, and
   * all timestamps are included. This is valuable for post-incident review,
   * audit, or compliance purposes, and supports root-cause analysis or
   * escalation workflows.
   *
   * Access control ensures sellers may retrieve alerts for their managed SKUs,
   * while admins may retrieve alerts platform-wide for investigation of
   * inventory actions or audit events as tracked in the system.
   *
   * @param connection
   * @param skuCode Globally unique business code identifying the target SKU
   *   (global scope)
   * @param alertId Unique identifier of the inventory alert to be retrieved.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":alertId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("skuCode")
    skuCode: string,
    @TypedParam("alertId")
    alertId: string & tags.Format<"uuid">,
  ): Promise<IShoppingInventoryAlert> {
    try {
      return await getShoppingSellerInventorySkuCodeAlertsAlertId({
        seller,
        skuCode,
        alertId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
