import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingSellerProductsProductCodeImages } from "../../../../../providers/postShoppingSellerProductsProductCodeImages";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { putShoppingSellerProductsProductCodeImagesImageId } from "../../../../../providers/putShoppingSellerProductsProductCodeImagesImageId";
import { deleteShoppingSellerProductsProductCodeImagesImageId } from "../../../../../providers/deleteShoppingSellerProductsProductCodeImagesImageId";

import { IShoppingProductImage } from "../../../../../api/structures/IShoppingProductImage";

@Controller("/shopping/seller/products/:productCode/images")
export class ShoppingSellerProductsImagesController {
  /**
   * Upload a new product image (JPEG/PNG, max 5MB) to a product owned by the
   * authenticated seller or admin. (shopping_product_images).
   *
   * Add a new display image to a specific product, identified by its business
   * code. This endpoint can only be accessed by the product's owning seller or
   * an admin. It performs full validation: verifies product existence, ensures
   * caller owns the product, and that the maximum image limit (10 images per
   * product per business requirements) is not exceeded. The input enforces file
   * type (JPEG or PNG) and size restrictions (5MB) with error feedback if
   * validation fails.
   *
   * If an image is successfully uploaded, its URI and index order are saved to
   * the shopping_product_images table, and the new image record is returned to
   * the client. Ownership checks and authentication are strictly enforced;
   * unauthorized requests are rejected. If the maximum limit is reached, a
   * specific error message is returned and the operation does not proceed. Only
   * valid, authenticated sellers and admins with relevant rights can access
   * this endpoint.
   *
   * This operation provides feedback on success or failure, returns the full
   * created image object if successful, and is integrated with business logic
   * for catalog display updates. Attempts to misuse, over-upload, or provide
   * invalid files are blocked according to schema and business policy.
   *
   * @param connection
   * @param productCode Unique business code (global scope) of the target
   *   product for image upload, as defined by the shopping_products.code
   *   (globally unique).
   * @param body Payload representing the uploaded image file and, optionally,
   *   display order. File must be JPEG or PNG and maximum 5MB. Index is
   *   optional. Business logic will assign index if omitted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productCode")
    productCode: string,
    @TypedBody()
    body: IShoppingProductImage.ICreate,
  ): Promise<IShoppingProductImage> {
    try {
      return await postShoppingSellerProductsProductCodeImages({
        seller,
        productCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update or replace a product image (URI, metadata, or file) for a product by
   * code and image ID. (shopping_product_images).
   *
   * Update or replace details for a specific product image, referenced by
   * unique product code and image ID. Image replacement (uploading a new file)
   * is allowed as long as new images conform to the business rules: acceptable
   * file types are JPEG or PNG, maximum file size is 5MB, and image count per
   * product does not change (this is not an upload for a new image, only a
   * modification of an existing one). Caller must be the product's seller or an
   * admin; requests from non-owners will be denied.
   *
   * Request can update image file (file URI), image order index, or
   * image-related metadata as supported by business policy. If an unauthorized
   * user or invalid data is provided, the API responds with relevant error
   * codes and messages. This operation ensures all updates maintain catalog
   * integrity: once the update is accepted, image records are immediately
   * reflected in product display listings. On success, the full updated image
   * record is returned.
   *
   * Extensive audit trails are maintained for any updates, ensuring
   * accountability and traceability per compliance requirements. Only validated
   * updates to images for products owned by the authenticated actor are
   * allowed.
   *
   * @param connection
   * @param productCode Unique business code (global scope) for the product to
   *   which the image belongs, matching shopping_products.code (globally
   *   unique).
   * @param imageId Unique identifier (UUID) of the image record to update,
   *   referencing shopping_product_images.id (globally unique).
   * @param body Body containing image file (for replacement) or fields for
   *   display index/metadata update. File requirements: JPEG or PNG, ≤5MB. Only
   *   updatable fields defined in the schema are accepted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":imageId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productCode")
    productCode: string,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingProductImage.IUpdate,
  ): Promise<IShoppingProductImage> {
    try {
      return await putShoppingSellerProductsProductCodeImagesImageId({
        seller,
        productCode,
        imageId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific image from a product by product code and image ID.
   *
   * This API operation allows for the permanent removal of a specific image
   * from a product by referencing the product's unique business code and the
   * image's unique identifier. The productCode parameter corresponds to the
   * globally unique code assigned to the product, ensuring that the deletion
   * targets the correct product even if IDs change. The imageId parameter is
   * the primary key of the image in the shopping_product_images table.
   *
   * The product image deletion operation enforces that only products which
   * belong to the authenticated seller (or admin) are modifiable, and any image
   * IT attempts to delete must be linked to the product corresponding to the
   * supplied product code. No soft-delete field is present for
   * shopping_product_images, so invoking this operation performs a hard delete,
   * permanently erasing the image from the database. There are no recovery
   * mechanisms available at the API level for accidentally deleted images, so
   * robust client confirmation dialogs are recommended.
   *
   * Security and authorization are critical: only authorized sellers owning the
   * product or administrators can execute this action. Attempting to delete
   * images on another seller's product will result in a forbidden error. The
   * operation is fully auditable; deletion events should be logged via
   * centralized audit mechanisms as defined in admin requirements.
   *
   * Related operations that might be used in conjunction with this API include
   * product detail retrieval and product update operations, as management of
   * product images is typically part of the broader product editing
   * capability.
   *
   * @param connection
   * @param productCode Unique business code identifying the target product
   *   (global scope) whose image is to be deleted.
   * @param imageId Unique identifier of the image to remove from the product.
   *   This is the primary key UUID of the image in shopping_product_images
   *   table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":imageId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productCode")
    productCode: string,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingSellerProductsProductCodeImagesImageId({
        seller,
        productCode,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
