import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingSellerShipments } from "../../../../providers/patchShoppingSellerShipments";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { putShoppingSellerShipmentsCode } from "../../../../providers/putShoppingSellerShipmentsCode";

import { IPageIShoppingShipment } from "../../../../api/structures/IPageIShoppingShipment";
import { IShoppingShipment } from "../../../../api/structures/IShoppingShipment";

@Controller("/shopping/seller/shipments")
export class ShoppingSellerShipmentsController {
  /**
   * Search and retrieve paginated shipment records with advanced filtering and
   * sorting for admins or sellers.
   *
   * This API endpoint is designed to facilitate comprehensive shipment search
   * and management. It handles complex queries over the shopping_shipments
   * records, allowing filters such as shipment status, carrier company, code,
   * seller, scheduled or dispatched time frames, and other relevant logistics
   * parameters.
   *
   * The search supports both administrative users (platform-wide visibility of
   * all shipments) and sellers (restricted to their own shipments). The
   * endpoint enforces result pagination and provides options for sorting by
   * various dates or business status fields for effective logistics
   * management.
   *
   * Sensitive shipment data, including internal business notes or admin
   * override context, is omitted unless the requester is an authorized admin.
   * Error handling includes validation of query parameters and rejection for
   * unauthorized sellers requesting other sellers' shipments. Track and trace
   * URLs or links may be included in summary views.
   *
   * Related endpoints may support shipment detail retrieval, update, or
   * management by authorized actors.
   *
   * @param connection
   * @param body Shipment search filters and pagination/sorting options (such as
   *   status, carrier, seller, scheduled date, etc).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingShipment.IRequest,
  ): Promise<IPageIShoppingShipment.ISummary> {
    try {
      return await patchShoppingSellerShipments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update core information for a specific shipment by code in
   * shopping_shipments.
   *
   * Update shipment information for a specific shipment using its business
   * code. This endpoint supports updates to attributes such as status (e.g.
   * pending, packed, in_transit, delivered), carrier company,
   * dispatch/delivered/cancel timestamps, and logistics metadata as required
   * for business workflow and audit compliance.
   *
   * Only authorized sellers (who own the shipment) and administrators are
   * permitted to update this record. All changes are recorded for audit, and
   * updates to critical fields (code, id, order association) are forbidden. If
   * the shipment has been soft deleted, the update will be rejected as per
   * business compliance rules.
   *
   * The request body structure references the update DTO, mapping schema fields
   * to updatable shipment attributes per platform requirements. Authorization
   * and validation logic ensure correct application of business rules.
   *
   * @param connection
   * @param code Unique shipment business code (e.g., SHPT-2025-0001) assigned
   *   in shopping_shipments for update purposes. Must match exactly to identify
   *   which shipment record to update.
   * @param body Information for fields eligible for update in the target
   *   shipment, as defined by the shopping_shipments update DTO.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":code")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("code")
    code: string,
    @TypedBody()
    body: IShoppingShipment.IUpdate,
  ): Promise<IShoppingShipment> {
    try {
      return await putShoppingSellerShipmentsCode({
        seller,
        code,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
