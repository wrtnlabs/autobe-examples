import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingSellerAttributeDimensionsDimensionCodeValues } from "../../../../../providers/patchShoppingSellerAttributeDimensionsDimensionCodeValues";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";

import { IPageIShoppingAttributeValue } from "../../../../../api/structures/IPageIShoppingAttributeValue";
import { IShoppingAttributeValue } from "../../../../../api/structures/IShoppingAttributeValue";

@Controller("/shopping/seller/attributeDimensions/:dimensionCode/values")
export class ShoppingSellerAttributedimensionsValuesController {
  /**
   * Search and retrieve all attribute values for a given attribute dimension
   * from shopping_attribute_values.
   *
   * This API endpoint allows catalog administrators or authorized sellers to
   * query all attribute values under a single attribute dimension, as indicated
   * by the dimensionCode path parameter. Attribute values represent selectable
   * options in product or SKU variants, such as color names, size labels, or
   * other feature values.
   *
   * The operation supports flexible search and filtering, including sorting by
   * display order, searching by value code, and paginating results for
   * efficient frontend display. It leverages the relationships defined in
   * shopping_attribute_dimensions and shopping_attribute_values, ensuring that
   * only options for the specified dimension are returned.
   *
   * The response includes detailed information for each attribute value, such
   * as its value_code, display_value, and display_order. Security and access
   * restrictions require that only authorized users managing the catalog can
   * access this endpoint. This operation is essential for product onboarding,
   * catalog cleanup, and management of variant options.
   *
   * @param connection
   * @param dimensionCode Unique business code of the attribute dimension whose
   *   values are being retrieved (global scope).
   * @param body Filtering, pagination, or search parameters for querying
   *   attribute values of a dimension.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("dimensionCode")
    dimensionCode: string,
    @TypedBody()
    body: IShoppingAttributeValue.IRequest,
  ): Promise<IPageIShoppingAttributeValue> {
    try {
      return await patchShoppingSellerAttributeDimensionsDimensionCodeValues({
        seller,
        dimensionCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
