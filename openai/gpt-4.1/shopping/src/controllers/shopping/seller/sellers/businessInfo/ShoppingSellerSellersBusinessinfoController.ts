import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingSellerSellersSellerIdBusinessInfo } from "../../../../../providers/getShoppingSellerSellersSellerIdBusinessInfo";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { putShoppingSellerSellersSellerIdBusinessInfo } from "../../../../../providers/putShoppingSellerSellersSellerIdBusinessInfo";

import { IShoppingSellerBusinessInfo } from "../../../../../api/structures/IShoppingSellerBusinessInfo";

@Controller("/shopping/seller/sellers/:sellerId/businessInfo")
export class ShoppingSellerSellersBusinessinfoController {
  /**
   * Fetch seller business information from shopping_seller_business_infos
   * table.
   *
   * This API retrieves all business information for a seller, including
   * corporate registration data, legal contacts, tax information, support
   * contact, and banking details as stored in the
   * shopping_seller_business_infos table. The endpoint is primarily used in
   * admin dashboards for compliance and onboarding workflows, but may also be
   * available to the seller for self-service updates.
   *
   * The response includes fields such as the legal entity name, business
   * registration number, official representative, support channel, and
   * settlement banking information. All returned data is subject to privacy and
   * audit rules, with sensitive fields masked as appropriate for non-admin
   * actors. Strict access control is enforced: only the seller themselves or
   * admin-role users may access this data.
   *
   * This operation is critical for regulatory requirements, fraud prevention,
   * and supporting KYC/business onboarding workflows, ensuring legal and
   * banking compliance for each seller.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingSellerBusinessInfo> {
    try {
      return await getShoppingSellerSellersSellerIdBusinessInfo({
        seller,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update legal and business registration information for a seller
   * (shopping_seller_business_infos).
   *
   * This API operation is designed to update the business registration, legal
   * entity, and compliance information for a given seller account identified by
   * sellerId. It is required that the seller or an authorized admin uses this
   * endpoint to submit changes, such as updating legal entity names, tax IDs,
   * representative contacts, support contact methods, and primary settlement
   * bank accounts. All updated information must meet platform validation
   * standards for format and completeness, including legal and country-specific
   * compliance checks.
   *
   * Security considerations for this operation are paramount: only the owning
   * seller or platform administrators may update this information, with every
   * change being logged for compliance, KYC/AML (Anti-Money Laundering)
   * validation, and legal audit. The endpoint is tied directly to the
   * shopping_seller_business_infos table, which enforces the strict one-to-one
   * link to each seller.
   *
   * The endpoint includes robust validation logic: all required fields must be
   * present, duplicate registration numbers are rejected, and changes to bank
   * account information trigger an additional verification process. Errors are
   * explicitly described in API responses, with codes for field violation,
   * business rule exceptions, and permission issues. Related operations include
   * seller onboarding and business info retrieval endpoints, which may be
   * referenced together for a complete admin/seller workflow.
   *
   * Expected behavior includes full replacement of the business info record;
   * partial updates are not allowed via this endpoint. Any attempt to modify
   * immutable or restricted fields, or to update information for another seller
   * without proper authorization, will be denied with detailed error messages.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller (UUID, required to
   *   access their business info).
   * @param body Updated business registration, KYC, and compliance details for
   *   the seller.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingSellerBusinessInfo.IUpdate,
  ): Promise<IShoppingSellerBusinessInfo> {
    try {
      return await putShoppingSellerSellersSellerIdBusinessInfo({
        seller,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
