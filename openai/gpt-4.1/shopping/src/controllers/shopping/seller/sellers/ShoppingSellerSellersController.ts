import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingSellerSellersSellerId } from "../../../../providers/getShoppingSellerSellersSellerId";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { putShoppingSellerSellersSellerId } from "../../../../providers/putShoppingSellerSellersSellerId";

import { IShoppingSeller } from "../../../../api/structures/IShoppingSeller";

@Controller("/shopping/seller/sellers/:sellerId")
export class ShoppingSellerSellersController {
  /**
   * Retrieve detailed information for a specific seller account
   * (shopping_sellers table) by sellerId.
   *
   * Retrieve all available profile information, contact details, and status
   * fields for a single seller actor. This endpoint provides admins and
   * authorized actors with full visibility into seller account data for
   * business administration, compliance oversight, or customer support
   * purposes.
   *
   * Security for this endpoint must ensure only admins or the owner seller
   * themselves may access the target seller data: access by account owner is
   * permitted for viewing their own information; access by admin roles supports
   * platform moderation, policy enforcement, or business compliance reviews.
   *
   * The operation directly maps to the shopping_sellers entity in the database
   * schema and incorporates all non-sensitive account properties, leveraging
   * associated profile and business data for completeness. In scenarios with
   * audit, suspension, or flag status, extra caution is advised when displaying
   * or exposing sensitive values.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account in the
   *   shopping_sellers table. This is a UUID value and refers directly to the
   *   seller's primary key.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingSeller> {
    try {
      return await getShoppingSellerSellersSellerId({
        seller,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update seller account profile or status in shopping_sellers by sellerId.
   *
   * Update the editable fields of a seller account, enabling the seller to
   * correct or improve their profile, or enabling admins to update status,
   * moderation, or compliance action as appropriate. Only fields present in the
   * IShoppingSeller.IUpdate request DTO are allowed to be modified.
   *
   * Authorization restrictions ensure that only the owner seller or an admin
   * can execute profile/account updates. Admin actions must be auditable,
   * trigger appropriate notification/workflow, and be compliant with business
   * policy. This endpoint validates payload against business rules, enforces
   * non-editability of restricted fields (such as immutable identifiers), and
   * applies updates atomically.
   *
   * The endpoint references the shopping_sellers table, and all field-level
   * update constraints, formats, and business logic are governed directly by
   * the schema and platform requirements. Error handling ensures any violations
   * (such as attempting to update a suspended account or modifying immutable
   * fields) are communicated with actionable detail.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account in the
   *   shopping_sellers table. This is a UUID value and refers directly to the
   *   seller's primary key.
   * @param body Payload specifying updatable profile fields for the seller,
   *   mapping to IShoppingSeller.IUpdate. Contains only fields allowed by
   *   business logic and schema for account update.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingSeller.IUpdate,
  ): Promise<IShoppingSeller> {
    try {
      return await putShoppingSellerSellersSellerId({
        seller,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
