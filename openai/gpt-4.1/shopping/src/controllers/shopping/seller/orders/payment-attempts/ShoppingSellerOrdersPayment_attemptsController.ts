import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingSellerOrdersOrderCodePaymentAttempts } from "../../../../../providers/patchShoppingSellerOrdersOrderCodePaymentAttempts";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingSellerOrdersOrderCodePaymentAttemptsPaymentReference } from "../../../../../providers/getShoppingSellerOrdersOrderCodePaymentAttemptsPaymentReference";

import { IPageIShoppingPaymentAttempt } from "../../../../../api/structures/IPageIShoppingPaymentAttempt";
import { IShoppingPaymentAttempt } from "../../../../../api/structures/IShoppingPaymentAttempt";

@Controller("/shopping/seller/orders/:orderCode/payment-attempts")
export class ShoppingSellerOrdersPayment_attemptsController {
  /**
   * Search and retrieve all payment attempts for an order by order code.
   *
   * This endpoint enables comprehensive search and review of all payment
   * attempt records linked to a specific order, using the global order_code as
   * a reference. The system returns complete details for each attempt,
   * including payment_reference (if assigned), attempt_status (pending,
   * completed, failed, cancelled), amount, timestamps, and outcome.
   *
   * The operation is designed for use by customers monitoring their own order
   * payment progress, sellers verifying transaction status, or admins
   * investigating payment workflows, failures, or fraud incidents. Result data
   * supports choice of page size, offset, and sorting per
   * IShoppingPaymentAttempt.IRequest definition: filtering by status,
   * timeframe, or reference is included where supported by implementation.
   *
   * All returned payment attempts strictly correspond to the order specified,
   * preventing cross-order data leakage. Authorization is required; only the
   * customer for the order, involved seller, or admins have access. This
   * operation references the documentation and relationships for
   * shopping_orders and shopping_payment_attempts, ensuring correct alignment
   * with the business and audit trail.
   *
   * @param connection
   * @param orderCode Globally unique, human-readable code of the target order
   *   (global scope)
   * @param body Search/filter parameters and pagination options for payment
   *   attempt records associated with the order. Follows standard paging and
   *   search conventions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedBody()
    body: IShoppingPaymentAttempt.IRequest,
  ): Promise<IPageIShoppingPaymentAttempt> {
    try {
      return await patchShoppingSellerOrdersOrderCodePaymentAttempts({
        seller,
        orderCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get a specific payment attempt detail for a given order (shopping_orders,
   * shopping_payment_attempts).
   *
   * Retrieve detailed information about a specific payment attempt associated
   * with an order. This API is essential for clients or internal services to
   * trace payment activity, whether for user/cashier confirmation, backend
   * support, or compliance review.
   *
   * Access control and validation logic ensure only the rightful order owner
   * (the purchasing customer), merchant stakeholders (for their order lines),
   * or platform admin can use this endpoint. For sensitive information, such as
   * raw external payment references or error strings, the provider
   * implementation must ensure proper masking or role-based filtering.
   *
   * The underlying data is derived from the shopping_payment_attempts table,
   * and the query is scoped both by order_code (from shopping_orders) and
   * paymentReference (from the payment_attempts table). Validation rules
   * enforce that the order_code and paymentReference must unambiguously
   * identify a row, and adequate error handling must be in place for not-found
   * and access-denied cases.
   *
   * @param connection
   * @param orderCode Globally unique order reference code (global scope)
   *   identifying the target order. Used for readable business and customer
   *   workflows.
   * @param paymentReference Unique business identifier for the payment attempt
   *   assigned either by the gateway or platform (global scope). Used to filter
   *   payment attempts within the order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":paymentReference")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedParam("paymentReference")
    paymentReference: string,
  ): Promise<IShoppingPaymentAttempt> {
    try {
      return await getShoppingSellerOrdersOrderCodePaymentAttemptsPaymentReference(
        {
          seller,
          orderCode,
          paymentReference,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
