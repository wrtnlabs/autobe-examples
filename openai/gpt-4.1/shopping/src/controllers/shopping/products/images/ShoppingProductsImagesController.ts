import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingProductsProductCodeImages } from "../../../../providers/patchShoppingProductsProductCodeImages";
import { getShoppingProductsProductCodeImagesImageId } from "../../../../providers/getShoppingProductsProductCodeImagesImageId";

import { IPageIShoppingProductImage } from "../../../../api/structures/IPageIShoppingProductImage";
import { IShoppingProductImage } from "../../../../api/structures/IShoppingProductImage";

@Controller("/shopping/products/:productCode/images")
export class ShoppingProductsImagesController {
  /**
   * Retrieve and search product images for a specific product using business
   * code.
   *
   * Retrieve a filtered and paginated list of all images associated with a
   * specific product by product business code. This endpoint enables clients to
   * request product images with additional filter/query options such as order,
   * partial file URI match, or other business-specific attributes for the image
   * entity. It will take into account that productCode is globally unique (as
   * ensured by the Prisma @@unique([code]) constraint on shopping_products),
   * and so only the correct product's images are returned.
   *
   * Security and access is primarily controlled at the product level, with
   * public users typically only seeing images for published/active products.
   * Sellers and admins may access images for unpublished, draft, or archived
   * products, pending authorization checks. The endpoint is read-only and does
   * not provide upload or modification capabilities. Pagination parameters and
   * result format follow standard platform conventions and return paginated
   * objects, with each image including full file URI, upload timestamp, and
   * display order if available.
   *
   * If the productCode is not found or refers to an archived/deleted product,
   * the endpoint will return an appropriate error to prevent information
   * leakage. Related endpoints for product detail queries or image
   * upload/delete may be combined for advanced client workflows.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target product
   *   (global scope)
   * @param body Search and pagination criteria for filtering product images
   *   under the chosen product
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productCode")
    productCode: string,
    @TypedBody()
    body: IShoppingProductImage.IRequest,
  ): Promise<IPageIShoppingProductImage> {
    try {
      return await patchShoppingProductsProductCodeImages({
        productCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific product image by product business code and image UUID.
   *
   * Retrieve a single image resource associated with a product using the
   * product's unique business code as context and the image's UUID as
   * identifier. This endpoint verifies the image belongs to the product and
   * enforces any visibility or access control configured for the product or its
   * images.
   *
   * If either the productCode is not found, or no image matching the provided
   * imageId exists within the product, the endpoint will return a not found
   * error. Only images for published or active products are available to public
   * users, whereas sellers or admins may be permitted to access images from
   * draft or archived products through separate authorization.
   *
   * The operation directly references the shopping_product_images table in the
   * Prisma schema and includes all available metadata for the image (URI,
   * upload timestamp, order index, etc.). No modification, deletion, or upload
   * is supported here.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target product
   *   (global scope)
   * @param imageId Unique identifier of the product image (UUID) belonging to
   *   the specified product
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":imageId")
  public async at(
    @TypedParam("productCode")
    productCode: string,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<IShoppingProductImage> {
    try {
      return await getShoppingProductsProductCodeImagesImageId({
        productCode,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
