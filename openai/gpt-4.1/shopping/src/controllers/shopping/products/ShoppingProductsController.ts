import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingProducts } from "../../../providers/patchShoppingProducts";
import { getShoppingProductsProductCode } from "../../../providers/getShoppingProductsProductCode";

import { IPageIShoppingProduct } from "../../../api/structures/IPageIShoppingProduct";
import { IShoppingProduct } from "../../../api/structures/IShoppingProduct";

@Controller("/shopping/products")
export class ShoppingProductsController {
  /**
   * Search, filter, and paginate available catalog products
   * (shopping_products).
   *
   * This operation retrieves a paginated and filtered list of catalog products
   * from the shopping_products table. It is designed to support wild-card
   * keyword searching on product name and description, as well as precise
   * filtering on product code, status, seller, and category. Advanced options
   * include faceted filtering over associated tags and variant attributes, as
   * well as multi-level sorts such as price ascending/descending, newest, or
   * rating.
   *
   * Security controls ensure that only active (published) products are returned
   * to customers. Sellers are enabled to search and filter on their own
   * products, while admins have access to global product listings. Business
   * logic supports only products with at least one active SKU, in line with the
   * business requirements. Sensitive filtering (e.g., unpublished or archived
   * products) is restricted to admins and sellers. Rate limiting may be applied
   * for excessive search requests, and results are paginated according to API
   * specification.
   *
   * This endpoint integrates with the shopping_products table and its relations
   * to categories, SKUs, tags, and sellers, incorporating all public-facing
   * catalog fields and business-required filters. Optimized summary information
   * is returned per product for efficient catalog display and UX needs.
   *
   * @param connection
   * @param body Product search, filter, and pagination parameters for catalog
   *   browsing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingProduct.IRequest,
  ): Promise<IPageIShoppingProduct.ISummary> {
    try {
      return await patchShoppingProducts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detail of a specific catalog product by its unique business code
   * (shopping_products).
   *
   * This operation reads the detailed information for a catalog product
   * identified by productCode in the shopping_products table. It returns
   * complete product metadata, including description, main image, status,
   * category assignments, associated SKUs, tag/attribute mapping, and current
   * active state, along with seller display information. If the requested
   * product is unpublished or archived, only seller or admin actors are
   * permitted access; public customers receive an error for such cases. The
   * request is read-only and does not allow any modification to product data.
   *
   * Path parameter productCode must match a unique product code, scoped
   * globally. Error responses are produced if the productCode does not exist or
   * is inaccessible under current actor permissions. Only fields physically
   * present in the schema (and their documented relationships) are included in
   * the returned result.
   *
   * This endpoint is core to supporting the catalog product detail page flows
   * for both the customer-facing UI and for seller/admin management views.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target product
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productCode")
  public async at(
    @TypedParam("productCode")
    productCode: string,
  ): Promise<IShoppingProduct> {
    try {
      return await getShoppingProductsProductCode({
        productCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
