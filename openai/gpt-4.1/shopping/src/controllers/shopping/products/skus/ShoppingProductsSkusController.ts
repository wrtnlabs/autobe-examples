import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getShoppingProductsProductCodeSkusSkuCode } from "../../../../providers/getShoppingProductsProductCodeSkusSkuCode";

import { IShoppingSku } from "../../../../api/structures/IShoppingSku";

@Controller("/shopping/products/:productCode/skus/:skuCode")
export class ShoppingProductsSkusController {
  /**
   * Retrieve detailed information of a specific SKU by product and SKU code.
   *
   * This API operation returns the complete detail for a SKU (Stock Keeping
   * Unit) under a given product, as identified by their unique business codes.
   * The operation leverages the unique constraint on shopping_products.code
   * (global scope) and shopping_skus.sku_code (global scope) to ensure
   * unambiguous results. The resulting response includes all SKU variant
   * attributes, retail price, is_active flag, barcode, business status, and
   * full audit timestamps, as well as a reference to its parent product for
   * secondary context.
   *
   * The endpoint is useful for customers, sellers, and admins for confirming
   * SKU availability, reviewing variant options, and supporting add-to-cart
   * validation flows. Access is public, but for inactive or archived SKUs
   * (status logic enforced by the business), the API may return either a
   * filtered view or a not found error as appropriate. All relationship and
   * attribute field values come directly from the shopping_skus table and its
   * related entities as defined in the schema. No request body is required; all
   * identification is path-based.
   *
   * Advanced error handling is in place for non-existent, deleted, or
   * permission-restricted SKUs, returning appropriately detailed not-found
   * errors or permission denied messages. This operation is often used in the
   * context of product page rendering, checkout workflows, or administrative
   * SKU review.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target product
   *   (global scope)
   * @param skuCode Unique business identifier code of the target SKU (global
   *   scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("productCode")
    productCode: string,
    @TypedParam("skuCode")
    skuCode: string,
  ): Promise<IShoppingSku> {
    try {
      return await getShoppingProductsProductCodeSkusSkuCode({
        productCode,
        skuCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
