import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingProductsProductIdReviewAggregates } from "../../../../providers/getShoppingProductsProductIdReviewAggregates";

import { IShoppingReviewRatingAggregate } from "../../../../api/structures/IShoppingReviewRatingAggregate";

@Controller("/shopping/products/:productId/reviewAggregates")
export class ShoppingProductsReviewaggregatesController {
  /**
   * Get aggregate review/rating statistics for a specific product by unique
   * productId from materialized review aggregates.
   *
   * Retrieve pre-computed aggregate review statistics (such as total reviews
   * and average rating) for a product, identified by its unique productId.
   * These aggregate statistics are generated by the
   * shopping_review_rating_aggregates view, which is associated with the
   * shopping_products table and provides summary information for product and
   * SKU level ratings.
   *
   * This API endpoint is designed to optimize catalog and product page
   * performance by delivering immediate access to pre-aggregated rating
   * metrics, such as number of reviews and the average rating for the overall
   * product and each of its SKUs. It does not include detailed review content
   * or author information, ensuring privacy and reducing data volume for client
   * applications.
   *
   * Internally, this endpoint cross-references the requested productId with the
   * shopping_products table to verify existence, and then queries the review
   * aggregates for that product. All metrics are derived directly from the
   * shopping_review_rating_aggregates model as defined in the Prisma schema,
   * including product-level and per-SKU review statistics.
   *
   * No authentication is required for this endpoint, as rating information is
   * public and intended for use across the catalog and product listing pages.
   * Error conditions, such as a missing or invalid productId, return standard
   * not found or validation errors as per platform conventions.
   *
   * @param connection
   * @param productId Unique identifier of the product whose review aggregates
   *   are requested. This must match the id field (UUID) in the
   *   shopping_products table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IShoppingReviewRatingAggregate> {
    try {
      return await getShoppingProductsProductIdReviewAggregates({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
