import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getShoppingBusinessPoliciesPolicyName } from "../../../providers/getShoppingBusinessPoliciesPolicyName";

import { IShoppingBusinessPolicy } from "../../../api/structures/IShoppingBusinessPolicy";

@Controller("/shopping/businessPolicies/:policyName")
export class ShoppingBusinesspoliciesController {
  /**
   * Retrieve a business policy configuration by unique policy name from
   * shopping_business_policies.
   *
   * Fetch detailed information for a specific business policy defined in the
   * shopping_business_policies table by policy name.
   *
   * This API is intended to expose policy details for platform rule
   * enforcement, configuration introspection, or compliance checks. The
   * policy_name path parameter must match a unique, active business policy
   * (case-insensitive string), as enforced by the Prisma schema's
   *
   * @param connection
   * @param policyName Unique policy_name string for the target business policy
   *   (global scope); must correspond to the policy_name column in the
   *   shopping_business_policies table. Policy names are case-insensitive and
   *   uniquely identify the policy rule to be fetched.
   * @@unique([policy_name,
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("policyName")
    policyName: string,
  ): Promise<IShoppingBusinessPolicy> {
    try {
      return await getShoppingBusinessPoliciesPolicyName({
        policyName,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
