import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingCustomerCustomersCustomerIdAddresses } from "../../../../../providers/postShoppingCustomerCustomersCustomerIdAddresses";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingCustomerCustomersCustomerIdAddresses } from "../../../../../providers/patchShoppingCustomerCustomersCustomerIdAddresses";
import { getShoppingCustomerCustomersCustomerIdAddressesAddressId } from "../../../../../providers/getShoppingCustomerCustomersCustomerIdAddressesAddressId";
import { putShoppingCustomerCustomersCustomerIdAddressesAddressId } from "../../../../../providers/putShoppingCustomerCustomersCustomerIdAddressesAddressId";
import { deleteShoppingCustomerCustomersCustomerIdAddressesAddressId } from "../../../../../providers/deleteShoppingCustomerCustomersCustomerIdAddressesAddressId";

import { IShoppingCustomerAddress } from "../../../../../api/structures/IShoppingCustomerAddress";
import { IPageIShoppingCustomerAddress } from "../../../../../api/structures/IPageIShoppingCustomerAddress";

@Controller("/shopping/customer/customers/:customerId/addresses")
export class ShoppingCustomerCustomersAddressesController {
  /**
   * Create a new address for a specific customer.
   *
   * This endpoint enables a customer to add a new shipping or billing address
   * to their address book. Addresses are associated with the customer's profile
   * and are needed for both order fulfillment and account management scenarios.
   * The shopping_customer_addresses table stores fields such as address lines,
   * recipient name, contact phone, street/city/state/postcode, and country. The
   * endpoint enforces validation of address format, zone, phone, and any
   * business-specific delivery constraints.
   *
   * Security is enforced so that a customer may only add addresses to their own
   * account, with ownership checks mandatory. The request body must provide all
   * required fields except for the primary key, which is generated by the
   * system. The endpoint returns the newly created address details, allowing
   * for immediate review and next-steps in checkout or profile flows.
   *
   * Related operations include listing all addresses for the customer,
   * updating/deleting addresses, and retrieving detailed information for a
   * specific address. Error scenarios covered include invalid or incomplete
   * data, unsupported delivery regions, and account permission violations.
   * Audit logs may be recorded for compliance and monitoring.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer (UUID format).
   *   (global scope)
   * @param body Data required to create a new customer address.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingCustomerAddress.ICreate,
  ): Promise<IShoppingCustomerAddress> {
    try {
      return await postShoppingCustomerCustomersCustomerIdAddresses({
        customer,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve all delivery addresses for a given customer
   * (shopping_customer_addresses).
   *
   * This endpoint retrieves all shipping and billing addresses associated with
   * a specified customer account. It operates on the
   * shopping_customer_addresses table, returning current and historical address
   * book entries for the given customerId. The customerId provided in the path
   * is a UUID that uniquely identifies the user whose addresses will be
   * fetched.
   *
   * The operation supports filtering for primary/default addresses and returns
   * sufficient address data for presentation in address selection, editing, or
   * deletion screens. For authorized actors (customer viewing their own
   * addresses, or admin performing account reviews or assistance), this
   * endpoint enables comprehensive address management. Security requirements
   * dictate that only the account owner or platform administrator may access
   * this data. Error handling includes cases where the specified customer does
   * not exist or has no associated addresses, returning an empty list where
   * appropriate.
   *
   * Pagination, sorting, and inclusion of soft-deleted (deleted_at is not null)
   * addresses may be implemented via request body (extendable in the DTO), but
   * at minimum, the full unpaginated list is returned for this base operation.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer whose address
   *   book is being fetched
   * @param body Request parameters for filtering, pagination, or sorting of
   *   customer addresses (may be null for basic list).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingCustomerAddress.IRequest,
  ): Promise<IPageIShoppingCustomerAddress> {
    try {
      return await patchShoppingCustomerCustomersCustomerIdAddresses({
        customer,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific customer address belonging to a given customerId and
   * addressId.
   *
   * This endpoint retrieves the details of a single address for a customer in
   * the shopping mall. It ensures that the returned address matches the
   * provided customerId, thereby preventing users from accessing or viewing
   * another customer's address. The shopping_customer_addresses table contains
   * current and historical addresses for each customer, allowing for accurate
   * shipping and billing management.
   *
   * Security considerations make it essential that only authenticated customers
   * can request their own address details; attempts to access another
   * customer's address must be rejected, and audit logs may be recorded for
   * compliance. The response includes all non-sensitive data required for
   * delivery, such as recipient name, contact phone, address lines,
   * city/state/country, and relevant timestamp metadata for auditing and change
   * history.
   *
   * Related operations allow customers to list all their addresses or update
   * existing address records. Error handling covers scenarios where the address
   * does not belong to the customer, is deleted, or does not exist. Appropriate
   * HTTP status codes and error messages will be returned in these situations.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer (UUID format).
   *   (global scope)
   * @param addressId Unique identifier of the address belonging to the target
   *   customer (UUID format) (scoped to customer)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":addressId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IShoppingCustomerAddress> {
    try {
      return await getShoppingCustomerCustomersCustomerIdAddressesAddressId({
        customer,
        customerId,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific address for a logged-in customer using customerId and
   * addressId.
   *
   * This operation allows an authenticated customer to update any field of
   * their own address record, such as address lines, city, state, postal code,
   * country, recipient name, phone, and indicates whether this is the primary
   * address on the account. The addressId parameter identifies the exact
   * address entry to be updated, while customerId ensures that the operation is
   * strictly scoped to the correct account holder for security and data privacy
   * reasons.
   *
   * Strict validation is enforced for every address field: address_line1 and
   * city are required and must not be empty; postal codes and phone numbers
   * must adhere to regional and carrier-specific format constraints; country
   * values should be validated against allowed international options. Only the
   * owning customer can update their own addresses, with authorization checks
   * implemented before any modification is applied.
   *
   * This update operation integrates with business logic to maintain at most
   * one primary address per customer and triggers downstream processes when
   * default addresses are changed, including notification workflows for order
   * processing and shipping. Related read operations, such as retrieving all
   * customer addresses or fetching the current primary address, provide
   * necessary context for UI address selection fields and order flows.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer (UUID format,
   *   corresponds to 'id' in shopping_customers, global scope).
   * @param addressId Unique identifier of the address to update (UUID format,
   *   corresponds to 'id' in shopping_customer_addresses, scoped to customer).
   * @param body Request body containing all fields to update for the customer
   *   address, matching IShoppingCustomerAddress.IUpdate DTO, excluding path
   *   parameters customerId and addressId.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":addressId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingCustomerAddress.IUpdate,
  ): Promise<IShoppingCustomerAddress> {
    try {
      return await putShoppingCustomerCustomersCustomerIdAddressesAddressId({
        customer,
        customerId,
        addressId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a specific address for a logged-in customer using customerId and
   * addressId (soft-delete).
   *
   * Customers may remove any of their own saved addresses by specifying both
   * their customerId (ownership verification) and the desired addressId.
   * Deleting an address is implemented as a soft delete in the database by
   * populating the deleted_at field, so address information is retained for
   * audit and compliance but is excluded from future selection, order
   * assignment, or delivery processing.
   *
   * Strict authorization is enforced: only the authenticated owner of the
   * address can perform this removal, and administrative actors cannot delete
   * customer addresses through this endpoint. Business logic checks ensure that
   * addressId corresponds to an address belonging to the supplied customerId.
   * If the deleted address was the primary address for the user, downstream
   * logic may trigger to auto-promote another address or prompt the user to set
   * a new default.
   *
   * This operation is designed to integrate with order and shipping logic to
   * ensure no active order is set to a newly removed address. It also
   * integrates with address management UI for address selection and customer
   * account views. Related endpoints allow for address retrieval, creation, or
   * updating as needed by end-user flows.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer (UUID format,
   *   corresponds to 'id' in shopping_customers, global scope).
   * @param addressId Unique identifier of the address to delete (UUID format,
   *   corresponds to 'id' in shopping_customer_addresses, scoped to customer).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":addressId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IShoppingCustomerAddress> {
    try {
      return await deleteShoppingCustomerCustomersCustomerIdAddressesAddressId({
        customer,
        customerId,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
