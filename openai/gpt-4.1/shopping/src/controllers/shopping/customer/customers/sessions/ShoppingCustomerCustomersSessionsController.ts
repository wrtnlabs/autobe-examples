import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingCustomerCustomersCustomerIdSessions } from "../../../../../providers/patchShoppingCustomerCustomersCustomerIdSessions";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";

import { IPageIShoppingCustomerSession } from "../../../../../api/structures/IPageIShoppingCustomerSession";
import { IShoppingCustomerSession } from "../../../../../api/structures/IShoppingCustomerSession";

@Controller("/shopping/customer/customers/:customerId/sessions")
export class ShoppingCustomerCustomersSessionsController {
  /**
   * Retrieve and search sessions for a specific customer account
   * (shopping_customer_sessions table).
   *
   * Retrieve a paginated and filterable list of session records for a specific
   * customer. This API enables customers to view all login sessions—including
   * concurrent and historical sessions—along with device, network, and
   * timestamp metadata. The customerId parameter identifies which customer's
   * sessions to access, ensuring that only sessions related to the
   * authenticated account are returned.
   *
   * The operation allows advanced search by session creation/expiration
   * timestamp, client IP, device type, and referrer fields. expired_at/null
   * distinction enables filtering between active and past sessions. Sensitive
   * information about session origin and network is available only to the
   * account owner or appropriate administrators. This API integrates with the
   * shopping_customer_sessions table, following all account privacy and audit
   * requirements, and supports compliance with session viewing and security
   * best practices.
   *
   * Authorization checks ensure only the owning customer or authorized admin
   * actors can view session listings. The operation aids account management,
   * device security awareness, and compliance with privacy requirements for
   * access logs. Related APIs include device logout or session revocation
   * endpoints, which can be combined for comprehensive session management
   * functionality.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer
   * @param body Filter, pagination, and search parameters for retrieving
   *   sessions of a customer
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingCustomerSession.IRequest,
  ): Promise<IPageIShoppingCustomerSession> {
    try {
      return await patchShoppingCustomerCustomersCustomerIdSessions({
        customer,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
