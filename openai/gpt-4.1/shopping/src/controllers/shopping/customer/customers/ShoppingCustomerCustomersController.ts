import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingCustomerCustomersCustomerId } from "../../../../providers/getShoppingCustomerCustomersCustomerId";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingCustomerCustomersCustomerId } from "../../../../providers/putShoppingCustomerCustomersCustomerId";
import { deleteShoppingCustomerCustomersCustomerId } from "../../../../providers/deleteShoppingCustomerCustomersCustomerId";

import { IShoppingCustomer } from "../../../../api/structures/IShoppingCustomer";

@Controller("/shopping/customer/customers/:customerId")
export class ShoppingCustomerCustomersController {
  /**
   * Retrieve detailed information for a specific shopping customer by UUID.
   *
   * This operation allows an authorized actor to retrieve the full detail of a
   * target customer's account using the unique customerId (UUID). The response
   * includes all profile data permitted by business rules and compliance, such
   * as name, email, phone number, is_active flag, and relevant timestamp
   * fields. Account status, including soft-deletion (deleted_at not null), is
   * disclosed for audit purposes.
   *
   * Access control is enforced by the actor permission model so that only
   * admins or the owner of the account (customer role) may view full details.
   * Sensitive fields are filtered according to requesting user's role.
   *
   * The underlying relation leverages the shopping_customers Prisma model.
   * Non-existent, suspended, or soft-deleted accounts are handled according to
   * business error policies, returning proper not-found or forbidden error
   * codes as appropriate. This endpoint is typically used for customer
   * self-service profile display, admin support functions, or automated system
   * integration.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer. Must be a UUID
   *   string that references the shopping_customers.id field.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingCustomer> {
    try {
      return await getShoppingCustomerCustomersCustomerId({
        customer,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update profile details for a specific shopping customer account by UUID.
   *
   * Allows an authorized actor to update account profile data for a particular
   * customer identified by customerId. Typical payloads include changes to
   * name, phone, or preferences, but cannot alter fields like email (login) or
   * account status without additional verification.
   *
   * This endpoint enforces edit permissions, ensuring only the account owner
   * (customer role) or platform admin may perform the update. The request body
   * must follow the IShoppingCustomer.IUpdate type, strictly validating each
   * field according to business requirements (e.g., valid phone format,
   * non-empty name). Attempted modification of restricted fields, or update by
   * unauthorized actor, will result in a policy-enforced error response.
   *
   * All changes are automatically audit-logged for regulatory and
   * troubleshooting purposes. Responses include the fully updated customer
   * profile data. Access and update to soft-deleted records are denied
   * according to retention rules.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer. Must be a UUID
   *   string that references the shopping_customers.id field (global scope).
   * @param body New profile fields and data to be applied to the target
   *   customer record. Follows strict validation and update policy.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingCustomer.IUpdate,
  ): Promise<IShoppingCustomer> {
    try {
      return await putShoppingCustomerCustomersCustomerId({
        customer,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes a customer account from the shopping_customers table.
   *
   * This API operation allows the irreversible deletion of a customer account
   * from the shopping mall platform. Upon invocation, it will remove the
   * customer record from the shopping_customers table using the provided
   * customerId, which is a UUID identifying the target account.
   *
   * The operation will also ensure that all related data, such as open
   * sessions, associated addresses, wishlists, carts, and user emails are
   * handled according to business retention policies. Specifically, associated
   * data may be anonymized or deleted as per legal, GDPR, or other privacy
   * guidelines. The customer's deleted_at field will be populated to indicate a
   * soft delete for audit trail purposes, while access to the account and
   * platform functionality is immediately revoked.
   *
   * Security for this operation is critical: Only an authenticated customer
   * (deleting their own account) or an admin with appropriate privilege can
   * trigger this endpoint. Proper verification and pre-deletion validation must
   * be performed to ensure that there are no unresolved or pending orders, and
   * all compliance requirements are met before deletion proceeds. Error
   * handling includes checking for non-existent or already deleted accounts,
   * and returning a clear error message if deletion cannot be completed.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingCustomerCustomersCustomerId({
        customer,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
