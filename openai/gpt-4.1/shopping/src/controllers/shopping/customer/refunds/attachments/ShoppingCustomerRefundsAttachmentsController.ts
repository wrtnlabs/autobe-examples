import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingCustomerRefundsRefundRequestIdAttachments } from "../../../../../providers/postShoppingCustomerRefundsRefundRequestIdAttachments";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingCustomerRefundsRefundRequestIdAttachments } from "../../../../../providers/patchShoppingCustomerRefundsRefundRequestIdAttachments";
import { getShoppingCustomerRefundsRefundRequestIdAttachmentsAttachmentId } from "../../../../../providers/getShoppingCustomerRefundsRefundRequestIdAttachmentsAttachmentId";
import { deleteShoppingCustomerRefundsRefundRequestIdAttachmentsAttachmentId } from "../../../../../providers/deleteShoppingCustomerRefundsRefundRequestIdAttachmentsAttachmentId";

import { IShoppingRefundAttachment } from "../../../../../api/structures/IShoppingRefundAttachment";
import { IPageIShoppingRefundAttachment } from "../../../../../api/structures/IPageIShoppingRefundAttachment";

@Controller("/shopping/customer/refunds/:refundRequestId/attachments")
export class ShoppingCustomerRefundsAttachmentsController {
  /**
   * Add a file attachment metadata record to an existing refund request
   * (shopping_refund_attachments table).
   *
   * Upload a new evidence file or attachment to a pending refund or return
   * claim. Customers, sellers, or admins may provide documentation such as
   * receipt images, defect photos, or shipping invoices to support the case.
   *
   * This operation first validates that the refund request exists and is
   * accessible to the actor, who must be either the customer who filed the
   * request, a seller listed on the order, or an admin. File type, size, and
   * quota are checked against policy constraints. On success, the operation
   * records the attachment metadata (file URI, type, and size) and links it to
   * the refundRequestId.
   *
   * The physical file upload is presumed to be completed in advance; this API
   * only registers the metadata and logical attachment link. It returns
   * metadata for the new attachment, which can then be accessed or later
   * reviewed by actor or admin. The operation enforces security, audit trail,
   * and business logic in accordance with the shopping_refund_attachments
   * schema.
   *
   * @param connection
   * @param refundRequestId Unique identifier for the refund request this
   *   attachment belongs to. Must match an existing refund case (UUID format).
   * @param body Metadata and linkage information for the new refund attachment,
   *   including file URI, type, and size. The actual file must be already
   *   uploaded and accessible via URI.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingRefundAttachment.ICreate,
  ): Promise<IShoppingRefundAttachment> {
    try {
      return await postShoppingCustomerRefundsRefundRequestIdAttachments({
        customer,
        refundRequestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * List and search all attachments for a given refund request
   * (shopping_refund_attachments).
   *
   * This API operation provides a filtered, paginated list of all
   * attachments—such as evidence images, receipts, or documents—associated with
   * a particular refund request. The refundRequestId path parameter indicates
   * which refund request's files will be retrieved. The operation supports
   * advanced search, filtering, and pagination criteria via a structured
   * request body and returns a paginated summary structure for all attachment
   * records. This is used for auditor, admin, or customer self-service review
   * of attached evidence prior to administrative action on the refund case.
   *
   * Authorization is restricted to users who are owners of the refund request
   * or administrative actors. Data is sourced from the
   * shopping_refund_attachments table, joined with the file entity and indexed
   * for efficient query by attachment_type, date, or description. Supports
   * business flows such as dispute evidence checks, refund review, or legal
   * audit. Related endpoints include refund attachment upload, deletion, and
   * download operations.
   *
   * When used in combination with administrative flows or compliance processes,
   * this endpoint enables full traceability and review for all evidence
   * associated with a given refund request.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the target refund request from
   *   which to retrieve attachments (UUID format). (global scope)
   * @param body Advanced filter and pagination request for searching or
   *   filtering refund attachments (by type, date, or keyword). Leave empty for
   *   all attachments.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingRefundAttachment.IRequest,
  ): Promise<IPageIShoppingRefundAttachment.ISummary> {
    try {
      return await patchShoppingCustomerRefundsRefundRequestIdAttachments({
        customer,
        refundRequestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get metadata for a file attachment belonging to a refund request in the
   * shopping_refund_attachments table.
   *
   * Retrieve a specific attachment linked to a refund request in the shopping
   * platform. This endpoint serves customers, sellers, and admins involved in a
   * particular refund, return, or cancellation process, providing access to
   * uploaded evidence such as photos, invoices, or compliance documents.
   *
   * Security and access control are enforced based on the refund case and user
   * actor: only the original requester (customer), affected seller, or an
   * administrator may access this resource. Unauthorized access attempts
   * trigger audit and may result in denial. The attachment is returned if it
   * exists, is linked to the given refund, and is not deleted or restricted by
   * moderation policy.
   *
   * This operation references the shopping_refund_attachments table. It checks
   * both the refundRequestId and attachmentId for relationship integrity and
   * access rules. On success, it returns structured metadata about the file
   * (including URI, type, and size) but not the binary file itself—file
   * download is handled via the file_uri property, not direct API streaming.
   *
   * @param connection
   * @param refundRequestId Unique identifier for the parent refund request.
   *   Must be a valid UUID referring to an existing refund process (scoped to
   *   the customer, seller, or admin actors as applicable).
   * @param attachmentId Unique identifier for the requested attachment record
   *   within the specified refund request (must be a valid UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":attachmentId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingRefundAttachment> {
    try {
      return await getShoppingCustomerRefundsRefundRequestIdAttachmentsAttachmentId(
        {
          customer,
          refundRequestId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete an attachment from a refund request
   * (shopping_refund_attachments).
   *
   * This operation deletes an attachment belonging to a specific refund
   * request, removing both the link and the stored file reference from the
   * refund process. It strictly enforces authorization by verifying that only
   * the actor who created the refund request, or platform administrators, can
   * perform deletion.
   *
   * The operation checks that the targeted attachmentId is actually linked
   * under the provided refundRequestId before deletion is allowed, ensuring
   * there is no accidental unlinking across requests or orphaned references.
   * Both refundRequestId and attachmentId must be valid UUIDs and correspond to
   * an existing parent-child relationship for the deletion to succeed.
   *
   * Business audit and compliance rules dictate that deleted attachments be
   * recorded in system logs. Any attempt to delete an attachment not owned by
   * the actor, or which is not linked to the specified refund request, triggers
   * an error. Attachments may not be deleted from closed or administratively
   * locked refund requests unless executed by an admin actor. Actual file blobs
   * will be deleted from storage as part of this operation to maintain storage
   * integrity.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the parent refund request
   *   containing the attachment (UUID format, global scope).
   * @param attachmentId Unique identifier for the attachment to be deleted
   *   (UUID format, must be linked to specified refund request).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":attachmentId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingCustomerRefundsRefundRequestIdAttachmentsAttachmentId(
        {
          customer,
          refundRequestId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
