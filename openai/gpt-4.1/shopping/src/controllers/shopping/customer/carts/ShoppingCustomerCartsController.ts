import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putShoppingCustomerCartsCartId } from "../../../../providers/putShoppingCustomerCartsCartId";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteShoppingCustomerCartsCartId } from "../../../../providers/deleteShoppingCustomerCartsCartId";

import { IShoppingCart } from "../../../../api/structures/IShoppingCart";

@Controller("/shopping/customer/carts/:cartId")
export class ShoppingCustomerCartsController {
  /**
   * Update and replace all items in a customer's shopping cart
   * (shopping_carts).
   *
   * Atomically replace all items in a customer's shopping cart. The request
   * fully overwrites existing items, removing any previously present but not
   * included in the current request body. This requires validation that all
   * SKUs exist, are available, and requested quantities do not exceed per-SKU
   * limits. Cart updates trigger inventory validation, check cart business
   * rules (such as max quantity per SKU), and ensure cart integrity before
   * saving. The operation is only accessible by the customer who owns the cart,
   * and will error if an unauthorized user attempts the update.
   *
   * All requests are validated according to the shopping_carts and
   * shopping_cart_items schema definitions. The endpoint does not allow partial
   * merges—clients must send the complete desired cart content. If an invalid
   * SKU, out-of-stock item, or quantity exceeding limits is provided, the
   * operation will fail with a specific error response. Successful updates
   * persist the new cart items and update the cart's modification timestamp.
   *
   * @param connection
   * @param cartId Unique identifier of the target cart (UUID format, globally
   *   unique per cart).
   * @param body Complete replacement list of cart items for the target cart.
   *   This follows the IShoppingCart.IUpdate structure, specifying all intended
   *   SKUs and quantities.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingCart.IUpdate,
  ): Promise<IShoppingCart> {
    try {
      return await putShoppingCustomerCartsCartId({
        customer,
        cartId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a customer's shopping cart and all its items (shopping_carts).
   *
   * Permanently remove a customer's shopping cart and all its associated cart
   * items from the platform. This is a hard delete—after execution, the cart
   * and its contents are removed from the system and cannot be recovered by the
   * customer. The operation verifies that the requesting customer owns the
   * specified cart before deletion, preventing unauthorized access or deletion
   * attempts. If the cartId does not exist or does not belong to the
   * authenticated customer, the operation will fail with an authorization
   * error.
   *
   * This supports customer business logic for clearing cart history or deleting
   * abandoned shopping carts, as outlined in the shopping_carts and
   * shopping_cart_items Prisma schemas. Carts removed through this operation
   * are not recoverable; users seeking to clear cart contents without deleting
   * the cart should use the update endpoint with an empty item list instead.
   *
   * @param connection
   * @param cartId Unique identifier of the cart to be deleted (UUID format,
   *   globally unique per cart).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingCustomerCartsCartId({
        customer,
        cartId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
