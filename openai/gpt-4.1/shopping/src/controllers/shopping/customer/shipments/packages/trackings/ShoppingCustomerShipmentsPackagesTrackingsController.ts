import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingCustomerShipmentsCodePackagesPackageLabelTrackings } from "../../../../../../providers/patchShoppingCustomerShipmentsCodePackagesPackageLabelTrackings";
import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { getShoppingCustomerShipmentsCodePackagesPackageLabelTrackingsTrackingSource } from "../../../../../../providers/getShoppingCustomerShipmentsCodePackagesPackageLabelTrackingsTrackingSource";

import { IPageIShoppingShipmentTracking } from "../../../../../../api/structures/IPageIShoppingShipmentTracking";
import { IShoppingShipmentTracking } from "../../../../../../api/structures/IShoppingShipmentTracking";

@Controller(
  "/shopping/customer/shipments/:code/packages/:packageLabel/trackings",
)
export class ShoppingCustomerShipmentsPackagesTrackingsController {
  /**
   * Search and retrieve all tracking instances with events for a shipment
   * package (shopping_shipment_trackings table) with advanced filtering and
   * pagination.
   *
   * This endpoint enables clients to search and paginate through all tracking
   * entries and their detailed event logs associated with a specific shipment
   * package. It operates principally on the shopping_shipment_trackings and
   * shopping_shipment_tracking_events tables, allowing for granular examination
   * of both carrier/courier tracking data and internal shipping lifecycle
   * events.
   *
   * The request body (IShoppingShipmentTracking.IRequest) supports filters for
   * tracking source (e.g., courier, warehouse scan), event window (start/end
   * date), status (in_transit, delivered, delayed, lost), and custom business
   * tag, along with pagination and sort properties. The result
   * (IPageIShoppingShipmentTracking) is a paginated array of tracking
   * instances, each including current status, last known location, and all
   * historical event records, suitable for both real-time user tracking and
   * operational or admin analytics.
   *
   * Strict access controls are enforced: only users with a direct business
   * relationship to the shipment (buyer, seller, admin) are allowed results.
   * Non-existent or mismatched codes/labels will result in failed lookups. This
   * operation supports shipping dashboards, logistics analytics, and support
   * workflows where incident investigation for lost or delayed packages is
   * necessary.
   *
   * @param connection
   * @param code Unique business identifier code for the target shipment (global
   *   scope).
   * @param packageLabel Unique business identifier label of the target package
   *   within the shipment (scoped to shipment).
   * @param body Filtering, sorting, pagination, and advanced tracking query
   *   parameters for shipment tracking events.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("code")
    code: string,
    @TypedParam("packageLabel")
    packageLabel: string,
    @TypedBody()
    body: IShoppingShipmentTracking.IRequest,
  ): Promise<IPageIShoppingShipmentTracking> {
    try {
      return await patchShoppingCustomerShipmentsCodePackagesPackageLabelTrackings(
        {
          customer,
          code,
          packageLabel,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific tracking instance for a shipment package
   * (shopping_shipment_trackings).
   *
   * This operation allows authorized actors to retrieve real-time tracking
   * information for a shipping package within a given shipment. The endpoint
   * takes the shipment business code, package label, and tracking source as
   * path parameters, ensuring precise traceability across multi-package,
   * multi-carrier orders.
   *
   * The underlying tracking logic leverages the shopping_shipment_trackings
   * table, joined with shopping_shipments and shopping_shipment_packages to
   * resolve the relationship between shipment, package, and tracking source.
   * The response provides current status, the latest status detail, and
   * metadata such as estimated delivery and the last carrier update timestamp,
   * as defined in the Prisma schema.
   *
   * Security considerations include strict enforcement of actor permissions:
   * only the customer, seller, or admin directly associated with the
   * shipment/order may access this endpoint. Unauthorized access or
   * insufficient parameterization will result in appropriate error responses.
   * Sensitive data such as carrier company and detailed status may only be
   * shown to actors with direct fulfillment responsibility (e.g., sellers,
   * admin). Related tracking event histories and status code explanations are
   * available via supplemental endpoints.
   *
   * Expected error handling scenarios include invalid or expired package
   * labels, unknown shipment codes, invalid or unsupported tracking sources,
   * permission violations, and external carrier API failures. The endpoint is
   * intended for use in shipment tracking screens, customer support dashboards,
   * and order detail pages.
   *
   * @param connection
   * @param code Unique business shipment code for the target shipment (global
   *   scope).
   * @param packageLabel Unique business label of the target package within the
   *   shipment (scoped to shipment).
   * @param trackingSource Source identifier for the tracking instance (e.g.,
   *   'courier_api', 'warehouse_scan').
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":trackingSource")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("code")
    code: string,
    @TypedParam("packageLabel")
    packageLabel: string,
    @TypedParam("trackingSource")
    trackingSource: string,
  ): Promise<IShoppingShipmentTracking> {
    try {
      return await getShoppingCustomerShipmentsCodePackagesPackageLabelTrackingsTrackingSource(
        {
          customer,
          code,
          packageLabel,
          trackingSource,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
