import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getShoppingCustomerShipmentsCodePackagesPackageLabel } from "../../../../../providers/getShoppingCustomerShipmentsCodePackagesPackageLabel";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";

import { IShoppingShipmentPackage } from "../../../../../api/structures/IShoppingShipmentPackage";

@Controller("/shopping/customer/shipments/:code/packages/:packageLabel")
export class ShoppingCustomerShipmentsPackagesController {
  /**
   * Retrieve detailed information for a specific shipment package by shipment
   * code and package label (shopping_shipment_packages table).
   *
   * This API operation retrieves the full set of details for a single shipment
   * package based on the provided shipment code and package label path
   * parameters. The underlying database table is shopping_shipment_packages,
   * which stores package-specific data such as tracking number, label,
   * dimensions, sequence in shipment, package status (pending, ready, shipped,
   * delivered, lost, damaged), and audit timestamps.
   *
   * The detailed package information includes all fields defined in the
   * shopping_shipment_packages schema and is returned only if the shipment code
   * and package label together uniquely identify a valid package. Security and
   * data privacy are strictly enforced: only the customer who placed the order,
   * the seller fulfilling the shipment, and authorized admins are permitted to
   * access these details. Attempts to access unauthorized or non-existent
   * packages will result in explicit error responses.
   *
   * This operation is typically used to power user package tracking UIs, enable
   * support for split or multi-package shipments, and deliver targeted
   * notifications about shipping events (such as package scanned, out for
   * delivery, delivered, or exceptions). If the shipment or package has been
   * soft-deleted, this operation will not return package details and may return
   * a 404 or business error.
   *
   * Integration with related shipment APIs is facilitated by using the same
   * package and shipment identification pattern; related endpoints include
   * shipment-level detail retrieval, tracking event patch, and admin shipment
   * audit.
   *
   * @param connection
   * @param code Unique business identifier code for the target shipment (global
   *   scope).
   * @param packageLabel Unique business identifier label of the target package
   *   within the shipment (scoped to shipment).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("code")
    code: string,
    @TypedParam("packageLabel")
    packageLabel: string,
  ): Promise<IShoppingShipmentPackage> {
    try {
      return await getShoppingCustomerShipmentsCodePackagesPackageLabel({
        customer,
        code,
        packageLabel,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
