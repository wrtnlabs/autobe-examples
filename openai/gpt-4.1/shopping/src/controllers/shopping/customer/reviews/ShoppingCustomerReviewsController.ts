import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingCustomerReviews } from "../../../../providers/postShoppingCustomerReviews";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingCustomerReviews } from "../../../../providers/patchShoppingCustomerReviews";
import { getShoppingCustomerReviewsReviewId } from "../../../../providers/getShoppingCustomerReviewsReviewId";
import { putShoppingCustomerReviewsReviewId } from "../../../../providers/putShoppingCustomerReviewsReviewId";
import { deleteShoppingCustomerReviewsReviewId } from "../../../../providers/deleteShoppingCustomerReviewsReviewId";

import { IShoppingReview } from "../../../../api/structures/IShoppingReview";
import { IPageIShoppingReview } from "../../../../api/structures/IPageIShoppingReview";

@Controller("/shopping/customer/reviews")
export class ShoppingCustomerReviewsController {
  /**
   * Create a new review for a SKU in an order (shopping_reviews table).
   *
   * This endpoint allows a customer who has received an order to submit a new
   * review for a specific SKU purchased as part of that order. The review must
   * include a star rating (1–5), a written comment (10–2000 characters), and
   * can optionally include up to five images or videos as attachments, each
   * less than 5MB. The customer must be authenticated and have valid
   * eligibility for the review: only SKUs actually delivered to the customer
   * (one review per SKU per order line).
   *
   * Upon submission, the API creates a new record in shopping_reviews, linking
   * the review with the customer, SKU, and order line. It checks for duplicates
   * and blocks submissions violating the one-per-order-line rule. Attachments
   * are registered via subsidiary tables and checked for file type and size.
   * The initial state of the review is typically 'visible,' but may be set to
   * 'pending_moderation' if content is flagged for abuse or requires admin
   * review.
   *
   * Only authenticated customers may create reviews via this endpoint. Sellers
   * and admins do not have access to this operation. The API responds with
   * complete review details, including unique identifiers, timestamps, and
   * links to any associated attachments.
   *
   * @param connection
   * @param body Review submission payload including rating (1–5), comment, SKU
   *   and order line associations, and optional attachments. Attachments must
   *   be referenced as URIs within constraints.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingReview.ICreate,
  ): Promise<IShoppingReview> {
    try {
      return await postShoppingCustomerReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve filtered, paginated list of product reviews
   * (shopping_reviews).
   *
   * Retrieve a filtered, paginated list of product reviews submitted by
   * customers for products and SKUs on the shopping mall platform. This
   * operation allows searching by review state, star rating, associated product
   * or SKU, customer ID, order line, keywords within comments, and date range.
   * The response includes review summary information for admin, seller, or
   * customer display, showing each review's unique identifiers, rating,
   * truncated comment, state, creation/update dates, and author details per
   * role permissions.
   *
   * Pagination and sorting are fully supported via the request body parameters,
   * with page size and offset controls. Security is enforced according to the
   * actor accessing the endpoint—admins may access all reviews, sellers those
   * for their products, and customers only their own. Integration with review
   * moderation and abuse workflows is supported. Errors include unauthorized
   * access, invalid parameters, and exceeded page size limits.
   *
   * @param connection
   * @param body Review search and filter criteria including pagination and
   *   advanced filters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingReview.IRequest,
  ): Promise<IPageIShoppingReview.ISummary> {
    try {
      return await patchShoppingCustomerReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete details for a single product review from shopping_reviews
   * table.
   *
   * Retrieve the complete record and associated data for a specific customer
   * product review by its unique reviewId (UUID, PK in shopping_reviews
   * schema). This operation is used to display all review information in
   * detail, including full text, rating, state, reviewer details, attachments,
   * and audit history if allowed. The returned data includes all fields and
   * relationships (customer, SKU, order line), for detailed view or moderation
   * workflows.
   *
   * Security and access control are based on role: customers access their own
   * reviews, sellers see reviews for their products, admins may access all.
   * Reference integrity and soft deletion are respected; if the review does not
   * exist, is deleted, or access is denied, an error or null is returned.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review (UUID as PK of
   *   shopping_reviews)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reviewId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IShoppingReview> {
    try {
      return await getShoppingCustomerReviewsReviewId({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing customer review (shopping_reviews table) within the
   * editable window.
   *
   * Allows an authenticated customer to update their own review for a given SKU
   * in a specific order line. The review can be edited only within a defined
   * period after initial submission (default 7 days); outside this window,
   * edits are blocked. The allowed fields for update are the numerical rating,
   * the written comment, and the associated attachments (e.g., up to five
   * images/videos under 5MB each). Attempts to change the review after the
   * window expires will result in error code 'REVIEW_EDIT_WINDOW_EXPIRED.'
   *
   * The API first validates review authorship, order eligibility, and update
   * permissions. It then applies changes to the review in the shopping_reviews
   * table and updates any attachments in the related records. Updated reviews
   * must pass the same content and moderation validations as new submissions.
   * The operation returns the updated review entity, including identifiers, new
   * content, and any attachments.
   *
   * Only the original customer author may use this endpoint. Reviews in
   * 'removed' or 'under_review' state are not eligible for update without admin
   * intervention.
   *
   * @param connection
   * @param reviewId Unique identifier of the existing review to be updated.
   *   Must be a valid UUID referring to a review owned by the requesting
   *   customer.
   * @param body New rating/comment/attachment data to update the review. Only
   *   permitted within the editing window (default 7 days after creation).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":reviewId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingReview.IUpdate,
  ): Promise<IShoppingReview> {
    try {
      return await putShoppingCustomerReviewsReviewId({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a specific customer review from shopping_reviews.
   *
   * This API endpoint deletes a customer review from the system by reviewId,
   * removing the review record and all its related attachments. The review must
   * exist in the shopping_reviews table and meet the criteria for deletion:
   * either the customer is the original author and within the permitted
   * edit/remove window, or an admin is performing a compliance or moderation
   * removal.
   *
   * Security considerations require strict authorization: customers may only
   * delete their own reviews within policy limits, and actions outside this
   * window are restricted to users with admin privileges. Attempts to delete
   * reviews outside these rules will return an appropriate error code and
   * rationale.
   *
   * Once this operation succeeds, the review and its references are no longer
   * available in search, product displays, or aggregation calculations. Hard
   * deletes are permanent and cannot be reversed, respecting any audit or legal
   * retention policies in effect. Error handling ensures that if the review
   * does not exist or the actor lacks permission, clear business error codes
   * are returned to the client.
   *
   * @param connection
   * @param reviewId Unique identifier of the review being deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reviewId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingCustomerReviewsReviewId({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
