import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingCustomerReviewsReviewIdAttachments } from "../../../../../providers/postShoppingCustomerReviewsReviewIdAttachments";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingCustomerReviewsReviewIdAttachments } from "../../../../../providers/patchShoppingCustomerReviewsReviewIdAttachments";
import { getShoppingCustomerReviewsReviewIdAttachmentsAttachmentId } from "../../../../../providers/getShoppingCustomerReviewsReviewIdAttachmentsAttachmentId";
import { deleteShoppingCustomerReviewsReviewIdAttachmentsAttachmentId } from "../../../../../providers/deleteShoppingCustomerReviewsReviewIdAttachmentsAttachmentId";

import { IShoppingReviewAttachment } from "../../../../../api/structures/IShoppingReviewAttachment";
import { IPageIShoppingReviewAttachment } from "../../../../../api/structures/IPageIShoppingReviewAttachment";

@Controller("/shopping/customer/reviews/:reviewId/attachments")
export class ShoppingCustomerReviewsAttachmentsController {
  /**
   * Attach a new file to a specific review as an image, video, or document
   * attachment.
   *
   * This API operation registers a new attachment to an existing review. Only
   * the review's author (customer) and admins (admin) are permitted actors.
   * Files are uploaded externally, and this API registers their metadata and
   * attaches them to a review.
   *
   * The review must be active and visible. Only reviews owned by the
   * authenticated customer or by admins may have attachments created. Files and
   * metadata (type, URI, size) are validated against all constraints—including
   * type, size, and per-review attachment limits. Records are inserted into
   * shopping_review_attachments and returned to the client. Auditing is
   * mandatory.
   *
   * @param connection
   * @param reviewId Unique identifier of the review to which the attachment
   *   will be associated (UUID).
   * @param body Metadata and file info for the attachment to register on a
   *   review. Files must already be uploaded to a storage URI before calling
   *   this API.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingReviewAttachment.ICreate,
  ): Promise<IShoppingReviewAttachment> {
    try {
      return await postShoppingCustomerReviewsReviewIdAttachments({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve all attachments for a specific customer review from
   * shopping_review_attachments.
   *
   * This API endpoint provides a comprehensive list of all files, images, or
   * videos attached to a customer product review, based on the unique reviewId
   * provided. Results are drawn from the shopping_review_attachments table,
   * which includes metadata such as file URIs, types, creation time, and soft
   * delete status. Attachments are tightly coupled to reviews and help enrich
   * product detail, assist in moderation, or offer evidence in customer service
   * cases.
   *
   * The operation supports advanced searching and filtering with request body
   * parameters, which may include file type, upload date range, and attachment
   * status. Results are paginated for efficiency. Authorization permits review
   * owners (customers) as well as admins and platform moderators to retrieve
   * this information. Attempts to access attachments for non-existent or
   * unauthorized reviews result in detailed business error messages. Data
   * returned excludes files marked as deleted unless specified.
   *
   * Related APIs include PATCH /reviews (for review searching) and GET
   * /products/{productId}/reviews for broader context. This endpoint is
   * essential for transparency in the feedback process and compliance with
   * content moderation requirements.
   *
   * @param connection
   * @param reviewId Unique identifier of the parent review for attachment
   *   lookup
   * @param body Filtering, search, and pagination options for attachments
   *   retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingReviewAttachment.IRequest,
  ): Promise<IPageIShoppingReviewAttachment> {
    try {
      return await patchShoppingCustomerReviewsReviewIdAttachments({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific attachment for a review by reviewId and attachmentId.
   *
   * This API operation retrieves the metadata and download URI for a single
   * attachment associated with a specific review. Clients may use this to fetch
   * images, videos, or documents included as part of a customer review.
   *
   * Strict authorization is enforced: only the review author (customer),
   * business admins (admin), or relevant seller-side actors (seller) may access
   * the attachment resource. Soft-deleted records are excluded, and requests
   * for non-associated attachment/review pairs are treated as not found.
   *
   * If validation fails (review not found, attachment missing/deleted, or auth
   * failure), an error is returned. The response includes the attachment's
   * metadata and its secure URI (string). Attachments are always associated to
   * their parent review and never exposed if the review is deleted or locked
   * for moderation. All accesses are audited.
   *
   * This operation references shopping_reviews and shopping_review_attachments.
   * Fine-grained error handling is recommended.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review for which the
   *   attachment is requested (UUID).
   * @param attachmentId Unique identifier of the attachment file to retrieve
   *   within the specified review (UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":attachmentId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingReviewAttachment> {
    try {
      return await getShoppingCustomerReviewsReviewIdAttachmentsAttachmentId({
        customer,
        reviewId,
        attachmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete an attachment from a review by review ID and attachment
   * ID (shopping_review_attachments table).
   *
   * This operation allows a customer (who created the review) or an admin to
   * permanently remove an attachment (such as an image or video) from a
   * specific product review. The review is identified by its unique 'reviewId'
   * UUID, and the attachment is specified by its unique 'attachmentId' UUID,
   * ensuring only the correct file is deleted.
   *
   * Removal of an attachment is immediate and cannot be undone; if the
   * attachment file is shared elsewhere on the platform, it is only removed
   * from the current review context. Security checks ensure that only the
   * owning customer or an authorized admin can perform this deletion. The
   * operation is especially important for compliance with user privacy,
   * copyright, and moderation requests (such as removing inappropriate or
   * private content).
   *
   * This operation interacts closely with the 'shopping_review_attachments'
   * Prisma table, which links files to reviews using the defined UUIDs. All
   * deletions are logged for audit history. Error cases include deletion of
   * attachments that do not exist, belong to another user, or have already been
   * deleted; these return a not found or forbidden error. Related operations
   * include adding attachments when editing or creating reviews and
   * admin-initiated moderation workflows.
   *
   * @param connection
   * @param reviewId Unique identifier of the review to which the attachment
   *   belongs
   * @param attachmentId Unique identifier of the attachment to be deleted from
   *   the review
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":attachmentId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingCustomerReviewsReviewIdAttachmentsAttachmentId(
        {
          customer,
          reviewId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
