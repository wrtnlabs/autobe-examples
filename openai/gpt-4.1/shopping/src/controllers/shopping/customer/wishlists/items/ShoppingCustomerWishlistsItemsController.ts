import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingCustomerWishlistsWishlistIdItems } from "../../../../../providers/postShoppingCustomerWishlistsWishlistIdItems";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingCustomerWishlistsWishlistIdItems } from "../../../../../providers/patchShoppingCustomerWishlistsWishlistIdItems";
import { getShoppingCustomerWishlistsWishlistIdItemsItemId } from "../../../../../providers/getShoppingCustomerWishlistsWishlistIdItemsItemId";
import { putShoppingCustomerWishlistsWishlistIdItemsItemId } from "../../../../../providers/putShoppingCustomerWishlistsWishlistIdItemsItemId";
import { deleteShoppingCustomerWishlistsWishlistIdItemsItemId } from "../../../../../providers/deleteShoppingCustomerWishlistsWishlistIdItemsItemId";

import { IShoppingWishlistItem } from "../../../../../api/structures/IShoppingWishlistItem";
import { IPageIShoppingWishlistItem } from "../../../../../api/structures/IPageIShoppingWishlistItem";

@Controller("/shopping/customer/wishlists/:wishlistId/items")
export class ShoppingCustomerWishlistsItemsController {
  /**
   * Add a SKU item to an existing customer wishlist (shopping_wishlists,
   * shopping_wishlist_items).
   *
   * Allow a logged-in customer to add a SKU to their personal wishlist. The
   * wishlistId path parameter identifies the customer's wishlist, and the
   * requestBody provides the SKU's unique code.
   *
   * The API validates that the wishlist is owned by the requesting customer and
   * that the SKU exists in the catalog. Duplicate entries for the same SKU
   * within a wishlist are not permitted, ensuring SKU uniqueness in the
   * wishlist. If the SKU is inactive or does not exist, an error is returned.
   *
   * Security is enforced so only the wishlist owner can add items, and the
   * response returns the updated wishlist item information upon success. All
   * writes trigger audit logging for personalization and compliance.
   *
   * @param connection
   * @param wishlistId Unique identifier (UUID) of the target wishlist (must
   *   belong to the authenticated customer).
   * @param body SKU code to add to wishlist. Must reference an existing SKU in
   *   the catalog.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingWishlistItem.ICreate,
  ): Promise<IShoppingWishlistItem> {
    try {
      return await postShoppingCustomerWishlistsWishlistIdItems({
        customer,
        wishlistId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve paginated items in a specific customer's wishlist by wishlistId.
   *
   * Query wishlist items for a specific wishlist by its unique identifier. This
   * operation enables customers to view the contents of their wishlist,
   * including product SKUs, variant information, and addition timestamps.
   *
   * This endpoint provides pagination and filtering options to support large
   * wishlists and can be extended with search criteria (e.g., filter by product
   * name or SKU code). Only customers can retrieve their own wishlists;
   * attempting to access a wishlist owned by another user will result in an
   * authorization error.
   *
   * The data structure returns an array of wishlist items with full SKU
   * details, enabling integration with the shopping catalog for displaying
   * product images, names, and prices. Security ensures customers cannot access
   * or modify others' wishlists. Related APIs include wishlist creation, item
   * addition/removal, and wishlist deletion.
   *
   * @param connection
   * @param wishlistId Unique identifier of the target wishlist (UUID).
   * @param body Request criteria for retrieving wishlist items, supporting
   *   pagination, filtering, or search.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingWishlistItem.IRequest,
  ): Promise<IPageIShoppingWishlistItem> {
    try {
      return await patchShoppingCustomerWishlistsWishlistIdItems({
        customer,
        wishlistId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific wishlist item by itemId in a
   * wishlist.
   *
   * Retrieve a single wishlist item by its unique itemId within the context of
   * a given wishlist. This endpoint allows customers to see detailed
   * information about an item saved for later, including SKU reference, product
   * info, addition date, and any supplementary attributes.
   *
   * The combination of wishlistId and itemId ensures both correct scoping and
   * secure access control. Only authenticated users who own the specified
   * wishlist can fetch associated items; access is denied otherwise. Returns
   * the wishlist item with necessary foreign key references to enable deeper
   * catalog lookups or move-to-cart actions.
   *
   * This operation is critical for enabling seamless user experiences around
   * wishlist item management and transitions to purchase flows.
   *
   * @param connection
   * @param wishlistId Unique identifier of the target wishlist (UUID).
   * @param itemId Unique identifier of the wishlist item to retrieve (UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingWishlistItem> {
    try {
      return await getShoppingCustomerWishlistsWishlistIdItemsItemId({
        customer,
        wishlistId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update fields of a specific wishlist item for the authenticated customer
   * (shopping_wishlist_items).
   *
   * Allows a customer to update a wishlist item, such as attaching a note or
   * modifying optional user-controlled metadata. The wishlistId path parameter
   * specifies which wishlist is targeted, and itemId specifies the particular
   * wishlist item.
   *
   * The request body provides the update information. The API first validates
   * the ownership of the wishlist and the item's existence. Only the owner
   * (authenticated customer) can update their wishlist items.
   *
   * Fields not present in the request body retain their existing values. Audit
   * logging of changes is performed for compliance and traceability.
   *
   * @param connection
   * @param wishlistId Unique identifier (UUID) of the wishlist that owns the
   *   item (must belong to the authenticated customer).
   * @param itemId Unique identifier (UUID) of the wishlist item to update.
   * @param body Fields to update for the wishlist item. Only user-controlled
   *   metadata fields are updateable; other fields (such as SKU reference)
   *   remain immutable.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":itemId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingWishlistItem.IUpdate,
  ): Promise<IShoppingWishlistItem> {
    try {
      return await putShoppingCustomerWishlistsWishlistIdItemsItemId({
        customer,
        wishlistId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Removes an item from the authenticated customer's wishlist.
   *
   * This API operation enables a logged-in customer to delete a specific item
   * from their wishlist. The endpoint requires the wishlist and item
   * identifiers as path parameters. The operation validates that the requester
   * is the owner of the wishlist via their authenticated customer session, then
   * proceeds to delete the wishlist item entry. If the wishlist or item does
   * not exist, or belong to a different customer, the operation fails with an
   * appropriate error message. The underlying SKU remains unaffected; only the
   * link between the wishlist and the SKU is removed. No soft-deletion is
   * performed as the schema does not support this for wishlist items.
   *
   * Security enforcement ensures that no customer can remove items from another
   * user's wishlist, and the operation is not available to sellers or admins.
   * Usage is tracked via standard audit logs attached to customer actions. This
   * serves the core business goal of allowing flexible management over users'
   * wishlist preferences and maintains accuracy of their favorites list. Errors
   * are handled gracefully with clear feedback.
   *
   * Typical usage involves customers managing their wishlists, removing items
   * they are no longer interested in, especially before making cart decisions
   * or as SKUs become unavailable. Business logic also ensures wishlist
   * integrity is maintained if customers merge accounts or if items are deleted
   * from the catalog.
   *
   * @param connection
   * @param wishlistId Unique identifier of the target wishlist (owned by the
   *   customer)
   * @param itemId Unique identifier of the wishlist item to remove from the
   *   wishlist (linked to a SKU)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":itemId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingCustomerWishlistsWishlistIdItemsItemId({
        customer,
        wishlistId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
