import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingCustomerWishlists } from "../../../../providers/patchShoppingCustomerWishlists";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingCustomerWishlistsWishlistId } from "../../../../providers/getShoppingCustomerWishlistsWishlistId";
import { putShoppingCustomerWishlistsWishlistId } from "../../../../providers/putShoppingCustomerWishlistsWishlistId";
import { deleteShoppingCustomerWishlistsWishlistId } from "../../../../providers/deleteShoppingCustomerWishlistsWishlistId";

import { IPageIShoppingWishlistItem } from "../../../../api/structures/IPageIShoppingWishlistItem";
import { IShoppingWishlist } from "../../../../api/structures/IShoppingWishlist";

@Controller("/shopping/customer/wishlists")
export class ShoppingCustomerWishlistsController {
  /**
   * Search and retrieve a paginated, filtered list of wishlist SKUs for the
   * authenticated customer.
   *
   * Allows a logged-in customer to view the contents of their wishlist as a
   * paginated collection with optional search, filtering, and sorting. Each
   * wishlist item entry represents a SKU the customer has added to their
   * wishlist, and includes relevant product and variant information summarized
   * for efficient display.
   *
   * Access is restricted to the authenticated customer; other roles and actors
   * are not permitted to view or modify another user's wishlist through this
   * endpoint. The operation integrates wishlist data with associated product
   * and SKU metadata, respecting the integrity of the underlying schema.
   *
   * Sensitive or unavailable products (e.g., out of stock, archived, or deleted
   * SKUs) are accurately represented, and the API supports edge cases where
   * wishlist items have become unavailable. Security considerations include
   * ensuring users cannot enumerate or access wishlists not owned by them.
   * Related endpoints may cover adding/removing wishlist items, which are
   * outside the read/search scope of this operation.
   *
   * The response includes only summary-level SKU and product data for quick
   * rendering, and details the most recent update to each wishlist item for
   * sorting or display purposes.
   *
   * @param connection
   * @param body Filter, search, and pagination options for retrieving wishlist
   *   SKUs (by name, SKU code, product attributes, tags, page size, etc.)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingWishlist.IRequest,
  ): Promise<IPageIShoppingWishlistItem.ISummary> {
    try {
      return await patchShoppingCustomerWishlists({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details and SKU items from a specific customer wishlist by unique
   * identifier.
   *
   * Fetches a specific wishlist for the authenticated user, identified by its
   * unique wishlistId. The API returns comprehensive information about the
   * wishlist, including its metadata and all contained SKU items, with
   * associated product summaries relevant for account or dashboard display.
   *
   * Access is strictly limited to the wishlist owner (authenticated customer
   * role), ensuring data security and privacy. Administrative and seller actors
   * cannot use this endpoint to access or enumerate customer wishlists.
   *
   * If the specified wishlist is deleted, does not exist, or does not belong to
   * the authenticated user, a suitable error is returned. The detailed view
   * supports client rendering of wishlists for customer accounts and can be
   * used to power account overview pages or personalized suggestions.
   * Cross-user access and unauthorized enumeration are prohibited.
   *
   * @param connection
   * @param wishlistId Unique identifier of the target wishlist for the
   *   authenticated customer
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":wishlistId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
  ): Promise<IShoppingWishlist> {
    try {
      return await getShoppingCustomerWishlistsWishlistId({
        customer,
        wishlistId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing wishlist belonging to a customer.
   *
   * This API operation allows a customer to update an existing wishlist
   * identified by its unique wishlistId. The wishlist can be modified to change
   * its properties such as the update timestamp or display name, in accordance
   * with the system's business rules.
   *
   * Access to this endpoint requires the customer to be currently authenticated
   * and to own the wishlist being updated. The update follows the
   * shopping_wishlists schema as defined in the Prisma DB, which ensures that
   * users can modify only their own wishlists. Attempts to update non-existent
   * or unauthorized wishlists will result in appropriate error messages.
   *
   * Changes to wishlists through this API are audited and tracked, contributing
   * to overall data integrity and user accountability. The endpoint helps
   * customers effectively manage their wishlists and keep changes synchronized
   * with their account preferences.
   *
   * @param connection
   * @param wishlistId Unique identifier of the wishlist to update
   * @param body Fields to update in the wishlist
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":wishlistId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingWishlist.IUpdate,
  ): Promise<IShoppingWishlist> {
    try {
      return await putShoppingCustomerWishlistsWishlistId({
        customer,
        wishlistId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove an existing wishlist belonging to a customer.
   *
   * This API operation allows a customer to delete their own wishlist,
   * referenced by the wishlistId parameter, in the shopping_wishlists table.
   * The deletion is performed as a soft-delete—filling in the deleted_at
   * timestamp field instead of permanently erasing the data—so that audit
   * trails and regulatory requirements are satisfied.
   *
   * Authentication is mandatory, and the system will validate that the customer
   * requesting deletion owns the relevant wishlist. If the wishlist does not
   * exist or does not belong to the user, the system will respond with an
   * error. In accordance with audit and compliance requirements, deleted
   * wishlists are marked as such for traceability rather than removed.
   *
   * Proper authorization is enforced to ensure only the owner can remove their
   * wishlists, maintaining the security model established in the database
   * schema. This operation complies with best practices for personal data
   * retention, user empowerment, and business integrity.
   *
   * @param connection
   * @param wishlistId Unique identifier of the wishlist to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":wishlistId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
  ): Promise<IShoppingWishlist> {
    try {
      return await deleteShoppingCustomerWishlistsWishlistId({
        customer,
        wishlistId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
