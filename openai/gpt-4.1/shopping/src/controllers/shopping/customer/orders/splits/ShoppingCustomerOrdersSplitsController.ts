import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getShoppingCustomerOrdersOrderCodeSplitsSplitCode } from "../../../../../providers/getShoppingCustomerOrdersOrderCodeSplitsSplitCode";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";

import { IShoppingOrderSplit } from "../../../../../api/structures/IShoppingOrderSplit";

@Controller("/shopping/customer/orders/:orderCode/splits/:splitCode")
export class ShoppingCustomerOrdersSplitsController {
  /**
   * Retrieve detail for a specific order split by order and split code.
   *
   * This endpoint fetches the complete data for an order split identified by
   * the composite keys 'orderCode' and 'splitCode', referencing the
   * shopping_orders and shopping_order_splits tables. It returns split-level
   * detail such as seller allocation, status, subtotal price, and fulfillment
   * progress.
   *
   * Permission control ensures only the related customer, seller assigned to
   * this split, or an admin may access this information. The operation is
   * crucial for both customers tracking a multi-seller order and sellers
   * viewing their segment of a customer's order.
   *
   * The returned data provides all split attributes, audits, and relationships
   * needed for business logic, dashboard displays, seller support, and customer
   * self-service. Related endpoints include top-level order retrieval, line
   * item details, and order audit logs.
   *
   * @param connection
   * @param orderCode Globally unique business reference code for the parent
   *   order (global scope).
   * @param splitCode Unique code identifying the split sub-order for a specific
   *   seller within the order (scoped to order).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedParam("splitCode")
    splitCode: string,
  ): Promise<IShoppingOrderSplit> {
    try {
      return await getShoppingCustomerOrdersOrderCodeSplitsSplitCode({
        customer,
        orderCode,
        splitCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
