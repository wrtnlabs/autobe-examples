import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingCustomerOrdersOrderCodeStatusHistory } from "../../../../../providers/patchShoppingCustomerOrdersOrderCodeStatusHistory";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingCustomerOrdersOrderCodeStatusHistoryOrderStatusHistoryId } from "../../../../../providers/getShoppingCustomerOrdersOrderCodeStatusHistoryOrderStatusHistoryId";

import { IPageIShoppingOrderStatusHistory } from "../../../../../api/structures/IPageIShoppingOrderStatusHistory";
import { IShoppingOrderStatusHistory } from "../../../../../api/structures/IShoppingOrderStatusHistory";

@Controller("/shopping/customer/orders/:orderCode/status-history")
export class ShoppingCustomerOrdersStatus_historyController {
  /**
   * Retrieve a filtered, paginated list of status change histories for a
   * specific order by order_code.
   *
   * This operation allows authorized users (admin, seller for their orders, or
   * customer for their own order) to retrieve a paginated list of all status
   * change events for a designated order from shopping_order_status_histories.
   * The endpoint expects the unique order_code as a path parameter, resolves
   * the corresponding order in shopping_orders, and then performs a joined
   * query on shopping_order_status_histories to collect all transitions,
   * including their timestamps, actors, from_status, to_status, and optional
   * event notes.
   *
   * Filtering parameters in the request body enable advanced search—for
   * example, by specific status transitions, triggering actor, or a date/time
   * window. The response contains paginated status history entries which are
   * useful for customer transparency, seller operational review, or
   * administrative audit. Access is gated so that customers only retrieve their
   * own order histories, sellers only see those tied to their products, and
   * admins may access any order's status transitions. Edge cases and error
   * handling are present: if the order_code does not exist, or the requester
   * lacks permission, a detailed business error is returned.
   *
   * @param connection
   * @param orderCode Unique business identifier code of the target order
   *   (global scope)
   * @param body Filtering, sorting, and pagination request for order status
   *   histories.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedBody()
    body: IShoppingOrderStatusHistory.IRequest,
  ): Promise<IPageIShoppingOrderStatusHistory> {
    try {
      return await patchShoppingCustomerOrdersOrderCodeStatusHistory({
        customer,
        orderCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single order status history event by order code and status
   * history ID.
   *
   * This operation fetches a single status change event from an order's
   * history, allowing users or administrators to review the full details of how
   * and when an order's state was altered. Each event captures the transition's
   * previous and new statuses, the actor (such as the system, customer, seller,
   * or admin) that initiated the change, the event note (if any), and an exact
   * timestamp (occurred_at).
   *
   * The details are composed from the shopping_order_status_histories schema,
   * referencing the associated order from shopping_orders by order_code. This
   * enables both deep forensic analysis (e.g., for fraud or shipping errors)
   * and informative UI displays (e.g., order tracking timelines for
   * customers).
   *
   * Only actors with proper visibility to the order in question (customer who
   * owns the order, the relevant seller, or platform admin) should be
   * authorized. The operation does not expose confidential business logic, but
   * ensures complete traceability as required by audit and compliance.
   *
   * Access to this endpoint must be secure and properly scoped to avoid leaking
   * data from orders that do not belong to the requesting actor. All status
   * event details align strictly with underlying order and status schema
   * documentation.
   *
   * @param connection
   * @param orderCode Globally unique, human-readable code of the target order
   *   (global scope)
   * @param orderStatusHistoryId Unique identifier (UUID) for the specific
   *   status history event entry (scoped to order)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderStatusHistoryId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedParam("orderStatusHistoryId")
    orderStatusHistoryId: string & tags.Format<"uuid">,
  ): Promise<IShoppingOrderStatusHistory> {
    try {
      return await getShoppingCustomerOrdersOrderCodeStatusHistoryOrderStatusHistoryId(
        {
          customer,
          orderCode,
          orderStatusHistoryId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
