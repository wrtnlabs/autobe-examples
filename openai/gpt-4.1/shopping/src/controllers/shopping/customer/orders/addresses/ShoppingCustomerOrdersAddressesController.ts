import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingCustomerOrdersOrderCodeAddresses } from "../../../../../providers/patchShoppingCustomerOrdersOrderCodeAddresses";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingCustomerOrdersOrderCodeAddressesOrderAddressId } from "../../../../../providers/getShoppingCustomerOrdersOrderCodeAddressesOrderAddressId";

import { IPageIShoppingOrderAddress } from "../../../../../api/structures/IPageIShoppingOrderAddress";
import { IShoppingOrderAddress } from "../../../../../api/structures/IShoppingOrderAddress";

@Controller("/shopping/customer/orders/:orderCode/addresses")
export class ShoppingCustomerOrdersAddressesController {
  /**
   * List all shipping and billing addresses associated with a given order.
   *
   * This API operation provides a comprehensive paginated list of all address
   * records related to the specified order, as stored in the
   * shopping_order_addresses table. The endpoint supports detailed querying so
   * actors can filter addresses by type (shipping, billing), search by
   * recipient name, or paginate through the addresses if an order includes
   * multiple address entries (for instance, split shipments or gifts).
   *
   * This operation is essential for reconciliation of order fulfillment,
   * auditing customer-provided addresses, and troubleshooting delivery issues.
   * Permissions should restrict this table to authenticated customers for their
   * own orders, relevant sellers, and platform admins. Related API operations
   * include general order detail endpoints and shipment tracking endpoints. The
   * implementation relies on accurate mapping of orderCode (globally unique
   * human-readable order reference) to its order addresses, with validation and
   * safe error handling for missing or unauthorized access.
   *
   * The operation integrates database pagination and search best practices and
   * is built to include future filtering extensions as needed (such as address
   * type or recipient search).
   *
   * @param connection
   * @param orderCode Globally unique identifier code for the target order
   *   (human-readable, global scope).
   * @param body Request parameters allowing address search, filtering (by type
   *   or recipient), and pagination options.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedBody()
    body: IShoppingOrderAddress.IRequest,
  ): Promise<IPageIShoppingOrderAddress.ISummary> {
    try {
      return await patchShoppingCustomerOrdersOrderCodeAddresses({
        customer,
        orderCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific order address by order code and address ID
   * (shopping_order_addresses).
   *
   * This API provides detailed information for a single address record
   * associated with an order, such as shipping or billing addresses. The
   * request requires two parameters: the unique business order code (as
   * assigned upon order creation for global reference) and the address record
   * ID.
   *
   * Use cases include customer order tracking, shipment preparation by sellers,
   * and auditing by admin users. The response includes all address fields
   * defined in the Prisma table, ensuring sufficient information for delivery
   * confirmations and legal compliance.
   *
   * Access to this endpoint is typically restricted: only the owning customer,
   * fulfillment sellers, or admin users may access the address, with checks
   * enforced at the controller/service layer. No request body is needed; all
   * necessary context comes via path parameters.
   *
   * If either orderCode or orderAddressId is invalid or does not exist, the
   * operation will return a 404 error. Sensitive data (such as phone numbers)
   * may be filtered based on actor permissions. This operation relies on the
   * integrity of both the shopping_orders and shopping_order_addresses tables,
   * referencing each entity's description for compliance and auditability.
   *
   * @param connection
   * @param orderCode Globally unique business order code for the target order
   *   (global scope)
   * @param orderAddressId Unique identifier of the target order address record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderAddressId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedParam("orderAddressId")
    orderAddressId: string & tags.Format<"uuid">,
  ): Promise<IShoppingOrderAddress> {
    try {
      return await getShoppingCustomerOrdersOrderCodeAddressesOrderAddressId({
        customer,
        orderCode,
        orderAddressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
