import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingCustomerOrders } from "../../../../providers/postShoppingCustomerOrders";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingCustomerOrders } from "../../../../providers/patchShoppingCustomerOrders";
import { getShoppingCustomerOrdersOrderCode } from "../../../../providers/getShoppingCustomerOrdersOrderCode";
import { putShoppingCustomerOrdersOrderCode } from "../../../../providers/putShoppingCustomerOrdersOrderCode";
import { deleteShoppingCustomerOrdersOrderCode } from "../../../../providers/deleteShoppingCustomerOrdersOrderCode";

import { IShoppingOrder } from "../../../../api/structures/IShoppingOrder";
import { IPageIShoppingOrder } from "../../../../api/structures/IPageIShoppingOrder";

@Controller("/shopping/customer/orders")
export class ShoppingCustomerOrdersController {
  /**
   * Create a new order in the system when a customer performs checkout
   * (shopping_orders).
   *
   * This endpoint processes a completed customer checkout and translates it
   * into a new order in the shopping_orders table. The operation accepts a
   * well-structured order creation payload (IShoppingOrder.ICreate) containing
   * the customer's ID, delivery/billing addresses (either selected or entered
   * anew), product SKUs and quantities, total pricing, selected payment method,
   * and any relevant contextual/coupon codes.
   *
   * Upon validation and business checks (e.g., inventory, eligibility,
   * address), the API atomically creates the new order with one or more order
   * lines (for each SKU), computes seller splits if multiple sellers are
   * present, and reserves inventory. It generates a globally unique order_code,
   * sets the order status to the initial workflow state (such as 'pending'),
   * and creates references to status history and payment attempt entities. On
   * success, the API returns the entire created IShoppingOrder instance.
   * Inventory is locked as necessary to prevent overselling, and security
   * checks enforce correct actor usage and business constraints.
   *
   * Edge and error cases such as insufficient inventory, invalid address, or
   * payment method failure trigger appropriate error responses. The operation
   * is open to authenticated customers only and is the central entry point for
   * order creation in the shopping platform.
   *
   * @param connection
   * @param body Comprehensive information about the new order: customer, SKUs,
   *   delivery/billing address, pricing, payment option, and all line items,
   *   adhering to the IShoppingOrder.ICreate schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingOrder.ICreate,
  ): Promise<IShoppingOrder> {
    try {
      return await postShoppingCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of the authenticated
   * customer's orders.
   *
   * This endpoint allows authenticated customers to search and retrieve a
   * paginated list of their orders by applying complex filter conditions,
   * sorting, and pagination controls. The list supports filtering by status
   * (such as completed, pending, cancelled), order_code for business
   * traceability, and allows limiting results to certain date ranges. The query
   * is submitted in the request body following the IRequest pattern, making it
   * possible to extend with additional filters as business requirements grow.
   *
   * The operation ensures customers can only fetch their own orders, never
   * another account's data. Results return essential order information such as
   * order_code, total_price, status, key timestamps, and summary details for
   * display on history screens. Sensitive data and PII from related customers
   * or sellers are excluded from the result for privacy compliance.
   *
   * Error handling is robust: if a requester is not authenticated or requests
   * orders they do not own, the API returns a clear error. Pagination, search,
   * and sorting are all supported by the IRequest DTO, and UI can traverse
   * through multiple pages of orders efficiently. The implementation serves
   * common use cases such as order history lookups, after-sales tracking, and
   * download/export of order summaries.
   *
   * @param connection
   * @param body Filter conditions, sorting, and pagination parameters for order
   *   search
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingOrder.IRequest,
  ): Promise<IPageIShoppingOrder.ISummary> {
    try {
      return await patchShoppingCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific order using its unique order code
   * (shopping_orders).
   *
   * This endpoint enables authorized actors (customer, seller, or admin,
   * depending on context) to retrieve all information for a specific order
   * based on its unique business order code. The response includes the complete
   * order entity and related data as per the Prisma schema—specifically,
   * information on order lines, splits (for orders with multiple sellers),
   * payment attempts, fulfillment/shipment status, and all historical status
   * transitions.
   *
   * The API uses strict access control: a customer may only request their own
   * orders, a seller may only see orders for products they own, and admins may
   * access any order in the system. Security checks are performed at the
   * application layer based on actor type and order ownership, with forbidden
   * access for unauthorized requests.
   *
   * The path parameter orderCode corresponds to the order_code column in
   * shopping_orders, which is globally unique and human-readable (e.g.,
   * ORD-20240001). When the specified code is not found, a clear error is
   * returned. The endpoint is intended for use in account order history, order
   * tracking, and customer support contexts. Associated data (order lines,
   * splits, addresses, payment attempts, shipments, etc.) is included using
   * Prisma's relationships and the response type IShoppingOrder.
   *
   * @param connection
   * @param orderCode Globally unique business order code of the target order
   *   (global scope), e.g., ORD-20240001.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderCode")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
  ): Promise<IShoppingOrder> {
    try {
      return await getShoppingCustomerOrdersOrderCode({
        customer,
        orderCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shopping order given its unique order code.
   *
   * Allows an authorized user to update an order's details using its unique
   * order code.
   *
   * The operation validates business policy and order status to ensure updates
   * are permitted (e.g., updates are only allowed before fulfillment or
   * shipment depending on platform policy). The fields eligible for update are
   * governed strictly by the 'shopping_orders' schema, and audit trails record
   * every change for security and compliance.
   *
   * Appropriate validation is performed to prevent unauthorized or
   * inappropriate modification, especially for fields tied to payment,
   * fulfillment, or legal requirements. Attempts to update immutable or
   * restricted fields are rejected with clear error messages. All business
   * logic for update eligibility is enforced by platform and captured in the
   * operation's audit trail.
   *
   * @param connection
   * @param orderCode Globally unique, human-readable business reference code
   *   for the target order (global scope)
   * @param body Order update payload containing modifiable order fields as
   *   allowed by business policy. Immutable system fields such as 'order_code'
   *   and audit timestamps cannot be changed via this API.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":orderCode")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedBody()
    body: IShoppingOrder.IUpdate,
  ): Promise<IShoppingOrder> {
    try {
      return await putShoppingCustomerOrdersOrderCode({
        customer,
        orderCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete an order given its order code (logical deletion for
   * compliance).
   *
   * Performs a soft-delete on an order identified by its unique business order
   * code, marking it as deleted in the system but retaining all data for
   * compliance and future audits.
   *
   * The operation checks business rules before allowing deletion, including
   * verifying whether the order is eligible for deletion or cancellation (e.g.,
   * only orders in certain states such as 'pending' may be deleted). Any
   * attempt to delete an order not meeting these criteria is rejected with a
   * specific error message, as mandated by the platform's business logic.
   *
   * All deletion actions are recorded in the audit trail, and the order remains
   * accessible for read-only compliance, audit, or reporting activities. Hard
   * deletion is never performed to ensure data retention standards are
   * maintained.
   *
   * @param connection
   * @param orderCode Globally unique, human-readable business reference code
   *   for the target order (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":orderCode")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
  ): Promise<IShoppingOrder> {
    try {
      return await deleteShoppingCustomerOrdersOrderCode({
        customer,
        orderCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
