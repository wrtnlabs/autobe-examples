import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingAdminStatusEnums } from "../../../../providers/postShoppingAdminStatusEnums";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminStatusEnums } from "../../../../providers/patchShoppingAdminStatusEnums";
import { getShoppingAdminStatusEnumsEnumDomainStatusCode } from "../../../../providers/getShoppingAdminStatusEnumsEnumDomainStatusCode";
import { putShoppingAdminStatusEnumsEnumDomainStatusCode } from "../../../../providers/putShoppingAdminStatusEnumsEnumDomainStatusCode";
import { deleteShoppingAdminStatusEnumsEnumDomainStatusCode } from "../../../../providers/deleteShoppingAdminStatusEnumsEnumDomainStatusCode";

import { IShoppingStatusEnum } from "../../../../api/structures/IShoppingStatusEnum";
import { IPageIShoppingStatusEnum } from "../../../../api/structures/IPageIShoppingStatusEnum";

@Controller("/shopping/admin/statusEnums")
export class ShoppingAdminStatusenumsController {
  /**
   * Create a new status enum for a given domain in the shopping_status_enums
   * table.
   *
   * This API creates a new status code/enum entry used by the system for
   * categorizing orders, reviews, payments, or other entities. The request must
   * specify the domain (such as 'order', 'review'), the internal status code
   * (e.g., 'pending', 'paid', 'rejected'), a display label for UI rendering,
   * and sort order to manage list sequencing in the frontend. The 'is_active'
   * flag enables or disables this status value in business logic, and the
   * optional description field provides operators with documentation on usage.
   * New (enum_domain, status_code) pairs created through this endpoint are
   * immediately available to business workflows and system validations. Strict
   * uniqueness is enforced at the (enum_domain, status_code) composite level.
   * Use cases include customizing order or review workflows, adding
   * business-specific state transitions, and runtime configuration support
   * without code changes.
   *
   * @param connection
   * @param body Payload with enum_domain, status_code, display_label,
   *   sort_order, is_active, and optional description for the new status code
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingStatusEnum.ICreate,
  ): Promise<IShoppingStatusEnum> {
    try {
      return await postShoppingAdminStatusEnums({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated, filtered list of status enum codes.
   *
   * This endpoint provides an advanced search, filtering, and pagination
   * interface for the list of business status enums used throughout the
   * shopping platform. Each enum row represents a possible status value for a
   * particular domain (such as orders, payments, reviews), including the code,
   * display label, activity/enablement state, and sort order.
   *
   * The endpoint supports filtering the list by enum_domain (domain of usage
   * such as 'order', 'payment'), is_active flag, display_label, partial
   * status_code, and supports result ordering and pagination suitable for UI
   * dropdowns and admin console scenario. All enums are sourced from the
   * shopping_status_enums Prisma schema table, which is soft deletable and
   * allows runtime modification.
   *
   * Security and permission: This operation is intended for use by platform
   * administrators and power users, and should be restricted in production
   * systems to authenticated admin actors. However, read access can be granted
   * to trusted service actors within the system for integration or
   * configuration purposes.
   *
   * System integrations may use this endpoint to dynamically generate forms,
   * drive conditional logic, or display the correct set of allowable status
   * transitions. Any status enums marked as deleted or inactive will be
   * excluded by default unless specific filters are applied. The status enum
   * table supports full text search of display labels and code using platform
   * search indices.
   *
   * @param connection
   * @param body Advanced search, filter, pagination, and ordering parameters
   *   for status enum lookup
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingStatusEnum.IRequest,
  ): Promise<IPageIShoppingStatusEnum.ISummary> {
    try {
      return await patchShoppingAdminStatusEnums({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details for a specific status enum by domain and code.
   *
   * This endpoint fetches the full details of a single status enum value,
   * uniquely identified by the enum domain and code, from the
   * shopping_status_enums table. This information includes the status_code,
   * domain usage, human-readable display label, activity flag, description,
   * sort order, and all business context needed to interpret or render this
   * status in UIs or logic flows.
   *
   * Both the domain (enumDomain) and the exact statusCode string must be
   * specified, as the system enforces a composite unique constraint
   * (enum_domain + status_code) to guarantee uniqueness. If no matching row is
   * found, a 404 is returned. Soft-deleted status enums are not returned by
   * this endpoint unless special admin override logic is implemented.
   *
   * This operation is primarily for admin and internal system actors needing to
   * inspect status code configuration, display logic, or infrastructure mapping
   * for custom business process flows. Typical use-cases include admin form
   * rendering, integrity validation, or dynamic status mapping for operation
   * auditing and configuration.
   *
   * @param connection
   * @param enumDomain Domain or entity scope for status codes (e.g., order,
   *   review, payment); required to uniquely identify the status enum (global
   *   scope)
   * @param statusCode The exact status code string within the domain to
   *   uniquely select the status enum (scoped to enumDomain)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":enumDomain/:statusCode")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("enumDomain")
    enumDomain: string,
    @TypedParam("statusCode")
    statusCode: string,
  ): Promise<IShoppingStatusEnum> {
    try {
      return await getShoppingAdminStatusEnumsEnumDomainStatusCode({
        admin,
        enumDomain,
        statusCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing status enum’s label, activation status, or metadata in
   * shopping_status_enums.
   *
   * This API allows administrators to edit details of an existing status code
   * or enum entry, such as renaming the UI display label, reordering
   * (sort_order), flagging it as active/inactive, or updating its
   * documentation. The path parameters enumDomain (e.g., 'order', 'review',
   * 'payment') and statusCode uniquely identify which status enum to update.
   * The system enforces the unique (enum_domain, status_code) composite key to
   * prevent accidental overwrites. Typical uses include adapting business
   * language, phase-out of legacy codes, UI improvements, or localization
   * support. Updates are immediately reflected for all business logic
   * referencing the modified status code. Audit logs capture all admin changes
   * for compliance and operational traceability.
   *
   * @param connection
   * @param enumDomain Domain/context to which the status enum code belongs
   *   (e.g., 'order', 'review', 'payment'). Uniquely scopes the statusCode.
   *   (global scope)
   * @param statusCode Unique status code to update within the enumDomain (e.g.,
   *   'pending', 'paid', 'delivered', 'failed'). Uniquely identifies the enum
   *   status within its domain. (scoped to enumDomain)
   * @param body Payload for updating display_label, sort_order, is_active, and
   *   description of the status enum; enum_domain and status_code are derived
   *   from path
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":enumDomain/:statusCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("enumDomain")
    enumDomain: string,
    @TypedParam("statusCode")
    statusCode: string,
    @TypedBody()
    body: IShoppingStatusEnum.IUpdate,
  ): Promise<IShoppingStatusEnum> {
    try {
      return await putShoppingAdminStatusEnumsEnumDomainStatusCode({
        admin,
        enumDomain,
        statusCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific status enum in the shopping_status_enums table by domain
   * and code.
   *
   * This API operation irreversibly deletes a status enum row from the
   * 'shopping_status_enums' table. Status enums are centrally managed
   * definitions for allowable status codes—such as 'pending', 'paid', or
   * 'delivered'—used throughout the platform for order processing, review
   * moderation, and payment transaction outcomes.
   *
   * Each status enum exists within a particular 'enum_domain' (e.g., 'order',
   * 'review', 'payment') and is uniquely identified by its 'status_code'
   * string. Deletion of a status enum should only be performed by
   * administrators after verifying that the status code is not currently in
   * active business logic or referenced in platform workflows.
   *
   * This operation enforces business logic by ensuring only actors with
   * administrative privileges ('admin') may invoke the endpoint. Application
   * code should validate that the relevant status code is not bound to any
   * critical live entity prior to allowing deletion, or provide warnings if
   * attempted. After deletion, the status code will no longer validate in
   * domain-specific logic, and any existing records using the deleted code may
   * show as invalid or legacy. No response body is returned, indicating the
   * operation was completed. Use with caution as this is a non-recoverable
   * action.
   *
   * @param connection
   * @param enumDomain Domain/entity scope for which to delete the status enum
   *   (e.g., 'order', 'review', 'payment'). Must correspond to an existing
   *   enum_domain value in shopping_status_enums (uniqueness: global scope).
   * @param statusCode Exact status code to be deleted within the specified enum
   *   domain (e.g., 'pending', 'paid', etc.). Must correspond to an existing
   *   status_code value in shopping_status_enums for the selected domain
   *   (scoped to enumDomain).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":enumDomain/:statusCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("enumDomain")
    enumDomain: string,
    @TypedParam("statusCode")
    statusCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminStatusEnumsEnumDomainStatusCode({
        admin,
        enumDomain,
        statusCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
