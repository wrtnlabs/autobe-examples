import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingAdminProducts } from "../../../../providers/postShoppingAdminProducts";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putShoppingAdminProductsProductCode } from "../../../../providers/putShoppingAdminProductsProductCode";
import { deleteShoppingAdminProductsProductCode } from "../../../../providers/deleteShoppingAdminProductsProductCode";

import { IShoppingProduct } from "../../../../api/structures/IShoppingProduct";

@Controller("/shopping/admin/products")
export class ShoppingAdminProductsController {
  /**
   * Create a new product in the shopping_products table for the catalog.
   *
   * This API endpoint is designed for sellers (and platform admins) to create a
   * new product entry in the catalog. The process requires the submission of
   * all required fields, including product code, name, description, main image
   * URI, current status, and business status. The request will be validated
   * against the business catalog requirements, ensuring all mandatory data is
   * present and the business code is unique.
   *
   * Upon successful creation, the product is registered under the requesting
   * seller's account, attached to a specific catalog, and prepared for linking
   * with SKUs and attributes. Business and workflow status control visibility,
   * so a draft or under_review product will not be publicly visible until
   * approved and published. Attempts to create a product with a duplicate code
   * or missing vital details will result in a validation error, and
   * comprehensive error messages will be provided based on the rule violated.
   *
   * Security measures enforce that only authenticated sellers or admins may
   * invoke this operation, and all actions are auditable for compliance. The
   * created product will be available for management through subsequent
   * endpoints handling images, variants/SKUs, category assignments, and
   * publishing workflows.
   *
   * @param connection
   * @param body Detailed product creation payload as required by catalog
   *   business rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingProduct.ICreate,
  ): Promise<IShoppingProduct> {
    try {
      return await postShoppingAdminProducts({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update existing product data in the shopping_products table identified by
   * productCode.
   *
   * This API endpoint handles updates to existing products within the
   * platform's catalog. The product to be updated is specified by its globally
   * unique business product code (code), ensuring clear and unambiguous
   * resource identification. Business rules dictate that product codes are
   * immutable once orders exist for the product, and attempts to update code in
   * those cases will result in validation errors. Fields like name,
   * description, images, status, business_status, and other updatable data can
   * be modified as long as the product is eligible for changes per the business
   * logic.
   *
   * Authorization is restricted to the seller who owns the product and platform
   * admins. All successful updates are logged for compliance, and any failed
   * modification attempts due to business constraints (such as changing product
   * code after order placement) will generate structured errors indicating the
   * reason for denial.
   *
   * Error scenarios such as forbidden access, invalid product code, or field
   * violation are handled with business-specific and detailed response
   * messages. This operation complements other product management endpoints
   * (SKU and attribute management, category reassignment) in the platform's
   * product lifecycle.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target product
   *   (global scope)
   * @param body Payload with updatable product fields as defined by catalog
   *   update policy.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("productCode")
    productCode: string,
    @TypedBody()
    body: IShoppingProduct.IUpdate,
  ): Promise<IShoppingProduct> {
    try {
      return await putShoppingAdminProductsProductCode({
        admin,
        productCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a catalog product using its unique business code from
   * shopping_products.
   *
   * This endpoint allows an authorized seller or admin to permanently delete a
   * product from the catalog based on the unique business 'code' field provided
   * in the path parameter. It operates strictly on the shopping_products table
   * and enforces that only the product owner (seller) or platform admin can
   * perform this operation. The operation leverages the code's uniqueness for
   * business traceability and compliance.
   *
   * Upon successful execution, the product and its related catalog data (SKUs,
   * images, category/tag assignments) are removed based on cascade or business
   * logic. The deleted_at column in the schema tracks the soft deletion for
   * historical and audit purposes. Hard delete is strictly enforced only if no
   * active orders or legal/business restrictions exist; otherwise, the process
   * must gracefully handle constraint failures.
   *
   * This endpoint is subject to security checks: the actor must match the owner
   * for seller-level deletes, or possess adequate privileges for admin-level
   * actions. Any failure due to active orders, regulatory, or referential
   * integrity constraints will return a conflict or validation error according
   * to platform policy. Proper audit log entries should be created for all
   * delete actions, with reasons recorded for future reference. Use of this API
   * affects product visibility across listings, recommendations, and search.
   *
   * @param connection
   * @param productCode Unique business identifier code of the target product
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("productCode")
    productCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminProductsProductCode({
        admin,
        productCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
