import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingAdminOrdersOrderCodeLines } from "../../../../../providers/postShoppingAdminOrdersOrderCodeLines";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminOrdersOrderCodeLines } from "../../../../../providers/patchShoppingAdminOrdersOrderCodeLines";
import { getShoppingAdminOrdersOrderCodeLinesOrderLineId } from "../../../../../providers/getShoppingAdminOrdersOrderCodeLinesOrderLineId";
import { putShoppingAdminOrdersOrderCodeLinesOrderLineId } from "../../../../../providers/putShoppingAdminOrdersOrderCodeLinesOrderLineId";
import { deleteShoppingAdminOrdersOrderCodeLinesOrderLineId } from "../../../../../providers/deleteShoppingAdminOrdersOrderCodeLinesOrderLineId";

import { IShoppingOrderLine } from "../../../../../api/structures/IShoppingOrderLine";
import { IPageIShoppingOrderLine } from "../../../../../api/structures/IPageIShoppingOrderLine";

@Controller("/shopping/admin/orders/:orderCode/lines")
export class ShoppingAdminOrdersLinesController {
  /**
   * Add a new order line item to an existing customer order
   * (shopping_order_lines).
   *
   * This endpoint is used to append an additional SKU line item to the list of
   * products/services on an open shopping order, typically prior to order
   * finalization and payment. The new order line captures the SKU reference,
   * desired quantity, calculated or offered unit price, and links back to the
   * parent order.
   *
   * The business rules check that the specified order (by orderCode) is in an
   * editable state (not expired, deleted, or paid). Inventory is validated for
   * the SKU, and only valid SKUs from active products may be added. The system
   * ensures duplicate SKUs are not added to the same order.
   *
   * Security requires that only the account owner (customer) or platform admin
   * can add lines; sellers are not permitted to modify order items at this
   * stage. Edge cases include handling attempts to add lines to orders in a
   * non-editable or finalized state, or with invalid SKU/quantity, and
   * responding with appropriate errors. This endpoint is a core utility for
   * cart-to-order transitions and manual admin order edits.
   *
   * @param connection
   * @param orderCode Globally unique business identifier of the parent order
   *   (ORD-... pattern, global scope)
   * @param body Details for the new order line to be added, including SKU,
   *   quantity, and unit price.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedBody()
    body: IShoppingOrderLine.ICreate,
  ): Promise<IShoppingOrderLine> {
    try {
      return await postShoppingAdminOrdersOrderCodeLines({
        admin,
        orderCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve and search paginated order line items for a specific order
   * (shopping_order_lines table).
   *
   * This API operation enables detailed retrieval of all line items belonging
   * to a specific customer order, identified by its unique business order code
   * (order_code, globally unique). Clients use this endpoint to retrieve all
   * SKUs, their quantities, status, per-unit pricing, and fulfillment
   * information under the given order. The list can be filtered and sorted by
   * multiple fields, such as SKU, seller, fulfillment status, and order line
   * status.
   *
   * Security logic ensures that customers may only access line items for their
   * own orders, while sellers and admins may review order lines for relevant
   * authorization scopes. Rate limiting applies for bulk queries, and sensitive
   * commercial information is filtered appropriately by actor type.
   *
   * Related business logic includes support for order audit history, returns,
   * and fulfillment by sellers (since lines drive fulfillment and refund
   * eligibility). The endpoint leverages indexed queries for optimal
   * performance on typical customer (recent orders) and admin (search/filter
   * across large volumes) use cases. Error handling distinguishes between
   * invalid order codes, permission errors, and unsupported filter parameters
   * based on precise Prisma schema mappings.
   *
   * @param connection
   * @param orderCode Unique business order reference code of the target order
   *   (global scope)
   * @param body Search query, pagination, and filter criteria for retrieving
   *   order line items of a specific order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedBody()
    body: IShoppingOrderLine.IRequest,
  ): Promise<IPageIShoppingOrderLine.ISummary> {
    try {
      return await patchShoppingAdminOrdersOrderCodeLines({
        admin,
        orderCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific order line item by order and
   * order line ID (shopping_order_lines table).
   *
   * This API operation fetches comprehensive details for a specific order line
   * item under a designated customer order. It requires both the unique order
   * code of the parent order and the unique identifier of the order line item,
   * ensuring unambiguous lookup even in complex, multi-line or multi-seller
   * scenarios.
   *
   * Order line details include SKU reference, quantity ordered, per-unit
   * pricing, seller identification, order line fulfillment status, latest
   * update timestamps, and soft deletion marker if present. Authorization rules
   * ensure customers, sellers, and admins see only allowed information. This
   * endpoint can be used on order detail pages, for refund/cancellation
   * eligibility checks, and by sellers reviewing fulfillment or shipping
   * responsibilities.
   *
   * The operation references the shopping_order_lines table in the Prisma
   * schema, ensuring data returned is fully up-to-date and reflects latest
   * transactional changes. Error responses handle not found, unauthorized
   * access, and input identifier validation scenarios.
   *
   * @param connection
   * @param orderCode Unique business order reference code of the target order
   *   (global scope)
   * @param orderLineId Unique identifier of the target order line item within
   *   the order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderLineId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedParam("orderLineId")
    orderLineId: string & tags.Format<"uuid">,
  ): Promise<IShoppingOrderLine> {
    try {
      return await getShoppingAdminOrdersOrderCodeLinesOrderLineId({
        admin,
        orderCode,
        orderLineId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing order line item for an open customer order
   * (shopping_order_lines).
   *
   * This endpoint enables the modification of an order line's fields—such as
   * quantity, referenced SKU (if allowed), or price—prior to the completion of
   * payment or finalization of the order. It strictly requires both the parent
   * order's business orderCode and the specific target orderLineId (UUID).
   *
   * Business and validation logic ensures the order is open for modification,
   * and the order line exists and is active. Only valid, stock-available SKUs
   * can be set. Attempts to update finalized, deleted, or paid orders, or lines
   * belonging to other users will result in error responses.
   *
   * Security context indicates that only the customer who owns the order (or
   * platform-level admin for manual interventions) may update order lines. This
   * is the main means by which customers or support staff adjust cart/order
   * line details prior to confirmation.
   *
   * @param connection
   * @param orderCode Globally unique business identifier of the parent order
   *   (ORD-... pattern, global scope)
   * @param orderLineId UUID primary key of the order line item being updated
   *   (scoped to the specified order)
   * @param body Fields to update in the selected order line (quantity, SKU,
   *   price, etc.)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":orderLineId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedParam("orderLineId")
    orderLineId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingOrderLine.IUpdate,
  ): Promise<IShoppingOrderLine> {
    try {
      return await putShoppingAdminOrdersOrderCodeLinesOrderLineId({
        admin,
        orderCode,
        orderLineId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove an order line from a specific order
   * (shopping_order_lines).
   *
   * This API endpoint removes a specific order line item from the system, given
   * an order's unique business reference code and a target order line ID. It is
   * intended for use in scenarios where a customer or administrator needs to
   * void a particular item within an order, such as mistaken purchase, order
   * correction, fraud prevention, or special administrative workflow.
   *
   * The deletion is restricted to order lines that are not already fulfilled,
   * shipped, or delivered. The implementation must check the current status of
   * the order and order line against fulfillment and refund/cancellation rules,
   * denying the operation if the line is already in a non-editable state.
   * Business validation logic incorporates audit trails for regulatory
   * compliance, and only authorized users (typically the customer who placed
   * the order, or an admin with elevated privileges) may invoke this
   * operation.
   *
   * Upon successful deletion, the system should cascade any necessary updates
   * to the parent order's total, fulfillment plans, inventory adjustments
   * (restocking any previously reserved quantities for the removed item), and
   * notify all relevant actors (customer, seller, platform admin) as required
   * by business policy. All deletions are audited for traceability based on the
   * Prisma model definition.
   *
   * @param connection
   * @param orderCode Unique business reference code of the target order (global
   *   scope)
   * @param orderLineId Unique identifier for the order line within the order
   *   (scoped to order)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":orderLineId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedParam("orderLineId")
    orderLineId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminOrdersOrderCodeLinesOrderLineId({
        admin,
        orderCode,
        orderLineId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
