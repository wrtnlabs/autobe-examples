import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingAdminOrdersOrderCodeSplits } from "../../../../../providers/patchShoppingAdminOrdersOrderCodeSplits";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingAdminOrdersOrderCodeSplitsSplitCode } from "../../../../../providers/getShoppingAdminOrdersOrderCodeSplitsSplitCode";
import { putShoppingAdminOrdersOrderCodeSplitsSplitCode } from "../../../../../providers/putShoppingAdminOrdersOrderCodeSplitsSplitCode";
import { deleteShoppingAdminOrdersOrderCodeSplitsSplitCode } from "../../../../../providers/deleteShoppingAdminOrdersOrderCodeSplitsSplitCode";

import { IPageIShoppingOrderSplit } from "../../../../../api/structures/IPageIShoppingOrderSplit";
import { IShoppingOrderSplit } from "../../../../../api/structures/IShoppingOrderSplit";

@Controller("/shopping/admin/orders/:orderCode/splits")
export class ShoppingAdminOrdersSplitsController {
  /**
   * Search and retrieve paginated order split summaries for a specific order
   * (shopping_order_splits).
   *
   * This API operation enables advanced querying and retrieval of order split
   * records under a specific order, allowing callers to filter by criteria such
   * as seller ID, split status, date range, or fulfillment conditions. Order
   * splits represent seller-focused subdivisions of a customer order,
   * supporting workflows in marketplaces handling multi-seller checkouts and
   * fulfillment.
   *
   * Resulting data is paginated for performance and scalability, supporting
   * attributes such as page size, cursor/offset, filters, and sort order. Only
   * authorized actors (admins and possibly sellers associated with the order)
   * may access detailed split data, with sensitive fields controlled by
   * business logic. The endpoint responds with a paginated summary DTO,
   * optimized for audit trail reviews, dashboard reporting, operations
   * management, or API clients displaying seller–order relationships.
   *
   * The operation is implemented by referencing the shopping_order_splits table
   * and is intended for use cases ranging from admin oversight to seller
   * settlement dashboards. Integration with related entities and query
   * structures must respect performance and security best practices, leveraging
   * pagination and efficient filtering in the response.
   *
   * @param connection
   * @param orderCode Unique business reference code of the parent order for
   *   which splits are being queried (global scope)
   * @param body Query and filter options for order split search (seller,
   *   status, time, pagination, etc.)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedBody()
    body: IShoppingOrderSplit.IRequest,
  ): Promise<IPageIShoppingOrderSplit.ISummary> {
    try {
      return await patchShoppingAdminOrdersOrderCodeSplits({
        admin,
        orderCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detail for a specific order split by order and split code.
   *
   * This endpoint fetches the complete data for an order split identified by
   * the composite keys 'orderCode' and 'splitCode', referencing the
   * shopping_orders and shopping_order_splits tables. It returns split-level
   * detail such as seller allocation, status, subtotal price, and fulfillment
   * progress.
   *
   * Permission control ensures only the related customer, seller assigned to
   * this split, or an admin may access this information. The operation is
   * crucial for both customers tracking a multi-seller order and sellers
   * viewing their segment of a customer's order.
   *
   * The returned data provides all split attributes, audits, and relationships
   * needed for business logic, dashboard displays, seller support, and customer
   * self-service. Related endpoints include top-level order retrieval, line
   * item details, and order audit logs.
   *
   * @param connection
   * @param orderCode Globally unique business reference code for the parent
   *   order (global scope).
   * @param splitCode Unique code identifying the split sub-order for a specific
   *   seller within the order (scoped to order).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":splitCode")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedParam("splitCode")
    splitCode: string,
  ): Promise<IShoppingOrderSplit> {
    try {
      return await getShoppingAdminOrdersOrderCodeSplitsSplitCode({
        admin,
        orderCode,
        splitCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific order split's status, fulfillment, or related business
   * fields.
   *
   * This endpoint enables an authorized seller or admin to update an order
   * split identified by orderCode and splitCode (shopping_orders and
   * shopping_order_splits tables). Updateable fields include status,
   * fulfillment progression, and other mutable attributes allowed by business
   * logic and table schema.
   *
   * Authorization logic ensures that only the seller assigned to this split or
   * platform admins may execute update operations. Customers are not permitted
   * to modify split records. Data integrity checks and status transition rules
   * are enforced according to business workflow requirements.
   *
   * This operation is central for order processing, fulfillment status updates,
   * and event management in multi-seller scenarios. Related endpoints are split
   * detail retrieval, fulfillment line item management, and split audit trail
   * review.
   *
   * @param connection
   * @param orderCode Globally unique business reference code for the parent
   *   order (global scope).
   * @param splitCode Unique code identifying the split sub-order for a specific
   *   seller within the order (scoped to order).
   * @param body Fields and values to update for the given order split, such as
   *   status, fulfillment state, or business-relevant attributes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":splitCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedParam("splitCode")
    splitCode: string,
    @TypedBody()
    body: IShoppingOrderSplit.IUpdate,
  ): Promise<IShoppingOrderSplit> {
    try {
      return await putShoppingAdminOrdersOrderCodeSplitsSplitCode({
        admin,
        orderCode,
        splitCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove an order split from shopping_order_splits by order code
   * and split code.
   *
   * This operation enables platform administrators to permanently remove
   * (soft-delete) an order split (shopping_order_splits) from the shopping mall
   * platform, using both the parent order_code and the split_code. The
   * operation ensures audit traceability by setting deleted_at according to the
   * business requirement. Only users with admin actor status may perform this
   * action, preventing unauthorized deletions. Composite business logic ensures
   * the split is uniquely identified by its split_code within the context of
   * the parent order.
   *
   * When invoked, the operation finds an order in shopping_orders using the
   * unique order_code, then locates the split in shopping_order_splits via
   * split_code. The target split's deleted_at is set, marking it as
   * archived/removed but preserving it for compliance and reporting. Related
   * business rules ensure that order split deletion is only allowed in
   * predefined cases (such as cancelled orders, merchant fulfillment failure,
   * or authorized administrative business processes). The operation also
   * ensures that active or completed splits tied to active fulfillment
   * processes are checked for constraints before allowing a delete, returning
   * domain-specific errors if deletion is not permitted.
   *
   * The endpoint is strictly limited to admin actors and should be documented
   * to clarify that end-users and sellers cannot invoke this operation. Any
   * failed attempt or business rule violation results in a detailed audit log
   * entry.
   *
   * @param connection
   * @param orderCode Unique business identifier code of the target order
   *   (global scope)
   * @param splitCode Unique business identifier code of the target order split
   *   within the order (scoped to order)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":splitCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderCode")
    orderCode: string,
    @TypedParam("splitCode")
    splitCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminOrdersOrderCodeSplitsSplitCode({
        admin,
        orderCode,
        splitCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
