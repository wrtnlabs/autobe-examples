import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

import { IPageIShoppingGuestCartItem } from "../../../../api/structures/IPageIShoppingGuestCartItem";
import { IShoppingGuestCartItem } from "../../../../api/structures/IShoppingGuestCartItem";

@Controller("/shopping/admin/guestCarts")
export class ShoppingAdminGuestcartsController {
  /**
   * Search and retrieve a paginated/admin-filtered list of guest carts
   * (shopping_guest_carts).
   *
   * This operation fetches an index of active and expired guest shopping carts,
   * returning summary information for each session as stored in the
   * shopping_guest_carts table. Designed for platform administrators and
   * internal operations, the endpoint supports sophisticated search (e.g., by
   * session_key substring), filter (e.g., by expiration date), and sorting
   * (e.g., by last update), ensuring scalable and reliable monitoring or
   * cleanup tasks. No guest cart content or customer identity information is
   * revealed by this endpoint, maintaining data privacy: only session-level
   * metadata is included in responses.
   *
   * Security considerations require that only admin users may access this
   * endpoint, as guest cart management can impact order migration, session
   * reconciliation, and compliance reporting. Rate limiting and proper access
   * control are expected to be enforced at the service/controller layer.
   * Related endpoints for deleting expired sessions or migrating carts are to
   * be implemented with separate operations.
   *
   * The business logic ensures cart expiration and deletion policies are
   * respected, and this operation's results are intended for operational
   * analytics, batch processing, and dashboards.
   *
   * @param connection
   * @param body Guest cart session search criteria, with optional fields for
   *   filtering by expiration, creation/update time, or substring match on
   *   session_key. See IShoppingGuestCart.IRequest for properties.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingGuestCartItem.IRequest,
  ): Promise<IPageIShoppingGuestCartItem.ISummary> {
    try {
      return await patchShoppingAdminGuestCarts({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
