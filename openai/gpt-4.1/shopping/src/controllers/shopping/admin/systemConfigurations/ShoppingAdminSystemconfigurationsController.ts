import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingAdminSystemConfigurations } from "../../../../providers/postShoppingAdminSystemConfigurations";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminSystemConfigurations } from "../../../../providers/patchShoppingAdminSystemConfigurations";
import { getShoppingAdminSystemConfigurationsConfigKey } from "../../../../providers/getShoppingAdminSystemConfigurationsConfigKey";
import { putShoppingAdminSystemConfigurationsConfigKey } from "../../../../providers/putShoppingAdminSystemConfigurationsConfigKey";
import { deleteShoppingAdminSystemConfigurationsConfigKey } from "../../../../providers/deleteShoppingAdminSystemConfigurationsConfigKey";

import { IShoppingSystemConfiguration } from "../../../../api/structures/IShoppingSystemConfiguration";
import { IPageIShoppingSystemConfiguration } from "../../../../api/structures/IPageIShoppingSystemConfiguration";

@Controller("/shopping/admin/systemConfigurations")
export class ShoppingAdminSystemconfigurationsController {
  /**
   * Create a new system configuration entry (shopping_system_configurations).
   *
   * Create a new system-level configuration entry for platform runtime settings
   * and control. This endpoint allows administrators to register a new
   * configuration key and value pair, which might be used for controlling
   * feature toggles, defining service URLs, SMTP connection details, or other
   * cross-cutting settings.
   *
   * Access to this endpoint should be restricted to admin users. Upon
   * submission, the provided config_key is validated for uniqueness
   * (case-insensitive and must not conflict with existing keys), and
   * config_value is saved as provided. The configuration may also include a
   * human-readable description for context or audit purposes.
   *
   * All changes are tracked in the shopping_system_configurations table,
   * including audit timestamps. After successful creation, the new
   * configuration entry is immediately available for use throughout the
   * platform. A soft delete mechanism is built-in for future invalidation, but
   * deletion is not handled by this endpoint.
   *
   * Validation errors (e.g., duplicate config_key) will return appropriate
   * error responses. Only administrators may access this operation as it
   * impacts the core runtime settings of the shopping system.
   *
   * @param connection
   * @param body Details of the configuration entry to be created, including
   *   unique config_key and config_value.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingSystemConfiguration.ICreate,
  ): Promise<IShoppingSystemConfiguration> {
    try {
      return await postShoppingAdminSystemConfigurations({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated, filtered list of system configuration
   * entries (shopping_system_configurations).
   *
   * This API operation is designed to enable administrators and DevOps users to
   * search, filter, and retrieve platform-wide system configuration entries
   * from the shopping_system_configurations table. Users can filter results by
   * configuration key, value, and text-search any part of the configuration
   * description, leveraging GIN trigram indexes for efficient matching and
   * relevance ranking.
   *
   * Each configuration entry includes critical details for platform operation,
   * such as SMTP servers, feature flags, service endpoints, or runtime
   * parameters. The operation provides pagination and supports ordering results
   * by creation or update timestamps, making it suitable for integration into
   * service dashboards or operational audit tools.
   *
   * Security considerations: Only administrative actors can use this API, as
   * exposure of configuration values could reveal infrastructure or security
   * secrets. The provider will enforce role-based filtering so only active
   * (non-soft-deleted) records are returned.
   *
   * Related operations include: retrieval of individual configuration details
   * by key, creation or updating of configuration values, and auditing or
   * rolling back changes when errors occur. Error responses provide full
   * diagnostic context for troubleshooting purposes. The operation never
   * exposes configuration secrets other than as required by admin actor
   * permissions.
   *
   * @param connection
   * @param body Advanced search, filtering, and pagination parameters for
   *   system configuration entries
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingSystemConfiguration.IRequest,
  ): Promise<IPageIShoppingSystemConfiguration.ISummary> {
    try {
      return await patchShoppingAdminSystemConfigurations({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a system configuration entry by config_key
   * (shopping_system_configurations).
   *
   * This API operation returns full details for a single configuration entry in
   * the shopping_system_configurations table, identified by its unique
   * config_key parameter (case-insensitive). It is essential for admin
   * dashboards and platform boot processes, such as loading SMTP settings, API
   * URLs, or critical feature flags.
   *
   * The operation ensures strict RBAC enforcement, only returning configuration
   * data to authorized admin users. If the target config_key does not exist or
   * is soft deleted, a 404-not found result is returned. Security controls mask
   * or redact configuration secrets as defined in platform policies to avoid
   * accidental credentials leakage.
   *
   * The response payload contains all core configuration metadata (key, value,
   * description, timestamps, deletion state) including documentation field for
   * operations or deployment traceability. Related operations include
   * list/search of all configuration entries, creation, update, and value
   * history auditing. Care is taken to log all access to this endpoint for
   * compliance and incident response.
   *
   * If the key is missing, invalid, or does not match an existing (active)
   * configuration entry, the response will follow platform error contract and
   * include a clear indication of not found with audit reference.
   *
   * @param connection
   * @param configKey Unique system configuration key (case-insensitive, e.g.
   *   'core.smtp_server'). (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":configKey")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("configKey")
    configKey: string,
  ): Promise<IShoppingSystemConfiguration> {
    try {
      return await getShoppingAdminSystemConfigurationsConfigKey({
        admin,
        configKey,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing system configuration (shopping_system_configurations) by
   * configKey.
   *
   * Update an existing system configuration entry by its unique configuration
   * key. This operation is restricted to administrators, as it may impact
   * global behavior of the shopping mall platform.
   *
   * The config_key in the path uniquely identifies the configuration entry to
   * be updated (case-insensitive match). The request body may include new
   * values for config_value and/or description. Upon successful validation, the
   * specified configuration value and description are updated and new audit
   * timestamps are set on the record for traceability.
   *
   * If the config_key does not exist, the system will return a not found error.
   * All changes are persistently tracked in the shopping_system_configurations
   * table, supporting platform runtime management and compliance. Soft deletes
   * are not handled via this endpoint.
   *
   * Only administrators can update system configurations to protect the
   * stability and security of platform operations.
   *
   * @param connection
   * @param configKey Unique system configuration key (case-insensitive, e.g.,
   *   'core.smtp_server'). (global scope)
   * @param body Fields to update for the system configuration, such as
   *   config_value and description.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":configKey")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("configKey")
    configKey: string,
    @TypedBody()
    body: IShoppingSystemConfiguration.IUpdate,
  ): Promise<IShoppingSystemConfiguration> {
    try {
      return await putShoppingAdminSystemConfigurationsConfigKey({
        admin,
        configKey,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a system configuration by its unique key
   * (shopping_system_configurations).
   *
   * This API operation enables an administrator to permanently remove a single
   * configuration entry from the shopping_system_configurations table, using
   * the unique config_key as the path parameter. Unlike soft deletion
   * operations which merely mark a record as deleted, this endpoint completely
   * erases the selected configuration row for compliance or security reasons,
   * especially when a misconfiguration must be purged from the platform.
   *
   * The actor must provide the exact config_key of the system configuration to
   * be deleted. The operation is restricted to admin-level actors to ensure
   * platform stability, as deleting configurations could impact system-wide
   * behaviors. The operation enforces uniqueness of the configuration key,
   * reducing the likelihood of accidental mass deletion.
   *
   * The underlying Prisma schema ensures that config_key is unique, so only one
   * record can ever be affected per call. There is no response body for this
   * operation; successful completion indicates removal. Attempts to delete a
   * non-existent config_key result in an appropriate error. Audit logging of
   * the deletion is recommended to meet regulatory and operational standards.
   *
   * @param connection
   * @param configKey Unique system configuration key identifying the target
   *   entry (global scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":configKey")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("configKey")
    configKey: string,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminSystemConfigurationsConfigKey({
        admin,
        configKey,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
