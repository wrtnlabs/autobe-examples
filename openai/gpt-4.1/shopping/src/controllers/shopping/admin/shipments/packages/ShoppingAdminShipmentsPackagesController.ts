import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingAdminShipmentsCodePackages } from "../../../../../providers/patchShoppingAdminShipmentsCodePackages";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingAdminShipmentsCodePackagesPackageLabel } from "../../../../../providers/getShoppingAdminShipmentsCodePackagesPackageLabel";

import { IPageIShoppingShipmentPackage } from "../../../../../api/structures/IPageIShoppingShipmentPackage";
import { IShoppingShipmentPackage } from "../../../../../api/structures/IShoppingShipmentPackage";

@Controller("/shopping/admin/shipments/:code/packages")
export class ShoppingAdminShipmentsPackagesController {
  /**
   * Search and retrieve paginated, filterable list of all packages related to a
   * shipment by code.
   *
   * This API endpoint allows administrators, shipping managers, and authorized
   * operators to search and browse all shipment package units for a single
   * shipment. The operation supports flexible search filters (package status,
   * label, tracking number, sequence, delivery state), pagination, and sorting
   * to enable end-to-end visibility of packaging and fulfillment for a single
   * shipment. Package details support audit and real-time operational
   * troubleshooting.
   *
   * Path parameter validation ensures that the provided business code exists in
   * the shopping_shipments table and filters only packages attached to that
   * shipment. Search and sort options are customizable through the request body
   * (IShoppingShipmentPackage.IRequest), allowing for highly granular package
   * inspection within a shipment.
   *
   * Security considerations restrict access to admin actors to preserve
   * delivery performance and package integrity. API responses conform to data
   * privacy and operational standards for shipment package information. This
   * endpoint supports core operational metrics for logistics performance
   * tracking and exception management.
   *
   * @param connection
   * @param code Unique business code identifying the shipment (global scope)
   *   whose packages are to be indexed. Example: SHPT-2025-0001
   * @param body Search and filter criteria for shipment packages (status,
   *   tracking number, sequence, delivery dates, etc.)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("code")
    code: string,
    @TypedBody()
    body: IShoppingShipmentPackage.IRequest,
  ): Promise<IPageIShoppingShipmentPackage.ISummary> {
    try {
      return await patchShoppingAdminShipmentsCodePackages({
        admin,
        code,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific shipment package by shipment
   * code and package label (shopping_shipment_packages table).
   *
   * This API operation retrieves the full set of details for a single shipment
   * package based on the provided shipment code and package label path
   * parameters. The underlying database table is shopping_shipment_packages,
   * which stores package-specific data such as tracking number, label,
   * dimensions, sequence in shipment, package status (pending, ready, shipped,
   * delivered, lost, damaged), and audit timestamps.
   *
   * The detailed package information includes all fields defined in the
   * shopping_shipment_packages schema and is returned only if the shipment code
   * and package label together uniquely identify a valid package. Security and
   * data privacy are strictly enforced: only the customer who placed the order,
   * the seller fulfilling the shipment, and authorized admins are permitted to
   * access these details. Attempts to access unauthorized or non-existent
   * packages will result in explicit error responses.
   *
   * This operation is typically used to power user package tracking UIs, enable
   * support for split or multi-package shipments, and deliver targeted
   * notifications about shipping events (such as package scanned, out for
   * delivery, delivered, or exceptions). If the shipment or package has been
   * soft-deleted, this operation will not return package details and may return
   * a 404 or business error.
   *
   * Integration with related shipment APIs is facilitated by using the same
   * package and shipment identification pattern; related endpoints include
   * shipment-level detail retrieval, tracking event patch, and admin shipment
   * audit.
   *
   * @param connection
   * @param code Unique business identifier code for the target shipment (global
   *   scope).
   * @param packageLabel Unique business identifier label of the target package
   *   within the shipment (scoped to shipment).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":packageLabel")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("code")
    code: string,
    @TypedParam("packageLabel")
    packageLabel: string,
  ): Promise<IShoppingShipmentPackage> {
    try {
      return await getShoppingAdminShipmentsCodePackagesPackageLabel({
        admin,
        code,
        packageLabel,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
