@Controller(
  "/shopping/admin/shipments/:code/packages/:packageLabel/trackings/:trackingSource/events",
)
export class ShoppingAdminShipmentsPackagesTrackingsEventsController {
  /**
   * Search and retrieve tracking events for a specific package tracking
   * instance (shopping_shipment_tracking_events).
   *
   * This operation provides a filtered and paginated event log of all tracking
   * updates, scan events, and status changes for a given shipment package
   * reference and tracking source. The lookup is resolved by joining on the
   * shipment code, package label, and tracking source, ultimately resolving the
   * tracking instance (shopping_shipment_trackings.id) and returning all
   * associated tracking event records from shopping_shipment_tracking_events.
   *
   * Typical use cases include displaying shipment tracking history to customers
   * (e.g., delivery progress screens), enabling seller support for delivery
   * disputes or exceptions, and providing administrators with a full audit
   * trail for compliance and incident management. The returned list contains
   * carrier and system-generated tracking milestones, location data, time
   * stamps, and event details as stored in the Prisma schema fields.
   *
   * Actor authentication is enforced: only parties associated with the shipment
   * (purchasing customer, responsible seller, or admin) may access this
   * endpoint. Rate limiting is applied to prevent excessive carrier polling or
   * brute-force enumeration. Expected error scenarios include unresolved or
   * expired package labels, tracking source mismatches, permission denials, and
   * unsupported event queries.
   *
   * Related endpoints: use the GET tracking instance endpoint for aggregate
   * status and summary before drilling down to full event history. The search
   * supports filter, sort, and pagination criteria as defined in the request
   * schema.
   *
   * @param connection
   * @param code Unique business shipment code for the target shipment (global
   *   scope).
   * @param packageLabel Unique business label of the target package within the
   *   shipment (scoped to shipment).
   * @param trackingSource Source identifier for the tracking instance (e.g.,
   *   'courier_api', 'warehouse_scan').
   * @param body Search and pagination parameters for tracking event retrieval.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("code")
    code: string,
    @TypedParam("packageLabel")
    packageLabel: string,
    @TypedParam("trackingSource")
    trackingSource: string,
    @TypedBody()
    body: IShoppingShipmentTrackingEvent.IRequest,
  ): Promise<IPageIShoppingShipmentTrackingEvent> {
    try {
      return await patchShoppingAdminShipmentsCodePackagesPackageLabelTrackingsTrackingSourceEvents(
        {
          admin,
          code,
          packageLabel,
          trackingSource,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
