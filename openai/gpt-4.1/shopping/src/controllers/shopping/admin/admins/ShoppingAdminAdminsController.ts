import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingAdminAdmins } from "../../../../providers/patchShoppingAdminAdmins";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingAdminAdminsAdminId } from "../../../../providers/getShoppingAdminAdminsAdminId";
import { putShoppingAdminAdminsAdminId } from "../../../../providers/putShoppingAdminAdminsAdminId";
import { deleteShoppingAdminAdminsAdminId } from "../../../../providers/deleteShoppingAdminAdminsAdminId";

import { IPageIShoppingAdmin } from "../../../../api/structures/IPageIShoppingAdmin";
import { IShoppingAdmin } from "../../../../api/structures/IShoppingAdmin";

@Controller("/shopping/admin/admins")
export class ShoppingAdminAdminsController {
  /**
   * Paginate and filter all admin user accounts for platform management
   * (shopping_admins).
   *
   * Retrieve a paginated, searchable list of all platform administrator
   * accounts. This API operation is essential for super admin and compliance
   * users to administer access privileges, role assignments, and status audits
   * of all admin users. Results can be filtered by email, name, privilege role,
   * and operational status to enable granular reviews and centralized user
   * management.
   *
   * Data is sourced from the shopping_admins table as defined in the Prisma
   * schema, returning only business-relevant fields, with password hashes and
   * authentication tokens excluded for security compliance. The response
   * utilizes a summary DTO for scalable list rendering in admin dashboards or
   * for supporting compliance/export workflows.
   *
   * Strict authorization checks ensure only other admins (role: admin) can
   * invoke this operation. Intended applications include RBAC (role-based
   * access control) management, periodic account reviews, audit event
   * correlation, and regulatory reporting processes in enterprise-class
   * e-commerce environments.
   *
   * @param connection
   * @param body Search, filtering, and pagination criteria for admin account
   *   queries
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingAdmin.IRequest,
  ): Promise<IPageIShoppingAdmin.ISummary> {
    try {
      return await patchShoppingAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific administrator from the
   * shopping_admins table.
   *
   * Fetch comprehensive administrator profile and authentication metadata by
   * adminId. This includes email, name, assigned role, and business status, all
   * stored in the shopping_admins entity. The endpoint is intended for system
   * operator dashboards, audit workflow, and admin lifecycle management,
   * supporting granular privilege tracking and compliance reporting.
   *
   * Access to this operation is restricted to high-privilege users, typically
   * other platform administrators, due to the sensitive nature of admin data.
   * Actor permissions and security logging are essential; only authorized
   * system operators should invoke this endpoint per the requirements outlined
   * in business documentation and Prisma schema comments on shopping_admins.
   *
   * The operation leverages primary key lookup to ensure efficient search and
   * avoids exposure of authentication hash or personal security secrets. In
   * error scenarios such as non-existent adminId or suspended admin accounts,
   * the endpoint returns a standardized error response, with audit logs
   * triggered for all access attempts. Related endpoints include PUT for
   * modifying administrator data, which requires an equivalent or higher
   * administrative privilege for access.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator (UUID format;
   *   global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IShoppingAdmin> {
    try {
      return await getShoppingAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update profile and privilege attributes of a specific administrator in the
   * shopping_admins table.
   *
   * Update administrator account fields such as name, email, assigned role, and
   * active/suspended status by adminId. Submitted changes are validated against
   * current admin policy and business rules, with all modifications recorded in
   * immutable logs for security and regulatory compliance.
   *
   * The shopping_admins table enforces unique email constraints and account
   * status lifecycle; this operation verifies constraints are maintained,
   * returning error responses if uniqueness or role policy is violated. Updates
   * should not include password hash modifications except through specialized
   * password/reset endpoints. Typical use cases include privilege changes,
   * account status enforcement (activation, suspension), and contact detail
   * updates by approved admin operators.
   *
   * Security is paramount; only higher or equivalent role-level admins may
   * update another admin's information, and full audit trails are maintained
   * for all requests. On successful update, the endpoint returns the new state
   * of the admin profile. Related endpoints include GET for detailed retrieval
   * and authentication endpoints for session management.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator (UUID format;
   *   global scope)
   * @param body Updated admin profile fields to apply to the administrator
   *   record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingAdmin.IUpdate,
  ): Promise<IShoppingAdmin> {
    try {
      return await putShoppingAdminAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a platform administrator account (shopping_admins).
   *
   * This API endpoint allows a super-admin to permanently delete a platform
   * administrator account by specifying the particular adminId (UUID) in the
   * path parameter. Once this operation is executed, the administrator's
   * credentials, account details, and all linked session records are removed
   * from the database as defined in the shopping_admins Prisma schema.
   *
   * This function is intended for compliance scenarios (such as legal takedown
   * or staff departure), security incident response, or enforced account
   * de-provisioning. The operation is restricted to actors with super-admin
   * privileges to prevent accidental or unauthorized deletion of critical admin
   * accounts. Permission checks and business safeguards (e.g., cannot delete
   * the last remaining admin, cannot delete currently logged-in self) must be
   * enforced by the provider implementation.
   *
   * Audit logging is critical—each deletion must record a full trace of the
   * performing actor, timestamp, originating IP, and deletion context for
   * regulatory review. No account information can be recovered once deleted,
   * and all privileges for the target adminId are revoked immediately upon
   * execution. The endpoint must return an explicit error if the operation is
   * disallowed by compliance/business rule (such as attempting to delete the
   * last or only active admin account).
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account to delete
   *   (UUID). Must reference a valid shopping_admins.id value to proceed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
