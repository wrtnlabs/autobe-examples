import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingAdminUserEmails } from "../../../../providers/patchShoppingAdminUserEmails";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingAdminUserEmailsUserEmailId } from "../../../../providers/getShoppingAdminUserEmailsUserEmailId";
import { putShoppingAdminUserEmailsUserEmailId } from "../../../../providers/putShoppingAdminUserEmailsUserEmailId";
import { deleteShoppingAdminUserEmailsUserEmailId } from "../../../../providers/deleteShoppingAdminUserEmailsUserEmailId";

import { IPageIShoppingUserEmail } from "../../../../api/structures/IPageIShoppingUserEmail";
import { IShoppingUserEmail } from "../../../../api/structures/IShoppingUserEmail";

@Controller("/shopping/admin/userEmails")
export class ShoppingAdminUseremailsController {
  /**
   * Search and list secondary or historic user email addresses for audit and
   * compliance.
   *
   * Retrieve a filtered, paginated list of user email records from the
   * shopping_user_emails table. Each record represents either a secondary,
   * pending, unverified, or historical email address used by a customer or a
   * seller in the shopping mall system. The operation supports advanced search
   * criteria, including filtering by owner type (customer or seller), email
   * verification status, primary email designation, and account association.
   * Sorting and pagination parameters are supported to efficiently navigate
   * large datasets.
   *
   * Access to this operation is restricted to admin-level actors, as user
   * emails are considered sensitive and are often used for security or
   * compliance processes. Admin users utilize this endpoint primarily for
   * audits, compliance checks, and resolving account-specific issues. The API
   * provides summaries optimized for search result display and does not return
   * full related actor (user/seller) objects for each result.
   *
   * This endpoint only reads data, does not allow modification or export, and
   * ensures full compliance with system data privacy rules. Errors are handled
   * gracefully, especially for unsupported filter/sort parameters or if an
   * unauthenticated (non-admin) actor attempts access. The results are derived
   * directly from the shopping_user_emails schema and related indexes.
   *
   * @param connection
   * @param body Search/filter and pagination criteria for user email addresses
   *   (secondary, pending, historical)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingUserEmail.IRequest,
  ): Promise<IPageIShoppingUserEmail.ISummary> {
    try {
      return await patchShoppingAdminUserEmails({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detail view for a single user email entity by unique identifier.
   *
   * Retrieve the detailed record for a specific user email entry from the
   * shopping_user_emails table, uniquely identified by userEmailId. This
   * operation provides complete information about a single email address
   * entity, such as its parent customer or seller, verification status,
   * primary/secondary designation, and timestamps for creation, update, or (if
   * relevant) deletion.
   *
   * The use of a unique identifier in the path aligns with the primary key of
   * the user email entity. Sensitive data contained in user email records
   * requires admin-level authorization. Typical use cases include account
   * audits, data privacy compliance, and troubleshooting account access issues
   * involving email addresses. Access by unauthorized actors is denied. Error
   * cases are handled for not-found IDs or access violations according to
   * platform policy.
   *
   * The operation is implemented strictly against the shopping_user_emails
   * schema, using only defined fields and relations. All outputs are fully
   * compliant with system audit and privacy requirements.
   *
   * @param connection
   * @param userEmailId Unique identifier of the target user email record (UUID
   *   primary key)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userEmailId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userEmailId")
    userEmailId: string & tags.Format<"uuid">,
  ): Promise<IShoppingUserEmail> {
    try {
      return await getShoppingAdminUserEmailsUserEmailId({
        admin,
        userEmailId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific user email record by ID (shopping_user_emails table).
   *
   * This endpoint enables the authorized actor to update an existing user email
   * record. Typical usage includes email address correction, toggling
   * verification status, or designating a different primary email for the
   * associated user (customer or seller).
   *
   * Security: This operation checks proper authentication and ensures only the
   * associated customer, seller, or an admin can edit their own user email
   * record. Attempts to update to a duplicate email will be rejected,
   * reflecting Prisma's unique constraint on the email field.
   *
   * Relationships: The operation is closely tied to the shopping_user_emails
   * table and is subject to the referenced user's role (either
   * shopping_customer_id or shopping_seller_id). Ensure all update information
   * is valid and conforms to business logic for email management (including
   * proper casing, verification, and primary status logic).
   *
   * Validation/boundaries: Addresses edge cases such as primary email
   * uniqueness, verified status changes, unique constraint violations, and
   * attempts to update a deleted record. Related fetch operations include GET
   * endpoints to list or retrieve user emails.
   *
   * @param connection
   * @param userEmailId Unique identifier of the user email record to update
   *   (shopping_user_emails.id)
   * @param body Update details for the user email record, including email,
   *   verification status, or primary designation. Fields must exist in
   *   shopping_user_emails schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userEmailId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userEmailId")
    userEmailId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingUserEmail.IUpdate,
  ): Promise<IShoppingUserEmail> {
    try {
      return await putShoppingAdminUserEmailsUserEmailId({
        admin,
        userEmailId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a user email record by ID from shopping_user_emails (permanent
   * removal).
   *
   * Executes the permanent deletion of a user email record by its unique
   * identifier. Intended for customer or seller self-service under account
   * management features, or for administrator use in correcting or cleaning up
   * orphaned or duplicate emails.
   *
   * Security: Authorization is enforced to ensure only the owning actor
   * (customer or seller) or an admin can delete email records associated with
   * their account. Deletion attempts on primary or currently verified emails
   * may be blocked depending on business rules, and all deletions are
   * irreversible.
   *
   * Schema relationships: The operation directly targets the
   * shopping_user_emails table using the unique id field, and cascades no other
   * deletes. Prisma's unique constraint on email is maintained; on successful
   * deletion, the email may be re-used for different accounts.
   *
   * Expected behavior: Attempts to delete an email in use as the main login
   * email or as primary will fail with a business validation error. The
   * operation provides confirmation of deletion and should be used with caution
   * in administrative interfaces.
   *
   * @param connection
   * @param userEmailId Unique identifier of the user email record to delete
   *   (shopping_user_emails.id)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userEmailId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userEmailId")
    userEmailId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminUserEmailsUserEmailId({
        admin,
        userEmailId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
