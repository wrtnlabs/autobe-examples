import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingAdminReviewsReviewIdModerations } from "../../../../../providers/postShoppingAdminReviewsReviewIdModerations";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminReviewsReviewIdModerations } from "../../../../../providers/patchShoppingAdminReviewsReviewIdModerations";
import { getShoppingAdminReviewsReviewIdModerationsModerationId } from "../../../../../providers/getShoppingAdminReviewsReviewIdModerationsModerationId";

import { IShoppingReviewModeration } from "../../../../../api/structures/IShoppingReviewModeration";
import { IPageIShoppingReviewModeration } from "../../../../../api/structures/IPageIShoppingReviewModeration";

@Controller("/shopping/admin/reviews/:reviewId/moderations")
export class ShoppingAdminReviewsModerationsController {
  /**
   * Create a new review moderation log entry (shopping_review_moderations).
   *
   * This operation allows a platform administrator to create a formal
   * moderation action record attached to a specific review. It is based on the
   * shopping_review_moderations Prisma schema model and is essential for audit
   * trails, compliance, and full traceability of all actions taken on
   * user-submitted reviews.
   *
   * The request body must include all details required by the model, such as
   * the moderation action type (approved, removed, restored, flagged, edited,
   * etc.), rationale, and the acting moderator's identity. These entries ensure
   * that every administrative decision regarding review content is properly
   * documented for regulatory, compliance, and appeal workflows.
   *
   * This operation is strictly limited to admin actors, in accordance with
   * role-based permission policies for moderation. The reviewId in the path
   * ensures the log is correctly associated with the specific review being
   * moderated. The response delivers the newly created moderation log record,
   * containing all provided information and assigned identifiers for lookup,
   * audit, or subsequent retrieval.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review to which the
   *   moderation action will be attached (global scope)
   * @param body Full details of the moderation action to apply to the target
   *   review, including action type, rationale, and moderator identity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingReviewModeration.ICreate,
  ): Promise<IShoppingReviewModeration> {
    try {
      return await postShoppingAdminReviewsReviewIdModerations({
        admin,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated, filterable list of review moderation log entries
   * (shopping_review_moderations table).
   *
   * This operation enables platform administrators to search and review the
   * complete moderation history applied to customer product reviews. Each
   * record corresponds to a moderation event (such as approval, removal, flag,
   * or restoration) and details the acting admin, action taken, associated
   * review, rationale, and timestamp. The operation supports advanced
   * filtering, including moderator identity, action type, affected review ID,
   * and custom date windows for compliance investigations.
   *
   * Moderation logs are critical for audit and transparency: all moderation
   * decisions taken on reviews are persisted in the
   * 'shopping_review_moderations' Prisma table, offering a detailed trail for
   * compliance and business oversight. The operation returns a paginated
   * response using the IPageIShoppingReviewModeration.ISummary DTO, optimized
   * for list and reporting views.
   *
   * Security is enforced to ensure that only users with admin privileges can
   * access this endpoint. No modification or deletion of moderation logs is
   * possible through this API; other endpoints support edit and delete actions
   * as required. The operation is closely related to admin dashboards and
   * reporting systems, allowing detailed cross-referencing and compliance
   * verification.
   *
   * @param connection
   * @param reviewId Unique identifier of the review for which moderation logs
   *   are queried
   * @param body Search and filter criteria for moderation history, including
   *   paging, sort, date range, and moderator/admin filter options
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingReviewModeration.IRequest,
  ): Promise<IPageIShoppingReviewModeration.ISummary> {
    try {
      return await patchShoppingAdminReviewsReviewIdModerations({
        admin,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific review moderation action
   * (shopping_review_moderations).
   *
   * Fetches the complete details for a single moderation action performed on a
   * given review, as recorded in the shopping_review_moderations table. The
   * operation includes all metadata such as action type (approved, removed,
   * restored, etc.), rationale provided by the moderator, moderator identity,
   * review reference, and precise timestamps.
   *
   * This endpoint is essential for administrative or legal transparency,
   * enabling full traceability of review moderation decisions on the platform.
   * Only admins or actors with elevated permissions can access this operation,
   * as it exposes sensitive audit log information.
   *
   * The moderation record must be uniquely identified based on the context of
   * the review and moderation IDs, following the composite unique constraints
   * in the schema. The related reviewId and moderationId must both be supplied
   * in the path for correct lookup and context disambiguation. The response
   * provides full information needed to support audits, appeals, and compliance
   * reviews associated with moderation activity.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review (global scope)
   * @param moderationId Unique identifier of the review moderation log within
   *   the review (scoped to review)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":moderationId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("moderationId")
    moderationId: string & tags.Format<"uuid">,
  ): Promise<IShoppingReviewModeration> {
    try {
      return await getShoppingAdminReviewsReviewIdModerationsModerationId({
        admin,
        reviewId,
        moderationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
