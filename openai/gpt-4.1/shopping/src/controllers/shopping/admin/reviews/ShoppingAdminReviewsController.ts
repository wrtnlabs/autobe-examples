import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingAdminReviews } from "../../../../providers/patchShoppingAdminReviews";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingAdminReviewsReviewId } from "../../../../providers/getShoppingAdminReviewsReviewId";
import { deleteShoppingAdminReviewsReviewId } from "../../../../providers/deleteShoppingAdminReviewsReviewId";

import { IPageIShoppingReview } from "../../../../api/structures/IPageIShoppingReview";
import { IShoppingReview } from "../../../../api/structures/IShoppingReview";

@Controller("/shopping/admin/reviews")
export class ShoppingAdminReviewsController {
  /**
   * Search and retrieve filtered, paginated list of product reviews
   * (shopping_reviews).
   *
   * Retrieve a filtered, paginated list of product reviews submitted by
   * customers for products and SKUs on the shopping mall platform. This
   * operation allows searching by review state, star rating, associated product
   * or SKU, customer ID, order line, keywords within comments, and date range.
   * The response includes review summary information for admin, seller, or
   * customer display, showing each review's unique identifiers, rating,
   * truncated comment, state, creation/update dates, and author details per
   * role permissions.
   *
   * Pagination and sorting are fully supported via the request body parameters,
   * with page size and offset controls. Security is enforced according to the
   * actor accessing the endpoint—admins may access all reviews, sellers those
   * for their products, and customers only their own. Integration with review
   * moderation and abuse workflows is supported. Errors include unauthorized
   * access, invalid parameters, and exceeded page size limits.
   *
   * @param connection
   * @param body Review search and filter criteria including pagination and
   *   advanced filters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingReview.IRequest,
  ): Promise<IPageIShoppingReview.ISummary> {
    try {
      return await patchShoppingAdminReviews({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete details for a single product review from shopping_reviews
   * table.
   *
   * Retrieve the complete record and associated data for a specific customer
   * product review by its unique reviewId (UUID, PK in shopping_reviews
   * schema). This operation is used to display all review information in
   * detail, including full text, rating, state, reviewer details, attachments,
   * and audit history if allowed. The returned data includes all fields and
   * relationships (customer, SKU, order line), for detailed view or moderation
   * workflows.
   *
   * Security and access control are based on role: customers access their own
   * reviews, sellers see reviews for their products, admins may access all.
   * Reference integrity and soft deletion are respected; if the review does not
   * exist, is deleted, or access is denied, an error or null is returned.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review (UUID as PK of
   *   shopping_reviews)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reviewId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IShoppingReview> {
    try {
      return await getShoppingAdminReviewsReviewId({
        admin,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a specific customer review from shopping_reviews.
   *
   * This API endpoint deletes a customer review from the system by reviewId,
   * removing the review record and all its related attachments. The review must
   * exist in the shopping_reviews table and meet the criteria for deletion:
   * either the customer is the original author and within the permitted
   * edit/remove window, or an admin is performing a compliance or moderation
   * removal.
   *
   * Security considerations require strict authorization: customers may only
   * delete their own reviews within policy limits, and actions outside this
   * window are restricted to users with admin privileges. Attempts to delete
   * reviews outside these rules will return an appropriate error code and
   * rationale.
   *
   * Once this operation succeeds, the review and its references are no longer
   * available in search, product displays, or aggregation calculations. Hard
   * deletes are permanent and cannot be reversed, respecting any audit or legal
   * retention policies in effect. Error handling ensures that if the review
   * does not exist or the actor lacks permission, clear business error codes
   * are returned to the client.
   *
   * @param connection
   * @param reviewId Unique identifier of the review being deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reviewId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminReviewsReviewId({
        admin,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
