import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingAdminReviewsReviewIdAbuseReports } from "../../../../../providers/patchShoppingAdminReviewsReviewIdAbuseReports";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingAdminReviewsReviewIdAbuseReportsAbuseReportId } from "../../../../../providers/getShoppingAdminReviewsReviewIdAbuseReportsAbuseReportId";
import { deleteShoppingAdminReviewsReviewIdAbuseReportsAbuseReportId } from "../../../../../providers/deleteShoppingAdminReviewsReviewIdAbuseReportsAbuseReportId";

import { IPageIShoppingReviewAbuseReport } from "../../../../../api/structures/IPageIShoppingReviewAbuseReport";
import { IShoppingReviewAbuseReport } from "../../../../../api/structures/IShoppingReviewAbuseReport";

@Controller("/shopping/admin/reviews/:reviewId/abuseReports")
export class ShoppingAdminReviewsAbusereportsController {
  /**
   * Retrieve a filtered, paginated list of abuse reports for a specific review
   * (shopping_review_abuse_reports).
   *
   * Retrieve and search all abuse reports associated with a product review to
   * support moderation and transparency workflows.
   *
   * This operation enables qualified actors to view who has reported a review,
   * for what reason, the type of abuse, and the current moderation state for
   * each report—while ensuring sensitive reporter details are masked or only
   * visible to administrators in accordance with business rules. Multiple
   * filtering options are available: type of abuse (e.g., spam, hate speech),
   * date of report, and moderation status (open, processed, dismissed,
   * removed). Pagination is provided for scalability and performance when
   * handling reviews with a high number of reports.
   *
   * The endpoint is used in conjunction with review detail endpoints and report
   * abuse actions, enabling a complete moderation and transparency cycle for
   * both review authors and platform admins. Error scenarios are handled
   * according to authorization (permission denied), missing review reference,
   * or invalid filtering options. Only reports not soft-deleted or hard-removed
   * are returned.
   *
   * @param connection
   * @param reviewId Unique identifier for the parent review whose abuse reports
   *   are being queried. (global scope)
   * @param body Search and pagination criteria for querying abuse reports
   *   associated with the specified review.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingReviewAbuseReport.IRequest,
  ): Promise<IPageIShoppingReviewAbuseReport.ISummary> {
    try {
      return await patchShoppingAdminReviewsReviewIdAbuseReports({
        admin,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single, detailed abuse report by ID for a given review
   * (shopping_review_abuse_reports).
   *
   * Fetch a specific abuse report record attached to a review, showing all
   * filed information and moderation status for audit and investigation
   * purposes.
   *
   * This operation exposes individual abuse report data using strict access
   * control—only admins and authorized staff can read full reporter and reason
   * details. Returns all available fields on the abuse report entity, with
   * special handling for anonymization or masking of personally identifying
   * information as business or regional regulations dictate. The operation is
   * most often used in admin dashboards or abuse investigation queues. Error
   * responses are provided if access is denied, if the report or review does
   * not exist, or if the requestor lacks permission to view sensitive details.
   * This complements listing, flag, and state update workflows for review
   * content moderation.
   *
   * @param connection
   * @param reviewId Unique identifier for the parent review to which the abuse
   *   report belongs. (global scope)
   * @param abuseReportId Unique identifier for the abuse report to retrieve.
   *   (scoped to review)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":abuseReportId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("abuseReportId")
    abuseReportId: string & tags.Format<"uuid">,
  ): Promise<IShoppingReviewAbuseReport> {
    try {
      return await getShoppingAdminReviewsReviewIdAbuseReportsAbuseReportId({
        admin,
        reviewId,
        abuseReportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete an abuse report from a specific product review
   * (shopping_review_abuse_reports).
   *
   * This API operation allows a privileged actor—such as an admin moderator—to
   * permanently remove an abuse report record from a specific review. The
   * underlying business scenario typically involves finalized moderation,
   * fraudulent reporting, or legal takedown, making this a destructive action
   * recorded for platform compliance.
   *
   * Security considerations mandate that only privileged actors (admin) can
   * perform this operation. All deletions trigger an audit trail in the admin
   * operations log for later investigation or regulatory review. The
   * corresponding abuse report will no longer be visible to any actor, and any
   * resolution or associated moderation actions are retained separately in
   * platform logs.
   *
   * This operation references the shopping_review_abuse_reports table,
   * requiring both the parent reviewId (UUID) and the abuseReportId (UUID).
   * Both values are mapped 1:1 to ensure only the targeted abuse report for the
   * correct review is deleted. If either UUID is invalid or not found, the
   * operation returns a not found or permission denied error. No soft delete or
   * recovery is provided through this API.
   *
   * Integration with related API operations may occur when reviewing or
   * resolving escalated review abuse complaints; typically, related GET
   * endpoints for review or abuse report details are used in tandem when
   * preparing for this action.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review (UUID, must match
   *   the review receiving the abuse report).
   * @param abuseReportId Unique identifier of the abuse report to be deleted
   *   from the specified review (UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":abuseReportId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("abuseReportId")
    abuseReportId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminReviewsReviewIdAbuseReportsAbuseReportId({
        admin,
        reviewId,
        abuseReportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
