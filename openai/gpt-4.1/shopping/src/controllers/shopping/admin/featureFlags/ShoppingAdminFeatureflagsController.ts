import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingAdminFeatureFlags } from "../../../../providers/postShoppingAdminFeatureFlags";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminFeatureFlags } from "../../../../providers/patchShoppingAdminFeatureFlags";
import { getShoppingAdminFeatureFlagsFlagName } from "../../../../providers/getShoppingAdminFeatureFlagsFlagName";
import { putShoppingAdminFeatureFlagsFlagName } from "../../../../providers/putShoppingAdminFeatureFlagsFlagName";
import { deleteShoppingAdminFeatureFlagsFlagName } from "../../../../providers/deleteShoppingAdminFeatureFlagsFlagName";

import { IShoppingFeatureFlag } from "../../../../api/structures/IShoppingFeatureFlag";
import { IPageIShoppingFeatureFlag } from "../../../../api/structures/IPageIShoppingFeatureFlag";

@Controller("/shopping/admin/featureFlags")
export class ShoppingAdminFeatureflagsController {
  /**
   * Create a new feature flag (shopping_feature_flags table).
   *
   * Allows administrative users to create a new feature flag entry by supplying
   * all required fields as defined in the shopping_feature_flags table,
   * including the flag_code (business identifier, unique), scope
   * (context/domain for the flag), enabled state, optional percent-based
   * rollout, and a business description. This operation is essential for
   * managing rollouts of new features, enabling A/B testing, and improving
   * operational safety during code deployments through runtime toggling.
   *
   * Strict validation ensures that the provided flag_code is globally unique
   * and rejects creation if a flag with the same code already exists. Inputs
   * are further validated to confirm the scope is provided and description is
   * meaningful for admins and developers referencing the flag. This endpoint is
   * for admin use only and enforces permissions at the controller level. Audit
   * logging should be performed for all creation events. Upon success, the
   * created feature flag entry is returned with all specified and
   * system-generated fields populated. In case of validation or authorization
   * errors, informative error messages are returned.
   *
   * @param connection
   * @param body Information needed to create a new feature flag, including
   *   unique code, scope, enablement, rollout percent, and admin-provided
   *   description.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingFeatureFlag.ICreate,
  ): Promise<IShoppingFeatureFlag> {
    try {
      return await postShoppingAdminFeatureFlags({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search, filter, and paginate feature flags for platform-wide feature
   * management.
   *
   * This endpoint allows administrative users to search and retrieve the
   * complete list of feature flags configured in the shopping mall platform.
   * The shopping_feature_flags model supports global and context-specific
   * feature toggles (enabling beta features, experiments, and rollouts by
   * scope), and this operation enables comprehensive querying based on flag
   * names, scopes, enabled states, and rollout percentages.
   *
   * Administrators can use flexible filters within the request body, specifying
   * criteria such as flagName, scope, enabled status, and pagination
   * preferences (page number, limit, and sorting options). Paginated results
   * ensure efficient retrieval regardless of catalog size, and each feature
   * flag returned includes all flag metadata needed for platform control and
   * auditing.
   *
   * Security: Only admin actors can access this endpoint, and all actions are
   * logged for compliance. The operation does not modify feature flags but
   * provides read-only insight to manage the platform's feature control
   * mechanisms.
   *
   * @param connection
   * @param body Filter and pagination parameters for feature flag search (e.g.,
   *   flag name, scope, enabled status, pagination and sort options).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingFeatureFlag.IRequest,
  ): Promise<IPageIShoppingFeatureFlag.ISummary> {
    try {
      return await patchShoppingAdminFeatureFlags({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a feature flag by flag code (shopping_feature_flags table).
   *
   * Fetches detailed information about a feature flag, including its status
   * (enabled or disabled), rollout percentage, description, and scope, by
   * looking up the provided flagName (business code) against the
   * shopping_feature_flags table. This operation enables platform code to
   * dynamically check for feature enablement during runtime, supports gradual
   * feature rollouts via percentage-based activation, and is essential for A/B
   * experimentation, admin toggling, or business rule enforcement.
   *
   * This endpoint includes authentication and requires proper actor
   * authorization to prevent unauthorized viewing or enumeration of feature
   * toggles. Only admin users may retrieve feature flag definitions.
   *
   * Business validation includes confirming the flag is not soft-deleted and
   * the flagName exists. Errors returned if the flag does not exist or access
   * is denied. This operation integrates tightly with continuous delivery and
   * admin dashboard interfaces. Relying on shopping_feature_flags's
   * constraints, attempts to access a missing or deleted flag return an
   * appropriate error, while valid lookups supply all fields needed for runtime
   * toggling, experimentation, and audit logging.
   *
   * @param connection
   * @param flagName Unique business code identifier for the feature flag
   *   (corresponds to flag_code in the shopping_feature_flags table; global
   *   scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":flagName")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("flagName")
    flagName: string,
  ): Promise<IShoppingFeatureFlag> {
    try {
      return await getShoppingAdminFeatureFlagsFlagName({
        admin,
        flagName,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a feature flag's configuration in the shopping_feature_flags table
   * by flagName (admin only).
   *
   * Update an existing feature flag's configuration by specifying the flag's
   * unique flagName and providing updated values for its attributes such as
   * enabled state, scope, rollout percentage, and business description. This
   * endpoint enables authorized admin actors to manage feature availability,
   * A/B testing rollout, and domain-controlled enablement for the shopping
   * platform. Business and compliance rules require that only admins can
   * perform updates, and all changes must be fully auditable with actor/entity
   * context recorded in the system logs.
   *
   * The feature flag is identified by the flagName (string), which maps to the
   * flag_name field in the shopping_feature_flags table. This endpoint allows
   * modification of the enabled (Boolean), rollout (Float, optional),
   * description (String), and scope (String) fields according to business
   * policy. The endpoint enforces that flagName is unique and exists before any
   * update occurs; attempts to update a non-existent or archived flag SHALL
   * result in a clear error.
   *
   * Proper validation must be performed to ensure logical and business
   * constraints are not violated (e.g., rollout must be between 0 and 100,
   * flagName must match an existing feature flag). This operation is critical
   * for controlling live feature toggles and test releases across platform
   * domains, supporting safe, controlled deployments and fast rollback in the
   * event of issue discovery. Admin-only access is strictly enforced through
   * authentication and role-based authorization mechanisms.
   *
   * @param connection
   * @param flagName Unique business identifier of the feature flag to be
   *   updated (global scope); this corresponds to the flag_name field and must
   *   be a string identifying an existing feature flag.
   * @param body Fields for updating feature flag configuration: enabled
   *   (Boolean), optional rollout (Float, 0.0–100.0), scope (String), and
   *   description (String). All fields are schema-validated for business rules
   *   and compliance.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":flagName")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("flagName")
    flagName: string,
    @TypedBody()
    body: IShoppingFeatureFlag.IUpdate,
  ): Promise<IShoppingFeatureFlag> {
    try {
      return await putShoppingAdminFeatureFlagsFlagName({
        admin,
        flagName,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a feature flag (flag_name) from the
   * shopping_feature_flags table by flagName (admin only).
   *
   * Permanently remove a specified feature flag from the system, using its
   * global flagName as the identifier (corresponding to the flag_name field in
   * the shopping_feature_flags table). This endpoint is restricted to admin
   * actors and enforces audit logging of all delete actions for compliance and
   * traceability. Attempting to delete a non-existent, already deleted, or
   * in-use flag will produce clear errors as defined by business policy.
   *
   * This delete operation is irreversible and removes all configuration,
   * rollout, and enablement data for the feature flag. It is suitable for
   * cleanup of deprecated, obsolete, or invalid feature toggles, and not for
   * soft-deletion or archival: once removed via this endpoint, the flag cannot
   * be restored and must be recreated if needed. Security checks ensure only
   * admins can invoke this action and that all deletion events are logged in
   * the platform's administrative audit logs for regulatory and support
   * review.
   *
   * This operation is critical for compliance and operational hygiene, ensuring
   * that obsolete or deprecated feature toggles do not persist and
   * inadvertently affect business logic or application flow. Admin permissions
   * must be strictly enforced; business rules also require clear user feedback
   * if the flagName does not exist or cannot be deleted due to in-use
   * constraints.
   *
   * @param connection
   * @param flagName Unique business identifier of the feature flag to be
   *   deleted (global scope), corresponding to the flag_name field in the
   *   database.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":flagName")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("flagName")
    flagName: string,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminFeatureFlagsFlagName({
        admin,
        flagName,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
