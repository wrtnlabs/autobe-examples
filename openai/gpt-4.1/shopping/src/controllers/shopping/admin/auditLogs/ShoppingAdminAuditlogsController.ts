import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingAdminAuditLogs } from "../../../../providers/patchShoppingAdminAuditLogs";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingAdminAuditLogsAuditLogId } from "../../../../providers/getShoppingAdminAuditLogsAuditLogId";

import { IPageIShoppingAuditLog } from "../../../../api/structures/IPageIShoppingAuditLog";
import { IShoppingAuditLog } from "../../../../api/structures/IShoppingAuditLog";

@Controller("/shopping/admin/auditLogs")
export class ShoppingAdminAuditlogsController {
  /**
   * Search and retrieve filtered, paginated audit log records for platform
   * security and compliance. Admins only.
   *
   * Retrieve a filtered, paginated list of audit log entries from the
   * shopping_audit_logs table, enabling admin users to review platform
   * security, compliance, and business operations events. The operation allows
   * extensive filtering on category, actor (admin, seller, customer), event
   * type, date range, or description text, supporting advanced incident
   * investigations and policy audits.
   *
   * All audit logs are immutably recorded in shopping_audit_logs, with
   * references to relevant account actors and operational categories. The API
   * supports pagination and sorting to handle large volumes of logs
   * efficiently.
   *
   * Access to this endpoint is restricted to admin actors. Security measures
   * include authentication, role-based permissions, and audit of log access
   * itself. The endpoint is vital for incident response, compliance reporting,
   * and platform governance. Any attempt to access this API by non-admins is
   * denied, and failed access is logged for security forensics.
   *
   * @param connection
   * @param body Search criteria for filtering and paginating audit log results,
   *   including actor, category, event type, date range, or description
   *   keyword.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingAuditLog.IRequest,
  ): Promise<IPageIShoppingAuditLog.ISummary> {
    try {
      return await patchShoppingAdminAuditLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve one audit log entry (shopping_audit_logs) by its UUID for
   * investigation/admin review.
   *
   * Fetch a single immutable audit log record by its unique identifier from the
   * shopping_audit_logs table. This endpoint is intended for compliance,
   * investigation, and platform administration; access is restricted strictly
   * to users with admin privileges. The returned data includes actor linkage
   * (admin, seller, customer as available), event category and type, summary,
   * timestamp, and any supplementary details. The API ensures that sensitive
   * business operations—such as administrative escalations, privilege changes,
   * critical order interventions, and platform configuration changes—can be
   * traced in support of regulatory audits and business rule enforcement.
   *
   * Security is a primary concern as audit logs may contain personally
   * identifiable and sensitive event context. Strong authentication and role
   * checks are enforced, and all accesses are tracked for meta-audit purposes.
   * Application layer rate limiting is advised to prevent data scraping. If the
   * specified audit log ID does not exist, a proper not found error is
   * returned, with no leakage of sensitive context. Referenced linked entities
   * must be internally resolved as required for full traceability.
   *
   * Returned data structure follows the IShoppingAuditLog schema and contains
   * all fields available in the shopping_audit_logs table, including actor
   * references and descriptive fields.
   *
   * @param connection
   * @param auditLogId Unique identifier (UUID) of the audit log record to fetch
   *   (global scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":auditLogId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("auditLogId")
    auditLogId: string & tags.Format<"uuid">,
  ): Promise<IShoppingAuditLog> {
    try {
      return await getShoppingAdminAuditLogsAuditLogId({
        admin,
        auditLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
