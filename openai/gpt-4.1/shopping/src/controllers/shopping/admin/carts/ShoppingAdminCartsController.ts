import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingAdminCarts } from "../../../../providers/patchShoppingAdminCarts";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingAdminCartsCartId } from "../../../../providers/getShoppingAdminCartsCartId";

import { IPageIShoppingCart } from "../../../../api/structures/IPageIShoppingCart";
import { IShoppingCart } from "../../../../api/structures/IShoppingCart";

@Controller("/shopping/admin/carts")
export class ShoppingAdminCartsController {
  /**
   * Search and retrieve a paginated list of shopping carts with filtering
   * options (shopping_carts table).
   *
   * This endpoint is designed to provide system access to the list of all
   * customer shopping carts in the platform. It is particularly useful for
   * administrative or operational roles that require a broad view of customer
   * engagement or troubleshooting of shopping cart behaviors.
   *
   * The response includes concise summary information about each cart, such as
   * the linked customer, creation and last update timestamps, number of items
   * in the cart, and relationships to customer or product data as necessary for
   * list context. Advanced filtering options enable searching for carts by
   * customer ID, activity date, or other identifying characteristics,
   * supporting both routine reviews and targeted queries.
   *
   * Security measures ensure that only authorized actors (typically admin or
   * designated operational personnel) can use this endpoint, and that
   * personally identifiable information is handled per compliance policies.
   * Results are paginated with customizable limits and standardized sorting
   * controls. This operation does not expose individual cart item details (see
   * specific cart retrieval for that functionality). Error handling covers
   * cases where query parameters are malformed or system access is not
   * permitted.
   *
   * @param connection
   * @param body Filter and pagination information for shopping cart listings.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingCart.IRequest,
  ): Promise<IPageIShoppingCart.ISummary> {
    try {
      return await patchShoppingAdminCarts({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the detailed contents and context of a single shopping cart by its
   * ID (shopping_carts table).
   *
   * This endpoint provides the complete state of a particular customer's
   * shopping cart, addressing both functional requirements for customer
   * self-management and administrative review needs.
   *
   * The API accepts a unique cartId in the path, which must be a valid UUID as
   * defined in the shopping_carts model. The response includes detailed cart
   * content: all associated cart items (with SKU references, quantities, and
   * item-level timestamps), customer linkage, and key activity milestones. This
   * comprehensive view is essential for client-side representations for order
   * review, customer support investigations, or fulfillment systems that need
   * to convert cart contents to orders.
   *
   * Security restrictions require appropriate actor privileges: typically
   * authenticated admin or platform operators for global access—normal
   * customers would access their own cart through a separate self-context
   * endpoint. Input validation ensures the cartId is correctly formatted, and
   * robust error handling covers non-existent or unauthorized access scenarios.
   * The design aligns with operational best practices and compliance
   * expectations for data access.
   *
   * @param connection
   * @param cartId Unique identifier of the target shopping cart (UUID format,
   *   references shopping_carts.id).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":cartId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
  ): Promise<IShoppingCart> {
    try {
      return await getShoppingAdminCartsCartId({
        admin,
        cartId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
