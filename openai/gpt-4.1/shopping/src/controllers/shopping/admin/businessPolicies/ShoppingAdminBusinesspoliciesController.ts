import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingAdminBusinessPolicies } from "../../../../providers/postShoppingAdminBusinessPolicies";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminBusinessPolicies } from "../../../../providers/patchShoppingAdminBusinessPolicies";
import { putShoppingAdminBusinessPoliciesPolicyName } from "../../../../providers/putShoppingAdminBusinessPoliciesPolicyName";
import { deleteShoppingAdminBusinessPoliciesPolicyName } from "../../../../providers/deleteShoppingAdminBusinessPoliciesPolicyName";

import { IShoppingBusinessPolicy } from "../../../../api/structures/IShoppingBusinessPolicy";
import { IPageIShoppingBusinessPolicy } from "../../../../api/structures/IPageIShoppingBusinessPolicy";

@Controller("/shopping/admin/businessPolicies")
export class ShoppingAdminBusinesspoliciesController {
  /**
   * Register a new business policy in shopping_business_policies (admin only).
   *
   * Create a new business policy configuration in the
   * shopping_business_policies table.
   *
   * This API requires submission of all mandatory business policy attributes,
   * including policy_name, scope, value, and a clear description of
   * purpose/impact. Business policy metadata such as activation status is also
   * recorded. The operation verifies uniqueness of the (policy_name, scope)
   * pair, returning a business validation error if a collision is found.
   *
   * Only authenticated admin users are authorized to create new business rules
   * via this endpoint, ensuring proper segregation of duties and audit
   * compliance. Once created, policies are immediately available for
   * operational use and system enforcement. Sensitive values (such as legal or
   * regulatory thresholds) should be correctly structured to prevent
   * misconfiguration or policy bypass.
   *
   * @param connection
   * @param body Full details for the business policy to be created, including
   *   policy_name, scope, value, activation, and description.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingBusinessPolicy.ICreate,
  ): Promise<IShoppingBusinessPolicy> {
    try {
      return await postShoppingAdminBusinessPolicies({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve paginated business policy configuration records
   * (BusinessPolicy table).
   *
   * Retrieve a filtered, paginated list of business policy records stored on
   * the system. This operation provides advanced search options by policy name,
   * scope, status, or descriptive text, enabling efficient location and audit
   * of platform policy settings.
   *
   * Supports full pagination, sorting, and logical search criteria. Intended
   * for admin users responsible for platform-wide rules management, the
   * endpoint returns record summaries excluding sensitive internal notes. Only
   * actors with appropriate admin privileges can invoke this endpoint. Related
   * edit or archival actions must use dedicated endpoints. Comprehensive search
   * audit logs and query performance metrics are recorded as part of
   * non-functional compliance enforcement.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for locating policy
   *   records (see IShoppingBusinessPolicy.IRequest)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingBusinessPolicy.IRequest,
  ): Promise<IPageIShoppingBusinessPolicy.ISummary> {
    try {
      return await patchShoppingAdminBusinessPolicies({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing business policy by unique policyName in the
   * shopping_business_policies table.
   *
   * This operation lets a platform administrator revise an existing business
   * policy's parameters. Updates can include changes to scope (domain of the
   * rule), value (allowed threshold or state), description (business
   * explanation), and the active flag, as defined in the
   * shopping_business_policies schema table. The implementation ensures the
   * correct row is found by the unique policy_name (strings matching
   *
   * @param connection
   * @param policyName Globally unique name of the business policy to update
   *   (global scope)
   * @param body The fields to update in the business policy, excluding
   *   policyName
   * @@unique([policy_name,
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":policyName")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("policyName")
    policyName: string,
    @TypedBody()
    body: IShoppingBusinessPolicy.IUpdate,
  ): Promise<IShoppingBusinessPolicy> {
    try {
      return await putShoppingAdminBusinessPoliciesPolicyName({
        admin,
        policyName,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a business policy by unique policyName in the
   * shopping_business_policies table.
   *
   * This operation enables an administrator to remove a business policy from
   * the system configuration using the policy's unique policyName. The business
   * policy being deleted is identified by the path parameter, which must
   * correspond to the policy_name column in the shopping_business_policies
   * table. Only platform administrators may execute this action.
   *
   * Deletion is immediate and permanent—meaning all associated business logic
   * controlled by the deleted policy will no longer apply in the platform. The
   * absence of soft deletion in this table (no deleted_at support) results in
   * thorough and unrecoverable removal. The implementation should reject
   * requests targeting a non-existent policyName and return a clear error for
   * not found situations. Audit logs of all deletes are critical for compliance
   * and regulatory oversight.
   *
   * @param connection
   * @param policyName Globally unique name of the business policy to delete
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":policyName")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("policyName")
    policyName: string,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminBusinessPoliciesPolicyName({
        admin,
        policyName,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
