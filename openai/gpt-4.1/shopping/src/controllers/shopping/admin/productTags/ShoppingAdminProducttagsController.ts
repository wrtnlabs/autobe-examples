import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingAdminProductTags } from "../../../../providers/postShoppingAdminProductTags";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminProductTags } from "../../../../providers/patchShoppingAdminProductTags";
import { putShoppingAdminProductTagsTagCode } from "../../../../providers/putShoppingAdminProductTagsTagCode";
import { deleteShoppingAdminProductTagsTagCode } from "../../../../providers/deleteShoppingAdminProductTagsTagCode";

import { IShoppingProductTag } from "../../../../api/structures/IShoppingProductTag";
import { IPageIShoppingProductTag } from "../../../../api/structures/IPageIShoppingProductTag";

@Controller("/shopping/admin/productTags")
export class ShoppingAdminProducttagsController {
  /**
   * Create a new product tag in the catalog (shopping_product_tags).
   *
   * This API endpoint supports the creation of new product tags that can be
   * assigned to products for catalog search and filtering. It requires
   * providing a unique tag_code, business-purpose display value, and a
   * descriptive string for the new tag. The operation performs strict
   * uniqueness checks against existing entries in the shopping_product_tags
   * schema and validates all provided fields for compliance with catalog
   * standards.
   *
   * This functionality is reserved for business actors with admin or catalog
   * management roles and may not be accessible by sellers or general users. If
   * the tag_code already exists, the endpoint will return an error. The
   * response returns the newly created product tag’s metadata as persisted in
   * the underlying schema, supporting business validation, platform navigation,
   * and future search display use cases.
   *
   * The endpoint enforces business integrity by ensuring only valid, new tags
   * are introduced into the platform ecosystem, and every field is recorded
   * with audit precision.
   *
   * @param connection
   * @param body Fields for creating a new product tag in the catalog. All
   *   required fields must be included and meet validation rules for catalog
   *   metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingProductTag.ICreate,
  ): Promise<IShoppingProductTag> {
    try {
      return await postShoppingAdminProductTags({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and paginate product tags (shopping_product_tags table).
   *
   * This API operation enables platform administrators to search and retrieve
   * the list of product tags that are registered in the system for cataloging
   * and classification purposes. It leverages advanced filtering criteria,
   * allowing searching by tag code, display value, or associated description,
   * as defined in the 'shopping_product_tags' table.
   *
   * The operation supports pagination with configurable page size and offset,
   * as well as sorting by tag name, creation date, or other tag metadata
   * fields. Tags that match partial queries or full-text searches can be
   * efficiently returned. The endpoint is valuable for tag audits, curation, or
   * mass-update planning.
   *
   * Security restricts access to authorized admin actors to prevent
   * unauthorized manipulation or review of catalog taxonomies. The typical use
   * case includes preparing for mass edits, compliance checks (e.g., flagging
   * unapproved terminology), or reviewing all tags tied to major catalog
   * campaigns. The response provides a summary view optimized for listing, not
   * detailed tag metadata.
   *
   * @param connection
   * @param body Advanced filter, search, and pagination parameters for product
   *   tag retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingProductTag.IRequest,
  ): Promise<IPageIShoppingProductTag.ISummary> {
    try {
      return await patchShoppingAdminProductTags({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product tag by tag code in the shopping_product_tags
   * table.
   *
   * Update an existing product tag by its unique tag code. The tagCode path
   * parameter identifies which tag will be updated. The fields that may be
   * updated include display_value and description, in accordance with the
   * Prisma schema for shopping_product_tags, which ensures that tag codes are
   * unique and used consistently across the platform. If a new display value is
   * supplied, it must fit platform guidelines (e.g., not exceed character
   * limits or include prohibited content). If description is modified, it
   * should clarify the tag's business purpose for admin and seller use.
   *
   * The operation checks that the tagCode provided in the path matches an
   * existing tag. If the update includes changes to display_value or
   * description, those changes propagate to all products presently using this
   * tag through the shopping_product_tag_assignments table. Attempts to update
   * the code itself or assign a display_value that duplicates existing tag
   * codes will result in a validation error as enforced by the unique
   * constraint defined in the Prisma schema.
   *
   * This endpoint is accessible by admin-level actors only, respecting the
   * sensitive nature of tag and catalog management. All changes are auditable,
   * and unauthorized use is strictly forbidden. This operation should be used
   * only for corrective or refinement edits, not for re-assigning tags across
   * product domains. Related endpoints support tag assignment to products and
   * tag deletion.
   *
   * @param connection
   * @param tagCode Globally unique business code to identify the target product
   *   tag (global scope).
   * @param body Fields to update for the product tag, such as display_value and
   *   description.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":tagCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("tagCode")
    tagCode: string,
    @TypedBody()
    body: IShoppingProductTag.IUpdate,
  ): Promise<IShoppingProductTag> {
    try {
      return await putShoppingAdminProductTagsTagCode({
        admin,
        tagCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a product tag by tag code from the shopping_product_tags
   * table.
   *
   * Permanently remove a product tag identified by its global tag code. The
   * tagCode path parameter specifies which tag will be deleted. The operation
   * targets the shopping_product_tags table, as defined in the Prisma schema,
   * which uses tag_code as a unique business identifier. All product-to-tag
   * assignments to this tag in shopping_product_tag_assignments are either
   * removed or prevent deletion as per configuration. If the tag is
   * system-reserved or does not exist, the operation fails with a clear error
   * message explaining the reason.
   *
   * This operation is only available to admins due to its business impact.
   * Deletion is permanent (hard delete) in the absence of a soft
   * delete/deleted_at field in the schema. All deletion actions are
   * audit-logged. Depending on platform policy, deletion may be prevented if
   * the tag is still referenced, or all assignments may be purged along with
   * the tag. Other endpoints exist for assigning or updating tags.
   *
   * @param connection
   * @param tagCode Globally unique business code to identify the target product
   *   tag (global scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":tagCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("tagCode")
    tagCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminProductTagsTagCode({
        admin,
        tagCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
