import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingAdminBusinessSettings } from "../../../../providers/postShoppingAdminBusinessSettings";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminBusinessSettings } from "../../../../providers/patchShoppingAdminBusinessSettings";
import { getShoppingAdminBusinessSettingsSettingKey } from "../../../../providers/getShoppingAdminBusinessSettingsSettingKey";
import { putShoppingAdminBusinessSettingsSettingKey } from "../../../../providers/putShoppingAdminBusinessSettingsSettingKey";
import { deleteShoppingAdminBusinessSettingsSettingKey } from "../../../../providers/deleteShoppingAdminBusinessSettingsSettingKey";

import { IShoppingBusinessSetting } from "../../../../api/structures/IShoppingBusinessSetting";
import { IPageIShoppingBusinessSetting } from "../../../../api/structures/IPageIShoppingBusinessSetting";

@Controller("/shopping/admin/businessSettings")
export class ShoppingAdminBusinesssettingsController {
  /**
   * Create a new business setting row in shopping_business_settings with
   * required fields.
   *
   * Create a new platform-wide business setting using the provided key and
   * value, defining operational parameters such as currency, country,
   * regulatory options, or other top-level configuration. The operation is tied
   * directly to the 'shopping_business_settings' table and supports the
   * creation of a single new row per call. Uniqueness is enforced on the
   * setting_key; if a duplicate key is detected, the operation must fail,
   * indicating the cause in a machine-readable business error.
   *
   * Security and authorization are required: only platform administrators may
   * perform this operation, as business policy settings control core system
   * behaviors and may have compliance or regulatory impacts. The operation
   * accepts a request body that must include setting_key and setting_value as
   * strings, with an optional description field. Upon success, the full setting
   * record is returned with all populated fields and audit information
   * (timestamps, etc.).
   *
   * Associated operations include updating an existing setting and retrieving
   * settings by key. All inputs are validated per schema requirements. The
   * operation ensures proper documentation, type usage, and audit traceability
   * for all newly created settings.
   *
   * @param connection
   * @param body Fields for the new business setting, including the unique
   *   business key, value, and optional description.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingBusinessSetting.ICreate,
  ): Promise<IShoppingBusinessSetting> {
    try {
      return await postShoppingAdminBusinessSettings({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated, filtered list of business settings
   * (shopping_business_settings).
   *
   * This API endpoint enables admin users to conduct advanced searches and
   * retrieval of business settings from the shopping_business_settings table.
   * The operation supports filtering by setting_key (case-insensitive),
   * setting_value (partial match), description content, and time-window on
   * creation or update timestamps. Pagination parameters such as page number
   * and page size are available, as well as sorting options on key fields like
   * created_at and updated_at.
   *
   * This function is critical for administrative audit, platform maintenance,
   * and regulatory oversight, giving authorized actors visibility into the
   * current and historical configuration of business rules such as currency,
   * region, tax policies, and other global settings. Search results reflect all
   * columns present in the Prisma schema, ensuring comprehensive visibility for
   * each setting, including active and soft-deleted records if business policy
   * demands. Response data is tailored for list display and further filtering,
   * without exposing sensitive internal details. Security is enforced so only
   * admin users can access this information.
   *
   * When used, this endpoint can be chained with single-setting CRUD operations
   * for detailed audit or configuration changes. Errors in filter expressions,
   * missing required pagination data, or invalid search terms result in clear
   * error responses. The operation provides defensive measures against
   * over-pagination or misuse by non-privileged actors.
   *
   * @param connection
   * @param body Criteria for searching, filtering, paginating, and sorting
   *   business settings.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingBusinessSetting.IRequest,
  ): Promise<IPageIShoppingBusinessSetting.ISummary> {
    try {
      return await patchShoppingAdminBusinessSettings({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single business setting by unique setting_key from
   * shopping_business_settings table.
   *
   * Fetch detailed business setting information by its business identifier key
   * as defined in the 'shopping_business_settings' table. This operation is
   * essential for retrieving configuration parameters that control global
   * behaviors, such as currency, supported country, or regulatory modes. The
   * setting is identified by setting_key, which MUST be unique and is enforced
   * at the database schema level.
   *
   * Security and access control should ensure that only authorized system
   * actors or platform administrators can access sensitive settings. The
   * operation excludes soft-deleted records, ensuring only live configuration
   * data is returned. If the key is not found, a 404 error with an appropriate
   * business message should be returned, clarifying the absence. This API is
   * commonly used by application servers, admin consoles, and system processes
   * initializing core parameters.
   *
   * This endpoint is directly associated with the shopping_business_settings
   * table and aligns with all comments and purpose descriptions found within
   * the schema. The setting_key path parameter is used instead of an id,
   * reflecting the business-centric design and maximizing clarity and developer
   * usability.
   *
   * Related operations may include business setting creation or update
   * (admin-only). Results are returned in a form suitable for direct
   * consumption by operational dashboards or internal system logic.
   *
   * @param connection
   * @param settingKey Business setting key (e.g., 'currency', 'tax_region',
   *   'supported_country'); uniquely identifies the row (global scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":settingKey")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("settingKey")
    settingKey: string,
  ): Promise<IShoppingBusinessSetting> {
    try {
      return await getShoppingAdminBusinessSettingsSettingKey({
        admin,
        settingKey,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a business setting by its unique settingKey
   * (shopping_business_settings).
   *
   * Update a business setting for the shopping platform using the unique
   * settingKey, which refers to a row in the shopping_business_settings table.
   * Administrators use this endpoint to modify configuration values that
   * influence core business logic, such as regional support, currency, or
   * compliance settings. The request body contains the new setting value and
   * optional description.
   *
   * This operation automatically updates the updated_at timestamp for
   * traceability. It does not allow creation of new settings; it only updates
   * existing ones, ensuring strict control over the business settings domain.
   * If a non-existent settingKey is provided, the operation returns an error
   * indicating the missing row. Authorization is limited to administrative
   * actors for system protection.
   *
   * Related operations include creating new business settings (not covered
   * here) and retrieving current business setting values. Error responses
   * handle cases such as a missing row, validation failure for setting_key, or
   * permission issues. The history of updates is retained via audit trails for
   * compliance and rollback support.
   *
   * @param connection
   * @param settingKey Unique business setting key identifying the setting to
   *   update (global scope).
   * @param body Data used to update the business setting, including the new
   *   value and optional description.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":settingKey")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("settingKey")
    settingKey: string,
    @TypedBody()
    body: IShoppingBusinessSetting.IUpdate,
  ): Promise<IShoppingBusinessSetting> {
    try {
      return await putShoppingAdminBusinessSettingsSettingKey({
        admin,
        settingKey,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a business setting by settingKey (hard delete on
   * shopping_business_settings table).
   *
   * Remove a business setting from the shopping platform using its unique
   * settingKey, which directly corresponds to a row in
   * shopping_business_settings. When an administrator invokes this operation,
   * the business setting is permanently deleted from the database, leaving no
   * remnants within the core business settings domain. This action is
   * irreversible; administrators should ensure the setting is no longer
   * required before relying on this endpoint.
   *
   * For compliance, an audit log entry is created detailing the deletion event,
   * including the settingKey and performing admin actor. Attempts to delete a
   * non-existent settingKey result in a clear error response. Authorization
   * checks are enforced for all administrative delete operations to prevent
   * accidental or malicious removal. No response body is returned if delete is
   * successful; otherwise, informative error messages guide remediation.
   *
   * The endpoint should not be used for routine disabling of settings, but only
   * for permanent removal of settings that are no longer operationally
   * relevant. Related endpoints include updating and retrieving setting values,
   * but not soft-deleting.
   *
   * @param connection
   * @param settingKey Unique business setting key identifying the setting to be
   *   deleted (global scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":settingKey")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("settingKey")
    settingKey: string,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminBusinessSettingsSettingKey({
        admin,
        settingKey,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
