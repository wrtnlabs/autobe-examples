import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { postShoppingAdminInventorySkuCodeAdjustments } from "../../../../../providers/postShoppingAdminInventorySkuCodeAdjustments";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminInventorySkuCodeAdjustments } from "../../../../../providers/patchShoppingAdminInventorySkuCodeAdjustments";

import { IShoppingInventoryAdjustment } from "../../../../../api/structures/IShoppingInventoryAdjustment";
import { IPageIShoppingInventoryAdjustment } from "../../../../../api/structures/IPageIShoppingInventoryAdjustment";

@Controller("/shopping/admin/inventory/:skuCode/adjustments")
export class ShoppingAdminInventoryAdjustmentsController {
  /**
   * Create a new inventory adjustment (atomic stock change) for a SKU
   * (shopping_inventory_adjustments).
   *
   * Append a new inventory adjustment record for a given SKU, documenting an
   * atomic change in inventory (increase/decrease/correction) for auditing and
   * operational accuracy. This API supports all legitimate business needs for
   * changing inventory: restock by sellers, system correction by admin,
   * order/return/refund reconciliation, and anomaly adjustments.
   *
   * A valid adjustment request must specify the SKU by code, the adjustment
   * amount (positive or negative integer), a business reason code, actor type,
   * and any contextual notes. The server will validate that the actor is
   * authorized to adjust this SKU (seller for own inventory, admin, or system
   * actor). Adjustments that would result in negative inventory are strictly
   * rejected and return a clear error. All fields (quantities before and after,
   * actor, timestamp) are immutably stored on acceptance for compliance. For
   * transactional consistency, the system applies the adjustment atomically
   * and, if required by business rules, triggers downstream alerts or low-stock
   * notifications. Error scenarios include unknown sku_code, lack of
   * permission, invalid adjustment amount, and business constraint violations.
   * Only authorized actors may use this endpoint; all events are audited.
   *
   * @param connection
   * @param skuCode Unique SKU business code for the target product (global
   *   scope). This identifies the specific SKU whose inventory is to be
   *   adjusted.
   * @param body Adjustment details including adjustment amount
   *   (positive/negative), business reason, actor type, and optional context
   *   notes. The request must also indicate which actor class is performing the
   *   adjustment (admin, seller, or system).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("skuCode")
    skuCode: string,
    @TypedBody()
    body: IShoppingInventoryAdjustment.ICreate,
  ): Promise<IShoppingInventoryAdjustment> {
    try {
      return await postShoppingAdminInventorySkuCodeAdjustments({
        admin,
        skuCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve audit and adjustment log for a specific SKU's inventory
   * (shopping_inventory_adjustments).
   *
   * Retrieve the full audit trail of all inventory adjustment events made to a
   * given SKU. This API returns detailed adjustment records, allowing
   * authorized users to investigate inventory changes, understand who made each
   * adjustment, and audit the operational history for compliance and
   * troubleshooting.
   *
   * Inventory adjustment events may occur due to customer orders, manual
   * restock by sellers or admins, refunds, cancellations, corrections, or
   * automated stock anomaly detection. All adjustment events are recorded with
   * before/after quantities, adjustment amounts, reason codes, context notes,
   * and a timestamp. Only users who have inventory management permission for
   * the SKU (owners, platform admins) can access this resource. Read access by
   * sellers is restricted to their own SKUs.
   *
   * The request supports advanced query parameters for audit/search purposes,
   * including filtering by actor type (customer, seller, admin, system), date
   * range, adjustment range, and free-text search of context notes. Pagination
   * and sorting controls are available to efficiently browse large adjustment
   * log histories. Users should inspect this audit log for troubleshooting
   * stock discrepancies or reviewing compliance with inventory policies.
   * Related error scenarios (e.g., unknown sku_code, unauthorized access) are
   * surfaced with clear error messages.
   *
   * @param connection
   * @param skuCode Unique SKU business code for the target product (global
   *   scope). Used to identify the specific SKU whose adjustments are to be
   *   audited.
   * @param body Parameters for filtering, paginating, and searching the SKU's
   *   inventory adjustment history. May include actor type, adjustment date
   *   range, quantity deltas, and reason code.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("skuCode")
    skuCode: string,
    @TypedBody()
    body: IShoppingInventoryAdjustment.IRequest,
  ): Promise<IPageIShoppingInventoryAdjustment> {
    try {
      return await patchShoppingAdminInventorySkuCodeAdjustments({
        admin,
        skuCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
