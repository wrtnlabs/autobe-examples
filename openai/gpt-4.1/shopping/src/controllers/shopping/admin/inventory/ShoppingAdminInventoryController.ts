import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingAdminInventory } from "../../../../providers/patchShoppingAdminInventory";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingAdminInventorySkuCode } from "../../../../providers/getShoppingAdminInventorySkuCode";

import { IPageIShoppingInventory } from "../../../../api/structures/IPageIShoppingInventory";
import { IShoppingInventory } from "../../../../api/structures/IShoppingInventory";

@Controller("/shopping/admin/inventory")
export class ShoppingAdminInventoryController {
  /**
   * Search and retrieve a paginated, filtered list of product SKU inventory
   * entries.
   *
   * Retrieve a paginated, filterable list of SKU inventory states from the
   * Inventory table. This operation allows admin and sellers to view inventory
   * levels across all SKUs, filter by SKU code, product, seller, and thresholds
   * for stock alerts. Pagination is supported to handle large item volumes, and
   * inventory may be sorted by SKU code, last updated timestamp, or stock
   * quantity.
   *
   * The operation enhances supply chain management by providing real-time
   * access to inventory, supporting decision-making for restocking, identifying
   * low or out-of-stock SKUs for operational follow-up, and integrating with
   * inventory alerts and adjustments for compliance. Additional security
   * measures restrict access to authorized admin and seller actors, with data
   * visibility scoped to their permissions.
   *
   * Advanced features include the ability to search SKUs by keyword, filter by
   * quantity range, and sort by recency or stock level. Proper use of this API
   * ensures continuous product availability and prevents overselling via timely
   * inventory checks. Error handling includes denial of unauthorized access and
   * reporting any schema validation issues in filters or sort parameters.
   *
   * @param connection
   * @param body Inventory search and pagination parameters such as SKU code,
   *   product ID, seller ID, quantity range, and sorting options
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingInventory.IRequest,
  ): Promise<IPageIShoppingInventory.ISummary> {
    try {
      return await patchShoppingAdminInventory({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed inventory state for an individual SKU by its unique code.
   *
   * Fetch detailed inventory data for a SKU using its globally unique SKU code
   * from the Inventory table. This includes current stock quantity, last
   * updated time, and references to the associated product. The endpoint
   * supports operational use cases such as confirming available quantity for
   * order processing, auditing stock changes, and managing real-time catalogue
   * listings.
   *
   * The operation requires valid SKU code input and restricts data visibility
   * to admin and seller roles for business safety. Validation includes
   * confirmation that the SKU exists, returning an error if not found or if the
   * code is invalid. The operation may be used in conjunction with inventory
   * adjustment operations for full traceability of stock movements.
   *
   * Security and error handling ensure that unauthorized actors are denied
   * access, and business logic prevents stock disclosure to non-permitted
   * actors. Related APIs include those for batch inventory searching, inventory
   * adjustment, and SKU management.
   *
   * @param connection
   * @param skuCode Globally unique business code of the SKU to look up (global
   *   scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":skuCode")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("skuCode")
    skuCode: string,
  ): Promise<IShoppingInventory> {
    try {
      return await getShoppingAdminInventorySkuCode({
        admin,
        skuCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
