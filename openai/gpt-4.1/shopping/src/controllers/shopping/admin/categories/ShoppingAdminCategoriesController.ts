import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingAdminCategories } from "../../../../providers/postShoppingAdminCategories";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminCategories } from "../../../../providers/patchShoppingAdminCategories";
import { putShoppingAdminCategoriesCategoryTreeCodeCategoryCode } from "../../../../providers/putShoppingAdminCategoriesCategoryTreeCodeCategoryCode";
import { deleteShoppingAdminCategoriesCategoryTreeCodeCategoryCode } from "../../../../providers/deleteShoppingAdminCategoriesCategoryTreeCodeCategoryCode";

import { IShoppingCategory } from "../../../../api/structures/IShoppingCategory";
import { IPageIShoppingCategory } from "../../../../api/structures/IPageIShoppingCategory";

@Controller("/shopping/admin/categories")
export class ShoppingAdminCategoriesController {
  /**
   * Create a new category node in a specified category tree
   * (shopping_categories table).
   *
   * This endpoint allows platform administrators to add a new category node to
   * a category tree. The administrator must provide the target tree, category
   * code (unique per tree), display name, sort order, and optionally the parent
   * category (for hierarchical nesting).
   *
   * The underlying operation inserts a new row into the shopping_categories
   * table. Business constraints such as unique category_code per tree and max
   * depth/structure are enforced. The operation enables building and
   * maintaining a hierarchical, multi-level product catalog.
   *
   * Only admin users can use this operation. Attempts by non-admin users will
   * be rejected. The system validates all required fields and returns an error
   * if uniqueness or format constraints are violated.
   *
   * @param connection
   * @param body Required fields for creating a new category in a category tree.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingCategory.ICreate,
  ): Promise<IShoppingCategory> {
    try {
      return await postShoppingAdminCategories({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search, filter, and page through all shopping categories.
   *
   * This API enables complex, paginated search for product categories as
   * defined in the shopping_categories table, including tree-scoped and global
   * queries. It allows searching by category name, code, parent, depth, or tree
   * and supports both precise parent-child navigation and freeform keyword
   * search. All results exclude categories where deleted_at is not null,
   * ensuring only active branches are returned.
   *
   * Security: This read-only query is accessible to both authenticated sellers
   * and admins (for management and assignment operations), but may be exposed
   * publicly for unprivileged catalog browsing where appropriate. Admins and
   * sellers can receive extra metadata (such as full path or assignment stats)
   * per business rules, but core output follows category table definitions.
   *
   * The query leverages existing category fields, ensures strict parent-child
   * context when 'parent_id' is supplied, and includes descriptions and display
   * ordering for all results. Sorting can be customized by 'sort_order', name,
   * or other indexed fields—scalable indexing ensures performance. Edge cases
   * such as orphaned or soft-deleted categories are safely excluded, and
   * invalid queries (e.g., parent mismatch) return helpful structured error
   * responses.
   *
   * This endpoint may work in tandem with child creation or category assignment
   * endpoints, or with product catalog searches referencing category codes. It
   * is robust to partial matches and large data sets, returning paginated data
   * by default. Client applications should expect total count, current page,
   * and last page estimates for best UX.
   *
   * @param connection
   * @param body Advanced search and filter parameters for categories, including
   *   tree, parent, keyword, and pagination settings
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingCategory.IRequest,
  ): Promise<IPageIShoppingCategory.ISummary> {
    try {
      return await patchShoppingAdminCategories({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing category node in a category tree (shopping_categories
   * table).
   *
   * This endpoint allows platform administrators to update the properties of an
   * existing category node in a given category tree. The category is specified
   * by the tree code (identifying the taxonomy) and the category code (unique
   * within the tree).
   *
   * The underlying operation modifies the relevant row in the
   * shopping_categories table, allowing changes to fields such as
   * category_name, sort_order, or even parent assignment. All updates must
   * respect catalog tree rules (e.g., no cycle creation, name/code uniqueness,
   * depth limit). Integrity constraints are enforced and invalid updates are
   * rejected.
   *
   * Only admin users are authorized to perform this action. Attempts by other
   * actors are denied. The operation returns the complete updated category
   * details upon success.
   *
   * @param connection
   * @param categoryTreeCode Unique business identifier code for the target
   *   category tree (global scope)
   * @param categoryCode Unique business identifier code for the target category
   *   within the category tree (scoped to tree)
   * @param body Fields to update on the target category node.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryTreeCode/:categoryCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryTreeCode")
    categoryTreeCode: string,
    @TypedParam("categoryCode")
    categoryCode: string,
    @TypedBody()
    body: IShoppingCategory.IUpdate,
  ): Promise<IShoppingCategory> {
    try {
      return await putShoppingAdminCategoriesCategoryTreeCodeCategoryCode({
        admin,
        categoryTreeCode,
        categoryCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a category node from a specific category tree (shopping_categories
   * table).
   *
   * This API operation is designed to facilitate the hard deletion of a
   * category node from a specified category tree used for product
   * classification in the shopping mall platform. When invoked, it targets a
   * single category identified by its unique categoryCode within a named
   * categoryTreeCode, both passed as path parameters.
   *
   * Upon execution, the service locates the category entry in the
   * 'shopping_categories' table via a composite unique constraint on
   * (category_tree_id, category_code), ensuring context-sensitive uniqueness.
   * If the target category is a parent (i.e., has child nodes), business logic
   * must ensure no orphaning occurs; typically, reassignment or forced removal
   * of descendant categories and related assignments may be triggered, subject
   * to business policy and UI confirmation. Products directly assigned to this
   * category may be marked as uncategorized or require mandatory reassignment,
   * depending on platform configuration.
   *
   * Security and authorization controls limit this endpoint to administrative
   * actors. An appropriate permission check is performed to ensure only
   * authorized admins execute such catalog-structure changes. Business logic
   * further validates that the root category of any tree cannot be deleted
   * except through tree archival or by explicit override.
   *
   * Because categories are fundamental to browsing, search, and catalog
   * integrity, any delete operation will also update hierarchical relationships
   * of sibling and child nodes, maintain deterministic sort order for remaining
   * categories, and may trigger downstream catalog update events for cache
   * invalidation or UI refresh.
   *
   * @param connection
   * @param categoryTreeCode Unique business identifier code of the target
   *   category tree (global scope)
   * @param categoryCode Unique business identifier code of the target category
   *   within the category tree (scoped to category tree)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryTreeCode/:categoryCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryTreeCode")
    categoryTreeCode: string,
    @TypedParam("categoryCode")
    categoryCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminCategoriesCategoryTreeCodeCategoryCode({
        admin,
        categoryTreeCode,
        categoryCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
