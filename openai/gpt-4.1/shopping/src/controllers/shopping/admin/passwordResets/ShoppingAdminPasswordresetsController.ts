import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingAdminPasswordResets } from "../../../../providers/patchShoppingAdminPasswordResets";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingAdminPasswordResetsPasswordResetId } from "../../../../providers/getShoppingAdminPasswordResetsPasswordResetId";
import { putShoppingAdminPasswordResetsPasswordResetId } from "../../../../providers/putShoppingAdminPasswordResetsPasswordResetId";
import { deleteShoppingAdminPasswordResetsPasswordResetId } from "../../../../providers/deleteShoppingAdminPasswordResetsPasswordResetId";

import { IPageIShoppingPasswordReset } from "../../../../api/structures/IPageIShoppingPasswordReset";
import { IShoppingPasswordReset } from "../../../../api/structures/IShoppingPasswordReset";

@Controller("/shopping/admin/passwordResets")
export class ShoppingAdminPasswordresetsController {
  /**
   * Retrieve a paginated, searchable list of all password reset requests across
   * actors.
   *
   * Retrieve a filtered and paginated list of password reset requests in the
   * system. This operation enables administrators or security auditors to
   * review password reset histories, identify recent or expired requests, and
   * investigate suspicious activity.
   *
   * The operation provides search and filter options, such as searching by
   * email address, filtering by actor type (customer, seller, admin), and
   * restricting results to a time window or showing consumed vs. unconsumed
   * reset codes. Sorting and pagination are supported for efficient browsing of
   * large log datasets.
   *
   * This endpoint operates on the shopping_password_resets table, which logs
   * all fields necessary for compliance and audit tracking. Only authorized
   * admin, support, or security actors should be permitted access to this
   * operation due to the sensitivity of password reset data. Abuse, mass
   * harvesting, or unauthorized querying must be strictly access-controlled.
   *
   * Related API operations include individual password reset detail retrieval,
   * password reset creation, and status update APIs.
   *
   * @param connection
   * @param body Search, filter, and pagination options for password reset
   *   requests audit.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingPasswordReset.IRequest,
  ): Promise<IPageIShoppingPasswordReset.ISummary> {
    try {
      return await patchShoppingAdminPasswordResets({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a single password reset request by ID.
   *
   * Fetch detailed information for a specific password reset request identified
   * by its unique passwordResetId. This information includes the requesting
   * email, associated account/actor details (customer, seller, or admin), the
   * generated reset code (only via secure or restricted access), request
   * creation and expiration timestamps, and status information indicating
   * whether the reset was consumed or is still active.
   *
   * Administrative and support actors use this endpoint for investigating
   * support cases, compliance-related inquiries, or proactively managing
   * account recovery flows. Proper access controls are mandatory due to the
   * sensitive nature of the information; results may be filtered or masked
   * depending on the role and business policy.
   *
   * This operation reads from the shopping_password_resets table in the Prisma
   * schema, with strict audit and access control. No modification is performed
   * by this endpoint; it is strictly read-only for informational and
   * investigative purposes.
   *
   * @param connection
   * @param passwordResetId Unique identifier of the target password reset
   *   request (UUID format, global scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":passwordResetId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("passwordResetId")
    passwordResetId: string & tags.Format<"uuid">,
  ): Promise<IShoppingPasswordReset> {
    try {
      return await getShoppingAdminPasswordResetsPasswordResetId({
        admin,
        passwordResetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing password reset request by its unique identifier.
   *
   * This API operation updates a password reset request's expiration,
   * consumption, or audit information by its unique identifier from the
   * shopping_password_resets table. It is commonly used when the reset link's
   * validity needs to be extended, consumed, or administratively invalidated.
   * Strict validation is required, ensuring only authorized actors (the account
   * owner or platform security admin) may update the request. The request and
   * response strictly follow the schema of the shopping_password_resets model,
   * including fields such as expires_at, consumed_at, and updated_at. Attempts
   * to update a reset after it has expired or been consumed will result in a
   * business error. Security logging and audit trails are essential for every
   * invocation.
   *
   * @param connection
   * @param passwordResetId Unique identifier of the target password reset
   *   request
   * @param body Data for updating password reset request, such as new
   *   expiration or marking as consumed
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":passwordResetId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("passwordResetId")
    passwordResetId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingPasswordReset.IUpdate,
  ): Promise<IShoppingPasswordReset> {
    try {
      return await putShoppingAdminPasswordResetsPasswordResetId({
        admin,
        passwordResetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a password reset request by its unique identifier.
   *
   * This API operation permanently removes a password reset request from the
   * system. It is used to clean up expired, invalid, or completed password
   * reset entries to minimize security risk and database clutter. The deletion
   * is irreversible and will not retain soft-deleted or archival data, as the
   * underlying Prisma schema lacks a soft delete field for this entity. Only
   * administrators are authorized to perform this operation. Appropriate audit
   * logging must be implemented to track each deletion for compliance and
   * security review. Attempts to delete a reset request that does not exist
   * will result in a not found error response.
   *
   * @param connection
   * @param passwordResetId Unique identifier of the target password reset
   *   request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":passwordResetId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("passwordResetId")
    passwordResetId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminPasswordResetsPasswordResetId({
        admin,
        passwordResetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
