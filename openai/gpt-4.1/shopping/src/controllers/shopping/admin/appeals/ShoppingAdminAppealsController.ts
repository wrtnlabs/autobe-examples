import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingAdminAppeals } from "../../../../providers/patchShoppingAdminAppeals";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingAdminAppealsAppealId } from "../../../../providers/getShoppingAdminAppealsAppealId";
import { putShoppingAdminAppealsAppealId } from "../../../../providers/putShoppingAdminAppealsAppealId";

import { IPageIShoppingAppeal } from "../../../../api/structures/IPageIShoppingAppeal";
import { IShoppingAppeal } from "../../../../api/structures/IShoppingAppeal";

@Controller("/shopping/admin/appeals")
export class ShoppingAdminAppealsController {
  /**
   * Search and retrieve a paginated, filtered list of all appeals within the
   * platform (shopping_appeals table).
   *
   * Retrieve a paginated, filterable list of platform appeals from the
   * shopping_appeals table, supporting advanced search and sorting. This
   * operation is critical for surfacing all formal appeals (against
   * suspensions, account actions, policy violations, or compliance events) open
   * or closed within the shopping mall backend.
   *
   * Multiple actor types may file appeals—customers appealing account
   * suspensions or policy violations, sellers disputing platform administrative
   * actions, or admins managing oversight. The search capability enables
   * filtering by status, type, decision state, dates, and full-text search in
   * the reason or decision fields. This facilitates compliance, escalation
   * workflow, and timely resolution.
   *
   * All results are scoped by the requesting actor's visibility; for instance,
   * customers can see their own appeals, sellers those cases they initiated,
   * and admins global appeals (subject to role restrictions). The response
   * returns paginated summary information for each matching appeal, with option
   * to fetch detail via the GET /appeals/{appealId} operation. Error handling
   * ensures that malformed filters or unauthorized access attempts return
   * specific error codes and audit logs.
   *
   * @param connection
   * @param body Search and filter parameters for querying appeals (status,
   *   filer, dates, etc).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingAppeal.IRequest,
  ): Promise<IPageIShoppingAppeal.ISummary> {
    try {
      return await patchShoppingAdminAppeals({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve full detail for a single appeal by appealId (shopping_appeals
   * table).
   *
   * Fetch comprehensive details of a specific appeal record by its unique
   * identifier from the shopping_appeals Prisma model. The response includes
   * full fields: filing/decision dates, actors, appeal reason text, status
   * transitions, decisions rendered, linked policy/suspension if applicable,
   * and all audit or resolution notes.
   *
   * Access is strictly limited by actor authorization: a customer or seller may
   * view only their own appeals; admin roles may request any appeal record. The
   * operation is essential for compliance, regulatory audit, and dispute
   * mediation workflows where history and evidence must be presented in detail.
   * Error responses are provided for not-found, unauthorized, or
   * inactive/deleted appeals, with full audit logging of access attempts.
   *
   * Related operation PATCH /appeals provides search and batch listing
   * capabilities; use GET for singular record deep-dive. Any decision edits or
   * moderation are performed after explicit admin escalation, not via this
   * endpoint.
   *
   * @param connection
   * @param appealId Unique identifier of the target appeal record (UUID
   *   format).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":appealId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("appealId")
    appealId: string & tags.Format<"uuid">,
  ): Promise<IShoppingAppeal> {
    try {
      return await getShoppingAdminAppealsAppealId({
        admin,
        appealId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an appeal status, decision, or rationale by admin (Appeals table).
   *
   * Update the status, decision, or supporting rationale/notes for a specific
   * appeal record, uniquely identified by its appealId path parameter. Admin
   * users can use this endpoint to transition an appeal through its lifecycle,
   * such as setting status to 'approved', 'rejected', or other valid states.
   *
   * All field edits are subject to business validation: status and decision
   * fields must match allowed business values, updates are recorded for audit,
   * and rationale must be provided if required for the status/decision
   * transition.
   *
   * Permission is restricted to admin-level users; attempts by non-admin actors
   * are denied. Internally, the handler records the admin making the update for
   * full audit trail compliance. Expected behavior includes full replacement of
   * mutable fields per supplied payload and returning the updated entity
   * post-operation. Error handling covers not-found, forbidden, and
   * invalid-transition scenarios, following shopping_appeals schema
   * enforcement.
   *
   * @param connection
   * @param appealId Unique identifier of the target appeal (UUID format, global
   *   scope)
   * @param body Fields for updating the appeal status, decision, and rationale.
   *   The structure follows IShoppingAppeal.IUpdate, excluding the path
   *   parameter appealId.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":appealId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("appealId")
    appealId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingAppeal.IUpdate,
  ): Promise<IShoppingAppeal> {
    try {
      return await putShoppingAdminAppealsAppealId({
        admin,
        appealId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
