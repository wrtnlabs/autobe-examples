import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingAdminAdminSuspensions } from "../../../../providers/postShoppingAdminAdminSuspensions";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminAdminSuspensions } from "../../../../providers/patchShoppingAdminAdminSuspensions";
import { getShoppingAdminAdminSuspensionsAdminSuspensionId } from "../../../../providers/getShoppingAdminAdminSuspensionsAdminSuspensionId";
import { putShoppingAdminAdminSuspensionsAdminSuspensionId } from "../../../../providers/putShoppingAdminAdminSuspensionsAdminSuspensionId";
import { deleteShoppingAdminAdminSuspensionsAdminSuspensionId } from "../../../../providers/deleteShoppingAdminAdminSuspensionsAdminSuspensionId";

import { IShoppingAdminSuspension } from "../../../../api/structures/IShoppingAdminSuspension";
import { IPageIShoppingAdminSuspension } from "../../../../api/structures/IPageIShoppingAdminSuspension";

@Controller("/shopping/admin/adminSuspensions")
export class ShoppingAdminAdminsuspensionsController {
  /**
   * Create a new admin suspension record (shopping_admin_suspensions).
   *
   * Create a new admin suspension event for a specified actor (admin, seller,
   * or customer) on the platform. This operation is used by administrators to
   * impose a temporary or permanent suspension for reasons such as policy
   * violations, compliance issues, or business enforcement requirements.
   *
   * The operation enforces required validation on who may be suspended, the
   * type and duration of suspension, and ensures all necessary context and
   * reason codes are included for auditability. Business rules such as
   * preventing the suspension of oneself or the last remaining super admin are
   * enforced.
   *
   * Upon successful creation, the new suspension instance is returned for
   * immediate display and further processing. Comprehensive error handling is
   * applied: attempts to suspend non-existent users, duplicate suspensions, or
   * invalid data will generate clear business error responses. Compliance with
   * audit and legal evidence retention rules is strictly followed.
   *
   * @param connection
   * @param body Details for creating a new admin suspension, including actor
   *   references and reason codes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingAdminSuspension.ICreate,
  ): Promise<IShoppingAdminSuspension> {
    try {
      return await postShoppingAdminAdminSuspensions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated list of admin suspension records from the
   * platform.
   *
   * Retrieve a filtered, paginated, and sortable list of admin suspensions
   * imposed across the shopping mall platform. This operation targets the
   * shopping_admin_suspensions table and enables administrators to review
   * actions taken against admin, seller, or customer accounts for compliance,
   * audit, or security analysis.
   *
   * The API allows optional search parameters such as suspension_type, status
   * (active, expired, revoked, pending_appeal), start_at/end_at range, and
   * references to either the enacting admin or the affected actor. Results are
   * paginated, with configurable page size and sort options by start date, end
   * date, or actor. Only actors with admin privileges may access this
   * operation; the endpoint is not public or available for self-service by
   * affected users or sellers.
   *
   * This endpoint supports operational and compliance requirements by providing
   * accountability and traceability for every suspension imposed on the
   * platform. It enables advanced filtering and auditing for disputed or
   * escalated actions and integrates with the overall admin operations and
   * audit logging features described in accompanying requirements
   * documentation.
   *
   * Errors are returned for invalid filters, insufficient admin permissions, or
   * attempts to access records outside the admin's visibility scope.
   *
   * @param connection
   * @param body Search criteria, pagination, and sorting parameters for admin
   *   suspension filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingAdminSuspension.IRequest,
  ): Promise<IPageIShoppingAdminSuspension.ISummary> {
    try {
      return await patchShoppingAdminAdminSuspensions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get details for a specific admin suspension record by its unique
   * identifier.
   *
   * Fetch the comprehensive details of a single admin suspension entry by its
   * unique identifier from the shopping_admin_suspensions table. The returned
   * record contains all business and audit fields: which admin created the
   * suspension, the affected account (admin, seller, or customer), suspension
   * type (temporary, permanent, pending_appeal), status, full reason for the
   * action, start and end times, and the suspension's current state.
   *
   * This operation is reserved exclusively for platform administrators,
   * providing an auditable, authoritative source for compliance reviews,
   * dispute resolution, and compliance reporting. Permissions are enforced such
   * that only admin users may access this endpoint, and all access is logged as
   * part of the platform's auditing mechanisms.
   *
   * Typical use cases include investigating appeals, verifying suspension
   * duration, and reviewing the history of compliance actions taken against any
   * platform actor. If the requested suspensionId is not found, or access is
   * denied, appropriate errors are returned.
   *
   * @param connection
   * @param adminSuspensionId Unique identifier of the target admin suspension
   *   record (UUID format)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminSuspensionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminSuspensionId")
    adminSuspensionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingAdminSuspension> {
    try {
      return await getShoppingAdminAdminSuspensionsAdminSuspensionId({
        admin,
        adminSuspensionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing admin suspension record (shopping_admin_suspensions).
   *
   * Update details of an existing admin suspension in the system. Permitted
   * updates include changing suspension status (e.g., from active to revoked),
   * modifying reason codes or context, or updating the end date for a temporary
   * suspension. All changes are subjected to business validation logic to
   * ensure data integrity.
   *
   * The adminSuspensionId parameter specifies the target suspension record
   * using the unique identifier from the shopping_admin_suspensions table. The
   * operation enforces that only authorized admin actors can update suspension
   * records, and that no illegal updates (such as unlocking permanent
   * suspensions without business justification) may be performed.
   *
   * Full error handling is provided for non-existent records, unauthorized
   * attempts, or invalid requested changes. On success, the complete updated
   * admin suspension entity is returned.
   *
   * @param connection
   * @param adminSuspensionId Unique identifier of the admin suspension to
   *   update
   * @param body Update information for the admin suspension, such as status,
   *   reason, or end date.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminSuspensionId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminSuspensionId")
    adminSuspensionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingAdminSuspension.IUpdate,
  ): Promise<IShoppingAdminSuspension> {
    try {
      return await putShoppingAdminAdminSuspensionsAdminSuspensionId({
        admin,
        adminSuspensionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a specific admin suspension record
   * (shopping_admin_suspensions table).
   *
   * This endpoint allows an authorized system administrator to permanently
   * delete an admin suspension record by its unique identifier. This is a hard
   * delete operation because the shopping_admin_suspensions table does not
   * specify a soft-delete field, which means the record is fully expunged from
   * the database and cannot be restored once removed.
   *
   * Security is critical: only platform admins with the correct privileges may
   * invoke this operation, ensuring that sensitive governance records are
   * tightly controlled. Any attempt to delete a non-existent admin suspension
   * will return a suitable error response, while unauthorized access will be
   * denied. The operation is commonly performed as part of internal audit
   * compliance or when cleaning up obsolete suspension states.
   *
   * Refer to business rules on audit logging—all such deletions should be noted
   * in the audit trail with actor, timestamp, and affected admin for regulatory
   * compliance. Errors in deletion due to integrity or FK constraints will be
   * returned as specific error codes for resolution.
   *
   * Detailed parameter documentation is derived from the Prisma model, using
   * the primary id field as the unique key.
   *
   * @param connection
   * @param adminSuspensionId Unique identifier of the target admin suspension
   *   record (shopping_admin_suspensions.id).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminSuspensionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminSuspensionId")
    adminSuspensionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminAdminSuspensionsAdminSuspensionId({
        admin,
        adminSuspensionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
