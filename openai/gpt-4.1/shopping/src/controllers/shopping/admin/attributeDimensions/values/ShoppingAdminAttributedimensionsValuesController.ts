import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { postShoppingAdminAttributeDimensionsDimensionCodeValues } from "../../../../../providers/postShoppingAdminAttributeDimensionsDimensionCodeValues";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminAttributeDimensionsDimensionCodeValues } from "../../../../../providers/patchShoppingAdminAttributeDimensionsDimensionCodeValues";
import { putShoppingAdminAttributeDimensionsDimensionCodeValuesValueCode } from "../../../../../providers/putShoppingAdminAttributeDimensionsDimensionCodeValuesValueCode";
import { deleteShoppingAdminAttributeDimensionsDimensionCodeValuesValueCode } from "../../../../../providers/deleteShoppingAdminAttributeDimensionsDimensionCodeValuesValueCode";

import { IShoppingAttributeValue } from "../../../../../api/structures/IShoppingAttributeValue";
import { IPageIShoppingAttributeValue } from "../../../../../api/structures/IPageIShoppingAttributeValue";

@Controller("/shopping/admin/attributeDimensions/:dimensionCode/values")
export class ShoppingAdminAttributedimensionsValuesController {
  /**
   * Add a new attribute value under a given attribute dimension using unique
   * codes and business validation.
   *
   * Create a new attribute value under an existing attribute dimension. The
   * attribute dimension is located via its globally unique dimension code. The
   * request body must provide all necessary fields for the attribute value: a
   * value code (unique within the dimension), display value, display order
   * (optional), and description. This ensures that only valid, non-duplicated
   * attribute values can be created for a variant dimension, compliant with
   * both catalog logic and data integrity enforced by the Prisma schema.
   *
   * This operation is central for catalog administrators or seller management
   * flows where new color, size, or custom attribute options may need to be
   * defined as part of product onboarding. The API enforces permissions such
   * that only admin users (or privileged catalog/seller users) may invoke it,
   * supporting business control over available attribute filters and variant
   * choices. On success, the full created attribute value entity is returned
   * for UI population and downstream use.
   *
   * @param connection
   * @param dimensionCode Unique business code for the target attribute
   *   dimension (global scope).
   * @param body Payload to create a new attribute value for the specified
   *   dimension. Must provide valueCode, displayValue, displayOrder (optional),
   *   and description (optional).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("dimensionCode")
    dimensionCode: string,
    @TypedBody()
    body: IShoppingAttributeValue.ICreate,
  ): Promise<IShoppingAttributeValue> {
    try {
      return await postShoppingAdminAttributeDimensionsDimensionCodeValues({
        admin,
        dimensionCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve all attribute values for a given attribute dimension
   * from shopping_attribute_values.
   *
   * This API endpoint allows catalog administrators or authorized sellers to
   * query all attribute values under a single attribute dimension, as indicated
   * by the dimensionCode path parameter. Attribute values represent selectable
   * options in product or SKU variants, such as color names, size labels, or
   * other feature values.
   *
   * The operation supports flexible search and filtering, including sorting by
   * display order, searching by value code, and paginating results for
   * efficient frontend display. It leverages the relationships defined in
   * shopping_attribute_dimensions and shopping_attribute_values, ensuring that
   * only options for the specified dimension are returned.
   *
   * The response includes detailed information for each attribute value, such
   * as its value_code, display_value, and display_order. Security and access
   * restrictions require that only authorized users managing the catalog can
   * access this endpoint. This operation is essential for product onboarding,
   * catalog cleanup, and management of variant options.
   *
   * @param connection
   * @param dimensionCode Unique business code of the attribute dimension whose
   *   values are being retrieved (global scope).
   * @param body Filtering, pagination, or search parameters for querying
   *   attribute values of a dimension.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("dimensionCode")
    dimensionCode: string,
    @TypedBody()
    body: IShoppingAttributeValue.IRequest,
  ): Promise<IPageIShoppingAttributeValue> {
    try {
      return await patchShoppingAdminAttributeDimensionsDimensionCodeValues({
        admin,
        dimensionCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an attribute value for a given attribute dimension.
   *
   * Update the details of an attribute value (such as display label, sort
   * order, or description) within a specified attribute dimension. The system
   * enforces uniqueness of value codes within each dimension and validates that
   * the attribute dimension and value currently exist. This operation is
   * essential for admin-driven management of structured variant options exposed
   * in the product SKU matrix.
   *
   * Security: Only administrators are authorized to perform updates to
   * attribute values. Requesting actor must be authenticated as an admin and
   * have modification permissions for product schema settings. All changes are
   * logged for audit and traceability.
   *
   * This endpoint strictly requires both the attribute dimension code (global
   * scope) and the value code (scoped to the attribute dimension) in the path
   * parameters. It leverages the Prisma schema models:
   * shopping_attribute_dimensions and shopping_attribute_values, joined by the
   * dimension and value codes. Updating an attribute value propagates changes
   * across all products/SKUs using that value.
   *
   * @param connection
   * @param dimensionCode Unique business code of the attribute dimension
   *   (global scope)
   * @param valueCode Unique business code of the attribute value within the
   *   attribute dimension (scoped to dimension)
   * @param body Update details for the attribute value, such as display value,
   *   sort order, and description.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":valueCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("dimensionCode")
    dimensionCode: string,
    @TypedParam("valueCode")
    valueCode: string,
    @TypedBody()
    body: IShoppingAttributeValue.IUpdate,
  ): Promise<IShoppingAttributeValue> {
    try {
      return await putShoppingAdminAttributeDimensionsDimensionCodeValuesValueCode(
        {
          admin,
          dimensionCode,
          valueCode,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an attribute value from a given attribute dimension.
   *
   * Permanently remove an attribute value from the specified attribute
   * dimension. The operation validates that both the dimension and value codes
   * exist and are currently associated in the schema. Successful execution will
   * remove the value option across all linked products and prevent its further
   * use in SKU or product variant composition.
   *
   * Only admin users can execute this operation, which is logged for audit
   * purposes. The system ensures referential cleanup and rejects deletion if
   * the value is in use in an active SKU or product, returning a constraint
   * violation error if so. Operation leverages shopping_attribute_dimensions
   * and shopping_attribute_values models.
   *
   * Path parameters must include both attribute dimension code (global scope)
   * and value code (scoped to that dimension) to ensure correct and unambiguous
   * identification of the entity. The deletion is a hard delete, as no
   * soft-delete column is present for this table in the schema. All references
   * are checked for integrity before removal.
   *
   * @param connection
   * @param dimensionCode Unique business code of the attribute dimension
   *   (global scope)
   * @param valueCode Unique business code of the attribute value within the
   *   attribute dimension (scoped to dimension)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":valueCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("dimensionCode")
    dimensionCode: string,
    @TypedParam("valueCode")
    valueCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminAttributeDimensionsDimensionCodeValuesValueCode(
        {
          admin,
          dimensionCode,
          valueCode,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
