import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingAdminAttributeDimensions } from "../../../../providers/postShoppingAdminAttributeDimensions";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminAttributeDimensions } from "../../../../providers/patchShoppingAdminAttributeDimensions";
import { getShoppingAdminAttributeDimensionsDimensionCode } from "../../../../providers/getShoppingAdminAttributeDimensionsDimensionCode";
import { putShoppingAdminAttributeDimensionsDimensionCode } from "../../../../providers/putShoppingAdminAttributeDimensionsDimensionCode";
import { deleteShoppingAdminAttributeDimensionsDimensionCode } from "../../../../providers/deleteShoppingAdminAttributeDimensionsDimensionCode";

import { IShoppingAttributeDimension } from "../../../../api/structures/IShoppingAttributeDimension";
import { IPageIShoppingAttributeDimension } from "../../../../api/structures/IPageIShoppingAttributeDimension";

@Controller("/shopping/admin/attributeDimensions")
export class ShoppingAdminAttributedimensionsController {
  /**
   * Create a new shopping attribute dimension.
   *
   * Create a new product attribute dimension record to define variant types in
   * the platform catalog. This enables sellers and administrators to add new
   * selectable variant categories, such as Color or Size, which may be
   * associated with multiple products for flexible SKU management.
   *
   * Operations using this endpoint require all mandatory fields—dimension_code
   * (unique per dimension), name (display name), and description
   * (purpose/business context). After creation, attribute dimensions are
   * available for assignment to attribute values and are visible in
   * variant-related API responses.
   *
   * Security: only admins or authorized sellers can access this operation. The
   * response will include the complete record of the newly created attribute
   * dimension as per the Prisma shopping_attribute_dimensions schema.
   *
   * Validation requires that the dimension_code is globally unique, the name is
   * provided and meaningful for the business context, and description
   * accurately captures its intended usage. Related endpoints include attribute
   * value creation and assignment APIs.
   *
   * @param connection
   * @param body Payload to create a new attribute dimension, including
   *   dimension_code, name, and description.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingAttributeDimension.ICreate,
  ): Promise<IShoppingAttributeDimension> {
    try {
      return await postShoppingAdminAttributeDimensions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated list of attribute dimensions for catalog
   * product variant setup.
   *
   * This API retrieves a filtered, paginated list of attribute dimensions (such
   * as color, size, or material) used in product catalog and SKU variant
   * structures. It enables advanced search and filter capabilities, including
   * partial name/code matching, ordering, and custom attribute filtering. The
   * response includes the list of matching attribute dimensions along with
   * paging context and summary information.
   *
   * The underlying Prisma schema for shopping_attribute_dimensions defines
   * fields such as dimension_code (unique code), name, description, and
   * creation timestamp. The endpoint supports search against any of these
   * fields using industry-standard search syntax. Attribute dimensions are core
   * to onboarding and updating product variants, and response data is suitable
   * for populating setup flows or filter UI components.
   *
   * Security and permissions: Only authenticated users with catalog read access
   * (e.g., sellers, admins) should be able to read attribute dimensions.
   * Public, unauthenticated listing is not allowed due to business
   * configuration sensitivity. Results are properly paginated and do not reveal
   * inactive or deleted dimensions.
   *
   * Pagination and sort order defaults are applied if not specified. Errors are
   * returned as standard API errors if invalid filter criteria are included or
   * database issues occur.
   *
   * @param connection
   * @param body Search and filter criteria for attribute dimension pagination
   *   and retrieval.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingAttributeDimension.IRequest,
  ): Promise<IPageIShoppingAttributeDimension.ISummary> {
    try {
      return await patchShoppingAdminAttributeDimensions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the details of a specific attribute dimension for catalog SKU
   * management by dimension code.
   *
   * This API returns detailed information about a single attribute dimension
   * (for example, "Color" or "Size") used for catalog product variants. Lookup
   * is performed by the globally unique dimension_code field, allowing
   * unambiguous resolution of the target attribute dimension for setup flows
   * and administrative management.
   *
   * Per the Prisma schema, attribute dimensions include a unique business code
   * (dimension_code), display name, description, and creation timestamp. This
   * operation ensures sellers and admins can retrieve the exact details
   * required to set up or audit product variant configuration. The endpoint
   * does not expose dimensions in a deleted or inactive state.
   *
   * Security: Only authenticated actors with catalog setup permissions (sellers
   * or admins) can call this endpoint. Results are filtered for business
   * context and do not include inactive records. Attempting to retrieve a
   * missing or deleted dimension triggers a standard not-found error.
   *
   * @param connection
   * @param dimensionCode Unique business code of the attribute dimension to
   *   retrieve (global scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":dimensionCode")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("dimensionCode")
    dimensionCode: string,
  ): Promise<IShoppingAttributeDimension> {
    try {
      return await getShoppingAdminAttributeDimensionsDimensionCode({
        admin,
        dimensionCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a shopping attribute dimension by its unique code.
   *
   * Update the display name and description of an existing attribute dimension,
   * identified by its unique dimension_code (global scope). Attribute
   * dimensions control the variant types available for products and
   * SKUs—changing the name or context may affect catalog presentation and
   * selection options platform-wide.
   *
   * The dimensionCode path parameter must refer to an existing dimension
   * (case-sensitive match). Only name and description fields may be updated;
   * dimension_code itself remains immutable for data integrity. This operation
   * is available to administrators and authorized sellers, enforcing business
   * rules on meaningful changes and audit requirements.
   *
   * Validation checks include ensuring the dimension exists, dimensionCode is
   * globally unique, and updated fields (name and description) conform to
   * business documentation standards. Failure to meet these requirements
   * results in appropriate error responses. Related endpoints include attribute
   * dimension creation and value management APIs.
   *
   * @param connection
   * @param dimensionCode Unique business identifier code of the target
   *   attribute dimension (global scope)
   * @param body Payload specifying updated name and description for the target
   *   attribute dimension. The dimension_code cannot be changed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":dimensionCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("dimensionCode")
    dimensionCode: string,
    @TypedBody()
    body: IShoppingAttributeDimension.IUpdate,
  ): Promise<IShoppingAttributeDimension> {
    try {
      return await putShoppingAdminAttributeDimensionsDimensionCode({
        admin,
        dimensionCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an attribute dimension by its business code (admin only, destructive
   * catalog operation) from shopping_attribute_dimensions.
   *
   * This API endpoint allows administrators to permanently delete a product
   * attribute dimension from the system, identified by its unique
   * dimensionCode. Attribute dimensions are used to define variant axes like
   * Color, Size, or Material, and are referenced by SKUs and products across
   * the catalog.
   *
   * Upon invocation, the system checks for any dependent SKUs or products that
   * utilize this dimension. If dependencies exist, the operation will fail with
   * a constraint violation error, as deleting a dimension in use would cause
   * catalog data integrity issues. If the dimension is not assigned to any
   * current SKUs or products, it is safely deleted from
   * shopping_attribute_dimensions. This is a hard delete, and all directly
   * related attribute values should be cleaned up as well.
   *
   * Security restrictions apply: only users with admin privileges may perform
   * this operation. All delete actions are logged in the system audit trail for
   * compliance purposes. The operation should be used infrequently and only
   * with a clear business justification, as it may impact SKU variant
   * definitions and product filtering across the catalog.
   *
   * @param connection
   * @param dimensionCode Unique business code of the attribute dimension to be
   *   deleted (global scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":dimensionCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("dimensionCode")
    dimensionCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminAttributeDimensionsDimensionCode({
        admin,
        dimensionCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
