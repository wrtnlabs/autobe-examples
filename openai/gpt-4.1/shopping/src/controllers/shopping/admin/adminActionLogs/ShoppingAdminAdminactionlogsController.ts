import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingAdminAdminActionLogs } from "../../../../providers/patchShoppingAdminAdminActionLogs";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingAdminAdminActionLogsAdminActionLogId } from "../../../../providers/getShoppingAdminAdminActionLogsAdminActionLogId";

import { IPageIShoppingAdminActionLog } from "../../../../api/structures/IPageIShoppingAdminActionLog";
import { IShoppingAdminActionLog } from "../../../../api/structures/IShoppingAdminActionLog";

@Controller("/shopping/admin/adminActionLogs")
export class ShoppingAdminAdminactionlogsController {
  /**
   * Search and retrieve a paginated, filtered list of admin action log entries
   * for auditing.
   *
   * Fetch a paginated list of admin action log entries from the
   * shopping_admin_action_logs table, supporting rich search criteria for
   * action type, actor, entity, time range, and business reason. This allows
   * system or compliance users to monitor, review, and audit platform-critical
   * operations for security, privacy, or investigation workflows.
   *
   * Each log record includes action author, affected entity info, event type,
   * description, and timestamps. Advanced filtering enables precise
   * investigation when compliance or operational anomalies are detected.
   * Sorting options are available on action time, admin, or entity for targeted
   * query workflows.
   *
   * Proper security controls are required, as only authorized admin users
   * should access the full log dataset due to the sensitive nature of recorded
   * operations. Performance best practices apply for large-scale log retrieval,
   * supporting paged loading and index-optimized queries. This endpoint is
   * essential for satisfying regulatory audit requirements and detecting
   * abnormal system activity.
   *
   * @param connection
   * @param body Admin action log filter/search parameters supporting action
   *   type, actor, entity, time range, and paging.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingAdminActionLog.IRequest,
  ): Promise<IPageIShoppingAdminActionLog.ISummary> {
    try {
      return await patchShoppingAdminAdminActionLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get detailed information for a specific admin action log by ID.
   *
   * Fetch a single admin action log record from shopping_admin_action_logs
   * using its unique identifier as a path parameter. This gives full audit
   * detail, including the admin who performed the action, the affected entity
   * (if any), action type, reason, and business context relevant to compliance
   * or operational investigations.
   *
   * This endpoint is used in compliance, security, and platform audit trails
   * when investigating specific events, privilege escalations, or system policy
   * changes. Only administrative users with sufficient permissions can access
   * individual actionable log records, as they may contain sensitive platform
   * data or user PII.
   *
   * Retrieval is ID-based (UUID format) with full traceability of event
   * rationale and operational metadata, ensuring support for system
   * auditability, incident review, and regulatory compliance.
   *
   * @param connection
   * @param adminActionLogId Unique identifier of the target admin action log
   *   entry for audit retrieval.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminActionLogId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminActionLogId")
    adminActionLogId: string & tags.Format<"uuid">,
  ): Promise<IShoppingAdminActionLog> {
    try {
      return await getShoppingAdminAdminActionLogsAdminActionLogId({
        admin,
        adminActionLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
