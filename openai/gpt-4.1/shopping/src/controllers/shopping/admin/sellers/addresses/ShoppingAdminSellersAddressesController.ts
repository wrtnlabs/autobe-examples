import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingAdminSellersSellerIdAddresses } from "../../../../../providers/postShoppingAdminSellersSellerIdAddresses";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminSellersSellerIdAddresses } from "../../../../../providers/patchShoppingAdminSellersSellerIdAddresses";
import { getShoppingAdminSellersSellerIdAddressesAddressId } from "../../../../../providers/getShoppingAdminSellersSellerIdAddressesAddressId";

import { IShoppingSellerAddress } from "../../../../../api/structures/IShoppingSellerAddress";
import { IPageIShoppingSellerAddress } from "../../../../../api/structures/IPageIShoppingSellerAddress";

@Controller("/shopping/admin/sellers/:sellerId/addresses")
export class ShoppingAdminSellersAddressesController {
  /**
   * Create a new seller address under a specific seller
   * (shopping_seller_addresses).
   *
   * This API endpoint enables the creation of a new address record for a
   * seller. Sellers may register multiple business, shipping, origin, or return
   * addresses, each of which must be uniquely identified. The schema requires
   * address_line1, city, state, postal_code, country, recipient_name, phone,
   * and attribute flags such as is_primary (main address) and is_return_address
   * (return/goods back address). These flags allow distinguishing multiple
   * address usages under one seller profile.
   *
   * Only authenticated sellers (owners) are authorized to create addresses
   * under their own account, and an admin may create addresses for a seller
   * only in exceptional cases for operational reasons. The endpoint ensures
   * that sellers cannot add addresses to other sellers' accounts, and business
   * logic will enforce the uniqueness or constraints for primary and return
   * addresses. Validation is performed for address format, duplicate entries,
   * and field requirements. Addresses are essential for order fulfillment,
   * shipping, and seller profile compliance.
   *
   * On success, a full address record is returned as confirmation. Soft
   * deletion will not affect address creation. Error scenarios include attempts
   * to create an address for a different sellerId or if required fields are
   * missing, both resulting in detailed validation or authorization errors.
   * This operation is a core part of seller profile and logistics management
   * workflows.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller who will own the new
   *   address (global scope)
   * @param body Full information required to create a new seller address
   *   (business, primary, return, or warehouse).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingSellerAddress.ICreate,
  ): Promise<IShoppingSellerAddress> {
    try {
      return await postShoppingAdminSellersSellerIdAddresses({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * List all logistics and business address records for a seller
   * (shopping_seller_addresses) with advanced filtering and pagination.
   *
   * This API endpoint returns a paginated, filterable list of all address
   * records associated with a specific seller, enabling users to retrieve key
   * logistics and business addresses for order fulfillment, returns, and
   * compliance. The data is sourced directly from the shopping_seller_addresses
   * table, which includes all address information such as address lines, city,
   * state, country, phone, and status flags (is_primary, is_return_address).
   *
   * Security is enforced through role-aware access controls: only the owning
   * seller or platform administrators can retrieve this information. The
   * operation provides advanced query options for filtering by address type
   * (primary, return), sorting by update or creation time, and pagination for
   * ease of use. Sensitive fields are not returned unless explicitly requested
   * by an authorized admin role.
   *
   * Validation ensures only permitted actors may access a seller's addresses,
   * and any attempt to access addresses for unauthorized sellers will be
   * rejected with a detailed error code. Related endpoints may include address
   * creation, update, or deletion operations, and these should be used in
   * concert to maintain a complete and accurate seller address book. Error and
   * edge cases are comprehensively detailed in API error messages.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller (UUID, required to
   *   retrieve their addresses).
   * @param body Filtering, sorting, and pagination criteria for listing seller
   *   address records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingSellerAddress.IRequest,
  ): Promise<IPageIShoppingSellerAddress> {
    try {
      return await patchShoppingAdminSellersSellerIdAddresses({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific seller address by seller and address ID
   * (shopping_seller_addresses).
   *
   * This API endpoint provides the means to retrieve the full details of a
   * specific seller address, such as return, shipping, or primary address,
   * stored on the shopping_mall platform. The address information includes
   * fields such as address_line1, address_line2, city, state, postal_code,
   * country, phone, recipient_name, and flags distinguishing between primary
   * and return addresses. The operation requires both the sellerId and
   * addressId. This ensures that the address is retrieved in the context of
   * ownership and prevents unauthorized access to other sellers' address
   * records.
   *
   * Security and permissions: Only authenticated sellers (owners of the
   * address) and platform admins are authorized to access this endpoint. The
   * API will enforce that the sellerId in the path matches the authenticated
   * user's ID for sellers, which prevents cross-seller data leaks. Admins may
   * use this endpoint for compliance or fraud investigation purposes.
   *
   * In the event that the specified address does not exist or does not belong
   * to the specified seller, the endpoint will return an error indicating
   * 'address not found' or 'unauthorized', according to business logic. Address
   * records marked as soft-deleted (deleted_at not null) will not be returned
   * unless explicitly permitted by admin logic. This operation corresponds to
   * the shopping_seller_addresses table and is relevant for address management
   * workflows, order fulfillment configuration, and seller profile editing.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account (global
   *   scope)
   * @param addressId Unique identifier of the target seller address within the
   *   seller (scoped to seller)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":addressId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IShoppingSellerAddress> {
    try {
      return await getShoppingAdminSellersSellerIdAddressesAddressId({
        admin,
        sellerId,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
