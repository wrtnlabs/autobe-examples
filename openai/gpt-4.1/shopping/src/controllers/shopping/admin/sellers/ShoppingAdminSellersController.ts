import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingAdminSellers } from "../../../../providers/patchShoppingAdminSellers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingAdminSellersSellerId } from "../../../../providers/getShoppingAdminSellersSellerId";
import { putShoppingAdminSellersSellerId } from "../../../../providers/putShoppingAdminSellersSellerId";
import { deleteShoppingAdminSellersSellerId } from "../../../../providers/deleteShoppingAdminSellersSellerId";

import { IPageIShoppingSeller } from "../../../../api/structures/IPageIShoppingSeller";
import { IShoppingSeller } from "../../../../api/structures/IShoppingSeller";

@Controller("/shopping/admin/sellers")
export class ShoppingAdminSellersController {
  /**
   * Search and list registered sellers for administrative review
   * (shopping_sellers table).
   *
   * Retrieve a paginated, searchable, and filterable list of all registered
   * sellers on the platform. The endpoint supports filtering by status (e.g.,
   * pending, active, suspended, rejected), search by business/shop name, email,
   * and contact phone, and date ranges for seller onboarding or updates.
   * Designed for admin actors to perform seller vetting, compliance checks, and
   * platform activity monitoring.
   *
   * The operation directly maps to the shopping_sellers table, ensuring
   * coverage of all current and historical seller records, as well as
   * supporting bulk actions such as export or review. Response data may be used
   * for business analytics, seller account approvals, or regulatory review.
   * Results may be sorted by onboarding date, shop name, or account status for
   * operational convenience.
   *
   * Authorization is restricted to admin actors, and sensitive seller
   * information (contact details, status, KYC data) is exposed only to those
   * with explicit administrative privileges. The endpoint complements seller
   * detail retrieval, status update, and suspension/ban APIs.
   *
   * @param connection
   * @param body Search, filter, and pagination parameters for querying platform
   *   sellers
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingSeller.IRequest,
  ): Promise<IPageIShoppingSeller.ISummary> {
    try {
      return await patchShoppingAdminSellers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific seller account
   * (shopping_sellers table) by sellerId.
   *
   * Retrieve all available profile information, contact details, and status
   * fields for a single seller actor. This endpoint provides admins and
   * authorized actors with full visibility into seller account data for
   * business administration, compliance oversight, or customer support
   * purposes.
   *
   * Security for this endpoint must ensure only admins or the owner seller
   * themselves may access the target seller data: access by account owner is
   * permitted for viewing their own information; access by admin roles supports
   * platform moderation, policy enforcement, or business compliance reviews.
   *
   * The operation directly maps to the shopping_sellers entity in the database
   * schema and incorporates all non-sensitive account properties, leveraging
   * associated profile and business data for completeness. In scenarios with
   * audit, suspension, or flag status, extra caution is advised when displaying
   * or exposing sensitive values.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account in the
   *   shopping_sellers table. This is a UUID value and refers directly to the
   *   seller's primary key.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingSeller> {
    try {
      return await getShoppingAdminSellersSellerId({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update seller account profile or status in shopping_sellers by sellerId.
   *
   * Update the editable fields of a seller account, enabling the seller to
   * correct or improve their profile, or enabling admins to update status,
   * moderation, or compliance action as appropriate. Only fields present in the
   * IShoppingSeller.IUpdate request DTO are allowed to be modified.
   *
   * Authorization restrictions ensure that only the owner seller or an admin
   * can execute profile/account updates. Admin actions must be auditable,
   * trigger appropriate notification/workflow, and be compliant with business
   * policy. This endpoint validates payload against business rules, enforces
   * non-editability of restricted fields (such as immutable identifiers), and
   * applies updates atomically.
   *
   * The endpoint references the shopping_sellers table, and all field-level
   * update constraints, formats, and business logic are governed directly by
   * the schema and platform requirements. Error handling ensures any violations
   * (such as attempting to update a suspended account or modifying immutable
   * fields) are communicated with actionable detail.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account in the
   *   shopping_sellers table. This is a UUID value and refers directly to the
   *   seller's primary key.
   * @param body Payload specifying updatable profile fields for the seller,
   *   mapping to IShoppingSeller.IUpdate. Contains only fields allowed by
   *   business logic and schema for account update.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sellerId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingSeller.IUpdate,
  ): Promise<IShoppingSeller> {
    try {
      return await putShoppingAdminSellersSellerId({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a seller account from shopping_sellers table.
   *
   * This API permanently deletes a seller account, removing access for the
   * specified seller and rendering all their data inactive on the platform. The
   * operation targets the shopping_sellers table using the seller's UUID
   * identifier. All business data, including product listings, order
   * fulfillment records, and legal/business registration, are handled according
   * to regulatory and audit guidelines. The deletion is irreversible and should
   * only be used by administrators with appropriate privileges.
   *
   * The endpoint enforces strict permission checks: only admin-role users may
   * execute this operation. It also validates that the seller account is not
   * currently active in ongoing fulfillment or dispute workflows. Attempting to
   * delete a seller who is participating in unresolved operational processes
   * will result in a business error.
   *
   * Upon successful execution, the operation marks the seller as deleted
   * (populating the 'deleted_at' field), ensures no new logins can occur for
   * this account, and triggers system audit logs for compliance. Associated
   * data such as products or orders remain retained for historical integrity
   * but no longer reference an active seller in business logic.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sellerId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminSellersSellerId({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
