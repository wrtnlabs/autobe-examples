import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingAdminSellersSellerIdSessions } from "../../../../../providers/patchShoppingAdminSellersSellerIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IPageIShoppingSellerSession } from "../../../../../api/structures/IPageIShoppingSellerSession";
import { IShoppingSellerSession } from "../../../../../api/structures/IShoppingSellerSession";

@Controller("/shopping/admin/sellers/:sellerId/sessions")
export class ShoppingAdminSellersSessionsController {
  /**
   * List seller's authentication sessions for account security and audit
   * (shopping_seller_sessions).
   *
   * Retrieve a paginated and filterable list of all authentication sessions for
   * a specific seller. This operation provides visibility into each login
   * attempt, session IP address, creation timestamp, expiration (if any), and
   * context about the device or connection used. The data is essential for both
   * sellers and administrators to monitor account access, detect potentially
   * unauthorized activity, and perform regular security audits.
   *
   * The sellerId parameter specifies the seller whose sessions are being
   * queried. The operation leverages the shopping_seller_sessions table as
   * defined in the Prisma schema, incorporating all its columns, such as
   * session ID, creation time, expiration, IP address, and href/referrer for
   * the session. Additional business logic should restrict access so that only
   * the session owner (the seller) or privileged admin actors can retrieve
   * session details. Session tokens and authentication security are managed
   * separately and not altered by this endpoint.
   *
   * Common usage scenarios include account security review, vendor dashboard
   * session lists, and compliance-driven reports for past authentication
   * events. Error handling must ensure that attempts to access sessions for
   * another seller (without appropriate permissions) are denied for data
   * privacy and security compliance. Only session metadata is returned; actual
   * authentication tokens are not exposed.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller
   * @param body Session filtering, pagination, and search criteria for seller's
   *   session history
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingSellerSession.IRequest,
  ): Promise<IPageIShoppingSellerSession> {
    try {
      return await patchShoppingAdminSellersSellerIdSessions({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
