import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingAdminBusinessConstraints } from "../../../../providers/postShoppingAdminBusinessConstraints";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminBusinessConstraints } from "../../../../providers/patchShoppingAdminBusinessConstraints";
import { getShoppingAdminBusinessConstraintsConstraintName } from "../../../../providers/getShoppingAdminBusinessConstraintsConstraintName";
import { putShoppingAdminBusinessConstraintsConstraintName } from "../../../../providers/putShoppingAdminBusinessConstraintsConstraintName";
import { deleteShoppingAdminBusinessConstraintsConstraintName } from "../../../../providers/deleteShoppingAdminBusinessConstraintsConstraintName";

import { IShoppingBusinessConstraint } from "../../../../api/structures/IShoppingBusinessConstraint";
import { IPageIShoppingBusinessConstraint } from "../../../../api/structures/IPageIShoppingBusinessConstraint";

@Controller("/shopping/admin/businessConstraints")
export class ShoppingAdminBusinessconstraintsController {
  /**
   * Create a new business constraint (shopping_business_constraints).
   *
   * This API creates a new business constraint to be enforced across the
   * shopping platform.
   *
   * The operation is essential for formalizing platform rules regarding
   * operational or quantitative limits (such as maximum items per cart,
   * transaction/amount ceilings, and domain-specific boundaries). Only an
   * administrator can execute this endpoint, ensuring that all business-level
   * constraints are declared, documented, and properly activated via an
   * auditable interface.
   *
   * Upon creation, unique constraint_name and scope are required to ensure no
   * accidental overlaps or duplicate business enforcement. The schema allows
   * specifying the constraint name, scope, value, value unit, descriptive text,
   * and its initial activation state. Creating a constraint through this
   * endpoint guarantees traceability and consistent enforcement across platform
   * modules. Standard application-level validation will reject requests with
   * missing or duplicated names/scopes, or with invalid types/units for the
   * constraint. Related operations include updating an existing constraint,
   * querying all constraints, or deactivating a constraint when its business
   * purpose lapses. Recovery and error scenarios include name collisions, scope
   * errors, or missing required input fields, each generating appropriate
   * validation messages for the operator.
   *
   * @param connection
   * @param body Information required to create a business constraint (unique
   *   constraint_name, scope, value, unit, description, activation state)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingBusinessConstraint.ICreate,
  ): Promise<IShoppingBusinessConstraint> {
    try {
      return await postShoppingAdminBusinessConstraints({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * List and filter all business constraints defined on the platform for
   * configuration management and audit.
   *
   * This API operation retrieves a paginated and filtered list of business
   * constraints defined for the platform, allowing audit, compliance, and
   * capacity review. Business constraints are critical for enforcing
   * operational boundaries, such as limits on order size, SKUs per product,
   * rate limits, or other operational guardrails defined in the
   * shopping_business_constraints table.
   *
   * The operation enables searching and filtering by constraint_name, scope,
   * activity status, and other key fields. Pagination and sorting ensure that
   * administrators and operators can efficiently browse large sets of
   * constraint records. Input supports business context queries, and returns
   * all visible constraint items in summary format. This is particularly useful
   * for proactive system management and compliance audits across changing
   * operational parameters.
   *
   * The business constraint record includes fields like constraint_name (name
   * of the rule), scope (domain of application, e.g., global, cart, product),
   * limit_value (the numeric or string limit), unit (what is being limited),
   * and active (if the constraint is in force). Detailed descriptions further
   * clarify business enforcement. Only users with admin-level or platform
   * operator privileges may access this endpoint.
   *
   * @param connection
   * @param body Search and filter criteria for retrieving business constraints,
   *   including scope, constraint_name, activity status, page size, and sort
   *   order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingBusinessConstraint.IRequest,
  ): Promise<IPageIShoppingBusinessConstraint.ISummary> {
    try {
      return await patchShoppingAdminBusinessConstraints({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch detail for a specific business constraint by constraintName for
   * auditing and configuration review.
   *
   * This API operation returns the complete detail record for a specific
   * business constraint, searched by its unique constraintName. Business
   * constraints establish quantitative or operational limits for various
   * shopping mall subsystems, enforced across the shopping_business_constraints
   * table.
   *
   * Calling this operation allows platform operators, administrators, or
   * technical auditors to review the enforced value, related scope, unit of
   * limitation, active/inactive status, and descriptive reasoning for any
   * quantitative rule in force. It provides transparency for business logic and
   * enables effective configuration troubleshooting, capacity planning, and
   * system documentation maintenance.
   *
   * The constraintName must be provided exactly as stored in the backend
   * (case-sensitive, unique). The returned schema includes constraint_name,
   * scope, limit_value, unit, description, and active flag. Permission to
   * access this detail is reserved for admins and configuration operators only.
   * If the constraintName does not exist, an appropriate error will be returned
   * indicating no such business constraint is found.
   *
   * @param connection
   * @param constraintName Unique name of the target business constraint (global
   *   scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":constraintName")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("constraintName")
    constraintName: string,
  ): Promise<IShoppingBusinessConstraint> {
    try {
      return await getShoppingAdminBusinessConstraintsConstraintName({
        admin,
        constraintName,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing business constraint (shopping_business_constraints) by
   * constraint name.
   *
   * This API allows platform administrators to edit and update an
   * already-defined business constraint. The targeted constraint is globally
   * identified by its unique constraint_name path parameter.
   *
   * Typical updates include changing the limit_value, adjusting the applicable
   * domain scope, modifying the constraint description for business clarity,
   * transitioning activation state, or correcting the unit of measurement. The
   * API operates with full validation on constraint types and value ranges. It
   * will return validation errors if attempting to update a non-existent
   * constraint, if the updated name or scope would collide with another, or if
   * value/unit types do not match policy expectations.
   *
   * Security and integrity are enforced by restricting access to platform
   * admins, and all update actions are fully audited in administrative logs.
   * The API's update operation maintains backward compatibility for dependent
   * platform modules and ensures consistent enforcement of the latest business
   * limits without introducing data inconsistencies.
   *
   * @param connection
   * @param constraintName Unique business constraint name to identify the
   *   constraint entry (global scope)
   * @param body Updated information for the business constraint (scope, value,
   *   unit, description, activation state)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":constraintName")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("constraintName")
    constraintName: string,
    @TypedBody()
    body: IShoppingBusinessConstraint.IUpdate,
  ): Promise<IShoppingBusinessConstraint> {
    try {
      return await putShoppingAdminBusinessConstraintsConstraintName({
        admin,
        constraintName,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete (archive) a business constraint by unique constraint name in
   * shopping_business_constraints table.
   *
   * This API endpoint allows an administrator to mark a specific business
   * constraint as deleted (soft delete) using its unique constraintName. The
   * operation references the shopping_business_constraints model, where each
   * constraint is uniquely identified by its constraint_name in the database.
   *
   * Upon invocation, the system first validates that the provided
   * constraintName exists and is eligible for deletion (for example, not a
   * platform-required constraint). If the constraint is deletable, the
   * operation sets the deleted_at timestamp, marking the constraint as inactive
   * without physically removing it from the database. This approach maintains
   * full retention for compliance and rollback. If the constraint does not
   * exist or cannot be deleted due to business dependency or policy, a detailed
   * business error should be returned, and no action is performed.
   *
   * Sensitive operation: Only accessible to admin actors. All soft deletions
   * are fully auditable and reversible by platform policy, and the endpoint is
   * secured with strict authentication and action logging.
   *
   * @param connection
   * @param constraintName Unique business constraint name of the target
   *   constraint (global scope). This must match the constraint_name column in
   *   shopping_business_constraints.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":constraintName")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("constraintName")
    constraintName: string,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminBusinessConstraintsConstraintName({
        admin,
        constraintName,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
