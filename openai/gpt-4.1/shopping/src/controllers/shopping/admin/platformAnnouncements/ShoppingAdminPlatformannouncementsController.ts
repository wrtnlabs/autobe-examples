import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingAdminPlatformAnnouncements } from "../../../../providers/postShoppingAdminPlatformAnnouncements";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminPlatformAnnouncements } from "../../../../providers/patchShoppingAdminPlatformAnnouncements";
import { putShoppingAdminPlatformAnnouncementsPlatformAnnouncementId } from "../../../../providers/putShoppingAdminPlatformAnnouncementsPlatformAnnouncementId";
import { deleteShoppingAdminPlatformAnnouncementsPlatformAnnouncementId } from "../../../../providers/deleteShoppingAdminPlatformAnnouncementsPlatformAnnouncementId";

import { IShoppingPlatformAnnouncement } from "../../../../api/structures/IShoppingPlatformAnnouncement";
import { IPageIShoppingPlatformAnnouncement } from "../../../../api/structures/IPageIShoppingPlatformAnnouncement";

@Controller("/shopping/admin/platformAnnouncements")
export class ShoppingAdminPlatformannouncementsController {
  /**
   * Create a new platform announcement (shopping_platform_announcements).
   *
   * This endpoint allows an admin to create a new platform announcement,
   * specifying key details like title, content, target audience, publication
   * window (start/end), and current status. It populates the
   * 'shopping_platform_announcements' Prisma table, supporting platform-wide
   * communication, legal notices, or operational updates as required by the
   * business.
   *
   * Security policies restrict this operation to admin actors only, ensuring
   * that only authorized personnel can publish announcements. Upon successful
   * creation, the API response includes a full record of the announcement,
   * including administrative metadata for traceability.
   *
   * The request body must match the IShoppingPlatformAnnouncement.ICreate type
   * and pass validation for all required fields (title, body, audience,
   * scheduling, status). Improper input, insufficient permissions, or
   * scheduling conflicts result in clear error messages and no announcement is
   * created. This endpoint is most commonly used in the admin dashboard for
   * global communication and compliance updates.
   *
   * @param connection
   * @param body Creation details for the new platform announcement including
   *   title, content, target, scheduling, and status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingPlatformAnnouncement.ICreate,
  ): Promise<IShoppingPlatformAnnouncement> {
    try {
      return await postShoppingAdminPlatformAnnouncements({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Advanced search, filtering, and pagination of admin platform announcements
   * (shopping_platform_announcements).
   *
   * Query the list of platform announcements by a wide variety of search and
   * filter parameters. Admins may query all announcements, while
   * sellers/customers view only currently visible or targeted announcements.
   * The search supports filters by status (draft, active, expired, scheduled),
   * target audience (all, customers, sellers, admins), publish window periods,
   * and full-text search over title and content. Pagination and sorting options
   * are provided to permit efficient dashboard rendering and compliance
   * auditing.
   *
   * Security considerations include strict role enforcement to prevent
   * unauthorized data access, especially for non-public or scheduled
   * announcements. Response omits or redacts unpublished/draft content for
   * non-admin actors, and sensitive scheduling information is only fully
   * available to admins. This API is essential for admin portal interfaces,
   * notification analytics, and regulated information reporting flows. Failure
   * or error scenarios include invalid filter combinations, access violations,
   * or exceeding quota/rate limits.
   *
   * Returned data structure is a paginated summary list using the
   * IPageIShoppingPlatformAnnouncement.ISummary schema, providing all primary
   * fields from the shopping_platform_announcements table.
   *
   * @param connection
   * @param body Search and filter criteria for announcements. Includes possible
   *   status, target audience, time windows, keywords, and pagination/sorting
   *   options.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingPlatformAnnouncement.IRequest,
  ): Promise<IPageIShoppingPlatformAnnouncement.ISummary> {
    try {
      return await patchShoppingAdminPlatformAnnouncements({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific platform announcement by ID in the
   * shopping_platform_announcements table.
   *
   * This API endpoint enables an admin to update the content, status, or
   * metadata of a specific platform announcement identified by its unique
   * platformAnnouncementId. The operation is designed for administrative
   * purposes, allowing platform admins to revise announcement details such as
   * the title, body, publication status, visibility window (start/end times),
   * or target audience based on platform needs.
   *
   * Administrative privileges are strictly enforced for this operation,
   * ensuring that only authorized users (admins) can perform modifications. The
   * endpoint interacts directly with the shopping_platform_announcements table,
   * ensuring all edits are tracked via audit logs for compliance reasons.
   * Changes made via this endpoint are immediately reflected in user-facing
   * announcement listings, affecting what is visible to users or system
   * actors.
   *
   * Validation rules include ensuring that all required fields are present, the
   * new title does not duplicate any existing active announcement, date/time
   * logic for the publish window is coherent, and the status field follows
   * accepted enum values (draft, scheduled, active, expired, or hidden).
   * Related endpoints for announcement creation or removal should be referenced
   * for full announcement lifecycle management. Error handling addresses cases
   * such as attempting to update a non-existent ID or lacking sufficient
   * privileges.
   *
   * @param connection
   * @param platformAnnouncementId Unique identifier of the platform
   *   announcement to update.
   * @param body Updated fields for the platform announcement.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":platformAnnouncementId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("platformAnnouncementId")
    platformAnnouncementId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingPlatformAnnouncement.IUpdate,
  ): Promise<IShoppingPlatformAnnouncement> {
    try {
      return await putShoppingAdminPlatformAnnouncementsPlatformAnnouncementId({
        admin,
        platformAnnouncementId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete (soft-remove) a platform announcement by ID in the
   * shopping_platform_announcements table (admin only).
   *
   * This API operation allows admin actors to delete (soft-delete) a specific
   * platform announcement, as identified by the platformAnnouncementId. The
   * deletion is implemented as a soft delete, updating the deleted_at field to
   * retain historical and audit trace even after the announcement is removed
   * from user-facing displays. The endpoint only accepts requests from
   * authenticated admins, following strict authorization policies to prevent
   * unauthorized removals.
   *
   * The soft deletion is required by business and audit logic, preserving
   * evidence of all past communications. Attempts to delete a non-existent or
   * already-deleted announcement will result in error responses, and all
   * actions are logged for compliance, security, and transparency. The deleted
   * record is omitted from future platform-wide announcements, notifications,
   * and dashboards, but remains available in administrator audit trails.
   *
   * Use this endpoint in accordance with platform-wide compliance,
   * communication, and historical announcement review requirements. The
   * operation does not physically erase the announcement from the database,
   * maintaining regulatory data retention standards.
   *
   * @param connection
   * @param platformAnnouncementId Unique identifier of the platform
   *   announcement to delete (soft delete).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":platformAnnouncementId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("platformAnnouncementId")
    platformAnnouncementId: string & tags.Format<"uuid">,
  ): Promise<IShoppingPlatformAnnouncement> {
    try {
      return await deleteShoppingAdminPlatformAnnouncementsPlatformAnnouncementId(
        {
          admin,
          platformAnnouncementId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
