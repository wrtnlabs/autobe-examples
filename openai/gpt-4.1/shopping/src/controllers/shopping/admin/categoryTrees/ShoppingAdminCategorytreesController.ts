import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingAdminCategoryTrees } from "../../../../providers/postShoppingAdminCategoryTrees";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putShoppingAdminCategoryTreesTreeCode } from "../../../../providers/putShoppingAdminCategoryTreesTreeCode";
import { deleteShoppingAdminCategoryTreesTreeCode } from "../../../../providers/deleteShoppingAdminCategoryTreesTreeCode";

import { IShoppingCategoryTree } from "../../../../api/structures/IShoppingCategoryTree";

@Controller("/shopping/admin/categoryTrees")
export class ShoppingAdminCategorytreesController {
  /**
   * Create a new category tree (taxonomy) in shopping_category_trees for
   * catalog organization.
   *
   * This API allows an admin user to create a new category tree in the platform
   * for use as a taxonomy to classify products, brands, or other entities. The
   * request body must include a unique tree_code, display name (tree_name), and
   * optional description. The operation validates that the code does not
   * conflict with existing rows in shopping_category_trees, and persists
   * auditing timestamps for creation and updates. Soft deletion support is
   * available for later archival without physical removal.
   *
   * Security: creation of category trees is a privileged admin-only action due
   * to its platform-wide impact on catalog organization, navigation, and
   * product assignment. Admins may use this to launch new product lines or
   * brand groupings.
   *
   * Business logic ensures that the tree_code is unique across the platform and
   * that the created tree is ready for assignment of categories. If attempted
   * with a duplicate code, the operation returns a conflict error. This
   * operation may be followed by category creation for detailed classification
   * arrangement.
   *
   * @param connection
   * @param body Category tree creation details (unique code, display name,
   *   optional description)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingCategoryTree.ICreate,
  ): Promise<IShoppingCategoryTree> {
    try {
      return await postShoppingAdminCategoryTrees({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Modify details of a category tree identified by tree_code
   * (shopping_category_trees).
   *
   * This API allows administrative modification of an existing category tree's
   * details on the shopping mall platform. Category trees define independent
   * taxonomies for product organization — such as main shop categories, brands,
   * or specialized browsing hierarchies. Each category tree is uniquely
   * referenced by its tree_code, which is globally unique according to the
   * schema (with a @@unique constraint).
   *
   * Update actions can include renaming the tree, updating its business context
   * description, or modifying other allowed metadata fields. Changing the
   * tree_code itself is not permitted because it is the unique business
   * identifier for all related categories and navigation features (the Prisma
   * schema enforces code uniqueness at the database layer).
   *
   * Security is paramount, as only admin-level actors are permitted to edit
   * category trees. Each update is fully logged for audit compliance to meet
   * business trace and regulatory needs. Clients should submit only allowed
   * updatable fields in the request body, and must use strict validation to
   * match data types and constraints defined in the database schema.
   *
   * Invalid update attempts — such as violating the unique constraint on
   * tree_code, submitting an empty display name, or removing all categories
   * with assigned products — will result in business-specific error responses.
   * Full details of allowed and failed attempts are always auditable and
   * visible in admin logs.
   *
   * @param connection
   * @param treeCode Unique business identifier code of the target category tree
   *   (global scope)
   * @param body Editable information for updating the catalog category tree
   *   (display name, business context description, etc).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":treeCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("treeCode")
    treeCode: string,
    @TypedBody()
    body: IShoppingCategoryTree.IUpdate,
  ): Promise<IShoppingCategoryTree> {
    try {
      return await putShoppingAdminCategoryTreesTreeCode({
        admin,
        treeCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Archive (soft-delete) a category tree and prevent further use, using its
   * tree_code (shopping_category_trees).
   *
   * This endpoint provides administrative capability to archive (soft-delete)
   * an entire category tree, identified by its unique tree_code, within the
   * shopping mall catalog system. In the Prisma schema, tree_code is globally
   * unique and directly identifies a category taxonomy for all product and
   * navigation organization.
   *
   * Archiving the tree sets the deleted_at field on the shopping_category_trees
   * record, which in turn disables all associated categories from further use.
   * All category assignments (e.g., to products) and hierarchical relationships
   * remain in the database for compliance and audit retention, but the archived
   * tree and its categories become unavailable for new product assignments,
   * navigation, or categorization features.
   *
   * This action is restricted to admin users due to the potentially significant
   * structural impact to catalog navigation and product taxonomy integrity. The
   * operation records a full audit log for traceability. Attempts to delete a
   * nonexistent treeCode or a tree with dependent live category assignments may
   * result in specific error codes or remediation requirements governed by the
   * business rules, such as forced reassignment of affected products prior to
   * archival.
   *
   * @param connection
   * @param treeCode Unique business identifier code of the target category tree
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":treeCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("treeCode")
    treeCode: string,
  ): Promise<IShoppingCategoryTree> {
    try {
      return await deleteShoppingAdminCategoryTreesTreeCode({
        admin,
        treeCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
