import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { postShoppingAdminCategoryTreesTreeCodeCategories } from "../../../../../providers/postShoppingAdminCategoryTreesTreeCodeCategories";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { putShoppingAdminCategoryTreesTreeCodeCategoriesCategoryCode } from "../../../../../providers/putShoppingAdminCategoryTreesTreeCodeCategoriesCategoryCode";
import { deleteShoppingAdminCategoryTreesTreeCodeCategoriesCategoryCode } from "../../../../../providers/deleteShoppingAdminCategoryTreesTreeCodeCategoriesCategoryCode";

import { IShoppingCategory } from "../../../../../api/structures/IShoppingCategory";

@Controller("/shopping/admin/categoryTrees/:treeCode/categories")
export class ShoppingAdminCategorytreesCategoriesController {
  /**
   * Create a new product category within a specific category tree in the
   * shopping mall platform (shopping_categories table).
   *
   * This operation creates a new category node under a specified category tree.
   * The caller must provide the tree's unique treeCode (see
   * shopping_category_trees) to identify the taxonomy in which the new category
   * will be created. The body must contain details for the new category,
   * including unique category_code, display name, parent relationship (optional
   * for root/category depth control), and sort order among siblings. The system
   * enforces unique codes within each tree and validates the category tree
   * exists before insert. Upon creation, the new category is ready for product
   * assignment and immediate use in catalog operations. Only admins may perform
   * this operation; all actions are fully audited for regulatory compliance and
   * business rules. The operation references the full description comments in
   * the shopping_categories Prisma model, ensuring the returned category object
   * matches all schema fields and relationships. Error handling covers invalid
   * parent tree, duplicate code, or depth violations, returning standard
   * business error codes as described in platform error scenarios.
   *
   * @param connection
   * @param treeCode Unique business identifier code of the target category tree
   *   (global scope)
   * @param body Category creation info including category_code, category_name,
   *   parent_id (optional), and sort_order for the new node.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("treeCode")
    treeCode: string,
    @TypedBody()
    body: IShoppingCategory.ICreate,
  ): Promise<IShoppingCategory> {
    try {
      return await postShoppingAdminCategoryTreesTreeCodeCategories({
        admin,
        treeCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update details or hierarchy of an existing category node in a specific
   * category tree (shopping_categories table).
   *
   * This operation modifies the details of a product category within the
   * taxonomy for a specific shopping mall category tree. The admin must specify
   * both the treeCode (from shopping_category_trees) and the categoryCode
   * (unique per tree, from shopping_categories) in the path. The request body
   * must provide new values for updatable fields such as category_name,
   * sort_order (for sibling ordering), description, and optionally a new
   * parent_id to adjust hierarchy. System logic enforces hierarchical
   * integrity, uniqueness constraints, and business rules (such as preventing
   * cycles or moving categories across trees). If the operation is successful,
   * the updated category is returned; all changes are subject to full audit
   * logging. This is restricted to admin actors only; unauthorized attempts are
   * rejected with standard business error codes. Detailed validation and error
   * scenarios are referenced from the shopping_categories schema
   * documentation.
   *
   * @param connection
   * @param treeCode Unique business identifier code of the target category tree
   *   (global scope)
   * @param categoryCode Unique business identifier code of the target category
   *   within the category tree (scoped to treeCode)
   * @param body Updated category details including category_name, sort_order,
   *   description, and optional parent_id to adjust hierarchy.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("treeCode")
    treeCode: string,
    @TypedParam("categoryCode")
    categoryCode: string,
    @TypedBody()
    body: IShoppingCategory.IUpdate,
  ): Promise<IShoppingCategory> {
    try {
      return await putShoppingAdminCategoryTreesTreeCodeCategoriesCategoryCode({
        admin,
        treeCode,
        categoryCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a category node from a category tree in
   * shopping_categories.
   *
   * This API endpoint removes a category node from a specified category tree,
   * requiring both the unique code for the target tree (treeCode) and for the
   * category node (categoryCode) as path parameters. The operation implements
   * strict hierarchical integrity: if the target category has child categories
   * or is assigned to active products, deletion is either blocked or must
   * follow re-assignment procedures depending on business logic. All audit and
   * compliance requirements for category changes are enforced. The operation is
   * restricted to administrative actors, and every removal action is logged
   * with metadata for future audit or rollback. The response is null,
   * indicating no data is returned on success unless business logic mandates a
   * status object.
   *
   * The underlying shopping_categories schema ensures that category_code is
   * unique within each tree, and all relationships between categories
   * (parent_id), tree assignment (category_tree_id), and product/category
   * assignments must be honored. If a category with subcategories or assignment
   * exists, the operation must enforce business rules such as orphan prevention
   * or re-assignment, reflecting changes throughout the product catalog
   * system.
   *
   * @param connection
   * @param treeCode Unique business identifier code of the target category tree
   *   (global scope)
   * @param categoryCode Unique business identifier code of the target category
   *   within the category tree (scoped to category tree)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("treeCode")
    treeCode: string,
    @TypedParam("categoryCode")
    categoryCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminCategoryTreesTreeCodeCategoriesCategoryCode(
        {
          admin,
          treeCode,
          categoryCode,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
