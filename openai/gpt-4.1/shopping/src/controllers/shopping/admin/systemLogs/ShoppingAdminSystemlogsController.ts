import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingAdminSystemLogsId } from "../../../../providers/getShoppingAdminSystemLogsId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

import { IShoppingSystemLog } from "../../../../api/structures/IShoppingSystemLog";

@Controller("/shopping/admin/systemLogs/:id")
export class ShoppingAdminSystemlogsController {
  /**
   * Retrieve a system log entry by its ID from shopping_system_logs table.
   *
   * This GET operation returns detailed information about a particular system
   * log entry identified by its unique ID in the shopping_system_logs database
   * model. System logs are append-only records used for tracking system events,
   * errors, administrative actions, migrations, or audit trails and contain
   * fields such as event_time, log_level, event_type, event_source, message,
   * and details.
   *
   * Security and access to this operation should be limited to admin or
   * operator roles only as system logs may contain sensitive operational
   * information. Attempting to retrieve a non-existent or unauthorized log
   * entry should return an appropriate error or access denied response.
   *
   * This endpoint is intended to support platform diagnostics, compliance
   * monitoring, and technical event analysis. It can be used in combination
   * with log list/search APIs for efficient backend system management. Make
   * sure log IDs are always treated as UUIDs and access is carefully protected
   * against leaks of internal information.
   *
   * @param connection
   * @param id Unique identifier of the target system log entry (UUID format)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingSystemLog> {
    try {
      return await getShoppingAdminSystemLogsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
