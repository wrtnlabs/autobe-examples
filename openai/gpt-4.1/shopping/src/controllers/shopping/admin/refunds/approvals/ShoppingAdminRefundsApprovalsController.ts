import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingAdminRefundsRefundRequestIdApprovals } from "../../../../../providers/patchShoppingAdminRefundsRefundRequestIdApprovals";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingAdminRefundsRefundRequestIdApprovalsApprovalId } from "../../../../../providers/getShoppingAdminRefundsRefundRequestIdApprovalsApprovalId";

import { IPageIShoppingRefundApproval } from "../../../../../api/structures/IPageIShoppingRefundApproval";
import { IShoppingRefundApproval } from "../../../../../api/structures/IShoppingRefundApproval";

@Controller("/shopping/admin/refunds/:refundRequestId/approvals")
export class ShoppingAdminRefundsApprovalsController {
  /**
   * Search and list approval/rejection actions for a given refund request
   * (shopping_refund_approvals table).
   *
   * Enables authorized users or admins to retrieve a paginated list of all
   * seller and admin approval or rejection records tied to a particular refund
   * request. This supports business audit, regulatory review, and dispute
   * investigation by exposing an authoritative record of all actions taken on
   * refund status transitions.
   *
   * The endpoint supports advanced filtering—by actor, action type
   * (approval/rejection), and time window—as well as paginated delivery of
   * result sets using request parameters. Access is limited to authorized
   * actors to ensure privacy, and sensitive rationale/notes are selectively
   * shown based on the actor requesting the data (full detail for admin,
   * business-safe versions for customers).
   *
   * Related operations include GET for single approval records and PATCH with
   * search criteria across multiple refund requests for admin/business
   * analytics. Errors are returned if the refund request does not exist or the
   * actor lacks permission.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request this
   *   approval action belongs to (global scope).
   * @param body Paging, filtering, and search criteria for refund approval
   *   records (actor, action, date, etc.).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingRefundApproval.IRequest,
  ): Promise<IPageIShoppingRefundApproval.ISummary> {
    try {
      return await patchShoppingAdminRefundsRefundRequestIdApprovals({
        admin,
        refundRequestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific refund approval action for a refund request
   * (shopping_refund_approvals table).
   *
   * Retrieve complete information for a single approval action related to a
   * customer refund request. This endpoint fetches all attributes—such as the
   * approval actor (admin or seller), action type (approved or rejected),
   * notes, and associated timestamps—from the shopping_refund_approvals table.
   *
   * This API provides critical visibility into the approval decision chain for
   * a given refund process, allowing compliance and support teams to audit,
   * troubleshoot, or present decision trails to external stakeholders when
   * necessary. It is particularly relevant to admin actors monitoring refund
   * escalations, as well as platform logic that needs an authoritative record
   * of user or admin decisions. Read-only access minimizes risk of accidental
   * changes, and strictly enforced parameter validation ensures only designated
   * actors can retrieve approval records.
   *
   * This endpoint expects both the refundRequestId and approvalId as URL path
   * parameters. Both values must be provided as UUID strings, referencing the
   * composite unique indexing and foreign key integrity defined in the Prisma
   * schema for robust security and data traceability.
   *
   * @param connection
   * @param refundRequestId UUID for the target refund request (global scope).
   *   Required, matches shopping_refund_requests.id.
   * @param approvalId UUID of the specific approval record (scoped to refund
   *   request). Required, matches shopping_refund_approvals.id.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":approvalId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedParam("approvalId")
    approvalId: string & tags.Format<"uuid">,
  ): Promise<IShoppingRefundApproval> {
    try {
      return await getShoppingAdminRefundsRefundRequestIdApprovalsApprovalId({
        admin,
        refundRequestId,
        approvalId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
