import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingAdminRefundsRefundRequestIdItems } from "../../../../../providers/patchShoppingAdminRefundsRefundRequestIdItems";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingAdminRefundsRefundRequestIdItemsItemId } from "../../../../../providers/getShoppingAdminRefundsRefundRequestIdItemsItemId";
import { deleteShoppingAdminRefundsRefundRequestIdItemsItemId } from "../../../../../providers/deleteShoppingAdminRefundsRefundRequestIdItemsItemId";

import { IPageIShoppingRefundRequestItem } from "../../../../../api/structures/IPageIShoppingRefundRequestItem";
import { IShoppingRefundRequestItem } from "../../../../../api/structures/IShoppingRefundRequestItem";

@Controller("/shopping/admin/refunds/:refundRequestId/items")
export class ShoppingAdminRefundsItemsController {
  /**
   * Search and retrieve refund request items for a specific refund, with
   * advanced filtering and pagination (shopping_refund_request_items).
   *
   * Retrieve a comprehensive, paginated list of all refund request items
   * attached to a specific refund request. This operation enables actors to
   * search, filter, and page through refund items pertaining to the original
   * refund request, referencing the shopping_refund_request_items table in the
   * Prisma schema. Each refund item provides full context: the associated order
   * line, SKU, quantity, business reason if set at item level, status, and
   * creation/modification timestamps.
   *
   * Security and permissions: The endpoint is available to authenticated users
   * with legitimate interest in the refund (customer who initiated, seller of
   * the orders involved, or admin overseeing disputes). The business logic
   * ensures that only those with appropriate access to the parent refund
   * request may query its items, with additional constraints for sensitive
   * order details.
   *
   * Business workflow connections: Listing refund items supports both UI and
   * automated workflows—such as reviewing pending claims, processing partial
   * approvals/denials, and auditing refund eligibility by status and linkage.
   * Filtering capabilities let actors focus on items needing manual action or
   * escalation, while pagination ensures efficiency on large/multi-item
   * requests. Errors for missing or ineligible refundRequestId are handled with
   * explicit business codes and user guidance.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the parent refund request
   *   (global scope)
   * @param body Filtering, search, and pagination criteria for refund request
   *   items list retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingRefundRequestItem.IRequest,
  ): Promise<IPageIShoppingRefundRequestItem.ISummary> {
    try {
      return await patchShoppingAdminRefundsRefundRequestIdItems({
        admin,
        refundRequestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get detailed information for a single refund request item for a given
   * refund and item ID (shopping_refund_request_items).
   *
   * Retrieve full detail for a specific refund request item by providing both
   * refundRequestId and the unique itemId. This operation references the
   * shopping_refund_request_items table in the Prisma schema and returns all
   * business fields required for process traceability, audit, and
   * human/business review. Output includes the associated order and order line,
   * SKU and quantity, and optionally any item-specific business reason.
   * Timestamps, operational status, and linkages to attachments are included
   * when available.
   *
   * Security and permissions: Access is restricted to actors with legitimate
   * business interest—namely, the customer requesting the refund, the seller
   * related to the order, and platform admins. Proper business logic ensures
   * that only actors authorized for the parent refund request can fetch refund
   * item detail.
   *
   * Typical integrations include use for detail screens in customer/seller
   * admin UIs, direct review in refund workflows, and data export for business
   * process auditing. Detailed error handling ensures that if either the
   * refundRequestId or itemId is invalid or not authorized, the user receives
   * explicit error feedback.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the parent refund request
   *   (global scope)
   * @param itemId Unique identifier of the refund request item (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingRefundRequestItem> {
    try {
      return await getShoppingAdminRefundsRefundRequestIdItemsItemId({
        admin,
        refundRequestId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a single refund request item from a refund request
   * (shopping_refund_request_items).
   *
   * This API operation permanently removes a specific refund request item from
   * an existing refund request, provided both the overall request and the item
   * are eligible for deletion according to business rules. The refundRequestId
   * in the path identifies the parent refund request, and itemId identifies the
   * refund item that will be deleted. This operation is typically used when a
   * customer or admin decides to remove a particular item from a pending or
   * draft refund or return, given that the refund or return process has not yet
   * been completed or irrevocably processed.
   *
   * For security, only actors who own the refund request item (such as the
   * requesting customer) and administrators may delete refund items. Audit
   * logging is enforced for all deletions, and attempts to delete a processed
   * or ineligible item will result in a clear error. This operation references
   * the shopping_refund_request_items table, which connects refund requests to
   * specific order lines and supports partial item-based refunds. Related
   * refund statuses and summaries are recomputed after deletion, with error
   * responses in case of integrity constraint violation.
   *
   * The API is related to refund request item management and is often used in
   * conjunction with refund request composition or update flows. If a refund
   * processing decision or payment has already occurred, deletion is
   * disallowed. All changes are audited and retrievable via the refund
   * management audit trail.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request to which the
   *   item belongs; identifies the parent refund request (UUID format). (global
   *   scope)
   * @param itemId Unique identifier for the specific refund request item to be
   *   deleted within the parent refund request (UUID format). (scoped to
   *   refundRequest)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":itemId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminRefundsRefundRequestIdItemsItemId({
        admin,
        refundRequestId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
