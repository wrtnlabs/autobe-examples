import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingAdminRefundsRefundRequestIdOverrides } from "../../../../../providers/patchShoppingAdminRefundsRefundRequestIdOverrides";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingAdminRefundsRefundRequestIdOverridesOverrideId } from "../../../../../providers/getShoppingAdminRefundsRefundRequestIdOverridesOverrideId";

import { IPageIShoppingRefundAdminOverride } from "../../../../../api/structures/IPageIShoppingRefundAdminOverride";
import { IShoppingRefundAdminOverride } from "../../../../../api/structures/IShoppingRefundAdminOverride";

@Controller("/shopping/admin/refunds/:refundRequestId/overrides")
export class ShoppingAdminRefundsOverridesController {
  /**
   * Search and page through all admin refund override actions for a given
   * refund request (shopping_refund_admin_overrides table).
   *
   * Search and retrieve a paginated listing of all override/escalation actions
   * performed by platform admins against a particular refund request. This
   * endpoint surfaces complete details—including override type, business/legal
   * reason, timestamp, admin actor, and detailed context—for every override
   * action, as modeled by the shopping_refund_admin_overrides table.
   *
   * Built for compliance, dispute management, and regulatory inquiry, this API
   * supports advanced query patterns: filter override actions by type, actor,
   * time range, or business rationale, paginate large volumes of records, and
   * deliver full context for each override. This allows platform teams,
   * auditors, and legal reviewers to quickly assemble a chronological timeline
   * for any refund dispute or intervention, supporting evidence-based
   * resolution and proactive monitoring.
   *
   * The refundRequestId path parameter targets the precise refund request under
   * review, and requestBody structures enable flexible search and secure
   * filtering. Results are always paginated for reliability and performance in
   * audit scenarios.
   *
   * @param connection
   * @param refundRequestId UUID for the refund request whose admin override
   *   actions should be listed (global scope). Required, matches
   *   shopping_refund_requests.id.
   * @param body Filtering, pagination, and sorting controls used to search
   *   admin override actions for the given refund request.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingRefundAdminOverride.IRequest,
  ): Promise<IPageIShoppingRefundAdminOverride.ISummary> {
    try {
      return await patchShoppingAdminRefundsRefundRequestIdOverrides({
        admin,
        refundRequestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific refund administrative override
   * (RefundAdminOverrides table), within a refund request context.
   *
   * This API operation enables retrieval of a single refund administrative
   * override record by its unique identifier, in the context of a specified
   * refund request. The endpoint provides full details of the override,
   * including the admin actor, override type, reason, detailed context, and
   * timestamp, as defined in the shopping_refund_admin_overrides Prisma schema.
   * The parent refundRequestId is validated against the
   * shopping_refund_requests table to confirm the context and traceability.
   *
   * The operation is typically used by platform admin users engaged in audit
   * investigations, dispute resolutions, or regular compliance reviews. Only
   * admin actors with appropriate privileges can access this endpoint, and the
   * data returned reflects all relevant fields (except sensitive business
   * context may be redacted according to policy).
   *
   * The response includes comprehensive override details for historical
   * tracking. Error cases include not found (if overrideId is invalid for the
   * specified refundRequestId), or insufficient authorization for non-admin
   * actors attempting access. Related endpoints include list/search operations
   * for overrides and creation endpoints (handled elsewhere).
   *
   * @param connection
   * @param refundRequestId Unique identifier of the parent refund request (UUID
   *   format, required for context validation).
   * @param overrideId Unique identifier of the refund admin override being
   *   retrieved (UUID format).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":overrideId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedParam("overrideId")
    overrideId: string & tags.Format<"uuid">,
  ): Promise<IShoppingRefundAdminOverride> {
    try {
      return await getShoppingAdminRefundsRefundRequestIdOverridesOverrideId({
        admin,
        refundRequestId,
        overrideId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
