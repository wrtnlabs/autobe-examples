import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingAdminRefunds } from "../../../../providers/postShoppingAdminRefunds";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingAdminRefunds } from "../../../../providers/patchShoppingAdminRefunds";
import { getShoppingAdminRefundsRefundRequestId } from "../../../../providers/getShoppingAdminRefundsRefundRequestId";
import { putShoppingAdminRefundsRefundRequestId } from "../../../../providers/putShoppingAdminRefundsRefundRequestId";
import { deleteShoppingAdminRefundsRefundRequestId } from "../../../../providers/deleteShoppingAdminRefundsRefundRequestId";

import { IShoppingRefundRequest } from "../../../../api/structures/IShoppingRefundRequest";
import { IPageIShoppingRefundRequest } from "../../../../api/structures/IPageIShoppingRefundRequest";

@Controller("/shopping/admin/refunds")
export class ShoppingAdminRefundsController {
  /**
   * Initiate a new refund, return, or cancellation request (insert to Refunds
   * table: shopping_refund_requests).
   *
   * This operation enables eligible customers, sellers, or admins to create a
   * new refund, return, or cancellation request associated with an existing
   * order. The request must include all mandatory business fields defined in
   * the Refunds table (shopping_refund_requests), such as order linkage,
   * requestor information, request type (refund, return, cancellation), the
   * business rationale, and structured context if needed.
   *
   * The operation will enforce all eligibility, prevent duplicate or erroneous
   * submissions (such as multiple refund requests for a single order line), and
   * tie any provided refund request items to individual order lines. Supporting
   * documents or image attachments (via linked entities), as well as audit
   * traceability, are handled as part of the operation. Security is paramount:
   * only authenticated and authorized users may submit refund requests, and
   * validations ensure order and item ownership, adherence to platform policy,
   * and compliance tracking.
   *
   * Error scenarios (such as submitting a refund for an ineligible or non-owned
   * order) trigger business error responses as per compliance requirements.
   * Related endpoints include refund info retrieval, status update, item and
   * attachment manipulation, and admin override/dispute intervention systems.
   *
   * @param connection
   * @param body All required data for new refund/cancellation request: order
   *   reference, requestor type/context, reason, line items, and any initial
   *   attachments or context info.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingRefundRequest.ICreate,
  ): Promise<IShoppingRefundRequest> {
    try {
      return await postShoppingAdminRefunds({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated list of refund/cancellation requests
   * (shopping_refund_requests).
   *
   * This API provides advanced search capabilities for refund, return, and
   * cancellation requests. The request body supports filters on request type,
   * status (pending, approved, declined, etc.), initiating actor, associated
   * order, and time periods. Pagination and sorting options are included to
   * support high-volume admin workflows and customer self-service scenarios.
   *
   * Results include summary information about each request as defined in the
   * Prisma schema, facilitating quick review. This operation supports business
   * needs such as refund queue management, status monitoring, and audit
   * reporting. The response provides a paginated list of refund requests with
   * associated meta information.
   *
   * Security is critical: results are filtered to only those requests the
   * current actor is permitted to access (own refunds for customer, seller's
   * order refunds for seller, globally for admin). Path parameters are not
   * used; all filtering is via request body.
   *
   * If no requests match the filters, an empty result set is returned. The
   * operation's implementation aligns with the shopping_refund_requests schema
   * comments and supports integration with related tables for joined/expanded
   * details.
   *
   * @param connection
   * @param body Search, filter, and pagination options for refund/cancellation
   *   request retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingRefundRequest.IRequest,
  ): Promise<IPageIShoppingRefundRequest.ISummary> {
    try {
      return await patchShoppingAdminRefunds({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific refund request from the
   * Refunds table (shopping_refund_requests).
   *
   * This operation fetches all details of a single refund, return, or
   * cancellation request for an order as recorded in the Refunds table
   * (shopping_refund_requests) in the system. It provides complete properties
   * of the refund request, including its type (refund, return, cancellation),
   * requestor and actor context, business reason, workflow/status fields,
   * timestamps, and audit traces.
   *
   * Refund request state transitions, status history logs, attached documents
   * or supporting evidence, and associated order lines/items are
   * included—allowing full tracking for customer service, admin arbitration, or
   * seller communication. Security is critical: only the requestor, associated
   * order/admin, or parties with explicit access rights may access private
   * refund details. Unauthenticated or unrelated actors are forbidden from
   * receiving sensitive data. Detailed error handling ensures the existence of
   * the refund request, access permission, and logic against exposing
   * ineligible data.
   *
   * This API forms the backbone of after-sales flows and should be integrated
   * with business logic for eligibility, status tracking, and documentation.
   * Related operations include refund request creation, refund item editing,
   * status update, and admin override endpoints.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the target refund request (UUID
   *   in shopping_refund_requests.id)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":refundRequestId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingRefundRequest> {
    try {
      return await getShoppingAdminRefundsRefundRequestId({
        admin,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update existing refund/cancellation request (shopping_refund_requests
   * table).
   *
   * This endpoint allows an authorized actor (such as a customer, seller, or
   * admin) to update the business reason, status, or additional context of an
   * existing refund, return, or cancellation request. Key use cases include
   * correcting or expanding the reason for a request, providing additional
   * context as requested by a seller or admin, or progressing the business
   * status based on negotiation or workflow requirements.
   *
   * The operation strictly enforces eligibility and status transition rules,
   * ensuring only permitted fields are updated and that audit trails are
   * properly recorded for compliance. Each update request is thoroughly
   * validated according to the refund system's business logic, and attempts to
   * modify non-updatable properties are rejected with detailed error messages.
   *
   * All modifications are subject to actor authorization as dictated by the
   * refund request's current status and type. Unauthorized attempts or
   * transitions are blocked and logged for audit and possible escalation.
   * Related operations may include submitting or approving refund requests,
   * viewing detailed request status, or attaching supporting evidence (which
   * are managed by separate endpoints).
   *
   * @param connection
   * @param refundRequestId Unique identifier of the target refund request (UUID
   *   format)
   * @param body Fields to update on the refund request, such as business_reason
   *   or status, following business rules defined for
   *   IShoppingRefundRequest.IUpdate.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":refundRequestId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingRefundRequest.IUpdate,
  ): Promise<IShoppingRefundRequest> {
    try {
      return await putShoppingAdminRefundsRefundRequestId({
        admin,
        refundRequestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Archive (soft-delete) a refund/cancellation request
   * (shopping_refund_requests table).
   *
   * This endpoint allows an authorized actor (admin or original requester) to
   * archive (soft delete) an existing refund, return, or cancellation request
   * by populating the deleted_at timestamp. The soft delete operation ensures
   * auditability and compliance with legal recordkeeping, instead of physically
   * removing the database record. The API validates that the refund request is
   * eligible for deletion (not currently under review or in a locked business
   * status), and only the owner (customer/seller who initiated it) or an
   * approved admin may delete the request.
   *
   * The operation audits every deletion event with actor, timestamp, and
   * reason, and logs all unsuccessful deletion attempts for compliance review.
   * Related endpoints may include listing or querying deleted records,
   * restoring records (if business policy allows), and audit-log access for
   * legal disputes. Attempts to delete ineligible or system-locked requests
   * will return a detailed error. The operation references the
   * shopping_refund_requests table and strictly follows all business
   * constraints on deletion eligibility.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the target refund request (UUID
   *   format)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":refundRequestId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingAdminRefundsRefundRequestId({
        admin,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
