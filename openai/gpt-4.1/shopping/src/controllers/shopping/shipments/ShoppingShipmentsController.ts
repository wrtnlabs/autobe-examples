import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getShoppingShipmentsCode } from "../../../providers/getShoppingShipmentsCode";

import { IShoppingShipment } from "../../../api/structures/IShoppingShipment";

@Controller("/shopping/shipments/:code")
export class ShoppingShipmentsController {
  /**
   * Retrieve detailed information for a specific shipment by code from
   * shopping_shipments.
   *
   * Retrieve a single shipment's details by its unique code. This endpoint
   * returns all essential shipment fields such as status, carrier company,
   * dispatch and delivery dates, and associated metadata, for both customer and
   * operations use cases.
   *
   * Authorization is generally required for viewing shipment details, with
   * role-based restrictions: customers may only view their own shipment codes;
   * sellers may view only those for their products; admins may access all
   * shipments. This aligns with business logic in shopping_shipments and the
   * requirements for secure, auditable tracking.
   *
   * Full tracking and historical status information are not included here but
   * may be retrieved using subsidiary audit endpoints. Error responses occur if
   * the shipment code does not exist or is not accessible by the actor context,
   * matching platform security standards.
   *
   * @param connection
   * @param code Unique shipment business code (e.g., SHPT-2025-0001) assigned
   *   in shopping_shipments for external and business workflows. Must match
   *   exactly to identify the shipment record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("code")
    code: string,
  ): Promise<IShoppingShipment> {
    try {
      return await getShoppingShipmentsCode({
        code,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
