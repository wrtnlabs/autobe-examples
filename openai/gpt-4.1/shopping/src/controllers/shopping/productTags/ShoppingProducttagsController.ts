import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getShoppingProductTagsTagCode } from "../../../providers/getShoppingProductTagsTagCode";

import { IShoppingProductTag } from "../../../api/structures/IShoppingProductTag";

@Controller("/shopping/productTags/:tagCode")
export class ShoppingProducttagsController {
  /**
   * Retrieve a product tag by its unique business tag code from
   * shopping_product_tags.
   *
   * This API operation allows clients to fetch the full metadata of a single
   * product tag identified by the unique tagCode. Product tags empower catalog
   * search and display, with each tag providing a display value, code, and
   * descriptive purpose for shoppers and filter builders.
   *
   * Access to this information is essential for scenarios such as tag-driven
   * catalog pages or when building tag-based search facets in product filtering
   * UIs. The endpoint ensures that only tags registered in the
   * shopping_product_tags schema are returned, and each response includes all
   * fields defined in the database table, supporting reliable search and
   * display logic.
   *
   * Authorization is open for all authenticated users, as reading tags does not
   * compromise business security or sensitive data. Related write operations,
   * such as creating and updating tags, require admin or seller permissions
   * through different endpoints.
   *
   * @param connection
   * @param tagCode Business code of the product tag to retrieve (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("tagCode")
    tagCode: string,
  ): Promise<IShoppingProductTag> {
    try {
      return await getShoppingProductTagsTagCode({
        tagCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
