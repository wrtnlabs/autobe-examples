import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingSkusSkuIdReviewAggregates } from "../../../../providers/getShoppingSkusSkuIdReviewAggregates";

import { IShoppingReviewRatingAggregate } from "../../../../api/structures/IShoppingReviewRatingAggregate";

@Controller("/shopping/skus/:skuId/reviewAggregates")
export class ShoppingSkusReviewaggregatesController {
  /**
   * Retrieve review & rating summary aggregate for a product SKU
   * (shopping_review_rating_aggregates).
   *
   * This API operation allows any actor (public) to fetch the detailed summary
   * statistics for customer reviews and ratings associated with a particular
   * product SKU. Typical use cases include displaying product star ratings,
   * total review counts, and average scores in catalog listings, product pages,
   * and search rankings.
   *
   * For the given SKU, the API returns the corresponding summary object from
   * the shopping_review_rating_aggregates table: including fields such as
   * average_rating, review_count, product_review_count, and
   * product_average_rating. Actors do not need to be authenticated for this
   * operation as review/rating data is intended for broad public consumption
   * and does not expose any personal information.
   *
   * The required path parameter skuId is the UUID of the SKU being queried. If
   * no review aggregate exists, a not found error is returned. This operation
   * stands alone but is also commonly used in conjunction with product/variant
   * detail endpoints in catalog APIs. This endpoint never requires a request
   * body or sensitive authentication.
   *
   * Error handling is limited to validation errors (UUID format) or missing
   * data (404 not found).
   *
   * @param connection
   * @param skuId Unique identifier of the target SKU (UUID) for which review
   *   aggregate summary is requested.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("skuId")
    skuId: string & tags.Format<"uuid">,
  ): Promise<IShoppingReviewRatingAggregate> {
    try {
      return await getShoppingSkusSkuIdReviewAggregates({
        skuId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
