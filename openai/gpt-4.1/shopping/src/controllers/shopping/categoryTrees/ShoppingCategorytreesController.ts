import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingCategoryTrees } from "../../../providers/patchShoppingCategoryTrees";
import { getShoppingCategoryTreesTreeCode } from "../../../providers/getShoppingCategoryTreesTreeCode";

import { IPageIShoppingCategoryTree } from "../../../api/structures/IPageIShoppingCategoryTree";
import { IShoppingCategoryTree } from "../../../api/structures/IShoppingCategoryTree";

@Controller("/shopping/categoryTrees")
export class ShoppingCategorytreesController {
  /**
   * Search and retrieve a paginated list of all category trees
   * (shopping_category_trees) with filtering and sorting options.
   *
   * This API operation enables retrieval of category tree metadata for all
   * hierarchical classification structures defined in the
   * 'shopping_category_trees' table. Category trees form the backbone of
   * catalog and product organization, supporting features such as
   * category-based browsing, filtering, and product discovery for users and
   * sellers.
   *
   * The PATCH method is employed to support complex request body filtering,
   * searching, and advanced pagination (such as partial code match, range
   * filtering on created_at, and sorted result sets). Clients may specify
   * search criteria such as tree_code, tree_name, creation date intervals, or
   * other fields; absence of criteria retrieves all trees.
   *
   * The operation returns a paginated result using the
   * 'IPageIShoppingCategoryTree.ISummary' DTO, providing a lightweight overview
   * of each tree, including its code, name, and creation details. Each page
   * contains summary information for optimal list rendering and navigation. No
   * sensitive data is included, so the operation is public and requires no
   * authentication. Associated categories within each tree are not included in
   * this endpoint but can be accessed via related APIs by specifying the
   * tree_code or id.
   *
   * @param connection
   * @param body Search and pagination criteria for category tree lookup,
   *   supporting filtering by code, name, and creation date intervals.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingCategoryTree.IRequest,
  ): Promise<IPageIShoppingCategoryTree.ISummary> {
    try {
      return await patchShoppingCategoryTrees({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific category tree by its unique business code from
   * shopping_category_trees.
   *
   * This API retrieves the full details for a specific category tree identified
   * by its unique business code (tree_code). The category tree includes
   * metadata such as the display name, description, and timestamps for
   * creation, update, and deletion (if applicable). This enables clients to
   * view which category groupings (such as 'main', 'brands', or other
   * taxonomies) exist and to inspect which one they are interacting with when
   * assigning or browsing categories.
   *
   * Security considerations: while category tree data is generally
   * non-sensitive, only actors with catalog or product management permissions
   * (admin, seller) should be able to modify or create them; however, reading
   * category tree data is allowed for public consumers for navigation and
   * display purposes.
   *
   * The Prisma schema guarantees the tree_code is globally unique within the
   * shopping_category_trees table. If the code does not exist or the row is
   * soft-deleted, the API will return an appropriate error. The operation is
   * routinely used in combination with category browsing or product onboarding
   * workflows to provide tree context.
   *
   * Related API operations include listing all category trees for
   * administrative purposes and managing individual categories under a tree.
   * Error handling covers not found and inactive (deleted) tree cases.
   *
   * @param connection
   * @param treeCode Unique business identifier code of the target category tree
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":treeCode")
  public async at(
    @TypedParam("treeCode")
    treeCode: string,
  ): Promise<IShoppingCategoryTree> {
    try {
      return await getShoppingCategoryTreesTreeCode({
        treeCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
