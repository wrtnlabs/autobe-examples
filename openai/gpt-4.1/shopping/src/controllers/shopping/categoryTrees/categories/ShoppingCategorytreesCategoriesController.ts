import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getShoppingCategoryTreesTreeCodeCategoriesCategoryCode } from "../../../../providers/getShoppingCategoryTreesTreeCodeCategoriesCategoryCode";

import { IShoppingCategory } from "../../../../api/structures/IShoppingCategory";

@Controller("/shopping/categoryTrees/:treeCode/categories/:categoryCode")
export class ShoppingCategorytreesCategoriesController {
  /**
   * Retrieve a specific shopping category within a category tree by code.
   *
   * This endpoint returns complete details for a single shopping category node
   * (as defined in shopping_categories), precisely identified by the
   * combination of category tree code (from shopping_category_trees) and
   * category code (unique within tree). The composite key construction
   * guarantees no ambiguity, supporting deep tree structures and multi-taxonomy
   * catalog environments.
   *
   * Security context: This API is safe for public or authenticated access as it
   * only reads (never creates, updates, or deletes) the specific category node.
   * When used by admins or sellers for management, additional relational
   * metadata may be exposed. When accessed for public navigation, only core
   * fields (category_code, category_name, description, parent, path, etc.) are
   * returned.
   *
   * Careful validation is enforced: A missing or invalid category code or tree
   * code returns a structured error. The query is always performed over active
   * (non soft-deleted) categories and trees. If the target node is a leaf,
   * downstream product assignment in the UI is enabled; if not, clients may
   * fetch child nodes for tree navigation. Related endpoints for children or
   * parent traversal are recommended to enhance typical e-commerce UX.
   *
   * @param connection
   * @param treeCode Unique tree code of the target category tree (global scope)
   * @param categoryCode Unique code of the target category within the tree
   *   (scoped to tree)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("treeCode")
    treeCode: string,
    @TypedParam("categoryCode")
    categoryCode: string,
  ): Promise<IShoppingCategory> {
    try {
      return await getShoppingCategoryTreesTreeCodeCategoriesCategoryCode({
        treeCode,
        categoryCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
