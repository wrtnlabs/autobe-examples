import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingGuestCartsGuestCartIdItems } from "../../../../providers/postShoppingGuestCartsGuestCartIdItems";
import { patchShoppingGuestCartsGuestCartIdItems } from "../../../../providers/patchShoppingGuestCartsGuestCartIdItems";
import { getShoppingGuestCartsGuestCartIdItemsItemId } from "../../../../providers/getShoppingGuestCartsGuestCartIdItemsItemId";
import { putShoppingGuestCartsGuestCartIdItemsItemId } from "../../../../providers/putShoppingGuestCartsGuestCartIdItemsItemId";
import { deleteShoppingGuestCartsGuestCartIdItemsItemId } from "../../../../providers/deleteShoppingGuestCartsGuestCartIdItemsItemId";

import { IShoppingGuestCartItem } from "../../../../api/structures/IShoppingGuestCartItem";

@Controller("/shopping/guestCarts/:guestCartId/items")
export class ShoppingGuestcartsItemsController {
  /**
   * Add an item (SKU) to an unauthenticated guest's cart session
   * (shopping_guest_cart_items).
   *
   * This operation allows guest (non-authenticated) users to add a specific SKU
   * item to their cart prior to registration or login. The endpoint expects the
   * target guest cart's unique identifier and the request body to specify the
   * SKU and quantity. The operation ensures that all business and inventory
   * validation is performed before appending or incrementing an item in the
   * cart.
   *
   * Security: This endpoint is strictly unauthenticated for temporary carts not
   * associated with customer accounts. Only the current session owner should be
   * able to add items to their own cart. Appropriate anti-CSRF and abuse
   * controls are recommended.
   *
   * The request is validated against the shopping_guest_cart_items data
   * structure and must reference a valid, active SKU available for purchase. If
   * the item/SKU is already present, the quantity is incremented in place
   * unless business rules specify otherwise (e.g., enforce a max per SKU per
   * cart). Stocks are not reserved at this stage but should be checked for
   * feasibility.
   *
   * Other operations in the guest cart domain include listing items,
   * updating/removing items, and merging to a customer cart at login. Error
   * handling must return clear validation messages for unavailable SKUs,
   * exceeded quantities, or invalid cart/session states.
   *
   * @param connection
   * @param guestCartId Unique identifier of the guest cart (session key or
   *   opaque ID for the guest cart; global scope)
   * @param body New item data specifying the SKU code and desired quantity to
   *   add to the guest cart.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedParam("guestCartId")
    guestCartId: string,
    @TypedBody()
    body: IShoppingGuestCartItem.ICreate,
  ): Promise<IShoppingGuestCartItem> {
    try {
      return await postShoppingGuestCartsGuestCartIdItems({
        guestCartId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the list of items in a guest shopping cart by guestCartId from
   * shopping_guest_cart_items table.
   *
   * Fetch and return all SKUs and their quantities contained within a guest
   * shopping cart, identified by the guestCartId in the path. This operation is
   * commonly used as part of guest-to-user cart migration (e.g., user logs in
   * and wants to merge guest cart with their authenticated user cart), or to
   * display the current contents of a guest cart for editing before checkout or
   * login.
   *
   * The operation queries the shopping_guest_cart_items table by the
   * guestCartId, joining on the shopping_skus for rich SKU details. For each
   * item, the response includes the skuId, quantity, and metadata about the
   * item (addedAt, updatedAt). The operation is read-only with no
   * authentication required; guests are not required to be logged in. The
   * results support a smooth bridge experience for users transitioning from
   * guest to registered customer by allowing extraction of cart items for merge
   * logic.
   *
   * Note: If the specified guestCartId does not exist, the operation returns an
   * empty list rather than error. No sensitive or user-specific information is
   * exposed by this endpoint beyond the items belonging to the provided
   * guestCartId.
   *
   * @param connection
   * @param guestCartId Unique identifier of the target guest cart (UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("guestCartId")
    guestCartId: string & tags.Format<"uuid">,
  ): Promise<IShoppingGuestCartItem.ISummary> {
    try {
      return await patchShoppingGuestCartsGuestCartIdItems({
        guestCartId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific item in a guest cart by cart and item ID
   * (shopping_guest_cart_items).
   *
   * This operation allows an unauthenticated (guest) user to retrieve detailed
   * information about a specific item in their session-linked shopping cart for
   * the current device/session. The item is uniquely identified by the cart and
   * item IDs, and the response includes the SKU, quantity, timestamps, and
   * related metadata.
   *
   * Security: No authentication or authorization is required, as this endpoint
   * is intended for temporary, session-based guest carts only. However, the
   * backend must ensure that only the current session owner can access the
   * referenced cart/item pair, typically validated using a secure session token
   * or cookie-based identifier.
   *
   * The operation is closely tied to the shopping_guest_cart_items entity in
   * the Prisma schema, which strictly ties each cart item to both the guest
   * cart and the target SKU. It does not permit direct manipulation or exposure
   * of personal information or customer carts.
   *
   * Business logic includes validation of the cart and item association,
   * ensuring the item exists, is not expired, and is not soft-deleted. Errors
   * should be handled with clear messages for missing or invalid items.
   *
   * Other endpoints in the guest cart domain include adding items (POST
   * /guestCarts/{guestCartId}/items), updating/removing items, and listing all
   * current guest cart items. This operation provides read-only introspection
   * for a single cart item to aid in pre-authenticated shopping workflows.
   *
   * @param connection
   * @param guestCartId Unique identifier of the guest cart (session or opaque
   *   key; global scope)
   * @param itemId Unique cart item identifier belonging to the target guest
   *   cart (scoped to guest cart)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @TypedParam("guestCartId")
    guestCartId: string,
    @TypedParam("itemId")
    itemId: string,
  ): Promise<IShoppingGuestCartItem> {
    try {
      return await getShoppingGuestCartsGuestCartIdItemsItemId({
        guestCartId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update quantity and details of an item in the guest cart.
   *
   * Update the quantity and details for a specific item within a guest's
   * shopping cart, identified by both the guest cart ID and the unique item ID
   * for the targeted SKU.
   *
   * This endpoint enables unauthenticated (guest) users to change the quantity
   * of a SKU they have previously added to their temporary cart, provided the
   * SKU remains available and in stock. The application enforces business logic
   * to ensure requested quantities do not exceed maximum limits and validates
   * current stock for the associated SKU. If the requested item does not exist
   * or is already removed from the cart, the operation will return a not found
   * error.
   *
   * All updates to cart item quantities are instantly reflected in the cart
   * state and will trigger a revalidation of business rules (e.g., per-SKU
   * limits, inventory checks). This operation is idempotent—repeated updates
   * with the same values do not create duplicates or additional cart entries.
   * Further, all updates are immediately persisted for the guest session and
   * will be merged into a user account cart if the guest logs in.
   *
   * @param connection
   * @param guestCartId Unique identifier for the guest cart session (global
   *   scope)
   * @param itemId Unique identifier of the target item (cart-SKU combination)
   *   within the guest cart (scoped to guest cart)
   * @param body New quantity and update information for the specified guest
   *   cart item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":itemId")
  public async update(
    @TypedParam("guestCartId")
    guestCartId: string,
    @TypedParam("itemId")
    itemId: string,
    @TypedBody()
    body: IShoppingGuestCartItem.IUpdate,
  ): Promise<IShoppingGuestCartItem> {
    try {
      return await putShoppingGuestCartsGuestCartIdItemsItemId({
        guestCartId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove an item from the guest cart.
   *
   * Remove a specific SKU/item from a guest's temporary shopping cart, using
   * both the guestCartId and itemId to ensure accurate targeting.
   *
   * This endpoint is used when a guest wishes to remove an unwanted or
   * unavailable SKU from their session-based cart prior to checkout or account
   * registration. The operation confirms that the specified cart and item
   * exist, enforcing data integrity and session security. It will not affect
   * other items in the cart, and if the specified item is not found, the system
   * will return a not found error or simply confirm no changes were necessary.
   *
   * The removal is immediate and irreversible within the guest session. All
   * removals will be reflected instantly in the cart summary and will be
   * accounted for if the cart is later merged into a registered user's account
   * upon login or sign-up. This endpoint helps ensure that cart expirations,
   * out-of-stock logic, and guest-to-user cart merging are implemented with
   * high accuracy.
   *
   * @param connection
   * @param guestCartId Unique identifier for the guest cart session (global
   *   scope)
   * @param itemId Unique identifier of the target item (cart-SKU combination)
   *   within the guest cart (scoped to guest cart)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":itemId")
  public async erase(
    @TypedParam("guestCartId")
    guestCartId: string,
    @TypedParam("itemId")
    itemId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingGuestCartsGuestCartIdItemsItemId({
        guestCartId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
