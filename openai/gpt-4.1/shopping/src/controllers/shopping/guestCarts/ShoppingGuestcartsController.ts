import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingGuestCartsGuestCartId } from "../../../providers/getShoppingGuestCartsGuestCartId";
import { putShoppingGuestCartsGuestCartId } from "../../../providers/putShoppingGuestCartsGuestCartId";
import { deleteShoppingGuestCartsGuestCartId } from "../../../providers/deleteShoppingGuestCartsGuestCartId";

import { IShoppingGuestCartItem } from "../../../api/structures/IShoppingGuestCartItem";

@Controller("/shopping/guestCarts/:guestCartId")
export class ShoppingGuestcartsController {
  /**
   * Retrieve guest cart by ID from shopping_guest_carts table.
   *
   * This endpoint allows retrieval of a guest shopping cart corresponding to
   * the given guestCartId. The primary use case is to allow session-based
   * (unauthenticated) users to see the current contents of their temporary
   * cart. The guest cart is identified by a session-keyed UUID and stores a
   * list of SKU IDs and their quantities. If the cart exists and is active, its
   * line items, expiration time, and details for all items will be returned. If
   * the guest cart has expired or the ID is not found, the response will be
   * null or a not-found error.
   *
   * Security: This is a public endpoint with no authentication required, but
   * session collision or brute-force enumeration is mitigated by requiring full
   * UUIDs and rate limiting per IP/device. Only guest-only carts (not
   * associated with logged-in accounts) can be fetched from this endpoint.
   *
   * This operation integrates with the shopping_guest_carts and
   * shopping_guest_cart_items tables (as described in the schema), as well as
   * shopping_skus for display of product info. No sensitive or personal user
   * data is returned; only SKU, quantity, and cart metadata is provided. It is
   * intended for temporary cart persistence before user registration or login.
   * Related operations include PUT on the same resource for updating cart
   * contents and POST /carts for merging after login.
   *
   * @param connection
   * @param guestCartId Unique identifier (UUID) for the guest cart session
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("guestCartId")
    guestCartId: string & tags.Format<"uuid">,
  ): Promise<IShoppingGuestCartItem> {
    try {
      return await getShoppingGuestCartsGuestCartId({
        guestCartId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update guest cart items and quantities by guestCartId in
   * shopping_guest_carts.
   *
   * This endpoint allows updating or replacing the cart items and their
   * quantities for a specific guest (session-based) cart identified by its
   * UUID. Clients can set the complete new list of SKU IDs and quantities in
   * the request body, and the backend will ensure the cart now matches the
   * provided structure. This is fundamental for managing session-based shopping
   * experiences for unauthenticated customers, enabling full cart modification
   * without requiring a user account.
   *
   * Security: Public access only; no personal user information exposed. The
   * endpoint is intended for unauthenticated (session/guest) shopping use
   * cases. Rate limiting and brute-force mitigation are recommended at the API
   * gateway or server for this operation. Carts associated with a logged-in
   * user or expired carts cannot be modified through this API. Validation will
   * ensure all referenced SKUs exist and quantity rules are enforced according
   * to business constraints.
   *
   * Table references: shopping_guest_carts (cart metadata such as timestamps
   * and session keys), shopping_guest_cart_items (line items for SKUs), and
   * shopping_skus (for product validation). Related operations: GET on the same
   * endpoint to fetch current cart state, POST /carts to merge guest cart on
   * login.
   *
   * @param connection
   * @param guestCartId Unique identifier (UUID) for the guest cart session
   *   (global scope)
   * @param body Complete set of cart items (SKU IDs and quantities) to set for
   *   the guest cart. Must reference valid SKUs and follow cart quantity
   *   business rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @TypedParam("guestCartId")
    guestCartId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingGuestCartItem.IUpdate,
  ): Promise<IShoppingGuestCartItem> {
    try {
      return await putShoppingGuestCartsGuestCartId({
        guestCartId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a guest shopping cart by its guestCartId from
   * shopping_guest_carts table.
   *
   * Delete a specific guest user's shopping cart from the system, using the
   * unique guestCartId provided in the path parameter. This operation is
   * intended to expire or remove temporary carts created for non-authenticated
   * users, either programmatically (e.g., after inactivity/expiry) or on
   * explicit user request (e.g., clear cart).
   *
   * Upon invocation, the operation deletes the guest cart from the
   * shopping_guest_carts table and all associated cart items from
   * shopping_guest_cart_items, as these are linked by the cart's id. This is a
   * hard delete, as there is no soft-deletion logic in the schema; once
   * deleted, the cart and its contents are permanently removed and cannot be
   * recovered by the user.
   *
   * No authentication is required: deletion of guest carts does not require an
   * authenticated actor, as the guestCartId is assumed to be possession-based
   * via session or cookie. Consumers should ensure guestCartId is securely
   * managed to prevent deletion of other users' carts. The endpoint is public
   * and access-controlled only by knowledge of the guestCartId value.
   *
   * If a non-existent guestCartId is provided, the operation is a no-op and
   * considered idempotent, returning success with no error if the cart does not
   * exist. If the cart exists but is already expired, it will be cleaned up and
   * associated items cleared. In all cases, no error is thrown for
   * missing/expired carts.
   *
   * No request or response body is used as this operation is path-driven and
   * has no payload; it simply executes the removal of one guest cart and its
   * item records. This helps ensure temporary/abandoned guest carts do not
   * persist indefinitely and allows for client-driven cleanup when carts are
   * merged on user login.
   *
   * @param connection
   * @param guestCartId Unique identifier of the target guest cart (UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @TypedParam("guestCartId")
    guestCartId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingGuestCartsGuestCartId({
        guestCartId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
