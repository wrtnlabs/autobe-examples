import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getShoppingCategoriesCategoryTreeCodeCategoryCode } from "../../../providers/getShoppingCategoriesCategoryTreeCodeCategoryCode";

import { IShoppingCategory } from "../../../api/structures/IShoppingCategory";

@Controller("/shopping/categories/:categoryTreeCode/:categoryCode")
export class ShoppingCategoriesController {
  /**
   * Retrieve details of a category node in a specific category tree by its
   * codes.
   *
   * This API operation provides full detail for a category node by resolving
   * both the category tree code and category code to the corresponding database
   * entities in shopping_category_trees and shopping_categories. The
   * categoryTreeCode parameter identifies the taxonomy root (e.g., 'main',
   * 'brand'), while the categoryCode identifies a unique node within that tree
   * (guaranteed unique per tree by the composite unique constraint in the
   * schema).
   *
   * Returned fields may include category name, code, hierarchy info, parent
   * relationship, display order, and optional description, matching those from
   * the shopping_categories schema. The operation is suitable for constructing
   * frontend navigation, displaying information about specific filters, or
   * preparing edit interfaces for admins.
   *
   * Security considerations: This operation is generally public, as category
   * trees and nodes need to be readable by all users for catalog display and
   * browsing; thus, the authorizationActors array is empty, indicating no
   * authentication is required for this read-only query. Error handling
   * includes responding with a clear not-found error if the category tree or
   * node is missing or has been soft-deleted.
   *
   * @param connection
   * @param categoryTreeCode Code uniquely identifying the category tree
   *   (taxonomy) (global scope). Only valid tree codes as defined in
   *   shopping_category_trees may be used.
   * @param categoryCode Code uniquely identifying the category node within the
   *   specified category tree (scoped to category tree). Composite unique
   *   constraint in shopping_categories ensures uniqueness per tree.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("categoryTreeCode")
    categoryTreeCode: string,
    @TypedParam("categoryCode")
    categoryCode: string,
  ): Promise<IShoppingCategory> {
    try {
      return await getShoppingCategoriesCategoryTreeCodeCategoryCode({
        categoryTreeCode,
        categoryCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
