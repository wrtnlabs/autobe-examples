import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminCarts } from "../../../../providers/patchShoppingMallAdminCarts";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCartsCartId } from "../../../../providers/getShoppingMallAdminCartsCartId";

import { IPageIShoppingMallCart } from "../../../../api/structures/IPageIShoppingMallCart";
import { IShoppingMallCart } from "../../../../api/structures/IShoppingMallCart";

@Controller("/shoppingMall/admin/carts")
export class ShoppingmallAdminCartsController {
  /**
   * Retrieve a filtered and paginated list of shopping cart records for all
   * customers across the platform.
   *
   * This operation allows platform admins to audit and analyze the state of all
   * customer shopping carts. The results can be filtered or sorted by customer,
   * creation date, recent update, or linked customer status, facilitating both
   * system maintenance and operational analytics.
   *
   * The operation covers validation for unique cart association per customer
   * (as enforced by the Prisma schema) and supports review of abandoned,
   * active, or recently checked-out carts. Data returned is suitable for
   * administrative dashboards, platform health checks, and compliance audits.
   * Security restrictions limit access to administrative actors only, ensuring
   * no unauthorized or customer-level user can access cart data for other
   * accounts.
   *
   * @param connection
   * @param body Search, filter, and pagination parameters for administrative
   *   shopping cart queries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCart.IRequest,
  ): Promise<IPageIShoppingMallCart.ISummary> {
    try {
      return await patchShoppingMallAdminCarts({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific customer shopping cart by
   * its unique identifier.
   *
   * This operation provides all cart metadata—including owner customer
   * reference, creation and update timestamps, and links to associated
   * subsidiary items. It is used by administrators to resolve support cases,
   * review suspicious or problematic cart activity, and maintain platform
   * integrity.
   *
   * Security restrictions apply to ensure only platform administrators can
   * access this endpoint. Carts may only be referenced by those with
   * administrative privileges; all other users must access their own carts
   * through alternate self-service flows.
   *
   * @param connection
   * @param cartId Unique identifier of the target shopping cart.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":cartId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCart> {
    try {
      return await getShoppingMallAdminCartsCartId({
        admin,
        cartId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
