import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallAdminShippingPartners } from "../../../../providers/postShoppingMallAdminShippingPartners";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminShippingPartners } from "../../../../providers/patchShoppingMallAdminShippingPartners";
import { getShoppingMallAdminShippingPartnersPartnerCode } from "../../../../providers/getShoppingMallAdminShippingPartnersPartnerCode";
import { putShoppingMallAdminShippingPartnersPartnerCode } from "../../../../providers/putShoppingMallAdminShippingPartnersPartnerCode";
import { deleteShoppingMallAdminShippingPartnersPartnerCode } from "../../../../providers/deleteShoppingMallAdminShippingPartnersPartnerCode";

import { IShoppingMallShippingPartner } from "../../../../api/structures/IShoppingMallShippingPartner";
import { IPageIShoppingMallShippingPartner } from "../../../../api/structures/IPageIShoppingMallShippingPartner";

@Controller("/shoppingMall/admin/shippingPartners")
export class ShoppingmallAdminShippingpartnersController {
  /**
   * Create a new shipping partner (shopping_mall_shipping_partners) record.
   *
   * Create a new entry for an official platform shipping or logistics partner
   * available for use in buyer and seller order flows on the shopping mall.
   *
   * Upon execution, admins can register third-party logistics companies who are
   * then available for all shipment, order, and tracking features via
   * foreign-key references throughout the order-shipping domain. This operation
   * requires unique values for both the partner_name (display UI/reference
   * name) and partner_code (system integration code).
   *
   * Additional business rules enforced include admin-only access, status
   * validation, and automatic population of audit fields for creation timestamp
   * and subsequent updates. Soft-delete functionality is supported for legacy
   * or deprecated partners (not through this operation, but in lifecycle
   * management). Proper validation occurs to prevent duplicate registrations of
   * code or name. Related operations include updating existing partners and
   * deprecating those no longer in service.
   *
   * @param connection
   * @param body Information required to create a new shipping/logistics partner
   *   for use in the shopping mall platform, including display name,
   *   integration code, status, and description.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallShippingPartner.ICreate,
  ): Promise<IShoppingMallShippingPartner> {
    try {
      return await postShoppingMallAdminShippingPartners({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search, filter, and list all shipping partners in the platform registry
   * (shopping_mall_shipping_partners).
   *
   * Retrieve a filtered and paginated list of logistics/shipping partners
   * currently registered on the platform for use in buyer and seller flows.
   *
   * Each shipping partner record provides rich descriptive details including
   * display name, integration code, operational status, and business notes, as
   * defined in the Prisma schema. Administrators and business users can use
   * this API to discover currently available, inactive, or deprecated partners
   * for operational planning or integration management.
   *
   * Security for this endpoint should restrict direct modification access and
   * ensure filtered read access only exposes non-sensitive audit trail fields.
   * Bulk retrieval of historical or inactive entries is supported for
   * compliance and audit review. All filtering options and keyword fields match
   * the schema fields (partner_name, partner_code, status, description). This
   * endpoint enables automated selection in shipment workflows and helps with
   * deprecating or activating shipping partners efficiently.
   *
   * @param connection
   * @param body Search and pagination criteria for filtering, sorting, and
   *   querying shipping partners.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallShippingPartner.IRequest,
  ): Promise<IPageIShoppingMallShippingPartner.ISummary> {
    try {
      return await patchShoppingMallAdminShippingPartners({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve all details of a single shipping partner from
   * shopping_mall_shipping_partners by its unique integration code.
   *
   * Fetch all descriptive and operational fields for a specific
   * logistics/shipping partner identified by its unique integration code.
   * Reference the Prisma schema for all available partner-related data fields,
   * including status, business description, and audit fields.
   *
   * Security policies will typically restrict this endpoint to platform
   * administrators or privileged actors. Returned data enables configuration,
   * audit, and system-level integration management. Lookups that do not match
   * any active or inactive record trigger a not-found error response.
   *
   * This endpoint enables admins and platform managers to view historical,
   * active, or deprecated shipping partner records by their integration code.
   * Related endpoints include the list/search operation (PATCH
   * /shippingPartners) and admin CRUD endpoints for partner management.
   *
   * @param connection
   * @param partnerCode Unique integration code (partner_code) for the shipping
   *   partner as defined in shopping_mall_shipping_partners (global scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":partnerCode")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("partnerCode")
    partnerCode: string,
  ): Promise<IShoppingMallShippingPartner> {
    try {
      return await getShoppingMallAdminShippingPartnersPartnerCode({
        admin,
        partnerCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the information on a shipping partner
   * (shopping_mall_shipping_partners) by its code.
   *
   * Update the registration details of a previously onboarded
   * shipping/logistics partner on the shopping mall platform by specifying its
   * unique partner_code.
   *
   * Through this operation, administrative users can update key information
   * such as the partner's display name, backend integration code, operational
   * status, and business description. Uniqueness constraints are rigorously
   * validated to avoid code or name conflicts with other registered partners.
   *
   * Security is maintained through admin-only access, and audit logging
   * captures any modifications for later review. The updated_at audit field is
   * refreshed on each modification. This endpoint only supports updating the
   * information of an existing partner, not creating or deleting partners.
   *
   * @param connection
   * @param partnerCode Unique integration code (partner_code) of the shipping
   *   partner to update (global scope).
   * @param body New information for the target shipping partner, including
   *   display name, code, status, and description fields. Must satisfy
   *   uniqueness constraints within the shopping_mall_shipping_partners table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":partnerCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("partnerCode")
    partnerCode: string,
    @TypedBody()
    body: IShoppingMallShippingPartner.IUpdate,
  ): Promise<IShoppingMallShippingPartner> {
    try {
      return await putShoppingMallAdminShippingPartnersPartnerCode({
        admin,
        partnerCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a shipping partner by partnerCode (hard delete) from
   * shopping_mall_shipping_partners table.
   *
   * Remove an existing shipping partner from the platform's official registry
   * by permanently and irreversibly deleting their record based on the unique
   * partnerCode. This API is restricted to administrative users and is used
   * when a logistics/shipping partner must no longer be available for use in
   * the system (for example, when a partnership is terminated or the partner
   * ceases business operations).
   *
   * All foreign key references are expected to be validated by business logic
   * prior to deletion (i.e., active shipments or orders using the partner
   * should be handled in advance). The operation does not perform a soft-delete
   * but applies a hard delete, permanently removing the record from the
   * database. Historical/inactive partner information that needs to be
   * preserved for audit or referencing legacy data should be retained elsewhere
   * if necessary, as this endpoint is meant for absolute removal.
   *
   * This operation requires strict permission controls and comprehensive
   * logging of the action performed. A successful deletion removes the partner
   * entirely, while any failure (e.g., missing or invalid partnerCode,
   * insufficient admin permissions, foreign key constraints) should return a
   * descriptive error.
   *
   * @param connection
   * @param partnerCode Globally unique integration code for the target shipping
   *   partner, used for backend/system-level identification (unique
   *   constraint).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":partnerCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("partnerCode")
    partnerCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminShippingPartnersPartnerCode({
        admin,
        partnerCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
