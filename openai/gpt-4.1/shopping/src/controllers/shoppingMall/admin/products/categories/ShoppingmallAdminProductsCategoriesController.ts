import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminProductsProductIdCategories } from "../../../../../providers/postShoppingMallAdminProductsProductIdCategories";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminProductsProductIdCategories } from "../../../../../providers/patchShoppingMallAdminProductsProductIdCategories";
import { deleteShoppingMallAdminProductsProductIdCategoriesProductCategoryId } from "../../../../../providers/deleteShoppingMallAdminProductsProductIdCategoriesProductCategoryId";

import { IShoppingMallProductsCategory } from "../../../../../api/structures/IShoppingMallProductsCategory";
import { IPageIShoppingMallProductsCategory } from "../../../../../api/structures/IPageIShoppingMallProductsCategory";

@Controller("/shoppingMall/admin/products/:productId/categories")
export class ShoppingmallAdminProductsCategoriesController {
  /**
   * Add a new category mapping to a product
   * (shopping_mall_products_categories).
   *
   * Assign a new category to a specific product in the shopping mall catalog by
   * adding a category mapping. This operation is used to enhance a product's
   * discoverability by associating it with an additional browsing category,
   * supporting improved navigation, search, and business-driven merchandising
   * placements.
   *
   * The productId path parameter uniquely identifies the product to update,
   * while the request body provides the category to be assigned. Validation
   * includes verifying the existence of both the product and the category, as
   * well as ensuring the mapping does not already exist to prevent duplicates.
   * Only authorized sellers (owners of the product) or platform administrators
   * may perform this action.
   *
   * Upon successful assignment, the new mapping will be reflected in category
   * navigation and search APIs. Any violation of uniqueness constraints or
   * authorization will result in informative API errors describing the cause
   * and remediation steps.
   *
   * @param connection
   * @param productId Unique identifier of the target product in the catalog
   *   (UUID).
   * @param body Detailed information identifying the category to be assigned to
   *   the specified product, following creation rules for the mapping.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductsCategory.ICreate,
  ): Promise<IShoppingMallProductsCategory> {
    try {
      return await postShoppingMallAdminProductsProductIdCategories({
        admin,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve and search product category assignments for a specific product
   * (shopping_mall_products_categories).
   *
   * Retrieve a paginated and filterable list of all category assignments that
   * currently apply to a specified product in the shopping mall's product
   * catalog.
   *
   * This operation enables authorized users to view all categories to which a
   * product is assigned, facilitating catalog management, quality control, and
   * product discoverability optimization. The response includes concise
   * metadata about each mapping, such as the mapping's creation date and
   * assigned category reference, allowing for easy tracking and navigation.
   *
   * Path parameter validation enforces the product's existence before
   * attempting to query category assignments, and proper error handling will
   * notify clients if the product does not exist or if the requesting actor
   * lacks sufficient permission. The operation is directly related to the
   * 'shopping_mall_products_categories' table and exposes only necessary
   * information for listing and search purposes, not for direct editing, which
   * should occur through related POST or DELETE endpoints.
   *
   * @param connection
   * @param productId Unique identifier of the target product in the catalog
   *   (UUID).
   * @param body Filtering, pagination, and search parameters for retrieving
   *   category assignments for a product.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductsCategory.IRequest,
  ): Promise<IPageIShoppingMallProductsCategory.ISummary> {
    try {
      return await patchShoppingMallAdminProductsProductIdCategories({
        admin,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a product-category mapping from shopping_mall_products_categories
   * table by ID.
   *
   * Remove a specific mapping between a product and a category in the shopping
   * mall catalog.
   *
   * This endpoint permanently deletes the product-category association,
   * ensuring the product is no longer listed under that category but remains
   * available in others if multiple mappings exist.
   *
   * Security requires the requestor to be either the product's owning seller or
   * an administrator, with backend validation against the mapping's existence
   * and ownership. Attempts to remove a mapping that does not exist, is not
   * owned by the requestor, or is required by business constraints result in
   * explicit error responses.
   *
   * The operation directly manipulates the shopping_mall_products_categories
   * table, using both product ID and mapping ID for precise targeting.
   * Downstream catalog views, filtering, and associated caches are updated
   * automatically upon successful removal. This operation does not affect the
   * product or category entities themselves, only the association row.
   *
   * @param connection
   * @param productId Unique identifier of the target product.
   * @param productCategoryId Unique identifier of the product-category mapping
   *   row to be deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productCategoryId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("productCategoryId")
    productCategoryId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminProductsProductIdCategoriesProductCategoryId(
        {
          admin,
          productId,
          productCategoryId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
