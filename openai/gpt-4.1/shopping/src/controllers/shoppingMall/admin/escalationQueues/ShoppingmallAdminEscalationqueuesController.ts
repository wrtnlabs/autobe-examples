import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminEscalationQueues } from "../../../../providers/postShoppingMallAdminEscalationQueues";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminEscalationQueues } from "../../../../providers/patchShoppingMallAdminEscalationQueues";
import { getShoppingMallAdminEscalationQueuesId } from "../../../../providers/getShoppingMallAdminEscalationQueuesId";
import { putShoppingMallAdminEscalationQueuesId } from "../../../../providers/putShoppingMallAdminEscalationQueuesId";
