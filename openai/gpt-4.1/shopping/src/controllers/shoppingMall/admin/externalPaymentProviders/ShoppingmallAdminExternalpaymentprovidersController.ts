import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallAdminExternalPaymentProviders } from "../../../../providers/postShoppingMallAdminExternalPaymentProviders";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminExternalPaymentProviders } from "../../../../providers/patchShoppingMallAdminExternalPaymentProviders";
import { putShoppingMallAdminExternalPaymentProvidersProviderCode } from "../../../../providers/putShoppingMallAdminExternalPaymentProvidersProviderCode";
import { deleteShoppingMallAdminExternalPaymentProvidersProviderCode } from "../../../../providers/deleteShoppingMallAdminExternalPaymentProvidersProviderCode";

import { IShoppingMallExternalPaymentProvider } from "../../../../api/structures/IShoppingMallExternalPaymentProvider";
import { IPageIShoppingMallExternalPaymentProvider } from "../../../../api/structures/IPageIShoppingMallExternalPaymentProvider";

@Controller("/shoppingMall/admin/externalPaymentProviders")
export class ShoppingmallAdminExternalpaymentprovidersController {
  /**
   * Admin-only operation to register a new external payment provider into the
   * registry table 'shopping_mall_external_payment_providers'. All core
   * metadata must be supplied, including provider_name, provider_code, status,
   * and a business/integration description. The operation ensures unique
   * constraints are enforced and captures audit timestamps.
   *
   * This enables the admin to introduce support for new payment platforms such
   * as Stripe, Toss, or PayPal, which can then be selected for orders and
   * payment orchestration. Only authorized admin users can invoke this
   * endpoint, and all writes are tracked for compliance. Duplicate errors are
   * returned if provider_name or provider_code has already been registered.
   *
   * Successful creation returns the full metadata for the external payment
   * provider, which can be used by further management or configuration
   * endpoints. This endpoint is for governance and platform setup, not for
   * end-user use.
   *
   * @param connection
   * @param body Complete metadata required to register a new external payment
   *   provider. Must include display name, integration provider_code, status
   *   (active/inactive/deprecated), and description. Uniqueness of
   *   provider_name and provider_code is enforced as per Prisma schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallExternalPaymentProvider.ICreate,
  ): Promise<IShoppingMallExternalPaymentProvider> {
    try {
      return await postShoppingMallAdminExternalPaymentProviders({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of registered external payment providers,
   * supporting filtering by provider name, integration code, status
   * (active/inactive/deprecated), and business context.
   *
   * This operation is intended for both administrative configuration dashboards
   * and platform features that expose available payment options to users. It
   * supports advanced query, sort, and search features via
   * IShoppingMallExternalPaymentProvider.IRequest, including keyword and field
   * filters.
   *
   * The response is a paginated set of payment provider summaries, showing
   * status, display names, integration codes, and additional business notes.
   * Security and business context are enforced at the provider service layer.
   * Only necessary fields are exposed in summaries to protect sensitive
   * integration data.
   *
   * @param connection
   * @param body Filtering, search, and pagination options for retrieving
   *   external payment providers.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallExternalPaymentProvider.IRequest,
  ): Promise<IPageIShoppingMallExternalPaymentProvider.ISummary> {
    try {
      return await patchShoppingMallAdminExternalPaymentProviders({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing external payment provider's configuration and metadata
   * for the shopping mall platform.
   *
   * This operation allows an admin to modify the data for a payment gateway or
   * platform, such as changing its display name, updating backend integration
   * codes, toggling its status between active, inactive, or deprecated, and
   * adjusting business/legal context documentation. The update is performed
   * securely using the unique `providerCode`, which identifies the target
   * provider in the Prisma table and is unique across all registered payment
   * providers.
   *
   * Only platform administrators are authorized to use this endpoint, ensuring
   * configuration changes are controlled and auditable. The operation will
   * update the modification tracking fields (`updated_at`) and ensure that
   * integrity is maintained throughout the system. If the provider is currently
   * referenced by live orders or payments, system validation ensures that only
   * non-breaking updates are allowed, according to business rules.
   *
   * Related endpoints include the search/list API for providers, details
   * retrieval by provider code, and provider creation/deprecation operations.
   * Audit logging of all modifications is expected for compliance and change
   * control.
   *
   * @param connection
   * @param providerCode System integration key/code—unique backend identifier
   *   for the external payment provider (global scope).
   * @param body Updated configuration and metadata values for the external
   *   payment provider. Follows the ShoppingMallExternalPaymentProvider.IUpdate
   *   structure; the target code is passed as a path parameter, so is not
   *   included in the body.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":providerCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("providerCode")
    providerCode: string,
    @TypedBody()
    body: IShoppingMallExternalPaymentProvider.IUpdate,
  ): Promise<IShoppingMallExternalPaymentProvider> {
    try {
      return await putShoppingMallAdminExternalPaymentProvidersProviderCode({
        admin,
        providerCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently deactivate (soft delete) a registered external payment provider
   * in the shopping mall system.
   *
   * This operation enables an admin to logically remove a payment provider from
   * active commerce flows, setting its `deleted_at` field to the current
   * timestamp, without physical removal of the row in the database. By using
   * the unique `providerCode` path parameter, the system identifies the target
   * provider according to the unique constraint set in the Prisma table
   * (`provider_code`).
   *
   * This action is only allowed for administrator users and is audit-logged for
   * compliance and platform governance. Previously processed orders and
   * historical payments linked to the provider remain valid, and the provider
   * stays available for audit purposes. Once soft-deleted, the provider can no
   * longer be selected for new transactions or configuration changes, ensuring
   * business rule integrity and regulatory compliance.
   *
   * @param connection
   * @param providerCode System integration key/code—unique backend identifier
   *   for the external payment provider (global scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":providerCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("providerCode")
    providerCode: string,
  ): Promise<IShoppingMallExternalPaymentProvider> {
    try {
      return await deleteShoppingMallAdminExternalPaymentProvidersProviderCode({
        admin,
        providerCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
