import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminSellers } from "../../../../providers/patchShoppingMallAdminSellers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminSellersSellerId } from "../../../../providers/getShoppingMallAdminSellersSellerId";
import { putShoppingMallAdminSellersSellerId } from "../../../../providers/putShoppingMallAdminSellersSellerId";
import { deleteShoppingMallAdminSellersSellerId } from "../../../../providers/deleteShoppingMallAdminSellersSellerId";

import { IPageIShoppingMallSeller } from "../../../../api/structures/IPageIShoppingMallSeller";
import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";

@Controller("/shoppingMall/admin/sellers")
export class ShoppingmallAdminSellersController {
  /**
   * Paginated, filtered search and listing of sellers from
   * shopping_mall_sellers.
   *
   * Retrieve a filtered and paginated list of registered sellers from the
   * platform database.
   *
   * This operation enables administrators to search and view sellers using
   * flexible criteria, including search by business name (with partial match
   * support), email, registration number, and account status (pending,
   * approved, rejected, suspended). The request body allows combining multiple
   * filters for precise control, and supports sorting and pagination to
   * efficiently manage large sets of results.
   *
   * Authorization is restricted: only admin actors can access this endpoint to
   * ensure information is kept secure and consistent with role-based access
   * policy.
   *
   * This operation directly reflects the shopping_mall_sellers Prisma model,
   * incorporating all corresponding fields and unique constraints. Its design
   * aligns with platform admin dashboard workflows where oversight and quick
   * access to seller information is critical. Related endpoints for single
   * seller detail and status change actions can be combined for full lifecycle
   * management.
   *
   * @param connection
   * @param body Search filters, pagination, and sorting options for querying
   *   registered sellers.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSeller.IRequest,
  ): Promise<IPageIShoppingMallSeller.ISummary> {
    try {
      return await patchShoppingMallAdminSellers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve full business and registration details for a specified seller
   * (shopping_mall_sellers).
   *
   * Retrieve complete details about a single seller account specified by unique
   * sellerId.
   *
   * This operation gives platform administrators access to all non-sensitive
   * fields for the seller, as recorded in the shopping_mall_sellers database
   * entity. The admin can use this information for compliance verification,
   * registration review, troubleshooting, or support actions. Seller data
   * returned includes business identity, contact information,
   * registration/licensing, verification state, and last modification
   * timestamps.
   *
   * Endpoint authorization is restricted to admin actors, ensuring only
   * platform operators can access this data for moderation and oversight. The
   * endpoint uses a path parameter "sellerId" with UUID format matching the
   * primary key field on the shopping_mall_sellers schema. Proper error
   * handling ensures requests for non-existent sellerIds are gracefully
   * reported as 'Not Found.'
   *
   * This is a central admin function, often linked to workflows for reviewing
   * seller approval, changing status, or viewing associated records (products,
   * orders, audits, etc.).
   *
   * @param connection
   * @param sellerId Unique identifier for the seller in UUID format, as stored
   *   in the shopping_mall_sellers table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSeller> {
    try {
      return await getShoppingMallAdminSellersSellerId({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shopping mall seller account ('shopping_mall_sellers'
   * table).
   *
   * Update details for a registered seller account in the shopping mall system.
   *
   * This operation allows authorized actors to modify mutable fields of a
   * seller, such as business contact information, email, phone number, business
   * name, and compliance-related statuses. It strictly prohibits any
   * modification of primary keys or irreversible compliance history,
   * referencing the 'shopping_mall_sellers' Prisma model to guarantee property
   * consistency and application of business rules.
   *
   * Security: This endpoint should be restricted to operation by system
   * administrators or Trusted Platform processes enforcing identity assurance
   * and proper business workflows. All modifications are logged with a
   * timestamp in 'updated_at', and attempts to violate unique constraints or
   * unauthorized changes will result in validation errors or rejection. The
   * operation guarantees data integrity and regulatory compliance for all legal
   * business transactions on the platform.
   *
   * Related operations include viewing seller accounts, onboarding new sellers,
   * or suspending sellers (beyond the scope of this endpoint). Error handling
   * covers invalid IDs, unauthorized modification attempts, and failed
   * validation for business uniqueness constraints.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account (UUID).
   * @param body Fields to update for the specified seller account, following
   *   Prisma schema property types and update conventions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sellerId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSeller.IUpdate,
  ): Promise<IShoppingMallSeller> {
    try {
      return await putShoppingMallAdminSellersSellerId({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a shopping mall seller account ('shopping_mall_sellers'
   * table).
   *
   * Permanently remove a seller account from the shopping mall platform.
   *
   * This operation enables authorized administrators to erase a seller’s
   * record, including all business information managed in the
   * 'shopping_mall_sellers' table. Erased entities cannot be recovered, and
   * this action is subject to validation checks for dependencies and regulatory
   * requirements. All deletions are logged for audit purposes in system audit
   * logs separate from business entities. Unauthorized or invalid attempts will
   * result in descriptive errors. The 'erase' operation is strictly for
   * governance—typical seller deactivation/suspension should employ other APIs
   * that change the seller status rather than deleting the record entirely.
   *
   * Security: Only platform admins or root governance actors can perform this
   * operation. The system validates the nonexistence of dependent business
   * records or legal holds before permitting deletion. Deletion cascades or
   * prevents based on database relationships, applying all validation and
   * enforcement via the Prisma schema.
   *
   * This endpoint serves as a final, irreversible deletion of legal business
   * identity from the platform.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account (UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sellerId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminSellersSellerId({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
