import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminSellersSellerIdVerifications } from "../../../../../providers/patchShoppingMallAdminSellersSellerIdVerifications";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminSellersSellerIdVerificationsVerificationId } from "../../../../../providers/getShoppingMallAdminSellersSellerIdVerificationsVerificationId";
import { putShoppingMallAdminSellersSellerIdVerificationsVerificationId } from "../../../../../providers/putShoppingMallAdminSellersSellerIdVerificationsVerificationId";

import { IPageIShoppingMallSellerVerification } from "../../../../../api/structures/IPageIShoppingMallSellerVerification";
import { IShoppingMallSellerVerification } from "../../../../../api/structures/IShoppingMallSellerVerification";

@Controller("/shoppingMall/admin/sellers/:sellerId/verifications")
export class ShoppingmallAdminSellersVerificationsController {
  /**
   * Retrieve a paginated, filtered list of business verification records
   * associated with a seller.
   *
   * This API operation enables authenticated sellers or administrative actors
   * to search and review the full verification history for a seller account.
   * Typical use cases include: checking the status of current KYC requests,
   * auditing prior compliance submission attempts, and tracking any rejections
   * or requests for more information. Filters provided in the request body
   * allow querying by verification status, date ranges, or reviewer/admin
   * information.
   *
   * Response fields follow summary conventions, ensuring the response is
   * lightweight but sufficiently informative for common dashboard or business
   * workflow scenarios. Security controls ensure that sellers may only query
   * their own records, while admins have platform-wide visibility. Related
   * endpoints include creating a new verification request (handled elsewhere)
   * and detailed verification record retrieval.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller whose verification records
   *   are being queried.
   * @param body Search filters and pagination options for retrieving
   *   verification records (status, date, admin, etc.).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSellerVerification.IRequest,
  ): Promise<IPageIShoppingMallSellerVerification.ISummary> {
    try {
      return await patchShoppingMallAdminSellersSellerIdVerifications({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific seller verification record
   * associated with a given seller.
   *
   * This API operation is critical for supporting KYC, business onboarding, and
   * compliance review flows. It provides all relevant data for a verification
   * submission, such as status, submitted documents, reviewer admin identity,
   * examination notes, timestamps, and workflow state as captured in the
   * shopping_mall_seller_verifications table. The design supports audit and
   * regulatory workflows, as well as business process requirements for seller
   * onboarding on the platform.
   *
   * Actors must supply both a valid sellerId and verificationId, as
   * verifications are strictly linked to sellers. Security checks ensure the
   * requesting actor has permission to access this record—sellers can only view
   * their own, while admins can access any verification. The response enables
   * full audit traceability and downstream compliance logic for KYC and
   * onboarding. Related API operations include list/search endpoints for seller
   * verifications and update/decision endpoints for compliance officers.
   *
   * The expected behavior is to return all columns as described in the schema,
   * and to return a not found error if the seller or verification does not
   * exist or are mismatched. Errors are handled with appropriate status codes
   * and clear error messages for clients.
   *
   * @param connection
   * @param sellerId Unique identifier (UUID) of the target seller whose
   *   verification is being requested. (References shopping_mall_sellers.id,
   *   global scope).
   * @param verificationId Unique identifier (UUID) of the specific seller
   *   verification record being requested. (References
   *   shopping_mall_seller_verifications.id, scoped to seller).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":verificationId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("verificationId")
    verificationId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerVerification> {
    try {
      return await getShoppingMallAdminSellersSellerIdVerificationsVerificationId(
        {
          admin,
          sellerId,
          verificationId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a business verification record for a specific seller, such as
   * approving, rejecting, or annotating a submitted verification. This
   * operation is strongly controlled: only platform admins can call this
   * endpoint, and all status or field changes are audited for regulatory
   * compliance.
   *
   * The request body follows the IShoppingMallSellerVerification.IUpdate DTO
   * schema and may include status changes, admin notes, compliance document
   * links, or changes to reviewer assignment. Validation enforces business
   * rules as specified in the Prisma schema and requirements documents.
   * Security checks ensure the caller is a platform admin, that the seller and
   * verification record exist and are correctly associated, and that only
   * allowed updates are submitted.
   *
   * Recommended workflow: admins may review pending verifications, update
   * status and reviewer ID, add notes, or append compliance artifact links.
   * Each update is recorded for append-only audit tracking. Errors for not
   * found, forbidden changes, or invalid request formats are handled with
   * standard error codes and messages. Downstream effects may include
   * notification triggers or state transitions for onboarding flows.
   *
   * @param connection
   * @param sellerId Unique identifier (UUID) of the seller to whom this
   *   verification record belongs. (References shopping_mall_sellers.id, global
   *   scope).
   * @param verificationId Unique identifier (UUID) of the verification record
   *   being updated. (References shopping_mall_seller_verifications.id, scoped
   *   to seller).
   * @param body Fields and changes to apply to the seller verification record
   *   (DTO: IShoppingMallSellerVerification.IUpdate).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":verificationId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("verificationId")
    verificationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSellerVerification.IUpdate,
  ): Promise<IShoppingMallSellerVerification> {
    try {
      return await putShoppingMallAdminSellersSellerIdVerificationsVerificationId(
        {
          admin,
          sellerId,
          verificationId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
