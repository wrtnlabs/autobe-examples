import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminSellersSellerIdSessions } from "../../../../../providers/patchShoppingMallAdminSellersSellerIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminSellersSellerIdSessionsSessionId } from "../../../../../providers/getShoppingMallAdminSellersSellerIdSessionsSessionId";

import { IPageIShoppingMallSellerSession } from "../../../../../api/structures/IPageIShoppingMallSellerSession";
import { IShoppingMallSellerSession } from "../../../../../api/structures/IShoppingMallSellerSession";

@Controller("/shoppingMall/admin/sellers/:sellerId/sessions")
export class ShoppingmallAdminSellersSessionsController {
  /**
   * List all seller session records for a given seller
   * (shopping_mall_seller_sessions).
   *
   * Retrieve a paginated, filterable list of session records belonging to a
   * specific seller account.
   *
   * This endpoint enables sellers or administrators to view recent and
   * historical login session activity for the specified seller, useful for
   * auditing access, device and browser usage patterns, and security reviews.
   * Each session includes creation time, potential expiration, IP address,
   * referrer information, and links to the seller it belongs to.
   *
   * Security is critical: Only the seller themselves or administrative actor(s)
   * may list sessions for an account, as these may contain sensitive device,
   * IP, and login metadata. Search parameters allow for filtering by login time
   * range, expiration state, or IP/network. The endpoint leverages the
   * subsidiary relationship of sessions to sellers as defined in the Prisma
   * schema, and always expects a valid sellerId as a required path parameter.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller. This must be the
   *   primary key UUID field from shopping_mall_sellers (global scope).
   * @param body Filter, search, and pagination parameters for seller session
   *   records, supporting time range and IP filtering.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSellerSession.IRequest,
  ): Promise<IPageIShoppingMallSellerSession.ISummary> {
    try {
      return await patchShoppingMallAdminSellersSellerIdSessions({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details for a specific seller session
   * (shopping_mall_seller_sessions).
   *
   * Retrieve the complete details for a specific authenticated session record
   * for a given seller.
   *
   * This endpoint allows sellers or administrative actors to view in-depth
   * information on a single session event, including login source, IP, referrer
   * details, creation and expiry timestamps, and other audit-trail relevant
   * metadata.
   *
   * The session record is always contextualized to the owner seller, scoped by
   * the sellerId primary key, and must reference a sessionId corresponding to
   * shopping_mall_seller_sessions. Only the relevant seller or an admin may
   * access these details for purposes including monitoring suspicious activity,
   * tracking unauthorized logins, or reviewing access history. Proper
   * authorization checks are enforced at the business logic layer, and access
   * is denied if session/seller linkage is invalid or the actor lacks
   * permission.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller. This must be the
   *   primary key UUID field from shopping_mall_sellers (global scope).
   * @param sessionId Unique identifier for the session record belonging to the
   *   seller. This is the primary key UUID field from
   *   shopping_mall_seller_sessions (scoped to the specified seller).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerSession> {
    try {
      return await getShoppingMallAdminSellersSellerIdSessionsSessionId({
        admin,
        sellerId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
