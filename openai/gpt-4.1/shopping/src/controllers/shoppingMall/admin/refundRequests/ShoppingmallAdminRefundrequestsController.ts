import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminRefundRequests } from "../../../../providers/patchShoppingMallAdminRefundRequests";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminRefundRequestsRefundRequestId } from "../../../../providers/getShoppingMallAdminRefundRequestsRefundRequestId";
import { putShoppingMallAdminRefundRequestsRefundRequestId } from "../../../../providers/putShoppingMallAdminRefundRequestsRefundRequestId";
import { deleteShoppingMallAdminRefundRequestsRefundRequestId } from "../../../../providers/deleteShoppingMallAdminRefundRequestsRefundRequestId";

import { IPageIShoppingMallRefundRequest } from "../../../../api/structures/IPageIShoppingMallRefundRequest";
import { IShoppingMallRefundRequest } from "../../../../api/structures/IShoppingMallRefundRequest";

@Controller("/shoppingMall/admin/refundRequests")
export class ShoppingmallAdminRefundrequestsController {
  /**
   * Search and paginate refund requests in shopping_mall_refund_requests with
   * advanced filters.
   *
   * Searches, filters, and returns a paginated list of refund requests from
   * shopping_mall_refund_requests, supporting advanced workflow and compliance
   * review.
   *
   * This operation enables robust filtering and searching by status (pending,
   * approved, rejected, etc.), affected customers/sellers/admins, created or
   * updated dates, request/approved amount ranges, and refund reasons.
   * Pagination and sorting options support efficient review of large-scale or
   * complex refund activity for operational and regulatory purposes.
   *
   * Access to this endpoint is typically limited to platform admins or
   * compliance actors, as refund records may contain private customer/seller
   * information, financial details, and dispute comments. Results are
   * structured for easy display in admin dashboards and facilitate bulk review,
   * reporting, or dispute resolution processes.
   *
   * This operation leverages indexes and filters on status, actor, and date for
   * high-performance queries. If no records match the search, an empty page is
   * returned. It complements endpoints to review or update refund request
   * details and related APIs for order and payment management.
   *
   * @param connection
   * @param body Refund request search, filtering, and pagination parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallRefundRequest.IRequest,
  ): Promise<IPageIShoppingMallRefundRequest.ISummary> {
    try {
      return await patchShoppingMallAdminRefundRequests({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve full detail of a specific refund request
   * (shopping_mall_refund_requests).
   *
   * Retrieve the full detail for a single refund request in the shopping mall.
   * This endpoint provides all information filed by the customer for this
   * request, including the refund reason, status (such as pending, approved,
   * rejected, processing, refunded), the requested and (if decided) approved
   * refund amounts, and timestamps indicating the creation and latest update to
   * the request.
   *
   * The response also includes references to the associated order, the customer
   * who initiated the refund, the seller involved, and any admin who has acted
   * on or is assigned to the request. Timestamps for creation and updates are
   * included for precise workflow tracking and compliance. The refund request's
   * workflow state, including any logical soft deletion ('deleted_at'), is
   * honored; if the record is logically deleted, it will be omitted or return a
   * suitable error response.
   *
   * This operation is critical for customer support, dispute resolution, and
   * refund workflow management by platform actors. Only authorized users
   * (admin, customer, or seller associated with the refund) should be allowed
   * to access the details. Related operations: create refund request (POST
   * /refundRequests), list/search refund requests (PATCH /refundRequests).
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request to retrieve
   *   (UUID primary key).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":refundRequestId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await getShoppingMallAdminRefundRequestsRefundRequestId({
        admin,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the details and status of a shopping mall refund request record.
   *
   * This API operation allows authorized actors to update the details of an
   * existing refund request in the shopping mall system.
   *
   * Refund requests represent formal customer applications for monetary refunds
   * on orders or items. This API enables the modification of fields such as
   * status, approved amount, and optionally admin assignment as part of a
   * resolution workflow. Typical update scenarios include progressing the
   * request through workflow states—such as moving from pending to approved or
   * rejected—setting the final refund amount, or administrative reassignment.
   *
   * Security is a primary consideration. Only admins (and possibly trusted
   * sellers depending on internal policies) are permitted to update refund
   * requests, and all modifications are recorded with updated timestamps and
   * are subject to audit. Attempting to change immutable fields (such as
   * requested_amount or customer/seller associations) is disallowed and will
   * result in validation errors.
   *
   * This operation is closely related to other refund workflow APIs, including
   * refund request creation, detailed retrieval, and the delete (erase)
   * endpoint for withdrawal or cancellation of refund applications.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request to update.
   * @param body The updated information for the refund request, including
   *   status, approved amount, and admin assignment, as permitted by business
   *   logic.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":refundRequestId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallRefundRequest.IUpdate,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await putShoppingMallAdminRefundRequestsRefundRequestId({
        admin,
        refundRequestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete a refund request record (set deleted_at for compliance and
   * auditability).
   *
   * This API operation enables authorized administrators to mark a refund
   * request as deleted within the shopping mall system using soft deletion
   * semantics, leveraging the deleted_at column defined in the schema.
   *
   * Refund requests are a sensitive business process and, due to audit and
   * regulatory requirements, are not physically removed. Instead, the record is
   * timestamped in deleted_at and excluded from active business workflow
   * queries. Only high-privilege actors can perform the erase operation, and
   * such actions are thoroughly logged for compliance. Attempts to erase
   * non-existent or already deleted refund requests return appropriate errors.
   *
   * This operation is typically used in cases such as withdrawal of erroneous
   * refund requests, administrative cleanup, or regulatory-driven removals. It
   * is related to other refund workflow endpoints, such as creation and update
   * of refund requests, and integrates with the audit logging system for
   * irreversible actions.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request to
   *   soft-delete.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":refundRequestId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await deleteShoppingMallAdminRefundRequestsRefundRequestId({
        admin,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
