import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminCustomersCustomerIdSessions } from "../../../../../providers/patchShoppingMallAdminCustomersCustomerIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCustomersCustomerIdSessionsSessionId } from "../../../../../providers/getShoppingMallAdminCustomersCustomerIdSessionsSessionId";
import { deleteShoppingMallAdminCustomersCustomerIdSessionsSessionId } from "../../../../../providers/deleteShoppingMallAdminCustomersCustomerIdSessionsSessionId";

import { IPageIShoppingMallCustomerSession } from "../../../../../api/structures/IPageIShoppingMallCustomerSession";
import { IShoppingMallCustomerSession } from "../../../../../api/structures/IShoppingMallCustomerSession";

@Controller("/shoppingMall/admin/customers/:customerId/sessions")
export class ShoppingmallAdminCustomersSessionsController {
  /**
   * Search and retrieve the session history for a customer account from the
   * shopping_mall_customer_sessions table.
   *
   * Fetch and search all authentication session history records tied to a
   * specific customer, as identified by customerId.
   *
   * This patch operation targets the shopping_mall_customer_sessions table,
   * enabling administrators to inspect a user's historic and current session
   * records, including data such as session creation time, expiration, IP
   * address, and source URLs. The response is paginated, supporting advanced
   * server-side search and sorting by fields like created_at, expired_at, or IP
   * address. Sensitive session information is only available to admin actors
   * due to privacy and compliance requirements.
   *
   * Error handling includes rejecting requests for non-existent customers (404
   * Not Found) or unauthorized actors (403 Forbidden). This operation is
   * essential for security auditing, breach investigation, and customer service
   * troubleshooting.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer account (UUID).
   * @param body Advanced search criteria and pagination options for filtering
   *   the session list.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCustomerSession.IRequest,
  ): Promise<IPageIShoppingMallCustomerSession> {
    try {
      return await patchShoppingMallAdminCustomersCustomerIdSessions({
        admin,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific customer session record from
   * shopping_mall_customer_sessions.
   *
   * Retrieve a specific session record for a customer, enabling audit and
   * tracking of session history.
   *
   * This operation is essential for customer account management, support
   * troubleshooting, and security monitoring. The response provides all session
   * metadata defined in the schema, such as creation and expiration timestamps,
   * client IP address, and original/referrer URLs, while ensuring that
   * sensitive authentication tokens are never returned over the API.
   *
   * Security restrictions ensure that only the owner customer or authorized
   * admin may access this endpoint. No authentication/refresh logic occurs
   * here—this is a read-only operation for existing sessions. Attempts to
   * access another customer's sessions are denied. This operation is tightly
   * coupled with the session table defined in the Prisma schema, and follows
   * all related foreign key and index constraints for session lookup. Related
   * operations may include listing all sessions for a customer or invalidating
   * (deleting) a session record.
   *
   * @param connection
   * @param customerId Unique identifier (UUID) of the target customer who owns
   *   the session.
   * @param sessionId Unique identifier (UUID) of the session to be retrieved
   *   within the customer's records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerSession> {
    try {
      return await getShoppingMallAdminCustomersCustomerIdSessionsSessionId({
        admin,
        customerId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific customer session from shopping_mall_customer_sessions
   * (hard delete only).
   *
   * Delete or revoke a session record for a specific customer, thereby
   * invalidating their login session for that device, browser, or context.
   *
   * This operation is commonly used for customer-initiated logout (e.g., from
   * account settings or security center), as well as by admin actors enforcing
   * security policy or handling fraudulent activity. It permanently removes the
   * session record from the system, with no recovery capability. The deletion
   * is strictly limited to the session's owner or an administrator;
   * unauthorized attempts are rejected and logged.
   *
   * Notes: This operation NEVER issues or refreshes authentication tokens; it
   * strictly removes session records as defined in the session table.
   * Associated events (such as removing active JWT tokens) should be handled by
   * the authorization infrastructure, not the API itself. The operation is
   * compliant with current data retention and security requirements specified
   * by the business and schema.
   *
   * @param connection
   * @param customerId Unique identifier (UUID) of the target customer who owns
   *   the session.
   * @param sessionId Unique identifier (UUID) of the session to be deleted from
   *   the customer's records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCustomersCustomerIdSessionsSessionId({
        admin,
        customerId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
