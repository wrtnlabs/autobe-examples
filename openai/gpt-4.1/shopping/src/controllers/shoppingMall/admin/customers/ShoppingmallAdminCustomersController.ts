import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminCustomers } from "../../../../providers/patchShoppingMallAdminCustomers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCustomersCustomerId } from "../../../../providers/getShoppingMallAdminCustomersCustomerId";
import { putShoppingMallAdminCustomersCustomerId } from "../../../../providers/putShoppingMallAdminCustomersCustomerId";
import { deleteShoppingMallAdminCustomersCustomerId } from "../../../../providers/deleteShoppingMallAdminCustomersCustomerId";

import { IPageIShoppingMallCustomer } from "../../../../api/structures/IPageIShoppingMallCustomer";
import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";

@Controller("/shoppingMall/admin/customers")
export class ShoppingmallAdminCustomersController {
  /**
   * Search and retrieve a paginated/filtered customer account list from
   * shopping_mall_customers table.
   *
   * Search and retrieve a list of customer accounts by applying flexible
   * filters based on attributes including email, name, phone, registration
   * data, and email verification status. This operation is designed for the
   * needs of administrative actors who require insight into the buyer user
   * base, such as for manual review, user management, support requests, or
   * fraud investigation.
   *
   * Pagination controls and sorting options allow efficient navigation of large
   * customer datasets. The API supports complex queries and partial matches,
   * using optimized indexes for performance. Sensitive data, such as password
   * hashes, are strictly excluded from responses and protected from access, in
   * compliance with platform security and privacy requirements.
   *
   * Authorization is restricted to administrative users, and all queries are
   * logged for compliance and auditing. Error handling addresses invalid
   * queries, overbroad requests, or result set overflows, and helps ensure
   * operational transparency and robust support for administrative tasks.
   *
   * @param connection
   * @param body Advanced customer search criteria and pagination/sorting
   *   options. Supports filtering by attributes such as email, name,
   *   registration period, and verification status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCustomer.IRequest,
  ): Promise<IPageIShoppingMallCustomer.ISummary> {
    try {
      return await patchShoppingMallAdminCustomers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch detailed profile for a shopping mall customer
   * (shopping_mall_customers table).
   *
   * Retrieve the complete profile information of a customer account identified
   * by their unique ID. This includes name, email, phone number, verification
   * status, and timestamps for creation and last update. All data are sourced
   * directly from the shopping_mall_customers table, assuring referential
   * integrity and up-to-date information.
   *
   * Security and authorization are critical; only the customer themselves,
   * platform admins, or designated support personnel may access a customer's
   * sensitive profile. Attempting to fetch another user's data without proper
   * authorization should result in access denial.
   *
   * The operation carefully omits sensitive fields such as the password hash
   * and exposes only business-relevant, user-facing information. This endpoint
   * is critical to supporting user dashboards, order workflows, and account
   * management features.
   *
   * @param connection
   * @param customerId Unique identifier (UUID) of the target customer account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await getShoppingMallAdminCustomersCustomerId({
        admin,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing customer's profile details (shopping_mall_customers
   * table).
   *
   * Update a customer's profile details such as name, phone, and email, while
   * enforcing business constraints from the shopping_mall_customers schema. The
   * operation validates email uniqueness before applying updates and prevents
   * changes to authentication secrets like password hashes. Only permitted
   * actors (the customer or platform admin) may execute this action. All
   * changes are logged for audit.
   *
   * Email updates may also trigger a new verification workflow if required by
   * business logic. Attempts to update the profile with an already-registered
   * email or other constraint violations will cause the request to be rejected
   * with meaningful error messaging.
   *
   * This operation is designed for use in both user-facing account settings
   * interfaces and admin-driven customer management dashboards.
   *
   * @param connection
   * @param customerId Unique identifier (UUID) of the customer account to
   *   update.
   * @param body Payload with customer fields allowed to be updated (name,
   *   phone, email).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":customerId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCustomer.IUpdate,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await putShoppingMallAdminCustomersCustomerId({
        admin,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a customer account by customerId using the
   * shopping_mall_customers table.
   *
   * Permanently remove a customer account from the system, identified by
   * customerId.
   *
   * This REST operation supports platform policies that allow only
   * administrative actors to delete customer accounts. Upon execution, it
   * irreversibly erases the customer's personal and authentication data,
   * including email, name, phone, and all status fields from the
   * shopping_mall_customers table. Foreign key relationships, including
   * addresses, shopping cart, wishlist, and order history, are handled via
   * on-delete policies or detached as appropriate. No soft delete is performed,
   * and once deleted, the customerId cannot be reused.
   *
   * Role-based authorization restricts this action to admin only, and automated
   * audit logging should capture the fact of deletion for compliance. Attempts
   * to delete non-existent or already deleted accounts should result in
   * appropriate error responses (e.g., 404 Not Found). No recoverability is
   * provided after this operation, supporting business needs for GDPR-compliant
   * data erasure upon privileged request.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer account (UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":customerId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCustomersCustomerId({
        admin,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
