import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminCustomersCustomerIdAddresses } from "../../../../../providers/patchShoppingMallAdminCustomersCustomerIdAddresses";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCustomersCustomerIdAddressesAddressId } from "../../../../../providers/getShoppingMallAdminCustomersCustomerIdAddressesAddressId";
import { putShoppingMallAdminCustomersCustomerIdAddressesAddressId } from "../../../../../providers/putShoppingMallAdminCustomersCustomerIdAddressesAddressId";
import { deleteShoppingMallAdminCustomersCustomerIdAddressesAddressId } from "../../../../../providers/deleteShoppingMallAdminCustomersCustomerIdAddressesAddressId";

import { IPageIShoppingMallAddress } from "../../../../../api/structures/IPageIShoppingMallAddress";
import { IShoppingMallAddress } from "../../../../../api/structures/IShoppingMallAddress";

@Controller("/shoppingMall/admin/customers/:customerId/addresses")
export class ShoppingmallAdminCustomersAddressesController {
  /**
   * Retrieve a paginated and filterable list of address records for a specific
   * customer.
   *
   * This endpoint is accessible to authenticated customers (for their own
   * addresses) and admins (for platform oversight). The operation enables
   * customers to view all of their stored addresses (up to the business maximum
   * of 10). Query capabilities allow for search by name, city, or status, and
   * results are paginated for efficient display in user interfaces. Security
   * and ownership checks ensure that only the owner/customer or platform admins
   * may access this data.
   *
   * Returned records cover all structured address fields, including recipient
   * name, full address breakdown, contact phone, whether it is the default, and
   * address creation time. Results conform to the business schema, omitting
   * fields that do not exist in shopping_mall_addresses (such as deleted_at).
   * Error conditions include access violation if an actor requests another
   * customer's addresses without admin privileges.
   *
   * Related operations include address retrieval and modification (GET, PUT,
   * DELETE /customers/{customerId}/addresses/{addressId}), which allow
   * management of individual address entries. This operation only lists the
   * current user's addresses, never those of sellers or other actors.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer whose addresses
   *   will be listed.
   * @param body Search, filtering, and pagination parameters for querying the
   *   address list of a specific customer.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAddress.IRequest,
  ): Promise<IPageIShoppingMallAddress.ISummary> {
    try {
      return await patchShoppingMallAdminCustomersCustomerIdAddresses({
        admin,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete details of a single address by ID for a given
   * customer.
   *
   * Only the account owner (authenticated customer) or an admin is allowed to
   * access the requested address. The addressId parameter must refer to an
   * address record that belongs to the customer identified by customerId;
   * otherwise, an error is returned. The returned data covers full address
   * structure in line with schema guidelines, ensuring only user-manageable
   * data is present. This is commonly used for editing addresses in personal
   * profile sections and for reviewing address details prior to order
   * checkout.
   *
   * If an address does not belong to the given customer, or the actor lacks
   * sufficient permissions, an authorization error is triggered. Related
   * endpoints include the paginated address list and update/delete operations
   * for the same resource.
   *
   * @param connection
   * @param customerId Unique identifier of the customer who owns the address.
   * @param addressId Unique identifier of the target address record being
   *   retrieved.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":addressId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAddress> {
    try {
      return await getShoppingMallAdminCustomersCustomerIdAddressesAddressId({
        admin,
        customerId,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the detailed shipping or billing address of a specific customer in
   * the platform's address book.
   *
   * The operation verifies that the addressId is associated with the given
   * customerId, ensuring correct ownership before allowing updates. All address
   * fields—including recipient's full name, street, city, province, postal
   * code, country (in ISO/local format), contact phone, and default status—must
   * be provided in the request, and are strictly validated as described in the
   * database schema. Only administrative actors can perform this update
   * operation to enforce business policies around hard data changes and data
   * integrity.
   *
   * Security and audit compliance are maintained—any modification is recorded
   * with a timestamp (updated_at) and attributed to the requesting admin. The
   * operation returns the updated address entry for verification and compliance
   * workflows. Related operations include the DELETE endpoint for address
   * removal and listing endpoints for retrieving addresses by customer.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer (UUID format,
   *   global scope).
   * @param addressId Unique identifier of the address to update (UUID format,
   *   must belong to the specified customer).
   * @param body Updated address details for the target customer address record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":addressId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAddress.IUpdate,
  ): Promise<IShoppingMallAddress> {
    try {
      return await putShoppingMallAdminCustomersCustomerIdAddressesAddressId({
        admin,
        customerId,
        addressId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes a specific address belonging to a given customer from
   * the platform's address book. This operation checks that the address record
   * identified by addressId is indeed owned by the customer specified by
   * customerId before proceeding with the deletion. Only admins are authorized
   * to perform this action.
   *
   * The operation enforces strict compliance with audit and business integrity.
   * Upon successful execution, the address record is completely erased from the
   * database and cannot be recovered. This is a hard delete as per the
   * platform's business rules, and all deletion actions are recorded for audit
   * trail purposes. Related retrieval and update endpoints exist for reviewing
   * address details or modifying address information.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer (UUID format,
   *   global scope).
   * @param addressId Unique identifier of the address to delete (UUID format,
   *   must belong to the specified customer).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":addressId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCustomersCustomerIdAddressesAddressId(
        {
          admin,
          customerId,
          addressId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
