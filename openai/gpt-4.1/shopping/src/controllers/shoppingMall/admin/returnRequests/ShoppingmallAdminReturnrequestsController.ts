import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminReturnRequests } from "../../../../providers/patchShoppingMallAdminReturnRequests";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminReturnRequestsReturnRequestId } from "../../../../providers/getShoppingMallAdminReturnRequestsReturnRequestId";
import { putShoppingMallAdminReturnRequestsReturnRequestId } from "../../../../providers/putShoppingMallAdminReturnRequestsReturnRequestId";
import { deleteShoppingMallAdminReturnRequestsReturnRequestId } from "../../../../providers/deleteShoppingMallAdminReturnRequestsReturnRequestId";

import { IPageIShoppingMallReturnRequest } from "../../../../api/structures/IPageIShoppingMallReturnRequest";
import { IShoppingMallReturnRequest } from "../../../../api/structures/IShoppingMallReturnRequest";

@Controller("/shoppingMall/admin/returnRequests")
export class ShoppingmallAdminReturnrequestsController {
  /**
   * Retrieve a paginated, searchable index of all return, pickup, and shipment
   * reverse logistics requests filed with the shopping mall platform.
   *
   * This endpoint allows staff and authorized partners to search return
   * requests with flexible filters including request status, creation and
   * scheduled pickup dates, return reason text search, order/line item, and
   * requesting actor (customer or seller). It also supports fine-grained
   * sorting (e.g., by status, most recent requests, scheduled pickups) and
   * paging for operational efficiency when reviewing or processing large
   * volumes.
   *
   * Comprehensive security controls ensure only authorized actors (operations,
   * fulfillment center, or customer-service staff) can access this endpoint.
   * Audit trails ensure every query can be reported for compliance. This index
   * view enables proactive customer support and timely reverse logistics
   * management. Additional details or lifecycle events for each request may be
   * retrieved via the detail view endpoint.
   *
   * @param connection
   * @param body Filter and search parameters for retrieving return requests,
   *   including status, requesting actor, order/item, date ranges, and
   *   pagination controls.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallReturnRequest.IRequest,
  ): Promise<IPageIShoppingMallReturnRequest.ISummary> {
    try {
      return await patchShoppingMallAdminReturnRequests({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete detail of a single return, pickup, or shipment
   * reverse logistics request.
   *
   * This endpoint provides the full set of information for a single return
   * request, including its status, associated order/item, customer or seller
   * attribution, reasoning, all logistics/carrier details, audit fields, as
   * well as lifecycle timestamps for submission, update, completion, or
   * cancellation. The detailed record enables authorized staff to view the
   * request's entire history and current disposition.
   *
   * Strict authorization ensures only platform support or logistics staff can
   * retrieve sensitive request details. This operation is commonly used after
   * searching or listing via the index endpoint, and is critical for root-cause
   * analysis, refund/dispute investigation, or direct customer communications
   * about a return event.
   *
   * @param connection
   * @param returnRequestId Unique identifier (UUID) of the return or reverse
   *   logistics request to retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":returnRequestId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("returnRequestId")
    returnRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReturnRequest> {
    try {
      return await getShoppingMallAdminReturnRequestsReturnRequestId({
        admin,
        returnRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the details or workflow status of an existing return or pickup
   * request in the shopping mall platform.
   *
   * This operation allows updates to any mutable property of the return/pickup
   * request, including status transitions, reason updates, scheduled pickup
   * modifications, or changes to shipping and tracking information. Validation
   * logic enforces proper workflow progression and authorized actor roles in
   * managing each field. Only valid status transitions are permitted.
   *
   * The update action records updated_at timestamps and retains full audit
   * details for each modification. Triggering of business events such as
   * scheduling, pickup assignment, or request completion/cancellation may be
   * dependent on proper use of this update endpoint in tandem with workflow
   * policies. It is critical that client apps and workflow automations adhere
   * strictly to business rules when invoking this operation.
   *
   * @param connection
   * @param returnRequestId Unique identifier of the return or pickup request
   *   record to update.
   * @param body Modifiable fields of the return or pickup request including
   *   status, scheduled pickup, carrier info, and reason.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":returnRequestId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("returnRequestId")
    returnRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReturnRequest.IUpdate,
  ): Promise<IShoppingMallReturnRequest> {
    try {
      return await putShoppingMallAdminReturnRequestsReturnRequestId({
        admin,
        returnRequestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a return or reverse logistics request from the system
   * database. This operation completely deletes the targeted return/pickup
   * request record from the platform, eliminating all status, shipment, actor
   * attribution, scheduling, and carrier/tracking fields for the specified
   * request.
   *
   * Only administrators and actors with elevated governance privileges are
   * permitted to execute this permanent erase action, due to its
   * irreversibility and potential compliance implications. The targeted record
   * is gone from the 'shopping_mall_return_requests' table and cannot be
   * recovered by normal means; related audit trails and referential links
   * should be checked by the system to prevent orphaned references.
   *
   * This hard deletion is differentiated from soft deletion (where 'deleted_at'
   * is set) because it physically removes the underlying row, instead of
   * marking as deleted. Use this operation only when business policy calls for
   * actual tombstone record destruction or irreparable data removal, such as
   * for error correction or sensitive personal data purges.
   *
   * @param connection
   * @param returnRequestId Unique identifier of the target return or pickup
   *   request.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":returnRequestId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("returnRequestId")
    returnRequestId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminReturnRequestsReturnRequestId({
        admin,
        returnRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
