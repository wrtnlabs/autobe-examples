import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminOrdersOrderNumberStatusHistories } from "../../../../../providers/patchShoppingMallAdminOrdersOrderNumberStatusHistories";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminOrdersOrderNumberStatusHistoriesStatusHistoryId } from "../../../../../providers/getShoppingMallAdminOrdersOrderNumberStatusHistoriesStatusHistoryId";

import { IPageIShoppingMallOrderStatusHistory } from "../../../../../api/structures/IPageIShoppingMallOrderStatusHistory";
import { IShoppingMallOrderStatusHistory } from "../../../../../api/structures/IShoppingMallOrderStatusHistory";

@Controller("/shoppingMall/admin/orders/:orderNumber/statusHistories")
export class ShoppingmallAdminOrdersStatushistoriesController {
  /**
   * Retrieve a paginated and filtered list of status history entries for a
   * specific order identified by its order number. The response reveals all
   * order state transitions (e.g., pending→paid, paid→shipped,
   * shipped→delivered, etc.), along with metadata about who or what system
   * triggered each event, when they occurred, and any associated business
   * comments.
   *
   * This operation is critical for customer support reps, administrators,
   * and—in self-service cases—end customers wishing to track the event lineage
   * of their order. Security policies ensure that only users with the right to
   * view order data (typically the order owner, seller, or admin) can access
   * these histories, and sensitive or internal comments may be masked as
   * business logic dictates.
   *
   * Advanced filtering, sorting, and pagination are supported via request body,
   * letting users locate particular status changes or focus on specific periods
   * of the order lifecycle. Integration with the
   * shopping_mall_order_status_histories table ensures data integrity and
   * auditability.
   *
   * @param connection
   * @param orderNumber Platform-unique business order number for the order to
   *   retrieve status history for (global scope).
   * @param body Filtering, pagination, and sorting parameters for querying
   *   status history; supports searching by status, actor type, timestamp
   *   range, or free-text comment.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedBody()
    body: IShoppingMallOrderStatusHistory.IRequest,
  ): Promise<IPageIShoppingMallOrderStatusHistory> {
    try {
      return await patchShoppingMallAdminOrdersOrderNumberStatusHistories({
        admin,
        orderNumber,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single status transition record associated with a specific
   * order, enabling review of a particular change event in an order's
   * lifecycle.
   *
   * This endpoint is intended for detailed order auditing, customer support
   * review, or compliance workflows requiring precise traceability of how and
   * when each status transition occurred for an order. All status transition
   * records are retained for audit and cannot be modified or deleted.
   *
   * The order_number path parameter identifies the target order using the
   * business order number (string, globally unique), while the statusHistoryId
   * parameter specifies the unique identifier (UUID) of the particular status
   * transition record. The response provides the full details of the transition
   * including old and new statuses, actor information, any business comment,
   * and the exact timestamp. This data supports operational workflows for order
   * fulfillment, status audit reporting, or legal inquiry. Only authorized
   * actors may access this detailed history per platform policy.
   *
   * @param connection
   * @param orderNumber Globally unique business order number identifying the
   *   order (order_number field, global scope).
   * @param statusHistoryId UUID identifying the specific order status
   *   transition record (global unique identifier).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":statusHistoryId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedParam("statusHistoryId")
    statusHistoryId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderStatusHistory> {
    try {
      return await getShoppingMallAdminOrdersOrderNumberStatusHistoriesStatusHistoryId(
        {
          admin,
          orderNumber,
          statusHistoryId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
