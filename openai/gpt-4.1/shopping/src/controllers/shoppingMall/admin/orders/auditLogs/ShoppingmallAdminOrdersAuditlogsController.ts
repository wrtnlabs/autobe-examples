import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminOrdersOrderNumberAuditLogs } from "../../../../../providers/patchShoppingMallAdminOrdersOrderNumberAuditLogs";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminOrdersOrderNumberAuditLogsAuditLogId } from "../../../../../providers/getShoppingMallAdminOrdersOrderNumberAuditLogsAuditLogId";

import { IPageIShoppingMallOrderAuditLog } from "../../../../../api/structures/IPageIShoppingMallOrderAuditLog";
import { IShoppingMallOrderAuditLog } from "../../../../../api/structures/IShoppingMallOrderAuditLog";

@Controller("/shoppingMall/admin/orders/:orderNumber/auditLogs")
export class ShoppingmallAdminOrdersAuditlogsController {
  /**
   * Search and retrieve all audit log events associated with a given order
   * using its business order number. This enables compliance workflows,
   * incident reviews, dispute investigations, or customer support follow-up for
   * any order activity—from updates and cancellations to comment history or
   * payment changes.
   *
   * The endpoint supports complex queries including time range, action type,
   * actor filtering, and pagination, all requested within the body according to
   * the IShoppingMallOrderAuditLog.IRequest DTO.
   *
   * Only actors with administrative permissions are allowed to access audit
   * logs due to the sensitive nature of recorded details. The response is a
   * paginated list (IPageIShoppingMallOrderAuditLog.ISummary) with summary
   * information suitable for dashboard views or administrative audit tools.
   * This supports at-a-glance system monitoring and allows compliance teams to
   * drill into the full context as needed.
   *
   * @param connection
   * @param orderNumber Globally unique business order number identifying the
   *   order (order_number field, global scope).
   * @param body Filtering criteria, time range, sort options, and pagination
   *   for audit log query.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedBody()
    body: IShoppingMallOrderAuditLog.IRequest,
  ): Promise<IPageIShoppingMallOrderAuditLog.ISummary> {
    try {
      return await patchShoppingMallAdminOrdersOrderNumberAuditLogs({
        admin,
        orderNumber,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single, detailed audit log event for a given order using the
   * business order number and the unique auditLogId. This operation allows
   * authorized actors (admin or the responsible seller) to view a specific
   * historical event that affected an order, such as order status changes,
   * refund processing, address updates, or any other auditable update. The data
   * returned includes the type of action performed, the actor (admin, seller,
   * or customer), the timestamp of the event, optional context details, and
   * references to both the order and the audit log event, fully aligned with
   * the append-only design for compliance and traceability.
   *
   * Security and privacy controls are strictly enforced for this endpoint. Only
   * administrators and the seller associated with the order are permitted to
   * access audit logs; customer actors are not authorized. The endpoint uses
   * business order numbers instead of technical UUIDs to facilitate real-world
   * referencing (e.g., customer support scenarios, order investigations).
   * Requests with invalid or mismatched orderNumber and auditLogId combinations
   * will return detailed error responses, clarifying the nature of the lookup
   * or authorization failure.
   *
   * Dependency: An order must already exist with the provided orderNumber, and
   * the requested auditLogId must correspond to a valid audit log row for that
   * order. The operation does not support creation, modification, or deletion
   * of audit logs, reflecting the immutable and system-generated nature of the
   * shopping_mall_order_audit_logs table. If more detailed context is needed,
   * consumers should reference the auditLogs index/search endpoint.
   *
   * @param connection
   * @param orderNumber Platform-unique business order number referencing the
   *   parent order (global scope).
   * @param auditLogId Unique identifier (UUID) of the specific audit log record
   *   to retrieve for the target order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":auditLogId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedParam("auditLogId")
    auditLogId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderAuditLog> {
    try {
      return await getShoppingMallAdminOrdersOrderNumberAuditLogsAuditLogId({
        admin,
        orderNumber,
        auditLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
