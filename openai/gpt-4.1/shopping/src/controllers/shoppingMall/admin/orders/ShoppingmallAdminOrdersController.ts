import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallAdminOrders } from "../../../../providers/patchShoppingMallAdminOrders";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminOrdersOrderNumber } from "../../../../providers/getShoppingMallAdminOrdersOrderNumber";
import { deleteShoppingMallAdminOrdersOrderNumber } from "../../../../providers/deleteShoppingMallAdminOrdersOrderNumber";

import { IPageIShoppingMallOrder } from "../../../../api/structures/IPageIShoppingMallOrder";
import { IShoppingMallOrder } from "../../../../api/structures/IShoppingMallOrder";

@Controller("/shoppingMall/admin/orders")
export class ShoppingmallAdminOrdersController {
  /**
   * Search, filter, and paginate shopping_mall_orders records.
   *
   * Retrieve a filtered and paginated list of all orders submitted on the
   * platform.
   *
   * This operation exposes robust search and filter capabilities to allow
   * administrators or authorized users to efficiently locate orders by multiple
   * criteria, including order number, customer, status, date placed, and the
   * responsible seller. It is ideal for order management systems, customer
   * support back offices, and analytical query panels that require dynamic
   * querying, sorting, and operational batch processing.
   *
   * Security considerations: Only users with proper access may retrieve full
   * order lists with all details. Depending on the requirements and
   * implementation, sensitive details may be filtered or restricted at the DTO
   * level for certain actors. Related operations include detailed order
   * retrieval and item listing for individual orders by order number.
   *
   * Validation logic ensures that page searches include well-formed query
   * inputs (such as ISO 8601 datetimes, correct status values, and optional
   * seller/customer codes). In case of input errors or excessive result count,
   * the system should provide appropriate error messages and guidance on filter
   * restrictions.
   *
   * @param connection
   * @param body Search criteria, filtering options, and pagination parameters
   *   for retrieving a list of orders.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallOrder.IRequest,
  ): Promise<IPageIShoppingMallOrder.ISummary> {
    try {
      return await patchShoppingMallAdminOrders({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get the complete shopping_mall_orders record by unique order_number.
   *
   * Fetches the complete details for a specific order identified by its
   * globally unique business order number.
   *
   * This endpoint is used for both customer and back office contexts requiring
   * a deep dive into an order's financial, fulfillment, and status details.
   * Data returned includes all order metadata, primary references to customer,
   * seller, address, and summarized item breakdowns. The order number parameter
   * uniquely identifies the target order across the entire platform, as
   * enforced by the database unique constraint.
   *
   * Appropriate access controls and audit logging must be in place to track
   * access and prevent unauthorized information disclosure. Related endpoints
   * include order search and order item operations for per-item details and
   * workflow processing. Input validation ensures that the order number follows
   * the correct business format and refers to an existing, non-deleted order.
   * Error handling provides clear messages for missing/invalid references or
   * restricted information access.
   *
   * @param connection
   * @param orderNumber Platform-unique business order number of the target
   *   order (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderNumber")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
  ): Promise<IShoppingMallOrder> {
    try {
      return await getShoppingMallAdminOrdersOrderNumber({
        admin,
        orderNumber,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete a shopping mall order by its unique business order number
   * (shopping_mall_orders table).
   *
   * Permanently remove a shopping mall order by its unique business order
   * number.
   *
   * This API is designed for use by administrators and auditors. It ensures
   * that the specified order has no critical dependencies that would block
   * deletion, such as active shipments or unresolved payments. The order
   * deletion logic is implemented as a soft delete by updating the deleted_at
   * field, indicating the order is no longer active in the system, but
   * retaining the record for compliance purposes.
   *
   * Security and audit standards are enforced on this operation, including
   * event logging and restricted access. If the order is already deleted or
   * cannot be found, the operation will fail with an appropriate error message.
   * Pre-execution of order item and attachment list retrieval is recommended
   * before performing deletion to ensure no business locks are in place.
   *
   * All related tables—including order items, shipments, and logs—are checked
   * before deletion to avoid broken references. Only actors with administrative
   * privileges should be granted this capability. All deletion events are
   * auditable, and the deleted order is excluded from all future business
   * workflows.
   *
   * @param connection
   * @param orderNumber Platform-unique business order number identifying the
   *   target order (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":orderNumber")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminOrdersOrderNumber({
        admin,
        orderNumber,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
