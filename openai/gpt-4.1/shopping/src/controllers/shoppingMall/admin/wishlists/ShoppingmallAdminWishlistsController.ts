import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminWishlists } from "../../../../providers/patchShoppingMallAdminWishlists";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminWishlistsWishlistId } from "../../../../providers/getShoppingMallAdminWishlistsWishlistId";

import { IPageIShoppingMallWishlist } from "../../../../api/structures/IPageIShoppingMallWishlist";
import { IShoppingMallWishlist } from "../../../../api/structures/IShoppingMallWishlist";

@Controller("/shoppingMall/admin/wishlists")
export class ShoppingmallAdminWishlistsController {
  /**
   * Search and retrieve a paginated, filterable list of shopping mall wishlists
   * (shopping_mall_wishlists table).
   *
   * Retrieve a paginated and filterable list of all customer wishlists in the
   * system.
   *
   * This operation is intended for administrative or reporting features where a
   * platform user (typically an admin) needs to review wishlists held by
   * customers. It supports advanced filtering based on creation time, customer
   * ID, or other business-defined criteria, as well as pagination and sorting
   * options for large data sets.
   *
   * The results respect the structure and constraints of the
   * shopping_mall_wishlists table, returning only basic wishlist information.
   * Sensitive data is excluded to preserve customer privacy unless higher
   * privileges are granted. When used with other endpoints, this operation
   * supports data-level audit, customer behavior analytics, and reporting on
   * product interest trends.
   *
   * @param connection
   * @param body Filter and pagination options for searching wishlists (e.g.,
   *   customer ID, creation time window, sort order).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallWishlist.IRequest,
  ): Promise<IPageIShoppingMallWishlist.ISummary> {
    try {
      return await patchShoppingMallAdminWishlists({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve all detailed information of a single shopping mall wishlist
   * (shopping_mall_wishlists table) by ID.
   *
   * Retrieve all available details for one specific customer wishlist by its
   * unique identifier.
   *
   * This operation is intended for administrative users or backend systems
   * requiring in-depth review of a customer's wishlist for troubleshooting,
   * analysis, or support. The wishlistId path parameter corresponds to the
   * primary key (UUID) for the shopping_mall_wishlists table. Related records
   * (such as the owning customer and wishlist items) may be retrievable through
   * composed or subsidiary endpoints, but this response focuses on the main
   * wishlist entity only.
   *
   * Security is crucial, as this endpoint usually contains sensitive customer
   * interest data, so access should be restricted to users with administrative
   * privileges. This operation is typically used in conjunction with the
   * list/search endpoint to investigate or manage specific customer records.
   *
   * @param connection
   * @param wishlistId Unique identifier (UUID) of the target wishlist in
   *   shopping_mall_wishlists.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":wishlistId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallWishlist> {
    try {
      return await getShoppingMallAdminWishlistsWishlistId({
        admin,
        wishlistId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
