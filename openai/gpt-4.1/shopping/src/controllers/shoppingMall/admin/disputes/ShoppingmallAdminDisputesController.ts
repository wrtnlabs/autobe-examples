import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminDisputes } from "../../../../providers/postShoppingMallAdminDisputes";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminDisputes } from "../../../../providers/patchShoppingMallAdminDisputes";
import { getShoppingMallAdminDisputesDisputeId } from "../../../../providers/getShoppingMallAdminDisputesDisputeId";
import { putShoppingMallAdminDisputesDisputeId } from "../../../../providers/putShoppingMallAdminDisputesDisputeId";
import { deleteShoppingMallAdminDisputesDisputeId } from "../../../../providers/deleteShoppingMallAdminDisputesDisputeId";

import { IShoppingMallDispute } from "../../../../api/structures/IShoppingMallDispute";
import { IPageIShoppingMallDispute } from "../../../../api/structures/IPageIShoppingMallDispute";

@Controller("/shoppingMall/admin/disputes")
export class ShoppingmallAdminDisputesController {
  /**
   * Create a new dispute case linked to customer, seller, and optionally an
   * admin actor in the shopping mall platform.
   *
   * This operation allows authenticated users to initiate a dispute by
   * submitting the necessary details about the dispute's subject, root cause,
   * and any related refund request. All required actor IDs must be specified
   * according to relationships in the shopping_mall_disputes schema. The
   * 'status' should reflect the starting dispute state (e.g., open).
   *
   * Upon creation, the dispute will be entered into the platform workflow for
   * mediation and compliance tracking. Security: Typically restricted to admins
   * or customer service staff for audit and platform integrity reasons.
   * Successful creation logs the current state and actor context for later
   * audit trail histories.
   *
   * If a refund request is applicable, its primary key must be provided and the
   * dispute will be linked to the request for traceability. The operation
   * validates that referenced actor records exist and that business logic for
   * allowed dispute creation paths is enforced.
   *
   * @param connection
   * @param body New dispute case to register. Must supply all necessary fields
   *   as per IShoppingMallDispute.ICreate.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallDispute.ICreate,
  ): Promise<IShoppingMallDispute> {
    try {
      return await postShoppingMallAdminDisputes({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of platform dispute cases from the
   * shopping_mall_disputes table. This operation provides administrative and
   * operational staff with advanced search capabilities to find disputes based
   * on status, origin, subject, actors, and date ranges.
   *
   * Each dispute record summarizes the origin (linked refund request if
   * present), involved actors (customer, seller, and handling admin), subject,
   * root cause, and resolution notes. Full support is given for searching by
   * status (open, investigating, resolved, rejected, escalated, closed),
   * subject keywords, date of creation, and actor roles. The results can be
   * sorted by most recent activity, status, or involved parties in either
   * ascending or descending order.
   *
   * This operation is core to platform compliance and dispute resolution
   * workflows, supporting review, escalation, and audit needs for platform
   * governance. The search parameters should be designed to provide maximum
   * flexibility while retaining strict adherence to business and privacy
   * rules.
   *
   * @param connection
   * @param body Request parameters for searching, filtering, and paginating
   *   dispute cases, including status, actor roles, keywords, and sort
   *   options.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallDispute.IRequest,
  ): Promise<IPageIShoppingMallDispute.ISummary> {
    try {
      return await patchShoppingMallAdminDisputes({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch detailed information for a specific dispute case using its disputeId.
   * The operation exposes all available context, including the origin of the
   * dispute (such as the associated refund request if any), the roles of
   * involved actors, the current status, business subject, root cause analysis,
   * and timestamps for key state transitions.
   *
   * Detailed resolution notes and all administrative actions taken are included
   * to aid in compliance audits, cross-actor mediation, and tracking of
   * platform decisions. Sensitive business logic, such as decision history and
   * privileged notes, are only shown to properly authorized actors as mandated
   * by platform policy.
   *
   * This operation is integral to dispute management and governance, supporting
   * both detailed review and workflow status monitoring. Error handling covers
   * cases where the disputeId is not found or the viewing actor lacks
   * appropriate permissions. It is closely coordinated with operations for
   * updating, resolving, or escalating disputes.
   *
   * @param connection
   * @param disputeId Unique identifier of the target dispute record in
   *   shopping_mall_disputes table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":disputeId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("disputeId")
    disputeId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallDispute> {
    try {
      return await getShoppingMallAdminDisputesDisputeId({
        admin,
        disputeId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update details, status, or resolution notes of an existing shopping mall
   * dispute by specifying the dispute's ID and the new data.
   *
   * The operation allows the assigned admin actor (or authorized platform
   * staff) to modify the state of a dispute record as it progresses through
   * investigation, mediation, or resolution. This may include changing the
   * status (open, resolved, closed, etc.), updating subject/root cause, or
   * adding a final resolution note once a decision has been made.
   *
   * Strict validation is applied on allowed status transitions and that
   * referenced actors and refund requests are valid according to the business
   * logic. All updates are logged for auditability. Security is enforced such
   * that only designated actors can mutate dispute records, maintaining
   * integrity across the complaint lifecycle.
   *
   * @param connection
   * @param disputeId Unique identifier of the target dispute record for update.
   * @param body New values to assign to the dispute record. Partial or full
   *   update allowed as per IShoppingMallDispute.IUpdate.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":disputeId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("disputeId")
    disputeId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallDispute.IUpdate,
  ): Promise<IShoppingMallDispute> {
    try {
      return await putShoppingMallAdminDisputesDisputeId({
        admin,
        disputeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently deletes a dispute from the shopping mall platform using its
   * unique identifier.
   *
   * This operation enforces strict administrative permissions: only platform
   * admins are authorized to perform permanent dispute deletion. The request is
   * verified against business rules and database constraints to prevent
   * accidental or unauthorized removal of disputes that are still relevant to
   * platform legal or compliance requirements.
   *
   * All child records, such as dispute histories, are generally retained under
   * audit policy; the operation centers on removing the root dispute entity
   * (from shopping_mall_disputes table). The operation uses a soft-deletion via
   * the deleted_at field, compliant with audit and regulatory retention
   * policies. This approach ensures that data is hidden from active business
   * workflows but available for legal review and historical analytics as
   * required.
   *
   * Attempting to delete a non-existent or already deleted dispute returns a
   * suitable error message. The endpoint ensures transactional consistency,
   * integrating with related API operations for dispute workflows, such as
   * dispute resolution and audit log inspection.
   *
   * @param connection
   * @param disputeId Unique identifier of the target dispute to delete (UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":disputeId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("disputeId")
    disputeId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminDisputesDisputeId({
        admin,
        disputeId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
