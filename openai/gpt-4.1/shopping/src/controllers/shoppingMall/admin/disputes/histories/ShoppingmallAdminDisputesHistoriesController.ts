import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminDisputesDisputeIdHistories } from "../../../../../providers/patchShoppingMallAdminDisputesDisputeIdHistories";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminDisputesDisputeIdHistoriesDisputeHistoryId } from "../../../../../providers/getShoppingMallAdminDisputesDisputeIdHistoriesDisputeHistoryId";

import { IPageIShoppingMallDisputeHistory } from "../../../../../api/structures/IPageIShoppingMallDisputeHistory";
import { IShoppingMallDisputeHistory } from "../../../../../api/structures/IShoppingMallDisputeHistory";

@Controller("/shoppingMall/admin/disputes/:disputeId/histories")
export class ShoppingmallAdminDisputesHistoriesController {
  /**
   * Returns a paginated list capturing the entire audit trail of status
   * changes, actions, and notes for a specific dispute's lifecycle.
   *
   * This endpoint is restricted to admin users to maintain strict
   * confidentiality and integrity of the dispute resolution process. The
   * operation queries the shopping_mall_dispute_histories table for all entries
   * associated with the given disputeId—and returns the results in descending
   * order by created_at (latest first for review efficiency).
   *
   * Returned data includes the status at each stage, involved actor roles
   * (admin, seller, customer), timestamps, and any contextual notes. The
   * endpoint supports pagination to allow efficient review of long-running or
   * complex disputes with extensive history. Combined with the main dispute
   * record, this audit trail provides the foundation for compliance,
   * governance, and forensic analysis in the shopping mall platform.
   *
   * @param connection
   * @param disputeId Unique identifier of the dispute whose histories are
   *   requested (UUID).
   * @param body Pagination and filtering parameters for auditing dispute
   *   histories.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("disputeId")
    disputeId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallDisputeHistory.IRequest,
  ): Promise<IPageIShoppingMallDisputeHistory> {
    try {
      return await patchShoppingMallAdminDisputesDisputeIdHistories({
        admin,
        disputeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single historical status or audit snapshot for a dispute.
   *
   * This operation fetches a specific record from the
   * shopping_mall_dispute_histories table, which logs every notable event,
   * transition, or actor action throughout the lifecycle of a dispute (such as
   * status changes, escalations, notes, and administrative interventions).
   *
   * Useful for customer support, sellers, admins, or compliance teams needing
   * to check a specific transition or note associated with the dispute. The
   * operation enforces that only users with proper linkage to the dispute or
   * administrative visibility can access this data.
   *
   * The operation requires the disputeId (identifying the parent dispute) and
   * the disputeHistoryId (identifying the history entry). Both must be valid
   * UUIDs, and the endpoint will return detailed audit information or a
   * suitable error if not found or not authorized. The response object contains
   * the complete snapshot as stored in the history log, supporting review and
   * traceability.
   *
   * @param connection
   * @param disputeId Unique identifier of the parent dispute associated with
   *   this history record.
   * @param disputeHistoryId Unique identifier of the specific dispute history
   *   record to retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":disputeHistoryId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("disputeId")
    disputeId: string & tags.Format<"uuid">,
    @TypedParam("disputeHistoryId")
    disputeHistoryId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallDisputeHistory> {
    try {
      return await getShoppingMallAdminDisputesDisputeIdHistoriesDisputeHistoryId(
        {
          admin,
          disputeId,
          disputeHistoryId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
