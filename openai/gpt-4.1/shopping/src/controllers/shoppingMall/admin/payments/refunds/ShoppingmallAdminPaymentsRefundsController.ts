  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("paymentId")
    paymentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallPaymentRefund.ICreate,
  ): Promise<IShoppingMallPaymentRefund> {
    try {
      return await postShoppingMallAdminPaymentsPaymentIdRefunds({
        admin,
        paymentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

