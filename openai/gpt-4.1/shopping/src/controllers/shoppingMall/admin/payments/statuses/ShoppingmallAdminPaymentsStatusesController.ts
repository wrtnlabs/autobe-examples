import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminPaymentsPaymentIdStatuses } from "../../../../../providers/patchShoppingMallAdminPaymentsPaymentIdStatuses";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminPaymentsPaymentIdStatusesStatusId } from "../../../../../providers/getShoppingMallAdminPaymentsPaymentIdStatusesStatusId";

import { IPageIShoppingMallPaymentStatus } from "../../../../../api/structures/IPageIShoppingMallPaymentStatus";
import { IShoppingMallPaymentStatus } from "../../../../../api/structures/IShoppingMallPaymentStatus";

@Controller("/shoppingMall/admin/payments/:paymentId/statuses")
export class ShoppingmallAdminPaymentsStatusesController {
  /**
   * Retrieve the status history for a payment managed by the platform.
   *
   * This PATCH operation allows authorized admin actors to search and filter
   * the temporal history of all status changes for a given payment, as well as
   * perform text or property-based queries on the audit log records. Returned
   * results are ordered by status change timestamp (changed_at) and include
   * both system-generated and admin-triggered status transitions for the target
   * payment, enabling deep traceability and business compliance review.
   *
   * Access is limited to admins due to financial/privacy sensitivity. The
   * operation validates the paymentId and supports pagination and search query
   * parameters via request body. Attempts to retrieve status history for
   * non-existent or unauthorized payment records will return appropriate error
   * responses.
   *
   * For related operations, use the payment detail retrieval endpoint for
   * current status, or the refunds endpoint for payment refund timeline.
   *
   * @param connection
   * @param paymentId Unique identifier (UUID) of the target payment for which
   *   status history is requested (global scope).
   * @param body Pagination and search filters for querying payment status
   *   history records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("paymentId")
    paymentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallPaymentStatus.IRequest,
  ): Promise<IPageIShoppingMallPaymentStatus> {
    try {
      return await patchShoppingMallAdminPaymentsPaymentIdStatuses({
        admin,
        paymentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific payment status transition event for a payment on the
   * shopping mall platform.
   *
   * This operation returns the full details of the requested status change
   * event, including old/new status values, the reason for the change,
   * timestamp, and information about the triggering actor. Intended for
   * auditing, compliance checking, and investigation of payment state issues,
   * it allows full traceability of how and when a payment's status changed.
   *
   * Sensitive details will only be exposed to authorized actors (e.g.,
   * admins/auditors), and attempts to access events for unrelated or
   * unauthorized payments will be denied. Error handling covers cases of
   * non-existent payments, invalid status log IDs, or insufficient permissions.
   * The data is sourced precisely from the shopping_mall_payment_statuses
   * Prisma model and cross-referenced to the payment indicated by paymentId.
   *
   * @param connection
   * @param paymentId Unique identifier (UUID) of the related payment whose
   *   status event is being queried.
   * @param statusId Unique identifier (UUID) of the requested payment status
   *   log record within the payment's history.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":statusId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("paymentId")
    paymentId: string & tags.Format<"uuid">,
    @TypedParam("statusId")
    statusId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallPaymentStatus> {
    try {
      return await getShoppingMallAdminPaymentsPaymentIdStatusesStatusId({
        admin,
        paymentId,
        statusId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
