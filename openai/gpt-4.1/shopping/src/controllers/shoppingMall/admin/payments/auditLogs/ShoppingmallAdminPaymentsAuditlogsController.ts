import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminPaymentsPaymentIdAuditLogs } from "../../../../../providers/patchShoppingMallAdminPaymentsPaymentIdAuditLogs";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminPaymentsPaymentIdAuditLogsAuditLogId } from "../../../../../providers/getShoppingMallAdminPaymentsPaymentIdAuditLogsAuditLogId";

import { IPageIShoppingMallPaymentAuditLog } from "../../../../../api/structures/IPageIShoppingMallPaymentAuditLog";
import { IShoppingMallPaymentAuditLog } from "../../../../../api/structures/IShoppingMallPaymentAuditLog";
import { IShoppingMallOrderAuditLog } from "../../../../../api/structures/IShoppingMallOrderAuditLog";

@Controller("/shoppingMall/admin/payments/:paymentId/auditLogs")
export class ShoppingmallAdminPaymentsAuditlogsController {
  /**
   * List and search audit log records for a payment from
   * shopping_mall_payment_audit_logs.
   *
   * Retrieve a filtered, paginated list of all audit log records associated
   * with a specific payment.
   *
   * This operation enables authorized admin users to search within all audit
   * log entries related to a given payment. Audit logs provide immutable
   * records of every relevant action (system or manual), including payment
   * creation, updates, callbacks, reversals, refunds, and more, with each
   * record timestamped for traceability. Results are filterable and sorted,
   * supporting advanced query structures via the request body: action type,
   * actor ID, time window, etc.
   *
   * Strict access control ensures only admins or audit investigators can use
   * this endpoint, preventing any exposure of payment audit data to
   * unauthorized actors. Pagination is required for large record sets.
   * Underlying data is stored in shopping_mall_payment_audit_logs model with
   * references to the payment specified by paymentId.
   *
   * @param connection
   * @param paymentId Unique identifier (UUID) of the payment whose audit logs
   *   are being queried.
   * @param body Filter, pagination, and search parameters for payment audit
   *   logs related to the specified payment.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("paymentId")
    paymentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallPaymentAuditLog.IRequest,
  ): Promise<IPageIShoppingMallPaymentAuditLog> {
    try {
      return await patchShoppingMallAdminPaymentsPaymentIdAuditLogs({
        admin,
        paymentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific order audit log event by payment and audit log ID from
   * shopping_mall_order_audit_logs.
   *
   * Retrieve detailed information about a single audit log entry connected to
   * the lifecycle of an order, identified by the provided payment and audit log
   * UUIDs.
   *
   * This endpoint exposes a full record of significant order actions, including
   * actor identities, event types, contextual metadata, and timestamped
   * snapshots. It allows system administrators, compliance officers, or
   * privileged support staff to investigate event histories, enforce business
   * accountability, and respond to queries or disputes regarding a payment's
   * history.
   *
   * Security for this operation is strict: Only users with administrative
   * authorization can access sensitive audit details, as order audit logs may
   * involve private customer, seller, or platform data. Attempts to access logs
   * without permission result in clear, auditable denial events. This API is
   * directly backed by the shopping_mall_order_audit_logs table, using joined
   * relations for contextual clarity.
   *
   * @param connection
   * @param paymentId Unique identifier (UUID) of the payment whose associated
   *   order's audit log is being retrieved.
   * @param auditLogId Unique identifier (UUID) of the audit log record to be
   *   retrieved, as logged in shopping_mall_order_audit_logs.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":auditLogId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("paymentId")
    paymentId: string & tags.Format<"uuid">,
    @TypedParam("auditLogId")
    auditLogId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderAuditLog> {
    try {
      return await getShoppingMallAdminPaymentsPaymentIdAuditLogsAuditLogId({
        admin,
        paymentId,
        auditLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
