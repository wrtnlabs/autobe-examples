import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminPayments } from "../../../../providers/postShoppingMallAdminPayments";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminPayments } from "../../../../providers/patchShoppingMallAdminPayments";
import { getShoppingMallAdminPaymentsPaymentId } from "../../../../providers/getShoppingMallAdminPaymentsPaymentId";
import { putShoppingMallAdminPaymentsPaymentId } from "../../../../providers/putShoppingMallAdminPaymentsPaymentId";
import { deleteShoppingMallAdminPaymentsPaymentId } from "../../../../providers/deleteShoppingMallAdminPaymentsPaymentId";

import { IShoppingMallPayment } from "../../../../api/structures/IShoppingMallPayment";
import { IPageIShoppingMallPayment } from "../../../../api/structures/IPageIShoppingMallPayment";

@Controller("/shoppingMall/admin/payments")
export class ShoppingmallAdminPaymentsController {
  /**
   * Initiate a new payment by providing all relevant details, including the
   * customer reference, payment amount, currency, method type, external payment
   * ID, transaction token, request timestamp, and links to the external
   * provider. This operation will check for uniqueness of transaction tokens
   * and external provider IDs to prevent double processing and fraud. Optional
   * fields like processed_at are set by the system or upon notification from
   * providers. Following submission, downstream payment provider workflows are
   * initiated by the system, and the resulting status changes are monitored via
   * webhook callbacks or internal state updates.
   *
   * Security and fraud prevention are key concerns—operations staff, not
   * customers, should create records directly. Access is restricted to
   * administrative actors managing payment flows or reconciling payments. Input
   * validation, idempotency enforcement (via transaction_token), and external
   * provider integration must all be carefully handled. Related operations
   * include updating payment status (PUT /payments/{paymentId}), and searching
   * for payments (PATCH /payments).
   *
   * @param connection
   * @param body Complete set of fields required to create a shopping mall
   *   payment record. These include customer, provider, amount, currency,
   *   method, status, external payment ID, transaction token, and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPayment.ICreate,
  ): Promise<IShoppingMallPayment> {
    try {
      return await postShoppingMallAdminPayments({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated, filtered list of payment records from the
   * shopping mall platform. This operation enables administrators to perform
   * powerful, structured searches across hundreds of thousands of payment
   * records, supporting advanced filters on payment status, method type,
   * provider, transaction token, and more. Query parameters are provided in the
   * request body for maximum flexibility, and results are sorted and paginated
   * for efficient processing.
   *
   * This operation is restricted exclusively to administrators due to the
   * sensitive and regulatory nature of payment data. Attempts by unauthorized
   * users (sellers, customers) are explicitly rejected and logged. The result
   * returns a page of summarized payment records, suitable for managing
   * reconciliation, compliance audits, or detailed platform reporting
   * purposes.
   *
   * When using this operation, clients should refer to the schema for allowed
   * request/response fields. Result ordering defaults to most recent payments
   * first unless specified otherwise in the query parameters. For complete
   * payment details, clients should follow up with the payment detail retrieval
   * endpoint.
   *
   * @param connection
   * @param body Search, filter, and pagination options for payments.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPayment.IRequest,
  ): Promise<IPageIShoppingMallPayment.ISummary> {
    try {
      return await patchShoppingMallAdminPayments({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Obtain all available data about a single payment processed within the
   * shopping mall system.
   *
   * This operation exposes every field from the payment's database record,
   * including the customer, payment provider, external transaction ID,
   * currency, status, and all change/audit timestamps. It is intended for
   * administrative investigation, compliance auditing, and reconciliation
   * workflows with financial partners.
   *
   * Only platform administrators and authorized payment operations staff should
   * have access to full payment details due to the financial and personal data
   * involved. The implementation expects stringent access control,
   * comprehensive logging of access for audit purposes, and may redact
   * sensitive information in responses unless explicitly authorized. Related
   * operations include searching for payments (PATCH /payments) and
   * administrative reconciliation flows.
   *
   * @param connection
   * @param paymentId Unique identifier (UUID) of the target payment record to
   *   retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":paymentId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("paymentId")
    paymentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallPayment> {
    try {
      return await getShoppingMallAdminPaymentsPaymentId({
        admin,
        paymentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update payment information for a specific payment record.
   *
   * This operation permits modification of mutable properties of a shopping
   * payment record. Critical attributes like 'amount', 'currency',
   * 'transaction_token', and 'external_payment_id' are immutable once the
   * record is created and should not be updated through this API. Instead,
   * fields such as 'status', 'processed_at', and other mutable
   * details—typically following status changes from asynchronous payment
   * providers or administrative tasks—can be changed as needed, subject to
   * rigorous validation.
   *
   * Authorization is strictly limited to system actors or admin users. A full
   * history of changes should be captured by the backend to support ongoing
   * financial audits. Validations ensure only legitimate status transitions are
   * permitted, and business logic should prevent unintentional loss of required
   * compliance data. The operation also updates the 'updated_at' timestamp, and
   * results in the latest version of the payment entity being returned.
   *
   * This operation is integral for integrating payment notifications from
   * external payment providers, supporting administrative updates for refunds,
   * dispute resolutions, or correction of payment state. All changes must be
   * independently auditable per financial recordkeeping standards.
   *
   * @param connection
   * @param paymentId Unique identifier of the payment record to be updated
   *   (shopping_mall_payments.id).
   * @param body Fields to update for the specified payment. Only editable
   *   properties (e.g., status, processed_at) can be changed. Immutable
   *   properties such as amount, currency, transaction_token, and
   *   external_payment_id are not modifiable.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":paymentId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("paymentId")
    paymentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallPayment.IUpdate,
  ): Promise<IShoppingMallPayment> {
    try {
      return await putShoppingMallAdminPaymentsPaymentId({
        admin,
        paymentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete (soft delete) a payment record in the shopping mall payments table.
   *
   * This operation sets the 'deleted_at' timestamp of a payment record to
   * indicate it is no longer active, complying with audit retention and
   * recordkeeping policies. The payment is excluded from most normal business
   * queries but is retained for future compliance, auditing, and reconciliation
   * purposes. This soft deletion method ensures no actual payment data is
   * erased from the underlying storage, protecting financial record integrity.
   *
   * Access is strictly restricted to highly privileged administrative actors.
   * Any attempt to erase an already deleted payment or a payment associated
   * with unresolved transactions should be denied with an explicit error
   * response. The deleted payment object is returned as confirmation, with
   * emphasis on the updated 'deleted_at' field to signal soft deletion state.
   *
   * This endpoint plays a critical role in corrective and compliance processes,
   * such as removing erroneous test data or fulfilling deletion requests as
   * part of legal regulations. All actions should be fully auditable, and any
   * failure due to business logic should return clear, actionable error
   * messages.
   *
   * @param connection
   * @param paymentId Unique identifier of the payment record to be deleted
   *   (shopping_mall_payments.id).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":paymentId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("paymentId")
    paymentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallPayment> {
    try {
      return await deleteShoppingMallAdminPaymentsPaymentId({
        admin,
        paymentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
