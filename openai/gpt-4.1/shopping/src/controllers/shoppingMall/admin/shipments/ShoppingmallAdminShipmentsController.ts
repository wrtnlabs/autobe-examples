import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminShipments } from "../../../../providers/postShoppingMallAdminShipments";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminShipments } from "../../../../providers/patchShoppingMallAdminShipments";
import { getShoppingMallAdminShipmentsShipmentId } from "../../../../providers/getShoppingMallAdminShipmentsShipmentId";
import { putShoppingMallAdminShipmentsShipmentId } from "../../../../providers/putShoppingMallAdminShipmentsShipmentId";
import { deleteShoppingMallAdminShipmentsShipmentId } from "../../../../providers/deleteShoppingMallAdminShipmentsShipmentId";

import { IShoppingMallShipment } from "../../../../api/structures/IShoppingMallShipment";
import { IPageIShoppingMallShipment } from "../../../../api/structures/IPageIShoppingMallShipment";

@Controller("/shoppingMall/admin/shipments")
export class ShoppingmallAdminShipmentsController {
  /**
   * Create a new shipment record for an order item, referencing a specific
   * order and assigning fulfillment responsibility to a shipping partner. This
   * operation requires that the target order and order item are valid and not
   * yet fulfilled or cancelled. Optionally, a carrier tracking code, initial
   * shipment status, shipping label manifest link, and provider response code
   * can be provided.
   *
   * Actor attribution must be provided: either an admin (for administrative
   * platform-initiated shipments) or a seller (for manual or self-fulfilled
   * shipments). The actor fields are mutually exclusive, but one must be set.
   * The shipping partner ID must reference a registered and active
   * shipping/logistics provider. Appropriate status transitions will be
   * enforced by the business logic depending on whether this is a
   * pre-fulfillment, pickup, or immediate delivery event.
   *
   * All shipment records include full audit trail with creator attribution, and
   * timestamps are managed for creation, updates, delivery, or cancellation as
   * relevant. Edge cases such as missing tracking information, label
   * non-issuance, or delayed carrier integration are handled gracefully, with
   * nullable fields indicating missing data at creation time. The payload
   * allows storing of partner label URLs and the current shipment status.
   * Related shipment update and cancellation operations are available for later
   * status modifications and logistics event handling.
   *
   * @param connection
   * @param body Creation information for a new shipment record, including
   *   order/item/partner IDs, status, actor attribution, and optional tracking
   *   or manifest fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallShipment.ICreate,
  ): Promise<IShoppingMallShipment> {
    try {
      return await postShoppingMallAdminShipments({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch a paginated and filtered list of shipment records for logistics
   * operations and monitoring.
   *
   * This endpoint allows users to search, sort, and filter shipments by
   * carrier, tracking information, shipment status, related orders or order
   * items, time windows (created or delivered at), and actor (which seller or
   * admin created it). Shipments are returned as a paged list, containing all
   * audit and reference information available for each result, such as tracking
   * code, partner, manifest/label location, shipment status, and relevant
   * timestamps. If provided, filter parameters may include combinations of
   * status, external response code, carrier, or actor identity.
   *
   * Security: Access to this endpoint can be restricted to actors with
   * operational, fulfillment, admin, or seller roles according to business
   * needs. Typically, logistics and warehouse actors use this endpoint for
   * operational workflow. Pagination and result filtering is required for all
   * accesses to guarantee performance and compliance with enterprise standards.
   * Sorting must be provided for common fields (created_at, status,
   * delivery_at). Sensitive fields (such as admin/seller identity) must be
   * filtered from responses if the actor is not authorized. Error responses
   * clearly indicate when filter criteria are invalid or when access is
   * restricted by user role.
   *
   * This operation is tightly coupled to the shopping_mall_shipments table and
   * related entities, including the Prisma schema and business rules documented
   * in requirements and schema comments. It should be coordinated with similar
   * list/index endpoints for orders and order items. Related operations include
   * GET /shipments/{shipmentId} for the detail view, creation endpoints (if
   * allowed), and shipment status tracking endpoints.
   *
   * @param connection
   * @param body Shipment search criteria and pagination/filter options
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallShipment.IRequest,
  ): Promise<IPageIShoppingMallShipment.ISummary> {
    try {
      return await patchShoppingMallAdminShipments({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch complete detail information for a single shipment record, given its
   * unique ID.
   *
   * This endpoint returns all attributes, references, and audit fields for a
   * shipment in the logistics subsystem. Included are links to order, item,
   * carrier; tracking and label/manifest references; carrier/provider codes;
   * actor identity; and a full audit trail of creation, updates, delivery, or
   * cancellation events. Shipments include their status (pending, ready,
   * picked_up, etc.), references to any involved actors, and all timestamps
   * available. Access policy can enforce that only authorized actors
   * (warehouse, admin, seller) see full actor detail fields—fields may be
   * redacted or hidden for users without required permissions. If the given
   * shipment is not found, or access is restricted, error responses describe
   * the failure reason precisely.
   *
   * This operation is implemented directly from the shopping_mall_shipments
   * table per the Prisma schema and must fully reflect all fields as described
   * in the schema commentary. It should be used to drill into detail after a
   * search or paged list result, and is related to update, status tracking, or
   * audit log endpoints (if available).
   *
   * @param connection
   * @param shipmentId Unique identifier of the target shipment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment> {
    try {
      return await getShoppingMallAdminShipmentsShipmentId({
        admin,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update shipment details—such as status, carrier tracking, manifests,
   * delivery/cancellation timestamps, or API provider result—by specifying the
   * shipmentId of the target shipment record. This operation allows status
   * updates for both administrative and manual (seller-driven) shipment
   * workflows, but does not permit changes to the base order, order item, or
   * shipping partner fields after creation.
   *
   * Acceptable status transitions are enforced in accordance with fulfillment
   * and return business rules. If updating status to 'delivered' or
   * 'cancelled', the corresponding delivery or cancellation timestamp must be
   * included in the request, ensuring proper auditability. Carrier tracking and
   * manifest/label links are modifiable as the shipment progresses, and
   * provider API result codes can be updated when available. Actor attribution
   * for the update (admin or seller) must be provided. All update operations
   * are fully auditable and time-stamped, with proper integration to logistics
   * or return flows as relevant.
   *
   * If validation fails due to invalid status transition or unauthorized actor
   * attempt, descriptive errors will be returned indicating the business rule
   * violation. Shipment state updates should be coordinated with related
   * shipment tracking history records for full event lifecycle management.
   *
   * @param connection
   * @param shipmentId Unique identifier of the target shipment record to
   *   update.
   * @param body Updatable fields for the shipment record, allowing for
   *   logistics status, tracking/manifest, provider response, and actor
   *   attribution changes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shipmentId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipment.IUpdate,
  ): Promise<IShoppingMallShipment> {
    try {
      return await putShoppingMallAdminShipmentsShipmentId({
        admin,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint deletes a shipment record from the system by its unique
   * identifier. Deleting a shipment is an irreversible operation and should
   * only be performed when the shipment has not been delivered, is not in
   * transit, or when allowed by platform business rules.
   *
   * Security controls ensure that only actors with explicit permission
   * (platform admins or the owning seller when applicable) can perform a
   * deletion. The system validates shipment status prior to deletion and
   * returns a descriptive error if the shipment cannot be removed due to
   * business constraints or logistical events already processed. Related audit
   * and tracking data will be evaluated for deletion or retention according to
   * regulatory compliance requirements.
   *
   * If dependent tracking histories exist or the shipment has progressed beyond
   * a cancellable state, the system will deny the request and provide details
   * in the error response. Related shipments for the same order or order item
   * will not be affected by this operation.
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment to be deleted. This is
   *   a globally unique UUID assigned to each shipment record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":shipmentId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminShipmentsShipmentId({
        admin,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
