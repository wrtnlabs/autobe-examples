import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminAuditLogs } from "../../../../providers/patchShoppingMallAdminAuditLogs";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminAuditLogsId } from "../../../../providers/getShoppingMallAdminAuditLogsId";

import { IPageIShoppingMallAuditLog } from "../../../../api/structures/IPageIShoppingMallAuditLog";
import { IShoppingMallAuditLog } from "../../../../api/structures/IShoppingMallAuditLog";

@Controller("/shoppingMall/admin/auditLogs")
export class ShoppingmallAdminAuditlogsController {
  /**
   * Provides administrators access to the full set of audit log records for
   * investigation or compliance review.
   *
   * This operation supports complex filtering, sorting, and pagination to help
   * admins pinpoint relevant events — such as changes to user data, permission
   * escalations, and regulated data accesses. Only admin actors may access this
   * functionality, reflecting the sensitive nature of audit data.
   *
   * Returned data includes details on the actor (admin/seller/customer/system),
   * change type, risk classification, compliance justification, and all
   * available event metadata per the audit log schema. Typically, admins use
   * this endpoint as the foundation for incident response, security validation,
   * or for performing regulatory data access reviews.
   *
   * @param connection
   * @param body Filter and pagination criteria for querying audit logs (e.g.,
   *   by change type, actor, risk, compliance tag, time range).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAuditLog.IRequest,
  ): Promise<IPageIShoppingMallAuditLog> {
    try {
      return await patchShoppingMallAdminAuditLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a single audit log entry from
   * shopping_mall_audit_logs, using its unique identifier as the primary data
   * key.
   *
   * This operation returns all principal fields for the audit log entry,
   * including the nature of the change (such as access, update,
   * permission_change, or data_export), full context about the actor
   * responsible (whether an admin, seller, or customer), applicable risk and
   * compliance details, and a complete textual or structured record of the
   * audited event. Timestamp information is provided for evidence and sequence
   * reconstruction.
   *
   * This endpoint is strictly read-only. It may be restricted to users with
   * elevated administrative or compliance roles due to the sensitive nature of
   * audit log data. The operation helps maintain transparency, fulfill
   * regulatory requirements, and provide tools for systematic security and
   * compliance review.
   *
   * If the unique identifier does not match any existing entry, an appropriate
   * error message indicating not found will be returned. Related APIs include
   * search/list operations for audit logs (not shown here) and endpoints to
   * retrieve actor detail records for any actor_id fields present in the
   * result.
   *
   * @param connection
   * @param id Unique identifier of the audit log entry to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAuditLog> {
    try {
      return await getShoppingMallAdminAuditLogsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
