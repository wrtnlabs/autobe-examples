import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminAdmins } from "../../../../providers/patchShoppingMallAdminAdmins";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminAdminsAdminId } from "../../../../providers/getShoppingMallAdminAdminsAdminId";
import { putShoppingMallAdminAdminsAdminId } from "../../../../providers/putShoppingMallAdminAdminsAdminId";
import { deleteShoppingMallAdminAdminsAdminId } from "../../../../providers/deleteShoppingMallAdminAdminsAdminId";

import { IPageIShoppingMallAdmin } from "../../../../api/structures/IPageIShoppingMallAdmin";
import { IShoppingMallAdmin } from "../../../../api/structures/IShoppingMallAdmin";

@Controller("/shoppingMall/admin/admins")
export class ShoppingmallAdminAdminsController {
  /**
   * Search and obtain a filtered, paginated list of all administrator accounts
   * registered within the shopping mall platform.
   *
   * This endpoint allows authorized users to execute sophisticated queries over
   * the shopping_mall_admins table, leveraging indexed fields such as email,
   * name (with partial or full text matching), account status, and verification
   * status. The request accepts typical search parameters, including page
   * number, page size, sort order, field selection, and arbitrary combination
   * of allowed filters. Leveraging database indexes, this operation is
   * optimized for administrators to quickly retrieve lists for audit, periodic
   * review, or mass communication with relevant admins.
   *
   * Results include key summary fields from the admin account, including email,
   * name, account status, and timestamps, but do not return sensitive data such
   * as password hashes. Fine-grained access control ensures that only users
   * with root-level platform roles can access this operation, as leaking
   * administrator details would create a severe security risk. If requested
   * filter criteria do not match any records, the result is an empty paginated
   * data set. Rate limiting and monitoring may be applied to prevent data
   * scraping or abuse.
   *
   * @param connection
   * @param body Search, filter, sorting, and pagination parameters for querying
   *   administrator accounts.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAdmin.IRequest,
  ): Promise<IPageIShoppingMallAdmin.ISummary> {
    try {
      return await patchShoppingMallAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete record for a specific administrator account by its
   * unique adminId, as stored in the shopping_mall_admins table.
   *
   * This endpoint allows authorized admin platform users to obtain all
   * relevant, non-sensitive information for a single administrator, including
   * their email, name, verification and account statuses, and record
   * timestamps. The adminId must be a valid UUID that exists in the database;
   * otherwise a not-found error is generated. No password or sensitive
   * authentication material is ever exposed in this response.
   *
   * Strict role-based access control ensures that only root admin users can
   * perform this operation, as administrator account details are considered
   * privileged. This operation is integral for audit, moderation, remediation,
   * and platform-wide governance. If used in conjunction with the search
   * operation, auditors can first enumerate admins using PATCH /admins, then
   * inspect details using this GET /admins/{adminId}.
   *
   * @param connection
   * @param adminId Unique identifier of the target platform administrator
   *   (UUID, primary key).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await getShoppingMallAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an administrator's account in the shopping mall platform.
   *
   * This API enables an active administrator to edit another administrator's
   * account details, such as email (which must remain unique per platform
   * rules), name, email verification status, and account status flags.
   * Modifications to the password_hash require secure handling and proper
   * validation. The administrator identified by the adminId path parameter is
   * targeted for modification. All update attempts are restricted to other
   * authenticated administrators and are subject to additional business
   * validation, such as prohibiting certain self-admin actions or steps
   * requiring multi-admin approval. The updated_at field records the datetime
   * of the latest change and is automatically managed by the system.
   *
   * All update actions are fully audited. Clients should expect update
   * validation errors if attempting to use duplicate emails or invalid status
   * transitions. Password changes must never expose plaintext values or hashes
   * in the API responses. Related operations include retrieving admin info and
   * removing an admin account.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator account.
   * @param body Administrator account update data for the specified adminId.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdmin.IUpdate,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await putShoppingMallAdminAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove an administrator account from the platform by administrator ID.
   *
   * The operation targets the admin account identified in the adminId path
   * parameter and performs a permanent deletion from the underlying
   * shopping_mall_admins table. Only authenticated administrators can perform
   * this operation and, depending on the business rules present, privileged or
   * critical accounts (such as the sole remaining admin or root-level
   * administrators) may be protected from removal. Deleted accounts are
   * immediately revoked from all administrative activity, and secret data
   * including credentials must be fully removed. All deletion actions are
   * logged for compliance and security. If invalid or protected accounts are
   * targeted, clear error responses must be issued.
   *
   * This operation does not return a response body on success. Clients may
   * reference logs for removal confirmation. Related operations include listing
   * administrators and updating admin account information.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
