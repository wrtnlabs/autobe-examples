import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminAdminsAdminIdSessions } from "../../../../../providers/patchShoppingMallAdminAdminsAdminIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/getShoppingMallAdminAdminsAdminIdSessionsSessionId";
import { deleteShoppingMallAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/deleteShoppingMallAdminAdminsAdminIdSessionsSessionId";

import { IPageIShoppingMallAdminSession } from "../../../../../api/structures/IPageIShoppingMallAdminSession";
import { IShoppingMallAdminSession } from "../../../../../api/structures/IShoppingMallAdminSession";

@Controller("/shoppingMall/admin/admins/:adminId/sessions")
export class ShoppingmallAdminAdminsSessionsController {
  /**
   * Retrieve a filtered and paginated list of all authenticated session logs
   * belonging to a specific shopping mall platform administrator.
   *
   * The endpoint allows authorized admin actors to audit login sessions, view
   * historical access patterns, cross-check origin IPs, and analyze URL and
   * referrer activities over time. The operation supports searching and sorting
   * by timestamp, IP address, referrer, and access URLs, and implements robust
   * pagination for scalable results regardless of session volume.
   *
   * Security: Only authenticated admins may access other admin session records;
   * authorization will be enforced on the adminId path parameter. The operation
   * integrates with shopping_mall_admin_sessions, providing access to all
   * session fields and ensuring all relationships and indexes from the Prisma
   * schema are respected. This forms the backbone of audit and compliance
   * workflows for administrator activity, enabling issue forensics, fraud
   * detection, and detailed oversight of privileged users.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin whose sessions are
   *   being queried (UUID, global scope).
   * @param body Search and filtering criteria for the admin session list,
   *   including optional pagination and query fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdminSession.IRequest,
  ): Promise<IPageIShoppingMallAdminSession.ISummary> {
    try {
      return await patchShoppingMallAdminAdminsAdminIdSessions({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * View a detailed record of an individual admin dashboard/API session by
   * specifying both the target admin's UUID and the session's UUID as path
   * parameters.
   *
   * This endpoint returns all session fields from the
   * shopping_mall_admin_sessions table, including timestamps, originating IP
   * address, accessed and referrer URLs, expiration status, and the linked
   * admin_id. Security controls ensure that only authorized admin actors can
   * access this sensitive audit data, with identity and permission enforcement
   * on both path parameters. The endpoint supports audit and compliance
   * workflows including threat analysis, incident forensics, and resolution of
   * suspicious activity by providing granular insight into admin session
   * behaviors and related platform events.
   *
   * @param connection
   * @param adminId Unique identifier of the admin owner of the session (UUID,
   *   global scope).
   * @param sessionId Unique identifier of the session record to retrieve (UUID,
   *   globally unique).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdminSession> {
    try {
      return await getShoppingMallAdminAdminsAdminIdSessionsSessionId({
        admin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Erase (delete) a specific admin session record associated with a particular
   * admin account from the platform.
   *
   * This operation enables a platform administrator to invalidate and
   * permanently remove the record of an admin session, identified by both
   * adminId (the owning admin's unique identifier) and sessionId (the specific
   * session's unique identifier). Deleting a session record may be required for
   * compliance actions, security investigations, or forcibly logging an admin
   * out of the system.
   *
   * This action does not modify user credentials or the admin's general account
   * status—it applies only to a single session instance. The adminId and
   * sessionId combination must correspond to existing records in the
   * 'shopping_mall_admin_sessions' table, and attempts to erase non-existent
   * sessions will result in an error response or no-operation.
   *
   * Security considerations: Only users with admin-actor status can invoke this
   * operation. Adequate auditing should log this action for compliance. If the
   * session is currently active, the admin may be required to re-authenticate
   * for further actions, depending on system session policies.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin account (global
   *   scope).
   * @param sessionId Unique identifier of the specific admin session record
   *   (scoped to admin).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminAdminsAdminIdSessionsSessionId({
        admin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
