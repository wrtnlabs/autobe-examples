import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallAdminReviews } from "../../../../providers/patchShoppingMallAdminReviews";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

import { IPageIShoppingMallReview } from "../../../../api/structures/IPageIShoppingMallReview";
import { IShoppingMallReview } from "../../../../api/structures/IShoppingMallReview";

@Controller("/shoppingMall/admin/reviews")
export class ShoppingmallAdminReviewsController {
  /**
   * Perform advanced search and retrieval of product reviews, supporting
   * filtering by various attributes such as product, SKU, customer, moderation
   * state, and keyword matches on title or body fields.
   *
   * The operation provides pagination, sorting, and multi-criteria filtering
   * for platform admins, allowing moderation, analytics, and business process
   * support. Users may filter by product or SKU to review feedback for specific
   * catalog items, analyze trends in ratings, or identify potential abuse
   * cases. Authorization checks enforce access: regular users can search their
   * own submitted reviews, while admins may search any review. Search logic
   * relies on full-text GIN indexes on title and body for efficient keyword
   * queries, and supports state, date, or entity-related filters as
   * appropriate. The underlying shopping_mall_reviews schema details all
   * relevant fields, relationships, and business rules.
   *
   * @param connection
   * @param body Advanced search query for filtering, sorting, and paginating
   *   reviews based on product, SKU, customer, moderation state, keywords, and
   *   time ranges.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallReview.IRequest,
  ): Promise<IPageIShoppingMallReview.ISummary> {
    try {
      return await patchShoppingMallAdminReviews({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
