import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminReviewsReviewIdStatusHistories } from "../../../../../providers/patchShoppingMallAdminReviewsReviewIdStatusHistories";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminReviewsReviewIdStatusHistoriesStatusHistoryId } from "../../../../../providers/getShoppingMallAdminReviewsReviewIdStatusHistoriesStatusHistoryId";

import { IPageIShoppingMallReviewStatusHistory } from "../../../../../api/structures/IPageIShoppingMallReviewStatusHistory";
import { IShoppingMallReviewStatusHistory } from "../../../../../api/structures/IShoppingMallReviewStatusHistory";

@Controller("/shoppingMall/admin/reviews/:reviewId/statusHistories")
export class ShoppingmallAdminReviewsStatushistoriesController {
  /**
   * Retrieve a filtered and paginated list of status history events associated
   * with a specific product review. This operation provides advanced query
   * capabilities to search, filter, sort, and page through the status history
   * records, allowing for detailed audit analysis and historical review
   * progression.
   *
   * The status histories reflect all moderation events (such as approval,
   * rejection, flagging), user withdrawals, and administrative actions. The
   * operation allows administrative actors to review the full chain of status
   * transitions for compliance, dispute resolution, or abuse analysis.
   *
   * Security is critical: only authorized admin or moderator actors can access
   * this sensitive moderation/audit history. All queries are rate-limited and
   * auditable for compliance. Results are governed by RBAC rules defined in the
   * requirements and enforced at the provider level. The response includes
   * summary information suitable for list and dashboard views, optimized for
   * audit and moderation team workflows.
   *
   * @param connection
   * @param reviewId Unique identifier of the target product review.
   * @param body Filtering, sorting, and pagination request for searching status
   *   history records related to the review.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewStatusHistory.IRequest,
  ): Promise<IPageIShoppingMallReviewStatusHistory.ISummary> {
    try {
      return await patchShoppingMallAdminReviewsReviewIdStatusHistories({
        admin,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the details of a specific status history record associated with a
   * product review. This operation returns the complete information for one
   * event in the review's moderation history, including status, reason, actor,
   * and timestamp.
   *
   * This operation supports audit, compliance, and dispute resolution scenarios
   * where understanding the history and reason for a review's state is
   * required. It enforces strict access controls; only admin or moderator
   * actors may view granular moderation histories due to the sensitivity of
   * audit trail information. Data returned is based strictly on the current
   * database schema, with no extraneous or system-generated fields.
   *
   * Related endpoint: Use the PATCH /reviews/{reviewId}/statusHistories to
   * retrieve the full history for auditing or dashboard purposes.
   *
   * @param connection
   * @param reviewId Unique identifier of the target product review.
   * @param statusHistoryId Unique identifier of the target status history
   *   record for the given review.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":statusHistoryId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("statusHistoryId")
    statusHistoryId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReviewStatusHistory> {
    try {
      return await getShoppingMallAdminReviewsReviewIdStatusHistoriesStatusHistoryId(
        {
          admin,
          reviewId,
          statusHistoryId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
