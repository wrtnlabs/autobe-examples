import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminReviewsReviewIdResponses } from "../../../../../providers/patchShoppingMallAdminReviewsReviewIdResponses";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminReviewsReviewIdResponsesResponseId } from "../../../../../providers/getShoppingMallAdminReviewsReviewIdResponsesResponseId";
import { deleteShoppingMallAdminReviewsReviewIdResponsesResponseId } from "../../../../../providers/deleteShoppingMallAdminReviewsReviewIdResponsesResponseId";

import { IPageIShoppingMallReviewResponse } from "../../../../../api/structures/IPageIShoppingMallReviewResponse";
import { IShoppingMallReviewResponse } from "../../../../../api/structures/IShoppingMallReviewResponse";

@Controller("/shoppingMall/admin/reviews/:reviewId/responses")
export class ShoppingmallAdminReviewsResponsesController {
  /**
   * Search and paginate seller responses tied to a specific customer review
   * (shopping_mall_review_responses table).
   *
   * Retrieve a paginated and filtered list of seller responses associated with
   * a specific product review.
   *
   * This operation enables users to search, filter, and page through all
   * response entries written by sellers in reply to the specified customer
   * review. Results can be filtered by moderation status, withdrawal date,
   * seller identity, and date range of creation or update.
   *
   * Strict access controls are enforced: only authorized actors (primarily
   * admins and moderators) may inspect all seller responses, while sellers and
   * customers may only see responses relevant to their own products or reviews.
   * The system must redact sensitive or non-public data for unauthorized
   * actors.
   *
   * The underlying table, shopping_mall_review_responses, supports full
   * auditability, with all responses traceable to their review, authoring
   * seller, and session. This operation is fundamental for moderation panels,
   * seller dashboards, and customer notification flows.
   *
   * @param connection
   * @param reviewId Unique identifier of the reviewed customer review
   *   (shopping_mall_reviews.id) for which to fetch associated seller
   *   responses.
   * @param body Filter, sorting, and pagination options for seller responses
   *   related to the specified review.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewResponse.IRequest,
  ): Promise<IPageIShoppingMallReviewResponse.ISummary> {
    try {
      return await patchShoppingMallAdminReviewsReviewIdResponses({
        admin,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the detailed information for a specific seller response related to
   * a customer review (shopping_mall_review_responses table).
   *
   * Retrieve the full detailed information of a seller's response to a specific
   * customer review, based on the given review and response identifiers.
   *
   * This operation fetches all relevant fields, including the response body,
   * moderation status and reason, creation/update timestamps, withdrawal info,
   * and traceability links (such as seller and session references). It ensures
   * audit and moderation requirements are met, showing additional diagnostic
   * info for privileged actors.
   *
   * Access is enforced according to user actor and relationship to the review
   * or seller—admins and moderators may view all, other actors only their own.
   * This operation uses the shopping_mall_review_responses table for lookup. It
   * is critical for transparency, dispute resolution, and platform trust.
   *
   * @param connection
   * @param reviewId Unique identifier of the customer review
   *   (shopping_mall_reviews.id) to which this response belongs.
   * @param responseId Unique identifier of the seller response
   *   (shopping_mall_review_responses.id) to retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":responseId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("responseId")
    responseId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReviewResponse> {
    try {
      return await getShoppingMallAdminReviewsReviewIdResponsesResponseId({
        admin,
        reviewId,
        responseId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a specific seller's response to a customer review
   * (shopping_mall_review_responses table).
   *
   * Delete a specific seller's response to a customer review.
   *
   * This endpoint is used when a seller, or an admin on their behalf, needs to
   * remove their response to a product review, for reasons such as moderation,
   * policy violation, or upon request. The DELETE operation targets the
   * shopping_mall_review_responses table, which enforces a single seller
   * response per customer review and ties responses to both seller and review
   * records.
   *
   * User authentication is required. Sellers may only delete their own
   * responses, while admins may delete any response for moderation and
   * oversight. The record is soft-deleted by setting the deleted_at field with
   * the current timestamp, allowing audit retention and potential recovery
   * within the platform's review/dispute process. Attempts to delete
   * already-deleted or non-existent responses will return a not found or gone
   * status. Deleting a response does not affect the visibility or moderation
   * status of the original review. Related operations include: creating a
   * response (POST), retrieving a response (GET), and updating a response
   * (PUT).
   *
   * @param connection
   * @param reviewId Unique identifier of the reviewed customer review (UUID
   *   referencing shopping_mall_reviews.id).
   * @param responseId Unique identifier of the seller's review response (UUID
   *   referencing shopping_mall_review_responses.id).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":responseId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("responseId")
    responseId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminReviewsReviewIdResponsesResponseId({
        admin,
        reviewId,
        responseId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
