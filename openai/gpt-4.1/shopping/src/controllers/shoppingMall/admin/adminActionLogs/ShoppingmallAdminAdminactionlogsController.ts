import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminAdminActionLogs } from "../../../../providers/patchShoppingMallAdminAdminActionLogs";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminAdminActionLogsId } from "../../../../providers/getShoppingMallAdminAdminActionLogsId";

import { IPageIShoppingMallAdminActionLog } from "../../../../api/structures/IPageIShoppingMallAdminActionLog";
import { IShoppingMallAdminActionLog } from "../../../../api/structures/IShoppingMallAdminActionLog";

@Controller("/shoppingMall/admin/adminActionLogs")
export class ShoppingmallAdminAdminactionlogsController {
  /**
   * Retrieve a filtered, paginated list of administrative action logs capturing
   * all privileged operations performed by platform admins. This operation
   * enables administrators and compliance auditors to review system changes,
   * user interventions, and security-impacting actions in a format suitable for
   * oversight and investigation.
   *
   * The response includes summary information from each log record, such as
   * actor, action type, target references, and timestamp. Advanced filtering is
   * supported on action_type, responsible admin, and time window to narrow
   * results for compliance reviews or security inquiries.
   *
   * Sensitive information is restricted to users with explicit administrative
   * privileges. Pagination and sorting are provided to manage potentially high
   * volumes of audit records, while summary view provides essential visibility
   * without exposing raw context data. Only authorized actor(s) may access this
   * operation, and usage is tracked for further compliance linkage.
   *
   * @param connection
   * @param body Query filter, sorting, and pagination configuration for
   *   searching admin action logs.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAdminActionLog.IRequest,
  ): Promise<IPageIShoppingMallAdminActionLog.ISummary> {
    try {
      return await patchShoppingMallAdminAdminActionLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch the detailed record of a single admin action log by unique
   * identifier. Provides complete audit information such as actor, action type,
   * timestamp, and context references, as well as any notes or additional
   * structured data attached at the time of the action.
   *
   * Intended for administrative and compliance users conducting in-depth
   * investigations, dispute trail reconstruction, or system audits. The
   * operation enforces strict access controls to ensure only authorized
   * administrator actors can access sensitive visibility over privileged
   * platform operations and their exact context.
   *
   * Returns all available fields for the given admin action log, correlating to
   * the database schema, including context_info (if present). Usage is
   * monitored and associated with compliance event tracking. Related endpoints
   * allow batch retrieval, aggregation, or compliance reporting.
   *
   * @param connection
   * @param id Unique identifier of the admin action log entry (UUID format).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdminActionLog> {
    try {
      return await getShoppingMallAdminAdminActionLogsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
