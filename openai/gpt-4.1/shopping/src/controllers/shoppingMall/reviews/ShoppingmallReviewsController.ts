import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallReviewsReviewId } from "../../../providers/getShoppingMallReviewsReviewId";
import { postShoppingMallReviews } from "../../../providers/postShoppingMallReviews";

import { IShoppingMallReview } from "../../../api/structures/IShoppingMallReview";

@Controller("/shoppingMall/reviews")
export class ShoppingmallReviewsController {
  /**
   * Retrieve the full details for a specific product review in the system. This
   * endpoint allows clients to fetch all available information about a review
   * by providing the unique identifier (UUID) for that review.
   *
   * The response includes the text content (title, body), status flags
   * (is_draft, moderation_status, withdrawn_at), relationships to the authoring
   * customer and session, the related product/SKU, order, order item, product
   * rating, and all relevant timestamps (created_at, updated_at, deleted_at if
   * soft-deleted). This ensures full contextual traceability for moderation and
   * audit.
   *
   * Use this operation to display review details in customer-facing pages,
   * moderation queues, seller dashboards, or administrative tools. Security and
   * visibility rules should ensure only authorized users view personally
   * identifiable information or system-sensitive moderation content. The
   * operation references the shopping_mall_reviews Prisma schema to guarantee
   * data completeness and correct linkage to related entities.
   *
   * Error handling covers missing or non-existent records, permission denials,
   * and soft-deleted/withdrawn reviews, with responses that comply with
   * established error and data presentation patterns.
   *
   * @param connection
   * @param reviewId Unique identifier (UUID) of the target review to retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reviewId")
  public async at(
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReview> {
    try {
      return await getShoppingMallReviewsReviewId({
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new product review for a purchased product SKU via this endpoint.
   * The request must specify the customer, session, product, SKU, related order
   * and order item (to ensure the reviewer actually purchased the product),
   * associated product rating, and all review content fields (title, body).
   * Status fields (is_draft, moderation_status, withdrawn_at) will be set based
   * on default values and business validation.
   *
   * The endpoint enforces that the customer matches a valid, completed purchase
   * of the SKU and order item and that the same order item can only be reviewed
   * once (uniqueness constraint). Validation covers mandatory content, body
   * length (min 10, max 1000 characters), moderation business rules, and
   * security for session and customer identity. On successful creation, the
   * full review record is returned including all system/populated fields.
   *
   * Error scenarios are communicated for invalid purchase, duplicate review,
   * moderation rejection, or request body violations. This endpoint references
   * the shopping_mall_reviews Prisma schema and is integral to authentic
   * customer feedback and platform transparency controls.
   *
   * @param connection
   * @param body Information necessary to create a new product review, including
   *   customer, session, product, SKU, order/item, rating, and content fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: IShoppingMallReview.ICreate,
  ): Promise<IShoppingMallReview> {
    try {
      return await postShoppingMallReviews({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
