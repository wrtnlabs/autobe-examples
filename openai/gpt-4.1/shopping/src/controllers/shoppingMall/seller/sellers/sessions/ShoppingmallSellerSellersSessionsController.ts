import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallSellerSellersSellerIdSessions } from "../../../../../providers/patchShoppingMallSellerSellersSellerIdSessions";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerSellersSellerIdSessionsSessionId } from "../../../../../providers/getShoppingMallSellerSellersSellerIdSessionsSessionId";
import { deleteShoppingMallSellerSellersSellerIdSessionsSessionId } from "../../../../../providers/deleteShoppingMallSellerSellersSellerIdSessionsSessionId";

import { IPageIShoppingMallSellerSession } from "../../../../../api/structures/IPageIShoppingMallSellerSession";
import { IShoppingMallSellerSession } from "../../../../../api/structures/IShoppingMallSellerSession";

@Controller("/shoppingMall/seller/sellers/:sellerId/sessions")
export class ShoppingmallSellerSellersSessionsController {
  /**
   * Retrieve a paginated, filterable list of session records belonging to a
   * specific seller account.
   *
   * This endpoint enables sellers or administrators to view recent and
   * historical login session activity for the specified seller, useful for
   * auditing access, device and browser usage patterns, and security reviews.
   * Each session includes creation time, potential expiration, IP address,
   * referrer information, and links to the seller it belongs to.
   *
   * Security is critical: Only the seller themselves or administrative actor(s)
   * may list sessions for an account, as these may contain sensitive device,
   * IP, and login metadata. Search parameters allow for filtering by login time
   * range, expiration state, or IP/network. The endpoint leverages the
   * subsidiary relationship of sessions to sellers as defined in the Prisma
   * schema, and always expects a valid sellerId as a required path parameter.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller. This must be the
   *   primary key UUID field from shopping_mall_sellers (global scope).
   * @param body Filter, search, and pagination parameters for seller session
   *   records, supporting time range and IP filtering.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSellerSession.IRequest,
  ): Promise<IPageIShoppingMallSellerSession.ISummary> {
    try {
      return await patchShoppingMallSellerSellersSellerIdSessions({
        seller,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete details for a specific authenticated session record
   * for a given seller.
   *
   * This endpoint allows sellers or administrative actors to view in-depth
   * information on a single session event, including login source, IP, referrer
   * details, creation and expiry timestamps, and other audit-trail relevant
   * metadata.
   *
   * The session record is always contextualized to the owner seller, scoped by
   * the sellerId primary key, and must reference a sessionId corresponding to
   * shopping_mall_seller_sessions. Only the relevant seller or an admin may
   * access these details for purposes including monitoring suspicious activity,
   * tracking unauthorized logins, or reviewing access history. Proper
   * authorization checks are enforced at the business logic layer, and access
   * is denied if session/seller linkage is invalid or the actor lacks
   * permission.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller. This must be the
   *   primary key UUID field from shopping_mall_sellers (global scope).
   * @param sessionId Unique identifier for the session record belonging to the
   *   seller. This is the primary key UUID field from
   *   shopping_mall_seller_sessions (scoped to the specified seller).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerSession> {
    try {
      return await getShoppingMallSellerSellersSellerIdSessionsSessionId({
        seller,
        sellerId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a seller's dashboard/session record, ending the session and revoking
   * associated access tokens immediately.
   *
   * This operation allows an authenticated seller to explicitly close/out one
   * of their sessions, whether for device management, security concerns, or
   * general housekeeping. The shopping_mall_seller_sessions schema enforces a
   * strict relationship to the parent seller entity via the
   * shopping_mall_seller_id foreign key, guaranteeing session ownership.
   *
   * Security: Only the owner seller can delete their session; admin-initiated
   * deletions should use a separate operation. Session expiry and revocation
   * are processed as part of this operation's logic. The database entry is
   * permanently deleted; soft-deletes are not employed for sessions.
   *
   * Audit trails and security logs capture the source, time, and cause of
   * session revocation for compliance monitoring. The related seller's session
   * list may be refreshed after this operation to reflect the change.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller who owns the session.
   * @param sessionId Unique identifier of the session to be deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerSellersSellerIdSessionsSessionId({
        seller,
        sellerId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
