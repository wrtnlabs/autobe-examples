import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallSellerSellersSellerIdAddresses } from "../../../../../providers/patchShoppingMallSellerSellersSellerIdAddresses";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerSellersSellerIdAddressesAddressId } from "../../../../../providers/getShoppingMallSellerSellersSellerIdAddressesAddressId";
import { putShoppingMallSellerSellersSellerIdAddressesAddressId } from "../../../../../providers/putShoppingMallSellerSellersSellerIdAddressesAddressId";
import { deleteShoppingMallSellerSellersSellerIdAddressesAddressId } from "../../../../../providers/deleteShoppingMallSellerSellersSellerIdAddressesAddressId";

import { IPageIShoppingMallAddress } from "../../../../../api/structures/IPageIShoppingMallAddress";
import { IShoppingMallAddress } from "../../../../../api/structures/IShoppingMallAddress";

@Controller("/shoppingMall/seller/sellers/:sellerId/addresses")
export class ShoppingmallSellerSellersAddressesController {
  /**
   * Retrieve a filtered and paginated list of addresses associated with the
   * specified seller account, supporting advanced search, filter, and sorting
   * capabilities.
   *
   * This enables sellers to view and manage their own shipping, billing, and
   * business addresses. The shopping_mall_addresses schema includes all
   * structured address fields (full name, street, city, province, postal code,
   * country, phone) and indicates if each address is the default address for
   * that seller account.
   *
   * Security and Ownership: Sellers may only access addresses where
   * shopping_mall_seller_id matches their own authenticated user identity. Up
   * to 10 addresses may be stored per seller, and administrators may have
   * delegated access through alternate privileged endpoints.
   *
   * The search request body supports pagination, multi-criteria filtering
   * (e.g., by city, is_default), and can sort by creation date or other indexed
   * field. Related operations include address creation, update, and deletion.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller whose addresses are being
   *   retrieved.
   * @param body Search criteria, filter settings, and pagination parameters for
   *   retrieving seller addresses.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAddress.IRequest,
  ): Promise<IPageIShoppingMallAddress.ISummary> {
    try {
      return await patchShoppingMallSellerSellersSellerIdAddresses({
        seller,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a detailed address record associated with a registered seller
   * account.
   *
   * This operation allows an authenticated seller or platform admin to retrieve
   * a complete address record by providing both the seller's unique identifier
   * (sellerId) and the unique address identifier (addressId). The address
   * includes structured fields such as full name, street, city, province,
   * postal code, country, phone, and whether it is the default address for the
   * seller.
   *
   * Security is strictly enforced—only the seller to whom the address belongs
   * or an admin may read this record. The system checks that the address is
   * actually linked to the provided sellerId, ensuring cross-account address
   * access is impossible. The endpoint is essential for both displaying seller
   * information on business documents and supporting seller-side address
   * management. In typical workflows, this endpoint supports seller onboarding,
   * tax documentation, and logistics integrations.
   *
   * If the sellerId or addressId is invalid, or the address does not belong to
   * the seller, the system returns a not-found or unauthorized error. This
   * operation is related to management endpoints for creating, updating, or
   * deleting seller addresses, but is strictly for retrieval of a single
   * record.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller who owns the address.
   * @param addressId Unique identifier of the address to retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":addressId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAddress> {
    try {
      return await getShoppingMallSellerSellersSellerIdAddressesAddressId({
        seller,
        sellerId,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the information of a specific address owned by a seller.
   *
   * This operation is available to authenticated sellers on their own address
   * records as well as platform admins for platform management purposes. By
   * specifying both sellerId and addressId, the system locates the target
   * address and allows updates to structured address fields: full name, street,
   * city, province, postal code, country, phone, and the default address flag.
   * All fields are validated for presence and data type, with the system
   * ensuring that updated addresses continue to meet formatting requirements
   * for postal operations.
   *
   * Robust permission checks ensure that only the owning seller or an admin can
   * update an address; attempts to edit addresses belonging to other entities
   * are blocked. The system also ensures that the address is correctly
   * associated with the targeted seller and disallows updates that would break
   * referential integrity. Typical use cases include updating shipping or
   * billing locations, or revising seller documentation details. Related
   * endpoints include retrieval, deletion, and creation of address records.
   *
   * Error handling covers not-found scenarios, validation errors, and
   * unauthorized attempts.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller owning the address to
   *   update.
   * @param addressId Unique identifier of the address to update.
   * @param body Updated address data for the seller address record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":addressId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAddress.IUpdate,
  ): Promise<IShoppingMallAddress> {
    try {
      return await putShoppingMallSellerSellersSellerIdAddressesAddressId({
        seller,
        sellerId,
        addressId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a business address associated with a registered seller from the
   * system.
   *
   * This API operation enables authorized sellers or platform administrators to
   * permanently erase an address within their address book. Addresses are
   * strictly linked either to a seller or customer, so the correct address is
   * unambiguously identified by the combined sellerId and addressId path
   * parameters.
   *
   * Security is critical: only authorized sellers (who own the address) or
   * platform admins may invoke this operation. Ownership is verified based on
   * the seller's session and address linkage. Upon execution, the address is
   * permanently deleted from the database (no soft delete is supported as per
   * the Prisma schema). Dependent workflows—such as order fulfillment or
   * compliance checks—must validate address existence before referencing this
   * record.
   *
   * Related operations include listing all addresses for a seller and updating
   * address details. Error handling covers scenarios where a non-existent or
   * mismatched addressId/sellerId is provided, returning appropriate not-found
   * or forbidden errors.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller who owns the address to be
   *   deleted.
   * @param addressId Unique identifier of the address to erase from the
   *   seller's address book.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":addressId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerSellersSellerIdAddressesAddressId({
        seller,
        sellerId,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
