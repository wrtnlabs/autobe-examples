import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerReviewsReviewIdResponses } from "../../../../../providers/postShoppingMallSellerReviewsReviewIdResponses";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerReviewsReviewIdResponsesResponseId } from "../../../../../providers/putShoppingMallSellerReviewsReviewIdResponsesResponseId";
import { deleteShoppingMallSellerReviewsReviewIdResponsesResponseId } from "../../../../../providers/deleteShoppingMallSellerReviewsReviewIdResponsesResponseId";

import { IShoppingMallReviewResponse } from "../../../../../api/structures/IShoppingMallReviewResponse";

@Controller("/shoppingMall/seller/reviews/:reviewId/responses")
export class ShoppingmallSellerReviewsResponsesController {
  /**
   * Create a new response to a customer review, allowing a seller to publicly
   * address and clarify feedback on their product. This fosters dialog and
   * transparency between customers and sellers.
   *
   * The seller must be authenticated and be the actual owner of the relevant
   * product. The operation enforces strict ownership validation, ensuring that
   * only the seller associated with the product reviewed can respond. Each
   * review can have no more than one seller response; attempts to create
   * additional responses are rejected.
   *
   * Moderation status and reasons are managed at creation according to platform
   * policies. Created responses are linked directly to the review and are
   * visible alongside the original review, supporting customer service and
   * brand reputation efforts. The response includes traceability to the seller
   * account and session for compliance and auditing. Related API operations
   * include updating or withdrawing a response and retrieving review with
   * associated seller replies.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review to which the
   *   response will be attached.
   * @param body Seller response creation payload.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewResponse.ICreate,
  ): Promise<IShoppingMallReviewResponse> {
    try {
      return await postShoppingMallSellerReviewsReviewIdResponses({
        seller,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing seller response for a specific product review. This
   * enables the seller to edit their original reply for clarification,
   * correction, or content improvement.
   *
   * The seller must be authenticated, and only the owner of the response (or an
   * authorized admin) can update it. The operation performs strict verification
   * of seller identity and editability, disallowing unauthorized updates or
   * edits after moderation lock. Any changes to moderation status or withdrawal
   * timestamp must comply with policy.
   *
   * Updates are fully audited, maintaining a history of changes for compliance
   * and trust. The updated response is returned with all fields, supporting
   * auditability and transparency. Related operations include creating a new
   * response and withdrawing or moderating responses.
   *
   * @param connection
   * @param reviewId Unique identifier of the review for which the response was
   *   written.
   * @param responseId Unique identifier of the seller's review response to
   *   update.
   * @param body Seller review response update payload.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":responseId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("responseId")
    responseId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewResponse.IUpdate,
  ): Promise<IShoppingMallReviewResponse> {
    try {
      return await putShoppingMallSellerReviewsReviewIdResponsesResponseId({
        seller,
        reviewId,
        responseId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific seller's response to a customer review.
   *
   * This endpoint is used when a seller, or an admin on their behalf, needs to
   * remove their response to a product review, for reasons such as moderation,
   * policy violation, or upon request. The DELETE operation targets the
   * shopping_mall_review_responses table, which enforces a single seller
   * response per customer review and ties responses to both seller and review
   * records.
   *
   * User authentication is required. Sellers may only delete their own
   * responses, while admins may delete any response for moderation and
   * oversight. The record is soft-deleted by setting the deleted_at field with
   * the current timestamp, allowing audit retention and potential recovery
   * within the platform's review/dispute process. Attempts to delete
   * already-deleted or non-existent responses will return a not found or gone
   * status. Deleting a response does not affect the visibility or moderation
   * status of the original review. Related operations include: creating a
   * response (POST), retrieving a response (GET), and updating a response
   * (PUT).
   *
   * @param connection
   * @param reviewId Unique identifier of the reviewed customer review (UUID
   *   referencing shopping_mall_reviews.id).
   * @param responseId Unique identifier of the seller's review response (UUID
   *   referencing shopping_mall_review_responses.id).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":responseId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("responseId")
    responseId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerReviewsReviewIdResponsesResponseId({
        seller,
        reviewId,
        responseId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
