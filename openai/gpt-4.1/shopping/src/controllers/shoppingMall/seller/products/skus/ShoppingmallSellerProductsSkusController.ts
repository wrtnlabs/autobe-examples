import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerProductsProductIdSkus } from "../../../../../providers/postShoppingMallSellerProductsProductIdSkus";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerProductsProductIdSkus } from "../../../../../providers/patchShoppingMallSellerProductsProductIdSkus";
import { putShoppingMallSellerProductsProductIdSkusSkuId } from "../../../../../providers/putShoppingMallSellerProductsProductIdSkusSkuId";
import { deleteShoppingMallSellerProductsProductIdSkusSkuId } from "../../../../../providers/deleteShoppingMallSellerProductsProductIdSkusSkuId";

import { IShoppingMallProductSku } from "../../../../../api/structures/IShoppingMallProductSku";
import { IPageIShoppingMallProductSku } from "../../../../../api/structures/IPageIShoppingMallProductSku";

@Controller("/shoppingMall/seller/products/:productId/skus")
export class ShoppingmallSellerProductsSkusController {
  /**
   * Create a new SKU variant for a specific product in the catalog. The API
   * requires a valid productId in the path to scope the SKU under the correct
   * parent product, as well as a request body containing all required SKU
   * information such as code, price, inventory, and variant status. System and
   * business validations ensure SKU combination uniqueness within the parent
   * product and proper attribute completion.
   *
   * The endpoint is open to authenticated sellers who own the referenced
   * product. It enforces validation for SKU code uniqueness (no duplicate SKU
   * codes for a product), positive price and inventory values, and compliance
   * with all audit and status rules captured in the shopping_mall_product_skus
   * schema. On success, it returns the full details of the created SKU.
   * Attempts to create SKUs for non-existent or unauthorized products will be
   * rejected with descriptive error responses. All business and lifecycle
   * fields from the schema are represented in the DTO.
   *
   * @param connection
   * @param productId Unique identifier of the parent catalog product (global
   *   scope) under which to create the SKU. Must reference
   *   shopping_mall_products.id.
   * @param body All details for the SKU to be created, including code, price,
   *   inventory, and status. Must satisfy schema validation constraints and
   *   uniqueness requirements per parent product.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductSku.ICreate,
  ): Promise<IShoppingMallProductSku> {
    try {
      return await postShoppingMallSellerProductsProductIdSkus({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a list of SKUs for a given product with advanced filtering and
   * pagination.
   *
   * This API endpoint provides sellers, admin users, and platform tools with a
   * powerful mechanism to search, filter, and page through the SKUs assigned to
   * a product. Queryable fields include attributes such as color, size, stock
   * levels, and SKU-specific pricing, in accordance with business requirements
   * and field definitions present in the SKU schema.
   *
   * The request supports structured search parameters as defined by the
   * IShoppingMallProductSku.IRequest DTO. Response objects conform to the
   * standard summary container structure
   * (IPageIShoppingMallProductSku.ISummary) for high-performance user interface
   * rendering.
   *
   * Permissions are enforced so that only owners of the product (seller) or
   * authorized admins may query complete SKU lists. Attempted access by
   * unauthorized users is rejected by backend logic. Pagination and sorting
   * behaviors strictly follow platform API conventions.
   *
   * @param connection
   * @param productId Unique identifier of the parent product whose SKUs are
   *   being listed.
   * @param body SKU search criteria and pagination options for filtering
   *   product SKUs.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductSku.IRequest,
  ): Promise<IPageIShoppingMallProductSku.ISummary> {
    try {
      return await patchShoppingMallSellerProductsProductIdSkus({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an individual SKU (Stock Keeping Unit) variant for a given product
   * in the shopping mall catalog.
   *
   * This operation allows authenticated sellers to modify details of a product
   * SKU—such as SKU code, price, stock quantity, or status—by referencing both
   * the parent product ID and the target SKU ID. It ensures that SKUs cannot be
   * updated independently of their associated product, maintaining data
   * consistency. All input is validated against allowed status values and
   * business rules for inventory and pricing as defined in the schema.
   *
   * This endpoint implements full auditability, tracking who updated the SKU
   * and when, via the updated_at timestamp. Only sellers who own the product
   * may perform updates, and business logic will prevent updates to SKUs that
   * have been deleted or whose parent product is no longer active. Appropriate
   * error responses are returned for access violation or nonexistent
   * SKU/product references.
   *
   * Use this endpoint to efficiently manage catalog variants without disrupting
   * historical sale or review data. For bulk updates, use corresponding batch
   * management tools or endpoints. Related operations: SKU creation, product
   * updates, and product detail retrieval.
   *
   * @param connection
   * @param productId Unique identifier of the parent catalog product
   *   (shopping_mall_products, UUID format) (global scope)
   * @param skuId Unique identifier of the SKU variant record to update
   *   (shopping_mall_product_skus, UUID format) (scoped to product)
   * @param body Updated SKU variant details. May include updated sku_code,
   *   price, stock quantity, and status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":skuId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("skuId")
    skuId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductSku.IUpdate,
  ): Promise<IShoppingMallProductSku> {
    try {
      return await putShoppingMallSellerProductsProductIdSkusSkuId({
        seller,
        productId,
        skuId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete a SKU variant associated with a given shopping mall product.
   * Rather than permanently removing SKU records from the database, this
   * operation sets the 'deleted_at' field, marking the SKU as archived. This
   * ensures traceability and enables SKU recovery for moderation, review, and
   * data analytics.
   *
   * Only the authenticated seller who owns the product may perform this action.
   * The API will validate references to both the parent product and the target
   * SKU to ensure they exist and the user has authorization. SKUs already
   * marked as deleted or belonging to deleted/archived products cannot be
   * deleted again and result in appropriate errors.
   *
   * This operation is foundational for catalog management, particularly when
   * adjusting available variants without losing business intelligence or
   * jeopardizing order/review consistency. Use corresponding endpoints for
   * listing or restoring SKUs as part of seller workflows. Related operations:
   * SKU update, product detail retrieval, and recovery endpoints.
   *
   * @param connection
   * @param productId Unique identifier of the parent catalog product
   *   (shopping_mall_products, UUID format) (global scope)
   * @param skuId Unique identifier of the SKU variant record to delete
   *   (shopping_mall_product_skus, UUID format) (scoped to product)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":skuId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("skuId")
    skuId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductIdSkusSkuId({
        seller,
        productId,
        skuId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
