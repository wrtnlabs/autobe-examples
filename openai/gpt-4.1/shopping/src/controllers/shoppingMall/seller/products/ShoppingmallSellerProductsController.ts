import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putShoppingMallSellerProductsProductId } from "../../../../providers/putShoppingMallSellerProductsProductId";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerProductsProductId } from "../../../../providers/deleteShoppingMallSellerProductsProductId";

import { IShoppingMallProduct } from "../../../../api/structures/IShoppingMallProduct";

@Controller("/shoppingMall/seller/products/:productId")
export class ShoppingmallSellerProductsController {
  /**
   * Update the business and catalog information for a specific product
   * identified by its primary key (productId) within the marketplace.
   *
   * This operation supports updating fields such as the product title,
   * description, default display price, and business status (e.g., draft,
   * published, archived) according to the values permitted by the database
   * schema. Only non-deleted products are eligible for updates—records with a
   * deleted_at timestamp must be ignored or rejected from modification.
   *
   * The operation enforces security by checking the identity and privileges of
   * the requesting user; only the product's owning seller or an administrator
   * may change the product's data. The action will update the updated_at
   * timestamp for audit and traceability, preserving created_at and soft delete
   * status. Attempts to update a deleted product will result in an error
   * response, and partial updates are disallowed—only whole data update
   * supported as per PUT semantics.
   *
   * Related APIs include the POST /products endpoint for new product
   * registration and PATCH /products for product search and listing functions.
   * Hard delete and restore functions are handled by separate endpoints per
   * business rules.
   *
   * @param connection
   * @param productId Unique identifier of the product to update (UUID, primary
   *   key in shopping_mall_products).
   * @param body Full set of fields for updating an existing product as defined
   *   in IShoppingMallProduct.IUpdate. Includes updatable business fields such
   *   as title, description, default_price, business_status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProduct.IUpdate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await putShoppingMallSellerProductsProductId({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove an existing product from the database, identified by its
   * UUID productId, from the shopping_mall_products table. This operation is a
   * hard delete: all product information is irreversibly eliminated from the
   * catalog, and the relevant product's references in search and analytics are
   * removed. Once deleted, the record and its data cannot be recovered.
   *
   * Only products not already soft deleted (i.e., deleted_at is null) are
   * eligible for hard removal. Ownership and permission checks are enforced:
   * only the product's owner seller or a system administrator may perform this
   * deletion.
   *
   * This operation integrates with the platform's data retention, audit, and
   * compliance policies. Attempts to delete nonexistent or already deleted
   * products will return an error. Related operations include soft-delete
   * workflows triggered by updating deleted_at, and product restoration
   * endpoints for reversible deletion cases as required by moderation or
   * recovery use cases.
   *
   * @param connection
   * @param productId Unique identifier of the product to delete (UUID, primary
   *   key in shopping_mall_products).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
