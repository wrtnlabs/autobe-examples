import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerProductsProductIdImages } from "../../../../../providers/postShoppingMallSellerProductsProductIdImages";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerProductsProductIdImages } from "../../../../../providers/patchShoppingMallSellerProductsProductIdImages";
import { putShoppingMallSellerProductsProductIdImagesImageId } from "../../../../../providers/putShoppingMallSellerProductsProductIdImagesImageId";
import { deleteShoppingMallSellerProductsProductIdImagesImageId } from "../../../../../providers/deleteShoppingMallSellerProductsProductIdImagesImageId";

import { IShoppingMallProductImage } from "../../../../../api/structures/IShoppingMallProductImage";
import { IPageIShoppingMallProductImage } from "../../../../../api/structures/IPageIShoppingMallProductImage";

@Controller("/shoppingMall/seller/products/:productId/images")
export class ShoppingmallSellerProductsImagesController {
  /**
   * Create a new image/media asset associated with a product, to be used in
   * product galleries and detail views.
   *
   * The operation allows authorized users—generally the product owner (seller)
   * or platform admins—to upload a new image to a product's gallery. Supplied
   * details include the CDN URI location of the image, optional alt text for
   * accessibility, position integer for carousel/Gallery ordering, and an
   * optional internal label. Validation ensures the image's uniqueness, the
   * correct association to the product and/or SKU, and that the business logic
   * (association to either product or SKU, but not both) is enforced.
   *
   * Security-wise, this API call is restricted to authenticated actors
   * authorized to manage the product's catalog. On success, the new image
   * becomes immediately available for inclusion in the product's frontend
   * gallery and is eligible for later updating or removal. Related endpoints
   * include updating image information, deleting images (soft delete by setting
   * deleted_at), and retrieving individual image or gallery metadata.
   * Soft-delete and audit field management is handled internally; clients do
   * not set those fields directly.
   *
   * @param connection
   * @param productId Unique identifier (UUID) of the product to which this
   *   image is being added.
   * @param body Metadata and information required to create a product image
   *   asset associated with the specified product. See business logic and
   *   schema for mandatory and optional fields. Must not include audit or
   *   soft-delete management fields, which are maintained by the system.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductImage.ICreate,
  ): Promise<IShoppingMallProductImage> {
    try {
      return await postShoppingMallSellerProductsProductIdImages({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a filtered, paginated list of all images attached to a given
   * product. The operation provides search/filter functionality to locate
   * images by position, label, and related fields. Results include image
   * summaries suitable for gallery or management views
   * (IShoppingMallProductImage.ISummary), with pagination metadata and
   * filtering for performance in large catalogs.
   *
   * The operation supports search and sort on critical fields like 'position',
   * 'label', 'created_at', enabling users to efficiently manage large image
   * sets. Only images that have not been soft deleted are included in
   * responses. Response data can be used directly for product page displays or
   * administrative asset management workflows.
   *
   * Security enforcement ensures that only users with valid permissions (the
   * product's seller or assigned admins) can browse associated images. Audit
   * logs track all access for compliance and moderation. Related endpoints
   * include image upload (POST) and image delete (DELETE).
   *
   * @param connection
   * @param productId Unique identifier of the target product (global scope).
   * @param body Search options, filtering criteria, and pagination info for
   *   retrieving product images.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IShoppingMallProductImage.IRequest,
  ): Promise<IPageIShoppingMallProductImage.ISummary> {
    try {
      return await patchShoppingMallSellerProductsProductIdImages({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product image associated with the specified product.
   * This operation allows sellers to change media asset attributes such as the
   * CDN URI, accessibility text, display order, or label for business
   * management purposes.
   *
   * Only authorized users, typically the product owner seller, can perform this
   * operation. Upon successful update, the 'updated_at' timestamp is refreshed,
   * and any position or label changes are enforced to maintain gallery
   * consistency. The operation validates that the image is actually associated
   * with the target product and that no SKU conflict exists.
   *
   * This operation references 'shopping_mall_product_images' in the Prisma
   * schema. Related operations include product image fetch, image creation, and
   * image deletion for the same product. Error handling covers validation
   * errors, permission denial, or missing associations between product and
   * image.
   *
   * @param connection
   * @param productId Unique identifier of the target shopping mall product.
   * @param imageId Unique identifier of the image asset to update, as
   *   registered in shopping_mall_product_images.
   * @param body Fields to update for the specified product image, such as URI,
   *   alt text, label, or position.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":imageId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductImage.IUpdate,
  ): Promise<IShoppingMallProductImage> {
    try {
      return await putShoppingMallSellerProductsProductIdImagesImageId({
        seller,
        productId,
        imageId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove an image from the specified product, performing a soft deletion by
   * setting the 'deleted_at' timestamp but keeping the record for potential
   * recovery or moderation audit.
   *
   * The operation only allows deletion if the image is currently associated
   * with the identified product. Only the product's seller or authorized actors
   * can invoke this operation. Image removal adjusts order/positioning for the
   * remaining images and excludes the deleted asset from product display.
   *
   * This operation leverages the 'shopping_mall_product_images' table's soft
   * delete support by updating the 'deleted_at' field to the current UTC time.
   * Attempts to delete images not associated with the product, already deleted,
   * or belonging to another SKU/product are rejected with clear error
   * messages.
   *
   * @param connection
   * @param productId Unique identifier of the target shopping mall product.
   * @param imageId Unique identifier of the image asset to remove.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":imageId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductIdImagesImageId({
        seller,
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
