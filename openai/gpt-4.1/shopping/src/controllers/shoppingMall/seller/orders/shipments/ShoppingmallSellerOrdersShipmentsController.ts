import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerOrdersOrderNumberShipments } from "../../../../../providers/postShoppingMallSellerOrdersOrderNumberShipments";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerOrdersOrderNumberShipments } from "../../../../../providers/patchShoppingMallSellerOrdersOrderNumberShipments";
import { getShoppingMallSellerOrdersOrderNumberShipmentsShipmentId } from "../../../../../providers/getShoppingMallSellerOrdersOrderNumberShipmentsShipmentId";
import { putShoppingMallSellerOrdersOrderNumberShipmentsShipmentId } from "../../../../../providers/putShoppingMallSellerOrdersOrderNumberShipmentsShipmentId";

import { IShoppingMallOrderShipment } from "../../../../../api/structures/IShoppingMallOrderShipment";
import { IPageIShoppingMallOrderShipment } from "../../../../../api/structures/IPageIShoppingMallOrderShipment";

@Controller("/shoppingMall/seller/orders/:orderNumber/shipments")
export class ShoppingmallSellerOrdersShipmentsController {
  /**
   * Create a new shipment event under the context of an existing order, as
   * identified by the globally unique business order number present in the path
   * parameter. Each shipment entry includes information such as the shipping
   * partner involved, unique tracking number used for logistics, current
   * shipment status, key timestamps for fulfillment, and any other logistics
   * metadata tracked by the platform.
   *
   * This operation references the shopping_mall_order_shipments table as the
   * insertion target, connecting new records to the parent shopping_mall_orders
   * entry via the resolved orderNumber. All logistics attributes are validated
   * and enforced, including constraints on the uniqueness of the tracking
   * number (across all shipments). Upon successful creation, the operation
   * returns a full shipment entity with all platform-audited fields included.
   * Related operations include updating an existing shipment for a particular
   * order and retrieving shipment details for tracking and customer
   * notification workflows.
   *
   * Robust permission checks are expected before allowing shipment creation,
   * typically restricted to system automation flows, admin actors, or
   * authorized seller actors who have management access to the order. Error
   * scenarios include attempting to create shipments for nonexistent or
   * soft-deleted orders, or submitting tracking numbers that would violate
   * unique constraints.
   *
   * @param connection
   * @param orderNumber Globally unique business order number for the order to
   *   which the new shipment will be linked (global scope).
   * @param body Logistics, tracking, and fulfillment details for creation of a
   *   new shipment related to the referenced order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedBody()
    body: IShoppingMallOrderShipment.ICreate,
  ): Promise<IShoppingMallOrderShipment> {
    try {
      return await postShoppingMallSellerOrdersOrderNumberShipments({
        seller,
        orderNumber,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Return a paginated, filterable list of all shipment (fulfillment batch)
   * entities associated with a single shopping mall order. Each shipment record
   * tracks detailed shipping, carrier, and status information relevant to one
   * or more items in the given order.
   *
   * The list supports filtering by shipment status, carrier, creation dates,
   * and other shipment attributes as defined in the request body DTO.
   * Pagination parameters allow clients to fetch results in configurable chunk
   * sizes for efficient UI rendering.
   *
   * Security is enforced by restricting access to only those with valid
   * authorization for the parent order. Business logic ensures only active
   * (non-soft deleted) shipments are returned, referencing the
   * shopping_mall_order_shipments schema. This API enables both customer and
   * seller portals to view full delivery status for a given order, but does not
   * expose system-level shipments unrelated to this order.
   *
   * @param connection
   * @param orderNumber Platform-unique business order number of the parent
   *   order (global scope). Example: ORD202500001.
   * @param body Filter, sort, and pagination settings for shipment batch search
   *   within the specified order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedBody()
    body: IShoppingMallOrderShipment.IRequest,
  ): Promise<IPageIShoppingMallOrderShipment.ISummary> {
    try {
      return await patchShoppingMallSellerOrdersOrderNumberShipments({
        seller,
        orderNumber,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch the comprehensive detail of a specific shipment (fulfillment batch),
   * using both the parent order's platform-unique order number and shipment's
   * unique identifier. This information includes all pertinent shipment fields
   * (including status, tracking, ship/delivery dates) and references to
   * external carrier information if available.
   *
   * Only actors authorized to access the parent order may retrieve this detail.
   * The operation ensures that the shipment belongs to the specified order and
   * that it is not a soft-deleted log entry. The schema description for
   * shopping_mall_order_shipments and the associated shopping_mall_orders table
   * are used as business logic references. Any discrepancies with parent/child
   * relations, access violations, or missing shipments result in clear error
   * responses.
   *
   * This endpoint enables both customer and seller actors to view critical
   * logistics details for multi-shipment, multi-actor fulfillment workflows.
   * Related shipment status or tracking operations are implemented separately
   * if required.
   *
   * @param connection
   * @param orderNumber Platform-unique business order number of the parent
   *   order (global scope). Example: ORD202500001.
   * @param shipmentId Unique identifier (UUID) of the shipment entity within
   *   the specified order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderShipment> {
    try {
      return await getShoppingMallSellerOrdersOrderNumberShipmentsShipmentId({
        seller,
        orderNumber,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a shipment record for a specific order, identified by its globally
   * unique order number and the shipment's unique ID. This operation allows
   * authorized actors to modify details such as shipment status, associated
   * shipping partner, tracking information, and fulfillment timestamps in
   * accordance with logistics and business requirements.
   *
   * The operation works on the shopping_mall_order_shipments table, referencing
   * the linked parent order based on orderNumber and targeting a child shipment
   * using shipmentId, which should be a UUID following best practice. Updates
   * are validated for consistency, field-level permission, and business logic
   * constraints, including uniqueness of tracking numbers and valid status
   * transitions.
   *
   * Modification of system-managed or immutable fields (such as creation date
   * or shipment ID) is prohibited. On a successful update, the endpoint returns
   * the updated shipment details reflecting all changes committed. Error
   * handling covers all cases of foreign key failure, invalid ID or order
   * reference, uniqueness violations, and field-level update errors. This
   * endpoint is usually permitted to admin and seller actors responsible for
   * fulfilling the order.
   *
   * @param connection
   * @param orderNumber Globally unique business order number of the target
   *   order (global scope).
   * @param shipmentId Unique identifier for the shipment to update (must be a
   *   valid UUID).
   * @param body Fields and updated values for the shipment, as permitted by
   *   platform business rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shipmentId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderShipment.IUpdate,
  ): Promise<IShoppingMallOrderShipment> {
    try {
      return await putShoppingMallSellerOrdersOrderNumberShipmentsShipmentId({
        seller,
        orderNumber,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
