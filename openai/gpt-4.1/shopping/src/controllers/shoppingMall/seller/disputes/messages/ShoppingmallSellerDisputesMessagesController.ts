import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallSellerDisputesDisputeIdMessages } from "../../../../../providers/patchShoppingMallSellerDisputesDisputeIdMessages";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerDisputesDisputeIdMessagesDisputeMessageId } from "../../../../../providers/putShoppingMallSellerDisputesDisputeIdMessagesDisputeMessageId";
import { deleteShoppingMallSellerDisputesDisputeIdMessagesDisputeMessageId } from "../../../../../providers/deleteShoppingMallSellerDisputesDisputeIdMessagesDisputeMessageId";

import { IPageIShoppingMallDisputeMessage } from "../../../../../api/structures/IPageIShoppingMallDisputeMessage";
import { IShoppingMallDisputeMessage } from "../../../../../api/structures/IShoppingMallDisputeMessage";

@Controller("/shoppingMall/seller/disputes/:disputeId/messages")
export class ShoppingmallSellerDisputesMessagesController {
  /**
   * Search and paginate messages relating to a specific dispute from
   * shopping_mall_dispute_messages.
   *
   * Retrieve a paginated, filtered set of messages exchanged about a particular
   * dispute.
   *
   * This operation queries the shopping_mall_dispute_messages table for all
   * messages where the parent disputeId matches the path parameter, returning
   * conversation history involving all actors. Powerful search and filter
   * options are supported in the request body, including sender/receiver ID,
   * role, partial content match, and date range filtering, as well as standard
   * pagination and sorting.
   *
   * Access control ensures only legitimate participants in the dispute
   * (customer, seller, or admin) and compliance officers can view messages.
   * This supports customer support, mediation, compliance documentation, and
   * forensics. The response contains paginated message summaries, aiding
   * transcript review and dispute management.
   *
   * @param connection
   * @param disputeId Unique identifier of the target dispute whose messages are
   *   being queried.
   * @param body Complex search, sorting, and pagination options for messages in
   *   a dispute context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("disputeId")
    disputeId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallDisputeMessage.IRequest,
  ): Promise<IPageIShoppingMallDisputeMessage.ISummary> {
    try {
      return await patchShoppingMallSellerDisputesDisputeIdMessages({
        seller,
        disputeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific shopping mall dispute message by its ID using the dispute
   * and message IDs.
   *
   * Update a specific dispute message within the context of a shopping mall
   * dispute.
   *
   * This endpoint allows authorized senders (admin, seller, or customer) to
   * modify the content of their own message during an active dispute. Only
   * messages that have not been deleted are eligible for updating. The primary
   * use case is correction of typographical errors or clarifying message
   * contents prior to resolution or closure of the dispute.
   *
   * The operation verifies the identity and role of the actor to ensure only
   * permitted edits. Edits to messages after the dispute is resolved may be
   * restricted based on platform policies. The database model ensures an audit
   * trail is maintained through timestamps and, where appropriate,
   * administrative override logs.
   *
   * Error handling includes permission checks, validation of message existence,
   * and restriction after logical deletion (soft delete via deleted_at field).
   * Related APIs include message creation, message erasure, and dispute state
   * retrieval.
   *
   * @param connection
   * @param disputeId Unique identifier of the parent dispute associated with
   *   the message.
   * @param disputeMessageId Unique identifier of the message to be updated
   *   within the specified dispute.
   * @param body Fields to update for the dispute message, including new content
   *   and/or updated role if needed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":disputeMessageId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("disputeId")
    disputeId: string & tags.Format<"uuid">,
    @TypedParam("disputeMessageId")
    disputeMessageId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallDisputeMessage.IUpdate,
  ): Promise<IShoppingMallDisputeMessage> {
    try {
      return await putShoppingMallSellerDisputesDisputeIdMessagesDisputeMessageId(
        {
          seller,
          disputeId,
          disputeMessageId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Erase (soft-delete) a specific shopping mall dispute message using the
   * dispute and message IDs.
   *
   * Erase (soft-delete) a specific dispute message by marking it as deleted in
   * the database, making it invisible to standard dispute communication flows.
   *
   * The operation sets the deleted_at timestamp for the target
   * message—identified by both dispute ID and message ID—to signify logical
   * deletion. This ensures that the message remains traceable for compliance
   * and record-keeping but is suppressed from UI listings and further
   * communication within the dispute.
   *
   * Permission checks enforce that only the message's sender, dispute
   * participants, or platform admins can perform erasures. Attempts to erase
   * already-deleted messages or non-existent messages will result in validation
   * errors. Related APIs include message creation, updates, and listing
   * messages for a dispute.
   *
   * @param connection
   * @param disputeId Unique identifier of the parent dispute associated with
   *   the message.
   * @param disputeMessageId Unique identifier of the dispute message to be
   *   erased within the given dispute.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":disputeMessageId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("disputeId")
    disputeId: string & tags.Format<"uuid">,
    @TypedParam("disputeMessageId")
    disputeMessageId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallDisputeMessage> {
    try {
      return await deleteShoppingMallSellerDisputesDisputeIdMessagesDisputeMessageId(
        {
          seller,
          disputeId,
          disputeMessageId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
