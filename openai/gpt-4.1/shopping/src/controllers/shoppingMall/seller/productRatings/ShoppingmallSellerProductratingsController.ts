import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallSellerProductRatings } from "../../../../providers/patchShoppingMallSellerProductRatings";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";

import { IPageIShoppingMallProductRating } from "../../../../api/structures/IPageIShoppingMallProductRating";
import { IShoppingMallProductRating } from "../../../../api/structures/IShoppingMallProductRating";

@Controller("/shoppingMall/seller/productRatings")
export class ShoppingmallSellerProductratingsController {
  /**
   * Search and retrieve paginated summaries of product ratings
   * (shopping_mall_product_ratings table).
   *
   * Retrieve a filtered, paginated list of product ratings on the shopping mall
   * platform.
   *
   * This operation targets the shopping_mall_product_ratings table, enabling
   * authenticated sellers and admins to search and analyze product ratings by a
   * range of criteria. Filters include product, SKU, order, or customer, as
   * well as numeric rating values (1–5). The PATCH method utilizes a request
   * body of type IShoppingMallProductRating.IRequest for specifying search
   * filters and pagination.
   *
   * Only sellers and admins are authorized to access this operation, ensuring
   * rating data remains an internal tool for feedback and product quality
   * analysis. The response includes page-wise summaries of product ratings,
   * compatible with reporting, analytics, and inventory workflows. Related
   * operations may include GET for individual ratings, POST to capture a new
   * rating (always tied to a review), and aggregation endpoints for analytics.
   *
   * @param connection
   * @param body Criteria for filtering, sorting, and paginating shopping mall
   *   product ratings.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProductRating.IRequest,
  ): Promise<IPageIShoppingMallProductRating.ISummary> {
    try {
      return await patchShoppingMallSellerProductRatings({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
