import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallSellerRefundRequestsRefundRequestId } from "../../../../providers/getShoppingMallSellerRefundRequestsRefundRequestId";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";

import { IShoppingMallRefundRequest } from "../../../../api/structures/IShoppingMallRefundRequest";

@Controller("/shoppingMall/seller/refundRequests/:refundRequestId")
export class ShoppingmallSellerRefundrequestsController {
  /**
   * Retrieve full detail of a specific refund request
   * (shopping_mall_refund_requests).
   *
   * Retrieve the full detail for a single refund request in the shopping mall.
   * This endpoint provides all information filed by the customer for this
   * request, including the refund reason, status (such as pending, approved,
   * rejected, processing, refunded), the requested and (if decided) approved
   * refund amounts, and timestamps indicating the creation and latest update to
   * the request.
   *
   * The response also includes references to the associated order, the customer
   * who initiated the refund, the seller involved, and any admin who has acted
   * on or is assigned to the request. Timestamps for creation and updates are
   * included for precise workflow tracking and compliance. The refund request's
   * workflow state, including any logical soft deletion ('deleted_at'), is
   * honored; if the record is logically deleted, it will be omitted or return a
   * suitable error response.
   *
   * This operation is critical for customer support, dispute resolution, and
   * refund workflow management by platform actors. Only authorized users
   * (admin, customer, or seller associated with the refund) should be allowed
   * to access the details. Related operations: create refund request (POST
   * /refundRequests), list/search refund requests (PATCH /refundRequests).
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request to retrieve
   *   (UUID primary key).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await getShoppingMallSellerRefundRequestsRefundRequestId({
        seller,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
