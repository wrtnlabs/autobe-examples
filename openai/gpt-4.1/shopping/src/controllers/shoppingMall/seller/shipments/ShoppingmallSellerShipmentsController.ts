import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerShipments } from "../../../../providers/postShoppingMallSellerShipments";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerShipmentsShipmentId } from "../../../../providers/putShoppingMallSellerShipmentsShipmentId";
import { deleteShoppingMallSellerShipmentsShipmentId } from "../../../../providers/deleteShoppingMallSellerShipmentsShipmentId";

import { IShoppingMallShipment } from "../../../../api/structures/IShoppingMallShipment";

@Controller("/shoppingMall/seller/shipments")
export class ShoppingmallSellerShipmentsController {
  /**
   * Create a new shipment record for an order item, referencing a specific
   * order and assigning fulfillment responsibility to a shipping partner. This
   * operation requires that the target order and order item are valid and not
   * yet fulfilled or cancelled. Optionally, a carrier tracking code, initial
   * shipment status, shipping label manifest link, and provider response code
   * can be provided.
   *
   * Actor attribution must be provided: either an admin (for administrative
   * platform-initiated shipments) or a seller (for manual or self-fulfilled
   * shipments). The actor fields are mutually exclusive, but one must be set.
   * The shipping partner ID must reference a registered and active
   * shipping/logistics provider. Appropriate status transitions will be
   * enforced by the business logic depending on whether this is a
   * pre-fulfillment, pickup, or immediate delivery event.
   *
   * All shipment records include full audit trail with creator attribution, and
   * timestamps are managed for creation, updates, delivery, or cancellation as
   * relevant. Edge cases such as missing tracking information, label
   * non-issuance, or delayed carrier integration are handled gracefully, with
   * nullable fields indicating missing data at creation time. The payload
   * allows storing of partner label URLs and the current shipment status.
   * Related shipment update and cancellation operations are available for later
   * status modifications and logistics event handling.
   *
   * @param connection
   * @param body Creation information for a new shipment record, including
   *   order/item/partner IDs, status, actor attribution, and optional tracking
   *   or manifest fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallShipment.ICreate,
  ): Promise<IShoppingMallShipment> {
    try {
      return await postShoppingMallSellerShipments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update shipment details—such as status, carrier tracking, manifests,
   * delivery/cancellation timestamps, or API provider result—by specifying the
   * shipmentId of the target shipment record. This operation allows status
   * updates for both administrative and manual (seller-driven) shipment
   * workflows, but does not permit changes to the base order, order item, or
   * shipping partner fields after creation.
   *
   * Acceptable status transitions are enforced in accordance with fulfillment
   * and return business rules. If updating status to 'delivered' or
   * 'cancelled', the corresponding delivery or cancellation timestamp must be
   * included in the request, ensuring proper auditability. Carrier tracking and
   * manifest/label links are modifiable as the shipment progresses, and
   * provider API result codes can be updated when available. Actor attribution
   * for the update (admin or seller) must be provided. All update operations
   * are fully auditable and time-stamped, with proper integration to logistics
   * or return flows as relevant.
   *
   * If validation fails due to invalid status transition or unauthorized actor
   * attempt, descriptive errors will be returned indicating the business rule
   * violation. Shipment state updates should be coordinated with related
   * shipment tracking history records for full event lifecycle management.
   *
   * @param connection
   * @param shipmentId Unique identifier of the target shipment record to
   *   update.
   * @param body Updatable fields for the shipment record, allowing for
   *   logistics status, tracking/manifest, provider response, and actor
   *   attribution changes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shipmentId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipment.IUpdate,
  ): Promise<IShoppingMallShipment> {
    try {
      return await putShoppingMallSellerShipmentsShipmentId({
        seller,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint deletes a shipment record from the system by its unique
   * identifier. Deleting a shipment is an irreversible operation and should
   * only be performed when the shipment has not been delivered, is not in
   * transit, or when allowed by platform business rules.
   *
   * Security controls ensure that only actors with explicit permission
   * (platform admins or the owning seller when applicable) can perform a
   * deletion. The system validates shipment status prior to deletion and
   * returns a descriptive error if the shipment cannot be removed due to
   * business constraints or logistical events already processed. Related audit
   * and tracking data will be evaluated for deletion or retention according to
   * regulatory compliance requirements.
   *
   * If dependent tracking histories exist or the shipment has progressed beyond
   * a cancellable state, the system will deny the request and provide details
   * in the error response. Related shipments for the same order or order item
   * will not be affected by this operation.
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment to be deleted. This is
   *   a globally unique UUID assigned to each shipment record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":shipmentId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerShipmentsShipmentId({
        seller,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
