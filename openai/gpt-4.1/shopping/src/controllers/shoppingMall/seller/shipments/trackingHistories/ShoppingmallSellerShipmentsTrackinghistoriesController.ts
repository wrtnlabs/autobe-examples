import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerShipmentsShipmentIdTrackingHistories } from "../../../../../providers/postShoppingMallSellerShipmentsShipmentIdTrackingHistories";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerShipmentsShipmentIdTrackingHistories } from "../../../../../providers/patchShoppingMallSellerShipmentsShipmentIdTrackingHistories";
import { getShoppingMallSellerShipmentsShipmentIdTrackingHistoriesTrackingHistoryId } from "../../../../../providers/getShoppingMallSellerShipmentsShipmentIdTrackingHistoriesTrackingHistoryId";

import { IShoppingMallShipmentTrackingHistory } from "../../../../../api/structures/IShoppingMallShipmentTrackingHistory";
import { IPageIShoppingMallShipmentTrackingHistory } from "../../../../../api/structures/IPageIShoppingMallShipmentTrackingHistory";

@Controller("/shoppingMall/seller/shipments/:shipmentId/trackingHistories")
export class ShoppingmallSellerShipmentsTrackinghistoriesController {
  /**
   * Create a new shipment tracking history event beneath
   * shopping_mall_shipments.
   *
   * Append a new shipment tracking event to a specific existing shipment for
   * complete carrier/logistics event journaling.
   *
   * This endpoint allows authorized system components (automated integrations),
   * sellers, platform admins, or customers to report discrete shipment tracking
   * updates, recording precise timestamps, statuses, event codes, optional
   * geolocation, and free-form progress messages. This event becomes part of
   * the shipment's official audit trail.
   *
   * Security and permissions: Only the shipment owner or authorized platform
   * actors can append tracking events, and all event data must be validated for
   * injection, duplication, and timestamp ordering. Proper cross-checks ensure
   * only valid events are written to the shipment's chronology. Automated and
   * manual insertions must be clearly attributed for audit purposes.
   *
   * This operation enforces the parent-child relationship between
   * shopping_mall_shipments and shopping_mall_shipment_tracking_histories, and
   * should be invoked by integrations, admin actions, or platform workflows
   * when new events are received from carriers or manually logged.
   *
   * @param connection
   * @param shipmentId Unique identifier of the parent shipment
   *   (shoppingMallShipments) to which this new tracking event will be
   *   appended.
   * @param body Information required to create a new shipment tracking event
   *   record for the given shipment.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipmentTrackingHistory.ICreate,
  ): Promise<IShoppingMallShipmentTrackingHistory> {
    try {
      return await postShoppingMallSellerShipmentsShipmentIdTrackingHistories({
        seller,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve paginated tracking history events for a specific shipment from
   * shopping_mall_shipment_tracking_histories.
   *
   * This endpoint returns the list of tracking status history events for a
   * given shipment. It provides all carrier or warehouse updates from dispatch
   * through delivery, showing detailed status codes, event times, locations,
   * and tracking messages as recorded in the
   * `shopping_mall_shipment_tracking_histories` table.
   *
   * The operation supports complex filtering, such as by status code or event
   * type, as well as pagination for large tracking histories. Only users with
   * permission to access the shipment (e.g., the shipment's customer or seller,
   * or platform admins) may call this endpoint. Returned tracking events are
   * always shown in chronological order.
   *
   * Security and privacy guidelines are enforced: only actors with a relevant
   * relationship to the shipment may access tracking history. Attempts to
   * access tracking data for shipments outside the actor's domain will result
   * in access denied errors. This endpoint is commonly used for customer
   * shipment tracking displays, seller dashboard views, and admin auditing.
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment whose tracking history
   *   is being retrieved. This is a globally unique UUID for the shipment
   *   record.
   * @param body Search criteria, filtering, and pagination options for shipment
   *   tracking history retrieval.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipmentTrackingHistory.IRequest,
  ): Promise<IPageIShoppingMallShipmentTrackingHistory> {
    try {
      return await patchShoppingMallSellerShipmentsShipmentIdTrackingHistories({
        seller,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific shipment tracking event detail from
   * shopping_mall_shipment_tracking_histories.
   *
   * Fetch a detailed tracking event update for a specific shipment in the order
   * fulfillment system.
   *
   * This endpoint enables platform customers, sellers, and admins to retrieve a
   * single shipment event from the full chronology of shipment tracking
   * histories. The result includes timestamp, status at the moment of the
   * event, carrier or system code, human-readable tracking message, geolocation
   * information if available, and all other logged event details as defined in
   * the schema.
   *
   * Security and privacy: Only the appropriate owners (customer, seller, admin)
   * may view shipment tracking history of their orders—authorization and
   * business rule enforcement must be handled at the provider/controller level
   * based on access rights. Path parameters prevent access to records outside
   * their shipment context, protecting platform integrity.
   *
   * This operation references the 'shopping_mall_shipment_tracking_histories'
   * subsidiary model and enforces correct parent-child referencing to maintain
   * auditability. It is used in dashboards, customer portals, and dispute
   * resolution scenarios where proof of shipment progress is needed.
   *
   * @param connection
   * @param shipmentId Unique identifier of the parent shipment
   *   (shoppingMallShipments) to which this tracking history event belongs.
   * @param trackingHistoryId Unique identifier for this tracking event record
   *   under the specified shipment.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":trackingHistoryId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedParam("trackingHistoryId")
    trackingHistoryId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipmentTrackingHistory> {
    try {
      return await getShoppingMallSellerShipmentsShipmentIdTrackingHistoriesTrackingHistoryId(
        {
          seller,
          shipmentId,
          trackingHistoryId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
