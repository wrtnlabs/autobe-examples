import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallCustomerOrders } from "../../../../providers/postShoppingMallCustomerOrders";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerOrdersOrderNumber } from "../../../../providers/putShoppingMallCustomerOrdersOrderNumber";

import { IShoppingMallOrder } from "../../../../api/structures/IShoppingMallOrder";

@Controller("/shoppingMall/customer/orders")
export class ShoppingmallCustomerOrdersController {
  /**
   * Create a new order record in shopping_mall_orders.
   *
   * Create a new shopping mall order on the platform.
   *
   * This operation enables customers (or system actors on their behalf) to
   * place a new order for one or more products, referencing a specific
   * customer, shipping address, and seller. The endpoint requires all
   * business-critical identifiers to be specified, including the unique
   * order_number, and ensures all relationships (such as customer and address)
   * are valid and active.
   *
   * Before an order can be created, the provided order_number will be validated
   * to ensure global uniqueness. The platform will also check that the
   * referenced customer, address, and seller exist and are eligible for
   * ordering. The total_amount must reflect the sum of all itemized values plus
   * shipping and discounts, and currency codes must comply with ISO 4217
   * standards. On success, the API returns the complete order details,
   * including status and creation timestamps.
   *
   * Initial order status is set as provided by the client, and further status
   * changes (cancelled, paid, shipped, etc.) are tracked by separate endpoints
   * and event records. This creation endpoint does not handle order item
   * creation, payment authorization, or shipment initiation, which are handled
   * in subsequent workflow operations. The created order will be visible in
   * customer and admin dashboards for order management and fulfillment.
   *
   * @param connection
   * @param body Order creation details, including business-unique order_number,
   *   references to customer, address, and seller, and order financial fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallOrder.ICreate,
  ): Promise<IShoppingMallOrder> {
    try {
      return await postShoppingMallCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an order in shopping_mall_orders by order_number.
   *
   * Update the details of an existing shopping mall order identified by its
   * business-unique order_number.
   *
   * This endpoint enables authorized actors, such as customers (up to certain
   * business-imposed rules) or customer service agents, to adjust certain
   * fields of an order. Typical modifications may include changing the delivery
   * address (before shipment), correcting order status, updating the assigned
   * seller, or modifying the total_amount and currency if no payment has yet
   * been finalized.
   *
   * The provided order_number is enforced as a globally unique identifier for
   * lookup. If no active (non-deleted) order matching the order_number exists,
   * the update is rejected. The update does not allow changes to the business
   * order_number itself, nor to any associated child entities (such as order
   * items, shipments, audit logs). Security logic ensures only eligible users
   * (such as the original purchaser or an admin) may make updates. All changes
   * will be tracked for audit and compliance, with updated_at reflecting the
   * modification time.
   *
   * @param connection
   * @param orderNumber Platform-wide unique business order number for the order
   *   to update (global scope).
   * @param body Order fields that can be updated, including status, seller,
   *   address, and other high-level order fields as allowed by business rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":orderNumber")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedBody()
    body: IShoppingMallOrder.IUpdate,
  ): Promise<IShoppingMallOrder> {
    try {
      return await putShoppingMallCustomerOrdersOrderNumber({
        customer,
        orderNumber,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
