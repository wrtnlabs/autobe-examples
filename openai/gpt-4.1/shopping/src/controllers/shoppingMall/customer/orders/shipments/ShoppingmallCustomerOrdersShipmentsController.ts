import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallCustomerOrdersOrderNumberShipments } from "../../../../../providers/patchShoppingMallCustomerOrdersOrderNumberShipments";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersOrderNumberShipmentsShipmentId } from "../../../../../providers/getShoppingMallCustomerOrdersOrderNumberShipmentsShipmentId";

import { IPageIShoppingMallOrderShipment } from "../../../../../api/structures/IPageIShoppingMallOrderShipment";
import { IShoppingMallOrderShipment } from "../../../../../api/structures/IShoppingMallOrderShipment";

@Controller("/shoppingMall/customer/orders/:orderNumber/shipments")
export class ShoppingmallCustomerOrdersShipmentsController {
  /**
   * Return a paginated, filterable list of all shipment (fulfillment batch)
   * entities associated with a single shopping mall order. Each shipment record
   * tracks detailed shipping, carrier, and status information relevant to one
   * or more items in the given order.
   *
   * The list supports filtering by shipment status, carrier, creation dates,
   * and other shipment attributes as defined in the request body DTO.
   * Pagination parameters allow clients to fetch results in configurable chunk
   * sizes for efficient UI rendering.
   *
   * Security is enforced by restricting access to only those with valid
   * authorization for the parent order. Business logic ensures only active
   * (non-soft deleted) shipments are returned, referencing the
   * shopping_mall_order_shipments schema. This API enables both customer and
   * seller portals to view full delivery status for a given order, but does not
   * expose system-level shipments unrelated to this order.
   *
   * @param connection
   * @param orderNumber Platform-unique business order number of the parent
   *   order (global scope). Example: ORD202500001.
   * @param body Filter, sort, and pagination settings for shipment batch search
   *   within the specified order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedBody()
    body: IShoppingMallOrderShipment.IRequest,
  ): Promise<IPageIShoppingMallOrderShipment.ISummary> {
    try {
      return await patchShoppingMallCustomerOrdersOrderNumberShipments({
        customer,
        orderNumber,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch the comprehensive detail of a specific shipment (fulfillment batch),
   * using both the parent order's platform-unique order number and shipment's
   * unique identifier. This information includes all pertinent shipment fields
   * (including status, tracking, ship/delivery dates) and references to
   * external carrier information if available.
   *
   * Only actors authorized to access the parent order may retrieve this detail.
   * The operation ensures that the shipment belongs to the specified order and
   * that it is not a soft-deleted log entry. The schema description for
   * shopping_mall_order_shipments and the associated shopping_mall_orders table
   * are used as business logic references. Any discrepancies with parent/child
   * relations, access violations, or missing shipments result in clear error
   * responses.
   *
   * This endpoint enables both customer and seller actors to view critical
   * logistics details for multi-shipment, multi-actor fulfillment workflows.
   * Related shipment status or tracking operations are implemented separately
   * if required.
   *
   * @param connection
   * @param orderNumber Platform-unique business order number of the parent
   *   order (global scope). Example: ORD202500001.
   * @param shipmentId Unique identifier (UUID) of the shipment entity within
   *   the specified order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderShipment> {
    try {
      return await getShoppingMallCustomerOrdersOrderNumberShipmentsShipmentId({
        customer,
        orderNumber,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
