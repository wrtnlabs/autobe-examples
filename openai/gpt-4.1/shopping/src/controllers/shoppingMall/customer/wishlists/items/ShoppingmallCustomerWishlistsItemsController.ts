import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerWishlistsWishlistIdItems } from "../../../../../providers/postShoppingMallCustomerWishlistsWishlistIdItems";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerWishlistsWishlistIdItems } from "../../../../../providers/patchShoppingMallCustomerWishlistsWishlistIdItems";
import { getShoppingMallCustomerWishlistsWishlistIdItemsItemId } from "../../../../../providers/getShoppingMallCustomerWishlistsWishlistIdItemsItemId";
import { putShoppingMallCustomerWishlistsWishlistIdItemsItemId } from "../../../../../providers/putShoppingMallCustomerWishlistsWishlistIdItemsItemId";
import { deleteShoppingMallCustomerWishlistsWishlistIdItemsItemId } from "../../../../../providers/deleteShoppingMallCustomerWishlistsWishlistIdItemsItemId";

import { IShoppingMallWishlistItem } from "../../../../../api/structures/IShoppingMallWishlistItem";
import { IPageIShoppingMallWishlistItem } from "../../../../../api/structures/IPageIShoppingMallWishlistItem";

@Controller("/shoppingMall/customer/wishlists/:wishlistId/items")
export class ShoppingmallCustomerWishlistsItemsController {
  /**
   * Add a product to a customer's wishlist by creating a new wishlist item
   * under the specified wishlist.
   *
   * This operation enables authenticated customers to persist product interest
   * for later purchase decisions by adding a SKU to their wishlist. The
   * wishlist ID specifies the parent wishlist context (which must belong to the
   * authenticated customer). The operation validates that the SKU is not
   * already in the wishlist (enforced by the composite unique constraint) and
   * that both the wishlist and SKU exist. On success, the new wishlist item is
   * returned with all relevant database fields and references. Security is
   * enforced so that a customer cannot add items to another customer's
   * wishlist. Upon duplication (e.g., SKU already present), an error is
   * returned according to business logic.
   *
   * This endpoint integrates with the 'shopping_mall_wishlists' and
   * 'shopping_mall_wishlist_items' schemas, supports advanced wishlist
   * interaction features, and is fundamental for persistent ecommerce
   * bookmarking.
   *
   * @param connection
   * @param wishlistId Unique identifier of the target customer wishlist to add
   *   the item to.
   * @param body Details for the new wishlist item to be created (SKU reference,
   *   etc.).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallWishlistItem.ICreate,
  ): Promise<IShoppingMallWishlistItem> {
    try {
      return await postShoppingMallCustomerWishlistsWishlistIdItems({
        customer,
        wishlistId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch the complete contents of a given wishlist in a paginated, searchable
   * fashion, leveraging the shopping_mall_wishlist_items subsidiary table.
   *
   * Customers may use this endpoint to view all saved SKUs across devices or
   * sessions, and may filter items by product details, SKU characteristics, or
   * category. Supports pagination (page/limit), keyword search, and sorting
   * (e.g., most recently added first).
   *
   * Security checks ensure that only the authenticated owner or an
   * administrator can access wishlist details for privacy. Attempts by
   * unauthorized users are refused. This operation is commonly used as the
   * initial step in displaying a user's wishlist before options to move items
   * to cart or remove from wishlist.
   *
   * Related operations include adding/removing wishlist items, wishlists root
   * retrieval, and SKU/product detail fetches.
   *
   * @param connection
   * @param wishlistId Unique identifier of the wishlist for which to retrieve
   *   items.
   * @param body Search, filter, and pagination criteria for querying a
   *   wishlist's items.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallWishlistItem.IRequest,
  ): Promise<IPageIShoppingMallWishlistItem.ISummary> {
    try {
      return await patchShoppingMallCustomerWishlistsWishlistIdItems({
        customer,
        wishlistId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve information for a single item within a customer wishlist using
   * specified wishlist and item identifiers.
   *
   * This endpoint is essential for enabling customers to see details about a
   * particular product they have saved to their wishlist. Since each wishlist
   * item references a SKU and is tied to a parent wishlist, this operation
   * utilizes both the parent wishlist and the specific item ID to ensure
   * precise retrieval and access control.
   *
   * Relationship to schema: The 'shopping_mall_wishlist_items' table enforces a
   * composite unique constraint pairing wishlist and SKU, preventing
   * duplicates. Security is enforced by ownership at the application level:
   * customers can only retrieve items from their own wishlist. If an item does
   * not exist or belongs to another customer's wishlist, an appropriate error
   * is returned. The response structure mirrors the 'IShoppingMallWishlistItem'
   * type.
   *
   * Related operations include retrieving all items in a wishlist,
   * adding/removing wishlist items, and listing products available for
   * addition. For detailed item info, this endpoint covers the primary use case
   * for managing persistent customer interest lists.
   *
   * @param connection
   * @param wishlistId Unique identifier of the customer wishlist containing the
   *   item.
   * @param itemId Unique identifier of the wishlist item to retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallWishlistItem> {
    try {
      return await getShoppingMallCustomerWishlistsWishlistIdItemsItemId({
        customer,
        wishlistId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the details of a specific wishlist item in a customer's wishlist.
   *
   * This operation enables modifications to a wishlist item—such as changing
   * the referenced product SKU, if allowed—by identifying the target using both
   * the parent wishlist's ID and the item's own ID. The operation strictly
   * enforces correct linkage to ensure updates only affect the intended
   * wishlist and item pair, leveraging the relationship between
   * shopping_mall_wishlists (parent) and shopping_mall_wishlist_items
   * (subsidiary), as detailed in the Prisma schema.
   *
   * Security is enforced so that only the owning customer, authenticated and
   * authorized, may update their wishlist items. Attempts to update a wishlist
   * item with an ID not owned by the customer will result in an authorization
   * error. Validation includes ensuring referenced SKUs exist and are not
   * duplicated within a single wishlist, as per the composite unique
   * constraint. The operation returns the fully updated wishlist item object.
   *
   * Related operations include: removing an item from the wishlist (DELETE
   * /wishlists/{wishlistId}/items/{itemId}) and adding a new item to a wishlist
   * (typically POST /wishlists/{wishlistId}/items). Error responses cover not
   * found, unauthorized, and business rule violations regarding SKU duplication
   * or non-existent products.
   *
   * @param connection
   * @param wishlistId Unique identifier of the parent wishlist containing the
   *   item (UUID).
   * @param itemId Unique identifier of the wishlist item to update (UUID).
   * @param body Payload specifying updated properties of the wishlist item.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":itemId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallWishlistItem.IUpdate,
  ): Promise<IShoppingMallWishlistItem> {
    try {
      return await putShoppingMallCustomerWishlistsWishlistIdItemsItemId({
        customer,
        wishlistId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove (delete) a specific item from a customer's wishlist.
   *
   * This operation allows authenticated customers to permanently delete a
   * wishlist item by specifying both the wishlist's ID and the item ID,
   * ensuring that only an item truly belonging to the user's wishlist can be
   * deleted. The relationship between shopping_mall_wishlists and
   * shopping_mall_wishlist_items, as described in the Prisma schema, is
   * enforced so an orphan or incorrectly referenced removal cannot occur.
   *
   * Security and authorization checks prevent customers from deleting wishlist
   * items they do not own. Attempts to delete a non-existent item or an item
   * not associated with the given wishlist result in appropriate error
   * responses. Additionally, this endpoint is typically paired with operations
   * for updating (PUT) and creating (POST) wishlist items, enabling a complete
   * management lifecycle. Upon successful deletion, the item is permanently
   * removed and cannot be recovered.
   *
   * @param connection
   * @param wishlistId Unique identifier of the parent wishlist containing the
   *   item (UUID).
   * @param itemId Unique identifier of the wishlist item to remove (UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":itemId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerWishlistsWishlistIdItemsItemId({
        customer,
        wishlistId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
