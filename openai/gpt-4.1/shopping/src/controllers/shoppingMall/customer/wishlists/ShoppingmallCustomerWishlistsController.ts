import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerWishlists } from "../../../../providers/postShoppingMallCustomerWishlists";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerWishlistsWishlistId } from "../../../../providers/putShoppingMallCustomerWishlistsWishlistId";
import { deleteShoppingMallCustomerWishlistsWishlistId } from "../../../../providers/deleteShoppingMallCustomerWishlistsWishlistId";

import { IShoppingMallWishlist } from "../../../../api/structures/IShoppingMallWishlist";

@Controller("/shoppingMall/customer/wishlists")
export class ShoppingmallCustomerWishlistsController {
  /**
   * Create a new customer wishlist (shopping_mall_wishlists).
   *
   * Create a new wishlist for a customer in the shopping mall platform.
   *
   * This API operation is essential for persistent customer product interest
   * tracking across sessions and devices. A wishlist acts as the root entity
   * for a customer's saved items. Each wishlist is associated with a single
   * customer by design, and per the schema, only one such list can exist for
   * any given customer (enforced by a unique index on the
   * `shopping_mall_customer_id` field). Duplicate creation requests should be
   * handled gracefully, either by returning the existing wishlist or providing
   * an appropriate error response.
   *
   * Upon creation, metadata such as `created_at` and `updated_at` are
   * automatically registered. Ownership is linked to the customer initiating
   * the request, and the wishlist will later serve as the parent entity for
   * subsidiary wishlist items representing concrete products or SKUs the
   * customer is interested in.
   *
   * Security: This endpoint must ensure the customer is authenticated and has
   * not already created a wishlist. If a wishlist already exists for a
   * customer, a clear error or existing wishlist reference should be returned.
   * Sensitive to privacy and consistency, only the owner should be able to
   * create their own wishlist.
   *
   * @param connection
   * @param body Data required to create a customer's wishlist. Ownership is
   *   implicitly determined by the authenticated user context; no manual
   *   customer ID is required in the request.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallWishlist.ICreate,
  ): Promise<IShoppingMallWishlist> {
    try {
      return await postShoppingMallCustomerWishlists({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing wishlist (shopping_mall_wishlists) by wishlistId.
   *
   * Update a customer's wishlist in the shopping mall system.
   *
   * This API operation allows modification of a customer's existing wishlist
   * record. According to the schema, only certain fields (such as metadata
   * fields) are likely updatable—relationships and the wishlist's owner must be
   * immutable. The method targets lists identified by the `wishlistId` path
   * parameter, which uniquely references the wishlist to be updated.
   *
   * Ownership and authorization checks must ensure that only the authenticated
   * customer can update their own wishlist. Data integrity is preserved by
   * restricting changes to valid wishlist entities and not permitting
   * reassignment of customer ownership or manipulation of subsidiary list
   * items, which are managed in a separate domain (wishlist items).
   *
   * Related operations may include list item management (adding/removing
   * products) and wishlist deletion (if supported).
   *
   * @param connection
   * @param wishlistId Unique identifier of the target wishlist to be updated.
   * @param body Fields allowed for wishlist update. Changing ownership/customer
   *   association is not permitted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":wishlistId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallWishlist.IUpdate,
  ): Promise<IShoppingMallWishlist> {
    try {
      return await putShoppingMallCustomerWishlistsWishlistId({
        customer,
        wishlistId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a customer's wishlist and all its items in
   * shopping_mall_wishlists.
   *
   * Execute the removal of a customer's wishlist from the database, along with
   * every item it contains.
   *
   * Once this operation is invoked, the root wishlist (shopping_mall_wishlists)
   * and all of its subsidiary wishlist items (shopping_mall_wishlist_items) are
   * deleted in a single transaction. This ensures there are no orphaned
   * records, maintaining referential integrity.
   *
   * Only the owner of the wishlist or an administrator may invoke this
   * endpoint, as the wishlist is considered sensitive, persistent state for the
   * user. The operation checks ownership based on the authenticated user's ID.
   * If an unauthorized user attempts to erase a wishlist, the system will deny
   * the request and return an error response.
   *
   * This behavior is irreversible, and all shopping-mall product SKUs
   * referenced in the wishlist will simply become untracked for the customer.
   * There is no recovery possible after deletion. Related API endpoints include
   * wishlist item management (add/update/remove items) and viewing wishlists
   * for the current user.
   *
   * @param connection
   * @param wishlistId Unique identifier of the wishlist to be deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":wishlistId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerWishlistsWishlistId({
        customer,
        wishlistId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
