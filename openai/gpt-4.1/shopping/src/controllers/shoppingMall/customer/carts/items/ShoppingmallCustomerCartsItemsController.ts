  /**
   * Update an existing shopping cart item (shopping_mall_cart_items) by itemId
   * within a specific cart.
   *
   * Update the details of a specific item in a customer's shopping cart
   * identified by its itemId. This operation enables modification of key cart
   * item properties, primarily the desired quantity, while ensuring inventory
   * constraints are enforced. The operation takes the cartId and itemId as path
   * parameters; these uniquely identify the cart and the item to update.
   *
   * User authentication is required; only the owner of the cart is allowed to
   * update its items. Inventory rules, such as the maximum allowed quantity
   * (not exceeding in-stock inventory), are validated during this operation. If
   * the updated quantity is zero, the client should use the DELETE endpoint
   * instead to remove the item. If the desired quantity exceeds current
   * availability, the request will be rejected. This operation is designed for
   * efficient updating of cart contents in all shopping and checkout flows.
   *
   * The endpoint operates over the shopping_mall_cart_items table, which is
   * subsidiary to the shopping_mall_carts table. Data integrity constraints
   * ensure only one cart item per SKU per cart is allowed; thus, itemId must
   * reference a unique cart item within the context of its parent cart. Related
   * operations include creation (POST to /carts/{cartId}/items), retrieval
   * (GET), and deletion (DELETE).
   *
   * @param connection
   * @param cartId Unique identifier of the shopping cart containing the target
   *   item.
   * @param itemId Unique identifier of the cart item to update.
   * @param body Fields for updating the cart item, such as new desired
   *   quantity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
