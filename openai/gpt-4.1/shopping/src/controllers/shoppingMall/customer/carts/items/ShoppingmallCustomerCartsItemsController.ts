  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCartItem.ICreate,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await postShoppingMallCustomerCartsCartIdItems({
        customer,
        cartId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and paginate items in a specific shopping cart
   * (shopping_mall_cart_items).
   *
   * Retrieve a filtered, paginated list of items for a given shopping cart.
   *
   * This operation is designed for the shopping_mall_cart_items subsidiary
   * table, listing all SKU records associated with a specific cart as
   * identified by cartId. It supports flexible querying, including search,
   * filtering by SKU, quantity constraints, and sorting options (e.g., by most
   * recently updated).
   *
   * The relationship between shopping_mall_cart_items and shopping_mall_carts
   * is enforced, so only items belonging to the specified cartId are returned.
   * Business logic ensures each SKU appears only once per cart (composite
   * unique), and information about each item includes quantity and inventory
   * validation context.
   *
   * Pagination logic enables efficient navigation through large numbers of cart
   * items, with controls for page size and sort order. Security permissions
   * ensure only the cart owner or authorized actors may access the full item
   * list. This endpoint is typically used for cart views, checkout preparation,
   * and client-side cart management flows.
   *
   * @param connection
   * @param cartId Unique identifier of the shopping cart whose items are being
   *   queried. (UUID format)
   * @param body Filtering and pagination parameters for querying shopping cart
   *   items.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
