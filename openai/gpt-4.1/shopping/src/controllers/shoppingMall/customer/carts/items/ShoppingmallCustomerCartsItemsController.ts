  /**
   * Retrieve a single cart item from the shopping_mall_cart_items table by cart
   * and item ID.
   *
   * Retrieve a single item from a customer's shopping cart by its unique ID.
   *
   * This operation ensures users can view specific items within their own cart
   * by referencing both the cart ID and the item ID. Only authenticated
   * customers with access to the referenced cart are permitted to access item
   * details, maintaining strict cart ownership boundaries. Relevant information
   * from the 'shopping_mall_cart_items' Prisma model, such as quantity, SKU,
   * creation, and update times, is included in the response.
   *
   * Security is enforced by verifying cart ownership, blocking access for
   * non-owners or unauthorized users. Related operations include listing all
   * items in a cart and updating or removing specific cart items by their
   * identifiers. Errors such as "not found" or "forbidden" are handled
   * according to platform security policies and standard API practices.
   *
   * @param connection
   * @param cartId Unique identifier of the target cart (UUID format). Used for
   *   cart ownership and lookup.
   * @param itemId Unique identifier of the cart item (UUID format). Used to
   *   identify the specific item within the cart.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
