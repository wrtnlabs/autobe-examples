  /**
   * Remove an item from a shopping cart (shopping_mall_cart_items) by itemId
   * within a specified cart.
   *
   * Remove a specific item from a customer's shopping cart by its itemId. This
   * operation is used when a user decides to no longer purchase a specific SKU
   * in their cart, immediately and permanently removing the item record from
   * both the user's cart and the shopping_mall_cart_items table.
   *
   * Only the owner of the shopping cart may remove items from their cart
   * through this endpoint. The operation ensures that child cart_items are
   * deleted only within the context of the currently authenticated user's cart,
   * ensuring no cross-user access is possible. Inventory is not adjusted until
   * checkout, but removing an item will reflect immediately in all cart read
   * operations.
   *
   * Validation includes verifying ownership and correct association between the
   * cartId and itemId (the item must be part of the given cart). Related
   * operations include item creation (POST to /carts/{cartId}/items),
   * list/detail retrieval, and update (PUT).
   *
   * @param connection
   * @param cartId Unique identifier of the shopping cart containing the item.
   * @param itemId Unique identifier of the cart item to remove.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
