import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerCarts } from "../../../../providers/postShoppingMallCustomerCarts";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerCartsCartId } from "../../../../providers/putShoppingMallCustomerCartsCartId";
import { deleteShoppingMallCustomerCartsCartId } from "../../../../providers/deleteShoppingMallCustomerCartsCartId";

import { IShoppingMallCart } from "../../../../api/structures/IShoppingMallCart";

@Controller("/shoppingMall/customer/carts")
export class ShoppingmallCustomerCartsController {
  /**
   * Create a new shopping cart for an authenticated customer
   * (shopping_mall_carts).
   *
   * This operation allows an authenticated customer to initialize a new
   * shopping cart, which serves as the primary container for their intended
   * purchases within the platform.
   *
   * The cart is directly linked to the customer's account, guaranteeing that
   * every customer maintains a single unique active cart at any time. When
   * invoked, the endpoint creates the cart record with all relevant foreign
   * keys, timestamps, and associations as required by business logic. Attempts
   * to create a cart for a customer who already possesses one should result in
   * a validation error, enforcing the one-cart-per-customer rule.
   *
   * Usage of this API is foundational for all add-to-cart, checkout, and
   * inventory verification operations that follow. The security model demands
   * that only authenticated customer actors invoke this operation, enforcing
   * business rule consistency and data integrity throughout the checkout
   * process. Error responses will indicate if preconditions are not met or if
   * the cart already exists for the session user.
   *
   * This API operation operates exclusively on the shopping_mall_carts table as
   * described in the Prisma schema, leveraging relationships and uniqueness
   * constraints for robust backend enforcement.
   *
   * @param connection
   * @param body No user-supplied request body is required to create a cart; the
   *   system depends on the authenticated customer context for association.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCart.ICreate,
  ): Promise<IShoppingMallCart> {
    try {
      return await postShoppingMallCustomerCarts({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shopping cart’s state fields by its ID
   * (shopping_mall_carts).
   *
   * This operation allows for modification of a customer's existing shopping
   * cart, given the cart's unique identifier. Typical update use cases include
   * refreshing the cart after certain business events (such as inventory or
   * item changes), or processing migration/ownership scenarios. The endpoint is
   * secured to ensure that only the rightful customer or privileged support
   * actors are permitted to perform updates, enforcing both business and data
   * integrity.
   *
   * The update API is tightly integrated with platform logic that ensures only
   * valid field modifications are possible, respecting all relevant constraints
   * as defined in the shopping_mall_carts table. Any attempt to update
   * non-modifiable fields or to access carts belonging to other customers is
   * strictly denied, with clear error feedback. Update support may include
   * refreshing last-modified timestamps or updating associated foreign keys per
   * validated flows.
   *
   * All update operations must be reflected in audit trails for compliance,
   * especially where admin actors are permitted. This endpoint guarantees
   * backend synchronization for all cart-related business transitions as part
   * of the shopping and checkout lifecycle.
   *
   * @param connection
   * @param cartId Unique identifier of the shopping cart to update (UUID
   *   format, global scope).
   * @param body Fields and values required to update the shopping cart, such as
   *   timestamps or foreign keys. Structure determined per Prisma schema and
   *   operation’s business rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":cartId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCart.IUpdate,
  ): Promise<IShoppingMallCart> {
    try {
      return await putShoppingMallCustomerCartsCartId({
        customer,
        cartId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a shopping cart and its items (shopping_mall_carts).
   *
   * Permanently delete a cart entity for a customer using the cart's unique
   * identifier.
   *
   * This operation targets the shopping_mall_carts table, which is the root
   * entity for customer shopping carts. By specifying the unique cartId, a
   * customer or authorized user can invoke this endpoint to remove the cart and
   * all items contained within it. The system enforces a one-cart-per-customer
   * rule, so deletion is only allowed if this rule and additional business
   * constraints are satisfied.
   *
   * Security considerations require that only the cart's owner or an admin be
   * able to perform deletion. If the cart is already checked out or in a locked
   * state due to an in-progress order, this operation will fail gracefully with
   * an appropriate error message.
   *
   * Associated cart items (records in shopping_mall_cart_items) are
   * cascade-removed as part of this operation to ensure referential integrity.
   * After a cart is deleted, any attempt to add new items for the customer will
   * require cart re-creation. This endpoint guarantees inventory and state
   * consistency by disallowing deletion when dependent business processes (such
   * as checkout) are active.
   *
   * @param connection
   * @param cartId Unique identifier of the target shopping cart to delete.
   *   (UUID format)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":cartId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerCartsCartId({
        customer,
        cartId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
