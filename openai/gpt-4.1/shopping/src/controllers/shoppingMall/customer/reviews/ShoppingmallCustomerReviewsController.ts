import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putShoppingMallCustomerReviewsReviewId } from "../../../../providers/putShoppingMallCustomerReviewsReviewId";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteShoppingMallCustomerReviewsReviewId } from "../../../../providers/deleteShoppingMallCustomerReviewsReviewId";

import { IShoppingMallReview } from "../../../../api/structures/IShoppingMallReview";

@Controller("/shoppingMall/customer/reviews/:reviewId")
export class ShoppingmallCustomerReviewsController {
  /**
   * This API endpoint allows updating of a product review in the shopping mall
   * platform, targeted by its unique identifier. The endpoint supports
   * modifications to core review fields such as the title (summary), body text,
   * draft status, and moderation information. Only actual customers who
   * purchased the product can update their reviews, and all changes must comply
   * with minimum/maximum content length, moderation policy, and withdrawal
   * rules.
   *
   * Security is enforced—users can only edit reviews they have authored and
   * only within the allowed edit window, except for moderation changes by
   * platform staff. All changes are tracked in the audit log with full
   * traceability (via updated_at and session/customer IDs). Review updates may
   * enter the moderation queue if required, and review status transitions must
   * follow business-defined state machines (e.g., draft → published → withdrawn
   * or pending moderation, etc.).
   *
   * This operation references the shopping_mall_reviews schema, respecting the
   * integrity of foreign keys to customer, session, order item, product, SKU,
   * and rating. Related fields not supplied in the request remain unchanged.
   * Error handling covers invalid states, forbidden access, and periods where
   * no modifications are allowed.
   *
   * @param connection
   * @param reviewId Unique identifier of the product review to update.
   * @param body Fields of the review to update, such as title, body, is_draft,
   *   withdrawn_at, moderation_status, or moderation_reason.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReview.IUpdate,
  ): Promise<IShoppingMallReview> {
    try {
      return await putShoppingMallCustomerReviewsReviewId({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API endpoint removes a specific product review from the platform
   * database, based on its unique reviewId. Depending on the business and
   * moderation rules, this may entail soft-deleting the review (setting
   * deleted_at or withdrawn_at), or permanent physical deletion if platform
   * policy allows it. The response confirms removal by returning the deleted
   * entity for compliance and API contract.
   *
   * Security rules strictly enforce access: only the original review author
   * (customer) within the review edit/removal period, or a privileged platform
   * administrator or moderator, may delete reviews. All delete operations are
   * logged for traceability, including the session, customer, and moderation
   * context. Relationships to the review's associated product, SKU, order item,
   * and rating are respected, and orphaned entities are prevented by foreign
   * key enforcement.
   *
   * This operation ensures compliance with shopping_mall_reviews business
   * rules, with error handling for invalid access, not found, forbidden state,
   * or non-removable reviews (due to moderation freeze, dispute, or time window
   * expiration).
   *
   * @param connection
   * @param reviewId Unique identifier of the product review to delete.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReview> {
    try {
      return await deleteShoppingMallCustomerReviewsReviewId({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
