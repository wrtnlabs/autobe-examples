import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallCustomerCustomersCustomerId } from "../../../../providers/getShoppingMallCustomerCustomersCustomerId";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerCustomersCustomerId } from "../../../../providers/putShoppingMallCustomerCustomersCustomerId";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";

@Controller("/shoppingMall/customer/customers/:customerId")
export class ShoppingmallCustomerCustomersController {
  /**
   * Fetch detailed profile for a shopping mall customer
   * (shopping_mall_customers table).
   *
   * Retrieve the complete profile information of a customer account identified
   * by their unique ID. This includes name, email, phone number, verification
   * status, and timestamps for creation and last update. All data are sourced
   * directly from the shopping_mall_customers table, assuring referential
   * integrity and up-to-date information.
   *
   * Security and authorization are critical; only the customer themselves,
   * platform admins, or designated support personnel may access a customer's
   * sensitive profile. Attempting to fetch another user's data without proper
   * authorization should result in access denial.
   *
   * The operation carefully omits sensitive fields such as the password hash
   * and exposes only business-relevant, user-facing information. This endpoint
   * is critical to supporting user dashboards, order workflows, and account
   * management features.
   *
   * @param connection
   * @param customerId Unique identifier (UUID) of the target customer account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await getShoppingMallCustomerCustomersCustomerId({
        customer,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing customer's profile details (shopping_mall_customers
   * table).
   *
   * Update a customer's profile details such as name, phone, and email, while
   * enforcing business constraints from the shopping_mall_customers schema. The
   * operation validates email uniqueness before applying updates and prevents
   * changes to authentication secrets like password hashes. Only permitted
   * actors (the customer or platform admin) may execute this action. All
   * changes are logged for audit.
   *
   * Email updates may also trigger a new verification workflow if required by
   * business logic. Attempts to update the profile with an already-registered
   * email or other constraint violations will cause the request to be rejected
   * with meaningful error messaging.
   *
   * This operation is designed for use in both user-facing account settings
   * interfaces and admin-driven customer management dashboards.
   *
   * @param connection
   * @param customerId Unique identifier (UUID) of the customer account to
   *   update.
   * @param body Payload with customer fields allowed to be updated (name,
   *   phone, email).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCustomer.IUpdate,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await putShoppingMallCustomerCustomersCustomerId({
        customer,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
