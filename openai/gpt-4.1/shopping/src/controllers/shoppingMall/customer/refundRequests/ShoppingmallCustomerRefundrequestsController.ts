import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallCustomerRefundRequestsRefundRequestId } from "../../../../providers/getShoppingMallCustomerRefundRequestsRefundRequestId";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { postShoppingMallCustomerRefundRequests } from "../../../../providers/postShoppingMallCustomerRefundRequests";

import { IShoppingMallRefundRequest } from "../../../../api/structures/IShoppingMallRefundRequest";

@Controller("/shoppingMall/customer/refundRequests")
export class ShoppingmallCustomerRefundrequestsController {
  /**
   * Retrieve the full detail for a single refund request in the shopping mall.
   * This endpoint provides all information filed by the customer for this
   * request, including the refund reason, status (such as pending, approved,
   * rejected, processing, refunded), the requested and (if decided) approved
   * refund amounts, and timestamps indicating the creation and latest update to
   * the request.
   *
   * The response also includes references to the associated order, the customer
   * who initiated the refund, the seller involved, and any admin who has acted
   * on or is assigned to the request. Timestamps for creation and updates are
   * included for precise workflow tracking and compliance. The refund request's
   * workflow state, including any logical soft deletion ('deleted_at'), is
   * honored; if the record is logically deleted, it will be omitted or return a
   * suitable error response.
   *
   * This operation is critical for customer support, dispute resolution, and
   * refund workflow management by platform actors. Only authorized users
   * (admin, customer, or seller associated with the refund) should be allowed
   * to access the details. Related operations: create refund request (POST
   * /refundRequests), list/search refund requests (PATCH /refundRequests).
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request to retrieve
   *   (UUID primary key).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":refundRequestId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await getShoppingMallCustomerRefundRequestsRefundRequestId({
        customer,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Submit a new refund request for an eligible order or order item. The
   * customer must provide the order reference, reason for the request, and the
   * requested refund amount. The seller and customer references link the refund
   * request to the transaction parties involved. On creation, the request
   * status is set to 'pending' and awaits review by platform actors. All
   * required fields must be present.
   *
   * The operation ensures that only valid and eligible orders/items may be
   * subject to refund, and that the correct customer and seller are associated
   * with the request. Audit trails are automatically established based on the
   * fields and relationships modeled in the schema. The system records
   * timestamps for creation and update, and supports soft deletion logic for
   * subsequent workflows or compliance requirements.
   *
   * This endpoint is a key entry point for the overall returns and dispute
   * management process in the shopping mall. Related operations: get refund
   * request (GET /refundRequests/{refundRequestId}), search refund requests
   * (PATCH /refundRequests), approve/refuse refund request (handled by
   * workflow, not this operation).
   *
   * @param connection
   * @param body Information required to submit a new refund request (must
   *   include order, customer, seller, reason, and requested amount).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallRefundRequest.ICreate,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await postShoppingMallCustomerRefundRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
