import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerProductRatings } from "../../../../providers/postShoppingMallCustomerProductRatings";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerProductRatingsProductRatingId } from "../../../../providers/putShoppingMallCustomerProductRatingsProductRatingId";
import { deleteShoppingMallCustomerProductRatingsProductRatingId } from "../../../../providers/deleteShoppingMallCustomerProductRatingsProductRatingId";

import { IShoppingMallProductRating } from "../../../../api/structures/IShoppingMallProductRating";

@Controller("/shoppingMall/customer/productRatings")
export class ShoppingmallCustomerProductratingsController {
  /**
   * Create a new standalone product rating entry linked to a given customer,
   * product SKU, and order item.
   *
   * This API endpoint accepts a structured request containing all necessary
   * fields to define a rating, including the value (1–5 stars), audit and
   * relationship references, and creates a new record adhering to the composite
   * unique constraint (customer, SKU, order item). The operation automatically
   * populates audit fields such as timestamps and session identifiers, enforces
   * value range limits, and checks eligibility (for example, that a customer
   * has purchased the item and has not already reviewed it). If all conditions
   * are satisfied, it creates the rating and returns the full record for
   * confirmation.
   *
   * Security and permissions are enforced to ensure that only eligible
   * customers can create ratings for products they have purchased. Appropriate
   * error handling is implemented for duplicate ratings, foreign key
   * mismatches, and values out of range.
   *
   * The operation can be paired with retrieval (GET
   * /productRatings/{productRatingId}) and statistics endpoints for complete
   * product rating management workflows.
   *
   * @param connection
   * @param body Rating creation data, including value, customer/product/order
   *   relationships, as defined by IShoppingMallProductRating.ICreate DTO.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallProductRating.ICreate,
  ): Promise<IShoppingMallProductRating> {
    try {
      return await postShoppingMallCustomerProductRatings({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product rating record associated with a customer,
   * product, SKU, and order details. This operation enables a customer to
   * modify their previously submitted rating value, for example if they wish to
   * change their feedback after experiencing changes in the product or service
   * quality.
   *
   * Only the original customer who submitted the rating can perform this
   * update, and only within a limited time window specified by business
   * policies. The system will verify the customer's session and enforce all
   * validation checks, including confirming that the rating remains associated
   * with a valid, non-deleted order item and product SKU. Attempting to update
   * outside of the allowed timeframe, or by unauthorized customers, will result
   * in an error.
   *
   * This API uses the shopping_mall_product_ratings Prisma table as its
   * underlying database model, referencing all relevant foreign key
   * relationships for integrity and audit trail. Updates are timestamped to
   * reflect the latest modification, and all changes are subject to audit
   * logging for security compliance.
   *
   * @param connection
   * @param productRatingId Unique identifier of the product rating to update.
   * @param body The new product rating data to be applied.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productRatingId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productRatingId")
    productRatingId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductRating.IUpdate,
  ): Promise<IShoppingMallProductRating> {
    try {
      return await putShoppingMallCustomerProductRatingsProductRatingId({
        customer,
        productRatingId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Erase an existing shopping mall product rating, identified by its unique
   * ID. This operation is typically performed when a customer wishes to
   * withdraw their rating, or in rare situations where an invalid or
   * inappropriate rating must be removed from aggregation statistics and search
   * results.
   *
   * The operation is restricted so that only the customer who originally
   * submitted the rating can request its removal; administrative removal is not
   * provided in this endpoint for audit and accountability reasons. Ratings are
   * not physically deleted but rather marked as deleted using the deleted_at
   * soft delete column, protecting system integrity and historical tracking.
   * Subsequent queries will exclude ratings marked as deleted unless explicitly
   * requested via admin operations.
   *
   * All removals are logged for compliance monitoring and security reasons.
   * Related API calls, such as search or get-by-ID, will not include ratings
   * flagged as deleted, ensuring accurate end-user experiences.
   *
   * @param connection
   * @param productRatingId Unique identifier of the product rating to remove.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productRatingId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productRatingId")
    productRatingId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerProductRatingsProductRatingId({
        customer,
        productRatingId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
