import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallProducts } from "../../../providers/postShoppingMallProducts";
import { patchShoppingMallProducts } from "../../../providers/patchShoppingMallProducts";
import { getShoppingMallProductsProductId } from "../../../providers/getShoppingMallProductsProductId";

import { IShoppingMallProduct } from "../../../api/structures/IShoppingMallProduct";
import { IPageIShoppingMallProduct } from "../../../api/structures/IPageIShoppingMallProduct";

@Controller("/shoppingMall/products")
export class ShoppingmallProductsController {
  /**
   * Create a new product entry in the shopping mall's catalog.
   *
   * The API accepts data for a new product, including its name, business
   * description, default listing price, workflow status string (e.g., draft,
   * published, archived, blocked), and the identifier of the owning seller. The
   * system automatically sets creation and update timestamps. This operation
   * enforces business logic such as requiring the title to be unique for each
   * seller, setting appropriate initial status, and storing the core catalog
   * structure to enable future expansion with SKUs, images, and
   * categorization.
   *
   * The response returns the full product record as stored, including all
   * fields present in the shopping_mall_products schema. Any attempted creation
   * with non-unique title per seller or invalid field values will result in
   * validation errors, which must be handled according to business rules.
   *
   * @param connection
   * @param body Product creation information to populate the
   *   shopping_mall_products table
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: IShoppingMallProduct.ICreate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await postShoppingMallProducts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * List and search products in the shopping mall catalog using complex query,
   * filtering, and pagination.
   *
   * This operation is accessible to all users and does not require
   * authentication, enabling public discovery of marketplace offerings. It
   * supports filtering by title, description, seller, workflow status,
   * creation/modification date, and more. Query results are paginated and
   * returned in summary DTO format, optimized for grid or list display in user
   * interfaces. Sorting options such as by price, popularity, and recency are
   * supported for flexible UX needs.
   *
   * The operation enforces query-side validation for supported fields, size
   * limits (to prevent overload), and input sanitization for search safety.
   * Related operations include creating, updating, retrieving, or deleting
   * individual products and categories. The resulting dataset is suitable for
   * front-facing discovery surfaces, search bars, and product suggestion
   * features across the platform. Hard-deleted or archived products are
   * automatically excluded from results.
   *
   * @param connection
   * @param body Filter and search criteria, pagination, and sorting for product
   *   list retrieval.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallProduct.IRequest,
  ): Promise<IPageIShoppingMallProduct.ISummary> {
    try {
      return await patchShoppingMallProducts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete product details for the specified product.
   *
   * This API is used to access all business and presentation data of a single
   * product, including its title, core description, default display price,
   * business status (such as draft, published, archived, etc.), and audit
   * timestamps such as creation and last update times. It returns seller
   * association by referencing the owning seller's unique identifier and
   * provides information on whether the product is soft-deleted or active via
   * the deleted_at field.
   *
   * Only public data and fields marked as non-sensitive are exposed in this
   * response; sensitive seller or internal audit information should be handled
   * at the service layer or via access scopes in the API layer.
   *
   * This endpoint strictly references the shopping_mall_products table as
   * described in the Prisma schema and ensures that all fields are included in
   * the response in accordance with the current schema structure. Related
   * entities such as SKUs, images, or category assignments are not directly
   * included in this response unless explicitly expanded through other
   * endpoints.
   *
   * @param connection
   * @param productId Unique identifier of the target product in the catalog
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProduct> {
    try {
      return await getShoppingMallProductsProductId({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
