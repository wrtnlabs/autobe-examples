import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallProductsProductIdImagesImageId } from "../../../../providers/getShoppingMallProductsProductIdImagesImageId";

import { IShoppingMallProductImage } from "../../../../api/structures/IShoppingMallProductImage";

@Controller("/shoppingMall/products/:productId/images/:imageId")
export class ShoppingmallProductsImagesController {
  /**
   * Retrieve a specific image for a shopping mall product
   * (shopping_mall_product_images).
   *
   * Retrieve a single image asset associated with a product for use in product
   * galleries or detail pages.
   *
   * This operation is designed to fetch the complete metadata for a specific
   * product image, identified by its unique ID within the scope of a given
   * product. The response includes the CDN URI, alt text, display order
   * position, and any associated management label, allowing clients to build
   * rich UI representations of product galleries and detail pages.
   *
   * The API enforces filtering so that only images which are active (not
   * soft-deleted, i.e., deleted_at is null) are returned. The product and image
   * linkage is validated to ensure proper ownership and data integrity
   * according to the product-image relationship as described in the
   * shopping_mall_product_images Prisma schema. This ensures only valid, active
   * images are exposed.
   *
   * Security-wise, the endpoint is publicly accessible, as product images are
   * intended for display on the customer-facing frontend. Soft-deleted or
   * orphaned images are automatically excluded, and no sensitive data is
   * disclosed. Related endpoints include creating, updating, and deleting
   * product images for gallery management.
   *
   * @param connection
   * @param productId Unique identifier (UUID) of the product to which the image
   *   belongs.
   * @param imageId Unique identifier (UUID) of the image asset to retrieve,
   *   associated with the product.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductImage> {
    try {
      return await getShoppingMallProductsProductIdImagesImageId({
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
