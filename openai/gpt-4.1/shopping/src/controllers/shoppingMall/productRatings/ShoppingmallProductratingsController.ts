import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallProductRatingsProductRatingId } from "../../../providers/getShoppingMallProductRatingsProductRatingId";

import { IShoppingMallProductRating } from "../../../api/structures/IShoppingMallProductRating";

@Controller("/shoppingMall/productRatings/:productRatingId")
export class ShoppingmallProductratingsController {
  /**
   * Retrieve full details for a standalone product rating record identified by
   * its unique ID.
   *
   * This API operation returns all properties of a product rating, including
   * the numeric value (1–5 stars), linked customer, product SKU, associated
   * order, and audit trail such as the customer session and timestamps. The
   * description field in the Prisma schema clarifies that this rating is always
   * tied to a specific customer, SKU, and order item, and updates are only
   * allowed by the original customer within the permitted edit window.
   *
   * Security: Access may be restricted based on requester permissions—customers
   * may view only their own ratings, sellers may view ratings for their
   * products, and admins may have broader access. The soft delete field
   * (deleted_at) is included for completeness, and consumers of this API should
   * check for this marker before presenting the rating in user-facing
   * applications.
   *
   * Use this operation in conjunction with the creation endpoint for new
   * ratings, and aggregation endpoints for overall product rating statistics.
   * Error scenarios include not found (invalid ID), unauthorized access, or
   * ratings that have been soft deleted and filtered by business policy.
   *
   * @param connection
   * @param productRatingId Unique identifier of the target product rating
   *   record (UUID format).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("productRatingId")
    productRatingId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductRating> {
    try {
      return await getShoppingMallProductRatingsProductRatingId({
        productRatingId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
