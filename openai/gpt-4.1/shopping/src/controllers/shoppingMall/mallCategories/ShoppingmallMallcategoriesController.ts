import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallMallCategories } from "../../../providers/patchShoppingMallMallCategories";
import { getShoppingMallMallCategoriesName } from "../../../providers/getShoppingMallMallCategoriesName";

import { IPageIShoppingMallCategory } from "../../../api/structures/IPageIShoppingMallCategory";
import { IShoppingMallCategory } from "../../../api/structures/IShoppingMallCategory";

@Controller("/shoppingMall/mallCategories")
export class ShoppingmallMallcategoriesController {
  /**
   * Search and list product categories (shopping_mall_categories) with
   * filtering, sorting, and pagination.
   *
   * Retrieve a paginated and filtered list of product categories and their
   * metadata for navigation, display, and management purposes.
   *
   * This endpoint supports hierarchical taxonomy exploration, focused category
   * searches (by name, parent, or status), and efficient listing for
   * catalog/admin panel usage. It exposes all key fields—including
   * relationships and status—from the Prisma schema.
   *
   * The API is designed both for public use (navigation and product browsing)
   * and for admin/merchandiser tooling (advanced querying, batch updates, or
   * audits). Security and rate-limiting considerations should be configured
   * according to usage context. Data returned conforms to the category summary
   * and pagination standards for frontend consumption.
   *
   * @param connection
   * @param body Filtering, search, sorting, and pagination parameters for
   *   category list management or frontend taxonomy exploration.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallCategory.IRequest,
  ): Promise<IPageIShoppingMallCategory.ISummary> {
    try {
      return await patchShoppingMallMallCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single shopping mall category by its unique name from
   * shopping_mall_categories table.
   *
   * Retrieve the detailed information of a shopping mall category by its unique
   * name.
   *
   * This operation allows clients to fetch the complete details for a single
   * product or navigation category within the shopping mall system. Categories
   * are uniquely identified by their name field, which is strictly enforced as
   * unique in the database.
   *
   * The operation returns all relevant fields for the category, including its
   * full description, parent-child hierarchy (through parent_id), navigation
   * sort order, current status (active/inactive/deprecated), and audit fields
   * for traceability. If the specified category name does not exist, a not
   * found error is returned.
   *
   * No authentication is required: this endpoint is public and meant for
   * general user/navigation use as well as for integrations needing trusted
   * category lookups. The operation does not require a request body, and only
   * the name parameter in the path.
   *
   * @param connection
   * @param name Unique category name of the shopping mall category (global
   *   scope). Required for locating the specific category. This must match
   *   exactly with a unique category name, as enforced by the
   * @@unique([name]) constraint in the database.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":name")
  public async at(
    @TypedParam("name")
    name: string,
  ): Promise<IShoppingMallCategory> {
    try {
      return await getShoppingMallMallCategoriesName({
        name,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
