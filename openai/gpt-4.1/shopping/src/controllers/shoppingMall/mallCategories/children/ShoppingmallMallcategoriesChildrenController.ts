import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallMallCategoriesNameChildren } from "../../../../providers/patchShoppingMallMallCategoriesNameChildren";

import { IPageIShoppingMallCategory } from "../../../../api/structures/IPageIShoppingMallCategory";
import { IShoppingMallCategory } from "../../../../api/structures/IShoppingMallCategory";

@Controller("/shoppingMall/mallCategories/:name/children")
export class ShoppingmallMallcategoriesChildrenController {
  /**
   * Retrieve a filtered and paginated list of direct child categories under a
   * specific parent category, identified by its unique name.
   *
   * This operation supports use cases such as building category navigation
   * trees for the shop UI, assisting admins in managing hierarchical category
   * structures, and enabling merchandising workflows that require knowledge of
   * category organization.
   *
   * The request must include filtering and pagination criteria as defined by
   * IShoppingMallCategory.IRequest. Only categories with parent_id mapped to
   * the specified category 'name' will be included. The response is a paginated
   * list of category summaries, supporting scalable UI rendering and efficient
   * browsing for large category trees.
   *
   * Note: Only active or admin-visible categories are included unless otherwise
   * specified in the request. Results are sorted by 'sort_order' by default.
   * Security and visibility are enforced based on actor role and API
   * configuration.
   *
   * @param connection
   * @param name Unique category name of the parent category (global scope).
   * @param body Search, filter, and pagination parameters for listing category
   *   children.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("name")
    name: string,
    @TypedBody()
    body: IShoppingMallCategory.IRequest,
  ): Promise<IPageIShoppingMallCategory.ISummary> {
    try {
      return await patchShoppingMallMallCategoriesNameChildren({
        name,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
