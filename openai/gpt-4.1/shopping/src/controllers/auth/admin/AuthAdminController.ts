import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { IShoppingAdmin } from "../../../api/structures/IShoppingAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Register a new admin account in shopping_admins table for platform
   * administration.
   *
   * This operation enables registration of a new administrator for the shopping
   * mall platform. The shopping_admins table defines the required fields: email
   * (unique identifier for admin login and notifications), password_hash
   * (securely stored password for authentication), name (real name for audit
   * and communications), role (privilege level string for RBAC), and status
   * (account state such as active, suspended, pending).
   *
   * The endpoint ensures that only unique emails are registered, leveraging the
   * shopping_admins.email unique constraint. Passwords are never stored as
   * plain text, aligning with the password_hash field and security best
   * practices. Additional admin attributes (such as MFA configuration) are
   * handled separately and not within this registration flow.
   *
   * Upon account creation, the admin is automatically assigned a role and an
   * active status, unless specified otherwise by an authorized superadmin. Role
   * assignment and status settings must match the permissible values supported
   * by the shopping_admins table. If any required field is invalid or missing,
   * the endpoint returns detailed error feedback.
   *
   * Security measures enforced by this endpoint include confirmation of email
   * uniqueness, the use of secure password hashing (never directly exposed),
   * and dedicated audit logging via related tables. Only actors with sufficient
   * privileges can invoke this operation.
   *
   * Related operations include: login for admin authentication (handled via a
   * different endpoint), update admin information, suspend/reactivate admin,
   * and enable MFA for an admin account, all of which have their own workflows
   * and endpoints. This operation serves as the dedicated entry point for
   * onboarding new admin accounts on the Shopping Mall platform.
   *
   * @param connection
   * @param body New admin registration data. Only email, password_hash, name,
   *   role, and status fields are accepted as per shopping_admins schema.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingAdmin.IJoin,
  ): Promise<IShoppingAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate and log in an admin account via shopping_admins table.
   *
   * This operation enables a registered admin to authenticate and establish a
   * new session on the platform. It is mapped to the shopping_admins table,
   * which contains the necessary fields for authentication: email (unique login
   * identifier) and password_hash (for credential validation). Status and role
   * fields are validated to ensure only active admins are granted access. The
   * operation checks that the status of the admin account is not suspended or
   * pending, before issuing JWT tokens.
   *
   * On successful login, the endpoint issues both access and refresh tokens as
   * part of the IShoppingAdmin.IAuthorized DTO, enabling administration
   * functions according to RBAC. The password_hash or other sensitive fields
   * are never included in the response. Failed authentication, due to invalid
   * credentials or account status, leads to appropriate error messaging. All
   * login attempts are audit-logged for compliance and security analysis.
   *
   * Other related API operations include join (registration for new admin),
   * refresh (token renewal), and enableMfa (enabling multifactor authentication
   * for the admin account), each handled on their own endpoints. This endpoint
   * is critical for secure backend platform management access.
   *
   * @param connection
   * @param body Admin login request payload, containing email and password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingAdmin.ILogin,
  ): Promise<IShoppingAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT tokens for authenticated admins with valid refresh token, via
   * shopping_admins table.
   *
   * Allows an authenticated admin to renew JWT access and refresh tokens. This
   * process checks token validity, admin account status, and ensures the admin
   * has not been suspended or deleted. Utilizes shopping_admins fields for
   * identity validation, while ensuring no sensitive information is leaked in
   * responses. Any misuse or expired tokens are reported with specific error
   * codes.
   *
   * The operation is mapped directly to the shopping_admins table for account
   * validation, but does not read or mutate any fields other than those
   * required for permission verification and session audit. Session and MFA
   * configuration reside outside of this refresh path. The endpoint is part of
   * the robust authentication model for admin actors.
   *
   * Related endpoints include join (admin registration), login (admin
   * authentication), and enableMfa (enabling multifactor authentication –
   * handled on a separate endpoint). This refresh endpoint provides for
   * rotation of tokens and session extension, integral for continuous
   * administrator access while maintaining security boundaries.
   *
   * @param connection
   * @param body Admin token refresh request parameters (must include the
   *   current refresh token).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingAdmin.IRefresh,
  ): Promise<IShoppingAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
