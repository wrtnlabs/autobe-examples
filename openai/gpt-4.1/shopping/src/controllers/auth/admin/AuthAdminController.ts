import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { IShoppingMallAdmin } from "../../../api/structures/IShoppingMallAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Register a new platform admin in the shopping_mall_admins table and issue
   * JWT tokens.
   *
   * This API operation allows registration of new admin accounts into the
   * system by collecting required credentials such as username, email, and
   * password, as specified in the 'shopping_mall_admins' Prisma schema. All
   * input fields are validated strictly according to the schema's constraints
   * (such as unique email, password policy, and required primitive fields). The
   * admin account is created and the administrator receives both an access
   * token and a refresh token in the response.
   *
   * Implementation leverages the available schema fields to bind each input
   * field directly to the database, ensuring that only present fields are
   * requested and stored. Only the fields available in the
   * 'shopping_mall_admins' schema can be used for registration (with additional
   * features omitted if they are not defined in the schema).
   *
   * This operation is tied to admin onboarding business logic, with
   * registration being reserved for authorized actors and limited in frequency
   * to mitigate abuse. The authentication tokens returned enable the admin to
   * log in and maintain authenticated sessions in subsequent requests.
   *
   * Security consideration: Registration abuse is prevented by business logic
   * limitations and auditing. All write operations are transactional, and
   * rollback is triggered for any unique constraint or business logic
   * violations based on schema specification.
   *
   * Related: login (credential authentication via /auth/admin/login) and
   * refresh (JWT/authorization token renewal via /auth/admin/refresh).
   *
   * @param connection
   * @param body Payload for admin registration (join) operation. Maps all
   *   registrable fields from the shopping_mall_admins schema, such as email,
   *   password, username, and any other required primitive fields.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.ICreate,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate admin credentials and issue new JWT tokens via the
   * shopping_mall_admins table.
   *
   * This API authenticates an admin account using credentials such as email and
   * password (or only those that exist in the 'shopping_mall_admins' schema).
   * It validates admin credentials against the stored database record, using
   * secure password hashing and comparison as appropriate for the schema
   * fields. On successful authentication, the admin receives new authentication
   * tokens (access and refresh), formatted per the unified security model and
   * response schema conventions.
   *
   * Only schema-defined fields are eligible for authentication. Rate limiting,
   * login failure tracking, and administrator lockout are enforced to prevent
   * brute-force and enumeration attacks, as specified by security requirements.
   * Admin sessions are established securely, never exposing sensitive
   * information in error conditions.
   *
   * This is a public endpoint, accessible to admin users attempting to log in.
   * After authentication, the JWT tokens conform to the required output DTO.
   * Related operations: admin token refresh (/auth/admin/refresh) and admin
   * registration (/auth/admin/join).
   *
   * @param connection
   * @param body Payload with all necessary admin login credential fields
   *   derived from the shopping_mall_admins Prisma schema (e.g., email,
   *   password).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.ILogin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew admin JWT tokens via secure token refresh using the
   * shopping_mall_admins table.
   *
   * This API receives a valid refresh token for a platform admin, validates the
   * token against the session context and the 'shopping_mall_admins' schema,
   * and issues a new authentication token set. The token rotation logic is
   * schema-driven, supporting only what is present in the database. If the
   * admin is inactive, deleted, or fails other schema-level conditions, an
   * error is returned.
   *
   * The operation strengthens security by enforcing strict validation of the
   * refresh token, user identity, and compliance with session management
   * requirements. It enables persistent platform admin authentication without
   * requiring re-entry of credentials, as long as the existing session remains
   * valid and the admin record exists in the database.
   *
   * This endpoint is accessible to authenticated admins presenting a valid
   * refresh token. Related operations include admin login (/auth/admin/login)
   * and admin registration (/auth/admin/join).
   *
   * @param connection
   * @param body Payload with the refresh token for admin JWT token rotation.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallAdmin.IRefresh,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
