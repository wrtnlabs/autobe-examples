import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthCustomerPasswordReset } from "../../../../../providers/postAuthCustomerPasswordReset";

import { IShoppingCustomer } from "../../../../../api/structures/IShoppingCustomer";

@Controller("/auth/customer/password/reset")
export class AuthCustomerPasswordResetController {
  /**
   * Finalize customer password reset by validating the token and updating
   * 'shopping_customers' schema.
   *
   * This endpoint finalizes customer password reset by verifying the secure
   * reset token against the 'shopping_password_resets' schema fields
   * ('reset_code', 'expires_at', 'consumed_at') and, if valid, updating the
   * related customer's password_hash in the 'shopping_customers' schema. After
   * updating the password, the token row is marked as consumed, with full
   * auditing enforced as described in the schema's relationships. All error
   * responses reference the exact schema validation that failed.
   *
   * Business logic enforces password strength and secure handling, with email
   * notification and session invalidation handled separately using schema
   * relationships. This operation is always linked to a prior call to the
   * password reset token initiation, and closely aligns with login and token
   * refresh endpoints for full customer account recovery. Only explicit,
   * existing schema fields are handled at all steps to ensure type and business
   * logic correctness.
   *
   * @param connection
   * @param body Password reset token and new password, matching schema for
   *   resets and customer updates.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async resetPassword(
    @TypedBody()
    body: IShoppingCustomer.ICompletePasswordReset,
  ): Promise<IShoppingCustomer.IPasswordResetCompleted> {
    try {
      return await postAuthCustomerPasswordReset({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
