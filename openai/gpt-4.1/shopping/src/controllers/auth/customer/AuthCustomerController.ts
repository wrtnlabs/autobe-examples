import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthCustomerJoin } from "../../../providers/postAuthCustomerJoin";
import { postAuthCustomerLogin } from "../../../providers/postAuthCustomerLogin";
import { postAuthCustomerRefresh } from "../../../providers/postAuthCustomerRefresh";

import { IShoppingMallCustomer } from "../../../api/structures/IShoppingMallCustomer";

@Controller("/auth/customer")
export class AuthCustomerController {
  /**
   * Registers a new customer by creating a member account in
   * shopping_mall_customers and returning JWT tokens.
   *
   * This operation registers a new customer account based on user-supplied
   * credentials, storing key identity fields in the shopping_mall_customers
   * table. Email uniqueness is enforced per schema constraints. Successful
   * registration returns JWT tokens for immediate use, transforming an
   * unauthenticated visitor into a full 'member' actor as defined in platform
   * requirements.
   *
   * During execution, input is validated for essential fields including email
   * and password, referencing the schema's unique and required constraints.
   * Password is securely hashed prior to storage, and email must be unique;
   * duplicate attempts trigger appropriate error responses.
   *
   * Account is created inside a transaction to ensure data integrity. The
   * operation does not assign additional roles or permissions at this stage,
   * but it does activate the core customer identity in the system.
   *
   * Security is a priority: passwords are never exposed, and JWT is returned in
   * the expected API response structure—see requirements for security and
   * compliance details. The join flow is the gateway for future login or
   * refresh actions.
   *
   * Related endpoints include login (credential verification post-registration)
   * and token refresh (session renewal), both forming the rest of the customer
   * authentication lifecycle and requiring this registration as a
   * prerequisite.
   *
   * @param connection
   * @param body Registration details for new customer account. Schema fields
   *   must match shopping_mall_customers model (e.g., email, password).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.ICreate,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postAuthCustomerJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates customer credentials against shopping_mall_customers and
   * returns a new JWT token set.
   *
   * This operation enables customer login via email and password
   * authentication, referencing required fields in the shopping_mall_customers
   * schema. Provided credentials are verified; correct input issues fresh JWT
   * access and refresh tokens. Unsuccessful attempts, such as invalid
   * credentials or locked-out accounts, use schema constraints and
   * requirements-driven error messaging.
   *
   * Authentication logic enforces password hashing and secure comparison
   * methods per platform security requirements. If login attempt limits or
   * lockout states exist in schema, these are handled as described, returning
   * errors for exceeded limits or inactive accounts.
   *
   * Login is the principal mechanism for customers to authenticate to protected
   * endpoints, re-using their registration identity. The process never returns
   * password hashes and all error messages are generic to avoid information
   * leakage.
   *
   * Tied directly to the registration (join) and refresh endpoints, this
   * completes the authentication cycle required for secure platform access.
   * Only registered users with valid credentials are authenticated.
   *
   * The schema explicitly provides both 'email' and 'password' fields, required
   * for any customer login, and implementation uses these without assumption.
   *
   * @param connection
   * @param body Customer login credentials—must match required fields in
   *   shopping_mall_customers (e.g., email, password).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.ILogin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postAuthCustomerLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes a customer's JWT tokens upon receipt of valid refresh token,
   * using shopping_mall_customer_sessions.
   *
   * This operation allows a customer to refresh JWT access and refresh tokens,
   * using the session tracking and token rotation logic keyed to
   * shopping_mall_customer_sessions. A valid refresh token must be provided,
   * and token validity is checked against session records for expiration or
   * revocation.
   *
   * The schema includes mechanisms for recording and managing sessions, which
   * are leveraged here for compliance and audit. Expired or invalid tokens
   * generate specific error responses without revealing information that could
   * aid attackers.
   *
   * The endpoint is critical in allowing customers to seamlessly maintain
   * authenticated sessions in accordance with platform security requirements.
   *
   * The process is fully integrated with authentication workflows established
   * in requirements, using both join and login as prerequisites for having
   * issued refresh tokens in the first place.
   *
   * All token management operations are based on schema-supported session
   * structures, ensuring correctness of the refresh logic and recordkeeping.
   *
   * @param connection
   * @param body Refresh token object as per session schema for customer.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallCustomer.IRefresh,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
