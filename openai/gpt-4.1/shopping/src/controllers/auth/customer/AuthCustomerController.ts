import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthCustomerJoin } from "../../../providers/postAuthCustomerJoin";
import { postAuthCustomerLogin } from "../../../providers/postAuthCustomerLogin";
import { postAuthCustomerRefresh } from "../../../providers/postAuthCustomerRefresh";

import { IShoppingCustomer } from "../../../api/structures/IShoppingCustomer";

@Controller("/auth/customer")
export class AuthCustomerController {
  /**
   * Register a new customer (shopping_customers table) and create JWT tokens.
   *
   * This API operation enables the registration of a new customer account by
   * accepting required fields defined in the 'shopping_customers' Prisma
   * schema, including email, password_hash, name, and phone. The operation
   * enforces uniqueness validation on the email field as described in the
   * schema and implemented in database constraints. Upon creation, the system
   * issues JWT access and refresh tokens for session management, utilizing the
   * related session and token infrastructure. Account registration is subject
   * to business logic requirements, including password complexity, real name
   * verification, and phone number validation, all of which must conform to
   * schema formats and constraints.
   *
   * Integration with the shopping_customer_sessions table occurs
   * post-registration to track session information, as customers receive tokens
   * for immediate authenticated use. All validation of input data—such as
   * proper email format and phone structure—relies on the schema-defined field
   * properties and system-enforced rules for the 'customer' actor. Security
   * best practices, including password hashing and audit trail generation, are
   * employed by this endpoint.
   *
   * Registrations resulting in errors, such as attempted duplicate emails
   * (violating the '@@unique([email])' constraint), are handled gracefully by
   * returning informative error messages referencing the violating schema
   * field. Related operations include subsequent login or token-refresh, both
   * of which consume the tokens issued here. All registration attempts are
   * audited for compliance with platform and regulatory requirements, ensuring
   * accountability as reflected in the schema's audit relations.
   *
   * @param connection
   * @param body Customer registration data, strictly matching
   *   'shopping_customers' schema fields required for account creation.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingCustomer.ICreate,
  ): Promise<IShoppingCustomer.IAuthorized> {
    try {
      return await postAuthCustomerJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate customer and issue tokens using 'shopping_customers' schema.
   *
   * This API endpoint authenticates a customer using 'email' and
   * 'password_hash' fields as defined in the 'shopping_customers' schema. If
   * the credentials match an active account, new JWT tokens are generated for
   * session management. The operation references the schema's is_active and
   * deleted_at fields to ensure only eligible accounts can access the system.
   * Audit log and session creation are triggered in the
   * 'shopping_customer_sessions' related table, using metadata such as IP
   * address stored at authentication time.
   *
   * Security is handled according to platform guidelines—hashing passwords on
   * comparison and strictly matching the schema column formats. If the email is
   * not found, the password is incorrect, or the account is marked deleted
   * (deleted_at not null) or inactive (is_active false), the endpoint returns
   * detailed authentication errors linked to schema field constraints.
   *
   * Post-login, the endpoint issues JWT access and refresh tokens containing
   * the customer ID, role, and permissions, drawing from the session management
   * infrastructure described in the schema. Security, audit, and compliance
   * requirements are enforced throughout.
   *
   * @param connection
   * @param body Customer login credentials ('email' and 'password_hash')
   *   referencing the 'shopping_customers' schema.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingCustomer.ILogin,
  ): Promise<IShoppingCustomer.IAuthorized> {
    try {
      return await postAuthCustomerLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT tokens for a customer session using session and
   * 'shopping_customers' schema.
   *
   * This endpoint handles the secure renewal of customer JWT tokens by
   * validating an existing refresh token. It leverages the
   * 'shopping_customer_sessions' and 'shopping_customers' schema to verify
   * token validity, session state, and account activity. Upon validation, new
   * access and refresh JWTs are generated and returned, with the session
   * metadata updated accordingly in the schema. The operation enforces token
   * expiration, revocation, and account validity, referring to is_active and
   * deleted_at fields in the 'shopping_customers' schema for eligibility.
   *
   * If validation fails due to token expiration, revocation, or customer
   * inactivity or deletion, a detailed error message referencing the relevant
   * schema constraint is returned. Security and traceability are prioritized,
   * as audit logs are created for all successful and failed token refreshes
   * according to the relationships laid out in the schema.
   *
   * This endpoint is a critical component of the customer authentication flow,
   * working closely with the login and join operations, and must be used after
   * those endpoints have completed. The operation references all necessary
   * schema fields and relationships for a complete and compliant token rotation
   * infrastructure.
   *
   * @param connection
   * @param body Refresh token and session data, based on schema for session and
   *   'shopping_customers' actor.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingCustomer.IRefresh,
  ): Promise<IShoppingCustomer.IAuthorized> {
    try {
      return await postAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
