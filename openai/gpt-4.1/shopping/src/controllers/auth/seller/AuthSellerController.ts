import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthSellerJoin } from "../../../providers/postAuthSellerJoin";
import { postAuthSellerLogin } from "../../../providers/postAuthSellerLogin";
import { postAuthSellerRefresh } from "../../../providers/postAuthSellerRefresh";

import { IShoppingMallSeller } from "../../../api/structures/IShoppingMallSeller";

@Controller("/auth/seller")
export class AuthSellerController {
  /**
   * Register a new seller account in the shopping_mall_sellers table and issue
   * a JWT token pair.
   *
   * This API registers a new seller account in the platform. It accepts
   * registration details necessary for a seller, as defined in the database
   * schema (shopping_mall_sellers), such as email, password, and other required
   * fields. On success, it creates a seller entity and issues authentication
   * tokens for immediate seller dashboard or API use.
   *
   * All validation logic—such as unique email/username, password policy, and
   * fulfillment of required schema fields—is applied to prevent duplicate
   * accounts and enforce security. The seller registration flow is
   * unauthenticated and permits onboarding for new marketplace merchants.
   *
   * This operation initiates the authentication lifecycle for the actor of kind
   * 'member', forming the basis for future logins and privileged actions.
   * Tokens returned follow the IShoppingMallSeller.IAuthorized DTO documented
   * in the service.
   *
   * Security considerations: rate limiting, anti-automation (CAPTCHA/throttle),
   * and strong password requirements should be enabled. Sensitive data
   * (password) must be securely transmitted and never exposed in logs or error
   * payloads.
   *
   * Any business logic linked to new account creation (e.g., send verification
   * mail, initiate approval process) must reference only actual fields present
   * in the seller table of the schema. This ensures compliance with functional
   * requirements and minimizes onboarding risk.
   *
   * @param connection
   * @param body Seller registration request body
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.ICreate,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a seller and issue a JWT token pair using schema-defined login
   * credentials.
   *
   * This API allows sellers to authenticate using credentials defined in the
   * seller database schema (shopping_mall_sellers), such as email and password.
   * The operation verifies credentials against stored records, handling all
   * error states for incorrect password, missing account, or locked/disabled
   * seller statuses using only those fields present in schema.
   *
   * On success, it issues JWT access and refresh tokens as described by the
   * IShoppingMallSeller.IAuthorized DTO. This is the canonical login entrypoint
   * for all seller account activity.
   *
   * Security controls include throttling on repeated failed login attempts,
   * secure password transmission, and ensuring only required data fields (as
   * per schema and DTO) are accepted in the request body. No extraneous profile
   * or non-auth fields are accepted.
   *
   * Login is a public operation (authorizationActor: null) but all subsequent
   * authenticated business operations require valid tokens, linking this
   * operation to the seller login session lifecycle and session storage if
   * schemas for session or audit logs exist.
   *
   * All referenced credential fields must be verified to exist in the
   * shopping_mall_sellers table, and the login handler may NOT assume standard
   * fields if they are absent from the schema.
   *
   * @param connection
   * @param body Seller login credentials (schema-defined)
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.ILogin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT tokens for seller, issuing new access/refresh token pair if the
   * refresh token is valid.
   *
   * This API accepts a valid refresh token, as defined in the authentication
   * DTO for sellers, and issues a new JWT access/refresh token pair if the
   * refresh token is valid. It implements token rotation and advanced security
   * controls such as issued-at/expiration checks, scope/claim verification, and
   * rotation logics if a refresh session table exists in the schema.
   *
   * On success, it returns the new tokens as IShoppingMallSeller.IAuthorized
   * response. Token renewal is critical for seamless authentication retention
   * by seller actors using long-lived dashboard/API sessions, and the
   * implementation should not go beyond schema support for session/token
   * storage.
   *
   * The operation fails with clear errors on attempt to use expired, reused, or
   * cryptographically invalid tokens. This endpoint does not require an
   * authenticated context (authorizationActor: null) because authentication is
   * performed via cryptographic token validation.
   *
   * Security notes: all refresh token logic uses only schema-supported
   * session/token features, with no reference to features unsupported by the
   * schema. This ensures security policy alignment and DTO compatibility.
   *
   * For sellers, refresh is required for persistent session management and
   * security; it is a mandatory part of the authentication lifecycle.
   *
   * @param connection
   * @param body Refresh token request body for seller
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallSeller.IRefresh,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
