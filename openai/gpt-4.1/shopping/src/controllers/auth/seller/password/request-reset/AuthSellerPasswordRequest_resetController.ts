import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthSellerPasswordRequestReset } from "../../../../../providers/postAuthSellerPasswordRequestReset";

import { IShoppingSeller } from "../../../../../api/structures/IShoppingSeller";

@Controller("/auth/seller/password/request-reset")
export class AuthSellerPasswordRequest_resetController {
  /**
   * Initiate password reset for seller (shopping_password_resets): request
   * reset code via registered email.
   *
   * This operation enables sellers to initiate a password reset process by
   * providing their registered email address. The system generates a new,
   * unique, and secure reset code (token), creates a password reset request
   * record in the 'shopping_password_resets' table, associating it with the
   * seller's account. The reset token is valid for a short period (typically
   * one hour) and must be consumed by the follow-up reset-completion endpoint.
   * No information about the presence or absence of the recipient email is
   * revealed to avoid enumeration attacks. Upon request, the system always
   * responds with a generic success/failure message, regardless of actual email
   * registration. All email delivery of reset codes is managed by platform
   * operations. Expired or used codes are cleaned up as part of periodic
   * background tasks.
   *
   * @param connection
   * @param body Email address for seller password reset request.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async requestPasswordReset(
    @TypedBody()
    body: IShoppingSeller.IResetPasswordRequest,
  ): Promise<IShoppingSeller.IPasswordResetResult> {
    try {
      return await postAuthSellerPasswordRequestReset({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
