import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthSellerPasswordCompleteReset } from "../../../../../providers/postAuthSellerPasswordCompleteReset";

import { IShoppingSeller } from "../../../../../api/structures/IShoppingSeller";

@Controller("/auth/seller/password/complete-reset")
export class AuthSellerPasswordComplete_resetController {
  /**
   * Complete password reset for seller by validating reset code and updating
   * password.
   *
   * This endpoint allows sellers to complete password reset by submitting the
   * reset code received in their email and a new password. The endpoint checks
   * that the code (token) exists in 'shopping_password_resets', is unexpired
   * and not consumed. If valid, it updates the seller's 'password_hash' to the
   * newly provided, securely hashed password. Once completed, the reset request
   * is marked as consumed, and password change audit logs are generated. No
   * authentication is required to call this completion endpoint, but all input
   * data must be valid and not expired. The response is always a generic result
   * and does not reveal details about account existence. This endpoint ties
   * directly to the password reset request endpoint, and together they fulfill
   * the full seller password reset lifecycle.
   *
   * @param connection
   * @param body Password reset completion: email, reset code, and new password
   *   for seller.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async completePasswordReset(
    @TypedBody()
    body: IShoppingSeller.IResetPasswordComplete,
  ): Promise<IShoppingSeller.IPasswordResetResult> {
    try {
      return await postAuthSellerPasswordCompleteReset({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
