/**
 * Search and retrieve paginated SKUs for a product from
 * shopping_mall_product_skus.
 *
 * Retrieve a list of SKUs for a given product with advanced filtering and
 * pagination.
 *
 * This API endpoint provides sellers, admin users, and platform tools with a
 * powerful mechanism to search, filter, and page through the SKUs assigned to a
 * product. Queryable fields include attributes such as color, size, stock
 * levels, and SKU-specific pricing, in accordance with business requirements
 * and field definitions present in the SKU schema.
 *
 * The request supports structured search parameters as defined by the
 * IShoppingMallProductSku.IRequest DTO. Response objects conform to the
 * standard summary container structure (IPageIShoppingMallProductSku.ISummary)
 * for high-performance user interface rendering.
 *
 * Permissions are enforced so that only owners of the product (seller) or
 * authorized admins may query complete SKU lists. Attempted access by
 * unauthorized users is rejected by backend logic. Pagination and sorting
 * behaviors strictly follow platform API conventions.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the parent product whose SKUs are
 *   being listed.
 * @param props.body SKU search criteria and pagination options for filtering
 *   product SKUs.
 * @path /shoppingMall/admin/products/:productId/skus
 * @accessor api.functional.shoppingMall.admin.products.skus.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the parent product whose SKUs are being listed. */
    productId: string & tags.Format<"uuid">;

    /**
     * SKU search criteria and pagination options for filtering product
     * SKUs.
     */
    body: IShoppingMallProductSku.IRequest;
  };
  export type Body = IShoppingMallProductSku.IRequest;
  export type Response = IPageIShoppingMallProductSku.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/products/:productId/skus",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/admin/products/${encodeURIComponent(props.productId ?? "null")}/skus`;
  export const random = (): IPageIShoppingMallProductSku.ISummary =>
    typia.random<IPageIShoppingMallProductSku.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
