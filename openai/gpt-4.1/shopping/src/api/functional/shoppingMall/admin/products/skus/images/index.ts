import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Removes a single product SKU image from the system by soft-deleting the image
 * record. Upon invocation, the system verifies that the image is associated
 * with both the specified product and SKU, and that the requesting actor is
 * authorized (either the product's seller or an administrator).
 *
 * The soft delete is implemented by setting the 'deleted_at' field in the
 * 'shopping_mall_product_images' schema, preserving audit history for later
 * recovery or review. End-users will not see deleted images in product or SKU
 * galleries after this operation. CDN references or digital assets should be
 * invalidated or archived outside this API's direct responsibility.
 *
 * Authorization is strictly enforced: only the owning seller or an admin actor
 * can invoke this operation. All deletion actions are logged for audit and
 * compliance. Related API operations include image upload/creation (POST) and
 * product/SKU updates (PUT).
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product (global
 *   scope).
 * @param props.skuId Unique identifier of the target SKU variant within the
 *   product (scoped to product).
 * @param props.imageId Unique identifier of the image asset to be deleted from
 *   the SKU (scoped to SKU).
 * @path /shoppingMall/admin/products/:productId/skus/:skuId/images/:imageId
 * @accessor api.functional.shoppingMall.admin.products.skus.images.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the target product (global scope). */
    productId: string;

    /**
     * Unique identifier of the target SKU variant within the product
     * (scoped to product).
     */
    skuId: string;

    /**
     * Unique identifier of the image asset to be deleted from the SKU
     * (scoped to SKU).
     */
    imageId: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/admin/products/:productId/skus/:skuId/images/:imageId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/products/${encodeURIComponent(props.productId ?? "null")}/skus/${encodeURIComponent(props.skuId ?? "null")}/images/${encodeURIComponent(props.imageId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.param("skuId")(() => typia.assert(props.skuId));
      assert.param("imageId")(() => typia.assert(props.imageId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
