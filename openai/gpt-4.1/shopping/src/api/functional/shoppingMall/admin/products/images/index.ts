/**
 * Search and list all images for a given product (shopping_mall_product_images)
 * with pagination and filters.
 *
 * Retrieves a filtered, paginated list of all images attached to a given
 * product. The operation provides search/filter functionality to locate images
 * by position, label, and related fields. Results include image summaries
 * suitable for gallery or management views
 * (IShoppingMallProductImage.ISummary), with pagination metadata and filtering
 * for performance in large catalogs.
 *
 * The operation supports search and sort on critical fields like 'position',
 * 'label', 'created_at', enabling users to efficiently manage large image sets.
 * Only images that have not been soft deleted are included in responses.
 * Response data can be used directly for product page displays or
 * administrative asset management workflows.
 *
 * Security enforcement ensures that only users with valid permissions (the
 * product's seller or assigned admins) can browse associated images. Audit logs
 * track all access for compliance and moderation. Related endpoints include
 * image upload (POST) and image delete (DELETE).
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product (global
 *   scope).
 * @param props.body Search options, filtering criteria, and pagination info for
 *   retrieving product images.
 * @path /shoppingMall/admin/products/:productId/images
 * @accessor api.functional.shoppingMall.admin.products.images.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target product (global scope). */
    productId: string;

    /**
     * Search options, filtering criteria, and pagination info for
     * retrieving product images.
     */
    body: IShoppingMallProductImage.IRequest;
  };
  export type Body = IShoppingMallProductImage.IRequest;
  export type Response = IPageIShoppingMallProductImage.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/products/:productId/images",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/admin/products/${encodeURIComponent(props.productId ?? "null")}/images`;
  export const random = (): IPageIShoppingMallProductImage.ISummary =>
    typia.random<IPageIShoppingMallProductImage.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
