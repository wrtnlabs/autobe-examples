/**
 * Retrieve a paginated and filtered list of seller responses associated with a
 * specific product review.
 *
 * This operation enables users to search, filter, and page through all response
 * entries written by sellers in reply to the specified customer review. Results
 * can be filtered by moderation status, withdrawal date, seller identity, and
 * date range of creation or update.
 *
 * Strict access controls are enforced: only authorized actors (primarily admins
 * and moderators) may inspect all seller responses, while sellers and customers
 * may only see responses relevant to their own products or reviews. The system
 * must redact sensitive or non-public data for unauthorized actors.
 *
 * The underlying table, shopping_mall_review_responses, supports full
 * auditability, with all responses traceable to their review, authoring seller,
 * and session. This operation is fundamental for moderation panels, seller
 * dashboards, and customer notification flows.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the reviewed customer review
 *   (shopping_mall_reviews.id) for which to fetch associated seller responses.
 * @param props.body Filter, sorting, and pagination options for seller
 *   responses related to the specified review.
 * @path /shoppingMall/admin/reviews/:reviewId/responses
 * @accessor api.functional.shoppingMall.admin.reviews.responses.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
