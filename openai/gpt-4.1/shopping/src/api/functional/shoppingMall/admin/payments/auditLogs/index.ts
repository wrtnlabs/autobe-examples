/**
 * List and search audit log records for a payment from
 * shopping_mall_payment_audit_logs.
 *
 * Retrieve a filtered, paginated list of all audit log records associated with
 * a specific payment.
 *
 * This operation enables authorized admin users to search within all audit log
 * entries related to a given payment. Audit logs provide immutable records of
 * every relevant action (system or manual), including payment creation,
 * updates, callbacks, reversals, refunds, and more, with each record
 * timestamped for traceability. Results are filterable and sorted, supporting
 * advanced query structures via the request body: action type, actor ID, time
 * window, etc.
 *
 * Strict access control ensures only admins or audit investigators can use this
 * endpoint, preventing any exposure of payment audit data to unauthorized
 * actors. Pagination is required for large record sets. Underlying data is
 * stored in shopping_mall_payment_audit_logs model with references to the
 * payment specified by paymentId.
 *
 * @param props.connection
 * @param props.paymentId Unique identifier (UUID) of the payment whose audit
 *   logs are being queried.
 * @param props.body Filter, pagination, and search parameters for payment audit
 *   logs related to the specified payment.
 * @path /shoppingMall/admin/payments/:paymentId/auditLogs
 * @accessor api.functional.shoppingMall.admin.payments.auditLogs.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
