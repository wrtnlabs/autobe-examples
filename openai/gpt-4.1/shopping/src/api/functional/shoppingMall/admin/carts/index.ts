import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCart } from "../../../../structures/IShoppingMallCart";
import { IPageIShoppingMallCart } from "../../../../structures/IPageIShoppingMallCart";

/**
 * Retrieve a filtered and paginated list of shopping cart records for all
 * customers across the platform.
 *
 * This operation allows platform admins to audit and analyze the state of all
 * customer shopping carts. The results can be filtered or sorted by customer,
 * creation date, recent update, or linked customer status, facilitating both
 * system maintenance and operational analytics.
 *
 * The operation covers validation for unique cart association per customer (as
 * enforced by the Prisma schema) and supports review of abandoned, active, or
 * recently checked-out carts. Data returned is suitable for administrative
 * dashboards, platform health checks, and compliance audits. Security
 * restrictions limit access to administrative actors only, ensuring no
 * unauthorized or customer-level user can access cart data for other accounts.
 *
 * @param props.connection
 * @param props.body Search, filter, and pagination parameters for
 *   administrative shopping cart queries.
 * @path /shoppingMall/admin/carts
 * @accessor api.functional.shoppingMall.admin.carts.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search, filter, and pagination parameters for administrative shopping
     * cart queries.
     */
    body: IShoppingMallCart.IRequest;
  };
  export type Body = IShoppingMallCart.IRequest;
  export type Response = IPageIShoppingMallCart.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/carts",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/carts";
  export const random = (): IPageIShoppingMallCart.ISummary =>
    typia.random<IPageIShoppingMallCart.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

