/**
 * Perform advanced search and retrieval of product reviews, supporting
 * filtering by various attributes such as product, SKU, customer, moderation
 * state, and keyword matches on title or body fields.
 *
 * The operation provides pagination, sorting, and multi-criteria filtering for
 * platform admins, allowing moderation, analytics, and business process
 * support. Users may filter by product or SKU to review feedback for specific
 * catalog items, analyze trends in ratings, or identify potential abuse cases.
 * Authorization checks enforce access: regular users can search their own
 * submitted reviews, while admins may search any review. Search logic relies on
 * full-text GIN indexes on title and body for efficient keyword queries, and
 * supports state, date, or entity-related filters as appropriate. The
 * underlying shopping_mall_reviews schema details all relevant fields,
 * relationships, and business rules.
 *
 * @param props.connection
 * @param props.body Advanced search query for filtering, sorting, and
 *   paginating reviews based on product, SKU, customer, moderation state,
 *   keywords, and time ranges.
 * @path /shoppingMall/admin/reviews
 * @accessor api.functional.shoppingMall.admin.reviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Advanced search query for filtering, sorting, and paginating reviews
     * based on product, SKU, customer, moderation state, keywords, and time
     * ranges.
     */
    body: IShoppingMallReview.IRequest;
  };
  export type Body = IShoppingMallReview.IRequest;
  export type Response = IPageIShoppingMallReview.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/reviews",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/reviews";
  export const random = (): IPageIShoppingMallReview.ISummary =>
    typia.random<IPageIShoppingMallReview.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
