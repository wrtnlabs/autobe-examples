import { IShoppingMallProductAttributeValue } from "../../../../structures/IShoppingMallProductAttributeValue";

/**
 * Retrieve details for a specific attribute value assigned to a product SKU
 * within the catalog.
 *
 * This operation allows users to view the display label, attribute type, and
 * audit fields for a given attribute value of a SKU, supporting variant
 * selection and catalog enrichment. Only attribute values that exist for the
 * target SKU (as defined by the unique constraint on (sku_id, attribute_id))
 * can be fetched through this endpoint. Users can leverage this endpoint to
 * build product variant selectors or provide detailed SKU information during
 * the shopping and management flows.
 *
 * Security-wise, access to SKU attribute values is generally public, but
 * sensitive audit or internal metadata may be filtered or restricted depending
 * on the actor's rights.
 *
 * Related endpoints may include listing all attribute values for a given SKU or
 * managing attributes via seller/admin tools.
 *
 * @param props.connection
 * @param props.skuId Unique identifier of the parent SKU (scoped for variant
 *   attribute values).
 * @param props.attributeValueId Unique identifier for the attribute value
 *   mapping within the given SKU.
 * @path /shoppingMall/skus/:skuId/attributeValues/:attributeValueId
 * @accessor api.functional.shoppingMall.skus.attributeValues.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the parent SKU (scoped for variant attribute
     * values).
     */
    skuId: string & tags.Format<"uuid">;

    /**
     * Unique identifier for the attribute value mapping within the given
     * SKU.
     */
    attributeValueId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallProductAttributeValue;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/skus/:skuId/attributeValues/:attributeValueId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/skus/${encodeURIComponent(props.skuId ?? "null")}/attributeValues/${encodeURIComponent(props.attributeValueId ?? "null")}`;
  export const random = (): IShoppingMallProductAttributeValue =>
    typia.random<IShoppingMallProductAttributeValue>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("skuId")(() => typia.assert(props.skuId));
      assert.param("attributeValueId")(() =>
        typia.assert(props.attributeValueId),
      );
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
