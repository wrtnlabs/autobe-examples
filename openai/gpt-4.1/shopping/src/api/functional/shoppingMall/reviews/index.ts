/**
 * Retrieve the detail for a single shopping_mall_reviews review record by ID.
 *
 * Retrieve the full details for a specific product review in the system. This
 * endpoint allows clients to fetch all available information about a review by
 * providing the unique identifier (UUID) for that review.
 *
 * The response includes the text content (title, body), status flags (is_draft,
 * moderation_status, withdrawn_at), relationships to the authoring customer and
 * session, the related product/SKU, order, order item, product rating, and all
 * relevant timestamps (created_at, updated_at, deleted_at if soft-deleted).
 * This ensures full contextual traceability for moderation and audit.
 *
 * Use this operation to display review details in customer-facing pages,
 * moderation queues, seller dashboards, or administrative tools. Security and
 * visibility rules should ensure only authorized users view personally
 * identifiable information or system-sensitive moderation content. The
 * operation references the shopping_mall_reviews Prisma schema to guarantee
 * data completeness and correct linkage to related entities.
 *
 * Error handling covers missing or non-existent records, permission denials,
 * and soft-deleted/withdrawn reviews, with responses that comply with
 * established error and data presentation patterns.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier (UUID) of the target review to
 *   retrieve.
 * @path /shoppingMall/reviews/:reviewId
 * @accessor api.functional.shoppingMall.reviews.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier (UUID) of the target review to retrieve. */
    reviewId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallReview;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/reviews/:reviewId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/reviews/${encodeURIComponent(props.reviewId ?? "null")}`;
  export const random = (): IShoppingMallReview =>
    typia.random<IShoppingMallReview>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

