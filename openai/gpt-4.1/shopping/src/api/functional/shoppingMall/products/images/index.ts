import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductImage } from "../../../../structures/IShoppingMallProductImage";

/**
 * Retrieve a specific image for a shopping mall product
 * (shopping_mall_product_images).
 *
 * Retrieve a single image asset associated with a product for use in product
 * galleries or detail pages.
 *
 * This operation is designed to fetch the complete metadata for a specific
 * product image, identified by its unique ID within the scope of a given
 * product. The response includes the CDN URI, alt text, display order position,
 * and any associated management label, allowing clients to build rich UI
 * representations of product galleries and detail pages.
 *
 * The API enforces filtering so that only images which are active (not
 * soft-deleted, i.e., deleted_at is null) are returned. The product and image
 * linkage is validated to ensure proper ownership and data integrity according
 * to the product-image relationship as described in the
 * shopping_mall_product_images Prisma schema. This ensures only valid, active
 * images are exposed.
 *
 * Security-wise, the endpoint is publicly accessible, as product images are
 * intended for display on the customer-facing frontend. Soft-deleted or
 * orphaned images are automatically excluded, and no sensitive data is
 * disclosed. Related endpoints include creating, updating, and deleting product
 * images for gallery management.
 *
 * @param props.connection
 * @param props.productId Unique identifier (UUID) of the product to which the
 *   image belongs.
 * @param props.imageId Unique identifier (UUID) of the image asset to retrieve,
 *   associated with the product.
 * @path /shoppingMall/products/:productId/images/:imageId
 * @accessor api.functional.shoppingMall.products.images.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier (UUID) of the product to which the image belongs. */
    productId: string & tags.Format<"uuid">;

    /**
     * Unique identifier (UUID) of the image asset to retrieve, associated
     * with the product.
     */
    imageId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallProductImage;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/products/:productId/images/:imageId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/products/${encodeURIComponent(props.productId ?? "null")}/images/${encodeURIComponent(props.imageId ?? "null")}`;
  export const random = (): IShoppingMallProductImage =>
    typia.random<IShoppingMallProductImage>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.param("imageId")(() => typia.assert(props.imageId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
