/**
 * Retrieve a filtered and paginated list of images linked to a specific SKU
 * variant of a product. This endpoint allows clients to search for images by
 * specifying image attributes—such as display position, alt text content, or
 * label—and supports advanced filtering, sorting, and pagination options
 * tailored for asset galleries in product detail views.
 *
 * For each image, details such as CDN URI, alt text, display position, and
 * internal label are included along with status information. Only images that
 * have not been soft deleted (i.e., deleted_at is null) will be returned in
 * results. Business logic ensures that either the SKU-scoped or product-scoped
 * images are queried according to the given identifiers, but not both at the
 * same time, maintaining category integrity.
 *
 * Security measures restrict access to image assets strictly based on SKU and
 * product binding. Only images valid for the given SKU and product are
 * included, with further constraints as needed for unpublished or hidden
 * products. This operation is useful for rendering SKU image carousels,
 * supporting accessibility via alt text, and moderation or auditing functions.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target catalog product
 *   (global scope).
 * @param props.skuId Unique identifier of the target SKU within the specified
 *   product (scoped to product).
 * @param props.body Filter and search criteria for querying images associated
 *   with a product SKU, including pagination and sorting parameters.
 * @path /shoppingMall/products/:productId/skus/:skuId/images
 * @accessor api.functional.shoppingMall.products.skus.images.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
