/**
 * Retrieve detailed information for a single order item associated with a
 * specific shopping mall order.
 *
 * This operation allows a customer, seller, or administrator to obtain a
 * comprehensive breakdown of an individual item in an order. Returned
 * information includes product/SKU reference, purchased quantity, unit price,
 * subtotal, currency, fulfillment status (delivered/not), refund status, and
 * created/updated/deleted timestamps—all as defined in the
 * shopping_mall_order_items schema.
 *
 * The business order number (orderNumber) is a human- and system-visible,
 * globally unique identifier for each order, supporting seamless integration
 * with customer service, logistics, and reporting systems. The order item
 * identifier (orderItemId) is a UUID that uniquely marks the line item within
 * the broader order context. Together, they eliminate ambiguity and provide
 * full traceability.
 *
 * Strict permission checks must be enforced: Only actors directly engaged with
 * the order (order owner/customer, associated seller, or privileged admin) are
 * authorized. If the item does not exist or access is not permitted,
 * appropriate error responses (404 Not Found or 403 Forbidden) shall be
 * returned. Detailed logging and compliance policies should be in place for
 * audit purposes.
 *
 * @param props.connection
 * @param props.orderNumber Platform-unique business order number of the parent
 *   order, identifying the scope of lookup (global scope).
 * @param props.orderItemId UUID of the order item to retrieve within the
 *   specified order (scoped to orderNumber).
 * @path /shoppingMall/seller/orders/:orderNumber/items/:orderItemId
 * @accessor api.functional.shoppingMall.seller.orders.items.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
