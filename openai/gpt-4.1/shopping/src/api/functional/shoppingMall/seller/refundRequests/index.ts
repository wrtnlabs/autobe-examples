import { IShoppingMallRefundRequest } from "../../../../structures/IShoppingMallRefundRequest";

/**
 * Retrieve full detail of a specific refund request
 * (shopping_mall_refund_requests).
 *
 * Retrieve the full detail for a single refund request in the shopping mall.
 * This endpoint provides all information filed by the customer for this
 * request, including the refund reason, status (such as pending, approved,
 * rejected, processing, refunded), the requested and (if decided) approved
 * refund amounts, and timestamps indicating the creation and latest update to
 * the request.
 *
 * The response also includes references to the associated order, the customer
 * who initiated the refund, the seller involved, and any admin who has acted on
 * or is assigned to the request. Timestamps for creation and updates are
 * included for precise workflow tracking and compliance. The refund request's
 * workflow state, including any logical soft deletion ('deleted_at'), is
 * honored; if the record is logically deleted, it will be omitted or return a
 * suitable error response.
 *
 * This operation is critical for customer support, dispute resolution, and
 * refund workflow management by platform actors. Only authorized users (admin,
 * customer, or seller associated with the refund) should be allowed to access
 * the details. Related operations: create refund request (POST
 * /refundRequests), list/search refund requests (PATCH /refundRequests).
 *
 * @param props.connection
 * @param props.refundRequestId Unique identifier of the refund request to
 *   retrieve (UUID primary key).
 * @path /shoppingMall/seller/refundRequests/:refundRequestId
 * @accessor api.functional.shoppingMall.seller.refundRequests.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the refund request to retrieve (UUID primary
     * key).
     */
    refundRequestId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallRefundRequest;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/seller/refundRequests/:refundRequestId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/seller/refundRequests/${encodeURIComponent(props.refundRequestId ?? "null")}`;
  export const random = (): IShoppingMallRefundRequest =>
    typia.random<IShoppingMallRefundRequest>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("refundRequestId")(() =>
        typia.assert(props.refundRequestId),
      );
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
