/**
 * Retrieve a paginated, filterable list of session records belonging to a
 * specific seller account.
 *
 * This endpoint enables sellers or administrators to view recent and historical
 * login session activity for the specified seller, useful for auditing access,
 * device and browser usage patterns, and security reviews. Each session
 * includes creation time, potential expiration, IP address, referrer
 * information, and links to the seller it belongs to.
 *
 * Security is critical: Only the seller themselves or administrative actor(s)
 * may list sessions for an account, as these may contain sensitive device, IP,
 * and login metadata. Search parameters allow for filtering by login time
 * range, expiration state, or IP/network. The endpoint leverages the subsidiary
 * relationship of sessions to sellers as defined in the Prisma schema, and
 * always expects a valid sellerId as a required path parameter.
 *
 * @param props.connection
 * @param props.sellerId Unique identifier of the target seller. This must be
 *   the primary key UUID field from shopping_mall_sellers (global scope).
 * @param props.body Filter, search, and pagination parameters for seller
 *   session records, supporting time range and IP filtering.
 * @path /shoppingMall/seller/sellers/:sellerId/sessions
 * @accessor api.functional.shoppingMall.seller.sellers.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
