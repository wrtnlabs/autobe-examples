/**
 * Search and retrieve a paginated list of shopping mall order shipments for a
 * given order (shopping_mall_order_shipments).
 *
 * Return a paginated, filterable list of all shipment (fulfillment batch)
 * entities associated with a single shopping mall order. Each shipment record
 * tracks detailed shipping, carrier, and status information relevant to one or
 * more items in the given order.
 *
 * The list supports filtering by shipment status, carrier, creation dates, and
 * other shipment attributes as defined in the request body DTO. Pagination
 * parameters allow clients to fetch results in configurable chunk sizes for
 * efficient UI rendering.
 *
 * Security is enforced by restricting access to only those with valid
 * authorization for the parent order. Business logic ensures only active
 * (non-soft deleted) shipments are returned, referencing the
 * shopping_mall_order_shipments schema. This API enables both customer and
 * seller portals to view full delivery status for a given order, but does not
 * expose system-level shipments unrelated to this order.
 *
 * @param props.connection
 * @param props.orderNumber Platform-unique business order number of the parent
 *   order (global scope). Example: ORD202500001.
 * @param props.body Filter, sort, and pagination settings for shipment batch
 *   search within the specified order.
 * @path /shoppingMall/customer/orders/:orderNumber/shipments
 * @accessor api.functional.shoppingMall.customer.orders.shipments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Platform-unique business order number of the parent order (global
     * scope). Example: ORD202500001.
     */
    orderNumber: string;

    /**
     * Filter, sort, and pagination settings for shipment batch search
     * within the specified order.
     */
    body: IShoppingMallOrderShipment.IRequest;
  };
  export type Body = IShoppingMallOrderShipment.IRequest;
  export type Response = IPageIShoppingMallOrderShipment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/customer/orders/:orderNumber/shipments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/customer/orders/${encodeURIComponent(props.orderNumber ?? "null")}/shipments`;
  export const random = (): IPageIShoppingMallOrderShipment.ISummary =>
    typia.random<IPageIShoppingMallOrderShipment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderNumber")(() => typia.assert(props.orderNumber));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

