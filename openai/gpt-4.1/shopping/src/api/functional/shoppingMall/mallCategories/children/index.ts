import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCategory } from "../../../../structures/IShoppingMallCategory";
import { IPageIShoppingMallCategory } from "../../../../structures/IPageIShoppingMallCategory";

/**
 * Retrieve a filtered and paginated list of direct child categories under a
 * specific parent category, identified by its unique name.
 *
 * This operation supports use cases such as building category navigation trees
 * for the shop UI, assisting admins in managing hierarchical category
 * structures, and enabling merchandising workflows that require knowledge of
 * category organization.
 *
 * The request must include filtering and pagination criteria as defined by
 * IShoppingMallCategory.IRequest. Only categories with parent_id mapped to the
 * specified category 'name' will be included. The response is a paginated list
 * of category summaries, supporting scalable UI rendering and efficient
 * browsing for large category trees.
 *
 * Note: Only active or admin-visible categories are included unless otherwise
 * specified in the request. Results are sorted by 'sort_order' by default.
 * Security and visibility are enforced based on actor role and API
 * configuration.
 *
 * @param props.connection
 * @param props.name Unique category name of the parent category (global scope).
 * @param props.body Search, filter, and pagination parameters for listing
 *   category children.
 * @path /shoppingMall/mallCategories/:name/children
 * @accessor api.functional.shoppingMall.mallCategories.children.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique category name of the parent category (global scope). */
    name: string;

    /**
     * Search, filter, and pagination parameters for listing category
     * children.
     */
    body: IShoppingMallCategory.IRequest;
  };
  export type Body = IShoppingMallCategory.IRequest;
  export type Response = IPageIShoppingMallCategory.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/mallCategories/:name/children",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/mallCategories/${encodeURIComponent(props.name ?? "null")}/children`;
  export const random = (): IPageIShoppingMallCategory.ISummary =>
    typia.random<IPageIShoppingMallCategory.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("name")(() => typia.assert(props.name));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
