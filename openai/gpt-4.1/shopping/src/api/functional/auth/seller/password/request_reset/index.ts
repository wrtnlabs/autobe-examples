import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingSeller } from "../../../../../structures/IShoppingSeller";

/**
 * Initiate password reset for seller (shopping_password_resets): request reset
 * code via registered email.
 *
 * This operation enables sellers to initiate a password reset process by
 * providing their registered email address. The system generates a new, unique,
 * and secure reset code (token), creates a password reset request record in the
 * 'shopping_password_resets' table, associating it with the seller's account.
 * The reset token is valid for a short period (typically one hour) and must be
 * consumed by the follow-up reset-completion endpoint. No information about the
 * presence or absence of the recipient email is revealed to avoid enumeration
 * attacks. Upon request, the system always responds with a generic
 * success/failure message, regardless of actual email registration. All email
 * delivery of reset codes is managed by platform operations. Expired or used
 * codes are cleaned up as part of periodic background tasks.
 *
 * @param props.connection
 * @param props.body Email address for seller password reset request.
 * @path /auth/seller/password/request-reset
 * @accessor api.functional.auth.seller.password.request_reset.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<requestPasswordReset.Response> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestPasswordReset {
  export type Props = {
    /** Email address for seller password reset request. */
    body: IShoppingSeller.IResetPasswordRequest;
  };
  export type Body = IShoppingSeller.IResetPasswordRequest;
  export type Response = IShoppingSeller.IPasswordResetResult;

  export const METADATA = {
    method: "POST",
    path: "/auth/seller/password/request-reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/seller/password/request-reset";
  export const random = (): IShoppingSeller.IPasswordResetResult =>
    typia.random<IShoppingSeller.IPasswordResetResult>();
  export const simulate = (
    connection: IConnection,
    props: requestPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
