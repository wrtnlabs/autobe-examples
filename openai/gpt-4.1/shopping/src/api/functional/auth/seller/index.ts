/**
 * Register a new seller account (shopping_sellers) and issue initial JWT
 * tokens.
 *
 * This operation registers a new seller in the 'shopping_sellers' table,
 * requiring a unique business email, password (hashed), display name, and
 * contact phone. Additional business verification fields such as business
 * registration and legal entity information are completed after account
 * creation, in separate flows.
 *
 * The operation enforces that provided emails are unique and not already
 * registered, in accordance with 'shopping_sellers.email' being a unique
 * indexed column. A password is provided as a plain string during registration
 * and securely hashed before storage in the 'password_hash' field. The initial
 * 'status' for the created seller account is set to 'pending', which triggers
 * downstream compliance and admin review workflows, as mandated in onboarding
 * requirements.
 *
 * Security is a primary concern: passwords are never stored in plaintext, and
 * registration errors do not reveal whether a given email is already in use.
 * Upon successful creation, the seller is authenticated automatically, with JWT
 * access and refresh tokens issued and returned in the authorized DTO
 * structure.
 *
 * Seller registration is limited to this endpoint; admin or customer accounts
 * must use their respective endpoints. This endpoint does not permit bypassing
 * post-onboarding verification flows – sellers must be approved by an admin
 * before listing products or receiving payments. Error handling follows strict
 * business patterns, returning actionable error codes for duplicate emails,
 * invalid formats, or password strength violations.
 *
 * This operation is related to the seller authentication (login) endpoint, the
 * token refresh endpoint, and downstream business onboarding API operations
 * (e.g., business info submission, document upload, compliance checks).
 *
 * @param props.connection
 * @param props.body New seller registration information, including email,
 *   plaintext password, display name, and contact phone.
 * @setHeader token.access Authorization
 *
 * @path /auth/seller/join
 * @accessor api.functional.auth.seller.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
