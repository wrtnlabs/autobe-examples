/**
 * This API registers a new seller account in the platform. It accepts
 * registration details necessary for a seller, as defined in the database
 * schema (shopping_mall_sellers), such as email, password, and other required
 * fields. On success, it creates a seller entity and issues authentication
 * tokens for immediate seller dashboard or API use.
 *
 * All validation logic—such as unique email/username, password policy, and
 * fulfillment of required schema fields—is applied to prevent duplicate
 * accounts and enforce security. The seller registration flow is
 * unauthenticated and permits onboarding for new marketplace merchants.
 *
 * This operation initiates the authentication lifecycle for the actor of kind
 * 'member', forming the basis for future logins and privileged actions. Tokens
 * returned follow the IShoppingMallSeller.IAuthorized DTO documented in the
 * service.
 *
 * Security considerations: rate limiting, anti-automation (CAPTCHA/throttle),
 * and strong password requirements should be enabled. Sensitive data (password)
 * must be securely transmitted and never exposed in logs or error payloads.
 *
 * Any business logic linked to new account creation (e.g., send verification
 * mail, initiate approval process) must reference only actual fields present in
 * the seller table of the schema. This ensures compliance with functional
 * requirements and minimizes onboarding risk.
 *
 * @param props.connection
 * @param props.body Seller registration request body
 * @setHeader token.access Authorization
 *
 * @path /auth/seller/join
 * @accessor api.functional.auth.seller.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
