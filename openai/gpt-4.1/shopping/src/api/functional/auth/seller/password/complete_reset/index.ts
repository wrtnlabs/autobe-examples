import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingSeller } from "../../../../../structures/IShoppingSeller";

/**
 * Complete password reset for seller by validating reset code and updating
 * password.
 *
 * This endpoint allows sellers to complete password reset by submitting the
 * reset code received in their email and a new password. The endpoint checks
 * that the code (token) exists in 'shopping_password_resets', is unexpired and
 * not consumed. If valid, it updates the seller's 'password_hash' to the newly
 * provided, securely hashed password. Once completed, the reset request is
 * marked as consumed, and password change audit logs are generated. No
 * authentication is required to call this completion endpoint, but all input
 * data must be valid and not expired. The response is always a generic result
 * and does not reveal details about account existence. This endpoint ties
 * directly to the password reset request endpoint, and together they fulfill
 * the full seller password reset lifecycle.
 *
 * @param props.connection
 * @param props.body Password reset completion: email, reset code, and new
 *   password for seller.
 * @path /auth/seller/password/complete-reset
 * @accessor api.functional.auth.seller.password.complete_reset.completePasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function completePasswordReset(
  connection: IConnection,
  props: completePasswordReset.Props,
): Promise<completePasswordReset.Response> {
  return true === connection.simulate
    ? completePasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...completePasswordReset.METADATA,
          path: completePasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace completePasswordReset {
  export type Props = {
    /**
     * Password reset completion: email, reset code, and new password for
     * seller.
     */
    body: IShoppingSeller.IResetPasswordComplete;
  };
  export type Body = IShoppingSeller.IResetPasswordComplete;
  export type Response = IShoppingSeller.IPasswordResetResult;

  export const METADATA = {
    method: "POST",
    path: "/auth/seller/password/complete-reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/seller/password/complete-reset";
  export const random = (): IShoppingSeller.IPasswordResetResult =>
    typia.random<IShoppingSeller.IPasswordResetResult>();
  export const simulate = (
    connection: IConnection,
    props: completePasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: completePasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
