/**
 * This API operation allows registration of new admin accounts into the system
 * by collecting required credentials such as username, email, and password, as
 * specified in the 'shopping_mall_admins' Prisma schema. All input fields are
 * validated strictly according to the schema's constraints (such as unique
 * email, password policy, and required primitive fields). The admin account is
 * created and the administrator receives both an access token and a refresh
 * token in the response.
 *
 * Implementation leverages the available schema fields to bind each input field
 * directly to the database, ensuring that only present fields are requested and
 * stored. Only the fields available in the 'shopping_mall_admins' schema can be
 * used for registration (with additional features omitted if they are not
 * defined in the schema).
 *
 * This operation is tied to admin onboarding business logic, with registration
 * being reserved for authorized actors and limited in frequency to mitigate
 * abuse. The authentication tokens returned enable the admin to log in and
 * maintain authenticated sessions in subsequent requests.
 *
 * Security consideration: Registration abuse is prevented by business logic
 * limitations and auditing. All write operations are transactional, and
 * rollback is triggered for any unique constraint or business logic violations
 * based on schema specification.
 *
 * Related: login (credential authentication via /auth/admin/login) and refresh
 * (JWT/authorization token renewal via /auth/admin/refresh).
 *
 * @param props.connection
 * @param props.body Payload for admin registration (join) operation. Maps all
 *   registrable fields from the shopping_mall_admins schema, such as email,
 *   password, username, and any other required primitive fields.
 * @setHeader token.access Authorization
 *
 * @path /auth/admin/join
 * @accessor api.functional.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
