import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingCustomer } from "../../../../../structures/IShoppingCustomer";

/**
 * Finalize customer password reset by validating the token and updating
 * 'shopping_customers' schema.
 *
 * This endpoint finalizes customer password reset by verifying the secure reset
 * token against the 'shopping_password_resets' schema fields ('reset_code',
 * 'expires_at', 'consumed_at') and, if valid, updating the related customer's
 * password_hash in the 'shopping_customers' schema. After updating the
 * password, the token row is marked as consumed, with full auditing enforced as
 * described in the schema's relationships. All error responses reference the
 * exact schema validation that failed.
 *
 * Business logic enforces password strength and secure handling, with email
 * notification and session invalidation handled separately using schema
 * relationships. This operation is always linked to a prior call to the
 * password reset token initiation, and closely aligns with login and token
 * refresh endpoints for full customer account recovery. Only explicit, existing
 * schema fields are handled at all steps to ensure type and business logic
 * correctness.
 *
 * @param props.connection
 * @param props.body Password reset token and new password, matching schema for
 *   resets and customer updates.
 * @path /auth/customer/password/reset
 * @accessor api.functional.auth.customer.password.reset.resetPassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resetPassword(
  connection: IConnection,
  props: resetPassword.Props,
): Promise<resetPassword.Response> {
  return true === connection.simulate
    ? resetPassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resetPassword.METADATA,
          path: resetPassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resetPassword {
  export type Props = {
    /**
     * Password reset token and new password, matching schema for resets and
     * customer updates.
     */
    body: IShoppingCustomer.ICompletePasswordReset;
  };
  export type Body = IShoppingCustomer.ICompletePasswordReset;
  export type Response = IShoppingCustomer.IPasswordResetCompleted;

  export const METADATA = {
    method: "POST",
    path: "/auth/customer/password/reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/customer/password/reset";
  export const random = (): IShoppingCustomer.IPasswordResetCompleted =>
    typia.random<IShoppingCustomer.IPasswordResetCompleted>();
  export const simulate = (
    connection: IConnection,
    props: resetPassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resetPassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
