import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingCustomer } from "../../../../../structures/IShoppingCustomer";

/**
 * Initiate password reset for customer using 'shopping_customers' and
 * 'shopping_password_resets' schema.
 *
 * This endpoint lets a customer initiate a password reset by providing their
 * email address, which is checked for existence and validity in the
 * 'shopping_customers' schema. If an active account is found, a secure,
 * time-limited reset token is generated and persisted in the
 * 'shopping_password_resets' schema using 'request_email', 'reset_code', and
 * 'expires_at' fields. The response does not disclose whether the email exists
 * to prevent enumeration.
 *
 * The operation only references schema fields and never exposes any customer
 * data if the supplied email is not matched, to protect user privacy. Rate
 * limiting, email delivery of reset links, and auditing are enforced per
 * business and platform security policies using the relationships provided in
 * the schema. The operation is closely related to password-update completion
 * endpoints and is the entrypoint for secure recovery workflows for the
 * customer actor.
 *
 * @param props.connection
 * @param props.body Customer email for initiating password reset, referencing
 *   the schema.
 * @path /auth/customer/password/reset-request
 * @accessor api.functional.auth.customer.password.reset_request.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<requestPasswordReset.Response> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestPasswordReset {
  export type Props = {
    /** Customer email for initiating password reset, referencing the schema. */
    body: IShoppingCustomer.IRequestPasswordReset;
  };
  export type Body = IShoppingCustomer.IRequestPasswordReset;
  export type Response = IShoppingCustomer.IPasswordResetInitiated;

  export const METADATA = {
    method: "POST",
    path: "/auth/customer/password/reset-request",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/customer/password/reset-request";
  export const random = (): IShoppingCustomer.IPasswordResetInitiated =>
    typia.random<IShoppingCustomer.IPasswordResetInitiated>();
  export const simulate = (
    connection: IConnection,
    props: requestPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
