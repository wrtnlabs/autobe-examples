import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingCategory } from "../../../structures/IShoppingCategory";

/**
 * Retrieve details of a category node in a specific category tree by its codes.
 *
 * This API operation provides full detail for a category node by resolving both
 * the category tree code and category code to the corresponding database
 * entities in shopping_category_trees and shopping_categories. The
 * categoryTreeCode parameter identifies the taxonomy root (e.g., 'main',
 * 'brand'), while the categoryCode identifies a unique node within that tree
 * (guaranteed unique per tree by the composite unique constraint in the
 * schema).
 *
 * Returned fields may include category name, code, hierarchy info, parent
 * relationship, display order, and optional description, matching those from
 * the shopping_categories schema. The operation is suitable for constructing
 * frontend navigation, displaying information about specific filters, or
 * preparing edit interfaces for admins.
 *
 * Security considerations: This operation is generally public, as category
 * trees and nodes need to be readable by all users for catalog display and
 * browsing; thus, the authorizationActors array is empty, indicating no
 * authentication is required for this read-only query. Error handling includes
 * responding with a clear not-found error if the category tree or node is
 * missing or has been soft-deleted.
 *
 * @param props.connection
 * @param props.categoryTreeCode Code uniquely identifying the category tree
 *   (taxonomy) (global scope). Only valid tree codes as defined in
 *   shopping_category_trees may be used.
 * @param props.categoryCode Code uniquely identifying the category node within
 *   the specified category tree (scoped to category tree). Composite unique
 *   constraint in shopping_categories ensures uniqueness per tree.
 * @path /shopping/categories/:categoryTreeCode/:categoryCode
 * @accessor api.functional.shopping.categories.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Code uniquely identifying the category tree (taxonomy) (global
     * scope). Only valid tree codes as defined in shopping_category_trees
     * may be used.
     */
    categoryTreeCode: string;

    /**
     * Code uniquely identifying the category node within the specified
     * category tree (scoped to category tree). Composite unique constraint
     * in shopping_categories ensures uniqueness per tree.
     */
    categoryCode: string;
  };
  export type Response = IShoppingCategory;

  export const METADATA = {
    method: "GET",
    path: "/shopping/categories/:categoryTreeCode/:categoryCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shopping/categories/${encodeURIComponent(props.categoryTreeCode ?? "null")}/${encodeURIComponent(props.categoryCode ?? "null")}`;
  export const random = (): IShoppingCategory =>
    typia.random<IShoppingCategory>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("categoryTreeCode")(() =>
        typia.assert(props.categoryTreeCode),
      );
      assert.param("categoryCode")(() => typia.assert(props.categoryCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
