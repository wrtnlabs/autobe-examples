import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingProductTag } from "../../../structures/IShoppingProductTag";

/**
 * Retrieve a product tag by its unique business tag code from
 * shopping_product_tags.
 *
 * This API operation allows clients to fetch the full metadata of a single
 * product tag identified by the unique tagCode. Product tags empower catalog
 * search and display, with each tag providing a display value, code, and
 * descriptive purpose for shoppers and filter builders.
 *
 * Access to this information is essential for scenarios such as tag-driven
 * catalog pages or when building tag-based search facets in product filtering
 * UIs. The endpoint ensures that only tags registered in the
 * shopping_product_tags schema are returned, and each response includes all
 * fields defined in the database table, supporting reliable search and display
 * logic.
 *
 * Authorization is open for all authenticated users, as reading tags does not
 * compromise business security or sensitive data. Related write operations,
 * such as creating and updating tags, require admin or seller permissions
 * through different endpoints.
 *
 * @param props.connection
 * @param props.tagCode Business code of the product tag to retrieve (global
 *   scope)
 * @path /shopping/productTags/:tagCode
 * @accessor api.functional.shopping.productTags.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Business code of the product tag to retrieve (global scope) */
    tagCode: string;
  };
  export type Response = IShoppingProductTag;

  export const METADATA = {
    method: "GET",
    path: "/shopping/productTags/:tagCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shopping/productTags/${encodeURIComponent(props.tagCode ?? "null")}`;
  export const random = (): IShoppingProductTag =>
    typia.random<IShoppingProductTag>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("tagCode")(() => typia.assert(props.tagCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
