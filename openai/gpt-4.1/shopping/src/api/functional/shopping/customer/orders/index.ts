/**
 * Create a new order in the system when a customer performs checkout
 * (shopping_orders).
 *
 * This endpoint processes a completed customer checkout and translates it into
 * a new order in the shopping_orders table. The operation accepts a
 * well-structured order creation payload (IShoppingOrder.ICreate) containing
 * the customer's ID, delivery/billing addresses (either selected or entered
 * anew), product SKUs and quantities, total pricing, selected payment method,
 * and any relevant contextual/coupon codes.
 *
 * Upon validation and business checks (e.g., inventory, eligibility, address),
 * the API atomically creates the new order with one or more order lines (for
 * each SKU), computes seller splits if multiple sellers are present, and
 * reserves inventory. It generates a globally unique order_code, sets the order
 * status to the initial workflow state (such as 'pending'), and creates
 * references to status history and payment attempt entities. On success, the
 * API returns the entire created IShoppingOrder instance. Inventory is locked
 * as necessary to prevent overselling, and security checks enforce correct
 * actor usage and business constraints.
 *
 * Edge and error cases such as insufficient inventory, invalid address, or
 * payment method failure trigger appropriate error responses. The operation is
 * open to authenticated customers only and is the central entry point for order
 * creation in the shopping platform.
 *
 * @param props.connection
 * @param props.body Comprehensive information about the new order: customer,
 *   SKUs, delivery/billing address, pricing, payment option, and all line
 *   items, adhering to the IShoppingOrder.ICreate schema.
 * @path /shopping/customer/orders
 * @accessor api.functional.shopping.customer.orders.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
