/**
 * Search and retrieve a paginated, filtered list of all appeals within the
 * platform (shopping_appeals table).
 *
 * Retrieve a paginated, filterable list of platform appeals from the
 * shopping_appeals table, supporting advanced search and sorting. This
 * operation is critical for surfacing all formal appeals (against suspensions,
 * account actions, policy violations, or compliance events) open or closed
 * within the shopping mall backend.
 *
 * Multiple actor types may file appeals—customers appealing account suspensions
 * or policy violations, sellers disputing platform administrative actions, or
 * admins managing oversight. The search capability enables filtering by status,
 * type, decision state, dates, and full-text search in the reason or decision
 * fields. This facilitates compliance, escalation workflow, and timely
 * resolution.
 *
 * All results are scoped by the requesting actor's visibility; for instance,
 * customers can see their own appeals, sellers those cases they initiated, and
 * admins global appeals (subject to role restrictions). The response returns
 * paginated summary information for each matching appeal, with option to fetch
 * detail via the GET /appeals/{appealId} operation. Error handling ensures that
 * malformed filters or unauthorized access attempts return specific error codes
 * and audit logs.
 *
 * @param props.connection
 * @param props.body Search and filter parameters for querying appeals (status,
 *   filer, dates, etc).
 * @path /shopping/customer/appeals
 * @accessor api.functional.shopping.customer.appeals.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search and filter parameters for querying appeals (status, filer,
     * dates, etc).
     */
    body: IShoppingAppeal.IRequest;
  };
  export type Body = IShoppingAppeal.IRequest;
  export type Response = IPageIShoppingAppeal.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/customer/appeals",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shopping/customer/appeals";
  export const random = (): IPageIShoppingAppeal.ISummary =>
    typia.random<IPageIShoppingAppeal.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

