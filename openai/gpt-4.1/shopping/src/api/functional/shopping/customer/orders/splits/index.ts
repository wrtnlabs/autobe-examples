import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingOrderSplit } from "../../../../../structures/IShoppingOrderSplit";

/**
 * Retrieve detail for a specific order split by order and split code.
 *
 * This endpoint fetches the complete data for an order split identified by the
 * composite keys 'orderCode' and 'splitCode', referencing the shopping_orders
 * and shopping_order_splits tables. It returns split-level detail such as
 * seller allocation, status, subtotal price, and fulfillment progress.
 *
 * Permission control ensures only the related customer, seller assigned to this
 * split, or an admin may access this information. The operation is crucial for
 * both customers tracking a multi-seller order and sellers viewing their
 * segment of a customer's order.
 *
 * The returned data provides all split attributes, audits, and relationships
 * needed for business logic, dashboard displays, seller support, and customer
 * self-service. Related endpoints include top-level order retrieval, line item
 * details, and order audit logs.
 *
 * @param props.connection
 * @param props.orderCode Globally unique business reference code for the parent
 *   order (global scope).
 * @param props.splitCode Unique code identifying the split sub-order for a
 *   specific seller within the order (scoped to order).
 * @path /shopping/customer/orders/:orderCode/splits/:splitCode
 * @accessor api.functional.shopping.customer.orders.splits.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Globally unique business reference code for the parent order (global
     * scope).
     */
    orderCode: string;

    /**
     * Unique code identifying the split sub-order for a specific seller
     * within the order (scoped to order).
     */
    splitCode: string;
  };
  export type Response = IShoppingOrderSplit;

  export const METADATA = {
    method: "GET",
    path: "/shopping/customer/orders/:orderCode/splits/:splitCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shopping/customer/orders/${encodeURIComponent(props.orderCode ?? "null")}/splits/${encodeURIComponent(props.splitCode ?? "null")}`;
  export const random = (): IShoppingOrderSplit =>
    typia.random<IShoppingOrderSplit>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderCode")(() => typia.assert(props.orderCode));
      assert.param("splitCode")(() => typia.assert(props.splitCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
