import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingRefundApproval } from "../../../../../structures/IShoppingRefundApproval";
import { IPageIShoppingRefundApproval } from "../../../../../structures/IPageIShoppingRefundApproval";

/**
 * Search and list approval/rejection actions for a given refund request
 * (shopping_refund_approvals table).
 *
 * Enables authorized users or admins to retrieve a paginated list of all seller
 * and admin approval or rejection records tied to a particular refund request.
 * This supports business audit, regulatory review, and dispute investigation by
 * exposing an authoritative record of all actions taken on refund status
 * transitions.
 *
 * The endpoint supports advanced filtering—by actor, action type
 * (approval/rejection), and time window—as well as paginated delivery of result
 * sets using request parameters. Access is limited to authorized actors to
 * ensure privacy, and sensitive rationale/notes are selectively shown based on
 * the actor requesting the data (full detail for admin, business-safe versions
 * for customers).
 *
 * Related operations include GET for single approval records and PATCH with
 * search criteria across multiple refund requests for admin/business analytics.
 * Errors are returned if the refund request does not exist or the actor lacks
 * permission.
 *
 * @param props.connection
 * @param props.refundRequestId Unique identifier of the refund request this
 *   approval action belongs to (global scope).
 * @param props.body Paging, filtering, and search criteria for refund approval
 *   records (actor, action, date, etc.).
 * @path /shopping/customer/refunds/:refundRequestId/approvals
 * @accessor api.functional.shopping.customer.refunds.approvals.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the refund request this approval action belongs
     * to (global scope).
     */
    refundRequestId: string & tags.Format<"uuid">;

    /**
     * Paging, filtering, and search criteria for refund approval records
     * (actor, action, date, etc.).
     */
    body: IShoppingRefundApproval.IRequest;
  };
  export type Body = IShoppingRefundApproval.IRequest;
  export type Response = IPageIShoppingRefundApproval.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/customer/refunds/:refundRequestId/approvals",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shopping/customer/refunds/${encodeURIComponent(props.refundRequestId ?? "null")}/approvals`;
  export const random = (): IPageIShoppingRefundApproval.ISummary =>
    typia.random<IPageIShoppingRefundApproval.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("refundRequestId")(() =>
        typia.assert(props.refundRequestId),
      );
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
