/**
 * Search and retrieve tracking events for a specific package tracking instance
 * (shopping_shipment_tracking_events).
 *
 * This operation provides a filtered and paginated event log of all tracking
 * updates, scan events, and status changes for a given shipment package
 * reference and tracking source. The lookup is resolved by joining on the
 * shipment code, package label, and tracking source, ultimately resolving the
 * tracking instance (shopping_shipment_trackings.id) and returning all
 * associated tracking event records from shopping_shipment_tracking_events.
 *
 * Typical use cases include displaying shipment tracking history to customers
 * (e.g., delivery progress screens), enabling seller support for delivery
 * disputes or exceptions, and providing administrators with a full audit trail
 * for compliance and incident management. The returned list contains carrier
 * and system-generated tracking milestones, location data, time stamps, and
 * event details as stored in the Prisma schema fields.
 *
 * Actor authentication is enforced: only parties associated with the shipment
 * (purchasing customer, responsible seller, or admin) may access this endpoint.
 * Rate limiting is applied to prevent excessive carrier polling or brute-force
 * enumeration. Expected error scenarios include unresolved or expired package
 * labels, tracking source mismatches, permission denials, and unsupported event
 * queries.
 *
 * Related endpoints: use the GET tracking instance endpoint for aggregate
 * status and summary before drilling down to full event history. The search
 * supports filter, sort, and pagination criteria as defined in the request
 * schema.
 *
 * @param props.connection
 * @param props.code Unique business shipment code for the target shipment
 *   (global scope).
 * @param props.packageLabel Unique business label of the target package within
 *   the shipment (scoped to shipment).
 * @param props.trackingSource Source identifier for the tracking instance
 *   (e.g., 'courier_api', 'warehouse_scan').
 * @param props.body Search and pagination parameters for tracking event
 *   retrieval.
 * @path /shopping/customer/shipments/:code/packages/:packageLabel/trackings/:trackingSource/events
 * @accessor api.functional.shopping.customer.shipments.packages.trackings.events.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique business shipment code for the target shipment (global scope). */
    code: string;

    /**
     * Unique business label of the target package within the shipment
     * (scoped to shipment).
     */
    packageLabel: string;

    /**
     * Source identifier for the tracking instance (e.g., 'courier_api',
     * 'warehouse_scan').
     */
    trackingSource: string;

    /** Search and pagination parameters for tracking event retrieval. */
    body: IShoppingShipmentTrackingEvent.IRequest;
  };
  export type Body = IShoppingShipmentTrackingEvent.IRequest;
  export type Response = IPageIShoppingShipmentTrackingEvent;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/customer/shipments/:code/packages/:packageLabel/trackings/:trackingSource/events",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shopping/customer/shipments/${encodeURIComponent(props.code ?? "null")}/packages/${encodeURIComponent(props.packageLabel ?? "null")}/trackings/${encodeURIComponent(props.trackingSource ?? "null")}/events`;
  export const random = (): IPageIShoppingShipmentTrackingEvent =>
    typia.random<IPageIShoppingShipmentTrackingEvent>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("code")(() => typia.assert(props.code));
      assert.param("packageLabel")(() => typia.assert(props.packageLabel));
      assert.param("trackingSource")(() => typia.assert(props.trackingSource));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
