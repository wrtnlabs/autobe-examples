/**
 * Search and retrieve all payment attempts for an order by order code.
 *
 * This endpoint enables comprehensive search and review of all payment attempt
 * records linked to a specific order, using the global order_code as a
 * reference. The system returns complete details for each attempt, including
 * payment_reference (if assigned), attempt_status (pending, completed, failed,
 * cancelled), amount, timestamps, and outcome.
 *
 * The operation is designed for use by customers monitoring their own order
 * payment progress, sellers verifying transaction status, or admins
 * investigating payment workflows, failures, or fraud incidents. Result data
 * supports choice of page size, offset, and sorting per
 * IShoppingPaymentAttempt.IRequest definition: filtering by status, timeframe,
 * or reference is included where supported by implementation.
 *
 * All returned payment attempts strictly correspond to the order specified,
 * preventing cross-order data leakage. Authorization is required; only the
 * customer for the order, involved seller, or admins have access. This
 * operation references the documentation and relationships for shopping_orders
 * and shopping_payment_attempts, ensuring correct alignment with the business
 * and audit trail.
 *
 * @param props.connection
 * @param props.orderCode Globally unique, human-readable code of the target
 *   order (global scope)
 * @param props.body Search/filter parameters and pagination options for payment
 *   attempt records associated with the order. Follows standard paging and
 *   search conventions.
 * @path /shopping/customer/orders/:orderCode/payment-attempts
 * @accessor api.functional.shopping.customer.orders.payment_attempts.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Globally unique, human-readable code of the target order (global
     * scope)
     */
    orderCode: string;

    /**
     * Search/filter parameters and pagination options for payment attempt
     * records associated with the order. Follows standard paging and search
     * conventions.
     */
    body: IShoppingPaymentAttempt.IRequest;
  };
  export type Body = IShoppingPaymentAttempt.IRequest;
  export type Response = IPageIShoppingPaymentAttempt;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/customer/orders/:orderCode/payment-attempts",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shopping/customer/orders/${encodeURIComponent(props.orderCode ?? "null")}/payment-attempts`;
  export const random = (): IPageIShoppingPaymentAttempt =>
    typia.random<IPageIShoppingPaymentAttempt>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderCode")(() => typia.assert(props.orderCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

