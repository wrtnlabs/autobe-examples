/**
 * Retrieve detailed information for a specific shipment package by shipment
 * code and package label (shopping_shipment_packages table).
 *
 * This API operation retrieves the full set of details for a single shipment
 * package based on the provided shipment code and package label path
 * parameters. The underlying database table is shopping_shipment_packages,
 * which stores package-specific data such as tracking number, label,
 * dimensions, sequence in shipment, package status (pending, ready, shipped,
 * delivered, lost, damaged), and audit timestamps.
 *
 * The detailed package information includes all fields defined in the
 * shopping_shipment_packages schema and is returned only if the shipment code
 * and package label together uniquely identify a valid package. Security and
 * data privacy are strictly enforced: only the customer who placed the order,
 * the seller fulfilling the shipment, and authorized admins are permitted to
 * access these details. Attempts to access unauthorized or non-existent
 * packages will result in explicit error responses.
 *
 * This operation is typically used to power user package tracking UIs, enable
 * support for split or multi-package shipments, and deliver targeted
 * notifications about shipping events (such as package scanned, out for
 * delivery, delivered, or exceptions). If the shipment or package has been
 * soft-deleted, this operation will not return package details and may return a
 * 404 or business error.
 *
 * Integration with related shipment APIs is facilitated by using the same
 * package and shipment identification pattern; related endpoints include
 * shipment-level detail retrieval, tracking event patch, and admin shipment
 * audit.
 *
 * @param props.connection
 * @param props.code Unique business identifier code for the target shipment
 *   (global scope).
 * @param props.packageLabel Unique business identifier label of the target
 *   package within the shipment (scoped to shipment).
 * @path /shopping/customer/shipments/:code/packages/:packageLabel
 * @accessor api.functional.shopping.customer.shipments.packages.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique business identifier code for the target shipment (global
     * scope).
     */
    code: string;

    /**
     * Unique business identifier label of the target package within the
     * shipment (scoped to shipment).
     */
    packageLabel: string;
  };
  export type Response = IShoppingShipmentPackage;

  export const METADATA = {
    method: "GET",
    path: "/shopping/customer/shipments/:code/packages/:packageLabel",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shopping/customer/shipments/${encodeURIComponent(props.code ?? "null")}/packages/${encodeURIComponent(props.packageLabel ?? "null")}`;
  export const random = (): IShoppingShipmentPackage =>
    typia.random<IShoppingShipmentPackage>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("code")(() => typia.assert(props.code));
      assert.param("packageLabel")(() => typia.assert(props.packageLabel));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
