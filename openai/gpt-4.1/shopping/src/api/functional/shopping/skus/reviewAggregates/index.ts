import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingReviewRatingAggregate } from "../../../../structures/IShoppingReviewRatingAggregate";

/**
 * Retrieve review & rating summary aggregate for a product SKU
 * (shopping_review_rating_aggregates).
 *
 * This API operation allows any actor (public) to fetch the detailed summary
 * statistics for customer reviews and ratings associated with a particular
 * product SKU. Typical use cases include displaying product star ratings, total
 * review counts, and average scores in catalog listings, product pages, and
 * search rankings.
 *
 * For the given SKU, the API returns the corresponding summary object from the
 * shopping_review_rating_aggregates table: including fields such as
 * average_rating, review_count, product_review_count, and
 * product_average_rating. Actors do not need to be authenticated for this
 * operation as review/rating data is intended for broad public consumption and
 * does not expose any personal information.
 *
 * The required path parameter skuId is the UUID of the SKU being queried. If no
 * review aggregate exists, a not found error is returned. This operation stands
 * alone but is also commonly used in conjunction with product/variant detail
 * endpoints in catalog APIs. This endpoint never requires a request body or
 * sensitive authentication.
 *
 * Error handling is limited to validation errors (UUID format) or missing data
 * (404 not found).
 *
 * @param props.connection
 * @param props.skuId Unique identifier of the target SKU (UUID) for which
 *   review aggregate summary is requested.
 * @path /shopping/skus/:skuId/reviewAggregates
 * @accessor api.functional.shopping.skus.reviewAggregates.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target SKU (UUID) for which review aggregate
     * summary is requested.
     */
    skuId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingReviewRatingAggregate;

  export const METADATA = {
    method: "GET",
    path: "/shopping/skus/:skuId/reviewAggregates",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shopping/skus/${encodeURIComponent(props.skuId ?? "null")}/reviewAggregates`;
  export const random = (): IShoppingReviewRatingAggregate =>
    typia.random<IShoppingReviewRatingAggregate>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("skuId")(() => typia.assert(props.skuId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
