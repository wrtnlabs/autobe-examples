import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingBusinessPolicy } from "../../../structures/IShoppingBusinessPolicy";

/**
 * Retrieve a business policy configuration by unique policy name from
 * shopping_business_policies.
 *
 * Fetch detailed information for a specific business policy defined in the
 * shopping_business_policies table by policy name.
 *
 * This API is intended to expose policy details for platform rule enforcement,
 * configuration introspection, or compliance checks. The policy_name path
 * parameter must match a unique, active business policy (case-insensitive
 * string), as enforced by the Prisma schema's @@unique([policy_name, scope])
 * constraint. Results include the policy value, scope, description, and
 * activation status, allowing clients (including admin panels or seller
 * integration code) to correctly interpret operational rules.
 *
 * The policy is not directly modifiable via this endpoint, and sensitive (e.g.,
 * audit-only or deleted) policies are not returned. Errors are raised if the
 * requested policy_name does not exist, points to an inactive or deleted
 * policy, or if the request attempts to access protected business domains. The
 * endpoint is publicly readable but some policy keys may be access-controlled
 * in implementation depending on data sensitivity.
 *
 * @param props.connection
 * @param props.policyName Unique policy_name string for the target business
 *   policy (global scope); must correspond to the policy_name column in the
 *   shopping_business_policies table. Policy names are case-insensitive and
 *   uniquely identify the policy rule to be fetched.
 * @path /shopping/businessPolicies/:policyName
 * @accessor api.functional.shopping.businessPolicies.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique policy_name string for the target business policy (global
     * scope); must correspond to the policy_name column in the
     * shopping_business_policies table. Policy names are case-insensitive
     * and uniquely identify the policy rule to be fetched.
     */
    policyName: string;
  };
  export type Response = IShoppingBusinessPolicy;

  export const METADATA = {
    method: "GET",
    path: "/shopping/businessPolicies/:policyName",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shopping/businessPolicies/${encodeURIComponent(props.policyName ?? "null")}`;
  export const random = (): IShoppingBusinessPolicy =>
    typia.random<IShoppingBusinessPolicy>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("policyName")(() => typia.assert(props.policyName));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
