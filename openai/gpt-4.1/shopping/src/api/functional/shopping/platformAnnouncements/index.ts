import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingPlatformAnnouncement } from "../../../structures/IShoppingPlatformAnnouncement";

/**
 * Retrieve detailed information for a specific platform announcement
 * (shopping_platform_announcements).
 *
 * This endpoint provides the complete details for a single platform
 * announcement specified by the unique 'platformAnnouncementId'. It is designed
 * to support admin and user views that display scheduled, active, or historical
 * announcements published by administrators. The response includes all
 * announcement metadata, such as title, body content, audience targeting,
 * publication status, scheduling windows, and the authoring admin's reference.
 *
 * Security is enforced so that only authenticated actors with viewing
 * permissions (such as admins or general platform users) may access the
 * announcement details. This operation reads from the
 * 'shopping_platform_announcements' Prisma table and reflects any changes to
 * announcement content or status in real time, ensuring up-to-date information
 * is always served.
 *
 * Error handling covers scenarios where the specified announcement does not
 * exist, is deleted, or the caller lacks permission to view the content. This
 * endpoint is typically used in any context requiring display or audit of
 * admin-issued platform announcements.
 *
 * @param props.connection
 * @param props.platformAnnouncementId Unique identifier (UUID) of the target
 *   platform announcement to retrieve (global scope)
 * @path /shopping/platformAnnouncements/:platformAnnouncementId
 * @accessor api.functional.shopping.platformAnnouncements.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier (UUID) of the target platform announcement to
     * retrieve (global scope)
     */
    platformAnnouncementId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingPlatformAnnouncement;

  export const METADATA = {
    method: "GET",
    path: "/shopping/platformAnnouncements/:platformAnnouncementId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shopping/platformAnnouncements/${encodeURIComponent(props.platformAnnouncementId ?? "null")}`;
  export const random = (): IShoppingPlatformAnnouncement =>
    typia.random<IShoppingPlatformAnnouncement>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("platformAnnouncementId")(() =>
        typia.assert(props.platformAnnouncementId),
      );
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
