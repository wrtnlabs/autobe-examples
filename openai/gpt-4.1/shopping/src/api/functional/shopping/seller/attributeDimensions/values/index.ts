/**
 * Search and retrieve all attribute values for a given attribute dimension from
 * shopping_attribute_values.
 *
 * This API endpoint allows catalog administrators or authorized sellers to
 * query all attribute values under a single attribute dimension, as indicated
 * by the dimensionCode path parameter. Attribute values represent selectable
 * options in product or SKU variants, such as color names, size labels, or
 * other feature values.
 *
 * The operation supports flexible search and filtering, including sorting by
 * display order, searching by value code, and paginating results for efficient
 * frontend display. It leverages the relationships defined in
 * shopping_attribute_dimensions and shopping_attribute_values, ensuring that
 * only options for the specified dimension are returned.
 *
 * The response includes detailed information for each attribute value, such as
 * its value_code, display_value, and display_order. Security and access
 * restrictions require that only authorized users managing the catalog can
 * access this endpoint. This operation is essential for product onboarding,
 * catalog cleanup, and management of variant options.
 *
 * @param props.connection
 * @param props.dimensionCode Unique business code of the attribute dimension
 *   whose values are being retrieved (global scope).
 * @param props.body Filtering, pagination, or search parameters for querying
 *   attribute values of a dimension.
 * @path /shopping/seller/attributeDimensions/:dimensionCode/values
 * @accessor api.functional.shopping.seller.attributeDimensions.values.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique business code of the attribute dimension whose values are
     * being retrieved (global scope).
     */
    dimensionCode: string;

    /**
     * Filtering, pagination, or search parameters for querying attribute
     * values of a dimension.
     */
    body: IShoppingAttributeValue.IRequest;
  };
  export type Body = IShoppingAttributeValue.IRequest;
  export type Response = IPageIShoppingAttributeValue;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/seller/attributeDimensions/:dimensionCode/values",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shopping/seller/attributeDimensions/${encodeURIComponent(props.dimensionCode ?? "null")}/values`;
  export const random = (): IPageIShoppingAttributeValue =>
    typia.random<IPageIShoppingAttributeValue>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("dimensionCode")(() => typia.assert(props.dimensionCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
