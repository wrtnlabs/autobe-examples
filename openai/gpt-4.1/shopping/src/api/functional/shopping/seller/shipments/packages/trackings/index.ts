/**
 * Search and retrieve all tracking instances with events for a shipment package
 * (shopping_shipment_trackings table) with advanced filtering and pagination.
 *
 * This endpoint enables clients to search and paginate through all tracking
 * entries and their detailed event logs associated with a specific shipment
 * package. It operates principally on the shopping_shipment_trackings and
 * shopping_shipment_tracking_events tables, allowing for granular examination
 * of both carrier/courier tracking data and internal shipping lifecycle
 * events.
 *
 * The request body (IShoppingShipmentTracking.IRequest) supports filters for
 * tracking source (e.g., courier, warehouse scan), event window (start/end
 * date), status (in_transit, delivered, delayed, lost), and custom business
 * tag, along with pagination and sort properties. The result
 * (IPageIShoppingShipmentTracking) is a paginated array of tracking instances,
 * each including current status, last known location, and all historical event
 * records, suitable for both real-time user tracking and operational or admin
 * analytics.
 *
 * Strict access controls are enforced: only users with a direct business
 * relationship to the shipment (buyer, seller, admin) are allowed results.
 * Non-existent or mismatched codes/labels will result in failed lookups. This
 * operation supports shipping dashboards, logistics analytics, and support
 * workflows where incident investigation for lost or delayed packages is
 * necessary.
 *
 * @param props.connection
 * @param props.code Unique business identifier code for the target shipment
 *   (global scope).
 * @param props.packageLabel Unique business identifier label of the target
 *   package within the shipment (scoped to shipment).
 * @param props.body Filtering, sorting, pagination, and advanced tracking query
 *   parameters for shipment tracking events.
 * @path /shopping/seller/shipments/:code/packages/:packageLabel/trackings
 * @accessor api.functional.shopping.seller.shipments.packages.trackings.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
