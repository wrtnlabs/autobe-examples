import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingReviewAttachment } from "../../../../../structures/IShoppingReviewAttachment";

/**
 * Retrieve a specific attachment for a review by reviewId and attachmentId.
 *
 * This API operation retrieves the metadata and download URI for a single
 * attachment associated with a specific review. Clients may use this to fetch
 * images, videos, or documents included as part of a customer review.
 *
 * Strict authorization is enforced: only the review author (customer), business
 * admins (admin), or relevant seller-side actors (seller) may access the
 * attachment resource. Soft-deleted records are excluded, and requests for
 * non-associated attachment/review pairs are treated as not found.
 *
 * If validation fails (review not found, attachment missing/deleted, or auth
 * failure), an error is returned. The response includes the attachment's
 * metadata and its secure URI (string). Attachments are always associated to
 * their parent review and never exposed if the review is deleted or locked for
 * moderation. All accesses are audited.
 *
 * This operation references shopping_reviews and shopping_review_attachments.
 * Fine-grained error handling is recommended.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the target review for which the
 *   attachment is requested (UUID).
 * @param props.attachmentId Unique identifier of the attachment file to
 *   retrieve within the specified review (UUID).
 * @path /shopping/seller/reviews/:reviewId/attachments/:attachmentId
 * @accessor api.functional.shopping.seller.reviews.attachments.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target review for which the attachment is
     * requested (UUID).
     */
    reviewId: string & tags.Format<"uuid">;

    /**
     * Unique identifier of the attachment file to retrieve within the
     * specified review (UUID).
     */
    attachmentId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingReviewAttachment;

  export const METADATA = {
    method: "GET",
    path: "/shopping/seller/reviews/:reviewId/attachments/:attachmentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shopping/seller/reviews/${encodeURIComponent(props.reviewId ?? "null")}/attachments/${encodeURIComponent(props.attachmentId ?? "null")}`;
  export const random = (): IShoppingReviewAttachment =>
    typia.random<IShoppingReviewAttachment>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
      assert.param("attachmentId")(() => typia.assert(props.attachmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
