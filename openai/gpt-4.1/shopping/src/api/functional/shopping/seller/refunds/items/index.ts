/**
 * Search and retrieve refund request items for a specific refund, with advanced
 * filtering and pagination (shopping_refund_request_items).
 *
 * Retrieve a comprehensive, paginated list of all refund request items attached
 * to a specific refund request. This operation enables actors to search,
 * filter, and page through refund items pertaining to the original refund
 * request, referencing the shopping_refund_request_items table in the Prisma
 * schema. Each refund item provides full context: the associated order line,
 * SKU, quantity, business reason if set at item level, status, and
 * creation/modification timestamps.
 *
 * Security and permissions: The endpoint is available to authenticated users
 * with legitimate interest in the refund (customer who initiated, seller of the
 * orders involved, or admin overseeing disputes). The business logic ensures
 * that only those with appropriate access to the parent refund request may
 * query its items, with additional constraints for sensitive order details.
 *
 * Business workflow connections: Listing refund items supports both UI and
 * automated workflows—such as reviewing pending claims, processing partial
 * approvals/denials, and auditing refund eligibility by status and linkage.
 * Filtering capabilities let actors focus on items needing manual action or
 * escalation, while pagination ensures efficiency on large/multi-item requests.
 * Errors for missing or ineligible refundRequestId are handled with explicit
 * business codes and user guidance.
 *
 * @param props.connection
 * @param props.refundRequestId Unique identifier of the parent refund request
 *   (global scope)
 * @param props.body Filtering, search, and pagination criteria for refund
 *   request items list retrieval
 * @path /shopping/seller/refunds/:refundRequestId/items
 * @accessor api.functional.shopping.seller.refunds.items.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the parent refund request (global scope) */
    refundRequestId: string & tags.Format<"uuid">;

    /**
     * Filtering, search, and pagination criteria for refund request items
     * list retrieval
     */
    body: IShoppingRefundRequestItem.IRequest;
  };
  export type Body = IShoppingRefundRequestItem.IRequest;
  export type Response = IPageIShoppingRefundRequestItem.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/seller/refunds/:refundRequestId/items",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shopping/seller/refunds/${encodeURIComponent(props.refundRequestId ?? "null")}/items`;
  export const random = (): IPageIShoppingRefundRequestItem.ISummary =>
    typia.random<IPageIShoppingRefundRequestItem.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("refundRequestId")(() =>
        typia.assert(props.refundRequestId),
      );
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

