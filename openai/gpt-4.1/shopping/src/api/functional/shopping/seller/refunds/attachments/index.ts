/**
 * Get metadata for a file attachment belonging to a refund request in the
 * shopping_refund_attachments table.
 *
 * Retrieve a specific attachment linked to a refund request in the shopping
 * platform. This endpoint serves customers, sellers, and admins involved in a
 * particular refund, return, or cancellation process, providing access to
 * uploaded evidence such as photos, invoices, or compliance documents.
 *
 * Security and access control are enforced based on the refund case and user
 * actor: only the original requester (customer), affected seller, or an
 * administrator may access this resource. Unauthorized access attempts trigger
 * audit and may result in denial. The attachment is returned if it exists, is
 * linked to the given refund, and is not deleted or restricted by moderation
 * policy.
 *
 * This operation references the shopping_refund_attachments table. It checks
 * both the refundRequestId and attachmentId for relationship integrity and
 * access rules. On success, it returns structured metadata about the file
 * (including URI, type, and size) but not the binary file itself—file download
 * is handled via the file_uri property, not direct API streaming.
 *
 * @param props.connection
 * @param props.refundRequestId Unique identifier for the parent refund request.
 *   Must be a valid UUID referring to an existing refund process (scoped to the
 *   customer, seller, or admin actors as applicable).
 * @param props.attachmentId Unique identifier for the requested attachment
 *   record within the specified refund request (must be a valid UUID).
 * @path /shopping/seller/refunds/:refundRequestId/attachments/:attachmentId
 * @accessor api.functional.shopping.seller.refunds.attachments.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
