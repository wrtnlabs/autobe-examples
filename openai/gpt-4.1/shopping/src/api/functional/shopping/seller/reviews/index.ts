export * as attachments from "./attachments/index";

/**
 * Search and retrieve filtered, paginated list of product reviews
 * (shopping_reviews).
 *
 * Retrieve a filtered, paginated list of product reviews submitted by customers
 * for products and SKUs on the shopping mall platform. This operation allows
 * searching by review state, star rating, associated product or SKU, customer
 * ID, order line, keywords within comments, and date range. The response
 * includes review summary information for admin, seller, or customer display,
 * showing each review's unique identifiers, rating, truncated comment, state,
 * creation/update dates, and author details per role permissions.
 *
 * Pagination and sorting are fully supported via the request body parameters,
 * with page size and offset controls. Security is enforced according to the
 * actor accessing the endpoint—admins may access all reviews, sellers those for
 * their products, and customers only their own. Integration with review
 * moderation and abuse workflows is supported. Errors include unauthorized
 * access, invalid parameters, and exceeded page size limits.
 *
 * @param props.connection
 * @param props.body Review search and filter criteria including pagination and
 *   advanced filters
 * @path /shopping/seller/reviews
 * @accessor api.functional.shopping.seller.reviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Review search and filter criteria including pagination and advanced
     * filters
     */
    body: IShoppingReview.IRequest;
  };
  export type Body = IShoppingReview.IRequest;
  export type Response = IPageIShoppingReview.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/seller/reviews",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shopping/seller/reviews";
  export const random = (): IPageIShoppingReview.ISummary =>
    typia.random<IPageIShoppingReview.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Retrieve complete details for a single product review from shopping_reviews
 * table.
 *
 * Retrieve the complete record and associated data for a specific customer
 * product review by its unique reviewId (UUID, PK in shopping_reviews schema).
 * This operation is used to display all review information in detail, including
 * full text, rating, state, reviewer details, attachments, and audit history if
 * allowed. The returned data includes all fields and relationships (customer,
 * SKU, order line), for detailed view or moderation workflows.
 *
 * Security and access control are based on role: customers access their own
 * reviews, sellers see reviews for their products, admins may access all.
 * Reference integrity and soft deletion are respected; if the review does not
 * exist, is deleted, or access is denied, an error or null is returned.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the target review (UUID as PK of
 *   shopping_reviews)
 * @path /shopping/seller/reviews/:reviewId
 * @accessor api.functional.shopping.seller.reviews.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
