import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingSellerSession } from "../../../../../structures/IShoppingSellerSession";
import { IPageIShoppingSellerSession } from "../../../../../structures/IPageIShoppingSellerSession";

/**
 * List seller's authentication sessions for account security and audit
 * (shopping_seller_sessions).
 *
 * Retrieve a paginated and filterable list of all authentication sessions for a
 * specific seller. This operation provides visibility into each login attempt,
 * session IP address, creation timestamp, expiration (if any), and context
 * about the device or connection used. The data is essential for both sellers
 * and administrators to monitor account access, detect potentially unauthorized
 * activity, and perform regular security audits.
 *
 * The sellerId parameter specifies the seller whose sessions are being queried.
 * The operation leverages the shopping_seller_sessions table as defined in the
 * Prisma schema, incorporating all its columns, such as session ID, creation
 * time, expiration, IP address, and href/referrer for the session. Additional
 * business logic should restrict access so that only the session owner (the
 * seller) or privileged admin actors can retrieve session details. Session
 * tokens and authentication security are managed separately and not altered by
 * this endpoint.
 *
 * Common usage scenarios include account security review, vendor dashboard
 * session lists, and compliance-driven reports for past authentication events.
 * Error handling must ensure that attempts to access sessions for another
 * seller (without appropriate permissions) are denied for data privacy and
 * security compliance. Only session metadata is returned; actual authentication
 * tokens are not exposed.
 *
 * @param props.connection
 * @param props.sellerId Unique identifier of the target seller
 * @param props.body Session filtering, pagination, and search criteria for
 *   seller's session history
 * @path /shopping/seller/sellers/:sellerId/sessions
 * @accessor api.functional.shopping.seller.sellers.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target seller */
    sellerId: string & tags.Format<"uuid">;

    /**
     * Session filtering, pagination, and search criteria for seller's
     * session history
     */
    body: IShoppingSellerSession.IRequest;
  };
  export type Body = IShoppingSellerSession.IRequest;
  export type Response = IPageIShoppingSellerSession;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/seller/sellers/:sellerId/sessions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shopping/seller/sellers/${encodeURIComponent(props.sellerId ?? "null")}/sessions`;
  export const random = (): IPageIShoppingSellerSession =>
    typia.random<IPageIShoppingSellerSession>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sellerId")(() => typia.assert(props.sellerId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
