import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingShipment } from "../../../structures/IShoppingShipment";

/**
 * Retrieve detailed information for a specific shipment by code from
 * shopping_shipments.
 *
 * Retrieve a single shipment's details by its unique code. This endpoint
 * returns all essential shipment fields such as status, carrier company,
 * dispatch and delivery dates, and associated metadata, for both customer and
 * operations use cases.
 *
 * Authorization is generally required for viewing shipment details, with
 * role-based restrictions: customers may only view their own shipment codes;
 * sellers may view only those for their products; admins may access all
 * shipments. This aligns with business logic in shopping_shipments and the
 * requirements for secure, auditable tracking.
 *
 * Full tracking and historical status information are not included here but may
 * be retrieved using subsidiary audit endpoints. Error responses occur if the
 * shipment code does not exist or is not accessible by the actor context,
 * matching platform security standards.
 *
 * @param props.connection
 * @param props.code Unique shipment business code (e.g., SHPT-2025-0001)
 *   assigned in shopping_shipments for external and business workflows. Must
 *   match exactly to identify the shipment record.
 * @path /shopping/shipments/:code
 * @accessor api.functional.shopping.shipments.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique shipment business code (e.g., SHPT-2025-0001) assigned in
     * shopping_shipments for external and business workflows. Must match
     * exactly to identify the shipment record.
     */
    code: string;
  };
  export type Response = IShoppingShipment;

  export const METADATA = {
    method: "GET",
    path: "/shopping/shipments/:code",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shopping/shipments/${encodeURIComponent(props.code ?? "null")}`;
  export const random = (): IShoppingShipment =>
    typia.random<IShoppingShipment>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("code")(() => typia.assert(props.code));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
