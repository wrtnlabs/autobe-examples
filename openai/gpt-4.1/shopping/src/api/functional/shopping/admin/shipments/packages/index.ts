/**
 * Search and retrieve paginated, filterable list of all packages related to a
 * shipment by code.
 *
 * This API endpoint allows administrators, shipping managers, and authorized
 * operators to search and browse all shipment package units for a single
 * shipment. The operation supports flexible search filters (package status,
 * label, tracking number, sequence, delivery state), pagination, and sorting to
 * enable end-to-end visibility of packaging and fulfillment for a single
 * shipment. Package details support audit and real-time operational
 * troubleshooting.
 *
 * Path parameter validation ensures that the provided business code exists in
 * the shopping_shipments table and filters only packages attached to that
 * shipment. Search and sort options are customizable through the request body
 * (IShoppingShipmentPackage.IRequest), allowing for highly granular package
 * inspection within a shipment.
 *
 * Security considerations restrict access to admin actors to preserve delivery
 * performance and package integrity. API responses conform to data privacy and
 * operational standards for shipment package information. This endpoint
 * supports core operational metrics for logistics performance tracking and
 * exception management.
 *
 * @param props.connection
 * @param props.code Unique business code identifying the shipment (global
 *   scope) whose packages are to be indexed. Example: SHPT-2025-0001
 * @param props.body Search and filter criteria for shipment packages (status,
 *   tracking number, sequence, delivery dates, etc.)
 * @path /shopping/admin/shipments/:code/packages
 * @accessor api.functional.shopping.admin.shipments.packages.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique business code identifying the shipment (global scope) whose
     * packages are to be indexed. Example: SHPT-2025-0001
     */
    code: string;

    /**
     * Search and filter criteria for shipment packages (status, tracking
     * number, sequence, delivery dates, etc.)
     */
    body: IShoppingShipmentPackage.IRequest;
  };
  export type Body = IShoppingShipmentPackage.IRequest;
  export type Response = IPageIShoppingShipmentPackage.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/admin/shipments/:code/packages",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shopping/admin/shipments/${encodeURIComponent(props.code ?? "null")}/packages`;
  export const random = (): IPageIShoppingShipmentPackage.ISummary =>
    typia.random<IPageIShoppingShipmentPackage.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("code")(() => typia.assert(props.code));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

