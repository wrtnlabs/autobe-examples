import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingCart } from "../../../../structures/IShoppingCart";
import { IPageIShoppingCart } from "../../../../structures/IPageIShoppingCart";

/**
 * Search and retrieve a paginated list of shopping carts with filtering options
 * (shopping_carts table).
 *
 * This endpoint is designed to provide system access to the list of all
 * customer shopping carts in the platform. It is particularly useful for
 * administrative or operational roles that require a broad view of customer
 * engagement or troubleshooting of shopping cart behaviors.
 *
 * The response includes concise summary information about each cart, such as
 * the linked customer, creation and last update timestamps, number of items in
 * the cart, and relationships to customer or product data as necessary for list
 * context. Advanced filtering options enable searching for carts by customer
 * ID, activity date, or other identifying characteristics, supporting both
 * routine reviews and targeted queries.
 *
 * Security measures ensure that only authorized actors (typically admin or
 * designated operational personnel) can use this endpoint, and that personally
 * identifiable information is handled per compliance policies. Results are
 * paginated with customizable limits and standardized sorting controls. This
 * operation does not expose individual cart item details (see specific cart
 * retrieval for that functionality). Error handling covers cases where query
 * parameters are malformed or system access is not permitted.
 *
 * @param props.connection
 * @param props.body Filter and pagination information for shopping cart
 *   listings.
 * @path /shopping/admin/carts
 * @accessor api.functional.shopping.admin.carts.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Filter and pagination information for shopping cart listings. */
    body: IShoppingCart.IRequest;
  };
  export type Body = IShoppingCart.IRequest;
  export type Response = IPageIShoppingCart.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/admin/carts",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shopping/admin/carts";
  export const random = (): IPageIShoppingCart.ISummary =>
    typia.random<IPageIShoppingCart.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Retrieve the detailed contents and context of a single shopping cart by its
 * ID (shopping_carts table).
 *
 * This endpoint provides the complete state of a particular customer's shopping
 * cart, addressing both functional requirements for customer self-management
 * and administrative review needs.
 *
 * The API accepts a unique cartId in the path, which must be a valid UUID as
 * defined in the shopping_carts model. The response includes detailed cart
 * content: all associated cart items (with SKU references, quantities, and
 * item-level timestamps), customer linkage, and key activity milestones. This
 * comprehensive view is essential for client-side representations for order
 * review, customer support investigations, or fulfillment systems that need to
 * convert cart contents to orders.
 *
 * Security restrictions require appropriate actor privileges: typically
 * authenticated admin or platform operators for global access—normal customers
 * would access their own cart through a separate self-context endpoint. Input
 * validation ensures the cartId is correctly formatted, and robust error
 * handling covers non-existent or unauthorized access scenarios. The design
 * aligns with operational best practices and compliance expectations for data
 * access.
 *
 * @param props.connection
 * @param props.cartId Unique identifier of the target shopping cart (UUID
 *   format, references shopping_carts.id).
 * @path /shopping/admin/carts/:cartId
 * @accessor api.functional.shopping.admin.carts.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target shopping cart (UUID format,
     * references shopping_carts.id).
     */
    cartId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingCart;

  export const METADATA = {
    method: "GET",
    path: "/shopping/admin/carts/:cartId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shopping/admin/carts/${encodeURIComponent(props.cartId ?? "null")}`;
  export const random = (): IShoppingCart => typia.random<IShoppingCart>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("cartId")(() => typia.assert(props.cartId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
