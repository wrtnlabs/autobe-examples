import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingCustomerSession } from "../../../../../structures/IShoppingCustomerSession";
import { IPageIShoppingCustomerSession } from "../../../../../structures/IPageIShoppingCustomerSession";

/**
 * Retrieve and search sessions for a specific customer account
 * (shopping_customer_sessions table).
 *
 * Retrieve a paginated and filterable list of session records for a specific
 * customer. This API enables customers to view all login sessions—including
 * concurrent and historical sessions—along with device, network, and timestamp
 * metadata. The customerId parameter identifies which customer's sessions to
 * access, ensuring that only sessions related to the authenticated account are
 * returned.
 *
 * The operation allows advanced search by session creation/expiration
 * timestamp, client IP, device type, and referrer fields. expired_at/null
 * distinction enables filtering between active and past sessions. Sensitive
 * information about session origin and network is available only to the account
 * owner or appropriate administrators. This API integrates with the
 * shopping_customer_sessions table, following all account privacy and audit
 * requirements, and supports compliance with session viewing and security best
 * practices.
 *
 * Authorization checks ensure only the owning customer or authorized admin
 * actors can view session listings. The operation aids account management,
 * device security awareness, and compliance with privacy requirements for
 * access logs. Related APIs include device logout or session revocation
 * endpoints, which can be combined for comprehensive session management
 * functionality.
 *
 * @param props.connection
 * @param props.customerId Unique identifier of the target customer
 * @param props.body Filter, pagination, and search parameters for retrieving
 *   sessions of a customer
 * @path /shopping/admin/customers/:customerId/sessions
 * @accessor api.functional.shopping.admin.customers.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target customer */
    customerId: string & tags.Format<"uuid">;

    /**
     * Filter, pagination, and search parameters for retrieving sessions of
     * a customer
     */
    body: IShoppingCustomerSession.IRequest;
  };
  export type Body = IShoppingCustomerSession.IRequest;
  export type Response = IPageIShoppingCustomerSession;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/admin/customers/:customerId/sessions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shopping/admin/customers/${encodeURIComponent(props.customerId ?? "null")}/sessions`;
  export const random = (): IPageIShoppingCustomerSession =>
    typia.random<IPageIShoppingCustomerSession>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("customerId")(() => typia.assert(props.customerId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
