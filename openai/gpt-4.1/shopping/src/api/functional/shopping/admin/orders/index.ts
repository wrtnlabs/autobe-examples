/**
 * Retrieve details of a specific order using its unique order code
 * (shopping_orders).
 *
 * This endpoint enables authorized actors (customer, seller, or admin,
 * depending on context) to retrieve all information for a specific order based
 * on its unique business order code. The response includes the complete order
 * entity and related data as per the Prisma schema—specifically, information on
 * order lines, splits (for orders with multiple sellers), payment attempts,
 * fulfillment/shipment status, and all historical status transitions.
 *
 * The API uses strict access control: a customer may only request their own
 * orders, a seller may only see orders for products they own, and admins may
 * access any order in the system. Security checks are performed at the
 * application layer based on actor type and order ownership, with forbidden
 * access for unauthorized requests.
 *
 * The path parameter orderCode corresponds to the order_code column in
 * shopping_orders, which is globally unique and human-readable (e.g.,
 * ORD-20240001). When the specified code is not found, a clear error is
 * returned. The endpoint is intended for use in account order history, order
 * tracking, and customer support contexts. Associated data (order lines,
 * splits, addresses, payment attempts, shipments, etc.) is included using
 * Prisma's relationships and the response type IShoppingOrder.
 *
 * @param props.connection
 * @param props.orderCode Globally unique business order code of the target
 *   order (global scope), e.g., ORD-20240001.
 * @path /shopping/admin/orders/:orderCode
 * @accessor api.functional.shopping.admin.orders.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Globally unique business order code of the target order (global
     * scope), e.g., ORD-20240001.
     */
    orderCode: string;
  };
  export type Response = IShoppingOrder;

  export const METADATA = {
    method: "GET",
    path: "/shopping/admin/orders/:orderCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shopping/admin/orders/${encodeURIComponent(props.orderCode ?? "null")}`;
  export const random = (): IShoppingOrder => typia.random<IShoppingOrder>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderCode")(() => typia.assert(props.orderCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

