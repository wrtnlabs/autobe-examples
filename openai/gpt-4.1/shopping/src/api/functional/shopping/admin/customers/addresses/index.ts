import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingCustomerAddress } from "../../../../../structures/IShoppingCustomerAddress";
import { IPageIShoppingCustomerAddress } from "../../../../../structures/IPageIShoppingCustomerAddress";

/**
 * Retrieve all delivery addresses for a given customer
 * (shopping_customer_addresses).
 *
 * This endpoint retrieves all shipping and billing addresses associated with a
 * specified customer account. It operates on the shopping_customer_addresses
 * table, returning current and historical address book entries for the given
 * customerId. The customerId provided in the path is a UUID that uniquely
 * identifies the user whose addresses will be fetched.
 *
 * The operation supports filtering for primary/default addresses and returns
 * sufficient address data for presentation in address selection, editing, or
 * deletion screens. For authorized actors (customer viewing their own
 * addresses, or admin performing account reviews or assistance), this endpoint
 * enables comprehensive address management. Security requirements dictate that
 * only the account owner or platform administrator may access this data. Error
 * handling includes cases where the specified customer does not exist or has no
 * associated addresses, returning an empty list where appropriate.
 *
 * Pagination, sorting, and inclusion of soft-deleted (deleted_at is not null)
 * addresses may be implemented via request body (extendable in the DTO), but at
 * minimum, the full unpaginated list is returned for this base operation.
 *
 * @param props.connection
 * @param props.customerId Unique identifier of the target customer whose
 *   address book is being fetched
 * @param props.body Request parameters for filtering, pagination, or sorting of
 *   customer addresses (may be null for basic list).
 * @path /shopping/admin/customers/:customerId/addresses
 * @accessor api.functional.shopping.admin.customers.addresses.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target customer whose address book is being
     * fetched
     */
    customerId: string & tags.Format<"uuid">;

    /**
     * Request parameters for filtering, pagination, or sorting of customer
     * addresses (may be null for basic list).
     */
    body: IShoppingCustomerAddress.IRequest;
  };
  export type Body = IShoppingCustomerAddress.IRequest;
  export type Response = IPageIShoppingCustomerAddress;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/admin/customers/:customerId/addresses",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shopping/admin/customers/${encodeURIComponent(props.customerId ?? "null")}/addresses`;
  export const random = (): IPageIShoppingCustomerAddress =>
    typia.random<IPageIShoppingCustomerAddress>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("customerId")(() => typia.assert(props.customerId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
