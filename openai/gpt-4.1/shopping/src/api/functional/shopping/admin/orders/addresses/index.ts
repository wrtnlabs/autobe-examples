/**
 * List all shipping and billing addresses associated with a given order.
 *
 * This API operation provides a comprehensive paginated list of all address
 * records related to the specified order, as stored in the
 * shopping_order_addresses table. The endpoint supports detailed querying so
 * actors can filter addresses by type (shipping, billing), search by recipient
 * name, or paginate through the addresses if an order includes multiple address
 * entries (for instance, split shipments or gifts).
 *
 * This operation is essential for reconciliation of order fulfillment, auditing
 * customer-provided addresses, and troubleshooting delivery issues. Permissions
 * should restrict this table to authenticated customers for their own orders,
 * relevant sellers, and platform admins. Related API operations include general
 * order detail endpoints and shipment tracking endpoints. The implementation
 * relies on accurate mapping of orderCode (globally unique human-readable order
 * reference) to its order addresses, with validation and safe error handling
 * for missing or unauthorized access.
 *
 * The operation integrates database pagination and search best practices and is
 * built to include future filtering extensions as needed (such as address type
 * or recipient search).
 *
 * @param props.connection
 * @param props.orderCode Globally unique identifier code for the target order
 *   (human-readable, global scope).
 * @param props.body Request parameters allowing address search, filtering (by
 *   type or recipient), and pagination options.
 * @path /shopping/admin/orders/:orderCode/addresses
 * @accessor api.functional.shopping.admin.orders.addresses.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Globally unique identifier code for the target order (human-readable,
     * global scope).
     */
    orderCode: string;

    /**
     * Request parameters allowing address search, filtering (by type or
     * recipient), and pagination options.
     */
    body: IShoppingOrderAddress.IRequest;
  };
  export type Body = IShoppingOrderAddress.IRequest;
  export type Response = IPageIShoppingOrderAddress.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/admin/orders/:orderCode/addresses",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shopping/admin/orders/${encodeURIComponent(props.orderCode ?? "null")}/addresses`;
  export const random = (): IPageIShoppingOrderAddress.ISummary =>
    typia.random<IPageIShoppingOrderAddress.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderCode")(() => typia.assert(props.orderCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

