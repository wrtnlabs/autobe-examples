/**
 * Create a new product in the shopping_products table for the catalog.
 *
 * This API endpoint is designed for sellers (and platform admins) to create a
 * new product entry in the catalog. The process requires the submission of all
 * required fields, including product code, name, description, main image URI,
 * current status, and business status. The request will be validated against
 * the business catalog requirements, ensuring all mandatory data is present and
 * the business code is unique.
 *
 * Upon successful creation, the product is registered under the requesting
 * seller's account, attached to a specific catalog, and prepared for linking
 * with SKUs and attributes. Business and workflow status control visibility, so
 * a draft or under_review product will not be publicly visible until approved
 * and published. Attempts to create a product with a duplicate code or missing
 * vital details will result in a validation error, and comprehensive error
 * messages will be provided based on the rule violated.
 *
 * Security measures enforce that only authenticated sellers or admins may
 * invoke this operation, and all actions are auditable for compliance. The
 * created product will be available for management through subsequent endpoints
 * handling images, variants/SKUs, category assignments, and publishing
 * workflows.
 *
 * @param props.connection
 * @param props.body Detailed product creation payload as required by catalog
 *   business rules.
 * @path /shopping/admin/products
 * @accessor api.functional.shopping.admin.products.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
