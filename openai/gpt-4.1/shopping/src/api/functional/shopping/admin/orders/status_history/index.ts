/**
 * Retrieve a filtered, paginated list of status change histories for a specific
 * order by order_code.
 *
 * This operation allows authorized users (admin, seller for their orders, or
 * customer for their own order) to retrieve a paginated list of all status
 * change events for a designated order from shopping_order_status_histories.
 * The endpoint expects the unique order_code as a path parameter, resolves the
 * corresponding order in shopping_orders, and then performs a joined query on
 * shopping_order_status_histories to collect all transitions, including their
 * timestamps, actors, from_status, to_status, and optional event notes.
 *
 * Filtering parameters in the request body enable advanced search—for example,
 * by specific status transitions, triggering actor, or a date/time window. The
 * response contains paginated status history entries which are useful for
 * customer transparency, seller operational review, or administrative audit.
 * Access is gated so that customers only retrieve their own order histories,
 * sellers only see those tied to their products, and admins may access any
 * order's status transitions. Edge cases and error handling are present: if the
 * order_code does not exist, or the requester lacks permission, a detailed
 * business error is returned.
 *
 * @param props.connection
 * @param props.orderCode Unique business identifier code of the target order
 *   (global scope)
 * @param props.body Filtering, sorting, and pagination request for order status
 *   histories.
 * @path /shopping/admin/orders/:orderCode/status-history
 * @accessor api.functional.shopping.admin.orders.status_history.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
