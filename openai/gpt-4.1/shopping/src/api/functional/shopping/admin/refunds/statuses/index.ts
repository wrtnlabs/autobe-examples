/**
 * Retrieve the paginated status history for a refund request
 * (shopping_refund_status_histories).
 *
 * Retrieves the chronological list of all status changes applied to a specific
 * refund request. This includes every state transition, the actor who performed
 * it (customer, seller, admin), timestamp, and any attached context or notes.
 * Enables compliance and support teams to review the full workflow of a
 * refund/return/cancellation case.
 *
 * The operation supports advanced filtering by actor type, specific statuses,
 * and date ranges when supplied in the request body. Pagination parameters
 * allow results to be batched and sorted for efficient navigation in case of
 * extensive audit trails. Consumers of this endpoint typically include admins
 * reviewing compliance, sellers overseeing requests involving their
 * products/orders, and customers tracking the lifecycle of their refund
 * claims.
 *
 * The input refundRequestId must identify an existing refund request, and the
 * caller must be authorized for the underlying business context. Any status
 * history found is returned in order from oldest to newest unless sorting
 * options are specified. Error responses occur if the request does not exist,
 * or if the actor lacks permission to view the refund's history.
 *
 * @param props.connection
 * @param props.refundRequestId Unique identifier of the target refund request
 *   to retrieve its status history (UUID format, global scope).
 * @param props.body Criteria for filtering, sorting, and paginating the list of
 *   refund status histories. This may include actor type, specific status
 *   transitions, date ranges, and sort order.
 * @path /shopping/admin/refunds/:refundRequestId/statuses
 * @accessor api.functional.shopping.admin.refunds.statuses.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target refund request to retrieve its status
     * history (UUID format, global scope).
     */
    refundRequestId: string & tags.Format<"uuid">;

    /**
     * Criteria for filtering, sorting, and paginating the list of refund
     * status histories. This may include actor type, specific status
     * transitions, date ranges, and sort order.
     */
    body: IShoppingRefundStatusHistory.IRequest;
  };
  export type Body = IShoppingRefundStatusHistory.IRequest;
  export type Response = IPageIShoppingRefundStatusHistory;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/admin/refunds/:refundRequestId/statuses",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shopping/admin/refunds/${encodeURIComponent(props.refundRequestId ?? "null")}/statuses`;
  export const random = (): IPageIShoppingRefundStatusHistory =>
    typia.random<IPageIShoppingRefundStatusHistory>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("refundRequestId")(() =>
        typia.assert(props.refundRequestId),
      );
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

