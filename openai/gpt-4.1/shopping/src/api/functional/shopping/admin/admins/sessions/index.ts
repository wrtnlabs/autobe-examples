/**
 * Retrieve a paginated, filterable list of admin session records
 * (shopping_admin_sessions).
 *
 * This API allows privileged administrators to search, filter, and paginate
 * through all recorded session instances for a given admin account, using the
 * requested adminId (UUID) as path parameter. Session data includes creation
 * and expiration times, originating IP addresses, login URLs, and referrers,
 * directly referencing shopping_admin_sessions and connected to shopping_admins
 * via shopping_admin_id.
 *
 * Designed for security monitoring, compliance, and audit, this operation
 * supports advanced query criteria—including session status (active/expired),
 * date intervals, IP/address search, and ordering by login/expiration
 * time—using parameters defined in IShoppingAdminSession.IRequest. Only
 * operators with sufficient privileges may query admin session logs; this helps
 * identify unusual login activity, enforce session revocation, or review system
 * access history for incident response.
 *
 * All activity via this endpoint must itself be audit-logged. The endpoint may
 * require additional access control to restrict which actors can monitor
 * sessions for given admin IDs (for example, super-admins viewing others). If
 * the specified adminId does not exist, an appropriate error response must be
 * returned. Pagination and sorting logic enables efficient management of large
 * session datasets for compliance and operational reviews.
 *
 * @param props.connection
 * @param props.adminId Unique identifier (UUID) of the administrator whose
 *   session records are being retrieved. This must match the shopping_admins.id
 *   field and is required for filtering results.
 * @param props.body Filtering, query, and pagination criteria for searching
 *   admin session records, structured according to
 *   IShoppingAdminSession.IRequest DTO. Includes filters for session status,
 *   IP, login/expiration time, and result limits.
 * @path /shopping/admin/admins/:adminId/sessions
 * @accessor api.functional.shopping.admin.admins.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier (UUID) of the administrator whose session records
     * are being retrieved. This must match the shopping_admins.id field and
     * is required for filtering results.
     */
    adminId: string & tags.Format<"uuid">;

    /**
     * Filtering, query, and pagination criteria for searching admin session
     * records, structured according to IShoppingAdminSession.IRequest DTO.
     * Includes filters for session status, IP, login/expiration time, and
     * result limits.
     */
    body: IShoppingAdminSession.IRequest;
  };
  export type Body = IShoppingAdminSession.IRequest;
  export type Response = IPageIShoppingAdminSession.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/admin/admins/:adminId/sessions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shopping/admin/admins/${encodeURIComponent(props.adminId ?? "null")}/sessions`;
  export const random = (): IPageIShoppingAdminSession.ISummary =>
    typia.random<IPageIShoppingAdminSession.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("adminId")(() => typia.assert(props.adminId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
