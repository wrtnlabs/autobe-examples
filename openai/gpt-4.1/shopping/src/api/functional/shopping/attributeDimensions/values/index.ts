import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingAttributeValue } from "../../../../structures/IShoppingAttributeValue";

/**
 * Retrieve an attribute value's details by dimension code and value code from
 * the Prisma schema.
 *
 * Retrieve the details of an attribute value associated with a given attribute
 * dimension. The API first verifies the existence of the attribute dimension,
 * identified by its globally unique dimension code. If found, it then searches
 * for the attribute value by valueCode within that dimension (scoped unique
 * constraint). The response will include all essential fields for the attribute
 * value (value code, display value, display order, etc.), referencing the
 * associated attribute dimension in the Prisma schema.
 *
 * In the context of catalog and variant management, this endpoint allows
 * systems to display variant options, support dynamic product configuration
 * UIs, and enforce attribute integrity. The operation provides robust error
 * handling for non-existent codes, and ensures returned data matches the
 * business and catalog state. Only publicly visible, non-deleted attribute
 * values are returned.
 *
 * Access to this endpoint should be open to all actors (including
 * public/unauthenticated) since attribute metadata is critical for catalog
 * search, product listing, and variant detail exposure. Logical use cases
 * include faceted product filtering, variant structure display, and integration
 * with product onboarding workflows.
 *
 * @param props.connection
 * @param props.dimensionCode Unique business code for the attribute dimension
 *   (global scope).
 * @param props.valueCode Unique code for the attribute value within the
 *   specified dimension (scoped to attribute dimension).
 * @path /shopping/attributeDimensions/:dimensionCode/values/:valueCode
 * @accessor api.functional.shopping.attributeDimensions.values.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique business code for the attribute dimension (global scope). */
    dimensionCode: string;

    /**
     * Unique code for the attribute value within the specified dimension
     * (scoped to attribute dimension).
     */
    valueCode: string;
  };
  export type Response = IShoppingAttributeValue;

  export const METADATA = {
    method: "GET",
    path: "/shopping/attributeDimensions/:dimensionCode/values/:valueCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shopping/attributeDimensions/${encodeURIComponent(props.dimensionCode ?? "null")}/values/${encodeURIComponent(props.valueCode ?? "null")}`;
  export const random = (): IShoppingAttributeValue =>
    typia.random<IShoppingAttributeValue>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("dimensionCode")(() => typia.assert(props.dimensionCode));
      assert.param("valueCode")(() => typia.assert(props.valueCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
