import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingCategory } from "../../../../structures/IShoppingCategory";

/**
 * Retrieve a specific shopping category within a category tree by code.
 *
 * This endpoint returns complete details for a single shopping category node
 * (as defined in shopping_categories), precisely identified by the combination
 * of category tree code (from shopping_category_trees) and category code
 * (unique within tree). The composite key construction guarantees no ambiguity,
 * supporting deep tree structures and multi-taxonomy catalog environments.
 *
 * Security context: This API is safe for public or authenticated access as it
 * only reads (never creates, updates, or deletes) the specific category node.
 * When used by admins or sellers for management, additional relational metadata
 * may be exposed. When accessed for public navigation, only core fields
 * (category_code, category_name, description, parent, path, etc.) are
 * returned.
 *
 * Careful validation is enforced: A missing or invalid category code or tree
 * code returns a structured error. The query is always performed over active
 * (non soft-deleted) categories and trees. If the target node is a leaf,
 * downstream product assignment in the UI is enabled; if not, clients may fetch
 * child nodes for tree navigation. Related endpoints for children or parent
 * traversal are recommended to enhance typical e-commerce UX.
 *
 * @param props.connection
 * @param props.treeCode Unique tree code of the target category tree (global
 *   scope)
 * @param props.categoryCode Unique code of the target category within the tree
 *   (scoped to tree)
 * @path /shopping/categoryTrees/:treeCode/categories/:categoryCode
 * @accessor api.functional.shopping.categoryTrees.categories.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique tree code of the target category tree (global scope) */
    treeCode: string;

    /** Unique code of the target category within the tree (scoped to tree) */
    categoryCode: string;
  };
  export type Response = IShoppingCategory;

  export const METADATA = {
    method: "GET",
    path: "/shopping/categoryTrees/:treeCode/categories/:categoryCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shopping/categoryTrees/${encodeURIComponent(props.treeCode ?? "null")}/categories/${encodeURIComponent(props.categoryCode ?? "null")}`;
  export const random = (): IShoppingCategory =>
    typia.random<IShoppingCategory>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("treeCode")(() => typia.assert(props.treeCode));
      assert.param("categoryCode")(() => typia.assert(props.categoryCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
