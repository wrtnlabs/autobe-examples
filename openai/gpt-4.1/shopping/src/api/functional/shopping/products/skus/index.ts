import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingSku } from "../../../../structures/IShoppingSku";

/**
 * Retrieve detailed information of a specific SKU by product and SKU code.
 *
 * This API operation returns the complete detail for a SKU (Stock Keeping Unit)
 * under a given product, as identified by their unique business codes. The
 * operation leverages the unique constraint on shopping_products.code (global
 * scope) and shopping_skus.sku_code (global scope) to ensure unambiguous
 * results. The resulting response includes all SKU variant attributes, retail
 * price, is_active flag, barcode, business status, and full audit timestamps,
 * as well as a reference to its parent product for secondary context.
 *
 * The endpoint is useful for customers, sellers, and admins for confirming SKU
 * availability, reviewing variant options, and supporting add-to-cart
 * validation flows. Access is public, but for inactive or archived SKUs (status
 * logic enforced by the business), the API may return either a filtered view or
 * a not found error as appropriate. All relationship and attribute field values
 * come directly from the shopping_skus table and its related entities as
 * defined in the schema. No request body is required; all identification is
 * path-based.
 *
 * Advanced error handling is in place for non-existent, deleted, or
 * permission-restricted SKUs, returning appropriately detailed not-found errors
 * or permission denied messages. This operation is often used in the context of
 * product page rendering, checkout workflows, or administrative SKU review.
 *
 * @param props.connection
 * @param props.productCode Unique business identifier code of the target
 *   product (global scope)
 * @param props.skuCode Unique business identifier code of the target SKU
 *   (global scope)
 * @path /shopping/products/:productCode/skus/:skuCode
 * @accessor api.functional.shopping.products.skus.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique business identifier code of the target product (global scope) */
    productCode: string;

    /** Unique business identifier code of the target SKU (global scope) */
    skuCode: string;
  };
  export type Response = IShoppingSku;

  export const METADATA = {
    method: "GET",
    path: "/shopping/products/:productCode/skus/:skuCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shopping/products/${encodeURIComponent(props.productCode ?? "null")}/skus/${encodeURIComponent(props.skuCode ?? "null")}`;
  export const random = (): IShoppingSku => typia.random<IShoppingSku>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productCode")(() => typia.assert(props.productCode));
      assert.param("skuCode")(() => typia.assert(props.skuCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
