import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingReviewRatingAggregate } from "../../../../structures/IShoppingReviewRatingAggregate";

/**
 * Get aggregate review/rating statistics for a specific product by unique
 * productId from materialized review aggregates.
 *
 * Retrieve pre-computed aggregate review statistics (such as total reviews and
 * average rating) for a product, identified by its unique productId. These
 * aggregate statistics are generated by the shopping_review_rating_aggregates
 * view, which is associated with the shopping_products table and provides
 * summary information for product and SKU level ratings.
 *
 * This API endpoint is designed to optimize catalog and product page
 * performance by delivering immediate access to pre-aggregated rating metrics,
 * such as number of reviews and the average rating for the overall product and
 * each of its SKUs. It does not include detailed review content or author
 * information, ensuring privacy and reducing data volume for client
 * applications.
 *
 * Internally, this endpoint cross-references the requested productId with the
 * shopping_products table to verify existence, and then queries the review
 * aggregates for that product. All metrics are derived directly from the
 * shopping_review_rating_aggregates model as defined in the Prisma schema,
 * including product-level and per-SKU review statistics.
 *
 * No authentication is required for this endpoint, as rating information is
 * public and intended for use across the catalog and product listing pages.
 * Error conditions, such as a missing or invalid productId, return standard not
 * found or validation errors as per platform conventions.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the product whose review
 *   aggregates are requested. This must match the id field (UUID) in the
 *   shopping_products table.
 * @path /shopping/products/:productId/reviewAggregates
 * @accessor api.functional.shopping.products.reviewAggregates.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the product whose review aggregates are
     * requested. This must match the id field (UUID) in the
     * shopping_products table.
     */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingReviewRatingAggregate;

  export const METADATA = {
    method: "GET",
    path: "/shopping/products/:productId/reviewAggregates",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shopping/products/${encodeURIComponent(props.productId ?? "null")}/reviewAggregates`;
  export const random = (): IShoppingReviewRatingAggregate =>
    typia.random<IShoppingReviewRatingAggregate>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
