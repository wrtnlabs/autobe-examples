/**
 * Retrieve and search product images for a specific product using business
 * code.
 *
 * Retrieve a filtered and paginated list of all images associated with a
 * specific product by product business code. This endpoint enables clients to
 * request product images with additional filter/query options such as order,
 * partial file URI match, or other business-specific attributes for the image
 * entity. It will take into account that productCode is globally unique (as
 * ensured by the Prisma @@unique([code]) constraint on shopping_products), and
 * so only the correct product's images are returned.
 *
 * Security and access is primarily controlled at the product level, with public
 * users typically only seeing images for published/active products. Sellers and
 * admins may access images for unpublished, draft, or archived products,
 * pending authorization checks. The endpoint is read-only and does not provide
 * upload or modification capabilities. Pagination parameters and result format
 * follow standard platform conventions and return paginated objects, with each
 * image including full file URI, upload timestamp, and display order if
 * available.
 *
 * If the productCode is not found or refers to an archived/deleted product, the
 * endpoint will return an appropriate error to prevent information leakage.
 * Related endpoints for product detail queries or image upload/delete may be
 * combined for advanced client workflows.
 *
 * @param props.connection
 * @param props.productCode Unique business identifier code of the target
 *   product (global scope)
 * @param props.body Search and pagination criteria for filtering product images
 *   under the chosen product
 * @path /shopping/products/:productCode/images
 * @accessor api.functional.shopping.products.images.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique business identifier code of the target product (global scope) */
    productCode: string;

    /**
     * Search and pagination criteria for filtering product images under the
     * chosen product
     */
    body: IShoppingProductImage.IRequest;
  };
  export type Body = IShoppingProductImage.IRequest;
  export type Response = IPageIShoppingProductImage;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/products/:productCode/images",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shopping/products/${encodeURIComponent(props.productCode ?? "null")}/images`;
  export const random = (): IPageIShoppingProductImage =>
    typia.random<IPageIShoppingProductImage>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productCode")(() => typia.assert(props.productCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

