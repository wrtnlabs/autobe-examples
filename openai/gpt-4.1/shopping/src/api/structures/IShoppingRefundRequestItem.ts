  item_business_reason?: string | null | undefined;

  /** Timestamp when the refund item request was created (ISO 8601, UTC). */
  created_at: string & tags.Format<"date-time">;

  /** Timestamp for last modification of this item (ISO 8601, UTC). */
  updated_at: string & tags.Format<"date-time">;

