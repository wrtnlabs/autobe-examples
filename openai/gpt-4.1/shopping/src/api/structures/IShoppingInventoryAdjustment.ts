/**
 * Represents an atomic adjustment to the inventory of a specific SKU in the
 * shopping mall system. Each adjustment records a before/after state, the
 * change in quantity, the actor performing the change, the business reason
 * behind the adjustment (such as manual restock, order, refund, anomaly, or
 * system correction), and an immutable timestamp. This schema is crucial for
 * audit compliance, operational traceability, and fraud prevention. It follows
 * a strict append-only ledger model: every inventory event (increase, decrease,
 * or administrative correction) must be recorded using this schema to support
 * real-time stock status and historical analysis.
 *
 * Related Prisma model: shopping_inventory_adjustments. Every property here
 * corresponds to a field in that model, and is fully documented for audit,
 * compliance, and analytics.
 *
 * This object is used as the response from inventory adjustment creation APIs
 * and for system-level reporting/business dashboards.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingInventoryAdjustment = {
  /**
   * Primary key (UUID) for this adjustment record. Used for referencing this
   * immutable log entry.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Reference to the precise inventory record being adjusted
   * (shopping_inventory.id), which is always linked to a unique SKU. Required
   * for cross-checking aggregate stock with ledger history.
   */
  shopping_inventory_id: string & tags.Format<"uuid">;

  /**
   * Unique ID for the SKU entity (shopping_skus.id) to which this adjustment
   * applies. Direct mapping to the SKU whose stock is changing.
   */
  shopping_sku_id: string & tags.Format<"uuid">;

  /**
   * Polymorphic string to record the actor class performing the adjustment
   * (e.g., 'customer', 'seller', 'admin', or 'system'). Used for audit,
   * permission enforcement, and analytics.
   */
  actor_type: string;

  /**
   * UUID of the involved actor (user/admin/seller/system). No foreign key:
   * stored as a simple UUID for immutable audit history. This enables tracing
   * all inventory events to an accountable entity across all actor types.
   */
  actor_id: string & tags.Format<"uuid">;

  /**
   * Business code describing why this adjustment occurred (e.g., 'order',
   * 'refund', 'manual', 'restock', 'correction'). Used for analytics, audit,
   * and operational business rules.
   */
  reason_code: string;

  /**
   * The stock value (units) prior to this adjustment. Enables precise tracing
   * and rollback analysis.
   */
  quantity_before: number & tags.Type<"int32">;

  /**
   * Post-adjustment stock value after this event was applied. Used for
   * consistency, business validation, and fast lookup.
   */
  quantity_after: number & tags.Type<"int32">;

  /**
   * The difference applied to the inventory: quantity_after = quantity_before
   * + adjustment_amount. Can be positive (restock), negative (sale/return),
   * or zero (correction/anomaly/no-op).
   */
  adjustment_amount: number & tags.Type<"int32">;

  /**
   * Optional freeform context/note for this adjustment (such as manual
   * restock batch label, order ID, administrator comment, anomaly fix, etc.).
   * Used for additional traceability. Nullable.
   */
  context_note?: string | null | undefined;

  /**
   * UTC timestamp of when the adjustment was recorded (immutable, set by
   * system at creation).
   */
  created_at: string & tags.Format<"date-time">;
};
