import { ArrayUtil, RandomGenerator, TestValidator } from "@nestia/e2e";
import { IConnection } from "@nestia/fetcher";
import typia, { tags } from "typia";

import api from "@ORGANIZATION/PROJECT-api";
import type { IAuthorizationToken } from "@ORGANIZATION/PROJECT-api/lib/structures/IAuthorizationToken";
import type { IShoppingMallAddress } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallAddress";
import type { IShoppingMallAdmin } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallAdmin";
import type { IShoppingMallCustomer } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallCustomer";
import type { IShoppingMallOrder } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallOrder";
import type { IShoppingMallOrderAuditLog } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallOrderAuditLog";
import type { IShoppingMallSeller } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallSeller";

/**
 * Seller successfully retrieves an audit log record for their order, with
 * proper access control validation.
 */
export async function test_api_seller_order_auditlog_retrieval(
  connection: api.IConnection,
) {
  // 1. Register seller
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = typia.random<
    string & tags.Format<"password"> & tags.MinLength<8>
  >();
  const sellerBusinessName = RandomGenerator.name();
  const registrationNumber = RandomGenerator.alphaNumeric(12);
  const businessPhone = RandomGenerator.mobile();
  const href = "https://shop.com/seller/register";
  const referrer = "https://shop.com/landing";

  const sellerAuth = await api.functional.auth.seller.join(connection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      business_name: sellerBusinessName,
      registration_number: registrationNumber,
      business_phone: businessPhone,
      href,
      referrer,
    },
  });
  typia.assert(sellerAuth);

  // 2. Register customer
  const customerEmail = typia.random<string & tags.Format<"email">>();
  const customerPassword = typia.random<
    string & tags.Format<"password"> & tags.MinLength<8>
  >();
  const customerName = RandomGenerator.name();
  const customerPhone = RandomGenerator.mobile();

  const customerAuth = await api.functional.auth.customer.join(connection, {
    body: {
      email: customerEmail,
      password: customerPassword,
      name: customerName,
      phone: customerPhone,
    },
  });
  typia.assert(customerAuth);

  // 3. Customer login (switch to customer)
  await api.functional.auth.customer.login(connection, {
    body: {
      email: customerEmail,
      password: customerPassword,
      href: "https://shop.com/customer/dashboard",
      referrer: "https://shop.com/landing",
    },
  });

  // 4. Create a shipping address for customer (simulated, fake address for test)
  // Use random UUID for address id as foreign keys/relations are handled in order API in test, not address table
  const address: IShoppingMallAddress.ISummary = {
    id: typia.random<string & tags.Format<"uuid">>(),
    full_name: customerName,
    street: RandomGenerator.paragraph(),
    city: RandomGenerator.name(1),
    province: RandomGenerator.name(1),
    postal_code: RandomGenerator.alphaNumeric(6),
    country: "Korea",
    phone: customerPhone,
    is_default: true,
  };

  // 5. Customer creates order (for seller)
  const orderNumber = RandomGenerator.alphaNumeric(12);
  const currency = RandomGenerator.pick(["KRW", "USD"] as const);
  const totalAmount = 10000;
  const orderStatus = "pending";
  const order = await api.functional.shoppingMall.customer.orders.create(
    connection,
    {
      body: {
        order_number: orderNumber,
        shopping_mall_customer_id: customerAuth.id,
        shopping_mall_address_id: address.id,
        shopping_mall_seller_id: sellerAuth.id,
        status: orderStatus,
        total_amount: totalAmount,
        currency: currency,
      },
    },
  );
  typia.assert(order);

  // 6. (Assume audit logs are generated by order creation. Simulate fetching a valid audit log via random values for test)
  // Audit log API requires order_number and auditLogId.
  // We'll simulate an existing log record relating to the customer placing the order.

  // In reality, you would use audit log index/search, but only auditLogs.at is available. We'll synthesize an auditLogId.
  // For the test, use a random UUID as a stub for a real auditLogId.
  // Test both positive (seller with proper linkage) and negative (unrelated seller gets denied) access.
  const auditLogId = typia.random<string & tags.Format<"uuid">>();

  // 7. Switch to seller (to use seller permissions)
  await api.functional.auth.seller.login(connection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      href: "https://shop.com/seller/dashboard",
      referrer: "https://shop.com/landing",
    },
  });

  // 8. Fetch audit log as the responsible seller
  const auditLog = await api.functional.shoppingMall.seller.orders.auditLogs.at(
    connection,
    {
      orderNumber,
      auditLogId,
    },
  );
  typia.assert(auditLog);
  TestValidator.equals(
    "audit log belongs to the correct order",
    auditLog.order.order_number,
    orderNumber,
  );
  TestValidator.equals("audit log id matches", auditLog.id, auditLogId);
  TestValidator.equals(
    "seller correctly linked in audit log",
    auditLog.seller?.id,
    sellerAuth.id,
  );

  // 9. Negative test: unrelated seller cannot access audit log
  // Register another seller
  const otherSellerEmail = typia.random<string & tags.Format<"email">>();
  const otherSellerPassword = typia.random<
    string & tags.Format<"password"> & tags.MinLength<8>
  >();
  const otherSellerBusinessName = RandomGenerator.name();
  const otherSellerRegistrationNumber = RandomGenerator.alphaNumeric(12);
  const otherSellerBusinessPhone = RandomGenerator.mobile();

  await api.functional.auth.seller.join(connection, {
    body: {
      email: otherSellerEmail,
      password: otherSellerPassword,
      business_name: otherSellerBusinessName,
      registration_number: otherSellerRegistrationNumber,
      business_phone: otherSellerBusinessPhone,
      href: "https://shop.com/seller/register",
      referrer: "https://shop.com/landing",
    },
  });

  // Login as the unrelated seller
  await api.functional.auth.seller.login(connection, {
    body: {
      email: otherSellerEmail,
      password: otherSellerPassword,
      href: "https://shop.com/seller/dashboard",
      referrer: "https://shop.com/landing",
    },
  });

  // Expect error when unrelated seller fetches audit log
  await TestValidator.error(
    "unrelated seller denied access to audit log",
    async () => {
      await api.functional.shoppingMall.seller.orders.auditLogs.at(connection, {
        orderNumber,
        auditLogId,
      });
    },
  );
}
