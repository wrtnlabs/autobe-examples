/**
 * Register a new admin account within the discussion_board_admins table and
 * issue the initial JWT tokens.
 *
 * This POST endpoint enables new administrator registration on the discussion
 * board platform by inserting a record in the 'discussion_board_admins' table.
 * The schema requires an email, a plaintext password (which is then securely
 * hashed), display_name, and allows an optional avatar_url string field. On
 * account creation, is_locked must be set to false and deleted_at must be null,
 * while created_at/updated_at timestamps are set automatically. All email
 * addresses must be unique, enforced by the @@unique constraint. If
 * registration attempts use a duplicate email, the request is rejected with a
 * descriptive error referencing the relevant unique index. The admin profile is
 * created with only fields explicitly defined in the schema, aligning with
 * privacy compliance and security requirements. This operation is for
 * privileged actors: endpoints MUST be locked down and typically disabled in
 * production to prevent arbitrary admin creation. Responses return the full
 * details of the newly registered admin, only from fields present in the
 * schema, plus the issued tokens in accordance with JWT practices. Related
 * endpoints: login and refresh must be used for subsequent auth/session flows.
 * The 'deleted_at' field supports future soft deletion and compliance cases but
 * is always null at creation time. Passwords are never returned in responses or
 * logs. This operation must be paired with login/database existence checks
 * before registering an admin with the same email, supporting both business
 * integrity and schema robusteness.
 *
 * @param props.connection
 * @param props.body Admin registration details (email, password, display_name,
 *   optional avatar_url) as required by discussion_board_admins schema. Only
 *   explicitly present fields accepted.
 * @setHeader token.access Authorization
 *
 * @path /auth/admin/join
 * @accessor api.functional.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
