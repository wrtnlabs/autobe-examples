/**
 * Creates a new administrator in the discussion_board_admins table and returns
 * JWT session.
 *
 * The administrator registration operation enables the secure creation of new
 * admin accounts in the discussion_board_admins table. This endpoint strictly
 * enforces the business requirement that platform administrators must
 * authenticate using unique, valid email addresses and strong passwords. When a
 * registration request is made, the system verifies email uniqueness via the
 * Prisma model constraint and mandates password strength (at least 8
 * characters, with numbers, letters, and special characters).
 *
 * Upon successful registration, the system sets is_email_verified to false,
 * marks is_active true, and is_blocked false, reflecting policy-compliant
 * default access. The password is stored as a bcrypt hash in the password_hash
 * field—no plaintext storage is allowed under any circumstance. The
 * registration workflow ensures auditability by stamping created_at and
 * updated_at, and supports later compliance actions via the optional deleted_at
 * soft delete field.
 *
 * The Prisma schema's unique index on email field directly powers business
 * validation; any duplicate triggers an error response. All admin session
 * records (created in discussion_board_admin_sessions) are linked to a unique
 * admin id (UUID), providing audit, time stamping, and traceability required
 * for platform moderation roles. Creation of an admin account is strictly
 * separated from assignment of elevated privileges—these must subsequently be
 * set by platform operators.
 *
 * The operation returns a JWT access and refresh token pair (see
 * IDiscussionBoardAdmin.IAuthorized), empowering immediate admin moderation
 * actions on the platform, in strict accordance with stateless, scalable
 * authentication policies. Business logic is tightly mapped to the schema for
 * maximal compiler safety, maintainability, and transparency.
 *
 * Related endpoints for login or token refresh are required for the full admin
 * authentication suite, enabling full coverage of onboarding and session
 * management. Any failure to meet field or business requirements produces
 * explicit, actionable errors for rapid feedback and improved developer
 * experience.
 *
 * @param props.connection
 * @param props.body Administrator registration info (email, password).
 * @setHeader token.access Authorization
 *
 * @path /auth/admin/join
 * @accessor api.functional.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
