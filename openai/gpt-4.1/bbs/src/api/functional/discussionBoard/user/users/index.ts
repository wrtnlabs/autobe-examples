import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Soft-delete a discussion board user account in the users table.
 *
 * Delete a user account from the discussion board user table by setting the
 * deleted_at field to the current timestamp instead of physical removal.
 *
 * This operation is reserved for authenticated users managing their own
 * account. Users must pass authentication before deletion. The API validates
 * that the account exists, is active (not deleted already), and matches the
 * user in session. No admin routes are granted through this endpoint, aligning
 * with the role definition in the user table.
 *
 * All related login session records remain in subsidiary tables for audit and
 * traceability. This operation triggers session invalidation and logs the
 * deletion event for compliance. Any attempt to delete another user's account
 * or a non-existent/previously-deleted user triggers appropriate errors. The
 * soft-delete approach is required by the schema to support recovery and
 * ensures the data remains available for moderation and legal traceability.
 *
 * @param props.connection
 * @param props.userId Unique identifier (UUID) of the target discussion board
 *   user account to delete.
 * @path /discussionBoard/user/users/:userId
 * @accessor api.functional.discussionBoard.user.users.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier (UUID) of the target discussion board user account
     * to delete.
     */
    userId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/user/users/:userId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/user/users/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
