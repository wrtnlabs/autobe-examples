import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardArticleSnapshot } from "../../../../../structures/IDiscussionBoardArticleSnapshot";
import { IPageIDiscussionBoardArticleSnapshot } from "../../../../../structures/IPageIDiscussionBoardArticleSnapshot";

/**
 * Retrieve a paginated, searchable list of snapshots for a specific article
 * from discussion_board_article_snapshots.
 *
 * Query the edit history (snapshots) of a specific article, allowing clients to
 * browse all previous versions of that article’s content.
 *
 * This operation supports advanced search parameters (such as filtering by
 * snapshot date, author type, or date ranges) and returns snapshot metadata
 * along with the historical content. The requesting user must have viewing
 * access to the target article; admins can access all articles’ histories for
 * audit and moderation purposes. The operation leverages strict pagination to
 * efficiently handle long article histories. Returned snapshots include
 * timestamps, author info, versioned content (title, body), and are ordered by
 * creation time (most recent first by default).
 *
 * Error responses are returned for non-existent articles, insufficient
 * permissions, or unexpected system failures. This reporting workflow is
 * critical for transparency, compliance, and ensuring the integrity of debate
 * on the platform. Related endpoints include article detail (retrieve current
 * version) and article edit (create new snapshot via update).
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article for which to list
 *   historical snapshots.
 * @param props.body Snapshot search criteria and pagination parameters. May
 *   include date range, author filters, and limit/offset or cursor.
 * @path /discussionBoard/admin/articles/:articleId/snapshots
 * @accessor api.functional.discussionBoard.admin.articles.snapshots.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the article for which to list historical
     * snapshots.
     */
    articleId: string & tags.Format<"uuid">;

    /**
     * Snapshot search criteria and pagination parameters. May include date
     * range, author filters, and limit/offset or cursor.
     */
    body: IDiscussionBoardArticleSnapshot.IRequest;
  };
  export type Body = IDiscussionBoardArticleSnapshot.IRequest;
  export type Response = IPageIDiscussionBoardArticleSnapshot;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/admin/articles/:articleId/snapshots",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/admin/articles/${encodeURIComponent(props.articleId ?? "null")}/snapshots`;
  export const random = (): IPageIDiscussionBoardArticleSnapshot =>
    typia.random<IPageIDiscussionBoardArticleSnapshot>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
