/**
 * Update the title, body, or attachments of an existing discussion board
 * article (discussion_board_articles).
 *
 * This API operation allows the author of an existing article, or an
 * administrator, to update the article's core fields (title, body, attachments)
 * in the 'discussion_board_articles' schema table. The article to update is
 * identified by the required path parameter 'articleId', which must reference a
 * valid article record that is not already soft-deleted.
 *
 * All input fields are validated according to business constraints (title:
 * 1–100 chars, body: 1–10,000 chars; file attachments must comply with
 * allowable types and per-article limits). Business logic strictly enforces
 * permissions, permitting only the original author or administrators to execute
 * this operation. Any attachment changes (adding or removing) are reflected in
 * the 'discussion_board_article_attachments' table and are subject to
 * virus/malware scan and storage integrity rules. Soft-deleted articles cannot
 * be updated; attempts will result in a business error.
 *
 * Security considerations include authorization checks to prevent cross-user or
 * cross-role modifications, and strict error responses if validation fails.
 * This update operation is related to article creation and deletion endpoints.
 * If attachments are modified, appropriate background cleanup of removed files
 * is triggered.
 *
 * @param props.connection
 * @param props.articleId The unique identifier (UUID) of the target article to
 *   update.
 * @param props.body Update payload for a discussion board article, allowing
 *   modification of title, body, and attachments.
 * @path /discussionBoard/admin/articles/:articleId
 * @accessor api.functional.discussionBoard.admin.articles.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
