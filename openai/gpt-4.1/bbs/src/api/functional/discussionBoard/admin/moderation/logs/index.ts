/**
 * Search and retrieve a paginated list of moderation logs
 * (discussion_board_moderation_logs table) for admin audit and review.
 *
 * Retrieve a filtered and paginated list of moderation and administrative
 * actions recorded in the platform.
 *
 * This endpoint exposes the discussion_board_moderation_logs table, allowing
 * platform administrators to search and review the complete moderation history.
 * Each log entry includes detailed contextual data: which admin performed the
 * action, which target entity or user was affected, the type of action taken
 * (such as delete, edit, suspend), additional explanatory notes, and precise
 * timestamps. Filtering can be performed on all major columns, such as admin
 * ID, target entity type, action code, and time ranges. Full text search is
 * also supported against moderation notes for deep-dive investigations.
 *
 * Security is paramount—this endpoint is strictly restricted to authorized
 * admin users due to the sensitive nature of moderation data. Logs are
 * immutable business records, and this endpoint is for review purposes only;
 * any modification of the underlying records is handled exclusively by internal
 * system processes. Pagination ensures scalability even as the number of
 * moderation events grows. Related endpoints include GET
 * /moderation/logs/{logId} for detail inspection of a specific event.
 *
 * @param props.connection
 * @param props.body Search, filter, and pagination criteria for moderation log
 *   listing, such as admin ID, action code, target entity, note keywords, and
 *   time ranges.
 * @path /discussionBoard/admin/moderation/logs
 * @accessor api.functional.discussionBoard.admin.moderation.logs.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
