/**
 * Remove an attachment from a discussion board comment
 * (discussion_board_comment_attachments).
 *
 * Remove an attachment (file or image) from a comment on the discussion board
 * by its attachment ID, confirming that the requester is either the owner of
 * the comment or an administrator. On success, the record and the actual
 * resource are deleted irreversibly from both the database and storage.
 *
 * Appropriate permission checks are enforced: users may only remove attachments
 * from their own comments; admins may remove any attachment as part of
 * moderation. All operations are logged, and attempts to delete already-removed
 * or non-existent attachments produce clear error messages, including for cases
 * of insufficient permissions or data inconsistencies.
 *
 * When the attachment is removed, its physical file resource is also deleted
 * from persistent storage. The endpoint enforces strong referential checks—an
 * attachment may only be removed if it currently belongs to the specified
 * comment, and the provided attachmentId and commentId must refer to existing,
 * related records. The operation supports both user self-service and
 * administrative moderation with detailed auditability and compliance,
 * referencing all relevant comment and attachment schema descriptions.
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the parent comment to which the
 *   attachment is linked. (global scope)
 * @param props.attachmentId Unique identifier of the attachment to be deleted
 *   from the comment.
 * @path /discussionBoard/admin/comments/:commentId/attachments/:attachmentId
 * @accessor api.functional.discussionBoard.admin.comments.attachments.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the parent comment to which the attachment is
     * linked. (global scope)
     */
    commentId: string & tags.Format<"uuid">;

    /** Unique identifier of the attachment to be deleted from the comment. */
    attachmentId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/admin/comments/:commentId/attachments/:attachmentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/admin/comments/${encodeURIComponent(props.commentId ?? "null")}/attachments/${encodeURIComponent(props.attachmentId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
      assert.param("attachmentId")(() => typia.assert(props.attachmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
