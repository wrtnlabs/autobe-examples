/**
 * Metadata and linkage entity for article attachments (images or documents).
 *
 * Links an uploaded file or image to a specific article, providing file
 * metadata, secure storage URI, and audit information. Attachments are
 * dependent on their parent article (cannot exist stand-alone). Validation for
 * file types, extension, size, and URI is strictly enforced per business and
 * security policy.
 *
 * All permissions for read and modification are derived via API ownership or
 * administrator access to the parent article. Soft deletion by users or
 * moderators is recorded via the deleted_at timestamp for compliance and
 * moderation trails.
 *
 * Typical clients display information from this DTO for file preview, secure
 * download rendering, and attachment management UI.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardArticleAttachment = {
  /**
   * Unique identifier for the attachment record (UUID, system-generated at
   * upload).
   *
   * Used for reference in all attachment operations.
   */
  id: string & tags.Format<"uuid">;

  /**
   * UUID of the parent article to which this attachment is related.
   *
   * Foreign key safe for display, never editable by the client; set by the
   * API context.
   */
  article_id: string & tags.Format<"uuid">;

  /**
   * Original filename and extension as provided by the uploading user. Used
   * for display, download, and business validation.
   *
   * Validated against length and forbidden character constraints.
   */
  file_name: string;

  /**
   * MIME type of the uploaded file, enforced by file type whitelist for
   * security and rendering behavior. Provided at upload and verified by the
   * backend.
   */
  mime_type: string;

  /**
   * Uploaded file size in bytes. Range: 1 byte to 10,485,760 bytes (10MB) for
   * validation and quota enforcement.
   *
   * Zero-length files forbidden; size upper bound set by business rules.
   */
  file_size: number &
    tags.Type<"int32"> &
    tags.Minimum<1> &
    tags.Maximum<10485760>;

  /**
   * Storage URI pointing to the uploaded file resource (S3, CDN, or local
   * storage). Never a direct public file path, always controlled via secure
   * access policy.
   */
  file_uri: string & tags.Format<"uri">;

  /**
   * Datestamp of record creation (UTC). Used for upload tracking, audit, and
   * chronological sorting.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Soft delete timestamp, set when moderation, user action, or compliance
   * removes an attachment. Null when active.
   */
  deleted_at?: (string & tags.Format<"date-time">) | null | undefined;
};
