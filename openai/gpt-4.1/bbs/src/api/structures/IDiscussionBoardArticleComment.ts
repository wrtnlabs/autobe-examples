  /**
   * Reference to the parent article this comment belongs to. Uses summary
   * type for reference context.
   */
  article: IDiscussionBoardArticle.ISummary;

  /**
   * Comment content as provided by the author. Must contain non-blank text
   * and not exceed 5,000 characters per business constraints.
   */
  body: string;

  /**
   * Timestamp when this comment was originally posted.
   * Immutable—automatically set on insertion.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp of the last update to this comment. Automatically refreshed on
   * edit.
   */
  updated_at: string & tags.Format<"date-time">;

  /** The timestamp of deletion or null if active. */
