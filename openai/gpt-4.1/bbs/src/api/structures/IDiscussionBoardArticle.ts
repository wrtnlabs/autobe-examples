  /**
   * Embedded summary of the admin who authored this article. Null if the
   * article was created by a user author.
   */
  author_admin?: IDiscussionBoardAdmin.ISummary | null | undefined;

  /** Timestamp when the article was created. */
  created_at: string & tags.Format<"date-time">;

  /** Timestamp when the article was last updated. */
  updated_at: string & tags.Format<"date-time">;
