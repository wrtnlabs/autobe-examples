/**
 * Historical snapshot of a discussion board article state, captured for
 * versioning and audit purposes.
 *
 * Each snapshot stores the article's title, body, author user (or admin) at a
 * given edit point in time. Used to support a complete edit history for
 * compliance and moderation. Snapshots are immutable and created by system
 * logic when articles are edited. Instead of referencing authors by UUIDs, this
 * structure provides full author context via `.ISummary` objects for both user
 * and admin.
 *
 * Article_id remains a scalar as the hierarchical parent.
 *
 * This allows for atomic retrieval of all auditing and author context with no
 * N+1 query problem.
 *
 * In addition, to maintain referential integrity and enable traceable audit
 * logs, the snapshot record also includes the author_user_id and
 * author_admin_id fields. These are stored as nullable UUIDs and enable
 * database-level connection to the original author identity even in scenarios
 * where the summary object cannot be reconstructed, such as after user or admin
 * deletion. This supports robust audit trails for regulatory, compliance, and
 * moderation workflows.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
