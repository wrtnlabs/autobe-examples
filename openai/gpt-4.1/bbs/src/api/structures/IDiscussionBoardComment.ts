/**
 * Represents a comment on a discussion board article.
 *
 * Each comment belongs to a specific article and is authored by either a user
 * or an administrator. Comments include content, audit fields, soft deletion
 * status, and provide full context for both article and author via summary
 * types. This response also lists any files/images attached to the comment,
 * with business rules enforcing a maximum of 2 attachments per comment (see:
 * attachments field). Attachments are surfaced as an array of summary DTOs
 * (IDiscussionBoardCommentAttachment.ISummary).
 *
 * Attachments are associated via a separate endpoint for creation, but always
 * returned as part of the comment for complete business context. API clients
 * should expect the attachments field to be present and to enforce client-side
 * attachment count and display logic. This resolves previous ambiguity
 * regarding the linkage between comments and their attachments, ensuring API
 * consumers always see attachment information in the canonical comment response
 * object.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardComment = {
  /** Unique identifier for the comment. */
  id: string & tags.Format<"uuid">;

  /** Summary context of the article this comment belongs to. */
  article: IDiscussionBoardArticle.ISummary;

  /**
   * Contextual summary of the comment author, discriminated between user
   * (regular member) or admin. Always present with type appropriate to
   * authorship.
   */
  author: IDiscussionBoardUser.ISummary | IDiscussionBoardAdmin.ISummary;

  /** Text content of the comment. Required. */
  body: string & tags.MinLength<2> & tags.MaxLength<1000>;

  /**
   * List of attachments—files or images—associated with this comment. Maximum
   * 2 attachments allowed per comment. Attachments are always returned here
   * in the comment response object for business context and UI rendering.
   * Each attachment contains metadata including filename, MIME type, URL, and
   * additional moderation or auditing data as per attachment summary DTO
   * definition.
   */
  attachments: IDiscussionBoardCommentAttachment.ISummary[];

  /** Timestamp when the comment was created. */
  created_at: string & tags.Format<"date-time">;

  /** Timestamp when the comment was last updated. */
  updated_at: string & tags.Format<"date-time">;

  /** Soft deletion timestamp. */
  deleted_at?: (string & tags.Format<"date-time">) | null | undefined;
};
