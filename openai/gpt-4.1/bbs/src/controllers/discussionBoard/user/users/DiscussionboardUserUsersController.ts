import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteDiscussionBoardUserUsersUserId } from "../../../../providers/deleteDiscussionBoardUserUsersUserId";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";

@Controller("/discussionBoard/user/users/:userId")
export class DiscussionboardUserUsersController {
  /**
   * Delete a user account from the discussion board user table by setting the
   * deleted_at field to the current timestamp instead of physical removal.
   *
   * This operation is reserved for authenticated users managing their own
   * account. Users must pass authentication before deletion. The API validates
   * that the account exists, is active (not deleted already), and matches the
   * user in session. No admin routes are granted through this endpoint,
   * aligning with the role definition in the user table.
   *
   * All related login session records remain in subsidiary tables for audit and
   * traceability. This operation triggers session invalidation and logs the
   * deletion event for compliance. Any attempt to delete another user's account
   * or a non-existent/previously-deleted user triggers appropriate errors. The
   * soft-delete approach is required by the schema to support recovery and
   * ensures the data remains available for moderation and legal traceability.
   *
   * @param connection
   * @param userId Unique identifier (UUID) of the target discussion board user
   *   account to delete.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
