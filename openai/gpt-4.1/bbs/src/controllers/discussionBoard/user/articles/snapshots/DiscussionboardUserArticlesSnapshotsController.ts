import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardUserArticlesArticleIdSnapshots } from "../../../../../providers/patchDiscussionBoardUserArticlesArticleIdSnapshots";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { IPageIDiscussionBoardArticleSnapshot } from "../../../../../api/structures/IPageIDiscussionBoardArticleSnapshot";
import { IDiscussionBoardArticleSnapshot } from "../../../../../api/structures/IDiscussionBoardArticleSnapshot";

@Controller("/discussionBoard/user/articles/:articleId/snapshots")
export class DiscussionboardUserArticlesSnapshotsController {
  /**
   * Retrieve a paginated, searchable list of snapshots for a specific article
   * from discussion_board_article_snapshots.
   *
   * Query the edit history (snapshots) of a specific article, allowing clients
   * to browse all previous versions of that article’s content.
   *
   * This operation supports advanced search parameters (such as filtering by
   * snapshot date, author type, or date ranges) and returns snapshot metadata
   * along with the historical content. The requesting user must have viewing
   * access to the target article; admins can access all articles’ histories for
   * audit and moderation purposes. The operation leverages strict pagination to
   * efficiently handle long article histories. Returned snapshots include
   * timestamps, author info, versioned content (title, body), and are ordered
   * by creation time (most recent first by default).
   *
   * Error responses are returned for non-existent articles, insufficient
   * permissions, or unexpected system failures. This reporting workflow is
   * critical for transparency, compliance, and ensuring the integrity of debate
   * on the platform. Related endpoints include article detail (retrieve current
   * version) and article edit (create new snapshot via update).
   *
   * @param connection
   * @param articleId Unique identifier of the article for which to list
   *   historical snapshots.
   * @param body Snapshot search criteria and pagination parameters. May include
   *   date range, author filters, and limit/offset or cursor.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleSnapshot.IRequest,
  ): Promise<IPageIDiscussionBoardArticleSnapshot> {
    try {
      return await patchDiscussionBoardUserArticlesArticleIdSnapshots({
        user,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
