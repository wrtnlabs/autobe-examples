import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardUserArticlesArticleIdAttachments } from "../../../../../providers/postDiscussionBoardUserArticlesArticleIdAttachments";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { putDiscussionBoardUserArticlesArticleIdAttachmentsAttachmentId } from "../../../../../providers/putDiscussionBoardUserArticlesArticleIdAttachmentsAttachmentId";
import { deleteDiscussionBoardUserArticlesArticleIdAttachmentsAttachmentId } from "../../../../../providers/deleteDiscussionBoardUserArticlesArticleIdAttachmentsAttachmentId";

import { IDiscussionBoardArticleAttachment } from "../../../../../api/structures/IDiscussionBoardArticleAttachment";

@Controller("/discussionBoard/user/articles/:articleId/attachments")
export class DiscussionboardUserArticlesAttachmentsController {
  /**
   * Upload a new file or image attachment to a discussion board article
   * (discussion_board_article_attachments).
   *
   * Upload a file or image attachment to an existing discussion article. This
   * enables users to provide supporting materials, such as evidence or
   * supplemental resources, for the article's discussion. The operation creates
   * a record in the attachments table and stores a secure URI for later
   * retrieval.
   *
   * Authentication is required. Only the article author or an admin may upload
   * new attachments. File upload validation includes type (e.g. PNG, JPG, PDF,
   * DOCX), maximum size (10MB), and restrictions on total attachments per
   * article, all enforced in business logic as per requirements. Upon failure,
   * the system returns validation errors indicating reasons (type, size, count,
   * or security scanning failures).
   *
   * On success, the operation persists file metadata (original name, MIME type,
   * upload time) and associates the new attachment with the target article. The
   * resulting attachment becomes visible in article details and is subject to
   * moderation and access controls. Removal of the article or this record will
   * remove the file from backend storage.
   *
   * @param connection
   * @param articleId Unique identifier of the target article to which the
   *   attachment will be uploaded.
   * @param body Details and metadata for the new article attachment, including
   *   file URI, original filename, type, size, and related article reference.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleAttachment.ICreate,
  ): Promise<IDiscussionBoardArticleAttachment> {
    try {
      return await postDiscussionBoardUserArticlesArticleIdAttachments({
        user,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update metadata of a specific article attachment
   * (discussion_board_article_attachments).
   *
   * Modify the details of an attachment associated with a discussion article.
   * This may include updating the original filename, file type, or related
   * metadata, but not replacing the actual file itself. Only owners of the
   * article or platform administrators may perform updates.
   *
   * The system applies stringent validation on attribute changes, ensuring
   * compliance with business and file safety rules. Attempts to update
   * non-editable properties or provide invalid values are rejected with clear
   * error messages. Every successful modification is persistently stored, and
   * all changes are logged for future audit and moderation.
   *
   * Both target article and attachment must exist. An error is returned if
   * identifiers are invalid or permissions are insufficient.
   *
   * @param connection
   * @param articleId Unique identifier of the parent article containing the
   *   attachment.
   * @param attachmentId Unique identifier of the target attachment to update.
   * @param body Fields to update for the attachment, such as original filename
   *   or file type. Forbidden to change file URI or parent article reference in
   *   this operation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":attachmentId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleAttachment.IUpdate,
  ): Promise<IDiscussionBoardArticleAttachment> {
    try {
      return await putDiscussionBoardUserArticlesArticleIdAttachmentsAttachmentId(
        {
          user,
          articleId,
          attachmentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific article attachment by its ID in
   * discussion_board_article_attachments.
   *
   * Delete an attachment from a specific discussion board article using the
   * attachment's unique identifier.
   *
   * Only the owner of the article or an admin can invoke this operation. The
   * system first validates the existence of both the specified article and
   * attachment, followed by verifying that the attachment is correctly related
   * to the target article. Permission checks ensure that ordinary users cannot
   * delete attachments from articles they do not own, while admins have
   * override privileges to manage content.
   *
   * On successful invocation, the attachment is permanently deleted from both
   * the database and backend file storage. All file access rights are
   * immediately revoked. Errors are returned if either entity does not exist,
   * the user lacks permission, or deletion fails due to storage constraints.
   * This operation leverages the discussion_board_article_attachments table and
   * is representative of granular, user-facing content management workflows.
   * Related operations include article deletion (which will cascade to all
   * attachments) and attachment upload (for file creation).
   *
   * @param connection
   * @param articleId Unique identifier of the article to which this attachment
   *   belongs.
   * @param attachmentId Unique identifier of the attachment to be deleted from
   *   the article.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":attachmentId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardUserArticlesArticleIdAttachmentsAttachmentId(
        {
          user,
          articleId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
