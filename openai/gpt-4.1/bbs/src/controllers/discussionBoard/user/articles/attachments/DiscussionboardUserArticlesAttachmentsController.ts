import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardUserArticlesArticleIdAttachments } from "../../../../../providers/postDiscussionBoardUserArticlesArticleIdAttachments";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { putDiscussionBoardUserArticlesArticleIdAttachmentsAttachmentId } from "../../../../../providers/putDiscussionBoardUserArticlesArticleIdAttachmentsAttachmentId";
import { deleteDiscussionBoardUserArticlesArticleIdAttachmentsAttachmentId } from "../../../../../providers/deleteDiscussionBoardUserArticlesArticleIdAttachmentsAttachmentId";

import { IDiscussionBoardArticleAttachment } from "../../../../../api/structures/IDiscussionBoardArticleAttachment";

@Controller("/discussionBoard/user/articles/:articleId/attachments")
export class DiscussionboardUserArticlesAttachmentsController {
  /**
   * Upload and attach a file to an existing article on the discussion board.
   *
   * This operation lets a registered user (article author) or admin add new
   * attachments, such as images or documents, to a specified article, provided
   * the user has permission. Attachments are subject to strict validation for
   * file size (up to 10MB), number of files (at most 5 per article), and
   * supported types (images: jpg, jpeg, png, gif; docs: pdf, doc, docx, xls,
   * xlsx, ppt, pptx).
   *
   * Security rules require that only the article's author or an administrator
   * may perform attachment actions. Ownership is verified using authentication
   * token context and the article's user_id in the schema. Business logic
   * ensures only the author or admin can update article attachments.
   *
   * File metadata (name, type, size, URI) and attachment linkage are stored in
   * the discussion_board_article_attachments table. Backend storage is
   * abstracted; end users receive only permitted metadata, never internal
   * paths. Attachment removal or exceeding policy limits results in clear,
   * actionable errors consistent with system validation documentation.
   *
   * @param connection
   * @param articleId Unique identifier of the target article to which the file
   *   will be attached.
   * @param body JSON representation of upload metadata, including filename,
   *   MIME type, and file size. Actual file is delivered as a file URI string,
   *   matching secure upload process. All fields must meet business rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleAttachment.ICreate,
  ): Promise<IDiscussionBoardArticleAttachment> {
    try {
      return await postDiscussionBoardUserArticlesArticleIdAttachments({
        user,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Modify an existing attachment for the specified article, either by updating
   * its metadata or replacing the stored file.
   *
   * This operation can be performed only by the attachment's owner (the article
   * author) or by an admin. It validates the requestor's privilege, ensures
   * that the specified attachment belongs to the identified article, and checks
   * all business validation rules (type, size, etc.). All updates, including
   * file replacement or metadata changes, are reflected in the underlying
   * Prisma schema record in discussion_board_article_attachments.
   *
   * Security is enforced by verifying ownership and permissions using token
   * context. System business logic ensures updates are compliant with file
   * validation, with explicit errors returned for any breach (e.g., replacing
   * with unsupported file type or exceeding max size). Upon successful update,
   * the current metadata for the attachment is returned, redacting sensitive
   * storage/internal fields from the user.
   *
   * @param connection
   * @param articleId Unique identifier of the article associated with the
   *   attachment (parent context).
   * @param attachmentId Unique identifier of the attachment to update (must
   *   belong to the specified article).
   * @param body Attachment file and/or updated metadata to replace the existing
   *   record. Follows business rules for allowed file types, size, and secure
   *   storage. All required fields and policies must be met.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":attachmentId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleAttachment.IUpdate,
  ): Promise<IDiscussionBoardArticleAttachment> {
    try {
      return await putDiscussionBoardUserArticlesArticleIdAttachmentsAttachmentId(
        {
          user,
          articleId,
          attachmentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Deletes a specific attachment (file or image) associated with an article on
   * the discussion board.
   *
   * The targeted attachment is identified by the unique combination of
   * articleId and attachmentId as specified in the path parameters. Only the
   * article author or an admin can invoke this operation. Attempting to delete
   * an attachment on an article not owned by the user, or as an unauthenticated
   * user, will result in a permissions error.
   *
   * The attachment's deleted_at timestamp is set to the current time, and all
   * related storage references are fully cleared. For compliance and
   * moderation, the action is logged. If the article itself is deleted, its
   * attachments are also deleted; this direct endpoint ensures users/admins can
   * selectively remove attachments without deleting the article. This operation
   * follows storage and validation requirements as detailed in the business
   * requirements and Prisma schema.
   *
   * @param connection
   * @param articleId Unique identifier of the article this attachment belongs
   *   to
   * @param attachmentId Unique identifier of the attachment to be deleted from
   *   the article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":attachmentId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardUserArticlesArticleIdAttachmentsAttachmentId(
        {
          user,
          articleId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
