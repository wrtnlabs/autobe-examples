import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardUserArticles } from "../../../../providers/postDiscussionBoardUserArticles";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { putDiscussionBoardUserArticlesArticleId } from "../../../../providers/putDiscussionBoardUserArticlesArticleId";
import { deleteDiscussionBoardUserArticlesArticleId } from "../../../../providers/deleteDiscussionBoardUserArticlesArticleId";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/user/articles")
export class DiscussionboardUserArticlesController {
  /**
   * Create a new article in the discussion board system with user-provided
   * title and content, linked to the authenticated user's account.
   *
   * This endpoint requires the client to submit a valid request body containing
   * the title (max 200 characters, plain text, whitespace-trimmed) and content
   * (max 10,000 characters, plain text). The user_id is implicitly associated
   * with the authenticated session, preventing manual spoofing of article
   * ownership. Audit fields (created_at, updated_at) are set automatically at
   * insertion.
   *
   * On successful creation, the response returns the complete article record,
   * including auto-generated audit fields and the unique articleId. Attachments
   * are not created in this operation; clients should use separate attachment
   * endpoints for images and files. If field validations fail (e.g. over
   * length, unsafe content), the server returns a validation error detailing
   * the issue. Public creation of articles is restricted—authentication is
   * required for submission and tracked for moderation purposes.
   *
   * Related operations include adding attachments to an article, updating
   * article content, and fetching detailed views for moderation or display.
   *
   * @param connection
   * @param body Payload with fields required to create a new discussion board
   *   article: title and content. user_id is auto-filled from the session
   *   context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.ICreate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await postDiscussionBoardUserArticles({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API endpoint allows for the full editing of a discussion article
   * already present in the platform discussion board.
   *
   * It performs complete updates on all fields allowed by the
   * discussion_board_articles Prisma schema, excluding immutable fields such as
   * the article's original ID, creation timestamp, or system-managed audit
   * data. The operation enforces permission checks to ensure only the original
   * article author or designated moderators/admins can edit the content. All
   * submitted changes undergo validation against business rules, including
   * content length, acceptable HTML, and attachment constraints, as specified
   * in requirements documents.
   *
   * If the article is successfully updated, the new state of the article is
   * returned to the requester. Modification attempts by unauthorized users, or
   * with invalid data, result in appropriate error responses. This endpoint is
   * closely related to article versioning, as edits may trigger creation of
   * article snapshots for audit trail support.
   *
   * @param connection
   * @param articleId Unique identifier of the target article for update (UUID
   *   format).
   * @param body Article updates according to the discussion_board_articles
   *   Prisma schema, excluding immutable fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":articleId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticle.IUpdate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await putDiscussionBoardUserArticlesArticleId({
        user,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint allows the authorized user to delete a discussion article
   * from the board. Deletion is absolute; once deleted, the record is removed
   * from the database and cannot be restored, following the hard-delete policy
   * as the discussion_board_articles Prisma schema does not define a soft
   * delete column.
   *
   * Business logic enforces that only the original author, a moderator, or an
   * administrator may perform this operation. The system ensures removal of any
   * associated data, such as attachments or comments, according to the
   * referential integrity rules set in the schema. Attempts to delete
   * nonexistent or already-deleted articles, or requests by unauthorized users,
   * produce clear error responses.
   *
   * This operation is coordinated with moderation logs to ensure full
   * traceability of deletion activities for compliance, and should be used in
   * conjunction with operational policies for audit and oversight.
   *
   * @param connection
   * @param articleId Unique identifier of the target article for deletion (UUID
   *   format).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":articleId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardUserArticlesArticleId({
        user,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
