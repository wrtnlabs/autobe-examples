import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardUserArticles } from "../../../../providers/postDiscussionBoardUserArticles";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchDiscussionBoardUserArticles } from "../../../../providers/patchDiscussionBoardUserArticles";
import { getDiscussionBoardUserArticlesArticleId } from "../../../../providers/getDiscussionBoardUserArticlesArticleId";
import { putDiscussionBoardUserArticlesArticleId } from "../../../../providers/putDiscussionBoardUserArticlesArticleId";
import { deleteDiscussionBoardUserArticlesArticleId } from "../../../../providers/deleteDiscussionBoardUserArticlesArticleId";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../api/structures/IPageIDiscussionBoardArticle";

@Controller("/discussionBoard/user/articles")
export class DiscussionboardUserArticlesController {
  /**
   * Create a new discussion board article with optional attachments
   * (discussion_board_articles).
   *
   * This API operation allows a registered user to create a new article (post)
   * in the discussion board, providing both required text content (title and
   * body) and, optionally, uploading one or more attachments (e.g., images or
   * documents). The article will be stored in the 'discussion_board_articles'
   * schema table and its 'author_user_id' field set to the authenticated user's
   * ID.
   *
   * The operation enforces all business constraints on article creation,
   * including title (1–100 characters), body (1–10,000 characters), and file
   * attachment validation (allowed file types and per-article limits, enforced
   * at upload). Metadata regarding the author, creation timestamp, and
   * validation results for any attachments will be captured in the database as
   * per schema requirements.
   *
   * Security and permissions are tightly controlled: only authenticated users
   * may create articles, and all fields are validated according to the business
   * rules. On failure due to validation (e.g., file type, size, prohibited
   * content), the API responds with descriptive error details to guide
   * remediation. Related operations include update and deletion of articles,
   * and attachment management (handled via separate endpoints).
   *
   * @param connection
   * @param body Payload for creating a new discussion board article, including
   *   title, body, and optional attachments.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.ICreate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await postDiscussionBoardUserArticles({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated, filtered list of active discussion board
   * articles.
   *
   * Retrieve a list of active (non-deleted) articles from the discussion board
   * system using advanced filters, search, and pagination. This operation
   * offers users a streamlined way to browse and find relevant articles
   * quickly.
   *
   * Articles returned by this operation are required to include only those that
   * have not been soft-deleted. The filter criteria (such as keywords, author,
   * or dates) should be provided in the request body according to the
   * IDiscussionBoardArticle.IRequest DTO. Only non-sensitive, properly redacted
   * information is included in the response.
   *
   * Pagination and sorting metadata are supplied so users can navigate the
   * collection efficiently and sort by most recent, by author, or by title.
   * Advanced business logic ensures article list visibility aligns with user
   * permissions and soft delete states. Any error (such as an invalid search
   * parameter or permission denial) results in a clear, actionable error
   * response.
   *
   * @param connection
   * @param body Search, filter, and pagination parameters for retrieving
   *   articles according to business and display requirements.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardUserArticles({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a single discussion board article by id.
   *
   * Retrieve the detail of one discussion board article (by its id), including
   * all available metadata, author and attachment information. Only articles
   * that have not been soft deleted are accessible to users; deleted articles
   * are accessible only to admins for moderation and auditing purposes.
   *
   * If the requested article id does not exist or the user does not have
   * permission, the system returns an error with a description of the problem.
   * Author and attachment details are strictly normalized and redacted as
   * appropriate for user privacy.
   *
   * The response includes the article's title, body, creation/update
   * timestamps, author display name and avatar, and any related attachment
   * details needed for detail view presentation.
   *
   * @param connection
   * @param articleId Unique identifier of the target article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await getDiscussionBoardUserArticlesArticleId({
        user,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the title, body, or attachments of an existing discussion board
   * article (discussion_board_articles).
   *
   * This API operation allows the author of an existing article, or an
   * administrator, to update the article's core fields (title, body,
   * attachments) in the 'discussion_board_articles' schema table. The article
   * to update is identified by the required path parameter 'articleId', which
   * must reference a valid article record that is not already soft-deleted.
   *
   * All input fields are validated according to business constraints (title:
   * 1–100 chars, body: 1–10,000 chars; file attachments must comply with
   * allowable types and per-article limits). Business logic strictly enforces
   * permissions, permitting only the original author or administrators to
   * execute this operation. Any attachment changes (adding or removing) are
   * reflected in the 'discussion_board_article_attachments' table and are
   * subject to virus/malware scan and storage integrity rules. Soft-deleted
   * articles cannot be updated; attempts will result in a business error.
   *
   * Security considerations include authorization checks to prevent cross-user
   * or cross-role modifications, and strict error responses if validation
   * fails. This update operation is related to article creation and deletion
   * endpoints. If attachments are modified, appropriate background cleanup of
   * removed files is triggered.
   *
   * @param connection
   * @param articleId The unique identifier (UUID) of the target article to
   *   update.
   * @param body Update payload for a discussion board article, allowing
   *   modification of title, body, and attachments.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":articleId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticle.IUpdate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await putDiscussionBoardUserArticlesArticleId({
        user,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an article (soft delete for authors, permanent for admins) including
   * all comments and attachments, by article ID in the
   * discussion_board_articles table.
   *
   * This API endpoint allows the author of an article or a platform
   * administrator to delete a target article by its unique identifier. For a
   * user deleting their own article, the system applies a soft delete, updating
   * the deleted_at field of the corresponding database row so that the article
   * is no longer visible to general users, while preserving it for moderation,
   * review, or recovery in line with privacy guidelines. For administrators,
   * this operation triggers permanent/physical deletion, removing the article
   * and all associated comments and attachments from the database. Attempts by
   * unauthorized users (such as deleting someone else’s article or
   * unauthenticated requests) result in a permission-denied error, following
   * strict business policies.
   *
   * The operation ensures security by restricting delete permissions to article
   * authors and admins only. Whenever an admin performs a deletion, an audit
   * log is created referencing the admin, the target article, and a required
   * reason for deletion, supporting traceability and regulatory compliance. The
   * cascading removal is handled via onDelete: Cascade in the Prisma schema,
   * meaning all related comments and attachments are deleted automatically at
   * the database level.
   *
   * Edge cases, such as attempting to delete an already deleted article or
   * trying to delete articles locked for moderation, are handled gracefully
   * with context-specific error messages as per the error-handling rules in the
   * requirements. The operation only requires the article ID as a path
   * parameter and does not take a request body. No content is returned in the
   * response for successful erasure.
   *
   * @param connection
   * @param articleId Unique identifier of the target article to delete.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":articleId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardUserArticlesArticleId({
        user,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
