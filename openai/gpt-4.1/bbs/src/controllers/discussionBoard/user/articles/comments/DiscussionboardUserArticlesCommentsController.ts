import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardUserArticlesArticleIdComments } from "../../../../../providers/postDiscussionBoardUserArticlesArticleIdComments";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { patchDiscussionBoardUserArticlesArticleIdComments } from "../../../../../providers/patchDiscussionBoardUserArticlesArticleIdComments";
import { getDiscussionBoardUserArticlesArticleIdCommentsCommentId } from "../../../../../providers/getDiscussionBoardUserArticlesArticleIdCommentsCommentId";
import { putDiscussionBoardUserArticlesArticleIdCommentsCommentId } from "../../../../../providers/putDiscussionBoardUserArticlesArticleIdCommentsCommentId";

import { IDiscussionBoardArticleComment } from "../../../../../api/structures/IDiscussionBoardArticleComment";
import { IPageIDiscussionBoardArticleComment } from "../../../../../api/structures/IPageIDiscussionBoardArticleComment";

@Controller("/discussionBoard/user/articles/:articleId/comments")
export class DiscussionboardUserArticlesCommentsController {
  /**
   * Create a new comment on a specific article in the discussion board system
   * (discussion_board_article_comments).
   *
   * This API operation enables an authenticated user to post a new comment
   * beneath a specific article within the discussion board system. The comment
   * body is required and must be between 1 to 1000 characters, as defined in
   * the business logic. To ensure auditability and proper linkage, the comment
   * record stores the author's user ID, the target article's ID, the comment
   * text, and creation timestamps.
   *
   * Security is enforced to require authentication, and only registered users
   * may invoke this operation. Appropriate access control ensures that
   * unauthenticated or blocked users cannot post comments. Errors resulting
   * from validation failures (such as empty body or exceeding character limits)
   * are handled with clear messages, referencing business rules. If the
   * referenced article does not exist or is deleted, the operation will respond
   * with a not-found or access denied error in compliance with business error
   * handling policies.
   *
   * @param connection
   * @param articleId Unique identifier of the target article to which this
   *   comment will be attached.
   * @param body Submission information for the new comment. The body text must
   *   be between 1 and 1000 characters as per business validation rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleComment.ICreate,
  ): Promise<IDiscussionBoardArticleComment> {
    try {
      return await postDiscussionBoardUserArticlesArticleIdComments({
        user,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of comments for a specific
   * article (from discussion_board_article_comments table).
   *
   * Retrieve a filtered and paginated list of comments associated with a
   * specific article. This operation enables clients to efficiently fetch
   * discussion threads for an article while supporting text search,
   * author-based filtering, and sort order customization for both regular end
   * users and administrators.
   *
   * The response omits comments that have been soft-deleted ('deleted_at' is
   * set), except when accessed by administrators who require access to the
   * entire moderation history. Security is enforced so that only authorized
   * users can view hidden/deleted comment content or comments attached to
   * articles the user does not have permission to access. The essential
   * relationships among articles, users, and comments are preserved: each
   * comment returns summary-level information, including the comment author
   * (via user foreign key) and the associated article's unique identifier.
   *
   * Business validation enforces the following: only authenticated users can
   * retrieve comments; filtering and pagination are required for articles with
   * many comments; and soft-deleted comments are suppressed unless explicitly
   * requested by a privileged actor. This endpoint's advanced search enables
   * effective moderation workflows (e.g., filtering by reported status or date)
   * and supports all standard user-facing comment listing demands.
   *
   * @param connection
   * @param articleId Unique identifier of the target article whose comments are
   *   being listed (discussion_board_articles.id, UUID format).
   * @param body Filter, sort, and pagination settings for comment search.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleComment.IRequest,
  ): Promise<IPageIDiscussionBoardArticleComment.ISummary> {
    try {
      return await patchDiscussionBoardUserArticlesArticleIdComments({
        user,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the full details of a specific comment on an article by ID
   * (discussion_board_article_comments table).
   *
   * Retrieve the full details of a single comment attached to a specific
   * article. The comment is identified by its unique UUID and validated as
   * belonging to the specified article via the articleId parent parameter. The
   * operation ensures strict access control, showing comment content only to
   * authorized users (the comment's author, involved parties, or admin for
   * moderation/audit). If the comment is soft-deleted, it is hidden from
   * regular users and only retrievable by admin actors for compliance and
   * review. The response includes all standard comment fields, relations to the
   * article, and a link to the author for audit and rendering.
   *
   * Business validation logic ensures that users cannot retrieve comments
   * unrelated to the article context given in the path and that normal users
   * cannot access deleted or hidden content. The endpoint implementation
   * references all required fields as documented in the Prisma schema,
   * reflecting the permission, audit, and relationship requirements described
   * in the requirements analysis.
   *
   * @param connection
   * @param articleId Unique identifier of the article containing the comment
   *   (discussion_board_articles.id, UUID format).
   * @param commentId Unique identifier of the target comment to retrieve
   *   (discussion_board_article_comments.id, UUID format).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":commentId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticleComment> {
    try {
      return await getDiscussionBoardUserArticlesArticleIdCommentsCommentId({
        user,
        articleId,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Edit an existing comment on a specific article
   * (discussion_board_article_comments).
   *
   * This API operation permits an authenticated user to update the content of
   * one of their own comments beneath a specified article, or an admin to
   * moderate or edit any comment. The comment content must adhere to the valid
   * range of 1-1000 characters as per validation requirements. The system
   * verifies that the editing actor is either the original author of the
   * comment or an administrator with moderation privileges.
   *
   * Security logic prohibits users from editing others' comments unless they
   * are administrators, and both comment and article must not be marked as
   * deleted. Attempts to edit a deleted comment or comments under deleted
   * articles will result in a not-found or access denied error. The operation
   * updates the comment text and the updated_at timestamp; audit and moderation
   * tracking are handled at the service layer for compliance.
   *
   * @param connection
   * @param articleId Unique identifier of the parent article to which the
   *   comment belongs.
   * @param commentId Unique identifier of the comment to be edited.
   * @param body New comment body to update the existing comment. Text must be
   *   between 1 and 1000 characters per business validation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleComment.IUpdate,
  ): Promise<IDiscussionBoardArticleComment> {
    try {
      return await putDiscussionBoardUserArticlesArticleIdCommentsCommentId({
        user,
        articleId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
