import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardUserComments } from "../../../../providers/postDiscussionBoardUserComments";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { putDiscussionBoardUserCommentsCommentId } from "../../../../providers/putDiscussionBoardUserCommentsCommentId";
import { deleteDiscussionBoardUserCommentsCommentId } from "../../../../providers/deleteDiscussionBoardUserCommentsCommentId";

import { IDiscussionBoardComment } from "../../../../api/structures/IDiscussionBoardComment";

@Controller("/discussionBoard/user/comments")
export class DiscussionboardUserCommentsController {
  /**
   * Create a new comment on a discussion board article
   * (discussion_board_comments).
   *
   * Create a new comment on an existing discussion board article.
   *
   * This operation allows a registered user or admin to add commentary to a
   * specific article. Business rules require either a user or admin author and
   * a target article. The body of the comment is validated for length and can
   * include up to 2 file attachments (managed via a separate system).
   * Timestamps for creation and update are automatically recorded.
   *
   * Security is enforced by allowing only authenticated users or admins to
   * create comments. The operation references all necessary foreign keys for
   * article and author. On successful creation, the comment is immediately
   * available under the parent article as per board display logic.
   *
   * Soft deletion and moderation actions are managed by separate operations.
   * Attachments are handled through a subsidiary API, linked via returned
   * metadata.
   *
   * @param connection
   * @param body Details for creating a new comment, including target article,
   *   author, content, and optional attachments.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IDiscussionBoardComment.ICreate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await postDiscussionBoardUserComments({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the content of a discussion board comment
   * (discussion_board_comments).
   *
   * Update an existing comment associated with a discussion board article.
   *
   * This endpoint allows the owner (user or admin) of the comment, or a
   * platform administrator, to modify the content of a specific comment.
   * Business validation ensures that comment text length remains within allowed
   * limits (2–1000 characters), and the operation only applies to active
   * (non-soft-deleted) comments. Requests that attempt to update soft-deleted
   * comments result in an error.
   *
   * All modifications update the 'updated_at' timestamp and are subject to
   * audit for moderation purposes. If needed, attachment management occurs
   * separately from this operation. This operation fully complies with the
   * business rule that only authorized actors can update comment content, and
   * all actions are traceable for moderation audits.
   *
   * @param connection
   * @param commentId Unique identifier of the target comment.
   * @param body Fields required to update a discussion board comment.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardUserCommentsCommentId({
        user,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete a comment on the discussion board (discussion_board_comments).
   *
   * Perform a soft deletion of a discussion board comment.
   *
   * This endpoint allows the owner (user or admin) of the comment, or a
   * platform administrator, to mark a comment as deleted. Rather than
   * permanently removing the comment from the database, the operation sets the
   * deleted_at field to the current timestamp, preserving the comment for
   * compliance and moderation auditing.
   *
   * Attempts to delete comments that are already soft-deleted will return an
   * error. Related attachments are left intact but may be restricted from
   * normal display. Security checks ensure that only authorized users can
   * perform deletions, and all actions are logged for traceability and future
   * review.
   *
   * @param connection
   * @param commentId Unique identifier of the target comment.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await deleteDiscussionBoardUserCommentsCommentId({
        user,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
