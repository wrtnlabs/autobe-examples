import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postDiscussionBoardUserAbuseReports } from "../../../../providers/postDiscussionBoardUserAbuseReports";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";

import { IDiscussionBoardAbuseReport } from "../../../../api/structures/IDiscussionBoardAbuseReport";

@Controller("/discussionBoard/user/abuseReports")
export class DiscussionboardUserAbusereportsController {
  /**
   * Create a new abuse report for user-flagged inappropriate content.
   *
   * Submit a new report about content suspected of violating community
   * guidelines or policies. Registered end-users can use this operation to
   * report suspected abuses for either an article or comment. All reports must
   * include the identity of the reporting user, a target (article or comment
   * ID), the abuse category, a detailed explanation, and status is defaulted to
   * 'pending'.
   *
   * This operation supports rapid self-reporting for moderation triage and
   * ensures all incidents are available for administrative review. Input
   * validation enforces that at least one target (article or comment) is
   * referenced, that a recognized abuse category is specified, and that the
   * reason field is provided and within acceptable length for auditing. On
   * successful creation, the reported abuse is queued for moderation,
   * supporting timely investigation and compliance with policy enforcement and
   * audit requirements. Only authenticated users may submit abuse reports using
   * this endpoint.
   *
   * @param connection
   * @param body Information required for submitting an abuse report, including
   *   target, reporter identity, category, and reason
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IDiscussionBoardAbuseReport.ICreate,
  ): Promise<IDiscussionBoardAbuseReport> {
    try {
      return await postDiscussionBoardUserAbuseReports({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
