import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminModerationLogs } from "../../../../../providers/patchDiscussionBoardAdminModerationLogs";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminModerationLogsLogId } from "../../../../../providers/getDiscussionBoardAdminModerationLogsLogId";

import { IPageIDiscussionBoardModerationLog } from "../../../../../api/structures/IPageIDiscussionBoardModerationLog";
import { IDiscussionBoardModerationLog } from "../../../../../api/structures/IDiscussionBoardModerationLog";

@Controller("/discussionBoard/admin/moderation/logs")
export class DiscussionboardAdminModerationLogsController {
  /**
   * Search and retrieve a paginated list of moderation logs
   * (discussion_board_moderation_logs table) for admin audit and review.
   *
   * Retrieve a filtered and paginated list of moderation and administrative
   * actions recorded in the platform.
   *
   * This endpoint exposes the discussion_board_moderation_logs table, allowing
   * platform administrators to search and review the complete moderation
   * history. Each log entry includes detailed contextual data: which admin
   * performed the action, which target entity or user was affected, the type of
   * action taken (such as delete, edit, suspend), additional explanatory notes,
   * and precise timestamps. Filtering can be performed on all major columns,
   * such as admin ID, target entity type, action code, and time ranges. Full
   * text search is also supported against moderation notes for deep-dive
   * investigations.
   *
   * Security is paramount—this endpoint is strictly restricted to authorized
   * admin users due to the sensitive nature of moderation data. Logs are
   * immutable business records, and this endpoint is for review purposes only;
   * any modification of the underlying records is handled exclusively by
   * internal system processes. Pagination ensures scalability even as the
   * number of moderation events grows. Related endpoints include GET
   * /moderation/logs/{logId} for detail inspection of a specific event.
   *
   * @param connection
   * @param body Search, filter, and pagination criteria for moderation log
   *   listing, such as admin ID, action code, target entity, note keywords, and
   *   time ranges.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardModerationLog.IRequest,
  ): Promise<IPageIDiscussionBoardModerationLog.ISummary> {
    try {
      return await patchDiscussionBoardAdminModerationLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve full details for a specific moderation log entry in the
   * discussion_board_moderation_logs table by UUID.
   *
   * Retrieve the full detail for a specific moderation or administrative log
   * entry.
   *
   * This endpoint enables platform administrators to deeply inspect an
   * individual moderation event captured by the
   * discussion_board_moderation_logs table. Information returned includes all
   * available data fields: which administrator performed the action, what
   * target entity or user was affected, what specific moderation action was
   * applied, and the administrator's explanatory notes and timestamps. This
   * supports both live incident reviews and retrospective policy enforcement
   * audits. The log entry is identified using its UUID primary key (logId).
   * Access is strictly limited to authorized admin users for data
   * confidentiality. This API is tightly integrated with other incident
   * investigation and governance processes.
   *
   * @param connection
   * @param logId Unique identifier of the target moderation log entry (UUID
   *   primary key of discussion_board_moderation_logs).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":logId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("logId")
    logId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardModerationLog> {
    try {
      return await getDiscussionBoardAdminModerationLogsLogId({
        admin,
        logId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
