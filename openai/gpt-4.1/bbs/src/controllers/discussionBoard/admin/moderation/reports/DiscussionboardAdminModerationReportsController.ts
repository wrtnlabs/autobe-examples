import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminModerationReports } from "../../../../../providers/patchDiscussionBoardAdminModerationReports";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminModerationReportsReportId } from "../../../../../providers/getDiscussionBoardAdminModerationReportsReportId";
import { putDiscussionBoardAdminModerationReportsReportId } from "../../../../../providers/putDiscussionBoardAdminModerationReportsReportId";
import { deleteDiscussionBoardAdminModerationReportsReportId } from "../../../../../providers/deleteDiscussionBoardAdminModerationReportsReportId";

import { IPageIDiscussionBoardReport } from "../../../../../api/structures/IPageIDiscussionBoardReport";
import { IDiscussionBoardReport } from "../../../../../api/structures/IDiscussionBoardReport";

@Controller("/discussionBoard/admin/moderation/reports")
export class DiscussionboardAdminModerationReportsController {
  /**
   * Search and retrieve a filtered, paginated list of moderation reports
   * (discussion_board_reports table).
   *
   * Retrieve a filtered and paginated list of moderation reports that have been
   * created by users in relation to any articles, comments, or attachments
   * within the discussion board. This endpoint supports advanced searching and
   * filtering by the type of report target (article, comment, attachment),
   * report status (such as open, in_review, resolved, rejected, escalated),
   * reason keyword, reporter identity, or creation date range. Pagination and
   * ordering features are included to allow efficient workflow for moderators
   * reviewing large volumes of reports.
   *
   * Only administrators may access this operation; strong access controls are
   * enforced. The query supports full-text and field-based filters for
   * effective moderation triage, including locating urgent or unresolved
   * issues. For each report, the response includes relevant metadata and the
   * current processing status, supporting compliance with audit and data
   * retention requirements. Soft-deleted reports are filtered according to
   * compliance policy and are excluded from general search unless specifically
   * requested. This operation references all mandatory report schema fields and
   * allows correlation with upstream content and user records.
   *
   * @param connection
   * @param body Filtering and pagination criteria for moderation report search,
   *   including report type, status, keywords, reporter, and time range.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardReport.IRequest,
  ): Promise<IPageIDiscussionBoardReport.ISummary> {
    try {
      return await patchDiscussionBoardAdminModerationReports({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific moderation report from discussion_board_reports by
   * reportId.
   *
   * Retrieve the full detail of a specific user-submitted moderation report,
   * including the entity type flagged (article, comment, attachment), the
   * detailed reason and description, the status of the moderation process, and
   * the identity of the reporting user.
   *
   * The moderation report is stored in the 'discussion_board_reports' table,
   * which acts as a central registry for all flagged content requiring admin
   * attention. Each report captures the reporter's user account, the target
   * entity type, a reason string referencing platform moderation categories,
   * and the processing status (open, in_review, resolved, etc). This enables
   * thorough case-by-case review and upholds audit integrity for community rule
   * enforcement.
   *
   * This API endpoint is designed for platform administrators and moderators,
   * ensuring only actor 'admin' can access detailed moderation data, preserving
   * user privacy and enforcing strict content control. If the report does not
   * exist or has been deleted, the operation returns a clear not found
   * response, exercising robust error handling. Permissions are enforced as
   * outlined in the user actor permission schema.
   *
   * @param connection
   * @param reportId Unique identifier of the target moderation report case.
   *   Used to retrieve full details of a single report record in the moderation
   *   system.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reportId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardReport> {
    try {
      return await getDiscussionBoardAdminModerationReportsReportId({
        admin,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing moderation report in the discussion_board_reports table.
   *
   * Update an existing moderation report submitted by a user against
   * inappropriate articles, comments, or attachments. This operation enables
   * modifying the reason for reporting, additional user-supplied description,
   * or the processing status as the moderation review progresses.
   *
   * The target report is strictly identified by its unique reportId path
   * parameter, a string of UUID format, referencing the primary key in the
   * discussion_board_reports table. Only fields declared as mutable by business
   * rules are updated. System-managed timestamps such as created_at are not
   * updatable; updating deleted_at through this method is prohibited as
   * deletion is handled by a dedicated endpoint.
   *
   * Permission to update is governed by both authentication and report
   * ownership: users may only update their own reports, while administrators
   * may update any report as part of moderation workflow. Updates are validated
   * for allowed status changes and application context. Input is type-checked
   * and business requirements such as length constraints or allowed reasons are
   * enforced. All update events are logged for compliance audit.
   *
   * Associated operations: DELETE /moderation/reports/{reportId} is used for
   * soft deletion. PATCH operations may exist for moderation report searching
   * or bulk status updates.
   *
   * @param connection
   * @param reportId Unique identifier of the target moderation report to
   *   update, referencing the primary key in discussion_board_reports.
   * @param body Fields to update in user-submitted moderation report, such as
   *   reason, description, and status. All fields are subject to business rule
   *   validation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":reportId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardReport.IUpdate,
  ): Promise<IDiscussionBoardReport> {
    try {
      return await putDiscussionBoardAdminModerationReportsReportId({
        admin,
        reportId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete (set deleted_at) a moderation report in the
   * discussion_board_reports table.
   *
   * Soft delete a moderation report submitted by a user regarding inappropriate
   * or abusive content. This operation sets the deleted_at timestamp on the
   * specified report to indicate removal without erasing audit history,
   * following business and compliance policy for traceability.
   *
   * The report is identified by its unique reportId path parameter (UUID
   * string) corresponding to the primary key in the discussion_board_reports
   * table. Deletion is permitted only by the original reporting user or an
   * administrator. Soft deleted reports become inaccessible to regular users
   * and are omitted from standard queries, but remain available for compliance
   * auditing by administrators.
   *
   * Moderator workflows may require notification or further action upon report
   * deletion. When a report is deleted, referential integrity is checked to
   * ensure no orphaned moderation workflow states remain. Deletion actions are
   * always recorded in audit logs, and related search operations (PATCH
   * endpoints) will automatically exclude soft deleted records.
   *
   * @param connection
   * @param reportId Unique identifier of the moderation report to delete,
   *   corresponding to the primary key in discussion_board_reports.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reportId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardReport> {
    try {
      return await deleteDiscussionBoardAdminModerationReportsReportId({
        admin,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
