import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardAdminModerationLogs } from "../../../../providers/postDiscussionBoardAdminModerationLogs";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchDiscussionBoardAdminModerationLogs } from "../../../../providers/patchDiscussionBoardAdminModerationLogs";
import { getDiscussionBoardAdminModerationLogsModerationLogId } from "../../../../providers/getDiscussionBoardAdminModerationLogsModerationLogId";
import { putDiscussionBoardAdminModerationLogsModerationLogId } from "../../../../providers/putDiscussionBoardAdminModerationLogsModerationLogId";
import { deleteDiscussionBoardAdminModerationLogsModerationLogId } from "../../../../providers/deleteDiscussionBoardAdminModerationLogsModerationLogId";

import { IDiscussionBoardModerationLog } from "../../../../api/structures/IDiscussionBoardModerationLog";
import { IPageIDiscussionBoardModerationLog } from "../../../../api/structures/IPageIDiscussionBoardModerationLog";

@Controller("/discussionBoard/admin/moderationLogs")
export class DiscussionboardAdminModerationlogsController {
  /**
   * Create a new moderation log entry for an administrative action on the
   * discussion board.
   *
   * This endpoint supports the documentation and transparency of all moderation
   * events, capturing detailed records whenever an admin takes action on
   * articles, comments, or attachments. The operation requires specifying the
   * type of entity (target_type: "article", "comment", or "attachment"), its
   * unique identifier, the moderation action performed, a human-readable
   * rationale, the outcome after the action, and identifies the responsible
   * admin. The created_at timestamp precisely records when the action was
   * performed using UTC in ISO 8601 format.
   *
   * Security: Only authenticated admin users are allowed to create moderation
   * logs. The action and outcome fields require controlled vocabularies
   * matching valid moderation actions and post-action statuses. The database
   * maintains uniqueness for each action instance per entity and time, and
   * admin_id must refer to a valid discussion_board_admins record. This
   * operation never deletes log entries, preserving the entire history needed
   * for compliance or investigation workflows. Related endpoints include
   * retrieval and searching by filters, but deletion is never permitted for
   * this table.
   *
   * @param connection
   * @param body Details of the new moderation event to be logged, including
   *   target type and id, action, rationale, outcome, admin, and timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardModerationLog.ICreate,
  ): Promise<IDiscussionBoardModerationLog> {
    try {
      return await postDiscussionBoardAdminModerationLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of moderation log entries reflecting
   * all administrative moderation actions performed within the discussion board
   * platform.
   *
   * This operation provides auditors or board administrators advanced search
   * capabilities to locate moderation decisions based on entity type (article,
   * comment, attachment), action (remove, edit, ban, etc.), responsible admin
   * account, target item, rationale, outcome, and precise timestamp. All fields
   * defined in the Prisma schema can be used for filtering or search criteria.
   *
   * Results are paginated and can be sorted by time or admin. Only users with
   * appropriate administrative privileges can access this data, ensuring
   * confidentiality and compliance with privacy policies. This operation
   * references the discussion_board_moderation_logs table in full fidelity and
   * is aligned with its field-level documentation. Related endpoints allow
   * detail retrieval or temporal analytics as required. Rate limiting and
   * logging may be enforced for excessive access.
   *
   * @param connection
   * @param body Search, filter, and pagination parameters for moderation log
   *   retrieval.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardModerationLog.IRequest,
  ): Promise<IPageIDiscussionBoardModerationLog.ISummary> {
    try {
      return await patchDiscussionBoardAdminModerationLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete details for a specific moderation event as tracked in the
   * discussion board moderation log table.
   *
   * This operation enables an authorized administrator or auditor to review all
   * aspects of a given moderation action, including what was acted upon
   * (article, comment, or attachment), which admin performed the action, action
   * taken, the reason declared, the outcome, and exact UTC timestamp. Access is
   * restricted to users with administrative privileges, and such accesses may
   * themselves be logged per audit requirements. Field mapping and entity
   * reference use the discussion_board_moderation_logs table as fully defined
   * in the Prisma schema, ensuring all relational and metadata fields are
   * transparently surfaced for business and compliance needs.
   *
   * Related operations include listing/searching moderation logs and retrieving
   * entity details by ID for entities acted upon.
   *
   * @param connection
   * @param moderationLogId Unique identifier (UUID) of the moderation log entry
   *   to retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":moderationLogId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("moderationLogId")
    moderationLogId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardModerationLog> {
    try {
      return await getDiscussionBoardAdminModerationLogsModerationLogId({
        admin,
        moderationLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Modify select fields (such as rationale or outcome) of a previously
   * recorded moderation event in the discussion board logs.
   *
   * This endpoint supports the need to correct or expand the historical record
   * of a moderation action after its creation, subject to strict compliance
   * requirements. The operation ensures that primary audit-traceable event
   * attributes (target_type, target_id, action, created_at, admin_id) remain
   * unaltered to preserve historical integrity. Only fields intended for
   * correction or commentary can be updated, such as the rationale or outcome,
   * as permitted by organizational policy. The system must verify that
   * moderationLogId exists and is correctly referenced before applying any
   * changes.
   *
   * Security: Only authenticated admin users are authorized to perform updates
   * on moderation log records. All updates are themselves audited, and changes
   * are expected to be rare and well-justified. Deletion is never permitted for
   * records in this table, and the complete log history is preserved for
   * compliance, investigative, and governance needs. This operation should be
   * used sparingly and only with proper authorization controls.
   *
   * @param connection
   * @param moderationLogId Unique identifier (UUID) of the moderation log
   *   record to be updated.
   * @param body Fields to update on the moderation log entry (usually
   *   rationale, outcome, or admin remarks).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":moderationLogId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("moderationLogId")
    moderationLogId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardModerationLog.IUpdate,
  ): Promise<IDiscussionBoardModerationLog> {
    try {
      return await putDiscussionBoardAdminModerationLogsModerationLogId({
        admin,
        moderationLogId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation removes a moderation log event entry from the discussion
   * board's moderation log table. The moderation log tracks every
   * administrative event performed on articles, comments, or attachments,
   * maintaining detailed records (target type/id, action, reason, outcome,
   * timestamps, admin performer) for audit and compliance.
   *
   * Under normal operations, moderation log entries are never deleted, in order
   * to preserve a full historical record for transparency. This delete
   * operation should only be performed under exceptional administrative
   * circumstances, such as data cleanup mandated by legal, privacy, or
   * compliance requirements. Deletion is irreversible and must be performed by
   * administrators with appropriate clearance.
   *
   * Strict authorization is enforced; only system administrators may invoke
   * this endpoint, and all deletions should themselves be logged in separate
   * secure audit channels if required for compliance. Removing a moderation log
   * entry does not alter the state of the moderated article, comment, or
   * attachment, but reduces overall auditability. Errors will be returned if
   * the specified log entry does not exist.
   *
   * @param connection
   * @param moderationLogId Unique identifier (UUID) of the moderation log event
   *   to delete. (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":moderationLogId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("moderationLogId")
    moderationLogId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminModerationLogsModerationLogId({
        admin,
        moderationLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
