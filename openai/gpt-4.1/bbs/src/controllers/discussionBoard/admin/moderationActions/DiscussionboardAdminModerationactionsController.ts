import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardAdminModerationActions } from "../../../../providers/postDiscussionBoardAdminModerationActions";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchDiscussionBoardAdminModerationActions } from "../../../../providers/patchDiscussionBoardAdminModerationActions";
import { getDiscussionBoardAdminModerationActionsModerationActionId } from "../../../../providers/getDiscussionBoardAdminModerationActionsModerationActionId";
import { putDiscussionBoardAdminModerationActionsModerationActionId } from "../../../../providers/putDiscussionBoardAdminModerationActionsModerationActionId";
import { deleteDiscussionBoardAdminModerationActionsModerationActionId } from "../../../../providers/deleteDiscussionBoardAdminModerationActionsModerationActionId";

import { IDiscussionBoardModerationAction } from "../../../../api/structures/IDiscussionBoardModerationAction";
import { IPageIDiscussionBoardModerationAction } from "../../../../api/structures/IPageIDiscussionBoardModerationAction";

@Controller("/discussionBoard/admin/moderationActions")
export class DiscussionboardAdminModerationactionsController {
  /**
   * Create a new moderation action by an administrator
   * (discussion_board_moderation_actions table).
   *
   * Create a new moderation action that is taken by an administrative actor.
   * Actions can include 'edit', 'delete', 'hide', or 'warn', targeting either
   * articles or comments as specified by the admin. Every action requires
   * complete references to the target (article or comment), the reason for
   * moderation, and a justification description according to business audit
   * requirements. The operation validates that the admin is authorized and that
   * referenced content exists prior to storing the action. If a related abuse
   * report exists, it is also referenced to close the audit loop. Actions are
   * permanently recorded for regulatory and compliance traceability. Returns
   * the complete moderation action record on success, including all referenced
   * foreign keys.
   *
   * @param connection
   * @param body Information for creating a new moderation action, including
   *   admin actor, target object(s), action type, reason, and data reference.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardModerationAction.ICreate,
  ): Promise<IDiscussionBoardModerationAction> {
    try {
      return await postDiscussionBoardAdminModerationActions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search, filter, and retrieve a paginated list of discussion board
   * moderation actions (table: discussion_board_moderation_actions).
   *
   * Retrieve a filtered and paginated list of moderation actions performed by
   * administrators on the discussion board system. This endpoint provides
   * advanced search capabilities for examining moderation activity, including
   * action type (edit, delete, hide, warn), affected article or comment,
   * justification for moderation, and the responsible admin profile. Results
   * can be filtered by date range, admin, specific articles or comments, or
   * moderation type, supporting compliance audit and workflow review purposes.
   *
   * This operation queries the discussion_board_moderation_actions table as
   * defined in the Prisma schema, making use of all indexed and full-text
   * searchable fields (action_reason, action_type, related
   * article/comment/admin, creation date, etc.) for efficient audits. It
   * integrates with review dashboards for system operators and compliance
   * teams. Returned data omits sensitive content unless explicitly requested by
   * authorized actors and applies row-level filtering based on the requesting
   * admin's permissions.
   *
   * Security is enforced via admin-only authentication. All access and query
   * events through this endpoint are logged in the audit trail. Pagination
   * ensures scalable queries for large volumes of moderation records.
   * Authorization checks prevent exposure to non-admin actors and restrict
   * export of raw data to authorized staff only.
   *
   * @param connection
   * @param body Search and filter criteria including moderator/admin,
   *   moderation type, article/comment targets, date ranges, and pagination
   *   options.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardModerationAction.IRequest,
  ): Promise<IPageIDiscussionBoardModerationAction.ISummary> {
    try {
      return await patchDiscussionBoardAdminModerationActions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get full details on a specific discussion board moderation action (table:
   * discussion_board_moderation_actions).
   *
   * Fetch the complete detail record for a specific moderation action performed
   * on the discussion board. Moderation actions capture edits, deletions,
   * hides, warning events, and associated justifications tied to affected
   * articles or comments. This endpoint retrieves the action meta-information,
   * including admin identity, type of action, reason, referenced article or
   * comment, and related audit references.
   *
   * The operation references the discussion_board_moderation_actions table in
   * the Prisma schema and is accessed using a unique moderationActionId
   * parameter (UUID). The response includes all actionable information for
   * compliance, audit, and detailed review of moderation workflows, supporting
   * regulatory requirements and system diagnostics.
   *
   * Only admin actors are authorized for this operation. System logging and
   * auditing mechanisms apply to all access of moderation details, and
   * row-level permissions may be enforced in multi-admin environments to
   * support privacy and need-to-know principles. Error responses are returned
   * if the moderation action record does not exist or if the actor lacks
   * sufficient permissions.
   *
   * @param connection
   * @param moderationActionId Unique identifier of the target moderation action
   *   event record (UUID) in the discussion_board_moderation_actions table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":moderationActionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("moderationActionId")
    moderationActionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardModerationAction> {
    try {
      return await getDiscussionBoardAdminModerationActionsModerationActionId({
        admin,
        moderationActionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing moderation action by its ID
   * (discussion_board_moderation_actions table).
   *
   * Update certain fields of a previously recorded moderation action. Only
   * admin actors are authorized to perform updates, which are restricted to
   * fields allowed by policy (e.g., adding additional audit notes or correcting
   * the action_reason). The operation requires the moderation action ID in the
   * path and ensures that referenced action exists. Immutable historical data,
   * such as the original actor and referenced target, cannot be changed,
   * protecting audit integrity. Enforcement includes validating field changes
   * versus allowed update schema and logging every modification. Returns the
   * updated moderation action entity if successful.
   *
   * @param connection
   * @param moderationActionId Unique identifier of the moderation action to
   *   update.
   * @param body Fields and audit notes for updating an existing moderation
   *   action. Only allowed fields per compliance policy will be processed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":moderationActionId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("moderationActionId")
    moderationActionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardModerationAction.IUpdate,
  ): Promise<IDiscussionBoardModerationAction> {
    try {
      return await putDiscussionBoardAdminModerationActionsModerationActionId({
        admin,
        moderationActionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a discussion board moderation action record by its
   * unique ID.
   *
   * This API endpoint allows an administrator to delete a specific moderation
   * action by providing its unique identifier. Moderation actions are critical
   * audit records describing interventions taken by administrators, such as
   * content hides, deletions, or warnings. Deleting a moderation action is a
   * permanent action and should be restricted to cases of erroneous or
   * accidental entries, or regulatory requirements demanding erasure.
   *
   * The operation interacts directly with the
   * discussion_board_moderation_actions table, ensuring that related child
   * entities such as audit logs remain present for compliance but will
   * reference a now-absent moderation action. Calling this operation with a
   * valid ID will remove the moderation action completely from the database;
   * there is no soft delete. Attempting to delete a non-existent or
   * already-removed action will return an error message indicating its
   * unavailability.
   *
   * Only administrators with sufficient privileges are authorized to use this
   * endpoint. Authorization checks must be enforced to prevent non-admins from
   * deleting moderation logs. Audit logs of the delete operation itself should
   * be maintained separately to ensure regulatory completeness and support
   * incident investigations.
   *
   * @param connection
   * @param moderationActionId Unique identifier of the moderation action to be
   *   permanently deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":moderationActionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("moderationActionId")
    moderationActionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminModerationActionsModerationActionId(
        {
          admin,
          moderationActionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
