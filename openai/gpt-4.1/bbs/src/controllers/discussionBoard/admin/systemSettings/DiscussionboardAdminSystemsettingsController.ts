import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardAdminSystemSettings } from "../../../../providers/postDiscussionBoardAdminSystemSettings";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchDiscussionBoardAdminSystemSettings } from "../../../../providers/patchDiscussionBoardAdminSystemSettings";
import { getDiscussionBoardAdminSystemSettingsKey } from "../../../../providers/getDiscussionBoardAdminSystemSettingsKey";
import { putDiscussionBoardAdminSystemSettingsKey } from "../../../../providers/putDiscussionBoardAdminSystemSettingsKey";
import { deleteDiscussionBoardAdminSystemSettingsKey } from "../../../../providers/deleteDiscussionBoardAdminSystemSettingsKey";

import { IDiscussionBoardSystemSetting } from "../../../../api/structures/IDiscussionBoardSystemSetting";
import { IPageIDiscussionBoardSystemSetting } from "../../../../api/structures/IPageIDiscussionBoardSystemSetting";

@Controller("/discussionBoard/admin/systemSettings")
export class DiscussionboardAdminSystemsettingsController {
  /**
   * Create a new global system setting in the discussion_board_system_settings
   * table.
   *
   * Create a new system-level configuration setting for the discussion board
   * platform.
   *
   * This operation enables administrators or system operators to introduce new
   * platform-wide settings identified by a unique key, supporting policy,
   * operational, or technical controls. The value can hold raw data, serialized
   * JSON, or policy text, while an optional description field provides
   * human-readable documentation of the setting's purpose.
   *
   * The operation validates that the provided 'key' does not conflict with
   * existing records in the discussion_board_system_settings table, leveraging
   * the unique constraint on 'key'. Upon creation, 'created_at' and
   * 'updated_at' timestamps are set to the current time, and the entry will
   * appear in the audit trail for administrative review.
   *
   * Only users with administrative privileges may execute this operation to
   * prevent unauthorized modification of universal system configuration. The
   * operation returns the full configuration setting as created, including
   * metadata fields for change tracking.
   *
   * @param connection
   * @param body Payload defining the new configuration setting, including
   *   unique key, value, and optionally a description.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardSystemSetting.ICreate,
  ): Promise<IDiscussionBoardSystemSetting> {
    try {
      return await postDiscussionBoardAdminSystemSettings({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of discussion board system
   * settings.
   *
   * Retrieve a paginated and filterable list of all system-level configuration
   * entries within the discussion board platform.
   *
   * This endpoint enables platform administrators to search, sort, and review
   * system settings that control core business and technical behavior.
   * Administrators may filter entries based on configuration key or partial
   * matches within values or descriptions, supporting efficient review and
   * audit. The operation supports pagination to handle large numbers of
   * settings, ensuring performant and manageable responses even as the list of
   * policies grows.
   *
   * Security is enforced by restricting access to administrative actors only.
   * Sensitive policy modifications and audits should be performed using this
   * endpoint in conjunction with corresponding create/update operations. The
   * action references the 'discussion_board_system_settings' table and
   * leverages Prisma's model comments for field-level business meaning.
   * Expected edge cases include handling settings with incomplete descriptions
   * or placeholder values.
   *
   * @param connection
   * @param body Search and filtering parameters for retrieving relevant system
   *   settings, including pagination and query terms.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardSystemSetting.IRequest,
  ): Promise<IPageIDiscussionBoardSystemSetting.ISummary> {
    try {
      return await patchDiscussionBoardAdminSystemSettings({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific discussion board system setting using its
   * unique key.
   *
   * Retrieve detailed information on a specific system-wide configuration
   * setting by its unique policy key.
   *
   * Administrators access this endpoint to view the full current state of a
   * particular platform setting, including value, audit timestamps, and
   * descriptive metadata. This is critical for change management, audit, and
   * validation of system operational parameters. The operation is restricted to
   * administrative access to prevent unauthorized disclosure of sensitive
   * configuration. The endpoint draws field structure and business meaning from
   * the 'discussion_board_system_settings' Prisma model, ensuring only
   * authorized actors can change or inspect global policy. Validation strictly
   * enforces that the key matches an existing setting; failures should return a
   * clear not-found response.
   *
   * Use this operation alongside search/list endpoints for targeted review and
   * policy management workflows. Typical use cases include compliance audit,
   * security review, or business rules analysis.
   *
   * @param connection
   * @param key Unique identifier for the configuration setting (global scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":key")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("key")
    key: string,
  ): Promise<IDiscussionBoardSystemSetting> {
    try {
      return await getDiscussionBoardAdminSystemSettingsKey({
        admin,
        key,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing global system setting (by key) in the
   * discussion_board_system_settings table.
   *
   * Update an existing platform-wide system configuration setting by its unique
   * key.
   *
   * This operation allows administrators to modify the value or description
   * fields tied to a specific configuration. The reference to the configuration
   * is made using the 'key' path parameter, which is enforced as globally
   * unique by the Prisma schema. If the setting does not exist, the operation
   * results in a not found error.
   *
   * The operation ensures that only administrators with appropriate privileges
   * may perform updates. It updates the 'updated_at' timestamp automatically,
   * and all changes are recorded for audit and potential rollback. Only the
   * 'value' and 'description' fields can be changed—'key' and audit metadata
   * (including 'created_at' and 'deleted_at') are server-managed. The returned
   * object includes the fully updated system setting.
   *
   * @param connection
   * @param key Unique identifier for this configuration setting (global scope)
   *   as defined by the discussion_board_system_settings schema.
   * @param body Payload specifying the updated value and/or description for the
   *   configuration setting; 'key' is derived from the path parameter and must
   *   not be duplicated in the body.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":key")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("key")
    key: string & tags.MinLength<1>,
    @TypedBody()
    body: IDiscussionBoardSystemSetting.IUpdate,
  ): Promise<IDiscussionBoardSystemSetting> {
    try {
      return await putDiscussionBoardAdminSystemSettingsKey({
        admin,
        key,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a system-wide configuration setting by key
   * (discussion_board_system_settings table).
   *
   * Remove a specific system-wide configuration setting identified by its key.
   * This operation empowers administrators to manage and clean up obsolete or
   * incorrect configuration entries that affect the entire discussion board
   * platform.
   *
   * Only users with administrative privileges can invoke this endpoint.
   * Business logic enforces existence checks and ensures that only valid
   * configuration keys are permitted for deletion. An attempt to delete a
   * non-existent key will result in a clear, actionable error message.
   *
   * While the schema supports soft deletion via a deleted_at field, this
   * endpoint executes a permanent removal of the configuration entry, erasing
   * it from the active configuration space. Audit and rollback capabilities
   * should be handled separately at the business or infrastructure level.
   *
   * This operation complements other configuration management endpoints,
   * allowing for full-lifecycle control of platform settings. Admins should use
   * this cautiously, as deleted settings cannot be restored via this endpoint.
   *
   * @param connection
   * @param key Unique identifier for this configuration setting in the system
   *   settings table (global scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":key")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("key")
    key: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminSystemSettingsKey({
        admin,
        key,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
