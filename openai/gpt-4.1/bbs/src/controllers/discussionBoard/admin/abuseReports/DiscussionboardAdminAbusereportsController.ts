import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminAbuseReports } from "../../../../providers/patchDiscussionBoardAdminAbuseReports";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminAbuseReportsAbuseReportId } from "../../../../providers/getDiscussionBoardAdminAbuseReportsAbuseReportId";
import { putDiscussionBoardAdminAbuseReportsAbuseReportId } from "../../../../providers/putDiscussionBoardAdminAbuseReportsAbuseReportId";
import { deleteDiscussionBoardAdminAbuseReportsAbuseReportId } from "../../../../providers/deleteDiscussionBoardAdminAbuseReportsAbuseReportId";

import { IPageIDiscussionBoardAbuseReport } from "../../../../api/structures/IPageIDiscussionBoardAbuseReport";
import { IDiscussionBoardAbuseReport } from "../../../../api/structures/IDiscussionBoardAbuseReport";

@Controller("/discussionBoard/admin/abuseReports")
export class DiscussionboardAdminAbusereportsController {
  /**
   * Search and retrieve a filtered, paginated list of abuse reports for
   * moderation, moderation review, and compliance
   * (discussion_board_abuse_reports table).
   *
   * Retrieve a filtered and paginated list of abuse reports submitted by users
   * through the discussion board system. This endpoint allows moderators to
   * review, filter, and sort reports by various criteria, including abuse type
   * (spam, harassment, etc.), status (pending, closed, etc.), report time,
   * reporter identity, and targeted articles or comments.
   *
   * Pagination options and comprehensive sorting enable efficient moderation
   * triage and workload distribution. Advanced filtering supports compliance
   * investigation by regulatory and legal reviewers. Security and audit
   * controls ensure only users with administrative privilege (admins) can
   * access this endpoint.
   *
   * Error responses are provided for invalid filtering or access violations.
   * The response returns a page of summarized abuse report entries as defined
   * by the DTO.
   *
   * @param connection
   * @param body Criteria for filtering, paginating, and sorting abuse reports
   *   as part of moderation or compliance review.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAbuseReport.IRequest,
  ): Promise<IPageIDiscussionBoardAbuseReport.ISummary> {
    try {
      return await patchDiscussionBoardAdminAbuseReports({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve an abuse report and all its details by unique ID from the
   * database.
   *
   * Retrieve the details of a specific abuse report from the system by
   * providing its unique identifier. This operation is essential for
   * administrative moderation workflows, allowing authorized reviewers to
   * examine abuse reports submitted by users concerning suspicious articles or
   * comments.
   *
   * The abuse report record includes the reporter's user ID, the targeted
   * article or comment IDs, a categorization of the abuse (such as 'spam',
   * 'harassment', or 'illegal'), and the detailed rationale given by the
   * reporting user. The response contains full state information regarding the
   * report, including its status (e.g., pending, in_review, closed) and all
   * audit fields for traceability and compliance.
   *
   * Security and privacy requirements dictate that only administrators are
   * allowed to use this endpoint, as abuse report content and workflow status
   * involve confidential moderation information. The endpoint directly
   * references the discussion_board_abuse_reports table, and the provided ID
   * must match an existing database record to retrieve its information.
   *
   * @param connection
   * @param abuseReportId Unique identifier of the target abuse report
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":abuseReportId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("abuseReportId")
    abuseReportId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAbuseReport> {
    try {
      return await getDiscussionBoardAdminAbuseReportsAbuseReportId({
        admin,
        abuseReportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an abuse report record in the discussion_board_abuse_reports table.
   *
   * Update an existing abuse report's information in the moderation subsystem.
   * This endpoint supports changing the abuse report's workflow status (for
   * example, from 'pending' to 'in_review' or 'closed'), updating the abuse
   * category, or amending the detailed reason text as needed during
   * moderation.
   *
   * Access to this operation is restricted to authenticated administrators, as
   * defined in the discussion_board_admins table. The implementation enforces
   * audit via moderation actions (logged in related tables) and maintains data
   * consistency with the abuse report's status lifecycle. The endpoint also
   * applies full payload validation, including possible restrictions on allowed
   * status values and abuse category types.
   *
   * The specification references the 'discussion_board_abuse_reports' table
   * fields and incorporates associated business logic for report management and
   * compliance audit. Input is expected to follow the
   * IDiscussionBoardAbuseReport.IUpdate DTO, while the response returns the
   * updated report as IDiscussionBoardAbuseReport.
   *
   * @param connection
   * @param abuseReportId Unique identifier (UUID) of the targeted abuse report
   *   to update.
   * @param body Fields and values to update on the abuse report record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":abuseReportId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("abuseReportId")
    abuseReportId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardAbuseReport.IUpdate,
  ): Promise<IDiscussionBoardAbuseReport> {
    try {
      return await putDiscussionBoardAdminAbuseReportsAbuseReportId({
        admin,
        abuseReportId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently erase an abuse report from the discussion_board_abuse_reports
   * table.
   *
   * Permanently delete an abuse report from the system using its unique report
   * ID. This operation is strictly reserved for administrative actors and
   * should be used carefully, as it irreversibly removes all traces of the
   * report and associated moderation actions in accordance with business data
   * retention policies.
   *
   * This operation references the 'discussion_board_abuse_reports' table and is
   * designed for compliance with regulatory or internal data purging workflows.
   * It is critical to record the deletion event in the audit log tables,
   * providing traceability about which admin performed the removal and the
   * identified reason. Only authenticated admins may invoke this operation, and
   * all business constraints must be strictly followed.
   *
   * Proper business process should ensure that deletion is only allowed when
   * the report is in a terminal status (such as 'closed' or 'rejected'), and
   * all related moderation actions have been fully resolved.
   *
   * @param connection
   * @param abuseReportId Unique identifier (UUID) of the abuse report to be
   *   deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":abuseReportId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("abuseReportId")
    abuseReportId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminAbuseReportsAbuseReportId({
        admin,
        abuseReportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
