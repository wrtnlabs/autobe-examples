import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminAuditLogs } from "../../../../providers/patchDiscussionBoardAdminAuditLogs";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminAuditLogsAuditLogId } from "../../../../providers/getDiscussionBoardAdminAuditLogsAuditLogId";

import { IPageIDiscussionBoardAuditLog } from "../../../../api/structures/IPageIDiscussionBoardAuditLog";
import { IDiscussionBoardAuditLog } from "../../../../api/structures/IDiscussionBoardAuditLog";

@Controller("/discussionBoard/admin/auditLogs")
export class DiscussionboardAdminAuditlogsController {
  /**
   * Query and retrieve a paginated, filtered list of discussion board audit
   * logs.
   *
   * This API endpoint enables administrative actors to search, filter, and page
   * through the set of audit logs recording all moderation and
   * compliance-relevant events within the discussion board. Audit logs capture
   * events such as moderation actions, compliance overrides, manual restores,
   * admin interventions, and contain references to the responsible
   * administrator, affected articles/comments, and related moderation actions.
   *
   * The resulting records are drawn from the discussion_board_audit_logs table,
   * incorporating filter criteria for event type, admin actor, date/time range,
   * and affected resources. Full-text search is available on audit_details to
   * facilitate incident review and regulatory compliance.
   *
   * This endpoint is designed for privileged access by administrators to
   * support platform governance, periodic reviews, and detailed compliance
   * reporting. Results are paginated and optimized for large data sets and
   * audit-heavy environments. Only authorized administrators should be able to
   * access these records to preserve privacy and security.
   *
   * @param connection
   * @param body Criteria for filtering, searching, sorting, and paginating
   *   audit log records
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAuditLog.IRequest,
  ): Promise<IPageIDiscussionBoardAuditLog.ISummary> {
    try {
      return await patchDiscussionBoardAdminAuditLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific audit log entry by ID from discussion_board_audit_logs.
   *
   * Retrieve the full details of a specific audit log entry associated with
   * moderation or system actions performed by administrators. This operation is
   * vital for tracking historic moderation actions, incident reviews, and
   * regulatory audits. The audit log record includes information such as the
   * actor admin ID, target article or comment IDs (if applicable), the
   * moderation action ID, the type of audit event (for example,
   * moderation_performed, compliance_override, or manual_restore), a free-text
   * justification or set of audit details, and the precise timestamp of audit
   * event creation.
   *
   * Access to audit log records is typically restricted to admin users or
   * compliance personnel due to the sensitive nature of logged actions. The
   * returned information is drawn directly from the discussion_board_audit_logs
   * table, matching the schema's definitions for each field and relationship,
   * ensuring a consistent and detailed historical record for each critical
   * event in the discussion board system.
   *
   * Permissions are tightly regulated to ensure that audit logs cannot be
   * modified or deleted; this endpoint only returns data and enforces strict
   * access controls as modeled in the Prisma schema. Audit logs are a
   * cornerstone of compliance, security, and dispute resolution, and should be
   * reviewed only by authorized personnel.
   *
   * @param connection
   * @param auditLogId Unique identifier of the target audit log record (UUID as
   *   defined by the discussion_board_audit_logs table).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":auditLogId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("auditLogId")
    auditLogId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAuditLog> {
    try {
      return await getDiscussionBoardAdminAuditLogsAuditLogId({
        admin,
        auditLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
