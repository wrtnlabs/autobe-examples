import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardAdminAttachments } from "../../../../providers/postDiscussionBoardAdminAttachments";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchDiscussionBoardAdminAttachments } from "../../../../providers/patchDiscussionBoardAdminAttachments";
import { getDiscussionBoardAdminAttachmentsAttachmentId } from "../../../../providers/getDiscussionBoardAdminAttachmentsAttachmentId";
import { putDiscussionBoardAdminAttachmentsAttachmentId } from "../../../../providers/putDiscussionBoardAdminAttachmentsAttachmentId";
import { deleteDiscussionBoardAdminAttachmentsAttachmentId } from "../../../../providers/deleteDiscussionBoardAdminAttachmentsAttachmentId";

import { IDiscussionBoardAttachment } from "../../../../api/structures/IDiscussionBoardAttachment";
import { IPageIDiscussionBoardAttachment } from "../../../../api/structures/IPageIDiscussionBoardAttachment";

@Controller("/discussionBoard/admin/attachments")
export class DiscussionboardAdminAttachmentsController {
  /**
   * Registers and records technical metadata for a new file or image uploaded
   * to the discussion board platform. This call initializes a persistent
   * attachment entry, storing user-provided details and internal storage
   * references.
   *
   * Upon upload, the system captures and stores metadata including the original
   * and internal filenames, file size in bytes, MIME type, and a
   * cryptographically secure SHA-256 checksum used to detect duplicates and
   * support security compliance. The storage provider location (local path or
   * cloud bucket) is also recorded, ensuring the backend can manage the
   * attachment lifecycle independently from any business object (e.g., article,
   * comment).
   *
   * File creation and update audit timestamps are set on record creation.
   * Validation enforces file size and MIME type requirements, and checks for
   * duplicate files using the checksum. Invalid or already-present files are
   * rejected with descriptive error codes, supporting best practices for
   * attachment management, compliance, and audit readiness. This operation does
   * not link the file to any business entity; such associations are managed in
   * downstream tables and logic.
   *
   * @param connection
   * @param body All required data needed to register an uploaded file's
   *   metadata and storage references.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAttachment.ICreate,
  ): Promise<IDiscussionBoardAttachment> {
    try {
      return await postDiscussionBoardAdminAttachments({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered, searchable, and paginated list of all attachments
   * managed by the discussion board system. Every uploaded attachment, whether
   * actively linked to content or soft-deleted, is discoverable via this
   * endpoint, which supports server-side filtering by file properties and
   * deletion status.
   *
   * Administrators can search using original filename, MIME type, file size
   * boundaries, upload/deletion windows, or general status, enabling detailed
   * storage management, audit review, and compliance checks. Returned data
   * includes file metadata, storage paths (for backend use), audit timestamps,
   * deletion status, and cryptographic checksums for deduplication and
   * monitoring.
   *
   * Access requires administrator privileges. Output includes both active and
   * soft-deleted files dependent on filter input. For each result, attachment
   * status, full technical details, and creation/update/deletion audit fields
   * are provided. The endpoint is essential for visibility into storage
   * resource utilization and compliance with attachment-related policy
   * enforcement. Errors are handled gracefully, with clear explanations for bad
   * filter parameters or out-of-range queries.
   *
   * @param connection
   * @param body Attachment filtering and pagination/search parameters for
   *   attachment list retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAttachment.IRequest,
  ): Promise<IPageIDiscussionBoardAttachment> {
    try {
      return await patchDiscussionBoardAdminAttachments({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete technical metadata and storage characteristics for a
   * specific attachment associated with the discussion board platform. This
   * operation allows clients to fetch all details for a single file or image
   * via its unique identifier.
   *
   * The returned information includes the user-supplied original filename,
   * internal storage filename and location, exact byte size, MIME type, and a
   * checksum used for duplicate detection and security auditing. Administrative
   * and compliance fields such as deletion timestamp and audit trails (created
   * and updated timestamps) are provided to support management, traceability,
   * and potential audit requirements.
   *
   * Only non-deleted attachments may be retrieved; requests for missing,
   * deleted, or invalid attachmentId values generate not-found errors. This
   * operation serves both UI file viewers and any back-end correction,
   * compliance, or auditing workflow that requires full file details. Related
   * listing and upload operations (PATCH, POST) are available for bulk
   * management and creation of attachments.
   *
   * @param connection
   * @param attachmentId Universally unique file identifier of the attachment
   *   record (UUID format). Use this to fetch a specific item's metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":attachmentId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAttachment> {
    try {
      return await getDiscussionBoardAdminAttachmentsAttachmentId({
        admin,
        attachmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the metadata (technical information) of an attachment object in the
   * discussion board system.
   *
   * This operation permits administrators to correct or modify technical
   * metadata fields such as the storage filename, MIME type, storage provider,
   * or file size in bytes. It does not enable the replacement or direct
   * modification of the underlying file contents; user-facing fields such as
   * the original user-uploaded filename remain immutable except for technical
   * corrections.
   *
   * The operation enforces strict field validations per the Prisma schema to
   * prevent impossible, malicious, or contradictory changes. All changes are
   * captured via the updated_at field, supporting forensic audit and root-cause
   * analysis if problems arise. An attempt to update non-editable or critical
   * identity fields (e.g., id, checksum_sha256, created_at) will result in a
   * validation error.
   *
   * Proper authorization is required, typically restricted to system
   * administrators. File content and business associations (such as article
   * linkage) are managed through other business-layer operations, not directly
   * in this endpoint.
   *
   * @param connection
   * @param attachmentId Unique identifier (UUID) of the target attachment
   *   record in the discussion_board_attachments table.
   * @param body Editable metadata fields for the attachment, per schema. Does
   *   not include primary key or creation timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":attachmentId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardAttachment.IUpdate,
  ): Promise<IDiscussionBoardAttachment> {
    try {
      return await putDiscussionBoardAdminAttachmentsAttachmentId({
        admin,
        attachmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Mark an attachment as deleted in the discussion board system (soft delete
   * only).
   *
   * This operation updates the deleted_at timestamp for a specific attachment,
   * based on its unique identifier. The record remains in the database but is
   * considered removed from active application usage; it can be later expunged
   * or audited via other maintenance processes. The attachment file is not
   * deleted from physical storage by this operation—separate backend processes
   * are responsible for physical file cleanup and business-layer linkage
   * removal.
   *
   * Soft deletion supports compliance, audit, and security policies by
   * retaining metadata and a deletion trail. Only authorized administrators can
   * perform this operation, and all such actions are logged for further
   * review.
   *
   * @param connection
   * @param attachmentId Unique identifier (UUID) of the target attachment
   *   record in the discussion_board_attachments table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":attachmentId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAttachment> {
    try {
      return await deleteDiscussionBoardAdminAttachmentsAttachmentId({
        admin,
        attachmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
