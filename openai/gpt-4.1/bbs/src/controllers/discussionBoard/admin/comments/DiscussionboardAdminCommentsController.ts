import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putDiscussionBoardAdminCommentsCommentId } from "../../../../providers/putDiscussionBoardAdminCommentsCommentId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteDiscussionBoardAdminCommentsCommentId } from "../../../../providers/deleteDiscussionBoardAdminCommentsCommentId";

import { IDiscussionBoardArticleComment } from "../../../../api/structures/IDiscussionBoardArticleComment";

@Controller("/discussionBoard/admin/comments/:commentId")
export class DiscussionboardAdminCommentsController {
  /**
   * Update an existing discussion board comment's content based on the provided
   * comment identifier.
   *
   * This operation allows either the comment's author or an administrator to
   * edit the text content of a comment that was previously posted under an
   * article. All such changes are strictly validated to ensure the updated
   * comment text remains within 5,000 characters, aligning with business rules
   * prohibiting blank or overly lengthy comments.
   *
   * On each update, the system automatically records a new version in the
   * comment snapshot table for full edit history and compliance review. Only
   * authenticated users who match the original author, or admins with required
   * privileges, may perform updates; this is strictly enforced through
   * authorizationActors and business logic validation. Audit logging and
   * moderation flows reference these updates, allowing for future review and
   * rollback if required.
   *
   * If a comment is in a deleted state, updates are typically prohibited, and
   * the system will return a validation error. The response reflects the
   * comment's new state upon successful update, including refreshed lifecycle
   * timestamps for both content and metadata.
   *
   * @param connection
   * @param commentId Unique identifier of the target comment within the board
   *   (UUID-based).
   * @param body New content for the comment, following validation rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleComment.IUpdate,
  ): Promise<IDiscussionBoardArticleComment> {
    try {
      return await putDiscussionBoardAdminCommentsCommentId({
        admin,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete a comment from the discussion board by marking its record as
   * deleted. The operation targets a specific comment using the provided
   * identifier and is accessible only to the comment's author or an authorized
   * administrator.
   *
   * When invoked, this operation does not physically remove the comment from
   * the database. Instead, it sets the 'deleted_at' field with the current
   * timestamp, effectively hiding the comment from standard board queries and
   * user views. This approach preserves the full comment entity and its
   * lifecycle metadata for compliance, audit, and moderation scenarios, as
   * described in schema documentation.
   *
   * Deletion rights are governed by strict business logic: only original
   * authors or admins with required privileges may soft-delete a comment. If
   * the comment is already in a deleted state or does not exist, a suitable
   * error response is triggered. The response reflects the entity with its new
   * deletion status for downstream processing or review.
   *
   * @param connection
   * @param commentId Unique identifier of the target comment within the board
   *   (UUID-based).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticleComment> {
    try {
      return await deleteDiscussionBoardAdminCommentsCommentId({
        admin,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
