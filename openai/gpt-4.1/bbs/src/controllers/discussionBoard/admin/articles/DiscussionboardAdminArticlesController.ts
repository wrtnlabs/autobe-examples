import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putDiscussionBoardAdminArticlesArticleId } from "../../../../providers/putDiscussionBoardAdminArticlesArticleId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteDiscussionBoardAdminArticlesArticleId } from "../../../../providers/deleteDiscussionBoardAdminArticlesArticleId";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/admin/articles/:articleId")
export class DiscussionboardAdminArticlesController {
  /**
   * Update a discussion board article in the discussion_board_articles table.
   *
   * Update a specific discussion board article by providing new values for the
   * title and body fields. This operation allows either the original user
   * author or an authorized admin to make changes, subject to permission and
   * business validation rules.
   *
   * Permission checks are enforced to ensure only the article owner or
   * authorized administrators can perform this action. All edits will be
   * timestamped, and prior versions may be stored in the system for audit
   * purposes via snapshot tables. The update propagates to all relevant
   * relationships, including possible cascading updates for related file
   * attachments or moderation logs.
   *
   * Validation rules require that the new title must be between 5 and 150
   * characters and the body must be between 20 and 5000 characters, precisely
   * matching the schema. Failure to meet these constraints will result in a
   * validation error and will not perform any update.
   *
   * @param connection
   * @param articleId UUID of the target article to be updated
   *   (discussion_board_articles.id).
   * @param body New article data including title and body, following validation
   *   rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticle.IUpdate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await putDiscussionBoardAdminArticlesArticleId({
        admin,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete a discussion board article in the discussion_board_articles
   * table by setting deleted_at.
   *
   * Delete a specific article from the discussion board by referencing its
   * UUID. This operation enforces permission checks to ensure that only the
   * article's original author or an admin with the necessary privileges can
   * delete content.
   *
   * In accordance with business compliance and audit requirements, deletions
   * are performed as soft deletions: the deleted_at field is set to the current
   * timestamp, and the account remains recoverable. Audit trails are recorded,
   * and all related content such as attachments and comments are also subject
   * to deletion or archiving as dictated by the requirements. Attempts to
   * delete an article that has already been deleted or does not exist will
   * result in a safe error response and will not compromise system integrity.
   *
   * The operation interacts with the discussion_board_articles table and
   * cascades to related tables for complete and compliant deletion workflow.
   *
   * @param connection
   * @param articleId UUID of the target article to be deleted
   *   (discussion_board_articles.id).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await deleteDiscussionBoardAdminArticlesArticleId({
        admin,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
