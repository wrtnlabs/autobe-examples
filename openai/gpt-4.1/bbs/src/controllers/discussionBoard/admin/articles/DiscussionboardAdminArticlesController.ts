import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putDiscussionBoardAdminArticlesArticleId } from "../../../../providers/putDiscussionBoardAdminArticlesArticleId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteDiscussionBoardAdminArticlesArticleId } from "../../../../providers/deleteDiscussionBoardAdminArticlesArticleId";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/admin/articles/:articleId")
export class DiscussionboardAdminArticlesController {
  /**
   * Update an existing article in the discussion_board_articles table by ID.
   *
   * This API endpoint allows for the full editing of a discussion article
   * already present in the platform discussion board.
   *
   * It performs complete updates on all fields allowed by the
   * discussion_board_articles Prisma schema, excluding immutable fields such as
   * the article's original ID, creation timestamp, or system-managed audit
   * data. The operation enforces permission checks to ensure only the original
   * article author or designated moderators/admins can edit the content. All
   * submitted changes undergo validation against business rules, including
   * content length, acceptable HTML, and attachment constraints, as specified
   * in requirements documents.
   *
   * If the article is successfully updated, the new state of the article is
   * returned to the requester. Modification attempts by unauthorized users, or
   * with invalid data, result in appropriate error responses. This endpoint is
   * closely related to article versioning, as edits may trigger creation of
   * article snapshots for audit trail support.
   *
   * @param connection
   * @param articleId Unique identifier of the target article for update (UUID
   *   format).
   * @param body Article updates according to the discussion_board_articles
   *   Prisma schema, excluding immutable fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticle.IUpdate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await putDiscussionBoardAdminArticlesArticleId({
        admin,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete an article from the discussion_board_articles table by
   * ID.
   *
   * This endpoint allows the authorized user to delete a discussion article
   * from the board. Deletion is absolute; once deleted, the record is removed
   * from the database and cannot be restored, following the hard-delete policy
   * as the discussion_board_articles Prisma schema does not define a soft
   * delete column.
   *
   * Business logic enforces that only the original author, a moderator, or an
   * administrator may perform this operation. The system ensures removal of any
   * associated data, such as attachments or comments, according to the
   * referential integrity rules set in the schema. Attempts to delete
   * nonexistent or already-deleted articles, or requests by unauthorized users,
   * produce clear error responses.
   *
   * This operation is coordinated with moderation logs to ensure full
   * traceability of deletion activities for compliance, and should be used in
   * conjunction with operational policies for audit and oversight.
   *
   * @param connection
   * @param articleId Unique identifier of the target article for deletion (UUID
   *   format).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminArticlesArticleId({
        admin,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
