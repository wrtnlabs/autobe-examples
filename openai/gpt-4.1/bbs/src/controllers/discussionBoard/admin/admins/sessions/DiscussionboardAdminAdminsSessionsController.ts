import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminAdminsAdminIdSessions } from "../../../../../providers/patchDiscussionBoardAdminAdminsAdminIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/getDiscussionBoardAdminAdminsAdminIdSessionsSessionId";

import { IPageIDiscussionBoardAdminSession } from "../../../../../api/structures/IPageIDiscussionBoardAdminSession";
import { IDiscussionBoardAdminSession } from "../../../../../api/structures/IDiscussionBoardAdminSession";

@Controller("/discussionBoard/admin/admins/:adminId/sessions")
export class DiscussionboardAdminAdminsSessionsController {
  /**
   * Search and paginate administrator login sessions by adminId
   * (discussion_board_admin_sessions).
   *
   * This API operation enables search and retrieval of administrator login
   * session records for a given administrator account. It is intended for use
   * by privileged actors or for admin self-service to review history of session
   * activity, including device, IP, and time/location context. Sessions are
   * shown only for the admin identified by the adminId path parameter.
   *
   * Search functionality includes paginated browsing, filtering by
   * active/expired status, sorting by creation or expiration, as well as
   * searching by IP address or referrer information, as supported by the schema
   * design. Returned data exposes only non-sensitive session attributes, and
   * session details are filtered to comply with audit and privacy
   * requirements.
   *
   * Security considerations include strict scoping to the admin specified in
   * the path parameter, enforcement of access control (only the admin themself
   * or super admins), and robust paging to handle potentially large session
   * histories. The underlying Prisma schema supports efficient index-based
   * queries and audit-compliant session traceability. This operation is
   * designed for use in admin panels, compliance dashboards, and security
   * review tools.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator account (UUID)
   *   for which to search sessions
   * @param body Search, filter, and pagination parameters for session listing
   *   and filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardAdminSession.IRequest,
  ): Promise<IPageIDiscussionBoardAdminSession.ISummary> {
    try {
      return await patchDiscussionBoardAdminAdminsAdminIdSessions({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve session details for a given admin and session
   * (discussion_board_admin_sessions).
   *
   * This operation retrieves all metadata of a particular administrator
   * session, identified by sessionId, belonging to the administrator identified
   * by adminId. The result includes IP address, connection location (href),
   * referrer, timestamps of creation and expiry, and a binding to the admin
   * actor. This record is drawn from the discussion_board_admin_sessions table,
   * supporting full traceability and session audit as required by regulatory
   * and business compliance policies.
   *
   * Requesting this detail is allowed only for the admin account owner or for
   * privileged super admins as determined by the system. The result omits
   * sensitive elements such as credential hashes but provides all data required
   * for admin device management, security review, or suspicious activity
   * investigation.
   *
   * Any attempt to access a session not belonging to the specified adminId will
   * result in an error response, ensuring strong data partitioning and internal
   * access control as reflected in the schema. This interface supports
   * integration into admin dashboards and session history viewers.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account (UUID) to
   *   which this session belongs
   * @param sessionId Unique session record identifier (UUID) for the
   *   administrator session to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAdminSession> {
    try {
      return await getDiscussionBoardAdminAdminsAdminIdSessionsSessionId({
        admin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
