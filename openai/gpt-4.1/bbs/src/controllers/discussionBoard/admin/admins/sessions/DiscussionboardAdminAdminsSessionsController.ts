import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminAdminsAdminIdSessions } from "../../../../../providers/patchDiscussionBoardAdminAdminsAdminIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/getDiscussionBoardAdminAdminsAdminIdSessionsSessionId";
import { deleteDiscussionBoardAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/deleteDiscussionBoardAdminAdminsAdminIdSessionsSessionId";

import { IPageIDiscussionBoardAdminSession } from "../../../../../api/structures/IPageIDiscussionBoardAdminSession";
import { IDiscussionBoardAdminSession } from "../../../../../api/structures/IDiscussionBoardAdminSession";

@Controller("/discussionBoard/admin/admins/:adminId/sessions")
export class DiscussionboardAdminAdminsSessionsController {
  /**
   * List all sessions for a platform admin (discussion_board_admin_sessions
   * table).
   *
   * Retrieve a paginated list of all sessions for the target admin in the
   * discussion board platform. This endpoint is intended for administrative
   * review, auditing, and session management by administrators and platform
   * operators.
   *
   * The operation queries the discussion_board_admin_sessions table using the
   * admin's unique ID, ensuring only session records belonging to the specified
   * admin are included. Filtering, searching, and pagination capabilities allow
   * efficient traversal of potentially large session datasets for oversight
   * purposes.
   *
   * Security is a priority for this endpoint. Only platform administrators (not
   * standard users) may access session data, ensuring sensitive authentication
   * records are restricted. The full context of each session is returned as
   * summarized by the ISummary interface, respecting all Prisma schema field
   * definitions, including IP address, URL, referrer, and associated
   * timestamps. This operation is related to session detail retrieval (GET
   * /admins/{adminId}/sessions/{sessionId}) for viewing specific session
   * attributes.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator. Should be the
   *   UUID that identifies the admin in the discussion_board_admins table.
   * @param body Pagination, filtering, or search parameters for session listing
   *   according to supported admin session filters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardAdminSession.IRequest,
  ): Promise<IPageIDiscussionBoardAdminSession.ISummary> {
    try {
      return await patchDiscussionBoardAdminAdminsAdminIdSessions({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific admin session
   * (discussion_board_admin_sessions table).
   *
   * Retrieve detailed information about a specific admin session for audit or
   * review. This endpoint allows a platform administrator to access all
   * attributes recorded for a single session instance, including the associated
   * admin reference, connection context, and lifecycle timestamps.
   *
   * The operation enforces strict authorization, allowing only admins to review
   * session details. The session data returned fully reflects the
   * discussion_board_admin_sessions schema, referencing related entities as
   * needed. If the session is not found or access is unauthorized, appropriate
   * error responses are generated. This endpoint is closely related to the
   * session list endpoint (PATCH /admins/{adminId}/sessions), which provides
   * broader session listings, and may support administrative or compliance
   * reviews requiring deep session visibility.
   *
   * @param connection
   * @param adminId Unique identifier of the admin who owns this session, as
   *   recorded in the discussion_board_admins table (UUID).
   * @param sessionId Unique identifier of the specific admin session (UUID) to
   *   retrieve details for, as defined in the discussion_board_admin_sessions
   *   table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAdminSession> {
    try {
      return await getDiscussionBoardAdminAdminsAdminIdSessionsSessionId({
        admin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete an admin session from discussion_board_admin_sessions.
   *
   * Delete a specific admin session from the system.
   *
   * This operation enables platform administrators to remove a session
   * referenced by its unique sessionId and the associated adminId. It is most
   * commonly used for forcibly ending active moderation sessions or managing
   * concurrent session security. For example, if suspicious activity is
   * detected or credentials have been rotated, the admin may terminate a
   * session immediately.
   *
   * This is a hard delete operation. The session record is removed from the
   * discussion_board_admin_sessions table and cannot be recovered. Audit
   * policies and logging should record the actor, timestamp, and session
   * details for compliance and forensic tracking.
   *
   * Administrators using this operation must possess appropriate privileges;
   * regular users are forbidden from accessing this endpoint. Related endpoints
   * may allow listing all sessions for an admin or searching the entire session
   * history for the platform.
   *
   * @param connection
   * @param adminId Unique identifier (UUID) of the administrator account to
   *   which this session belongs.
   * @param sessionId Unique identifier (UUID) of the admin session to be
   *   deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminAdminsAdminIdSessionsSessionId({
        admin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
