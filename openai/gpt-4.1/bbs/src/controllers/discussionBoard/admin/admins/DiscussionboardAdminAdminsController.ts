import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminAdmins } from "../../../../providers/patchDiscussionBoardAdminAdmins";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminAdminsAdminId } from "../../../../providers/getDiscussionBoardAdminAdminsAdminId";
import { putDiscussionBoardAdminAdminsAdminId } from "../../../../providers/putDiscussionBoardAdminAdminsAdminId";
import { deleteDiscussionBoardAdminAdminsAdminId } from "../../../../providers/deleteDiscussionBoardAdminAdminsAdminId";

import { IPageIDiscussionBoardAdmin } from "../../../../api/structures/IPageIDiscussionBoardAdmin";
import { IDiscussionBoardAdmin } from "../../../../api/structures/IDiscussionBoardAdmin";

@Controller("/discussionBoard/admin/admins")
export class DiscussionboardAdminAdminsController {
  /**
   * Retrieve a filtered, paginated list of discussion board admins
   * (discussion_board_admins table).
   *
   * Retrieve a list of administrator accounts for the discussion platform,
   * supporting filtering, sorting, and pagination.
   *
   * This operation enables the calling actor to search for admins using any
   * combination of email address, account status (active, blocked), email
   * verification status, and creation date. Query logic respects the unique
   * constraint on email and indexes for fast response times. Results return
   * summary information for each matched admin account, including primary
   * fields, status flags, and timestamps. The admin's password, password hash,
   * and security-sensitive information are not included in the search results.
   *
   * Only authenticated admins and system operators may access this endpoint.
   * Rate limiting and audit-logging are applied to every request to maintain
   * accountability and compliance for permissioned actions affecting
   * administrator records. The results reflect current state, including
   * soft-deleted accounts marked by non-null deleted_at timestamps, allowing
   * both active and deleted admin records to be reviewed as appropriate.
   *
   * @param connection
   * @param body Search/filter, pagination, and sorting criteria for admin
   *   account retrieval.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAdmin.IRequest,
  ): Promise<IPageIDiscussionBoardAdmin.ISummary> {
    try {
      return await patchDiscussionBoardAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get detailed information for a discussion board admin by adminId
   * (discussion_board_admins table).
   *
   * Retrieve detailed information about an individual administrator account
   * using their unique adminId.
   *
   * This endpoint allows authorized platform admins or system-level operators
   * to access a specific admin's full profile and account metadata, except for
   * private fields such as password_hash. Core properties returned include the
   * admin's email address, verification status, account activation state,
   * block/suspension flag, and audit fields for creation, last update, and soft
   * deletion (deleted_at).
   *
   * Strict permission checks are enforced: only authenticated platform admins
   * may read this information. Audit logs track every read for compliance
   * purposes, and results fully conform to GDPR privacy best practices. This
   * allows for secure oversight of admin accounts, compliance investigations,
   * and privileged management operations that require account-level detail.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator account
   *   (primary key, UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAdmin> {
    try {
      return await getDiscussionBoardAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update administrator account in the discussion_board_admins table.
   *
   * Update an administrator account in the discussion board system.
   *
   * This endpoint enables privileged platform operators to modify information
   * related to an administrator, including email, password hash, and status
   * attributes such as email verification, account activation, and
   * ban/suspension.
   *
   * All fields provided in the request are subject to strong validation. The
   * email must be unique, the password hash must adhere to secure standards,
   * and status flags are checked for adherence to allowed transitions (e.g.,
   * accounts cannot simultaneously be active and blocked). Audit fields are
   * updated to maintain traceability of admin actions.
   *
   * Security: Only authorized infrastructure operators or higher-level staff
   * should invoke this endpoint. All update actions are logged for compliance
   * oversight. Any attempt to update sensitive status fields is validated
   * against platform rules to prevent privilege escalation or unauthorized
   * actions.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator account.
   * @param body Fields to update in the administrator account (email, password
   *   hash, status flags). All values are strictly validated, and partial
   *   updates are not supported via this operation. All required fields must be
   *   provided.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardAdmin.IUpdate,
  ): Promise<IDiscussionBoardAdmin> {
    try {
      return await putDiscussionBoardAdminAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete administrator record in the discussion_board_admins
   * table.
   *
   * Permanently remove an administrator account from the discussion board
   * administration system.
   *
   * This endpoint is intended for exceptional cases, such as severe policy
   * violations or security incidents, where an administrator's privileges must
   * be revoked and their account removed. All actions taken are logged and
   * audited for regulatory compliance and operational accuracy.
   *
   * Authorization to perform this action is strictly restricted to
   * infrastructure operators or system-level admins with appropriate
   * permissions. Upon execution, the administrator record is permanently
   * removed from the system database. This action cannot be undone.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account to be
   *   deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
