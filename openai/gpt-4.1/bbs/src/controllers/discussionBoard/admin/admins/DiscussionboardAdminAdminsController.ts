import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminAdmins } from "../../../../providers/patchDiscussionBoardAdminAdmins";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminAdminsAdminId } from "../../../../providers/getDiscussionBoardAdminAdminsAdminId";
import { putDiscussionBoardAdminAdminsAdminId } from "../../../../providers/putDiscussionBoardAdminAdminsAdminId";
import { deleteDiscussionBoardAdminAdminsAdminId } from "../../../../providers/deleteDiscussionBoardAdminAdminsAdminId";

import { IPageIDiscussionBoardAdmin } from "../../../../api/structures/IPageIDiscussionBoardAdmin";
import { IDiscussionBoardAdmin } from "../../../../api/structures/IDiscussionBoardAdmin";

@Controller("/discussionBoard/admin/admins")
export class DiscussionboardAdminAdminsController {
  /**
   * Search and retrieve a paginated, filtered list of discussion board
   * administrators from the admin registry.
   *
   * Retrieve a comprehensive, filtered, and paginated list of administrators
   * registered in the discussion board platform. The operation allows filtering
   * administrators by email address, display name, lock/ban status, and
   * creation/deletion date ranges. Full-text and partial match search is
   * supported for the display_name and email fields, leveraging the GIN index
   * present in the discussion_board_admins schema.
   *
   * Administrators may use this endpoint to manage accounts, review current
   * administrative actors, audit for unusual lock/deleted states, and organize
   * admin teams for moderation. Results include avatar URL, lock status,
   * deletion timestamp (for audit/GDPR support), and timestamps for creation
   * and last update. Filtering on is_locked and deleted_at fields enables
   * targeted review of suspended or deactivated admin accounts.
   *
   * Security restrictions ensure only authenticated administrators can access
   * this operation. Non-administrative actors MUST receive an appropriate
   * permission error. Rate limiting and logging are recommended to prevent
   * enumeration abuse. The request parameters allow specifying page size, sort
   * order (by email, creation date, or status), and advanced search options.
   * This operation directly references the discussion_board_admins Prisma
   * schema for all returned and queryable fields.
   *
   * This operation assists in meeting compliance, audit, and team management
   * requirements for the administrative actors of the discussion board.
   *
   * @param connection
   * @param body Search criteria, filtering options, pagination, and sorting for
   *   administrator account listing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAdmin.IRequest,
  ): Promise<IPageIDiscussionBoardAdmin.ISummary> {
    try {
      return await patchDiscussionBoardAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific administrator by UUID id from
   * the administrator registry.
   *
   * Retrieve full details of an administrator account in the discussion board
   * system by specifying the administrator's unique identifier (UUID). The
   * returned data includes the administrator's display name, email address,
   * avatar URL (if set), lock state, deletion timestamp (if soft-deleted), and
   * creation/update timestamps, as defined in the discussion_board_admins
   * schema.
   *
   * This endpoint is essential for platform-level identity management,
   * providing visibility into who holds administrative privileges and the state
   * of their account. Only authenticated administrators can use this endpoint;
   * attempts from non-admin users or unauthenticated actors MUST result in a
   * permission denied response. This operation supports audit trails and
   * privilege verification workflows used during incident response, onboarding,
   * or periodic admin review.
   *
   * It references all profile and audit fields from discussion_board_admins,
   * ensuring data returned are current and complete for compliance and review
   * purposes. Error handling returns an explicit not-found message if the
   * specified admin does not exist, is deleted, or is inaccessible due to lock
   * or soft-delete state.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator account (UUID,
   *   global scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAdmin> {
    try {
      return await getDiscussionBoardAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing discussion board administrator's profile and credentials
   * (discussion_board_admins table).
   *
   * This operation allows a privileged actor to update the core profile,
   * credentials, and settings of an existing discussion board administrator.
   * The changes may include updating the admin's email (which must remain
   * unique within the system), display name for transparency and moderation
   * tools, password hash for account security (never accepting plaintext
   * passwords), the avatar image URL, and the lock status (which disables
   * access). This endpoint is strictly for administrators or platform
   * compliance agents.
   *
   * All business rules for uniqueness, data validation, and secure
   * authentication must be enforced. Audit logging is required for each update,
   * with changes to credentials triggering additional compliance tracking.
   * Changing the lock state immediately restricts or re-enables access and must
   * be monitored for security. The endpoint integrates tightly with the
   * administrator table as structured in the Prisma schema, ensuring that all
   * data integrity and compliance requirements are observed.
   *
   * Permission to use this endpoint is limited to privileged actors (admins),
   * with all requests thoroughly validated and logged for subsequent compliance
   * review. Updates to email or lock status may trigger notifications or
   * recovery flows per platform operations policy. This operation forms the
   * core update action for privileged administrator management and should be
   * used in conjunction with session and audit log APIs where needed.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator account to be
   *   updated
   * @param body Administrator update data: email, display name, hashed
   *   password, avatar URL, lock state, and optional deletion timestamp (for
   *   GDPR/rotation).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardAdmin.IUpdate,
  ): Promise<IDiscussionBoardAdmin> {
    try {
      return await putDiscussionBoardAdminAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete an administrator account and all associated data
   * (discussion_board_admins table).
   *
   * This endpoint allows privileged administrators to permanently remove an
   * administrator account identified by the adminId path parameter. The
   * operation performs a complete, irreversible hard delete: all session
   * records, moderation actions, and audit logs related to the deleted admin
   * are purged in accordance with the discussion_board_admins schema and
   * onDelete cascade rules. This is in contrast to user deletion (which may
   * support PII anonymization), as administrator actions are always traceable
   * in audit records until deletion.
   *
   * Strict business rules and compliance protocols apply. Every deletion is
   * logged with sufficient context for future audits. Use of this endpoint
   * should require explicit confirmation and traceability for legal and
   * business compliance. No recovery is possible once executed. Only verified
   * administrators (authorizationActors: admin) can invoke this action, and all
   * calls and their justifications are included in compliance logs.
   *
   * Any error during execution, such as lack of administrator privileges,
   * non-existent adminId, or attempt to delete the requesting user's own admin
   * account, triggers a specific, user-friendly error response and leaves all
   * data intact.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
