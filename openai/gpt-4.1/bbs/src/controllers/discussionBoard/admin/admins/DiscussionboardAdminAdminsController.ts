import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminAdmins } from "../../../../providers/patchDiscussionBoardAdminAdmins";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminAdminsAdminId } from "../../../../providers/getDiscussionBoardAdminAdminsAdminId";
import { putDiscussionBoardAdminAdminsAdminId } from "../../../../providers/putDiscussionBoardAdminAdminsAdminId";
import { deleteDiscussionBoardAdminAdminsAdminId } from "../../../../providers/deleteDiscussionBoardAdminAdminsAdminId";

import { IPageIDiscussionBoardAdmin } from "../../../../api/structures/IPageIDiscussionBoardAdmin";
import { IDiscussionBoardAdmin } from "../../../../api/structures/IDiscussionBoardAdmin";

@Controller("/discussionBoard/admin/admins")
export class DiscussionboardAdminAdminsController {
  /**
   * List and search for administrator accounts registered for the discussion
   * board system.
   *
   * This operation allows privileged administrators to view, filter, and
   * paginate through the set of admin accounts responsible for platform
   * governance and moderation. Providers may search by unique email, creation
   * or update timestamp, or deletion status for audit, onboarding, or
   * compliance review.
   *
   * Only authenticated admins may access this endpoint for security reasons.
   * The results are assembled using summary representations of administrator
   * accounts, with all searches performed based on the unique fields and
   * indexes defined in the discussion_board_admins schema. Pagination and
   * sorting are enabled for efficient browsing.
   *
   * @param connection
   * @param body Search and filter criteria for querying administrator accounts,
   *   including pagination and sorting parameters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAdmin.IRequest,
  ): Promise<IPageIDiscussionBoardAdmin.ISummary> {
    try {
      return await patchDiscussionBoardAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete administrator account profile using the unique admin
   * ID. This API returns all visible details of the admin, including the email
   * address, creation and update timestamps, and the current status (active or
   * soft-deleted).
   *
   * Access to this operation is strictly controlled. Only privileged actors
   * (typically internal admin interfaces or core system processes) are
   * permitted. Sensitive information such as the password hash is never exposed
   * through this API under any circumstance.
   *
   * The detailed admin entity information is sourced from the
   * 'discussion_board_admins' Prisma schema table, which provides a full audit
   * trail of account lifecycle actions. The primary key is the 'id' UUID field.
   * Soft deletion is supported through a nullable 'deleted_at' column, which is
   * reflected in the returned data. This endpoint does not require a request
   * body and returns all relevant admin profile information found in the
   * database. Error handling will return appropriate messages for missing or
   * deactivated accounts, with audit logging as required by compliance
   * policies.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account (UUID) in the
   *   discussion_board_admins table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAdmin> {
    try {
      return await getDiscussionBoardAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the profile information for a specific administrator account
   * identified by adminId. This includes changing the admin's email address,
   * rotating the password hash (for password resets), and enabling or revoking
   * the account by updating associated timestamps. The request may include only
   * the fields to modify; all fields are validated for schema and business rule
   * compliance.
   *
   * Authentication and authorization are mandatory: only actors with explicit
   * system administrator privileges can invoke this operation. Attempted
   * modifications to immutable fields or constraint-violating updates (e.g.,
   * email uniqueness breaks) result in explicit validation errors.
   *
   * Underlying data is stored in the 'discussion_board_admins' table, and all
   * changes are fully audited for compliance. Soft deletion is achieved by
   * setting 'deleted_at'; reactivation resets it to null. Successful updates
   * return the full admin profile after modification. No field related to raw
   * passwords is ever accepted or returned.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account (UUID) to
   *   update.
   * @param body Administrator profile update payload. Supports fields for
   *   email, password hash, and soft-deletion control. Must conform to
   *   IDiscussionBoardAdmin.IUpdate.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardAdmin.IUpdate,
  ): Promise<IDiscussionBoardAdmin> {
    try {
      return await putDiscussionBoardAdminAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a system administration account from the discussion
   * board's governance infrastructure.
   *
   * This operation revokes all administrative rights, removes the administrator
   * from active user lists, and triggers removal or invalidation of all session
   * tokens and privileges associated with the account. It is designed to be
   * called by another admin (or a system super-admin) and is strictly
   * restricted to actors with system-level authority, as defined in the
   * permissions matrix. Any active or future admin sessions linked to the
   * deleted account will become invalid. The operation carefully logs the
   * deletion action for ongoing audit and future compliance checks; a
   * soft-delete will mark the deleted_at field, supporting historical inquiries
   * when required by compliance or investigation teams.
   *
   * If an invalid or already-deleted adminId is supplied, the operation returns
   * a 404 or equivalent error. Comprehensive validation ensures robust
   * role-based access control and prevents unauthorized deletions.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account to delete
   *   (discussion_board_admins.id).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
