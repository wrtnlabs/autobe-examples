import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminUsersUserIdSessions } from "../../../../../providers/patchDiscussionBoardAdminUsersUserIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminUsersUserIdSessionsSessionId } from "../../../../../providers/getDiscussionBoardAdminUsersUserIdSessionsSessionId";
import { putDiscussionBoardAdminUsersUserIdSessionsSessionId } from "../../../../../providers/putDiscussionBoardAdminUsersUserIdSessionsSessionId";
import { deleteDiscussionBoardAdminUsersUserIdSessionsSessionId } from "../../../../../providers/deleteDiscussionBoardAdminUsersUserIdSessionsSessionId";

import { IPageIDiscussionBoardUserSession } from "../../../../../api/structures/IPageIDiscussionBoardUserSession";
import { IDiscussionBoardUserSession } from "../../../../../api/structures/IDiscussionBoardUserSession";

@Controller("/discussionBoard/admin/users/:userId/sessions")
export class DiscussionboardAdminUsersSessionsController {
  /**
   * Search and retrieve session records for any discussion board user,
   * supporting advanced filters and pagination for admin audits.
   *
   * Only users with admin privileges may access this operation. The request
   * body allows specifying filters such as user_id, session status
   * (active/expired), IP address, time range, and pagination controls. No
   * session creation, deletion, or editing is supported—sessions are managed
   * internally by the authentication subsystem.
   *
   * This endpoint is used for platform security and audit investigations only.
   * Sessions are immutable from the admin search API. The operation supports
   * response pagination, and results include session metadata (timestamps, IP,
   * referrer, href) along with user linkage for full traceability. If no
   * records match the query, an empty list is returned. Admins must handle this
   * data securely as it may contain sensitive information.
   *
   * @param connection
   * @param body Search filters and pagination parameters for discussion board
   *   user sessions (admin only).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string,
    @TypedBody()
    body: IDiscussionBoardUserSession.IRequest,
  ): Promise<IPageIDiscussionBoardUserSession> {
    try {
      return await patchDiscussionBoardAdminUsersUserIdSessions({
        admin,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a single login session record for a
   * discussion board user. This endpoint is intended for administrative access
   * and provides insight into user authentication activity within the
   * discussion platform.
   *
   * By supplying both the userId (identifies the account owner) and sessionId
   * (uniquely identifies the session), administrators can audit specific
   * sessions, validate connection metadata, and review session expiration
   * status. Typical use cases include investigation of suspicious logins,
   * resolving user complaints about session handling, or reviewing historical
   * login events during compliance audits.
   *
   * Session records contain metadata such as IP address, request referrer, URL
   * (href), creation time, and expiry. This data aids in detecting unauthorized
   * access patterns and supports traceability for moderation or security
   * reviews. Access to this endpoint is strictly limited to users with
   * administrative roles; ordinary users cannot query others' session records
   * by design. No modification or deletion occurs via this endpoint,
   * maintaining immutable, audit-safe session traces.
   *
   * @param connection
   * @param userId Unique identifier of the target discussion board user (UUID).
   *   Used to restrict session scope for accurate lookup.
   * @param sessionId Unique identifier of the login session record (UUID).
   *   Identifies the specific session to retrieve under the specified user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardUserSession> {
    try {
      return await getDiscussionBoardAdminUsersUserIdSessionsSessionId({
        admin,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the metadata of a particular discussion board user session,
   * including (but not limited to) setting the expired_at timestamp to force
   * session termination or modifying trace data for audit reasons.
   * Administrative operations may include revoking user sessions after
   * detecting policy violations or handling account compromise scenarios.
   *
   * Both userId and sessionId path parameters ensure only the target user's
   * session is altered, preventing cross-user modification. The request body
   * must include the necessary session update fields as defined by security
   * policy—generally only administrators may change session status or expiry.
   * All updates are to be logged and auditable for compliance and security
   * review.
   *
   * Related endpoints include the corresponding GET (read-only, for
   * verification/audit) and other session listing/search endpoints. Critical
   * validation includes permission checks: this operation is restricted to
   * admin-level users, with all updates done under strict audit trail
   * requirements.
   *
   * @param connection
   * @param userId Unique identifier of the target discussion board user (UUID).
   *   Used to restrict session scope for accurate update.
   * @param sessionId Unique identifier of the login session record (UUID).
   *   Identifies the specific session to update under the specified user.
   * @param body Session fields to update (typically expired_at for forced
   *   logout or expiry extension). Structure follows
   *   IDiscussionBoardUserSession.IUpdate.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sessionId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardUserSession.IUpdate,
  ): Promise<IDiscussionBoardUserSession> {
    try {
      return await putDiscussionBoardAdminUsersUserIdSessionsSessionId({
        admin,
        userId,
        sessionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a specific user session from the discussion board
   * authentication system.
   *
   * This operation is primarily used by administrators responding to suspicious
   * or compromised sessions, or when forcibly logging out a user for compliance
   * or security investigation. It accepts both the unique user ID of the
   * session owner and the unique session ID to guarantee accuracy and prevent
   * accidental deletion of other users' sessions.
   *
   * Only privileged administrators are authorized to perform this action. The
   * operation directly deletes the session record from the database,
   * invalidating associated tokens and enforcing immediate logout of the
   * session. All removals are typically logged for future audits, as per the
   * platform's security standards and schema documentation.
   *
   * @param connection
   * @param userId Unique identifier of the user account
   *   (discussion_board_users) who owns the session.
   * @param sessionId Unique identifier of the session record
   *   (discussion_board_user_sessions) to delete.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminUsersUserIdSessionsSessionId({
        admin,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
