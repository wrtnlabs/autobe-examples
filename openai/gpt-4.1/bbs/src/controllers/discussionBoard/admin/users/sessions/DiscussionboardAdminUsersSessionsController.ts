import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminUsersUserIdSessions } from "../../../../../providers/patchDiscussionBoardAdminUsersUserIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminUsersUserIdSessionsSessionId } from "../../../../../providers/getDiscussionBoardAdminUsersUserIdSessionsSessionId";

import { IPageIDiscussionBoardUserSession } from "../../../../../api/structures/IPageIDiscussionBoardUserSession";
import { IDiscussionBoardUserSession } from "../../../../../api/structures/IDiscussionBoardUserSession";

@Controller("/discussionBoard/admin/users/:userId/sessions")
export class DiscussionboardAdminUsersSessionsController {
  /**
   * Query and paginate all login sessions for a specific user
   * (discussion_board_user_sessions).
   *
   * Retrieve a filtered, paginated list of all active and historical login
   * sessions for a specific user of the discussion board. This operation
   * enables security-conscious users to review all their logins, including
   * device/IP details, timestamps, and session expiration status.
   *
   * Filtering and pagination parameters allow users to search by timeframe, IP,
   * or session status, assisting with suspicious activity detection or general
   * session history review. This operation is also useful for audit and
   * compliance purposes, and enables users to proactively identify unauthorized
   * access.
   *
   * Sensitive session information is restricted to authenticated owners or
   * privileged admins; only actors with proper rights may access a user's
   * sessions. The Prisma schema's discussion_board_user_sessions fields are
   * fully represented in the response structure. Error handling covers
   * not-found, permission failure, and system access errors.
   *
   * @param connection
   * @param userId Unique identifier of the target user (UUID, global scope).
   * @param body Search, filter, and pagination options for session listing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardUserSession.IRequest,
  ): Promise<IPageIDiscussionBoardUserSession.ISummary> {
    try {
      return await patchDiscussionBoardAdminUsersUserIdSessions({
        admin,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed info for a single user login session
   * (discussion_board_user_sessions).
   *
   * Retrieve a single login session for a user by specifying both the userId
   * and the sessionId. This operation returns the full details of the session,
   * including when and where it was created, its expiration status, and other
   * metadata such as IP, referring page, and originating location.
   *
   * This operation is essential for users who wish to investigate login
   * activity, perform self-audit on account access, or for admins reviewing
   * session records during security analysis. All session attributes from the
   * discussion_board_user_sessions Prisma table are available in the detailed
   * view, mapped according to privacy and access policies.
   *
   * Comprehensive permission checks ensure only the session owner (user) or
   * platform admins can access this sensitive information. If the session or
   * user does not exist, or the actor lacks access rights, the operation
   * returns an appropriate error code and description.
   *
   * @param connection
   * @param userId Unique identifier of the user owning the session (UUID,
   *   global scope).
   * @param sessionId Unique identifier of the specific user session (UUID,
   *   globally unique).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardUserSession> {
    try {
      return await getDiscussionBoardAdminUsersUserIdSessionsSessionId({
        admin,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
