import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminUsers } from "../../../../providers/patchDiscussionBoardAdminUsers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminUsersUserId } from "../../../../providers/getDiscussionBoardAdminUsersUserId";
import { putDiscussionBoardAdminUsersUserId } from "../../../../providers/putDiscussionBoardAdminUsersUserId";
import { deleteDiscussionBoardAdminUsersUserId } from "../../../../providers/deleteDiscussionBoardAdminUsersUserId";

import { IPageIDiscussionBoardUser } from "../../../../api/structures/IPageIDiscussionBoardUser";
import { IDiscussionBoardUser } from "../../../../api/structures/IDiscussionBoardUser";

@Controller("/discussionBoard/admin/users")
export class DiscussionboardAdminUsersController {
  /**
   * Paginate and filter user accounts in the discussion_board_users table
   * (admin only).
   *
   * Fetch a paginated and searchable list of user accounts for the platform.
   * Administrators can query user registrations using criteria such as email,
   * account status, email verification, or created_at window. Only authorized
   * admin accounts may invoke this endpoint.
   *
   * Advanced query parameters support flexible user management and compliance
   * auditing, including lookups by activation status, blocked status, or
   * soft-deletion (deleted_at not null). Results are sorted by created_at
   * (descending by default) but alternative sort orders may be implemented
   * according to business preferences.
   *
   * Returned results include essential profile and audit metadata per the
   * Prisma schema, omitting sensitive data such as password hashes. This
   * endpoint complements single-user and session-viewing APIs, supporting
   * broader administrative user oversight.
   *
   * @param connection
   * @param body Search and filter criteria for finding and paginating
   *   discussion board user accounts. Includes registration window, account
   *   status, verification, and related filters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardUser.IRequest,
  ): Promise<IPageIDiscussionBoardUser.ISummary> {
    try {
      return await patchDiscussionBoardAdminUsers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a discussion board user's detailed account information by unique
   * id.
   *
   * Retrieve detailed account information for a single user on the discussion
   * board platform using their unique identifier.
   *
   * This operation is intended for administrative contexts, such as user
   * support, moderation, or audit. It provides all profile details, including
   * email, status flags (active, blocked, email verified), and temporal
   * information (created, updated, and optionally soft-deleted timestamps).
   *
   * Security: Access to this endpoint should be strictly limited to users with
   * administrative or moderation roles. The operation queries by primary key
   * and incorporates fields necessary for resolving account issues, compliance
   * checks, or internal investigations. Related endpoints include searching
   * users and modifying user status.
   *
   * @param connection
   * @param userId Primary key identifier (UUID) of the target user account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardUser> {
    try {
      return await getDiscussionBoardAdminUsersUserId({
        admin,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update properties of a discussion board user account specified by id.
   *
   * Update an existing discussion board user account's properties using the
   * user's unique id as the path parameter.
   *
   * This operation enables authorized staff to manage key user properties, such
   * as activating or blocking accounts, changing email addresses, or verifying
   * user email addresses. All changes are validated per business rules,
   * especially around account status transitions and email uniqueness.
   *
   * Access is restricted to administrative users, and certain changes (such as
   * email updates) may trigger security-related workflows like re-verification
   * or email notifications. The response returns the fully-updated user record.
   * All modifications are timestamped for audit and compliance.
   *
   * @param connection
   * @param userId Primary key identifier (UUID) of the target user account.
   * @param body Subset of user account fields that may be changed by authorized
   *   staff.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardUser.IUpdate,
  ): Promise<IDiscussionBoardUser> {
    try {
      return await putDiscussionBoardAdminUsersUserId({
        admin,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a user account from discussion_board_users via soft
   * deletion.
   *
   * Delete a user account and perform a soft deletion by setting the deleted_at
   * field in discussion_board_users.
   *
   * This operation targets user lifecycle management for compliance,
   * moderation, and account recovery scenarios. When an administrator deletes a
   * user via this endpoint, the backend sets the deleted_at field with the
   * current timestamp. This logical deletion ensures the user's data is
   * preserved for future audit or recovery, complying with common privacy and
   * governance requirements. The user is no longer able to log in or
   * participate on the platform after deletion.
   *
   * The endpoint ensures that all active sessions associated with the user
   * (tracked in discussion_board_user_sessions) are expired or invalidated to
   * prevent unauthorized access by deleted accounts. The API enforces that only
   * administrators (authorizationActors: ["admin"]) can perform this operation.
   * Error handling scenarios include invalid userId, attempts to delete a
   * non-existent account, or lack of authorization. This operation should be
   * used together with user viewing and user search endpoints to enable
   * comprehensive user lifecycle control for platform administrators.
   *
   * @param connection
   * @param userId Unique identifier of the target user (UUID format, global
   *   scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardUser> {
    try {
      return await deleteDiscussionBoardAdminUsersUserId({
        admin,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
