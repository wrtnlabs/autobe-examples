import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminUsers } from "../../../../providers/patchDiscussionBoardAdminUsers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminUsersUserId } from "../../../../providers/getDiscussionBoardAdminUsersUserId";

import { IPageIDiscussionBoardUser } from "../../../../api/structures/IPageIDiscussionBoardUser";
import { IDiscussionBoardUser } from "../../../../api/structures/IDiscussionBoardUser";

@Controller("/discussionBoard/admin/users")
export class DiscussionboardAdminUsersController {
  /**
   * Retrieve a filtered, paginated list of discussion board user accounts for
   * administration.
   *
   * This API endpoint enables administrators to search and enumerate end user
   * accounts registered with the discussion board system. The operation accepts
   * advanced search criteria in the request body, supporting filtering by email
   * address, display name (with partial or fuzzy search), lock status, and
   * soft-deletion status. The API integrates business logic for privacy
   * compliance (such as explicit filtering of soft-deleted/inactive accounts)
   * and ensures results respect administrative privileges.
   *
   * Each response includes user profile metadata needed for audit, privilege
   * escalation requests, or moderation. Sensitive information such as hashed
   * passwords are never included in the response. The results are paginated
   * with configurable page size, supporting high-performance queries even on
   * very large user bases.
   *
   * Security is enforced by restricting this operation to administrative
   * actors. Rate limiting and logging are required to prevent abuse and ensure
   * traceability during user management activities. Errors are reported
   * explicitly when filters are invalid or if admin permission is missing. The
   * schema enforces complete alignment with the discussion_board_users model,
   * using its index and unique fields for maximal query power.
   *
   * @param connection
   * @param body Advanced user account search and filter criteria for
   *   administrative user listing, including fields for email, display name,
   *   lock and deletion state, and pagination.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardUser.IRequest,
  ): Promise<IPageIDiscussionBoardUser.ISummary> {
    try {
      return await patchDiscussionBoardAdminUsers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get detailed information for a specific discussion board user by userId
   * (UUID).
   *
   * This API endpoint enables an administrator to retrieve comprehensive
   * profile information for a specific user, as identified by their
   * system-assigned UUID. The operation consolidates all user attributes
   * required for administrative review, including email, display name, avatar,
   * locked state, soft deletion status, and creation/update timestamps. The
   * result does not include password hashes or any authentication credentials,
   * maintaining security best practices.
   *
   * The operation enforces strict access control to ensure only authorized
   * administrators may query arbitrary user information. Auditing and logging
   * are integral to this endpoint to facilitate traceability and support
   * privacy law compliance. If the specified user is soft-deleted (deleted_at
   * set), this status is explicitly indicated. Any attempt to access a
   * non-existent or unauthorized user record results in a precise error
   * message.
   *
   * This endpoint is essential for user management, audit, and compliance
   * flows, and leverages all documentation/description constraints from the
   * discussion_board_users Prisma schema. It also serves as a foundation for
   * privilege escalation, account locking/unlocking, or account removal.
   *
   * @param connection
   * @param userId Unique identifier of the target discussion board user (UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardUser> {
    try {
      return await getDiscussionBoardAdminUsersUserId({
        admin,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
