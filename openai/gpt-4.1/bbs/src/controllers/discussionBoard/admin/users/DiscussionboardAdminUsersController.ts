import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminUsers } from "../../../../providers/patchDiscussionBoardAdminUsers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminUsersUserId } from "../../../../providers/getDiscussionBoardAdminUsersUserId";
import { putDiscussionBoardAdminUsersUserId } from "../../../../providers/putDiscussionBoardAdminUsersUserId";

import { IPageIDiscussionBoardUser } from "../../../../api/structures/IPageIDiscussionBoardUser";
import { IDiscussionBoardUser } from "../../../../api/structures/IDiscussionBoardUser";

@Controller("/discussionBoard/admin/users")
export class DiscussionboardAdminUsersController {
  /**
   * Search and paginate users from the discussion_board_users table.
   *
   * Search, filter, and paginate through the discussion board's registered user
   * accounts. Administrators can locate specific users quickly by email
   * address, review account status, and navigate through large user sets
   * efficiently thanks to robust pagination and search query logic.
   *
   * Security constraints ensure this endpoint is only available to admin
   * actors, minimizing exposure of user account data. Full audit trails are
   * maintained for all access to this endpoint. The structure of the response
   * is optimized for administrative summaries, returning data suited for
   * management dashboards and user audit screens.
   *
   * Extensive input validation prevents abusive queries, and performance
   * guarantees are outlined in the requirements to ensure timely responses even
   * for large user bases. Related endpoints include GET /users/{userId} for
   * single account retrieval and PATCH /users for bulk user searches.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering user
   *   accounts by email or other attributes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardUser.IRequest,
  ): Promise<IPageIDiscussionBoardUser.ISummary> {
    try {
      return await patchDiscussionBoardAdminUsers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details for a specific registered user in discussion_board_users
   * table.
   *
   * Retrieve the full profile, audit, and identity information for a single
   * discussion board user.
   *
   * This operation is intended for administrative use only. Administrative
   * actors can utilize this endpoint to view account details, including the
   * user's email, lifecycle timestamps (created, updated, soft-deleted), and
   * other authentication-related metadata. The endpoint does not reveal
   * sensitive fields such as password hashes in the API response, adhering to
   * privacy and security best practices.
   *
   * This operation references the discussion_board_users table and presents all
   * user-profile information stored therein, except for sensitive
   * authentication fields. If the user does not exist or is deleted, the system
   * will return a Not Found error. Access to this endpoint is strictly limited
   * to admins, reflecting the permission matrix defined for the platform.
   * Related endpoints include updating user data and listing/searching users
   * for administrative tasks.
   *
   * @param connection
   * @param userId Unique identifier of the target user (UUID from
   *   discussion_board_users.id).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardUser> {
    try {
      return await getDiscussionBoardAdminUsersUserId({
        admin,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update profile or management data for a specific user in
   * discussion_board_users.
   *
   * Updates the information of a single user account for management or
   * correction purposes.
   *
   * Only administrative actors can perform this update operation, reflecting
   * the elevated privileges necessary for modifying user identities. The
   * endpoint is used in cases such as email correction, account auditing, and
   * administrative reactivation. Validation enforces unique email constraint,
   * prevents direct manipulation of authentication secrets (such as
   * password_hash), and updates audit fields like updated_at. Soft-deletion is
   * handled by updating deleted_at as appropriate.
   *
   * This API directly maps to the discussion_board_users table and enforces all
   * associated constraints and business logic. Attempts to update with a
   * duplicate email or invalid data will result in validation errors. If the
   * target user does not exist or is already deleted, an appropriate error is
   * returned. Related APIs include retrieving or searching users.
   *
   * @param connection
   * @param userId Unique identifier of the target user (UUID from
   *   discussion_board_users.id).
   * @param body Fields allowed for update on the user profile. Must comply with
   *   business validation rules and cannot include password changes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardUser.IUpdate,
  ): Promise<IDiscussionBoardUser> {
    try {
      return await putDiscussionBoardAdminUsersUserId({
        admin,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
