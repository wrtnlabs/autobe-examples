import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardComments } from "../../../providers/patchDiscussionBoardComments";
import { getDiscussionBoardCommentsCommentId } from "../../../providers/getDiscussionBoardCommentsCommentId";

import { IPageIDiscussionBoardComment } from "../../../api/structures/IPageIDiscussionBoardComment";
import { IDiscussionBoardComment } from "../../../api/structures/IDiscussionBoardComment";

@Controller("/discussionBoard/comments")
export class DiscussionboardCommentsController {
  /**
   * Search and list comments from discussion_board_comments with pagination and
   * filtering.
   *
   * Retrieve a filtered, paginated collection of comments from the discussion
   * board, possibly across multiple articles.
   *
   * This operation provides advanced moderation and analytics capabilities,
   * allowing clients to search for comments using a wide range of filters (such
   * as article ID, author user/admin ID, content keywords, creation time span)
   * and customize the result page size and order. The target is the
   * discussion_board_comments table, which logs every user or admin comment and
   * uses a soft delete mechanism (`deleted_at`), so only active (non-deleted)
   * comments are included by default.
   *
   * This endpoint is valuable for public browsing of recent comments,
   * administrative moderation listing, or search functionality. Although it
   * supports broad querying, results must respect access and privacy rules as
   * specified in requirements. Comment attachment data is accessible via
   * related APIs.
   *
   * @param connection
   * @param body Search, pagination, and filtering criteria for comment
   *   retrieval. Follows IDiscussionBoardComment.IRequest DTO structure.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardComment.IRequest,
  ): Promise<IPageIDiscussionBoardComment.ISummary> {
    try {
      return await patchDiscussionBoardComments({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific discussion board comment by ID
   * (discussion_board_comments).
   *
   * Fetch a specific comment from the discussion board using its unique
   * identifier.
   *
   * This operation supports retrieval of all information about a comment,
   * including its body, creation and update timestamps, and both user and admin
   * authorship. It also reveals soft deletion status for moderation
   * traceability. Security considerations include ensuring only authorized
   * actors access sensitive comment metadata, especially in the presence of
   * soft deleted content.
   *
   * The operation strictly follows the discussion_board_comments schema,
   * supporting both user and admin ownership and referencing the parent article
   * context. Returned data is structured for full client and moderation
   * review.
   *
   * Other operations, such as comment editing, deletion, or attachment access,
   * are related and may require separate calls.
   *
   * @param connection
   * @param commentId Unique identifier of the target comment.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":commentId")
  public async at(
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await getDiscussionBoardCommentsCommentId({
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
