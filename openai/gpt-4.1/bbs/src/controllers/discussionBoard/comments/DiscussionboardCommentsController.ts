import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardComments } from "../../../providers/patchDiscussionBoardComments";
import { getDiscussionBoardCommentsCommentId } from "../../../providers/getDiscussionBoardCommentsCommentId";

import { IPageIDiscussionBoardArticleComment } from "../../../api/structures/IPageIDiscussionBoardArticleComment";
import { IDiscussionBoardArticleComment } from "../../../api/structures/IDiscussionBoardArticleComment";

@Controller("/discussionBoard/comments")
export class DiscussionboardCommentsController {
  /**
   * Search and retrieve comments posted on articles in the discussion board.
   *
   * This operation enables users to search for comments by keywords, authors,
   * article association, and date ranges. Pagination and advanced filtering are
   * fully supported, improving the ability to navigate lengthy or active
   * discussion threads. Only comments that are not soft-deleted are shown to
   * regular users, while admins may search and list all (including deleted)
   * comments as required for moderation or audit.
   *
   * The API incorporates query capabilities based on allowed search fields per
   * the business rules—body content (with GIN search), article ID, author user
   * ID, and timestamps. Rate limiting and result size restrictions apply to
   * protect system performance. Response data adheres to the comment summary
   * view, omitting large bodies or non-essential fields for efficiency. This
   * operation directly covers the core user journey of finding and reviewing
   * discussion contributions across the board.
   *
   * @param connection
   * @param body Search and pagination criteria for filtering comments. Supports
   *   filtering by article, user, timestamps, and keywords in comment body.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardArticleComment.IRequest,
  ): Promise<IPageIDiscussionBoardArticleComment.ISummary> {
    try {
      return await patchDiscussionBoardComments({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single comment's detailed information using the unique comment
   * identifier.
   *
   * This operation returns the complete data for an individual comment posted
   * beneath an article on the discussion board. The response provides core
   * fields such as the comment's body, timestamps, author reference, and parent
   * article reference, as explicitly defined in the discussion_board_comments
   * Prisma schema. If the comment has been soft-deleted (deleted_at populated),
   * appropriate handling is required to indicate its status (e.g., masking body
   * text in the UI, marking as deleted for end users) in accordance with
   * business rules and audit requirements.
   *
   * Security is enforced through comment lifecycle compliance—only
   * authenticated users can view comments, and access to soft-deleted comments
   * may be restricted based on business role and context. The operation
   * references timestamps for creation and updates for accurate display of
   * editing status. Related operations include comment creation, updating,
   * deletion, and comment history retrieval via companion snapshot table. Error
   * handling includes missing comment IDs, invalid/unknown IDs, or attempts to
   * access comments with deletion status inconsistent with user permissions.
   *
   * @param connection
   * @param commentId Unique identifier of the target comment in the discussion
   *   board comments table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":commentId")
  public async at(
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticleComment> {
    try {
      return await getDiscussionBoardCommentsCommentId({
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
