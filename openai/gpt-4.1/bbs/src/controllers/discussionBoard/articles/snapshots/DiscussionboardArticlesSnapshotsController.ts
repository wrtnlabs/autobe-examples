import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getDiscussionBoardArticlesArticleIdSnapshotsSnapshotId } from "../../../../providers/getDiscussionBoardArticlesArticleIdSnapshotsSnapshotId";

import { IDiscussionBoardArticleSnapshot } from "../../../../api/structures/IDiscussionBoardArticleSnapshot";

@Controller("/discussionBoard/articles/:articleId/snapshots/:snapshotId")
export class DiscussionboardArticlesSnapshotsController {
  /**
   * Retrieve a specific article snapshot from
   * discussion_board_article_snapshots by article and snapshot ID.
   *
   * Retrieve a precise historical snapshot of an article from the discussion
   * board's audit log.
   *
   * This operation allows users or administrators to view a previous version of
   * an article, as stored at the moment of a save or edit event. Snapshots
   * preserve the content, title, and author at the time of change, supporting
   * robust compliance and moderation requirements specified in business rules.
   *
   * Each snapshot is immutable and can be used to review edit histories or
   * reconstruct past states. Viewing a snapshot does not alter any data. Only
   * valid articleId and snapshotId pairs are accepted; attempts to query
   * nonexistent or mismatched pairs return appropriate errors.
   *
   * This API is valuable for moderation workflows, user transparency, and
   * regulatory compliance to show all historic edits to a post, as required in
   * the requirements documentation. This endpoint does not require
   * authentication; both registered and unregistered users may view article
   * history for posts that remain public.
   *
   * Related operations include listing available snapshots for a given article
   * and retrieving current article versions.
   *
   * @param connection
   * @param articleId The unique identifier (UUID) of the target article (from
   *   discussion_board_articles.id).
   * @param snapshotId The unique identifier (UUID) of the target snapshot
   *   within the article's history (from
   *   discussion_board_article_snapshots.id).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticleSnapshot> {
    try {
      return await getDiscussionBoardArticlesArticleIdSnapshotsSnapshotId({
        articleId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
