import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardArticlesArticleIdAttachments } from "../../../../providers/patchDiscussionBoardArticlesArticleIdAttachments";
import { getDiscussionBoardArticlesArticleIdAttachmentsAttachmentId } from "../../../../providers/getDiscussionBoardArticlesArticleIdAttachmentsAttachmentId";

import { IPageIDiscussionBoardArticleAttachment } from "../../../../api/structures/IPageIDiscussionBoardArticleAttachment";
import { IDiscussionBoardArticleAttachment } from "../../../../api/structures/IDiscussionBoardArticleAttachment";

@Controller("/discussionBoard/articles/:articleId/attachments")
export class DiscussionboardArticlesAttachmentsController {
  /**
   * List and paginate attachments for a specific article using the article
   * attachments table.
   *
   * Retrieve a filtered and paginated list of all attachments (images,
   * documents, files) associated with the specified discussion board article.
   *
   * This operation enables clients to list metadata for all attachments
   * currently linked to a given article, including filename, MIME type, file
   * size, and upload date. Only non-deleted attachments are included;
   * soft-deleted attachments are excluded from results. Advanced clients may
   * supply additional filtering, sorting, and pagination options within the
   * request body to narrow the attachment set.
   *
   * Security considerations include ensuring that only users with permission to
   * view the article or its attachments may call this endpoint. Permissions may
   * be enforced via business logic, role checks, or visibility constraints.
   * Response data includes only summary fields relevant for display or
   * management, omitting storage URIs and backend-only information. The
   * underlying implementation efficiently paginates results, supporting
   * scalable frontend consumption of attachment metadata.
   *
   * @param connection
   * @param articleId Unique identifier (UUID) of the article whose attachments
   *   are being retrieved.
   * @param body Query object for pagination, sorting, and filtering attachments
   *   linked to the article.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleAttachment.IRequest,
  ): Promise<IPageIDiscussionBoardArticleAttachment.ISummary> {
    try {
      return await patchDiscussionBoardArticlesArticleIdAttachments({
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve metadata for a specified article attachment using article and
   * attachment IDs.
   *
   * Retrieve full detailed metadata for a single attachment that is linked to
   * the given article, identified by its UUID within the article's set of
   * attachments.
   *
   * This operation is used when a client needs in-depth information on a
   * specific attachment, such as when preparing to preview, download, or
   * moderate a file. It enforces both article and attachment existence, as well
   * as linkage integrity: the attachment must be owned by the specified
   * article. Security and authorization checks ensure that only users with
   * access rights to the article (and relevant attachments) may use this
   * endpoint. The response excludes any backend-only storage or security
   * fields, returning attachment metadata relevant for client display and
   * auditing.
   *
   * The implementation validates that both the article and the attachment exist
   * and are properly linked, returning an error if linkage fails or if the
   * attachment has been soft-deleted.
   *
   * @param connection
   * @param articleId Unique identifier (UUID) of the article to which the
   *   attachment belongs.
   * @param attachmentId Unique identifier (UUID) of the attachment record being
   *   retrieved.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":attachmentId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticleAttachment> {
    try {
      return await getDiscussionBoardArticlesArticleIdAttachmentsAttachmentId({
        articleId,
        attachmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
