import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardArticlesArticleIdAttachments } from "../../../../providers/patchDiscussionBoardArticlesArticleIdAttachments";
import { getDiscussionBoardArticlesArticleIdAttachmentsAttachmentId } from "../../../../providers/getDiscussionBoardArticlesArticleIdAttachmentsAttachmentId";

import { IPageIDiscussionBoardArticleAttachment } from "../../../../api/structures/IPageIDiscussionBoardArticleAttachment";
import { IDiscussionBoardArticleAttachment } from "../../../../api/structures/IDiscussionBoardArticleAttachment";

@Controller("/discussionBoard/articles/:articleId/attachments")
export class DiscussionboardArticlesAttachmentsController {
  /**
   * Paginated and searchable list of attachments for a specified article
   * (discussion_board_article_attachments).
   *
   * Retrieve a searchable and paginated list of all attachments for a specific
   * article in the discussion board. This API allows clients to request
   * attachments related to an article, supporting advanced search capabilities
   * by file name (with full-text match), file type (MIME), and upload date
   * through request filters.
   *
   * The returned data includes all metadata such as storage URI, filename, MIME
   * type, file size (with enforced business rule limits), and upload
   * timestamps. This enables clients to efficiently display, preview, or
   * download relevant files. Security considerations ensure that only
   * article-level permissions are checked—if the article or its attachments
   * have been deleted or moved, appropriate error responses are issued.
   *
   * This operation is optimized for scenarios like evidence-based discussions,
   * where users need to access supporting files contributed to an article.
   * Pagination and sorting capabilities enable scalable user experiences in
   * both web and mobile clients.
   *
   * @param connection
   * @param articleId Unique identifier of the parent article whose attachments
   *   are being queried.
   * @param body Attachment search and pagination parameters, including file
   *   name, MIME type, and uploaded date filters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleAttachment.IRequest,
  ): Promise<IPageIDiscussionBoardArticleAttachment.ISummary> {
    try {
      return await patchDiscussionBoardArticlesArticleIdAttachments({
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detail metadata for a specific article attachment
   * (discussion_board_article_attachments).
   *
   * Retrieve full metadata and storage information for a single attachment
   * associated with a given article. This endpoint allows clients to access all
   * available properties of an attachment—such as its storage URI, MIME type,
   * original filename, file size, and upload timestamp—as defined in the
   * discussion_board_article_attachments schema.
   *
   * This API enforces that the attachmentId truly belongs to the specified
   * articleId, preventing cross-article access and maintaining strict
   * relationship integrity. If the requested attachment is not found, or is not
   * scoped to the given article, a not-found or error response is provided for
   * clarity.
   *
   * The operation supports user-facing use cases such as previewing evidence
   * files, downloading attachments, or displaying metadata in the discussion
   * board UI. It is also the main accessor for attachment-level validations in
   * content moderation and auditing workflows.
   *
   * @param connection
   * @param articleId Unique identifier of the parent article that owns the
   *   attachment.
   * @param attachmentId Unique identifier of the attachment within the
   *   specified article.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":attachmentId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticleAttachment> {
    try {
      return await getDiscussionBoardArticlesArticleIdAttachmentsAttachmentId({
        articleId,
        attachmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
