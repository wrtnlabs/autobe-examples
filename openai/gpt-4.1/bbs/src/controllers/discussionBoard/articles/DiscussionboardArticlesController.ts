import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardArticles } from "../../../providers/patchDiscussionBoardArticles";
import { getDiscussionBoardArticlesArticleId } from "../../../providers/getDiscussionBoardArticlesArticleId";

import { IPageIDiscussionBoardArticle } from "../../../api/structures/IPageIDiscussionBoardArticle";
import { IDiscussionBoardArticle } from "../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/articles")
export class DiscussionboardArticlesController {
  /**
   * Retrieve a filtered, paginated list of discussion_board_articles.
   *
   * Fetch a paginated and filtered list of discussion board articles for
   * display or review.
   *
   * The result set may be filtered using search keywords against the title or
   * body, or by author (user or admin), and sorted according to parameters such
   * as creation date or relevance. Pagination options support efficient
   * navigation through large volumes of debates and posts.
   *
   * This endpoint is accessible publicly, allowing any user or unauthenticated
   * client to browse discussions without restriction unless articles are hidden
   * due to moderation. Advanced business rules, such as excluding deleted
   * articles or those flagged by admins, are enforced at the service layer.
   * Clients can use this operation to support article feed interfaces,
   * full-text search, or browsing experiences.
   *
   * @param connection
   * @param body Filter criteria, search keywords, pagination, and sorting
   *   options for searching articles.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve all details for a specific discussion board article
   * (discussion_board_articles).
   *
   * Retrieve the complete details of a discussion article for display to users
   * or administrators.
   *
   * This endpoint fetches a single article, using its unique identifier, and
   * returns all data fields as defined in the 'discussion_board_articles'
   * schema. This ensures clients receive both the essential article content and
   * critical metadata (timestamps for creation and last update, author
   * information for provenance, etc.). Both user-authored and admin-authored
   * articles are supported. Article access is available to all users regardless
   * of authentication status unless the article has been removed by
   * moderation.
   *
   * The operation enforces business rules regarding article visibility as
   * described in the requirements and supports future integration of moderation
   * or audit logs. Clients consuming this endpoint should also refer to comment
   * and attachment APIs for rendering related data. Error scenarios include
   * attempts to access removed articles, which result in appropriate errors
   * (e.g., not found or forbidden).
   *
   * Detailed validation logic ensures the articleId parameter is a valid UUID
   * and corresponds to an existing article.
   *
   * @param connection
   * @param articleId Unique identifier of the target discussion board article
   *   to retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await getDiscussionBoardArticlesArticleId({
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
