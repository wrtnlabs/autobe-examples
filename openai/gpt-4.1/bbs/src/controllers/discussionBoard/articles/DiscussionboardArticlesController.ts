import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardArticles } from "../../../providers/patchDiscussionBoardArticles";
import { getDiscussionBoardArticlesArticleId } from "../../../providers/getDiscussionBoardArticlesArticleId";

import { IPageIDiscussionBoardArticle } from "../../../api/structures/IPageIDiscussionBoardArticle";
import { IDiscussionBoardArticle } from "../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/articles")
export class DiscussionboardArticlesController {
  /**
   * Query and retrieve a paginated list of discussion articles from the system.
   *
   * This operation enables searching, filtering, and paginating the main
   * discussion_board_articles entities. Parameters such as title (partial
   * match), author, created/updated time window, and deletion status can be
   * provided in the request body. Supports powerful browsing capabilities:
   * default ordering is by most recent, but alternative sort or filter
   * parameters may be used. Returns a paginated response
   * (IPageIDiscussionBoardArticle.ISummary type) optimized for list display
   * with minimal metadata, but includes enough fields for the frontend to
   * present a complete article index.
   *
   * No authentication is required—this endpoint is public, allowing all users,
   * visitors, and admins to browse visible articles (soft-deleted and hidden
   * articles are visible only to privileged admins as per business logic).
   * Robust validation is performed: invalid, misformatted, or excessive input
   * parameters yield structured error messages. The endpoint is central for the
   * discussion board's browsing and search functionality and is the main entry
   * point for public/read operations over articles. For detailed article
   * retrieval, alternative GET /articles/{articleId} endpoint is available (not
   * covered here).
   *
   * @param connection
   * @param body Request parameters for filtering, sorting, and paginating
   *   article results (title, author, date range, deletion status, sort
   *   criteria, pagination info).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete detail record for a single discussion board article
   * using its unique articleId (UUID primary key).
   *
   * This endpoint allows any client to access full information for published or
   * non-deleted board articles. The detailed response includes title, content,
   * author identifier (user_id), and essential audit timestamps (created_at,
   * updated_at, deleted_at if soft deleted). Soft deleted articles return a
   * deleted_at value for moderation purposes but may be excluded from standard
   * public listings.
   *
   * Access is public, meaning any user (authenticated or not) can fetch article
   * details as long as the article is not soft deleted. For deleted articles,
   * special moderation or administrative clients may access them for audit or
   * compliance, but public clients will typically receive not-found responses.
   *
   * The articleId path parameter must be a valid UUID; requests with an invalid
   * or non-existent ID will result in 404 not found. Attachments are not
   * included by default in this direct detail view. For attachment metadata and
   * file references, a separate endpoint against
   * discussion_board_article_attachments is available.
   *
   * @param connection
   * @param articleId Unique identifier (UUID) of the discussion board article
   *   to retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await getDiscussionBoardArticlesArticleId({
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
