import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { IDiscussionBoardUser } from "../../../api/structures/IDiscussionBoardUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Register a new user account (discussion_board_users) as a member actor with
   * session start.
   *
   * Registers a new user account in the discussion_board_users table by storing
   * email, password_hash (hashed by the service), display_name, and optional
   * avatar_url, leveraging schema constraints for uniqueness, length, and
   * optionality. Does not set is_locked or deleted_at, ensuring the account is
   * active upon creation. Soft deletion and locks are deferred to update/delete
   * operations, not present on registration.
   *
   * Implements full business rules for user credentials: unique email,
   * non-empty display_name, secure password captured as password_hash (never
   * plain text), and avatar_url accepted as optional per schema definition.
   * Account locking and soft deletion fields are exposed for future permission
   * or moderation flows only, not triggered here.
   *
   * On success, immediately issues a new session in
   * discussion_board_user_sessions, capturing session audit attributes: ip,
   * href, referrer, and timestamps for security review. This aligns to the
   * schema's session relationship for usage reporting, recovery, and
   * compliance.
   *
   * API strongly references the schema's author, display_name, password_hash,
   * is_locked, and avatar_url columns, and enforces validation strictly per
   * backend logic specified for those columns. No extraneous fields are
   * considered. Avatar_url's presence is optional, matching the schema's
   * handling of nullable values and enforced size/type.
   *
   * Security is implemented using JWT token response structures, compliant with
   * core DiscussionBoard requirements and the business logic described in actor
   * flows. This endpoint sets up the foundational credential for all
   * authenticated workflows for regular members.
   *
   * Relates to login (next step in JWT issuance) and refresh (for session
   * continuation), all using the same authorization actor. This endpoint never
   * returns raw password_hash, but only returns tokens and session meta per
   * IDiscussionBoardUser.IAuthorized structure.
   *
   * @param connection
   * @param body User registration details for creation of a new
   *   discussion_board_users record, including required email (unique),
   *   password, display_name, and optional avatar_url. All fields must conform
   *   to schema validation rules.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardUser.ICreate,
  ): Promise<IDiscussionBoardUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * User login for discussion_board_users to create a JWT session as a member
   * actor.
   *
   * Authenticates a member (user) for the discussion board by verifying
   * submitted credentials against the email and password_hash stored in the
   * discussion_board_users table. Only accounts with is_locked=false and
   * deleted_at=null may log in, hard enforcing schema's lock and soft-delete
   * logic for security. On successful authentication, creates a new session in
   * discussion_board_user_sessions for the audit trail and returns JWT tokens
   * and authorized context as defined in IDiscussionBoardUser.IAuthorized
   * structure. Login flows comply with the schema's unique email, hashed
   * password, and soft/hard lockout controls. Does not allow login if is_locked
   * is true or deleted_at is not null, enabling business rules for
   * banned/suspended or deleted actors. Auditing uses related session columns
   * (ip, href, referrer) and timestamping. No sensitive columns like raw
   * password_hash are exposed via API response.
   *
   * The API references schema constraints for both login credentials and
   * session log. Integration with join (registration) and refresh (session
   * continuation) is explicit. Unsuccessful logins always hide details of
   * authentication state, leaking no business logic other than account not
   * found or credential invalid. All error responses follow the business-driven
   * validation failures per requirements.
   *
   * Related to join (initial registration) and refresh (session/token renewal).
   * This endpoint is the canonical login entry point for members (users).
   *
   * @param connection
   * @param body Credentials (email and password) for authenticating an existing
   *   member user. Parsed to validate against schema's email and password_hash
   *   columns.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardUser.ILogin,
  ): Promise<IDiscussionBoardUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT session and tokens for an authenticated member user
   * (discussion_board_users), using session validation.
   *
   * Refreshes the session and JWT tokens for a member user by validating the
   * provided refresh token against valid, unexpired
   * discussion_board_user_sessions records. Only active, not expired sessions
   * (expired_at is null or in the future) for non-deleted, non-locked users are
   * eligible. Integrates with the session fields in the schema to enforce
   * business logic for refresh validity and session rollover. On success,
   * issues new tokens via the IDiscussionBoardUser.IAuthorized response
   * structure; on failure, returns an explicit error tied to authentication
   * state.
   *
   * Relates to login (creates session) and join (initial registration) – forms
   * the third leg of membership authentication flows. Ensures tokens and
   * sessions always reference current schema structure and validation logic by
   * using only exposed session and user columns. No password_hash or other
   * credentials are re-used or re-exposed during the refresh. Integrates with
   * session and audit logic by chaining with session's created_at and
   * expired_at business flows.
   *
   * Does not expose any user or session schema columns directly in the API
   * response, only via authentication structure conforming to actor-appropriate
   * expectations. The refresh logic is an essential part of business
   * authentication flows for members (users).
   *
   * @param connection
   * @param body Refresh token for validating current session and extending
   *   token lifecycle. Only valid unexpired sessions for member actor allowed.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardUser.IRefresh,
  ): Promise<IDiscussionBoardUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
