import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { IDiscussionBoardUser } from "../../../api/structures/IDiscussionBoardUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * This endpoint allows new users to register an account on the discussion
   * board platform. It creates a new entry in the discussion_board_users table,
   * leveraging only the fields that are actually present in the schema, such as
   * `username`, `email`, and `password`, if available. User registration is
   * subject to all business rules and validation constraints, including
   * uniqueness checks for identifiers and compliance with password or identity
   * field requirements enforced at the schema level.
   *
   * Upon successful registration, the system issues initial authentication
   * tokens using JWT, granting immediate authenticated access so the user can
   * create, edit, or delete their own articles and comments. There is no
   * authentication required to access this endpoint, but the backend must
   * rigorously validate all input fields to maintain data integrity and
   * security. This operation is a primary entry point and must integrate
   * seamlessly with downstream session management.
   *
   * All sensitive operations, such as password hashing and verification token
   * generation (if schema fields exist), are strictly constrained to the fields
   * available within the discussion_board_users table. Business logic must
   * follow the rules described in platform requirements, including any specific
   * rules for handling new registrations stated in the requirements files
   * loaded in context.
   *
   * Exception cases, such as registration attempts with existing identifiers,
   * must produce consistent error responses conforming to the platform-wide API
   * error format. Related endpoints include login (for authenticating with
   * existing accounts) and refresh (for token renewal), completing the core
   * authentication workflow.
   *
   * Schemas referenced by this operation must only cite fields verifiably
   * present in discussion_board_users; placeholder or assumed fields are
   * prohibited. For a comprehensive authentication lifecycle, users should
   * proceed to login with the credentials created via this endpoint after
   * registration is complete if automatic login is not performed upon join.
   *
   * @param connection
   * @param body Fields required to create a new user account as per
   *   discussion_board_users schema. Only include real schema fields.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardUser.ICreate,
  ): Promise<IDiscussionBoardUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint provides login functionality for registered users of the
   * discussion board system. It uses only actual credential fields defined in
   * the discussion_board_users table, which may include `username`, `email`,
   * and/or `password`, according to the schema. Upon receiving correct
   * credentials, the backend authenticates the identity, issues new JWT access
   * and refresh tokens, and records the session if session management is
   * present in the requirements or database.
   *
   * All input validation must be performed against the true database schema
   * fields, with no assumptions about identifier type or secret field names.
   * Error messages for failed logins must not reveal specifics about which
   * credential was incorrect, to maintain security and best practices.
   *
   * The operation does not require prior authentication and is publicly
   * accessible. On success, the user obtains JWT tokens permitting them to
   * access protected endpoints for article and comment posting, file
   * attachments, and profile management as allowed by business rules.
   *
   * Business logic, including account lockout and rate limiting (if present in
   * requirements or schema), must adhere strictly to those rules and only use
   * fields present in the discussion_board_users table. Related endpoints are
   * the registration (join) endpoint for account creation and the refresh
   * endpoint for session renewal, providing a full authentication lifecycle.
   *
   * Reference to schema fields in all documentation and error responses is
   * mandatory, and no unsupported operations should be enabled if the schema is
   * lacking the required fields.
   *
   * @param connection
   * @param body Credentials for this login operation per discussion_board_users
   *   schema. Use only fields that actually exist in the schema.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardUser.ILogin,
  ): Promise<IDiscussionBoardUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint processes refresh token requests for persistent JWT-based
   * sessions. By submitting a valid refresh token (provided at registration or
   * login), the user receives a new set of access and refresh tokens, extending
   * their session according to business rules and requirements. This mechanism
   * uses only schema- and requirement-documented fields such as session
   * references, refresh token tables, or dedicated fields in
   * discussion_board_users if present.
   *
   * No credential validation is required here; the endpoint is accessed by
   * token holders to maintain a seamless login experience. The backend must
   * rigorously validate token expiration, revocation status, and integrity
   * before issuing new tokens, as informed by the schema and requirements.
   *
   * Special care must be taken to avoid leaking sensitive details in error
   * responses related to refresh failures. This endpoint forms an integral part
   * of the authentication workflow, working with the registration (join) and
   * login operations to provide a complete secure lifecycle.
   *
   * Session recording or logging (if schema or requirements specify) should
   * track refresh events as appropriate, ensuring auditability as per platform
   * governance.
   *
   * Schema field references and implementation must remain strictly constrained
   * to what exists in discussion_board_users and subsidiary session tables,
   * with no inferred or placeholder fields allowed.
   *
   * @param connection
   * @param body Payload for refresh token request. Must be compatible with
   *   schema fields for refresh operations.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardUser.IRefresh,
  ): Promise<IDiscussionBoardUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
