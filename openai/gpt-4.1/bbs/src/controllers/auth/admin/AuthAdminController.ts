import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { IDiscussionBoardAdmin } from "../../../api/structures/IDiscussionBoardAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Creates a new administrator in the discussion_board_admins table and
   * returns JWT session.
   *
   * The administrator registration operation enables the secure creation of new
   * admin accounts in the discussion_board_admins table. This endpoint strictly
   * enforces the business requirement that platform administrators must
   * authenticate using unique, valid email addresses and strong passwords. When
   * a registration request is made, the system verifies email uniqueness via
   * the Prisma model constraint and mandates password strength (at least 8
   * characters, with numbers, letters, and special characters).
   *
   * Upon successful registration, the system sets is_email_verified to false,
   * marks is_active true, and is_blocked false, reflecting policy-compliant
   * default access. The password is stored as a bcrypt hash in the
   * password_hash field—no plaintext storage is allowed under any circumstance.
   * The registration workflow ensures auditability by stamping created_at and
   * updated_at, and supports later compliance actions via the optional
   * deleted_at soft delete field.
   *
   * The Prisma schema's unique index on email field directly powers business
   * validation; any duplicate triggers an error response. All admin session
   * records (created in discussion_board_admin_sessions) are linked to a unique
   * admin id (UUID), providing audit, time stamping, and traceability required
   * for platform moderation roles. Creation of an admin account is strictly
   * separated from assignment of elevated privileges—these must subsequently be
   * set by platform operators.
   *
   * The operation returns a JWT access and refresh token pair (see
   * IDiscussionBoardAdmin.IAuthorized), empowering immediate admin moderation
   * actions on the platform, in strict accordance with stateless, scalable
   * authentication policies. Business logic is tightly mapped to the schema for
   * maximal compiler safety, maintainability, and transparency.
   *
   * Related endpoints for login or token refresh are required for the full
   * admin authentication suite, enabling full coverage of onboarding and
   * session management. Any failure to meet field or business requirements
   * produces explicit, actionable errors for rapid feedback and improved
   * developer experience.
   *
   * @param connection
   * @param body Administrator registration info (email, password).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardAdmin.IJoin,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an administrator from discussion_board_admins and issues JWT
   * tokens.
   *
   * The admin login endpoint authenticates an administrator using their unique
   * email and secure password, as stored in the discussion_board_admins Prisma
   * table. Credentials are validated by first verifying the existence of the
   * email, then hashing and comparing the input password against password_hash.
   * The account must also be active and not blocked (is_active=true,
   * is_blocked=false).
   *
   * Business validation leverages the unique index on email and audits the
   * login attempt for compliance. If the credentials are invalid or the admin
   * is blocked, a relevant error message is produced. Soft deletion is enforced
   * (deleted_at is checked), and the email verification flag
   * (is_email_verified) may be checked in extended policies. Security is
   * paramount: all password checks use secure, salt-hardened hashes and error
   * messages must be generic to avoid information leakage.
   *
   * Successful authentication results in new JWT session tokens (access,
   * refresh) returned in IDiscussionBoardAdmin.IAuthorized, empowering
   * immediate moderation and account actions per the actor's role. Session
   * creation and time stamping supports comprehensive audit logs in
   * discussion_board_admin_sessions, meeting strict platform requirements for
   * compliance and traceability.
   *
   * The endpoint is central to all administrator moderation, user management,
   * and compliance tasks, and is complemented by token refresh and logout
   * endpoints for complete stateless session design. Security, audit, and
   * business logic directly tie to actual Prisma schema fields for safe,
   * maintainable implementation.
   *
   * @param connection
   * @param body Administrator login credentials (email, password).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardAdmin.ILogin,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes JWT tokens for administrator via discussion_board_admin_sessions.
   *
   * The admin token refresh endpoint enables an authenticated administrator to
   * renew their JWT access/refresh tokens using a valid refresh token, as
   * required by platform business rules and the discussion_board_admin_sessions
   * secondary table. The refresh process validates the session and admin
   * account status using Prisma fields (is_active, is_blocked, deleted_at). If
   * the request passes validation, a new authorized session response is
   * returned (IDiscussionBoardAdmin.IAuthorized), powering stateless session
   * rotation and secure long-term moderation access.
   *
   * If the refresh request references a revoked, expired, or invalidated
   * token/session, the operation fails securely with a generic error—no
   * sensitive implementation details are leaked. All session renewal actions
   * are logged for audit by updating discussion_board_admin_sessions. This
   * endpoint is essential for best-practice JWT token management, supporting
   * business-critical requirements for automatic session renewal, long-term
   * moderation, and transparent compliance tracing.
   *
   * The operation is deeply integrated with admin compliance mechanisms and may
   * trigger platform alerts if a session is being abused or misused. Related
   * endpoints for login, registration, and logout complete the admin
   * authentication flow, with every step anchored to fields and constraints in
   * the loaded Prisma schema.
   *
   * @param connection
   * @param body Current valid refresh token.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardAdmin.IRefresh,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
