import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { IDiscussionBoardAdmin } from "../../../api/structures/IDiscussionBoardAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Register a new admin account within the discussion_board_admins table and
   * issue the initial JWT tokens.
   *
   * This POST endpoint enables new administrator registration on the discussion
   * board platform by inserting a record in the 'discussion_board_admins'
   * table. The schema requires an email, a plaintext password (which is then
   * securely hashed), display_name, and allows an optional avatar_url string
   * field. On account creation, is_locked must be set to false and deleted_at
   * must be null, while created_at/updated_at timestamps are set automatically.
   * All email addresses must be unique, enforced by the @@unique constraint. If
   * registration attempts use a duplicate email, the request is rejected with a
   * descriptive error referencing the relevant unique index. The admin profile
   * is created with only fields explicitly defined in the schema, aligning with
   * privacy compliance and security requirements. This operation is for
   * privileged actors: endpoints MUST be locked down and typically disabled in
   * production to prevent arbitrary admin creation. Responses return the full
   * details of the newly registered admin, only from fields present in the
   * schema, plus the issued tokens in accordance with JWT practices. Related
   * endpoints: login and refresh must be used for subsequent auth/session
   * flows. The 'deleted_at' field supports future soft deletion and compliance
   * cases but is always null at creation time. Passwords are never returned in
   * responses or logs. This operation must be paired with login/database
   * existence checks before registering an admin with the same email,
   * supporting both business integrity and schema robusteness.
   *
   * @param connection
   * @param body Admin registration details (email, password, display_name,
   *   optional avatar_url) as required by discussion_board_admins schema. Only
   *   explicitly present fields accepted.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardAdmin.ICreate,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing admin account within the discussion_board_admins
   * table and issue new JWT tokens.
   *
   * This POST endpoint authenticates administrators using credentials stored in
   * the 'discussion_board_admins' table. The operation checks that the provided
   * email exists and is unique (enforced by the @@unique constraint), and that
   * the supplied password, when properly hashed, matches the stored
   * password_hash. If is_locked is true, or the deleted_at field is non-null,
   * login is denied with a business-appropriate error. Successful logins
   * establish a new admin session (discussion_board_admin_sessions record) with
   * the relevant created_at/expired_at timestamps and session metadata. On
   * correct credentials, the operation issues JWT access and refresh tokens as
   * expected by requirements, including admin profile data and authorized
   * permission tags. The avatar_url field is returned if present. This endpoint
   * is the exclusive admin login API: all incorrect login attempts are
   * carefully traced and all errors avoid information leaks. Related endpoints:
   * join must be used for admin registration; refresh must be used for
   * session/token lifecycle management.
   *
   * @param connection
   * @param body Administrator login credentials for authentication (email and
   *   password only per schema).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardAdmin.ILogin,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT tokens for the discussion_board_admins account after verifying
   * session validity.
   *
   * This POST endpoint refreshes the JWT tokens for an admin actor on the
   * discussion board, providing continuity for authenticated administrative
   * sessions. It verifies the supplied refresh token against valid, non-expired
   * session records in the discussion_board_admin_sessions table, ensuring that
   * the admin account is not locked and not soft-deleted per the is_locked and
   * deleted_at fields in the discussion_board_admins schema. Upon successful
   * validation, it issues new JWT access and refresh tokens along with the full
   * current admin profile (limited strictly to fields in the schema). The
   * endpoint does not allow impersonation, privilege escalation, or refresh for
   * deleted/locked accounts. Related endpoints: login (required for initial
   * session/token acquisition); join (admin registration). Subsequent business
   * logic may rotate or revoke tokens and sessions depending on compliance
   * requirements.
   *
   * @param connection
   * @param body Valid refresh token and session information for token renewal,
   *   matching admin schema/session requirements.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardAdmin.IRefresh,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
