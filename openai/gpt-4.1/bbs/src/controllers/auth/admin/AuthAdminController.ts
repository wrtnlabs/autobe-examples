import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { IDiscussionBoardAdmin } from "../../../api/structures/IDiscussionBoardAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Registers a new admin account in discussion_board_admins table.
   *
   * This operation registers a new board administrator, referencing the
   * discussion_board_admins table. The client submits a unique email and
   * password (will be hashed inside the service) to create a new admin record.
   * Only the email and password_hash fields are populated by the initial join
   * request, while created_at, updated_at, and (null) deleted_at are populated
   * internally by the system. Email uniqueness is enforced and derived from the
   * unique index. Passwords are stored as hashed values only, never in raw
   * form, reflecting strict security described in schema comments.
   *
   * After joining successfully, the service issues a set of authentication
   * tokens using the admin's new identity; these tokens follow standard JWT
   * conventions. This design prevents direct linkage to any user account schema
   * and is compliant with business requirements for strict separation between
   * admins and regular users.
   *
   * The operation is open and requires no prior authentication but enforces all
   * validation rules regarding uniqueness and password encoding. Admin accounts
   * created through this endpoint can perform all moderation and management
   * actions indicated by admin role definition, but account removal,
   * suspension, or soft deletion is achieved through separate operations, not
   * through join, as indicated by the discussion_board_admins schema.
   *
   * @param connection
   * @param body Administrator registration information (email and password).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardAdmin.IJoin,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an administrator from discussion_board_admins table and
   * issues JWT tokens.
   *
   * Allows a registered admin to log in using their email and password. This
   * operation reads the discussion_board_admins table by email (enforcing that
   * email is unique across admins) and verifies the provided password using a
   * BCrypt comparison to the stored password_hash. The account is checked for
   * soft-deleted status by confirming deleted_at is null before proceeding.
   *
   * On successful authentication, the server issues fresh JWT tokens and
   * returns the admin's identity in an authorized response, strictly
   * referencing the definition of admin authentication fields in the schema.
   * The operation enforces security without leaking whether an email is
   * registered or not, adhering to best practices described in the database
   * schema description.
   *
   * This endpoint does not allow login for deleted accounts (deleted_at not
   * null). All authentication logic matches expectations for privileged admin
   * access, and ties directly to business needs for robust moderation and
   * oversight.
   *
   * @param connection
   * @param body Administrator authentication credentials (email and password).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardAdmin.ILogin,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews JWT tokens for an admin account from discussion_board_admins table.
   *
   * This operation allows an authenticated admin to refresh their set of JWT
   * tokens. The refresh token is checked against session data and only valid if
   * the admin's account (located in the discussion_board_admins table) is still
   * active (deleted_at remains null). If validation succeeds, a new tuple of
   * JWT tokens is issued and returned in the response (see
   * IDiscussionBoardAdmin.IAuthorized). Attempts to refresh for soft-deleted or
   * non-existent accounts are rejected, strictly following schema and business
   * policy. This operation integrates fully with admin authentication flows and
   * supports audit requirements for admin identity renewal.
   *
   * Note this endpoint must enforce strict verification of the refresh token,
   * including linking to the current admin record and confirming account status
   * via discussion_board_admins fields, matching the design intent described in
   * the schema. No other admin or user identities are affected.
   *
   * @param connection
   * @param body Refresh token request for admin identity renewal.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardAdmin.IRefresh,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
