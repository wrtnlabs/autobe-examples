/**
 * Create a temporary guest identity (writes to todo_app_guest).
 *
 * Purpose and overview: This operation creates a new guest identity record in
 * the `todo_app_guest` table. The record will populate the table fields such as
 * `id`, `created_at`, `updated_at`, and may include an optional
 * `anonymous_label`. The created guest identity is intended for ephemeral
 * identification of unauthenticated visitors and to enable issuance of
 * temporary access tokens for read-only public content access.
 *
 * Implementation details and schema references: The operation writes to
 * `todo_app_guest` (Prisma model `todo_app_guest`). Confirmed columns available
 * for use are: `id` (primary key), `created_at`, `updated_at`, `deleted_at`
 * (soft-delete timestamp), and `anonymous_label`. On creation the
 * implementation must set `created_at` and `updated_at`. Because `deleted_at`
 * exists on the model, the application can record soft-delete for guest records
 * if necessary; however typical guest accounts are short-lived and the service
 * may choose to leave `deleted_at` null for active ephemeral guests.
 *
 * Actor-specific integration and business context: Guests are unauthenticated
 * visitors that may view public lists and shared content only. The guest row
 * intentionally contains no password or credential fields. The guest record can
 * be used to link ephemeral browsing sessions to public interactions; guests
 * relate indirectly to lists and public interactions via other components in
 * the schema, for example public list sharing (`todo_app_list_shares`) and
 * public index preferences (`todo_app_public_index_preferences`). This
 * operation is public (no prior authentication) and returns an authorization
 * payload enabling limited read access.
 *
 * Security considerations and validation rules: Because the `todo_app_guest`
 * model does not hold authentication credentials, token issuance must be
 * managed by the authorization subsystem (tokens themselves are not persisted
 * in `todo_app_guest` fields). The server MUST issue short-lived access and
 * refresh tokens following business rules for guest sessions. Validate any
 * provided optional `anonymous_label` against application rules (e.g., max
 * length) before persisting. Record the creation event in activity/audit logs
 * (e.g., `todo_app_user_activity_logs`) to support traceability; do not persist
 * secrets in the guest table.
 *
 * Related operations and workflow integration: This endpoint is intended to be
 * used together with a token refresh endpoint (`POST /auth/guest/refresh`) and
 * with public list read endpoints. Clients will call `POST /auth/guest/join` to
 * obtain initial temporary authorization and then use refresh when the refresh
 * token is available. The `todo_app_guest` table is the canonical Prisma table
 * referenced by this operation.
 *
 * @param props.connection
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/join
 * @accessor api.functional.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(connection: IConnection): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Response = ITodoAppGuest.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/guest/join",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/guest/join";
  export const random = (): ITodoAppGuest.IAuthorized =>
    typia.random<ITodoAppGuest.IAuthorized>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Refresh guest authorization (associated with todo_app_guest).
 *
 * Purpose and overview: This endpoint accepts a refresh credential from a
 * previously issued guest authorization and returns a renewed short-lived
 * access (and optionally a renewed refresh) token. It conceptually maps to the
 * guest identity represented by the `todo_app_guest` table so audit and
 * activity logs may reference `todo_app_guest.id` for traceability.
 *
 * Implementation details and schema references: The `todo_app_guest` model
 * contains `id`, `created_at`, `updated_at`, `deleted_at`, and
 * `anonymous_label`. This model does not include persistent fields for refresh
 * tokens or revocation timestamps; therefore, implementations must validate
 * refresh tokens against the token store or the session subsystem rather than
 * relying on columns in `todo_app_guest`. Successful refresh operations SHOULD
 * record activity in `todo_app_user_activity_logs` or `todo_app_audit_logs` for
 * monitoring and abuse detection.
 *
 * Actor-specific integration and business context: Guests only have read-only
 * access to public/shared lists; refreshing a guest session only extends that
 * ephemeral read access and does not convert a guest into a persistent
 * authenticated account. If a refresh token is presented for a guest that no
 * longer has an active guest record (for example, the `deleted_at` column is
 * set), the refresh operation MUST fail and return an appropriate authorization
 * error.
 *
 * Security considerations and validation rules: Validate the refresh token for
 * integrity and expiry before issuing new access tokens. Because
 * `todo_app_guest` lacks refresh-token fields, the refresh token store must
 * support revocation (for example, blacklists or a centralized session store).
 * Log refresh attempts (success/failure) in `todo_app_user_activity_logs` with
 * reference to the acting `todo_app_guest.id` where available. Enforce
 * anti-replay and rate-limiting controls to prevent abuse.
 *
 * Related operations and workflow integration: This operation pairs with `POST
 * /auth/guest/join` (initial issuance). Implementations should also consider a
 * public registration (member join) flow separate from guest operations. Where
 * a guest transitions to a registered account, ensure refresh tokens are
 * invalidated and relevant audit entries are recorded.
 *
 * @param props.connection
 * @param props.body Refresh request containing the guest refresh credential
 *   (application/json). The schema should include a single `refreshToken`
 *   string property in the components as an appropriate request DTO.
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/refresh
 * @accessor api.functional.auth.guest.refresh
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function refresh(
  connection: IConnection,
  props: refresh.Props,
): Promise<refresh.Response> {
  const output: refresh.Response =
    true === connection.simulate
      ? refresh.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...refresh.METADATA,
            path: refresh.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
