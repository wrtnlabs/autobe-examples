/**
 * Register a new admin (creates todo_app_admin record and returns authorization
 * payload).
 *
 * Purpose and overview: This endpoint registers a new administrative operator
 * and creates a record in the Prisma `todo_app_admin` table. The operation
 * accepts an email, a plaintext password (to be hashed server-side and
 * persisted to `password_hash`), and optional `display_name` and `role` fields.
 * The endpoint is public and intended for controlled admin onboarding flows
 * only.
 *
 * Implementation details and DB field usage: On successful registration the
 * implementation MUST create a `todo_app_admin` row setting `email`,
 * `password_hash` (hashed server-side), `display_name` (if provided), and
 * `role` (if provided). The Prisma schema enforces uniqueness on `email`
 * (`@@unique([email])`) so the controller MUST return a validation error if the
 * submitted email already exists. Timestamps `created_at` and `updated_at` are
 * recorded by the service per the schema contract.
 *
 * Actor-specific integration and lifecycle: The `todo_app_admin` model exposes
 * `is_active` and `deleted_at` which the service can use for admin lifecycle
 * (activation, suspension, or removal). While this endpoint creates the admin
 * record, downstream admin lifecycle operations (suspend/reactivate) should
 * update `is_active` and may set `deleted_at` when an admin is removed; those
 * actions are separate and not performed by this join operation.
 *
 * Security considerations and token issuance: The endpoint MUST never log
 * plaintext passwords. The server MUST hash the supplied password before
 * writing to `password_hash`. After successful creation the endpoint SHOULD
 * issue the standard authorization response (short-lived access token and
 * longer-lived refresh token) and use secure cookie or Authorization header
 * semantics per platform rules. Because admin accounts are high-privilege, the
 * implementation SHOULD require out-of-band approval or invite-code validation
 * in production; that gating is an implementation choice but must reference the
 * `email` uniqueness constraint and `role` semantics in the schema.
 *
 * Related operations and error handling: This operation is intended to be used
 * together with `POST /auth/admin/login` and `POST /auth/admin/refresh`.
 * Validation errors to return include duplicate `email` (conflict/400 with
 * details), invalid email format, and password policy violations. Successful
 * responses return an authorized payload referencing the `todo_app_admin`
 * identity and tokens.
 *
 * @param props.connection
 * @param props.body Admin registration payload. The server expects email and
 *   password; optional display_name and role may be provided.
 * @setHeader token.access Authorization
 *
 * @path /auth/admin/join
 * @accessor api.functional.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
