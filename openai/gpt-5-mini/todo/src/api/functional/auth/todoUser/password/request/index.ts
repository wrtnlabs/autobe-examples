/**
 * Request a password reset for a todoUser (updates password_reset_token and
 * password_reset_expires_at).
 *
 * Purpose and overview: Allows a user (or guest supplying an email) to request
 * a password reset. Implementation will create or update the fields
 * todo_app_todouser.password_reset_token and
 * todo_app_todouser.password_reset_expires_at so the reset action can be
 * verified later.
 *
 * Implementation details and field usage: This operation references schema
 * fields password_reset_token and password_reset_expires_at directly. The
 * server must persist an opaque token in password_reset_token and set
 * password_reset_expires_at to a near-future expiry (e.g., one hour). The API
 * must not return the stored token in the response; instead, it triggers an
 * email containing a secure acceptance link embedding the invite/reset code.
 *
 * Actor-specific integration: This is a public operation (authorizationActor:
 * null) related to todoUser accounts. It ties to todo_app_todouser by email and
 * writes the reset fields for use by the reset endpoint.
 *
 * Security considerations: Because password_reset_token is persisted, the
 * implementation must ensure tokens are high-entropy and single-use. The
 * description references exact schema fields: password_reset_token and
 * password_reset_expires_at and notes the responsibility to clear or rotate
 * tokens on successful reset.
 *
 * Related operations and workflow: After the user receives the reset link, use
 * POST /auth/todoUser/password/reset to finalize the reset and rotate refresh
 * tokens via refresh_tokens_revoked_at.
 *
 * @param props.connection
 * @param props.body Password reset request payload containing the user's email
 *   to identify todo_app_todouser record. Maps to todo_app_todouser.email for
 *   lookup.
 * @path /auth/todoUser/password/request
 * @accessor api.functional.auth.todoUser.password.request.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<requestPasswordReset.Response> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
