import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppTodoUser } from "../../../../../structures/ITodoAppTodoUser";

/**
 * Reset a todoUser's password using a valid reset token (todo_app_todouser).
 *
 * Purpose and overview: Finalizes a password reset by validating
 * todo_app_todouser.password_reset_token and password_reset_expires_at,
 * updating todo_app_todouser.password_hash with a newly hashed password, and
 * clearing the reset token fields.
 *
 * Implementation details and field usage: This operation references the exact
 * schema fields: password_reset_token, password_reset_expires_at,
 * password_hash, and refresh_tokens_revoked_at. On successful reset the
 * implementation MUST set password_hash to the new hashed password, nullify
 * password_reset_token and password_reset_expires_at, and set
 * refresh_tokens_revoked_at to the current time to revoke any outstanding
 * refresh tokens.
 *
 * Actor-specific integration: This is a public operation that transitions a
 * user credential state and affects the user's session revocation window via
 * refresh_tokens_revoked_at.
 *
 * Security considerations: The endpoint must enforce one-time use of
 * password_reset_token and ensure that tokens cannot be replayed. It must never
 * return password_hash or refresh token values.
 *
 * Related operations and workflow: This operation complements
 * requestPasswordReset. After reset, the client should re-authenticate (login)
 * to obtain fresh tokens.
 *
 * @param props.connection
 * @param props.body Password reset confirmation payload containing the reset
 *   token and the new password. Server validates token against
 *   todo_app_todouser.password_reset_token and expiry
 *   (password_reset_expires_at).
 * @path /auth/todoUser/password/reset
 * @accessor api.functional.auth.todoUser.password.reset.resetPassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resetPassword(
  connection: IConnection,
  props: resetPassword.Props,
): Promise<resetPassword.Response> {
  return true === connection.simulate
    ? resetPassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resetPassword.METADATA,
          path: resetPassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resetPassword {
  export type Props = {
    /**
     * Password reset confirmation payload containing the reset token and
     * the new password. Server validates token against
     * todo_app_todouser.password_reset_token and expiry
     * (password_reset_expires_at).
     */
    body: ITodoAppTodoUser.IResetPassword;
  };
  export type Body = ITodoAppTodoUser.IResetPassword;
  export type Response = ITodoAppTodoUser.ISummary;

  export const METADATA = {
    method: "POST",
    path: "/auth/todoUser/password/reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/todoUser/password/reset";
  export const random = (): ITodoAppTodoUser.ISummary =>
    typia.random<ITodoAppTodoUser.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: resetPassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resetPassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
