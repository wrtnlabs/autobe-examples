/**
 * Create a new todoUser account (todo_app_todouser) and return initial
 * authorization tokens.
 *
 * Purpose and overview: This endpoint registers a new todoUser by creating a
 * row in the Prisma table todo_app_todouser. It persists the provided email and
 * a hashed password (stored in the schema column password_hash) and records
 * creation metadata fields such as created_at and updated_at. The API will
 * initialize account lifecycle fields (status) and set is_verified according to
 * verification flow expectations.
 *
 * Implementation details and field usage: On successful registration the
 * implementation will populate todo_app_todouser.email and
 * todo_app_todouser.password_hash. It will set todo_app_todouser.status (for
 * example to "pending_verification" if email verification is required) and set
 * created_at/updated_at timestamps. The description references exact schema
 * fields: email, password_hash, is_verified, status, created_at, updated_at,
 * deleted_at.
 *
 * Actor-specific integration: This registration is the primary join operation
 * for the actor "todoUser" and produces the authentication bundle consumed by
 * subsequent actor operations (login, refresh). The response must follow the
 * authentication response pattern ITodoAppTodoUser.IAuthorized and the
 * operation path uses the actor name in the route (/auth/todoUser/join).
 *
 * Security considerations: The API MUST never return password_hash. Passwords
 * MUST be hashed before persisting to todo_app_todouser.password_hash. The
 * description references lockout-related schema fields (failed_login_attempts,
 * last_failed_login_at) only to note they exist and will be unset/zeroed on
 * successful registration. The endpoint must ensure that no sensitive seed data
 * (mfa_secret, mfa_backup_codes) are created implicitly without explicit user
 * action.
 *
 * Related operations and workflow: After join, clients typically call login to
 * authenticate or wait for verification. See related endpoints: POST
 * /auth/todoUser/login (login) and POST /auth/todoUser/refresh (refresh). If
 * the system requires email verification, the registration handler will set
 * status and rely on separate verification flows (note: verification token
 * fields are not present in the prisma schema and must be handled by an
 * external verification mechanism).
 *
 * @param props.connection
 * @param props.body Registration request payload for creating a new todoUser
 *   account. Maps to the todo_app_todouser table fields: email and initial
 *   password input (plain-text transmitted over TLS). Do not include fields
 *   that are stored server-side only such as password_hash, created_at,
 *   updated_at, deleted_at.
 * @setHeader token.access Authorization
 *
 * @path /auth/todoUser/join
 * @accessor api.functional.auth.todoUser.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
