import { ITodoAppTodoUser } from "../../../../../structures/ITodoAppTodoUser";

/**
 * Disable two-factor authentication for authenticated todoUser
 * (todo_app_todouser).
 *
 * Purpose and overview: This authenticated endpoint disables MFA for the
 * caller's account by clearing the stored MFA metadata and setting
 * todo_app_todouser.mfa_enabled=false.
 *
 * Implementation details and field usage: This operation references the exact
 * fields mfa_enabled, mfa_secret, and mfa_backup_codes. On successful disable
 * the implementation SHOULD nullify mfa_secret and mfa_backup_codes (or
 * securely overwrite) and set mfa_enabled to false. Audit logs referencing the
 * acting user should record the change.
 *
 * Actor-specific integration: Requires authentication (authorizationActor:
 * "todoUser"). The operation must protect against abuse by requiring
 * re-authentication or step-up verification before disabling MFA.
 *
 * Security considerations: Do not return persisted secrets. Clearing MFA should
 * also consider invalidating any backup codes and logging the operation in
 * todo_app_audit_logs for compliance.
 *
 * Related operations and workflow: Complementary to enableTwoFactor and login
 * flows that consult mfa_enabled during authentication.
 *
 * @param props.connection
 * @param props.body Disable MFA request (may include a confirmation or current
 *   password for step-up). Server will clear mfa_secret and mfa_backup_codes
 *   and set mfa_enabled=false on the todo_app_todouser row.
 * @path /auth/todoUser/mfa/disable
 * @accessor api.functional.auth.todoUser.mfa.disable.disableTwoFactor
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function disableTwoFactor(
  connection: IConnection,
  props: disableTwoFactor.Props,
): Promise<disableTwoFactor.Response> {
  return true === connection.simulate
    ? disableTwoFactor.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...disableTwoFactor.METADATA,
          path: disableTwoFactor.path(),
          status: null,
        },
        props.body,
      );
}
export namespace disableTwoFactor {
  export type Props = {
    /**
     * Disable MFA request (may include a confirmation or current password
     * for step-up). Server will clear mfa_secret and mfa_backup_codes and
     * set mfa_enabled=false on the todo_app_todouser row.
     */
    body: ITodoAppTodoUser.IDisableMfa;
  };
  export type Body = ITodoAppTodoUser.IDisableMfa;
  export type Response = ITodoAppTodoUser.ISummary;

  export const METADATA = {
    method: "POST",
    path: "/auth/todoUser/mfa/disable",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/todoUser/mfa/disable";
  export const random = (): ITodoAppTodoUser.ISummary =>
    typia.random<ITodoAppTodoUser.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: disableTwoFactor.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: disableTwoFactor.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
