/**
 * Revoke previously issued refresh tokens by setting refresh_tokens_revoked_at
 * (todo_app_todouser).
 *
 * Purpose and overview: Allows an authenticated todoUser to revoke outstanding
 * refresh tokens by setting todo_app_todouser.refresh_tokens_revoked_at to the
 * current time, preventing previously issued refresh tokens from being used to
 * obtain new access tokens.
 *
 * Implementation details and field usage: This operation references the exact
 * schema field refresh_tokens_revoked_at. On invocation the server updates this
 * field on the caller's todo_app_todouser row to the current timestamp.
 * Session-specific records in todo_app_todouser_sessions may be used for
 * presentation but the revocation mechanism is the refresh_tokens_revoked_at
 * cutoff.
 *
 * Actor-specific integration: Requires authentication (authorizationActor:
 * "todoUser"). The operation affects all refresh tokens issued before the new
 * refresh_tokens_revoked_at and is commonly called after password changes or
 * account compromise detection.
 *
 * Security considerations: The endpoint should log the revocation in
 * todo_app_audit_logs or todo_app_user_activity_logs, and may also optionally
 * terminate active sessions in todo_app_todouser_sessions depending on
 * implementation.
 *
 * Related operations and workflow: Often invoked by changePassword or
 * resetPassword flows that set refresh_tokens_revoked_at to revoke prior
 * tokens. Clients should be notified that existing sessions will require
 * re-authentication.
 *
 * @param props.connection
 * @path /auth/todoUser/revoke
 * @accessor api.functional.auth.todoUser.revoke.revokeRefreshTokens
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function revokeRefreshTokens(
  connection: IConnection,
): Promise<revokeRefreshTokens.Response> {
  return true === connection.simulate
    ? revokeRefreshTokens.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...revokeRefreshTokens.METADATA,
          path: revokeRefreshTokens.path(),
          status: null,
        },
      );
}
export namespace revokeRefreshTokens {
  export type Response = ITodoAppTodoUser.ISummary;

  export const METADATA = {
    method: "POST",
    path: "/auth/todoUser/revoke",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/todoUser/revoke";
  export const random = (): ITodoAppTodoUser.ISummary =>
    typia.random<ITodoAppTodoUser.ISummary>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
