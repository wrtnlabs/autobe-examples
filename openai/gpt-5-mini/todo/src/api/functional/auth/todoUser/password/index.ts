/**
 * Authenticated change of todoUser password and revocation of prior refresh
 * tokens (todo_app_todouser).
 *
 * Purpose and overview: Allows an authenticated todoUser to change their
 * password by providing current and new passwords. The operation updates
 * todo_app_todouser.password_hash and sets
 * todo_app_todouser.refresh_tokens_revoked_at to revoke other refresh tokens.
 *
 * Implementation details and field usage: This endpoint is actor-restricted
 * (authorizationActor: "todoUser") and references password_hash and
 * refresh_tokens_revoked_at explicitly. On successful change the implementation
 * MUST set password_hash to the new hashed password and update
 * refresh_tokens_revoked_at to the current timestamp so that previously issued
 * refresh tokens are invalidated.
 *
 * Actor-specific integration: This operation applies to the authenticated
 * todoUser and requires the caller to be the owner represented by
 * todo_app_todouser.id in the security context. It leverages session records
 * (todo_app_todouser_sessions) for auditing if desired.
 *
 * Security considerations: The endpoint must validate the current password by
 * comparing with password_hash and must not disclose password_hash or any
 * secrets. It should also log the action in audit structures
 * (todo_app_user_activity_logs or todo_app_audit_logs) referencing the acting
 * user's id.
 *
 * Related operations and workflow: After changePassword, clients should
 * re-authenticate where necessary and use refresh flows only after obtaining
 * new tokens. See POST /auth/todoUser/refresh for token renewal behavior.
 *
 * @param props.connection
 * @param props.body Change password request containing currentPassword and
 *   newPassword; server validates currentPassword against
 *   todo_app_todouser.password_hash and updates password_hash and
 *   refresh_tokens_revoked_at on success.
 * @path /auth/todoUser/password
 * @accessor api.functional.auth.todoUser.password.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<changePassword.Response> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /**
     * Change password request containing currentPassword and newPassword;
     * server validates currentPassword against
     * todo_app_todouser.password_hash and updates password_hash and
     * refresh_tokens_revoked_at on success.
     */
    body: ITodoAppTodoUser.IChangePassword;
  };
  export type Body = ITodoAppTodoUser.IChangePassword;
  export type Response = ITodoAppTodoUser.ISummary;

  export const METADATA = {
    method: "PUT",
    path: "/auth/todoUser/password",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/todoUser/password";
  export const random = (): ITodoAppTodoUser.ISummary =>
    typia.random<ITodoAppTodoUser.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
