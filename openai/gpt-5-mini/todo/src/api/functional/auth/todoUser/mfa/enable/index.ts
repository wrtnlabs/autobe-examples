/**
 * Enable two-factor authentication for authenticated todoUser
 * (todo_app_todouser).
 *
 * Purpose and overview: This authenticated endpoint enables MFA for the
 * caller's todo_app_todouser account by recording mfa_enabled=true and storing
 * the necessary secret material in mfa_secret and mfa_backup_codes (encrypted).
 * It returns provisioning information for the client to complete setup.
 *
 * Implementation details and field usage: The operation directly references
 * schema fields mfa_enabled, mfa_secret, and mfa_backup_codes. On enable, the
 * server generates a secure mfa_secret, derives backup codes, persists
 * encrypted values to mfa_secret and mfa_backup_codes, and sets mfa_enabled to
 * true. The operation should return only provisioning material (e.g., QR data
 * or one-time secret) suitable for the client; stored secrets must never be
 * returned in plain form after persistence.
 *
 * Actor-specific integration: This endpoint requires authentication
 * (authorizationActor: "todoUser") and binds MFA artifacts to the actor row in
 * todo_app_todouser. Audit entries should be recorded in todo_app_audit_logs or
 * todo_app_user_activity_logs to record the change.
 *
 * Security considerations: mfa_secret and mfa_backup_codes are sensitive and
 * must be encrypted at rest. The description references the exact schema fields
 * and stipulates careful handling. Enabling MFA should require
 * proof-of-possession of the secret in a verification step before finalizing
 * mfa_enabled.
 *
 * Related operations and workflow: Complementary operations include disabling
 * MFA and using MFA during login flows when todo_app_todouser.mfa_enabled is
 * true.
 *
 * @param props.connection
 * @param props.body MFA enable request may include desired
 *   delivery/provisioning preferences; server will generate mfa_secret and
 *   mfa_backup_codes and persist them to todo_app_todouser.mfa_secret and
 *   todo_app_todouser.mfa_backup_codes. The actual persisted fields are
 *   encrypted and not returned verbatim.
 * @path /auth/todoUser/mfa/enable
 * @accessor api.functional.auth.todoUser.mfa.enable.enableTwoFactor
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function enableTwoFactor(
  connection: IConnection,
  props: enableTwoFactor.Props,
): Promise<enableTwoFactor.Response> {
  return true === connection.simulate
    ? enableTwoFactor.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...enableTwoFactor.METADATA,
          path: enableTwoFactor.path(),
          status: null,
        },
        props.body,
      );
}
export namespace enableTwoFactor {
  export type Props = {
    /**
     * MFA enable request may include desired delivery/provisioning
     * preferences; server will generate mfa_secret and mfa_backup_codes and
     * persist them to todo_app_todouser.mfa_secret and
     * todo_app_todouser.mfa_backup_codes. The actual persisted fields are
     * encrypted and not returned verbatim.
     */
    body: ITodoAppTodoUser.IEnableMfa;
  };
  export type Body = ITodoAppTodoUser.IEnableMfa;
  export type Response = ITodoAppTodoUser.ISummary;

  export const METADATA = {
    method: "POST",
    path: "/auth/todoUser/mfa/enable",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/todoUser/mfa/enable";
  export const random = (): ITodoAppTodoUser.ISummary =>
    typia.random<ITodoAppTodoUser.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: enableTwoFactor.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: enableTwoFactor.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
