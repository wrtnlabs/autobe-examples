import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppInvitation } from "../../../../structures/ITodoAppInvitation";

/**
 * Accept an invitation by invite code and create collaborator membership for
 * the authenticated user.
 *
 * Purpose and overview: This endpoint is the acceptance flow for invitations
 * created via todo_app_invitations. It consumes the path parameter
 * {inviteCode}, enforces pending-state and expiry checks, binds the
 * authenticated user to the invite when appropriate, creates a
 * todo_app_list_collaborators membership (respecting the unique constraint on
 * (todo_app_list_id, todo_app_todouser_id)), updates the invitation
 * (state='accepted', accepted_at=now()), and records audit and activity logs
 * for compliance.
 *
 * Security considerations and permissions: Only authenticated todo users may
 * accept invitations. If the invitation was issued to a specific registered
 * user (invitee_todouser_id), acceptance is restricted to that user. If
 * invitee_email was used and the invitee is not yet bound, accepting will bind
 * the authenticated user's id as invitee_todouser_id. The service MUST verify
 * the invitation has not expired (expires_at) and is in state 'pending' before
 * granting membership.
 *
 * Relationship to underlying database entities: Primary table:
 * todo_app_invitations. Auxiliary tables: todo_app_list_collaborators
 * (membership creation), todo_app_audit_logs, and todo_app_user_activity_logs
 * (for acceptance event logging). Relevant invitation fields: invite_code,
 * state, expires_at, invitee_todouser_id, invitee_email, accepted_at.
 *
 * Validation and business logic:
 *
 * - Path parameter inviteCode is the opaque invite token and must match
 *   todo_app_invitations.invite_code.
 * - If the invitation is missing, deleted, or in a non-pending state, return 404
 *   or 400 as appropriate.
 * - If the invitation has expired (now > expires_at), update its state to
 *   'expired' and return a validation error.
 * - If a collaborator membership already exists for this user and list, return
 *   409 Conflict.
 * - On success, return the updated invitation resource representation.
 *
 * Responses and errors:
 *
 * - 200 OK: returns the updated invitation (ITodoAppInvitation)
 * - 400 Bad Request: invalid invite, expired invitation, or state violation
 * - 401 Unauthorized: caller not authenticated
 * - 404 Not Found: invite code not found
 * - 409 Conflict: membership already exists
 *
 * @param props.connection
 * @param props.inviteCode Opaque invite code that identifies the invitation
 *   (todo_app_invitations.invite_code) (unique)
 * @path /todoApp/todoUser/invitations/:inviteCode/accept
 * @accessor api.functional.todoApp.todoUser.invitations.accept
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function accept(
  connection: IConnection,
  props: accept.Props,
): Promise<accept.Response> {
  return true === connection.simulate
    ? accept.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...accept.METADATA,
          path: accept.path(props),
          status: null,
        },
      );
}
export namespace accept {
  export type Props = {
    /**
     * Opaque invite code that identifies the invitation
     * (todo_app_invitations.invite_code) (unique)
     */
    inviteCode: string;
  };
  export type Response = ITodoAppInvitation;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/todoUser/invitations/:inviteCode/accept",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/todoUser/invitations/${encodeURIComponent(props.inviteCode ?? "null")}/accept`;
  export const random = (): ITodoAppInvitation =>
    typia.random<ITodoAppInvitation>();
  export const simulate = (
    connection: IConnection,
    props: accept.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: accept.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("inviteCode")(() => typia.assert(props.inviteCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
