import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Admin revoke (soft-delete) a public share for a todo list
 * (todo_app_list_shares).
 *
 * Purpose and overview: This admin endpoint revokes a previously created public
 * share for a todo list by marking the corresponding todo_app_list_shares row
 * as deleted (setting deleted_at). It ensures the share token/public_url can no
 * longer be used to access the list while preserving the record for audit and
 * administrative review.
 *
 * Security & permissions: Only an authorized admin may call this route. The
 * server MUST validate the admin's identity and privileges before applying the
 * soft-delete. All successful revocations MUST generate an audit log entry with
 * event_type = 'share_revoked' and target_type = 'list_share' and SHOULD also
 * create a todo_app_admin_actions record documenting the admin action and
 * reason.
 *
 * Validation & business rules:
 *
 * - Validate both path parameters as UUIDs.
 * - Confirm the parent list exists (todo_app_lists.id) and the share exists and
 *   is linked to that list.
 * - If the share is already soft-deleted (deleted_at not null), return 404 Not
 *   Found (or 204 if opting for idempotent semantics).
 * - On success, set deleted_at to the current timestamp, record an audit entry,
 *   and record an admin_action with reason.
 *
 * Errors: 400 for invalid UUIDs, 403 for unauthorized attempts, 404 if not
 * found/already-deleted, 204 for success.
 *
 * @param props.connection
 * @param props.listId Unique identifier of the target list (todo_app_lists.id).
 *   Provide the parent list UUID to scope the share to the correct list.
 * @param props.shareId Unique identifier of the target public share
 *   (todo_app_list_shares.id). Provide the share UUID to identify the share
 *   record to revoke.
 * @path /todoApp/admin/lists/:listId/shares/:shareId
 * @accessor api.functional.todoApp.admin.lists.shares.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the target list (todo_app_lists.id). Provide the
     * parent list UUID to scope the share to the correct list.
     */
    listId: string & tags.Format<"uuid">;

    /**
     * Unique identifier of the target public share
     * (todo_app_list_shares.id). Provide the share UUID to identify the
     * share record to revoke.
     */
    shareId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/todoApp/admin/lists/:listId/shares/:shareId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/admin/lists/${encodeURIComponent(props.listId ?? "null")}/shares/${encodeURIComponent(props.shareId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("listId")(() => typia.assert(props.listId));
      assert.param("shareId")(() => typia.assert(props.shareId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
