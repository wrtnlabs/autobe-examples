import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppTask } from "../../../../structures/ITodoAppTask";
import { IPageITodoAppTask } from "../../../../structures/IPageITodoAppTask";

/**
 * Search and retrieve tasks for a todo list with filtering, sorting, and
 * pagination (todo_app_tasks).
 *
 * Purpose and overview: Return a paginated collection of tasks for the
 * specified todo list. Implementation queries todo_app_tasks for rows whose
 * todo_app_list_id matches the provided listId and where deleted_at IS NULL.
 * The result set uses a summary DTO optimized for list displays and includes
 * fields: id, title, description, is_completed, completed_at, due_date,
 * priority, created_at, updated_at.
 *
 * Security & permissions:
 *
 * - For private lists, enforce authorization: only owner or accepted
 *   collaborators may retrieve results (implementation must check
 *   list.visibility at runtime and enforce access accordingly).
 * - For public lists, the endpoint may be accessible to guests (no authentication
 *   required), but results must still exclude soft-deleted tasks and respect
 *   public-indexing preferences.
 *
 * Validation & business rules:
 *
 * - Validate listId as UUID and verify the parent list exists.
 * - Validate request body fields: isCompleted (boolean),
 *   dueDateBefore/dueDateAfter (RFC3339 date-time), search (string), page
 *   (integer), pageSize (integer, capped by service policy), sortBy in
 *   ['dueDate','createdAt'], order in ['asc','desc'].
 * - Exclude tasks with deleted_at set (soft-deleted) from results.
 * - Enforce maximum pageSize to prevent excessive payloads.
 *
 * Errors: 400 for invalid parameters, 403 for unauthorized access to private
 * lists, 404 if list not found. Response: 200 with a paginated summary
 * container.
 *
 * @param props.connection
 * @param props.listId Unique identifier of the target list (todo_app_lists.id).
 *   Scopes the task search to the specific list.
 * @param props.body Search, filter, sort and pagination parameters for tasks
 *   within the specified list
 * @path /todoApp/lists/:listId/tasks
 * @accessor api.functional.todoApp.lists.tasks.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target list (todo_app_lists.id). Scopes the
     * task search to the specific list.
     */
    listId: string & tags.Format<"uuid">;

    /**
     * Search, filter, sort and pagination parameters for tasks within the
     * specified list
     */
    body: ITodoAppTask.IRequest;
  };
  export type Body = ITodoAppTask.IRequest;
  export type Response = IPageITodoAppTask.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/lists/:listId/tasks",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todoApp/lists/${encodeURIComponent(props.listId ?? "null")}/tasks`;
  export const random = (): IPageITodoAppTask.ISummary =>
    typia.random<IPageITodoAppTask.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("listId")(() => typia.assert(props.listId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
