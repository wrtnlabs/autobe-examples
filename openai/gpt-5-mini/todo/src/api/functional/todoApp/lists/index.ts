/**
 * Retrieve a todo list by its UUID (todo_app_lists).
 *
 * Purpose and overview: Retrieve a single todo list identified by its primary
 * key (todo_app_lists.id). This operation returns the canonical list metadata
 * (id, title, description, visibility, created_at, updated_at) as defined by
 * the `todo_app_lists` Prisma model.
 *
 * Security considerations and user permissions: This endpoint may be accessed
 * publicly for lists with visibility='public' (authorizationActor = null). For
 * private or shared-invite-only lists the service MUST enforce runtime
 * authorization and only allow the owner or accepted collaborators to view
 * private data. When the caller is not authorized, the implementation must
 * avoid leaking sensitive relationship metadata (do not return collaborator
 * lists or share tokens). The API contract should specify whether a 403 or a
 * 404 is returned for unauthorized access per product policy.
 *
 * Relationship to underlying database entities: This operation maps to the
 * `todo_app_lists` table. Implementations may query `todo_app_list_shares`,
 * `todo_app_list_collaborators`, and `todo_app_public_index_preferences` to
 * determine visibility and enrich the response for authorized callers.
 *
 * Validation rules and business logic:
 *
 * - Validate `listId` is a UUID and return 400 when malformed.
 * - If no list is found with the given id, return 404.
 * - Enforce visibility rules: if a list is private and the caller is not owner or
 *   accepted collaborator, return an authorization error (403) or 404 per
 *   policy.
 *
 * Expected behavior and error handling:
 *
 * - 200: single list record returned as `ITodoAppList` when authorized
 * - 400: invalid UUID format
 * - 404: list not found
 * - 403: caller not authorized to view the list (enforced by business logic at
 *   runtime)
 *
 * @param props.connection
 * @param props.listId Unique identifier of the target list (UUID). Corresponds
 *   to todo_app_lists.id.
 * @path /todoApp/lists/:listId
 * @accessor api.functional.todoApp.lists.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target list (UUID). Corresponds to
     * todo_app_lists.id.
     */
    listId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppList;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/lists/:listId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/lists/${encodeURIComponent(props.listId ?? "null")}`;
  export const random = (): ITodoAppList => typia.random<ITodoAppList>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("listId")(() => typia.assert(props.listId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
