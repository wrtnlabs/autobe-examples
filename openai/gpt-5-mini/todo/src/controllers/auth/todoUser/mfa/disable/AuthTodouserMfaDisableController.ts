import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthTodoUserMfaDisable } from "../../../../../providers/postAuthTodoUserMfaDisable";
import { TodouserAuth } from "../../../../../decorators/TodouserAuth";
import { TodouserPayload } from "../../../../../decorators/payload/TodouserPayload";

import { ITodoAppTodoUser } from "../../../../../api/structures/ITodoAppTodoUser";

@Controller("/auth/todoUser/mfa/disable")
export class AuthTodouserMfaDisableController {
  /**
   * Disable two-factor authentication for authenticated todoUser
   * (todo_app_todouser).
   *
   * Purpose and overview: This authenticated endpoint disables MFA for the
   * caller's account by clearing the stored MFA metadata and setting
   * todo_app_todouser.mfa_enabled=false.
   *
   * Implementation details and field usage: This operation references the exact
   * fields mfa_enabled, mfa_secret, and mfa_backup_codes. On successful disable
   * the implementation SHOULD nullify mfa_secret and mfa_backup_codes (or
   * securely overwrite) and set mfa_enabled to false. Audit logs referencing
   * the acting user should record the change.
   *
   * Actor-specific integration: Requires authentication (authorizationActor:
   * "todoUser"). The operation must protect against abuse by requiring
   * re-authentication or step-up verification before disabling MFA.
   *
   * Security considerations: Do not return persisted secrets. Clearing MFA
   * should also consider invalidating any backup codes and logging the
   * operation in todo_app_audit_logs for compliance.
   *
   * Related operations and workflow: Complementary to enableTwoFactor and login
   * flows that consult mfa_enabled during authentication.
   *
   * @param connection
   * @param body Disable MFA request (may include a confirmation or current
   *   password for step-up). Server will clear mfa_secret and mfa_backup_codes
   *   and set mfa_enabled=false on the todo_app_todouser row.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async disableTwoFactor(
    @TodouserAuth()
    todoUser: TodouserPayload,
    @TypedBody()
    body: ITodoAppTodoUser.IDisableMfa,
  ): Promise<ITodoAppTodoUser.ISummary> {
    try {
      return await postAuthTodoUserMfaDisable({
        todoUser,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
