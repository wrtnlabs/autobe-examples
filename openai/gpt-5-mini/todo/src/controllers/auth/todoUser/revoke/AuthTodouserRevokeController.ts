import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postAuthTodoUserRevoke } from "../../../../providers/postAuthTodoUserRevoke";
import { TodouserAuth } from "../../../../decorators/TodouserAuth";
import { TodouserPayload } from "../../../../decorators/payload/TodouserPayload";

import { ITodoAppTodoUser } from "../../../../api/structures/ITodoAppTodoUser";

@Controller("/auth/todoUser/revoke")
export class AuthTodouserRevokeController {
  /**
   * Revoke previously issued refresh tokens by setting
   * refresh_tokens_revoked_at (todo_app_todouser).
   *
   * Purpose and overview: Allows an authenticated todoUser to revoke
   * outstanding refresh tokens by setting
   * todo_app_todouser.refresh_tokens_revoked_at to the current time, preventing
   * previously issued refresh tokens from being used to obtain new access
   * tokens.
   *
   * Implementation details and field usage: This operation references the exact
   * schema field refresh_tokens_revoked_at. On invocation the server updates
   * this field on the caller's todo_app_todouser row to the current timestamp.
   * Session-specific records in todo_app_todouser_sessions may be used for
   * presentation but the revocation mechanism is the refresh_tokens_revoked_at
   * cutoff.
   *
   * Actor-specific integration: Requires authentication (authorizationActor:
   * "todoUser"). The operation affects all refresh tokens issued before the new
   * refresh_tokens_revoked_at and is commonly called after password changes or
   * account compromise detection.
   *
   * Security considerations: The endpoint should log the revocation in
   * todo_app_audit_logs or todo_app_user_activity_logs, and may also optionally
   * terminate active sessions in todo_app_todouser_sessions depending on
   * implementation.
   *
   * Related operations and workflow: Often invoked by changePassword or
   * resetPassword flows that set refresh_tokens_revoked_at to revoke prior
   * tokens. Clients should be notified that existing sessions will require
   * re-authentication.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async revokeRefreshTokens(
    @TodouserAuth()
    todoUser: TodouserPayload,
  ): Promise<ITodoAppTodoUser.ISummary> {
    try {
      return await postAuthTodoUserRevoke({
        todoUser,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
