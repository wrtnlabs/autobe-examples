import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppTodoUserTodoUsersTodoUserIdSessions } from "../../../../../providers/patchTodoAppTodoUserTodoUsersTodoUserIdSessions";
import { TodouserAuth } from "../../../../../decorators/TodouserAuth";
import { TodouserPayload } from "../../../../../decorators/payload/TodouserPayload";
import { getTodoAppTodoUserTodoUsersTodoUserIdSessionsSessionId } from "../../../../../providers/getTodoAppTodoUserTodoUsersTodoUserIdSessionsSessionId";
import { deleteTodoAppTodoUserTodoUsersTodoUserIdSessionsSessionId } from "../../../../../providers/deleteTodoAppTodoUserTodoUsersTodoUserIdSessionsSessionId";

import { IPageITodoAppTodouserSession } from "../../../../../api/structures/IPageITodoAppTodouserSession";
import { ITodoAppTodouserSession } from "../../../../../api/structures/ITodoAppTodouserSession";

@Controller("/todoApp/todoUser/todoUsers/:todoUserId/sessions")
export class TodoappTodouserTodousersSessionsController {
  /**
   * Search and retrieve sessions for a todo user.
   *
   * Purpose and overview: This operation provides a search-capable listing of
   * session records for a single todo user. It operates on the
   * `todo_app_todouser_sessions` Prisma model which stores session context (ip,
   * href, referrer, created_at, expired_at) and supports auditability via
   * related snapshot and activity tables.
   *
   * Security and ownership: Only authenticated users may access this endpoint.
   * Implementations MUST enforce that a caller with the "todoUser" actor can
   * only list sessions for their own `todoUserId`. Administrative cross-user
   * session management should be provided by a separate admin-controlled
   * endpoint. Because session records contain sensitive metadata (IP,
   * referrer), results should be scoped and redacted according to the
   * requester's authorization.
   *
   * Filtering, pagination and sorting: The request
   * (`ITodoAppTodouserSession.IRequest`) supports filtering by activeOnly
   * (boolean), ip (string pattern), createdBefore/createdAfter (date-time),
   * expiredOnly (boolean), pagination (page, pageSize), and sort fields
   * (created_at, expired_at). Responses return a paginated summary
   * `IPageITodoAppTodouserSession.ISummary` containing session summary fields
   * appropriate for listing (id, created_at, expired_at, a truncated href or
   * alias, and an optional device label if available).
   *
   * Validation and error handling:
   *
   * - Validate `todoUserId` as UUID; return 400 for invalid format.
   * - If the user does not exist, return 404.
   * - If the caller is not authorized to view the user's sessions, return 403.
   * - On success, return 200 with `IPageITodoAppTodouserSession.ISummary`
   *   containing pagination metadata and session summary items.
   *
   * @param connection
   * @param todoUserId Unique identifier of the todo user whose sessions are
   *   being queried (UUID).
   * @param body Search criteria and pagination parameters for session listing
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TodouserAuth()
    todoUser: TodouserPayload,
    @TypedParam("todoUserId")
    todoUserId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppTodouserSession.IRequest,
  ): Promise<IPageITodoAppTodouserSession.ISummary> {
    try {
      return await patchTodoAppTodoUserTodoUsersTodoUserIdSessions({
        todoUser,
        todoUserId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific todo_app_todouser_sessions record (session) by id.
   *
   * Retrieve detailed information for a single authenticated session belonging
   * to a todo user.
   *
   * This operation returns the session record stored in the
   * `todo_app_todouser_sessions` Prisma table, including IP address,
   * originating href, referrer, creation timestamp, and optional expiry. It is
   * intended for an account session management UI where users review or manage
   * their active sessions.
   *
   * Security considerations and user permissions: Only the owning authenticated
   * user may retrieve their own session details via this endpoint. The server
   * implementation MUST verify that the session's `todo_app_todouser_id` equals
   * the authenticated caller's user id before returning any session data.
   * Administrative viewing of arbitrary sessions must be implemented separately
   * as an auditable admin API.
   *
   * Validation and errors:
   *
   * - Both path parameters `todoUserId` and `sessionId` are required and must be
   *   valid UUIDs.
   * - Return 400 when path parameter formats are invalid, 403 when the caller is
   *   authenticated but not the owner, and 404 when the session is not found
   *   for the given identifiers.
   *
   * @param connection
   * @param todoUserId Unique identifier (UUID) of the owning todo user (maps to
   *   todo_app_todouser.id).
   * @param sessionId Unique identifier (UUID) of the target session (maps to
   *   todo_app_todouser_sessions.id).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @TodouserAuth()
    todoUser: TodouserPayload,
    @TypedParam("todoUserId")
    todoUserId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodouserSession> {
    try {
      return await getTodoAppTodoUserTodoUsersTodoUserIdSessionsSessionId({
        todoUser,
        todoUserId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Revoke (delete) a specific todo_app_todouser_sessions record.
   *
   * Permanently remove an active session belonging to the specified todo user.
   *
   * This operation deletes the session row from the
   * `todo_app_todouser_sessions` Prisma table. Because the sessions model does
   * not include a soft-delete column, deletion is a hard removal from the
   * active sessions table and the session will no longer be usable for
   * authentication or attribution.
   *
   * Security and permissions: Only the owning authenticated user may revoke
   * their own session via this endpoint. The server implementation MUST
   * validate that the session's `todo_app_todouser_id` equals the authenticated
   * caller's id before performing deletion. Administrative revocation of
   * arbitrary sessions should be performed through separate admin APIs with
   * audit logging.
   *
   * Validation and errors:
   *
   * - Path parameters `todoUserId` and `sessionId` are required and must be valid
   *   UUIDs.
   * - Return 400 when UUID formats are invalid, 403 when the authenticated caller
   *   is not the owner, and 404 when the session does not exist for the
   *   supplied identifiers.
   * - On success return 204 No Content.
   *
   * Operational note: Implementations MUST invalidate any in-memory or external
   * session/token caches to ensure the session cannot be used after DB
   * deletion. Record the revoke action in audit logs for traceability.
   *
   * @param connection
   * @param todoUserId Unique identifier (UUID) of the owning todo user (maps to
   *   todo_app_todouser.id).
   * @param sessionId Unique identifier (UUID) of the target session (maps to
   *   todo_app_todouser_sessions.id).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @TodouserAuth()
    todoUser: TodouserPayload,
    @TypedParam("todoUserId")
    todoUserId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppTodoUserTodoUsersTodoUserIdSessionsSessionId({
        todoUser,
        todoUserId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
