import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppTodoUserLists } from "../../../../providers/postTodoAppTodoUserLists";
import { TodouserAuth } from "../../../../decorators/TodouserAuth";
import { TodouserPayload } from "../../../../decorators/payload/TodouserPayload";
import { putTodoAppTodoUserListsListId } from "../../../../providers/putTodoAppTodoUserListsListId";
import { deleteTodoAppTodoUserListsListId } from "../../../../providers/deleteTodoAppTodoUserListsListId";

import { ITodoAppList } from "../../../../api/structures/ITodoAppList";

@Controller("/todoApp/todoUser/lists")
export class TodoappTodouserListsController {
  /**
   * Create a new todo list (writes to todo_app_lists).
   *
   * Create a new todo list owned by the authenticated user.
   *
   * Purpose and overview: Allows authenticated TodoUser to create a list with
   * title, optional description, and visibility. Title is required and must be
   * non-empty after trimming. Default visibility is 'private'. The operation
   * persists a row in `todo_app_lists` and returns the created entity.
   *
   * Security and permissions: Requires authenticated user (authorizationActors:
   * ["todoUser"]). The server must set `todo_app_todouser_id` to the caller's
   * id and validate that callers cannot create lists on behalf of other users.
   *
   * DB relationships: Primary table `todo_app_lists`; may also create related
   * `todo_app_public_index_preferences` for public lists and write audit logs
   * to `todo_app_audit_logs` describing the creation event.
   *
   * Expected behaviour: On success return 201 with the created `ITodoAppList`.
   * On validation failure return 400 with structured ValidationError. On unique
   * constraint violation return 409.
   *
   * @param connection
   * @param body Creation payload for a new todo list
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TodouserAuth()
    todoUser: TodouserPayload,
    @TypedBody()
    body: ITodoAppList.ICreate,
  ): Promise<ITodoAppList> {
    try {
      return await postTodoAppTodoUserLists({
        todoUser,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a todo list's metadata (todo_app_lists).
   *
   * Purpose and overview: Update metadata of a todo list owned by a user. This
   * operation updates fields on the `todo_app_lists` Prisma model such as
   * title, description, and visibility. It is intended for owner-driven list
   * management flows and must be guarded by ownership checks.
   *
   * Security considerations and user permissions: Only the owner of the list
   * (or an admin performing moderation actions) may update the list metadata.
   * The endpoint requires authentication (authorizationActor = "todoUser") and
   * the service MUST perform an ownership check; otherwise the operation must
   * return 403.
   *
   * Relationship to underlying database entities: This operation writes to
   * `todo_app_lists`. On visibility changes, implementations may need to also
   * create or update `todo_app_list_shares` and
   * `todo_app_public_index_preferences` depending on how public
   * sharing/indexing is represented in the platform. Audit events should be
   * recorded in `todo_app_audit_logs` to capture the actor, session, and change
   * reason.
   *
   * Validation rules and business logic:
   *
   * - Title must be non-empty (application-enforced) and not exceed 250
   *   characters.
   * - Visibility must be one of the allowed semantics (e.g.,
   *   'private','shared-invite-only','public') as defined by application policy
   *   (validate at business layer).
   * - The request body should not include fields that are immutable in the domain
   *   model (for example, created_at or id); such attempts should be ignored or
   *   produce a validation error.
   *
   * Expected behavior and error handling:
   *
   * - 200: updated list returned as `ITodoAppList`
   * - 400: validation failure or malformed UUID
   * - 403: not authorized
   * - 404: list not found
   *
   * @param connection
   * @param listId Unique identifier of the target list (UUID). Corresponds to
   *   todo_app_lists.id.
   * @param body Fields to update for the target todo list. Use
   *   ITodoAppList.IUpdate to provide updatable list metadata (title,
   *   description, visibility). Do not include immutable fields such as id or
   *   createdAt.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":listId")
  public async update(
    @TodouserAuth()
    todoUser: TodouserPayload,
    @TypedParam("listId")
    listId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppList.IUpdate,
  ): Promise<ITodoAppList> {
    try {
      return await putTodoAppTodoUserListsListId({
        todoUser,
        listId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete (mark deleted_at) a todo list (todo_app_lists).
   *
   * Purpose and overview: This operation performs a business soft-delete of a
   * todo list. It marks the `todo_app_lists.deleted_at` column with the current
   * server timestamp to hide the list from normal application read paths while
   * preserving tasks, collaborators, invitations, shares, and snapshots for
   * possible restoration and audit.
   *
   * Security and permissions: Only the list owner (todo_app_todouser referenced
   * by todo_app_lists.todo_app_todouser_id) or an authorized administrator may
   * delete the list. The service MUST verify the caller's identity and
   * ownership or admin role. Unauthorized requests MUST return 403 Forbidden.
   *
   * Relationship to database entities: Operates on the `todo_app_lists` model.
   * Related records (todo_app_tasks, todo_app_list_collaborators,
   * todo_app_invitations, todo_app_list_shares,
   * todo_app_public_index_preferences, todo_app_task_snapshots) remain
   * unchanged and are interpreted as logically hidden by application logic when
   * the parent list is soft-deleted.
   *
   * Validation and business logic:
   *
   * - Validate `listId` as a UUID. Return 400 for invalid UUID formats.
   * - If no matching active list exists (not found or already soft-deleted),
   *   return 404 Not Found.
   * - Verify caller is owner or admin; otherwise return 403 Forbidden.
   * - Set `deleted_at` to current timestamp and persist change; create an audit
   *   record (todo_app_audit_logs) recording event_type `delete` (or
   *   `remove_list`) with actor id, session id, list id, and human-readable
   *   details.
   *
   * Responses and error handling:
   *
   * - 204 No Content on success
   * - 400 Bad Request for invalid UUID format
   * - 403 Forbidden for insufficient permissions
   * - 404 Not Found when list is absent or already deleted
   * - 500 Internal Server Error for unexpected failures
   *
   * @param connection
   * @param listId Unique identifier (UUID) of the target todo list
   *   (todo_app_lists.id)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":listId")
  public async erase(
    @TodouserAuth()
    todoUser: TodouserPayload,
    @TypedParam("listId")
    listId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppTodoUserListsListId({
        todoUser,
        listId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
