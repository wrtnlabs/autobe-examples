import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoAppTodoUserListsListIdPublicIndexPreferences } from "../../../../../providers/getTodoAppTodoUserListsListIdPublicIndexPreferences";
import { TodouserAuth } from "../../../../../decorators/TodouserAuth";
import { TodouserPayload } from "../../../../../decorators/payload/TodouserPayload";

import { ITodoAppPublicIndexPreference } from "../../../../../api/structures/ITodoAppPublicIndexPreference";

@Controller("/todoApp/todoUser/lists/:listId/publicIndexPreferences")
export class TodoappTodouserListsPublicindexpreferencesController {
  /**
   * Get todo_app_public_index_preferences for a list.
   *
   * Purpose and overview: Return the public indexing preferences for a
   * specified list. The returned record includes `indexing_enabled`,
   * `allow_search_engine`, `allow_discovery`, optional `index_scope`, and
   * metadata timestamps (`created_at`, `updated_at`). These settings govern
   * whether the list may be surfaced in internal discovery and external search
   * indexing pipelines.
   *
   * Security and permissions: Access is restricted to the list owner
   * (todo_app_todouser) or authorized administrative/platform operators.
   * Unauthorized requests MUST return 403 Forbidden. If the parent list is
   * soft-deleted or the preferences row is soft-deleted, return 404 Not Found.
   *
   * Relationship to database entities: This operation reads
   * `todo_app_public_index_preferences` (1:1 with todo_app_lists). The
   * preferences are considered inactive when deleted_at is non-null or when the
   * parent list is soft-deleted.
   *
   * Validation and business logic:
   *
   * - Validate `listId` as a UUID. Return 400 for invalid formats.
   * - Verify caller is owner or admin; otherwise return 403.
   * - If preferences row not found or deleted, return 404.
   *
   * Successful response contains the ITodoAppPublicIndexPreference DTO with the
   * properties: indexing_enabled, allow_search_engine, allow_discovery,
   * index_scope, created_at, updated_at, deleted_at (nullable) and
   * todo_app_list_id.
   *
   * @param connection
   * @param listId Unique identifier (UUID) of the todo list whose indexing
   *   preferences will be retrieved
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TodouserAuth()
    todoUser: TodouserPayload,
    @TypedParam("listId")
    listId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppPublicIndexPreference> {
    try {
      return await getTodoAppTodoUserListsListIdPublicIndexPreferences({
        todoUser,
        listId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update public index preferences for a todo list.
   *
   * Update the public indexing preferences associated with a specific todo
   * list. This operation allows the list owner (or an authorized admin) to
   * control whether the platform indexing pipeline and external search engines
   * may index the list's public content.
   *
   * The API maps directly to the `todo_app_public_index_preferences` table in
   * the Prisma schema. The resource is a 1:1 subsidiary record tied to a list
   * (`todo_app_list_id`). The table stores boolean flags (`indexing_enabled`,
   * `allow_search_engine`, `allow_discovery`) and an optional `index_scope` tag
   * for routing indexing. The model includes audit timestamps and a
   * `deleted_at` soft-delete column; providers must treat soft-deleted
   * preference rows as inactive.
   *
   * Security: Only the list owner (todoAppTodouser) or authorized admin may
   * update these preferences. Attempting to update preferences for a
   * non-existent or soft-deleted list should return 404 Not Found. Invalid
   * payload shapes (non-boolean flags, invalid `index_scope`) should return 400
   * Bad Request.
   *
   * @param connection
   * @param listId Unique identifier (UUID) of the target todo list
   *   (todo_app_lists.id).
   * @param body Payload containing the public index preference values to create
   *   or update for the target list.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @TypedParam("listId")
    listId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppPublicIndexPreference.IUpdate,
  ): Promise<ITodoAppPublicIndexPreference> {
    listId;
    body;
    return typia.random<ITodoAppPublicIndexPreference>();
  }
}
