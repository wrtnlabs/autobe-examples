  /**
   * Create a public or scoped share for the specified list.
   *
   * Purpose and overview:
   *
   * Create a new todo_app_list_shares record for the specified todo list. This
   * allows the list owner to produce a share token and optional public URL so
   * the list can be consumed externally. Because the schema enforces uniqueness
   * on todo_app_list_id, the operation must either replace an existing active
   * share or return 409 Conflict; the default behavior is to return 409 to
   * avoid accidental replacement.
   *
   * Security considerations and user permissions:
   *
   * Only the list owner (or an admin with explicit moderation rights) may
   * create a public share. This endpoint requires authentication and ownership
   * verification. Administrative overrides must be recorded in admin actions
   * and audit logs. Creation must be idempotent for client retries: the service
   * should avoid creating multiple active shares for the same list when clients
   * retry requests.
   *
   * Relationship to underlying database entities:
   *
   * Writes the new share row to todo_app_list_shares with generated
   * share_token, public_url (optional), is_public (boolean), visibility
   * (string), expires_at (nullable), created_by_todouser_id, created_at and
   * updated_at. The parent todo_app_lists must exist and not be soft-deleted;
   * otherwise the endpoint returns 404.
   *
   * Validation rules and business logic:
   *
   * - ListId path parameter: must be a valid UUID referencing an existing, active
   *   todo_app_lists.id.
   * - Request body must conform to schema (ITodoAppListShare.ICreate) and include
   *   necessary fields (is_public or visibility); malformed bodies return 400.
   * - If an active share already exists for the list
   *   (todo_app_list_shares.todo_app_list_id with deleted_at IS NULL), return
   *   409 Conflict.
   * - On success, respond with 201 and the created share record.
   *
   * Errors and behavior:
   *
   * - 201: Share created (returns created share record)
   * - 400: Validation error
   * - 401: Unauthenticated
   * - 403: Authenticated but not owner
   * - 404: Parent list not found or soft-deleted
   * - 409: Active share already exists for this list
   *
   * Notes:
   *
   * This specification relies on the Prisma schema behavior: unique constraint
   * on todo_app_list_id and unique share_token, soft-delete via deleted_at, and
   * relation to created_by_todouser_id for attribution.
   *
   * @param connection
   * @param listId UUID of the target todo list (todo_app_lists.id). List must
   *   exist and not be soft-deleted.
   * @param body Creation payload for new list share. Service will generate
   *   share_token; client may provide public_url, is_public, visibility and
   *   optional expires_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TodouserAuth()
    todoUser: TodouserPayload,
    @TypedParam("listId")
    listId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppListShare.ICreate,
  ): Promise<ITodoAppListShare> {
    try {
      return await postTodoAppTodoUserListsListIdShares({
        todoUser,
        listId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve paginated shares for a specific list (management).
   *
   * Purpose and overview:
   *
   * Retrieve a paginated and filterable collection of share metadata
   * (todo_app_list_shares) for the specified todo list. This operation is
   * intended for list owners and authorized collaborators to inspect and manage
   * share tokens and public URLs. Returned items are active shares (deleted_at
   * IS NULL) and include expiry metadata so clients can detect expired shares.
   *
   * Security considerations and user permissions:
   *
   * Access requires authentication. Although public shares can be read by
   * guests in other public flows, this management endpoint requires that the
   * caller be the list owner or an authorized collaborator. Implementations
   * MUST verify the requesting actor's relationship to the list and deny access
   * (403) when the caller is not authorized. All management access should be
   * recorded in audit logs (todo_app_audit_logs) by the service layer.
   *
   * Relationship to underlying database entities:
   *
   * This operation maps to the todo_app_list_shares table (share_token,
   * public_url, is_public, visibility, expires_at, created_by_todouser_id,
   * created_at, updated_at, deleted_at) and is scoped by todo_app_lists.id via
   * todo_app_list_shares.todo_app_list_id. The parent list's visibility and
   * deleted_at (soft-delete) must be considered: if the parent list is
   * soft-deleted, the endpoint returns 404.
   *
   * Validation rules and business logic:
   *
   * - ListId path parameter: must be a valid UUID referencing an existing
   *   todo_app_lists.id; if not found or soft-deleted return 404.
   * - Query filters: isPublic (boolean), visibility (string),
   *   expiresBefore/expiresAfter (date-time) are optional; invalid formats
   *   return 400.
   * - Pagination: page (uint), pageSize (uint) must be validated and clamped;
   *   default sorting is created_at asc. The service should return stable
   *   ordering and a total count for pagination.
   *
   * Errors and behavior:
   *
   * - 200: Paginated response with summary DTOs
   * - 400: Invalid query or pagination parameters
   * - 401: Unauthenticated
   * - 403: Authenticated but unauthorized
   * - 404: Parent list not found or soft-deleted
   *
   * Notes:
   *
   * The specification strictly references the Prisma model comments:
   * todo_app_list_shares enforces uniqueness on todo_app_list_id and
   * share_token; soft-delete semantics exist via deleted_at and therefore share
   * management must account for prior soft-deleted rows.
   *
   * @param connection
   * @param listId UUID of the target todo list (todo_app_lists.id). List must
   *   exist and not be soft-deleted.
   * @param body Search, filter, sort and pagination parameters for retrieving
   *   list shares.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
