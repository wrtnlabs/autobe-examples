  public async erase(
    @TodouserAuth()
    todoUser: TodouserPayload,
    @TypedParam("listId")
    listId: string & tags.Format<"uuid">,
    @TypedParam("shareId")
    shareId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppTodoUserListsListIdSharesShareId({
        todoUser,
        listId,
        shareId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
