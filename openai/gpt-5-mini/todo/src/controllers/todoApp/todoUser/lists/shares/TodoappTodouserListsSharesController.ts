  /**
   * Revoke (soft-delete) a public share for a todo list (todo_app_list_shares).
   *
   * Purpose and overview: This endpoint revokes a previously created public
   * share for a todo list by marking the corresponding todo_app_list_shares row
   * as deleted (setting deleted_at). It ensures the share token/public_url can
   * no longer be used to access the list while preserving the record for audit
   * and possible administrative review.
   *
   * Security & permissions: Only the list owner (todoUser) may revoke a public
   * share via this route. The server MUST validate the caller's identity and
   * ownership of the parent list before applying the soft-delete. All
   * successful revocations MUST generate an audit log entry with event_type =
   * 'share_revoked' and target_type = 'list_share'.
   *
   * Validation & business rules:
   *
   * - Validate both path parameters as UUIDs.
   * - Confirm the parent list exists (todo_app_lists.id) and the share exists and
   *   is linked to that list.
   * - If the share is already soft-deleted (deleted_at not null), return 404 Not
   *   Found (or 204 if idempotent-delete semantics are chosen; be consistent
   *   across API).
   * - If the caller is not authorized (not the owner), return 403 Forbidden.
   * - On success, set deleted_at to the current timestamp and record an audit
   *   entry linking the actor, session, list and share ids.
   *
   * Errors: 400 for invalid UUIDs, 403 for unauthorized attempts, 404 if
   * list/share not found or already-deleted, 204 for success.
   *
   * @param connection
   * @param listId Unique identifier of the target list (todo_app_lists.id).
   *   Provide the parent list UUID to scope the share to the correct list.
   * @param shareId Unique identifier of the target public share
   *   (todo_app_list_shares.id). Provide the share UUID to identify the share
   *   record to revoke.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
