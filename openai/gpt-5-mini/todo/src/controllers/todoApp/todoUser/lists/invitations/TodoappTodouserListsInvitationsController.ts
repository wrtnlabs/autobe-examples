  /**
   * Soft-delete an invitation for a list (todo_app_invitations).
   *
   * Delete (soft-delete) an invitation belonging to a specific list.
   *
   * Purpose and overview: This endpoint removes an invitation identified by
   * {invitationId} from the specified list {listId}. It operates on the
   * todo_app_invitations Prisma model and implements soft-delete semantics by
   * setting deleted_at and updating state to a terminal value (for example,
   * 'revoked'). The row is retained for forensic review and compliance.
   *
   * Security considerations and user permissions: Only authorized actors may
   * perform this operation. Primary authorized actor: the list owner (the
   * todo_app_lists owner). Platform administrators (todo_app_admin) are also
   * permitted to remove invitations for moderation reasons. The service MUST
   * verify the caller's identity and ownership of the parent list prior to
   * performing the soft-delete. When an admin performs the removal, the
   * implementation MUST record an admin action in todo_app_admin_actions and an
   * audit entry in todo_app_audit_logs with reason, admin id, session id, and
   * affected target details.
   *
   * Relationship to underlying database entities: Primary table:
   * todo_app_invitations. This operation validates that
   * todo_app_invitations.todo_app_list_id equals the provided {listId}. The
   * invitation model contains fields invite_code, state, expires_at,
   * accepted_at, and deleted_at which are used for validation and lifecycle
   * transitions. The parent list's owner is stored in
   * todo_app_lists.todo_app_todouser_id and is used for authorization checks.
   *
   * Validation and business logic:
   *
   * - Path parameters listId and invitationId must be valid UUIDs.
   * - If the invitation does not exist or does not belong to the specified list,
   *   return 404.
   * - If deleted_at is already set (already soft-deleted), the call is idempotent
   *   and returns 204.
   * - On success, set deleted_at = now(), optionally update state to a terminal
   *   state (e.g., 'revoked'), and insert an audit log referencing the caller
   *   and the invitation.
   *
   * Related operations:
   *
   * - GET /todoApp/todoUser/lists/{listId}/invitations (list)
   * - POST /todoApp/todoUser/lists/{listId}/invitations (create)
   *
   * Error handling and responses:
   *
   * - 400 Bad Request: invalid UUID format for path parameters
   * - 403 Forbidden: unauthorized caller
   * - 404 Not Found: invitation not found for the specified list
   * - 204 No Content: successful soft-delete (idempotent)
   *
   * @param connection
   * @param listId Unique identifier of the parent todo list (todo_app_lists.id)
   *   (UUID)
   * @param invitationId Unique identifier of the invitation to delete
   *   (todo_app_invitations.id) (UUID)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
