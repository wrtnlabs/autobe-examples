import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getTodoAppTodoUserDashboardUserOverview } from "../../../../../providers/getTodoAppTodoUserDashboardUserOverview";
import { TodouserAuth } from "../../../../../decorators/TodouserAuth";
import { TodouserPayload } from "../../../../../decorators/payload/TodouserPayload";

import { ITodoAppUserDashboard } from "../../../../../api/structures/ITodoAppUserDashboard";

@Controller("/todoApp/todoUser/dashboard/user-overview")
export class TodoappTodouserDashboardUser_overviewController {
  /**
   * Per-user dashboard summary aggregating owned lists, shared lists, tasks
   * due, and invitations.
   *
   * Purpose and overview:
   *
   * This endpoint provides an authenticated user's personal dashboard
   * summarizing their account and activity. It includes metrics such as number
   * of owned lists, number of shared lists the user participates in, total
   * tasks, tasks due within a configurable window (default next 7 days), tasks
   * completed in recent window, and pending invitations. The underlying Prisma
   * models used are todo_app_todouser, todo_app_lists, todo_app_tasks,
   * todo_app_list_collaborators, and todo_app_invitations. The operation is
   * read-only and intended to be efficient for interactive use.
   *
   * Security and permissions:
   *
   * Only authenticated users may access this endpoint. The service layer must
   * verify the caller is the authenticated principal and scope results to
   * owner/collaborator membership. The response must NOT include sensitive
   * fields such as password_hash, mfa_secret, or refresh token revocation
   * timestamps. For shared lists, only items and metadata the user is
   * authorized to see should be returned.
   *
   * Validation and performance:
   *
   * - This is read-only and uses indexed fields for efficient queries (due_date,
   *   is_completed, visibility).
   * - Arrays are capped (default top 20 for personal lists) and support
   *   pagination.
   * - On authentication failure: return 401; on authorization errors: return 403;
   *   on backend issues: return 5xx.
   *
   * Expected response:
   *
   * - Response type: ITodoAppUserDashboard (computed DTO). DTO must exclude
   *   sensitive fields and document array caps and pagination.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TodouserAuth()
    todoUser: TodouserPayload,
  ): Promise<ITodoAppUserDashboard> {
    try {
      return await getTodoAppTodoUserDashboardUserOverview({
        todoUser,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
