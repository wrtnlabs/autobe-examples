import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postTodoAppTodoUserTaskTags } from "../../../../providers/postTodoAppTodoUserTaskTags";
import { TodouserAuth } from "../../../../decorators/TodouserAuth";
import { TodouserPayload } from "../../../../decorators/payload/TodouserPayload";
import { patchTodoAppTodoUserTaskTags } from "../../../../providers/patchTodoAppTodoUserTaskTags";

import { ITodoAppTaskTag } from "../../../../api/structures/ITodoAppTaskTag";
import { IPageITodoAppTaskTag } from "../../../../api/structures/IPageITodoAppTaskTag";

@Controller("/todoApp/todoUser/taskTags")
export class TodoappTodouserTasktagsController {
  /**
   * Create a new task tag (todo_app_task_tags).
   *
   * Create a new canonical task tag in the system. The operation writes to the
   * Prisma model `todo_app_task_tags` and returns the created entity including
   * id and timestamps.
   *
   * Purpose and overview: The canonical tag dictionary allows consistent
   * tagging across tasks. This API allows authors to add a new tag name that
   * may be used when creating or updating tasks. The server must normalize the
   * incoming name (trim whitespace, apply case normalization as policy
   * dictates) and verify uniqueness according to the table's @@unique([name])
   * rule.
   *
   * Security considerations and user permissions: This is a write operation and
   * requires an authenticated actor. The operation is assigned to `todoUser`
   * actors in the current design; if business policy requires admin-only tag
   * creation, adjust authorization accordingly. Every successful create should
   * also emit an audit log entry (actor id, session id, target type `task_tag`,
   * and details).
   *
   * Validation and business logic: The `name` field is mandatory and must not
   * be empty. Service-layer validation must reject empty or whitespace-only
   * names with a clear validation error. On uniqueness violation, return 409
   * Conflict with a machine-readable error code. The response on success
   * returns the full ITodoAppTaskTag record with created_at and updated_at.
   *
   * Related operations: Use PATCH /taskTags to search or list tags. Admin-only
   * endpoints may examine or purge soft-deleted tags; those are separate
   * operations.
   *
   * @param connection
   * @param body Creation information for a new task tag
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TodouserAuth()
    todoUser: TodouserPayload,
    @TypedBody()
    body: ITodoAppTaskTag.ICreate,
  ): Promise<ITodoAppTaskTag> {
    try {
      return await postTodoAppTodoUserTaskTags({
        todoUser,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated list of task tags (todo_app_task_tags).
   *
   * Retrieve a filtered and paginated list of canonical task tags from the
   * system. The underlying data comes from the Prisma model
   * `todo_app_task_tags`, which is the canonical tag dictionary used across
   * lists and tasks.
   *
   * This operation is read-only and intended for client list views,
   * autocompletion, and administrative inspection. The response returns tag
   * summary information (id, name, created_at) inside a paginated container. By
   * default, only active tags (where `deleted_at` is null) are returned.
   *
   * Security considerations: Tag creation and deletion are write operations and
   * are subject to authorization checks; this endpoint should be callable by
   * authenticated todo users for discovery and autocomplete. If the request
   * includes flags that expose soft-deleted data, the service must verify the
   * requesting actor has admin privileges before returning those rows.
   * Non-admin attempts to request deleted rows must be rejected with 403
   * Forbidden.
   *
   * Relationship to database entities: Maps directly to the
   * `todo_app_task_tags` Prisma model. Use the table's trigram-enabled index on
   * `name` for efficient partial-match searching. Ensure results respect the
   * model's uniqueness of `name` and do not return duplicate names.
   *
   * Validation rules and error handling: Invalid request parameters (bad date
   * format, non-integer pagination values) must result in a 400 Bad Request
   * with structured validation errors. When paging beyond available ranges,
   * return an empty data array with pagination metadata. Avoid exposing
   * internal database errors; map transient DB errors to a 500-level response
   * with a safe message and log details for diagnostics.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for task tag
   *   retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TodouserAuth()
    todoUser: TodouserPayload,
    @TypedBody()
    body: ITodoAppTaskTag.IRequest,
  ): Promise<IPageITodoAppTaskTag.ISummary> {
    try {
      return await patchTodoAppTodoUserTaskTags({
        todoUser,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
