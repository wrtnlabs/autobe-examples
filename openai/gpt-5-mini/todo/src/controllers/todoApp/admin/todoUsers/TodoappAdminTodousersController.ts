import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppAdminTodoUsers } from "../../../../providers/patchTodoAppAdminTodoUsers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteTodoAppAdminTodoUsersTodoUserId } from "../../../../providers/deleteTodoAppAdminTodoUsersTodoUserId";
import { getTodoAppAdminTodoUsersTodoUserIdMetrics } from "../../../../providers/getTodoAppAdminTodoUsersTodoUserIdMetrics";

import { IPageITodoAppTodouser } from "../../../../api/structures/IPageITodoAppTodouser";
import { ITodoAppTodoUser } from "../../../../api/structures/ITodoAppTodoUser";
import { ITodoAppUserMetrics } from "../../../../api/structures/ITodoAppUserMetrics";

@Controller("/todoApp/admin/todoUsers")
export class TodoappAdminTodousersController {
  /**
   * Search and retrieve a filtered, paginated list of TodoApp users
   * (todo_app_todouser).
   *
   * Purpose and overview: This operation provides administrators with a
   * filtered, paginated view of TodoApp user accounts for management and
   * moderation purposes. It supports text search (email, display_name), status
   * filtering, isVerified flag, and created_at date ranges. The operation
   * returns sanitized summaries and pagination metadata.
   *
   * Security considerations and user permissions: Because the endpoint exposes
   * personal data (email), it MUST be restricted to authorized admin actors.
   * The provider MUST NOT return authentication secrets or tokens. Access to
   * this endpoint by admins should be audited in todo_app_audit_logs or
   * todo_app_user_activity_logs.
   *
   * Relationship to underlying database entities: Reads directly from
   * todo_app_todouser. The Prisma schema enforces email uniqueness; searches
   * should avoid exposing password_hash, mfa_secret, or password reset tokens.
   * Implementations should filter out soft-deleted users (deleted_at IS NULL)
   * by default unless an explicit admin parameter requests deleted records.
   *
   * Validation rules and business logic:
   *
   * - Request body supports pagination (page, pageSize), filters (email,
   *   displayName, status, isVerified, createdBefore, createdAfter), and
   *   sorting (created_at/updated_at with direction).
   * - Providers MUST enforce a maximum pageSize (e.g., 100) to prevent expensive
   *   queries.
   * - Returned summaries include safe fields only: id, email, display_name,
   *   is_verified, status, failed_login_attempts, last_failed_login_at,
   *   created_at, updated_at.
   *
   * Related operations:
   *
   * - GET /todoUsers/{userId} (detailed user view) should enforce stricter
   *   authorization and may include additional fields where necessary and
   *   permitted.
   *
   * Errors:
   *
   * - 200 OK: paginated summaries returned.
   * - 400 Bad Request: invalid filters or pagination values.
   * - 403 Forbidden: caller not authorized.
   *
   * @param connection
   * @param body Search criteria, filtering, sorting and pagination parameters
   *   for listing TodoApp users
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoAppTodoUser.IRequest,
  ): Promise<IPageITodoAppTodouser.ISummary> {
    try {
      return await patchTodoAppAdminTodoUsers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete a todo user account (admin).
   *
   * Purpose and overview: This endpoint allows platform administrators to
   * remove a user's account from active service by marking the
   * `todo_app_todouser` record as deleted. The Prisma model defines a
   * `deleted_at` column so a soft-delete pattern is used: set `deleted_at` and
   * update lifecycle metadata rather than performing an immediate hard purge.
   *
   * Security and permissions: Only administrators may call this endpoint. The
   * provider MUST verify the caller's actor is an admin and MUST record the
   * acting admin id and session in audit tables (`todo_app_admin_actions` and
   * `todo_app_audit_logs`). Implementations should record a reason for
   * compliance and legal traceability.
   *
   * Database relationships and side effects: This operation updates the
   * `todo_app_todouser` row (set `deleted_at`, update `status`, set
   * `refresh_tokens_revoked_at`). It should also trigger session revocation for
   * `todo_app_todouser_sessions` and create audit records in
   * `todo_app_admin_actions` and `todo_app_audit_logs` describing the action.
   *
   * Validation and error handling:
   *
   * - Validate `todoUserId` as a UUID; return 400 for invalid format.
   * - If the user does not exist in primary stores (purged), return 404.
   * - If the user exists but is already soft-deleted, return 204 (idempotent).
   * - On success, return 204 with no response body.
   *
   * @param connection
   * @param todoUserId Unique identifier of the target todo user (UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoUserId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("todoUserId")
    todoUserId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppAdminTodoUsersTodoUserId({
        admin,
        todoUserId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve aggregated user metrics for a TodoApp user (admin view).
   *
   * Purpose and overview: Retrieve aggregated, read-only metrics for a specific
   * TodoApp user. This endpoint aggregates across multiple Prisma models
   * (todo_app_tasks, todo_app_lists, todo_app_task_snapshots,
   * todo_app_user_activity_logs) to return counts and derived metrics useful
   * for admin dashboards and diagnostics.
   *
   * Security and permissions: Access is restricted to platform administrators.
   * The implementing service must verify the requester has admin privileges.
   * All accesses should be recorded in audit logs with actor id, session id,
   * and request href.
   *
   * Relationship to underlying database entities:
   *
   * - Todo_app_tasks: used to compute total, completed, and overdue task counts
   *   (exclude deleted tasks where deleted_at IS NOT NULL).
   * - Todo_app_lists: used to compute active list counts for the user (exclude
   *   lists with deleted_at IS NOT NULL).
   * - Todo_app_task_snapshots: used to compute average time-to-complete (use
   *   snapshots where completed_at and original_created_at are present).
   * - Todo_app_user_activity_logs: used to compute last_active_at (most recent
   *   activity.created_at for the user).
   *
   * Validation rules and business logic:
   *
   * - Path parameter `todoUserId` must be a valid UUID corresponding to
   *   todo_app_todouser.id. Return 400 for invalid UUID format and 404 if the
   *   user does not exist.
   * - Exclude any rows where `deleted_at IS NOT NULL` from counts and averages.
   * - If the user has no tasks, numeric counts should be 0 and
   *   average_time_to_complete_seconds should be null.
   * - Time values must be returned as ISO-8601 UTC timestamps. Duration values
   *   are numeric seconds.
   *
   * Errors and expected responses:
   *
   * - 200: aggregated metrics object
   * - 400: invalid todoUserId format
   * - 401/403: unauthorized if requester is not an admin
   * - 404: user not found
   *
   * @param connection
   * @param todoUserId Unique identifier of the target TodoApp user (corresponds
   *   to todo_app_todouser.id)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoUserId/metrics")
  public async metrics(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("todoUserId")
    todoUserId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUserMetrics> {
    try {
      return await getTodoAppAdminTodoUsersTodoUserIdMetrics({
        admin,
        todoUserId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
