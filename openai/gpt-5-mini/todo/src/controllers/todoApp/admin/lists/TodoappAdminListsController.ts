import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteTodoAppAdminListsListId } from "../../../../providers/deleteTodoAppAdminListsListId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

@Controller("/todoApp/admin/lists/:listId")
export class TodoappAdminListsController {
  /**
   * Soft-delete (mark deleted_at) a todo list (todo_app_lists).
   *
   * Purpose and overview: This operation performs a business soft-delete of a
   * todo list. It marks the `todo_app_lists.deleted_at` column with the current
   * server timestamp to hide the list from normal application read paths while
   * preserving tasks, collaborators, invitations, shares, and snapshots for
   * possible restoration and audit.
   *
   * Security and permissions: Only an authorized administrator may call this
   * admin-scoped route. The service MUST verify the caller's admin role.
   * Unauthorized requests MUST return 403 Forbidden.
   *
   * Relationship to database entities: Operates on the `todo_app_lists` model.
   * Related records remain unchanged and are interpreted as logically hidden by
   * application logic when the parent list is soft-deleted.
   *
   * Validation and business logic:
   *
   * - Validate `listId` as a UUID. Return 400 for invalid UUID formats.
   * - If no matching active list exists (not found or already soft-deleted),
   *   return 404 Not Found.
   * - Verify caller is admin; otherwise return 403 Forbidden.
   * - Set `deleted_at` to current timestamp and persist change; create an audit
   *   record (todo_app_audit_logs) recording event_type `delete` (or
   *   `remove_list`) with actor id, session id, list id, and human-readable
   *   details.
   *
   * Responses and error handling:
   *
   * - 204 No Content on success
   * - 400 Bad Request for invalid UUID format
   * - 403 Forbidden for insufficient permissions
   * - 404 Not Found when list is absent or already deleted
   * - 500 Internal Server Error for unexpected failures
   *
   * @param connection
   * @param listId Unique identifier (UUID) of the target todo list
   *   (todo_app_lists.id)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("listId")
    listId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppAdminListsListId({
        admin,
        listId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
