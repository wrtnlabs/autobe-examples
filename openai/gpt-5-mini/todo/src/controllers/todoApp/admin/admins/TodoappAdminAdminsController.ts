import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppAdminAdmins } from "../../../../providers/patchTodoAppAdminAdmins";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getTodoAppAdminAdminsAdminId } from "../../../../providers/getTodoAppAdminAdminsAdminId";
import { putTodoAppAdminAdminsAdminId } from "../../../../providers/putTodoAppAdminAdminsAdminId";
import { deleteTodoAppAdminAdminsAdminId } from "../../../../providers/deleteTodoAppAdminAdminsAdminId";

import { IPageITodoAppAdmin } from "../../../../api/structures/IPageITodoAppAdmin";
import { ITodoAppAdmin } from "../../../../api/structures/ITodoAppAdmin";

@Controller("/todoApp/admin/admins")
export class TodoappAdminAdminsController {
  /**
   * Search and retrieve a paginated list of TodoApp admin accounts
   * (todo_app_admin).
   *
   * Purpose and overview: Provide a paginated, filterable list of admin
   * accounts for platform operators. Supports searching by email or
   * display_name (case-insensitive partial matches), filtering by role and
   * is_active, sorting by created_at or display_name, and pagination (page,
   * pageSize).
   *
   * Security and permissions: This endpoint MUST be restricted to platform
   * administrators. Only admin actors may call this operation. Sensitive fields
   * (password_hash, mfa_secret, mfa_backup_codes, deleted_at) MUST NOT be
   * returned in normal responses. All access to this endpoint must be audited.
   *
   * Relationship to underlying database entities: Queries map to the
   * `todo_app_admin` Prisma model. Use indexed fields (email, role, is_active,
   * created_at) for performant filtering.
   *
   * Validation rules and business logic:
   *
   * - Request body (ITodoAppAdmin.IRequest) contains search, filter, sort, and
   *   pagination parameters. Validate page and pageSize as positive integers
   *   with reasonable upper bounds (e.g., pageSize <= 100).
   * - Sorting only allows approved fields (created_at, display_name). Invalid
   *   sort fields return 400.
   * - Search fields should be normalized for case-insensitive partial matching.
   *
   * Responses and errors:
   *
   * - 200: paginated summary of admin accounts (IPageITodoAppAdmin.ISummary)
   * - 400: invalid request (bad pagination or invalid sort field)
   * - 401/403: unauthorized when requester is not an admin
   *
   * @param connection
   * @param body Search, filtering and pagination parameters for admin listing
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoAppAdmin.IRequest,
  ): Promise<IPageITodoAppAdmin.ISummary> {
    try {
      return await patchTodoAppAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve an administrator account by ID (todo_app_admin).
   *
   * Purpose and overview: This endpoint retrieves a single administrator
   * account from the system for authorized platform operators. It returns
   * administrative account metadata pulled from the `todo_app_admin` Prisma
   * model including non-sensitive fields such as id, email, display_name, role,
   * is_active, created_at, updated_at, and the optional deleted_at timestamp.
   *
   * Security considerations and permissions: Access to this endpoint MUST be
   * restricted to actors with administrative privileges. Requests must be
   * authenticated and authorized; all successful and failed access attempts
   * SHOULD be recorded in `todo_app_audit_logs` with the acting admin/session
   * for compliance and traceability.
   *
   * Relationship to underlying database entity: This operation directly reads
   * from the `todo_app_admin` table. The model's schema comments describe the
   * purpose of each column: `email` is the unique admin login, `password_hash`
   * is stored but MUST NOT be returned by this API, `role` identifies admin
   * scope (e.g., moderator, support, superadmin), and `is_active` indicates
   * whether the account may authenticate.
   *
   * Validation rules and error handling:
   *
   * - `adminId` path parameter is validated as a UUID; invalid formats return 400
   *   with a validation error.
   * - If the target admin record does not exist, the endpoint returns 404.
   * - Sensitive fields (e.g., `password_hash`, `mfa_secret`, `mfa_backup_codes`)
   *   are omitted from the response payload.
   *
   * Expected behavior and edge cases:
   *
   * - If the record exists but `is_active` is false or `deleted_at` is non-null,
   *   the endpoint still returns the record for authorized admin consumers but
   *   the response SHOULD clearly indicate `is_active` and the `deleted_at`
   *   timestamp to aid moderation workflows.
   * - The API MUST not return `password_hash` or any secret material.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin (UUID). Matches
   *   todo_app_admin.id in the Prisma schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppAdmin> {
    try {
      return await getTodoAppAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an administrator account (todo_app_admin).
   *
   * Purpose and overview: This endpoint updates mutable fields of an existing
   * administrator account in the `todo_app_admin` table. It is suitable for
   * maintaining admin metadata such as display name, role, and active flag. The
   * endpoint deliberately excludes secrets management; password updates must
   * occur through a dedicated password-change or reset flow.
   *
   * Security considerations and permissions: Only actors with appropriate
   * administrative authority may call this endpoint. Every update request MUST
   * be authenticated and authorized, and all changes MUST be recorded in
   * administrative audit tables (`todo_app_admin_actions` and
   * `todo_app_audit_logs`) to provide a complete compliance trail.
   *
   * Relationship to underlying database entity: The Prisma model
   * `todo_app_admin` defines the persisted columns. This operation operates on
   * the `id` primary key and updates fields permitted by policy. The `email`
   * column is unique and immutable in many policies; if email changes are
   * allowed, the implementation must enforce uniqueness and verification
   * workflows.
   *
   * Validation rules and business logic:
   *
   * - Validate `adminId` as UUID; return 400 for invalid format.
   * - Validate incoming fields in the request body: `display_name` (string),
   *   `role` (valid role string), `is_active` (boolean). Reject unknown or
   *   disallowed fields.
   * - Do not accept `password_hash`, `mfa_secret`, or `mfa_backup_codes` in the
   *   request. If password change is required, use a dedicated endpoint.
   * - On success, return the updated admin DTO excluding secrets.
   *
   * Related operations and expected behavior:
   *
   * - After deactivating an admin account (setting `is_active=false`),
   *   implementations SHOULD revoke sessions and record an admin action
   *   describing the reason.
   * - Changes to `role` may affect authorization and SHOULD be reflected in
   *   subsequent access checks immediately or after a short propagation
   *   window.
   *
   * Error handling:
   *
   * - 400: invalid input (including invalid UUID format or invalid role value)
   * - 404: admin not found
   * - 409: conflict (e.g., attempting to set an email that conflicts with an
   *   existing account, if email updates are permitted)
   *
   * @param connection
   * @param adminId Unique identifier of the target admin (UUID). Matches
   *   todo_app_admin.id in the Prisma schema.
   * @param body Admin update payload containing mutable administrator fields
   *   (display_name, role, is_active). `password_hash`, `mfa_secret`, and
   *   `mfa_backup_codes` MUST NOT be provided through this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppAdmin.IUpdate,
  ): Promise<ITodoAppAdmin> {
    try {
      return await putTodoAppAdminAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete an administrator account (todo_app_admin).
   *
   * Delete an administrator account (soft-delete) and revoke active admin
   * sessions.
   *
   * Purpose and overview: This operation marks the specified administrator
   * account as deleted by setting the todo_app_admin.deleted_at timestamp. It
   * preserves the record for audit and compliance while preventing the deleted
   * admin from authenticating and taking administrative actions. The operation
   * also writes a moderation record to todo_app_admin_actions and an audit
   * entry to todo_app_audit_logs.
   *
   * Security and permissions: Only authorized administrative actors with
   * sufficient privileges may call this endpoint. The implementation MUST
   * verify the caller's role/privileges (for example: superadmin), require a
   * reason for the action, and record actor id and actor session id in the
   * admin action and audit log. Active sessions for the deleted admin should be
   * revoked or expired immediately.
   *
   * Relationship to underlying DB entities: Primary resource: todo_app_admin
   * (fields used: id, deleted_at). Side-effect tables: todo_app_admin_sessions
   * (to revoke/expire sessions), todo_app_admin_actions (to record the
   * moderation action), todo_app_audit_logs (to capture the event). All
   * referenced fields exist in the Prisma schema.
   *
   * Validation and business logic: Validate adminId is a UUID referencing an
   * existing todo_app_admin.id. If target not found -> 404. If caller lacks
   * privileges -> 403. If already deleted (deleted_at not null) -> 410 Gone (or
   * 400 per product policy). Permanent purge is not performed by this endpoint;
   * it only marks deleted_at and triggers revocation/audit logic.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin (UUID)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
