import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppAdminAdminsAdminIdSessions } from "../../../../../providers/patchTodoAppAdminAdminsAdminIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getTodoAppAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/getTodoAppAdminAdminsAdminIdSessionsSessionId";
import { deleteTodoAppAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/deleteTodoAppAdminAdminsAdminIdSessionsSessionId";

import { IPageITodoAppAdminSession } from "../../../../../api/structures/IPageITodoAppAdminSession";
import { ITodoAppAdminSession } from "../../../../../api/structures/ITodoAppAdminSession";

@Controller("/todoApp/admin/admins/:adminId/sessions")
export class TodoappAdminAdminsSessionsController {
  /**
   * Search and retrieve paginated admin session records for a specific
   * administrator (todo_app_admin_sessions).
   *
   * Retrieve paginated and filtered admin session records for a specified
   * administrator.
   *
   * Purpose and overview: Provide administrators with the ability to list and
   * filter session records associated with a specific administrator account.
   * Supports filters for IP address, created_at range, expired/active state,
   * referrer, and href. Results are intended for administrative investigation
   * and session management.
   *
   * Security and permissions: Only authorized admin actors may perform this
   * operation. The endpoint MUST NOT return secrets. Accesses should be
   * recorded in todo_app_audit_logs for compliance and traceability.
   *
   * Relationship to DB entities: Primary table: todo_app_admin_sessions
   * (fields: id, todo_app_admin_id, ip, href, referrer, created_at,
   * expired_at). The operation validates existence of parent todo_app_admin
   * record prior to returning results.
   *
   * Validation and business logic: Validate adminId as UUID and existence of
   * admin. Validate request filters (ISO-8601 dates, booleans). Apply
   * pagination and result-size limits (recommended default page size: 25; max:
   * 200). Errors: 400 for invalid params, 403 for insufficient privileges, 404
   * for missing admin.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin (UUID)
   * @param body Search criteria and pagination parameters for admin sessions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppAdminSession.IRequest,
  ): Promise<IPageITodoAppAdminSession.ISummary> {
    try {
      return await patchTodoAppAdminAdminsAdminIdSessions({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific admin session (todo_app_admin_sessions).
   *
   * Purpose and overview:
   *
   * Retrieve detailed information about a specific administrator session for
   * audit and session-management UIs. The response includes the session id,
   * owning admin id, ip, href, referrer, created_at, and expired_at as defined
   * by the Prisma model `todo_app_admin_sessions`.
   *
   * Security and permissions:
   *
   * Only actors with the `admin` actor role may call this endpoint. The
   * implementation MUST verify that the caller is authenticated as an admin and
   * has rights to inspect sessions. This DTO MUST NOT include admin credentials
   * or secrets (for example: password_hash, mfa_secret, mfa_backup_codes).
   * Those fields are never returned by this endpoint.
   *
   * Relationship to DB entities and business rules:
   *
   * This operation reads the `todo_app_admin_sessions` table (Prisma model). If
   * the matching session row has `deleted_at` set, the endpoint treats it as
   * not active and returns 404 for standard UI usage. Forensic retrieval of
   * soft-deleted rows may be supported via a separate admin-only flag and
   * endpoint (not included here).
   *
   * Validation rules and error handling:
   *
   * Path parameters `adminId` and `sessionId` MUST be valid UUIDs. If either
   * path parameter fails format validation, return 400 Bad Request. If no
   * active session exists matching both the admin and session IDs (or the row's
   * `deleted_at` is non-null), return 404 Not Found. On success return 200 with
   * the ITodoAppAdminSession DTO. Unexpected server errors return 500 and
   * should be recorded in audit logs.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin (todo_app_admin.id) in
   *   UUID format
   * @param sessionId Unique identifier of the target admin session
   *   (todo_app_admin_sessions.id) in UUID format
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppAdminSession> {
    try {
      return await getTodoAppAdminAdminsAdminIdSessionsSessionId({
        admin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete (erase) a specific admin session (todo_app_admin_sessions).
   *
   * Purpose and overview:
   *
   * Mark an administrator session as deleted by setting the `deleted_at`
   * timestamp on the `todo_app_admin_sessions` record. This revokes the session
   * from active lists while preserving the row for historical/audit purposes.
   *
   * Security and permissions:
   *
   * Only privileged admin actors may perform this operation. The endpoint MUST
   * verify the caller's admin privileges and record the actor id and rationale
   * in admin-action and audit tables. Implementations MUST ensure audit entries
   * are created atomically with the soft-delete to avoid gaps in the audit
   * trail.
   *
   * Relationship to underlying database entities:
   *
   * The operation updates the `todo_app_admin_sessions` record identified by
   * `sessionId` that belongs to the admin `adminId`. The referenced admin
   * account (`todo_app_admin`) is not modified. Append-only audit tables
   * (todo_app_admin_actions, todo_app_audit_logs) remain untouched except for
   * the created audit records documenting this action.
   *
   * Validation rules and business logic:
   *
   * Path parameters `adminId` and `sessionId` MUST be valid UUIDs. If invalid,
   * return 400. If no matching active session exists (absent or already
   * `deleted_at` set), return 404 (alternatively, API owners may choose to
   * implement idempotent behavior and return 204 in this case — be consistent
   * across the API). On successful soft-delete return 204 No Content. The
   * implementation MUST set `deleted_at` to the current server timestamptz and
   * create corresponding admin action and audit log entries.
   *
   * Error handling:
   *
   * - 400 Bad Request: invalid UUID path parameter format.
   * - 404 Not Found: session not found or already soft-deleted (or implementers
   *   may opt for 204 idempotent behavior).
   * - 403 Forbidden: caller lacks admin privileges.
   * - 500 Internal Server Error: unexpected failure; must be logged for
   *   investigation.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin (todo_app_admin.id) in
   *   UUID format
   * @param sessionId Unique identifier of the target admin session
   *   (todo_app_admin_sessions.id) in UUID format
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppAdminAdminsAdminIdSessionsSessionId({
        admin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
