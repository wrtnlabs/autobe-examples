import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppAdminGuests } from "../../../../providers/patchTodoAppAdminGuests";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getTodoAppAdminGuestsGuestId } from "../../../../providers/getTodoAppAdminGuestsGuestId";

import { IPageITodoAppGuest } from "../../../../api/structures/IPageITodoAppGuest";
import { ITodoAppGuest } from "../../../../api/structures/ITodoAppGuest";

@Controller("/todoApp/admin/guests")
export class TodoappAdminGuestsController {
  /**
   * Search, filter, and retrieve a paginated list of guest records
   * (todo_app_guest).
   *
   * Retrieve a filtered and paginated list of guest records from the
   * `todo_app_guest` table.
   *
   * Purpose and overview: This operation supports administrative search and
   * listing of guest visitors. The underlying Prisma model `todo_app_guest`
   * stores minimal guest metadata: id (UUID), created_at, updated_at, optional
   * anonymous_label, and deleted_at (soft-delete timestamp). The endpoint
   * accepts complex request parameters (search text, pagination, sort,
   * created_at ranges) via the request body and returns a paginated summary
   * view optimized for list displays.
   *
   * Security and permissions: Restricted to administrative actors. The
   * operation must ensure that sensitive fields are not exposed to unauthorized
   * clients. When returning soft-deleted records (where `deleted_at` is
   * non-null), the implementation must confirm the caller has administrative
   * privileges and/or the request explicitly requests inclusion of deleted
   * entries.
   *
   * Relationship to the Prisma model: Direct queries against the
   * `todo_app_guest` model. Queryable fields MUST match the model fields (id,
   * created_at, updated_at, anonymous_label, deleted_at). Leverage available
   * indexes (created_at) and optional trigram search on anonymous_label for
   * efficient partial matches.
   *
   * Validation rules and business logic: Validate pagination parameters, date
   * ranges (created_at filters), and text search length. If includeDeleted is
   * provided, only allow when caller is admin; otherwise filter out
   * soft-deleted rows (deleted_at IS NULL). Return pagination metadata (page,
   * pageSize, total) in the response container.
   *
   * @param connection
   * @param body Search and pagination parameters for querying guest records.
   *   Supports text search on anonymous_label, date-range filters on
   *   created_at, pagination (page, pageSize), sort options, and an optional
   *   includeDeleted boolean (admin-only) to include soft-deleted records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoAppGuest.IRequest,
  ): Promise<IPageITodoAppGuest.ISummary> {
    try {
      return await patchTodoAppAdminGuests({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single guest record by guestId (todo_app_guest).
   *
   * Retrieve detailed information about a single guest record identified by
   * UUID.
   *
   * Purpose and overview: Returns the `ITodoAppGuest` representation for the
   * specified guest. The guest model stores only limited metadata (id,
   * created_at, updated_at, optional anonymous_label, and deleted_at). This
   * endpoint is intended for administrative or support use when investigating a
   * specific guest or correlating guest activity with audit logs.
   *
   * Security and user permissions: Strictly restricted to administrative
   * actors. The returned payload includes only fields defined on the
   * `todo_app_guest` Prisma model. If the target record is soft-deleted
   * (`deleted_at` non-null), the response reflects that state and the caller
   * must be authorized to view deleted entries.
   *
   * Relationship to underlying database entity: Direct mapping to
   * `todo_app_guest` table; the id path parameter maps to `todo_app_guest.id`
   * (UUID primary key). The operation validates existence and returns 404 when
   * the id does not match an active or visible record per authorization rules.
   *
   * Validation and error handling: Validate `guestId` path parameter as UUID
   * and return 400 for invalid formats. For missing records return 404. For
   * insufficient privileges return 401/403. Unexpected server errors return 500
   * with structured error.
   *
   * @param connection
   * @param guestId Unique identifier of the target guest (UUID) corresponding
   *   to `todo_app_guest.id`.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":guestId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppGuest> {
    try {
      return await getTodoAppAdminGuestsGuestId({
        admin,
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
