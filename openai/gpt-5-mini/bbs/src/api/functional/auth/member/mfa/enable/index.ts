import { IDiscussionBoardMember } from "../../../../../structures/IDiscussionBoardMember";

/**
 * Enable two-factor authentication (member.mfa_enabled).
 *
 * Purpose and overview: This protected endpoint enables MFA for the
 * authenticated member by setting discussion_board_member.mfa_enabled = true
 * and returning any required setup artifact (QR code or secret). The
 * discussion_board_member.mfa_enabled boolean in the Prisma schema directly
 * indicates whether MFA is active for the account.
 *
 * Implementation details and referenced schema fields: The operation MUST
 * update discussion_board_member.mfa_enabled and persist updated_at. If the
 * service issues a TOTP secret or device registration artifact, that secret
 * should be stored securely (outside the visible member profile) and not
 * returned in plain text except as a time-limited enrollment token or QR image.
 * The schema provides mfa_enabled to represent enrollment state.
 *
 * Actor-specific integration and business context: This endpoint is protected
 * and must be callable only by the authenticated member (authorizationActor:
 * "member"). Enabling MFA typically requires a subsequent verification step at
 * login (step-up) and ties into the login flow described earlier.
 *
 * Security considerations and validation rules: Store MFA secrets under strong
 * encryption and record enabling events in discussion_board_audit_logs. Do not
 * expose persistent secrets in API responses. The endpoint SHOULD require
 * recent re-authentication or step-up if the session is old.
 *
 * Related operations and workflow integration: Related APIs: POST
 * /auth/member/login (may require second-factor when mfa_enabled is true), POST
 * /auth/member/mfa/disable, and audit log entries in
 * discussion_board_moderation_audit or discussion_board_audit_logs for
 * enrollment events.
 *
 * @param props.connection
 * @param props.body Optional payload to initiate MFA enrollment; server may
 *   respond with an enrollment artifact (QR/secret) and will set
 *   discussion_board_member.mfa_enabled on successful enrollment.
 * @path /auth/member/mfa/enable
 * @accessor api.functional.auth.member.mfa.enable.enableTwoFactor
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function enableTwoFactor(
  connection: IConnection,
  props: enableTwoFactor.Props,
): Promise<enableTwoFactor.Response> {
  return true === connection.simulate
    ? enableTwoFactor.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...enableTwoFactor.METADATA,
          path: enableTwoFactor.path(),
          status: null,
        },
        props.body,
      );
}
export namespace enableTwoFactor {
  export type Props = {
    /**
     * Optional payload to initiate MFA enrollment; server may respond with
     * an enrollment artifact (QR/secret) and will set
     * discussion_board_member.mfa_enabled on successful enrollment.
     */
    body: IDiscussionBoardMember.IEnableTwoFactor;
  };
  export type Body = IDiscussionBoardMember.IEnableTwoFactor;
  export type Response = IDiscussionBoardMember;

  export const METADATA = {
    method: "POST",
    path: "/auth/member/mfa/enable",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/member/mfa/enable";
  export const random = (): IDiscussionBoardMember =>
    typia.random<IDiscussionBoardMember>();
  export const simulate = (
    connection: IConnection,
    props: enableTwoFactor.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: enableTwoFactor.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
