import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMember } from "../../../../../structures/IDiscussionBoardMember";

/**
 * Reset password using token (discussion_board_password_resets).
 *
 * Purpose and overview: This endpoint consumes a single-use reset token stored
 * in discussion_board_password_resets (token, created_at, expires_at,
 * consumed_at, request_ip) and updates the corresponding
 * discussion_board_member.password_hash with a securely hashed new password.
 * The consumed_at timestamp MUST be set to prevent replay.
 *
 * Implementation details and referenced schema fields: The implementation MUST
 * locate the reset record by token, verify expires_at and that consumed_at is
 * null, atomically set consumed_at, and then update
 * discussion_board_member.password_hash for the referenced
 * discussion_board_member_id. The operation may also create or update
 * discussion_board_member_sessions to revoke existing sessions or optionally
 * issue a new session/authorization pair.
 *
 * Actor-specific integration and business context: This operation is part of a
 * public reset flow (token in email acts as bearer). Because the Prisma schema
 * records request_ip, implementations can use that data to detect anomalies and
 * log the event to discussion_board_audit_logs.
 *
 * Security considerations and validation rules: Password strength checks MUST
 * be enforced before updating discussion_board_member.password_hash. After a
 * successful reset the system SHOULD revoke active refresh credentials (e.g.,
 * update discussion_board_member_sessions.expired_at) to prevent session
 * fixation.
 *
 * Related operations and workflow integration: Related APIs: POST
 * /auth/member/password/request (creates the reset token), POST
 * /auth/member/login, and session revocation endpoints for full security
 * alignment.
 *
 * @param props.connection
 * @param props.body Payload containing the reset token and the new password.
 *   The server will validate the token against discussion_board_password_resets
 *   and update discussion_board_member.password_hash on success.
 * @path /auth/member/password/reset
 * @accessor api.functional.auth.member.password.reset.resetPassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resetPassword(
  connection: IConnection,
  props: resetPassword.Props,
): Promise<resetPassword.Response> {
  return true === connection.simulate
    ? resetPassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resetPassword.METADATA,
          path: resetPassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resetPassword {
  export type Props = {
    /**
     * Payload containing the reset token and the new password. The server
     * will validate the token against discussion_board_password_resets and
     * update discussion_board_member.password_hash on success.
     */
    body: IDiscussionBoardMember.IResetPassword;
  };
  export type Body = IDiscussionBoardMember.IResetPassword;
  export type Response = IDiscussionBoardMember;

  export const METADATA = {
    method: "POST",
    path: "/auth/member/password/reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/member/password/reset";
  export const random = (): IDiscussionBoardMember =>
    typia.random<IDiscussionBoardMember>();
  export const simulate = (
    connection: IConnection,
    props: resetPassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resetPassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
