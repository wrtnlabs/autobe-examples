/**
 * List moderator's active sessions (reads discussion_board_moderator_sessions).
 *
 * Purpose and overview: Return a paginated list of session records belonging to
 * the authenticated moderator. This operation reads
 * discussion_board_moderator_sessions and exposes id, ip, href, referrer,
 * created_at and expired_at for each session row.
 *
 * Implementation details and field usage: The implementation queries
 * discussion_board_moderator_sessions filtered by discussion_board_moderator_id
 * = authenticated moderator id, orders by created_at desc, and returns
 * pagination metadata. The session records include created_at and expired_at to
 * allow clients to show session age and expiry.
 *
 * Actor-specific integration and business context: Moderators may use this
 * endpoint to inspect active sessions across devices and locations; session
 * records map directly to the discussion_board_moderator_sessions model,
 * enabling re-use of existing fields for UI and audit purposes.
 *
 * Security considerations within schema constraints: This endpoint is protected
 * and returns only the sessions for the authenticated moderator. Do not expose
 * other moderators' sessions. Access should be recorded in
 * discussion_board_audit_logs or discussion_board_audit_log_accesses when
 * required for compliance.
 *
 * Related operations and workflow integration: Clients often call this endpoint
 * after login or when managing sessions. It pairs with the eraseSession
 * operation to revoke individual sessions recorded in
 * discussion_board_moderator_sessions.
 *
 * @param props.connection
 * @path /auth/moderator/sessions
 * @accessor api.functional.auth.moderator.sessions.listSessions
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function listSessions(
  connection: IConnection,
): Promise<listSessions.Response> {
  return true === connection.simulate
    ? listSessions.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...listSessions.METADATA,
          path: listSessions.path(),
          status: null,
        },
      );
}
export namespace listSessions {
  export type Response = IDiscussionBoardModerator.ISessionsPage;

  export const METADATA = {
    method: "GET",
    path: "/auth/moderator/sessions",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/moderator/sessions";
  export const random = (): IDiscussionBoardModerator.ISessionsPage =>
    typia.random<IDiscussionBoardModerator.ISessionsPage>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Revoke a specific moderator session by id (modifies
 * discussion_board_moderator_sessions).
 *
 * Purpose and overview: Allow an authenticated moderator to revoke a specific
 * session by id. This operation targets discussion_board_moderator_sessions and
 * either deletes the row or sets expired_at to the current time to invalidate
 * the session.
 *
 * Implementation details and field usage: The implementation locates
 * discussion_board_moderator_sessions.id = {sessionId} and verifies the
 * session.discussion_board_moderator_id equals the authenticated moderator id.
 * On success it either deletes the row or updates expired_at to revoke the
 * session. The operation should record the revocation in
 * discussion_board_audit_logs for traceability.
 *
 * Actor-specific integration and business context: This operation is intended
 * for per-session session management: a moderator may revoke lost device
 * sessions or terminate other active connections. Because the sessions table
 * includes ip, href and referrer, the UI can display contextual details to help
 * the moderator identify the correct session to revoke.
 *
 * Security considerations within schema constraints: Only the session owner (or
 * an administrator acting via separate admin APIs) may revoke a session. The
 * operation must not allow revoking sessions belonging to other moderators.
 * After revocation, clients depending on that session must fail authentication
 * and require re-login.
 *
 * Related operations and workflow integration: This complements listSessions
 * and changePassword flows. When a password change occurs, implementations
 * SHOULD revoke all sessions (bulk revoke) and this endpoint allows targeted
 * revocation.
 *
 * @param props.connection
 * @param props.sessionId Target session's ID
 * @path /auth/moderator/sessions/:sessionId
 * @accessor api.functional.auth.moderator.sessions.eraseSession
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function eraseSession(
  connection: IConnection,
  props: eraseSession.Props,
): Promise<eraseSession.Response> {
  return true === connection.simulate
    ? eraseSession.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...eraseSession.METADATA,
          path: eraseSession.path(props),
          status: null,
        },
      );
}
export namespace eraseSession {
  export type Props = {
    /** Target session's ID */
    sessionId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardModerator.ISessionErasedResult;

  export const METADATA = {
    method: "DELETE",
    path: "/auth/moderator/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/auth/moderator/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): IDiscussionBoardModerator.ISessionErasedResult =>
    typia.random<IDiscussionBoardModerator.ISessionErasedResult>();
  export const simulate = (
    connection: IConnection,
    props: eraseSession.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: eraseSession.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
