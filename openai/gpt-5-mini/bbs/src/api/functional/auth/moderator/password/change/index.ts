import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardModerator } from "../../../../../structures/IDiscussionBoardModerator";

/**
 * Change current moderator's password (updates
 * discussion_board_moderator.password_hash and revokes sessions).
 *
 * Purpose and overview: Allow an authenticated moderator to change their
 * account password. This operation targets discussion_board_moderator and
 * updates the password_hash column after validating the current password.
 *
 * Implementation details and field usage: The operation looks up the moderator
 * row by authenticated actor id, verifies the provided current password against
 * discussion_board_moderator.password_hash, and replaces the stored hash with
 * the new password_hash. The updated_at field on discussion_board_moderator
 * should be updated to reflect the change and deleted_at must be considered to
 * ensure suspended accounts cannot change passwords.
 *
 * Actor-specific integration and business context: Because the Prisma schema
 * stores password_hash in discussion_board_moderator, the system can implement
 * a secure change-password flow without additional DB objects. The operation
 * should also revoke existing sessions in discussion_board_moderator_sessions
 * (set expired_at or remove rows) to enforce re-authentication across devices
 * after password change.
 *
 * Security considerations within schema constraints: Never return password_hash
 * in responses. After changing the password the implementation MUST invalidate
 * existing sessions recorded in discussion_board_moderator_sessions to prevent
 * session fixation. Record a discussion_board_audit_logs entry capturing the
 * password change event for compliance.
 *
 * Related operations and workflow integration: This operation complements login
 * and session-management endpoints. There is no moderator-specific password
 * reset model in the schema, so password reset via email is not generated for
 * moderator actor by this interface.
 *
 * @param props.connection
 * @param props.body Change password payload (currentPassword, newPassword).
 * @path /auth/moderator/password/change
 * @accessor api.functional.auth.moderator.password.change.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<changePassword.Response> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /** Change password payload (currentPassword, newPassword). */
    body: IDiscussionBoardModerator.IChangePassword;
  };
  export type Body = IDiscussionBoardModerator.IChangePassword;
  export type Response = IDiscussionBoardModerator;

  export const METADATA = {
    method: "POST",
    path: "/auth/moderator/password/change",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/moderator/password/change";
  export const random = (): IDiscussionBoardModerator =>
    typia.random<IDiscussionBoardModerator>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
