/**
 * Search and bulk-manage notifications for a member.
 *
 * Retrieve and perform bulk operations on a member's notifications. This
 * operation provides advanced search, filtering, sorting and bulk mutation
 * capabilities for notifications tied to a member. It is implemented against
 * the discussion_board_notifications table as defined in the Prisma schema and
 * returns paginated summary entries optimized for list displays.
 *
 * Security and permissions: This endpoint requires authentication and that the
 * authenticated actor either be the member identified by {memberUsername} or
 * have appropriate administrative privileges. Server-side logic MUST verify
 * member ownership by resolving the provided username to
 * discussion_board_member.id and matching notifications by
 * discussion_board_notifications.recipient_member_id. Audit-write actions (bulk
 * modifications) SHOULD create appropriate audit entries in
 * discussion_board_audit_logs. For list results the ISummary type SHOULD NOT
 * include full `payload` content to avoid accidental PII exposure; include only
 * sanitized excerpt or a hasPayload flag in the summary.
 *
 * @param props.connection
 * @param props.memberUsername Unique username of the target member (global
 *   scope)
 * @param props.body Search filters, pagination parameters and optional bulk
 *   actions to perform on the matched notifications
 *   (IDiscussionBoardNotification.IRequest)
 * @path /discussionBoard/member/members/:memberUsername/notifications
 * @accessor api.functional.discussionBoard.member.members.notifications.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
