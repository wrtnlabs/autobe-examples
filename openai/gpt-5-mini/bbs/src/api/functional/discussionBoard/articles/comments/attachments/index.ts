import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardCommentAttachment } from "../../../../../structures/IDiscussionBoardCommentAttachment";

/**
 * Get metadata for a comment attachment (discussion_board_comment_attachments).
 *
 * Retrieve metadata for a single comment attachment from the
 * discussion_board_comment_attachments table.
 *
 * Returns metadata required for UI previews and for obtaining a download
 * reference from object storage. The returned fields (per Prisma model)
 * include: id, discussion_board_comment_id, discussion_board_uploaded_by_id
 * (nullable), original_filename, storage_key (internal) or downloadUrl (signed
 * URL for public use), mime_type, size, is_image, quarantined, and created_at.
 *
 * Security and visibility: If the attachment is quarantined or the parent
 * comment/article is hidden/deleted, the implementation must return 403 or 404
 * according to policy. Public responses MUST NOT include raw internal
 * `storage_key`; instead provide an expiring `downloadUrl` (signed) or
 * `cdnUrl`. Moderator/internal consumers may receive `storage_key` when
 * authorized.
 *
 * This operation does not stream binary content — it returns metadata only. Use
 * returned metadata to request a signed download URL or to initiate a proxied
 * download flow.
 *
 * @param props.connection
 * @param props.articleId UUID of the target article to validate hierarchical
 *   context (ensures comment belongs to article).
 * @param props.commentId UUID of the target comment to validate hierarchical
 *   context.
 * @param props.attachmentId UUID of the attachment to retrieve.
 * @path /discussionBoard/articles/:articleId/comments/:commentId/attachments/:attachmentId
 * @accessor api.functional.discussionBoard.articles.comments.attachments.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * UUID of the target article to validate hierarchical context (ensures
     * comment belongs to article).
     */
    articleId: string & tags.Format<"uuid">;

    /** UUID of the target comment to validate hierarchical context. */
    commentId: string & tags.Format<"uuid">;

    /** UUID of the attachment to retrieve. */
    attachmentId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardCommentAttachment;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/articles/:articleId/comments/:commentId/attachments/:attachmentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/comments/${encodeURIComponent(props.commentId ?? "null")}/attachments/${encodeURIComponent(props.attachmentId ?? "null")}`;
  export const random = (): IDiscussionBoardCommentAttachment =>
    typia.random<IDiscussionBoardCommentAttachment>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.param("commentId")(() => typia.assert(props.commentId));
      assert.param("attachmentId")(() => typia.assert(props.attachmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
