/**
 * Search and retrieve a filtered, paginated list of comments for an article
 * (DiscussionBoardComment).
 *
 * Purpose and overview:
 *
 * Retrieve a filtered, sorted and paginated list of comments that belong to a
 * single article. This operation is intended for article comment listings and
 * supports search (full-text/trigram on content), filtering by author, parent
 * comment, moderation state, and pagination. Results are returned in a
 * paginated envelope containing comment summary items to minimize payload
 * size.
 *
 * Security considerations and user permissions:
 *
 * This is a public read operation for standard audiences. However, comments
 * that are soft-deleted (discussion_board_comments.deleted_at IS NOT NULL) or
 * explicitly hidden by moderation (is_hidden = true) MUST NOT be returned to
 * unauthenticated or non-moderator actors. Authorization checks and additional
 * fields returned must be implemented in the business layer; the public API
 * surface is unauthenticated ([]). Moderator actors will require a separate
 * authenticated endpoint or an actor-aware variant to include hidden comments.
 *
 * Relationship to underlying database entities:
 *
 * This operation maps to the discussion_board_comments table in the Prisma
 * schema. Key columns used: discussion_board_article_id (scoping), content
 * (search), discussion_board_author_id (author filtering),
 * discussion_board_parent_comment_id (threading), is_hidden (moderation
 * filtering), created_at/updated_at (sorting and pagination) and deleted_at
 * (soft-delete filtering). The endpoint must join or hydrate author summary
 * information from discussion_board_member as necessary for the response DTO.
 *
 * Validation rules and business logic:
 *
 * - ArticleId path parameter must be a UUID corresponding to an existing
 *   discussion_board_articles.id; if article not found, return 404.
 * - Request body (IDiscussionBoardComment.IRequest) provides pagination (page,
 *   limit), optional search string (search), optional filters (authorId,
 *   parentCommentId, includeThreaded boolean), and sorting instructions (sort =
 *   createdAt or -createdAt). Default sorting is created_at desc. Page/limit
 *   defaults must be applied server-side and limited to sensible maxima.
 * - Comments with deleted_at != NULL are excluded from results. Comments with
 *   is_hidden = true are excluded for public callers.
 *
 * Related API operations:
 *
 * - GET /articles/{articleId}/comments/{commentId} — retrieve a single comment
 *   detail (useful for deep linking or comment permalinks).
 * - POST /articles/{articleId}/comments — create a new comment (writes into
 *   discussion_board_comments).
 * - PATCH /articles/{articleId}/comments — this search/list operation pairs with
 *   create/update endpoints for comment workflows.
 *
 * Expected behavior and error handling:
 *
 * - On malformed UUIDs or invalid request schemas, return 400 with validation
 *   details.
 * - On non-existent articleId, return 404.
 * - If filtering or search yields no results, return an empty data array with
 *   pagination metadata.
 * - If moderation service or search index is degraded, return either degraded
 *   results with a clear warning in response metadata or a 503 when listing
 *   cannot be safely served.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article (UUID) used to
 *   scope comment listing to a specific article
 * @param props.body Comment list request including pagination, optional
 *   full-text search over content, and filters (authorId, parentCommentId,
 *   isHidden for moderators).
 * @path /discussionBoard/articles/:articleId/comments
 * @accessor api.functional.discussionBoard.articles.comments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
