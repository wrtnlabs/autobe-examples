/**
 * Search and retrieve a filtered, paginated list of DiscussionBoard articles.
 *
 * Purpose and overview: This operation provides powerful search and listing
 * capabilities for `discussion_board_articles`. It supports fuzzy search on
 * title/content using trigram indexes, tag and category filtering (via
 * discussion_board_article_tags and discussion_board_tags), author scoping,
 * state filtering, pinned ordering, date-range filtering, pagination and
 * sorting.
 *
 * Security and permissions: Public (unauthenticated) callers must only receive
 * publicly-visible articles: `state = 'published'`, `deleted_at IS NULL`, and
 * `state != 'hidden'`. Authenticated calls by moderators or admins may request
 * additional states (pending_review, hidden) subject to RBAC checks implemented
 * by the service layer.
 *
 * Validation and business logic:
 *
 * - Request DTO must validate pagination parameters and enforce server-side
 *   maxLimit to prevent large responses.
 * - Tag filters may be provided as tag slugs and must be resolved via
 *   `discussion_board_tags` → `discussion_board_article_tags` joins.
 * - The response is paginated (IPageIDiscussionBoardArticle.ISummary) and
 *   includes summary items (id, title, excerpt, author summary, isPinned,
 *   publishedAt, hasAttachments).
 *
 * Error handling:
 *
 * - 400 for malformed requests or exceeding allowed limits.
 * - 200 with empty data array for no results.
 * - 500 for transient backend errors.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for article
 *   filtering
 * @path /discussionBoard/articles
 * @accessor api.functional.discussionBoard.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for article filtering */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/articles";
  export const random = (): IPageIDiscussionBoardArticle.ISummary =>
    typia.random<IPageIDiscussionBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
