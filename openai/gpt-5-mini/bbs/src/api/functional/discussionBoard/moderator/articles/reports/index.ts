/**
 * Search and retrieve paginated reports for a specific article (moderator
 * only).
 *
 * Purpose and overview: This operation provides a flexible search and
 * pagination interface to retrieve reports that target a specific article. The
 * underlying Prisma entity is discussion_board_reports. This endpoint filters
 * reports where target_type = 'article' and target_id = the given articleId and
 * supports additional request-scoped filters passed in the request body.
 *
 * Security considerations and user permissions: Only moderator actors should
 * access this endpoint because returned data may contain reporter identities
 * and free-text explanations. The implementation must enforce moderator
 * authorization and log access for audit purposes. Reporter session IPs and
 * other session-level sensitive fields are redacted by default; inclusion
 * requires elevated audit privileges.
 *
 * Relationship to underlying database entities: The response is derived from
 * the discussion_board_reports table and may aggregate counts for automated
 * thresholds. The operation does not modify the reports table. Returned
 * summaries should include: id, reporter_member_id, reason_category, status,
 * created_at, processed_at and explanationExcerpt. Full explanation text may be
 * returned only with appropriate moderator-level access.
 *
 * Validation rules and business logic:
 *
 * - ArticleId must be a UUID corresponding to an existing
 *   discussion_board_articles.id.
 * - Request body may include filters: status (enum), reasonCategory,
 *   reporterMemberId (UUID), createdFrom/createdTo (ISO 8601),
 *   processedFrom/processedTo (ISO 8601), search (string), sort, page and
 *   limit.
 * - Pagination defaults: page=1, limit=20, max limit=100. Results include
 *   pagination metadata (total, page, limit).
 * - Implement query timeouts for heavy text searches and respect moderation
 *   endpoint rate limits.
 *
 * Expected behavior and error handling:
 *
 * - 200 OK with a paginated summary of matching reports.
 * - 400 Bad Request for invalid filter values or paging parameters.
 * - 401 Unauthorized if not authenticated.
 * - 403 Forbidden if authenticated but not a moderator.
 * - 404 Not Found if the articleId does not reference an existing article.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article (UUID)
 * @param props.body Search and pagination parameters for retrieving reports
 *   targeting the specified article. Fields may include status, reasonCategory,
 *   reporterMemberId, createdFrom, createdTo, processedFrom, processedTo,
 *   search (free-text), page and limit.
 * @path /discussionBoard/moderator/articles/:articleId/reports
 * @accessor api.functional.discussionBoard.moderator.articles.reports.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target article (UUID) */
    articleId: string & tags.Format<"uuid">;

    /**
     * Search and pagination parameters for retrieving reports targeting the
     * specified article. Fields may include status, reasonCategory,
     * reporterMemberId, createdFrom, createdTo, processedFrom, processedTo,
     * search (free-text), page and limit.
     */
    body: IDiscussionBoardReport.IRequest;
  };
  export type Body = IDiscussionBoardReport.IRequest;
  export type Response = IPageIDiscussionBoardReport.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/articles/:articleId/reports",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/articles/${encodeURIComponent(props.articleId ?? "null")}/reports`;
  export const random = (): IPageIDiscussionBoardReport.ISummary =>
    typia.random<IPageIDiscussionBoardReport.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
