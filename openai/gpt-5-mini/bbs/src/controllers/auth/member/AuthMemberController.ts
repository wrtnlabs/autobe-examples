import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthMemberJoin } from "../../../providers/postAuthMemberJoin";
import { postAuthMemberLogin } from "../../../providers/postAuthMemberLogin";
import { postAuthMemberRefresh } from "../../../providers/postAuthMemberRefresh";

import { IDiscussionBoardMember } from "../../../api/structures/IDiscussionBoardMember";

@Controller("/auth/member")
export class AuthMemberController {
  /**
   * Register a new member (discussion_board_member).
   *
   * Purpose and overview: This endpoint registers a new discussionBoard member
   * by creating a row in the Prisma table discussion_board_member. It accepts
   * the required registration fields (username, email, password) and optional
   * profile fields (display_name). On successful registration the service MUST
   * store a password hash into discussion_board_member.password_hash and
   * persist created_at/updated_at timestamps per the schema.
   *
   * Implementation details and referenced schema fields: The implementation
   * MUST write to discussion_board_member (columns: username, email,
   * password_hash, display_name, role, mfa_enabled, created_at, updated_at).
   * The registration flow SHOULD set role to a default application value (e.g.,
   * "USER") and mfa_enabled to false unless otherwise configured. The operation
   * also creates a verification token row in
   * discussion_board_email_verifications (token, discussion_board_member_id,
   * created_at, expires_at) to support the email verification workflow.
   *
   * Actor-specific integration and business context: This operation is public
   * (no existing authentication required) and targets the "member" actor type.
   * Because discussion_board_member.email and discussion_board_member.username
   * are unique in the schema, the operation MUST fail with a 409 conflict when
   * those uniqueness constraints are violated and return an explanatory error
   * message.
   *
   * Security considerations and validation rules: Passwords MUST never be
   * persisted in plain text—the field discussion_board_member.password_hash
   * must contain a securely hashed password (application responsibility). Input
   * validation MUST enforce well-formed email addresses and the uniqueness
   * constraints represented in the schema. The operation MUST NOT return
   * password_hash in responses.
   *
   * Related operations and workflow integration: After successful join, callers
   * typically call POST /auth/member/login to authenticate or follow the email
   * verification flow implemented by POST /auth/member/email/verify which
   * consumes discussion_board_email_verifications.token. The refresh operation
   * (POST /auth/member/refresh) may be used later to renew tokens.
   *
   * @param connection
   * @param body Registration payload for creating a new
   *   discussion_board_member. Fields map to discussion_board_member columns:
   *   username, email, password (hashed server-side), display_name (optional).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardMember.IJoin,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postAuthMemberJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate member and issue tokens (discussion_board_member).
   *
   * Purpose and overview: This endpoint authenticates a discussionBoard member
   * by validating credentials against the discussion_board_member table
   * (matching username or email to the stored password_hash). On success it
   * issues authorization material (access and refresh tokens) and creates a
   * member session row in discussion_board_member_sessions that records ip,
   * href, referrer, created_at and an optional expired_at.
   *
   * Implementation details and referenced schema fields: The service MUST
   * consult discussion_board_member.password_hash to validate the supplied
   * password and MUST record a new discussion_board_member_sessions row
   * (fields: discussion_board_member_id, ip, href, referrer, created_at,
   * expired_at) for session management. The login flow should not expose
   * password_hash in any response and must respect uniqueness constraints on
   * email/username.
   *
   * Actor-specific integration and business context: This operation is public
   * and intended to return token sets usable for protected endpoints associated
   * with the "member" actor. The session record links back to the
   * discussion_board_member.id enabling subsequent session revocation and
   * refresh behaviors.
   *
   * Security considerations and validation rules: Implementers MUST enforce
   * lockout thresholds at the authentication layer (see business requirements)
   * and log authentication events to discussion_board_audit_logs. The operation
   * MUST rate-limit and avoid leaking whether an email exists to callers.
   *
   * Related operations and workflow integration: After login, clients will use
   * POST /auth/member/refresh to renew access tokens based on refresh semantics
   * and may call protected endpoints that require an authenticated member.
   * Password reset or MFA flows (discussion_board_password_resets and
   * mfa_enabled on discussion_board_member) integrate with this operation for
   * step-up authentication.
   *
   * @param connection
   * @param body Login payload with credential (usernameOrEmail) and password.
   *   Caller may also supply device/context info used to populate
   *   discussion_board_member_sessions.ip, href, and referrer.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardMember.ILogin,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postAuthMemberLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh member access tokens (discussion_board_member_sessions).
   *
   * Purpose and overview: This endpoint refreshes short-lived access
   * credentials for a member using refresh tokens or session references. It
   * must validate refresh token integrity and verify the underlying
   * discussion_board_member_sessions row (if sessions are used to back refresh
   * tokens) is valid and not expired (expired_at).
   *
   * Implementation details and referenced schema fields: Implementers MAY
   * persist refresh metadata in discussion_board_member_sessions.expired_at or
   * in an associated storage; the operation MUST consult
   * discussion_board_member_sessions (fields: discussion_board_member_id, ip,
   * href, referrer, created_at, expired_at) to determine session validity and
   * to optionally rotate session expiration. The operation interacts with
   * discussion_board_member.id to ensure the actor is still active (deleted_at
   * null).
   *
   * Actor-specific integration and business context: Clients call this endpoint
   * when the access token lifetime elapses and they hold a valid refresh
   * credential. Because the Prisma schema includes
   * discussion_board_member_sessions, this operation should update or create
   * session rows to reflect sliding expiration behavior and to support
   * revocation by administrators or users.
   *
   * Security considerations and validation rules: Refresh requests MUST
   * validate token signatures and check session expiry. If the member record
   * indicates deleted_at is set, the refresh MUST be denied. Refresh operations
   * MUST be logged for audit and cause session rotation per security policy.
   *
   * Related operations and workflow integration: This endpoint complements POST
   * /auth/member/login and revocation endpoints (DELETE
   * /auth/member/sessions/{sessionId}) which operate against
   * discussion_board_member_sessions. Successful refresh returns a structure
   * consistent with IDiscussionBoardMember.IAuthorized.
   *
   * @param connection
   * @param body Refresh request containing the refresh token or session
   *   identifier used to obtain a new access token. Server interprets and
   *   validates token against session state.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardMember.IRefresh,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
