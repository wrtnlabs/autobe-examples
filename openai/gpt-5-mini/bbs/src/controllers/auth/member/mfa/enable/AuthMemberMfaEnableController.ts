import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthMemberMfaEnable } from "../../../../../providers/postAuthMemberMfaEnable";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";

import { IDiscussionBoardMember } from "../../../../../api/structures/IDiscussionBoardMember";

@Controller("/auth/member/mfa/enable")
export class AuthMemberMfaEnableController {
  /**
   * Enable two-factor authentication (member.mfa_enabled).
   *
   * Purpose and overview: This protected endpoint enables MFA for the
   * authenticated member by setting discussion_board_member.mfa_enabled = true
   * and returning any required setup artifact (QR code or secret). The
   * discussion_board_member.mfa_enabled boolean in the Prisma schema directly
   * indicates whether MFA is active for the account.
   *
   * Implementation details and referenced schema fields: The operation MUST
   * update discussion_board_member.mfa_enabled and persist updated_at. If the
   * service issues a TOTP secret or device registration artifact, that secret
   * should be stored securely (outside the visible member profile) and not
   * returned in plain text except as a time-limited enrollment token or QR
   * image. The schema provides mfa_enabled to represent enrollment state.
   *
   * Actor-specific integration and business context: This endpoint is protected
   * and must be callable only by the authenticated member (authorizationActor:
   * "member"). Enabling MFA typically requires a subsequent verification step
   * at login (step-up) and ties into the login flow described earlier.
   *
   * Security considerations and validation rules: Store MFA secrets under
   * strong encryption and record enabling events in
   * discussion_board_audit_logs. Do not expose persistent secrets in API
   * responses. The endpoint SHOULD require recent re-authentication or step-up
   * if the session is old.
   *
   * Related operations and workflow integration: Related APIs: POST
   * /auth/member/login (may require second-factor when mfa_enabled is true),
   * POST /auth/member/mfa/disable, and audit log entries in
   * discussion_board_moderation_audit or discussion_board_audit_logs for
   * enrollment events.
   *
   * @param connection
   * @param body Optional payload to initiate MFA enrollment; server may respond
   *   with an enrollment artifact (QR/secret) and will set
   *   discussion_board_member.mfa_enabled on successful enrollment.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async enableTwoFactor(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardMember.IEnableTwoFactor,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await postAuthMemberMfaEnable({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
