import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getAuthMemberSessions } from "../../../../providers/getAuthMemberSessions";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteAuthMemberSessionsSessionId } from "../../../../providers/deleteAuthMemberSessionsSessionId";

import { IDiscussionBoardMember } from "../../../../api/structures/IDiscussionBoardMember";

@Controller("/auth/member/sessions")
export class AuthMemberSessionsController {
  /**
   * List member sessions (discussion_board_member_sessions).
   *
   * Purpose and overview: This protected endpoint retrieves session records for
   * the authenticated member from discussion_board_member_sessions. It returns
   * session metadata (ip, href, referrer, created_at, expired_at) so members
   * can review and revoke sessions they do not recognize.
   *
   * Implementation details and referenced schema fields: The operation queries
   * discussion_board_member_sessions where discussion_board_member_id equals
   * the authenticated member id and returns rows with fields: id, ip, href,
   * referrer, created_at, expired_at. The session table's composite index on
   * discussion_board_member_id and created_at supports efficient retrieval.
   *
   * Actor-specific integration and business context: This endpoint requires the
   * "member" actor to be authenticated and provides account security tooling
   * (show active sessions and allow targeted revocation). The schema supports
   * session expiry via expired_at and session listing for lifecycle
   * management.
   *
   * Security considerations and validation rules: Access to this endpoint must
   * be restricted to the authenticated owner (authorizationActor: "member").
   * Responses MUST not leak sensitive internal token values—only use session
   * identifiers and metadata for revocation operations.
   *
   * Related operations and workflow integration: Related APIs: DELETE
   * /auth/member/sessions/{sessionId} to revoke a specific session, POST
   * /auth/member/refresh to rotate session expirations, and audit logging in
   * discussion_board_audit_logs for session revocation events.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async listSessions(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IDiscussionBoardMember.ISessionsPage> {
    try {
      return await getAuthMemberSessions({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Revoke a member session (discussion_board_member_sessions).
   *
   * Purpose and overview: This protected endpoint revokes a member session by
   * removing or marking expired the discussion_board_member_sessions row
   * referenced by id. It is used to immediately invalidate refresh semantics
   * tied to that session and prevent further token refreshes for that session.
   *
   * Implementation details and referenced schema fields: The operation targets
   * discussion_board_member_sessions.id and either deletes the row or sets
   * expired_at to the current timestamp in accordance with application
   * retention policies. It must verify that the caller is the owning
   * discussion_board_member_id (or has administrative privileges) before taking
   * action.
   *
   * Actor-specific integration and business context: The endpoint requires the
   * "member" actor for owner-initiated revocation; administrators may revoke
   * others' sessions per role. After revocation the system SHOULD log the
   * action in discussion_board_audit_logs for traceability and may create a
   * discussion_board_notification for the account owner.
   *
   * Security considerations and validation rules: The operation MUST check
   * ownership and ensure revocation is auditable. If the session does not exist
   * the endpoint should return 404. If the caller is not authorized to revoke
   * the session it should return 403.
   *
   * Related operations and workflow integration: Related APIs: GET
   * /auth/member/sessions to enumerate sessions, POST /auth/member/refresh to
   * obtain new tokens, and authentication endpoints that check session presence
   * during refresh.
   *
   * @param connection
   * @param sessionId Target session's ID (discussion_board_member_sessions.id)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async eraseSession(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteAuthMemberSessionsSessionId({
        member,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
