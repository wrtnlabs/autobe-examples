import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { putAuthMemberPasswordChange } from "../../../../../providers/putAuthMemberPasswordChange";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";

import { IDiscussionBoardMember } from "../../../../../api/structures/IDiscussionBoardMember";

@Controller("/auth/member/password/change")
export class AuthMemberPasswordChangeController {
  /**
   * Change password (protected, member).
   *
   * Purpose and overview: This protected endpoint enables an authenticated
   * member to change their password. It reads
   * discussion_board_member.password_hash to validate the current password and
   * then updates discussion_board_member.password_hash with the new hash on
   * success.
   *
   * Implementation details and referenced schema fields: The operation MUST
   * verify the caller is authenticated as the discussion_board_member.id in
   * question, compare the provided current password against
   * discussion_board_member.password_hash, and update the password_hash field.
   * It SHOULD also set updated_at on the member row and revoke active sessions
   * by updating discussion_board_member_sessions.expired_at when users request
   * "revoke all sessions" as part of the change.
   *
   * Actor-specific integration and business context: This operation requires
   * the actor to be "member" and the request will be authorized using the
   * member's JWT. It ties directly to the session model
   * (discussion_board_member_sessions) when revocation or session invalidation
   * is required after a password change.
   *
   * Security considerations and validation rules: New passwords MUST meet
   * policy constraints (length and character-class rules from business
   * requirements). After changing the password the service SHOULD invalidate
   * active refresh tokens or set discussion_board_member_sessions.expired_at to
   * force re-authentication.
   *
   * Related operations and workflow integration: Related APIs: POST
   * /auth/member/password/request (if the user cannot recall current password),
   * POST /auth/member/login, and DELETE /auth/member/sessions/{sessionId} for
   * session revocation.
   *
   * @param connection
   * @param body Payload containing currentPassword and newPassword. The service
   *   will verify the current password against
   *   discussion_board_member.password_hash and update the stored hash on
   *   success.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async changePassword(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardMember.IChangePassword,
  ): Promise<void> {
    try {
      return await putAuthMemberPasswordChange({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
