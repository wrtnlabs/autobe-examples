import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getAuthModeratorSessions } from "../../../../providers/getAuthModeratorSessions";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { deleteAuthModeratorSessionsSessionId } from "../../../../providers/deleteAuthModeratorSessionsSessionId";

import { IDiscussionBoardModerator } from "../../../../api/structures/IDiscussionBoardModerator";

@Controller("/auth/moderator/sessions")
export class AuthModeratorSessionsController {
  /**
   * List moderator's active sessions (reads
   * discussion_board_moderator_sessions).
   *
   * Purpose and overview: Return a paginated list of session records belonging
   * to the authenticated moderator. This operation reads
   * discussion_board_moderator_sessions and exposes id, ip, href, referrer,
   * created_at and expired_at for each session row.
   *
   * Implementation details and field usage: The implementation queries
   * discussion_board_moderator_sessions filtered by
   * discussion_board_moderator_id = authenticated moderator id, orders by
   * created_at desc, and returns pagination metadata. The session records
   * include created_at and expired_at to allow clients to show session age and
   * expiry.
   *
   * Actor-specific integration and business context: Moderators may use this
   * endpoint to inspect active sessions across devices and locations; session
   * records map directly to the discussion_board_moderator_sessions model,
   * enabling re-use of existing fields for UI and audit purposes.
   *
   * Security considerations within schema constraints: This endpoint is
   * protected and returns only the sessions for the authenticated moderator. Do
   * not expose other moderators' sessions. Access should be recorded in
   * discussion_board_audit_logs or discussion_board_audit_log_accesses when
   * required for compliance.
   *
   * Related operations and workflow integration: Clients often call this
   * endpoint after login or when managing sessions. It pairs with the
   * eraseSession operation to revoke individual sessions recorded in
   * discussion_board_moderator_sessions.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async listSessions(
    @ModeratorAuth()
    moderator: ModeratorPayload,
  ): Promise<IDiscussionBoardModerator.ISessionsPage> {
    try {
      return await getAuthModeratorSessions({
        moderator,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Revoke a specific moderator session by id (modifies
   * discussion_board_moderator_sessions).
   *
   * Purpose and overview: Allow an authenticated moderator to revoke a specific
   * session by id. This operation targets discussion_board_moderator_sessions
   * and either deletes the row or sets expired_at to the current time to
   * invalidate the session.
   *
   * Implementation details and field usage: The implementation locates
   * discussion_board_moderator_sessions.id = {sessionId} and verifies the
   * session.discussion_board_moderator_id equals the authenticated moderator
   * id. On success it either deletes the row or updates expired_at to revoke
   * the session. The operation should record the revocation in
   * discussion_board_audit_logs for traceability.
   *
   * Actor-specific integration and business context: This operation is intended
   * for per-session session management: a moderator may revoke lost device
   * sessions or terminate other active connections. Because the sessions table
   * includes ip, href and referrer, the UI can display contextual details to
   * help the moderator identify the correct session to revoke.
   *
   * Security considerations within schema constraints: Only the session owner
   * (or an administrator acting via separate admin APIs) may revoke a session.
   * The operation must not allow revoking sessions belonging to other
   * moderators. After revocation, clients depending on that session must fail
   * authentication and require re-login.
   *
   * Related operations and workflow integration: This complements listSessions
   * and changePassword flows. When a password change occurs, implementations
   * SHOULD revoke all sessions (bulk revoke) and this endpoint allows targeted
   * revocation.
   *
   * @param connection
   * @param sessionId Target session's ID
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async eraseSession(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardModerator.ISessionErasedResult> {
    try {
      return await deleteAuthModeratorSessionsSessionId({
        moderator,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
