import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthModeratorPasswordChange } from "../../../../../providers/postAuthModeratorPasswordChange";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IDiscussionBoardModerator } from "../../../../../api/structures/IDiscussionBoardModerator";

@Controller("/auth/moderator/password/change")
export class AuthModeratorPasswordChangeController {
  /**
   * Change current moderator's password (updates
   * discussion_board_moderator.password_hash and revokes sessions).
   *
   * Purpose and overview: Allow an authenticated moderator to change their
   * account password. This operation targets discussion_board_moderator and
   * updates the password_hash column after validating the current password.
   *
   * Implementation details and field usage: The operation looks up the
   * moderator row by authenticated actor id, verifies the provided current
   * password against discussion_board_moderator.password_hash, and replaces the
   * stored hash with the new password_hash. The updated_at field on
   * discussion_board_moderator should be updated to reflect the change and
   * deleted_at must be considered to ensure suspended accounts cannot change
   * passwords.
   *
   * Actor-specific integration and business context: Because the Prisma schema
   * stores password_hash in discussion_board_moderator, the system can
   * implement a secure change-password flow without additional DB objects. The
   * operation should also revoke existing sessions in
   * discussion_board_moderator_sessions (set expired_at or remove rows) to
   * enforce re-authentication across devices after password change.
   *
   * Security considerations within schema constraints: Never return
   * password_hash in responses. After changing the password the implementation
   * MUST invalidate existing sessions recorded in
   * discussion_board_moderator_sessions to prevent session fixation. Record a
   * discussion_board_audit_logs entry capturing the password change event for
   * compliance.
   *
   * Related operations and workflow integration: This operation complements
   * login and session-management endpoints. There is no moderator-specific
   * password reset model in the schema, so password reset via email is not
   * generated for moderator actor by this interface.
   *
   * @param connection
   * @param body Change password payload (currentPassword, newPassword).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async changePassword(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardModerator.IChangePassword,
  ): Promise<IDiscussionBoardModerator> {
    try {
      return await postAuthModeratorPasswordChange({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
