import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { getDiscussionBoardMembersMemberUsername } from "../../../providers/getDiscussionBoardMembersMemberUsername";
import { putDiscussionBoardMembersMemberUsername } from "../../../providers/putDiscussionBoardMembersMemberUsername";
import { MemberAuth } from "../../../decorators/MemberAuth";
import { MemberPayload } from "../../../decorators/payload/MemberPayload";

import { IDiscussionBoardMember } from "../../../api/structures/IDiscussionBoardMember";

@Controller("/discussionBoard/members/:memberUsername")
export class DiscussionboardMembersController {
  /**
   * Retrieve public member profile by username (DiscussionBoardMember).
   *
   * Retrieve a member's public profile by their unique username. This read-only
   * operation returns a sanitized summary view derived from the
   * discussion_board_member table suitable for public display.
   *
   * Security and permissions: This endpoint is public and requires no
   * authentication. The service MUST exclude sensitive fields (password_hash,
   * email, role, mfa_enabled) from the public response. For richer,
   * authenticated views use a separate authenticated endpoint (for example GET
   * /me).
   *
   * Database relationship and validation: This operation reads the
   * discussion_board_member model using the unique username index
   * (@@unique([username])). The path parameter memberUsername is a global
   * unique business identifier. The service MUST return 404 if the member is
   * not found or if discussion_board_member.deleted_at is not null
   * (soft-deleted).
   *
   * Error handling: Return 404 for not found. Return standard 5xx responses for
   * server errors. Ensure returned timestamps are ISO 8601 (UTC).
   *
   * @param connection
   * @param memberUsername Unique username of the target member (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("memberUsername")
    memberUsername: string,
  ): Promise<IDiscussionBoardMember.ISummary> {
    try {
      return await getDiscussionBoardMembersMemberUsername({
        memberUsername,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a member's profile (self-service).
   *
   * Allows a member to update their own profile information. The operation
   * updates the discussion_board_member record identified by the unique
   * username path parameter. Updatable fields are limited to display_name and
   * password. Passwords are supplied in plaintext in the request, MUST be
   * validated for strength (minimum 12 characters and at least three categories
   * among uppercase, lowercase, number, symbol), and MUST be hashed server-side
   * before persisting to password_hash. The service MUST NOT accept
   * password_hash or allow clients to set created_at/updated_at/deleted_at.
   *
   * Security and authorization: This endpoint requires authentication and
   * enforces ownership: the authenticated actor must be the member identified
   * by {memberUsername} or possess administrative privileges. If the caller is
   * not authorized, return 403. On successful password change, revoke active
   * refresh tokens per security policy and write an audit log entry (without
   * including raw passwords).
   *
   * Database relationship and validation: Validate that the target member
   * exists and is not soft-deleted (deleted_at is null). Map request DTO
   * IDiscussionBoardMember.IUpdate to the persisted fields, disallowing any
   * direct write to password_hash. Return the sanitized updated member
   * representation (do not include password_hash).
   *
   * @param connection
   * @param memberUsername Unique username of the target member (global scope)
   * @param body Editable member fields (IDiscussionBoardMember.IUpdate).
   *   Allowed properties: displayName (string) and password (string,
   *   plaintext). Password must meet strength rules and will be hashed
   *   server-side.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("memberUsername")
    memberUsername: string,
    @TypedBody()
    body: IDiscussionBoardMember.IUpdate,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await putDiscussionBoardMembersMemberUsername({
        member,
        memberUsername,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
