import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getDiscussionBoardArticlesArticleIdCommentsCommentIdAttachmentsAttachmentId } from "../../../../../providers/getDiscussionBoardArticlesArticleIdCommentsCommentIdAttachmentsAttachmentId";

import { IDiscussionBoardCommentAttachment } from "../../../../../api/structures/IDiscussionBoardCommentAttachment";

@Controller(
  "/discussionBoard/articles/:articleId/comments/:commentId/attachments/:attachmentId",
)
export class DiscussionboardArticlesCommentsAttachmentsController {
  /**
   * Get metadata for a comment attachment
   * (discussion_board_comment_attachments).
   *
   * Retrieve metadata for a single comment attachment from the
   * discussion_board_comment_attachments table.
   *
   * Returns metadata required for UI previews and for obtaining a download
   * reference from object storage. The returned fields (per Prisma model)
   * include: id, discussion_board_comment_id, discussion_board_uploaded_by_id
   * (nullable), original_filename, storage_key (internal) or downloadUrl
   * (signed URL for public use), mime_type, size, is_image, quarantined, and
   * created_at.
   *
   * Security and visibility: If the attachment is quarantined or the parent
   * comment/article is hidden/deleted, the implementation must return 403 or
   * 404 according to policy. Public responses MUST NOT include raw internal
   * `storage_key`; instead provide an expiring `downloadUrl` (signed) or
   * `cdnUrl`. Moderator/internal consumers may receive `storage_key` when
   * authorized.
   *
   * This operation does not stream binary content — it returns metadata only.
   * Use returned metadata to request a signed download URL or to initiate a
   * proxied download flow.
   *
   * @param connection
   * @param articleId UUID of the target article to validate hierarchical
   *   context (ensures comment belongs to article).
   * @param commentId UUID of the target comment to validate hierarchical
   *   context.
   * @param attachmentId UUID of the attachment to retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardCommentAttachment> {
    try {
      return await getDiscussionBoardArticlesArticleIdCommentsCommentIdAttachmentsAttachmentId(
        {
          articleId,
          commentId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
