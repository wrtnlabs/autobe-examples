import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardArticles } from "../../../providers/patchDiscussionBoardArticles";

import { IPageIDiscussionBoardArticle } from "../../../api/structures/IPageIDiscussionBoardArticle";
import { IDiscussionBoardArticle } from "../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/articles")
export class DiscussionboardArticlesController {
  /**
   * Search and retrieve a filtered, paginated list of DiscussionBoard articles.
   *
   * Purpose and overview: This operation provides powerful search and listing
   * capabilities for `discussion_board_articles`. It supports fuzzy search on
   * title/content using trigram indexes, tag and category filtering (via
   * discussion_board_article_tags and discussion_board_tags), author scoping,
   * state filtering, pinned ordering, date-range filtering, pagination and
   * sorting.
   *
   * Security and permissions: Public (unauthenticated) callers must only
   * receive publicly-visible articles: `state = 'published'`, `deleted_at IS
   * NULL`, and `state != 'hidden'`. Authenticated calls by moderators or admins
   * may request additional states (pending_review, hidden) subject to RBAC
   * checks implemented by the service layer.
   *
   * Validation and business logic:
   *
   * - Request DTO must validate pagination parameters and enforce server-side
   *   maxLimit to prevent large responses.
   * - Tag filters may be provided as tag slugs and must be resolved via
   *   `discussion_board_tags` → `discussion_board_article_tags` joins.
   * - The response is paginated (IPageIDiscussionBoardArticle.ISummary) and
   *   includes summary items (id, title, excerpt, author summary, isPinned,
   *   publishedAt, hasAttachments).
   *
   * Error handling:
   *
   * - 400 for malformed requests or exceeding allowed limits.
   * - 200 with empty data array for no results.
   * - 500 for transient backend errors.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for article filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
