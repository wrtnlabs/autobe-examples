import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardMemberMembersMemberUsernameNotificationsNotificationIdFailures } from "../../../../../../providers/patchDiscussionBoardMemberMembersMemberUsernameNotificationsNotificationIdFailures";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { getDiscussionBoardMemberMembersMemberUsernameNotificationsNotificationIdFailuresAttemptNumber } from "../../../../../../providers/getDiscussionBoardMemberMembersMemberUsernameNotificationsNotificationIdFailuresAttemptNumber";

import { IPageIDiscussionBoardNotificationFailure } from "../../../../../../api/structures/IPageIDiscussionBoardNotificationFailure";
import { IDiscussionBoardNotificationFailure } from "../../../../../../api/structures/IDiscussionBoardNotificationFailure";

@Controller(
  "/discussionBoard/member/members/:memberUsername/notifications/:notificationId/failures",
)
export class DiscussionboardMemberMembersNotificationsFailuresController {
  /**
   * List delivery failure records for a member's notification.
   *
   * Purpose and overview:
   *
   * Retrieve a filtered and paginated list of delivery failure records related
   * to a single notification (discussion_board_notifications) for the specified
   * member. Each returned item maps to a row in the
   * discussion_board_notification_failures table and contains the
   * attempt_number, attempted_at, error_code, error_message, backoff_until and
   * created_at fields. This endpoint is intended for diagnostics by the member
   * or support staff to inspect why a notification delivery failed.
   *
   * Security and permissions:
   *
   * Only the member who owns the notification (identified by memberUsername) or
   * an authorized support/administrator role should be allowed to inspect these
   * failure records. The controller must verify that the notification
   * (discussion_board_notifications.id) is associated with the member
   * (discussion_board_notifications.recipient_member_id ->
   * discussion_board_member.id) that matches the provided memberUsername, or
   * that the caller holds appropriate elevated privileges. JWT-based
   * authentication and role checks are expected to be enforced by the API
   * layer.
   *
   * Relationship to database entities:
   *
   * This operation queries discussion_board_notification_failures with
   * discussion_board_notification_id equal to the notificationId path
   * parameter. Use the composite unique constraint
   *
   * @param connection
   * @param memberUsername Unique username of the target member (global scope)
   * @param notificationId Unique identifier (UUID) of the target notification
   *   (discussion_board_notifications.id)
   * @param body Search, filtering and pagination parameters for notification
   *   failure records scoped to the notificationId. Fields include page (int),
   *   limit (int), sort (string, e.g., 'attempted_at' or '-attempted_at'),
   *   attemptNumberFrom (int), attemptNumberTo (int), attemptedAtFrom (string,
   *   date-time), attemptedAtTo (string, date-time), createdAtFrom (string,
   *   date-time), createdAtTo (string, date-time), errorCode (string),
   *   errorMessageQuery (string for full-text search).
   * @@unique([discussion_board_notification_id,
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("memberUsername")
    memberUsername: string,
    @TypedParam("notificationId")
    notificationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardNotificationFailure.IRequest,
  ): Promise<IPageIDiscussionBoardNotificationFailure.ISummary> {
    try {
      return await patchDiscussionBoardMemberMembersMemberUsernameNotificationsNotificationIdFailures(
        {
          member,
          memberUsername,
          notificationId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get a specific delivery failure entry for a notification.
   *
   * Purpose and overview:
   *
   * Return the detailed delivery failure record for a specific attempt
   * (attemptNumber) of a given notification. Useful for members or support
   * staff to view the exact error and timing captured in
   * discussion_board_notification_failures for one delivery attempt.
   *
   * Security and permissions:
   *
   * Access is restricted to the member owning the notification (memberUsername)
   * or authorized support/administration roles. The controller must verify
   * ownership by resolving discussion_board_notifications.recipient_member_id
   * to the discussion_board_member record matching memberUsername, or validate
   * the caller's elevated privileges.
   *
   * Relationship to database entities:
   *
   * This operation reads from discussion_board_notification_failures and uses
   * the composite unique constraint
   *
   * @param connection
   * @param memberUsername Unique username of the target member (global scope)
   * @param notificationId Unique identifier (UUID) of the target notification
   *   (discussion_board_notifications.id)
   * @param attemptNumber Sequential attempt number of the notification failure
   *   scoped to the notification
   * @@unique([discussion_board_notification_id,
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":attemptNumber")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("memberUsername")
    memberUsername: string,
    @TypedParam("notificationId")
    notificationId: string & tags.Format<"uuid">,
    @TypedParam("attemptNumber")
    attemptNumber: number & tags.Type<"int32"> & tags.Minimum<1>,
  ): Promise<IDiscussionBoardNotificationFailure> {
    try {
      return await getDiscussionBoardMemberMembersMemberUsernameNotificationsNotificationIdFailuresAttemptNumber(
        {
          member,
          memberUsername,
          notificationId,
          attemptNumber,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
