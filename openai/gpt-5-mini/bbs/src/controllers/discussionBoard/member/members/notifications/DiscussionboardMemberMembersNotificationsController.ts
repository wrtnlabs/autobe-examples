import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardMemberMembersMemberUsernameNotifications } from "../../../../../providers/patchDiscussionBoardMemberMembersMemberUsernameNotifications";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getDiscussionBoardMemberMembersMemberUsernameNotificationsNotificationId } from "../../../../../providers/getDiscussionBoardMemberMembersMemberUsernameNotificationsNotificationId";

import { IPageIDiscussionBoardNotification } from "../../../../../api/structures/IPageIDiscussionBoardNotification";
import { IDiscussionBoardNotification } from "../../../../../api/structures/IDiscussionBoardNotification";

@Controller("/discussionBoard/member/members/:memberUsername/notifications")
export class DiscussionboardMemberMembersNotificationsController {
  /**
   * Search and bulk-manage notifications for a member.
   *
   * Retrieve and perform bulk operations on a member's notifications. This
   * operation provides advanced search, filtering, sorting and bulk mutation
   * capabilities for notifications tied to a member. It is implemented against
   * the discussion_board_notifications table as defined in the Prisma schema
   * and returns paginated summary entries optimized for list displays.
   *
   * Security and permissions: This endpoint requires authentication and that
   * the authenticated actor either be the member identified by {memberUsername}
   * or have appropriate administrative privileges. Server-side logic MUST
   * verify member ownership by resolving the provided username to
   * discussion_board_member.id and matching notifications by
   * discussion_board_notifications.recipient_member_id. Audit-write actions
   * (bulk modifications) SHOULD create appropriate audit entries in
   * discussion_board_audit_logs. For list results the ISummary type SHOULD NOT
   * include full `payload` content to avoid accidental PII exposure; include
   * only sanitized excerpt or a hasPayload flag in the summary.
   *
   * @param connection
   * @param memberUsername Unique username of the target member (global scope)
   * @param body Search filters, pagination parameters and optional bulk actions
   *   to perform on the matched notifications
   *   (IDiscussionBoardNotification.IRequest)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("memberUsername")
    memberUsername: string,
    @TypedBody()
    body: IDiscussionBoardNotification.IRequest,
  ): Promise<IPageIDiscussionBoardNotification.ISummary> {
    try {
      return await patchDiscussionBoardMemberMembersMemberUsernameNotifications(
        {
          member,
          memberUsername,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get a single notification for a member.
   *
   * Return full details for a single notification belonging to the specified
   * member. The response contains the complete notification record as defined
   * by the discussion_board_notifications table and is intended to support a
   * notification detail view in the client UI.
   *
   * Security: The endpoint requires authentication. The authenticated actor
   * must be the member identified by {memberUsername} or an administrator.
   * Ownership is enforced by matching notification.recipient_member_id to the
   * member id resolved from the username. Access by moderators/administrators
   * should be logged for audit purposes. Full `payload` content should be
   * returned only to authorized callers (recipient or admin) and otherwise
   * redacted.
   *
   * @param connection
   * @param memberUsername Unique username of the target member (global scope)
   * @param notificationId Unique identifier (UUID) of the notification
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":notificationId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("memberUsername")
    memberUsername: string,
    @TypedParam("notificationId")
    notificationId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardNotification> {
    try {
      return await getDiscussionBoardMemberMembersMemberUsernameNotificationsNotificationId(
        {
          member,
          memberUsername,
          notificationId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
