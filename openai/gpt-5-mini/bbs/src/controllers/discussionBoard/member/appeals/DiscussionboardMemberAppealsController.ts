import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberAppeals } from "../../../../providers/postDiscussionBoardMemberAppeals";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getDiscussionBoardMemberAppealsAppealId } from "../../../../providers/getDiscussionBoardMemberAppealsAppealId";

import { IDiscussionBoardAppeal } from "../../../../api/structures/IDiscussionBoardAppeal";

@Controller("/discussionBoard/member/appeals")
export class DiscussionboardMemberAppealsController {
  /**
   * Create a new appeal (persist to discussion_board_appeals).
   *
   * Create a new appeal submitted by a member contesting a moderation action or
   * a report.
   *
   * Purpose and overview: This endpoint creates an appeal record in the
   * discussion_board_appeals table. Appeals are an append-only business
   * artifact used to request secondary review of moderator actions or reports.
   * The appeal record stores the appellant_member_id (populated from the
   * authenticated caller), optional moderation_action_id, optional report_id,
   * the appellant-provided explanation, and a processing status 'pending'. The
   * created record is used to queue secondary review tasks for moderators and
   * to pause purge timers for the underlying content while the appeal is
   * pending.
   *
   * Security and permissions: Only authenticated members may submit appeals.
   * The API MUST authenticate the caller (requesting member) and use the
   * caller's identity as appellant_member_id. The endpoint MUST NOT accept or
   * honor an appellant_member_id in the request payload to prevent identity
   * injection. Moderation/administrative actors should not call this endpoint
   * on behalf of other members; administrative workflows exist separately.
   *
   * Relationship to the Prisma table: This operation directly maps to the
   * Prisma model discussion_board_appeals. The implementation must persist only
   * the model fields: appellant_member_id, moderation_action_id, report_id,
   * explanation, status, created_at, resolved_at, resolution_reason. Do NOT
   * invent fields not present in the model. The operation should validate
   * referenced IDs exist (when provided) and return 400 when they do not.
   *
   * Validation rules and business logic:
   *
   * - Explanation is required (<= 2000 chars as per business rules).
   * - At least one of moderation_action_id or report_id MUST be present.
   * - Status is set to 'pending' server-side and clients cannot set resolved
   *   statuses on create.
   * - Created_at is server-populated; clients must not supply created_at or
   *   resolved_at values.
   *
   * Related operations: Moderators will query appeals via PATCH
   * /discussionBoard/moderator/appeals and will resolve appeals with moderation
   * action endpoints. When an appeal is created the system should also emit a
   * moderation_audit entry and push the item onto the moderator queue for
   * handling.
   *
   * Errors and handling: 400 for validation errors (missing explanation or
   * missing referenced id), 401/403 for auth failures, 404 if referenced
   * moderation_action_id/report_id do not exist, 409 for unique-constraint
   * duplicate appeals, 500 for server errors.
   *
   * @param connection
   * @param body Appeal creation payload. Clients MUST provide: explanation
   *   (string) and at least one of moderation_action_id (uuid) or report_id
   *   (uuid). Do NOT include appellant_member_id, created_at, resolved_at or
   *   status in the payload; those are managed by the server.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardAppeal.ICreate,
  ): Promise<IDiscussionBoardAppeal> {
    try {
      return await postDiscussionBoardMemberAppeals({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a DiscussionBoard appeal by ID (discussion_board_appeals).
   *
   * Purpose and overview:
   *
   * Retrieve a single appeal record stored in the discussion_board_appeals
   * table. The appeal contains appellant_member_id, optional links to
   * moderation_action and/or report, the appellant's explanation, processing
   * status and resolution metadata. Clients use this endpoint to display appeal
   * details and timelines to the appellant and to support member-facing appeal
   * status pages.
   *
   * Security and permissions:
   *
   * This endpoint requires authentication as a member. The implementation MUST
   * enforce that a member may retrieve only their own appeals (owner check:
   * appeal.appellant_member_id === auth.memberId). Moderators should use
   * dedicated moderator endpoints to retrieve any appeal. Do not expose
   * internal audit trails in this member-facing response.
   *
   * Validation rules and error handling:
   *
   * - Validate that the path parameter appealId is a well-formed UUID; return 400
   *   for invalid format.
   * - If the appeal is not found, return 404 with an explanatory message.
   * - Enforce authorization: return 403 when an unauthorized member attempts to
   *   access another member's appeal.
   *
   * Related operations:
   *
   * - PUT /discussionBoard/moderator/appeals/{appealId} — moderator updates to
   *   appeal status and resolution metadata.
   *
   * @param connection
   * @param appealId Unique identifier (UUID) of the target appeal in the
   *   discussion_board_appeals table (UUID format)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":appealId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("appealId")
    appealId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAppeal> {
    try {
      return await getDiscussionBoardMemberAppealsAppealId({
        member,
        appealId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
