import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberArticlesArticleIdCommentsCommentIdAttachments } from "../../../../../../providers/postDiscussionBoardMemberArticlesArticleIdCommentsCommentIdAttachments";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { patchDiscussionBoardMemberArticlesArticleIdCommentsCommentIdAttachments } from "../../../../../../providers/patchDiscussionBoardMemberArticlesArticleIdCommentsCommentIdAttachments";
import { deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentIdAttachmentsAttachmentId } from "../../../../../../providers/deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentIdAttachmentsAttachmentId";

import { IPageIDiscussionBoardCommentAttachment } from "../../../../../../api/structures/IPageIDiscussionBoardCommentAttachment";
import { IDiscussionBoardCommentAttachment } from "../../../../../../api/structures/IDiscussionBoardCommentAttachment";

@Controller(
  "/discussionBoard/member/articles/:articleId/comments/:commentId/attachments",
)
export class DiscussionboardMemberArticlesCommentsAttachmentsController {
  /**
   * Create attachments for a comment.
   *
   * Purpose and overview: This endpoint creates
   * `discussion_board_comment_attachments` records that link previously
   * uploaded storage objects to the specified comment. Clients MUST perform
   * object uploads ahead-of-time to object storage and provide `storage_key`
   * references in the manifest. The API will validate each manifest entry,
   * create metadata rows and return the created attachment summaries.
   *
   * Security and permissions: Only authenticated members may add attachments to
   * their own comments; moderators are also permitted to add or manage
   * attachments. The server MUST assert author ownership or moderator role
   * before creating attachments. All creation events MUST be logged for audit.
   *
   * Validation rules and business logic:
   *
   * - Validate `articleId` and `commentId` exist and are associated; return 404
   *   for mismatches.
   * - Enforce per-comment attachment quota (MVP: max 1 attachment per comment).
   *   Quota enforcement MUST be atomic in a DB transaction.
   * - Request manifest items MUST include: `storage_key` (string, required),
   *   `original_filename` (string), `mime_type` (string), and `size` (integer
   *   bytes). The server MUST validate `size` and `mime_type` against
   *   configured limits.
   * - If integrated scanning flags a file, set `quarantined = true`, do not
   *   return a publicUrl, and create a moderator review task.
   * - The request body MUST NOT duplicate the path `commentId` or `articleId`
   *   fields (these are supplied in path parameters).
   *
   * Response and error handling:
   *
   * - On success return a paginated summary of the comment's attachments (IDs,
   *   original_filename, mime_type, size, is_image, quarantined, publicUrl) so
   *   clients can refresh the attachment list. Do NOT return raw internal
   *   `storage_key` in public responses.
   * - Errors: 400 Bad Request (validation errors or quota exceeded), 403
   *   Forbidden (not allowed), 404 Not Found (article/comment mismatch), 422
   *   Unprocessable Entity (storage_key unresolved or quarantined), 500
   *   Internal Server Error for unexpected failures.
   *
   * @param connection
   * @param articleId UUID of the parent article used to validate comment
   *   context
   * @param commentId UUID of the target comment to attach files to
   * @param body Attachment manifest: array of items each containing storage_key
   *   (required), original_filename, mime_type and size in bytes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardCommentAttachment.ICreate,
  ): Promise<IPageIDiscussionBoardCommentAttachment.ISummary> {
    try {
      return await postDiscussionBoardMemberArticlesArticleIdCommentsCommentIdAttachments(
        {
          member,
          articleId,
          commentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Add or update attachments for a comment.
   *
   * Purpose and overview: This operation creates or updates
   * `discussion_board_comment_attachments` records for the given comment.
   * Clients MUST upload binary files to object storage first and provide
   * `storage_key` URIs here. The API validates each manifest entry and creates
   * metadata rows linking the attachment to `discussion_board_comment_id`.
   *
   * Security and permissions: Only authenticated members may add attachments.
   * The caller must be the comment author or an authorized moderator to modify
   * attachments. The server MUST set `discussion_board_uploaded_by_id` to the
   * authenticated member id when available and MUST log creation events for
   * audit.
   *
   * Validation rules and business logic:
   *
   * - Validate `articleId` and `commentId` exist and are correctly associated;
   *   return 404 if not.
   * - Enforce a per-comment attachment quota (MVP: max 1 attachment per comment)
   *   and return 400 when the quota would be exceeded.
   * - Each manifest entry must include: `storage_key` (string, required),
   *   `original_filename` (string), `mime_type` (string), and `size` (integer
   *   bytes). The server should validate `size` against configured limits and
   *   `mime_type` against allowed types.
   * - If integrated scanning flags a file, set `quarantined = true` and create a
   *   moderator review task; quarantined attachments must not be publicly
   *   served until cleared.
   *
   * Response and error handling:
   *
   * - On success return a paginated summary of the comment's attachments so
   *   clients can refresh the attachment list
   *   (IPageIDiscussionBoardCommentAttachment.ISummary).
   * - Errors: 400 Bad Request (validation errors or quota exceeded), 403
   *   Forbidden (not allowed), 404 Not Found (article/comment mismatch), 422
   *   Unprocessable Entity (storage_key unresolved or quarantined), 500
   *   Internal Server Error for unexpected failures.
   *
   * @param connection
   * @param articleId UUID of the parent article used to validate comment
   *   context
   * @param commentId UUID of the target comment to attach files to
   * @param body Attachment manifest: array of items each containing storage_key
   *   (required), original_filename, mime_type and size in bytes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updateAttachments(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardCommentAttachment.IRequest,
  ): Promise<IPageIDiscussionBoardCommentAttachment.ISummary> {
    try {
      return await patchDiscussionBoardMemberArticlesArticleIdCommentsCommentIdAttachments(
        {
          member,
          articleId,
          commentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a comment attachment
   * (discussion_board_comment_attachments).
   *
   * Purpose and overview: This operation permanently deletes a specific
   * attachment that belongs to a comment on a specified article. It targets the
   * discussion_board_comment_attachments table (fields: id,
   * discussion_board_comment_id, discussion_board_uploaded_by_id,
   * original_filename, storage_key, mime_type, size, is_image, quarantined,
   * created_at). The operation verifies the hierarchical relationship article
   * -> comment -> attachment before deletion.
   *
   * Security considerations and user permissions: Only authenticated members
   * may call this endpoint. The server-side implementation MUST enforce that
   * the caller is either the attachment uploader, the author of the parent
   * article, or a moderator with appropriate privileges. All deletion actions
   * MUST generate an immutable audit entry (discussion_board_moderation_audit
   * and/or discussion_board_audit_logs) capturing actor id, action_type,
   * event_payload (including storage_key), and timestamps.
   *
   * Relationship to underlying database entities: This operation checks
   * discussion_board_articles (articleId) -> discussion_board_comments
   * (commentId) -> discussion_board_comment_attachments (attachmentId). If the
   * attachment's discussion_board_comment_id does not match commentId, or the
   * comment's discussion_board_article_id does not match articleId, the
   * implementation MUST return 404 Not Found.
   *
   * Validation and business logic:
   *
   * - Validate articleId, commentId and attachmentId as UUIDs and existence.
   * - Confirm hierarchical relation (article -> comment -> attachment); return
   *   404 if inconsistent.
   * - Confirm caller authorization (uploader, article author, or moderator);
   *   return 403 when unauthorized.
   * - If attachment.quarantined is true, include quarantine metadata in the audit
   *   payload.
   * - Perform DB deletion and storage object removal in a transactional or
   *   compensating manner; if storage deletion fails, roll back DB deletion or
   *   persist a complete audit record including storage_key to enable forensic
   *   action.
   *
   * Expected behavior and errors:
   *
   * - Success: HTTP 204 No Content and an audit entry recorded.
   * - Not found: HTTP 404 when identifiers are missing or relation mismatch.
   * - Forbidden: HTTP 403 when caller lacks permission.
   * - Storage error: HTTP 500 with operational alert when storage deletion fails
   *   after retries.
   *
   * @param connection
   * @param articleId Unique identifier of the target article (UUID)
   * @param commentId Unique identifier of the target comment within the article
   *   (UUID)
   * @param attachmentId Unique identifier of the target comment attachment
   *   (UUID) from discussion_board_comment_attachments
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":attachmentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentIdAttachmentsAttachmentId(
        {
          member,
          articleId,
          commentId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
