import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberArticles } from "../../../../providers/postDiscussionBoardMemberArticles";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putDiscussionBoardMemberArticlesArticleId } from "../../../../providers/putDiscussionBoardMemberArticlesArticleId";
import { deleteDiscussionBoardMemberArticlesArticleId } from "../../../../providers/deleteDiscussionBoardMemberArticlesArticleId";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/member/articles")
export class DiscussionboardMemberArticlesController {
  /**
   * Create a new discussionBoard article (discussion_board_articles).
   *
   * Purpose and overview: Create a new article record in
   * discussion_board_articles for the authenticated member. The request body
   * contains article fields (title, content, category, tags, optional state).
   * The server sets created_at/updated_at and the article's
   * discussion_board_member_id from the authenticated context. The response
   * returns the stored article and an author summary limited to safe fields.
   *
   * Security and permissions:
   *
   * - This endpoint requires authentication as a member. authorizationActor =
   *   "member".
   * - The request DTO MUST NOT include discussion_board_member_id; it is derived
   *   by the server from the authenticated session.
   * - If the client requests state='published', the server must verify the member
   *   is email-verified and authorized to publish; otherwise return 403.
   *
   * Validation and behavior:
   *
   * - Enforce title and content min/max lengths as per product rules; reject
   *   invalid inputs with 400.
   * - If state='published', set published_at to now on successful persist.
   * - After creation, attachments are associated via separate endpoints.
   *
   * Response contract:
   *
   * - Return HTTP 201 Created with the created article (IDiscussionBoardArticle).
   *   The author object included in the response is a summary: { id, username,
   *   display_name } — do NOT return password_hash, email, or other sensitive
   *   fields.
   *
   * @param connection
   * @param body Creation info of the article. The DTO MUST NOT include
   *   discussion_board_member_id; the server derives the author from the
   *   authenticated context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.ICreate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await postDiscussionBoardMemberArticles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an article (discussion_board_articles).
   *
   * Update an existing article in the discussion board. This endpoint updates
   * fields in the discussion_board_articles Prisma model and creates a version
   * snapshot in discussion_board_article_snapshots before applying changes.
   *
   * Purpose and overview: This endpoint allows permitted actors to update an
   * article's editable properties such as title, content, primary category,
   * pinned state and lifecycle state. It writes to the
   * discussion_board_articles table and records a prior-state snapshot into
   * discussion_board_article_snapshots for audit/versioning.
   *
   * Security and permissions: Only authenticated members (article author) may
   * perform updates for their own articles. Moderators and administrators are
   * also permitted to update articles for moderation purposes. The
   * implementation MUST verify caller's ownership or elevated role and return
   * 403 Forbidden when the caller lacks permission.
   *
   * Relationship to database entities: This operation manipulates
   * discussion_board_articles (fields: id, discussion_board_member_id,
   * discussion_board_category_id, title, content, state, is_pinned,
   * published_at, created_at, updated_at, deleted_at). A snapshot row shall be
   * inserted into discussion_board_article_snapshots prior to applying the
   * update.
   *
   * Validation and business logic:
   *
   * - Verify article exists and deleted_at is null; otherwise return 404.
   * - Enforce product-level constraints: title min 5 / max 250 chars; content min
   *   10 / max 200000 chars.
   * - Enforce edit-window policy in application logic; disallow edits when
   *   outside allowed window unless caller is moderator/admin.
   * - Persist snapshot before update; update updated_at after successful write.
   *
   * Errors and edge cases:
   *
   * - 400: validation failures for input fields
   * - 403: unauthorized (not author/admin) or edit-window violation
   * - 404: article not found or already purged
   * - 409: concurrent modification conflict
   * - 500: internal server error
   *
   * @param connection
   * @param articleId Unique identifier of the target article
   * @param body Update payload for the article. Only allowed editable fields
   *   are applied; do not set id, created_at, or deleted_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":articleId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticle.IUpdate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await putDiscussionBoardMemberArticlesArticleId({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete (soft-delete) an article (discussion_board_articles).
   *
   * Soft-delete an article by setting discussion_board_articles.deleted_at to
   * the current timestamp. This removes the article from public listings while
   * preserving the record for retention, audit and appeals.
   *
   * Purpose and overview: Marks an article as deleted in the
   * discussion_board_articles table by setting deleted_at. Downstream
   * retention, attachment retention and eventual purge are handled by
   * background jobs per the data lifecycle policy.
   *
   * Security and permissions: Only authorized members (article author) or
   * moderators/admins may request deletion. The implementation MUST verify
   * caller identity and ownership or elevated privileges and return 403 if
   * unauthorized.
   *
   * Validation and side effects:
   *
   * - If the article does not exist or has already been permanently purged,
   *   return 404.
   * - If deletion is blocked by active legal hold or pending appeal, return 409
   *   Conflict with an explanation.
   * - On success, set deleted_at, remove article from public listings, record an
   *   audit entry, and respond 204 No Content.
   *
   * Related entities: discussion_board_attachments (inherit retention),
   * discussion_board_article_snapshots (preserve for audit), moderation
   * artifacts (reports/appeals).
   *
   * @param connection
   * @param articleId Unique identifier of the target article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":articleId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberArticlesArticleId({
        member,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
