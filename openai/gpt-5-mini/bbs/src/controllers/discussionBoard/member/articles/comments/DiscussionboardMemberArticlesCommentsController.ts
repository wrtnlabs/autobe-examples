import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberArticlesArticleIdComments } from "../../../../../providers/postDiscussionBoardMemberArticlesArticleIdComments";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { putDiscussionBoardMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/putDiscussionBoardMemberArticlesArticleIdCommentsCommentId";
import { deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId";

import { IDiscussionBoardComment } from "../../../../../api/structures/IDiscussionBoardComment";

@Controller("/discussionBoard/member/articles/:articleId/comments")
export class DiscussionboardMemberArticlesCommentsController {
  /**
   * Create a comment for the specified article (discussion_board_comments).
   *
   * Create a new comment associated with the specified article.
   *
   * This operation inserts a new record into the discussion_board_comments
   * table. The server MUST set discussion_board_author_id to the authenticated
   * caller's member id and populate created_at and updated_at timestamps. An
   * optional parent comment id may be supplied to create a reply; when provided
   * the API MUST validate that the parent exists, belongs to the same article,
   * and that the resulting reply depth does not exceed the product policy
   * maximum (application-enforced). Content length validation (per product
   * policy; e.g., up to 500–5000 chars) and rate-limiting/anti-abuse checks
   * MUST be enforced before persisting.
   *
   * Security and moderation: Only authenticated members (authorization actor:
   * member) may create comments. The service MUST ensure the member is verified
   * and not suspended before accepting the comment. Comments that trigger
   * automated abuse heuristics should be routed to moderation: they may be
   * persisted with is_hidden=true or flagged for review as determined by
   * product policy. This operation does not allow clients to set
   * moderation-only fields (is_hidden, deleted_at) directly.
   *
   * DB relationships and error handling: This operation targets the
   * discussion_board_comments table and uses discussion_board_article_id to
   * relate the comment to its article. If articleId does not exist or is not in
   * a commentable state, return 404. If parentCommentId is provided but invalid
   * or from a different article, return 400. Validation errors yield 400,
   * authentication/authorization errors yield 401/403, and rate-limit
   * violations yield 429.
   *
   * @param connection
   * @param articleId Unique identifier of the target article
   *   (discussion_board_articles.id).
   * @param body Comment creation payload with properties: content (string),
   *   optional parentCommentId (uuid).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.ICreate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await postDiscussionBoardMemberArticlesArticleIdComments({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing comment (discussion_board_comments).
   *
   * Update the content of an existing comment for the specified article.
   *
   * This operation updates discussion_board_comments.content and updated_at.
   * The API MUST verify the comment exists, belongs to the specified article,
   * and is not soft-deleted (deleted_at is null). Ownership checks are
   * REQUIRED: only the original discussion_board_author_id or an authorized
   * administrative actor may modify the comment. The application MUST enforce
   * the edit window policy (application-level rule) and log the update to
   * moderation/audit systems (discussion_board_moderation_audit) to preserve
   * history. If the edit triggers automated abuse heuristics, the comment may
   * be flagged or routed to moderation according to product rules.
   *
   * Error handling and constraints: Return 404 if the article or comment is not
   * found, 403 if the caller is not authorized to edit, 400 for validation
   * errors (content length or invalid payload), and 409 for detected edit
   * conflicts. This endpoint does not permit changing the comment's article
   * association or parent reference.
   *
   * @param connection
   * @param articleId Unique identifier of the parent article
   *   (discussion_board_articles.id).
   * @param commentId Unique identifier of the target comment
   *   (discussion_board_comments.id).
   * @param body Comment update payload containing editable fields (e.g.,
   *   content).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardMemberArticlesArticleIdCommentsCommentId({
        member,
        articleId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete a comment for the specified article.
   *
   * Purpose and overview: This endpoint performs a recoverable deletion
   * (soft-delete) of a comment stored in the `discussion_board_comments` table.
   * The Prisma model defines a nullable `deleted_at` timestamp; therefore this
   * operation sets `deleted_at` to the current UTC time instead of permanently
   * removing the database row. Child comments and attachments are preserved and
   * handled by application-level retention logic.
   *
   * Security considerations and permissions: Only authenticated actors may call
   * this endpoint. The operation permits deletion when the caller is the
   * original comment author (ownership) or an authorized
   * moderator/administrator. The server MUST validate the authenticated actor's
   * identity and role and must not allow unauthorized deletions.
   * Moderator-initiated removals MUST create corresponding moderation audit
   * records in `discussion_board_moderation_audit` and optionally a
   * `discussion_board_moderation_actions` entry.
   *
   * Relationship to DB entities: This operation updates the `deleted_at` column
   * of `discussion_board_comments`. It MUST validate that `commentId` exists
   * and that it belongs to the provided `articleId` to avoid cross-article
   * mismatches.
   *
   * Validation and business rules:
   *
   * - Validate `articleId` and `commentId` are valid UUIDs and that the comment
   *   belongs to the article; return 404 if not found or mismatched.
   * - Verify caller is the comment author or a moderator/admin; return 403 if not
   *   authorized.
   * - Check for active legal holds or appeals that prevent deletion; if present
   *   return 409 Conflict or 422 per policy.
   * - Set `deleted_at` to current UTC timestamp and record the actor and reason
   *   for audit.
   *
   * Errors and related operations:
   *
   * - 404 Not Found (invalid article/comment or mismatch)
   * - 403 Forbidden (insufficient permissions)
   * - 409 Conflict / 422 Unprocessable Entity (legal hold or active appeal)
   * - 500 Internal Server Error for unexpected failures
   *
   * @param connection
   * @param articleId Unique identifier (UUID) of the parent article
   * @param commentId Unique identifier (UUID) of the comment to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId(
        {
          member,
          articleId,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
