import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardTags } from "../../../providers/patchDiscussionBoardTags";
import { getDiscussionBoardTagsTagSlug } from "../../../providers/getDiscussionBoardTagsTagSlug";

import { IPageIDiscussionBoardTag } from "../../../api/structures/IPageIDiscussionBoardTag";
import { IDiscussionBoardTag } from "../../../api/structures/IDiscussionBoardTag";

@Controller("/discussionBoard/tags")
export class DiscussionboardTagsController {
  /**
   * Search and paginate discussion tags (discussion_board_tags).
   *
   * Purpose and overview:
   *
   * Provides a flexible listing and search endpoint for tags
   * (discussion_board_tags). The Prisma model contains id, name, slug,
   * description, is_active, created_at, updated_at and deleted_at. This
   * operation is read-only and excludes rows where deleted_at is set. Clients
   * may use this endpoint for tag pickers, auto-complete, and tag browsing.
   *
   * Security and permissions:
   *
   * This is a public read operation and requires no authentication.
   * Administrative changes (create/update/delete of tags) are out of scope and
   * should be handled via authenticated admin endpoints.
   *
   * Relationship to underlying database entity:
   *
   * This operation queries the discussion_board_tags table. Use available
   * indexes (is_active, created_at and trigram indexes on
   * name/slug/description) for efficient searches. The endpoint maps request
   * parameters to safe SQL operations and must validate pagination and sorting
   * parameters.
   *
   * Validation rules and business logic:
   *
   * - Accept pagination parameters (page, limit) with sensible defaults and
   *   enforce a maximum limit (e.g., 100).
   * - Accept search text to match against name, slug, and description using
   *   trigram/GIN-assisted queries.
   * - Accept optional filters: is_active (boolean), createdAfter and
   *   createdBefore (ISO 8601 datetimes).
   * - Accept sorting options: created_at (asc|desc) or name (asc|desc).
   * - Return paginated metadata: total, page, limit and an array of tag
   *   summaries.
   *
   * Expected behavior and error handling:
   *
   * - On success: return IPageIDiscussionBoardTag.ISummary containing pagination
   *   and an array of tag summaries (id, name, slug, is_active, description
   *   excerpt, created_at).
   * - Errors: 400 for invalid pagination or filter parameters; 500 for unexpected
   *   failures.
   *
   * @param connection
   * @param body Search criteria, filters, pagination and sorting for tag
   *   listing
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardTag.IRequest,
  ): Promise<IPageIDiscussionBoardTag.ISummary> {
    try {
      return await patchDiscussionBoardTags({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a tag by its slug (discussion_board_tags table).
   *
   * Purpose and overview: Retrieve a single tag resource identified by its slug
   * from the discussion_board_tags table. The Prisma model contains: id (UUID),
   * name, slug (unique), optional description, is_active flag, created_at,
   * updated_at and deleted_at. This endpoint returns the canonical tag record
   * used for tag detail pages and client-side tag metadata.
   *
   * Security and visibility: This is a public, read-only endpoint and does not
   * require authentication. Public consumers receive only tags that are active
   * and not soft-deleted (is_active = true and deleted_at IS NULL). If
   * administrative visibility into inactive or soft-deleted tags is required, a
   * separate admin-only endpoint must be provided.
   *
   * Database relationship and behavior: Maps to the Prisma model
   * `discussion_board_tags`. The table defines `@@unique([slug])`, therefore
   * this operation resolves tags by `slug` (human-friendly identifier) rather
   * than by UUID. Implementations should consider normalizing slug casing to
   * ensure consistent lookup behavior. Exclude records where deleted_at is set
   * for public reads.
   *
   * Validation and error handling:
   *
   * - 200: returns the tag record when found and visible.
   * - 404: returned when no tag with the provided slug exists or when the tag is
   *   soft-deleted or inactive for public callers.
   * - 500: unexpected database errors.
   *
   * @param connection
   * @param tagSlug URL-friendly unique tag key (slug) of the target tag (global
   *   scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":tagSlug")
  public async at(
    @TypedParam("tagSlug")
    tagSlug: string,
  ): Promise<IDiscussionBoardTag> {
    try {
      return await getDiscussionBoardTagsTagSlug({
        tagSlug,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
