import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorReports } from "../../../../providers/patchDiscussionBoardModeratorReports";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { getDiscussionBoardModeratorReportsReportId } from "../../../../providers/getDiscussionBoardModeratorReportsReportId";
import { putDiscussionBoardModeratorReportsReportId } from "../../../../providers/putDiscussionBoardModeratorReportsReportId";

import { IPageIDiscussionBoardReport } from "../../../../api/structures/IPageIDiscussionBoardReport";
import { IDiscussionBoardReport } from "../../../../api/structures/IDiscussionBoardReport";

@Controller("/discussionBoard/moderator/reports")
export class DiscussionboardModeratorReportsController {
  /**
   * Search and retrieve paginated moderation reports from
   * discussion_board_reports.
   *
   * Retrieve a paginated list of moderation reports for moderator triage and
   * queue management. This operation queries the discussion_board_reports table
   * and returns results in a paginated summary form optimized for moderator
   * dashboards.
   *
   * Security and permissions: Access to this operation is restricted to
   * moderator actors. Only authenticated moderators with appropriate privileges
   * may call this endpoint. All reads should be recorded in moderation audit
   * logs for accountability. The default response excludes closed reports
   * unless the request explicitly requests closed=true.
   *
   * Behavior and constraints:
   *
   * - Accepts structured search request (IDiscussionBoardReport.IRequest)
   *   including pagination (page, limit), filters (status, reason_category,
   *   reporterMemberId, targetType, targetId), date ranges, text search over
   *   explanation, and sorting options.
   * - Server enforces max page size (recommended 100) to avoid expensive queries.
   * - By default returns non-closed reports (closed_at IS NULL) unless closed
   *   filter is set.
   * - Summaries include id, reporter_member_id, target_type, target_id,
   *   reason_category, status, created_at, processed_at, brief excerpt of
   *   explanation, and aggregated signals (e.g., uniqueReporterCount). Do NOT
   *   include reporter_session_id in the default summary to avoid exposing
   *   session-level detail; session id may be available in the detail endpoint
   *   under additional authorization checks.
   *
   * Errors:
   *
   * - 400 for invalid params; 404 for invalid referenced targets when used with
   *   strict mode; 503 for transient DB errors with correlation id.
   *
   * @param connection
   * @param body Search request parameters for moderator reports including
   *   pagination, filters (status, reason_category, reporterMemberId,
   *   targetType, targetId), date ranges, text search over explanation, and
   *   sorting options.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardReport.IRequest,
  ): Promise<IPageIDiscussionBoardReport.ISummary> {
    try {
      return await patchDiscussionBoardModeratorReports({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single moderation report by ID from discussion_board_reports.
   *
   * Return the detailed record of a moderation report stored in
   * discussion_board_reports for use by moderators during triage. The response
   * contains canonical fields: id, reporter_member_id, reporter_session_id
   * (sensitive: include only id, not session payload), target_type
   * (article|comment|attachment), target_id (UUID), reason_category
   * (Spam|Harassment|Misinformation|Illegal|Other), explanation, status,
   * created_at, processed_at and closed_at.
   *
   * Security and permissions: Only moderators may call this endpoint. Reads of
   * report details and reporter identity MUST be recorded in moderation audit
   * logs. If session-level details are required for investigation, include only
   * reporter_session_id (id) and access must be additionally logged and
   * restricted.
   *
   * Relationships and embedding: This endpoint may embed a capped list of
   * related moderation actions and appeals (e.g., last 5) or provide links to
   * full lists. Prefer links or paginated sub-resources for large related
   * collections.
   *
   * Validation:
   *
   * - Path parameter reportId is a UUID and corresponds to
   *   discussion_board_reports.id. Return 400 for invalid UUID, 404 if not
   *   found.
   *
   * Error handling:
   *
   * - 400 invalid input; 403 unauthorized; 404 not found; 503 transient DB errors
   *   with correlation id.
   *
   * @param connection
   * @param reportId Unique identifier (UUID) of the target report from
   *   discussion_board_reports.id
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reportId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardReport> {
    try {
      return await getDiscussionBoardModeratorReportsReportId({
        moderator,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a report's processing status and timestamps (moderator only).
   *
   * Purpose and overview: This operation updates an existing report record in
   * the discussion_board_reports table. Reports capture member-submitted
   * complaints about articles, comments, or attachments (fields include
   * reporter_member_id, reporter_session_id, target_type, target_id,
   * reason_category, explanation, status, created_at, processed_at, closed_at).
   * Moderators use this endpoint to record triage outcomes, change the report's
   * processing status, and set processed/closed timestamps.
   *
   * Security and permissions: Only moderator actors are allowed to call this
   * endpoint. The operation must verify the caller has moderator privileges and
   * return 403 Forbidden for non-moderators. All changes must be recorded in
   * the moderation audit subsystem (discussion_board_moderation_audit).
   * Reporter session identifiers and IP addresses are considered sensitive and
   * are redacted by default in responses; full session details are available
   * only to authorized audit roles via separate audit APIs.
   *
   * Relationship to database entity: This operation maps directly to the
   * discussion_board_reports model from the Prisma schema. The request updates
   * the report's status, processed_at and closed_at columns. The operation MUST
   * NOT assume additional fields exist on the report model (for example
   * processed_by) and must not create or modify moderation action rows (those
   * are created via discussion_board_moderation_actions).
   *
   * Validation rules and business logic:
   *
   * - Validate reportId is a UUID and that a report with the given id exists.
   * - Request status values must be validated against the canonical set enforced
   *   by the application (e.g., 'pending','triaged','resolved').
   * - Processed_at and closed_at must be valid ISO 8601 timestamps if provided.
   * - Setting closed_at earlier than created_at MUST result in 400 Bad Request.
   * - Changing status to a resolved/closed state should set closed_at if not
   *   explicitly provided.
   *
   * Expected behavior and error handling:
   *
   * - 200 OK with the updated report when update succeeds.
   * - 400 Bad Request for validation errors (malformed timestamps, invalid status
   *   values, closed_at earlier than created_at).
   * - 401 Unauthorized when caller is not authenticated.
   * - 403 Forbidden when caller is authenticated but not a moderator.
   * - 404 Not Found when the reportId does not exist.
   *
   * @param connection
   * @param reportId Unique identifier of the target report (UUID)
   * @param body Moderator-provided processing update for the report. Contains
   *   allowed status and optional processed/closed timestamps. DTO:
   *   IDiscussionBoardReport.IUpdate
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":reportId")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardReport.IUpdate,
  ): Promise<IDiscussionBoardReport> {
    try {
      return await putDiscussionBoardModeratorReportsReportId({
        moderator,
        reportId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
