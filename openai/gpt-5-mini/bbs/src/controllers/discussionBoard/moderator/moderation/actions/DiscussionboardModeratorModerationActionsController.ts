import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardModeratorModerationActions } from "../../../../../providers/postDiscussionBoardModeratorModerationActions";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { patchDiscussionBoardModeratorModerationActions } from "../../../../../providers/patchDiscussionBoardModeratorModerationActions";
import { getDiscussionBoardModeratorModerationActionsActionId } from "../../../../../providers/getDiscussionBoardModeratorModerationActionsActionId";

import { IDiscussionBoardModerationAction } from "../../../../../api/structures/IDiscussionBoardModerationAction";
import { IPageIDiscussionBoardModerationAction } from "../../../../../api/structures/IPageIDiscussionBoardModerationAction";

@Controller("/discussionBoard/moderator/moderation/actions")
export class DiscussionboardModeratorModerationActionsController {
  /**
   * Record a moderator action and trigger enforcement
   * (discussion_board_moderation_actions).
   *
   * Purpose and overview:
   *
   * This endpoint enables a moderator to record and apply a moderation action.
   * It persists a discussion_board_moderation_actions entry capturing
   * moderator_id, optional discussion_board_report_id, action_type,
   * action_reason, action_duration_days for temporary sanctions, and
   * polymorphic target references (target_type + target_id). The moderation
   * action record is auditable and is used as the source of truth for
   * enforcement workers that apply content state changes or member sanctions.
   *
   * Security and permissions:
   *
   * Access to this endpoint is strictly limited to authenticated moderators.
   * The service must validate moderator privileges prior to persisting the
   * action. All moderation actions must also produce corresponding audit
   * records in discussion_board_moderation_audit and emit events for
   * enforcement subsystems.
   *
   * Validation and business rules:
   *
   * - Moderator_id must be derived from the authenticated moderator principal;
   *   clients must not impersonate moderators.
   * - Action_type must be one of the allowed values. Implementations must
   *   validate and reject unsupported action types.
   * - If discussion_board_report_id is supplied it must reference an existing
   *   report; otherwise return 400/404 as appropriate.
   * - When action_duration_days is supplied, compute effective_until as
   *   created_at + action_duration_days and schedule revocation accordingly.
   * - The endpoint returns 201 Created with the created moderation action;
   *   consumers (appeals, audit) will reference moderation_action.id.
   *
   * Errors and expected responses:
   *
   * - 201 Created with the created IDiscussionBoardModerationAction on success
   * - 400 Bad Request for validation failures
   * - 401/403 for authentication/authorization failures
   * - 404 Not Found for missing referenced resources
   *
   * Implementation note:
   *
   * Persist the moderation action and ensure an audit entry is created
   * atomically or via a reliable outbox pattern.
   *
   * @param connection
   * @param body Moderation action creation payload
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardModerationAction.ICreate,
  ): Promise<IDiscussionBoardModerationAction> {
    try {
      return await postDiscussionBoardModeratorModerationActions({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of moderation actions
   * (discussion_board_moderation_actions).
   *
   * Retrieve a filtered and paginated collection of moderation actions from the
   * `discussion_board_moderation_actions` table.
   *
   * This operation is designed for moderators to find moderation actions by
   * multiple criteria: moderator id (`moderator_id`), originating report
   * (`discussion_board_report_id`), action type (`action_type`, e.g.,
   * 'hide','remove','warn','suspend','ban'), target_type/target_id (polymorphic
   * target), date ranges over `created_at` or `effective_from`, and free-text
   * search over `action_reason`. The request DTO
   * `IDiscussionBoardDiscussionBoardModerationAction.IRequest` should express
   * pagination (page, limit), sort instructions, and filter predicates. The
   * implementation should leverage existing indexes (e.g.,
   * `@@index([moderator_id, created_at])`, `@@index([target_type, target_id])`)
   * to ensure efficient queries.
   *
   * Security and permissions: Only authenticated moderators may call this
   * endpoint (authorization actor: `moderator`). The response must be scoped to
   * the caller's permissions. Fields that reveal sensitive investigation
   * details should be redacted unless the moderator's role permits viewing full
   * audit payloads. Access to some audit payloads may additionally require
   * cross-checking the `discussion_board_moderation_audit` table and the
   * moderator's audit access rights.
   *
   * Relationship to database entities and validation: This operation maps
   * directly to the `discussion_board_moderation_actions` Prisma model; valid
   * filter fields must correspond to actual columns described in the Prisma
   * schema (for example, `action_type`, `moderator_id`,
   * `discussion_board_report_id`, `target_type`, `target_id`, `created_at`,
   * `effective_from`, `effective_until`). The request DTO must NOT attempt to
   * filter on non-existent columns. The response summaries should include safe
   * subsets of the moderation action fields and small related objects
   * (moderator summary, linked report summary) when authorized.
   *
   * Related operations: Use `GET /moderation/actions/{actionId}` to retrieve a
   * single moderation action with full details, including linked audit entries
   * and the original report if present. Error handling: validate pagination
   * parameters, return 400 for invalid filters, and return an empty page when
   * no records match. Typical errors include 400 (bad request), 401
   * (unauthorized), and 403 (forbidden if moderator lacks privileges).
   *
   * @param connection
   * @param body Search, filter and pagination parameters for moderation
   *   actions. Use fields such as moderatorId, reportId, actionType,
   *   targetType, createdFrom, createdTo, page, limit, sort.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardModerationAction.IRequest,
  ): Promise<IPageIDiscussionBoardModerationAction.ISummary> {
    try {
      return await patchDiscussionBoardModeratorModerationActions({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single moderation action by id
   * (discussion_board_moderation_actions).
   *
   * Return detailed information for a single moderation action.
   *
   * Purpose & overview: This operation provides moderators with the complete
   * details of a moderation action recorded in
   * `discussion_board_moderation_actions`. The response includes core fields
   * such as `action_type`, `action_reason`, `action_duration_days`,
   * `target_type`, `target_id`, timestamps (`created_at`, `effective_from`,
   * `effective_until`) and references (`moderator_id`,
   * `discussion_board_report_id`). When permitted, the response may also
   * include a minimal moderator profile (id, username, display_name) and a
   * brief linked report summary.
   *
   * Security considerations and permissions: Access to this endpoint is
   * restricted to moderator actors (`moderator`). Implementations must verify
   * that the requesting moderator has the right to view the specific action and
   * related context. If access is restricted, return 403. All calls must be
   * authenticated and authorized; sensitive audit payloads referenced by this
   * action should only be returned when the requesting moderator's privileges
   * allow it.
   *
   * Relationship to underlying database entities: This operation queries the
   * Prisma `discussion_board_moderation_actions` model. If the moderation
   * action references `discussion_board_report_id`, the service may join to the
   * `discussion_board_reports` table to surface summary information (report
   * reason_category, created_at) for context. For forensic reconstruction,
   * callers should use the separate moderation audit endpoints which read
   * `discussion_board_moderation_audit` records.
   *
   * Validation rules and error handling: The path parameter `actionId` must be
   * a UUID that corresponds to an existing moderation action. If not found,
   * return 404. If the caller lacks permission, return 403. If the `actionId`
   * format is invalid, return 400. Related operations: `PATCH
   * /moderation/actions` for list/search and `GET
   * /moderation/actions/{actionId}/audit` (not implemented here) for the audit
   * trail details.
   *
   * @param connection
   * @param actionId Unique identifier (UUID) of the target moderation action
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":actionId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("actionId")
    actionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardModerationAction> {
    try {
      return await getDiscussionBoardModeratorModerationActionsActionId({
        moderator,
        actionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
