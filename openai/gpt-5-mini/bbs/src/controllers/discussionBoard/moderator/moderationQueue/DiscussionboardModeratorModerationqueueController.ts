@Controller("/discussionBoard/moderator/moderationQueue")
export class DiscussionboardModeratorModerationqueueController {
  /**
   * Search and retrieve paginated moderation reports.
   *
   * Purpose and overview:
   *
   * This operation returns a paginated, filterable list of report summaries
   * drawn directly from the discussion_board_reports Prisma model. It is used
   * by moderators to triage reported items (articles, comments, attachments)
   * and to identify high-priority targets by aggregating report counts per
   * target. The operation supports advanced filters and sorting to enable
   * prioritized moderation workflows.
   *
   * Security and user permissions:
   *
   * Access to this endpoint MUST be restricted to moderator actors. Reporter
   * session details (reporter_session_id) and raw session metadata (IP/href)
   * MUST only be returned when the calling moderator has the explicit audit
   * privilege (e.g., 'moderation.audit'); otherwise those fields MUST be
   * omitted to protect reporter privacy. All accesses that return reporter
   * session or reporter email MUST be logged in moderation audit trails and
   * discussion_board_audit_logs.
   *
   * Relationship to underlying database entities:
   *
   * This operation maps to the discussion_board_reports table and uses these
   * columns: reporter_member_id, reporter_session_id, target_type, target_id,
   * reason_category, explanation, status, created_at, processed_at, closed_at.
   * When reporter context is requested and permitted by RBAC, the service may
   * join to discussion_board_member (reporterMember) and
   * discussion_board_member_sessions (reporterSession) to include reporter
   * display_name and session ip for triage; however email and any other PII
   * MUST only be returned to privileged callers and must be audited.
   *
   * Validation rules and business logic:
   *
   * - Filters accepted in request body: targetType (string), targetId (UUID),
   *   reasonCategory (string), status (string), createdAtFrom (ISO 8601),
   *   createdAtTo (ISO 8601), priority (boolean derived via aggregation),
   *   includeProcessed (boolean), includeReporterContext (boolean - requires
   *   audit privilege).
   * - Sorting options: created_at (asc/desc), processed_at (asc/desc), priority
   *   (desc).
   * - Pagination: page, limit (server enforces a maximum limit to protect DB;
   *   recommended max limit = 100).
   * - Aggregation: service SHOULD compute reportCount per (target_type,
   *   target_id) and MAY include an aggregation field reportCount in the
   *   response to help moderators identify hot targets.
   * - Behavior: If a filter references a non-existent target_id, return an empty
   *   page rather than an error. Malformed UUIDs or dates MUST return 400 with
   *   validation details.
   *
   * Related operations:
   *
   * This operation is typically followed by moderator action endpoints that
   * create discussion_board_moderation_actions and append entries to
   * discussion_board_moderation_audit. Clients may call this endpoint to
   * assemble the moderator queue and then call action endpoints to resolve
   * items.
   *
   * @param connection
   * @param body Search and pagination parameters for moderation queue
   *   retrieval. Fields: targetType, targetId, reasonCategory, status,
   *   priority, createdAtFrom, createdAtTo, includeProcessed,
   *   includeReporterContext (boolean - requires audit privilege), page, limit,
   *   sortBy.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardReport.IRequest,
  ): Promise<IPageIDiscussionBoardReport.ISummary> {
    try {
      return await patchDiscussionBoardModeratorModerationQueue({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
