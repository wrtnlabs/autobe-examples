import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postDiscussionBoardModeratorTags } from "../../../../providers/postDiscussionBoardModeratorTags";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { putDiscussionBoardModeratorTagsTagSlug } from "../../../../providers/putDiscussionBoardModeratorTagsTagSlug";
import { deleteDiscussionBoardModeratorTagsTagSlug } from "../../../../providers/deleteDiscussionBoardModeratorTagsTagSlug";

import { IDiscussionBoardTag } from "../../../../api/structures/IDiscussionBoardTag";

@Controller("/discussionBoard/moderator/tags")
export class DiscussionboardModeratorTagsController {
  /**
   * Create a new tag (discussion_board_tags table).
   *
   * Purpose and overview: Create a new tag record to be used for article
   * labeling and discovery. The Prisma model `discussion_board_tags` stores tag
   * metadata including name, slug, optional description and an is_active flag.
   * The endpoint accepts a creation DTO and returns the created resource.
   *
   * Security and permissions: This endpoint is restricted to privileged actors
   * who manage taxonomy. The moderator actor is required to call this endpoint.
   * Calls from non-moderator actors must be rejected with 403 Forbidden.
   *
   * Business validation and DB mapping:
   *
   * - Required (business-level): name, slug. Optional: description.
   * - Note: `is_active` is non-nullable in the Prisma model; the server WILL set
   *   `is_active = true` when omitted by the client, and WILL populate
   *   created_at/updated_at timestamps before calling Prisma.create unless the
   *   DTO explicitly provides them. Ensure application or DB-level defaults
   *   exist to satisfy Prisma non-nullable constraints.
   * - Slug must be URL-friendly and unique (enforced by @@unique([slug]) in the
   *   Prisma schema). Implementations should normalize slug to lower-case when
   *   case-insensitive behavior is desired.
   * - On unique constraint violation (slug or name), return 409 Conflict with a
   *   clear message.
   *
   * Implementation details: Use Prisma `create` for discussion_board_tags
   * within transactional context if additional side-effects (audit log entries)
   * are required. Audit log entries must be created server-side (e.g.,
   * discussion_board_moderation_audit) recording moderator id and action_type
   * 'tag.create'. Do NOT accept audit payloads from clients.
   *
   * @param connection
   * @param body Creation payload for a new tag. Required fields: name (string),
   *   slug (string). Optional: description (string), is_active (boolean). If
   *   is_active is omitted the server will set is_active = true before
   *   persisting to the database.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardTag.ICreate,
  ): Promise<IDiscussionBoardTag> {
    try {
      return await postDiscussionBoardModeratorTags({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an article tag by slug in the discussion_board_tags table.
   *
   * Update metadata for an existing tag identified by slug.
   *
   * Purpose and overview: Tags are business-facing labels used to categorize
   * articles and improve discovery. This endpoint updates editable tag fields
   * while preserving the canonical slug used in URLs and integrations. The API
   * accepts a partial update payload containing allowed fields (name,
   * description, is_active, sort_order) and returns the full updated tag record
   * as stored in the discussion_board_tags table.
   *
   * Security and permissions: Only moderator actors may invoke this endpoint.
   * Implementations MUST validate the caller's role and record the update in
   * the moderation/audit subsystem (discussion_board_moderation_audit) for
   * traceability. Audit records MUST include moderator id, action_type,
   * target_type, target_id, action_reason and occurred_at.
   *
   * Validation and error handling: Return 404 when tag not found; 409 when
   * update would violate unique constraints (e.g., name); 400 for validation
   * errors (including attempts to change slug). Name and slug uniqueness
   * constraints are enforced by the DB; the service should catch unique
   * constraint violations and return human-friendly messages.
   *
   * Relationship to DB entity: Maps to the Prisma model
   * `discussion_board_tags`. Fields in the response reflect the persisted row
   * (id, name, slug, description, is_active, sort_order, created_at,
   * updated_at, deleted_at).
   *
   * @param connection
   * @param tagSlug Unique tag slug of the target tag (global scope)
   * @param body Fields to update for the target tag. Omit `slug` from the body
   *   — slug is immutable. Allowed fields: name, description, is_active,
   *   sort_order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":tagSlug")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("tagSlug")
    tagSlug: string,
    @TypedBody()
    body: IDiscussionBoardTag.IUpdate,
  ): Promise<IDiscussionBoardTag> {
    try {
      return await putDiscussionBoardModeratorTagsTagSlug({
        moderator,
        tagSlug,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete (soft-delete) a tag by slug in discussion_board_tags.
   *
   * Soft-delete a tag identified by its globally-unique slug.
   *
   * Purpose and overview: Administrators use this endpoint to remove tags from
   * the active catalogue while preserving historical references for auditing
   * and potential restore workflows. Implementation should set `deleted_at` to
   * the current timestamp, set `is_active` to false, and optionally
   * disassociate or block active assignments per product policy. The operation
   * must create a moderation audit record describing the actor and reason.
   *
   * Security and permissions: Only moderator actors may delete tags. The
   * implementation MUST validate actor privileges and write a
   * `discussion_board_moderation_audit` entry with moderator id, action_type
   * ('remove' or 'hide'), target_type ('tag'), target_id (tag id),
   * action_reason (optional), and occurred_at.
   *
   * Referential considerations: This operation affects
   * `discussion_board_article_tags`. Implementers MUST either block deletion
   * when assignments exist (return 409) or perform safe disassociation and
   * record the changes. Document chosen policy and ensure clients can detect
   * and handle 409 conflict responses.
   *
   * Relationship to DB entity: Maps to `discussion_board_tags` and must respect
   * referential relationships with `discussion_board_article_tags`. Because
   * `deleted_at` exists in the model, soft-delete semantics are supported by
   * the schema.
   *
   * @param connection
   * @param tagSlug Unique tag slug of the target tag (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":tagSlug")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("tagSlug")
    tagSlug: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardModeratorTagsTagSlug({
        moderator,
        tagSlug,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
