import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postDiscussionBoardModeratorCategories } from "../../../../providers/postDiscussionBoardModeratorCategories";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { putDiscussionBoardModeratorCategoriesCategorySlug } from "../../../../providers/putDiscussionBoardModeratorCategoriesCategorySlug";
import { deleteDiscussionBoardModeratorCategoriesCategorySlug } from "../../../../providers/deleteDiscussionBoardModeratorCategoriesCategorySlug";

import { IDiscussionBoardCategory } from "../../../../api/structures/IDiscussionBoardCategory";

@Controller("/discussionBoard/moderator/categories")
export class DiscussionboardModeratorCategoriesController {
  /**
   * Create a new discussion board category (discussion_board_categories).
   *
   * Create a new category used to organize articles.
   *
   * Purpose and overview: This operation allows administrators to create a new
   * category record stored in the discussion_board_categories table. The Prisma
   * schema documents that categories include name, slug, optional description,
   * is_active, sort_order, and temporal audit fields (created_at, updated_at)
   * as well as deleted_at for soft-delete handling. The API accepts semantic
   * fields and returns the canonical representation of the newly created
   * category.
   *
   * Security and permissions: Only admin actors are permitted to call this
   * endpoint. The controller MUST enforce authorization checks and only allow
   * users with administrative privileges to create categories. The operation
   * should validate that the requesting actor is authorized and log the
   * creation action into moderation/audit systems per product policy.
   *
   * Relationship to DB entities: This operation writes to the
   * discussion_board_categories Prisma model described in the schema. New
   * categories become available for assignment by articles via
   * discussion_board_articles.discussion_board_category_id. Uniqueness rules
   * from the schema (@@unique([slug]) and @@unique([name])) MUST be enforced by
   * the service layer; attempts to create a category with an existing slug or
   * name MUST return a 409 conflict error.
   *
   * Validation and business logic: Validate 'name' length and presence, ensure
   * 'slug' is a URL-friendly identifier (lowercase recommended) and globally
   * unique, and validate optional 'sort_order' as integer when provided. The
   * service should set created_at/updated_at values (DB defaults are
   * recommended) and return the fully-populated entity. Error handling: on
   * uniqueness violation return 409 with an explanatory message; on validation
   * errors return 400. Unexpected server errors return 500.
   *
   * Related operations: GET /categories (list), GET /categories/{categorySlug}
   * (retrieve by slug), PUT /categories/{categorySlug} (update) and
   * administrative delete operations (if implemented) interact with the same
   * Prisma model and should apply consistent validation and audit logging.
   *
   * @param connection
   * @param body Category creation payload
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardCategory.ICreate,
  ): Promise<IDiscussionBoardCategory> {
    try {
      return await postDiscussionBoardModeratorCategories({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing discussion board category by slug
   * (discussion_board_categories).
   *
   * Purpose and overview: Update mutable fields of an existing category stored
   * in discussion_board_categories. The Prisma schema documents that categories
   * have name, slug (globally unique), description, is_active, sort_order, and
   * temporal audit columns. This operation allows administrators to change
   * display name, description, activation state, and ordering.
   *
   * Security and permissions: Only admin actors may call this endpoint. The
   * service MUST verify the caller's authorization and record the update in
   * audit logs (discussion_board_moderation_audit or
   * discussion_board_audit_logs) with the acting moderator/admin id, reason,
   * and timestamp per governance policy.
   *
   * Relationship to underlying DB entities: The operation identifies the target
   * category by its unique slug (schema-level @@unique([slug])). Because slug
   * is globally unique, the path parameter uses the slug to locate the single
   * category record. On success the operation updates the
   * discussion_board_categories record and returns the updated category. The
   * service must ensure that updating slug or name does not violate @@unique
   * constraints; concurrent update conflicts should be handled gracefully.
   *
   * Validation rules and business logic: Validate provided fields (name
   * non-empty, slug pattern if changing, sort_order integer when present). If
   * the requested slug does not correspond to any active record, return 404. If
   * attempting to change slug or name to a value that conflicts with an
   * existing category, return 409 conflict with an explanatory message. The
   * operation should update the updated_at timestamp and preserve created_at
   * and deleted_at values.
   *
   * Related operations: GET /categories, POST /categories (create), and
   * administrative delete endpoints. Consumers must use the same slug semantics
   * across list and detail endpoints to maintain URL stability.
   *
   * @param connection
   * @param categorySlug Unique business identifier code of the target category
   *   (global scope)
   * @param body Category update payload
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categorySlug")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("categorySlug")
    categorySlug: string,
    @TypedBody()
    body: IDiscussionBoardCategory.IUpdate,
  ): Promise<IDiscussionBoardCategory> {
    try {
      return await putDiscussionBoardModeratorCategoriesCategorySlug({
        moderator,
        categorySlug,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete (soft-delete) a discussion category by slug
   * (discussion_board_categories).
   *
   * Purpose and overview:
   *
   * This endpoint marks a discussion category as deleted by setting the
   * discussion_board_categories.deleted_at timestamp using the category's slug
   * as the identifier. The Prisma schema for discussion_board_categories
   * includes fields id, name, slug, description, is_active, sort_order,
   * created_at, updated_at and deleted_at; because deleted_at exists, the
   * operation implements a soft-delete pattern to preserve the record for
   * audit, appeals, and legal hold workflows.
   *
   * Security considerations and user permissions:
   *
   * Only privileged actors (moderators) are allowed to call this endpoint. The
   * calling moderator must be authenticated and authorized; the implementation
   * MUST record an audit entry containing the moderator id, timestamp, category
   * id/slug and an optional reason. Public users or regular members are not
   * permitted to perform this action.
   *
   * Relationship to underlying database entity:
   *
   * This operation acts on the discussion_board_categories table in the Prisma
   * schema. It resolves the target category by slug (unique) and performs a
   * soft-delete by setting deleted_at = now() (ISO 8601 UTC) and typically
   * is_active = false. It leaves related articles intact (no automatic
   * reassignment) and relies on explicit administrative or background processes
   * for reclassification of dependent content.
   *
   * Validation rules and business logic:
   *
   * - Validate that a category exists for the given slug; return 404 when not
   *   found.
   * - If the category already has deleted_at set, the endpoint may respond
   *   idempotently (204) or return 409 depending on policy; the implementation
   *   should log repeated attempts.
   * - Ensure the caller is authorized as a moderator and record the moderator
   *   identity in an audit log.
   * - After setting deleted_at, return the category summary showing deleted_at
   *   populated so the caller can confirm the soft-delete.
   *
   * Related operations:
   *
   * - Related admin endpoints: GET /categories/{categorySlug}, PATCH
   *   /categories/{categorySlug} (update) should respect deleted_at and
   *   generally exclude soft-deleted categories from public listings.
   * - A separate purge endpoint (not included here) should be used for hard
   *   deletes and must enforce legal hold checks.
   *
   * Expected behavior and error handling:
   *
   * - Success: return the category summary with deleted_at populated indicating
   *   the soft-delete timestamp.
   * - Errors: 404 when slug not found, 403 when caller is not authorized, 409 for
   *   conflicting/deleted state when policy requires, and 500 for unexpected
   *   failures.
   *
   * @param connection
   * @param categorySlug Unique business identifier code of the target category
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categorySlug")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("categorySlug")
    categorySlug: string,
  ): Promise<IDiscussionBoardCategory> {
    try {
      return await deleteDiscussionBoardModeratorCategoriesCategorySlug({
        moderator,
        categorySlug,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
