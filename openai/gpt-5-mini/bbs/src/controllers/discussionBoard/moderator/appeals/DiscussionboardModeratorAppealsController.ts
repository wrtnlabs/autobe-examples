import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorAppeals } from "../../../../providers/patchDiscussionBoardModeratorAppeals";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { putDiscussionBoardModeratorAppealsAppealId } from "../../../../providers/putDiscussionBoardModeratorAppealsAppealId";

import { IPageIDiscussionBoardAppeal } from "../../../../api/structures/IPageIDiscussionBoardAppeal";
import { IDiscussionBoardAppeal } from "../../../../api/structures/IDiscussionBoardAppeal";

@Controller("/discussionBoard/moderator/appeals")
export class DiscussionboardModeratorAppealsController {
  /**
   * Search and retrieve paginated appeals for moderator triage
   * (discussion_board_appeals).
   *
   * Search and list appeals for moderator triage and management.
   *
   * Purpose and overview: This read-only endpoint allows moderators to retrieve
   * a paginated collection of appeals from the discussion_board_appeals model.
   * The operation supports filtering by status (pending, accepted, rejected,
   * etc.), filtering by appellant_member_id, related moderation_action_id or
   * report_id, as well as creation time ranges and optional full-text search on
   * the explanation field. Results are returned in a paginated summary format
   * optimized for moderator queues.
   *
   * Security and permissions: Access to this endpoint is restricted to
   * moderators and administrative actors. The implementation MUST enforce
   * authentication and role checks (moderator role). For auditability, every
   * listing request MUST create an audit access record
   * (discussion_board_audit_log_accesses) capturing the requesting moderator id
   * and the query parameters used.
   *
   * Relationship to Prisma table: This operation reads from
   * discussion_board_appeals and may join to related models
   * (discussion_board_moderation_actions, discussion_board_reports,
   * discussion_board_member) to populate safe summary fields such as appellant
   * display_name and referenced action/report short info. Do not return
   * moderator-only internal notes.
   *
   * Filtering, pagination and sorting:
   *
   * - Request body (IDiscussionBoardAppeal.IRequest) supports page/limit (with
   *   enforced maxPageSize server-side), status list, appellant_member_id,
   *   moderation_action_id, report_id, created_at_from, created_at_to, sort
   *   parameters and optional cursor for seek pagination.
   * - Response uses a paginated container IPageIDiscussionBoardAppeal.ISummary
   *   containing pagination metadata and an array of appeal summary objects.
   *
   * Validation and behavior:
   *
   * - Invalid filter values produce 400 responses with descriptive validation
   *   messages.
   * - Default sort = -created_at (most recent first).
   * - Enforce a conservative maximum page size (recommendation: 200) to prevent
   *   large scans. Use seek pagination (cursor) for high-volume workloads.
   *
   * Related operations: Use POST /discussionBoard/member/appeals for creation
   * and moderation action endpoints for resolving appeals. When appeals are
   * resolved the moderator should call the appropriate moderation action
   * endpoints which will update the appeal's status and resolved_at timestamp.
   *
   * @param connection
   * @param body Search criteria, filters and pagination parameters for
   *   retrieving appeals. Use pagination parameters and limit page size to
   *   server-allowed maximum.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardAppeal.IRequest,
  ): Promise<IPageIDiscussionBoardAppeal.ISummary> {
    try {
      return await patchDiscussionBoardModeratorAppeals({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a DiscussionBoard appeal (discussion_board_appeals) — moderator
   * action.
   *
   * Purpose and overview:
   *
   * Allows privileged moderators to update an appeal's mutable properties in
   * the discussion_board_appeals table. Typical updates include status
   * transitions (e.g., 'pending' → 'accepted'|'rejected'), resolution_reason
   * text, resolved_at timestamp, and optional moderation_action_id linking the
   * resolution to a concrete moderation action. The endpoint returns the
   * updated appeal record.
   *
   * Security and permissions:
   *
   * Only moderator actors are authorized to call this endpoint. Implementations
   * MUST authenticate the caller as a moderator and MUST record the acting
   * moderator id in moderation audit trails
   * (discussion_board_moderation_audit). Unauthorized callers must receive a
   * 403 Forbidden response.
   *
   * Validation rules, referential integrity and business logic:
   *
   * - Validate appealId is a UUID; return 400 if invalid.
   * - Reject requests that attempt disallowed status transitions (for example
   *   moving from 'accepted' back to 'pending' without an explicative reason),
   *   returning 400 with details.
   * - If moderation_action_id is provided, ensure the referenced moderation
   *   action exists (discussion_board_moderation_actions); if the referenced
   *   action conflicts with current appeal state, return 409 Conflict.
   * - When setting resolved_at, validate it is an ISO 8601 datetime not earlier
   *   than created_at.
   *
   * Side effects and audit:
   *
   * After a successful update, the implementation SHOULD append an audit entry
   * to discussion_board_moderation_audit capturing moderator id, action details
   * and before/after appeal state. If appeal resolution changes content
   * visibility or retention timers, update related content workflows
   * accordingly.
   *
   * @param connection
   * @param appealId Unique identifier (UUID) of the appeal to update in
   *   discussion_board_appeals (UUID format)
   * @param body Fields to update on the appeal (status, resolution_reason,
   *   resolved_at, moderation_action_id)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":appealId")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("appealId")
    appealId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardAppeal.IUpdate,
  ): Promise<IDiscussionBoardAppeal> {
    try {
      return await putDiscussionBoardModeratorAppealsAppealId({
        moderator,
        appealId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
