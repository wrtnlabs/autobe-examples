import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorModerationAudits } from "../../../../providers/patchDiscussionBoardModeratorModerationAudits";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { getDiscussionBoardModeratorModerationAuditsModerationAuditId } from "../../../../providers/getDiscussionBoardModeratorModerationAuditsModerationAuditId";

import { IPageIDiscussionBoardModerationAudit } from "../../../../api/structures/IPageIDiscussionBoardModerationAudit";
import { IDiscussionBoardModerationAudit } from "../../../../api/structures/IDiscussionBoardModerationAudit";

@Controller("/discussionBoard/moderator/moderationAudits")
export class DiscussionboardModeratorModerationauditsController {
  /**
   * Search and retrieve paginated moderation audit entries.
   *
   * Provide a flexible search API for moderation audit entries. Intended for
   * moderators and investigators to query historical moderation events. The
   * request body supports filters (eventType, moderatorId, reportId,
   * moderationActionId), time range (occurredFrom, occurredTo), free-text
   * `textSearch` for payloads and pagination parameters (page, limit, sort).
   * Implementations MUST validate UUIDs and datetimes, enforce pagination
   * defaults and maximum limits (e.g., default limit 20, max limit 100) and
   * protect full-text queries with rate limits or privilege checks.
   *
   * Security and permissions: Access MUST be restricted to moderator actors.
   * `event_payload` may contain sensitive content; unless the caller has full
   * audit privileges, the service SHOULD redact or truncate `event_payload` in
   * results. Requests that include free-text searches on `event_payload` SHOULD
   * be rate-limited or require elevated privileges.
   *
   * Errors:
   *
   * - 200: Returns paginated list of moderation audit summaries.
   * - 400: Invalid filter formats or pagination parameters.
   * - 401/403: Unauthorized.
   * - 500: Server error. Include correlation id.
   *
   * @param connection
   * @param body Search criteria, filtering, pagination and sorting parameters
   *   for moderation audit entries (eventType, moderatorId, reportId,
   *   moderationActionId, occurredFrom, occurredTo, textSearch, page, limit,
   *   sort).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardModerationAudit.IRequest,
  ): Promise<IPageIDiscussionBoardModerationAudit.ISummary> {
    try {
      return await patchDiscussionBoardModeratorModerationAudits({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single moderation audit entry
   * (discussion_board_moderation_audit).
   *
   * Retrieve a single moderation audit entry by its identifier from the
   * append-only moderation audit table.
   *
   * Purpose and overview: Returns the immutable audit entry captured in
   * discussion_board_moderation_audit. This data is used for investigations and
   * compliance. The canonical stored payload (event_payload) is returned
   * according to the caller's privilege level: raw payload only for elevated
   * admin roles; moderated summary or redacted payload for standard moderator
   * roles.
   *
   * Security considerations and user permissions: Access is restricted to
   * authorized moderator or administrative actors. The service MUST log every
   * access to this endpoint in discussion_board_audit_log_accesses with
   * accessor id, accessor role, access_purpose (e.g., 'investigation'), ip, and
   * timestamp. Implement server-side redaction or privilege checks to avoid
   * leaking reporter contact information or other PII inside event_payload.
   *
   * Relationship to underlying database entities: Maps directly to the Prisma
   * model discussion_board_moderation_audit and returns the stored fields:
   * moderation_action_id, report_id, actor_moderator_id, event_type,
   * event_payload, occurred_at.
   *
   * Validation rules and business logic: Path parameter moderationAuditId is
   * required and must be a UUID. Return codes: 200 with the audit entry
   * (subject to redaction rules), 401 unauthorized, 403 forbidden (insufficient
   * role), 404 not found, 500 internal error.
   *
   * @param connection
   * @param moderationAuditId UUID identifier of the target moderation audit
   *   entry
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":moderationAuditId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("moderationAuditId")
    moderationAuditId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardModerationAudit> {
    try {
      return await getDiscussionBoardModeratorModerationAuditsModerationAuditId(
        {
          moderator,
          moderationAuditId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
