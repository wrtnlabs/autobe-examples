import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoListUserTodos } from "../../../../providers/postTodoListUserTodos";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoListUserTodos } from "../../../../providers/patchTodoListUserTodos";
import { getTodoListUserTodosTodoId } from "../../../../providers/getTodoListUserTodosTodoId";
import { putTodoListUserTodosTodoId } from "../../../../providers/putTodoListUserTodosTodoId";
import { deleteTodoListUserTodosTodoId } from "../../../../providers/deleteTodoListUserTodosTodoId";

import { ITodoListTodo } from "../../../../api/structures/ITodoListTodo";
import { IPageITodoListTodo } from "../../../../api/structures/IPageITodoListTodo";

@Controller("/todoList/user/todos")
export class TodolistUserTodosController {
  /**
   * Create a new todo task (todo_list_todos table) owned by the authenticated
   * user.
   *
   * Create a new todo item belonging to the authenticated user. This endpoint
   * enables users to add actionable business tasks to their personal todo list.
   * Each todo must include a brief title that is between 1 and 100 characters;
   * descriptions are optional, supporting up to 600 characters if provided. The
   * completion status defaults to false and can be updated later; a due date is
   * optional and, if supplied, must be a current or future ISO 8601 date.
   *
   * Only authenticated users may create new todos; ownership is enforced, and
   * users cannot assign todos to other users. Any attempt to submit an invalid
   * payload—such as missing a required title, using a duplicate title for the
   * same due date, or setting a due date in the past—will be rejected with a
   * clear error message. Submission also records creation and update times
   * automatically for history and sorting purposes.
   *
   * This operation directly persists todo data in the todo_list_todos table
   * with a unique index on [user, title, due_date] to prevent accidental
   * duplicate task entries. Related endpoints: update an existing todo (PUT
   * /todos/{todoId}), delete a todo (DELETE /todos/{todoId}), and search todos
   * (PATCH /todos).
   *
   * @param connection
   * @param body Data for creating a new todo task: title (required),
   *   description (optional), completed (defaults to false), due_date
   *   (optional).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.ICreate,
  ): Promise<ITodoListTodo> {
    try {
      return await postTodoListUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated, filterable list of todos from
   * todo_list_todos.
   *
   * Request a list of todo tasks, filtered and paginated according to advanced
   * user-defined criteria. The client may filter todos by completion status,
   * time window, or perform a search on title/description fields. Pagination
   * controls (page, pageSize) enable scalable handling of large datasets, and
   * sort options allow prioritizing specific tasks for display.
   *
   * All returned data is sourced from the todo_list_todos table, which holds
   * all user-generated todos. The schema provides fields for basic metadata,
   * due/completed flags, and optional notes. This operation is optimal for
   * rendering todo overviews or preview cards in applications.
   *
   * To ensure secure and private data handling, the operation will filter
   * results to only include tasks owned by or shared with the authenticated
   * user (enforced at the business logic/service layer, not in input).
   * Administrative users may search all records; normal users will see only
   * their own. Related endpoints include single-todo fetch, create, update, and
   * erase for detailed management workflows.
   *
   * @param connection
   * @param body Search, filter, and pagination parameters for listing todos,
   *   using the ITodoListTodo.IRequest DTO.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.IRequest,
  ): Promise<IPageITodoListTodo.ISummary> {
    try {
      return await patchTodoListUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch full detail for a single todo by ID from todo_list_todos.
   *
   * Retrieve all available data for a specific todo task using its unique
   * identifier as a path parameter. This endpoint is used for opening detail
   * views, supporting edit forms, or displaying task information in full
   * context to the user. The response contains all fields stored in the
   * todo_list_todos schema.
   *
   * Security is enforced so that only the owner or authorized collaborators may
   * access non-administrative tasks; attempts to fetch others' tasks will
   * result in access denial unless the authenticated actor holds administrative
   * privileges.
   *
   * This operation is designed for single-resource reads. For list displays and
   * search, use the paginated todos endpoint. For modifying or deleting a todo,
   * use the update or erase endpoints, respectively.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo, as a UUID string.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodo> {
    try {
      return await getTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo task by its UUID (todo_list_todos table).
   *
   * Update an existing todo item owned by the authenticated user. This endpoint
   * allows modification of key todo task attributes such as the title, the
   * optional long description, the completion status (true or false), and the
   * optional due date. Business rules such as title length, description maximum
   * length, and due date validation are strictly enforced at both the
   * application and persistence layer.
   *
   * To update a todo, the user must specify the todo's unique UUID identifier
   * in the path. If the specified todo does not exist or does not belong to the
   * user, the operation is rejected with a not-found or forbidden response. On
   * successful update, the todo's updated_at timestamp is automatically
   * refreshed. Ownership validation ensures data privacy and prevents
   * unauthorized modification of other users' tasks.
   *
   * This operation persists all changes to the todo_list_todos table and is
   * intended for granular task management. Related endpoints include task
   * creation (POST /todos) and todo deletion (DELETE /todos/{todoId}).
   *
   * @param connection
   * @param todoId Unique identifier (UUID) of the target todo item the user
   *   wishes to update.
   * @param body Fields to update for the specified todo task: title (required),
   *   description (optional), completed, and due_date as applicable.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListTodo.IUpdate,
  ): Promise<ITodoListTodo> {
    try {
      return await putTodoListUserTodosTodoId({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a todo from todo_list_todos by its unique identifier.
   *
   * Permanently remove a single todo task from the system for its owner user.
   * This action irreversibly deletes a business todo from persistent storage.
   *
   * This endpoint enforces owner-only access—only the authenticated user who
   * owns the todo (as referenced by todo_list_user_id) is allowed to perform
   * the deletion. If a user attempts to delete a todo owned by another user,
   * the request is denied with an authorization error. If the target todo does
   * not exist, a not found error is returned to maintain business integrity.
   *
   * This operation interacts directly with the todo_list_todos database table,
   * using the todo's universally unique identifier (UUID) as path parameter. As
   * the application follows strict data isolation, deleted todos are fully
   * removed (no soft deletion) with no opportunity for recovery after
   * completion. Security and audit compliance are maintained by logging
   * deletion events. This operation is typically used in conjunction with list,
   * detail, and create endpoints as part of a complete user todo management
   * workflow.
   *
   * @param connection
   * @param todoId Unique identifier (UUID) of the target todo record to be
   *   permanently deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
