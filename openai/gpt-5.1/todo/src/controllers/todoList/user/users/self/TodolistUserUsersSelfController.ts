import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { getTodoListUserUsersSelf } from "../../../../../providers/getTodoListUserUsersSelf";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { putTodoListUserUsersSelf } from "../../../../../providers/putTodoListUserUsersSelf";
import { deleteTodoListUserUsersSelf } from "../../../../../providers/deleteTodoListUserUsersSelf";

import { ITodoListUser } from "../../../../../api/structures/ITodoListUser";

@Controller("/todoList/user/users/self")
export class TodolistUserUsersSelfController {
  /**
   * Retrieve authenticated user's own account details (todo_list_users).
   *
   * Retrieve the authenticated user's own account information from the Todo
   * List service.
   *
   * This operation is designed for end-users to inspect their own identity,
   * profile, and account audit details, using the login context from their
   * session. Only the current user's data will ever be returned, and
   * authorization is strictly enforced.
   *
   * Fields include unique user ID, email address, timestamps of creation and
   * most recent update, as well as deleted_at if the account is in a
   * soft-deleted state. No sensitive fields such as raw password are available
   * from this endpoint. This operation forms the basis for all user-driven
   * account management features within the service.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoListUser> {
    try {
      return await getTodoListUserUsersSelf({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update own user account information (todo_list_users).
   *
   * Update specific details of the currently authenticated user's account in
   * the Todo List service.
   *
   * Permissible updates include changing the email address (with required
   * uniqueness and format constraints) and updating the password, which is
   * securely re-hashed and never exposed in plaintext. The operation enforces
   * attribute-level validation according to the todo_list_users schema, and
   * logs all changes for audit and security purposes.
   *
   * Strict security is ensured: the update may be performed only by the
   * authenticated user, with no cross-user updates possible from this endpoint.
   * Account updates are atomic and return the revised account information upon
   * success.
   *
   * @param connection
   * @param body Fields to update for the current authenticated user's account.
   *   Only mutable fields from todo_list_users are included.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.IUpdate,
  ): Promise<ITodoListUser> {
    try {
      return await putTodoListUserUsersSelf({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete the authenticated user's `todo_list_users` account and all
   * associated data.
   *
   * Permanently delete the currently authenticated user's account along with
   * all personal data including todos and session history.
   *
   * This operation can only be performed by a user on their own account.
   * Cross-account deletion is strictly forbidden. Upon invocation, the system
   * verifies that the caller is authenticated and that the user matches the
   * session. If authentication fails or the user is not found, an error
   * response is issued without revealing user existence information.
   *
   * When deletion is successful, all todos owned by the user (from the
   * `todo_list_todos` table) are deleted. Active and historical session records
   * (from the `todo_list_user_sessions`) are removed to ensure complete data
   * minimization and compliance with privacy requirements. There is no recovery
   * or soft-deletion—this is a hard, permanent remove. Rate limiting and audit
   * logging are applied to prevent abuse or accidental mass deletions.
   *
   * This action supersedes any pending operations for the user; all pending
   * tasks and sessions are cleared. The operation ends the authenticated
   * session and invalidates all access tokens, immediately logging the user out
   * after completion. No further actions can be performed once the account is
   * deleted.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @UserAuth()
    user: UserPayload,
  ): Promise<void> {
    try {
      return await deleteTodoListUserUsersSelf({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
