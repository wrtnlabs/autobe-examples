import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoListUser } from "../../../api/structures/ITodoListUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Register a new user in the todo_list_users table.
   *
   * This API operation enables new user registration by creating a record in
   * the `todo_list_users` table, which represents each registered end-user in
   * the Todo List application. The request must provide a unique email and a
   * securely hashed password, ensuring that only verified credentials allow
   * access to the service.
   *
   * Security considerations include enforcing uniqueness of `email`, hashing of
   * passwords using current best cryptographic standards, and immediate audit
   * of registration attempts. The table's `created_at` and `updated_at` fields
   * record the registration and any future account changes, while the
   * `deleted_at` field provides a soft-deletion mechanism, which is not
   * triggered by this endpoint.
   *
   * This endpoint ties directly to the single actor identity of the Todo List
   * application, ensuring each account is separate and cannot view or modify
   * other users' data. All business task ownership, session records, and
   * interactions track back to this primary key.
   *
   * Validation rules enforce proper email format, case-insensitive uniqueness,
   * and reject registrations that attempt to reuse deleted or existing
   * addresses. Account creation is always a public operation and requires no
   * existing authentication.
   *
   * The endpoint is critical to the authentication workflow: registration must
   * precede all login or session management, making this the foundational
   * endpoint for onboarding new users.
   *
   * @param connection
   * @param body New user registration fields, including unique email and
   *   password (plain, to be hashed server-side).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.IJoin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate user and issue JWT token (todo_list_users table).
   *
   * Authenticate a user using credentials in the `todo_list_users` table,
   * validating their unique email and password. Passwords are never stored or
   * transmitted in plain text but always processed as secure hashes. This
   * operation interacts with the `password_hash` and `email` columns for
   * verification and relies on `deleted_at` to determine if accounts are
   * eligible for login.
   *
   * Security considerations include constant-time comparison to prevent timing
   * attacks, full audit logging through session insertion in the
   * `todo_list_user_sessions` schema, and avoidance of explicit existence
   * confirmation for any user account.
   *
   * The endpoint ties every session and all business data ownership in the
   * application back to a valid, authenticated user record. Audit requirements
   * drive full contextual session logging.
   *
   * Input validation rejects malformed or non-unique emails and fails
   * authentication if the supplied credentials do not match. The endpoint is
   * fully public and does not require prior authentication.
   *
   * This operation must be used in conjunction with registration for account
   * onboarding and with token refresh for session continuity.
   *
   * @param connection
   * @param body Login credentials for authentication, including registered
   *   email and password (plain, for server-side verification).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ILogin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh user JWT token using session (todo_list_user_sessions table).
   *
   * Refresh an existing user session's JWT access token using a valid refresh
   * token, with all user and session validation handled against
   * `todo_list_user_sessions` and `todo_list_users` tables. Successful refresh
   * issues a new access token and updates session timestamps and audit
   * metadata.
   *
   * Privacy is maintained by never disclosing whether a session or user still
   * exists; errors give no additional information. The endpoint supports
   * continuous access security by limiting session lifetimes and granting users
   * flexible authentication continuity with strong integrity.
   *
   * This operation is core to supporting modern SPA and mobile session
   * lifecycles.
   *
   * Input is strictly limited to a valid refresh token, and output is a new
   * authentication payload in standard format. No user credentials are required
   * for this flow, and the endpoint is available only to clients already
   * holding a valid refresh token associated with an active session.
   *
   * @param connection
   * @param body Refresh token for current session, linked securely to
   *   user/session records.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListUser.IRefresh,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
