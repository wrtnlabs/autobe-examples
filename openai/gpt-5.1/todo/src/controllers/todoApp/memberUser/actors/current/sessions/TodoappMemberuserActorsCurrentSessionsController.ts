import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchTodoAppMemberUserActorsCurrentSessions } from "../../../../../../providers/patchTodoAppMemberUserActorsCurrentSessions";
import { MemberuserAuth } from "../../../../../../decorators/MemberuserAuth";
import { MemberuserPayload } from "../../../../../../decorators/payload/MemberuserPayload";
import { deleteTodoAppMemberUserActorsCurrentSessionsSessionId } from "../../../../../../providers/deleteTodoAppMemberUserActorsCurrentSessionsSessionId";

import { IPageITodoAppSession } from "../../../../../../api/structures/IPageITodoAppSession";
import { ITodoAppSession } from "../../../../../../api/structures/ITodoAppSession";

@Controller("/todoApp/memberUser/actors/current/sessions")
export class TodoappMemberuserActorsCurrentSessionsController {
  /**
   * Search and list sessions for the current actor using
   * todo_app_memberuser_sessions and todo_app_adminuser_sessions.
   *
   * Retrieve a filtered, paginated list of sessions associated with the
   * currently authenticated actor. This operation allows a logged-in member or
   * administrator to inspect their existing authentication sessions without
   * modifying them.
   *
   * From a security perspective, this endpoint is strictly read-only and does
   * not perform any creation, modification, or deletion of session records. It
   * exists to support features such as "view my active logins" or "audit where
   * I am signed in". The underlying data is stored in the
   * todo_app_memberuser_sessions and todo_app_adminuser_sessions Prisma models,
   * which typically include fields such as a unique session identifier, foreign
   * keys to the owning user, timestamps for creation and last activity, and
   * metadata about the client device or IP address. Only sessions that belong
   * to the currently authenticated actor are returned; there is no ability to
   * query sessions for other users.
   *
   * The request body uses ITodoAppSession.IRequest, which encapsulates optional
   * filter criteria and pagination parameters. These criteria can include time
   * ranges (for creation or last activity), device or user-agent strings, IP
   * address fragments, and a flag indicating whether to show only currently
   * active sessions versus historical ones. Pagination parameters in the same
   * DTO allow the client to control page size, page index, and sort ordering
   * while still using a single PATCH endpoint rather than encoding complex
   * filters into query parameters.
   *
   * The response body uses IPageITodoAppSession.ISummary, a paginated container
   * of concise session summary objects. Each summary includes the session's key
   * identifiers and human-relevant information such as device description, last
   * activity time, and an "active" indicator, but omits sensitive internal
   * details. This keeps the payload efficient while still giving the user clear
   * visibility into their login state across devices.
   *
   * This operation is related to the DELETE
   * /actors/current/sessions/{sessionId} endpoint, which allows terminating a
   * specific session. A typical workflow is for the client to first call this
   * PATCH endpoint to list all sessions, then allow the user to select one to
   * terminate using the delete operation. Error handling should cover cases
   * such as invalid pagination parameters in the request body or attempting to
   * use filters that the server cannot interpret, returning appropriate
   * validation errors without exposing internal implementation details.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for listing the
   *   current actor's sessions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberuserAuth()
    memberUser: MemberuserPayload,
    @TypedBody()
    body: ITodoAppSession.IRequest,
  ): Promise<IPageITodoAppSession.ISummary> {
    try {
      return await patchTodoAppMemberUserActorsCurrentSessions({
        memberUser,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Terminate a specific current-actor session from
   * todo_app_memberuser_sessions or todo_app_adminuser_sessions.
   *
   * Terminate a specific authentication session belonging to the currently
   * authenticated actor. This endpoint allows a member or administrator to
   * explicitly end one of their own login sessions, such as logging out a
   * session from another device.
   *
   * The underlying data is stored in the todo_app_memberuser_sessions and
   * todo_app_adminuser_sessions Prisma models. These models typically define a
   * primary key identifier for each session, a foreign key to the owning user
   * (member or admin), timestamp fields indicating when the session was created
   * and last used, and fields related to session validity or revocation. When
   * this DELETE operation is invoked with a particular sessionId, the service
   * will locate the corresponding row in the appropriate table for the current
   * actor, validate that ownership, and then terminate the session by updating
   * or deleting the record according to the retention rules defined for the
   * session tables.
   *
   * Security is a primary concern for this operation. The implementation must
   * ensure that the caller can only terminate sessions that belong to
   * themselves. Even if a valid sessionId is provided, if that session does not
   * belong to the current actor, the service should respond with an
   * authorization error or a not-found response that does not reveal whether
   * the ID corresponds to another user's session. This protects against
   * attempts to tamper with other users' authentication state.
   *
   * This DELETE endpoint is closely related to the PATCH
   * /todoApp/memberUser/actors/current/sessions operation, which lists the
   * caller's sessions for selection. A typical client workflow is to first call
   * the listing endpoint, display all sessions, and then for any session the
   * user chooses to terminate, invoke this delete endpoint with the
   * corresponding sessionId. Error handling should cover cases such as
   * providing a malformed sessionId, specifying a session that does not exist
   * or has already been terminated, and attempting to terminate a session when
   * the caller is not properly authenticated.
   *
   * @param connection
   * @param sessionId Unique identifier of the target session belonging to the
   *   current actor.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @MemberuserAuth()
    memberUser: MemberuserPayload,
    @TypedParam("sessionId")
    sessionId: string,
  ): Promise<void> {
    try {
      return await deleteTodoAppMemberUserActorsCurrentSessionsSessionId({
        memberUser,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
