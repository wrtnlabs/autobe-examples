import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchTodoAppAdminUserActorsSearch } from "../../../../../providers/patchTodoAppAdminUserActorsSearch";
import { AdminuserAuth } from "../../../../../decorators/AdminuserAuth";
import { AdminuserPayload } from "../../../../../decorators/payload/AdminuserPayload";

import { IPageITodoAppActorSearch } from "../../../../../api/structures/IPageITodoAppActorSearch";
import { ITodoAppActorSearch } from "../../../../../api/structures/ITodoAppActorSearch";

@Controller("/todoApp/adminUser/actors/search")
export class TodoappAdminuserActorsSearchController {
  /**
   * Search todoApp user actors across guest, member, and admin Prisma tables
   * and return a paginated summary list.
   *
   * Search todoApp actors (guest users, member users, and admin users) using
   * flexible criteria and retrieve a paginated list of summarized actor
   * records.
   *
   * This operation is designed for administrative and operational use cases
   * where a supervisor or support agent needs to locate and inspect various
   * kinds of actors in the system. An "actor" in this context is a conceptual
   * union over the concrete user entities represented by the Prisma models
   * `todo_app_guestusers`, `todo_app_memberusers`, and `todo_app_adminusers`.
   * These tables hold identities for unauthenticated guests, authenticated end
   * users who own todo lists, and privileged administrators of the service,
   * respectively. The API does not expose raw table structures directly;
   * instead, it returns a normalized summary that indicates the actor type and
   * key identifiers.
   *
   * The request body, represented by `ITodoAppActorSearch.IRequest`, allows
   * callers to filter by actor type, by creation or last-activity date ranges
   * (as supported by the underlying tables), and by identifying values such as
   * email or username where they exist on the member and admin models. It also
   * includes pagination controls (like page number and page size) and sorting
   * preferences (such as newest first or alphabetical by display name). These
   * fields are validated against business rules from the requirements, for
   * example limiting maximum page size to protect performance and enforcing
   * that at least one filter is present for potentially expensive queries.
   *
   * From a security perspective this endpoint is restricted to administrative
   * actors, represented by `authorizationActors: ["adminUser"]`. Only users
   * mapped to that actor type may invoke this operation, because it can expose
   * sensitive information about accounts and internal administrative
   * identities. Implementation must ensure that the effective caller is
   * authorized and that results may be further constrained based on the
   * caller’s administrative scope if such rules exist. This endpoint is
   * read-only: it does not modify any data in the underlying Prisma tables and
   * is intended purely for search and inspection.
   *
   * Related endpoints in a full system might include administrative detail
   * views for single member or admin users, or additional analytics endpoints
   * that aggregate actor statistics. However, `/actors/search` stands on its
   * own as the primary, flexible search surface for locating actors across the
   * todoApp domain. Errors include validation failures when search criteria are
   * malformed, authorization errors when a non-admin attempts to use the
   * endpoint, and generic server errors if underlying database queries fail or
   * time out.
   *
   * @param connection
   * @param body Search criteria, pagination, and sorting options for querying
   *   todoApp actors across guest, member, and admin user tables.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminuserAuth()
    adminUser: AdminuserPayload,
    @TypedBody()
    body: ITodoAppActorSearch.IRequest,
  ): Promise<IPageITodoAppActorSearch.ISummary> {
    try {
      return await patchTodoAppAdminUserActorsSearch({
        adminUser,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
