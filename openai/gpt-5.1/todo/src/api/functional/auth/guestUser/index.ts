/**
 * This operation registers a new guest user concept in the todo_app_guestusers
 * table and issues initial authorization tokens for the guestUser actor. The
 * underlying Prisma table todo_app_guestusers is designed to represent
 * unauthenticated visitors, with an id field as the primary key and optional
 * metadata fields. When this endpoint is called, the service will create a new
 * row with a generated id and timestamps in created_at and updated_at,
 * optionally using the provided external_ref to correlate with external
 * analytics or tracking systems.
 *
 * From a security perspective, this endpoint is intentionally public
 * (authorizationActor is null) because guest users do not yet have any
 * credentials or authenticated identity. However, the service must implement
 * rate limiting and abuse prevention at an infrastructure level, as repeated
 * creation of guest concepts could be used for resource exhaustion. The
 * external_ref field, when supplied, should be validated as a bounded-length
 * string to avoid log pollution or injection issues.
 *
 * On the database side, the todo_app_guestusers table stores external_ref as a
 * nullable string, created_at as a non-null timestamp of when the record is
 * created, and updated_at as a non-null timestamp updated whenever the record
 * is modified. This API operation will populate created_at and updated_at with
 * the current server time when inserting the new guest concept row. The id
 * field is generated as a UUID, guaranteeing uniqueness across all guestUser
 * records.
 *
 * The business logic for this operation does not create any todos or sessions;
 * guest users in this system never own todo_app_todos records and do not have
 * dedicated session tables. Instead, the returned ITodoAppGuestUser.IAuthorized
 * payload will embed token information (such as accessToken and refreshToken
 * properties defined in the DTO) associated with the created guest id, allowing
 * subsequent token-based access to other public or guest-limited endpoints.
 *
 * Validation rules include ensuring that external_ref, if provided, conforms to
 * any length or format constraints defined in the
 * ITodoAppGuestUser.IJoinRequest DTO and matches the semantics described for
 * external_ref in the todo_app_guestusers schema: an optional reference or
 * correlation identifier. The system should also ensure that timestamps are
 * generated server-side and not taken from client input. If insertion fails due
 * to database errors, the API must return an appropriate 5xx error with a
 * generic message while logging details internally.
 *
 * This operation is typically used at the beginning of guest journeys as
 * described in the requirements, where an unauthenticated visitor first
 * interacts with the todo service and needs a transient identifier for
 * analytics or feature gating. Related operations in the same authentication
 * workflow are the guestUser refresh endpoint, which renews tokens based on a
 * valid refresh token, and various public read-only endpoints that accept the
 * guest's access token to personalize or track usage without associating
 * persistent personal data.
 *
 * @param props.connection
 * @param props.body Guest join request payload containing optional external
 *   reference or metadata necessary to create a todo_app_guestusers record and
 *   establish an authorized guestUser context.
 * @setHeader token.access Authorization
 *
 * @path /auth/guestUser/join
 * @accessor api.functional.auth.guestUser.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
