import { IETodoAppActorKind } from "./IETodoAppActorKind";
import { ITodoAppAdminUser } from "./ITodoAppAdminUser";
import { ITodoAppMemberUser } from "./ITodoAppMemberUser";
import { ITodoAppGuestUser } from "./ITodoAppGuestUser";

/**
 * Unified representation of the actor currently authenticated in the todoApp
 * service.
 *
 * This DTO does not map directly to a single Prisma table; instead it
 * aggregates identity and role information derived from the active security
 * context, which may point to an admin user, member user, or guest user record.
 * It is returned by the `/todoApp/memberUser/actors/current` endpoint so that
 * clients can bootstrap their state after authentication without knowing
 * underlying table structures.
 *
 * The structure exposes which actor kind is active and provides exactly one
 * non-null summary object for the concrete actor implementation (for example an
 * admin summary when the actorKind is `adminUser`). It intentionally excludes
 * sensitive authentication material such as password hashes, and it relies on
 * session or token mechanisms for actual authentication state.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoAppActorCurrent = {
  /**
   * Kind of actor that is currently authenticated.
   *
   * This value tells the client whether the authenticated principal is an
   * administrative user, a member user, or a guest. It is used to branch UI
   * flows and authorization checks, and it corresponds to one of the concrete
   * summary objects embedded in this DTO.
   */
  actorKind: IETodoAppActorKind;

  /**
   * Administrative user summary when the current actor is an admin, or null
   * otherwise.
   *
   * When `actorKind` is `adminUser`, this property contains a populated
   * `ITodoAppAdminUser.ISummary` object summarizing the admin account
   * associated with the current session or token. For other actor kinds it
   * will be null so that clients do not need to guess which summary is
   * relevant.
   */
  adminUser: ITodoAppAdminUser.ISummary | null;

  /**
   * Member user summary when the current actor is an authenticated member, or
   * null otherwise.
   *
   * If `actorKind` is `memberUser`, this property contains a lightweight view
   * of the owning member account from `todo_app_memberusers`. It remains null
   * for admin or guest sessions, ensuring only one concrete actor summary is
   * populated at a time.
   */
  memberUser: ITodoAppMemberUser.ISummary | null;

  /**
   * Guest user summary when the current actor corresponds to a guest concept,
   * or null otherwise.
   *
   * For sessions or tokens that represent guests rather than authenticated
   * accounts, this property carries a summary of the relevant
   * `todo_app_guestusers` record if one exists. In all other actor modes the
   * value is null and should be ignored by clients.
   */
  guestUser: ITodoAppGuestUser.ISummary | null;
};
