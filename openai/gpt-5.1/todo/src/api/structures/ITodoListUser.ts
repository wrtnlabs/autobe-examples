/**
 * Authenticated Todo List service user account entity.
 *
 * Represents a single registered user within the Todo List application. This
 * type is returned when retrieving the authenticated user's account details.
 * Includes unique ID, email, (soft) deletion status, and audit timestamps.
 * Passwords, hashes, and any sensitive authentication context are excluded for
 * security. Each user owns their own todos; direct relations are not included
 * in this DTO, keeping strict privacy boundaries between users.
 *
 * Field and business rules are derived directly from the todo_list_users Prisma
 * model. Data isolation and actor boundaries are strictly enforced—no
 * cross-account access is ever possible via API or DTO structure.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoListUser = {
  /** Primary Key. Uniquely identifies each user account. Read-only. */
  id: string & tags.Format<"uuid">;

  /**
   * Unique email address for login. Case-insensitive. Required, enforced
   * unique in app and DB. Never exposed to other users.
   */
  email: string;

  /** Timestamp for when the user account was first created. */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp of last modification to user account data (e.g., password or
   * email update). Always present.
   */
  updated_at: string & tags.Format<"date-time">;

  /** Null unless account is soft-deleted. Present for audit and recovery. */
  deleted_at?: (string & tags.Format<"date-time">) | null | undefined;
};
