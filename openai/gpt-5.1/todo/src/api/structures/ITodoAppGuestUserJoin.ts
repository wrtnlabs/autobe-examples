import { tags } from "typia";

export namespace ITodoAppGuestUserJoin {
  /**
   * Request payload for establishing or reusing a guestUser identity and
   * creating an associated guest session.
   *
   * This DTO captures client-supplied context used to seed the
   * `todo_app_guestusers` identity row and the `todo_app_guestuser_sessions`
   * session row. It is intentionally minimal and unauthenticated, allowing
   * any visitor to initiate a guest session for tracking, analytics, or later
   * upgrade flows.
   *
   * The properties map conceptually to `external_reference` and
   * `display_name` in `todo_app_guestusers`, and to `ip`, `href`, and
   * `referrer` in `todo_app_guestuser_sessions`. System-managed fields such
   * as `status`, `created_at`, and `updated_at` are not exposed here and must
   * be populated server-side based on business rules and Prisma defaults.
   */
  export type IRequest = {
    /**
     * Optional external reference identifier for this guest user.
     *
     * This value is conceptually aligned with
     * `todo_app_guestusers.external_reference` and can be used to link the
     * guest identity to cookies, device identifiers, or external systems.
     * When provided, the implementation may attempt to reuse an existing
     * guest identity row that has the same external reference instead of
     * creating a new one.
     *
     * Typical values are opaque strings generated by the client or
     * front-end infrastructure. The backend should treat this as a stable
     * but non-sensitive identifier and may normalize or validate length and
     * character set according to service policy.
     */
    external_reference?: string | undefined;

    /**
     * Optional human-readable nickname or label for the guest user.
     *
     * This value seeds the `display_name` field in `todo_app_guestusers`
     * when creating or updating a guest identity. It is used only for
     * presentation and analytics and has no authentication significance.
     *
     * The value should be a short, user-friendly string such as "Guest on
     * iPhone" or "Trial User", and can be omitted when no nickname is
     * needed.
     */
    display_name?: string | undefined;

    /**
     * Client IP address for this guest session.
     *
     * This property maps to the non-nullable `ip` column in
     * `todo_app_guestuser_sessions` and is used for audit, telemetry, and
     * security analysis. In many deployments the server can reliably derive
     * the IP from HTTP headers or connection metadata, but this field
     * allows clients—especially SSR or proxied environments—to explicitly
     * provide the value when they have more accurate information.
     *
     * When this field is omitted or blank in the request, the
     * implementation is responsible for resolving and persisting an
     * appropriate non-null IP value based on server-side context, ensuring
     * that the underlying Prisma model constraint is always satisfied.
     */
    ip?: string | undefined;

    /**
     * Full URL that the guest initially accessed when this session was
     * established.
     *
     * This property corresponds to the `href` column in
     * `todo_app_guestuser_sessions`. It records the landing page or route
     * that initiated the guest session, enabling downstream analytics and
     * debugging of navigation flows.
     *
     * Clients should provide the complete absolute URL, including scheme,
     * host, path, and query string where applicable. The value must be a
     * valid URI as enforced by the `format: "uri"` constraint so that
     * consumers can safely rely on it for logging, analysis, and
     * redirection logic.
     */
    href: string & tags.Format<"uri">;

    /**
     * Referrer URL indicating where the guest user navigated from when the
     * session started.
     *
     * This field is stored in `todo_app_guestuser_sessions.referrer` and
     * helps reconstruct user journeys and acquisition channels. It
     * typically originates from the browser `document.referrer` value or an
     * equivalent signal in non-browser environments.
     *
     * Clients should send an absolute URL when available; in cases where
     * there is no natural referrer (for example, direct navigation), they
     * may send a synthetic or sentinel referrer URI according to API-level
     * conventions. Regardless of origin, the value must conform to the
     * `format: "uri"` constraint to ensure consistent handling by
     * downstream tooling.
     */
    referrer: string & tags.Format<"uri">;
  };
}
