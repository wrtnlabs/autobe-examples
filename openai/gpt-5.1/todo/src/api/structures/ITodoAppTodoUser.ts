/**
 * Todo user account entity exposed to administrative APIs.
 *
 * Represents a registered end-user account for the todoApp service, modeled as
 * a safe projection of the underlying `todo_app_todousers` Prisma table. It is
 * designed for administrative inspection and management flows where todoAdmin
 * actors need to see identity and lifecycle information for a specific todo
 * user.
 *
 * This DTO intentionally excludes any password-related fields such as
 * `password_hash` so that credential secrets are never serialized into API
 * responses, logs, or external systems. It focuses on business-visible
 * attributes like email, display name, account status, last login timestamp,
 * and creation / update metadata.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoAppTodoUser = {
  /**
   * Primary key of the todo user account.
   *
   * This value corresponds directly to the `id` column of the
   * `todo_app_todousers` table and uniquely identifies a single todoUser
   * actor. It is used as the `todoUserId` path parameter in administrative
   * endpoints and is immutable for the lifetime of the account.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Unique email address for this todo user.
   *
   * The email acts as the primary login identifier and contact point for the
   * todo user. It maps to the `email` column in the `todo_app_todousers`
   * table, which has a unique index so that no two accounts can share the
   * same address.
   *
   * Administrative update flows must respect the uniqueness constraint, and
   * conflicting updates should produce a clear validation error.
   */
  email: string & tags.Format<"email">;

  /**
   * Optional human-readable display name for this todo user.
   *
   * This field corresponds to the nullable `display_name` column in
   * `todo_app_todousers`. When present, it is shown in user interfaces and
   * administrative consoles instead of or alongside the email address.
   *
   * When null, consumers should gracefully fall back to using the email or
   * another identifier for display purposes.
   */
  display_name?: string | null | undefined;

  /**
   * Current lifecycle status of the todo user account.
   *
   * This value maps to the non-nullable `status` column of
   * `todo_app_todousers`. Typical values include business-level states such
   * as "active", "suspended", or "closed" according to account lifecycle
   * rules.
   *
   * Administrative tooling uses this field to determine whether the user can
   * log in or interact with Todos, and to drive workflows for suspension or
   * reactivation.
   */
  status: string;

  /**
   * Timestamp of the last successful login for this todo user.
   *
   * This field is backed by the nullable `last_login_at` column in
   * `todo_app_todousers`. It records when the user last authenticated
   * successfully.
   *
   * The value is null when the account has never successfully logged in.
   * Administrative consumers can use this for audit views and to identify
   * inactive accounts.
   */
  last_login_at?: (string & tags.Format<"date-time">) | null | undefined;

  /**
   * Creation timestamp of the todo user account.
   *
   * This field maps to the non-nullable `created_at` column of
   * `todo_app_todousers`. It records when the user account row was first
   * inserted into the database.
   *
   * The value is system-managed and immutable from the perspective of API
   * clients, providing a stable reference point for audits and lifecycle
   * analysis.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Last update timestamp of the todo user account.
   *
   * This field corresponds to the non-nullable `updated_at` column of
   * `todo_app_todousers`. It is automatically refreshed by the service
   * whenever mutable attributes of the user account change.
   *
   * Administrative consumers can compare `updated_at` to `created_at` to
   * understand how recently the account was modified and to assist in
   * debugging or reconciliation tasks.
   */
  updated_at: string & tags.Format<"date-time">;
};
