/**
 * Retrieve a filtered and paginated collection of report records targeting a
 * specific attachment on an article, enabling moderators to review how that
 * attachment has been reported.
 *
 * This endpoint operates over the discussion_board_reports primary table, which
 * holds individual report entities describing why a piece of content has been
 * flagged, and the discussion_board_report_of_attachments subsidiary table,
 * which associates those reports with a particular attachment. The attachment
 * itself is defined in the discussion_board_attachments table and is related to
 * a parent article in the discussion_board_articles table. The path parameters
 * articleId and attachmentId together identify the attachment whose related
 * reports are to be listed.
 *
 * Because report data often contains sensitive information such as reporter
 * identities, internal moderation notes, and detailed reason text, this API
 * must be restricted to privileged actors. The authorizationActors field is set
 * to ["adminUser"] to indicate that only authenticated administrative users, as
 * modeled in the discussion_board_adminusers table, should be permitted to
 * access this endpoint. Implementations must enforce appropriate authentication
 * and authorization around this actor.
 *
 * The request body uses the IDiscussionBoardReport.IRequest DTO, which
 * encapsulates complex search criteria including status filters (for example,
 * pending, under_review, resolved), reason categories, reporter account type
 * (guest, member, or admin), and date ranges. It also supports pagination and
 * sorting settings so that clients can request specific pages of results in a
 * particular order. The server must interpret these criteria, construct a
 * corresponding query that joins discussion_board_reports with
 * discussion_board_report_of_attachments and their related article/attachment
 * records, and apply pagination.
 *
 * The response body returns an IPageIDiscussionBoardReport.ISummary payload
 * representing a paginated container of report summary records. Each summary
 * entry should provide enough information for moderators to quickly understand
 * the nature of the report (such as status, primary reason, created timestamp,
 * and minimal reporter/target identifiers) without exposing unnecessary
 * internal details. If either the articleId or attachmentId does not correspond
 * to an existing record, or if the attachment is not actually linked to the
 * given article, the implementation should respond with an appropriate domain
 * error (typically a 404 Not Found) instead of returning an empty list, to
 * avoid masking misuse of the path parameters.
 *
 * This operation is intended to be used alongside other report management APIs,
 * such as endpoints that retrieve full report details for a particular report
 * ID or that update report status. Together they support a complete moderation
 * workflow for attachment-related content on the discussion board.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article that owns the target
 *   attachment whose related reports are being queried.
 * @param props.attachmentId Unique identifier of the attachment belonging to
 *   the specified article for which associated reports should be listed.
 * @param props.body Search criteria, filters, and pagination parameters for
 *   retrieving reports about the specified attachment.
 * @path /discussionBoard/adminUser/articles/:articleId/attachments/:attachmentId/reportLinks
 * @accessor api.functional.discussionBoard.adminUser.articles.attachments.reportLinks.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the article that owns the target attachment
     * whose related reports are being queried.
     */
    articleId: string;

    /**
     * Unique identifier of the attachment belonging to the specified
     * article for which associated reports should be listed.
     */
    attachmentId: string;

    /**
     * Search criteria, filters, and pagination parameters for retrieving
     * reports about the specified attachment.
     */
    body: IDiscussionBoardReport.IRequest;
  };
  export type Body = IDiscussionBoardReport.IRequest;
  export type Response = IPageIDiscussionBoardReport.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/adminUser/articles/:articleId/attachments/:attachmentId/reportLinks",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/adminUser/articles/${encodeURIComponent(props.articleId ?? "null")}/attachments/${encodeURIComponent(props.attachmentId ?? "null")}/reportLinks`;
  export const random = (): IPageIDiscussionBoardReport.ISummary =>
    typia.random<IPageIDiscussionBoardReport.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.param("attachmentId")(() => typia.assert(props.attachmentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
