/**
 * Retrieve aggregated statistics of moderation reports grouped by reason_code
 * based on data stored in the discussion_board_reports table.
 *
 * The primary purpose of this endpoint is to provide administrators with an
 * at-a-glance view of how frequently each report reason is used across the
 * discussion board. Each row in discussion_board_reports represents a single
 * report, with target_type describing what was reported (for example, an
 * article, comment, or attachment), reporter_type identifying whether a member
 * user or admin user filed the report, reason_code indicating the main category
 * such as "hate_abuse", "harassment", "spam", "off_topic",
 * "dangerous_misleading", or "other", description capturing optional free-text
 * justification when needed, status tracking workflow stage (like "submitted",
 * "in_review", or "resolved"), action capturing the final moderation decision
 * (like "none", "keep", "hide_content", "delete_content", or "restrict_user"),
 * and created_at/updated_at storing timestamps. The aggregation logic groups
 * these report rows by reason_code, and computes counts and possibly
 * percentages for each reason.
 *
 * From an authorization and security perspective, only administrative staff
 * should see this level of moderation analytics, because it reveals internal
 * categorization and volumes of problematic content, which are not intended for
 * regular members. Therefore the endpoint is restricted to the adminUser actor
 * via authorizationActors set to ["adminUser"]. Actual authentication and
 * session management are handled by other parts of the system; this operation
 * assumes it is invoked only when an admin user has been properly
 * authenticated.
 *
 * The request body, typed as IDiscussionBoardReportByReasonStatistics.IRequest,
 * is designed to express a rich set of filters. For example, an administrator
 * can limit the statistics to a particular date range using created_at or
 * updated_at boundaries, focus only on certain target_type values (like only
 * "article" reports), restrict to specific reporter_type values, or combine
 * filters on status and action to understand how many reports of each type
 * remain unresolved or have led to content removal or user restriction. The
 * implementation will translate these filters into WHERE conditions over
 * discussion_board_reports (and, when necessary, joins to subsidiary link
 * tables such as discussion_board_report_of_articles,
 * discussion_board_report_of_comments, discussion_board_report_of_attachments,
 * discussion_board_report_of_memberusers, and
 * discussion_board_report_of_adminusers), before performing the GROUP BY
 * reason_code aggregation.
 *
 * The response body uses the IDiscussionBoardReportByReasonStatistics DTO. This
 * type does not map one-to-one to any Prisma model; instead, it represents
 * computed rows where each entry includes a reason_code and aggregated metrics
 * such as total_count, and possibly additional derived values depending on the
 * project’s analytics design. Typically, the DTO encapsulates a collection of
 * statistics rows, each corresponding to a single reason_code.
 *
 * Errors such as invalid filter shapes, unsupported reason_code values, or
 * contradictory conditions must be reported according to the shared
 * error-handling conventions of the API (for example, using structured
 * validation errors). The endpoint is intended to be used by moderation
 * dashboards and reporting UIs that need to chart or tabulate report volumes by
 * reason over selected time periods.
 *
 * @param props.connection
 * @param props.body Filter and search criteria defining which
 *   discussion_board_reports rows are included in the by-reason aggregation,
 *   including time ranges, target_type, reporter_type, status, action, and
 *   optional reason_code subsets.
 * @path /discussionBoard/adminUser/reports/statistics/byReason
 * @accessor api.functional.discussionBoard.adminUser.reports.statistics.byReason.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Filter and search criteria defining which discussion_board_reports
     * rows are included in the by-reason aggregation, including time
     * ranges, target_type, reporter_type, status, action, and optional
     * reason_code subsets.
     */
    body: IDiscussionBoardReportByReasonStatistics.IRequest;
  };
  export type Body = IDiscussionBoardReportByReasonStatistics.IRequest;
  export type Response = IDiscussionBoardReportByReasonStatistics;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/adminUser/reports/statistics/byReason",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/discussionBoard/adminUser/reports/statistics/byReason";
  export const random = (): IDiscussionBoardReportByReasonStatistics =>
    typia.random<IDiscussionBoardReportByReasonStatistics>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
