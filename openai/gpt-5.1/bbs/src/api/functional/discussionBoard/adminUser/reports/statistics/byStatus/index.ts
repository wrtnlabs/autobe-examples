/**
 * Retrieve aggregated statistics of moderation reports grouped by status based
 * on the discussion_board_reports table.
 *
 * This endpoint lets administrators monitor the state of the moderation queue
 * by counting how many reports exist for each status value. Each record in
 * discussion_board_reports carries a status such as "submitted", "in_review",
 * or "resolved", alongside related information like target_type, reporter_type,
 * reason_code, description, action, and timestamps created_at and updated_at.
 * The service applies filters from the request body to the
 * discussion_board_reports table and then groups the remaining rows by status,
 * computing per-status counts and potentially additional metrics needed for
 * dashboards.
 *
 * Only admin users should access this endpoint because it exposes internal
 * workload and decision distributions that would not be appropriate for general
 * members. To reflect this, authorizationActors is set to ["adminUser"].
 * Authentication, session validation, and any role-based access control
 * enforcement are delegated to the surrounding infrastructure; by the time this
 * operation executes, it assumes that the caller represents a valid admin
 * user.
 *
 * The request body is structured as
 * IDiscussionBoardReportByStatusStatistics.IRequest and is intended to support
 * rich filtering scenarios. Administrators may specify created_at or updated_at
 * time ranges to focus on recent reports, restrict by target_type to view only
 * article-related or attachment-related workloads, constrain by reporter_type
 * to examine memberuser versus adminuser submissions, or filter by specific
 * reason_code and action combinations to understand how certain categories are
 * progressing through the workflow. Internally, these filters become conditions
 * over discussion_board_reports, with optional joins to link tables such as
 * discussion_board_report_of_articles, discussion_board_report_of_comments,
 * discussion_board_report_of_attachments,
 * discussion_board_report_of_memberusers, and
 * discussion_board_report_of_adminusers when deeper scoping is needed.
 *
 * The response uses the IDiscussionBoardReportByStatusStatistics DTO, which
 * encapsulates analytical rows instead of direct Prisma entities. Each row
 * typically includes a status value and associated counts (and potentially
 * derived metrics like proportions), and the DTO normally represents a
 * collection of such per-status statistics entries.
 *
 * Any invalid filter structures, unsupported literal values for status or
 * related fields, or contradictions in the request should be reported back
 * following the project’s standard validation and error-handling conventions.
 * These statistics are intended to drive moderation dashboards, SLA monitoring
 * panels, and other internal tools that visualize report handling performance
 * over time.
 *
 * @param props.connection
 * @param props.body Filter and search criteria defining which
 *   discussion_board_reports rows are included in the by-status aggregation,
 *   including created_at/updated_at ranges, target_type, reporter_type,
 *   reason_code, and action filters.
 * @path /discussionBoard/adminUser/reports/statistics/byStatus
 * @accessor api.functional.discussionBoard.adminUser.reports.statistics.byStatus.indexByStatus
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function indexByStatus(
  connection: IConnection,
  props: indexByStatus.Props,
): Promise<indexByStatus.Response> {
  return true === connection.simulate
    ? indexByStatus.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...indexByStatus.METADATA,
          path: indexByStatus.path(),
          status: null,
        },
        props.body,
      );
}
