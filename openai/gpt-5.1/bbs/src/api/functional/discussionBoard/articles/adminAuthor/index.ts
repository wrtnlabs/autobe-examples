import { IDiscussionBoardArticleOfAdminusersAdminAuthor } from "../../../../structures/IDiscussionBoardArticleOfAdminusersAdminAuthor";

/**
 * Retrieve information about the admin user who authored a particular
 * discussion board article.
 *
 * In the economic and political discussion board, some articles are written by
 * administrator users whose accounts are stored in the
 * `discussion_board_adminusers` table. The authorship relationship for those
 * articles is captured in the `discussion_board_article_of_adminusers`
 * subsidiary table. Clients call this endpoint with an `articleId` path
 * parameter that identifies a row in `discussion_board_articles`. The backend
 * then resolve the relevant `discussion_board_article_of_adminusers` record
 * and, based on that, fetches the associated admin user profile.
 *
 * From a security and governance perspective, the response must be limited to
 * admin profile information that is intended for public exposure as an article
 * author. This may include admin display name, title or role labels, and other
 * non-sensitive metadata that conveys the administrator's status or function on
 * the board. Internal-only fields such as privileged access scopes, internal
 * staff notes, or contact information not meant for end users must never be
 * included. Because the endpoint is read-only and only returns information that
 * would normally be visible wherever admin-authored articles are presented, it
 * can typically be made publicly accessible.
 *
 * The operation is tightly coupled to the `discussion_board_articles` and
 * `discussion_board_article_of_adminusers` tables. If the referenced article
 * does not exist, has no admin authorship record, or has been removed or hidden
 * according to moderation rules, the implementation should return an
 * appropriate error state to indicate that admin author information is
 * unavailable. This endpoint will often be used alongside the general article
 * retrieval endpoint and comment listing endpoints, enabling clients to render
 * a clear banner or badge showing that the article was posted by an
 * administrator rather than a regular member user.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article in the
 *   `discussion_board_articles` table for which the admin user author
 *   information should be retrieved.
 * @path /discussionBoard/articles/:articleId/adminAuthor
 * @accessor api.functional.discussionBoard.articles.adminAuthor.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target article in the
     * `discussion_board_articles` table for which the admin user author
     * information should be retrieved.
     */
    articleId: string;
  };
  export type Response = IDiscussionBoardArticleOfAdminusersAdminAuthor;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/articles/:articleId/adminAuthor",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/adminAuthor`;
  export const random = (): IDiscussionBoardArticleOfAdminusersAdminAuthor =>
    typia.random<IDiscussionBoardArticleOfAdminusersAdminAuthor>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
