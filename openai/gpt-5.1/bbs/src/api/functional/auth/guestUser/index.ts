/**
 * Register or materialize a guest placeholder account in
 * discussion_board_guestusers and issue JWT tokens for guestUser.
 *
 * This API operation registers or materializes a guest user placeholder account
 * in the discussion board system based on the Prisma table
 * discussion_board_guestusers.
 *
 * The underlying discussion_board_guestusers table has an id primary key of
 * type uuid that uniquely identifies each guest user placeholder record. The
 * core business identifier stored for a guest is anonymous_token, a non-null
 * string that serves as an opaque token or fingerprint to correlate the same
 * unauthenticated visitor across visits. The schema enforces a unique index on
 * anonymous_token so that the same token cannot map to multiple guest rows,
 * which allows this endpoint to either create a new record or reuse an existing
 * one when the same token is presented.
 *
 * The table also has created_at and updated_at datetime fields that capture
 * when the guest record was created and last updated. These timestamps must be
 * maintained consistently whenever a new guest is created or when an existing
 * guest record is touched as part of join processing. Additionally, there is a
 * nullable deleted_at field that marks when a guest record has been closed or
 * is no longer in active use. When deleted_at is not null, the system should
 * treat the guest as inactive and either create a new record or restore the
 * existing one according to business policy.
 *
 * From a security perspective, this endpoint does not collect passwords or
 * personally identifiable information. It instead relies on the opaque
 * anonymous_token to represent the guest identity and then issues JWT tokens
 * for the guestUser actor role. The token payload will internally reference the
 * discussion_board_guestusers.id value so the backend can later resolve
 * guest-specific state if needed, while still keeping the external interface
 * minimal.
 *
 * Validation rules should ensure that anonymous_token is a non-empty string
 * that meets any length or pattern constraints defined at the DTO level, and
 * that a single active guest record exists per token, in line with the unique
 * index on anonymous_token. If an existing record is found with a non-null
 * deleted_at timestamp, the implementation should either reject the join or
 * clear deleted_at and update updated_at, depending on defined business rules.
 *
 * This operation is typically the first step for guests that need a persistent
 * identity for features like tracking read history or later conversion to a
 * full member account. It works together with the guest token refresh endpoint,
 * which uses the guest's refresh token to get a new access token without
 * changing the underlying discussion_board_guestusers record.
 *
 * @param props.connection
 * @param props.body Guest join payload containing the opaque token or
 *   fingerprint used to derive or look up anonymous_token in
 *   discussion_board_guestusers.
 * @setHeader token.access Authorization
 *
 * @path /auth/guestUser/join
 * @accessor api.functional.auth.guestUser.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
