import { tags } from "typia";

import { IDiscussionBoardArticle } from "./IDiscussionBoardArticle";

/**
 * Like engagement state for a single discussion board article in the economic
 * and political discussion board.
 *
 * This DTO aggregates per-member like records from the
 * `discussion_board_article_likes` table together with the target article
 * context. It is used by read operations to answer whether the current
 * authenticated member user has liked the article and to expose the current
 * total like count.
 *
 * The DTO is deliberately limited to engagement-focused fields and does not
 * expose underlying member profile details or full article content. It is safe
 * to return to both authenticated member users and, where policy allows, to
 * public callers when like counts are considered public information.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardArticleLike = {
  /**
   * Summary information about the article whose like engagement state is
   * being represented.
   *
   * This association is derived from the `discussion_board_articles` table
   * and corresponds to the article primary key that backs the like
   * aggregation. Using `IDiscussionBoardArticle.ISummary` here ensures
   * clients have immediate access to the article identifier and key display
   * fields without issuing an additional article-detail request.
   */
  article: IDiscussionBoardArticle.ISummary;

  /**
   * Total number of active like records associated with the article.
   *
   * This count is typically computed by aggregating rows in
   * `discussion_board_article_likes` for the given article, or by reading a
   * denormalized counter on the article entity that is kept in sync with that
   * table. The value is always non-negative.
   */
  totalLikeCount: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Flag indicating whether the current authenticated member user has an
   * active like record for this article.
   *
   * When the caller is an authenticated `memberUser`, this flag is derived
   * from the presence or absence of a row in `discussion_board_article_likes`
   * linking the member to the article. When the caller is unauthenticated or
   * not a member user, service implementations may always return `false` here
   * while still exposing the `totalLikeCount`. This field never reveals any
   * information about other members.
   */
  likedByCurrentMember: boolean;
};
