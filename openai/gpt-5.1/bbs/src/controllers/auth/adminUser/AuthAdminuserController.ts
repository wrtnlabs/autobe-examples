import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminUserJoin } from "../../../providers/postAuthAdminUserJoin";
import { postAuthAdminUserLogin } from "../../../providers/postAuthAdminUserLogin";
import { postAuthAdminUserRefresh } from "../../../providers/postAuthAdminUserRefresh";
import { AdminuserAuth } from "../../../decorators/AdminuserAuth";
import { AdminuserPayload } from "../../../decorators/payload/AdminuserPayload";

import { IDiscussionBoardAdminuser } from "../../../api/structures/IDiscussionBoardAdminuser";
import { IDiscussionBoardAdminUserJoin } from "../../../api/structures/IDiscussionBoardAdminUserJoin";
import { IDiscussionBoardAdminUserLogin } from "../../../api/structures/IDiscussionBoardAdminUserLogin";
import { IDiscussionBoardAdminUserRefresh } from "../../../api/structures/IDiscussionBoardAdminUserRefresh";

@Controller("/auth/adminUser")
export class AuthAdminuserController {
  /**
   * This operation registers a new administrative user account for the
   * discussionBoard service by creating a record in the
   * `discussion_board_adminusers` table and then issuing initial authentication
   * tokens specific to the `adminUser` actor.
   *
   * At the database level, the operation persists core authentication and
   * profile fields defined on `discussion_board_adminusers`, including `email`,
   * `password_hash`, `display_name`, and the optional `bio` field. The service
   * layer is responsible for hashing the incoming credential into
   * `password_hash`, ensuring that plain-text passwords are never stored. The
   * `email_verified` boolean is initialized based on business rules for admin
   * onboarding (typically `false` until a verification flow completes), and
   * `account_status` is set to a valid lifecycle value such as `"active"`.
   * Timestamps `created_at` and `updated_at` are set to the current time, while
   * `deleted_at` and `last_login_at` remain `null` for a newly created
   * administrator.
   *
   * From a security perspective, the endpoint is public because new
   * administrators may be provisioned through this API according to operational
   * policy, but it still enforces strict validation on `email` to respect the
   * unique index on the `email` column and on password strength according to
   * technical guidelines. If an email already exists in
   * `discussion_board_adminusers.email`, the operation must fail with a clear
   * error without creating a duplicate row. The newly created admin will be
   * immediately treated as an `adminUser` actor for the purpose of JWT
   * issuance, but subsequent access to privileged moderation APIs will still be
   * controlled by those endpoints' `authorizationActor` configuration.
   *
   * The operation is tightly coupled to the `discussion_board_adminusers`
   * model, whose description highlights that it stores authentication
   * credentials, basic profile fields, and lifecycle state for administrative
   * users. By setting `account_status` appropriately and honoring
   * `email_verified`, the system can later restrict or suspend access in
   * cooperation with other admin management features. The `deleted_at` field is
   * left `null` here, so that the admin account is fully usable until an
   * explicit lifecycle change or soft deletion happens through another
   * operation.
   *
   * On successful registration, the service issues JWT tokens representing the
   * `adminUser` actor and returns them using the
   * `IDiscussionBoardAdminUser.IAuthorized` response schema. This response
   * encapsulates both token information and essential admin profile data
   * derived from `discussion_board_adminusers`, such as `id`, `email`,
   * `display_name`, `account_status`, and `email_verified`. Error responses
   * include validation failures (e.g., invalid email format, weak password),
   * uniqueness violations on `email`, and unexpected persistence errors, all
   * surfaced with appropriate HTTP status codes.
   *
   * This endpoint is typically used once per administrative account creation,
   * and is logically followed by the admin login and refresh operations. Other
   * business APIs, such as moderation of articles or processing of reports,
   * depend on the existence of admin accounts created through this or
   * equivalent provisioning flows but are not direct prerequisites for this
   * operation.
   *
   * @param connection
   * @param body Registration information required to create a new adminUser
   *   account, including email, credential, display name, and optional profile
   *   fields.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardAdminUserJoin.IRequest,
  ): Promise<IDiscussionBoardAdminuser.IAuthorized> {
    try {
      return await postAuthAdminUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation performs login for an existing administrative account of the
   * `adminUser` actor by validating credentials against the
   * `discussion_board_adminusers` table and then issuing fresh JWT tokens.
   *
   * The service first locates an administrator row using the unique `email`
   * column on `discussion_board_adminusers`. If no row matches the provided
   * email, or if the stored `password_hash` does not correspond to the supplied
   * credential after hashing, the operation fails with an authentication error
   * without revealing whether the email exists. It also checks lifecycle state
   * via the `account_status` column, denying login for disallowed states such
   * as suspended or closed as defined in business rules, and may consider the
   * `deleted_at` timestamp to prevent login when an account has been logically
   * removed.
   *
   * When authentication succeeds, the service updates `last_login_at` in
   * `discussion_board_adminusers` to the current timestamp and may also refresh
   * `updated_at` to reflect the change. Additionally, it can insert a new row
   * into `discussion_board_adminuser_sessions`, populating
   * `discussion_board_adminuser_id` with the administrator's `id`, capturing
   * `ip`, `href`, and `referrer` from the incoming request context for audit
   * purposes, and setting `created_at` and an eventual `expired_at` according
   * to the session strategy. This session record provides traceable context for
   * privileged admin activity.
   *
   * Security-wise, this endpoint is public in terms of HTTP access because it
   * must accept credentials from unauthenticated clients, but all subsequent
   * access to administrative features is guarded by the tokens it issues. It
   * enforces strict validation on the `email` format and credential structure
   * and respects the `email_verified` column to optionally block or warn about
   * logins from unverified admin accounts depending on policy. The
   * `account_status` and `deleted_at` fields ensure that closed or banned
   * admins cannot authenticate.
   *
   * Upon successful login, the operation returns
   * `IDiscussionBoardAdminUser.IAuthorized`, which encapsulates both the JWT
   * token pair and an admin profile projection based on
   * `discussion_board_adminusers`, including fields such as `id`, `email`,
   * `display_name`, `account_status`, and `email_verified`. Error responses
   * cover invalid credentials, disallowed `account_status`, unverified email
   * restrictions, and internal server failures, each mapped to appropriate HTTP
   * status codes.
   *
   * This endpoint is typically the primary entry point for admin sessions and
   * is closely related to the admin refresh operation, which re-issues tokens
   * based on a valid refresh token. It does not require prior calls beyond the
   * existence of an admin account, usually created via the admin join endpoint
   * or an internal provisioning process.
   *
   * @param connection
   * @param body Login credentials for an existing adminUser account, including
   *   email and credential information required for authentication.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardAdminUserLogin.IRequest,
  ): Promise<IDiscussionBoardAdminuser.IAuthorized> {
    try {
      return await postAuthAdminUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation renews JWT tokens for an administrative user who is already
   * recognized as an `adminUser` actor, using a valid refresh token rather than
   * credentials. It is designed to extend authenticated admin sessions while
   * respecting account lifecycle and session policies defined in the database.
   *
   * At the data layer, the operation ties the incoming refresh token to an
   * administrator row in `discussion_board_adminusers`, typically by embedding
   * the admin `id` in the token or by looking up a token store that references
   * `discussion_board_adminusers.id`. Before issuing new tokens, it inspects
   * lifecycle fields such as `account_status`, `deleted_at`, and optionally
   * `email_verified` to ensure that the administrator is still allowed to act.
   * If `account_status` indicates a suspended or closed state, or if
   * `deleted_at` is non-null, the refresh attempt fails and no new tokens are
   * issued.
   *
   * The operation may also consult `discussion_board_adminuser_sessions` to
   * validate that the underlying admin session is still active. Using the
   * `discussion_board_adminuser_id` foreign key and `created_at` or
   * `expired_at` timestamps, it can confirm that the session has not been
   * explicitly terminated or expired. If a corresponding session record is
   * missing or has an `expired_at` earlier than the current time, the refresh
   * request is rejected to prevent indefinite session extension.
   *
   * From a security standpoint, this endpoint requires an existing refresh
   * token and should not be publicly usable without prior authentication
   * context. It does not accept credentials or modify sensitive fields like
   * `password_hash` or `email`; instead, it focuses solely on re-issuing access
   * and refresh tokens when the admin account and session remain valid. The
   * tokens produced continue to represent the `adminUser` actor and are
   * constrained by whatever scopes or claims the system assigns to
   * administrators.
   *
   * On success, the operation returns `IDiscussionBoardAdminUser.IAuthorized`,
   * which contains the new JWT token set and a current snapshot of relevant
   * admin information derived from `discussion_board_adminusers`, such as `id`,
   * `email`, `display_name`, `account_status`, and `email_verified`. This
   * allows clients to update any cached admin profile state alongside tokens.
   * Failure responses include invalid or expired refresh tokens, disallowed
   * account states, terminated sessions detected via
   * `discussion_board_adminuser_sessions.expired_at`, and internal server
   * errors.
   *
   * This refresh endpoint is typically called after the admin login endpoint
   * has already created both a database session record and an initial token
   * set. It works in conjunction with logout or session invalidation features,
   * which update `discussion_board_adminuser_sessions.expired_at` or revoke
   * tokens so that subsequent refresh attempts fail as expected.
   *
   * @param connection
   * @param body Refresh token payload for an existing adminUser session, used
   *   to request new JWT tokens without resubmitting credentials.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @AdminuserAuth()
    adminUser: AdminuserPayload,
    @TypedBody()
    body: IDiscussionBoardAdminUserRefresh.IRequest,
  ): Promise<IDiscussionBoardAdminuser.IAuthorized> {
    try {
      return await postAuthAdminUserRefresh({
        adminUser,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
