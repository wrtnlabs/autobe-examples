import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardArticleCategories } from "../../../providers/patchDiscussionBoardArticleCategories";
import { getDiscussionBoardArticleCategoriesCategoryCode } from "../../../providers/getDiscussionBoardArticleCategoriesCategoryCode";

import { IPageIDiscussionBoardArticleCategory } from "../../../api/structures/IPageIDiscussionBoardArticleCategory";
import { IDiscussionBoardArticleCategory } from "../../../api/structures/IDiscussionBoardArticleCategory";

@Controller("/discussionBoard/articleCategories")
export class DiscussionboardArticlecategoriesController {
  /**
   * Search and retrieve a paginated list of discussion board article categories
   * based on flexible filter and sort criteria.
   *
   * This operation operates on the discussion_board_article_categories Prisma
   * model, which defines the available categories for organizing economic and
   * political discussion board articles. Each category record may include a
   * unique code, a human-readable name, a descriptive text, sort order, and
   * status flags as indicated by the Prisma schema comments. Clients call this
   * endpoint when they need to render category lists in navigation menus,
   * article creation dialogs, or filter sidebars and require more than simple
   * unfiltered retrieval.
   *
   * The request body uses the IDiscussionBoardArticleCategory.IRequest DTO,
   * which encapsulates all supported search parameters: for example, free-text
   * search on the category name or description, filtering by one or more
   * category codes, and controlling whether disabled or archived categories are
   * included. Pagination parameters such as page index and page size, along
   * with sort options (e.g., by display order or creation date), are also part
   * of this request DTO. The service translates these fields into a Prisma
   * query against discussion_board_article_categories, using WHERE clauses for
   * filters and ORDER BY with SKIP/TAKE for pagination.
   *
   * The response body returns a paginated structure of category summaries using
   * the IPageIDiscussionBoardArticleCategory.ISummary type. Each summary
   * element provides the key information required for list presentation, such
   * as category code, display name, and a small subset of flags, while omitting
   * heavier or rarely used fields. Because article categories represent public
   * classification data, this endpoint is made available without
   * authentication, indicated by an empty authorizationActors array. Related
   * operations may include article listing APIs that filter by category and
   * administrative endpoints (not defined here) for managing the category
   * master itself. Error handling should report invalid filter combinations or
   * pagination parameters as structured 400 Bad Request responses, while still
   * returning 200 OK with an empty page when no categories match the provided
   * criteria.
   *
   * @param connection
   * @param body Search and pagination criteria for retrieving discussion board
   *   article categories, including filters, sorting, and paging information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardArticleCategory.IRequest,
  ): Promise<IPageIDiscussionBoardArticleCategory.ISummary> {
    try {
      return await patchDiscussionBoardArticleCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get detailed information for a single discussion-board article category
   * identified by its stable business code.
   *
   * This operation reads from the `discussion_board_article_categories` Prisma
   * model, which is documented as "Article category master data for the
   * economic and political discussion board". Each row represents one category
   * such as "Economy" or "Politics" and contains a machine-friendly `code`
   * field that is guaranteed unique across the table through a dedicated unique
   * index. The API path parameter `categoryCode` is mapped directly to this
   * `code` column, making the URL both human-readable and stable for
   * integrations.
   *
   * When handling the request, the implementation must query
   * `discussion_board_article_categories` using the provided `categoryCode` and
   * must only consider records where `deleted_at` is null. The `deleted_at`
   * column is described as indicating when a category was retired; when it is
   * non-null, the category should not be exposed through this normal retrieval
   * API so that newly created or edited articles cannot accidentally reuse
   * retired categories. If no active category is found for the given code, the
   * service should return a 404 Not Found error.
   *
   * The response returns a single `IDiscussionBoardArticleCategory` object
   * representing the category master data. Its properties correspond to the
   * Prisma columns: the UUID primary key `id`, the unique `code`, the
   * human-readable `name`, the optional explanatory `description`, the integer
   * `order` used for display sorting, and the audit timestamps `created_at`,
   * `updated_at`, and `deleted_at`. Client applications can use this endpoint
   * when they need to show category details on management screens, validate a
   * category code, or pre-fill editing forms.
   *
   * Security-wise, article categories are not sensitive user data, so this
   * operation can be exposed publicly with no authentication
   * (`authorizationActors: []`) if desired by the overall system design. If the
   * broader service decides that only authenticated users or admins may inspect
   * category metadata, an authorization guard can be added later without
   * changing the contract of this endpoint. This operation is typically used
   * together with the list endpoint `PATCH /articleCategories` (not in the
   * current scope) and the creation endpoint `POST /articleCategories` to
   * provide a complete category-management flow.
   *
   * @param connection
   * @param categoryCode Unique business identifier code of the target
   *   discussion-board article category (global scope). This maps to the `code`
   *   column in the `discussion_board_article_categories` table and uniquely
   *   identifies a category such as "ECONOMY" or "POLITICS".
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryCode")
  public async at(
    @TypedParam("categoryCode")
    categoryCode: string,
  ): Promise<IDiscussionBoardArticleCategory> {
    try {
      return await getDiscussionBoardArticleCategoriesCategoryCode({
        categoryCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
