import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardAdminUserReports } from "../../../../providers/patchDiscussionBoardAdminUserReports";
import { AdminuserAuth } from "../../../../decorators/AdminuserAuth";
import { AdminuserPayload } from "../../../../decorators/payload/AdminuserPayload";
import { getDiscussionBoardAdminUserReportsReportId } from "../../../../providers/getDiscussionBoardAdminUserReportsReportId";
import { putDiscussionBoardAdminUserReportsReportId } from "../../../../providers/putDiscussionBoardAdminUserReportsReportId";
import { deleteDiscussionBoardAdminUserReportsReportId } from "../../../../providers/deleteDiscussionBoardAdminUserReportsReportId";

import { IPageIDiscussionBoardReport } from "../../../../api/structures/IPageIDiscussionBoardReport";
import { IDiscussionBoardReport } from "../../../../api/structures/IDiscussionBoardReport";

@Controller("/discussionBoard/adminUser/reports")
export class DiscussionboardAdminuserReportsController {
  /**
   * Search and retrieve a paginated list of discussion_board_reports for
   * moderation purposes.
   *
   * Retrieve a paginated and filtered list of reports registered in the
   * discussion board system for administrative review.
   *
   * This operation targets the `discussion_board_reports` Prisma model, which
   * stores central report records describing issues raised by users or
   * administrators against specific pieces of content. Each report may be
   * associated with an article, comment, or attachment through subsidiary link
   * tables such as `discussion_board_report_of_articles`,
   * `discussion_board_report_of_comments`, and
   * `discussion_board_report_of_attachments`. Additional link tables like
   * `discussion_board_report_of_memberusers` and
   * `discussion_board_report_of_adminusers` track whether a report was created
   * by a member user or an admin user.
   *
   * The endpoint accepts a rich set of search criteria in the request body,
   * allowing administrators to filter reports by status (for example, open, in
   * review, resolved), target type, reporter type, and creation or update time
   * ranges. Pagination parameters such as page index and page size enable
   * efficient browsing of large report volumes, and sorting options can be used
   * to prioritize more recent or more severe reports. This design lets
   * moderation staff quickly find the most urgent or relevant reports to act
   * upon.
   *
   * Security-wise, access to this operation is restricted to administrative
   * actors because reports often contain sensitive information about user
   * behavior, policy violations, and potentially problematic content. The
   * implementation must enforce that only adminUser actors can invoke this API
   * successfully. The operation is read-only and does not change the state of
   * reports or associated content; it is typically used alongside detail
   * retrieval and update endpoints that allow admins to inspect and resolve
   * individual reports.
   *
   * @param connection
   * @param body Search and pagination criteria for listing discussion board
   *   reports, including filters for status, target type, reporter type, and
   *   date ranges.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminuserAuth()
    adminUser: AdminuserPayload,
    @TypedBody()
    body: IDiscussionBoardReport.IRequest,
  ): Promise<IPageIDiscussionBoardReport.ISummary> {
    try {
      return await patchDiscussionBoardAdminUserReports({
        adminUser,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get detailed information of a single report from discussion_board_reports.
   *
   * Retrieve a single discussion board report record for detailed inspection by
   * an authorized actor.
   *
   * This operation targets the Prisma table that stores central report metadata
   * for articles, comments, and attachments. It looks up the report using its
   * unique identifier and returns the full report object shaped as
   * `IDiscussionBoardReport`. The description and field coverage must align
   * with the Prisma schema comments for `discussion_board_reports`, including
   * fields such as status, category, reason text, timestamps, and any foreign
   * keys to link tables that connect the report to articles, comments,
   * attachments, and reporting users.
   *
   * From a security perspective, this endpoint should be restricted to
   * administrative or internal moderation tooling, because reports may contain
   * sensitive notes, internal status, or personal information about reporters
   * or reported users. The `authorizationActors` will therefore use the
   * `adminUser` role rather than generic end users. The implementation must
   * enforce that only appropriately authenticated and authorized actors can
   * read this data, while normal board visitors or member users cannot fetch
   * arbitrary reports.
   *
   * The operation is purely read-only and does not change any state in the
   * `discussion_board_reports` table or its related entities. It should be used
   * together with the listing and search endpoint on reports (for example, a
   * future `PATCH /reports` search) where moderators first narrow down to a set
   * of reports and then call this detail endpoint for a specific `reportId`.
   * Error handling should clearly distinguish between a missing report (not
   * found), lack of permission (forbidden), and other server-side issues.
   *
   * @param connection
   * @param reportId Unique identifier of the target discussion board report in
   *   the discussion_board_reports table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reportId")
  public async at(
    @AdminuserAuth()
    adminUser: AdminuserPayload,
    @TypedParam("reportId")
    reportId: string,
  ): Promise<IDiscussionBoardReport> {
    try {
      return await getDiscussionBoardAdminUserReportsReportId({
        adminUser,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a discussion board report in the `discussion_board_reports` table by
   * reportId.
   *
   * Update the status and moderation details of a specific discussion board
   * report record identified by `reportId`.
   *
   * This operation targets the `discussion_board_reports` Prisma model, which
   * serves as the central entity for all reports filed against articles,
   * comments, or attachments on the economic and political discussion board.
   * Each report typically stores information such as the reporting actor, a
   * reference to the reported resource, the reason category, free-text
   * description, and the current handling status. Administrators, represented
   * by the `discussion_board_adminusers` table in the database, use this
   * endpoint to progress a report through its lifecycle when they review and
   * act upon the reported content.
   *
   * The request body type `IDiscussionBoardReport.IUpdate` is designed to
   * include only those fields that may change after the report is first
   * created, such as the moderation status (for example, pending, inReview,
   * resolved, dismissed), resolution notes, or outcome codes. Fields that
   * identify the reporter or the target resource remain immutable and are
   * therefore not part of the update DTO. The implementation must check that
   * the given `reportId` corresponds to an existing record, and that the
   * requested update is compatible with any status-transition rules defined in
   * the reporting and moderation requirements.
   *
   * Only administrative users should be allowed to perform this action.
   * Accordingly, `authorizationActors` is set to `["adminUser"]`, meaning the
   * controller layer will require authentication as an admin user and inject
   * the corresponding identity into the service. If the `reportId` does not
   * exist, the provider should respond with a not-found error. If the update
   * violates domain rules (for example, attempting to modify a locked or
   * archived report), the provider should respond with an appropriate error
   * describing why the operation cannot be completed. This endpoint is expected
   * to be used together with report listing and detail retrieval APIs that
   * admins rely on to triage and review reported content.
   *
   * @param connection
   * @param reportId Unique identifier of the target report record in the
   *   `discussion_board_reports` table that should be updated.
   * @param body Mutable fields for updating a discussion board report, such as
   *   moderation status and resolution notes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":reportId")
  public async update(
    @AdminuserAuth()
    adminUser: AdminuserPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardReport.IUpdate,
  ): Promise<IDiscussionBoardReport> {
    try {
      return await putDiscussionBoardAdminUserReportsReportId({
        adminUser,
        reportId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a discussion board report in the `discussion_board_reports` table by
   * reportId.
   *
   * Delete a specific discussion board report record from the
   * `discussion_board_reports` table using its `reportId` as identifier.
   *
   * This operation directly targets the central reporting entity used to track
   * complaints about articles, comments, or attachments on the discussion
   * board. Each record in `discussion_board_reports` corresponds to a single
   * report instance. When administrators decide that some reports must be
   * removed entirely—for example, because they were created during testing, are
   * exact duplicates created by mistake, or must be purged under a data
   * retention policy—they can call this endpoint to erase the associated
   * record.
   *
   * Only administrative users represented by `discussion_board_adminusers` are
   * allowed to perform this deletion, which is reflected by setting
   * `authorizationActors` to `["adminUser"]`. The service must ensure that the
   * provided `reportId` matches an existing report before attempting deletion
   * and should respond with an appropriate not-found error when no such record
   * exists. If the report is linked to other rows in subsidiary tables, the
   * implementation must conform to the configured Prisma relations, either
   * relying on cascade rules or performing explicit cleanup to maintain
   * referential integrity. Because the primary signal of success is the HTTP
   * status code indicating that the delete operation completed, the response
   * body is left null.
   *
   * @param connection
   * @param reportId Unique identifier of the target report record in the
   *   `discussion_board_reports` table that should be deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reportId")
  public async erase(
    @AdminuserAuth()
    adminUser: AdminuserPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminUserReportsReportId({
        adminUser,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
