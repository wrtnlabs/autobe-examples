/**
 * Validate that an admin can be added as a formal dispute party with correct
 * actor linkage.
 *
 * Business flow:
 *
 * 1. Admin joins and becomes authenticated.
 * 2. Admin configures country, region, SKU inventory state, shipping method, and
 *    payment method.
 * 3. Customer joins and becomes authenticated, then creates a cart.
 * 4. Seller joins and becomes authenticated, then creates a product and SKU using
 *    the inventory state.
 * 5. Customer logs in again explicitly, creates a shipping address referencing the
 *    country and region, creates an order using the cart, shipment, payment,
 *    and SKU, and then creates a logical payment for the order.
 * 6. Admin logs in explicitly, creates a dispute linked to the order, capturing
 *    dispute_code.
 * 7. Admin creates a dispute party for the dispute with actor_type "admin", a role
 *    like "investigator", and admin_id set to the admin’s id.
 * 8. Validate that the dispute party response has actor_type "admin", the correct
 *    role, a non-null admin summary whose id matches the admin, and a dispute
 *    summary whose dispute_code matches the created dispute.
 * 9. Optionally attempt to create the same admin party for the same dispute again
 *    and expect an error from business validation, using TestValidator.error
 *    without any type misuse.
 */
export async function test_api_dispute_party_creation_with_admin_actor(
  connection: api.IConnection,
) {
  // 1. Admin joins (initial authentication)
  const adminEmail: string & tags.Format<"email"> = typia.random<
    string & tags.Format<"email">
  >();
  const adminPassword: string & tags.Format<"password"> = typia.random<
    string & tags.Format<"password">
  >();

  const adminJoinBody = {
    email: adminEmail,
    password: adminPassword,
    ip: null,
    href: "https://admin.shoppingmall.test/join",
    referrer: "https://admin.shoppingmall.test/login",
  } satisfies IShoppingMallAdminJoin.ICreate;

  const adminJoin: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.join(connection, {
      body: adminJoinBody,
    });
  typia.assert(adminJoin);

  const adminId = adminJoin.id;

  // 2. Admin creates country
  const countryCode = "UT";
  const countryBody = {
    country_code: countryCode,
    name_en: "UnitTest Country",
    phone_code: "+99",
    is_active: true,
    sort_order: 1 as number & tags.Type<"int32">,
  } satisfies IShoppingMallCountry.ICreate;

  const country: IShoppingMallCountry =
    await api.functional.shoppingMall.admin.countries.create(connection, {
      body: countryBody,
    });
  typia.assert(country);

  // 2-1. Admin creates region under that country
  const regionBody = {
    code: "UT-R1",
    name_en: "UnitTest Region 1",
    region_type: "state",
    is_active: true,
    sort_order: 1 as number & tags.Type<"int32">,
  } satisfies IShoppingMallRegion.ICreate;

  const region: IShoppingMallRegion =
    await api.functional.shoppingMall.admin.countries.regions.create(
      connection,
      {
        countryCode: country.country_code,
        body: regionBody,
      },
    );
  typia.assert(region);

  // 2-2. Admin creates SKU inventory state
  const inventoryStateBody = {
    code: "in_stock",
    name: "In Stock",
    description: "Available for purchase",
    is_purchasable: true,
  } satisfies IShoppingMallSkuInventoryState.ICreate;

  const inventoryState: IShoppingMallSkuInventoryState =
    await api.functional.shoppingMall.admin.skuInventoryStates.create(
      connection,
      {
        body: inventoryStateBody,
      },
    );
  typia.assert(inventoryState);

  // 2-3. Admin creates shipping method
  const shippingMethodBody = {
    method_code: "standard",
    display_name: "Standard Shipping",
    service_level_description: "3-5 business days",
  } satisfies IShoppingMallShippingMethod.ICreate;

  const shippingMethod: IShoppingMallShippingMethod =
    await api.functional.shoppingMall.admin.shippingMethods.create(connection, {
      body: shippingMethodBody,
    });
  typia.assert(shippingMethod);

  // 2-4. Admin creates payment method
  const paymentMethodBody = {
    code: "card",
    display_name: "Credit Card",
    description: "Standard credit card payment",
    provider_type: "card_processor",
    allowed_currencies: null,
    allowed_countries: null,
    min_amount: null,
    max_amount: null,
    status: "active",
  } satisfies IShoppingMallPaymentMethod.ICreate;

  const paymentMethod: IShoppingMallPaymentMethod =
    await api.functional.shoppingMall.admin.paymentMethods.create(connection, {
      body: paymentMethodBody,
    });
  typia.assert(paymentMethod);

  // 3. Customer joins (authenticated)
  const customerEmail: string & tags.Format<"email"> = typia.random<
    string & tags.Format<"email">
  >();

  const customerJoinBody = {
    email: customerEmail,
    password: typia.random<string & tags.Format<"password">>(),
    ip: null,
    href: "https://shoppingmall.test/join",
    referrer: "https://shoppingmall.test/landing",
  } satisfies IShoppingMallCustomerJoin.IRequest;

  const customerJoin: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.join(connection, {
      body: customerJoinBody,
    });
  typia.assert(customerJoin);

  const customerId = customerJoin.id;

  // 4. As customer, create cart
  const cartBody = {
    actor_type: "customer",
    status: "active",
    currency_code: "USD",
  } satisfies IShoppingMallCart.ICreate;

  const cart: IShoppingMallCart =
    await api.functional.shoppingMall.customer.carts.create(connection, {
      body: cartBody,
    });
  typia.assert(cart);

  // 5. Seller joins (authenticated)
  const sellerEmail: string & tags.Format<"email"> = typia.random<
    string & tags.Format<"email">
  >();
  const sellerJoinBody = {
    email: sellerEmail,
    password: typia.random<string & tags.Format<"password">>(),
    ip: null,
    href: "https://seller.shoppingmall.test/join",
    referrer: "https://seller.shoppingmall.test/landing",
  } satisfies IShoppingMallSellerAuthJoin.IRequest;

  const sellerJoin: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.join(connection, {
      body: sellerJoinBody,
    });
  typia.assert(sellerJoin);

  // 6. As seller, create product and SKU
  const productBody = {
    code: "UT-PROD-1",
    title: "Unit Test Product",
    summary: "Summary for unit test product",
    description: "Detailed description for unit test product",
    brand: "UTBrand",
    model_name: "Model-1",
    status: "active",
    primary_image_uri: "https://cdn.shoppingmall.test/images/ut-prod-1.png",
    default_locale: "en-US",
  } satisfies IShoppingMallProduct.ICreate;

  const product: IShoppingMallProduct =
    await api.functional.shoppingMall.seller.products.create(connection, {
      body: productBody,
    });
  typia.assert(product);

  const skuBody = {
    code: "UT-SKU-1" as string & tags.MinLength<1> & tags.MaxLength<255>,
    barcode: "1234567890123",
    status: "active" as string & tags.MinLength<1> & tags.MaxLength<64>,
    price: 100,
    original_price: 120,
    inventory_quantity: 10 as number & tags.Type<"int32"> & tags.Minimum<0>,
    low_stock_threshold: 1 as number & tags.Type<"int32"> & tags.Minimum<0>,
    shopping_mall_sku_inventory_state_id: inventoryState.id,
    attribute_value_ids: [],
    external_ids: [],
  } satisfies IShoppingMallSku.ICreate;

  const sku: IShoppingMallSku =
    await api.functional.shoppingMall.seller.products.skus.create(connection, {
      productId: product.id,
      body: skuBody,
    });
  typia.assert(sku);

  // 7. Switch back to customer context using login
  const customerLoginBody = {
    email: customerEmail,
    password: customerJoinBody.password,
    ip: null,
    href: "https://shoppingmall.test/login",
    referrer: "https://shoppingmall.test/landing",
  } satisfies IShoppingMallCustomerLogin.IRequest;

  const customerLogin: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.login(connection, {
      body: customerLoginBody,
    });
  typia.assert(customerLogin);

  // 8. Customer creates shipping address referencing country and region
  const addressBody = {
    shopping_mall_country_id: country.id,
    shopping_mall_region_id: region.id,
    recipient_name: "Unit Test Customer",
    line1: "123 Test St",
    line2: "Apt 1",
    city: "Testville",
    postal_code: "12345",
    phone_number: RandomGenerator.mobile(),
    is_default: true,
  } satisfies IShoppingMallCustomerAddress.ICreate;

  const address: IShoppingMallCustomerAddress =
    await api.functional.shoppingMall.customer.customers.addresses.create(
      connection,
      {
        customerId,
        body: addressBody,
      },
    );
  typia.assert(address);

  // 9. Customer creates order
  const orderItemCreate = {
    shopping_mall_sku_id: sku.id,
    quantity: 1 as number & tags.Type<"int32">,
  } satisfies IShoppingMallOrderItem.ICreate;

  const orderCreateBody = {
    cart_id: cart.id,
    currency_code: "USD",
    items: [orderItemCreate],
    shipping_address_id: address.id,
    shipping_address_snapshot: null,
    shipping_method_id: shippingMethod.id,
    payment_method_id: paymentMethod.id,
    buyer_memo: null,
    platform_note: null,
  } satisfies IShoppingMallOrder.ICreate;

  const order: IShoppingMallOrder =
    await api.functional.shoppingMall.customer.orders.create(connection, {
      body: orderCreateBody,
    });
  typia.assert(order);

  // 10. Customer creates logical payment for the order
  const orderPaymentBody = {
    payment_method_id: paymentMethod.id,
    currency_code: order.currency_code,
    payable_amount: order.grand_total_amount,
    provider_reference: null,
    provider_status_code: null,
    metadata: null,
  } satisfies IShoppingMallOrderPayment.ICreate;

  const orderPayment: IShoppingMallOrderPayment =
    await api.functional.shoppingMall.customer.orders.payments.create(
      connection,
      {
        orderId: order.id,
        body: orderPaymentBody,
      },
    );
  typia.assert(orderPayment);

  // 11. Switch back to admin context using login
  const adminLoginBody = {
    email: adminEmail,
    password: adminPassword,
    ip: null,
    href: "https://admin.shoppingmall.test/login",
    referrer: "https://admin.shoppingmall.test/landing",
  } satisfies IShoppingMallAdminLogin.ICreate;

  const adminLogin: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.login(connection, {
      body: adminLoginBody,
    });
  typia.assert(adminLogin);

  // 12. Admin creates dispute linked to the order
  const disputeCreateBody = {
    dispute_code: null,
    type: "order_dispute",
    severity: "high",
    summary: "Unit test dispute for admin party creation",
    description: "Dispute created to verify admin dispute party linkage.",
    opened_at: null,
    shopping_mall_order_id: order.id,
    shopping_mall_refund_request_id: null,
    shopping_mall_payment_chargeback_id: null,
    shopping_mall_risk_case_id: null,
  } satisfies IShoppingMallDispute.ICreate;

  const dispute: IShoppingMallDispute =
    await api.functional.shoppingMall.admin.disputes.create(connection, {
      body: disputeCreateBody,
    });
  typia.assert(dispute);

  const disputeCode = dispute.dispute_code;

  // 13. Admin creates dispute party with actor_type "admin"
  const role = "investigator";

  const partyCreateBody = {
    actor_type: "admin",
    role,
    display_name: "Admin Investigator",
    customer_id: null,
    seller_id: null,
    admin_id: adminId,
  } satisfies IShoppingMallDisputeParty.ICreate;

  const party: IShoppingMallDisputeParty =
    await api.functional.shoppingMall.admin.disputes.parties.create(
      connection,
      {
        disputeCode,
        body: partyCreateBody,
      },
    );
  typia.assert(party);

  // 14. Validate dispute party response
  TestValidator.equals("actor_type should be admin", party.actor_type, "admin");
  TestValidator.equals("role should match requested role", party.role, role);

  TestValidator.predicate(
    "admin summary should be present on dispute party",
    party.admin !== null && party.admin !== undefined,
  );

  if (party.admin !== null && party.admin !== undefined) {
    TestValidator.equals(
      "dispute party admin.id should match admin id",
      party.admin.id,
      adminId,
    );
  }

  TestValidator.equals(
    "dispute summary dispute_code should match created dispute",
    party.dispute.dispute_code,
    disputeCode,
  );

  // 15. Optional negative scenario: attempt duplicate admin party with same role
  await TestValidator.error(
    "duplicate admin dispute party with same role should be rejected if business rules enforce uniqueness",
    async () => {
      await api.functional.shoppingMall.admin.disputes.parties.create(
        connection,
        {
          disputeCode,
          body: partyCreateBody,
        },
      );
    },
  );
}
