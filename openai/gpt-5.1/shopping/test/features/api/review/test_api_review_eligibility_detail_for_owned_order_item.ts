/**
 * Validate that a customer can retrieve detailed review eligibility for their
 * own order item and that the detail is consistent with the index summary and
 * underlying order item context.
 *
 * Business flow:
 *
 * 1. Admin joins & logs in.
 * 2. Admin creates a country and region.
 * 3. Admin creates a SKU inventory state (purchasable), shipping method, and
 *    payment method.
 * 4. Seller joins & logs in, creates a product, and a SKU under that product.
 * 5. Admin creates a category and links it to the product (catalog completeness).
 * 6. Customer joins & logs in.
 * 7. Customer creates a shipping address for themselves.
 * 8. Customer creates a cart and adds a cart item for the SKU.
 * 9. Customer creates an order from the cart, with shipping/payment method and
 *    shipping address snapshot.
 * 10. Using the created order's first order item, customer calls PATCH
 *     reviewEligibilities index to get a page of eligibilities and (if any)
 *     picks one summary.
 * 11. When an eligibility exists, customer calls GET reviewEligibilities.at for
 *     that orderItemId and eligibilityId and verifies that:
 *
 *     - Ids match between summary and detail
 *     - Status, eligible_from, eligible_until equal
 *     - Detail.order_item.id equals the order item id
 *     - Detail.product.id equals summary.product.id
 *     - Detail.sku?.id equals summary.sku?.id (when present)
 *     - Detail.review?.id equals summary.review?.id (when present).
 * 12. When an eligibility exists, customer re-calls PATCH index and verifies that
 *     eligibility ids and statuses are unchanged, proving GET detail is
 *     side-effect free.
 */
export async function test_api_review_eligibility_detail_for_owned_order_item(
  connection: api.IConnection,
) {
  // 1. Admin joins & logs in
  const adminJoinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: typia.random<string & tags.Format<"password">>(),
    ip: null,
    href: "https://admin.example.com/join",
    referrer: "https://admin.example.com/",
  } satisfies IShoppingMallAdminJoin.ICreate;
  const adminAuthorized: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.join(connection, {
      body: adminJoinBody,
    });
  typia.assert(adminAuthorized);

  const adminLoginBody = {
    email: adminJoinBody.email,
    password: adminJoinBody.password,
    ip: null,
    href: "https://admin.example.com/login",
    referrer: "https://admin.example.com/",
  } satisfies IShoppingMallAdminLogin.ICreate;
  const adminLoggedIn: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.login(connection, {
      body: adminLoginBody,
    });
  typia.assert(adminLoggedIn);

  // 2. Admin creates country and region
  const countryBody = {
    country_code: "KR",
    name_en: "Korea, Republic of",
    phone_code: "+82",
    is_active: true,
    sort_order: 1,
  } satisfies IShoppingMallCountry.ICreate;
  const country: IShoppingMallCountry =
    await api.functional.shoppingMall.admin.countries.create(connection, {
      body: countryBody,
    });
  typia.assert(country);

  const regionBody = {
    code: "SEOUL",
    name_en: "Seoul",
    region_type: "city",
    is_active: true,
    sort_order: 1,
  } satisfies IShoppingMallRegion.ICreate;
  const region: IShoppingMallRegion =
    await api.functional.shoppingMall.admin.countries.regions.create(
      connection,
      {
        countryCode: country.country_code,
        body: regionBody,
      },
    );
  typia.assert(region);

  // 3. Admin creates SKU inventory state, shipping method, and payment method
  const inventoryStateBody = {
    code: "in_stock",
    name: "In Stock",
    description: "Sellable inventory",
    is_purchasable: true,
  } satisfies IShoppingMallSkuInventoryState.ICreate;
  const inventoryState: IShoppingMallSkuInventoryState =
    await api.functional.shoppingMall.admin.skuInventoryStates.create(
      connection,
      {
        body: inventoryStateBody,
      },
    );
  typia.assert(inventoryState);

  const shippingMethodBody = {
    method_code: "standard",
    display_name: "Standard Shipping",
    service_level_description: "Standard delivery",
  } satisfies IShoppingMallShippingMethod.ICreate;
  const shippingMethod: IShoppingMallShippingMethod =
    await api.functional.shoppingMall.admin.shippingMethods.create(connection, {
      body: shippingMethodBody,
    });
  typia.assert(shippingMethod);

  const paymentMethodBody = {
    code: "card",
    display_name: "Credit Card",
    description: "Generic card processor",
    provider_type: "card_processor",
    allowed_currencies: null,
    allowed_countries: null,
    min_amount: null,
    max_amount: null,
    status: "active",
  } satisfies IShoppingMallPaymentMethod.ICreate;
  const paymentMethod: IShoppingMallPaymentMethod =
    await api.functional.shoppingMall.admin.paymentMethods.create(connection, {
      body: paymentMethodBody,
    });
  typia.assert(paymentMethod);

  // 4. Seller joins & logs in
  const sellerJoinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: typia.random<string & tags.Format<"password">>(),
    ip: null,
    href: "https://seller.example.com/join",
    referrer: "https://seller.example.com/",
  } satisfies IShoppingMallSellerAuthJoin.IRequest;
  const sellerAuthorized: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.join(connection, {
      body: sellerJoinBody,
    });
  typia.assert(sellerAuthorized);

  const sellerLoginBody = {
    email: sellerJoinBody.email,
    password: sellerJoinBody.password,
    ip: null,
    href: "https://seller.example.com/login",
    referrer: "https://seller.example.com/",
  } satisfies IShoppingMallSellerAuthLogin.IRequest;
  const sellerLoggedIn: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.login(connection, {
      body: sellerLoginBody,
    });
  typia.assert(sellerLoggedIn);

  // Seller creates a product
  const productBody = {
    code: RandomGenerator.alphaNumeric(8),
    title: RandomGenerator.paragraph({ sentences: 3 }),
    summary: RandomGenerator.paragraph({ sentences: 5 }),
    description: RandomGenerator.content({ paragraphs: 2 }),
    brand: "TestBrand",
    model_name: "Model-1",
    status: "active",
    primary_image_uri: "https://cdn.example.com/product.jpg",
    default_locale: "en-US",
  } satisfies IShoppingMallProduct.ICreate;
  const product: IShoppingMallProduct =
    await api.functional.shoppingMall.seller.products.create(connection, {
      body: productBody,
    });
  typia.assert(product);

  // 5. Admin creates a category and links it to product
  const categoryBody = {
    parent_id: null,
    slug: RandomGenerator.alphaNumeric(8),
    name_en: "General",
    description_en: "General category",
    status: "active",
    sort_order: 1,
    is_leaf: true,
  } satisfies IShoppingMallCategory.ICreate;
  const category: IShoppingMallCategory =
    await api.functional.shoppingMall.admin.categories.create(connection, {
      body: categoryBody,
    });
  typia.assert(category);

  const productCategoryBody = {
    shopping_mall_category_id: category.id,
    is_primary: true,
  } satisfies IShoppingMallProductCategory.ICreate;
  const productCategory: IShoppingMallProductCategory =
    await api.functional.shoppingMall.admin.products.categories.create(
      connection,
      {
        productId: product.id,
        body: productCategoryBody,
      },
    );
  typia.assert(productCategory);

  // Seller creates a SKU for the product
  const skuBody = {
    code: RandomGenerator.alphaNumeric(8),
    barcode: null,
    status: "active",
    price: 100,
    original_price: 120,
    inventory_quantity: 10,
    low_stock_threshold: 2,
    shopping_mall_sku_inventory_state_id: inventoryState.id,
    attribute_value_ids: [],
    external_ids: [],
  } satisfies IShoppingMallSku.ICreate;
  const sku: IShoppingMallSku =
    await api.functional.shoppingMall.seller.products.skus.create(connection, {
      productId: product.id as string & tags.Format<"uuid">,
      body: skuBody,
    });
  typia.assert(sku);

  // 6. Customer joins & logs in
  const customerJoinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: typia.random<string & tags.Format<"password">>(),
    ip: null,
    href: "https://customer.example.com/join",
    referrer: "https://customer.example.com/",
  } satisfies IShoppingMallCustomerJoin.IRequest;
  const customerAuthorized: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.join(connection, {
      body: customerJoinBody,
    });
  typia.assert(customerAuthorized);

  const customerLoginBody = {
    email: customerJoinBody.email,
    password: customerJoinBody.password,
    ip: null,
    href: "https://customer.example.com/login",
    referrer: "https://customer.example.com/",
  } satisfies IShoppingMallCustomerLogin.IRequest;
  const customerLoggedIn: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.login(connection, {
      body: customerLoginBody,
    });
  typia.assert(customerLoggedIn);

  // 7. Customer creates a shipping address
  const addressBody = {
    shopping_mall_country_id: country.id,
    shopping_mall_region_id: region.id,
    recipient_name: RandomGenerator.name(2),
    line1: RandomGenerator.paragraph({ sentences: 2 }),
    line2: null,
    city: "Seoul",
    postal_code: "06236",
    phone_number: RandomGenerator.mobile(),
    is_default: true,
  } satisfies IShoppingMallCustomerAddress.ICreate;
  const address: IShoppingMallCustomerAddress =
    await api.functional.shoppingMall.customer.customers.addresses.create(
      connection,
      {
        customerId: customerAuthorized.id,
        body: addressBody,
      },
    );
  typia.assert(address);

  // 8. Customer creates a cart and cart item
  const cartBody = {
    actor_type: "customer",
    status: "active",
    currency_code: "KRW",
  } satisfies IShoppingMallCart.ICreate;
  const cart: IShoppingMallCart =
    await api.functional.shoppingMall.customer.carts.create(connection, {
      body: cartBody,
    });
  typia.assert(cart);

  const cartItemBody = {
    shopping_mall_sku_id: sku.id,
    quantity: 1,
  } satisfies IShoppingMallCartItem.ICreate;
  const cartItem: IShoppingMallCartItem =
    await api.functional.shoppingMall.customer.carts.items.create(connection, {
      cartId: cart.id as string & tags.Format<"uuid">,
      body: cartItemBody,
    });
  typia.assert(cartItem);

  // 9. Customer creates an order from the cart
  const shippingAddressSnapshotBody = {
    recipient_name: address.recipient_name,
    phone_number: address.phone_number ?? RandomGenerator.mobile(),
    country_code: country.country_code,
    postal_code: address.postal_code,
    state_or_region: region.name_en,
    city: address.city,
    address_line1: address.line1,
    address_line2: address.line2 ?? null,
  } satisfies IShoppingMallShippingAddressSnapshot.ICreate;

  const orderItemsCreate: IShoppingMallOrderItem.ICreate[] = [
    {
      shopping_mall_sku_id: sku.id,
      quantity: 1,
    },
  ];

  const orderBody = {
    cart_id: cart.id,
    currency_code: cart.currency_code,
    items: orderItemsCreate,
    shipping_address_id: null,
    shipping_address_snapshot: shippingAddressSnapshotBody,
    shipping_method_id: shippingMethod.id,
    payment_method_id: paymentMethod.id,
    buyer_memo: null,
    platform_note: null,
  } satisfies IShoppingMallOrder.ICreate;
  const order: IShoppingMallOrder =
    await api.functional.shoppingMall.customer.orders.create(connection, {
      body: orderBody,
    });
  typia.assert(order);

  TestValidator.predicate(
    "order has at least one order item",
    order.items.length > 0,
  );

  const orderItem: IShoppingMallOrderItem = order.items[0];

  // 10. Call PATCH index for review eligibilities of the order item
  const indexRequestBody = {
    customer_id: null,
    product_id: null,
    sku_id: null,
    order_item_id: orderItem.id,
    status: null,
    eligible_from_from: null,
    eligible_from_to: null,
    eligible_until_from: null,
    eligible_until_to: null,
    page: 1,
    limit: 10,
    sort_by: null,
    sort_direction: null,
  } satisfies IShoppingMallReviewEligibility.IRequest;
  const page: IPageIShoppingMallReviewEligibility.ISummary =
    await api.functional.shoppingMall.customer.orderItems.reviewEligibilities.index(
      connection,
      {
        orderItemId: orderItem.id,
        body: indexRequestBody,
      },
    );
  typia.assert(page);

  TestValidator.predicate(
    "eligibility index may or may not return records",
    page.data.length >= 0,
  );

  if (page.data.length === 0) {
    // No eligibilities exist for this order item yet; nothing further to assert.
    return;
  }

  const summary: IShoppingMallReviewEligibility.ISummary = page.data[0];

  // 11. Call GET detail and verify consistency
  const detail: IShoppingMallReviewEligibility =
    await api.functional.shoppingMall.customer.orderItems.reviewEligibilities.at(
      connection,
      {
        orderItemId: orderItem.id,
        eligibilityId: summary.id,
      },
    );
  typia.assert(detail);

  TestValidator.equals("detail id matches summary id", detail.id, summary.id);
  TestValidator.equals(
    "detail status matches summary status",
    detail.status,
    summary.status,
  );
  TestValidator.equals(
    "detail eligible_from matches summary eligible_from",
    detail.eligible_from,
    summary.eligible_from,
  );
  TestValidator.equals(
    "detail eligible_until matches summary eligible_until",
    detail.eligible_until ?? null,
    summary.eligible_until ?? null,
  );

  TestValidator.predicate(
    "detail.order_item must be present",
    detail.order_item !== undefined && detail.order_item !== null,
  );
  if (detail.order_item !== undefined && detail.order_item !== null) {
    TestValidator.equals(
      "detail order_item.id matches orderItem.id",
      detail.order_item.id,
      orderItem.id,
    );
  }

  TestValidator.predicate(
    "detail.product must be present",
    detail.product !== undefined && detail.product !== null,
  );
  if (detail.product !== undefined && detail.product !== null) {
    TestValidator.equals(
      "detail product.id matches summary product.id",
      detail.product.id,
      summary.product.id,
    );
  }

  if (summary.sku !== undefined && summary.sku !== null) {
    TestValidator.predicate(
      "detail sku should be present when summary.sku exists",
      detail.sku !== undefined && detail.sku !== null,
    );
    if (detail.sku !== undefined && detail.sku !== null) {
      TestValidator.equals(
        "detail sku.id matches summary sku.id",
        detail.sku.id,
        summary.sku.id,
      );
    }
  }

  if (summary.review !== undefined && summary.review !== null) {
    TestValidator.predicate(
      "detail review should be present when summary.review exists",
      detail.review !== undefined && detail.review !== null,
    );
    if (detail.review !== undefined && detail.review !== null) {
      TestValidator.equals(
        "detail review.id matches summary review.id",
        detail.review.id,
        summary.review.id,
      );
    }
  } else {
    TestValidator.predicate(
      "detail review may be null when summary.review is null",
      detail.review === undefined || detail.review === null,
    );
  }

  // 12. Re-call PATCH index and ensure side-effect free
  const pageAfter: IPageIShoppingMallReviewEligibility.ISummary =
    await api.functional.shoppingMall.customer.orderItems.reviewEligibilities.index(
      connection,
      {
        orderItemId: orderItem.id,
        body: indexRequestBody,
      },
    );
  typia.assert(pageAfter);

  const idsBefore: string[] = page.data.map((e) => e.id);
  const statusesBefore: string[] = page.data.map((e) => e.status);
  const idsAfter: string[] = pageAfter.data.map((e) => e.id);
  const statusesAfter: string[] = pageAfter.data.map((e) => e.status);

  TestValidator.equals(
    "eligibility ids unchanged after GET detail",
    idsAfter,
    idsBefore,
  );
  TestValidator.equals(
    "eligibility statuses unchanged after GET detail",
    statusesAfter,
    statusesBefore,
  );
}
