export async function test_api_review_helpful_vote_update_rejects_nonexistent_id(
  connection: api.IConnection,
) {
  // 1. Register a fresh customer so we have a valid authenticated actor
  const joinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: typia.random<string & tags.Format<"password">>(),
    ip: null,
    href: "https://customer.example.com/join",
    referrer: "https://customer.example.com/landing",
  } satisfies IShoppingMallCustomerJoin.IRequest;

  const joined: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.join(connection, {
      body: joinBody,
    });
  typia.assert(joined);

  // Optional: exercise login as well to align with dependency expectations
  const loginBody = {
    email: joined.email,
    password: joinBody.password,
    ip: null,
    href: "https://customer.example.com/login",
    referrer: "https://customer.example.com/join-complete",
  } satisfies IShoppingMallCustomerLogin.IRequest;

  const loggedIn: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.login(connection, {
      body: loginBody,
    });
  typia.assert(loggedIn);

  // 2. Prepare a random UUID that does not correspond to any helpful vote row
  const nonexistentHelpfulVoteId = typia.random<string & tags.Format<"uuid">>();

  // 3. Build a valid update payload toggling helpfulness
  const updateBody = {
    is_helpful: true,
  } satisfies IShoppingMallReviewHelpfulVote.IUpdate;

  // 4. Attempt to update a helpful vote that does not exist and
  //    assert that the API responds with an error instead of creating it.
  await TestValidator.error(
    "updating non-existent helpful vote must fail",
    async () => {
      await api.functional.shoppingMall.customer.reviewHelpfulVotes.update(
        connection,
        {
          helpfulVoteId: nonexistentHelpfulVoteId,
          body: updateBody,
        },
      );
    },
  );
}
