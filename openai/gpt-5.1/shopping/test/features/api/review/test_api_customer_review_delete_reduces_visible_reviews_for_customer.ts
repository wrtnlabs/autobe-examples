export async function test_api_customer_review_delete_reduces_visible_reviews_for_customer(
  connection: api.IConnection,
) {
  // 1. Arrange: register a customer and authenticate via join
  const joinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: typia.random<string & tags.Format<"password">>(),
    ip: null,
    href: "https://customer.example.com/join" as string & tags.Format<"uri">,
    referrer: "https://customer.example.com/landing" as string &
      tags.Format<"uri">,
  } satisfies IShoppingMallCustomerJoin.IRequest;

  const customerAuthorized: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.join(connection, {
      body: joinBody,
    });
  typia.assert<IShoppingMallCustomer.IAuthorized>(customerAuthorized);

  // 2. Act: create two reviews (A and B) for this authenticated customer
  const reviewBodyA = {
    rating: 5 as number &
      tags.Type<"int32"> &
      tags.Minimum<1> &
      tags.Maximum<5>,
    title: typia.random<string & tags.MinLength<1> & tags.MaxLength<255>>(),
    body: typia.random<string & tags.MinLength<1>>(),
  } satisfies IShoppingMallReview.ICreate;

  const reviewA: IShoppingMallReview =
    await api.functional.shoppingMall.customer.reviews.create(connection, {
      body: reviewBodyA,
    });
  typia.assert<IShoppingMallReview>(reviewA);

  const reviewBodyB = {
    rating: 4 as number &
      tags.Type<"int32"> &
      tags.Minimum<1> &
      tags.Maximum<5>,
    title: typia.random<string & tags.MinLength<1> & tags.MaxLength<255>>(),
    body: typia.random<string & tags.MinLength<1>>(),
  } satisfies IShoppingMallReview.ICreate;

  const reviewB: IShoppingMallReview =
    await api.functional.shoppingMall.customer.reviews.create(connection, {
      body: reviewBodyB,
    });
  typia.assert<IShoppingMallReview>(reviewB);

  TestValidator.predicate(
    "created reviews A and B must have different IDs",
    reviewA.id !== reviewB.id,
  );

  // 3. Act: delete review A
  await api.functional.shoppingMall.customer.reviews.erase(connection, {
    reviewId: reviewA.id,
  });

  // 4. Assert behavior in terms of API contracts (no error thrown and other review unaffected)
  // Since there is no review listing or GET endpoint available in the SDK, we
  // cannot re-fetch reviews to directly assert visibility. Instead, we assert
  // that:
  // - erase() resolved successfully for reviewA.id without throwing
  // - reviewB remains untouched in-memory and has a distinct ID from reviewA

  TestValidator.predicate(
    "deletion targeted only review A (B ID remains unchanged and distinct)",
    reviewB.id !== reviewA.id,
  );
}
