export async function test_api_review_helpful_vote_delete_nonexistent_id(
  connection: api.IConnection,
) {
  // 1. Register and authenticate a customer so that customer-scoped APIs work
  const joinRequestBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: typia.random<string & tags.Format<"password">>(),
    ip: null,
    href: typia.random<string & tags.Format<"uri">>(),
    referrer: typia.random<string & tags.Format<"uri">>(),
  } satisfies IShoppingMallCustomerJoin.IRequest;

  const customerAuthorized: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.join(connection, {
      body: joinRequestBody,
    });
  typia.assert<IShoppingMallCustomer.IAuthorized>(customerAuthorized);

  // 2. Create a legitimate helpful vote as control data
  const helpfulVoteCreateBody = {
    is_helpful: true,
  } satisfies IShoppingMallReviewHelpfulVote.ICreate;

  const createdHelpfulVote: IShoppingMallReviewHelpfulVote =
    await api.functional.shoppingMall.customer.reviewHelpfulVotes.create(
      connection,
      {
        body: helpfulVoteCreateBody,
      },
    );
  typia.assert<IShoppingMallReviewHelpfulVote>(createdHelpfulVote);

  // Sanity assertion: created helpful vote has a UUID id
  TestValidator.predicate(
    "created helpful vote should have a non-empty UUID id",
    () =>
      typeof createdHelpfulVote.id === "string" &&
      createdHelpfulVote.id.length > 0,
  );

  // 3. Generate a random UUID that is guaranteed to differ from the existing helpful vote id
  let nonexistentHelpfulVoteId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();

  if (nonexistentHelpfulVoteId === createdHelpfulVote.id) {
    nonexistentHelpfulVoteId = typia.random<string & tags.Format<"uuid">>();
  }

  TestValidator.predicate(
    "nonexistent helpful vote id must be different from created id",
    () => nonexistentHelpfulVoteId !== createdHelpfulVote.id,
  );

  // 4. Attempt to delete the non-existent helpful vote ID and assert error
  await TestValidator.error(
    "deleting a non-existent helpful vote id should fail",
    async () => {
      await api.functional.shoppingMall.customer.reviewHelpfulVotes.erase(
        connection,
        {
          helpfulVoteId: nonexistentHelpfulVoteId,
        },
      );
    },
  );

  // 5. Re-assert the original helpful vote object still has a valid structure
  //    (we cannot re-fetch it by ID with the given SDK, but we can still
  //    validate the in-memory object and id to ensure our test state is coherent).
  typia.assert<IShoppingMallReviewHelpfulVote>(createdHelpfulVote);
  TestValidator.equals(
    "original helpful vote id remains unchanged in memory",
    createdHelpfulVote.id,
    createdHelpfulVote.id,
  );
}
