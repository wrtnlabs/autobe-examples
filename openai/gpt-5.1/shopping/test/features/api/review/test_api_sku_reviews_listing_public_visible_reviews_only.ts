export async function test_api_sku_reviews_listing_public_visible_reviews_only(
  connection: api.IConnection,
) {
  // 1. Admin join + login
  const adminEmail: string = typia.random<string & tags.Format<"email">>();
  const adminJoinBody = {
    email: adminEmail,
    password: "Admin1234!",
    ip: null,
    href: "https://admin.example.com/join",
    referrer: "https://admin.example.com/landing",
  } satisfies IShoppingMallAdminJoin.ICreate;
  const adminAuthorized: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.join(connection, {
      body: adminJoinBody,
    });
  typia.assert(adminAuthorized);

  const adminLoginBody = {
    email: adminEmail,
    password: "Admin1234!",
    ip: null,
    href: "https://admin.example.com/login",
    referrer: "https://admin.example.com/landing",
  } satisfies IShoppingMallAdminLogin.ICreate;
  const adminLoggedIn: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.login(connection, {
      body: adminLoginBody,
    });
  typia.assert(adminLoggedIn);

  // 2. Configure master data: country, region, shipping method, payment method, sku inventory state
  const countryCreateBody = {
    country_code: "KR",
    name_en: "Korea",
    phone_code: "+82",
    is_active: true,
    sort_order: 1,
  } satisfies IShoppingMallCountry.ICreate;
  const country: IShoppingMallCountry =
    await api.functional.shoppingMall.admin.countries.create(connection, {
      body: countryCreateBody,
    });
  typia.assert(country);

  const regionCreateBody = {
    code: "SEOUL",
    name_en: "Seoul",
    region_type: "city",
    is_active: true,
    sort_order: 1,
  } satisfies IShoppingMallRegion.ICreate;
  const region: IShoppingMallRegion =
    await api.functional.shoppingMall.admin.countries.regions.create(
      connection,
      {
        countryCode: country.country_code,
        body: regionCreateBody,
      },
    );
  typia.assert(region);

  const shippingMethodBody = {
    method_code: "STANDARD",
    display_name: "Standard Shipping",
    service_level_description: "Standard domestic shipping",
  } satisfies IShoppingMallShippingMethod.ICreate;
  const shippingMethod: IShoppingMallShippingMethod =
    await api.functional.shoppingMall.admin.shippingMethods.create(connection, {
      body: shippingMethodBody,
    });
  typia.assert(shippingMethod);

  const paymentMethodBody = {
    code: "CARD",
    display_name: "Credit Card",
    description: "Card payment",
    provider_type: "card_processor",
    allowed_currencies: null,
    allowed_countries: null,
    min_amount: null,
    max_amount: null,
    status: "active",
  } satisfies IShoppingMallPaymentMethod.ICreate;
  const paymentMethod: IShoppingMallPaymentMethod =
    await api.functional.shoppingMall.admin.paymentMethods.create(connection, {
      body: paymentMethodBody,
    });
  typia.assert(paymentMethod);

  const skuInventoryStateBody = {
    code: "IN_STOCK",
    name: "In Stock",
    description: "Available for purchase",
    is_purchasable: true,
  } satisfies IShoppingMallSkuInventoryState.ICreate;
  const skuInventoryState: IShoppingMallSkuInventoryState =
    await api.functional.shoppingMall.admin.skuInventoryStates.create(
      connection,
      {
        body: skuInventoryStateBody,
      },
    );
  typia.assert(skuInventoryState);

  // 3. Seller join + login
  const sellerEmail: string = typia.random<string & tags.Format<"email">>();
  const sellerJoinBody = {
    email: sellerEmail,
    password: "Seller1234!",
    ip: null,
    href: "https://seller.example.com/join",
    referrer: "https://seller.example.com/landing",
  } satisfies IShoppingMallSellerAuthJoin.IRequest;
  const sellerAuthorized: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.join(connection, {
      body: sellerJoinBody,
    });
  typia.assert(sellerAuthorized);

  const sellerLoginBody = {
    email: sellerEmail,
    password: "Seller1234!",
    ip: null,
    href: "https://seller.example.com/login",
    referrer: "https://seller.example.com/landing",
  } satisfies IShoppingMallSellerAuthLogin.IRequest;
  const sellerLoggedIn: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.login(connection, {
      body: sellerLoginBody,
    });
  typia.assert(sellerLoggedIn);

  // 4. Seller creates product and SKU
  const productBody = {
    code: RandomGenerator.alphaNumeric(8),
    title: RandomGenerator.paragraph({ sentences: 3 }),
    summary: RandomGenerator.paragraph({ sentences: 5 }),
    description: RandomGenerator.content({ paragraphs: 2 }),
    brand: "BrandX",
    model_name: "ModelY",
    status: "active",
    primary_image_uri: "https://cdn.example.com/product.jpg" as string &
      tags.Format<"uri">,
    default_locale: "en-US",
  } satisfies IShoppingMallProduct.ICreate;
  const product: IShoppingMallProduct =
    await api.functional.shoppingMall.seller.products.create(connection, {
      body: productBody,
    });
  typia.assert(product);

  const skuBody = {
    code: RandomGenerator.alphaNumeric(8),
    barcode: RandomGenerator.alphaNumeric(13),
    status: "active",
    price: 10000,
    original_price: 12000,
    inventory_quantity: 100,
    low_stock_threshold: 5,
    shopping_mall_sku_inventory_state_id: skuInventoryState.id,
    attribute_value_ids: [],
    external_ids: [],
  } satisfies IShoppingMallSku.ICreate;
  const sku: IShoppingMallSku =
    await api.functional.shoppingMall.seller.products.skus.create(connection, {
      productId: product.id as string & tags.Format<"uuid">,
      body: skuBody,
    });
  typia.assert(sku);

  // 5. Customer A and B join + login
  const customerAEmail: string = typia.random<string & tags.Format<"email">>();
  const customerBEmail: string = typia.random<string & tags.Format<"email">>();

  const customerAJoinBody = {
    email: customerAEmail,
    password: "CustomerA1234!" as string & tags.Format<"password">,
    ip: null,
    href: "https://shop.example.com/join",
    referrer: "https://shop.example.com/landing",
  } satisfies IShoppingMallCustomerJoin.IRequest;
  const customerAAuthorized: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.join(connection, {
      body: customerAJoinBody,
    });
  typia.assert(customerAAuthorized);

  const customerALoginBody = {
    email: customerAEmail,
    password: "CustomerA1234!",
    ip: null,
    href: "https://shop.example.com/login",
    referrer: "https://shop.example.com/landing",
  } satisfies IShoppingMallCustomerLogin.IRequest;
  const customerALoggedIn: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.login(connection, {
      body: customerALoginBody,
    });
  typia.assert(customerALoggedIn);

  const customerBJoinBody = {
    email: customerBEmail,
    password: "CustomerB1234!" as string & tags.Format<"password">,
    ip: null,
    href: "https://shop.example.com/join",
    referrer: "https://shop.example.com/landing",
  } satisfies IShoppingMallCustomerJoin.IRequest;
  const customerBAuthorized: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.join(connection, {
      body: customerBJoinBody,
    });
  typia.assert(customerBAuthorized);

  const customerBLoginBody = {
    email: customerBEmail,
    password: "CustomerB1234!",
    ip: null,
    href: "https://shop.example.com/login",
    referrer: "https://shop.example.com/landing",
  } satisfies IShoppingMallCustomerLogin.IRequest;
  const customerBLoggedIn: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.login(connection, {
      body: customerBLoginBody,
    });
  typia.assert(customerBLoggedIn);

  // 6. Customer A creates address
  const addressBody = {
    shopping_mall_country_id: country.id,
    shopping_mall_region_id: region.id,
    recipient_name: RandomGenerator.name(2),
    line1: RandomGenerator.paragraph({ sentences: 2 }),
    line2: null,
    city: "Seoul",
    postal_code: "06000",
    phone_number: RandomGenerator.mobile("010"),
    is_default: true,
  } satisfies IShoppingMallCustomerAddress.ICreate;
  const customerAAddress: IShoppingMallCustomerAddress =
    await api.functional.shoppingMall.customer.customers.addresses.create(
      connection,
      {
        customerId: customerAAuthorized.id,
        body: addressBody,
      },
    );
  typia.assert(customerAAddress);

  // 7. Customer A creates cart and adds SKU item
  const cartBody = {
    actor_type: "customer",
    status: "active",
    currency_code: "KRW",
  } satisfies IShoppingMallCart.ICreate;
  const cart: IShoppingMallCart =
    await api.functional.shoppingMall.customer.carts.create(connection, {
      body: cartBody,
    });
  typia.assert(cart);

  const cartItemBody = {
    shopping_mall_sku_id: sku.id,
    quantity: 1,
  } satisfies IShoppingMallCartItem.ICreate;
  const cartItem: IShoppingMallCartItem =
    await api.functional.shoppingMall.customer.carts.items.create(connection, {
      cartId: cart.id as string & tags.Format<"uuid">,
      body: cartItemBody,
    });
  typia.assert(cartItem);

  // 8. Customer A creates order from cart
  const orderItemCreate: IShoppingMallOrderItem.ICreate = {
    shopping_mall_sku_id: sku.id,
    quantity: 1,
  };

  const shippingAddressSnapshotBody = {
    recipient_name: customerAAddress.recipient_name,
    phone_number: customerAAddress.phone_number ?? "01000000000",
    country_code: country.country_code,
    postal_code: customerAAddress.postal_code,
    state_or_region: "Seoul",
    city: customerAAddress.city,
    address_line1: customerAAddress.line1,
    address_line2: customerAAddress.line2 ?? null,
  } satisfies IShoppingMallShippingAddressSnapshot.ICreate;

  const orderCreateBody = {
    cart_id: cart.id,
    currency_code: "KRW",
    items: [orderItemCreate],
    shipping_address_id: customerAAddress.id,
    shipping_address_snapshot: shippingAddressSnapshotBody,
    shipping_method_id: shippingMethod.id,
    payment_method_id: paymentMethod.id,
    buyer_memo: null,
    platform_note: null,
  } satisfies IShoppingMallOrder.ICreate;
  const order: IShoppingMallOrder =
    await api.functional.shoppingMall.customer.orders.create(connection, {
      body: orderCreateBody,
    });
  typia.assert(order);

  // 9. Customer A creates order payment
  const paymentCreateBody = {
    payment_method_id: paymentMethod.id,
    currency_code: order.currency_code,
    payable_amount: order.grand_total_amount,
    provider_reference: null,
    provider_status_code: null,
    metadata: null,
  } satisfies IShoppingMallOrderPayment.ICreate;
  const orderPayment: IShoppingMallOrderPayment =
    await api.functional.shoppingMall.customer.orders.payments.create(
      connection,
      {
        orderId: order.id,
        body: paymentCreateBody,
      },
    );
  typia.assert(orderPayment);

  // 10. Customer A and B create reviews for the SKU
  const customerAReviewBody = {
    rating: 5,
    title: "Great product",
    body: "Very satisfied",
  } satisfies IShoppingMallReview.ICreate;
  const customerAReview: IShoppingMallReview =
    await api.functional.shoppingMall.customer.skus.reviews.create(connection, {
      skuId: sku.id,
      body: customerAReviewBody,
    });
  typia.assert(customerAReview);

  const customerBReviewBody = {
    rating: 4,
    title: "Good product",
    body: "Works well",
  } satisfies IShoppingMallReview.ICreate;
  const customerBReview: IShoppingMallReview =
    await api.functional.shoppingMall.customer.skus.reviews.create(connection, {
      skuId: sku.id,
      body: customerBReviewBody,
    });
  typia.assert(customerBReview);

  const hiddenReviewBody = {
    rating: 1,
    title: "Bad product",
    body: "Not satisfied",
  } satisfies IShoppingMallReview.ICreate;
  const hiddenReview: IShoppingMallReview =
    await api.functional.shoppingMall.customer.skus.reviews.create(connection, {
      skuId: sku.id,
      body: hiddenReviewBody,
    });
  typia.assert(hiddenReview);

  // 11. Customer A reports the hiddenReview
  const reportBody = {
    shopping_mall_review_id: hiddenReview.id,
    actor_type: "customer",
    reporter_actor_reference: customerAAuthorized.id,
    reason_code: "offensive_content",
    description: "Inappropriate content",
    status: "open",
  } satisfies IShoppingMallReviewReport.ICreate;
  const reviewReport: IShoppingMallReviewReport =
    await api.functional.shoppingMall.customer.reviews.reports.create(
      connection,
      {
        reviewId: hiddenReview.id,
        body: reportBody,
      },
    );
  typia.assert(reviewReport);

  // 12. Admin moderates the hiddenReview to hide it
  const moderationBody = {
    action_type: "hide_review",
    previous_visibility_status: hiddenReview.visibility_status,
    new_visibility_status: "hidden",
    previous_moderation_state: hiddenReview.moderation_state,
    new_moderation_state: "approved",
    reason_code: "policy_violation",
    note: "Hidden due to policy violation",
  } satisfies IShoppingMallReviewModerationAction.ICreate;
  const moderationAction: IShoppingMallReviewModerationAction =
    await api.functional.shoppingMall.admin.reviews.moderationActions.create(
      connection,
      {
        reviewId: hiddenReview.id,
        body: moderationBody,
      },
    );
  typia.assert(moderationAction);

  // 13. Call public SKU review listing without filters, expect only visible reviews
  const listBody = {
    page: 1,
    limit: 10,
    min_rating: null,
    max_rating: null,
    created_from: null,
    created_to: null,
    visibility_statuses: null,
    moderation_states: null,
    verified_purchase_only: null,
    incentivized_only: null,
    sort_by: "created_at",
    sort_direction: "desc",
  } satisfies IShoppingMallReview.IRequest;
  const page: IPageIShoppingMallReview.ISummary =
    await api.functional.shoppingMall.skus.reviews.index(connection, {
      skuId: sku.id,
      body: listBody,
    });
  typia.assert(page);

  // 14. Assertions on returned reviews
  const visibleReviewIds = [customerAReview.id, customerBReview.id];

  // Ensure that hidden review is not returned
  TestValidator.predicate(
    "hidden review must not be listed",
    page.data.every((review) => review.id !== hiddenReview.id),
  );

  // Ensure that all returned reviews belong to the target SKU
  TestValidator.predicate(
    "all listed reviews target the same SKU",
    page.data.every((review) => review.sku?.id === sku.id),
  );

  // Ensure that visible reviews we created are present
  const returnedIds = page.data.map((review) => review.id);
  TestValidator.predicate(
    "customer A and B reviews are included",
    visibleReviewIds.every((id) => returnedIds.includes(id)),
  );

  // Pagination metadata is consistent
  TestValidator.predicate(
    "pagination records match data length or exceed it",
    page.pagination.records >= page.data.length,
  );
}
