/**
 * End-to-end test for updating a seller payout item within a payout batch after
 * a complete but minimal order and payment lifecycle that is feasible with the
 * exposed SDK functions.
 *
 * Steps:
 *
 * 1. Admin joins and logs in to obtain admin context.
 * 2. Seller joins and logs in; remember seller id and email.
 * 3. Customer joins and logs in; remember customer id.
 * 4. Admin creates a country and a region (used by the customer address).
 * 5. Admin creates a category.
 * 6. Seller creates a product.
 * 7. Admin associates the product with the category.
 * 8. Admin creates a SKU inventory state.
 * 9. Seller creates a SKU under the product referencing that inventory state.
 * 10. Customer creates an address record referencing the country & region.
 * 11. Admin creates a shipping method and a payment method.
 * 12. Customer creates an order with a single order item using the SKU id,
 *     referencing the customer address and concrete shipping/payment methods.
 * 13. Customer creates an order payment for that order referencing the concrete
 *     payment method id.
 * 14. Admin creates a seller earning that references the order and payment, with
 *     positive net_earning_amount.
 * 15. Admin creates a payout batch whose period covers the earning and whose totals
 *     equal that earning’s net_earning_amount composition.
 * 16. Admin creates a payout item under the batch for the earning.
 * 17. Admin calls PUT
 *     /shoppingMall/admin/payoutBatches/{batchCode}/items/{payoutItemId} to
 *     update the payout item’s currency_code, payout_amount, status, and
 *     paid_at/reversed_at timestamps via
 *     IShoppingMallSellerPayoutItem.IUpdate.
 * 18. Validate that the updated payout item:
 *
 *     - Keeps its id and payoutBatch/sellerEarning associations.
 *     - Reflects new payout_amount and status.
 *     - Has paid_at non-null and reversed_at null for a paid item.
 *     - Has created_at unchanged and updated_at >= original updated_at.
 */
