import { ArrayUtil, RandomGenerator, TestValidator } from "@nestia/e2e";
import { IConnection } from "@nestia/fetcher";
import typia, { tags } from "typia";

import api from "@ORGANIZATION/PROJECT-api";
import type { IAuthorizationToken } from "@ORGANIZATION/PROJECT-api/lib/structures/IAuthorizationToken";
import type { IShoppingMallActorSecurityOverview } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallActorSecurityOverview";
import type { IShoppingMallActorSecurityOverviewActorSegment } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallActorSecurityOverviewActorSegment";
import type { IShoppingMallPlatformAdmin } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallPlatformAdmin";
import type { IShoppingMallPlatformAdminJoin } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallPlatformAdminJoin";

/**
 * Verify that the platform-admin security overview endpoint requires
 * authentication and returns a valid analytical payload when accessed with a
 * properly authenticated platform administrator session.
 *
 * Business purpose: Platform-level security dashboards must never be exposed
 * anonymously. This test ensures that the consolidated security overview for
 * all shopping mall actors is only accessible to authenticated platform
 * administrators, and that once authenticated, the endpoint returns a
 * structurally valid IShoppingMallActorSecurityOverview document with sane
 * metric values.
 *
 * Test steps:
 *
 * 1. Clone the provided connection into an unauthenticated connection with empty
 *    headers and attempt to call the security overview. Expect an error due to
 *    missing authentication using TestValidator.error.
 * 2. Join a new platform administrator via POST /auth/platformAdmin/join using a
 *    valid IShoppingMallPlatformAdminJoin.IRequest payload generated by
 *    typia.random.
 *
 *    - Assert that the response is a valid IShoppingMallPlatformAdmin.IAuthorized.
 *    - Rely on the SDK to automatically attach the access token into
 *         connection.headers.Authorization for subsequent calls.
 * 3. With the now-authenticated connection, call GET
 *    /shoppingMall/platformAdmin/actors/securityOverview again.
 *
 *    - Assert that the response matches IShoppingMallActorSecurityOverview using
 *         typia.assert.
 *    - Perform sanity checks on the numeric metrics for each actor segment to ensure
 *         non-negative values and basic relationships (e.g., recentSessions <=
 *         activeSessions when both are non-zero).
 */
export async function test_api_platform_admin_security_overview_authorization_required(
  connection: api.IConnection,
) {
  // 1. Attempt to call overview without any Authorization header
  const unauthConn: api.IConnection = { ...connection, headers: {} };

  await TestValidator.error(
    "security overview requires authentication",
    async () => {
      await api.functional.shoppingMall.platformAdmin.actors.securityOverview.at(
        unauthConn,
      );
    },
  );

  // 2. Register (join) a new platform administrator
  const joinBody = typia.random<IShoppingMallPlatformAdminJoin.IRequest>();

  const admin = await api.functional.auth.platformAdmin.join(connection, {
    body: joinBody,
  });
  typia.assert<IShoppingMallPlatformAdmin.IAuthorized>(admin);

  // 3. Authenticated call should succeed and return overview
  const overview =
    await api.functional.shoppingMall.platformAdmin.actors.securityOverview.at(
      connection,
    );
  typia.assert<IShoppingMallActorSecurityOverview>(overview);

  // 4. Sanity checks on overview payload
  const segments: IShoppingMallActorSecurityOverview[
    | "customer"
    | "seller"
    | "platformAdmin"][] = [
    overview.customer,
    overview.seller,
    overview.platformAdmin,
  ];

  TestValidator.predicate(
    "timeWindowMinutes must be non-negative",
    overview.timeWindowMinutes >= 0,
  );

  segments.forEach((segment, index) => {
    const label =
      index === 0 ? "customer" : index === 1 ? "seller" : "platformAdmin";

    TestValidator.predicate(
      `${label} totalActors is non-negative`,
      segment.totalActors >= 0,
    );
    TestValidator.predicate(
      `${label} activeSessions is non-negative`,
      segment.activeSessions >= 0,
    );
    TestValidator.predicate(
      `${label} recentSessions is non-negative`,
      segment.recentSessions >= 0,
    );
    TestValidator.predicate(
      `${label} failedLoginAttempts is non-negative`,
      segment.failedLoginAttempts >= 0,
    );
    TestValidator.predicate(
      `${label} successfulLogins is non-negative`,
      segment.successfulLogins >= 0,
    );
    TestValidator.predicate(
      `${label} lockedAccounts is non-negative`,
      segment.lockedAccounts >= 0,
    );
    TestValidator.predicate(
      `${label} mfaChallenges is non-negative`,
      segment.mfaChallenges >= 0,
    );

    TestValidator.predicate(
      `${label} recentSessions does not exceed activeSessions when both positive`,
      segment.activeSessions === 0 ||
        segment.recentSessions <= segment.activeSessions,
    );
  });
}
