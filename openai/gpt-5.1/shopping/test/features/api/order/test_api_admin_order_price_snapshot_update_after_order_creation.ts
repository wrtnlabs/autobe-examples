export async function test_api_admin_order_price_snapshot_update_after_order_creation(
  connection: api.IConnection,
) {
  // 1. Admin, customer, and seller registration
  const adminEmail = `admin+${RandomGenerator.alphaNumeric(8)}@example.com`;
  const adminPassword = "AdminPass123!" as string & tags.Format<"password">;

  const adminJoinBody = {
    email: adminEmail,
    password: adminPassword,
    ip: null,
    href: "https://admin.example.com/join",
    referrer: "https://admin.example.com/landing",
  } satisfies IShoppingMallAdminJoin.ICreate;

  const adminAuthorized: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.join(connection, {
      body: adminJoinBody,
    });
  typia.assert(adminAuthorized);

  const customerEmail = `customer+${RandomGenerator.alphaNumeric(8)}@example.com`;
  const customerPassword = RandomGenerator.alphaNumeric(12) as string &
    tags.Format<"password">;

  const customerJoinBody = {
    email: customerEmail,
    password: customerPassword,
    ip: null,
    href: "https://shop.example.com/join",
    referrer: "https://shop.example.com/landing",
  } satisfies IShoppingMallCustomerJoin.IRequest;

  const customerAuthorized: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.join(connection, {
      body: customerJoinBody,
    });
  typia.assert(customerAuthorized);

  const sellerEmail = `seller+${RandomGenerator.alphaNumeric(8)}@example.com`;
  const sellerPassword = RandomGenerator.alphaNumeric(12) as string &
    tags.Format<"password">;

  const sellerJoinBody = {
    email: sellerEmail,
    password: sellerPassword,
    ip: null,
    href: "https://seller.example.com/join",
    referrer: "https://seller.example.com/landing",
  } satisfies IShoppingMallSellerAuthJoin.IRequest;

  const sellerAuthorized: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.join(connection, {
      body: sellerJoinBody,
    });
  typia.assert(sellerAuthorized);

  // 2. Admin: configure master data (country, region, shipping method, payment method, sku inventory state)
  // Switch to admin explicitly
  const adminLoginBody = {
    email: adminEmail,
    password: adminPassword,
    ip: null,
    href: "https://admin.example.com/login",
    referrer: "https://admin.example.com/landing",
  } satisfies IShoppingMallAdminLogin.ICreate;
  const adminLogin: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.login(connection, {
      body: adminLoginBody,
    });
  typia.assert(adminLogin);

  const countryCode = `CTY-${RandomGenerator.alphaNumeric(5)}`;
  const countryCreateBody = {
    country_code: countryCode,
    name_en: "Test Country",
    phone_code: "+99",
    is_active: true,
    sort_order: 1 as number & tags.Type<"int32">,
  } satisfies IShoppingMallCountry.ICreate;

  const country: IShoppingMallCountry =
    await api.functional.shoppingMall.admin.countries.create(connection, {
      body: countryCreateBody,
    });
  typia.assert(country);

  const regionCode = `R-${RandomGenerator.alphaNumeric(4)}`;
  const regionCreateBody = {
    code: regionCode,
    name_en: "Test Region",
    region_type: "state",
    is_active: true,
    sort_order: 1 as number & tags.Type<"int32">,
  } satisfies IShoppingMallRegion.ICreate;

  const region: IShoppingMallRegion =
    await api.functional.shoppingMall.admin.countries.regions.create(
      connection,
      {
        countryCode,
        body: regionCreateBody,
      },
    );
  typia.assert(region);

  const shippingMethodCode = `ship-${RandomGenerator.alphaNumeric(6)}`;
  const shippingMethodCreateBody = {
    method_code: shippingMethodCode,
    display_name: "Standard Shipping",
    service_level_description: "Standard delivery",
  } satisfies IShoppingMallShippingMethod.ICreate;

  const shippingMethod: IShoppingMallShippingMethod =
    await api.functional.shoppingMall.admin.shippingMethods.create(connection, {
      body: shippingMethodCreateBody,
    });
  typia.assert(shippingMethod);

  const paymentMethodCode = `pay-${RandomGenerator.alphaNumeric(6)}`;
  const paymentMethodCreateBody = {
    code: paymentMethodCode,
    display_name: "Credit Card",
    description: "Generic credit card payment",
    provider_type: "card_processor",
    allowed_currencies: null,
    allowed_countries: null,
    min_amount: null,
    max_amount: null,
    status: "active",
  } satisfies IShoppingMallPaymentMethod.ICreate;

  const paymentMethod: IShoppingMallPaymentMethod =
    await api.functional.shoppingMall.admin.paymentMethods.create(connection, {
      body: paymentMethodCreateBody,
    });
  typia.assert(paymentMethod);

  const inventoryStateCode = `state-${RandomGenerator.alphaNumeric(5)}`;
  const skuInventoryStateCreateBody = {
    code: inventoryStateCode,
    name: "In Stock",
    description: "Standard in-stock state",
    is_purchasable: true,
  } satisfies IShoppingMallSkuInventoryState.ICreate;

  const skuInventoryState: IShoppingMallSkuInventoryState =
    await api.functional.shoppingMall.admin.skuInventoryStates.create(
      connection,
      {
        body: skuInventoryStateCreateBody,
      },
    );
  typia.assert(skuInventoryState);

  // 3. Seller: create product and SKU
  const sellerLoginBody = {
    email: sellerEmail,
    password: sellerPassword,
    ip: null,
    href: "https://seller.example.com/login",
    referrer: "https://seller.example.com/landing",
  } satisfies IShoppingMallSellerAuthLogin.IRequest;

  const sellerLogin: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.login(connection, {
      body: sellerLoginBody,
    });
  typia.assert(sellerLogin);

  const productCode = `P-${RandomGenerator.alphaNumeric(6)}`;
  const productCreateBody = {
    code: productCode,
    title: RandomGenerator.paragraph({ sentences: 3 }),
    summary: RandomGenerator.paragraph({ sentences: 5 }),
    description: RandomGenerator.content({ paragraphs: 2 }),
    brand: "TestBrand",
    model_name: "Model X",
    status: "active",
    primary_image_uri: "https://cdn.example.com/product.png" as string &
      tags.Format<"uri">,
    default_locale: "en-US",
  } satisfies IShoppingMallProduct.ICreate;

  const product: IShoppingMallProduct =
    await api.functional.shoppingMall.seller.products.create(connection, {
      body: productCreateBody,
    });
  typia.assert(product);

  const skuCreateBody = {
    code: `SKU-${RandomGenerator.alphaNumeric(6)}` as string &
      tags.MinLength<1> &
      tags.MaxLength<255>,
    barcode: null,
    status: "active" as string & tags.MinLength<1> & tags.MaxLength<64>,
    price: 100 as number & tags.Minimum<0>,
    original_price: 120 as number & tags.Minimum<0>,
    inventory_quantity: 10 as number & tags.Type<"int32"> & tags.Minimum<0>,
    low_stock_threshold: 2 as number & tags.Type<"int32"> & tags.Minimum<0>,
    shopping_mall_sku_inventory_state_id: skuInventoryState.id,
    attribute_value_ids: [],
    external_ids: [],
  } satisfies IShoppingMallSku.ICreate;

  const sku: IShoppingMallSku =
    await api.functional.shoppingMall.seller.products.skus.create(connection, {
      productId: product.id,
      body: skuCreateBody,
    });
  typia.assert(sku);

  // 4. Customer: create cart, add item, create shipping address
  const customerLoginBody = {
    email: customerEmail,
    password: customerPassword,
    ip: null,
    href: "https://shop.example.com/login",
    referrer: "https://shop.example.com/landing",
  } satisfies IShoppingMallCustomerLogin.IRequest;
  const customerLoginAgain: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.login(connection, {
      body: customerLoginBody,
    });
  typia.assert(customerLoginAgain);

  const cartCreateBody = {
    actor_type: "customer",
    status: "active",
    currency_code: "USD",
  } satisfies IShoppingMallCart.ICreate;

  const cart: IShoppingMallCart =
    await api.functional.shoppingMall.customer.carts.create(connection, {
      body: cartCreateBody,
    });
  typia.assert(cart);

  const cartItemCreateBody = {
    shopping_mall_sku_id: sku.id,
    quantity: 1 as number & tags.Type<"int32"> & tags.Minimum<1>,
  } satisfies IShoppingMallCartItem.ICreate;

  const cartItem: IShoppingMallCartItem =
    await api.functional.shoppingMall.customer.carts.items.create(connection, {
      cartId: cart.id,
      body: cartItemCreateBody,
    });
  typia.assert(cartItem);

  const addressCreateBody = {
    shopping_mall_country_id: country.id,
    shopping_mall_region_id: region.id,
    recipient_name: "John Doe",
    line1: "123 Test Street",
    line2: null,
    city: "Testville",
    postal_code: "12345",
    phone_number: RandomGenerator.mobile(),
    is_default: true,
  } satisfies IShoppingMallCustomerAddress.ICreate;

  const customerAddress: IShoppingMallCustomerAddress =
    await api.functional.shoppingMall.customer.customers.addresses.create(
      connection,
      {
        customerId: customerAuthorized.id,
        body: addressCreateBody,
      },
    );
  typia.assert(customerAddress);

  // 5. Customer: create order from cart
  const orderItemCreate: IShoppingMallOrderItem.ICreate = {
    shopping_mall_sku_id: sku.id,
    quantity: 1 as number & tags.Type<"int32">,
  };

  const orderCreateBody = {
    cart_id: cart.id,
    currency_code: cart.currency_code,
    items: [orderItemCreate],
    shipping_address_id: customerAddress.id,
    shipping_address_snapshot: null,
    shipping_method_id: shippingMethod.id,
    payment_method_id: paymentMethod.id,
    buyer_memo: "Please deliver between 9-5",
    platform_note: "Test order",
  } satisfies IShoppingMallOrder.ICreate;

  const order: IShoppingMallOrder =
    await api.functional.shoppingMall.customer.orders.create(connection, {
      body: orderCreateBody,
    });
  typia.assert(order);

  // 6. Admin: create initial price snapshot
  const adminLoginAgain: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.login(connection, {
      body: adminLoginBody,
    });
  typia.assert(adminLoginAgain);

  const initialSnapshotCreateBody = {
    item_subtotal_amount: order.grand_total_amount,
    item_discount_amount: 0,
    order_discount_amount: 0,
    shipping_fee_amount: 10,
    payment_surcharge_amount: 0,
    tax_amount: 5,
    grand_total_amount: order.grand_total_amount + 15,
    is_final: true,
  } satisfies IShoppingMallOrderPriceSnapshot.ICreate;

  const initialSnapshot: IShoppingMallOrderPriceSnapshot =
    await api.functional.shoppingMall.admin.orders.priceSnapshots.create(
      connection,
      {
        orderCode: order.order_code,
        body: initialSnapshotCreateBody,
      },
    );
  typia.assert(initialSnapshot);

  // 7. Admin: update the price snapshot
  const deltaTax = 3;
  const updatedSnapshotBody = {
    tax_amount: initialSnapshot.tax_amount + deltaTax,
    grand_total_amount: initialSnapshot.grand_total_amount + deltaTax,
    is_final: true,
  } satisfies IShoppingMallOrderPriceSnapshot.IUpdate;

  const updatedSnapshot: IShoppingMallOrderPriceSnapshot =
    await api.functional.shoppingMall.admin.orders.priceSnapshots.update(
      connection,
      {
        orderCode: order.order_code,
        snapshotId: initialSnapshot.id,
        body: updatedSnapshotBody,
      },
    );
  typia.assert(updatedSnapshot);

  // 8. Assertions on update behavior
  TestValidator.equals(
    "snapshot id should stay the same after update",
    updatedSnapshot.id,
    initialSnapshot.id,
  );

  TestValidator.equals(
    "item_subtotal_amount unchanged after update",
    updatedSnapshot.item_subtotal_amount,
    initialSnapshot.item_subtotal_amount,
  );

  TestValidator.equals(
    "item_discount_amount unchanged after update",
    updatedSnapshot.item_discount_amount,
    initialSnapshot.item_discount_amount,
  );

  TestValidator.equals(
    "order_discount_amount unchanged after update",
    updatedSnapshot.order_discount_amount,
    initialSnapshot.order_discount_amount,
  );

  TestValidator.equals(
    "shipping_fee_amount unchanged after update",
    updatedSnapshot.shipping_fee_amount,
    initialSnapshot.shipping_fee_amount,
  );

  TestValidator.equals(
    "payment_surcharge_amount unchanged after update",
    updatedSnapshot.payment_surcharge_amount,
    initialSnapshot.payment_surcharge_amount,
  );

  TestValidator.equals(
    "tax_amount should be increased by delta",
    updatedSnapshot.tax_amount,
    initialSnapshot.tax_amount + deltaTax,
  );

  TestValidator.equals(
    "grand_total_amount should be increased by delta",
    updatedSnapshot.grand_total_amount,
    initialSnapshot.grand_total_amount + deltaTax,
  );

  TestValidator.equals(
    "created_at must remain unchanged after update",
    updatedSnapshot.created_at,
    initialSnapshot.created_at,
  );
}
