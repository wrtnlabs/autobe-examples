/**
 * Verify that a customer can attach a shipping address snapshot to an order
 * even after the order header has been updated once, and that the snapshot
 * correctly reflects the provided address and links back to the same order.
 *
 * Business flow implemented in this test:
 *
 * 1. Admin joins and logs in to gain privileges for master-data setup.
 * 2. Admin creates a country and a region (these are not directly required by the
 *    shipping address DTO but reflect realistic environment setup).
 * 3. Admin creates a SKU inventory state that allows purchasing.
 * 4. Admin creates a shipping method and a payment method.
 * 5. Seller joins and logs in, then creates a product under their account.
 * 6. Admin creates a category and links the product to that category.
 * 7. Seller creates a SKU for the product, wired to the previously created
 *    inventory state.
 * 8. Customer joins and logs in.
 * 9. Customer creates a cart and adds the SKU as a cart item.
 * 10. Customer creates an order from the cart with: cart_id set, items built from
 *     the cart SKU, and shipping_method_id / payment_method_id populated, but
 *     with no shipping address snapshot yet (shipping_address_id and
 *     shipping_address_snapshot set to null).
 * 11. Using the order_code from the created order, customer calls PUT
 *     /shoppingMall/customer/orders/{orderCode} with an empty
 *     IShoppingMallOrder.IUpdate body ({}). The DTO is intentionally empty by
 *     design, but this call simulates an order header update that should not
 *     prevent later shipping address creation.
 * 12. After the update, customer calls POST
 *     /shoppingMall/customer/orders/{orderCode}/shippingAddress with a fully
 *     populated IShoppingMallOrderShippingAddress.ICreate body using realistic
 *     random data.
 * 13. The test asserts that the returned IShoppingMallOrderShippingAddress is
 *     structurally valid, that its embedded order summary has the same
 *     order_code as the order created in step 10, and that all address fields
 *     (recipient_name, line1, line2, city, postal_code, country_code, region,
 *     phone_number) match what was provided in the request (taking into account
 *     that line2 and phone_number may be null or optional).
 *
 * The test focuses on these key validations:
 *
 * - Order update via IShoppingMallOrder.IUpdate (empty object) does not block
 *   subsequent shipping address creation while the order is still in a
 *   modifiable state.
 * - Authorization context is consistent: the same customer account performs order
 *   creation, order update, and shipping address creation.
 * - Shipping address snapshot is immutable at creation time: the snapshot
 *   returned by the POST call accurately echoes the request payload and is
 *   bound to the correct order summary.
 */
export async function test_api_order_shipping_address_create_after_order_update(
  connection: api.IConnection,
) {
  // 1. Admin joins
  const adminEmail: string = typia.random<string & tags.Format<"email">>();
  const adminJoinBody = {
    email: adminEmail,
    password: RandomGenerator.alphaNumeric(12) as string &
      tags.Format<"password">,
    ip: null,
    href: "https://admin.example.com/join" as string & tags.Format<"uri">,
    referrer: "https://admin.example.com" as string & tags.Format<"uri">,
  } satisfies IShoppingMallAdminJoin.ICreate;
  const admin: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.join(connection, {
      body: adminJoinBody,
    });
  typia.assert(admin);

  // 2. Admin logs in (to simulate realistic flow, even though join already authenticated)
  const adminLoginBody = {
    email: adminEmail,
    password: adminJoinBody.password,
    ip: null,
    href: "https://admin.example.com/login" as string & tags.Format<"uri">,
    referrer: "https://admin.example.com" as string & tags.Format<"uri">,
  } satisfies IShoppingMallAdminLogin.ICreate;
  const adminLogin: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.login(connection, {
      body: adminLoginBody,
    });
  typia.assert(adminLogin);

  // 3. Admin creates country
  const countryBody = {
    country_code: "US",
    name_en: "United States",
    phone_code: "+1",
    is_active: true,
    sort_order: 1,
  } satisfies IShoppingMallCountry.ICreate;
  const country: IShoppingMallCountry =
    await api.functional.shoppingMall.admin.countries.create(connection, {
      body: countryBody,
    });
  typia.assert(country);

  // 4. Admin creates region under that country
  const regionBody = {
    code: "CA",
    name_en: "California",
    region_type: "state",
    is_active: true,
    sort_order: 1,
  } satisfies IShoppingMallRegion.ICreate;
  const region: IShoppingMallRegion =
    await api.functional.shoppingMall.admin.countries.regions.create(
      connection,
      {
        countryCode: country.country_code,
        body: regionBody,
      },
    );
  typia.assert(region);

  // 5. Admin creates SKU inventory state
  const skuInventoryStateBody = {
    code: "in_stock",
    name: "In Stock",
    description: "Available for purchase",
    is_purchasable: true,
  } satisfies IShoppingMallSkuInventoryState.ICreate;
  const skuInventoryState: IShoppingMallSkuInventoryState =
    await api.functional.shoppingMall.admin.skuInventoryStates.create(
      connection,
      {
        body: skuInventoryStateBody,
      },
    );
  typia.assert(skuInventoryState);

  // 6. Admin creates shipping method
  const shippingMethodCode = `std-${RandomGenerator.alphaNumeric(6)}`;
  const shippingMethodBody = {
    method_code: shippingMethodCode,
    display_name: "Standard Shipping",
    service_level_description: "Standard ground shipping",
  } satisfies IShoppingMallShippingMethod.ICreate;
  const shippingMethod: IShoppingMallShippingMethod =
    await api.functional.shoppingMall.admin.shippingMethods.create(connection, {
      body: shippingMethodBody,
    });
  typia.assert(shippingMethod);

  // 7. Admin creates payment method
  const paymentMethodCode = `card-${RandomGenerator.alphaNumeric(6)}`;
  const paymentMethodBody = {
    code: paymentMethodCode,
    display_name: "Credit Card",
    description: "Generic credit card payment",
    provider_type: "card_processor",
    allowed_currencies: null,
    allowed_countries: null,
    min_amount: null,
    max_amount: null,
    status: "active",
  } satisfies IShoppingMallPaymentMethod.ICreate;
  const paymentMethod: IShoppingMallPaymentMethod =
    await api.functional.shoppingMall.admin.paymentMethods.create(connection, {
      body: paymentMethodBody,
    });
  typia.assert(paymentMethod);

  // 8. Seller joins
  const sellerEmail: string = typia.random<string & tags.Format<"email">>();
  const sellerJoinBody = {
    email: sellerEmail,
    password: RandomGenerator.alphaNumeric(12) as string &
      tags.Format<"password">,
    ip: null,
    href: "https://seller.example.com/join" as string & tags.Format<"uri">,
    referrer: "https://seller.example.com" as string & tags.Format<"uri">,
  } satisfies IShoppingMallSellerAuthJoin.IRequest;
  const sellerJoin: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.join(connection, {
      body: sellerJoinBody,
    });
  typia.assert(sellerJoin);

  // 9. Seller logs in
  const sellerLoginBody = {
    email: sellerEmail,
    password: sellerJoinBody.password,
    ip: null,
    href: "https://seller.example.com/login" as string & tags.Format<"uri">,
    referrer: "https://seller.example.com" as string & tags.Format<"uri">,
  } satisfies IShoppingMallSellerAuthLogin.IRequest;
  const sellerLogin: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.login(connection, {
      body: sellerLoginBody,
    });
  typia.assert(sellerLogin);

  // 10. Seller creates product
  const productBody = {
    code: `P-${RandomGenerator.alphaNumeric(8)}`,
    title: RandomGenerator.paragraph({ sentences: 3 }),
    summary: RandomGenerator.paragraph({ sentences: 5 }),
    description: RandomGenerator.content({ paragraphs: 2 }),
    brand: "AutoBE Brand",
    model_name: "Model-X",
    status: "active",
    primary_image_uri: "https://cdn.example.com/product.jpg" as string &
      tags.Format<"uri">,
    default_locale: "en-US",
  } satisfies IShoppingMallProduct.ICreate;
  const product: IShoppingMallProduct =
    await api.functional.shoppingMall.seller.products.create(connection, {
      body: productBody,
    });
  typia.assert(product);

  // 11. Admin creates a category
  const categoryBody = {
    parent_id: null,
    slug: `cat-${RandomGenerator.alphaNumeric(6)}`,
    name_en: "General",
    description_en: "General category",
    status: "active",
    sort_order: 1,
    is_leaf: true,
  } satisfies IShoppingMallCategory.ICreate;
  const category: IShoppingMallCategory =
    await api.functional.shoppingMall.admin.categories.create(connection, {
      body: categoryBody,
    });
  typia.assert(category);

  // 12. Admin links product to category
  const productCategoryBody = {
    shopping_mall_category_id: category.id,
    is_primary: true,
  } satisfies IShoppingMallProductCategory.ICreate;
  const productCategory: IShoppingMallProductCategory =
    await api.functional.shoppingMall.admin.products.categories.create(
      connection,
      {
        productId: product.id,
        body: productCategoryBody,
      },
    );
  typia.assert(productCategory);

  // 13. Seller creates SKU for product
  const skuBody = {
    code: `SKU-${RandomGenerator.alphaNumeric(8)}`,
    barcode: null,
    status: "active",
    price: 100,
    original_price: null,
    inventory_quantity: 100,
    low_stock_threshold: 5,
    shopping_mall_sku_inventory_state_id: skuInventoryState.id,
    attribute_value_ids: [],
    external_ids: [],
  } satisfies IShoppingMallSku.ICreate;
  const sku: IShoppingMallSku =
    await api.functional.shoppingMall.seller.products.skus.create(connection, {
      productId: product.id as string & tags.Format<"uuid">,
      body: skuBody,
    });
  typia.assert(sku);

  // 14. Customer joins
  const customerEmail: string = typia.random<string & tags.Format<"email">>();
  const customerJoinBody = {
    email: customerEmail,
    password: RandomGenerator.alphaNumeric(12) as string &
      tags.Format<"password">,
    ip: null,
    href: "https://shop.example.com/join" as string & tags.Format<"uri">,
    referrer: "https://shop.example.com" as string & tags.Format<"uri">,
  } satisfies IShoppingMallCustomerJoin.IRequest;
  const customerJoin: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.join(connection, {
      body: customerJoinBody,
    });
  typia.assert(customerJoin);

  // 15. Customer logs in
  const customerLoginBody = {
    email: customerEmail,
    password: customerJoinBody.password,
    ip: null,
    href: "https://shop.example.com/login" as string & tags.Format<"uri">,
    referrer: "https://shop.example.com" as string & tags.Format<"uri">,
  } satisfies IShoppingMallCustomerLogin.IRequest;
  const customerLogin: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.login(connection, {
      body: customerLoginBody,
    });
  typia.assert(customerLogin);

  // 16. Customer creates cart
  const cartBody = {
    actor_type: "customer",
    status: "active",
    currency_code: "USD",
  } satisfies IShoppingMallCart.ICreate;
  const cart: IShoppingMallCart =
    await api.functional.shoppingMall.customer.carts.create(connection, {
      body: cartBody,
    });
  typia.assert(cart);

  // 17. Customer adds SKU to cart
  const cartItemBody = {
    shopping_mall_sku_id: sku.id,
    quantity: 1,
  } satisfies IShoppingMallCartItem.ICreate;
  const cartItem: IShoppingMallCartItem =
    await api.functional.shoppingMall.customer.carts.items.create(connection, {
      cartId: cart.id as string & tags.Format<"uuid">,
      body: cartItemBody,
    });
  typia.assert(cartItem);

  // 18. Customer creates order from cart (no shipping address snapshot yet)
  const orderItemCreate: IShoppingMallOrderItem.ICreate = {
    shopping_mall_sku_id: sku.id,
    quantity: 1,
  };
  const orderCreateBody = {
    cart_id: cart.id,
    currency_code: cart.currency_code,
    items: [orderItemCreate],
    shipping_address_id: null,
    shipping_address_snapshot: null,
    shipping_method_id: shippingMethod.id,
    payment_method_id: paymentMethod.id,
    buyer_memo: null,
    platform_note: null,
  } satisfies IShoppingMallOrder.ICreate;
  const order: IShoppingMallOrder =
    await api.functional.shoppingMall.customer.orders.create(connection, {
      body: orderCreateBody,
    });
  typia.assert(order);

  // 19. Customer updates order header with empty IUpdate body
  const orderUpdateBody = {} satisfies IShoppingMallOrder.IUpdate;
  const updatedOrder: IShoppingMallOrder =
    await api.functional.shoppingMall.customer.orders.update(connection, {
      orderCode: order.order_code,
      body: orderUpdateBody,
    });
  typia.assert(updatedOrder);
  TestValidator.equals(
    "order_code remains the same after update",
    updatedOrder.order_code,
    order.order_code,
  );

  // 20. Customer creates shipping address snapshot after the update
  const shippingAddressCreateBody = {
    recipient_name: RandomGenerator.name(2),
    line1: RandomGenerator.paragraph({ sentences: 3 }),
    line2: RandomGenerator.paragraph({ sentences: 2 }),
    city: "San Francisco",
    postal_code: "94105",
    country_code: country.country_code as string &
      tags.MinLength<2> &
      tags.MaxLength<2>,
    region: region.name_en,
    phone_number: RandomGenerator.mobile(),
  } satisfies IShoppingMallOrderShippingAddress.ICreate;

  const orderShippingAddress: IShoppingMallOrderShippingAddress =
    await api.functional.shoppingMall.customer.orders.shippingAddress.create(
      connection,
      {
        orderCode: order.order_code,
        body: shippingAddressCreateBody,
      },
    );
  typia.assert(orderShippingAddress);

  // 21. Validate association and immutability semantics via response
  TestValidator.equals(
    "shipping address linked to correct order",
    orderShippingAddress.order.order_code,
    order.order_code,
  );

  TestValidator.equals(
    "recipient_name echoed in snapshot",
    orderShippingAddress.recipient_name,
    shippingAddressCreateBody.recipient_name,
  );
  TestValidator.equals(
    "line1 echoed in snapshot",
    orderShippingAddress.line1,
    shippingAddressCreateBody.line1,
  );
  TestValidator.equals(
    "line2 echoed in snapshot",
    orderShippingAddress.line2 ?? null,
    shippingAddressCreateBody.line2 ?? null,
  );
  TestValidator.equals(
    "city echoed in snapshot",
    orderShippingAddress.city,
    shippingAddressCreateBody.city,
  );
  TestValidator.equals(
    "postal_code echoed in snapshot",
    orderShippingAddress.postal_code,
    shippingAddressCreateBody.postal_code,
  );
  TestValidator.equals(
    "country_code echoed in snapshot",
    orderShippingAddress.country_code,
    shippingAddressCreateBody.country_code,
  );
  TestValidator.equals(
    "region echoed in snapshot",
    orderShippingAddress.region ?? null,
    shippingAddressCreateBody.region ?? null,
  );
  TestValidator.equals(
    "phone_number echoed in snapshot",
    orderShippingAddress.phone_number ?? null,
    shippingAddressCreateBody.phone_number ?? null,
  );
}
