import { ArrayUtil, RandomGenerator, TestValidator } from "@nestia/e2e";
import { IConnection } from "@nestia/fetcher";
import typia, { tags } from "typia";

import api from "@ORGANIZATION/PROJECT-api";
import type { IAuthorizationToken } from "@ORGANIZATION/PROJECT-api/lib/structures/IAuthorizationToken";
import type { IShoppingMallCart } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallCart";
import type { IShoppingMallCartItemSummary } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallCartItemSummary";
import type { IShoppingMallCartOwnerCustomerSummary } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallCartOwnerCustomerSummary";
import type { IShoppingMallCartOwnerGuestUserSummary } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallCartOwnerGuestUserSummary";
import type { IShoppingMallCustomer } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallCustomer";
import type { IShoppingMallCustomerJoin } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallCustomerJoin";

/**
 * Validate customer cart creation with explicit non-default currency and
 * status.
 *
 * Business goal: Ensure that when an authenticated customer creates a cart and
 * explicitly provides a currency_code and initial status in
 * IShoppingMallCart.ICreate, the backend honors these values (subject to its
 * policies) instead of always forcing platform defaults. Also verify that
 * server-managed fields like id and timestamps are generated by the backend.
 *
 * Flow:
 *
 * 1. Register a new customer via POST /auth/customer/join using a randomly
 *    generated IShoppingMallCustomerJoin.IRequest payload.
 *
 *    - This returns IShoppingMallCustomer.IAuthorized and, via the SDK, sets the
 *         Authorization header on the shared connection so subsequent customer
 *         endpoints run in that context.
 * 2. As that customer, call POST /shoppingMall/customer/carts with an
 *    IShoppingMallCart.ICreate body that explicitly sets:
 *
 *    - Actor_type = "customer".
 *    - Status = some valid non-default lifecycle label, e.g. "preconfigured". (DTO
 *         treats status as a free-form string, so we pick any meaningful value
 *         and conceptually treat it as non-default.)
 *    - Currency_code = "EUR" to represent a supported non-default currency.
 * 3. Assert that the response is a valid IShoppingMallCart and that:
 *
 *    - Cart.actor_type === "customer".
 *    - Cart.status === requestedStatus.
 *    - Cart.currency_code === requestedCurrency.
 * 4. Assert that server-managed fields are populated:
 *
 *    - Typia.assert(cart) already enforces id/currency/status/timestamps
 *         format-level correctness.
 *    - Additionally, check that id is non-empty and created_at/updated_at look
 *         non-empty (we rely on typia for strict format validation).
 *    - Deleted_at and last_validated_at should be either null or undefined on a
 *         freshly created cart; we only check that they are not non-empty
 *         strings.
 *
 * Negative tests about unsupported currency_code or invalid status are
 * intentionally omitted because their exact business rules are unknown and we
 * must not rely on specific error codes or validation shapes.
 */
export async function test_api_customer_cart_creation_with_custom_currency_and_status(
  connection: api.IConnection,
) {
  // 1. Register a new customer (join)
  const joinRequest = typia.random<IShoppingMallCustomerJoin.IRequest>();

  const customer: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.join(connection, {
      body: joinRequest,
    });
  typia.assert(customer);

  // 2. Create a cart with explicit actor_type, status, and currency_code
  const requestedStatus = "preconfigured";
  const requestedCurrency = "EUR";

  const createBody = {
    actor_type: "customer",
    status: requestedStatus,
    currency_code: requestedCurrency,
  } satisfies IShoppingMallCart.ICreate;

  const cart: IShoppingMallCart =
    await api.functional.shoppingMall.customer.carts.create(connection, {
      body: createBody,
    });
  typia.assert(cart);

  // 3. Assert that explicit fields are honored
  TestValidator.equals(
    "cart actor_type should match explicit 'customer'",
    cart.actor_type,
    "customer",
  );
  TestValidator.equals(
    "cart status should equal requested non-default status",
    cart.status,
    requestedStatus,
  );
  TestValidator.equals(
    "cart currency_code should equal requested non-default currency",
    cart.currency_code,
    requestedCurrency,
  );

  // 4. Assert server-managed fields are populated and not simply echoed
  TestValidator.predicate(
    "cart id should be a non-empty UUID-like string",
    (cart.id as string).length > 0,
  );
  TestValidator.predicate(
    "cart created_at should be a non-empty date-time string",
    (cart.created_at as string).length > 0,
  );
  TestValidator.predicate(
    "cart updated_at should be a non-empty date-time string",
    (cart.updated_at as string).length > 0,
  );

  // deleted_at and last_validated_at are optional and nullable; ensure they
  // are not non-empty strings on freshly created cart (either undefined/null
  // or empty is acceptable; typia already enforces type-level correctness).
  TestValidator.predicate(
    "cart deleted_at should be undefined or null on creation",
    cart.deleted_at === undefined || cart.deleted_at === null,
  );
  TestValidator.predicate(
    "cart last_validated_at should be undefined or null on creation",
    cart.last_validated_at === undefined || cart.last_validated_at === null,
  );
}
