/**
 * Ensure invalid payment status history updates are rejected and do not mutate
 * stored data.
 *
 * Business flow:
 *
 * 1. Create customer, seller, and admin accounts and authenticate them via auth
 *    join/login APIs.
 * 2. As admin, create country, region, shipping method, and payment method
 *    configuration.
 * 3. As seller, create a product; as admin, create a category and link the
 *    product; create a purchasable SKU inventory state; as seller, create a SKU
 *    for the product.
 * 4. As customer, create a cart, add the SKU to the cart, register a shipping
 *    address, and create an order from the cart using the configured shipping
 *    and payment methods.
 * 5. As customer, create a logical payment for the order.
 * 6. As admin, create an initial valid payment status history entry for that
 *    logical payment.
 * 7. Attempt to update that history entry with an invalid backward business status
 *    transition and assert that the update API call fails.
 * 8. Re-fetch the history entry and verify that business-critical fields remain
 *    unchanged, proving rejected updates do not corrupt stored status history.
 */
export async function test_api_payment_status_history_update_invalid_transition_rejected(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer join & login
  const customerJoinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: RandomGenerator.alphaNumeric(12),
    ip: null,
    href: "https://customer.example.com/join",
    referrer: "https://customer.example.com/landing",
  } satisfies IShoppingMallCustomerJoin.IRequest;
  const customerAuth: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.join(connection, {
      body: customerJoinBody,
    });
  typia.assert(customerAuth);

  const customerLoginBody = {
    email: customerJoinBody.email,
    password: customerJoinBody.password,
    ip: null,
    href: "https://customer.example.com/login",
    referrer: "https://customer.example.com/landing",
  } satisfies IShoppingMallCustomerLogin.IRequest;
  const customerLogin: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.login(connection, {
      body: customerLoginBody,
    });
  typia.assert(customerLogin);

  // 2. Seller join & login
  const sellerJoinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: RandomGenerator.alphaNumeric(12) as string &
      tags.Format<"password">,
    ip: null,
    href: "https://seller.example.com/join",
    referrer: "https://seller.example.com/landing",
  } satisfies IShoppingMallSellerAuthJoin.IRequest;
  const sellerAuth: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.join(connection, {
      body: sellerJoinBody,
    });
  typia.assert(sellerAuth);

  const sellerLoginBody = {
    email: sellerJoinBody.email,
    password: sellerJoinBody.password,
    ip: null,
    href: "https://seller.example.com/login",
    referrer: "https://seller.example.com/landing",
  } satisfies IShoppingMallSellerAuthLogin.IRequest;
  const sellerLogin: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.login(connection, {
      body: sellerLoginBody,
    });
  typia.assert(sellerLogin);

  // 3. Admin join & login
  const adminJoinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: RandomGenerator.alphaNumeric(16) as string &
      tags.Format<"password">,
    ip: null,
    href: "https://admin.example.com/join",
    referrer: "https://admin.example.com/landing",
  } satisfies IShoppingMallAdminJoin.ICreate;
  const adminAuth: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.join(connection, {
      body: adminJoinBody,
    });
  typia.assert(adminAuth);

  const adminLoginBody = {
    email: adminJoinBody.email,
    password: adminJoinBody.password,
    ip: null,
    href: "https://admin.example.com/login",
    referrer: "https://admin.example.com/landing",
  } satisfies IShoppingMallAdminLogin.ICreate;
  const adminLogin: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.login(connection, {
      body: adminLoginBody,
    });
  typia.assert(adminLogin);

  // 4. Admin: country and region
  const countryBody = {
    country_code: "KR",
    name_en: "Korea, Republic of",
    phone_code: "+82",
    is_active: true,
    sort_order: 1,
  } satisfies IShoppingMallCountry.ICreate;
  const country: IShoppingMallCountry =
    await api.functional.shoppingMall.admin.countries.create(connection, {
      body: countryBody,
    });
  typia.assert(country);

  const regionBody = {
    code: "SEOUL",
    name_en: "Seoul",
    region_type: "city",
    is_active: true,
    sort_order: 1,
  } satisfies IShoppingMallRegion.ICreate;
  const region: IShoppingMallRegion =
    await api.functional.shoppingMall.admin.countries.regions.create(
      connection,
      {
        countryCode: country.country_code,
        body: regionBody,
      },
    );
  typia.assert(region);

  // 5. Admin: shipping & payment methods
  const shippingMethodBody = {
    method_code: "STANDARD",
    display_name: "Standard Shipping",
    service_level_description: "Standard delivery",
  } satisfies IShoppingMallShippingMethod.ICreate;
  const shippingMethod: IShoppingMallShippingMethod =
    await api.functional.shoppingMall.admin.shippingMethods.create(connection, {
      body: shippingMethodBody,
    });
  typia.assert(shippingMethod);

  const paymentMethodBody = {
    code: "CARD",
    display_name: "Credit Card",
    description: "Generic card payment",
    provider_type: "card_processor",
    allowed_currencies: null,
    allowed_countries: null,
    min_amount: null,
    max_amount: null,
    status: "active",
  } satisfies IShoppingMallPaymentMethod.ICreate;
  const paymentMethod: IShoppingMallPaymentMethod =
    await api.functional.shoppingMall.admin.paymentMethods.create(connection, {
      body: paymentMethodBody,
    });
  typia.assert(paymentMethod);

  // 6. Seller: product, category, product-category link, inventory state, SKU
  const productBody = {
    code: RandomGenerator.alphaNumeric(10),
    title: RandomGenerator.paragraph({ sentences: 3 }),
    summary: RandomGenerator.paragraph({ sentences: 5 }),
    description: RandomGenerator.content({ paragraphs: 2 }),
    brand: "TestBrand",
    model_name: "Model-X",
    status: "active",
    primary_image_uri: "https://cdn.example.com/images/product.jpg",
    default_locale: "en-US",
  } satisfies IShoppingMallProduct.ICreate;
  const product: IShoppingMallProduct =
    await api.functional.shoppingMall.seller.products.create(connection, {
      body: productBody,
    });
  typia.assert(product);

  const categoryBody = {
    parent_id: null,
    slug: RandomGenerator.alphaNumeric(8),
    name_en: "General",
    description_en: "General category",
    status: "active",
    sort_order: 1,
    is_leaf: true,
  } satisfies IShoppingMallCategory.ICreate;
  const category: IShoppingMallCategory =
    await api.functional.shoppingMall.admin.categories.create(connection, {
      body: categoryBody,
    });
  typia.assert(category);

  const productCategoryBody = {
    shopping_mall_category_id: category.id,
    is_primary: true,
  } satisfies IShoppingMallProductCategory.ICreate;
  const productCategory: IShoppingMallProductCategory =
    await api.functional.shoppingMall.admin.products.categories.create(
      connection,
      {
        productId: product.id,
        body: productCategoryBody,
      },
    );
  typia.assert(productCategory);

  const skuInventoryStateBody = {
    code: "IN_STOCK",
    name: "In Stock",
    description: "Available for purchase",
    is_purchasable: true,
  } satisfies IShoppingMallSkuInventoryState.ICreate;
  const skuInventoryState: IShoppingMallSkuInventoryState =
    await api.functional.shoppingMall.admin.skuInventoryStates.create(
      connection,
      {
        body: skuInventoryStateBody,
      },
    );
  typia.assert(skuInventoryState);

  const skuBody = {
    code: RandomGenerator.alphaNumeric(8),
    barcode: null,
    status: "active",
    price: 10000,
    original_price: 12000,
    inventory_quantity: 10,
    low_stock_threshold: 1,
    shopping_mall_sku_inventory_state_id: skuInventoryState.id,
    attribute_value_ids: [],
    external_ids: [],
  } satisfies IShoppingMallSku.ICreate;
  const sku: IShoppingMallSku =
    await api.functional.shoppingMall.seller.products.skus.create(connection, {
      productId: product.id,
      body: skuBody,
    });
  typia.assert(sku);

  // 7. Customer: cart, cart item, shipping address, order
  const cartBody = {
    actor_type: "customer",
    status: undefined,
    currency_code: "KRW",
  } satisfies IShoppingMallCart.ICreate;
  const cart: IShoppingMallCart =
    await api.functional.shoppingMall.customer.carts.create(connection, {
      body: cartBody,
    });
  typia.assert(cart);

  const cartItemBody = {
    shopping_mall_sku_id: sku.id,
    quantity: 1,
  } satisfies IShoppingMallCartItem.ICreate;
  const cartItem: IShoppingMallCartItem =
    await api.functional.shoppingMall.customer.carts.items.create(connection, {
      cartId: cart.id,
      body: cartItemBody,
    });
  typia.assert(cartItem);

  const customerAddressBody = {
    shopping_mall_country_id: country.id,
    shopping_mall_region_id: region.id,
    recipient_name: "Test Customer",
    line1: "123 Test Street",
    line2: null,
    city: "Seoul",
    postal_code: "06236",
    phone_number: RandomGenerator.mobile(),
    is_default: true,
  } satisfies IShoppingMallCustomerAddress.ICreate;
  const customerAddress: IShoppingMallCustomerAddress =
    await api.functional.shoppingMall.customer.customers.addresses.create(
      connection,
      {
        customerId: customerAuth.id,
        body: customerAddressBody,
      },
    );
  typia.assert(customerAddress);

  const orderItemCreate = {
    shopping_mall_sku_id: sku.id,
    quantity: 1,
  } satisfies IShoppingMallOrderItem.ICreate;

  const shippingSnapshot = {
    recipient_name: customerAddress.recipient_name,
    phone_number: customerAddress.phone_number ?? RandomGenerator.mobile(),
    country_code: country.country_code,
    postal_code: customerAddress.postal_code,
    state_or_region: region.name_en,
    city: customerAddress.city,
    address_line1: customerAddress.line1,
    address_line2: customerAddress.line2 ?? null,
  } satisfies IShoppingMallShippingAddressSnapshot.ICreate;

  const orderBody = {
    cart_id: cart.id,
    currency_code: cart.currency_code,
    items: [orderItemCreate],
    shipping_address_id: customerAddress.id,
    shipping_address_snapshot: shippingSnapshot,
    shipping_method_id: shippingMethod.id,
    payment_method_id: paymentMethod.id,
    buyer_memo: null,
    platform_note: null,
  } satisfies IShoppingMallOrder.ICreate;
  const order: IShoppingMallOrder =
    await api.functional.shoppingMall.customer.orders.create(connection, {
      body: orderBody,
    });
  typia.assert(order);

  // 8. Customer: create logical payment for order
  const orderPaymentCreate = {
    payment_method_id: paymentMethod.id,
    currency_code: order.currency_code,
    payable_amount: order.grand_total_amount,
    provider_reference: null,
    provider_status_code: null,
    metadata: null,
  } satisfies IShoppingMallOrderPayment.ICreate;
  const orderPayment: IShoppingMallOrderPayment =
    await api.functional.shoppingMall.customer.orders.payments.create(
      connection,
      {
        orderId: order.id,
        body: orderPaymentCreate,
      },
    );
  typia.assert(orderPayment);

  // 9. Admin: initial valid payment status history
  const initialHistoryCreate = {
    previous_business_status: "pending",
    new_business_status: "paid",
    previous_provider_status_code: "PENDING",
    new_provider_status_code: "CAPTURED",
    reason_code: "initial_capture",
    reason_message: "Initial payment captured",
  } satisfies IShoppingMallPaymentStatusHistory.ICreate;
  const initialHistory: IShoppingMallPaymentStatusHistory =
    await api.functional.shoppingMall.admin.payments.statusHistories.create(
      connection,
      {
        orderPaymentId: orderPayment.id,
        body: initialHistoryCreate,
      },
    );
  typia.assert(initialHistory);

  const originalHistory: IShoppingMallPaymentStatusHistory = {
    ...initialHistory,
  };
  typia.assert(originalHistory);

  // 10. Attempt invalid backward transition update and expect error
  const invalidUpdateBody = {
    previous_business_status: initialHistory.previous_business_status,
    new_business_status: "pending",
    previous_provider_status_code: initialHistory.previous_provider_status_code,
    new_provider_status_code: "REVERTED",
    reason_code: "invalid_backwards_transition",
    reason_message: "Attempt to revert paid to pending",
  } satisfies IShoppingMallPaymentStatusHistory.IUpdate;

  await TestValidator.error(
    "invalid backward payment business status transition is rejected",
    async () => {
      await api.functional.shoppingMall.admin.payments.statusHistories.update(
        connection,
        {
          orderPaymentId: orderPayment.id,
          paymentStatusHistoryId: initialHistory.id,
          body: invalidUpdateBody,
        },
      );
    },
  );

  // 11. Re-fetch history and ensure business-critical fields are unchanged
  const reloadedHistory: IShoppingMallPaymentStatusHistory =
    await api.functional.shoppingMall.admin.payments.statusHistories.at(
      connection,
      {
        orderPaymentId: orderPayment.id,
        paymentStatusHistoryId: initialHistory.id,
      },
    );
  typia.assert(reloadedHistory);

  TestValidator.equals(
    "history id remains same",
    reloadedHistory.id,
    originalHistory.id,
  );
  TestValidator.equals(
    "previous business status unchanged",
    reloadedHistory.previous_business_status ?? null,
    originalHistory.previous_business_status ?? null,
  );
  TestValidator.equals(
    "new business status unchanged from original valid value",
    reloadedHistory.new_business_status,
    originalHistory.new_business_status,
  );
  TestValidator.equals(
    "previous provider status code unchanged",
    reloadedHistory.previous_provider_status_code ?? null,
    originalHistory.previous_provider_status_code ?? null,
  );
  TestValidator.equals(
    "new provider status code unchanged from original",
    reloadedHistory.new_provider_status_code ?? null,
    originalHistory.new_provider_status_code ?? null,
  );
  TestValidator.equals(
    "reason_code unchanged",
    reloadedHistory.reason_code ?? null,
    originalHistory.reason_code ?? null,
  );
  TestValidator.equals(
    "reason_message unchanged",
    reloadedHistory.reason_message ?? null,
    originalHistory.reason_message ?? null,
  );
}
