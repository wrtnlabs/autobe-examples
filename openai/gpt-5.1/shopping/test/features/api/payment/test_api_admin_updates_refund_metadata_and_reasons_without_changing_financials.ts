export async function test_api_admin_updates_refund_metadata_and_reasons_without_changing_financials(
  connection: api.IConnection,
) {
  // 1. Bootstrap admin, seller, and customer actors
  const adminJoinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: "Admin1234!" as string & tags.Format<"password">,
    ip: null,
    href: "https://admin.example.com/join" as string & tags.Format<"uri">,
    referrer: "https://admin.example.com" as string & tags.Format<"uri">,
  } satisfies IShoppingMallAdminJoin.ICreate;
  const admin: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.join(connection, { body: adminJoinBody });
  typia.assert(admin);

  const adminLoginBody = {
    email: admin.email,
    password: adminJoinBody.password,
    ip: null,
    href: "https://admin.example.com/login" as string & tags.Format<"uri">,
    referrer: "https://admin.example.com" as string & tags.Format<"uri">,
  } satisfies IShoppingMallAdminLogin.ICreate;
  const adminLoggedIn: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.login(connection, {
      body: adminLoginBody,
    });
  typia.assert(adminLoggedIn);

  const sellerJoinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: "Seller1234!" as string & tags.Format<"password">,
    ip: null,
    href: "https://seller.example.com/join" as string & tags.Format<"uri">,
    referrer: "https://seller.example.com" as string & tags.Format<"uri">,
  } satisfies IShoppingMallSellerAuthJoin.IRequest;
  const seller: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.join(connection, {
      body: sellerJoinBody,
    });
  typia.assert(seller);

  const sellerLoginBody = {
    email: seller.email,
    password: sellerJoinBody.password,
    ip: null,
    href: "https://seller.example.com/login" as string & tags.Format<"uri">,
    referrer: "https://seller.example.com" as string & tags.Format<"uri">,
  } satisfies IShoppingMallSellerAuthLogin.IRequest;
  const sellerLoggedIn: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.login(connection, {
      body: sellerLoginBody,
    });
  typia.assert(sellerLoggedIn);

  const customerJoinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: "Customer1234!" as string & tags.Format<"password">,
    ip: null,
    href: "https://shop.example.com/join" as string & tags.Format<"uri">,
    referrer: "https://shop.example.com" as string & tags.Format<"uri">,
  } satisfies IShoppingMallCustomerJoin.IRequest;
  const customer: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.join(connection, {
      body: customerJoinBody,
    });
  typia.assert(customer);

  const customerLoginBody = {
    email: customer.email,
    password: customerJoinBody.password,
    ip: null,
    href: "https://shop.example.com/login" as string & tags.Format<"uri">,
    referrer: "https://shop.example.com" as string & tags.Format<"uri">,
  } satisfies IShoppingMallCustomerLogin.IRequest;
  const customerLoggedIn: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.login(connection, {
      body: customerLoginBody,
    });
  typia.assert(customerLoggedIn);

  // 2. As admin, create country and region
  const countryCreateBody = {
    country_code: "KR",
    name_en: "Korea",
    phone_code: "+82",
    is_active: true,
    sort_order: 1 as number & tags.Type<"int32">,
  } satisfies IShoppingMallCountry.ICreate;
  const country: IShoppingMallCountry =
    await api.functional.shoppingMall.admin.countries.create(connection, {
      body: countryCreateBody,
    });
  typia.assert(country);

  const regionCreateBody = {
    code: "SEOUL",
    name_en: "Seoul",
    region_type: "city",
    is_active: true,
    sort_order: 1 as number & tags.Type<"int32">,
  } satisfies IShoppingMallRegion.ICreate;
  const region: IShoppingMallRegion =
    await api.functional.shoppingMall.admin.countries.regions.create(
      connection,
      {
        countryCode: country.country_code,
        body: regionCreateBody,
      },
    );
  typia.assert(region);

  // 3. As admin, create category, inventory state, shipping method, payment method
  const categoryCreateBody = {
    parent_id: null,
    slug: RandomGenerator.alphabets(8),
    name_en: "General",
    description_en: null,
    status: "active",
    sort_order: 1 as number & tags.Type<"int32">,
    is_leaf: true,
  } satisfies IShoppingMallCategory.ICreate;
  const category: IShoppingMallCategory =
    await api.functional.shoppingMall.admin.categories.create(connection, {
      body: categoryCreateBody,
    });
  typia.assert(category);

  const inventoryStateCreateBody = {
    code: "in_stock",
    name: "In Stock",
    description: "Purchasable",
    is_purchasable: true,
  } satisfies IShoppingMallSkuInventoryState.ICreate;
  const inventoryState: IShoppingMallSkuInventoryState =
    await api.functional.shoppingMall.admin.skuInventoryStates.create(
      connection,
      { body: inventoryStateCreateBody },
    );
  typia.assert(inventoryState);

  const shippingMethodCreateBody = {
    method_code: "standard",
    display_name: "Standard Shipping",
    service_level_description: "Standard delivery",
  } satisfies IShoppingMallShippingMethod.ICreate;
  const shippingMethod: IShoppingMallShippingMethod =
    await api.functional.shoppingMall.admin.shippingMethods.create(connection, {
      body: shippingMethodCreateBody,
    });
  typia.assert(shippingMethod);

  const paymentMethodCreateBody = {
    code: "card",
    display_name: "Credit Card",
    description: "Card payment",
    provider_type: "card_processor",
    allowed_currencies: "KRW",
    allowed_countries: "KR",
    min_amount: null,
    max_amount: null,
    status: "active",
  } satisfies IShoppingMallPaymentMethod.ICreate;
  const paymentMethod: IShoppingMallPaymentMethod =
    await api.functional.shoppingMall.admin.paymentMethods.create(connection, {
      body: paymentMethodCreateBody,
    });
  typia.assert(paymentMethod);

  // 4. As seller, create product and SKU (seller auth already active via seller login above)
  const productCreateBody = {
    code: RandomGenerator.alphaNumeric(8),
    title: "Test Product",
    summary: "Test product summary",
    description: "Detailed description",
    brand: null,
    model_name: null,
    status: "active",
    primary_image_uri: null,
    default_locale: "ko-KR",
  } satisfies IShoppingMallProduct.ICreate;
  const product: IShoppingMallProduct =
    await api.functional.shoppingMall.seller.products.create(connection, {
      body: productCreateBody,
    });
  typia.assert(product);

  const productCategoryCreateBody = {
    shopping_mall_category_id: category.id,
    is_primary: true,
  } satisfies IShoppingMallProductCategory.ICreate;
  const productCategory: IShoppingMallProductCategory =
    await api.functional.shoppingMall.admin.products.categories.create(
      connection,
      {
        productId: product.id,
        body: productCategoryCreateBody,
      },
    );
  typia.assert(productCategory);

  const skuCreateBody = {
    code: RandomGenerator.alphaNumeric(8) as string &
      tags.MinLength<1> &
      tags.MaxLength<255>,
    barcode: null,
    status: "active" as string & tags.MinLength<1> & tags.MaxLength<64>,
    price: 10000,
    original_price: 12000,
    inventory_quantity: 10 as number & tags.Type<"int32"> & tags.Minimum<0>,
    low_stock_threshold: 1 as number & tags.Type<"int32"> & tags.Minimum<0>,
    shopping_mall_sku_inventory_state_id: inventoryState.id,
    attribute_value_ids: [],
    external_ids: [],
  } satisfies IShoppingMallSku.ICreate;
  const sku: IShoppingMallSku =
    await api.functional.shoppingMall.seller.products.skus.create(connection, {
      productId: product.id as string & tags.Format<"uuid">,
      body: skuCreateBody,
    });
  typia.assert(sku);

  // 5. As customer, create cart, add item, create address, and order
  const cartCreateBody = {
    actor_type: "customer",
    status: "active",
    currency_code: "KRW",
  } satisfies IShoppingMallCart.ICreate;
  const cart: IShoppingMallCart =
    await api.functional.shoppingMall.customer.carts.create(connection, {
      body: cartCreateBody,
    });
  typia.assert(cart);

  const cartItemCreateBody = {
    shopping_mall_sku_id: sku.id,
    quantity: 1 as number & tags.Type<"int32"> & tags.Minimum<1>,
  } satisfies IShoppingMallCartItem.ICreate;
  const cartItem: IShoppingMallCartItem =
    await api.functional.shoppingMall.customer.carts.items.create(connection, {
      cartId: cart.id as string & tags.Format<"uuid">,
      body: cartItemCreateBody,
    });
  typia.assert(cartItem);

  const customerAddressCreateBody = {
    shopping_mall_country_id: country.id,
    shopping_mall_region_id: region.id,
    recipient_name: "Customer",
    line1: "Line 1",
    line2: null,
    city: "Seoul",
    postal_code: "12345",
    phone_number: RandomGenerator.mobile(),
    is_default: true,
  } satisfies IShoppingMallCustomerAddress.ICreate;
  const customerAddress: IShoppingMallCustomerAddress =
    await api.functional.shoppingMall.customer.customers.addresses.create(
      connection,
      {
        customerId: customer.id,
        body: customerAddressCreateBody,
      },
    );
  typia.assert(customerAddress);

  const shippingAddressSnapshotCreateBody = {
    recipient_name: customerAddress.recipient_name,
    phone_number: customerAddress.phone_number ?? RandomGenerator.mobile(),
    country_code: country.country_code,
    postal_code: customerAddress.postal_code,
    state_or_region: region.name_en,
    city: customerAddress.city,
    address_line1: customerAddress.line1,
    address_line2: customerAddress.line2 ?? null,
  } satisfies IShoppingMallShippingAddressSnapshot.ICreate;

  const orderItemCreateBody = {
    shopping_mall_sku_id: sku.id,
    quantity: 1 as number & tags.Type<"int32">,
  } satisfies IShoppingMallOrderItem.ICreate;

  const orderCreateBody = {
    cart_id: cart.id,
    currency_code: "KRW",
    items: [orderItemCreateBody],
    shipping_address_id: customerAddress.id,
    shipping_address_snapshot: shippingAddressSnapshotCreateBody,
    shipping_method_id: shippingMethod.id,
    payment_method_id: paymentMethod.id,
    buyer_memo: null,
    platform_note: null,
  } satisfies IShoppingMallOrder.ICreate;
  const order: IShoppingMallOrder =
    await api.functional.shoppingMall.customer.orders.create(connection, {
      body: orderCreateBody,
    });
  typia.assert(order);

  // 6. As customer, create order payment for the order
  const payableAmount = 10000;
  const orderPaymentCreateBody = {
    payment_method_id: paymentMethod.id,
    currency_code: order.currency_code,
    payable_amount: payableAmount,
    provider_reference: "INIT_REF",
    provider_status_code: "INIT",
    metadata: "initial-metadata",
  } satisfies IShoppingMallOrderPayment.ICreate;
  const orderPayment: IShoppingMallOrderPayment =
    await api.functional.shoppingMall.customer.orders.payments.create(
      connection,
      {
        orderId: order.id,
        body: orderPaymentCreateBody,
      },
    );
  typia.assert(orderPayment);

  // switch back to admin (login ensures admin token)
  const adminReloginBody = {
    email: admin.email,
    password: adminJoinBody.password,
    ip: null,
    href: "https://admin.example.com/login2" as string & tags.Format<"uri">,
    referrer: "https://admin.example.com" as string & tags.Format<"uri">,
  } satisfies IShoppingMallAdminLogin.ICreate;
  const adminRelogged: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.login(connection, {
      body: adminReloginBody,
    });
  typia.assert(adminRelogged);

  // 7. As admin, create initial refund with specific values
  const initialRefundBody = {
    currency_code: orderPayment.currency_code,
    requested_amount: payableAmount,
    approved_amount: payableAmount,
    refunded_amount: 0,
    status: "pending",
    reason_code: "INITIAL",
    reason_message: "Initial reason",
    provider_reference: "PROV_INIT",
    metadata: '{"step":1}',
  } satisfies IShoppingMallPaymentRefund.ICreate;
  const refund: IShoppingMallPaymentRefund =
    await api.functional.shoppingMall.admin.payments.refunds.create(
      connection,
      {
        orderPaymentId: orderPayment.id,
        body: initialRefundBody,
      },
    );
  typia.assert(refund);

  // Capture original state
  const originalId = refund.id;
  const originalPaymentId = refund.shopping_mall_order_payment_id;
  const originalSequence = refund.refund_sequence;
  const originalCurrency = refund.currency_code;
  const originalRequested = refund.requested_amount;
  const originalApproved = refund.approved_amount;
  const originalRefunded = refund.refunded_amount;
  const originalStatus = refund.status;
  const originalReasonCode = refund.reason_code ?? null;
  const originalReasonMessage = refund.reason_message ?? null;
  const originalProviderRef = refund.provider_reference ?? null;
  const originalMetadata = refund.metadata ?? null;
  const originalCreatedAt = refund.created_at;
  const originalUpdatedAt = refund.updated_at;

  // 9. As admin, update only metadata-relevant fields
  const updatedReasonCode: string | null = null; // explicit clear
  const updatedReasonMessage = "Updated message";
  const updatedProviderRef: string | null = null; // explicit clear
  const updatedMetadata = '{"step":2,"note":"changed"}';

  const refundUpdateBody = {
    status: undefined,
    approved_amount: undefined,
    refunded_amount: undefined,
    reason_code: updatedReasonCode,
    reason_message: updatedReasonMessage,
    provider_reference: updatedProviderRef,
    metadata: updatedMetadata,
  } satisfies IShoppingMallPaymentRefund.IUpdate;

  const updatedRefund: IShoppingMallPaymentRefund =
    await api.functional.shoppingMall.admin.payments.refunds.update(
      connection,
      {
        orderPaymentId: originalPaymentId,
        refundSequence: originalSequence as number & tags.Type<"int32">,
        body: refundUpdateBody,
      },
    );
  typia.assert(updatedRefund);

  // 10. Verify invariants and updated metadata
  TestValidator.equals(
    "id should remain unchanged",
    updatedRefund.id,
    originalId,
  );
  TestValidator.equals(
    "order payment id should remain unchanged",
    updatedRefund.shopping_mall_order_payment_id,
    originalPaymentId,
  );
  TestValidator.equals(
    "refund sequence should remain unchanged",
    updatedRefund.refund_sequence,
    originalSequence,
  );
  TestValidator.equals(
    "currency should remain unchanged",
    updatedRefund.currency_code,
    originalCurrency,
  );
  TestValidator.equals(
    "requested amount should remain unchanged",
    updatedRefund.requested_amount,
    originalRequested,
  );
  TestValidator.equals(
    "approved amount should remain unchanged",
    updatedRefund.approved_amount,
    originalApproved,
  );
  TestValidator.equals(
    "refunded amount should remain unchanged",
    updatedRefund.refunded_amount,
    originalRefunded,
  );
  TestValidator.equals(
    "status should remain unchanged",
    updatedRefund.status,
    originalStatus,
  );

  TestValidator.equals(
    "reason code should follow update (null clears)",
    updatedRefund.reason_code ?? null,
    updatedReasonCode,
  );
  TestValidator.equals(
    "reason message should follow update",
    updatedRefund.reason_message ?? null,
    updatedReasonMessage,
  );
  TestValidator.equals(
    "provider reference should follow update (null clears)",
    updatedRefund.provider_reference ?? null,
    updatedProviderRef,
  );
  TestValidator.equals(
    "metadata should follow update",
    updatedRefund.metadata ?? null,
    updatedMetadata,
  );

  TestValidator.equals(
    "created_at should remain unchanged",
    updatedRefund.created_at,
    originalCreatedAt,
  );

  const updatedTimeNewer =
    new Date(updatedRefund.updated_at).getTime() >
    new Date(originalUpdatedAt).getTime();
  TestValidator.predicate(
    "updated_at should be greater than original",
    updatedTimeNewer,
  );
}
