export async function test_api_payment_status_history_retrieval_after_successful_payment(
  connection: api.IConnection,
) {
  // 1. Register and authenticate core actors: customer, seller, admin
  const customerJoinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: RandomGenerator.alphaNumeric(12),
    ip: null,
    href: "https://customer.example.com/join",
    referrer: "https://customer.example.com/landing",
  } satisfies IShoppingMallCustomerJoin.IRequest;

  const customer: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.join(connection, {
      body: customerJoinBody,
    });
  typia.assert(customer);

  const sellerJoinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: RandomGenerator.alphaNumeric(12) as string &
      tags.Format<"password">,
    ip: null,
    href: "https://seller.example.com/join",
    referrer: "https://seller.example.com/landing",
  } satisfies IShoppingMallSellerAuthJoin.IRequest;

  const seller: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.join(connection, {
      body: sellerJoinBody,
    });
  typia.assert(seller);

  const adminJoinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: RandomGenerator.alphaNumeric(16) as string &
      tags.Format<"password">,
    ip: null,
    href: "https://admin.example.com/join",
    referrer: "https://admin.example.com/landing",
  } satisfies IShoppingMallAdminJoin.ICreate;

  const admin: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.join(connection, {
      body: adminJoinBody,
    });
  typia.assert(admin);

  // 2. Seed configuration as admin: country, region, category, sku inventory state, shipping & payment methods
  const countryCreateBody = {
    country_code: "US",
    name_en: "United States",
    phone_code: "+1",
    is_active: true,
    sort_order: 1 as number & tags.Type<"int32">,
  } satisfies IShoppingMallCountry.ICreate;

  const country: IShoppingMallCountry =
    await api.functional.shoppingMall.admin.countries.create(connection, {
      body: countryCreateBody,
    });
  typia.assert(country);

  const regionCreateBody = {
    code: "CA",
    name_en: "California",
    region_type: "state",
    is_active: true,
    sort_order: 1 as number & tags.Type<"int32">,
  } satisfies IShoppingMallRegion.ICreate;

  const region: IShoppingMallRegion =
    await api.functional.shoppingMall.admin.countries.regions.create(
      connection,
      {
        countryCode: country.country_code,
        body: regionCreateBody,
      },
    );
  typia.assert(region);

  const categoryCreateBody = {
    parent_id: null,
    slug: `electronics-${RandomGenerator.alphaNumeric(8)}`,
    name_en: "Electronics",
    description_en: "Electronic devices",
    status: "active",
    sort_order: 1 as number & tags.Type<"int32">,
    is_leaf: true,
  } satisfies IShoppingMallCategory.ICreate;

  const category: IShoppingMallCategory =
    await api.functional.shoppingMall.admin.categories.create(connection, {
      body: categoryCreateBody,
    });
  typia.assert(category);

  const skuInventoryStateCreateBody = {
    code: `in_stock_${RandomGenerator.alphaNumeric(6)}`,
    name: "In Stock",
    description: "Sku is in stock and purchasable",
    is_purchasable: true,
  } satisfies IShoppingMallSkuInventoryState.ICreate;

  const skuInventoryState: IShoppingMallSkuInventoryState =
    await api.functional.shoppingMall.admin.skuInventoryStates.create(
      connection,
      {
        body: skuInventoryStateCreateBody,
      },
    );
  typia.assert(skuInventoryState);

  const shippingMethodCreateBody = {
    method_code: `standard_${RandomGenerator.alphaNumeric(6)}`,
    display_name: "Standard Shipping",
    service_level_description: "Standard ground shipping",
  } satisfies IShoppingMallShippingMethod.ICreate;

  const shippingMethod: IShoppingMallShippingMethod =
    await api.functional.shoppingMall.admin.shippingMethods.create(connection, {
      body: shippingMethodCreateBody,
    });
  typia.assert(shippingMethod);

  const paymentMethodCreateBody = {
    code: `card_${RandomGenerator.alphaNumeric(6)}`,
    display_name: "Credit Card",
    description: "Generic credit card payment",
    provider_type: "card_processor",
    allowed_currencies: "USD",
    allowed_countries: "US",
    min_amount: 0,
    max_amount: null,
    status: "active",
  } satisfies IShoppingMallPaymentMethod.ICreate;

  const paymentMethod: IShoppingMallPaymentMethod =
    await api.functional.shoppingMall.admin.paymentMethods.create(connection, {
      body: paymentMethodCreateBody,
    });
  typia.assert(paymentMethod);

  // 3. Seed catalog as seller: product, product-category link, SKU
  const productCreateBody = {
    code: `SKU-PROD-${RandomGenerator.alphaNumeric(6)}`,
    title: "Test Phone",
    summary: "A test smartphone",
    description: "A fully featured test smartphone for integration tests.",
    brand: "TestBrand",
    model_name: "TB-Phone-1",
    status: "active",
    primary_image_uri:
      "https://cdn.example.com/images/test-phone.png" as string &
        tags.Format<"uri">,
    default_locale: "en-US",
  } satisfies IShoppingMallProduct.ICreate;

  const product: IShoppingMallProduct =
    await api.functional.shoppingMall.seller.products.create(connection, {
      body: productCreateBody,
    });
  typia.assert(product);

  const productCategoryCreateBody = {
    shopping_mall_category_id: category.id,
    is_primary: true,
  } satisfies IShoppingMallProductCategory.ICreate;

  const productCategory: IShoppingMallProductCategory =
    await api.functional.shoppingMall.admin.products.categories.create(
      connection,
      {
        productId: product.id,
        body: productCategoryCreateBody,
      },
    );
  typia.assert(productCategory);

  const skuPrice = 199.99;
  const skuCreateBody = {
    code: `SKU-${RandomGenerator.alphaNumeric(8)}` as string &
      tags.MinLength<1> &
      tags.MaxLength<255>,
    barcode: null,
    status: "active" as string & tags.MinLength<1> & tags.MaxLength<64>,
    price: skuPrice,
    original_price: skuPrice,
    inventory_quantity: 10 as number & tags.Type<"int32"> & tags.Minimum<0>,
    low_stock_threshold: 1 as number & tags.Type<"int32"> & tags.Minimum<0>,
    shopping_mall_sku_inventory_state_id: skuInventoryState.id,
    attribute_value_ids: [],
    external_ids: [],
  } satisfies IShoppingMallSku.ICreate;

  const sku: IShoppingMallSku =
    await api.functional.shoppingMall.seller.products.skus.create(connection, {
      productId: product.id as string & tags.Format<"uuid">,
      body: skuCreateBody,
    });
  typia.assert(sku);

  // 4. Customer cart and address setup
  const cartCreateBody = {
    actor_type: "customer",
    status: "active",
    currency_code: "USD",
  } satisfies IShoppingMallCart.ICreate;

  const cart: IShoppingMallCart =
    await api.functional.shoppingMall.customer.carts.create(connection, {
      body: cartCreateBody,
    });
  typia.assert(cart);

  const cartItemCreateBody = {
    shopping_mall_sku_id: sku.id,
    quantity: 1 as number & tags.Type<"int32"> & tags.Minimum<1>,
  } satisfies IShoppingMallCartItem.ICreate;

  const cartItem: IShoppingMallCartItem =
    await api.functional.shoppingMall.customer.carts.items.create(connection, {
      cartId: cart.id,
      body: cartItemCreateBody,
    });
  typia.assert(cartItem);

  const customerAddressCreateBody = {
    shopping_mall_country_id: country.id,
    shopping_mall_region_id: region.id,
    recipient_name: RandomGenerator.name(),
    line1: "123 Test Street",
    line2: "Suite 100",
    city: "Test City",
    postal_code: "12345",
    phone_number: RandomGenerator.mobile(),
    is_default: true,
  } satisfies IShoppingMallCustomerAddress.ICreate;

  const customerAddress: IShoppingMallCustomerAddress =
    await api.functional.shoppingMall.customer.customers.addresses.create(
      connection,
      {
        customerId: customer.id,
        body: customerAddressCreateBody,
      },
    );
  typia.assert(customerAddress);

  // 5. Create order from cart as customer
  const orderItemCreate: IShoppingMallOrderItem.ICreate = {
    shopping_mall_sku_id: sku.id,
    quantity: 1 as number & tags.Type<"int32">,
  };

  const orderCreateBody: IShoppingMallOrder.ICreate = {
    cart_id: cart.id,
    currency_code: cart.currency_code,
    items: [orderItemCreate],
    shipping_address_id: customerAddress.id,
    shipping_address_snapshot: null,
    shipping_method_id: shippingMethod.id,
    payment_method_id: paymentMethod.id,
    buyer_memo: null,
    platform_note: null,
  };

  const order: IShoppingMallOrder =
    await api.functional.shoppingMall.customer.orders.create(connection, {
      body: orderCreateBody,
    });
  typia.assert(order);

  // 6. Create a logical payment for the order as customer
  const payableAmount = order.grand_total_amount;
  const orderPaymentCreateBody = {
    payment_method_id: paymentMethod.id,
    currency_code: order.currency_code,
    payable_amount: payableAmount,
    provider_reference: null,
    provider_status_code: null,
    metadata: null,
  } satisfies IShoppingMallOrderPayment.ICreate;

  const orderPayment: IShoppingMallOrderPayment =
    await api.functional.shoppingMall.customer.orders.payments.create(
      connection,
      {
        orderId: order.id,
        body: orderPaymentCreateBody,
      },
    );
  typia.assert(orderPayment);

  // 7. As admin, create payment status history for the logical payment
  const adminLoginBody = {
    email: admin.email,
    password: adminJoinBody.password,
    ip: null,
    href: "https://admin.example.com/login",
    referrer: "https://admin.example.com/dashboard",
  } satisfies IShoppingMallAdminLogin.ICreate;

  const adminLoggedIn: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.login(connection, {
      body: adminLoginBody,
    });
  typia.assert(adminLoggedIn);

  const previousBusinessStatus: string | null = orderPayment.business_status;
  const newBusinessStatus =
    orderPayment.business_status === "pending" ? "paid" : "completed";

  const paymentStatusHistoryCreateBody = {
    previous_business_status: previousBusinessStatus,
    new_business_status: newBusinessStatus,
    previous_provider_status_code: orderPayment.provider_status_code ?? null,
    new_provider_status_code: "CAPTURED",
    reason_code: "payment_captured",
    reason_message: "Payment captured successfully for the order.",
  } satisfies IShoppingMallPaymentStatusHistory.ICreate;

  const createdHistory: IShoppingMallPaymentStatusHistory =
    await api.functional.shoppingMall.admin.payments.statusHistories.create(
      connection,
      {
        orderPaymentId: orderPayment.id,
        body: paymentStatusHistoryCreateBody,
      },
    );
  typia.assert(createdHistory);

  // 8. Retrieve the specific payment status history as admin
  const retrievedHistory: IShoppingMallPaymentStatusHistory =
    await api.functional.shoppingMall.admin.payments.statusHistories.at(
      connection,
      {
        orderPaymentId: orderPayment.id,
        paymentStatusHistoryId: createdHistory.id,
      },
    );
  typia.assert(retrievedHistory);

  // 9. Assertions and business validations
  TestValidator.equals(
    "retrieved history id matches created history id",
    retrievedHistory.id,
    createdHistory.id,
  );

  if (createdHistory.orderPayment !== undefined) {
    TestValidator.equals(
      "created history orderPayment id matches logical payment id",
      createdHistory.orderPayment.id,
      orderPayment.id,
    );
  }

  if (retrievedHistory.orderPayment !== undefined) {
    TestValidator.equals(
      "retrieved history orderPayment id matches logical payment id",
      retrievedHistory.orderPayment.id,
      orderPayment.id,
    );
  }

  TestValidator.equals(
    "new business status in created history matches input",
    createdHistory.new_business_status,
    newBusinessStatus,
  );

  TestValidator.equals(
    "new business status in retrieved history matches input",
    retrievedHistory.new_business_status,
    newBusinessStatus,
  );

  TestValidator.equals(
    "previous business status in created history matches input",
    createdHistory.previous_business_status ?? null,
    previousBusinessStatus,
  );

  TestValidator.equals(
    "previous business status in retrieved history matches input",
    retrievedHistory.previous_business_status ?? null,
    previousBusinessStatus,
  );

  TestValidator.equals(
    "new provider status code in created history matches input",
    createdHistory.new_provider_status_code ?? null,
    paymentStatusHistoryCreateBody.new_provider_status_code ?? null,
  );

  TestValidator.equals(
    "new provider status code in retrieved history matches input",
    retrievedHistory.new_provider_status_code ?? null,
    paymentStatusHistoryCreateBody.new_provider_status_code ?? null,
  );

  TestValidator.equals(
    "reason code in retrieved history matches input",
    retrievedHistory.reason_code ?? null,
    paymentStatusHistoryCreateBody.reason_code ?? null,
  );

  TestValidator.equals(
    "reason message in retrieved history matches input",
    retrievedHistory.reason_message ?? null,
    paymentStatusHistoryCreateBody.reason_message ?? null,
  );

  TestValidator.predicate(
    "new business status differs from previous business status when previous exists",
    previousBusinessStatus === null ||
      previousBusinessStatus === undefined ||
      previousBusinessStatus !== newBusinessStatus,
  );

  TestValidator.predicate(
    "payable amount is non-negative",
    orderPayment.payable_amount >= 0,
  );

  TestValidator.predicate(
    "captured, refunded and chargeback amounts are non-negative",
    orderPayment.captured_amount >= 0 &&
      orderPayment.refunded_amount >= 0 &&
      orderPayment.chargeback_amount >= 0,
  );
}
