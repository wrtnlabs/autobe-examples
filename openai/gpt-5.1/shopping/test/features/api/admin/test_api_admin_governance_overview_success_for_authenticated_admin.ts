import { ArrayUtil, RandomGenerator, TestValidator } from "@nestia/e2e";
import { IConnection } from "@nestia/fetcher";
import typia, { tags } from "typia";

import api from "@ORGANIZATION/PROJECT-api";
import type { IAuthorizationToken } from "@ORGANIZATION/PROJECT-api/lib/structures/IAuthorizationToken";
import type { IShoppingMallAdmin } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallAdmin";
import type { IShoppingMallAdminActivityStatsSummary } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallAdminActivityStatsSummary";
import type { IShoppingMallAdminGovernanceOverview } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallAdminGovernanceOverview";
import type { IShoppingMallAdminJoin } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallAdminJoin";
import type { IShoppingMallLegalHoldStatsSummary } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallLegalHoldStatsSummary";
import type { IShoppingMallOrderDailyStatPoint } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallOrderDailyStatPoint";
import type { IShoppingMallOrderStatsSummary } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallOrderStatsSummary";
import type { IShoppingMallPlatformKpisSummary } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallPlatformKpisSummary";
import type { IShoppingMallRefundAndDisputeStatsSummary } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallRefundAndDisputeStatsSummary";

/**
 * Validate successful governance overview retrieval for an authenticated admin.
 *
 * Business context:
 *
 * - The governance overview dashboard aggregates multiple KPI and governance
 *   snapshot tables into a single read-only DTO for shopping mall admins.
 * - Only authenticated administrators are allowed to access this endpoint, and
 *   the SDK automatically manages the Authorization header after a successful
 *   admin join/login.
 *
 * Test steps:
 *
 * 1. Register a new admin via POST /auth/admin/join using a valid
 *    IShoppingMallAdminJoin.ICreate payload (generated by typia.random). This
 *    implicitly authenticates the admin and sets the access token on the shared
 *    connection instance.
 * 2. While authenticated as this admin, call GET
 *    /shoppingMall/admin/adminDashboard/governanceOverview through
 *    api.functional.shoppingMall.admin.adminDashboard.governanceOverview.at.
 * 3. Assert that the response structurally matches
 *    IShoppingMallAdminGovernanceOverview using typia.assert, which also
 *    validates all nested summary DTOs and formats like generatedAt.
 * 4. Perform additional business sanity checks using TestValidator to ensure key
 *    numeric metrics are non-negative and that simple relationships (such as
 *    highSeverityAuditEventCount not exceeding recentAuditEventCount) hold,
 *    without depending on specific snapshot values.
 */
export async function test_api_admin_governance_overview_success_for_authenticated_admin(
  connection: api.IConnection,
) {
  // 1. Register and authenticate an admin via /auth/admin/join
  const joinBody = typia.random<IShoppingMallAdminJoin.ICreate>();

  const authorizedAdmin: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.join(connection, {
      body: joinBody,
    });
  typia.assert<IShoppingMallAdmin.IAuthorized>(authorizedAdmin);
  typia.assert<IAuthorizationToken>(authorizedAdmin.token);

  // 2. Retrieve governance overview as the authenticated admin
  const overview: IShoppingMallAdminGovernanceOverview =
    await api.functional.shoppingMall.admin.adminDashboard.governanceOverview.at(
      connection,
    );
  typia.assert<IShoppingMallAdminGovernanceOverview>(overview);

  const platformKpis: IShoppingMallPlatformKpisSummary = overview.platformKpis;
  const orderStats: IShoppingMallOrderStatsSummary = overview.orderStats;
  const refundAndDisputeStats: IShoppingMallRefundAndDisputeStatsSummary =
    overview.refundAndDisputeStats;
  const legalHoldStats: IShoppingMallLegalHoldStatsSummary =
    overview.legalHoldStats;
  const adminActivityStats: IShoppingMallAdminActivityStatsSummary =
    overview.adminActivityStats;

  // 3. Basic business sanity checks on platform KPIs
  TestValidator.predicate(
    "platformKpis.activeCustomerCount is non-negative",
    platformKpis.activeCustomerCount >= 0,
  );
  TestValidator.predicate(
    "platformKpis.activeSellerCount is non-negative",
    platformKpis.activeSellerCount >= 0,
  );
  TestValidator.predicate(
    "platformKpis.orderCount is non-negative",
    platformKpis.orderCount >= 0,
  );
  TestValidator.predicate(
    "platformKpis.grossMerchandiseVolume is non-negative",
    platformKpis.grossMerchandiseVolume >= 0,
  );
  TestValidator.predicate(
    "platformKpis.currency is non-empty string",
    platformKpis.currency.length > 0,
  );

  // 4. Order statistics sanity checks
  TestValidator.predicate(
    "orderStats.totalOrders is non-negative",
    orderStats.totalOrders >= 0,
  );
  TestValidator.predicate(
    "orderStats.totalRevenue is non-negative",
    orderStats.totalRevenue >= 0,
  );
  TestValidator.predicate(
    "orderStats.currency is non-empty string",
    orderStats.currency.length > 0,
  );

  const dailyStats: IShoppingMallOrderDailyStatPoint[] | undefined =
    orderStats.recentDailyStats;
  if (dailyStats !== undefined) {
    await ArrayUtil.asyncForEach(dailyStats, async (point) => {
      TestValidator.predicate(
        "dailyStat.orderCount is non-negative",
        point.orderCount >= 0,
      );
      TestValidator.predicate(
        "dailyStat.revenue is non-negative",
        point.revenue >= 0,
      );
    });
  }

  // 5. Refund and dispute statistics sanity checks
  TestValidator.predicate(
    "refundAndDisputeStats.totalRefundCount is non-negative",
    refundAndDisputeStats.totalRefundCount >= 0,
  );
  TestValidator.predicate(
    "refundAndDisputeStats.totalRefundAmount is non-negative",
    refundAndDisputeStats.totalRefundAmount >= 0,
  );
  TestValidator.predicate(
    "refundAndDisputeStats.totalDisputeCount is non-negative",
    refundAndDisputeStats.totalDisputeCount >= 0,
  );
  TestValidator.predicate(
    "refundAndDisputeStats.refundRate is non-negative",
    refundAndDisputeStats.refundRate >= 0,
  );
  TestValidator.predicate(
    "refundAndDisputeStats.disputeRate is non-negative",
    refundAndDisputeStats.disputeRate >= 0,
  );
  TestValidator.predicate(
    "refundAndDisputeStats.currency is non-empty string",
    refundAndDisputeStats.currency.length > 0,
  );

  // 6. Legal hold statistics sanity checks
  TestValidator.predicate(
    "legalHoldStats.activeLegalHoldCount is non-negative",
    legalHoldStats.activeLegalHoldCount >= 0,
  );
  TestValidator.predicate(
    "legalHoldStats.recentlyClosedLegalHoldCount is non-negative",
    legalHoldStats.recentlyClosedLegalHoldCount >= 0,
  );
  TestValidator.predicate(
    "legalHoldStats.affectedEntityCount is non-negative",
    legalHoldStats.affectedEntityCount >= 0,
  );

  // 7. Admin activity statistics sanity checks
  TestValidator.predicate(
    "adminActivityStats.totalAdminCount is non-negative",
    adminActivityStats.totalAdminCount >= 0,
  );
  TestValidator.predicate(
    "adminActivityStats.activeAdminCount is non-negative",
    adminActivityStats.activeAdminCount >= 0,
  );
  TestValidator.predicate(
    "adminActivityStats.recentAuditEventCount is non-negative",
    adminActivityStats.recentAuditEventCount >= 0,
  );
  TestValidator.predicate(
    "adminActivityStats.highSeverityAuditEventCount is non-negative",
    adminActivityStats.highSeverityAuditEventCount >= 0,
  );
  TestValidator.predicate(
    "highSeverityAuditEventCount does not exceed recentAuditEventCount",
    adminActivityStats.highSeverityAuditEventCount <=
      adminActivityStats.recentAuditEventCount,
  );

  // 8. Ensure generatedAt is a non-empty ISO date-time string
  TestValidator.predicate(
    "overview.generatedAt is non-empty string",
    overview.generatedAt.length > 0,
  );
}
