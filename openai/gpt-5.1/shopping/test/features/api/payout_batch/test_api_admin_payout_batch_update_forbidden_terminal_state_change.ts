export async function test_api_admin_payout_batch_update_forbidden_terminal_state_change(
  connection: api.IConnection,
) {
  // 1. Admin signs up (join) and becomes authenticated for admin operations
  const adminJoinBody = {
    email: `admin+${RandomGenerator.alphaNumeric(8)}@example.com`,
    password: RandomGenerator.alphabets(12),
    ip: null,
    href: "https://admin.shoppingmall.test/join",
    referrer: "https://admin.shoppingmall.test/landing",
  } satisfies IShoppingMallAdminJoin.ICreate;

  const adminAuthorized: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.join(connection, {
      body: adminJoinBody,
    });
  typia.assert<IShoppingMallAdmin.IAuthorized>(adminAuthorized);

  // 2. Create a non-terminal payout batch as admin
  const now = new Date();
  const sevenDaysAgo = new Date(now.getTime() - 7 * 24 * 60 * 60 * 1000);

  const batchCode = `PB-${RandomGenerator.alphaNumeric(10)}`;

  const createBody = {
    batch_code: batchCode,
    payout_period_start: sevenDaysAgo.toISOString(),
    payout_period_end: now.toISOString(),
    currency_code: "USD",
    total_gross_amount: 1000,
    total_commission_amount: 100,
    total_net_payout_amount: 900,
    status: "processing",
    external_reference: RandomGenerator.alphaNumeric(12),
    notes: "initial payout batch for forbidden transition test",
  } satisfies IShoppingMallSellerPayoutBatch.ICreate;

  const createdBatch: IShoppingMallSellerPayoutBatch =
    await api.functional.shoppingMall.admin.payoutBatches.create(connection, {
      body: createBody,
    });
  typia.assert<IShoppingMallSellerPayoutBatch>(createdBatch);

  TestValidator.equals(
    "created batch should have the requested batchCode",
    createdBatch.batchCode,
    batchCode,
  );

  // 3. Move the payout batch into a terminal status (e.g., "completed")
  const terminalStatus = "completed";

  const terminalUpdateBody = {
    status: terminalStatus,
  } satisfies IShoppingMallSellerPayoutBatch.IUpdate;

  const terminalBatch: IShoppingMallSellerPayoutBatch =
    await api.functional.shoppingMall.admin.payoutBatches.update(connection, {
      batchCode: createdBatch.batchCode,
      body: terminalUpdateBody,
    });
  typia.assert<IShoppingMallSellerPayoutBatch>(terminalBatch);

  TestValidator.equals(
    "batch status should be updated to terminal status",
    terminalBatch.status,
    terminalStatus,
  );

  // 4. Attempt forbidden change from terminal status back to non-terminal
  const invalidUpdateBody = {
    status: "draft",
    notes: "attempt to revert status from completed to draft",
  } satisfies IShoppingMallSellerPayoutBatch.IUpdate;

  await TestValidator.error(
    "updating a completed payout batch back to a non-terminal status should fail",
    async () => {
      await api.functional.shoppingMall.admin.payoutBatches.update(connection, {
        batchCode: createdBatch.batchCode,
        body: invalidUpdateBody,
      });
    },
  );
}
