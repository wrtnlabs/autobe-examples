/**
 * Validate that inventory movement search can be scoped by order and
 * reservation identifiers.
 *
 * Business goal: Ensure that PATCH
 * /shoppingMall/inventoryItems/{inventoryItemId}/movements respects the
 * combination of order_id, order_line_id, and reservation_id filters so that
 * operational tooling can drill down into all movements generated by a specific
 * order line and its reservations.
 *
 * High-level workflow:
 *
 * 1. Register and authenticate a seller.
 * 2. As seller, create a product, then a SKU under that product, and finally an
 *    inventory item for that SKU.
 * 3. Register and authenticate a customer.
 * 4. As customer, create a customer cart, add the SKU as a cart item, and create
 *    an order from that cart so that an order and at least one order line
 *    exist.
 * 5. Register and authenticate a platform admin.
 * 6. As platform admin, create an inventory reservation for the inventory item,
 *    referencing the created order and a specific order line.
 * 7. As platform admin, delete that reservation so that the backend produces at
 *    least a reservation_create and a reservation_release movement tied to the
 *    same order_id, order_line_id and reservation_id.
 * 8. Call PATCH /shoppingMall/inventoryItems/{inventoryItemId}/movements with a
 *    body that includes page/limit pagination and sets order_id, order_line_id,
 *    and reservation_id to the IDs created earlier.
 * 9. Assert that the response only contains movements for the inventory item and
 *    that pagination metadata is consistent and non-negative.
 * 10. Optionally, issue a second search that omits reservation_id but keeps
 *     order_id and order_line_id, and verify that the result set is non-empty
 *     and still bound to the same inventory item.
 */
export async function test_api_inventory_movement_search_by_order_and_reservation(
  connection: api.IConnection,
) {
  // 1. Register seller and obtain authorized session
  const sellerJoinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: RandomGenerator.alphabets(12),
    storeName: RandomGenerator.name(2),
    contactPhone: RandomGenerator.mobile(),
  } satisfies IShoppingMallSellerJoin.IRequest;
  const sellerAuthorized: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.join(connection, { body: sellerJoinBody });
  typia.assert(sellerAuthorized);

  // 2. Seller creates product
  const productBody = {
    shopping_mall_seller_id: sellerAuthorized.id,
    shopping_mall_brand_id: null,
    code: `SKU-PROD-${RandomGenerator.alphaNumeric(8)}`,
    name: RandomGenerator.paragraph({ sentences: 2 }),
    short_description: RandomGenerator.paragraph({ sentences: 3 }),
    description: RandomGenerator.content({ paragraphs: 2 }),
    status: "active",
    is_multi_sku: true,
    primary_image_uri: undefined,
    additional_data: undefined,
  } satisfies IShoppingMallProduct.ICreate;
  const product: IShoppingMallProduct =
    await api.functional.shoppingMall.seller.products.create(connection, {
      body: productBody,
    });
  typia.assert(product);

  // 3. Seller creates a SKU under the product
  const skuBody = {
    code: `SKU-${RandomGenerator.alphaNumeric(6)}`,
    name: RandomGenerator.paragraph({ sentences: 2 }),
    listPrice: 10000,
    salePrice: 9000,
    currency: "KRW",
    isActive: true,
    isPurchasable: true,
  } satisfies IShoppingMallProductSku.ICreate;
  const sku: IShoppingMallProductSku =
    await api.functional.shoppingMall.seller.products.skus.create(connection, {
      productCode: product.code,
      body: skuBody,
    });
  typia.assert(sku);

  // 4. Seller creates an inventory item for the SKU
  const inventoryCreateBody = {
    product_sku_id: sku.id,
    on_hand_quantity: 10,
    low_stock_threshold: 1,
    backorder_enabled: false,
    preorder_enabled: false,
  } satisfies IShoppingMallInventoryItem.ICreate;
  const inventoryItem: IShoppingMallInventoryItem =
    await api.functional.shoppingMall.seller.inventoryItems.create(connection, {
      body: inventoryCreateBody,
    });
  typia.assert(inventoryItem);

  // 5. Register customer and obtain authorized session
  const customerJoinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: RandomGenerator.alphabets(12),
    name: RandomGenerator.name(2),
    ip: null,
    href: "https://customer.example.com/join",
    referrer: "https://customer.example.com/landing",
  } satisfies IShoppingMallCustomerAuth.IJoin;
  const customerAuthorized: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.join(connection, {
      body: customerJoinBody,
    });
  typia.assert(customerAuthorized);

  // 6. Customer creates a cart
  const cartCreateBody = {
    currency_code: "KRW",
    region_code: undefined,
    channel: "web",
    metadata: undefined,
    is_active: true,
    source_guest_token: undefined,
  } satisfies IShoppingMallCustomerCart.ICreate;
  const cart: IShoppingMallCustomerCart =
    await api.functional.shoppingMall.customer.customerCarts.create(
      connection,
      {
        body: cartCreateBody,
      },
    );
  typia.assert(cart);

  // 7. Customer adds the SKU as a cart item
  const cartItemBody = {
    skuId: sku.id,
    quantity: 1,
    note: RandomGenerator.paragraph({ sentences: 2 }),
  } satisfies IShoppingMallCustomerCartItem.ICreate;
  const cartItem: IShoppingMallCustomerCartItem =
    await api.functional.shoppingMall.customer.customerCarts.items.create(
      connection,
      {
        customerCartId: cart.id,
        body: cartItemBody,
      },
    );
  typia.assert(cartItem);

  // 8. Customer creates an order from the cart
  const orderCreateBody = {
    customer_cart_id: cart.id,
    currency_code: cart.currency_code,
    items_subtotal_amount: cart.subtotal_amount,
    discount_total_amount: cart.discount_amount,
    shipping_total_amount: cart.shipping_amount,
    tax_total_amount: cart.tax_amount,
    grand_total_amount: cart.total_amount,
    shipping_address_id: typia.random<string & tags.Format<"uuid">>(),
    billing_address_id: typia.random<string & tags.Format<"uuid">>(),
    customer_note: undefined,
  } satisfies IShoppingMallOrder.ICreate;
  const order: IShoppingMallOrder =
    await api.functional.shoppingMall.customer.orders.create(connection, {
      body: orderCreateBody,
    });
  typia.assert(order);

  // NOTE: The SDK does not expose order lines directly. We synthesize an
  // order_line_id for the reservation and then consistently reuse
  // reservation.order_line_id in movement filters, keeping the scenario
  // internally consistent while remaining compilable.
  const assumedOrderLineId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();

  // 9. Register platform admin and obtain authorized session
  const platformAdminJoinBody = {
    email: typia.random<string & tags.Format<"email">>(),
    name: RandomGenerator.name(2),
    password: RandomGenerator.alphabets(12),
    ip: null,
    href: "https://admin.example.com/join",
    referrer: "https://admin.example.com/landing",
  } satisfies IShoppingMallPlatformAdminJoin.IRequest;
  const platformAdminAuthorized: IShoppingMallPlatformAdmin.IAuthorized =
    await api.functional.auth.platformAdmin.join(connection, {
      body: platformAdminJoinBody,
    });
  typia.assert(platformAdminAuthorized);

  // 10. Platform admin creates an inventory reservation for the inventory item
  const expiresAt = new Date(Date.now() + 60 * 60 * 1000).toISOString();
  const reservationCreateBody = {
    inventory_item_id: inventoryItem.id,
    order_id: order.id,
    order_line_id: assumedOrderLineId,
    reserved_quantity: 1,
    reservation_state: "active",
    expires_at: expiresAt,
    consumed_at: null,
    cancelled_at: null,
  } satisfies IShoppingMallInventoryReservation.ICreate;
  const reservation: IShoppingMallInventoryReservation =
    await api.functional.shoppingMall.platformAdmin.inventoryItems.reservations.create(
      connection,
      {
        inventoryItemId: inventoryItem.id,
        body: reservationCreateBody,
      },
    );
  typia.assert(reservation);

  // 11. Platform admin deletes the reservation, which should generate a
  // reservation_release movement in addition to the reservation_create movement.
  await api.functional.shoppingMall.platformAdmin.inventoryItems.reservations.erase(
    connection,
    {
      inventoryItemId: inventoryItem.id,
      reservationId: reservation.id,
    },
  );

  // 12. Query movements for this inventory item filtered by order, order line,
  // and reservation.
  const movementsPage: IPageIShoppingMallInventoryMovement.ISummary =
    await api.functional.shoppingMall.inventoryItems.movements.index(
      connection,
      {
        inventoryItemId: inventoryItem.id,
        body: {
          page: 1,
          limit: 50,
          fromDate: undefined,
          toDate: undefined,
          movementTypes: undefined,
          direction: undefined,
          order_id: reservation.order_id,
          order_line_id: reservation.order_line_id,
          reservation_id: reservation.id,
          sortBy: "created_at",
          sortOrder: "asc",
        } satisfies IShoppingMallInventoryMovement.IRequest,
      },
    );
  typia.assert(movementsPage);

  // Basic pagination sanity checks
  const pagination = movementsPage.pagination;
  typia.assert<IPage.IPagination>(pagination);
  TestValidator.predicate(
    "movements pagination records non-negative",
    pagination.records >= 0,
  );

  const movements = movementsPage.data;
  TestValidator.predicate(
    "movements list should not be empty for the reservation filters",
    movements.length > 0,
  );

  // Ensure every movement belongs to the inventory item
  for (const movement of movements) {
    typia.assert<IShoppingMallInventoryMovement.ISummary>(movement);
    TestValidator.equals(
      "movement.inventory_item_id matches inventoryItem.id",
      movement.inventory_item_id,
      inventoryItem.id,
    );
  }

  // 13. Optionally, query again omitting reservation_id while still filtering
  // by order_id and order_line_id.
  const widenedPage: IPageIShoppingMallInventoryMovement.ISummary =
    await api.functional.shoppingMall.inventoryItems.movements.index(
      connection,
      {
        inventoryItemId: inventoryItem.id,
        body: {
          page: 1,
          limit: 50,
          fromDate: undefined,
          toDate: undefined,
          movementTypes: undefined,
          direction: undefined,
          order_id: reservation.order_id,
          order_line_id: reservation.order_line_id,
          reservation_id: undefined,
          sortBy: "created_at",
          sortOrder: "asc",
        } satisfies IShoppingMallInventoryMovement.IRequest,
      },
    );
  typia.assert(widenedPage);

  const widenedMovements = widenedPage.data;
  TestValidator.predicate(
    "widened movements list should not be empty when filtering only by order and order line",
    widenedMovements.length > 0,
  );
  for (const movement of widenedMovements) {
    typia.assert<IShoppingMallInventoryMovement.ISummary>(movement);
    TestValidator.equals(
      "widened movement.inventory_item_id matches inventoryItem.id",
      movement.inventory_item_id,
      inventoryItem.id,
    );
  }
}
