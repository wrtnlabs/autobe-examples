export async function test_api_admin_payment_method_analytics_refund_and_chargeback_metrics(
  connection: api.IConnection,
) {
  // 1. Admin join & login
  const adminEmail: string = typia.random<string & tags.Format<"email">>();
  const adminJoinBody = {
    email: adminEmail,
    password: RandomGenerator.alphabets(12),
    ip: null,
    href: "https://admin.example.com/join",
    referrer: "https://admin.example.com/",
  } satisfies IShoppingMallAdminJoin.ICreate;
  const admin: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.join(connection, {
      body: adminJoinBody,
    });
  typia.assert(admin);

  const adminLoginBody = {
    email: adminEmail,
    password: adminJoinBody.password,
    ip: null,
    href: "https://admin.example.com/login",
    referrer: "https://admin.example.com/",
  } satisfies IShoppingMallAdminLogin.ICreate;
  const adminLogin: IShoppingMallAdmin.IAuthorized =
    await api.functional.auth.admin.login(connection, {
      body: adminLoginBody,
    });
  typia.assert(adminLogin);

  // 2. Create payment method as admin
  const paymentMethodCode: string = `pm_${RandomGenerator.alphaNumeric(8)}`;
  const paymentMethodBody = {
    code: paymentMethodCode,
    display_name: "Test Card",
    description: "Test payment method for analytics",
    provider_type: "card_processor",
    allowed_currencies: null,
    allowed_countries: null,
    min_amount: null,
    max_amount: null,
    status: "active",
  } satisfies IShoppingMallPaymentMethod.ICreate;
  const paymentMethod: IShoppingMallPaymentMethod =
    await api.functional.shoppingMall.admin.paymentMethods.create(connection, {
      body: paymentMethodBody,
    });
  typia.assert(paymentMethod);

  // 3. Create inventory state as admin
  const skuInventoryStateBody = {
    code: `state_${RandomGenerator.alphaNumeric(6)}`,
    name: "In Stock",
    description: "Purchasable state for tests",
    is_purchasable: true,
  } satisfies IShoppingMallSkuInventoryState.ICreate;
  const inventoryState: IShoppingMallSkuInventoryState =
    await api.functional.shoppingMall.admin.skuInventoryStates.create(
      connection,
      { body: skuInventoryStateBody },
    );
  typia.assert(inventoryState);

  // 4. Seller join & login
  const sellerEmail: string = typia.random<string & tags.Format<"email">>();
  const sellerJoinBody = {
    email: sellerEmail,
    password: RandomGenerator.alphabets(12),
    ip: null,
    href: "https://seller.example.com/join",
    referrer: "https://seller.example.com/",
  } satisfies IShoppingMallSellerAuthJoin.IRequest;
  const seller: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.join(connection, {
      body: sellerJoinBody,
    });
  typia.assert(seller);

  const sellerLoginBody = {
    email: sellerEmail,
    password: sellerJoinBody.password,
    ip: null,
    href: "https://seller.example.com/login",
    referrer: "https://seller.example.com/",
  } satisfies IShoppingMallSellerAuthLogin.IRequest;
  const sellerLogin: IShoppingMallSeller.IAuthorized =
    await api.functional.auth.seller.login(connection, {
      body: sellerLoginBody,
    });
  typia.assert(sellerLogin);

  // 5. Seller creates product
  const productBody = {
    code: `PROD-${RandomGenerator.alphaNumeric(6)}`,
    title: RandomGenerator.paragraph({ sentences: 3 }),
    summary: RandomGenerator.paragraph({ sentences: 2 }),
    description: RandomGenerator.content({ paragraphs: 2 }),
    brand: null,
    model_name: null,
    status: "active",
    primary_image_uri: null,
    default_locale: "en-US",
  } satisfies IShoppingMallProduct.ICreate;
  const product: IShoppingMallProduct =
    await api.functional.shoppingMall.seller.products.create(connection, {
      body: productBody,
    });
  typia.assert(product);

  // 6. Seller creates SKU under product with inventory state
  const skuBody = {
    code: `SKU-${RandomGenerator.alphaNumeric(6)}`,
    barcode: null,
    status: "active",
    price: 100,
    original_price: null,
    inventory_quantity: 10,
    low_stock_threshold: null,
    shopping_mall_sku_inventory_state_id: inventoryState.id,
    attribute_value_ids: [],
    external_ids: [],
  } satisfies IShoppingMallSku.ICreate;
  const sku: IShoppingMallSku =
    await api.functional.shoppingMall.seller.products.skus.create(connection, {
      productId: product.id,
      body: skuBody,
    });
  typia.assert(sku);

  // 7. Customer join & login
  const customerEmail: string = typia.random<string & tags.Format<"email">>();
  const customerJoinBody = {
    email: customerEmail,
    password: RandomGenerator.alphabets(12) as string & tags.Format<"password">,
    ip: null,
    href: "https://shop.example.com/join",
    referrer: "https://shop.example.com/",
  } satisfies IShoppingMallCustomerJoin.IRequest;
  const customer: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.join(connection, {
      body: customerJoinBody,
    });
  typia.assert(customer);

  const customerLoginBody = {
    email: customerEmail,
    password: customerJoinBody.password,
    ip: null,
    href: "https://shop.example.com/login",
    referrer: "https://shop.example.com/",
  } satisfies IShoppingMallCustomerLogin.IRequest;
  const customerLogin: IShoppingMallCustomer.IAuthorized =
    await api.functional.auth.customer.login(connection, {
      body: customerLoginBody,
    });
  typia.assert(customerLogin);

  // 8. Customer creates cart
  const cartBody = {
    actor_type: "customer",
    status: "active",
    currency_code: "USD",
  } satisfies IShoppingMallCart.ICreate;
  const cart: IShoppingMallCart =
    await api.functional.shoppingMall.customer.carts.create(connection, {
      body: cartBody,
    });
  typia.assert(cart);

  // 9. Customer address
  const addressBody = {
    shopping_mall_country_id: typia.random<string & tags.Format<"uuid">>(),
    shopping_mall_region_id: null,
    recipient_name: RandomGenerator.name(2),
    line1: "123 Test Street",
    line2: null,
    city: "Seoul",
    postal_code: "12345",
    phone_number: RandomGenerator.mobile(),
    is_default: true,
  } satisfies IShoppingMallCustomerAddress.ICreate;
  const address: IShoppingMallCustomerAddress =
    await api.functional.shoppingMall.customer.customers.addresses.create(
      connection,
      {
        customerId: customer.id,
        body: addressBody,
      },
    );
  typia.assert(address);

  // 10. Create order
  const shippingSnapshotBody = {
    recipient_name: address.recipient_name,
    phone_number: address.phone_number ?? RandomGenerator.mobile(),
    country_code: "KR",
    postal_code: address.postal_code,
    state_or_region: "Seoul",
    city: address.city,
    address_line1: address.line1,
    address_line2: address.line2 ?? null,
  } satisfies IShoppingMallShippingAddressSnapshot.ICreate;

  const orderBody = {
    cart_id: cart.id,
    currency_code: cart.currency_code,
    items: [
      {
        shopping_mall_sku_id: sku.id,
        quantity: 1,
      } satisfies IShoppingMallOrderItem.ICreate,
    ],
    shipping_address_id: null,
    shipping_address_snapshot: shippingSnapshotBody,
    shipping_method_id: null,
    payment_method_id: paymentMethod.id,
    buyer_memo: null,
    platform_note: null,
  } satisfies IShoppingMallOrder.ICreate;
  const order: IShoppingMallOrder =
    await api.functional.shoppingMall.customer.orders.create(connection, {
      body: orderBody,
    });
  typia.assert(order);

  // 11. Create logical payment for order using configured payment method
  const paymentBody = {
    payment_method_id: paymentMethod.id,
    currency_code: order.currency_code,
    payable_amount: order.grand_total_amount,
    provider_reference: null,
    provider_status_code: null,
    metadata: null,
  } satisfies IShoppingMallOrderPayment.ICreate;
  const payment: IShoppingMallOrderPayment =
    await api.functional.shoppingMall.customer.orders.payments.create(
      connection,
      {
        orderId: order.id,
        body: paymentBody,
      },
    );
  typia.assert(payment);

  // Small time window around now for analytics
  const now = new Date();
  const from = new Date(now.getTime() - 5 * 60 * 1000).toISOString();
  const to = new Date(now.getTime() + 5 * 60 * 1000).toISOString();

  const baseRequest = {
    from,
    to,
    paymentMethodCodes: [paymentMethod.code],
    regionCodes: [],
    groupBy: ["paymentMethod"],
    granularity: undefined,
    minTotalAmount: undefined,
    maxTotalAmount: undefined,
    includeRefunds: false,
    includeChargebacks: false,
    sortBy: "totalAmount",
    sortDirection: "desc",
    page: 1,
    limit: 50,
  } satisfies IShoppingMallPaymentMethodAnalytics.IRequest;

  const analyticsWithoutFlags: IPageIShoppingMallPaymentMethodAnalytics.ISummary =
    await api.functional.shoppingMall.admin.analytics.paymentMethods.stats.index(
      connection,
      { body: baseRequest },
    );
  typia.assert(analyticsWithoutFlags);

  const withFlagsRequest: IShoppingMallPaymentMethodAnalytics.IRequest = {
    ...baseRequest,
    includeRefunds: true,
    includeChargebacks: true,
  };
  const analyticsWithFlags: IPageIShoppingMallPaymentMethodAnalytics.ISummary =
    await api.functional.shoppingMall.admin.analytics.paymentMethods.stats.index(
      connection,
      { body: withFlagsRequest },
    );
  typia.assert(analyticsWithFlags);

  // Find the row for our payment method in both responses
  const rowWithout = analyticsWithoutFlags.data.find(
    (row) => row.payment_method_code === paymentMethod.code,
  );
  const rowWith = analyticsWithFlags.data.find(
    (row) => row.payment_method_code === paymentMethod.code,
  );

  TestValidator.predicate(
    "analytics row for payment method exists without flags",
    rowWithout !== undefined,
  );
  TestValidator.predicate(
    "analytics row for payment method exists with flags",
    rowWith !== undefined,
  );

  if (!rowWithout || !rowWith) return;

  // Unrelated metrics should remain the same regardless of flags
  TestValidator.equals(
    "payment_attempt_count stable across flag toggles",
    rowWithout.payment_attempt_count,
    rowWith.payment_attempt_count,
  );
  TestValidator.equals(
    "paid_gmv_amount stable across flag toggles",
    rowWithout.paid_gmv_amount,
    rowWith.paid_gmv_amount,
  );
}
