/**
 * Retrieve aggregated analytics about review moderation activity, workload, and
 * outcomes based on review-related moderation and reporting tables.
 *
 * This operation is centered on the review moderation lifecycle as represented
 * in Prisma models like shopping_mall_review_reports for reports and flags
 * submitted against reviews, shopping_mall_review_moderation_actions for the
 * decisions and actions taken by moderators, shopping_mall_review_helpful_votes
 * for signals related to perceived usefulness, and
 * shopping_mall_review_eligibilities for determining when customers are allowed
 * to submit reviews. By aggregating across these tables, the endpoint provides
 * metrics such as number of reviews reported, number of open vs resolved
 * reports, actions taken over a period, and breakdowns by report reason,
 * moderator, seller, or product.
 *
 * From a security and authorization perspective, this endpoint should be
 * exposed only to administrative or governance actors who are responsible for
 * content quality and policy enforcement. It does not return raw review text or
 * personally identifiable information; instead, it returns aggregated counts
 * and KPI-like measures that can be safely used for internal dashboards. This
 * design respects the intent of the underlying Prisma schema comments that
 * position these tables as system-of-record structures for moderation and
 * reporting events, while the analytics layer surfaces only the information
 * needed to operate the moderation function.
 *
 * The request body allows clients to define a time range, select specific
 * moderation states (for example, reported, under_review, resolved), filter by
 * report reasons, and choose grouping dimensions (such as time buckets, report
 * reason, moderator, or seller). The server will translate this configuration
 * into appropriate queries across the moderation-related tables, compute
 * aggregates such as counts, resolution times, and action distributions, and
 * return them in a normalized analytical DTO. This endpoint is typically used
 * together with PATCH /analytics/reviews/volume to provide both volume and
 * moderation views of the review ecosystem.
 *
 * @param props.connection
 * @param props.body Filter, time range, and grouping configuration for
 *   computing review moderation analytics over review reporting and moderation
 *   tables.
 * @path /shoppingMall/admin/analytics/reviews/moderation
 * @accessor api.functional.shoppingMall.admin.analytics.reviews.moderation.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Filter, time range, and grouping configuration for computing review
     * moderation analytics over review reporting and moderation tables.
     */
    body: IShoppingMallReviewModerationAnalytics.IRequest;
  };
  export type Body = IShoppingMallReviewModerationAnalytics.IRequest;
  export type Response = IShoppingMallReviewModerationAnalytics;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/analytics/reviews/moderation",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/analytics/reviews/moderation";
  export const random = (): IShoppingMallReviewModerationAnalytics =>
    typia.random<IShoppingMallReviewModerationAnalytics>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
