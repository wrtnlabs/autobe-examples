/**
 * Retrieve an aggregated refund and post-payment adjustment summary derived
 * from ShoppingMall refund- and dispute-related tables.
 *
 * Retrieve a comprehensive analytical summary of refunds and related
 * post-payment adjustments on the ShoppingMall platform for a specified period
 * and filter set.
 *
 * This operation primarily reads from the `shopping_mall_payment_refunds`
 * table, which records individual refund transactions tied to one or more order
 * payments, and the `shopping_mall_payment_refund_items` table, which breaks
 * refunds down per order item or price component. It also pulls contextual case
 * data from `shopping_mall_refund_requests` and
 * `shopping_mall_refund_request_items`, which model high-level refund cases and
 * their line-level impact, as well as `shopping_mall_refund_request_reasons`
 * and `shopping_mall_refund_request_status_histories` to analyze why refunds
 * are requested and how they progress over time.
 *
 * Where relevant, the summary may incorporate dispute-related context by
 * reading from `shopping_mall_disputes`, `shopping_mall_dispute_events`, and
 * SLA-focused tables such as `shopping_mall_case_sla_configs` and
 * `shopping_mall_case_sla_violations`, enabling metrics like percentage of
 * refunds that escalated into disputes or percentage of cases that breached
 * defined SLAs. Snapshot tables like `shopping_mall_refund_and_dispute_stats`
 * can be leveraged to answer common time-series questions efficiently without
 * scanning all raw records.
 *
 * The request body `IShoppingMallAnalyticsRefundSummary.IRequest` allows
 * callers to provide a mandatory date range, optional dimensions such as
 * grouping by reason code or seller, and filters such as minimum refund amount,
 * inclusion or exclusion of certain case types (e.g., goodwill vs.
 * policy-driven refunds), or focusing on specific risk flags. Validation
 * confirms that provided reason codes, seller identifiers, and any status
 * filters map correctly to the corresponding Prisma reference or enumeration
 * fields, and that the date range and grouping parameters are within allowed
 * bounds to protect system performance.
 *
 * From a security perspective, this endpoint is restricted to administrative
 * actors, because it exposes platform-wide financial adjustments, operational
 * efficiency metrics, and policy-driven outcomes that should not be visible to
 * general customers or individual sellers. Authorization based on the `admin`
 * actor ensures only authorized administrators can query this analytics view.
 * The endpoint is intended to power internal dashboards, governance reports,
 * and risk oversight tooling, and is expected to be invoked by backend cron
 * jobs or admin UI components rather than by public clients.
 *
 * This analytic refund summary endpoint is designed to complement both raw
 * record endpoints on `shopping_mall_payment_refunds` and case management APIs
 * around `shopping_mall_refund_requests` and `shopping_mall_disputes`.
 * Together, these APIs allow the ShoppingMall organization to both act on
 * individual cases and continuously monitor aggregate behavior to refine
 * business policies over time.
 *
 * @param props.connection
 * @param props.body Filter and configuration parameters defining the time
 *   window, grouping, and optional scoping for the refund analytics summary.
 * @path /shoppingMall/admin/analytics/refunds/summary
 * @accessor api.functional.shoppingMall.admin.analytics.refunds.summary.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
