import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallActorSearch } from "../../../../../structures/IShoppingMallActorSearch";
import { IPageIShoppingMallActorSearch } from "../../../../../structures/IPageIShoppingMallActorSearch";

/**
 * Search across customers, sellers, admins, and guest users using a unified
 * actor search over multiple shoppingMall actor tables.
 *
 * Search across all major actor types (customers, sellers, admins, and guest
 * users) in the shoppingMall platform using a unified query interface.
 *
 * This operation does not correspond to a single Prisma table. Instead, it is
 * an analytical search API that composes results from the primary actor models
 * `shopping_mall_customers`, `shopping_mall_sellers`, `shopping_mall_admins`,
 * and `shopping_mall_guestusers` and may enrich them with data from associated
 * profile models such as `shopping_mall_customer_profiles`,
 * `shopping_mall_seller_profiles`, and `shopping_mall_admin_profiles`. The
 * intention is to provide a single endpoint where administrators can search for
 * any actor, regardless of type, using common criteria such as email, phone
 * number, name, external identifiers, or internal reference codes.
 *
 * From a security and governance standpoint, this endpoint is reserved for
 * administrative personnel, as denoted by the `admin` authorization actor.
 * Ordinary customers, sellers, or guest users should not have access to a
 * cross-actor directory, because that could reveal sensitive correlation
 * information between accounts or expose internal identifiers. Administrative
 * users rely on this search for tasks such as fraud investigations, customer
 * support escalations, policy enforcement, and compliance checks.
 *
 * The request body uses `IShoppingMallActorSearch.IRequest`, which encapsulates
 * complex search criteria, pagination configuration, and sorting options. It
 * may include filters specific to one or more actor types, status flags
 * (active, suspended, under investigation), registration date ranges, or other
 * business attributes defined at the requirements level. The HTTP method is
 * PATCH to allow for this rich and potentially large filter structure in the
 * body while preserving idempotent read semantics.
 *
 * The response type `IPageIShoppingMallActorSearch.ISummary` delivers a
 * paginated list of actor search result summaries. Each summary record includes
 * the basic identification data (such as actor type, primary identifier,
 * display name, and contact points) sufficient for administrative screens to
 * render search results and allow operators to navigate to more detailed,
 * actor-type-specific views. Error handling covers invalid filter structures,
 * unauthorized access by non-admin users, and internal failures in the composed
 * search logic that aggregates records from multiple underlying Prisma models.
 *
 * @param props.connection
 * @param props.body Unified search criteria, pagination, and sorting
 *   configuration for cross-actor search across customers, sellers, admins, and
 *   guest users.
 * @path /shoppingMall/admin/actors/search
 * @accessor api.functional.shoppingMall.admin.actors.search.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unified search criteria, pagination, and sorting configuration for
     * cross-actor search across customers, sellers, admins, and guest
     * users.
     */
    body: IShoppingMallActorSearch.IRequest;
  };
  export type Body = IShoppingMallActorSearch.IRequest;
  export type Response = IPageIShoppingMallActorSearch.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/actors/search",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/actors/search";
  export const random = (): IPageIShoppingMallActorSearch.ISummary =>
    typia.random<IPageIShoppingMallActorSearch.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
