import { IShoppingMallConfig } from "../../../../../structures/IShoppingMallConfig";
import { IPageIShoppingMallConfig } from "../../../../../structures/IPageIShoppingMallConfig";

/**
 * Search and list configuration records from the shopping_mall_configs table by
 * namespace using rich filter criteria.
 *
 * Retrieve a paginated list of configuration records from the
 * shopping_mall_configs table filtered by namespace and other optional
 * criteria.
 *
 * The /configs/byNamespace search API is targeted at admin users who need to
 * browse and manage global configuration grouped by logical namespaces. The
 * underlying shopping_mall_configs Prisma model is assumed to store
 * configuration metadata such as namespace, key, effective value, and
 * descriptive text. The request payload, represented by
 * IShoppingMallConfig.IRequest, allows clients to specify namespace filters,
 * free-text search terms, and pagination parameters like page number and page
 * size, along with optional sorting preferences.
 *
 * Upon receiving a valid request, the service composes a Prisma query that
 * selects configuration records whose namespace and other attributes match the
 * provided criteria. The result set is converted into summary DTOs defined by
 * IShoppingMallConfig.ISummary and wrapped in a paginated container
 * IPageIShoppingMallConfig.ISummary, which includes metadata such as total
 * count and paging cursors or offsets. No changes are made to the underlying
 * data; this is a read-only operation that simply exposes search capabilities
 * over shopping_mall_configs.
 *
 * Security-wise, this endpoint is restricted to admin actors because
 * configuration records can influence core platform behavior and may expose
 * sensitive operational details. It is commonly used alongside configuration
 * detail, creation, update, and deletion APIs to provide a complete
 * administrative experience for managing the ShoppingMall platform's global
 * settings.
 *
 * @param props.connection
 * @param props.body Search and pagination criteria for filtering configuration
 *   records in shopping_mall_configs by namespace and related attributes.
 * @path /shoppingMall/admin/configs/byNamespace
 * @accessor api.functional.shoppingMall.admin.configs.byNamespace.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search and pagination criteria for filtering configuration records in
     * shopping_mall_configs by namespace and related attributes.
     */
    body: IShoppingMallConfig.IRequest;
  };
  export type Body = IShoppingMallConfig.IRequest;
  export type Response = IPageIShoppingMallConfig.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/configs/byNamespace",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/configs/byNamespace";
  export const random = (): IPageIShoppingMallConfig.ISummary =>
    typia.random<IPageIShoppingMallConfig.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
