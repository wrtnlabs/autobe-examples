/**
 * Retrieve a paginated and filtered list of risk flags attached to a specific
 * seller account, using the shopping_mall_account_risk_flags and
 * shopping_mall_account_risk_flags_of_sellers tables as the underlying data
 * sources.
 *
 * From a security and governance perspective, this operation is intended for
 * internal administrative tooling rather than for seller self-service. The risk
 * flags themselves are created and maintained automatically by the platform’s
 * risk and security subsystems based on rules, policies, and detection events
 * defined elsewhere in the system. Because of this, the API is strictly
 * read-only: it allows inspection of risk flags but provides no capability to
 * create, modify, or erase them. This design avoids accidental tampering with
 * system-generated data while still giving risk and support personnel the
 * visibility they require.
 *
 * On the database side, each logical risk flag is stored in the
 * shopping_mall_account_risk_flags primary table, which may include fields such
 * as a unique identifier, the flagged subject type, severity, category or rule
 * key, status, timestamps, and descriptive metadata. The subsidiary table
 * shopping_mall_account_risk_flags_of_sellers links those generic risk flags
 * specifically to seller accounts in shopping_mall_sellers, ensuring that the
 * same risk flag model can also be used for customers, admins, and guest users
 * through their respective linkage tables. This operation uses the sellerId
 * path parameter to constrain the query to flags whose linkage row points at
 * the given seller, thereby returning only risk flags relevant to that seller.
 *
 * The request body uses IShoppingMallAccountRiskFlag.IRequest to express search
 * criteria such as severity filters, status filters, creation date ranges,
 * free-text search over reasons or categories, as well as pagination and
 * sorting preferences. The response body wraps the resulting flag summaries in
 * IPageIShoppingMallAccountRiskFlag.ISummary, providing page metadata like
 * total count, pageSize, and current page alongside a list of summary objects
 * suited for list views. Related operations that may be used together include
 * higher-level risk dashboards for sellers, case management endpoints based on
 * shopping_mall_risk_cases, and account-level security event views backed by
 * shopping_mall_actor_security_events and its seller linkage table, but those
 * are handled by separate endpoints.
 *
 * Error handling is focused on validation and authorization. If the sellerId
 * does not correspond to any existing seller record, the implementation should
 * return a not-found error. If the authenticated principal does not have the
 * "admin" actor role, access must be denied to prevent disclosure of sensitive
 * risk assessments. The operation should also guard against excessively large
 * page sizes or overly broad filter combinations to protect performance,
 * potentially returning validation errors when request constraints are
 * violated. In all cases, the underlying risk flag records remain immutable
 * through this API, ensuring that system-generated risk posture remains
 * authoritative.
 *
 * @param props.connection
 * @param props.sellerId Unique identifier of the target seller whose associated
 *   account risk flags should be retrieved. This corresponds to the primary key
 *   of a record in the shopping_mall_sellers table and scopes the search to
 *   risk flags linked through shopping_mall_account_risk_flags_of_sellers.
 * @param props.body Search criteria, filters, and pagination options for
 *   querying seller-related risk flags.
 * @path /shoppingMall/admin/sellers/:sellerId/accountRiskFlags
 * @accessor api.functional.shoppingMall.admin.sellers.accountRiskFlags.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target seller whose associated account risk
     * flags should be retrieved. This corresponds to the primary key of a
     * record in the shopping_mall_sellers table and scopes the search to
     * risk flags linked through
     * shopping_mall_account_risk_flags_of_sellers.
     */
    sellerId: string & tags.Format<"uuid">;

    /**
     * Search criteria, filters, and pagination options for querying
     * seller-related risk flags.
     */
    body: IShoppingMallAccountRiskFlag.IRequest;
  };
  export type Body = IShoppingMallAccountRiskFlag.IRequest;
  export type Response = IPageIShoppingMallAccountRiskFlag.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/sellers/:sellerId/accountRiskFlags",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/admin/sellers/${encodeURIComponent(props.sellerId ?? "null")}/accountRiskFlags`;
  export const random = (): IPageIShoppingMallAccountRiskFlag.ISummary =>
    typia.random<IPageIShoppingMallAccountRiskFlag.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sellerId")(() => typia.assert(props.sellerId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
