/**
 * Retrieve the saved customer contact snapshot for a given order identified by
 * its business `orderCode`.
 *
 * This operation focuses on the `shopping_mall_order_customer_contacts` Prisma
 * model, which is a subsidiary snapshot table linked to the primary
 * `shopping_mall_orders` entity. When a customer completes checkout, the
 * platform typically records fields such as the recipient's full name, primary
 * phone number, optional secondary phone number, and contact email address into
 * this snapshot table. The business rationale is that contact details at the
 * time of order creation must remain immutable for audit and traceability, even
 * if the customer later edits their profile information or contact
 * preferences.
 *
 * From a security and authorization standpoint, the endpoint is restricted to
 * authenticated customer actors, represented here with the `customer` role. The
 * provider logic must additionally ensure that the requesting customer is
 * allowed to view this particular order's data by verifying that they are the
 * owner of the order, or by granting access to privileged roles acting on
 * behalf of the customer (such as customer support operating under an `admin`
 * context in separate back-office tools). Because the endpoint is read-only and
 * does not alter any data, it does not accept a request body, and all necessary
 * context is provided by the path parameter `orderCode`.
 *
 * This API is typically used in conjunction with other order detail endpoints.
 * For example, a client application may first load general order information
 * (items, totals, and status) from an order detail endpoint, then call this
 * `/orders/{orderCode}/customerContact` endpoint to retrieve the associated
 * contact snapshot for display in a "Order Detail" or "Delivery Information"
 * section. In case of disputes or delivery issues, support tools can rely on
 * this endpoint to display the exact contact data that were used when the order
 * was placed, which can differ from the customer's current profile and thus are
 * critical for reconstruction of historical events.
 *
 * @param props.connection
 * @param props.orderCode Unique business identifier code of the target order
 *   (global scope) used to locate the associated customer contact snapshot in
 *   `shopping_mall_order_customer_contacts`. This code maps to a single
 *   `shopping_mall_orders` record.
 * @path /shoppingMall/customer/orders/:orderCode/customerContact
 * @accessor api.functional.shoppingMall.customer.orders.customerContact.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
