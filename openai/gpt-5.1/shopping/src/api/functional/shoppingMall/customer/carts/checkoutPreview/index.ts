import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCartCheckoutPreview } from "../../../../../structures/IShoppingMallCartCheckoutPreview";

/**
 * Generate a detailed checkout preview for a specific cart, composing pricing
 * and eligibility information from shopping_mall_carts,
 * shopping_mall_cart_items, and related payment, shipping, and policy
 * configuration tables.
 *
 * This operation accepts a path parameter cartId identifying the cart to
 * preview and a structured request body
 * IShoppingMallCartCheckoutPreview.IRequest that carries customer-selected
 * options relevant to checkout. Typical inputs include the chosen shipping
 * method, candidate payment method, optional coupon or promotion codes, and
 * contextual information like delivery region or desired delivery window when
 * not already fixed on the cart. The endpoint does not mutate the cart or
 * create an order; instead, it uses the provided inputs along with current
 * catalog and configuration data to calculate a comprehensive price and
 * eligibility preview.
 *
 * Internally, the implementation reads the cart header and items from
 * shopping_mall_carts and shopping_mall_cart_items, then joins these with SKU
 * and product data, shopping_mall_regions and
 * shopping_mall_region_shipping_policies for shipping eligibility and cost
 * rules, shopping_mall_payment_methods and
 * shopping_mall_payment_method_surcharges for payment-related fees, and any
 * business policy configurations that affect discounts or eligibility. It may
 * populate or update snapshot tables like shopping_mall_order_price_snapshots
 * for traceability, but these are system-generated and remain hidden from the
 * public API.
 *
 * The response object IShoppingMallCartCheckoutPreview contains a per-line item
 * breakdown showing base price, discount allocations, tax components, and
 * shipping share if applicable, as well as order-level totals such as subtotal,
 * total discounts, tax total, shipping total, payment surcharges, and final
 * payable amount. It also indicates whether checkout is currently allowed and
 * may carry explanatory messages if certain items or options are not eligible
 * under the current rules. Customers generally invoke this endpoint after
 * successfully validating the cart via POST /carts/{cartId}/validate and prior
 * to triggering downstream payment authorization or order creation flows.
 *
 * From an authorization standpoint, the endpoint is restricted to authenticated
 * customer actors and uses the relationships encoded in shopping_mall_carts to
 * ensure that only the owner or appropriately linked actor can generate a
 * checkout preview. Error handling should distinguish between transport-level
 * errors such as missing or unauthorized carts, and business-level issues such
 * as an invalid coupon code; the latter should be reflected in the preview
 * structure rather than by failing the HTTP call outright.
 *
 * @param props.connection
 * @param props.cartId Unique identifier of the target cart in the
 *   shopping_mall_carts table for which a checkout preview should be
 *   generated.
 * @param props.body Checkout context and options used to compute a preview for
 *   the specified cart, including shipping, payment, and promotion selections
 *   that influence the price breakdown.
 * @path /shoppingMall/customer/carts/:cartId/checkoutPreview
 * @accessor api.functional.shoppingMall.customer.carts.checkoutPreview.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target cart in the shopping_mall_carts table
     * for which a checkout preview should be generated.
     */
    cartId: string & tags.Format<"uuid">;

    /**
     * Checkout context and options used to compute a preview for the
     * specified cart, including shipping, payment, and promotion selections
     * that influence the price breakdown.
     */
    body: IShoppingMallCartCheckoutPreview.IRequest;
  };
  export type Body = IShoppingMallCartCheckoutPreview.IRequest;
  export type Response = IShoppingMallCartCheckoutPreview;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/customer/carts/:cartId/checkoutPreview",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/customer/carts/${encodeURIComponent(props.cartId ?? "null")}/checkoutPreview`;
  export const random = (): IShoppingMallCartCheckoutPreview =>
    typia.random<IShoppingMallCartCheckoutPreview>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("cartId")(() => typia.assert(props.cartId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
