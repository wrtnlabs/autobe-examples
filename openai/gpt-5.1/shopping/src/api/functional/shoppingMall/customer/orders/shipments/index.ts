import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallShipment } from "../../../../../structures/IShoppingMallShipment";
import { IPageIShoppingMallShipment } from "../../../../../structures/IPageIShoppingMallShipment";

/**
 * Retrieve a filtered, paginated list of shipments belonging to a specific
 * customer order from the `shopping_mall_shipments` table.
 *
 * This operation is centered on the shipment header model
 * `shopping_mall_shipments`, but it is always scoped by a parent order
 * identified through the `orderCode` path parameter, which corresponds to the
 * business-facing code of a row in the `shopping_mall_orders` table. Once the
 * order is resolved, the implementation verifies that the authenticated
 * customer owns this order and then queries the shipments that reference the
 * order, applying the filter, sort, and pagination criteria provided in the
 * `IShoppingMallShipment.IRequest` request body. Typical filter dimensions
 * include shipment status, shipping method, time windows, and possibly flags
 * for partial or complete shipments.
 *
 * The response is a page of shipment summary objects represented by
 * `IPageIShoppingMallShipment.ISummary`. Each summary focuses on information
 * that is useful in customer list or detail views, such as shipment code,
 * current status, shipping method, key timestamps, and limited tracking
 * information. By returning summaries rather than full detail graphs, the API
 * ensures that customer order detail screens can efficiently render shipment
 * lists while still allowing future detail endpoints to provide deeper
 * information on a single shipment when needed.
 *
 * Authorization and visibility rules ensure that only a customer who owns the
 * underlying order can see its shipments through this path. These rules should
 * be enforced using the relationships defined between
 * `shopping_mall_customers`, `shopping_mall_orders`, and
 * `shopping_mall_shipments` within Prisma.
 *
 * Error handling should differentiate between cases where the `orderCode` does
 * not correspond to any order owned by the customer, in which case an
 * appropriate not-found or authorization error should be returned, and cases
 * where the order exists but no shipments have been created yet, in which case
 * the operation should return an empty page of shipment summaries. The
 * operation must not modify any database records and should be optimized for
 * query performance, as it may be called frequently by customer-facing order
 * detail pages.
 *
 * @param props.connection
 * @param props.orderCode Unique business identifier code of the target order
 *   (global scope). This code corresponds to the order-level business
 *   identifier in the `shopping_mall_orders` table and is globally unique
 *   across all orders.
 * @param props.body Search, filter, and pagination criteria for listing
 *   shipments of the specified customer order, including status filters, date
 *   ranges, and sort options.
 * @path /shoppingMall/customer/orders/:orderCode/shipments
 * @accessor api.functional.shoppingMall.customer.orders.shipments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique business identifier code of the target order (global scope).
     * This code corresponds to the order-level business identifier in the
     * `shopping_mall_orders` table and is globally unique across all
     * orders.
     */
    orderCode: string;

    /**
     * Search, filter, and pagination criteria for listing shipments of the
     * specified customer order, including status filters, date ranges, and
     * sort options.
     */
    body: IShoppingMallShipment.IRequest;
  };
  export type Body = IShoppingMallShipment.IRequest;
  export type Response = IPageIShoppingMallShipment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/customer/orders/:orderCode/shipments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/customer/orders/${encodeURIComponent(props.orderCode ?? "null")}/shipments`;
  export const random = (): IPageIShoppingMallShipment.ISummary =>
    typia.random<IPageIShoppingMallShipment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderCode")(() => typia.assert(props.orderCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
