/**
 * Retrieve tracking details and event timeline for a shipment from the
 * shopping_mall_shipments table using its shipmentCode.
 *
 * Retrieve the full tracking view for a single shipment identified by its
 * business-level shipment code.
 *
 * This operation focuses on read-only exposure of data in the
 * `shopping_mall_shipments` Prisma model, which represents shipment headers
 * created from confirmed orders, along with related subsidiary entities such as
 * `shopping_mall_shipment_items` and `shopping_mall_shipment_events`. The
 * shipment header typically includes fields describing the shipment status,
 * shipment type, carrier or shipping method, and key timing information (such
 * as shippedAt and deliveredAt timestamps) as defined in the schema comments.
 * The related `shopping_mall_shipment_events` model captures the detailed
 * shipping and tracking timeline, storing each event with timestamp, event
 * type, and descriptive message according to its own schema documentation.
 *
 * From a security and authorization perspective, this endpoint is intended for
 * authenticated customers tracking their orders. The `authorizationActor` field
 * is therefore set to `"customer"`, and actual implementation must ensure that
 * only the customer who owns the underlying order can view the tracking details
 * for a given shipment code. The shipment code is treated as a secret enough
 * identifier that should not be enumerable; however, access control must still
 * validate the relationship between the requesting principal and the shipment
 * record in `shopping_mall_shipments`.
 *
 * On the database level, the operation first resolves the shipment by
 * `shipmentCode` from the `shopping_mall_shipments` table. It then fetches
 * shipping method details from `shopping_mall_shipping_methods`, the snapshot
 * address from `shopping_mall_shipping_addresses`, and tracking timeline events
 * from `shopping_mall_shipment_events`, ordered chronologically. All these
 * pieces are projected into the `IShoppingMallShipmentTracking` DTO, which is
 * purpose-built to reflect the comments and structure of the shipment-related
 * Prisma schemas while remaining a stable API contract.
 *
 * Typical validation rules include verifying that the shipment exists, has not
 * been fully purged from the system, and that the code belongs to the correct
 * marketplace context. If the shipment cannot be found or is not accessible to
 * the caller, the operation should return an appropriate error such as 404 or
 * 403. This operation is purely read-only and does not modify any state in
 * `shopping_mall_shipments` or its subsidiary models. It is often used together
 * with order detail APIs that retrieve `shopping_mall_orders`, allowing clients
 * to navigate from an order to its shipments and then to shipment tracking.
 *
 * Error handling should gracefully distinguish between an unknown shipment
 * code, a forbidden access attempt, and temporary backend failures when
 * contacting external carriers if the system enriches the
 * `shopping_mall_shipment_events` table using carrier webhooks or polling jobs.
 * The description comments in the Prisma models for shipments and shipment
 * events should be mirrored in the response DTO fields, for example clearly
 * indicating the meaning of each status code and event type to ensure that
 * frontends can render a consistent tracking experience across carriers.
 *
 * @param props.connection
 * @param props.shipmentCode Unique business identifier code of the target
 *   shipment (global scope). This code maps to a single shipment record in the
 *   shopping_mall_shipments table and is the value typically shown to customers
 *   and sellers for tracking purposes.
 * @path /shoppingMall/customer/shipments/:shipmentCode/tracking
 * @accessor api.functional.shoppingMall.customer.shipments.tracking.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique business identifier code of the target shipment (global
     * scope). This code maps to a single shipment record in the
     * shopping_mall_shipments table and is the value typically shown to
     * customers and sellers for tracking purposes.
     */
    shipmentCode: string;
  };
  export type Response = IShoppingMallShipmentTracking;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/shipments/:shipmentCode/tracking",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/shipments/${encodeURIComponent(props.shipmentCode ?? "null")}/tracking`;
  export const random = (): IShoppingMallShipmentTracking =>
    typia.random<IShoppingMallShipmentTracking>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shipmentCode")(() => typia.assert(props.shipmentCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
