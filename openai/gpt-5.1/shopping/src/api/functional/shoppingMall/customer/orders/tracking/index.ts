import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallOrderTracking } from "../../../../../structures/IShoppingMallOrderTracking";

/**
 * Retrieve the shipping and delivery tracking information for a specific order,
 * identified by its business order code, focusing on shipment and
 * carrier-related events.
 *
 * This operation is backed primarily by the `shopping_mall_shipments` and
 * `shopping_mall_shipment_events` Prisma models, which store shipment headers
 * and detailed tracking events respectively. It may also join data from
 * `shopping_mall_orders` to validate that the order exists and belongs to the
 * requesting customer, from `shopping_mall_shipping_addresses` to expose the
 * destination address snapshot, and from `shopping_mall_shipping_methods` to
 * determine the shipping carrier, service level, and promised delivery windows.
 * The operation provides a normalized `IShoppingMallOrderTracking` structure so
 * that clients do not need to query these tables individually.
 *
 * From a security and authorization standpoint, this endpoint is intended for
 * authenticated customers tracking their own orders. The `authorizationActor`
 * is set to `customer`, and the implementation must verify that the order
 * related to `{orderCode}` is owned by the authenticated customer before
 * returning tracking details.
 *
 * If the provided `{orderCode}` cannot be resolved to an order, or if the order
 * has no associated shipments yet, the implementation should handle these cases
 * gracefully—typically returning a 404 for non-existent or inaccessible orders,
 * or an empty shipment list with explanatory status when the order has not
 * progressed to fulfillment. Related operations include the full order timeline
 * at `GET /shoppingMall/customer/orders/{orderCode}/timeline`, which
 * encompasses financial and dispute events in addition to the logistics-focused
 * view returned here.
 *
 * @param props.connection
 * @param props.orderCode Unique business identifier code of the target order
 *   (global scope), corresponding to the `code` field with a unique constraint
 *   in the `shopping_mall_orders` Prisma table.
 * @path /shoppingMall/customer/orders/:orderCode/tracking
 * @accessor api.functional.shoppingMall.customer.orders.tracking.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique business identifier code of the target order (global scope),
     * corresponding to the `code` field with a unique constraint in the
     * `shopping_mall_orders` Prisma table.
     */
    orderCode: string;
  };
  export type Response = IShoppingMallOrderTracking;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/orders/:orderCode/tracking",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/orders/${encodeURIComponent(props.orderCode ?? "null")}/tracking`;
  export const random = (): IShoppingMallOrderTracking =>
    typia.random<IShoppingMallOrderTracking>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderCode")(() => typia.assert(props.orderCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
