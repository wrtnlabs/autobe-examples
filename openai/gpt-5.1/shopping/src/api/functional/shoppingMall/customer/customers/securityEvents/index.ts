/**
 * Search security events in shopping_mall_security_events for a specific
 * customer.
 *
 * Retrieve security-related events for a specific customer in the shopping mall
 * platform.
 *
 * This operation queries the shopping_mall_security_events table to return a
 * paginated list of events associated with the customer identified by the
 * customerId path parameter. Each security event row captures one
 * security-relevant action such as LOGIN_SUCCESS, LOGIN_FAILURE,
 * PASSWORD_RESET_REQUEST, or TOKEN_REVOKED, as described by the event_type
 * field in the Prisma schema. It also stores contextual attributes like
 * actor_type, actor_identifier, ip, user_agent, metadata, and created_at to
 * support risk analysis and forensics.
 *
 * The shopping_mall_security_events model may optionally reference
 * shopping_mall_auth_credentials via the shopping_mall_auth_credentials_id
 * foreign key when the underlying identity is known. For customer-focused
 * queries, the implementation resolves the mapping from the given customerId to
 * its authentication credentials and filters events accordingly. When direct
 * credential linkage is not available, events can still be associated via
 * actor_type and actor_identifier, where actor_type typically takes values such
 * as customer, seller, platformAdmin, or guestUser.
 *
 * The request body uses the IShoppingMallSecurityEvent.IRequest DTO to express
 * search constraints. Clients can specify pagination parameters (page size and
 * page index or cursor), date range filters on created_at, one or more
 * event_type categories, actor_type filters, and optional metadata search
 * criteria leveraging the indexed metadata field. This keeps query complexity
 * in the body while the method remains a PATCH for complex read operations.
 *
 * Only authorized customer actors should be allowed to access this endpoint for
 * their own security events, or privileged platformAdmin actors in tightly
 * controlled back-office tools. The authorizationActors array is therefore set
 * to ["customer"], with the understanding that business logic will additionally
 * enforce that the authenticated customer can only see security events tied to
 * their own identity. Platform administrator tooling that needs cross-customer
 * views would typically use separate, more generic endpoints.
 *
 * Related operations may include generic security event searches across all
 * actors or similar per-seller and per-admin views. This particular endpoint
 * focuses on the customer dimension, using shopping_mall_customer.id to scope
 * which subset of the shopping_mall_security_events data set is visible. Error
 * handling must clearly indicate when the customerId does not resolve to an
 * existing customer or when the caller lacks required permissions.
 *
 * @param props.connection
 * @param props.customerId Unique identifier of the target customer whose
 *   security events are being queried.
 * @param props.body Search filters and pagination parameters for retrieving
 *   security events associated with the specified customer.
 * @path /shoppingMall/customer/customers/:customerId/securityEvents
 * @accessor api.functional.shoppingMall.customer.customers.securityEvents.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
