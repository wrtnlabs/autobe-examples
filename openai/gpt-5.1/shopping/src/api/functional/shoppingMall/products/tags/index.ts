/**
 * List product tags linked to a specific product using
 * shopping_mall_product_tags and shopping_mall_product_tag_links.
 *
 * Retrieve the list of tags currently associated with a specific product,
 * leveraging the shopping_mall_product_tags and shopping_mall_product_tag_links
 * Prisma models.
 *
 * This operation is exposed as PATCH /products/{productId}/tags to align with
 * the platform’s convention that PATCH methods are used for list retrievals
 * with potential complex query capabilities. The core behavior is to query the
 * shopping_mall_product_tag_links junction table for all associations that
 * reference the product identified by productId, then join those associations
 * to the corresponding tag records in the shopping_mall_product_tags master
 * catalog. The result set is returned as a paginated collection of
 * IShoppingMallProductTag.ISummary objects, each representing a concise view of
 * a tag linked to the given product.
 *
 * From a domain perspective, shopping_mall_products represents the core product
 * catalog entity that sellers manage and customers browse. The ability to see
 * which tags are attached to a particular product is essential for both
 * customers—who may use tags for discovery, browsing, and understanding product
 * attributes—and sellers, who need to verify that their products are
 * categorized and discoverable as intended. Because
 * shopping_mall_product_tag_links is explicitly described as a junction table
 * representing associations between products and tags, the operation’s query is
 * centered on these relationships, ensuring that the set of returned tags
 * accurately reflects current link state.
 *
 * This endpoint is intended primarily for read-only consumption. Other
 * endpoints—such as those for assigning or removing tags from products—would
 * also operate on shopping_mall_product_tag_links but with POST/PUT/DELETE
 * semantics. When implementing this read operation, care should be taken to
 * respect any catalog visibility and governance rules defined across tables
 * like shopping_mall_catalog_visibility_rules,
 * shopping_mall_catalog_block_reasons, shopping_mall_product_rating_aggregates,
 * and risk-related models. For example, tags that have been blocked from
 * customer view or that are associated with blocked products should not be
 * exposed to unauthorized actors.
 *
 * Error handling should distinguish between a non-existent productId, which
 * should yield a 404 Not Found, and a valid product that simply has no tags,
 * which should result in an empty list within the paginated response structure.
 * Implementations may also choose to return validation errors when an invalid
 * identifier format is supplied for productId, depending on how product keys
 * are defined in the shopping_mall_products schema. This endpoint can be safely
 * treated as a public or broadly accessible read API for visible products,
 * while still applying stricter authorization checks for internal or
 * pre-release catalog items in the service layer.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the product in the
 *   shopping_mall_products table whose associated tags should be retrieved.
 * @path /shoppingMall/products/:productId/tags
 * @accessor api.functional.shoppingMall.products.tags.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
