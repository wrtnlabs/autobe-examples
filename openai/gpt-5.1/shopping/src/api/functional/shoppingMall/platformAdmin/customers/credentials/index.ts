import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCustomerCredential } from "../../../../../structures/IShoppingMallCustomerCredential";

/**
 * Get the administrative credential view for a customer from
 * shopping_mall_auth_credentials_of_customers.
 *
 * Retrieve the authentication credential linkage and administrative view for a
 * specific customer identified by customerId.
 *
 * This endpoint targets the shopping_mall_auth_credentials_of_customers Prisma
 * model, which is described as a subtype entity connecting authentication
 * credentials to customer actors. It exists alongside the
 * shopping_mall_auth_credentials primary model, which holds core credential
 * attributes, and the shopping_mall_customer model, which represents buyer
 * accounts on the shoppingMall platform. When this API is invoked, the service
 * layer must locate the customer by the provided customerId, then traverse the
 * relationship to the corresponding auth_credentials_of_customers row and the
 * underlying auth_credentials record. The result is projected into an
 * IShoppingMallCustomerCredential DTO that summarizes the credential state for
 * administrative use.
 *
 * Typical fields exposed by this DTO are those documented in the Prisma schema
 * comments for the credential and linkage tables: credential identifiers, login
 * handle (e.g., email or username, as modeled), credential type
 * (password-based, social login, etc.), flags related to account lockout, MFA
 * enrollment status, and risk indicators that are safe to reveal to platform
 * admins. Sensitive implementation details such as password hashes or raw auth
 * tokens must never be included in this response, even though they might be
 * present in the underlying tables. The description comments on the Prisma
 * models should be treated as the authoritative guide for what is considered
 * safe and intended to be exposed.
 *
 * Access to this endpoint is restricted to platform administrators because it
 * reveals internal security posture and credential configuration for customer
 * accounts. Normal customers and sellers must not be able to call this endpoint
 * either for themselves or for others. The authorization layer must therefore
 * ensure that the caller has a platformAdmin role before allowing the operation
 * to proceed. If there is no credential linkage record for the specified
 * customer, or if the customerId does not match any row in
 * shopping_mall_customer, the service should respond with 404 Not Found rather
 * than leaking information about the non-existence of credentials. This GET
 * endpoint is purely for read operations; any updates to credentials, including
 * password resets or MFA changes, are handled by the separate authentication
 * subsystem and must not be implemented here.
 *
 * @param props.connection
 * @param props.customerId Unique identifier of the target customer account in
 *   the shopping_mall_customer table whose credential linkage and state should
 *   be retrieved.
 * @path /shoppingMall/platformAdmin/customers/:customerId/credentials
 * @accessor api.functional.shoppingMall.platformAdmin.customers.credentials.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target customer account in the
     * shopping_mall_customer table whose credential linkage and state
     * should be retrieved.
     */
    customerId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallCustomerCredential;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/platformAdmin/customers/:customerId/credentials",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/platformAdmin/customers/${encodeURIComponent(props.customerId ?? "null")}/credentials`;
  export const random = (): IShoppingMallCustomerCredential =>
    typia.random<IShoppingMallCustomerCredential>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("customerId")(() => typia.assert(props.customerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
