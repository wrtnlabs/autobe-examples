/**
 * Search paginated authentication history logs in shopping_mall_auth_logs for a
 * specific seller.
 *
 * Retrieve a paginated, filterable list of authentication history records for a
 * specific seller, focusing on entries stored in the shopping_mall_auth_logs
 * Prisma model.
 *
 * This endpoint is intended primarily for administrative and security use
 * cases, such as reviewing suspicious activity, investigating support cases, or
 * complying with internal audit policies. It fetches records from the
 * shopping_mall_auth_logs table that are associated with the seller identified
 * by the sellerId path parameter, typically via foreign keys or correlation
 * fields that link log entries to the underlying shopping_mall_seller and
 * shopping_mall_auth_credentials_of_sellers entities. Only summary-level fields
 * that are useful for timeline views, such as event type, timestamp, IP, user
 * agent, session identifier, and status, are returned via the
 * IShoppingMallAuthLog.ISummary structure to ensure that responses remain
 * performant even when histories are long.
 *
 * Security-wise, this operation must be restricted to privileged actors,
 * because authentication logs often include sensitive metadata such as
 * originating IP addresses, device fingerprints, or partial token identifiers.
 * The authorizationActors array therefore includes only "platformAdmin",
 * representing platform administrator accounts modeled in the
 * shopping_mall_platformadmin table. Business logic is responsible for
 * enforcing that admins can only access histories for sellers they are
 * permitted to manage, and that no seller or customer can access another
 * actor's auth logs directly.
 *
 * From a business and compliance perspective, the endpoint supports rich
 * filtering and paging, encapsulated by the IShoppingMallAuthLog.IRequest DTO.
 * Clients can submit time windows, event-type lists, search keywords, or risk
 * flags, which are translated into WHERE conditions against
 * shopping_mall_auth_logs and related tables like shopping_mall_security_events
 * or shopping_mall_risk_flags when those relationships exist. The resulting
 * paginated structure IPageIShoppingMallAuthLog.ISummary includes page size,
 * current page, total count, and an array of summarized auth log records. This
 * operation is typically used alongside other security and audit endpoints,
 * such as admin action audits or access logs, to provide a full picture of
 * account- and session-related behavior.
 *
 * @param props.connection
 * @param props.sellerId Unique identifier of the target seller whose
 *   authentication history is being queried. This corresponds to the primary
 *   key of the seller entity in the shopping_mall_seller Prisma model and is
 *   used to filter authentication log records in shopping_mall_auth_logs that
 *   are associated with this seller via credentials or sessions.
 * @param props.body Search criteria, filters, and pagination options for
 *   retrieving seller authentication history records from
 *   shopping_mall_auth_logs.
 * @path /shoppingMall/platformAdmin/sellers/:sellerId/authHistory
 * @accessor api.functional.shoppingMall.platformAdmin.sellers.authHistory.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target seller whose authentication history
     * is being queried. This corresponds to the primary key of the seller
     * entity in the shopping_mall_seller Prisma model and is used to filter
     * authentication log records in shopping_mall_auth_logs that are
     * associated with this seller via credentials or sessions.
     */
    sellerId: string;

    /**
     * Search criteria, filters, and pagination options for retrieving
     * seller authentication history records from shopping_mall_auth_logs.
     */
    body: IShoppingMallAuthLog.IRequest;
  };
  export type Body = IShoppingMallAuthLog.IRequest;
  export type Response = IPageIShoppingMallAuthLog.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/platformAdmin/sellers/:sellerId/authHistory",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/platformAdmin/sellers/${encodeURIComponent(props.sellerId ?? "null")}/authHistory`;
  export const random = (): IPageIShoppingMallAuthLog.ISummary =>
    typia.random<IPageIShoppingMallAuthLog.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sellerId")(() => typia.assert(props.sellerId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
