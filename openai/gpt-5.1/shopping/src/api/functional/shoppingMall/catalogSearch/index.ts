import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCatalogSearchIndexEntry } from "../../../structures/IShoppingMallCatalogSearchIndexEntry";
import { IPageIShoppingMallCatalogSearchIndexEntry } from "../../../structures/IPageIShoppingMallCatalogSearchIndexEntry";

/**
 * Execute an advanced catalog search over products and SKUs using the
 * denormalized search index maintained in the
 * shopping_mall_catalog_search_index_entries table.
 *
 * This operation is designed as the primary search entry point for the
 * shoppingMall storefront. Clients send a rich search request encapsulated by
 * IShoppingMallCatalogSearch.IRequest that includes a query string for
 * full-text search along with structured filters such as selected category
 * identifiers, tag identifiers, price bands, inventory state requirements, and
 * attribute-value selections. The server translates these search criteria into
 * queries against the underlying search index and related catalog entities
 * while respecting catalog visibility rules and business policies.
 *
 * The endpoint is public in the sense that it does not require authentication
 * at the transport layer, as indicated by an empty authorizationActors array.
 * However, the server implementation should still consider contextual
 * information such as inferred region, locale, or optional authenticated user
 * identity to enforce catalog visibility policies, exclude blocked products
 * based on shopping_mall_catalog_visibility_rules and
 * shopping_mall_catalog_block_reasons, and adjust results for geo-specific
 * availability when necessary.
 *
 * From a data modeling perspective, the search results are not direct
 * projections of the raw shopping_mall_catalog_search_index_entries rows.
 * Instead, the IShoppingMallCatalogSearch.ISummary items in the
 * IPageIShoppingMallCatalogSearch.ISummary response are higher-level view
 * models that combine information from products, SKUs, category taxonomy, and
 * rating aggregates. The summary DTO should expose fields needed to render grid
 * or list views, such as primary product name, main image URL derived from
 * product image data, effective sale price and optional original price, a
 * condensed category breadcrumb, rating summary backed by
 * shopping_mall_product_rating_aggregates or
 * shopping_mall_sku_rating_aggregates, and flags indicating add-to-cart
 * eligibility.
 *
 * The operation supports pagination by requiring page index and page size
 * inputs and returning total count and page metadata in the
 * IPageIShoppingMallCatalogSearch.ISummary container. It should also validate
 * request constraints such as maximum page size, maximum length of search query
 * text, and legal combinations of filters. Errors for invalid filter
 * combinations or malformed input should be surfaced using the platform’s
 * standard error envelope rather than custom shapes in this operation.
 *
 * This search endpoint is expected to be called frequently and should be
 * optimized for performance and responsiveness. Implementations may leverage
 * database indexes, external search engines, or caching strategies, but these
 * details do not change the contract: clients always send
 * IShoppingMallCatalogSearch.IRequest and receive
 * IPageIShoppingMallCatalogSearch.ISummary as the canonical interface.
 *
 * @param props.connection
 * @param props.body Complex catalog search criteria including full-text query,
 *   filters, sorting, and pagination settings.
 * @path /shoppingMall/catalogSearch
 * @accessor api.functional.shoppingMall.catalogSearch.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Complex catalog search criteria including full-text query, filters,
     * sorting, and pagination settings.
     */
    body: IShoppingMallCatalogSearchIndexEntry.IRequest;
  };
  export type Body = IShoppingMallCatalogSearchIndexEntry.IRequest;
  export type Response = IPageIShoppingMallCatalogSearchIndexEntry.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/catalogSearch",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/catalogSearch";
  export const random =
    (): IPageIShoppingMallCatalogSearchIndexEntry.ISummary =>
      typia.random<IPageIShoppingMallCatalogSearchIndexEntry.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
