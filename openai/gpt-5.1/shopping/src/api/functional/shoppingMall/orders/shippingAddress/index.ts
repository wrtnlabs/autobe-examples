import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallShippingAddress } from "../../../../structures/IShoppingMallShippingAddress";

/**
 * Get the immutable shipping address snapshot for a given order identified by
 * its business orderCode.
 *
 * This read-only operation is centered around the
 * shopping_mall_shipping_addresses table, which stores snapshot records of
 * shipping destinations used by orders from the shopping_mall_orders table.
 * Unlike the current, user-editable addresses stored in
 * shopping_mall_customer_addresses, these snapshot rows reflect exactly what
 * was used for a specific checkout, preserving historical accuracy for
 * logistics tracking, dispute resolution, and regulatory audits. When invoked,
 * the operation resolves the provided orderCode to an order and returns the
 * attached shipping address snapshot if one is present.
 *
 * Security and privacy considerations are important because shipping addresses
 * contain personally identifiable information. Although authorizationActors is
 * left empty to allow reuse in different contexts, the underlying
 * implementation should apply authentication and masking rules based on the
 * caller’s role, such as customer, seller, or admin, and should also respect
 * any legal holds recorded in shopping_mall_legal_holds and related target
 * tables. For example, some address fields may be partially redacted for
 * non-privileged viewers while remaining fully visible to authorized admins
 * handling disputes or compliance tasks.
 *
 * This endpoint is typically used alongside other order-detail operations that
 * expose high-level information from shopping_mall_orders, line items from
 * shopping_mall_order_items, and shipment data from shopping_mall_shipments.
 * Error handling must cover cases where the orderCode is unknown, where an
 * order legitimately has no shipping address snapshot (such as purely digital
 * deliveries, if supported by the model), or where access is denied due to
 * business policies. The response should use a DTO type that faithfully mirrors
 * the snapshot structure and omits unrelated fields to keep the contract clear
 * and focused on the shipping address context.
 *
 * @param props.connection
 * @param props.orderCode Unique business identifier code of the target order
 *   (global scope). This code maps to a row in shopping_mall_orders whose
 *   associated shipping address snapshot in shopping_mall_shipping_addresses
 *   will be returned.
 * @path /shoppingMall/orders/:orderCode/shippingAddress
 * @accessor api.functional.shoppingMall.orders.shippingAddress.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique business identifier code of the target order (global scope).
     * This code maps to a row in shopping_mall_orders whose associated
     * shipping address snapshot in shopping_mall_shipping_addresses will be
     * returned.
     */
    orderCode: string;
  };
  export type Response = IShoppingMallShippingAddress;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/orders/:orderCode/shippingAddress",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/orders/${encodeURIComponent(props.orderCode ?? "null")}/shippingAddress`;
  export const random = (): IShoppingMallShippingAddress =>
    typia.random<IShoppingMallShippingAddress>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderCode")(() => typia.assert(props.orderCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
