import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCartSummary } from "../../../../structures/IShoppingMallCartSummary";

/**
 * Compute and retrieve a summarized view of the current cart using
 * shopping_mall_guest_carts and shopping_mall_customer_carts.
 *
 * Retrieve a computed summary of the current shopping cart for the active
 * shopper, aggregating line items and pricing information into a denormalized
 * response structure.
 *
 * This operation conceptually reads from the `shopping_mall_guest_carts` and
 * `shopping_mall_guest_cart_items` tables for unauthenticated visitors, or from
 * `shopping_mall_customer_carts` and `shopping_mall_customer_cart_items` for
 * authenticated customers. Each cart item references a specific SKU from the
 * `shopping_mall_product_skus` model, which in turn is linked to a base product
 * record in `shopping_mall_products`. By joining these entities, the system can
 * present human-readable product names, option selections, and per-SKU pricing
 * while still reflecting the cart's true transactional state.
 *
 * From a security perspective, this endpoint is available to any shopping
 * context and should be guarded so that the implementation binds the effective
 * cart (guest or customer) to the caller's session or identity. In this
 * specification, `authorizationActors` is intentionally left empty (`[]`),
 * indicating that authentication and actor typing are handled by the broader
 * platform, while the business logic still enforces that only the owner of a
 * cart can see its summary. The implementation MUST derive the cart identity
 * exclusively from the authenticated session or a secure guest token and MUST
 * NOT accept arbitrary cart identifiers in the request body or query
 * parameters.
 *
 * The request body `IShoppingMallCartSummary.IRequest` allows clients to
 * provide contextual parameters that affect how the summary is computed or
 * presented, such as preferred currency, region code for shipping estimates, or
 * flags that toggle inclusion of certain computed sections (e.g., whether to
 * include promotion breakdowns). The response `IShoppingMallCartSummary`
 * returns the consolidated view for display in cart and checkout UI flows, and
 * is expected to be used together with cart mutation APIs (add/update/remove
 * items) and checkout initiation APIs that actually create orders based on the
 * cart state.
 *
 * Error handling must cover cases where the effective cart does not exist
 * (e.g., an empty cart), referenced SKUs or products have been disabled or are
 * no longer sellable, or configuration-based computations (such as shipping or
 * discount rules) cannot be evaluated. In such cases, the API should still
 * return a structured error response with clear messaging while avoiding
 * exposing internal policy implementation details.
 *
 * @param props.connection
 * @param props.body Contextual parameters for computing the cart summary, such
 *   as region, currency, or inclusion flags for various computed sections.
 * @path /shoppingMall/carts/summary
 * @accessor api.functional.shoppingMall.carts.summary.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Contextual parameters for computing the cart summary, such as region,
     * currency, or inclusion flags for various computed sections.
     */
    body: IShoppingMallCartSummary.IRequest;
  };
  export type Body = IShoppingMallCartSummary.IRequest;
  export type Response = IShoppingMallCartSummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/carts/summary",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/carts/summary";
  export const random = (): IShoppingMallCartSummary =>
    typia.random<IShoppingMallCartSummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
