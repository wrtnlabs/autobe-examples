import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCategory } from "../../../../structures/IShoppingMallCategory";

/**
 * Retrieve all ancestor categories of a given category, ordered from the
 * highest-level root down to the category’s immediate parent, based on the
 * shopping_mall_categories taxonomy.
 *
 * This operation focuses on the shopping_mall_categories Prisma model and the
 * logical tree it defines. The categoryId path parameter identifies the target
 * category. Using either a parent pointer in shopping_mall_categories or a
 * dedicated closure table such as shopping_mall_category_closures, the
 * implementation discovers every ancestor category that leads from the taxonomy
 * root to the specified category. The results are sorted so that the first
 * element is the root category, followed by each intermediate category, ending
 * with the immediate parent of the target.
 *
 * The primary use cases include constructing breadcrumb UI components,
 * generating navigation aids on product listing and detail pages, and enabling
 * admins and sellers to see the full path of a category when managing catalog
 * assignments. Each ancestor is returned as a summary representation backed by
 * fields from shopping_mall_categories, such as display name and any codes or
 * slugs required for building URLs or internal links.
 *
 * From a security perspective, the endpoint is intentionally accessible without
 * authentication because breadcrumb and hierarchy information is typically
 * public. Nevertheless, the implementation will apply business rules that may
 * hide certain categories based on configuration, using columns in
 * shopping_mall_categories or related visibility configuration tables.
 * Ancestors that are blocked or not intended to be visible can be excluded to
 * avoid leaking internal classification structures.
 *
 * Error handling behavior includes returning a not-found error when the
 * specified categoryId does not match any record in shopping_mall_categories
 * that the caller is allowed to see. When a category exists but has no
 * ancestors (for example, it is a root category), the endpoint successfully
 * returns an empty array. Clients commonly invoke this operation alongside
 * category detail retrieval so that both the category’s own data and its
 * hierarchical context can be displayed together.
 *
 * @param props.connection
 * @param props.categoryId Unique identifier of the category in
 *   shopping_mall_categories whose ancestor chain should be retrieved.
 * @path /shoppingMall/categories/:categoryId/ancestors
 * @accessor api.functional.shoppingMall.categories.ancestors.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the category in shopping_mall_categories whose
     * ancestor chain should be retrieved.
     */
    categoryId: string;
  };
  export type Response = IShoppingMallCategory.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/categories/:categoryId/ancestors",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/categories/${encodeURIComponent(props.categoryId ?? "null")}/ancestors`;
  export const random = (): IShoppingMallCategory.ISummary =>
    typia.random<IShoppingMallCategory.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("categoryId")(() => typia.assert(props.categoryId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
