import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCustomerAuth } from "../../../../../structures/IShoppingMallCustomerAuth";
import { IShoppingMallCustomer } from "../../../../../structures/IShoppingMallCustomer";

/**
 * Allow an authenticated customer to change their password by updating
 * shopping_mall_auth_credentials.password_hash after verifying the current
 * password.
 *
 * This endpoint allows an already authenticated customer to change their
 * password by confirming their current credentials and updating the underlying
 * authentication record while preserving a complete audit trail.
 *
 * The handler operates under the customer’s authenticated context, using the
 * identity (such as the credentials ID or email claim) to locate the
 * corresponding shopping_mall_auth_credentials row where actor_type is
 * "customer". It expects a request body that contains the current password and
 * the desired new password. First, it validates the supplied current password
 * by hashing it and comparing it to the stored password_hash value. If the
 * comparison fails, the operation is rejected and a failure entry is written to
 * shopping_mall_auth_logs with event_type such as "password_change_failed",
 * success=false, failure_reason="invalid_current_password", and created_at, and
 * an optional correlated entry is added to shopping_mall_security_events.
 *
 * If the current password is correct, the implementation hashes the new
 * password and updates password_hash in shopping_mall_auth_credentials while
 * also refreshing updated_at to the current timestamp. The credentials status
 * may be inspected to ensure that changes are allowed and to determine whether
 * any additional lifecycle transitions are needed. Because the customer account
 * itself resides in shopping_mall_customer, the operation may also check the
 * customer’s status and deleted_at fields to ensure the account is still
 * active.
 *
 * For observability, the system records a successful password change event in
 * shopping_mall_auth_logs with event_type like "password_change_success",
 * actor_type="customer", actor_id and actor_email populated from the
 * authenticated context or the credentials row, success=true, and created_at.
 * Detailed security context such as ip and user_agent can be captured either in
 * metadata_json in shopping_mall_auth_logs or as separate entries in
 * shopping_mall_security_events with event_type PASSWORD_CHANGED.
 *
 * Finally, depending on platform security policy, the endpoint may rotate JWT
 * tokens to reflect the new credential state and mitigate token theft risk. In
 * such cases it returns an updated IShoppingMallCustomer.IAuthorized payload
 * with fresh tokens and the current customer identity, allowing the client to
 * continue using the session with minimal disruption.
 *
 * @param props.connection
 * @param props.body Authenticated password change payload containing the
 *   current password and the desired new password.
 * @path /auth/customer/password/change
 * @accessor api.functional.auth.customer.password.change.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<changePassword.Response> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /**
     * Authenticated password change payload containing the current password
     * and the desired new password.
     */
    body: IShoppingMallCustomerAuth.IChangePassword;
  };
  export type Body = IShoppingMallCustomerAuth.IChangePassword;
  export type Response = IShoppingMallCustomer.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/customer/password/change",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/customer/password/change";
  export const random = (): IShoppingMallCustomer.IAuthorized =>
    typia.random<IShoppingMallCustomer.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
