import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCustomerAuth } from "../../../../../../structures/IShoppingMallCustomerAuth";

/**
 * Initiate a customer password reset by creating a
 * shopping_mall_password_reset_tokens entry while returning only a generic
 * success acknowledgement.
 *
 * This endpoint initiates a password reset workflow for customer accounts by
 * minting a password reset token in the shopping_mall_password_reset_tokens
 * table and recording audit entries, without revealing whether the target email
 * is registered.
 *
 * The handler receives a payload containing a customer login email. It attempts
 * to find a shopping_mall_auth_credentials record where actor_type equals
 * "customer" and email matches the supplied value. When such a record exists
 * and its status allows password reset (for example, not permanently disabled),
 * the implementation generates a secure, opaque token value and inserts a new
 * record into shopping_mall_password_reset_tokens with fields token,
 * expires_at, consumed_at set to null, created_at, and updated_at, and links it
 * via shopping_mall_auth_credentials_id. If multiple outstanding tokens are
 * allowed, the system may keep older ones or invalidate them according to
 * security policy.
 *
 * Regardless of whether a matching credentials record is found, the endpoint
 * returns a uniform success response in order to avoid leaking whether an email
 * is associated with a customer account. This behavior is especially important
 * given that shopping_mall_auth_credentials.email and
 * shopping_mall_customer.email are both unique identifiers used for login and
 * communication. Instead of exposing the token in the API response, the
 * platform is expected to deliver the token to the user through an email
 * channel.
 *
 * For monitoring and incident response, the operation should create entries in
 * shopping_mall_auth_logs with event_type set to "password_reset_request",
 * actor_type="customer" when the actor can be identified, actor_email equal to
 * the input email, success=true, and created_at. It may also create correlated
 * entries in shopping_mall_security_events, using event_type such as
 * PASSWORD_RESET_REQUEST along with actor_type, actor_identifier, ip,
 * user_agent, and metadata describing rate-limiting decisions or risk scoring
 * results.
 *
 * The endpoint does not authenticate the customer and therefore does not return
 * an IShoppingMallCustomer.IAuthorized payload. Instead, it returns a minimal
 * acknowledgement DTO that simply indicates that the request has been accepted
 * and, if appropriate, that a reset email has been sent.
 *
 * @param props.connection
 * @param props.body Password reset request payload containing the customer’s
 *   login email address.
 * @path /auth/customer/password/reset/request
 * @accessor api.functional.auth.customer.password.reset.request.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<requestPasswordReset.Response> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestPasswordReset {
  export type Props = {
    /**
     * Password reset request payload containing the customer’s login email
     * address.
     */
    body: IShoppingMallCustomerAuth.IRequestPasswordReset;
  };
  export type Body = IShoppingMallCustomerAuth.IRequestPasswordReset;
  export type Response = IShoppingMallCustomerAuth.IRequestPasswordResetResult;

  export const METADATA = {
    method: "POST",
    path: "/auth/customer/password/reset/request",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/customer/password/reset/request";
  export const random =
    (): IShoppingMallCustomerAuth.IRequestPasswordResetResult =>
      typia.random<IShoppingMallCustomerAuth.IRequestPasswordResetResult>();
  export const simulate = (
    connection: IConnection,
    props: requestPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
