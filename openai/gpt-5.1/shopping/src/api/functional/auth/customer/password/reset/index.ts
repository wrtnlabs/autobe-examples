import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCustomerAuth } from "../../../../../structures/IShoppingMallCustomerAuth";
import { IShoppingMallCustomer } from "../../../../../structures/IShoppingMallCustomer";
export * as request from "./request/index";

/**
 * Complete a customer password reset by consuming a token from
 * shopping_mall_password_reset_tokens and updating
 * shopping_mall_auth_credentials.password_hash.
 *
 * This endpoint finalizes the customer password reset process by validating a
 * reset token and updating authentication credentials while maintaining strict
 * auditability using the Prisma models dedicated to security.
 *
 * The handler receives a payload containing a reset token and a new password.
 * It starts by querying shopping_mall_password_reset_tokens for a row where
 * token equals the supplied value. If no such row exists, if expires_at is in
 * the past, or if consumed_at is already set, the request is rejected and an
 * appropriate failure event is written to shopping_mall_auth_logs (for example,
 * event_type="password_reset_failed", success=false, failure_reason describing
 * the cause) and optionally to shopping_mall_security_events with event_type
 * such as PASSWORD_RESET_FAILED.
 *
 * When a valid reset token is found, the endpoint follows
 * shopping_mall_auth_credentials_id to the owning
 * shopping_mall_auth_credentials record. It verifies that actor_type equals
 * "customer" and that the status column indicates the credentials are allowed
 * to be modified (for example, not permanently disabled). The new password is
 * then securely hashed and stored into password_hash, and updated_at is set to
 * the current timestamp to reflect the credential update.
 *
 * The shopping_mall_password_reset_tokens record is updated to set consumed_at
 * to the current time and updated_at accordingly, preventing reuse of the
 * token. For logging and forensics, the system records a password_reset_success
 * event in shopping_mall_auth_logs with event_type="password_reset_success",
 * actor_type="customer", actor_email derived from the credentials.email column,
 * success=true, and created_at. Additional context such as IP and user_agent
 * may be stored in both shopping_mall_auth_logs and
 * shopping_mall_security_events to support risk analysis.
 *
 * Depending on platform policy, the operation may optionally authenticate the
 * customer as part of password reset completion. If so, it will load the
 * corresponding shopping_mall_auth_credentials_of_customers and
 * shopping_mall_customer records to build an identity view, possibly create or
 * update a shopping_mall_customer_sessions entry, and issue fresh JWT tokens.
 * Those tokens and the customer identity are then returned in an
 * IShoppingMallCustomer.IAuthorized response, enabling the user to continue
 * without a separate login step.
 *
 * @param props.connection
 * @param props.body Password reset completion payload including the reset token
 *   and the customer’s new password.
 * @path /auth/customer/password/reset
 * @accessor api.functional.auth.customer.password.reset.resetPassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resetPassword(
  connection: IConnection,
  props: resetPassword.Props,
): Promise<resetPassword.Response> {
  return true === connection.simulate
    ? resetPassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resetPassword.METADATA,
          path: resetPassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resetPassword {
  export type Props = {
    /**
     * Password reset completion payload including the reset token and the
     * customer’s new password.
     */
    body: IShoppingMallCustomerAuth.IResetPassword;
  };
  export type Body = IShoppingMallCustomerAuth.IResetPassword;
  export type Response = IShoppingMallCustomer.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/customer/password/reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/customer/password/reset";
  export const random = (): IShoppingMallCustomer.IAuthorized =>
    typia.random<IShoppingMallCustomer.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: resetPassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resetPassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
