import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCustomerAuth } from "../../../../../structures/IShoppingMallCustomerAuth";
import { IShoppingMallCustomer } from "../../../../../structures/IShoppingMallCustomer";

/**
 * Verify a customer’s email using shopping_mall_email_verification_tokens and
 * update shopping_mall_customer.is_verified, optionally returning an authorized
 * session.
 *
 * This endpoint finalizes email verification for a customer by consuming a
 * stored verification token and synchronizing state across multiple
 * authentication-related tables.
 *
 * The handler receives a payload containing a token string that must match the
 * token column in shopping_mall_email_verification_tokens. It queries this
 * table to ensure that the token exists, has not expired based on expires_at,
 * and has not yet been used as indicated by a null consumed_at. If any of these
 * checks fail, the operation rejects the request and may optionally record a
 * corresponding event in shopping_mall_security_events with event_type such as
 * EMAIL_VERIFICATION_FAILED and in shopping_mall_auth_logs with event_type
 * values that denote a failed verification attempt.
 *
 * When a valid verification token is found, the endpoint follows the
 * shopping_mall_auth_credentials_id foreign key to the
 * shopping_mall_auth_credentials record. It checks that actor_type equals
 * "customer" and that status allows the account to be verified (for example,
 * not permanently locked). Using shopping_mall_auth_credentials_of_customers,
 * it resolves the owning shopping_mall_customer row and updates its is_verified
 * field to true while also updating updated_at to the current timestamp. This
 * ensures that the customer’s profile in shopping_mall_customer accurately
 * records that the primary email has been verified.
 *
 * The token record in shopping_mall_email_verification_tokens is then updated
 * to set consumed_at to the current timestamp and updated_at accordingly,
 * preventing reuse of the same token. For observability and forensics, the
 * operation is expected to create one or more records in
 * shopping_mall_security_events with event_type like EMAIL_VERIFICATION_SUCCESS
 * and in shopping_mall_auth_logs capturing event_type (for example,
 * "email_verification"), actor_type="customer", actor_id, actor_email,
 * success=true, and created_at.
 *
 * Depending on platform policy, if the customer is not already authenticated,
 * the endpoint may create or update a shopping_mall_customer_sessions row and
 * issue JWT tokens as part of a smooth onboarding experience. In that case, the
 * response body uses IShoppingMallCustomer.IAuthorized to return access and
 * refresh tokens together with the now-verified customer identity, allowing the
 * client to treat verification completion as an authenticated state
 * transition.
 *
 * @param props.connection
 * @param props.body Email verification payload containing the opaque
 *   verification token issued to the customer.
 * @path /auth/customer/email/verify
 * @accessor api.functional.auth.customer.email.verify.verifyEmail
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function verifyEmail(
  connection: IConnection,
  props: verifyEmail.Props,
): Promise<verifyEmail.Response> {
  return true === connection.simulate
    ? verifyEmail.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verifyEmail.METADATA,
          path: verifyEmail.path(),
          status: null,
        },
        props.body,
      );
}
export namespace verifyEmail {
  export type Props = {
    /**
     * Email verification payload containing the opaque verification token
     * issued to the customer.
     */
    body: IShoppingMallCustomerAuth.IVerifyEmail;
  };
  export type Body = IShoppingMallCustomerAuth.IVerifyEmail;
  export type Response = IShoppingMallCustomer.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/customer/email/verify",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/customer/email/verify";
  export const random = (): IShoppingMallCustomer.IAuthorized =>
    typia.random<IShoppingMallCustomer.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: verifyEmail.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: verifyEmail.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
