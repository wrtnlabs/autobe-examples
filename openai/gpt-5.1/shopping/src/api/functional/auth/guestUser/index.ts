/**
 * Register a new guestUser identity using shopping_mall_guestuser and issue an
 * initial IShoppingMallGuestUser.IAuthorized token payload.
 *
 * This operation registers an unauthenticated visitor as a tracked guest user
 * by creating a new record in the shopping_mall_guestuser table and issuing an
 * initial JWT authorization payload tailored for the guestUser actor.
 *
 * At the persistence layer, the implementation will primarily insert into
 * shopping_mall_guestuser, populating fields such as temporary_identifier for
 * correlating pre-registration activity, user_agent for device analytics, and
 * the mandatory created_at and updated_at timestamps. The deleted_at field is
 * kept null for active guests; if a record is later soft deleted by setting
 * deleted_at, this API must ensure those logically removed identities are not
 * inadvertently reused, protecting historical analytics integrity.
 *
 * Security-wise, the endpoint is publicly accessible (authorizationActor is
 * null) but all requests must be strictly validated. The request body will
 * carry benign context only (no passwords or emails) and is limited to fields
 * that can be safely stored: for example, a temporary_identifier derived from
 * cookies, IP and user_agent strings, and an optional guest cart token from
 * shopping_mall_guest_carts.guest_token to indicate that an existing cart
 * should be associated with the newly created guest. Input validation should
 * enforce reasonable string lengths and ensure that any URI-like referrer
 * values match their documented expectations in shopping_mall_guest_carts.
 *
 * From a relational standpoint, this operation does not write directly into
 * shopping_mall_guest_carts or shopping_mall_guest_cart_items, but the
 * application layer can use the provided guest cart token to look up an
 * existing shopping_mall_guest_carts row (by its unique guest_token index) and
 * link it to the new guestUser via shopping_mall_guestuser.id and
 * shopping_mall_guest_carts.shopping_mall_guestuser_id. This design leverages
 * the optional foreign key shopping_mall_guest_carts.shopping_mall_guestuser_id
 * to gradually transition anonymous carts into identified guest or customer
 * flows.
 *
 * For observability and security analytics, the implementation should insert
 * log entries into shopping_mall_auth_logs and shopping_mall_security_events.
 * In shopping_mall_auth_logs, fields like event_type (for example,
 * "guest_join"), actor_type ("guestUser"), actor_id (the new guestUser.id), ip,
 * user_agent, success, and created_at enable later analysis of funnel behavior
 * and anomaly detection. In shopping_mall_security_events, a complementary
 * record with event_type such as LOGIN_SUCCESS or a guest-specific registration
 * category, actor_type "guestUser", actor_identifier based on the
 * temporary_identifier, and metadata describing the request context helps risk
 * and compliance teams.
 *
 * This endpoint is part of the broader guest lifecycle: after join, callers use
 * the /auth/guestUser/refresh endpoint to renew tokens without re-registering,
 * and platform flows may later upgrade a guestUser into a customer by linking
 * shopping_mall_guestuser to shopping_mall_customer and
 * shopping_mall_auth_credentials_of_customers. Error handling should return
 * validation errors for malformed inputs, and internal errors should be logged
 * but not leak sensitive implementation details.
 *
 * Note that this API intentionally does not touch
 * shopping_mall_auth_credentials or passwords because guestUser actors do not
 * authenticate with credentials; they rely solely on issued guest tokens
 * managed by this join and the refresh operation.
 *
 * @param props.connection
 * @param props.body Guest registration payload carrying optional correlation
 *   identifiers and cart context needed to create a shopping_mall_guestuser
 *   record and optionally associate existing guest carts.
 * @setHeader token.access Authorization
 *
 * @path /auth/guestUser/join
 * @accessor api.functional.auth.guestUser.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
