/**
 * Create a new guest user identity in shopping_mall_guestusers and issue
 * initial JWT tokens for the guestUser actor.
 *
 * This API operation creates a new logical guest user identity in the
 * shoppingMall platform using the shopping_mall_guestusers table and
 * immediately issues initial JWT tokens for subsequent guestUser interactions.
 *
 * From a database perspective, the operation inserts a row into
 * shopping_mall_guestusers, whose description states that it represents
 * "Logical identities for guest users of the shoppingMall platform" and that it
 * "represents unauthenticated visitors who may still own transient business
 * data such as temporary carts or wishlists before converting to registered
 * customers." The primary key id is generated to uniquely identify this guest
 * identity, while created_at and updated_at are populated with the current
 * timestamp to reflect record creation time and last update time. If the client
 * provides correlation information, it is stored in the external_reference
 * column, which the schema describes as an "Optional external or device-based
 * reference used to correlate guest sessions, such as a cookie or device
 * identifier, stored in a privacy-aware way." The deleted_at column remains
 * null to indicate that the record is active.
 *
 * From a security and authorization standpoint, this operation has
 * authorizationType set to "join" and authorizationActor set to null, meaning
 * that it is publicly accessible and does not require any existing
 * authentication context. The join classification reflects that the endpoint
 * creates a new account-like identity and returns an authorization payload for
 * the guestUser actor in a single step. The response body uses the
 * IShoppingMallGuestUser.IAuthorized schema, which encapsulates access and
 * refresh tokens and basic guest identity context suitable for client-side
 * storage.
 *
 * In relation to other database entities, the created
 * shopping_mall_guestusers.id may later be referenced by
 * shopping_mall_guestuser_sessions as the owner of individual browsing
 * sessions, by shopping_mall_actor_security_events_of_guestusers when
 * security-related events must be linked to a particular guest identity, and by
 * shopping_mall_account_risk_flags_of_guestusers when risk evaluation results
 * need to be attached to this guest. None of these subsidiary tables are
 * written directly by this operation; instead, they are populated by downstream
 * authentication/session management and risk subsystems when tokens are used.
 *
 * Validation rules for this endpoint are intentionally minimal, aligning with
 * the schema which does not impose unique constraints beyond the primary key
 * and exposes external_reference as a nullable string. The implementation
 * should validate that any provided external_reference respects length or
 * format limits defined in the corresponding DTO but does not attempt to
 * enforce uniqueness or specific semantics, because the Prisma schema for
 * shopping_mall_guestusers declares no unique indexes on this column. The
 * timestamps created_at and updated_at must always be non-null at creation time
 * as indicated by their non-nullable definitions.
 *
 * This join endpoint is typically used as the first step in a guest browsing
 * flow, and is closely related to the /auth/guestUser/refresh operation that
 * allows rotating tokens using a refresh token. Clients are expected to call
 * this operation once when they need a stable guest identity (for example on
 * initial app launch), store the returned tokens, and later call the refresh
 * endpoint as needed. If the guest later converts to a registered customer,
 * other higher-level business APIs will be responsible for migrating carts,
 * wishlists, and risk data from this guest user identity to the new customer
 * account, leveraging the stable id and related linkage tables.
 *
 * @param props.connection
 * @param props.body Registration payload for initializing a guestUser identity
 *   using optional device or external correlation data.
 * @setHeader token.access Authorization
 *
 * @path /auth/guestUser/join
 * @accessor api.functional.auth.guestUser.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
