/**
 * Consume a seller password reset token from
 * shopping_mall_password_reset_tokens and update the corresponding
 * shopping_mall_auth_credentials password_hash.
 *
 * This operation completes a seller password reset flow by validating and
 * consuming a password reset token from shopping_mall_password_reset_tokens and
 * applying a new password to the corresponding credentials record in
 * shopping_mall_auth_credentials. It enforces token validity, credential
 * status, and security observability requirements.
 *
 * The handler begins by querying shopping_mall_password_reset_tokens using the
 * unique index on token to locate the token row that matches the provided token
 * string. If no such row exists, if the expires_at timestamp is in the past, or
 * if consumed_at is already populated, the operation treats the token as
 * invalid or unusable and rejects the reset request. This prevents reuse of
 * expired or previously consumed tokens and aligns with the design of
 * shopping_mall_password_reset_tokens, which tracks token lifecycle through
 * expires_at, consumed_at, created_at, and updated_at.
 *
 * For a valid token, the service loads the associated credentials record from
 * shopping_mall_auth_credentials using the foreign key
 * shopping_mall_auth_credentials_id. It confirms that the actor_type of this
 * credentials record corresponds to a seller and that the status value does not
 * represent a permanently disabled state such as "compromised" or "terminated".
 * If the status is incompatible with password reset, the operation rejects the
 * request and may also initiate additional security remediation, although such
 * side effects are beyond the scope of this interface.
 *
 * When the credentials record is eligible, the handler computes a new
 * password_hash from the supplied new password and updates the credentials row
 * accordingly, setting password_hash to the new value and updating the
 * updated_at timestamp. It may also clear or adjust fields like last_login_at
 * depending on policy, but the core requirement is to persist the new hash in
 * shopping_mall_auth_credentials while leaving email, actor_type, and id
 * unchanged.
 *
 * The token row in shopping_mall_password_reset_tokens is then marked as
 * consumed by populating consumed_at with the current time and updating
 * updated_at. This update ensures that subsequent attempts to reuse the same
 * token will be rejected in the initial validation step and that the lifecycle
 * of the token is clearly recorded.
 *
 * To maintain an immutable audit trail, the handler writes an entry into
 * shopping_mall_auth_logs with event_type such as "password_reset_success",
 * success=true, actor_type="seller", actor_email derived from the credentials,
 * and created_at set to when the reset was applied. Fields such as ip,
 * user_agent, session_id, correlation_id, and metadata_json can be filled as
 * appropriate to aid incident response. A corresponding record in
 * shopping_mall_security_events with event_type like "PASSWORD_RESET_SUCCESS"
 * and optional shopping_mall_auth_credentials_id plus actor_type,
 * actor_identifier, ip, user_agent, metadata, and created_at supports security
 * analytics and compliance reporting.
 *
 * The API responds with an IShoppingMallSellerPasswordResetComplete.IResponse
 * structure that indicates whether the password reset succeeded. It does not
 * expose internal details of shopping_mall_auth_credentials or
 * shopping_mall_password_reset_tokens, keeping those tables as strictly backend
 * concerns while the interface expresses a clear, user-centric outcome.
 *
 * @param props.connection
 * @param props.body Request payload containing the password reset token and the
 *   new seller password.
 * @path /auth/seller/password/reset/complete
 * @accessor api.functional.auth.seller.password.reset.complete.completePasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function completePasswordReset(
  connection: IConnection,
  props: completePasswordReset.Props,
): Promise<completePasswordReset.Response> {
  return true === connection.simulate
    ? completePasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...completePasswordReset.METADATA,
          path: completePasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace completePasswordReset {
  export type Props = {
    /**
     * Request payload containing the password reset token and the new
     * seller password.
     */
    body: IShoppingMallSellerPasswordResetComplete.IRequest;
  };
  export type Body = IShoppingMallSellerPasswordResetComplete.IRequest;
  export type Response = IShoppingMallSellerPasswordResetComplete.IResponse;

  export const METADATA = {
    method: "POST",
    path: "/auth/seller/password/reset/complete",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/seller/password/reset/complete";
  export const random =
    (): IShoppingMallSellerPasswordResetComplete.IResponse =>
      typia.random<IShoppingMallSellerPasswordResetComplete.IResponse>();
  export const simulate = (
    connection: IConnection,
    props: completePasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: completePasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
