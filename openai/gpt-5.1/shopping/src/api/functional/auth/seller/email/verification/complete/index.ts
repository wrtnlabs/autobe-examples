/**
 * Consume a seller email verification token from
 * shopping_mall_email_verification_tokens and mark the associated credentials
 * as verified.
 *
 * This operation finalizes an email verification flow for a seller by consuming
 * a verification token previously created in
 * shopping_mall_email_verification_tokens and applying any credential updates
 * required by policy. It is typically invoked when the seller follows a link
 * contained in a verification email.
 *
 * The handler receives a token string and queries
 * shopping_mall_email_verification_tokens using the unique index on token. If
 * no matching row is found, or if the row's expires_at is in the past, the
 * operation rejects the request as invalid or expired. When the token exists
 * but its consumed_at field is already populated, the handler also rejects the
 * request to prevent replay of tokens that were already used to complete
 * verification.
 *
 * For a valid, unexpired, and unconsumed token, the service updates the token
 * row by setting consumed_at to the current timestamp and updating the
 * updated_at column to reflect the change. This ensures that future lookups
 * recognize the token as used. The foreign key
 * shopping_mall_auth_credentials_id is then used to load the associated
 * credentials record from shopping_mall_auth_credentials, establishing the
 * identity whose email address is being verified.
 *
 * Once the credentials row is loaded, the operation may modify it according to
 * email verification policy—for example, updating status from a preliminary
 * state to an "active" state, or setting verification-related metadata in an
 * additional column if defined elsewhere in the schema. The status and
 * updated_at fields on shopping_mall_auth_credentials are central to reflecting
 * this state transition. The actor_type field ensures that only seller-relevant
 * flows are processed by this endpoint when used in a multi-actor environment.
 *
 * To maintain a robust security audit trail, the endpoint can log the
 * verification event into shopping_mall_auth_logs with an event_type such as
 * "email_verification", success=true, actor_type="seller", actor_email derived
 * from the credentials email, and created_at set to the current time. In
 * addition, it can create a record in shopping_mall_security_events with
 * event_type like "EMAIL_VERIFICATION_COMPLETED" and, when possible,
 * shopping_mall_auth_credentials_id referencing the credentials record, plus
 * actor_type, actor_identifier, ip, user_agent, metadata, and created_at to
 * support later investigation.
 *
 * The response confirms that the seller's email has been successfully verified
 * using an IShoppingMallSellerEmailVerificationComplete.IResponse structure.
 * This DTO may indicate whether the seller can now access additional features
 * or whether further steps are required, while leaving internal token and
 * credential state hidden from the client.
 *
 * @param props.connection
 * @param props.body Request payload containing the email verification token to
 *   be consumed.
 * @path /auth/seller/email/verification/complete
 * @accessor api.functional.auth.seller.email.verification.complete.completeEmailVerification
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function completeEmailVerification(
  connection: IConnection,
  props: completeEmailVerification.Props,
): Promise<completeEmailVerification.Response> {
  return true === connection.simulate
    ? completeEmailVerification.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...completeEmailVerification.METADATA,
          path: completeEmailVerification.path(),
          status: null,
        },
        props.body,
      );
}
