import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallSellerPasswordChange } from "../../../../../structures/IShoppingMallSellerPasswordChange";

/**
 * Allow an authenticated seller to change their password by validating the
 * current password and updating shopping_mall_auth_credentials.
 *
 * This operation enables an authenticated seller to proactively change their
 * password by re-authenticating with the existing password and specifying a new
 * password. It leverages the centralized credentials table
 * shopping_mall_auth_credentials and the security-focused logging tables
 * shopping_mall_auth_logs and shopping_mall_security_events.
 *
 * The handler derives the seller's credentials identifier from the current
 * authentication context, ensuring that the change is scoped to the logged-in
 * seller and that actor_type in shopping_mall_auth_credentials corresponds to a
 * seller value. It then validates the provided current password against the
 * stored password_hash in shopping_mall_auth_credentials. If this comparison
 * fails, the operation rejects the request, logs a failed password change
 * attempt, and does not alter any credentials data.
 *
 * When the current password matches, the service computes a new password_hash
 * from the proposed new password, subject to platform password policy rules
 * enforced at the application layer. It updates the credentials row by setting
 * password_hash to the new hash and updating the updated_at timestamp. The
 * email, actor_type, and id remain unchanged. The status column can also be
 * used to track transitional states if the platform decides, for example, to
 * force re-login after password change, but this behavior is beyond the scope
 * of this description.
 *
 * For auditability, the operation creates a shopping_mall_auth_logs entry
 * capturing the password change event. The log row may use event_type such as
 * "password_change", success=true, actor_type="seller", actor_id referencing
 * the seller id, actor_email from the credentials email, and created_at set to
 * the current time. It can also populate ip, user_agent, session_id,
 * correlation_id, and metadata_json with contextual information about the
 * request. These attributes, along with indexes on event_type and actor_type,
 * make it easier to trace credential changes.
 *
 * Additionally, the handler can produce a record in
 * shopping_mall_security_events with event_type like "PASSWORD_CHANGED" and,
 * where applicable, shopping_mall_auth_credentials_id referencing the updated
 * credentials record. The entry may include actor_type, actor_identifier, ip,
 * user_agent, metadata, and created_at for security analysis. These logs help
 * flag unexpected password changes as part of broader risk detection.
 *
 * The API responds with an IShoppingMallSellerPasswordChange.IResponse
 * structure signaling whether the password change succeeded. It never exposes
 * raw password or password_hash values from shopping_mall_auth_credentials,
 * maintaining strict separation between sensitive credential storage and the
 * interface layer.
 *
 * @param props.connection
 * @param props.body Request payload containing the seller's current password
 *   and the desired new password.
 * @path /auth/seller/password/change
 * @accessor api.functional.auth.seller.password.change.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<changePassword.Response> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /**
     * Request payload containing the seller's current password and the
     * desired new password.
     */
    body: IShoppingMallSellerPasswordChange.IRequest;
  };
  export type Body = IShoppingMallSellerPasswordChange.IRequest;
  export type Response = IShoppingMallSellerPasswordChange.IResponse;

  export const METADATA = {
    method: "POST",
    path: "/auth/seller/password/change",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/seller/password/change";
  export const random = (): IShoppingMallSellerPasswordChange.IResponse =>
    typia.random<IShoppingMallSellerPasswordChange.IResponse>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
