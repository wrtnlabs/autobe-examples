export type IShoppingMallCartItem = {
  /**
   * Primary key of the cart item.
   *
   * This is the unique identifier of the row in `shopping_mall_cart_items`
   * and corresponds to the `id` column in the Prisma model.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Identifier of the cart header that owns this item.
   *
   * This value references `shopping_mall_carts.id` and groups line items
   * under a single cart for a particular customer or guest session.
   */
  shopping_mall_cart_id: string & tags.Format<"uuid">;

  /**
   * Identifier of the SKU being purchased in this cart item.
   *
   * This value references `shopping_mall_skus.id` and determines which
   * concrete product variant the cart line refers to. It is primarily used by
   * the backend for joins and validations; for UI rendering, prefer the `sku`
   * summary association.
   */
  shopping_mall_sku_id: string & tags.Format<"uuid">;

  /**
   * Requested quantity of the SKU in this cart item.
   *
   * The value is stored as an integer and represents how many units of the
   * SKU the cart currently holds. Business validation ensures that it is
   * positive and within allowed inventory and policy limits.
   */
  quantity: number & tags.Type<"int32">;

  /**
   * Snapshot unit price of the SKU in the cart currency at the time it was
   * last recalculated.
   *
   * This value is stored as a double precision number and is used to compute
   * line subtotals at checkout. It reflects the price at the time of the last
   * cart recalculation, not necessarily the current catalog price.
   */
  unit_price: number;

  /**
   * ISO currency code associated with `unit_price`.
   *
   * This code should match the currency of the owning cart, and it indicates
   * the monetary unit for all price calculations on this line item.
   */
  currency_code: string;

  /**
   * Result of the most recent lightweight validation for this item.
   *
   * Typical values include states such as `"ok"`, `"out_of_stock"`, or
   * `"price_changed"`. The field is nullable when no validation has been
   * performed yet.
   */
  last_validation_status?: string | null | undefined;

  /**
   * Timestamp of the last validation status update.
   *
   * When present, this value indicates when the system last evaluated the
   * validity of this cart line with respect to inventory, pricing, or policy
   * checks.
   */
  last_validation_at?: (string & tags.Format<"date-time">) | null | undefined;

  /**
   * Timestamp when the item was first added to the cart.
   *
   * This is set when the cart item row is initially created and remains
   * unchanged for the lifetime of the item, even if quantities or other
   * fields are updated later.
   */
  added_at: string & tags.Format<"date-time">;

  /**
   * Timestamp when the cart item record was created.
   *
   * This is the audit creation time for the row in `shopping_mall_cart_items`
   * and usually matches or is very close to `added_at`.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp when the cart item was last modified.
   *
   * The system updates this value whenever mutable fields such as `quantity`
   * are changed, providing an audit trail of modifications.
   */
  updated_at: string & tags.Format<"date-time">;

  /**
   * Soft deletion timestamp for the cart item.
   *
   * When non-null, the item is logically removed from the cart while its data
   * is preserved for analytics or historical reporting. Active cart items
   * have this field set to null.
   */
  deleted_at?: (string & tags.Format<"date-time">) | null | undefined;

  /**
   * Summary view of the SKU variant associated with this cart item.
   *
   * This association is derived from `shopping_mall_skus` and provides
   * human‑readable context such as SKU code and variant name for rendering
   * cart UIs without additional SKU detail requests.
   */
  sku?: IShoppingMallSku.ISummary | undefined;
};
