import { IShoppingMallCartSummaryItem } from "./IShoppingMallCartSummaryItem";
import { IShoppingMallCartSummaryTotals } from "./IShoppingMallCartSummaryTotals";
import { IShoppingMallCartSummaryMessage } from "./IShoppingMallCartSummaryMessage";

/**
 * Denormalized, computed view of the active shopper's current cart on the
 * shoppingMall platform.
 *
 * This DTO aggregates guest or customer cart line items with product and SKU
 * metadata to present a user-facing cart summary used in cart and checkout UIs.
 * It includes per-line pricing, quantities, and subtotals, along with overall
 * totals such as item count, subtotal, estimated discounts, shipping estimates,
 * and grand total. It is read-only and not mapped 1:1 to a single Prisma
 * model.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallCartSummary = {
  /**
   * List of cart line items included in the current cart summary. Each item
   * combines cart quantity with product/SKU presentation data and computed
   * line-level pricing.
   */
  items: IShoppingMallCartSummaryItem[];

  /**
   * Aggregated cart totals including item count, subtotal, estimated
   * discounts, estimated shipping, taxes (if applicable), and grand total.
   */
  totals: IShoppingMallCartSummaryTotals;

  /**
   * Three-letter ISO 4217 currency code used for all monetary fields in this
   * cart summary (for example, "USD" or "KRW").
   */
  currency: string;

  /**
   * Business-defined region or market code used when computing region-aware
   * pricing, shipping estimates, and eligibility rules.
   */
  regionCode?: string | null | undefined;

  /**
   * Indicates whether the cart summary includes any blocking issues at the
   * time of computation, such as disabled products or SKUs that can no longer
   * be purchased.
   */
  hasErrors: boolean;

  /**
   * Non-blocking warnings about the current cart state, such as low
   * inventory, products nearing end-of-sale, or minor inconsistencies that do
   * not prevent checkout.
   */
  warnings?: IShoppingMallCartSummaryMessage[] | undefined;

  /**
   * Blocking issues that prevent the cart from being directly eligible for
   * checkout from the summary perspective (for example, disabled SKUs or
   * items that are no longer sellable).
   */
  errors?: IShoppingMallCartSummaryMessage[] | undefined;
};
export namespace IShoppingMallCartSummary {
  /**
   * Request DTO for computing a summarized view of the current shopping cart
   * on the shoppingMall platform.
   *
   * This type is used by the PATCH /shoppingMall/carts/summary endpoint to
   * pass contextual parameters that influence how the cart summary is
   * computed and presented. It does not identify the cart directly; the
   * effective cart (guest or customer) MUST always be resolved from the
   * caller's session or a secure guest token at the implementation layer.
   *
   * Typical use cases include specifying the shopper's region for shipping
   * and tax estimation, choosing a preferred currency, and toggling inclusion
   * of optional computed sections such as promotion breakdowns or diagnostic
   * information. The DTO is read-only with respect to cart state: using this
   * type MUST NOT mutate cart contents or server-side configuration.
   */
  export type IRequest = {
    /**
     * Code representing the shopper's active region or market used for
     * region-aware pricing, tax, and shipping estimation.
     *
     * The value should align with region identifiers configured in
     * shopping_mall_region_settings and may follow ISO country/region codes
     * or a platform-specific scheme. When omitted, the backend uses the
     * default region associated with the session or platform
     * configuration.
     */
    region_code?: string | undefined;

    /**
     * Preferred ISO 4217 currency code (for example, "USD", "EUR", "KRW")
     * to use when presenting cart totals and line item prices.
     *
     * If omitted, the platform's default currency for the resolved region
     * is used. When specified, it must be one of the currencies supported
     * by the platform and, if applicable, the shopper's region.
     */
    currency_code?: string | undefined;

    /**
     * Flag indicating whether promotion and discount breakdown information
     * should be included in the computed cart summary response.
     *
     * When true, the server attempts to evaluate applicable promotions,
     * coupons, and discounts, and to surface corresponding line-level and
     * cart-level adjustments in the summary. When false or omitted, the
     * server may return only basic pricing information without detailed
     * promotion metadata.
     */
    include_promotions?: boolean | undefined;

    /**
     * Flag controlling whether estimated shipping fees and related
     * breakdowns are included in the summary response.
     *
     * When true, the server calculates shipping cost estimates based on the
     * shopper's region and any available shipping address context, using
     * configuration from shopping_mall_shipping_zone_settings or similar
     * tables. When omitted or false, the response may omit shipping
     * sections or include only minimal placeholders.
     */
    include_shipping_estimate?: boolean | undefined;

    /**
     * Optional flag used primarily by frontends or admin tools to request
     * additional diagnostic information in the cart summary response.
     *
     * When true, the server may include internal evaluation details such as
     * which promotions were considered, why certain items were excluded
     * from discounts, or warnings about invalid SKUs. This field should be
     * used sparingly in production contexts to avoid leaking sensitive
     * implementation details to end-users.
     */
    include_diagnostics?: boolean | undefined;
  };
}
