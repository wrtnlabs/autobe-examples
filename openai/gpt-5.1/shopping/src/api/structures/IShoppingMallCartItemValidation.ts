import { tags } from "typia";

import { IShoppingMallCartItem } from "./IShoppingMallCartItem";

export namespace IShoppingMallCartItemValidation {
  /**
   * Search and filtering DTO for querying cart item validation records.
   *
   * This type is used by admin-facing operations such as `PATCH
   * /shoppingMall/admin/carts/{cartId}/items/validations` and `PATCH
   * /shoppingMall/admin/carts/{cartId}/items/{cartItemId}/validations` to
   * express filter criteria and pagination parameters when listing validation
   * events stored in the `shopping_mall_cart_item_validations` table.
   *
   * It does not map directly to a Prisma row; instead, it represents query
   * parameters for read-only search use cases over the validation history of
   * one cart or a single cart item.
   */
  export type IRequest = {
    /**
     * Optional filter for validation outcome status.
     *
     * When provided, only validation records whose `status` column matches
     * this value (for example `"success"`, `"error"`, or `"adjusted"`) are
     * returned. When null or omitted, validations of all statuses are
     * considered.
     */
    status?: string | null | undefined;

    /**
     * Optional filter for the business type of validation.
     *
     * Typical values include `"add_to_cart"`, `"cart_view"`, or
     * `"checkout"` and correspond to the `validation_type` column in
     * `shopping_mall_cart_item_validations`. When specified, only records
     * of the given type are included.
     */
    validation_type?: string | null | undefined;

    /**
     * Lower bound (inclusive) for filtering by `created_at` timestamp.
     *
     * When provided, only validation records created at or after this
     * timestamp are returned. This allows narrowing the search window to a
     * recent time period. The field name uses camelCase to align with other
     * request DTOs such as `IShoppingMallCartMergeEvent.IRequest`.
     */
    createdAtFrom?: (string & tags.Format<"date-time">) | null | undefined;

    /**
     * Upper bound (inclusive) for filtering by `created_at` timestamp.
     *
     * When provided, only validation records created at or before this
     * timestamp are returned. Used together with `createdAtFrom` to define
     * a time range. The field name uses camelCase to match the broader API
     * schema naming convention.
     */
    createdAtTo?: (string & tags.Format<"date-time">) | null | undefined;

    /**
     * Page number for pagination.
     *
     * This is a 1-based index indicating which page of results to retrieve.
     * When omitted, implementations typically default to the first page.
     */
    page?: (number & tags.Type<"int32">) | undefined;

    /**
     * Maximum number of validation records to return in a single page.
     *
     * Clients can use this to control page size; implementations may
     * enforce an upper bound to protect performance.
     */
    limit?: (number & tags.Type<"int32">) | undefined;
  };

  /**
   * Summary view of a single validation record for a shopping cart item.
   *
   * This DTO is used in list responses and embedded contexts where only
   * high-level information about a validation attempt is required, not the
   * full historical payload. It focuses on identifiers, core classification
   * fields, and timestamps that allow clients to understand when and how a
   * cart item was validated.
   *
   * The underlying persistence is provided by the
   * `shopping_mall_cart_item_validations` table, which stores detailed audit
   * entries for validations triggered during cart interactions such as
   * add-to-cart, cart view, and checkout. This summary variant intentionally
   * omits large text fields and non-essential numeric detail so that lists
   * remain lightweight while still supporting debugging, analytics
   * correlation, and drill-down navigation to detail resources.
   */
  export type ISummary = {
    /**
     * Unique identifier of the cart item validation record.
     *
     * This value corresponds to `shopping_mall_cart_item_validations.id`
     * and is generated by the database. Clients use this identifier when
     * referencing a specific validation entry in logs, support tools, or
     * detail views. It is immutable for the lifetime of the record.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Owning cart item whose state was evaluated during this validation.
     *
     * This reference provides lightweight context about the item that was
     * checked, such as the SKU and quantity, without requiring clients to
     * issue an additional lookup. Internally it maps to the
     * `shopping_mall_cart_item_validations.shopping_mall_cart_item_id`
     * foreign key that joins to `shopping_mall_cart_items.id`. The summary
     * projection of the cart item MUST follow the `.ISummary` DTO rules and
     * must not contain its own child collections.
     */
    cartItem: IShoppingMallCartItem.ISummary;

    /**
     * Business type of validation that was executed for the cart item.
     *
     * The value reflects the interaction or lifecycle event that triggered
     * the validation, such as `add_to_cart`, `cart_view`, or `checkout`. It
     * comes from the `shopping_mall_cart_item_validations.validation_type`
     * column and is used in analytics and diagnostics to group and filter
     * validation records by scenario.
     *
     * API consumers should treat this as an opaque but stable business code
     * string and avoid hard-coding assumptions about the full list of
     * possible values.
     */
    validation_type: string;

    /**
     * Outcome classification of the validation attempt.
     *
     * This value is derived from the
     * `shopping_mall_cart_item_validations.status` field and typically
     * expresses states like `success`, `error`, or `adjusted` depending on
     * how the validation completed. It allows client applications and
     * reporting tools to quickly determine whether the corresponding cart
     * item remains valid, was rejected, or required correction.
     *
     * Combined with timestamps and validation type, the status enables
     * high-level analysis of cart friction and error patterns without
     * inspecting full underlying rule logic.
     */
    status: string;

    /**
     * Optional human-readable explanation of the validation result.
     *
     * The content comes from `shopping_mall_cart_item_validations.message`
     * and is intended for logging, support tooling, or, when appropriate,
     * customer-facing error messaging. It may describe reasons such as
     * stock unavailability, pricing changes, or policy violations.
     *
     * When null, either no additional description was recorded for this
     * validation or the message is not relevant in the current presentation
     * context.
     */
    message?: string | null | undefined;

    /**
     * Creation timestamp of this validation record.
     *
     * This value mirrors `shopping_mall_cart_item_validations.created_at`
     * and indicates when the validation was executed and stored. It is
     * expressed in ISO 8601 date-time format and is immutable once
     * written.
     *
     * Clients commonly use this timestamp to order validation records
     * chronologically, filter validation history over a time range, and
     * correlate cart validation events with other operational logs or
     * customer interactions.
     */
    created_at: string & tags.Format<"date-time">;
  };
}
