import { tags } from "typia";

/**
 * Single-line item overview entry within an `IShoppingMallOrderItemsOverview`
 * response.
 *
 * This DTO corresponds conceptually to a row in `shopping_mall_order_lines`
 * enriched with denormalized snapshots from related entities such as products,
 * SKUs, and seller segments. It provides enough information for a UI to display
 * each purchased item within an order without issuing further lookups for
 * product names, SKU codes, or basic seller information.
 *
 * The structure is intentionally stable and does not expose low-level technical
 * details or internal audit information.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallOrderItemsOverviewItem = {
  /**
   * Unique identifier of the underlying order line record, typically
   * corresponding to the primary key of a row in
   * `shopping_mall_order_lines`.
   */
  orderLineId: string & tags.Format<"uuid">;

  /**
   * Identifier of the seller segment within the master order that this line
   * belongs to. Typically corresponds to a record in
   * `shopping_mall_order_seller_segments` when the order involves multiple
   * sellers.
   */
  sellerSegmentId?: (string & tags.Format<"uuid">) | undefined;

  /**
   * Human-readable name of the seller responsible for fulfilling this line
   * item. This is a snapshot value suitable for display in customer order
   * detail views.
   */
  sellerDisplayName?: string | undefined;

  /**
   * Identifier of the product associated with this line, corresponding to a
   * record in `shopping_mall_products` at the time of ordering.
   */
  productId: string & tags.Format<"uuid">;

  /**
   * Snapshot of the product name at the time of ordering, used for stable
   * display even if the current catalog name changes later.
   */
  productName: string;

  /**
   * Identifier of the concrete SKU purchased for this line, generally
   * referencing `shopping_mall_product_skus`.
   */
  skuId: string & tags.Format<"uuid">;

  /**
   * Snapshot of the SKU code associated with the purchased variant, used for
   * display and support/troubleshooting workflows.
   */
  skuCode: string;

  /**
   * Human-readable concatenated summary of the option values chosen for this
   * SKU (for example, `Color: Black / Size: M`). This is a snapshot to keep
   * the overview self-contained.
   */
  skuOptionsSummary?: string | undefined;

  /** Number of units of the SKU purchased on this order line. */
  quantity: number & tags.Type<"int32">;

  /**
   * Snapshot of the per-unit price captured for this order line at checkout
   * time, before per-line discounts. Expressed in the same currency as the
   * parent overview.
   */
  unitPrice: number;

  /**
   * Total discount amount applied specifically to this order line, if
   * applicable. Expressed in the same currency as the parent overview.
   */
  lineDiscountAmount?: number | undefined;

  /**
   * Total monetary amount for this line after line-level discounts but before
   * proportional allocation of shipping or tax. Calculated from `quantity`,
   * `unitPrice`, and `lineDiscountAmount` as captured at checkout. Expressed
   * in the same currency as the parent overview.
   */
  lineTotal: number;

  /**
   * High-level fulfillment or shipment status for this line item (for
   * example, `pending`, `preparing`, `shipped`, or `delivered`). The concrete
   * values are derived from fulfillment or shipment records and are aligned
   * with the platform's business-defined status vocabulary.
   */
  fulfillmentStatus:
    | "pending"
    | "preparing"
    | "shipped"
    | "delivered"
    | "cancelled"
    | "returned";

  /**
   * Optional human-readable summary of fulfillment state or shipment progress
   * for this line item, such as `Shipped via DHL - Tracking #123456` or
   * `Awaiting warehouse processing`.
   */
  fulfillmentSummary?: string | undefined;
};
