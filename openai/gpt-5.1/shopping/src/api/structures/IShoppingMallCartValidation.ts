import { tags } from "typia";

/**
 * Result of validating the current shopper's cart prior to checkout on the
 * shoppingMall platform.
 *
 * Represents a read-only snapshot of validation outcomes for the active cart
 * (guest or customer). It indicates whether the cart is currently eligible for
 * checkout and, if not, enumerates blocking errors and non-blocking warnings
 * for individual cart lines and for cart-level conditions such as shipping,
 * payment, and coupons.
 *
 * This DTO is not directly mapped to a single Prisma model; rather, it
 * aggregates information derived from cart tables (guest/customer carts and
 * items), product and SKU definitions, inventory state, and policy tables such
 * as age or regional restrictions.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallCartValidation = {
  /**
   * Overall validation result flag.
   *
   * True when the cart is currently eligible to proceed to checkout without
   * blocking issues. False when at least one blocking validation error exists
   * for any cart line or cart-level rule.
   */
  isValid: boolean;

  /**
   * Collection of blocking validation errors that prevent checkout.
   *
   * Each entry describes a violation that must be resolved before the
   * checkout process can continue, such as out-of-stock items, inactive
   * products, unsupported shipping destinations, or invalid coupons.
   */
  blockingErrors: IShoppingMallCartValidation.IMessage[];

  /**
   * Collection of non-blocking warnings discovered during validation.
   *
   * Warnings highlight potential issues or recommendations (e.g., low
   * inventory, soon-to-expire promotions, or address normalization
   * suggestions) that do not strictly block checkout but should be
   * communicated to the shopper.
   */
  warnings: IShoppingMallCartValidation.IMessage[];

  /**
   * Optional snapshot of the cart state at the time of validation.
   *
   * Provides a lightweight view of cart lines, quantities, and their current
   * availability status so that clients can render a consistent view of what
   * was evaluated. This snapshot is derived from guest or customer cart
   * tables and associated product/SKU records.
   */
  cartSnapshot?: IShoppingMallCartValidation.ICartSnapshot | undefined;
};
export namespace IShoppingMallCartValidation {
  /**
   * Request payload for triggering validation of the current shopper's cart.
   *
   * Carries contextual parameters that influence validation logic, such as
   * shipping destination, selected shipping method, intended payment method,
   * and coupon or promotion codes. The cart identity itself is NOT supplied
   * here and must be derived from the authenticated session or secure guest
   * token by the backend implementation.
   */
  export type ICreate = {
    /**
     * Candidate shipping address that will be used for validation.
     *
     * Used to evaluate regional availability, shipping-zone compatibility,
     * and potential address-related restrictions such as age or product
     * compliance policies.
     */
    shippingAddress: IShoppingMallCartValidation.IShippingAddress;

    /**
     * Optional code of the selected shipping method for this cart
     * validation.
     *
     * When provided, the validator will check whether this shipping method
     * is available for the given address, cart contents, and region
     * policies. Typical values correspond to configured shipping methods in
     * shopping mall configuration tables.
     */
    shippingMethodCode?: (string & tags.MinLength<1>) | undefined;

    /**
     * Optional code of the intended payment method for this cart
     * validation.
     *
     * If provided, the validator confirms that this payment method is
     * currently enabled for the shopper's region and for the cart
     * currency/amounts, according to payment configuration and risk
     * policies.
     */
    paymentMethodCode?: (string & tags.MinLength<1>) | undefined;

    /**
     * List of coupon or promotion codes the shopper intends to apply to the
     * current cart.
     *
     * The validator checks each code for validity, applicability to the
     * cart contents, expiration, and compatibility with other active
     * promotions.
     */
    couponCodes?: (string & tags.MinLength<1>)[] | undefined;

    /**
     * Optional free-form note or client-side context attached to this
     * validation attempt.
     *
     * Can be used for logging or diagnostic purposes, but is not
     * interpreted by core validation rules.
     */
    notes?: (string & tags.MaxLength<1000>) | undefined;
  };

  /**
   * Structured representation of a single cart validation message.
   *
   * Used for both blocking errors and non-blocking warnings. Each message
   * identifies the affected scope (cart-level or specific line), a
   * machine-readable code for programmatic handling, and a human-readable
   * message for display to end users.
   */
  export type IMessage = {
    /**
     * Scope within the cart that this validation message applies to.
     *
     * Typical values distinguish between cart-level and line-level issues,
     * for example: `cart`, `line`, or other domain-specific scopes used by
     * the implementation.
     */
    scope: string & tags.MinLength<1>;

    /**
     * Identifier of the affected cart line when this message pertains to a
     * specific item.
     *
     * Usually corresponds to the primary key or stable identifier of a cart
     * item record. This field may be omitted or null for cart-level
     * messages that are not tied to a single line.
     */
    lineId?: (string & tags.MinLength<1>) | undefined;

    /**
     * Machine-readable code representing the validation rule or error type.
     *
     * Clients can use this code to implement localized messaging, automated
     * remediation flows, or analytics on common validation failures.
     */
    code: string & tags.MinLength<1>;

    /**
     * Human-readable description of the validation issue or warning.
     *
     * Intended to be displayed directly to end users, possibly after
     * localization, to explain why an item or the entire cart is not valid
     * for checkout.
     */
    message: string & tags.MinLength<1>;
  };

  /**
   * Lightweight snapshot of cart contents as evaluated during a specific
   * validation run.
   *
   * This DTO is a read-only projection derived from the current state of
   * guest or customer carts in the shopping mall backend (for example, from
   * `shopping_mall_guest_carts` or `shopping_mall_customer_carts` and their
   * related item tables). It does not represent a mutable cart entity itself,
   * but rather a point-in-time view used by validation services.
   *
   * The snapshot aggregates line-level information together with the outcomes
   * of inventory and policy checks. It is primarily consumed by frontend or
   * orchestration layers that need to understand which cart lines are
   * currently purchasable and why certain lines may be blocked or require
   * user attention.
   */
  export type ICartSnapshot = {
    /**
     * Array of cart line snapshots evaluated during validation.
     *
     * Each element in this collection corresponds to a single logical cart
     * item record that exists in either a guest cart (e.g.,
     * `shopping_mall_guest_cart_items`) or a persistent customer cart
     * (e.g., `shopping_mall_customer_cart_items`). The snapshot captures
     * the line as it appears at validation time, including quantities and
     * the result of inventory and policy evaluation.
     *
     * The array is always present but may be empty if the underlying cart
     * currently contains no items. Clients should handle the empty case
     * gracefully, treating it as a valid representation of an empty cart at
     * the moment of validation.
     */
    lines: IShoppingMallCartValidation.ICartLineSnapshot[];
  };

  /**
   * Summary of a single cart line at validation time.
   *
   * This DTO represents one logical line item from a guest or customer cart
   * at the exact moment validation is executed. It links back to the
   * underlying cart item row as well as the associated catalog product and
   * SKU records, providing enough information to reason about availability
   * and policy decisions.
   *
   * The line snapshot is intentionally lightweight and read-only. It omits
   * large product detail payloads and instead focuses on identifiers,
   * requested quantity, and a simple boolean flag that states whether the
   * line can proceed to checkout under the current inventory and policy
   * constraints.
   */
  export type ICartLineSnapshot = {
    /**
     * Identifier of the cart line in the underlying cart item table.
     *
     * This value typically corresponds to the primary key of a row in
     * either `shopping_mall_guest_cart_items` or
     * `shopping_mall_customer_cart_items`, depending on whether the shopper
     * is a guest or an authenticated customer.
     *
     * Client applications use this identifier to correlate validation
     * feedback with specific UI line items, enabling targeted updates (such
     * as highlighting an invalid line or displaying an error badge) without
     * re-resolving the entire cart structure.
     */
    lineId: string & tags.MinLength<1>;

    /**
     * Identifier of the product associated with this cart line.
     *
     * This usually maps directly to the primary key of a record in the
     * `shopping_mall_products` table and is stable across SKUs that belong
     * to the same product family.
     *
     * The product identifier is used for higher-level catalog lookups,
     * pricing rules, marketing content, and cross-cutting policy
     * evaluations (for example, age restrictions, global visibility flags,
     * or brand-level constraints) that apply at the product level rather
     * than the SKU level.
     */
    productId: string & tags.MinLength<1>;

    /**
     * Identifier of the SKU (stock keeping unit) associated with this cart
     * line.
     *
     * The SKU identifier corresponds to a record in
     * `shopping_mall_product_skus` and represents the concrete variant that
     * the shopper intends to purchase (for example, a specific size, color,
     * or configuration).
     *
     * During validation, this field is used to join into inventory
     * (`shopping_mall_inventory_items` and related movement/reservation
     * tables) and variant-level configuration (such as per-SKU visibility
     * overrides or compliance flags), ensuring that decisions about
     * purchasability are made at the precise variant level.
     */
    skuId: string & tags.MinLength<1>;

    /**
     * Requested quantity for this cart line at the time of validation.
     *
     * The quantity reflects exactly what is stored in the underlying cart
     * item row for this line and is what the validation service evaluates
     * against available inventory and purchase-limit policies.
     *
     * A minimum of `1` is enforced, which means a line with quantity `0` is
     * not considered a valid cart entry in this view. If users attempt to
     * reduce a quantity to zero, client code or cart APIs should remove the
     * line entirely rather than representing it here as a zero-quantity
     * snapshot.
     */
    quantity: number & tags.Type<"int32"> & tags.Minimum<1>;

    /**
     * Flag indicating whether this specific line is currently purchasable
     * under the evaluated conditions.
     *
     * A value of `true` means that, at validation time, the associated
     * product and SKU are active and visible, the requested quantity does
     * not violate inventory constraints or per-order limits, and no
     * blocking compliance or business rules prevent purchase.
     *
     * A value of `false` indicates that at least one blocking condition was
     * detected—for example, the SKU is out of stock, the product is
     * temporarily hidden for the shopper's region, the item violates age or
     * restriction policies, or the quantity exceeds allowed thresholds.
     * Client applications should use this flag to highlight problematic
     * lines and may need to inspect separate validation message structures
     * for detailed error reasons.
     */
    isPurchasable: boolean;
  };

  /**
   * Shipping address supplied for cart validation.
   *
   * Represents the destination that will be used to evaluate shipping zone
   * eligibility, regional product restrictions, and address-dependent
   * policies such as age restrictions or compliance flags.
   */
  export type IShippingAddress = {
    /**
     * ISO 3166-1 alpha-2 country code for the shipping destination.
     *
     * Used to determine applicable regional policies, tax rules, and
     * shipping zones.
     */
    countryCode: string & tags.MinLength<2> & tags.MaxLength<2>;

    /**
     * Postal or ZIP code for the shipping address.
     *
     * Used in conjunction with other address fields to determine
     * shipping-zone membership and availability of services.
     */
    postalCode: string & tags.MinLength<1>;

    /**
     * State, province, or region component of the shipping address.
     *
     * Optional depending on country, but when provided it can further
     * refine regional policies and shipping options.
     */
    stateOrProvince?: (string & tags.MinLength<1>) | undefined;

    /**
     * City or locality component of the shipping address.
     *
     * Used primarily for display and may play a role in fine-grained
     * regional rules.
     */
    city: string & tags.MinLength<1>;

    /** Primary street address line for the shipping destination. */
    addressLine1: string & tags.MinLength<1>;

    /**
     * Secondary address information, such as apartment, suite, or building
     * details.
     *
     * Optional and used for display and precise delivery routing.
     */
    addressLine2?: (string & tags.MinLength<1>) | undefined;

    /**
     * Full name of the person or entity receiving the shipment.
     *
     * Used on shipping labels and for carrier delivery operations.
     */
    recipientName: string & tags.MinLength<1>;

    /**
     * Contact phone number for the recipient at the shipping address.
     *
     * May be required by some carriers or regions for delivery coordination
     * and notifications.
     */
    phoneNumber?: (string & tags.MinLength<1>) | undefined;
  };
}
