import { tags } from "typia";

/**
 * Non-blocking validation warning for a cart or cart item.
 *
 * Represents an advisory condition that does not prevent checkout but should be
 * communicated to the customer, such as a small price change, limited remaining
 * stock, or shipping constraints that do not violate policy.
 *
 * Warnings can optionally be scoped to a specific cart via `cartId`, or to a
 * particular cart line via `cartItemId`. This DTO is used alongside
 * `IShoppingMallCartValidationResult` and `IShoppingMallCartValidationError` to
 * give clients a complete picture of potential issues detected during
 * pre-checkout validation.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallCartValidationWarning = {
  /**
   * Machine-readable warning code describing the type of condition detected.
   *
   * Examples include `CART_PRICE_UPDATED`, `CART_LOW_STOCK`,
   * `CART_SHIPPING_DELAY`, and other enumerated business codes that can be
   * localized and mapped to user-facing messages in the client layer.
   */
  code: string;

  /**
   * Human-readable warning message explaining the detected condition.
   *
   * Intended primarily for presentation in the user interface, either
   * directly or after localization based on the warning code. The text should
   * be concise but clear enough to guide the customer about any potential
   * impact on checkout.
   */
  message: string;

  /**
   * Identifier of the affected cart in the `shopping_mall_carts` table when
   * the warning applies to the cart as a whole.
   *
   * Use this field for conditions such as global shipping constraints,
   * payment eligibility issues, or other cart-level validations that are not
   * tied to a single cart item. It mirrors the `cartId` field used in
   * `IShoppingMallCartValidationResult` so that clients can easily correlate
   * warnings with a specific cart.
   */
  cartId?: (string & tags.Format<"uuid">) | undefined;

  /**
   * Identifier of the affected cart item in the `shopping_mall_cart_items`
   * table when the warning is item-specific.
   *
   * Use this field for conditions such as low stock, price changes, or
   * attribute mismatches that only impact a single line in the cart. For
   * warnings that apply to the entire cart, this field can be omitted while
   * `cartId` remains populated.
   */
  cartItemId?: (string & tags.Format<"uuid">) | undefined;
};
