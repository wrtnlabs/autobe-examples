export namespace IShoppingMallSellerAuthRefresh {
  /**
   * Request body schema for refreshing seller authentication tokens using a
   * long-lived refresh token.
   *
   * This DTO is consumed by the `/auth/seller/refresh` endpoint, which has
   * `authorizationType: "refresh"` and `authorizationActor: null`. The
   * refresh token acts as the credential for this operation. The backend will
   * validate the token, ensure the associated seller in
   * `shopping_mall_sellers` is still active and not logically deleted, and
   * may cross-check the corresponding `shopping_mall_seller_sessions` row for
   * expiry or revocation.
   *
   * Unlike the login request, this DTO does not include credentials such as
   * email or password and does not require session context fields, because
   * the session was already established during the original login or join
   * operation.
   */
  export type IRequest = {
    /**
     * Opaque refresh token previously issued to the seller.
     *
     * This token is used to derive the seller identity and session context
     * without re-supplying email and password. It must be a valid,
     * non-expired, non-revoked token generated by the authentication
     * subsystem.
     *
     * The backend will verify this token’s signature, expiration, and
     * revocation status, then look up the underlying seller and session
     * records before issuing new JWT tokens.
     */
    refreshToken: string;
  };
}
