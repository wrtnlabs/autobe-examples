import { tags } from "typia";

export namespace IShoppingMallFulfillmentOrderLine {
  /**
   * Nested request schema representing a single order-line level fulfillment
   * instruction within a new fulfillment aggregate.
   *
   * Each object identifies an order line belonging to the target order and
   * specifies the quantity from that line to be processed in the current
   * fulfillment. The backend validates that the order line exists, belongs to
   * the order identified in the path, and that the requested quantity is
   * positive and does not exceed the remaining fulfillable quantity for that
   * line.
   *
   * Actor identity and order ownership are enforced using the authentication
   * context and the order path parameter, not via this nested DTO.
   *
   * This DTO is logically mapped to the `shopping_mall_fulfillment_items`
   * Prisma model through its `quantity` field, which corresponds to
   * `shopping_mall_fulfillment_items.quantity`. Other physical columns on
   * that model, such as `id`, `fulfillment_id`, `shipment_id`, and
   * `created_at`, are intentionally omitted because they are derived from the
   * parent fulfillment and shipment context or generated by the database.
   *
   * The `order_line_id` field is a foreign reference to
   * `shopping_mall_order_lines.id` used by the fulfillment creation logic to
   * determine which order line is being fulfilled, rather than a direct
   * column on `shopping_mall_fulfillment_items`.
   */
  export type ICreate = {
    /**
     * Identifier of the order line in `shopping_mall_order_lines` that is
     * being fulfilled as part of this fulfillment.
     *
     * The referenced order line must belong to the order identified by the
     * `orderId` path parameter of the parent endpoint. The backend enforces
     * that linkage and rejects references to order lines from other
     * orders.
     */
    order_line_id: string & tags.Format<"uuid">;

    /**
     * Number of units from the referenced order line to include in this
     * fulfillment.
     *
     * The quantity must be a positive integer greater than zero and must
     * not exceed the remaining fulfillable quantity on the order line after
     * accounting for prior fulfillments or cancellations.
     *
     * This field maps directly to the `quantity` column on the
     * `shopping_mall_fulfillment_items` Prisma model and is always stored
     * as a non-null integer, reflecting the number of units that this
     * specific fulfillment item is responsible for processing.
     */
    quantity: number & tags.Type<"int32">;
  };
}
