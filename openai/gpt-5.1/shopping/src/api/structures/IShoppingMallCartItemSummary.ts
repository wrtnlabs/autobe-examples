import { tags } from "typia";

/**
 * Compact summary of a single cart line item suitable for embedding in cart
 * detail responses.
 *
 * This projection is derived primarily from the `shopping_mall_cart_items`
 * table along with linked product and SKU entities. It surfaces the essential
 * attributes needed to render a cart view, such as the referenced SKU,
 * quantity, unit price, and extended price, while omitting internal identifiers
 * that are not required at the cart header level.
 *
 * The summary is intentionally read-only and is not used for create or update
 * operations; dedicated cart item endpoints operate directly on cart item DTOs
 * for mutating line items.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallCartItemSummary = {
  /**
   * Unique identifier of the cart item row.
   *
   * This value maps to the primary key of the underlying
   * `shopping_mall_cart_items` record and allows targeted operations on
   * individual items through dedicated cart item endpoints.
   *
   * In the context of the cart summary, it is primarily useful for
   * diagnostics, debugging, and as a stable key for UI rendering.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Identifier of the SKU associated with this cart item.
   *
   * This field points to the corresponding `shopping_mall_skus` row and is
   * used by downstream logic to join product metadata, pricing rules, and
   * inventory information.
   *
   * Client applications typically use this value only indirectly, relying
   * instead on richer product information loaded from catalog APIs when
   * needed.
   */
  sku_id: string & tags.Format<"uuid">;

  /**
   * Display name of the product or variant associated with this cart item.
   *
   * The value is denormalized from catalog entities for convenience so that
   * cart detail views can display meaningful labels without additional
   * catalog lookups.
   *
   * It should reflect the user-facing name at the time the item was added to
   * the cart, even if catalog data later evolves.
   */
  product_name: string;

  /**
   * Quantity of the SKU that the customer or guest user has placed into the
   * cart for this line item.
   *
   * This value is sourced from the `shopping_mall_cart_items` quantity column
   * and must be a positive integer. Validation logic ensures that it complies
   * with minimum and maximum purchase constraints defined by the business.
   *
   * Changes to quantity are typically performed through dedicated cart item
   * update operations rather than by editing this summary structure
   * directly.
   */
  quantity: number & tags.Type<"int32"> & tags.Minimum<1>;

  /**
   * Unit price of the SKU at the time it was added to the cart, expressed in
   * the cart’s currency.
   *
   * This value is calculated from pricing rules and stored with the cart item
   * to preserve price consistency even if catalog prices change later.
   *
   * It is used together with quantity and any applied discounts to compute
   * the extended price for the line item.
   */
  unit_price: number;

  /**
   * Extended price for the line item, generally equal to unit price
   * multiplied by quantity and adjusted for any line-level discounts.
   *
   * This value is derived from `shopping_mall_cart_items` monetary columns or
   * computed at read time to provide a ready-to-display monetary total per
   * item.
   *
   * The sum of all line totals, together with shipping and surcharges,
   * contributes to the cart’s overall estimated total amount.
   */
  line_total: number;
};
