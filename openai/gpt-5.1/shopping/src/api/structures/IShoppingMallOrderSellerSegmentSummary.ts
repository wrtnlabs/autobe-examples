import { tags } from "typia";

/**
 * Summary information for a single seller's segment within a multi-seller
 * order.
 *
 * This projection is conceptually derived from the
 * `shopping_mall_order_seller_segments` Prisma model together with associated
 * `shopping_mall_order_lines` and fulfillment/ shipment records. It exposes
 * enough information to show how much of the order belongs to a specific seller
 * and the operational status of that segment without returning every underlying
 * row or event.
 *
 * The DTO is intended for embedding inside order summaries and seller-facing
 * dashboards, providing a concise, denormalized view of per-seller monetary
 * totals and item counts that can be traced back to the underlying segment and
 * line data when needed.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallOrderSellerSegmentSummary = {
  /**
   * Unique identifier of the seller that owns this segment.
   *
   * This corresponds to the primary key of the `shopping_mall_seller` model,
   * typically referenced through a foreign key on the
   * `shopping_mall_order_seller_segments` table. It is used to correlate the
   * segment with seller-facing screens, analytics, and other APIs that
   * operate on seller accounts.
   */
  sellerId: string & tags.Format<"uuid">;

  /**
   * Display name of the seller for this segment, derived from the seller
   * profile.
   *
   * The value is normally populated from a human-readable field on the
   * `shopping_mall_seller` record (such as shop name or display name) and is
   * intended for customer-facing UI labels. It should not be used as a stable
   * technical identifier; consumers should rely on `sellerId` for joins and
   * lookups.
   */
  sellerDisplayName: string;

  /**
   * Primary lifecycle status of this seller segment, derived from
   * seller-segment and fulfillment data.
   *
   * The field summarizes the high-level state of the seller-specific portion
   * of the order, using a constrained business vocabulary such as `pending`,
   * `accepted`, `in_fulfillment`, `shipped`, `delivered`, or `cancelled`. It
   * is computed from fields on `shopping_mall_order_seller_segments` and
   * related fulfillment and shipment records, and it may differ from the
   * overall order status when different sellers progress at different
   * speeds.
   */
  segmentStatus: string;

  /**
   * Number of line items belonging to this seller segment.
   *
   * This value is typically computed as the count of
   * `shopping_mall_order_lines` (or the sum of their quantities) that are
   * associated with this seller for the parent order. It allows customer and
   * seller UIs to display how many items are contained in this segment
   * without loading the full line-level dataset.
   */
  itemCount: number & tags.Type<"int32">;

  /**
   * Subtotal amount for this seller segment before discounts, shipping, and
   * taxes.
   *
   * Conceptually this is the portion of the order snapshot
   * `items_subtotal_amount` that belongs to this seller, computed from the
   * base prices and quantities of the `shopping_mall_order_lines` linked to
   * this segment. It is expressed in the same currency as the parent order
   * and provides a per-seller view of pre-discount merchandise value.
   */
  subtotalAmount?: number | undefined;

  /**
   * Total discount amount applied to this seller segment.
   *
   * The value aggregates all promotions, coupons, and adjustments that apply
   * specifically to items from this seller. It conceptually partitions the
   * master order’s `discount_total_amount` across sellers and is useful for
   * per-seller revenue and promotion effectiveness reporting.
   */
  discountAmount?: number | undefined;

  /**
   * Total shipping charges for this seller segment.
   *
   * This amount represents the shipping costs incurred for this seller's
   * items, based on shipping methods, regions, and carrier rules that apply
   * to the segment. It conceptually contributes to the overall
   * `shipping_total_amount` on the master order and is expressed in the same
   * currency as the order.
   */
  shippingAmount?: number | undefined;

  /**
   * Total tax amount for this seller segment.
   *
   * The value reflects the aggregated tax computed for the items and shipping
   * charges in this seller segment, partitioning the master order's
   * `tax_total_amount` into per-seller components. It is expressed in the
   * same currency as the parent order and follows the tax rules that were
   * applied at checkout.
   */
  taxAmount?: number | undefined;

  /**
   * Grand total for this seller segment.
   *
   * This amount represents the final payable total for items belonging to
   * this seller after discounts, including shipping and taxes, expressed in
   * the same currency as the parent order summary. Conceptually, the sum of
   * `grandTotalAmount` across all seller segments will not exceed the master
   * order `grand_total_amount` and can be used for per-seller settlement and
   * payout calculations.
   */
  grandTotalAmount: number;
};
