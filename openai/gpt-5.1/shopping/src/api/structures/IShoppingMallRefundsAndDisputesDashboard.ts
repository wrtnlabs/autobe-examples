import { IShoppingMallDashboardPeriod } from "./IShoppingMallDashboardPeriod";
import { IShoppingMallRefundsSummary } from "./IShoppingMallRefundsSummary";
import { IShoppingMallDisputesSummary } from "./IShoppingMallDisputesSummary";
import { IShoppingMallCaseSlaSummary } from "./IShoppingMallCaseSlaSummary";
import { IShoppingMallTopRefundReason } from "./IShoppingMallTopRefundReason";
import { IShoppingMallRefundRequest } from "./IShoppingMallRefundRequest";
import { IShoppingMallDispute } from "./IShoppingMallDispute";

/**
 * Aggregated dashboard view over refund and dispute activity for administrative
 * and governance users.
 *
 * This composite DTO does not map to a single Prisma table. Instead it
 * aggregates snapshot metrics from `shopping_mall_refund_and_dispute_stats` and
 * current case information from `shopping_mall_refund_requests`,
 * `shopping_mall_disputes`, `shopping_mall_case_sla_violations`, and related
 * models.
 *
 * It is designed to power admin console pages that present an at-a-glance
 * overview of refund volume, dispute workload, SLA performance, and resolution
 * times without requiring multiple API calls or client-side aggregation logic.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallRefundsAndDisputesDashboard = {
  /**
   * Information about the time window over which the dashboard aggregates are
   * calculated.
   *
   * The period section allows the UI to present which date range or preset
   * (for example last 7 days or current month) the displayed metrics
   * reference so that operators can interpret trend and volume values
   * correctly.
   */
  period: IShoppingMallDashboardPeriod;

  /**
   * Aggregated statistics related to refund requests and monetary refunds.
   *
   * This section summarizes counts, approval and rejection volumes, and basic
   * resolution time metrics derived from snapshot tables like
   * `shopping_mall_refund_and_dispute_stats` and live refund case data.
   */
  refundSummary: IShoppingMallRefundsSummary;

  /**
   * Aggregated statistics related to disputes and their outcomes.
   *
   * It captures counts of opened and resolved disputes, distribution of
   * resolutions by party, and typical resolution times drawn from snapshot
   * data and current dispute records.
   */
  disputeSummary: IShoppingMallDisputesSummary;

  /**
   * Aggregated view of SLA performance across refund and dispute cases.
   *
   * This section surfaces counts of SLA breaches and may break them down by
   * case type, actor role, or action type to help admins understand where
   * process or staffing issues are causing missed commitments.
   */
  slaSummary: IShoppingMallCaseSlaSummary;

  /**
   * List of top recurring refund reasons within the selected period.
   *
   * Each entry represents a structured reason code and associated counts,
   * helping operations and product teams identify systemic issues that drive
   * refund demand.
   */
  topRefundReasons: IShoppingMallTopRefundReason[];

  /**
   * A small, recency-ordered sample of refund requests relevant to the
   * selected dashboard period.
   *
   * This collection is intended for quick navigation from the dashboard to
   * specific cases and should remain limited in size to keep the dashboard
   * payload manageable.
   */
  recentRefundRequests: IShoppingMallRefundRequest.ISummary[];

  /**
   * A small, recency-ordered sample of disputes relevant to the selected
   * dashboard period.
   *
   * It allows administrators to quickly open high-priority or recently
   * updated disputes directly from the dashboard view.
   */
  recentDisputes: IShoppingMallDispute.ISummary[];
};
